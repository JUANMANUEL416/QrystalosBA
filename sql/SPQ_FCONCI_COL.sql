CREATE OR ALTER PROCEDURE DBO.SPQ_FCONCI_COL @JSON NVARCHAR(MAX)
	WITH ENCRYPTION 
AS
SET DATEFORMAT dmy

DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
	
DECLARE  @PARAMETROS NVARCHAR(MAX)			,@MODELO VARCHAR(100)			   ,@METODO VARCHAR(100)
		,@USUARIO VARCHAR(12)				   ,@COMPANIA VARCHAR(2)		      ,@IDSEDE      VARCHAR(5)		
      ,@SYS_COMPUTERNAME VARCHAR(200)     ,@DATOS    VARCHAR(MAX)
      ,@PROCESO VARCHAR(20)               ,@ESTADO VARCHAR(20)             ,@FECHACONC DATETIME
      ,@FECHADIG DATETIME                 ,@IDTERCERO VARCHAR(20)          ,@CNSEXTERNO INT
      ,@VALOR DECIMAL(14,2)               ,@FECHAPAGCONC DATETIME         ,@OBSERVACION VARCHAR(255)
      ,@IDFCONCI VARCHAR(20)              ,@PORCENTAJE DECIMAL(14,2)      ,@FUNCIONARIOADMIN VARCHAR(120)
      ,@TIPO VARCHAR(20)                  ,@CONDCONCEPTO VARCHAR(20)      ,@N_FACTURA VARCHAR(20)
      ,@CNSCXC VARCHAR(20)                ,@ITEM_FCXCDV INT               ,@CNSGLO VARCHAR(20)
      ,@SALDONETO DECIMAL(14,2)           ,@VLRRECUPERAR DECIMAL(14,2)    ,@VLRACEPTADO DECIMAL(14,2)
      ,@CONCEPTO VARCHAR(24)              ,@CNSFCGLO VARCHAR(20)          ,@ITEM_FCONCID INT	      
	  ,@ITEM INT						  ,@CNSNOTADB VARCHAR(20)		  ,@CNSFNOT VARCHAR(20)
	  -- Variables para m�todos adicionales
	  ,@VLRACEPTADO_ITEM DECIMAL(18,2)   ,@CNSNOTADB_ITEM VARCHAR(20)    ,@ESTADO_ITEM VARCHAR(20)
	  ,@NUEVO_CONSECUTIVO VARCHAR(20)    ,@PREFIJO VARCHAR(10)
	  ,@CONTADOR INT = 0
	  ,@FECHACONC_CONFIRMAR DATE         ,@PERIODO_CERRADO BIT = 0
	  ,@ESTADO_FINAL VARCHAR(20)         ,@FNOT_FECHACONCILIA VARCHAR(20)
	  ,@ITEM_ACTUAL INT                  ,@ITEM_CREDITO INT
	  ,@CONCIGLOSA_TIPOSPERM VARCHAR(200) = ''

BEGIN

	SELECT *
	INTO #JSON
	FROM OPENJSON(@json) WITH (
			MODELO VARCHAR(100) '$.MODELO'
			,METODO VARCHAR(100) '$.METODO'
			,USUARIO VARCHAR(12) '$.USUARIO'
			,PARAMETROS NVARCHAR(MAX) AS JSON
	)

	SELECT   @MODELO = MODELO			,@METODO = METODO
			,@PARAMETROS = PARAMETROS	,@USUARIO = USUARIO
	FROM #JSON

	SELECT @IDSEDE=COALESCE(UBEQ.IDSEDE,USUSU.IDSEDE),@COMPANIA=COALESCE(UBEQ.COMPANIA,USUSU.COMPANIA),  @SYS_COMPUTERNAME=COALESCE(USUSU.SYS_ComputerName,HOST_NAME())   
	FROM USUSU LEFT JOIN UBEQ ON USUSU.SYS_ComputerName=UBEQ.SYS_ComputerName
	WHERE USUSU.USUARIO=@USUARIO

	SELECT @CONCIGLOSA_TIPOSPERM = LTRIM(RTRIM(COALESCE(DATO, '')))
	FROM USVGS
	WHERE IDVARIABLE = 'CONCIGLOSA_TIPOSPERM'

-- M�TODO 1:CRUD CONCI
	IF @METODO='CRUD_FCONCI'     
	BEGIN         
      SELECT @DATOS=DATOS        
      FROM   OPENJSON (@PARAMETROS)
      WITH (           
      DATOS NVARCHAR(MAX) AS JSON 
      )
                 
      SELECT @PROCESO=PROCESO,@IDFCONCI=IDFCONCI,@ESTADO=ESTADO,@FECHACONC=CONVERT(DATE,FECHACONC),@FECHADIG=CONVERT(DATE,FECHADIG),
             @IDTERCERO=IDTERCERO,@CNSEXTERNO=CNSEXTERNO,@VALOR=VALOR,@FECHAPAGCONC=CONVERT(DATE,FECHAPAGCONC),
             @OBSERVACION=OBSERVACION,@FUNCIONARIOADMIN=FUNCIONARIOADMIN,@TIPO=TIPO,@PORCENTAJE=PORCENTAJE   
      FROM   OPENJSON (@DATOS)
      WITH   ( 
         PROCESO VARCHAR(20)             '$.PROCESO',
         IDFCONCI  VARCHAR(20)           '$.IDFCONCI',
         ESTADO VARCHAR(20)              '$.ESTADO',
         FECHACONC VARCHAR(20)           '$.FECHACONC',
         FECHADIG VARCHAR(20)            '$.FECHADIG',
         IDTERCERO VARCHAR(20)           '$.IDTERCERO',
         CNSEXTERNO INT				     '$.CNSEXTERNO',
         VALOR DECIMAL(14,2)             '$.VALOR',
         FECHAPAGCONC VARCHAR(20)        '$.FECHAPAGCONC',
         OBSERVACION VARCHAR(255)        '$.OBSERVACION',
         FUNCIONARIOADMIN  VARCHAR(120)   '$.FUNCIONARIOADMIN',
         TIPO VARCHAR(20)                '$.TIPO.value',
         PORCENTAJE DECIMAL(7,2)          '$.PORCENTAJE'
      ) 

	IF @PROCESO='Borrar'
	BEGIN
        IF EXISTS(SELECT 1 FROM FCONCID WHERE IDFCONCI = @IDFCONCI)
		BEGIN 
			INSERT INTO @TBLERRORES(ERROR)
			SELECT 'La conciliaci�n tiene detalles y no puede eliminarse.';
			SELECT 'KO' OK, ERROR FROM @TBLERRORES
			RETURN
		END

        DELETE FROM FCONCI WHERE IDFCONCI = @IDFCONCI;
        SELECT 'OK' AS OK;
        RETURN;
    END

      IF @PROCESO='Nueva'
      BEGIN
         BEGIN TRY           
               SET @IDFCONCI=''
		       EXEC SPK_GENCONSECUTIVO @COMPANIA,@IDSEDE, '@CONCI', @IDFCONCI OUTPUT  
		       SET @IDFCONCI = @IDSEDE + REPLACE(SPACE(8 - LEN(@IDFCONCI))+LTRIM(RTRIM(@IDFCONCI)),SPACE(1),0)
         END TRY
         BEGIN CATCH
                 INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
                 SELECT 'KO' OK, ERROR FROM @TBLERRORES
                 RETURN
         END CATCH

         INSERT INTO FCONCI(IDFCONCI, IDTERCERO, FECHACONC, CNSEXTERNO, USUARIO, FECHADIG, ESTADO, VALOR, FUNCIONARIOADMIN, OBSERVACION, FECHA_PAGCONC, TIPO, PORCENTAJE, CONTABILIZADA, NROCOMPROBANTE, PROCEDENCIA,  IDSEDE)
         SELECT @IDFCONCI, @IDTERCERO, @FECHACONC, @CNSEXTERNO, @USUARIO, @FECHADIG, 'Ingresada', @VALOR, @FUNCIONARIOADMIN,@OBSERVACION,@FECHAPAGCONC, @TIPO, @PORCENTAJE, 0, NULL, 'CXC', @IDSEDE
      END

      IF @PROCESO='Editar'
      BEGIN
         IF EXISTS(SELECT 1 FROM FCONCI WHERE IDFCONCI=@IDFCONCI AND ESTADO='Ingresada')
         BEGIN
            UPDATE FCONCI SET IDTERCERO=@IDTERCERO, FECHACONC=@FECHACONC, CNSEXTERNO=@CNSEXTERNO,VALOR=@VALOR,FUNCIONARIOADMIN=@FUNCIONARIOADMIN,
                   OBSERVACION=@OBSERVACION, FECHA_PAGCONC=@FECHAPAGCONC, TIPO=@TIPO, PORCENTAJE=@PORCENTAJE
            WHERE IDFCONCI=@IDFCONCI
         END
         ELSE
         BEGIN
            INSERT INTO @TBLERRORES(ERROR)
            SELECT 'No se Encontro Conciliaci�n o ya Esta cerrada, Verifique e intente de nuevo '
         END
      END

      IF(SELECT COUNT(*) FROM @TBLERRORES)>0
      BEGIN
         SELECT 'KO' OK, ERROR FROM @TBLERRORES
         RETURN
      END

      SELECT 'OK' OK 
      RETURN 
   END    

-- M�TODO 2:CRUD CONCID
	IF @METODO='CRUD_FCONCID'     
	BEGIN         
      SELECT @DATOS=DATOS        
      FROM   OPENJSON (@PARAMETROS)
      WITH (           
      DATOS NVARCHAR(MAX) AS JSON 
      )
                 
      SELECT @PROCESO=PROCESO, @ESTADO=ESTADO, @IDFCONCI=IDFCONCI, @CONDCONCEPTO=CONDCONCEPTO, @N_FACTURA=N_FACTURA, @CNSCXC=CNSCXC,
         @ITEM_FCXCDV=ITEM_FCXCDV, @TIPO=TIPO, @CNSGLO=CNSGLO, @SALDONETO=SALDONETO,@VLRRECUPERAR=VLRRECUPERAR,@VLRACEPTADO=VLRACEPTADO,
         @CNSFCGLO=CNSFCGLO,@OBSERVACION=OBSERVACION,@ITEM_FCONCID=ITEM_FCONCID
      FROM   OPENJSON (@DATOS)
      WITH   (  
         PROCESO VARCHAR(20)        '$.PROCESO',
         ESTADO VARCHAR(20)         '$.ESTADO',
         IDFCONCI VARCHAR(20)       '$.IDFCONCI',
         ITEM_FCONCID  INT          '$.ITEM_FCONCID',
         CONDCONCEPTO VARCHAR(20)   '$.CONDCONCEPTO',
         N_FACTURA VARCHAR(20)      '$.N_FACTURA',
         CNSCXC VARCHAR(20)         '$.CNSCXC',
         ITEM_FCXCDV INT            '$.ITEM_FCXCDV',
         TIPO VARCHAR(20)           '$.TIPO',
         CNSGLO VARCHAR(20)         '$.CNSGLO',
         SALDONETO DECIMAL(14,2)    '$.SALDONETO',
         VLRRECUPERAR DECIMAL(14,2) '$.VLRRECUPERAR',
         VLRACEPTADO DECIMAL(14,2)  '$.VLRACEPTADO',
         CNSFCGLO VARCHAR(20)       '$.CNSFCGLO',
		 CNSNOTADB VARCHAR(20)      '$.CNSNOTADB',
         OBSERVACION VARCHAR(255)   '$.OBSERVACION'    
       )    

       IF EXISTS(SELECT 1 FROM FCONCI WHERE IDFCONCI=@IDFCONCI AND ESTADO='Ingresada')
       BEGIN
          IF @PROCESO='Nueva'
          BEGIN
             IF NOT EXISTS(SELECT 1 FROM FCONCID WHERE IDFCONCI=@IDFCONCI AND ITEM_FCXCDV=@ITEM_FCXCDV)
             BEGIN
                IF COALESCE(@CONCIGLOSA_TIPOSPERM, '') <> ''
                   AND NOT EXISTS (
                      SELECT 1
                      FROM STRING_SPLIT(@CONCIGLOSA_TIPOSPERM, ',') S
                      WHERE LTRIM(RTRIM(S.value)) = @TIPO
                   )
                BEGIN
                   INSERT INTO @TBLERRORES(ERROR)
                   SELECT 'El tipo de vencimiento no esta permitido para conciliacion. Tipos permitidos: ' + @CONCIGLOSA_TIPOSPERM
                END

                IF @TIPO IN ('G','C','R','L') AND COALESCE(@CNSGLO,'') = ''
                BEGIN
                   INSERT INTO @TBLERRORES(ERROR)
                   SELECT 'Debe indicar el consecutivo de glosa para este tipo de vencimiento'
                END

                IF COALESCE(@CNSGLO,'') <> ''
                BEGIN
                   IF NOT EXISTS (SELECT 1 FROM FGLO WHERE CNSGLO = @CNSGLO)
                   BEGIN
                      INSERT INTO @TBLERRORES(ERROR)
                      SELECT 'La glosa indicada no existe en el sistema'
                   END
                   ELSE IF EXISTS (SELECT 1 FROM FGLO WHERE CNSGLO = @CNSGLO AND COALESCE(CERRADA, 0) <> 1)
                   BEGIN
                      INSERT INTO @TBLERRORES(ERROR)
                      SELECT 'La glosa no tiene respuesta aplicada. Debe aplicar la respuesta antes de conciliar'
                   END
                   ELSE IF EXISTS (SELECT 1 FROM FGLO WHERE CNSGLO = @CNSGLO AND FECHARESP IS NULL)
                   BEGIN
                      INSERT INTO @TBLERRORES(ERROR)
                      SELECT 'La glosa no tiene fecha de respuesta registrada'
                   END
                   ELSE IF EXISTS (
                      SELECT 1
                      FROM FGLO G
                      WHERE G.CNSGLO = @CNSGLO
                        AND COALESCE(G.RADICADO, '') IN ('', '0')
                        AND NOT EXISTS (
                           SELECT 1 FROM FGLOI GI
                           WHERE GI.CNSGLOI = G.CNSGLOI
                             AND (GI.FECHARAD IS NOT NULL OR COALESCE(GI.RADICADO, 0) = 1)
                        )
                        AND NOT EXISTS (
                           SELECT 1 FROM FGLOID GD
                           INNER JOIN FGLOI GI ON GI.CNSGLOI = GD.CNSGLOI
                           WHERE GD.CNSGLO = G.CNSGLO AND COALESCE(GI.RADICADO, 0) = 1
                        )
                   )
                   BEGIN
                      INSERT INTO @TBLERRORES(ERROR)
                      SELECT 'La glosa no esta radicada'
                   END
                END

                IF (SELECT COUNT(*) FROM @TBLERRORES) = 0
                BEGIN
                SELECT @ITEM_FCONCID=COALESCE(MAX(ITEM_FCONCID),0)+1 FROM FCONCID WHERE IDFCONCI=@IDFCONCI

                INSERT INTO FCONCID(IDFCONCI, ITEM_FCONCID, CNSCXC, N_FACTURA, ITEM_FCXCDV, TIPO, CNSGLO, SALDONETO, VLRACEPTADO, VLRRECUPERAR, 
                                    CNSFNOT, CLASE, ESTADO, OBSERVACION, CONDCONCEPTO, CNSFCGLO, CNSNOTADB, NROCOMPROBANTE_A )
                SELECT @IDFCONCI, @ITEM_FCONCID, @CNSCXC, @N_FACTURA, @ITEM_FCXCDV, @TIPO, @CNSGLO, @SALDONETO, @VLRACEPTADO, @VLRRECUPERAR, 
                       @CNSFNOT, 'C', @ESTADO, @OBSERVACION, @CONDCONCEPTO, @CNSFCGLO, @CNSNOTADB, NULL 
                END
             END
             ELSE
             BEGIN
               INSERT INTO @TBLERRORES(ERROR)
               SELECT 'Ya existe este item en esta conciliaci�n. Verifique e intente de nuevo'
             END
          END

          IF @PROCESO='Editar'
          BEGIN
             IF COALESCE(@CONCIGLOSA_TIPOSPERM, '') <> ''
                AND NOT EXISTS (
                   SELECT 1
                   FROM STRING_SPLIT(@CONCIGLOSA_TIPOSPERM, ',') S
                   WHERE LTRIM(RTRIM(S.value)) = @TIPO
                )
             BEGIN
                INSERT INTO @TBLERRORES(ERROR)
                SELECT 'El tipo de vencimiento no esta permitido para conciliacion. Tipos permitidos: ' + @CONCIGLOSA_TIPOSPERM
             END

             IF @TIPO IN ('G','C','R','L') AND COALESCE(@CNSGLO,'') = ''
             BEGIN
                INSERT INTO @TBLERRORES(ERROR)
                SELECT 'Debe indicar el consecutivo de glosa para este tipo de vencimiento'
             END

             IF COALESCE(@CNSGLO,'') <> ''
             BEGIN
                IF NOT EXISTS (SELECT 1 FROM FGLO WHERE CNSGLO = @CNSGLO)
                BEGIN
                   INSERT INTO @TBLERRORES(ERROR)
                   SELECT 'La glosa indicada no existe en el sistema'
                END
                ELSE IF EXISTS (SELECT 1 FROM FGLO WHERE CNSGLO = @CNSGLO AND COALESCE(CERRADA, 0) <> 1)
                BEGIN
                   INSERT INTO @TBLERRORES(ERROR)
                   SELECT 'La glosa no tiene respuesta aplicada. Debe aplicar la respuesta antes de conciliar'
                END
                ELSE IF EXISTS (SELECT 1 FROM FGLO WHERE CNSGLO = @CNSGLO AND FECHARESP IS NULL)
                BEGIN
                   INSERT INTO @TBLERRORES(ERROR)
                   SELECT 'La glosa no tiene fecha de respuesta registrada'
                END
                ELSE IF EXISTS (
                   SELECT 1
                   FROM FGLO G
                   WHERE G.CNSGLO = @CNSGLO
                     AND COALESCE(G.RADICADO, '') IN ('', '0')
                     AND NOT EXISTS (
                        SELECT 1 FROM FGLOI GI
                        WHERE GI.CNSGLOI = G.CNSGLOI
                          AND (GI.FECHARAD IS NOT NULL OR COALESCE(GI.RADICADO, 0) = 1)
                     )
                     AND NOT EXISTS (
                        SELECT 1 FROM FGLOID GD
                        INNER JOIN FGLOI GI ON GI.CNSGLOI = GD.CNSGLOI
                        WHERE GD.CNSGLO = G.CNSGLO AND COALESCE(GI.RADICADO, 0) = 1
                     )
                )
                BEGIN
                   INSERT INTO @TBLERRORES(ERROR)
                   SELECT 'La glosa no esta radicada'
                END
             END

             IF (SELECT COUNT(*) FROM @TBLERRORES) = 0
             BEGIN
             IF EXISTS(SELECT 1 FROM FCONCID WHERE IDFCONCI=@IDFCONCI AND ITEM_FCXCDV=@ITEM_FCXCDV  AND ITEM_FCONCID=@ITEM_FCONCID)
             BEGIN
               UPDATE FCONCID SET VLRACEPTADO=@VLRACEPTADO,VLRRECUPERAR=@VLRRECUPERAR,CONDCONCEPTO=@CONDCONCEPTO,CNSFCGLO=@CNSFCGLO,OBSERVACION=@OBSERVACION
               WHERE IDFCONCI=@IDFCONCI
               AND ITEM_FCXCDV=@ITEM_FCXCDV
               AND ITEM_FCONCID=@ITEM_FCONCID
             END
             ELSE
             BEGIN
                DELETE FCONCID WHERE IDFCONCI=@IDFCONCI AND ITEM_FCONCID=@ITEM_FCONCID

                SELECT @ITEM_FCONCID=COALESCE(MAX(ITEM_FCONCID),0)+1 FROM FCONCID WHERE IDFCONCI=@IDFCONCI

                INSERT INTO FCONCID(IDFCONCI, ITEM_FCONCID, CNSCXC, N_FACTURA, ITEM_FCXCDV, TIPO, CNSGLO, SALDONETO, VLRACEPTADO, VLRRECUPERAR, 
                                    CNSFNOT, CLASE, ESTADO, OBSERVACION, CONDCONCEPTO, CNSFCGLO, CNSNOTADB, NROCOMPROBANTE_A )
                SELECT @IDFCONCI, @ITEM_FCONCID, @CNSCXC, @N_FACTURA, @ITEM_FCXCDV, @TIPO, @CNSGLO, @SALDONETO, @VLRACEPTADO, @VLRRECUPERAR, 
                       @CNSFNOT, 'C', @ESTADO, @OBSERVACION, @CONDCONCEPTO, @CNSFCGLO, @CNSNOTADB, NULL 
             END
             END
          END

          IF @PROCESO='Borrar'
          BEGIN
              IF EXISTS(SELECT 1 FROM FCONCID WHERE IDFCONCI=@IDFCONCI AND ITEM_FCXCDV=@ITEM_FCXCDV  AND ITEM_FCONCID=@ITEM_FCONCID)
              BEGIN
                  DELETE FCONCID WHERE IDFCONCI=@IDFCONCI AND ITEM_FCXCDV=@ITEM_FCXCDV  AND ITEM_FCONCID=@ITEM_FCONCID
              END
              ELSE
              BEGIN
                 INSERT INTO @TBLERRORES(ERROR)
                 SELECT 'Item no encontrado. Varifique los datos e intente de nuevo '
              END
          END
       END
       ELSE
       BEGIN
         INSERT INTO @TBLERRORES(ERROR)
         SELECT 'Conciliaci�n no Encontrada o ya fue cerrada, Verifique e intente de nuevo '
       END

       IF(SELECT COUNT(*) FROM @TBLERRORES)>0
       BEGIN
          SELECT 'KO' OK, ERROR FROM @TBLERRORES
          RETURN
       END

       SELECT 'OK' OK 
       RETURN 
   END  

-- M�TODO 3: LIMPIAR_FCONCID
	IF @METODO = 'LIMPIAR_FCONCID'
	BEGIN  
		SELECT @IDFCONCI = IDFCONCI
		FROM OPENJSON(@PARAMETROS)
		WITH (
			IDFCONCI VARCHAR(20) '$.IDFCONCI'
		)
    
		IF @IDFCONCI IS NULL OR @IDFCONCI = ''
		BEGIN
			SELECT 'KO' AS OK, 'IDFCONCI es requerido' AS ERROR
			RETURN
		END
    
		DELETE FROM FCONCID 
		WHERE IDFCONCI = @IDFCONCI 
		  AND ESTADO = 'Ingresada'
    
		SELECT 'OK' AS OK, 'Registros eliminados correctamente' AS MENSAJE
		RETURN
	END

-- M�TODO 4: CONFIRMAR_CONCILIACION
	IF @METODO = 'CONFIRMAR_CONCILIACION'
	BEGIN
		SELECT @IDFCONCI = IDFCONCI
		FROM OPENJSON(@PARAMETROS)
		WITH (
			IDFCONCI VARCHAR(20) '$.IDFCONCI'
		)
		
		IF @IDFCONCI IS NULL OR @IDFCONCI = ''
		BEGIN
			SELECT 'KO' AS OK, 'IDFCONCI es requerido' AS ERROR
			RETURN
		END
    
		SELECT @FECHACONC = FECHACONC
		FROM FCONCI
		WHERE IDFCONCI = @IDFCONCI
    
		IF @FECHACONC IS NULL
		BEGIN
			SELECT 'KO' AS OK, 'Conciliaci�n no encontrada' AS ERROR
			RETURN
		END
    
		BEGIN TRY
			SELECT @FNOT_FECHACONCILIA = DBO.FNK_VALORVARIABLE('FNOT_FECHACONCILIA')
			IF @FNOT_FECHACONCILIA = 'CONCILIACION'
			BEGIN
				SELECT @PERIODO_CERRADO = COALESCE(CERRADO, 0)
				FROM PRI
				WHERE FECHA_INI <= @FECHACONC
				  AND FECHA_FIN >= @FECHACONC
            
				IF @PERIODO_CERRADO = 1
				BEGIN
					SELECT 'KO' AS OK, 
						'Tiene Configurado Como Fecha de la Nota Cr�dito Generada en la Conciliaci�n ' + CHAR(13) + CHAR(10) + 
						'La Fecha de Conciliaci�n y El Per�odo Esta Cerrado.' AS ERROR
					RETURN
				END
			END

			IF EXISTS (
				SELECT 1
				FROM FCONCID D
				WHERE D.IDFCONCI = @IDFCONCI
				  AND COALESCE(D.CNSGLO, '') <> ''
				  AND (
					NOT EXISTS (SELECT 1 FROM FGLO G WHERE G.CNSGLO = D.CNSGLO)
					OR EXISTS (SELECT 1 FROM FGLO G WHERE G.CNSGLO = D.CNSGLO AND COALESCE(G.CERRADA, 0) <> 1)
					OR EXISTS (SELECT 1 FROM FGLO G WHERE G.CNSGLO = D.CNSGLO AND G.FECHARESP IS NULL)
					OR EXISTS (
						SELECT 1
						FROM FGLO G
						WHERE G.CNSGLO = D.CNSGLO
						  AND COALESCE(G.RADICADO, '') IN ('', '0')
						  AND NOT EXISTS (
							SELECT 1 FROM FGLOI GI
							WHERE GI.CNSGLOI = G.CNSGLOI
							  AND (GI.FECHARAD IS NOT NULL OR COALESCE(GI.RADICADO, 0) = 1)
						  )
						  AND NOT EXISTS (
							SELECT 1 FROM FGLOID GD
							INNER JOIN FGLOI GI ON GI.CNSGLOI = GD.CNSGLOI
							WHERE GD.CNSGLO = G.CNSGLO AND COALESCE(GI.RADICADO, 0) = 1
						  )
					)
				  )
			)
			BEGIN
				SELECT 'KO' AS OK, 'Existen lineas con glosas no aplicadas o no radicadas. Verifique el detalle antes de confirmar.' AS ERROR
				RETURN
			END

			IF COALESCE(@CONCIGLOSA_TIPOSPERM, '') <> ''
			   AND EXISTS (
					SELECT 1
					FROM FCONCID D
					WHERE D.IDFCONCI = @IDFCONCI
					  AND NOT EXISTS (
						SELECT 1
						FROM STRING_SPLIT(@CONCIGLOSA_TIPOSPERM, ',') S
						WHERE LTRIM(RTRIM(S.value)) = D.TIPO
					  )
			   )
			BEGIN
				SELECT 'KO' AS OK, 'Existen lineas con tipos de vencimiento no permitidos para conciliacion.' AS ERROR
				RETURN
			END
        
			DECLARE cursor_confirmar CURSOR FOR
			SELECT ITEM_FCONCID, VLRACEPTADO, CNSFNOT
			FROM FCONCID
			WHERE IDFCONCI = @IDFCONCI
			  AND VLRACEPTADO > 0
        
			OPEN cursor_confirmar
			FETCH NEXT FROM cursor_confirmar INTO @ITEM_FCONCID, @VLRACEPTADO, @CNSFNOT
        
			WHILE @@FETCH_STATUS = 0
			BEGIN

				IF @CNSFNOT IS NULL OR @CNSFNOT = ''
				BEGIN
					SET @PREFIJO = @IDSEDE + 'C'
					EXEC SPK_GENCONSECUTIVO @IDSEDE, '01', '@FNOTC', @NUEVO_CONSECUTIVO OUTPUT
					SET @NUEVO_CONSECUTIVO = @PREFIJO + RIGHT('00000000' + LTRIM(RTRIM(@NUEVO_CONSECUTIVO)), 8)
                
					UPDATE FCONCID
					SET CNSFNOT = @NUEVO_CONSECUTIVO
					WHERE IDFCONCI = @IDFCONCI
					  AND ITEM_FCONCID = @ITEM_FCONCID
				END
            
				FETCH NEXT FROM cursor_confirmar INTO @ITEM_FCONCID, @VLRACEPTADO, @CNSFNOT
			END
        
			CLOSE cursor_confirmar
			DEALLOCATE cursor_confirmar

			EXEC SPK_APLICA_CONCILIACION 
				@IDFCONCI, 
				@IDSEDE, 
				@COMPANIA, 
				@USUARIO, 
				@SYS_COMPUTERNAME

			SELECT @ESTADO_FINAL = ESTADO
			FROM FCONCI
			WHERE IDFCONCI = @IDFCONCI
        
			IF UPPER(@ESTADO_FINAL) <> 'CERRADA'
			BEGIN
				SELECT 'KO' AS OK, 'La Conciliaci�n No se ha aplicado correctamente, revise y vuelva a intentarlo' AS ERROR
				RETURN
			END
        
			SELECT 'OK' AS OK, 'La Conciliaci�n se ha aplicado correctamente' AS MENSAJE
			RETURN
		END TRY
		BEGIN CATCH
			IF CURSOR_STATUS('global', 'cursor_confirmar') >= 0
			BEGIN
				CLOSE cursor_confirmar
				DEALLOCATE cursor_confirmar
			END        
			SELECT 'KO' AS OK, 'ERROR: ' + ERROR_MESSAGE() AS ERROR
			RETURN
		END CATCH
	END
-- M�TODO 5: ANULAR_CONCILIACION 
	IF @METODO = 'ANULAR_CONCILIACION'
	BEGIN
		SELECT @IDFCONCI = IDFCONCI
		FROM OPENJSON(@PARAMETROS)
		WITH (IDFCONCI VARCHAR(20) '$.IDFCONCI')
    
		DECLARE @ItemActual        INT;
		    
		SET @CONTADOR = 0;
		SET @PREFIJO = @IDSEDE + 'D';

		BEGIN TRY
			BEGIN TRANSACTION;

			DECLARE Cursor_DetalleConciliacion CURSOR LOCAL FAST_FORWARD FOR
			SELECT ITEM_FCONCID, VLRACEPTADO, CNSNOTADB
			FROM FCONCID
			WHERE IDFCONCI = @IDFCONCI AND UPPER(ESTADO) = 'CERRADA'
			ORDER BY ITEM_FCONCID;

			OPEN Cursor_DetalleConciliacion;

			FETCH NEXT FROM Cursor_DetalleConciliacion 
			INTO @ItemActual, @VLRACEPTADO, @CNSNOTADB;

			WHILE @@FETCH_STATUS = 0
			BEGIN
            
				IF @VLRACEPTADO > 0 AND (@CNSNOTADB IS NULL OR @CNSNOTADB = '')
				BEGIN					
					SET @NUEVO_CONSECUTIVO = '';
					EXEC SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE, '@FNOTD', @NUEVO_CONSECUTIVO OUTPUT;
					SET @NUEVO_CONSECUTIVO = @PREFIJO + RIGHT('00000000' + LTRIM(RTRIM(@NUEVO_CONSECUTIVO)), 8);
                
					UPDATE FCONCID SET CNSNOTADB = @NUEVO_CONSECUTIVO 
					WHERE IDFCONCI = @IDFCONCI AND ITEM_FCONCID = @ItemActual;
				END

				EXEC SPK_RETIRA_FACTURA_CONCI 
					@IDFCONCI, 
					@ItemActual, 
					@COMPANIA, 
					@IDSEDE, 
					@USUARIO, 
					@SYS_COMPUTERNAME;

				SET @CONTADOR = @CONTADOR + 1;

				FETCH NEXT FROM Cursor_DetalleConciliacion 
				INTO @ItemActual, @VLRACEPTADO, @CNSNOTADB;
			END

			CLOSE Cursor_DetalleConciliacion;
			DEALLOCATE Cursor_DetalleConciliacion;

			UPDATE FCONCID SET ESTADO = 'Anulada' WHERE IDFCONCI = @IDFCONCI AND UPPER(ESTADO) = 'CERRADA';
			UPDATE FCONCI  SET ESTADO = 'Anulada' WHERE IDFCONCI = @IDFCONCI;

			COMMIT TRANSACTION;

			SELECT 'OK' AS OK, 'Conciliaci�n anulada: ' + CAST(@CONTADOR AS VARCHAR) + ' items procesados.' AS MENSAJE;

		END TRY
		BEGIN CATCH
			IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
        
			IF CURSOR_STATUS('local', 'Cursor_DetalleConciliacion') >= 0
			BEGIN
				CLOSE Cursor_DetalleConciliacion;
				DEALLOCATE Cursor_DetalleConciliacion;
			END

			SELECT 'KO' AS OK, ERROR_MESSAGE() AS ERROR;
		END CATCH
		RETURN;
	END

