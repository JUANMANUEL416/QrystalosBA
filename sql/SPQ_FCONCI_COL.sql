-- M�TODO 7: IMPRIMIR CONCILIACI�N
	IF @METODO = 'IMPRIMIR'
	BEGIN
		SELECT @IDFCONCI = JSON_VALUE(@PARAMETROS, '$.IDFCONCI')
		IF ISNULL(@IDFCONCI, '') = ''
		BEGIN
			SELECT 'KO' AS OK, 'IDFCONCI es requerido para imprimir conciliaci�n' AS ERROR
			RETURN
		END

		SELECT
			CIU.NOMBRE AS CIUDAD,
			SED.IDSEDE,
			SED.NIT AS NIT_SEDE,
			SED.DESCRIPCION AS DESCRIPCION_SEDE,
			SED.DIRECCION AS DIRECCION_SEDE,
			SED.TELEFONOS AS TELEFONOS,
			FCONCI.IDFCONCI,
			FCONCI.FECHACONC,
			FCONCI.FECHADIG,
			FCONCI.ESTADO,
			FCONCI.OBSERVACION,
			FCONCI.VALOR,
			FCONCI.CNSEXTERNO,
			FCONCI.FUNCIONARIOADMIN,
			TER.IDTERCERO,
			TER.RAZONSOCIAL,
			FECHA_IMPRESION = CURRENT_TIMESTAMP,
			BASE = IIF(
				DBO.FNK_VALORVARIABLE('BDATA_PRODUCCION') = DB_NAME(),
				'OK',
				'DEMO'
			),

			FCONCID = (
				SELECT
					FCONCID.ITEM_FCONCID,
					FCONCID.CNSCXC,
					FCONCID.N_FACTURA,
					FCONCID.TIPO,
					N_GLOSA = COALESCE(FCONCID.CNSGLO, ''),
					FCONCID.SALDONETO,
					FCONCID.VLRACEPTADO,
					FCONCID.VLRRECUPERAR 
				FROM FCONCID 
				WHERE FCONCID.IDFCONCI = FCONCI.IDFCONCI
				ORDER BY FCONCID.ITEM_FCONCID
				FOR JSON PATH
			)

		FROM FCONCI 
		INNER JOIN TER ON TER.IDTERCERO = FCONCI.IDTERCERO
		LEFT JOIN SED ON SED.IDSEDE = FCONCI.IDSEDE
		LEFT JOIN CIU ON SED.CIUDAD = CIU.CIUDAD
		WHERE FCONCI.IDFCONCI = @IDFCONCI
		RETURN
	END

	-- M�TODO 7: CARGA EXCEL
	IF @METODO = 'CARGA_EXCEL_FCONCID'
	BEGIN
		DECLARE @DETALLE NVARCHAR(MAX) 
		SELECT 
			@IDFCONCI = JSON_VALUE(@PARAMETROS, '$.IDFCONCI'), 
			@USUARIO = JSON_VALUE(@PARAMETROS, '$.USUARIO'), 
			@DETALLE = JSON_QUERY(@PARAMETROS, '$.DETALLE') 
			
			IF NOT EXISTS (SELECT 1 FROM FCONCI WHERE IDFCONCI = @IDFCONCI AND UPPER(ESTADO) = 'INGRESADA') 
			BEGIN 
				SELECT 'KO' AS OK, 'La conciliaci�n no existe o no est� en estado Ingresada' AS MENSAJE 
				RETURN 
			END

			SELECT 
				N_FACTURA, 
				TIPO, 
				CNSGLO, 
				VLRACEPTADO, 
				CODCONCEPTO, 				
				CAST(0 AS BIT) ERROR,
				CAST('' AS VARCHAR(500)) AS SMSERROR
			INTO #EXCEL_FCONCID 
			FROM OPENJSON(@DETALLE) 
			WITH ( 
				N_FACTURA VARCHAR(20) '$.N_FACTURA', 
				TIPO VARCHAR(20) '$.TIPO', 
				CNSGLO VARCHAR(20) '$.CNSGLO', 
				VLRACEPTADO DECIMAL(14,2)'$.VLRACEPTADO', 
				CODCONCEPTO VARCHAR(20) '$.CONDCONCEPTO'
				) 
		
		--Validaciones en excel 
		--1.Si esta vac�o 
		IF NOT EXISTS (SELECT 1 FROM #EXCEL_FCONCID) 
		BEGIN 
			SELECT 'KO' AS OK, 'El archivo Excel no contiene registros' AS MENSAJE 
			RETURN 
		END 
		--2.campos obligatorios 
		--IF EXISTS ( SELECT 1 FROM #EXCEL_FCONCID WHERE ISNULL(N_FACTURA,'') = ''  )
		--BEGIN 
		--	SELECT 'KO' AS OK, 'Hay filas con campos obligatorios vac�os' AS MENSAJE
		--	RETURN 
		--END
		
		UPDATE #EXCEL_FCONCID SET ERROR=1, SMSERROR='El numero de factura es obligatorio'
		FROM #EXCEL_FCONCID A
		WHERE ERROR=0 AND COALESCE(N_FACTURA,'')=''
		
		UPDATE #EXCEL_FCONCID SET ERROR=1, SMSERROR='El tipo es obligatorio'
		FROM #EXCEL_FCONCID A
		WHERE ERROR=0 AND COALESCE(TIPO,'')=''

		UPDATE #EXCEL_FCONCID SET ERROR=1, SMSERROR='El codigo de concepto es obligatorio'
		FROM #EXCEL_FCONCID A
		WHERE ERROR=0 AND COALESCE(CODCONCEPTO,'')=''

		UPDATE #EXCEL_FCONCID SET ERROR=1, SMSERROR='La Factura  y el Tipo no existe en FCXCDV'
		FROM #EXCEL_FCONCID A
		WHERE ERROR=0 AND NOT EXISTS(SELECT 1 FROM FCXCDV WHERE N_FACTURA = A.N_FACTURA AND TIPO=A.TIPO)
		
		UPDATE #EXCEL_FCONCID SET ERROR=1, SMSERROR='La factura no pertenece al tercero de la conciliaci�n'
		FROM #EXCEL_FCONCID A
		INNER JOIN FCONCI ON FCONCI.IDFCONCI=@IDFCONCI
		WHERE ERROR=0 AND NOT EXISTS(SELECT 1 FROM FTR WHERE FTR.N_FACTURA = A.N_FACTURA AND FTR.IDTERCERO=FCONCI.IDTERCERO)
		
		UPDATE #EXCEL_FCONCID SET ERROR=1, SMSERROR='La factura al ser tipo glosa, ratificacion o conciliacion debe tener asociada el consecutivo de glosa'
		FROM #EXCEL_FCONCID A
		WHERE A.ERROR=0 AND A.TIPO IN('G','C','R','L') AND COALESCE(A.CNSGLO,'')=''

		IF COALESCE(@CONCIGLOSA_TIPOSPERM, '') <> ''
		BEGIN
			UPDATE #EXCEL_FCONCID SET ERROR=1, SMSERROR='El tipo de vencimiento no esta permitido para conciliacion'
			FROM #EXCEL_FCONCID A
			WHERE A.ERROR=0
			  AND NOT EXISTS (
				SELECT 1
				FROM STRING_SPLIT(@CONCIGLOSA_TIPOSPERM, ',') S
				WHERE LTRIM(RTRIM(S.value)) = A.TIPO
			  )
		END

		UPDATE #EXCEL_FCONCID SET ERROR=1, SMSERROR='La glosa indicada no existe en el sistema'
		FROM #EXCEL_FCONCID A
		WHERE A.ERROR=0 AND COALESCE(A.CNSGLO,'') <> ''
		  AND NOT EXISTS (SELECT 1 FROM FGLO G WHERE G.CNSGLO = A.CNSGLO)

		UPDATE #EXCEL_FCONCID SET ERROR=1, SMSERROR='La glosa no tiene respuesta aplicada'
		FROM #EXCEL_FCONCID A
		WHERE A.ERROR=0 AND COALESCE(A.CNSGLO,'') <> ''
		  AND EXISTS (SELECT 1 FROM FGLO G WHERE G.CNSGLO = A.CNSGLO AND COALESCE(G.CERRADA, 0) <> 1)

		UPDATE #EXCEL_FCONCID SET ERROR=1, SMSERROR='La glosa no tiene fecha de respuesta registrada'
		FROM #EXCEL_FCONCID A
		WHERE A.ERROR=0 AND COALESCE(A.CNSGLO,'') <> ''
		  AND EXISTS (SELECT 1 FROM FGLO G WHERE G.CNSGLO = A.CNSGLO AND G.FECHARESP IS NULL)

		UPDATE #EXCEL_FCONCID SET ERROR=1, SMSERROR='La glosa no esta radicada'
		FROM #EXCEL_FCONCID A
		WHERE A.ERROR=0 AND COALESCE(A.CNSGLO,'') <> ''
		  AND EXISTS (
			SELECT 1
			FROM FGLO G
			WHERE G.CNSGLO = A.CNSGLO
			  AND COALESCE(G.RADICADO, '') IN ('', '0')
			  AND NOT EXISTS (
				SELECT 1 FROM FGLOI GI
				WHERE GI.CNSGLOI = G.CNSGLOI
				  AND (GI.FECHARAD IS NOT NULL OR COALESCE(GI.RADICADO, 0) = 1)
			  )
			  AND NOT EXISTS (
				SELECT 1 FROM FGLOID GD
				INNER JOIN FGLOI GI ON GI.CNSGLOI = GD.CNSGLOI
				WHERE GD.CNSGLO = G.CNSGLO AND COALESCE(GI.RADICADO, 0) = 1
			  )
		  )
		
		UPDATE #EXCEL_FCONCID SET ERROR=1, SMSERROR='El saldo de la factura es menor o igual a 0 (cero)'
		FROM #EXCEL_FCONCID A
		WHERE A.ERROR=0 AND A.TIPO IN('G','C','R','L') 
			AND EXISTS (SELECT 1 FROM FCXCDV V WHERE V.N_FACTURA=A.N_FACTURA AND A.TIPO=V.TIPO AND A.CNSGLO=V.CNSGLO AND COALESCE(V.SALDONETO,0)<=0)

		UPDATE #EXCEL_FCONCID SET ERROR=1, SMSERROR='El saldo de la factura es menor o igual a 0 (cero)'
		FROM #EXCEL_FCONCID A
		WHERE A.ERROR=0 AND A.TIPO NOT IN('G','C','R','L') 
			AND EXISTS (SELECT 1 FROM FCXCDV V WHERE V.N_FACTURA=A.N_FACTURA AND A.TIPO=V.TIPO AND COALESCE(V.SALDONETO,0)<=0)
			
		UPDATE #EXCEL_FCONCID SET ERROR=1, SMSERROR='El saldo de la factura es menor al valor aceptado'
		FROM #EXCEL_FCONCID A
		WHERE A.ERROR=0 AND A.TIPO IN('G','C','R','L')
			AND NOT EXISTS (SELECT 1 FROM FCXCDV V WHERE V.N_FACTURA=A.N_FACTURA AND A.TIPO=V.TIPO AND A.CNSGLO=V.CNSGLO AND COALESCE(V.SALDONETO,0) >= A.VLRACEPTADO)

		UPDATE #EXCEL_FCONCID SET ERROR=1, SMSERROR='El saldo de la factura es menor al valor aceptado'
		FROM #EXCEL_FCONCID A
		WHERE A.ERROR=0 AND A.TIPO NOT IN('G','C','R','L') 
			AND NOT EXISTS (SELECT 1 FROM FCXCDV V WHERE V.N_FACTURA=A.N_FACTURA AND A.TIPO=V.TIPO AND COALESCE(V.SALDONETO,0) >= A.VLRACEPTADO)
			
		UPDATE #EXCEL_FCONCID SET ERROR=1, SMSERROR='La factura y tipo de factura ya existe en esta conciliaci�n'
		FROM #EXCEL_FCONCID A
		INNER JOIN FCONCID ON FCONCID.IDFCONCI=@IDFCONCI AND FCONCID.N_FACTURA=A.N_FACTURA AND FCONCID.TIPO=A.TIPO
		WHERE ERROR=0 
		
		UPDATE #EXCEL_FCONCID SET ERROR=1, SMSERROR='La factura y tipo de factura ya existe en otra conciliaci�n'
		FROM #EXCEL_FCONCID A
		WHERE ERROR=0 AND EXISTS (SELECT 1 FROM FCONCID D WHERE D.N_FACTURA=A.N_FACTURA AND D.TIPO=A.TIPO AND D.IDFCONCI<>@IDFCONCI AND D.ESTADO='INGRESADA')

		UPDATE #EXCEL_FCONCID SET ERROR=1, SMSERROR='El concepto ingresado no existe en la tabla de configuracion CPNT'
		FROM #EXCEL_FCONCID A
		WHERE A.ERROR=0
		  AND NOT EXISTS (SELECT 1 FROM CPNT C WHERE C.CODIGO=A.CODCONCEPTO)

		--Inserci�n masiva 
		DECLARE @BASE_ITEM INT 
		
		SELECT @BASE_ITEM = COALESCE(MAX(ITEM_FCONCID),0) FROM FCONCID WHERE IDFCONCI = @IDFCONCI 

		INSERT INTO FCONCID ( 
					IDFCONCI, 
					ITEM_FCONCID, 
					CNSCXC, 
					N_FACTURA, 
					ITEM_FCXCDV, 
					TIPO, 
					CNSGLO, 
					SALDONETO, 
					VLRACEPTADO, 
					VLRRECUPERAR, 
					CLASE, 
					ESTADO, 
					OBSERVACION, 
					CONDCONCEPTO ) 
		SELECT 
			@IDFCONCI, 
			ROW_NUMBER() OVER (ORDER BY (SELECT 1)) + @BASE_ITEM, 
			V.CNSCXC,
			V.N_FACTURA,
			V.ITEM,
			A.TIPO, 
			A.CNSGLO,
			V.SALDONETO, 
			COALESCE(A.VLRACEPTADO,0), 
			COALESCE(V.SALDONETO,0)-COALESCE(A.VLRACEPTADO,0) VLRRECUPERAR, 
			'C', 
			'Ingresada', 
			'', 
			A.CODCONCEPTO 
		FROM #EXCEL_FCONCID A
		INNER JOIN FCXCDV V ON V.N_FACTURA=A.N_FACTURA AND V.TIPO=A.TIPO
			AND (A.TIPO NOT IN ('G','C','R','L') OR V.CNSGLO = A.CNSGLO)
		WHERE A.ERROR=0

		SELECT 'OK' AS OK, 'Carga Excel realizada correctamente' AS MENSAJE

		SELECT * FROM #EXCEL_FCONCID A 
		WHERE A.ERROR=1
	END
