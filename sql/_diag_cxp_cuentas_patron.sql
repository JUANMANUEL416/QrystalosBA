SET NOCOUNT ON;
DECLARE @T TABLE (CNSFCXP varchar(20) PRIMARY KEY);
INSERT INTO @T VALUES
 (N'03CM002080'),(N'03CM002152'),(N'03CM002125'),(N'03CM002102'),(N'03CM002116'),
 (N'03CM002375'),(N'03CM002412'),(N'34CM000132');

SELECT P.CNSFCXP, P.NOREFERENCIA, P.ESTADO, P.CONTABILIZADA,
  D.ITEM, D.IDSERVICIO, CONVERT(decimal(18,2), D.VLR_IVA) IVA,
  D.CUENTA_SER, D.CUENTA_IVA, A.IDITAR,
  C.MCUEGRAV, C.CUENTAGRAV
FROM @T T
JOIN dbo.FCXP P ON P.CNSFCXP = T.CNSFCXP
JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
LEFT JOIN dbo.IART A ON A.IDARTICULO = D.IDSERVICIO
LEFT JOIN dbo.CUE C ON C.CUENTA = D.CUENTA_SER
ORDER BY P.CNSFCXP, D.ITEM;
