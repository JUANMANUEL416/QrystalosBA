CREATE OR ALTER PROCEDURE DBO.SPQ_USVGS_COL
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @PARAMETROS NVARCHAR(MAX), @MODELO   VARCHAR(100), @METODO     VARCHAR(100)
DECLARE  @USUARIO    VARCHAR(20),   @GRUPO      VARCHAR(8), @IDVARIABLE VARCHAR(20),
	      @DATO VARCHAR(256), @OBSERVACION VARCHAR(MAX)
DECLARE  @ERRORES AS TABLE(ERROR VARCHAR(MAX))
BEGIN
	SELECT  @MODELO = MODELO , @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS=PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)  AS JSON
	)
	--SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO
	--FROM #JSON
	IF @METODO = 'VALORVARIABLE'
	BEGIN
		SELECT @IDVARIABLE = IDVARIABLE
		FROM OPENJSON(@PARAMETROS)
		WITH (IDVARIABLE VARCHAR(20) '$.IDVARIABLE')

		SELECT OK = 'OK'

		SELECT @DATO = COALESCE(DATO,''), @OBSERVACION = COALESCE(OBSERVACION,'')
		FROM USVGS WHERE IDVARIABLE = @IDVARIABLE

		SELECT DATO = @DATO, IDVARIABLE = @IDVARIABLE, OBSERVACION = @OBSERVACION
	END
	IF @METODO = 'VALORVARIABLES'
	BEGIN
		IF ISJSON(@PARAMETROS) <> 1
		BEGIN
			SELECT OK = 'ERROR', MENSAJE = 'PARAMETROS no es JSON válido';
			RETURN;
		END;

		SELECT OK = 'OK';

		;WITH VARIABLES AS
		(
			SELECT DISTINCT IDVARIABLE
			FROM OPENJSON(@PARAMETROS, '$.VARIABLES')
			WITH (IDVARIABLE VARCHAR(20) '$')
		)
		SELECT  V.IDVARIABLE, COALESCE(U.DATO, '') AS DATO, COALESCE(U.OBSERVACION, '') AS OBSERVACION
		FROM VARIABLES V
		LEFT JOIN USVGS U ON U.IDVARIABLE = V.IDVARIABLE;

		RETURN;
	END

	IF @METODO = 'CONF_INVENTARIO'
	BEGIN

		SELECT OK = 'OK'

		EXEC DBO.SPK_INSERT_USVGS_MODULO @MODULO = 'INV'
		SELECT DBO.FNK_TESTCONFIG('INV') AS VARIABLES_PENDIENTES
	END

	IF @METODO = 'ACTUALIZA_DATO'
	BEGIN
		BEGIN TRY
			SELECT @IDVARIABLE = JSON_VALUE(@PARAMETROS, '$.IDVARIABLE')
				

			IF COALESCE(@IDVARIABLE,'')='' 
				INSERT INTO @ERRORES
				SELECT 'Id. Variable es obligatorio'
			ELSE
			BEGIN
				SELECT @DATO = DATO FROM USVGS WHERE IDVARIABLE = @IDVARIABLE

				UPDATE USVGS 
				SET DATO = JSON_VALUE(@PARAMETROS, '$.DATO')
				WHERE IDVARIABLE = @IDVARIABLE

				INSERT INTO KLOG (TABLA, ACCION, FECHA_LOG, USUARIO, DETALLE, CAMPO, VALOR_ANT, VALOR_NUEVO, PROCEDENCIA)
				SELECT 'USVGS','CAMBIAR', DBO.FNK_GETDATE(), ISNULL(@USUARIO, SYSTEM_USER), @IDVARIABLE, 'USVGS:DATO' ,@DATO, JSON_VALUE(@PARAMETROS, '$.DATO'), APP_NAME()
			END
		END TRY
		BEGIN CATCH
			INSERT INTO @ERRORES(ERROR) SELECT ERROR_MESSAGE()            
		END CATCH


		IF (SELECT COUNT(1) FROM @ERRORES)>0
		BEGIN
			SELECT OK='KO'
			SELECT * FROM @ERRORES
			RETURN
		END

		SELECT 'OK' AS OK, @IDVARIABLE AS IDVARIABLE
	END
END
