CREATE OR ALTER PROCEDURE DBO.SPQ_IUNI
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @PARAMETROS NVARCHAR(MAX), @MODELO         VARCHAR(100),   @METODO         VARCHAR(100)
DECLARE  @USUARIO    VARCHAR(20),   @IDUNIDAD		VARCHAR(100),	@DESCRIPCION	VARCHAR(1000)
DECLARE	 @IDITAR	 VARCHAR(2)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDUNIDAD = IDUNIDAD, @DESCRIPCION = DESCRIPCION, @IDITAR = IDITAR 
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				IDUNIDAD VARCHAR(100)  '$.IDUNIDAD', DESCRIPCION VARCHAR(1000)  '$.DESCRIPCION',
				IDITAR	 VARCHAR(2)	   '$.IDITAR'
			)

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'LA UNIDAD DE MEDIDA YA EXISTE'
			WHERE EXISTS (SELECT * FROM IUNI WHERE IDUNIDAD = @IDUNIDAD)

			IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
			BEGIN
				INSERT INTO IUNI (IDUNIDAD ,DESCRIPCION ,IDITAR ) 
				SELECT @IDUNIDAD, @DESCRIPCION, @IDITAR
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ACTUALIZAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDUNIDAD = IDUNIDAD, @DESCRIPCION = DESCRIPCION, @IDITAR = IDITAR 
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				IDUNIDAD VARCHAR(100)  '$.IDUNIDAD', DESCRIPCION VARCHAR(1000)  '$.DESCRIPCION',
				IDITAR	 VARCHAR(2)  '$.IDITAR'
			)

			UPDATE IUNI SET DESCRIPCION = @DESCRIPCION, IDITAR = @IDITAR WHERE IDUNIDAD = @IDUNIDAD			
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
	
	IF @METODO = 'ELIMINAR'
	BEGIN
		BEGIN TRY
			SELECT @IDUNIDAD = JSON_VALUE(@PARAMETROS, '$.IDUNIDAD')

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'LA UNIDAD DE MEDIDA TIENE ARTICULOS RELACIONADOS (IART)'
			WHERE EXISTS (SELECT * FROM IART WHERE IDUNIDAD = @IDUNIDAD)

			IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
			BEGIN
				DELETE FROM IUNI WHERE IDUNIDAD = @IDUNIDAD
			END		
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
END
