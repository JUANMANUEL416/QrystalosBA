IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='SPK_ADMIN_PAGOMASIVO' AND XTYPE='P')
BEGIN
 DROP PROCEDURE SPK_ADMIN_PAGOMASIVO
END

GO
CREATE PROCEDURE DBO.SPK_ADMIN_PAGOMASIVO
	@CNSFCXPP             VARCHAR(20), 
     @CNSFCXPPM            VARCHAR(20),
     @TAREA                VARCHAR(6),
     @SYS_COMPUTERNAME     VARCHAR(255),
     @USUARIO              VARCHAR(12)
WITH ENCRYPTION
AS
DECLARE @SALDO    DECIMAL(14,2)
DECLARE @ESTADO   VARCHAR(1)
DECLARE @CODCAJA  VARCHAR(4)
DECLARE @CNSFACJ  VARCHAR(20)
DECLARE @CNSFCXP  VARCHAR(20)
BEGIN
   IF @TAREA='ANULAR' 
   BEGIN
      PRINT 'ANULAR'

      SELECT @CODCAJA=CODCAJA,
         @CNSFACJ=CNSFACJ,
         @CNSFCXP=CNSFCXP
      FROM FCXPP
      WHERE CNSFCXPP=@CNSFCXPP AND CNSFCXPPM=@CNSFCXPPM

      UPDATE FCXPP SET ESTADO='A', FECHACONF=DBO.FNK_FECHA_SIN_MLS(GETDATE()), 
                     SYS_COMPUTERNAME=@SYS_COMPUTERNAME, USUARIOCONF=@USUARIO
      WHERE CNSFCXPP=@CNSFCXPP
  
      UPDATE FCXPPM SET VALOR=(SELECT SUM(ABONO) FROM FCXPP WHERE CNSFCXPPM=@CNSFCXPPM AND ESTADO<>'A')
      WHERE CNSFCXPPM=@CNSFCXPPM

      DELETE FROM FCJD WHERE CODCAJA=@CODCAJA AND CNSFACJ=@CNSFACJ AND IDSERVICIO=@CNSFCXPP

      UPDATE FCXP SET ESTADO=(CASE WHEN EXISTS(SELECT ABONO 
                                             FROM FCXPP 
                                             WHERE CNSFCXP=@CNSFCXP AND ESTADO<>'A') THEN 'C' ELSE 'N' END)
      WHERE CNSFCXP=@CNSFCXP

      UPDATE FCJ SET VALORTOTAL=(SELECT SUM(VALORTOTAL) FROM FCJD WHERE CNSFACJ=@CNSFACJ AND CODCAJA=@CODCAJA)
      WHERE CNSFACJ=@CNSFACJ AND CODCAJA=@CODCAJA  

      EXEC SPK_CALCULOVALORESCXP @CNSFCXP
   END
END
