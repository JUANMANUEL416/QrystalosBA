CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NPRFE @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
BEGIN
	SET NOCOUNT ON;
	SET XACT_ABORT ON;-- Revierte autom�ticamente si hay un error fatal

	DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20);
	DECLARE @PROCESO VARCHAR(20), @CODPRFEDITE VARCHAR(20);
	DECLARE @NUMDOC VARCHAR(20), @CODPRF VARCHAR(20), @NUMDOCCOPY VARCHAR(20);
	DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX));

	-- Extracci�n inicial
	SELECT @MODELO = MODELO, @METODO = UPPER(METODO), @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@JSON) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			);

	BEGIN TRY
		-- --- M�TODO: GUARDAR (INSERTAR / EDITAR) ---
		IF @METODO = 'GUARDAR'
		BEGIN
			SELECT @NUMDOC = NUMDOC, @CODPRF = CODPRF, @PROCESO = UPPER(PROCESO), @CODPRFEDITE = JSON_VALUE(DATO, '$.CODPRFEDITE')
			FROM OPENJSON(@PARAMETROS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC', CODPRF VARCHAR(20) '$.CODPRF', PROCESO VARCHAR(20) '$.PROCESO', DATO NVARCHAR(MAX) AS JSON
					);

			IF @PROCESO = 'INSERTAR'
			BEGIN
				IF EXISTS (
						SELECT 1
						FROM NPRFE
						WHERE NUMDOC = @NUMDOC AND CODPRF = @CODPRF
						)
					INSERT INTO @TBLERRORES (ERROR)
					VALUES (CONCAT ('EL APORTE YA SE ENCUENTRA REGISTRADO PARA EL EMPLEADO ', @NUMDOC)
						);
				ELSE
					INSERT INTO NPRFE (NUMDOC, CODPRF)
					VALUES (@NUMDOC, @CODPRF);
			END
			ELSE IF @PROCESO = 'EDITAR'
			BEGIN
				UPDATE NPRFE
				SET CODPRF = @CODPRF
				WHERE NUMDOC = @NUMDOC AND CODPRF = @CODPRFEDITE;
			END
		END
				-- --- M�TODO: ELIMINAR ---
		ELSE IF @METODO = 'ELIMINAR'
		BEGIN
			SELECT @NUMDOC = NUMDOC, @CODPRF = CODPRF
			FROM OPENJSON(@PARAMETROS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC', CODPRF VARCHAR(20) '$.CODPRF');

			DELETE
			FROM NPRFE
			WHERE NUMDOC = @NUMDOC AND CODPRF = @CODPRF;
		END
				-- --- M�TODO: COPIAR ---
		ELSE IF @METODO = 'COPIAR_NPRFE'
		BEGIN
			SELECT @NUMDOC = NUMDOC, @NUMDOCCOPY = NUMDOCCOPY
			FROM OPENJSON(@PARAMETROS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC', NUMDOCCOPY VARCHAR(20) '$.NUMDOCCOPY');

			BEGIN TRANSACTION;

			-- Limpieza de registros existentes
			DELETE
			FROM NFUNR
			WHERE NUMDOC = @NUMDOC;

			DELETE
			FROM NPRFED
			WHERE NUMDOC = @NUMDOC;

			DELETE
			FROM NPRFE
			WHERE NUMDOC = @NUMDOC;

			-- Copia de registros desde el origen
			INSERT INTO NPRFE (NUMDOC, CODPRF)
			SELECT @NUMDOC, CODPRF
			FROM NPRFE
			WHERE NUMDOC = @NUMDOCCOPY;

			INSERT INTO NPRFED (NUMDOC, CODPRF, ITEM, FECHAINI, IDTERCERO)
			SELECT @NUMDOC, CODPRF, ITEM, FECHAINI, IDTERCERO
			FROM NPRFED
			WHERE NUMDOC = @NUMDOCCOPY;

			COMMIT TRANSACTION;
		END
	END TRY

	BEGIN CATCH
		-- Si hay una transacci�n abierta en caso de error, se revierte
		IF @@TRANCOUNT > 0
			ROLLBACK TRANSACTION;

		INSERT INTO @TBLERRORES (ERROR)
		VALUES (ERROR_MESSAGE());
	END CATCH

	-- --- RETORNO DE RESULTADOS UNIFICADO ---
	IF EXISTS (
			SELECT 1
			FROM @TBLERRORES
			)
	BEGIN
		SELECT 'KO' AS OK;

		SELECT ERROR
		FROM @TBLERRORES;
	END
	ELSE
	BEGIN
		SELECT 'OK' AS OK;
	END
END
