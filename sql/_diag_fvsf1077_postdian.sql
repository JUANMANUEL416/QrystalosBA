SET NOCOUNT ON;
DECLARE @NF VARCHAR(20) = N'FVSF1077';
DECLARE @CNS VARCHAR(20) = N'2500001087';

SELECT F.N_FACTURA, F.CNSFCT, F.VR_TOTAL, F.VALORSERVICIOS, F.VIVA, F.VALORCOPAGO, F.COPAPROPIO, F.CP_VLR_COPAGOS,
  F.VR_ABONOS, F.DESCUENTO, F.VALORPCOMP
FROM dbo.FTR F WHERE F.N_FACTURA = @NF;

SELECT D.ITEM, D.REFERENCIA, D.CANTIDAD, D.VALOR, D.VLR_SERVICI, D.VR_TOTAL, D.PCOSTO, D.VIVA, D.PIVA
FROM dbo.FTRD D WHERE D.N_FACTURA = @NF ORDER BY D.ITEM;

SELECT D.ITEM, D.METODO, D.TIPO, D.FECHA, LEN(CAST(D.xml_solicitud AS NVARCHAR(MAX))) LEN_XML
FROM dbo.FDIANR D WHERE D.CNSDOCUMENTO = @CNS ORDER BY D.ITEM DESC;

SELECT TOP 1
  CAST(D.xml_solicitud AS NVARCHAR(MAX)) AS XML_SNIP
FROM dbo.FDIANR D
WHERE D.CNSDOCUMENTO = @CNS AND D.METODO = N'SendBillSync' AND D.TIPO = N'FV'
ORDER BY D.ITEM DESC;
