CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NCAR @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20)
DECLARE @PROCESO VARCHAR(20)
DECLARE @CODCARGO VARCHAR(20), @DESCRIPCION VARCHAR(255), @ALTORIESGO BIT, @CODCARGOEDITE VARCHAR(20)
DECLARE @DATO NVARCHAR(MAX)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @CODCARGO = CODCARGO, @DESCRIPCION = DESCRIPCION, @ALTORIESGO = ALTORIESGO, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (CODCARGO VARCHAR(20) '$.CODCARGO', DESCRIPCION VARCHAR(255) '$.DESCRIPCION', ALTORIESGO BIT '$.ALTORIESGO', PROCESO VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('EL AREA ', @CODCARGO, ' YA SE ENCUENTRA REGISTRADO')
					WHERE EXISTS (
							SELECT 1
							FROM NCAR
							WHERE CODCARGO = @CODCARGO
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO NCAR (CODCARGO, DESCRIPCION, ALTORIESGO)
						SELECT @CODCARGO, @DESCRIPCION, @ALTORIESGO
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @DATO = DATO
					FROM OPENJSON(@PARAMETROS) WITH (DATO NVARCHAR(MAX) AS JSON)

					SELECT @CODCARGOEDITE = CODCARGOEDITE
					FROM OPENJSON(@DATO) WITH (CODCARGOEDITE VARCHAR(20) '$.CODCARGOEDITE')

					IF (@CODCARGOEDITE <> @CODCARGO)
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('EL AREA ', @CODCARGO, ' YA SE ENCUENTRA REGISTRADO')
						WHERE EXISTS (
								SELECT 1
								FROM NCAR
								WHERE CODCARGO = @CODCARGO
								)

						IF (
								SELECT COUNT(*)
								FROM @TBLERRORES
								) <= 0
						BEGIN
							UPDATE NCAR
							SET CODCARGO = @CODCARGO, DESCRIPCION = @DESCRIPCION, ALTORIESGO = @ALTORIESGO
							WHERE CODCARGO = @CODCARGOEDITE
						END
					END
					ELSE
					BEGIN
						UPDATE NCAR
						SET DESCRIPCION = @DESCRIPCION, ALTORIESGO = @ALTORIESGO
						WHERE CODCARGO = @CODCARGO
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @CODCARGO = CODCARGO
		FROM OPENJSON(@PARAMETROS) WITH (CODCARGO VARCHAR(20) '$.CODCARGO')

		BEGIN TRY
			DELETE
			FROM NCAR
			WHERE CODCARGO = @CODCARGO
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
