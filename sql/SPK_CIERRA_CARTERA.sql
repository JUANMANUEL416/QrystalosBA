IF EXISTS (SELECT name FROM sysobjects 
   WHERE NAME = 'SPK_CIERRA_CARTERA' AND type = 'P')
   DROP PROCEDURE SPK_CIERRA_CARTERA

GO
CREATE PROCEDURE DBO.SPK_CIERRA_CARTERA 
@ANO     VARCHAR(4),
@MES     VARCHAR(2),
@USUARIO VARCHAR(12),
@PROCEDENCIA VARCHAR(10)
WITH ENCRYPTION
AS
DECLARE @AUX INT
DECLARE @FECHACORTE DATETIME
BEGIN
	IF COALESCE(DBO.FNK_VALORVARIABLE('INFO_CARTERACONGLOSA'),'XX') NOT IN('CONGLO','SINGLO')
	BEGIN
		RAISERROR('La variable del sistema  INFO_CARTERACONGLOSA no esta Configurada.. No se Puede Continuar',16,1)
		RETURN
	END
	SET @FECHACORTE = DBO.FNK_DIA_DEL_MES(@ANO, @MES, 'ULTIMO')
	SET @FECHACORTE=DATEADD(DAY,1,@FECHACORTE)
	--DELETE  FCARTH WHERE ANO = @ANO AND MES = @MES AND PROCEDENCIA=@PROCEDENCIA
	SELECT @AUX = COUNT(*) FROM FCARTH WHERE ANO = @ANO AND MES = @MES AND PROCEDENCIA=@PROCEDENCIA
	IF @AUX IS NULL
		SELECT @AUX = 0


	IF @AUX > 0
	BEGIN
		PRINT 'YA SE REALIZO EL CIERRE DE ESTE MES'
		IF @PROCEDENCIA='CARTERA'
		BEGIN
			IF (SELECT ISNULL(CERRADO_CARTERA,0) FROM PRI WHERE ANO = @ANO AND MES =@MES)=0
			UPDATE PRI SET CERRADO_CARTERA = 1 WHERE ANO = @ANO AND MES = @MES 
		END
		ELSE
		BEGIN
			IF @PROCEDENCIA='FACTURA'
			BEGIN
				IF (SELECT ISNULL(CERRADO_FAC,0) FROM PRI WHERE ANO = @ANO AND MES =@MES)=0
					UPDATE PRI SET CERRADO_FAC = 1 WHERE ANO = @ANO AND MES = @MES 
			END
			ELSE
			BEGIN
				IF (SELECT ISNULL(CERRADO_CXP,0) FROM PRI WHERE ANO = @ANO AND MES =@MES)=0
					UPDATE PRI SET CERRADO_CXP = 1 WHERE ANO = @ANO AND MES = @MES 
			END
		END
		RETURN
	END
	DELETE  FCARTH WHERE ANO = @ANO AND MES = @MES AND PROCEDENCIA=@PROCEDENCIA
	IF @PROCEDENCIA='CARTERA'
	BEGIN
		INSERT INTO FCARTH(ANO, MES, IDTERCERO, CNSCXC, N_FACTURA, ITEM, CNSGLO, TIPO, SALDONETO, FECHA, F_VENCE, F_RECIBIDO, SALDOINICIAL, 
							MARCAPAGO, DIASVENCE, PORVENCER, DM361_MAS, DM181_360, DM151_180, DM121_150, DM91_120, DM61_90, DM31_60, DM0_30,
							D0_30, D31_60, D61_90, D91_120, D121_150, D151_180, D181_360, D361_MAS, PROCEDENCIA, IDPLAN, NORADICADA ,PARTICULAR,
							RAD,CLASEINFO)
		SELECT @ANO, @MES, IDTERCERO, CNSCXC, N_FACTURA, ITEM, CNSGLO, TIPO, SALDONETO, FECHA, F_VENCE, F_RECIBIDO, SALDOINICIAL, 
				MARCAPAGO, DIASVENCE, PORVENCER, DM361_MAS, DM181_360, DM151_180, DM121_150, DM91_120, DM61_90, DM31_60, DM0_30,
				D0_30, D31_60, D61_90, D91_120, D121_150, D151_180, D181_360, D361_MAS, @PROCEDENCIA, IDPLAN, NORADICADA ,PARTICULAR,
				RAD,CLASEINFO
		FROM   VWK_CXCDIASVTO 
		WHERE  VWK_CXCDIASVTO.CLASEINFO=DBO.FNK_VALORVARIABLE('INFO_CARTERACONGLOSA')
		AND @FECHACORTE>CASE WHEN VWK_CXCDIASVTO.RAD='SI' THEN F_RECIBIDO ELSE FECHA END
	END
	IF @PROCEDENCIA='FACTURA'
	BEGIN
		INSERT INTO FCARTH(ANO, MES, IDTERCERO, CNSCXC, N_FACTURA, ITEM, CNSGLO, TIPO, SALDONETO, FECHA, F_VENCE, F_RECIBIDO, SALDOINICIAL, 
							MARCAPAGO, DIASVENCE, PORVENCER, DM361_MAS, DM181_360, DM151_180, DM121_150, DM91_120, DM61_90, DM31_60, DM0_30,
							D0_30, D31_60, D61_90, D91_120, D121_150, D151_180, D181_360, D361_MAS, PROCEDENCIA, IDPLAN, NORADICADA ,PARTICULAR,
							RAD)
		SELECT @ANO, @MES, VK.IDTERCERO, CNSCXC, VK.N_FACTURA, ITEM, CNSGLO, TIPO, SALDONETO, FECHA, VK.F_VENCE, F_RECIBIDO, SALDOINICIAL, 
				MARCAPAGO, DIASVENCE, PORVENCER, DM361_MAS, DM181_360, DM151_180, DM121_150, DM91_120, DM61_90, DM31_60, DM0_30,
				D0_30, D31_60, D61_90, D91_120, D121_150, D151_180, D181_360, D361_MAS, @PROCEDENCIA, VK.IDPLAN, NORADICADA ,PARTICULAR,
				RAD
		FROM   VWK_CXCDIASVTO VK INNER JOIN FTR ON VK.N_FACTURA=FTR.N_FACTURA
		WHERE  YEAR(FTR.F_FACTURA)=@ANO
		AND MONTH(FTR.F_FACTURA)=@MES
		AND VK.CLASEINFO=DBO.FNK_VALORVARIABLE('INFO_CARTERACONGLOSA')
	END
	IF @PROCEDENCIA='CXP'
	BEGIN
		INSERT INTO FCARTH(ANO, MES, IDTERCERO, CNSCXC, N_FACTURA, ITEM, CNSGLO, TIPO, SALDONETO, FECHA, F_VENCE, F_RECIBIDO, SALDOINICIAL, 
							MARCAPAGO, DIASVENCE, PORVENCER, DM361_MAS, DM181_360, DM151_180, DM121_150, DM91_120, DM61_90, DM31_60, DM0_30,
							D0_30, D31_60, D61_90, D91_120, D121_150, D151_180, D181_360, D361_MAS, PROCEDENCIA, IDPLAN, NORADICADA ,PARTICULAR,
							RAD) 
		SELECT @ANO, @MES, IDTERCERO,CNSFCXP,LEFT(NOREFERENCIA,16),ROW_NUMBER() OVER(ORDER  BY CNSFCXP  ASC) ITEM,NOREFERENCIA,ESTADO,SALDO,F_FACTURAREF,F_VENCE,FECHA,VLR_NETO,
				0,DIASVENCE,PORVENCER, DM361_MAS, DM181_360, DM151_180, DM121_150, DM91_120, DM61_90, DM31_60, DM0_30,
				D0_30, D31_60, D61_90, D91_120, D121_150, D151_180, D181_360, D361_MAS,@PROCEDENCIA,LEFT(PROCEDENCIA,6),0,0,'SI'
		FROM VWK_CXPDIASVTO
		WHERE FECHA<@FECHACORTE
	END

	IF @@ERROR = 0 
	BEGIN
		IF @PROCEDENCIA='CARTERA'
		BEGIN
			UPDATE PRI SET CERRADO_CARTERA = 1 WHERE ANO = @ANO AND MES = @MES 
		END
		ELSE
		BEGIN
			IF @PROCEDENCIA='FACTURA'
			BEGIN
				UPDATE PRI SET CERRADO_FAC = 1 WHERE ANO = @ANO AND MES = @MES 
			END
			ELSE
			BEGIN
				UPDATE PRI SET CERRADO_CXP = 1 WHERE ANO = @ANO AND MES = @MES 
			END
		END
	END
END
