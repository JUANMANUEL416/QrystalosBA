		WITH( 
			CODIGO			VARCHAR(20)		'$.CODIGO'
			,IDARTICULO		VARCHAR(20)		'$.IDARTICULO'
			)
		
		IF EXISTS (SELECT 1 FROM IEXI 
				INNER JOIN IART ON IART.IDARTICULO=IEXI.IDARTICULO
				WHERE  @CODIGO IN (NROUNIDAD,SELLOCALIDAD))
		BEGIN
			SELECT 'OK' OK
			IF COALESCE(@IDARTICULO,'')=''
			BEGIN
				SELECT DESCRIPCION, NROUNIDAD, SELLOCALIDAD,IEXI.GRUPOABO, IEXI.GRUPORH, IEXI.IDARTICULO, IEXI.FECHAVENCE
				FROM IEXI 
				INNER JOIN IART ON IART.IDARTICULO=IEXI.IDARTICULO
				WHERE  @CODIGO IN (NROUNIDAD,SELLOCALIDAD)
			END
			ELSE
			BEGIN
				SELECT  @NROUNIDAD = NROUNIDAD, @SELLOCALIDAD = SELLOCALIDAD 
				FROM IEXI INNER JOIN IART ON IART.IDARTICULO=IEXI.IDARTICULO
				WHERE IART.IDARTICULO = @IDARTICULO AND @CODIGO IN (NROUNIDAD,SELLOCALIDAD)
				GROUP BY DESCRIPCION, NROUNIDAD, SELLOCALIDAD,IEXI.GRUPOABO, IEXI.GRUPORH, IEXI.IDARTICULO

				SELECT @TRAZABILIDAD_NUEVA = 0
				SELECT @TRAZABILIDAD_NUEVA = IIF(COUNT(1) > 0,1,0) 
				FROM BSREST 
				WHERE NOLOTE IN (SELECT NOLOTE FROM IEXI WHERE IDARTICULO = @IDARTICULO AND @CODIGO IN (NROUNIDAD,SELLOCALIDAD))

				IF @TRAZABILIDAD_NUEVA=1
				BEGIN
					SELECT FECHA, STRINGGRANDE1 DESCRIPCION, NOLOTE CODIGOINTERNO, CNSRELACIONADO CONSECUTIVO, STRINGGRANDE2 USUARIO, VALOR1 CAPACIDAD FROM
					(
						SELECT FECHA,
						CASE WHEN EVENTO LIKE '%DESTRUCCI_N%' THEN
							CASE WHEN (SELECT TOP 1 OBSERVACION+' ('+DESCCLASE+')' FROM BSDESTR WHERE NOLOTE=BSREST.NOLOTE AND BSDESTR.USUARIO=BSREST.USUARIO AND CONVERT(DATE,BSDESTR.FDESTRUCCION)=CONVERT(DATE,BSREST.FECHA)) IS NULL
							THEN REPLACE(EVENTO,'HEMOCOMPONENTE','BOLSA VACIA') 
							ELSE REPLACE(EVENTO,'HEMOCOMPONENTE',(SELECT TOP 1 OBSERVACION+' ('+DESCCLASE+')' FROM BSDESTR WHERE NOLOTE=BSREST.NOLOTE AND BSDESTR.USUARIO=BSREST.USUARIO AND CONVERT(DATE,BSDESTR.FDESTRUCCION)=CONVERT(DATE,BSREST.FECHA))) END
						ELSE EVENTO END AS STRINGGRANDE1,
						NOLOTE,
						CNSRELACIONADO,
						(SELECT top 1 NOMBRE FROM USUSU WHERE USUARIO = BSREST.USUARIO) AS STRINGGRANDE2,
						CASE WHEN EVENTO LIKE '%DESTRUCCI_N%' THEN 
							CASE WHEN 
								(SELECT TOP 1 UPPER(DESCCLASE) FROM BSDESTR WHERE BSDESTR.NOLOTE=BSREST.NOLOTE AND BSDESTR.USUARIO=BSREST.USUARIO AND CONVERT(DATE,BSDESTR.FDESTRUCCION)=CONVERT(DATE,BSREST.FECHA)) LIKE '%VENCID%' 
								OR (SELECT TOP 1 UPPER(DESCCLASE) FROM BSDESTR WHERE BSDESTR.NOLOTE=BSREST.NOLOTE AND BSDESTR.USUARIO=BSREST.USUARIO AND CONVERT(DATE,BSDESTR.FDESTRUCCION)=CONVERT(DATE,BSREST.FECHA)) LIKE '%ROTO%'
								OR (SELECT TOP 1 UPPER(DESCCLASE) FROM BSDESTR WHERE BSDESTR.NOLOTE=BSREST.NOLOTE AND BSDESTR.USUARIO=BSREST.USUARIO AND CONVERT(DATE,BSDESTR.FDESTRUCCION)=CONVERT(DATE,BSREST.FECHA)) LIKE '%ABIERTO%' 
								OR (SELECT TOP 1 UPPER(DESCCLASE) FROM BSDESTR WHERE BSDESTR.NOLOTE=BSREST.NOLOTE AND BSDESTR.USUARIO=BSREST.USUARIO AND CONVERT(DATE,BSDESTR.FDESTRUCCION)=CONVERT(DATE,BSREST.FECHA)) IS NULL
								THEN (CASE WHEN EVENTO LIKE '%HEMOCOMPONENTE%' THEN 0 ELSE CAPACIDAD END)
							ELSE 0 END
						ELSE 
							CASE WHEN ISNULL(CAPACIDAD,-1)>=0 THEN 
								CAPACIDAD
							ELSE
								CASE WHEN 
									(SELECT TOP 1 CAPACIDAD FROM IMOVH WHERE NOLOTE=BSREST.NOLOTE AND CNSMOV=BSREST.CNSRELACIONADO) IS NOT NULL
								THEN
									(SELECT TOP 1 CAPACIDAD FROM IMOVH WHERE NOLOTE=BSREST.NOLOTE AND CNSMOV=BSREST.CNSRELACIONADO)
								ELSE 
									(SELECT TOP 1 CAPACIDAD FROM IEXI WHERE NOLOTE = BSREST.NOLOTE) 
								END
							END
						END AS VALOR1
						FROM BSREST 
						WHERE NOLOTE IN (SELECT NOLOTE FROM IEXI WHERE @NROUNIDAD = NROUNIDAD AND @SELLOCALIDAD = SELLOCALIDAD AND (@IDARTICULO IS NULL OR IEXI.IDARTICULO = @IDARTICULO))
					)X ORDER BY FECHA
				END
				ELSE
				BEGIN
					SELECT FECHA, DESCRIPCION, CODIGOINTERNO, CONSECUTIVO, USUARIO, CAPACIDAD
					FROM (
						-- MOVIMIENTOS
						SELECT IMOV.FECHACONF FECHA,CASE WHEN ITMO.TIPO='CREDITO' THEN 'INGRESO A LA UNIDAD TRANSFUSIONAL' ELSE 'ENTREGA A '+DBO.FNK_NOMBRE_AFI(HADM.IDAFILIADO) END DESCRIPCION,IMOVH.NOLOTE AS CODIGOINTERNO,IMOV.CNSMOV AS CONSECUTIVO
						,USUSU.NOMBRE USUARIO, ISNULL(IMOVH.CAPACIDAD,IEXI.CAPACIDAD) CAPACIDAD--CASE WHEN IEXI.CAPACIDAD<=0 THEN (SELECT SUM(CAPACIDAD) FROM IEXI WHERE NOLOTE LIKE IMOVH.NOLOTE+'%') ELSE IEXI.CAPACIDAD END CAPACIDAD
						FROM IMOVH INNER JOIN IMOV ON IMOV.CNSMOV=IMOVH.CNSMOV
						INNER JOIN ITMO ON IMOV.IDTIPOMOV=ITMO.IDTIPOMOV
						INNER JOIN IART ON IART.IDARTICULO=IMOVH.IDARTICULO
						INNER JOIN USUSU ON USUSU.USUARIO=IMOV.USUARIOCONF
						LEFT JOIN IEXI ON IEXI.NOLOTE=IMOVH.NOLOTE
						LEFT JOIN IZSOL ON IMOV.NODOCUMENTO=IZSOL.CNSIZSOL
						LEFT JOIN HADM ON HADM.NOADMISION=IZSOL.NOADMISION
						WHERE IMOVH.NOLOTE IN (SELECT NOLOTE FROM IEXI WHERE @CODIGO=NROUNIDAD AND @SELLOCALIDAD=SELLOCALIDAD AND (@IDARTICULO IS NULL OR IEXI.IDARTICULO = @IDARTICULO))
						AND IMOV.ESTADO=1
	
						-- SOLICITUDES
						UNION ALL
						SELECT IZSOL.FECHASOL,'SOLICITUD DE RESERVA DE '+IART.DESCRIPCION DESCRIPCION,IART.IDARTICULO CODIGOINTERNO, IZSOL.CNSIZSOL CONSECUTIVO, USUSU.NOMBRE
						,BSRES.BSCAPACIDAD
						FROM IZSOLD INNER JOIN IZSOL ON IZSOL.CNSIZSOL=IZSOLD.CNSIZSOL 
						INNER JOIN IART ON IART.IDARTICULO=IZSOLD.IDARTICULO
						LEFT JOIN BSRES ON IZSOLD.CNSIZSOLD = BSRES.CNSIZSOLD
						LEFT JOIN USUSU ON USUSU.USUARIO=IZSOL.USUARIOSOL
						WHERE @CODIGO IN (CNSRES,NUMUNIDAD) AND @SELLOCALIDAD=SELLOCALIDAD 
						AND (@IDARTICULO IS NULL OR IART.IDARTICULO = @IDARTICULO)
	
						-- RESERVAS
						UNION ALL

						SELECT ISNULL(F_RECIBE,FECHARESERVA) AS FECHA,
							CASE WHEN BSRES.ESTADO = 'Reservada' THEN
							'RESERVADA A '
							ELSE
							'RECIBIDO PARA '
							END
         
							+DBO.FNK_NOMBRE_AFI(BSRES.IDAFILIADO) DESCRIPCION
						,LOTE CODIGOINTERNO, CNSRES CONSECUTIVO
						,USUSU.NOMBRE 
						,BSRES.BSCAPACIDAD
						FROM BSRES 
						INNER JOIN USUSU ON BSRES.IDRECIBE=USUSU.USUARIO
						WHERE @CODIGO IN (CNSRES,NUMUNIDAD) AND @SELLOCALIDAD=SELLOCALIDAD 
						AND (@IDARTICULO IS NULL OR BSRES.IDARTICULO = @IDARTICULO)

						-- DESTRUCCI�N DE BOLSAS
						UNION ALL
						SELECT FDESTRUCCION,
      
							CASE WHEN EXISTS (SELECT BSRES.IDDESECHO FROM BSRES WHERE IDDESECHO=BSDESTR.CNSBSDESTR) THEN
							'DESTRUCCI�N DE BOLSA ('+OBSERVACION+')'
							ELSE 
							'DESTRUCCI�N DE HEMODERIVADO ('+OBSERVACION+')'
							END
         
							,BSDESTR.NOLOTE,CNSBSDESTR,USUSU.NOMBRE,
							CAPACIDAD=(CASE COALESCE(BSDESTR.DESCCLASE,'') WHEN 'Vencida' THEN IEXI.CAPACIDAD ELSE 0 END)
						FROM BSDESTR 
						LEFT JOIN USUSU ON USUSU.USUARIO=ISNULL(BSDESTR.USUARIOCONF, BSDESTR.USUARIO)
						LEFT JOIN IEXI ON IEXI.NOLOTE=BSDESTR.NOLOTE
						WHERE @CODIGO=BSDESTR.NROUNIDAD AND @SELLOCALIDAD=BSDESTR.SELLOCALIDAD
						AND (@IDARTICULO IS NULL OR IEXI.IDARTICULO = @IDARTICULO)
						)X ORDER BY FECHA
				END
			END
		END
		ELSE
		SELECT 'KO' OK
	END	
