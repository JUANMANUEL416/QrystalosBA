				SELECT IDBODEGA, @Result ,IDARTICULO, 1,1, DBO.FNK_GETDATE(),FECHAVENCE,  NOLOTEPEDIDO,SELLOCALIDAD , @CANTIDAD , PCOSTO , IDDONANTE, NROUNIDAD , PROCEDENCIA , CODBANSAN, GRUPOABO, GRUPORH, FRECOLECCION,PRESENCIA  
