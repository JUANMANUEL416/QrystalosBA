CREATE OR ALTER PROCEDURE DBO.SPQ_TRANSFUSIONAL
@JSON  NVARCHAR(MAX) 
WITH
ENCRYPTION
AS
DECLARE  @PARAMETROS	NVARCHAR(MAX)	,@MODELO			VARCHAR(100)	
		,@METODO		VARCHAR(100)	,@USUARIO			VARCHAR(12)
		,@GRUPO			VARCHAR(8)		,@SYS_COMPUTERNAME	VARCHAR(254)	
		,@IDSEDE		VARCHAR(5)		,@USUNOMBRE			VARCHAR(100)
		,@SEDE			VARCHAR(5)		,@FECHA				VARCHAR(10)
		,@IDEMEDICA     VARCHAR(4)		,@FECHA1			DATETIME		
		,@SQL           VARCHAR(MAX)	,@CODCAJERO			VARCHAR(20)
		,@COMPANIA		VARCHAR(10)		,@IDAFILIADO		VARCHAR(20)	
		,@IDMEDICO		VARCHAR(20)		,@FECHAINI			DATE
		,@FECHAFIN		DATE			,@CONSECUTIVOS		NVARCHAR(MAX)
		,@MARCAR		BIT				,@NOAUTORIZACION	VARCHAR(50)	
		,@CONSECUTIVO	VARCHAR(20)		,@OBSERVACION		VARCHAR (200)
		,@IDCAUSAL		VARCHAR(20)		,@IDSERVICIO		VARCHAR(20)	
		,@CONT			INT				,@CNSIZSOL			VARCHAR(20)
		,@CONSECUTIVOCAN VARCHAR(20)	,@GRUPAL			BIT			
		,@IDAUT			VARCHAR(20)		,@VR_TOTAL			DECIMAL(14,2)   
		,@VLRDEPOSITOS	DECIMAL(14,2)	,@MENSAJE			VARCHAR(500)
		,@PROCESO		VARCHAR(50)		,@PROCEDENCIA		VARCHAR(20)
		,@ITEM			INT				,@TIPOFAC			VARCHAR(20)
		,@CNSFCOM		VARCHAR(20)		,@IDARTICULO		VARCHAR(20)
		,@IDTERCERO		VARCHAR(500)	,@IDBODEGA			VARCHAR(20)
		,@CCOSTO		VARCHAR(20)		,@IDAREA			VARCHAR(20)
		,@TIENE			VARCHAR(20)		,@CANTIDAD			INT
		,@DETALLE		VARCHAR (500)	,@CNSITRA			VARCHAR(20)
		,@CNSRPDX		VARCHAR(20)		,@CNSRPDX_2			VARCHAR(20)
		,@PCOSTO		VARCHAR(20)		,@PRESENCIA			VARCHAR(20)
		,@DESCRIPCION	VARCHAR(20)		,@NROUNIDAD			VARCHAR(20)
		,@SELLO			VARCHAR(20)		,@CAPACIDAD			DECIMAL(14,2)
		,@GRUPOABO		VARCHAR(20)		,@GRUPORH			VARCHAR(20)				
		,@FRECOLECCION	DATE			,@FECHAVENCE		DATE
		,@IDDONANTE		VARCHAR(50)		,@TEMPERATURA		DECIMAL(14,2)	
		,@CODIGOBARRA	VARCHAR(20)		,@CANTIDAD_TOTAL	DECIMAL(14,2) 	
		,@CNSIZSOLD		VARCHAR(20)		,@PRUEBA			BIT	
		,@EME			BIT				,@NOLOTE			VARCHAR(20)				
		,@NOLOTEPEDIDO	VARCHAR(20)		,@NOADMISION		VARCHAR(20)
		,@CNSRES		VARCHAR(20)		,@TOTAL				INT
		,@RESPUESTA		VARCHAR(20)		,@CNSIZSOLDT		VARCHAR(20)
		,@NOITEM		INT				,@NORDEN			VARCHAR(20)	
		,@SUBGRUPO		VARCHAR(20)		,@datoIEXI			NVARCHAR(MAX)			
		,@datoBSRES		NVARCHAR(MAX)	,@CNSINCIN			VARCHAR(20)
		,@CNSBSDESTR	VARCHAR(20)		,@datoBSDESTR		NVARCHAR(MAX)
		,@CODIGO		VARCHAR(20)		,@SELLOCALIDAD		VARCHAR(20)		,@LOTE VARCHAR(20)
		,@TRAZABILIDAD_NUEVA BIT		,@CNSMOV			VARCHAR(20)		,@Result VARCHAR(50)
		,@NOLOTE_NUEVO	VARCHAR(20)		,@sqlCommand		NVARCHAR(max), @CAPACIDADMIN_HEMODE INT
		,@CUMPLE		BIT				,@APROBADO BIT
DECLARE @TABLERRR		TABLE (ERROR VARCHAR(200))

BEGIN 
	SET LANGUAGE Spanish;  
	SET DATEFORMAT dmy
	SELECT *
	INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)  AS JSON
	)

	SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON
	--DEFINICION DE TABLA DE ERRORES
	DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200));
	-- TOMA DEL GRUPO, SYS_COMPUTERNAME, SEDE   DE ACUERDO AL USUARIOpl,   --PRINT 'USUARIO:'+@USUARIO
	SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO), @USUNOMBRE = NOMBRE FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME, @COMPANIA = COMPANIA, @CODCAJERO= CODCAJERO FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @IDSEDE = IDSEDE, @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
	PRINT '@USUARIO='+@USUARIO

	IF @METODO = 'AGREGA_FCOM'
	BEGIN
		SELECT @IDTERCERO=IDTERCERO , @OBSERVACION = OBSERVACION ,@IDBODEGA = IDBODEGA, @TIENE = TIENE, @CNSFCOM = CNSFCOM
		FROM OPENJSON(@PARAMETROS)
		WITH( IDTERCERO			VARCHAR(20)		'$.IDTERCERO'
			,OBSERVACION		VARCHAR(20)		'$.OBSERVACION'
			,IDBODEGA			VARCHAR(20)		'$.IDBODEGA'
			,TIENE				VARCHAR(20)		'$.TIENE'
			,CNSFCOM			VARCHAR(20)		'$.CNSFCOM'
		)
		
		IF COALESCE(@IDTERCERO,'') = ''
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'Seleccione un Tercero'
		END
	
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
			IF @TIENE = 'NO'
				BEGIN
					EXEC SPK_GENCONSECUTIVO @COMPANIA,@IDSEDE,'@FCOM', @CNSFCOM OUTPUT 
					SELECT @CNSFCOM = @IDSEDE + RIGHT('00000000' + CONVERT(VARCHAR(8), @CNSFCOM), 8)
					SELECT @CCOSTO = CCOSTO, @IDAREA = IDAREA FROM IBOD WHERE IDBODEGA = @IDBODEGA

					INSERT INTO FCOM (CNSFCOM, COMPANIA, IDTERCERO, ESTADO, OBSERVACION, USUARIO, FECHA, IDBODEGA, CCOSTO, IDAREA, IDTIPOSER, DECONSUMO, APROVAL, ORDENCOMPRA)
					SELECT @CNSFCOM, '01', @IDTERCERO, 'C', @OBSERVACION, @USUARIO, DBO.FNK_GETDATE(), @IDBODEGA, @CCOSTO, @IDAREA,  'Presta', 1, 2, 0
				END
			END TRY  
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK, @CNSFCOM CNSFCOM, CASE COALESCE(@CNSFCOM,'') WHEN @CNSFCOM THEN 'SI' ELSE 'NO' END TIENE
		END 
	END
	IF @METODO = 'AGREGA_FCOMD'
	BEGIN
		SELECT @CNSFCOM = CNSFCOM, @IDARTICULO = IDARTICULO, @CANTIDAD = CANTIDAD, @DETALLE = DETALLE
		FROM OPENJSON(@PARAMETROS)
		WITH( CNSFCOM			VARCHAR(20)		'$.CNSFCOM'
			,IDARTICULO			VARCHAR(20)		'$.IDARTICULO'
			,CANTIDAD			VARCHAR(20)		'$.CANTIDAD'
			,DETALLE			VARCHAR(20)		'$.DETALLE'
		)
		
		--IF COALESCE(@IDTERCERO,'') = ''
		--BEGIN
		--	INSERT INTO @TBLERRORES(ERROR) SELECT 'Seleccione un Tercero'
		--END
	
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
					INSERT INTO FCOMD (CNSFCOM, IDARTICULO, ESTADO, CANTIDAD, DETALLE, TIPO, TIPODTO, CANTISOL, NOLOTE)
					SELECT @CNSFCOM, @IDARTICULO, 'P', @CANTIDAD, @DETALLE, 'Articulos', 'V', @CANTIDAD, ''
			END TRY  
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK, @CNSFCOM CNSFCOM, CASE COALESCE(@CNSFCOM,'') WHEN @CNSFCOM THEN 'SI' ELSE 'NO' END TIENE
		END 
	END
	IF @METODO = 'CERRAR_FCOM'
	BEGIN
		SELECT @CNSFCOM = CNSFCOM
		FROM OPENJSON(@PARAMETROS)
		WITH( CNSFCOM			VARCHAR(20)		'$.CNSFCOM'
		)

		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				DELETE FROM FCOMD WHERE CNSFCOM = @CNSFCOM
				DELETE FROM FCOM WHERE CNSFCOM = @CNSFCOM
			END TRY  
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK, @CNSFCOM CNSFCOM, CASE COALESCE(@CNSFCOM,'') WHEN @CNSFCOM THEN 'SI' ELSE 'NO' END TIENE
		END 
	END
	IF @METODO = 'GUARDA_FCOM'
	BEGIN
		SELECT @CNSFCOM = CNSFCOM
		FROM OPENJSON(@PARAMETROS)
		WITH( CNSFCOM			VARCHAR(20)		'$.CNSFCOM'
		)
		IF NOT EXISTS (SELECT * FROM FCOMD WHERE CNSFCOM = @CNSFCOM)
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'No existe Detalles, por favor, ingrese los detalles.'
		END
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				UPDATE FCOM SET ESTADO = 'P'  WHERE CNSFCOM = @CNSFCOM
				EXEC SPK_INSERT_ITRA_REQ @CNSFCOM, @USUARIO, @SYS_COMPUTERNAME, @COMPANIA, @SEDE
			END TRY  
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK, @CNSFCOM CNSFCOM, CASE COALESCE(@CNSFCOM,'') WHEN @CNSFCOM THEN 'SI' ELSE 'NO' END TIENE
		END 
	END
	IF @METODO = 'AGREGAR_IART'
	BEGIN
		SELECT @CNSITRA = CNSITRA,  @IDBODEGA = IDBODEGA, @CNSRPDX = CNSRPDX, @CNSRPDX_2 = CNSRPDX_2, @ITEM = ITEM
			, @IDARTICULO = IDARTICULO, @PCOSTO = PCOSTO, @PRESENCIA = PRESENCIA, @DESCRIPCION = DESCRIPCION, @NROUNIDAD = NROUNIDAD
			, @SELLO = SELLO, @CAPACIDAD = CAPACIDAD, @GRUPOABO = GRUPOABO, @GRUPORH = GRUPORH, @FRECOLECCION = FRECOLECCION
			, @FECHAVENCE = FECHAVENCE, @IDDONANTE = IDDONANTE, @TEMPERATURA = TEMPERATURA, @PROCEDENCIA = PROCEDENCIA, @SUBGRUPO = SUBGRUPO
			,@CUMPLE = CUMPLE , @APROBADO = APROBADO
		FROM OPENJSON(@PARAMETROS)
		WITH( CNSITRA			VARCHAR(20)		'$.CNSITRA'				,IDBODEGA		VARCHAR(20)		'$.IDBODEGA'
			,CNSRPDX			VARCHAR(20)		'$.CNSRPDX'				,CNSRPDX_2		VARCHAR(20)		'$.CNSRPDX_2'
			,ITEM				INT				'$.ITEM'				,IDARTICULO		VARCHAR(20)		'$.IDARTICULO'
			,PCOSTO				DECIMAL(14,2)	'$.PCOSTO'				,PRESENCIA		VARCHAR(20)		'$.PRESENCIA'
			,DESCRIPCION		VARCHAR(20)		'$.DESCRIPCION'			,NROUNIDAD		VARCHAR(20)				'$.NROUNIDAD'
			,SELLO				VARCHAR(20)		'$.SELLO'				,CAPACIDAD		DECIMAL(14,2)	'$.CAPACIDAD'
			,GRUPOABO			VARCHAR(20)		'$.GRUPOABO'			,GRUPORH		VARCHAR(20)		'$.GRUPORH'
			,FRECOLECCION		DATE			'$.FRECOLECCION'		,FECHAVENCE		DATE			'$.FECHAVENCE'
			,IDDONANTE			VARCHAR(20)		'$.IDDONANTE'			,TEMPERATURA	DECIMAL(14,2)	'$.TEMPERATURA'
			,PROCEDENCIA		VARCHAR(20)		'$.PROCEDENCIA'			,SUBGRUPO		VARCHAR(20)		'$.SUBGRUPO'
			,CUMPLE				BIT				'$.CUMPLE'
			,APROBADO			BIT				'$.APROBADO'
		)

		
		IF (SELECT ID2 FROM RPDX WHERE CNS = @CNSRPDX AND ITEM = @ITEM )<>DBO.FNK_VALORVARIABLE('IDITARHEMODERIVADOS')
		BEGIN
			IF (@FECHAVENCE) < CAST(GETDATE()+ COALESCE(DBO.FNK_VALORVARIABLE('IDINVDIASPARAVENCER'),0) AS DATE)
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) SELECT 'La fecha de Vencimiento no puede ser menor a la Fecha Configurada'
			END
			IF (@FECHAVENCE) < CAST(GETDATE()+ COALESCE(DBO.FNK_VALORVARIABLE('NDIASANTESVENCE'),0) AS DATE)
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) SELECT 'El Nro de D�as Faltantes Por Vencer Es Menor Al Configurado:' + DBO.FNK_VALORVARIABLE('NDIASANTESVENCE')
			END
		END
		ELSE
		BEGIN
			IF (@FECHAVENCE) < CAST(GETDATE() AS DATE)
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) SELECT 'El Nro de D�as Faltantes Por Vencer Es Menor Al Configurado:' + DBO.FNK_VALORVARIABLE('NDIASANTESVENCE')
			END
		END
		IF (SELECT COALESCE(CANTIDAD,0) FROM RPDX WHERE  CNS = @CNSRPDX AND ITEM = @ITEM) <= (SELECT COALESCE(CANTIDAD1,0) FROM RPDX WHERE  CNS = @CNSRPDX AND ITEM = @ITEM)
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'No se puede ingresar m�s de lo que est� pedido'
		END
		IF (SELECT ITAR.MFECHAVENCIMIENTO FROM IART INNER JOIN ITAR ON IART.IDITAR = ITAR.IDITAR WHERE IDARTICULO = @IDARTICULO) = 1
		BEGIN
			IF (SELECT COALESCE(IART.REGINVIMA,'') FROM IART WHERE IDARTICULO = @IDARTICULO) = '' OR (SELECT COALESCE(IART.F_VIGENCIAINV,'') FROM IART WHERE IDARTICULO = @IDARTICULO) = '' 
			OR (SELECT LEN(IART.REGINVIMA) FROM IART WHERE IDARTICULO = @IDARTICULO)<8  OR (SELECT CONVERT(DATE,F_VIGENCIAINV) FROM IART WHERE IDARTICULO = @IDARTICULO)< CONVERT(DATE,GETDATE())
			INSERT INTO @TBLERRORES(ERROR) SELECT 'Debe Actualizar el Registro Invima antes de Continuar'
		END
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				SELECT 'OK' AS OK
				
				SELECT @CODIGOBARRA = NULL
				EXEC SPK_GENCONSECUTIVO @COMPANIA,@IDSEDE,'@ICBU',@CODIGOBARRA OUTPUT
				SELECT @CODIGOBARRA = @IDSEDE + 'L' + REPLACE(SPACE(8 - LEN(@CODIGOBARRA))+LTRIM(RTRIM(@CODIGOBARRA)),SPACE(1),0)

				INSERT INTO RPDX  (CNS, ID1, ID2,ID3,ID4, ID5,CANTIDAD,VALOR1, FECHA1, FECHA2,  ID10  , ID11, ID12, ID13, ID14, ID15, ID16, ID17, ID18, VALOR10
				, ID9, VALOR5, VALOR11, VALOR27, CANTIDAD3, CANTIDAD4, CANTIDAD5, CANTIDAD1, CANTIDAD2, STRINGMEDIO1, STRINGGRANDE1 , FECHAREGISTRO, STRINGMEDIO9  )
				SELECT @CNSRPDX_2, R.ID1, @IDARTICULO, @CODIGOBARRA, @NROUNIDAD, @SELLO,1, @PCOSTO, @FECHAVENCE, @FRECOLECCION, R.ID4, R.ID3, @IDDONANTE, @NROUNIDAD,@PROCEDENCIA , @DESCRIPCION, @GRUPOABO,@GRUPORH, @PRESENCIA, NULL
				, '', @CAPACIDAD, R.ITEM,@TEMPERATURA, 0, @CUMPLE,  @APROBADO, 0, 0, '', '', DBO.FNK_GETDATE(), @SUBGRUPO
				FROM RPDX R WHERE R.CNS = @CNSRPDX AND R.ITEM = @ITEM

				SELECT CNS, ITEM, ID1, ID2, ID3, ID4, CANTIDAD, CANTIDAD1, CANTIDAD2, ID5, VALOR5
				, STRINGMEDIO1, STRINGGRANDE1, FECHAREGISTRO,ID9, ID10, ID11, ID15, VALOR1, VALOR11, FECHA1,VALOR27, CANTIDAD3, CANTIDAD4, CANTIDAD5 
				FROM RPDX WHERE RPDX.CNS = @CNSRPDX_2

				UPDATE RPDX SET CANTIDAD1 = COALESCE(CANTIDAD1,0)+1, VALOR10 = 1, CANTIDAD2 =COALESCE(CANTIDAD2,0)-1  WHERE CNS = @CNSRPDX AND ITEM = @ITEM

			END TRY  
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK
		END 
	END
	IF @METODO = 'RESERVAR_TRANS'
	BEGIN
		SELECT @CNSIZSOL = CNSIZSOL, @CNSIZSOLD = CNSIZSOLD, @PRUEBA = PRUEBA, @EME = EME, @NOLOTE = NOLOTE, @NOLOTEPEDIDO = NOLOTEPEDIDO, @IDBODEGA = IDBODEGA
		FROM OPENJSON(@PARAMETROS)
		WITH( CNSIZSOL			VARCHAR(20)		'$.CNSIZSOL'			,CNSIZSOLD			VARCHAR(20)		'$.CNSIZSOLD'
			,PRUEBA				BIT				'$.PRUEBA'				,EME				BIT				'$.EME'
			,NOLOTE				VARCHAR(20)		'$.NOLOTE'				,NOLOTEPEDIDO		VARCHAR(20)		'$.NOLOTEPEDIDO'
			,IDBODEGA			VARCHAR(20)		'$.IDBODEGA'
		)

		IF NOT EXISTS (SELECT * FROM IEXI WHERE NOLOTE = @NOLOTE AND COALESCE(IEXI.EXISLOTE,0)>0 AND IEXI.IDBODEGA = @IDBODEGA)
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El registro no cuenta con existencias actualmente'
		END
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				SELECT @NOADMISION = IZSOL.NOADMISION, @SEDE = IZSOL.IDSEDE, @COMPANIA = '01', @IDAFILIADO = HADM.IDAFILIADO
				FROM IZSOLD 
				INNER JOIN IZSOL ON IZSOL.CNSIZSOL=IZSOLD.CNSIZSOL 
				INNER JOIN HADM ON HADM.NOADMISION=IZSOL.NOADMISION
				WHERE CNSIZSOLD = @CNSIZSOLD

				SELECT @IDMEDICO = IDMEDICO FROM USUSU WHERE USUARIO=@USUARIO

				EXEC SPK_GENCONSECUTIVO @COMPANIA, @SEDE, '@BSRES',  @CNSRES OUTPUT  
				SELECT @CNSRES = @SEDE + REPLACE(SPACE(8 - LEN(@CNSRES))+LTRIM(RTRIM(@CNSRES)),SPACE(1),0)
   
				INSERT INTO BSRES(CNSRES,CNSIZSOLD,NOADMISION,IDAFILIADO,IDARTICULO,LOTE,NUMUNIDAD,SELLOCALIDAD,BSCAPACIDAD,FACTORABO,FACTORRH,ESTADO, F_CREA, IDMEDICO, USUARIO)
				SELECT TOP 1 @CNSRES,@CNSIZSOLD,@NOADMISION,@IDAFILIADO,IDARTICULO,NOLOTE,NROUNIDAD,SELLOCALIDAD,CAPACIDAD,GRUPOABO,GRUPORH,'EnProceso', DBO.FNK_GETDATE()
					,@IDMEDICO ,@USUARIO
				FROM IEXI WHERE NOLOTE = @NOLOTE AND IDBODEGA = @IDBODEGA
				

				SELECT @IDSERVICIO = HCATD.IDSERVICIO 
				FROM  IZSOLD	INNER JOIN IZSOL ON IZSOL.CNSIZSOL=IZSOLD.CNSIZSOL 
								INNER JOIN HCATD ON CONSECUTIVO=CONSECUTIVOHCA AND HCATD.IDSERVICIO=IZSOLD.IDSERVICIO
				WHERE CNSIZSOLD = @CNSIZSOLD
   
				IF (SELECT COUNT(*) FROM SERR WHERE IDSERVICIO=@IDSERVICIO)<1
				BEGIN
					UPDATE BSRES SET ESTADO='Reservada' WHERE CNSRES=@CNSRES
				END
				ELSE
				BEGIN
					IF @PRUEBA=1 
					BEGIN
						EXEC SPK_ENVIA_PRUEBASCRUZADAS @CNSRES,@SEDE,@COMPANIA,@USUARIO
					END
					ELSE 
					BEGIN
						UPDATE BSRES SET ESTADO='Reservada' WHERE CNSRES=@CNSRES
					END
				END
			END TRY  
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK,@CNSRES CNSRES
		END 
	END
	IF @METODO = 'REGRESAR_TRANS'
	BEGIN
		SELECT @CNSIZSOL = CNSIZSOL, @CNSRES = CNSRES,  @IDARTICULO = IDARTICULO, @NOLOTE = NOLOTE, @IDARTICULO = IDARTICULO,  @IDBODEGA = IDBODEGA
		FROM OPENJSON(@PARAMETROS)
		WITH( CNSIZSOL			VARCHAR(20)		'$.CNSIZSOL'			,CNSRES			VARCHAR(20)		'$.CNSRES'
			,IDARTICULO			VARCHAR(20)		'$.IDARTICULO'			,NOLOTE			VARCHAR(20)		'$.NOLOTE'
			,IDBODEGA			VARCHAR(20)		'$.IDBODEGA'
		)
		
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
