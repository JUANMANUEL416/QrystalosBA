IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME= 'SPK_RADICAGLOSAS' AND TYPE='P')
BEGIN
   DROP PROCEDURE SPK_RADICAGLOSAS
END

GO
CREATE PROCEDURE DBO.SPK_RADICAGLOSAS
@CNSGLOI  VARCHAR(20),
@FECHARAD DATETIME, 
@USUARIO  VARCHAR(12)
WITH ENCRYPTION
AS
DECLARE @DV     INT
DECLARE @CNSCXC VARCHAR(20)
DECLARE @N_FACTURA VARCHAR(12)
DECLARE @VALOR     DECIMAL(14,2)
DECLARE @PORPAG    DECIMAL(14,6)
BEGIN
   
  IF @FECHARAD IS NULL OR @FECHARAD = '' 
     RETURN
  IF @USUARIO IS NULL OR @USUARIO = '' 
     RETURN
  
  SELECT @CNSCXC = CNSCXC 
  FROM   FGLO 
  WHERE  FGLO.CNSGLOI = @CNSGLOI
  
  UPDATE FCXCDV SET F_RECIBIDO = @FECHARAD, F_VENCE = @FECHARAD + CASE COALESCE(PPT.DIASVTO,0) WHEN 0 THEN 30 ELSE PPT.DIASVTO END 
  FROM   FCXCDV INNER JOIN FGLO ON FCXCDV.CNSGLO    = FGLO.CNSGLO
                               AND FCXCDV.N_FACTURA = FGLO.N_FACTURA
                INNER JOIN FTR  ON FGLO.N_FACTURA   = FTR.N_FACTURA
                 LEFT JOIN PPT  ON FGLO.IDTERCERO   = PPT.IDTERCERO
                               AND FTR.IDPLAN       = PPT.IDPLAN
  WHERE  FGLO.CNSGLOI     = @CNSGLOI
  AND    (FCXCDV.TIPO      = 'G' OR FCXCDV.TIPO      = 'R')
  
  
  UPDATE FGLOI SET RADICADO = 1, FECHARAD = @FECHARAD, USUARIORAD = @USUARIO,FECHADIG=GETDATE()
  WHERE  CNSGLOI = @CNSGLOI
  
  EXEC SPK_RELIQUIDACXCQX @CNSCXC
  
  --SELECT TOP 10 * FROM FGLO
  DECLARE  RADICARESP CURSOR FOR
  SELECT B.N_FACTURA,SUM(VLRRECUPERAR) VALOR
  FROM FGLO A INNER JOIN FGLOID B ON A.CNSGLO=B.CNSGLO
  WHERE B.CNSGLOI=@CNSGLOI
  GROUP BY B.N_FACTURA
  OPEN  RADICARESP
  FETCH NEXT FROM RADICARESP    
   INTO @N_FACTURA, @VALOR 
   WHILE @@FETCH_STATUS = 0    
   BEGIN   
      SELECT  @PORPAG=((@VALOR*100)/SUM(SALDO)) 
      FROM FTRCXC  INNER JOIN TTEC ON FTRCXC.TIPOTTEC=TTEC.TIPO
      WHERE N_FACTURA=@N_FACTURA AND FTRCXC.CUENTACXC=TTEC.CUENTARAD
      
      
      PRINT 'ESTE ES EL  %   '+STR(@PORPAG)
      PRINT 'LA SUMA DEL PAGO  ' + STR(@VALOR)

      UPDATE FTRCXC SET SALDO= SALDO+(ROUND((SALDO *@PORPAG)/100,2))
      FROM FTRCXC A INNER JOIN TTEC B ON A.TIPOTTEC=B.TIPO
      WHERE N_FACTURA=@N_FACTURA AND A.CUENTACXC=B.CUENTARAD 
       
      UPDATE FTRCXC SET SALDO= SALDO - @VALOR
      FROM FTRCXC A INNER JOIN TTEC B ON A.TIPOTTEC=B.TIPO
      WHERE N_FACTURA=@N_FACTURA AND A.CUENTACXC=B.CTAGLOSADB
        
      FETCH NEXT FROM RADICARESP    
      INTO @N_FACTURA, @VALOR 
            
      EXEC SPK_RELIQUIDA_FTR @CNSCXC, @N_FACTURA

     END    
   CLOSE RADICARESP    
   DEALLOCATE RADICARESP 
   
END
