CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_REPORTES @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @DATOS NVARCHAR(MAX)
DECLARE @USUARIO VARCHAR(20), @PROCESO VARCHAR(20)
DECLARE @CNSPAGO VARCHAR(20), @CODCONCEPTO VARCHAR(20), @CNS VARCHAR(20), @IDSEDE VARCHAR(5), @SYS_COMPUTERNAME VARCHAR(254), @COMPANIA VARCHAR(2)
DECLARE @CODNOMINA VARCHAR(2), @ANO VARCHAR(4), @MES VARCHAR(2), @CODPPAGO VARCHAR(5), @CNSEXCEL VARCHAR(20), @FECHAINI DATETIME, @FECHAFIN DATETIME
DECLARE @CCOSTO VARCHAR(20), @IDAREA VARCHAR(20), @NUMDOC VARCHAR(20), @ESTADO VARCHAR(8), @CAMPO VARCHAR(20), @CODIGO VARCHAR(20), @DESCRIPCION VARCHAR(255)
DECLARE @IDTGEN INT, @TIPO VARCHAR(20), @CARGO VARCHAR(20), @filterg NVARCHAR(MAX), @CODCARGO VARCHAR(20), @NIVEL VARCHAR(20), @GRADO VARCHAR(20), @AFU VARCHAR(20), 
	@SEDE VARCHAR(20)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
	FROM USUSU
	WHERE USUARIO = @USUARIO

	SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
	FROM UBEQ
	WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	IF @METODO = 'TOTAL_X_CONCEPTOS'
	BEGIN
		SELECT @CNSPAGO = CNSPAGO
		FROM OPENJSON(@PARAMETROS) WITH (CNSPAGO VARCHAR(20) '$.CNSPAGO')

		SELECT 'OK' OK

		SELECT NIEPE.NOMBRE_PERIODO, NCON.CODCONCEPTO, NCON.DESCRIPCION, ISNULL(SUM(NIEPED.VALOR), 0) AS VALOR_EMPLEADO, ISNULL(SUM(NIEPED.VALOR_APORTES), 0) AS 
			VALOR_EMPLEADOR, ISNULL(SUM(NIEPED.VALOR), 0) + ISNULL(SUM(NIEPED.VALOR_APORTES), 0) AS VALOR_TOTAL
		FROM [dbo].[NCON]
		LEFT JOIN NIEPED ON NCON.CODCONCEPTO = NIEPED.CODCONCEPTO
		LEFT JOIN NIEPE ON NIEPED.CNSNIEPE = NIEPE.CNSNIEPE AND NIEPED.NUMDOC = NIEPE.NUMDOC
		WHERE NCON.CODCONCEPTO IN (
				SELECT NIEPED.CODCONCEPTO
				FROM NIEPE
				INNER JOIN NIEPED ON NIEPE.CNSNIEPE = NIEPED.CNSNIEPE
				WHERE NIEPE.CNSPAGO = @CNSPAGO
				GROUP BY NIEPED.CODCONCEPTO
				) AND (NIEPE.CNSPAGO = @CNSPAGO OR NIEPE.CNSPAGO IS NULL)
		GROUP BY NCON.CODCONCEPTO, NCON.DESCRIPCION, NIEPE.NOMBRE_PERIODO
		ORDER BY NCON.CODCONCEPTO
	END

	IF @METODO = 'TOTAL_DETALLADO_X_CONCEPTOS'
	BEGIN
		SELECT @CNSPAGO = CNSPAGO
		FROM OPENJSON(@PARAMETROS) WITH (CNSPAGO VARCHAR(20) '$.CNSPAGO')

		SELECT 'OK' OK

		SELECT NCON.CODCONCEPTO, NCON.DESCRIPCION, DETALLE = (
				SELECT NEMP.DOCIDEMPLEADO, NIEPE.NOMBRE_EMPLEADO, NIEPED.CODCONCEPTO, NIEPED.NOMBRE_CONCEPTO, NIEPED.VALOR AS VALOR_EMPLEADO, NIEPED.
					VALOR_APORTES AS VALOR_EMPLEADOR, ISNULL(NIEPED.VALOR, 0) + ISNULL(NIEPED.VALOR_APORTES, 0) AS VALOR_TOTAL
				FROM NIEPE
				INNER JOIN NIEPED ON NIEPED.CNSNIEPE = NIEPE.CNSNIEPE AND NIEPED.NUMDOC = NIEPE.NUMDOC
				INNER JOIN NEMP ON NIEPE.NUMDOC = NEMP.NUMDOC
				WHERE CODCONCEPTO = NCON.CODCONCEPTO AND NIEPE.CNSPAGO = @CNSPAGO
				ORDER BY NIEPE.NOMBRE_EMPLEADO
				FOR JSON PATH
				)
		FROM [dbo].[NCON]
		WHERE CODCONCEPTO IN (
				SELECT NIEPED.CODCONCEPTO
				FROM NIEPE
				INNER JOIN NIEPED ON NIEPE.CNSNIEPE = NIEPED.CNSNIEPE
				WHERE CNSPAGO = @CNSPAGO
				GROUP BY NIEPED.CODCONCEPTO
				)
		ORDER BY CODCONCEPTO

		SELECT TOP 1 NOMBRE_PERIODO
		FROM NIEPE
		WHERE CNSPAGO = @CNSPAGO
	END

	IF @METODO = 'EMPLEADO_DET_X_CONCEPTO'
	BEGIN
		SELECT @CNSPAGO = CNSPAGO, @CODCONCEPTO = CODCONCEPTO
		FROM OPENJSON(@PARAMETROS) WITH (CNSPAGO VARCHAR(20) '$.CNSPAGO', CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO')

		SELECT 'OK' OK

		SELECT NCON.CODCONCEPTO, NCON.DESCRIPCION, DETALLE = (
				SELECT NEMP.DOCIDEMPLEADO, NIEPE.NOMBRE_EMPLEADO, NIEPED.CODCONCEPTO, NIEPED.NOMBRE_CONCEPTO, NIEPED.VALOR AS VALOR_EMPLEADO, NIEPED.
					VALOR_APORTES AS VALOR_EMPLEADOR, ISNULL(NIEPED.VALOR, 0) + ISNULL(NIEPED.VALOR_APORTES, 0) AS VALOR_TOTAL
				FROM NIEPE
				INNER JOIN NIEPED ON NIEPED.CNSNIEPE = NIEPE.CNSNIEPE AND NIEPED.NUMDOC = NIEPE.NUMDOC
				INNER JOIN NEMP ON NIEPE.NUMDOC = NEMP.NUMDOC
				WHERE CODCONCEPTO = NCON.CODCONCEPTO AND NIEPE.CNSPAGO = @CNSPAGO
				ORDER BY NIEPE.NOMBRE_EMPLEADO
				FOR JSON PATH
				)
		FROM [dbo].[NCON]
		WHERE CODCONCEPTO IN (
				SELECT NIEPED.CODCONCEPTO
				FROM NIEPE
				INNER JOIN NIEPED ON NIEPE.CNSNIEPE = NIEPED.CNSNIEPE
				WHERE CNSPAGO = @CNSPAGO AND NIEPED.CODCONCEPTO = @CODCONCEPTO
				GROUP BY NIEPED.CODCONCEPTO
				)
		ORDER BY CODCONCEPTO

		SELECT TOP 1 NOMBRE_PERIODO
		FROM NIEPE
		WHERE CNSPAGO = @CNSPAGO
	END

	IF @METODO = 'TERCEROS_DET_X_CONCEPTO'
	BEGIN
		SELECT @CNSPAGO = CNSPAGO, @CODCONCEPTO = CODCONCEPTO
		FROM OPENJSON(@PARAMETROS) WITH (CNSPAGO VARCHAR(20) '$.CNSPAGO', CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO')

		SELECT 'OK' OK

		SELECT NCON.CODCONCEPTO, NCON.DESCRIPCION, DETALLE = (
				SELECT IDTERCERO_PRF, RAZONSOCIAL_PRF, SUM(VALOR) AS VALOR_EMPLEADO, SUM(NIEPED.VALOR_APORTES) AS VALOR_EMPLEADOR, SUM(VALOR) + SUM(NIEPED.
						VALOR_APORTES) AS VALOR_TOTAL
				FROM NIEPE
				INNER JOIN NIEPED ON NIEPED.CNSNIEPE = NIEPE.CNSNIEPE AND NIEPED.NUMDOC = NIEPE.NUMDOC
				WHERE NIEPE.CNSPAGO = @CNSPAGO AND NIEPED.CODCONCEPTO = @CODCONCEPTO
				GROUP BY RAZONSOCIAL_PRF, IDTERCERO_PRF
				ORDER BY RAZONSOCIAL_PRF
				FOR JSON PATH
				)
		FROM [dbo].[NCON]
		WHERE CODCONCEPTO IN (
				SELECT NIEPED.CODCONCEPTO
				FROM NIEPE
				INNER JOIN NIEPED ON NIEPE.CNSNIEPE = NIEPED.CNSNIEPE
				WHERE CNSPAGO = @CNSPAGO AND NIEPED.CODCONCEPTO = @CODCONCEPTO
				GROUP BY NIEPED.CODCONCEPTO
				)
		ORDER BY CODCONCEPTO

		SELECT TOP 1 NOMBRE_PERIODO
		FROM NIEPE
		WHERE CNSPAGO = @CNSPAGO
	END

	IF @METODO = 'TERCEROS_DET_X_CONCEPTO_X_EMP'
	BEGIN
		SELECT @CNSPAGO = CNSPAGO, @CODCONCEPTO = CODCONCEPTO
		FROM OPENJSON(@PARAMETROS) WITH (CNSPAGO VARCHAR(20) '$.CNSPAGO', CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO')

		SELECT 'OK' OK

		SELECT RAZONSOCIAL_PRF, GNIEPED.IDTERCERO_PRF, CODCONCEPTO, NOMBRE_CONCEPTO AS DESCRIPCION, NIEPE.CNSNIEPE, 'TER_X_CON_X_EMP' AS REP, DETALLE = (
				SELECT NEMP.DOCIDEMPLEADO, NIEPE.NOMBRE_EMPLEADO, NIEPED.VALOR AS VALOR_EMPLEADO, NIEPED.VALOR_APORTES AS VALOR_EMPLEADOR, VALOR + NIEPED.
					VALOR_APORTES AS VALOR_TOTAL
				FROM NIEPED
				INNER JOIN NIEPE ON NIEPED.CNSNIEPE = NIEPE.CNSNIEPE AND NIEPED.NUMDOC = NIEPE.NUMDOC
				INNER JOIN NEMP ON NIEPE.NUMDOC = NEMP.NUMDOC
				WHERE IDTERCERO_PRF = GNIEPED.IDTERCERO_PRF AND CODCONCEPTO = @CODCONCEPTO AND NIEPE.CNSPAGO = @CNSPAGO
				ORDER BY NIEPE.NOMBRE_EMPLEADO
				FOR JSON PATH
				)
		FROM NIEPE
		INNER JOIN NIEPED AS GNIEPED ON GNIEPED.CNSNIEPE = NIEPE.CNSNIEPE AND GNIEPED.NUMDOC = NIEPE.NUMDOC
		WHERE NIEPE.CNSPAGO = @CNSPAGO AND GNIEPED.CODCONCEPTO = @CODCONCEPTO
		GROUP BY RAZONSOCIAL_PRF, IDTERCERO_PRF, CODCONCEPTO, NOMBRE_CONCEPTO, NIEPE.CNSNIEPE

		SELECT TOP 1 NOMBRE_PERIODO
		FROM NIEPE
		WHERE CNSPAGO = @CNSPAGO
	END

	IF @METODO = 'PAGOS_X_TERCEROS'
	BEGIN
		SELECT @CNSPAGO = CNSPAGO
		FROM OPENJSON(@PARAMETROS) WITH (CNSPAGO VARCHAR(20) '$.CNSPAGO')

		SELECT 'OK' OK

		SELECT TERF.NIT, TERF.RAZONSOCIAL, DETALLE = (
				SELECT TER.NIT AS NIT_EMPLEADO, TER.RAZONSOCIAL AS RAZONSOCIAL_EMPLEADO, NCON.CODCONCEPTO, NCON.DESCRIPCION, (NIEPED.VALOR + NIEPED.VALOR_APORTES
						) AS VALOR
				FROM NIEPE
				INNER JOIN NIEPED ON NIEPE.CNSNIEPE = NIEPED.CNSNIEPE AND NIEPE.NUMDOC = NIEPED.NUMDOC
				INNER JOIN NCON ON NIEPED.CODCONCEPTO = NCON.CODCONCEPTO
				INNER JOIN NEMP ON NEMP.NUMDOC = NIEPED.NUMDOC
				INNER JOIN TER ON TER.IDTERCERO = NEMP.TERCEROID
				WHERE NIEPE.CNSPAGO = @CNSPAGO AND NCON.INFO = 'No' AND NCON.TIPO = 'Egreso' AND NCON.CLASE <> 'Provision' AND NIEPED.IDTERCERO_PRF = TERF.IDTERCERO
				-- correlaci�n con la fila externa
				FOR JSON PATH
				)
		FROM TER AS TERF
		WHERE TERF.IDTERCERO IN (
				SELECT DISTINCT NIEPED.IDTERCERO_PRF
				FROM NIEPE
				INNER JOIN NIEPED ON NIEPE.CNSNIEPE = NIEPED.CNSNIEPE AND NIEPE.NUMDOC = NIEPED.NUMDOC
				INNER JOIN NCON ON NIEPED.CODCONCEPTO = NCON.CODCONCEPTO
				INNER JOIN NEMP ON NEMP.NUMDOC = NIEPED.NUMDOC
				INNER JOIN TER ON TER.IDTERCERO = NEMP.TERCEROID
				WHERE NIEPE.CNSPAGO = @CNSPAGO AND NCON.INFO = 'No' AND NCON.TIPO = 'Egreso' AND NCON.CLASE <> 'Provision'
				)
		ORDER BY TERF.NIT, TERF.RAZONSOCIAL;

		SELECT TOP 1 NOMBRE_PERIODO
		FROM NIEPE
		WHERE CNSPAGO = @CNSPAGO
	END

	IF @METODO = 'ACUMULADO_X_EMPLEADOS'
	BEGIN
		SELECT @FECHAINI = FECHAINI, @FECHAFIN = FECHAFIN, @CCOSTO = CCOSTO, @IDAREA = IDAREA, @NUMDOC = NUMDOC, @CODCONCEPTO = CODCONCEPTO
		FROM OPENJSON(@PARAMETROS) WITH (
				FECHAINI DATETIME '$.FECHAINI', FECHAFIN DATETIME '$.FECHAFIN', CCOSTO VARCHAR(20) '$.CCOSTO', IDAREA VARCHAR(20) '$.IDAREA', NUMDOC VARCHAR(20) 
				'$.NUMDOC', CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO'
				);

		SELECT 'OK' OK;

		SELECT P1.NUMDOC, P1.NIT, P1.RAZONSOCIAL, P1.CNSPAGO, INGRESOS = (
				SELECT P2.CODCONCEPTO, P2.NOMCONCEPTO, P2.TIPO, P2.VLR_EMPLEADO, P2.VLR_CONTRATANTE, P2.VLR_TOTAL
				FROM VWK_NOM_ACUMULADOS AS P2
				WHERE P1.NUMDOC = P2.NUMDOC AND P2.TIPO = 'Ingreso' AND P1.CNSPAGO = P2.CNSPAGO AND (@CODCONCEPTO IS NULL OR P2.CODCONCEPTO = @CODCONCEPTO
						)
				FOR JSON AUTO
				), EGRESOS = (
				SELECT P2.CODCONCEPTO, P2.NOMCONCEPTO, P2.TIPO, P2.VLR_EMPLEADO, P2.VLR_CONTRATANTE, P2.VLR_TOTAL
				FROM VWK_NOM_ACUMULADOS AS P2
				WHERE P1.NUMDOC = P2.NUMDOC AND P2.TIPO = 'Egreso' AND P1.CNSPAGO = P2.CNSPAGO AND (@CODCONCEPTO IS NULL OR P2.CODCONCEPTO = @CODCONCEPTO
						)
				FOR JSON AUTO
				)
		FROM VWK_NOM_ACUMULADOS AS P1
		WHERE TRY_CONVERT(DATE, P1.FECHA) >= @FECHAINI AND TRY_CONVERT(DATE, P1.FECHA) <= @FECHAFIN AND (@CCOSTO IS NULL OR P1.CCOSTO = @CCOSTO) AND (@IDAREA IS NULL OR P1.IDAREA = @IDAREA
				) AND (@NUMDOC IS NULL OR P1.NUMDOC = @NUMDOC)
		GROUP BY P1.NUMDOC, P1.NIT, P1.RAZONSOCIAL, P1.CNSPAGO
		ORDER BY P1.NUMDOC ASC;
	END

	IF @METODO = 'ACUMULADO_X_DETALLE'
	BEGIN
		SELECT @FECHAINI = FECHAINI, @FECHAFIN = FECHAFIN, @CCOSTO = CCOSTO, @IDAREA = IDAREA, @NUMDOC = NUMDOC, @CODCONCEPTO = CODCONCEPTO
		FROM OPENJSON(@PARAMETROS) WITH (
				FECHAINI DATETIME '$.FECHAINI', FECHAFIN DATETIME '$.FECHAFIN', CCOSTO VARCHAR(20) '$.CCOSTO', IDAREA VARCHAR(20) '$.IDAREA', NUMDOC VARCHAR(20) 
				'$.NUMDOC', CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO'
				);

		SELECT 'OK' OK;

		SELECT P1.NUMDOC, P1.NIT, P1.RAZONSOCIAL, P1.CNSPAGO, DETALLE = (
				SELECT P2.CODCONCEPTO, P2.NOMCONCEPTO, P2.TIPO, P2.VLR_EMPLEADO, P2.VLR_CONTRATANTE, P2.VLR_TOTAL
				FROM VWK_NOM_ACUMULADOS AS P2
				WHERE P1.NUMDOC = P2.NUMDOC AND P1.CNSPAGO = P2.CNSPAGO AND (@CODCONCEPTO IS NULL OR P2.CODCONCEPTO = @CODCONCEPTO)
				FOR JSON AUTO
				), INGRESOS = (
				SELECT P2.VLR_CONTRATANTE, P2.VLR_TOTAL
				FROM VWK_NOM_ACUMULADOS AS P2
				WHERE P1.NUMDOC = P2.NUMDOC AND P2.TIPO = 'Ingreso' AND P1.CNSPAGO = P2.CNSPAGO AND (@CODCONCEPTO IS NULL OR P2.CODCONCEPTO = @CODCONCEPTO
						)
				FOR JSON AUTO
				), EGRESOS = (
				SELECT P2.VLR_EMPLEADO, P2.VLR_CONTRATANTE, P2.VLR_TOTAL
				FROM VWK_NOM_ACUMULADOS AS P2
				WHERE P1.NUMDOC = P2.NUMDOC AND P2.TIPO = 'Egreso' AND P1.CNSPAGO = P2.CNSPAGO AND (@CODCONCEPTO IS NULL OR P2.CODCONCEPTO = @CODCONCEPTO
						)
				FOR JSON AUTO
				)
		FROM VWK_NOM_ACUMULADOS AS P1
		WHERE TRY_CONVERT(DATE, P1.FECHA) >= @FECHAINI AND TRY_CONVERT(DATE, P1.FECHA) <= @FECHAFIN AND (@CCOSTO IS NULL OR P1.CCOSTO = @CCOSTO) AND (@IDAREA IS NULL OR P1.IDAREA = @IDAREA
				) AND (@NUMDOC IS NULL OR P1.NUMDOC = @NUMDOC)
		GROUP BY P1.NUMDOC, P1.NIT, P1.RAZONSOCIAL, P1.CNSPAGO
		ORDER BY P1.NUMDOC ASC;
	END

	IF @METODO = 'EXPORTAR_ACUMULADOS'
	BEGIN
		SELECT @FECHAINI = FECHAINI, @FECHAFIN = FECHAFIN, @CCOSTO = CCOSTO, @IDAREA = IDAREA, @NUMDOC = NUMDOC, @CODCONCEPTO = CODCONCEPTO
		FROM OPENJSON(@PARAMETROS) WITH (
				FECHAINI DATETIME '$.FECHAINI', FECHAFIN DATETIME '$.FECHAFIN', CCOSTO VARCHAR(20) '$.CCOSTO', IDAREA VARCHAR(20) '$.IDAREA', NUMDOC VARCHAR(20) 
				'$.NUMDOC', CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO'
				);

		IF @CNSEXCEL IS NULL
		BEGIN
			EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@EXCEL', @LONGITUD = 8, @NVOCONSEC = @CNSEXCEL OUTPUT
		END

		DECLARE @SQL VARCHAR(MAX);

		SET @SQL = 
			'
    SELECT NIT AS DOCUMENTO, RAZONSOCIAL AS EMPLEADO, CODCONCEPTO AS ID_CONCEPTO, NOMCONCEPTO AS CONCEPTO, TIPO,
           VLR_EMPLEADO, VLR_CONTRATANTE, VLR_TOTAL, CCOSTO AS ID_CCOSTO, NOMCCOSTO AS CCOSTO,
            IDAREA AS ID_AREA, NOMIDAREA AS AREA, CERRADO
    FROM VWK_NOM_ACUMULADOS
    WHERE TRY_CONVERT(DATE, FECHA) >= ''' 
			+ CONVERT(VARCHAR(10), @FECHAINI, 120) + '''
      AND TRY_CONVERT(DATE, FECHA) <= ''' + CONVERT(VARCHAR(10), @FECHAFIN, 120) + '''';

		IF @CCOSTO IS NOT NULL AND @CCOSTO <> ''
			SET @SQL = @SQL + ' AND CCOSTO = ''' + @CCOSTO + '''';

		IF @IDAREA IS NOT NULL AND @IDAREA <> ''
			SET @SQL = @SQL + ' AND IDAREA = ''' + @IDAREA + '''';

		IF @NUMDOC IS NOT NULL AND @NUMDOC <> ''
			SET @SQL = @SQL + ' AND NUMDOC = ''' + @NUMDOC + '''';

		IF @CODCONCEPTO IS NOT NULL AND @CODCONCEPTO <> ''
			SET @SQL = @SQL + ' AND CODCONCEPTO = ''' + @CODCONCEPTO + '''';
		SET @SQL = @SQL + ' ORDER BY NUMDOC ASC';

		BEGIN TRY
			INSERT INTO KEXCEL_FILL (CNSEXCEL, NOMBRE, BORRAR, CONSULTA)
			SELECT @CNSEXCEL, 'ACUMULADO' + '.xlsx', 1, @SQL;
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();
		END CATCH;

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK, @CNSEXCEL CNSEXCEL;

			SELECT ERROR
			FROM @TBLERRORES;

			RETURN;
		END

		SELECT 'OK' OK, @CNSEXCEL CNSEXCEL;
	END

	IF @METODO = 'GUARDAR_CONF_REP'
	BEGIN
		BEGIN TRY
			SELECT @CAMPO = CAMPO, @CODIGO = CODIGO, @DESCRIPCION = DESCRIPCION, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (CAMPO VARCHAR(20) '$.CAMPO', CODIGO VARCHAR(20) '$.CODIGO', DESCRIPCION VARCHAR(255) '$.DESCRIPCION', PROCESO VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('EL CODIGO ', @CODIGO, ' YA SE ENCUENTRAN REGISTRADO PARA EL REPORTE DE ', @CAMPO)
					WHERE EXISTS (
							SELECT 1
							FROM TGEN
							WHERE TABLA = 'REPNOMPRESO' AND CAMPO = @CAMPO AND CODIGO = @CODIGO
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO TGEN (TABLA, CAMPO, CODIGO, DESCRIPCION)
						SELECT 'REPNOMPRESO', @CAMPO, @CODIGO, @DESCRIPCION
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @IDTGEN = IDTGEN
					FROM OPENJSON(@PARAMETROS) WITH (IDTGEN INT '$.IDTGEN')

					BEGIN
						UPDATE TGEN
						SET CAMPO = @CAMPO, CODIGO = @CODIGO, DESCRIPCION = @DESCRIPCION
						WHERE IDTGEN = @IDTGEN
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR_CONF_REP'
	BEGIN
		SELECT @IDTGEN = IDTGEN
		FROM OPENJSON(@PARAMETROS) WITH (IDTGEN INT '$.IDTGEN')

		BEGIN TRY
			DELETE
			FROM TGEN
			WHERE IDTGEN = @IDTGEN
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'REPORTE_PRESOCIAL'
	BEGIN
		SELECT @ANO = ANO, @MES = MES, @ESTADO = ESTADO, @TIPO = TIPO
		FROM OPENJSON(@PARAMETROS) WITH (ANO VARCHAR(4) '$.ANO', MES VARCHAR(2) '$.MES', ESTADO VARCHAR(8) '$.ESTADO', TIPO VARCHAR(20) '$.TIPO')

		SELECT 'OK' OK

		DECLARE @CodNominaEspecial VARCHAR(20);
		DECLARE @CnsPagoEspecial VARCHAR(20);

		SELECT @CodNominaEspecial = CODIGO
		FROM TGEN
		WHERE TABLA = 'CODNESPECIAL' AND CAMPO = @TIPO;

		IF @TIPO <> 'Vacaciones'
		BEGIN
			SELECT @CnsPagoEspecial = CNSPAGO
			FROM NPER
			WHERE ANO = @ANO AND MES = @MES AND CODNOMINA = @CodNominaEspecial;
		END

		SELECT NPER.ANO, NPER.MES, NIEPE.CNSPAGO, NEMP.DOCIDEMPLEADO, LTRIM(RTRIM(REPLACE(ISNULL(TER.PAPELLIDO, '') + ' ' + ISNULL(TER.SAPELLIDO, '') + ' ' + ISNULL(
							TER.PNOMBRE, '') + ' ' + ISNULL(TER.SNOMBRE, ''), '  ', ' '))) AS NOMBRE_COMPLETO, DBO.FNK_LIMPIATEXTO(NCARNG.DESCRIPCION, 'A-Z ') AS 
			CARGO, NEMP.BASICO, NEMP.CCOSTO, NIEPED.CNSNIEPE, NIEPED.NUMDOC, NIEPED.ITEM, NIEPED.CODCONCEPTO, NIEPED.NOMBRE_CONCEPTO, NIEPED.TIPO, CASE 
				WHEN NIEPED.TIPO = 'INGRESO'
					THEN NIEPED.VALOR
				ELSE 0
				END AS VALOR_INGRESO, CASE 
				WHEN NIEPED.TIPO = 'EGRESO'
					THEN NIEPED.VALOR
				ELSE 0
				END AS VALOR_EGRESO
		FROM NIEPED
		INNER JOIN NIEPE ON NIEPE.CNSNIEPE = NIEPED.CNSNIEPE AND NIEPE.NUMDOC = NIEPED.NUMDOC
		INNER JOIN NPER ON NPER.CNSPAGO = NIEPE.CNSPAGO
		INNER JOIN NEMP ON NIEPE.NUMDOC = NEMP.NUMDOC
		INNER JOIN TER ON TER.IDTERCERO = NEMP.TERCEROID
		INNER JOIN NCARNG ON NCARNG.CODCARGO = NEMP.CODCARGO AND NCARNG.GRADO = NEMP.GRADO AND NCARNG.NIVEL = NEMP.NIVEL
		WHERE EXISTS (
				SELECT 1
				FROM TGEN
				WHERE TABLA = 'REPNOMPRESO' AND CAMPO = @TIPO AND CODIGO = NIEPED.CODCONCEPTO
				) AND NPER.ANO = @ANO AND (@MES = '0' OR NPER.MES = @MES) AND (@ESTADO = '0' OR NEMP.ESTADO = @ESTADO) AND (@TIPO = 'Vacaciones' OR NIEPE.CNSPAGO = @CnsPagoEspecial
				)
		ORDER BY TER.PAPELLIDO, TER.SAPELLIDO, TER.PNOMBRE, TER.SNOMBRE;
	END

	IF @METODO = 'REPORTE_NIEPE'
	BEGIN
		SELECT @CNSPAGO = CNSPAGO, @SEDE = SEDE, @CCOSTO = CCOSTO, @AFU = AFU, @CARGO = CARGO, @filterg = filterg, @CODCARGO = COALESCE(CODCARGO, ''), @NIVEL = COALESCE(NIVEL, 
				''), @GRADO = COALESCE(GRADO, '')
		FROM OPENJSON(@PARAMETROS) WITH (
				CNSPAGO VARCHAR(20) '$.CNSPAGO', SEDE VARCHAR(20) '$.SEDE', CCOSTO VARCHAR(20) '$.CCOSTO', AFU VARCHAR(20) '$.AFU', CARGO VARCHAR(20) '$.CARGO', 
				filterg VARCHAR(20) '$.filter', CODCARGO VARCHAR(20) '$.CODCARGO', NIVEL VARCHAR(20) '$.NIVEL', GRADO VARCHAR(20) '$.GRADO'
				)

		SELECT 'OK' OK

		SELECT NEMP.DOCIDEMPLEADO, LTRIM(RTRIM(REPLACE(ISNULL(TER.PAPELLIDO, '') + ' ' + ISNULL(TER.SAPELLIDO, '') + ' ' + ISNULL(TER.PNOMBRE, '') + ' ' + ISNULL(TER.
							SNOMBRE, ''), '  ', ' '))) AS NOMBRE_COMPLETO, NIEPE.CNSPAGO, NIEPE.CNSNIEPE, TER.NIT, NIEPE.NOMBRE_EMPLEADO, NIEPE.VALOR_NETO, NIEPE
			.VALOR_INGRESOS, NIEPE.VALOR_EGRESOS, NIEPE.VALOR_APORTES, NIEPE.TOTAL_NOMINA, NIEPE.NOMBRE_AREA, NIEPE.CCOSTO, NIEPE.NOMBRE_CCOSTO, DBO.
			FNK_LIMPIATEXTO(NCARNG.DESCRIPCION, 'A-Z ') AS CARGO, NIEPE.GRADO, NIEPE.NIVEL, NIEPE.DETALLE_CARGO, NIEPE.NUMDOC, NIEPE.NOMBRE_PERIODO, NEMP.
			BASICO, @CARGO, (
				SELECT TOP 1 VALOR100P
				FROM NIEPED
				WHERE NIEPED.CNSNIEPE = NIEPE.CNSNIEPE AND NIEPED.NUMDOC = NIEPE.NUMDOC AND NIEPED.SEIMPRIME = 'Si'
				) AS SALARIO, DEVENGADOS = (
				SELECT NOMBRE_CONCEPTO, CANTIDAD, VALOR, RAZONSOCIAL_PRF
				FROM NIEPED
				WHERE NIEPED.CNSNIEPE = NIEPE.CNSNIEPE AND NIEPED.NUMDOC = NIEPE.NUMDOC AND NIEPED.SEIMPRIME = 'Si' AND TIPO = 'Ingreso'
				FOR JSON PATH
				), DEDUCIDOS = (
				SELECT NOMBRE_CONCEPTO, CANTIDAD, VALOR, RAZONSOCIAL_PRF
				FROM NIEPED
				WHERE NIEPED.CNSNIEPE = NIEPE.CNSNIEPE AND NIEPED.NUMDOC = NIEPE.NUMDOC AND NIEPED.SEIMPRIME = 'Si' AND TIPO = 'Egreso'
				FOR JSON PATH
				)
		FROM [dbo].[NIEPE]
		INNER JOIN NEMP ON NEMP.NUMDOC = NIEPE.NUMDOC
		LEFT JOIN TER ON NEMP.TERCEROID = TER.IDTERCERO
		INNER JOIN NCARNG ON NCARNG.CODCARGO = NEMP.CODCARGO AND NCARNG.GRADO = NEMP.GRADO AND NCARNG.NIVEL = NEMP.NIVEL
		WHERE (
				TER.NIT LIKE '%%' + @filterg + '%%' OR NIEPE.NOMBRE_EMPLEADO LIKE '%%' + @filterg + '%%' OR NIEPE.NOMBRE_CCOSTO LIKE '%%' + @filterg + '%%' OR NIEPE.
				NOMBRE_CARGO LIKE '%%' + @filterg + '%%' OR NIEPE.NOMBRE_AREA LIKE '%%' + @filterg + '%%'
				) AND 1 = 1 AND NIEPE.CNSPAGO = @CNSPAGO AND COALESCE(NIEPE.IDAREA, '') LIKE (
				CASE 
					WHEN @AFU = '0'
						THEN '%%%%'
					ELSE '%%' + @AFU + '%%'
					END
				) AND COALESCE(NIEPE.CCOSTO, '') LIKE (
				CASE 
					WHEN @CCOSTO = '0'
						THEN '%%%%'
					ELSE '%%' + @CCOSTO + '%%'
					END
				) AND COALESCE(NIEPE.CODCARGO, '') LIKE (
				CASE 
					WHEN @CARGO = '0'
						THEN '%%%%'
					ELSE '%%' + @CODCARGO + '%%'
					END
				) AND COALESCE(NIEPE.NIVEL, '') LIKE (
				CASE 
					WHEN @CARGO = '0'
						THEN '%%%%'
					ELSE '%%' + @NIVEL + '%%'
					END
				) AND COALESCE(NIEPE.GRADO, '') LIKE (
				CASE 
					WHEN @CARGO = '0'
						THEN '%%%%'
					ELSE '%%' + @GRADO + '%%'
					END
				)
		ORDER BY NIEPE.NUMDOC

		RETURN
	END
