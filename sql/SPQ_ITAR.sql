CREATE OR ALTER PROCEDURE DBO.SPQ_ITAR @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100)
DECLARE @USUARIO VARCHAR(20), @IDITAR VARCHAR(2), @DESCRIPCION VARCHAR(80)
DECLARE @MCLASE BIT, @MPAC BIT, @MFFA BIT
DECLARE @MCCN BIT, @MUNI BIT, @MFECHAVENCIMIENTO BIT
DECLARE @DECONSUMO BIT, @MLOTEO BIT, @CUENTA VARCHAR(16)
DECLARE @PREFIJO VARCHAR(6), @ESACTIVO BIT, @MSTOCK BIT
DECLARE @MPRINCIPAL BIT, @MCNS BIT, @PRECNS VARCHAR(10)
DECLARE @MGRUPO BIT, @MLABILIDAD BIT, @MRIESGO VARCHAR(10)
DECLARE @OPTICA BIT, @MIVA BIT, @CUE_IVA VARCHAR(20), @IDTARIFA VARCHAR(5), @IDSEDE VARCHAR(5), @SYS_COMPUTERNAME VARCHAR(254), @COMPANIA VARCHAR(2)
DECLARE @IDIMPUESTO VARCHAR(10), @IDCLASE VARCHAR(10), @CNSEXCEL VARCHAR(20), @IDSERVICIO VARCHAR(20)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
	FROM USUSU
	WHERE USUARIO = @USUARIO

	SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
	FROM UBEQ
	WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @IDITAR = IDITAR, @DESCRIPCION = DESCRIPCION, @MCLASE = MCLASE, @MPAC = MPAC, @MFFA = MFFA, @MCCN = MCCN, @MUNI = MUNI, @MFECHAVENCIMIENTO = 
				MFECHAVENCIMIENTO, @CUENTA = CUENTA, @DECONSUMO = DECONSUMO, @PREFIJO = PREFIJO, @MLOTEO = MLOTEO, @ESACTIVO = ESACTIVO, @MSTOCK = MSTOCK, @MPRINCIPAL = 
				MPRINCIPAL, @MCNS = MCNS, @PRECNS = PRECNS, @MGRUPO = MGRUPO, @MLABILIDAD = MLABILIDAD, @MRIESGO = MRIESGO, @OPTICA = OPTICA, @MIVA = MIVA, @CUE_IVA = CUE_IVA
				, @IDIMPUESTO = IDIMPUESTO, @IDCLASE = IDCLASE
			FROM OPENJSON(@PARAMETROS) WITH (
					IDITAR VARCHAR(2) '$.IDITAR', DESCRIPCION VARCHAR(80) '$.DESCRIPCION', MCLASE BIT '$.MCLASE', MPAC BIT '$.MPAC', MFFA BIT '$.MFFA', MCCN BIT 
					'$.MCCN', MUNI BIT '$.MUNI', MFECHAVENCIMIENTO BIT '$.MFECHAVENCIMIENTO', CUENTA VARCHAR(16) '$.CUENTA', DECONSUMO BIT '$.DECONSUMO', PREFIJO 
					VARCHAR(6) '$.PREFIJO', MLOTEO BIT '$.MLOTEO', ESACTIVO BIT '$.ESACTIVO', MSTOCK BIT '$.MSTOCK', MPRINCIPAL BIT '$.MPRINCIPAL', MCNS BIT '$.MCNS', 
					PRECNS VARCHAR(10) '$.PRECNS', MGRUPO BIT '$.MGRUPO', MLABILIDAD BIT '$.MLABILIDAD', MRIESGO BIT '$.MRIESGO', OPTICA BIT '$.OPTICA', MIVA BIT 
					'$.MIVA', CUE_IVA VARCHAR(20) '$.CUE_IVA', IDIMPUESTO VARCHAR(10) '$.IDIMPUESTO', IDCLASE VARCHAR(10) '$.IDCLASE'
					)

			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'EL TIPO DE ARTICULO YA EXISTE'
			WHERE EXISTS (
					SELECT *
					FROM ITAR
					WHERE IDITAR = @IDITAR
					)

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				INSERT INTO ITAR (
					IDITAR, DESCRIPCION, MCLASE, MPAC, MFFA, MCCN, MUNI, MFECHAVENCIMIENTO, CUENTA, DECONSUMO, PREFIJO, MLOTEO, ESACTIVO, MSTOCK, MPRINCIPAL, MCNS, 
					PRECNS, MGRUPO, MLABILIDAD, MRIESGO, OPTICA, MIVA, CUE_IVA, IDIMPUESTO, IDCLASE
					)
				SELECT @IDITAR, @DESCRIPCION, @MCLASE, @MPAC, @MFFA, @MCCN, @MUNI, @MFECHAVENCIMIENTO, @CUENTA, @DECONSUMO, @PREFIJO, @MLOTEO, @ESACTIVO, @MSTOCK, 
					@MPRINCIPAL, @MCNS, @PRECNS, @MGRUPO, @MLABILIDAD, @MRIESGO, @OPTICA, @MIVA, @CUE_IVA, @IDIMPUESTO, @IDCLASE
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ACTUALIZAR'
	BEGIN
		BEGIN TRY
			SELECT @IDITAR = IDITAR, @DESCRIPCION = DESCRIPCION, @MCLASE = MCLASE, @MPAC = MPAC, @MFFA = MFFA, @MCCN = MCCN, @MUNI = MUNI, @MFECHAVENCIMIENTO = 
				MFECHAVENCIMIENTO, @CUENTA = CUENTA, @DECONSUMO = DECONSUMO, @PREFIJO = PREFIJO, @MLOTEO = MLOTEO, @ESACTIVO = ESACTIVO, @MSTOCK = MSTOCK, @MPRINCIPAL = 
				MPRINCIPAL, @MCNS = MCNS, @PRECNS = PRECNS, @MGRUPO = MGRUPO, @MLABILIDAD = MLABILIDAD, @MRIESGO = MRIESGO, @OPTICA = OPTICA, @MIVA = MIVA, @CUE_IVA = CUE_IVA
				, @IDIMPUESTO = IDIMPUESTO, @IDCLASE = IDCLASE
			FROM OPENJSON(@PARAMETROS) WITH (
					IDITAR VARCHAR(2) '$.IDITAR', DESCRIPCION VARCHAR(80) '$.DESCRIPCION', MCLASE BIT '$.MCLASE', MPAC BIT '$.MPAC', MFFA BIT '$.MFFA', MCCN BIT 
					'$.MCCN', MUNI BIT '$.MUNI', MFECHAVENCIMIENTO BIT '$.MFECHAVENCIMIENTO', CUENTA VARCHAR(16) '$.CUENTA', DECONSUMO BIT '$.DECONSUMO', PREFIJO 
					VARCHAR(6) '$.PREFIJO', MLOTEO BIT '$.MLOTEO', ESACTIVO BIT '$.ESACTIVO', MSTOCK BIT '$.MSTOCK', MPRINCIPAL BIT '$.MPRINCIPAL', MCNS BIT '$.MCNS', 
					PRECNS VARCHAR(10) '$.PRECNS', MGRUPO BIT '$.MGRUPO', MLABILIDAD BIT '$.MLABILIDAD', MRIESGO BIT '$.MRIESGO', OPTICA BIT '$.OPTICA', MIVA BIT 
					'$.MIVA', CUE_IVA VARCHAR(20) '$.CUE_IVA', IDIMPUESTO VARCHAR(10) '$.IDIMPUESTO', IDCLASE VARCHAR(10) '$.IDCLASE'
					)

			UPDATE ITAR
			SET DESCRIPCION = @DESCRIPCION, MCLASE = @MCLASE, MPAC = @MPAC, MFFA = @MFFA, MCCN = @MCCN, MUNI = @MUNI, MFECHAVENCIMIENTO = @MFECHAVENCIMIENTO, CUENTA = @CUENTA
				, DECONSUMO = @DECONSUMO, PREFIJO = @PREFIJO, MLOTEO = @MLOTEO, ESACTIVO = @ESACTIVO, MSTOCK = @MSTOCK, MPRINCIPAL = @MPRINCIPAL, MCNS = @MCNS, PRECNS = 
				@PRECNS, MGRUPO = @MGRUPO, MLABILIDAD = @MLABILIDAD, MRIESGO = @MRIESGO, OPTICA = @OPTICA, MIVA = @MIVA, CUE_IVA = @CUE_IVA, IDIMPUESTO = @IDIMPUESTO, 
				IDCLASE = @IDCLASE
			WHERE IDITAR = @IDITAR
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		BEGIN TRY
			SELECT @IDITAR = JSON_VALUE(@PARAMETROS, '$.IDITAR')

			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'EL TIPO DE ARTICULO TIENE ARTICULOS ASIGNADOS (IART)'
			WHERE EXISTS (
					SELECT *
					FROM IART
					WHERE IDITAR = @IDITAR
					)

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				DELETE
				FROM ITAR
				WHERE IDITAR = @IDITAR
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GET_IDITAR'
	BEGIN
		SELECT 'OK' OK

		SELECT @IDITAR = JSON_VALUE(@PARAMETROS, '$.IDITAR')

		SELECT MCNS, PRECNS
		FROM ITAR
		WHERE IDITAR = @IDITAR

		RETURN
	END

	IF @METODO = 'TARI_EXPORTAR_EXCEL'
	BEGIN
		SELECT @IDTARIFA = IDTARIFA
		FROM OPENJSON(@PARAMETROS) WITH (IDTARIFA VARCHAR(5) '$.IDTARIFA')

		IF @CNSEXCEL IS NULL
		BEGIN
			EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@EXCEL', @LONGITUD = 8, @NVOCONSEC = @CNSEXCEL OUTPUT
		END

		BEGIN TRY
			INSERT INTO KEXCEL_FILL (CNSEXCEL, NOMBRE, BORRAR, CONSULTA)
			SELECT @CNSEXCEL, @IDTARIFA + '.xlsx', 1, 
				'SELECT TARD.IDTARIFA,TAR.DESCTARIFA AS TARIFA,SER.PREFIJO,SER.IDSERVICIO,SER.DESCSERVICIO AS SERVICIO FROM [dbo].[TARD] INNER JOIN SER ON TARD.IDSERVICIO = SER.IDSERVICIO INNER JOIN TAR ON TARD.IDTARIFA = TAR.IDTARIFA WHERE TARD.IDTARIFA=  ''' 
				+ @IDTARIFA + ''' ORDER BY 1 DESC'
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK, @CNSEXCEL CNSEXCEL

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK, @CNSEXCEL CNSEXCEL
	END

	IF @METODO = 'TARD_EXPORTAR_EXCEL'
	BEGIN
		SELECT @IDTARIFA = IDTARIFA, @IDSERVICIO = IDSERVICIO
		FROM OPENJSON(@PARAMETROS) WITH (IDTARIFA VARCHAR(5) '$.IDTARIFA', IDSERVICIO VARCHAR(20) '$.IDSERVICIO')

		IF @CNSEXCEL IS NULL
		BEGIN
			EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@EXCEL', @LONGITUD = 8, @NVOCONSEC = @CNSEXCEL OUTPUT
		END

		BEGIN TRY
			INSERT INTO KEXCEL_FILL (CNSEXCEL, NOMBRE, BORRAR, CONSULTA)
			SELECT @CNSEXCEL, @IDSERVICIO + '.xlsx', 1, 
				'SELECT NOITEM, TARDV.IDSERVICIO AS ID_SERVICIO,SER.DESCSERVICIO AS SERVICIO ,DBO.FNK_FECHA_GRINGA(FECHAINI) FECHA_INICIO, LEFT(CONVERT(VARCHAR, FECHAINI, 108), 10) HORA, DBO.FNK_FECHA_GRINGA(FECHAFIN) FECHA_FINAL, LEFT(CONVERT(
			VARCHAR, FECHAFIN, 108), 10) HORA_FINAL, CAST(CONVERT(DECIMAL(14, 4), VALOR) AS VARCHAR(20)) VALOR
FROM [dbo].[TARDV] INNER JOIN SER ON SER.IDSERVICIO = TARDV.IDSERVICIO
WHERE TARDV.IDTARIFA = ''' 
				+ @IDTARIFA + ''' AND TARDV.IDSERVICIO = ''' + @IDSERVICIO + ''' ORDER BY NOITEM DESC'
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK, @CNSEXCEL CNSEXCEL

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK, @CNSEXCEL CNSEXCEL
	END
END
