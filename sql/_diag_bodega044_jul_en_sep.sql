SET NOCOUNT ON;
/* ¿Los 17 julio entran en FNK pre-cierre SEP? */
SELECT COUNT(*) AS EN_FNK_SEP_2026
FROM IMOV M
WHERE M.IDBODEGA=N'044' AND M.MARCACONT=1 AND COALESCE(M.CONTABILIZADA,0)=0 AND M.ESTADO=1
  AND YEAR(M.FECHACONF)=2026 AND MONTH(M.FECHACONF)=9;

SELECT COUNT(*) AS EN_FNK_JUL_2026
FROM IMOV M
WHERE M.IDBODEGA=N'044' AND M.MARCACONT=1 AND COALESCE(M.CONTABILIZADA,0)=0 AND M.ESTADO=1
  AND YEAR(M.FECHACONF)=2026 AND MONTH(M.FECHACONF)=7;

/* Global FNK inventario sep (todas bodegas) - muestra jul en 044 */
SELECT M.CNSMOV, M.IDBODEGA, M.FECHAMOV, M.FECHACONF
FROM IMOV M
WHERE YEAR(M.FECHACONF)=2026 AND MONTH(M.FECHACONF)=9
  AND COALESCE(M.CONTABILIZADA,0)=0 AND COALESCE(M.SECONTABILIZA,0)=1 AND M.ESTADO=1
  AND M.IDBODEGA=N'044'
ORDER BY M.FECHACONF;
