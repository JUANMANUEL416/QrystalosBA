IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='SPK_AJUSTE_IDXB_IART' AND XTYPE='P')
BEGIN
   DROP PROCEDURE SPK_AJUSTE_IDXB_IART
END

GO
CREATE PROCEDURE DBO.SPK_AJUSTE_IDXB_IART
WITH ENCRYPTION
AS
BEGIN
 PRINT 'Colocando en 0 Posibles LoTes con CanTidades NegaTivas'
 UPDATE IEXI SET EXISLOTE=0 WHERE EXISLOTE<0
 
 PRINT 'InserTando ArTiculos Nuevos en IDXB '
 INSERT INTO IDXB (IDBODEGA,IDARTICULO,STOCKMINIMO,STOCKMAXIMO,PUNTOREORDEN,EXISTOTAL)
 SELECT IEXI.IDBODEGA,
	IEXI.IDARTICULO,
	IART.STOCKMINIMO,
	IART.STOCKMAXIMO,
	IART.PUNTOREORDEN,
	SUM(IEXI.EXISLOTE)
 FROM IART,IEXI
 WHERE IART.IDARTICULO=IEXI.IDARTICULO AND NOT IART.IDARTICULO IN
                               (SELECT IDARTICULO FROM IDXB X WHERE 
 X.IDBODEGA=IEXI.IDBODEGA)
 GROUP BY IEXI.IDBODEGA,
          IEXI.IDARTICULO,
	       IART.STOCKMINIMO,
	       IART.STOCKMAXIMO,
	       IART.PUNTOREORDEN

 PRINT 'AcTualizando IDXB. Poniendo en 0 las ExisTencia de ArTiculo que no ExisTen en IEXI'
 UPDATE IDXB SET EXISTOTAL=0 WHERE NOT IDARTICULO IN (SELECT IDARTICULO FROM IEXI WHERE IDBODEGA=IDXB.IDBODEGA)
 PRINT 'AcTualizando ExisTencias en IDXB'
 UPDATE IDXB SET EXISTOTAL=(SELECT SUM(EXISLOTE)
                           FROM IEXI
                           WHERE IEXI.IDARTICULO=IDXB.IDARTICULO AND IEXI.IDBODEGA=IDXB.IDBODEGA)
 WHERE IDARTICULO IN (SELECT IDARTICULO FROM IEXI WHERE IDBODEGA=IDXB.IDBODEGA)

 PRINT 'AcTualizando IART. Poniendo en 0 las ExisTencia de ArTiculo que no ExisTen en IDXB'
 UPDATE IART SET EXISTOTAL=0 WHERE NOT IDARTICULO IN (SELECT IDARTICULO FROM IDXB)

 PRINT 'AcTualizando las ExisTencia'
 UPDATE IART SET EXISTOTAL=(SELECT SUM(EXISTOTAL)
                           FROM IDXB
                           WHERE IDXB.IDARTICULO=IART.IDARTICULO
                           GROUP BY IDARTICULO)
 WHERE IDARTICULO IN (SELECT IDARTICULO FROM IDXB)

 PRINT 'AcTualizando Posibles Valores Nulos'
 UPDATE IEXI SET EXISLOTE=0 WHERE EXISLOTE IS NULL
 UPDATE IDXB SET EXISTOTAL=0 WHERE EXISTOTAL IS NULL
 UPDATE IART SET PCOSTO=0 WHERE PCOSTO IS NULL
 UPDATE IART SET EXISTOTAL=0 WHERE EXISTOTAL IS NULL
END
