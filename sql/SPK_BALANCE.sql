CREATE OR ALTER PROCEDURE DBO.SPK_BALANCE
    @TIPO            VARCHAR(2),
    @TPROCONT        VARCHAR(20),
    @ANO             INT,
    @MES             INT,
    @ANOFIN          INT,
    @MESFIN          INT,
    @CTAINI          VARCHAR(16),
    @CTAFIN          VARCHAR(16),
    @NIVELINI        SMALLINT    = 1,
    @NIVELFIN        SMALLINT    = 10,
    @CCOSTOINI       VARCHAR(20) = '',
    @CCOSTOFIN       VARCHAR(20) = '',
    @COMPANIA        VARCHAR(2)  = '01',
    @SEDE            VARCHAR(2)  = '01',
    @IDTERCERO       VARCHAR(20) = '',
    @IDTERCEROFIN    VARCHAR(20) = '',
    @VERTER          SMALLINT    = 0,
    @VERCCOSTO       SMALLINT    = 0
WITH ENCRYPTION
AS
    DECLARE @VLRNTDB           DECIMAL(14,2)
    DECLARE @VLRNTCR           DECIMAL(14,2)
    DECLARE @MESANT            INT
    DECLARE @ANOANT            INT
    DECLARE @NVOCONSEC         VARCHAR(20)
    DECLARE @PERIODOINICIAL    VARCHAR(6)
    DECLARE @PERIODOFINAL      VARCHAR(6)
    DECLARE @PERIODOSI         VARCHAR(6)
    DECLARE @ULTPERIODOCER     VARCHAR(6)
    DECLARE @ULTPERIODOCERMAS1 VARCHAR(6)
    DECLARE @PRIPERSIS         VARCHAR(6)
    DECLARE @PROCESO           INT
    DECLARE @ANOAUX            INT
    DECLARE @MESAUX            INT
    DECLARE @ANOSIN            INT
    DECLARE @MESSIN            INT
    DECLARE @QINS              VARCHAR(8000)
    DECLARE @IDTERCEROINI      VARCHAR(20)

BEGIN
    PRINT 'Se limpia la Tabla'
    DELETE TBALANCETERFAC WHERE CNSPRO = @TPROCONT

    IF @VERTER = 1
    BEGIN
        SELECT @IDTERCERO    = ''
        SELECT @IDTERCEROFIN = ''
    END
    SELECT @IDTERCEROINI = @IDTERCERO
    SELECT @NIVELFIN     = 10

    PRINT '@TIPO=' + @TIPO
    IF @MES = 1
    BEGIN
        SELECT @MESANT = 12
        SELECT @ANOANT  = @ANO - 1
    END
    ELSE
    BEGIN
        SELECT @MESANT = @MES - 1
        SELECT @ANOANT = @ANO
    END

    SELECT @NVOCONSEC = @TPROCONT
    IF @CTAFIN = ''
        SELECT @CTAFIN = DBO.FNK_MICOLLATE()
    IF @IDTERCEROFIN = ''
        SELECT @IDTERCEROFIN = DBO.FNK_MICOLLATE()
    IF @CCOSTOFIN = ''
        SET @CCOSTOFIN = DBO.FNK_MICOLLATE()

    PRINT '@NVOCONSEC=' + @NVOCONSEC

    SELECT @PERIODOSI = CAST(ANO AS VARCHAR(20)) + CASE WHEN MES < 10 THEN '0' + CAST(MES AS VARCHAR(1)) ELSE CAST(MES AS VARCHAR(2)) END
    FROM   PRI
    WHERE  SI = 1

    SELECT @ULTPERIODOCER = COALESCE(MAX(CAST(ANO AS VARCHAR(20)) + CASE WHEN MES < 10 THEN '0' + CAST(MES AS VARCHAR(1)) ELSE CAST(MES AS VARCHAR(2)) END), '')
    FROM   PRI
    WHERE  CERRADO = 1

    SELECT @ANOAUX = LEFT(@ULTPERIODOCER, 4)
    SELECT @MESAUX = SUBSTRING(@ULTPERIODOCER, 5, 2)
    IF @MESAUX = 12
    BEGIN
        SELECT @MESAUX = 1, @ANOAUX = @ANOAUX + 1
    END
    ELSE
    BEGIN
        SELECT @MESAUX = @MESAUX + 1
    END

    SELECT @ULTPERIODOCERMAS1 = COALESCE(MAX(CAST(@ANOAUX AS VARCHAR(20)) + CASE WHEN @MESAUX < 10 THEN '0' + CAST(@MESAUX AS VARCHAR(1)) ELSE CAST(@MESAUX AS VARCHAR(2)) END), '')
    SELECT @PERIODOINICIAL = CAST(@ANO AS VARCHAR(20)) + CASE WHEN @MES < 10 THEN '0' + CAST(@MES AS VARCHAR(1)) ELSE CAST(@MES AS VARCHAR(2)) END
    SELECT @PERIODOFINAL  = CAST(@ANOFIN AS VARCHAR(20)) + CASE WHEN @MESFIN < 10 THEN '0' + CAST(@MESFIN AS VARCHAR(1)) ELSE CAST(@MESFIN AS VARCHAR(2)) END

    IF @ULTPERIODOCER = ''
    BEGIN
        SELECT @PRIPERSIS = MIN(CAST(ANO AS VARCHAR(20)) + CASE WHEN MES < 10 THEN '0' + CAST(MES AS VARCHAR(1)) ELSE CAST(MES AS VARCHAR(2)) END)
        FROM   PRI

        SELECT @ANOSIN = ANO, @MESSIN = MES
        FROM   PRI
        WHERE  (CAST(ANO AS VARCHAR(20)) + CASE WHEN MES < 10 THEN '0' + CAST(MES AS VARCHAR(1)) ELSE CAST(MES AS VARCHAR(2)) END) = @PRIPERSIS

        SELECT @ULTPERIODOCER     = CAST(@ANOSIN AS VARCHAR(20)) + CASE WHEN @MESSIN < 10 THEN '0' + CAST(@MESSIN AS VARCHAR(1)) ELSE CAST(@MESSIN AS VARCHAR(2)) END
        SELECT @ULTPERIODOCERMAS1 = @ULTPERIODOCER
        SELECT @PROCESO = 3
    END
    ELSE
    BEGIN
        IF @ULTPERIODOCER >= @PERIODOFINAL
            SELECT @PROCESO = 1
        ELSE IF @ULTPERIODOCER >= @PERIODOINICIAL
            SELECT @PROCESO = 2
        ELSE
            SELECT @PROCESO = 3
    END

    PRINT '@PROCESO=' + STR(@PROCESO) + '//@ULTPERIODOCERMAS1=' + @ULTPERIODOCERMAS1

    IF @PROCESO = 1
    BEGIN
        PRINT '-- SE COLOCAN TODAS LAS CUENTAS Y SALDO FINAL DEL PERIODO FINAL (QUE ESTA CERRADO @PROCESO = 1)'
        INSERT INTO TBALANCETERFAC(CNSPRO, CUENTA, IDTERCERO, CCOSTO, N_FACTURA, NOMCUENTA, SI, DB, CR, SF, SM, NTZ)
        SELECT @NVOCONSEC, X.CUENTA,
           CASE COALESCE(@IDTERCERO,'') WHEN '' THEN CASE @VERTER WHEN 0 THEN '' ELSE COALESCE(M.IDTERCERO,'') END ELSE COALESCE(M.IDTERCERO,'') END,
           CASE COALESCE(@CCOSTOINI,'') WHEN '' THEN CASE @VERCCOSTO WHEN 0 THEN '' ELSE COALESCE(M.CCOSTO,'') END ELSE COALESCE(M.CCOSTO,'') END,
           '', X.NOMCUENTA, 0, 0, 0, SUM(COALESCE(M.SF,0)), 0, M.NTZ
        FROM   SALDOMESTERFAC M
            INNER JOIN CUE X ON X.CUENTA = M.CUENTA
        WHERE  M.ANOMES = @PERIODOFINAL
            AND ( @CCOSTOINI = '' OR COALESCE(M.CCOSTO,'') >= @CCOSTOINI )
            AND ( COALESCE(M.CCOSTO,'') <= @CCOSTOFIN )
            AND M.CUENTA >= @CTAINI
            AND M.CUENTA <= @CTAFIN
            AND X.NIVEL >= @NIVELINI
            AND X.NIVEL <= @NIVELFIN
            AND ( @IDTERCERO = '' OR COALESCE(M.IDTERCERO,'') >= @IDTERCERO )
            AND ( COALESCE(M.IDTERCERO,'') <= @IDTERCEROFIN )
        GROUP BY X.CUENTA,
                 CASE COALESCE(@IDTERCERO,'') WHEN '' THEN CASE @VERTER WHEN 0 THEN '' ELSE COALESCE(M.IDTERCERO,'') END ELSE COALESCE(M.IDTERCERO,'') END,
                 CASE COALESCE(@CCOSTOINI,'') WHEN '' THEN CASE @VERCCOSTO WHEN 0 THEN '' ELSE COALESCE(M.CCOSTO,'') END ELSE COALESCE(M.CCOSTO,'') END,
                 X.NOMCUENTA, M.NTZ

        PRINT '-- DEBEMOS COLOCAR REGISTROS QUE NO ESTAN EN EL PERIODO FINAL...'
        INSERT INTO TBALANCETERFAC(CNSPRO, CUENTA, IDTERCERO, CCOSTO, N_FACTURA, NOMCUENTA, SI, DB, CR, SF, SM, NTZ)
        SELECT CNSPRO, CUENTA, COALESCE(IDTERCERO,''), CCOSTO, N_FACTURA, NOMCUENTA, SI, DB, CR, SF, SM, NTZ
        FROM (
            SELECT @NVOCONSEC CNSPRO, X.CUENTA,
                CASE COALESCE(@IDTERCERO,'') WHEN '' THEN CASE @VERTER WHEN 0 THEN '' ELSE COALESCE(M.IDTERCERO,'') END ELSE COALESCE(M.IDTERCERO,'') END IDTERCERO,
                CASE COALESCE(@CCOSTOINI,'') WHEN '' THEN CASE @VERCCOSTO WHEN 0 THEN '' ELSE COALESCE(M.CCOSTO,'') END ELSE COALESCE(M.CCOSTO,'') END CCOSTO,
                '' N_FACTURA, X.NOMCUENTA, 0 SI, 0 DB, 0 CR, 0 SF, 0 SM, M.NTZ
            FROM SALDOMESTERFAC M
                INNER JOIN CUE X ON X.CUENTA = M.CUENTA
            WHERE  M.ANOMES < @PERIODOFINAL
                AND  M.ANOMES >= @PERIODOINICIAL
                AND ( @CCOSTOINI = '' OR COALESCE(M.CCOSTO,'') >= @CCOSTOINI )
                AND ( COALESCE(M.CCOSTO,'') <= @CCOSTOFIN )
                AND M.CUENTA >= @CTAINI
                AND M.CUENTA <= @CTAFIN
                AND X.NIVEL >= @NIVELINI
                AND X.NIVEL <= @NIVELFIN
                AND ( @IDTERCERO = '' OR COALESCE(M.IDTERCERO,'') >= @IDTERCERO )
                AND ( COALESCE(M.IDTERCERO,'') <= @IDTERCEROFIN )
            GROUP BY X.CUENTA,
                CASE COALESCE(@IDTERCERO,'') WHEN '' THEN CASE @VERTER WHEN 0 THEN '' ELSE COALESCE(M.IDTERCERO,'') END ELSE COALESCE(M.IDTERCERO,'') END,
                CASE COALESCE(@CCOSTOINI,'') WHEN '' THEN CASE @VERCCOSTO WHEN 0 THEN '' ELSE COALESCE(M.CCOSTO,'') END ELSE COALESCE(M.CCOSTO,'') END,
                X.NOMCUENTA, M.NTZ
            ) X
        WHERE NOT EXISTS ( SELECT 1 FROM TBALANCETERFAC T2 WHERE  T2.CNSPRO = @NVOCONSEC
                AND  T2.CUENTA = X.CUENTA
                AND  COALESCE(T2.IDTERCERO,'') = COALESCE(X.IDTERCERO,'')
                AND  T2.CCOSTO = X.CCOSTO
                AND  T2.N_FACTURA = X.N_FACTURA 
        )

        PRINT 'ACTUALIZAMOS SALDO INICIAL'
        UPDATE TBALANCETERFAC SET TBALANCETERFAC.SI = COALESCE(M.SI,0)
        FROM   TBALANCETERFAC
        INNER JOIN (
            SELECT X.CUENTA,
                    CASE COALESCE(@IDTERCERO,'') WHEN '' THEN CASE @VERTER WHEN 0 THEN '' ELSE COALESCE(M.IDTERCERO,'') END ELSE COALESCE(M.IDTERCERO,'') END IDTERCERO,
                    CASE COALESCE(@CCOSTOINI,'') WHEN '' THEN CASE @VERCCOSTO WHEN 0 THEN '' ELSE COALESCE(M.CCOSTO,'') END ELSE COALESCE(M.CCOSTO,'') END CCOSTO,
                    '' N_FACTURA, SUM(COALESCE(SI,0)) SI
            FROM   SALDOMESTERFAC M
                INNER JOIN CUE X ON X.CUENTA = M.CUENTA
            WHERE  M.ANOMES = @PERIODOINICIAL
                AND ( @CCOSTOINI = '' OR COALESCE(M.CCOSTO,'') >= @CCOSTOINI )
                AND ( COALESCE(M.CCOSTO,'') <= @CCOSTOFIN )
                AND M.CUENTA >= @CTAINI
                AND M.CUENTA <= @CTAFIN
                AND X.NIVEL >= @NIVELINI
                AND X.NIVEL <= @NIVELFIN
                AND ( @IDTERCERO = '' OR COALESCE(M.IDTERCERO,'') >= @IDTERCERO )
                AND ( COALESCE(M.IDTERCERO,'') <= @IDTERCEROFIN )
            GROUP BY X.CUENTA,
                    CASE COALESCE(@IDTERCERO,'') WHEN '' THEN CASE @VERTER WHEN 0 THEN '' ELSE COALESCE(M.IDTERCERO,'') END ELSE COALESCE(M.IDTERCERO,'') END,
                    CASE COALESCE(@CCOSTOINI,'') WHEN '' THEN CASE @VERCCOSTO WHEN 0 THEN '' ELSE COALESCE(M.CCOSTO,'') END ELSE COALESCE(M.CCOSTO,'') END
        ) M ON TBALANCETERFAC.CUENTA = M.CUENTA
           AND COALESCE(TBALANCETERFAC.IDTERCERO,'') = COALESCE(M.IDTERCERO,'')
           AND COALESCE(TBALANCETERFAC.CCOSTO,'') = COALESCE(M.CCOSTO,'')
           AND COALESCE(TBALANCETERFAC.N_FACTURA,'') = COALESCE(M.N_FACTURA,'')
        WHERE  TBALANCETERFAC.CNSPRO = @NVOCONSEC

        PRINT 'ACTUALIZAMOS DB Y CR'
        UPDATE TBALANCETERFAC SET TBALANCETERFAC.DB = X.DB, TBALANCETERFAC.CR = X.CR
        FROM TBALANCETERFAC
        INNER JOIN (
            SELECT X.CUENTA,
                CASE COALESCE(@IDTERCERO,'') WHEN '' THEN CASE @VERTER WHEN 0 THEN '' ELSE COALESCE(M.IDTERCERO,'') END ELSE COALESCE(M.IDTERCERO,'') END IDTERCERO,
                CASE COALESCE(@CCOSTOINI,'') WHEN '' THEN CASE @VERCCOSTO WHEN 0 THEN '' ELSE COALESCE(M.CCOSTO,'') END ELSE COALESCE(M.CCOSTO,'') END CCOSTO,
                '' N_FACTURA,
                SUM(COALESCE(M.DB,0)) DB, SUM(COALESCE(M.CR,0)) CR
            FROM   SALDOMESTERFAC M
                INNER JOIN CUE X ON X.CUENTA = M.CUENTA
            WHERE  M.ANOMES >= @PERIODOINICIAL
                AND  M.ANOMES <= @PERIODOFINAL
                AND ( @CCOSTOINI = '' OR COALESCE(M.CCOSTO,'') >= @CCOSTOINI )
                AND ( COALESCE(M.CCOSTO,'') <= @CCOSTOFIN )
                AND M.CUENTA >= @CTAINI
                AND M.CUENTA <= @CTAFIN
                AND X.NIVEL >= @NIVELINI
                AND X.NIVEL <= @NIVELFIN
                AND ( @IDTERCERO = '' OR COALESCE(M.IDTERCERO,'') >= @IDTERCERO )
                AND ( COALESCE(M.IDTERCERO,'') <= @IDTERCEROFIN )
            GROUP BY X.CUENTA,
                    CASE COALESCE(@IDTERCERO,'') WHEN '' THEN CASE @VERTER WHEN 0 THEN '' ELSE COALESCE(M.IDTERCERO,'') END ELSE COALESCE(M.IDTERCERO,'') END,
                    CASE COALESCE(@CCOSTOINI,'') WHEN '' THEN CASE @VERCCOSTO WHEN 0 THEN '' ELSE COALESCE(M.CCOSTO,'') END ELSE COALESCE(M.CCOSTO,'') END
        ) X ON TBALANCETERFAC.CUENTA = X.CUENTA
            AND TBALANCETERFAC.IDTERCERO = X.IDTERCERO
            AND TBALANCETERFAC.CCOSTO = X.CCOSTO
            AND TBALANCETERFAC.N_FACTURA = X.N_FACTURA
        WHERE  TBALANCETERFAC.CNSPRO = @NVOCONSEC

        PRINT 'UPDATE SM'
        UPDATE TBALANCETERFAC SET TBALANCETERFAC.SM = CASE NTZ.TIPO WHEN 'DB' THEN TBALANCETERFAC.DB - TBALANCETERFAC.CR WHEN 'CR' THEN TBALANCETERFAC.CR - TBALANCETERFAC.DB END
        FROM TBALANCETERFAC
        INNER JOIN NTZ ON LEFT(TBALANCETERFAC.CUENTA, 1) = NTZ.N_INICIAL
        WHERE  TBALANCETERFAC.CNSPRO = @NVOCONSEC
    END
    ELSE IF @PROCESO = 2
    BEGIN
        INSERT INTO TBALANCETERFAC (CNSPRO, CUENTA, IDTERCERO, CCOSTO, N_FACTURA, NOMCUENTA, SI, DB, CR, SF, SM, NTZ)
        SELECT @NVOCONSEC, X.CUENTA,
            CASE COALESCE(@IDTERCERO,'') WHEN '' THEN CASE @VERTER WHEN 0 THEN '' ELSE COALESCE(MCH.IDTERCERO,'') END ELSE COALESCE(MCH.IDTERCERO,'') END,
            CASE COALESCE(@CCOSTOINI,'') WHEN '' THEN CASE @VERCCOSTO WHEN 0 THEN '' ELSE COALESCE(MCH.CCOSTO,'') END ELSE COALESCE(MCH.CCOSTO,'') END,
            '', X.NOMCUENTA, 0, 0, 0, 0, 0, NTZ.TIPO
        FROM MCP
            INNER JOIN MCH ON MCP.NROCOMPROBANTE = MCH.NROCOMPROBANTE
            INNER JOIN CUE X ON X.CUENTA = MCH.CUENTA
            INNER JOIN NTZ ON LEFT(MCH.CUENTA, 1) = NTZ.N_INICIAL
        WHERE MCP.ESTADO = 2
            AND  ISNULL(MCP.ANULADO, 0) = 0
            AND  MCP.ANOMES >= @ULTPERIODOCERMAS1
            AND  MCP.ANOMES <= @PERIODOFINAL
            AND ( @CCOSTOINI = '' OR COALESCE(MCH.CCOSTO,'') >= @CCOSTOINI )
            AND ( COALESCE(MCH.CCOSTO,'') <= @CCOSTOFIN )
            AND  MCH.CUENTA >= @CTAINI
            AND  MCH.CUENTA <= @CTAFIN
            AND  X.NIVEL >= @NIVELINI
            AND  X.NIVEL <= @NIVELFIN
            AND ( @IDTERCERO = '' OR COALESCE(MCH.IDTERCERO,'') >= @IDTERCERO )
            AND ( COALESCE(MCH.IDTERCERO,'') <= @IDTERCEROFIN )
        GROUP BY X.CUENTA,
            CASE COALESCE(@IDTERCERO,'') WHEN '' THEN CASE @VERTER WHEN 0 THEN '' ELSE COALESCE(MCH.IDTERCERO,'') END ELSE COALESCE(MCH.IDTERCERO,'') END,
            CASE COALESCE(@CCOSTOINI,'') WHEN '' THEN CASE @VERCCOSTO WHEN 0 THEN '' ELSE COALESCE(MCH.CCOSTO,'') END ELSE COALESCE(MCH.CCOSTO,'') END,
            X.NOMCUENTA, NTZ.TIPO

        INSERT INTO TBALANCETERFAC(CNSPRO, CUENTA, IDTERCERO, CCOSTO, N_FACTURA, NOMCUENTA, SI, DB, CR, SF, SM, NTZ)
        SELECT @NVOCONSEC, X.CUENTA,
            CASE COALESCE(@IDTERCERO,'') WHEN '' THEN CASE @VERTER WHEN 0 THEN '' ELSE COALESCE(M.IDTERCERO,'') END ELSE COALESCE(M.IDTERCERO,'') END,
            CASE COALESCE(@CCOSTOINI,'') WHEN '' THEN CASE @VERCCOSTO WHEN 0 THEN '' ELSE COALESCE(M.CCOSTO,'') END ELSE COALESCE(M.CCOSTO,'') END CCOSTO,
            '', X.NOMCUENTA, 0, 0, 0, 0, 0, NTZ.TIPO
        FROM SALDOMESTERFAC M
            INNER JOIN NTZ ON LEFT(M.CUENTA, 1) = NTZ.N_INICIAL
            INNER JOIN CUE X ON X.CUENTA = M.CUENTA
        WHERE  M.ANOMES >= @PERIODOINICIAL
            AND  M.ANOMES <= @ULTPERIODOCER
            AND ( @CCOSTOINI = '' OR COALESCE(M.CCOSTO,'') >= @CCOSTOINI )
            AND ( COALESCE(M.CCOSTO,'') <= @CCOSTOFIN )
            AND  X.CUENTA >= @CTAINI
            AND  X.CUENTA <= @CTAFIN
            AND  X.NIVEL >= @NIVELINI
            AND  X.NIVEL <= @NIVELFIN
            AND ( @IDTERCERO = '' OR COALESCE(M.IDTERCERO,'') >= @IDTERCERO )
            AND ( COALESCE(M.IDTERCERO,'') <= @IDTERCEROFIN )
            AND NOT EXISTS ( SELECT 1 FROM TBALANCETERFAC Y
                    WHERE  Y.CNSPRO = @NVOCONSEC
                    AND  Y.CUENTA = X.CUENTA
                    AND  COALESCE(Y.IDTERCERO,'') = CASE COALESCE(@IDTERCERO,'') WHEN '' THEN CASE @VERTER WHEN 0 THEN '' ELSE COALESCE(M.IDTERCERO,'') END ELSE COALESCE(M.IDTERCERO,'') END
                    AND  COALESCE(Y.CCOSTO,'') = CASE COALESCE(@CCOSTOINI,'') WHEN '' THEN '' ELSE CASE WHEN X.CLASE IN ('CXC','CXP') THEN '' ELSE COALESCE(M.CCOSTO,'') END END
                    AND  COALESCE(Y.N_FACTURA,'') = '' 
                )
        GROUP BY X.CUENTA,
            CASE COALESCE(@IDTERCERO,'') WHEN '' THEN CASE @VERTER WHEN 0 THEN '' ELSE COALESCE(M.IDTERCERO,'') END ELSE COALESCE(M.IDTERCERO,'') END,
            CASE COALESCE(@CCOSTOINI,'') WHEN '' THEN CASE @VERCCOSTO WHEN 0 THEN '' ELSE COALESCE(M.CCOSTO,'') END ELSE COALESCE(M.CCOSTO,'') END,
            X.NOMCUENTA, NTZ.TIPO

        UPDATE TBALANCETERFAC SET TBALANCETERFAC.SI = M.SI
        FROM   TBALANCETERFAC
        INNER JOIN (
            SELECT X.CUENTA,
                CASE COALESCE(@IDTERCERO,'') WHEN '' THEN CASE @VERTER WHEN 0 THEN '' ELSE COALESCE(M.IDTERCERO,'') END ELSE COALESCE(M.IDTERCERO,'') END IDTERCERO,
                CASE COALESCE(@CCOSTOINI,'') WHEN '' THEN CASE @VERCCOSTO WHEN 0 THEN '' ELSE COALESCE(M.CCOSTO,'') END ELSE COALESCE(M.CCOSTO,'') END CCOSTO,
                '' N_FACTURA, SUM(SI) SI
            FROM   SALDOMESTERFAC M
                INNER JOIN CUE X ON X.CUENTA = M.CUENTA
            WHERE  M.ANOMES = @PERIODOINICIAL
                AND ( @CCOSTOINI = '' OR COALESCE(M.CCOSTO,'') >= @CCOSTOINI )
                AND ( COALESCE(M.CCOSTO,'') <= @CCOSTOFIN )
                AND  M.CUENTA >= @CTAINI
                AND  M.CUENTA <= @CTAFIN
                AND  X.NIVEL >= @NIVELINI
                AND  X.NIVEL <= @NIVELFIN
                AND ( @IDTERCERO = '' OR COALESCE(M.IDTERCERO,'') >= @IDTERCERO )
                AND ( COALESCE(M.IDTERCERO,'') <= @IDTERCEROFIN )
            GROUP BY X.CUENTA,
                CASE COALESCE(@IDTERCERO,'') WHEN '' THEN CASE @VERTER WHEN 0 THEN '' ELSE COALESCE(M.IDTERCERO,'') END ELSE COALESCE(M.IDTERCERO,'') END,
                CASE COALESCE(@CCOSTOINI,'') WHEN '' THEN CASE @VERCCOSTO WHEN 0 THEN '' ELSE COALESCE(M.CCOSTO,'') END ELSE COALESCE(M.CCOSTO,'') END
        ) M ON TBALANCETERFAC.CUENTA = M.CUENTA
            AND TBALANCETERFAC.IDTERCERO = M.IDTERCERO
            AND TBALANCETERFAC.CCOSTO = M.CCOSTO
            AND TBALANCETERFAC.N_FACTURA = M.N_FACTURA
        WHERE  TBALANCETERFAC.CNSPRO = @NVOCONSEC

        UPDATE TBALANCETERFAC SET TBALANCETERFAC.DB = M.DB, TBALANCETERFAC.CR = M.CR
        FROM   TBALANCETERFAC
        INNER JOIN (
            SELECT X.CUENTA,
                CASE COALESCE(@IDTERCERO,'') WHEN '' THEN CASE @VERTER WHEN 0 THEN '' ELSE COALESCE(M.IDTERCERO,'') END ELSE COALESCE(M.IDTERCERO,'') END IDTERCERO,
                CASE COALESCE(@CCOSTOINI,'') WHEN '' THEN CASE @VERCCOSTO WHEN 0 THEN '' ELSE COALESCE(M.CCOSTO,'') END ELSE COALESCE(M.CCOSTO,'') END CCOSTO,
                '' N_FACTURA, SUM(DB) DB, SUM(CR) CR
            FROM   SALDOMESTERFAC M
                INNER JOIN CUE X ON X.CUENTA = M.CUENTA
            WHERE  M.ANOMES >= @PERIODOINICIAL
                AND  M.ANOMES <= @ULTPERIODOCER
                AND ( @CCOSTOINI = '' OR COALESCE(M.CCOSTO,'') >= @CCOSTOINI )
                AND ( COALESCE(M.CCOSTO,'') <= @CCOSTOFIN )
                AND  M.CUENTA >= @CTAINI
                AND  M.CUENTA <= @CTAFIN
                AND  X.NIVEL >= @NIVELINI
                AND  X.NIVEL <= @NIVELFIN
                AND ( @IDTERCERO = '' OR COALESCE(M.IDTERCERO,'') >= @IDTERCERO )
                AND ( COALESCE(M.IDTERCERO,'') <= @IDTERCEROFIN )
            GROUP BY X.CUENTA,
                CASE COALESCE(@IDTERCERO,'') WHEN '' THEN CASE @VERTER WHEN 0 THEN '' ELSE COALESCE(M.IDTERCERO,'') END ELSE COALESCE(M.IDTERCERO,'') END,
                CASE COALESCE(@CCOSTOINI,'') WHEN '' THEN CASE @VERCCOSTO WHEN 0 THEN '' ELSE COALESCE(M.CCOSTO,'') END ELSE COALESCE(M.CCOSTO,'') END
        ) M ON TBALANCETERFAC.CUENTA = M.CUENTA
            AND TBALANCETERFAC.IDTERCERO = M.IDTERCERO
            AND TBALANCETERFAC.CCOSTO = M.CCOSTO
            AND TBALANCETERFAC.N_FACTURA = M.N_FACTURA
        WHERE  TBALANCETERFAC.CNSPRO = @NVOCONSEC

        UPDATE TBALANCETERFAC SET TBALANCETERFAC.DB = TBALANCETERFAC.DB + M.DB, TBALANCETERFAC.CR = TBALANCETERFAC.CR + M.CR
        FROM   TBALANCETERFAC
        INNER JOIN (
            SELECT X.CUENTA,
                CASE COALESCE(@IDTERCERO,'') WHEN '' THEN CASE @VERTER WHEN 0 THEN '' ELSE COALESCE(MCH.IDTERCERO,'') END ELSE COALESCE(MCH.IDTERCERO,'') END IDTERCERO,
                CASE COALESCE(@CCOSTOINI,'') WHEN '' THEN CASE @VERCCOSTO WHEN 0 THEN '' ELSE COALESCE(MCH.CCOSTO,'') END ELSE COALESCE(MCH.CCOSTO,'') END CCOSTO,
                '' N_FACTURA,
                SUM(CASE MCH.TIPO WHEN 'DB' THEN MCH.VALOR ELSE 0 END) DB,
                SUM(CASE MCH.TIPO WHEN 'CR' THEN MCH.VALOR ELSE 0 END) CR
            FROM MCP
                INNER JOIN MCH ON MCP.NROCOMPROBANTE = MCH.NROCOMPROBANTE
                INNER JOIN CUE X ON X.CUENTA = MCH.CUENTA
                INNER JOIN NTZ ON LEFT(MCH.CUENTA, 1) = NTZ.N_INICIAL
            WHERE  MCP.ESTADO = 2
                AND  ISNULL(MCP.ANULADO, 0) = 0
