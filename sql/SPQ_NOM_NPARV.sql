CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NPARV
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @DATO				NVARCHAR(MAX)
DECLARE  @PARAMETROS		NVARCHAR(MAX),	@MODELO		VARCHAR(100),   @METODO		VARCHAR(100),	@USUARIO	VARCHAR(20)
DECLARE	 @PROCESO			VARCHAR(20)
DECLARE  @CODPARAMETRO		VARCHAR(20),	@FECHAINI			DATETIME,		@FECHAFIN	DATETIME,		@VALOR		DECIMAL
DECLARE	 @FECHAINIEDITE		DATETIME,		@FECHAFINEDITE		DATETIME,		@VALOREDITE	DECIMAL	

DECLARE  @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

	IF @METODO = 'GUARDAR'
		BEGIN
			BEGIN TRY
				SELECT  @CODPARAMETRO = CODPARAMETRO, @FECHAINI = FECHAINI, @FECHAFIN = FECHAFIN, @VALOR = VALOR,
						@PROCESO = PROCESO
				FROM	OPENJSON (@PARAMETROS) 
				WITH	(
					CODPARAMETRO	VARCHAR(20)			'$.CODPARAMETRO',
					FECHAINI		DATETIME			'$.FECHAINI',
					FECHAFIN		DATETIME			'$.FECHAFIN',
					VALOR			DECIMAL				'$.VALOR',		
					PROCESO			VARCHAR(20)			'$.PROCESO'

				)
				IF UPPER(@PROCESO) = 'INSERTAR'
				BEGIN
					BEGIN TRY
						BEGIN
							INSERT INTO NPARV (CODPARAMETRO ,FECHAINI ,FECHAFIN ,VALOR)   
							SELECT @CODPARAMETRO, @FECHAINI, @FECHAFIN, @VALOR
						END
					END TRY
					BEGIN CATCH
						INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
					END CATCH

					IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
					BEGIN
						SELECT 'KO' OK
						SELECT ERROR FROM @TBLERRORES
						RETURN
					END

					SELECT 'OK' OK 
					RETURN
				END
			
				IF UPPER(@PROCESO) = 'EDITAR'
					BEGIN
						BEGIN TRY
							SELECT @DATO = DATO        
							  FROM   OPENJSON (@PARAMETROS)
							  WITH (DATO NVARCHAR(MAX) AS JSON)   
							  
							  SELECT @FECHAINIEDITE = FECHAINIEDITE, @FECHAFINEDITE = FECHAFINEDITE, @VALOREDITE = VALOREDITE
							  FROM   OPENJSON (@DATO)
							  WITH   (   
							  FECHAINIEDITE		DATETIME '$.FECHAINIEDITE',
							  FECHAFINEDITE		DATETIME '$.FECHAFINEDITE',
							  VALOREDITE		DECIMAL	 '$.VALOREDITE'
							  )

							UPDATE NPARV SET FECHAINI = @FECHAINI ,FECHAFIN = @FECHAFIN,VALOR = @VALOR
							WHERE FECHAINI = @FECHAINIEDITE AND FECHAFIN = @FECHAFINEDITE AND VALOR = @VALOREDITE
						END TRY

						BEGIN CATCH
							INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
						END CATCH

						IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
						BEGIN
							SELECT 'KO' OK
							SELECT ERROR FROM @TBLERRORES
							RETURN
						END

						SELECT 'OK' OK 
						RETURN
					END
			END TRY

			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
			END CATCH

			IF(SELECT COUNT(*) FROM @TBLERRORES) >0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END

			SELECT 'OK' OK
		END

		IF @METODO = 'GET_NPARV_DETALLE'
		BEGIN
			SELECT @CODPARAMETRO = CODPARAMETRO    
					FROM   OPENJSON (@PARAMETROS)
					WITH   (CODPARAMETRO VARCHAR(20) '$.CODPARAMETRO') 
			SELECT 'OK' OK
			SELECT * FROM NPARV
			WHERE CODPARAMETRO = JSON_VALUE(@PARAMETROS, '$.CODPARAMETRO') 
			RETURN
		END
END
