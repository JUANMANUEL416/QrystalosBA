CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NFUTC @JSON NVARCHAR(MAX) WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100)
DECLARE @USUARIO VARCHAR(20), @PROCESO VARCHAR(20)
DECLARE @TIPOCOTIZANTE VARCHAR(10), @DESCRIPCION VARCHAR(255), @HOMOLOGODIAN VARCHAR(2)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @TIPOCOTIZANTE = TIPOCOTIZANTE, @DESCRIPCION = DESCRIPCION, @HOMOLOGODIAN = HOMOLOGODIAN, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					TIPOCOTIZANTE VARCHAR(10) '$.TIPOCOTIZANTE', DESCRIPCION VARCHAR(255) '$.DESCRIPCION', HOMOLOGODIAN VARCHAR(2) '$.HOMOLOGODIAN', PROCESO 
					VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
            BEGIN TRY
				INSERT INTO @TBLERRORES (ERROR)
					SELECT 'EL TIPO COTIZANTE YA SE ENCUENTRA REGISTRADO'
					WHERE EXISTS (
							SELECT 1
							FROM NFUTC
							WHERE TIPOCOTIZANTE = @TIPOCOTIZANTE
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
                        INSERT INTO NFUTC (TIPOCOTIZANTE,DESCRIPCION,HOMOLOGODIAN) VALUES (@TIPOCOTIZANTE,@DESCRIPCION,@HOMOLOGODIAN)
                    END
                    	END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					UPDATE NFUTC
					SET DESCRIPCION = @DESCRIPCION, HOMOLOGODIAN = @HOMOLOGODIAN
					WHERE TIPOCOTIZANTE = @TIPOCOTIZANTE
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

    IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @TIPOCOTIZANTE = TIPOCOTIZANTE
		FROM OPENJSON(@PARAMETROS) WITH (TIPOCOTIZANTE VARCHAR(10) '$.TIPOCOTIZANTE')

		BEGIN TRY
			DELETE
			FROM NFUTC
			WHERE TIPOCOTIZANTE = @TIPOCOTIZANTE
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
