/*
  Corrección de cuentas. CEM. Septiembre 2026.
  Once líneas de compras tienen IVA y la cuenta del servicio sigue en excluidos.
  Si la línea tiene IVA, el servicio pasa a la gravada y la cuenta de IVA
  queda en 24080501 (descontable). El lote nacido en esa entrada hace lo mismo:
  débito gravado, reversión gravada y cuenta de IVA.
  use cem
  Sin contabilizar, estado N, crédito 22050101 (no se toca el encabezado):
    03CM001991  DPE11292    ítems 1 y 2. Sin cuenta de IVA. 14150502 → 14150501.
    03CM001818  FE602801    ítem 1. 14150502 → 14150501.
    03CM001611  FEP109844   ítem 1. 14200502 → 14200501. Esta entrada no tiene lote.
    03CM001809  FEP109948   ítems 1 y 2. 14200502 → 14200501.
                            El ítem 1 trae el IVA en 24080601 y pasa a 24080501.
    26CM000449  INST256930  ítem 4. 14200502 → 14200501.
    26CM000477  INST257106  ítems 3, 4, 5 y 6. 14200502 → 14200501.
                            El ítem 4 no tiene lote en esta entrada.

  Fuera de este bloque:
    01CM000740 DPE10712 ya está contabilizada (2664000000002688).
    El lote DM0089-1 de 03CM001611 y el lote DM65-1 del ítem 4 de 26CM000477
    están en otras entradas. No se modifican.

  Si una línea, un encabezado o un lote no está como se espera, no deja nada grabado.
  Ejecutar el bloque completo. No contabiliza.
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @L TABLE (
  CNSFCXP varchar(20) NOT NULL,
  ITEM int NOT NULL,
  CUENTA_HOY varchar(20) NOT NULL,
  IVA_HOY varchar(20) NOT NULL,
  CUENTA_OK varchar(20) NOT NULL,
  REV_OK varchar(20) NOT NULL,
  PRIMARY KEY (CNSFCXP, ITEM)
);

INSERT INTO @L (CNSFCXP, ITEM, CUENTA_HOY, IVA_HOY, CUENTA_OK, REV_OK) VALUES
  (N'03CM001991', 1, N'14150502', N'',         N'14150501', N'14150590'),
  (N'03CM001991', 2, N'14150502', N'',         N'14150501', N'14150590'),
  (N'03CM001818', 1, N'14150502', N'24080501', N'14150501', N'14150590'),
  (N'03CM001611', 1, N'14200502', N'24080501', N'14200501', N'14200590'),
  (N'03CM001809', 1, N'14200502', N'24080601', N'14200501', N'14200590'),
  (N'03CM001809', 2, N'14200502', N'24080501', N'14200501', N'14200590'),
  (N'26CM000449', 4, N'14200502', N'24080501', N'14200501', N'14200590'),
  (N'26CM000477', 3, N'14200502', N'24080501', N'14200501', N'14200590'),
  (N'26CM000477', 4, N'14200502', N'24080501', N'14200501', N'14200590'),
  (N'26CM000477', 5, N'14200502', N'24080501', N'14200501', N'14200590'),
  (N'26CM000477', 6, N'14200502', N'24080501', N'14200501', N'14200590');

BEGIN TRAN;

IF (
  SELECT COUNT(*)
  FROM CUE
  WHERE CUENTA = N'14150501'
    AND TIPO = N'Detalle'
    AND ESTADO = N'Activa'
    AND COALESCE(MCUEGRAV, 0) = 0
    AND COALESCE(MCUEREV, 0) = 1
    AND CUENTAREV = N'14150590'
) <> 1
OR (
  SELECT COUNT(*)
  FROM CUE
  WHERE CUENTA = N'14200501'
    AND TIPO = N'Detalle'
    AND ESTADO = N'Activa'
    AND COALESCE(MCUEGRAV, 0) = 0
    AND COALESCE(MCUEREV, 0) = 1
    AND CUENTAREV = N'14200590'
) <> 1
OR (
  SELECT COUNT(*)
  FROM CUE
  WHERE CUENTA = N'24080501'
    AND TIPO = N'Detalle'
    AND ESTADO = N'Activa'
) <> 1
OR (
  SELECT COUNT(*)
  FROM CUE
  WHERE CUENTA = N'14150502'
    AND MCUEGRAV = 1
    AND CUENTAGRAV = N'14150501'
    AND CUENTAREV = N'14150591'
) <> 1
OR (
  SELECT COUNT(*)
  FROM CUE
  WHERE CUENTA = N'14200502'
    AND MCUEGRAV = 1
    AND CUENTAGRAV = N'14200501'
    AND CUENTAREV = N'14200591'
) <> 1
BEGIN
  ROLLBACK TRAN;
  THROW 50001, 'La cuenta gravada, de excluidos o de IVA no esta como se espera. No se cambio nada.', 1;
END;

IF (
  SELECT COUNT(*)
  FROM FCXP
  WHERE CNSFCXP IN (
      N'03CM001611', N'03CM001809', N'03CM001818',
      N'03CM001991', N'26CM000449', N'26CM000477'
    )
    AND ESTADO = N'N'
    AND COALESCE(CONTABILIZADA, 0) = 0
    AND COALESCE(NROCOMPROBANTE, N'') = N''
    AND CUECREDITO = N'22050101'
) <> 6
BEGIN
  ROLLBACK TRAN;
  THROW 50002, 'Alguna CxP no esta en estado N, ya tiene comprobante o el credito no es proveedores. No se cambio nada.', 1;
END;

IF (
  SELECT COUNT(*)
  FROM @L L
  INNER JOIN FCXPD D ON D.CNSFCXP = L.CNSFCXP AND D.ITEM = L.ITEM
  WHERE D.PROCEDENCIA = N'Compras'
    AND COALESCE(D.VLR_IVA, 0) > 0
    AND D.CUENTA_SER = L.CUENTA_HOY
    AND COALESCE(D.CUENTA_IVA, N'') = L.IVA_HOY
) <> 11
BEGIN
  ROLLBACK TRAN;
  THROW 50003, 'Hay una linea que ya no esta en excluidos o cuyo IVA no es el esperado. No se cambio nada.', 1;
END;

IF (
  SELECT COUNT(*)
  FROM @L L
  INNER JOIN FCXPD D ON D.CNSFCXP = L.CNSFCXP AND D.ITEM = L.ITEM
  INNER JOIN IEXI I
    ON I.CNSMOV = D.N_PRESUP
   AND I.IDARTICULO = D.IDSERVICIO
   AND I.IDBODEGA = D.IDBODEGA
   AND I.NOLOTEPEDIDO = D.NOLOTE
  WHERE I.CUEDEBITO = L.CUENTA_HOY
    AND I.CUECREDITO = CASE L.CUENTA_HOY
                         WHEN N'14150502' THEN N'14150591'
                         ELSE N'14200591'
                       END
    AND COALESCE(I.CUENTAIVA, N'') = N''
) <> 9
OR (
  SELECT COUNT(*)
  FROM @L L
  INNER JOIN FCXPD D ON D.CNSFCXP = L.CNSFCXP AND D.ITEM = L.ITEM
  WHERE NOT EXISTS (
    SELECT 1
    FROM IEXI I
    WHERE I.CNSMOV = D.N_PRESUP
      AND I.IDARTICULO = D.IDSERVICIO
      AND I.IDBODEGA = D.IDBODEGA
      AND I.NOLOTEPEDIDO = D.NOLOTE
  )
  AND NOT (
    (L.CNSFCXP = N'03CM001611' AND L.ITEM = 1)
    OR (L.CNSFCXP = N'26CM000477' AND L.ITEM = 4)
  )
) <> 0
BEGIN
  ROLLBACK TRAN;
  THROW 50004, 'El lote de la entrada no esta en excluidos, o falta un lote que si debia estar. No se cambio nada.', 1;
END;

UPDATE D
SET CUENTA_SER = L.CUENTA_OK,
    CUENTA_IVA = N'24080501'
FROM FCXPD D
INNER JOIN @L L ON L.CNSFCXP = D.CNSFCXP AND L.ITEM = D.ITEM
WHERE D.CUENTA_SER = L.CUENTA_HOY
  AND COALESCE(D.CUENTA_IVA, N'') = L.IVA_HOY
  AND COALESCE(D.VLR_IVA, 0) > 0;

UPDATE I
SET CUEDEBITO = L.CUENTA_OK,
    CUECREDITO = L.REV_OK,
    CUENTAIVA = N'24080501'
FROM IEXI I
INNER JOIN FCXPD D
  ON D.N_PRESUP = I.CNSMOV
 AND D.IDSERVICIO = I.IDARTICULO
 AND D.IDBODEGA = I.IDBODEGA
 AND D.NOLOTE = I.NOLOTEPEDIDO
INNER JOIN @L L ON L.CNSFCXP = D.CNSFCXP AND L.ITEM = D.ITEM
WHERE I.CUEDEBITO = L.CUENTA_HOY
  AND I.CUECREDITO = CASE L.CUENTA_HOY
                       WHEN N'14150502' THEN N'14150591'
                       ELSE N'14200591'
                     END
  AND COALESCE(I.CUENTAIVA, N'') = N'';

IF (
  SELECT COUNT(*)
  FROM @L L
  INNER JOIN FCXPD D ON D.CNSFCXP = L.CNSFCXP AND D.ITEM = L.ITEM
  WHERE D.CUENTA_SER = L.CUENTA_OK
    AND COALESCE(D.CUENTA_IVA, N'') = N'24080501'
) <> 11
OR (
  SELECT COUNT(*)
  FROM @L L
  INNER JOIN FCXPD D ON D.CNSFCXP = L.CNSFCXP AND D.ITEM = L.ITEM
  INNER JOIN IEXI I
    ON I.CNSMOV = D.N_PRESUP
   AND I.IDARTICULO = D.IDSERVICIO
   AND I.IDBODEGA = D.IDBODEGA
   AND I.NOLOTEPEDIDO = D.NOLOTE
  WHERE I.CUEDEBITO = L.CUENTA_OK
    AND I.CUECREDITO = L.REV_OK
    AND COALESCE(I.CUENTAIVA, N'') = N'24080501'
) <> 9
OR EXISTS (
  SELECT 1
  FROM FCXP
  WHERE CNSFCXP IN (
      N'03CM001611', N'03CM001809', N'03CM001818',
      N'03CM001991', N'26CM000449', N'26CM000477'
    )
    AND (
      CUECREDITO <> N'22050101'
      OR ESTADO <> N'N'
      OR COALESCE(CONTABILIZADA, 0) <> 0
      OR COALESCE(NROCOMPROBANTE, N'') <> N''
    )
)
BEGIN
  ROLLBACK TRAN;
  THROW 50005, 'La correccion no quedo completa. No se cambio nada.', 1;
END;

COMMIT TRAN;

SELECT P.CNSFCXP, P.NOREFERENCIA, D.ITEM, D.IDSERVICIO,
       CONVERT(decimal(18,2), D.VLR_IVA) AS IVA,
       D.CUENTA_SER, D.CUENTA_IVA
FROM FCXP P
INNER JOIN FCXPD D ON D.CNSFCXP = P.CNSFCXP
INNER JOIN @L L ON L.CNSFCXP = D.CNSFCXP AND L.ITEM = D.ITEM
WHERE D.CUENTA_SER = L.CUENTA_OK
  AND D.CUENTA_IVA = N'24080501'
ORDER BY P.CNSFCXP, D.ITEM;
