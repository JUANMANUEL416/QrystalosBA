CREATE OR ALTER PROCEDURE DBO.SPQ_CEFM_CREA_AUT_DESDE_IMOV
  @CNSMOV   VARCHAR(20),
  @USUARIO  VARCHAR(12),
  @IDSEDE   VARCHAR(5) = NULL,
  @COMPANIA VARCHAR(2) = '01',
  @IDAUT    VARCHAR(20) = NULL OUTPUT,
  @ERROR    VARCHAR(500) = NULL OUTPUT
AS
DECLARE
  @CNSIZSOL VARCHAR(20),
  @FECHACONF DATETIME,
  @IDBODEGA VARCHAR(20),
  @IDAF VARCHAR(20),
  @IDP VARCHAR(6),
  @IDT VARCHAR(20),
  @IDS VARCHAR(5),
  @SYSCOMP VARCHAR(254),
  @CNSCEFM VARCHAR(20),
  @PREF_A VARCHAR(6),
  @CCOSTO_A VARCHAR(20),
  @IDAREA_A VARCHAR(20),
  @DX_A VARCHAR(10),
  @NUMAUT_A VARCHAR(30),
  @FECHAAUTZ DATETIME,
  @VRCOP_A DECIMAL(14,2),
  @MIPRES_A VARCHAR(100),
  @IDMED_A VARCHAR(12),
  @DOCMED_A VARCHAR(20),
  @TIPOAFI_A VARCHAR(2),
  @CLASEC_A VARCHAR(1),
  @PAT_AUT VARCHAR(2),
  @FECHAV_A DATETIME,
  @FECHAFORM_A DATETIME,
  @IDPROV_A VARCHAR(20),
  @CLASEORD_A VARCHAR(20),
  @NOPOS_A BIT,
  @PREF_CEFM VARCHAR(6),
  @PREF_POS VARCHAR(6),
  @PREF_NOPOS VARCHAR(6),
  @FIN_A VARCHAR(2),
  @IDSOL_A VARCHAR(20),
  @NOAUT VARCHAR(20),
  @MIPRES_AUT VARCHAR(100),
  @LINEAS INT,
  @COMPANIA_X VARCHAR(2),
  @IDP_FTR VARCHAR(6),
  @PERIODO_A VARCHAR(10)

BEGIN
  SET NOCOUNT ON
  SET @ERROR = NULL
  SET @IDAUT = NULL
  SET @COMPANIA_X = COALESCE(NULLIF(@COMPANIA, ''), '01')

  IF COALESCE(@CNSMOV, '') = ''
  BEGIN
    SET @ERROR = 'CNSMOV vacío.'
    RETURN
  END

  IF COL_LENGTH('dbo.AUT', 'CNSIMOV') IS NULL
  BEGIN
    SET @ERROR = 'Falta columna AUT.CNSIMOV. Ejecutar CEFM_ALTER_EXISTENTES.sql.'
    RETURN
  END

  /* Solo IMOV confirmado */
  IF NOT EXISTS (
    SELECT 1 FROM IMOV WITH (NOLOCK)
    WHERE CNSMOV = @CNSMOV AND COALESCE(ESTADO, 0) = 1
      AND COALESCE(PROCEDENCIA, '') <> 'DEVOLUCION'
  )
  BEGIN
    SET @ERROR = 'IMOV no confirmado: ' + @CNSMOV
    RETURN
  END

  /* Idempotencia: ya se creó AUT para este IMOV (CNSIMOV, no HCA) */
  IF EXISTS (
    SELECT 1 FROM AUT WITH (NOLOCK)
    WHERE CNSIMOV = @CNSMOV
      AND COALESCE(MANUALCE, 0) = 1
  )
  BEGIN
    SELECT @IDAUT = IDAUT
    FROM AUT WITH (NOLOCK)
    WHERE CNSIMOV = @CNSMOV
      AND COALESCE(MANUALCE, 0) = 1
    EXEC DBO.SPQ_CEFM_LLENA_AUTD_IVA @IDAUT, @CNSMOV
    RETURN
  END

  SELECT
    @CNSIZSOL = M.NODOCUMENTO,
    @FECHACONF = COALESCE(M.FECHACONF, GETDATE()),
    @IDBODEGA = M.IDBODEGA
  FROM IMOV M WITH (NOLOCK)
  WHERE M.CNSMOV = @CNSMOV
  SET @IDS = NULLIF(@IDSEDE, '')

  /* CE de Autorizador: NOADMISION = AUT.IDAUT (MANUALCE=0). No crear otra AUT.
     El IDAUT puede coincidir con AFI.IDAFILIADO de OTRA persona (IZSOL 040000081493:
     AUT 0400002257 = Giraldo; AFI 0400002257 = Bedoya). AFI nunca gana a AUT. */
  IF COALESCE(@CNSIZSOL, '') = ''
     OR NOT EXISTS (
       SELECT 1 FROM IZSOL WITH (NOLOCK)
       WHERE CNSIZSOL = @CNSIZSOL
         AND (
           CLASE IN ('TRANS_CE', 'FORMEDCE')
           OR (CLASE = 'CE'
               AND EXISTS (SELECT 1 FROM AFI A WITH (NOLOCK) WHERE A.IDAFILIADO = IZSOL.NOADMISION)
               AND NOT EXISTS (SELECT 1 FROM AUT A WITH (NOLOCK) WHERE A.IDAUT = IZSOL.NOADMISION))
           OR (CLASE = 'CE' AND EXISTS (
                 SELECT 1 FROM AUT A WITH (NOLOCK)
                 WHERE A.IDAUT = IZSOL.NOADMISION AND COALESCE(A.MANUALCE, 0) = 1))
         )
     )
  BEGIN
    /* No es Transcripciones / Traer de ? no crear AUT (Autorizador ya tiene AUT) */
    SET @ERROR = 'IZSOL no aplica CREA_AUT (CLASE/NOADMISION): ' + COALESCE(@CNSIZSOL, '')
    RETURN
  END

  /* Solo Transcripciones (TRANS_CE) / legado CE sin AUT / CE MANUALCE / FORMEDCE */
  IF NOT EXISTS (
    SELECT 1 FROM IZSOL WITH (NOLOCK)
    WHERE CNSIZSOL = @CNSIZSOL
      AND (
        CLASE IN ('TRANS_CE', 'FORMEDCE')
        OR (CLASE = 'CE'
            AND EXISTS (SELECT 1 FROM AFI A WITH (NOLOCK) WHERE A.IDAFILIADO = IZSOL.NOADMISION)
            AND NOT EXISTS (SELECT 1 FROM AUT A WITH (NOLOCK) WHERE A.IDAUT = IZSOL.NOADMISION))
        OR (CLASE = 'CE' AND EXISTS (
              SELECT 1 FROM AUT A WITH (NOLOCK)
              WHERE A.IDAUT = IZSOL.NOADMISION AND COALESCE(A.MANUALCE, 0) = 1))
      )
  )
    RETURN

  /* TRANS_CE: NOADMISION es IDAFILIADO. Ese número puede ser AUT.IDAUT de
     OTRA persona (0300035796 = AFI Adriana Estrada y AUT Gloria Sepúlveda).
     En transcripción manda CEFM. En CE de Autorizador sigue ganando AUT. */
  SELECT
    @IDAF = CASE
              WHEN Z.CLASE = 'TRANS_CE' THEN COALESCE(
                (SELECT TOP 1 C.IDAFILIADO
                 FROM AUTE E WITH (NOLOCK)
                 INNER JOIN CEFM C WITH (NOLOCK) ON C.CNSCEFM = E.CNSCEFM
                 WHERE E.CNSIZSOL = Z.CNSIZSOL
                   AND COALESCE(C.ESTADO, '') <> 'ANULADO'
                   AND COALESCE(C.IDAFILIADO, '') <> ''
                 ORDER BY E.FECHA),
                (SELECT A.IDAFILIADO FROM AFI A WITH (NOLOCK) WHERE A.IDAFILIADO = Z.NOADMISION)
              )
              WHEN EXISTS (SELECT 1 FROM AUT WITH (NOLOCK) WHERE IDAUT = Z.NOADMISION)
                THEN (SELECT TOP 1 IDAFILIADO FROM AUT WITH (NOLOCK) WHERE IDAUT = Z.NOADMISION)
              WHEN EXISTS (SELECT 1 FROM AFI WITH (NOLOCK) WHERE IDAFILIADO = Z.NOADMISION)
                THEN Z.NOADMISION
              ELSE NULL
            END,
    @IDP = Z.IDPLAN,
    @IDT = COALESCE(NULLIF(Z.IDTERCEROC, ''), '0100000011'),
    @IDS = COALESCE(NULLIF(Z.IDSEDE, ''), @IDSEDE, @IDS)
  FROM IZSOL Z WITH (NOLOCK)
  WHERE Z.CNSIZSOL = @CNSIZSOL

  /* Contexto CEFM (si existe) */
  SET @CNSCEFM = NULL
  IF COL_LENGTH('dbo.AUTE', 'CNSIZSOL') IS NOT NULL
    SELECT TOP 1 @CNSCEFM = NULLIF(AE.CNSCEFM, '')
    FROM AUTE AE WITH (NOLOCK)
    WHERE AE.CNSIZSOL = @CNSIZSOL
    ORDER BY AE.FECHA

  IF COALESCE(@CNSCEFM, '') = ''
    SELECT TOP 1 @CNSCEFM = C.CNSCEFM
    FROM CEFM C WITH (NOLOCK)
    WHERE C.IDAFILIADO = @IDAF
      AND C.ESTADO = 'AUDITADO'
      AND EXISTS (
        SELECT 1 FROM AUTE AE WITH (NOLOCK)
        WHERE AE.CNSCEFM = C.CNSCEFM AND AE.CNSIZSOL = @CNSIZSOL
      )
    ORDER BY C.FECHAAUD DESC

  IF COALESCE(@CNSCEFM, '') <> ''
  BEGIN
    SELECT
      @NOPOS_A     = COALESCE(C.NOPOS, 0),
      @PREF_CEFM   = NULLIF(LTRIM(RTRIM(C.PREFIJO)), ''),
      @CCOSTO_A    = C.CCOSTO,
      @IDAREA_A    = C.IDAREA,
      @DX_A        = C.DXPPAL,
      @NUMAUT_A    = C.NUMAUTORIZA,
      @FECHAAUTZ   = DBO.FNK_CEFM_FECHA_AUT(C.NUMAUTORIZA, C.FECHAAUTORIZA),
      @VRCOP_A     = COALESCE(C.VALORCOPAGO, 0),
      @MIPRES_A    = C.IDMIPRESS,
      @IDMED_A     = C.IDMEDICOSOLICITA,
      @DOCMED_A    = NULLIF(C.DOCMEDICO, ''),
      @TIPOAFI_A   = C.TIPOAFILIADO,
      @CLASEC_A    = C.CLASECONTRATO,
      @FECHAFORM_A = COALESCE(C.FECHA_FORMULA, C.FECHA),
      @IDP         = COALESCE(NULLIF(@IDP, ''), C.IDPLAN),
      @IDAF        = CASE
                       WHEN EXISTS (
                         SELECT 1 FROM IZSOL Z WITH (NOLOCK)
                         WHERE Z.CNSIZSOL = @CNSIZSOL AND Z.CLASE = 'TRANS_CE'
                       ) THEN C.IDAFILIADO
                       ELSE COALESCE(@IDAF, C.IDAFILIADO)
                     END,
      @IDS         = COALESCE(NULLIF(@IDS, ''), C.IDSEDE)
    FROM CEFM C WITH (NOLOCK)
    WHERE C.CNSCEFM = @CNSCEFM
  END

  SET @NUMAUT_A = NULLIF(LTRIM(RTRIM(@NUMAUT_A)), '')

  IF COALESCE(@IDAF, '') = ''
  BEGIN
    SET @ERROR = 'No se resolvió afiliado para IMOV ' + @CNSMOV
    RETURN
  END

  /* Plan AUT = plan del afiliado (Autorizador lista por coincidencia con AFI.IDPLAN en la práctica).
     CEFM/IZSOL pueden traer otro plan (p. ej. NPBS26); el valor ESP se resuelve aparte (relajado). */
  DECLARE @IDP_AFI VARCHAR(20) = NULL
  SELECT @IDP_AFI = AFI.IDPLAN
  FROM AFI WITH (NOLOCK)
  WHERE AFI.IDAFILIADO = @IDAF

  /* Tercero de tarifas CE / ESP */
  SET @IDT = '0100000011'

  IF COALESCE(@IDP_AFI, '') <> ''
    SET @IDP = @IDP_AFI

  SET @CLASEORD_A = 'Normal'
  SET @FIN_A = DBO.FNK_CEFM_FINALIDAD_DX()
  IF COALESCE(@TIPOAFI_A, '') = '' OR COALESCE(@IDP, '') = ''
  BEGIN
    SELECT
      @TIPOAFI_A = COALESCE(NULLIF(@TIPOAFI_A, ''), DBO.FNK_CEFM_TIPOAFILIADO(AFI.TIPOAFILIADO, AFI.TIPOUSUARIO)),
      @IDP = COALESCE(NULLIF(@IDP, ''),
        CASE WHEN AFI.IDADMINISTRADORA = '0100000011' THEN AFI.IDPLAN ELSE NULL END)
    FROM AFI WITH (NOLOCK)
    WHERE AFI.IDAFILIADO = @IDAF
  END

  SELECT @SYSCOMP = SYS_ComputerName, @IDSOL_A = COALESCE(NULLIF(IDMEDICO, ''), USUARIO)
  FROM USUSU WITH (NOLOCK)
  WHERE USUARIO = @USUARIO

  IF COALESCE(@CCOSTO_A, '') = '' OR COALESCE(@IDAREA_A, '') = ''
    SELECT
      @CCOSTO_A = COALESCE(NULLIF(@CCOSTO_A, ''), UBEQ.CCOSTO),
      @IDAREA_A = COALESCE(NULLIF(@IDAREA_A, ''), UBEQ.IDAREA),
      @IDS = COALESCE(NULLIF(@IDS, ''), UBEQ.IDSEDE)
    FROM USUSU WITH (NOLOCK)
    LEFT JOIN UBEQ WITH (NOLOCK) ON UBEQ.SYS_ComputerName = USUSU.SYS_ComputerName
    WHERE USUSU.USUARIO = @USUARIO

  IF COALESCE(@IDS, '') = ''
    SELECT @IDS = NULLIF(RTRIM(IDSEDE), '')
    FROM IZSOL WITH (NOLOCK)
    WHERE CNSIZSOL = @CNSIZSOL

  /* Médico solicitante (misma lógica que SPQ_CEFM AUDITAR):
       1) MED por IDMEDICO = DOCMEDICO / IDMEDICOSOLICITA
       2) CEFMMED / DOCMEDICO de la transcripción (aunque no esté en MED)
       3) USUSU.IDMEDICO solo si existe en MED
     Autorizador lista NOMBRE vía subquery MED o CEFMMED (no INNER JOIN). */
  SET @IDSOL_A = NULL
  IF COALESCE(@DOCMED_A, '') <> '' AND EXISTS (SELECT 1 FROM MED WITH (NOLOCK) WHERE IDMEDICO = LEFT(@DOCMED_A, 20))
  BEGIN
    SET @IDSOL_A = LEFT(@DOCMED_A, 20)
    SET @IDMED_A = COALESCE(NULLIF(@IDMED_A, ''), LEFT(@DOCMED_A, 12))
  END
  ELSE IF COALESCE(@IDMED_A, '') <> '' AND EXISTS (SELECT 1 FROM MED WITH (NOLOCK) WHERE IDMEDICO = LEFT(@IDMED_A, 20))
  BEGIN
    SET @IDSOL_A = LEFT(@IDMED_A, 20)
  END
  ELSE IF COALESCE(@DOCMED_A, '') <> ''
  BEGIN
    /* Transcripción CE: DOCMEDICO es la cédula en CEFMMED */
    SET @IDSOL_A = LEFT(@DOCMED_A, 20)
    SET @IDMED_A = COALESCE(NULLIF(@IDMED_A, ''), LEFT(@DOCMED_A, 12))
  END
  ELSE
  BEGIN
    SELECT @IDSOL_A = NULLIF(IDMEDICO, '') FROM USUSU WITH (NOLOCK) WHERE USUARIO = @USUARIO
    IF COALESCE(@IDSOL_A, '') <> '' AND NOT EXISTS (SELECT 1 FROM MED WITH (NOLOCK) WHERE IDMEDICO = @IDSOL_A)
      SET @IDSOL_A = NULL
  END

  SET @PAT_AUT = NULL
  IF OBJECT_ID('dbo.CEFMMED', 'U') IS NOT NULL AND COALESCE(@DOCMED_A, '') <> ''
    SELECT TOP 1 @PAT_AUT = DBO.FNK_CEFM_PERSONAL_AT(ESPECIALIDAD)
    FROM CEFMMED WITH (NOLOCK)
    WHERE IDMEDICO = @DOCMED_A

  /* Si cualquier transcripción del pedido es NOPOS, la AUT es NOPOS (bodega 052 / MIPRES). */
  SET @NOPOS_A = COALESCE(@NOPOS_A, 0)
  IF COALESCE(@CNSIZSOL, '') <> '' AND COL_LENGTH('dbo.AUTE', 'CNSIZSOL') IS NOT NULL
     AND EXISTS (
       SELECT 1
       FROM AUTE AE WITH (NOLOCK)
       INNER JOIN CEFM C WITH (NOLOCK) ON C.CNSCEFM = AE.CNSCEFM
       WHERE AE.CNSIZSOL = @CNSIZSOL
         AND COALESCE(C.NOPOS, 0) = 1
     )
  BEGIN
    SET @NOPOS_A = 1
    IF COALESCE(@MIPRES_A, '') = ''
      SELECT TOP 1 @MIPRES_A = NULLIF(C.IDMIPRESS, '')
      FROM AUTE AE WITH (NOLOCK)
      INNER JOIN CEFM C WITH (NOLOCK) ON C.CNSCEFM = AE.CNSCEFM
      WHERE AE.CNSIZSOL = @CNSIZSOL
        AND COALESCE(C.NOPOS, 0) = 1
        AND COALESCE(C.IDMIPRESS, '') <> ''
      ORDER BY AE.FECHA
    IF COALESCE(@PREF_CEFM, '') = ''
      SELECT TOP 1 @PREF_CEFM = NULLIF(LTRIM(RTRIM(C.PREFIJO)), '')
      FROM AUTE AE WITH (NOLOCK)
      INNER JOIN CEFM C WITH (NOLOCK) ON C.CNSCEFM = AE.CNSCEFM
      WHERE AE.CNSIZSOL = @CNSIZSOL
        AND COALESCE(C.NOPOS, 0) = 1
        AND COALESCE(C.PREFIJO, '') <> ''
      ORDER BY AE.FECHA
  END

  SET @PREF_POS = LEFT(NULLIF(LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('PREFIJOMEDICAMENTOS'))), ''), 6)
  SET @PREF_NOPOS = LEFT(NULLIF(LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('PREFIJOMEDNOPOS'))), ''), 6)
  IF COALESCE(@PREF_NOPOS, '') = ''
    SET @PREF_NOPOS = LEFT(NULLIF(LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('PREF_MED_NOPOS'))), ''), 6)

  IF @NOPOS_A = 1
  BEGIN
    /* NOPOS: variable de sistema. Nunca SER.PREFIJO POS (Autorizador INNER JOIN PRE). */
    SET @PREF_A = NULLIF(@PREF_NOPOS, '')
    IF COALESCE(@PREF_A, '') = '' OR NOT EXISTS (SELECT 1 FROM PRE WITH (NOLOCK) WHERE PREFIJO = @PREF_A)
    BEGIN
      IF COALESCE(@PREF_CEFM, '') <> ''
         AND @PREF_CEFM <> COALESCE(@PREF_POS, '')
         AND EXISTS (SELECT 1 FROM PRE WITH (NOLOCK) WHERE PREFIJO = @PREF_CEFM)
        SET @PREF_A = @PREF_CEFM
    END
    IF COALESCE(@PREF_A, '') = '' OR NOT EXISTS (SELECT 1 FROM PRE WITH (NOLOCK) WHERE PREFIJO = @PREF_A)
    BEGIN
      SELECT TOP 1 @PREF_A = LEFT(NULLIF(LTRIM(RTRIM(REPLACE(P.value, '''', ''))), ''), 6)
      FROM STRING_SPLIT(COALESCE(DBO.FNK_VALORVARIABLE('PREFIJOSMEDNOPOS'), ''), ',') P
      INNER JOIN PRE WITH (NOLOCK)
        ON PRE.PREFIJO = LEFT(LTRIM(RTRIM(REPLACE(P.value, '''', ''))), 6)
      WHERE NULLIF(LTRIM(RTRIM(REPLACE(P.value, '''', ''))), '') IS NOT NULL
        AND LEFT(LTRIM(RTRIM(REPLACE(P.value, '''', ''))), 6) <> COALESCE(@PREF_POS, '')
    END
    IF COALESCE(@PREF_A, '') = '' OR @PREF_A = COALESCE(@PREF_POS, '')
      SET @PREF_A = COALESCE(@PREF_NOPOS, NULLIF(@PREF_CEFM, ''))
  END
  ELSE
  BEGIN
    SET @PREF_A = @PREF_POS
    /* Fallback POS: prefijo del servicio papá (evita AUT invisible por INNER JOIN PRE). */
    IF COALESCE(@PREF_A, '') = '' OR NOT EXISTS (SELECT 1 FROM PRE WITH (NOLOCK) WHERE PREFIJO = @PREF_A)
    BEGIN
      SELECT TOP 1 @PREF_A = NULLIF(LTRIM(RTRIM(S.PREFIJO)), '')
      FROM IMOVH H WITH (NOLOCK)
      LEFT JOIN IART IA WITH (NOLOCK) ON IA.IDARTICULO = H.IDARTICULO
      LEFT JOIN SER S WITH (NOLOCK) ON S.IDSERVICIO = COALESCE(NULLIF(IA.IDSERVICIO, ''), H.IDARTICULO)
      WHERE H.CNSMOV = @CNSMOV
        AND COALESCE(H.CANTIDAD, 0) > 0
        AND COALESCE(S.PREFIJO, '') <> ''
      ORDER BY H.IDARTICULO
    END
  END

  SELECT @IDPROV_A = COALESCE(@IDT, IDPROVEEDORDEF) FROM PRE WITH (NOLOCK) WHERE PREFIJO = @PREF_A
  SET @IDPROV_A = COALESCE(@IDT, @IDPROV_A)
  SET @IDP_FTR = CASE
    WHEN COALESCE(@IDP, '') IN ('NPBC26', 'CSRC26', 'AUTCON') THEN 'CSRC26'
    WHEN COALESCE(@IDP, '') IN ('NPBS26', 'CSRS26', 'AUTSUB') THEN 'CSRS26'
    ELSE @IDP
  END
  IF COALESCE(@IDP_FTR, '') NOT IN ('CSRC26', 'CSRS26')
  BEGIN
    SELECT @IDP_FTR = CASE
      WHEN PLN.DESCPLAN LIKE '%CONTRIB%' THEN 'CSRC26'
      WHEN PLN.DESCPLAN LIKE '%SUBSID%' THEN 'CSRS26'
      ELSE COALESCE(@IDP_FTR, @IDP)
    END
    FROM PLN WITH (NOLOCK)
    WHERE PLN.IDPLAN = COALESCE(@IDP, @IDP_FTR)
  END
  SET @PERIODO_A = NULL
  IF COL_LENGTH('dbo.AUTE', 'CNSIZSOL') IS NOT NULL
    SELECT TOP 1 @PERIODO_A = NULLIF(RTRIM(AE.PERIODO), '')
    FROM AUTE AE WITH (NOLOCK)
    WHERE AE.CNSIZSOL = @CNSIZSOL
      AND (AE.PERIODO LIKE '1/%' OR AE.PERIODO = '1')
    ORDER BY AE.FECHA
  SET @FECHAV_A = DATEADD(DAY, 30, @FECHACONF)
  SET @FECHAFORM_A = COALESCE(@FECHAFORM_A, @FECHACONF)

  /* Detalle desde IMOVH: una AUTD por SKU dispensado (no por papá SER).
     FTRMAut cobra AUTD.IDSERVICIO. Índice único AUTDIDSERVICIO (IDSERVICIO, IDAUT).
     Varios lotes del mismo SKU se suman. */
  IF OBJECT_ID('tempdb..#AUT_IMOV_DET') IS NOT NULL DROP TABLE #AUT_IMOV_DET
  SELECT
    H.IDARTICULO AS IDSERVICIO,
    H.IDARTICULO AS IDARTICULO,
    CAST(SUM(COALESCE(NULLIF(H.CANTIDAD, 0), NULLIF(H.CANTPEDIDA, 0), 0)) AS DECIMAL(18, 2)) AS CANTIDAD
  INTO #AUT_IMOV_DET
  FROM IMOVH H WITH (NOLOCK)
  WHERE H.CNSMOV = @CNSMOV
    AND COALESCE(H.ESTADO, 0) <> 99
    AND COALESCE(NULLIF(RTRIM(H.IDARTICULO), ''), '') <> ''
  GROUP BY H.IDARTICULO
  HAVING SUM(COALESCE(NULLIF(H.CANTIDAD, 0), NULLIF(H.CANTPEDIDA, 0), 0)) > 0

  SELECT @LINEAS = COUNT(*) FROM #AUT_IMOV_DET
  IF COALESCE(@LINEAS, 0) = 0
  BEGIN
    SET @ERROR = 'IMOV sin líneas dispensadas: ' + @CNSMOV
    RETURN
  END

  /* SER mínimo: FTRMAut legado hace INNER JOIN SER. El front ya usa LEFT JOIN. */
  BEGIN TRY
    INSERT INTO SER (
      IDSERVICIO, PREFIJO, DESCSERVICIO, IDARTICULO, ESTADO, IVA, POS, NIVELATENCION
    )
    SELECT
      D.IDARTICULO,
      SP.PREFIJO,
      LEFT(COALESCE(IA.DESCRIPCION, SP.DESCSERVICIO, D.IDARTICULO), 255),
      D.IDARTICULO,
      'Activo',
      COALESCE(SP.IVA, 'No'),
      COALESCE(SP.POS, 0),
      COALESCE(SP.NIVELATENCION, '1')
    FROM #AUT_IMOV_DET D
    INNER JOIN IART IA WITH (NOLOCK) ON IA.IDARTICULO = D.IDARTICULO
    INNER JOIN SER SP WITH (NOLOCK) ON SP.IDSERVICIO = IA.IDSERVICIO
    WHERE NOT EXISTS (
      SELECT 1 FROM SER S WITH (NOLOCK) WHERE S.IDSERVICIO = D.IDARTICULO
    )
  END TRY
  BEGIN CATCH
    PRINT 'SPQ_CEFM_CREA_AUT_DESDE_IMOV SER: ' + ERROR_MESSAGE()
  END CATCH

  /* Consecutivos AUT */
  BEGIN TRY
    EXEC DBO.SPQ_GENSEQUENCE @SEDE = @IDS, @PREFIJO = '@AUTF', @LONGITUD = 8, @NVOCONSEC = @NOAUT OUTPUT
  END TRY
  BEGIN CATCH
    SET @NOAUT = NULL
  END CATCH
  IF COALESCE(@NOAUT, '') = ''
  BEGIN
    BEGIN TRY
      EXEC SPK_GENCONSECUTIVO @COMPANIA_X, @IDS, '@AUTF', @NOAUT OUTPUT
    END TRY
    BEGIN CATCH
      SET @NOAUT = NULL
    END CATCH
  END

  BEGIN TRY
    EXEC DBO.SPQ_GENSEQUENCE @SEDE = @IDS, @PREFIJO = '@AUT', @LONGITUD = 8, @NVOCONSEC = @IDAUT OUTPUT
  END TRY
  BEGIN CATCH
    SET @IDAUT = NULL
  END CATCH
  IF COALESCE(@IDAUT, '') = ''
  BEGIN
    BEGIN TRY
      EXEC SPK_GENCONSECUTIVO @COMPANIA_X, @IDS, '@AUT', @IDAUT OUTPUT
    END TRY
    BEGIN CATCH
      SET @IDAUT = NULL
    END CATCH
  END

  IF COALESCE(@IDAUT, '') = '' OR COALESCE(@NOAUT, '') = ''
  BEGIN
    SET @ERROR = 'No se pudo generar consecutivo AUT/AUTF.'
    RETURN
  END

  BEGIN TRY
    INSERT INTO AUT (
      IDAUT, NOAUT, FECHA, FECHAVENCE, FECHASOL, IDAFILIADO, NUMCARNET, IDPLAN,
      PREFIJO, IDSEDE, IDSEDEORIGEN, TIPOAUTORIZACION, ALTOCOSTO, ATENCION, URGENCIA, IMPUTABLE_A,
      IDSOLICITANTE, IDPROVEEDOR, ESTADO,
      VALORTOTAL, VALORCOPAGO, VALORBENEFICIO, VALOREXEDENTE, VALORTOTALCOSTO, VALORCOPAGOCOSTO, IMPRESO,
      AUTORIZADOPOR, NUMAUTORIZA, FECHAAUTORIZA, AUTORIZADO,
      USUARIO, DXPPAL, CLASEORDEN, GENEROCAJA, IDCONTRATANTE,
      TIPOCOPAGO, PEDIDOINV, IDCLASEAUT, CLASECONT, ESDEINV, FECHAGEN,
      IDAREA, CCOSTO, NIVELATENCION, FACTURADA, FACTURABLE,
      CLASECONTRATO, COPAGOPROPIO, IDTERCEROCA, CONSECUTIVOHCA,
      TIPOCAJA, SYS_COMPUTERNAME, TIPOUSUARIO,
      CERRADA, CONTABILIZADA, IDPLAN_AFI, IDTERCERO_AFI,
      IDMEDICOSOLICITA, TIPOAFILIADO, MENTREGA, AMBITO, PERSONAL_AT,
      FINALIDAD, IDCAUSAEXT, CNSMOV
    )
    VALUES (
      @IDAUT, @NOAUT, @FECHACONF, @FECHAV_A, @FECHACONF,
      @IDAF, '', COALESCE(@IDP_FTR, @IDP),
      @PREF_A, @IDS, @IDS, 'Previa', 'No', 'Ambulatoria', 0, 'Administradora',
      @IDSOL_A, @IDT, 'Pendiente',
      0, COALESCE(@VRCOP_A, 0), 0, 0, 0, 0, 0,
      @USUARIO, @NUMAUT_A, @FECHAAUTZ, 0,
      @USUARIO, @DX_A, @CLASEORD_A, 0, @IDT,
      CASE WHEN COALESCE(@VRCOP_A, 0) > 0 THEN 'C' ELSE 'N' END,
      1, 'CE', 'ENGE', 1, GETDATE(),
      @IDAREA_A, @CCOSTO_A, '1', 0, 1,
      @CLASEC_A, 0, @IDT, NULL,  /* CONSECUTIVOHCA: solo HCA clínica; IMOV va en CNSIMOV */
      NULL, @SYSCOMP, 'I',
      0, 0, COALESCE(@IDP_AFI, @IDP), @IDT,
      @IDMED_A, @TIPOAFI_A, 'Institucional', '1', @PAT_AUT,
      @FIN_A, '13', @CNSIZSOL
    )
  END TRY
  BEGIN CATCH
    SET @ERROR = 'INSERT AUT: ' + ERROR_MESSAGE()
    SET @IDAUT = NULL
    RETURN
  END CATCH

  SET @MIPRES_AUT = NULLIF(LTRIM(RTRIM(@MIPRES_A)), '')
  /* AUT.IDMIPRESS suele ser VARCHAR(20); no cortar de más si la columna es mayor */
  IF COL_LENGTH('dbo.AUT', 'IDMIPRESS') IS NOT NULL AND @MIPRES_AUT IS NOT NULL
    SET @MIPRES_AUT = LEFT(@MIPRES_AUT, COL_LENGTH('dbo.AUT', 'IDMIPRESS'))

  IF COL_LENGTH('dbo.AUT', 'NOPOS') IS NOT NULL
    EXEC sp_executesql N'UPDATE AUT SET NOPOS = @N WHERE IDAUT = @I',
      N'@N BIT, @I VARCHAR(20)', @NOPOS_A, @IDAUT

  IF COL_LENGTH('dbo.AUT', 'IDMIPRESS') IS NOT NULL
  BEGIN
    IF @MIPRES_AUT IS NOT NULL
      EXEC sp_executesql N'UPDATE AUT SET IDMIPRESS = @M WHERE IDAUT = @I',
        N'@M VARCHAR(100), @I VARCHAR(20)', @MIPRES_AUT, @IDAUT
    ELSE IF COALESCE(@NOPOS_A, 0) = 1
      EXEC sp_executesql N'UPDATE AUT SET IDMIPRESS = NULL WHERE IDAUT = @I',
        N'@I VARCHAR(20)', @IDAUT
  END
  IF COL_LENGTH('dbo.AUT', 'MANUALCE') IS NOT NULL
    EXEC sp_executesql N'UPDATE AUT SET MANUALCE = 1 WHERE IDAUT = @I',
      N'@I VARCHAR(20)', @IDAUT
  /* CNSIMOV = salida IMOV (idempotencia Transcripciones CE; no tocar CONSECUTIVOHCA) */
  EXEC sp_executesql N'UPDATE AUT SET CNSIMOV = @M WHERE IDAUT = @I',
    N'@M VARCHAR(20), @I VARCHAR(20)', @CNSMOV, @IDAUT
  IF COL_LENGTH('dbo.AUT', 'FECHA_FORMULA') IS NOT NULL AND @FECHAFORM_A IS NOT NULL
    EXEC sp_executesql N'UPDATE AUT SET FECHA_FORMULA = @F WHERE IDAUT = @I',
      N'@F DATETIME, @I VARCHAR(20)', @FECHAFORM_A, @IDAUT
  IF COL_LENGTH('dbo.AUT', 'PERIODO_DISPENSA') IS NOT NULL AND COALESCE(@PERIODO_A, '') <> ''
    EXEC sp_executesql N'UPDATE AUT SET PERIODO_DISPENSA = @P WHERE IDAUT = @I',
      N'@P VARCHAR(10), @I VARCHAR(20)', @PERIODO_A, @IDAUT
  IF COL_LENGTH('dbo.AUT', 'ENTREGADO') IS NOT NULL
    EXEC sp_executesql N'UPDATE AUT SET ENTREGADO = 1 WHERE IDAUT = @I',
      N'@I VARCHAR(20)', @IDAUT
  IF COL_LENGTH('dbo.AUT', 'FENTREGA') IS NOT NULL
    EXEC sp_executesql N'UPDATE AUT SET FENTREGA = @F WHERE IDAUT = @I',
      N'@F DATETIME, @I VARCHAR(20)', @FECHACONF, @IDAUT

  BEGIN TRY
    INSERT INTO AUTD (
      IDAUT, NO_ITEM, IDSERVICIO, CANTIDAD,
      VALOR, VALORCOPAGO, VALORCOPAGOCOSTO, VALOREXCEDENTE, VALORTOTALCOSTO,
      IDPLAN, IMPRESO, AUTORIZADO, COMENTARIOS, PCOBERTURA,
      IDTERCEROCA, MDOSIFICACION, CANTIDIA, DIAS, FRECUENCIA, POSOLOGIA, PRIORIDAD, IDARTICULO,
      CCOSTO, SYS_COMPUTERNAME
    )
    SELECT
      @IDAUT,
      ROW_NUMBER() OVER (ORDER BY D.IDSERVICIO, D.IDARTICULO),
      D.IDSERVICIO,
      D.CANTIDAD,
      0, 0, 0, 0, 0,
      COALESCE(@IDP_FTR, @IDP), 0, 1,
      'Dispensado IMOV ' + @CNSMOV,
      100, @IDT, 1,
      CAST(D.CANTIDAD AS INT), 0, 0, NULL, 0,
      D.IDARTICULO,
      @CCOSTO_A,
      @SYSCOMP
    FROM #AUT_IMOV_DET D
  END TRY
  BEGIN CATCH
    DELETE FROM AUTD WHERE IDAUT = @IDAUT
    DELETE FROM AUT WHERE IDAUT = @IDAUT
    SET @ERROR = 'INSERT AUTD: ' + ERROR_MESSAGE()
    SET @IDAUT = NULL
    RETURN
  END CATCH

  IF COL_LENGTH('dbo.AUTD', 'NOAUTORIZEXT') IS NOT NULL AND COALESCE(@NUMAUT_A, '') <> ''
    UPDATE AUTD SET NOAUTORIZEXT = LEFT(@NUMAUT_A, 30) WHERE IDAUT = @IDAUT
  IF COL_LENGTH('dbo.AUTD', 'FACTURADA') IS NOT NULL
    UPDATE AUTD SET FACTURADA = 0 WHERE IDAUT = @IDAUT AND FACTURADA IS NULL

  EXEC DBO.SPQ_CEFM_LLENA_AUTD_IVA @IDAUT, @CNSMOV

  /* Liquidación unitaria vía SPK_COPAGO_AUT_CEHOSP (FNK_VLRAUTORIZACION) */
  BEGIN TRY
    DECLARE @NO_ITEM_R SMALLINT, @IDSER_R VARCHAR(20), @VAL_R DECIMAL(14,2)
    DECLARE @FECHA_R DATETIME, @IDAREA_R VARCHAR(20), @SYS_R VARCHAR(254)
    DECLARE @SEDE_R VARCHAR(5), @IDAF_R VARCHAR(20)
    DECLARE @PYP_R SMALLINT = 0, @AC_R SMALLINT = 0
    DECLARE @VRTOTCOPAGO DECIMAL(14,2)

    SELECT
      @FECHA_R = FECHA,
      @IDAREA_R = COALESCE(NULLIF(IDAREA, ''), @IDAREA_A),
      @IDAF_R = IDAFILIADO,
      @SEDE_R = IDSEDE,
      @PYP_R = CASE WHEN CLASEORDEN = 'PyP' THEN 1 ELSE 0 END,
      @AC_R = CASE WHEN ALTOCOSTO = 'Si' THEN 1 ELSE 0 END
    FROM AUT WITH (NOLOCK)
    WHERE IDAUT = @IDAUT

    SET @SYS_R = NULLIF(@SYSCOMP, '')
    IF COALESCE(@SYS_R, '') = ''
      SELECT @SYS_R = SYS_ComputerName FROM USUSU WITH (NOLOCK) WHERE USUARIO = @USUARIO
    IF COALESCE(@SEDE_R, '') = '' SET @SEDE_R = COALESCE(NULLIF(@IDS, ''), '01')

    DECLARE c_liq CURSOR LOCAL FAST_FORWARD FOR
      SELECT NO_ITEM, IDSERVICIO, COALESCE(VALOR, 0)
      FROM AUTD WITH (NOLOCK)
      WHERE IDAUT = @IDAUT
      ORDER BY NO_ITEM
    OPEN c_liq
    FETCH NEXT FROM c_liq INTO @NO_ITEM_R, @IDSER_R, @VAL_R
    WHILE @@FETCH_STATUS = 0
    BEGIN
      SELECT @IDAREA_R = COALESCE(CEN.IDAREA, @IDAREA_R)
      FROM AUTD WITH (NOLOCK)
      LEFT JOIN CEN WITH (NOLOCK) ON CEN.CCOSTO = AUTD.CCOSTO
      WHERE AUTD.IDAUT = @IDAUT AND AUTD.NO_ITEM = @NO_ITEM_R

      EXEC DBO.SPK_COPAGO_AUT_CEHOSP
        @IDAF_R, @IDAUT, @NO_ITEM_R, @IDSER_R,
        @PYP_R, @AC_R, @VAL_R,
        'CE', @SYS_R, @COMPANIA_X, @SEDE_R, @USUARIO,
        NULL, @IDAREA_R, @FECHA_R, 0, 0

      FETCH NEXT FROM c_liq INTO @NO_ITEM_R, @IDSER_R, @VAL_R
    END
    CLOSE c_liq
    DEALLOCATE c_liq

    IF COALESCE((SELECT COPAGOPROPIO FROM AUT WITH (NOLOCK) WHERE IDAUT = @IDAUT), 0) = 0
    BEGIN
      IF COALESCE(@VRCOP_A, 0) > 0
        UPDATE AUT SET VALORCOPAGO = @VRCOP_A, TIPOCOPAGO = 'C' WHERE IDAUT = @IDAUT
      ELSE IF (SELECT SUM(COALESCE(VALORCOPAGO, 0)) FROM AUTD WITH (NOLOCK) WHERE IDAUT = @IDAUT) > 0
      BEGIN
        SELECT @VRTOTCOPAGO = SUM(COALESCE(VALORCOPAGO, 0)) FROM AUTD WITH (NOLOCK) WHERE IDAUT = @IDAUT
        UPDATE AUT SET VALORCOPAGO = @VRTOTCOPAGO, TIPOCOPAGO = 'C' WHERE IDAUT = @IDAUT
      END
      ELSE
        UPDATE AUT SET VALORCOPAGO = 0, TIPOCOPAGO = 'N' WHERE IDAUT = @IDAUT
    END
  END TRY
  BEGIN CATCH
    IF CURSOR_STATUS('local', 'c_liq') >= 0
    BEGIN
      CLOSE c_liq
      DEALLOCATE c_liq
    END
    /* AUT queda creada; valor puede quedar en 0 — no rollback de dispensación */
    PRINT 'SPQ_CEFM_CREA_AUT_DESDE_IMOV liquidación: ' + ERROR_MESSAGE()
  END CATCH

  UPDATE AUT
  SET NO_ITEMES = (SELECT COUNT(*) FROM AUTD WHERE IDAUT = @IDAUT),
      VALORTOTAL = COALESCE((SELECT SUM(COALESCE(CANTIDAD, 0) * COALESCE(VALOR, 0)) FROM AUTD WHERE IDAUT = @IDAUT), 0),
      DESCUENTO = COALESCE(DESCUENTO, 0)
  WHERE IDAUT = @IDAUT

  /* Primera AUT ? CEFM.IDAUT; AUTE del periodo ligado al CNSIZSOL */
  IF COALESCE(@CNSCEFM, '') <> '' AND COL_LENGTH('dbo.CEFM', 'IDAUT') IS NOT NULL
  BEGIN
    IF EXISTS (SELECT 1 FROM CEFM WITH (NOLOCK) WHERE CNSCEFM = @CNSCEFM AND COALESCE(IDAUT, '') = '')
      EXEC sp_executesql N'UPDATE CEFM SET IDAUT = @A WHERE CNSCEFM = @C AND COALESCE(IDAUT, '''') = ''''',
        N'@A VARCHAR(20), @C VARCHAR(20)', @IDAUT, @CNSCEFM
  END

  IF COL_LENGTH('dbo.AUTE', 'CNSIZSOL') IS NOT NULL
  BEGIN
    UPDATE AUTE
    SET IDAUT = COALESCE(NULLIF(IDAUT, ''), @IDAUT),
        ESTADO = CASE
                   WHEN (PERIODO LIKE '1/%' OR PERIODO = '1') THEN 'Dispensado'
                   ELSE ESTADO
                 END
    WHERE CNSIZSOL = @CNSIZSOL
      AND (PERIODO LIKE '1/%' OR PERIODO = '1' OR IDAUT IS NULL OR IDAUT = '')
  END

  /* Legado CE (NOADMISION = IDAFILIADO, sin AUT). TRANS_CE: no tocar.
     Si NOADMISION ya es AUT.IDAUT, no pisar: ese número puede ser el
     IDAFILIADO de otra persona (0400002257 AUT Giraldo vs AFI Bedoya). */
  IF EXISTS (
    SELECT 1 FROM IZSOL Z WITH (NOLOCK)
    WHERE Z.CNSIZSOL = @CNSIZSOL
      AND Z.CLASE = 'CE'
      AND EXISTS (SELECT 1 FROM AFI A WITH (NOLOCK) WHERE A.IDAFILIADO = Z.NOADMISION)
      AND NOT EXISTS (SELECT 1 FROM AUT A WITH (NOLOCK) WHERE A.IDAUT = Z.NOADMISION)
      AND Z.NOADMISION <> @IDAUT
  )
    UPDATE IZSOL SET NOADMISION = @IDAUT WHERE CNSIZSOL = @CNSIZSOL AND CLASE = 'CE'

  /* Si el copago/FNK no liquidó: 1) FNK  2) ESP estricto  3) ESP relajado */
  IF EXISTS (SELECT 1 FROM AUTD WITH (NOLOCK) WHERE IDAUT = @IDAUT AND COALESCE(VALOR, 0) = 0)
  BEGIN
    IF OBJECT_ID('dbo.FNK_VLRAUTORIZACION', 'FN') IS NOT NULL
      UPDATE AD
      SET AD.VALOR = COALESCE(DBO.FNK_VLRAUTORIZACION(
            AD.IDAUT, AD.NO_ITEM, AD.IDTERCEROCA, AD.IDPLAN,
            COALESCE(A.IDAREA, ''), A.FECHA), 0)
      FROM AUTD AD
      INNER JOIN AUT A ON A.IDAUT = AD.IDAUT
      WHERE AD.IDAUT = @IDAUT
        AND COALESCE(AD.VALOR, 0) = 0

    IF OBJECT_ID('dbo.ESP', 'U') IS NOT NULL
    BEGIN
      /* 2a) Estricto: proveedor + plan + SKU/papá + vigencia */
      UPDATE AD
      SET AD.VALOR = COALESCE((
            SELECT TOP 1 E.VALOR
            FROM ESP E WITH (NOLOCK)
            WHERE E.IDPROVEEDOR = COALESCE(NULLIF(AD.IDTERCEROCA, ''), A.IDTERCEROCA)
              AND E.IDPLAN = COALESCE(NULLIF(AD.IDPLAN, ''), A.IDPLAN)
              AND E.IDSERVICIO IN (NULLIF(AD.IDARTICULO, ''), AD.IDSERVICIO)
              AND E.TIPORESTRICCION = 'Valor'
              AND E.FECHAINI <= A.FECHA AND E.FECHAFIN >= A.FECHA
              AND COALESCE(E.VALOR, 0) > 0
            ORDER BY CASE WHEN E.IDSERVICIO = AD.IDARTICULO THEN 0 ELSE 1 END, E.FECHAINI DESC
          ), AD.VALOR)
      FROM AUTD AD
      INNER JOIN AUT A ON A.IDAUT = AD.IDAUT
      WHERE AD.IDAUT = @IDAUT AND COALESCE(AD.VALOR, 0) = 0

      /* 2b) Relaja plan */
      UPDATE AD
      SET AD.VALOR = COALESCE((
            SELECT TOP 1 E.VALOR
            FROM ESP E WITH (NOLOCK)
            WHERE E.IDPROVEEDOR = COALESCE(NULLIF(AD.IDTERCEROCA, ''), A.IDTERCEROCA)
              AND E.IDSERVICIO IN (NULLIF(AD.IDARTICULO, ''), AD.IDSERVICIO)
              AND E.TIPORESTRICCION = 'Valor'
              AND E.FECHAINI <= A.FECHA AND E.FECHAFIN >= A.FECHA
              AND COALESCE(E.VALOR, 0) > 0
            ORDER BY
              CASE WHEN E.IDPLAN = COALESCE(NULLIF(AD.IDPLAN, ''), A.IDPLAN) THEN 0 ELSE 1 END,
              CASE WHEN E.IDSERVICIO = AD.IDARTICULO THEN 0 ELSE 1 END,
              E.FECHAINI DESC
          ), AD.VALOR)
      FROM AUTD AD
      INNER JOIN AUT A ON A.IDAUT = AD.IDAUT
      WHERE AD.IDAUT = @IDAUT AND COALESCE(AD.VALOR, 0) = 0

      /* 2c) Solo SKU/papá + vigencia */
      UPDATE AD
      SET AD.VALOR = COALESCE((
            SELECT TOP 1 E.VALOR
            FROM ESP E WITH (NOLOCK)
            WHERE E.IDSERVICIO IN (NULLIF(AD.IDARTICULO, ''), AD.IDSERVICIO)
              AND E.TIPORESTRICCION = 'Valor'
              AND E.FECHAINI <= A.FECHA AND E.FECHAFIN >= A.FECHA
              AND COALESCE(E.VALOR, 0) > 0
            ORDER BY
              CASE WHEN E.IDSERVICIO = AD.IDARTICULO THEN 0 ELSE 1 END,
              E.FECHAINI DESC
          ), AD.VALOR)
      FROM AUTD AD
      INNER JOIN AUT A ON A.IDAUT = AD.IDAUT
      WHERE AD.IDAUT = @IDAUT AND COALESCE(AD.VALOR, 0) = 0

      /* 2d) Savia 0100000011 + CSRC26/CSRS26 + familia IART (NOPOS no tiene ESP propio) */
      UPDATE AD
      SET AD.VALOR = COALESCE((
            SELECT TOP 1 E.VALOR
            FROM ESP E WITH (NOLOCK)
            WHERE E.IDPROVEEDOR = '0100000011'
              AND E.TIPORESTRICCION = 'Valor'
              AND COALESCE(E.VALOR, 0) > 0
              AND E.FECHAINI <= A.FECHA AND E.FECHAFIN >= A.FECHA
              AND E.IDPLAN IN (
                CASE
                  WHEN COALESCE(NULLIF(AD.IDPLAN, ''), A.IDPLAN) IN ('CSRC26', 'NPBC26', 'AUTCON') THEN 'CSRC26'
                  WHEN COALESCE(NULLIF(AD.IDPLAN, ''), A.IDPLAN) IN ('CSRS26', 'NPBS26', 'AUTSUB') THEN 'CSRS26'
                  ELSE COALESCE(NULLIF(AD.IDPLAN, ''), A.IDPLAN)
                END,
                COALESCE(NULLIF(AD.IDPLAN, ''), A.IDPLAN)
              )
              AND (
                   E.IDSERVICIO IN (NULLIF(AD.IDARTICULO, ''), AD.IDSERVICIO)
                OR E.IDSERVICIO IN (
                     SELECT IA.IDSERVICIO FROM IART IA WITH (NOLOCK)
                     WHERE IA.IDARTICULO IN (NULLIF(AD.IDARTICULO, ''), AD.IDSERVICIO)
                   )
                OR EXISTS (
                     SELECT 1 FROM IART IA2 WITH (NOLOCK)
                     WHERE IA2.IDARTICULO = E.IDSERVICIO
                       AND IA2.IDSERVICIO IN (
                         AD.IDSERVICIO,
                         (SELECT TOP 1 IA.IDSERVICIO FROM IART IA WITH (NOLOCK)
                          WHERE IA.IDARTICULO IN (NULLIF(AD.IDARTICULO, ''), AD.IDSERVICIO))
                       )
                   )
              )
            ORDER BY
              CASE WHEN E.IDSERVICIO = AD.IDARTICULO THEN 0
                   WHEN E.IDSERVICIO = AD.IDSERVICIO THEN 1
                   ELSE 2 END,
              E.FECHAINI DESC
          ), AD.VALOR)
      FROM AUTD AD
      INNER JOIN AUT A ON A.IDAUT = AD.IDAUT
      WHERE AD.IDAUT = @IDAUT AND COALESCE(AD.VALOR, 0) = 0
    END
  END

  /* Sello facturador: lo que FTRMAut / la vista leen de AUT+AUTD */
  UPDATE AUT
  SET VALORTOTAL = COALESCE((SELECT SUM(COALESCE(CANTIDAD, 0) * COALESCE(VALOR, 0)) FROM AUTD WHERE IDAUT = @IDAUT), 0),
      NO_ITEMES = (SELECT COUNT(*) FROM AUTD WHERE IDAUT = @IDAUT),
      DESCUENTO = COALESCE(DESCUENTO, 0),
      FACTURABLE = 1,
      FACTURADA = 0,
      IDPROVEEDOR = @IDT,
      IDCONTRATANTE = @IDT,
      IDTERCEROCA = @IDT,
      IDPLAN = COALESCE(@IDP_FTR, IDPLAN),
      PREFIJO = COALESCE(@PREF_A, PREFIJO),
      IDSEDE = COALESCE(@IDS, IDSEDE),
      IDSEDEORIGEN = COALESCE(@IDS, IDSEDEORIGEN)
  WHERE IDAUT = @IDAUT

  UPDATE AUTD
  SET IDTERCEROCA = @IDT,
      IDPLAN = COALESCE(@IDP_FTR, IDPLAN)
  WHERE IDAUT = @IDAUT
END
