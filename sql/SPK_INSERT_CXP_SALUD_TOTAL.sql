IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='SPK_INSERT_CXP_SALUD_TOTAL' AND XTYPE='P')
BEGIN
 DROP PROCEDURE SPK_INSERT_CXP_SALUD_TOTAL
END

GO
CREATE PROCEDURE DBO.SPK_INSERT_CXP_SALUD_TOTAL
@CNSFCXP  VARCHAR(20)
WITH ENCRYPTION
AS
DECLARE @N_PRESUP VARCHAR(16)  
BEGIN
   DECLARE FXP_CURSOR CURSOR FOR
   SELECT N_PRESUP FROM FXP WHERE ESTADO = 'S'
   OPEN FXP_CURSOR
   FETCH NEXT FROM FXP_CURSOR
   INTO @N_PRESUP
   WHILE @@FETCH_STATUS = 0
   BEGIN

      EXEC SPK_INSERT_CXP_SALUD @CNSFCXP, @N_PRESUP
   
      FETCH NEXT FROM FXP_CURSOR
      INTO @N_PRESUP
   END
   CLOSE FXP_CURSOR
   DEALLOCATE FXP_CURSOR  
END
