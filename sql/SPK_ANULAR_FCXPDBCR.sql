IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='SPK_ANULAR_FCXPDBCR' AND XTYPE='P')
BEGIN
 DROP PROCEDURE SPK_ANULAR_FCXPDBCR
END

GO
CREATE PROCEDURE DBO.SPK_ANULAR_FCXPDBCR
    @CNSFCXP VARCHAR(20),
    @ITEM    INT
AS
DECLARE @COMPANIA VARCHAR(2)
DECLARE @CONTABILIZADA INT
DECLARE @NROCOMPROBANTE VARCHAR(20)
DECLARE @TIPO VARCHAR(2)
DECLARE @VALOR DECIMAL(14,2)
DECLARE @IDSEDE VARCHAR (5)
DECLARE @USUARIO VARCHAR(20)
DECLARE @SYS_COMPUTERNAME VARCHAR(255)
DECLARE @CUANTAS INT
DECLARE @ESTADOMCP INT
DECLARE @PROCEDENCIA VARCHAR(10)
BEGIN
   SELECT @TIPO = B.TIPO, @CONTABILIZADA = ISNULL(B.CONTABILIZADA,0), @NROCOMPROBANTE = B.NROCOMPROBANTE, @VALOR = B.VLR_NETO+B.VLR_IMPUESTOS,
          @COMPANIA = A.COMPANIA,@IDSEDE=A.IDSEDE,@USUARIO=B.USUARIO,@SYS_COMPUTERNAME=HOST_NAME(),@PROCEDENCIA=B.PROCEDENCIA
   FROM FCXPDBCR B INNER JOIN FCXP A ON B.CNSFCXP = A.CNSFCXP
   WHERE B.CNSFCXP = @CNSFCXP AND B.ITEM = @ITEM
   
   IF @CONTABILIZADA=1
   BEGIN
      PRINT 'CONTABILIZADA......'
      PRINT 'NROCOMPROBANTE...'+@NROCOMPROBANTE
      SELECT @CUANTAS=COUNT(*) FROM MCPE WHERE NROCOMPROBANTE=@NROCOMPROBANTE
      IF @CUANTAS>0
      BEGIN
         PRINT 'ESTA CON ERROR...'
         DELETE MCHE WHERE NROCOMPROBANTE=@NROCOMPROBANTE
         DELETE MCPE WHERE NROCOMPROBANTE=@NROCOMPROBANTE
      END
      ELSE
      BEGIN
         SELECT @ESTADOMCP=ESTADO FROM MCP WHERE NROCOMPROBANTE=@NROCOMPROBANTE
         IF @ESTADOMCP<>2
         BEGIN
            PRINT 'COMPROBANTE NO CONFIRMADO...'
            UPDATE MCP SET ANULADO=1 WHERE NROCOMPROBANTE=@NROCOMPROBANTE
            EXEC SPK_NC_SUMA_DBCR @NROCOMPROBANTE
         END
         ELSE
         BEGIN
            IF (SELECT CERRADO FROM PRI WHERE EXISTS(SELECT * FROM MCP WHERE NROCOMPROBANTE=@NROCOMPROBANTE AND PRI.MES=MCP.MES AND PRI.ANO=MCP.ANO))=1
            BEGIN
               PRINT 'COMPROBANTE CONFIRMADO....'
               EXEC SPK_REVERSAR_MCP @NROCOMPROBANTE,@CNSFCXP,'NOTDBCRCXP','','',@COMPANIA,@IDSEDE,@USUARIO,@SYS_COMPUTERNAME,''
            END
            ELSE
            BEGIN
               PRINT 'PERIODO NO ESTA CERRADO SOLO ANULO EL COMPROBANTE'
               UPDATE MCP SET ANULADO=1 WHERE NROCOMPROBANTE=@NROCOMPROBANTE
               EXEC SPK_NC_SUMA_DBCR @NROCOMPROBANTE
            END
         END         
      END
	   IF @TIPO = 'DB'
	   BEGIN
        IF @PROCEDENCIA='AUDT'
        BEGIN
		     UPDATE FCXPDBCR SET ESTADO = 'P',CONTABILIZADA=0,NROCOMPROBANTE=NULL
		     WHERE CNSFCXP = @CNSFCXP AND ITEM = @ITEM
           UPDATE FCXPS SET ESTADO='Nuevo' WHERE CNSFCXP = @CNSFCXP AND ITEM = @ITEM
        END
        ELSE
        BEGIN
		     UPDATE FCXPDBCR SET ESTADO = 'A'
		     WHERE CNSFCXP = @CNSFCXP AND ITEM = @ITEM
        END
        UPDATE FCXP SET VLR_NOTASDEBITO = VLR_NOTASDEBITO - @VALOR WHERE CNSFCXP = @CNSFCXP 
		  EXEC SPK_CALCULOVALORESCXP @CNSFCXP
	   END
	   IF @TIPO = 'CR'
	   BEGIN
        IF @PROCEDENCIA='AUDT'
        BEGIN
		     UPDATE FCXPDBCR SET ESTADO = 'P',CONTABILIZADA=0,NROCOMPROBANTE=NULL
		     WHERE CNSFCXP = @CNSFCXP AND ITEM = @ITEM
           UPDATE FCXPS SET ESTADO='Nuevo' WHERE CNSFCXP = @CNSFCXP AND ITEM = @ITEM
        END
        ELSE
        BEGIN
		     UPDATE FCXPDBCR SET ESTADO = 'A' 
		     WHERE CNSFCXP = @CNSFCXP AND ITEM = @ITEM

       END
       UPDATE FCXP SET VLR_NOTASCREDITO = VLR_NOTASCREDITO - @VALOR WHERE CNSFCXP = @CNSFCXP
		 EXEC SPK_CALCULOVALORESCXP @CNSFCXP
	   END
   END
   ELSE
   BEGIN
      IF @CONTABILIZADA=2
      BEGIN
         DELETE MCHE WHERE NROCOMPROBANTE=@NROCOMPROBANTE
         DELETE MCPE WHERE NROCOMPROBANTE=@NROCOMPROBANTE
      END
	   IF @TIPO = 'DB'
	   BEGIN
		  UPDATE FCXPDBCR SET CONTABILIZADA = 0, NROCOMPROBANTE = '' 
		  WHERE CNSFCXP = @CNSFCXP AND ITEM = @ITEM
        IF @PROCEDENCIA='AUD'
        BEGIN
           UPDATE FCXPS SET ESTADO='Nuevo' WHERE CNSFCXP = @CNSFCXP AND ITEM = @ITEM
        END
		  UPDATE FCXP SET VLR_NOTASDEBITO = VLR_NOTASDEBITO - @VALOR WHERE CNSFCXP = @CNSFCXP 
      
		  EXEC SPK_CALCULOVALORESCXP @CNSFCXP
	   END
	   IF @TIPO = 'CR'
	   BEGIN
		  UPDATE FCXPDBCR SET CONTABILIZADA = 0, NROCOMPROBANTE = '' 
		  WHERE CNSFCXP = @CNSFCXP AND ITEM = @ITEM
      
		  UPDATE FCXP SET VLR_NOTASCREDITO = VLR_NOTASCREDITO - @VALOR WHERE CNSFCXP = @CNSFCXP
        IF @PROCEDENCIA='AUD'
        BEGIN
           UPDATE FCXPS SET ESTADO='Nuevo' WHERE CNSFCXP = @CNSFCXP AND ITEM = @ITEM
        END      
		  EXEC SPK_CALCULOVALORESCXP @CNSFCXP
	   END
   END
   
END
