CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_RETUVT @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
BEGIN
	SET NOCOUNT ON;
	SET XACT_ABORT ON;

	DECLARE @PARAMETROS NVARCHAR(MAX), @METODO VARCHAR(100), @USUARIO VARCHAR(20);
	DECLARE @IDSEDE VARCHAR(5), @PROCESO VARCHAR(20), @IDUVT VARCHAR(10);
	DECLARE @DESCRIPCION VARCHAR(255), @UVTMIN DECIMAL(7, 2), @UVTMAX DECIMAL(7, 2);
	DECLARE @TARMARG DECIMAL(7, 2), @UVTADI DECIMAL(7, 2), @ESTADO VARCHAR(10);
	DECLARE @SYS_COMPUTERNAME VARCHAR(254);
	-- Variables de control transaccional
	DECLARE @StartedTran BIT = 0;
	DECLARE @SavePointName VARCHAR(32) = 'SPQ_NOM_RETUVT_sp';

	-- Extracci�n de cabecera inicial
	SELECT @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON);

	BEGIN TRY
		-- L�gica de apertura de transacci�n o Savepoint
		IF @@TRANCOUNT = 0
		BEGIN
			BEGIN TRANSACTION;

			SET @StartedTran = 1;
		END
		ELSE
		BEGIN
			SAVE TRANSACTION @SavePointName;
		END

		/* =========================
           L�GICA DE NEGOCIO
           ========================= */
		IF @METODO = 'GUARDAR'
		BEGIN
			-- Obtener contexto de sede/equipo
			SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
			FROM USUSU
			WHERE USUARIO = @USUARIO;

			SELECT @IDSEDE = IDSEDE
			FROM UBEQ
			WHERE SYS_ComputerName = @SYS_COMPUTERNAME;

			-- Mapeo de par�metros del modelo
			SELECT @IDUVT = IDUVT, @DESCRIPCION = DESCRIPCION, @UVTMIN = UVTMIN, @UVTMAX = UVTMAX, @TARMARG = TARMARG, @UVTADI = UVTADI, @ESTADO = ESTADO, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					IDUVT VARCHAR(10) '$.IDUVT', DESCRIPCION VARCHAR(255) '$.DESCRIPCION', UVTMIN DECIMAL(7, 2) '$.UVTMIN', UVTMAX DECIMAL(7, 2) '$.UVTMAX', TARMARG 
					DECIMAL(7, 2) '$.TARMARG', UVTADI DECIMAL(7, 2) '$.UVTADI', ESTADO VARCHAR(10) '$.ESTADO', PROCESO VARCHAR(20) '$.PROCESO'
					);

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@RETUVT', @LONGITUD = 4, @NVOCONSEC = @IDUVT OUTPUT;

				INSERT INTO [RETUVT] ([IDUVT], [DESCRIPCION], [UVTMIN], [UVTMAX], [TARMARG], [UVTADI], [ESTADO])
				VALUES (@IDUVT, @DESCRIPCION, @UVTMIN, @UVTMAX, @TARMARG, @UVTADI, @ESTADO);
			END
			ELSE IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				UPDATE RETUVT
				SET DESCRIPCION = @DESCRIPCION, UVTMIN = @UVTMIN, UVTMAX = @UVTMAX, TARMARG = @TARMARG, UVTADI = @UVTADI, ESTADO = @ESTADO
				WHERE IDUVT = @IDUVT;
			END
		END
		ELSE IF @METODO = 'ELIMINAR'
		BEGIN
			SELECT @IDUVT = IDUVT
			FROM OPENJSON(@PARAMETROS) WITH (IDUVT VARCHAR(10) '$.IDUVT');

			DELETE
			FROM RETUVT
			WHERE IDUVT = @IDUVT;
		END

		-- Si yo la abr�, yo la cierro
		IF @StartedTran = 1
			COMMIT TRANSACTION;

		SELECT 'OK' AS OK;
	END TRY

	BEGIN CATCH
		-- Manejo de reversi�n inteligente
		IF XACT_STATE() = - 1
		BEGIN
			-- Transacci�n no confirmable: Rollback total
			ROLLBACK TRANSACTION;
		END
		ELSE IF XACT_STATE() = 1
		BEGIN
			-- Transacci�n v�lida: Rollback parcial o total seg�n el origen
			IF @StartedTran = 1
				ROLLBACK TRANSACTION;
			ELSE
				ROLLBACK TRANSACTION @SavePointName;
		END;-- <--- Punto y coma obligatorio antes de THROW

		-- Re-lanzar el error para que el proceso llamador (SP Padre) se entere
		THROW;
	END CATCH
END
