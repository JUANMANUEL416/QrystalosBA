SET NOCOUNT ON;
SET QUOTED_IDENTIFIER ON;

SELECT F.N_FACTURA, F.CNSFCT, F.VR_TOTAL, F.FACTE, F.CONTABILIZADA, F.F_FACTURA, F.CUFE
FROM dbo.FTR F
WHERE F.N_FACTURA IN (N'FVSF1076', N'FVSF1077')
   OR F.CNSFCT IN (N'2500001087', N'2500001086', N'2500001088')
ORDER BY F.CNSFCT, F.N_FACTURA;

SELECT D.CNSDOCUMENTO, D.ITEM, D.METODO, D.FECHA
FROM dbo.FDIANR D
WHERE D.CNSDOCUMENTO IN (
  SELECT CNSFCT FROM dbo.FTR WHERE N_FACTURA IN (N'FVSF1076', N'FVSF1077')
);

DECLARE @xml XML;
SELECT TOP 1 @xml = CAST(xml_solicitud AS XML)
FROM dbo.FDIANR WHERE CNSDOCUMENTO = N'2500001087' AND METODO = N'SendBillSync'
ORDER BY ITEM DESC;

WITH XMLNAMESPACES (
  'urn:oasis:names:specification:ubl:schema:xsd:Invoice-2' AS inv,
  'urn:oasis:names:specification:ubl:schema:xsd:CommonBasicComponents-2' AS cbc
)
SELECT @xml.value('(/inv:Invoice/cbc:ID)[1]', 'varchar(30)') AS XML_FACTURA_ID;
