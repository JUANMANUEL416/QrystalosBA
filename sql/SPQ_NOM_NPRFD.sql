CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NPRFD @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20)
DECLARE @PROCESO VARCHAR(20)
DECLARE @CODPRF VARCHAR(20), @ITEM VARCHAR(8), @FECHAINI DATETIME, @VALOR_APORTE DECIMAL(14, 6)
DECLARE @TIPOCALCULO VARCHAR(10), @VALOR_EMPRESA DECIMAL(14, 6), @VALOR_EMPLEADO DECIMAL(14, 6), @CODCONCEPTO VARCHAR(20)
DECLARE @ESTADO VARCHAR(12), @IDTERCERO VARCHAR(20), @INICIAL SMALLINT
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @CODPRF = CODPRF, @ITEM = ITEM, @FECHAINI = FECHAINI, @VALOR_APORTE = VALOR_APORTE, @TIPOCALCULO = TIPOCALCULO, @VALOR_EMPRESA = VALOR_EMPRESA, 
				@VALOR_EMPLEADO = VALOR_EMPLEADO, @ESTADO = ESTADO, @IDTERCERO = IDTERCERO, @INICIAL = INICIAL, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					CODPRF VARCHAR(20) '$.CODPRF', ITEM VARCHAR(8) '$.ITEM', FECHAINI DATETIME '$.FECHAINI', VALOR_APORTE DECIMAL(14, 6) '$.VALOR_APORTE', 
					TIPOCALCULO VARCHAR(10) '$.TIPOCALCULO', VALOR_EMPRESA DECIMAL(14, 6) '$.VALOR_EMPRESA', VALOR_EMPLEADO DECIMAL(14, 6) '$.VALOR_EMPLEADO', 
					ESTADO BIT '$.ESTADO', IDTERCERO VARCHAR(20) '$.IDTERCERO', INICIAL SMALLINT '$.INICIAL', PROCESO VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('EL ITEM ', @ITEM, ' YA SE ENCUENTRA REGISTRADO')
					WHERE EXISTS (
							SELECT 1
							FROM NPRFD
							WHERE CODPRF = @CODPRF AND ITEM = @ITEM
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO NPRFD (CODPRF, ITEM, FECHAINI, VALOR_APORTE, TIPOCALCULO, VALOR_EMPRESA, VALOR_EMPLEADO, ESTADO, IDTERCERO, INICIAL
							)
						SELECT @CODPRF, @ITEM, @FECHAINI, @VALOR_APORTE, @TIPOCALCULO, @VALOR_EMPRESA, @VALOR_EMPLEADO, CASE 
								WHEN @ESTADO = 1
									THEN 'Activo'
								ELSE 'Inactivo'
								END, @IDTERCERO, 0
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					UPDATE NPRFD
					SET FECHAINI = @FECHAINI, VALOR_APORTE = @VALOR_APORTE, TIPOCALCULO = @TIPOCALCULO, VALOR_EMPRESA = @VALOR_EMPRESA, VALOR_EMPLEADO = 
						@VALOR_EMPLEADO, ESTADO = CASE 
							WHEN @ESTADO = 1
								THEN 'Activo'
							ELSE 'Inactivo'
							END, IDTERCERO = @IDTERCERO, INICIAL = 0
					WHERE CODPRF = @CODPRF AND ITEM = @ITEM
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GET_NPRFD_DETALLE'
	BEGIN
		SELECT @CODPRF = CODPRF
		FROM OPENJSON(@PARAMETROS) WITH (CODPRF VARCHAR(20) '$.CODPRF')

		SELECT 'OK' OK

		SELECT NPRFD.CODPRF, NPRFD.ITEM, NPRFD.FECHAINI, NPRFD.VALOR_APORTE, NPRFD.TIPOCALCULO, NPRFD.VALOR_EMPRESA, NPRFD.VALOR_EMPLEADO, NPRFD.ESTADO, NPRFD.
			IDTERCERO, TER.RAZONSOCIAL
		FROM NPRFD
		LEFT JOIN TER ON TER.IDTERCERO = NPRFD.IDTERCERO
		WHERE CODPRF = JSON_VALUE(@PARAMETROS, '$.CODPRF')

		RETURN
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @CODPRF = CODPRF, @ITEM = ITEM
		FROM OPENJSON(@PARAMETROS) WITH (CODPRF VARCHAR(20) '$.CODPRF', ITEM VARCHAR(8) '$.ITEM')

		BEGIN TRY
			INSERT INTO @TBLERRORES (ERROR)
			SELECT CONCAT ('NO ES POSIBLE ELIMINAR EL DETALLE DE LA AGRUPACION ', @CODPRF, ' YA QUE SE ENCUENTRA EN LIQUIDACIONES PREVIAMENTE PROCESADAS'
					)
			WHERE EXISTS (
					SELECT 1
					FROM NIEPED
					WHERE CODPRF = @CODPRF
					)

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				DELETE
				FROM NPRFD
				WHERE CODPRF = @CODPRF AND ITEM = @ITEM
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
