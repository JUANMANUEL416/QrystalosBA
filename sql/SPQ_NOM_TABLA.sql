CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_TABLA @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
SET DATEFORMAT dmy

DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(12), @TIPOTABLA VARCHAR(20), @DESCRIPCION VARCHAR(255), @ITEM 
	DECIMAL(14, 0), @FECHAINI DATETIME, @VALORINICIAL DECIMAL(14, 6), @VALORINICIAL_OLD DECIMAL(14, 6), @PORCENTAJE DECIMAL(14, 6), @VALOR DECIMAL(14, 6), 
	@TIPOCALCULO VARCHAR(12), @PROCESO VARCHAR(20), @XFECHA VARCHAR(20)

BEGIN
	SELECT *
	INTO #JSON
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	SELECT @MODELO = MODELO, @METODO = METODO, @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON

	-- ----------------------------------------------------------------
	-- M�TODO: GET_NCONT
	-- Retorna el cat�logo de tipos de tablas tabuladas (NCONT)
	-- con el conteo de vigencias disponibles por tabla.
	-- Alias de salida: CODTABLA = TIPOTABLA
	-- ----------------------------------------------------------------
	IF @METODO = 'GET_NCONT'
	BEGIN
		SELECT 'OK' OK

		SELECT T.TIPOTABLA AS CODTABLA, T.DESCRIPCION, COUNT(D.ITEM) AS TOTAL_VIGENCIAS
		FROM NCONT T
		LEFT JOIN NCONTD D ON D.TIPOTABLA = T.TIPOTABLA
		GROUP BY T.TIPOTABLA, T.DESCRIPCION
		ORDER BY T.TIPOTABLA ASC

		RETURN
	END

	-- ----------------------------------------------------------------
	-- M�TODO: GUARDAR_NCONT
	-- Inserta o actualiza un registro en el cat�logo NCONT.
	-- PARAMETROS: CODTABLA, DESCRIPCION, PROCESO (INSERTAR|EDITAR)
	-- ----------------------------------------------------------------
	IF @METODO = 'GUARDAR_NCONT'
	BEGIN
		SELECT @TIPOTABLA = CODTABLA, @DESCRIPCION = DESCRIPCION, @PROCESO = PROCESO
		FROM OPENJSON(@PARAMETROS) WITH (CODTABLA VARCHAR(20) '$.CODTABLA', DESCRIPCION VARCHAR(255) '$.DESCRIPCION', PROCESO VARCHAR(20) '$.PROCESO'
				)

		IF LEN(LTRIM(RTRIM(COALESCE(@TIPOTABLA, '')))) = 0
		BEGIN
			SELECT 'KO' OK, 'El c�digo de la tabla (CODTABLA) es obligatorio' ERROR

			RETURN
		END

		IF LEN(LTRIM(RTRIM(COALESCE(@DESCRIPCION, '')))) = 0
		BEGIN
			SELECT 'KO' OK, 'La descripci�n de la tabla es obligatoria' ERROR

			RETURN
		END

		BEGIN TRY
			IF @PROCESO = 'INSERTAR'
			BEGIN
				IF EXISTS (
						SELECT 1
						FROM NCONT
						WHERE TIPOTABLA = @TIPOTABLA
						)
				BEGIN
					SELECT 'KO' OK, 'Ya existe una tabla con el c�digo ' + @TIPOTABLA + '. Verifique e intente de nuevo.' ERROR

					RETURN
				END

				INSERT INTO NCONT (TIPOTABLA, DESCRIPCION)
				SELECT @TIPOTABLA, LTRIM(RTRIM(@DESCRIPCION))
			END
			ELSE
			BEGIN
				IF NOT EXISTS (
						SELECT 1
						FROM NCONT
						WHERE TIPOTABLA = @TIPOTABLA
						)
				BEGIN
					SELECT 'KO' OK, 'No se encontr� la tabla ' + @TIPOTABLA + ' para actualizar.' ERROR

					RETURN
				END

				UPDATE NCONT
				SET DESCRIPCION = LTRIM(RTRIM(@DESCRIPCION))
				WHERE TIPOTABLA = @TIPOTABLA
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK, ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK, @TIPOTABLA CODTABLA

		RETURN
	END

	-- ----------------------------------------------------------------
	-- M�TODO: ELIMINAR_NCONT
	-- Elimina un registro del cat�logo NCONT.
	-- Valida dependencias en NCONTD, NCOND y NEMPT antes de borrar.
	-- PARAMETROS: CODTABLA
	-- ----------------------------------------------------------------
	IF @METODO = 'ELIMINAR_NCONT'
	BEGIN
		SELECT @TIPOTABLA = CODTABLA
		FROM OPENJSON(@PARAMETROS) WITH (CODTABLA VARCHAR(20) '$.CODTABLA')

		IF NOT EXISTS (
				SELECT 1
				FROM NCONT
				WHERE TIPOTABLA = @TIPOTABLA
				)
		BEGIN
			SELECT 'KO' OK, 'No se encontr� la tabla ' + @TIPOTABLA + ' para eliminar.' ERROR

			RETURN
		END

		IF EXISTS (
				SELECT 1
				FROM NCONTD
				WHERE TIPOTABLA = @TIPOTABLA
				)
		BEGIN
			SELECT 'KO' OK, 'No se puede eliminar. La tabla ' + @TIPOTABLA + ' tiene vigencias en NCONTD. Elim�nelas primero.' ERROR

			RETURN
		END

		IF EXISTS (
				SELECT 1
				FROM NCOND
				WHERE TIPOTABLA = @TIPOTABLA
				)
		BEGIN
			SELECT 'KO' OK, 'No se puede eliminar. La tabla ' + @TIPOTABLA + ' est� referenciada en condiciones de conceptos (NCOND).' ERROR

			RETURN
		END

		IF EXISTS (
				SELECT 1
				FROM NEMPT
				WHERE TIPOTABLA = @TIPOTABLA
				)
		BEGIN
			SELECT 'KO' OK, 'No se puede eliminar. La tabla ' + @TIPOTABLA + ' est� asignada a empleados (NEMPT).' ERROR

			RETURN
		END

		BEGIN TRY
			DELETE NCONT
			WHERE TIPOTABLA = @TIPOTABLA
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK, ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK

		RETURN
	END

	-- ----------------------------------------------------------------
	-- M�TODO: GET_VIGENCIAS
	-- Retorna las vigencias (NCONTD) de un tipo de tabla espec�fico.
	-- Alias de salida: CODTABLA = TIPOTABLA, FECHAVIGENCIA = FECHAINI
	-- PARAMETROS: CODTABLA
	-- ----------------------------------------------------------------
	IF @METODO = 'GET_VIGENCIAS'
	BEGIN
		SELECT @TIPOTABLA = CODTABLA
		FROM OPENJSON(@PARAMETROS) WITH (CODTABLA VARCHAR(20) '$.CODTABLA')

		IF NOT EXISTS (
				SELECT 1
				FROM NCONT
				WHERE TIPOTABLA = @TIPOTABLA
				)
		BEGIN
			SELECT 'KO' OK, 'No se encontr� la tabla ' + @TIPOTABLA + '.' ERROR

			RETURN
		END

		SELECT 'OK' OK

		SELECT D.TIPOTABLA AS CODTABLA, D.ITEM, DBO.FNK_FECHA_GRINGA(D.FECHAINI) AS FECHAVIGENCIA, COUNT(V.VALORINICIAL) AS TOTAL_TRAMOS
		FROM NCONTD D
		LEFT JOIN NCONTDV V ON V.TIPOTABLA = D.TIPOTABLA AND V.ITEM = D.ITEM
		WHERE D.TIPOTABLA = @TIPOTABLA
		GROUP BY D.TIPOTABLA, D.ITEM, D.FECHAINI
		ORDER BY D.FECHAINI ASC, D.ITEM ASC

		RETURN
	END

	-- ----------------------------------------------------------------
	-- M�TODO: GUARDAR_VIGENCIA
	-- Inserta o actualiza una vigencia en NCONTD.
	-- ITEM se genera autom�tico al insertar (MAX+1 por CODTABLA).
	-- PARAMETROS: CODTABLA, ITEM, FECHAVIGENCIA, PROCESO (INSERTAR|EDITAR)
	-- ----------------------------------------------------------------
	IF @METODO = 'GUARDAR_VIGENCIA'
	BEGIN
		SELECT @TIPOTABLA = CODTABLA, @ITEM = ITEM, @XFECHA = FECHAVIGENCIA, @PROCESO = PROCESO
		FROM OPENJSON(@PARAMETROS) WITH (CODTABLA VARCHAR(20) '$.CODTABLA', ITEM DECIMAL(14, 0) '$.ITEM', FECHAVIGENCIA VARCHAR(20) '$.FECHAVIGENCIA', PROCESO VARCHAR(20) '$.PROCESO'
				)

		IF NOT EXISTS (
				SELECT 1
				FROM NCONT
				WHERE TIPOTABLA = @TIPOTABLA
				)
		BEGIN
			SELECT 'KO' OK, 'No existe la tabla ' + @TIPOTABLA + ' en el cat�logo NCONT.' ERROR

			RETURN
		END

		IF ISDATE(@XFECHA) = 0
		BEGIN
			SELECT 'KO' OK, 'La fecha de vigencia no es v�lida: ' + COALESCE(@XFECHA, 'NULL') ERROR

			RETURN
		END

		SELECT @FECHAINI = CONVERT(DATETIME, CONVERT(DATE, @XFECHA))

		BEGIN TRY
			IF @PROCESO = 'INSERTAR'
			BEGIN
				IF EXISTS (
						SELECT 1
						FROM NCONTD
						WHERE TIPOTABLA = @TIPOTABLA AND FECHAINI = @FECHAINI
						)
				BEGIN
					SELECT 'KO' OK, 'Ya existe una vigencia con la fecha ' + CONVERT(VARCHAR, @FECHAINI, 103) + ' para la tabla ' + @TIPOTABLA + '.' ERROR

					RETURN
				END

				SELECT @ITEM = COALESCE(MAX(ITEM), 0) + 1
				FROM NCONTD
				WHERE TIPOTABLA = @TIPOTABLA

				INSERT INTO NCONTD (TIPOTABLA, ITEM, FECHAINI)
				SELECT @TIPOTABLA, @ITEM, @FECHAINI
			END
			ELSE
			BEGIN
				IF NOT EXISTS (
						SELECT 1
						FROM NCONTD
						WHERE TIPOTABLA = @TIPOTABLA AND ITEM = @ITEM
						)
				BEGIN
					SELECT 'KO' OK, 'No se encontr� la vigencia con ITEM=' + CAST(@ITEM AS VARCHAR(20)) + ' para la tabla ' + @TIPOTABLA + '.' ERROR

					RETURN
				END

				UPDATE NCONTD
				SET FECHAINI = @FECHAINI
				WHERE TIPOTABLA = @TIPOTABLA AND ITEM = @ITEM
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK, ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK, @TIPOTABLA CODTABLA, @ITEM ITEM

		RETURN
	END

	-- ----------------------------------------------------------------
	-- M�TODO: ELIMINAR_VIGENCIA
	-- Elimina una vigencia de NCONTD.
	-- Valida que no existan tramos dependientes en NCONTDV.
	-- PARAMETROS: CODTABLA, ITEM
	-- ----------------------------------------------------------------
	IF @METODO = 'ELIMINAR_VIGENCIA'
	BEGIN
		SELECT @TIPOTABLA = CODTABLA, @ITEM = ITEM
		FROM OPENJSON(@PARAMETROS) WITH (CODTABLA VARCHAR(20) '$.CODTABLA', ITEM DECIMAL(14, 0) '$.ITEM')

		IF NOT EXISTS (
				SELECT 1
				FROM NCONTD
				WHERE TIPOTABLA = @TIPOTABLA AND ITEM = @ITEM
				)
		BEGIN
			SELECT 'KO' OK, 'No se encontr� la vigencia ITEM=' + CAST(@ITEM AS VARCHAR(20)) + ' de la tabla ' + @TIPOTABLA + '.' ERROR

			RETURN
		END

		IF EXISTS (
				SELECT 1
				FROM NCONTDV
				WHERE TIPOTABLA = @TIPOTABLA AND ITEM = @ITEM
				)
		BEGIN
			SELECT 'KO' OK, 'No se puede eliminar. La vigencia tiene tramos de valores en NCONTDV. Elim�nelos primero.' ERROR

			RETURN
		END

		BEGIN TRY
			DELETE NCONTD
			WHERE TIPOTABLA = @TIPOTABLA AND ITEM = @ITEM
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK, ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK

		RETURN
	END

	-- ----------------------------------------------------------------
	-- M�TODO: GET_DETVALORES
	-- Retorna los tramos/rangos (NCONTDV) de una vigencia espec�fica.
	-- Alias de salida: CODTABLA = TIPOTABLA, TIPOVALOR = TIPOCALCULO,
	--                  VALORAPLICAR = VALOR
	-- IDDETVAL: clave compuesta como identificador �nico de fila en UI.
	-- PARAMETROS: CODTABLA, ITEM
	-- ----------------------------------------------------------------
	IF @METODO = 'GET_DETVALORES'
	BEGIN
		SELECT @TIPOTABLA = CODTABLA, @ITEM = ITEM
		FROM OPENJSON(@PARAMETROS) WITH (CODTABLA VARCHAR(20) '$.CODTABLA', ITEM DECIMAL(14, 0) '$.ITEM')

		IF NOT EXISTS (
				SELECT 1
				FROM NCONTD
				WHERE TIPOTABLA = @TIPOTABLA AND ITEM = @ITEM
				)
		BEGIN
			SELECT 'KO' OK, 'No se encontr� la vigencia ITEM=' + CAST(@ITEM AS VARCHAR(20)) + ' de la tabla ' + @TIPOTABLA + '.' ERROR

			RETURN
		END

		SELECT 'OK' OK

		SELECT V.TIPOTABLA AS CODTABLA, V.ITEM, V.VALORINICIAL, V.PORCENTAJE, V.VALOR AS VALORAPLICAR, V.TIPOCALCULO AS TIPOVALOR, V.TIPOTABLA + '_' + CAST(V.ITEM AS 
				VARCHAR(20)) + '_' + CAST(V.VALORINICIAL AS VARCHAR(30)) AS IDDETVAL
		FROM NCONTDV V
		WHERE V.TIPOTABLA = @TIPOTABLA AND V.ITEM = @ITEM
		ORDER BY V.VALORINICIAL ASC

		RETURN
	END

	-- ----------------------------------------------------------------
	-- M�TODO: GUARDAR_DETVAL
	-- Inserta o actualiza un tramo/rango en NCONTDV.
	-- PARAMETROS: CODTABLA, ITEM, VALORINICIAL, PORCENTAJE, VALORAPLICAR,
	--             TIPOVALOR, PROCESO (INSERTAR|EDITAR),
	--             VALORINICIAL_OLD (solo EDITAR si cambia VALORINICIAL)
	-- ----------------------------------------------------------------
	IF @METODO = 'GUARDAR_DETVAL'
	BEGIN
		SELECT @TIPOTABLA = CODTABLA, @ITEM = ITEM, @VALORINICIAL = VALORINICIAL, @PORCENTAJE = PORCENTAJE, @VALOR = VALORAPLICAR, @TIPOCALCULO = TIPOVALOR, @PROCESO = 
			PROCESO, @VALORINICIAL_OLD = VALORINICIAL_OLD
		FROM OPENJSON(@PARAMETROS) WITH (
				CODTABLA VARCHAR(20) '$.CODTABLA', ITEM DECIMAL(14, 0) '$.ITEM', VALORINICIAL DECIMAL(14, 6) '$.VALORINICIAL', PORCENTAJE DECIMAL(14, 6) 
				'$.PORCENTAJE', VALORAPLICAR DECIMAL(14, 6) '$.VALORAPLICAR', TIPOVALOR VARCHAR(12) '$.TIPOVALOR', PROCESO VARCHAR(20) '$.PROCESO', 
				VALORINICIAL_OLD DECIMAL(14, 6) '$.VALORINICIAL_OLD'
				)

		IF NOT EXISTS (
				SELECT 1
				FROM NCONTD
				WHERE TIPOTABLA = @TIPOTABLA AND ITEM = @ITEM
				)
		BEGIN
			SELECT 'KO' OK, 'No existe la vigencia ITEM=' + CAST(@ITEM AS VARCHAR(20)) + ' para la tabla ' + @TIPOTABLA + '. No se puede guardar el tramo.' ERROR

			RETURN
		END

		IF @TIPOCALCULO NOT IN ('Porcentaje', 'Valor')
		BEGIN
			SELECT 'KO' OK, 'El tipo de valor debe ser Porcentaje o Valor. Recibido: ' + COALESCE(@TIPOCALCULO, 'NULL') ERROR

			RETURN
		END

		BEGIN TRY
			IF @PROCESO = 'INSERTAR'
			BEGIN
				IF EXISTS (
						SELECT 1
						FROM NCONTDV
						WHERE TIPOTABLA = @TIPOTABLA AND ITEM = @ITEM AND VALORINICIAL = @VALORINICIAL
						)
				BEGIN
					SELECT 'KO' OK, 'Ya existe un tramo con VALORINICIAL=' + CAST(@VALORINICIAL AS VARCHAR(30)) + ' en esta vigencia.' ERROR

					RETURN
				END

				INSERT INTO NCONTDV (TIPOTABLA, ITEM, VALORINICIAL, PORCENTAJE, VALOR, TIPOCALCULO)
				SELECT @TIPOTABLA, @ITEM, @VALORINICIAL, CASE 
						WHEN @TIPOCALCULO = 'Porcentaje'
							THEN @PORCENTAJE
						ELSE NULL
						END, CASE 
						WHEN @TIPOCALCULO = 'Valor'
							THEN @VALOR
						ELSE NULL
						END, @TIPOCALCULO
			END
			ELSE
			BEGIN
				DECLARE @VI_REF DECIMAL(14, 6) = COALESCE(@VALORINICIAL_OLD, @VALORINICIAL)

				IF NOT EXISTS (
						SELECT 1
						FROM NCONTDV
						WHERE TIPOTABLA = @TIPOTABLA AND ITEM = @ITEM AND VALORINICIAL = @VI_REF
						)
				BEGIN
					SELECT 'KO' OK, 'No se encontr� el tramo con VALORINICIAL=' + CAST(@VI_REF AS VARCHAR(30)) + ' para actualizar.' ERROR

					RETURN
				END

				UPDATE NCONTDV
				SET VALORINICIAL = @VALORINICIAL, PORCENTAJE = CASE 
						WHEN @TIPOCALCULO = 'Porcentaje'
							THEN @PORCENTAJE
						ELSE NULL
						END, VALOR = CASE 
						WHEN @TIPOCALCULO = 'Valor'
							THEN @VALOR
						ELSE NULL
						END, TIPOCALCULO = @TIPOCALCULO
				WHERE TIPOTABLA = @TIPOTABLA AND ITEM = @ITEM AND VALORINICIAL = @VI_REF
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK, ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK, @TIPOTABLA CODTABLA, @ITEM ITEM, @VALORINICIAL VALORINICIAL

		RETURN
	END

	-- ----------------------------------------------------------------
	-- M�TODO: ELIMINAR_DETVAL
	-- Elimina un tramo/rango de NCONTDV por su clave compuesta.
	-- PARAMETROS: CODTABLA, ITEM, VALORINICIAL
	-- ----------------------------------------------------------------
	IF @METODO = 'ELIMINAR_DETVAL'
	BEGIN
		SELECT @TIPOTABLA = CODTABLA, @ITEM = ITEM, @VALORINICIAL = VALORINICIAL
		FROM OPENJSON(@PARAMETROS) WITH (CODTABLA VARCHAR(20) '$.CODTABLA', ITEM DECIMAL(14, 0) '$.ITEM', VALORINICIAL DECIMAL(14, 6) '$.VALORINICIAL'
				)

		IF NOT EXISTS (
				SELECT 1
				FROM NCONTDV
				WHERE TIPOTABLA = @TIPOTABLA AND ITEM = @ITEM AND VALORINICIAL = @VALORINICIAL
				)
		BEGIN
			SELECT 'KO' OK, 'No se encontr� el tramo con VALORINICIAL=' + CAST(@VALORINICIAL AS VARCHAR(30)) + ' para eliminar.' ERROR

			RETURN
		END

		BEGIN TRY
			DELETE NCONTDV
			WHERE TIPOTABLA = @TIPOTABLA AND ITEM = @ITEM AND VALORINICIAL = @VALORINICIAL
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK, ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK

		RETURN
	END
END
