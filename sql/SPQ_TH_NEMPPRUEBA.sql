CREATE OR ALTER PROCEDURE DBO.SPQ_TH_NEMPPRUEBA @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @DATOS NVARCHAR(MAX)
DECLARE @USUARIO VARCHAR(20), @PROCESOSPQ VARCHAR(20)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @CONSECUTIVO VARCHAR(20), @IDSEDE VARCHAR(5), @NUMDOC VARCHAR(20), @ID INT

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'VALIDAR_NOTIFICACIONES'
	BEGIN
		BEGIN TRY
			SELECT @IDSEDE = COALESCE(UBEQ.IDSEDE, USUSU.IDSEDE)
			FROM USUSU
			LEFT JOIN UBEQ ON USUSU.SYS_ComputerName = UBEQ.SYS_ComputerName
			WHERE USUSU.USUARIO = @USUARIO

			EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@QRY_ENVIOS', @LONGITUD = 8, @NVOCONSEC = @CONSECUTIVO OUTPUT

			INSERT INTO QRY_ENVIOS (TIPOCNS, CONSECUTIVO, ESTADO, DESTINOS, FECHA_REGISTRO, CLASE, TIPO, IDAFILIADO, CANAL, ASUNTO)
			SELECT 'NEMP', @CONSECUTIVO, 'POR ENVIAR',  COALESCE(NEMP.EMAIL, TER.EMAIL), GETDATE(), 'NEMPERIODOPRUEBA', CASE 
					WHEN DATEDIFF(DAY, GETDATE(), NEMP.FECHAFINPRUEBA) <= 0
						THEN 'Vencido'
					WHEN DATEDIFF(DAY, GETDATE(), NEMP.FECHAFINPRUEBA) <= 30
						THEN 'Menos de 30 dias'
					WHEN DATEDIFF(DAY, GETDATE(), NEMP.FECHAFINPRUEBA) <= 60
						THEN 'Menos de 60 dias'
					ELSE 'Mas de 60 dias'
					END AS EstadoPrueba, NEMP.NUMDOC, 'MAIL', DATEDIFF(DAY, GETDATE(), NEMP.FECHAFINPRUEBA)
			FROM [dbo].[NEMP]
			INNER JOIN TER ON TER.IDTERCERO = NEMP.TERCEROID
			WHERE DATEDIFF(DAY, GETDATE(), NEMP.FECHAFINPRUEBA) <= 30 AND NOT EXISTS (
					SELECT 1
					FROM QRY_ENVIOS AS Q
					WHERE Q.IDAFILIADO = NEMP.NUMDOC AND CLASE = 'NEMPERIODOPRUEBA'
					)
			ORDER BY NEMP.NUMDOC ASC

			SELECT 'OK' OK

			SELECT QRY_ENVIOS.*, TER.RAZONSOCIAL AS NOMBRE_EMPLEADO, REPLACE(TRANSLATE(NCARNG.DESCRIPCION, '0123456789', '          '), '  ', ' ') AS CARGO,
				-- Diferencia en meses completos
				DATEDIFF(MONTH, NEMP.FECHAINIPRUEBA, NEMP.FECHAFINPRUEBA) - CASE 
					WHEN DAY(NEMP.FECHAINIPRUEBA) > DAY(NEMP.FECHAFINPRUEBA)
						THEN 1
					ELSE 0
					END AS MESES,
				-- D�as restantes (ajustados si no se complet� el mes)
				CASE 
					WHEN DAY(NEMP.FECHAFINPRUEBA) >= DAY(NEMP.FECHAINIPRUEBA)
						THEN DAY(NEMP.FECHAFINPRUEBA) - DAY(NEMP.FECHAINIPRUEBA) + 1
					ELSE DAY(EOMONTH(NEMP.FECHAINIPRUEBA)) - DAY(NEMP.FECHAINIPRUEBA) + DAY(NEMP.FECHAFINPRUEBA) + 1
					END AS DIAS, NEMP.FECHAFINPRUEBA, A.DICOM, U.NOMBRE AS NOMBREJEFE, U.CARGO AS CARGOJEFE
			FROM QRY_ENVIOS
			INNER JOIN NEMP ON QRY_ENVIOS.IDAFILIADO = NEMP.NUMDOC
			LEFT JOIN NCAR ON NCAR.CODCARGO = NEMP.CODCARGO
			LEFT JOIN NCARNG ON NCARNG.CODCARGO = NEMP.CODCARGO AND NCARNG.GRADO = NEMP.GRADO AND NCARNG.NIVEL = NEMP.NIVEL
			INNER JOIN TER ON NEMP.TERCEROID = TER.IDTERCERO
			LEFT JOIN USUSU U ON U.USUARIO = dbo.FNK_VALORVARIABLE('USUARIOJEFERH')
			LEFT JOIN ARCHIVOS A ON A.ID = U.IDFIRMA
			WHERE CLASE = 'NEMPERIODOPRUEBA' AND QRY_ENVIOS.ESTADO = 'POR ENVIAR'
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'VER_NOTINEMPPRUEBA'
	BEGIN
		SELECT @NUMDOC = NUMDOC
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC')

		SELECT 'OK' OK

		SELECT QRY_ENVIOS.*, TER.RAZONSOCIAL AS NOMBRE_EMPLEADO, REPLACE(TRANSLATE(NCARNG.DESCRIPCION, '0123456789', '          '), '  ', ' ') AS CARGO,
			-- Diferencia en meses completos
			DATEDIFF(MONTH, NEMP.FECHAINIPRUEBA, NEMP.FECHAFINPRUEBA) - CASE 
				WHEN DAY(NEMP.FECHAINIPRUEBA) > DAY(NEMP.FECHAFINPRUEBA)
					THEN 1
				ELSE 0
				END AS MESES,
			-- D�as restantes (ajustados si no se complet� el mes)
			CASE 
				WHEN DAY(NEMP.FECHAFINPRUEBA) >= DAY(NEMP.FECHAINIPRUEBA)
					THEN DAY(NEMP.FECHAFINPRUEBA) - DAY(NEMP.FECHAINIPRUEBA) + 1
				ELSE DAY(EOMONTH(NEMP.FECHAINIPRUEBA)) - DAY(NEMP.FECHAINIPRUEBA) + DAY(NEMP.FECHAFINPRUEBA) + 1
				END AS DIAS, NEMP.FECHAFINPRUEBA, A.DICOM, U.NOMBRE AS NOMBREJEFE, U.CARGO AS CARGOJEFE
		FROM QRY_ENVIOS
		INNER JOIN NEMP ON QRY_ENVIOS.IDAFILIADO = NEMP.NUMDOC
		LEFT JOIN NCAR ON NCAR.CODCARGO = NEMP.CODCARGO
		LEFT JOIN NCARNG ON NCARNG.CODCARGO = NEMP.CODCARGO AND NCARNG.GRADO = NEMP.GRADO AND NCARNG.NIVEL = NEMP.NIVEL
		INNER JOIN TER ON NEMP.TERCEROID = TER.IDTERCERO
		LEFT JOIN USUSU U ON U.USUARIO = dbo.FNK_VALORVARIABLE('USUARIOJEFERH')
		LEFT JOIN ARCHIVOS A ON A.ID = U.IDFIRMA
		WHERE CLASE = 'NEMPERIODOPRUEBA' AND QRY_ENVIOS.IDAFILIADO = @NUMDOC;

		RETURN
	END

	IF @METODO = 'ACTUALIZA_NOIF'
	BEGIN
		BEGIN TRY
			SELECT @ID = ID
			FROM OPENJSON(@PARAMETROS) WITH (ID INT '$.ID')

			UPDATE QRY_ENVIOS
			SET ESTADO = 'ENVIADO', FECHA_ENVIO = GETDATE()
			WHERE ID = @ID
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK

		RETURN
	END
END
