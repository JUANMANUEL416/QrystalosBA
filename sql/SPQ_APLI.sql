		END
	END

	/* REQ APLIM: listar citas de agenda bloqueadas por duraci�n (IDAPLIMBLOQUEO) para una cita de aplicaci�n */
	IF @METODO = 'LIST_CIT_BLOQUEO_APLIM'
	BEGIN
		SELECT @CONSECUTIVOCIT = CONSECUTIVOCIT
		FROM OPENJSON(@PARAMETROS)
		WITH (CONSECUTIVOCIT VARCHAR(13) '$.CONSECUTIVOCIT')

		IF COALESCE(@CONSECUTIVOCIT,'') = ''
		BEGIN
			SELECT 'KO' OK
			SELECT 'CONSECUTIVOCIT requerido.' ERROR
			RETURN
		END

		SELECT @IDAPLIM = COALESCE(
			(SELECT CIT.IDAPLIM FROM CIT WHERE CIT.CONSECUTIVO = @CONSECUTIVOCIT AND COALESCE(CIT.IDAPLIM,0) > 0),
			(SELECT TOP 1 APLIM.ID FROM APLIM WHERE APLIM.CONSECUTIVOCIT = @CONSECUTIVOCIT ORDER BY APLIM.ID DESC)
		)

		IF COALESCE(@IDAPLIM,0) <= 0
		BEGIN
			SELECT 'KO' OK
			SELECT 'La cita no tiene aplicaci�n APLIM asociada.' ERROR
			RETURN
		END

		SELECT @FECHAINICIO = CIT.FECHA, @IDSERVICIO = CIT.IDSERVICIO
		FROM CIT WHERE CIT.CONSECUTIVO = @CONSECUTIVOCIT

		SELECT @DURACIONCITA = COALESCE(SER.DURACIONCITA, 20)
		FROM SER WHERE IDSERVICIO = @IDSERVICIO

		SET @FECHA_FIN_PLAN_APLIM = DATEADD(MINUTE, @DURACIONCITA, @FECHAINICIO)

		SELECT 'OK' OK

		SELECT @IDAPLIM AS IDAPLIM, @FECHAINICIO AS FECHA_INICIO_CITA, @FECHA_FIN_PLAN_APLIM AS FECHA_FIN_PLAN

		SELECT C.CONSECUTIVO, C.FECHA, C.IDMEDICO, MED.NOMBRE AS NOMBRE_MEDICO, C.IDSERVICIO, SER.DESCSERVICIO AS DESCSERVICIO
			, COALESCE(C.BLOQUEADO,0) AS BLOQUEADO, C.IDAPLIMBLOQUEO
		FROM CIT C
		LEFT JOIN MED ON C.IDMEDICO = MED.IDMEDICO
		LEFT JOIN SER ON C.IDSERVICIO = SER.IDSERVICIO
		WHERE COALESCE(C.IDAPLIMBLOQUEO,0) = @IDAPLIM
		  AND COALESCE(C.BLOQUEADO,0) = 1
		  AND COALESCE(C.IDAFILIADO,'') = ''
		  AND C.FECHA > DBO.FNK_GETDATE()
		ORDER BY C.FECHA

		RETURN
	END

	/* REQ APLIM: liberar bloqueos de agenda desde hora de fin real (cita cumplida, APLIM aplicado, antes del fin planificado) */
	IF @METODO = 'FINALIZAR_ATENCION_APLIM'
	BEGIN
		SELECT @CONSECUTIVOCIT = CONSECUTIVOCIT, @OBSERVACION = NULLIF(LTRIM(RTRIM(OBSERVACION)),'')
		FROM OPENJSON(@PARAMETROS)
		WITH (
			CONSECUTIVOCIT VARCHAR(13) '$.CONSECUTIVOCIT',
			OBSERVACION VARCHAR(500) '$.OBSERVACION'
		)

		SELECT @FECHA_HORA_FIN_USUARIO = TRY_CONVERT(DATETIME, FECHA_HORA_FIN, 126)
		FROM OPENJSON(@PARAMETROS)
		WITH (FECHA_HORA_FIN VARCHAR(33) '$.FECHA_HORA_FIN')

		IF COALESCE(@CONSECUTIVOCIT,'') = ''
		BEGIN
			SELECT 'KO' OK
			SELECT 'CONSECUTIVOCIT requerido.' ERROR
			RETURN
		END
		IF @OBSERVACION IS NULL OR LEN(@OBSERVACION) < 1
		BEGIN
			SELECT 'KO' OK
			SELECT 'La observaci�n es obligatoria.' ERROR
			RETURN
		END
		IF @FECHA_HORA_FIN_USUARIO IS NULL
		BEGIN
			SELECT 'KO' OK
			SELECT 'FECHA_HORA_FIN inv�lida o requerida (formato ISO 8601).' ERROR
			RETURN
		END

		SELECT @IDAPLIM = COALESCE(
			(SELECT CIT.IDAPLIM FROM CIT WHERE CIT.CONSECUTIVO = @CONSECUTIVOCIT AND COALESCE(CIT.IDAPLIM,0) > 0),
			(SELECT TOP 1 APLIM.ID FROM APLIM WHERE APLIM.CONSECUTIVOCIT = @CONSECUTIVOCIT ORDER BY APLIM.ID DESC)
		)

		IF COALESCE(@IDAPLIM,0) <= 0
		BEGIN
			SELECT 'KO' OK
			SELECT 'La cita no tiene aplicaci�n APLIM asociada.' ERROR
			RETURN
		END

		IF NOT EXISTS (
			SELECT 1 FROM APLIM WHERE APLIM.ID = @IDAPLIM AND APLIM.ESTADO = 'APLICADO' AND COALESCE(APLIM.APLICADO,0) = 1
		)
		BEGIN
			SELECT 'KO' OK
			SELECT 'Solo aplica con APLIM en estado APLICADO.' ERROR
			RETURN
		END

		SELECT @CUMPLIDA = CIT.CUMPLIDA, @FECHAINICIO = CIT.FECHA, @IDSERVICIO = CIT.IDSERVICIO
		FROM CIT WHERE CIT.CONSECUTIVO = @CONSECUTIVOCIT

		IF COALESCE(@CUMPLIDA,0) <> 1
		BEGIN
			SELECT 'KO' OK
			SELECT 'La cita debe estar cumplida (CUMPLIDA = 1).' ERROR
			RETURN
		END

		SELECT @DURACIONCITA = COALESCE(SER.DURACIONCITA, 20)
		FROM SER WHERE IDSERVICIO = @IDSERVICIO

		SET @FECHA_FIN_PLAN_APLIM = DATEADD(MINUTE, @DURACIONCITA, @FECHAINICIO)

		IF @FECHA_HORA_FIN_USUARIO < @FECHAINICIO OR @FECHA_HORA_FIN_USUARIO >= @FECHA_FIN_PLAN_APLIM
		BEGIN
			SELECT 'KO' OK
			SELECT 'La hora de finalizaci�n debe ser mayor o igual al inicio de la cita y anterior al fin planificado de la duraci�n.' ERROR
			RETURN
		END

		IF NOT EXISTS (
			SELECT 1
			FROM CIT
			WHERE COALESCE(IDAPLIMBLOQUEO,0) = @IDAPLIM
			  AND COALESCE(BLOQUEADO,0) = 1
			  AND COALESCE(IDAFILIADO,'') = ''
			  AND CIT.FECHA > DBO.FNK_GETDATE()
			  AND CIT.FECHA >= @FECHA_HORA_FIN_USUARIO
		)
		BEGIN
			SELECT 'KO' OK
			SELECT 'No hay citas bloqueadas futuras a liberar para la hora de fin indicada.' ERROR
			RETURN
		END

		BEGIN TRY
			BEGIN TRAN

			UPDATE CIT
			SET BLOQUEADO = 0, IDAPLIMBLOQUEO = NULL
			WHERE COALESCE(IDAPLIMBLOQUEO,0) = @IDAPLIM
			  AND COALESCE(BLOQUEADO,0) = 1
			  AND COALESCE(IDAFILIADO,'') = ''
			  AND CIT.FECHA >= @FECHA_HORA_FIN_USUARIO
			  AND CIT.FECHA > DBO.FNK_GETDATE()

			SET @LIBERADOS = @@ROWCOUNT

			SELECT @DETALLE_APLIMG = CONCAT('Finalizaci�n anticipada de atenci�n APLIM. Hora fin declarada: ',
				CONVERT(VARCHAR(19), @FECHA_HORA_FIN_USUARIO, 120), '. Registros de agenda liberados: ', CAST(@LIBERADOS AS VARCHAR(10)), '. ', @OBSERVACION)
			FROM USUSU WHERE USUARIO = @USUARIO

			SELECT @ESTADO_ANTERIOR = ESTADO, @ESTADO_NUEVO = ESTADO FROM APLIM WHERE ID = @IDAPLIM

			EXEC SPK_AGREGAR_EVENTO_APLIM @IDAPLIM, 'FINALIZA_ATENCION', @DETALLE_APLIMG, @USUARIO, 'AGENDA', @ESTADO_ANTERIOR, @ESTADO_NUEVO, @OBSERVACION, NULL, NULL

			COMMIT TRAN
		END TRY
		BEGIN CATCH
			IF @@TRANCOUNT > 0 ROLLBACK TRAN
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END CATCH

		SELECT 'OK' OK
		SELECT @LIBERADOS AS REGISTROS_LIBERADOS
		RETURN
	END
