                PLN.DESCPLAN AS CONTRATO,
                SERAC.DESCSERVICIO AS SERVICIO,
                SERAC.CODCUPS,
                SER.IDSERVICIO,
                COALESCE(NULLIF(LTRIM(RTRIM(IART.DESCRIPCION)), ''), SER.DESCSERVICIO) AS MEDICAMENTO,
                APLI.FRECUENCIA,
                SUM(APLIMF.CANTIDAD) AS CANTIDAD,
                APLIM.FECHA_APLI AS FECHA_APLICACION,
                APLIM.FECHAPROXLLAMADA AS FECHA_PROXIMA_LLAMADA,
                MED.NOMBRE AS MEDICO_APLICA,
				APLI.NOAUTORIZACION AS NUMERO_AUTORIZACION,
				APLI.CANTAUT AS CUBRIMIENTO_AUTORIZACION,
                TIPO_ITEM = CASE WHEN COALESCE(APLIMF.CLASE, 'MEDI') = 'MEDI' THEN 'Medicamento' ELSE 'Insumo' END,
                APLIMF.CLASE AS CLASE_APLIMF
            FROM APLIM
                INNER JOIN APLI ON APLIM.IDAPLI = APLI.ID
                INNER JOIN APLIMF ON APLIMF.IDAPLIM = APLIM.ID AND (@VER_INSUMOS = 1 OR APLIMF.CLASE = 'MEDI')
                INNER JOIN AFI ON APLI.IDAFILIADO = AFI.IDAFILIADO
                LEFT JOIN CIT ON APLIM.CONSECUTIVOCIT = CIT.CONSECUTIVO
                LEFT JOIN MED MED_SILLA ON CIT.IDMEDICO = MED_SILLA.IDMEDICO
                INNER JOIN TER ON APLI.IDTERCERO = TER.IDTERCERO
                INNER JOIN PLN ON APLI.IDPLAN = PLN.IDPLAN
                INNER JOIN SER ON APLIMF.IDSERVICIO = SER.IDSERVICIO
                LEFT JOIN IART ON APLIMF.IDARTICULO = IART.IDARTICULO
                LEFT JOIN MED ON APLIM.IDMEDICO_APLI = MED.IDMEDICO
                INNER JOIN SED ON APLI.IDSEDE = SED.IDSEDE
                LEFT JOIN SER SERAC ON SERAC.IDSERVICIO = APLI.IDSERVICIO
            WHERE APLI.ESTADO = 'Activo'
              AND (@FECHAPROXLLAMADA IS NULL
                   OR CONVERT(DATE, APLIM.FECHAPROXLLAMADA) = @FECHAPROXLLAMADA)
              AND (@FECHA_AGEN IS NULL
                   OR CONVERT(DATE, CIT.FECHA) = @FECHA_AGEN)
              AND (@ESTADO = 'Todos' OR APLIM.ESTADO = @ESTADO)
              AND (@IDSEDE = '0' OR APLI.IDSEDE = @IDSEDE)
              AND (
                    @OPCION = 'Todos'
                    OR (@OPCION = 'Confirmadas' AND COALESCE(CIT.CONFIRMADA, 0) = 1)
                    OR (@OPCION = 'No Confirmadas' AND COALESCE(CIT.CONFIRMADA, 0) = 0)
                  )
            GROUP BY APLIM.ID,SED.DESCRIPCION,APLIM.ESTADO,CIT.CONFIRMADA,APLIMF.ESTADO,CIT.FECHA,AFI.DOCIDAFILIADO,AFI.NOMBREAFI,TER.RAZONSOCIAL
				,PLN.DESCPLAN,SERAC.DESCSERVICIO,SERAC.CODCUPS,SER.IDSERVICIO,SER.DESCSERVICIO,APLI.FRECUENCIA,APLIM.FECHA_APLI,APLIM.FECHAPROXLLAMADA,MED.NOMBRE
				,APLI.NOAUTORIZACION,APLI.CANTAUT, APLIMF.CLASE, IART.DESCRIPCION, MED_SILLA.NOMBRE
            ORDER BY SED.DESCRIPCION DESC, AFI.NOMBREAFI, APLIM.ID

            -- Recordset 2: trazabilidad de gestiones (APLIMG) de los mismos filtros
            SELECT
                APLIM.ID AS ID_APLIM,
                AFI.DOCIDAFILIADO AS DOCUMENTO,
                AFI.NOMBREAFI AS PACIENTE,
                SED.DESCRIPCION AS SEDE,
                CASE WHEN COALESCE(CIT.CONFIRMADA, 0) = 1 THEN 'Confirmada' ELSE 'No Confirmada' END AS [Estado de confirmaci�n],
                APLIMG.FECHA AS FECHA_GESTION,
                APLIMG.EVENTO AS TIPO_GESTION,
                APLIMG.ESTADO_ANTERIOR,
                APLIMG.ESTADO_NUEVO,
                APLIMG.DETALLES,
                APLIMG.OBSERVACION,
                APLIMG.PROCEDENCIA,
                APLIMG.USUARIO,
                COALESCE(USU.NOMBRE, APLIMG.USUARIO) AS NOMBRE_USUARIO,
                CAU.DESCCAUSAL AS CAUSAL,
                APLIMG.FECHAPROXLLAMADA AS FECHA_PROXIMA_LLAMADA
            FROM APLIMG
                INNER JOIN APLIM ON APLIMG.IDAPLIM = APLIM.ID
                INNER JOIN APLI ON APLIM.IDAPLI = APLI.ID
                INNER JOIN AFI ON APLI.IDAFILIADO = AFI.IDAFILIADO
                INNER JOIN SED ON APLI.IDSEDE = SED.IDSEDE
                LEFT JOIN CIT ON APLIM.CONSECUTIVOCIT = CIT.CONSECUTIVO
                LEFT JOIN CAU ON CAU.IDCAUSAL = APLIMG.IDCAUSAL
                LEFT JOIN USUSU USU ON USU.USUARIO = APLIMG.USUARIO
            WHERE APLI.ESTADO = 'Activo'
              AND (@FECHAPROXLLAMADA IS NULL
                   OR CONVERT(DATE, APLIM.FECHAPROXLLAMADA) = @FECHAPROXLLAMADA)
              AND (@FECHA_AGEN IS NULL
                   OR CONVERT(DATE, CIT.FECHA) = @FECHA_AGEN)
              AND (@ESTADO = 'Todos' OR APLIM.ESTADO = @ESTADO)
              AND (@IDSEDE = '0' OR APLI.IDSEDE = @IDSEDE)
              AND (
                    @OPCION = 'Todos'
                    OR (@OPCION = 'Confirmadas' AND COALESCE(CIT.CONFIRMADA, 0) = 1)
                    OR (@OPCION = 'No Confirmadas' AND COALESCE(CIT.CONFIRMADA, 0) = 0)
                  )
              AND EXISTS (
                    SELECT 1
                    FROM APLIMF
                    WHERE APLIMF.IDAPLIM = APLIM.ID
                      AND (@VER_INSUMOS = 1 OR APLIMF.CLASE = 'MEDI')
                  )
            ORDER BY AFI.NOMBREAFI, APLIM.ID, APLIMG.FECHA, APLIMG.ID
        END TRY
        BEGIN CATCH
            INSERT INTO @TBLERRORES(ERROR)
            SELECT ERROR_MESSAGE();
        END CATCH

        IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
        BEGIN
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
        END

        RETURN
    END


