CREATE OR ALTER PROCEDURE DBO.SPQ_APLI
@JSON  NVARCHAR(MAX)
WITH
ENCRYPTION
AS
DECLARE @PARAMETROS         NVARCHAR(MAX)  ,@MODELO           VARCHAR(100)    ,@METODO        VARCHAR(100)  ,@USUARIO        VARCHAR(12)
       ,@GRUPO              VARCHAR(8)     ,@SYS_COMPUTERNAME VARCHAR(254)    ,@SEDE          VARCHAR(5)	   ,@A              INT
       ,@IDENTITY           INT            ,@HOY DATETIME = CONVERT(SMALLDATETIME, GETDATE()), @SQL		VARCHAR(MAX)
       ,@PROCESO            VARCHAR(50)    ,@APLI    NVARCHAR(MAX)  ,@APLIM    NVARCHAR(MAX), @APLISER    NVARCHAR(MAX)
              ,@ID     INT       ,@IDAPLI     INT  , @IDAPLIM     INT  , @IDAPLIMF     INT, @IDAPLISER INT, @IDTGEN INT, @CODUNG VARCHAR(5)
       ,@FECHA     DATETIME, @IDSEDE VARCHAR(5), @FILTRO    NVARCHAR(MAX) , @FechaMinima DATETIME,@IDEMEDICA    VARCHAR(4),@FECHA1           DATETIME
       ,@FECHA_STR VARCHAR(10),@MODALIDAD    VARCHAR(10) ,@CONSECUTIVOCIT     VARCHAR(13),@CONSECUTIVO VARCHAR(20), @CONSECUTIVOANT	VARCHAR(20)
       ,@TIPO   VARCHAR(50),@AUTORIZACION  VARCHAR(50) ,@CONSECUTIVOHCA     VARCHAR(13) ,@PROCEDENCIA     VARCHAR(20) ,@IDAFILIADO     VARCHAR(20)
       ,@IDCAUSAL VARCHAR(5), @OBSCAUSA    VARCHAR(255),@IDSERVICIO     VARCHAR(20) ,@IDSERVICIOAC     VARCHAR(20),@IDTERCERO     VARCHAR(20)
       ,@IDPLAN     VARCHAR(6),@CANTIDAD     INT  ,@CANTIDADAPLIMF     INT, @CANTIDADAPLIM INT, @MEDCUSTODIA     BIT,@NOAUTORIZACION     VARCHAR(20)
       ,@APLICADO     BIT , @PVEZ     BIT , @REQBOMBA     BIT, @ACCION     BIT,@CUMPLIDA			INT,@CERRADA			BIT,@PARTICULAR	BIT
       ,@ESTADO     VARCHAR(20) ,@FECHA_APLI     DATETIME ,@FECHA_APLI_STR VARCHAR(10) ,@IDMEDICO_APLI     VARCHAR(20) ,@IDMEDICO    VARCHAR(20)
       ,@FRECUENCIA INT ,@TIPOFRECUENCIA CHAR(1) ,@DURACION INT ,@TIPODURACION CHAR(1) ,@VIA VARCHAR(20) ,@FECHAACTUAL DATETIME ,@FECHAFIN DATETIME
       ,@FECHAINICIO DATETIME,   @FECHAPROXLLAMADA    DATETIME, @SIGUIENTE_FECHA DATE, @FECHA_MENSUAL_BASE DATE, @DIASAVANZAR INT
       ,@FECHA_AGEN VARCHAR(10) ,@DESCSERVICIO VARCHAR(255) ,@DURACIONCITA SMALLINT ,@INTERVALOMIN SMALLINT ,@VALORCOPAGO DECIMAL(14,2)
       ,@CANTAUT INT ,@DETALLE_APLIMG  VARCHAR(500) ,@EVENTO  VARCHAR(30) ,@ESTADO_ANTERIOR     VARCHAR(40) = NULL,@ESTADO_NUEVO        VARCHAR(40) = NULL
       ,@OBSERVACION         VARCHAR(500) = NULL ,@CNSIZSOL       VARCHAR(20),@TIPOCAJA		  VARCHAR(10),@NORECIBOCAJA	VARCHAR(20)
       ,@IDBODEGA       VARCHAR(20), @CHECK1 SMALLINT, @DESCRIPCION  VARCHAR(MAX),@MOTIVO		VARCHAR(100), @DATO1 VARCHAR(255), @CHECK2 SMALLINT
       ,@CHECK3 SMALLINT ,@CHECK4 SMALLINT ,@CODIGO VARCHAR(20), @OPCION VARCHAR(20),@PRIORITARIO	BIT,@MOTIVO_PRIORIDAD VARCHAR(20), @DATO2 VARCHAR(255)
	   ,@CHECKLIST_ENF NVARCHAR(MAX), @TIENE_RESTRICCIONES BIT = 0, @MENSAJES_RESTRICCION NVARCHAR(MAX), @VALIDACION VARCHAR(50), @MENSAJE NVARCHAR(MAX)
	   ,@MED_ANTICIPADO BIT,@FECHAAUT DATETIME,@FECHAAUTVEN DATETIME,@DURACIONCITAAPLI SMALLINT,@CONSECUTIVONUE   VARCHAR(20),@CODCAJA		VARCHAR(6),  @FECHA_CITA_2 DATETIME,@MARCA			BIT,@CNSFACJ		VARCHAR(20),@MINUTOS_LIBRES INT,@CONT			INT, @ISSUBCUTANEO     BIT, @IDPESPECIAL VARCHAR(6)
	   ,@CLASEORDEN VARCHAR(20), @ISINTRAVENOSO     BIT, @IDAREA VARCHAR(20), @CCOSTO_APLIM VARCHAR(20)
       ,@VER_INSUMOS BIT
       ,@FECHA_HORA_FIN_USUARIO DATETIME, @FECHA_FIN_PLAN_APLIM DATETIME, @LIBERADOS INT

DECLARE @FechasAplicacion TABLE (
   FechaAplicacion DATETIME
)

BEGIN
   SET LANGUAGE Spanish
   SET DATEFORMAT dmy

   SELECT @A = ISJSON(@JSON)
   IF @A = 0
   BEGIN
     RAISERROR('Json: Formato Erroneo',16,1)
     RETURN
   END
   PRINT 'INGRESE A SPQ_APLI'
   SELECT *
   INTO #JSON
   FROM OPENJSON (@json)
   WITH (
     MODELO         VARCHAR(100)     '$.MODELO',
     METODO         VARCHAR(100)     '$.METODO',
     USUARIO        VARCHAR(12)      '$.USUARIO',
     PARAMETROS     NVARCHAR(MAX)     AS JSON
   )

   SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS , @USUARIO = USUARIO
   FROM #JSON
   --DEFINICION DE TABLA DE ERRORES
   DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200))
   -- TOMA DEL GRUPO, SYS_COMPUTERNAME, SEDE   DE ACUERDO AL USUARIO
   PRINT 'USUARIO:'+@USUARIO
   --SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO) FROM USUSU WHERE USUARIO = @USUARIO
   SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
   SELECT @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
   IF COALESCE(@SEDE,'') = '' SELECT @SEDE = '01'
   PRINT 'SEDE='+@SEDE

   IF @METODO = 'GET_BODEGA'
   BEGIN
      SELECT 'OK' OK

      SELECT @IDSEDE = JSON_VALUE(@PARAMETROS, '$.IDSEDE'), @MEDCUSTODIA = JSON_VALUE(@PARAMETROS, '$.MEDCUSTODIA')

      SELECT IIF(COALESCE(@MEDCUSTODIA,0)=1,SED.IDBODEGACUSTODIA,SED.IDBODEGALOG) IDBODEGA, IBOD.DESCRIPCION
      FROM SED
      INNER JOIN IBOD ON IBOD.IDBODEGA= IIF(COALESCE(@MEDCUSTODIA,0)=1,SED.IDBODEGACUSTODIA,SED.IDBODEGALOG)
      WHERE IDSEDE = @IDSEDE
      RETURN
   END

   IF @METODO = 'GET_SILLAS'
   BEGIN
      SELECT 'OK' OK

      SELECT @IDSEDE = JSON_VALUE(@PARAMETROS, '$.IDSEDE'), @REQBOMBA = JSON_VALUE(@PARAMETROS, '$.REQBOMBA')
		, @ISSUBCUTANEO = JSON_VALUE(@PARAMETROS, '$.ISSUBCUTANEO'), @ISINTRAVENOSO = JSON_VALUE(@PARAMETROS, '$.ISINTRAVENOSO')

		IF DBO.FNK_VALORVARIABLE('APLIM_VALIDA_MEDSC') = 'SI'
		BEGIN
			SELECT MED.IDMEDICO, MED.NOMBRE
			FROM MED INNER JOIN TGEN ON MED.TIPO_USUARIO = TGEN.CODIGO
			WHERE TABLA = 'MED' AND CAMPO = 'TIPO_USUARIO' AND CHECK2 = 1 AND MED.ESTADO = 'Activo'
			AND (@IDSEDE IS NULL OR IDMEDICO IN (SELECT IDMEDICO FROM MEDS WHERE IDSEDEATENCION = @IDSEDE))
			AND (@REQBOMBA IS NULL OR IDMEDICO IN (SELECT CODIGO FROM TGEN WHERE TGEN.TABLA = 'APLIM' AND TGEN.CAMPO = 'REQBOMBA'))
			AND (@ISSUBCUTANEO IS NULL OR IDMEDICO NOT IN (SELECT CODIGO FROM TGEN WHERE TGEN.TABLA = 'APLIM' AND TGEN.CAMPO = 'REQBOMBA'))
			AND (@ISINTRAVENOSO IS NULL OR IDMEDICO IN (SELECT CODIGO FROM TGEN WHERE TGEN.TABLA = 'APLIM' AND TGEN.CAMPO = 'REQBOMBA'))
		END
		ELSE
		BEGIN
		  SELECT MED.IDMEDICO, MED.NOMBRE
		  FROM MED INNER JOIN TGEN ON MED.TIPO_USUARIO = TGEN.CODIGO
		  WHERE TABLA = 'MED' AND CAMPO = 'TIPO_USUARIO' AND CHECK2 = 1 AND MED.ESTADO = 'Activo'
		  AND (@IDSEDE IS NULL OR IDMEDICO IN (SELECT IDMEDICO FROM MEDS WHERE IDSEDEATENCION = @IDSEDE))
		  AND (@REQBOMBA IS NULL OR IDMEDICO IN (SELECT CODIGO FROM TGEN WHERE TGEN.TABLA = 'APLIM' AND TGEN.CAMPO = 'REQBOMBA'))
		END


      SELECT TOP 1 CCOSTO, DESCRIPCION
      FROM CEN
      WHERE IDSEDE = @IDSEDE

      SELECT KUNG.CODUNG, KUNG.DESCRIPCION
      FROM SEDUNG
      INNER JOIN KUNG ON KUNG.CODUNG=SEDUNG.CODUNG
      WHERE SEDUNG.IDSEDE = @IDSEDE

      RETURN
   END

   IF @METODO = 'GET_DIAS'
	BEGIN
		SELECT @IDMEDICO = IDMEDICO FROM OPENJSON (@PARAMETROS)
		WITH(IDMEDICO VARCHAR(12) '$.IDMEDICO')

      SELECT 'OK' OK

		SELECT CONVERT(varchar,CIT.FECHA,111) as FECHA --, CIT.FECHA
		FROM CIT
		INNER JOIN MED ON CIT.IDMEDICO = MED.IDMEDICO
      INNER JOIN TGEN ON MED.TIPO_USUARIO = TGEN.CODIGO
		WHERE CONVERT(DATE,FECHA) >= CONVERT(DATE, @HOY)
      AND COALESCE(CIT.IDAFILIADO, '') = ''
      AND CIT.IDMEDICO = @IDMEDICO
      AND TGEN.TABLA = 'MED' AND TGEN.CAMPO = 'TIPO_USUARIO' AND CHECK2 = 1
      --AND (@FILTRO IS NULL OR CIT.IDSEDE = @FILTRO)
		GROUP BY CONVERT(varchar,CIT.FECHA,111)
      RETURN
	END

   IF @METODO = 'GET_HORAS'
	BEGIN
		SELECT @IDMEDICO = IDMEDICO, @FECHA_AGEN  = FECHA FROM OPENJSON (@PARAMETROS)
		WITH(IDMEDICO VARCHAR(12) '$.IDMEDICO', FECHA VARCHAR(10) '$.FECHA')

      SELECT 'OK' OK

	  IF DBO.FNK_VALORVARIABLE('VER_THORAS_APLIM') = 'SI'
	  BEGIN
		SELECT CIT.CONSECUTIVO, CONVERT(varchar,CIT.FECHA,108)  AS HORAS
			FROM CIT
			INNER JOIN MED ON CIT.IDMEDICO = MED.IDMEDICO
		  INNER JOIN TGEN ON MED.TIPO_USUARIO = TGEN.CODIGO
			WHERE CONVERT(DATE,FECHA) >= CONVERT(DATE, @HOY)
		  AND TGEN.TABLA = 'MED' AND TGEN.CAMPO = 'TIPO_USUARIO' AND CHECK2 = 1
			AND COALESCE(CIT.IDAFILIADO, '') = ''
			AND COALESCE(CIT.BLOQUEADO,0) = 0
			AND CONVERT(varchar,CIT.FECHA,111) = @FECHA_AGEN
			AND NOT EXISTS(SELECT 1 FROM CIT C INNER JOIN MAGPRP ON C.IDMEDICO = MAGPRP.IDMEDICO AND C.FECHA  >= MAGPRP.FECHAINICIAL AND C.FECHA< MAGPRP.FECHAFINAL WHERE  C.CONSECUTIVO = CIT.CONSECUTIVO)
		  AND (
				CONVERT(DATE, @FECHA_AGEN) > CONVERT(DATE, @HOY)
				OR CIT.FECHA >= GETDATE()
			)
			AND CIT.IDMEDICO = @IDMEDICO
			ORDER BY CIT.FECHA
	  END
	  ELSE
	  BEGIN
		  SELECT TOP 1 CIT.CONSECUTIVO, CONVERT(varchar,CIT.FECHA,108)  AS HORAS
			FROM CIT
			INNER JOIN MED ON CIT.IDMEDICO = MED.IDMEDICO
		  INNER JOIN TGEN ON MED.TIPO_USUARIO = TGEN.CODIGO
			WHERE CONVERT(DATE,FECHA) >= CONVERT(DATE, @HOY)
		  AND TGEN.TABLA = 'MED' AND TGEN.CAMPO = 'TIPO_USUARIO' AND CHECK2 = 1
			AND COALESCE(CIT.IDAFILIADO, '') = ''
			AND COALESCE(CIT.BLOQUEADO,0) = 0
			AND CONVERT(varchar,CIT.FECHA,111) = @FECHA_AGEN
		  AND (
				CONVERT(DATE, @FECHA_AGEN) > CONVERT(DATE, @HOY)
				OR CIT.FECHA >= GETDATE()
			)
			AND CIT.IDMEDICO = @IDMEDICO
			ORDER BY CIT.FECHA
	  END
      RETURN
	END

   IF @METODO = 'GET_APLIMF'
	BEGIN
		SELECT @IDAPLIM = IDAPLIM FROM OPENJSON (@PARAMETROS)
		WITH(IDAPLIM INT '$.IDAPLIM')

      SELECT 'OK' OK

      SELECT APLIMF.ID, APLIMF.IDAPLIM
         , IDARTICULO = COALESCE(SER.IDARTICULO, APLIMF.IDSERVICIO, APLIMF.IDARTICULO)
         , DESC_ART = COALESCE(SER.DESCSERVICIO, IART.DESCRIPCION)
         , APLIMF.IDSERVICIO, SER.DESCSERVICIO DESC_SERVICIO
         , SER.VIA, APLIMF.CANTIDAD, APLIMF.PROCEDENCIA, APLIMF.ESTADO, APLIMF.IDIEXI, IEXI.NOLOTEPEDIDO, APLIMF.CNSIZSOL, APLIMF.MEDCUSTODIA
         , APLIMF.CLASE
      FROM APLIMF
      INNER JOIN SER ON APLIMF.IDSERVICIO = SER.IDSERVICIO
      LEFT JOIN IART ON APLIMF.IDARTICULO = IART.IDARTICULO
      LEFT JOIN IEXI ON IEXI.ID=APLIMF.IDIEXI
      WHERE IDAPLIM = @IDAPLIM
      RETURN
	END

   IF @METODO = 'GET_APLIMG'
	BEGIN
		SELECT @IDAPLIM = IDAPLIM FROM OPENJSON (@PARAMETROS)
		WITH(IDAPLIM INT '$.IDAPLIM')

      SELECT 'OK' OK

      SELECT APLIMG.ID,APLIMG.IDAPLIM,APLIMG.FECHA,APLIMG.EVENTO,APLIMG.DETALLES,APLIMG.PROCEDENCIA,APLIMG.OBSERVACION,APLIMG.USUARIO,APLIMG.ESTADO_ANTERIOR,APLIMG.ESTADO_NUEVO,APLIMG.FECHAPROXLLAMADA,APLIMG.IDCAUSAL,CAU.DESCCAUSAL DESC_CAUSAL
      FROM APLIMG
      INNER JOIN APLIM ON APLIMG.IDAPLIM = APLIM.ID
      LEFT JOIN CAU ON CAU.IDCAUSAL = APLIMG.IDCAUSAL
      WHERE IDAPLIM = @IDAPLIM ORDER BY APLIMG.ID DESC
      RETURN
	END

   /* GET_TRAZABILIDAD_GESTIONES: Informe de gestiones por usuario y tipo en rango de fechas */
   IF @METODO = 'GET_TRAZABILIDAD_GESTIONES'
	BEGIN
		SELECT @FECHAINICIO = CONVERT(DATETIME, JSON_VALUE(@PARAMETROS, '$.FECHA_INICIO'), 120)
		     , @FECHAFIN   = CONVERT(DATETIME, JSON_VALUE(@PARAMETROS, '$.FECHA_FIN'), 120)

		-- Valores por defecto si no se env�an
		IF @FECHAINICIO IS NULL SET @FECHAINICIO = DATEADD(MONTH, -1, @HOY)
		IF @FECHAFIN IS NULL SET @FECHAFIN = @HOY

		SELECT 'OK' OK

		-- Recordset 1: Resumen por MES, USUARIO, TIPO_GESTION (EVENTO), CANTIDAD
		SELECT APLIMG.USUARIO
		     , COALESCE(USU.NOMBRE, APLIMG.USUARIO) NOMBRE_USUARIO
		     , YEAR(APLIMG.FECHA) ANIO
		     , MONTH(APLIMG.FECHA) MES
		     , COALESCE(APLIMG.EVENTO, '(Sin tipo)') TIPO_GESTION
		     , COUNT(1) CANTIDAD_GESTIONES
		     , CONVERT(VARCHAR(10), @FECHAINICIO, 111) + ' - ' + CONVERT(VARCHAR(10), @FECHAFIN, 111) RANGO_FECHAS
		FROM APLIMG
		INNER JOIN APLIM ON APLIMG.IDAPLIM = APLIM.ID
		LEFT JOIN USUSU USU ON USU.USUARIO = APLIMG.USUARIO
		WHERE APLIMG.FECHA >= @FECHAINICIO
		  AND APLIMG.FECHA < DATEADD(DAY, 1, @FECHAFIN)
		GROUP BY APLIMG.USUARIO, USU.NOMBRE, YEAR(APLIMG.FECHA), MONTH(APLIMG.FECHA), APLIMG.EVENTO
		ORDER BY ANIO DESC, MES DESC, APLIMG.USUARIO, CANTIDAD_GESTIONES DESC, TIPO_GESTION

		-- Recordset 2: Total por usuario (subtotal)
		SELECT APLIMG.USUARIO
		     , COALESCE(USU.NOMBRE, APLIMG.USUARIO) NOMBRE_USUARIO
		     , COUNT(1) TOTAL_GESTIONES
		     , CONVERT(VARCHAR(10), @FECHAINICIO, 111) + ' - ' + CONVERT(VARCHAR(10), @FECHAFIN, 111) RANGO_FECHAS
		FROM APLIMG
		INNER JOIN APLIM ON APLIMG.IDAPLIM = APLIM.ID
		LEFT JOIN USUSU USU ON USU.USUARIO = APLIMG.USUARIO
		WHERE APLIMG.FECHA >= @FECHAINICIO
		  AND APLIMG.FECHA < DATEADD(DAY, 1, @FECHAFIN)
		GROUP BY APLIMG.USUARIO, USU.NOMBRE
		ORDER BY TOTAL_GESTIONES DESC, APLIMG.USUARIO

		RETURN
	END

   IF @METODO = 'GET_INSUMOS'
	BEGIN
		SELECT @IDSERVICIO = IDSERVICIO, @CONSECUTIVOCIT = CONSECUTIVO  FROM OPENJSON (@PARAMETROS)
		WITH(IDSERVICIO VARCHAR(12) '$.IDSERVICIO', CONSECUTIVO		VARCHAR(20) '$.CONSECUTIVO')

      SELECT 'OK' OK

      SELECT @IDAPLIM = ID FROM APLIM WHERE CONSECUTIVOCIT = @CONSECUTIVOCIT

      SELECT APLIMF.ID, APLIMF.IDAPLIM, APLIMF.IDARTICULO, IART.DESCRIPCION DESC_ART, APLIMF.IDSERVICIO, SER.DESCSERVICIO DESC_SERVICIO, APLIMF.CANTIDAD, APLIMF.PROCEDENCIA, APLIMF.ESTADO, APLIMF.CLASE, APLIMF.CNSMOV, APLIMF.CNSMOV_DEV, CAST(COALESCE(APLIMF.DISPENSADO,0) AS BIT) DISPENSADO, APLIMF.FDISPENSADO, CAST(COALESCE(APLIMF.RECIBIDO,0) AS BIT) RECIBIDO, APLIMF.FRECIBIDO
      FROM APLIMF
      INNER JOIN SER ON SER.IDSERVICIO = APLIMF.IDSERVICIO
      LEFT JOIN IART ON APLIMF.IDARTICULO = IART.IDARTICULO
      WHERE IDAPLIM = @IDAPLIM
      RETURN
	END

	IF @METODO = 'GET_CHECKLIST'
	BEGIN
		SELECT @IDAPLIM = JSON_VALUE(@PARAMETROS, '$.IDAPLIM')

		IF COALESCE(@IDAPLIM, 0) = 0
		BEGIN
			SELECT 'KO' OK
			SELECT 'NO SE PUDO OBTENER EL ID DE APLICACION DEL MEDICAMENTO.' ERROR
			RETURN
		END

		SELECT 'OK' OK

		-- Misma l�gica que la subconsulta FOR JSON que antes iba en el listado de APLIM (pre-agenda)
		-- Incluye CHECK4/DATO2 para validar preguntas restrictivas al aprobar
		SELECT TGEN.TABLA, TGEN.CAMPO, TGEN.CODIGO, TGEN.DATO1, TGEN.DESCRIPCION
			, TGEN.VALOR1, TGEN.VALOR2, TGEN.VALOR3, TGEN.CHECK1, TGEN.CHECK2, TGEN.CHECK3
			, CHECK4 = CAST(COALESCE(TGEN.CHECK4, 0) AS BIT)
			, TGEN.DATO2
		FROM TGEN
		INNER JOIN APLIM ON APLIM.ID = @IDAPLIM
		INNER JOIN APLI ON APLI.ID = APLIM.IDAPLI
		WHERE TGEN.TABLA = 'APLIM'
			AND TGEN.CAMPO = 'CHECKLIST'
			AND TGEN.DATO1 = 'APLIM'
			AND (COALESCE(TGEN.CHECK2, 0) = 0 OR (COALESCE(TGEN.CHECK2, 0) = 1 AND APLI.PVEZ = 1))
			AND (
				COALESCE(TGEN.CHECK3, 0) = 0
				OR (
					COALESCE(TGEN.CHECK3, 0) = 1
					AND EXISTS (
						SELECT 1
						FROM TGENOP
						INNER JOIN (
							SELECT TOP 1 IDSERVICIO
							FROM APLIMF
							WHERE APLIMF.IDAPLIM = APLIM.ID
							ORDER BY APLIMF.ID
						) AS MED ON TGENOP.OPCION = MED.IDSERVICIO
						WHERE TGENOP.TABLA = TGEN.TABLA
							AND TGENOP.CAMPO = TGEN.CAMPO
							AND TGENOP.CODIGO = TGEN.CODIGO
					)
				)
			)
		ORDER BY TGEN.CHECK1

		RETURN
	END

	IF @METODO = 'GET_CHECKLIST_ENF'
	BEGIN
		SELECT @CONSECUTIVOCIT = JSON_VALUE(@PARAMETROS, '$.CONSECUTIVO')

		SELECT @IDAPLIM = ID FROM APLIM WHERE CONSECUTIVOCIT = @CONSECUTIVOCIT

		SELECT 'OK' OK
		SELECT APLIM.ID, APLIM.APLICADO, APLIM.CHECKLIST_ENF, APLIM.OBSERVACION_CHECKLIST_ENF, APLIM.PUNTAJE_CHECKLIST_ENF
        ,CHECKLIST = (SELECT TGEN.TABLA,TGEN.CAMPO,TGEN.CODIGO,TGEN.DATO1,TGEN.DESCRIPCION,TGEN.VALOR1,TGEN.VALOR2,TGEN.VALOR3,TGEN.CHECK1,TGEN.CHECK2,TGEN.CHECK3 FROM TGEN WHERE TGEN.TABLA = 'APLIM' AND TGEN.CAMPO = 'CHECKLIST' AND TGEN.DATO1 = 'APLIM_ENF' AND (COALESCE(TGEN.CHECK2, 0) = 0 OR (COALESCE(TGEN.CHECK2, 0) = 1 AND APLI.PVEZ = 1)) AND (COALESCE(TGEN.CHECK3, 0) = 0 OR (COALESCE(TGEN.CHECK3, 0) = 1 AND EXISTS (SELECT 1 FROM TGENOP INNER JOIN (SELECT TOP 1 IDSERVICIO FROM APLIMF WHERE APLIMF.IDAPLIM = APLIM.ID ORDER BY APLIMF.ID) AS MED ON TGENOP.OPCION = MED.IDSERVICIO WHERE TGENOP.TABLA = TGEN.TABLA AND TGENOP.CAMPO = TGEN.CAMPO AND TGENOP.CODIGO = TGEN.CODIGO))) ORDER BY TGEN.CHECK1 FOR JSON PATH)
		,MEDICAMENTOS = (SELECT SER.IDSERVICIO, SER.DESCSERVICIO FROM APLIMF INNER JOIN SER ON SER.IDSERVICIO=APLIMF.IDSERVICIO WHERE APLIMF.IDAPLIM=APLIM.ID AND APLIMF.CLASE='MEDI' FOR JSON PATH)
        FROM APLIM INNER JOIN APLI ON APLI.ID = APLIM.IDAPLI
		WHERE APLIM.ID = @IDAPLIM
		RETURN
	END

   IF @METODO = 'APLIM_CONFIG'
	BEGIN
		SELECT @PARAMETROS = DATOS, @PROCESO = PROCESO
		FROM   OPENJSON (@PARAMETROS)
		WITH (
			PROCESO VARCHAR(50) '$.PROCESO'
			,DATOS  NVARCHAR(MAX)  AS JSON
		)

      BEGIN TRY

         IF UPPER(@PROCESO) = 'CHECKLIST'
         BEGIN
            PRINT 'INGRESE A CHECKLIST'

            SELECT @CHECK1 = JSON_VALUE(@PARAMETROS, '$.CHECK1'), @DESCRIPCION = JSON_VALUE(@PARAMETROS, '$.DESCRIPCION')
               , @IDTGEN = JSON_VALUE(@PARAMETROS, '$.IDTGEN'), @DATO1 = JSON_VALUE(@PARAMETROS, '$.DATO1'), @CHECK2 = CAST(JSON_VALUE(@PARAMETROS, '$.CHECK2') AS BIT)
               , @CHECK3 = CAST(JSON_VALUE(@PARAMETROS, '$.CHECK3') AS BIT) , @CHECK4 = CAST(JSON_VALUE(@PARAMETROS, '$.CHECK4') AS BIT), @DATO2 = JSON_VALUE(@PARAMETROS, '$.DATO2')

            IF COALESCE(@CHECK1,'')<>'' AND EXISTS(SELECT 1 FROM TGEN WHERE TABLA = 'APLIM' AND CAMPO = 'CHECKLIST' AND CHECK1 = @CHECK1 AND DATO1 = @DATO1)
            BEGIN
               SELECT 'KO' OK
               SELECT 'YA EXISTE UNA PREGUNTA EN ESTE ORDEN POR FAVOR VALIDE.' ERROR
               RETURN
            END

            IF COALESCE(@CHECK1,'')<>'' -- ORDEN DE LA PREGUNTA
                UPDATE TGEN SET CHECK1 = @CHECK1, CODIGO = @DATO1 + '-1.' + CAST(@CHECK1 AS VARCHAR(3)) WHERE IDTGEN = @IDTGEN
            ELSE IF COALESCE(@DESCRIPCION,'')<>''
                UPDATE TGEN SET DESCRIPCION = @DESCRIPCION WHERE IDTGEN = @IDTGEN
            ELSE IF @CHECK2 IS NOT NULL -- INDICA SI ES UNA PREGUNTA DE SOLO DE 1RA VEZ (PACIENTES DE 1RA VEZ APLI.PVEZ)
                UPDATE TGEN SET CHECK2 = @CHECK2 WHERE IDTGEN = @IDTGEN
            ELSE IF @CHECK3 IS NOT NULL -- -- INDICA SI ES UNA PREGUNTA SOLO PARA CIERTOS MEDICAMENTOS (LOS MEDICAMENTOS QUEDAN CONFIGURADOS EN TGENOP)
                UPDATE TGEN SET CHECK3 = @CHECK3 WHERE IDTGEN = @IDTGEN
			ELSE IF @CHECK4 IS NOT NULL -- -- INDICA SI ES UNA PREGUNTA RESTRICTIVA
                UPDATE TGEN SET CHECK4 = @CHECK4 WHERE IDTGEN = @IDTGEN

			IF @DATO2 IS NOT NULL -- -- RESPUESTA QUE ES RESTRICTIVA
                UPDATE TGEN SET DATO2 = @DATO2 WHERE IDTGEN = @IDTGEN

         END

         IF UPPER(@PROCESO) = 'CHECKLIST_ADD'
         BEGIN
            PRINT 'INGRESE A CHECKLIST_ADD'

