/*
  Relleno CUFE en IMOV desde FRADIAN.UUID (solo lista FACTU · 03/10/2026).
  CEM. Especificación — ejecutar en ventana de mantenimiento.

  Precondiciones:
    - Entrada compra (USVGS IDINVMOV_COMPRAS), IMOV.CUFE vacío.
    - Un solo UUID en FRADIAN para NIT + NODOCUMENTO de la CxP.
    - Preferir SPK_SINCRONIZAR_CUFE_RADIAN por CNSMOV desde inv.ges cuando exista.

  No toca FCOM (no hay columna CUFE). Después ejecutar VERIFICACION_CUFE_OC_RADIAN_OCT2026.sql
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @DOC TABLE (
  CNSFCXP      varchar(20) NOT NULL PRIMARY KEY,
  NOREFERENCIA varchar(20) NOT NULL
);

INSERT INTO @DOC (CNSFCXP, NOREFERENCIA) VALUES
  (N'03CM002017', N'FE5150'),
  (N'03CM001933', N'FE603306');

DECLARE @FIX TABLE (
  CNSMOV varchar(20) NOT NULL PRIMARY KEY,
  CUFE   varchar(200) NOT NULL,
  CNSRADIAN varchar(20) NOT NULL
);

INSERT INTO @FIX (CNSMOV, CUFE, CNSRADIAN)
SELECT
  M.CNSMOV,
  LTRIM(RTRIM(R.UUID)),
  R.CNSRADIAN
FROM @DOC D
INNER JOIN dbo.FCXP P ON P.CNSFCXP = D.CNSFCXP
INNER JOIN dbo.TER T ON T.IDTERCERO = P.IDTERCERO
INNER JOIN dbo.IMOV M ON M.CNSFCOM = P.CNSFCOM
CROSS APPLY (
  SELECT TOP 1 FR.CNSRADIAN, FR.UUID
  FROM dbo.FRADIAN FR
  WHERE FR.NIT = T.NIT
    AND (
      FR.NODOCUMENTO = D.NOREFERENCIA
      OR FR.NODOCUMENTO = D.NOREFERENCIA + N'.'
      OR REPLACE(FR.NODOCUMENTO, N'FE-', N'FE') = REPLACE(D.NOREFERENCIA, N'FE-', N'FE')
    )
  ORDER BY FR.FECHA DESC
) R
WHERE P.ESTADO = N'N'
  AND COALESCE(P.CONTABILIZADA, 0) = 0
  AND COALESCE(M.ESTADO, 0) <> 2
  AND LTRIM(RTRIM(COALESCE(M.CUFE, N''))) = N''
  AND LEN(LTRIM(RTRIM(R.UUID))) >= 90;

/* FE603306: si el tercero en FCXP sigue Todo Drogas, cruzar Radian por NIT RAMEDICAS */
INSERT INTO @FIX (CNSMOV, CUFE, CNSRADIAN)
SELECT M.CNSMOV, LTRIM(RTRIM(R.UUID)), R.CNSRADIAN
FROM dbo.IMOV M
INNER JOIN dbo.FCXP P ON P.CNSFCOM = M.CNSFCOM AND P.CNSFCXP = N'03CM001933'
CROSS APPLY (
  SELECT TOP 1 FR.CNSRADIAN, FR.UUID
  FROM dbo.FRADIAN FR
  WHERE FR.NIT LIKE N'901429936%'
    AND FR.NODOCUMENTO IN (N'FE603306', N'FE-603306')
  ORDER BY FR.FECHA DESC
) R
WHERE NOT EXISTS (SELECT 1 FROM @FIX F WHERE F.CNSMOV = M.CNSMOV)
  AND LTRIM(RTRIM(COALESCE(M.CUFE, N''))) = N''
  AND LEN(LTRIM(RTRIM(R.UUID))) >= 90;

BEGIN TRAN;

IF EXISTS (
  SELECT 1
  FROM @FIX F
  INNER JOIN dbo.IMOV M ON M.CNSMOV = F.CNSMOV
  WHERE LTRIM(RTRIM(COALESCE(M.CUFE, N''))) <> N''
)
BEGIN
  ROLLBACK TRAN;
  THROW 54001, 'Alguna entrada ya tiene CUFE. No se cambio nada.', 1;
END;

UPDATE M
SET CUFE = F.CUFE
FROM dbo.IMOV M
INNER JOIN @FIX F ON F.CNSMOV = M.CNSMOV
WHERE LTRIM(RTRIM(COALESCE(M.CUFE, N''))) = N'';

IF EXISTS (
  SELECT 1
  FROM @FIX F
  INNER JOIN dbo.IMOV M ON M.CNSMOV = F.CNSMOV
  WHERE LTRIM(RTRIM(M.CUFE)) <> F.CUFE
)
BEGIN
  ROLLBACK TRAN;
  THROW 54002, 'El CUFE no quedo en IMOV. No se cambio nada.', 1;
END;

COMMIT TRAN;

SELECT N'CUFE actualizado' AS RESULTADO, F.CNSMOV, F.CNSRADIAN, LEFT(F.CUFE, 24) AS CUFE_INI
FROM @FIX F
INNER JOIN dbo.IMOV M ON M.CNSMOV = F.CNSMOV;
