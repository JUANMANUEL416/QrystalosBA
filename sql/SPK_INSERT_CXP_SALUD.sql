IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='SPK_INSERT_CXP_SALUD' AND XTYPE='P')
BEGIN
 DROP PROCEDURE SPK_INSERT_CXP_SALUD
END

GO
CREATE PROCEDURE DBO.SPK_INSERT_CXP_SALUD
	@CNSFCXP VARCHAR(20),
	@N_PRESUP VARCHAR(20)
WITH ENCRYPTION
AS
DECLARE @VALOR DECIMAL(14,2)
DECLARE @VLR_DESCUENTO DECIMAL(14,2)  
DECLARE @VLR_IVA DECIMAL(14,2)
DECLARE @VLR_NETO DECIMAL(14,2)

DECLARE @VALOR_CUR DECIMAL(14,2)
DECLARE @VLR_DESCUENTO_CUR DECIMAL(14,2)  
DECLARE @VLR_IVA_CUR DECIMAL(14,2)
DECLARE @VLR_NETO_CUR DECIMAL(14,2)
DECLARE @IDTERCERO_CUR VARCHAR(20)
DECLARE @IDSERVICIO_CUR VARCHAR(20)
DECLARE @CANTIDAD_CUR DECIMAL(14,2)
DECLARE @IDGRUPOIMP_CUR VARCHAR(2)

DECLARE @ITEM_CUR INT
DECLARE @ITEM INT
DECLARE @ITEM_ANT INT

DECLARE @PREFIJO	VARCHAR(20)
DECLARE @CCOSTO		VARCHAR(20)
DECLARE @IDAREA		VARCHAR(20)
DECLARE @IDAREAH	VARCHAR(20)
DECLARE @CODUNG VARCHAR(5)
DECLARE @CODPRG VARCHAR(20)

BEGIN

 SELECT @CODUNG = CODUNG, @CODPRG = CODPRG
 FROM FCXP WHERE CNSFCXP = @CNSFCXP

 DECLARE CUR_FXP CURSOR FOR
 SELECT FXPD.IDSERVICIO,FXPD.CANTIDAD,FXPD.VALOR,FXPD.ITEM,LEFT(PRE.IDTIPOSER,2), 
	FXPD.PREFIJO, FXPD.CCOSTO, FXPD.IDAREA, FXPD.IDAREAH
 FROM FXPD,SER,PRE
 WHERE	FXPD.N_PRESUP=@N_PRESUP AND FXPD.ESTADO='S' AND 
	FXPD.IDSERVICIO=SER.IDSERVICIO AND SER.PREFIJO=PRE.PREFIJO
  
 OPEN CUR_FXP

 FETCH NEXT FROM CUR_FXP
 INTO @IDSERVICIO_CUR, @CANTIDAD_CUR, @VALOR_CUR, @ITEM_CUR, @IDGRUPOIMP_CUR, @PREFIJO, @CCOSTO, @IDAREA, @IDAREAH

 SELECT @ITEM=MAX(ITEM)+1 FROM FCXPD WHERE CNSFCXP=@CNSFCXP
 IF @ITEM IS NULL
 BEGIN
  SET @ITEM=1
 END
 SET @ITEM_ANT=@ITEM
 WHILE @@FETCH_STATUS = 0
 BEGIN  
  INSERT INTO FCXPD (CNSFCXP,ITEM,IDSERVICIO,CANTIDAD,VALOR,VLR_DESCUENTO,VLR_IVA,VLR_NETO,ESTADO,
                     N_PRESUP,ITEM_PRESUP,IDCLASEIMP, PREFIJO, CCOSTO, IDAREA, IDAREAH, VLR_GLOSAS,
                     CUENTA_SER, CODUNG, CODPRG, PROCEDENCIA)
  SELECT @CNSFCXP,@ITEM,@IDSERVICIO_CUR,@CANTIDAD_CUR,@VALOR_CUR,0,0,@VALOR_CUR*@CANTIDAD_CUR,'P',
	 @N_PRESUP,@ITEM_CUR,@IDGRUPOIMP_CUR, @PREFIJO, @CCOSTO, @IDAREA, @IDAREAH, 0,
         DBO.FNK_CUENTA_KMCOM(DBO.FNK_VALORVARIABLE('IDMODELOCONTABLE'),'CXP_SALUD','DB',@PREFIJO,@IDAREA,@CCOSTO,'P',''), 
         @CODUNG, @CODPRG, 'Salud'
  SET @ITEM=@ITEM+1
  FETCH NEXT FROM CUR_FXP
  INTO @IDSERVICIO_CUR, @CANTIDAD_CUR, @VALOR_CUR, @ITEM_CUR, @IDGRUPOIMP_CUR, @PREFIJO, @CCOSTO, @IDAREA, @IDAREAH
 END
 CLOSE CUR_FXP
 DEALLOCATE CUR_FXP

 IF @ITEM_ANT<>@ITEM
 BEGIN
  UPDATE FCXP 
  SET VALOR=X.VALORTOTAL, SALDO=X.VLR_NETO-ISNULL(VLR_NOTASDEBITO,0)+ISNULL(VLR_NOTASCREDITO,0), 
      VLR_DESCUENTO=X.VLR_DESCUENTO, VLR_IVA=X.VLR_IVA, VLR_NETO=X.VLR_NETO
  FROM (SELECT SUM(VALOR*CANTIDAD) VALORTOTAL, SUM(VLR_NETO) VLR_NETO, SUM(VLR_DESCUENTO) VLR_DESCUENTO, SUM(VLR_IVA) VLR_IVA
        FROM FCXPD WHERE CNSFCXP=@CNSFCXP) X
  WHERE FCXP.CNSFCXP=@CNSFCXP

  UPDATE FXPD SET ESTADO='E' WHERE N_PRESUP=@N_PRESUP AND ESTADO='S'
  UPDATE FXP SET ESTADO='E' WHERE N_PRESUP=@N_PRESUP
 END
END
