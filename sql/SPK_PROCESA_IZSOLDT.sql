CREATE OR ALTER PROCEDURE DBO.SPK_PROCESA_IZSOLDT
	@CNSIZSOL VARCHAR(20),
	@CNSMOV   VARCHAR(20),
	@COMPANIA VARCHAR(2),
	@IDSEDE   VARCHAR(5),
	@USUARIO  VARCHAR(12)
WITH ENCRYPTION
AS
/* 
Fecha:		 2018-09-25
Descripci�n: Procedimiento que pasar� de IZSOLDT a IMOVH para su confirmaci�n
*/
DECLARE @CURSOR TABLE (ID INT IDENTITY, CNSIZSOLD VARCHAR(20) COLLATE DATABASE_DEFAULT, IDARTICULO VARCHAR(20) COLLATE DATABASE_DEFAULT, IDITAR VARCHAR(2) COLLATE DATABASE_DEFAULT)
DECLARE @I INT, @I_TO INT, @CNSIZSOLD VARCHAR(20), @IDARTICULO VARCHAR(20), @IDITAR VARCHAR(2), @IDITARHEMODERIVADOS VARCHAR(20)
BEGIN
	PRINT 'EXEC SPK_PROCESA_IZSOLDT '''+ISNULL(@CNSIZSOL,'')+''', '''+ISNULL(@CNSMOV,'')+''', '''+ISNULL(@COMPANIA,'')+''', '''+ISNULL(@IDSEDE,'')+''', '''+ISNULL(@USUARIO,'')+''' '
    
	SELECT @IDITARHEMODERIVADOS = DATO COLLATE DATABASE_DEFAULT FROM USVGS WHERE IDVARIABLE = 'IDITARHEMODERIVADOS'

	INSERT INTO @CURSOR (CNSIZSOLD, IDARTICULO, IDITAR)
	SELECT IZSOLD.CNSIZSOLD, IZSOLD.IDARTICULO, IART.IDITAR 
	FROM IZSOL 
		INNER JOIN IZSOLD ON IZSOLD.CNSIZSOL=IZSOL.CNSIZSOL
		INNER JOIN IZSOLDT ON IZSOLDT.CNSIZSOLD=IZSOLD.CNSIZSOLD
		INNER JOIN IART   ON IART.IDARTICULO = IZSOLDT.IDARTICULOREAL
	WHERE IZSOL.CNSIZSOL=@CNSIZSOL AND IZSOLDT.ESTADO=0
	GROUP BY IZSOLD.CNSIZSOLD, IZSOLD.IDARTICULO, IART.IDITAR --STORRES

	SELECT @I=1, @I_TO=MAX(ID) FROM @CURSOR
	WHILE @I <= @I_TO
	BEGIN
		SELECT @CNSIZSOLD=CNSIZSOLD, @IDARTICULO=IDARTICULO, @IDITAR=IDITAR FROM @CURSOR WHERE ID=@I

		IF @IDITAR = @IDITARHEMODERIVADOS
			EXEC SPK_ENVIA_PRUEBASCRUZADAS @CNSIZSOL, @IDSEDE, @COMPANIA, @USUARIO
		ELSE
		BEGIN
        	EXEC SPK_ASIGNA_ARTSOLICITUDES_CM @CNSIZSOLD, @IDARTICULO, @USUARIO, @CNSMOV
		END
		SET @I += 1
	END
	DELETE @CURSOR
END
