IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='FNK_VALIDA_TOPE_FACTURA' AND XTYPE='FN')
BEGIN
   DROP FUNCTION FNK_VALIDA_TOPE_FACTURA
END
GO
CREATE FUNCTION DBO.FNK_VALIDA_TOPE_FACTURA(@PROCEDENCIA VARCHAR(20),@MONTO DECIMAL(14,2))
RETURNS SMALLINT
AS
BEGIN
   DECLARE @OK BIT 
   IF EXISTS(SELECT  * FROM TGEN WHERE TABLA='General' AND CAMPO='TOPEFACTURA' AND CODIGO=@PROCEDENCIA AND VALOR1>0)
   BEGIN
      --ENCUENTRO TOPE
        IF EXISTS(SELECT  * FROM TGEN WHERE TABLA='General' AND CAMPO='TOPEFACTURA' AND CODIGO=@PROCEDENCIA AND VALOR1>=@MONTO)
        BEGIN
           --ESTA DENTRO DEL MONTO 
           SELECT @OK=1
        END
        ELSE
        BEGIN
           SELECT @OK=0
        END
   END
   ELSE
   BEGIN
      --NO SE ENCONTRO PARAMETRIZACION
      SELECT @OK=1
   END
   RETURN @OK
END
