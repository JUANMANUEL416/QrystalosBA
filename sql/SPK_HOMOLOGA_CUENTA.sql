IF EXISTS (SELECT NAME FROM SYSOBJECTS WHERE NAME = 'SPK_HOMOLOGA_CUENTA' AND TYPE = 'P')
BEGIN
   DROP PROCEDURE SPK_HOMOLOGA_CUENTA 
END
GO
CREATE PROCEDURE DBO.SPK_HOMOLOGA_CUENTA  
@CUENTAANTE    VARCHAR(20),  
@CUENTANUEVA   VARCHAR(20),
@PERIOCONTA    VARCHAR(6),
@COMPANIA      VARCHAR(2),
@SEDE          VARCHAR(6),
@USUARIO       VARCHAR(20),
@IDTERCERO     VARCHAR(20)
WITH ENCRYPTION
AS  
DECLARE @EXISTE INT
DECLARE @ANO    VARCHAR(4)
DECLARE @MES    INT
DECLARE @ANON   VARCHAR(4)
DECLARE @MESN   INT
DECLARE @COM              VARCHAR(6)
DECLARE @NOREFERENCIA     VARCHAR(20)
DECLARE @IDMODELOCONT	  VARCHAR(2)
DECLARE @IDPLAN		     VARCHAR(6) 
DECLARE @TIPOTERCONTABLE  VARCHAR(10) 
DECLARE @VALORGLOSAS	     DECIMAL(14,2)
DECLARE @VALORIMPUESTOS	  DECIMAL(14,2)
DECLARE @PREFIJO_USCXS    VARCHAR(10)
DECLARE @INGRESO          VARCHAR(10)
DECLARE @VLRAJUSTEPESO    DECIMAL(14,2)
DECLARE @VLRDTOFINAN      DECIMAL(14,2)
DECLARE @FECHATRA         DATETIME
DECLARE @CUE_OFIN		     VARCHAR(16)
DECLARE @NROCOMPROBANTE   VARCHAR(20)
BEGIN  
   PRINT 'SALDOMESTERFACT'
   SELECT @ANO=LEFT(@PERIOCONTA,4),@MES=CONVERT(INT,RIGHT(@PERIOCONTA,2))
   IF @MES=12
   BEGIN 
      SELECT @MESN=1,@ANON=@ANO+1
   END
   ELSE
   BEGIN
      SELECT @MESN=@MES+1,@ANON=@ANO
   END
   IF(SELECT COUNT(*) FROM SALDOMESTERFAC WHERE ANO=@ANO AND MES=@MES AND CUENTA=@CUENTAANTE)>0
   BEGIN   
      SET @IDMODELOCONT = DBO.FNK_VALORVARIABLE('IDMODELOCONTABLE')
      SET @NROCOMPROBANTE = SPACE(20) 
      EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@MCP',@NROCOMPROBANTE OUTPUT  
      SELECT @NROCOMPROBANTE = @SEDE + REPLACE(SPACE(8 - CASE WHEN LEN(@NROCOMPROBANTE) > 8 THEN 8 ELSE LEN(@NROCOMPROBANTE) END)+LTRIM(RTRIM(@NROCOMPROBANTE)),SPACE(1),0) 
      PRINT '@NROCOMPROBANTE:' + ISNULL(@NROCOMPROBANTE,'')
      SET @COM=LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('IDCON_TCOM_HOTERCUE')))
      SET @PREFIJO_USCXS='@COM'+@COM
      SET @NOREFERENCIA=SPACE(20)
      EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,@PREFIJO_USCXS,@NOREFERENCIA OUTPUT   
      SELECT @NOREFERENCIA = REPLACE(SPACE(8 - LEN(@NOREFERENCIA))+LTRIM(RTRIM(@NOREFERENCIA)),SPACE(1),0)
      PRINT 'Nuevo Comprobante: '+@COM+' '+@NOREFERENCIA
         
      PRINT 'Comprobanrte Contable (MCP)'
      INSERT INTO MCP(NROCOMPROBANTE, COMPANIA, PROCEDENCIA, NOREFERENCIA, ANO, MES, FECHACONTABLE, TOTALDEBITO,
                       TOTALCREDITO, REFERENCIA1, REFERENCIA2, USUARIO, FECHA, LOTE, OBSERVACION, IDSEDE, ESTADO,
                       COMPROBANTE, IDTERCERO)
      SELECT @NROCOMPROBANTE, @COMPANIA, 'MANUAL', @NOREFERENCIA, @ANON, @MESN, DBO.FNK_DIA_DEL_MES(@ANON,@MES,'PRIMERO'),
              0, 0, 'MANUAL', '', @USUARIO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), NULL, 
              'RECLASIFICACION DE CUENTAS CONTABLES', @SEDE, 0, @COM, @IDTERCERO


      INSERT INTO MCH( NROCOMPROBANTE, COMPANIA,  TIPO, CUENTA, IDTERCERO, CCOSTO, DETALLE, VALOR, REFERENCIA1, REFERENCIA2, REFERENCIA3, N_FACTURA, F_FACTURAREF, 
                       F_VENCE, GENERA, CLASE_GENERA, CNSPAGO, ITEMREF, USUARIO, FECHA, PREFIJO, IDAREA, CLASECONT, ESTADO, PROCESO, VALOR_PORCIMP, BASE_IMP, PROCEDENCIA, 
                       REFERENCIA_PRO, CONCILIADO, CNSFCXCXP, CODUNG, CODPRG, ERROR, IDOPERACION, FECHACONCILIACION, IDPROVEEDOR, ENPRESUPUESTO, ESTADOIMP )
      SELECT  @NROCOMPROBANTE, @COMPANIA, CASE WHEN NTZ='DB' AND SF>0 THEN 'CR'  WHEN NTZ='DB' AND SF<0 THEN 'DB' WHEN NTZ='CR' AND SF>0 THEN 'DB'  WHEN NTZ='CR' AND SF<0 THEN 'CR'  END, CUENTA, IDTERCERO, CCOSTO, 'Reclasificacion de Cuentas', ABS(SF), 'HOMOLAGATER', 'HOMOLAGATER', NULL, N_FACTURA, NULL, 
                       NULL, 'Movimiento', NULL, NULL, NULL, @USUARIO, GETDATE(), NULL, DBO.FNK_AREADELCCOSTO(CCOSTO), 'P', 0, 'RECLA_TER', NULL, NULL, 'MANUAL', 
                       NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL
      FROM SALDOMESTERFAC 
      WHERE ANO=@ANO AND MES=@MES 
      AND CUENTA=@CUENTAANTE
      AND COALESCE(SF,0)<>0
      


      INSERT INTO MCH( NROCOMPROBANTE, COMPANIA,  TIPO, CUENTA, IDTERCERO, CCOSTO, DETALLE, VALOR, REFERENCIA1, REFERENCIA2, REFERENCIA3, N_FACTURA, F_FACTURAREF, 
                       F_VENCE, GENERA, CLASE_GENERA, CNSPAGO, ITEMREF, USUARIO, FECHA, PREFIJO, IDAREA, CLASECONT, ESTADO, PROCESO, VALOR_PORCIMP, BASE_IMP, PROCEDENCIA, 
                       REFERENCIA_PRO, CONCILIADO, CNSFCXCXP, CODUNG, CODPRG, ERROR, IDOPERACION, FECHACONCILIACION, IDPROVEEDOR, ENPRESUPUESTO, ESTADOIMP )
      SELECT  @NROCOMPROBANTE, @COMPANIA, CASE WHEN NTZ='DB' AND SF>0 THEN 'DB'  WHEN NTZ='DB' AND SF<0 THEN 'CR'  WHEN NTZ='CR' AND SF>0 THEN 'CR'  WHEN NTZ='CR' AND SF<0 THEN 'DB' END, @CUENTANUEVA, IDTERCERO, CCOSTO, 'Reclasificacion de Cuentas', ABS(SF), 'HOMOLAGATER', 'HOMOLAGATER', NULL, N_FACTURA, NULL, 
                       NULL, 'Movimiento', NULL, NULL, NULL, @USUARIO, GETDATE(), NULL, DBO.FNK_AREADELCCOSTO(CCOSTO), 'P', 0, 'RECLA_TER', NULL, NULL, 'MANUAL', 
                       NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL
      FROM SALDOMESTERFAC 
      WHERE ANO=@ANO AND MES=@MES 
      AND CUENTA=@CUENTAANTE
      AND COALESCE(SF,0)<>0


      EXEC SPK_SUMA_DBCR @NROCOMPROBANTE
      EXEC SPK_REVISAR_COMPROBANTE @COMPANIA,@NROCOMPROBANTE

   END
   PRINT 'COMPROBANTES ERRADOS'
   IF EXISTS(SELECT * FROM MCHE WHERE CUENTA=@CUENTAANTE)
   BEGIN
      UPDATE MCHE SET CUENTA=@CUENTANUEVA WHERE CUENTA=@CUENTAANTE
   END
   PRINT 'CONTABILIDAD'
   IF EXISTS(SELECT * FROM MCP INNER JOIN MCH ON MCP.NROCOMPROBANTE=MCH.NROCOMPROBANTE WHERE CAST(ANO AS VARCHAR(4))+CAST(CASE WHEN MES<10 THEN '0' ELSE '' END AS VARCHAR(1) )+CAST(MES AS VARCHAR(2))>@PERIOCONTA AND MCH.CUENTA=@CUENTAANTE)
   BEGIN
      UPDATE MCH SET CUENTA=@CUENTANUEVA
      FROM MCP INNER JOIN MCH ON MCP.NROCOMPROBANTE=MCH.NROCOMPROBANTE 
      WHERE CAST(ANO AS VARCHAR(4))+CAST(CASE WHEN MES<10 THEN '0' ELSE '' END AS VARCHAR(1) )+CAST(MES AS VARCHAR(2))>@PERIOCONTA 
      AND MCH.CUENTA=@CUENTAANTE
      AND MCH.NROCOMPROBANTE<>@NROCOMPROBANTE
   END

END
