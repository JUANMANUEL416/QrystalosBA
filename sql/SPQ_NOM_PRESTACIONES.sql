CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_PRESTACIONES @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS AS NVARCHAR(MAX), @MODELO AS VARCHAR(100), @METODO AS VARCHAR(100), @USUARIO AS VARCHAR(20);
DECLARE @PROCESO AS VARCHAR(20);
DECLARE @CNSVAC AS VARCHAR(20), @NUMDOC AS VARCHAR(20), @ANO AS VARCHAR(4), @FECHAINI AS DATETIME, @FECHAFIN AS DATETIME, @DIAS AS INT, @PAGADAS AS VARCHAR(2), @CLASE AS 
	VARCHAR(10), @OBSERVACION AS VARCHAR(800), @CNSPAGO AS VARCHAR(20), @IDEVENTO_PAGO AS VARCHAR(6);
DECLARE @SYS_COMPUTERNAME AS VARCHAR(254);
DECLARE @IDSEDE AS VARCHAR(5), @CNSLIQUIDA AS VARCHAR(20), @CNSNUEVO AS VARCHAR(20), @MAXITEM AS INT;
DECLARE @COMPANIA AS VARCHAR(2), @MESINI AS INT, @MESFIN AS INT, @DIASMIN AS INT, @CAMPO AS VARCHAR(12), @FECHAINILIQ AS DATETIME, @FECHAFINLIQ AS DATETIME, @FECHAINIL AS 
	DATETIME, @FECHAFINL AS DATETIME, @CODNOMINA AS VARCHAR(10), @ITEM AS VARCHAR(8), @ITEM_N AS INT, @ITEM_NEW AS VARCHAR(8), @CODCONCEPTO AS VARCHAR(20), @TERAPORTE AS 
	VARCHAR(20), @DIASL AS INT, @DIASBASE AS INT, @BASICO AS DECIMAL(14, 2), @CANTI AS INT, @VALORL AS DECIMAL(14, 2), @VALORD AS DECIMAL(14, 2), @DETALLE AS VARCHAR(100), 
	@ACCION AS VARCHAR(20);
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX));
DECLARE @ADELANTO_CESAN AS DECIMAL(14, 2);
DECLARE @CODCONCEPTO_CUR AS VARCHAR(20);

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			);

	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
	FROM USUSU
	WHERE USUARIO = @USUARIO;

	SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
	FROM UBEQ
	WHERE SYS_ComputerName = @SYS_COMPUTERNAME;

	IF @METODO = 'GUARDAR'
	BEGIN
		EXECUTE SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@NVAC', @LONGITUD = 8, @NVOCONSEC = @CNSVAC OUTPUT;

		BEGIN TRY
			SELECT @NUMDOC = NUMDOC, @ANO = ANO, @FECHAINI = FECHAINI, @FECHAFIN = FECHAFIN, @DIAS = DIAS, @PAGADAS = PAGADAS, @CLASE = CLASE, @OBSERVACION = OBSERVACION, 
				@CNSPAGO = CNSPAGO, @IDEVENTO_PAGO = IDEVENTO_PAGO, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					NUMDOC VARCHAR(20) '$.NUMDOC', ANO VARCHAR(4) '$.ANO', FECHAINI DATETIME '$.FECHAINI', FECHAFIN DATETIME '$.FECHAFIN', DIAS INT '$.DIAS', PAGADAS 
					VARCHAR(2) '$.PAGADAS', CLASE VARCHAR(10) '$.CLASE', OBSERVACION VARCHAR(800) '$.OBSERVACION', CNSPAGO VARCHAR(20) '$.CNSPAGO', IDEVENTO_PAGO 
					VARCHAR(6) '$.IDEVENTO_PAGO', PROCESO VARCHAR(20) '$.PROCESO'
					);

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO NVAC (
						CNSVAC, NUMDOC, ANO, FECHAINI, FECHAFIN, DIAS, DADISFRUTAR, DDISFRUTADOS, DPORDISFRUTAR, DIASPAGOS, PAGADAS, VALOR, CLASE, CNSLIQUIDA, 
						OBSERVACION, ESTADO
						)
					SELECT @CNSVAC, @NUMDOC, @ANO, @FECHAINI, @FECHAFIN, @DIAS, 0, 0, 0, 0, @PAGADAS, 0, @CLASE, 'Sin Cns', @OBSERVACION, 'Preparadas';

					INSERT INTO NVACD (
						CNSVAC, FECHAINI, FECHAFIN, DIAS, INCSABADOS, DADISFRUTAR, DDISFRUTADOS, DPORDISFRUTAR, DIASPAGOS, OBSERVACION, ITEM_REF, ESTADO, BASICO, 
						VALOR, PAGADAS, CNSPAGO, IDEVENTO_PAGO, HORASXDIA, INCDOMINGOS, INCFESTIVOS, MESCALENDARIO, CLASE
						)
					SELECT @CNSVAC, @FECHAINI, @FECHAFIN, @DIAS, 0, 0, 0, 0, 0, @OBSERVACION, 1, 'Generado', 0, 0, @PAGADAS, @CNSPAGO, @IDEVENTO_PAGO, 8, 0, 0, 0, @CLASE;
				END TRY

				BEGIN CATCH
					-- validar uso de la columna item_ref
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE();
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' AS OK;

					SELECT ERROR
					FROM @TBLERRORES;

					RETURN;
				END

				SELECT 'OK' AS OK;

				RETURN;
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @CNSVAC = CNSVAC
					FROM OPENJSON(@PARAMETROS) WITH (CNSVAC VARCHAR(20) '$.CNSVAC');

					UPDATE NVAC
					SET NUMDOC = @NUMDOC, ANO = @ANO, FECHAINI = @FECHAINI, FECHAFIN = @FECHAFIN, DIAS = @DIAS, PAGADAS = @PAGADAS, CLASE = @CLASE, OBSERVACION = @OBSERVACION
					WHERE CNSVAC = @CNSVAC;

					UPDATE NVACD
					SET FECHAINI = @FECHAINI, FECHAFIN = @FECHAFIN, DIAS = @DIAS, PAGADAS = @PAGADAS, CLASE = @CLASE, OBSERVACION = @OBSERVACION
					WHERE CNSVAC = @CNSVAC;
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE();
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' AS OK;

					SELECT ERROR
					FROM @TBLERRORES;

					RETURN;
				END

				SELECT 'OK' AS OK;

				RETURN;
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' AS OK;

			SELECT ERROR
			FROM @TBLERRORES;

			RETURN;
		END

		SELECT 'OK' AS OK;
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @CNSVAC = CNSVAC
		FROM OPENJSON(@PARAMETROS) WITH (CNSVAC VARCHAR(20) '$.CNSVAC');

		BEGIN TRY
			DELETE NVAC
			WHERE CNSVAC = @CNSVAC;
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' AS OK;

			SELECT ERROR
			FROM @TBLERRORES;

			RETURN;
		END

		SELECT 'OK' AS OK;
	END

	IF @METODO = 'CAMBIA_ESTADO'
	BEGIN
		SELECT @NUMDOC = NUMDOC, @ANO = ANO, @MESINI = MESINI, @MESFIN = MESFIN, @CLASE = CLASE, @CNSPAGO = CNSPAGO, @ACCION = ACCION
		FROM OPENJSON(@PARAMETROS) WITH (
				NUMDOC VARCHAR(20) '$.NUMDOC', ANO VARCHAR(4) '$.ANO', MESINI INT '$.MESINI', MESFIN INT '$.MESFIN', CLASE VARCHAR(10) '$.CLASE', CNSPAGO VARCHAR(20) 
				'$.CNSPAGO', ACCION VARCHAR(20) '$.ACCION'
				);

		BEGIN TRY
			IF (@ACCION = 'Pagado')
			BEGIN
				UPDATE NIEPED
				SET NIEPED.PAGADO = '1'
				FROM NIEPED AS NPED
				INNER JOIN NIEPE ON NIEPE.CNSNIEPE = NPED.CNSNIEPE
				WHERE NPED.NUMDOC = @NUMDOC AND NIEPE.NUMDOC = @NUMDOC AND NIEPE.ANO = @ANO AND NIEPE.MES >= @MESINI AND NIEPE.MES <= @MESFIN AND NPED.CODCONCEPTO IN (
						SELECT CODIGO
						FROM TGEN
						WHERE TABLA = 'NOMINA' AND CAMPO = @CLASE
						) AND CNSPAGO = @CNSPAGO;
			END

			IF (@ACCION = 'No Pagar')
			BEGIN
				UPDATE NIEPED
				SET NIEPED.PAGADO = '2'
				FROM NIEPED AS NPED
				INNER JOIN NIEPE ON NIEPE.CNSNIEPE = NPED.CNSNIEPE
				WHERE NPED.NUMDOC = @NUMDOC AND NIEPE.NUMDOC = @NUMDOC AND NIEPE.ANO = @ANO AND NIEPE.MES >= @MESINI AND NIEPE.MES <= @MESFIN AND NPED.CODCONCEPTO IN (
						SELECT CODIGO
						FROM TGEN
						WHERE TABLA = 'NOMINA' AND CAMPO = @CLASE
						) AND CNSPAGO = @CNSPAGO;
			END

			IF (@ACCION = 'Sin Liquidar')
			BEGIN
				UPDATE NIEPED
				SET NIEPED.PAGADO = '0'
				FROM NIEPED AS NPED
				INNER JOIN NIEPE ON NIEPE.CNSNIEPE = NPED.CNSNIEPE
				WHERE NPED.NUMDOC = @NUMDOC AND NIEPE.NUMDOC = @NUMDOC AND NIEPE.ANO = @ANO AND NIEPE.MES >= @MESINI AND NIEPE.MES <= @MESFIN AND NPED.CODCONCEPTO IN (
						SELECT CODIGO
						FROM TGEN
						WHERE TABLA = 'NOMINA' AND CAMPO = @CLASE
						) AND CNSPAGO = @CNSPAGO;
			END

			SELECT 'OK' AS OK;

			SELECT NPED.PAGADO AS PAGADO
			FROM NIEPED AS NPED
			INNER JOIN NIEPE ON NIEPE.CNSNIEPE = NPED.CNSNIEPE
			WHERE NPED.NUMDOC = @NUMDOC AND NIEPE.NUMDOC = @NUMDOC AND NIEPE.ANO = @ANO AND NIEPE.MES >= @MESINI AND NIEPE.MES <= @MESFIN AND NPED.CODCONCEPTO IN (
					SELECT CODIGO
					FROM TGEN
					WHERE TABLA = 'NOMINA' AND CAMPO = @CLASE
					) AND CNSPAGO = @CNSPAGO;
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' AS OK;

			SELECT ERROR
			FROM @TBLERRORES;

			RETURN;
		END

		SELECT 'OK' AS OK;
	END

	IF @METODO = 'GEN_DETALLESPRESTACIONES_NOM'
	BEGIN
		SELECT @CNSVAC = CNSVAC, @CNSLIQUIDA = CNSLIQUIDA, @CLASE = CLASE
		FROM OPENJSON(@PARAMETROS) WITH (CNSVAC VARCHAR(20) '$.CNSVAC', CNSLIQUIDA VARCHAR(20) '$.CNSLIQUIDA', CLASE VARCHAR(10) '$.CLASE');

		BEGIN TRY
			IF (@CNSLIQUIDA = 'Sin Cns')
			BEGIN
				EXECUTE SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@NVACL', @LONGITUD = 8, @NVOCONSEC = @CNSLIQUIDA OUTPUT;

				UPDATE NVAC
				SET CNSLIQUIDA = @CNSLIQUIDA
				WHERE CNSVAC = @CNSVAC;
			END

			INSERT INTO @TBLERRORES (ERROR)
			SELECT CONCAT ('No Existe Una Programcion, Para El Consecutivo ', @CNSVAC, ' Registre Un Detalle.')
			WHERE (
					SELECT COUNT(1)
					FROM NVACD
					WHERE CNSVAC = @CNSVAC
					) = 0;

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				PRINT 'SE CREAN LAS PROGRMACIONES';

				SELECT TOP 1 @CNSPAGO = NVACD.CNSPAGO
				FROM NVAC
				INNER JOIN NVACD ON NVAC.CNSVAC = NVACD.CNSVAC
				WHERE NVAC.CNSLIQUIDA = @CNSLIQUIDA;

				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'la Nomina Se Encuentra cerrada... No se Puede Continuar.'
				WHERE EXISTS (
						SELECT *
						FROM NPER
						WHERE CNSPAGO = @CNSPAGO AND CERRADO = 1
						);

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) <= 0
				BEGIN
					DELETE PREVENT
					WHERE CNSLIQUIDA = @CNSLIQUIDA;

					DELETE NVACD
					FROM NVACD
					WHERE EXISTS (
							SELECT *
							FROM NVAC
							WHERE NVACD.CNSVAC = NVAC.CNSVAC AND CNSLIQUIDA = @CNSLIQUIDA AND EXISTS (
									SELECT *
									FROM NEMP
									WHERE NVAC.NUMDOC = NEMP.NUMDOC
									)
							);

					DELETE NVAC
					WHERE CNSLIQUIDA = @CNSLIQUIDA AND EXISTS (
							SELECT *
							FROM NEMP
							WHERE NVAC.NUMDOC = NEMP.NUMDOC
							);

					DECLARE CURSOR_NVAC CURSOR
					FOR
					SELECT NOMIE.NUMDOC
					FROM NVAC
					INNER JOIN NOMIE ON NVAC.NUMDOC = NOMIE.CODNOMINA
					INNER JOIN NEMP ON NOMIE.NUMDOC = NEMP.NUMDOC
					WHERE NVAC.CNSVAC = @CNSVAC AND NEMP.ESTADO = 'Activo' AND NOT EXISTS (
							SELECT 1
							FROM NVAC
							WHERE CNSVAC = @CNSVAC AND NVAC.NUMDOC = NOMIE.NUMDOC
							);

					PRINT @CNSLIQUIDA;

					OPEN CURSOR_NVAC;

					FETCH NEXT
					FROM CURSOR_NVAC
					INTO @NUMDOC;

					WHILE @@FETCH_STATUS = 0
					BEGIN
						SET @CNSNUEVO = SPACE(20);

						EXECUTE SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE, '@NVAC', @CNSNUEVO OUTPUT;

						SELECT @CNSNUEVO = @IDSEDE + REPLACE(SPACE(8 - LEN(@CNSNUEVO)) + LTRIM(RTRIM(@CNSNUEVO)), SPACE(1), 0);

						PRINT 'INSERTO NVAC...';
						PRINT @CNSLIQUIDA;

						INSERT INTO NVAC (
							CNSVAC, NUMDOC, ANO, FECHAINI, FECHAFIN, DIAS, DADISFRUTAR, DDISFRUTADOS, DPORDISFRUTAR, DIASPAGOS, PAGADAS, ESTADO, VALOR, CLASE, 
							CNSLIQUIDA, OBSERVACION
							)
						SELECT @CNSNUEVO, @NUMDOC, ANO, FECHAINI, FECHAFIN, DIAS, DADISFRUTAR, DDISFRUTADOS, DPORDISFRUTAR, DIASPAGOS, PAGADAS, 'Generado', VALOR, 
							CLASE, CNSLIQUIDA, OBSERVACION
						FROM NVAC
						WHERE CNSVAC = @CNSVAC;

						PRINT 'INSERTO NVACD....';

						SELECT @MAXITEM = MAX(ITEM) + 1
						FROM NVACD;

						INSERT INTO NVACD (
							CNSVAC, FECHAINI, FECHAFIN, DIAS, INCSABADOS, DADISFRUTAR, DDISFRUTADOS, DPORDISFRUTAR, DIASPAGOS, OBSERVACION, ITEM_REF, IDMOTIVOVAC
							, ESTADO, BASICO, VALOR, PAGADAS, CNSPAGO, IDEVENTO_PAGO, IDEVENTO_DESC, HORASXDIA, FORMALIQUIDACION, INCDOMINGOS, INCFESTIVOS, 
							MESCALENDARIO, CLASE
							)
						SELECT @CNSNUEVO, FECHAINI, FECHAFIN, DIAS, INCSABADOS, DADISFRUTAR, DDISFRUTADOS, DPORDISFRUTAR, DIASPAGOS, OBSERVACION, ITEM_REF, 
							IDMOTIVOVAC, 'Generado', BASICO, VALOR, PAGADAS, CNSPAGO, IDEVENTO_PAGO, IDEVENTO_DESC, HORASXDIA, FORMALIQUIDACION, INCDOMINGOS, 
							INCFESTIVOS, MESCALENDARIO, @CLASE
						FROM NVACD
						WHERE CNSVAC = @CNSVAC;

						FETCH NEXT
						FROM CURSOR_NVAC
						INTO @NUMDOC;
					END

					CLOSE CURSOR_NVAC;

					DEALLOCATE CURSOR_NVAC;

					UPDATE NVAC
					SET ESTADO = 'Generado'
					WHERE CNSVAC = @CNSVAC;

					UPDATE NVACD
					SET ESTADO = 'Generado'
					WHERE CNSVAC = @CNSVAC;
				END
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' AS OK;

			SELECT ERROR
			FROM @TBLERRORES;

			RETURN;
		END

		SELECT 'OK' AS OK;
	END

	-- ============================================================
	-- PREPARAR_GENPRESTACIONES
	-- Limpia pren�mina del CNSPAGO, inserta NEMPF y retorna
	-- la lista de empleados a liquidar (uno por NUMDOC).
	-- ============================================================
	IF @METODO = 'PREPARAR_GENPRESTACIONES'
	BEGIN
		SELECT @CNSVAC = CNSVAC
		FROM OPENJSON(@PARAMETROS) WITH (CNSVAC VARCHAR(20) '$.CNSVAC');

		SELECT @PAGADAS = NVACD.PAGADAS, @CLASE = NVACD.CLASE, @CNSPAGO = NVACD.CNSPAGO, @CNSLIQUIDA = NVAC.CNSLIQUIDA
		FROM NVACD
		INNER JOIN NVAC ON NVAC.CNSVAC = NVACD.CNSVAC
		WHERE NVACD.CNSVAC = @CNSVAC;

		BEGIN TRY
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'la Nomina Se Encuentra cerrada... No se Puede Continuar.'
			WHERE EXISTS (
					SELECT *
					FROM NPER
					WHERE CNSPAGO = @CNSPAGO AND CERRADO = 1
					);

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) > 0
			BEGIN
				SELECT 'KO' AS OK;

				SELECT ERROR
				FROM @TBLERRORES;

				RETURN;
			END

			SELECT @FECHAINIL = NVAC.FECHAINI, @FECHAFINL = NVAC.FECHAFIN, @CNSPAGO = C.CNSPAGO, @ANO = NVAC.ANO
			FROM NVAC
			INNER JOIN NOMI AS B ON NVAC.NUMDOC = B.CODNOMINA
			INNER JOIN NVACD AS C ON NVAC.CNSVAC = C.CNSVAC
			WHERE NVAC.CNSVAC = @CNSVAC;

			SELECT @FECHAINI = NPER.FECHAINI, @FECHAFIN = NPER.FECHAFIN, @CODNOMINA = NOMI.CODNOMINA
			FROM NPER
			INNER JOIN NOMI ON NPER.CNSPAGO = @CNSPAGO AND NPER.CODNOMINA = NOMI.CODNOMINA;

			-- Orden obligatorio: NEMPFD_RUN ? NEMPFD ? NEMPF (FK)
			IF OBJECT_ID('dbo.NEMPFD_RUN') IS NOT NULL
			BEGIN
				DELETE NEMPFD_RUN
				WHERE CNSPAGO = @CNSPAGO;
			END

			DELETE NEMPFD
			WHERE CNSPAGO = @CNSPAGO;

			DELETE NEMPF
			WHERE CNSPAGO = @CNSPAGO;

			SELECT @ITEM = MAX(ITEM)
			FROM NEMPF
			WHERE LEFT(ITEM, 3) = 'CAR' AND CNSPAGO = @CNSPAGO;

			IF @ITEM IS NULL OR @ITEM = ''
			BEGIN
				SET @ITEM_NEW = 'CAR00001';
			END
			ELSE
			BEGIN
				SET @ITEM = RIGHT(@ITEM, 5);
				SET @ITEM_N = CAST(@ITEM AS INT);
				SET @ITEM_N = @ITEM_N + 1;
				SET @ITEM_NEW = 'CAR' + RIGHT('0000' + RTRIM(LTRIM(STR(@ITEM_N))), 5);
			END

			IF OBJECT_ID('tempdb..#TMP_EMP_LISTA') IS NOT NULL
				DROP TABLE #TMP_EMP_LISTA;

			CREATE TABLE #TMP_EMP_LISTA (NUMDOC VARCHAR(20) NOT NULL PRIMARY KEY, NOMBRE_EMPLEADO VARCHAR(200) NULL);

			INSERT INTO #TMP_EMP_LISTA (NUMDOC, NOMBRE_EMPLEADO)
			SELECT A.NUMDOC, MAX(LTRIM(RTRIM(COALESCE(D.PRIMERAPELLIDO, '') + ' ' + COALESCE(D.SEGUNDOAPELLIDO, '') + ' ' + COALESCE(D.PRIMERNOMBRE, '') + ' ' + 
							COALESCE(D.SEGUNDONOMBRE, ''))))
			FROM NVAC AS A
			INNER JOIN NVACD AS B ON A.CNSVAC = B.CNSVAC
			INNER JOIN NOMIE AS C ON A.NUMDOC = C.NUMDOC
			INNER JOIN NEMP AS D ON A.NUMDOC = D.NUMDOC
			WHERE A.CNSLIQUIDA = @CNSLIQUIDA AND D.ESTADO = 'Activo'
			GROUP BY A.NUMDOC;

			IF @PAGADAS = 'P'
			BEGIN
				INSERT INTO NEMPF (CNSPAGO, NUMDOC, ITEM)
				SELECT @CNSPAGO, NUMDOC, @ITEM_NEW
				FROM #TMP_EMP_LISTA;
			END
			ELSE
			BEGIN
				INSERT INTO NEMPF (CNSPAGO, NUMDOC, ITEM)
				SELECT @CNSPAGO, NEMP.NUMDOC, @ITEM_NEW
				FROM NEMP
				INNER JOIN NOMIE ON NEMP.NUMDOC = NOMIE.NUMDOC AND NOMIE.CODNOMINA = @CODNOMINA AND NOMIE.ESTADO = 'Activo' AND NEMP.ESTADO = 'Activo'
				GROUP BY NEMP.NUMDOC;

				INSERT INTO NEMPF (CNSPAGO, NUMDOC, ITEM)
				SELECT @CNSPAGO, L.NUMDOC, @ITEM_NEW
				FROM #TMP_EMP_LISTA L
				WHERE NOT EXISTS (
						SELECT 1
						FROM NEMPF F
						WHERE F.CNSPAGO = @CNSPAGO AND F.NUMDOC = L.NUMDOC
						);
			END

			SELECT 'OK' AS OK;

			SELECT @CNSLIQUIDA AS CNSLIQUIDA, @CNSPAGO AS CNSPAGO, @PAGADAS AS PAGADAS, @CLASE AS CLASE, (
					SELECT COUNT(*)
					FROM #TMP_EMP_LISTA
					) AS TOTAL_EMPLEADOS;

			SELECT NUMDOC, NOMBRE_EMPLEADO
			FROM #TMP_EMP_LISTA
			ORDER BY NUMDOC;

			DROP TABLE #TMP_EMP_LISTA;
		END TRY

		BEGIN CATCH
			IF OBJECT_ID('tempdb..#TMP_EMP_LISTA') IS NOT NULL
				DROP TABLE #TMP_EMP_LISTA;

			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();

			SELECT 'KO' AS OK;

			SELECT ERROR
			FROM @TBLERRORES;

			RETURN;
		END CATCH

		RETURN;
	END

	-- ============================================================
	-- GENPRESTACIONES_NOMINA
	-- Procesa UN empleado (NUMDOC). Requiere PREPARAR previo.
	-- PARAMETROS: CNSVAC, NUMDOC
	-- ============================================================
	IF @METODO = 'GENPRESTACIONES_NOMINA'
	BEGIN
		SELECT @CNSVAC = CNSVAC, @NUMDOC = NUMDOC
		FROM OPENJSON(@PARAMETROS) WITH (CNSVAC VARCHAR(20) '$.CNSVAC', NUMDOC VARCHAR(20) '$.NUMDOC');

		IF COALESCE(@NUMDOC, '') = ''
		BEGIN
			SELECT 'KO' AS OK;

			SELECT 'Debe indicar NUMDOC. Utilice PREPARAR_GENPRESTACIONES, luego GENPRESTACIONES_NOMINA por empleado y FINALIZAR_GENPRESTACIONES.' AS ERROR;

			RETURN;
		END

		SELECT @PAGADAS = NVACD.PAGADAS, @CLASE = NVACD.CLASE, @CNSPAGO = NVACD.CNSPAGO, @CNSLIQUIDA = NVAC.CNSLIQUIDA
		FROM NVACD
		INNER JOIN NVAC ON NVAC.CNSVAC = NVACD.CNSVAC
		WHERE NVACD.CNSVAC = @CNSVAC;

		BEGIN TRY
			SELECT @DIASMIN = CONVERT(INT, COALESCE(DBO.FNK_VALORVARIABLE('NOMI_PRIMADIAS_MIN'), 0));

			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'la Nomina Se Encuentra cerrada... No se Puede Continuar.'
			WHERE EXISTS (
					SELECT *
					FROM NPER
					WHERE CNSPAGO = @CNSPAGO AND CERRADO = 1
					);

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) > 0
			BEGIN
				SELECT 'KO' AS OK;

				SELECT ERROR
				FROM @TBLERRORES;

				RETURN;
			END

			SELECT @FECHAINIL = NVAC.FECHAINI, @FECHAFINL = NVAC.FECHAFIN, @CNSPAGO = C.CNSPAGO, @ANO = NVAC.ANO
			FROM NVAC
			INNER JOIN NOMI AS B ON NVAC.NUMDOC = B.CODNOMINA
			INNER JOIN NVACD AS C ON NVAC.CNSVAC = C.CNSVAC
			WHERE NVAC.CNSVAC = @CNSVAC;

			IF DBO.FNK_VALORVARIABLE('PERIODO_PRESTA_NOM') = 'FECHAS'
			BEGIN
				SELECT @FECHAINILIQ = FECHAINI, @FECHAFINLIQ = DATEADD(DAY, 1, FECHAFIN)
				FROM NVAC
				WHERE CNSVAC = @CNSVAC;
			END

			SELECT @FECHAINI = NPER.FECHAINI, @FECHAFIN = NPER.FECHAFIN, @CODNOMINA = NOMI.CODNOMINA
			FROM NPER
			INNER JOIN NOMI ON NPER.CNSPAGO = @CNSPAGO AND NPER.CODNOMINA = NOMI.CODNOMINA;

			SELECT @ITEM_NEW = ITEM
			FROM NEMPF
			WHERE CNSPAGO = @CNSPAGO AND NUMDOC = @NUMDOC;

			IF @ITEM_NEW IS NULL OR @ITEM_NEW = ''
			BEGIN
				SET @ITEM_NEW = 'CAR00001';

				IF NOT EXISTS (
						SELECT 1
						FROM NEMPF
						WHERE CNSPAGO = @CNSPAGO AND NUMDOC = @NUMDOC
						)
				BEGIN
					INSERT INTO NEMPF (CNSPAGO, NUMDOC, ITEM)
					VALUES (@CNSPAGO, @NUMDOC, @ITEM_NEW);
				END
			END

			-- Igual que ORIGINAL: cursor por NUMDOC + IDEVENTO_PAGO (usado como CODCONCEPTO)
			IF OBJECT_ID('tempdb..#TMP_EMP_PRESTA') IS NOT NULL
				DROP TABLE #TMP_EMP_PRESTA;

			CREATE TABLE #TMP_EMP_PRESTA (NUMDOC VARCHAR(20) NOT NULL, CODCONCEPTO VARCHAR(20) NOT NULL, PRIMARY KEY (NUMDOC, CODCONCEPTO)
				);

			INSERT INTO #TMP_EMP_PRESTA (NUMDOC, CODCONCEPTO)
			SELECT A.NUMDOC, E.CODCONCEPTO
			FROM NVAC AS A
			INNER JOIN NVACD AS B ON A.CNSVAC = B.CNSVAC
			INNER JOIN NOMIE AS C ON A.NUMDOC = C.NUMDOC
			INNER JOIN NEMP AS D ON A.NUMDOC = D.NUMDOC
			INNER JOIN NEVE AS E ON E.IDEVENTO = B.IDEVENTO_PAGO
			WHERE A.CNSLIQUIDA = @CNSLIQUIDA AND D.ESTADO = 'Activo' AND A.NUMDOC = @NUMDOC
			GROUP BY A.NUMDOC, E.CODCONCEPTO;

			IF NOT EXISTS (
					SELECT 1
					FROM #TMP_EMP_PRESTA
					)
			BEGIN
				DROP TABLE #TMP_EMP_PRESTA;

				SELECT 'OK' AS OK;

				SELECT @NUMDOC AS NUMDOC, 'SIN_CONCEPTOS' AS ESTADO;

				RETURN;
			END

			DECLARE PGE_CURSOR CURSOR LOCAL FAST_FORWARD
			FOR
			SELECT NUMDOC, CODCONCEPTO
			FROM #TMP_EMP_PRESTA;

			OPEN PGE_CURSOR;

			FETCH NEXT
			FROM PGE_CURSOR
			INTO @NUMDOC, @CODCONCEPTO;

			WHILE @@FETCH_STATUS = 0
			BEGIN
				SELECT TOP 1 @TERAPORTE = NPRFED.IDTERCERO
				FROM NPRFE
				INNER JOIN NPRFED ON NPRFE.CODPRF = NPRFED.CODPRF
				INNER JOIN NCOND ON NCOND.CODPRF = NPRFE.CODPRF
				WHERE NPRFE.NUMDOC = @NUMDOC AND NCOND.CODCONCEPTO = @CODCONCEPTO
				ORDER BY NPRFED.FECHAINI DESC;

				SELECT @DIASL = DATEDIFF(DAY, FECHAING, @FECHAFIN), @DIASBASE = DATEDIFF(DAY, @FECHAINIL, @FECHAFINL), @BASICO = BASICO, @CANTI = HORASXCARGO
				FROM FNK_INFO_NEMPHIS_NEMP(@FECHAFIN, @NUMDOC)

				IF @PAGADAS = 'C'
				BEGIN
					SELECT @VALORL = VALOR_EMPLEADO
					FROM FNK_CALCULO_VALORCONCEPTO_NOM(@NUMDOC, @CODCONCEPTO, @FECHAINI, @FECHAFIN, @CNSPAGO, 1, 0, 0);
				END

				-- C�lculo de provisiones EXACTO del ORIGINAL (sin JOIN que multiplique filas)
				IF @PAGADAS = 'P'
				BEGIN
					IF DBO.FNK_VALORVARIABLE('PERIODO_PRESTA_NOM') = 'FECHAS'
					BEGIN
						SELECT @VALORD = SUM(NIEPED.VALOR_APORTES)
						FROM NIEPE
						INNER JOIN NIEPED ON NIEPE.CNSNIEPE = NIEPED.CNSNIEPE AND NIEPE.NUMDOC = NIEPED.NUMDOC
						WHERE NIEPE.NUMDOC IN (
								SELECT N1.NUMDOC
								FROM NEMP N1
								WHERE EXISTS (
										SELECT 1
										FROM NEMP N2
										WHERE N1.TERCEROID = N2.TERCEROID AND N2.NUMDOC = @NUMDOC
										)
								) AND CAST('01/' + MES + '/' + ANO AS DATETIME) >= @FECHAINILIQ AND CAST('01/' + MES + '/' + ANO AS DATETIME) < @FECHAFINLIQ AND COALESCE(NIEPED
								.PAGADO, 0) = 0 AND NIEPED.CODCONCEPTO IN (
								SELECT CODCONCEPTOA
								FROM NCONDA
								WHERE CODCONCEPTO = @CODCONCEPTO
								);
					END
					ELSE
					BEGIN
						SELECT @VALORD = SUM(NIEPED.VALOR_APORTES)
						FROM NIEPE
						INNER JOIN NIEPED ON NIEPE.CNSNIEPE = NIEPED.CNSNIEPE AND NIEPE.NUMDOC = NIEPED.NUMDOC
						WHERE NIEPE.ANO = @ANO AND NIEPE.NUMDOC IN (
								SELECT N1.NUMDOC
								FROM NEMP N1
								WHERE EXISTS (
										SELECT 1
										FROM NEMP N2
										WHERE N1.TERCEROID = N2.TERCEROID AND N2.NUMDOC = @NUMDOC
										)
								) AND MES >= CASE 
								WHEN @CLASE <> 'PrimaD'
									THEN 1
								ELSE 7
								END AND MES < CASE 
								WHEN @CLASE NOT IN ('PrimaD', 'Cesan', 'ICesan')
									THEN 7
								ELSE 13
								END AND COALESCE(NIEPED.PAGADO, 0) = 0 AND NIEPED.CODCONCEPTO IN (
								SELECT CODCONCEPTOA
								FROM NCONDA
								WHERE CODCONCEPTO = @CODCONCEPTO
								);
					END

					SELECT @VALORD = COALESCE(@VALORD, 0);
				END

				IF @PAGADAS = 'C'
				BEGIN
					IF @DIASBASE > @DIASL
					BEGIN
						IF @DIASL < @DIASMIN
						BEGIN
							DELETE NEMPFD
							WHERE NUMDOC = @NUMDOC AND CNSPAGO = @CNSPAGO;

							DELETE NEMPF
							WHERE NUMDOC = @NUMDOC AND CNSPAGO = @CNSPAGO;

							FETCH NEXT
							FROM PGE_CURSOR
							INTO @NUMDOC, @CODCONCEPTO;

							CONTINUE;
						END
						ELSE
						BEGIN
							SELECT @VALORD = (@VALORL * ROUND(@DIASL, - 1)) / 360;
						END
					END
					ELSE
					BEGIN
						SELECT @VALORD = @VALORL;
					END
				END

				SELECT @ADELANTO_CESAN = 0;

				IF @PAGADAS = 'P' AND @CLASE = 'Cesan' AND COALESCE(@VALORD, 0) > 0
				BEGIN
					SELECT @ADELANTO_CESAN = DBO.FNK_VALOR_ADELANTO_CESAN_PENDIENTE(@NUMDOC, @ANO);

					IF COALESCE(@ADELANTO_CESAN, 0) > 0
					BEGIN
						IF @ADELANTO_CESAN > @VALORD
							SET @ADELANTO_CESAN = @VALORD;
						SET @VALORD = @VALORD - @ADELANTO_CESAN;

						EXECUTE SPQ_ADELANTO_CESAN 'APLICAR', @NUMDOC, @ANO, @CNSPAGO, @ADELANTO_CESAN;
					END
				END

				IF @PAGADAS = 'P'
				BEGIN
					IF COALESCE(@VALORD, 0) <= 0
					BEGIN
						IF @CLASE = 'Cesan' AND COALESCE(@ADELANTO_CESAN, 0) > 0
						BEGIN
							UPDATE NVAC
							SET ESTADO = 'Liquidado'
							WHERE CNSLIQUIDA = @CNSLIQUIDA AND NUMDOC = @NUMDOC;

							UPDATE NVACD
							SET ESTADO = 'Liquidado', VALOR = 0, VALOR_CNSVAC = 0, BASICO = @BASICO
							FROM NVAC
							INNER JOIN NVACD ON NVAC.CNSVAC = NVACD.CNSVAC
							WHERE NVAC.CNSLIQUIDA = @CNSLIQUIDA AND NVAC.NUMDOC = @NUMDOC AND NVACD.CNSPAGO = @CNSPAGO;
						END
						ELSE
						BEGIN
							DELETE NEMPFD
							WHERE CNSPAGO = @CNSPAGO AND NUMDOC = @NUMDOC;

							DELETE NEMPF
							WHERE CNSPAGO = @CNSPAGO AND NUMDOC = @NUMDOC;
						END

						FETCH NEXT
						FROM PGE_CURSOR
						INTO @NUMDOC, @CODCONCEPTO;

						CONTINUE;
					END
				END

				INSERT INTO NEMPFD (
					NUMDOC, CNSPAGO, ITEM, CODCONCEPTO, DETALLE, CANTIDAD, VALOR, VALOR_EMPRESA, VALOR100P, IDTRANSPRESTAMO, NUMDOCPRESTAMO, NUMCUOTA, CODPRF, 
					IDTERCERO, INCLUIR_EXCLUIR, LIQUIDAR, INFO, BASE_PRESTACIONES, ITEMCONCEPTO, VALHORASLAB, GENERANOVEFU, CODNOVEFU, BASE_CALCULO, LINEA
					)
				SELECT @NUMDOC, @CNSPAGO, @ITEM_NEW, @CODCONCEPTO, @DETALLE, CASE 
						WHEN A.CANTIDAD <= 0
							THEN @CANTI
						ELSE A.CANTIDAD
						END, @VALORD, A.VALOR_EMPRESA, @VALORD, A.IDTRANSPRESTAMO, A.NUMDOCPRESTAMO, A.NUMCUOTA, A.CODPRF, COALESCE(@TERAPORTE, @NUMDOC), 
					'Automatica', 'Si', 'No', 'No', A.ITEMCONCEPTO, 1, 0, 0, A.BASE_CALCULO, 1
				FROM FNK_CALCULO_VALORCONCEPTO_NOM(@NUMDOC, @CODCONCEPTO, @FECHAINI, @FECHAFIN, @CNSPAGO, 1, 0, 0) AS A;

				UPDATE NVAC
				SET ESTADO = 'Liquidado'
				WHERE CNSLIQUIDA = @CNSLIQUIDA AND NUMDOC = @NUMDOC;

				UPDATE NVACD
				SET ESTADO = 'Liquidado', VALOR = @VALORD, VALOR_CNSVAC = @VALORD, BASICO = @BASICO
				FROM NVAC
				INNER JOIN NVACD ON NVAC.CNSVAC = NVACD.CNSVAC
				WHERE NVAC.CNSLIQUIDA = @CNSLIQUIDA AND NVAC.NUMDOC = @NUMDOC AND NVACD.CNSPAGO = @CNSPAGO;

				IF @PAGADAS = 'P'
				BEGIN
					DELETE NEMPFD
					WHERE CNSPAGO = @CNSPAGO AND NUMDOC = @NUMDOC AND CODCONCEPTO IN (
							SELECT CODCONCEPTOA
							FROM NCONDA
							WHERE CODCONCEPTO = @CODCONCEPTO
							);
				END

				IF EXISTS (
						SELECT *
						FROM NPERC
						WHERE CNSPAGO = @CNSPAGO AND NUMDOC = @NUMDOC
						)
				BEGIN
					SELECT @CODCONCEPTO_CUR = CODCONCEPTO
					FROM NPERC
					WHERE CNSPAGO = @CNSPAGO AND NUMDOC = @NUMDOC;

					INSERT INTO NEMPFD (
						NUMDOC, CNSPAGO, ITEM, CODCONCEPTO, DETALLE, CANTIDAD, VALOR, VALOR_EMPRESA, VALOR100P, IDTRANSPRESTAMO, NUMDOCPRESTAMO, NUMCUOTA, CODPRF, 
						IDTERCERO, INCLUIR_EXCLUIR, LIQUIDAR, INFO, BASE_PRESTACIONES, ITEMCONCEPTO, VALHORASLAB, GENERANOVEFU, CODNOVEFU, BASE_CALCULO, LINEA
						)
					SELECT @NUMDOC, @CNSPAGO, @ITEM_NEW, @CODCONCEPTO_CUR, @DETALLE, CASE 
							WHEN A.CANTIDAD <= 0
								THEN @CANTI
							ELSE A.CANTIDAD
							END, A.VALOR_EMPLEADO, A.VALOR_EMPRESA, A.VALOR_EMPLEADO, A.IDTRANSPRESTAMO, A.NUMDOCPRESTAMO, A.NUMCUOTA, A.CODPRF, COALESCE(
							@TERAPORTE, @NUMDOC), 'Automatica', 'Si', 'No', 'No', A.ITEMCONCEPTO, 1, 0, 0, A.BASE_CALCULO, 1
					FROM FNK_CALCULO_VALORCONCEPTO_NOM(@NUMDOC, @CODCONCEPTO_CUR, @FECHAINI, @FECHAFIN, @CNSPAGO, 1, 0, 0) AS A;
				END

				EXECUTE SPK_CALCULAR_NEMPF @CNSPAGO, @NUMDOC;

				FETCH NEXT
				FROM PGE_CURSOR
				INTO @NUMDOC, @CODCONCEPTO;
			END

			CLOSE PGE_CURSOR;

			DEALLOCATE PGE_CURSOR;

			IF OBJECT_ID('tempdb..#TMP_EMP_PRESTA') IS NOT NULL
				DROP TABLE #TMP_EMP_PRESTA;

			SELECT 'OK' AS OK;

			SELECT @NUMDOC AS NUMDOC, 'LIQUIDADO' AS ESTADO;
		END TRY

		BEGIN CATCH
			IF CURSOR_STATUS('local', 'PGE_CURSOR') >= 0
			BEGIN
				CLOSE PGE_CURSOR;

				DEALLOCATE PGE_CURSOR;
			END

			IF OBJECT_ID('tempdb..#TMP_EMP_PRESTA') IS NOT NULL
				DROP TABLE #TMP_EMP_PRESTA;

			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();

			SELECT 'KO' AS OK;

			SELECT ERROR
			FROM @TBLERRORES;

			RETURN;
		END CATCH

		RETURN;
	END

	-- ============================================================
	-- FINALIZAR_GENPRESTACIONES
	-- Totales NPER, limpieza NEMPF sin detalle y ajuste IDTERCERO.
	-- ============================================================
	IF @METODO = 'FINALIZAR_GENPRESTACIONES'
	BEGIN
		SELECT @CNSVAC = CNSVAC
		FROM OPENJSON(@PARAMETROS) WITH (CNSVAC VARCHAR(20) '$.CNSVAC');

		SELECT @PAGADAS = NVACD.PAGADAS, @CNSPAGO = NVACD.CNSPAGO, @CNSLIQUIDA = NVAC.CNSLIQUIDA
		FROM NVACD
		INNER JOIN NVAC ON NVAC.CNSVAC = NVACD.CNSVAC
		WHERE NVACD.CNSVAC = @CNSVAC;

		BEGIN TRY
			IF @PAGADAS = 'P'
			BEGIN
				DELETE F
				FROM NEMPF F
				WHERE F.CNSPAGO = @CNSPAGO AND NOT EXISTS (
						SELECT 1
						FROM NEMPFD D
						WHERE D.CNSPAGO = F.CNSPAGO AND D.NUMDOC = F.NUMDOC AND D.ITEM = F.ITEM
						);
			END

			EXECUTE SPK_CALCULAR_NEMPF @CNSPAGO, '';

			UPDATE NPER
			SET TOTAL_INGRESOS = CASE 
					WHEN V.TOTAL_INGRESOS IS NULL
						THEN 0
					ELSE V.TOTAL_INGRESOS
					END, TOTAL_EGRESOS = CASE 
					WHEN V.TOTAL_EGRESOS IS NULL
						THEN 0
					ELSE V.TOTAL_EGRESOS
					END, TOTAL_APORTES = CASE 
					WHEN V.TOTAL_APORTES IS NULL
						THEN 0
					ELSE V.TOTAL_APORTES
					END, TOTAL_PARAFISCALES = CASE 
					WHEN P.TOTAL_PARAFISCALES IS NULL
						THEN 0
					ELSE P.TOTAL_PARAFISCALES
					END
			FROM NPER, (
					SELECT SUM(VALOR_INGRESOS) AS TOTAL_INGRESOS, SUM(VALOR_EGRESOS) AS TOTAL_EGRESOS, SUM(VALOR_APORTES) AS TOTAL_APORTES
					FROM NEMPF
					WHERE CNSPAGO = @CNSPAGO
					) AS V, (
					SELECT SUM(TOTAL_PARAFISCALES) AS TOTAL_PARAFISCALES
					FROM NPERP
					INNER JOIN NPRF ON NPRF.CODPRF = NPERP.CODPRF
					WHERE NPERP.CNSPAGO = @CNSPAGO AND NPRF.CLASE = 'Parafiscal'
					) AS P
			WHERE CNSPAGO = @CNSPAGO;

			UPDATE NPER
			SET TOTAL_NOMINA = TOTAL_INGRESOS + TOTAL_APORTES + TOTAL_PARAFISCALES
			WHERE CNSPAGO = @CNSPAGO;

			UPDATE NEMPFD
			SET IDTERCERO = NEMP.TERCEROID
			FROM NEMPFD
			INNER JOIN NEMP ON NEMPFD.NUMDOC = NEMP.NUMDOC AND IDTERCERO = NEMP.NUMDOC
			WHERE CNSPAGO = @CNSPAGO;

			SELECT 'OK' AS OK;

			SELECT @CNSLIQUIDA AS CNSLIQUIDA, @CNSPAGO AS CNSPAGO;
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();

			SELECT 'KO' AS OK;

			SELECT ERROR
			FROM @TBLERRORES;

			RETURN;
		END CATCH

		RETURN;
	END

	IF @METODO = 'GET_TOTAL_APORTES'
	BEGIN
		SELECT @NUMDOC = NUMDOC, @ANO = ANO, @MESINI = MESINI, @MESFIN = MESFIN, @CLASE = CLASE
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC', ANO VARCHAR(4) '$.ANO', MESINI INT '$.MESINI', MESFIN INT '$.MESFIN', CLASE VARCHAR(10) '$.CLASE'
				);

		SELECT 'OK' AS OK;

		SELECT SUM(A.VALOR_APORTES) AS TOTAL
		FROM NIEPED AS A
		INNER JOIN NIEPE AS B ON A.CNSNIEPE = B.CNSNIEPE AND A.NUMDOC = B.NUMDOC
		WHERE B.NUMDOC IN (
				SELECT N1.NUMDOC
				FROM NEMP AS N1
				WHERE EXISTS (
						SELECT 1
						FROM NEMP AS N2
						WHERE N1.TERCEROID = N2.TERCEROID AND N2.NUMDOC = @NUMDOC
						)
				) AND B.ANO = @ANO AND B.MES >= @MESINI AND B.MES <= @MESFIN AND A.CODCONCEPTO IN (
				SELECT CODIGO
				FROM TGEN
				WHERE TABLA = 'NOMINA' AND CAMPO = CONCAT ('Prov', @CLASE)
				);

		RETURN;
	END
