CREATE OR ALTER PROCEDURE DBO.SPQ_IEXI
	@JSON  NVARCHAR(MAX)
WITH
ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX),  @MODELO   VARCHAR(100),		@METODO     VARCHAR(100),         @USUARIO   VARCHAR(12),   @ID   INT,
        @MODELOACT  NVARCHAR(MAX),  @GASTOS_CONSUMO BIT,	    @GASTOCONSUMOENCERO VARCHAR(120), @A  INT,
		@datoIEXI NVARCHAR(MAX),    @IDARTICULO VARCHAR(20),	@NOLOTE VARCHAR(20),			  @IDBODEGA VARCHAR(20),
		@NOLOTEPEDIDO VARCHAR(50),  @MOTIVO_SALIDA VARCHAR(500),@OBSERVACIONES VARCHAR(1000),	  @FECHA_INGRESO_CUARENTENA DATETIME,
		@SYS_COMPUTERNAME VARCHAR(254)
BEGIN                                                
	SELECT @A = ISJSON(@JSON)
	IF @A = 0 
	BEGIN
		RAISERROR('Json: Formato Erroneo',16,1)
		RETURN
	END
      
	SELECT *
	INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

	SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON

	IF @METODO = 'CONSULTA'
	BEGIN
		SELECT @GASTOS_CONSUMO = GASTOS_CONSUMO
		FROM   OPENJSON (@PARAMETROS)
		WITH ( GASTOS_CONSUMO  BIT)
		
		SELECT @GASTOCONSUMOENCERO = DATO FROM USVGS WHERE IDVARIABLE='GASTOCONSUMOENCERO'

		IF @GASTOS_CONSUMO = 1
		BEGIN
			SELECT IDARTICULO, DESCRIPCION FROM IART WHERE PRINCIPAL=1
			AND ESTADO='Activo'
         AND COALESCE(@GASTOCONSUMOENCERO,'')='SI'
         OR EXISTS	(
			   SELECT * 
            FROM IEXI INNER JOIN VWK_HERMANOS_INVENTARIO HH ON HH.IDARTICULO=IEXI.IDARTICULO 
            WHERE EXISLOTE>0 
            AND HH.HERMANO_MAYOR=IART.IDARTICULO
			)
		END
		RETURN
	END

	IF @METODO = 'EXISTENCIA'
	BEGIN
		
		SELECT @IDBODEGA=IDBODEGA FROM USUSU WHERE USUARIO=@USUARIO
		IF COALESCE(@IDBODEGA,'')='' RETURN
		SELECT IEXI.IDARTICULO,IART.DESCRIPCION,IEXI.EXISLOTE,IEXI.NOLOTE,IEXI.NOLOTEPEDIDO,IEXI.FECHAVENCE 
		FROM IEXI INNER JOIN IART ON IART.IDARTICULO=IEXI.IDARTICULO
		WHERE EXISLOTE>0 AND IDBODEGA=@IDBODEGA
		RETURN
	END

	IF @METODO = 'EDITAR'
	BEGIN
		SELECT 
			@IDBODEGA = IDBODEGA,
			@IDARTICULO = IDARTICULO,
			@NOLOTE = NOLOTE,
			@datoIEXI = datoIEXI
		FROM OPENJSON(@PARAMETROS)
		WITH (
			IDBODEGA    VARCHAR(20)     '$.IDBODEGA',
			IDARTICULO  VARCHAR(20)     '$.IDARTICULO',
			NOLOTE		VARCHAR(20)   '$.NOLOTE',
			datoIEXI    NVARCHAR(MAX)   AS JSON
		);

		SELECT * INTO #datoIEXI
		FROM OPENJSON(@datoIEXI)
		WITH (
			NOLOTEPEDIDO   VARCHAR(20)   '$.NOLOTEPEDIDO',
			FECHAVENCE     DATETIME      '$.FECHAVENCE',
			GRUPORH		   VARCHAR(10)   '$.GRUPORH',
			GRUPOABO	   VARCHAR(10)   '$.GRUPOABO',
			LUGAR1		   VARCHAR(50)   '$.LUGAR1',
			LUGAR2	       VARCHAR(50)   '$.LUGAR2',
			LUGAR3	       VARCHAR(50)   '$.LUGAR3',
			LUGAR4	       VARCHAR(50)   '$.LUGAR4',
			LUGAR5	       VARCHAR(50)   '$.LUGAR5'
		
		);

		UPDATE IEXI SET IEXI.NOLOTEPEDIDO = d.NOLOTEPEDIDO, IEXI.FECHAVENCE = d.FECHAVENCE, IEXI.GRUPORH = d.GRUPORH 
			  ,IEXI.GRUPOABO = d.GRUPOABO,IEXI.LUGAR1 = d.LUGAR1, IEXI.LUGAR2 = d.LUGAR2,IEXI.LUGAR3 = d.LUGAR3
			  ,IEXI.LUGAR4 = d.LUGAR4, IEXI.LUGAR5 = d.LUGAR5
		FROM IEXI
		CROSS JOIN #datoIEXI AS d
		WHERE 
			IEXI.IDBODEGA = @IDBODEGA
			AND IEXI.IDARTICULO = @IDARTICULO
			AND IEXI.NOLOTE = @NOLOTE

		SELECT 'OK'OK
	END

	IF @METODO = 'SACAR_CUARENTENA'
	BEGIN
		SELECT 
			@IDBODEGA = IDBODEGA,
			@IDARTICULO = IDARTICULO,
			@NOLOTE = NOLOTE,
			@NOLOTEPEDIDO = NOLOTEPEDIDO,
			@MOTIVO_SALIDA = MOTIVO_SALIDA,
			@OBSERVACIONES = OBSERVACIONES
		FROM OPENJSON(@PARAMETROS)
		WITH (
			IDBODEGA VARCHAR(20) '$.IDBODEGA',
			IDARTICULO VARCHAR(20) '$.IDARTICULO',
			NOLOTE VARCHAR(20) '$.NOLOTE',
			NOLOTEPEDIDO VARCHAR(50) '$.NOLOTEPEDIDO',
			MOTIVO_SALIDA VARCHAR(500) '$.MOTIVO_SALIDA',
			OBSERVACIONES VARCHAR(1000) '$.OBSERVACIONES'
		)

		-- Obtener SYS_COMPUTERNAME del usuario
		SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO

		-- Validar que el medicamento existe y est� en cuarentena
		IF NOT EXISTS (
			SELECT 1 FROM IEXI 
			WHERE IDBODEGA = @IDBODEGA 
			AND IDARTICULO = @IDARTICULO 
			AND NOLOTE = @NOLOTE
			AND COALESCE(CUARENTENA, 0) = 1
		)
		BEGIN
			SELECT 'KO' OK, 'El medicamento no existe o no est� en cuarentena' ERROR
			RETURN
		END

		-- Validar que el motivo est� lleno
		IF COALESCE(@MOTIVO_SALIDA, '') = ''
		BEGIN
			SELECT 'KO' OK, 'El motivo de salida de cuarentena es obligatorio' ERROR
			RETURN
		END

		BEGIN TRY
			-- Obtener la fecha de ingreso a cuarentena (buscar en el log m�s reciente sin fecha de salida)
			SET @FECHA_INGRESO_CUARENTENA = NULL
			SELECT TOP 1 @FECHA_INGRESO_CUARENTENA = FECHA_INGRESO_CUARENTENA
			FROM IEXI_CUARENTENA_LOG
			WHERE IDBODEGA = @IDBODEGA
			AND IDARTICULO = @IDARTICULO
			AND NOLOTE = @NOLOTE
			AND FECHA_SALIDA_CUARENTENA IS NULL
			ORDER BY ID DESC

			-- Si no hay fecha de ingreso en el log, intentar obtenerla de alg�n movimiento reciente
			IF @FECHA_INGRESO_CUARENTENA IS NULL
			BEGIN
				-- Intentar obtener la fecha del movimiento m�s reciente donde entr� a cuarentena
				SELECT TOP 1 @FECHA_INGRESO_CUARENTENA = IMOV.FECHAMOV
				FROM IMOVH
				INNER JOIN IMOV ON IMOVH.CNSMOV = IMOV.CNSMOV
				WHERE IMOVH.IDARTICULO = @IDARTICULO
				AND IMOVH.NOLOTE = @NOLOTE
				AND IMOV.IDBODEGA = @IDBODEGA
				AND COALESCE(IMOVH.CUARENTENA, 0) = 1
				ORDER BY IMOV.FECHAMOV DESC

				-- Si a�n no hay fecha, usar la fecha actual
				IF @FECHA_INGRESO_CUARENTENA IS NULL
				BEGIN
					SET @FECHA_INGRESO_CUARENTENA = DBO.FNK_GETDATE()
				END
			END

			-- Insertar registro en el log de cuarentena
			INSERT INTO IEXI_CUARENTENA_LOG (
				IDBODEGA,
				IDARTICULO,
				NOLOTE,
				NOLOTEPEDIDO,
				FECHA_INGRESO_CUARENTENA,
				FECHA_SALIDA_CUARENTENA,
				MOTIVO_SALIDA,
				USUARIO,
				SYS_COMPUTERNAME,
				OBSERVACIONES
			)
			VALUES (
				@IDBODEGA,
				@IDARTICULO,
				@NOLOTE,
				@NOLOTEPEDIDO,
				@FECHA_INGRESO_CUARENTENA,
				GETDATE(),
				@MOTIVO_SALIDA,
				@USUARIO,
				@SYS_COMPUTERNAME,
				@OBSERVACIONES
			)

			-- Actualizar IEXI: sacar de cuarentena
			UPDATE IEXI
			SET CUARENTENA = 0
			WHERE IDBODEGA = @IDBODEGA
			AND IDARTICULO = @IDARTICULO
			AND NOLOTE = @NOLOTE

			SELECT 'OK' OK
		END TRY
		BEGIN CATCH
			SELECT 'KO' OK, ERROR_MESSAGE() ERROR
		END CATCH
	END
END
