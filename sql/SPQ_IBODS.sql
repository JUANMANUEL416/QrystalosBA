CREATE OR ALTER PROCEDURE DBO.SPQ_IBODS
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @PARAMETROS   NVARCHAR(MAX), @MODELO         VARCHAR(100),   @METODO   VARCHAR(100)
DECLARE  @USUARIO      VARCHAR(20),   @IDBODEGA       VARCHAR(20),	  @TIPO		VARCHAR(50)
DECLARE	 @VALOR		   VARCHAR(20),   @ACCESO		  VARCHAR(2)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

	IF @METODO = 'GET_TIPO_SEGURIDAD'
	BEGIN
		SELECT 'OK' OK, @TIPO TIPO

		SELECT  @TIPO = TIPO 
		FROM	OPENJSON (@PARAMETROS)
		WITH	(TIPO VARCHAR(50)  '$.TIPO')

		SELECT * FROM TSEG WHERE TIPO = @TIPO
		RETURN
	END

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDBODEGA = IDBODEGA, @TIPO = TIPO, @VALOR = VALOR , @ACCESO = ACCESO  
			FROM	OPENJSON (@PARAMETROS)
			WITH	(
				IDBODEGA VARCHAR(20)  '$.IDBODEGA', TIPO   VARCHAR(50)  '$.TIPO', 
				VALOR	 VARCHAR(20)  '$.VALOR',	ACCESO VARCHAR(2)  '$.ACCESO'
			)

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'LA CONFIGURACION DE SEGURIDAD YA EXISTE'
			WHERE EXISTS (SELECT 1 FROM IBODS WHERE IDBODEGA = @IDBODEGA AND TIPO = @TIPO AND VALOR = @VALOR)

			IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
			BEGIN
				INSERT INTO IBODS (IDBODEGA ,TIPO ,VALOR ,ACCESO) 
				SELECT @IDBODEGA, @TIPO, @VALOR, @ACCESO
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ACTUALIZAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDBODEGA = IDBODEGA, @TIPO = TIPO, @VALOR = VALOR , @ACCESO = ACCESO  
			FROM	OPENJSON (@PARAMETROS)
			WITH	(
				IDBODEGA VARCHAR(20)  '$.IDBODEGA', TIPO   VARCHAR(50)  '$.TIPO', 
				VALOR	 VARCHAR(20)  '$.VALOR',	ACCESO VARCHAR(2)  '$.ACCESO'
			)

			UPDATE IBODS SET ACCESO = @ACCESO WHERE IDBODEGA = @IDBODEGA AND TIPO = @TIPO AND VALOR = @VALOR
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
	
	IF @METODO = 'ELIMINAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDBODEGA = IDBODEGA, @TIPO = TIPO, @VALOR = VALOR  
			FROM	OPENJSON (@PARAMETROS)
			WITH	(
				IDBODEGA VARCHAR(20)  '$.IDBODEGA', TIPO   VARCHAR(50)  '$.TIPO', 
				VALOR	 VARCHAR(20)  '$.VALOR'
			)

			DELETE FROM IBODS WHERE IDBODEGA = @IDBODEGA AND TIPO = @TIPO AND VALOR = @VALOR
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
END
