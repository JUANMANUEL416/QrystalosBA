CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NEMPE @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100)
DECLARE @USUARIO VARCHAR(20), @PROCESO VARCHAR(20)
DECLARE @NUMDOC VARCHAR(20), @CODCONCEPTO VARCHAR(20)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @NUMDOC = NUMDOC, @CODCONCEPTO = CODCONCEPTO, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC', CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO', PROCESO VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('YA SE ENCUENTRA REGISTRADO EL CONCEPTO ', @CODCONCEPTO)
					WHERE EXISTS (
							SELECT 1
							FROM NEMPE
							WHERE NUMDOC = @NUMDOC AND CODCONCEPTO = @CODCONCEPTO
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO NEMPE (NUMDOC, CODCONCEPTO)
						SELECT @NUMDOC, @CODCONCEPTO
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @NUMDOC = NUMDOC, @CODCONCEPTO = CODCONCEPTO
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC', CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO')

		BEGIN TRY
			DELETE
			FROM NEMPE
			WHERE NUMDOC = @NUMDOC AND CODCONCEPTO = @CODCONCEPTO
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
