CREATE OR

ALTER PROCEDURE DBO.SPQ_NOM_NPLT @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20)
DECLARE @PROCESO VARCHAR(20), @DATO NVARCHAR(MAX), @DATOS NVARCHAR(MAX)
DECLARE @IDPLANTILLA VARCHAR(20), @IDPLANTILLAEDITE VARCHAR(20), @DESCRIPCION VARCHAR(255), @ESTADO VARCHAR(11), @WHERES VARCHAR(2000), @QUERY VARCHAR(8000)
DECLARE @CODCARGO VARCHAR(20), @NIVEL VARCHAR(10), @GRADO VARCHAR(10), @CollationName NVARCHAR(150)
DECLARE @SQL NVARCHAR(MAX)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @IDPLANTILLA = IDPLANTILLA, @DESCRIPCION = DESCRIPCION, @ESTADO = ESTADO, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (IDPLANTILLA VARCHAR(20) '$.IDPLANTILLA', DESCRIPCION VARCHAR(255) '$.DESCRIPCION', ESTADO BIT '$.ESTADO', PROCESO VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('EL ID PLANTILLA ', @IDPLANTILLA, ' YA SE ENCUENTRA REGISTRADO')
					WHERE EXISTS (
							SELECT 1
							FROM NPLT
							WHERE IDPLANTILLA = @IDPLANTILLA
							)

					INSERT INTO NPLT (IDPLANTILLA, DESCRIPCION, ESTADO)
					SELECT @IDPLANTILLA, @DESCRIPCION, CASE 
							WHEN @ESTADO = 1
								THEN 'Activa'
							ELSE 'Inactiva'
							END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @DATO = DATO
					FROM OPENJSON(@PARAMETROS) WITH (DATO NVARCHAR(MAX) AS JSON)

					SELECT @IDPLANTILLAEDITE = IDPLANTILLAEDITE
					FROM OPENJSON(@DATO) WITH (IDPLANTILLAEDITE VARCHAR(20) '$.IDPLANTILLAEDITE')

					IF (@IDPLANTILLA <> @IDPLANTILLAEDITE)
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('EL ID PLANTILLA ', @IDPLANTILLA, ' YA SE ENCUENTRA REGISTRADO')
						WHERE EXISTS (
								SELECT 1
								FROM NPLT
								WHERE IDPLANTILLA = @IDPLANTILLA
								)

						UPDATE NPLT
						SET IDPLANTILLA = @IDPLANTILLA, DESCRIPCION = @DESCRIPCION, ESTADO = CASE 
								WHEN @ESTADO = 1
									THEN 'Activa'
								ELSE 'Inactiva'
								END
						WHERE IDPLANTILLA = @IDPLANTILLAEDITE
					END
					ELSE
						UPDATE NPLT
						SET DESCRIPCION = @DESCRIPCION, ESTADO = CASE 
								WHEN @ESTADO = 1
									THEN 'Activa'
								ELSE 'Inactiva'
								END
						WHERE IDPLANTILLA = @IDPLANTILLA
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GET_NPLTCA'
	BEGIN
		SELECT @IDPLANTILLA = IDPLANTILLA
		FROM OPENJSON(@PARAMETROS) WITH (IDPLANTILLA VARCHAR(20) '$.IDPLANTILLA')

		SELECT 'OK' OK

		SELECT NPLTCA.CODCARGO, NCAR.DESCRIPCION, NPLTCA.NIVEL, NPLTCA.GRADO, NCARNG.DESCRIPCION AS CARGO, CONCAT (NCARNG.CODCARGO, NCARNG.NIVEL, NCARNG.GRADO
				) AS ROWKEY
		FROM NPLTCA
		INNER JOIN NCARNG ON NPLTCA.CODCARGO = NCARNG.CODCARGO AND NPLTCA.NIVEL = NCARNG.NIVEL AND NPLTCA.GRADO = NCARNG.GRADO
		INNER JOIN NCAR ON NPLTCA.CODCARGO = NCAR.CODCARGO
		WHERE NPLTCA.IDPLANTILLA = @IDPLANTILLA
		ORDER BY NPLTCA.CODCARGO

		RETURN
	END

	IF @METODO = 'GET_NPLTCO'
	BEGIN
		SELECT @IDPLANTILLA = IDPLANTILLA
		FROM OPENJSON(@PARAMETROS) WITH (IDPLANTILLA VARCHAR(20) '$.IDPLANTILLA')

		SELECT 'OK' OK

		SELECT NPLTCO.CODCONCEPTO, NCON.DESCRIPCION, NCON.TIPO, NCON.CLASE, NCON.ESTADO
		FROM NPLTCO
		INNER JOIN NCON ON NCON.CODCONCEPTO = NPLTCO.CODCONCEPTO
		WHERE NPLTCO.IDPLANTILLA = @IDPLANTILLA

		RETURN
	END

	IF @METODO = 'STATE'
	BEGIN
		BEGIN TRY
			SELECT @IDPLANTILLA = IDPLANTILLA
			FROM OPENJSON(@PARAMETROS) WITH (IDPLANTILLA VARCHAR(20) '$.IDPLANTILLA')

			BEGIN
				UPDATE NPLT
				SET ESTADO = IIF((
							SELECT ESTADO
							FROM NPLT
							WHERE IDPLANTILLA = JSON_VALUE(@PARAMETROS, '$.IDPLANTILLA')
							) = 'Activa', 'Inactiva', 'Activa')
				WHERE IDPLANTILLA = JSON_VALUE(@PARAMETROS, '$.IDPLANTILLA')
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'UPDATE_NPLTCA'
	BEGIN
		BEGIN TRY
			SELECT @DATOS = DATOS, @IDPLANTILLA = IDPLANTILLA
			FROM OPENJSON(@PARAMETROS) WITH (DATOS NVARCHAR(MAX) AS JSON, IDPLANTILLA VARCHAR(20) '$.IDPLANTILLA')

			BEGIN
				SELECT @CollationName = CONVERT(NVARCHAR(150), DATABASEPROPERTYEX(DB_NAME(), 'Collation'));

				SET NOCOUNT ON;

				CREATE TABLE #TempTable (ID INT PRIMARY KEY IDENTITY, IDPLANTILLA VARCHAR(20), CODCARGO VARCHAR(20), NIVEL VARCHAR(10), GRADO VARCHAR(10)
					);

				SET @SQL = 'ALTER TABLE #TempTable ALTER COLUMN IDPLANTILLA VARCHAR(20) COLLATE ' + @CollationName + 
					';ALTER TABLE #TempTable ALTER COLUMN CODCARGO VARCHAR(20) COLLATE ' + @CollationName + 
					';ALTER TABLE #TempTable ALTER COLUMN NIVEL VARCHAR(10) COLLATE ' + @CollationName + 
					';ALTER TABLE #TempTable ALTER COLUMN GRADO VARCHAR(10) COLLATE ' + @CollationName + ';';

				EXEC sp_executesql @SQL;

				INSERT INTO #TempTable (IDPLANTILLA, CODCARGO, NIVEL, GRADO)
				SELECT @IDPLANTILLA COLLATE DATABASE_DEFAULT, JSON_VALUE(value, '$.CODCARGO') COLLATE DATABASE_DEFAULT, JSON_VALUE(value, '$.NIVEL') COLLATE 
					DATABASE_DEFAULT, JSON_VALUE(value, '$.GRADO') COLLATE DATABASE_DEFAULT
				FROM OPENJSON(@DATOS);

				IF ISJSON(@DATOS) = 1
				BEGIN
					INSERT INTO NPLTCA (IDPLANTILLA, CODCARGO, NIVEL, GRADO)
					SELECT t.IDPLANTILLA COLLATE DATABASE_DEFAULT, t.CODCARGO COLLATE DATABASE_DEFAULT, t.NIVEL COLLATE DATABASE_DEFAULT, t.GRADO COLLATE 
						DATABASE_DEFAULT
					FROM #TempTable t
					LEFT JOIN NPLTCA ON t.IDPLANTILLA COLLATE DATABASE_DEFAULT = NPLTCA.IDPLANTILLA AND t.CODCARGO COLLATE DATABASE_DEFAULT = NPLTCA.CODCARGO AND t.
						NIVEL COLLATE DATABASE_DEFAULT = NPLTCA.NIVEL AND t.GRADO COLLATE DATABASE_DEFAULT = NPLTCA.GRADO
					WHERE NPLTCA.CODCARGO IS NULL

					DELETE NPLTCA
					FROM NPLTCA
					LEFT JOIN #TempTable t ON NPLTCA.IDPLANTILLA = t.IDPLANTILLA COLLATE DATABASE_DEFAULT AND t.CODCARGO COLLATE DATABASE_DEFAULT = NPLTCA.CODCARGO 
						AND t.NIVEL COLLATE DATABASE_DEFAULT = NPLTCA.NIVEL AND t.GRADO COLLATE DATABASE_DEFAULT = NPLTCA.GRADO
					WHERE t.CODCARGO IS NULL AND NPLTCA.IDPLANTILLA = jSON_VALUE(@PARAMETROS, '$.IDPLANTILLA') COLLATE DATABASE_DEFAULT;

					DROP TABLE #TempTable;
				END
				ELSE
				BEGIN
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ('El parametro JSON no es valido.')
				END
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'UPDATE_NPLTCO'
	BEGIN
		BEGIN TRY
			SELECT @DATOS = DATOS, @IDPLANTILLA = IDPLANTILLA
			FROM OPENJSON(@PARAMETROS) WITH (DATOS NVARCHAR(MAX) AS JSON, IDPLANTILLA VARCHAR(20) '$.IDPLANTILLA')

			BEGIN
				SELECT @CollationName = CONVERT(NVARCHAR(150), DATABASEPROPERTYEX(DB_NAME(), 'Collation'));

				SET NOCOUNT ON;

				CREATE TABLE #TempTableC (ID INT PRIMARY KEY IDENTITY, IDPLANTILLA VARCHAR(20), CODCONCEPTO VARCHAR(20));

				SET @SQL = 'ALTER TABLE #TempTableC ALTER COLUMN IDPLANTILLA VARCHAR(20) COLLATE ' + @CollationName + 
					';ALTER TABLE #TempTableC ALTER COLUMN CODCONCEPTO VARCHAR(20) COLLATE ' + @CollationName + ';';

				EXEC sp_executesql @SQL;

				INSERT INTO #TempTableC (IDPLANTILLA, CODCONCEPTO)
				SELECT @IDPLANTILLA COLLATE DATABASE_DEFAULT, JSON_VALUE(value, '$.CODCONCEPTO') COLLATE DATABASE_DEFAULT
				FROM OPENJSON(@DATOS);

				IF ISJSON(@DATOS) = 1
				BEGIN
					INSERT INTO NPLTCO (IDPLANTILLA, CODCONCEPTO)
					SELECT t.IDPLANTILLA COLLATE DATABASE_DEFAULT, t.CODCONCEPTO COLLATE DATABASE_DEFAULT
					FROM #TempTableC t
					LEFT JOIN NPLTCO ON t.IDPLANTILLA COLLATE DATABASE_DEFAULT = NPLTCO.IDPLANTILLA AND t.CODCONCEPTO COLLATE DATABASE_DEFAULT = NPLTCO.CODCONCEPTO
					WHERE NPLTCO.CODCONCEPTO IS NULL

					DELETE NPLTCO
					FROM NPLTCO
					LEFT JOIN #TempTableC t ON NPLTCO.IDPLANTILLA = t.IDPLANTILLA COLLATE DATABASE_DEFAULT AND t.CODCONCEPTO COLLATE DATABASE_DEFAULT = NPLTCO.
						CODCONCEPTO
					WHERE t.CODCONCEPTO IS NULL AND NPLTCO.IDPLANTILLA = jSON_VALUE(@PARAMETROS, '$.IDPLANTILLA') COLLATE DATABASE_DEFAULT;

					DROP TABLE #TempTableC;
				END
				ELSE
				BEGIN
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ('El parametro JSON no es valido.')
				END
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GET_NPLT'
	BEGIN
		SELECT IDPLANTILLA value, DESCRIPCION label
		FROM NPLT
		WHERE ESTADO = 'Activa'

		RETURN
	END

	IF @METODO = 'GET_NPLT_CARGO'
	BEGIN
		SELECT @CODCARGO = CODCARGO, @NIVEL = NIVEL, @GRADO = GRADO
		FROM OPENJSON(@PARAMETROS) WITH (CODCARGO VARCHAR(20) '$.CODCARGO', NIVEL VARCHAR(10) '$.NIVEL', GRADO VARCHAR(10) '$.GRADO')

		SELECT IDPLANTILLA
		FROM NPLTCA
		WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVEL AND GRADO = @GRADO

		RETURN
	END

	IF @METODO = 'GET_NPLTCA_RPDX'
	BEGIN
		SELECT @IDPLANTILLA = IDPLANTILLA
		FROM OPENJSON(@PARAMETROS) WITH (IDPLANTILLA VARCHAR(20) '$.IDPLANTILLA')

		SELECT 'OK' OK

		SELECT NCARNG.CODCARGO, NCARNG.NIVEL, NCARNG.GRADO, NCARNG.DESCRIPCION AS CARGO, NCAR.DESCRIPCION AS STRINGMEDIO1, CONCAT (NCARNG.CODCARGO, NCARNG.NIVEL, NCARNG.GRADO
				) AS ROWKEY
		FROM NCARNG
		LEFT JOIN RPDX ON RPDX.ID1 = NCARNG.CODCARGO AND RPDX.ID2 = NCARNG.NIVEL AND RPDX.ID3 = NCARNG.GRADO
		INNER JOIN NCAR ON NCAR.CODCARGO = NCARNG.CODCARGO
		WHERE RPDX.ID1 IS NULL
		ORDER BY NCARNG.DESCRIPCION ASC;

		SELECT ITEM, ID1 AS CODCARGO, ID2 AS NIVEL, ID3 AS GRADO, STRINGMEDIO1, FECHA1, FECHAREGISTRO, NCARNG.DESCRIPCION AS CARGO
		FROM RPDX
		INNER JOIN NCARNG ON RPDX.ID1 = NCARNG.CODCARGO AND RPDX.ID2 = NCARNG.NIVEL AND RPDX.ID3 = NCARNG.GRADO
		WHERE CNS = 'NCAR'
		ORDER BY NCARNG.DESCRIPCION ASC

		RETURN
	END

	IF @METODO = 'GET_NPLTCO_RPDX'
	BEGIN
		SELECT @IDPLANTILLA = IDPLANTILLA
		FROM OPENJSON(@PARAMETROS) WITH (IDPLANTILLA VARCHAR(20) '$.IDPLANTILLA')

		SELECT 'OK' OK

		SELECT NCON.CODCONCEPTO, NCON.ESTADO, NCON.DESCRIPCION, NCON.CODCONCEPTO AS ROWKEY
		FROM NCON
		LEFT JOIN RPDX ON RPDX.ID1 = NCON.CODCONCEPTO
		WHERE RPDX.ID1 IS NULL
		ORDER BY NCON.DESCRIPCION ASC;

		SELECT ITEM, ID1 AS CODCONCEPTO, STRINGMEDIO1 AS DESCRIPCION
		FROM RPDX
		INNER JOIN NCON ON RPDX.ID1 = NCON.CODCONCEPTO
		WHERE CNS = 'NCON'
		ORDER BY STRINGMEDIO1 ASC

		RETURN
	END
END
