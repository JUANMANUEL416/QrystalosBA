CREATE OR ALTER FUNCTION DBO.FNK_VALIDA_CCOSTO(@CCOSTO VARCHAR(20),@IDSEDE VARCHAR(5))
RETURNS VARCHAR(20)
WITH ENCRYPTION
AS
BEGIN
    DECLARE @CCOSTONEW VARCHAR(20)=@CCOSTO
    DECLARE @FACTSEDE VARCHAR(20)=DBO.FNK_VALORVARIABLE('FACTSEDE')
    DECLARE @HOMOLOGA_CCOSTOYSEDE VARCHAR(20)=DBO.FNK_VALORVARIABLE('HOMOLOGA_CCOSTOYSEDE')

    IF EXISTS(SELECT 1 FROM CEN WHERE CCOSTO=@CCOSTO AND ESTADO='Inactivo' AND IDSEDE=CASE WHEN @FACTSEDE='SI' THEN @IDSEDE ELSE IDSEDE END)
    BEGIN
        SELECT @CCOSTONEW=HOMOLOGO
        FROM CEN WHERE  CCOSTO=@CCOSTO AND ESTADO='Inactivo' AND IDSEDE=CASE WHEN @FACTSEDE='SI' THEN @IDSEDE ELSE IDSEDE END
    END

    IF @HOMOLOGA_CCOSTOYSEDE='SI'
    BEGIN
        IF NOT EXISTS(SELECT 1 FROM CENH WHERE IDSEDE=@IDSEDE AND CCOSTO=@CCOSTO)
        BEGIN
            SELECT @CCOSTONEW=@CCOSTO FROM CENH WHERE IDSEDE=@IDSEDE AND CCOSTOOR=@CCOSTO
        END
    END

    RETURN(@CCOSTONEW)
END
