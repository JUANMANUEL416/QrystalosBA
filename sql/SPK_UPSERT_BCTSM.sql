CREATE OR ALTER PROCEDURE DBO.SPK_UPSERT_BCTSM
  @BANCO     VARCHAR(3),
  @SUCURSAL  VARCHAR(2),
  @CTA_BCO   VARCHAR(40),
  @ANO       VARCHAR(4),
  @MES       SMALLINT,
  @CNSBCTC   VARCHAR(20) = NULL,
  @USUARIO   VARCHAR(20) = NULL
AS
SET NOCOUNT ON;
SET LANGUAGE Spanish;

DECLARE
  @SI             DECIMAL(14, 2) = 0,
  @DB             DECIMAL(14, 2) = 0,
  @CR             DECIMAL(14, 2) = 0,
  @SF             DECIMAL(14, 2) = 0,
  @SALDOB         DECIMAL(14, 2) = NULL,
  @SALDOCONT      DECIMAL(14, 2) = NULL,
  @ANO_ANT        VARCHAR(4),
  @MES_ANT        SMALLINT,
  @AVISO          VARCHAR(500) = NULL,
  @FINI           DATE;

BEGIN
  IF @BANCO IS NULL OR @SUCURSAL IS NULL OR @CTA_BCO IS NULL
     OR @ANO IS NULL OR @MES IS NULL OR @MES < 1 OR @MES > 12
     OR TRY_CONVERT(INT, @ANO) IS NULL
  BEGIN
    RAISERROR('Datos incompletos para generar el auxiliar del mes.', 16, 1);
    RETURN;
  END

  IF NOT EXISTS (
    SELECT 1 FROM BCT
    WHERE BANCO = @BANCO AND SUCURSAL = @SUCURSAL AND CTA_BCO = @CTA_BCO
  )
  BEGIN
    RAISERROR('La cuenta bancaria no existe.', 16, 1);
    RETURN;
  END

  SET @FINI = DATEFROMPARTS(CONVERT(INT, @ANO), @MES, 1);

  IF @MES = 1
  BEGIN
    SET @ANO_ANT = CONVERT(VARCHAR(4), CONVERT(INT, @ANO) - 1);
    SET @MES_ANT = 12;
  END
  ELSE
  BEGIN
    SET @ANO_ANT = @ANO;
    SET @MES_ANT = @MES - 1;
  END

  SELECT @SI = COALESCE(SF, 0)
  FROM BCTSM
  WHERE BANCO = @BANCO AND SUCURSAL = @SUCURSAL AND CTA_BCO = @CTA_BCO
    AND ANO = @ANO_ANT AND MES = @MES_ANT;

  SET @SI = COALESCE(@SI, 0);

  SELECT @DB = COALESCE(SUM(BMOV.VLROPERACION), 0)
  FROM BMOV
  INNER JOIN OFIN ON BMOV.IDOPERACION = OFIN.IDOPERACION
  WHERE BMOV.BANCO = @BANCO
    AND BMOV.SUCURSAL = @SUCURSAL
    AND BMOV.CTA_BCO = @CTA_BCO
    AND BMOV.ESTADO = 'O'
    AND OFIN.TIPO = 'DB'
    AND BMOV.FECHAOK >= @FINI
    AND BMOV.FECHAOK < DATEADD(MONTH, 1, CONVERT(DATETIME, @FINI));

  SELECT @CR = COALESCE(SUM(BMOV.VLROPERACION), 0)
  FROM BMOV
  INNER JOIN OFIN ON BMOV.IDOPERACION = OFIN.IDOPERACION
  WHERE BMOV.BANCO = @BANCO
    AND BMOV.SUCURSAL = @SUCURSAL
    AND BMOV.CTA_BCO = @CTA_BCO
    AND BMOV.ESTADO = 'O'
    AND OFIN.TIPO = 'CR'
    AND BMOV.FECHAOK >= @FINI
    AND BMOV.FECHAOK < DATEADD(MONTH, 1, CONVERT(DATETIME, @FINI));

  SET @SF = @SI + @DB - @CR;

  IF COALESCE(@CNSBCTC, '') <> ''
  BEGIN
    SELECT
      @SALDOB = SALDOB,
      @SALDOCONT = SALDOCONT
    FROM BCTC
    WHERE CNSBCTC = @CNSBCTC;
  END

  IF @SALDOCONT IS NOT NULL AND ABS(@SF - @SALDOCONT) > 0.01
  BEGIN
    SET @AVISO = 'El saldo final del auxiliar (' + CONVERT(VARCHAR(30), @SF)
      + ') difiere del saldo en libros de la conciliaci�n ('
      + CONVERT(VARCHAR(30), @SALDOCONT) + ').';
  END

  IF EXISTS (
    SELECT 1 FROM BCTSM
    WHERE BANCO = @BANCO AND SUCURSAL = @SUCURSAL AND CTA_BCO = @CTA_BCO
      AND ANO = @ANO AND MES = @MES
  )
  BEGIN
    UPDATE BCTSM
      SET SI = @SI,
          DB = @DB,
          CR = @CR,
          SF = @SF,
          CNSBCTC = COALESCE(NULLIF(@CNSBCTC, ''), CNSBCTC),
          SALDOB_BCTC = @SALDOB,
          SALDOCONT_BCTC = @SALDOCONT,
          USUARIO = @USUARIO,
          FECHA = GETDATE()
    WHERE BANCO = @BANCO AND SUCURSAL = @SUCURSAL AND CTA_BCO = @CTA_BCO
      AND ANO = @ANO AND MES = @MES;
  END
  ELSE
  BEGIN
    INSERT INTO BCTSM (
      BANCO, SUCURSAL, CTA_BCO, ANO, MES,
      SI, DB, CR, SF, CNSBCTC, SALDOB_BCTC, SALDOCONT_BCTC, USUARIO, FECHA
    )
    VALUES (
      @BANCO, @SUCURSAL, @CTA_BCO, @ANO, @MES,
      @SI, @DB, @CR, @SF, NULLIF(@CNSBCTC, ''), @SALDOB, @SALDOCONT, @USUARIO, GETDATE()
    );
  END

  SELECT 'OK' OK,
         @ANO ANO,
         @MES MES,
         @SI SI,
         @DB DB,
         @CR CR,
         @SF SF,
         @CNSBCTC CNSBCTC,
         @AVISO AVISO;
END
