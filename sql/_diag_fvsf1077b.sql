SET NOCOUNT ON;
DECLARE @NF VARCHAR(20) = N'FVSF1077';
DECLARE @NC VARCHAR(20) = N'0161000000099663';

SELECT F.N_FACTURA, F.ESTADO, F.CONTABILIZADA, F.NROCOMPROBANTE, F.PROCEDENCIA, F.FACTE, F.VR_TOTAL, F.CUENTACXC
FROM dbo.FTR F WHERE F.N_FACTURA = @NF;

SELECT P.NROCOMPROBANTE, P.PROCEDENCIA, P.ESTADO, P.REFERENCIA1, P.REFERENCIA2, P.TOTALDEBITO, P.TOTALCREDITO
FROM dbo.MCP P WHERE P.NROCOMPROBANTE = @NC;

SELECT H.TIPO, H.CUENTA, H.VALOR, LEFT(CAST(H.DETALLE AS VARCHAR(80)),80) DET, H.PROCEDENCIA, H.N_FACTURA
FROM dbo.MCH H WHERE H.NROCOMPROBANTE = @NC;

SELECT H.TIPO, H.CUENTA, H.VALOR, H.PROCEDENCIA, H.N_FACTURA, H.REFERENCIA_PRO
FROM dbo.MCHE H WHERE H.NROCOMPROBANTE = @NC;

SELECT DBO.FNK_VALORVARIABLE('CONTAB_GASTOVEN_UNI') AS GASTOVEN_UNI,
  DBO.FNK_VALORVARIABLE('CONTAB_FTR_POSTDIAN') AS POSTDIAN;
