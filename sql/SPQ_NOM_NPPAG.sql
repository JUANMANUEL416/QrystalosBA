CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NPPAG @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @DATO NVARCHAR(MAX)
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20)
DECLARE @PROCESO VARCHAR(20)
DECLARE @CODPPAG VARCHAR(5), @DESCRIPCION VARCHAR(255), @CODPPAGEDITE VARCHAR(5)
DECLARE @HORADESLABOR DECIMAL(7, 2), @DIAS SMALLINT, @CODPERIODO SMALLINT
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @CODPPAG = CODPPAG, @DESCRIPCION = DESCRIPCION, @HORADESLABOR = HORASDELABOR, @DIAS = DIAS, @CODPERIODO = CODPERIODO, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					CODPPAG VARCHAR(5) '$.CODPPAG', DESCRIPCION VARCHAR(255) '$.DESCRIPCION', HORASDELABOR DECIMAL(7, 2) '$.HORASDELABOR', DIAS SMALLINT '$.DIAS', 
					CODPERIODO SMALLINT '$.CODPERIODO', PROCESO VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('EL CONSECUTIVO ', @CODPPAG, ' YA SE ENCUENTRA REGISTRADO')
					WHERE EXISTS (
							SELECT 1
							FROM NPPAG
							WHERE CODPPAG = @CODPPAG
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO NPPAG (CODPPAG, DESCRIPCION, HORASDELABOR, DIAS, CODPERIODO)
						SELECT @CODPPAG, @DESCRIPCION, @HORADESLABOR, @DIAS, @CODPERIODO
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @DATO = DATO
					FROM OPENJSON(@PARAMETROS) WITH (DATO NVARCHAR(MAX) AS JSON)

					SELECT @CODPPAGEDITE = CODPPAGEDITE
					FROM OPENJSON(@DATO) WITH (CODPPAGEDITE VARCHAR(5) '$.CODPPAGEDITE')

					IF (@CODPPAGEDITE <> @CODPPAG)
					BEGIN
						IF EXISTS (
								SELECT 1
								FROM NPPAG
								WHERE CODPPAG = @CODPPAG
								)
						BEGIN
							INSERT INTO @TBLERRORES (ERROR)
							SELECT CONCAT ('EL CONSECUTIVO ', @CODPPAG, ' YA SE ENCUENTRA REGISTRADO')
						END

						IF (
								SELECT COUNT(*)
								FROM @TBLERRORES
								) <= 0
						BEGIN
							UPDATE NPPAG
							SET CODPPAG = @CODPPAG, DESCRIPCION = @DESCRIPCION, HORASDELABOR = @HORADESLABOR, DIAS = @DIAS, CODPERIODO = @CODPERIODO
							WHERE CODPPAG = @CODPPAGEDITE
						END
					END
					ELSE
					BEGIN
						UPDATE NPPAG
						SET DESCRIPCION = @DESCRIPCION, HORASDELABOR = @HORADESLABOR, DIAS = @DIAS, CODPERIODO = @CODPERIODO
						WHERE CODPPAG = @CODPPAG
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @CODPPAG = CODPPAG
		FROM OPENJSON(@PARAMETROS) WITH (CODPPAG VARCHAR(5) '$.CODPPAG')

		BEGIN TRY
			DELETE
			FROM NPPAG
			WHERE CODPPAG = @CODPPAG
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
