IF EXISTS (SELECT name FROM sysobjects 
         WHERE name = 'SPK_CREACXP_QX' AND type = 'P')
   DROP PROCEDURE SPK_CREACXP_QX

GO
CREATE PROCEDURE DBO.SPK_CREACXP_QX  
@NOADMISION VARCHAR(16),  
@COMPANIA   VARCHAR(2),  
@SEDE       VARCHAR(5),  
@USUARIO    VARCHAR(12)  
WITH ENCRYPTION
AS      
DECLARE @CONTADOR INT  
DECLARE @VALORES  DECIMAL(14,2)  
DECLARE @NVOCONSEC INT  
DECLARE @IDPROVEEDOR VARCHAR(20)  
DECLARE @VALOR DECIMAL(14,2)  
BEGIN  
   SELECT @CONTADOR = COUNT(*) FROM HPRED,HPRE  
   WHERE  HPRE.NOADMISION   = @NOADMISION  
   AND    HPRE.NOPRESTACION = HPRED.NOPRESTACION  
   AND    HPRED.IDPROVEEDOR <> ''  
   AND    HPRED.IDPROVEEDOR IS NOT NULL  
   IF @CONTADOR <= 0  
   BEGIN
      RETURN  
   END
   CREATE TABLE #ICXP (IDPROVEEDOR VARCHAR(20)     ,IDSERVICIO   VARCHAR(20),  
                       VALOREXCEDENTE DECIMAL(14,2),DESCSEVICIO VARCHAR(255),  
                       IDAREA VARCHAR(20) ,IDCIRUGIA VARCHAR(20),PREFIJO VARCHAR(6),  
                       VALOR DECIMAL(14,2),CANTIDAD INT,NOPRESTACION VARCHAR(16) ,  
                       NOITEM SMALLINT ,N_FACTURA VARCHAR(16), CCOSTO VARCHAR(20),
                       IDAREAH VARCHAR(20), ITEM INT IDENTITY)  
   INSERT INTO #ICXP  
   SELECT HPRED.IDPROVEEDOR,SER.IDSERVICIO,HPRED.VALOREXCEDENTE,SER.DESCSERVICIO,  
          HPRE.IDAREA,HPRED.IDCIRUGIA,SER.PREFIJO,HPRED.VALOR,HPRED.CANTIDAD,HPRED.NOPRESTACION,  
          HPRED.NOITEM,HPRED.N_FACTURA, HPRE.CCOSTO, HPRE.IDAREAH  
   FROM   HPRED,SER,HPRE    
   WHERE  HPRE.NOADMISION= @NOADMISION  
   AND    SER.IDSERVICIO    = HPRED.IDSERVICIO   
   AND    HPRE.NOPRESTACION = HPRED.NOPRESTACION   
   AND    HPRED.IDPROVEEDOR is not null   
   AND    HPRED.IDPROVEEDOR <> ''   
   ORDER BY HPRED.IDPROVEEDOR   
   --  
   CREATE TABLE #PCXP (IDPROVEEDOR VARCHAR(20),VALOR DECIMAL(14,2))  
   INSERT INTO  #PCXP (IDPROVEEDOR,VALOR)  
   SELECT IDPROVEEDOR,SUM(VALOREXCEDENTE)  FROM #ICXP  
   GROUP BY IDPROVEEDOR  
   --CURSOR--  
   DECLARE CXP_CURSOR CURSOR FOR  
   SELECT IDPROVEEDOR,VALOR FROM #PCXP  
   OPEN CXP_CURSOR  
   FETCH NEXT FROM CXP_CURSOR  
   INTO @IDPROVEEDOR,@VALOR  
   WHILE @@FETCH_STATUS = 0  
   BEGIN   
         EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@FCXP',@NVOCONSEC OUTPUT  
   
         INSERT INTO FXP(N_PRESUP,IDTERCERO,NOREFERENCIA,F_FACTURAREF,F_VENCE,VR_TOTAL,ESTADO,  
                         F_CANCELADO,EMPLEADO,PROCEDENCIA,OBSERVACION,COMPANIA,INDCOBRADA)  
         SELECT @NVOCONSEC,@IDPROVEEDOR,@NOADMISION, DBO.FNK_FECHA_SIN_MLS(GETDATE()),NULL,@VALOR,'P',NULL,@USUARIO,  
                'SALUD','',@COMPANIA,0  
         INSERT INTO FXPD(N_PRESUP,IDTERCERO,ITEM,IDSERVICIO,PREFIJO,VALOR,CANTIDAD,VR_TOTAL,  
                          NOPRESTACION,NOITEM,IDCIRUGIA, N_FACTURA, ESTADO, CCOSTO, IDAREA,
                          IDAREAH)  
         SELECT @NVOCONSEC,@IDPROVEEDOR,ITEM,IDSERVICIO,PREFIJO,VALOR,CANTIDAD,  
                (VALOR*CANTIDAD),NOPRESTACION,NOITEM,IDCIRUGIA, N_FACTURA, 'P', CCOSTO, IDAREA,
                IDAREAH  
         FROM #ICXP  
         WHERE IDPROVEEDOR = @IDPROVEEDOR  
         FETCH NEXT FROM CXP_CURSOR  
         INTO @IDPROVEEDOR,@VALOR  
   END  
   CLOSE CXP_CURSOR  
   DEALLOCATE CXP_CURSOR     
   UPDATE HADM SET CXP = 1  
   WHERE NOADMISION = @NOADMISION    
   DROP TABLE #ICXP  
   DROP TABLE #PCXP  
END
