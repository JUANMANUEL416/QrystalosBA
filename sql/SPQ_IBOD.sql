CREATE OR ALTER PROCEDURE DBO.SPQ_IBOD @JSON  NVARCHAR(MAX)
WITH      ENCRYPTION
AS
DECLARE  @IDBODEGA				 VARCHAR(20),	  @DESCRIPCION	  VARCHAR(100)
DECLARE  @IDSEDE_BOD             VARCHAR(20)
DECLARE	 @IDBODEGAPIDE			 VARCHAR(20),	  @IDTBODEGA      VARCHAR(2),	  @ESTADO  		  VARCHAR(8)
DECLARE	 @TIPOBODEGA			 VARCHAR(12),	  @IDDEP	      VARCHAR(20),	  @CCOSTO  		  VARCHAR(20)
DECLARE	 @MUEVEEXISTENCIAS		 VARCHAR(20),	  @IDAREA  		  VARCHAR(20),	  @CONSUMO		  BIT		  
DECLARE	 @CONFIRMAAUTOMDESDEQX   BIT,			  @COMPRASOL	  BIT,			  @CODEBAR		  BIT
DECLARE	 @NOCONTABILIZA			 BIT,			  @VALIDASTOCK	  BIT,			  @RPEDIDOAUT	  BIT
DECLARE  @AUTOSTOCK	  BIT          ,          @ESDECUSTODIA	  BIT
DECLARE  @MANEJA_PICKPACK BIT
DECLARE  @ERRORES AS TABLE(ERROR VARCHAR(MAX))
DECLARE  @PARAMETROS NVARCHAR(MAX), 
			@METODO VARCHAR(100), 
			@MODELOACT NVARCHAR(MAX), 
			@USUARIO VARCHAR(12),
			@SYS_COMPUTERNAME VARCHAR(50)

BEGIN
	SELECT *
	INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)  AS JSON
	)
	SELECT @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON
	
	SELECT @SYS_COMPUTERNAME = SYS_ComputerName
	FROM USUSU 
	WHERE USUARIO=@USUARIO
	
	IF @METODO = 'BODEGASELECT'
	BEGIN


		SELECT IDBODEGA,DESCRIPCION
		INTO #IBOD
		FROM IBOD
		WHERE IDBODEGA IN (
			SELECT IDBODEGA FROM USUSU WHERE USUARIO=@USUARIO
			UNION ALL
			SELECT COALESCE(IDBODEGA, IDBODEGA2) FROM UBEQ WHERE SYS_COMPUTERNAME = @SYS_COMPUTERNAME
			UNION ALL
			SELECT IDBODEGA FROM IBODS WHERE VALOR=@USUARIO AND TIPO='USUSU' AND ACCESO='SI'
		)
		AND IDBODEGA IN (
			SELECT IDBODEGA 
			FROM IBODS 
			WHERE VALOR=@USUARIO  
			AND TIPO='USUSU' 
			AND ACCESO='SI'
		)

		IF NOT EXISTS(SELECT 1 FROM #IBOD)
		BEGIN
			SELECT 'KO' AS OK
			SELECT 'No posee privilegios necesarios para ingresar a �ste m�dulo.' AS ERROR
			RETURN
		END

		SELECT 'OK' AS OK, @USUARIO AS USUARIO, @SYS_COMPUTERNAME AS SYS_COMPUTERNAME

		SELECT * FROM #IBOD


	END
	/*IF @METODO = 'UPDATEBODEGAUSER'
	BEGIN
		SELECT @SYS_COMPUTERNAME = SYS_ComputerName FROM OPENJSON(@PARAMETROS) WITH(SYS_ComputerName VARCHAR(50) '$.SYS_ComputerName')
		SELECT 'OK' AS OK
		UPDATE UBEQ 
		SET 
		IDBODEGA = JSON_VALUE(@PARAMETROS, '$.IDBODEGA')
		WHERE SYS_ComputerName = @SYS_COMPUTERNAME
	END*/
	IF @METODO = 'BODEGAUSERASIG'
	BEGIN
		--SELECT @USUARIO = JSON_VALUE(@PARAMETROS,'$.USUARIO') 
		
		SELECT 'OK' AS OK
		
		SELECT IBODS.IDBODEGA, IBOD.DESCRIPCION 
			,SELECTED = CAST(CASE WHEN IBODS.IDBODEGA = (SELECT COALESCE(IDBODEGA,IDBODEGA2,IDBODEGANOCHE) FROM UBEQ WHERE SYS_ComputerName=@SYS_COMPUTERNAME)
			THEN 1 ELSE 0 END AS BIT)
			,CAST(COALESCE(CODEBAR, 0) AS BIT) AS CODEBAR
			,VERIFDOC = CAST(IIF(COALESCE(ITBOD.VERIFDOC, 'No')<>'Si', 0, 1) AS BIT)
         ,COALESCE(MHIJO,0) MHIJO
         ,CAST(COALESCE(IBOD.MANEJA_PICKPACK, 0) AS BIT) AS MANEJA_PICKPACK
			
		FROM IBODS 
		INNER JOIN IBOD ON IBOD.IDBODEGA=IBODS.IDBODEGA
		INNER JOIN ITBOD ON IBOD.IDTBODEGA=ITBOD.IDTBODEGA
		WHERE	VALOR	= @USUARIO
		AND		TIPO	= 'USUSU'
		AND		ACCESO	= 'SI'
		AND		IBOD.ESTADO = 'Activo'
		ORDER BY IBOD.IDBODEGA, IBOD.DESCRIPCION
	END

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDBODEGA = IDBODEGA, @DESCRIPCION = DESCRIPCION, @IDBODEGAPIDE = IDBODEGAPIDE,	@IDTBODEGA = IDTBODEGA,
        @IDSEDE_BOD = IDSEDE_BOD,
				@ESTADO = ESTADO, @TIPOBODEGA = TIPOBODEGA, @IDDEP = IDDEP, @IDAREA = IDAREA, @CCOSTO = CCOSTO,
				@MUEVEEXISTENCIAS = MUEVEEXISTENCIAS, @COMPRASOL = COMPRASOL, @CONFIRMAAUTOMDESDEQX = CONFIRMAAUTOMDESDEQX, 
				@CODEBAR = CODEBAR, @CONSUMO = CONSUMO, @NOCONTABILIZA = NOCONTABILIZA, @VALIDASTOCK = VALIDASTOCK,
				@RPEDIDOAUT = RPEDIDOAUT, @AUTOSTOCK = AUTOSTOCK, @ESDECUSTODIA = ESDECUSTODIA,
				@MANEJA_PICKPACK = MANEJA_PICKPACK
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				IDBODEGA	  VARCHAR(20)  '$.IDBODEGA',	 DESCRIPCION	VARCHAR(100)  '$.DESCRIPCION',	 IDBODEGAPIDE		  VARCHAR(20)  '$.IDBODEGAPIDE',
        IDSEDE_BOD   VARCHAR(20)  '$.IDSEDE_BOD',
				IDTBODEGA	  VARCHAR(20)  '$.IDTBODEGA',	 ESTADO			VARCHAR(8)	  '$.ESTADO',		 TIPOBODEGA			  VARCHAR(12)  '$.TIPOBODEGA',
				IDDEP		  VARCHAR(20)  '$.IDDEP',		 IDAREA			VARCHAR(20)   '$.IDAREA',		 CCOSTO				  VARCHAR(20)  '$.CCOSTO',
				CONSUMO		  BIT		   '$.CONSUMO',		 COMPRASOL		BIT			  '$.COMPRASOL',	 CONFIRMAAUTOMDESDEQX BIT		   '$.CONFIRMAAUTOMDESDEQX',
				CODEBAR		  BIT		   '$.CODEBAR',		 NOCONTABILIZA  BIT			  '$.NOCONTABILIZA', MUEVEEXISTENCIAS	  VARCHAR(20)  '$.MUEVEEXISTENCIAS',
				VALIDASTOCK   BIT		   '$.VALIDASTOCK',  RPEDIDOAUT     BIT		      '$.RPEDIDOAUT',    AUTOSTOCK			  BIT		   '$.AUTOSTOCK',
            ESDECUSTODIA     BIT		      '$.ESDECUSTODIA',
            MANEJA_PICKPACK  BIT		      '$.MANEJA_PICKPACK'
			)

			INSERT INTO @ERRORES(ERROR) 
			SELECT 'LA BODEGA YA EXISTE'
			WHERE EXISTS (SELECT IDBODEGA FROM IBOD WHERE IDBODEGA = @IDBODEGA)

			IF(SELECT COUNT(*) FROM @ERRORES) <=0
			BEGIN
				INSERT INTO IBOD (IDBODEGA ,DESCRIPCION ,IDSEDE_BOD ,RPEDIDOAUT ,IDBODEGAPIDE ,IDTBODEGA ,ESTADO ,TIPOBODEGA ,IDDEP ,CCOSTO ,IDAREA ,
               MUEVEEXISTENCIAS ,AUTOSTOCK ,CONFIRMAAUTOMDESDEQX ,COMPRASOL ,CODEBAR ,VALIDASTOCK ,CONSUMO ,NOCONTABILIZA ,ESDECUSTODIA ,MANEJA_PICKPACK) 
				SELECT @IDBODEGA ,@DESCRIPCION ,@IDSEDE_BOD ,@RPEDIDOAUT ,@IDBODEGAPIDE ,@IDTBODEGA ,@ESTADO ,@TIPOBODEGA ,@IDDEP ,@CCOSTO ,@IDAREA ,
					@MUEVEEXISTENCIAS ,@AUTOSTOCK ,@CONFIRMAAUTOMDESDEQX ,@COMPRASOL ,@CODEBAR ,@VALIDASTOCK ,@CONSUMO ,@NOCONTABILIZA ,@ESDECUSTODIA ,COALESCE(@MANEJA_PICKPACK, 0)
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @ERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @ERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @ERRORES
			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ACTUALIZAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDBODEGA = IDBODEGA, @DESCRIPCION = DESCRIPCION, @IDBODEGAPIDE = IDBODEGAPIDE,	@IDTBODEGA = IDTBODEGA,
        @IDSEDE_BOD = IDSEDE_BOD,
				@ESTADO = ESTADO, @TIPOBODEGA = TIPOBODEGA, @IDDEP = IDDEP, @IDAREA = IDAREA, @CCOSTO = CCOSTO,
				@MUEVEEXISTENCIAS = MUEVEEXISTENCIAS, @COMPRASOL = COMPRASOL, @CONFIRMAAUTOMDESDEQX = CONFIRMAAUTOMDESDEQX, 
				@CODEBAR = CODEBAR, @CONSUMO = CONSUMO, @NOCONTABILIZA = NOCONTABILIZA, @VALIDASTOCK = VALIDASTOCK,
				@RPEDIDOAUT = RPEDIDOAUT, @AUTOSTOCK = AUTOSTOCK, @ESDECUSTODIA = ESDECUSTODIA,
				@MANEJA_PICKPACK = MANEJA_PICKPACK
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				IDBODEGA	  VARCHAR(20)  '$.IDBODEGA',	 DESCRIPCION	VARCHAR(100)  '$.DESCRIPCION',	 IDBODEGAPIDE		  VARCHAR(20)  '$.IDBODEGAPIDE',
        IDSEDE_BOD   VARCHAR(20)  '$.IDSEDE_BOD',
				IDTBODEGA	  VARCHAR(20)  '$.IDTBODEGA',	 ESTADO			VARCHAR(8)	  '$.ESTADO',		 TIPOBODEGA			  VARCHAR(12)  '$.TIPOBODEGA',
				IDDEP		  VARCHAR(20)  '$.IDDEP',		 IDAREA			VARCHAR(20)   '$.IDAREA',		 CCOSTO				  VARCHAR(20)  '$.CCOSTO',
				CONSUMO		  BIT		   '$.CONSUMO',		 COMPRASOL		BIT			  '$.COMPRASOL',	 CONFIRMAAUTOMDESDEQX BIT		   '$.CONFIRMAAUTOMDESDEQX',
				CODEBAR		  BIT		   '$.CODEBAR',		 NOCONTABILIZA  BIT			  '$.NOCONTABILIZA', MUEVEEXISTENCIAS	  VARCHAR(20)  '$.MUEVEEXISTENCIAS',
				VALIDASTOCK   BIT		   '$.VALIDASTOCK',  RPEDIDOAUT     BIT		      '$.RPEDIDOAUT',    AUTOSTOCK			  BIT		   '$.AUTOSTOCK',
            ESDECUSTODIA     BIT		      '$.ESDECUSTODIA',
            MANEJA_PICKPACK  BIT		      '$.MANEJA_PICKPACK'
			)

			UPDATE IBOD SET DESCRIPCION = @DESCRIPCION, IDSEDE_BOD = @IDSEDE_BOD, IDBODEGAPIDE = @IDBODEGAPIDE, IDTBODEGA = @IDTBODEGA, ESTADO = @ESTADO,TIPOBODEGA = @TIPOBODEGA,IDDEP = @IDDEP,
				CCOSTO = @CCOSTO,IDAREA = @IDAREA, MUEVEEXISTENCIAS = @MUEVEEXISTENCIAS,CONFIRMAAUTOMDESDEQX = @CONFIRMAAUTOMDESDEQX,COMPRASOL =@COMPRASOL,
				CODEBAR = @CODEBAR,VALIDASTOCK = @VALIDASTOCK,CONSUMO = @CONSUMO,NOCONTABILIZA = @NOCONTABILIZA,RPEDIDOAUT = @RPEDIDOAUT,AUTOSTOCK = @AUTOSTOCK,
            ESDECUSTODIA = @ESDECUSTODIA, MANEJA_PICKPACK = COALESCE(@MANEJA_PICKPACK, 0)
			WHERE IDBODEGA = @IDBODEGA
		END TRY

		BEGIN CATCH
			INSERT INTO @ERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @ERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @ERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
	
	IF @METODO = 'ELIMINAR'
	BEGIN
		BEGIN TRY
			SELECT @IDBODEGA = JSON_VALUE(@PARAMETROS, '$.IDBODEGA')

			INSERT INTO @ERRORES(ERROR) 
			SELECT 'LA BODEGA TIENE EXCEPCIONES PARA REPOSICIONES ASIGNADOS'
			WHERE EXISTS (SELECT IDBODEGA FROM IBODEX WHERE IDBODEGA = @IDBODEGA)
			
			IF(SELECT COUNT(*) FROM @ERRORES) <=0
			BEGIN
				DELETE FROM IBOD WHERE IDBODEGA = @IDBODEGA
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @ERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @ERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @ERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
END
