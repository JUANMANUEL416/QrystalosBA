CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NCONDTC
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @DATO					NVARCHAR(MAX)
DECLARE  @PARAMETROS			NVARCHAR(MAX),	@MODELO			VARCHAR(100),   @METODO		VARCHAR(100),	@USUARIO	VARCHAR(20)
DECLARE	 @PROCESO				VARCHAR(20)
DECLARE	 @CODCONCEPTO			VARCHAR(20),	@ITEM				DECIMAL(14,0)
DECLARE	 @CODCONCEPTO_BASE		VARCHAR(20)
DECLARE	 @FACTOR				DECIMAL(14,6),	@OPERACION			VARCHAR(2)
DECLARE	 @VALHORASLAB			SMALLINT	
DECLARE	 @HORAS					INT,			@DIAS				INT
DECLARE @CODCONCEPTO_BASEDITE	VARCHAR(20)

DECLARE  @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

	IF @METODO = 'GUARDAR'
		BEGIN
			BEGIN TRY
				SELECT  @CODCONCEPTO = CODCONCEPTO, @ITEM = ITEM,@CODCONCEPTO_BASE = CODCONCEPTO_BASE,
						@FACTOR = FACTOR, @OPERACION = OPERACION,
						@VALHORASLAB=VALHORASLAB,
						@HORAS = HORAS, @DIAS = DIAS,
						@PROCESO = PROCESO
				FROM	OPENJSON (@PARAMETROS) 
				WITH	(
					CODCONCEPTO			VARCHAR(20)			'$.CODCONCEPTO',
					ITEM				DECIMAL(14,0)		'$.ITEM',
					CODCONCEPTO_BASE	VARCHAR(20)			'$.CODCONCEPTO_BASE',
					FACTOR				DECIMAL(15,6)		'$.FACTOR',
					OPERACION			VARCHAR(2)			'$.OPERACION',
					VALHORASLAB			BIT					'$.VALHORASLAB',
					HORAS				INT					'$.HORAS',
					DIAS				INT					'$.DIAS',
					PROCESO				VARCHAR(20)			'$.PROCESO'
				)
				IF UPPER(@PROCESO) = 'INSERTAR'
				BEGIN
					BEGIN TRY
							INSERT INTO @TBLERRORES(ERROR) 
							SELECT CONCAT('EL CONCEPTO ',@CODCONCEPTO_BASE, ' YA SE ENCUENTRA REGISTRADO')
							WHERE EXISTS (SELECT 1 FROM NCONDTC WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM AND CODCONCEPTO_BASE = @CODCONCEPTO_BASE)

							IF(SELECT COUNT(*) FROM @TBLERRORES) <= 0
								BEGIN
									INSERT INTO NCONDTC (CODCONCEPTO ,ITEM ,CODCONCEPTO_BASE ,FACTOR ,
									OPERACION ,VALHORASLAB ,HORAS , DIAS )
									SELECT @CODCONCEPTO, @ITEM, @CODCONCEPTO_BASE, @FACTOR,
									@OPERACION, @VALHORASLAB,@HORAS, @DIAS 
								END
					END TRY
					BEGIN CATCH
						INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
					END CATCH

					IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
					BEGIN
						SELECT 'KO' OK
						SELECT ERROR FROM @TBLERRORES
						RETURN
					END

					SELECT 'OK' OK 
					RETURN
				END

				IF UPPER(@PROCESO) = 'EDITAR'
					BEGIN
						BEGIN TRY
						SELECT @DATO = DATO       
							  FROM   OPENJSON (@PARAMETROS)
							  WITH (DATO NVARCHAR(MAX) AS JSON)   
							  
							  SELECT @CODCONCEPTO_BASEDITE = CODCONCEPTO_BASEDITE
							  FROM   OPENJSON (@DATO)
							  WITH   (   
							  CODCONCEPTO_BASEDITE	VARCHAR(20)	 '$.CODCONCEPTO_BASEDITE'
							  )

							  --INSERT INTO @TBLERRORES(ERROR) 
							  --SELECT CONCAT('EL CONCEPTO ASOCIADO ',@CODCONCEPTO_BASE, ' YA SE ENCUENTRA REGISTRADO')
							  --WHERE EXISTS (SELECT 1 FROM NCONDA WHERE  CODCONCEPTO = @CODCONCEPTO AND CODCONCEPTOA = @CODCONCEPTOAEDITE)

								--IF(SELECT COUNT(*) FROM @TBLERRORES) <= 0
								BEGIN
									UPDATE NCONDTC SET  
									CODCONCEPTO_BASE = @CODCONCEPTO_BASE, FACTOR = @FACTOR, 
									OPERACION = @OPERACION, 
									VALHORASLAB = @VALHORASLAB, 
									HORAS = @HORAS ,
									DIAS = @DIAS WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM 
									AND CODCONCEPTO_BASE = @CODCONCEPTO_BASEDITE
								END
						END TRY

						BEGIN CATCH
							INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
						END CATCH

						IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
						BEGIN
							SELECT 'KO' OK
							SELECT ERROR FROM @TBLERRORES
							RETURN
						END

						SELECT 'OK' OK 
						RETURN
					END
		END TRY

			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
			END CATCH

			IF(SELECT COUNT(*) FROM @TBLERRORES) >0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END

			SELECT 'OK' OK
		END

		IF @METODO = 'ELIMINAR'
			BEGIN
					SELECT  @CODCONCEPTO = CODCONCEPTO, @ITEM = ITEM, @CODCONCEPTO_BASE = CODCONCEPTO_BASE
					FROM	OPENJSON (@PARAMETROS) 
					WITH(
						CODCONCEPTO				VARCHAR(20)			'$.CODCONCEPTO',
						ITEM					DECIMAL(14,0)		'$.ITEM',
						CODCONCEPTO_BASE		VARCHAR(20)			'$.CODCONCEPTO_BASE'
						)
			BEGIN TRY
					DELETE FROM NCONDTC WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM 
					AND CODCONCEPTO_BASE = @CODCONCEPTO_BASE
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
				END CATCH

				IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
				BEGIN
					SELECT 'KO' OK
					SELECT ERROR FROM @TBLERRORES
					RETURN
				END
		SELECT 'OK' OK
		END
END
