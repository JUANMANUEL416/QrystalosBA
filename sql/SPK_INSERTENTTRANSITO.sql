CREATE  OR ALTER PROCEDURE DBO.SPK_INSERTENTTRANSITO
@CNSITRA     VARCHAR(20),
@USUARIO     VARCHAR(20),
@IDBODEGA    VARCHAR(20),
@IDTIPOMOV   VARCHAR(2),
@SYSCOMPUTER VARCHAR(20),
@COMPANIA    VARCHAR(2),
@SEDE        VARCHAR(5)
WITH ENCRYPTION
AS
DECLARE @NUEVOCNS             VARCHAR(20)
DECLARE @IDITAR_CUR           VARCHAR(2)
DECLARE @CNSMOV_CUR           VARCHAR(20)
DECLARE @CONT              INT
DECLARE @NOLOTE               VARCHAR(20)
DECLARE @IDARTICULOOBS_CUR    VARCHAR(20)
DECLARE @CANTIDADOBS_CUR      INT
DECLARE @IDITAR_CUR2          VARCHAR(2)
DECLARE @CNSMOV_CUR2          VARCHAR(20)
DECLARE @CONT2                INT
DECLARE @VIDITAR              INT
DECLARE @IDITAR               VARCHAR(2) 
DECLARE @DECONSUMO            SMALLINT
DECLARE @ESTADO               SMALLINT 
DECLARE @LOTEADO              TINYINT
DECLARE @IDARTICULO			  VARCHAR(20)
DECLARE @VLRCOMPRA			  DECIMAL(14,2)

-- Datos del movimiento de salida origen
DECLARE @CCOSTO_ORIGEN		  VARCHAR(20)
DECLARE @IDSOLICITA_ORIGEN	  VARCHAR(20)
DECLARE @IDRECIBE_ORIGEN	  VARCHAR(20)
DECLARE @IDAREA_ORIGEN		  VARCHAR(20)

DECLARE @IXCOUNTRY VARCHAR(20)=DBO.FNK_VALORVARIABLE('IXCOUNTRY')
BEGIN
	--SET NOCOUNT ON 
	DECLARE @DEPURAR BIT = 1 -- ACTIVA/DESACTIVA LOS PRINT
	SELECT @ESTADO = ESTADO, @LOTEADO = COALESCE(LOTEADO,0) FROM ITRA WHERE CNSITRA = @CNSITRA
	DECLARE @TIPOMOV VARCHAR(20)=(SELECT IDTIPOMOV FROM ITRA WHERE CNSITRA=@CNSITRA)

	DECLARE @IDINVMOV_COMPRAS     VARCHAR(20)=DBO.FNK_VALORVARIABLE('IDINVMOV_COMPRAS')
	DECLARE @IDINVMOV_PRESTAMOS   VARCHAR(20)=DBO.FNK_VALORVARIABLE('IDINVMOV_PRESTAMOS')
	DECLARE @IDINVENTRADAUNICA    VARCHAR(20)=DBO.FNK_VALORVARIABLE('IDINVENTRADAUNICA')
	DECLARE @INVCONSECUTIVOSINDEP VARCHAR(20)=DBO.FNK_VALORVARIABLE('INVCONSECUTIVOSINDEP')
	DECLARE @IDINVIDITARUNICA     VARCHAR(20)=DBO.FNK_VALORVARIABLE('IDINVIDITARUNICA')
	DECLARE @CODIGOUNICOICBU      VARCHAR(20)=DBO.FNK_VALORVARIABLE('CODIGOUNICOICBU')
	DECLARE @IDINVENTXOBSEQUIOS   VARCHAR(20)=DBO.FNK_VALORVARIABLE('IDINVENTXOBSEQUIOS')
	DECLARE @IDINVMOV_REMISION_EN VARCHAR(20)=DBO.FNK_VALORVARIABLE('IDINVMOV_REMISION_EN')
	DECLARE @IDINVMOV_SI          VARCHAR(20)=DBO.FNK_VALORVARIABLE('IDINVMOV_SI')
	DECLARE @IDBOD_HEMODERIVADOS  VARCHAR(20) -- =DBO.FNK_VALORVARIABLE('IDBOD_HEMODERIVADOS')
	
	-- EZERPA 02/12/2020 Consultar la bodega de Unidad Transfusional desde la sede
	SELECT @IDBOD_HEMODERIVADOS = IDBODHEMO FROM SED WHERE IDSEDE=@SEDE
	IF COALESCE(@IDBOD_HEMODERIVADOS,'')='' SELECT @IDBOD_HEMODERIVADOS = SED.IDBODHEMO FROM UBEQ INNER JOIN SED ON SED.IDSEDE=UBEQ.IDSEDE WHERE SYS_COMPUTERNAME=@SYSCOMPUTER
	IF COALESCE(@IDBOD_HEMODERIVADOS,'')='' SELECT TOP 1 @IDBOD_HEMODERIVADOS = SED.IDBODHEMO FROM SED WHERE COALESCE(SED.IDBODHEMO,'')<>''
	IF COALESCE(@IDBOD_HEMODERIVADOS,'')='' SELECT @IDBOD_HEMODERIVADOS = DATO FROM USVGS WHERE IDVARIABLE='IDBOD_HEMODERIVADOS'
	-- EZERPA 02/12/2020 END

	-- Datos del movimiento de salida origen (IMOV.CNSMOVORI) - se usan SOLO en no compras
	SELECT
		@CCOSTO_ORIGEN     = CCOSTO,
		@IDSOLICITA_ORIGEN = IDSOLICITA,
		@IDRECIBE_ORIGEN   = IDRECIBE,
		@IDAREA_ORIGEN     = IDAREA
	FROM IMOV
	WHERE CNSMOV = (SELECT CNSMOVORI FROM ITRA WHERE CNSITRA = @CNSITRA);

   
	SELECT @IDINVMOV_COMPRAS=(CASE IDTIPOSER WHEN 'Presta' THEN @IDINVMOV_PRESTAMOS ELSE @IDINVMOV_COMPRAS END) FROM FCOM WHERE CNSFCOM IN (SELECT CNSFCOM FROM ITRA WHERE CNSITRA=@CNSITRA)
	

	IF  @ESTADO = 2
	BEGIN
		RAISERROR('Transito ya traido por otra estaci�n', 16, 1)
		RETURN
	END
	IF  @ESTADO = 1
	BEGIN
		RAISERROR('Transito ya traido y confirmado', 16, 1)
		RETURN
	END
	IF NOT EXISTS (SELECT 1 FROM ITRAH WHERE CNSITRA=@CNSITRA AND ESTADO<>1)
    BEGIN
        UPDATE ITRA SET ESTADO=1 FROM ITRA WHERE CNSITRA=@CNSITRA
		RAISERROR('Transito ya tiene todo su detalle diligenciado', 16, 1)
		RETURN
    END

	DECLARE @trancount int = @@trancount
	IF @trancount = 0
		BEGIN TRANSACTION
	ELSE
		SAVE TRANSACTION USP_SPK_INSERTENTTRANSITO

	BEGIN TRY

		DECLARE @MSG_SIN_DET    NVARCHAR(500)
		DECLARE @MSG_SIN_IMOV   NVARCHAR(500)
		DECLARE @MSG_SIN_IMOV_TR NVARCHAR(500)

		IF @IDTIPOMOV = @IDINVMOV_COMPRAS 
		BEGIN
			IF @DEPURAR = 1 PRINT '1.- '+CONVERT(VARCHAR,GETDATE(),108)
			
			DECLARE @PVENTA_IART_XTAR 
			TABLE (IDARTICULO       VARCHAR(20)  COLLATE database_default,
					DESCRIPCION      VARCHAR(512) COLLATE database_default,
					PVENTA           DECIMAL(14,2)
					)
			
			DECLARE @ARTICULOS TABLE (ITEM INT IDENTITY(1,1),IDARTICULO VARCHAR(20)) 
			INSERT INTO @ARTICULOS(IDARTICULO)
			SELECT DISTINCT IDARTICULO 
            FROM ITRAH WHERE CNSITRA=@CNSITRA


			
			DECLARE @ITEM_ACTUAL INT = 0
			DECLARE @TOTAL_ITEMS INT = (SELECT COUNT(1) FROM @ARTICULOS)
			WHILE @ITEM_ACTUAL < @TOTAL_ITEMS
			BEGIN
				SET @ITEM_ACTUAL = @ITEM_ACTUAL+1
				SELECT @IDARTICULO = IDARTICULO FROM @ARTICULOS WHERE ITEM=@ITEM_ACTUAL

				INSERT INTO @PVENTA_IART_XTAR(IDARTICULO,DESCRIPCION,PVENTA)
				SELECT IDARTICULO,DESCRIPCION,PVENTA FROM 
				DBO.FNK_PVENTA_IART_XTAR_IDARTICULO(@IDARTICULO,'MAX') 
			END

			CREATE TABLE #T (IDITAR VARCHAR(2) COLLATE DATABASE_DEFAULT, 
							CNSMOV VARCHAR(20)COLLATE DATABASE_DEFAULT)
			IF @IDINVENTRADAUNICA = 'SI' --AND @VIDITAR > 1
			BEGIN
				INSERT INTO #T (IDITAR, CNSMOV )
				SELECT @IDINVIDITARUNICA AS IDITAR, SPACE(20) AS CNSMOV 
			END
			ELSE
			BEGIN
				INSERT INTO #T (IDITAR, CNSMOV )
				SELECT DISTINCT IDITAR,SPACE(20) AS CNSMOV 
				FROM   ITRAH,ITRA,IART
				WHERE  ITRA.CNSITRA     = @CNSITRA 
				AND    ITRA.CNSITRA     = ITRAH.CNSITRA 
				AND    ITRAH.IDARTICULO = IART.IDARTICULO
				AND    ITRAH.INICIAL = 1
			END

			IF @DEPURAR = 1 PRINT '2.- '+CONVERT(VARCHAR,GETDATE(),108)

			IF NOT EXISTS (SELECT 1 FROM #T)
			BEGIN
				SET @MSG_SIN_DET = 'No hay detalle de tr�nsito con INICIAL=1 para generar la entrada del tr�nsito ' + COALESCE(@CNSITRA,'') + '.';
				THROW 50002, @MSG_SIN_DET, 1;
			END

			DECLARE CUR_CNS CURSOR FOR
				SELECT * FROM #T ORDER BY IDITAR
			OPEN CUR_CNS
			FETCH NEXT FROM CUR_CNS
			INTO @IDITAR_CUR,@CNSMOV_CUR
			SET @CONT = 0   
			WHILE @@FETCH_STATUS = 0
			BEGIN
				SET @CONT = @CONT + 1
				SET @NUEVOCNS = SPACE(20)
				IF @INVCONSECUTIVOSINDEP = 'SI'  
				BEGIN
					EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@EMOV',@NUEVOCNS OUTPUT
					SELECT @NUEVOCNS = @SEDE +'E'+ REPLACE(SPACE(8 - LEN(@NUEVOCNS))+LTRIM(RTRIM(@NUEVOCNS)),SPACE(1),0)          
				END
				ELSE
				BEGIN
					EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@MOV',@NUEVOCNS OUTPUT
					SELECT @NUEVOCNS = @SEDE + REPLACE(SPACE(8 - LEN(@NUEVOCNS))+LTRIM(RTRIM(@NUEVOCNS)),SPACE(1),0)
				END
			PRINT '@NUEVOCNS='+@NUEVOCNS
				-- MODIFICADO POR R.JAY EL 2009.04.22 ESTO FUE UNA RECOMENDACION DE ALEX ARROYO PARA EVITAR QUE EL
				-- LOS CONSECUTIVOS QUE SEAN REVERSADOS POR TERCEROS, NO VUELVA A SER USADOS
				IF EXISTS(SELECT * FROM IMOV WHERE CNSMOV = @NUEVOCNS)
				BEGIN
					RAISERROR('EL CONSECUTIVO %s UTILIZADO POR UN MOVIMIENTO, VERIFIQUE SUS CONTADORES', 16,1,@NUEVOCNS)
					--ROLLBACK  --01.JUNIO.2011_JEDM
					IF @@trancount <> 0
						IF @trancount = 0 ROLLBACK TRANSACTION
						ELSE
							IF XACT_STATE() <> -1
								ROLLBACK TRANSACTION USP_SPK_INSERTENTTRANSITO
					RETURN
				END           
            
				UPDATE #T SET CNSMOV = @NUEVOCNS WHERE IDITAR = @IDITAR_CUR


				--EZERPA 23.04.2018 RECONSTRUIR ITRAH PARA LOTES UNICOS ICBU
				IF @CODIGOUNICOICBU = 'SI' 
				BEGIN
					IF @DEPURAR = 1 PRINT 'GENERACION DE NOLOTES: '+CAST(CAST(GETDATE() AS TIME) AS VARCHAR)
				
					--EZERPA 26.02.2019 PARA QUITAR EL SPK QUE GENERA LOS CONSECUTIVOS y GENERARLOS MANUALMENTE

					EXEC SPK_INSERTENTTRANSITO_ICBU @CNSITRA, @COMPANIA, @SEDE
				
					--SELECT * FROM ITRAH WHERE CNSITRA=@CNSITRA
					IF @DEPURAR = 1 PRINT 'FIN GENERACION DE NOLOTES: '+CAST(CAST(GETDATE() AS TIME) AS VARCHAR)
				END
				--END EZERPA
				ELSE
				BEGIN
					--Distribuyo lotes por articulo
					IF (SELECT COUNT(1)
						FROM ITRAH I INNER JOIN IART A ON I.IDARTICULOORI=A.IDARTICULO
						WHERE I.CNSITRA=@CNSITRA AND ISNULL(A.ICBU,0)=1
						)>0
					BEGIN
						DECLARE @ICBU TABLE (ID INT IDENTITY(1,1), CODIGO_ICBU VARCHAR(20))
						DECLARE @CODIGO_ICBU VARCHAR(20), @FIX INT, @FIX_TO INT

						INSERT INTO @ICBU (CODIGO_ICBU)
						SELECT DISTINCT IDARTICULOORI 
						FROM ITRAH I INNER JOIN IART A ON I.IDARTICULOORI=A.IDARTICULO
						WHERE I.CNSITRA=@CNSITRA AND ISNULL(A.ICBU,0)=1

						SELECT @FIX=1, @FIX_TO=COUNT(1) FROM @ICBU

						WHILE @FIX<=@FIX_TO
						BEGIN
							SELECT @CODIGO_ICBU=CODIGO_ICBU FROM @ICBU WHERE ID=@FIX
							EXEC SPK_INSERTENTTRANSITO_ICBU @CNSITRA, @COMPANIA, @SEDE, @CODIGO_ICBU
							SET @FIX+=1
						END

						DELETE @ICBU WHERE 1=1
					END
				END



				-- Entradas remanentes (2.�+ OC): no heredar factura/fechas de FCOM ni USUARIOTRA como proveedor.
				DECLARE @OC_ENTRADA_PREVIA BIT = 0
				IF @IDTIPOMOV = @IDINVMOV_COMPRAS
				BEGIN
					SELECT @OC_ENTRADA_PREVIA = CASE
						WHEN EXISTS (
							SELECT 1
							FROM ITRA T0
							INNER JOIN IMOV I0 ON I0.CNSFCOM = T0.CNSFCOM
							WHERE T0.CNSITRA = @CNSITRA
							  AND COALESCE(I0.ESTADO, 0) = 1
							  AND I0.IDTIPOMOV = @IDINVMOV_COMPRAS
						) THEN 1 ELSE 0
					END
				END

				IF @IDBOD_HEMODERIVADOS = @IDBODEGA
				BEGIN
					IF @DEPURAR = 1 PRINT 'INSERTO IMOV BODEGA HEMODERIVADOS'
					--INSERTO EN IMOV CON OBSERVACION DISTINTA POR HEMODERIVADOS LROJAS 2018.05.18
					INSERT INTO IMOV (CNSMOV,IDBODEGA,IDTIPOMOV,NODOCUMENTO,F_FACTURA,F_VENCE,TIPODOCU,FECHAMOV,CCOSTO,IDSOLICITA,IDTERCERO,
							IDFUNCIONARIO,IDRECIBE,FACTORVENTA,ESTADO,IDBODEGAEXTERNA,CNSTRAN,OBSERVACION,CNSFCOM,  
							SUBIOCOMPRA,NOPRESTACION,IDAREA,CONTABILIZADA,NROCOMPROBANTE,PROCEDENCIA,USUARIO,  
							USUARIOCONF,FECHACONF,PARCIAL,IDAREAH,NIVELATENCION,SYS_COMPUTERNAME,TIENECAMBIO,
							IDITAR,ESTRANSITO,CNSITRA, CODUNG, CODPRG, TIPO_DOC_COMPRA, VLR_FLETE)
					SELECT @NUEVOCNS, @IDBODEGA, @IDTIPOMOV,
							CASE WHEN @OC_ENTRADA_PREVIA = 1 THEN NULL ELSE FCOM.N_FACTURA END,
							CASE WHEN @OC_ENTRADA_PREVIA = 1 THEN NULL ELSE FCOM.F_FACTURA END,
							CASE WHEN @OC_ENTRADA_PREVIA = 1 THEN NULL ELSE FCOM.F_VENCE END,
							'',
							DBO.FNK_FECHA_SIN_MLS(GETDATE()), FCOM.CCOSTO, FCOM.USUARIOORDEN,
							COALESCE(NULLIF(FCOM.IDTERCERO,''), NULLIF(ITRA.USUARIOTRA,'')),
							'', @USUARIO, 0, '0', IDBODEGADES,
							'', 'Condiciones de transporte:  '+ CHAR(13) + CHAR(10) + 'Aspecto visual:  ', FCOM.CNSFCOM, 0, '', FCOM.IDAREA, 0, '', ITRA.PROCEDENCIA, @USUARIO,
							NULL, NULL, 0, '', '', @SYSCOMPUTER, 0, @IDITAR_CUR, 1, ITRA.CNSITRA, FCOM.CODUNG, FCOM.CODPRG,'F', FCOM.VLR_FLETE
					FROM   ITRA LEFT JOIN FCOM ON ITRA.CNSFCOM=FCOM.CNSFCOM
					WHERE  ITRA.CNSITRA = @CNSITRA
				END
				ELSE
				BEGIN
					IF @DEPURAR = 1 PRINT 'INSERTO IMOV DESPUES HEMODERIVADOS'
					INSERT INTO IMOV (CNSMOV,IDBODEGA,IDTIPOMOV,NODOCUMENTO,F_FACTURA,F_VENCE,TIPODOCU,FECHAMOV,CCOSTO,IDSOLICITA,IDTERCERO,
						IDFUNCIONARIO,IDRECIBE,FACTORVENTA,ESTADO,IDBODEGAEXTERNA,CNSTRAN,OBSERVACION,CNSFCOM,  
						SUBIOCOMPRA,NOPRESTACION,IDAREA,CONTABILIZADA,NROCOMPROBANTE,PROCEDENCIA,USUARIO,  
						USUARIOCONF,FECHACONF,PARCIAL,IDAREAH,NIVELATENCION,SYS_COMPUTERNAME,TIENECAMBIO,
						IDITAR,ESTRANSITO,CNSITRA, CODUNG, CODPRG, TIPO_DOC_COMPRA, VLR_FLETE)
					SELECT @NUEVOCNS, @IDBODEGA, @IDTIPOMOV,
						CASE WHEN @OC_ENTRADA_PREVIA = 1 THEN NULL ELSE FCOM.N_FACTURA END,
						CASE WHEN @OC_ENTRADA_PREVIA = 1 THEN NULL ELSE FCOM.F_FACTURA END,
						CASE WHEN @OC_ENTRADA_PREVIA = 1 THEN NULL ELSE FCOM.F_VENCE END,
						'',
						DBO.FNK_FECHA_SIN_MLS(GETDATE()), FCOM.CCOSTO, FCOM.USUARIOORDEN,
						COALESCE(NULLIF(FCOM.IDTERCERO,''), NULLIF(ITRA.USUARIOTRA,'')),
						'', @USUARIO, 0, '0', IDBODEGADES,
						'', 'Compras a Proveedores', FCOM.CNSFCOM, 0, '', FCOM.IDAREA, 0, '', ITRA.PROCEDENCIA, @USUARIO,
						NULL, NULL, 0, '', '', @SYSCOMPUTER, 0, @IDITAR_CUR, 1, ITRA.CNSITRA, FCOM.CODUNG, FCOM.CODPRG,'F', FCOM.VLR_FLETE
					FROM   ITRA LEFT JOIN FCOM ON ITRA.CNSFCOM=FCOM.CNSFCOM
					WHERE  ITRA.CNSITRA = @CNSITRA 
				END
			
				-- Si no se insert� IMOV, NO continuar con IMOVH (evita FK).
				IF @@ROWCOUNT = 0 OR NOT EXISTS (SELECT 1 FROM IMOV WITH (UPDLOCK, HOLDLOCK) WHERE CNSMOV = @NUEVOCNS)
				BEGIN
					SET @MSG_SIN_IMOV = 'No fue posible insertar el encabezado IMOV para el movimiento ' + COALESCE(@NUEVOCNS,'') + ' (antes de insertar IMOVH). Verifique el movimiento origen del tr�nsito.';
					THROW 50001, @MSG_SIN_IMOV, 1;
				END

				IF @DEPURAR = 1 PRINT 'INSERTO IMOVH'

				SELECT @DECONSUMO = FCOM.DECONSUMO 
				FROM   FCOM, ITRA 
				WHERE  ITRA.CNSITRA = @CNSITRA 
				AND    ITRA.CNSFCOM = FCOM.CNSFCOM

				SELECT * INTO #PVENTA_IART_XTAR FROM @PVENTA_IART_XTAR

				IF @LOTEADO = 1
				BEGIN
					INSERT INTO IMOVH (CNSMOV, IDARTICULO,EXISTENCIA,CANTIDAD,CANTPEDIDA,PCOSTO,
										NOLOTE, ESTADO, CNSTRAN,USUARIO, NOLOTEPEDIDO,FECHAVENCE,
										DETALLE,VLRDTO, VLRIVA,PDTO,PIVA,PVENTA, IDIMPUESTO, IDCLASE, IDITAR, IDARTICULOORI,SELLOCALIDAD,RINVIMA,CAPACIDAD,
								ODESFERA,OIESFERA,ODCILINDRO,OICILINDRO,ODEJE,OIEJE,ODADICION,OIADICION,ODALT,OIALT,ODAVL,OIAVL,ODTLENTE,
								OITLENTE,ODDNP,OIDNP, ESTANTE, CUARENTENA)
					SELECT @NUEVOCNS, UPPER(
								CASE
									WHEN COALESCE(ITRAH.IDARTICULOORI, '') <> ''
										AND ITRAH.IDARTICULO <> ITRAH.IDARTICULOORI
										AND NOT EXISTS (
											SELECT 1
											FROM IART DET WITH (NOLOCK)
											INNER JOIN IART ORI WITH (NOLOCK) ON ORI.IDARTICULO = ITRAH.IDARTICULOORI
											LEFT JOIN ITAR T WITH (NOLOCK) ON T.IDITAR = ORI.IDITAR
											LEFT JOIN ITRA TRA WITH (NOLOCK) ON TRA.CNSITRA = ITRAH.CNSITRA
											LEFT JOIN FCOM FC WITH (NOLOCK) ON FC.CNSFCOM = TRA.CNSFCOM
											WHERE DET.IDARTICULO = ITRAH.IDARTICULO
											  AND (
													DET.IDARTICULO LIKE ORI.IDARTICULO + '-%'
													OR ORI.IDARTICULO LIKE DET.IDARTICULO + '-%'
													OR (
														COALESCE(FC.PROCEDENCIA, '') <> 'ILPRE'
														AND COALESCE(ORI.PRINCIPAL, 0) = 1
														AND COALESCE(T.MPRINCIPAL, 0) = 1
														AND COALESCE(DET.IDSERVICIO, '') <> ''
														AND DET.IDSERVICIO = ORI.IDSERVICIO
														AND COALESCE(DET.PRINCIPAL, 0) = 0
													)
											  )
										)
									THEN ITRAH.IDARTICULOORI
									ELSE ITRAH.IDARTICULO
								END
							), 0, CASE @IDTIPOMOV 
																		WHEN @IDINVMOV_COMPRAS THEN ITRAH.CANTIDADDES 
																		ELSE ITRAH.CANTIDADORI 
																	END AS CANTIDAD  ,ITRAH.CANTIDADORI,
							CASE @DECONSUMO WHEN 1 THEN ITRAH.PCOSTO WHEN 0 THEN FCOMD.VR_ANTESIVA/ITRAH.CANTIDADORI END,
							ITRAH.NOLOTE, '0', '', @USUARIO, ITRAH.NOLOTEPEDIDO, ITRAH.FECHAVENCE, ITRAH.DETALLE,
							FCOMD.VR_DESCUENTO,
							ROUND (ITRAH.CANTIDADDES * ROUND( ITRAH.PCOSTO / (1+((CASE COALESCE(FCOMD.IDIMPUESTO,'') WHEN '' THEN 0 ELSE FCOMD.FACTORIVA END)/100.00)),2) * ((CASE COALESCE(FCOMD.IDIMPUESTO,'') WHEN '' THEN 0 ELSE FCOMD.FACTORIVA END)/100.00) ,2),
							CASE WHEN COALESCE(FCOMD.VR_ANTESIVA,0)<=0 THEN 0 ELSE (FCOMD.VR_DESCUENTO*100)/FCOMD.VR_ANTESIVA END, FCOMD.FACTORIVA, X.PVENTA,
							FCOMD.IDIMPUESTO, FCOMD.IDCLASE, IART.IDITAR, ITRAH.IDARTICULOORI,ITRAH.SELLOCALIDAD,ITRAH.RINVIMA,ITRAH.CAPACIDAD,ITRAH.ODESFERA,ITRAH.OIESFERA,ITRAH.ODCILINDRO,
						ITRAH.OICILINDRO,ITRAH.ODEJE,ITRAH.OIEJE,ITRAH.ODADICION,ITRAH.OIADICION,ITRAH.ODALT,ITRAH.OIALT,ITRAH.ODAVL,ITRAH.OIAVL,
						ITRAH.ODTLENTE,ITRAH.OITLENTE,ITRAH.ODDNP,ITRAH.OIDNP, ITRAH.ESRTANTE, ITRAH.CUARENTENA
					FROM   ITRAH LEFT  JOIN #PVENTA_IART_XTAR X ON COALESCE(ITRAH.IDARTICULOORI, ITRAH.IDARTICULO) = X.IDARTICULO
								INNER JOIN ITRA  ON ITRA.CNSITRA       = ITRAH.CNSITRA
								INNER JOIN IART  ON COALESCE(ITRAH.IDARTICULOORI, ITRAH.IDARTICULO) = IART.IDARTICULO
								INNER JOIN FCOMD ON ITRA.CNSFCOM       = FCOMD.CNSFCOM
												AND COALESCE(ITRAH.IDARTICULOORI, ITRAH.IDARTICULO) = FCOMD.IDARTICULO
								INNER JOIN IMOV M ON M.CNSMOV = @NUEVOCNS
					WHERE  ITRA.CNSITRA = @CNSITRA AND ITRAH.INICIAL=1
                           
				END
				ELSE
				BEGIN
					INSERT INTO IMOVH (CNSMOV, IDARTICULO,EXISTENCIA,CANTIDAD,CANTPEDIDA,PCOSTO,
										NOLOTE, ESTADO, CNSTRAN,USUARIO, NOLOTEPEDIDO,FECHAVENCE,
										DETALLE,VLRDTO, VLRIVA,PDTO,PIVA,PVENTA, IDIMPUESTO, IDCLASE, IDITAR, IDARTICULOORI,SELLOCALIDAD,RINVIMA,CAPACIDAD,
								ODESFERA,OIESFERA,ODCILINDRO,OICILINDRO,ODEJE,OIEJE,ODADICION,OIADICION,ODALT,OIALT,ODAVL,OIAVL,ODTLENTE,
								OITLENTE,ODDNP,OIDNP, ESTANTE, CUARENTENA )                             
					SELECT @NUEVOCNS, UPPER(
								CASE
									WHEN COALESCE(ITRAH.IDARTICULOORI, '') <> ''
										AND ITRAH.IDARTICULO <> ITRAH.IDARTICULOORI
										AND NOT EXISTS (
											SELECT 1
											FROM IART DET WITH (NOLOCK)
											INNER JOIN IART ORI WITH (NOLOCK) ON ORI.IDARTICULO = ITRAH.IDARTICULOORI
											LEFT JOIN ITAR T WITH (NOLOCK) ON T.IDITAR = ORI.IDITAR
											LEFT JOIN ITRA TRA WITH (NOLOCK) ON TRA.CNSITRA = ITRAH.CNSITRA
											LEFT JOIN FCOM FC WITH (NOLOCK) ON FC.CNSFCOM = TRA.CNSFCOM
											WHERE DET.IDARTICULO = ITRAH.IDARTICULO
											  AND (
													DET.IDARTICULO LIKE ORI.IDARTICULO + '-%'
													OR ORI.IDARTICULO LIKE DET.IDARTICULO + '-%'
													OR (
														COALESCE(FC.PROCEDENCIA, '') <> 'ILPRE'
														AND COALESCE(ORI.PRINCIPAL, 0) = 1
														AND COALESCE(T.MPRINCIPAL, 0) = 1
														AND COALESCE(DET.IDSERVICIO, '') <> ''
														AND DET.IDSERVICIO = ORI.IDSERVICIO
														AND COALESCE(DET.PRINCIPAL, 0) = 0
													)
											  )
										)
									THEN ITRAH.IDARTICULOORI
									ELSE ITRAH.IDARTICULO
								END
							), 0,CASE @IDTIPOMOV 
																		WHEN @IDINVMOV_COMPRAS THEN ITRAH.CANTIDADDES 
																		ELSE ITRAH.CANTIDADORI 
																END AS CANTIDAD , ITRAH.CANTIDADORI, 
							CASE @DECONSUMO WHEN 1 THEN ITRAH.PCOSTO WHEN 0 THEN FCOMD.VR_ANTESIVA/FCOMD.CANTIDAD END,
							ITRAH.NOLOTE, '0', '', @USUARIO, ITRAH.NOLOTEPEDIDO, ITRAH.FECHAVENCE, ITRAH.DETALLE, 
							FCOMD.VR_DESCUENTO,
							ROUND (ITRAH.CANTIDADDES * ROUND( ITRAH.PCOSTO / (1+((CASE COALESCE(FCOMD.IDIMPUESTO,'') WHEN '' THEN 0 ELSE FCOMD.FACTORIVA END)/100.00)),2) * ((CASE COALESCE(FCOMD.IDIMPUESTO,'') WHEN '' THEN 0 ELSE FCOMD.FACTORIVA END)/100.00) ,2),
							CASE WHEN COALESCE(FCOMD.VR_ANTESIVA,0)<=0 THEN 0 ELSE (FCOMD.VR_DESCUENTO*100)/FCOMD.VR_ANTESIVA END, FCOMD.FACTORIVA, X.PVENTA, 
							FCOMD.IDIMPUESTO, FCOMD.IDCLASE, IART.IDITAR, ITRAH.IDARTICULOORI,ITRAH.SELLOCALIDAD,ITRAH.RINVIMA,ITRAH.CAPACIDAD,
								ITRAH.ODESFERA,ITRAH.OIESFERA,ITRAH.ODCILINDRO,ITRAH.OICILINDRO,ITRAH.ODEJE,ITRAH.OIEJE,ITRAH.ODADICION,ITRAH.OIADICION,
								ITRAH.ODALT,ITRAH.OIALT,ITRAH.ODAVL,ITRAH.OIAVL,ITRAH.ODTLENTE,ITRAH.OITLENTE,ITRAH.ODDNP,ITRAH.OIDNP,
								ITRAH.ESTANTE, ITRAH.CUARENTENA
					FROM   ITRAH LEFT  JOIN #PVENTA_IART_XTAR X ON COALESCE(ITRAH.IDARTICULOORI, ITRAH.IDARTICULO) = X.IDARTICULO 
								INNER JOIN ITRA  ON ITRA.CNSITRA       = ITRAH.CNSITRA 
								INNER JOIN IART  ON COALESCE(ITRAH.IDARTICULOORI, ITRAH.IDARTICULO) = IART.IDARTICULO 
								LEFT JOIN FCOMD ON ITRA.CNSFCOM       = FCOMD.CNSFCOM 
												AND FCOMD.IDARTICULO   = ITRAH.IDARTICULOORI
								INNER JOIN IMOV M ON M.CNSMOV = @NUEVOCNS
					WHERE  ITRA.CNSITRA = @CNSITRA AND ITRAH.INICIAL=1
				END  

				DROP TABLE #PVENTA_IART_XTAR
				
				--INSERTA OBSEQUIOS (se dejan igual que original)
				-- ...
				-- (todo el bloque de obsequios IMOV / IMOVH que ya ten�as, sin cambios)
				-- ...

			FETCH NEXT FROM CUR_CNS
			INTO @IDITAR_CUR,@CNSMOV_CUR
			END
			CLOSE CUR_CNS
			DEALLOCATE CUR_CNS
     
			IF @CONT > 1
				UPDATE ITRA SET ESTADO = 2, CNSMOVDES = 'VARIOS'  WHERE ITRA.CNSITRA = @CNSITRA
			ELSE
				UPDATE ITRA SET ESTADO = 2, CNSMOVDES = @NUEVOCNS WHERE ITRA.CNSITRA = @CNSITRA
		END
		ELSE--NO ES DE TIPO DE MOVIMIENTO COMPRAS
		BEGIN
			
			SET @NUEVOCNS=SPACE(20)  
			EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@MOV',@NUEVOCNS OUTPUT
			SELECT @NUEVOCNS = @SEDE + REPLACE(SPACE(8 - LEN(@NUEVOCNS))+LTRIM(RTRIM(@NUEVOCNS)),SPACE(1),0)
			/*ALEX*/ 
			IF @IDINVENTRADAUNICA = 'SI' --AND @VIDITAR > 1
			BEGIN
				SET @IDITAR = @IDINVIDITARUNICA
			END
			ELSE
			BEGIN
				SELECT @IDITAR = X.IDITAR
				FROM  IMOV X, ITRA
				WHERE ITRA.CNSITRA=@CNSITRA AND X.CNSMOV=ITRA.CNSMOVORI

				-- Si no existe el movimiento origen, tomar IDITAR desde el detalle del tr�nsito.
				IF COALESCE(@IDITAR,'') = ''
				BEGIN
					SELECT TOP 1 @IDITAR = IART.IDITAR
					FROM ITRAH INNER JOIN IART ON ITRAH.IDARTICULO = IART.IDARTICULO
					WHERE ITRAH.CNSITRA = @CNSITRA
				END
			END 
			
			-- Nota: en traslados entre bodegas (no compras) NO se debe marcar como Factura.
			-- Esta rama inserta el IMOV destino con datos de FCOM y fuerza TIPO_DOC_COMPRA='F'.
			-- Debe aplicar solo para hemoderivados; IDINVTPROPIA debe caer en la rama de traslados
			-- que hereda del IMOV origen y usa TIPO_DOC_COMPRA='N'.
			IF @IDBOD_HEMODERIVADOS = @IDBODEGA
			BEGIN

				-- ESTA RAMA (hemoderivados / propia) 
				INSERT INTO IMOV (CNSMOV,IDBODEGA,IDTIPOMOV,NODOCUMENTO,F_FACTURA,F_VENCE,TIPODOCU,FECHAMOV,CCOSTO,IDSOLICITA,IDTERCERO,
								IDFUNCIONARIO,IDRECIBE,FACTORVENTA,ESTADO,IDBODEGAEXTERNA,CNSTRAN,OBSERVACION,CNSFCOM,  
								SUBIOCOMPRA,NOPRESTACION,IDAREA,CONTABILIZADA,NROCOMPROBANTE,PROCEDENCIA,USUARIO,  
								USUARIOCONF,FECHACONF,PARCIAL,IDAREAH,NIVELATENCION,SYS_COMPUTERNAME,TIENECAMBIO,
								IDITAR,ESTRANSITO,CNSITRA, CODUNG, CODPRG, TIPO_DOC_COMPRA, VLR_FLETE)
						SELECT @NUEVOCNS, @IDBODEGA, @IDTIPOMOV, FCOM.N_FACTURA, FCOM.F_FACTURA,FCOM.F_VENCE,'', 
								DBO.FNK_FECHA_SIN_MLS(GETDATE()), COALESCE(FCOM.CCOSTO, @CCOSTO_ORIGEN), COALESCE(FCOM.USUARIOORDEN, @IDSOLICITA_ORIGEN), USUARIOTRA, COALESCE(NULLIF(@IDRECIBE_ORIGEN,''), ''), 
								@IDRECIBE_ORIGEN, 0, '0', IDBODEGADES, '', 'Condiciones de transporte:  '+ CHAR(13) + CHAR(10) + 'Aspecto visual:  ', FCOM.CNSFCOM, 0, '', COALESCE(FCOM.IDAREA, @IDAREA_ORIGEN), 0, '', ITRA.PROCEDENCIA, @USUARIO, 
								NULL, NULL, 0, '', '', @SYSCOMPUTER, 0, @IDITAR, 1, ITRA.CNSITRA, FCOM.CODUNG, FCOM.CODPRG,'F', FCOM.VLR_FLETE
						FROM   ITRA LEFT JOIN FCOM ON ITRA.CNSFCOM = FCOM.CNSFCOM
						WHERE  ITRA.CNSITRA = @CNSITRA 
			END
			ELSE
			BEGIN

   				-- TRASLADOS ENTRE BODEGAS (NO COMPRAS): heredar desde IMOV origen si existe,
				-- pero SIEMPRE insertar encabezado aunque CNSMOVORI est� vac�o.
				INSERT INTO IMOV (CNSMOV,IDBODEGA,IDTIPOMOV,NODOCUMENTO,TIPODOCU,FECHAMOV,CCOSTO,IDSOLICITA,IDTERCERO,
								IDFUNCIONARIO,IDRECIBE,FACTORVENTA,ESTADO,IDBODEGAEXTERNA,cnsTran,OBSERVACION,CNSFCOM,  
								SUBIOCOMPRA,NOPRESTACION,IDAREA,CONTABILIZADA,NROCOMPROBANTE,PROCEDENCIA,USUARIO,  
								USUARIOCONF,FECHACONF,PARCIAL,IDAREAH,NIVELATENCION,SYS_CompuTerName,TIENECAMBIO,
								IDITAR,ESTRANSITO,CNSITRA, CODUNG, CODPRG,TIPO_DOC_COMPRA)
				SELECT @NUEVOCNS, @IDBODEGA, @IDTIPOMOV,
						COALESCE(NULLIF(X.NODOCUMENTO,''), ITRA.NOADMISION, ''), COALESCE(X.TIPODOCU,''), DBO.FNK_FECHA_SIN_MLS(GETDATE()),
						COALESCE(NULLIF(@CCOSTO_ORIGEN,''), X.CCOSTO, ITRA.CCOSTO, ''), 
						COALESCE(NULLIF(@IDSOLICITA_ORIGEN,''), X.IDSOLICITA, '' ),
						COALESCE(X.IDTERCERO, ITRA.USUARIOTRA),
						ITRA.USUARIOTRA,
						COALESCE(NULLIF(@IDRECIBE_ORIGEN,''), NULLIF(X.IDRECIBE,''), @USUARIO),
						COALESCE(X.FACTORVENTA, 0), '0', COALESCE(X.IDBODEGA, ITRA.IDBODEGAORI, ''),
						COALESCE(X.CNSTRAN,''), COALESCE(X.OBSERVACION,'Traslado entre bodegas'), COALESCE(X.CNSFCOM, ITRA.CNSFCOM, ''), COALESCE(X.SUBIOCOMPRA,0), COALESCE(X.NOPRESTACION,''),
						COALESCE(NULLIF(@IDAREA_ORIGEN,''), X.IDAREA, ITRA.IDAREA, ''), 0,
						'', COALESCE(X.PROCEDENCIA, ITRA.PROCEDENCIA, ''), @USUARIO, NULL, NULL, COALESCE(X.PARCIAL,0), COALESCE(X.IDAREAH,''), COALESCE(X.NIVELATENCION,''),
						COALESCE(X.SYS_CompuTerName, @SYSCOMPUTER), COALESCE(X.TIENECAMBIO,0), @IDITAR, 1, ITRA.CNSITRA, COALESCE(X.CODUNG,''), COALESCE(X.CODPRG,''),'N'
				FROM   ITRA
				LEFT JOIN IMOV X ON X.CNSMOV = ITRA.CNSMOVORI
				WHERE  ITRA.CNSITRA = @CNSITRA 
			END

			-- Validaci�n: si no qued� encabezado IMOV, no continuar con IMOVH (evita FK).
			IF @@ROWCOUNT = 0 OR NOT EXISTS (SELECT 1 FROM IMOV WITH (UPDLOCK, HOLDLOCK) WHERE CNSMOV = @NUEVOCNS)
			BEGIN
				SET @MSG_SIN_IMOV_TR = 'No fue posible insertar el encabezado IMOV para el movimiento ' + COALESCE(@NUEVOCNS,'') + ' (traslado). Verifique ITRA.CNSMOVORI y el movimiento origen.';
				THROW 50001, @MSG_SIN_IMOV_TR, 1;
			END

			INSERT INTO IMOVH (CNSMOV,IDARTICULO,EXISTENCIA,CANTIDAD,CANTPEDIDA,PCOSTO,NOLOTE,
							ESTADO,CNSTRAN,USUARIO,NOLOTEPEDIDO,FECHAVENCE,PVENTA, ESTANTE, CUARENTENA)
			SELECT @NUEVOCNS, UPPER(
								CASE
									WHEN COALESCE(ITRAH.IDARTICULOORI, '') <> ''
										AND ITRAH.IDARTICULO <> ITRAH.IDARTICULOORI
										AND NOT EXISTS (
											SELECT 1
											FROM IART DET WITH (NOLOCK)
											INNER JOIN IART ORI WITH (NOLOCK) ON ORI.IDARTICULO = ITRAH.IDARTICULOORI
											LEFT JOIN ITAR T WITH (NOLOCK) ON T.IDITAR = ORI.IDITAR
											LEFT JOIN ITRA TRA WITH (NOLOCK) ON TRA.CNSITRA = ITRAH.CNSITRA
											LEFT JOIN FCOM FC WITH (NOLOCK) ON FC.CNSFCOM = TRA.CNSFCOM
											WHERE DET.IDARTICULO = ITRAH.IDARTICULO
											  AND (
													DET.IDARTICULO LIKE ORI.IDARTICULO + '-%'
													OR ORI.IDARTICULO LIKE DET.IDARTICULO + '-%'
													OR (
														COALESCE(FC.PROCEDENCIA, '') <> 'ILPRE'
														AND COALESCE(ORI.PRINCIPAL, 0) = 1
														AND COALESCE(T.MPRINCIPAL, 0) = 1
														AND COALESCE(DET.IDSERVICIO, '') <> ''
														AND DET.IDSERVICIO = ORI.IDSERVICIO
														AND COALESCE(DET.PRINCIPAL, 0) = 0
													)
											  )
										)
									THEN ITRAH.IDARTICULOORI
									ELSE ITRAH.IDARTICULO
								END
							), 0,CASE @IDTIPOMOV 
																WHEN @IDINVMOV_COMPRAS THEN ITRAH.CANTIDADDES 
																ELSE ITRAH.CANTIDADORI 
																END AS CANTIDAD,ITRAH.CANTIDADORI,  ITRAH.PCOSTO,
				ITRAH.NOLOTE, '0', '', @USUARIO, ITRAH.NOLOTEPEDIDO,ITRAH.FECHAVENCE,X.PVENTA
				,ITRAH.ESTANTE, ITRAH.CUARENTENA
			FROM   ITRAH INNER JOIN ITRA ON ITRA.CNSITRA = ITRAH.CNSITRA 
						INNER JOIN IMOV M ON M.CNSMOV = @NUEVOCNS
						LEFT  JOIN FNK_PVENTA_IART_XTAR('MAX') X ON ITRAH.IDARTICULO = X.IDARTICULO
			WHERE  ITRA.CNSITRA = @CNSITRA
			  AND  ITRAH.INICIAL = 1


                       
			UPDATE ITRA SET ESTADO = 2, CNSMOVDES = @NUEVOCNS WHERE ITRA.CNSITRA = @CNSITRA
		END

		--REQ 3211 JFRANCO 20200305
		IF dbo.FNK_VALORVARIABLE('COLOCAR_TOTAL_IMOV') = 'SI'
		BEGIN
			SELECT @VLRCOMPRA = SUM( (IMOVH.CANTIDAD * ROUND( IMOVH.PCOSTO / (1+((CASE COALESCE(IMOVH.IDIMPUESTO,'') WHEN '' THEN 0 ELSE IMOVH.PIVA END)/100.00)) ,2)) + COALESCE(IMOVH.VLRIVA,0)) 
			FROM IMOVH 
			WHERE IMOVH.CNSMOV = @NUEVOCNS

			UPDATE IMOV SET VLRCOMPRA = @VLRCOMPRA
			WHERE CNSMOV = @NUEVOCNS
		END

		UPDATE  IMOVH
		SET	  EXISTENCIA = IDXB.EXISTOTAL
		FROM	  IMOV,IDXB
		WHERE   IMOV.CNSITRA     = @CNSITRA 
		AND     IMOVH.IDARTICULO = IDXB.IDARTICULO 
		AND     IMOV.IDBODEGA    = IDXB.IDBODEGA 
		AND     IMOV.CNSMOV      = IMOVH.CNSMOV
 
		UPDATE ITRAH SET ESTADO = 2 
		WHERE  ITRAH.CNSITRA = @CNSITRA

		IF @DEPURAR = 1 PRINT '5.- '+CONVERT(VARCHAR,GETDATE(),108)
		/*EZERPA 30.01.2016 */
		/*PARA CREAR DE UNA LAS ETIQUETAS AL CONFIRMAR LAS ENTRADAS AL ALMACEN*/
		/*REVISAMOS QUE SEAN MOVIMIENTOS DE ENTRADAS POR COMPRAS Y POR REMISION*/
		DECLARE @CNSMOV AS VARCHAR(20)
		DECLARE @CNSFCOM AS VARCHAR(20)
		DECLARE @NOLOTEPEDIDO AS VARCHAR(20)

		SELECT @CNSMOV=CNSMOV,@CNSFCOM=CNSFCOM,@IDTIPOMOV=IDTIPOMOV FROM IMOV WHERE CNSITRA=@CNSITRA 

		IF @DEPURAR = 1 PRINT '@CNSFCOM = '+ @CNSFCOM + ', @CNSMOV = '+@CNSMOV
		IF @DEPURAR = 1 PRINT 'INSERSION EN ICBU: '+CAST(CAST(GETDATE() AS TIME) AS VARCHAR)
		IF (ISNULL(@CNSMOV,'')<>'') 
		BEGIN
			IF @IDTIPOMOV IN (@IDINVMOV_COMPRAS, @IDINVMOV_REMISION_EN, @IDINVMOV_SI) AND @CODIGOUNICOICBU = 'SI'
			BEGIN
			
				INSERT INTO ICBU ( IDARTICULO, CODIGOBARRA, NOLOTE, FECVTO, CNSFCOM, CNSMOV,SELLOCALIDAD,CAPACIDAD)
				SELECT IDARTICULO, NOLOTE, NOLOTEPEDIDO, FECHAVENCE,CNSFCOM,IMOV.CNSMOV,SELLOCALIDAD,CAPACIDAD
				FROM   IMOVH INNER JOIN IMOV ON IMOV.CNSMOV=IMOVH.CNSMOV    
				WHERE  IMOVH.CNSMOV = @CNSMOV AND NOT EXISTS (
						SELECT 1 FROM ICBU WHERE ICBU.IDARTICULO=IMOVH.IDARTICULO AND ICBU.NOLOTE=IMOVH.NOLOTEPEDIDO
						AND IMOV.CNSFCOM=ICBU.CNSFCOM AND IMOV.CNSMOV=ICBU.CNSMOV AND IMOVH.NOLOTE=ICBU.CODIGOBARRA  )
			END
		END
		/*EZERPA END*/
		IF @DEPURAR = 1 PRINT 'FIN INSERSION EN ICBU: '+CAST(CAST(GETDATE() AS TIME) AS VARCHAR)
		IF @DEPURAR = 1 PRINT '6.- '+CONVERT(VARCHAR,GETDATE(),108)
	
		IF @trancount = 0 AND XACT_STATE() = 1
			COMMIT
	END TRY
	BEGIN CATCH
		DECLARE @ERRMSG NVARCHAR(2048) = ERROR_MESSAGE()

		IF XACT_STATE() <> 0
		BEGIN
			IF @trancount = 0
				ROLLBACK TRANSACTION
			ELSE
			BEGIN
				IF XACT_STATE() = 1
					ROLLBACK TRANSACTION USP_SPK_INSERTENTTRANSITO
				ELSE
					ROLLBACK TRANSACTION
			END
		END

		RAISERROR(@ERRMSG, 16, 1)
		RETURN
	END CATCH
