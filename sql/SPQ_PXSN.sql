CREATE OR ALTER PROCEDURE DBO.SPQ_PXSN @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
BEGIN
	SET NOCOUNT ON;

	-- Declaraci�n de Variables
	DECLARE @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20), @PARAMETROS NVARCHAR(MAX)
	DECLARE @PROCESO VARCHAR(20)
	DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
	-- Variables de datos (PXSN)
	DECLARE @IDTERCERO VARCHAR(20), @IDADMINISTRADORA VARCHAR(20), @IDPLAN VARCHAR(6)
	DECLARE @IDTARIFA VARCHAR(5), @FACTOR DECIMAL(7, 3), @IDPROVEEDOR VARCHAR(20), @IDPROVEEDORCOPIA VARCHAR(20)
	-- Variables para Edici�n (Old Values)
	DECLARE @IDTERCEROEDITE VARCHAR(20), @IDADMINISTRADORAEDITE VARCHAR(20), @IDPLANEDITE VARCHAR(6)

	-- Lectura Inicial (Cabecera)
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@JSON) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			);

	BEGIN TRY
		BEGIN TRANSACTION;

		IF @METODO = 'GUARDAR'
		BEGIN
			SELECT @IDTERCERO = IDTERCERO, @IDADMINISTRADORA = IDADMINISTRADORA, @IDPLAN = IDPLAN, @IDTARIFA = IDTARIFA, @FACTOR = FACTOR, @PROCESO = PROCESO, 
				@IDADMINISTRADORAEDITE = IDADMINISTRADORAEDITE, @IDPLANEDITE = IDPLANEDITE, @IDTERCEROEDITE = IDTERCEROEDITE
			FROM OPENJSON(@PARAMETROS) WITH (
					IDTERCERO VARCHAR(20) '$.IDTERCERO', IDADMINISTRADORA VARCHAR(20) '$.IDADMINISTRADORA', IDPLAN VARCHAR(6) '$.IDPLAN', IDTARIFA VARCHAR(5) 
					'$.IDTARIFA', FACTOR DECIMAL(7, 3) '$.FACTOR', PROCESO VARCHAR(20) '$.PROCESO', IDADMINISTRADORAEDITE VARCHAR(20) '$.IDADMINISTRADORAEDITE', 
					IDPLANEDITE VARCHAR(6) '$.IDPLANEDITE', IDTERCEROEDITE VARCHAR(20) '$.IDTERCEROEDITE'
					);

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				IF EXISTS (
						SELECT 1
						FROM PXSN
						WHERE IDTERCERO = @IDTERCERO AND IDADMINISTRADORA = @IDADMINISTRADORA AND IDPLAN = @IDPLAN
						)
				BEGIN
					INSERT INTO @TBLERRORES (ERROR)
					VALUES ('EL REGISTRO SE ENCUENTRA DUPLICADO');
				END
				ELSE
				BEGIN
					INSERT INTO [PXSN] ([IDTERCERO], [IDADMINISTRADORA], [IDPLAN], [IDTARIFA], [FACTOR], [IDCONTRATO], [NIVELATENCION], [TIPOCONTRATO], [TIPORECOBRO]
						)
					SELECT @IDTERCERO, @IDADMINISTRADORA, @IDPLAN, @IDTARIFA, @FACTOR, '', '', 'E', 'N';-- Valores por defecto seg�n l�gica original
				END
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				--  Validar duplicado SOLO si cambian las claves primarias
				IF (@IDADMINISTRADORAEDITE <> @IDADMINISTRADORA OR @IDPLANEDITE <> @IDPLAN OR @IDTERCEROEDITE <> @IDTERCERO)
				BEGIN
					IF EXISTS (
							SELECT 1
							FROM PXSN
							WHERE IDTERCERO = @IDTERCERO AND IDADMINISTRADORA = @IDADMINISTRADORA AND IDPLAN = @IDPLAN
							)
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						VALUES ('EL REGISTRO SE ENCUENTRA DUPLICADO');
					END
				END

				--  Si no hay errores detectados arriba, proceder con UPDATE
				IF NOT EXISTS (
						SELECT 1
						FROM @TBLERRORES
						)
				BEGIN
					UPDATE PXSN
					SET IDTERCERO = @IDTERCERO, IDADMINISTRADORA = @IDADMINISTRADORA, IDPLAN = @IDPLAN, IDTARIFA = @IDTARIFA, FACTOR = @FACTOR
					WHERE IDTERCERO = @IDTERCEROEDITE AND IDADMINISTRADORA = @IDADMINISTRADORAEDITE AND IDPLAN = @IDPLANEDITE;

					--  Validar si realmente se actualiz� algo
					IF @@ROWCOUNT = 0
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						VALUES ('NO SE ENCONTR� EL REGISTRO A EDITAR');
					END
				END
			END
		END

		IF @METODO = 'ELIMINAR'
		BEGIN
			SELECT @IDTERCERO = IDTERCERO, @IDADMINISTRADORA = IDADMINISTRADORA, @IDPLAN = IDPLAN
			FROM OPENJSON(@PARAMETROS) WITH (IDTERCERO VARCHAR(20) '$.IDTERCERO', IDADMINISTRADORA VARCHAR(20) '$.IDADMINISTRADORA', IDPLAN VARCHAR(6) '$.IDPLAN'
					);

			DELETE
			FROM PXSN
			WHERE IDTERCERO = @IDTERCERO AND IDADMINISTRADORA = @IDADMINISTRADORA AND IDPLAN = @IDPLAN;
		END

		IF @METODO = 'COPIAR_CONTRATACION'
		BEGIN
			SELECT @IDPROVEEDOR = IDPROVEEDOR, @IDPROVEEDORCOPIA = IDPROVEEDORCOPIA
			FROM OPENJSON(@PARAMETROS) WITH (IDPROVEEDOR VARCHAR(20) '$.IDPROVEEDOR', IDPROVEEDORCOPIA VARCHAR(20) '$.IDPROVEEDORCOPIA');

			EXEC SPK_COPIAPROVEEDORXS @IDPROVEEDORCOPIA, @IDPROVEEDOR
		END

		COMMIT TRANSACTION;
	END TRY

	BEGIN CATCH
		IF @@TRANCOUNT > 0
			ROLLBACK TRANSACTION;

		INSERT INTO @TBLERRORES (ERROR)
		SELECT ERROR_MESSAGE();
	END CATCH

	IF EXISTS (
			SELECT 1
			FROM @TBLERRORES
			)
	BEGIN
		SELECT 'KO' AS OK;

		SELECT ERROR
		FROM @TBLERRORES;
	END
	ELSE
	BEGIN
		SELECT 'OK' AS OK;
	END
END
