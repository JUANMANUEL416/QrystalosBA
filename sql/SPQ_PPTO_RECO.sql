			RECO VARCHAR(20) '$.RECO',
			CCOSTO VARCHAR(10) '$.CCOSTO',
			FECHA DATETIME '$.FECHA',
			TIPO VARCHAR(10) '$.TIPO',
			VALOR DECIMAL(18,2) '$.VALOR',
			ESTADO VARCHAR(20) '$.ESTADO',
			ORIGENPAGO VARCHAR(20) '$.ORIGENPAGO',
			CODCAJA VARCHAR(20) '$.CODCAJA',
			CNSFACJ VARCHAR(20) '$.CNSFACJ',
			BANCO VARCHAR(50) '$.BANCO',
			SUCURSAL VARCHAR(50) '$.SUCURSAL',
