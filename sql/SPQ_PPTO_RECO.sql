			REGISTRO NVARCHAR(MAX) AS JSON
		)

		SELECT
			@PROCESO_PTRECAD = PROCESO,
			@COMPANIA_PTRECAD = COMPANIA,
			@CONSECUTIVO_PTRECAD = CONSECUTIVO,
			@CNSPAGO_PTRECAD = CNSPAGO,
			@RECO_PTRECAD = RECO,
			@CLASE_PTRECAD = CLASE,
			@RUBRO_PTRECAD = RUBRO,
			@RUBRO_ID_PTRECAD = RUBRO_ID,
			@VALOR_PTRECAD = VALOR,
			@OBSERVACION_PTRECAD = OBSERVACION
		FROM OPENJSON(@REGISTRO_PTRECAD) WITH (
			PROCESO VARCHAR(20) '$.PROCESO',
			COMPANIA VARCHAR(2) '$.COMPANIA',
			CONSECUTIVO VARCHAR(20) '$.CONSECUTIVO',
