				INSERT INTO PTRECA (
					COMPANIA, CNSPAGO, CONSECUTIVO, RECO, CCOSTO, FECHA, TIPO,
					VALOR, ESTADO, ORIGENPAGO, CODCAJA, CNSFACJ, BANCO, SUCURSAL,
					CTA_BCO, ITEM_BMOV, OBSERVACION
				)
				VALUES (
					@COMPANIA_PTRECA, @CNSPAGO_PTRECA, @CONSECUTIVO_PTRECA, @RECO_PTRECA, @CCOSTO_PTRECA, @FECHA_PTRECA, @TIPO_PTRECA,
					ISNULL(@VALOR_PTRECA, 0), ISNULL(@ESTADO_PTRECA, 'NoConfirmado'), @ORIGENPAGO_PTRECA,
					@CODCAJA_PTRECA, @CNSFACJ_PTRECA, @BANCO_PTRECA, @SUCURSAL_PTRECA,
					@CTA_BCO_PTRECA, @ITEM_BMOV_PTRECA, @OBSERVACION_PTRECA
				)

				SELECT 'OK' AS OK, @CNSPAGO_PTRECA AS CNSPAGO
			END TRY
			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
				SELECT 'KO' AS OK, ERROR FROM @TBLERRORES
			END CATCH
		END

		ELSE IF @PROCESO_PTRECA = 'EDITAR'
		BEGIN
			BEGIN TRY
				-- Verificar que existe el registro
				IF NOT EXISTS(SELECT 1 FROM PTRECA WHERE COMPANIA=@COMPANIA_PTRECA AND CNSPAGO=@CNSPAGO_PTRECA)
				BEGIN
					INSERT INTO @TBLERRORES VALUES('El registro de recaudo no existe')
					SELECT 'ERROR' AS OK, ERROR FROM @TBLERRORES
					RETURN
				END

				UPDATE PTRECA SET
					FECHA = @FECHA_PTRECA,
					TIPO = @TIPO_PTRECA,
					VALOR = ISNULL(@VALOR_PTRECA, VALOR),
					ORIGENPAGO = @ORIGENPAGO_PTRECA,
					CODCAJA = @CODCAJA_PTRECA,
					CNSFACJ = @CNSFACJ_PTRECA,
					BANCO = @BANCO_PTRECA,
					SUCURSAL = @SUCURSAL_PTRECA,
					CTA_BCO = @CTA_BCO_PTRECA,
					ITEM_BMOV = @ITEM_BMOV_PTRECA,
					OBSERVACION = @OBSERVACION_PTRECA
				WHERE COMPANIA = @COMPANIA_PTRECA AND CNSPAGO = @CNSPAGO_PTRECA

				SELECT 'OK' AS OK
			END TRY
			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
				SELECT 'KO' AS OK, ERROR FROM @TBLERRORES
			END CATCH
		END

		ELSE IF @PROCESO_PTRECA = 'ANULAR'
		BEGIN
			BEGIN TRY
				-- Verificar que existe el registro
				IF NOT EXISTS(SELECT 1 FROM PTRECA WHERE COMPANIA=@COMPANIA_PTRECA AND CNSPAGO=@CNSPAGO_PTRECA)
				BEGIN
					INSERT INTO @TBLERRORES VALUES('El registro de recaudo no existe')
					SELECT 'ERROR' AS OK, ERROR FROM @TBLERRORES
					RETURN
				END

				UPDATE PTRECA SET ESTADO = 'Anulado'
				WHERE COMPANIA = @COMPANIA_PTRECA AND CNSPAGO = @CNSPAGO_PTRECA

				SELECT 'OK' AS OK
			END TRY
			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
				SELECT 'KO' AS OK, ERROR FROM @TBLERRORES
			END CATCH
		END

		ELSE IF @PROCESO_PTRECA = 'CONFIRMAR'
		BEGIN
      PRINT  'VOY A CONFIRMAR'
			BEGIN TRY
				-- Verificar que existe el registro
				IF NOT EXISTS(SELECT 1 FROM PTRECA WHERE COMPANIA=@COMPANIA_PTRECA AND CNSPAGO=@CNSPAGO_PTRECA)
				BEGIN
					INSERT INTO @TBLERRORES VALUES('El registro de recaudo no existe')
					SELECT 'ERROR' AS OK, ERROR FROM @TBLERRORES
					RETURN
				END
        PRINT '@COMPANIA_PTRECA='+@COMPANIA_PTRECA
        PRINT '@RECO_PTRECA'+@RECO_PTRECA
        PRINT '@CNSPAGO_PTRECA='+@CNSPAGO_PTRECA
				UPDATE PTRECA SET ESTADO = 'Confirmado'	WHERE COMPANIA = @COMPANIA_PTRECA AND RECO=@RECO_PTRECA AND CNSPAGO = @CNSPAGO_PTRECA

				SELECT 'OK' AS OK
			END TRY
			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
