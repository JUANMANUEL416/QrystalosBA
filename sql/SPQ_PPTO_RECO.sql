	BEGIN
		DECLARE @REGISTRO_PTRECAD NVARCHAR(MAX)
		DECLARE @PROCESO_PTRECAD VARCHAR(20)
		DECLARE @COMPANIA_PTRECAD VARCHAR(2)
		DECLARE @CONSECUTIVO_PTRECAD VARCHAR(20)
		DECLARE @CNSPAGO_PTRECAD VARCHAR(20)
		DECLARE @RECO_PTRECAD VARCHAR(20)
		DECLARE @CLASE_PTRECAD VARCHAR(20)
		DECLARE @RUBRO_PTRECAD VARCHAR(50)
		DECLARE @RUBRO_ID_PTRECAD VARCHAR(20)
