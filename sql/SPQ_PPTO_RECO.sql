		DECLARE @CCOSTO_PTRECA VARCHAR(10)
		DECLARE @FECHA_PTRECA DATETIME
		DECLARE @TIPO_PTRECA VARCHAR(10)
		DECLARE @VALOR_PTRECA DECIMAL(18,2)
