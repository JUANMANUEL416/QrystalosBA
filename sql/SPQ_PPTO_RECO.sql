		BEGIN
			INSERT INTO @TBLERRORES VALUES('Proceso no v?lido para PTRECA: ' + ISNULL(@PROCESO_PTRECA, 'NULL'))
			SELECT 'ERROR' AS OK, ERROR FROM @TBLERRORES
			RETURN
		END
	END
