		DECLARE @CTA_BCO_PTRECA VARCHAR(20)
		DECLARE @ITEM_BMOV_PTRECA INT
		DECLARE @OBSERVACION_PTRECA VARCHAR(MAX)

		SELECT @REGISTRO_PTRECA = REGISTRO
		FROM OPENJSON(@PARAMETROS) WITH (
			REGISTRO NVARCHAR(MAX) AS JSON
