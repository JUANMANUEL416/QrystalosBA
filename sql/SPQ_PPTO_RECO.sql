		DECLARE @ESTADO VARCHAR(20)
		DECLARE @CLASE VARCHAR(20)
		DECLARE @IDSEDE_REG VARCHAR(5)

		SELECT @REGISTRO = REGISTRO
		FROM OPENJSON(@PARAMETROS) WITH (
			REGISTRO NVARCHAR(MAX) AS JSON
		)

