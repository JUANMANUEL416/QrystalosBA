				ESTADO = 'NoConfirmado'
			WHERE COMPANIA = @COMPANIA 
				AND CONSECUTIVO = @CONSECUTIVO 
				AND RECO = @RECO

			IF @@ROWCOUNT = 0
			BEGIN
				INSERT INTO @TBLERRORES VALUES('No se encontr? el reconocimiento a desconfirmar')
				SELECT 'ERROR' AS OK, ERROR FROM @TBLERRORES
				RETURN
			END

			SELECT 'OK' AS OK, @RECO AS RECO, NULL AS ERROR
		END
		ELSE
		BEGIN
			INSERT INTO @TBLERRORES VALUES('Proceso no v?lido: ' + ISNULL(@PROCESO, 'NULL'))
			SELECT 'ERROR' AS OK, ERROR FROM @TBLERRORES
			RETURN
		END
	END
