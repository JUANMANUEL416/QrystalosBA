					INSERT INTO @TBLERRORES VALUES('El reconocimiento especificado no existe')
					SELECT 'ERROR' AS OK, ERROR FROM @TBLERRORES
					RETURN
				END

				-- Generar CNSPAGO si no viene
				IF @CNSPAGO_PTRECA IS NULL OR @CNSPAGO_PTRECA = ''
				BEGIN
					SELECT @CNSPAGO_PTRECA = SPACE(8)
					EXEC SPK_GENCONSECUTIVO_PPTO @COMPANIA_PTRECA, @CONSECUTIVO_PTRECA, 'RECA', @CNSPAGO_PTRECA OUTPUT
