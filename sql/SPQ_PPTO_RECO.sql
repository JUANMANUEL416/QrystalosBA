			ITEM_BMOV INT '$.ITEM_BMOV',
			OBSERVACION VARCHAR(MAX) '$.OBSERVACION'
		)
    PRINT 'INGRESO A CRUDPTRECA'
		-- Validaciones b?sicas
		IF @COMPANIA_PTRECA IS NULL OR @CONSECUTIVO_PTRECA IS NULL OR @RECO_PTRECA IS NULL
		BEGIN
			INSERT INTO @TBLERRORES VALUES('COMPANIA, CONSECUTIVO y RECO son requeridos')
			SELECT 'ERROR' AS OK, ERROR FROM @TBLERRORES
			RETURN
		END

		-- Procesar seg?n el PROCESO
		IF @PROCESO_PTRECA = 'INSERTAR'
		BEGIN
			BEGIN TRY
				-- Verificar que existe el reconocimiento padre
				IF NOT EXISTS(SELECT 1 FROM PTRECO WHERE COMPANIA=@COMPANIA_PTRECA AND CONSECUTIVO=@CONSECUTIVO_PTRECA AND RECO=@RECO_PTRECA)
