CREATE OR ALTER PROCEDURE DBO.SPQ_FCTSERD_COL
@JSON  NVARCHAR(MAX)
WITH
ENCRYPTION
AS
DECLARE @PARAMETROS         NVARCHAR(MAX)  ,@MODELO           VARCHAR(100)    ,@METODO        VARCHAR(100)  ,@USUARIO        VARCHAR(12)
       ,@GRUPO              VARCHAR(8)     ,@SYS_COMPUTERNAME VARCHAR(254)    ,@SEDE          VARCHAR(5)	   ,@A              INT
       ,@IDENTITY           INT 
       ,@PROCESO            VARCHAR(20)    ,@FCTSERD    NVARCHAR(MAX)
              ,@IDSERVICIO     VARCHAR(20)
       ,@IDTIPOSER     VARCHAR(6)
       ,@DESCRIPCION     VARCHAR(256)
       ,@ENBRIGADA     BIT
       ,@CLASECOBRO     VARCHAR(20)
       ,@VALOR     DECIMAL(9,2)
BEGIN
   SET LANGUAGE Spanish
   SET DATEFORMAT dmy
   
   SELECT @A = ISJSON(@JSON)
   IF @A = 0
   BEGIN
     RAISERROR('Json: Formato Erroneo',16,1)
     RETURN
   END
   PRINT 'INGRESE A SPQ_FCTSERD_COL'
   SELECT *
   INTO #JSON
   FROM OPENJSON (@json)
   WITH (
     MODELO         VARCHAR(100)     '$.MODELO',
     METODO         VARCHAR(100)     '$.METODO',
     USUARIO        VARCHAR(12)      '$.USUARIO',
     PARAMETROS     NVARCHAR(MAX)     AS JSON
   )
   
   SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS , @USUARIO = USUARIO
   FROM #JSON
   --DEFINICION DE TABLA DE ERRORES
   DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200))
   -- TOMA DEL GRUPO, SYS_COMPUTERNAME, SEDE   DE ACUERDO AL USUARIO
   PRINT 'USUARIO:'+@USUARIO
   --SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO) FROM USUSU WHERE USUARIO = @USUARIO
   --SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
   --SELECT @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
   IF COALESCE(@SEDE,'') = '' SELECT @SEDE = '01'
   PRINT 'SEDE='+@SEDE
   IF @METODO = 'CRUDFCTSERD'
   BEGIN
      PRINT 'CRUDFCTSERD'
      SELECT @FCTSERD  = REGISTRO
      FROM OPENJSON (@PARAMETROS)
      WITH(
         REGISTRO   NVARCHAR(MAX)     AS JSON
      )
      
      SELECT @PROCESO     = JSON_VALUE(@FCTSERD ,'$.PROCESO')
      --Leo Campos enviados y los coloco en las variables respectivas
      SELECT @IDSERVICIO = JSON_VALUE(@FCTSERD , '$.IDSERVICIO' )
      SELECT @IDTIPOSER = JSON_VALUE(@FCTSERD , '$.IDTIPOSER' )
      SELECT @DESCRIPCION = JSON_VALUE(@FCTSERD , '$.DESCRIPCION' )
      SELECT @ENBRIGADA = JSON_VALUE(@FCTSERD , '$.ENBRIGADA' )
      SELECT @CLASECOBRO = JSON_VALUE(@FCTSERD , '$.CLASECOBRO' )
      SELECT @VALOR = JSON_VALUE(@FCTSERD , '$.VALOR' )
      IF UPPER(@PROCESO) = 'INSERTAR'
      BEGIN
         PRINT 'INSERTAR'
         BEGIN TRY
            INSERT INTO FCTSERD(IDSERVICIO,IDTIPOSER,DESCRIPCION,ENBRIGADA,CLASECOBRO,VALOR)
            SELECT @IDSERVICIO,@IDTIPOSER,@DESCRIPCION,@ENBRIGADA,@CLASECOBRO,@VALOR
            SELECT @IDENTITY = SCOPE_IDENTITY()
         END TRY
         BEGIN CATCH
            INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
         END CATCH
         IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
         BEGIN
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
         END
         SELECT 'OK' OK ,@IDENTITY CNS 
         RETURN
      END
      IF UPPER(@PROCESO) = 'EDITAR'
      BEGIN
         BEGIN TRY
            UPDATE FCTSERD SET
                    IDSERVICIO = @IDSERVICIO,IDTIPOSER = @IDTIPOSER,DESCRIPCION = @DESCRIPCION,ENBRIGADA = @ENBRIGADA,CLASECOBRO = @CLASECOBRO,VALOR = @VALOR
            WHERE IDSERVICIO = @IDSERVICIO
         END TRY
         BEGIN CATCH
            INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
         END CATCH
         IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
         BEGIN
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
         END
         SELECT 'OK' OK
         RETURN
      END
      RETURN
   END
END
