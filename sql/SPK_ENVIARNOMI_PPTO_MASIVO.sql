IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='SPK_ENVIARNOMI_PPTO_MASIVO' AND XTYPE='P')
BEGIN
   DROP PROCEDURE SPK_ENVIARNOMI_PPTO_MASIVO
END
GO
CREATE   PROCEDURE DBO.SPK_ENVIARNOMI_PPTO_MASIVO
@CNSPAGO VARCHAR(20),
@SEDE VARCHAR(5),
@USUARIO VARCHAR(20)
WITH ENCRYPTION
AS
DECLARE @PPPTO VARCHAR(20)
DECLARE @CDP VARCHAR(20)
DECLARE @CNSFCXP VARCHAR(20)
DECLARE @SOLICITANTE VARCHAR(20)
DECLARE @CCOSTOPPTO VARCHAR(20)
DECLARE @CNSRP      VARCHAR(20)
DECLARE @IDTERCERO_CUR VARCHAR(20)
DECLARE @PPTOACTUAL VARCHAR(20)
DECLARE @FECHAININO DATETIME
DECLARE @FECHAFINNO DATETIME
DECLARE @CNSPPTONO  VARCHAR(20)
DECLARE @CNSCDPNO   VARCHAR(20)
DECLARE @CONTROLCXP BIT
DECLARE @VALORCXP  DECIMAL(14,2)
DECLARE @SALDOCDP  DECIMAL(14,2)
BEGIN
   SELECT @FECHAININO=FECHAINI,@FECHAFINNO=FECHAFIN,@CNSPPTONO=CNSPPTO,@CNSCDPNO=CNSCDP  FROM NPER WHERE CNSPAGO=@CNSPAGO

   SELECT @PPTOACTUAL=CONSECUTIVO  FROM PTPTO WHERE FECHAINI<=@FECHAININO AND FECHAFIN+1>@FECHAFINNO

   UPDATE FCXP SET CNSPPTO=@PPTOACTUAL,CNSCDP=@CNSCDPNO WHERE NOREFERENCIA=@CNSPAGO AND CNSCDP<>@CNSCDPNO

   SELECT @SALDOCDP=SALDO
   FROM PTCDP WHERE CONSECUTIVO=@PPTOACTUAL
   AND CDP=@CNSCDPNO

   SELECT @VALORCXP=SUM(SALDO)
   FROM FCXP WHERE NOREFERENCIA=@CNSPAGO
   AND COALESCE(ENPRESUPUESTO,0)=0
   AND CNSCDP=@CNSCDPNO
   AND ESTADO<>'A'
   
   IF (COALESCE(@SALDOCDP,0)-COALESCE(@VALORCXP,0))<=0
   BEGIN
      PRINT 'No hay saldo suficiente para enviar las cxp a presupuesto, me regreso CDP='+@CNSCDPNO
      RETURN
   END

	DECLARE CXP_PPTO_CUR CURSOR FOR 
	SELECT CNSFCXP,CNSPPTO,CNSCDP,IDTERCERO 
   FROM FCXP WHERE 
   NOREFERENCIA=@CNSPAGO
   AND COALESCE(ENPRESUPUESTO,0)=0
   AND PROCEDENCIA='Nomina'
   AND ESTADO<>'A'
   AND VLR_NETO>0
   AND SALDO>0
	ORDER BY CNSFCXP     
	OPEN CXP_PPTO_CUR    
	FETCH NEXT FROM CXP_PPTO_CUR    
	INTO @CNSFCXP,@PPPTO,@CDP,@IDTERCERO_CUR
	WHILE @@FETCH_STATUS = 0    
	BEGIN 
      SELECT @CONTROLCXP=0
      EXEC SPK_CALCULOVALORESCXP @CNSFCXP
		PRINT 'BUSCO LOS CDP Y PTTPTO '+@CNSFCXP
      IF NOT EXISTS( SELECT  * FROM PTCDP WHERE CONSECUTIVO=@PPPTO AND CDP=@CDP)
      BEGIN
         PRINT 'No existe presupuesto o la vigencia no es la correcta @PPTOACTUAL='+COALESCE(@PPTOACTUAL,'NO TENGO')+' @CDP='+COALESCE(@CDP,'NO TENGO')
         break
      END
      IF COALESCE(@CDP,'')='' OR  COALESCE(@PPPTO,'')=''
      BEGIN
         SELECT @CDP=@CNSCDPNO,@PPPTO=@CNSPPTONO
         UPDATE FCXP SET CNSCDP=@CDP, CNSPPTO=@PPPTO WHERE CNSFCXP=@CNSFCXP
      END
      SELECT @CCOSTOPPTO=DBO.FNK_VALORVARIABLE('PRESUP_CCOSTO')
      IF COALESCE(DBO.FNK_VALORVARIABLE('TOMA_RUBROENVIO_NOMI'),'NCOND')='NCOND'
      BEGIN
         UPDATE FCXPD SET RUBRO=NCOND.RUBRO, RUBRO_ID=COALESCE(PTRUB.RUBRO_ID,NCOND.RUBRO_ID)
         FROM FCXPD INNER JOIN NCOND ON FCXPD.IDSERVICIO=NCOND.CODCONCEPTO
                    LEFT  JOIN PTRUB ON FCXPD.RUBRO=PTRUB.RUBRO AND PTRUB.CONSECUTIVO=@PPTOACTUAL
         WHERE FCXPD.CNSFCXP=@CNSFCXP
      END
      ELSE
      BEGIN
         UPDATE FCXPD SET RUBRO=NPLTCO.RUBRO, RUBRO_ID=COALESCE(PTRUB.RUBRO_ID,NPLTCO.RUBRO_ID)
         FROM FCXPD INNER JOIN NPER ON FCXPD.N_PRESUP=NPER.CNSPAGO
                    INNER JOIN NOMI ON NPER.CODNOMINA=NOMI.CODNOMINA
                    INNER JOIN NPLTCO ON FCXPD.IDSERVICIO=NPLTCO.CODCONCEPTO AND NOMI.IDPLANTILLA=NPLTCO.IDPLANTILLA
                    LEFT  JOIN PTRUB ON NPLTCO.RUBRO=PTRUB.RUBRO AND PTRUB.CONSECUTIVO=@PPTOACTUAL
         WHERE FCXPD.CNSFCXP=@CNSFCXP
      END

      IF EXISTS(SELECT * FROM FCXPD WHERE CNSFCXP=@CNSFCXP AND RUBRO IS NULL)
      BEGIN
         CONTINUE
	      FETCH NEXT FROM CXP_PPTO_CUR    
	      INTO  @CNSFCXP,@PPPTO,@CDP,@IDTERCERO_CUR            
      END
      IF NOT EXISTS (SELECT * FROM PTRP WHERE CONSECUTIVO=@PPPTO AND CDP=@CDP AND CNSFCXP=@CNSFCXP AND NODOCUMENTO=@CNSPAGO)
      BEGIN
		   SELECT @CNSRP = ISNULL(CONTADOR_RP,0) + 1 
		   FROM   PTPTO 
		   WHERE  COMPANIA = '01' AND CONSECUTIVO = @PPPTO
             
		   SELECT @CNSRP = @SEDE + REPLACE(SPACE(8 - LEN(@CNSRP))+LTRIM(RTRIM(@CNSRP)),SPACE(1),0) 

		   UPDATE PTPTO SET CONTADOR_RP = ISNULL(CONTADOR_RP,0) + 1 
		   WHERE  COMPANIA    = '01' 
		   AND    CONSECUTIVO = @PPPTO
         
		   SELECT @SOLICITANTE= AUTORIZADOR  FROM PTCDP  WHERE CONSECUTIVO=@PPPTO AND CDP=@CDP

         INSERT INTO PTRP(COMPANIA, CONSECUTIVO, CDP, RP, OBJETIVO, VALOR, SALDO, SOLICITANTE, CNSFCOM, CNSFCXP, IDTERCERO, NODOCUMENTO, FECHARP, FECHAPLAZO, ESTADO, CCOSTO, USUARIO, JEFEPTPTO)
         SELECT '01',@PPPTO,@CDP,@CNSRP,LEFT	(OBSERVACION,1000),FCXP.VLR_NETO,FCXP.VLR_NETO,@SOLICITANTE,CNSFCOM,CNSFCXP,FCXP.IDTERCERO,FCXP.NOREFERENCIA,F_FACTURAREF,F_FACTURAREF,'NoConfirmado',
                  @CCOSTOPPTO,@USUARIO,DBO.FNK_VALORVARIABLE('JEFE_PRESUPUESTO_USU')
         FROM FCXP 
         WHERE CNSFCXP=@CNSFCXP
      END
      ELSE
      BEGIN
         SELECT @CNSRP=RP FROM PTRP WHERE CONSECUTIVO=@PPPTO AND CDP=@CDP AND CNSFCXP=@CNSFCXP AND NODOCUMENTO=@CNSPAGO
         IF EXISTS(SELECT * FROM  PTRP WHERE CONSECUTIVO=@PPPTO AND CDP=@CDP AND CNSFCXP=@CNSFCXP AND RP=@CNSRP AND NODOCUMENTO=@CNSPAGO AND ESTADO<>'Confirmado' )
         BEGIN
            DELETE PTRPD WHERE CONSECUTIVO=@PPPTO AND CDP=@CDP  AND RP=@CNSRP
            SELECT @CONTROLCXP=0 
         END
         ELSE
         BEGIN
            UPDATE FCXP SET CNSRP=@CNSRP WHERE CNSFCXP=@CNSFCXP

	         PRINT 'VOY A ENVIAR LA CXP'
            EXEC SPK_ENTREGA_CXP_PTTO @CNSFCXP, @USUARIO
		      PRINT 'REGRESO PRESUPUESTO'

            SELECT @CONTROLCXP=1 
         END
      END
      IF @CONTROLCXP=0 
      BEGIN
         PRINT 'Inserto en PTRPD..'
         INSERT INTO PTRPD(COMPANIA, CONSECUTIVO, CDP, RP, CLASE, RUBRO, VALOR, VALOR_CXP, SALDO, OBJETIVO)
         SELECT '01',@PPPTO,@CDP,@CNSRP,'Gasto',RUBRO,SUM(VLR_NETO),0,SUM(VLR_NETO),''
         FROM FCXPD 
         WHERE CNSFCXP=@CNSFCXP
         AND COALESCE(RUBRO,'')<>''
         AND NOT EXISTS(SELECT * FROM PTRPD WHERE CONSECUTIVO=@PPPTO AND CDP=@CDP AND RP=@CNSRP AND PTRPD.RUBRO=FCXPD.RUBRO )
         GROUP BY RUBRO

         UPDATE PTRPD SET RUBRO_ID=PTRUB.RUBRO_ID
         FROM PTRPD INNER JOIN PTRUB ON PTRPD.CONSECUTIVO=PTRUB.CONSECUTIVO AND PTRPD.RUBRO=PTRUB.RUBRO AND PTRUB.CLASE=PTRPD.CLASE
         WHERE PTRPD.CONSECUTIVO=@PPPTO AND PTRPD.CDP=@CDP AND PTRPD.RP=@CNSRP

         UPDATE PTRPD SET ITEMCDPD=PTCDPD.ITEM
         FROM PTRPD INNER JOIN PTCDPD ON PTRPD.CONSECUTIVO=PTCDPD.CONSECUTIVO
         AND PTRPD.CDP=PTCDPD.CDP
         AND PTCDPD.RUBRO=PTRPD.RUBRO
         AND PTCDPD.RUBRO_ID=PTRPD.RUBRO_ID
         WHERE PTRPD.CONSECUTIVO=@PPPTO
         AND PTRPD.CDP=@CDP
         AND PTRPD.RP=@CNSRP

	      IF (SELECT ESTADO FROM  PTRP WHERE CONSECUTIVO=@PPPTO AND COMPANIA='01' AND CDP=@CDP AND IDTERCERO=@IDTERCERO_CUR AND RP=@CNSRP)='NoConfirmado'
	      BEGIN
            UPDATE PTRP SET ESTADO='Confirmado' WHERE COMPANIA='01' AND CONSECUTIVO=@PPPTO AND CDP=@CDP AND RP=@CNSRP AND CCOSTO=@CCOSTOPPTO        
	      END
         UPDATE FCXP SET CNSRP=@CNSRP WHERE CNSFCXP=@CNSFCXP

	      PRINT 'VOY A ENVIAR LA CXP'
         EXEC SPK_ENTREGA_CXP_PTTO @CNSFCXP, @USUARIO
		   PRINT 'REGRESO PRESUPUESTO'		
      END
	   FETCH NEXT FROM CXP_PPTO_CUR    
	   INTO  @CNSFCXP,@PPPTO,@CDP,@IDTERCERO_CUR
	END
	CLOSE CXP_PPTO_CUR
	DEALLOCATE CXP_PPTO_CUR

   IF NOT EXISTS(SELECT * FROM FCXP WHERE NOREFERENCIA=@CNSPAGO AND COALESCE(ENPRESUPUESTO,0)=0)
   BEGIN
      UPDATE NPER SET ENPPTO=1 WHERE CNSPAGO=@CNSPAGO
   END

END
