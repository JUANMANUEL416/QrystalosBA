CREATE PROC DBO.SPK_NC_CONTAB_CASTIGO_CARTERA
@PROCESO VARCHAR(10),
@USUARIO VARCHAR(20),
@SYS_COMPUTERNAME VARCHAR(255),
@COMPANIA VARCHAR(2),
@IDSEDE   VARCHAR(6),
@FECHACA  DATETIME,
@NROCOMPROBANTE VARCHAR(20)
WITH ENCRYPTION
AS 
DECLARE @COM              VARCHAR(6)
DECLARE @NOREFERENCIA     VARCHAR(20)
DECLARE @ANO              VARCHAR(4)
DECLARE @MES              INT
DECLARE @IDMODELOCONT	  VARCHAR(2)
DECLARE @IDPLAN		     VARCHAR(6) 
DECLARE @TIPOTERCONTABLE  VARCHAR(10) 
DECLARE @VALORGLOSAS	     DECIMAL(14,2)
DECLARE @VALORIMPUESTOS	  DECIMAL(14,2)
DECLARE @PREFIJO_USCXS    VARCHAR(10)
DECLARE @INGRESO          VARCHAR(10)
DECLARE @VLRAJUSTEPESO    DECIMAL(14,2)
DECLARE @VLRDTOFINAN      DECIMAL(14,2)
DECLARE @FECHATRA         DATETIME
DECLARE @CUE_OFIN		  VARCHAR(16)
BEGIN

   SELECT   @ANO = YEAR(@FECHACA), @MES = MONTH(@FECHACA)

   
   IF NOT EXISTS(SELECT COMPANIA,ANO,MES FROM PRI WHERE COMPANIA=@COMPANIA AND ANO=@ANO AND MES=@MES)
   BEGIN
      Print 'Per�odo Contable No Existe'
      RAISERROR('Per�odo Contable No Existe',16,1)
      RETURN
   END  
   IF (SELECT CERRADO FROM PRI WHERE COMPANIA=@COMPANIA AND ANO=@ANO AND MES=@MES) = 1
   BEGIN
      Print 'Per�odo Contable Cerrado'
      RAISERROR('Per�odo Contable Cerrado',16,1)
      RETURN
   END
   
   SET @IDMODELOCONT = DBO.FNK_VALORVARIABLE('IDMODELOCONTABLE')
   PRINT '@NROCOMPROBANTE:' + ISNULL(@NROCOMPROBANTE,'') -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD
   IF ISNULL(@NROCOMPROBANTE,'') = '' -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD
   BEGIN
      SET @NROCOMPROBANTE = SPACE(20) -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD
      EXEC SPK_GENCONSECUTIVO @COMPANIA,@IDSEDE,'@MCP',@NROCOMPROBANTE OUTPUT -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD     
      SELECT @NROCOMPROBANTE = @IDSEDE + REPLACE(SPACE(8 - CASE WHEN LEN(@NROCOMPROBANTE) > 8 THEN 8 ELSE LEN(@NROCOMPROBANTE) END)+LTRIM(RTRIM(@NROCOMPROBANTE)),SPACE(1),0) 
      PRINT '@NROCOMPROBANTE:' + ISNULL(@NROCOMPROBANTE,'') -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD 
      IF (SELECT DBO.FNK_VALORVARIABLE('COMPROBMULTISEDE')) = 'SI'
      BEGIN
         IF @PROCESO='DIFICIL'
         BEGIN
            SELECT @COM = RTRIM(LTRIM(COMMS.COMPROBANTE)) FROM COMMS WHERE IDSEDE = @IDSEDE AND COMMS.CLASE = 'CXC' AND TIPO = 'DIFICIL'
         END
         ELSE
         BEGIN
            SELECT @COM = RTRIM(LTRIM(COMMS.COMPROBANTE)) FROM COMMS WHERE IDSEDE = @IDSEDE AND COMMS.CLASE = 'CXC' AND TIPO = 'CASTIGO'
         END
      END
      ELSE
      BEGIN
         IF @PROCESO='DIFICIL'
         BEGIN
            SET @COM=LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('IDCON_TCOM_CXC_DIFIC')))
         END
         ELSE 
         BEGIN
            IF @INGRESO='CASTIGO' 
            BEGIN 
               SET @COM=LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('IDCON_TCOM_CASTICART')))
            END 
            ELSE 
            BEGIN 
               SET @COM=LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('IDCON_TCOM_CXC')))
            END 
         END
      END
           
      SET @PREFIJO_USCXS='@COM'+@COM
      SET @NOREFERENCIA=SPACE(20)
      EXEC SPK_GENCONSECUTIVO @COMPANIA,@IDSEDE,@PREFIJO_USCXS,@NOREFERENCIA OUTPUT   
      SELECT @NOREFERENCIA = REPLACE(SPACE(8 - LEN(@NOREFERENCIA))+LTRIM(RTRIM(@NOREFERENCIA)),SPACE(1),0)
      PRINT 'Nuevo Comprobante: '+@COM+' '+@NOREFERENCIA
         
      PRINT 'Comprobanrte Contable (MCP)'

      INSERT INTO MCPE(NROCOMPROBANTE, COMPANIA, PROCEDENCIA, NOREFERENCIA, ANO, MES, FECHACONTABLE, TOTALDEBITO,
                       TOTALCREDITO, REFERENCIA1, REFERENCIA2, USUARIO, FECHA, LOTE, OBSERVACION, IDSEDE, ESTADO,
                       COMPROBANTE, IDTERCERO)
      SELECT @NROCOMPROBANTE, @COMPANIA, 'CXC', @NOREFERENCIA, @ANO, @MES, CAST(STR(DAY(@FECHACA))+'/'+LTRIM(STR(@MES))+'/'+@ANO AS DATETIME),
              0, 0, 'FCXCDV', '', @USUARIO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), NULL, 
             CASE WHEN @PROCESO='DIFICIL' THEN ' RECLASIFICACION  DE CUENTAS POR COBRAR DIFICIL COBRO'
                  ELSE 'CASTIGO DE CARTERA CUENTAS DE DIFICIL COBRO' END,
             @IDSEDE, 0, @COM,DBO.FNK_VALORVARIABLE('IDTERCEROINSTALADO')
             
   END  
   IF (SELECT COUNT(*) FROM MCP WHERE NROCOMPROBANTE=@NROCOMPROBANTE)>0
   BEGIN
      INSERT INTO MCPE (COMPANIA, NROCOMPROBANTE, PROCEDENCIA, NOREFERENCIA, ANO, MES, FECHACONTABLE, TOTALDEBITO ,TOTALCREDITO, REFERENCIA1, REFERENCIA2,
                       REFERENCIA3, USUARIO, FECHA, LOTE ,OBSERVACION ,IDSEDE ,ESTADO ,ANULADO ,COMPROBANTE ,IDTERCERO, BANCO ,NOCHEQUE, VALOR_CHEQUE,
                       RPT_COMPROBANTE, FECHARADICACION, MARCA, SYS_COMPUTERNAME_MARCA, ESTADOIMP, CBTEINTERNO)
      SELECT COMPANIA, NROCOMPROBANTE, PROCEDENCIA, NOREFERENCIA, ANO, MES, FECHACONTABLE, TOTALDEBITO ,TOTALCREDITO, REFERENCIA1, REFERENCIA2,
                       REFERENCIA3, USUARIO, FECHA, LOTE ,OBSERVACION ,IDSEDE ,ESTADO ,ANULADO ,COMPROBANTE ,IDTERCERO, BANCO ,NOCHEQUE, VALOR_CHEQUE,
                       RPT_COMPROBANTE, FECHARADICACION, MARCA, SYS_COMPUTERNAME_MARCA, ESTADOIMP, CBTEINTERNO
      FROM   MCP
      WHERE  NROCOMPROBANTE = @NROCOMPROBANTE
      --se borran de mcp, mch
      DELETE MCH WHERE NROCOMPROBANTE = @NROCOMPROBANTE
      DELETE MCP WHERE NROCOMPROBANTE = @NROCOMPROBANTE   
   END
   DELETE MCHE WHERE NROCOMPROBANTE=@NROCOMPROBANTE

   PRINT 'Contabilizando CR a la CxC del Cliente...' 
   
   -- MOD.JQUIROGA 20090523 - REQ.1641
   INSERT INTO MCHE(NROCOMPROBANTE, COMPANIA, TIPO, CUENTA, IDTERCERO, CCOSTO, DETALLE, VALOR ,REFERENCIA1,
                 	 REFERENCIA2 ,ITEMREF, USUARIO, FECHA, IDAREA, PREFIJO,ESTADO, PROCESO, GENERA, 
                   CLASECONT, N_FACTURA, F_FACTURAREF, F_VENCE, PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
   SELECT @NROCOMPROBANTE, @COMPANIA, 'CR',   
                  CASE   WHEN FCXCDV.TIPO='F' THEN TTEC.CUENTARAD 
                         WHEN FCXCDV.TIPO='G' THEN TTEC.CUENTALG
                         WHEN FCXCDV.TIPO='R' THEN TTEC.CUENTALG 
                         WHEN FCXCDV.TIPO='C' THEN TTEC.CUENTACG                                                                                                                             
         END,
         FTR.IDTERCERO, '' AS CCOSTO, @PROCESO+' De cuentas por Cobrar' DETALLE,FCXCDV.SALDONETO,
        @PROCESO,FCXCDV.CNSCXC,FCXCDV.ITEM, @USUARIO,DBO.FNK_FECHA_SIN_MLS(GETDATE()), 
        '' AS IDAREA, '' AS PREFIJO, 1, 'CXC_CLIENTE', 'Movimiento','S',
       FCXCDV.N_FACTURA, DBO.FNK_FECHA_SIN_HORA(FCXCDV.F_RECIBIDO), DBO.FNK_FECHA_SIN_HORA(FCXCDV.F_VENCE), 'CXC', @PROCESO, 
        FTR.CODUNG, FTR.CODPRG
   FROM FCXCDV INNER JOIN FTR ON FCXCDV.N_FACTURA=FTR.N_FACTURA
               LEFT JOIN  TTEC ON FTR.TIPOTTEC=TTEC.TIPO
   WHERE FCXCDV.MARCA=1
   AND FCXCDV.EQUIMARCA=@SYS_COMPUTERNAME
   INSERT INTO MCHE(NROCOMPROBANTE, COMPANIA, TIPO, CUENTA, IDTERCERO, CCOSTO, DETALLE, VALOR ,REFERENCIA1,
                 	 REFERENCIA2 ,ITEMREF, USUARIO, FECHA, IDAREA, PREFIJO,ESTADO, PROCESO, GENERA, 
                   CLASECONT, N_FACTURA, F_FACTURAREF, F_VENCE, PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
   SELECT @NROCOMPROBANTE, @COMPANIA, 'DB',CASE WHEN @PROCESO='DIFICIL' THEN TTEC.CUEDIFCOB ELSE (SELECT CUENTA FROM KCDE WHERE TIPO='CXC_CASTIGO_CARTERA') END,
         FTR.IDTERCERO, '' AS CCOSTO, @PROCESO+' De cuentas por Cobrar' DETALLE,FCXCDV.SALDONETO,
        @PROCESO,FCXCDV.CNSCXC,FCXCDV.ITEM, @USUARIO,DBO.FNK_FECHA_SIN_MLS(GETDATE()), 
        '' AS IDAREA, '' AS PREFIJO, 1, 'CXC_CLIENTE', 'Movimiento','S',
       FCXCDV.N_FACTURA, DBO.FNK_FECHA_SIN_HORA(FCXCDV.F_RECIBIDO), DBO.FNK_FECHA_SIN_HORA(FCXCDV.F_VENCE), 'CXC', @PROCESO, 
        FTR.CODUNG, FTR.CODPRG
   FROM FCXCDV INNER JOIN FTR ON FCXCDV.N_FACTURA=FTR.N_FACTURA
               LEFT JOIN  TTEC ON FTR.TIPOTTEC=TTEC.TIPO
   WHERE FCXCDV.MARCA=1
   AND FCXCDV.EQUIMARCA=@SYS_COMPUTERNAME

   
   UPDATE FCXCDV  SET NROCOMPROBANTE=@NROCOMPROBANTE,CASTIGADA=1,TCOBRO=CASE WHEN @PROCESO='DIFICIL' THEN 'Dificil' ELSE 'Castigo' END
   WHERE FCXCDV.MARCA=1
   AND FCXCDV.EQUIMARCA=@SYS_COMPUTERNAME

   PRINT 'Libero FCXCV'
   UPDATE FCXCDV  SET MARCA=0,EQUIMARCA=NULL
   WHERE FCXCDV.MARCA=1
   AND FCXCDV.EQUIMARCA=@SYS_COMPUTERNAME
 
   
   --EXEC SPK_REVISAR_COMPROBANTE @COMPANIA,@NROCOMPROBANTE
   EXEC SPK_NC_REVISAMCPE @NROCOMPROBANTE, @COMPANIA, @USUARIO, @IDSEDE, @SYS_COMPUTERNAME 
   EXEC SPK_PASA_MCP_MCPNIIF @NROCOMPROBANTE, @COMPANIA, @USUARIO, @SYS_COMPUTERNAME, @IDSEDE,@COM,''
   -- EXEC SPK_SUMA_DBCR @NROCOMPROBANTE
   
END
