IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='SPK_DESCONFIRMAR_PAGOSMASIVO' AND XTYPE='P')
BEGIN
   DROP PROCEDURE SPK_DESCONFIRMAR_PAGOSMASIVO
END

GO
CREATE PROCEDURE DBO.SPK_DESCONFIRMAR_PAGOSMASIVO
@CNSFCXPPM             VARCHAR(20),
@COMPANIA              VARCHAR(2),
@SEDE                  VARCHAR(5),
@SYS_COMPUTERNAME      VARCHAR(255),
@USUARIO               VARCHAR(12)
WITH ENCRYPTION
AS
DECLARE @CNS              VARCHAR(20) 
DECLARE @CNSFCXP          VARCHAR(20) 
DECLARE @CNSFCXPP         VARCHAR(20) 
DECLARE @N_FACTURA        VARCHAR(20)
DECLARE @F_FACTURA        DATETIME
DECLARE @F_VENCE          DATETIME    
DECLARE @IDTERCERO        VARCHAR(20)
DECLARE @SALDO            DECIMAL(14,2)
DECLARE @OBSERVACION      VARCHAR(255) 

DECLARE @CNSFACJ               VARCHAR(20)
DECLARE @CODCAJA          VARCHAR(4)  
DECLARE @VALORTOTAL       DECIMAL(14,2)
DECLARE @NOMBRECLIENTE    VARCHAR(40)
DECLARE @CNSACJ           VARCHAR(20)  
DECLARE @IDTERCERO_ANT    VARCHAR(20)
DECLARE @ITEM             SMALLINT
DECLARE @FECHAPAGO        DATETIME
DECLARE @IDTERCERO_AFAVOR VARCHAR(20)
DECLARE @SW               INT
DECLARE @PORPAGAR         DECIMAL(14,2)
DECLARE @CODUNG           VARCHAR(5)
DECLARE @CODPRG           VARCHAR(20)
DECLARE @TIPOEGRESO       VARCHAR(8)
DECLARE @CODCAJA1         VARCHAR(4)
DECLARE @IDSEDE           VARCHAR(5)
BEGIN
   SELECT @IDTERCERO_AFAVOR = IDTERCERO_AFAVOR,
   @PORPAGAR = VALOR-(CASE WHEN (SELECT SUM(VALOR) 
                              FROM FCXPCXC 
                              WHERE CNSFCXPPM=@CNSFCXPPM) >0 THEN (SELECT SUM(VALOR) 
                                                                  FROM FCXPCXC 
                                                                  WHERE CNSFCXPPM=@CNSFCXPPM) 
                        ELSE 0 
                  END)
   FROM FCXPPM WHERE CNSFCXPPM=@CNSFCXPPM

   PRINT 'IDTERCERO_AFAVOR: '+@IDTERCERO_AFAVOR
   PRINT @PORPAGAR
   PRINT '@CNSFCXPPM: '+@CNSFCXPPM

   SELECT @CODCAJA1   = CAJA,@IDSEDE=IDSEDE FROM UBEQ WHERE SYS_COMPUTERNAME = @SYS_COMPUTERNAME
   SELECT @TIPOEGRESO = TIPOEGRESO FROM CAJ WHERE CODCAJA = @CODCAJA1
   SELECT @CODUNG=CODUNG , @CODPRG=CODPRG FROM SED WHERE IDSEDE = @IDSEDE


   IF @TIPOEGRESO = '' OR @TIPOEGRESO IS NULL
   BEGIN
      SELECT @TIPOEGRESO = DBO.FNK_VALORVARIABLE('IDCJTECXP')
   END
   IF ISNULL(@IDTERCERO_AFAVOR,'')='' 
   BEGIN
      PRINT 'ENTRA @TIPOEGRESO = '' '
      SET @SW = 0
      DECLARE CUR_PAGOS CURSOR FOR
      SELECT FCXP.NOREFERENCIA, FCXPP.CNSFCXPP, FCXPP.CNSFCXP, FCXPP.ABONO, FCXP.IDTERCERO, FCXPPM.VALOR, 
      FCXPPM.CODCAJA, TER.RAZONSOCIAL,FCXPPM.FECHA, 
      CASE WHEN FCXPP.OBSERVACION='' THEN LEFT(FCXPPM.OBSERVACION,100) ELSE LEFT(FCXPP.OBSERVACION,100) END, 
      FCXP.CODUNG, FCXP.CODPRG
      FROM   FCXP,FCXPPM,TER,FCXPP
      WHERE  FCXPPM.CNSFCXPPM = @CNSFCXPPM 
      AND    FCXPPM.CNSFCXPPM = FCXPP.CNSFCXPPM 
      AND    FCXPP.CNSFCXP    = FCXP.CNSFCXP 
      AND    TER.IDTERCERO    = FCXP.IDTERCERO 
      AND    FCXPP.ESTADO    <> 'A'
      ORDER BY FCXP.IDTERCERO, FCXP.NOREFERENCIA
   END
   ELSE
   BEGIN
      PRINT 'ENTRA @TIPOEGRESO'
      SET @SW = 1
      DECLARE CUR_PAGOS CURSOR FOR
      SELECT FCXP.NOREFERENCIA, FCXPP.CNSFCXPP, FCXPP.CNSFCXP, FCXPP.ABONO, FCXPPM.IDTERCERO_AFAVOR, FCXPPM.VALOR, 
      FCXPPM.CODCAJA, TER.RAZONSOCIAL,FCXPPM.FECHA, 
      CASE WHEN FCXPP.OBSERVACION='' THEN LEFT(FCXPPM.OBSERVACION,100) ELSE LEFT(FCXPP.OBSERVACION,100) END, 
      FCXP.CODUNG, FCXP.CODPRG
      FROM   FCXP,FCXPPM,TER,FCXPP
      WHERE  FCXPPM.CNSFCXPPM  = @CNSFCXPPM 
      AND    FCXPPM.CNSFCXPPM  = FCXPP.CNSFCXPPM 
      AND    FCXPP.CNSFCXP     = FCXP.CNSFCXP 
      AND    TER.IDTERCERO     = FCXPPM.IDTERCERO_AFAVOR 
      AND    FCXPP.ESTADO     <> 'A'
      ORDER BY FCXPPM.IDTERCERO_AFAVOR,FCXP.NOREFERENCIA
   END  
   OPEN CUR_PAGOS
   FETCH NEXT FROM CUR_PAGOS
   INTO @N_FACTURA,@CNSFCXPP,@CNSFCXP,@SALDO,@IDTERCERO,@VALORTOTAL,@CODCAJA,@NOMBRECLIENTE,@FECHAPAGO, @OBSERVACION, @CODUNG, @CODPRG

   SELECT @CNSACJ = CNSACJ FROM CAJ WHERE CODCAJA = @CODCAJA
   SET    @IDTERCERO_ANT = ''

   PRINT '@CNSACJ '+@CNSACJ

   WHILE @@FETCH_STATUS = 0
   BEGIN  
      IF (@PORPAGAR > 0 AND @SW = 0) OR (@SW = 1)
      BEGIN
         IF @SALDO>@PORPAGAR 
         BEGIN
            SET @SALDO=@PORPAGAR
         END
         PRINT 'SALDO'   
         PRINT @SALDO
         PRINT 'PAGO'
         PRINT @PORPAGAR
         PRINT '(@PORPAGAR > 0 AND @SW = 0) OR (@SW = 1)'
         IF @IDTERCERO_ANT<>@IDTERCERO
         BEGIN
            PRINT @IDTERCERO_ANT+' '+@IDTERCERO
	      
            SET @VALORTOTAL=(SELECT SUM(ABONO) FROM FCXPP
			   WHERE CNSFCXPPM=@CNSFCXPPM AND 
					   IDTERCERO=(CASE WHEN @SW=0 THEN @IDTERCERO ELSE IDTERCERO END) AND 
					   ESTADO<>'A')
            PRINT '@VALORTOTAL: '
            PRINT @VALORTOTAL
	      
            IF @VALORTOTAL>@PORPAGAR
            Begin
               SET @VALORTOTAL=@PORPAGAR
            End
	      
            PRINT @VALORTOTAL
	      
            SET @IDTERCERO_ANT=@IDTERCERO
            SET @ITEM=0
	      
            PRINT @CODCAJA+' '+@CNSFACJ
            SELECT @CODUNG=CODUNG , @CODPRG=CODPRG FROM SED WHERE IDSEDE = @IDSEDE

         END
         --	    	    
         PRINT 'Actualizando FCXPP...'
         PRINT 'CAJA: '
         PRINT @CODCAJA
         PRINT '@CNSFCXPP: '
         PRINT @CNSFCXPP
         UPDATE FCXPP SET ESTADO='N',USUARIOCONF='',FECHACONF='',
		         SYS_COMPUTERNAME=@SYS_COMPUTERNAME,CNSFACJ='',CODCAJA=''
         WHERE CNSFCXPP=@CNSFCXPP
	   
      END
      ELSE
      BEGIN
         UPDATE FCXPP SET ESTADO='N',USUARIOCONF='',FECHACONF='',
		       SYS_COMPUTERNAME=@SYS_COMPUTERNAME,CNSFACJ='',CODCAJA=''
         WHERE CNSFCXPP=@CNSFCXPP
		 
         /****** CAMADO *** 11/05/2009 -- REQ: 1592 ***/			 	 
         UPDATE FCXP SET SALDO=SALDO+@SALDO, VLR_ABONOS=VLR_ABONOS-@SALDO WHERE CNSFCXP=@CNSFCXP           
         /*********************************************/
      END
      EXEC SPK_CALCULOVALORESCXP @CNSFCXP
	   
      FETCH NEXT FROM CUR_PAGOS
      INTO @N_FACTURA,@CNSFCXPP,@CNSFCXP,@SALDO,@IDTERCERO,@VALORTOTAL,@CODCAJA,@NOMBRECLIENTE,@FECHAPAGO, @OBSERVACION, @CODUNG, @CODPRG
   END
   
   CLOSE CUR_PAGOS
   DEALLOCATE CUR_PAGOS

   PRINT '@CNSFCXPPM:' +@CNSFCXPPM

   UPDATE FCXPPM SET
   USUARIOCONF = '',
   FECHACONF   = '',
   ESTADO      = 'N'
   WHERE CNSFCXPPM=@CNSFCXPPM
END
