CREATE OR ALTER FUNCTION DBO.FNK_CEFM_FECHATRANSCRIPCION (@CNSIZSOL VARCHAR(20))
RETURNS DATETIME
AS
BEGIN
  DECLARE @FECHA DATETIME = NULL

  IF UPPER(LTRIM(RTRIM(COALESCE(DBO.FNK_VALORVARIABLE('CEFM_FECHA_TRANS'), 'NO')))) = 'SI'
     AND COALESCE(@CNSIZSOL, '') <> ''
  BEGIN
    SELECT @FECHA = C.FECHATRANSCRIPCION
    FROM DBO.AUTE A WITH (NOLOCK)
    INNER JOIN DBO.CEFM C WITH (NOLOCK) ON C.CNSCEFM = A.CNSCEFM
    WHERE A.CNSIZSOL = @CNSIZSOL
      AND C.FECHATRANSCRIPCION IS NOT NULL
  END

  RETURN @FECHA
END
