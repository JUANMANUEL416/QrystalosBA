                          NOPRESTACION	  varchar(16)   COLLATE database_default,       
                          NOITEM         int,	
                          AREAFUNCONT    varchar(20)   COLLATE database_default,   
                          N_FACTURA      varchar(16)   COLLATE database_default,
                          SUBCCOSTO      varchar(4)    COLLATE database_default,    
                          PCOSTO	        decimal(14,2),     
