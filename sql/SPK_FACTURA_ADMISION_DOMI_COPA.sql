      PRINT '1'
      SELECT @CUENTACXC = CUENTA,@CUENTACXC_RAD=CUENTARAD FROM TTEC
      WHERE TIPO = @TTEC
      PRINT '2'
      IF @DV IS NULL
      BEGIN
         SELECT @DV = 30
      END
      IF @DV = 0
      BEGIN
         SELECT @DV = 30  
      END
      PRINT '3'         
      SELECT @TV = 'Credito'
