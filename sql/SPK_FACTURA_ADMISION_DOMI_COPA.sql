                   CASE WHEN COALESCE(VIVATCOPA,0)>0 THEN COALESCE(VIVATCOPA,0) ELSE  HPRED.VALORCOPAGO END,
                   NULL,HPRE.CCOSTO,SER.PREFIJO, SER.DESCSERVICIO, HPRED.IDSERVICIO, HPRED.IDCIRUGIA,
                   HPRED.CANTIDAD,(HPRED.VALORCOPAGO/HPRED.CANTIDAD),
                   CASE WHEN COALESCE(VIVATCOPA,0)>0 THEN COALESCE(VIVATCOPA,0) ELSE  HPRED.VALORCOPAGO END,
                   0,
                   HPRED.VALORPCOMP, HPRED.IDPROVEEDOR, @NOADMISION, HPRED.NOPRESTACION,
                   HPRED.NOITEM, NULL, @NVOCONSEC, HPRE.SUBCCOSTO, HPRED.PCOSTO,
                   HPRE.FECHA, HPRED.IDPLAN,0,@SYS_COMPUTERNAME,@USUARIO,
                   CASE WHEN COALESCE(VIVATCOPA,0)>0 THEN 1 ELSE 0 END,
                   CASE WHEN COALESCE(VIVATCOPA,0)>0 THEN VIVATCOPA-HPRED.VALORCOPAGO ELSE 0 END
            FROM   HPRE, HPRED, SER 
            WHERE  HPRE.NOADMISION   = @NOADMISION
            AND    HPRE.NOPRESTACION = HPRED.NOPRESTACION 
            AND    HPRED.IDSERVICIO  = SER.IDSERVICIO  
            AND    COALESCE(HPRED.N_FACTURAH,'')=''
            AND    ISNULL(HPRE.ANULADO,0) = 0 
            AND    ISNULL(HPRED.ANULADO,0) = 0 
            --AND    HPRE.PREFIJO=@PREFIJOF
            AND    COALESCE(HPRED.VALORCOPAGO,0)>0
            AND    COALESCE(HPRED.NOCOBRABLE,0)<>1
            AND    COALESCE(HPRED.MARCA,0)=CASE WHEN @MARCA=1 THEN 1 ELSE COALESCE(HPRED.MARCA,0) END
            AND    COALESCE(HPRED.USUARIOMARCA,'')=CASE WHEN @MARCA=1 THEN @USUARIO ELSE COALESCE(HPRED.USUARIOMARCA,'') END
         END
      END
      ELSE
      BEGIN
         PRINT 'INSERTA POR AUX1 = 0 AND CNSMOV<>'''' ' 
