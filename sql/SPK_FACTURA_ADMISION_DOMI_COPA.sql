      BEGIN
         SELECT @EC = 0
      END
               
      SELECT @IDTERPART = DATO FROM USVGS WHERE IDVARIABLE = 'IDCJTERCEROEXTERNO'
               
      IF @IDTERCERO = @IDTERPART 
