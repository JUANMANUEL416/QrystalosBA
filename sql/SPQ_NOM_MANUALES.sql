CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_MANUALES @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20), @PROCESO VARCHAR(20)
DECLARE @NUMDOC VARCHAR(20), @AUTOITEM DECIMAL(14, 0), @CODCONCEPTO VARCHAR(20), @DETALLE VARCHAR(10), @VALOR DECIMAL(14, 2)
DECLARE @VALOR_EMPRESA DECIMAL(14, 2), @VALOR100P DECIMAL(15, 6), @CANTIDAD DECIMAL(14, 2), @IDTRANSPRESTAMO VARCHAR(6)
DECLARE @NUMDOCPRESTAMO VARCHAR(20), @NUMCUOTA SMALLINT, @CODPRF VARCHAR(20), @IDTERCERO VARCHAR(20)
DECLARE @LIQUIDADO VARCHAR(2), @CNSPAGO VARCHAR(20)
DECLARE @DATO NVARCHAR(MAX), @CODCONCEPTOEDITE VARCHAR(20), @NUMDOCEDITE VARCHAR(20), @CNSPAGOEDITE VARCHAR(20)

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @CNSPAGO = CNSPAGO, @NUMDOC = NUMDOC, @AUTOITEM = AUTOITEM, @CODCONCEPTO = CODCONCEPTO, @DETALLE = DETALLE, @VALOR = VALOR, @VALOR_EMPRESA = 
				VALOR_EMPRESA, @VALOR100P = VALOR100P, @CANTIDAD = CANTIDAD, @IDTRANSPRESTAMO = IDTRANSPRESTAMO, @NUMDOCPRESTAMO = NUMDOCPRESTAMO, @NUMCUOTA = 
				NUMCUOTA, @CODPRF = CODPRF, @IDTERCERO = IDTERCERO, @LIQUIDADO = LIQUIDADO, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					CNSPAGO VARCHAR(20) '$.CNSPAGO', NUMDOC VARCHAR(20) '$.NUMDOC', AUTOITEM DECIMAL(14, 0) '$.AUTOITEM', CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO', 
					DETALLE VARCHAR(10) '$.DETALLE', VALOR DECIMAL(14, 2) '$.VALOR', VALOR_EMPRESA DECIMAL(14, 2) '$.VALOR_EMPRESA', VALOR100P DECIMAL(15, 6) 
					'$.VALOR100P', CANTIDAD DECIMAL(14, 2) '$.CANTIDAD', IDTRANSPRESTAMO VARCHAR(6) '$.IDTRANSPRESTAMO', NUMDOCPRESTAMO VARCHAR(20) 
					'$.NUMDOCPRESTAMO', NUMCUOTA SMALLINT '$.NUMCUOTA', CODPRF VARCHAR(20) '$.CODPRF', IDTERCERO VARCHAR(20) '$.IDTERCERO', LIQUIDADO VARCHAR(2) 
					'$.LIQUIDADO', PROCESO VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'EL ITEM YA SE ENCUENTRA REGISTRADO'
					WHERE EXISTS (
							SELECT 1
							FROM NPERC
							WHERE CNSPAGO = @CNSPAGO AND NUMDOC = @NUMDOC AND CODCONCEPTO = @CODCONCEPTO
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO [NPERC] (
							[CNSPAGO], [NUMDOC], [CODCONCEPTO], [DETALLE], [VALOR], [VALOR_EMPRESA], [VALOR100P], [CANTIDAD], [IDTRANSPRESTAMO], 
							[NUMDOCPRESTAMO], [NUMCUOTA], [CODPRF], [IDTERCERO], [LIQUIDADO]
							)
						SELECT @CNSPAGO, @NUMDOC, @CODCONCEPTO, @DETALLE, @VALOR, @VALOR_EMPRESA, @VALOR100P, 0, @IDTRANSPRESTAMO, @NUMDOCPRESTAMO, 0, @CODPRF, 
							@IDTERCERO, 'No'
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					UPDATE NPERC
					SET NUMDOC = @NUMDOC, VALOR = @VALOR, VALOR100P = @VALOR100P, VALOR_EMPRESA = @VALOR_EMPRESA
					WHERE CNSPAGO = @CNSPAGO AND AUTOITEM = @AUTOITEM
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @AUTOITEM = AUTOITEM
		FROM OPENJSON(@PARAMETROS) WITH (AUTOITEM DECIMAL(14, 0) '$.AUTOITEM')

		BEGIN TRY
			DELETE
			FROM NPERC
			WHERE AUTOITEM = @AUTOITEM
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
