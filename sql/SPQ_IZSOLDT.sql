CREATE OR ALTER PROCEDURE DBO.SPQ_IZSOLDT @JSON  NVARCHAR(MAX)
WITH      ENCRYPTION
AS
DECLARE  @ERRORES AS TABLE(ERROR VARCHAR(MAX))
DECLARE  @PARAMETROS NVARCHAR(MAX), 
		 @METODO VARCHAR(100), 
		 @MODELOACT NVARCHAR(MAX), 
		 @USUARIO VARCHAR(12),
		 @CNSIZSOLDT VARCHAR(20),
		 @CNSIZSOL VARCHAR(20),
		 @CNSMOV VARCHAR(20),
		 @SYS_COMPUTERNAME VARCHAR(50),
		 @CONSECUTIVO VARCHAR(20),
		 @NOLOTE VARCHAR(50),
		 @IDBODEGA VARCHAR(10),
		 @EXISLOTE INT,
		 @CANT_APRO INT,
		 @IDSEDE VARCHAR(10),
		 @COMPANIA VARCHAR(2)
BEGIN
	SELECT *
	INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)  AS JSON
	)
	SELECT @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON

	-- Listado de INMHOV por izsol
	IF @METODO = 'IVNMOV'
	BEGIN
		SELECT @CNSIZSOL = CNSIZSOL FROM OPENJSON(@PARAMETROS) WITH(CNSIZSOL VARCHAR(20) '$.CNSIZSOL')
		SELECT 'OK' AS OK
		select IMOV.*,IBOD.DESCRIPCION as DESCRICIONBOG from IMOV
		INNER Join IBOD ON IBOD.IDBODEGA=IMOV.IDBODEGA
		where IMOV.NODOCUMENTO = @CNSIZSOL
		order by IMOV.ESTADO, IMOV.FECHAMOV DESC
	END
	-- Agregando entrega desde codigo de barras
	IF @METODO = 'AGGEXISTLOTE'
	BEGIN
		SELECT @NOLOTE = NOLOTE FROM OPENJSON(@PARAMETROS) WITH(NOLOTE VARCHAR(20) '$.NOLOTE')
		SELECT @IDBODEGA = IDBODEGA FROM OPENJSON(@PARAMETROS) WITH(IDBODEGA VARCHAR(20) '$.IDBODEGA')
		SELECT 'OK' AS OK
		SELECT TOP 1 
		IEXI.IDARTICULO,
		IEXI.FECHAVENCE,
		IEXI.NOLOTE,
		IEXI.NOLOTEPEDIDO,
		IEXI.EXISLOTE,
		IEXI.SELLOCALIDAD,
		IEXI.IDBODEGA,
		IART.DESCRIPCION
		FROM IEXI
		INNER JOIN IART on IART.IDARTICULO = IEXI.IDARTICULO
		WHERE IEXI.NOLOTE = @NOLOTE
		OR IEXI.NOLOTEPEDIDO = @NOLOTE
		and IEXI.IDBODEGA = @IDBODEGA
		order by IEXI.FECHAVENCE

	END
	-- Guarda entrega a izsoldt
	IF @METODO = 'GUARDARENTREGA'
	BEGIN
		SELECT @CNSIZSOL = CNSIZSOL FROM OPENJSON(@PARAMETROS) WITH(CNSIZSOL VARCHAR(20) '$.CNSIZSOL')
		SELECT @CNSMOV = CNSMOV FROM OPENJSON(@PARAMETROS) WITH(CNSMOV VARCHAR(20) '$.CNSMOV')
		SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
		SELECT @IDSEDE = IDSEDE, @COMPANIA=COMPANIA FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
		
		SELECT 'OK' AS OK
		EXEC SPQ_PROCESA_IZSOLDT
		@CNSIZSOL, 
		@CNSMOV, 
		@COMPANIA,
		@IDSEDE,
		@USUARIO
	END
	-- Confirmaci�n de entrega en IMOV y IMOVH 
	IF @METODO = 'CONFIRMARENTREGA'
	BEGIN
		SELECT @CNSMOV = CNSMOV FROM OPENJSON(@PARAMETROS) WITH(CNSMOV VARCHAR(20) '$.CNSMOV')
		SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
		SELECT @IDSEDE = IDSEDE, @COMPANIA=COMPANIA FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
		
		SELECT 'OK' AS OK
		EXEC SPQ_CONFIRMASAL_CM
		@CNSMOV, 
		@USUARIO,
		@IDSEDE,
		@SYS_COMPUTERNAME,
		'LOG_PROD'
	END
	--Generacion de CNSDEMOVIMIENTO 
	IF @METODO = 'GENERATEIVNMOV'
	BEGIN
		SELECT @CNSIZSOL = CNSIZSOL 
			,@IDBODEGA = IDBODEGA
		FROM OPENJSON(@PARAMETROS) 
		WITH(
			CNSIZSOL VARCHAR(20) '$.CNSIZSOL',
			IDBODEGA VARCHAR(20) '$.IDBODEGA'
		)

		SELECT @CNSMOV = CNSMOV FROM OPENJSON(@PARAMETROS) WITH(CNSMOV VARCHAR(20) '$.CNSMOV')
		SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
		SELECT @IDSEDE = IDSEDE, @COMPANIA=COMPANIA FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME

		EXEC SPQ_CM_GENIMOV_SOL 
			 @CNSIZSOL = @CNSIZSOL
			,@SEDE = @IDSEDE
			,@SYS_COMPUTERNAME
			= @SYS_COMPUTERNAME
			,@USUARIO = @USUARIO
			,@PROCESO = 'ENTREGALOG'
			,@IDBODEGA = @IDBODEGA

		SELECT 'OK' AS OK
		SELECT CNSMOV,ESTADO  FROM IMOV
		WHERE NODOCUMENTO = @CNSIZSOL
		AND ESTADO = 0
		ORDER BY ESTADO
	END
	-- Devoluci�n de Existencias 
	IF @METODO = 'DEVOLVEREXISTENCIA'
	BEGIN
		DELETE from IZSOLDT where CNSIZSOLDT=JSON_VALUE(@PARAMETROS, '$.CNSIZSOLDT')

		SELECT @CANT_APRO = SUM(CANT_APRO - JSON_VALUE(@PARAMETROS, '$.CANTIDADSOL')) FROM IZSOLD 
		WHERE CNSIZSOLD=JSON_VALUE(@PARAMETROS, '$.CNSIZSOLD')

		update IZSOLD set 
		ESTADO=1,
		CANT_APRO= @CANT_APRO
		where CNSIZSOLD=JSON_VALUE(@PARAMETROS, '$.CNSIZSOLD')

		SELECT @EXISLOTE = SUM(EXISLOTE + JSON_VALUE(@PARAMETROS, '$.CANTIDADSOL')) FROM IEXI 
		WHERE IDARTICULO=JSON_VALUE(@PARAMETROS, '$.IDARTICULOREAL') 
		and NOLOTE=JSON_VALUE(@PARAMETROS, '$.NOLOTE') 
		and IDBODEGA=JSON_VALUE(@PARAMETROS, '$.BODEGA')

		update IEXI set 
		EXISLOTE=@EXISLOTE
		where IDARTICULO=JSON_VALUE(@PARAMETROS, '$.IDARTICULOREAL') and NOLOTE=JSON_VALUE(@PARAMETROS, '$.NOLOTE') and IDBODEGA=JSON_VALUE(@PARAMETROS, '$.BODEGA')
		SELECT 'OK' AS OK

		DELETE IMOVH where CNSMOV=JSON_VALUE(@PARAMETROS, '$.CNSMOV') and IDARTICULO=JSON_VALUE(@PARAMETROS, '$.IDARTICULOREAL') and NOLOTE=JSON_VALUE(@PARAMETROS, '$.NOLOTE')
		DELETE ISAL where CNSMOV=JSON_VALUE(@PARAMETROS, '$.CNSMOV') and IDARTICULO=JSON_VALUE(@PARAMETROS, '$.IDARTICULOREAL') and NOLOTE=JSON_VALUE(@PARAMETROS, '$.NOLOTE')

	END
	-- Busqueda de variable Imprimir costo de ventas 
	IF @METODO = 'IMPRIMIRCOSTOSVENTAS'
	BEGIN
		SELECT 'OK' AS OK
		select DATO1 from TGEN where CAMPO='PRNPCOSTO_IMOV' and CODIGO='06'
	END
	-- Consulta MCIERRAIZSOL
	IF @METODO = 'MCIERRAIZSOL'
	BEGIN
		SELECT 'OK' AS OK
		SELECT CODIGO, DESCRIPCION FROM TGEN WHERE CAMPO='MCIERRAIZSOL' 
	END
	-- Cerrar Solicitud
	IF @METODO = 'CERRARSOLICITUD'
	BEGIN
		SELECT 'OK' AS OK
		update IZSOL set 
		USUARIOCIERRA=JSON_VALUE(@PARAMETROS, '$.USUARIOCIERRA'),
		F_CANCEL=GETDATE(),	
		SYS_COMPUTER=JSON_VALUE(@PARAMETROS, '$.SYS_COMPUTER'), 
		ESTADO='2', 
		DESCRIPCERRAR=JSON_VALUE(@PARAMETROS, '$.DESCRIPCERRAR'), 
		CODIGOCERRAR=JSON_VALUE(@PARAMETROS, '$.CODIGOCERRAR')
		where CNSIZSOL=JSON_VALUE(@PARAMETROS, '$.CNSIZSOL')
		
		update IMOVH set ESTADO='2' where CNSMOV=JSON_VALUE(@PARAMETROS, '$.CNSMOV')
	END
	--Consulta busqueda cerrar solicitud
	IF @METODO = 'CONSULTARPENDIZSOLDT'
	BEGIN
		SELECT @CNSMOV = CNSMOV FROM OPENJSON(@PARAMETROS) WITH(CNSMOV VARCHAR(20) '$.CNSMOV')

		SELECT 'OK' AS OK
		select 1 from IZSOLDT Where CNSMOV=@CNSMOV and ESTADO='0'
		select 1 from IMOVH where  CNSMOV=@CNSMOV and ESTADO='0'
	END

	-- Guarda producto agregado a izoldt
	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY

			SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
			SELECT @IDSEDE = IDSEDE, @COMPANIA=COMPANIA FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
			EXEC SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE, '@IZSOLDT', @CNSIZSOLDT OUTPUT
			SELECT @CNSIZSOLDT = @IDSEDE + RIGHT('00000000' + CONVERT(VARCHAR(8), @CNSIZSOLDT), 8)

			INSERT INTO IZSOLDT (CNSIZSOLDT ,CNSIZSOLD ,IDARTICULO ,CANTIDADSOL ,ESTADO ,NOLOTE ,IDARTICULOREAL ,CNSMOV ,COBRADOINS  ,BSCAPACIDAD )   
			SELECT @CNSIZSOLDT ,CNSIZSOLD ,IDARTICULO ,CANTIDADSOL ,'0' ,NOLOTE ,IDARTICULOREAL ,CNSMOV ,COBRADOINS  ,BSCAPACIDAD
			FROM OPENJSON(@PARAMETROS) WITH(
				CNSIZSOLD			VARCHAR(20)	'$.CNSIZSOLD',
				IDARTICULO			VARCHAR(20)	'$.IDARTICULO',
				CANTIDADSOL			decimal	(9)	'$.CANTIDADSOL',
				NOLOTE				VARCHAR(20)	'$.NOLOTE',
				IDARTICULOREAL		VARCHAR(20)	'$.IDARTICULOREAL',
				CNSMOV				VARCHAR(20)	'$.CNSMOV',
				COBRADOINS			SMALLINT	'$.COBRADOINS',
				BSCAPACIDAD			decimal	(9)	'$.BSCAPACIDAD'
			) AS #T
			update IZSOLD set 
			ESTADO=JSON_VALUE(@PARAMETROS, '$.ESTADO'),
			CANT_APRO=JSON_VALUE(@PARAMETROS, '$.CANT_APRO')
			where CNSIZSOLD=JSON_VALUE(@PARAMETROS, '$.CNSIZSOLD')

			update IEXI set 
			EXISLOTE=JSON_VALUE(@PARAMETROS, '$.EXISLOTE')
			where IDARTICULO=JSON_VALUE(@PARAMETROS, '$.IDARTICULOREAL') and NOLOTE=JSON_VALUE(@PARAMETROS, '$.NOLOTE') and IDBODEGA=JSON_VALUE(@PARAMETROS, '$.BODEGA')

		END TRY
		BEGIN CATCH
			INSERT INTO @ERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (SELECT COUNT(1) FROM @ERRORES)>0
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @ERRORES
			RETURN
		END

		SELECT 'OK' AS OK, @CNSIZSOLDT AS CNSIZSOLDT
		END
	END
