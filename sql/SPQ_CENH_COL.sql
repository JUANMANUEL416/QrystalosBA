CREATE OR ALTER PROCEDURE DBO.SPQ_CENH_COL @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
SET DATEFORMAT dmy
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE  @PARAMETROS NVARCHAR(MAX)			,@MODELO VARCHAR(100)			   ,@METODO VARCHAR(100)
		,@USUARIO VARCHAR(12)				   ,@COMPANIA VARCHAR(2)		      ,@IDSEDE      VARCHAR(5)		
      ,@SYS_COMPUTERNAME VARCHAR(200)     ,@DATOS    NVARCHAR(MAX)
	  ,@CENH NVARCHAR(MAX)
	  ,@PROCESO VARCHAR(20)
	  ,@IDSEDEORI VARCHAR(5)
	  ,@CCOSTOOR VARCHAR(20)
	  ,@IDSEDE_DEST VARCHAR(5)
	  ,@CCOSTO VARCHAR(20)
	  ,@ESTADO VARCHAR(10)
	  ,@HOMOANULA VARCHAR(20)

BEGIN
	SELECT *
	INTO #JSON
	FROM OPENJSON(@json) WITH (
			MODELO VARCHAR(100) '$.MODELO'
			,METODO VARCHAR(100) '$.METODO'
			,USUARIO VARCHAR(12) '$.USUARIO'
			,PARAMETROS NVARCHAR(MAX) AS JSON
	)

	SELECT   @MODELO = MODELO			,@METODO = METODO
			,@PARAMETROS = PARAMETROS	,@USUARIO = USUARIO
	FROM #JSON

	IF @METODO = 'CRUD_CENH'
	BEGIN
		SELECT @CENH = DATOS
		FROM OPENJSON(@PARAMETROS) WITH (
			DATOS NVARCHAR(MAX) AS JSON
		)

		SELECT @PROCESO = JSON_VALUE(@CENH, '$.PROCESO')
		SELECT @COMPANIA = JSON_VALUE(@CENH, '$.COMPANIA')
		SELECT @IDSEDEORI = JSON_VALUE(@CENH, '$.IDSEDEORI')
		SELECT @CCOSTOOR = JSON_VALUE(@CENH, '$.CCOSTOOR')
		SELECT @IDSEDE_DEST = JSON_VALUE(@CENH, '$.IDSEDE')
		SELECT @CCOSTO = JSON_VALUE(@CENH, '$.CCOSTO')
		SELECT @ESTADO = JSON_VALUE(@CENH, '$.ESTADO')
		SELECT @HOMOANULA = JSON_VALUE(@CENH, '$.HOMOANULA')

		-- Validaciones comunes
		IF @COMPANIA IS NULL OR LEN(@COMPANIA) = 0
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'La compa��a es requerida'
		END
		IF @IDSEDEORI IS NULL OR LEN(@IDSEDEORI) = 0
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'La sede origen es requerida'
		END
		IF @CCOSTOOR IS NULL OR LEN(@CCOSTOOR) = 0
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El centro de costo origen es requerido'
		END
		IF @IDSEDE_DEST IS NULL OR LEN(@IDSEDE_DEST) = 0
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'La sede destino es requerida'
		END
		IF @CCOSTO IS NULL OR LEN(@CCOSTO) = 0
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El centro de costo homologado es requerido'
		END

		-- Validar que el centro de costo origen existe
		IF NOT EXISTS(SELECT 1 FROM CEN WHERE COMPANIA = @COMPANIA AND CCOSTO = @CCOSTOOR AND IDSEDE = @IDSEDEORI)
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El centro de costo origen no existe'
		END

		-- Validar que el centro de costo destino existe
		IF NOT EXISTS(SELECT 1 FROM CEN WHERE COMPANIA = @COMPANIA AND CCOSTO = @CCOSTO AND IDSEDE = @IDSEDE_DEST)
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El centro de costo homologado no existe'
		END

		IF EXISTS(SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		IF UPPER(@PROCESO) = 'Nuevo' OR UPPER(@PROCESO) = 'INSERTAR'
		BEGIN
			-- Validar que no exista ya la homologaci�n
			IF EXISTS(SELECT 1 FROM CENH WHERE COMPANIA = @COMPANIA AND IDSEDEORI = @IDSEDEORI AND CCOSTOOR = @CCOSTOOR 
					  AND IDSEDE = @IDSEDE_DEST AND CCOSTO = @CCOSTO)
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR = 'Ya existe una homologaci�n para estos centros de costo'
				RETURN
			END
         PRINT 'Voy a insertar'
			BEGIN TRY
				INSERT INTO CENH(COMPANIA, IDSEDEORI, CCOSTOOR, IDSEDE, CCOSTO, ESTADO, HOMOANULA)
				VALUES(@COMPANIA, @IDSEDEORI, @CCOSTOOR, @IDSEDE_DEST, @CCOSTO, ISNULL(@ESTADO, 'Activo'), @HOMOANULA)
			END TRY
			BEGIN CATCH
				SELECT 'KO' OK
				SELECT ERROR = 'Error al insertar homologaci�n: ' + ERROR_MESSAGE()
				RETURN
			END CATCH
			SELECT 'OK' OK
			RETURN
		END

		IF UPPER(@PROCESO) = 'EDITAR' OR UPPER(@PROCESO) = 'ACTUALIZAR'
		BEGIN
			IF NOT EXISTS(SELECT 1 FROM CENH WHERE COMPANIA = @COMPANIA AND IDSEDEORI = @IDSEDEORI AND CCOSTOOR = @CCOSTOOR 
						  AND IDSEDE = @IDSEDE_DEST AND CCOSTO = @CCOSTO)
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR = 'La homologaci�n a editar no existe'
				RETURN
			END

			BEGIN TRY
				UPDATE CENH 
				SET ESTADO = ISNULL(@ESTADO, ESTADO),
					HOMOANULA = @HOMOANULA
				WHERE COMPANIA = @COMPANIA 
				  AND IDSEDEORI = @IDSEDEORI 
				  AND CCOSTOOR = @CCOSTOOR
				  AND IDSEDE = @IDSEDE_DEST
				  AND CCOSTO = @CCOSTO
			END TRY
			BEGIN CATCH
				SELECT 'KO' OK
				SELECT ERROR = 'Error al actualizar homologaci�n: ' + ERROR_MESSAGE()
				RETURN
			END CATCH
			SELECT 'OK' OK
			RETURN
		END

		IF UPPER(@PROCESO) = 'ELIMINAR' OR UPPER(@PROCESO) = 'BORRAR'
		BEGIN
			IF NOT EXISTS(SELECT 1 FROM CENH WHERE COMPANIA = @COMPANIA AND IDSEDEORI = @IDSEDEORI AND CCOSTOOR = @CCOSTOOR 
						  AND IDSEDE = @IDSEDE_DEST AND CCOSTO = @CCOSTO)
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR = 'La homologaci�n a eliminar no existe'
				RETURN
			END

			BEGIN TRY
				DELETE FROM CENH 
				WHERE COMPANIA = @COMPANIA 
				  AND IDSEDEORI = @IDSEDEORI 
				  AND CCOSTOOR = @CCOSTOOR
				  AND IDSEDE = @IDSEDE_DEST
				  AND CCOSTO = @CCOSTO
			END TRY
			BEGIN CATCH
				SELECT 'KO' OK
				SELECT ERROR = 'Error al eliminar homologaci�n: ' + ERROR_MESSAGE()
				RETURN
			END CATCH
			SELECT 'OK' OK
			RETURN
		END

		SELECT 'KO' OK
		SELECT ERROR = 'Proceso no reconocido: ' + ISNULL(@PROCESO, 'NULL')
		RETURN
	END

	-- M�todo para obtener centro de costo homologado
	IF @METODO = 'GET_CCOSTO_HOMOLOGO'
	BEGIN
		SELECT @COMPANIA = JSON_VALUE(@PARAMETROS, '$.COMPANIA')
		SELECT @IDSEDEORI = JSON_VALUE(@PARAMETROS, '$.IDSEDEORI')
		SELECT @CCOSTOOR = JSON_VALUE(@PARAMETROS, '$.CCOSTOOR')
		SELECT @IDSEDE_DEST = JSON_VALUE(@PARAMETROS, '$.IDSEDE')

		IF @COMPANIA IS NULL OR @IDSEDEORI IS NULL OR @CCOSTOOR IS NULL OR @IDSEDE_DEST IS NULL
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR = 'Par�metros incompletos para obtener homologaci�n'
			RETURN
		END

		SELECT 'OK' OK
		SELECT CCOSTO, ESTADO, HOMOANULA
		FROM CENH
		WHERE COMPANIA = @COMPANIA
		  AND IDSEDEORI = @IDSEDEORI
		  AND CCOSTOOR = @CCOSTOOR
		  AND IDSEDE = @IDSEDE_DEST
		  AND ESTADO = 'Activo'
		  AND (HOMOANULA IS NULL OR HOMOANULA = '')
		RETURN
	END

	SELECT 'KO' OK
	SELECT ERROR = 'M�todo no reconocido: ' + ISNULL(@METODO, 'NULL')
END
