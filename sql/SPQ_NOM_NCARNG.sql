CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NCARNG @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100)
DECLARE @USUARIO VARCHAR(20), @PROCESO VARCHAR(20)
DECLARE @CODCARGO VARCHAR(20), @NIVEL VARCHAR(10), @GRADO VARCHAR(10), @DESCRIPCION VARCHAR(255), @BASICO DECIMAL(14, 2)
DECLARE @PLANTILLAS NVARCHAR(MAX), @FECHA DATETIME
DECLARE @HORASDELABOR SMALLINT, @DIAS SMALLINT, @NVACACIONES SMALLINT, @NIVELEDITE VARCHAR(10), @GRADOEDITE VARCHAR(10), @CollationName NVARCHAR(150)
DECLARE @DATO NVARCHAR(MAX)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @CODCARGO = CODCARGO, @DESCRIPCION = DESCRIPCION, @NIVEL = NIVEL, @GRADO = GRADO, @BASICO = BASICO, @HORASDELABOR = HORASDELABOR, @DIAS = DIAS, 
				@NVACACIONES = NVACACIONES, @PROCESO = PROCESO, @PLANTILLAS = PLANTILLAS, @FECHA = FECHA
			FROM OPENJSON(@PARAMETROS) WITH (
					CODCARGO VARCHAR(20) '$.CODCARGO', DESCRIPCION VARCHAR(255) '$.DESCRIPCION', NIVEL VARCHAR(10) '$.NIVEL', GRADO VARCHAR(10) '$.GRADO', BASICO 
					DECIMAL(14, 2) '$.BASICO', HORASDELABOR SMALLINT '$.HORASDELABOR', DIAS SMALLINT '$.DIAS', NVACACIONES SMALLINT '$.NVACACIONES', FECHA DATETIME 
					'$.FECHA', PROCESO VARCHAR(20) '$.PROCESO', PLANTILLAS NVARCHAR(MAX) AS JSON
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('YA SE ENCUENTRA REGISTRADO EL CARGO, CON EL GRADO ', @GRADO, ' Y EL NIVEL ', @NIVEL)
					WHERE EXISTS (
							SELECT 1
							FROM NCARNG
							WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVEL AND GRADO = @GRADO
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						-- Creo una tabla temporal para dividir el JSON en filas (PLANTILLAS QUE SE RELACIONARAN CON EL CARGO)
						CREATE TABLE #ParsedTable (IDPLANTILLA NVARCHAR(20), CODCARGO VARCHAR(20), NIVEL VARCHAR(10), GRADO VARCHAR(10)
							);

						-- Convierto el JSON en filas usando OPENJSON
						INSERT INTO #ParsedTable (IDPLANTILLA, CODCARGO, NIVEL, GRADO)
						SELECT JSON_VALUE(value, '$.IDPLANTILLA'), @CODCARGO, @NIVEL, @GRADO
						FROM OPENJSON(@PLANTILLAS);

						IF ISJSON(@PLANTILLAS) = 1 -- verifico si el json de plantillas es valido
						BEGIN
							INSERT INTO NCARNG (CODCARGO, NIVEL, GRADO, DESCRIPCION, BASICO, HORASDELABOR, DIAS, NVACACIONES)
							SELECT @CODCARGO, @NIVEL, @GRADO, @DESCRIPCION, 0, 0, 0, @NVACACIONES

							/* Asigna el valor del salario para el cargo creado */
							INSERT INTO NCARNGV (CODCARGO, NIVEL, GRADO, BASICO, HORASDELABOR, DIAS, FECHA)
							SELECT @CODCARGO, @NIVEL, @GRADO, @BASICO, @HORASDELABOR, @DIAS, @FECHA

							-- Insertar los datos en la tabla NPLTCA (ASIGNANDO EL CARGO A LAS PLANTILLAS SELECCIONADAS)
							INSERT INTO NPLTCA (IDPLANTILLA, CODCARGO, NIVEL, GRADO)
							SELECT IDPLANTILLA, CODCARGO, NIVEL, GRADO
							FROM #ParsedTable;

							DROP TABLE #ParsedTable;
						END
						ELSE
						BEGIN
							INSERT INTO @TBLERRORES (ERROR)
							SELECT ('El parametro JSON de plantillas no es valido.')
						END
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @DATO = DATO
					FROM OPENJSON(@PARAMETROS) WITH (DATO NVARCHAR(MAX) AS JSON)

					SELECT @NIVELEDITE = NIVELEDITE, @GRADOEDITE = GRADOEDITE
					FROM OPENJSON(@DATO) WITH (NIVELEDITE VARCHAR(10) '$.NIVELEDITE', GRADOEDITE VARCHAR(10) '$.GRADOEDITE')

					SELECT @CollationName = CONVERT(NVARCHAR(128), DATABASEPROPERTYEX(DB_NAME(), 'Collation'));

					-- Creo una tabla temporal para dividir el JSON en filas (PLANTILLAS QUE SE RELACIONARAN CON EL CARGO)
					CREATE TABLE #ParsedTableE (IDPLANTILLA NVARCHAR(20) NULL, CODCARGO VARCHAR(20) NULL, NIVEL VARCHAR(10) NULL, GRADO VARCHAR(10) NULL
						);

					DECLARE @SQL NVARCHAR(MAX);

					SET @SQL = 'ALTER TABLE #ParsedTableE ALTER COLUMN IDPLANTILLA VARCHAR(20) COLLATE ' + @CollationName + 
						';ALTER TABLE #ParsedTableE ALTER COLUMN CODCARGO VARCHAR(20) COLLATE ' + @CollationName + 
						';ALTER TABLE #ParsedTableE ALTER COLUMN NIVEL VARCHAR(10) COLLATE ' + @CollationName + 
						';ALTER TABLE #ParsedTableE ALTER COLUMN GRADO VARCHAR(10) COLLATE ' + @CollationName + ';';

					EXEC sp_executesql @SQL;

					-- Convierto el JSON en filas usando OPENJSON
					INSERT INTO #ParsedTableE (IDPLANTILLA, CODCARGO, NIVEL, GRADO)
					SELECT JSON_VALUE(value, '$.IDPLANTILLA') COLLATE DATABASE_DEFAULT, @CODCARGO COLLATE DATABASE_DEFAULT, @NIVEL COLLATE DATABASE_DEFAULT, 
						@GRADO COLLATE DATABASE_DEFAULT
					FROM OPENJSON(@PLANTILLAS);

					IF ISJSON(@PLANTILLAS) = 1 -- verifico si el json de plantillas es valido
					BEGIN
						IF (@NIVELEDITE <> @NIVEL OR @GRADOEDITE <> @GRADO)
						BEGIN
							INSERT INTO @TBLERRORES (ERROR)
							SELECT CONCAT ('YA SE ENCUENTRA REGISTRADO EL CARGO, CON EL GRADO ', @GRADO, ' Y EL NIVEL ', @NIVEL
									)
							WHERE EXISTS (
									SELECT 1
									FROM NCARNG
									WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVEL AND GRADO = @GRADO
									)

							IF (
									SELECT COUNT(*)
									FROM @TBLERRORES
									) <= 0
							BEGIN
								UPDATE NCARNG
								SET NIVEL = @NIVEL, GRADO = @GRADO, NVACACIONES = @NVACACIONES, DESCRIPCION = @DESCRIPCION
								WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVELEDITE AND GRADO = @GRADOEDITE

								/* ACTUALIZA TODOS VALORES DE AJUSTE DE SUELDO, DEL CARGO SEGUN EL GRADO Y NIVEL*/
								UPDATE NCARNGV
								SET NIVEL = @NIVEL, GRADO = @GRADO
								WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVELEDITE AND GRADO = @GRADOEDITE

								-- agrega plantillas nueva a NPLTCA
								INSERT INTO NPLTCA (IDPLANTILLA, CODCARGO, NIVEL, GRADO)
								SELECT t.IDPLANTILLA COLLATE DATABASE_DEFAULT, t.CODCARGO COLLATE DATABASE_DEFAULT, t.NIVEL COLLATE DATABASE_DEFAULT, t.GRADO 
									COLLATE DATABASE_DEFAULT
								FROM #ParsedTableE t
								LEFT JOIN NPLTCA ON t.IDPLANTILLA COLLATE DATABASE_DEFAULT = NPLTCA.IDPLANTILLA AND t.CODCARGO COLLATE DATABASE_DEFAULT = NPLTCA.
									CODCARGO AND t.NIVEL COLLATE DATABASE_DEFAULT = NPLTCA.NIVEL AND t.GRADO COLLATE DATABASE_DEFAULT = NPLTCA.GRADO
								WHERE NPLTCA.CODCARGO IS NULL

								-- elimina plantillas de NPLTCA
								DELETE NPLTCA
								FROM NPLTCA
								LEFT JOIN #ParsedTableE t ON NPLTCA.IDPLANTILLA = t.IDPLANTILLA AND t.CODCARGO COLLATE DATABASE_DEFAULT = NPLTCA.CODCARGO AND t.
									NIVEL COLLATE DATABASE_DEFAULT = NPLTCA.NIVEL AND t.GRADO COLLATE DATABASE_DEFAULT = NPLTCA.GRADO
								WHERE t.CODCARGO IS NULL AND NPLTCA.CODCARGO = @CODCARGO AND NPLTCA.NIVEL = @NIVEL AND NPLTCA.grado = @GRADO
							END
						END
						ELSE
						BEGIN
							UPDATE NCARNG
							SET DESCRIPCION = @DESCRIPCION, NVACACIONES = @NVACACIONES
							WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVEL AND GRADO = @GRADO

							-- agrega plantillas nueva a NPLTCA
							INSERT INTO NPLTCA (IDPLANTILLA, CODCARGO, NIVEL, GRADO)
							SELECT t.IDPLANTILLA COLLATE DATABASE_DEFAULT, t.CODCARGO COLLATE DATABASE_DEFAULT, t.NIVEL COLLATE DATABASE_DEFAULT, t.GRADO COLLATE 
								DATABASE_DEFAULT
							FROM #ParsedTableE t
							LEFT JOIN NPLTCA ON t.IDPLANTILLA COLLATE DATABASE_DEFAULT = NPLTCA.IDPLANTILLA AND t.CODCARGO COLLATE DATABASE_DEFAULT = NPLTCA.
								CODCARGO AND t.NIVEL COLLATE DATABASE_DEFAULT = NPLTCA.NIVEL AND t.GRADO COLLATE DATABASE_DEFAULT = NPLTCA.GRADO
							WHERE NPLTCA.CODCARGO IS NULL

							-- elimina plantillas de NPLTCA
							DELETE NPLTCA
							FROM NPLTCA
							LEFT JOIN #ParsedTableE t ON NPLTCA.IDPLANTILLA = t.IDPLANTILLA COLLATE DATABASE_DEFAULT AND t.CODCARGO COLLATE DATABASE_DEFAULT = 
								NPLTCA.CODCARGO AND t.NIVEL COLLATE DATABASE_DEFAULT = NPLTCA.NIVEL AND t.GRADO COLLATE DATABASE_DEFAULT = NPLTCA.GRADO
							WHERE t.CODCARGO IS NULL AND NPLTCA.CODCARGO = @CODCARGO AND NPLTCA.NIVEL = @NIVEL AND NPLTCA.grado = @GRADO
						END
					END
					ELSE
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT ('El parametro JSON de plantillas no es valido.')
					END

					DROP TABLE #ParsedTableE;
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @CODCARGO = CODCARGO, @NIVEL = NIVEL, @GRADO = GRADO
		FROM OPENJSON(@PARAMETROS) WITH (CODCARGO VARCHAR(20) '$.CODCARGO', NIVEL VARCHAR(10) '$.NIVEL', GRADO VARCHAR(10) '$.GRADO')

		BEGIN TRY
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'NO ES POSIBLE ELIMINAR, DEBIDO A QUE EXISTEN PLANTAS RELACIONADAS AL CARGO (NPLA)'
			WHERE EXISTS (
					SELECT 1
					FROM NPLA
					WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVEL AND GRADO = @GRADO
					)

			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'NO ES POSIBLE ELIMINAR, DEBIDO A QUE EXISTEN DATOS RELACIONADOS AL CARGO (NEMPHIS)'
			WHERE EXISTS (
					SELECT 1
					FROM NEMPHIS
					WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVEL AND GRADO = @GRADO
					)

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				/* ELIMINA RELACION DE PLANTILLAS AL CARGO*/
				DELETE
				FROM NPLTCA
				WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVEL AND GRADO = @GRADO

				/* ELIMINA TODOS VALORES DE AJUSTE DE SUELDOS DEL CARGO SEGUN EL GRADO Y NIVEL*/
				DELETE
				FROM NCARNGV
				WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVEL AND GRADO = @GRADO

				/* ELIMINA EL CARGO */
				DELETE
				FROM NCARNG
				WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVEL AND GRADO = @GRADO
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
