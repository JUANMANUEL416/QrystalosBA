CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NEVED @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20)
DECLARE @PROCESO VARCHAR(20), @DATO NVARCHAR(MAX)
DECLARE @IDEVENTO VARCHAR(6)
DECLARE @ITEM DECIMAL(14, 0), @ITEMEDITE DECIMAL(14, 0), @FACTOR DECIMAL(14, 6), @FECHAINI DATETIME, @CODCONCEPTO VARCHAR(16), @INDEMNIZA BIT
DECLARE @PERINDEM VARCHAR(10)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @IDEVENTO = IDEVENTO, @ITEM = ITEM, @FACTOR = FACTOR, @FECHAINI = FECHAINI, @CODCONCEPTO = CODCONCEPTO, @INDEMNIZA = INDEMNIZA, @PERINDEM = PERINDEM, 
				@PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					IDEVENTO VARCHAR(6) '$.IDEVENTO', ITEM DECIMAL(14, 0) '$.ITEM', FACTOR DECIMAL(14, 6) '$.FACTOR', FECHAINI DATETIME '$.FECHAINI', CODCONCEPTO 
					VARCHAR(16) '$.CODCONCEPTO', INDEMNIZA BIT '$.INDEMNIZA', PERINDEM VARCHAR(10) '$.PERINDEM', PROCESO VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('EL EVENTO ', @IDEVENTO, ' CON ITEM, ', @ITEM, ' YA SE ENCUENTRA REGISTRADO')
					WHERE EXISTS (
							SELECT 1
							FROM NEVED
							WHERE IDEVENTO = @IDEVENTO AND ITEM = @ITEM
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO NEVED (IDEVENTO, ITEM, FACTOR, FECHAINI, CODCONCEPTO, INDEMNIZA, PERINDEM)
						SELECT @IDEVENTO, @ITEM, @FACTOR, @FECHAINI, @CODCONCEPTO, @INDEMNIZA, @PERINDEM
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @DATO = DATO
					FROM OPENJSON(@PARAMETROS) WITH (DATO NVARCHAR(MAX) AS JSON)

					SELECT @ITEMEDITE = ITEMEDITE
					FROM OPENJSON(@DATO) WITH (ITEMEDITE DECIMAL(14, 0) '$.ITEMEDITE')

					IF (@ITEMEDITE <> @ITEM)
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('EL EVENTO ', @IDEVENTO, ' CON ITEM, ', @ITEM, ' YA SE ENCUENTRA REGISTRADO')
						WHERE EXISTS (
								SELECT 1
								FROM NEVED
								WHERE IDEVENTO = @IDEVENTO AND ITEM = @ITEM
								)

						IF (
								SELECT COUNT(*)
								FROM @TBLERRORES
								) <= 0
						BEGIN
							UPDATE NEVED
							SET ITEM = @ITEM, FACTOR = @FACTOR, FECHAINI = @FECHAINI, CODCONCEPTO = @CODCONCEPTO, INDEMNIZA = @INDEMNIZA, PERINDEM = @PERINDEM
							WHERE IDEVENTO = @IDEVENTO AND ITEM = @ITEMEDITE
						END
					END
					ELSE
					BEGIN
						UPDATE NEVED
						SET FACTOR = @FACTOR, FECHAINI = @FECHAINI, CODCONCEPTO = @CODCONCEPTO, INDEMNIZA = @INDEMNIZA, PERINDEM = @PERINDEM
						WHERE IDEVENTO = @IDEVENTO AND ITEM = @ITEMEDITE
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @IDEVENTO = IDEVENTO, @ITEM = ITEM
		FROM OPENJSON(@PARAMETROS) WITH (IDEVENTO VARCHAR(6) '$.IDEVENTO', ITEM DECIMAL(14, 0) '$.ITEM')

		BEGIN TRY
			DELETE
			FROM NEVED
			WHERE IDEVENTO = @IDEVENTO AND ITEM = @ITEM
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
