CREATE OR ALTER PROCEDURE DBO.SPQ_PROVISIONES @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
SET DATEFORMAT dmy

DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(12)
DECLARE @COLUMNS VARCHAR(MAX)
DECLARE @SQL NVARCHAR(MAX)
DECLARE @MESINI VARCHAR(2)
DECLARE @MESFIN VARCHAR(2)
DECLARE @CAMPO VARCHAR(20)
DECLARE @ANO VARCHAR(4)
DECLARE @CODNOMINA VARCHAR(20)
DECLARE @CONDICIONAL VARCHAR(50), @CNSLIQUIDA VARCHAR(20)
DECLARE @CNSVAC VARCHAR(20), @CNSRPDX VARCHAR(20), @IDSEDE VARCHAR(5), @SYS_COMPUTERNAME VARCHAR(254), @COMPANIA VARCHAR(2), @CNSEXCEL VARCHAR(20)

BEGIN
	SELECT *
	INTO #JSON
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	SELECT @MODELO = MODELO, @METODO = METODO, @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON

	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
	FROM USUSU
	WHERE USUARIO = @USUARIO

	SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
	FROM UBEQ
	WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	IF @METODO = 'GENERA_RPDX_REPORTE'
	BEGIN
		SELECT @CNSRPDX = CNSRPDX, @CNSVAC = CNSVAC
		FROM OPENJSON(@PARAMETROS) WITH (CNSRPDX VARCHAR(20) '$.CNSRPDX', CNSVAC VARCHAR(20) '$.CNSVAC')

		BEGIN TRY
			DELETE
			FROM RPDX
			WHERE CNS = @CNSRPDX

			SELECT @ANO = ANO, @CAMPO = CASE CLASE
					WHEN 'PrimaJ'
						THEN 'ProvPrimaJ'
					WHEN 'PrimaD'
						THEN 'ProvPrimaD'
					WHEN 'Cesan'
						THEN 'ProvCesan'
					WHEN 'Vaca'
						THEN 'ProvVaca'
					WHEN 'ICesan'
						THEN 'ProvICesan'
					END, @MESINI = CASE CLASE
					WHEN 'PrimaJ'
						THEN 1
					WHEN 'PrimaD'
						THEN 7
					WHEN 'Cesan'
						THEN 1
					WHEN 'Vaca'
						THEN 1
					WHEN 'ICesan'
						THEN 1
					END, @MESFIN = CASE CLASE
					WHEN 'PrimaJ'
						THEN 6
					WHEN 'PrimaD'
						THEN 12
					WHEN 'Cesan'
						THEN 12
					WHEN 'Vaca'
						THEN 12
					WHEN 'ICesan'
						THEN 12
					END, @CODNOMINA = NUMDOC, @CONDICIONAL = CASE CLASE
					WHEN 'PrimaJ'
						THEN ' AND B.MES>=1 AND B.MES<=6 '
					WHEN 'PrimaD'
						THEN ' AND B.MES>=7 AND B.MES<=12 '
					WHEN 'Cesan'
						THEN ' AND B.MES>=1 AND B.MES<=12 '
					WHEN 'Vaca'
						THEN ' AND B.MES>=1 AND B.MES<=12 '
					WHEN 'ICesan'
						THEN ' AND B.MES>=1 AND B.MES<=12 '
					END
			FROM NVAC
			WHERE CNSVAC = @CNSVAC

			SELECT @COLUMNS = STUFF((
						SELECT ',' + QUOTENAME(LTRIM(MES))
						FROM (
							SELECT DISTINCT M.DESCRIPCION MES, M.MES N
							FROM NIEPED A
							LEFT JOIN NIEPE B ON A.CNSNIEPE = B.CNSNIEPE AND A.NUMDOC = B.NUMDOC
							LEFT JOIN MESES M ON CONVERT(INT, B.MES) = M.MES
							LEFT JOIN NEMP ON B.NUMDOC = NEMP.NUMDOC AND NEMP.FECHARETIRO IS NULL
							LEFT JOIN NOMIE ON NOMIE.NUMDOC = NEMP.NUMDOC
							WHERE A.CODCONCEPTO IN (
									SELECT CODIGO
									FROM TGEN
									WHERE TABLA = 'NOMINA' AND CAMPO = @CAMPO
									) AND NOMIE.CODNOMINA = @CODNOMINA AND B.ANO = @ANO
							) AS T
						ORDER BY N
						FOR XML PATH('')
						), 1, 1, '');

			SET @SQL = 
				N'
		INSERT INTO RPDX (CNS,IDTERCERO,STRINGGRANDE1,FECHA1,VALOR1,VALOR2,VALOR3,VALOR4,VALOR5,VALOR6,VALOR7,VALOR8,VALOR9,VALOR10,VALOR11,VALOR12)
		SELECT ''' 
				+ @CNSRPDX + 
				''', * FROM (
			SELECT NEMP.DOCIDEMPLEADO [IDENTIFICACION],
			   COALESCE(NEMP.PRIMERAPELLIDO,'''')+'' ''+COALESCE(NEMP.SEGUNDOAPELLIDO,'''')+'' ''+COALESCE(NEMP.PRIMERNOMBRE,'''')+'' ''+COALESCE(SEGUNDONOMBRE,'''') [NOMBRE], 
			   NEMP.FECHAINGRESO,
			   COALESCE(A.VALOR_APORTES,0)VALOR_APORTES , M.DESCRIPCION MES FROM NIEPED A 
			LEFT JOIN NIEPE B ON A.CNSNIEPE=B.CNSNIEPE AND A.NUMDOC=B.NUMDOC 
			LEFT JOIN MESES M ON CONVERT(INT,B.MES)=M.MES
			LEFT JOIN NEMP ON B.NUMDOC =NEMP.NUMDOC AND NEMP.FECHARETIRO IS NULL
			LEFT JOIN NOMIE ON NOMIE.NUMDOC=NEMP.NUMDOC
			WHERE  A.CODCONCEPTO IN(SELECT CODIGO FROM TGEN WHERE TABLA=''NOMINA'' AND CAMPO=''' 
				+ @CAMPO + ''') AND NOMIE.CODNOMINA=''' + @CODNOMINA + '''
			AND B.ANO=' + @ANO + ' ' + @CONDICIONAL + 
				N' AND B.FECHA>=NEMP.FECHAINGRESO
			) AS X PIVOT(
				 SUM(X.VALOR_APORTES) FOR MES IN (' + @COLUMNS + 
				N')
			) AS Z ORDER BY IDENTIFICACION '

			EXEC (@SQL)
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK

		RETURN
	END

	IF @METODO = 'ELIMINA_RPDX_REPORTE'
	BEGIN
		SELECT @CNSRPDX = CNSRPDX
		FROM OPENJSON(@PARAMETROS) WITH (CNSRPDX VARCHAR(20) '$.CNSRPDX')

		BEGIN TRY
			DELETE
			FROM RPDX
			WHERE CNS = @CNSRPDX
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK

		RETURN
	END

	IF @METODO = 'EXPORTAR_EXCEL'
	BEGIN
		SELECT @CNSVAC = CNSVAC, @CNSLIQUIDA = CNSLIQUIDA
		FROM OPENJSON(@PARAMETROS) WITH (CNSVAC VARCHAR(20) '$.CNSVAC', CNSLIQUIDA VARCHAR(20) '$.CNSLIQUIDA')

		BEGIN TRY
			SELECT @ANO = ANO, @CAMPO = CASE CLASE
					WHEN 'PrimaJ'
						THEN 'ProvPrimaJ'
					WHEN 'PrimaD'
						THEN 'ProvPrimaD'
					WHEN 'Cesan'
						THEN 'ProvCesan'
					WHEN 'Vaca'
						THEN 'ProvVaca'
					WHEN 'ICesan'
						THEN 'ProvICesan'
					END, @CONDICIONAL = CASE CLASE
					WHEN 'PrimaJ'
						THEN ' AND NIEPE.MES>=1 AND NIEPE.MES<=6 '
					WHEN 'PrimaD'
						THEN ' AND NIEPE.MES>=7 AND NIEPE.MES<=12 '
					WHEN 'Cesan'
						THEN ' AND NIEPE.MES>=1 AND NIEPE.MES<=12 '
					WHEN 'Vaca'
						THEN ' AND NIEPE.MES>=1 AND NIEPE.MES<=12 '
					WHEN 'ICesan'
						THEN ' AND NIEPE.MES>=1 AND NIEPE.MES<=12 '
					END
			FROM NVAC
			WHERE CNSVAC = @CNSVAC

			IF @CNSEXCEL IS NULL
			BEGIN
				EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@EXCEL', @LONGITUD = 8, @NVOCONSEC = @CNSEXCEL OUTPUT
			END

			INSERT INTO KEXCEL_FILL (CNSEXCEL, NOMBRE, BORRAR, CONSULTA)
			SELECT @CNSEXCEL, @CNSVAC + '.xlsx', 1, 'SELECT NEMP.DOCIDEMPLEADO, TER.RAZONSOCIAL, NCARNG.DESCRIPCION AS CARGO, NEMP.BASICO, NEMP.ESTADO, ' + 
				'NIEPED.VALOR_APORTES AS PROVISION, NIEPED.CODCONCEPTO AS IDCONCEPTO, NCON.DESCRIPCION AS CONCEPTO, ' + 
				'NIEPE.ANO, NIEPE.MES, NVACD.CNSVAC AS CONSECUTIVO ' + 'FROM [dbo].[NVACD] ' + 'INNER JOIN NVAC ON NVAC.CNSVAC = NVACD.CNSVAC ' + 
				'INNER JOIN NIEPE ON NVAC.NUMDOC = NIEPE.NUMDOC ' + 'INNER JOIN NEMP ON NIEPE.NUMDOC = NEMP.NUMDOC ' + 
				'INNER JOIN TER ON NEMP.TERCEROID = TER.IDTERCERO ' + 
				'LEFT JOIN NIEPED ON NIEPE.CNSNIEPE = NIEPED.CNSNIEPE AND NIEPE.NUMDOC = NIEPED.NUMDOC ' + 
				'LEFT JOIN NCARNG ON NCARNG.CODCARGO = NEMP.CODCARGO AND NCARNG.NIVEL = NEMP.NIVEL AND NCARNG.GRADO = NEMP.GRADO ' + 
				'INNER JOIN NCON ON NCON.CODCONCEPTO = NIEPED.CODCONCEPTO ' + 'WHERE NVAC.CNSLIQUIDA = ''' + ISNULL(@CNSLIQUIDA, '') + ''' ' + 
				'AND NIEPE.ANO = ''' + ISNULL(@ANO, '') + ''' ' + 'AND NIEPED.CODCONCEPTO IN ( ' + 'SELECT CODIGO FROM TGEN ' + 
				'WHERE TABLA = ''NOMINA'' AND CAMPO = ''' + ISNULL(@CAMPO, '') + ''' ' + ') ' + 'AND NVACD.ESTADO = ''Liquidado'' ' + ISNULL(@CONDICIONAL, '') + ' ' 
				+ -- Aqu� se inyecta el fragmento SQL de fecha/mes
				'ORDER BY TER.RAZONSOCIAL'
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK, @CNSEXCEL CNSEXCEL

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK, @CNSEXCEL CNSEXCEL
	END
END
