CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NEMPDA @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100)
DECLARE @USUARIO VARCHAR(20), @PROCESO VARCHAR(20)
DECLARE @NUMDOC VARCHAR(20), @ITEM SMALLINT, @CODCONCEPTO VARCHAR(20), @TIPOCALCULO VARCHAR(10), @VALOR DECIMAL(14, 6)
DECLARE @IDTERCERO VARCHAR(20), @FECHAFIN DATETIME, @FECHAINI DATETIME
DECLARE @CODFINANCIACION VARCHAR(20), @OBSERVACION VARCHAR(255), @CNSMASIVO VARCHAR(20)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @NUMDOC = NUMDOC, @ITEM = ITEM, @IDTERCERO = IDTERCERO, @FECHAFIN = FECHAFIN, @FECHAINI = FECHAINI, @CODFINANCIACION = CODFINANCIACION, @OBSERVACION = 
				OBSERVACION, @CNSMASIVO = CNSMASIVO, @CODCONCEPTO = CODCONCEPTO, @TIPOCALCULO = TIPOCALCULO, @VALOR = VALOR, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					NUMDOC VARCHAR(20) '$.NUMDOC', ITEM SMALLINT '$.ITEM', IDTERCERO VARCHAR(20) '$.IDTERCERO', FECHAFIN DATETIME '$.FECHAFIN', FECHAINI DATETIME 
					'$.FECHAINI', CODFINANCIACION VARCHAR(20) '$.CODFINANCIACION', OBSERVACION VARCHAR(255) '$.OBSERVACION', CNSMASIVO VARCHAR(20) 
					'$.CNSMASIVO', CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO', TIPOCALCULO VARCHAR(10) '$.TIPOCALCULO', VALOR DECIMAL(14, 6) '$.VALOR', PROCESO 
					VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('EL CONCEPTO ', @CODCONCEPTO, ' YA SE ENCUENTRA REGISTRADO PARA EL EMPLEADO ', @NUMDOC, ' EN EL PERIODO DE TIEMPO REGISTRADO'
							)
					WHERE EXISTS (
							SELECT 1
							FROM NEMPDA
							INNER JOIN NCON ON NCON.CODCONCEPTO = NEMPDA.CODCONCEPTO
							WHERE NEMPDA.CODCONCEPTO = @CODCONCEPTO AND NUMDOC = @NUMDOC AND @FECHAFIN >= FECHAINI AND @FECHAINI <= FECHAFIN AND NCON.SEREPITE = 'No'
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO NEMPDA (NUMDOC, ITEM, CODCONCEPTO, TIPOCALCULO, VALOR, IDTERCERO, FECHAFIN, FECHAINI, CODFINANCIACION, OBSERVACION, CNSMASIVO
							)
						SELECT @NUMDOC, @ITEM, @CODCONCEPTO, @TIPOCALCULO, @VALOR, @IDTERCERO, @FECHAFIN, @FECHAINI, @CODFINANCIACION, @OBSERVACION, NULL
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('EL CONCEPTO ', @CODCONCEPTO, ' YA SE ENCUENTRA REGISTRADO PARA EL EMPLEADO ', @NUMDOC, ' EN EL PERIODO DE TIEMPO REGISTRADO'
							)
					WHERE EXISTS (
							SELECT 1
							FROM NEMPDA
							INNER JOIN NCON ON NCON.CODCONCEPTO = NEMPDA.CODCONCEPTO
							WHERE NEMPDA.CODCONCEPTO = @CODCONCEPTO AND NUMDOC = @NUMDOC AND @FECHAFIN >= FECHAINI AND @FECHAINI <= FECHAFIN AND ITEM <> @ITEM AND NCON.
								SEREPITE = 'No'
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						UPDATE NEMPDA
						SET CODCONCEPTO = @CODCONCEPTO, TIPOCALCULO = @TIPOCALCULO, VALOR = @VALOR, IDTERCERO = @IDTERCERO, FECHAFIN = @FECHAFIN, FECHAINI = @FECHAINI, 
							CODFINANCIACION = @CODFINANCIACION, OBSERVACION = @OBSERVACION
						WHERE NUMDOC = @NUMDOC AND ITEM = @ITEM
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @NUMDOC = NUMDOC, @ITEM = ITEM, @CODCONCEPTO = CODCONCEPTO
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC', ITEM SMALLINT '$.ITEM', CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO')

		BEGIN TRY
			DELETE
			FROM NEMPDA
			WHERE NUMDOC = @NUMDOC AND CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'OPTENER_ITEMS'
	BEGIN
		SELECT @NUMDOC = NUMDOC
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC')

		SELECT 'OK' OK

		SELECT TOP 1 ITEM
		FROM NEMPDA
		WHERE NUMDOC = @NUMDOC
		ORDER BY ITEM DESC
	END
END
