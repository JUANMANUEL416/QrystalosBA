CREATE OR ALTER PROCEDURE DBO.SPQ_DELIVERY_MAD @JSON NVARCHAR(MAX)
WITH ENCRYPTION
AS
SET NOCOUNT ON;
SET LANGUAGE Spanish;
SET DATEFORMAT dmy;

DECLARE
  @PARAMETROS NVARCHAR(MAX),
  @MODELO      VARCHAR(100),
  @METODO      VARCHAR(100),
  @USUARIO     VARCHAR(12),
  @A           INT;

DECLARE @IDAUT           VARCHAR(20);
DECLARE @IDRUTA          INT;
DECLARE @DIRECCION       VARCHAR(500);
DECLARE @DIR_LAT         VARCHAR(50);
DECLARE @DIR_LON         VARCHAR(50);
DECLARE @REFERENCIA      VARCHAR(250);
DECLARE @TELEFONO_REF    VARCHAR(50);
DECLARE @OBSERVACION     VARCHAR(500);
DECLARE @FECHA_REF       DATETIME;
DECLARE @HORAINI_REF     VARCHAR(5);
DECLARE @HORAFIN_REF     VARCHAR(5);
DECLARE @NUEVO_ID        INT;
DECLARE @CNT_AUTDF       INT;
DECLARE @IDBODEGA        VARCHAR(20);
DECLARE @CNSIZSOL        VARCHAR(20);
DECLARE @CNSMOV          VARCHAR(20);

DECLARE @FECHA_DIA             DATE;
DECLARE @ID_IZDOMP_GEO         INT;
DECLARE @ID_LINEA_GEO          INT;
DECLARE @NUEVO_ESTADO_LINEA    VARCHAR(30);
DECLARE @OBSERVACION_LINEA     VARCHAR(500);
DECLARE @HID_SYNC              INT;
DECLARE @TOT_L                 INT;
DECLARE @ENT_L                 INT;
DECLARE @NOE_L                 INT;

BEGIN
  SELECT @A = ISJSON(@JSON);
  IF @A = 0
  BEGIN
    RAISERROR('Json: formato erroneo', 16, 1);
    RETURN;
  END;

  SELECT
    @MODELO = MODELO,
    @METODO = METODO,
    @PARAMETROS = PARAMETROS,
    @USUARIO = USUARIO
  FROM OPENJSON(@JSON)
  WITH (
    MODELO     VARCHAR(100) '$.MODELO',
    METODO     VARCHAR(100) '$.METODO',
    PARAMETROS NVARCHAR(MAX) AS JSON,
    USUARIO    VARCHAR(12)   '$.USUARIO'
  );

  IF COALESCE(@USUARIO, '') = ''
  BEGIN
    RAISERROR('USUARIO requerido', 16, 1);
    RETURN;
  END;

  IF COALESCE(@MODELO, '') <> 'DELIVERY_MAD'
  BEGIN
    RAISERROR('MODELO invalido para SPQ_DELIVERY_MAD', 16, 1);
    RETURN;
  END;

  IF @METODO = 'LISTAR_CABECERAS'
  BEGIN
    SELECT @IDAUT = IDAUT
    FROM OPENJSON(@PARAMETROS)
    WITH (IDAUT VARCHAR(20) '$.IDAUT');

    IF COALESCE(@IDAUT, '') = ''
    BEGIN
      RAISERROR('LISTAR_CABECERAS: IDAUT requerido', 16, 1);
      RETURN;
    END;

    SELECT
      H.ID,
      H.IDAUT,
      H.USUARIO,
      H.FECHA,
      H.ESTADO,
      H.IDRUTA,
      H.DIRECCION,
      H.DIR_LAT,
      H.DIR_LON,
      H.REFERENCIA,
      H.TELEFONO_REF,
      H.IDAFILIADO,
      H.IDPLAN,
      H.CONSECUTIVOCIT,
      AFI.NOMBREAFI
    FROM dbo.IZDOMP H
    LEFT JOIN dbo.AFI ON AFI.IDAFILIADO = H.IDAFILIADO
    WHERE H.IDAUT = @IDAUT
    ORDER BY H.ID DESC;

    RETURN;
  END;

  IF @METODO = 'CREAR_REPARTO'
  BEGIN
    /*
      Crea la cabecera IZDOMP y genera el detalle IZDOMPD a partir de AUTDF
      (dispensaciones ya confirmadas via LISTA_AUT/PROCESAR_MEDICAMENTOS/CONFIRMAR).
    */

    SELECT
      @IDAUT = IDAUT,
      @IDRUTA = IDRUTA,
      @DIRECCION = DIRECCION,
      @DIR_LAT = DIR_LAT,
      @DIR_LON = DIR_LON,
      @REFERENCIA = REFERENCIA,
      @TELEFONO_REF = TELEFONO_REF,
      @OBSERVACION = OBSERVACION,
      @FECHA_REF = FECHA_REF,
      @HORAINI_REF = HORAINI_REF,
      @HORAFIN_REF = HORAFIN_REF
    FROM OPENJSON(@PARAMETROS)
    WITH (
      IDAUT         VARCHAR(20)   '$.IDAUT',
      IDRUTA        INT           '$.IDRUTA',
      DIRECCION     VARCHAR(500)  '$.DIRECCION',
      DIR_LAT       VARCHAR(50)   '$.DIR_LAT',
      DIR_LON       VARCHAR(50)   '$.DIR_LON',
      REFERENCIA    VARCHAR(250)  '$.REFERENCIA',
      TELEFONO_REF  VARCHAR(50)   '$.TELEFONO_REF',
      OBSERVACION   VARCHAR(500)  '$.OBSERVACION',
      FECHA_REF     DATETIME      '$.FECHA_REF',
      HORAINI_REF   VARCHAR(5)    '$.HORAINI_REF',
      HORAFIN_REF   VARCHAR(5)    '$.HORAFIN_REF'
    );

    IF COALESCE(@IDAUT, '') = ''
    BEGIN
      RAISERROR('CREAR_REPARTO: IDAUT requerido', 16, 1);
      RETURN;
    END;

    IF NOT EXISTS (SELECT 1 FROM dbo.AUT WHERE AUT.IDAUT = @IDAUT)
    BEGIN
      RAISERROR('CREAR_REPARTO: AUT no existe', 16, 1);
      RETURN;
    END;

    IF EXISTS (SELECT 1 FROM dbo.IZDOMP WHERE IDAUT = @IDAUT)
    BEGIN
      RAISERROR('CREAR_REPARTO: la autorizacion ya tiene un reparto MAD creado', 16, 1);
      RETURN;
    END;

    -- Debe existir dispensacion previa confirmada (AUTDF con IDSERVICIO_AUTD)
    SELECT @CNT_AUTDF = COUNT(*)
    FROM dbo.AUTDF
    WHERE IDAUT = @IDAUT
      AND COALESCE(IDSERVICIO_AUTD, '') <> '';

    IF @CNT_AUTDF < 1
    BEGIN
      RAISERROR('CREAR_REPARTO: no hay medicamentos dispensados (AUTDF) para esta autorizacion. Confirme la dispensacion primero.', 16, 1);
      RETURN;
    END;

    IF @IDRUTA IS NOT NULL AND NOT EXISTS (SELECT 1 FROM dbo.RUTA R WHERE R.ID = @IDRUTA)
    BEGIN
      RAISERROR('CREAR_REPARTO: IDRUTA no existe', 16, 1);
      RETURN;
    END;

    -- Bodega / IZSOL / IMOV ya generados por el CONFIRMAR de LISTA_AUT.
    SELECT TOP (1) @IDBODEGA = IDBODEGA
    FROM dbo.AUTDF
    WHERE IDAUT = @IDAUT
      AND COALESCE(IDBODEGA, '') <> '';

    IF COALESCE(@IDBODEGA, '') = ''
    BEGIN
      RAISERROR('CREAR_REPARTO: no se encontro bodega en AUTDF para esta autorizacion', 16, 1);
      RETURN;
    END;

    SELECT @CNSIZSOL = CNSMOV FROM dbo.AUT WHERE IDAUT = @IDAUT;

    SELECT TOP (1) @CNSMOV = M.CNSMOV
    FROM dbo.IMOV M
    WHERE M.NODOCUMENTO = @CNSIZSOL
      AND M.PROCEDENCIA = 'CM_SOL'
      AND COALESCE(M.ESTADO, 0) = 1;

    BEGIN TRY
      BEGIN TRAN;

      INSERT INTO dbo.IZDOMP (
        IDAUT,
        USUARIO,
        FECHA,
        IDAFILIADO,
        IDPLAN,
        IDTERCERO,
        IDRUTA,
        DIRECCION,
        DIR_LAT,
        DIR_LON,
        REFERENCIA,
        TELEFONO_REF,
        FECHA_REF,
        HORAINI_REF,
        HORAFIN_REF,
        ESTADO,
        OBSERVACION,
        CONSECUTIVOCIT
      )
      SELECT
        A.IDAUT,
        @USUARIO,
        GETDATE(),
        A.IDAFILIADO,
        A.IDPLAN,
        COALESCE(NULLIF(RTRIM(A.IDTERCERO_AFI), ''), NULLIF(RTRIM(A.IDPROVEEDOR), '')),
        @IDRUTA,
        @DIRECCION,
        @DIR_LAT,
        @DIR_LON,
        @REFERENCIA,
        @TELEFONO_REF,
        @FECHA_REF,
        @HORAINI_REF,
        @HORAFIN_REF,
        'PROGRAMADO',
        @OBSERVACION,
        NULLIF(RTRIM(A.CONSECUTIVOCIT), '')
      FROM dbo.AUT A
      WHERE A.IDAUT = @IDAUT;

      SET @NUEVO_ID = CAST(SCOPE_IDENTITY() AS INT);

      INSERT INTO dbo.IZDOMPD (
        ID_IZDOMP,
        IDBODEGA,
        CNSIZSOL,
        CNSMOV,
        IDAUT,
        IDSERVICIO,
        CANTIDAD,
        NOLOTE,
        ESTADO,
        FECHA,
        USUARIO
      )
      SELECT
        @NUEVO_ID,
        @IDBODEGA,
        @CNSIZSOL,
        @CNSMOV,
        @IDAUT,
        A.IDSERVICIO_AUTD,
        SUM(A.CANTIDAD),
        A.NOLOTEPEDIDO,
        'EN_REPARTO',
        GETDATE(),
        @USUARIO
      FROM dbo.AUTDF A
      WHERE A.IDAUT = @IDAUT
        AND COALESCE(A.IDSERVICIO_AUTD, '') <> ''
      GROUP BY A.IDSERVICIO_AUTD, A.NOLOTEPEDIDO;

      COMMIT TRAN;
    END TRY
    BEGIN CATCH
      IF @@TRANCOUNT > 0
        ROLLBACK TRAN;

      THROW;
    END CATCH;

    SELECT 'OK' AS OK;
    SELECT @NUEVO_ID AS ID_IZDOMP;
    RETURN;
  END;

  IF @METODO = 'LISTAR_ENTREGAS_CONDUCTOR'
  BEGIN
    SELECT @FECHA_DIA = TRY_CONVERT(DATE, FECHA, 23)
    FROM OPENJSON(@PARAMETROS)
    WITH (FECHA VARCHAR(10) '$.FECHA');

    IF @FECHA_DIA IS NULL
      SET @FECHA_DIA = CONVERT(DATE, GETDATE());

    IF NOT EXISTS (
      SELECT 1
      FROM dbo.USUSU U
      WHERE U.USUARIO = @USUARIO
        AND COALESCE(U.TIPO_USUARIOADM, '') = 'MOTO'
    )
    BEGIN
      RAISERROR('LISTAR_ENTREGAS_CONDUCTOR: usuario no es motorizado (MOTO)', 16, 1);
      RETURN;
    END;

    SELECT
      H.ID,
      H.IDAUT,
      H.FECHA,
      H.ESTADO AS ESTADO_CAB,
      H.DIRECCION,
      H.DIR_LAT,
      H.DIR_LON,
      H.REFERENCIA,
      H.TELEFONO_REF,
      H.IDRUTA,
      CONVERT(VARCHAR(10), H.FECHA_REF, 23) AS FECHA_REF_TXT,
      NULLIF(RTRIM(H.HORAINI_REF), '') AS HORAINI_REF,
      NULLIF(RTRIM(H.HORAFIN_REF), '') AS HORAFIN_REF,
      NULLIF(RTRIM(H.OBSERVACION), '') AS OBSERVACION_CAB,
      AFI.NOMBREAFI,
      AFI.DOCIDAFILIADO,
      COALESCE(AFI.CELULAR, AFI.TELEFONORES, '') AS TELEFONO_PACIENTE,
      (
        SELECT COUNT(*)
        FROM dbo.IZDOMPD D2
        WHERE D2.ID_IZDOMP = H.ID
          AND D2.ESTADO = 'ENTREGADO'
      ) AS LINEAS_ENTREGADAS,
      (
        SELECT COUNT(*)
        FROM dbo.IZDOMPD D2
        WHERE D2.ID_IZDOMP = H.ID
          AND D2.ESTADO = 'NO_ENTREGADO'
      ) AS LINEAS_NO_ENTREGADAS,
      (
        SELECT COUNT(*)
        FROM dbo.IZDOMPD D2
        WHERE D2.ID_IZDOMP = H.ID
      ) AS LINEAS_TOTAL
    FROM dbo.IZDOMP H
    INNER JOIN dbo.RUTA R ON R.ID = H.IDRUTA
    LEFT JOIN dbo.AFI ON AFI.IDAFILIADO = H.IDAFILIADO
    WHERE R.IDCONDUCTOR = @USUARIO
      AND CONVERT(DATE, R.FECHA) = @FECHA_DIA
    ORDER BY H.ID DESC;

    RETURN;
  END;

  IF @METODO = 'LISTAR_LINEAS_REPARTO_GEO'
  BEGIN
    SELECT @ID_IZDOMP_GEO = ID_IZDOMP
    FROM OPENJSON(@PARAMETROS)
    WITH (ID_IZDOMP INT '$.ID_IZDOMP');

    IF @ID_IZDOMP_GEO IS NULL
    BEGIN
      RAISERROR('LISTAR_LINEAS_REPARTO_GEO: ID_IZDOMP requerido', 16, 1);
      RETURN;
    END;

    IF NOT EXISTS (
      SELECT 1
      FROM dbo.USUSU U
      WHERE U.USUARIO = @USUARIO
        AND COALESCE(U.TIPO_USUARIOADM, '') = 'MOTO'
    )
    BEGIN
      RAISERROR('LISTAR_LINEAS_REPARTO_GEO: usuario no es motorizado (MOTO)', 16, 1);
      RETURN;
    END;

    IF NOT EXISTS (
      SELECT 1
      FROM dbo.IZDOMP H
      INNER JOIN dbo.RUTA R ON R.ID = H.IDRUTA
      WHERE H.ID = @ID_IZDOMP_GEO
        AND R.IDCONDUCTOR = @USUARIO
    )
    BEGIN
      RAISERROR('LISTAR_LINEAS_REPARTO_GEO: reparto no autorizado para este conductor', 16, 1);
      RETURN;
    END;

    SELECT
      D.ID,
      D.ID_IZDOMP,
      D.IDAUT,
      D.IDSERVICIO,
      D.CANTIDAD,
      D.NOLOTE,
      D.ESTADO,
      D.FECHA,
      SER.DESCSERVICIO,
      D.OBSERVACION,
      CONVERT(VARCHAR(36), D.ID_DOC_FIRMA_PAC) AS ID_DOC_FIRMA_PAC
    FROM dbo.IZDOMPD D
    INNER JOIN dbo.SER ON SER.IDSERVICIO = D.IDSERVICIO
    WHERE D.ID_IZDOMP = @ID_IZDOMP_GEO
    ORDER BY D.ID;

    RETURN;
  END;

  IF @METODO = 'REGISTRAR_ESTADO_LINEA_GEO'
  BEGIN
    SELECT
      @ID_LINEA_GEO = ID_LINEA,
      @NUEVO_ESTADO_LINEA = NUEVO_ESTADO,
      @OBSERVACION_LINEA = OBS_LINEA
    FROM OPENJSON(@PARAMETROS)
    WITH (
      ID_LINEA       INT           '$.ID_LINEA',
      NUEVO_ESTADO   VARCHAR(30)   '$.NUEVO_ESTADO',
      OBS_LINEA      VARCHAR(500)  '$.OBSERVACION'
    );

    IF @ID_LINEA_GEO IS NULL
    BEGIN
      RAISERROR('REGISTRAR_ESTADO_LINEA_GEO: ID_LINEA requerido', 16, 1);
      RETURN;
    END;

    IF NOT EXISTS (
      SELECT 1
      FROM dbo.USUSU U
      WHERE U.USUARIO = @USUARIO
        AND COALESCE(U.TIPO_USUARIOADM, '') = 'MOTO'
    )
    BEGIN
      RAISERROR('REGISTRAR_ESTADO_LINEA_GEO: usuario no es motorizado (MOTO)', 16, 1);
      RETURN;
    END;

    IF @NUEVO_ESTADO_LINEA NOT IN ('ENTREGADO', 'NO_ENTREGADO')
    BEGIN
      RAISERROR('REGISTRAR_ESTADO_LINEA_GEO: NUEVO_ESTADO debe ser ENTREGADO o NO_ENTREGADO', 16, 1);
      RETURN;
    END;

    IF NOT EXISTS (
      SELECT 1
      FROM dbo.IZDOMPD D
      INNER JOIN dbo.IZDOMP H ON H.ID = D.ID_IZDOMP
      INNER JOIN dbo.RUTA R ON R.ID = H.IDRUTA
      WHERE D.ID = @ID_LINEA_GEO
        AND R.IDCONDUCTOR = @USUARIO
        AND D.ESTADO = 'EN_REPARTO'
    )
    BEGIN
      RAISERROR('REGISTRAR_ESTADO_LINEA_GEO: linea no disponible o no es su ruta', 16, 1);
      RETURN;
    END;

    IF @NUEVO_ESTADO_LINEA = 'ENTREGADO'
      AND COL_LENGTH('dbo.IZDOMPD', 'ID_DOC_FIRMA_PAC') IS NOT NULL
      AND NOT EXISTS (
        SELECT 1
        FROM dbo.IZDOMPD DX
        WHERE DX.ID = @ID_LINEA_GEO
          AND DX.ID_DOC_FIRMA_PAC IS NOT NULL
      )
    BEGIN
      RAISERROR('REGISTRAR_ESTADO_LINEA_GEO: debe registrar la firma del paciente antes de marcar ENTREGADO', 16, 1);
      RETURN;
    END;

    SET @HID_SYNC = (
      SELECT TOP (1) D.ID_IZDOMP
      FROM dbo.IZDOMPD D
      WHERE D.ID = @ID_LINEA_GEO
    );

    BEGIN TRY
      BEGIN TRAN;

      UPDATE dbo.IZDOMPD
      SET
        ESTADO = @NUEVO_ESTADO_LINEA,
        FECHA = GETDATE(),
        USUARIO = @USUARIO,
        OBSERVACION = CASE
          WHEN @NUEVO_ESTADO_LINEA = 'NO_ENTREGADO' THEN @OBSERVACION_LINEA
          ELSE NULL
        END
      WHERE ID = @ID_LINEA_GEO;

      SELECT
        @TOT_L = COUNT(*),
        @ENT_L = ISNULL(SUM(CASE WHEN ESTADO = 'ENTREGADO' THEN 1 ELSE 0 END), 0),
        @NOE_L = ISNULL(SUM(CASE WHEN ESTADO = 'NO_ENTREGADO' THEN 1 ELSE 0 END), 0)
      FROM dbo.IZDOMPD
      WHERE ID_IZDOMP = @HID_SYNC;

      UPDATE dbo.IZDOMP
      SET ESTADO = CASE
        WHEN @ENT_L = @TOT_L THEN 'ENTREGADO'
        WHEN @NOE_L = @TOT_L THEN 'NO_ENTREGADO'
        WHEN @ENT_L + @NOE_L = @TOT_L THEN 'CERRADO_PARCIAL'
        ELSE ESTADO
      END
      WHERE ID = @HID_SYNC;

      COMMIT TRAN;
    END TRY
    BEGIN CATCH
      IF @@TRANCOUNT > 0
        ROLLBACK TRAN;

      THROW;
    END CATCH;

    SELECT 'OK' AS OK;
    RETURN;
  END;

  RAISERROR('SPQ_DELIVERY_MAD: METODO no implementado', 16, 1);
END;
