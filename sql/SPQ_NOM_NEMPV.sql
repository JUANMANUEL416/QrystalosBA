CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NEMPV @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @DATOS VARCHAR(MAX), @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20), @IDSEDE VARCHAR(5), @PROCESO VARCHAR(20)
DECLARE @NUMDOC VARCHAR(20), @ITEM SMALLINT, @CONCEPTO VARCHAR(20), @F_CUMPLE DATETIME, @NDIAS SMALLINT, @F_INICAL DATETIME
DECLARE @F_FINAL DATETIME, @CNSPAGO VARCHAR(20), @ESTADO VARCHAR(10), @DIASG DECIMAL(7, 4), @DIASP DECIMAL(7, 4), @MAX SMALLINT
DECLARE @COMPANIA VARCHAR(2), @SYS_COMPUTERNAME VARCHAR(200), @OBSERVACIONES VARCHAR(512), @PROCEDENCIA VARCHAR(20)
DECLARE @NIVEL VARCHAR(10), @GRADO VARCHAR(10), @CODCARGO VARCHAR(20), @NPERIODOS SMALLINT

BEGIN
	SELECT *
	INTO #JSON
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	SELECT @MODELO = MODELO, @METODO = METODO, @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @NUMDOC = NUMDOC, @ITEM = ITEM, @CONCEPTO = CONCEPTO, @F_CUMPLE = F_CUMPLE, @NDIAS = NDIAS, @F_INICAL = F_INICAL, @F_FINAL = F_FINAL, @CNSPAGO = CNSPAGO, 
				@ESTADO = ESTADO, @DIASG = DIASG, @DIASP = DIASP, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					NUMDOC VARCHAR(20) '$.NUMDOC', ITEM SMALLINT '$.ITEM', CONCEPTO VARCHAR(20) '$.CONCEPTO', F_CUMPLE DATETIME '$.F_CUMPLE', NDIAS SMALLINT 
					'$.NDIAS', F_INICAL DATETIME '$.F_INICAL', F_FINAL DATETIME '$.F_FINAL', CNSPAGO VARCHAR(20) '$.CNSPAGO', ESTADO VARCHAR(10) '$.ESTADO', DIASG 
					DECIMAL(7, 4) '$.DIASG', DIASP DECIMAL(7, 4) '$.DIASP', PROCESO VARCHAR(20) '$.PROCESO'
					)

			SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
			FROM USUSU
			WHERE USUARIO = @USUARIO

			SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
			FROM UBEQ
			WHERE SYS_ComputerName = @SYS_COMPUTERNAME

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					SELECT @CODCARGO = CODCARGO, @NIVEL = NIVEL, @GRADO = GRADO
					FROM NEMP
					WHERE ESTADO = 'Activo' AND NUMDOC = @NUMDOC

					SELECT @NPERIODOS = COALESCE(NVACACIONES, 1)
					FROM NCARNG
					WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVEL AND GRADO = @GRADO

					SELECT @MAX = MAX(ITEM)
					FROM NEMPV
					WHERE NUMDOC = @NUMDOC

					SELECT @MAX = COALESCE(@MAX, 0) + 1

					INSERT INTO [NEMPV] ([NUMDOC], [ITEM], [CONCEPTO], [F_CUMPLE], [NDIAS], [F_INICAL], [F_FINAL], [CNSPAGO], [ESTADO], [DIASG], [DIASP], [USUARIO], [PROCEDENCIA]
						)
					SELECT @NUMDOC, @MAX, NULL, @F_CUMPLE, 15 * @NPERIODOS, @F_INICAL, @F_FINAL, NULL, @ESTADO, @DIASG, @DIASP, @USUARIO, 'Manual'

					EXEC SPK_PROCESO_VACACIONES '', 'ACTUALIZA', @NUMDOC
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					UPDATE NEMPV
					SET F_CUMPLE = @F_CUMPLE, F_INICAL = @F_INICAL, F_FINAL = @F_FINAL, DIASG = @DIASG, DIASP = @DIASP, PROCEDENCIA = 'Manual'
					WHERE NUMDOC = @NUMDOC AND ITEM = @ITEM

					EXEC SPK_PROCESO_VACACIONES '', 'ACTUALIZA', @NUMDOC
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
