CREATE OR ALTER PROCEDURE DBO.SPQ_FCXPDBCR
	@JSON NVARCHAR(MAX)
WITH ENCRYPTION
AS
DECLARE @PARAMETROS       NVARCHAR(MAX)
       ,@METODO           VARCHAR(100)
       ,@USUARIO          VARCHAR(20)
       ,@SYS_COMPUTERNAME VARCHAR(200)
       ,@SEDE             VARCHAR(5)
       ,@IDSEDE           VARCHAR(20)
       ,@COMPANIA         VARCHAR(5)
       ,@PROCESO          VARCHAR(20)
       ,@CNSFCXP          VARCHAR(100)
       ,@ITEM             INT
       ,@ITEM_DBCR        INT
       ,@TIPO             VARCHAR(20)
       ,@IDNOTA           VARCHAR(20)
       ,@CUENTADB         VARCHAR(20)
       ,@CUENTACR         VARCHAR(20)
       ,@datoFCXPDBCR     NVARCHAR(MAX)
       ,@CONSECUTIVO      NVARCHAR(MAX)
       ,@IMPUESTOS        NVARCHAR(MAX)
       ,@DETALLE_VALORES  NVARCHAR(MAX)
       ,@SALDO            DECIMAL(14,2)
       ,@VLR_NETO         DECIMAL(14,2)
       ,@CONTABILIZADA    INT
       ,@VALOR            DECIMAL(14,2)
       ,@VLR_IMPUESTOS    DECIMAL(14,2)
       ,@VALOR_DESC       DECIMAL(16,2)
       ,@TOTAL            DECIMAL(16,2)

DECLARE @TBLERRORES TABLE(ERROR VARCHAR(500));

BEGIN
	SET DATEFORMAT dmy
	SET NOCOUNT ON

	SELECT *
	INTO #JSON
	FROM OPENJSON(@JSON) WITH (
		METODO     VARCHAR(100) '$.METODO',
		USUARIO    VARCHAR(100) '$.USUARIO',
		PARAMETROS NVARCHAR(MAX) AS JSON
	)

	SELECT @METODO     = METODO,
	       @PARAMETROS = PARAMETROS,
	       @USUARIO    = USUARIO
	FROM #JSON

	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SEDE = IDSEDE, @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
	FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
	IF @METODO = 'CONSULTAR_RESPUESTA_DIAN_NOTA'
	BEGIN
		SELECT @IDNOTA = JSON_VALUE(@PARAMETROS, '$.IDNOTA')

		IF COALESCE(@IDNOTA,'') = ''
		BEGIN
			SELECT 'KO' AS OK, 'No se recibi? IDNOTA para consultar.' AS ERROR
			RETURN
		END

		IF NOT EXISTS(
			SELECT 1
			FROM FCXPDBCR NDBCR
			INNER JOIN FDIANR RD ON RD.CNSDOCUMENTO = NDBCR.CNSFCXP
			WHERE NDBCR.IDNOTA = @IDNOTA
		)
		BEGIN
			SELECT 'KO' AS OK, 'No existe informaci?n de env?o/respuesta DIAN para la nota.' AS ERROR
			RETURN
		END

		SELECT TOP 1
			'OK' AS OK,
			NDBCR.*,
			RD.*
		FROM FCXPDBCR NDBCR
		INNER JOIN FDIANR RD ON RD.CNSDOCUMENTO = NDBCR.CNSFCXP
		WHERE NDBCR.IDNOTA = @IDNOTA
		ORDER BY RD.FECHA DESC, RD.CNSDOCUMENTO DESC
		RETURN
	END
	IF @METODO = 'CRUD_FCXPDBCR'
	BEGIN
		SELECT @datoFCXPDBCR =  datoFCXPDBCR
	   FROM OPENJSON (@PARAMETROS)
	   WITH		 (
		datoFCXPDBCR		NVARCHAR(MAX) AS JSON
		)
		SELECT @PROCESO =UPPER( JSON_VALUE(@datoFCXPDBCR,'$.PROCESO'))
		SELECT * INTO #datoFCXPDBCR FROM  OPENJSON(@datoFCXPDBCR)
		WITH (
		CNSFCXP					VARCHAR(20)			'$.CNSFCXP'				,ITEM				INT					'$.ITEM'
		,IDNOTA					VARCHAR(20)			'$.IDNOTA'				,TIPO				VARCHAR(20)			'$.TIPO'
		,DECRUCES				INT					'$.DECRUCES'			,GIVA				BIT					'$.GIVA'
		,GIMPUESTOS				BIT					'$.GIMPUESTOS'			,VALOR				DECIMAL(14,2)		'$.VALOR'
		,PORCENTAJEIVA			DECIMAL(14,2)		'$.PORCENTAJEIVA'		,VALORIVA			DECIMAL(14,2)		'$.VALORIVA'
		,GENCXP					BIT					'$.GENCXP'				,VLR_IMPUESTOS		DECIMAL(14,2)		'$.VLR_IMPUESTOS'
		,VLR_NETO				DECIMAL(14,2)		'$.VLR_NETO'			,CAMTER				BIT					'$.CAMTER'
		,IDTERCEROGENCXP		VARCHAR(20)			'$.IDTERCEROGENCXP'		,IDSERVICIO			VARCHAR(20)			'$.IDSERVICIO'
		,NODOCUMENTO			VARCHAR(20)			'$.NODOCUMENTO'			,OBSERVACION		VARCHAR(MAX)		'$.OBSERVACION'
		,PROCEDENCIA			VARCHAR(10)			'$.PROCEDENCIA'			,CUENTA_DB			VARCHAR(20)			'$.CUENTA_DB'
		,CUENTA_CR				VARCHAR(20)			'$.CUENTA_CR'			,CCOSTO				VARCHAR(20)			'$.CCOSTO'
		,NOREFERENCIA			VARCHAR(20)			'$.NOREFERENCIA'		,CODUNG				VARCHAR(20)			'$.CODUNG'
		,CODPRG					VARCHAR(20)			'$.CODPRG'				,USUARIO			VARCHAR(20)			'$.USUARIO'
		,SYS_COMPUTERNAME		VARCHAR(20)			'$.SYS_COMPUTERNAME'	,NROCOMPROBANTE		VARCHAR(20)			'$.NROCOMPROBANTE'
		,MASITEM				BIT					'$.MASITEM' )

		IF (SELECT ESTADO FROM FCXP WHERE  CNSFCXP= JSON_VALUE(@datoFCXPDBCR,'$.CNSFCXP')) = 'A'
         BEGIN
            INSERT INTO @TBLERRORES(ERROR) SELECT 'LA  CXP ESTA ANULADA O NO EXISTE'
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
         END
		 IF (SELECT COALESCE(SALDO,0) FROM FCXP WHERE  CNSFCXP= JSON_VALUE(@datoFCXPDBCR,'$.CNSFCXP')) <=0
         BEGIN
            INSERT INTO @TBLERRORES(ERROR) SELECT 'LA CXP NO TIENE SALDO PARA HACER NOTAS'
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
         END
			
		BEGIN TRY 
			IF UPPER(@PROCESO)='EDITAR'
			BEGIN
				--SELECT @CUENTADB=CUENTA, @TIPO = TIPO FROM FNT WHERE IDNOTA = JSON_VALUE(@datoFCXPDBCR,'$.IDNOTA') 
				--SELECT @CNSFCXP=CNSFCXP, @CUENTACR=CUECREDITO FROM FCXP WHERE  CNSFCXP= JSON_VALUE(@datoFCXPDBCR,'$.CNSFCXP')
				UPDATE FCXPDBCR SET
					IDNOTA = #datoFCXPDBCR.IDNOTA, TIPO = #datoFCXPDBCR.TIPO, DECRUCES = #datoFCXPDBCR.DECRUCES
					, FECHA = REPLACE(JSON_VALUE(@datoFCXPDBCR ,'$.FECHA'),'-',''), GIVA = #datoFCXPDBCR.GIVA, GIMPUESTOS = #datoFCXPDBCR.GIMPUESTOS
					, VALOR = #datoFCXPDBCR.VALOR, PORCENTAJEIVA = DBO.FNK_VALORVARIABLE('IDIVA'), VALORIVA = #datoFCXPDBCR.VALORIVA
					, GENCXP = #datoFCXPDBCR.GENCXP, VLR_IMPUESTOS = #datoFCXPDBCR.VLR_IMPUESTOS, VLR_NETO = #datoFCXPDBCR.VLR_NETO
					, CAMTER = #datoFCXPDBCR.CAMTER, IDTERCEROGENCXP = #datoFCXPDBCR.IDTERCEROGENCXP, IDSERVICIO = #datoFCXPDBCR.IDSERVICIO
					, NODOCUMENTO = #datoFCXPDBCR.NODOCUMENTO, OBSERVACION = #datoFCXPDBCR.OBSERVACION, PROCEDENCIA = #datoFCXPDBCR.PROCEDENCIA
					, CUENTA_DB = #datoFCXPDBCR.CUENTA_DB, CUENTA_CR = #datoFCXPDBCR.CUENTA_CR, CCOSTO = #datoFCXPDBCR.CCOSTO
					, NOREFERENCIA = #datoFCXPDBCR.NOREFERENCIA, CODUNG = #datoFCXPDBCR.CODUNG, CODPRG = #datoFCXPDBCR.CODPRG
					, USUARIO = #datoFCXPDBCR.USUARIO, SYS_COMPUTERNAME = #datoFCXPDBCR.SYS_COMPUTERNAME, NROCOMPROBANTE = #datoFCXPDBCR.NROCOMPROBANTE
					, MASITEM = COALESCE(#datoFCXPDBCR.MASITEM, 0)
				FROM FCXPDBCR INNER JOIN #datoFCXPDBCR ON FCXPDBCR.CNSFCXP = #datoFCXPDBCR.CNSFCXP AND FCXPDBCR.ITEM = #datoFCXPDBCR.ITEM

				IF COALESCE((SELECT MASITEM FROM #datoFCXPDBCR), 0) = 0
				BEGIN
					DELETE N
					FROM FCXPDNOT N
					INNER JOIN #datoFCXPDBCR B
						ON N.CNSFCXP = B.CNSFCXP
					WHERE N.ITEM_DBCR = B.ITEM
				END
			END
			IF UPPER(@PROCESO)='NUEVO'
			BEGIN
				--SELECT @CUENTADB=CUENTA, @TIPO = TIPO FROM FNT WHERE IDNOTA = JSON_VALUE(@datoFCXPDBCR,'$.IDNOTA') 
				SELECT @ITEM=COALESCE(MAX(ITEM),0)+1 FROM FCXPDBCR WHERE CNSFCXP= JSON_VALUE(@datoFCXPDBCR,'$.CNSFCXP')
				SELECT @CNSFCXP=CNSFCXP, @CUENTACR=CUECREDITO FROM FCXP WHERE  CNSFCXP= JSON_VALUE(@datoFCXPDBCR,'$.CNSFCXP')

				INSERT INTO FCXPDBCR (CNSFCXP,ITEM,IDNOTA,TIPO,DECRUCES,FECHA,GIVA ,GIMPUESTOS,VALOR,PORCENTAJEIVA,VALORIVA,GENCXP,VLR_IMPUESTOS,
            VLR_NETO	,CAMTER,IDTERCEROGENCXP	,IDSERVICIO,NODOCUMENTO	,OBSERVACION,PROCEDENCIA,CUENTA_DB	,CUENTA_CR	,CCOSTO,NOREFERENCIA	,CODUNG
            ,CODPRG ,USUARIO ,SYS_COMPUTERNAME	,NROCOMPROBANTE, ESTADO, MASITEM)
				SELECT #datoFCXPDBCR.CNSFCXP	,@ITEM,#datoFCXPDBCR.IDNOTA,#datoFCXPDBCR.TIPO ,#datoFCXPDBCR.DECRUCES,REPLACE(JSON_VALUE(@datoFCXPDBCR ,'$.FECHA'),'-','') 					
                   ,#datoFCXPDBCR.GIVA	,#datoFCXPDBCR.GIMPUESTOS	,#datoFCXPDBCR.VALOR	,DBO.FNK_VALORVARIABLE('IDIVA')	,#datoFCXPDBCR.VALORIVA	,#datoFCXPDBCR.GENCXP				
                   ,#datoFCXPDBCR.VLR_IMPUESTOS	,#datoFCXPDBCR.VLR_NETO	,#datoFCXPDBCR.CAMTER	,#datoFCXPDBCR.IDTERCEROGENCXP	,#datoFCXPDBCR.IDSERVICIO			,#datoFCXPDBCR.NODOCUMENTO		
                   ,#datoFCXPDBCR.OBSERVACION		,#datoFCXPDBCR.PROCEDENCIA		,#datoFCXPDBCR.CUENTA_DB		,#datoFCXPDBCR.CUENTA_CR		,#datoFCXPDBCR.CCOSTO				,#datoFCXPDBCR.NOREFERENCIA		
                   ,#datoFCXPDBCR.CODUNG				,#datoFCXPDBCR.CODPRG				,@USUARIO			,@SYS_COMPUTERNAME,#datoFCXPDBCR.NROCOMPROBANTE	, 'N', COALESCE(#datoFCXPDBCR.MASITEM, 0)
            FROM #datoFCXPDBCR
			END
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF EXISTS(SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' AS OK
		RETURN
	END
	IF @METODO IN ('CRUD_FCXPDBCR_2', 'CRUD_FCXPDBCR_2_MANUAL')
	BEGIN
		SELECT @datoFCXPDBCR =  datoFCXPDBCR, @CONSECUTIVO = CONSECUTIVO, @IMPUESTOS = IMPUESTOS, @DETALLE_VALORES = DETALLE_VALORES
	   FROM OPENJSON (@PARAMETROS)
	   WITH		 (
		datoFCXPDBCR		NVARCHAR(MAX) AS JSON
		,CONSECUTIVO		NVARCHAR(MAX) AS JSON
		,IMPUESTOS			NVARCHAR(MAX) AS JSON
		,DETALLE_VALORES	NVARCHAR(MAX) AS JSON
		)
		SELECT * INTO #CONSECUTIVO FROM  OPENJSON(@CONSECUTIVO)
		WITH (	CNSFCXP		VARCHAR(20)			'$.CNSFCXP'
				,ITEM		INT					'$.ITEM')

		SELECT * INTO #IMPUESTOS FROM  OPENJSON(@IMPUESTOS)
		WITH (	CNSFCXPI		VARCHAR(20)			'$.CNSFCXPI')

		SELECT * INTO #DETALLE_VALORES FROM OPENJSON(COALESCE(@DETALLE_VALORES, '[]'))
		WITH (
			CNSFCXP    VARCHAR(20)    '$.CNSFCXP',
			ITEM       INT            '$.ITEM',
			VALOR_DBCR DECIMAL(14,2)  '$.VALOR_DBCR'
		)

		SELECT @PROCESO = UPPER(LTRIM(RTRIM(ISNULL(JSON_VALUE(@datoFCXPDBCR,'$.PROCESO'), ''))))
		SELECT * INTO #datoFCXPDBCR_2 FROM  OPENJSON(@datoFCXPDBCR)
		WITH (
		CNSFCXP					VARCHAR(20)		'$.CNSFCXP'				,ITEM					INT				'$.ITEM'
		,IDNOTA					VARCHAR(20)		'$.IDNOTA'				,TIPO					VARCHAR(20)		'$.TIPO'
		,DECRUCES				INT				'$.DECRUCES'			,GIVA					BIT				'$.GIVA'
		,GIMPUESTOS				BIT				'$.GIMPUESTOS'			,VALOR					DECIMAL(14,2)	'$.VALOR'
		,PORCENTAJEIVA			DECIMAL(14,2)	'$.PORCENTAJEIVA'		,VALORIVA				DECIMAL(14,2)	'$.VALORIVA'
		,GENCXP					BIT				'$.GENCXP'				,VLR_IMPUESTOS			DECIMAL(14,2)	'$.VLR_IMPUESTOS'
		,VLR_NETO				DECIMAL(14,2)	'$.VLR_NETO'			,CAMTER					BIT				'$.CAMTER'
		,IDTERCEROGENCXP		VARCHAR(20)		'$.IDTERCEROGENCXP'		,IDSERVICIO				VARCHAR(20)		'$.IDSERVICIO'
		,NODOCUMENTO			VARCHAR(20)		'$.NODOCUMENTO'			,OBSERVACION			VARCHAR(MAX)	'$.OBSERVACION'
		,PROCEDENCIA			VARCHAR(10)		'$.PROCEDENCIA'			,CUENTA_DB				VARCHAR(20)		'$.CUENTA_DB'
		,CUENTA_CR				VARCHAR(20)		'$.CUENTA_CR'			,CCOSTO					VARCHAR(20)		'$.CCOSTO'
		,NOREFERENCIA			VARCHAR(20)		'$.NOREFERENCIA'		,CODUNG					VARCHAR(20)		'$.CODUNG'
		,CODPRG					VARCHAR(20)		'$.CODPRG'				,USUARIO				VARCHAR(20)		'$.USUARIO'
		,SYS_COMPUTERNAME		VARCHAR(20)		'$.SYS_COMPUTERNAME'	,NROCOMPROBANTE			VARCHAR(20)		'$.NROCOMPROBANTE'
		,TIPO_TOTAL				BIT				'$.TIPO_TOTAL'			,ITEMS					BIT				'$.ITEMS'
		,MASITEM				BIT				'$.MASITEM')
		
		IF (SELECT ESTADO FROM FCXP WHERE  CNSFCXP= JSON_VALUE(@datoFCXPDBCR,'$.CNSFCXP')) = 'A'
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'LA CXP ESTA ANULADA O NO EXISTE'
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		BEGIN TRY 
			IF UPPER(@PROCESO)='EDITAR'
			BEGIN
				IF EXISTS (
					SELECT 1
					FROM FCXPDBCR
					WHERE CNSFCXP = JSON_VALUE(@datoFCXPDBCR,'$.CNSFCXP')
						AND ITEM = CAST(JSON_VALUE(@datoFCXPDBCR,'$.ITEM') AS INT)
						AND COALESCE(CONTABILIZADA, 0) <> 0
				)
				BEGIN
					INSERT INTO @TBLERRORES(ERROR) SELECT 'La nota est? contabilizada y no se puede modificar.'
					SELECT 'KO' AS OK
					SELECT ERROR FROM @TBLERRORES
					RETURN
				END
				SELECT @CUENTADB=CUENTA, @TIPO = TIPO FROM FNT WHERE IDNOTA = JSON_VALUE(@datoFCXPDBCR,'$.IDNOTA') 
				SELECT @CNSFCXP=CNSFCXP, @CUENTACR=CUECREDITO FROM FCXP WHERE  CNSFCXP= JSON_VALUE(@datoFCXPDBCR,'$.CNSFCXP')
				SELECT @ITEM = COALESCE(
					TRY_CAST(JSON_VALUE(@datoFCXPDBCR, '$.ITEM') AS INT),
					(SELECT TOP 1 ITEM FROM #datoFCXPDBCR_2)
				)
				UPDATE FCXPDBCR SET
					IDNOTA = #datoFCXPDBCR_2.IDNOTA, TIPO = @TIPO, DECRUCES = #datoFCXPDBCR_2.DECRUCES
					, FECHA = REPLACE(JSON_VALUE(@datoFCXPDBCR ,'$.FECHA'),'-',''), GIVA = #datoFCXPDBCR_2.GIVA, GIMPUESTOS = #datoFCXPDBCR_2.GIMPUESTOS
					, VALOR = #datoFCXPDBCR_2.VALOR, PORCENTAJEIVA = DBO.FNK_VALORVARIABLE('IDIVA'), VALORIVA = #datoFCXPDBCR_2.VALORIVA
					, GENCXP = #datoFCXPDBCR_2.GENCXP, VLR_IMPUESTOS = #datoFCXPDBCR_2.VLR_IMPUESTOS, VLR_NETO = #datoFCXPDBCR_2.VLR_NETO
					, CAMTER = #datoFCXPDBCR_2.CAMTER, IDTERCEROGENCXP = #datoFCXPDBCR_2.IDTERCEROGENCXP, IDSERVICIO = #datoFCXPDBCR_2.IDSERVICIO
					, NODOCUMENTO = #datoFCXPDBCR_2.NODOCUMENTO, OBSERVACION = #datoFCXPDBCR_2.OBSERVACION, PROCEDENCIA = #datoFCXPDBCR_2.PROCEDENCIA
					, CUENTA_DB = @CUENTADB, CUENTA_CR = @CUENTACR, CCOSTO = #datoFCXPDBCR_2.CCOSTO, NOREFERENCIA = #datoFCXPDBCR_2.NOREFERENCIA
					, CODUNG = #datoFCXPDBCR_2.CODUNG, CODPRG = #datoFCXPDBCR_2.CODPRG, USUARIO = #datoFCXPDBCR_2.USUARIO, SYS_COMPUTERNAME = #datoFCXPDBCR_2.SYS_COMPUTERNAME
					, NROCOMPROBANTE = #datoFCXPDBCR_2.NROCOMPROBANTE
					, MASITEM = CASE
						WHEN @METODO = 'CRUD_FCXPDBCR_2_MANUAL'
							AND EXISTS(SELECT 1 FROM #DETALLE_VALORES WHERE COALESCE(VALOR_DBCR, 0) > 0)
							THEN CAST(1 AS BIT)
						ELSE COALESCE(#datoFCXPDBCR_2.MASITEM, 0)
					END
				FROM FCXPDBCR INNER JOIN #datoFCXPDBCR_2 ON FCXPDBCR.CNSFCXP = #datoFCXPDBCR_2.CNSFCXP AND FCXPDBCR.ITEM = #datoFCXPDBCR_2.ITEM

				IF COALESCE((
					SELECT CASE
						WHEN @METODO = 'CRUD_FCXPDBCR_2_MANUAL'
							AND EXISTS(SELECT 1 FROM #DETALLE_VALORES WHERE COALESCE(VALOR_DBCR, 0) > 0)
							THEN 1
						ELSE COALESCE(CAST(#datoFCXPDBCR_2.MASITEM AS INT), 0)
					END
					FROM #datoFCXPDBCR_2
				), 0) = 0
				BEGIN
					DELETE N
					FROM FCXPDNOT N
					WHERE N.CNSFCXP = @CNSFCXP
						AND N.ITEM_DBCR = @ITEM
				END
			END
			IF UPPER(@PROCESO)='NUEVO'
			BEGIN
				SELECT @CUENTADB=CUENTA, @TIPO = TIPO FROM FNT WHERE IDNOTA = JSON_VALUE(@datoFCXPDBCR,'$.IDNOTA') 
				SELECT @ITEM=COALESCE(MAX(ITEM),0)+1 FROM FCXPDBCR WHERE CNSFCXP= JSON_VALUE(@datoFCXPDBCR,'$.CNSFCXP')
				SELECT @CNSFCXP=CNSFCXP, @CUENTACR=CUECREDITO FROM FCXP WHERE  CNSFCXP= JSON_VALUE(@datoFCXPDBCR,'$.CNSFCXP')

				INSERT INTO FCXPDBCR (
					CNSFCXP, ITEM, IDNOTA, TIPO, DECRUCES, FECHA, GIVA, GIMPUESTOS, VALOR, PORCENTAJEIVA, VALORIVA, GENCXP, VLR_IMPUESTOS
					, VLR_NETO, CAMTER, IDTERCEROGENCXP, IDSERVICIO, NODOCUMENTO, OBSERVACION, PROCEDENCIA, CUENTA_DB, CUENTA_CR, CCOSTO, NOREFERENCIA
					, CODUNG, CODPRG, USUARIO, SYS_COMPUTERNAME, NROCOMPROBANTE, ESTADO, ORIGEN, TIPO_TOTAL, MASITEM
				)
				SELECT
					#datoFCXPDBCR_2.CNSFCXP, @ITEM, #datoFCXPDBCR_2.IDNOTA, @TIPO, #datoFCXPDBCR_2.DECRUCES
					, REPLACE(JSON_VALUE(@datoFCXPDBCR ,'$.FECHA'),'-',''), #datoFCXPDBCR_2.GIVA, #datoFCXPDBCR_2.GIMPUESTOS, #datoFCXPDBCR_2.VALOR
					, #datoFCXPDBCR_2.PORCENTAJEIVA, #datoFCXPDBCR_2.VALORIVA, #datoFCXPDBCR_2.GENCXP, #datoFCXPDBCR_2.VLR_IMPUESTOS, #datoFCXPDBCR_2.VLR_NETO
					, #datoFCXPDBCR_2.CAMTER, #datoFCXPDBCR_2.IDTERCEROGENCXP, #datoFCXPDBCR_2.IDSERVICIO, #datoFCXPDBCR_2.NODOCUMENTO, #datoFCXPDBCR_2.OBSERVACION
					, #datoFCXPDBCR_2.PROCEDENCIA, @CUENTADB, @CUENTACR, #datoFCXPDBCR_2.CCOSTO, #datoFCXPDBCR_2.NOREFERENCIA, #datoFCXPDBCR_2.CODUNG, #datoFCXPDBCR_2.CODPRG
					, @USUARIO, @SYS_COMPUTERNAME, #datoFCXPDBCR_2.NROCOMPROBANTE, 'N', 'QUASAR', #datoFCXPDBCR_2.TIPO_TOTAL
					, CASE WHEN @METODO = 'CRUD_FCXPDBCR_2_MANUAL' THEN CAST(1 AS BIT) ELSE COALESCE(#datoFCXPDBCR_2.MASITEM, 0) END
				FROM #datoFCXPDBCR_2
			END

			-- Detalle por ?tem (FCXPDNOT): NUEVO y EDITAR.
			-- ITEMS en JSON a veces no mapea bien a BIT en #datoFCXPDBCR_2; CRUD_FCXPDBCR_2_MANUAL es siempre masivo por ?tem.
			IF @PROCESO IN ('NUEVO', 'EDITAR')
				AND (SELECT COUNT(*) FROM #CONSECUTIVO)>0
				AND (SELECT COALESCE(#datoFCXPDBCR_2.TIPO_TOTAL,0) FROM #datoFCXPDBCR_2 ) = 0 
				AND (
					COALESCE((
						SELECT CASE
							WHEN @METODO = 'CRUD_FCXPDBCR_2_MANUAL'
								AND EXISTS(SELECT 1 FROM #DETALLE_VALORES WHERE COALESCE(VALOR_DBCR, 0) > 0)
								THEN 1
							ELSE COALESCE(CAST(#datoFCXPDBCR_2.MASITEM AS INT), 0)
						END
						FROM #datoFCXPDBCR_2
					), 0) = 1
					OR (SELECT COALESCE(CAST(#datoFCXPDBCR_2.ITEMS AS INT), 0) FROM #datoFCXPDBCR_2) = 1
					OR @METODO = 'CRUD_FCXPDBCR_2_MANUAL'
					OR LOWER(LTRIM(RTRIM(ISNULL(JSON_VALUE(@datoFCXPDBCR, '$.ITEMS'), '')))) IN ('true', '1')
				)
			BEGIN
				-- Evita arrastres/duplicados al reintentar guardado de la misma nota por ?tem.
				DELETE N
				FROM FCXPDNOT N
				INNER JOIN #datoFCXPDBCR_2 B
					ON N.CNSFCXP = B.CNSFCXP
				WHERE N.ITEM_DBCR = @ITEM;

				IF @METODO = 'CRUD_FCXPDBCR_2_MANUAL' AND EXISTS(SELECT 1 FROM #DETALLE_VALORES WHERE COALESCE(VALOR_DBCR, 0) > 0)
				BEGIN
