CREATE OR ALTER PROCEDURE DBO.SPK_ANTICIPO_LEG_CXP
@CNSFCOM    VARCHAR(20),
@CNSANT     VARCHAR(20),
@COMPANIA   VARCHAR(2),
@USUARIO    VARCHAR(12),
@SEDE       VARCHAR(5)
WITH ENCRYPTION
AS      
DECLARE @CNSFCXP VARCHAR(20)
DECLARE @VEZ     INT
DECLARE @CIUDAD  VARCHAR(5)
--
DECLARE @IDTERCERO_CUR     VARCHAR(20)
DECLARE @IDSERVICIO_CUR    VARCHAR(20)
DECLARE @CANTIDAD_CUR      DECIMAL(14,2)
DECLARE @VALOR_CUR         DECIMAL(14,2)
DECLARE @VLR_DESCUENTO_CUR DECIMAL(14,2)  
DECLARE @VLR_IVA_CUR       DECIMAL(14,2)
DECLARE @VLR_NETO_CUR      DECIMAL(14,2)
DECLARE @PREFIJO_CUR       VARCHAR(6)
DECLARE @CCOSTO_CUR        VARCHAR(20)
DECLARE @IDAREA_CUR        VARCHAR(20)
DECLARE @IDCLASEIMP_CUR    VARCHAR(2)
DECLARE @ITEM              INT
DECLARE @CODUNG            VARCHAR(5)
DECLARE @CODPRG            VARCHAR(20)
DECLARE @IDIMPUESTO        VARCHAR(10)
DECLARE @IDCLASE           VARCHAR(10)
DECLARE @DECONSUMO         SMALLINT
DECLARE @ITEM_FIMPDV       SMALLINT
DECLARE @CUENTA_IVA        VARCHAR(16)
DECLARE @FECHA_FAC         DATETIME
DECLARE @NOREFERENCIA      VARCHAR(20)
DECLARE @VLR_NETO          DECIMAL(14,2)
DECLARE @F_FACTURAREF      DATETIME
DECLARE @VLR_DESCUENTO     DECIMAL(14,2)  
DECLARE @VALOR             DECIMAL(14,2)
DECLARE @F_VENCE           DATETIME
DECLARE @VLR_IVA           DECIMAL(14,2)
DECLARE @CNSFCOT           VARCHAR(20)
DECLARE @VLRABONO          DECIMAL(14,2)
DECLARE @NROCOMPROBANTE    VARCHAR(20)
DECLARE @CUENTANT          VARCHAR(20)
DECLARE @CUECREDITO        VARCHAR(20)
DECLARE @CNSFCXPANT        VARCHAR(20)
BEGIN
   SELECT @VEZ = COUNT(*),@VLRABONO=  SUM(VALOR) FROM FCXP WHERE PROCEDENCIA = 'Anticipos' AND CNSFCOM = @CNSFCOM
   SELECT @VEZ = @VEZ + 1

   SELECT @CIUDAD = CIUDAD FROM SED WHERE IDSEDE = @SEDE

   SELECT @VALOR =  VALOR_LEG,
   --@VLRABONO=VALORCXP, 
   @NOREFERENCIA = NOREFERENCIA, @FECHA_FAC = F_FACTURAREF, @F_VENCE = F_FACTURAREF,
          @CNSFCXPANT=ANT.CNSFCXP,@CUENTANT=TANT.CUEDEBITO,@CNSFCXP=ANT.CNSFCXP
   FROM   ANT INNER JOIN FCOM ON ANT.CNSFCOM=FCOM.CNSFCOM
              INNER JOIN TANT ON FCOM.TIPOANTICIPO=TANT.TIPOANTICIPO
   WHERE  CNSANT = @CNSANT

   IF @VALOR - @VLRABONO>0
   BEGIN
      EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@FCXPSR', @CNSFCXP OUTPUT  
      SELECT @CNSFCXP = @SEDE + 'SR' + REPLACE(SPACE(6 - LEN(@CNSFCXP))+LTRIM(RTRIM(@CNSFCXP)),SPACE(1),0) 
   
      PRINT '@CNSFCXP == '+@CNSFCXP    

      INSERT INTO FCXP (CNSFCXP, FECHA, CNSFCOM, IDTERCERO, NOREFERENCIA, F_FACTURAREF, F_VENCE, VALOR, ESTADO,
                        F_CANCELADO, USUARIO, TIPOCXP, PROCEDENCIA, OBSERVACION, COMPANIA, SYS_ComputerName,
                        USUARIOMOD, FECHAMOD, NUMCUOTA, MARCACONT, CONTABILIZADA, NROCOMPROBANTE, SALDO,
                        IDCLASEIMP, VLR_DESCUENTO, VLR_IVA, VLR_NETO, VLR_IMPUESTOS, SALDO_IMPUESTO, 
                        VLR_NOTASDEBITO, VLR_COMISION, VLR_GLOSAS, VLR_FLETE, CUEDEBITO, CUECREDITO,
                        CNSFCXPPM, MODALIDAD, SUBSIDIO, IDCONTRATO, VLR_NOTASCREDITO ,VLR_ABONOS, IDSEDE,
                        PERIODO_ANO, PERIODO_MES, CODUNG, CODPRG, CIUDAD, ENPRESUPUESTO, SEAMORTIZA, NUMPERAMORT, 
                        IDPROPIETARIO, FACCONTROL, USUARIOMARCA, FECHAMARCA)
      SELECT @CNSFCXP, DBO.FNK_FECHA_SIN_MLS( GETDATE()), @CNSFCOM, IDTERCERO, 
             @NOREFERENCIA, @FECHA_FAC, @F_VENCE, FCOM.VR_ANTESIVA, 'N', NULL, @USUARIO,
             RTRIM(LTRIM(DBO.FNK_VALORVARIABLE('IDTIPOCXP_DEFAULT'))), 'Servicios', 'Legalizaci�n:'+RTRIM(OBSERVACION), 
             @COMPANIA, HOST_NAME(), 
             NULL, NULL, 0, 0, 0 , '', 0, 
			 NULL, 0, 0, 0, 0, 0, 0, 0, 0, 0, NULL, TANT.CUEDEBITO, NULL, 'Evento', 'Total',
             NULL, 0, 0, @SEDE, NULL, NULL, '', '', @CIUDAD, 0, 0, 0, NULL, NULL, NULL, NULL       
      FROM   FCOM LEFT JOIN TANT ON FCOM.TIPOANTICIPO = TANT.TIPOANTICIPO
      WHERE  CNSFCOM = @CNSFCOM 

      --GENERAR FCXPD
      DECLARE CUR_FCOM CURSOR FOR
      SELECT FCOMD.IDARTICULO, FCOMD.CANTIDAD, FCOMD.VR_ANTESIVA, FCOMD.VR_DESCUENTO, FCOMD.IVA, FCOMD.VR_TOTAL,
             FCTSERD.IDTIPOSER,FCOM.CCOSTO,FCOM.IDAREA,NULL, FCOM.CODUNG, FCOM.CODPRG, FCOMD.IDIMPUESTO, FCOMD.IDCLASE,
             FCOM.DECONSUMO, ISNULL(FCOM.FECHA, GETDATE()) 
      FROM   FCOM INNER JOIN FCOMD   ON FCOM.CNSFCOM     = FCOMD.CNSFCOM 
                   LEFT JOIN FCTSERD ON FCOMD.IDARTICULO = FCTSERD.IDSERVICIO 
                                    AND FCOMD.TIPO       = 'Servicios'
      WHERE  FCOM.CNSFCOM = @CNSFCOM
   
      OPEN CUR_FCOM
   
      FETCH NEXT FROM CUR_FCOM
      INTO @IDSERVICIO_CUR, @CANTIDAD_CUR, @VALOR_CUR, @VLR_DESCUENTO_CUR, @VLR_IVA_CUR, @VLR_NETO_CUR,
	        @PREFIJO_CUR, @CCOSTO_CUR, @IDAREA_CUR, @IDCLASEIMP_CUR, @CODUNG, @CODPRG, @IDIMPUESTO, @IDCLASE, 
           @DECONSUMO, @FECHA_FAC
      SET  @ITEM=1
      WHILE @@FETCH_STATUS = 0
      BEGIN      
         SELECT @ITEM_FIMPDV = ITEM, @CUENTA_IVA = CUENTA
         FROM   FNK_VALOR_IMPUESTO(@IDIMPUESTO, @IDCLASE, @FECHA_FAC, @VALOR_CUR)
      
         INSERT INTO FCXPD (CNSFCXP,ITEM,IDSERVICIO,CANTIDAD,VALOR,VLR_DESCUENTO,VLR_IVA,VLR_NETO,ESTADO,
                            N_PRESUP,ITEM_PRESUP,IDCLASEIMP,PREFIJO,CCOSTO,IDAREA,VLR_GLOSAS,
                            CUENTA_SER, CODUNG, CODPRG, PROCEDENCIA, IDIMPUESTO, IDCLASE, ITEM_FIMPDV, CUENTA_IVA ) 
         SELECT @CNSFCXP,@ITEM,@IDSERVICIO_CUR,@CANTIDAD_CUR,@VALOR_CUR,@VLR_DESCUENTO_CUR,@VLR_IVA_CUR, @VLR_NETO_CUR, 'P', 
                @CNSFCOM,0,@IDCLASEIMP_CUR,@PREFIJO_CUR,@CCOSTO_CUR,@IDAREA_CUR,0,
                DBO.FNK_CUENTA_KMCOM(DBO.FNK_VALORVARIABLE('IDMODELOCONTABLE'),'CXP_SERVICIOS','DB',@PREFIJO_CUR, @IDAREA_CUR,@CCOSTO_CUR,'P',''), 
                @CODUNG, @CODPRG, 'Servicios', @IDIMPUESTO, @IDCLASE, CASE @DECONSUMO WHEN 1 THEN NULL
                                                                                      ELSE @ITEM_FIMPDV
                                                                      END,
                CASE @DECONSUMO WHEN 1 THEN NULL
                                ELSE @CUENTA_IVA
                END      
         SET @ITEM=@ITEM+1
         FETCH NEXT FROM CUR_FCOM
         INTO	@IDSERVICIO_CUR,@CANTIDAD_CUR,@VALOR_CUR,@VLR_DESCUENTO_CUR,@VLR_IVA_CUR,@VLR_NETO_CUR,
               @PREFIJO_CUR,@CCOSTO_CUR,@IDAREA_CUR,@IDCLASEIMP_CUR, @CODUNG, @CODPRG, @IDIMPUESTO, @IDCLASE, 
               @DECONSUMO, @FECHA_FAC
      END
      CLOSE CUR_FCOM 
      DEALLOCATE CUR_FCOM
   
	  IF (SELECT SUM(VLR_NETO) FROM FCXPD WHERE CNSFCXP=@CNSFCXP)<@VALOR 
		AND (SELECT COUNT(1) FROM FCXPD WHERE CNSFCXP=@CNSFCXP)=1
	  BEGIN
		 UPDATE FCXPD SET VALOR=@VALOR, VLR_NETO=@VALOR WHERE CNSFCXP=@CNSFCXP
	  END

      SELECT @VLR_DESCUENTO = SUM(VLR_DESCUENTO), @VLR_IVA = SUM(VLR_IVA), @VLR_NETO=SUM(VLR_NETO)
      FROM   FCXPD WHERE CNSFCXP = @CNSFCXP
   
      UPDATE FCXP SET CNSFCOM  = @CNSFCOM,
            	  	    VALOR    = @VALOR,
            		    SALDO    = @VALOR-@VLRABONO,
            		    VLR_DESCUENTO=@VLR_DESCUENTO,
            		    VLR_IVA  = @VLR_IVA,
            		    VLR_NETO = @VLR_NETO,
            		    VLR_ABONOS=@VLRABONO
      WHERE  CNSFCXP = @CNSFCXP
      PRINT 'ACTUALIZAMOS ANT'
   END
   UPDATE FCOM SET ENCXP = 1, ESTADO = 'I' WHERE CNSFCOM=@CNSFCOM 
   UPDATE ANT SET ESTADO='L', CNSFCXP= CASE WHEN COALESCE(CNSFCXP, '') = '' THEN @CNSFCXP ELSE CNSFCXP END,IDRESPONSABLE=@USUARIO WHERE CNSANT=@CNSANT
   -- 20260312 - STORRES - nO DEBE CAMBIAR LA FCXP YA QUE ESTAS CUENTAS SON LAS QUE SE LEGALIZAN AL FINAL CON EL PROCEOS DE CONTABILIZACION 
   --IF (SELECT COALESCE(CUECREDITO,'') FROM FCXP WHERE CNSFCXP=@CNSFCXPANT)<>@CUENTANT 
   --BEGIN 
   --   UPDATE FCXP SET CUECREDITO=@CUENTANT WHERE CNSFCXP=@CNSFCXPANT
   --END
   -- 20260312 - STORRES - nO DEBE CAMBIAR LA FCXP YA QUE ESTAS CUENTAS SON LAS QUE SE LEGALIZAN AL FINAL CON EL PROCEOS DE CONTABILIZACION 

   IF DBO.FNK_VALORVARIABLE('GENANTIDESDEORDENSER')='SI' 
   BEGIN 
      PRINT 'VOY A CONTABILIZAR EL ANTICIPO'
      EXEC SPK_NC_CONTAB_ANTICIPO @CNSANT,@CNSFCOM,@SEDE,@USUARIO,@NROCOMPROBANTE
   END
   EXEC SPK_CALCULOVALORESCXP @CNSFCXP
END
