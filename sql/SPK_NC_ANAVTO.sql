BEGIN
   DROP PROCEDURE SPK_NC_ANAVTO
END

GO
CREATE PROCEDURE DBO.SPK_NC_ANAVTO
@COMPANIA      VARCHAR(2),
@ANO           VARCHAR(4),
@MES           INT,
@CNS           VARCHAR(20),
@CUENTA_INI    VARCHAR(16),
@CUENTA_FIN    VARCHAR(16),
@IDTERCERO     VARCHAR(20),
@REPORTE       VARCHAR(12),
@CCOSTO        VARCHAR(20),
@CLASIFICADOR  VARCHAR(20),
@DPTOINI       VARCHAR(2)
WITH ENCRYPTION
AS
DECLARE @CUENTA_CJU VARCHAR(20)
DECLARE @CUENTA_GLO VARCHAR(20)
BEGIN
   --SET @CUENTA_CJU = '130563'
   --SET @CUENTA_GLO = '130562'
   IF @IDTERCERO = ''
   BEGIN
      SET @IDTERCERO = NULL 
   END
   IF @CCOSTO = ''
   BEGIN
      SET @CCOSTO = NULL 
   END
   IF @DPTOINI = ''
   BEGIN
      SET @DPTOINI = NULL
   END
   IF @CUENTA_INI = ''
   BEGIN
      SELECT @CUENTA_INI = NULL
   END 
   IF @CUENTA_FIN = ''
   BEGIN
      SELECT @CUENTA_FIN = NULL
   END
   IF @REPORTE='CXC'
   BEGIN        
      --SELECT COMPANIA, CUENTA INTO #T 
      --FROM CUE 
      --WHERE CUENTA  >= (CASE WHEN @CUENTA_INI='' THEN '1' ELSE @CUENTA_INI END) 
      --AND   CUENTA  <= (CASE WHEN @CUENTA_FIN='' THEN 'zzzzzzzzzzzzzzzz' ELSE @CUENTA_FIN END) 
      --AND   COMPANIA = @COMPANIA 
      --AND   CLASE    = 'CXC'
      
      IF (DBO.FNK_VALORVARIABLE('IDTIPOCXP_DEFAULT') ) = 'IPS'
      BEGIN
         INSERT INTO RPDX2 (CNS,CNS1,STRINGMEDIO1,CNS2,STRINGMEDIO2,CNS3,FECHA1,FECHA2,CANTIDAD,VALOR1,
                            VALOR2,VALOR3,VALOR4,VALOR5,VALOR6,VALOR7,VALOR8,VALOR9,
                            VALOR10,VALOR11) --,ID1,ID2)
         SELECT @CNS, F.CUENTA,NOMCUENTA, IDTERCERO, LEFT(F.RAZONSOCIAL,100) RAZONSOCIAL, N_FACTURA,F_FACTURA,F_VENCE,DIASVENCE,SUM(SALDO),
                SUM(D0_30), SUM(D31_60), SUM(D61_90), SUM(D91_120), SUM(D91_180), SUM(D121_150), SUM(D151_180), SUM(D181_360), SUM(D361_MAS),
                SUM(DM1_30+DM31_60+DM61_90+DM91_120+DM121_150+DM151_180+DM181_360+DMENOS_361)               
         FROM   FNK_NC_ANAVTO_CONTAB(@ANO,@MES, 'CXC') F 
         WHERE  F.SALDO <> 0 
         AND    F.IDTERCERO =  ISNULL(@IDTERCERO, F.IDTERCERO) 
         AND    F.CUENTA    >= COALESCE(@CUENTA_INI, F.CUENTA)
         AND    F.CUENTA    <= COALESCE(@CUENTA_FIN, F.CUENTA)
         GROUP BY F.CUENTA, NOMCUENTA, IDTERCERO, LEFT(F.RAZONSOCIAL,100), N_FACTURA, F_FACTURA, F_VENCE, DIASVENCE
                  --CIU.CIUDAD, CIU.DPTO
         HAVING SUM(SALDO)<>0
         ORDER BY F.CUENTA, RAZONSOCIAL, N_FACTURA
      END
      ELSE
      BEGIN
         INSERT INTO RPDX2 (CNS,CNS1,STRINGMEDIO1,CNS2,STRINGMEDIO2,CNS3,FECHA1,FECHA2,CANTIDAD,VALOR1,
                            VALOR2,VALOR3,VALOR4,VALOR5,VALOR6,VALOR7,VALOR8,VALOR9,
                            VALOR10,VALOR11,ID1,ID2)
         SELECT @CNS,F.CUENTA,NOMCUENTA,IDTERCERO,LEFT(F.RAZONSOCIAL,100) RAZONSOCIAL,N_FACTURA,F_FACTURA,F_VENCE,DIASVENCE,SUM(SALDO),
                SUM(D0_30), SUM(D31_60), SUM(D61_90), SUM(D91_120),SUM(D91_180), SUM(D121_150), SUM(D151_180), SUM(D181_360), SUM(D361_MAS),
                SUM(DM1_30+DM31_60+DM61_90+DM91_120+DM121_150+DM151_180+DM181_360+DMENOS_361),
                ISNULL(CIU.CIUDAD,''), ISNULL(CIU.DPTO,'')
         FROM FNK_ANAVTO_CONTAB(@COMPANIA,@ANO,@MES,'CXC') F LEFT JOIN  CEN ON F.CCOSTO   = CEN.CCOSTO 
                                                             LEFT JOIN  CIU ON CEN.CIUDAD = CIU.CIUDAD
         WHERE F.SALDO <> 0 
         AND   F.IDTERCERO = ISNULL(@IDTERCERO, F.IDTERCERO) 
         AND   F.CCOSTO    = ISNULL(@CCOSTO,F.CCOSTO)
         AND    F.CUENTA    >= COALESCE(@CUENTA_INI, F.CUENTA)
         AND    F.CUENTA    <= COALESCE(@CUENTA_FIN, F.CUENTA)
         GROUP BY F.CUENTA, NOMCUENTA, IDTERCERO, LEFT(F.RAZONSOCIAL,100), N_FACTURA, F_FACTURA, F_VENCE, DIASVENCE,
                  CIU.CIUDAD, CIU.DPTO
         HAVING SUM(SALDO)<>0
         ORDER BY F.CUENTA, RAZONSOCIAL, N_FACTURA
      END
   END
   ELSE
   IF @REPORTE='CXP' OR @REPORTE='HCXP'
   BEGIN
      -- BEGIN:JEDM001   08/ENE/2005
      IF @CLASIFICADOR = 'IPS'
      BEGIN
         PRINT 'CLASIFICADOR=' + @CLASIFICADOR
         INSERT INTO RPDX2 (CNS,CNS1,STRINGMEDIO1,CNS2,STRINGMEDIO2,CNS3,FECHA1,FECHA2,CANTIDAD,VALOR1,
                            VALOR2,VALOR3,VALOR4,VALOR5,VALOR6,VALOR7,VALOR8,VALOR9,VALOR10,VALOR11,ID1,ID2)
         SELECT @CNS,F.CUENTA,F.NOMCUENTA,F.IDTERCERO,LEFT(F.RAZONSOCIAL,100) RAZONSOCIAL,F.N_FACTURA,F.F_FACTURA,F.F_VENCE,F.DIASVENCE,SUM(F.SALDO),
                SUM(D0_30), SUM(D31_60), SUM(D61_90), SUM(D91_120), SUM(D91_180), SUM(D121_150), SUM(D151_180), SUM(D181_360), SUM(D361_MAS),
                SUM(DM1_30+DM31_60+DM61_90+DM91_120+DM121_150+DM151_180+DM181_360+DMENOS_361),
                ISNULL(CIU.CIUDAD,''), ISNULL(CIU.DPTO,'')
         FROM   DBO.FNK_NC_ANAVTO_CONTAB(@ANO, @MES,'CXP') F LEFT  JOIN CEN   ON F.CCOSTO        = CEN.CCOSTO 
                                                             LEFT  JOIN CIU   ON CEN.CIUDAD      = CIU.CIUDAD
         WHERE  F.SALDO    <> 0 
         AND    F.IDTERCERO = ISNULL(@IDTERCERO,F.IDTERCERO) 
         AND    F.CCOSTO    = ISNULL(@CCOSTO,F.CCOSTO)
         AND    F.CUENTA    >= COALESCE(@CUENTA_INI, F.CUENTA)
         AND    F.CUENTA    <= COALESCE(@CUENTA_FIN, F.CUENTA)
         GROUP BY F.CUENTA, F.NOMCUENTA, F.IDTERCERO, LEFT(F.RAZONSOCIAL,100), F.N_FACTURA, F.F_FACTURA, F.F_VENCE, F.DIASVENCE,
                  CIU.CIUDAD, CIU.DPTO
         HAVING SUM(SALDO)<>0
         ORDER BY F.CUENTA, RAZONSOCIAL, N_FACTURA
      END
      ELSE
      BEGIN    
         PRINT 'CLASIFICADOR=' + @CLASIFICADOR
         
         INSERT INTO RPDX2 (CNS, CNS1, STRINGMEDIO1, CNS2, STRINGMEDIO2, CNS3, FECHA1, FECHA2, CANTIDAD, VALOR1,
                            VALOR2, VALOR3, VALOR4, VALOR5, VALOR6, VALOR7, VALOR8, VALOR9, VALOR10 ,VALOR11, ID1, ID2)
         SELECT @CNS, F.CUENTA, F.NOMCUENTA, F.IDTERCERO, LEFT(F.RAZONSOCIAL,100) RAZONSOCIAL, F.N_FACTURA, F.F_FACTURA, F.F_VENCE, F.DIASVENCE, SUM(F.SALDO),
                SUM(D0_30), SUM(D31_60), SUM(D61_90), SUM(D91_120), SUM(D91_180), SUM(D121_150), SUM(D151_180), SUM(D181_360), SUM(D361_MAS),
                SUM(DM1_30+DM31_60+DM61_90+DM91_120+DM121_150+DM151_180+DM181_360+DMENOS_361)
                ,ISNULL(CIU.CIUDAD,''), ISNULL(CIU.DPTO,'')
         FROM   DBO.FNK_NC_ANAVTO_CONTAB(@ANO,@MES,'CXP') F LEFT JOIN CEN  ON F.CCOSTO   = CEN.CCOSTO 
                                                                LEFT JOIN CIU  ON CEN.CIUDAD = CIU.CIUDAD
         WHERE  F.SALDO     <> 0 
         AND    F.IDTERCERO = CASE WHEN ISNULL(@IDTERCERO,'') <> '' THEN @IDTERCERO ELSE F.IDTERCERO END
         AND    F.CCOSTO    = CASE WHEN ISNULL(@CCOSTO,'') <> '' THEN @CCOSTO ELSE F.CCOSTO END
         AND    F.CUENTA    >= COALESCE(@CUENTA_INI, F.CUENTA)
         AND    F.CUENTA    <= COALESCE(@CUENTA_FIN, F.CUENTA)
         AND    ISNULL(CIU.DPTO,'')    = CASE WHEN ISNULL(@DPTOINI,'') <> '' THEN ISNULL(@DPTOINI,'') ELSE ISNULL(CIU.DPTO,'') END
         GROUP BY F.CUENTA,F.NOMCUENTA,F.IDTERCERO,LEFT(F.RAZONSOCIAL,100),F.N_FACTURA,F.F_FACTURA,F.F_VENCE,F.DIASVENCE
                 , CIU.CIUDAD, CIU.DPTO
         HAVING SUM(SALDO)<>0
         ORDER BY F.CUENTA, RAZONSOCIAL, N_FACTURA
      END
      -- END:JEDM001   08/ENE/2005
   END
   ELSE
   IF @REPORTE='EMCXP'
   BEGIN
      PRINT 'REPORTE='+@REPORTE
      SELECT COMPANIA, CUENTA INTO #Z 
      FROM CUE 
      WHERE CUENTA >= (CASE WHEN @CUENTA_INI='' THEN '1' ELSE @CUENTA_INI END) AND
            CUENTA <= (CASE WHEN @CUENTA_FIN='' THEN 'zzzzzzzzzzzzzzzz' ELSE @CUENTA_FIN END) AND
            COMPANIA=@COMPANIA AND CLASE='CXP'
      
      INSERT INTO RPDX2 (CNS, CNS1, STRINGMEDIO1, CNS2, STRINGMEDIO2, CNS3, FECHA1, FECHA2, CANTIDAD, VALOR1,
                       VALOR2, VALOR3, VALOR4, VALOR5, VALOR6,VALOR7, VALOR8, VALOR9, VALOR10, VALOR11, ID2)
      SELECT @CNS,NULL,NULL,F.IDTERCERO,LEFT(F.RAZONSOCIAL,100),NULL,NULL,NULL,NULL,NULL,
             SUM(DM1_30), SUM(DM31_60), SUM(DM61_90), SUM(DM91_120+DM121_150+DM151_180+DM181_360+DMENOS_361), 
             SUM(DM1_30+DM31_60+DM61_90+DM91_120+DM121_150+DM151_180+DM181_360+DMENOS_361),
             SUM(D0_30), SUM(D31_60), SUM(D61_90+D91_120+D121_150+D151_180+D181_360+D361_MAS), 
             SUM(D0_30+D31_60+D61_90+D91_120+D121_150+D151_180+D181_360+D361_MAS),
             SUM(DM1_30+DM31_60+DM61_90+DM91_120+DM121_150+DM151_180+DM181_360+DMENOS_361+D0_30+D31_60+D61_90+D91_120+D121_150+D151_180+D181_360+D361_MAS),
             ISNULL(CIU.DPTO,'')
      FROM   FNK_ANAVTO_CONTAB(@COMPANIA,@ANO,@MES,'CXP') F INNER JOIN (SELECT COMPANIA, CUENTA FROM #Z) T ON F.CUENTA = T.CUENTA 
                                                             LEFT JOIN  CEN ON F.CCOSTO = CEN.CCOSTO AND T.COMPANIA = CEN.COMPANIA 
                                                             LEFT JOIN  CIU ON CEN.CIUDAD = CIU.CIUDAD
      WHERE  F.SALDO<>0
      AND    F.IDTERCERO = ISNULL(@IDTERCERO,F.IDTERCERO)
      AND    F.CCOSTO = ISNULL(@CCOSTO,F.CCOSTO)
      AND    F.CUENTA    >= COALESCE(@CUENTA_INI, F.CUENTA)
      AND    F.CUENTA    <= COALESCE(@CUENTA_FIN, F.CUENTA)
      GROUP BY F.IDTERCERO, LEFT(F.RAZONSOCIAL,100), CIU.DPTO
      HAVING SUM(DM1_30+DM31_60+DM61_90+DM91_120+DM121_150+DM151_180+DM181_360+DMENOS_361+D0_30+D31_60+D61_90+D91_120+D121_150+D151_180+D181_360+D361_MAS)<>0
   END
   ELSE
   -- Cartera con Cobro Juridico y Glosas
   IF @REPORTE='CXCCJG'
   BEGIN
      PRINT 'REPORTE='+@REPORTE
      SELECT CUENTA INTO #T_CXCCJG 
      FROM CUE 
      WHERE CUENTA >= (CASE WHEN @CUENTA_INI='' THEN '1' ELSE @CUENTA_INI END) AND
            CUENTA <= (CASE WHEN @CUENTA_FIN='' THEN 'zzzzzzzzzzzzzzzz' ELSE @CUENTA_FIN END) AND
            COMPANIA=@COMPANIA AND CLASE='CXC'
      
      INSERT INTO RPDX2(CNS, CNS2, STRINGMEDIO2, CNS3, VALOR1, VALOR2, VALOR3, VALOR4, VALOR5)
      SELECT CNS, IDTERCERO, RAZONSOCIAL, N_FACTURA, SUM(SALDO), SUM(COBROJURIDICO), SUM(GLOSAS), SUM(PORRADICAR), SUM(RADICADO)
      FROM (SELECT CNS=@CNS, X.IDTERCERO, LEFT(TER.RAZONSOCIAL,100) RAZONSOCIAL, X.N_FACTURA, 
            SALDO         = CASE WHEN X.CUENTA<>@CUENTA_CJU AND X.CUENTA<>@CUENTA_GLO THEN SUM(X.SALDO) ELSE 0 END, 
            COBROJURIDICO = CASE WHEN @CUENTA_CJU = X.CUENTA THEN SUM(X.SALDO) ELSE 0 END,
            GLOSAS        = CASE WHEN @CUENTA_GLO = X.CUENTA THEN SUM(X.SALDO) ELSE 0 END,
            PORRADICAR    = CASE WHEN ISNULL(FCXC.INDRECIBIDO,0) = 0 THEN SUM(X.SALDO) ELSE 0 END,
            RADICADO      = CASE WHEN ISNULL(FCXC.INDRECIBIDO,0) = 1 THEN SUM(X.SALDO) ELSE 0 END
            FROM (SELECT CUENTA, IDTERCERO, N_FACTURA, CCOSTO, 
                  SALDO = CASE @MES 
                            WHEN 1 THEN SF01
                            WHEN 2 THEN SF02
                            WHEN 3 THEN SF03
                            WHEN 4 THEN SF04
                            WHEN 5 THEN SF05
                            WHEN 6 THEN SF06
                            WHEN 7 THEN SF07
                            WHEN 8 THEN SF08
                            WHEN 9 THEN SF09
                            WHEN 10 THEN SF10
                            WHEN 11 THEN SF11
                            WHEN 12 THEN SF12
                           END
                  FROM VWK_SXT WHERE ANO=@ANO) X LEFT JOIN
                 FCXC ON X.IDTERCERO = FCXC.IDTERCERO INNER JOIN
                 FCXCD ON FCXC.CNSCXC=FCXCD.CNSCXC AND FCXCD.N_FACTURA = X.N_FACTURA LEFT JOIN
                 TER ON X.IDTERCERO=TER.IDTERCERO
            WHERE X.CUENTA IN (SELECT CUENTA FROM #T_CXCCJG) AND X.SALDO<>0 AND
                  X.IDTERCERO = ISNULL(@IDTERCERO,X.IDTERCERO)
           GROUP BY X.CUENTA, X.IDTERCERO, LEFT(TER.RAZONSOCIAL,100), X.N_FACTURA, FCXC.INDRECIBIDO) X
      GROUP BY CNS, IDTERCERO, RAZONSOCIAL, N_FACTURA
      HAVING SUM(SALDO)<>0
      ORDER BY IDTERCERO, RAZONSOCIAL, N_FACTURA
   END
END
