SET NOCOUNT ON;
DECLARE @MOV VARCHAR(20) = N'250000001369';

SELECT P.CNSPRESELL, P.IDARTICULO, P.CANTIDAD, P.VALOR, P.PCOSTO, P.PROCESADO, P.CNSMOV
FROM dbo.PRESELL P WHERE P.CNSMOV = @MOV;

SELECT H.IDARTICULO, H.CANTIDAD, H.PCOSTO, H.PVENTA, S.VR_IVA
FROM dbo.IMOVH H
LEFT JOIN dbo.ISAL S ON S.CNSMOV = H.CNSMOV AND S.IDARTICULO_IMOVH = H.IDARTICULO
WHERE H.CNSMOV = @MOV;

SELECT F.N_FACTURA, F.VR_TOTAL, F.FECHAFAC, F.F_FACTURA
FROM dbo.FTR F WHERE F.NOREFERENCIA = @MOV;
