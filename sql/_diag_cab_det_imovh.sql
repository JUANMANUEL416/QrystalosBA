SET NOCOUNT ON;

SELECT H.CNSMOV, H.IDARTICULO, H.NOLOTE, H.CANTIDAD, H.PCOSTO,
  CONVERT(decimal(18,2), H.CANTIDAD * H.PCOSTO) BASE,
  CONVERT(decimal(18,2), COALESCE(H.VLRIVA,0)) IVA_H
FROM dbo.IMOVH H
WHERE H.CNSMOV IN (N'0300028179', N'0300028554')
ORDER BY H.CNSMOV, H.IDARTICULO, H.NOLOTE;

SELECT CONVERT(decimal(18,2), SUM(H.CANTIDAD * H.PCOSTO)) BASE,
  CONVERT(decimal(18,2), SUM(COALESCE(H.VLRIVA,0))) IVA
FROM dbo.IMOVH H WHERE H.CNSMOV = N'0300028179';

SELECT CONVERT(decimal(18,2), SUM(H.CANTIDAD * H.PCOSTO)) BASE,
  CONVERT(decimal(18,2), SUM(COALESCE(H.VLRIVA,0))) IVA
FROM dbo.IMOVH H WHERE H.CNSMOV = N'0300028554';
