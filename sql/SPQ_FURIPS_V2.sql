					COALESCE( SER.DESCSERVICIO, '' ) 	CAMPO11_NOMBRESERVICIO,
					0 CAMPO12_CANTIDADSERVICIO,
					0 CAMPO13_VALORUNITARIO,
					0 CAMPO14_VALORTOTAL
					, CONCAT( 
					CASE when COALESCE( Ser.CODFURIPS,'8') =1  THEN CASE WHEN  COALESCE(S.CODCUM,'')='' THEN S.IDSERVICIO ELSE S.CODCUM END 
							when COALESCE( Ser.CODFURIPS,'8') = 2  
							then CASE 
								WHEN LEN(Ser.IDSERVICIO) =  5 THEN Ser.IDSERVICIO
								WHEN LEN(Ser.IDALTERNA) =  5 THEN Ser.IDALTERNA
								ELSE Ser.IDSERVICIO
							END 
						ELSE  ''
					END 		, '- ', QXPCXD.ITEM	, '- ' , '0' )  CONSECUTIVO
				From	FCXC INNER JOIN  FCXCD ON FCXC.CNSCXC=FCXCD.CNSCXC
						INNER JOIN FTR  ON FCXCD.N_FACTURA=FTR.N_FACTURA		  AND COALESCE( FTR.TIPOANULACION,'')<>'NC'  AND FTR.ESTADO ='P'
						LEFT OUTER JOIN FTRD FD	ON FTR.N_fACTURA = FD.N_FACTURA
						LEFT OUTER JOIN HADM B	ON FTR.NOREFERENCIA=B.NOADMISION AND FTR.PROCEDENCIA='SALUD'
						LEFT OUTER JOIN AUT D	ON FTR.NOREFERENCIA=D.NOAUT AND FTR.PROCEDENCIA='CE'
						LEFT OUTER JOIN CIT C   ON C.CONSECUTIVO = FTR.NOREFERENCIA AND FTR.PROCEDENCIA='CI' 
						INNER JOIN AFI E		ON FTR.IDAFILIADO = E.IDAFILIADO
						LEFT OUTER JOIN CIU G	ON E.CIUDAD =	G.CIUDAD
						LEFT OUTER JOIN HACTRAN  A ON A.IDAFILIADO= FTR.IDAFILIADO AND  (A.CNSHACTRAN  = D.CNSHACTRAN   OR A.CNSHACTRAN  = B.CNSHACTRAN   OR A.CNSHACTRAN  = C.CNSHACTRAN   )
						LEFT OUTER JOIN SER	S	ON FD.REFERENCIA=S.IDSERVICIO
						LEFT OUTER JOIN TER ON A.IDASEGURADORA =TER.IDTERCERO
						LEFT OUTER JOIN hpred on FD.n_Factura = hpred.n_Factura and FD.noprestacion = hpred.noprestacion and FD.NOITEM =hpred.NOITEM 
						LEFT OUTER JOIN qxpcxd on hpred.CONSECUTIVOCX =qxpcxd.CONSECUTIVO and hpred.ITEMCIRUGIA = QXPCXD.ITEM
						LEFT OUTER JOIN ser on qxpcxd.IDSERVICIO = ser.IDSERVICIO 

					WHERE FCXC.CNSCXC= @CNSCXC	 AND 
					COALESCE(QXPCXD.consecutivo,'')<>''	 

		UNION ALL

			SELECT distinct 
				COALESCE( TER.IDALTERNA2,'') CAMPO01_CODASEGURADORA,  -- TER.IDALTERNA2
					FORMAT( COALESCE( A.FECHACERTIFICA,GETDATE()) ,'dd/MM/yyyy') CAMPO02_FECHACERTIFICA,
					@CODHABILITA  CAMPO03_CODIGO_HABILITACION,
					CASE  WHEN E.TIPO_DOC IN ('CC' ,'CE' ,'CN' ,'PA' ,'RC' ,'TI' ,'AS' ,'MS' ,'PT' ,'PE' ,'SC' ,'CD' ,'DE') THEN  E.TIPO_DOC  ELSE '' END  CAMPO03_TIPODOCVICTIMA,
					LEFT(COALESCE( E.DOCIDAFILIADO,''),16) 	CAMPO05_NUMDOCVICTIMA,
					case when COALESCE( FORMAT( A.FECHAACC ,'dd/MM/yyyy') ,'01/01/1900')  ='01/01/1900' then '' else COALESCE( FORMAT( A.FECHAACC ,'dd/MM/yyyy') ,'')  end CAMPO06_FECHAOCURRENCIA,
					COALESCE( A.NOPOLIZA,'') CAMPO07_NUMEROPOLIZASOAT,
					COALESCE(  FTR.N_FACTURA ,'')  CAMPO08_NUMERO_FACTURA,
					COALESCE( S.CODFURIPS,'8') CAMPO09_TIPOSERVICIO,
					CASE when COALESCE( S.CODFURIPS,'8') =1 
							THEN CASE WHEN  COALESCE(S.CODCUM,'')='' THEN S.IDSERVICIO ELSE S.CODCUM END 
							when COALESCE( S.CODFURIPS,'8') = 2  
							then CASE 
								WHEN LEN(S.IDSERVICIO) =  5 THEN S.IDSERVICIO
								WHEN LEN(S.IDALTERNA) =  5 THEN S.IDALTERNA
								ELSE S.IDSERVICIO
							END 
						ELSE  ''
					END 	CAMPO10_CODIGOSERVICIO,
					CONCAT( 
					CASE when COALESCE( S.CODFURIPS,'8') =1  THEN CASE WHEN  COALESCE(S.CODCUM,'')='' THEN S.IDSERVICIO ELSE S.CODCUM END 
							when COALESCE( S.CODFURIPS,'8') = 2  
							then CASE 
								WHEN LEN(S.IDSERVICIO) =  5 THEN S.IDSERVICIO
								WHEN LEN(S.IDALTERNA) =  5 THEN S.IDALTERNA
								ELSE S.IDSERVICIO
							END 
						ELSE  ''
					END 		, '- ' , S.DESCSERVICIO ) 	CAMPO11_NOMBRESERVICIO,
					COALESCE( FD.CANTIDAD,1) CAMPO12_CANTIDADSERVICIO,
					COALESCE( FD.VALOR,0) CAMPO13_VALORUNITARIO,
					COALESCE( FD.VLR_SERVICI,0) CAMPO14_VALORTOTAL
					, CONCAT( 
					CASE when COALESCE( S.CODFURIPS,'8') =1  THEN CASE WHEN  COALESCE(S.CODCUM,'')='' THEN S.IDSERVICIO ELSE S.CODCUM END 
							when COALESCE( S.CODFURIPS,'8') = 2  
							then CASE 
								WHEN LEN(S.IDSERVICIO) =  5 THEN S.IDSERVICIO
								WHEN LEN(S.IDALTERNA) =  5 THEN S.IDALTERNA
								ELSE S.IDSERVICIO
							END 
						ELSE  ''
					END 		, '- ', QXPCXD.ITEM	, '- ' , convert(varchar(10) , row_number() over (partition by hpred.idcirugia order by hpred.idservicio ) ) ) CONSECUTIVO
				From	FCXC INNER JOIN  FCXCD ON FCXC.CNSCXC=FCXCD.CNSCXC
						INNER JOIN FTR  ON FCXCD.N_FACTURA=FTR.N_FACTURA		  AND COALESCE( FTR.TIPOANULACION,'')<>'NC'  AND FTR.ESTADO ='P'
						LEFT OUTER JOIN FTRD FD	ON FTR.N_fACTURA = FD.N_FACTURA
						LEFT OUTER JOIN HADM B	ON FTR.NOREFERENCIA=B.NOADMISION AND FTR.PROCEDENCIA='SALUD'
						LEFT OUTER JOIN AUT D	ON FTR.NOREFERENCIA=D.NOAUT AND FTR.PROCEDENCIA='CE'
						LEFT OUTER JOIN CIT C   ON C.CONSECUTIVO = FTR.NOREFERENCIA AND FTR.PROCEDENCIA='CI' 
						INNER JOIN AFI E		ON FTR.IDAFILIADO = E.IDAFILIADO
						LEFT OUTER JOIN CIU G	ON E.CIUDAD =	G.CIUDAD
						LEFT OUTER JOIN HACTRAN  A ON A.IDAFILIADO= FTR.IDAFILIADO AND  (A.CNSHACTRAN  = D.CNSHACTRAN   OR A.CNSHACTRAN  = B.CNSHACTRAN   OR A.CNSHACTRAN  = C.CNSHACTRAN   )
						LEFT OUTER JOIN SER	S	ON FD.REFERENCIA=S.IDSERVICIO
						LEFT OUTER JOIN TER ON A.IDASEGURADORA =TER.IDTERCERO
						LEFT OUTER JOIN hpred on FD.n_Factura = hpred.n_Factura and FD.noprestacion = hpred.noprestacion and FD.NOITEM =hpred.NOITEM 
						LEFT OUTER JOIN qxpcxd on hpred.CONSECUTIVOCX =qxpcxd.CONSECUTIVO and hpred.ITEMCIRUGIA = QXPCXD.ITEM
						LEFT OUTER JOIN ser on qxpcxd.IDSERVICIO = ser.IDSERVICIO 

				WHERE FCXC.CNSCXC= @CNSCXC 
					AND 	 COALESCE(qxpcxd.CONSECUTIVO,'')<>''  
					AND COALESCE( FD.VLR_SERVICI,0) <> 0  
	
		)
		B
		ORDER BY CAMPO08_NUMERO_FACTURA,
			CAMPO09_TIPOSERVICIO,
			CONSECUTIVO ,
			CAMPO10_CODIGOSERVICIO,
			CAMPO11_NOMBRESERVICIO

		RETURN
	END   -- FUCTASCXC
