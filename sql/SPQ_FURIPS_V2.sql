CREATE OR ALTER PROCEDURE DBO.SPQ_FURIPS_V2
@JSON  NVARCHAR(MAX)
WITH
ENCRYPTION
AS
DECLARE	 @PARAMETROS   NVARCHAR(MAX),@MODELO           VARCHAR(100) ,@METODO		VARCHAR(100)	,@USUARIO      VARCHAR(12)
		,@GRUPO        VARCHAR(8)	,@SYS_COMPUTERNAME VARCHAR(254) ,@SEDE			VARCHAR(5)		,@FECHA        VARCHAR(10)   
		,@CNSHACTRAN    VARCHAR(20)	,@FECHA1           DATETIME		,@SQL			VARCHAR(MAX)	,@IDMEDICO     VARCHAR(20)
		,@CNSCXC		VARCHAR(20)	,@FIRMAREPRE	   VARCHAR(MAX)	,@NOMBREREPRE	VARCHAR(100)
		,@PAPELLIDOREPRE	VARCHAR(100)		,@SAPELLIDOREPRE	VARCHAR(100)	,@TIPOIDREPRE	VARCHAR(20)
		,@NITREPRE		VARCHAR(20) , @NOREFERENCIA		VARCHAR(20), @PROCEDENCIA	VARCHAR(20) ,	@SIRAS		VARCHAR(20) ,	@FTR 	VARCHAR(20) 
		,@VR_FTR		FLOAT ,		 @CODHABILITA		VARCHAR (20) , @DIRECIONTER  VARCHAR(1000) , @TELEFONOTER  VARCHAR(100)  , @DEPTOTER  VARCHAR(02)  , @CIUDADTER  VARCHAR(5) 
		,@RAZONSOCIAL	VARCHAR(200)	, @NIT VARCHAR (20) , @TIPODOCTER VARCHAR (2) 
		
BEGIN
	SET DATEFORMAT dmy
 /*	DBO.SPQ_FURIPS
	Modulo:		SOAT
	Funcion:	Consultas y procedimientos para la exportacion delos FURIPS
	Metodos:	
				CONTINUACION DE SPQ_FURIPS
				FURTRAN		(Para exportar el plano del FURTRAN ),
				FURTRANCXC		(Para exportar el plano del FURTRAN  Por Cuenta de Cobro ),
				PDFFURTRAN	(Para exportar el PDF del FURTRAN )
				FUCTAS		(Para exportar el plano del FUCTAS )
				FUCTASCXC	(Para exportar el plano del FUCTAS  Por Cuenta de Cobro ),

	Elabora:	Edgardo Martinez
	Fecha:		13-12-2023 SE DIVIDIO SPQ_FURIPS
*/  

	SELECT *
	INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)  AS JSON
	)

	SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON

	IF @METODO NOT IN ('FURTRAN', 'FURTRANCXC', 'PDFFURTRAN', 'FUCTAS', 'FUCTASCXC')
	BEGIN
		EXEC DBO.SPQ_FURIPS_V3 @JSON
		RETURN
	END

	DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200));
	SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO) FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME


	SELECT @CNSHACTRAN  = COALESCE(  CNSHACTRAN  ,'' ) , @PROCEDENCIA = COALESCE(  PROCEDENCIA ,'' ) , @NOREFERENCIA = COALESCE( NOREFERENCIA ,'' ) , @FTR = COALESCE( FACTURA ,'')
	FROM OPENJSON(@PARAMETROS)
	WITH(
		CNSHACTRAN		VARCHAR(20) '$.CNSHACTRAN ',
		PROCEDENCIA		VARCHAR(20) '$.PROCEDENCIA',
		NOREFERENCIA	VARCHAR(20) '$.NOREFERENCIA',
		FACTURA			VARCHAR(20) '$.FACTURA'
	)
		
	SELECT TOP 1 @SIRAS = SIRAS  FROM HACTRAND WHERE CNSHACTRAN  = @CNSHACTRAN  AND PROCEDENCIA = @PROCEDENCIA  AND NOREFERENCIA = @NOREFERENCIA

	IF @FTR =''   -- SI NO RECIBIÓ LA FACTURA 
	BEGIN
		SET @VR_FTR = 0
		PRINT 'NO TRAE FACTURA POR LO QUE PONE EL VALOR EN 0'
	END
	ELSE
	BEGIN
		SELECT  @VR_FTR = VR_TOTAL FROM FTR WHERE   N_FACTURA = @FTR
		PRINT @FTR +' FACTURA ' + @FTR +' POR EL VALOR :' + CONVERT(VARCHAR(20) ,@VR_FTR )
	END

	IF @PROCEDENCIA = '' 
	BEGIN
		PRINT ' LA PROCEDENCIA ESTA VACIA '
		SELECT TOP 1 @PROCEDENCIA ='QX', @NOREFERENCIA = NOADMISION FROM HADM  WHERE CNSHACTRAN = @CNSHACTRAN
		SELECT TOP 1 @PROCEDENCIA ='CI', @NOREFERENCIA = CONSECUTIVO  FROM CIT  WHERE CNSHACTRAN = @CNSHACTRAN
		SELECT TOP 1 @PROCEDENCIA ='CE', @NOREFERENCIA = NOAUT  FROM AUT  WHERE CNSHACTRAN = @CNSHACTRAN
	END

	IF  @METODO in ('FURIPS', 'PDFFURIPS', 'FURTRAN', 'PDFFURTRAN', 'FUCTAS')
	BEGIN
		SELECT  @RAZONSOCIAL= TER.RAZONSOCIAL, @NIT = CONCAT( TER.NIT , '-', TER.DV ) , @TIPODOCTER= TER.TIPO_ID ,  @CODHABILITA = LEFT(COALESCE( CODHABILITA, COALESCE( IDSGSSS,'')),12), @DIRECIONTER = SED.DIRECCION ,  @TELEFONOTER = SED.TELEFONOS , @DEPTOTER = LEFT (SED.CIUDAD ,2), @CIUDADTER = RIGHT(SED.CIUDAD,3)
		FROM SED
			LEFT JOIN  FTR ON SED.IDSEDE =FTR.IDSEDE 
			INNER JOIN TER ON FTR.IDTERCERO = TER.IDTERCERO  
		WHERE PROCEDENCIA = CASE @PROCEDENCIA WHEN 'QX' THEN 'SALUD' ELSE @PROCEDENCIA END  
		AND NOREFERENCIA = @NOREFERENCIA 
		AND COALESCE(FTR.ESTADO,'A')<>'A' 
		AND COALESCE(FTR.TIPOANULACION,'')<>'NC'
	END
	ELSE 
	BEGIN
		SELECT  @RAZONSOCIAL= TER.RAZONSOCIAL, @NIT = CONCAT( TER.NIT , '-', TER.DV ) , @TIPODOCTER= TER.TIPO_ID , @CODHABILITA = IDALTERNA2 , @DIRECIONTER = TER.DIRECCION ,  @TELEFONOTER = TER.TELEFONOS , @DEPTOTER = LEFT (TER.CIUDAD ,2)   , @CIUDADTER = RIGHT( TER.CIUDAD ,3 )  
		FROM TER WHERE IDTERCERO  = DBO.FNK_VALORVARIABLE ('IDTERCEROINSTALADO' )
	END

	IF COALESCE(@CODHABILITA,'' ) =''
	BEGIN
		SELECT  @RAZONSOCIAL= TER.RAZONSOCIAL, @NIT = CONCAT( TER.NIT , '-', TER.DV ) , @TIPODOCTER= TER.TIPO_ID , @CODHABILITA = IDALTERNA2  , @DIRECIONTER = TER.DIRECCION ,  @TELEFONOTER = TER.TELEFONOS , @DEPTOTER = LEFT (TER.CIUDAD ,2)   , @CIUDADTER = RIGHT( TER.CIUDAD ,3 )  
		FROM TER WHERE IDTERCERO  = DBO.FNK_VALORVARIABLE ('IDTERCEROINSTALADO' )
	END
	PRINT '@CIUDADTER='+ COALESCE ( @CIUDADTER ,' NO ENCONTRE LA CIUDAD')
			 
	IF @METODO = 'FURTRAN'
	BEGIN
		PRINT '---------------------------'
		PRINT 'FURTRAN' 
		PRINT 'FACTURA : ' +  @FTR
		PRINT 'VALOR :  ' + CAST ( @VR_FTR AS VARCHAR(30) )

		--SELECT @CNSHACTRAN  = CNSHACTRAN 
		--FROM OPENJSON(@PARAMETROS)
		--WITH(CNSHACTRAN   VARCHAR(20) '$.CNSHACTRAN ')

		SELECT 'OK' OK
		BEGIN -- FURTRAN
			IF @PROCEDENCIA = 'QX'  --'SALUD' -- FURTRAN
			BEGIN
				SELECT 
					COALESCE( A.NRORADICADOANT,'') CAMPO01_NUMERO_RADICADO_ANTERIOR,
					COALESCE( RESPGLOSA, '') CAMPO02_RGO, -- 1,2,6 
					COALESCE(  F1.N_FACTURA ,COALESCE( @FTR ,'') )  CAMPO03_NUMERO_FACTURA,
					@CODHABILITA 		CAMPO04_CODIGO_HABILITACION,
					COALESCE(  A.COND_PAPELLIDO ,'') CAMPO05_PAPELLIDORECLAMA, 
					COALESCE(  A.COND_SAPELLIDO ,'') CAMPO06_SPAPELLIDORECLAMA, 
					COALESCE(  A.COND_PNOMBRE ,'') CAMPO07_PNOMBRERECLAMA, 
					COALESCE(  A.COND_SNOMBRE ,'') CAMPO08_SNOMBRERECLAMA, 
					CASE  WHEN A.TIPODOC IN ('CC' ,'CE' ,'PA' ,'PT' ,'PE'  ,'CD' ,'DE') THEN  A.TIPODOC  ELSE '' END  CAMPO09_TIPODOCRECLAMA, 
					COALESCE(  A.NODOCUMENTO  ,'')  CAMPO10_NODOCUMENTORECLAMA, 
					CASE COALESCE( A.TIPOTRANSPORTE,'')	
							WHEN 'Basica'			THEN '1'		WHEN 'Medicada'			THEN '2'		WHEN 'Particular'		THEN '3'
							WHEN 'Publico'			THEN '4'		WHEN 'Oficial'			THEN '5' 		WHEN 'Emergencia'		THEN '6'
							WHEN 'Diplomatic'		THEN '7'		WHEN 'Masivo'			THEN '8' 		WHEN 'Escolar'			THEN '9'
							ELSE '0' END CAMPO11_TIPOVEHICULOTRASLADO , 
					COALESCE( A.PLACA_AMPARO ,'') CAMPO12_PLACAVEHICULOTRASLADO, 
					COALESCE( @DIRECIONTER ,'NO REPORTA DIRECCION')  CAMPO13_DIRECCIONRECLAMA, 
					COALESCE( @TELEFONOTER  ,'') CAMPO14_TELEFONORECLAMA, 
					COALESCE( @DEPTOTER ,'') CAMPO15_CODDEPARTAMENTORECLAMA, 
					COALESCE( @CIUDADTER,'' ) CAMPO16_CODMUNICPIORECLAMA, 
					CASE  WHEN E.TIPO_DOC IN ('CC' ,'CE' ,'CN' ,'PA' ,'RC' ,'TI' ,'AS' ,'MS' ,'PT' ,'PE' ,'SC' ,'CD' ,'DE') THEN  E.TIPO_DOC  ELSE '' END  CAMPO17_TIPODOCVICTIMA,
						/*CUANDO CORRESPONDA USAR AS ADULTO SIN IDENTIFICACION O MS MENOR SIN IDENTIFICACION SE DEBE UTILIZAR LA TABLA DE LA RESOLUCION 4622 DE 2016
						CUANDO EL PACIENTE ADULTO O MENOR SIN IDENTIFICACION ES EXTRANJERO SE DETERMINA EL NUMERO DE IDENTIFICACION SEGUN LA CIRCULAR 029 DE 2017 ASI:
						*/
					LEFT(COALESCE( E.DOCIDAFILIADO,''),16) 	CAMPO18_NUMDOCVICTIMA, 
					LEFT(COALESCE( E.PNOMBRE,''),20) 	CAMPO19_PNOMBREVICTIMA, 
					COALESCE( E.SNOMBRE,'')	CAMPO20_SNOMBREVICTIMA,
					LEFT(COALESCE( E.PAPELLIDO,''),20)	CAMPO21_PAPELLIDOVICTIMA,
					COALESCE( E.SAPELLIDO,'')	CAMPO22_SAPELLIDOVICTIMA,
					COALESCE( convert(varchar(10) ,E.FNACIMIENTO ,103),'')	CAMPO23_FNACIMIENTOVICTIMA,
					CASE WHEN E.SEXO IN ('F','M','O') THEN E.SEXO  WHEN E.SEXO ='Masculino' THEN 'M'   WHEN E.SEXO ='Femenino' THEN 'F'  ELSE 'O' END  	CAMPO24_SEXOVICTIMA,
					CASE   A.NATUREVENTO 
						WHEN 'ACCTR' THEN '1'   -- Accidente de Tránsito
						WHEN 'SISMO' THEN '2'   -- Sismo
						WHEN 'MAREM' THEN '2'   -- Maremoto
						WHEN 'ERUPV' THEN '2'   -- Erupciones Volcánicas
						WHEN 'HURAC' THEN '2'   -- Huracán
						WHEN 'INUND' THEN '2'   -- Inundaciones
						WHEN 'AVALA' THEN '2'   -- Avalancha
						WHEN 'DESLI' THEN '2'   -- Deslizamiento de Tierra
						WHEN 'INCEN' THEN '2'   -- Incendio Natural
						WHEN 'EXPLO' THEN '3'   -- Explosión
						WHEN 'MASAC' THEN '3'   -- Masacre
						WHEN 'MINAA' THEN '3'   -- Mina Antipersonal
						WHEN 'COMBA' THEN '3'   -- Combate
						WHEN 'INCEM' THEN '3'   -- Incendio Terrorista
						WHEN 'ATAQU' THEN '3'   -- Ataques a Municipios
						WHEN 'OTRO'	 THEN '3'   -- Otro
						WHEN 'DESPL' THEN '3'   -- Desplazados
						WHEN 'RAYO'  THEN '2'   -- Rayo
						WHEN 'VENDA' THEN '2'   -- Vendaval
						WHEN 'TORNA' THEN '2'   -- Tornado
						ELSE '1'
					END  CAMPO25_TIPOEVENTOTRASLADO,
					COALESCE(LEFT(A.SITIOACC, 40) ,'')	CAMPO26_DIRECCIONRECOGE,
					CASE LEN( COALESCE( A.CIUDAD, '') ) WHEN 5 THEN LEFT(COALESCE( A.CIUDAD, ''),2) WHEN 4 THEN LEFT(COALESCE( A.CIUDAD, ''),1) ELSE '' END 	CAMPO27_CODDEPARTAMENTORECOGE,
					CASE LEN( COALESCE( A.CIUDAD, '') ) WHEN 5 THEN RIGHT(COALESCE( A.CIUDAD, ''),3) WHEN 4 THEN RIGHT(COALESCE( A.CIUDAD, ''),3)  ELSE '' END  	CAMPO28_CODMUNICIPIORECOGE,
					CASE A.ZONA WHEN 'URBANA' THEN 'U' WHEN 'RURAL' THEN 'R' ELSE 'ERROR ZONA' END 	CAMPO29_ZONARECOGE,
					case when COALESCE( FORMAT( A.FECHAACC ,'dd/MM/yyyy')  ,'01/01/1900') ='01/01/1900' then '' else COALESCE( FORMAT( A.FECHAACC ,'dd/MM/yyyy')  ,'') end	CAMPO30_FECHATRASLADOPRIMARIO,
					COALESCE( FORMAT( A.FECHAACC ,N'HH:mm')  ,'')	 	CAMPO31_HORATRASLADOPRIMARIO,
					COALESCE( A.COD_IPSRECIBE_AMPARO , @CODHABILITA ,'')	CAMPO32_CODHABILITACIONIPSRECIBE,		
					CASE LEN( COALESCE( A.CIUDAD_AMPARO, @CIUDADTER , '')) WHEN 5 THEN LEFT(COALESCE( A.CIUDAD_AMPARO, @CIUDADTER, ''),2) WHEN 4 THEN LEFT(COALESCE( A.CIUDAD_AMPARO, @CIUDADTER, ''),1) ELSE LEFT(COALESCE( @CIUDADTER, ''),2) END  CAMPO33_CODDEPARTAMENTORECIBE, 
					CASE LEN( COALESCE( A.CIUDAD_AMPARO, @CIUDADTER , '')) WHEN 5 THEN RIGHT(COALESCE( A.CIUDAD_AMPARO, @CIUDADTER ,''),3) WHEN 4 THEN RIGHT(COALESCE( A.CIUDAD_AMPARO, @CIUDADTER, ''),3)  ELSE  RIGHT(COALESCE(  @CIUDADTER, ''),3)   END  CAMPO34_CODMUNICIPIORECIBE,
					CASE A.CONDICIONACC WHEN 'Conducto' THEN 1 WHEN 'Peaton' THEN '2' WHEN 'Ocupante' THEN '3' WHEN 'Ciclista' THEN '4' ELSE '1' END 	CAMPO35_CONDICIONVICTIMA,
					CASE A.TIPOPOLIZA
						WHEN 'ASEGURADO'				THEN '1'	WHEN 'Vigente'			THEN '1'	WHEN 'NO ASEGURADO'			THEN '2'	WHEN 'No Asegurado'		THEN '2'
						WHEN 'VEHICULO FANTASMA'		THEN '3'	WHEN 'Auto Fantasma'	THEN '3'	WHEN 'POLIZA FALSA'			THEN '4'	WHEN 'FALSA'			THEN '4'
						WHEN 'VEHICULO EN FUGA'			THEN '5'	WHEN 'Auto en Fuga'		THEN '5'	WHEN 'ASEGURADO D.2497'		THEN '6'	WHEN 'Aseg. D.2497'		THEN '6'
						WHEN 'NO ASEGURADO PROPIETARIO'	THEN '7'	WHEN 'No Aseg. prop'	THEN '7'	WHEN 'No Aseg. plac'		THEN '8'
						ELSE CASE 
								WHEN A.FECHAACC >= A.FECHAINIPOL
									AND A.FECHAACC <= A.FECHAFINPOL
									AND COALESCE( A.NOPOLIZA, '') <> ''
									THEN '1'
								ELSE CASE 
										WHEN (
												A.FECHAACC < A.FECHAINIPOL
												OR A.FECHAACC > A.FECHAFINPOL
												)
											AND COALESCE( A.NOPOLIZA, '') <> ''
											THEN '2'
										ELSE CASE 
												WHEN COALESCE( A.NOPOLIZA, '') = ''
													THEN '4'
												ELSE 'ERROR EN ESTADO ASEGURAMIENTO'
												END
										END
								END
						END	CAMPO36_ESTADOASEGURAMIENTO, 
					COALESCE( A.TIPOVEHICULO,'')	CAMPO37_TIPOVEHICULOACC,
					COALESCE( A.PLACA ,'')	CAMPO38_PLACAVEHICULOACC,
					CASE A.TIPOPOLIZA
						WHEN 'ASEGURADO'		THEN  COALESCE( TER.IDALTERNA2 ,'') -- '1'
						WHEN 'Vigente'			THEN  COALESCE( TER.IDALTERNA2 ,'') -- '1'
						WHEN 'NO ASEGURADO'		THEN  COALESCE( ( SELECT IDALTERNA2 FROM TER WHERE IDTERCERO = DBO.FNK_VALORVARIABLE('IDNITFONSAT')) ,'') -- '2'
						WHEN 'No Asegurado'		THEN  COALESCE( ( SELECT IDALTERNA2 FROM TER WHERE IDTERCERO = DBO.FNK_VALORVARIABLE('IDNITFONSAT')) ,'') -- '2'
						WHEN 'Auto Fantasma'	THEN  COALESCE( ( SELECT IDALTERNA2 FROM TER WHERE IDTERCERO = DBO.FNK_VALORVARIABLE('IDNITFONSAT')) ,'') --'3' 
						WHEN 'AUTO FANTASMA'	THEN  COALESCE( ( SELECT IDALTERNA2 FROM TER WHERE IDTERCERO = DBO.FNK_VALORVARIABLE('IDNITFONSAT')) ,'') --'3' 
						WHEN 'Auto en Fuga'		THEN  COALESCE( ( SELECT IDALTERNA2 FROM TER WHERE IDTERCERO = DBO.FNK_VALORVARIABLE('IDNITFONSAT')) ,'') --'3' 
						WHEN 'AUTO EN FUGA'		THEN  COALESCE( ( SELECT IDALTERNA2 FROM TER WHERE IDTERCERO = DBO.FNK_VALORVARIABLE('IDNITFONSAT')) ,'') --'3' 
						WHEN 'POLIZA FALSA'		THEN  COALESCE( TER.IDALTERNA2 ,'') -- '4'
						WHEN 'ASEGURADO D.2497'	THEN  COALESCE( TER.IDALTERNA2 ,'') -- '6'
						WHEN 'Aseg. D.2497'		THEN  COALESCE( TER.IDALTERNA2 ,'') --'6'
						WHEN 'No Aseg. plac'	THEN  COALESCE( TER.IDALTERNA2 ,'') --'6'
						ELSE ''
						END 	CAMPO39_CODASEGURADORA,
						-- COALESCE( TER.IDALTERNA2 ,'')	CAMPO39_CODASEGURADORA,
					CASE A.TIPOPOLIZA
						WHEN 'ASEGURADO'		THEN COALESCE( A.NOPOLIZA,'')  -- '1'
						WHEN 'Vigente'			THEN COALESCE( A.NOPOLIZA,'')  -- '1'
						WHEN 'NO ASEGURADO'		THEN  COALESCE( A.NOPOLIZA,'')  -- '2'
						WHEN 'No Asegurado'		THEN  COALESCE( A.NOPOLIZA,'')  -- '2'
						WHEN 'POLIZA FALSA'		THEN  COALESCE( A.NOPOLIZA,'')  -- '4'
						WHEN 'ASEGURADO D.2497'	THEN  COALESCE( A.NOPOLIZA,'')  -- '6'
						WHEN 'Aseg. D.2497'		THEN  COALESCE( A.NOPOLIZA,'')  --'6'
						WHEN 'No Aseg. plac'	THEN COALESCE( A.NOPOLIZA ,'') --'6'
						ELSE ''
						END  CAMPO40_NUMPOLIZA,
      
					CASE A.TIPOPOLIZA
						WHEN 'ASEGURADO'		THEN  COALESCE(convert(varchar(10) ,  A.FECHAINIPOL ,103) ,'') -- '1'
						WHEN 'Vigente'			THEN  COALESCE(convert(varchar(10) ,  A.FECHAINIPOL ,103) ,'') -- '1'
						WHEN 'NO ASEGURADO'		THEN  COALESCE(convert(varchar(10) ,  A.FECHAINIPOL ,103) ,'') -- '2'
						WHEN 'No Asegurado'		THEN  COALESCE(convert(varchar(10) ,  A.FECHAINIPOL ,103) ,'') -- '2'
						WHEN 'POLIZA FALSA'		THEN   COALESCE(convert(varchar(10) ,  A.FECHAINIPOL ,103) ,'') -- '4'
						WHEN 'ASEGURADO D.2497'	THEN   COALESCE(convert(varchar(10) ,  A.FECHAINIPOL ,103) ,'')-- '6'
						WHEN 'Aseg. D.2497'		THEN   COALESCE(convert(varchar(10) ,  A.FECHAINIPOL ,103) ,'') --'6'
						WHEN 'No Aseg. plac'	THEN  COALESCE(convert(varchar(10) ,  A.FECHAINIPOL ,103) ,'') --'6'
						ELSE ''
						END  CAMPO41_FECHAINIVIGENCIA,
					-- COALESCE(convert(varchar(10) ,  A.FECHAINIPOL ,103) ,'')	CAMPO41_FECHAINIVIGENCIA,
		 
					CASE A.TIPOPOLIZA
						WHEN 'ASEGURADO'		THEN  COALESCE(convert(varchar(10) ,  A.FECHAFINPOL ,103) ,'') -- '1'
						WHEN 'Vigente'			THEN  COALESCE(convert(varchar(10) ,  A.FECHAFINPOL ,103) ,'') -- '1'
						WHEN 'NO ASEGURADO'		THEN  COALESCE(convert(varchar(10) ,  A.FECHAFINPOL ,103) ,'') -- '2'
						WHEN 'No Asegurado'		THEN  COALESCE(convert(varchar(10) ,  A.FECHAFINPOL ,103) ,'')-- '2'
						WHEN 'POLIZA FALSA'		THEN  COALESCE(convert(varchar(10) ,  A.FECHAFINPOL ,103) ,'') -- '4'
						WHEN 'ASEGURADO D.2497'	THEN  COALESCE(convert(varchar(10) ,  A.FECHAFINPOL ,103) ,'')-- '6'
						WHEN 'Aseg. D.2497'		THEN  COALESCE(convert(varchar(10) ,  A.FECHAFINPOL ,103) ,'') --'6'
						WHEN 'No Aseg. plac'	THEN  COALESCE(convert(varchar(10) ,  A.FECHAFINPOL ,103) ,'') --'6'
						ELSE ''
						END  	CAMPO42_FECHAFINVIGENCIA,
						--  COALESCE(convert(varchar(10) ,  A.FECHAFINPOL ,103) ,'')	CAMPO42_FECHAFINVIGENCIA,
					COALESCE( @SIRAS , COALESCE( A.NOSIRAS,'') ) 	CAMPO43_NUMSIRAS,
					COALESCE( A.ARTRANSFACTURADO,0) CAMPO44_VALORFACTURADO,
					COALESCE( A.ARTRANSFOSYGA,0) CAMPO45_VALORRECLAMADO,
					'1' CAMPO46_MANIFESTACIONHABILITADO
					--SELECT  COALESCE(convert(varchar(10) ,  A.FECHAINIPOL ,103) ,'')	CAMPO41_FECHAINIVIGENCIA, 		COALESCE(convert(varchar(10) ,  A.FECHAFINPOL ,103) ,'')	
					FROM HACTRAN  A 
							INNER JOIN AFI E		ON A.IDAFILIADO = E.IDAFILIADO
							LEFT OUTER JOIN HADM B	ON A.CNSHACTRAN  = B.CNSHACTRAN  AND E.IDAFILIADO= B.IDAFILIADO and B.NOADMISION = @NOREFERENCIA
							LEFT OUTER JOIN CIU G	ON E.CIUDAD =	G.CIUDAD
