/*
  CEM — movimientos de inventario sin confirmar, septiembre 2026.
  Solo lectura. Una fila para Excel.

  Universo: fecha de movimiento del 1 al 30 de septiembre, estado sin confirmar,
  tipo que se contabiliza.

  SITUACION:
    Con detalle     = tiene líneas IMOVH (artículo y cantidad)
    Encabezado vacío = no tiene líneas ni entrega

  Cómo pasarlo a Excel (SSMS):
    Consulta → Resultados en cuadrícula → ejecutar →
    clic derecho sobre la grilla → Guardar resultados como… → CSV → abrir en Excel.
*/
SET NOCOUNT ON;

DECLARE @INI datetime = '20260901';
DECLARE @FIN datetime = '20261001';

;WITH MOV AS (
  SELECT
    M.CNSMOV,
    z.CLASE,
    Z.NOADMISION,
    M.IDBODEGA,
    B.DESCRIPCION AS BODEGA_NOM,
    M.IDTIPOMOV,
    T.DESCRIPCION AS TIPO_NOM,
    M.NODOCUMENTO,
    M.FECHAMOV,
    Z.CNSIZSOL,
    COALESCE(A.DOCIDAFILIADO, A.IDAFILIADO, N'') AS PACIENTE,
    COALESCE(A.NOMBREAFI, N'') AS NOMBRE
  FROM dbo.IMOV M
  INNER JOIN dbo.ITMO T ON T.IDTIPOMOV = M.IDTIPOMOV
  LEFT JOIN dbo.IBOD B ON B.IDBODEGA = M.IDBODEGA
  LEFT JOIN dbo.IZSOL Z ON Z.CNSIZSOL = M.NODOCUMENTO
  LEFT JOIN dbo.HADM H ON H.NOADMISION = COALESCE(
        CASE
          WHEN Z.CLASE NOT IN (N'CE', N'TRANS_CE', N'FORMEDCE', N'HPRE', N'APLIM', N'ONCO', N'QXPGCX')
          THEN Z.NOADMISION
        END,
        M.NODOCUMENTO
      )
  LEFT JOIN dbo.AFI A ON A.IDAFILIADO = COALESCE(
        H.IDAFILIADO,
        CASE
          WHEN Z.CLASE IN (N'CE', N'TRANS_CE', N'FORMEDCE', N'HPRE') THEN Z.NOADMISION
        END
      )
  WHERE M.FECHAMOV >= @INI
    AND M.FECHAMOV < @FIN
    AND COALESCE(M.ESTADO, 0) = 0
    AND COALESCE(T.SECONTABILIZA, 0) = 1
)
SELECT
  CASE WHEN H.CNSMOV IS NULL THEN N'Encabezado vacío' ELSE N'Con detalle' END AS SITUACION,
  MOV.IDBODEGA + N' ' + COALESCE(MOV.BODEGA_NOM, N'') AS BODEGA,
  COALESCE(MOV.CNSIZSOL, MOV.NODOCUMENTO, N'') AS SOLICITUD,
  CONVERT(varchar(10), MOV.FECHAMOV, 103) AS FECHA,
  MOV.CLASE,
  COALESCE(MOV.PACIENTE,AFI.DOCIDAFILIADO)DOCIDAFILIADO,
  COALESCE(MOV.NOMBRE,AFI.NOMBREAFI)NOMBREAFI,
  MOV.CNSMOV,
  MOV.IDTIPOMOV + N' ' + COALESCE(MOV.TIPO_NOM, N'') AS TIPO,
  COALESCE(H.IDARTICULO, N'') AS IDARTICULO,
  COALESCE(A.DESCRIPCION, N'') AS DESCRIPCION,
 CONVERT(INT, H.CANTIDAD)CANTIDAD
FROM MOV
INNER JOIN dbo.IMOVH H ON H.CNSMOV = MOV.CNSMOV
LEFT JOIN dbo.IART A ON A.IDARTICULO = H.IDARTICULO
LEFT JOIN AUT ON MOV.NOADMISION=AUT.IDAUT AND MOV.CLASE IN('TRANS_CE','CE')
LEFT JOIN APLIMF ON MOV.CNSIZSOL=APLIMF.CNSIZSOL AND MOV.CLASE='APLIM'
LEFT  JOIN APLIM ON APLIMF.IDAPLIM=APLIM.IDAPLI
LEFT JOIN CIT ON APLIM.CONSECUTIVOCIT=CIT.CONSECUTIVO
LEFT JOIN AFI ON COALESCE(AUT.IDAFILIADO,CIT.IDAFILIADO)=AFI.IDAFILIADO
WHERE H.CNSMOV IS NOT NULL
   OR (
        NOT EXISTS (SELECT 1 FROM dbo.IMOVH X WHERE X.CNSMOV = MOV.CNSMOV)
        AND NOT EXISTS (SELECT 1 FROM dbo.ISAL S WHERE S.CNSMOV = MOV.CNSMOV)
      )
ORDER BY
  CASE WHEN H.CNSMOV IS NULL THEN 2 ELSE 1 END,
  MOV.IDBODEGA,
  MOV.FECHAMOV,
  MOV.CNSMOV,
  H.IDARTICULO;


