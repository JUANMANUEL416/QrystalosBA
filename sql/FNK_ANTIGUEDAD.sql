IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='FNK_ANTIGUEDAD' AND XTYPE='FN')
BEGIN
 DROP FUNCTION FNK_ANTIGUEDAD 
END

GO
CREATE FUNCTION DBO.FNK_ANTIGUEDAD(@FECHAINI DATETIME, @FECHAFIN DATETIME, @FORMATO VARCHAR(1))  
RETURNS DECIMAL(15,6)
AS  
BEGIN  
 DECLARE @ANTIGUEDAD DECIMAL(16,5)
 SET @ANTIGUEDAD =
 CASE @FORMATO
  WHEN 'D' THEN DATEDIFF(DAY,@FECHAINI,@FECHAFIN)
  WHEN 'M' THEN DATEDIFF(MONTH,@FECHAINI,@FECHAFIN)
  WHEN 'A' THEN DATEDIFF(YEAR,@FECHAINI,@FECHAFIN)
 END
 RETURN @ANTIGUEDAD
END
