CREATE OR ALTER PROCEDURE DBO.SPQ_ITRADEV
@JSON NVARCHAR(MAX)
WITH ENCRYPTION
AS
DECLARE
  @PARAMETROS       NVARCHAR(MAX),
  @MODELO           VARCHAR(100),
  @METODO           VARCHAR(100),
  @USUARIO          VARCHAR(20),
  @SYS_COMPUTERNAME VARCHAR(254),
  @IDSEDE           VARCHAR(10),
  @SEDE             VARCHAR(5),
  @COMPANIA         VARCHAR(10),
  @CNSITRADEV       VARCHAR(20),
  @CNSITRA          VARCHAR(20),
  @IDBODEGA         VARCHAR(20),
  @MOTIVORECHAZO    VARCHAR(500),
  @OBSERVACION      VARCHAR(500),
  @CNSMOVDEV        VARCHAR(20),
  @NVOCONSEC        VARCHAR(20),
  @APRUEBA          VARCHAR(20);

DECLARE @TBLERRORES TABLE (ERROR VARCHAR(1200));

BEGIN
  SET DATEFORMAT dmy;

  SELECT *
  INTO #JSON
  FROM OPENJSON(@JSON)
  WITH (
    MODELO     VARCHAR(100)  '$.MODELO',
    METODO     VARCHAR(100)  '$.METODO',
    USUARIO    VARCHAR(20)   '$.USUARIO',
    PARAMETROS NVARCHAR(MAX) AS JSON
  );

  SELECT @MODELO = MODELO, @METODO = METODO, @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
  FROM #JSON;

  SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO;
  SELECT @IDSEDE = IDSEDE, @SEDE = IDSEDE, @COMPANIA = COMPANIA
  FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME;

  SET @APRUEBA = COALESCE(DBO.FNK_VALORVARIABLE('INV_APRU_DEVTRA'), 'NO');

  /* ---------- CONTAR pendientes (badge) ---------- */
  IF @METODO = 'CONTAR_PENDIENTES'
  BEGIN
    SELECT @IDBODEGA = IDBODEGA
    FROM OPENJSON(@PARAMETROS)
    WITH (IDBODEGA VARCHAR(20) '$.IDBODEGA');

    IF @APRUEBA <> 'SI'
    BEGIN
      SELECT 'OK' OK, 0 AS TOTAL, 'NO' AS APRUEBA;
      RETURN;
    END

    SELECT 'OK' OK,
           COALESCE((
             SELECT COUNT(1)
             FROM ITRADEV
             WHERE ESTADO = 0
               AND (@IDBODEGA IS NULL OR @IDBODEGA = '' OR IDBODEGAORI = @IDBODEGA)
           ), 0) AS TOTAL,
           'SI' AS APRUEBA;
    RETURN;
  END

  /* ---------- LISTAR pendientes / historial reciente ---------- */
  IF @METODO = 'LISTAR'
  BEGIN
    SELECT @IDBODEGA = IDBODEGA
    FROM OPENJSON(@PARAMETROS)
    WITH (IDBODEGA VARCHAR(20) '$.IDBODEGA');

    IF @APRUEBA <> 'SI'
    BEGIN
      SELECT 'OK' OK, 'NO' AS APRUEBA;
      SELECT TOP 0
        CAST(NULL AS VARCHAR(20)) CNSITRADEV;
      RETURN;
    END

    SELECT 'OK' OK, 'SI' AS APRUEBA;

    SELECT
      D.CNSITRADEV,
      D.CNSITRA,
      D.CNSMOVORI,
      D.IDBODEGAORI,
      BOD_O.DESCRIPCION AS BOD_ORI_DESC,
      D.IDBODEGADES,
      BOD_D.DESCRIPCION AS BOD_DES_DESC,
      D.ESTADO,
      CASE D.ESTADO
        WHEN 0 THEN 'Pendiente'
        WHEN 1 THEN 'Aceptada'
        WHEN 2 THEN 'Rechazada'
        ELSE CAST(D.ESTADO AS VARCHAR(10))
      END AS ESTADO_DESC,
      D.USUARIOSOL,
      USOL.NOMBRE AS USUARIOSOL_NOM,
      D.FECHASOL,
      D.USUARIORES,
      URES.NOMBRE AS USUARIORES_NOM,
      D.FECHARES,
      D.MOTIVORECHAZO,
      D.CNSMOVDEV,
      D.OBSERVACION,
      ITRA.IDTIPOMOV,
      ITMO.DESCRIPCION AS ITMO_DESC
    FROM ITRADEV D
    LEFT JOIN ITRA ON ITRA.CNSITRA = D.CNSITRA
    LEFT JOIN ITMO ON ITMO.IDTIPOMOV = ITRA.IDTIPOMOV
    LEFT JOIN IBOD BOD_O ON BOD_O.IDBODEGA = D.IDBODEGAORI
    LEFT JOIN IBOD BOD_D ON BOD_D.IDBODEGA = D.IDBODEGADES
    LEFT JOIN USUSU USOL ON USOL.USUARIO = D.USUARIOSOL
    LEFT JOIN USUSU URES ON URES.USUARIO = D.USUARIORES
    WHERE D.ESTADO = 0
      AND (@IDBODEGA IS NULL OR @IDBODEGA = '' OR D.IDBODEGAORI = @IDBODEGA)
    ORDER BY D.FECHASOL DESC;

    -- Detalle de l�neas de los pendientes (segundo recordset)
    SELECT
      D.CNSITRADEV,
      H.CNSITRA,
      H.IDARTICULO,
      LEFT(IART.DESCRIPCION, 120) AS DESCRIPCION,
      H.NOLOTE,
      H.NOLOTEPEDIDO,
      H.CANTIDADORI,
      H.CANTIDADDES,
      H.PCOSTO,
      H.FECHAVENCE,
      COALESCE(IART.UNID_VENTA, 0) AS UNID_VENTA
    FROM ITRADEV D
    INNER JOIN ITRAH H ON H.CNSITRA = D.CNSITRA
    LEFT JOIN IART ON IART.IDARTICULO = H.IDARTICULO
    WHERE D.ESTADO = 0
      AND (@IDBODEGA IS NULL OR @IDBODEGA = '' OR D.IDBODEGAORI = @IDBODEGA)
    ORDER BY D.CNSITRADEV, H.IDARTICULO, H.NOLOTE;

    RETURN;
  END

  /* ---------- ACEPTAR ? reintegra existencias en origen ---------- */
  IF @METODO = 'ACEPTAR'
  BEGIN
    SELECT @CNSITRADEV = CNSITRADEV
    FROM OPENJSON(@PARAMETROS)
    WITH (CNSITRADEV VARCHAR(20) '$.CNSITRADEV');

    IF @APRUEBA <> 'SI'
    BEGIN
      SELECT 'KO' OK, 'La aprobaci�n de devoluciones no est� activa (INV_APRU_DEVTRA).' ERROR;
      RETURN;
    END

    IF NOT EXISTS (SELECT 1 FROM ITRADEV WHERE CNSITRADEV = @CNSITRADEV AND ESTADO = 0)
    BEGIN
      SELECT 'KO' OK, 'La solicitud no existe o ya fue resuelta.' ERROR;
      RETURN;
    END

    SELECT @CNSITRA = CNSITRA, @IDBODEGA = IDBODEGAORI
    FROM ITRADEV WHERE CNSITRADEV = @CNSITRADEV;

    IF NOT EXISTS (
      SELECT 1 FROM ITRA
      WHERE CNSITRA = @CNSITRA
        AND ESTADO IN (0, 3)
        AND COALESCE(USUARIODES, '') = ''
        AND COALESCE(CNSMOVDES, '') = ''
    )
    AND NOT EXISTS (
      SELECT 1
      FROM ITMO
      INNER JOIN ITRA ON ITMO.IDTIPOMOV = ITRA.IDTIPOMOV
      WHERE ITRA.CNSITRA = @CNSITRA AND ITMO.GENTRANSITO = 1 AND ITRA.ESTADO IN (0, 3)
    )
    BEGIN
      SELECT 'KO' OK, 'El tr�nsito ya no es elegible para devoluci�n (recibido o cerrado).' ERROR;
      RETURN;
    END

    BEGIN TRY
      EXEC SPK_REINTGRA_TRASLADO_INV @CNSITRA, @COMPANIA, @IDSEDE, @USUARIO, @SYS_COMPUTERNAME;

      SELECT TOP 1 @CNSMOVDEV = CNSMOV
      FROM IMOV
      WHERE NODOCUMENTO = @CNSITRA
        AND IDTIPOMOV = DBO.FNK_VALORVARIABLE('IDTIMOVDEV_TRASLBOD')
        AND ESTADO = 1
      ORDER BY FECHACONF DESC, CNSMOV DESC;

      UPDATE ITRADEV
      SET ESTADO = 1,
          USUARIORES = @USUARIO,
          FECHARES = DBO.FNK_GETDATE(),
          CNSMOVDEV = @CNSMOVDEV
      WHERE CNSITRADEV = @CNSITRADEV AND ESTADO = 0;

      -- REINTGRA deja ITRA/ITRAH en ESTADO=2; refuerzo por si acaso
      UPDATE ITRA  SET ESTADO = 2 WHERE CNSITRA = @CNSITRA
      UPDATE ITRAH SET ESTADO = 2 WHERE CNSITRA = @CNSITRA

      SELECT 'OK' OK,
             'Devoluci�n aceptada. Existencias reintegradas en bodega origen.' AS MENSAJE,
             @CNSMOVDEV AS CNSMOVDEV,
             @CNSITRA AS CNSITRA;
    END TRY
    BEGIN CATCH
      SELECT 'KO' OK, ERROR_MESSAGE() AS ERROR;
    END CATCH
    RETURN;
  END

  /* ---------- RECHAZAR ? tr�nsito sigue; destino debe recibirlo ---------- */
  IF @METODO = 'RECHAZAR'
  BEGIN
    SELECT
      @CNSITRADEV = CNSITRADEV,
      @MOTIVORECHAZO = MOTIVORECHAZO,
      @OBSERVACION = OBSERVACION
    FROM OPENJSON(@PARAMETROS)
    WITH (
      CNSITRADEV    VARCHAR(20)  '$.CNSITRADEV',
      MOTIVORECHAZO VARCHAR(500) '$.MOTIVORECHAZO',
      OBSERVACION   VARCHAR(500) '$.OBSERVACION'
    );

    IF @APRUEBA <> 'SI'
    BEGIN
      SELECT 'KO' OK, 'La aprobaci�n de devoluciones no est� activa (INV_APRU_DEVTRA).' ERROR;
      RETURN;
    END

    IF COALESCE(LTRIM(RTRIM(@MOTIVORECHAZO)), '') = ''
    BEGIN
      SELECT 'KO' OK, 'Debe indicar el motivo del rechazo.' ERROR;
      RETURN;
    END

    IF NOT EXISTS (SELECT 1 FROM ITRADEV WHERE CNSITRADEV = @CNSITRADEV AND ESTADO = 0)
    BEGIN
      SELECT 'KO' OK, 'La solicitud no existe o ya fue resuelta.' ERROR;
      RETURN;
    END

    SELECT @CNSITRA = CNSITRA FROM ITRADEV WHERE CNSITRADEV = @CNSITRADEV;

    UPDATE ITRADEV
    SET ESTADO = 2,
        USUARIORES = @USUARIO,
        FECHARES = DBO.FNK_GETDATE(),
        MOTIVORECHAZO = LEFT(@MOTIVORECHAZO, 500),
        OBSERVACION = LEFT(@OBSERVACION, 500)
    WHERE CNSITRADEV = @CNSITRADEV AND ESTADO = 0;

    -- Reactiva tr�nsito (cabecera + detalle) para que destino pueda Traer
    UPDATE ITRA  SET ESTADO = 0 WHERE CNSITRA = @CNSITRA AND ESTADO = 3
    UPDATE ITRAH SET ESTADO = 0 WHERE CNSITRA = @CNSITRA AND ESTADO = 3

    SELECT 'OK' OK,
           'Devoluci�n rechazada. El tr�nsito sigue disponible para recepci�n en destino. No se podr� solicitar nuevamente Regresar Traslado.' AS MENSAJE;
    RETURN;
  END

  SELECT 'KO' OK, 'M�todo no soportado en SPQ_ITRADEV' ERROR;
END
