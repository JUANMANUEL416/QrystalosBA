CREATE OR ALTER PROCEDURE DBO.SPQ_IGEN
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @PARAMETROS	NVARCHAR(MAX),	@MODELO         VARCHAR(100),   @METODO         VARCHAR(100)
DECLARE  @USUARIO		VARCHAR(20),	@IDGENERICO		VARCHAR(20),	@DESCRIPCION	VARCHAR(100)
DECLARE	 @IDCLASE		VARCHAR(2),		@IDSUBCLASE		VARCHAR(4),		@IDGRUPO		VARCHAR(4)
DECLARE	 @IDPRINACTIVO	VARCHAR(10),	@IDTGENERICO	VARCHAR(20),	@CODIGO_DCI	VARCHAR(20)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

	IF @METODO = 'GET_GENERICO'
	BEGIN
		SELECT 'OK' OK
		SELECT @IDGENERICO = JSON_VALUE(@PARAMETROS, '$.IDGENERICO')

		SELECT IGEN.IDGENERICO, IGEN.DESCRIPCION DESC_GENERICO, IGEN.CODIGO_DCI, IDCI.DESCRIPCION AS DESC_DCI,
				ICLA.IDCLASE, ICLA.DESCRIPCION DESC_CLASE,
				ICLAH.IDSUBCLASE, ICLAH.DESCRIPCION DESC_SUBCLASE, IGRU.IDGRUPO, IGRU.DESCRIPCION DESC_GRUPO, IPAC.IDPRINACTIVO, IPAC.DESCRIPCION DESC_PRINACTIVO
				--,IFFA.IDFORFARM, IFFA.DESCRIPCION DESC_FORFARM, ICCN.IDCONCENTRA, ICCN.DESCRIPCION DESC_CONCENTRA, IUNI.IDUNIDAD, IUNI.DESCRIPCION DESC_UNIDAD
		FROM IGEN
		INNER JOIN ICLA ON ICLA.IDCLASE = IGEN.IDCLASE
		INNER JOIN ICLAH ON ICLAH.IDCLASE = ICLA.IDCLASE AND ICLAH.IDSUBCLASE = IGEN.IDSUBCLASE
		INNER JOIN IGRU ON IGRU.IDSUBCLASE = ICLAH.IDSUBCLASE AND IGRU.IDGRUPO = IGEN.IDGRUPO
		INNER JOIN IPAC ON IPAC.IDPRINACTIVO = IGEN.IDPRINACTIVO
		LEFT JOIN DBO.IDCI WITH (NOLOCK) ON IDCI.CODIGO = IGEN.CODIGO_DCI
		WHERE IDGENERICO = @IDGENERICO
		RETURN
	END

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDGENERICO = IDGENERICO, @DESCRIPCION = DESCRIPCION, @IDCLASE = IDCLASE,
					@IDSUBCLASE = IDSUBCLASE, @IDGRUPO = IDGRUPO, @IDPRINACTIVO = IDPRINACTIVO,
					@IDTGENERICO = IDTGENERICO, @CODIGO_DCI = CODIGO_DCI
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				IDGENERICO	VARCHAR(20) '$.IDGENERICO', DESCRIPCION VARCHAR(100) '$.DESCRIPCION', IDCLASE		VARCHAR(2)	'$.IDCLASE',
				IDSUBCLASE	VARCHAR(4)  '$.IDSUBCLASE', IDGRUPO		VARCHAR(4)	 '$.IDGRUPO',	  IDPRINACTIVO	VARCHAR(10) '$.IDPRINACTIVO',
				IDTGENERICO VARCHAR(20) '$.IDTGENERICO', CODIGO_DCI VARCHAR(20) '$.CODIGO_DCI'
			)

			SET @CODIGO_DCI = NULLIF(LTRIM(RTRIM(@CODIGO_DCI)), '')

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'El c�digo DCI "' + @CODIGO_DCI + '" no existe en la tabla IDCI'
			WHERE @CODIGO_DCI IS NOT NULL AND NOT EXISTS (SELECT 1 FROM DBO.IDCI WITH (NOLOCK) WHERE CODIGO = @CODIGO_DCI)

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'EL GENERICO YA EXISTE'
			WHERE EXISTS (SELECT * FROM IGEN WHERE IDGENERICO = @IDGENERICO)

			IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
			BEGIN
				INSERT INTO IGEN (IDGENERICO ,DESCRIPCION ,IDCLASE ,IDSUBCLASE ,IDGRUPO ,IDPRINACTIVO ,IDTGENERICO ,CODIGO_DCI )
				SELECT @IDGENERICO, @DESCRIPCION, @IDCLASE, @IDSUBCLASE, @IDGRUPO, @IDPRINACTIVO, @IDTGENERICO, @CODIGO_DCI
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ACTUALIZAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDGENERICO = IDGENERICO, @DESCRIPCION = DESCRIPCION, @IDCLASE = IDCLASE,
					@IDSUBCLASE = IDSUBCLASE, @IDGRUPO = IDGRUPO, @IDPRINACTIVO = IDPRINACTIVO,
					@IDTGENERICO = IDTGENERICO, @CODIGO_DCI = CODIGO_DCI
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				IDGENERICO	VARCHAR(20) '$.IDGENERICO', DESCRIPCION VARCHAR(100) '$.DESCRIPCION', IDCLASE		VARCHAR(2)	'$.IDCLASE',
				IDSUBCLASE	VARCHAR(4)  '$.IDSUBCLASE', IDGRUPO		VARCHAR(4)	 '$.IDGRUPO',	  IDPRINACTIVO	VARCHAR(10) '$.IDPRINACTIVO',
				IDTGENERICO VARCHAR(20) '$.IDTGENERICO', CODIGO_DCI VARCHAR(20) '$.CODIGO_DCI'
			)

			SET @CODIGO_DCI = NULLIF(LTRIM(RTRIM(@CODIGO_DCI)), '')

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'El c�digo DCI "' + @CODIGO_DCI + '" no existe en la tabla IDCI'
			WHERE @CODIGO_DCI IS NOT NULL AND NOT EXISTS (SELECT 1 FROM DBO.IDCI WITH (NOLOCK) WHERE CODIGO = @CODIGO_DCI)

			IF (SELECT COUNT(*) FROM @TBLERRORES) <= 0
			BEGIN
				UPDATE IGEN SET DESCRIPCION = @DESCRIPCION, IDCLASE = @IDCLASE,	IDSUBCLASE = @IDSUBCLASE, IDGRUPO = @IDGRUPO,
								IDPRINACTIVO = @IDPRINACTIVO, IDTGENERICO = @IDTGENERICO, CODIGO_DCI = @CODIGO_DCI
				WHERE IDGENERICO = @IDGENERICO
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
	
	IF @METODO = 'ELIMINAR'
	BEGIN
		BEGIN TRY
			SELECT @IDGENERICO = JSON_VALUE(@PARAMETROS, '$.IDGENERICO')

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'EL GENERICO TIENE ARTICULOS RELACIONADOS (IART)'
			WHERE EXISTS (SELECT * FROM IART WHERE IDGENERICO = @IDGENERICO)

			IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
			BEGIN
				DELETE FROM IGEN WHERE IDGENERICO = @IDGENERICO
			END		
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
END
