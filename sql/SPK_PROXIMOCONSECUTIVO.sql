IF EXISTS (SELECT NAME FROM SYSOBJECTS WHERE NAME = 'SPK_PROXIMOCONSECUTIVO' AND TYPE = 'P')
	DROP PROCEDURE SPK_PROXIMOCONSECUTIVO

GO
CREATE PROCEDURE DBO.SPK_PROXIMOCONSECUTIVO  
@COMPANIA  VARCHAR(2),  
@SEDE      VARCHAR(5),  
@PREFIJO   VARCHAR(10),   
@NVOCONSEC VARCHAR(20) OUTPUT
WITH ENCRYPTION
AS  
DECLARE @EXISTE INT
BEGIN  
	IF @PREFIJO IS NULL
	BEGIN
		PRINT 'ES NULL EL PREFIJO'
	END

	SELECT @EXISTE = COUNT(*) FROM USCXS
	WHERE COMPANIA = @COMPANIA  
	AND   IDSEDE   = @SEDE  
	AND   PREFIJO  = @PREFIJO  
        IF @EXISTE  > 0  
	BEGIN
		SELECT @NVOCONSEC = CONSECUTIVO + 1 FROM USCXS  
		WHERE  COMPANIA   = @COMPANIA  
		AND    IDSEDE     = @SEDE  
		AND    PREFIJO    = @PREFIJO

	END
	ELSE
	BEGIN
		SET @NVOCONSEC = 1
	END

END
