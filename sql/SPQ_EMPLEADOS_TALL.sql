CREATE OR ALTER PROCEDURE DBO.SPQ_EMPLEADOS_TALL @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @EMPLEADOS NVARCHAR(MAX), @IDCAP INT
DECLARE @USUARIO VARCHAR(20), @PROCESO VARCHAR(20), @TALLERID INT
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'EMPLEADOS_EVALUAR'
	BEGIN
		SELECT @IDCAP = IDCAP, @TALLERID = TALLERID
		FROM OPENJSON(@PARAMETROS) WITH (IDCAP INT '$.IDCAP', TALLERID INT '$.TALLERID')

		SELECT 'OK' OK

		SELECT NEMP.NUMDOC, DOCIDEMPLEADO, CONCAT (PRIMERNOMBRE, ' ', PRIMERAPELLIDO) NOMBRE, 'Pendiente' AS ESTADO
		FROM NEMP
		INNER JOIN CAPASI ON CAPASI.NUMDOC = NEMP.NUMDOC
		INNER JOIN CEN ON CEN.CCOSTO = NEMP.CCOSTO
		WHERE IDCAPD = @IDCAP AND ISACTIVA = 1 AND CAPASI.ASISTENCIA = 1
		
		UNION
		
		SELECT NEMP.NUMDOC, DOCIDEMPLEADO, CONCAT (PRIMERNOMBRE, ' ', PRIMERAPELLIDO) NOMBRE, TASIGNACION.ESTADO
		FROM TASIGNACION
		INNER JOIN NEMP ON TASIGNACION.NUMDOC = NEMP.NUMDOC
		INNER JOIN CEN ON CEN.CCOSTO = NEMP.CCOSTO
		WHERE TASIGNACION.TALLERID = @TALLERID

		RETURN
	END

	IF @METODO = 'GUARDAR_EMPLEADOS_ASIS_CAP'
	BEGIN
		SELECT @EMPLEADOS = EMPLEADOS, @TALLERID = TALLERID
		FROM OPENJSON(@PARAMETROS) WITH (EMPLEADOS NVARCHAR(MAX) '$.EMPLEADOS' AS JSON, TALLERID INT '$.TALLERID')

		-- Tabla temporal para los empleados
		DECLARE @TBL_EMPLEADOS TABLE (NUMDOC VARCHAR(20))

		-- Cargar los empleados del JSON al tabla temporal
		INSERT INTO @TBL_EMPLEADOS (NUMDOC)
		SELECT NUMDOC
		FROM OPENJSON(@EMPLEADOS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC')

		BEGIN TRY
			BEGIN TRAN;

			INSERT INTO dbo.TASIGNACION (TALLERID, NUMDOC, FECHAASIGNACION, ESTADO)
			SELECT @TALLERID, E.NUMDOC, GETDATE(), 'Pendiente'
			FROM @TBL_EMPLEADOS E
			WHERE NOT EXISTS (
					SELECT 1
					FROM dbo.TASIGNACION T
					WHERE T.TALLERID = @TALLERID AND T.NUMDOC = E.NUMDOC
					)

			COMMIT TRAN;
		END TRY

		BEGIN CATCH
			IF @@TRANCOUNT > 0
			BEGIN
				ROLLBACK TRAN;
			END

			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK

		RETURN
	END

	IF @METODO = 'EMPEADOS_ASIGNAR_TALLER'
	BEGIN
		BEGIN TRY
			SELECT @TALLERID = TALLERID, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (TALLERID INT '$.TALLERID', PROCESO VARCHAR(20) '$.PROCESO')

			IF UPPER(@PROCESO) = 'GUARDAR'
			BEGIN
				BEGIN TRY
					SELECT @EMPLEADOS = JSON_QUERY(@PARAMETROS, '$.EMPLEADOS')

					CREATE TABLE #Empleados (EMPLEADO VARCHAR(20) COLLATE SQL_Latin1_General_CP1_CI_AS);

					INSERT INTO #Empleados (EMPLEADO)
					SELECT value
					FROM OPENJSON(@EMPLEADOS);

					-- INSERTAR NUEVOS EMPLEADOS
					INSERT INTO TASIGNACION (TALLERID, NUMDOC, FECHAASIGNACION, ESTADO)
					SELECT @TALLERID, E.EMPLEADO, GETDATE(), 'Pendiente'
					FROM #Empleados E
					WHERE NOT EXISTS (
							SELECT 1
							FROM TASIGNACION T
							WHERE T.TALLERID = @TALLERID AND T.NUMDOC = E.EMPLEADO
							);

					-- ELIMINAR EMPLEADOS YA NO PRESENTES
					DELETE T
					FROM TASIGNACION T
					WHERE T.TALLERID = @TALLERID AND NOT EXISTS (
							SELECT 1
							FROM #Empleados E
							WHERE E.EMPLEADO = T.NUMDOC
							);

					DROP TABLE #Empleados;
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
