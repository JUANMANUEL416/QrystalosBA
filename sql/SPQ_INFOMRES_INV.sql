            CONVERT(DECIMAL(18,6), ISAL.CANTIDAD) SALIDA_CANTIDAD,
            CONVERT(DECIMAL(14,2), ISAL.PCOSTO) SALIDA_COSTO_UNIT,
            CONVERT(DECIMAL(14,2), ISAL.CANTIDAD * ISAL.PCOSTO) SALIDA_COSTO_TOTAL,
            CONVERT(DECIMAL(18,6), NULL) SALDO_CANTIDAD,
            CONVERT(DECIMAL(14,2), NULL) SALDO_COSTO_UNIT,
            CONVERT(DECIMAL(14,2), NULL) SALDO_COSTO_TOTAL,
            COALESCE(USU_CONF.NOMBRE, COALESCE(IMOV.USUARIOCONF, IMOV.USUARIO)) USUARIO_CONF
         FROM ISAL WITH (NOLOCK)
         INNER JOIN IMOV WITH (NOLOCK) ON ISAL.CNSMOV = IMOV.CNSMOV
         INNER JOIN IART WITH (NOLOCK) ON IART.IDARTICULO = ISAL.IDARTICULO
            AND COALESCE(IART.PRINCIPAL,0) = 0 AND IART.ESTADO = 'Activo'
         INNER JOIN ITMO WITH (NOLOCK) ON IMOV.IDTIPOMOV = ITMO.IDTIPOMOV
         LEFT JOIN TER WITH (NOLOCK) ON IMOV.IDTERCERO = TER.IDTERCERO
         LEFT JOIN USUSU USU_CONF WITH (NOLOCK) ON USU_CONF.USUARIO = COALESCE(IMOV.USUARIOCONF, IMOV.USUARIO)
         WHERE ISAL.IDARTICULO = CASE WHEN COALESCE(@IDARTICULO,'') <> '' THEN @IDARTICULO ELSE ISAL.IDARTICULO END
           AND IMOV.ESTADO = 1 AND ITMO.TIPO = 'Debito'
           AND COALESCE(IMOV.FECHACONF, IMOV.FECHAMOV) >= @F_INICIAL
           AND COALESCE(IMOV.FECHACONF, IMOV.FECHAMOV) < @F_FINAL + 1
           AND IMOV.IDBODEGA = CASE WHEN COALESCE(@IDBODEGA,'Todas') <> 'Todas' THEN @IDBODEGA ELSE IMOV.IDBODEGA END
           AND IMOV.IDTIPOMOV = CASE WHEN COALESCE(@TIPOMOV,'Todos') <> 'Todos' THEN @TIPOMOV ELSE IMOV.IDTIPOMOV END
      )
      SELECT
         IDARTICULO, DESCRIPCION_ART,
         FECHA, HORA, TIPO_MOV, CNSMOV, NODOCUMENTO, PROCEDENCIA, NOLOTE, DESCRIPCION_MOV,
         ENTRADA_CANTIDAD, ENTRADA_COSTO_UNIT, ENTRADA_COSTO_TOTAL,
         SALIDA_CANTIDAD, SALIDA_COSTO_UNIT, SALIDA_COSTO_TOTAL,
         SALDO_CANTIDAD, SALDO_COSTO_UNIT, SALDO_COSTO_TOTAL, USUARIO_CONF
      FROM K
      ORDER BY K.IDARTICULO ASC, K.FECHA_ORD ASC, K.CNSMOV ASC

