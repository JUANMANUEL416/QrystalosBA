               ITMO.DESCRIPCION
               + CASE WHEN COALESCE(TER.RAZONSOCIAL,'') <> '' THEN ' | Tercero: ' + TER.RAZONSOCIAL ELSE '' END
               + CASE WHEN COALESCE(IMOV.OBSERVACION,'') <> '' THEN ' | Obs: ' + IMOV.OBSERVACION ELSE '' END
            )) DESCRIPCION_MOV,
            CONVERT(DECIMAL(18,6), CASE WHEN ITMO.TIPO='Credito' THEN IMOVH.CANTIDAD ELSE 0 END) ENTRADA_CANTIDAD,
            CONVERT(DECIMAL(14,2), CASE WHEN ITMO.TIPO='Credito' THEN IMOVH.PCOSTO ELSE 0 END) ENTRADA_COSTO_UNIT,
