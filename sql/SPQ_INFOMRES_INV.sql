        AND A.IDSERVICIO COLLATE DATABASE_DEFAULT = K.IDSERVICIO COLLATE DATABASE_DEFAULT
        AND A.CLASE COLLATE DATABASE_DEFAULT = K.CLASE COLLATE DATABASE_DEFAULT
