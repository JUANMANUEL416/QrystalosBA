CREATE OR ALTER PROCEDURE DBO.SPQ_INFOMRES_INV @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
SET DATEFORMAT dmy
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE  @PARAMETROS NVARCHAR(MAX)			,@MODELO VARCHAR(100)			    ,@METODO VARCHAR(100)
		,@USUARIO VARCHAR(12)				   ,@COMPANIA VARCHAR(2)		       ,@IDSEDE      VARCHAR(5)		
      ,@SYS_COMPUTERNAME VARCHAR(200)     ,@DATOS    VARCHAR(MAX)           ,@IDTIPOMOV VARCHAR(20)
      ,@IDARTICULO VARCHAR(20)            ,@PCOSTO   DECIMAL(14,2)          ,@IDBODEGA VARCHAR(20)
      ,@TIPOMOV VARCHAR(20)               ,@F_INICIAL DATETIME              ,@F_FINAL DATETIME
      ,@CNSRPDX VARCHAR(20)               ,@NOLOTE    VARCHAR(20)           ,@CNSLOG VARCHAR(20)
      ,@TBODEGA VARCHAR(20)               ,@SVENTAS BIT                     ,@ANO VARCHAR(4)
      ,@MES SMALLINT                      ,@HERMANO_MAYOR VARCHAR(20)
      ,@ES_HIJO BIT                       ,@ART_CAB VARCHAR(20)
      ,@FILTRO_ART_PRINCIPAL VARCHAR(10)  -- USVGS INF_ART_X_PRINCIPAL: SI=principal+hermanos, NO=hijo
      ,@SALDO_APERTURA DECIMAL(18,6)
BEGIN
	BEGIN TRY

	SELECT *
	INTO #JSON
	FROM OPENJSON(@json) WITH (
			MODELO VARCHAR(100) '$.MODELO'
			,METODO VARCHAR(100) '$.METODO'
			,USUARIO VARCHAR(12) '$.USUARIO'
			,PARAMETROS NVARCHAR(MAX) AS JSON
	)

	SELECT   @MODELO = MODELO			,@METODO = METODO
			,@PARAMETROS = PARAMETROS	,@USUARIO = USUARIO
	FROM #JSON

	SELECT @FILTRO_ART_PRINCIPAL = UPPER(LTRIM(RTRIM(COALESCE(DBO.FNK_VALORVARIABLE('INF_ART_X_PRINCIPAL'), 'SI'))))
	IF @FILTRO_ART_PRINCIPAL NOT IN ('SI', 'NO')
		SET @FILTRO_ART_PRINCIPAL = 'SI'

   IF @METODO='IBOD_ITAR'     
   BEGIN         
      SELECT 'OK' OK
      SELECT IDBODEGA as value, DESCRIPCION AS label FROM IBOD
      WHERE EXISTS(SELECT * FROM IEXI WHERE IEXI.IDBODEGA=IBOD.IDBODEGA)
      AND IBOD.ESTADO='Activo'
      ORDER BY IBOD.IDBODEGA

      SELECT IDITAR AS value, DESCRIPCION AS label
      FROM ITAR 
      ORDER BY IDITAR ASC

      RETURN
   END   
   IF @METODO='SOLO_IBOD'     
   BEGIN         
      SELECT 'OK' OK

      SELECT IDBODEGA as value, DESCRIPCION AS label FROM IBOD
      WHERE EXISTS(SELECT * FROM IEXI WHERE IEXI.IDBODEGA=IBOD.IDBODEGA)
      AND IBOD.ESTADO='Activo'
      ORDER BY IBOD.IDBODEGA
      RETURN
    END 
   IF @METODO='IBOD_ITMO'     
   BEGIN         
      SELECT 'OK' OK
      SELECT IDBODEGA as value, DESCRIPCION AS label FROM IBOD
      WHERE EXISTS(SELECT * FROM IEXI WHERE IEXI.IDBODEGA=IBOD.IDBODEGA)
      AND IBOD.ESTADO='Activo'
      ORDER BY IBOD.IDBODEGA

      SELECT IDTIPOMOV AS value, DESCRIPCION AS label
      FROM ITMO 
      ORDER BY IDTIPOMOV ASC

      RETURN
    END 
   IF @METODO='TRAE_EXISTS'     
   BEGIN         
      SELECT @IDARTICULO=IDARTICULO, @NOLOTE=NOLOTE
      FROM   OPENJSON (@PARAMETROS)
      WITH (           
          IDARTICULO VARCHAR(20) '$.IDARTICULO',
          NOLOTE     VARCHAR(20) '$.NOLOTE'
            )

      IF COALESCE(@IDARTICULO,'')='' OR NOT EXISTS(SELECT 1 FROM IART WHERE IDARTICULO=@IDARTICULO)
      BEGIN
         SELECT 'KO'KO
         RETURN
      END

      /* Sin lote: respeta USVGS INF_ART_X_PRINCIPAL (SI=principal, NO=hijo) */
      IF COALESCE(@NOLOTE,'')=''
      BEGIN
         IF @FILTRO_ART_PRINCIPAL = 'SI'
            AND EXISTS(SELECT 1 FROM IART WHERE IDARTICULO=@IDARTICULO AND COALESCE(PRINCIPAL,0)=0)
         BEGIN
            SELECT 'KO' KO, 'Consulta configurada por art�culo principal (INF_ART_X_PRINCIPAL=SI).' ERROR
            RETURN
         END
         IF @FILTRO_ART_PRINCIPAL = 'NO'
            AND EXISTS(SELECT 1 FROM IART WHERE IDARTICULO=@IDARTICULO AND COALESCE(PRINCIPAL,0)=1)
         BEGIN
            SELECT 'KO' KO, 'Consulta configurada por art�culo hijo (INF_ART_X_PRINCIPAL=NO).' ERROR
            RETURN
         END
      END

      /* Consulta por lote espec�fico (trazabilidad) */
      IF COALESCE(@NOLOTE,'')<>''
      BEGIN
         SELECT @PCOSTO = COALESCE(
            (SELECT TOP 1 PCOSTO FROM IEXI WHERE IDARTICULO=@IDARTICULO AND NOLOTE=@NOLOTE AND COALESCE(PCOSTO,0)>0),
            (SELECT PCOSTO FROM IART WHERE IDARTICULO=@IDARTICULO),
            0
         )
         SELECT 'OK'OK,@PCOSTO PCOSTO
         SELECT IEXI.IDBODEGA, IBOD.DESCRIPCION, SUM(COALESCE(IEXI.EXISLOTE,0)) CANTIDAD
         FROM IEXI
            INNER JOIN IBOD ON IEXI.IDBODEGA=IBOD.IDBODEGA
         WHERE IEXI.IDARTICULO=@IDARTICULO
           AND IEXI.NOLOTE=@NOLOTE
         GROUP BY IEXI.IDBODEGA, IBOD.DESCRIPCION
         HAVING SUM(COALESCE(IEXI.EXISLOTE,0))>0
         RETURN
      END

      /* Consulta por art�culo hijo (PRINCIPAL=0): consolida todos los lotes del IDARTICULO */
      IF EXISTS(SELECT 1 FROM IART WHERE IDARTICULO=@IDARTICULO AND COALESCE(PRINCIPAL,0)=0)
      BEGIN
         SELECT @PCOSTO = COALESCE((SELECT PCOSTO FROM IART WHERE IDARTICULO=@IDARTICULO), 0)
         SELECT 'OK'OK,@PCOSTO PCOSTO
         SELECT IEXI.IDBODEGA, IBOD.DESCRIPCION, SUM(COALESCE(IEXI.EXISLOTE,0)) CANTIDAD
         FROM IEXI
            INNER JOIN IBOD ON IEXI.IDBODEGA=IBOD.IDBODEGA
         WHERE IEXI.IDARTICULO=@IDARTICULO
         GROUP BY IEXI.IDBODEGA, IBOD.DESCRIPCION
         HAVING SUM(COALESCE(IEXI.EXISLOTE,0))>0
         RETURN
      END

      /* Consulta por art�culo principal: consolida hermanos */
      SELECT @HERMANO_MAYOR = COALESCE(
         (SELECT TOP 1 HERMANO_MAYOR FROM VWK_HERMANOS_INVENTARIO WHERE IDARTICULO = @IDARTICULO),
         @IDARTICULO
      )
      IF EXISTS(SELECT 1 FROM IART WHERE IDARTICULO=@IDARTICULO AND COALESCE(PRINCIPAL,0)=1)
         AND EXISTS(SELECT 1 FROM VWK_HERMANOS_INVENTARIO WHERE HERMANO_MAYOR=@HERMANO_MAYOR)
      BEGIN
         SELECT @PCOSTO=PCOSTO FROM IART WHERE IDARTICULO=@HERMANO_MAYOR
         SELECT 'OK'OK,@PCOSTO PCOSTO 

         SELECT IEXI.IDBODEGA,IBOD.DESCRIPCION,SUM(COALESCE(IEXI.EXISLOTE,0))CANTIDAD
         FROM IEXI 
            INNER JOIN VWK_HERMANOS_INVENTARIO VHI ON VHI.IDARTICULO = IEXI.IDARTICULO
            INNER JOIN IBOD ON IEXI.IDBODEGA=IBOD.IDBODEGA
         WHERE VHI.HERMANO_MAYOR=@HERMANO_MAYOR
         GROUP BY IEXI.IDBODEGA,IBOD.DESCRIPCION
         HAVING SUM(COALESCE(IEXI.EXISLOTE,0))>0

         RETURN
      END
      ELSE
      BEGIN
         SELECT 'KO'KO
         RETURN
      END
        
   END   
   IF @METODO='BUSCAR_MOV'     
   BEGIN         
      SELECT @DATOS=DATOS        
      FROM   OPENJSON (@PARAMETROS)
      WITH (           
         DATOS NVARCHAR(MAX) AS JSON 
            )           
      
         SELECT @IDBODEGA=IDBODEGA,   @TIPOMOV=TIPOMOV,  @F_INICIAL=CONVERT(DATETIME,F_INICIAL), @F_FINAL=CONVERT(DATETIME,F_FINAL), @IDARTICULO=IDARTICULO,
                @NOLOTE=NOLOTE
         FROM   OPENJSON (@DATOS)
         WITH   ( 
         IDBODEGA VARCHAR(20)       '$.IDBODEGA',
         TIPOMOV VARCHAR(20)       '$.TIPOMOV',
         F_INICIAL DATE        '$.F_INICIAL',
         F_FINAL DATE           '$.F_FINAL',
         IDARTICULO VARCHAR(20)    '$.IDARTICULO',
         NOLOTE VARCHAR(20)        '$.NOLOTE'
         )

         IF COALESCE(@IDARTICULO,'')='' OR NOT EXISTS(SELECT 1 FROM IART WHERE IDARTICULO=@IDARTICULO)
         BEGIN
            SELECT 'KO'KO
            RETURN
         END

         IF COALESCE(@NOLOTE,'')=''
         BEGIN
            IF @FILTRO_ART_PRINCIPAL = 'SI'
               AND EXISTS(SELECT 1 FROM IART WHERE IDARTICULO=@IDARTICULO AND COALESCE(PRINCIPAL,0)=0)
            BEGIN
               SELECT 'KO' KO, 'Consulta configurada por art�culo principal (INF_ART_X_PRINCIPAL=SI).' ERROR
               RETURN
            END
            IF @FILTRO_ART_PRINCIPAL = 'NO'
               AND EXISTS(SELECT 1 FROM IART WHERE IDARTICULO=@IDARTICULO AND COALESCE(PRINCIPAL,0)=1)
            BEGIN
               SELECT 'KO' KO, 'Consulta configurada por art�culo hijo (INF_ART_X_PRINCIPAL=NO).' ERROR
               RETURN
            END
         END

         /* ===== Por lote espec�fico ===== */
         IF COALESCE(@NOLOTE,'')<>''
         BEGIN
            SELECT @PCOSTO = COALESCE(
               (SELECT TOP 1 PCOSTO FROM IEXI WHERE IDARTICULO=@IDARTICULO AND NOLOTE=@NOLOTE AND COALESCE(PCOSTO,0)>0),
               (SELECT PCOSTO FROM IART WHERE IDARTICULO=@IDARTICULO),
               0
            )
            SELECT 'OK' OK

            SELECT IMOV.IDBODEGA, IMOV.IDTIPOMOV, ITMO.DESCRIPCION, SUM(IMOVH.CANTIDAD)CANTIDAD,
                   CONVERT(DECIMAL(14,2),SUM(COALESCE(IMOVH.CANTIDAD,0)) * @PCOSTO) PCOSTO
            FROM IMOV INNER JOIN IMOVH ON IMOV.CNSMOV=IMOVH.CNSMOV
                     INNER JOIN ITMO  ON IMOV.IDTIPOMOV=ITMO.IDTIPOMOV
            WHERE IMOV.ESTADO=1 AND IMOVH.ESTADO=1 AND ITMO.TIPO='Credito'
              AND IMOVH.IDARTICULO=@IDARTICULO
              AND IMOVH.NOLOTE=@NOLOTE
              AND IMOV.IDBODEGA=CASE WHEN COALESCE(@IDBODEGA,'Todas') <> 'Todas' THEN @IDBODEGA ELSE IMOV.IDBODEGA END
              AND IMOV.IDTIPOMOV=CASE WHEN COALESCE(@TIPOMOV,'Todos') <> 'Todos' THEN  @TIPOMOV ELSE IMOV.IDTIPOMOV END
              AND COALESCE(IMOV.FECHACONF, IMOV.FECHAMOV)>=@F_INICIAL
              AND COALESCE(IMOV.FECHACONF, IMOV.FECHAMOV)<@F_FINAL+1
            GROUP BY IMOV.IDBODEGA, IMOV.IDTIPOMOV, ITMO.DESCRIPCION

            SELECT IDBODEGA, IDTIPOMOV, DESCRIPCION, SUM(CANTIDAD)CANTIDAD,
                   CONVERT(DECIMAL(14,2),SUM(COALESCE(CANTIDAD,0)) * @PCOSTO) PCOSTO
            FROM (
               SELECT IMOV.IDBODEGA, IMOV.IDTIPOMOV, ITMO.DESCRIPCION, ISAL.CANTIDAD, ISAL.PCOSTO
               FROM IMOV INNER JOIN ISAL ON IMOV.CNSMOV=ISAL.CNSMOV
                        INNER JOIN ITMO ON IMOV.IDTIPOMOV=ITMO.IDTIPOMOV
               WHERE IMOV.ESTADO=1 AND ITMO.TIPO='Debito'
                 AND ISAL.IDARTICULO=@IDARTICULO
                 AND ISAL.NOLOTE=@NOLOTE
                 AND IMOV.IDBODEGA=CASE WHEN COALESCE(@IDBODEGA,'Todas') <> 'Todas' THEN @IDBODEGA ELSE IMOV.IDBODEGA END
                 AND IMOV.IDTIPOMOV=CASE WHEN COALESCE(@TIPOMOV,'Todos') <> 'Todos' THEN @TIPOMOV ELSE IMOV.IDTIPOMOV END
                 AND COALESCE(IMOV.FECHACONF, IMOV.FECHAMOV)>=@F_INICIAL
                 AND COALESCE(IMOV.FECHACONF, IMOV.FECHAMOV)<@F_FINAL+1
               UNION ALL
               /* Respaldo IMOVH: se usa solo si no existe entrega f�sica ISAL equivalente. */
               SELECT IMOV.IDBODEGA, IMOV.IDTIPOMOV, ITMO.DESCRIPCION, IMOVH.CANTIDAD, IMOVH.PCOSTO
               FROM IMOV INNER JOIN IMOVH ON IMOV.CNSMOV=IMOVH.CNSMOV
                        INNER JOIN ITMO ON IMOV.IDTIPOMOV=ITMO.IDTIPOMOV
               WHERE IMOV.ESTADO=1 AND IMOVH.ESTADO=1 AND ITMO.TIPO='Debito'
                 AND IMOVH.IDARTICULO=@IDARTICULO
                 AND IMOVH.NOLOTE=@NOLOTE
                 AND IMOV.IDBODEGA=CASE WHEN COALESCE(@IDBODEGA,'Todas') <> 'Todas' THEN @IDBODEGA ELSE IMOV.IDBODEGA END
                 AND IMOV.IDTIPOMOV=CASE WHEN COALESCE(@TIPOMOV,'Todos') <> 'Todos' THEN @TIPOMOV ELSE IMOV.IDTIPOMOV END
                 AND COALESCE(IMOV.FECHACONF, IMOV.FECHAMOV)>=@F_INICIAL
                 AND COALESCE(IMOV.FECHACONF, IMOV.FECHAMOV)<@F_FINAL+1
                 AND NOT EXISTS (
                    SELECT 1 FROM ISAL S
                    WHERE S.CNSMOV = IMOV.CNSMOV
                      AND S.IDARTICULO = IMOVH.IDARTICULO
                      AND S.NOLOTE = IMOVH.NOLOTE
                 )
            ) SAL
            GROUP BY IDBODEGA, IDTIPOMOV, DESCRIPCION
            RETURN
         END

         /* ===== Por art�culo hijo (PRINCIPAL=0): todos los lotes del IDARTICULO ===== */
         IF EXISTS(SELECT 1 FROM IART WHERE IDARTICULO=@IDARTICULO AND COALESCE(PRINCIPAL,0)=0)
         BEGIN
            SELECT @PCOSTO = COALESCE((SELECT PCOSTO FROM IART WHERE IDARTICULO=@IDARTICULO), 0)
            SELECT 'OK' OK

            SELECT IMOV.IDBODEGA, IMOV.IDTIPOMOV, ITMO.DESCRIPCION, SUM(IMOVH.CANTIDAD)CANTIDAD,
                   CONVERT(DECIMAL(14,2),SUM(COALESCE(IMOVH.CANTIDAD,0)) * @PCOSTO) PCOSTO
            FROM IMOV INNER JOIN IMOVH ON IMOV.CNSMOV=IMOVH.CNSMOV
                     INNER JOIN ITMO  ON IMOV.IDTIPOMOV=ITMO.IDTIPOMOV
            WHERE IMOV.ESTADO=1 AND IMOVH.ESTADO=1 AND ITMO.TIPO='Credito'
              AND IMOVH.IDARTICULO=@IDARTICULO
              AND IMOV.IDBODEGA=CASE WHEN COALESCE(@IDBODEGA,'Todas') <> 'Todas' THEN @IDBODEGA ELSE IMOV.IDBODEGA END
              AND IMOV.IDTIPOMOV=CASE WHEN COALESCE(@TIPOMOV,'Todos') <> 'Todos' THEN  @TIPOMOV ELSE IMOV.IDTIPOMOV END
              AND COALESCE(IMOV.FECHACONF, IMOV.FECHAMOV)>=@F_INICIAL
              AND COALESCE(IMOV.FECHACONF, IMOV.FECHAMOV)<@F_FINAL+1
            GROUP BY IMOV.IDBODEGA, IMOV.IDTIPOMOV, ITMO.DESCRIPCION

            SELECT IDBODEGA, IDTIPOMOV, DESCRIPCION, SUM(CANTIDAD)CANTIDAD,
                   CONVERT(DECIMAL(14,2),SUM(COALESCE(CANTIDAD,0)) * @PCOSTO) PCOSTO
            FROM (
               SELECT IMOV.IDBODEGA, IMOV.IDTIPOMOV, ITMO.DESCRIPCION, ISAL.CANTIDAD, ISAL.PCOSTO
               FROM IMOV INNER JOIN ISAL ON IMOV.CNSMOV=ISAL.CNSMOV
                        INNER JOIN ITMO ON IMOV.IDTIPOMOV=ITMO.IDTIPOMOV
               WHERE IMOV.ESTADO=1 AND ITMO.TIPO='Debito'
                 AND ISAL.IDARTICULO=@IDARTICULO
                 AND IMOV.IDBODEGA=CASE WHEN COALESCE(@IDBODEGA,'Todas') <> 'Todas' THEN @IDBODEGA ELSE IMOV.IDBODEGA END
                 AND IMOV.IDTIPOMOV=CASE WHEN COALESCE(@TIPOMOV,'Todos') <> 'Todos' THEN @TIPOMOV ELSE IMOV.IDTIPOMOV END
                 AND COALESCE(IMOV.FECHACONF, IMOV.FECHAMOV)>=@F_INICIAL
                 AND COALESCE(IMOV.FECHACONF, IMOV.FECHAMOV)<@F_FINAL+1
               UNION ALL
               /* Respaldo IMOVH: se usa solo si no existe entrega f�sica ISAL equivalente. */
               SELECT IMOV.IDBODEGA, IMOV.IDTIPOMOV, ITMO.DESCRIPCION, IMOVH.CANTIDAD, IMOVH.PCOSTO
               FROM IMOV INNER JOIN IMOVH ON IMOV.CNSMOV=IMOVH.CNSMOV
                        INNER JOIN ITMO ON IMOV.IDTIPOMOV=ITMO.IDTIPOMOV
               WHERE IMOV.ESTADO=1 AND IMOVH.ESTADO=1 AND ITMO.TIPO='Debito'
                 AND IMOVH.IDARTICULO=@IDARTICULO
                 AND IMOV.IDBODEGA=CASE WHEN COALESCE(@IDBODEGA,'Todas') <> 'Todas' THEN @IDBODEGA ELSE IMOV.IDBODEGA END
                 AND IMOV.IDTIPOMOV=CASE WHEN COALESCE(@TIPOMOV,'Todos') <> 'Todos' THEN @TIPOMOV ELSE IMOV.IDTIPOMOV END
                 AND COALESCE(IMOV.FECHACONF, IMOV.FECHAMOV)>=@F_INICIAL
                 AND COALESCE(IMOV.FECHACONF, IMOV.FECHAMOV)<@F_FINAL+1
                 AND NOT EXISTS (
                    SELECT 1 FROM ISAL S
                    WHERE S.CNSMOV = IMOV.CNSMOV
                      AND S.IDARTICULO = IMOVH.IDARTICULO
                      AND S.NOLOTE = IMOVH.NOLOTE
                 )
            ) SAL
            GROUP BY IDBODEGA, IDTIPOMOV, DESCRIPCION
            RETURN
         END

         /* ===== Por art�culo principal: consolida hermanos ===== */
         SELECT @HERMANO_MAYOR = COALESCE(
            (SELECT TOP 1 HERMANO_MAYOR FROM VWK_HERMANOS_INVENTARIO WHERE IDARTICULO = @IDARTICULO),
            @IDARTICULO
         )
         IF EXISTS(SELECT 1 FROM IART WHERE IDARTICULO=@IDARTICULO AND COALESCE(PRINCIPAL,0)=1)
            AND EXISTS(SELECT 1 FROM VWK_HERMANOS_INVENTARIO WHERE HERMANO_MAYOR=@HERMANO_MAYOR)
         BEGIN
            SELECT @PCOSTO=COALESCE(PCOSTO,0) FROM IART WHERE IDARTICULO=@HERMANO_MAYOR
            SELECT 'OK' OK
            PRINT 'Entradas'
            SELECT IMOV.IDBODEGA, IMOV.IDTIPOMOV, ITMO.DESCRIPCION, SUM(IMOVH.CANTIDAD)CANTIDAD, CONVERT(DECIMAL(14,2),SUM(COALESCE(IMOVH.CANTIDAD,0)) * @PCOSTO) PCOSTO
            FROM IMOV INNER JOIN IMOVH ON IMOV.CNSMOV=IMOVH.CNSMOV  
                     INNER JOIN ITMO  ON IMOV.IDTIPOMOV=ITMO.IDTIPOMOV 
            WHERE IMOV.ESTADO=1 AND IMOVH.ESTADO=1 AND ITMO.TIPO='Credito' 
            AND   IMOVH.IDARTICULO IN (SELECT IDARTICULO FROM VWK_HERMANOS_INVENTARIO WHERE HERMANO_MAYOR=@HERMANO_MAYOR)
            AND   IMOV.IDBODEGA=CASE WHEN COALESCE(@IDBODEGA,'Todas') <> 'Todas' THEN @IDBODEGA ELSE IMOV.IDBODEGA END 
            AND   IMOV.IDTIPOMOV=CASE WHEN COALESCE(@TIPOMOV,'Todos') <> 'Todos' THEN  @TIPOMOV ELSE IMOV.IDTIPOMOV END 
            AND   COALESCE(IMOV.FECHACONF, IMOV.FECHAMOV)>=@F_INICIAL
            AND   COALESCE(IMOV.FECHACONF, IMOV.FECHAMOV)<@F_FINAL+1
            GROUP BY IMOV.IDBODEGA, IMOV.IDTIPOMOV, ITMO.DESCRIPCION 

            PRINT 'SALIDAS'

            SELECT IDBODEGA, IDTIPOMOV, DESCRIPCION, SUM(CANTIDAD)CANTIDAD, CONVERT(DECIMAL(14,2),SUM(COALESCE(CANTIDAD,0)) * @PCOSTO) PCOSTO
            FROM (
               SELECT IMOV.IDBODEGA, IMOV.IDTIPOMOV, ITMO.DESCRIPCION, ISAL.CANTIDAD, ISAL.PCOSTO
               FROM IMOV INNER JOIN ISAL ON IMOV.CNSMOV=ISAL.CNSMOV
                        INNER JOIN ITMO ON IMOV.IDTIPOMOV=ITMO.IDTIPOMOV
               WHERE IMOV.ESTADO=1 AND ITMO.TIPO='Debito'
               AND   ISAL.IDARTICULO IN (SELECT IDARTICULO FROM VWK_HERMANOS_INVENTARIO WHERE HERMANO_MAYOR=@HERMANO_MAYOR)
               /* En consulta principal, IMOVH es la fuente oficial y
                  ISAL solo respalda movimientos sin detalle padre/hijo equivalente. */
               AND NOT EXISTS (
                  SELECT 1
                  FROM IMOVH H
                  WHERE H.CNSMOV=ISAL.CNSMOV
                    AND H.ESTADO=1
                    AND H.IDARTICULO IN (
                       SELECT IDARTICULO
                       FROM VWK_HERMANOS_INVENTARIO
                       WHERE HERMANO_MAYOR=@HERMANO_MAYOR
                    )
               )
               AND   IMOV.IDBODEGA=CASE WHEN COALESCE(@IDBODEGA,'Todas') <> 'Todas' THEN @IDBODEGA ELSE IMOV.IDBODEGA END 
               AND   IMOV.IDTIPOMOV=CASE WHEN COALESCE(@TIPOMOV,'Todos') <> 'Todos' THEN @TIPOMOV ELSE IMOV.IDTIPOMOV END 
               AND   COALESCE(IMOV.FECHACONF, IMOV.FECHAMOV)>=@F_INICIAL
               AND   COALESCE(IMOV.FECHACONF, IMOV.FECHAMOV)<@F_FINAL+1
               UNION ALL
               /* IMOVH es la fuente oficial de la consulta principal. */
               SELECT IMOV.IDBODEGA, IMOV.IDTIPOMOV, ITMO.DESCRIPCION, IMOVH.CANTIDAD, IMOVH.PCOSTO
               FROM IMOV INNER JOIN IMOVH ON IMOV.CNSMOV=IMOVH.CNSMOV
                        INNER JOIN ITMO ON IMOV.IDTIPOMOV=ITMO.IDTIPOMOV
               WHERE IMOV.ESTADO=1 AND IMOVH.ESTADO=1 AND ITMO.TIPO='Debito'
               AND   IMOVH.IDARTICULO IN (SELECT IDARTICULO FROM VWK_HERMANOS_INVENTARIO WHERE HERMANO_MAYOR=@HERMANO_MAYOR)
               AND   IMOV.IDBODEGA=CASE WHEN COALESCE(@IDBODEGA,'Todas') <> 'Todas' THEN @IDBODEGA ELSE IMOV.IDBODEGA END 
               AND   IMOV.IDTIPOMOV=CASE WHEN COALESCE(@TIPOMOV,'Todos') <> 'Todos' THEN @TIPOMOV ELSE IMOV.IDTIPOMOV END 
               AND   COALESCE(IMOV.FECHACONF, IMOV.FECHAMOV)>=@F_INICIAL
               AND   COALESCE(IMOV.FECHACONF, IMOV.FECHAMOV)<@F_FINAL+1
            ) SAL
            GROUP BY IDBODEGA, IDTIPOMOV, DESCRIPCION
         RETURN
      END
      ELSE
      BEGIN
         SELECT 'KO'KO
         RETURN
      END
   END   
   IF @METODO='DETALLE_ENTRADA'     
   BEGIN         
      SELECT @DATOS=DATOS,@IDBODEGA=IDBODEGA,@TIPOMOV=IDTIPOMOV       
      FROM   OPENJSON (@PARAMETROS)
      WITH (           
         DATOS NVARCHAR(MAX) AS JSON ,
         IDBODEGA VARCHAR(20) '$.IDBODEGA',
         IDTIPOMOV VARCHAR(20) '$.IDTIPOMOV'
            )           
         PRINT '@IDBODEGA ='+@IDBODEGA
         PRINT '@TIPOMOV ='+@TIPOMOV
         SELECT  @F_INICIAL=CONVERT(DATETIME,F_INICIAL), @F_FINAL=CONVERT(DATETIME,F_FINAL), @IDARTICULO=IDARTICULO,
                 @NOLOTE=NOLOTE
         FROM   OPENJSON (@DATOS)
         WITH   ( 
         F_INICIAL DATE        '$.F_INICIAL',
         F_FINAL DATE           '$.F_FINAL',
         IDARTICULO VARCHAR(20)    '$.IDARTICULO',
         NOLOTE VARCHAR(20)        '$.NOLOTE'
         )

         IF COALESCE(@IDARTICULO,'')='' OR NOT EXISTS(SELECT 1 FROM IART WHERE IDARTICULO=@IDARTICULO)
         BEGIN
            SELECT 'KO'KO
            RETURN
         END

         IF COALESCE(@NOLOTE,'')=''
         BEGIN
            IF @FILTRO_ART_PRINCIPAL = 'SI'
               AND EXISTS(SELECT 1 FROM IART WHERE IDARTICULO=@IDARTICULO AND COALESCE(PRINCIPAL,0)=0)
            BEGIN
               SELECT 'KO' KO, 'Consulta configurada por art�culo principal (INF_ART_X_PRINCIPAL=SI).' ERROR
               RETURN
