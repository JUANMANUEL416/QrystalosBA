                   AND (
                         D.CNSHBALI COLLATE DATABASE_DEFAULT = HD.CNSHBALI COLLATE DATABASE_DEFAULT
                      OR COALESCE(HD.CNSHBALI, '') COLLATE DATABASE_DEFAULT = '' COLLATE DATABASE_DEFAULT
