         LEFT JOIN TER WITH (NOLOCK) ON IMOV.IDTERCERO = TER.IDTERCERO
         LEFT JOIN USUSU USU_CONF WITH (NOLOCK) ON USU_CONF.USUARIO = COALESCE(IMOV.USUARIOCONF, IMOV.USUARIO)
         WHERE IMOVH.IDARTICULO = CASE WHEN COALESCE(@IDARTICULO,'') <> '' THEN @IDARTICULO ELSE IMOVH.IDARTICULO END
