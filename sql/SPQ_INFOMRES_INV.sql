               + CASE WHEN COALESCE(TER.RAZONSOCIAL,'') <> '' THEN ' | Tercero: ' + TER.RAZONSOCIAL ELSE '' END
               + CASE WHEN COALESCE(IMOV.OBSERVACION,'') <> '' THEN ' | Obs: ' + IMOV.OBSERVACION ELSE '' END
