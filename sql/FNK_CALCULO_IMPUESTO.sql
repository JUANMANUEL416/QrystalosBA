CREATE OR ALTER FUNCTION DBO.FNK_CALCULO_IMPUESTO(@IDIMPUESTO VARCHAR(10),
    @IDCLASE VARCHAR(10),
    @VALOR_NETO DECIMAL(14,2),
    @FECHA DATETIME) 
RETURNS @TABLA

TABLE (ITEM SMALLINT, VALOR DECIMAL(14,2), FECHAINI  DATETIME, FECHAFIN  DATETIME, VALORIMP  DECIMAL(14,2),
       BASE DECIMAL(14,2), CUENTA    VARCHAR(16), CUENTA_ASUM VARCHAR(16), MUVT BIT, VRLUVT DECIMAL(14,2)) 

WITH ENCRYPTION
AS
BEGIN
   IF @VALOR_NETO > 0
      INSERT INTO @TABLA (ITEM, VALOR, FECHAINI, FECHAFIN, VALORIMP, BASE, CUENTA, CUENTA_ASUM,MUVT,VRLUVT)      
      SELECT ITEM,  dbo.FNK_DECIMALES_IMP_CXP(@VALOR_NETO * VALOR * 0.01), FECHAINI, FECHAFIN, VALOR, BASE, CUENTA, CUENTA_ASUM,MUVT,VLRUTV -- GG redondeos con variable
      FROM   FIMPDV,FIMPD
      WHERE @IDIMPUESTO=FIMPD.IDIMPUESTO AND @IDCLASE=FIMPD.IDCLASE AND FIMPDV.IDIMPUESTO=FIMPD.IDIMPUESTO AND
            FIMPDV.IDCLASE=FIMPD.IDCLASE AND FIMPDV.FECHAINI<=@FECHA AND FIMPDV.FECHAFIN>=@FECHA AND
            (CASE WHEN FIMPDV.VALOR_INICIAL IS NULL THEN 0 ELSE FIMPDV.VALOR_INICIAL END)<=@VALOR_NETO AND 
            (CASE WHEN ISNULL(FIMPDV.VALOR_FINAL,0) = 0 THEN @VALOR_NETO ELSE FIMPDV.VALOR_FINAL END)>=@VALOR_NETO
   ELSE
      INSERT INTO @TABLA (ITEM, VALOR, FECHAINI, FECHAFIN, VALORIMP, BASE, CUENTA, CUENTA_ASUM,MUVT,VRLUVT)
      SELECT ITEM, dbo.FNK_DECIMALES_IMP_CXP(@VALOR_NETO * VALOR * 0.01), FECHAINI, FECHAFIN, VALOR, BASE, CUENTA, CUENTA_ASUM,MUVT,VLRUTV -- GG redondeos con variable
      FROM   FIMPDV,FIMPD
      WHERE @IDIMPUESTO=FIMPD.IDIMPUESTO AND @IDCLASE=FIMPD.IDCLASE AND FIMPDV.IDIMPUESTO=FIMPD.IDIMPUESTO AND
            FIMPDV.IDCLASE=FIMPD.IDCLASE AND FIMPDV.FECHAINI<=@FECHA AND FIMPDV.FECHAFIN>=@FECHA 
   RETURN
END
