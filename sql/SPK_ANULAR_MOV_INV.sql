   DROP PROCEDURE SPK_ANULAR_MOV_INV
END

GO
CREATE PROCEDURE DBO.SPK_ANULAR_MOV_INV
@CNSMOV   VARCHAR(20),
@USUARIO  VARCHAR(12),
@TIPOMOV  VARCHAR(3),
@COMPANIA VARCHAR(2),
@SEDE     VARCHAR(5)
WITH ENCRYPTION
AS
DECLARE @CNSFCOM    VARCHAR(20)
DECLARE @CNSCTZ     VARCHAR(20)
DECLARE @IDTERCERO  VARCHAR(20)
DECLARE @ESTADO     VARCHAR(1)
DECLARE @NUEVOCNS   VARCHAR(20)
DECLARE @TMOVANUENT VARCHAR(2)
DECLARE @IDBODEGA   VARCHAR(2)
DECLARE @SYS_COMPUTERNAME VARCHAR(255)
DECLARE @PROCEDENCIA      VARCHAR(10)
DECLARE @CNSHTX           VARCHAR(20)
BEGIN
 SELECT @SYS_COMPUTERNAME = HOST_NAME()
 SELECT @ESTADO = ESTADO, @IDBODEGA = IDBODEGA, @PROCEDENCIA = PROCEDENCIA FROM IMOV WHERE CNSMOV = @CNSMOV 
 IF @TIPOMOV='ENT'
 BEGIN 
    PRINT 'ES ENTRADA'
    IF DBO.FNK_VALORVARIABLE('ESFARMACIA') = 'SI' AND @ESTADO = '1'
    BEGIN
       PRINT 'PROCESANDO'
       EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@SMOV',@NUEVOCNS OUTPUT
       SELECT @NUEVOCNS = @SEDE +'S'+ REPLACE(SPACE(8 - LEN(@NUEVOCNS))+LTRIM(RTRIM(@NUEVOCNS)),SPACE(1),0)          

       PRINT '@NUEVOCONS='+ @NUEVOCNS
       -- VARIABLE DEL MOVIMIENTO CONTRARIO DE INVENTARIOS
       SELECT @TMOVANUENT = DBO.FNK_VALORVARIABLE('FAR_MOVANULAENTRADA')   
       
       INSERT INTO IMOV ( CNSMOV, IDBODEGA, IDTIPOMOV, NODOCUMENTO, TIPODOCU, FECHAMOV,
                          CCOSTO, IDSOLICITA, IDTERCERO, IDFUNCIONARIO, IDRECIBE, FACTORVENTA,
                          ESTADO, IDBODEGAEXTERNA, cnstran, OBSERVACION, CNSFCOM, SUBIOCOMPRA,
                          NOPRESTACION, IDAREA, CONTABILIZADA, NROCOMPROBANTE, PROCEDENCIA,
                          USUARIO, USUARIOCONF, FECHACONF, PARCIAL, IDAREAH, NIVELATENCION,
                          SYS_ComputerName, TIENECAMBIO, IDITAR, ESTRANSITO, CNSREP, CNSIDEV,
                          IDDEP, CNSITRA, SECONTABILIZA, F_FACTURA, F_VENCE, MARCACONT,
                          VLR_FLETE, CODUNG, CODPRG, ITFC, CNSITFC, IDARTICULODESTINO,
                          CANTIDADDESTINO, GENFACTURA, IDPLAN, FACTURADA, N_FACTURA )
       SELECT @NUEVOCNS, IDBODEGA, @TMOVANUENT, @CNSMOV, TIPODOCU, 
              DBO.FNK_FECHA_SIN_MLS(GETDATE()), CCOSTO, IDSOLICITA, IDTERCERO, 
              IDFUNCIONARIO, IDRECIBE, FACTORVENTA,
              '0', IDBODEGAEXTERNA, cnstran, OBSERVACION, CNSFCOM, 0,
              NOPRESTACION, IDAREA, 0, NROCOMPROBANTE, PROCEDENCIA,
              @USUARIO, USUARIOCONF, FECHACONF, PARCIAL, IDAREAH, NIVELATENCION,
              HOST_NAME(), TIENECAMBIO, IDITAR, ESTRANSITO, CNSREP, CNSIDEV,
              IDDEP, CNSITRA, SECONTABILIZA, F_FACTURA, F_VENCE, MARCACONT,
              VLR_FLETE, CODUNG, CODPRG, ITFC, CNSITFC, IDARTICULODESTINO,
              CANTIDADDESTINO, GENFACTURA, IDPLAN, FACTURADA, N_FACTURA
       FROM   IMOV WHERE CNSMOV = @CNSMOV
       -- CONFIRMO LA SALIDA AUTOMATICAMENTE
       INSERT INTO IMOVH ( CNSMOV, IDARTICULO, EXISTENCIA, CANTIDAD, CANTPEDIDA, PCOSTO, NOLOTE,
                           NOLOTEPEDIDO, FECHAVENCE, ESTADO, IDARTICULOTF, CANTIDADTF, 
                           PCOSTOANTES, CNSTRAN, ITEM, PVENTA, USUARIO, USUARIOCONF, FECHACONF,
                           PRIEXI, FECHAREPOSI, IDARTICULOORI, CANTIDADORI, TIENECAMBIO, 
                           DETALLE, CANT_EN_ACTIVOS, ENCXP, PIVA, VLRIVA, PDTO, VLRDTO, 
                           CNSHTX, COTIZADO, IDIMPUESTO, IDCLASE, ITFC, CNSITFC, 
                           CUENTA_FIMPDV )
       SELECT  @NUEVOCNS, IMOVH.IDARTICULO, IMOVH.EXISTENCIA, IMOVH.CANTIDAD, IMOVH.CANTPEDIDA, IMOVH.PCOSTO, IMOVH.NOLOTE,
                           IMOVH.NOLOTEPEDIDO, IMOVH.FECHAVENCE, 0, IMOVH.IDARTICULOTF, IMOVH.CANTIDADTF, 
                           IMOVH.PCOSTOANTES, IMOVH.CNSTRAN, IMOVH.ITEM, IMOVH.PVENTA, IMOVH.USUARIO, IMOVH.USUARIOCONF, IMOVH.FECHACONF,
                           IMOVH.PRIEXI, IMOVH.FECHAREPOSI, IMOVH.IDARTICULOORI, IMOVH.CANTIDADORI, IMOVH.TIENECAMBIO, 
                           IMOVH.DETALLE, IMOVH.CANT_EN_ACTIVOS, IMOVH.ENCXP, IMOVH.PIVA, IMOVH.VLRIVA, IMOVH.PDTO, IMOVH.VLRDTO, 
                           IMOVH.CNSHTX, IMOVH.COTIZADO, IMOVH.IDIMPUESTO, IMOVH.IDCLASE, IMOVH.ITFC, IMOVH.CNSITFC, 
                           IMOVH.CUENTA_FIMPDV

       FROM    IMOVH 
       WHERE   CNSMOV = @CNSMOV
        
       
       EXEC SPK_CONFIRMARSALIDAS @IDBODEGA, @NUEVOCNS, @USUARIO, 	@COMPANIA, 	@SEDE
    END
    UPDATE IMOVH SET ESTADO=2 WHERE CNSMOV=@CNSMOV
    UPDATE IMOV SET ESTADO=2,FECHACONF=DBO.FNK_FECHA_SIN_MLS(GETDATE()),USUARIOCONF=@USUARIO WHERE CNSMOV=@CNSMOV
    IF EXISTS(SELECT * FROM IMOV WHERE CNSFCOM IN (SELECT CNSFCOM FROM FCOM))
    BEGIN
       SELECT @CNSFCOM=CNSFCOM FROM IMOV WHERE CNSMOV=@CNSMOV
       UPDATE FCOM SET ESTADO='C',ENINVENTARIO=0, ORDENCOMPRA= 0 WHERE CNSFCOM=@CNSFCOM
       
       DELETE ITRAH  
       FROM   ITRAH INNER JOIN ITRA ON ITRAH.CNSITRA = ITRA.CNSITRA         
       WHERE  ITRA.CNSFCOM = @CNSFCOM
       
       DELETE ITRA WHERE  ITRA.CNSFCOM = @CNSFCOM
       
       SELECT @CNSCTZ=CNSFCOT,@IDTERCERO=IDTERCERO FROM FCOM WHERE CNSFCOM=@CNSFCOM
       UPDATE FCTZTE SET ESTADO=2 WHERE CNSCTZ=@CNSCTZ AND IDTERCERO=@IDTERCERO
    END
 END
 ELSE
 IF @TIPOMOV='SAL'
 BEGIN
    IF DBO.FNK_VALORVARIABLE('ESFARMACIA') = 'SI' AND @ESTADO = '1'
    BEGIN      
       EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@EMOV',@NUEVOCNS OUTPUT
       SELECT @NUEVOCNS = @SEDE +'E'+ REPLACE(SPACE(8 - LEN(@NUEVOCNS))+LTRIM(RTRIM(@NUEVOCNS)),SPACE(1),0)          
       PRINT '@NUEVOCNS=' + @NUEVOCNS
         
       -- VARIABLE DEL MOVIMIENTO CONTRARIO DE INVENTARIOS
       SELECT @TMOVANUENT = DBO.FNK_VALORVARIABLE('FAR_MOVANULASALIDA')   
       
       INSERT INTO IMOV ( CNSMOV, IDBODEGA, IDTIPOMOV, NODOCUMENTO, TIPODOCU, FECHAMOV,
                          CCOSTO, IDSOLICITA, IDTERCERO, IDFUNCIONARIO, IDRECIBE, FACTORVENTA,
                          ESTADO, IDBODEGAEXTERNA, cnstran, OBSERVACION, CNSFCOM, SUBIOCOMPRA,
                          NOPRESTACION, IDAREA, CONTABILIZADA, NROCOMPROBANTE, PROCEDENCIA,
                          USUARIO, USUARIOCONF, FECHACONF, PARCIAL, IDAREAH, NIVELATENCION,
                          SYS_ComputerName, TIENECAMBIO, IDITAR, ESTRANSITO, CNSREP, CNSIDEV,
                          IDDEP, CNSITRA, SECONTABILIZA, F_FACTURA, F_VENCE, MARCACONT,
                          VLR_FLETE, CODUNG, CODPRG, ITFC, CNSITFC, IDARTICULODESTINO,
                          CANTIDADDESTINO, GENFACTURA, IDPLAN, FACTURADA, N_FACTURA )
       SELECT @NUEVOCNS, IDBODEGA, @TMOVANUENT, @CNSMOV, TIPODOCU, 
              DBO.FNK_FECHA_SIN_MLS(GETDATE()), CCOSTO, IDSOLICITA, IDTERCERO, 
              IDFUNCIONARIO, IDRECIBE, FACTORVENTA,
              '0', IDBODEGAEXTERNA, cnstran, OBSERVACION, CNSFCOM, 0,
              NOPRESTACION, IDAREA, 0, NROCOMPROBANTE, PROCEDENCIA,
              @USUARIO, USUARIOCONF, FECHACONF, PARCIAL, IDAREAH, NIVELATENCION,
              HOST_NAME(), TIENECAMBIO, IDITAR, ESTRANSITO, CNSREP, CNSIDEV,
              IDDEP, CNSITRA, SECONTABILIZA, F_FACTURA, F_VENCE, MARCACONT,
              VLR_FLETE, CODUNG, CODPRG, ITFC, CNSITFC, IDARTICULODESTINO,
              CANTIDADDESTINO, GENFACTURA, IDPLAN, FACTURADA, N_FACTURA
       FROM   IMOV WHERE CNSMOV = @CNSMOV
       INSERT INTO IMOVH ( CNSMOV, IDARTICULO, EXISTENCIA, CANTIDAD, CANTPEDIDA, PCOSTO, NOLOTE,
                           NOLOTEPEDIDO, FECHAVENCE, ESTADO, IDARTICULOTF, CANTIDADTF, 
                           PCOSTOANTES, CNSTRAN, ITEM, PVENTA, USUARIO, USUARIOCONF, FECHACONF,
                           PRIEXI, FECHAREPOSI, IDARTICULOORI, CANTIDADORI, TIENECAMBIO, 
                           DETALLE, CANT_EN_ACTIVOS, ENCXP, PIVA, VLRIVA, PDTO, VLRDTO, 
                           CNSHTX, COTIZADO, IDIMPUESTO, IDCLASE, ITFC, CNSITFC, 
                           CUENTA_FIMPDV )
           SELECT  @NUEVOCNS, IMOVH.IDARTICULO, IMOVH.EXISTENCIA, ISAL.CANTIDAD, ISAL.CANTIDAD, ISAL.PCOSTO, ISAL.NOLOTE,
                   ISAL.NOLOTEPEDIDO, ISAL.FECHAVENCE, 0, IMOVH.IDARTICULOTF, IMOVH.CANTIDADTF, 
                   IMOVH.PCOSTOANTES, IMOVH.CNSTRAN, IMOVH.ITEM, IMOVH.PVENTA, IMOVH.USUARIO, IMOVH.USUARIOCONF, IMOVH.FECHACONF,
                   IMOVH.PRIEXI, IMOVH.FECHAREPOSI, IMOVH.IDARTICULOORI, IMOVH.CANTIDADORI, IMOVH.TIENECAMBIO, 
                   IMOVH.DETALLE, IMOVH.CANT_EN_ACTIVOS, IMOVH.ENCXP, IMOVH.PIVA, IMOVH.VLRIVA, IMOVH.PDTO, IMOVH.VLRDTO, 
                   IMOVH.CNSHTX, IMOVH.COTIZADO, IMOVH.IDIMPUESTO, IMOVH.IDCLASE, IMOVH.ITFC, IMOVH.CNSITFC, 
                   IMOVH.CUENTA_FIMPDV
           FROM    IMOVH INNER JOIN ISAL ON IMOVH.IDARTICULO = ISAL.IDARTICULO
                                        AND IMOVH.CNSMOV     = ISAL.CNSMOV  AND ISAL.NOLOTE=IMOVH.NOLOTE
           WHERE   IMOVH.CNSMOV = @CNSMOV
       PRINT 'TERMINO LA INSERCION DE MOVIMIENTO'  
       -- CONFIRMO LA ENTRADA AUTOMATICAMENTE
       EXEC SPK_CONFIRMARENTRADAS @IDBODEGA, @NUEVOCNS, @USUARIO, @COMPANIA, @SEDE, @SYS_COMPUTERNAME
       UPDATE IMOVH SET ESTADO=2 WHERE CNSMOV=@CNSMOV
       UPDATE IMOV  SET ESTADO=2, FECHACONF=DBO.FNK_FECHA_SIN_MLS(GETDATE()),USUARIOCONF=@USUARIO WHERE CNSMOV=@CNSMOV
       UPDATE IREP SET ESTADO = 2 WHERE CNSMOV=@CNSMOV       
    END

	IF DBO.FNK_VALORVARIABLE('ESFARMACIA') = 'SI' AND COALESCE(@ESTADO,0)=0
	BEGIN
		UPDATE IMOVH SET ESTADO=2 WHERE CNSMOV=@CNSMOV
        UPDATE IMOV  SET ESTADO=2, FECHACONF=DBO.FNK_FECHA_SIN_MLS(GETDATE()),USUARIOCONF=@USUARIO WHERE CNSMOV=@CNSMOV
	END

    /*Aqui revisamos si la procedencia es de HTX para marcar en la hoja de tratamiento esta anulaci�n*/
    if @PROCEDENCIA = 'HTX'
    Begin      
       DECLARE IMOVH_CURSOR CURSOR FOR
       SELECT IMOVH.CNSHTX FROM IMOVH WHERE CNSMOV = @CNSMOV
       OPEN IMOVH_CURSOR
       FETCH NEXT FROM IMOVH_CURSOR
       INTO @CNSHTX
       WHILE @@FETCH_STATUS = 0
       BEGIN  
          IF (SELECT COALESCE(COUNT(*),0) FROM HTX WHERE CNSHTX = @CNSHTX AND  HTX.SOLICITADO   = 1 AND LISTOENTREGA = 0 AND ENTREGADO    = 0) > 0
          BEGIN
             UPDATE HTX SET CLASEANUINV = 1, SOLICITADO = 0 WHERE CNSHTX = @CNSHTX
             FETCH NEXT FROM IMOVH_CURSOR
             INTO @CNSHTX         
          END   
          ELSE
          BEGIN
             FETCH NEXT FROM IMOVH_CURSOR
             INTO @CNSHTX
          END   
       END
       CLOSE IMOVH_CURSOR
       DEALLOCATE IMOVH_CURSOR
       UPDATE IMOVH SET ESTADO=2 WHERE CNSMOV=@CNSMOV
       UPDATE IMOV  SET ESTADO=2, FECHACONF=DBO.FNK_FECHA_SIN_MLS(GETDATE()),USUARIOCONF=@USUARIO WHERE CNSMOV=@CNSMOV
       UPDATE IREP  SET ESTADO = 2 WHERE CNSMOV=@CNSMOV
    End  
 END   
END
