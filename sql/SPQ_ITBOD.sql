CREATE OR ALTER PROCEDURE DBO.SPQ_ITBOD
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @PARAMETROS NVARCHAR(MAX), @MODELO         VARCHAR(100),   @METODO         VARCHAR(100)
DECLARE  @USUARIO    VARCHAR(20),   @IDTBODEGA      VARCHAR(2),		@DESCRIPCION	VARCHAR(80)
DECLARE	 @CLASE		 INT,			@VERIFDOC		VARCHAR(2)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDTBODEGA = IDTBODEGA, @DESCRIPCION = DESCRIPCION, @CLASE = CLASE, @VERIFDOC = VERIFDOC 
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				IDTBODEGA VARCHAR(2)  '$.IDTBODEGA', DESCRIPCION VARCHAR(80)  '$.DESCRIPCION',
				CLASE INT  '$.CLASE', VERIFDOC VARCHAR(2)  '$.VERIFDOC'
			)

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'EL TIPO DE BODEGA YA EXISTE'
			WHERE EXISTS (SELECT IDTBODEGA FROM ITBOD WHERE IDTBODEGA = @IDTBODEGA)

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'LA DESCRIPCION DE LA BODEGA YA EXISTE'
			WHERE EXISTS (SELECT IDTBODEGA FROM ITBOD WHERE DESCRIPCION = @DESCRIPCION)

			IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
			BEGIN
				INSERT INTO ITBOD (IDTBODEGA ,DESCRIPCION ,CLASE ,VERIFDOC) 
				SELECT @IDTBODEGA, @DESCRIPCION, @CLASE, @VERIFDOC
				WHERE NOT EXISTS (SELECT IDTBODEGA FROM ITBOD WHERE IDTBODEGA = @IDTBODEGA) 
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ACTUALIZAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDTBODEGA = IDTBODEGA, @DESCRIPCION = DESCRIPCION, @CLASE = CLASE, @VERIFDOC = VERIFDOC 
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				IDTBODEGA VARCHAR(2)  '$.IDTBODEGA', DESCRIPCION VARCHAR(80)  '$.DESCRIPCION',
				CLASE INT  '$.CLASE', VERIFDOC VARCHAR(2)  '$.VERIFDOC'
			)

			UPDATE ITBOD SET DESCRIPCION = @DESCRIPCION, CLASE = @CLASE, VERIFDOC = @VERIFDOC WHERE IDTBODEGA = @IDTBODEGA			
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
	
	IF @METODO = 'ELIMINAR'
	BEGIN
		BEGIN TRY
			SELECT @IDTBODEGA = JSON_VALUE(@PARAMETROS, '$.IDTBODEGA')

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'EL TIPO DE BODEGA TIENE BODEGAS ASIGNADAS (IBOD)'
			WHERE EXISTS (SELECT * FROM IBOD WHERE IDTBODEGA = @IDTBODEGA)

			IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
			BEGIN
				DELETE FROM ITBOD WHERE IDTBODEGA = @IDTBODEGA
			END
			
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
END
