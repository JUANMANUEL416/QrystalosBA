CREATE OR ALTER PROCEDURE DBO.NC_SPK_GEN_LIBROAUXILIAR 
@FECHAINI       DATETIME, 
@FECHAFIN       DATETIME, 
@IDTERCEROINI   VARCHAR(20), 
@IDTERCEROFIN   VARCHAR(20), 
@CUENTAINI      VARCHAR(16), 
@CUENTAFIN      VARCHAR(16),
@CCOSTOINI      VARCHAR(20),
@CCOSTOFIN      VARCHAR(20),
@WHERE          VARCHAR(3000),
@CONSECUTIVORPDX VARCHAR(20),
@SINCIERRE BIT =0,
@NROCOMPROBANTE VARCHAR(50) = NULL
WITH ENCRYPTION
AS
BEGIN
   CREATE TABLE #TABLA_FNK_MOVXTERCERO
         (TIPO          SMALLINT UNIQUE (TIPO, ITEM), 
          CUENTA         VARCHAR(16)   COLLATE database_default,
          NOMCUENTA      VARCHAR(250)   COLLATE database_default,
          CCOSTO         VARCHAR (20)  COLLATE database_default,
          NOMCCOSTO      VARCHAR (100) COLLATE database_default,
          IDTERCERO      VARCHAR(20)   COLLATE database_default, 
          RAZONSOCIAL    VARCHAR(120)  COLLATE database_default,
          N_FACTURA      VARCHAR (20)  COLLATE database_default,
          FECHAMOV       DATETIME UNIQUE (CUENTA, CCOSTO, IDTERCERO, N_FACTURA, FECHAMOV, ITEM),
          DETALLE        VARCHAR(512) COLLATE database_default,  
          COMPROBANTE    VARCHAR(20) COLLATE database_default,  
          NOREFERENCIA   VARCHAR(20) COLLATE database_default,  
          NROCOMPROBANTE VARCHAR(20) COLLATE database_default,  
          FECHAINI       DATETIME,
          FECHAFIN       DATETIME,
          SI             DECIMAL(14,2),
          DB             DECIMAL(14,2),
          CR             DECIMAL(14,2),
          SF             AS SI + DB - CR,
          ITEM           INT IDENTITY NOT NULL PRIMARY KEY CLUSTERED (ITEM),
          CODUNG         VARCHAR(5)  COLLATE database_default,
          CODPRG         VARCHAR(20) COLLATE database_default,
          NOCHEQUE		 VARCHAR(20) COLLATE database_default, --- CAMPO ADICIONADO (JREYES 20090421)
	       ESTADO         VARCHAR(1)  COLLATE database_default,
          NTZ            VARCHAR(2) COLLATE database_default)  --- CAMPO ADICIONADO (JREYES 20090421) 

   --AS  
   --BEGIN
   DECLARE 
    @ANOINI SMALLINT,
    @ANOFIN SMALLINT,
    @MESINI SMALLINT,
    @MESFIN SMALLINT,
    @ITEM_CUR INT,
    @CUENTA_ANT VARCHAR(20),
    @CUENTA_CUR VARCHAR(20),
    @CCOSTO_ANT  VARCHAR(20),
    @CCOSTO_CUR VARCHAR(20),
    @IDTERCERO_ANT VARCHAR(20),
    @IDTERCERO_CUR VARCHAR(20),
    @N_FACTURA_ANT VARCHAR(20),
    @N_FACTURA_CUR VARCHAR(20),
    @CODUNG_CUR VARCHAR(5), 
    @CODPRG_CUR VARCHAR(20),
    @SI_CUR DECIMAL(14,2),
    @DB_CUR DECIMAL(14,2),
    @CR_CUR DECIMAL(14,2),
    @SF DECIMAL(14,2),
    @SF_ANT DECIMAL(14,2),
    @COMPANIA VARCHAR(2),
    @QUERYFINAL VARCHAR(3000),
    @PERIODO       VARCHAR(6),
    @PERIODOINI       VARCHAR(6),
    @PERIODOFIN       VARCHAR(6),
    @WHERE_FINAL VARCHAR(4000)
   DECLARE @MESANT            INT
   DECLARE @ANOANT            INT
   DECLARE @MES               INT
   DECLARE @ANO               INT
   DECLARE @NTZ               VARCHAR(2)

    SET @COMPANIA='01'

    IF @IDTERCEROFIN = ''    
       SET @IDTERCEROFIN = DBO.FNK_MICOLLATE()

    IF @CUENTAFIN = ''    
       SET @CUENTAFIN    = DBO.FNK_MICOLLATE()

    IF @CCOSTOFIN = ''    
       SET @CCOSTOFIN    = DBO.FNK_MICOLLATE()
                      
    SELECT @ANOINI = YEAR(@FECHAINI), @MESINI = MONTH(@FECHAINI),
           @ANOFIN = YEAR(@FECHAFIN), @MESFIN = MONTH(@FECHAFIN)
   SELECT @ANO=YEAR(@FECHAINI),@MES=MONTH(@FECHAINI)
   IF @MES = 1
   BEGIN
      SELECT @MESANT = 12
      SELECT @ANOANT = @ANO - 1
   END   
   ELSE   
   BEGIN
      SELECT @MESANT = @MES -1
      SELECT @ANOANT = @ANO 
   END 
    -- Saldo Inicial del Mes																												   
      SELECT @PERIODO= CAST(@ANOANT AS VARCHAR(4))+CASE WHEN @MESANT<10 THEN '0'+CAST(@MESANT AS VARCHAR(1)) ELSE CAST(@MESANT AS VARCHAR(2)) END
      SELECT @PERIODOINI= CAST(YEAR(@FECHAINI) AS VARCHAR(4))+CASE WHEN MONTH(@FECHAINI) <10 THEN '0'+CAST(MONTH(@FECHAINI) AS VARCHAR(1)) ELSE CAST(MONTH(@FECHAINI) AS VARCHAR(2)) END
      SELECT @PERIODOFIN= CAST(YEAR(@FECHAFIN) AS VARCHAR(4))+CASE WHEN MONTH(@FECHAFIN) <10 THEN '0'+CAST(MONTH(@FECHAFIN) AS VARCHAR(1)) ELSE CAST(MONTH(@FECHAFIN) AS VARCHAR(2)) END

      INSERT INTO #TABLA_FNK_MOVXTERCERO (TIPO, IDTERCERO, CUENTA, CCOSTO, N_FACTURA, DETALLE, COMPROBANTE, NOREFERENCIA, NROCOMPROBANTE, 
                                       FECHAMOV, FECHAINI, FECHAFIN, SI, DB, CR, CODUNG, CODPRG, NOCHEQUE,NTZ)
      SELECT 1, VK.IDTERCERO , VK.CUENTA, '','','','','', '', @FECHAINI, @FECHAINI, @FECHAFIN, SUM(COALESCE(SI,0)), 0, 0,'', '', '',NTZ
      FROM VWK_BALANCE_CUE_DETALLE VK
      WHERE  VK.CUENTA >= @CUENTAINI 
      AND    VK.CUENTA <= @CUENTAFIN 
      AND    VK.PERIODO=@PERIODOINI
      AND    COALESCE(VK.IDTERCERO,'') >= @IDTERCEROINI 
      AND    COALESCE(VK.IDTERCERO,'') <= @IDTERCEROFIN 
      AND    COALESCE(VK.CCOSTO,'')    >= @CCOSTOINI 
      AND    COALESCE(VK.CCOSTO,'')    <= @CCOSTOFIN
      GROUP BY  VK.IDTERCERO , VK.CUENTA,VK.CCOSTO,VK.NTZ
      

    IF CAST('01/'+STR(LTRIM(@MESINI))+'/'+STR(LTRIM(@ANOINI)) AS DATETIME) < @FECHAINI
    BEGIN
       -- Saldo Inicial desde el dia exacto
       PRINT 'ANTES DEL UPDATE(*1) entre aqui ok'
       UPDATE #TABLA_FNK_MOVXTERCERO 
	    SET  SI = ISNULL(X.SI,0) + ISNULL(Y.DB,0) - ISNULL(Y.CR,0)
	    FROM #TABLA_FNK_MOVXTERCERO X INNER JOIN
           (SELECT IDTERCERO=ISNULL(TER.IDTERCERO,''), CUENTA=MCH.CUENTA, CCOSTO=ISNULL(CEN.CCOSTO,''),
                   N_FACTURA = ISNULL(MCH.N_FACTURA,''), CODUNG = ISNULL(MCH.CODUNG,''), CODPRG = ISNULL(MCH.CODPRG,''),
                   DB = SUM(CASE WHEN MCH.TIPO = 'DB' THEN MCH.VALOR ELSE 0 END),
                   CR = SUM(CASE WHEN MCH.TIPO = 'CR' THEN MCH.VALOR ELSE 0 END)
            FROM   MCP  INNER JOIN MCH  ON MCP.COMPANIA=MCH.COMPANIA 
                                       AND MCP.NROCOMPROBANTE = MCH.NROCOMPROBANTE 
                        LEFT JOIN  TER  ON TER.IDTERCERO = MCH.IDTERCERO 
                        LEFT JOIN  CEN  ON CEN.COMPANIA  = MCP.COMPANIA 
                                       AND CEN.CCOSTO    = MCH.CCOSTO
            WHERE  MCP.COMPANIA=@COMPANIA 
            AND    MCP.FECHACONTABLE >= CAST('01/'+STR(LTRIM(@MESINI))+'/'+STR(LTRIM(@ANOINI)) AS DATETIME) 
            AND    MCP.FECHACONTABLE < @FECHAINI 
            AND    ISNULL(MCH.IDTERCERO,'') >= @IDTERCEROINI 
            AND    ISNULL(MCH.IDTERCERO,'') <= @IDTERCEROFIN 
            AND    MCH.CUENTA >= @CUENTAINI 
            AND    MCH.CUENTA <= @CUENTAFIN 
            AND    ISNULL(MCH.CCOSTO,'') >= @CCOSTOINI 
            AND    ISNULL(MCH.CCOSTO,'') <= @CCOSTOFIN 
            AND    MCP.ESTADO = 2 
            AND    ISNULL(MCP.ANULADO,0) = 0 
            AND   MCP.COMPROBANTE<>CASE WHEN @SINCIERRE=1 THEN DBO.FNK_VALORVARIABLE('IDCONT_TCOM_CIERRE')ELSE '' END
            AND   (@NROCOMPROBANTE IS NULL OR RTRIM(@NROCOMPROBANTE)='' OR RTRIM(ISNULL(MCP.NROCOMPROBANTE,'')) LIKE RTRIM(@NROCOMPROBANTE)+'%')
            GROUP BY ISNULL(TER.IDTERCERO,''), 
                     MCH.CUENTA, ISNULL(CEN.CCOSTO,''), ISNULL(MCH.N_FACTURA,''), 
                     ISNULL(MCH.CODUNG,''), ISNULL(MCH.CODPRG,'')) Y ON X.IDTERCERO = Y.IDTERCERO 
                                                                    AND X.CUENTA    = Y.CUENTA 
                                                                    AND X.CCOSTO    = Y.CCOSTO 
                                                                    AND X.N_FACTURA = Y.N_FACTURA 
                                                                    AND X.CODUNG    = Y.CODUNG 
                                                                    AND X.CODPRG    = Y.CODPRG 
       
       PRINT 'ANTES DEL UPDATE(*2)'
    
       INSERT INTO #TABLA_FNK_MOVXTERCERO (TIPO, IDTERCERO, CUENTA, CCOSTO, N_FACTURA, DETALLE, COMPROBANTE, 
                         NOREFERENCIA, NROCOMPROBANTE, FECHAMOV, FECHAINI, FECHAFIN, SI, DB, CR, CODUNG, CODPRG,NTZ)
       SELECT 1, Y.IDTERCERO, Y.CUENTA, Y.CCOSTO, Y.N_FACTURA,DBO.FNK_RTF(Y.DETALLE), Y.COMPROBANTE, 
              Y.NOREFERENCIA, Y.NROCOMPROBANTE, Y.FECHAMOV, @FECHAINI, @FECHAFIN, SI = 0, DB = ISNULL(Y.DB,0), CR = ISNULL(Y.CR,0), 
              Y.CODUNG, Y.CODPRG,Y.TIPO
       FROM   (SELECT MCP.COMPANIA, 
                      IDTERCERO=ISNULL(TER.IDTERCERO,''), 
                      CUENTA=MCH.CUENTA,
                      CCOSTO=ISNULL(CEN.CCOSTO,''),
                      N_FACTURA=ISNULL(MCH.N_FACTURA,''),
                      DETALLE = MCH.DETALLE, 
                      MCP.COMPROBANTE, 
                      MCP.NOREFERENCIA, 
                      MCP.NROCOMPROBANTE,
                      FECHAMOV = MCP.FECHACONTABLE,
                      DB = SUM(CASE WHEN MCH.TIPO = 'DB' THEN MCH.VALOR ELSE 0 END),
                      CR = SUM(CASE WHEN MCH.TIPO = 'CR' THEN MCH.VALOR ELSE 0 END),
                      CODUNG = ISNULL(MCH.CODUNG,''),
                      CODPRG = ISNULL(MCH.CODPRG,''),NTZ.TIPO		
               FROM   MCP  INNER JOIN MCH  ON MCP.COMPANIA = MCH.COMPANIA 
                                          AND MCP.NROCOMPROBANTE = MCH.NROCOMPROBANTE 
                           INNER JOIN CUE ON MCH.CUENTA=CUE.Cuenta
                           LEFT  JOIN NTZ ON LEFT(CUE.Cuenta,1)=NTZ.N_INICIAL
                           LEFT JOIN  TER  ON TER.IDTERCERO = MCH.IDTERCERO 
                           LEFT JOIN  CEN  ON CEN.CCOSTO    = MCH.CCOSTO 
                                          AND CEN.COMPANIA  = MCP.COMPANIA
               WHERE MCP.COMPANIA=@COMPANIA 
			   AND MCP.FECHACONTABLE >= CAST('01/'+STR(LTRIM(@MESINI))+'/'+STR(LTRIM(@ANOINI)) AS DATETIME) 
               AND   MCP.FECHACONTABLE < @FECHAINI 
               AND   ISNULL(MCH.IDTERCERO,'') >= @IDTERCEROINI AND ISNULL(MCH.IDTERCERO,'') <= @IDTERCEROFIN 
               AND   MCH.CUENTA >= @CUENTAINI AND MCH.CUENTA <= @CUENTAFIN 
               AND   ISNULL(MCH.CCOSTO,'') >= @CCOSTOINI AND ISNULL(MCH.CCOSTO,'') <= @CCOSTOFIN 
               AND   MCP.ESTADO=2 
               AND   ISNULL(MCP.ANULADO,0) = 0
               AND   MCP.COMPROBANTE<>CASE WHEN @SINCIERRE=1 THEN DBO.FNK_VALORVARIABLE('IDCONT_TCOM_CIERRE')ELSE '' END
               AND   (@NROCOMPROBANTE IS NULL OR RTRIM(@NROCOMPROBANTE)='' OR RTRIM(ISNULL(MCP.NROCOMPROBANTE,'')) LIKE RTRIM(@NROCOMPROBANTE)+'%')
               GROUP BY MCP.COMPANIA, ISNULL(TER.IDTERCERO,''), MCH.CUENTA, ISNULL(CEN.CCOSTO,''), 
                        ISNULL(MCH.N_FACTURA,''), MCP.FECHACONTABLE, MCH.DETALLE, MCP.COMPROBANTE, 
                        MCP.NOREFERENCIA, MCP.NROCOMPROBANTE, ISNULL(MCH.CODUNG,''), 
                        ISNULL(MCH.CODPRG,''),NTZ.TIPO) Y LEFT JOIN #TABLA_FNK_MOVXTERCERO X ON X.IDTERCERO = Y.IDTERCERO 
                                                                                   AND X.CUENTA    = Y.CUENTA 
                                                                                   AND X.CCOSTO    = Y.CCOSTO 
                                                                                   AND X.N_FACTURA = Y.N_FACTURA 
                                                                                   AND X.CODUNG    = Y.CODUNG 
                                                                                   AND X.CODPRG    = Y.CODPRG
       WHERE X.CUENTA IS NULL
       ORDER BY Y.CUENTA, Y.CCOSTO, Y.IDTERCERO, Y.N_FACTURA, Y.FECHAMOV 
    END 
    PRINT 'ANTES DEL UPDATE(*3)'
    -- Movimientos
    IF (SELECT DBO.FNK_VALORVARIABLE('CHEQUE_ANULADO') ) = 'SI'
    BEGIN
       PRINT 'ANTES DEL UPDATE(*4)'
       INSERT INTO #TABLA_FNK_MOVXTERCERO (TIPO, IDTERCERO, CUENTA, CCOSTO, N_FACTURA, DETALLE, COMPROBANTE, 
                   NOREFERENCIA, NROCOMPROBANTE, FECHAMOV, FECHAINI, FECHAFIN, SI, DB, CR, CODUNG, CODPRG, NOCHEQUE, ESTADO,NTZ)
	    SELECT 2, IDTERCERO = MCH.IDTERCERO, CUENTA = MCH.CUENTA, CCOSTO = MCH.CCOSTO, N_FACTURA = ISNULL(MCH.N_FACTURA,''), 
              DETALLE =DBO.FNK_RTF(MCH.DETALLE), MCP.COMPROBANTE, MCP.NOREFERENCIA, MCP.NROCOMPROBANTE, 
              MCP.FECHACONTABLE, @FECHAINI, @FECHAFIN, SI = 0, 
              DB = CASE WHEN MCH.TIPO = 'DB' THEN MCH.VALOR ELSE 0 END, 
              CR = CASE WHEN MCH.TIPO = 'CR' THEN MCH.VALOR ELSE 0 END,     
              ISNULL(MCH.CODUNG,''), ISNULL(MCH.CODPRG,''), MCP.NOCHEQUE, BCTDD.ESTADO,NTZ.TIPO
       FROM   MCP INNER JOIN MCH   ON MCP.COMPANIA       = MCH.COMPANIA 
                                  AND MCP.NROCOMPROBANTE = MCH.NROCOMPROBANTE 
                  INNER JOIN CUE  ON MCH.CUENTA=CUE.Cuenta
                  LEFT  JOIN NTZ ON LEFT(CUE.Cuenta,1)=NTZ.N_INICIAL
                  LEFT JOIN  BCTDD ON BCTDD.CNSFACJ      = MCP.REFERENCIA1 
                                  AND BCTDD.N_RECIBO     = MCP.NOREFERENCIA 
                                  AND BCTDD.NODOCUMENTO  = MCP.NOCHEQUE
       WHERE  MCP.COMPANIA              = @COMPANIA 
       AND    MCP.FECHACONTABLE        >= @FECHAINI 
       AND    MCP.FECHACONTABLE         < @FECHAFIN+1 
       AND 	  MCP.ESTADO                = 2 
       AND    ISNULL(MCP.ANULADO,0)     = 0 
       AND    MCH.CUENTA               >= @CUENTAINI 
       AND    MCH.CUENTA               <= @CUENTAFIN 
       AND    ISNULL(MCH.IDTERCERO,'') >= @IDTERCEROINI 
       AND    ISNULL(MCH.IDTERCERO,'') <= @IDTERCEROFIN 
       AND    ISNULL(MCH.CCOSTO,'')    >= @CCOSTOINI 
       AND    ISNULL(MCH.CCOSTO,'')    <= @CCOSTOFIN
       AND   MCP.COMPROBANTE<>CASE WHEN @SINCIERRE=1 THEN DBO.FNK_VALORVARIABLE('IDCONT_TCOM_CIERRE')ELSE '' END
       AND   (@NROCOMPROBANTE IS NULL OR RTRIM(@NROCOMPROBANTE)='' OR RTRIM(ISNULL(MCP.NROCOMPROBANTE,'')) LIKE RTRIM(@NROCOMPROBANTE)+'%')
    
    END
    ELSE
    BEGIN
	print 'entre por aqui hace ultimo insert'
       INSERT INTO #TABLA_FNK_MOVXTERCERO (TIPO, IDTERCERO, CUENTA, CCOSTO, N_FACTURA, DETALLE, COMPROBANTE, NOREFERENCIA, NROCOMPROBANTE, 
                   FECHAMOV, FECHAINI, FECHAFIN, SI, DB, CR, CODUNG, CODPRG, NOCHEQUE,NTZ)
	    SELECT 2, IDTERCERO=MCH.IDTERCERO, CUENTA=MCH.CUENTA, CCOSTO=MCH.CCOSTO, N_FACTURA = ISNULL(MCH.N_FACTURA,''), 
              DETALLE =DBO.FNK_RTF(MCH.DETALLE), MCP.COMPROBANTE, MCP.NOREFERENCIA, MCP.NROCOMPROBANTE, MCP.FECHACONTABLE, @FECHAINI, @FECHAFIN, SI = 0, 
              DB = CASE WHEN MCH.TIPO = 'DB' THEN MCH.VALOR ELSE 0 END, 
              CR = CASE WHEN MCH.TIPO = 'CR' THEN MCH.VALOR ELSE 0 END,     
              ISNULL(MCH.CODUNG,''), ISNULL(MCH.CODPRG,''),MCP.NOCHEQUE,NTZ.TIPO
       FROM   MCP INNER JOIN MCH ON MCP.COMPANIA       = MCH.COMPANIA 
                                AND MCP.NROCOMPROBANTE = MCH.NROCOMPROBANTE
                  LEFT JOIN NTZ ON LEFT(MCH.CUENTA,1)=NTZ.N_INICIAL
       WHERE  MCP.COMPANIA=@COMPANIA 
       AND    MCP.FECHACONTABLE >= @FECHAINI 
       AND    MCP.FECHACONTABLE < @FECHAFIN+1 
       AND    MCP.ESTADO        = 2 
       AND    ISNULL(MCP.ANULADO,0) = 0 
       AND    MCH.CUENTA >= @CUENTAINI 
       AND    MCH.CUENTA <= @CUENTAFIN 
       AND    ISNULL(MCH.IDTERCERO,'') >= @IDTERCEROINI 
       AND    ISNULL(MCH.IDTERCERO,'') <= @IDTERCEROFIN 
       AND    ISNULL(MCH.CCOSTO,'')    >= @CCOSTOINI 
       AND    ISNULL(MCH.CCOSTO,'') <= @CCOSTOFIN
       AND   MCP.COMPROBANTE<>CASE WHEN @SINCIERRE=1 THEN DBO.FNK_VALORVARIABLE('IDCONT_TCOM_CIERRE')ELSE '' END
       AND   (@NROCOMPROBANTE IS NULL OR RTRIM(@NROCOMPROBANTE)='' OR RTRIM(ISNULL(MCP.NROCOMPROBANTE,'')) LIKE RTRIM(@NROCOMPROBANTE)+'%')
   END
   
    DELETE #TABLA_FNK_MOVXTERCERO WHERE SI=0 AND DB = 0 AND CR = 0
 
    DECLARE CUR_MOV CURSOR FOR
    SELECT ITEM, CUENTA, CCOSTO, IDTERCERO, N_FACTURA, SI, DB, CR, CODUNG, CODPRG,NTZ
    FROM   #TABLA_FNK_MOVXTERCERO 
    WHERE  TIPO = 2
    ORDER BY CUENTA, CCOSTO, IDTERCERO, N_FACTURA, FECHAMOV,NTZ

    OPEN CUR_MOV

    FETCH NEXT FROM CUR_MOV
    INTO @ITEM_CUR, @CUENTA_CUR, @CCOSTO_CUR, @IDTERCERO_CUR, @N_FACTURA_CUR, @SI_CUR, @DB_CUR, @CR_CUR,
	@CODUNG_CUR, @CODPRG_CUR, @NTZ

    SET @SF_ANT = 0
    SET @SF     = 0
    SELECT @CUENTA_ANT = '', @CCOSTO_ANT = '', @IDTERCERO_ANT = '', @N_FACTURA_ANT = ''
    WHILE @@FETCH_STATUS = 0
    BEGIN
         IF @CUENTA_ANT = @CUENTA_CUR AND @CCOSTO_ANT = @CCOSTO_CUR AND @IDTERCERO_ANT = @IDTERCERO_CUR 
		 AND @N_FACTURA_ANT = @N_FACTURA_CUR
         BEGIN
		 print 'entre aqui a actualizar sf'
            SET @SF =CASE WHEN @NTZ='DB'THEN   @SF_ANT + @DB_CUR - @CR_CUR ELSE  @SF_ANT +  @CR_CUR -@DB_CUR  END
            UPDATE #TABLA_FNK_MOVXTERCERO SET SI = @SF_ANT WHERE ITEM = @ITEM_CUR
         END
         ELSE
         BEGIN
            SET @SF =CASE WHEN @NTZ='DB'THEN   @SF_ANT + @DB_CUR - @CR_CUR ELSE  @SF_ANT +  @CR_CUR -@DB_CUR  END
         END

         SELECT @CUENTA_ANT = @CUENTA_CUR, @CCOSTO_ANT = @CCOSTO_CUR, @IDTERCERO_ANT = @IDTERCERO_CUR, @N_FACTURA_ANT = @N_FACTURA_CUR

         FETCH NEXT FROM CUR_MOV
         INTO  @ITEM_CUR, @CUENTA_CUR, @CCOSTO_CUR, @IDTERCERO_CUR, @N_FACTURA_CUR, @SI_CUR, @DB_CUR, @CR_CUR, @CODUNG_CUR, @CODPRG_CUR, @NTZ

         IF @CUENTA_ANT = @CUENTA_CUR AND @CCOSTO_ANT = @CCOSTO_CUR AND @IDTERCERO_ANT = @IDTERCERO_CUR AND @N_FACTURA_ANT = @N_FACTURA_CUR
            SET @SF_ANT = @SF
         ELSE
            SET @SF_ANT = CASE WHEN @NTZ='DB'THEN   @SF_ANT + @DB_CUR - @CR_CUR ELSE  @SF_ANT +  @CR_CUR -@DB_CUR  END
    END
    CLOSE CUR_MOV
    DEALLOCATE CUR_MOV

   UPDATE #TABLA_FNK_MOVXTERCERO

   SET RAZONSOCIAL = TER.RAZONSOCIAL, NOMCUENTA = CUE.NOMCUENTA, NOMCCOSTO = CEN.DESCRIPCION ,  IDTERCERO=CASE WHEN TER.NIT IS NULL THEN A.IDTERCERO ELSE TER.NIT END
   FROM #TABLA_FNK_MOVXTERCERO  A LEFT JOIN
        TER  ON A.IDTERCERO = TER.IDTERCERO LEFT JOIN    
        CUE  ON CUE.CUENTA = A.CUENTA AND CUE.COMPANIA = @COMPANIA LEFT JOIN    
        CEN  ON CEN.CCOSTO = A.CCOSTO AND CEN.COMPANIA = @COMPANIA
   
   DELETE FROM RPDX2 WHERE CNS = @CONSECUTIVORPDX
   SET @QUERYFINAL ='INSERT INTO RPDX2 (CNS, VALOR10, ID1, STRINGMEDIO1, ID2, STRINGMEDIO2, ID3, STRINGMEDIO3, VALOR1, VALOR2, VALOR3, VALOR4, FECHA1, FECHA2, ID4, FECHA3, STRINGGRANDE1, ID5, ID6, ID7, ID8, ID9, ID10,ID11,ID12) '+ --se argrega ID12 para nrocomprobante
   'SELECT ''' + @CONSECUTIVORPDX +''', TIPO, CUENTA, NOMCUENTA, CCOSTO, LEFT(NOMCCOSTO, 100), IDTERCERO, LEFT(RAZONSOCIAL,100), (CASE WHEN ESTADO = ''A'' THEN 0 ELSE SI END) SI, (CASE WHEN ESTADO = ''A'' THEN 0 ELSE DB END) DB, ' +
   '(CASE WHEN ESTADO = ''A'' THEN 0 ELSE CR END) CR, (CASE WHEN ESTADO = ''A'' THEN 0 ELSE SF END) SF, FECHAINI, FECHAFIN, N_FACTURA, FECHAMOV, DETALLE, COMPROBANTE, NOREFERENCIA, CODUNG, CODPRG, NOCHEQUE, ESTADO,NTZ,NROCOMPROBANTE ' +  --se agregaNCROCOMPROBANTE
   'FROM #TABLA_FNK_MOVXTERCERO ' + CASE WHEN DBO.FNK_VALORVARIABLE('MMCORPORATIVO')='NO' THEN '' ELSE  @WHERE END 
   PRINT @QUERYFINAL
   EXEC (@QUERYFINAL)
   --SELECT * FROM RPDX2 WHERE CNS = @CONSECUTIVORPDX  
   DROP TABLE #TABLA_FNK_MOVXTERCERO
END
