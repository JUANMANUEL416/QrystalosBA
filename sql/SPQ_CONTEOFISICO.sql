					WHEN P0 LIKE '%.%' AND P0 LIKE '%,%' AND CHARINDEX(',', P0) > CHARINDEX('.', P0)
						THEN REPLACE(REPLACE(P0, '.', ''), ',', '.')
					ELSE REPLACE(P0, ',', '')
				END
			) AS PCOSTO,
			ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS FILA
		INTO #DATOS_SALDO_IN_A
		FROM OPENJSON(@DATOS_SALDO)
		WITH (
			IDARTICULO		VARCHAR(20)		'$.IDARTICULO',
			CANTIDAD		VARCHAR(20)		'$.CANTIDAD',
			NOLOTE			VARCHAR(50)		'$.NOLOTE',
			NOLOTEPEDIDO	VARCHAR(50)		'$.NOLOTEPEDIDO',
			FECHAVENCE		VARCHAR(20)		'$.FECHAVENCE',
			PCOSTO			VARCHAR(20)		'$.PCOSTO'
		)
		CROSS APPLY (
			SELECT REPLACE(REPLACE(REPLACE(REPLACE(LTRIM(RTRIM(COALESCE(PCOSTO, ''))), '$', ''), ' ', ''), CHAR(160), ''), CHAR(9), '') AS P0
		) PX
		WHERE COALESCE(LTRIM(RTRIM(IDARTICULO)), '') <> ''

		SELECT
			D.IDARTICULO, D.NOLOTE, D.CANTIDAD, D.PCOSTO,
			COALESCE(
				TRY_CONVERT(DATE, D.FECHAVENCE_TXT, 103),
				TRY_CONVERT(DATE, D.FECHAVENCE_TXT, 23),
				TRY_CONVERT(DATE, D.FECHAVENCE_TXT, 111),
				CASE WHEN TRY_CONVERT(FLOAT, D.FECHAVENCE_TXT) BETWEEN 1 AND 600000
					THEN DATEADD(DAY, TRY_CONVERT(INT, TRY_CONVERT(FLOAT, D.FECHAVENCE_TXT)), CONVERT(DATE, '18991230')) END,
				IX.FECHAVENCE
			) AS FECHAVENCE,
			CASE WHEN IA.IDARTICULO IS NULL THEN 1 ELSE 0 END AS ERROR_ARTICULO,
			CASE WHEN COALESCE(D.NOLOTE, '') = '' THEN 1 WHEN IX.IDARTICULO IS NOT NULL THEN 0 ELSE 1 END AS CREAR_LOTE,
			CASE WHEN M.NOLOTE IS NOT NULL THEN 1 ELSE 0 END AS EN_LISTADO,
			M.NOLOTE AS IFISHU_NOLOTE,
			CASE WHEN EXISTS (SELECT 1 FROM #DATOS_SALDO_IN_A X WHERE X.IDARTICULO = D.IDARTICULO AND X.NOLOTE = D.NOLOTE AND X.FILA < D.FILA) THEN 1 ELSE 0 END AS DUPLICADO,
			D.FILA
		INTO #DATOS_PROCESADOS_A
		FROM #DATOS_SALDO_IN_A D
		LEFT JOIN IART IA ON IA.IDARTICULO = D.IDARTICULO
		OUTER APPLY (
			SELECT TOP 1 IX.FECHAVENCE, IX.IDARTICULO, IX.NOLOTEPEDIDO, IX.NOLOTE
			FROM IEXI IX
			WHERE IX.IDBODEGA = @IDBODEGA AND IX.IDARTICULO = D.IDARTICULO
			  AND (LTRIM(RTRIM(COALESCE(IX.NOLOTEPEDIDO, ''))) = LTRIM(RTRIM(D.NOLOTE))
				OR LTRIM(RTRIM(COALESCE(IX.NOLOTE, ''))) = LTRIM(RTRIM(D.NOLOTE))
				OR (TRY_CONVERT(BIGINT, LTRIM(RTRIM(IX.NOLOTEPEDIDO))) IS NOT NULL AND TRY_CONVERT(BIGINT, LTRIM(RTRIM(D.NOLOTE))) IS NOT NULL
					AND TRY_CONVERT(BIGINT, LTRIM(RTRIM(IX.NOLOTEPEDIDO))) = TRY_CONVERT(BIGINT, LTRIM(RTRIM(D.NOLOTE)))))
			ORDER BY
				CASE
					WHEN LTRIM(RTRIM(COALESCE(IX.NOLOTEPEDIDO, ''))) = LTRIM(RTRIM(D.NOLOTE)) THEN 0
					WHEN LTRIM(RTRIM(COALESCE(IX.NOLOTE, ''))) = LTRIM(RTRIM(D.NOLOTE)) THEN 1
					ELSE 2
				END,
				IX.NOLOTEPEDIDO
		) IX
		OUTER APPLY (
			SELECT TOP 1 U.NOLOTE, U.NOLOTEPEDIDO
			FROM IFISHU U
			WHERE U.CNSIFIS = @CNSIFIS AND U.USUARIO = @LISTADO
			  AND LTRIM(RTRIM(U.IDARTICULO)) = LTRIM(RTRIM(D.IDARTICULO))
			  AND (LTRIM(RTRIM(COALESCE(U.NOLOTEPEDIDO, ''))) = LTRIM(RTRIM(D.NOLOTE))
				OR LTRIM(RTRIM(COALESCE(U.NOLOTE, ''))) = LTRIM(RTRIM(D.NOLOTE))
				OR (TRY_CONVERT(BIGINT, LTRIM(RTRIM(U.NOLOTEPEDIDO))) IS NOT NULL AND TRY_CONVERT(BIGINT, LTRIM(RTRIM(D.NOLOTE))) IS NOT NULL
					AND TRY_CONVERT(BIGINT, LTRIM(RTRIM(U.NOLOTEPEDIDO))) = TRY_CONVERT(BIGINT, LTRIM(RTRIM(D.NOLOTE))))
				OR (TRY_CONVERT(BIGINT, LTRIM(RTRIM(U.NOLOTE))) IS NOT NULL AND TRY_CONVERT(BIGINT, LTRIM(RTRIM(D.NOLOTE))) IS NOT NULL
					AND TRY_CONVERT(BIGINT, LTRIM(RTRIM(U.NOLOTE))) = TRY_CONVERT(BIGINT, LTRIM(RTRIM(D.NOLOTE)))))
			ORDER BY
				CASE
					WHEN LTRIM(RTRIM(COALESCE(U.NOLOTEPEDIDO, ''))) = LTRIM(RTRIM(D.NOLOTE)) THEN 0
					WHEN LTRIM(RTRIM(COALESCE(U.NOLOTE, ''))) = LTRIM(RTRIM(D.NOLOTE)) THEN 1
					ELSE 2
				END,
				U.NOLOTE
		) M
		WHERE D.CANTIDAD IS NOT NULL AND COALESCE(D.NOLOTE, '') <> ''

		IF EXISTS (
			SELECT 1 FROM #DATOS_PROCESADOS_A
			WHERE COALESCE(ERROR_ARTICULO, 0) = 1
				OR COALESCE(DUPLICADO, 0) = 1
				OR (COALESCE(EN_LISTADO, 0) = 0 AND @ES_SI_A = 0)
				OR (COALESCE(CREAR_LOTE, 0) = 1 AND FECHAVENCE IS NULL)
		)
		BEGIN
			SELECT 'KO' OK
			INSERT INTO @TBLERRORES(ERROR) SELECT 'Debe procesar el archivo sin errores antes de almacenar.'
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		DECLARE @LOCAL_TRAN_EXCEL BIT = 0
		BEGIN TRY
			/* Nest-safe con SPQ_JSON (evitar Msg 266/3903) */
			IF @@TRANCOUNT = 0
			BEGIN
				BEGIN TRAN
				SET @LOCAL_TRAN_EXCEL = 1
			END
			ELSE
				SAVE TRANSACTION EXCEL_CONTEO

			IF EXISTS (SELECT 1 FROM #DATOS_PROCESADOS_A P WHERE NOT EXISTS (
				SELECT 1 FROM IEXI E WHERE E.IDBODEGA = @IDBODEGA AND E.IDARTICULO = P.IDARTICULO AND E.NOLOTEPEDIDO = P.NOLOTE))
			BEGIN
				SELECT @IEXI_Q_A = COUNT(1) FROM #DATOS_PROCESADOS_A P
				WHERE NOT EXISTS (SELECT 1 FROM IEXI E WHERE E.IDBODEGA = @IDBODEGA AND E.IDARTICULO = P.IDARTICULO AND E.NOLOTEPEDIDO = P.NOLOTE)

				SELECT @IEXI_CNS_A = CONSECUTIVO FROM USCXS WHERE PREFIJO = '@ICBU'
				UPDATE USCXS SET CONSECUTIVO = CONSECUTIVO + @IEXI_Q_A WHERE PREFIJO = '@ICBU'

				INSERT INTO IEXI (IDBODEGA, NOLOTE, IDARTICULO, CANTINICIAL, EXISLOTE, FECHAVENCE, NOLOTEPEDIDO, PCOSTO, IDTERCERO, FECHAMOV)
				SELECT @IDBODEGA, '01L' + RIGHT('0000000000' + CONVERT(VARCHAR(10), @IEXI_CNS_A + ROW_NUMBER() OVER (ORDER BY P.NOLOTE)), 8),
					P.IDARTICULO, 0, 0, P.FECHAVENCE, P.NOLOTE, COALESCE(P.PCOSTO, 0), NULL, CONVERT(SMALLDATETIME, GETDATE())
				FROM #DATOS_PROCESADOS_A P
				WHERE NOT EXISTS (SELECT 1 FROM IEXI E WHERE E.IDBODEGA = @IDBODEGA AND E.IDARTICULO = P.IDARTICULO AND E.NOLOTEPEDIDO = P.NOLOTE)

				INSERT INTO IFISH (CNSIFIS, IDBODEGA, IDARTICULO, EXISTOTAL, NOLOTE, NOLOTEPEDIDO, DESCRIPCION, PCOSTO, CONTEO1, CONTEO2, CONTEO3, ESTADO1, ESTADO2, ESTADO3)
				SELECT @CNSIFIS, I.IDBODEGA, I.IDARTICULO, I.EXISLOTE, I.NOLOTE, I.NOLOTEPEDIDO, A.DESCRIPCION, I.PCOSTO, 0, 0, 0, 0, 0, 0
				FROM IEXI AS I INNER JOIN IART AS A ON I.IDARTICULO = A.IDARTICULO
				WHERE I.IDBODEGA = @IDBODEGA
				  AND EXISTS (SELECT 1 FROM #DATOS_PROCESADOS_A P WHERE P.CREAR_LOTE = 1 AND I.IDARTICULO = P.IDARTICULO AND I.NOLOTEPEDIDO = P.NOLOTE)
				  AND NOT EXISTS (SELECT 1 FROM IFISH F WHERE F.CNSIFIS = @CNSIFIS AND F.IDBODEGA = I.IDBODEGA AND F.IDARTICULO = I.IDARTICULO AND F.NOLOTE = I.NOLOTE)

				EXEC SPK_GENERARFISICO_U @CNSIFIS, @IDBODEGA, 0, @LISTADO
			END

			INSERT INTO IDXB (IDBODEGA, IDARTICULO, STOCKMINIMO, STOCKMAXIMO, PUNTOREORDEN, EXISTOTAL)
			SELECT @IDBODEGA, P.IDARTICULO, IART.STOCKMINIMO, IART.STOCKMAXIMO, IART.PUNTOREORDEN, 0
			FROM (
				SELECT DISTINCT IDARTICULO
				FROM #DATOS_PROCESADOS_A
			) P
			INNER JOIN IART ON IART.IDARTICULO = P.IDARTICULO
			WHERE NOT EXISTS (
				SELECT 1 FROM IDXB
				WHERE IDXB.IDBODEGA = @IDBODEGA AND IDXB.IDARTICULO = P.IDARTICULO
			)

			/* PCOSTO del Excel en el lote (IEXI) y en el conteo (IFISH), SI o conteo fisico. */
			UPDATE E
			SET PCOSTO = P.PCOSTO
			FROM IEXI E
			INNER JOIN #DATOS_PROCESADOS_A P ON E.IDARTICULO = P.IDARTICULO
				AND (
					LTRIM(RTRIM(COALESCE(E.NOLOTEPEDIDO, ''))) = LTRIM(RTRIM(P.NOLOTE))
					OR LTRIM(RTRIM(COALESCE(E.NOLOTE, ''))) = LTRIM(RTRIM(P.NOLOTE))
				)
			WHERE E.IDBODEGA = @IDBODEGA
			  AND COALESCE(P.PCOSTO, 0) > 0

			UPDATE F
			SET PCOSTO = P.PCOSTO
			FROM IFISH F
			INNER JOIN #DATOS_PROCESADOS_A P ON LTRIM(RTRIM(P.IDARTICULO)) = LTRIM(RTRIM(F.IDARTICULO))
				AND (
					P.IFISHU_NOLOTE = F.NOLOTE
					OR LTRIM(RTRIM(COALESCE(F.NOLOTEPEDIDO, ''))) = LTRIM(RTRIM(P.NOLOTE))
					OR LTRIM(RTRIM(COALESCE(F.NOLOTE, ''))) = LTRIM(RTRIM(P.NOLOTE))
				)
			WHERE F.CNSIFIS = @CNSIFIS AND F.IDBODEGA = @IDBODEGA
			  AND COALESCE(F.NOLOTE, '') <> '__LISTADO__'
			  AND COALESCE(P.PCOSTO, 0) > 0

			UPDATE IART SET PCOSTO = I.PCOSTO
			FROM IART INNER JOIN IEXI I ON I.IDARTICULO = IART.IDARTICULO
			WHERE I.IDBODEGA = @IDBODEGA AND COALESCE(IART.PCOSTO, 0) = 0
			  AND EXISTS (SELECT 1 FROM #DATOS_PROCESADOS_A P WHERE P.IDARTICULO = I.IDARTICULO AND COALESCE(P.PCOSTO, 0) > 0)

			IF @RONDA_A = 1
				UPDATE U SET CONTEO1 = P.CANTIDAD, FECHA1 = CONVERT(SMALLDATETIME, GETDATE())
				FROM IFISHU U
				INNER JOIN #DATOS_PROCESADOS_A P ON LTRIM(RTRIM(P.IDARTICULO)) = LTRIM(RTRIM(U.IDARTICULO))
					AND (
						P.IFISHU_NOLOTE = U.NOLOTE
						OR LTRIM(RTRIM(COALESCE(U.NOLOTEPEDIDO, ''))) = LTRIM(RTRIM(P.NOLOTE))
						OR LTRIM(RTRIM(COALESCE(U.NOLOTE, ''))) = LTRIM(RTRIM(P.NOLOTE))
					)
				WHERE U.CNSIFIS = @CNSIFIS AND U.IDBODEGA = @IDBODEGA AND U.USUARIO = @LISTADO
				  AND COALESCE(U.NOLOTE, '') <> '__LISTADO__'
			ELSE IF @RONDA_A = 2
				UPDATE U SET CONTEO2 = P.CANTIDAD, FECHA2 = CONVERT(SMALLDATETIME, GETDATE())
				FROM IFISHU U
				INNER JOIN #DATOS_PROCESADOS_A P ON LTRIM(RTRIM(P.IDARTICULO)) = LTRIM(RTRIM(U.IDARTICULO))
					AND (
						P.IFISHU_NOLOTE = U.NOLOTE
						OR LTRIM(RTRIM(COALESCE(U.NOLOTEPEDIDO, ''))) = LTRIM(RTRIM(P.NOLOTE))
						OR LTRIM(RTRIM(COALESCE(U.NOLOTE, ''))) = LTRIM(RTRIM(P.NOLOTE))
					)
				WHERE U.CNSIFIS = @CNSIFIS AND U.IDBODEGA = @IDBODEGA AND U.USUARIO = @LISTADO
				  AND COALESCE(U.NOLOTE, '') <> '__LISTADO__'
			ELSE IF @RONDA_A = 3
				UPDATE U SET CONTEO3 = P.CANTIDAD, FECHA3 = CONVERT(SMALLDATETIME, GETDATE())
				FROM IFISHU U
				INNER JOIN #DATOS_PROCESADOS_A P ON LTRIM(RTRIM(P.IDARTICULO)) = LTRIM(RTRIM(U.IDARTICULO))
					AND (
						P.IFISHU_NOLOTE = U.NOLOTE
						OR LTRIM(RTRIM(COALESCE(U.NOLOTEPEDIDO, ''))) = LTRIM(RTRIM(P.NOLOTE))
						OR LTRIM(RTRIM(COALESCE(U.NOLOTE, ''))) = LTRIM(RTRIM(P.NOLOTE))
					)
				WHERE U.CNSIFIS = @CNSIFIS AND U.IDBODEGA = @IDBODEGA AND U.USUARIO = @LISTADO
				  AND COALESCE(U.NOLOTE, '') <> '__LISTADO__'

			IF @ES_SI_A = 1
			BEGIN
				/* Saldo inicial: un Excel es la cantidad definitiva. No usar -1 de tercer conteo. */
				UPDATE IFISHU
				SET
					CONTEO1 = CASE WHEN COALESCE(NOLOTE, '') = '__LISTADO__' THEN 0 ELSE CONTEO1 END,
					CONTEO2 = CASE WHEN COALESCE(NOLOTE, '') = '__LISTADO__' THEN 0 ELSE CONTEO1 END,
					CONTEO3 = CASE WHEN COALESCE(NOLOTE, '') = '__LISTADO__' THEN 0 ELSE CONTEO1 END,
					FECHA2 = CONVERT(SMALLDATETIME, GETDATE()),
					FECHA3 = CONVERT(SMALLDATETIME, GETDATE()),
					ESTADO1 = 1, ESTADO2 = 1, ESTADO3 = 1
				WHERE CNSIFIS = @CNSIFIS AND USUARIO = @LISTADO

				UPDATE IFISH
				SET
					CONTEO1 = X.C1, CONTEO2 = X.C2, CONTEO3 = X.C3,
					ESTADO1 = 1, ESTADO2 = 1, ESTADO3 = 1,
					FECHA1 = X.F1, FECHA2 = X.F2, FECHA3 = X.F3
				FROM IFISH F
				INNER JOIN (
					SELECT IDARTICULO, NOLOTE,
						SUM(COALESCE(CONTEO1, 0)) C1,
						SUM(COALESCE(CONTEO2, 0)) C2,
						SUM(COALESCE(CONTEO3, 0)) C3,
						MAX(FECHA1) F1, MAX(FECHA2) F2, MAX(FECHA3) F3
					FROM IFISHU
					WHERE CNSIFIS = @CNSIFIS
					GROUP BY IDARTICULO, NOLOTE
				) X ON X.IDARTICULO = F.IDARTICULO AND X.NOLOTE = F.NOLOTE
				WHERE F.CNSIFIS = @CNSIFIS AND F.IDBODEGA = @IDBODEGA
			END
			ELSE IF @RONDA_A = 1
				UPDATE IFISHU SET ESTADO1 = 1 WHERE CNSIFIS = @CNSIFIS AND USUARIO = @LISTADO
			ELSE IF @RONDA_A = 2
				UPDATE IFISHU SET ESTADO2 = 1,
					CONTEO3 = CASE
						WHEN COALESCE(CONTEO2, 0) = COALESCE(CONTEO1, 0) THEN CONTEO2
						ELSE COALESCE(CONTEO3, 0)
					END,
					ESTADO3 = CASE
						WHEN COALESCE(CONTEO2, 0) = COALESCE(CONTEO1, 0) THEN 1
						ELSE COALESCE(ESTADO3, 0)
					END
				WHERE CNSIFIS = @CNSIFIS AND USUARIO = @LISTADO
			ELSE IF @RONDA_A = 3
				UPDATE IFISHU SET ESTADO3 = 1 WHERE CNSIFIS = @CNSIFIS AND USUARIO = @LISTADO

			IF @LOCAL_TRAN_EXCEL = 1 AND @@TRANCOUNT > 0
				COMMIT TRAN
		END TRY
		BEGIN CATCH
			IF @LOCAL_TRAN_EXCEL = 1
			BEGIN
				IF @@TRANCOUNT > 0 ROLLBACK TRAN
			END
			ELSE IF @@TRANCOUNT > 0 AND XACT_STATE() <> -1
				ROLLBACK TRANSACTION EXCEL_CONTEO
			ELSE IF @@TRANCOUNT > 0 AND XACT_STATE() = -1
				ROLLBACK TRAN
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK, @RONDA_A RONDA, 1 ALMACENADO
	END
END
