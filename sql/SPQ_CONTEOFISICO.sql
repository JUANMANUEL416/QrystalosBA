CREATE OR ALTER PROCEDURE DBO.SPQ_CONTEOFISICO
@JSON  NVARCHAR(MAX) 
WITH
ENCRYPTION
AS
DECLARE  @PARAMETROS   NVARCHAR(MAX) ,@MODELO           VARCHAR(100) ,@METODO           VARCHAR(100)  ,@USUARIO        VARCHAR(12),
			@GRUPO        VARCHAR(8)    ,@SYS_COMPUTERNAME VARCHAR(254) ,@IDSEDE             VARCHAR(5)    ,@USUNOMBRE     VARCHAR(100), @SEDE VARCHAR(5),
			@FECHA        VARCHAR(10)   ,@IDEMEDICA        VARCHAR(4)	,@FECHA1           DATETIME		,@SQL            VARCHAR(MAX),
			@COMPANIA		VARCHAR(10)	,@IDAFILIADO VARCHAR(20)	,@FECHAINI DATE
			,@OBSERVACION	VARCHAR(MAX)	,@IDAUT	VARCHAR(20)	,@NO_ITEM INT	,@PROCEDENCIA VARCHAR(20)	,@CONTEO INT
			,@CONSECUTIVO VARCHAR(20)	 , @datoIFIS NVARCHAR(MAX)	, @PROCESO VARCHAR(20), @CODCAJERO VARCHAR(20)	,@CNSIFIS VARCHAR(20)
			,@CONEXISTENCIAS BIT, @SALDOINICIAL BIT, @IDBODEGA VARCHAR(20), @IN_ANTERIORES BIT, @PORESTANTE BIT, @IN_INACTIVOS BIT, @ESTANTE BIT
			,@ESTADO1 INT ,@ESTADO2 INT ,@ESTADO3 INT	,@DATO INT	,@LISTADO VARCHAR(20)	,@NOLOTE VARCHAR(20), @IDARTICULO VARCHAR(20)
			, @CONTADOR_ANTERIOR VARCHAR(20)	,@FECHAVENCE VARCHAR(10), @CONTEO1 DECIMAL(14,2), @CONTEO2 DECIMAL(14,2), @CONTEO3 DECIMAL(14,2)
			,@CONTEO_ACTUAL VARCHAR(20), @CONTEO_ANTERIOR VARCHAR(20), @SINDETALLE BIT, @FECHASANT BIT, @FILA INT	, @NOLOTEPEDIDO VARCHAR(50)
			,@sqlCommand		NVARCHAR(max) ,@Result VARCHAR(50), @PCOSTO DECIMAL(14,2), @NOLOTE_NUEVO VARCHAR(20)
			,@CNSRPDX VARCHAR(20), @DATOS_SALDO NVARCHAR(MAX), @ERRADOS INT, @CANTIDAD_SI DECIMAL(14,2)
BEGIN 
	SET LANGUAGE Spanish;  
	SET DATEFORMAT dmy
	SELECT *
	INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)  AS JSON
	)

	SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON
	--DEFINICION DE TABLA DE ERRORES
	DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200));
	-- TOMA DEL GRUPO, SYS_COMPUTERNAME, SEDE   DE ACUERDO AL USUARIOpl,   --PRINT 'USUARIO:'+@USUARIO
	SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO), @USUNOMBRE = NOMBRE FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME, @COMPANIA = COMPANIA, @CODCAJERO= CODCAJERO FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @IDSEDE = IDSEDE, @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
	PRINT '@USUARIO='+@USUARIO

	

	IF @METODO = 'CRUD'
	BEGIN
		SELECT @datoIFIS =  datoIFIS
		FROM OPENJSON (@PARAMETROS)
		WITH		 ( datoIFIS	NVARCHAR(MAX)  AS JSON )

		SELECT @PROCESO     = JSON_VALUE(@datoIFIS ,'$.PROCESO') 
		SELECT    *  INTO #datoIFIS
		FROM OPENJSON (@datoIFIS)
		WITH (	PROCESO				VARCHAR(20)		'$.PROCESO'			,CONEXISTENCIAS				BIT				'$.CONEXISTENCIAS'
				,IN_ANTERIORES		BIT				'$.IN_ANTERIORES'	,IN_INACTIVOS		BIT				'$.IN_INACTIVOS'
				,SALDOINICIAL		BIT				'$.SALDOINICIAL'	,PORESTANTE		BIT	'$.PORESTANTE'
				,IDBODEGA			VARCHAR	(20)		'$.IDBODEGA'		,ESTANTE		VARCHAR	'$.ESTANTE'
				,CNSIFIS			VARCHAR(20)	'$.CNSIFIS'		)

		SELECT  @CONEXISTENCIAS = COALESCE(CONEXISTENCIAS,0),@IN_ANTERIORES = COALESCE(IN_ANTERIORES,0),@IN_INACTIVOS = COALESCE(IN_INACTIVOS,0)
		,@SALDOINICIAL = COALESCE(SALDOINICIAL,0),@PORESTANTE = COALESCE(PORESTANTE,0),@IDBODEGA = COALESCE(IDBODEGA,NULL),@PORESTANTE = COALESCE(PORESTANTE,0)
		,@ESTANTE = COALESCE(ESTANTE,NULL) FROM #datoIFIS

		IF COALESCE(@IDBODEGA,'')=''
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'Debe de Seleccionar una Bodega'
		END
	
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				IF @PROCESO = 'NUEVO'
				BEGIN
					EXEC SPK_GENCONSECUTIVO '01',@IDSEDE,'@IFIS',@CNSIFIS OUTPUT

					SET @CNSIFIS = @IDSEDE + REPLACE(SPACE(8 - LEN(@CNSIFIS))+LTRIM(RTRIM(@CNSIFIS)),SPACE(1),0) 

					INSERT INTO IFIS (CNSIFIS, FECHA, IDBODEGA, CERRADO, DETALLE, SI, PORESTANTE, ESTANTE)
					SELECT @CNSIFIS, DBO.FNK_GETDATE(), IDBODEGA, 0,
						SUBSTRING('Inventario f?sico de '+LTRIM(RTRIM(DESCRIPCION))+' '+LTRIM(RTRIM(CAST(GETDATE() AS VARCHAR(30)))),1,60), 
						@SALDOINICIAL, @PORESTANTE, @ESTANTE
					FROM IBOD WHERE IDBODEGA = @IDBODEGA 
						--AND NOT EXISTS (SELECT 1 FROM IFIS WHERE CNSIFIS=@CNSIFIS AND IBOD.IDBODEGA=IFIS.IDBODEGA)

					IF @PORESTANTE=1
					BEGIN
						INSERT INTO IFISH (CNSIFIS, IDBODEGA, IDARTICULO, NOLOTE, NOLOTEPEDIDO, EXISTOTAL, DESCRIPCION, PCOSTO, CONTEO1, CONTEO2, CONTEO3, ESTADO1, ESTADO2, ESTADO3)
						SELECT @CNSIFIS, IEXI.IDBODEGA, IEXI.IDARTICULO, IEXI.NOLOTE, IEXI.NOLOTEPEDIDO, IEXI.EXISLOTE, IART.DESCRIPCION, COALESCE(NULLIF(IEXI.PCOSTO, 0), IART.PCOSTO, 0), 0, 0, 0, 0, 0, 0
						FROM IART INNER JOIN IEXI ON IART.IDARTICULO = IEXI.IDARTICULO
						WHERE IEXI.IDBODEGA=@IDBODEGA AND IEXI.EXISLOTE>=@CONEXISTENCIAS AND COALESCE(IEXI.ESTADO,'Activo')='Activo'
							AND IART.ESTADO=(CASE @IN_INACTIVOS WHEN 0 THEN 'Activo' ELSE IART.ESTADO END)
							AND EXISTS (SELECT 1 FROM IARTE INNER JOIN TGEN E ON E.TABLA=IARTE.IDBODEGA AND E.CAMPO='ESTANTE' AND E.CODIGO=IARTE.ESTANTE
										WHERE IARTE.IDBODEGA=IEXI.IDBODEGA AND IARTE.IDARTICULO=IEXI.IDARTICULO AND COALESCE(E.DATO1,'')=@ESTANTE)
							AND NOT EXISTS (SELECT 1 FROM IFISH WHERE IFISH.CNSIFIS=@CNSIFIS AND IFISH.IDBODEGA=@IDBODEGA 
											AND IFISH.IDARTICULO=IART.IDARTICULO AND IFISH.NOLOTE=IEXI.NOLOTE)
					END
					ELSE
					BEGIN
						INSERT INTO IFISH (CNSIFIS, IDBODEGA, IDARTICULO, NOLOTE, NOLOTEPEDIDO, EXISTOTAL, DESCRIPCION, PCOSTO, CONTEO1, CONTEO2, CONTEO3, ESTADO1, ESTADO2, ESTADO3)
						SELECT @CNSIFIS, IEXI.IDBODEGA, IEXI.IDARTICULO, IEXI.NOLOTE, IEXI.NOLOTEPEDIDO, IEXI.EXISLOTE, IART.DESCRIPCION, COALESCE(NULLIF(IEXI.PCOSTO, 0), IART.PCOSTO, 0), 0, 0, 0, 0, 0, 0
						FROM IART INNER JOIN IEXI ON IART.IDARTICULO = IEXI.IDARTICULO
						WHERE IEXI.IDBODEGA=@IDBODEGA AND IEXI.EXISLOTE>=@CONEXISTENCIAS AND COALESCE(IEXI.ESTADO,'Activo')='Activo'
							AND IART.ESTADO=(CASE @IN_INACTIVOS WHEN 0 THEN 'Activo' ELSE IART.ESTADO END)
							AND NOT EXISTS (SELECT 1 FROM IFISH WHERE IFISH.CNSIFIS=@CNSIFIS AND IFISH.IDBODEGA=@IDBODEGA 
											AND IFISH.IDARTICULO=IART.IDARTICULO AND IFISH.NOLOTE=IEXI.NOLOTE) 

						IF @IN_ANTERIORES = 1
						BEGIN
							INSERT INTO IFISH (CNSIFIS, IDBODEGA, IDARTICULO, NOLOTE, NOLOTEPEDIDO, EXISTOTAL, DESCRIPCION, PCOSTO, CONTEO1, CONTEO2, CONTEO3, ESTADO1, ESTADO2, ESTADO3) 
							SELECT @CNSIFIS, @IDBODEGA, IFISH.IDARTICULO, IFISH.NOLOTE, IFISH.NOLOTEPEDIDO, 0, IART.DESCRIPCION, COALESCE(NULLIF(IFISH.PCOSTO, 0), IART.PCOSTO, 0), 0, 0, 0, 0, 0, 0
							FROM IFISH INNER JOIN IART ON IFISH.IDARTICULO=IART.IDARTICULO
							WHERE IART.ESTADO=(CASE @IN_INACTIVOS WHEN 0 THEN 'Activo' ELSE IART.ESTADO END)
								AND CNSIFIS=(SELECT TOP 1 CNSIFIS FROM IFIS WHERE CNSIFIS<>@CNSIFIS AND IDBODEGA=@IDBODEGA AND CERRADO=1 ORDER BY FECHACONF DESC)
								AND NOT EXISTS (SELECT 1 FROM IFISH A WHERE A.CNSIFIS=@CNSIFIS AND A.IDBODEGA=@IDBODEGA AND A.IDARTICULO=IFISH.IDARTICULO AND A.NOLOTE=IFISH.NOLOTE)
								AND ISNULL(CONTEO1,0)+ISNULL(CONTEO2,0)+ISNULL(CONTEO3,0) > 0
						END
					END

					/* Bodega nueva: si "solo existencias" no trajo filas, incluir lotes en cero. */
					IF NOT EXISTS (SELECT 1 FROM IFISH WHERE CNSIFIS = @CNSIFIS)
					BEGIN
						INSERT INTO IFISH (CNSIFIS, IDBODEGA, IDARTICULO, NOLOTE, NOLOTEPEDIDO, EXISTOTAL, DESCRIPCION, PCOSTO, CONTEO1, CONTEO2, CONTEO3, ESTADO1, ESTADO2, ESTADO3)
						SELECT @CNSIFIS, @IDBODEGA, IEXI.IDARTICULO, IEXI.NOLOTE, IEXI.NOLOTEPEDIDO, IEXI.EXISLOTE, IART.DESCRIPCION, COALESCE(NULLIF(IEXI.PCOSTO, 0), IART.PCOSTO, 0), 0, 0, 0, 0, 0, 0
						FROM IART INNER JOIN IEXI ON IART.IDARTICULO = IEXI.IDARTICULO
						WHERE LTRIM(RTRIM(IEXI.IDBODEGA)) = LTRIM(RTRIM(@IDBODEGA))
							AND COALESCE(IEXI.ESTADO,'Activo')='Activo'
							AND IART.ESTADO=(CASE @IN_INACTIVOS WHEN 0 THEN 'Activo' ELSE IART.ESTADO END)
							AND NOT EXISTS (SELECT 1 FROM IFISH WHERE IFISH.CNSIFIS=@CNSIFIS AND IFISH.IDARTICULO=IART.IDARTICULO AND IFISH.NOLOTE=IEXI.NOLOTE)
					END

				END
			END TRY  
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK
		END 
	END
	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @CNSIFIS =  CNSIFIS
		FROM OPENJSON (@PARAMETROS)
		WITH		 ( CNSIFIS		VARCHAR(20)		'$.CNSIFIS')

		IF EXISTS (SELECT * FROM IFIS WHERE COALESCE(CERRADO,0) = 1 AND CNSIFIS = @CNSIFIS)
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El Conteo ya se Encuentra Aplicado'
		END
		IF EXISTS (SELECT * FROM IFISH WHERE  (ISNULL(ESTADO1,0)=1 OR ISNULL(ESTADO2,0)=1 OR ISNULL(ESTADO3,0)=1)  AND CNSIFIS = @CNSIFIS)
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'Este consecutivo ya tiene conteos cerrados por lo que no se puede borrar.'
		END

		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				DELETE FROM IFISHU WHERE CNSIFIS=@CNSIFIS 
				DELETE FROM IFISH WHERE CNSIFIS=@CNSIFIS 
				DELETE FROM IFIS WHERE CNSIFIS=@CNSIFIS 
			END TRY  
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK
		END 

	END
	IF @METODO = 'CERRAR_CONTEO'
	BEGIN
		SELECT @CNSIFIS =  CNSIFIS, @LISTADO = LISTADO
		FROM OPENJSON (@PARAMETROS)
		WITH		 ( CNSIFIS		VARCHAR(20)		'$.CNSIFIS', LISTADO		VARCHAR(20)		'$.LISTADO')

		IF NOT EXISTS (SELECT * FROM IFISHU WHERE CNSIFIS = @CNSIFIS AND COALESCE(ESTADO1,0) = 0 AND USUARIO = @LISTADO)
			AND NOT EXISTS (SELECT * FROM IFISHU WHERE CNSIFIS = @CNSIFIS AND COALESCE(ESTADO2,0) = 0  AND USUARIO = @LISTADO)
			AND NOT EXISTS (SELECT * FROM IFISHU WHERE CNSIFIS = @CNSIFIS AND COALESCE(ESTADO3,0) = 0  AND USUARIO = @LISTADO)
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'Todos los Conteos para Este Contador en esta Bodega han sido Aplicados.'
		END
		IF NOT EXISTS (SELECT * FROM IFISHU WHERE CNSIFIS = @CNSIFIS AND USUARIO = @LISTADO )
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'No existen registros para el Listado Seleccionado'
		END
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				SELECT @IDBODEGA = IDBODEGA FROM IFIS WHERE CNSIFIS = @CNSIFIS
				IF  EXISTS (SELECT * FROM IFISHU WHERE CNSIFIS = @CNSIFIS AND COALESCE(ESTADO1,0) = 0 AND USUARIO = @LISTADO)
				BEGIN
					SELECT @CONTEO = 1
					UPDATE IFISHU SET ESTADO1=1
					WHERE CNSIFIS=@CNSIFIS AND USUARIO = @LISTADO
					IF NOT EXISTS (
						SELECT 1 FROM IFISHU
						WHERE CNSIFIS = @CNSIFIS AND COALESCE(ESTADO1, 0) = 0 AND COALESCE(NOLOTE, '') <> '__LISTADO__'
					)
					BEGIN
						SELECT IART.IDARTICULO, IFISHU.NOLOTE, IART.PCOSTO,
							SUM(CONTEO1) AS CONTEO1, SUM(CONTEO2) AS CONTEO2, SUM(CONTEO3) AS CONTEO3
						INTO #C1
						FROM IFISHU, IART
						WHERE CNSIFIS = @CNSIFIS AND IDBODEGA = @IDBODEGA AND ESTADO1 = 1
						  AND IFISHU.IDARTICULO = IART.IDARTICULO
						  AND COALESCE(IFISHU.NOLOTE, '') <> '__LISTADO__'
						GROUP BY IART.IDARTICULO, IFISHU.NOLOTE, IART.PCOSTO

						UPDATE IFISH SET CONTEO1 = #C1.CONTEO1, ESTADO1 = 1, FECHA1 = DBO.FNK_FECHA_SIN_MLS(GETDATE()), PCOSTO = #C1.PCOSTO
						FROM #C1
						WHERE CNSIFIS = @CNSIFIS AND IDBODEGA = @IDBODEGA
						  AND IFISH.IDARTICULO = #C1.IDARTICULO AND IFISH.NOLOTE = #C1.NOLOTE

						UPDATE IFISH
						SET ESTADO1 = 1, CONTEO1 = COALESCE(EXISTOTAL, 0), FECHA1 = COALESCE(FECHA1, DBO.FNK_FECHA_SIN_MLS(GETDATE()))
						WHERE CNSIFIS = @CNSIFIS AND IDBODEGA = @IDBODEGA
						  AND COALESCE(ESTADO1, 0) = 0 AND COALESCE(NOLOTE, '') <> '__LISTADO__'
					END
					SELECT 'OK'OK, @CONTEO CONTEO
					RETURN
				END
				IF NOT EXISTS (SELECT * FROM IFISHU WHERE CNSIFIS = @CNSIFIS AND COALESCE(ESTADO1,0) = 0 AND USUARIO = @LISTADO)
					AND EXISTS (SELECT * FROM IFISHU WHERE CNSIFIS = @CNSIFIS AND COALESCE(ESTADO2,0) = 0 AND USUARIO = @LISTADO)
				BEGIN
					SELECT @CONTEO = 2
					IF EXISTS (SELECT 1 FROM IFIS WHERE CNSIFIS = @CNSIFIS AND COALESCE(SI, 0) = 1)
						UPDATE IFISHU SET ESTADO2 = 1, CONTEO2 = CONTEO1, CONTEO3 = CONTEO1, ESTADO3 = 1
						WHERE CNSIFIS = @CNSIFIS AND USUARIO = @LISTADO
					ELSE
						/* Sin sentinel -1: si C1?C2 se deja CONTEO3 y ESTADO3 abiertos para forzar 3er conteo */
						UPDATE IFISHU
						SET ESTADO2 = 1,
							CONTEO3 = CASE
								WHEN COALESCE(CONTEO2, 0) = COALESCE(CONTEO1, 0) THEN CONTEO2
								ELSE COALESCE(CONTEO3, 0)
							END,
							ESTADO3 = CASE
								WHEN COALESCE(CONTEO2, 0) = COALESCE(CONTEO1, 0) THEN 1
								ELSE COALESCE(ESTADO3, 0)
							END
						WHERE CNSIFIS = @CNSIFIS AND USUARIO = @LISTADO
					IF NOT EXISTS (
						SELECT 1 FROM IFISHU
						WHERE CNSIFIS = @CNSIFIS AND COALESCE(ESTADO2, 0) = 0 AND COALESCE(NOLOTE, '') <> '__LISTADO__'
					)
					BEGIN
						SELECT IART.IDARTICULO, IFISHU.NOLOTE, IART.PCOSTO,
							SUM(CONTEO1) AS CONTEO1, SUM(CONTEO2) AS CONTEO2, SUM(CONTEO3) AS CONTEO3
						INTO #C2
						FROM IFISHU, IART
						WHERE CNSIFIS = @CNSIFIS AND IDBODEGA = @IDBODEGA AND ESTADO2 = 1
						  AND IFISHU.IDARTICULO = IART.IDARTICULO
						  AND COALESCE(IFISHU.NOLOTE, '') <> '__LISTADO__'
						GROUP BY IART.IDARTICULO, IFISHU.NOLOTE, IART.PCOSTO

						UPDATE IFISH
						SET CONTEO2 = #C2.CONTEO2,
							ESTADO2 = 1,
							FECHA2 = DBO.FNK_FECHA_SIN_MLS(GETDATE()),
							PCOSTO = #C2.PCOSTO,
							/* Si C1=C2 el 3er conteo se cierra autom�ticamente con la misma cantidad */
							CONTEO3 = CASE
								WHEN COALESCE(#C2.CONTEO1, 0) = COALESCE(#C2.CONTEO2, 0) THEN #C2.CONTEO3
								ELSE IFISH.CONTEO3
							END,
							ESTADO3 = CASE
								WHEN COALESCE(#C2.CONTEO1, 0) = COALESCE(#C2.CONTEO2, 0) THEN 1
								ELSE IFISH.ESTADO3
							END,
							FECHA3 = CASE
								WHEN COALESCE(#C2.CONTEO1, 0) = COALESCE(#C2.CONTEO2, 0)
									THEN DBO.FNK_FECHA_SIN_MLS(GETDATE())
								ELSE IFISH.FECHA3
							END
						FROM #C2
						WHERE CNSIFIS = @CNSIFIS AND IDBODEGA = @IDBODEGA
						  AND IFISH.IDARTICULO = #C2.IDARTICULO AND IFISH.NOLOTE = #C2.NOLOTE

						UPDATE IFISH
						SET ESTADO2 = 1, CONTEO2 = COALESCE(EXISTOTAL, 0), FECHA2 = COALESCE(FECHA2, DBO.FNK_FECHA_SIN_MLS(GETDATE()))
						WHERE CNSIFIS = @CNSIFIS AND IDBODEGA = @IDBODEGA
						  AND COALESCE(ESTADO2, 0) = 0 AND COALESCE(NOLOTE, '') <> '__LISTADO__'
					END
					SELECT 'OK'OK, @CONTEO CONTEO
					RETURN
				END
				IF NOT EXISTS (SELECT * FROM IFISHU WHERE CNSIFIS = @CNSIFIS AND COALESCE(ESTADO1,0) = 0 AND USUARIO = @LISTADO)
					AND NOT EXISTS (SELECT * FROM IFISHU WHERE CNSIFIS = @CNSIFIS AND COALESCE(ESTADO2,0) = 0 AND USUARIO = @LISTADO)
					AND EXISTS (SELECT * FROM IFISHU WHERE CNSIFIS = @CNSIFIS AND COALESCE(ESTADO3,0) = 0 AND USUARIO = @LISTADO)
				BEGIN
					SELECT @CONTEO = 3
					UPDATE IFISHU SET ESTADO3=1
					WHERE CNSIFIS=@CNSIFIS  AND USUARIO = @LISTADO
					IF NOT EXISTS (
						SELECT 1 FROM IFISHU
						WHERE CNSIFIS = @CNSIFIS AND COALESCE(ESTADO3, 0) = 0 AND COALESCE(NOLOTE, '') <> '__LISTADO__'
					)
					BEGIN
						SELECT IART.IDARTICULO, IFISHU.NOLOTE, IART.PCOSTO,
							SUM(CONTEO1) AS CONTEO1, SUM(CONTEO2) AS CONTEO2, SUM(CONTEO3) AS CONTEO3
						INTO #C3
						FROM IFISHU, IART
						WHERE CNSIFIS = @CNSIFIS AND IDBODEGA = @IDBODEGA AND ESTADO3 = 1
						  AND IFISHU.IDARTICULO = IART.IDARTICULO
						  AND COALESCE(IFISHU.NOLOTE, '') <> '__LISTADO__'
						GROUP BY IART.IDARTICULO, IFISHU.NOLOTE, IART.PCOSTO

						UPDATE IFISH SET CONTEO3 = #C3.CONTEO3, ESTADO3 = 1, FECHA3 = DBO.FNK_FECHA_SIN_MLS(GETDATE()), PCOSTO = #C3.PCOSTO
						FROM #C3
						WHERE CNSIFIS = @CNSIFIS AND IDBODEGA = @IDBODEGA
						  AND IFISH.IDARTICULO = #C3.IDARTICULO AND IFISH.NOLOTE = #C3.NOLOTE

						UPDATE IFISH
						SET ESTADO3 = 1, CONTEO3 = COALESCE(EXISTOTAL, 0), FECHA3 = COALESCE(FECHA3, DBO.FNK_FECHA_SIN_MLS(GETDATE()))
						WHERE CNSIFIS = @CNSIFIS AND IDBODEGA = @IDBODEGA
						  AND COALESCE(ESTADO3, 0) = 0 AND COALESCE(NOLOTE, '') <> '__LISTADO__'
					END
					SELECT 'OK'OK, @CONTEO CONTEO
					RETURN
				END

			END TRY  
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK
		END 

	END
	IF @METODO = 'ABRIR_CONTEO'
	BEGIN
		SELECT @CNSIFIS =  CNSIFIS, @LISTADO = LISTADO
		FROM OPENJSON (@PARAMETROS)
		WITH		 ( CNSIFIS		VARCHAR(20)		'$.CNSIFIS', LISTADO		VARCHAR(20)		'$.LISTADO')

		SELECT @ESTADO1 = 0, @ESTADO2 = 0, @ESTADO3 = 0
		IF NOT EXISTS (SELECT * FROM IFISHU WHERE CNSIFIS = @CNSIFIS AND COALESCE(ESTADO1,0) = 0  AND USUARIO = @LISTADO)
		BEGIN
			SELECT @ESTADO1 = 1
		END
		IF NOT EXISTS (SELECT * FROM IFISHU WHERE CNSIFIS = @CNSIFIS AND COALESCE(ESTADO2,0) = 0  AND USUARIO = @LISTADO)
		BEGIN
			SELECT @ESTADO2 = 1
		END
