SET NOCOUNT ON;
SELECT COUNT(*) TOTAL,
  SUM(CASE WHEN MONTH(M.FECHAMOV)=9 AND YEAR(M.FECHAMOV)=2026 THEN 1 ELSE 0 END) FECHAMOV_SEP,
  SUM(CASE WHEN MONTH(M.FECHAMOV)=7 THEN 1 ELSE 0 END) FECHAMOV_JUL,
  SUM(CASE WHEN M.IDTIPOMOV=N'05' THEN 1 ELSE 0 END) TIPO_05
FROM IMOV M
WHERE M.IDBODEGA=N'044' AND M.MARCACONT=1 AND COALESCE(M.CONTABILIZADA,0)=0 AND M.ESTADO=1;

SELECT TOP 5 M.CNSMOV, M.IDTIPOMOV, M.IDPLAN, COALESCE(P.CAPITADO,0) CAP, COALESCE(P.PGP,0) PGP
FROM IMOV M
LEFT JOIN PPT P ON P.IDTERCERO=M.IDTERCERO AND P.IDPLAN=M.IDPLAN
WHERE M.IDBODEGA=N'044' AND M.MARCACONT=1 AND COALESCE(M.CONTABILIZADA,0)=0 AND M.ESTADO=1
  AND M.IDTIPOMOV IN (N'31',N'VC') AND MONTH(M.FECHAMOV)=9;
