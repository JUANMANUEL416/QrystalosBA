CREATE OR ALTER PROCEDURE DBO.SPQ_SEMAFORO
@JSON NVARCHAR(MAX)
WITH ENCRYPTION
AS
DECLARE   @PARAMETROS       NVARCHAR(MAX),      @MODELO         VARCHAR(100)	,@METODO      VARCHAR(100)
        , @QUERY            VARCHAR(MAX),       @USUARIO        VARCHAR(12)		,@NVOCONSEC   VARCHAR(20)
        , @SEDE             VARCHAR(5)        , @NOADMISION     VARCHAR(16)		,@FECHA       VARCHAR(20)         
        , @HORA             VARCHAR(10)       , @ITEM           SMALLINT		,@OBS         VARCHAR(2048)
        , @SYS_COMPUTERNAME VARCHAR(254)      , @GRUPO          VARCHAR(8)		,@PENDIENTES  SMALLINT
        , @CNSMOV           VARCHAR(20)		  , @FIRMA			VARBINARY(MAX)	,@IDBODEGA VARCHAR(20)
		, @CNSITRA			VARCHAR(20)			,@datoIMOVH NVARCHAR(MAX)	, @PROCESO VARCHAR(50)
		,@NOLOTE VARCHAR(50)	, @datoIMOV NVARCHAR(MAX)	, @TIPO VARCHAR(20),	@MAYOR0 BIT	,@ESTADO VARCHAR(20)
		,@BODEGAACTUAL BIT		,@SELECCIONADO BIT	,@IDARTICULO VARCHAR(20)	,@BODEGASELECCIONADA VARCHAR(20)
		,@COMPANIA VARCHAR(10)	,@SYSCOMPUTERNAME VARCHAR(50)	, @CNSRPDX VARCHAR(20)	, @LONGITUD INT	, @PREFIJO VARCHAR(20)
		,@IDSEDE VARCHAR(20)	,@FDESDE DATE	,@FHASTA DATE
		,@VENCIDOS VARCHAR(20)	,@VIGENTES VARCHAR(20)	,@PORVENCER VARCHAR(20)
		,@NARANJA    VARCHAR(20) ,@TABLA      VARCHAR(20) = '';
BEGIN   
   SET DATEFORMAT dmy
   --SELECT @JSON
   SELECT *
   INTO #JSON
   FROM OPENJSON (@json)
   WITH (
      MODELO  VARCHAR(100) '$.MODELO',
      METODO  VARCHAR(100) '$.METODO',
      USUARIO VARCHAR(20) '$.USUARIO',
      PARAMETROS NVARCHAR(MAX) AS JSON
   )
   SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
   FROM #JSON
   --DEFINICION DE TABLA DE ERRORES
   DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200));
   	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SEDE = IDSEDE, @COMPANIA = COMPANIA FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
	SELECT @SYSCOMPUTERNAME = LEFT(LTRIM(RTRIM(@SYS_COMPUTERNAME)), 50)

   --  
	IF @METODO = 'GEN_MOVIMIENTO'
	BEGIN
		SELECT @IDBODEGA = IDBODEGA, @NOLOTE = NOLOTE, @PROCESO = PROCESO ,@IDARTICULO = IDARTICULO
		FROM OPENJSON (@PARAMETROS)
		WITH ( 
				IDARTICULO						VARCHAR(20)		'$.IDARTICULO'
				,IDBODEGA					VARCHAR(20)		'$.IDBODEGA'
				,NOLOTE						VARCHAR(20)		'$.NOLOTE'
				,PROCESO					VARCHAR(20)		'$.PROCESO'
		)
		IF (SELECT COUNT(*) FROM ITMO WHERE IDTIPOMOV = DBO.FNK_VALORVARIABLE('IDINVSALVENCIDOS') ) = 0
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'No Existe Configuraci�n Para Realizar Este movimiento.'
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN 
		END
		IF ( SELECT COUNT(*) FROM IBODS WHERE TIPO='ITMO' AND VALOR=  DBO.FNK_VALORVARIABLE('IDINVSALVENCIDOS')  AND IDBODEGA= @IDBODEGA ) = 0
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'Esta Bodega No Tiene Permisos  Para Realizar Este movimiento.'
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN 
		END
		BEGIN TRY
			IF UPPER(@PROCESO) = 'UNO'
			BEGIN
				EXEC DBO.SPK_MOVSALIDAVENCIDOS  @COMPANIA, @SEDE, @USUARIO, @IDBODEGA, @SYSCOMPUTERNAME, @IDARTICULO
			END
			ELSE IF UPPER(@PROCESO) = 'TODOS'
			BEGIN
				EXEC DBO.SPK_MOVSALIDAVENCIDOS  @COMPANIA, @SEDE, @USUARIO, @IDBODEGA, @SYSCOMPUTERNAME, null
			END
			ELSE
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) SELECT 'Proceso no v�lido para generar movimiento de vencidos.';
			END

		END TRY
		BEGIN CATCH
			-- SPK_MOVSALIDAVENCIDOS hace ROLLBACK interno; aqu� solo reportamos el error al front
            INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE();
         END CATCH
         IF(SELECT COUNT(*) FROM @TBLERRORES)>0
         BEGIN
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
         END
         SELECT 'OK' OK
	END
	IF @METODO = 'SEMAFORO_STOCK'
	BEGIN
		SELECT @IDBODEGA = IDBODEGA
		FROM OPENJSON (@PARAMETROS)
		WITH ( 
				IDBODEGA		VARCHAR(20)		'$.IDBODEGA'
		)
	
		BEGIN TRY
			SELECT 'OK' OK
			DELETE FROM RPDX WHERE STRINGMAX = 'TEMPORAL_SEMAFORO'
			SELECT @CNSRPDX = NULL
			EXEC SPQ_GENSEQUENCE @SEDE,@PREFIJO='@RPDX', @LONGITUD = 8, @NVOCONSEC=@CNSRPDX OUTPUT  
			SELECT @CNSRPDX CNSRPDX
			INSERT INTO RPDX(CNS, ID1, STRINGMEDIO1, CANTIDAD1, CANTIDAD2, CANTIDAD3, CANTIDAD4,CANTIDAD5, CANTIDAD6, CANTIDAD7, ID2, ID3, STRINGMEDIO2,CANTIDAD, STRINGMAX)
			SELECT @CNSRPDX, IDARTICULO,ARTICULO,EXISTBODEGA,STOCKMINIMO,STOCKMAXIMO,PUNTOREORDEN 
				,CASE WHEN (PUNTOREORDEN >= EXISTBODEGA) THEN 0 ELSE 1 END REORDEN
				,CASE WHEN (EXISTBODEGA <= STOCKMINIMO) THEN 1
				   WHEN (EXISTBODEGA <  PUNTOREORDEN ) THEN 2
				   ELSE 0
			  END STOCKMINIMO
			  ,CASE WHEN (EXISTBODEGA >= STOCKMAXIMO ) THEN 1 ELSE 0 END STOCKMAXIMO
			  ,ESTADO
			  ,IDITAR
			  ,TIPOARTICULO
			  ,1  [SELF_BODEGA], 'TEMPORAL_SEMAFORO'
			FROM (
			SELECT VK.HERMANO_MAYOR IDARTICULO,IART.DESCRIPCION ARTICULO
				--,IDBODEGA
				,CAST((SELECT SUM(IEXI.EXISLOTE) FROM IEXI WITH(NOLOCK) WHERE IDBODEGA=IDBODEGA AND IDARTICULO IN (SELECT IDARTICULO FROM VWK_HERMANOS_INVENTARIO  WITH(NOLOCK) WHERE HERMANO_MAYOR=VK.HERMANO_MAYOR)) AS int) EXISTBODEGA
				,CAST(ISNULL(IDXB.STOCKMINIMO,0) AS int)	STOCKMINIMO
				,CAST(ISNULL(IDXB.PUNTOREORDEN,0) AS int)	PUNTOREORDEN
				,CAST(ISNULL(IDXB.STOCKMAXIMO,0) AS int)	STOCKMAXIMO
				,IART.ESTADO
				,IART.IDITAR,ITAR.DESCRIPCION TIPOARTICULO
			FROM VWK_HERMANOS_INVENTARIO VK
			INNER JOIN IART ON IART.IDARTICULO=VK.IDARTICULO
			INNER JOIN ITAR ON ITAR.IDITAR = IART.IDITAR
			LEFT JOIN IDXB ON IDXB.IDARTICULO=IART.IDARTICULO
			WHERE ISNULL(IDXB.IDBODEGA,'')<>'' AND IDXB.STOCKMINIMO>0
			AND IDXB.IDBODEGA = @IDBODEGA
			GROUP BY VK.HERMANO_MAYOR,IART.DESCRIPCION,IDBODEGA,IDXB.STOCKMINIMO,IDXB.PUNTOREORDEN,IDXB.STOCKMAXIMO,IART.ESTADO,IART.IDITAR,ITAR.DESCRIPCION
		 ) AS #T
		 UNION
		  SELECT @CNSRPDX, IART.IDARTICULO,LEFT ( IART.DESCRIPCION,100)DESCRIPCION, X.EXISTENCIAS, IART.STOCKMINIMO, IART.STOCKMAXIMO, IART.PUNTOREORDEN, 
				  CASE WHEN (IART.PUNTOREORDEN >= X.EXISTENCIAS) THEN 0 ELSE 1 END REORDEN, 
				  CASE WHEN (X.EXISTENCIAS <= IART.STOCKMINIMO) THEN 1
					   WHEN (X.EXISTENCIAS <  IART.PUNTOREORDEN ) THEN 2
					   ELSE 0
				  END STOCKMINIMO,
				  CASE WHEN (X.EXISTENCIAS >= IART.STOCKMAXIMO ) THEN 1 ELSE 0 END STOCKMAXIMO, IART.ESTADO,
				  IART.IDITAR,LEFT ( ITAR.DESCRIPCION,100) DESCRIPCION
				  ,0 [SELF_BODEGA], 'TEMPORAL_SEMAFORO'
		   FROM   IART INNER JOIN ( SELECT IEXI.IDARTICULO, SUM(IEXI.EXISLOTE) EXISTENCIAS
									FROM   IEXI WHERE @IDBODEGA IS NULL OR @IDBODEGA=IDBODEGA
									GROUP BY IEXI.IDARTICULO
								  ) X ON IART.IDARTICULO = X.IDARTICULO
					   INNER JOIN ITAR ON IART.IDITAR = ITAR.IDITAR
		   AND    COALESCE(ITAR.MSTOCK,0) = 1

		END TRY
		BEGIN CATCH
            INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE();
         END CATCH
         IF(SELECT COUNT(*) FROM @TBLERRORES)>0
         BEGIN
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
         END
         SELECT 'OK' OK
	END

	IF @METODO = 'EXPORTAR_SEMAFORO'
	BEGIN
		SELECT 'OK' AS OK;

		SELECT
			@IDBODEGA  = NULLIF(BODEGA, ''),
			@FDESDE    = FDESDE,
			@FHASTA    = FHASTA,
			@VENCIDOS  = NULLIF(VENCIDOS, ''),
			@NARANJA   = NULLIF(NARANJA, ''),
			@PORVENCER = NULLIF(PORVENCER, ''),
			@VIGENTES  = NULLIF(VIGENTES, ''),
			@TABLA     = COALESCE(NULLIF(TABLA_SEMAFORO, ''), '')
		FROM OPENJSON(@PARAMETROS)
		WITH (
			BODEGA         VARCHAR(20) '$.BODEGA',
			FDESDE         DATE        '$.FDESDE',
			FHASTA         DATE        '$.FHASTA',
			VENCIDOS       VARCHAR(20) '$.VENCIDOS',
			NARANJA        VARCHAR(20) '$.NARANJA',
			PORVENCER      VARCHAR(20) '$.PORVENCER',
			VIGENTES       VARCHAR(20) '$.VIGENTES',
			TABLA_SEMAFORO VARCHAR(20) '$.TABLA_SEMAFORO'
		);

		SELECT
			IEXI.IDARTICULO,
			IART.DESCRIPCION AS ARTICULO,
			IEXI.NOLOTE,
			IEXI.NOLOTEPEDIDO,
			IEXI.RINVIMA,
			IEXI.EXISLOTE,
			IEXI.FECHAVENCE,
			S.SEMAFORO AS ESTADO_2,
			IEXI.IDBODEGA,
			IBOD.DESCRIPCION AS DESC_BODEGA
		FROM IEXI
		INNER JOIN IART ON IEXI.IDARTICULO = IART.IDARTICULO
		LEFT JOIN IBOD ON IBOD.IDBODEGA = IEXI.IDBODEGA
		OUTER APPLY (
			SELECT TOP 1 F.SEMAFORO
			FROM DBO.FNK_SEMAFORO_TRANSITO_TABLE(IEXI.FECHAVENCE, @TABLA) F
			WHERE F.ORDEN IS NULL
		) S
		WHERE (@IDBODEGA IS NULL OR IEXI.IDBODEGA = @IDBODEGA)
		  AND IEXI.EXISLOTE > 0
		  AND (@FDESDE IS NULL OR CONVERT(DATE, IEXI.FECHAVENCE) >= @FDESDE)
		  AND (@FHASTA IS NULL OR CONVERT(DATE, IEXI.FECHAVENCE) <= @FHASTA)
		  AND (
				(@VENCIDOS IS NULL AND @NARANJA IS NULL AND @PORVENCER IS NULL AND @VIGENTES IS NULL)
				OR S.SEMAFORO IN (@VENCIDOS, @NARANJA, @PORVENCER, @VIGENTES)
			  )
		ORDER BY IART.IDARTICULO ASC;
	END;

	IF @METODO = 'CONFIG_SEMAFORO_LEER'
	BEGIN
		SELECT @TABLA = COALESCE(NULLIF(LTRIM(RTRIM(TABLA_SEMAFORO)), ''), '')
		FROM OPENJSON(@PARAMETROS)
		WITH (TABLA_SEMAFORO VARCHAR(20) '$.TABLA_SEMAFORO');

		SELECT 'OK' AS OK;

		SELECT
			S.SEMAFORO,
			S.ETIQUETA,
			S.LEYENDA_DIAS,
			S.ORDEN
		FROM DBO.FNK_SEMAFORO_TRANSITO_TABLE(NULL, @TABLA) S
		WHERE S.ORDEN IS NOT NULL
		ORDER BY S.ORDEN;

		DECLARE @TABLA_TGEN_LEER VARCHAR(20) = CASE WHEN @TABLA = '' THEN 'SEMAFORO' ELSE 'SEMAFORO_' + @TABLA END;

		IF NOT EXISTS (
			SELECT 1
			FROM TGEN
			WHERE TABLA = @TABLA_TGEN_LEER
			  AND CAMPO IN ('ROJO','NARANJA','AMARILLO','VERDE')
			  AND VALOR1 IS NOT NULL
		)
			SET @TABLA_TGEN_LEER = 'SEMAFORO';

		SELECT
			T.IDTGEN,
			T.TABLA,
			T.CAMPO,
			T.CODIGO,
			T.DESCRIPCION,
			T.VALOR1
		FROM TGEN T
		WHERE T.TABLA = @TABLA_TGEN_LEER
		  AND (
				(T.CODIGO = 'N<' AND T.CAMPO IN ('ROJO','NARANJA','AMARILLO'))
			 OR (T.CODIGO = 'N>' AND T.CAMPO = 'VERDE')
		  )
		ORDER BY T.VALOR1 ASC, CASE WHEN T.CAMPO = 'VERDE' THEN 1 ELSE 0 END, T.CAMPO;
	END;

	IF @METODO = 'CONFIG_SEMAFORO_GUARDAR'
	BEGIN
		DECLARE @REGISTROS NVARCHAR(MAX);
		DECLARE @TABLA_TGEN_GUARDAR VARCHAR(20);

		SELECT
			@TABLA     = COALESCE(NULLIF(LTRIM(RTRIM(TABLA_SEMAFORO)), ''), ''),
			@REGISTROS = REGISTROS
		FROM OPENJSON(@PARAMETROS)
		WITH (
			TABLA_SEMAFORO VARCHAR(20) '$.TABLA_SEMAFORO',
			REGISTROS      NVARCHAR(MAX) AS JSON
		);

		SET @TABLA_TGEN_GUARDAR = CASE WHEN @TABLA = '' THEN 'SEMAFORO' ELSE 'SEMAFORO_' + @TABLA END;

		DECLARE @CFG_SAVE TABLE (
			IDTGEN      INT,
			CAMPO       VARCHAR(20),
			DESCRIPCION NVARCHAR(100),
			VALOR1      INT
		);

		INSERT INTO @CFG_SAVE (IDTGEN, CAMPO, DESCRIPCION, VALOR1)
		SELECT IDTGEN, CAMPO, DESCRIPCION, VALOR1
		FROM OPENJSON(@REGISTROS)
		WITH (
			IDTGEN      INT            '$.IDTGEN',
			CAMPO       VARCHAR(20)    '$.CAMPO',
			DESCRIPCION NVARCHAR(100)  '$.DESCRIPCION',
			VALOR1      INT            '$.VALOR1'
		);

		DECLARE @V_ROJO INT, @V_NARANJA INT, @V_AMARILLO INT;

		SELECT @V_ROJO     = COALESCE(MAX(CASE WHEN CAMPO = 'ROJO'     THEN VALOR1 END), 0)     FROM @CFG_SAVE;
		SELECT @V_NARANJA  = COALESCE(MAX(CASE WHEN CAMPO = 'NARANJA'  THEN VALOR1 END), 90)  FROM @CFG_SAVE;
		SELECT @V_AMARILLO = COALESCE(MAX(CASE WHEN CAMPO = 'AMARILLO' THEN VALOR1 END), 180) FROM @CFG_SAVE;

		IF @V_ROJO IS NULL OR @V_NARANJA IS NULL OR @V_AMARILLO IS NULL
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'Debe configurar los rangos ROJO, NARANJA y AMARILLO.';
		END
		ELSE IF NOT (@V_ROJO < @V_NARANJA AND @V_NARANJA < @V_AMARILLO)
		BEGIN
			INSERT INTO @TBLERRORES(ERROR)
			SELECT 'Los d�as l�mite deben ser crecientes: Vencidos < Vence pronto < Por vencer.';
		END

		IF NOT EXISTS(SELECT 1 FROM @TBLERRORES)
		BEGIN
			BEGIN TRY
				DECLARE @C VARCHAR(20), @D NVARCHAR(100), @V INT, @ID INT, @COD VARCHAR(10);

				DECLARE cur_cfg CURSOR LOCAL FAST_FORWARD FOR
					SELECT CAMPO, DESCRIPCION, VALOR1, IDTGEN FROM @CFG_SAVE;

				OPEN cur_cfg;
				FETCH NEXT FROM cur_cfg INTO @C, @D, @V, @ID;

				WHILE @@FETCH_STATUS = 0
				BEGIN
					SET @COD = CASE WHEN @C = 'VERDE' THEN 'N>' ELSE 'N<' END;

					IF @C = 'VERDE'
						SET @V = @V_AMARILLO;

					IF @ID IS NOT NULL AND EXISTS (SELECT 1 FROM TGEN WHERE IDTGEN = @ID)
					BEGIN
						UPDATE TGEN
						SET DESCRIPCION = @D,
							VALOR1      = @V
						WHERE IDTGEN = @ID;
					END
					ELSE IF EXISTS (
						SELECT 1
						FROM TGEN
						WHERE TABLA = @TABLA_TGEN_GUARDAR
						  AND CAMPO = @C
						  AND CODIGO = @COD
					)
					BEGIN
						UPDATE TGEN
						SET DESCRIPCION = @D,
							VALOR1      = @V
						WHERE TABLA = @TABLA_TGEN_GUARDAR
						  AND CAMPO = @C
						  AND CODIGO = @COD;
					END
					ELSE
					BEGIN
						INSERT INTO TGEN (TABLA, CAMPO, CODIGO, DESCRIPCION, VALOR1)
						VALUES (@TABLA_TGEN_GUARDAR, @C, @COD, @D, @V);
					END

					FETCH NEXT FROM cur_cfg INTO @C, @D, @V, @ID;
				END

				CLOSE cur_cfg;
				DEALLOCATE cur_cfg;
			END TRY
			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE();
			END CATCH
		END

		IF EXISTS(SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' AS OK;
			SELECT ERROR FROM @TBLERRORES;
			RETURN;
		END

		SELECT 'OK' AS OK;
	END;
END
