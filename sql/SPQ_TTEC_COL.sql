CREATE OR ALTER PROCEDURE DBO.SPQ_TTEC_COL
@JSON  NVARCHAR(MAX)
WITH
ENCRYPTION
AS
DECLARE @PARAMETROS         NVARCHAR(MAX)  ,@MODELO           VARCHAR(100)    ,@METODO        VARCHAR(100)  ,@USUARIO        VARCHAR(12)
       ,@GRUPO              VARCHAR(8)     ,@SYS_COMPUTERNAME VARCHAR(254)    ,@SEDE          VARCHAR(5)	   ,@A              INT
       ,@IDENTITY           INT 
       ,@PROCESO            VARCHAR(20)    ,@TTEC    NVARCHAR(MAX)
              ,@TIPO     VARCHAR(10)
       ,@DETALLE     VARCHAR(60)
       ,@CUENTA     VARCHAR(16)
       ,@TIPOMOV     VARCHAR(2)
       ,@CUEORDENGLOSADB     VARCHAR(16)
       ,@CUEORDENGLOSACR     VARCHAR(16)
       ,@CTAGLOSADB     VARCHAR(16)
       ,@CUENTARAD     VARCHAR(16)
       ,@CUENTALG     VARCHAR(20)
       ,@CUENTACG     VARCHAR(20)
       ,@CXC_ESTIMADA     VARCHAR(16)
       ,@PASIVO_EST     VARCHAR(16)
       ,@CREEDB     VARCHAR(20)
       ,@CREECR     VARCHAR(20)
       ,@INGRESOEST     VARCHAR(20)
       ,@CUEDIFCOB     VARCHAR(20)
       ,@CUECOJURI     VARCHAR(20)
       ,@TASEGU     VARCHAR(2)
BEGIN
   SET LANGUAGE Spanish
   SET DATEFORMAT dmy
   
   SELECT @A = ISJSON(@JSON)
   IF @A = 0
   BEGIN
     RAISERROR('Json: Formato Erroneo',16,1)
     RETURN
   END
   PRINT 'INGRESE A SPQ_TTEC_COL'
   SELECT *
   INTO #JSON
   FROM OPENJSON (@json)
   WITH (
     MODELO         VARCHAR(100)     '$.MODELO',
     METODO         VARCHAR(100)     '$.METODO',
     USUARIO        VARCHAR(12)      '$.USUARIO',
     PARAMETROS     NVARCHAR(MAX)     AS JSON
   )
   
   SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS , @USUARIO = USUARIO
   FROM #JSON
   --DEFINICION DE TABLA DE ERRORES
   DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200))
   -- TOMA DEL GRUPO, SYS_COMPUTERNAME, SEDE   DE ACUERDO AL USUARIO
   PRINT 'USUARIO:'+@USUARIO
   --SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO) FROM USUSU WHERE USUARIO = @USUARIO
   --SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
   --SELECT @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
   IF COALESCE(@SEDE,'') = '' SELECT @SEDE = '01'
   PRINT 'SEDE='+@SEDE
   IF @METODO = 'CRUDTTEC'
   BEGIN
      PRINT 'CRUDTTEC'
      SELECT @TTEC  = REGISTRO
      FROM OPENJSON (@PARAMETROS)
      WITH(
         REGISTRO   NVARCHAR(MAX)     AS JSON
      )
      
      SELECT @PROCESO     = JSON_VALUE(@TTEC ,'$.PROCESO')
      --Leo Campos enviados y los coloco en las variables respectivas
      SELECT @TIPO = JSON_VALUE(@TTEC , '$.TIPO' )
      SELECT @DETALLE = JSON_VALUE(@TTEC , '$.DETALLE' )
      SELECT @CUENTA = JSON_VALUE(@TTEC , '$.CUENTA' )
      SELECT @TIPOMOV = JSON_VALUE(@TTEC , '$.TIPOMOV' )
      SELECT @CUEORDENGLOSADB = JSON_VALUE(@TTEC , '$.CUEORDENGLOSADB' )
      SELECT @CUEORDENGLOSACR = JSON_VALUE(@TTEC , '$.CUEORDENGLOSACR' )
      SELECT @CTAGLOSADB = JSON_VALUE(@TTEC , '$.CTAGLOSADB' )
      SELECT @CUENTARAD = JSON_VALUE(@TTEC , '$.CUENTARAD' )
      SELECT @CUENTALG = JSON_VALUE(@TTEC , '$.CUENTALG' )
      SELECT @CUENTACG = JSON_VALUE(@TTEC , '$.CUENTACG' )
      SELECT @CXC_ESTIMADA = JSON_VALUE(@TTEC , '$.CXC_ESTIMADA' )
      SELECT @PASIVO_EST = JSON_VALUE(@TTEC , '$.PASIVO_EST' )
      SELECT @CREEDB = JSON_VALUE(@TTEC , '$.CREEDB' )
      SELECT @CREECR = JSON_VALUE(@TTEC , '$.CREECR' )
      SELECT @INGRESOEST = JSON_VALUE(@TTEC , '$.INGRESOEST' )
      SELECT @CUEDIFCOB = JSON_VALUE(@TTEC , '$.CUEDIFCOB' )
      SELECT @CUECOJURI = JSON_VALUE(@TTEC , '$.CUECOJURI' )
      SELECT @TASEGU = JSON_VALUE(@TTEC , '$.TASEGU.value' )
      IF UPPER(@PROCESO) = 'INSERTAR'
      BEGIN
         PRINT 'INSERTAR'
         BEGIN TRY
            INSERT INTO TTEC(TIPO,DETALLE,CUENTA,TIPOMOV,CUEORDENGLOSADB,CUEORDENGLOSACR,CTAGLOSADB,
                             CUENTARAD,CUENTALG,CUENTACG,CXC_ESTIMADA,PASIVO_EST,CREEDB,CREECR,
                             INGRESOEST,CUEDIFCOB,CUECOJURI,TASEGU)
            SELECT @TIPO,@DETALLE,@CUENTA,@TIPOMOV,@CUEORDENGLOSADB,@CUEORDENGLOSACR,@CTAGLOSADB,
                             @CUENTARAD,@CUENTALG,@CUENTACG,@CXC_ESTIMADA,@PASIVO_EST,@CREEDB,@CREECR,
                             @INGRESOEST,@CUEDIFCOB,@CUECOJURI,@TASEGU
            SELECT @IDENTITY = SCOPE_IDENTITY()
         END TRY
         BEGIN CATCH
            INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
         END CATCH
         IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
         BEGIN
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
         END
         SELECT 'OK' OK ,@IDENTITY CNS 
         RETURN
      END
      IF UPPER(@PROCESO) = 'EDITAR'
      BEGIN
         BEGIN TRY
            UPDATE TTEC SET
                    TIPO = @TIPO,DETALLE = @DETALLE,CUENTA = @CUENTA,TIPOMOV = @TIPOMOV,CUEORDENGLOSADB = @CUEORDENGLOSADB,CUEORDENGLOSACR = @CUEORDENGLOSACR,CTAGLOSADB = @CTAGLOSADB,
                             CUENTARAD = @CUENTARAD,CUENTALG = @CUENTALG,CUENTACG = @CUENTACG,CXC_ESTIMADA = @CXC_ESTIMADA,PASIVO_EST = @PASIVO_EST,CREEDB = @CREEDB,CREECR = @CREECR,
                             INGRESOEST = @INGRESOEST,CUEDIFCOB = @CUEDIFCOB,CUECOJURI = @CUECOJURI,TASEGU = @TASEGU
            WHERE TIPO = @TIPO
         END TRY
         BEGIN CATCH
            INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
         END CATCH
         IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
         BEGIN
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
         END
         SELECT 'OK' OK
         RETURN
      END
      RETURN
   END
END
