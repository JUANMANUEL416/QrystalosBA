CREATE OR ALTER PROCEDURE DBO.SPQ_MOBI
@JSON NVARCHAR(MAX)
WITH ENCRYPTION
AS
DECLARE   @PARAMETROS       NVARCHAR(MAX)		,@MODELO         VARCHAR(100)	,@METODO      VARCHAR(100)
        ,@QUERY				VARCHAR(MAX)		,@USUARIO        VARCHAR(12)		,@NVOCONSEC   VARCHAR(20)
        ,@SEDE				VARCHAR(5)			,@NOADMISION     VARCHAR(16)		,@FECHA       VARCHAR(20)         
        ,@HORA				VARCHAR(10)			,@ITEM           SMALLINT		,@OBS         VARCHAR(2048)
        ,@SYS_COMPUTERNAME	VARCHAR(254)		,@GRUPO          VARCHAR(8)		,@PENDIENTES  SMALLINT
		,@ESTADO			VARCHAR(20)			,@FECHA_TIME DATETIME		, @NODOCUMENTO VARCHAR(50)
		,@IDARTICULO_IMOVH VARCHAR(20)			,@datoIACTMOV	NVARCHAR(MAX)	,@IDENTITY INT
		,@datoNOTA			NVARCHAR(MAX)		,@IDSEDE		VARCHAR(20)		,@COMPANIA VARCHAR(20)
		,@IDBODEGA			VARCHAR(20)			,@PROCESO		VARCHAR(20)
BEGIN   
   SET DATEFORMAT dmy
   --SELECT @JSON
   SELECT *
   INTO #JSON
   FROM OPENJSON (@json)
   WITH (
      MODELO  VARCHAR(100) '$.MODELO',
      METODO  VARCHAR(100) '$.METODO',
      USUARIO VARCHAR(20) '$.USUARIO',
      PARAMETROS NVARCHAR(MAX) AS JSON
   )
   SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
   FROM #JSON
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @IDSEDE = IDSEDE, @SEDE = IDSEDE, @COMPANIA=COMPANIA, @IDBODEGA = COALESCE(IDBODEGA, IDBODEGA2, IDBODEGANOCHE, IDBODEGACONSUMO) FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
	SELECT @GRUPO = (SELECT DBO.FNK_DESCIFRAR(USUSU.GRUPO) FROM USUSU WHERE  USUARIO = @USUARIO)

   --DEFINICION DE TABLA DE ERRORES
   DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200));
   --  

	IF @METODO = 'CRUD_IACTMOV'
	BEGIN
		SELECT @datoIACTMOV =  datoIACTMOV
	   FROM OPENJSON (@PARAMETROS)
	   WITH		 (
		datoIACTMOV		NVARCHAR(MAX) AS JSON
		)
		
		SELECT @PROCESO =UPPER( JSON_VALUE(@datoIACTMOV,'$.PROCESO'))
		SELECT * INTO #datoIACTMOV FROM OPENJSON (@datoIACTMOV)
		WITH(
		IDIACTMOV					INT								'$.IDIACTMOV'
		,PROCESO					VARCHAR(20)						'$.PROCESO'
		,IDACTIVO					VARCHAR(20)						'$.IDACTIVO'
		,CONSECUTIVO				VARCHAR(20)						'$.CONSECUTIVO'
		,USUARIOREC					VARCHAR(20)						'$.USUARIOREC'
		,IACTMOV_ESTADO				VARCHAR(20)						'$.IACTMOV_ESTADO'
		,OBSERVACION				VARCHAR(500)					'$.OBSERVACION'
		,IDSERVICIO					VARCHAR(500)					'$.IDSERVICIO'
		)
			
		BEGIN TRY 
			IF UPPER(@PROCESO)='EDITAR'
			BEGIN
				UPDATE IACTMOV SET
				IDACTIVO			= #datoIACTMOV.IDACTIVO		
				,CONSECUTIVO		= #datoIACTMOV.CONSECUTIVO
				,USUARIOREC			= #datoIACTMOV.USUARIOREC
				,ESTADO				= #datoIACTMOV.IACTMOV_ESTADO		
				,OBSERVACION		= #datoIACTMOV.OBSERVACION
				FROM IACTMOV , #datoIACTMOV WHERE IACTMOV.IDIACTMOV = #datoIACTMOV.IDIACTMOV
				
				IF (SELECT IACTMOV_ESTADO FROM #datoIACTMOV ) = 'Mobiliario Devuelto'
				BEGIN
					UPDATE IACT SET ESTADO = NULL WHERE IDACTIVO = (SELECT  #datoIACTMOV.IDACTIVO FROM #datoIACTMOV )
				END

			END
			IF UPPER(@PROCESO)='NUEVO'
			BEGIN
				INSERT INTO IACTMOV (
				IDACTIVO			
				,CONSECUTIVO
				,USUARIOREC
				,ESTADO		
				,OBSERVACION
				,F_POSIBLE
				,FECHA
				,USUARIO
				)
				SELECT
				   #datoIACTMOV.IDACTIVO			
				  ,#datoIACTMOV.CONSECUTIVO
				  ,#datoIACTMOV.USUARIOREC
				  ,#datoIACTMOV.IACTMOV_ESTADO		
				  ,#datoIACTMOV.OBSERVACION	
				   ,REPLACE(JSON_VALUE(@datoIACTMOV ,'$.F_POSIBLE'),'-','')
				  ,DBO.FNK_GETDATE()
				  ,@USUARIO
				FROM #datoIACTMOV
				SELECT @IDENTITY = SCOPE_IDENTITY()
				--SELECT @IDARTICULO = IDARTICULO FROM IACT, #datoIACTMOV WHERE IACT.IDACTIVO = #datoIACTMOV.IDACTIVO
				UPDATE HCATD SET HCATD.MOB_ESTADO = 1 , HCATD.IDIACTMOV = @IDENTITY FROM HCATD, #datoIACTMOV WHERE HCATD.CONSECUTIVO = #datoIACTMOV.CONSECUTIVO AND HCATD.IDSERVICIO = #datoIACTMOV.IDSERVICIO
				UPDATE IACTMOV SET IACTMOV.IDAFILIADO = HCA.IDAFILIADO FROM IACTMOV,HCA WHERE IACTMOV.IDIACTMOV = @IDENTITY AND HCA.CONSECUTIVO = IACTMOV.CONSECUTIVO
				UPDATE IACT SET ESTADO = 'En Uso' FROM IACT,#datoIACTMOV WHERE  IACT.IDACTIVO = #datoIACTMOV.IDACTIVO
			END
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF EXISTS(SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' AS OK
		RETURN
	END
	IF @METODO = 'CRUD_NOTA'
	BEGIN
		SELECT @datoNOTA =  datoNOTA
	   FROM OPENJSON (@PARAMETROS)
	   WITH		 (
		datoNOTA		NVARCHAR(MAX) AS JSON
		)
		
		SELECT @PROCESO =UPPER( JSON_VALUE(@datoNOTA,'$.PROCESO'))
		SELECT * INTO #datoNOTA FROM OPENJSON (@datoNOTA)
		WITH(
		ITEM						INT								'$.ITEM'
		,IDIACTMOV					INT								'$.IDIACTMOV'
		,PROCESO					VARCHAR(20)						'$.PROCESO'
		,DESCRIPCION				VARCHAR(500)					'$.DESCRIPCION'
		)
			
		BEGIN TRY 
			IF UPPER(@PROCESO)='EDITAR'
			BEGIN
				UPDATE IACTMOVD SET
					DESCRIPCION			= #datoNOTA.DESCRIPCION		
				FROM IACTMOVD , #datoNOTA WHERE IACTMOVD.ITEM = #datoNOTA.ITEM
			END
			IF UPPER(@PROCESO)='NUEVO'
			BEGIN
				INSERT INTO IACTMOVD (
				IDIACTMOV			
				,FECHA
				,DESCRIPCION
				,USUARIO
				)
				SELECT
				   #datoNOTA.IDIACTMOV			
				  ,DBO.FNK_GETDATE()
				  ,#datoNOTA.DESCRIPCION
				  ,@USUARIO	
				FROM #datoNOTA
			END
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF EXISTS(SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' AS OK
		RETURN
	END
	IF @METODO = 'CONSULTA_PENDIENTE'
	BEGIN
		BEGIN TRY
			SELECT 'OK' AS OK
			
			SELECT HCATD.CONSECUTIVO, HCA.NOADMISION, HCA.IDAFILIADO,HCATD.CODOM, HCA.FECHA, HCATD.CODOM, HCATD.IDSERVICIO, SER.DESCSERVICIO, HCATD.CANTIDAD, HCA.IDMEDICO, HCA.IDEMEDICA  
			, AFI.IDAFILIADO, AFI.TIPO_DOC, AFI.DOCIDAFILIADO, AFI.CELULAR, AFI.TELEFONORES, AFI.NOMBREAFI
			FROM HCATD 
			INNER JOIN HCA ON HCATD.CONSECUTIVO = HCA.CONSECUTIVO
			INNER JOIN AFI ON HCA.IDAFILIADO = AFI.IDAFILIADO
			INNER JOIN SER ON HCATD.IDSERVICIO = SER.IDSERVICIO
			INNER JOIN MED ON HCA.IDMEDICO = MED.IDMEDICO
			LEFT JOIN MES ON HCA.IDEMEDICA = MES.IDEMEDICA
			WHERE HCATD.CODOM = DBO.FNK_VALORVARIABLE('PRE_MOBILIARIO')
			AND COALESCE(HCATD.MOB_ESTADO,0) = 0 AND COALESCE(HCATD.IDIACTMOV,'') = '' --AND 1 = 2

		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF EXISTS(SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' AS OK
		RETURN
	END
END
