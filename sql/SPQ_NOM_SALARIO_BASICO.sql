CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_SALARIO_BASICO
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @DATO				NVARCHAR(MAX)
DECLARE  @PARAMETROS		NVARCHAR(MAX),	@MODELO			VARCHAR(100),   @METODO		VARCHAR(100),	@USUARIO	VARCHAR(20)
DECLARE	 @PROCESO			VARCHAR(20)
DECLARE	 @CODCONCEPTO		VARCHAR(20),	@ITEM				DECIMAL(14,0)
DECLARE	 @PRIORIDAD			SMALLINT,		@DIAS1				DECIMAL(14,6)
DECLARE	 @DIAS2				DECIMAL(14,6),	@CONDICION			VARCHAR(2)
DECLARE	 @PRIORIDADEDITE	SMALLINT

DECLARE  @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

	IF @METODO = 'GUARDAR'
		BEGIN
			BEGIN TRY
				SELECT  @CODCONCEPTO = CODCONCEPTO, @ITEM = ITEM,
						@PRIORIDAD = PRIORIDAD, @DIAS1 = DIAS1,
						@DIAS2 = DIAS2, @CONDICION = CONDICION,
						@PROCESO = PROCESO
				FROM	OPENJSON (@PARAMETROS) 
				WITH	(
					CODCONCEPTO		VARCHAR(20)			'$.CODCONCEPTO',
					ITEM			DECIMAL(14,0)		'$.ITEM',
					PRIORIDAD		SMALLINT			'$.PRIORIDAD',
					DIAS1			DECIMAL(14,6)		'$.DIAS1',
					DIAS2			DECIMAL(14,6)		'$.DIAS2',
					CONDICION		VARCHAR(2)			'$.CONDICION',
					PROCESO			VARCHAR(20)			'$.PROCESO'
				)
				IF UPPER(@PROCESO) = 'INSERTAR'
				BEGIN
					BEGIN TRY
							INSERT INTO @TBLERRORES(ERROR) 
								SELECT CONCAT('LA PRIORIDAD ',@PRIORIDAD, ' YA SE ENCUENTRA REGISTRADO, INGRESE UNA MAYOR O MENOR')
								WHERE EXISTS (SELECT 1 FROM NCONDB WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM AND PRIORIDAD = @PRIORIDAD)
								IF(SELECT COUNT(*) FROM @TBLERRORES) <= 0
							BEGIN
								INSERT INTO NCONDB (CODCONCEPTO ,ITEM ,PRIORIDAD ,DIAS1 ,DIAS2 ,CONDICION ) 
								SELECT @CODCONCEPTO, @ITEM, @PRIORIDAD, @DIAS1, @DIAS2, @CONDICION
							END
					END TRY
					BEGIN CATCH
						INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
					END CATCH

					IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
					BEGIN
						SELECT 'KO' OK
						SELECT ERROR FROM @TBLERRORES
						RETURN
					END

					SELECT 'OK' OK 
					RETURN
				END

				IF UPPER(@PROCESO) = 'EDITAR'
					BEGIN
						BEGIN TRY
						SELECT @DATO = DATO       
							  FROM   OPENJSON (@PARAMETROS)
							  WITH (DATO NVARCHAR(MAX) AS JSON)   
							  
							  SELECT @PRIORIDADEDITE = PRIORIDADEDITE
							  FROM   OPENJSON (@DATO)
							  WITH   (   
							  PRIORIDADEDITE		SMALLINT		 '$.PRIORIDADEDITE'
							  )

								BEGIN
									UPDATE NCONDB SET PRIORIDAD = @PRIORIDAD,DIAS1 = @DIAS1,DIAS2 = @DIAS2,CONDICION=@CONDICION
									WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM AND PRIORIDAD = @PRIORIDADEDITE
								END
						END TRY

						BEGIN CATCH
							INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
						END CATCH

						IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
						BEGIN
							SELECT 'KO' OK
							SELECT ERROR FROM @TBLERRORES
							RETURN
						END

						SELECT 'OK' OK 
						RETURN
					END
				END TRY

			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
			END CATCH

			IF(SELECT COUNT(*) FROM @TBLERRORES) >0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END

			SELECT 'OK' OK
		END

		IF @METODO = 'ELIMINAR'
			BEGIN
					SELECT  @CODCONCEPTO = CODCONCEPTO, @ITEM = ITEM, @PRIORIDAD = PRIORIDAD
					FROM	OPENJSON (@PARAMETROS) 
					WITH(
						CODCONCEPTO			VARCHAR(20)			'$.CODCONCEPTO',
						ITEM				DECIMAL(14,0)		'$.ITEM',
						PRIORIDAD			SMALLINT			'$.PRIORIDAD'
						)

			BEGIN TRY
					DELETE FROM NCONDB WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM AND PRIORIDAD = @PRIORIDAD
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
				END CATCH

				IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
				BEGIN
					SELECT 'KO' OK
					SELECT ERROR FROM @TBLERRORES
					RETURN
				END
		SELECT 'OK' OK
		END
END
