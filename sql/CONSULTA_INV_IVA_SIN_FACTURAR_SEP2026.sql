/*
  CEM — entradas de septiembre 2026 con IVA
  contra el servicio del hijo (SER.IDSERVICIO = artículo, p. ej. INS0040-5).

  No usa el padre (IART.IDSERVICIO = INS0040).
  Factura IVA cuando el hijo está Activo y SER.IVA = 'SER'.
*/
SET NOCOUNT ON;

SELECT
  CASE
    WHEN SH.IDSERVICIO IS NULL THEN N'Sin fila en SER'
    WHEN SH.ESTADO = N'Inactivo' AND COALESCE(SH.IVA, N'') = N'SER' THEN N'Inactivo, IVA = SER'
    WHEN SH.ESTADO = N'Inactivo' THEN N'Inactivo, IVA distinto de SER'
    WHEN COALESCE(SH.IVA, N'') = N'SER' THEN N'Activo, IVA = SER'
    ELSE N'Activo, IVA distinto de SER'
  END AS SITUACION,
  COUNT(DISTINCT H.IDARTICULO) AS ARTICULOS,
  CONVERT(decimal(18, 2), SUM(COALESCE(H.VLRIVA, 0))) AS IVA
FROM dbo.IMOVH H
INNER JOIN dbo.IMOV M ON M.CNSMOV = H.CNSMOV
INNER JOIN dbo.ITMO T ON T.IDTIPOMOV = M.IDTIPOMOV
LEFT JOIN dbo.SER SH ON SH.IDSERVICIO = H.IDARTICULO
WHERE M.FECHAMOV >= '20260901'
  AND M.FECHAMOV < '20261001'
  AND COALESCE(M.ESTADO, '0') = '1'
  AND T.TIPO = 'Credito'
  AND (COALESCE(H.VLRIVA, 0) > 0 OR COALESCE(H.PIVA, 0) > 0)
GROUP BY
  CASE
    WHEN SH.IDSERVICIO IS NULL THEN N'Sin fila en SER'
    WHEN SH.ESTADO = N'Inactivo' AND COALESCE(SH.IVA, N'') = N'SER' THEN N'Inactivo, IVA = SER'
    WHEN SH.ESTADO = N'Inactivo' THEN N'Inactivo, IVA distinto de SER'
    WHEN COALESCE(SH.IVA, N'') = N'SER' THEN N'Activo, IVA = SER'
    ELSE N'Activo, IVA distinto de SER'
  END
ORDER BY IVA DESC;

SELECT
  H.IDARTICULO,
  A.DESCRIPCION,
  SH.ESTADO,
  COALESCE(SH.IVA, N'') AS IVA_SERVICIO,
  COALESCE(SH.IDIMPUESTO, N'') AS IMPUESTO,
  COALESCE(SH.IDCLASE, N'') AS CLASE,
  COUNT(DISTINCT M.CNSMOV) AS ENTRADAS,
  CONVERT(decimal(18, 2), SUM(H.CANTIDAD)) AS CANTIDAD,
  CONVERT(decimal(18, 2), SUM(COALESCE(H.VLRIVA, 0))) AS IVA_ENTRADA
FROM dbo.IMOVH H
INNER JOIN dbo.IMOV M ON M.CNSMOV = H.CNSMOV
INNER JOIN dbo.ITMO T ON T.IDTIPOMOV = M.IDTIPOMOV
INNER JOIN dbo.IART A ON A.IDARTICULO = H.IDARTICULO
LEFT JOIN dbo.SER SH ON SH.IDSERVICIO = H.IDARTICULO
WHERE M.FECHAMOV >= '20260901'
  AND M.FECHAMOV < '20261001'
  AND COALESCE(M.ESTADO, '0') = '1'
  AND T.TIPO = 'Credito'
  AND (COALESCE(H.VLRIVA, 0) > 0 OR COALESCE(H.PIVA, 0) > 0)
  AND NOT (
    SH.ESTADO = N'Activo'
    AND COALESCE(SH.IVA, N'') = N'SER'
  )
GROUP BY H.IDARTICULO, A.DESCRIPCION, SH.ESTADO, SH.IVA, SH.IDIMPUESTO, SH.IDCLASE
ORDER BY SH.ESTADO, SUM(COALESCE(H.VLRIVA, 0)) DESC, H.IDARTICULO;
