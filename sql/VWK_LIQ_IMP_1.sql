CREATE OR ALTER VIEW DBO.VWK_LIQ_IMP_1
WITH ENCRYPTION
AS 
SELECT MCP.ANO,
       MCP.MES,
       MCH.IDTERCERO,
       (SELECT RAZONSOCIAL FROM TER WHERE MCH.IDTERCERO=TER.IDTERCERO) AS RAZONSOACIAL,
       MCH.CUENTA,
       CUE.NOMCUENTA,
       MAX(MCH.NROASIENTO) AS NROASIENTO,
       SUM(CASE WHEN MCH.TIPO='CR' THEN  MCH.BASE_IMP ELSE 0 END-CASE WHEN MCH.TIPO='DB' THEN  MCH.BASE_IMP ELSE 0 END) AS BASE,
       CASE WHEN MCH.TIPO='DB' THEN SUM(MCH.VALOR) ELSE 0 END AS DEBITOS,  
       CASE WHEN MCH.TIPO='CR' THEN SUM(MCH.VALOR) ELSE 0 END AS CREDITOS,
       MCH.CNSFCXP
FROM   MCP,MCH,CUE
WHERE  MCP.NROCOMPROBANTE=MCH.NROCOMPROBANTE AND MCH.CUENTA=CUE.CUENTA AND MCP.ESTADO=2 AND
       CUE.IMPUESTO=1 AND CUE.COMPANIA='01' AND NOT (BASE_IMP IS NULL OR BASE_IMP=0) AND COALESCE(MCP.ANULADO,0)<>1
	   AND NOT EXISTS(SELECT * FROM FCXPI WHERE COALESCE(IMPUESTO_ASUM,0)= CASE WHEN DBO.FNK_VALORVARIABLE('LIQIMPASUMIDO')='NO' THEN 1 ELSE 4 END  AND MCH.CNSPAGO=FCXPI.CNSFCXPI 
          AND FCXPI.IDIMPUESTO=MCH.REFERENCIA1 AND FCXPI.IDCLASE=MCH.REFERENCIA2 
          AND FCXPI.ITEM=CASE WHEN ISNUMERIC(MCH.REFERENCIA3)=0 THEN 0 ELSE MCH.REFERENCIA3 END 
          AND REFERENCIA_PRO=FCXPI.CNSFCXP
          )
GROUP BY MCP.ANO,
       MCP.MES,
       MCH.IDTERCERO,
       MCH.CUENTA,
       CUE.NOMCUENTA,
       MCH.TIPO,
       MCH.CNSFCXP
       --MCH.NROASIENTO
