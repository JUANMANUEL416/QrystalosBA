CREATE OR ALTER PROCEDURE DBO.SPQ_GES_LENTES_COL
@JSON  NVARCHAR(MAX) 
WITH
ENCRYPTION
AS
DECLARE  @PARAMETROS   NVARCHAR(MAX) ,@MODELO           VARCHAR(100) ,@METODO           VARCHAR(100)  ,@USUARIO        VARCHAR(12),
			@GRUPO        VARCHAR(8)    ,@SYS_COMPUTERNAME VARCHAR(254) ,@IDSEDE             VARCHAR(5)    ,@USUNOMBRE     VARCHAR(100), @SEDE VARCHAR(5),
			@FECHA        VARCHAR(10)   ,@IDEMEDICA        VARCHAR(4)	,@FECHA1           DATETIME		,@SQL            VARCHAR(MAX),
			@CODCAJERO		VARCHAR(20),@COMPANIA		VARCHAR(10)	,@IDAFILIADO VARCHAR(20)	,@IDMEDICO	VARCHAR(20)	,@FECHAINI DATE	,
			@FECHAFIN	DATE	,@CONSECUTIVOS	NVARCHAR(MAX)	,@MARCAR BIT	,@NOAUTORIZACION VARCHAR(50)	,@CONSECUTIVO VARCHAR(20),
			@OBSERVACION	VARCHAR (200)	,@IDCAUSAL VARCHAR(20)	,@IDSERVICIO VARCHAR(20)	,@CONT INT		,@CNSIZSOL VARCHAR(20)
			,@CONSECUTIVOCAN VARCHAR(20)	,@GRUPAL BIT	,@IDAUT VARCHAR(20)		,@VR_TOTAL DECIMAL(14,2)   ,@VLRDEPOSITOS DECIMAL(14,2) 
DECLARE @ITEM_AUTD INT, @CONSECUTIVO_NEW VARCHAR(20),  @LIMITE_AU INT		,@NUMERO VARCHAR(20)		,@MENSAJE VARCHAR(500)		,@PROCESO VARCHAR(50)
DECLARE @ITEM_REGISTRO INT	,@NOITEM INT, @VLRTOTAL DECIMAL(14,2), @VLRABONADO DECIMAL(14,2), @FALTANTE DECIMAL(14,2),  @VLRABONAR DECIMAL(14,2)
DECLARE @LIMITE_REGISTRO INT	,@NOAUT VARCHAR(20)	,@PROCEDENCIA VARCHAR(20), @ITEM INT
DECLARE @TABLERRR		TABLE (ERROR VARCHAR(200))

BEGIN 
	SET LANGUAGE Spanish;  
	SET DATEFORMAT dmy
	SELECT *
	INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)  AS JSON
	)

	SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON
	--DEFINICION DE TABLA DE ERRORES
	DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200));
	-- TOMA DEL GRUPO, SYS_COMPUTERNAME, SEDE   DE ACUERDO AL USUARIOpl,   --PRINT 'USUARIO:'+@USUARIO
	SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO), @USUNOMBRE = NOMBRE FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME, @COMPANIA = COMPANIA, @CODCAJERO= CODCAJERO FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @IDSEDE = IDSEDE, @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
	PRINT '@USUARIO='+@USUARIO


	IF @METODO = 'MARCAR_ITEM'
	BEGIN
		SELECT @CONSECUTIVOS =  CONSECUTIVOS, @MARCAR =  MARCAR
	   FROM OPENJSON (@PARAMETROS)
	   WITH		 (
		CONSECUTIVOS		NVARCHAR(MAX) AS JSON
		,MARCAR				BIT  '$.MARCAR'
		)

		SELECT ROW_NUMBER()OVER(ORDER BY  CONSECUTIVO  DESC) FILA, * INTO #TABLA_LORD
		FROM OPENJSON (@CONSECUTIVOS)
		WITH (
			CONSECUTIVO		VARCHAR(20)  '$.CONSECUTIVO'
		)
		BEGIN TRY 
			SELECT 'OK'OK

            SELECT @ITEM_REGISTRO=1,@LIMITE_REGISTRO=0
            SELECT @LIMITE_REGISTRO=COUNT(*) FROM  #TABLA_LORD
			WHILE @ITEM_REGISTRO<=@LIMITE_REGISTRO
            BEGIN
				IF @MARCAR = 1
				BEGIN
					UPDATE AUT SET MARCAENV = 1, IDALTERNA = @USUARIO FROM AUT INNER JOIN #TABLA_LORD ON AUT.IDAUT  = #TABLA_LORD.CONSECUTIVO
					WHERE #TABLA_LORD.FILA = @ITEM_REGISTRO
				END
				IF @MARCAR = 0
				BEGIN
					PRINT 'DESMARCAAAA'
					UPDATE AUT SET MARCAENV = 0, IDALTERNA = NULL FROM AUT INNER JOIN #TABLA_LORD ON AUT.IDAUT  = #TABLA_LORD.CONSECUTIVO 
					WHERE #TABLA_LORD.FILA = @ITEM_REGISTRO
				END
                SELECT @ITEM_REGISTRO = @ITEM_REGISTRO+1 
            END

		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF EXISTS(SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' AS OK
		RETURN
	END
	IF @METODO = 'TERMINAR'
	BEGIN
		SELECT @IDAUT =  IDAUT
	   FROM OPENJSON (@PARAMETROS)
	   WITH		 (
		IDAUT				VARCHAR(20)  '$.IDAUT'
		)
		IF (SELECT COALESCE(AUT.ENTREGADO,0) FROM AUT WHERE AUT.IDAUT = @IDAUT) = 1
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'el registro ya esta Registrado.'
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		IF (SELECT COALESCE(AUT.NOTIFICADO,0) FROM AUT WHERE AUT.IDAUT = @IDAUT) = 0
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El Paciente No ha Sido Notificado...'
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		
		SELECT TOP 1 @VR_TOTAL = FTR.VR_TOTAL , @VLRDEPOSITOS = AUT.VLRDEPOSITOS
        FROM   AUT INNER JOIN AUTD ON AUT.IDAUT=AUTD.IDAUT 
                   INNER JOIN FTR ON AUTD.N_FACTURA=FTR.N_FACTURA 
        WHERE AUT.IDAUT= @IDAUT
        AND AUTD.IDPLAN = DBO.FNK_VALORVARIABLE('IDPLANPART') 
        GROUP BY FTR.VR_TOTAL,AUT.VLRDEPOSITOS 
		BEGIN TRY 
			IF @VR_TOTAL > @VLRDEPOSITOS
				SELECT 'OK'OK,  'SI' PREGUNTAR
			ELSE
				SELECT 'OK'OK,  'NO' PREGUNTAR

		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF EXISTS(SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' AS OK
		RETURN
	END
	IF @METODO = 'TERMINAR_GO'
	BEGIN
		SELECT @IDAUT =  IDAUT
	   FROM OPENJSON (@PARAMETROS)
	   WITH		 (
		IDAUT				VARCHAR(20)  '$.IDAUT'
		)
	
		BEGIN TRY 
			UPDATE AUT SET ENTREGADO = 1 , FENTREGA = DBO.FNK_GETDATE() , UENTREGA = @USUARIO WHERE AUT.IDAUT = @IDAUT
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF EXISTS(SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' AS OK
		RETURN
	END
	IF @METODO = 'NOTIFICAR'
	BEGIN
		SELECT @CONSECUTIVOS =  CONSECUTIVOS
	   FROM OPENJSON (@PARAMETROS)
	   WITH		 (
		CONSECUTIVOS		NVARCHAR(MAX) AS JSON
		)

		SELECT ROW_NUMBER()OVER(ORDER BY  CONSECUTIVO  DESC) FILA, * INTO #TABLA_NOTI
		FROM OPENJSON (@CONSECUTIVOS)
		WITH (
			CONSECUTIVO		VARCHAR(20)  '$.CONSECUTIVO'
		)
		BEGIN TRY 
			SELECT 'OK'OK

            SELECT @ITEM_REGISTRO=1,@LIMITE_REGISTRO=0
            SELECT @LIMITE_REGISTRO=COUNT(*) FROM  #TABLA_NOTI
			WHILE @ITEM_REGISTRO<=@LIMITE_REGISTRO
            BEGIN
				SELECT @IDAFILIADO = AUT.IDAFILIADO FROM AUT, #TABLA_NOTI WHERE AUT.IDAUT = #TABLA_NOTI.CONSECUTIVO AND #TABLA_NOTI.FILA = @ITEM_REGISTRO
				IF (SELECT COUNT(*) FROM DBO.FNK_TELEFONOS_SMS(@IDAFILIADO)) > 0
				BEGIN

					SELECT TOP 1 @NUMERO = NUMERO FROM DBO.FNK_TELEFONOS_SMS(@IDAFILIADO)
					SELECT @MENSAJE = (SELECT LTRIM(RTRIM(OBSERVACION)) FROM USVGS WHERE IDVARIABLE='MSM_NOTIFICACION_AUT')
					EXEC SPK_SENDSMS @NUMERO , @MENSAJE

					UPDATE AUT SET AUT.NOTIFICADO = 1 FROM AUT, #TABLA_NOTI WHERE AUT.IDAUT = #TABLA_NOTI.CONSECUTIVO AND #TABLA_NOTI.FILA = @ITEM_REGISTRO 
				END
                SELECT @ITEM_REGISTRO = @ITEM_REGISTRO+1 
            END

		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF EXISTS(SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' AS OK
		RETURN
	END
	IF @METODO = 'FORMATER'
	BEGIN
		SELECT @PROCESO =  PROCESO
	   FROM OPENJSON (@PARAMETROS)
	   WITH		 (
		PROCESO		VARCHAR(50)  '$.PROCESO'
		)
		BEGIN TRY 
			SELECT 'OK'OK
			UPDATE AUT SET MARCAENV = 0 , IDALTERNA = NULL WHERE AUT.IDALTERNA = @USUARIO
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF EXISTS(SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' AS OK
		RETURN
	END
	IF @METODO = 'ENTREGA_LABORATORIO'
	BEGIN
		SELECT @IDAUT =  IDAUT, @NOITEM = NOITEM
	   FROM OPENJSON (@PARAMETROS)
	   WITH		 (
		IDAUT		VARCHAR(50)		'$.IDAUT'
		,NOITEM		INT				'$.NOITEM'
		)
		IF (SELECT COALESCE (AUTD.F_INGLAB,'') FROM AUTD WHERE AUTD.IDAUT = @IDAUT AND AUTD.NO_ITEM = @NOITEM ) <> ''
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'Ya se le Asigno Fecha de Ingreso al Laboratorio...'
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		BEGIN TRY 
			UPDATE AUTD SET F_INGLAB = DBO.FNK_GETDATE() WHERE AUTD.IDAUT = @IDAUT AND AUTD.NO_ITEM = @NOITEM
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF EXISTS(SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' AS OK
		RETURN
	END
	IF @METODO = 'SALIDA_LABORATORIO'
	BEGIN
		SELECT @IDAUT =  IDAUT, @NOITEM = NOITEM
	   FROM OPENJSON (@PARAMETROS)
	   WITH		 (
			IDAUT		VARCHAR(50)		'$.IDAUT'
			,NOITEM		INT				'$.NOITEM'
			)
		IF (SELECT COALESCE (AUTD.F_SALILAB,'') FROM AUTD WHERE AUTD.IDAUT = @IDAUT AND AUTD.NO_ITEM = @NOITEM) <> ''
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'Ya se le Asigno Fecha de Salida al Laboratorio...'
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		BEGIN TRY 
			UPDATE AUTD SET F_SALILAB = DBO.FNK_GETDATE() WHERE AUTD.IDAUT = @IDAUT AND AUTD.NO_ITEM = @NOITEM
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF EXISTS(SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' AS OK
		RETURN
	END
	IF @METODO = 'VER_ABONO'
	BEGIN
		SELECT @IDAUT =  IDAUT
	   FROM OPENJSON (@PARAMETROS)
	   WITH		 (
			IDAUT		VARCHAR(50)		'$.IDAUT'
			)
	
		BEGIN TRY 
			IF EXISTS (
				  SELECT TOP 1 'OK' OK, FTR.VR_TOTAL,AUT.VLRDEPOSITOS 
					FROM   AUT INNER JOIN AUTD ON AUT.IDAUT=AUTD.IDAUT 
							INNER JOIN FTR ON AUTD.N_FACTURA=FTR.N_FACTURA 
					WHERE AUT.IDAUT=@IDAUT
					AND AUTD.IDPLAN=DBO.FNK_VALORVARIABLE('IDPLANPART')
					GROUP BY FTR.VR_TOTAL,AUT.VLRDEPOSITOS)
					SELECT TOP 1 'OK' OK, COALESCE( FTR.VR_TOTAL,0) VR_TOTAL,AUT.VLRDEPOSITOS 
					FROM   AUT INNER JOIN AUTD ON AUT.IDAUT=AUTD.IDAUT 
							INNER JOIN FTR ON AUTD.N_FACTURA=FTR.N_FACTURA 
					WHERE AUT.IDAUT=@IDAUT
					AND AUTD.IDPLAN=DBO.FNK_VALORVARIABLE('IDPLANPART')
					GROUP BY FTR.VR_TOTAL,AUT.VLRDEPOSITOS
					ELSE
					SELECT  'OK' OK, 0 VR_TOTAL, 0 VLRDEPOSITOS
					
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF EXISTS(SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' AS OK
		RETURN
	END
	IF @METODO = 'ABONAR' 
	BEGIN
		SELECT @IDAUT =  IDAUT, @VLRTOTAL = VLRTOTAL, @VLRABONADO = VLRABONADO, @FALTANTE = FALTANTE, @VLRABONAR = VLRABONAR
	   FROM OPENJSON (@PARAMETROS)
	   WITH		 (
			IDAUT		VARCHAR(50)			'$.IDAUT'
			,VLRTOTAL	DECIMAL(14,2)		'$.VLRTOTAL'
			,VLRABONADO	DECIMAL(14,2)		'$.VLRABONADO'
			,FALTANTE	DECIMAL(14,2)		'$.FALTANTE'
			,VLRABONAR	DECIMAL(14,2)		'$.VLRABONAR'
			)
		
		IF @VLRABONAR <= 0
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El Valor Ingresado no es Valido'
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		IF @FALTANTE < @FALTANTE
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El Valor Ingresado no es Mayor al valor Pendiente de Pago'
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		BEGIN TRY 
			SELECT @NOAUT = NOAUT FROM AUT WHERE AUT.IDAUT = @IDAUT
			  IF @VLRABONADO <= 0
			  BEGIN
				EXEC SPK_PAGOSCAJA_AUT_RELACIONADOS @NOAUT, @SYS_COMPUTERNAME, @COMPANIA, @SEDE, @USUARIO, @VLRABONAR
			  END
			  ELSE
			  BEGIN
				EXEC SPK_ABONOFACTURA_AUT_CAJAPART @NOAUT, @SYS_COMPUTERNAME, @COMPANIA, @SEDE, @USUARIO, @VLRABONAR
			  END
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF EXISTS(SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' AS OK
		RETURN
	END
	IF @METODO = 'GUARDA_CITSE' 
	BEGIN
		SELECT @IDAUT =  IDAUT, @PROCEDENCIA = PROCEDENCIA, @OBSERVACION = OBSERVACION, @ITEM = ITEM, @PROCESO = PROCESO
	   FROM OPENJSON (@PARAMETROS)
	   WITH		 (
			IDAUT			VARCHAR(50)			'$.IDAUT'
			,PROCEDENCIA	VARCHAR(50)			'$.PROCEDENCIA'
			,OBSERVACION	VARCHAR(500)		'$.OBSERVACION'
			,ITEM			INT					'$.ITEM'
			,PROCESO		VARCHAR(50)			'$.PROCESO'
			)
		
		
		BEGIN TRY 
			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				SELECT @IDAFILIADO = IDAFILIADO, @NOAUT = NOAUT FROM AUT WHERE IDAUT = @IDAUT
				IF (SELECT COUNT(*) FROM CITSE WHERE CONSECUTIVO = @IDAUT AND PROCEDENCIA = @PROCEDENCIA) = 0 
					SET @CONT = 1
				ELSE 
					SELECT @CONT = (SELECT COUNT(1) FROM CITSE WHERE CONSECUTIVO = @IDAUT AND PROCEDENCIA = @PROCEDENCIA) + 1

				INSERT INTO CITSE (CONSECUTIVO, ITEM, USUARIO, SYS_COMPUTERNAME, OBSERVACION, PROCEDENCIA, FECHA, IDAFILIADO)
				SELECT @IDAUT, @CONT,@USUARIO,@SYS_COMPUTERNAME, @OBSERVACION, @PROCEDENCIA, DBO.FNK_GETDATE(), @IDAFILIADO
			END
			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				SELECT @IDAFILIADO = IDAFILIADO, @NOAUT = NOAUT FROM AUT WHERE IDAUT = @IDAUT
				
				UPDATE CITSE SET OBSERVACION = @OBSERVACION WHERE CONSECUTIVO = @IDAUT AND ITEM = @ITEM
			END
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF EXISTS(SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' AS OK
		RETURN
	END
END
