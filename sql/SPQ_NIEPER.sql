CREATE OR ALTER PROCEDURE DBO.SPQ_NIEPER @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @DATO NVARCHAR(MAX)
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20)
DECLARE @PROCESO VARCHAR(20), @IDTERCERO_PRF VARCHAR(20), @TOTAL_NOMINA DECIMAL(15, 6), @NUMDOC VARCHAR(20), @CNSPAGO VARCHAR(20), @CODCONCEPTO VARCHAR(20)
DECLARE @VLRPAGO DECIMAL(12, 2), @REFERENCIA VARCHAR(20), @REFERENCIA1 VARCHAR(20), @ITEMR SMALLINT, @RENGLON SMALLINT, @NOITEM SMALLINT, @PROCE VARCHAR(10), @IDSEDE 
	VARCHAR(5), @SYS_COMPUTERNAME VARCHAR(254), @COMPANIA VARCHAR(2), @NROCOMPROBANTE VARCHAR(20), @DATE AS DATETIME, @DESCRIPCION AS VARCHAR(255)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
	FROM USUSU
	WHERE USUARIO = @USUARIO

	SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
	FROM UBEQ
	WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	IF @METODO = 'PROC_PAGO'
	BEGIN
		BEGIN TRY
			SELECT @VLRPAGO = VLRPAGO, @TOTAL_NOMINA = TOTAL_NOMINA, @CNSPAGO = CNSPAGO, @NUMDOC = NUMDOC, @CODCONCEPTO = CODCONCEPTO, @NOITEM = NOITEM, @REFERENCIA = 
				REFERENCIA, @REFERENCIA1 = REFERENCIA1, @PROCE = PROCE, @ITEMR = ITEMR, @RENGLON = RENGLON, @DESCRIPCION = DESCRIPCION, @IDTERCERO_PRF = IDTERCERO_PRF
			FROM OPENJSON(@PARAMETROS) WITH (
					VLRPAGO DECIMAL(12, 2) '$.VLRPAGO', TOTAL_NOMINA DECIMAL(15, 6) '$.TOTAL_NOMINA', CNSPAGO VARCHAR(20) '$.CNSPAGO', NUMDOC VARCHAR(20) 
					'$.NUMDOC', CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO', NOITEM SMALLINT '$.NOITEM', REFERENCIA VARCHAR(20) '$.REFERENCIA', REFERENCIA1 VARCHAR(
						20) '$.REFERENCIA1', PROCE VARCHAR(10) '$.PROCE', ITEMR SMALLINT '$.ITEMR', RENGLON SMALLINT '$.RENGLON', DESCRIPCION VARCHAR(255) 
					'$.DESCRIPCIONR', IDTERCERO_PRF VARCHAR(20) '$.IDTERCERO_PRF'
					)

			UPDATE NIEPER
			SET VLRPAGO = @VLRPAGO, ESTADO = 'Pagado', DESCRIPCION = @DESCRIPCION, USUARIOP = @USUARIO, PROCE = @PROCE, REFERENCIA = @REFERENCIA, REFERENCIA1 = 
				@REFERENCIA1, IDTERCERO_PRF = @IDTERCERO_PRF, ITEMR = @ITEMR, RENGLON = @RENGLON
			WHERE CNSPAGO = @CNSPAGO AND NUMDOC = @NUMDOC AND CODCONCEPTO = @CODCONCEPTO AND NOITEM = @NOITEM

			IF @VLRPAGO < @TOTAL_NOMINA
			BEGIN
				INSERT INTO NIEPER (CNSPAGO, NUMDOC, CODCONCEPTO, TOTAL_NOMINA, IDTERCERO_PRF, ESTADO, VLRPAGO, NOITEM)
				SELECT CNSPAGO, NUMDOC, CODCONCEPTO, TOTAL_NOMINA - SUM(VLRPAGO), IDTERCERO_PRF, 'Nuevo', 0, @NOITEM + 1
				FROM NIEPER
				WHERE CNSPAGO = @CNSPAGO AND NUMDOC = @NUMDOC AND CODCONCEPTO = @CODCONCEPTO AND NOITEM = @NOITEM
				GROUP BY CNSPAGO, NUMDOC, CODCONCEPTO, TOTAL_NOMINA, IDTERCERO_PRF
			END

			IF @REFERENCIA <> ''
			BEGIN
				IF @PROCE = 'Bancos'
				BEGIN
					UPDATE BMOVD
					SET ENPAGOS = CASE 
							WHEN VLRITEM <= (VLRLEGALIZADO + @VLRPAGO)
								THEN 1
							ELSE 0
							END, VLRLEGALIZADO = COALESCE(VLRLEGALIZADO, 0) + @VLRPAGO
					WHERE CTA_BCO = @REFERENCIA AND BANCO = @REFERENCIA1 AND ITEM = @ITEMR AND RENGLON = @RENGLON
				END
				ELSE
				BEGIN
					UPDATE FCJ
					SET ENTREGADO = CASE 
							WHEN VALORTOTAL <= (VLRLEGALIZADO + @VLRPAGO)
								THEN 1
							ELSE 0
							END, VLRLEGALIZADO = COALESCE(VLRLEGALIZADO, 0) + @VLRPAGO
					WHERE CODCAJA = @REFERENCIA1 AND CNSFACJ = @REFERENCIA
				END
			END

			SET @DATE = GETDATE()

			EXEC SPK_NC_CONTAB_RECOBRONOMI @CNSPAGO, @NOITEM, @NUMDOC, @USUARIO, @SYS_ComputerName, @COMPANIA, @IDSEDE, '', @DATE
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GETREF'
	BEGIN
		SELECT @IDTERCERO_PRF = IDTERCERO_PRF
		FROM OPENJSON(@PARAMETROS) WITH (IDTERCERO_PRF VARCHAR(20) '$.IDTERCERO_PRF')

		SELECT 'OK' OK

		SELECT BMOVD.CTA_BCO, 'Bancos' AS TIPO, BMOVD.BANCO, BMOVD.ITEM, BMOVD.RENGLON, BMOVD.IDTERCERO, TER.RAZONSOCIAL, BMOVD.VLRITEM, VLRLEGALIZADO
		FROM [BMOVD]
		INNER JOIN BMOV ON BMOVD.BANCO = BMOV.BANCO AND BMOVD.CTA_BCO = BMOV.CTA_BCO AND BMOVD.SUCURSAL = BMOV.SUCURSAL AND BMOVD.ITEM = BMOV.ITEM
		INNER JOIN TER ON BMOVD.IDTERCERO = TER.IDTERCERO
		WHERE COALESCE(BMOVD.RNOMI, 0) = 1 AND BMOVD.VLRITEM - COALESCE(BMOVD.VLRLEGALIZADO, 0) > 0 AND COALESCE(BMOVD.ENPAGOS, 0) = 0 AND COALESCE(BMOV.ESTADO, '') = 'O' 
			AND COALESCE(BMOVD.IDTERCERO, '') = @IDTERCERO_PRF
		
		UNION ALL
		
		SELECT FCJ.CNSFACJ, 'Caja', FCJ.CODCAJA, 1, 1, FCJ.IDTERCERO, TER.RAZONSOCIAL, FCJ.VALORTOTAL, 0
		FROM FCJ
		INNER JOIN TER ON FCJ.IDTERCERO = TER.IDTERCERO
		WHERE COALESCE(FCJ.RNOMI, 0) = 1 AND COALESCE(FCJ.VALORTOTAL, 0) - COALESCE(FCJ.VLRLEGALIZADO, 0) > 0 AND COALESCE(FCJ.ENTREGADO, 0) = 0 AND COALESCE(FCJ.CERRADA
				, 0) = 1 AND COALESCE(FCJ.ESTADO, '') = 'P' AND COALESCE(FCJ.IDTERCERO, '') = @IDTERCERO_PRF

		RETURN
	END

	IF @METODO = 'TOTAL'
	BEGIN
		SELECT @TOTAL_NOMINA = TOTAL_NOMINA, @CNSPAGO = CNSPAGO, @NUMDOC = NUMDOC, @CODCONCEPTO = CODCONCEPTO
		FROM OPENJSON(@PARAMETROS) WITH (
				TOTAL_NOMINA DECIMAL(15, 6) '$.TOTAL_NOMINA', CNSPAGO VARCHAR(20) '$.CNSPAGO', NUMDOC VARCHAR(20) '$.NUMDOC', CODCONCEPTO VARCHAR(20) 
				'$.CODCONCEPTO'
				)

		SELECT 'OK' OK

		SELECT @TOTAL_NOMINA - SUM(VLRPAGO) AS VLRPAGOTOTAL
		FROM NIEPER
		WHERE CNSPAGO = @CNSPAGO AND NUMDOC = @NUMDOC AND CODCONCEPTO = @CODCONCEPTO
		GROUP BY TOTAL_NOMINA

		RETURN
	END

	IF @METODO = 'VALD_BANCOS'
	BEGIN
		SELECT @VLRPAGO = VLRPAGO, @REFERENCIA = REFERENCIA, @REFERENCIA1 = REFERENCIA1, @ITEMR = ITEMR, @RENGLON = RENGLON
		FROM OPENJSON(@PARAMETROS) WITH (
				VLRPAGO DECIMAL(12, 2) '$.VLRPAGO', REFERENCIA VARCHAR(20) '$.REFERENCIA', REFERENCIA1 VARCHAR(20) '$.REFERENCIA1', ITEMR SMALLINT '$.ITEMR', 
				RENGLON SMALLINT '$.RENGLON'
				)

		SELECT 'OK' OK

		SELECT CASE 
				WHEN VLRITEM < (COALESCE(VLRLEGALIZADO, 0) + @VLRPAGO)
					THEN 1
				ELSE 0
				END AS RES
		FROM BMOVD
		WHERE CTA_BCO = @REFERENCIA AND BANCO = @REFERENCIA1 AND ITEM = @ITEMR AND RENGLON = @RENGLON

		RETURN
	END

	IF @METODO = 'VALD_CAJA'
	BEGIN
		SELECT @VLRPAGO = VLRPAGO, @REFERENCIA = REFERENCIA, @REFERENCIA1 = REFERENCIA1, @ITEMR = ITEMR, @RENGLON = RENGLON
		FROM OPENJSON(@PARAMETROS) WITH (
				VLRPAGO DECIMAL(12, 2) '$.VLRPAGO', REFERENCIA VARCHAR(20) '$.REFERENCIA', REFERENCIA1 VARCHAR(20) '$.REFERENCIA1', ITEMR SMALLINT '$.ITEMR', 
				RENGLON SMALLINT '$.RENGLON'
				)

		SELECT 'OK' OK

		SELECT CASE 
				WHEN VALORTOTAL < (COALESCE(VLRLEGALIZADO, 0) + @VLRPAGO)
					THEN 1
				ELSE 0
				END AS RES
		FROM FCJ
		WHERE CODCAJA = @REFERENCIA1 AND CNSFACJ = @REFERENCIA

		RETURN
	END

	IF @METODO = 'AUTO_EMP'
	BEGIN
		SELECT @CNSPAGO = CNSPAGO, @NUMDOC = NUMDOC, @CODCONCEPTO = CODCONCEPTO, @NOITEM = NOITEM
		FROM OPENJSON(@PARAMETROS) WITH (CNSPAGO VARCHAR(20) '$.CNSPAGO', NUMDOC VARCHAR(20) '$.NUMDOC', CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO', NOITEM SMALLINT '$.NOITEM'
				)

		BEGIN TRY
			UPDATE NIEPER
			SET ESTADO = 'Consignado', DESCRIPCION = 'Consignado Directamente al Empleado'
			WHERE CNSPAGO = @CNSPAGO AND NUMDOC = @NUMDOC AND CODCONCEPTO = @CODCONCEPTO AND NOITEM = @NOITEM
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
