CREATE OR ALTER PROCEDURE DBO.SPK_NC_CONTAB_ANTICIPO 
@CNSANT             VARCHAR(20), 
@CNSFCOM            VARCHAR(20),
@SEDE               VARCHAR(5),
@USUARIO            VARCHAR(12),
@NROCOMPROBANTE     VARCHAR(20),
@ES_RECONSTRUCCION  BIT = NULL   -- NULL=auto, 1=no mover, 0=mover a MCP
WITH ENCRYPTION
AS
DECLARE @COM              VARCHAR(6)
DECLARE @NOREFERENCIA     VARCHAR(20)
DECLARE @ANO              VARCHAR(4)
DECLARE @MES              INT
DECLARE @IDMODELOCONT     VARCHAR(2)
DECLARE @TIPOTERCONTABLE  VARCHAR(10) 
DECLARE @PREFIJO_USCXS    VARCHAR(10)
DECLARE @FECHATRA         DATETIME
DECLARE @COMPANIA         VARCHAR(2)
DECLARE @IDTERCERO        VARCHAR(20)
DECLARE @SYS_COMPUTERNAME VARCHAR(255)
DECLARE @OBSERVACION      VARCHAR(255)
DECLARE @CNSCXCP          VARCHAR(20)
DECLARE @CUENTALEG        VARCHAR(20)
DECLARE @CRUCETER         BIT
DECLARE @IDTERCXP         VARCHAR(20)
DECLARE @NO_MOVER_MCP     BIT = 0  -- 1 = no ejecutar SPK_PASA_MCP_MCPNIIF
BEGIN  
   -- Determinar si mover MCPE?MCP: si @ES_RECONSTRUCCION es NULL, inferir de NROCOMPROBANTE
   IF @ES_RECONSTRUCCION IS NOT NULL
      SET @NO_MOVER_MCP = @ES_RECONSTRUCCION
   ELSE IF LTRIM(RTRIM(ISNULL(@NROCOMPROBANTE,''))) <> ''
      SET @NO_MOVER_MCP = 1  -- NROCOMPROBANTE informado = reconstrucci�n

   SELECT   @ANO            = YEAR(FECHA),
            @MES            = MONTH(FECHA),
            @COMPANIA       ='01',
            @SYS_COMPUTERNAME= HOST_NAME(),
            @OBSERVACION=DESCRIPCION,
            @CNSCXCP=CNSFCXP,
            @CUENTALEG='',
            @CRUCETER=CRUCETER
   FROM ANT
   WHERE CNSANT=@CNSANT
   
   SELECT @IDTERCERO=IDTERCERO FROM FCOM WHERE CNSFCOM=@CNSFCOM
   IF COALESCE(@CRUCETER,0)=1
   BEGIN
      SELECT @IDTERCXP=IDTERCERO FROM FCXP WHERE CNSFCXP=@CNSCXCP
   END
   IF NOT EXISTS(SELECT COMPANIA,ANO,MES FROM PRI WHERE COMPANIA=@COMPANIA AND ANO=@ANO AND MES=@MES)
   BEGIN
      RAISERROR('Periodo Contable NO Existe', 16, 1)
      RETURN
   END
   
   IF (SELECT CERRADO FROM PRI WHERE COMPANIA=@COMPANIA AND ANO=@ANO AND MES=@MES) = 1
   BEGIN
      RAISERROR('Periodo Contable Cerrado', 16, 1)
      RETURN
   END   
   SET @IDMODELOCONT = DBO.FNK_VALORVARIABLE('IDMODELOCONTABLE')
   IF ISNULL(@NROCOMPROBANTE,'') = '' 
   BEGIN
      SET @NROCOMPROBANTE = SPACE(20) 
      EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@MCP',@NROCOMPROBANTE OUTPUT 
      PRINT '@NROCOMPROBANTE:' + ISNULL(@NROCOMPROBANTE,'')
      SELECT @NROCOMPROBANTE = @SEDE + REPLACE(SPACE(8 - CASE WHEN LEN(@NROCOMPROBANTE) > 8 THEN 8 ELSE LEN(@NROCOMPROBANTE) END)+LTRIM(RTRIM(@NROCOMPROBANTE)),SPACE(1),0) 

      PRINT '@NROCOMPROBANTE:' + ISNULL(@NROCOMPROBANTE,'') 
      
      SELECT @COM=TANT.COMPROBANTE
      FROM FCOM INNER JOIN TANT ON FCOM.TIPOANTICIPO=TANT.TIPOANTICIPO
      WHERE FCOM.CNSFCOM=@CNSFCOM
      --IF (SELECT DBO.FNK_VALORVARIABLE('COMPROBMULTISEDE')) = 'SI'
      --BEGIN
      --   SELECT @COM = RTRIM(LTRIM(COMMS.COMPROBANTE)) FROM COMMS WHERE IDSEDE = @SEDE AND COMMS.CLASE = 'ANTICIPOS' 
      --   IF @COM IS NULL
      --      SET @COM=LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('IDCON_TCOM_ANTI')))
      --END
      --ELSE
      --BEGIN
      --   SET @COM=LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('IDCON_TCOM_ANTI')))
      --END
      
      SET @PREFIJO_USCXS='@COM'+@COM
      SET @NOREFERENCIA=SPACE(20)
      EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,@PREFIJO_USCXS,@NOREFERENCIA OUTPUT   
      SELECT @NOREFERENCIA = REPLACE(SPACE(8 - LEN(@NOREFERENCIA))+LTRIM(RTRIM(@NOREFERENCIA)),SPACE(1),0)
      PRINT 'Nuevo Comprobante: '+@COM+' '+@NOREFERENCIA
      
      PRINT 'Comprobante Contable (MCPE)'
      INSERT INTO MCPE(NROCOMPROBANTE, COMPANIA, PROCEDENCIA, NOREFERENCIA, ANO, MES, FECHACONTABLE, TOTALDEBITO,
                      TOTALCREDITO, REFERENCIA1, REFERENCIA2, USUARIO, FECHA, LOTE, OBSERVACION, IDSEDE, ESTADO,
                      COMPROBANTE, IDTERCERO)
      SELECT @NROCOMPROBANTE, @COMPANIA, 'ANTICIPOS', @NOREFERENCIA, @ANO, @MES, 
             CAST(STR(DAY(FECHA))+'/'+LTRIM(STR(@MES))+'/'+@ANO AS DATETIME), 0, 0, CNSANT, @CNSFCOM, @USUARIO, 
             DBO.FNK_FECHA_SIN_MLS(GETDATE()), NULL, DESCRIPCION, @SEDE, 0, @COM, @IDTERCERO
      FROM   ANT
      WHERE  CNSANT=@CNSANT
   END
   IF (SELECT COUNT(*) FROM MCP WHERE NROCOMPROBANTE=@NROCOMPROBANTE)>0
   BEGIN
      IF EXISTS(SELECT  * FROM MCPE WHERE NROCOMPROBANTE=@NROCOMPROBANTE)
      BEGIN
         DELETE MCHE WHERE NROCOMPROBANTE=@NROCOMPROBANTE
         DELETE MCPE WHERE NROCOMPROBANTE=@NROCOMPROBANTE
      END
      INSERT INTO MCPE (COMPANIA, NROCOMPROBANTE, PROCEDENCIA, NOREFERENCIA, ANO, MES, FECHACONTABLE, TOTALDEBITO ,TOTALCREDITO, REFERENCIA1, REFERENCIA2,
                       REFERENCIA3, USUARIO, FECHA, LOTE ,OBSERVACION ,IDSEDE ,ESTADO ,ANULADO ,COMPROBANTE ,IDTERCERO, BANCO ,NOCHEQUE, VALOR_CHEQUE,
                       RPT_COMPROBANTE, FECHARADICACION, MARCA, SYS_COMPUTERNAME_MARCA, ESTADOIMP, CBTEINTERNO)
      SELECT COMPANIA, NROCOMPROBANTE, PROCEDENCIA, NOREFERENCIA, ANO, MES, FECHACONTABLE, TOTALDEBITO ,TOTALCREDITO, REFERENCIA1, REFERENCIA2,
                       REFERENCIA3, USUARIO, FECHA, LOTE ,OBSERVACION ,IDSEDE ,ESTADO ,ANULADO ,COMPROBANTE ,IDTERCERO, BANCO ,NOCHEQUE, VALOR_CHEQUE,
                       RPT_COMPROBANTE, FECHARADICACION, MARCA, SYS_COMPUTERNAME_MARCA, ESTADOIMP, CBTEINTERNO
      FROM   MCP
      WHERE NROCOMPROBANTE=@NROCOMPROBANTE
      --se borran de mcp, mch
      UPDATE MCP SET ESTADO=1 WHERE NROCOMPROBANTE=@NROCOMPROBANTE AND ESTADO=2
      DELETE MCH WHERE NROCOMPROBANTE = @NROCOMPROBANTE
      DELETE MCP WHERE NROCOMPROBANTE = @NROCOMPROBANTE   
   END
   ELSE
   BEGIN
      DELETE MCHE WHERE NROCOMPROBANTE=@NROCOMPROBANTE
   END
   IF EXISTS(SELECT * FROM FCXP WHERE CNSFCXP=@CNSCXCP ) --20260311 -- STORRES -- SE QUITA PROCEDENCIA YA QUE NO TIENE EN CUENTA LA CONTABILIZAICON ORIGINAL
   BEGIN
      SELECT @CUENTALEG=CUECREDITO FROM FCXP WHERE CNSFCXP=@CNSCXCP  --20260311 -- STORRES -- SE QUITA PROCEDENCIA YA QUE NO TIENE EN CUENTA LA CONTABILIZAICON ORIGINAL
   END
   INSERT INTO MCHE(NROCOMPROBANTE, COMPANIA, TIPO, CUENTA, IDTERCERO, CCOSTO, DETALLE, VALOR ,REFERENCIA1,
          	        REFERENCIA2, ITEMREF, USUARIO, FECHA, IDAREA, PREFIJO, ESTADO, PROCESO, GENERA, 
                   CLASECONT, N_FACTURA, F_FACTURAREF, F_VENCE, PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
   SELECT @NROCOMPROBANTE, @COMPANIA, 'DB', CASE WHEN COALESCE(@CUENTALEG,'')<>'' THEN @CUENTALEG ELSE  TANT.CUEDEBITO END,
          CASE WHEN COALESCE(@CRUCETER,0)=1 AND COALESCE(@IDTERCXP,'')<>'' THEN @IDTERCXP ELSE FCOM.IDTERCERO END,'' AS CCOSTO, 
          CASE WHEN COALESCE(@CRUCETER,0)=1 THEN  'LEGALIZACION ANTICIPO CON CRUCE DE TERCEROS  : '+ANT.CNSANT+' ORDEN DE SERVICIO: '+ANT.CNSFCOM+'  '+@OBSERVACION
          ELSE 'LEGALIZACION ANTICIPO : '+ANT.CNSANT+' ORDEN DE SERVICIO: '+ANT.CNSFCOM+'  '+@OBSERVACION END, ANT.VALOR_LEG, ANT.CNSANT, ANT.CNSFCOM, NULL, 
          @USUARIO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), '' AS IDAREA, '' AS PREFIJO, 1, 
          'CONC_GLOSAS', 'Movimiento','S',ANT.NOREFERENCIA, DBO.FNK_FECHA_SIN_HORA(ANT.FECHA),
          DBO.FNK_FECHA_SIN_HORA(ANT.FECHA),'Anticipos',@CNSANT, '', ''
   FROM   ANT INNER JOIN FCOM ON ANT.CNSFCOM=FCOM.CNSFCOM
              INNER JOIN TANT ON FCOM.TIPOANTICIPO=TANT.TIPOANTICIPO
   WHERE  ANT.CNSANT=@CNSANT 
   AND FCOM.CNSFCOM=@CNSFCOM

   INSERT INTO MCHE(NROCOMPROBANTE, COMPANIA, TIPO, CUENTA, IDTERCERO, CCOSTO, DETALLE, VALOR ,REFERENCIA1,
          	        REFERENCIA2, ITEMREF, USUARIO, FECHA, IDAREA, PREFIJO, ESTADO, PROCESO, GENERA, 
                   CLASECONT, N_FACTURA, F_FACTURAREF, F_VENCE, PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
   SELECT @NROCOMPROBANTE, @COMPANIA, 'CR', TANT.CUECREDITO,FCOM.IDTERCERO,'' AS CCOSTO, 
          'LEGALIZACION ANTICIPO : '+ANT.CNSANT+' ORDEN DE SERVICIO: '+ANT.CNSFCOM+' '+@OBSERVACION, ANT.VALOR_LEG, ANT.CNSANT, ANT.CNSFCOM, NULL, 
          @USUARIO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), '' AS IDAREA, '' AS PREFIJO, 1, 
          'CONC_GLOSAS', 'Movimiento','S',ANT.NOREFERENCIA, DBO.FNK_FECHA_SIN_HORA(ANT.FECHA),
          DBO.FNK_FECHA_SIN_HORA(ANT.FECHA),'Anticipos',@CNSANT, '', ''
   FROM   ANT INNER JOIN FCOM ON ANT.CNSFCOM=FCOM.CNSFCOM
              INNER JOIN TANT ON FCOM.TIPOANTICIPO=TANT.TIPOANTICIPO
   WHERE  ANT.CNSANT=@CNSANT 
   AND FCOM.CNSFCOM=@CNSFCOM
   
   PRINT 'Poniendo Estado de CONTABILIZADA en La Tabla FCONCI' 
   
   EXEC SPK_NC_REVISAMCPE @NROCOMPROBANTE, @COMPANIA, @USUARIO, @SEDE, @SYS_COMPUTERNAME
   
   -- Mover MCPE?MCP seg�n par�metro: @NO_MOVER_MCP=0 (contabilizaci�n) s� mueve, =1 (reconstrucci�n) no mueve
   IF @NO_MOVER_MCP = 0
   BEGIN
      IF @COM IS NULL
         SELECT @COM = TANT.COMPROBANTE FROM FCOM INNER JOIN TANT ON FCOM.TIPOANTICIPO=TANT.TIPOANTICIPO WHERE FCOM.CNSFCOM=@CNSFCOM --para traer el tipo de comprobante 
      EXEC SPK_PASA_MCP_MCPNIIF @NROCOMPROBANTE, @COMPANIA, @USUARIO, @SYS_COMPUTERNAME, @SEDE,@COM,''
   END
END
