CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NOMI @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20)
DECLARE @PROCESO VARCHAR(20)
DECLARE @CODNOMINA VARCHAR(2), @DESCRIPCION VARCHAR(60), @MAXADEDUCIR DECIMAL(14, 6), @IDPLANTILLA VARCHAR(20), @CODNOMINAEDITE VARCHAR(2)
DECLARE @CODUNG VARCHAR(5), @CCOSTO VARCHAR(20), @IDAREA VARCHAR(20), @REPORTA BIT
DECLARE @DATO NVARCHAR(MAX)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @CODNOMINA = CODNOMINA, @DESCRIPCION = DESCRIPCION, @MAXADEDUCIR = MAXADEDUCIR, @IDPLANTILLA = IDPLANTILLA, @CCOSTO = CCOSTO, @IDAREA = IDAREA, 
				@REPORTA = REPORTA, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					CODNOMINA VARCHAR(2) '$.CODNOMINA', DESCRIPCION VARCHAR(60) '$.DESCRIPCION', MAXADEDUCIR DECIMAL(14, 6) '$.MAXADEDUCIR', IDPLANTILLA VARCHAR(
						20) '$.IDPLANTILLA', CCOSTO VARCHAR(20) '$.CCOSTO', IDAREA VARCHAR(20) '$.IDAREA', REPORTA BIT '$.REPORTA', PROCESO VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('EL CODIGO DE NOMINA ', @CODNOMINA, ' YA SE ENCUENTRA REGISTRADO')
					WHERE EXISTS (
							SELECT 1
							FROM NOMI
							WHERE CODNOMINA = @CODNOMINA
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO NOMI (CODNOMINA, DESCRIPCION, IDPLANTILLA, CCOSTO, IDAREA, MAXADEDUCIR, REPORTA)
						SELECT @CODNOMINA, @DESCRIPCION, @IDPLANTILLA, @CCOSTO, @IDAREA, @MAXADEDUCIR, @REPORTA
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @DATO = DATO
					FROM OPENJSON(@PARAMETROS) WITH (DATO NVARCHAR(MAX) AS JSON)

					SELECT @CODNOMINAEDITE = CODNOMINAEDITE
					FROM OPENJSON(@DATO) WITH (CODNOMINAEDITE VARCHAR(2) '$.CODNOMINAEDITE')

					IF (@CODNOMINAEDITE <> @CODNOMINA)
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('EL CODIGO DE NOMINA ', @CODNOMINA, ' YA SE ENCUENTRA REGISTRADO')
						WHERE EXISTS (
								SELECT 1
								FROM NOMI
								WHERE CODNOMINA = @CODNOMINA
								)

						IF (
								SELECT COUNT(*)
								FROM @TBLERRORES
								) <= 0
						BEGIN
							UPDATE NOMI
							SET CODNOMINA = @CODNOMINA, DESCRIPCION = @DESCRIPCION, IDPLANTILLA = @IDPLANTILLA, CCOSTO = @CCOSTO, IDAREA = @IDAREA, MAXADEDUCIR = 
								@MAXADEDUCIR, REPORTA = @REPORTA
							WHERE CODNOMINA = @CODNOMINAEDITE
						END
					END
					ELSE
					BEGIN
						UPDATE NOMI
						SET DESCRIPCION = @DESCRIPCION, IDPLANTILLA = @IDPLANTILLA, CCOSTO = @CCOSTO, IDAREA = @IDAREA, MAXADEDUCIR = @MAXADEDUCIR, REPORTA = @REPORTA
						WHERE CODNOMINA = @CODNOMINA
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
