CREATE OR ALTER PROCEDURE DBO.SPQ_ESTANTE
@JSON  NVARCHAR(MAX) 
WITH
ENCRYPTION
AS
DECLARE  @PARAMETROS	NVARCHAR(MAX)	,@MODELO			VARCHAR(100)	,@METODO		VARCHAR(100)	,@USUARIO       VARCHAR(12)
		,@GRUPO			VARCHAR(8)		,@SYS_COMPUTERNAME	VARCHAR(254)	,@IDSEDE		VARCHAR(5)		,@USUNOMBRE     VARCHAR(100), @SEDE VARCHAR(5)
		,@FECHA			VARCHAR(10)		,@IDEMEDICA			VARCHAR(4)		,@FECHA1		DATETIME		,@SQL			VARCHAR(MAX)
		,@CODCAJERO		VARCHAR(20)		,@COMPANIA			VARCHAR(10)		,@IDAFILIADO	VARCHAR(20)		,@PROCESO		VARCHAR(20)	,@FECHAINI DATE	
		,@datoTGEN		NVARCHAR(MAX)	,@datoAIRTE			NVARCHAR(MAX)	,@datoGrupo		NVARCHAR(MAX)
DECLARE @TABLERRR		TABLE (ERROR VARCHAR(200))

BEGIN 
	SET LANGUAGE Spanish;  
	SET DATEFORMAT dmy
	SELECT *
	INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)  AS JSON
	)

	SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON
	--DEFINICION DE TABLA DE ERRORES
	DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200));
	-- TOMA DEL GRUPO, SYS_COMPUTERNAME, SEDE   DE ACUERDO AL USUARIOpl,   --PRINT 'USUARIO:'+@USUARIO
	SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO), @USUNOMBRE = NOMBRE FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME, @COMPANIA = COMPANIA, @CODCAJERO= CODCAJERO FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @IDSEDE = IDSEDE, @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
	PRINT '@USUARIO='+@USUARIO

	IF @METODO = 'CRUD_TGEN'
	BEGIN
		SELECT  @datoTGEN = datoTGEN 
		FROM OPENJSON(@PARAMETROS)
		WITH( datoTGEN		NVARCHAR(MAX) AS JSON )
		SELECT @PROCESO =UPPER( JSON_VALUE(@datoTGEN,'$.PROCESO'))
		SELECT * INTO #datoTGEN FROM OPENJSON(@datoTGEN)
		WITH (	TABLA		VARCHAR(20)		'$.TABLA'	,CAMPO			VARCHAR(20)		'$.CAMPO'
				,CODIGO		VARCHAR(20)		'$.CODIGO'	,DESCRIPCION	VARCHAR(250)	'$.DESCRIPCION'
				,DATO1		VARCHAR(20)		'$.DATO1'	,IDTGEN			INT				'$.IDTGEN'	)
	
		IF @PROCESO = 'NUEVO' AND EXISTS (SELECT * FROM TGEN,#datoTGEN  WHERE  TGEN.TABLA = #datoTGEN.TABLA AND TGEN.CODIGO = #datoTGEN.CODIGO AND TGEN.CAMPO = 'ESTANTE')
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El Estante ingresado, ya existe.'
		END
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				IF @PROCESO = 'EDITA'
				BEGIN
					UPDATE TGEN SET TGEN.TABLA =  #datoTGEN.TABLA , TGEN.CODIGO = #datoTGEN.CODIGO , TGEN.DESCRIPCION = #datoTGEN.DESCRIPCION , TGEN.DATO1 = #datoTGEN.DATO1 
					FROM TGEN,#datoTGEN WHERE TGEN.IDTGEN = #datoTGEN.IDTGEN AND TGEN.CAMPO = 'ESTANTE'
				END
				IF @PROCESO = 'NUEVO'
				BEGIN
					INSERT INTO TGEN (TABLA, CAMPO, CODIGO, DESCRIPCION, DATO1)
					SELECT TABLA, 'ESTANTE', CODIGO, DESCRIPCION, DATO1
					FROM #datoTGEN
				END
			END TRY
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK
		END 
	END
	IF @METODO = 'CRUD_IARTE'
	BEGIN
		SELECT  @datoAIRTE = datoAIRTE 
		FROM OPENJSON(@PARAMETROS)
		WITH( datoAIRTE		NVARCHAR(MAX) AS JSON )
		SELECT @PROCESO =UPPER( JSON_VALUE(@datoAIRTE,'$.PROCESO'))
		SELECT * INTO #datoAIRTE FROM OPENJSON(@datoAIRTE)
		WITH (	IDBODEGA		VARCHAR(20)		'$.IDBODEGA'	,IDARTICULO			VARCHAR(20)		'$.IDARTICULO'
				,ESTANTE		VARCHAR(20)		'$.ESTANTE'		,IDARTICULO_ORI		VARCHAR(20)		'$.IDARTICULO_ORI'	)
	
		IF @PROCESO = 'NUEVO' AND EXISTS (SELECT * FROM IARTE,#datoAIRTE  WHERE  IARTE.IDBODEGA = #datoAIRTE.IDBODEGA 
		AND IARTE.IDARTICULO = #datoAIRTE.IDARTICULO AND IARTE.ESTANTE = #datoAIRTE.ESTANTE)
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El articulo ingresado, ya existe, para este Estante'
		END
		IF @PROCESO = 'EDITAR' AND EXISTS (SELECT * FROM IARTE,#datoAIRTE  WHERE  IARTE.IDBODEGA = #datoAIRTE.IDBODEGA 
		AND IARTE.IDARTICULO = #datoAIRTE.IDARTICULO AND IARTE.ESTANTE = #datoAIRTE.ESTANTE AND IARTE.IDARTICULO <> #datoAIRTE.IDARTICULO_ORI)
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El articulo ingresado, ya existe, para este Estante'
		END
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				IF @PROCESO = 'EDITAR'
				BEGIN
					UPDATE IARTE SET IARTE.IDARTICULO =  #datoAIRTE.IDARTICULO
					FROM IARTE,#datoAIRTE WHERE IARTE.IDBODEGA = #datoAIRTE.IDBODEGA AND IARTE.ESTANTE = #datoAIRTE.ESTANTE AND IARTE.IDARTICULO = #datoAIRTE.IDARTICULO_ORI
				END
				IF @PROCESO = 'NUEVO'
				BEGIN
					INSERT INTO IARTE (IDBODEGA, IDARTICULO, ESTANTE)
					SELECT IDBODEGA, IDARTICULO, ESTANTE 
					FROM #datoAIRTE
				END
				IF @PROCESO = 'ELIMINAR'
				BEGIN
					DELETE IARTE FROM IARTE,#datoAIRTE WHERE IARTE.IDBODEGA = #datoAIRTE.IDBODEGA AND IARTE.ESTANTE = #datoAIRTE.ESTANTE AND IARTE.IDARTICULO = #datoAIRTE.IDARTICULO
				END
			END TRY
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK
		END 
	END
	IF @METODO = 'CRUD_TGEN_GRUPO'
	BEGIN
		SELECT  @datoGrupo = datoGrupo 
		FROM OPENJSON(@PARAMETROS)
		WITH( datoGrupo		NVARCHAR(MAX) AS JSON )
		SELECT @PROCESO =UPPER( JSON_VALUE(@datoGrupo,'$.PROCESO'))
		SELECT * INTO #datoGrupo FROM OPENJSON(@datoGrupo)
		WITH (	IDBODEGA		VARCHAR(20)		'$.IDBODEGA',IDTGEN			INT
				,CODIGO			VARCHAR(20)		'$.CODIGO'	,DESCRIPCION	VARCHAR(250)	'$.DESCRIPCION'	)
	
		IF @PROCESO = 'NUEVO' AND EXISTS (SELECT * FROM TGEN,#datoGrupo  WHERE  TGEN.TABLA = #datoGrupo.IDBODEGA AND TGEN.CODIGO = #datoGrupo.CODIGO AND TGEN.CAMPO = 'ESTANTE_P')
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El Grupo ingresado, ya existe.'
		END
		IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				IF @PROCESO = 'EDITAR'
				BEGIN
					UPDATE TGEN SET TGEN.CODIGO = #datoGrupo.CODIGO , TGEN.DESCRIPCION = #datoGrupo.DESCRIPCION 
					FROM TGEN,#datoGrupo WHERE TGEN.IDTGEN = #datoGrupo.IDTGEN AND TGEN.CAMPO = 'ESTANTE_P'
				END
				IF @PROCESO = 'NUEVO'
				BEGIN
					INSERT INTO TGEN (TABLA, CAMPO, CODIGO, DESCRIPCION)
					SELECT IDBODEGA, 'ESTANTE_P', CODIGO, DESCRIPCION
					FROM #datoGrupo
				END
			END TRY
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK
		END 
	END
END
