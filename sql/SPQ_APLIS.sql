        INSERT INTO @ESTADOS_COMPRA_ACTIVOS_SOL(ESTADO)
        VALUES ('PENDIENTE COMPRA'), ('PENDIENTE GESTION'), ('EN RUTA'), ('RECEPCIONADO')

        SELECT
            @ID_APLIS_SOLICITUD = JSON_VALUE(@PARAMETROS, '$.ID')

        -- Obtener datos del APLIS
        SELECT 
            @CANTIDAD_SOLICITUD = A.CANTIDAD,
            @IDSERVICIO_SOLICITUD = A.IDSERVICIO,
            @FECHA_PREVISTA_SOLICITUD = A.FECHA_PREVISTA,
            @IDBODEGA_SOLICITUD = SED.IDBODEGALOG
        FROM APLIS A
        LEFT JOIN SED ON A.IDSEDE = SED.IDSEDE
        WHERE A.ID = @ID_APLIS_SOLICITUD

        IF @ID_APLIS_SOLICITUD IS NULL
        BEGIN
            SELECT 'KO' AS OK
            SELECT 'APLIS no encontrado' AS ERROR
            RETURN
        END

        -- Obtener IDARTICULO del servicio
        SELECT @IDARTICULO_SOLICITUD = IDARTICULO
        FROM SER
        WHERE IDSERVICIO = @IDSERVICIO_SOLICITUD

        IF @IDARTICULO_SOLICITUD IS NULL
        BEGIN
            SELECT 'KO' AS OK
            SELECT 'El servicio no tiene art�culo asociado' AS ERROR
            RETURN
        END

        -- Verificar existencia actual
        SELECT @EXISTENCIA_ACTUAL = COALESCE(SUM(EXISLOTE), 0)
        FROM IEXI
        WHERE IDARTICULO = @IDARTICULO_SOLICITUD
          AND IDBODEGA = @IDBODEGA_SOLICITUD

        -- Solo crear solicitud si no hay existencias o es menor que la cantidad requerida
        IF @EXISTENCIA_ACTUAL < @CANTIDAD_SOLICITUD
        BEGIN
            -- Verificar si ya existe una solicitud pendiente para este APLIS
            IF NOT EXISTS (
                SELECT 1 
                FROM IEXIF WITH (UPDLOCK, HOLDLOCK)
                WHERE IDAPLIS = @ID_APLIS_SOLICITUD 
                  AND ESTADO IN (SELECT ESTADO FROM @ESTADOS_COMPRA_ACTIVOS_SOL)
            )
            BEGIN
                -- Insertar solicitud de existencias faltantes
                INSERT INTO IEXIF (IDAPLIS, CANTIDAD, FRECUENCIA, TIPOFRECUENCIA, DURACION, TIPODURACION, FECHAINI, ESTADO, IDBODEGA, ESDECUSTODIA)
                SELECT @ID_APLIS_SOLICITUD, @CANTIDAD_SOLICITUD, 1, 'D', 1, 'D', GETDATE(), 'PENDIENTE COMPRA', @IDBODEGA_SOLICITUD, 0

                SELECT 'OK' AS OK
                SELECT 'Solicitud de existencias faltantes creada correctamente' AS MENSAJE
                SELECT @ID_APLIS_SOLICITUD AS IDAPLIS, @EXISTENCIA_ACTUAL AS EXISTENCIA_ACTUAL, @CANTIDAD_SOLICITUD AS CANTIDAD_REQUERIDA
            END
            ELSE
            BEGIN
                SELECT 'OK' AS OK
                SELECT 'Ya existe una solicitud de compra activa para este seguimiento' AS MENSAJE
            END
        END
        ELSE
        BEGIN
            SELECT 'OK' AS OK
            SELECT 'Hay existencias suficientes, no se requiere solicitud' AS MENSAJE
            SELECT @EXISTENCIA_ACTUAL AS EXISTENCIA_ACTUAL, @CANTIDAD_SOLICITUD AS CANTIDAD_REQUERIDA
        END

        RETURN
    END

