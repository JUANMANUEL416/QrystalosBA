CREATE OR ALTER PROCEDURE DBO.SPQ_APLIS
   @JSON  NVARCHAR(MAX)
WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX),  @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20), @SYS_COMPUTERNAME VARCHAR(254),
  @SEDE VARCHAR(5), @A INT

BEGIN
    SET NOCOUNT ON
    SET LANGUAGE Spanish
    SET DATEFORMAT dmy

    SELECT @A = ISJSON(@JSON)
    IF @A = 0
    BEGIN
      RAISERROR('Json: Formato Erroneo',16,1)
      RETURN
    END
    PRINT 'INGRESE A SPQ_APLIS'
    SELECT *
    INTO #JSON
    FROM OPENJSON (@json)
    WITH (
      MODELO         VARCHAR(100)     '$.MODELO',
      METODO         VARCHAR(100)     '$.METODO',
      USUARIO        VARCHAR(12)      '$.USUARIO',
      PARAMETROS     NVARCHAR(MAX)     AS JSON
    )

    SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS , @USUARIO = USUARIO
    FROM #JSON
    --DEFINICION DE TABLA DE ERRORES
    DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200))
    -- TOMA DEL GRUPO, SYS_COMPUTERNAME, SEDE   DE ACUERDO AL USUARIO
    PRINT 'USUARIO:'+@USUARIO
    --SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO) FROM USUSU WHERE USUARIO = @USUARIO
    SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
    SELECT @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
    IF COALESCE(@SEDE,'') = '' SELECT @SEDE = '01'
    PRINT 'SEDE='+@SEDE

    DECLARE @HOY DATE = CONVERT(DATE, GETDATE())

    -- ============================================
    -- METODO: CONSULTAR_POR_PACIENTE
    -- Obtiene APLIS de un paciente especifico
    -- ============================================
    IF @METODO = 'CONSULTAR_POR_PACIENTE'
    BEGIN
        DECLARE @IDAFILIADO_PAC VARCHAR(20)
        SELECT @IDAFILIADO_PAC = JSON_VALUE(@PARAMETROS, '$.IDAFILIADO')

        SELECT A.ID, A.IDAUTE, A.PERIODO, A.PERIODO_ACTUAL, A.PERIODO_TOTAL, A.FECHA_PREVISTA, A.ESTADO, A.VENDRA_RECOGER, A.OBSERVACION, SER.DESCSERVICIO,
            DATEDIFF(DAY, @HOY, A.FECHA_PREVISTA) AS DIAS_PARA_ENTREGA
        FROM APLIS A
        LEFT JOIN SER ON A.IDSERVICIO = SER.IDSERVICIO
        WHERE A.IDAFILIADO = @IDAFILIADO_PAC
        ORDER BY A.FECHA_PREVISTA DESC

        SELECT 'OK' AS OK
        RETURN
    END

    -- ============================================
    -- METODO: OBTENER_DETALLE
    -- Obtiene detalle completo de un APLIS
    -- ============================================
    IF @METODO = 'OBTENER_DETALLE'
    BEGIN
        DECLARE @ID_DETALLE INT
        SELECT @ID_DETALLE = JSON_VALUE(@PARAMETROS, '$.ID')

        -- Datos principales
        SELECT A.*, AFI.DOCIDAFILIADO, AFI.NOMBREAFI, AFI.CELULAR, AFI.EMAIL, AFI.TELEFONORES, AFI.DIRECCION, SER.DESCSERVICIO, SED.DESCRIPCION AS NOMBRESEDE,
            TER.RAZONSOCIAL AS NOMBRETERCERO, PLN.DESCPLAN AS NOMBREPLAN, DATEDIFF(DAY, @HOY, A.FECHA_PREVISTA) AS DIAS_PARA_ENTREGA
        FROM APLIS A
        INNER JOIN AFI ON A.IDAFILIADO = AFI.IDAFILIADO
        LEFT JOIN SER ON A.IDSERVICIO = SER.IDSERVICIO
        LEFT JOIN SED ON A.IDSEDE = SED.IDSEDE
        LEFT JOIN TER ON A.IDTERCERO = TER.IDTERCERO
        LEFT JOIN PLN ON A.IDPLAN = PLN.IDPLAN
        WHERE A.ID = @ID_DETALLE

        -- Historial de gestiones
        SELECT G.ID, G.FECHA, G.PROCEDENCIA, G.EVENTO, G.DETALLES, G.OBSERVACION, G.USUARIO, USUSU.NOMBRE AS NOMBRE_USUARIO, G.ESTADO_ANTERIOR, G.ESTADO_NUEVO,
            G.FECHAPROXLLAMADA, G.RESULTADO_CONTACTO, G.DURACION_LLAMADA
        FROM APLISG G
        LEFT JOIN USUSU ON G.USUARIO = USUSU.USUARIO
        WHERE G.IDAPLIS = @ID_DETALLE
        ORDER BY G.FECHA DESC

        SELECT 'OK' AS OK
        RETURN
    END

    -- ============================================
    -- METODO: REGISTRAR_GESTION
    -- Registra una gestion (llamada, nota, etc.)
    -- ============================================
    IF @METODO = 'REGISTRAR_GESTION'
    BEGIN
        DECLARE @ID_GESTION INT
        DECLARE @EVENTO VARCHAR(50)
        DECLARE @OBSERVACION_GESTION VARCHAR(500)
        DECLARE @RESULTADO_CONTACTO VARCHAR(50)
        DECLARE @DURACION_LLAMADA INT
        DECLARE @FECHA_ASISTENCIA DATETIME
        DECLARE @FECHAPROXLLAMADA DATETIME
        DECLARE @ESTADO_NUEVO_GESTION VARCHAR(30)
        DECLARE @VENDRA_RECOGER_GESTION BIT
        DECLARE @VENDRA_RECOGER_ACTUAL BIT
        DECLARE @IDAFILIADO_GESTION VARCHAR(20)
        DECLARE @MOTIVO_REPROGRAMACION VARCHAR(50)
        DECLARE @PRIORITARIO_GESTION BIT
        DECLARE @MOTIVO_PRIORIDAD_GESTION VARCHAR(20)

        SELECT
            @ID_GESTION = JSON_VALUE(@PARAMETROS, '$.ID'),
            @EVENTO = JSON_VALUE(@PARAMETROS, '$.EVENTO'),
            @OBSERVACION_GESTION = JSON_VALUE(@PARAMETROS, '$.OBSERVACION'),
            @RESULTADO_CONTACTO = JSON_VALUE(@PARAMETROS, '$.RESULTADO_CONTACTO'),
            @DURACION_LLAMADA = JSON_VALUE(@PARAMETROS, '$.DURACION_LLAMADA'),
            @FECHA_ASISTENCIA = CASE
                WHEN JSON_VALUE(@PARAMETROS, '$.FECHAASISTENCIA') IS NOT NULL AND JSON_VALUE(@PARAMETROS, '$.FECHAASISTENCIA') != ''
                THEN TRY_CONVERT(DATETIME, REPLACE(JSON_VALUE(@PARAMETROS, '$.FECHAASISTENCIA'), 'T', ' '), 120)
                ELSE NULL
            END,
            @FECHAPROXLLAMADA = CASE 
                WHEN JSON_VALUE(@PARAMETROS, '$.FECHAPROXLLAMADA') IS NOT NULL AND JSON_VALUE(@PARAMETROS, '$.FECHAPROXLLAMADA') != ''
                THEN TRY_CONVERT(DATETIME, REPLACE(JSON_VALUE(@PARAMETROS, '$.FECHAPROXLLAMADA'), 'T', ' '), 120)
                ELSE NULL
            END,
            @ESTADO_NUEVO_GESTION = JSON_VALUE(@PARAMETROS, '$.ESTADO'),
            @VENDRA_RECOGER_GESTION = JSON_VALUE(@PARAMETROS, '$.VENDRA_RECOGER'),
            @MOTIVO_REPROGRAMACION = JSON_VALUE(@PARAMETROS, '$.MOTIVO_REPROGRAMACION.CODIGO'),
            @PRIORITARIO_GESTION = CASE WHEN COALESCE(JSON_VALUE(@PARAMETROS, '$.PRIORITARIO'), '0') IN ('1', 'true') THEN 1 ELSE 0 END,
            @MOTIVO_PRIORIDAD_GESTION = COALESCE(JSON_VALUE(@PARAMETROS, '$.MOTIVO_PRIORIDAD.CODIGO'), JSON_VALUE(@PARAMETROS, '$.MOTIVO_PRIORIDAD'))

        -- Estado obligatorio: ya no se admite SIN_CAMBIO; observaci�n obligatoria en todo registro de gesti�n
        IF @ESTADO_NUEVO_GESTION IS NULL
            OR @ESTADO_NUEVO_GESTION NOT IN ('REPROGRAMADO', 'CONFIRMADO', 'NO_ASISTIO', 'SUSPENDIDO/RETIRADO')
        BEGIN
            SELECT 'KO' AS OK
            SELECT 'Debe seleccionar un estado v�lido (reprogramado, confirmado, no asisti� o suspendido/retirado).' AS ERROR
            RETURN
        END

        IF @OBSERVACION_GESTION IS NULL OR LTRIM(RTRIM(@OBSERVACION_GESTION)) = ''
        BEGIN
            SELECT 'KO' AS OK
            SELECT 'La observaci�n es obligatoria para registrar la gesti�n.' AS ERROR
            RETURN
        END

        SELECT
            @IDAFILIADO_GESTION = IDAFILIADO,
            @VENDRA_RECOGER_ACTUAL = ISNULL(VENDRA_RECOGER, 0)
        FROM APLIS
        WHERE ID = @ID_GESTION

        -- Validar campos obligatorios seg�n estado
        -- REPROGRAMADO:
        --   * Si YA estaba confirmado (VENDRA_RECOGER = 1): requiere FECHA_ASISTENCIA
        --   * Si NO estaba confirmado: requiere FECHAPROXLLAMADA (seguimiento)
        -- CONFIRMADO: requiere FECHA_ASISTENCIA
        -- NO_ASISTIO: requiere FECHAPROXLLAMADA para seguimiento
        IF @ESTADO_NUEVO_GESTION = 'REPROGRAMADO'
        BEGIN
            IF @MOTIVO_REPROGRAMACION IS NULL OR @MOTIVO_REPROGRAMACION = ''
            BEGIN
                SELECT 'KO' AS OK
                SELECT 'El motivo de reprogramaci�n es obligatorio' AS ERROR
                RETURN
            END

            IF ISNULL(@VENDRA_RECOGER_ACTUAL, 0) = 1 AND @FECHA_ASISTENCIA IS NULL
            BEGIN
                SELECT 'KO' AS OK
                SELECT 'La nueva fecha de asistencia es obligatoria al reprogramar un paciente confirmado' AS ERROR
                RETURN
            END

            IF ISNULL(@VENDRA_RECOGER_ACTUAL, 0) = 0 AND @FECHAPROXLLAMADA IS NULL
            BEGIN
                SELECT 'KO' AS OK
                SELECT 'La fecha de pr�xima llamada es obligatoria para seguimiento cuando se reprograma un paciente no confirmado' AS ERROR
                RETURN
            END
        END

        IF @ESTADO_NUEVO_GESTION = 'CONFIRMADO' AND @FECHA_ASISTENCIA IS NULL
        BEGIN
            SELECT 'KO' AS OK
            SELECT 'La fecha de asistencia es obligatoria cuando el paciente confirma.' AS ERROR
            RETURN
        END

        IF @ESTADO_NUEVO_GESTION = 'NO_ASISTIO' AND @FECHAPROXLLAMADA IS NULL
        BEGIN
            SELECT 'KO' AS OK
            SELECT 'La fecha de pr�xima llamada es obligatoria para seguimiento.' AS ERROR
            RETURN
        END

        -- Para CONFIRMADO/NO_ASISTIO: establecer VENDRA_RECOGER seg�n corresponda
        IF @ESTADO_NUEVO_GESTION = 'CONFIRMADO'
            SET @VENDRA_RECOGER_GESTION = 1
        IF @ESTADO_NUEVO_GESTION = 'NO_ASISTIO'
            SET @VENDRA_RECOGER_GESTION = 0

        -- Si dispensaci�n prioritaria, motivo de prioridad es obligatorio
        IF @PRIORITARIO_GESTION = 1 AND (@MOTIVO_PRIORIDAD_GESTION IS NULL OR LTRIM(RTRIM(@MOTIVO_PRIORIDAD_GESTION)) = '')
        BEGIN
            SELECT 'KO' AS OK
            SELECT 'Si la dispensaci�n es prioritaria, el motivo de prioridad es obligatorio' AS ERROR
            RETURN
        END

        -- CONFIRMADO y SUSPENDIDO/RETIRADO: exigir al menos un documento de validaci�n de derechos (DOCXTPO, tipo APLIS)
        IF @ESTADO_NUEVO_GESTION IN ('CONFIRMADO', 'SUSPENDIDO/RETIRADO')
        BEGIN
            IF NOT EXISTS (SELECT 1 FROM DOCXTPO WHERE NODOCUMENTO = @ID_GESTION AND IDAFILIADO = @IDAFILIADO_GESTION AND TIPO = 'APLIS')
            BEGIN
                SELECT 'KO' AS OK
                SELECT 'Debe adjuntar al menos un documento de validaci�n de derechos para este seguimiento antes de guardar.' AS ERROR
                RETURN
            END
        END

        -- Obtener estado anterior
        DECLARE @ESTADO_ANTERIOR_GESTION VARCHAR(30)
        SELECT @ESTADO_ANTERIOR_GESTION = ESTADO
        FROM APLIS WHERE ID = @ID_GESTION

        -- No permitir sobrescribir estados finales: CONFIRMADO, NO_ASISTIO, SUSPENDIDO/RETIRADO
        -- REPROGRAMADO s� puede aplicarse m�ltiples veces
        IF @ESTADO_NUEVO_GESTION = 'CONFIRMADO' AND ISNULL(@VENDRA_RECOGER_ACTUAL, 0) = 1
        BEGIN
            SELECT 'KO' AS OK
            SELECT 'El paciente ya est� confirmado.' AS ERROR
            RETURN
        END

        IF @ESTADO_NUEVO_GESTION = 'NO_ASISTIO' AND @ESTADO_ANTERIOR_GESTION = 'NO_ASISTIO'
        BEGIN
            SELECT 'KO' AS OK
            SELECT 'El paciente ya tiene registrado que no asistir�.' AS ERROR
            RETURN
        END

        IF @ESTADO_NUEVO_GESTION = 'SUSPENDIDO/RETIRADO' AND @ESTADO_ANTERIOR_GESTION = 'SUSPENDIDO/RETIRADO'
        BEGIN
            SELECT 'KO' AS OK
            SELECT 'El seguimiento ya est� registrado como suspendido/retirado.' AS ERROR
            RETURN
        END

        -- Mapear estado para actualizaci�n: CONFIRMADO -> GESTIONADO, NO_ASISTIO se mantiene; resto seg�n estado elegido
        DECLARE @ESTADO_ACTUALIZAR VARCHAR(30) = CASE
            WHEN @ESTADO_NUEVO_GESTION = 'CONFIRMADO' THEN 'GESTIONADO'
            WHEN @ESTADO_NUEVO_GESTION = 'NO_ASISTIO' THEN 'NO_ASISTIO'
            ELSE COALESCE(@ESTADO_NUEVO_GESTION, @ESTADO_ANTERIOR_GESTION)
        END

        -- Evento para historial: CONFIRMADO/NO_ASISTIO usan eventos espec�ficos
        DECLARE @EVENTO_LOG VARCHAR(50) = CASE
            WHEN @ESTADO_NUEVO_GESTION = 'CONFIRMADO' THEN 'CONFIRMACION_ASISTENCIA'
            WHEN @ESTADO_NUEVO_GESTION = 'NO_ASISTIO' THEN 'CONFIRMACION_NO_ASISTE'
            ELSE @EVENTO
        END

        -- Insertar registro de gestion
        INSERT INTO APLISG (IDAPLIS, FECHA, PROCEDENCIA, EVENTO, DETALLES, OBSERVACION, USUARIO, ESTADO_ANTERIOR, ESTADO_NUEVO, FECHAPROXLLAMADA,
            RESULTADO_CONTACTO, DURACION_LLAMADA, MOTIVO_REPROGRAMACION)
        SELECT @ID_GESTION, GETDATE(), 'WEB', @EVENTO_LOG,
            CASE
                WHEN @ESTADO_NUEVO_GESTION = 'CONFIRMADO' AND @FECHA_ASISTENCIA IS NOT NULL
                    THEN CONCAT('Fecha de asistencia: ', CONVERT(VARCHAR(10), @FECHA_ASISTENCIA, 23))
                WHEN @ESTADO_NUEVO_GESTION = 'REPROGRAMADO' AND ISNULL(@VENDRA_RECOGER_ACTUAL, 0) = 1 AND @FECHA_ASISTENCIA IS NOT NULL
                    THEN CONCAT('Reprogramaci�n - nueva fecha de asistencia: ', CONVERT(VARCHAR(10), @FECHA_ASISTENCIA, 23))
                WHEN @ESTADO_NUEVO_GESTION = 'REPROGRAMADO' AND ISNULL(@VENDRA_RECOGER_ACTUAL, 0) = 0 AND @FECHAPROXLLAMADA IS NOT NULL
                    THEN CONCAT('Reprogramaci�n de seguimiento - pr�xima llamada: ', CONVERT(VARCHAR(10), @FECHAPROXLLAMADA, 23))
                WHEN @ESTADO_NUEVO_GESTION = 'NO_ASISTIO' AND @FECHAPROXLLAMADA IS NOT NULL
                    THEN CONCAT('Pr�xima llamada: ', CONVERT(VARCHAR(10), @FECHAPROXLLAMADA, 23))
                ELSE NULL
            END,
            @OBSERVACION_GESTION, @USUARIO, @ESTADO_ANTERIOR_GESTION, @ESTADO_ACTUALIZAR,
            CASE WHEN @ESTADO_NUEVO_GESTION = 'SUSPENDIDO/RETIRADO' THEN NULL ELSE @FECHAPROXLLAMADA END,
            @RESULTADO_CONTACTO, @DURACION_LLAMADA, @MOTIVO_REPROGRAMACION

        -- Actualizar APLIS
        UPDATE APLIS
        SET ESTADO = @ESTADO_ACTUALIZAR,
            VENDRA_RECOGER = COALESCE(@VENDRA_RECOGER_GESTION, VENDRA_RECOGER),
            FECHA_GESTION = GETDATE(),
            USUARIO_GESTION = @USUARIO,
            OBSERVACION = @OBSERVACION_GESTION,
            MEDIO_CONTACTO = CASE WHEN @EVENTO LIKE 'LLAMADA%' THEN 'LLAMADA'
                                  WHEN @EVENTO LIKE 'SMS%' THEN 'SMS'
                                  WHEN @EVENTO LIKE 'WHATSAPP%' THEN 'WHATSAPP'
                                  WHEN @EVENTO LIKE 'EMAIL%' THEN 'EMAIL'
                                  ELSE MEDIO_CONTACTO END,
            FECHA_ASISTENCIA = CASE
                                  WHEN @ESTADO_NUEVO_GESTION = 'CONFIRMADO' AND @FECHA_ASISTENCIA IS NOT NULL
                                      THEN @FECHA_ASISTENCIA
                                  WHEN @ESTADO_NUEVO_GESTION = 'REPROGRAMADO' AND ISNULL(@VENDRA_RECOGER_ACTUAL, 0) = 1 AND @FECHA_ASISTENCIA IS NOT NULL
                                      THEN @FECHA_ASISTENCIA
                                  ELSE FECHA_ASISTENCIA
                               END,
            PRIORITARIO = @PRIORITARIO_GESTION,
            MOTIVO_PRIORIDAD = CASE WHEN @PRIORITARIO_GESTION = 1 THEN @MOTIVO_PRIORIDAD_GESTION ELSE NULL END,
            FECHAPROXLLAMADA = CASE
                                  WHEN @ESTADO_NUEVO_GESTION = 'SUSPENDIDO/RETIRADO' THEN NULL
                                  WHEN @ESTADO_NUEVO_GESTION = 'CONFIRMADO' THEN @FECHA_ASISTENCIA
                                  WHEN @ESTADO_NUEVO_GESTION = 'REPROGRAMADO' AND ISNULL(@VENDRA_RECOGER_ACTUAL, 0) = 1 THEN FECHAPROXLLAMADA
                                  WHEN @ESTADO_NUEVO_GESTION = 'REPROGRAMADO' AND ISNULL(@VENDRA_RECOGER_ACTUAL, 0) = 0 THEN @FECHAPROXLLAMADA
                                  ELSE @FECHAPROXLLAMADA
                               END,
            MOTIVO_REPROGRAMACION = CASE WHEN @ESTADO_NUEVO_GESTION = 'REPROGRAMADO' THEN @MOTIVO_REPROGRAMACION ELSE MOTIVO_REPROGRAMACION END
        WHERE ID = @ID_GESTION

        SELECT 'OK' AS OK
        SELECT 'Gestion registrada correctamente' AS MENSAJE
        RETURN
    END

    -- ============================================
    -- METODO: CAMBIAR_ESTADO
    -- Cambia el estado de un APLIS
    -- ============================================
    IF @METODO = 'CAMBIAR_ESTADO'
    BEGIN
        DECLARE @ID_CAMBIO INT
        DECLARE @NUEVO_ESTADO VARCHAR(30)
        DECLARE @OBSERVACION_CAMBIO VARCHAR(500)
        DECLARE @IDCAUSAL VARCHAR(5)

        SELECT
            @ID_CAMBIO = JSON_VALUE(@PARAMETROS, '$.ID'),
            @NUEVO_ESTADO = JSON_VALUE(@PARAMETROS, '$.ESTADO'),
            @OBSERVACION_CAMBIO = JSON_VALUE(@PARAMETROS, '$.OBSERVACION'),
            @IDCAUSAL = JSON_VALUE(@PARAMETROS, '$.IDCAUSAL')

        -- Obtener estado anterior
        DECLARE @ESTADO_ANT VARCHAR(30)
        SELECT @ESTADO_ANT = ESTADO FROM APLIS WHERE ID = @ID_CAMBIO

        -- Actualizar estado
        UPDATE APLIS
        SET ESTADO = @NUEVO_ESTADO,
            FECHA_GESTION = GETDATE(),
            USUARIO_GESTION = @USUARIO,
            OBSERVACION = COALESCE(@OBSERVACION_CAMBIO, OBSERVACION)
        WHERE ID = @ID_CAMBIO

        -- Registrar en log
        INSERT INTO APLISG (IDAPLIS, FECHA, PROCEDENCIA, EVENTO, OBSERVACION, USUARIO, ESTADO_ANTERIOR, ESTADO_NUEVO, IDCAUSAL)
        SELECT @ID_CAMBIO, GETDATE(), 'WEB', 'CAMBIO_ESTADO', @OBSERVACION_CAMBIO, @USUARIO, @ESTADO_ANT, @NUEVO_ESTADO, @IDCAUSAL

        SELECT 'OK' AS OK
        SELECT 'Estado actualizado correctamente' AS MENSAJE
        RETURN
    END

    -- ============================================
    -- METODO: CONFIRMAR_ASISTENCIA
    -- Registra confirmacion de que el paciente vendra
    -- ============================================
    IF @METODO = 'CONFIRMAR_ASISTENCIA'
    BEGIN
        DECLARE @ID_CONF INT
        DECLARE @VENDRA BIT
        DECLARE @OBS_CONF VARCHAR(500)

        SELECT
            @ID_CONF = JSON_VALUE(@PARAMETROS, '$.ID'),
            @VENDRA = JSON_VALUE(@PARAMETROS, '$.VENDRA_RECOGER'),
            @OBS_CONF = JSON_VALUE(@PARAMETROS, '$.OBSERVACION')

        -- Actualizar APLIS
        UPDATE APLIS
        SET VENDRA_RECOGER = @VENDRA,
            ESTADO = CASE WHEN @VENDRA = 1 THEN 'GESTIONADO' ELSE ESTADO END,
            FECHA_GESTION = GETDATE(),
            USUARIO_GESTION = @USUARIO,
            OBSERVACION = COALESCE(@OBS_CONF, OBSERVACION)
        WHERE ID = @ID_CONF

        -- Registrar en log
        INSERT INTO APLISG (IDAPLIS, FECHA, PROCEDENCIA, EVENTO, OBSERVACION, USUARIO, ESTADO_NUEVO)
        SELECT @ID_CONF, GETDATE(), 'WEB',
            CASE WHEN @VENDRA = 1 THEN 'CONFIRMACION_ASISTENCIA' ELSE 'CONFIRMACION_NO_ASISTE' END,
            @OBS_CONF, @USUARIO, CASE WHEN @VENDRA = 1 THEN 'GESTIONADO' ELSE NULL END

        SELECT 'OK' AS OK
        SELECT CASE WHEN @VENDRA = 1 THEN 'Asistencia confirmada' ELSE 'No asistencia registrada' END AS MENSAJE
        RETURN
    END

    -- ============================================
    -- METODO: OBTENER_ESTADISTICAS
    -- Estadisticas del modulo APLIS
    -- ============================================
    IF @METODO = 'OBTENER_ESTADISTICAS'
    BEGIN
        DECLARE @FECHA_DESDE DATE
        DECLARE @FECHA_HASTA DATE
        DECLARE @IDSEDE_STATS VARCHAR(5)

        SELECT
            @FECHA_DESDE = COALESCE(JSON_VALUE(@PARAMETROS, '$.FECHA_DESDE'), DATEADD(DAY, -30, @HOY)),
            @FECHA_HASTA = COALESCE(JSON_VALUE(@PARAMETROS, '$.FECHA_HASTA'), @HOY),
            @IDSEDE_STATS = JSON_VALUE(@PARAMETROS, '$.IDSEDE')

        -- Resumen por estado
        SELECT
            A.ESTADO,
            COUNT(*) AS CANTIDAD,
            COUNT(CASE WHEN A.VENDRA_RECOGER = 1 THEN 1 END) AS CONFIRMADOS
        FROM APLIS A
        WHERE A.FECHA_PREVISTA BETWEEN @FECHA_DESDE AND @FECHA_HASTA
          AND (@IDSEDE_STATS IS NULL OR A.IDSEDE = @IDSEDE_STATS)
        GROUP BY A.ESTADO

        -- Entregas vencidas pendientes
        SELECT
            COUNT(*) AS VENCIDOS_PENDIENTES
        FROM APLIS A
        WHERE A.FECHA_PREVISTA < @HOY
          AND A.ESTADO IN ('PENDIENTE', 'GESTIONADO')
          AND (@IDSEDE_STATS IS NULL OR A.IDSEDE = @IDSEDE_STATS)

        -- Proximas entregas (proximos 7 dias)
        SELECT
            COUNT(*) AS PROXIMAS_7_DIAS
        FROM APLIS A
        WHERE A.FECHA_PREVISTA BETWEEN @HOY AND DATEADD(DAY, 7, @HOY)
          AND A.ESTADO IN ('PENDIENTE', 'GESTIONADO')
          AND (@IDSEDE_STATS IS NULL OR A.IDSEDE = @IDSEDE_STATS)

        SELECT 'OK' AS OK
        RETURN
    END

    -- ============================================
    -- METODO: OBTENER_DISPENSACIONES_ANTERIORES
    -- Dispensaciones de per�odos anteriores al actual para un paciente+servicio
    -- ============================================
    IF @METODO = 'OBTENER_DISPENSACIONES_ANTERIORES'
    BEGIN
        DECLARE @ID_DISP INT
        SELECT @ID_DISP = JSON_VALUE(@PARAMETROS, '$.ID')

        DECLARE @IDAFILIADO_DISP VARCHAR(20), @IDSERVICIO_DISP VARCHAR(20), @IDAUTE_ACTUAL INT, @CONSECUTIVOHCA_DISP VARCHAR(20)
        SELECT @IDAFILIADO_DISP = IDAFILIADO, @IDSERVICIO_DISP = IDSERVICIO, @IDAUTE_ACTUAL = IDAUTE,
            @CONSECUTIVOHCA_DISP = CONSECUTIVOHCA
        FROM APLIS WHERE ID = @ID_DISP

        SELECT 'OK' AS OK

        -- Recordset 2: Dispensaciones anteriores (AUTEs anteriores al actual, misma atenci�n)
        SELECT AUTE.IDAUTE, AUTE.PERIODO,AUTE.ESTADO AS ESTADO_AUTE, AUTE.CNSIZSOL,
            A.ID AS IDAPLIS, A.FECHA_PREVISTA, A.FECHA_APLICACION, A.ESTADO AS ESTADO_APLIS,
            A.OBSERVACION AS OBSERVACION_APLIS,
            IEXIF_D.IDIEXIF_APLIS, IEXIF_D.ESTADO_COMPRA_IEXIF, IEXIF_D.CNSFCOM AS CNSFCOM_COMPRA,
            IZSOLD_D.CANTIDADSOL, IZSOLD_D.CANTIDAD_DISPENSADA, IZSOLD_D.CANTIDAD_PENDIENTE,
            IZSOL_D.CNSIZSOL AS CNSIZSOL_SOL, IZSOL_D.FECHASOL, IZSOL_D.ESTADO_SOL, USUSU_SOL.NOMBRE AS USUARIO_SOL,
            @IDSERVICIO_DISP AS IDSERVICIO, SER.DESCSERVICIO,
            IMOV_D.CNSMOV, IMOV_D.FECHAMOV AS FECHA_DESPACHO, IMOV_D.ESTADO AS ESTADO_MOV, USUSU_MOV.NOMBRE AS USUARIO_MOV,
            IMOVH_D.IDARTICULO, IMOVH_D.DESC_ARTICULO, IMOVH_D.ESTADO_ARTICULO, IMOVH_D.CANTIDAD AS CANTIDAD_DESPACHADA,
            IMOVH_D.NOLOTE, IMOVH_D.NOLOTEPEDIDO, IMOVH_D.FECHAVENCE
        FROM AUTE WITH (NOLOCK)
        LEFT JOIN SER WITH (NOLOCK) ON SER.IDSERVICIO = @IDSERVICIO_DISP
        LEFT JOIN APLIS A ON A.IDAUTE = AUTE.IDAUTE
            AND A.IDAFILIADO = @IDAFILIADO_DISP AND A.IDSERVICIO = @IDSERVICIO_DISP
        OUTER APPLY (
            SELECT TOP 1 IEXIF.ID AS IDIEXIF_APLIS, IEXIF.ESTADO AS ESTADO_COMPRA_IEXIF, IEXIF.CNSFCOM
            FROM IEXIF WITH (NOLOCK)
            WHERE IEXIF.IDAPLIS = A.ID
              AND COALESCE(IEXIF.ESTADO, '') <> 'ANULADO'
            ORDER BY IEXIF.ID DESC
        ) IEXIF_D
        OUTER APPLY (
            SELECT TOP 1 IZSOLD.CANTIDADSOL, IZSOLD.CANTIDAD_DISPENSADA, IZSOLD.CANTIDAD_PENDIENTE
            FROM IZSOLD WITH (NOLOCK)
            WHERE IZSOLD.CNSIZSOL = AUTE.CNSIZSOL AND IZSOLD.IDSERVICIO = @IDSERVICIO_DISP
        ) IZSOLD_D
        OUTER APPLY (
            SELECT TOP 1 IZSOL.CNSIZSOL, IZSOL.FECHASOL, IZSOL.USUARIOSOL,
                CASE COALESCE(IZSOL.ESTADO,0) WHEN 0 THEN 'Sin Solicitar' WHEN 1 THEN 'Abierta' WHEN 2 THEN 'Cerrada' ELSE '' END AS ESTADO_SOL
            FROM IZSOL WITH (NOLOCK)
            WHERE IZSOL.CNSIZSOL = AUTE.CNSIZSOL
        ) IZSOL_D
        LEFT JOIN USUSU USUSU_SOL ON USUSU_SOL.USUARIO = IZSOL_D.USUARIOSOL
        OUTER APPLY (
            SELECT TOP 1 IMOV.CNSMOV, IMOV.FECHAMOV, IMOV.USUARIO,
                CASE COALESCE(IMOV.ESTADO,0) WHEN 0 THEN 'Pendiente' WHEN 1 THEN 'Confirmado' WHEN 2 THEN 'Anulado' ELSE '' END AS ESTADO
            FROM IMOV WITH (NOLOCK)
            WHERE IMOV.NODOCUMENTO = AUTE.CNSIZSOL --AND IMOV.ESTADO = 1
            ORDER BY IMOV.FECHAMOV DESC
        ) IMOV_D
        LEFT JOIN USUSU USUSU_MOV ON USUSU_MOV.USUARIO = IMOV_D.USUARIO
        OUTER APPLY (
            SELECT TOP 1 IMOVH.IDARTICULO, IMOVH.CANTIDAD, IMOVH.NOLOTE, IMOVH.NOLOTEPEDIDO, IMOVH.FECHAVENCE,
                IART.DESCRIPCION AS DESC_ARTICULO,
                CASE COALESCE(IMOVH.ESTADO,0) WHEN 2 THEN 'Inactivo' WHEN 1 THEN 'Confirmado' ELSE 'Pendiente' END AS ESTADO_ARTICULO
            FROM IMOVH WITH (NOLOCK)
            LEFT JOIN IART WITH (NOLOCK) ON IART.IDARTICULO = IMOVH.IDARTICULO
            WHERE IMOVH.CNSMOV = IMOV_D.CNSMOV AND (IMOVH.IDSERVICIO = @IDSERVICIO_DISP OR IMOVH.IDARTICULO = @IDSERVICIO_DISP)  --AND IMOVH.ESTADO = 1
        ) IMOVH_D
        WHERE AUTE.IDAFILIADO = @IDAFILIADO_DISP
          AND AUTE.CONSECUTIVOHCA = @CONSECUTIVOHCA_DISP
          AND AUTE.IDAUTE < @IDAUTE_ACTUAL
        ORDER BY AUTE.FECHA DESC

        -- Recordset 3: Historial de gestiones del APLIS actual
        SELECT G.ID, G.FECHA, G.PROCEDENCIA, G.EVENTO, G.DETALLES, G.OBSERVACION, G.USUARIO, USUSU.NOMBRE AS NOMBRE_USUARIO, G.ESTADO_ANTERIOR,
            G.ESTADO_NUEVO, G.FECHAPROXLLAMADA, G.RESULTADO_CONTACTO, G.DURACION_LLAMADA, G.IDCAUSAL, G.MOTIVO_REPROGRAMACION,
            TGEN.DESCRIPCION AS DESC_MOTIVO_REPROG
        FROM APLISG G
        LEFT JOIN USUSU ON G.USUARIO = USUSU.USUARIO
        LEFT JOIN TGEN ON TGEN.TABLA = 'APLIS' AND TGEN.CAMPO = 'MOTIVO_REPROG' AND TGEN.CODIGO = G.MOTIVO_REPROGRAMACION
        WHERE G.IDAPLIS = @ID_DISP
        ORDER BY G.FECHA DESC

        RETURN
    END

