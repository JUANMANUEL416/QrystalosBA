    -- ============================================
    -- METODO: PROCESAR_EXISTENCIAS_FALTANTES
    -- Procesa autom�ticamente todos los APLIS sin existencias y crea solicitudes
    -- ============================================
    IF @METODO = 'PROCESAR_EXISTENCIAS_FALTANTES'
    BEGIN
        DECLARE @CONTADOR_CREADOS INT = 0
        DECLARE @CONTADOR_YA_EXISTENTES INT = 0
        DECLARE @CONTADOR_CON_EXISTENCIAS INT = 0
        DECLARE @ESTADOS_COMPRA_ACTIVOS TABLE(ESTADO VARCHAR(30))
        INSERT INTO @ESTADOS_COMPRA_ACTIVOS(ESTADO)
        VALUES ('PENDIENTE COMPRA'), ('PENDIENTE GESTION'), ('EN RUTA'), ('RECEPCIONADO')

        -- Procesar todos los APLIS pendientes o gestionados que no tengan existencias suficientes
        DECLARE curAPLIS CURSOR FOR
        SELECT 
            A.ID,
            A.CANTIDAD,
            A.IDSERVICIO,
            A.FECHA_PREVISTA,
            SED.IDBODEGALOG,
            SER.IDARTICULO,
            COALESCE(EXIS.EXISLOTE, 0) AS EXISTENCIA_ACTUAL
        FROM APLIS A
        INNER JOIN SER ON A.IDSERVICIO = SER.IDSERVICIO
        LEFT JOIN SED ON A.IDSEDE = SED.IDSEDE
        LEFT JOIN (
            SELECT IDARTICULO, IDBODEGA, SUM(EXISLOTE) AS EXISLOTE
            FROM IEXI
            GROUP BY IDARTICULO, IDBODEGA
        ) EXIS ON SER.IDARTICULO = EXIS.IDARTICULO 
               AND EXIS.IDBODEGA = SED.IDBODEGALOG
        WHERE A.ESTADO IN ('PENDIENTE', 'GESTIONADO')
          AND SER.IDARTICULO IS NOT NULL
          AND SED.IDBODEGALOG IS NOT NULL
          AND COALESCE(EXIS.EXISLOTE, 0) < A.CANTIDAD
          AND NOT EXISTS (
              SELECT 1 
              FROM IEXIF 
              WHERE IDAPLIS = A.ID 
                AND ESTADO IN (SELECT ESTADO FROM @ESTADOS_COMPRA_ACTIVOS)
          )

        DECLARE @ID_APLIS_CUR INT
        DECLARE @CANTIDAD_CUR INT
        DECLARE @IDSERVICIO_CUR VARCHAR(20)
        DECLARE @FECHA_PREVISTA_CUR DATE
        DECLARE @IDBODEGA_CUR VARCHAR(20)
        DECLARE @IDARTICULO_CUR VARCHAR(20)
        DECLARE @EXISTENCIA_CUR INT

        OPEN curAPLIS
        FETCH NEXT FROM curAPLIS INTO @ID_APLIS_CUR, @CANTIDAD_CUR, @IDSERVICIO_CUR, @FECHA_PREVISTA_CUR, @IDBODEGA_CUR, @IDARTICULO_CUR, @EXISTENCIA_CUR

        WHILE @@FETCH_STATUS = 0
        BEGIN
            IF NOT EXISTS (
                SELECT 1
                FROM IEXIF WITH (UPDLOCK, HOLDLOCK)
                WHERE IDAPLIS = @ID_APLIS_CUR
                  AND ESTADO IN (SELECT ESTADO FROM @ESTADOS_COMPRA_ACTIVOS)
            )
            BEGIN
                -- Insertar solicitud de existencias faltantes
                INSERT INTO IEXIF (IDAPLIS, CANTIDAD, FRECUENCIA, TIPOFRECUENCIA, DURACION, TIPODURACION, FECHAINI, ESTADO, IDBODEGA, ESDECUSTODIA)
                SELECT @ID_APLIS_CUR, @CANTIDAD_CUR, 1, 'D', 1, 'D', GETDATE(), 'PENDIENTE COMPRA', @IDBODEGA_CUR, 0
                
                SET @CONTADOR_CREADOS = @CONTADOR_CREADOS + 1
            END

            FETCH NEXT FROM curAPLIS INTO @ID_APLIS_CUR, @CANTIDAD_CUR, @IDSERVICIO_CUR, @FECHA_PREVISTA_CUR, @IDBODEGA_CUR, @IDARTICULO_CUR, @EXISTENCIA_CUR
        END

        CLOSE curAPLIS
        DEALLOCATE curAPLIS

        -- Contar los que ya ten�an solicitud
        SELECT @CONTADOR_YA_EXISTENTES = COUNT(*)
        FROM APLIS A
        INNER JOIN SER ON A.IDSERVICIO = SER.IDSERVICIO
        LEFT JOIN SED ON A.IDSEDE = SED.IDSEDE
        LEFT JOIN (
            SELECT IDARTICULO, IDBODEGA, SUM(EXISLOTE) AS EXISLOTE
            FROM IEXI
            GROUP BY IDARTICULO, IDBODEGA
        ) EXIS ON SER.IDARTICULO = EXIS.IDARTICULO 
               AND EXIS.IDBODEGA = SED.IDBODEGALOG
        WHERE A.ESTADO IN ('PENDIENTE', 'GESTIONADO')
          AND SER.IDARTICULO IS NOT NULL
          AND SED.IDBODEGALOG IS NOT NULL
          AND COALESCE(EXIS.EXISLOTE, 0) < A.CANTIDAD
          AND EXISTS (
              SELECT 1 
              FROM IEXIF 
              WHERE IDAPLIS = A.ID 
                AND ESTADO IN (SELECT ESTADO FROM @ESTADOS_COMPRA_ACTIVOS)
          )
        SET @CONTADOR_YA_EXISTENTES = IIF(@CONTADOR_YA_EXISTENTES - @CONTADOR_CREADOS > 0, @CONTADOR_YA_EXISTENTES - @CONTADOR_CREADOS, 0)

        -- Contar los que tienen existencias suficientes
        SELECT @CONTADOR_CON_EXISTENCIAS = COUNT(*)
        FROM APLIS A
        INNER JOIN SER ON A.IDSERVICIO = SER.IDSERVICIO
        LEFT JOIN SED ON A.IDSEDE = SED.IDSEDE
        LEFT JOIN (
            SELECT IDARTICULO, IDBODEGA, SUM(EXISLOTE) AS EXISLOTE
            FROM IEXI
            GROUP BY IDARTICULO, IDBODEGA
        ) EXIS ON SER.IDARTICULO = EXIS.IDARTICULO 
               AND EXIS.IDBODEGA = SED.IDBODEGALOG
        WHERE A.ESTADO IN ('PENDIENTE', 'GESTIONADO')
          AND SER.IDARTICULO IS NOT NULL
          AND SED.IDBODEGALOG IS NOT NULL
          AND COALESCE(EXIS.EXISLOTE, 0) >= A.CANTIDAD

        SELECT 'OK' AS OK
        SELECT 
            @CONTADOR_CREADOS AS SOLICITUDES_CREADAS,
            @CONTADOR_YA_EXISTENTES AS YA_TENIAN_SOLICITUD,
            @CONTADOR_CON_EXISTENCIAS AS CON_EXISTENCIAS_SUFICIENTES,
            'Procesamiento completado' AS MENSAJE

        RETURN
    END

