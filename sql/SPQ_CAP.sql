CREATE OR ALTER PROCEDURE DBO.SPQ_CAP @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100)
DECLARE @USUARIO VARCHAR(20), @IDCAP INT, @TEMA VARCHAR(100)
DECLARE @OBJETIVO VARCHAR(MAX), @IDCAPD INT, @MODALIDAD VARCHAR(50)
DECLARE @FECHAINI DATE, @FECHAFIN DATE, @SERVICIO VARCHAR(100)
DECLARE @LUGAR VARCHAR(100), @LINK VARCHAR(255), @DIRIGIDOA VARCHAR(100)
DECLARE @RESPONSABLE VARCHAR(100), @ESEXTERNO BIT, @EVALUADA BIT
DECLARE @ESTADO VARCHAR(50), @IDCAPASI INT, @NUMDOC VARCHAR(20)
DECLARE @EMPLEADOS NVARCHAR(MAX), @PROCESO VARCHAR(20), @COPIAR_ASI BIT
DECLARE @HORAINI TIME, @HORAFIN TIME, @CNSEXCEL VARCHAR(20)
DECLARE @IDSEDE VARCHAR(5), @SYS_COMPUTERNAME VARCHAR(254), @COMPANIA VARCHAR(2)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
	FROM USUSU
	WHERE USUARIO = @USUARIO

	SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
	FROM UBEQ
	WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	IF @METODO = 'GET_SESION'
	BEGIN
		SELECT 'OK' OK

		SELECT CAPD.*, TER.RAZONSOCIAL NOM_RESPONSABLE, SUM(CAST(CAPASI.ISACTIVA AS INT)) CONVOCADOS, SUM(CAST(CAPASI.ASISTENCIA AS INT)) ASISTENTES
		FROM CAPD
		LEFT JOIN TER ON TER.IDTERCERO = CAPD.RESPONSABLE
		LEFT JOIN CAPASI ON CAPD.IDCAPD = CAPASI.IDCAPD
		WHERE IDCAP = JSON_VALUE(@PARAMETROS, '$.IDCAP')
		GROUP BY CAPD.IDCAPD, CAPD.IDCAP, CAPD.MODALIDAD, CAPD.FECHAINI, CAPD.FECHAFIN, CAPD.SERVICIO, CAPD.LUGAR, CAPD.LINK, CAPD.DIRIGIDOA, CAPD.RESPONSABLE, 
			CAPD.ESEXTERNO, CAPD.EVALUADA, CAPD.ESTADO, CAPD.FECHAREGISTRO, CAPD.HORAINI, CAPD.HORAFIN, CAPD.OBSERVACIONES, TER.RAZONSOCIAL
		ORDER BY IDCAPD DESC

		RETURN
	END

	IF @METODO = 'GET_CONVOCADOS_X_SESION'
	BEGIN
		SELECT 'OK' OK

		SELECT NEMP.NUMDOC, DOCIDEMPLEADO, CONCAT (PRIMERNOMBRE, ' ', PRIMERAPELLIDO) NOMBRE, CEN.DESCRIPCION DESC_CCOSTO, CAPASI.IDCAPASI, 
			CAPASI.ASISTENCIA
		FROM NEMP
		INNER JOIN CAPASI ON CAPASI.NUMDOC = NEMP.NUMDOC
		INNER JOIN CEN ON CEN.CCOSTO = NEMP.CCOSTO
		WHERE IDCAPD = JSON_VALUE(@PARAMETROS, '$.IDCAPD') AND ISACTIVA = 1

		RETURN
	END

	IF @METODO = 'GET_CAP_INSCRITO'
	BEGIN
		SELECT 'OK' OK

		SELECT CAP.TEMA, CAP.OBJETIVO, CAPD.*, IDCAPASI, CAPASI.ASISTENCIA, TALL.TALLERID, TALL.FECHACREACION, TALL.FECHACIERRE, TALL.NOMBRETALLER, TALL.ESTADO 
			AS ESTADOTALL, TA.ESTADO AS ESTADOEVALUACION, TALL.DESCRIPCION, TR.CALIFICACIONFINAL, TA.NUMDOC
		FROM CAPD
		INNER JOIN CAP ON CAP.IDCAP = CAPD.IDCAP
		INNER JOIN CAPASI ON CAPASI.IDCAPD = CAPD.IDCAPD
		LEFT JOIN TALL ON TALL.IDCAP = CAP.IDCAP
		LEFT JOIN TASIGNACION AS TA ON TA.TALLERID = TALL.TALLERID AND TA.NUMDOC = JSON_VALUE(@PARAMETROS, '$.IDEMPLEADO')
		LEFT JOIN TRESULTADOS AS TR ON TR.AsignacionID = TA.ASIGNACIONID
		WHERE CAPASI.NUMDOC = JSON_VALUE(@PARAMETROS, '$.IDEMPLEADO') AND CAPASI.ISACTIVA = 1

		RETURN
	END

	IF @METODO = 'GET_SOPORTES'
	BEGIN
		SELECT 'OK' OK

		SELECT DocumentoID, DocNombre, DocExtension, DocFS ARCHIVO
		FROM DOCS
		WHERE DocConsecutivo = JSON_VALUE(@PARAMETROS, '$.IDCAPD') AND DocTipo = 'SOPORTE_CAPD'

		RETURN
	END

	IF @METODO = 'ELIMINAR_SOPORTE'
	BEGIN
		BEGIN TRY
			SELECT @IDCAPD = JSON_VALUE(@PARAMETROS, '$.IDCAPD')

			IF COALESCE(@IDCAPD, '') = ''
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'DEBE ESPECIFICAR UN ID DE SESION (IDCAPD)'
			END

			IF COALESCE(JSON_VALUE(@PARAMETROS, '$.DOCID'), '') = ''
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'NO SE PROPORCIONO EL ID DEL DOCUMENTO'
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				DELETE
				FROM DOCS
				WHERE DocumentoID = JSON_VALUE(@PARAMETROS, '$.DOCID') AND DocConsecutivo = @IDCAPD AND DocTipo = 'SOPORTE_CAPD'
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK

		RETURN
	END

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @IDCAP = IDCAP, @TEMA = TEMA, @OBJETIVO = OBJETIVO, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (IDCAP INT '$.IDCAP', TEMA VARCHAR(100) '$.TEMA', OBJETIVO VARCHAR(MAX) '$.OBJETIVO', PROCESO VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'LA CAPACITACION YA EXISTE'
					WHERE EXISTS (
							SELECT 1
							FROM CAP
							WHERE IDCAP = @IDCAP
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO CAP (TEMA, OBJETIVO)
						SELECT @TEMA, @OBJETIVO
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					UPDATE CAP
					SET TEMA = @TEMA, OBJETIVO = @OBJETIVO
					WHERE IDCAP = @IDCAP
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'SESION'
	BEGIN
		BEGIN TRY
			SELECT @IDCAPD = IDCAPD, @IDCAP = IDCAP, @MODALIDAD = MODALIDAD, @FECHAINI = FECHAINI, @FECHAFIN = FECHAFIN, @SERVICIO = SERVICIO, @LUGAR = LUGAR, @LINK = LINK, 
				@DIRIGIDOA = DIRIGIDOA, @RESPONSABLE = RESPONSABLE, @ESEXTERNO = ESEXTERNO, @EVALUADA = EVALUADA, @ESTADO = ESTADO, @PROCESO = PROCESO, @COPIAR_ASI = 
				COPIAR_ASI, @HORAINI = HORAINI, @HORAFIN = HORAFIN
			FROM OPENJSON(@PARAMETROS) WITH (
					IDCAPD INT '$.IDCAPD', IDCAP INT '$.IDCAP', MODALIDAD VARCHAR(100) '$.MODALIDAD', FECHAINI DATE '$.FECHAINI', FECHAFIN DATE '$.FECHAFIN', 
					SERVICIO VARCHAR(100) '$.SERVICIO', LUGAR VARCHAR(100) '$.LUGAR', LINK VARCHAR(255) '$.LINK', DIRIGIDOA VARCHAR(100) '$.DIRIGIDOA', 
					RESPONSABLE VARCHAR(100) '$.RESPONSABLE', ESEXTERNO BIT '$.ESEXTERNO', EVALUADA BIT '$.EVALUADA', ESTADO VARCHAR(50) '$.ESTADO', PROCESO 
					VARCHAR(20) '$.PROCESO', COPIAR_ASI BIT '$.COPIAR_ASI', HORAINI TIME '$.HORAINI', HORAFIN TIME '$.HORAFIN'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'YA EXISTE UNA SESION CON ESTE ID'
					WHERE EXISTS (
							SELECT 1
							FROM CAPD
							WHERE IDCAPD = @IDCAPD
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO CAPD (IDCAP, MODALIDAD, FECHAINI, FECHAFIN, SERVICIO, LUGAR, LINK, DIRIGIDOA, RESPONSABLE, ESEXTERNO, EVALUADA, HORAINI, HORAFIN
							)
						SELECT @IDCAP, @MODALIDAD, @FECHAINI, @FECHAFIN, @SERVICIO, @LUGAR, @LINK, @DIRIGIDOA, @RESPONSABLE, @ESEXTERNO, COALESCE(@EVALUADA, 0), 
							@HORAINI, @HORAFIN
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					UPDATE CAPD
					SET MODALIDAD = @MODALIDAD, FECHAINI = @FECHAINI, FECHAFIN = @FECHAFIN, SERVICIO = @SERVICIO, LUGAR = @LUGAR, LINK = @LINK, DIRIGIDOA = @DIRIGIDOA, 
						RESPONSABLE = @RESPONSABLE, ESEXTERNO = @ESEXTERNO, EVALUADA = @EVALUADA, ESTADO = @ESTADO, HORAINI = @HORAINI, HORAFIN = @HORAFIN
					WHERE IDCAPD = @IDCAPD
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'ELIMINAR'
			BEGIN
				BEGIN TRY
					SELECT @IDCAPD = JSON_VALUE(@PARAMETROS, '$.IDCAPD')

					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'LA SESION TIENE EMPLEADOS INSCRITOS (CAPASI)'
					WHERE EXISTS (
							SELECT 1
							FROM CAPASI
							WHERE IDCAPD = @IDCAPD
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						DELETE
						FROM CAPD
						WHERE IDCAPD = @IDCAPD
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK
			END

			IF UPPER(@PROCESO) = 'DUPLICAR'
			BEGIN
				INSERT INTO CAPD (IDCAP, MODALIDAD, FECHAINI, FECHAFIN, SERVICIO, LUGAR, LINK, DIRIGIDOA, RESPONSABLE, ESEXTERNO, EVALUADA, HORAINI, HORAFIN
					)
				SELECT @IDCAP, @MODALIDAD, @FECHAINI, @FECHAFIN, @SERVICIO, @LUGAR, @LINK, @DIRIGIDOA, @RESPONSABLE, @ESEXTERNO, 0, @HORAINI, @HORAFIN

				IF (@COPIAR_ASI) = 1
				BEGIN
					DECLARE @NEWIDCAPD INT = SCOPE_IDENTITY()

					CREATE TABLE #Nemp (EMPLEADO VARCHAR(20));

					INSERT INTO #Nemp (EMPLEADO)
					SELECT CAPASI.NUMDOC
					FROM CAPASI
					INNER JOIN NEMP ON NEMP.NUMDOC = CAPASI.NUMDOC
					WHERE IDCAPD = @IDCAPD AND ISACTIVA = 1 AND NEMP.ESTADO = 'Activo'

					INSERT INTO CAPASI (NUMDOC, IDCAPD)
					SELECT EMPLEADO, @NEWIDCAPD
					FROM #Nemp

					DROP TABLE #Nemp
				END
			END

			IF UPPER(@PROCESO) = 'CONFIRMAR_EVALUACION'
			BEGIN
				BEGIN TRY
					UPDATE CAPD
					SET EVALUADA = 1
					WHERE IDCAPD = @IDCAPD
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ASISTENCIA'
	BEGIN
		BEGIN TRY
			SELECT @IDCAPASI = IDCAPASI, @IDCAPD = IDCAPD, @NUMDOC = NUMDOC, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (IDCAPASI INT '$.IDCAPASI', IDCAPD INT '$.IDCAPD', NUMDOC VARCHAR(20) '$.NUMDOC', PROCESO VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'GUARDAR'
			BEGIN
				BEGIN TRY
					SELECT @EMPLEADOS = JSON_QUERY(@PARAMETROS, '$.EMPLEADOS')

					CREATE TABLE #Empleados (EMPLEADO VARCHAR(20) COLLATE SQL_Latin1_General_CP1_CI_AS);

					INSERT INTO #Empleados (EMPLEADO)
					SELECT value
					FROM OPENJSON(@EMPLEADOS);

					UPDATE CAPASI
					SET ISACTIVA = 0
					WHERE IDCAPD = @IDCAPD AND NUMDOC COLLATE SQL_Latin1_General_CP1_CI_AS NOT IN (
							SELECT EMPLEADO
							FROM #Empleados
							);

					MERGE CAPASI AS target
					USING #Empleados AS source
						ON target.NUMDOC COLLATE SQL_Latin1_General_CP1_CI_AS = source.EMPLEADO AND target.IDCAPD = @IDCAPD
					WHEN MATCHED
						THEN
							UPDATE
							SET ISACTIVA = 1, FECHAREGISTRO = GETDATE()
					WHEN NOT MATCHED
						THEN
							INSERT (NUMDOC, IDCAPD)
							VALUES (source.EMPLEADO, @IDCAPD);

					DROP TABLE #Empleados;
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'CONFIRMAR'
			BEGIN
				UPDATE CAPASI
				SET ASISTENCIA = 1
				WHERE IDCAPASI = @IDCAPASI
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		BEGIN TRY
			SELECT @IDCAP = JSON_VALUE(@PARAMETROS, '$.IDCAP')

			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'LA CAPACITACION TIENE SESIONES REALIZADAS (CAPD)'
			WHERE EXISTS (
					SELECT *
					FROM CAPD
					WHERE IDCAP = @IDCAP
					)

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				DELETE
				FROM CAP
				WHERE IDCAP = @IDCAP
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'EXPORTA_CRONO_CAP'
	BEGIN
		SELECT @CNSEXCEL = JSON_VALUE(@PARAMETROS, '$.CNSEXCEL')

		IF @CNSEXCEL IS NULL
		BEGIN
			EXEC SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE, '@EXCEL', @CNSEXCEL OUTPUT

			SELECT @CNSEXCEL = @IDSEDE + REPLACE(SPACE(8 - LEN(@CNSEXCEL)) + LTRIM(RTRIM(@CNSEXCEL)), SPACE(1), 0)
		END

		BEGIN TRY
			DECLARE @SQL NVARCHAR(MAX) = ''

			SET @SQL = 
				'SELECT 
	                CAP.IDCAP AS CODIGO_CAPACITACION,
	                CAP.TEMA,
	                CAP.OBJETIVO AS OBJETIVOS,
	                CAPD.SERVICIO AS TEMAS_ESPECIFICOS,
	                CAPD.MODALIDAD,
	                CAPD.DIRIGIDOA AS DIRIGIDO_A,
	                FORMAT(CAPD.FECHAINI, ''dd/MM/yyyy'') AS FECHA_INICIAL,
					FORMAT(CAPD.FECHAFIN, ''dd/MM/yyyy'') AS FECHA_FINAL,
	                CASE CAPD.ESEXTERNO
	                	WHEN 1 THEN CAPD.RESPONSABLE
	                	WHEN 0 THEN TER.RAZONSOCIAL
	                END AS RESPONSABLE,
	                CAPD.LUGAR,
	                RIGHT(''0'' + CAST(DATEDIFF(SECOND, CAPD.HORAINI, CAPD.HORAFIN) / 3600 AS VARCHAR), 2) + '':''
	                + RIGHT(''0'' + CAST((DATEDIFF(SECOND, CAPD.HORAINI, CAPD.HORAFIN) % 3600) / 60 AS VARCHAR), 2) + '':''
	                + RIGHT(''0'' + CAST(DATEDIFF(SECOND, CAPD.HORAINI, CAPD.HORAFIN) % 60 AS VARCHAR), 2) AS DURACION,
	                MAX(CASE WHEN MONTH(CAPD.FECHAINI) = 1 THEN ''X'' ELSE '''' END) AS ENERO,
	                MAX(CASE WHEN MONTH(CAPD.FECHAINI) = 2 THEN ''X'' ELSE '''' END) AS FEBRERO,
	                MAX(CASE WHEN MONTH(CAPD.FECHAINI) = 3 THEN ''X'' ELSE '''' END) AS MARZO,
	                MAX(CASE WHEN MONTH(CAPD.FECHAINI) = 4 THEN ''X'' ELSE '''' END) AS ABRIL,
	                MAX(CASE WHEN MONTH(CAPD.FECHAINI) = 5 THEN ''X'' ELSE '''' END) AS MAYO,
	                MAX(CASE WHEN MONTH(CAPD.FECHAINI) = 6 THEN ''X'' ELSE '''' END) AS JUNIO,
	                MAX(CASE WHEN MONTH(CAPD.FECHAINI) = 7 THEN ''X'' ELSE '''' END) AS JULIO,
	                MAX(CASE WHEN MONTH(CAPD.FECHAINI) = 8 THEN ''X'' ELSE '''' END) AS AGOSTO,
	                MAX(CASE WHEN MONTH(CAPD.FECHAINI) = 9 THEN ''X'' ELSE '''' END) AS SEPTIEMBRE,
	                MAX(CASE WHEN MONTH(CAPD.FECHAINI) = 10 THEN ''X'' ELSE '''' END) AS OCTUBRE,
	                MAX(CASE WHEN MONTH(CAPD.FECHAINI) = 11 THEN ''X'' ELSE '''' END) AS NOVIEMBRE,
	                MAX(CASE WHEN MONTH(CAPD.FECHAINI) = 12 THEN ''X'' ELSE '''' END) AS DICIEMBRE
                    FROM CAPD
                    INNER JOIN CAP ON CAPD.IDCAP = CAP.IDCAP
                    LEFT JOIN TER ON TER.IDTERCERO = CAPD.RESPONSABLE
                    GROUP BY 
                    	CAP.IDCAP, CAP.TEMA, CAP.OBJETIVO, CAPD.SERVICIO, CAPD.MODALIDAD,
                    	CAPD.DIRIGIDOA, CAPD.FECHAINI, CAPD.FECHAFIN, CAPD.ESEXTERNO, 
                    	CAPD.RESPONSABLE, CAPD.LUGAR, CAPD.HORAINI, CAPD.HORAFIN, TER.RAZONSOCIAL
                    ORDER BY CAPD.FECHAINI;'

			INSERT INTO KEXCEL_FILL (CNSEXCEL, NOMBRE, BORRAR, CONSULTA)
			SELECT @CNSEXCEL, 'Cronograma ' + CONVERT(VARCHAR, GETDATE(), 112) + '_' + REPLACE(CONVERT(VARCHAR, GETDATE(), 108), ':', '') + '.xlsx', 1, @SQL
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK, @CNSEXCEL CNSEXCEL

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK, @CNSEXCEL CNSEXCEL
	END

	IF @METODO = 'EXPORTA_CAPD'
	BEGIN
		SELECT @IDCAPD = IDCAPD
		FROM OPENJSON(@PARAMETROS) WITH (IDCAPD INT '$.IDCAPD');

		SELECT @CNSEXCEL = JSON_VALUE(@PARAMETROS, '$.CNSEXCEL');

		IF @CNSEXCEL IS NULL
		BEGIN
			EXEC SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE, '@EXCEL', @CNSEXCEL OUTPUT;

			SELECT @CNSEXCEL = @IDSEDE + REPLACE(SPACE(8 - LEN(@CNSEXCEL)) + LTRIM(RTRIM(@CNSEXCEL)), SPACE(1), '0');
		END

		BEGIN TRY
			DECLARE @SQLr NVARCHAR(MAX) = N'';

			SET @SQLr = 
				N'
                    SELECT 
                        NEMP.DOCIDEMPLEADO AS DOCUMENTO,
                        NEMP.TIPO_DOC AS TIPO_DOCUMENTO,
                        LTRIM(RTRIM(CONCAT_WS('' '',
                            NULLIF(LTRIM(RTRIM(NEMP.PRIMERNOMBRE)), ''''),
                            NULLIF(LTRIM(RTRIM(NEMP.SEGUNDONOMBRE)), ''''),
                            NULLIF(LTRIM(RTRIM(NEMP.PRIMERAPELLIDO)), ''''),
                            NULLIF(LTRIM(RTRIM(NEMP.SEGUNDOAPELLIDO)), '''')
                        ))) AS NOMBRE_PARTICIPANTE,
                        CAP.TEMA AS TEMA_CAPACITACION,
                        CAP.OBJETIVO AS DETALLE_CAPACITACION, 
                        FORMAT(CAPD.FECHAINI, ''dd/MM/yyyy'') AS FECHA_INICIO_CAPACITACION,
                        FORMAT(CAPD.FECHAFIN, ''dd/MM/yyyy'') AS FECHA_FIN_CAPACITACION,
                        CONVERT(VARCHAR(5), CAPD.HORAINI, 108) AS HORAINICIO,
                        CONVERT(VARCHAR(5), CAPD.HORAFIN, 108) AS HORAFIN,
                        TER.RAZONSOCIAL AS RESPONSABLE,
                        CASE CAPASI.ASISTENCIA
                            WHEN 0 THEN ''Sin Asistir''
