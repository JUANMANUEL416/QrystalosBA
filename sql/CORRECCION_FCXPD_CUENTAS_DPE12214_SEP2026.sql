/*
  CEM — 03CM002193 DPE12214: IVA en gravada + 24080501 (2 líneas MX2434-1).
  No modifica montos. Pre: N, sin contabilizar.
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @CNSFCXP varchar(20) = N'03CM002193';

BEGIN TRAN;

IF NOT EXISTS (
  SELECT 1 FROM dbo.FCXP P
  WHERE P.CNSFCXP = @CNSFCXP AND P.NOREFERENCIA = N'DPE12214'
    AND P.ESTADO = N'N' AND COALESCE(P.CONTABILIZADA, 0) = 0
)
BEGIN
  ROLLBACK TRAN;
  THROW 55301, 'CxP 03CM002193 no esta libre.', 1;
END;

IF (SELECT COUNT(*) FROM dbo.FCXPD WHERE CNSFCXP = @CNSFCXP AND COALESCE(VLR_IVA, 0) > 0) <> 2
BEGIN
  ROLLBACK TRAN;
  THROW 55302, 'Se esperaban 2 lineas con IVA. Revisar detalle.', 1;
END;

UPDATE dbo.FCXPD
SET CUENTA_SER = N'14150501',
    CUENTA_IVA = N'24080501'
WHERE CNSFCXP = @CNSFCXP
  AND COALESCE(VLR_IVA, 0) > 0
  AND IDSERVICIO = N'MX2434-1';

IF EXISTS (
  SELECT 1 FROM dbo.FCXPD
  WHERE CNSFCXP = @CNSFCXP AND COALESCE(VLR_IVA, 0) > 0
    AND (CUENTA_SER <> N'14150501' OR COALESCE(CUENTA_IVA, N'') <> N'24080501')
)
BEGIN
  ROLLBACK TRAN;
  THROW 55303, 'Cuentas no quedaron gravada+IVA. No se cambio nada.', 1;
END;

COMMIT TRAN;

SELECT D.ITEM, D.IDSERVICIO, CONVERT(decimal(18, 2), D.VLR_IVA) AS IVA,
       D.CUENTA_SER, D.CUENTA_IVA
FROM dbo.FCXPD D WHERE D.CNSFCXP = @CNSFCXP ORDER BY D.ITEM;
