CREATE OR ALTER VIEW DBO.VWK_AUT_FTR_DISP_TRANSCE
AS
SELECT
  AUT.IDAUT, AUT.NOAUT, AUT.FECHA, AUT.FECHAVENCE, AUT.IDAFILIADO,
  AFI.DOCIDAFILIADO, AFI.TIPO_DOC, AFI.NOMBREAFI, AUT.NUMCARNET, AD.IDPLAN,
  AUT.PREFIJO, PRE.NOM_PREFIJO,
  AUT.IDSEDE, AUT.TIPOAUTORIZACION, AUT.ALTOCOSTO, AUT.ATENCION, AUT.URGENCIA, AUT.IMPUTABLE_A, AUT.IDSOLICITANTE,
  AUT.IDPROVEEDOR, AUT.ESTADO, AUT.CONSANULADO, AUT.IDOPERADORANULA, AUT.FECHAANULA, AUT.CAUSALANULA,
  AUT.NO_ITEMES, AUT.VALORTOTAL, AUT.VALORCOPAGO, AUT.VALORBENEFICIO, AUT.VALOREXEDENTE, AUT.VALORTOTALCOSTO,
  AUT.VALORCOPAGOCOSTO, AUT.IMPRESO, AUT.CXPGEN, AUT.CXCGEN, AUT.AUTORIZADOPOR, AUT.NUMAUTORIZA, AUT.FECHAAUTORIZA,
  AUT.AUTORIZADO, AUT.IDPESPECIAL, AUT.IDESTADOE, AUT.USUARIO, AUT.RECOBRARA, AUT.FUENTE, AUT.IDCAUSAEXT,
  AUT.AMBITO, AUT.FINALIDAD, AUT.PERSONAL_AT, AUT.DXPPAL, AUT.DXRELACIONADO, AUT.COMPLICACION, AUT.FORMAQX,
  AUT.TIPOURGENCIA, AUT.SPD, AUT.NORECIBOCAJA, AUT.CLASEORDEN, AUT.GENEROCAJA, AD.IDTERCEROCA AS IDCONTRATANTE,
  AUT.TIPOCOPAGO, AUT.PEDIDOINV, AUT.ENVIO, AUT.OBS, AUT.ESCONTINUACION, AUT.NOAUTORIGEN, AUT.IDSEDEORIGEN,
  AUT.SEMANASCOT,
  AUT.LIQUIDAPC, AUT.OBSDX, AUT.COMITE, AUT.CERTIFICACION, AUT.IDCLASEAUT, AUT.CLASECONT, AUT.ESDEINV,
  AUT.NOGENERACIONOPS, AUT.FECHAGEN, AUT.IDAREA, AUT.NIVELATENCION, AUT.CNSAFIAA, AUT.SUBCCOSTO, AUT.CCOSTO,
  AUT.PROCEDENCIA, AUT.IDAREAH, AD.FACTURADA, AD.N_FACTURA, AD.CNSFCT, AUT.VFACTURAS, AUT.FACTURABLE,
  AUT.DESCUENTO, AUT.TIPODTO, AUT.MARCAFAC, AUT.IDIPS, AUT.CLASECONTRATO, AUT.ENPAQUETE, AUT.IDCIRUGIA,
  AUT.SOAT, AUT.NOADMISION, AUT.IDCONTRATO, AUT.RUBRO, AUT.CLASERUBRO, AUT.FECHASOL, AUT.PERIODICIDAD,
  AUT.CNSFACT, AUT.CONTINUACION, AUT.VLRUTOTRA, AUT.TIPOCONT, AUT.DXRELACIONADO2, AUT.FECHACOMITE,
  AUT.IDALTERNA, AUT.MARCAENV, AUT.COPAGOPROPIO, AUT.CNSHACTRAN, AUT.ESDELAB, AUT.ENLAB, AUT.COBRARA,
  AD.IDTERCEROCA, AUT.CONSECUTIVOHCA, AUT.RAZONANULACION, AUT.FECHAREALIZACION, AUT.IDGRUPOSER, AUT.PEXTERNA,
  AUT.PIDECCOSTO, AUT.CODCAJA, AUT.TIPOCAJA, AUT.CERRADA,
  AUT.IDMIPRESS, AUT.TIPOAFILIADO,
  CONVERT(VARCHAR(20), AUT.IDAUT) + '|'
    + CONVERT(VARCHAR(2), AD.FACTURADA) + '|'
    + COALESCE(AD.N_FACTURA, '') AS IDUNICO
FROM AUT WITH (NOLOCK)
INNER JOIN (
  SELECT
    D.IDAUT,
    MAX(NULLIF(RTRIM(LTRIM(D.IDPLAN)), '')) AS IDPLAN,
    MAX(NULLIF(RTRIM(LTRIM(D.IDTERCEROCA)), '')) AS IDTERCEROCA,
    COALESCE(D.FACTURADA, 0) AS FACTURADA,
    NULLIF(RTRIM(LTRIM(COALESCE(D.N_FACTURA, ''))), '') AS N_FACTURA,
    MAX(D.CNSFCT) AS CNSFCT
  FROM AUTD D WITH (NOLOCK)
  GROUP BY
    D.IDAUT,
    COALESCE(D.FACTURADA, 0),
    NULLIF(RTRIM(LTRIM(COALESCE(D.N_FACTURA, ''))), '')
) AD
  ON AD.IDAUT = AUT.IDAUT
INNER JOIN AFI WITH (NOLOCK)
  ON AFI.IDAFILIADO = AUT.IDAFILIADO
OUTER APPLY (
  SELECT TOP (1) P.NOM_PREFIJO
  FROM PRE P WITH (NOLOCK)
  WHERE P.PREFIJO = AUT.PREFIJO
) PRE
WHERE COALESCE(AUT.ESTADO, '') <> 'Anulada'
  AND (
    EXISTS (
      SELECT 1
      FROM IZSOL Z WITH (NOLOCK)
      WHERE Z.CNSIZSOL = AUT.CNSMOV
        AND (
             Z.CLASE = 'TRANS_CE'
          OR (Z.CLASE = 'CE' AND COALESCE(AUT.MANUALCE, 0) = 1)
        )
    )
    OR (
      AUT.USUARIO = 'CONSOL_EXCEL'
      AND COALESCE(AUT.MANUALCE, 0) = 1
    )
  )
