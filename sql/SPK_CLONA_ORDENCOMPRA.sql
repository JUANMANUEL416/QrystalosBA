IF EXISTS (SELECT NAME FROM SYSOBJECTS WHERE NAME = 'SPK_CLONA_ORDENCOMPRA' AND TYPE = 'P')
BEGIN
   DROP PROCEDURE SPK_CLONA_ORDENCOMPRA 
END
GO
CREATE   PROCEDURE DBO.SPK_CLONA_ORDENCOMPRA
@CNSFCOMA VARCHAR(20),
@CNSFCOMN VARCHAR(20),
@USUARIO  VARCHAR(20)
AS
BEGIN
   
   INSERT INTO FCOM(CNSFCOM, COMPANIA, IDTERCERO, N_FACTURA, F_FACTURA, F_VENCE, VENDEDOR, ESTADO, F_CANCELADO, OBSERVACION, VR_ANTESIVA, IVA, VR_TOTAL, CNSFCOT, AJUSTADO, AJUSTEALPESO, ENINVENTARIO, ENCXP, 
                  VR_DESCUENTO, USUARIO, FECHA, ORDENCOMPRA, USUARIOORDEN, FECHAORDEN, IDBODEGA, CCOSTO, IDAREA, IDTIPOSER, CODUNG, CODPRG, DCONSUMO, DECONSUMO, TIPOANTICIPO, ESACTIVO, MANTICIPO, 
                  APROVAL, INTEFAX, CNSMOVRESP)
   SELECT @CNSFCOMN, COMPANIA, IDTERCERO, NULL, NULL, NULL, VENDEDOR, 'C', F_CANCELADO, NULL, VR_ANTESIVA, IVA, VR_TOTAL, NULL, AJUSTADO, AJUSTEALPESO, ENINVENTARIO, 0, 
         VR_DESCUENTO, @USUARIO, GETDATE(), 0, USUARIOORDEN, FECHAORDEN, IDBODEGA, CCOSTO, IDAREA, IDTIPOSER, CODUNG, CODPRG, DCONSUMO, DECONSUMO, TIPOANTICIPO, ESACTIVO, MANTICIPO, 
         APROVAL, INTEFAX, CNSMOVRESP 
   FROM FCOM 
   WHERE CNSFCOM=@CNSFCOMA

   INSERT INTO FCOMD(CNSFCOM, IDARTICULO, ESTADO, VLR_UNITARIO, CANTIDAD, VR_ANTESIVA, IVA, VR_TOTAL, VR_UNITMASIVA, COMPANIA, TIENEIVA, FACTORIVA, NOLOTE, FECHAVENCE, VR_DESCUENTO, DETALLE, TIPO, IDIMPUESTO, 
                     IDCLASE, UTILIDAD, TDESCUENTO, TIPODTO, PDTO, IDTUTELD, TEMP, HUMEDAD, DECONSUMO)
   SELECT @CNSFCOMN, IDARTICULO, ESTADO, VLR_UNITARIO, CANTIDAD, VR_ANTESIVA, IVA, VR_TOTAL, VR_UNITMASIVA, COMPANIA, TIENEIVA, FACTORIVA, NOLOTE, FECHAVENCE, VR_DESCUENTO, DETALLE, TIPO, IDIMPUESTO, 
          IDCLASE, UTILIDAD, TDESCUENTO, TIPODTO, PDTO, IDTUTELD, TEMP, HUMEDAD, DECONSUMO
   FROM FCOMD
   WHERE CNSFCOM=@CNSFCOMA

END
