CREATE OR ALTER PROCEDURE DBO.SPK_PREFIJOFACTURA  
@COMPANIA   VARCHAR(2),  
@IDSEDE     VARCHAR(5),  
@PRE        VARCHAR(20) OUTPUT  
WITH ENCRYPTION
AS  
DECLARE @PREFIJOFAC  VARCHAR(10)
BEGIN    
   IF DBO.FNK_VALORVARIABLE('BLOQUEADIAN')='SI'
   BEGIN
      SELECT @PREFIJOFAC=COALESCE(PREFIJO,'') FROM FDIAN WHERE IDENTIFICADOR=@IDSEDE AND VENCIDA=0 AND PROCEDENCIA='FTR' 
      IF COALESCE(@PREFIJOFAC,'')<>''
      BEGIN
         SELECT @PRE = '@FTR_'+LTRIM(RTRIM(@PREFIJOFAC))
      END
      ELSE
      BEGIN
	      SELECT @PRE = '@FTR_'
      END
   END
   ELSE
   BEGIN  
      IF UPPER(DBO.FNK_VALORVARIABLE('MPREFIJOFAC')) = 'SI'
      BEGIN
         IF @IDSEDE = '01'
            SELECT @PREFIJOFAC = DBO.FNK_VALORVARIABLE('PREFIJOFAC')
         ELSE
            SELECT @PREFIJOFAC = DBO.FNK_VALORVARIABLE('PREFIJOFAC_'+LTRIM(RTRIM(@IDSEDE)))
         PRINT 'PREFIJOFAC = '+ @PREFIJOFAC       
         SET @PRE = '@FTR_'+LTRIM(RTRIM(@PREFIJOFAC))
      END
      ELSE
      BEGIN
         SET @PRE = '@FTR_'
      END
   END          
END
