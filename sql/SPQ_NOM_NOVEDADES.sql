CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NOVEDADES @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS AS NVARCHAR(MAX), @MODELO AS VARCHAR(100), @METODO AS VARCHAR(100), @USUARIO AS VARCHAR(20);
DECLARE @PROCESO AS VARCHAR(20), @DATOS AS NVARCHAR(MAX);
DECLARE @IDEVENTO AS VARCHAR(6), @IDEVENTOEDITE AS VARCHAR(6);
DECLARE @DESCRIPCION AS VARCHAR(60), @CODCONCEPTO AS VARCHAR(20), @AFECTAHORAS AS SMALLINT, @GEN_EVE_SEC AS SMALLINT, @IDEVENTO_SEC AS VARCHAR(6);
DECLARE @TIPONOV AS VARCHAR(10), @SOLDX AS BIT, @DCALEN AS BIT, @CNSPAGO AS VARCHAR(20), @CNSRPDX AS VARCHAR(20), @INDICE AS INT, @ESTRUCTURA AS INT;
DECLARE @DATO AS NVARCHAR(MAX), @CNSEXCEL AS VARCHAR(20), @IDSEDE AS VARCHAR(5), @SYS_COMPUTERNAME AS VARCHAR(200), @COMPANIA AS VARCHAR(2), @NROLINEAS AS INT, @ITEM AS 
	INT;
DECLARE @NUMDOC AS VARCHAR(20), @DOCIDEMPLEADO AS VARCHAR(20), @NOMBREEMPLEADO AS VARCHAR(250), @DIAS AS INT, @HORAS AS INT, @DESCRIPCIONEVENTO AS VARCHAR(100), 
	@DESCRIDDX AS VARCHAR(512), @TODOS AS SMALLINT, @JSONPARAM AS NVARCHAR(MAX), @RPDXIDEVENTO AS VARCHAR(20), @NDIASEG AS SMALLINT, @RNOVE AS SMALLINT, @IDDIAGNOSTICO 
	AS VARCHAR(10);
DECLARE @ERROR AS VARCHAR(2024), @ER AS BIT, @TERRORES AS SMALLINT, @TOK AS SMALLINT, @CODNOMINA AS VARCHAR(2), @LINEA AS VARCHAR(MAX), @FECHAINI_REG AS DATETIME = NULL, 
	@FECHAFIN_REG AS DATETIME = NULL;
DECLARE @TABLA AS TABLE (ITEM INT IDENTITY(1, 1), VALOR VARCHAR(MAX));
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX));
DECLARE @FECHAS_NOV AS BIT, @HASIDDX AS BIT, @SEREPITE AS VARCHAR(2);

BEGIN
	SET LANGUAGE Spanish;
	SET DATEFORMAT dmy;

	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			);

	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
	FROM USUSU
	WHERE USUARIO = @USUARIO;

	SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
	FROM UBEQ
	WHERE SYS_ComputerName = @SYS_COMPUTERNAME;

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @IDEVENTO = IDEVENTO, @DESCRIPCION = DESCRIPCION, @CODCONCEPTO = CODCONCEPTO, @GEN_EVE_SEC = GEN_EVE_SEC, @IDEVENTO_SEC = IDEVENTO_SEC, 
				@AFECTAHORAS = AFECTAHORAS, @TIPONOV = TIPONOV, @SOLDX = SOLDX, @DCALEN = DCALEN, @NDIASEG = NDIASEG, @RNOVE = RNOVE, @PROCESO = PROCESO, @FECHAS_NOV = 
				FECHAS_NOV
			FROM OPENJSON(@PARAMETROS) WITH (
					IDEVENTO VARCHAR(6) '$.IDEVENTO', DESCRIPCION VARCHAR(60) '$.DESCRIPCION', CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO', GEN_EVE_SEC SMALLINT 
					'$.GEN_EVE_SEC', IDEVENTO_SEC VARCHAR(6) '$.IDEVENTO_SEC', AFECTAHORAS SMALLINT '$.AFECTAHORAS', TIPONOV VARCHAR(10) '$.TIPONOV', SOLDX BIT 
					'$.SOLDX', DCALEN BIT '$.DCALEN', NDIASEG SMALLINT '$.NDIASEG', RNOVE SMALLINT '$.RNOVE', PROCESO VARCHAR(20) '$.PROCESO', FECHAS_NOV BIT 
					'$.FECHAS_NOV'
					);

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('EL EVENTO ', @IDEVENTO, ' YA SE ENCUENTRA REGISTRADO')
					WHERE EXISTS (
							SELECT 1
							FROM NEVE
							WHERE IDEVENTO = @IDEVENTO
							);

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO NEVE (IDEVENTO, DESCRIPCION, CODCONCEPTO, AFECTAHORAS, GEN_EVE_SEC, IDEVENTO_SEC, TIPONOV, SOLDX, DCALEN, NDIASEG, RNOVE, FECHAS_NOV
							)
						SELECT @IDEVENTO, @DESCRIPCION, @CODCONCEPTO, @AFECTAHORAS, @GEN_EVE_SEC, @IDEVENTO_SEC, @TIPONOV, @SOLDX, @DCALEN, @NDIASEG, @RNOVE, 
							@FECHAS_NOV;
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE();
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' AS OK;

					SELECT ERROR
					FROM @TBLERRORES;

					RETURN;
				END

				SELECT 'OK' AS OK;

				RETURN;
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @DATO = DATO
					FROM OPENJSON(@PARAMETROS) WITH (DATO NVARCHAR(MAX) AS JSON);

					SELECT @IDEVENTOEDITE = IDEVENTOEDITE
					FROM OPENJSON(@DATO) WITH (IDEVENTOEDITE VARCHAR(6) '$.IDEVENTOEDITE');

					IF (@IDEVENTOEDITE <> @IDEVENTO)
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('EL EVENTO ', @IDEVENTO, ' YA SE ENCUENTRA REGISTRADO')
						WHERE EXISTS (
								SELECT 1
								FROM NEVE
								WHERE IDEVENTO = @IDEVENTO
								);

						IF (
								SELECT COUNT(*)
								FROM @TBLERRORES
								) <= 0
						BEGIN
							UPDATE NEVE
							SET IDEVENTO = @IDEVENTO, DESCRIPCION = @DESCRIPCION, CODCONCEPTO = @CODCONCEPTO, AFECTAHORAS = @AFECTAHORAS, GEN_EVE_SEC = @GEN_EVE_SEC, 
								IDEVENTO_SEC = @IDEVENTO_SEC, TIPONOV = @TIPONOV, SOLDX = @SOLDX, DCALEN = @DCALEN, NDIASEG = @NDIASEG, RNOVE = @RNOVE, FECHAS_NOV = 
								@FECHAS_NOV
							WHERE IDEVENTO = @IDEVENTOEDITE;
						END
					END
					ELSE
					BEGIN
						UPDATE NEVE
						SET DESCRIPCION = @DESCRIPCION, CODCONCEPTO = @CODCONCEPTO, AFECTAHORAS = @AFECTAHORAS, GEN_EVE_SEC = @GEN_EVE_SEC, IDEVENTO_SEC = 
							@IDEVENTO_SEC, TIPONOV = @TIPONOV, SOLDX = @SOLDX, DCALEN = @DCALEN, NDIASEG = @NDIASEG, RNOVE = @RNOVE, FECHAS_NOV = @FECHAS_NOV
						WHERE IDEVENTO = @IDEVENTO;
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE();
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' AS OK;

					SELECT ERROR
					FROM @TBLERRORES;

					RETURN;
				END

				SELECT 'OK' AS OK;

				RETURN;
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' AS OK;

			SELECT ERROR
			FROM @TBLERRORES;

			RETURN;
		END

		SELECT 'OK' AS OK;
	END

	IF @METODO = 'GET_NEVED_DETALLE'
	BEGIN
		SELECT @IDEVENTO = IDEVENTO
		FROM OPENJSON(@PARAMETROS) WITH (IDEVENTO VARCHAR(6) '$.IDEVENTO');

		SELECT 'OK' AS OK;

		SELECT NEVED.IDEVENTO, NEVED.ITEM, NEVED.FACTOR, NEVED.FECHAINI, NEVED.CODCONCEPTO, NEVED.INDEMNIZA, NEVED.PERINDEM, NCON.DESCRIPCION
		FROM NEVED
		LEFT OUTER JOIN NCON ON NCON.CODCONCEPTO = NEVED.CODCONCEPTO
		WHERE NEVED.IDEVENTO = JSON_VALUE(@PARAMETROS, '$.IDEVENTO');

		RETURN;
	END

	IF @METODO = 'EXPORTA_EMPLEADOS_NOVEDAD'
	BEGIN
		SELECT @CNSEXCEL = JSON_VALUE(@PARAMETROS, '$.CNSEXCEL');

		SELECT @CNSPAGO = CNSPAGO
		FROM OPENJSON(@PARAMETROS) WITH (CNSPAGO VARCHAR(20) '$.CNSPAGO');

		IF @CNSEXCEL IS NULL
		BEGIN
			EXECUTE SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE, '@EXCEL', @CNSEXCEL OUTPUT;

			SELECT @CNSEXCEL = @IDSEDE + REPLACE(SPACE(8 - LEN(@CNSEXCEL)) + LTRIM(RTRIM(@CNSEXCEL)), SPACE(1), 0);
		END

		BEGIN TRY
			INSERT INTO KEXCEL_FILL (CNSEXCEL, NOMBRE, BORRAR, CONSULTA)
			SELECT @CNSEXCEL, 'Empleados ' + CONVERT(VARCHAR, GETDATE(), 112) + '_' + REPLACE(CONVERT(VARCHAR, GETDATE(), 108), ':', '') + '.xlsx', 1, 
				'SELECT NEMP.NUMDOC,TRIM(CONCAT('' '' + COALESCE(NEMP.PRIMERAPELLIDO, ''''), '' '' + COALESCE(NEMP.SEGUNDOAPELLIDO, ''''), '' '' + COALESCE(NEMP.PRIMERNOMBRE, ''''), '' '' + COALESCE(NEMP.SEGUNDONOMBRE, ''''))) AS NOMBREEMPLEADO, NEMP.DOCIDEMPLEADO, ''IDEVENTO'' AS IDEVENTO,''0'' AS DIAS,''0'' AS HORAS,FORMAT(NEMP.FECHAINGRESO,''yyyy-MM-dd'') AS FECHAINGRESO,FORMAT(NEMP.FECHARETIRO,''yyyy-MM-dd'') AS FECHARETIRO FROM NEMPF INNER JOIN NEMP ON NEMP.NUMDOC = NEMPF.NUMDOC WHERE NEMPF.CNSPAGO = ''' 
				+ @CNSPAGO + '''';
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' AS OK, @CNSEXCEL AS CNSEXCEL;

			SELECT ERROR
			FROM @TBLERRORES;

			RETURN;
		END

		SELECT 'OK' AS OK, @CNSEXCEL AS CNSEXCEL;
	END

	IF @METODO IN ('CARGAR_EMPLEADOS_NOVEDAD', 'CARGAR_EMPLEADO_NOVEDAD')
	BEGIN
		DECLARE @EsCargaMasiva AS BIT = CASE 
				WHEN @METODO = 'CARGAR_EMPLEADOS_NOVEDAD'
					THEN 1
				ELSE 0
				END;
		DECLARE @NumDocRoot AS VARCHAR(20), @DocIdEmpleadoRoot AS VARCHAR(20);
		DECLARE @ColumnasMin AS INT = CASE 
				WHEN @EsCargaMasiva = 1
					THEN 6
				ELSE 3
				END;
		DECLARE @ColumnasMax AS INT = CASE 
				WHEN @EsCargaMasiva = 1
					THEN 9
				ELSE 6
				END;

		SELECT @NROLINEAS = COUNT(*)
		FROM OPENJSON(@PARAMETROS, '$.LINEAS');

		SELECT @CODNOMINA = CODNOMINA
		FROM OPENJSON(@PARAMETROS) WITH (CODNOMINA VARCHAR(2) '$.CODNOMINA');

		IF @EsCargaMasiva = 0
		BEGIN
			SELECT @NumDocRoot = NUMDOC, @DocIdEmpleadoRoot = DOCIDEMPLEADO
			FROM OPENJSON(@PARAMETROS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC', DOCIDEMPLEADO VARCHAR(20) '$.DOCIDEMPLEADO');
		END

		IF @NROLINEAS > 0
		BEGIN
			SELECT @IDSEDE = COALESCE(UBEQ.IDSEDE, USUSU.IDSEDE), @COMPANIA = COALESCE(UBEQ.COMPANIA, USUSU.COMPANIA), @SYS_COMPUTERNAME = COALESCE(USUSU.
					SYS_ComputerName, HOST_NAME())
			FROM USUSU
			LEFT OUTER JOIN UBEQ ON USUSU.SYS_ComputerName = UBEQ.SYS_ComputerName
			WHERE USUSU.USUARIO = @USUARIO;

			SELECT @CNSRPDX = '';

			EXECUTE SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE, '@RPDX', @CNSRPDX OUTPUT;

			SELECT @CNSRPDX = @IDSEDE + REPLACE(SPACE(8 - LEN(@CNSRPDX)) + LTRIM(RTRIM(@CNSRPDX)), SPACE(1), 0);

			PRINT '@CNSRPDX=' + COALESCE(@CNSRPDX, '');

			SELECT @INDICE = 0;

			SELECT @DESCRIPCIONEVENTO = '', @DESCRIDDX = '';

			DECLARE SUBIR_CURSOR CURSOR
			FOR
			SELECT VALUE
			FROM OPENJSON(@PARAMETROS, '$.LINEAS');

			OPEN SUBIR_CURSOR;

			FETCH NEXT
			FROM SUBIR_CURSOR
			INTO @LINEA;

			WHILE @@FETCH_STATUS = 0
			BEGIN
				DELETE @TABLA
				WHERE 1 = 1;

				INSERT INTO @TABLA (VALOR)
				SELECT VALUE
				FROM string_split(@LINEA, ',');

				SELECT @ESTRUCTURA = COUNT(*)
				FROM @TABLA;

				SET @ERROR = '';
				SET @ER = 0;

				SELECT @NUMDOC = NULL, @DOCIDEMPLEADO = NULL, @NOMBREEMPLEADO = NULL, @IDEVENTO = NULL, @DIAS = NULL, @HORAS = NULL, @FECHAINI_REG = NULL, @FECHAFIN_REG = 
					NULL, @CODCONCEPTO = NULL, @SEREPITE = NULL;

				BEGIN TRY
					IF @ESTRUCTURA < @ColumnasMin OR @ESTRUCTURA > @ColumnasMax
					BEGIN
						SELECT @ER = 1, @ERROR = 'Error de Estructura Campos = ' + CAST(@ESTRUCTURA AS VARCHAR(4)) + ' (Esperados entre: ' + CAST(@ColumnasMin AS 
								VARCHAR(4)) + ' y ' + CAST(@ColumnasMax AS VARCHAR(4)) + ')';
					END
					ELSE
					BEGIN
						IF @EsCargaMasiva = 1
						BEGIN
							SELECT @NUMDOC = VALOR
							FROM @TABLA
							WHERE ITEM = 1 + @INDICE;

							SELECT @DOCIDEMPLEADO = VALOR
							FROM @TABLA
							WHERE ITEM = 2 + @INDICE;

							SELECT @NOMBREEMPLEADO = VALOR
							FROM @TABLA
							WHERE ITEM = 3 + @INDICE;

							SELECT @IDEVENTO = VALOR
							FROM @TABLA
							WHERE ITEM = 4 + @INDICE;

							SELECT @DIAS = VALOR
							FROM @TABLA
							WHERE ITEM = 5 + @INDICE;

							SELECT @HORAS = VALOR
							FROM @TABLA
							WHERE ITEM = 6 + @INDICE;

							SELECT @IDDIAGNOSTICO = VALOR
							FROM @TABLA
							WHERE ITEM = 7 + @INDICE;

							SELECT @FECHAINI_REG = VALOR
							FROM @TABLA
							WHERE ITEM = 8 + @INDICE;

							SELECT @FECHAFIN_REG = VALOR
							FROM @TABLA
							WHERE ITEM = 9 + @INDICE;
						END
						ELSE
						BEGIN
							SET @NUMDOC = @NumDocRoot;
							SET @DOCIDEMPLEADO = @DocIdEmpleadoRoot;

							SELECT @IDEVENTO = VALOR
							FROM @TABLA
							WHERE ITEM = 1 + @INDICE;

							SELECT @DIAS = VALOR
							FROM @TABLA
							WHERE ITEM = 2 + @INDICE;

							SELECT @HORAS = VALOR
							FROM @TABLA
							WHERE ITEM = 3 + @INDICE;

							SELECT @IDDIAGNOSTICO = VALOR
							FROM @TABLA
							WHERE ITEM = 4 + @INDICE;

							SELECT @FECHAINI_REG = VALOR
							FROM @TABLA
							WHERE ITEM = 5 + @INDICE;

							SELECT @FECHAFIN_REG = VALOR
							FROM @TABLA
							WHERE ITEM = 6 + @INDICE;
						END
					END

					IF @ER = 0
					BEGIN
						IF NOT EXISTS (
								SELECT *
								FROM NEMP
								WHERE NUMDOC = @NUMDOC
								)
							SELECT @ER = 1, @ERROR = @ERROR + ' - Codigo de contrato No existe';

						IF @ER = 0 AND NOT EXISTS (
								SELECT *
								FROM NEMP
								WHERE NUMDOC = @NUMDOC AND DOCIDEMPLEADO = @DOCIDEMPLEADO
								)
							SELECT @ER = 1, @ERROR = @ERROR + ' - Documento del empleado no pertenece al numero de contrato';

						IF NOT EXISTS (
								SELECT *
								FROM NEVE
								WHERE IDEVENTO = @IDEVENTO
								)
							SELECT @ER = 1, @ERROR = @ERROR + ' - El id del evento no existe ';
						ELSE
						BEGIN
							SELECT @DESCRIPCIONEVENTO = DESCRIPCION
							FROM NEVE
							WHERE IDEVENTO = @IDEVENTO;

							-- Concepto asociado a la novedad (NEVED primero, si no NEVE.CODCONCEPTO)
							SELECT @CODCONCEPTO = COALESCE((
										SELECT TOP 1 NULLIF(LTRIM(RTRIM(NEVED.CODCONCEPTO)), '')
										FROM NEVED
										WHERE NEVED.IDEVENTO = @IDEVENTO AND ISNULL(NEVED.CODCONCEPTO, '') <> ''
										ORDER BY NEVED.ITEM
										), NULLIF(LTRIM(RTRIM(NEVE.CODCONCEPTO)), ''))
							FROM NEVE
							WHERE NEVE.IDEVENTO = @IDEVENTO;

							-- SEREPITE='Si' si ALG�N concepto de la novedad lo permite
							SELECT @SEREPITE = CASE 
									WHEN EXISTS (
											SELECT 1
											FROM NCON
											WHERE ISNULL(NCON.SEREPITE, 'No') = 'Si' AND NCON.CODCONCEPTO IN (
													SELECT NEVE.CODCONCEPTO
													FROM NEVE
													WHERE NEVE.IDEVENTO = @IDEVENTO AND ISNULL(NEVE.CODCONCEPTO, '') <> ''
													
													UNION
													
													SELECT NEVED.CODCONCEPTO
													FROM NEVED
													WHERE NEVED.IDEVENTO = @IDEVENTO AND ISNULL(NEVED.CODCONCEPTO, '') <> ''
													)
											)
										THEN 'Si'
									ELSE 'No'
									END;
						END

						SELECT @HASIDDX = SOLDX
						FROM NEVE
						WHERE IDEVENTO = @IDEVENTO;

						IF @HASIDDX = 1
						BEGIN
							IF ISNULL(LTRIM(RTRIM(@IDDIAGNOSTICO)), '') = ''
							BEGIN
								SELECT @ER = 1, @ERROR = @ERROR + ' - El diagnostico para la novedad ' + @IDEVENTO + ' es obligatoria.';
							END
							ELSE
							BEGIN
								IF NOT EXISTS (
										SELECT 1
										FROM MDX
										WHERE IDDX = @IDDIAGNOSTICO AND ESTADO = 'Activo'
										)
								BEGIN
									SELECT @ER = 1, @ERROR = @ERROR + ' - El id del diagnostico no existe ';
								END
								ELSE
								BEGIN
									SELECT @DESCRIDDX = DESCRIPCION
									FROM MDX
									WHERE IDDX = @IDDIAGNOSTICO;
								END
							END
						END
						ELSE
						BEGIN
							SELECT @DESCRIDDX = '', @IDDIAGNOSTICO = NULL;
						END

						IF NOT EXISTS (
								SELECT *
								FROM NOMIE
								WHERE NUMDOC = @NUMDOC AND CODNOMINA = @CODNOMINA
								)
						BEGIN
							SELECT @ER = 1, @ERROR = @ERROR + ' - El Empleado ' + @DOCIDEMPLEADO + ' no existe dentro de la plantilla de la nomina.';
						END
						ELSE
						BEGIN
							IF (
									SELECT ESTADO
									FROM NOMIE
									WHERE CODNOMINA = @CODNOMINA AND NUMDOC = @NUMDOC
									) = 'Inactivo'
								SELECT @ER = 1, @ERROR = @ERROR + ' - El Empleado ' + @DOCIDEMPLEADO + ' se encuentra inactivo en la plantilla de la nomina.';
						END

						SELECT @FECHAS_NOV = FECHAS_NOV
						FROM NEVE
						WHERE IDEVENTO = @IDEVENTO;

						IF @FECHAS_NOV = 1
						BEGIN
							IF @FECHAINI_REG IS NULL OR @FECHAFIN_REG IS NULL
							BEGIN
								SELECT @ER = 1, @ERROR = @ERROR + ' - Las fechas de registro para la novedad ' + @IDEVENTO + ' son obligatorias.';
							END
						END
						ELSE
						BEGIN
							SELECT @FECHAINI_REG = NULL, @FECHAFIN_REG = NULL;
						END

						SELECT @NOMBREEMPLEADO = CONCAT_WS(' ', NEMP.PRIMERNOMBRE, NEMP.SEGUNDONOMBRE, NEMP.PRIMERAPELLIDO, NEMP.SEGUNDOAPELLIDO)
						FROM NEMP
						WHERE NUMDOC = @NUMDOC;

						-- SEREPITE='No': no se acepta otra novedad del mismo concepto para el empleado en este lote
						-- SEREPITE='Si': cada fila se carga como novedad independiente (detalle repetible)
						IF @ER = 0 AND ISNULL(@SEREPITE, 'No') <> 'Si' AND ISNULL(@IDEVENTO, '') <> ''
						BEGIN
							IF EXISTS (
									SELECT 1
									FROM RPDX AS R
									WHERE R.CNS = @CNSRPDX AND R.ID1 = @NUMDOC AND ISNULL(R.CANTIDAD10, 0) = 0 AND EXISTS (
											SELECT 1
											FROM (
												SELECT NEVE.CODCONCEPTO
												FROM NEVE
												WHERE NEVE.IDEVENTO = R.ID3 AND ISNULL(NEVE.CODCONCEPTO, '') <> ''
												
												UNION
												
												SELECT NEVED.CODCONCEPTO
												FROM NEVED
												WHERE NEVED.IDEVENTO = R.ID3 AND ISNULL(NEVED.CODCONCEPTO, '') <> ''
												) AS CPrev
											INNER JOIN (
												SELECT NEVE.CODCONCEPTO
												FROM NEVE
												WHERE NEVE.IDEVENTO = @IDEVENTO AND ISNULL(NEVE.CODCONCEPTO, '') <> ''
												
												UNION
												
												SELECT NEVED.CODCONCEPTO
												FROM NEVED
												WHERE NEVED.IDEVENTO = @IDEVENTO AND ISNULL(NEVED.CODCONCEPTO, '') <> ''
												) AS CNew ON CPrev.CODCONCEPTO = CNew.CODCONCEPTO
											INNER JOIN NCON ON NCON.CODCONCEPTO = CNew.CODCONCEPTO AND ISNULL(NCON.SEREPITE, 'No') <> 'Si'
											)
									)
							BEGIN
								SELECT @ER = 1, @ERROR = @ERROR + ' - El concepto ' + ISNULL(@CODCONCEPTO, '') + ' asociado a la novedad ' + ISNULL(@IDEVENTO, '') + 
									' no permite repetirse. Ya existe otra novedad del mismo concepto para este empleado.';
							END
						END

						IF @ER = 0
						BEGIN
							INSERT INTO RPDX (
								CNS, ID1, ID2, STRINGGRANDE1, ID3, CANTIDAD, CANTIDAD1, STRINGMEDIO3, STRINGMEDIO1, STRINGMEDIO2, CANTIDAD10, STRINGMAX, FECHA1, 
								FECHA2
								)
							SELECT @CNSRPDX, @NUMDOC, @DOCIDEMPLEADO, @NOMBREEMPLEADO, @IDEVENTO, @DIAS, @HORAS, @IDDIAGNOSTICO, @DESCRIPCIONEVENTO, @DESCRIDDX, 
								0, '', @FECHAINI_REG, @FECHAFIN_REG;-- 0 errores
						END
						ELSE
						BEGIN
							INSERT INTO RPDX (
								CNS, ID1, ID2, STRINGGRANDE1, ID3, CANTIDAD, CANTIDAD1, STRINGMEDIO3, STRINGMEDIO1, STRINGMEDIO2, FECHA1, FECHA2, CANTIDAD10, 
								STRINGMAX
								)
							SELECT @CNSRPDX, @NUMDOC, @DOCIDEMPLEADO, @NOMBREEMPLEADO, @IDEVENTO, @DIAS, @HORAS, @IDDIAGNOSTICO, @DESCRIPCIONEVENTO, @DESCRIDDX, 
								@FECHAINI_REG, @FECHAFIN_REG, 1, @ERROR;
						END
					END
					ELSE
					BEGIN
						INSERT INTO RPDX (CNS, ID1, STRINGMAX, CANTIDAD10)
						SELECT @CNSRPDX, COALESCE(@NUMDOC, 'ERR'), @ERROR, 1;
					END
				END TRY

				BEGIN CATCH
					INSERT INTO RPDX (CNS, ID1, STRINGGRANDE2, STRINGMAX, CANTIDAD10)
					SELECT @CNSRPDX, COALESCE(@NUMDOC, 'ERR'), ERROR_MESSAGE(), @LINEA, 1;
				END CATCH

				SET @INDICE += @ESTRUCTURA;

				FETCH NEXT
				FROM SUBIR_CURSOR
				INTO @LINEA;
			END

			CLOSE SUBIR_CURSOR;

			DEALLOCATE SUBIR_CURSOR;

			SELECT @NROLINEAS = COUNT(*)
			FROM RPDX
			WHERE CNS = @CNSRPDX;

			SELECT @TERRORES = SUM(CASE 
						WHEN CANTIDAD10 = 1
							THEN 1
						ELSE 0
						END), @TOK = SUM(CASE 
						WHEN CANTIDAD10 = 1
							THEN 0
						ELSE 1
						END)
			FROM RPDX
			WHERE CNS = @CNSRPDX;

			SELECT 'OK' AS OK, @CNSRPDX AS CNSRPDX, @NROLINEAS AS TODOS, @TERRORES AS ERRADOS, @TOK AS TOK;

			RETURN;
		END
		ELSE
		BEGIN
			SELECT 'KO', 'No se encontraron Datos para Procesar, Verfique e intente de nuevo' AS ERROR;

			RETURN;
		END
	END

	IF @METODO = 'VALIDAR_RPDX_EMPLEADO_NOVEDAD'
	BEGIN
		SELECT @DATOS = DATOS, @CODNOMINA = CODNOMINA
		FROM OPENJSON(@PARAMETROS) WITH (DATOS NVARCHAR(MAX) AS JSON, CODNOMINA VARCHAR(2) '$.CODNOMINA');

		SELECT @DESCRIPCIONEVENTO = '', @DESCRIDDX = '';

		SELECT @CNSRPDX = CNS, @ITEM = ID, @NUMDOC = NUMDOC, @DOCIDEMPLEADO = DOCIDEMPLEADO, @NOMBREEMPLEADO = NOMBREEMPLEADO, @IDEVENTO = IDEVENTO, @DIAS = DIAS, @HORAS = 
			HORAS, @FECHAINI_REG = COALESCE(TRY_CONVERT(DATETIME, LTRIM(RTRIM(FECHAINI_REG)), 120), TRY_CONVERT(DATETIME, LTRIM(RTRIM(FECHAINI_REG)), 23)), 
			@FECHAFIN_REG = COALESCE(TRY_CONVERT(DATETIME, LTRIM(RTRIM(FECHAFIN_REG)), 120), TRY_CONVERT(DATETIME, LTRIM(RTRIM(FECHAFIN_REG)), 23)), @ERROR = 
			ERRORTXT, @IDDIAGNOSTICO = IDDIAGNOSTICO
		FROM OPENJSON(@DATOS) WITH (
				CNS VARCHAR(20) '$.CNS', ID INT '$.ID', NUMDOC VARCHAR(20) '$.NUMDOC', DOCIDEMPLEADO VARCHAR(20) '$.DOCIDEMPLEADO', NOMBREEMPLEADO VARCHAR(250) 
				'$.NOMBREEMPLEADO', IDEVENTO VARCHAR(6) '$.IDEVENTO', DIAS INT '$.DIAS', HORAS INT '$.HORAS', FECHAINI_REG VARCHAR(20) '$.FECHAINI_REG', 
				FECHAFIN_REG VARCHAR(20) '$.FECHAFIN_REG', ERRORTXT VARCHAR(500) '$.ERRORTXT', IDDIAGNOSTICO VARCHAR(10) '$.IDDIAGNOSTICO'
				);

		PRINT 'Validaici�n de existencia de datos';

		SELECT @ER = 0, @ERROR = '', @CODCONCEPTO = NULL, @SEREPITE = NULL;

		IF NOT EXISTS (
				SELECT *
				FROM NEMP
				WHERE NUMDOC = @NUMDOC
				)
		BEGIN
			SELECT @ER = 1, @ERROR = @ERROR + ' - Codigo de contrato No existe';
		END

		IF NOT EXISTS (
				SELECT *
				FROM NEMP
				WHERE NUMDOC = @NUMDOC AND DOCIDEMPLEADO = @DOCIDEMPLEADO
				)
		BEGIN
			SELECT @ER = 1, @ERROR = @ERROR + ' - Documento del empleado no pertenece al numero de contrato';
		END

		IF NOT EXISTS (
				SELECT *
				FROM NEVE
				WHERE IDEVENTO = @IDEVENTO
				)
		BEGIN
			SELECT @ER = 1, @ERROR = @ERROR + ' - El id del evento no existe';
		END
		ELSE
		BEGIN
			SELECT @DESCRIPCIONEVENTO = DESCRIPCION
			FROM NEVE
			WHERE IDEVENTO = @IDEVENTO;

			SELECT @CODCONCEPTO = COALESCE((
						SELECT TOP 1 NULLIF(LTRIM(RTRIM(NEVED.CODCONCEPTO)), '')
						FROM NEVED
						WHERE NEVED.IDEVENTO = @IDEVENTO AND ISNULL(NEVED.CODCONCEPTO, '') <> ''
						ORDER BY NEVED.ITEM
						), NULLIF(LTRIM(RTRIM(NEVE.CODCONCEPTO)), ''))
			FROM NEVE
			WHERE NEVE.IDEVENTO = @IDEVENTO;

			SELECT @SEREPITE = CASE 
					WHEN EXISTS (
							SELECT 1
							FROM NCON
							WHERE ISNULL(NCON.SEREPITE, 'No') = 'Si' AND NCON.CODCONCEPTO IN (
									SELECT NEVE.CODCONCEPTO
									FROM NEVE
									WHERE NEVE.IDEVENTO = @IDEVENTO AND ISNULL(NEVE.CODCONCEPTO, '') <> ''
									
									UNION
									
									SELECT NEVED.CODCONCEPTO
									FROM NEVED
									WHERE NEVED.IDEVENTO = @IDEVENTO AND ISNULL(NEVED.CODCONCEPTO, '') <> ''
									)
							)
						THEN 'Si'
					ELSE 'No'
					END;
		END

		SELECT @HASIDDX = SOLDX
		FROM NEVE
		WHERE IDEVENTO = @IDEVENTO;

		IF @HASIDDX = 1
		BEGIN
			IF ISNULL(LTRIM(RTRIM(@IDDIAGNOSTICO)), '') = ''
			BEGIN
				SELECT @ER = 1, @ERROR = @ERROR + ' - El diagnostico para la novedad ' + @IDEVENTO + ' es obligatoria.';
			END
			ELSE
			BEGIN
				IF NOT EXISTS (
						SELECT 1
						FROM MDX
						WHERE IDDX = @IDDIAGNOSTICO AND ESTADO = 'Activo'
						)
				BEGIN
					SELECT @ER = 1, @ERROR = @ERROR + ' - El id del diagnostico no existe ';
				END
				ELSE
				BEGIN
					SELECT @DESCRIDDX = DESCRIPCION
					FROM MDX
					WHERE IDDX = @IDDIAGNOSTICO;
				END
			END
		END
		ELSE
		BEGIN
			SELECT @DESCRIDDX = '', @IDDIAGNOSTICO = NULL;
		END

		IF NOT EXISTS (
				SELECT *
				FROM NOMIE
				WHERE NUMDOC = @NUMDOC AND CODNOMINA = @CODNOMINA
				)
		BEGIN
			SELECT @ER = 1, @ERROR = @ERROR + ' - El Empleado ' + @DOCIDEMPLEADO + ' no existe dentro de la plantilla de la nomina';
		END
		ELSE
		BEGIN
			IF (
					(
						SELECT ESTADO
						FROM NOMIE
						WHERE CODNOMINA = @CODNOMINA AND NUMDOC = @NUMDOC
						) = 'Inactivo'
					)
			BEGIN
				SELECT ' - El Empleado ' + @DOCIDEMPLEADO + ' se encuentra inactivo en la plantilla de la nomina';
			END
		END

		SELECT @FECHAS_NOV = FECHAS_NOV
		FROM NEVE
		WHERE IDEVENTO = @IDEVENTO;

		IF @FECHAS_NOV = 1
		BEGIN
			IF @FECHAINI_REG IS NULL OR @FECHAFIN_REG IS NULL
			BEGIN
				SELECT @ER = 1, @ERROR = @ERROR + ' - Las fechas de registro para la novedad ' + @IDEVENTO + ' son obligatorias.';
			END
		END
		ELSE
		BEGIN
			SELECT @FECHAINI_REG = NULL, @FECHAFIN_REG = NULL;
		END

		SELECT @NOMBREEMPLEADO = CONCAT_WS(' ', NEMP.PRIMERNOMBRE, NEMP.SEGUNDONOMBRE, NEMP.PRIMERAPELLIDO, NEMP.SEGUNDOAPELLIDO)
		FROM NEMP
		WHERE NUMDOC = @NUMDOC;

		IF @ER = 0 AND ISNULL(@SEREPITE, 'No') <> 'Si' AND ISNULL(@IDEVENTO, '') <> ''
		BEGIN
			IF EXISTS (
					SELECT 1
					FROM RPDX AS R
					WHERE R.CNS = @CNSRPDX AND R.ITEM <> @ITEM AND R.ID1 = @NUMDOC AND ISNULL(R.CANTIDAD10, 0) = 0 AND EXISTS (
							SELECT 1
							FROM (
								SELECT NEVE.CODCONCEPTO
								FROM NEVE
								WHERE NEVE.IDEVENTO = R.ID3 AND ISNULL(NEVE.CODCONCEPTO, '') <> ''
								
								UNION
								
								SELECT NEVED.CODCONCEPTO
								FROM NEVED
								WHERE NEVED.IDEVENTO = R.ID3 AND ISNULL(NEVED.CODCONCEPTO, '') <> ''
								) AS CPrev
							INNER JOIN (
								SELECT NEVE.CODCONCEPTO
								FROM NEVE
								WHERE NEVE.IDEVENTO = @IDEVENTO AND ISNULL(NEVE.CODCONCEPTO, '') <> ''
								
								UNION
								
								SELECT NEVED.CODCONCEPTO
								FROM NEVED
								WHERE NEVED.IDEVENTO = @IDEVENTO AND ISNULL(NEVED.CODCONCEPTO, '') <> ''
								) AS CNew ON CPrev.CODCONCEPTO = CNew.CODCONCEPTO
							INNER JOIN NCON ON NCON.CODCONCEPTO = CNew.CODCONCEPTO AND ISNULL(NCON.SEREPITE, 'No') <> 'Si'
							)
					)
			BEGIN
				SELECT @ER = 1, @ERROR = @ERROR + ' - El concepto ' + ISNULL(@CODCONCEPTO, '') + ' asociado a la novedad ' + ISNULL(@IDEVENTO, '') + 
					' no permite repetirse. Ya existe otra novedad del mismo concepto para este empleado.';
			END
		END

		PRINT 'ACTUALIZO RPDX ITEM=' + CAST(@ITEM AS VARCHAR(20)) + '@ER=' + CAST(@ER AS VARCHAR(2));

		BEGIN TRY
			UPDATE RPDX
			SET ID1 = @NUMDOC, ID2 = @DOCIDEMPLEADO, STRINGGRANDE1 = @NOMBREEMPLEADO, ID3 = @IDEVENTO, CANTIDAD = @DIAS, CANTIDAD1 = @HORAS, STRINGMEDIO3 = @IDDIAGNOSTICO, 
				STRINGMEDIO1 = @DESCRIPCIONEVENTO, STRINGMEDIO2 = @DESCRIDDX, FECHA1 = @FECHAINI_REG, FECHA2 = @FECHAFIN_REG, CANTIDAD10 = @ER, STRINGMAX = @ERROR
			WHERE ITEM = @ITEM;
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' AS OK, ERROR
			FROM @TBLERRORES;

			RETURN;
		END

		SELECT @TERRORES = SUM(CASE 
					WHEN CANTIDAD10 = 1
						THEN 1
					ELSE 0
					END), @TOK = SUM(CASE 
					WHEN CANTIDAD10 = 1
						THEN 0
					ELSE 1
					END), @TODOS = COUNT(*)
		FROM RPDX
		WHERE CNS = @CNSRPDX;

		SELECT 'OK' AS OK, @TERRORES AS ERRADOS, @TOK AS TOK, @TODOS AS TODOS;

		RETURN;
	END

	IF @METODO = 'AGREGAR_NOVEDAD_EMPLEADOS'
	BEGIN
		DECLARE @ERROR_MSG AS NVARCHAR(MAX);

		SELECT @CNSRPDX = CNS, @CNSPAGO = CNSPAGO, @CODNOMINA = CODNOMINA
		FROM OPENJSON(@PARAMETROS) WITH (CNS VARCHAR(20) '$.CNS', CNSPAGO VARCHAR(20) '$.CNSPAGO', CODNOMINA VARCHAR(2) '$.CODNOMINA');

		DECLARE @FECHAINIPER AS DATETIME;
		DECLARE @FECHAFINPER AS DATETIME;

		SELECT @FECHAINIPER = FECHAINI, @FECHAFINPER = FECHAFIN
		FROM NPER
		WHERE CNSPAGO = @CNSPAGO;

		-- Inserta en bloque todas las novedades v�lidas
		INSERT INTO NEDIA (
			CNSPAGO, NUMDOC, FECHAINI, FECHAFIN, HORAS, MINUTOS, IDEVENTO, FACTOR, PAGO, OBSERVACION, CNSVAC, ITEM_VAC, FORMALIQUIDACION, CNSMASIVO, FECHAINI_REG, 
			FECHAFIN_REG, IDDX
			)
		SELECT @CNSPAGO, R.ID1, @FECHAINIPER, CASE 
				WHEN DATEADD(DAY, CASE 
							WHEN R.CANTIDAD > 0
								THEN R.CANTIDAD
							ELSE R.CANTIDAD1 / 8
							END, @FECHAINIPER) = DATEADD(DAY, 1, N.FECHAFIN)
					THEN N.FECHAFIN
				ELSE DATEADD(DAY, CASE 
							WHEN R.CANTIDAD > 0
								THEN R.CANTIDAD
							ELSE R.CANTIDAD1 / 8
							END, @FECHAINIPER)
				END, CASE 
				WHEN R.CANTIDAD > 0
					THEN CONVERT(INT, (E.HORASDELABOR / CAST(E.DIASXCARGO AS FLOAT)) * R.CANTIDAD) + ISNULL(R.CANTIDAD1, 0)
				ELSE ISNULL(R.CANTIDAD1, 0)
				END, CASE 
				WHEN R.CANTIDAD > 0
					THEN DBO.FNQ_NOVEDAD_MINUTOS(R.CANTIDAD, E.HORASDELABOR)
				ELSE 0
				END, R.ID3, (
				SELECT TOP 1 FACTOR
				FROM NEVED
				WHERE IDEVENTO = R.ID3
				ORDER BY FECHAINI DESC
				), 0, '', '', 0, 'PorFecha', R.CNS, R.FECHA1, R.FECHA2, R.STRINGMEDIO3
		FROM RPDX AS R
		INNER JOIN NEMP AS E ON R.ID1 = E.NUMDOC
		INNER JOIN NPER AS N ON N.CNSPAGO = @CNSPAGO
		WHERE R.CNS = @CNSRPDX AND ISNULL(R.CANTIDAD10, 0) = 0 AND (R.CANTIDAD > 0 OR R.CANTIDAD1 > 0) AND EXISTS (
				SELECT 1
				FROM NOMIE
				WHERE NUMDOC = R.ID1 AND CODNOMINA = @CODNOMINA AND ESTADO = 'Activo'
				);

		SELECT 'OK' AS OK;

		SELECT DISTINCT NEDIA.NUMDOC
		FROM RPDX
		INNER JOIN NEDIA ON RPDX.ID1 = NEDIA.NUMDOC
		WHERE CNS = @CNSRPDX AND NEDIA.FECHAINI BETWEEN @FECHAINIPER AND @FECHAFINPER AND NEDIA.FECHAFIN BETWEEN @FECHAINIPER AND @FECHAFINPER;

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' AS OK, ERROR
			FROM @TBLERRORES;

			RETURN;
		END

		SELECT 'OK' AS OK;
	END

