					WHEN CANTIDAD10 = 1
						THEN 0
					ELSE 1
					END), @TODOS = COUNT(*)
		FROM RPDX
		WHERE CNS = @CNSRPDX;

		SELECT 'OK' AS OK, @TERRORES AS ERRADOS, @TOK AS TOK, @TODOS AS TODOS;

		RETURN;
	END
