SET NOCOUNT ON;
DECLARE @NF VARCHAR(20) = N'FVSF1077';

SELECT F.N_FACTURA, F.CONTABILIZADA, F.NROCOMPROBANTE, F.FACTE, F.IMPRESO, F.INDCARTERA, F.INDCXC
FROM dbo.FTR F WHERE F.N_FACTURA = @NF;

SELECT FCJ.CNSFACJ, FCJ.CODCAJA, FCJ.ESTADO, FCJ.CONTABILIZADA, FCJ.NROCOMPROBANTE, FCJ.PROCEDENCIA, FCJ.VALORTOTAL, FCJ.CERRADA
FROM dbo.FCJ FCJ WHERE FCJ.N_FACTURA = @NF;

SELECT P.NROCOMPROBANTE, P.PROCEDENCIA, P.ESTADO, P.REFERENCIA1
FROM dbo.MCP P
WHERE P.NROCOMPROBANTE IN (SELECT FCJ.NROCOMPROBANTE FROM dbo.FCJ FCJ WHERE FCJ.N_FACTURA = @NF AND FCJ.NROCOMPROBANTE IS NOT NULL AND FCJ.NROCOMPROBANTE <> '');

SELECT M.CNSMOV, M.N_FACTURA, M.CONTABILIZADA, M.NROCOMPROBANTE
FROM dbo.IMOV M WHERE M.NODOCUMENTO = @NF OR M.N_FACTURA = @NF;
