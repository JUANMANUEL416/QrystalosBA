IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='FNK_INFO_NEMPHIS_NEMP' AND XTYPE='TF')
BEGIN
    DROP FUNCTION FNK_INFO_NEMPHIS_NEMP
END
GO
CREATE FUNCTION DBO.FNK_INFO_NEMPHIS_NEMP(@FECHA DATETIME, @NUMDOC VARCHAR(20))
RETURNS @TABLA  
 TABLE (NUMDOC            VARCHAR(20) COLLATE database_default,
        ITEM              DECIMAL(14,2),
        BASICO            DECIMAL(15,6),
        HORASXCARGO       INT,
        DIASXCARGO        INT,
        FECHAING          DATETIME,
        CODCARGO          VARCHAR(20) COLLATE database_default,
        NIVEL             VARCHAR(10) COLLATE database_default,
        GRADO             VARCHAR(10) COLLATE database_default,
        CODPLANTA         VARCHAR(20) COLLATE database_default,
        IDAREA            VARCHAR(20) COLLATE database_default,
        CCOSTO            VARCHAR(20) COLLATE database_default,
        FECHAMOV          DATETIME)
AS    
BEGIN 
    INSERT INTO @TABLA(NUMDOC, ITEM, BASICO, HORASXCARGO, DIASXCARGO, FECHAING, CODCARGO, NIVEL, GRADO, CODPLANTA, IDAREA, CCOSTO, FECHAMOV)
    SELECT NUMDOC, ITEM, BASICO, HORASDELABOR, DIASXCARGO, FECHAINGRESO, CODCARGO, NIVEL, GRADO, CODPLANTA, IDAREA, CCOSTO, FECHAMOV
    FROM (
        SELECT ROW_NUMBER() OVER (PARTITION BY NUMDOC ORDER BY FECHAMOV DESC, ITEM DESC) ID,
            NUMDOC, ITEM, BASICO, HORASDELABOR, DIASXCARGO, FECHAINGRESO, CODCARGO, NIVEL, GRADO, CODPLANTA, IDAREA, CCOSTO, FECHAMOV 
        FROM NEMPHIS WHERE NUMDOC=@NUMDOC AND FECHAMOV<=@FECHA
    ) AS X WHERE ID=1

    RETURN     
END
