CREATE OR ALTER PROCEDURE DBO.SPQ_IPAC
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @PARAMETROS NVARCHAR(MAX), @MODELO         VARCHAR(100),   @METODO         VARCHAR(100)
DECLARE  @USUARIO    VARCHAR(20),   @IDPRINACTIVO    VARCHAR(10),		@DESCRIPCION	VARCHAR(1000)
DECLARE	 @IDITAR	 VARCHAR(2)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDPRINACTIVO = IDPRINACTIVO, @DESCRIPCION = DESCRIPCION, @IDITAR = IDITAR 
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				IDPRINACTIVO VARCHAR(10)  '$.IDPRINACTIVO', DESCRIPCION VARCHAR(1000)  '$.DESCRIPCION',
				IDITAR		VARCHAR(2)  '$.IDITAR'
			)

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'EL PRINCIPIO ACTIVO YA EXISTE'
			WHERE EXISTS (SELECT * FROM IPAC WHERE IDPRINACTIVO = @IDPRINACTIVO)

			IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
			BEGIN
				INSERT INTO IPAC (IDPRINACTIVO ,DESCRIPCION ,IDITAR ) 
				SELECT @IDPRINACTIVO, @DESCRIPCION, @IDITAR
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ACTUALIZAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDPRINACTIVO = IDPRINACTIVO, @DESCRIPCION = DESCRIPCION, @IDITAR = IDITAR 
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				IDPRINACTIVO VARCHAR(10)  '$.IDPRINACTIVO', DESCRIPCION VARCHAR(1000)  '$.DESCRIPCION',
				IDITAR		VARCHAR(2)  '$.IDITAR'
			)

			UPDATE IPAC SET DESCRIPCION = @DESCRIPCION, IDITAR = @IDITAR WHERE IDPRINACTIVO = @IDPRINACTIVO			
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
	
	IF @METODO = 'ELIMINAR'
	BEGIN
		BEGIN TRY
			SELECT @IDPRINACTIVO = JSON_VALUE(@PARAMETROS, '$.IDPRINACTIVO')

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'EL PRINCIPIO ACTIVO TIENE ARTICULOS RELACIONADOS (IART)'
			WHERE EXISTS (SELECT * FROM IART WHERE IDPRINACTIVO = @IDPRINACTIVO)

			IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
			BEGIN
				DELETE FROM IPAC WHERE IDPRINACTIVO = @IDPRINACTIVO
			END		
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
END
