CREATE OR ALTER PROCEDURE dbo.SPQ_NOM_NFUN @JSON NVARCHAR(MAX) WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100)
DECLARE @USUARIO VARCHAR(20), @PROCESO VARCHAR(20)
DECLARE @CODNOVEFU VARCHAR(10), @DESCRIPCION VARCHAR(100), @TIPO VARCHAR(12), @DE_CONCEPTOS SMALLINT, @DE_EMPLEADOS SMALLINT
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @CODNOVEFU = CODNOVEFU, @DESCRIPCION = DESCRIPCION, @TIPO = TIPO, @DE_CONCEPTOS = DE_CONCEPTOS, @DE_EMPLEADOS = DE_EMPLEADOS,@PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					CODNOVEFU VARCHAR(10) '$.CODNOVEFU', DESCRIPCION VARCHAR(100) '$.DESCRIPCION', TIPO VARCHAR(12) '$.TIPO',DE_CONCEPTOS SMALLINT '$.DE_CONCEPTOS',DE_EMPLEADOS SMALLINT '$.DE_EMPLEADOS', PROCESO 
					VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
            BEGIN TRY
				INSERT INTO @TBLERRORES (ERROR)
					SELECT 'LA NOVEDAD YA SE ENCUENTRA REGISTRADO'
					WHERE EXISTS (
							SELECT 1
							FROM NFUN
							WHERE CODNOVEFU = @CODNOVEFU
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
                        INSERT INTO NFUN (CODNOVEFU,DESCRIPCION ,TIPO, DE_CONCEPTOS, DE_EMPLEADOS) VALUES (@CODNOVEFU,@DESCRIPCION,@TIPO,@DE_CONCEPTOS,@DE_EMPLEADOS)
                    END
                    	END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					UPDATE NFUN
					SET DESCRIPCION = @DESCRIPCION, TIPO = @TIPO,DE_CONCEPTOS = @DE_CONCEPTOS,DE_EMPLEADOS = @DE_EMPLEADOS
					WHERE CODNOVEFU = @CODNOVEFU
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

    IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @CODNOVEFU = CODNOVEFU
		FROM OPENJSON(@PARAMETROS) WITH (CODNOVEFU VARCHAR(10) '$.CODNOVEFU')

		BEGIN TRY
			DELETE
			FROM NFUN
			WHERE CODNOVEFU = @CODNOVEFU
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
