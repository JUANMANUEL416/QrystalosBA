IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='SPK_ANULAR_ITEM_CXP' AND XTYPE='P')
BEGIN
   DROP PROCEDURE SPK_ANULAR_ITEM_CXP
END

GO
CREATE PROCEDURE DBO.SPK_ANULAR_ITEM_CXP
	@CNSFCXP VARCHAR(20),
	@ITEM VARCHAR(20),
	@COMPANIA VARCHAR(2),
	@SEDE VARCHAR(5)
WITH ENCRYPTION
AS
DECLARE @VALOR_ITEM DECIMAL(14,2)
DECLARE @VLR_DESCUENTO_ITEM DECIMAL(14,2)
DECLARE @VLR_IVA_ITEM DECIMAL(14,2)
DECLARE @VLR_NETO_ITEM DECIMAL(14,2)
DECLARE @N_PRESUP VARCHAR(16) 
DECLARE @ITEM_PRESUP INT
DECLARE @IDCLASEIMP VARCHAR(2)
DECLARE @PROCEDENCIA VARCHAR(10)  
DECLARE @IDARTICULO VARCHAR(20)
DECLARE @CNSMOV VARCHAR(20)
DECLARE @CNSFCOM VARCHAR(20)
DECLARE @NOLOTE VARCHAR(20)
DECLARE @IDCATEGORIA VARCHAR(10)
DECLARE @NROCOMPROBANTEANT VARCHAR(20)
BEGIN
   SELECT @IDCLASEIMP=IDCLASEIMP,@PROCEDENCIA=PROCEDENCIA FROM FCXP WHERE CNSFCXP=@CNSFCXP
   IF @PROCEDENCIA='Salud'
      SELECT @VALOR_ITEM    = VALOR,    @VLR_DESCUENTO_ITEM = VLR_DESCUENTO, @VLR_IVA_ITEM = VLR_IVA,
             @VLR_NETO_ITEM = VLR_NETO, @N_PRESUP           = N_PRESUP,      @ITEM_PRESUP  = ITEM_PRESUP
      FROM   FCXPD 
      WHERE  CNSFCXP = @CNSFCXP 
      AND    ITEM    = @ITEM
   ELSE
   IF @PROCEDENCIA='Compras'
   BEGIN
      SELECT @VALOR_ITEM = VALOR,      @VLR_DESCUENTO_ITEM = VLR_DESCUENTO, @VLR_IVA_ITEM = VLR_IVA, @VLR_NETO_ITEM = VLR_NETO,
             @IDARTICULO = IDSERVICIO, @CNSMOV             = N_PRESUP,      @NOLOTE       = NOLOTE
      FROM   FCXPD 
      WHERE  CNSFCXP=@CNSFCXP AND ITEM=@ITEM
      SELECT @CNSFCOM=CNSFCOM FROM IMOV WHERE CNSMOV=@CNSMOV
   END
   ELSE
   IF @PROCEDENCIA='Servicios'
      SELECT @VALOR_ITEM = VALOR,      @VLR_DESCUENTO_ITEM = VLR_DESCUENTO, @VLR_IVA_ITEM = VLR_IVA, @VLR_NETO_ITEM = VLR_NETO,
             @IDARTICULO = IDSERVICIO, @CNSFCOM            = N_PRESUP
      FROM   FCXPD 
      WHERE  CNSFCXP = @CNSFCXP 
      AND    ITEM=@ITEM
   
   DELETE FROM FCXPD WHERE CNSFCXP=@CNSFCXP AND ITEM=@ITEM
   
   UPDATE FCXP SET VALOR   = VALOR - @VALOR_ITEM,     VLR_DESCUENTO = VLR_DESCUENTO - @VLR_DESCUENTO_ITEM,
                   VLR_IVA = VLR_IVA - @VLR_IVA_ITEM, VLR_NETO      = VLR_NETO - @VLR_NETO_ITEM,
                   SALDO   = SALDO - @VLR_NETO_ITEM - ISNULL(VLR_NOTASDEBITO,0) + ISNULL(VLR_NOTASCREDITO,0)
   WHERE  CNSFCXP = @CNSFCXP
   
   IF @PROCEDENCIA='Salud'
   BEGIN 
      UPDATE FXPD SET ESTADO='P' WHERE N_PRESUP=@N_PRESUP AND ITEM=@ITEM_PRESUP
      
      UPDATE FXP SET ESTADO='P'  
      FROM FXP A INNER JOIN FXPD B ON A.N_PRESUP=B.N_PRESUP AND A.IDTERCERO=B.IDTERCERO
      WHERE A.N_PRESUP=@N_PRESUP AND B.ITEM=@ITEM_PRESUP
   END
   ELSE
   IF @PROCEDENCIA='Compras'
   BEGIN
      UPDATE IMOVH SET ENCXP=0 WHERE CNSMOV=@CNSMOV AND IDARTICULO=@IDARTICULO AND NOLOTEPEDIDO=@NOLOTE
      PRINT 'REVISO LOS ANTICIPOS LEGALIZADOS'
      IF (SELECT COUNT(*) FROM FCXPD WHERE CNSFCXP=@CNSFCXP AND N_PRESUP=@CNSMOV)<=0
      BEGIN
         IF EXISTS( SELECT * FROM ANT WHERE CNSFCOM=@CNSFCOM AND CNSFCXP=@CNSFCXP AND ESTADO='L')
         BEGIN
            SELECT @NROCOMPROBANTEANT = NROCOMPROBANTE FROM ANT WHERE CNSFCOM=@CNSFCOM AND CNSFCXP=@CNSFCXP AND ESTADO='L'
            UPDATE  ANT SET ESTADO='A'  WHERE CNSFCOM=@CNSFCOM AND CNSFCXP=@CNSFCXP AND ESTADO='L'
            IF EXISTS(SELECT * FROM MCP WHERE NROCOMPROBANTE=@NROCOMPROBANTEANT)
            BEGIN
               ALTER TABLE MCP DISABLE TRIGGER ALL;
               UPDATE MCP SET ANULADO=1,ESTADO=0 WHERE NROCOMPROBANTE=@NROCOMPROBANTEANT
               ALTER TABLE MCP ENABLE TRIGGER ALL;
            END
            ELSE
            BEGIN 
               DELETE MCHE WHERE  NROCOMPROBANTE=@NROCOMPROBANTEANT
               DELETE MCPE WHERE  NROCOMPROBANTE=@NROCOMPROBANTEANT
            END
         END
      END
   END
   IF @PROCEDENCIA='Servicios'
      UPDATE FCOM SET ENCXP=0 WHERE CNSFCOM=@CNSFCOM
   SET @IDCATEGORIA=(SELECT DBO.FNK_VALORVARIABLE('TERCATPROVEEDOR'))
   EXEC SPK_IMPUESTOS_CXP @CNSFCXP,@IDCATEGORIA,@COMPANIA,@SEDE
END
