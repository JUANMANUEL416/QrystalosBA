SET NOCOUNT ON;
SELECT TOP 10 D.CNSDOCUMENTO, D.ITEM, D.FECHA
FROM dbo.FDIANR D
WHERE D.METODO = N'SendBillSync' AND D.TIPO = N'FV'
  AND CAST(D.xml_solicitud AS NVARCHAR(MAX)) LIKE N'%FVSF1077%'
ORDER BY D.FECHA DESC;

SELECT TOP 5 D.CNSDOCUMENTO, D.ITEM
FROM dbo.FDIANR D
WHERE D.METODO = N'SendBillSync' AND D.TIPO = N'FV'
  AND CAST(D.xml_solicitud AS NVARCHAR(MAX)) LIKE N'%FVSF1077%'
  AND CAST(D.xml_solicitud AS NVARCHAR(MAX)) LIKE N'%59200%';
