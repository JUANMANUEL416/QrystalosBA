CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NEMPHIS @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @DATOS NVARCHAR(MAX)
DECLARE @USUARIO VARCHAR(20), @PROCESO VARCHAR(20)
DECLARE @NUMDOC VARCHAR(20), @FECHAMOV DATETIME, @SEXO VARCHAR(9), @IDAREA VARCHAR(20), @CCOSTO VARCHAR(20), @FECHAINGRESO DATETIME, @ESTADO VARCHAR(12), 
	@FECHARETIRO DATETIME, @CAUSARETIRO VARCHAR(5), @BASICO DECIMAL(14, 2), @CODCARGO VARCHAR(20), @NIVEL VARCHAR(10), @GRADO VARCHAR(10), @HORASDELABOR SMALLINT, 
	@DIASXCARGO DECIMAL(14, 2), @CODPLANTA VARCHAR(20), @TIPOSALARIO VARCHAR(20), @TALLA_CALZADO DECIMAL(14, 2), @TALLA_CAMISA VARCHAR(12), @TALLA_PANTALON DECIMAL
	(14, 2), @GRUPOSANGUINEO VARCHAR(3), @LIBRETAMILITAR VARCHAR(20), @ESTADOCIVIL VARCHAR(20), @TIPOCONTRATO VARCHAR(20), @CODNOMINA VARCHAR(2), @CTA_BCO VARCHAR(
		40), @BANCO VARCHAR(3), @SUCURSAL VARCHAR(2), @FNACIMIENTO DATETIME, @FULTIMOPAGO DATETIME, @TIPOCESANTIAS VARCHAR(12), @FLEY50 DATETIME, @ENSINDICATO 
	VARCHAR(2), @FORMADEPAGO VARCHAR(20), @FONDODEVIVIENDA VARCHAR(20), @USUARIOMOD VARCHAR(12), @FECHAMOD DATETIME, @SYS_COMPUTERNAME VARCHAR(254), @OPERACION 
	VARCHAR(12), @ITEM DECIMAL(14, 0)
DECLARE @FECHAMOV_TXT VARCHAR(40), @FECHAINGRESO_TXT VARCHAR(40), @FECHARETIRO_TXT VARCHAR(40), @FNACIMIENTO_TXT VARCHAR(40), @FULTIMOPAGO_TXT VARCHAR(40), 
	@FLEY50_TXT VARCHAR(40), @FECHAMOD_TXT VARCHAR(40)
DECLARE @IDSEDE VARCHAR(5)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
		FROM USUSU
		WHERE USUARIO = @USUARIO

		SELECT @IDSEDE = IDSEDE
		FROM UBEQ
		WHERE SYS_ComputerName = @SYS_COMPUTERNAME

		BEGIN TRY
			SELECT @NUMDOC = NUMDOC, @SEXO = SEXO, @IDAREA = IDAREA, @CCOSTO = CCOSTO, @FECHAINGRESO_TXT = FECHAINGRESO, @ESTADO = ESTADO, @FECHARETIRO_TXT = FECHARETIRO, 
				@CAUSARETIRO = CAUSARETIRO, @BASICO = BASICO, @CODCARGO = CODCARGO, @NIVEL = NIVEL, @GRADO = GRADO, @HORASDELABOR = HORASDELABOR, @DIASXCARGO = DIASXCARGO
				, @CODPLANTA = CODPLANTA, @TIPOSALARIO = TIPOSALARIO, @TALLA_CALZADO = TALLA_CALZADO, @TALLA_CAMISA = TALLA_CAMISA, @TALLA_PANTALON = TALLA_PANTALON, 
				@GRUPOSANGUINEO = GRUPOSANGUINEO, @LIBRETAMILITAR = LIBRETAMILITAR, @ESTADOCIVIL = ESTADOCIVIL, @TIPOCONTRATO = TIPOCONTRATO, @CODNOMINA = CODNOMINA
				, @CTA_BCO = CTA_BCO, @BANCO = BANCO, @SUCURSAL = SUCURSAL, @FNACIMIENTO_TXT = FNACIMIENTO, @FULTIMOPAGO_TXT = FULTIMOPAGO, @TIPOCESANTIAS = 
				TIPOCESANTIAS, @FLEY50_TXT = FLEY50, @ENSINDICATO = ENSINDICATO, @FORMADEPAGO = FORMADEPAGO, @FONDODEVIVIENDA = FONDODEVIVIENDA, @PROCESO = PROCESO, 
				@FECHAMOV_TXT = FECHAMOV, @USUARIOMOD = USUARIOMOD, @FECHAMOD_TXT = FECHAMOD, @SYS_COMPUTERNAME = COALESCE(NULLIF(SYS_COMPUTERNAME, ''), 
					@SYS_COMPUTERNAME), @OPERACION = OPERACION, @ITEM = ITEM
			FROM OPENJSON(@PARAMETROS) WITH (
					NUMDOC VARCHAR(20) '$.NUMDOC', SEXO VARCHAR(9) '$.SEXO', IDAREA VARCHAR(20) '$.IDAREA', CCOSTO VARCHAR(20) '$.CCOSTO', FECHAINGRESO VARCHAR(40) 
					'$.FECHAINGRESO', ESTADO VARCHAR(12) '$.ESTADO', FECHARETIRO VARCHAR(40) '$.FECHARETIRO', CAUSARETIRO VARCHAR(5) '$.CAUSARETIRO', BASICO 
					DECIMAL(14, 2) '$.BASICO', CODCARGO VARCHAR(20) '$.CODCARGO', NIVEL VARCHAR(10) '$.NIVEL', GRADO VARCHAR(10) '$.GRADO', HORASDELABOR SMALLINT 
					'$.HORASDELABOR', DIASXCARGO DECIMAL(14, 2) '$.DIASXCARGO', CODPLANTA VARCHAR(20) '$.CODPLANTA', TIPOSALARIO VARCHAR(20) '$.TIPOSALARIO', 
					TALLA_CALZADO DECIMAL(14, 2) '$.TALLA_CALZADO', TALLA_CAMISA VARCHAR(12) '$.TALLA_CAMISA', TALLA_PANTALON DECIMAL(14, 2) '$.TALLA_PANTALON', 
					GRUPOSANGUINEO VARCHAR(3) '$.GRUPOSANGUINEO', LIBRETAMILITAR VARCHAR(20) '$.LIBRETAMILITAR', ESTADOCIVIL VARCHAR(20) '$.ESTADOCIVIL', 
					TIPOCONTRATO VARCHAR(20) '$.TIPOCONTRATO', CODNOMINA VARCHAR(2) '$.CODNOMINA', CTA_BCO VARCHAR(40) '$.CTA_BCO', BANCO VARCHAR(3) '$.BANCO', 
					SUCURSAL VARCHAR(2) '$.SUCURSAL', FNACIMIENTO VARCHAR(40) '$.FNACIMIENTO', FULTIMOPAGO VARCHAR(40) '$.FULTIMOPAGO', TIPOCESANTIAS VARCHAR(12
					) '$.TIPOCESANTIAS', FLEY50 VARCHAR(40) '$.FLEY50', ENSINDICATO VARCHAR(2) '$.ENSINDICATO', FORMADEPAGO VARCHAR(20) '$.FORMADEPAGO', 
					FONDODEVIVIENDA VARCHAR(20) '$.FONDODEVIVIENDA', PROCESO VARCHAR(20) '$.PROCESO', FECHAMOV VARCHAR(40) '$.FECHAMOV', USUARIOMOD VARCHAR(12) 
					'$.USUARIOMOD', FECHAMOD VARCHAR(40) '$.FECHAMOD', SYS_COMPUTERNAME VARCHAR(254) '$.SYS_COMPUTERNAME', OPERACION VARCHAR(12) '$.OPERACION', 
					ITEM DECIMAL(14, 0) '$.ITEM'
					)

			-- yyyy-mm-dd (23) no depende del LANGUAGE; 120 cubre ISO con hora; 103 cubre dd/mm/yyyy
			SET @FECHAMOV = COALESCE(TRY_CONVERT(DATETIME, NULLIF(LTRIM(RTRIM(@FECHAMOV_TXT)), ''), 23), TRY_CONVERT(DATETIME, NULLIF(LTRIM(RTRIM(REPLACE(
										REPLACE(@FECHAMOV_TXT, 'T', ' '), 'Z', ''))), ''), 120), TRY_CONVERT(DATETIME, NULLIF(LTRIM(RTRIM(@FECHAMOV_TXT)), ''), 
						103))
			SET @FECHAINGRESO = COALESCE(TRY_CONVERT(DATETIME, NULLIF(LTRIM(RTRIM(@FECHAINGRESO_TXT)), ''), 23), TRY_CONVERT(DATETIME, NULLIF(LTRIM(RTRIM(
									REPLACE(REPLACE(@FECHAINGRESO_TXT, 'T', ' '), 'Z', ''))), ''), 120), TRY_CONVERT(DATETIME, NULLIF(LTRIM(RTRIM(
									@FECHAINGRESO_TXT)), ''), 103))
			SET @FECHARETIRO = COALESCE(TRY_CONVERT(DATETIME, NULLIF(LTRIM(RTRIM(@FECHARETIRO_TXT)), ''), 23), TRY_CONVERT(DATETIME, NULLIF(LTRIM(RTRIM(
									REPLACE(REPLACE(@FECHARETIRO_TXT, 'T', ' '), 'Z', ''))), ''), 120), TRY_CONVERT(DATETIME, NULLIF(LTRIM(RTRIM(
									@FECHARETIRO_TXT)), ''), 103))
			SET @FNACIMIENTO = COALESCE(TRY_CONVERT(DATETIME, NULLIF(LTRIM(RTRIM(@FNACIMIENTO_TXT)), ''), 23), TRY_CONVERT(DATETIME, NULLIF(LTRIM(RTRIM(
									REPLACE(REPLACE(@FNACIMIENTO_TXT, 'T', ' '), 'Z', ''))), ''), 120), TRY_CONVERT(DATETIME, NULLIF(LTRIM(RTRIM(
									@FNACIMIENTO_TXT)), ''), 103))
			SET @FULTIMOPAGO = COALESCE(TRY_CONVERT(DATETIME, NULLIF(LTRIM(RTRIM(@FULTIMOPAGO_TXT)), ''), 23), TRY_CONVERT(DATETIME, NULLIF(LTRIM(RTRIM(
									REPLACE(REPLACE(@FULTIMOPAGO_TXT, 'T', ' '), 'Z', ''))), ''), 120), TRY_CONVERT(DATETIME, NULLIF(LTRIM(RTRIM(
									@FULTIMOPAGO_TXT)), ''), 103))
			SET @FLEY50 = COALESCE(TRY_CONVERT(DATETIME, NULLIF(LTRIM(RTRIM(@FLEY50_TXT)), ''), 23), TRY_CONVERT(DATETIME, NULLIF(LTRIM(RTRIM(REPLACE(REPLACE(
											@FLEY50_TXT, 'T', ' '), 'Z', ''))), ''), 120), TRY_CONVERT(DATETIME, NULLIF(LTRIM(RTRIM(@FLEY50_TXT)), ''), 103))
			SET @FECHAMOD = COALESCE(TRY_CONVERT(DATETIME, NULLIF(LTRIM(RTRIM(@FECHAMOD_TXT)), ''), 23), TRY_CONVERT(DATETIME, NULLIF(LTRIM(RTRIM(REPLACE(
										REPLACE(@FECHAMOD_TXT, 'T', ' '), 'Z', ''))), ''), 120), TRY_CONVERT(DATETIME, NULLIF(LTRIM(RTRIM(@FECHAMOD_TXT)), ''), 
						103))

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO NEMPHIS (
						NUMDOC, FECHAMOV, SEXO, IDAREA, CCOSTO, FECHAINGRESO, ESTADO, FECHARETIRO, CAUSARETIRO, BASICO, CODCARGO, NIVEL, GRADO, HORASDELABOR, 
						DIASXCARGO, CODPLANTA, TIPOSALARIO, TALLA_CALZADO, TALLA_CAMISA, TALLA_PANTALON, GRUPOSANGUINEO, LIBRETAMILITAR, ESTADOCIVIL, 
						TIPOCONTRATO, CODNOMINA, CTA_BCO, BANCO, SUCURSAL, FNACIMIENTO, FULTIMOPAGO, TIPOCESANTIAS, FLEY50, ENSINDICATO, FORMADEPAGO, 
						FONDODEVIVIENDA, USUARIOMOD, FECHAMOD, SYS_COMPUTERNAME, OPERACION
						)
					SELECT @NUMDOC, @FECHAMOV, @SEXO, @IDAREA, @CCOSTO, @FECHAINGRESO, @ESTADO, @FECHARETIRO, @CAUSARETIRO, @BASICO, @CODCARGO, @NIVEL, @GRADO, 
						@HORASDELABOR, @DIASXCARGO, @CODPLANTA, @TIPOSALARIO, @TALLA_CALZADO, @TALLA_CAMISA, @TALLA_PANTALON, @GRUPOSANGUINEO, @LIBRETAMILITAR
						, @ESTADOCIVIL, @TIPOCONTRATO, @CODNOMINA, @CTA_BCO, @BANCO, @SUCURSAL, @FNACIMIENTO, @FULTIMOPAGO, @TIPOCESANTIAS, @FLEY50, @ENSINDICATO
						, @FORMADEPAGO, @FONDODEVIVIENDA, @USUARIOMOD, @FECHAMOD, @SYS_COMPUTERNAME, @OPERACION
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					UPDATE NEMPHIS
					SET SEXO = @SEXO, FECHAMOV = @FECHAMOV, IDAREA = @IDAREA, CCOSTO = @CCOSTO, FECHAINGRESO = @FECHAINGRESO, ESTADO = @ESTADO, FECHARETIRO = @FECHARETIRO, 
						CAUSARETIRO = @CAUSARETIRO, BASICO = @BASICO, CODCARGO = @CODCARGO, NIVEL = @NIVEL, GRADO = @GRADO, HORASDELABOR = @HORASDELABOR, DIASXCARGO = 
						@DIASXCARGO, CODPLANTA = @CODPLANTA, TIPOSALARIO = @TIPOSALARIO, TALLA_CALZADO = @TALLA_CALZADO, TALLA_CAMISA = @TALLA_CAMISA, 
						TALLA_PANTALON = @TALLA_PANTALON, GRUPOSANGUINEO = @GRUPOSANGUINEO, LIBRETAMILITAR = @LIBRETAMILITAR, ESTADOCIVIL = @ESTADOCIVIL, 
						TIPOCONTRATO = @TIPOCONTRATO, CODNOMINA = @CODNOMINA, CTA_BCO = @CTA_BCO, BANCO = @BANCO, SUCURSAL = @SUCURSAL, FNACIMIENTO = @FNACIMIENTO, 
						FULTIMOPAGO = @FULTIMOPAGO, TIPOCESANTIAS = @TIPOCESANTIAS, FLEY50 = @FLEY50, ENSINDICATO = @ENSINDICATO, FORMADEPAGO = @FORMADEPAGO, 
						FONDODEVIVIENDA = @FONDODEVIVIENDA, USUARIOMOD = @USUARIOMOD, FECHAMOD = @FECHAMOD, OPERACION = @OPERACION, SYS_COMPUTERNAME = 
						@SYS_COMPUTERNAME
					WHERE NUMDOC = @NUMDOC AND ITEM = @ITEM
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @NUMDOC = NUMDOC, @ITEM = ITEM
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC', ITEM DECIMAL(14, 0) '$.ITEM')

		BEGIN TRY
			DELETE
			FROM NEMPHIS
			WHERE NUMDOC = @NUMDOC AND ITEM = @ITEM
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
