						OR COALESCE(V.VLR_CXPA_ACU, 0) <> 0
						OR COALESCE(V.VLR_CXPA_MES, 0) <> 0
						OR COALESCE(V.VLR_PAGA_ACU, 0) <> 0
						OR COALESCE(V.VLR_PAGA_MES, 0) <> 0
					)
				)
				OR (
					@VIGENCIA = N'Recupera'
					AND (
						COALESCE(V.VLR_CDPV_ACU, 0) <> 0
						OR COALESCE(V.VLR_RPV_ACU, 0) <> 0
						OR COALESCE(V.VLR_CXPV_ACU, 0) <> 0
						OR COALESCE(V.VLR_PAGV_ACU, 0) <> 0
					)
				)
			)
		ORDER BY V.ORDEN, V.RUBRO, V.MES, V.CCOSTO, V.IDTIPOMOV

		RETURN
	END

	IF @METODO IN ('PTOI_EjecucionxCCosto', 'PTOI_Ejecucion_Anual_RubroxCCosto')
	BEGIN
		IF @COMPANIA_PARAM IS NULL OR @CONSECUTIVO IS NULL
		BEGIN
			SELECT 'KO' AS OK, 'COMPANIA y CONSECUTIVO requeridos' AS ERROR
			RETURN
		END
		IF OBJECT_ID('dbo.VWK_PTOI_EJE', 'V') IS NULL
		BEGIN
			SELECT 'KO' AS OK, 'Vista dbo.VWK_PTOI_EJE no existe en la BD.' AS ERROR
			RETURN
		END

		IF @VIGENCIA IS NULL OR LTRIM(RTRIM(@VIGENCIA)) = N''
			SET @VIGENCIA = N'Actual'

		SELECT 'OK' AS OK

		SELECT
			V.COMPANIA,
			V.CCOSTO,
			V.CONSECUTIVO,
			V.MES,
			V.IDTIPOMOV,
			V.RUBRO,
			V.RECURSO,
			V.NOMRUBRO,
			@VIGENCIA AS VIGENCIA,
			V.PTPTO_INICIAL,
			V.VLR_INICIAL,
			V.VLR_TDB,
			V.VLR_TCR,
			V.VLR_ACU_MDB,
			V.VLR_ACU_MCR,
			V.VLR_MDB,
			V.VLR_MCR,
			V.VLR_FINAL,
			CASE @VIGENCIA
				WHEN N'Anterior' THEN V.VLR_RECOA_ACU
				WHEN N'Recupera'  THEN V.VLR_RECOR_ACU
				ELSE V.VLR_RECO_ACU
			END AS VLR_RECO_ACU,
			CASE @VIGENCIA
				WHEN N'Anterior' THEN V.VLR_RECOA_MES
				WHEN N'Recupera'  THEN V.VLR_RECOR_MES
				ELSE V.VLR_RECO_MES
			END AS VLR_RECO_MES,
			CASE @VIGENCIA
				WHEN N'Anterior' THEN CAST(0 AS DECIMAL(18, 2))
				WHEN N'Recupera'  THEN CAST(0 AS DECIMAL(18, 2))
				ELSE V.VLR_RECO_TOT
			END AS VLR_RECO_TOT,
			CASE @VIGENCIA
				WHEN N'Anterior' THEN CAST(0 AS DECIMAL(18, 2))
				WHEN N'Recupera'  THEN CAST(0 AS DECIMAL(18, 2))
				ELSE V.VLR_RECO_POR
			END AS VLR_RECO_POR,
			CASE @VIGENCIA
				WHEN N'Anterior' THEN V.VLR_RECAA_ACU
				WHEN N'Recupera'  THEN V.VLR_RECAR_ACU
				ELSE V.VLR_RECA_ACU
			END AS VLR_RECA_ACU,
			CASE @VIGENCIA
				WHEN N'Anterior' THEN V.VLR_RECAA_MES
				WHEN N'Recupera'  THEN V.VLR_RECAR_MES
				ELSE V.VLR_RECA_MES
			END AS VLR_RECA_MES,
			CASE @VIGENCIA
				WHEN N'Anterior' THEN CAST(0 AS DECIMAL(18, 2))
				WHEN N'Recupera'  THEN CAST(0 AS DECIMAL(18, 2))
				ELSE V.VLR_RECA_TOT
			END AS VLR_RECA_TOT,
			CASE @VIGENCIA
				WHEN N'Anterior' THEN CAST(0 AS DECIMAL(18, 2))
				WHEN N'Recupera'  THEN CAST(0 AS DECIMAL(18, 2))
				ELSE V.VLR_RECA_POR
			END AS VLR_RECA_POR,
			V.VLR_APROPIACION,
			V.VLR_PORCOBRAR
		FROM dbo.VWK_PTOI_EJE AS V
		WHERE V.COMPANIA = @COMPANIA_PARAM
			AND V.CONSECUTIVO = @CONSECUTIVO
			AND V.MES >= @MESINI
			AND V.MES <= @MESFIN
			AND (
				(@CCOSTOINI IS NULL AND @CCOSTOFIN IS NULL)
				OR (V.CCOSTO >= @CCOSTOINI AND V.CCOSTO <= @CCOSTOFIN)
			)
			AND (
				(@RUBROINI IS NULL AND @RUBROFIN IS NULL)
				OR (
					@RUBROINI IS NOT NULL
					AND @RUBROFIN IS NOT NULL
					AND @RUBROINI = @RUBROFIN
					AND V.RUBRO = @RUBROINI
				)
				OR (
					NOT (
						@RUBROINI IS NOT NULL
						AND @RUBROFIN IS NOT NULL
						AND @RUBROINI = @RUBROFIN
					)
					AND (@RUBROINI IS NULL OR V.RUBRO >= @RUBROINI)
					AND (@RUBROFIN IS NULL OR V.RUBRO <= @RUBROFIN)
				)
			)
			AND (
				@VIGENCIA = N'Actual'
				OR @VIGENCIA = N'Todos'
				OR (
					@VIGENCIA = N'Anterior'
					AND (
						COALESCE(V.VLR_RECOA_ACU, 0) <> 0
						OR COALESCE(V.VLR_RECOA_MES, 0) <> 0
						OR COALESCE(V.VLR_RECAA_ACU, 0) <> 0
						OR COALESCE(V.VLR_RECAA_MES, 0) <> 0
					)
				)
				OR (
					@VIGENCIA = N'Recupera'
					AND (
						COALESCE(V.VLR_RECOR_ACU, 0) <> 0
						OR COALESCE(V.VLR_RECOR_MES, 0) <> 0
						OR COALESCE(V.VLR_RECAR_ACU, 0) <> 0
						OR COALESCE(V.VLR_RECAR_MES, 0) <> 0
					)
				)
			)
		ORDER BY V.RUBRO, V.MES, V.CCOSTO, V.IDTIPOMOV

		RETURN
	END

