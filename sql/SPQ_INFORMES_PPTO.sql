CREATE OR ALTER PROCEDURE DBO.SPQ_INFORMES_PPTO @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
SET NOCOUNT ON
SET DATEFORMAT dmy

DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @PARAMETROS NVARCHAR(MAX)
	, @MODELO VARCHAR(100)
	, @METODO VARCHAR(100)
	, @USUARIO VARCHAR(12)
	, @COMPANIA_PARAM VARCHAR(4)
	, @CONSECUTIVO VARCHAR(30)
	, @MESINI INT
	, @MESFIN INT
	, @RUBROINI VARCHAR(60)
	, @RUBROFIN VARCHAR(60)
	, @CCOSTOINI VARCHAR(30)
	, @CCOSTOFIN VARCHAR(30)
	, @VIGENCIA VARCHAR(20)
	, @FECHAINI DATE
	, @FECHAFIN DATE
	, @ESTADO VARCHAR(40)
	, @IDTERCERO VARCHAR(30)
	, @RAZONSOCIAL VARCHAR(200)
	, @ANO_PPTO INT
	, @IDTIPOMOV VARCHAR(20)

BEGIN
	SELECT *
	INTO #JSON
	FROM OPENJSON(@JSON) WITH (
		MODELO VARCHAR(100) '$.MODELO'
		, METODO VARCHAR(100) '$.METODO'
		, USUARIO VARCHAR(12) '$.USUARIO'
		, PARAMETROS NVARCHAR(MAX) AS JSON
	)

	SELECT @MODELO = MODELO
		, @METODO = METODO
		, @PARAMETROS = PARAMETROS
		, @USUARIO = USUARIO
	FROM #JSON

	IF @PARAMETROS IS NULL OR LTRIM(RTRIM(@PARAMETROS)) IN ('', '{}')
	BEGIN
		SELECT 'KO' AS OK, 'PARAMETROS requerido' AS ERROR
		RETURN
	END

	SET @COMPANIA_PARAM = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.COMPANIA'))), '')
	SET @CONSECUTIVO = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.CONSECUTIVO'))), '')
	SET @RUBROINI = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.RUBROINI'))), '')
	SET @RUBROFIN = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.RUBROFIN'))), '')
	SET @CCOSTOINI = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.CCOSTOINI'))), '')
	SET @CCOSTOFIN = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.CCOSTOFIN'))), '')
	SET @VIGENCIA = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.VIGENCIA'))), '')
	SET @ESTADO = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.ESTADO'))), '')
	SET @IDTERCERO = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.IDTERCERO'))), '')
	SET @RAZONSOCIAL = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.RAZONSOCIAL'))), '')

	SET @MESINI = TRY_CONVERT(INT, JSON_VALUE(@PARAMETROS, '$.MESINI'))
	SET @MESFIN = TRY_CONVERT(INT, JSON_VALUE(@PARAMETROS, '$.MESFIN'))
	SET @MESINI = TRY_CONVERT(INT, JSON_VALUE(@PARAMETROS, '$.MESINI'))
	SET @MESFIN = TRY_CONVERT(INT, JSON_VALUE(@PARAMETROS, '$.MESFIN'))
	SET @IDTIPOMOV = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.IDTIPOMOV'))), '')

	IF @IDTIPOMOV IS NOT NULL AND LOWER(@IDTIPOMOV) IN (N'todos', N'todas')
		SET @IDTIPOMOV = NULL

	IF @MESINI IS NULL OR @MESINI < 1 OR @MESINI > 12
		SET @MESINI = 1
	IF @MESFIN IS NULL
		SET @MESFIN = @MESINI
	IF @MESFIN < 1 OR @MESFIN > 12
		SET @MESFIN = 12
	IF @MESINI > @MESFIN
		SET @MESFIN = @MESINI

	-- Fechas (ListaDiaria_CDP y similares): ISO yyyy-mm-dd o texto reconocible por TRY_CONVERT
	SET @FECHAINI = TRY_CONVERT(DATE, NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.FECHAINI'))), ''), 23)
	IF @FECHAINI IS NULL
		SET @FECHAINI = TRY_CONVERT(DATE, NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.FECHAINI'))), ''), 103)
	SET @FECHAFIN = TRY_CONVERT(DATE, NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.FECHAFIN'))), ''), 23)
	IF @FECHAFIN IS NULL
		SET @FECHAFIN = TRY_CONVERT(DATE, NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.FECHAFIN'))), ''), 103)

	IF @METODO = 'Lista_CDP'
	BEGIN
		IF @COMPANIA_PARAM IS NULL
		BEGIN
			SELECT 'KO' AS OK, 'COMPANIA requerida' AS ERROR
			RETURN
		END
		IF @CONSECUTIVO IS NULL
		BEGIN
			SELECT 'KO' AS OK, 'CONSECUTIVO (PTPTO) requerido' AS ERROR
			RETURN
		END

		SELECT 'OK' AS OK

		SELECT A.COMPANIA
			, A.CONSECUTIVO
			, A.IDTIPOMOV
			, A.RUBRO
			, A.RECURSO
			, PR.NOMRUBRO
			, B.CDP
			, COALESCE(A.VIGENCIA, 'Actual') AS VIGENCIA
			, B.FECHAEXPEDICION AS FECHAEXPEDICION
			, A.VALOR
			, A.VALOR_RP
			, COALESCE(A.VLR_LIBERADO, 0) AS VLR_LIBERADO
			, A.SALDO
			, B.CCOSTO
			, B.OBJETIVO
		FROM PTCDPD A
		INNER JOIN PTCDP B
			ON A.COMPANIA = B.COMPANIA
			AND A.CONSECUTIVO = B.CONSECUTIVO
			AND A.CDP = B.CDP
		INNER JOIN PTRUB PR
			ON PR.RUBRO_ID = A.RUBRO_ID
		WHERE B.COMPANIA = @COMPANIA_PARAM
			AND B.CONSECUTIVO = @CONSECUTIVO
			AND (@RUBROINI IS NULL OR A.RUBRO >= @RUBROINI)
			AND (@RUBROFIN IS NULL OR A.RUBRO <= @RUBROFIN)
			AND (@CCOSTOINI IS NULL OR B.CCOSTO >= @CCOSTOINI)
			AND (@CCOSTOFIN IS NULL OR B.CCOSTO <= @CCOSTOFIN)
			AND MONTH(B.FECHAEXPEDICION) BETWEEN @MESINI AND @MESFIN
			AND (
				@VIGENCIA IS NULL
				OR LOWER(@VIGENCIA) = 'todos'
				OR LOWER(COALESCE(A.VIGENCIA, 'actual')) = LOWER(@VIGENCIA)
			)
		ORDER BY A.RUBRO, B.FECHAEXPEDICION, B.CDP, A.ITEM

		RETURN
	END

	-- Rpt:ListaDiaria_CDP — filtros equivalentes a Brw:ListaDiaria_CDP (KPPT1022.clw ApplyFilter) + joins del reporte (KPPT1023.clw)
	IF @METODO = 'ListaDiaria_CDP'
	BEGIN
		IF @COMPANIA_PARAM IS NULL
		BEGIN
			SELECT 'KO' AS OK, 'COMPANIA requerida' AS ERROR
			RETURN
		END
		IF @CONSECUTIVO IS NULL
		BEGIN
			SELECT 'KO' AS OK, 'CONSECUTIVO (PTPTO) requerido' AS ERROR
			RETURN
		END
		IF @FECHAINI IS NULL OR @FECHAFIN IS NULL
		BEGIN
			SELECT 'KO' AS OK, 'FECHAINI y FECHAFIN requeridas' AS ERROR
			RETURN
		END

		SELECT 'OK' AS OK

		SELECT A.COMPANIA
			, A.CONSECUTIVO
			, A.CDP
			, A.FECHAEXPEDICION
			, A.ESTADO
			, A.VALOR
			, A.SALDO
			, A.CCOSTO
			, A.OBJETIVO
			, COALESCE((
				SELECT TOP (1) D.VIGENCIA
				FROM PTCDPD D
				WHERE D.COMPANIA = A.COMPANIA
					AND D.CONSECUTIVO = A.CONSECUTIVO
					AND D.CDP = A.CDP
				ORDER BY D.ITEM
			), 'Actual') AS VIGENCIA
			, CEN.DESCRIPCION AS NOM_CCOSTO
		FROM PTCDP A
		LEFT JOIN CEN
			ON CEN.COMPANIA = A.COMPANIA
			AND CEN.CCOSTO = A.CCOSTO
		WHERE A.COMPANIA = @COMPANIA_PARAM
			AND A.CONSECUTIVO = @CONSECUTIVO
			AND (
				(@CCOSTOINI IS NULL AND @CCOSTOFIN IS NULL)
				OR (
					@CCOSTOINI IS NOT NULL
					AND @CCOSTOFIN IS NOT NULL
					AND A.CCOSTO BETWEEN @CCOSTOINI AND @CCOSTOFIN
				)
			)
			AND CAST(A.FECHAEXPEDICION AS DATE) BETWEEN @FECHAINI AND @FECHAFIN
			AND (
				@VIGENCIA IS NULL
				OR LOWER(@VIGENCIA) = 'todos'
				OR EXISTS (
					SELECT 1
					FROM PTCDPD X
					WHERE X.COMPANIA = A.COMPANIA
						AND X.CONSECUTIVO = A.CONSECUTIVO
						AND X.CDP = A.CDP
						AND LOWER(COALESCE(X.VIGENCIA, 'Actual')) = LOWER(@VIGENCIA)
				)
			)
		ORDER BY A.FECHAEXPEDICION, A.CDP

		RETURN
	END

	-- Rpt:Lista_RP (Brw:KPPT1024 ApplyFilter)
	IF @METODO = 'Lista_RP'
	BEGIN
		IF @COMPANIA_PARAM IS NULL OR @CONSECUTIVO IS NULL
		BEGIN
			SELECT 'KO' AS OK, 'COMPANIA y CONSECUTIVO requeridos' AS ERROR
			RETURN
		END
		IF @FECHAINI IS NULL OR @FECHAFIN IS NULL
		BEGIN
			SELECT 'KO' AS OK, 'FECHAINI y FECHAFIN requeridas' AS ERROR
			RETURN
		END

		SELECT 'OK' AS OK

		SELECT A.COMPANIA
			, A.CONSECUTIVO
			, A.RP
			, A.CDP
			, A.FECHARP
			, A.IDTERCERO
			, A.ESTADO
			, A.CCOSTO
			, A.OBJETIVO
			, B.RUBRO
			, B.RUBRO_ID
			, B.VALOR
			, B.VLR_LIBERADO
			, B.SALDO
			, COALESCE(C.VIGENCIA, 'Actual') AS VIGENCIA
			, PR.NOMRUBRO
		FROM PTRP A
		INNER JOIN PTRPD B ON B.COMPANIA = A.COMPANIA AND B.CONSECUTIVO = A.CONSECUTIVO AND B.CDP = A.CDP AND B.RP = A.RP
		INNER JOIN PTCDPD C ON C.COMPANIA = B.COMPANIA AND C.CONSECUTIVO = B.CONSECUTIVO AND C.CDP = B.CDP AND C.CLASE = B.CLASE AND C.RUBRO = B.RUBRO AND C.ITEM = B.ITEMCDPD
		LEFT JOIN PTRUB PR ON PR.RUBRO_ID = B.RUBRO_ID
		WHERE A.COMPANIA = @COMPANIA_PARAM
			AND A.CONSECUTIVO = @CONSECUTIVO
			AND (
				(@RUBROINI IS NULL OR @RUBROFIN IS NULL)
				OR (B.RUBRO BETWEEN @RUBROINI AND @RUBROFIN)
			)
			AND (
				(@CCOSTOINI IS NULL AND @CCOSTOFIN IS NULL)
				OR (A.CCOSTO BETWEEN @CCOSTOINI AND @CCOSTOFIN)
			)
			AND CAST(A.FECHARP AS DATE) BETWEEN @FECHAINI AND @FECHAFIN
			AND (
				@VIGENCIA IS NULL
				OR LOWER(@VIGENCIA) = 'todos'
				OR LOWER(COALESCE(C.VIGENCIA, 'Actual')) = LOWER(@VIGENCIA)
			)
			AND (
				@ESTADO IS NULL
				OR LOWER(@ESTADO) = 'todos'
				OR A.ESTADO = @ESTADO
			)
			AND (
				@IDTERCERO IS NULL
				OR EXISTS (
					SELECT 1
					FROM TER T
					WHERE T.IDTERCERO = A.IDTERCERO
						AND (T.IDTERCERO = @IDTERCERO OR T.NIT = @IDTERCERO)
				)
			)
		ORDER BY B.RUBRO, A.FECHARP, A.RP

		RETURN
	END

	-- Rpt:Lista_CXP (Brw:KPPT1026 ApplyFilter)
	IF @METODO = 'Lista_CXP'
	BEGIN
		IF @COMPANIA_PARAM IS NULL OR @CONSECUTIVO IS NULL
		BEGIN
			SELECT 'KO' AS OK, 'COMPANIA y CONSECUTIVO requeridos' AS ERROR
			RETURN
		END
		IF @FECHAINI IS NULL OR @FECHAFIN IS NULL
		BEGIN
			SELECT 'KO' AS OK, 'FECHAINI y FECHAFIN requeridas' AS ERROR
			RETURN
		END

		SELECT 'OK' AS OK

		SELECT A.COMPANIA
			, A.CONSECUTIVO
			, A.CDP
			, A.RP
			, A.CNSCXP
			, A.FECHA
			, A.ESTADO
			, A.CCOSTO
			, A.OBSERVACION
			, T.NIT
			, T.RAZONSOCIAL
			, C.RUBRO
			, C.RUBRO_ID
			, C.VALOR
			, C.VLR_LIBERADO
			, C.SALDO
			, COALESCE(D.VIGENCIA, 'Actual') AS VIGENCIA
			, PR.NOMRUBRO
		FROM PTCXP A
		INNER JOIN PTRP B ON B.RP = A.RP AND B.COMPANIA = A.COMPANIA AND B.CONSECUTIVO = A.CONSECUTIVO AND B.CDP = A.CDP
		LEFT JOIN TER T ON T.IDTERCERO = B.IDTERCERO
		INNER JOIN PTCXPD C ON C.COMPANIA = A.COMPANIA AND C.CONSECUTIVO = A.CONSECUTIVO AND C.CDP = A.CDP AND C.CNSCXP = A.CNSCXP AND C.RP = A.RP
		INNER JOIN PTCDPD D ON D.COMPANIA = C.COMPANIA AND D.CONSECUTIVO = C.CONSECUTIVO AND D.CDP = C.CDP AND D.CLASE = C.CLASE AND D.RUBRO_ID = C.RUBRO_ID AND D.ITEM = C.ITEMCDPD
		LEFT JOIN PTRUB PR ON PR.RUBRO_ID = C.RUBRO_ID
		WHERE A.COMPANIA = @COMPANIA_PARAM
			AND A.CONSECUTIVO = @CONSECUTIVO
			AND (
				(@RUBROINI IS NULL OR @RUBROFIN IS NULL)
				OR (C.RUBRO BETWEEN @RUBROINI AND @RUBROFIN)
			)
			AND (
				(@CCOSTOINI IS NULL AND @CCOSTOFIN IS NULL)
				OR (A.CCOSTO BETWEEN @CCOSTOINI AND @CCOSTOFIN)
			)
			AND CAST(A.FECHA AS DATE) BETWEEN @FECHAINI AND @FECHAFIN
			AND (
				@VIGENCIA IS NULL
				OR LOWER(@VIGENCIA) = 'todos'
				OR LOWER(COALESCE(D.VIGENCIA, 'Actual')) = LOWER(@VIGENCIA)
			)
			AND (
				@ESTADO IS NULL
				OR LOWER(@ESTADO) = 'todos'
				OR B.ESTADO = @ESTADO
			)
			AND (
				@IDTERCERO IS NULL
				OR EXISTS (
					SELECT 1
					FROM TER T
					WHERE T.IDTERCERO = B.IDTERCERO
						AND (T.IDTERCERO = @IDTERCERO OR T.NIT = @IDTERCERO)
				)
			)
		ORDER BY A.FECHA, A.CNSCXP

		RETURN
	END

	-- Rpt:Lista_PAG (Brw:KPPT1040 ApplyFilter)
	IF @METODO = 'Lista_PAG'
	BEGIN
		IF @COMPANIA_PARAM IS NULL OR @CONSECUTIVO IS NULL
		BEGIN
			SELECT 'KO' AS OK, 'COMPANIA y CONSECUTIVO requeridos' AS ERROR
			RETURN
		END
		IF @FECHAINI IS NULL OR @FECHAFIN IS NULL
		BEGIN
			SELECT 'KO' AS OK, 'FECHAINI y FECHAFIN requeridas' AS ERROR
			RETURN
		END

		SELECT 'OK' AS OK

		SELECT A.COMPANIA
			, A.CONSECUTIVO
			, A.CDP
			, A.CLASE
			, A.RUBRO
			, A.RUBRO_ID
			, A.VALOR
			, A.RP
			, A.CNSCXP
			, A.CNSPAGO
			, B.FECHA
			, B.ESTADO
			, B.CCOSTO
			, B.OBSERVACION
			, COALESCE(C.VIGENCIA, 'Actual') AS VIGENCIA
			, PR.NOMRUBRO
		FROM PTPAGD A
		INNER JOIN PTPAG B ON B.COMPANIA = A.COMPANIA AND B.CONSECUTIVO = A.CONSECUTIVO AND B.CDP = A.CDP AND B.RP = A.RP AND B.CNSCXP = A.CNSCXP AND B.CNSPAGO = A.CNSPAGO
		INNER JOIN PTCDPD C ON C.COMPANIA = A.COMPANIA AND C.CONSECUTIVO = A.CONSECUTIVO AND C.CDP = A.CDP AND C.CLASE = A.CLASE AND C.RUBRO = A.RUBRO AND C.RUBRO_ID = A.RUBRO_ID AND C.ITEM = A.ITEMCDPD
		LEFT JOIN PTRUB PR ON PR.RUBRO_ID = A.RUBRO_ID
		WHERE B.COMPANIA = @COMPANIA_PARAM
			AND A.CONSECUTIVO = @CONSECUTIVO
			AND (
				(@RUBROINI IS NULL OR @RUBROFIN IS NULL)
				OR (A.RUBRO BETWEEN @RUBROINI AND @RUBROFIN)
			)
			AND (
				(@CCOSTOINI IS NULL AND @CCOSTOFIN IS NULL)
				OR (B.CCOSTO BETWEEN @CCOSTOINI AND @CCOSTOFIN)
			)
			AND CAST(B.FECHA AS DATE) BETWEEN @FECHAINI AND @FECHAFIN
			AND (
				@VIGENCIA IS NULL
				OR LOWER(@VIGENCIA) = 'todos'
				OR LOWER(COALESCE(C.VIGENCIA, 'Actual')) = LOWER(@VIGENCIA)
			)
			AND (
				@ESTADO IS NULL
				OR LOWER(@ESTADO) = 'todos'
				OR B.ESTADO = @ESTADO
			)
		ORDER BY B.FECHA, A.CNSPAGO

		RETURN
	END

	-- Rpt:ListaUtiliza_CDP (Brw:KPPT1028 ApplyFilter)
	IF @METODO = 'ListaUtiliza_CDP'
	BEGIN
		IF @COMPANIA_PARAM IS NULL OR @CONSECUTIVO IS NULL
		BEGIN
			SELECT 'KO' AS OK, 'COMPANIA y CONSECUTIVO requeridos' AS ERROR
			RETURN
		END

		SELECT 'OK' AS OK

		SELECT A.COMPANIA
			, A.CONSECUTIVO
			, A.RP
			, A.CDP
			, A.FECHARP
			, A.FECHAPLAZO
			, A.IDTERCERO
			, A.CCOSTO
			, B.RUBRO
			, B.VALOR
			, C.RECURSO
			, COALESCE(C.VIGENCIA, 'Actual') AS VIGENCIA
			, PR.NOMRUBRO
		FROM PTRP A
		INNER JOIN PTRPD B ON B.COMPANIA = A.COMPANIA AND B.CONSECUTIVO = A.CONSECUTIVO AND B.CDP = A.CDP AND B.RP = A.RP
		INNER JOIN PTCDPD C ON C.COMPANIA = B.COMPANIA AND C.CONSECUTIVO = B.CONSECUTIVO AND C.CDP = B.CDP AND C.CLASE = B.CLASE AND C.RUBRO = B.RUBRO AND C.ITEM = B.ITEMCDPD
		LEFT JOIN PTRUB PR ON PR.RUBRO_ID = B.RUBRO_ID
		WHERE A.COMPANIA = @COMPANIA_PARAM
			AND A.CONSECUTIVO = @CONSECUTIVO
			AND MONTH(A.FECHARP) BETWEEN @MESINI AND @MESFIN
			AND (
				(@RUBROINI IS NULL OR @RUBROFIN IS NULL)
				OR (B.RUBRO BETWEEN @RUBROINI AND @RUBROFIN)
			)
			AND (
				(@CCOSTOINI IS NULL AND @CCOSTOFIN IS NULL)
				OR (A.CCOSTO BETWEEN @CCOSTOINI AND @CCOSTOFIN)
			)
		ORDER BY A.FECHARP, A.RP

		RETURN
	END

	IF @METODO = 'Lista_RECA'
	BEGIN
		IF @COMPANIA_PARAM IS NULL OR @CONSECUTIVO IS NULL
		BEGIN
			SELECT 'KO' AS OK, 'COMPANIA y CONSECUTIVO requeridos' AS ERROR
			RETURN
		END

		SET @ANO_PPTO = NULL
		SELECT @ANO_PPTO = P.ANO
		FROM PTPTO P
		WHERE P.COMPANIA = @COMPANIA_PARAM
			AND P.CONSECUTIVO = @CONSECUTIVO

		IF @ANO_PPTO IS NULL
			SET @ANO_PPTO = YEAR(GETDATE())

		IF @VIGENCIA IS NOT NULL AND LOWER(LTRIM(RTRIM(@VIGENCIA))) IN (N'', N'todos', N'todas')
			SET @VIGENCIA = NULL

		IF @ESTADO IS NOT NULL AND LOWER(LTRIM(RTRIM(@ESTADO))) = N'todos'
			SET @ESTADO = NULL

		SELECT 'OK' AS OK

		SELECT A.COMPANIA
			, A.CONSECUTIVO
			, A.RECO
			, A.CNSPAGO
			, A.RUBRO
			, A.RUBRO_ID
			, A.VALOR
			, B.FECHA
			, B.ESTADO
			, B.CCOSTO
			, C.IDTERCERO
			, T.NIT
			, T.RAZONSOCIAL
			, C.OBJETIVO
			, PR.NOMRUBRO
			, PR.RECURSO AS IDTIPOMOV
			, COALESCE(D.VIGENCIA, N'Actual') AS VIGENCIA
		FROM PTRECAD A
		INNER JOIN PTRECA B
			ON B.COMPANIA = A.COMPANIA
			AND B.CONSECUTIVO = A.CONSECUTIVO
			AND B.RECO = A.RECO
			AND B.CNSPAGO = A.CNSPAGO
		INNER JOIN PTRECO C
			ON C.COMPANIA = A.COMPANIA
			AND C.CONSECUTIVO = A.CONSECUTIVO
			AND C.RECO = A.RECO
		LEFT JOIN TER T
			ON T.IDTERCERO = C.IDTERCERO
		LEFT JOIN PTRUB PR
			ON PR.RUBRO_ID = A.RUBRO_ID
		LEFT JOIN PTRECOD D
			ON D.COMPANIA = A.COMPANIA
			AND D.CONSECUTIVO = A.CONSECUTIVO
			AND D.RECO = A.RECO
			AND D.RUBRO_ID = A.RUBRO_ID
		WHERE B.COMPANIA = @COMPANIA_PARAM
			AND B.CONSECUTIVO = @CONSECUTIVO
			AND (
				(@RUBROINI IS NULL OR @RUBROFIN IS NULL)
				OR (A.RUBRO BETWEEN @RUBROINI AND @RUBROFIN)
			)
			AND (
				(@CCOSTOINI IS NULL AND @CCOSTOFIN IS NULL)
				OR (B.CCOSTO BETWEEN @CCOSTOINI AND @CCOSTOFIN)
			)
			AND B.FECHA >= DATEFROMPARTS(@ANO_PPTO, @MESINI, 1)
			AND B.FECHA < DATEADD(MONTH, 1, DATEFROMPARTS(@ANO_PPTO, @MESFIN, 1))
			AND (
				@VIGENCIA IS NULL
				OR COALESCE(D.VIGENCIA, N'Actual') = @VIGENCIA
			)
			AND (
				@ESTADO IS NULL
				OR B.ESTADO = @ESTADO
			)
			AND (
				@IDTERCERO IS NULL
				OR C.IDTERCERO = @IDTERCERO
				OR T.NIT = @IDTERCERO
			)
			AND (
				@RAZONSOCIAL IS NULL
				OR T.RAZONSOCIAL LIKE CONCAT(N'%', @RAZONSOCIAL, N'%')
				OR T.NIT LIKE CONCAT(N'%', @RAZONSOCIAL, N'%')
			)
		ORDER BY A.RUBRO, B.FECHA, A.RECO, A.CNSPAGO

		RETURN
	END

	-- Rpt:Lista_RECO (Brw:KPPT1030 ApplyFilter)
	IF @METODO = 'Lista_RECO'
	BEGIN
		IF @COMPANIA_PARAM IS NULL OR @CONSECUTIVO IS NULL
		BEGIN
			SELECT 'KO' AS OK, 'COMPANIA y CONSECUTIVO requeridos' AS ERROR
			RETURN
		END

		SELECT 'OK' AS OK

		SELECT A.COMPANIA
			, A.CONSECUTIVO
			, A.RECO
			, A.RUBRO
			, A.RUBRO_ID
			, A.VIGENCIA
			, A.VALOR
