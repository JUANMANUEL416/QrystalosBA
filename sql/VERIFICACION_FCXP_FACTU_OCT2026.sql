/* 1 — Resumen cabecera vs detalle vs PDF */
SELECT
  D.CNSFCXP,
  D.NOREFERENCIA,
  T.NIT,
  LEFT(T.RAZONSOCIAL, 32) AS PROVEEDOR,
  P.ESTADO,
  P.CONTABILIZADA,
  P.NROCOMPROBANTE,
  CONVERT(varchar(10), P.F_FACTURAREF, 103) AS F_FACT,
  CONVERT(decimal(18, 2), D.NETO_PDF) AS NETO_PDF,
  CONVERT(decimal(18, 2), P.VLR_NETO) AS NETO_CAB,
  CONVERT(decimal(18, 2), SUM(FD.VLR_NETO)) AS NETO_DET,
  CONVERT(decimal(18, 2), P.VLR_NETO - SUM(FD.VLR_NETO)) AS DIF_CAB_DET,
  CONVERT(decimal(18, 2), P.VLR_NETO - D.NETO_PDF) AS DIF_CAB_PDF,
  CASE
    WHEN P.CONTABILIZADA <> 0 THEN N'CONTAB'
    WHEN ABS(P.VLR_NETO - D.NETO_PDF) > 0.01 THEN N'VALOR_CAB'
    WHEN ABS(P.VLR_NETO - SUM(FD.VLR_NETO)) > 0.01 THEN N'CAB_DET'
    WHEN SUM(CASE WHEN FD.VLR_IVA > 0 AND COALESCE(FD.CUENTA_IVA, N'') <> N'24080501' THEN 1 ELSE 0 END) > 0
      OR SUM(CASE WHEN FD.VLR_IVA > 0 AND FD.CUENTA_SER IN (N'14150502', N'14200502') THEN 1 ELSE 0 END) > 0
    THEN N'CUENTAS_IVA'
    WHEN D.NOREFERENCIA = N'FE603306' AND T.NIT NOT LIKE N'901429936%' THEN N'TERCERO'
    ELSE N'OK'
  END AS SEMAFORO,
  D.NOTA
FROM @DOC D
INNER JOIN dbo.FCXP P ON P.CNSFCXP = D.CNSFCXP
LEFT JOIN dbo.TER T ON T.IDTERCERO = P.IDTERCERO
LEFT JOIN dbo.FCXPD FD ON FD.CNSFCXP = P.CNSFCXP
WHERE P.ESTADO <> N'A'
GROUP BY
  D.CNSFCXP, D.NOREFERENCIA, D.NETO_PDF, D.NOTA,
  T.NIT, T.RAZONSOCIAL,
  P.ESTADO, P.CONTABILIZADA, P.NROCOMPROBANTE, P.F_FACTURAREF,
  P.VLR_NETO
ORDER BY D.NOREFERENCIA;

/* 2 — Líneas con IVA mal amarrado */
SELECT
  P.CNSFCXP,
  P.NOREFERENCIA,
  D.ITEM,
  D.IDSERVICIO,
  CONVERT(decimal(18, 2), D.VLR_IVA) AS IVA,
  D.CUENTA_SER,
  D.CUENTA_IVA,
  D.N_PRESUP AS CNSMOV
FROM @DOC DOC
INNER JOIN dbo.FCXP P ON P.CNSFCXP = DOC.CNSFCXP
INNER JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
WHERE P.ESTADO <> N'A'
  AND COALESCE(D.VLR_IVA, 0) > 0
  AND (
    D.CUENTA_SER IN (N'14150502', N'14200502')
    OR COALESCE(D.CUENTA_IVA, N'') <> N'24080501'
  )
ORDER BY P.NOREFERENCIA, D.ITEM;

/* 3 — Cabecera distinta a suma detalle (todas las del lote) */
SELECT
  P.CNSFCXP,
  P.NOREFERENCIA,
  CONVERT(decimal(18, 2), P.VLR_IVA) AS IVA_CAB,
  CONVERT(decimal(18, 2), SUM(D.VLR_IVA)) AS IVA_DET,
  CONVERT(decimal(18, 2), P.VLR_NETO) AS NETO_CAB,
  CONVERT(decimal(18, 2), SUM(D.VLR_NETO)) AS NETO_DET
FROM @DOC DOC
INNER JOIN dbo.FCXP P ON P.CNSFCXP = DOC.CNSFCXP
INNER JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
WHERE P.ESTADO <> N'A'
GROUP BY P.CNSFCXP, P.NOREFERENCIA, P.VLR_IVA, P.VLR_NETO
HAVING ABS(P.VLR_IVA - SUM(D.VLR_IVA)) > 0.01
    OR ABS(P.VLR_NETO - SUM(D.VLR_NETO)) > 0.01
ORDER BY P.NOREFERENCIA;
