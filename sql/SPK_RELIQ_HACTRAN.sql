IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='SPK_RELIQ_HACTRAN' AND XTYPE='P')
BEGIN
   DROP PROCEDURE SPK_RELIQ_HACTRAN
END

GO
CREATE PROCEDURE DBO.SPK_RELIQ_HACTRAN
@CNSHACTRAN VARCHAR(20)
WITH ENCRYPTION
AS
BEGIN
	DECLARE @NOADMISION VARCHAR(20), @PROCEDENCIA VARCHAR(2)
	SELECT 'QX' AS PROCEDENCIA, NOADMISION AS NOADMISION INTO #HACTRAN
	FROM HADM  WHERE CNSHACTRAN=@CNSHACTRAN AND HADM.TIPOADM=dbo.FNK_VALORVARIABLE('IDTARIFASOAT')
	UNION ALL
	SELECT 'CI' PROCEDENCIA, CONSECUTIVO FROM CIT WHERE CNSHACTRAN=@CNSHACTRAN AND SOAT=1
	UNION ALL
	SELECT 'CE' PROCEDENCIA, NOAUT FROM AUT WHERE CNSHACTRAN=@CNSHACTRAN AND SOAT=1

	DECLARE CUR_HACTRAND CURSOR FOR 
	SELECT PROCEDENCIA, NOADMISION FROM #HACTRAN A WHERE NOT EXISTS (SELECT 1 FROM HACTRAND WHERE CNSHACTRAN=@CNSHACTRAN AND PROCEDENCIA=A.PROCEDENCIA AND NOREFERENCIA=A.NOADMISION)

	OPEN CUR_HACTRAND 
	FETCH NEXT FROM CUR_HACTRAND INTO @PROCEDENCIA, @NOADMISION
	WHILE @@FETCH_STATUS = 0
	BEGIN
		IF NOT EXISTS (SELECT 1 FROM HACTRAND WHERE CNSHACTRAN=@CNSHACTRAN AND PROCEDENCIA=@PROCEDENCIA AND NOREFERENCIA=@NOADMISION)
		BEGIN
			EXEC SPK_MOV_ACTRAN 'INGRESO', @PROCEDENCIA, @NOADMISION
		END	
		FETCH NEXT FROM CUR_HACTRAND INTO @PROCEDENCIA, @NOADMISION
	END
	CLOSE CUR_HACTRAND
	DEALLOCATE CUR_HACTRAND
	
	UPDATE HACTRAND SET VLRGASTADO = AUT.VALORTOTAL 
	FROM   AUT
	WHERE  AUT.NOAUT            = HACTRAND.NOREFERENCIA
	AND    HACTRAND.PROCEDENCIA = 'CE'
	AND    HACTRAND.CNSHACTRAN  = @CNSHACTRAN
   
	UPDATE HACTRAND SET VLRGASTADO = CIT.VALORTOTAL 
	FROM   CIT
	WHERE  CIT.CONSECUTIVO      = HACTRAND.NOREFERENCIA
	AND    HACTRAND.PROCEDENCIA = 'CI'
	AND    HACTRAND.CNSHACTRAN  = @CNSHACTRAN
   
	UPDATE HACTRAND SET VLRGASTADO = ( SELECT SUM(VALOREXEDENTE) FROM HPRE 
										WHERE HPRE.NOADMISION = HACTRAND.NOREFERENCIA)
	WHERE  HACTRAND.PROCEDENCIA = 'QX'
	AND    HACTRAND.CNSHACTRAN  = @CNSHACTRAN
   
	UPDATE HACTRAN SET VLRGASTADO = (SELECT COALESCE(SUM(VLRGASTADO), 0) 
									FROM   HACTRAND 
									WHERE  HACTRAND.CNSHACTRAN = HACTRAN.CNSHACTRAN)
	WHERE  HACTRAN.CNSHACTRAN = @CNSHACTRAN


	UPDATE HACTRAN SET VLRFALTA = TOPE - VLRGASTADO
	WHERE  HACTRAN.CNSHACTRAN   = @CNSHACTRAN
   
END
