CREATE OR ALTER PROCEDURE DBO.SPQ_USGRU
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @PARAMETROS NVARCHAR(MAX), @MODELO   VARCHAR(100), @METODO     VARCHAR(100)
DECLARE  @USUARIO    VARCHAR(20),   @GRUPO      VARCHAR(8)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)
	
	SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO) FROM USUSU WHERE USUARIO = @USUARIO

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			INSERT INTO USGRU (GRUPO, NOMBRE, AMBITOMTTO)
			SELECT JSON_VALUE(@PARAMETROS, '$.GRUPO'),
				JSON_VALUE(@PARAMETROS, '$.NOMBRE'),
				JSON_VALUE(@PARAMETROS, '$.AMBITOMTTO') 
			WHERE NOT EXISTS (SELECT GRUPO FROM USGRU WHERE GRUPO = JSON_VALUE(@PARAMETROS, '$.GRUPO')) 

			UPDATE USGRU SET NOMBRE = JSON_VALUE(@PARAMETROS, '$.NOMBRE'), AMBITOMTTO = UPPER(JSON_VALUE(@PARAMETROS, '$.AMBITOMTTO')) 
			WHERE GRUPO = JSON_VALUE(@PARAMETROS, '$.GRUPO')
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		BEGIN TRY
			SELECT @GRUPO = JSON_VALUE(@PARAMETROS, '$.GRUPO')

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'EL GRUPO TIENE USUARIOS ASIGNADOS (USUSU)'
			WHERE EXISTS (SELECT * FROM USUSU WHERE DBO.FNK_DESCIFRAR(GRUPO) = @GRUPO)

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'EL GRUPO TIENE PREFIJOS ASIGNADOS (PREGR)'
			WHERE EXISTS (SELECT * FROM PREGR WHERE GRUPO = @GRUPO)

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'EL GRUPO TIENE ADMINISTRADORAS ASIGNADAS (USGRUA)'
			WHERE EXISTS (SELECT * FROM USGRUA WHERE GRUPO = @GRUPO)

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'EL GRUPO TIENE DETALLES VINCULADOS (USGRUH)'
			WHERE EXISTS (SELECT * FROM USGRUH WHERE GRUPO = @GRUPO)

			IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
			BEGIN
				DELETE FROM USGRU WHERE GRUPO = @GRUPO
			END
			
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
END
