IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='SPK_GENCXP_NOMI_ESP' AND XTYPE='P')
BEGIN
   DROP PROCEDURE SPK_GENCXP_NOMI_ESP
END
GO
CREATE PROCEDURE DBO.SPK_GENCXP_NOMI_ESP
@CNSPAGO VARCHAR(20),
@COMPANIA VARCHAR(5),
@IDSEDE  VARCHAR(5),
@USUARIO VARCHAR(20),
@SYS_COMPUTERNAME VARCHAR(255)
WITH ENCRYPTION
AS
DECLARE @CONCEPTO VARCHAR(120)
DECLARE @CUANTOS INT
DECLARE @CODNOMINA VARCHAR(4)
DECLARE @NUMDOC    VARCHAR(20)
DECLARE @IDTERCERO_PRF    VARCHAR(20)
DECLARE @CNSFCXP   VARCHAR(20)
DECLARE @NROCOMPROBANTE VARCHAR(20)
DECLARE @FECHA  DATETIME
DECLARE @DETALLE VARCHAR(100)
DECLARE @CMD     VARCHAR(2000)
BEGIN
  SELECT @CUANTOS=COUNT(*) FROM TGEN WHERE TABLA='NOMINA' AND CAMPO='CXPESPECIAL'
  IF COALESCE(@CUANTOS,0)=0
  BEGIN 
     RAISERROR ('NO EXISTEN CONCEPTOS ESPECIALES',16,1)
     RETURN
  END
  PRINT 'ESTOS SON LOS CONCEPTOS:::::::'+@CONCEPTO
  SELECT @CUANTOS=COUNT(*) 
  FROM NIEPE  INNER JOIN NIEPED ON NIEPE.CNSNIEPE=NIEPED.CNSNIEPE AND NIEPE.NUMDOC=NIEPED.NUMDOC
  WHERE NIEPE.CNSPAGO=@CNSPAGO
  AND   NIEPED.CODCONCEPTO IN (SELECT CODIGO FROM TGEN WHERE TABLA='NOMINA' AND CAMPO='CXPESPECIAL')
  AND   COALESCE(NIEPED.CODFINANCIACION,'')<>'CXP'
      
  PRINT 'CUANTOS '+STR(@CUANTOS)

  IF @CUANTOS>1
  BEGIN
     SELECT TOP 1 @FECHA= DBO.FNK_DIA_DEL_MES(ANO,MES,'ULTIMO')FROM NIEPE WHERE CNSPAGO=@CNSPAGO
     DECLARE CUR CURSOR FOR
     SELECT NIEPE.CODNOMINA,NIEPED.IDTERCERO_PRF
     FROM NIEPE  INNER JOIN NIEPED ON NIEPE.CNSNIEPE=NIEPED.CNSNIEPE AND NIEPE.NUMDOC=NIEPED.NUMDOC
     WHERE NIEPE.CNSPAGO=@CNSPAGO
     AND   NIEPED.CODCONCEPTO IN (SELECT CODIGO FROM TGEN WHERE TABLA='NOMINA' AND CAMPO='CXPESPECIAL')
     AND  COALESCE(NIEPED.CODFINANCIACION,'')<>'CXP'
     GROUP BY NIEPE.CODNOMINA,NIEPED.IDTERCERO_PRF
     OPEN CUR 
     FETCH NEXT FROM CUR
     INTO @CODNOMINA, @IDTERCERO_PRF
     WHILE @@FETCH_STATUS = 0
     BEGIN
        SET @CNSFCXP=SPACE(20)
        EXEC SPK_GENCONSECUTIVO @COMPANIA,@IDSEDE,'@FCXPNM',@CNSFCXP OUTPUT   
        SELECT @CNSFCXP = @IDSEDE + 'NM'+REPLACE(SPACE(6 - LEN(@CNSFCXP))+LTRIM(RTRIM(@CNSFCXP)),SPACE(1),0)
         
        SELECT TOP 1 @NROCOMPROBANTE=NIEPED.NROCOMPROBANTE,@DETALLE=NIEPED.NOMBRE_CONCEPTO 
        FROM NIEPE INNER JOIN 
             NIEPED ON NIEPE.CNSNIEPE = NIEPED.CNSNIEPE
        WHERE NIEPE.CNSPAGO=@CNSPAGO 
        AND NIEPED.NUMDOC=@IDTERCERO_PRF
        AND NIEPED.CODCONCEPTO IN(SELECT CODIGO FROM TGEN WHERE TABLA='NOMINA' AND CAMPO='CXPESPECIAL')
         
       PRINT 'FCXP.'
       INSERT INTO FCXP (CNSFCXP,FECHA,CNSFCOM,IDTERCERO,NOREFERENCIA,F_FACTURAREF,F_VENCE,VALOR,ESTADO,F_CANCELADO,USUARIO,
                         PROCEDENCIA,OBSERVACION,COMPANIA,SYS_COMPUTERNAME,USUARIOMOD,FECHAMOD,NUMCUOTA,MARCACONT,
                         CONTABILIZADA,NROCOMPROBANTE,SALDO,IDCLASEIMP,VLR_DESCUENTO,VLR_IVA,VLR_NETO,VLR_IMPUESTOS,
                         VLR_NOTASDEBITO,VLR_COMISION,CUEDEBITO,CUECREDITO,CNSFCXPPM)
       SELECT @CNSFCXP, DBO.FNK_FECHA_SIN_MLS(GETDATE()),@CODNOMINA,@IDTERCERO_PRF, @CNSPAGO, @FECHA, 
              @FECHA, 0, 'N', NULL, @USUARIO, 
              'Nomina', @DETALLE+', N�mina No. '+@CNSPAGO, @COMPANIA, @SYS_COMPUTERNAME, NULL, NULL, NULL, 0, 1, 
              @NROCOMPROBANTE, 0, NULL, 0, 0, 0, 0, 0, 0, NULL, NULL, NULL
         
       PRINT 'FCXPD.'
       INSERT INTO FCXPD(CNSFCXP,ITEM,IDSERVICIO,CANTIDAD,VALOR,ESTADO,N_PRESUP,ITEM_PRESUP,IDCLASEIMP,VLR_DESCUENTO,
                          VLR_IVA,VLR_NETO,NOLOTE,PREFIJO,CCOSTO,IDAREAH,IDAREA,NROCOMPROBANTE,PROCEDENCIA, CUENTA_SER)
       SELECT @CNSFCXP CNSFCXP, ROW_NUMBER() OVER(ORDER  BY @CNSFCXP  DESC), NIEPED.CODCONCEPTO , 1 CANTIDAD, NIEPED.TOTAL_NOMINA, 'P' ESTADO, 
               NIEPE.CNSNIEPE , ROW_NUMBER() OVER(ORDER  BY @CNSFCXP  DESC) ITEM_PRESUP, NULL IDCLASEIMP, 0 VLR_DESCUENTO,
               0 VLR_IVA, NIEPED.TOTAL_NOMINA , NIEPE.NUMDOC NOLOTE, NIEPED.CODCONCEPTO , NIEPE.CCOSTO, 
               NULL IDAREAH, NIEPE.IDAREA,NULL NROCOMPROBANTE, 'Nomina', '0'
       FROM NIEPE INNER JOIN NIEPED ON NIEPE.CNSNIEPE=NIEPED.CNSNIEPE AND NIEPE.NUMDOC=NIEPED.NUMDOC
       WHERE NIEPE.CNSPAGO=@CNSPAGO
       AND   NIEPED.IDTERCERO_PRF=@IDTERCERO_PRF
       AND   NIEPED.CODCONCEPTO IN (SELECT CODIGO FROM TGEN WHERE TABLA='NOMINA' AND CAMPO='CXPESPECIAL')
       AND  COALESCE(NIEPED.CODFINANCIACION,'')<>'CXP'    
              
       EXEC SPK_CALCULOVALORESCXP @CNSFCXP
       
       UPDATE NIEPED SET CODFINANCIACION='CXP'
       FROM NIEPE INNER JOIN NIEPED ON NIEPE.CNSNIEPE=NIEPED.CNSNIEPE
       WHERE NIEPE.CNSPAGO=@CNSPAGO
       AND   NIEPED.IDTERCERO_PRF=@IDTERCERO_PRF
       AND   NIEPED.CODCONCEPTO IN (SELECT CODIGO FROM TGEN WHERE TABLA='NOMINA' AND CAMPO='CXPESPECIAL')
       AND  COALESCE(NIEPED.CODFINANCIACION,'')<>'CXP' 
       
       FETCH NEXT FROM CUR
       INTO @CODNOMINA, @IDTERCERO_PRF
    END 
    CLOSE CUR
    DEALLOCATE CUR
   END
END
