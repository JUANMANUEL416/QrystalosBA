CREATE OR ALTER PROCEDURE DBO.SPQ_ITRA
@JSON NVARCHAR(MAX)
WITH ENCRYPTION
AS
DECLARE   @PARAMETROS       NVARCHAR(MAX)		,@MODELO			VARCHAR(100)	,@METODO			VARCHAR(100)
		,@USUARIO			VARCHAR(12)			,@NVOCONSEC			VARCHAR(20)		,@CANTIDAD			INT
		,@SEDE				VARCHAR(5)			,@CNSITRA			VARCHAR(20)		,@DATOS			NVARCHAR(MAX)	,@CODIGOBARRA VARCHAR(20)
		,@IDBODEGA VARCHAR(20)	,@SYS_COMPUTERNAME VARCHAR(20)	, @IDSEDE VARCHAR(20)	, @GRUPO VARCHAR(20)	, @COMPANIA VARCHAR(20)
		,	@CANTOTAL DECIMAL(14,2), @CANTORG DECIMAL(14,2), @IDARTICULO VARCHAR(20), @CANT DECIMAL(14,2)
		,@CNSFCOM		VARCHAR(20)
DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200));
BEGIN   
	SET DATEFORMAT dmy
   
	SELECT * INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		MODELO  VARCHAR(100) '$.MODELO',
		METODO  VARCHAR(100) '$.METODO',
		USUARIO VARCHAR(20) '$.USUARIO',
		PARAMETROS NVARCHAR(MAX) AS JSON
	)
	SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @IDSEDE = IDSEDE, @SEDE = IDSEDE, @COMPANIA=COMPANIA, @IDBODEGA = COALESCE(IDBODEGA, IDBODEGA2, IDBODEGANOCHE, IDBODEGACONSUMO) FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
	SELECT @GRUPO = (SELECT DBO.FNK_DESCIFRAR(USUSU.GRUPO) FROM USUSU WHERE  USUARIO = @USUARIO)

	--DEFINICION DE TABLA DE ERRORES
	--  
	IF @METODO = 'ANIOS'
	BEGIN
		SELECT 'OK' OK

		SELECT DISTINCT YEAR(FECHAING) ANIO FROM ITRA ORDER BY YEAR(FECHAING) DESC

		RETURN
	END
	IF @METODO = 'EXCEL_DETALLE'
	BEGIN
		SELECT @CNSITRA = JSON_VALUE(@PARAMETROS, '$.CNSITRA')
		
		SELECT 'OK'OK
		SELECT ITRAH.CNSITRA,ITRAH.IDARTICULO,IART.DESCRIPCION,ITRAH.CANTIDADORI,NULL ID_ARTICULO , NULL  NOLOTE,NULL CANTIDADDES,NULL  FECHAVENCE
		,NULL PCOSTO,NULL IVA, NULL NROUNIDAD,NULL GRUPOABO, GRUPORH,NULL SUBGRUPO, NULL OBSERVACION
		FROM ITRAH 
		INNER JOIN IART ON ITRAH.IDARTICULO=IART.IDARTICULO 
		WHERE ITRAH.CNSITRA= @CNSITRA
		AND COALESCE(ITRAH.INICIAL,0)=0
	END	
	IF @METODO = 'EXPORT_TRANSITO'
	BEGIN
		SELECT @CNSITRA = JSON_VALUE(@PARAMETROS, '$.CNSITRA')
			,@CNSFCOM = JSON_VALUE(@PARAMETROS, '$.CNSFCOM')
		
		SELECT 'OK' OK
		SELECT FCOMD.IDARTICULO
			, IART.DESCRIPCION
			, CANTIDADSOL = FCOMD.CANTIDAD
			, PRECIO = CAST(FCOMD.VLR_UNITARIO AS DECIMAL(14,2))
			, OPCIONES = (
				SELECT * FROM (
					SELECT TOP 1 D.IDARTICULO, D.DESCRIPCION, PRINCIPAL
					FROM IART D 
					WHERE D.ESTADO='Activo'
					AND D.IDSERVICIO=IART.IDSERVICIO
					AND D.PRINCIPAL=1
					ORDER BY LEN(D.DESCRIPCION)
					UNION ALL
					SELECT D.IDARTICULO, D.DESCRIPCION, PRINCIPAL
					FROM IART D 
					WHERE D.ESTADO='Activo'
					AND D.IDSERVICIO=IART.IDSERVICIO
					AND D.PRINCIPAL=0
				) AS #T
				ORDER BY LEN(DESCRIPCION)
				FOR JSON PATH
			)
		FROM FCOMD 
		INNER JOIN FCOM ON FCOMD.CNSFCOM = FCOM.CNSFCOM
		INNER JOIN IART ON FCOMD.IDARTICULO=IART.IDARTICULO 
		LEFT JOIN ITRA ON FCOM.CNSFCOM = ITRA.CNSFCOM
		LEFT JOIN ITRAH ON FCOMD.CNSFCOM = ITRA.CNSFCOM AND FCOMD.IDARTICULO=ITRAH.IDARTICULO
		WHERE (@CNSITRA IS NULL OR ITRAH.CNSITRA = @CNSITRA)
		AND (@CNSFCOM IS NULL OR @CNSFCOM = ITRA.CNSFCOM)
		AND COALESCE(ITRAH.INICIAL,0)=0


		--SELECT ITRAH.IDARTICULO
		--	, IART.DESCRIPCION
		--	, CANTIDADSOL = ITRAH.CANTIDADORI
		--	, PRECIO = CAST(FCOMD.VLR_UNITARIO AS DECIMAL(14,2))
		--	, OPCIONES = (
		--		SELECT * FROM (
		--			SELECT TOP 1 D.IDARTICULO, D.DESCRIPCION, PRINCIPAL
		--			FROM IART D 
		--			WHERE D.ESTADO='Activo'
		--			AND D.IDSERVICIO=IART.IDSERVICIO
		--			AND D.PRINCIPAL=1
		--			ORDER BY LEN(D.DESCRIPCION)
		--			UNION ALL
		--			SELECT D.IDARTICULO, D.DESCRIPCION, PRINCIPAL
		--			FROM IART D 
		--			WHERE D.ESTADO='Activo'
		--			AND D.IDSERVICIO=IART.IDSERVICIO
		--			AND D.PRINCIPAL=0
		--		) AS #T
		--		ORDER BY LEN(DESCRIPCION)
		--		FOR JSON PATH
		--	)
		--FROM ITRAH 
		--INNER JOIN ITRA ON ITRA.CNSITRA = ITRAH.CNSITRA
		--INNER JOIN IART ON ITRAH.IDARTICULO=IART.IDARTICULO 
		--INNER JOIN FCOMD ON FCOMD.CNSFCOM = ITRA.CNSFCOM AND FCOMD.IDARTICULO=ITRAH.IDARTICULO
		--WHERE (@CNSITRA IS NULL OR ITRAH.CNSITRA = @CNSITRA)
		--AND (@CNSFCOM IS NULL OR @CNSFCOM = ITRA.CNSFCOM)
		--AND COALESCE(ITRAH.INICIAL,0)=0


		
		RETURN
	END	
	IF @METODO = 'ON_PROCESAR'
	BEGIN
		SELECT @DATOS =  DATOS, @IDBODEGA = IDBODEGA, @CNSITRA = CNSITRA
	   FROM OPENJSON (@PARAMETROS)
	   WITH		 (	DATOS		NVARCHAR(MAX) AS JSON 
					,IDBODEGA	VARCHAR(20)		'$.IDBODEGA'
					,CNSITRA	VARCHAR(20)		'$.CNSITRA')

		SELECT  * INTO #PROCESO FROM OPENJSON (@DATOS)
		WITH(
		CNSITRA				VARCHAR(20)		'$.CNSITRA'
		,IDARTICULO			VARCHAR(20)		'$.IDARTICULO'
		,CANTIDADORI		INT				'$.CANTIDADORI'
		,ID_ARTICULO		VARCHAR(20)		'$.ID_ARTICULO'
		,CANTIDADDES		INT				'$.CANTIDADDES'
		,NOLOTE				VARCHAR(20)		'$.NOLOTE'
		,FECHAVENCE			DATE		'$.FECHAVENCE'
		,PCOSTO				DECIMAL(14,2)	'$.PCOSTO'
		,IVA				DECIMAL(14,2)	'$.IVA'
		,NROUNIDAD			VARCHAR(20)		'$.NROUNIDAD'
		,GRUPOABO			VARCHAR(20)		'$.GRUPOABO'
		,GRUPORH			VARCHAR(20)		'$.GRUPORH'
		,SUBGRUPO			VARCHAR(20)		'$.SUBGRUPO'
		,OBSERVACION		VARCHAR(50)		'$.OBSERVACION'
		)

		SELECT ROW_NUMBER() OVER(ORDER BY #PROCESO.IDARTICULO DESC) AS FILA_CITA,  @CNSITRA CNSITRA, #PROCESO.IDARTICULO,  #PROCESO.CANTIDADORI, #PROCESO.ID_ARTICULO, #PROCESO.NOLOTE, #PROCESO.CANTIDADDES
		, #PROCESO.PCOSTO, #PROCESO.GRUPOABO, #PROCESO.GRUPORH,  #PROCESO.OBSERVACION, #PROCESO.IVA, #PROCESO.NROUNIDAD, REPLACE(#PROCESO.FECHAVENCE,'-','')FECHAVENCE, #PROCESO.SUBGRUPO 
		INTO #PROCESO_LIMPIO 
		FROM #PROCESO
		INNER JOIN IART ON #PROCESO.ID_ARTICULO = IART.IDARTICULO
		INNER JOIN IART ORI ON #PROCESO.IDARTICULO = ORI.IDARTICULO
		WHERE #PROCESO.CANTIDADORI >= #PROCESO.CANTIDADDES AND COALESCE(#PROCESO.CANTIDADDES,0)>0

		SELECT TOP 100   * FROM #PROCESO_LIMPIO

		DECLARE @ITEM_CANT INT
		DECLARE @LIMITE_MAX INT
		SELECT @ITEM_CANT=1,@LIMITE_MAX=0
		SELECT @LIMITE_MAX=COUNT(*) FROM  #PROCESO_LIMPIO
		WHILE @ITEM_CANT<=@LIMITE_MAX
		BEGIN
			SELECT @CODIGOBARRA = NULL
			EXEC SPK_GENCONSECUTIVO @COMPANIA,@IDSEDE,'@ICBU',@CODIGOBARRA OUTPUT
			SELECT @CODIGOBARRA = @IDSEDE + 'L' + REPLACE(SPACE(8 - LEN(@CODIGOBARRA))+LTRIM(RTRIM(@CODIGOBARRA)),SPACE(1),0)

			INSERT INTO ITRAH (CNSITRA,IDARTICULO,NOLOTE,CANTIDADORI,CANTIDADDES,IDCAUSAL,ESTADO,       
						PCOSTO,NOLOTEPEDIDO,FECHAVENCE,DETALLE,INICIAL,IDARTICULOORI,    
						RINVIMA,SELLOCALIDAD,TEMPETURA,CAPACIDAD,IDDONANTE,NROUNIDAD,        
						PROCEDENCIA,CODBANSAN,GRUPOABO,GRUPORH,FRECOLECCION,
						CANTIDADREV,CUMPLE,APROBADO,PRESENCIA,SUBGRUPO, IVA )
			SELECT @CNSITRA,#PROCESO_LIMPIO.ID_ARTICULO, @CODIGOBARRA, #PROCESO_LIMPIO.CANTIDADDES, #PROCESO_LIMPIO.CANTIDADDES, '', 0
				,#PROCESO_LIMPIO.PCOSTO, #PROCESO_LIMPIO.NOLOTE, #PROCESO_LIMPIO.FECHAVENCE, #PROCESO_LIMPIO.OBSERVACION, 1, #PROCESO_LIMPIO.IDARTICULO, (SELECT TOP 1 RINVIMA FROM IEXI WHERE IEXI.IDARTICULO = #PROCESO_LIMPIO.ID_ARTICULO AND IEXI.IDBODEGA = @IDBODEGA)
				,NULL, NULL, NULL, NULL, #PROCESO_LIMPIO.NROUNIDAD , NULL, NULL, #PROCESO_LIMPIO.GRUPOABO, #PROCESO_LIMPIO.GRUPORH, NULL, 0, 1, 1, NULL, #PROCESO_LIMPIO.SUBGRUPO, IVA
			FROM #PROCESO_LIMPIO WHERE #PROCESO_LIMPIO.FILA_CITA = @ITEM_CANT

			UPDATE ITRAH SET ITRAH.CANTIDADORI=ITRAH.CANTIDADORI - #PROCESO_LIMPIO.CANTIDADDES ,ITRAH.CANTIDADDES=ITRAH.CANTIDADORI - #PROCESO_LIMPIO.CANTIDADDES
			FROM ITRAH, #PROCESO_LIMPIO 
				WHERE ITRAH.CNSITRA = @CNSITRA AND ITRAH.IDARTICULO = #PROCESO_LIMPIO.IDARTICULO AND #PROCESO_LIMPIO.FILA_CITA = @ITEM_CANT
				AND COALESCE(ITRAH.INICIAL,0)= 0  

			SELECT @ITEM_CANT = @ITEM_CANT+1 
		END	

		SELECT 'OK' OK

	END
END
