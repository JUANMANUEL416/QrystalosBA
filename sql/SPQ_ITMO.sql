CREATE OR ALTER PROCEDURE DBO.SPQ_ITMO
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @PARAMETROS   NVARCHAR(MAX), @MODELO         VARCHAR(100),   @METODO         VARCHAR(100)
DECLARE  @USUARIO      VARCHAR(20),   @IDTIPOMOV      VARCHAR(2),	  @DESCRIPCION	  VARCHAR(30)
DECLARE	 @TIPO		   VARCHAR(12),   @IDTIPOMOVOP    VARCHAR(2),	  @MPROVEEDOR	  BIT
DECLARE  @AFECTAPROM   BIT,			  @PIDEVALOR      BIT,			  @SECONTABILIZA  BIT
DECLARE  @GENTRANSITO  BIT,			  @AFECTACOSTO    BIT,			  @ESTADO		  VARCHAR(8)
DECLARE  @COMPROBANTE  VARCHAR(2),	  @OCULTARCOSTOS  BIT
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDTIPOMOV = IDTIPOMOV, @DESCRIPCION = DESCRIPCION, @TIPO = TIPO, @MPROVEEDOR = MPROVEEDOR, @AFECTAPROM = AFECTAPROM,
					@PIDEVALOR = PIDEVALOR, @SECONTABILIZA = SECONTABILIZA, @IDTIPOMOVOP = IDTIPOMOVOP, @GENTRANSITO = GENTRANSITO,
					@AFECTACOSTO = AFECTACOSTO, @ESTADO = ESTADO, @COMPROBANTE = COMPROBANTE, @OCULTARCOSTOS = OCULTARCOSTOS
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				IDTIPOMOV     VARCHAR(2)  '$.IDTIPOMOV',		DESCRIPCION		VARCHAR(30) '$.DESCRIPCION',	TIPO		VARCHAR(12) '$.TIPO',  
				MPROVEEDOR    BIT		  '$.MPROVEEDOR',		AFECTAPROM		BIT			'$.AFECTAPROM',		PIDEVALOR   BIT			'$.PIDEVALOR',
				SECONTABILIZA BIT		  '$.SECONTABILIZA',	IDTIPOMOVOP		VARCHAR(2)  '$.IDTIPOMOVOP',	GENTRANSITO	BIT			'$.GENTRANSITO',
				AFECTACOSTO   BIT		  '$.AFECTACOSTO',		ESTADO			VARCHAR(8)  '$.ESTADO',			COMPROBANTE	VARCHAR(2)  '$.COMPROBANTE',
				OCULTARCOSTOS BIT		  '$.OCULTARCOSTOS'
			)

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'EL TIPO DE MOVIMIENTO YA EXISTE'
			WHERE EXISTS (SELECT * FROM ITMO WHERE IDTIPOMOV = @IDTIPOMOV)

			IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
			BEGIN
				INSERT INTO ITMO (IDTIPOMOV ,DESCRIPCION ,TIPO ,MPROVEEDOR ,AFECTAPROM ,PIDEVALOR ,SECONTABILIZA ,IDTIPOMOVOP ,GENTRANSITO ,AFECTACOSTO ,ESTADO ,COMPROBANTE ,OCULTARCOSTOS)   
				SELECT @IDTIPOMOV ,@DESCRIPCION ,@TIPO ,@MPROVEEDOR ,@AFECTAPROM ,@PIDEVALOR ,@SECONTABILIZA ,@IDTIPOMOVOP ,@GENTRANSITO ,@AFECTACOSTO ,@ESTADO ,@COMPROBANTE ,COALESCE(@OCULTARCOSTOS, 0)
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ACTUALIZAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDTIPOMOV = IDTIPOMOV, @DESCRIPCION = DESCRIPCION, @TIPO = TIPO, @MPROVEEDOR = MPROVEEDOR, @AFECTAPROM = AFECTAPROM,
					@PIDEVALOR = PIDEVALOR, @SECONTABILIZA = SECONTABILIZA, @IDTIPOMOVOP = IDTIPOMOVOP, @GENTRANSITO = GENTRANSITO,
					@AFECTACOSTO = AFECTACOSTO, @ESTADO = ESTADO, @COMPROBANTE = COMPROBANTE, @OCULTARCOSTOS = OCULTARCOSTOS
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				IDTIPOMOV     VARCHAR(2)  '$.IDTIPOMOV',		DESCRIPCION		VARCHAR(30) '$.DESCRIPCION',	TIPO		VARCHAR(12) '$.TIPO',  
				MPROVEEDOR    BIT		  '$.MPROVEEDOR',		AFECTAPROM		BIT			'$.AFECTAPROM',		PIDEVALOR   BIT			'$.PIDEVALOR',
				SECONTABILIZA BIT		  '$.SECONTABILIZA',	IDTIPOMOVOP		VARCHAR(2)  '$.IDTIPOMOVOP',	GENTRANSITO	BIT			'$.GENTRANSITO',
				AFECTACOSTO   BIT		  '$.AFECTACOSTO',		ESTADO			VARCHAR(8)  '$.ESTADO',			COMPROBANTE	VARCHAR(2)  '$.COMPROBANTE',
				OCULTARCOSTOS BIT		  '$.OCULTARCOSTOS'
			)

			UPDATE ITMO SET DESCRIPCION = @DESCRIPCION, TIPO = @TIPO, MPROVEEDOR = @MPROVEEDOR, AFECTAPROM = @AFECTAPROM, PIDEVALOR = @PIDEVALOR,
						SECONTABILIZA = @SECONTABILIZA, IDTIPOMOVOP = @IDTIPOMOVOP, GENTRANSITO = @GENTRANSITO, AFECTACOSTO = @AFECTACOSTO,
						ESTADO = @ESTADO, COMPROBANTE = @COMPROBANTE, OCULTARCOSTOS = COALESCE(@OCULTARCOSTOS, 0)
			WHERE  IDTIPOMOV = @IDTIPOMOV
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
	
	IF @METODO = 'ELIMINAR'
	BEGIN
		BEGIN TRY
			SELECT @IDTIPOMOV = JSON_VALUE(@PARAMETROS, '$.IDTIPOMOV')

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'EL TIPO DE MOVIMIENTO TIENE EXCEPCIONES ASIGNADAS (IEXCEP)'
			WHERE EXISTS (SELECT * FROM IEXCEP WHERE IDTIPOMOV = @IDTIPOMOV)

			IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
			BEGIN
				DELETE FROM ITMO WHERE IDTIPOMOV = @IDTIPOMOV
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
END
