CREATE OR ALTER PROCEDURE DBO.SPQ_IFFA
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @PARAMETROS NVARCHAR(MAX), @MODELO         VARCHAR(100),   @METODO         VARCHAR(100)
DECLARE  @USUARIO    VARCHAR(20),   @IDFORFARM      VARCHAR(3),		@DESCRIPCION	VARCHAR(100)
DECLARE	 @IDITAR	 VARCHAR(2)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDFORFARM = IDFORFARM, @DESCRIPCION = DESCRIPCION, @IDITAR = IDITAR 
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				IDFORFARM VARCHAR(3)  '$.IDFORFARM', DESCRIPCION VARCHAR(100)  '$.DESCRIPCION',
				IDITAR	  VARCHAR(2)  '$.IDITAR'
			)

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'LA FORMA FARMACEUTICA YA EXISTE'
			WHERE EXISTS (SELECT * FROM IFFA WHERE IDFORFARM = @IDFORFARM)

			IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
			BEGIN
				INSERT INTO IFFA (IDFORFARM ,DESCRIPCION ,IDITAR ) 
				SELECT @IDFORFARM, @DESCRIPCION, @IDITAR
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ACTUALIZAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDFORFARM = IDFORFARM, @DESCRIPCION = DESCRIPCION, @IDITAR = IDITAR 
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				IDFORFARM VARCHAR(3)  '$.IDFORFARM', DESCRIPCION VARCHAR(100)  '$.DESCRIPCION',
				IDITAR	  VARCHAR(2)  '$.IDITAR'
			)

			UPDATE IFFA SET DESCRIPCION = @DESCRIPCION, IDITAR = @IDITAR WHERE IDFORFARM = @IDFORFARM			
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
	
	IF @METODO = 'ELIMINAR'
	BEGIN
		BEGIN TRY
			SELECT @IDFORFARM = JSON_VALUE(@PARAMETROS, '$.IDFORFARM')

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'LA FORMA FARMACEUTICA TIENE ARTICULOS RELACIONADOS (IART)'
			WHERE EXISTS (SELECT * FROM IART WHERE IDFORFARM = @IDFORFARM)

			IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
			BEGIN
				DELETE FROM IFFA WHERE IDFORFARM = @IDFORFARM
			END		
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
END
