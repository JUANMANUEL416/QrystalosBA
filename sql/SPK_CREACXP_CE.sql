IF EXISTS (SELECT name FROM sysobjects 
   WHERE name = 'SPK_CREACXP_CE' AND type = 'P')
   DROP PROCEDURE SPK_CREACXP_CE

GO
CREATE PROCEDURE DBO.SPK_CREACXP_CE
@NOAUT         VARCHAR(16),  
@COMPANIA      VARCHAR(2),  
@SEDE          VARCHAR(5),  
@USUARIO       VARCHAR(12),
@NVOCONSECFTR  VARCHAR(20)
WITH ENCRYPTION
AS      
DECLARE @CONTADOR INT  
DECLARE @VALORES  DECIMAL(14,2)  
DECLARE @NVOCONSEC INT  
DECLARE @IDPROVEEDOR VARCHAR(20)  
DECLARE @VALOR DECIMAL(14,2)  
DECLARE @IDAUT     VARCHAR(13)
DECLARE @N_FACTURA VARCHAR(16)
DECLARE @F_FACTURA  DATETIME
BEGIN  
   SELECT @CONTADOR = COUNT(*) FROM AUTD, AUT  
   WHERE  AUT.NOAUT = @NOAUT  
   AND    AUT.IDAUT = AUTD.IDAUT
   AND    ISNULL(AUT.IDPROVEEDOR,'') <> ''  
   AND    AUTD.N_FACTURA = CASE WHEN @NVOCONSECFTR IS NULL THEN AUTD.N_FACTURA ELSE @NVOCONSECFTR END  
   AND    ISNULL(AUT.CXPGEN,0) = 0
   PRINT '1'
   IF @CONTADOR <= 0  
   BEGIN
      RETURN  
   END
   SELECT @IDAUT = IDAUT FROM AUT WHERE NOAUT = @NOAUT
   PRINT '2'
   CREATE TABLE #ICXP (IDPROVEEDOR    VARCHAR(20)  COLLATE database_default, 
                       IDSERVICIO     VARCHAR(20) COLLATE database_default,  
                       VALOREXCEDENTE DECIMAL(14,2), 
                       DESCSEVICIO    VARCHAR(255) COLLATE database_default,  
                       IDAREA         VARCHAR(20) COLLATE database_default, 
                       IDCIRUGIA      VARCHAR(20) COLLATE database_default ,
                       PREFIJO        VARCHAR(6) COLLATE database_default,  
                       VALOR          DECIMAL(14,2),
                       CANTIDAD       INT,
                       NOPRESTACION   VARCHAR(16) COLLATE database_default,  
                       NOITEM         SMALLINT ,
                       N_FACTURA      VARCHAR(16) COLLATE database_default, 
                       CCOSTO         VARCHAR(20) COLLATE database_default,
                       IDAREAH        VARCHAR(20) COLLATE database_default, 
                       ITEM           INT IDENTITY, 
                       IDTERCEROCA    VARCHAR(20) COLLATE database_default, 
	                    IDPLAN         VARCHAR(6) COLLATE database_default, 
	                    FACTOR         DECIMAL(14,2), 
	                    VALORCXP       DECIMAL(14,2) ) 
   
   PRINT '3'
   	IF (DBO.FNK_VALORVARIABLE('HONORATAR_DIF')='SI')
   BEGIN
    INSERT INTO #ICXP  (IDPROVEEDOR, IDSERVICIO, VALOREXCEDENTE, DESCSEVICIO, IDAREA,
                         PREFIJO, VALOR, CANTIDAD, NOPRESTACION, N_FACTURA, CCOSTO,
                         IDAREAH, IDTERCEROCA, IDPLAN, FACTOR, VALORCXP )
    SELECT IDPROVEEDOR,AUTD.IDSERVICIO,VALOREXEDENTE,SER.DESCSERVICIO,IDAREA,SER.PREFIJO,CASE DBO.TARF.REDONDEO
               WHEN 'Unidad'   THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,0)
               WHEN 'Decena'   THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,-1)
               WHEN 'Centena'  THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,-2)
               WHEN 'Millar'   THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,-3)
               WHEN 'Dos Dec.' THEN ROUND(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,2)
               WHEN 'SIN'      THEN (DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO)
               ELSE round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,0)    
               END    ,
   AUTD.CANTIDAD,AUT.IDAUT,AUT.N_FACTURA,AUT.CCOSTO,IDAREAH,AUT.IDTERCEROCA,AUT.IDPLAN,FACTOR,CASE DBO.TARF.REDONDEO
               WHEN 'Unidad'   THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,0)
               WHEN 'Decena'   THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,-1)
               WHEN 'Centena'  THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,-2)
               WHEN 'Millar'   THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,-3)
               WHEN 'Dos Dec.' THEN ROUND(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,2)
               WHEN 'SIN'      THEN (DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO)
               ELSE round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,0)    
               END    
   FROM AUT INNER JOIN AUTD ON AUT.IDAUT=AUTD.IDAUT  
             INNER JOIN SER ON AUTD.IDSERVICIO=SER.IDSERVICIO
             INNER JOIN PXS ON PXS.IDTERCERO=AUT.IDPROVEEDOR 
             INNER JOIN TARDV ON TARDV.IDSERVICIO=SER.CODCUPS
             AND AUT.IDPLAN = PXS.IDPLAN
	          AND AUT.IDTERCEROCA  = PXS.IDADMINISTRADORA
             INNER JOIN TARF ON TARDV.IDTARIFA=TARF.IDTARIFA         
   WHERE AUT.NOAUT=@NOAUT
   GROUP BY IDPROVEEDOR,AUTD.IDSERVICIO,VALOREXEDENTE,SER.DESCSERVICIO,IDAREA,SER.PREFIJO,CASE DBO.TARF.REDONDEO
               WHEN 'Unidad'   THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,0)
               WHEN 'Decena'   THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,-1)
               WHEN 'Centena'  THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,-2)
               WHEN 'Millar'   THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,-3)
               WHEN 'Dos Dec.' THEN ROUND(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,2)
               WHEN 'SIN'      THEN (DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO)
               ELSE round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,0)    
               END    ,
   AUTD.CANTIDAD,AUT.IDAUT,AUT.N_FACTURA,AUT.CCOSTO,IDAREAH,AUT.IDTERCEROCA,AUT.IDPLAN,FACTOR,CASE DBO.TARF.REDONDEO
               WHEN 'Unidad'   THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,0)
               WHEN 'Decena'   THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,-1)
               WHEN 'Centena'  THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,-2)
               WHEN 'Millar'   THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,-3)
               WHEN 'Dos Dec.' THEN ROUND(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,2)
               WHEN 'SIN'      THEN (DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO)
               ELSE round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,0)    
               END  
   END
   ELSE
   BEGIN
      INSERT INTO #ICXP  
      SELECT AUT.IDPROVEEDOR, SER.IDSERVICIO, AUTD.VALOR * AUTD.CANTIDAD  ,SER.DESCSERVICIO,  
             AUT.IDAREA, '' , SER.PREFIJO, VALORPROV, AUTD.CANTIDAD,AUTD.IDAUT,  
             AUTD.NO_ITEM, AUTD.N_FACTURA, AUT.CCOSTO, AUT.IDAREA, AUTD.IDTERCEROCA, 
             AUTD.IDPLAN, 0, VALORPROV  
      FROM   AUTD, SER, AUT    
      WHERE  AUT.NOAUT         = @NOAUT
      AND    SER.IDSERVICIO    = AUTD.IDSERVICIO   
      AND    AUT.IDAUT         = AUTD.IDAUT
      AND    ISNULL(AUT.IDPROVEEDOR,'') <> ''
      AND    AUTD.N_FACTURA = CASE WHEN @NVOCONSECFTR IS NULL THEN AUTD.N_FACTURA ELSE @NVOCONSECFTR END  
      AND    ISNULL(AUT.CXPGEN,0) = 0
      ORDER BY AUT.IDPROVEEDOR   
   END
   PRINT '4'
   
   --  
   CREATE TABLE #PCXP (IDPROVEEDOR VARCHAR(20),VALOR DECIMAL(14,2))  
   INSERT INTO  #PCXP (IDPROVEEDOR,VALOR)  
   SELECT IDPROVEEDOR,SUM(VALORCXP)  
   FROM   #ICXP  
   WHERE COALESCE(VALOR,0)>0
   GROUP BY IDPROVEEDOR  
   --CURSOR--  
   DECLARE CXP_CURSOR CURSOR FOR  
   SELECT IDPROVEEDOR,VALOR FROM #PCXP  
   OPEN CXP_CURSOR  
   FETCH NEXT FROM CXP_CURSOR  
   INTO @IDPROVEEDOR,@VALOR  
   WHILE @@FETCH_STATUS = 0  
   BEGIN  

         IF @NVOCONSECFTR IS NULL
         BEGIN
            SELECT TOP 1 @N_FACTURA = N_FACTURA FROM AUTD WHERE IDAUT = @IDAUT
            SELECT @F_FACTURA = F_FACTURA FROM FTR WHERE N_FACTURA = @N_FACTURA
         END
         
         EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@FCXP',@NVOCONSEC OUTPUT  
         SELECT @NVOCONSEC = @SEDE + REPLACE(SPACE(8 - LEN(@NVOCONSEC))+LTRIM(RTRIM(@NVOCONSEC)),SPACE(1),0)
         INSERT INTO FXP(N_PRESUP,IDTERCERO,NOREFERENCIA,F_FACTURAREF,F_VENCE,VR_TOTAL,ESTADO,  
                         F_CANCELADO,EMPLEADO,PROCEDENCIA,OBSERVACION,COMPANIA,INDCOBRADA)  
         SELECT @NVOCONSEC,@IDPROVEEDOR,@IDAUT, CASE WHEN @NVOCONSECFTR IS NULL THEN @F_FACTURA ELSE GETDATE() END, 
                NULL,@VALOR,'P',NULL,@USUARIO,  
                'CE','',@COMPANIA,0  
         INSERT INTO FXPD(N_PRESUP,IDTERCERO,ITEM,IDSERVICIO,PREFIJO,VALOR,CANTIDAD,VR_TOTAL,  
                          NOPRESTACION,NOITEM,IDCIRUGIA, N_FACTURA, ESTADO, CCOSTO, IDAREA,
                          IDAREAH )  
         SELECT @NVOCONSEC,@IDPROVEEDOR,ITEM,IDSERVICIO,PREFIJO,VALOR,CANTIDAD,  
                VALORCXP,NOPRESTACION,NOITEM,IDCIRUGIA, N_FACTURA , 'P', CCOSTO, IDAREA,
                IDAREAH
         FROM   #ICXP  
         WHERE  IDPROVEEDOR = @IDPROVEEDOR  

         FETCH NEXT FROM CXP_CURSOR  
         INTO  @IDPROVEEDOR,@VALOR  
   END  
   CLOSE CXP_CURSOR      
   DEALLOCATE CXP_CURSOR
           
   UPDATE AUT SET CXPGEN = 1  
   WHERE  NOAUT = @NOAUT    
   PRINT @NVOCONSEC
   DROP TABLE #ICXP  
   DROP TABLE #PCXP  

   IF EXISTS( SELECT * FROM HOMED WHERE PROCEDENCIA='AUT' AND NOPRESTACION=@IDAUT)
   BEGIN
      DECLARE @NPRESTACIONH VARCHAR(20)
      DECLARE @ITEM SMALLINT
      DECLARE @IDTERCEROP VARCHAR(20)
      DECLARE @PORCEN  DECIMAL(7,2)
      DECLARE CXP_CURSOR CURSOR FOR  
      SELECT NOPRESTACION,ITEM,IDTERCERO,PORCEN  FROM HOMED WHERE PROCEDENCIA='AUT' AND NOPRESTACION=@IDAUT
      ORDER BY NOPRESTACION
      OPEN CXP_CURSOR  
      FETCH NEXT FROM CXP_CURSOR  
      INTO @NPRESTACIONH,@ITEM,@IDTERCEROP, @PORCEN 
      WHILE @@FETCH_STATUS = 0  
      BEGIN  
         SELECT @VALOR=(VALOR*CANTIDAD)*(@PORCEN/100) FROM AUTD WHERE IDAUT=@IDAUT AND NO_ITEM=@ITEM
         IF @NVOCONSECFTR IS NULL
         BEGIN
            SELECT TOP 1 @N_FACTURA = N_FACTURA FROM AUTD WHERE IDAUT = @IDAUT
            SELECT @F_FACTURA = F_FACTURA FROM FTR WHERE N_FACTURA = @N_FACTURA
         END
         
         EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@FCXP',@NVOCONSEC OUTPUT  
         SELECT @NVOCONSEC = @SEDE + REPLACE(SPACE(8 - LEN(@NVOCONSEC))+LTRIM(RTRIM(@NVOCONSEC)),SPACE(1),0)
         INSERT INTO FXP(N_PRESUP,IDTERCERO,NOREFERENCIA,F_FACTURAREF,F_VENCE,VR_TOTAL,ESTADO,  
                         F_CANCELADO,EMPLEADO,PROCEDENCIA,OBSERVACION,COMPANIA,INDCOBRADA)  
         SELECT @NVOCONSEC,@IDTERCEROP,@IDAUT, CASE WHEN @NVOCONSECFTR IS NULL THEN @F_FACTURA ELSE GETDATE() END, 
                NULL,@VALOR,'P',NULL,@USUARIO,  
                'CE','',@COMPANIA,0  

         INSERT INTO FXPD(N_PRESUP,IDTERCERO,ITEM,IDSERVICIO,PREFIJO,VALOR,CANTIDAD,VR_TOTAL,  
                          NOPRESTACION,NOITEM,IDCIRUGIA, N_FACTURA, ESTADO, CCOSTO, IDAREA,
                          IDAREAH )  
         SELECT @NVOCONSEC,@IDTERCEROP,NO_ITEM,AUTD.IDSERVICIO,AUT.PREFIJO,ROUND((@VALOR/AUTD.CANTIDAD),2),AUTD.CANTIDAD,  
                @VALOR,AUTD.IDAUT,NO_ITEM,AUTD.IDSERVICIO, AUT.N_FACTURA , 'P', AUT.CCOSTO, AUT.IDAREA,
                AUT.IDAREAH
         FROM   AUTD INNER JOIN AUT ON AUTD.IDAUT=AUT.IDAUT
         WHERE  AUT.IDAUT=@IDAUT
         AND NO_ITEM=@ITEM

         FETCH NEXT FROM CXP_CURSOR  
         INTO  @NPRESTACIONH,@ITEM,@IDTERCEROP, @PORCEN  
      END  
      CLOSE CXP_CURSOR      
      DEALLOCATE CXP_CURSOR      

   END


END
