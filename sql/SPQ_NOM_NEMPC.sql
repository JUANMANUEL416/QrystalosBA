CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NEMPC @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100)
DECLARE @USUARIO VARCHAR(20), @PROCESO VARCHAR(20)
DECLARE @NUMDOC VARCHAR(20), @NOITEM SMALLINT, @FECHAFIN DATETIME, @FECHAINI DATETIME, @TIPOCON VARCHAR(20)
DECLARE @DETALLES VARCHAR(1025), @IDALTERNA VARCHAR(20), @IDCONTRATO VARCHAR(20), @IDALTERNAEDITE VARCHAR(20)
DECLARE @IDSEDE VARCHAR(5), @SYS_COMPUTERNAME VARCHAR(254)
DECLARE @DATO NVARCHAR(MAX)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
		FROM USUSU
		WHERE USUARIO = @USUARIO

		SELECT @IDSEDE = IDSEDE
		FROM UBEQ
		WHERE SYS_ComputerName = @SYS_COMPUTERNAME

		BEGIN TRY
			SELECT @NUMDOC = NUMDOC, @NOITEM = NOITEM, @FECHAFIN = FECHAFIN, @FECHAINI = FECHAINI, @TIPOCON = TIPOCON, @DETALLES = DETALLES, @IDALTERNA = IDALTERNA, 
				@PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					NUMDOC VARCHAR(10) '$.NUMDOC', NOITEM SMALLINT '$.NOITEM', FECHAFIN DATETIME '$.FECHAFIN', FECHAINI DATETIME '$.FECHAINI', TIPOCON VARCHAR(20) 
					'$.TIPOCON', DETALLES VARCHAR(1025) '$.DETALLES', IDALTERNA VARCHAR(20) '$.IDALTERNA', PROCESO VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@NEMPC', @LONGITUD = 8, @NVOCONSEC = @IDCONTRATO OUTPUT

					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('YA SE ENCUENTRA REGISTRADO EL NUMERO DE CONTRATO ', @IDALTERNA)
					WHERE EXISTS (
							SELECT 1
							FROM NEMPC
							WHERE NUMDOC = @NUMDOC AND IDALTERNA = @IDALTERNA
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO NEMPC (
							NUMDOC, NOITEM, IDCONTRATO, FECHAINI, FECHAFIN, TIPOCON, USUARIO, DETALLES, IDALTERNA, CONTRATOLAB, IDFORMATO, FECHA, DOCUMENTOID, 
							IDFIRMAJEFE, IDFIRMAEMPLE
							)
						SELECT @NUMDOC, @NOITEM, @IDCONTRATO, @FECHAINI, @FECHAFIN, @TIPOCON, @USUARIO, @DETALLES, @IDALTERNA, '', '', NULL, '', '', ''
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @DATO = DATO
					FROM OPENJSON(@PARAMETROS) WITH (DATO NVARCHAR(MAX) AS JSON)

					SELECT @IDALTERNAEDITE = IDALTERNAEDITE
					FROM OPENJSON(@DATO) WITH (IDALTERNAEDITE VARCHAR(20) '$.IDALTERNAEDITE')

					IF (@IDALTERNAEDITE <> @IDALTERNA)
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('YA SE ENCUENTRA REGISTRADO EL NUMERO DE CONTRATO ', @IDALTERNA)
						WHERE EXISTS (
								SELECT 1
								FROM NEMPC
								WHERE NUMDOC = @NUMDOC AND IDALTERNA = @IDALTERNA
								)

						IF (
								SELECT COUNT(*)
								FROM @TBLERRORES
								) <= 0
						BEGIN
							UPDATE NEMPC
							SET FECHAINI = @FECHAINI, FECHAFIN = @FECHAFIN, TIPOCON = @TIPOCON, DETALLES = @DETALLES, IDALTERNA = @IDALTERNA
							WHERE NUMDOC = @NUMDOC AND NOITEM = @NOITEM
						END
					END
					ELSE
					BEGIN
						UPDATE NEMPC
						SET FECHAINI = @FECHAINI, FECHAFIN = @FECHAFIN, TIPOCON = @TIPOCON, DETALLES = @DETALLES
						WHERE NUMDOC = @NUMDOC AND NOITEM = @NOITEM
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @NUMDOC = NUMDOC, @NOITEM = NOITEM
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC', NOITEM SMALLINT '$.NOITEM')

		BEGIN TRY
			DELETE
			FROM NEMPC
			WHERE NUMDOC = @NUMDOC AND NOITEM = @NOITEM
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
