CREATE OR ALTER PROCEDURE DBO.SPK_TRAECOMPRA_SALIDA
@CNSMOVSAL VARCHAR(16),
@CNSMOVORI VARCHAR(16),
@IDBODEGA  VARCHAR(20),
@PARA      VARCHAR(5)
WITH ENCRYPTION
AS
DECLARE @IDARTICULO VARCHAR(20)
DECLARE @NOLOTE     VARCHAR(20)
DECLARE @CANTIDAD   DECIMAL(14,2)
DECLARE @PCOSTO     DECIMAL(14,2)
BEGIN
   /*
     Web / entrega din�mica:
     - NO insertar IMOVH aqu�: el usuario puede editar/borrar lotes en pantalla.
       IMOVH se crea al Confirmar Entrega (sincroniza desde ISAL).
     - Solo deja las l�neas en ISAL (como borrador de entrega).
   */
   -- INSERT INTO IMOVH ( CNSMOV,IDARTICULO,EXISTENCIA,CANTIDAD,CANTPEDIDA,PCOSTO,NOLOTE,NOLOTEPEDIDO,FECHAVENCE,ESTADO,
   --                                                     IDARTICULOTF,CANTIDADTF,PCOSTOANTES,CNSTRAN,ITEM,PVENTA,USUARIO,USUARIOCONF,FECHACONF,PRIEXI,
   --                                                     FECHAREPOSI,IDARTICULOORI,CANTIDADORI,TIENECAMBIO,DETALLE,CANT_EN_ACTIVOS,ENCXP,PIVA,VLRIVA,PDTO,
   --                                                     VLRDTO,CNSHTX,COTIZADO,IDIMPUESTO,IDCLASE,ITFC,CNSITFC,CUENTA_FIMPDV,IDITAR,CODCUM,CAMBIADO,
   --                                                     PCOSTOANTESMOD,USUARIOCAMBIO,IDFABRICANTE,CUENTADB,CUENTACR )
   -- SELECT @CNSMOVSAL,IDARTICULO,EXISTENCIA,CANTIDAD,CANTPEDIDA,PCOSTO,NOLOTE,NOLOTEPEDIDO,FECHAVENCE,0,
   --         IDARTICULOTF,CANTIDADTF,PCOSTOANTES,CNSTRAN,ITEM,PVENTA,USUARIO,USUARIOCONF,FECHACONF,PRIEXI,
   --         FECHAREPOSI,IDARTICULOORI,CANTIDADORI,TIENECAMBIO,DETALLE,CANT_EN_ACTIVOS,ENCXP,PIVA,VLRIVA,PDTO,
   --         VLRDTO,CNSHTX,COTIZADO,IDIMPUESTO,IDCLASE,ITFC,CNSITFC,CUENTA_FIMPDV,IDITAR,CODCUM,CAMBIADO,
   --         PCOSTOANTESMOD,USUARIOCAMBIO,IDFABRICANTE,CUENTADB,CUENTACR
   -- FROM IMOVH WHERE CNSMOV=@CNSMOVORI

   DECLARE INSER_ISAL CURSOR FOR
   SELECT IMOVH.IDARTICULO, IMOVH.NOLOTE, IMOVH.CANTIDAD, IMOVH.PCOSTO
   FROM IMOV
   INNER JOIN IMOVH ON IMOV.CNSMOV = IMOVH.CNSMOV
   WHERE IMOV.CNSMOV = @CNSMOVORI
     AND IMOV.IDBODEGA = @IDBODEGA

   OPEN INSER_ISAL
   FETCH NEXT FROM INSER_ISAL
   INTO @IDARTICULO, @NOLOTE, @CANTIDAD, @PCOSTO

   WHILE @@FETCH_STATUS = 0
   BEGIN
      INSERT INTO ISAL (CNSMOV, NOLOTE, IDARTICULO, CANTIDAD, FECHA, NOLOTEPEDIDO, FECHAVENCE, PCOSTO, IDARTICULO_IMOVH)
      SELECT
         @CNSMOVSAL,
         @NOLOTE,
         @IDARTICULO,
         CASE WHEN IEXI.EXISLOTE < @CANTIDAD THEN IEXI.EXISLOTE ELSE @CANTIDAD END,
         DBO.FNK_FECHA_SIN_MLS(GETDATE()),
         IEXI.NOLOTEPEDIDO,
         IEXI.FECHAVENCE,
         CASE WHEN @PARA = 'ACT' THEN @PCOSTO ELSE IART.PCOSTO END,
         @IDARTICULO
      FROM IEXI
      INNER JOIN IART ON IEXI.IDARTICULO = IART.IDARTICULO
      WHERE IEXI.NOLOTE = @NOLOTE
        AND IEXI.IDARTICULO = @IDARTICULO
        AND IEXI.IDBODEGA = @IDBODEGA
        AND NOT EXISTS (
           SELECT 1
           FROM ISAL S
           WHERE S.CNSMOV = @CNSMOVSAL
             AND S.IDARTICULO = @IDARTICULO
             AND S.NOLOTE = @NOLOTE
             AND COALESCE(S.NOLOTEPEDIDO, '') = COALESCE(IEXI.NOLOTEPEDIDO, '')
        )

      FETCH NEXT FROM INSER_ISAL
      INTO @IDARTICULO, @NOLOTE, @CANTIDAD, @PCOSTO
   END

   CLOSE INSER_ISAL
   DEALLOCATE INSER_ISAL
END
