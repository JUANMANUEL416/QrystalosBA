CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NCONDA
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @DATO				NVARCHAR(MAX)
DECLARE  @PARAMETROS		NVARCHAR(MAX),	@MODELO			VARCHAR(100),   @METODO		VARCHAR(100),	@USUARIO	VARCHAR(20)
DECLARE	 @PROCESO			VARCHAR(20)
DECLARE	 @CODCONCEPTO		VARCHAR(20),	@ITEM				DECIMAL(14,0)
DECLARE	 @CODCONCEPTOA		VARCHAR(20),	@FACTOR				DECIMAL(15,6)
DECLARE	 @HORAS				INT,			@DIAS				INT
DECLARE	 @CODCONCEPTOAEDITE		VARCHAR(20)

DECLARE  @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

	IF @METODO = 'GUARDAR'
		BEGIN
			BEGIN TRY
				SELECT  @CODCONCEPTO = CODCONCEPTO, @ITEM = ITEM,
						@CODCONCEPTOA = CODCONCEPTOA, @FACTOR = FACTOR,
						@HORAS = HORAS, @DIAS = DIAS,
						@PROCESO = PROCESO
				FROM	OPENJSON (@PARAMETROS) 
				WITH	(
					CODCONCEPTO		VARCHAR(20)			'$.CODCONCEPTO',
					ITEM			DECIMAL(14,0)		'$.ITEM',
					CODCONCEPTOA	VARCHAR(20)			'$.CODCONCEPTOA',
					FACTOR			DECIMAL(15,6)		'$.FACTOR',
					HORAS			INT					'$.HORAS',
					DIAS			INT					'$.DIAS',
					PROCESO			VARCHAR(20)			'$.PROCESO'
				)
				IF UPPER(@PROCESO) = 'INSERTAR'
				BEGIN
					BEGIN TRY
							INSERT INTO @TBLERRORES(ERROR) 
							SELECT CONCAT('EL CONCEPTO ASOCIADO ',@CODCONCEPTOA, ' YA SE ENCUENTRA REGISTRADO')
							WHERE EXISTS (SELECT 1 FROM NCONDA WHERE CODCONCEPTO = @CODCONCEPTO AND CODCONCEPTOA = @CODCONCEPTOA)

							IF(SELECT COUNT(*) FROM @TBLERRORES) <= 0
								BEGIN
									INSERT INTO NCONDA (CODCONCEPTO ,ITEM ,CODCONCEPTOA ,
									FACTOR , HORAS ,DIAS ) 
									SELECT @CODCONCEPTO, @ITEM, @CODCONCEPTOA,
									@FACTOR, @HORAS, @DIAS 
								END
					END TRY
					BEGIN CATCH
						INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
					END CATCH

					IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
					BEGIN
						SELECT 'KO' OK
						SELECT ERROR FROM @TBLERRORES
						RETURN
					END

					SELECT 'OK' OK 
					RETURN
				END

				IF UPPER(@PROCESO) = 'EDITAR'
					BEGIN
						BEGIN TRY
						SELECT @DATO = DATO       
							  FROM   OPENJSON (@PARAMETROS)
							  WITH (DATO NVARCHAR(MAX) AS JSON)   
							  
							  SELECT @CODCONCEPTOAEDITE = CODCONCEPTOAEDITE
							  FROM   OPENJSON (@DATO)
							  WITH   (   
							  CODCONCEPTOAEDITE		VARCHAR(20)		 '$.CODCONCEPTOAEDITE'
							  )

							  --INSERT INTO @TBLERRORES(ERROR) 
							  --SELECT CONCAT('EL CONCEPTO ASOCIADO ',@CODCONCEPTOA, ' YA SE ENCUENTRA REGISTRADO')
							 -- WHERE EXISTS (SELECT 1 FROM NCONDA WHERE  CODCONCEPTO = @CODCONCEPTO AND CODCONCEPTOA = @CODCONCEPTOAEDITE)

								--IF(SELECT COUNT(*) FROM @TBLERRORES) <= 0
								BEGIN
									UPDATE NCONDA SET CODCONCEPTOA = @CODCONCEPTOA, FACTOR = @FACTOR,
									HORAS = @HORAS ,DIAS = @DIAS
									WHERE CODCONCEPTOA = @CODCONCEPTOAEDITE
								END
						END TRY

						BEGIN CATCH
							INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
						END CATCH

						IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
						BEGIN
							SELECT 'KO' OK
							SELECT ERROR FROM @TBLERRORES
							RETURN
						END

						SELECT 'OK' OK 
						RETURN
					END
		END TRY

			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
			END CATCH

			IF(SELECT COUNT(*) FROM @TBLERRORES) >0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END

			SELECT 'OK' OK
		END

		IF @METODO = 'ELIMINAR'
			BEGIN
					SELECT  @CODCONCEPTO = CODCONCEPTO, @ITEM = ITEM, @CODCONCEPTOA = CODCONCEPTOA
					FROM	OPENJSON (@PARAMETROS) 
					WITH(
						CODCONCEPTO			VARCHAR(20)			'$.CODCONCEPTO',
						ITEM				DECIMAL(14,0)		'$.ITEM',
						CODCONCEPTOA		VARCHAR(20)			'$.CODCONCEPTOA'
						)

			BEGIN TRY
					DELETE FROM NCONDA WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM AND CODCONCEPTOA = @CODCONCEPTOA
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
				END CATCH

				IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
				BEGIN
					SELECT 'KO' OK
					SELECT ERROR FROM @TBLERRORES
					RETURN
				END
		SELECT 'OK' OK
		END
END
