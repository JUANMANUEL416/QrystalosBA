CREATE OR ALTER PROCEDURE DBO.SPK_GENERARFISICO_U
    @CNSIFIS VARCHAR(20),
    @IDBODEGA VARCHAR(20),
    @TODASLASBODEGAS SMALLINT,
    @USUARIO VARCHAR(12)
WITH ENCRYPTION
AS
DECLARE @ESTADO1 INT = 0
DECLARE @ESTADO2 INT = 0
DECLARE @ESTADO3 INT = 0
BEGIN
    SELECT @ESTADO1=ISNULL(MAX(ESTADO1),0), @ESTADO2=ISNULL(MAX(ESTADO2),0), @ESTADO3=ISNULL(MAX(ESTADO3),0) 
    FROM IFISHU WHERE CNSIFIS=@CNSIFIS AND IDBODEGA=@IDBODEGA 

    IF ISNULL(@USUARIO,'') <> ''
    BEGIN
        IF @TODASLASBODEGAS=1
        BEGIN
            INSERT INTO IFISHU(
                CNSIFIS, IDBODEGA, IDARTICULO, NOLOTE, NOLOTEPEDIDO, LUGAR1, LUGAR2, LUGAR3, LUGAR4, LUGAR5, 
                CONTEO1, CONTEO2, CONTEO3, ESTADO1, ESTADO2, ESTADO3, USUARIO, DESCRIPCION
            )
            SELECT
                @CNSIFIS, IFISH.IDBODEGA, IFISH.IDARTICULO, IFISH.NOLOTE, IFISH.NOLOTEPEDIDO, ISNULL(IEXI.LUGAR1,''), ISNULL(IEXI.LUGAR2,''), ISNULL(IEXI.LUGAR3,''), ISNULL(IEXI.LUGAR4,''), ISNULL(IEXI.LUGAR5,''),
                0, 0, 0, @ESTADO1, @ESTADO2, @ESTADO3, @USUARIO, IART.DESCRIPCION
            FROM IFIS
                INNER JOIN IFISH ON IFISH.CNSIFIS=IFIS.CNSIFIS AND IFISH.IDBODEGA=IFIS.IDBODEGA 
                LEFT JOIN IEXI  ON IFISH.IDBODEGA=IEXI.IDBODEGA AND IFISH.IDARTICULO=IEXI.IDARTICULO AND IFISH.NOLOTE=IEXI.NOLOTE
                INNER JOIN IART  ON IFISH.IDARTICULO=IART.IDARTICULO
            WHERE IFIS.CNSIFIS=@CNSIFIS AND IFIS.IDBODEGA=@IDBODEGA AND IFIS.CERRADO=0
                AND NOT EXISTS (
                    SELECT 1 FROM IFISHU AS U WHERE U.CNSIFIS=IFIS.CNSIFIS AND U.IDBODEGA=IFIS.IDBODEGA 
                        AND U.USUARIO=@USUARIO AND U.IDARTICULO=IFISH.IDARTICULO AND U.NOLOTE=IFISH.NOLOTE 
                    )
        END
        ELSE
        BEGIN
            INSERT INTO IFISHU(
                CNSIFIS, IDBODEGA, IDARTICULO, NOLOTE, NOLOTEPEDIDO, LUGAR1, LUGAR2, LUGAR3, LUGAR4, LUGAR5,
                CONTEO1, CONTEO2, CONTEO3, ESTADO1, ESTADO2, ESTADO3, USUARIO, DESCRIPCION
            )
            SELECT 
                @CNSIFIS, IFISH.IDBODEGA, IFISH.IDARTICULO, IFISH.NOLOTE, IFISH.NOLOTEPEDIDO, 
                ISNULL(IEXI.LUGAR1,''), ISNULL(IEXI.LUGAR2,''), ISNULL(IEXI.LUGAR3,''), ISNULL(IEXI.LUGAR4,''), ISNULL(IEXI.LUGAR5,''),
                0, 0, 0, @ESTADO1, @ESTADO2, @ESTADO3, @USUARIO, IART.DESCRIPCION
            FROM IFIS
                INNER JOIN IFISH ON IFISH.CNSIFIS=IFIS.CNSIFIS AND IFISH.IDBODEGA=IFIS.IDBODEGA 
                LEFT JOIN IEXI  ON IFISH.IDBODEGA=IEXI.IDBODEGA AND IFISH.IDARTICULO=IEXI.IDARTICULO AND IFISH.NOLOTE=IEXI.NOLOTE
                INNER JOIN IART  ON IFISH.IDARTICULO=IART.IDARTICULO
            WHERE IFIS.CNSIFIS=@CNSIFIS AND IFIS.CERRADO=0
                AND NOT EXISTS (
                    SELECT 1 FROM IFISHU AS U WHERE U.CNSIFIS=IFIS.CNSIFIS AND U.IDBODEGA=IFIS.IDBODEGA 
                        AND U.USUARIO=@USUARIO AND U.IDARTICULO=IFISH.IDARTICULO AND U.NOLOTE=IFISH.NOLOTE 
                    )
        END
    END

    SELECT DISTINCT IDBODEGA, USUARIO INTO #Y FROM IFISHU WHERE CNSIFIS=@CNSIFIS

    INSERT INTO IFISHU(
        CNSIFIS, IDBODEGA, IDARTICULO, NOLOTE, NOLOTEPEDIDO, LUGAR1, LUGAR2, LUGAR3, LUGAR4, LUGAR5,
        CONTEO1, CONTEO2, CONTEO3, ESTADO1, ESTADO2, ESTADO3, USUARIO, DESCRIPCION
    )
    SELECT 
        @CNSIFIS, IFISH.IDBODEGA, IFISH.IDARTICULO, IFISH.NOLOTE, IFISH.NOLOTEPEDIDO, 
        ISNULL(IEXI.LUGAR1,''), ISNULL(IEXI.LUGAR2,''), ISNULL(IEXI.LUGAR3,''), ISNULL(IEXI.LUGAR4,''), ISNULL(IEXI.LUGAR5,''),
        0, 0, 0, @ESTADO1, @ESTADO2, @ESTADO3, Y.USUARIO, IART.DESCRIPCION
        FROM IFIS
        CROSS JOIN #Y AS Y 
        INNER JOIN IFISH ON IFISH.CNSIFIS=IFIS.CNSIFIS AND IFISH.IDBODEGA=Y.IDBODEGA 
        LEFT JOIN IEXI  ON IFISH.IDBODEGA=IEXI.IDBODEGA AND IFISH.IDARTICULO=IEXI.IDARTICULO AND IFISH.NOLOTE=IEXI.NOLOTE
        INNER JOIN IART  ON IFISH.IDARTICULO=IART.IDARTICULO
    WHERE IFIS.CNSIFIS=@CNSIFIS AND IFIS.CERRADO=0
        AND NOT EXISTS (
            SELECT 1 FROM IFISHU AS U WHERE U.CNSIFIS=IFIS.CNSIFIS AND U.IDBODEGA=IFIS.IDBODEGA 
                AND U.USUARIO=Y.USUARIO AND U.IDARTICULO=IFISH.IDARTICULO AND U.NOLOTE=IFISH.NOLOTE 
            )

    UPDATE IFISH SET ESTADO1=@ESTADO1, ESTADO2=@ESTADO2, ESTADO3=@ESTADO3
    WHERE CNSIFIS=@CNSIFIS AND IDBODEGA=@IDBODEGA AND (CONTEO1<>@ESTADO1 OR CONTEO2<>@ESTADO2 OR CONTEO3<>@ESTADO3)

END
