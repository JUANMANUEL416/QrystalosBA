/*
  CEM — ajuste acotado de CxP. No toca IMOV, IMOVH ni IEXI.
  DPE11002  quita comprobante inexistente
  DPE11791  IVA del lote una sola vez (309.250,08), prorrateado por cantidad
  FE603306  credito proveedores 22050101
  FE5176    lineas sin IVA a excluidos 14200502
  DPE12286  lineas sin IVA a excluidos 14150502
  DPE11024, DPE11941, DPE12658  fecha = factura de la orden
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;

BEGIN TRAN;

IF EXISTS (
  SELECT 1 FROM dbo.FCXP
  WHERE CNSFCXP IN (
      N'01CM000852', N'03CM002019', N'03CM001933', N'03CM002317',
      N'03CM002248', N'01CM000833', N'03CM002067', N'03CM002343'
    )
    AND (ESTADO <> N'N' OR COALESCE(CONTABILIZADA, 0) <> 0)
)
BEGIN
  ROLLBACK TRAN;
  THROW 56001, 'Alguna cuenta no esta en estado N o ya esta contabilizada.', 1;
END;

/* DPE11002 — comprobante huerfano */
IF NOT EXISTS (
  SELECT 1 FROM dbo.FCXP
  WHERE CNSFCXP = N'01CM000852' AND NOREFERENCIA = N'DPE11002'
    AND RTRIM(COALESCE(NROCOMPROBANTE, N'')) = N'2667000000002875'
)
BEGIN
  ROLLBACK TRAN;
  THROW 56002, 'DPE11002 no tiene el comprobante esperado.', 1;
END;

IF EXISTS (SELECT 1 FROM dbo.MCP WHERE RTRIM(NROCOMPROBANTE) = N'2667000000002875')
   OR EXISTS (SELECT 1 FROM dbo.MCPE WHERE RTRIM(NROCOMPROBANTE) = N'2667000000002875')
BEGIN
  ROLLBACK TRAN;
  THROW 56003, 'El comprobante 2667000000002875 si existe. No se quito.', 1;
END;

/* DPE11791 — tres lineas con el IVA completo cada una */
IF (
  SELECT COUNT(*) FROM dbo.FCXPD
  WHERE CNSFCXP = N'03CM002019'
    AND ABS(VLR_IVA - 309250.08) < 0.01
) <> 3
   OR ABS((SELECT SUM(CANTIDAD) FROM dbo.FCXPD WHERE CNSFCXP = N'03CM002019') - 720) > 0.01
   OR ABS((SELECT VLR_IVA FROM dbo.FCXP WHERE CNSFCXP = N'03CM002019') - 927750.24) > 0.01
   OR ABS((SELECT VLR_NETO FROM dbo.FCXP WHERE CNSFCXP = N'03CM002019') - 2555382.24) > 0.01
   OR ABS((SELECT SALDO FROM dbo.FCXP WHERE CNSFCXP = N'03CM002019') - (SELECT VLR_NETO FROM dbo.FCXP WHERE CNSFCXP = N'03CM002019')) > 0.01
BEGIN
  ROLLBACK TRAN;
  THROW 56004, 'DPE11791 no esta en el estado revisado. No se cambio el IVA.', 1;
END;

/* FE603306 — credito vacio */
IF NOT EXISTS (
  SELECT 1 FROM dbo.FCXP
  WHERE CNSFCXP = N'03CM001933' AND NOREFERENCIA = N'FE603306'
    AND COALESCE(CUECREDITO, N'') = N''
    AND ABS(VLR_NETO - 594780.00) < 0.01
)
BEGIN
  ROLLBACK TRAN;
  THROW 56005, 'FE603306 ya tiene credito o el neto cambio.', 1;
END;

/* FE5176 — dos lineas sin IVA en gravados, una con IVA 632,32 */
IF (
  SELECT COUNT(*) FROM dbo.FCXPD
  WHERE CNSFCXP = N'03CM002317' AND COALESCE(VLR_IVA, 0) = 0 AND CUENTA_SER = N'14200501'
) <> 2
   OR (
  SELECT COUNT(*) FROM dbo.FCXPD
  WHERE CNSFCXP = N'03CM002317' AND ABS(VLR_IVA - 632.32) < 0.01 AND CUENTA_SER = N'14200501' AND CUENTA_IVA = N'24080501'
) <> 1
BEGIN
  ROLLBACK TRAN;
  THROW 56006, 'FE5176 no tiene las tres lineas esperadas.', 1;
END;

/* DPE12286 — 21 sin IVA en gravados, una con IVA 74.403 */
IF (
  SELECT COUNT(*) FROM dbo.FCXPD
  WHERE CNSFCXP = N'03CM002248' AND COALESCE(VLR_IVA, 0) = 0 AND CUENTA_SER = N'14150501'
) <> 21
   OR (
  SELECT COUNT(*) FROM dbo.FCXPD
  WHERE CNSFCXP = N'03CM002248' AND ABS(VLR_IVA - 74403.00) < 0.01 AND CUENTA_SER = N'14150501' AND CUENTA_IVA = N'24080501'
) <> 1
BEGIN
  ROLLBACK TRAN;
  THROW 56007, 'DPE12286 no tiene las 22 lineas esperadas.', 1;
END;

/* Fechas actuales */
IF NOT EXISTS (SELECT 1 FROM dbo.FCXP WHERE CNSFCXP = N'01CM000833' AND CONVERT(date, FECHA) = '20260908' AND CONVERT(date, F_FACTURAREF) = '20260907')
   OR NOT EXISTS (SELECT 1 FROM dbo.FCXP WHERE CNSFCXP = N'03CM002067' AND CONVERT(date, FECHA) = '20260921' AND CONVERT(date, F_FACTURAREF) = '20260917')
   OR NOT EXISTS (SELECT 1 FROM dbo.FCXP WHERE CNSFCXP = N'03CM002343' AND CONVERT(date, FECHA) = '20260925' AND CONVERT(date, F_FACTURAREF) = '20260925')
BEGIN
  ROLLBACK TRAN;
  THROW 56008, 'Alguna fecha ya no es la revisada.', 1;
END;

UPDATE dbo.FCXP
SET NROCOMPROBANTE = N''
WHERE CNSFCXP = N'01CM000852'
  AND RTRIM(COALESCE(NROCOMPROBANTE, N'')) = N'2667000000002875';

UPDATE D
SET VLR_IVA = ROUND(309250.08 * D.CANTIDAD / 720.0, 2),
    VLR_NETO = ROUND(D.CANTIDAD * D.VALOR, 2) + ROUND(309250.08 * D.CANTIDAD / 720.0, 2) - ISNULL(D.VLR_DESCUENTO, 0)
FROM dbo.FCXPD D
WHERE D.CNSFCXP = N'03CM002019';

UPDATE dbo.FCXP
SET VLR_IVA = X.IVA,
    VLR_NETO = X.NETO,
    SALDO = X.NETO
FROM dbo.FCXP P
INNER JOIN (
  SELECT CNSFCXP,
         CONVERT(decimal(18, 2), SUM(VLR_IVA)) AS IVA,
         CONVERT(decimal(18, 2), SUM(VLR_NETO)) AS NETO
  FROM dbo.FCXPD
  WHERE CNSFCXP = N'03CM002019'
  GROUP BY CNSFCXP
) X ON X.CNSFCXP = P.CNSFCXP
WHERE P.CNSFCXP = N'03CM002019';

UPDATE dbo.FCXP
SET CUECREDITO = N'22050101'
WHERE CNSFCXP = N'03CM001933'
  AND COALESCE(CUECREDITO, N'') = N'';

UPDATE dbo.FCXPD
SET CUENTA_SER = N'14200502'
WHERE CNSFCXP = N'03CM002317'
  AND COALESCE(VLR_IVA, 0) = 0
  AND CUENTA_SER = N'14200501';

UPDATE dbo.FCXPD
SET CUENTA_SER = N'14150502'
WHERE CNSFCXP = N'03CM002248'
  AND COALESCE(VLR_IVA, 0) = 0
  AND CUENTA_SER = N'14150501';

UPDATE dbo.FCXP
SET FECHA = CONVERT(datetime, '20260907')
WHERE CNSFCXP = N'01CM000833' AND CONVERT(date, FECHA) = '20260908';

UPDATE dbo.FCXP
SET FECHA = CONVERT(datetime, '20260917')
WHERE CNSFCXP = N'03CM002067' AND CONVERT(date, FECHA) = '20260921';

UPDATE dbo.FCXP
SET FECHA = CONVERT(datetime, '20260923'),
    F_FACTURAREF = CONVERT(datetime, '20260923')
WHERE CNSFCXP = N'03CM002343' AND CONVERT(date, FECHA) = '20260925';

/* Cierre: si algo no quedo, no se graba nada */
IF EXISTS (SELECT 1 FROM dbo.FCXP WHERE CNSFCXP = N'01CM000852' AND RTRIM(COALESCE(NROCOMPROBANTE, N'')) <> N'')
   OR ABS((SELECT SUM(VLR_IVA) FROM dbo.FCXPD WHERE CNSFCXP = N'03CM002019') - 309250.08) > 0.01
   OR ABS((SELECT VLR_NETO FROM dbo.FCXP WHERE CNSFCXP = N'03CM002019') - 1936882.08) > 0.01
   OR ABS((SELECT VLR_IVA FROM dbo.FCXP WHERE CNSFCXP = N'03CM002019') - 309250.08) > 0.01
   OR EXISTS (SELECT 1 FROM dbo.FCXP WHERE CNSFCXP = N'03CM001933' AND COALESCE(CUECREDITO, N'') <> N'22050101')
   OR (SELECT COUNT(*) FROM dbo.FCXPD WHERE CNSFCXP = N'03CM002317' AND COALESCE(VLR_IVA, 0) = 0 AND CUENTA_SER = N'14200502') <> 2
   OR (SELECT COUNT(*) FROM dbo.FCXPD WHERE CNSFCXP = N'03CM002317' AND ABS(VLR_IVA - 632.32) < 0.01 AND CUENTA_SER = N'14200501') <> 1
   OR (SELECT COUNT(*) FROM dbo.FCXPD WHERE CNSFCXP = N'03CM002248' AND COALESCE(VLR_IVA, 0) = 0 AND CUENTA_SER = N'14150502') <> 21
   OR (SELECT COUNT(*) FROM dbo.FCXPD WHERE CNSFCXP = N'03CM002248' AND ABS(VLR_IVA - 74403.00) < 0.01 AND CUENTA_SER = N'14150501') <> 1
   OR NOT EXISTS (SELECT 1 FROM dbo.FCXP WHERE CNSFCXP = N'01CM000833' AND CONVERT(date, FECHA) = '20260907' AND CONVERT(date, F_FACTURAREF) = '20260907')
   OR NOT EXISTS (SELECT 1 FROM dbo.FCXP WHERE CNSFCXP = N'03CM002067' AND CONVERT(date, FECHA) = '20260917' AND CONVERT(date, F_FACTURAREF) = '20260917')
   OR NOT EXISTS (SELECT 1 FROM dbo.FCXP WHERE CNSFCXP = N'03CM002343' AND CONVERT(date, FECHA) = '20260923' AND CONVERT(date, F_FACTURAREF) = '20260923')
BEGIN
  ROLLBACK TRAN;
  THROW 56009, 'La verificacion final no cuadra. No se cambio nada.', 1;
END;

COMMIT TRAN;

SELECT
  P.CNSFCXP,
  P.NOREFERENCIA,
  COALESCE(P.CUECREDITO, N'') AS CUECREDITO,
  COALESCE(P.NROCOMPROBANTE, N'') AS NROCOMPROBANTE,
  CONVERT(varchar(10), P.FECHA, 23) AS FECHA,
  CONVERT(varchar(10), P.F_FACTURAREF, 23) AS F_FACTURAREF,
  CONVERT(decimal(18, 2), P.VLR_IVA) AS IVA,
  CONVERT(decimal(18, 2), P.VLR_NETO) AS NETO,
  CONVERT(decimal(18, 2), P.SALDO) AS SALDO
FROM dbo.FCXP P
WHERE P.CNSFCXP IN (
  N'01CM000852', N'03CM002019', N'03CM001933', N'03CM002317',
  N'03CM002248', N'01CM000833', N'03CM002067', N'03CM002343'
)
ORDER BY P.NOREFERENCIA;
