IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='SPK_CONTAB_FLEG' AND XTYPE='P')
BEGIN
   DROP PROCEDURE SPK_CONTAB_FLEG
END

GO
CREATE PROCEDURE DBO.SPK_CONTAB_FLEG 
@CNSFLEG             VARCHAR(20),
@COMPANIA            VARCHAR(2),
@SEDE                VARCHAR(5),
@USUARIO             VARCHAR(12),
@SYS_COMPUTERNAME    VARCHAR(254),
@NROCOMPROBANTE      VARCHAR(20) 
WITH ENCRYPTION
AS
DECLARE @NOREFERENCIA    VARCHAR(20)
DECLARE @MAUX		        VARCHAR(20)
DECLARE @ANO		        VARCHAR(4)
DECLARE @MES		        INT
DECLARE @REFERENCIA_PRO  VARCHAR(20)
DECLARE @PROCEDENCIA	  VARCHAR(10)
DECLARE @COM             VARCHAR(2)  
DECLARE @PREFIJO_USCXS   VARCHAR(10)
DECLARE @FECHACONTABLE   DATETIME
DECLARE @ESTADO          VARCHAR(1)
DECLARE @VALORPAGO       DECIMAL(14,2)
DECLARE @VLRDTOFIN       DECIMAL(14,2)
DECLARE @VLRAJUSTEPESO   DECIMAL(14,2)
DECLARE @VLRIMPUESTOS    DECIMAL(14,2)
DECLARE @INGRESO         VARCHAR(10)
BEGIN
   SELECT * INTO #T  FROM FLEG WHERE CNSFLEG=@CNSFLEG
   SELECT * INTO #TH FROM FLEGD WHERE CNSFLEG=@CNSFLEG
   
   SET @REFERENCIA_PRO = @CNSFLEG
    
   PRINT '@NROCOMPROBANTE:' + ISNULL(@NROCOMPROBANTE,'') -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD
   IF ISNULL(@NROCOMPROBANTE,'') = '' -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD
   BEGIN
      SELECT 
      @ESTADO         = ESTADO,
      @ANO            = YEAR(FECHA),
      @MES            = MONTH(FECHA),
      @FECHACONTABLE  = FECHA,
      @VALORPAGO      = VALORPAGO,
      @VLRDTOFIN      = VLRDTOFIN,
      @VLRAJUSTEPESO  = VLRAJUSTEPESO,
      @VLRIMPUESTOS   = VLRIMPUESTOS,
      @INGRESO        = INGRESO
      FROM #T
      
      SET @COM = RTRIM(LTRIM(DBO.FNK_VALORVARIABLE('IDCON_TCOM_CXC')))
      
      IF @COM IS NULL OR @COM=''
         SET @COM = RTRIM(LTRIM(DBO.FNK_VALORVARIABLE('IDCON_TCOM_DEFAULT')))
      IF @COM IS NULL OR @COM=''
         SET @COM='IX'
      
      SET @MAUX = SPACE(20) -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD
      EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@MCP',@MAUX OUTPUT -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD
      PRINT '@MAUX:' + ISNULL(@MAUX,'') -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD
      SELECT @MAUX = @SEDE + REPLACE(SPACE(8 - CASE WHEN LEN(@MAUX) > 8 THEN 8 ELSE LEN(@MAUX) END)+LTRIM(RTRIM(@MAUX)),SPACE(1),0) -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD
      PRINT '@MAUX:' + ISNULL(@MAUX,'') -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD
      
      SET @PREFIJO_USCXS='@COM'+@COM
      SET @NOREFERENCIA=SPACE(20)
      EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,@PREFIJO_USCXS,@NOREFERENCIA OUTPUT   
      SELECT @NOREFERENCIA = REPLACE(SPACE(8 - LEN(@NOREFERENCIA))+LTRIM(RTRIM(@NOREFERENCIA)),SPACE(1),0)
      PRINT 'Nuevo Comprobante: '+@COM+' '+@NOREFERENCIA
   
      IF NOT EXISTS(SELECT COMPANIA,ANO,MES FROM PRI WHERE COMPANIA=@COMPANIA AND ANO=@ANO AND MES=@MES)
      BEGIN
         RAISERROR('Periodo Contable NO Existe', 16, 1)
         RETURN
         --PRINT 'Insertando Periodo Contable...'
         --INSERT INTO PRI (COMPANIA,ANO,MES,NOMPERIODO,FECHA_INI,CERRADO,FECHA_FIN,AJUSTADO,PAAG,COMPROBANTE,
         --       DOCUMENTO,NROCOMPROBANTE,TIPO_AJ,CERRADO_INV)
         --SELECT @COMPANIA,@ANO,@MES,LEFT(DATENAME(MONTH,@FECHACONTABLE),3)+' de '+@ANO,CAST('01/'+LTRIM(STR(@MES))+'/'+@ANO AS DATETIME),
         --       1,DBO.FNK_DIA_DEL_MES(@ANO,@MES,'ULTIMO'),1,0,'',
         --       '','','Mensual',1
      
         --PRINT 'Fijando Saldos Inicales...'
         --EXEC SPK_FIJAR_SALDO_INICIAL @COMPANIA, @ANO, @MES
      END
      --COMPROBANRTE CONTABLE (MCP)
      INSERT INTO MCP(NROCOMPROBANTE, COMPANIA, PROCEDENCIA, NOREFERENCIA, ANO, MES, FECHACONTABLE, TOTALDEBITO,
                      TOTALCREDITO, REFERENCIA1, REFERENCIA2, USUARIO, FECHA, LOTE, OBSERVACION, IDSEDE, ESTADO, 
                      COMPROBANTE, IDTERCERO)
      SELECT @MAUX, @COMPANIA, 'LEGALIZACION', @NOREFERENCIA, @ANO, @MES, CAST(STR(DAY(@FECHACONTABLE))+'/'+LTRIM(STR(@MES))+'/'+@ANO AS DATETIME),
             0, 0, @CNSFLEG, '', @USUARIO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), NULL, 'COMPROBANTE DE LEGALIZACION', 
             @SEDE, 0, @COM, (CASE WHEN #T.IDTERCERO IS NULL THEN '' ELSE #T.IDTERCERO END)
      FROM #T
   END
   ELSE
   BEGIN
      SELECT 
      @ESTADO         = ESTADO,
      @VALORPAGO      = VALORPAGO,
      @VLRDTOFIN      = VLRDTOFIN,
      @VLRAJUSTEPESO  = VLRAJUSTEPESO,
      @VLRIMPUESTOS   = VLRIMPUESTOS,
      @INGRESO        = INGRESO
      FROM #T
      
      SELECT @COM=COMPROBANTE FROM MCP WHERE NROCOMPROBANTE=@NROCOMPROBANTE
      SELECT @MAUX = @NROCOMPROBANTE
      
      SELECT @ANO = ANO, @MES = MES, @FECHACONTABLE = FECHACONTABLE FROM MCP WHERE NROCOMPROBANTE = @MAUX
      
      DELETE MCH WHERE NROCOMPROBANTE=@MAUX AND PROCEDENCIA='LEGALIZACION' AND REFERENCIA_PRO=@REFERENCIA_PRO
   END
   
   IF @ESTADO='A' 
   BEGIN 
      DELETE MCH WHERE NROCOMPROBANTE=@MAUX AND PROCEDENCIA='LEGALIZACION' AND REFERENCIA_PRO=@REFERENCIA_PRO 
      
      UPDATE MCP 
      SET ESTADO  = CASE WHEN MCH.NROCOMPROBANTE IS NULL THEN '2' ELSE MCP.ESTADO END,
          ANULADO = CASE WHEN MCH.NROCOMPROBANTE IS NULL THEN 1 ELSE 0 END
      FROM MCP LEFT JOIN MCH ON MCP.NROCOMPROBANTE=MCH.NROCOMPROBANTE 
      WHERE MCP.COMPANIA=@COMPANIA AND MCP.NROCOMPROBANTE=@MAUX
      
      EXEC SPK_SUMA_DBCR @MAUX
      
      UPDATE FLEG SET CONTABILIZADO=1, MARCACONT=0, NROCOMPROBANTE=@MAUX WHERE CNSFLEG=@CNSFLEG
      RETURN
   END
   
   
   PRINT '- Contabilizando el Debito (Descueto a la Cuenta Puente).'
   IF @VALORPAGO <> 0
   BEGIN
      PRINT '  Si hay Pago.'
      IF @INGRESO='BANCOS' OR @INGRESO = 'CXP'
      BEGIN
         PRINT 'Ingreso en Bancos.'
         INSERT INTO MCH(NROCOMPROBANTE,COMPANIA,TIPO,CUENTA,IDTERCERO,CCOSTO,DETALLE,VALOR,
                         REFERENCIA1,REFERENCIA2,REFERENCIA3,ITEMREF,USUARIO,FECHA,PREFIJO,IDAREA,CLASECONT,
                         ESTADO,PROCESO,GENERA,N_FACTURA,F_FACTURAREF, F_VENCE, PROCEDENCIA, REFERENCIA_PRO,
                         CODUNG, CODPRG)
         SELECT @MAUX, @COMPANIA, 'DB', #T.CUENTA_REC, #T.IDTERCERO, '', 
                'DOCUMENTO No. '+CASE WHEN BMOVD.NODOCUMENTO='' OR BMOVD.NODOCUMENTO IS NULL THEN #T.IDTERCERO ELSE BMOVD.NODOCUMENTO END,
                @VALORPAGO, @CNSFLEG, '', '', NULL, @USUARIO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), '', '', 'P', 1,
                'FLEG_DB_PAGO', 'Movimiento',
                CASE WHEN BMOVD.NODOCUMENTO='' OR BMOVD.NODOCUMENTO IS NULL THEN #T.IDTERCERO ELSE BMOVD.NODOCUMENTO END, 
                DBO.FNK_FECHA_SIN_HORA(BMOV.FECHAOPERACION), DBO.FNK_FECHA_SIN_HORA(BMOV.FECHAOPERACION), 
                'LEGALIZACION',  @CNSFLEG, NULL, NULL
         FROM #T LEFT JOIN
              BMOVD ON #T.BANCO=BMOVD.BANCO AND #T.SUCURSAL=BMOVD.SUCURSAL AND #T.CTA_BCO=BMOVD.CTA_BCO AND
                    #T.ITEM=BMOVD.ITEM AND #T.RENGLON=BMOVD.RENGLON LEFT JOIN
              BMOV ON BMOV.BANCO=BMOVD.BANCO AND BMOV.SUCURSAL=BMOVD.SUCURSAL AND BMOV.CTA_BCO=BMOVD.CTA_BCO AND
                    BMOV.ITEM=BMOVD.ITEM
      END 
      ELSE
      BEGIN
         IF @INGRESO='CAJA'
         BEGIN
            PRINT 'Ingreso en Caja.'
         END
      END
   END
   
   PRINT ' - Contabilizando el Debito (Dto. Financiero)'
   IF @VLRDTOFIN<>0
   BEGIN
      INSERT INTO MCH(NROCOMPROBANTE,COMPANIA,TIPO,CUENTA,IDTERCERO,CCOSTO,DETALLE,VALOR,
                  REFERENCIA1,REFERENCIA2,REFERENCIA3,ITEMREF,USUARIO,FECHA,PREFIJO,IDAREA,CLASECONT,
                  ESTADO,PROCESO,GENERA,N_FACTURA,F_FACTURAREF, F_VENCE, PROCEDENCIA, REFERENCIA_PRO,
                  CODUNG, CODPRG)
      SELECT @MAUX, @COMPANIA, 'DB', #T.CUENTA_DTO, #T.IDTERCERO, '', 
         'DESCUENTO FINANCIERO', @VLRDTOFIN, @CNSFLEG, '', '', NULL, @USUARIO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), 
         '', '', 'P', 1, 'FLEG_DB_DTOFIN', 'Movimiento', @CNSFLEG, DBO.FNK_FECHA_SIN_HORA(#T.FECHA), 
         DBO.FNK_FECHA_SIN_HORA(#T.FECHA), 'LEGALIZACION',  @CNSFLEG, NULL, NULL
      FROM #T
   END
   
   PRINT ' - Contabilizando el Debito (Ajuste al Peso)'
   IF @VLRAJUSTEPESO<>0
   BEGIN
      INSERT INTO MCH(NROCOMPROBANTE,COMPANIA,TIPO,CUENTA,IDTERCERO,CCOSTO,DETALLE,VALOR,
                      REFERENCIA1,REFERENCIA2,REFERENCIA3,ITEMREF,USUARIO,FECHA,PREFIJO,IDAREA,CLASECONT,
                      ESTADO,PROCESO,GENERA,N_FACTURA,F_FACTURAREF, F_VENCE, PROCEDENCIA, REFERENCIA_PRO,
                      CODUNG, CODPRG)
      SELECT @MAUX, @COMPANIA, CASE WHEN @VLRAJUSTEPESO < 0 THEN 'CR' ELSE 'DB' END, #T.CUENTA_AJP, #T.IDTERCERO, '', 
             'AJUSTE AL PESO', CASE WHEN @VLRAJUSTEPESO < 0 THEN (@VLRAJUSTEPESO * (-1)) ELSE @VLRAJUSTEPESO END, @CNSFLEG, 
             '', '', NULL, @USUARIO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), 
             '', '', 'P', 1, 'FLEG_DB_AJPESO', 'Movimiento', @CNSFLEG, DBO.FNK_FECHA_SIN_HORA(#T.FECHA), 
             DBO.FNK_FECHA_SIN_HORA(#T.FECHA), 'LEGALIZACION',  @CNSFLEG, NULL, NULL
      FROM #T
   END
   
   PRINT ' - Contabilizando el Debito (CxC).'
   INSERT INTO MCH(NROCOMPROBANTE, COMPANIA, TIPO, CUENTA, IDTERCERO, CCOSTO, DETALLE, VALOR, 
                   REFERENCIA1 ,REFERENCIA2 ,ITEMREF, USUARIO, FECHA, PREFIJO, IDAREA, CLASECONT, 
                   ESTADO, PROCESO, GENERA, PROCEDENCIA, REFERENCIA_PRO,
                   N_FACTURA, F_FACTURAREF, F_VENCE)
   SELECT @MAUX, @COMPANIA, 'CR', #TH.CUENTA_CXC, #T.IDTERCERO, CNT.CCOSTO, 
          LTRIM(RTRIM(TER.RAZONSOCIAL))+',  FACTURA No. '+#TH.N_FACTURA+' - '+LTRIM(RTRIM(CNTCF.DESCCONCEPTO))+', FUENTE: '+LTRIM(RTRIM(FTRD.REFERENCIA)), 
          #TH.VLRTOTAL, @CNSFLEG, #TH.ITEM, NULL, @USUARIO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), 
          FTRD.NOPRESTACION, NULL, 'S', 1, 'FLEG_CR', 'Movimiento', 'LEGALIZACION', @CNSFLEG,
          #TH.N_FACTURA, DBO.FNK_FECHA_SIN_HORA(FTR.F_FACTURA), DBO.FNK_FECHA_SIN_HORA(FTR.F_VENCE)
   FROM #T, #TH LEFT JOIN 
        FTRD ON #TH.CNSFTR=FTRD.CNSFTR AND #TH.N_CUOTA=FTRD.N_CUOTA LEFT JOIN
        FTR ON FTRD.CNSFTR=FTR.CNSFCT LEFT JOIN
        CNTPC ON FTRD.NOADMISION = CNTPC.IDCONTRATO AND FTRD.NOPRESTACION = CNTPC.IDCONCEPTO AND
               FTRD.REFERENCIA = CNTPC.CODIGOINTERNO AND FTRD.TIPOCONTRATOARS = CNTPC.TIPOCONTRATOARS AND 
               FTRD.ARSTIPOCONTRATO = CNTPC.ARSTIPOCONTRATO AND FTRD.ANO=CNTPC.ANO AND FTRD.MES=CNTPC.MES LEFT JOIN
        CNT ON CNTPC.IDCONTRATO=CNT.IDCONTRATO LEFT JOIN 
        TER ON CNT.IDTERCERO = TER.IDTERCERO LEFT JOIN
        CNTCF ON FTRD.TIPOCONTRATOARS=CNTCF.TIPOCONTRATOARS AND FTRD.ARSTIPOCONTRATO=CNTCF.ARSTIPOCONTRATO AND 
               FTRD.NOPRESTACION=CNTCF.IDCONCEPTO
   
   PRINT 'Poniendo Estado de CONTABILIZADA en La Tabla FCESD'
   UPDATE FLEG SET CONTABILIZADO=1, MARCACONT=0, NROCOMPROBANTE=@MAUX WHERE CNSFLEG=@CNSFLEG
   
   EXEC SPK_REVISAR_COMPROBANTE @COMPANIA, @MAUX
   EXEC SPK_SUMA_DBCR @MAUX
   
   DROP TABLE #T
   DROP TABLE #TH
END
