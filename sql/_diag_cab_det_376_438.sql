SET NOCOUNT ON;
DECLARE @T TABLE (CNS varchar(20));
INSERT INTO @T VALUES (N'03CM002376'), (N'03CM002438');

SELECT P.CNSFCXP, P.NOREFERENCIA,
  CONVERT(decimal(18,2), P.VALOR) VALOR,
  CONVERT(decimal(18,2), P.VLR_IVA) IVA_CAB,
  CONVERT(decimal(18,2), P.VLR_NETO) NETO_CAB,
  CONVERT(decimal(18,2), SUM(D.VLR_NETO)) NETO_DET,
  CONVERT(decimal(18,2), SUM(D.VLR_IVA)) IVA_DET,
  CONVERT(decimal(18,2), SUM(D.CANTIDAD * D.VALOR)) SUM_CANT_VALOR,
  COUNT(*) LIN
FROM dbo.FCXP P
JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
JOIN @T T ON T.CNS = P.CNSFCXP
GROUP BY P.CNSFCXP, P.NOREFERENCIA, P.VALOR, P.VLR_IVA, P.VLR_NETO;

SELECT P.CNSFCXP, D.ITEM, D.IDSERVICIO, D.CANTIDAD, D.VALOR,
  CONVERT(decimal(18,2), D.VLR_IVA) IVA_LIN,
  CONVERT(decimal(18,2), D.VLR_NETO) NETO_LIN,
  CONVERT(decimal(18,2), D.CANTIDAD * D.VALOR) CANT_X_VALOR,
  CONVERT(decimal(18,2), D.CANTIDAD * D.VALOR + COALESCE(D.VLR_IVA,0) - ISNULL(D.VLR_DESCUENTO,0)) FORMULA_NETO,
  D.N_PRESUP, D.CUENTA_SER
FROM dbo.FCXP P
JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
JOIN @T T ON T.CNS = P.CNSFCXP
ORDER BY P.CNSFCXP, D.ITEM;

SELECT P.CNSFCXP, M.CNSMOV, M.FECHAMOV, SUM(H.CANTIDAD * H.PCOSTO) COSTO_IMOVH
FROM dbo.FCXP P
JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP AND COALESCE(D.N_PRESUP,N'') <> N''
JOIN dbo.IMOV M ON M.CNSMOV = D.N_PRESUP
JOIN dbo.IMOVH H ON H.CNSMOV = M.CNSMOV
JOIN @T T ON T.CNS = P.CNSFCXP
GROUP BY P.CNSFCXP, M.CNSMOV, M.FECHAMOV;
