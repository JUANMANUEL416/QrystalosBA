CREATE OR ALTER PROCEDURE DBO.SPQ_RETEFTE_SALARIO @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
SET DATEFORMAT dmy
SET NOCOUNT ON
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE  @PARAMETROS NVARCHAR(MAX)			,@MODELO VARCHAR(100)			      ,@METODO VARCHAR(100)
		   ,@USUARIO VARCHAR(12)				   ,@COMPANIA VARCHAR(2)		      ,@IDSEDE      VARCHAR(5)		
         ,@SYS_COMPUTERNAME VARCHAR(200)     ,@DATOS    NVARCHAR(MAX)         ,@ORDEN   SMALLINT 
	      ,@PROCESO VARCHAR(20)				   ,@CODIGO VARCHAR(10)
	      ,@DESCRIPCION VARCHAR(200)		      ,@CLASE VARCHAR(20)
	      ,@ESTADO VARCHAR(20)				      ,@CNSNUEVO INT
	      ,@IDVARIABLE VARCHAR(50)			   ,@VALOR VARCHAR(50)
	      ,@ANIO INT

BEGIN
	SELECT *
	INTO #JSON
	FROM OPENJSON(@json) WITH (
			MODELO VARCHAR(100) '$.MODELO'
			,METODO VARCHAR(100) '$.METODO'
			,USUARIO VARCHAR(12) '$.USUARIO'
			,PARAMETROS NVARCHAR(MAX) AS JSON
	)

	SELECT   @MODELO = MODELO			,@METODO = METODO
			,@PARAMETROS = PARAMETROS	,@USUARIO = USUARIO
	FROM #JSON

	-- =====================================================================
	-- METODO: CRUD_RETEI - CRUD para tabla RETEI (Tipos de Retenci�n)
	-- Campos: CODIGO (R001, R002...), DESCRIPCION, CLASE (suma|resta), ESTADO
	-- =====================================================================
	IF @METODO = 'CRUD_RETEI'
	BEGIN
		SELECT @DATOS = DATOS
		FROM OPENJSON(@PARAMETROS) WITH (DATOS NVARCHAR(MAX) AS JSON)

		SELECT @PROCESO = UPPER(JSON_VALUE(@DATOS, '$.PROCESO'))
		SELECT @CODIGO = NULLIF(LTRIM(RTRIM(JSON_VALUE(@DATOS, '$.CODIGO'))), '')
		SELECT @DESCRIPCION = NULLIF(LTRIM(RTRIM(JSON_VALUE(@DATOS, '$.DESCRIPCION'))), '')
		SELECT @CLASE = NULLIF(LTRIM(RTRIM(JSON_VALUE(@DATOS, '$.CLASE'))), '')
		SELECT @ESTADO = NULLIF(LTRIM(RTRIM(JSON_VALUE(@DATOS, '$.ESTADO'))), 'Activo')
		SELECT @ORDEN = NULLIF(LTRIM(RTRIM(JSON_VALUE(@DATOS, '$.ORDEN'))),0)

		-- Validaciones
		IF @PROCESO IN ('INSERTAR', 'NUEVO') AND (@DESCRIPCION IS NULL OR LEN(@DESCRIPCION) = 0)
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'La descripci�n es requerida'
		END
		IF @PROCESO IN ('INSERTAR', 'NUEVO') AND (@CLASE IS NULL OR LEN(@CLASE) = 0)
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'La clase (suma/resta) es requerida'
		END
		IF @PROCESO IN ('EDITAR', 'BORRAR', 'ACTUALIZAR', 'ELIMINAR')
			AND (@CODIGO IS NULL OR LEN(@CODIGO) = 0)
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El c�digo es requerido para editar o inactivar'
		END
		IF @CLASE IS NOT NULL AND @CLASE NOT IN ('suma', 'resta')
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'La clase debe ser suma o resta'
		END
		IF @ESTADO IS NOT NULL AND @ESTADO NOT IN ('Activo', 'Inactivo')
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El estado debe ser Activo o Inactivo'
		END

		IF EXISTS(SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		-- INSERTAR
		IF @PROCESO IN ('INSERTAR', 'NUEVO')
		BEGIN
			-- Generar CODIGO: R + 3 d�gitos con ceros a la izquierda (R001, R002, ...)
			SELECT @CNSNUEVO = ISNULL(MAX(
				CASE 
					WHEN CODIGO LIKE 'R[0-9][0-9][0-9]' THEN CAST(SUBSTRING(CODIGO, 2, 3) AS INT)
					ELSE 0
				END
			), 0) + 1
			FROM RETEI

			SELECT @CODIGO = 'R' + RIGHT('000' + CAST(@CNSNUEVO AS VARCHAR(3)), 3)

			IF EXISTS(SELECT 1 FROM RETEI WHERE CODIGO = @CODIGO)
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) SELECT 'Error al generar c�digo. Intente de nuevo.'
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END

			BEGIN TRY
				INSERT INTO RETEI (CODIGO, DESCRIPCION, CLASE, ESTADO,ORDEN)
				VALUES (@CODIGO, @DESCRIPCION, @CLASE, ISNULL(@ESTADO, 'Activo'),@ORDEN)
			END TRY
			BEGIN CATCH
				SELECT 'KO' OK
				SELECT ERROR = 'Error al insertar: ' + ERROR_MESSAGE()
				RETURN
			END CATCH

			SELECT 'OK' OK, @CODIGO AS CODIGO
			RETURN
		END

		-- EDITAR
		IF @PROCESO IN ('EDITAR', 'ACTUALIZAR')
		BEGIN
			IF NOT EXISTS(SELECT 1 FROM RETEI WHERE CODIGO = @CODIGO)
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR = 'El registro a editar no existe'
				RETURN
			END

			IF @DESCRIPCION IS NULL OR LEN(@DESCRIPCION) = 0
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) SELECT 'La descripci�n es requerida'
			END
			IF @CLASE IS NULL OR LEN(@CLASE) = 0
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) SELECT 'La clase es requerida'
			END
			IF EXISTS(SELECT 1 FROM @TBLERRORES)
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END

			BEGIN TRY
				UPDATE RETEI
				SET DESCRIPCION = @DESCRIPCION,
					CLASE = @CLASE,
					ESTADO = ISNULL(@ESTADO, ESTADO),
               ORDEN =@ORDEN
				WHERE CODIGO = @CODIGO
			END TRY
			BEGIN CATCH
				SELECT 'KO' OK
				SELECT ERROR = 'Error al actualizar: ' + ERROR_MESSAGE()
				RETURN
			END CATCH

			SELECT 'OK' OK
			RETURN
		END

		-- BORRAR / INACTIVAR
		IF @PROCESO IN ('BORRAR', 'ELIMINAR')
		BEGIN
			IF NOT EXISTS(SELECT 1 FROM RETEI WHERE CODIGO = @CODIGO)
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR = 'El registro a inactivar no existe'
				RETURN
			END

			BEGIN TRY
				UPDATE RETEI
				SET ESTADO = 'Inactivo'
				WHERE CODIGO = @CODIGO
			END TRY
			BEGIN CATCH
				SELECT 'KO' OK
				SELECT ERROR = 'Error al inactivar: ' + ERROR_MESSAGE()
				RETURN
			END CATCH

			SELECT 'OK' OK
			RETURN
		END

		SELECT 'KO' OK
		SELECT ERROR = 'Proceso no reconocido: ' + ISNULL(@PROCESO, '')
		RETURN
	END

	-- =====================================================================
	-- METODO: ACTUALIZAR_UVT - Actualiza variable VALOR_UVT_RETEFTE
	-- Par�metros: IDVARIABLE, VALOR, ANIO (opcional)
	-- =====================================================================
	IF @METODO = 'ACTUALIZAR_UVT'
	BEGIN
		SELECT @IDVARIABLE = LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.IDVARIABLE')))
		SELECT @VALOR = LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.VALOR')))
		SELECT @ANIO = TRY_CAST(JSON_VALUE(@PARAMETROS, '$.ANIO') AS INT)

		IF @IDVARIABLE IS NULL OR LEN(@IDVARIABLE) = 0
			SELECT @IDVARIABLE = 'VALOR_UVT_RETEFTE'

		IF @VALOR IS NULL OR LEN(@VALOR) = 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR = 'El valor UVT es requerido'
			RETURN
		END

		IF EXISTS(SELECT 1 FROM USVGS WHERE IDVARIABLE = @IDVARIABLE)
		BEGIN
			BEGIN TRY
				UPDATE USVGS
				SET DATO = @VALOR
				WHERE IDVARIABLE = @IDVARIABLE
			END TRY
			BEGIN CATCH
				SELECT 'KO' OK
				SELECT ERROR = 'Error al actualizar UVT: ' + ERROR_MESSAGE()
				RETURN
			END CATCH
		END
		ELSE
		BEGIN
			BEGIN TRY
				INSERT INTO USVGS (IDVARIABLE, DATO, OBSERVACION)
				VALUES (@IDVARIABLE, @VALOR, 'UVT a�o ' + ISNULL(CAST(@ANIO AS VARCHAR), CAST(YEAR(GETDATE()) AS VARCHAR)))
			END TRY
			BEGIN CATCH
				SELECT 'KO' OK
				SELECT ERROR = 'Error al insertar UVT: ' + ERROR_MESSAGE()
				RETURN
			END CATCH
		END

		SELECT 'OK' OK
		RETURN
	END

	-- =====================================================================
	-- METODO: CRUD_RETTER - CRUD para tabla RETTER (Retenciones por Tercero/Asalariado)
	-- Campos: IDTERCERO, CODRETI (FK?RETEI.CODIGO), ESNOMINA, DESCRIPCION, CLASE, VALOR, ESTADO
	-- =====================================================================
	IF @METODO = 'CRUD_RETTER'
	BEGIN
		DECLARE @IDTERCERO   VARCHAR(20)
			   ,@CODRETI     VARCHAR(10)
			   ,@ESNOMINA    BIT
			  -- ,@VALOR       DECIMAL(18,4)

		SELECT @PROCESO     = UPPER(JSON_VALUE(@PARAMETROS, '$.DATOS.PROCESO'))
		SELECT @IDTERCERO   = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.DATOS.IDTERCERO'))), '')
		SELECT @CODRETI     = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.DATOS.CODRETI'))), '')
		SELECT @ESNOMINA    = CAST(ISNULL(JSON_VALUE(@PARAMETROS, '$.DATOS.ESNOMINA'), 0) AS BIT)
		SELECT @DESCRIPCION = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.DATOS.DESCRIPCION'))), '')
		SELECT @CLASE       = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.DATOS.CLASE'))), '')
		SELECT @VALOR       = TRY_CAST(JSON_VALUE(@PARAMETROS, '$.DATOS.VALOR') AS DECIMAL(18,4))
		SELECT @ESTADO      = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.DATOS.ESTADO'))), '')

		-- Validaciones
		IF @IDTERCERO IS NULL OR LEN(@IDTERCERO) = 0
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'IDTERCERO es requerido'
		END
		IF @CODRETI IS NULL OR LEN(@CODRETI) = 0
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'CODRETI (tipo de retenci�n) es requerido'
		END

		IF EXISTS(SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		-- INSERTAR
		IF @PROCESO IN ('INSERTAR', 'NUEVO')
		BEGIN
			IF EXISTS(SELECT 1 FROM RETTER WHERE IDTERCERO = @IDTERCERO AND CODRETI = @CODRETI)
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) SELECT 'Ya existe una retenci�n con ese c�digo para este tercero'
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			IF NOT EXISTS(SELECT 1 FROM RETEI WHERE CODIGO = @CODRETI AND ESTADO = 'Activo')
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) SELECT 'El tipo de retenci�n (CODRETI) no existe o est� inactivo en RETEI'
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END

			BEGIN TRY
				INSERT INTO RETTER (IDTERCERO, CODRETI, ESNOMINA, DESCRIPCION, CLASE, VALOR, ESTADO)
				VALUES (
					@IDTERCERO,
					@CODRETI,
					ISNULL(@ESNOMINA, 0),
					ISNULL(@DESCRIPCION, (SELECT DESCRIPCION FROM RETEI WHERE CODIGO = @CODRETI)),
					ISNULL(@CLASE, (SELECT CLASE FROM RETEI WHERE CODIGO = @CODRETI)),
					@VALOR,
					ISNULL(@ESTADO, 'Activo')
				)
			END TRY
			BEGIN CATCH
				SELECT 'KO' OK
				SELECT ERROR = 'Error al insertar: ' + ERROR_MESSAGE()
				RETURN
			END CATCH

			SELECT 'OK' OK
			RETURN
		END

		-- EDITAR
		IF @PROCESO IN ('Editar', 'ACTUALIZAR')
		BEGIN
         PRINT 'INGRESO A EDITAR'
			BEGIN TRY
				UPDATE RETTER
				SET ESNOMINA    = ISNULL(@ESNOMINA, ESNOMINA),
					DESCRIPCION = ISNULL(@DESCRIPCION, DESCRIPCION),
					CLASE       = ISNULL(@CLASE, CLASE),
					VALOR       = @VALOR,
					ESTADO      = ISNULL(@ESTADO, ESTADO)
				WHERE IDTERCERO = @IDTERCERO 
            AND CODRETI = @CODRETI
			END TRY
			BEGIN CATCH
				SELECT 'KO' OK
				SELECT ERROR = 'Error al actualizar: ' + ERROR_MESSAGE()+' ---'+@IDTERCERO+'--'+@CODRETI
				RETURN
			END CATCH

			--IF @@ROWCOUNT = 0
			--BEGIN
			--	SELECT 'KO' OK
			--	SELECT ERROR = 'No se encontr� el registro para actualizar '+' --'+@IDTERCERO+'--'+@CODRETI
			--	RETURN
			--END

			SELECT 'OK' OK
			RETURN
		END

		-- BORRAR / INACTIVAR
		IF @PROCESO IN ('BORRAR', 'ELIMINAR')
		BEGIN
			BEGIN TRY
				UPDATE RETTER
				SET ESTADO = 'Inactivo'
				WHERE IDTERCERO = @IDTERCERO AND CODRETI = @CODRETI
			END TRY
			BEGIN CATCH
				SELECT 'KO' OK
				SELECT ERROR = 'Error al inactivar: ' + ERROR_MESSAGE()
				RETURN
			END CATCH

			IF @@ROWCOUNT = 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR = 'No se encontr� el registro para inactivar'
				RETURN
			END

			SELECT 'OK' OK
			RETURN
		END

		SELECT 'KO' OK
		SELECT ERROR = 'Proceso no reconocido: ' + ISNULL(@PROCESO, '')
		RETURN
	END
   IF @METODO='LIQUIDAR_RTFTASALA'     
   BEGIN    
      PRINT  'SI INGRESE A ...'
      DECLARE @CNSFCXP VARCHAR(20)
      DECLARE @VLR_CXP DECIMAL(14,2)
      SELECT @CNSFCXP=CNSFCXP        
      FROM   OPENJSON (@PARAMETROS)
      WITH (           
      CNSFCXP  VARCHAR(20)   '$.CNSFCXP'
      )
      SELECT @IDTERCERO=IDTERCERO FROM FCXP WHERE CNSFCXP=@CNSFCXP
      BEGIN TRY           
          EXEC SPK_CALCULA_REFTE_NOMI @CNSFCXP,@IDTERCERO,'CXP'             
      END TRY
      BEGIN CATCH
              INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
      END CATCH
      IF(SELECT COUNT(*) FROM @TBLERRORES)>0
      BEGIN
         SELECT 'KO' OK, ERROR FROM @TBLERRORES
          RETURN
      END
      SELECT 'OK' OK, BASERET,VLR_REFTE,UVTLIQ, CNSLIQRET  FROM RETEL WHERE NOREFERENCIA=@CNSFCXP AND IDTERCERO=@IDTERCERO AND PROCEDENCIA='CXP'
      RETURN 
   END  

	-- M�todo no reconocido
	SELECT 'KO' OK
	SELECT ERROR = 'M�todo no implementado: ' + ISNULL(@METODO, '')
END
