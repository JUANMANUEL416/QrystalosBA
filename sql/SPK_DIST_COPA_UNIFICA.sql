CREATE OR ALTER PROC SPK_DIST_COPA_UNIFICA 
@N_FACTURA VARCHAR(20)
AS
DECLARE @VR_TOTAL DECIMAL(14,2)
DECLARE @PORC DECIMAL(7,4)
DECLARE @COPOAGO DECIMAL(14,2)
DECLARE @COPANEVO DECIMAL(14,2)
DECLARE @IDAFILIADO VARCHAR(20)
DECLARE @N_CUOTA INT
BEGIN
   IF EXISTS(SELECT * FROM FTRD WHERE N_FACTURA=@N_FACTURA AND VR_TOTAL<0)
   BEGIN
      PRINT  'BUSCO EL ORIGEN'

      DECLARE FTRDCIT_CURSOR CURSOR FOR 
      SELECT DISTINCT  CIT.IDAFILIADO  FROM FTRD INNER JOIN CIT ON FTRD.NOADMISION=CIT.CONSECUTIVO
      WHERE FTRD.N_FACTURA=@N_FACTURA
      AND FTRD.VR_TOTAL<0
      OPEN FTRDCIT_CURSOR    
      FETCH NEXT FROM FTRDCIT_CURSOR    
      INTO @IDAFILIADO
      WHILE @@FETCH_STATUS = 0    
      BEGIN 
         PRINT '@IDAFILIADO='+@IDAFILIADO
         SELECT @VR_TOTAL=SUM((CANTIDAD*VALOR)),@COPOAGO=SUM(VLR_COPAGOS) 
         FROM FTRD INNER JOIN CIT ON FTRD.NOADMISION=CIT.CONSECUTIVO
         WHERE FTRD.N_FACTURA=@N_FACTURA
         AND CIT.IDAFILIADO=@IDAFILIADO

         SELECT @PORC=((@COPOAGO*100)/@VR_TOTAL)

         DECLARE FTRX_CURSOR CURSOR FOR 
         SELECT N_CUOTA FROM FTRD INNER JOIN CIT ON FTRD.NOADMISION=CIT.CONSECUTIVO
         WHERE FTRD.N_FACTURA=@N_FACTURA
         AND CIT.IDAFILIADO=@IDAFILIADO
         GROUP BY N_CUOTA
         OPEN FTRX_CURSOR    
         FETCH NEXT FROM FTRX_CURSOR    
         INTO @N_CUOTA
         WHILE @@FETCH_STATUS = 0    
         BEGIN 
            PRINT '@N_CUOTA='+STR(@N_CUOTA)
            UPDATE FTRD SET VLR_COPAGOS=((VALOR*CANTIDAD)*(@PORC/100)) WHERE N_FACTURA=@N_FACTURA AND N_CUOTA=@N_CUOTA
            UPDATE FTRD SET VR_TOTAL=(VALOR*CANTIDAD)-VLR_COPAGOS WHERE N_FACTURA=@N_FACTURA AND N_CUOTA=@N_CUOTA
            FETCH NEXT FROM FTRX_CURSOR    
            INTO @N_CUOTA
         END
         CLOSE FTRX_CURSOR
         DEALLOCATE FTRX_CURSOR

         SELECT @COPANEVO=SUM(VLR_COPAGOS)  FROM FTRD INNER JOIN CIT ON FTRD.NOADMISION=CIT.CONSECUTIVO
         WHERE FTRD.N_FACTURA=@N_FACTURA
         AND CIT.IDAFILIADO=@IDAFILIADO

            IF ABS(@COPOAGO-@COPANEVO)>0
            BEGIN
               UPDATE FTRD SET VLR_COPAGOS=VLR_COPAGOS-(@COPOAGO-@COPANEVO) WHERE N_FACTURA=@N_FACTURA AND N_CUOTA=@N_CUOTA
               UPDATE FTRD SET VR_TOTAL=(VALOR*CANTIDAD)-VLR_COPAGOS WHERE N_FACTURA=@N_FACTURA AND N_CUOTA=@N_CUOTA
            END

         FETCH NEXT FROM FTRDCIT_CURSOR    
         INTO @IDAFILIADO
      END
      CLOSE FTRDCIT_CURSOR
      DEALLOCATE FTRDCIT_CURSOR


   END
   
END
