CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_VACACIONES @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(12), @COMPANIA VARCHAR(2), @IDSEDE VARCHAR(5), @SYS_COMPUTERNAME 
	VARCHAR(200), @DATOS VARCHAR(MAX), @EXISTE INT, @NUMDOC VARCHAR(20), @CODCARGO VARCHAR(20), @NIVEL VARCHAR(10), @GRADO VARCHAR(10), @FECHAING DATETIME, @FFINAL 
	DATETIME, @FINICIAL DATETIME, @NPERIODOS SMALLINT, @ANOS SMALLINT, @MAX SMALLINT, @FECHARET DATETIME, @FECHACORTE DATETIME, @F_ACTUALIZA DATETIME, @ITEMV INT, 
	@DIASG DECIMAL(7, 4), @DIASP DECIMAL(7, 4), @DIASC DECIMAL(7, 2), @CNSPAGO VARCHAR(20), @PROCESO VARCHAR(10), @NUMDOCR VARCHAR(20) = NULL, @ITEM INT, @AJDIAS SMALLINT
	, @FECHAINI DATETIME, @OBSERVACIONES VARCHAR(255), @VACA VARCHAR(20), @CNSNEMPVD VARCHAR(20), @DIASCAL INT, @NDIAS SMALLINT, @SABADO SMALLINT, @DOMINGO SMALLINT, 
	@FESTIVO SMALLINT, @JSONPARAM NVARCHAR(MAX)
DECLARE @CONT INT, @DADISFRUTAR INT, @FECHA DATETIME, @DIASEMANA SMALLINT, @DIASFINMES SMALLINT, @ULTIMO SMALLINT
DECLARE @NOVEDAD VARCHAR(10), @NOVEDAD1 VARCHAR(10), @FECHASAL DATETIME, @F_REGRESO DATETIME, @CNSPAGON VARCHAR(20), @DIAS SMALLINT, @DIAS1 SMALLINT, @FINI DATETIME, 
	@FFIN DATETIME, @HORASLABOR DECIMAL(14, 2), @DIASCARGO SMALLINT, @OBS VARCHAR(512), @CODNOMINA VARCHAR(10), @ANO VARCHAR(4), @MESP SMALLINT, @IDEVEN VARCHAR(10), 
	@IDEVANTE VARCHAR(10), @DAJUS SMALLINT, @CODPPAG VARCHAR(5), @ESTADO VARCHAR(10), @PROCE VARCHAR(10), @VAC_ULTIMOS_4PER VARCHAR(20)

BEGIN
	SET LANGUAGE Spanish;
	SET DATEFORMAT dmy;

	SELECT @VAC_ULTIMOS_4PER = UPPER(LTRIM(RTRIM(COALESCE(DBO.FNK_VALORVARIABLE('VAC_ULTIMOS_4PER'), ''))))

	SELECT *
	INTO #JSON
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	SELECT @MODELO = MODELO, @METODO = METODO, @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON

	IF @METODO = 'ACTUALIZA_VACACIONES'
	BEGIN
		SELECT @CNSPAGO = CNSPAGO, @PROCESO = PROCESO
		FROM OPENJSON(@PARAMETROS) WITH (CNSPAGO VARCHAR(20) '$.CNSPAGO', PROCESO VARCHAR(10) '$.PROCESO')

		BEGIN TRY
			EXEC SPK_PROCESO_VACACIONES '', @PROCESO
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'AJUSTE_DIASVACA'
	BEGIN
		SELECT @NUMDOC = NUMDOC, @ITEM = ITEM, @AJDIAS = AJDIAS, @FECHAINI = FECHAINI, @OBSERVACIONES = OBSERVACIONES
		FROM OPENJSON(@PARAMETROS) WITH (
				NUMDOC VARCHAR(20) '$.NUMDOC', ITEM INT '$.ITEM', AJDIAS SMALLINT '$.AJDIAS', FECHAINI DATETIME '$.FECHAINI', OBSERVACIONES VARCHAR(255) 
				'$.OBSERVACIONES'
				)

		SELECT @IDSEDE = COALESCE(UBEQ.IDSEDE, USUSU.IDSEDE), @COMPANIA = COALESCE(UBEQ.COMPANIA, USUSU.COMPANIA), @SYS_COMPUTERNAME = COALESCE(USUSU.
				SYS_ComputerName, HOST_NAME())
		FROM USUSU
		LEFT JOIN UBEQ ON USUSU.SYS_ComputerName = UBEQ.SYS_ComputerName
		WHERE USUSU.USUARIO = @USUARIO

		SET @CNSNEMPVD = SPACE(20)

		EXEC SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE, '@NEMPVD', @CNSNEMPVD OUTPUT

		SELECT @CNSNEMPVD = @IDSEDE + REPLACE(SPACE(8 - LEN(@CNSNEMPVD)) + LTRIM(RTRIM(@CNSNEMPVD)), SPACE(1), 0)

		SELECT @DIASCAL = DIASPAGO
		FROM DBO.FNK_DIAS_VACACIONES_CALENDARIO(@FECHAINI, @AJDIAS, 1, 0, 0)

		SELECT TOP 1 @VACA = COALESCE(IDEVENTO, dbo.FNK_VALORVARIABLE('NOMICODCON_VACA'))
		FROM NEVE
		WHERE CODCONCEPTO = dbo.FNK_VALORVARIABLE('NOMICODCON_VACA')

		BEGIN TRY
			INSERT INTO NEMPVD (CNSNEMPVD, NUMDOC, ITEM, EVENTO, NDIAS, OBSERVACIONES, CNSPAGO, USUARIO, SYS_COMPUTERNAME, ESTADO, FECHAINI, SABADO, DOMINGO, FESTIVO, DIASCAL, PROCE
				)
			SELECT @CNSNEMPVD, @NUMDOC, @ITEM, @VACA, @AJDIAS, @OBSERVACIONES, 'AjusteVaca', @USUARIO, @SYS_COMPUTERNAME, 'EnNomina', @FECHAINI, 1, 0, 0, @DIASCAL, 
				'Ajuste'
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		UPDATE NEMPV
		SET DIASP = DIASP + @AJDIAS
		WHERE NUMDOC = @NUMDOC AND ITEM = @ITEM

		SELECT 'OK' OK
	END

	IF @METODO = 'DIAS_VACACIONES_CALEN'
	BEGIN
		SELECT @FECHAINI = FECHAINI, @NDIAS = NDIAS, @SABADO = SABADO, @DOMINGO = DOMINGO, @FESTIVO = FESTIVO
		FROM OPENJSON(@PARAMETROS) WITH (FECHAINI DATETIME '$.FECHASALIDA', NDIAS SMALLINT '$.NDIAS', SABADO SMALLINT '$.SABADO', DOMINGO SMALLINT '$.DOMINGO', FESTIVO SMALLINT '$.FESTIVO'
				)

		SELECT 'OK' OK

		SELECT F_REGRESO, DIASPAGO
		FROM DBO.FNK_DIAS_VACACIONES_CALENDARIO(@FECHAINI, @NDIAS, @SABADO, @DOMINGO, @FESTIVO)

		RETURN
	END

	IF @METODO = 'GENERA_NOVEDAD_VACACIONES'
	BEGIN
		SELECT @CNSNEMPVD = CNSNEMPVD
		FROM OPENJSON(@PARAMETROS) WITH (CNSNEMPVD VARCHAR(20) '$.CNSNEMPVD')

		BEGIN TRY
			-- PRINT 'CAPTURO LOS DATOS'
			SELECT @NUMDOC = NUMDOC, @CNSPAGO = CNSPAGO, @DIASP = NDIAS, @ITEM = ITEM, @NOVEDAD = EVENTO, @FECHASAL = FECHAINI, @F_REGRESO = DATEADD(DAY, DIASCAL, FECHAINI), 
				@DIAS = DIASCAL, @OBS = OBSERVACIONES
			FROM NEMPVD
			WHERE CNSNEMPVD = @CNSNEMPVD AND ESTADO = 'Nuevo'

			SELECT @FINI = FECHAINI, @FFIN = FECHAFIN, @DIAS1 = CASE 
					WHEN @F_REGRESO > FECHAFIN
						THEN (
								DATEDIFF(DAY, FECHAFIN, @F_REGRESO) - CASE 
									WHEN DAY(@F_REGRESO) = 1
										THEN 0
									ELSE 1
									END
								)
					ELSE 0
					END, @ANO = ANO, @MESP = MES, @CODNOMINA = CODNOMINA, @DAJUS = CASE 
					WHEN DAY(FECHAFIN) - 30 > 0
						THEN 1
					ELSE 0
					END, @CODPPAG = CODPPAG
			FROM NPER
			WHERE CNSPAGO = @CNSPAGO

			IF COALESCE(@DIAS1, 0) > 0
			BEGIN
				SELECT @DIAS = @DIAS - @DIAS1 - @DAJUS + CASE 
						WHEN DAY(@F_REGRESO) = 1
							THEN 1
						ELSE 0
						END
			END

			SELECT @HORASLABOR = HORASDELABOR, @DIASCARGO = DIASXCARGO
			FROM NEMP
			WHERE NUMDOC = @NUMDOC

			--PRINT '@HORASLABOR=' + STR(@HORASLABOR)
			--PRINT '@DIASCARGO=' + STR(@DIASCARGO)
			--PRINT 'PRIMER INSERT'
			--
			IF (
					SELECT CERRADO
					FROM NPER
					WHERE CNSPAGO = @CNSPAGO
					) = 1
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT CONCAT ('EL PERIODO ', @CNSPAGO, ' SE ENCUENTRRA CERRADO, NO ES POSIBLE AGREAGAR LA NOVEDAD')
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				INSERT INTO NEDIA (CNSPAGO, NUMDOC, FECHAINI, FECHAFIN, DIAS, HORAS, MINUTOS, IDEVENTO, FACTOR, PAGO, OBSERVACION, CNSVAC, ITEM_VAC, FORMALIQUIDACION
					)
				SELECT @CNSPAGO, @NUMDOC, @FECHASAL, CASE 
						WHEN @DIAS1 > 0
							THEN @FFIN
						ELSE @F_REGRESO
						END, @DIAS, CAST((@DIAS * (@HORASLABOR / 30)) AS DECIMAL(7, 2)), DBO.
					FNK_NOVEDAD_MINUTOS(@DIAS, @HORASLABOR), @NOVEDAD, 1, NULL, @OBS, @CNSNEMPVD, 1, 'PorFecha'

				-- revisado para vacaciones aplicadad en el mismo mes.
				--
				IF COALESCE(@DIAS1, 0) > 0
				BEGIN
					--PRINT 'INSERTO LA NOVEDA DEL MES SIGUENTE'
					IF COALESCE(DBO.FNK_VALORVARIABLE('VACA_MESSIGUE_COBRO'), 'ACTUAL') = 'ACTUAL'
					BEGIN
						SELECT @IDEVEN = DBO.FNK_VALORVARIABLE('IDNOVEDADVACSIGMES')

						INSERT INTO NEDIA (CNSPAGO, NUMDOC, FECHAINI, FECHAFIN, DIAS, HORAS, MINUTOS, IDEVENTO, FACTOR, PAGO, OBSERVACION, CNSVAC, ITEM_VAC, FORMALIQUIDACION
							)
						SELECT @CNSPAGO, @NUMDOC, @FINI, DATEADD(DAY, @DIAS1, @FINI), @DIAS1 + @DAJUS - CASE 
								WHEN DAY(@F_REGRESO) = 1
									THEN 1
								ELSE 0
								END, CAST((
									(
										@DIAS1 + @DAJUS - CASE 
											WHEN DAY(@F_REGRESO) = 1
												THEN 1
											ELSE 0
											END
										) * (@HORASLABOR / 30.00)
									) AS DECIMAL(7, 2)), DBO.FNK_NOVEDAD_MINUTOS((
									@DIAS1 + @DAJUS - CASE 
										WHEN DAY(@F_REGRESO) = 1
											THEN 1
										ELSE 0
										END
									), @HORASLABOR), @IDEVEN, 1, NULL, @OBS, @CNSNEMPVD, 1, 'PorFecha'
					END

					IF EXISTS (
							SELECT *
							FROM NPER
							WHERE CODNOMINA = @CODNOMINA AND MES = CASE 
									WHEN @MESP = 12
										THEN 1
									ELSE @MESP + 1
									END AND ANO = CASE 
									WHEN @MESP = 12
										THEN @ANO + 1
									ELSE @ANO
									END
							)
					BEGIN
						SELECT @CNSPAGON = CNSPAGO
						FROM NPER
						WHERE CODNOMINA = @CODNOMINA AND MES = CASE 
								WHEN @MESP = 12
									THEN 1
								ELSE @MESP + 1
								END AND ANO = CASE 
								WHEN @MESP = 12
									THEN @ANO + 1
								ELSE @ANO
								END
					END
					ELSE
					BEGIN
						-- PRINT 'NO EXISTE VOY A CREAR EL PERIDO'
						SELECT @CNSPAGON = @CODNOMINA + CAST(CASE 
									WHEN @MESP = 12
										THEN @ANO + 1
									ELSE @ANO
									END AS VARCHAR(4)) + CASE 
								WHEN @MESP = 12
									THEN '01'
								ELSE CASE 
										WHEN @MESP + 1 < 10
											THEN '0' + CAST(@MESP + 1 AS VARCHAR(2))
										ELSE CAST(@MESP + 1 AS VARCHAR(2))
										END
								END + SUBSTRING(@CNSPAGO, 9, 5)

						INSERT INTO NPER (
							CNSPAGO, CODNOMINA, ANO, MES, CODPPAG, TIPOLIQ, GENERADO, CERRADO, FECHAINI, FECHAFIN, TOTAL_INGRESOS, TOTAL_EGRESOS, TOTAL_APORTES, 
							TOTAL_PARAFISCALES, TOTAL_NOMINA, NROCOMPROBANTE, CONTABILIZADA, COMPROBANTE, NOREFERENCIA, CNSPPTO, CNSCDP
							)
						SELECT @CNSPAGON, @CODNOMINA, CASE 
								WHEN @MESP = 12
									THEN @ANO + 1
								ELSE @ANO
								END, CASE 
								WHEN @MESP = 12
									THEN 1
								ELSE @MESP + 1
								END, @CODPPAG, 'PorNomina', 0, 0, DBO.FNK_DIA_DEL_MES(CASE 
									WHEN @MESP = 12
										THEN @ANO + 1
									ELSE @ANO
									END, CASE 
									WHEN @MESP = 12
										THEN 1
									ELSE @MESP
									END, 'PRIMERO'), DBO.FNK_DIA_DEL_MES(CASE 
									WHEN @MESP = 12
										THEN @ANO + 1
									ELSE @ANO
									END, CASE 
									WHEN @MESP = 12
										THEN 1
									ELSE @MESP + 1
									END, 'ULTIMO'), 0, 0, 0, 0, 0, '', 0, NULL, NULL, NULL, NULL
					END

					IF COALESCE(DBO.FNK_VALORVARIABLE('VACA_MESSIGUE_COBRO'), 'ACTUAL') = 'ACTUAL'
					BEGIN
						SELECT @IDEVANTE = DBO.FNK_VALORVARIABLE('IDNOVEDADVACMESANTE')
					END
					ELSE
					BEGIN
						SELECT @IDEVANTE = @NOVEDAD
					END

					-- PRINT '@CNSPAGON=' + @CNSPAGON
					SELECT @FINI = FECHAINI, @FFIN = FECHAFIN, @ANO = ANO, @MESP = MES, @CODNOMINA = CODNOMINA
					FROM NPER
					WHERE CNSPAGO = @CNSPAGON

					INSERT INTO NEDIA (CNSPAGO, NUMDOC, FECHAINI, FECHAFIN, DIAS, HORAS, MINUTOS, IDEVENTO, FACTOR, PAGO, OBSERVACION, CNSVAC, ITEM_VAC, FORMALIQUIDACION
						)
					SELECT @CNSPAGON, @NUMDOC, @FINI, @F_REGRESO, @DIAS1 + @DAJUS - CASE 
							WHEN DAY(@F_REGRESO) = 1
								THEN 1
							ELSE 0
							END, CAST((
								(
									@DIAS1 + @DAJUS - CASE 
										WHEN DAY(@F_REGRESO) = 1
											THEN 1
										ELSE 0
										END
									) * (@HORASLABOR / 30.00)
								) AS DECIMAL(7, 2)), DBO.FNK_NOVEDAD_MINUTOS(@DIAS1 + @DAJUS - CASE 
								WHEN DAY(@F_REGRESO) = 1
									THEN 1
								ELSE 0
								END, @HORASLABOR), @IDEVANTE, 1, NULL, @OBS, @CNSNEMPVD, 1, 'PorFecha'
				END

				UPDATE NEMPVD
				SET ESTADO = 'EnNomina'
				WHERE CNSNEMPVD = @CNSNEMPVD

				UPDATE NEMPV
				SET DIASP = COALESCE(DIASP, 0) + @DIASP
				WHERE NUMDOC = @NUMDOC AND ITEM = @ITEM

				UPDATE NEMPV
				SET ESTADO = CASE 
						WHEN DIASG >= NDIAS
							THEN CASE 
									WHEN DIASP >= DIASG
										THEN 'Pagado'
									ELSE 'Cumplidas'
									END
						ELSE 'Proceso'
						END
				WHERE NUMDOC = @NUMDOC AND ITEM = @ITEM

				SET @JSONPARAM = CONCAT (
						'{"MODELO": "ADDDEL_CONCEPTOS_DE_CARGOS_NUMDOC",', '"METODO": "PRENOMINA",', '"PARAMETROS": {', '"PROCESO": "ADD",', 
						'"CNSPAGO": "', @CNSPAGO, '",', '"NUMDOC": "', @NUMDOC, '"', '}}'
						);

				EXEC SPQ_ADDDEL_CONCEPTOS_DE_CARGOS_NUMDOC @JSONPARAM;
					--
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR_NOVEDAD_VACACIONES'
	BEGIN
		SELECT @CNSNEMPVD = CNSNEMPVD, @NUMDOC = NUMDOC, @IDEVEN = EVENTO, @CNSPAGO = CNSPAGO, @ITEM = ITEM
		FROM OPENJSON(@PARAMETROS) WITH (
				CNSNEMPVD VARCHAR(20) '$.CNSNEMPVD', NUMDOC VARCHAR(20) '$.NUMDOC', EVENTO VARCHAR(10) '$.EVENTO', CNSPAGO VARCHAR(20) '$.CNSPAGO', ITEM INT 
				'$.ITEM'
				)

		BEGIN TRY
			IF (
					SELECT CERRADO
					FROM NPER
					WHERE CNSPAGO = @CNSPAGO
					) = 1
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT CONCAT ('EL PERIODO ', @CNSPAGO, ' SE ENCUENTRRA CERRADO, NO SERA POSIBLE DESHACER LA NOVEDAD')
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				DELETE
				FROM NEDIA
				WHERE CNSVAC = @CNSNEMPVD AND NUMDOC = @NUMDOC AND (IDEVENTO = @IDEVEN OR IDEVENTO = '' OR IDEVENTO = '');

				UPDATE NEMPVD
				SET ESTADO = 'Nuevo'
				WHERE CNSNEMPVD = @CNSNEMPVD

				UPDATE NEMPV
				SET DIASP = DIASP - NEMPVD.NDIAS
				FROM NEMPV
				INNER JOIN NEMPVD ON NEMPV.NUMDOC = NEMPVD.NUMDOC
				WHERE NEMPVD.CNSNEMPVD = @CNSNEMPVD AND NEMPV.ITEM = @ITEM

				UPDATE NEMPV
				SET ESTADO = CASE 
						WHEN DIASG >= NDIAS
							THEN CASE 
									WHEN DIASP >= DIASG
										THEN 'Pagado'
									ELSE 'Cumplidas'
									END
						ELSE 'Proceso'
						END
				WHERE NUMDOC = @NUMDOC AND ITEM = @ITEM

				SET @JSONPARAM = CONCAT (
						'{"MODELO": "ADDDEL_CONCEPTOS_DE_CARGOS_NUMDOC",', '"METODO": "PRENOMINA",', '"PARAMETROS": {', '"PROCESO": "ADD",', 
						'"CNSPAGO": "', @CNSPAGO, '",', '"NUMDOC": "', @NUMDOC, '"', '}}'
						);

				EXEC SPQ_ADDDEL_CONCEPTOS_DE_CARGOS_NUMDOC @JSONPARAM;
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ANULAR_NOVEDAD_VACACIONES'
	BEGIN
		SELECT @CNSNEMPVD = CNSNEMPVD, @NUMDOC = NUMDOC, @CNSPAGO = CNSPAGO, @IDEVEN = EVENTO, @ITEM = ITEM, @PROCE = PROCE
		FROM OPENJSON(@PARAMETROS) WITH (
				CNSNEMPVD VARCHAR(20) '$.CNSNEMPVD', EVENTO VARCHAR(10) '$.EVENTO', NUMDOC VARCHAR(20) '$.NUMDOC', CNSPAGO VARCHAR(20) '$.CNSPAGO', ITEM INT 
				'$.ITEM', PROCE VARCHAR(10) '$.PROCE'
				)

		BEGIN TRY
			IF (
					SELECT CERRADO
					FROM NPER
					WHERE CNSPAGO = @CNSPAGO
					) = 1
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT CONCAT ('EL PERIODO ', @CNSPAGO, ' SE ENCUENTRRA CERRADO, NO SERA POSIBLE ANULAR LA NOVEDAD')
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				UPDATE NEMPVD
				SET ESTADO = 'Anulado'
				WHERE CNSNEMPVD = @CNSNEMPVD

				IF (@PROCE = 'Ajuste')
				BEGIN
					DELETE
					FROM NEDIA
					WHERE CNSVAC = @CNSNEMPVD AND NUMDOC = @NUMDOC AND (IDEVENTO = @IDEVEN OR IDEVENTO = '' OR IDEVENTO = '');

					UPDATE NEMPV
					SET DIASP = DIASP - NEMPVD.NDIAS
					FROM NEMPV
					INNER JOIN NEMPVD ON NEMPV.NUMDOC = NEMPVD.NUMDOC
					WHERE NEMPVD.CNSNEMPVD = @CNSNEMPVD AND NEMPV.ITEM = @ITEM

					SET @JSONPARAM = CONCAT (
							'{"MODELO": "ADDDEL_CONCEPTOS_DE_CARGOS_NUMDOC",', '"METODO": "PRENOMINA",', '"PARAMETROS": {', '"PROCESO": "ADD",', 
							'"CNSPAGO": "', @CNSPAGO, '",', '"NUMDOC": "', @NUMDOC, '"', '}}'
							);

					EXEC SPQ_ADDDEL_CONCEPTOS_DE_CARGOS_NUMDOC @JSONPARAM;
				END
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GET_DIASP'
	BEGIN
		SELECT @NUMDOC = NUMDOC, @ITEM = ITEM
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC', ITEM INT '$.ITEM')

		SELECT 'OK' OK

		SELECT DIASP
		FROM NEMPV
		WHERE NUMDOC = @NUMDOC AND ITEM = @ITEM

		RETURN
	END

	IF @METODO = 'DIA_AJUSTE'
	BEGIN
		SELECT @NUMDOC = NUMDOC, @ITEM = ITEM
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC', ITEM INT '$.ITEM')

		SELECT 'OK' OK

		SELECT TER.NIT, TER.RAZONSOCIAL, NEMPV.NDIAS, NEMPV.DIASG, NEMPV.DIASP, COALESCE((
					SELECT SUM(NDIAS)
					FROM NEMPVD
					WHERE NUMDOC = NEMPV.NUMDOC AND ITEM = NEMPV.ITEM AND COALESCE(PROCE, '') <> 'AJUSTE' AND ESTADO = 'EnNomina'
					), 0) DIASNOMI, COALESCE((
					SELECT SUM(NDIAS)
					FROM NEMPVD
					WHERE NUMDOC = NEMPV.NUMDOC AND ITEM = NEMPV.ITEM AND COALESCE(PROCE, '') = 'AJUSTE' AND ESTADO = 'EnNomina'
					), 0) DIASAJUST
		FROM NEMPV
		INNER JOIN NEMP ON NEMP.NUMDOC = NEMPV.NUMDOC
		INNER JOIN TER ON NEMP.TERCEROID = TER.IDTERCERO
		WHERE NEMPV.NUMDOC = @NUMDOC AND NEMPV.ITEM = @ITEM

		RETURN
	END

	IF @METODO = 'VALIDAR_PERIODOS'
	BEGIN
		SELECT @NUMDOC = NUMDOC
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC')

		BEGIN TRY
			SELECT @FECHACORTE = NULL

			SELECT @NUMDOC = NUMDOC, @CODCARGO = CODCARGO, @NIVEL = NIVEL, @GRADO = GRADO, @FECHAING = FECHAINGRESO, @FECHARET = COALESCE(FECHARETIRO, GETDATE() + 1)
			FROM NEMP
			WHERE ESTADO = 'Activo' AND NUMDOC = @NUMDOC

			SELECT @F_ACTUALIZA = MAX(FECHAFIN)
			FROM NPER
			INNER JOIN NIEPE ON NPER.CNSPAGO = NIEPE.CNSPAGO
			WHERE NIEPE.NUMDOC = @NUMDOC AND NPER.CERRADO = 1

			IF ISDATE(@FECHARET) = 0
			BEGIN
				SELECT @FECHACORTE = FECHAFIN
				FROM NPER
				WHERE CNSPAGO = @CNSPAGO
			END
			ELSE
			BEGIN
				SELECT @FECHACORTE = @FECHARET

				IF DBO.FNK_VALORVARIABLE('PERIODO_VACACIONES') = 'VIGENCIA'
				BEGIN
					SELECT @FECHAING = CAST('01/01/' + CONVERT(VARCHAR(4), YEAR(GETDATE())) AS DATE)
				END
			END

			IF ISDATE(@FECHACORTE) = 0
			BEGIN
				SELECT @FECHACORTE = @F_ACTUALIZA
			END

			SELECT @NPERIODOS = COALESCE(NVACACIONES, 1)
			FROM NCARNG
			WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVEL AND GRADO = @GRADO

			SELECT @MAX = MAX(ITEM)
			FROM NEMPV
			WHERE NUMDOC = @NUMDOC

			IF NOT EXISTS (
					SELECT *
					FROM NEMPV
					WHERE NUMDOC = @NUMDOC
					) OR COALESCE((
						SELECT MAX(F_FINAL)
						FROM NEMPV
						WHERE NUMDOC = @NUMDOC
						), @FECHAING) < COALESCE(@FECHACORTE, GETDATE())
			BEGIN
				IF COALESCE(@NPERIODOS, 0) > 0
				BEGIN
					SELECT @ANOS = (DBO.FNK_DATEDIFF360(@FECHAING, @FECHACORTE) / 360.00) + CASE 
							WHEN (DBO.FNK_DATEDIFF360(@FECHAING, @FECHACORTE) % 360.00) > 0
								THEN 1
							ELSE 0
							END

					DECLARE @ANOSC INT

					IF @VAC_ULTIMOS_4PER = 'SI' AND @ANOS > 4
					BEGIN
						SELECT @ANOSC = 4
						SELECT @FINICIAL = DATEADD(YEAR, @ANOS - 4, @FECHAING)
					END
					ELSE
					BEGIN
						SELECT @ANOSC = @ANOS
						SELECT @FINICIAL = @FECHAING
					END

					WHILE @ANOSC > 0
					BEGIN
						IF NOT EXISTS (
								SELECT *
								FROM NEMPV
								WHERE NUMDOC = @NUMDOC AND YEAR(F_INICAL) = YEAR(@FINICIAL) AND YEAR(F_FINAL) = YEAR(DATEADD(YEAR, 1, @FINICIAL))
								)
						BEGIN
							SELECT @MAX = MAX(ITEM)
							FROM NEMPV
							WHERE NUMDOC = @NUMDOC

							SELECT @MAX = COALESCE(@MAX, 0) + 1

							SELECT 'OK' OK

							SELECT 1 AS CREAPERIODO

							RETURN
						END

						SELECT @MAX = ITEM
						FROM NEMPV
						WHERE NUMDOC = @NUMDOC AND YEAR(F_INICAL) = YEAR(@FINICIAL) AND YEAR(F_FINAL) = YEAR(DATEADD(YEAR, 1, @FINICIAL))

						SELECT @FINICIAL = F_FINAL
						FROM NEMPV
						WHERE NUMDOC = @NUMDOC AND ITEM = @MAX

						SELECT @FFINAL = DATEADD(YEAR, 1, @FINICIAL)

						SELECT @ANOSC = @ANOSC - 1
					END
				END
			END

			SELECT 'OK' OK

			SELECT 0 AS CREAPERIODO
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'RESTABLECER_PERIODOS'
	BEGIN
		SELECT @NUMDOC = NUMDOC
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC')

		IF COALESCE(@NUMDOC, '') = ''
		BEGIN
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'Debe indicar el empleado para restablecer los periodos de vacaciones.'
		END
		ELSE IF NOT EXISTS (
				SELECT 1
				FROM NEMP
				WHERE NUMDOC = @NUMDOC
				)
		BEGIN
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'El empleado no existe.'
		END

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) = 0
		BEGIN
			BEGIN TRY
				BEGIN TRAN

				DELETE NEDIA
				FROM NEDIA
				INNER JOIN NPER ON NPER.CNSPAGO = NEDIA.CNSPAGO
				INNER JOIN NEMPVD ON NEDIA.CNSVAC = NEMPVD.CNSNEMPVD AND NEDIA.NUMDOC = NEMPVD.NUMDOC AND NPER.CERRADO = 0 AND NEDIA.NUMDOC = @NUMDOC

				DELETE
				FROM NEMPVD
				WHERE NUMDOC = @NUMDOC

				DELETE
				FROM NEMPV
				WHERE NUMDOC = @NUMDOC

				EXEC SPK_PROCESO_VACACIONES '', 'ACTUALIZA', @NUMDOC

				COMMIT TRAN
			END TRY

			BEGIN CATCH
				IF @@TRANCOUNT > 0
					ROLLBACK TRAN

				INSERT INTO @TBLERRORES (ERROR)
				SELECT ERROR_MESSAGE()
			END CATCH
		END

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
