SET NOCOUNT ON;
SELECT M.CNSMOV, M.IDTIPOMOV, M.IDPLAN, M.IDTERCERO, M.CNSFCOM, M.NOREFERENCIA,
  F.N_FACTURA, F.NROCOMPROBANTE AS FTR_NROCOMP, F.CONTABILIZADA AS FTR_CONT
FROM IMOV M
LEFT JOIN FTR F ON F.N_FACTURA = M.NOREFERENCIA OR F.N_FACTURA = M.CNSFCOM
WHERE M.IDBODEGA=N'044' AND M.MARCACONT=1 AND COALESCE(M.CONTABILIZADA,0)=0 AND M.ESTADO=1
  AND M.IDTIPOMOV IN (N'31',N'VC')
ORDER BY M.CNSMOV;
