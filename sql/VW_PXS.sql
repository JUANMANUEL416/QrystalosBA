IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME= 'VW_PXS' AND TYPE='V')
BEGIN
   DROP VIEW VW_PXS
END

GO
CREATE VIEW DBO.VW_PXS AS
SELECT ROW_NUMBER() OVER(ORDER BY X.IDSEDE, X.IDTERCERO, X.IDPLAN, X.IDADMINISTRADORA) ID, X.IDSEDE, X.IDPLAN, X.PREFIJO, X.PRIORIDAD
      ,X.IDTERCERO, X.UMBRAL, X.EXCOBROPC
      ,X.IDADMINISTRADORA, X.LIQUIDARPC, X.COBRARPC, X.TIPOTARIFA, X.IDTARIFA, X.FACTOR, X.RAZONSOCIAL
FROM (
      SELECT DISTINCT PXS.IDSEDE, PXS.IDPLAN, PXS.PREFIJO, PXS.PRIORIDAD, PXS.IDTERCERO, PXS.UMBRAL, PXS.EXCOBROPC,
             PXS.IDADMINISTRADORA, PXS.LIQUIDARPC, PXS.COBRARPC, PXS.TIPOTARIFA, PXS.IDTARIFA, PXS.FACTOR, TER.RAZONSOCIAL
      FROM   PXS INNER JOIN TER ON PXS.IDTERCERO = TER.IDTERCERO
     ) X
