CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_AGRUPACIONES @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @DATO NVARCHAR(MAX)
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20)
DECLARE @PROCESO VARCHAR(20), @DATOS NVARCHAR(MAX)
DECLARE @CODPRF VARCHAR(20), @CODPRFEDITE VARCHAR(20), @CollationName NVARCHAR(128)
DECLARE @DESCRIPCION VARCHAR(100), @CLASE VARCHAR(10), @ESTADO VARCHAR(12), @TIPO VARCHAR(12), @ESBASE SMALLINT
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @CODPRF = CODPRF, @DESCRIPCION = DESCRIPCION, @CLASE = CLASE, @TIPO = TIPO, @ESTADO = ESTADO, @ESBASE = ESBASE, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					CODPRF VARCHAR(20) '$.CODPRF', DESCRIPCION VARCHAR(100) '$.DESCRIPCION', CLASE VARCHAR(10) '$.CLASE', TIPO VARCHAR(12) '$.TIPO', ESTADO BIT 
					'$.ESTADO', ESBASE BIT '$.ESBASE', PROCESO VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('EL CODIGO ', @CODPRF, ' YA SE ENCUENTRA REGISTRADO')
					WHERE EXISTS (
							SELECT 1
							FROM NPRF
							WHERE CODPRF = @CODPRF
							)

					IF JSON_VALUE(@PARAMETROS, '$.CLASE') = 'Salario'
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT ('SOLO SE PERMITE UN GRUPO DE CONCEPTO DE CLASE SALARIO')
						WHERE EXISTS (
								SELECT 1
								FROM NPRF
								WHERE TIPO = 'Salario'
								)
					END

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO NPRF (CODPRF, DESCRIPCION, CLASE, ESTADO, COMPROBANTE, CUENTA, NATURALEZA, TIPO, INICIAL, ESBASE)
						SELECT @CODPRF, @DESCRIPCION, @CLASE, CASE 
								WHEN @ESTADO = 1
									THEN 'Activo'
								ELSE 'Inactivo'
								END, NULL, NULL, 'CR', @TIPO, 0, @ESBASE
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @DATO = DATO
					FROM OPENJSON(@PARAMETROS) WITH (DATO NVARCHAR(MAX) AS JSON)

					SELECT @CODPRFEDITE = CODPRFEDITE
					FROM OPENJSON(@DATO) WITH (CODPRFEDITE VARCHAR(20) '$.CODPRFEDITE')

					IF (@CODPRFEDITE <> @CODPRF)
					BEGIN
						IF EXISTS (
								SELECT 1
								FROM NPRF
								WHERE CODPRF = @CODPRF
								)
						BEGIN
							INSERT INTO @TBLERRORES (ERROR)
							SELECT CONCAT ('EL CODIGO ', @CODPRF, ' YA SE ENCUENTRA REGISTRADO')
						END

						IF EXISTS (
								SELECT 1
								FROM NPRF
								INNER JOIN NCOND ON NPRF.CODPRF = NCOND.CODPRF
								WHERE NPRF.CODPRF = @CODPRFEDITE
								)
						BEGIN
							INSERT INTO @TBLERRORES (ERROR)
							SELECT CONCAT ('LA AGRUPACION ', @CODPRFEDITE, ' CUENTA CON CONCEPTOS RELACIONADOS POR LO TANDO NO ES POSIBLE EDITAR SU CODIGO'
									)
						END

						IF (
								SELECT COUNT(*)
								FROM @TBLERRORES
								) <= 0
						BEGIN
							UPDATE NPRF
							SET CODPRF = @CODPRF, DESCRIPCION = @DESCRIPCION, CLASE = @CLASE, ESTADO = CASE 
									WHEN @ESTADO = 1
										THEN 'Activo'
									ELSE 'Inactivo'
									END, COMPROBANTE = NULL, CUENTA = NULL, NATURALEZA = 'CR', TIPO = @TIPO, INICIAL = 0, ESBASE = @ESBASE
							WHERE CODPRF = @CODPRFEDITE
						END
					END
					ELSE
					BEGIN
						UPDATE NPRF
						SET DESCRIPCION = @DESCRIPCION, CLASE = @CLASE, ESTADO = CASE 
								WHEN @ESTADO = 1
									THEN 'Activo'
								ELSE 'Inactivo'
								END, COMPROBANTE = NULL, CUENTA = NULL, NATURALEZA = 'CR', TIPO = @TIPO, INICIAL = 0, ESBASE = @ESBASE
						WHERE CODPRF = @CODPRF
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'STATE'
	BEGIN
		BEGIN TRY
			SELECT @CODPRF = CODPRF
			FROM OPENJSON(@PARAMETROS) WITH (CODPRF VARCHAR(20) '$.CODPRF')

			BEGIN
				UPDATE NPRF
				SET ESTADO = IIF((
							SELECT ESTADO
							FROM NPRF
							WHERE CODPRF = JSON_VALUE(@PARAMETROS, '$.CODPRF')
							) = 'Activo', 'Inactivo', 'Activo')
				WHERE CODPRF = JSON_VALUE(@PARAMETROS, '$.CODPRF')
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GET_NPRFT'
	BEGIN
		SELECT @CODPRF = CODPRF
		FROM OPENJSON(@PARAMETROS) WITH (CODPRF VARCHAR(20) '$.CODPRF')

		SELECT 'OK' OK

		SELECT TER.IDTERCERO, TER.NIT, TER.RAZONSOCIAL, TER.DV
		FROM NPRFT
		INNER JOIN TER ON TER.IDTERCERO = NPRFT.IDTERCERO
		WHERE NPRFT.CODPRF = JSON_VALUE(@PARAMETROS, '$.CODPRF')

		RETURN
	END

	IF @METODO = 'GET_NPRFT'
	BEGIN
		SELECT @CODPRF = CODPRF
		FROM OPENJSON(@PARAMETROS) WITH (CODPRF VARCHAR(20) '$.CODPRF')

		SELECT 'OK' OK

		SELECT TER.IDTERCERO, TER.NIT, TER.RAZONSOCIAL, TER.DV
		FROM NPRFT
		INNER JOIN TER ON TER.IDTERCERO = NPRFT.IDTERCERO
		WHERE NPRFT.CODPRF = JSON_VALUE(@PARAMETROS, '$.CODPRF')

		RETURN
	END

	IF @METODO = 'UPDATE_NPRFT'
	BEGIN
		BEGIN TRY
			SET NOCOUNT ON;

			SELECT @DATOS = DATOS, @CODPRF = CODPRF
			FROM OPENJSON(@PARAMETROS) WITH (DATOS NVARCHAR(MAX) AS JSON, CODPRF VARCHAR(20) '$.CODPRF')

			SELECT @CollationName = CONVERT(NVARCHAR(128), DATABASEPROPERTYEX(DB_NAME(), 'Collation'));

			-- Crear la tabla temporal sin especificar collation
			CREATE TABLE #temporal (ID INT IDENTITY(1, 1) NOT NULL PRIMARY KEY, IDTERCERO VARCHAR(20) NULL, IDCODPRF VARCHAR(20) NULL);

			DECLARE @SQL NVARCHAR(MAX);

			SET @SQL = 'ALTER TABLE #temporal ALTER COLUMN IDTERCERO VARCHAR(20) COLLATE ' + @CollationName + 
				';ALTER TABLE #temporal ALTER COLUMN IDCODPRF VARCHAR(20) COLLATE ' + @CollationName + ';';

			EXEC sp_executesql @SQL;

			INSERT INTO #temporal (IDTERCERO, IDCODPRF)
			SELECT JSON_VALUE(value, '$.IDTERCERO') COLLATE DATABASE_DEFAULT, JSON_VALUE(@PARAMETROS, '$.CODPRF') COLLATE DATABASE_DEFAULT
			FROM OPENJSON(@DATOS);

			IF ISJSON(@DATOS) = 1
			BEGIN
				-- Insertar los nuevos datos que no existan en la tabla NPRFT
				INSERT INTO NPRFT (CODPRF, IDTERCERO)
				SELECT d.IDCODPRF COLLATE DATABASE_DEFAULT, d.IDTERCERO COLLATE DATABASE_DEFAULT
				FROM #temporal d
				LEFT JOIN NPRFT ON d.IDCODPRF COLLATE DATABASE_DEFAULT = NPRFT.CODPRF COLLATE DATABASE_DEFAULT AND d.IDTERCERO COLLATE DATABASE_DEFAULT = NPRFT.
					IDTERCERO COLLATE DATABASE_DEFAULT
				WHERE NPRFT.CODPRF IS NULL AND NPRFT.IDTERCERO IS NULL;

				-- Eliminar los datos en NPRFT que no est�n en el JSON @DATOS
				DELETE NPRFT
				FROM NPRFT
				LEFT JOIN #temporal d ON NPRFT.IDTERCERO COLLATE DATABASE_DEFAULT = d.IDTERCERO COLLATE DATABASE_DEFAULT AND NPRFT.CODPRF COLLATE DATABASE_DEFAULT = d
					.IDCODPRF COLLATE DATABASE_DEFAULT
				WHERE d.IDTERCERO IS NULL AND NPRFT.CODPRF COLLATE DATABASE_DEFAULT = JSON_VALUE(@PARAMETROS, '$.CODPRF') COLLATE DATABASE_DEFAULT;
			END
			ELSE
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT ('El par?metro JSON no es v?lido.')
			END

			DROP TABLE #temporal;

			SET NOCOUNT OFF;
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @CODPRF = CODPRF
		FROM OPENJSON(@PARAMETROS) WITH (CODPRF VARCHAR(20) '$.CODPRF')

		BEGIN TRY
			INSERT INTO @TBLERRORES (ERROR)
			SELECT CONCAT ('NO ES POSIBLE ELIMINAR LA AGRUPACION ', @CODPRF, ' YA QUE SE ENCUENTRA EN LIQUIDACIONES PREVIAMENTE PROCESADAS'
					)
			WHERE EXISTS (
					SELECT 1
					FROM NIEPED
					WHERE CODPRF = @CODPRF
					)

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				DELETE
				FROM NPRFT
				WHERE CODPRF = @CODPRF

				DELETE
				FROM NPRFD
				WHERE CODPRF = @CODPRF

				DELETE
				FROM NPRF
				WHERE CODPRF = @CODPRF
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
