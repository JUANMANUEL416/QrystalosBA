SET NOCOUNT ON;

SELECT
  CASE WHEN OBJECT_DEFINITION(OBJECT_ID(N'dbo.SPK_CONTAB_MASIVA')) LIKE N'%NO filtrar por FECHACONF%' THEN N'PREVERSION_OK' ELSE N'CEM_VIEJO' END AS SPK_MASIVA,
  CASE WHEN OBJECT_DEFINITION(OBJECT_ID(N'dbo.SPQ_CONTABILIDAD_3')) LIKE N'%éxito vacío%' OR OBJECT_DEFINITION(OBJECT_ID(N'dbo.SPQ_CONTABILIDAD_3')) LIKE N'%exito vacio%' THEN N'SPQ_NUEVO' ELSE N'SPQ_VIEJO' END AS SPQ_CONT3;

SELECT M.IDTIPOMOV, T.DESCRIPCION, COUNT(*) CNT,
  SUM(CASE WHEN COALESCE(M.SECONTABILIZA,0)=0 THEN 1 ELSE 0 END) NO_SECONT,
  SUM(CASE WHEN COALESCE(M.CONTABILIZADA,0)=0 THEN 1 ELSE 0 END) SIN_CONTAB
FROM IMOV M
LEFT JOIN ITMO T ON T.IDTIPOMOV = M.IDTIPOMOV
WHERE M.IDBODEGA = N'044' AND COALESCE(M.MARCACONT,0)=1 AND COALESCE(M.CONTABILIZADA,0)=0 AND M.ESTADO=1
GROUP BY M.IDTIPOMOV, T.DESCRIPCION ORDER BY CNT DESC;

SELECT TOP 8 M.CNSMOV, M.IDTIPOMOV, M.CONTABILIZADA, M.SECONTABILIZA, M.CCOSTO, M.IDAREA,
  B.NOCONTABILIZA AS BOD_NOCONTAB
FROM IMOV M JOIN IBOD B ON B.IDBODEGA = M.IDBODEGA
WHERE M.IDBODEGA=N'044' AND M.MARCACONT=1 AND COALESCE(M.CONTABILIZADA,0)=0 AND M.ESTADO=1;

SELECT COUNT(*) ERRADOS_INV_044
FROM MCP P JOIN MCH H ON H.NROCOMPROBANTE=P.NROCOMPROBANTE
WHERE P.PROCEDENCIA=N'INV' AND P.ESTADO=0
AND EXISTS (SELECT 1 FROM IMOV M WHERE M.NROCOMPROBANTE=P.NROCOMPROBANTE AND M.IDBODEGA=N'044');
