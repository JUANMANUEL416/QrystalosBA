			, MANEJAOMEX CHAR(1) COLLATE DATABASE_DEFAULT, BORRAR CHAR(1) COLLATE DATABASE_DEFAULT, COBRARA CHAR(1) COLLATE DATABASE_DEFAULT, IDTERCEROCA VARCHAR(20
			) COLLATE DATABASE_DEFAULT, IDPLANCA VARCHAR(20) COLLATE DATABASE_DEFAULT, REQAUTORIZACION CHAR(1) COLLATE DATABASE_DEFAULT, ES_DUPLICADO_DB BIT 
