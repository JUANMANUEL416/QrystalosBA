				, ISNULL(P.MANEJAOMEX, 'N'), ISNULL(P.BORRAR, '0'), ISNULL(P.COBRARA, 'O'), P.IDTERCEROCA, P.IDPLANCA, ISNULL(P.REQAUTORIZACION, '0');

			UPDATE T
			SET ES_DUPLICADO_DB = 1
			FROM #TEMPDATA T
