CREATE OR ALTER PROCEDURE DBO.SPQ_CONF_PLANES @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @DATOS NVARCHAR(MAX)
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20)
DECLARE @PROCESO VARCHAR(20), @IDPLAN VARCHAR(6), @DESCPLAN VARCHAR(45), @ESTADO VARCHAR(8), @TIPOSISTEMA VARCHAR(20)
DECLARE @REGIMEN2193 VARCHAR(20), @ESPAQUETE BIT, @TIPOVOLUNTARIO VARCHAR(3), @RIAS BIT, @HCSINCIT SMALLINT, @DEPRUEBAS BIT
DECLARE @PREFIJOCARNET VARCHAR(2), @IDSERVICIO VARCHAR(20), @CRONICO BIT, @HOMOLOGO VARCHAR(20)
DECLARE @IDPLANEDITE VARCHAR(6), @IDTERCEROCA VARCHAR(20), @IDPLANCA VARCHAR(6), @TAR VARCHAR(5)
DECLARE @IDPLANORI VARCHAR(6), @TIPOCOPIA VARCHAR(1), @PREFIJO VARCHAR(6), @IDPLANG VARCHAR(6)
DECLARE @IDTERCEROOR VARCHAR(20), @IDPLANOR VARCHAR(6), @IDTERCERODES VARCHAR(20), @IDPLANDES VARCHAR(6), @IDTERCEROAC VARCHAR(20), @IDMODELODSS VARCHAR(20), 
	@IDAREAS NVARCHAR(MAX), @PREFR NVARCHAR(MAX), @COBRARA VARCHAR(20), @NIVELATENCION VARCHAR(5), @CNSEXCEL VARCHAR(20), @IDSEDE VARCHAR(5), @SYS_COMPUTERNAME 
	VARCHAR(254), @COMPANIA VARCHAR(2)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @TASEGURA025 VARCHAR(2)
DECLARE @DESC_COB NVARCHAR(200), @SUG_COD VARCHAR(3), @SUG_DESC NVARCHAR(120)

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
	FROM USUSU
	WHERE USUARIO = @USUARIO

	SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
	FROM UBEQ
	WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @IDPLAN = IDPLAN, @DESCPLAN = DESCPLAN, @ESTADO = ESTADO, @TIPOSISTEMA = TIPOSISTEMA, @REGIMEN2193 = REGIMEN2193, @ESPAQUETE = ESPAQUETE, 
				@TIPOVOLUNTARIO = TIPOVOLUNTARIO, @HCSINCIT = HCSINCIT, @DEPRUEBAS = DEPRUEBAS, @PREFIJOCARNET = PREFIJOCARNET, @RIAS = RIAS, @PROCESO = PROCESO, 
				@IDSERVICIO = IDSERVICIO, @CRONICO = CRONICO, @HOMOLOGO = HOMOLOGO, @TASEGURA025 = TASEGURA025
			FROM OPENJSON(@PARAMETROS) WITH (
					IDPLAN VARCHAR(6) '$.IDPLAN', DESCPLAN VARCHAR(45) '$.DESCPLAN', ESTADO VARCHAR(8) '$.ESTADO', TIPOSISTEMA VARCHAR(20) '$.TIPOSISTEMA', 
					REGIMEN2193 VARCHAR(20) '$.REGIMEN2193', ESPAQUETE BIT '$.ESPAQUETE', TIPOVOLUNTARIO VARCHAR(3) '$.TIPOVOLUNTARIO.CODIGO', RIAS BIT '$.RIAS', 
					HCSINCIT SMALLINT '$.HCSINCIT', DEPRUEBAS BIT '$.DEPRUEBAS', PREFIJOCARNET VARCHAR(2) '$.PREFIJOCARNET', PROCESO VARCHAR(20) '$.PROCESO', 
					IDSERVICIO VARCHAR(20) '$.IDSERVICIO', CRONICO BIT '$.CRONICO', TASEGURA025 SMALLINT '$.TASEGURA025', HOMOLOGO VARCHAR(20)
					)

			/* REQ 0100016503: bloquear pareja TIPOSISTEMA + cobertura SISPRO inválida */
			IF NULLIF(LTRIM(RTRIM(@TIPOVOLUNTARIO)), '') IS NOT NULL
				AND NULLIF(LTRIM(RTRIM(@TIPOSISTEMA)), '') IS NOT NULL
				AND NOT EXISTS (
					SELECT 1
					FROM (
						VALUES
							('Contributivo', '16'), ('Contributivo', '02'),
							('Desplazado Reg Cont', '16'), ('Desplazado Reg Cont', '02'),
							('Subsidiado', '17'), ('Subsidiado', '02'),
							('Desplazado Reg Sub', '17'), ('Desplazado Reg Sub', '02'),
							('Particular', '15'),
							('ARL', '05'),
							('Vinculado', '07'), ('Vinculado', '08'),
							('Desplazado Vinc', '07'), ('Desplazado Vinc', '08'),
							('Exepcion', '13'), ('Exepcion', '14'),
							('Prepagado', '11'), ('Prepagado', '10'), ('Prepagado', '12'),
							('SinRegimen', '04'), ('SinRegimen', '03'), ('SinRegimen', '09'), ('SinRegimen', '06'),
							('Otro', '06'), ('Otro', '03'), ('Otro', '09'), ('Otro', '14')
						) V(TIPOSISTEMA, COBERTURA)
					WHERE V.TIPOSISTEMA = @TIPOSISTEMA
						AND V.COBERTURA = LTRIM(RTRIM(@TIPOVOLUNTARIO))
					)
			BEGIN
				SELECT @DESC_COB = DESCRIPCION
				FROM TGEN
				WHERE TABLA = N'PLN'
					AND CAMPO = N'CobertuPlanBeneficio'
					AND CODIGO = LTRIM(RTRIM(@TIPOVOLUNTARIO))

				SELECT @SUG_COD = CASE @TIPOSISTEMA
						WHEN 'Contributivo' THEN '16'
						WHEN 'Desplazado Reg Cont' THEN '16'
						WHEN 'Subsidiado' THEN '17'
						WHEN 'Desplazado Reg Sub' THEN '17'
						WHEN 'Particular' THEN '15'
						WHEN 'ARL' THEN '05'
						WHEN 'Vinculado' THEN '07'
						WHEN 'Desplazado Vinc' THEN '07'
						WHEN 'Exepcion' THEN '13'
						WHEN 'Prepagado' THEN '11'
						WHEN 'SinRegimen' THEN '04'
						WHEN 'Otro' THEN '06'
						ELSE NULL
						END
					, @SUG_DESC = CASE @TIPOSISTEMA
						WHEN 'Contributivo' THEN N'Plan de beneficios UPC régimen contributivo'
						WHEN 'Desplazado Reg Cont' THEN N'Plan de beneficios UPC régimen contributivo'
						WHEN 'Subsidiado' THEN N'Plan de beneficios UPC régimen subsidiado'
						WHEN 'Desplazado Reg Sub' THEN N'Plan de beneficios UPC régimen subsidiado'
						WHEN 'Particular' THEN N'Particular'
						WHEN 'ARL' THEN N'Cobertura ARL'
						WHEN 'Vinculado' THEN N'Cobertura salud pública'
						WHEN 'Desplazado Vinc' THEN N'Cobertura salud pública'
						WHEN 'Exepcion' THEN N'Cobertura régimen especial o excepción'
						WHEN 'Prepagado' THEN N'Plan medicina prepagada'
						WHEN 'SinRegimen' THEN N'Cobertura póliza SOAT'
						WHEN 'Otro' THEN N'Cobertura ADRES'
						ELSE NULL
						END

				INSERT INTO @TBLERRORES (ERROR)
				SELECT CONCAT (
						N'La cobertura ', ISNULL(@DESC_COB, N'seleccionada'), N' (', LTRIM(RTRIM(@TIPOVOLUNTARIO)),
						N') no corresponde al tipo de sistema ', @TIPOSISTEMA, N'.',
						CASE
							WHEN @SUG_COD IS NOT NULL
								THEN CONCAT (N' Para este tipo de sistema se sugiere ', @SUG_DESC, N' (', @SUG_COD, N').')
							ELSE N' Seleccione una cobertura permitida para ese tipo de sistema.'
							END
						)

				SELECT 'KO' OK

				SELECT ERROR
				FROM @TBLERRORES

				RETURN
			END

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('El CODIGO ', @IDPLAN, ' YA SE ENCUENTRA REGISTRADO')
					WHERE EXISTS (
							SELECT 1
							FROM PLN
							WHERE IDPLAN = @IDPLAN
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO PLN (
							IDPLAN, DESCPLAN, ESTADO, TIPOSISTEMA, REGIMEN2193, ESPAQUETE, TIPOVOLUNTARIO, RIAS, HCSINCIT, DEPRUEBAS, PREFIJOCARNET, IDSERVICIO, 
							CRONICO, HOMOLOGO, TASEGURA025
							)
						SELECT @IDPLAN, @DESCPLAN, @ESTADO, @TIPOSISTEMA, @REGIMEN2193, @ESPAQUETE, @TIPOVOLUNTARIO, @RIAS, @HCSINCIT, @DEPRUEBAS, @PREFIJOCARNET
							, @IDSERVICIO, @CRONICO, @HOMOLOGO, @TASEGURA025
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @DATOS = DATOS
					FROM OPENJSON(@PARAMETROS) WITH (DATOS NVARCHAR(MAX) AS JSON)

					SELECT @IDPLANEDITE = IDPLANEDITE
					FROM OPENJSON(@DATOS) WITH (IDPLANEDITE VARCHAR(6) '$.IDPLANEDITE')

					IF (@IDPLAN <> @IDPLANEDITE)
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('El CODIGO ', @IDPLAN, ' YA SE ENCUENTRA REGISTRADO')
						WHERE EXISTS (
								SELECT 1
								FROM PLN
								WHERE IDPLAN = @IDPLAN
								)

						IF (
								SELECT COUNT(*)
								FROM @TBLERRORES
								) <= 0
						BEGIN
							UPDATE PLN
							SET IDPLAN = @IDPLAN, DESCPLAN = @DESCPLAN, ESTADO = @ESTADO, TIPOSISTEMA = @TIPOSISTEMA, REGIMEN2193 = @REGIMEN2193, ESPAQUETE = @ESPAQUETE
								, TIPOVOLUNTARIO = @TIPOVOLUNTARIO, RIAS = @RIAS, HCSINCIT = @HCSINCIT, DEPRUEBAS = @DEPRUEBAS, PREFIJOCARNET = @PREFIJOCARNET, 
								IDSERVICIO = @IDSERVICIO, CRONICO = @CRONICO, HOMOLOGO = @HOMOLOGO, TASEGURA025 = @TASEGURA025
							WHERE IDPLAN = @IDPLANEDITE
						END
					END
					ELSE
					BEGIN
						UPDATE PLN
						SET IDPLAN = @IDPLAN, DESCPLAN = @DESCPLAN, ESTADO = @ESTADO, TIPOSISTEMA = @TIPOSISTEMA, REGIMEN2193 = @REGIMEN2193, ESPAQUETE = @ESPAQUETE, 
							TIPOVOLUNTARIO = @TIPOVOLUNTARIO, RIAS = @RIAS, HCSINCIT = @HCSINCIT, DEPRUEBAS = @DEPRUEBAS, PREFIJOCARNET = @PREFIJOCARNET, IDSERVICIO = 
							@IDSERVICIO, CRONICO = @CRONICO, HOMOLOGO = @HOMOLOGO, TASEGURA025 = @TASEGURA025
						WHERE IDPLAN = @IDPLAN
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'COPIA_CONTRATO'
	BEGIN
		BEGIN TRY
			SELECT @IDPLAN = IDPLAN, @IDTERCEROCA = IDTERCEROCA, @IDPLANORI = IDPLANORI, @TIPOCOPIA = TIPOCOPIA, @IDTERCEROCA = IDTERCEROCA
			FROM OPENJSON(@PARAMETROS) WITH (
					IDPLAN VARCHAR(6) '$.IDPLAN', IDTERCEROCA VARCHAR(20) '$.IDTERCEROCA', IDPLANORI VARCHAR(6) '$.IDPLANORI', TIPOCOPIA VARCHAR(1) '$.TIPOCOPIA'
					, IDTERCEROCA VARCHAR(20) '$.IDTERCEROCA'
					)

			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'No existe contratacion entre el Plan y el Tercero. Revisar...'
			WHERE NOT EXISTS (
					SELECT 1
					FROM PPT
					WHERE IDPLAN = @IDPLANORI AND IDTERCERO = @IDTERCEROCA
					)

			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'El Contrato a Copiar esta en Blanco.'
			WHERE NOT EXISTS (
					SELECT 1
					FROM CPPAF
					WHERE IDPLAN = @IDPLAN
					)

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				IF @TIPOCOPIA = '1'
				BEGIN
					DELETE CPPAF
					WHERE IDPLAN = @IDPLANORI

					INSERT INTO CPPAF (
						IDPLAN, IDSERVICIO, IDAREA, CARENCIA, CUENTAUTILP, USO, FACTOR, MANEJAPRO, MANEJAOMEX, BORRAR, COBRARA, IDTERCEROCA, IDPLANCA, 
						REQAUTORIZACION
						)
					SELECT @IDPLANORI, IDSERVICIO, IDAREA, CARENCIA, CUENTAUTILP, USO, FACTOR, MANEJAPRO, MANEJAOMEX, BORRAR, COBRARA, @IDTERCEROCA, @IDPLANORI, 
						REQAUTORIZACION
					FROM CPPAF
					WHERE IDPLAN = @IDPLAN
				END

				IF @TIPOCOPIA = '2'
				BEGIN
					INSERT INTO CPPAF (
						IDPLAN, IDSERVICIO, IDAREA, CARENCIA, CUENTAUTILP, USO, FACTOR, MANEJAPRO, MANEJAOMEX, BORRAR, COBRARA, IDTERCEROCA, IDPLANCA, 
						REQAUTORIZACION
						)
					SELECT O.IDPLANDES, O.IDSERVICIO, O.IDAREA, O.CARENCIA, O.CUENTAUTILP, O.USO, O.FACTOR, O.MANEJAPRO, O.MANEJAOMEX, O.BORRAR, O.COBRARA, O.
						IDTERCEROCA, O.IDPLANCA, O.REQAUTORIZACION
					FROM (
						SELECT @IDPLANORI IDPLANDES, IDSERVICIO, IDAREA, CARENCIA, CUENTAUTILP, USO, FACTOR, MANEJAPRO, MANEJAOMEX, BORRAR, COBRARA, @IDTERCEROCA 
							IDTERCEROCA, @IDPLANORI IDPLANCA, REQAUTORIZACION
						FROM CPPAF
						WHERE IDPLAN = @IDPLAN
						) O
					LEFT JOIN CPPAF D ON O.IDAREA = D.IDAREA AND O.IDSERVICIO = D.IDSERVICIO AND @IDPLANORI = D.IDPLAN
					WHERE D.IDAREA IS NULL
				END
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'COPIA_IDENT_CONTRATO'
	BEGIN
		BEGIN TRY
			BEGIN TRAN

			SET DATEFORMAT dmy;

			SELECT @IDMODELODSS = IDMODELODSS, @IDTERCEROAC = IDTERCEROAC, @IDPLANDES = IDPLANDES, @IDTERCERODES = IDTERCERODES, @IDPLANOR = IDPLANOR, @IDTERCEROOR = 
				IDTERCEROOR, @IDAREAS = IDAREAS
			FROM OPENJSON(@PARAMETROS) WITH (
					IDMODELODSS VARCHAR(20) '$.IDMODELODSS', IDTERCEROAC VARCHAR(20) '$.IDTERCEROAC', IDPLANDES VARCHAR(6) '$.IDPLANDES', IDTERCERODES VARCHAR(
						20) '$.IDTERCERODES', IDPLANOR VARCHAR(6) '$.IDPLANOR', IDTERCEROOR VARCHAR(20) '$.IDTERCEROOR', IDAREAS NVARCHAR(MAX) AS JSON
					);

			DECLARE @AREAS TABLE (IDAREA INT);

			INSERT INTO @AREAS (IDAREA)
			SELECT value
			FROM OPENJSON(@IDAREAS);

			-- ==========================================================
			-- TABLA 1: PPT
			-- ==========================================================
			INSERT INTO PPT (
				IDTERCERO, IDPLAN, MTOPE, TOPE, DIASVTO, TIPOTERCONTABLE, MCARENCIA, LIQCARENCIA, MMINUTOSCIRDS, FECHAVENCIMIENTO, IDTARIFA, FACTOR, CAPITADO, 
				MAXCITASMESAFI, MAXCITASINCMES, TIPORECOBRO, COBRACOPAGO, TIPOFACTURACION, BDPROPIA, IDMODELOPC, MEFARMACIA, MEDROGAALTA, TIPOLIQCX, IDMODELOPCA
				, IDMODELOPCH, NODESCUENTACOPAGO, CEAUTORIZADO, COPAGOIND, CAMBIACONT, IDCONTRATO, FACTPORAFU, RESUMEN, IMPRIMEEST
				)
			SELECT @IDTERCERODES, @IDPLANDES, MTOPE, TOPE, DIASVTO, TIPOTERCONTABLE, MCARENCIA, LIQCARENCIA, MMINUTOSCIRDS, FECHAVENCIMIENTO, IDTARIFA, FACTOR, 
				CAPITADO, MAXCITASMESAFI, MAXCITASINCMES, TIPORECOBRO, COBRACOPAGO, TIPOFACTURACION, BDPROPIA, IDMODELOPC, MEFARMACIA, MEDROGAALTA, TIPOLIQCX, 
				IDMODELOPCA, IDMODELOPCH, NODESCUENTACOPAGO, CEAUTORIZADO, COPAGOIND, CAMBIACONT, IDCONTRATO, FACTPORAFU, RESUMEN, IMPRIMEEST
			FROM PPT Origen
			WHERE IDTERCERO = @IDTERCEROOR AND IDPLAN = @IDPLANOR AND NOT EXISTS (
					-- Validación: No insertar si ya existe en ppt
					SELECT 1
					FROM PPT Destino
					WHERE Destino.IDTERCERO = @IDTERCERODES AND Destino.IDPLAN = @IDPLANDES
					);

			-- ==========================================================
			-- TABLA 2: ETP
			-- ==========================================================
			INSERT INTO ETP (IDPROVEEDOR, IDPLAN, PREFIJO, NIVELATENCION, TIPOCONTRATO, IDTARIFA, FACTOR, PCUBIERTOAMB, PCUBIERTOHOS, PAQUETE, TIPORECOBRO, TIPORESTRICCION
				)
			SELECT @IDTERCERODES, @IDPLANDES, PREFIJO, NIVELATENCION, TIPOCONTRATO, IDTARIFA, FACTOR, PCUBIERTOAMB, PCUBIERTOHOS, PAQUETE, TIPORECOBRO, 
				TIPORESTRICCION
			FROM ETP Origen
			WHERE IDPROVEEDOR = @IDTERCEROOR AND IDPLAN = @IDPLANOR AND NOT EXISTS (
					-- Validación: No insertar si ya existe en etp
					SELECT 1
					FROM ETP Destino
					WHERE Destino.IDPROVEEDOR = @IDTERCERODES AND Destino.IDPLAN = @IDPLANDES
					);

			-- ==========================================================
			-- TABLA 3: ESP
			-- ==========================================================
			INSERT INTO ESP (
				IDPROVEEDOR, IDPLAN, IDSERVICIO, TIPORESTRICCION, IDTARIFA, FACTOR, VALOR, PAQUETE, TIPOCONTRATO, TIPORECOBRO, FECHAINI, FECHAFIN, IDACUMULADOR, 
				MAREA, IDAREA
				)
			SELECT @IDTERCERODES, @IDPLANDES, IDSERVICIO, TIPORESTRICCION, IDTARIFA, FACTOR, VALOR, PAQUETE, TIPOCONTRATO, TIPORECOBRO, FECHAINI, FECHAFIN, 
				IDACUMULADOR, MAREA, IDAREA
			FROM ESP Origen
			WHERE IDPROVEEDOR = @IDTERCEROOR AND IDPLAN = @IDPLANOR AND NOT EXISTS (
					SELECT 1
					FROM ESP Destino
					WHERE Destino.IDPROVEEDOR = @IDTERCERODES AND Destino.IDPLAN = @IDPLANDES AND Destino.IDSERVICIO = Origen.IDSERVICIO
						-- Validamos por servicio también
					);

			-- ==========================================================
			-- TABLA 4: CPPAF
			-- ==========================================================
			INSERT INTO CPPAF (IDPLAN, IDSERVICIO, IDAREA, CARENCIA, CUENTAUTILP, USO, FACTOR, MANEJAPRO, MANEJAOMEX, BORRAR, COBRARA, IDTERCEROCA, IDPLANCA, REQAUTORIZACION
				)
			SELECT DISTINCT @IDPLANDES, SERTOT.IDSERVICIO, AFU.IDAREA, NULL, NULL, NULL, NULL, NULL, NULL, NULL, 'C', @IDTERCEROCA, @IDPLANDES, 0
			FROM SERTOT
			CROSS JOIN AFU
			WHERE SERTOT.IDTERCERO = @IDTERCEROOR AND SERTOT.IDPLAN = @IDPLANOR AND AFU.IDAREA IN (
					SELECT IDAREA
					FROM @AREAS
					) AND SERTOT.IDSERVICIO IN (
					SELECT IDSERVICIO
					FROM SER
					) AND (
					CASE 
						WHEN TRY_CONVERT(DATETIME, SERTOT.FECHAFIN, 103) IS NULL
							THEN 0
						WHEN TRY_CONVERT(DATETIME, SERTOT.FECHAFIN, 103) > DBO.FNK_FECHA_SIN_MLS(GETDATE())
							THEN 1
						ELSE 0
						END
					) = 1
				-- Validación Existencia
				AND NOT EXISTS (
					SELECT 1
					FROM CPPAF Destino
					WHERE Destino.IDPLAN = @IDPLANDES AND Destino.IDSERVICIO = SERTOT.IDSERVICIO AND Destino.IDAREA = AFU.IDAREA
					);

			-- ==========================================================
			-- TABLA 5: PPTD
			-- ==========================================================
			INSERT INTO PPTD (IDTERCERO, IDPLAN, IDSERVICIO, TIPOCOBRABLE, CANTNOCOBRABLE, MAREA, IDAREA, TIPORESTRICCION)
			SELECT @IDTERCERODES, @IDPLANDES, IDSERVICIO, TIPOCOBRABLE, CANTNOCOBRABLE, MAREA, IDAREA, TIPORESTRICCION
			FROM PPTD Origen
			WHERE IDTERCERO = @IDTERCEROOR AND IDPLAN = @IDPLANOR AND NOT EXISTS (
					SELECT 1
					FROM PPTD Destino
					WHERE Destino.IDTERCERO = @IDTERCERODES AND Destino.IDPLAN = @IDPLANDES AND Destino.IDSERVICIO = Origen.IDSERVICIO
					);

			-- ==========================================================
			-- TABLA 6: PXSN
			-- ==========================================================
			INSERT INTO PXSN (IDTERCERO, IDADMINISTRADORA, IDPLAN, IDTARIFA, FACTOR, IDCONTRATO, NIVELATENCION, TIPORECOBRO, TIPOCONTRATO)
			SELECT IDTERCERO, @IDTERCERODES, @IDPLANDES, IDTARIFA, FACTOR, IDCONTRATO, NIVELATENCION, TIPORECOBRO, TIPOCONTRATO
			FROM PXSN Origen
			WHERE IDADMINISTRADORA = @IDTERCEROOR AND IDPLAN = @IDPLANOR AND NOT EXISTS (
					SELECT 1
					FROM PXSN Destino
					WHERE Destino.IDTERCERO = Origen.IDTERCERO -- Ojo aquí, el tercero prestador se mantiene
						AND Destino.IDADMINISTRADORA = @IDTERCERODES AND Destino.IDPLAN = @IDPLANDES
					);

			-- ==========================================================
			-- TABLA 7: PXS
			-- ==========================================================
			INSERT INTO PXS (IDSEDE, IDPLAN, PREFIJO, PRIORIDAD, IDTERCERO, UMBRAL, EXCOBROPC, IDADMINISTRADORA, LIQUIDARPC, COBRARPC, TIPOTARIFA, IDTARIFA, FACTOR
				)
			SELECT IDSEDE, @IDPLANDES, PREFIJO, PRIORIDAD, IDTERCERO, UMBRAL, EXCOBROPC, @IDTERCERODES, LIQUIDARPC, COBRARPC, TIPOTARIFA, IDTARIFA, FACTOR
			FROM PXS Origen
			WHERE IDADMINISTRADORA = @IDTERCEROOR AND IDPLAN = @IDPLANOR AND NOT EXISTS (
					SELECT 1
					FROM PXS Destino
					WHERE Destino.IDSEDE = Origen.IDSEDE AND Destino.IDPLAN = @IDPLANDES AND Destino.IDADMINISTRADORA = @IDTERCERODES
					);

			-- ==========================================================
			-- TABLA 8: PXSE
			-- ==========================================================
			INSERT INTO PXSE (IDTERCERO, IDADMINISTRADORA, IDPLAN, IDSEDE, PREFIJO, IDSERVICIO, TIPORESTRICCION, IDTARIFA, FACTOR, VALOR)
			SELECT IDTERCERO, @IDTERCERODES, @IDPLANDES, IDSEDE, PREFIJO, IDSERVICIO, TIPORESTRICCION, IDTARIFA, FACTOR, VALOR
