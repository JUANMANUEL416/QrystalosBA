	IF @METODO = 'CRUDPLNU'
	BEGIN
		DECLARE @ID_PLNU INT, @REGISTRO_PLNU NVARCHAR(MAX), @UNIDATENCION VARCHAR(12)

		-- Leer PROCESO (obligatorio) desde nivel superior
		SELECT @PROCESO = NULLIF(LTRIM(RTRIM(PROCESO)), '')
		FROM OPENJSON(@PARAMETROS) WITH (PROCESO VARCHAR(20) '$.PROCESO')

		-- Leer datos: si existe REGISTRO, leer desde ahí; si no, desde el propio @PARAMETROS
		SELECT @REGISTRO_PLNU = REGISTRO
		FROM OPENJSON(@PARAMETROS) WITH (REGISTRO NVARCHAR(MAX) AS JSON)
		WHERE REGISTRO IS NOT NULL

		IF @REGISTRO_PLNU IS NOT NULL
		BEGIN
			SELECT @ID_PLNU = ID, @IDPLAN = IDPLAN, @UNIDATENCION = UNIDATENCION, @ESTADO = ESTADO
			FROM OPENJSON(@REGISTRO_PLNU) WITH (ID INT '$.ID', IDPLAN VARCHAR(6) '$.IDPLAN', UNIDATENCION VARCHAR(12) '$.UNIDATENCION', ESTADO VARCHAR(20) '$.ESTADO'
					)
		END
		ELSE
		BEGIN
			SELECT @ID_PLNU = ID, @IDPLAN = IDPLAN, @UNIDATENCION = UNIDATENCION, @ESTADO = ESTADO
			FROM OPENJSON(@PARAMETROS) WITH (ID INT '$.ID', IDPLAN VARCHAR(6) '$.IDPLAN', UNIDATENCION VARCHAR(12) '$.UNIDATENCION', ESTADO VARCHAR(20) '$.ESTADO'
					)
		END

		-- Validar PROCESO
		IF @PROCESO IS NULL OR @PROCESO NOT IN ('INSERTAR', 'EDITAR', 'eliminar', 'ELIMINAR')
		BEGIN
			INSERT INTO @TBLERRORES (ERROR)
			VALUES ('Proceso no válido. Debe ser INSERTAR, EDITAR o eliminar.')

			SELECT 'KO' AS OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		BEGIN TRY
			-- INSERTAR
			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				IF @IDPLAN IS NULL OR LTRIM(RTRIM(@IDPLAN)) = ''
				BEGIN
					INSERT INTO @TBLERRORES (ERROR)
					VALUES ('IDPLAN es requerido.')
				END
				ELSE IF @UNIDATENCION IS NULL OR LTRIM(RTRIM(@UNIDATENCION)) = ''
				BEGIN
					INSERT INTO @TBLERRORES (ERROR)
					VALUES ('UNIDATENCION (Rol) es requerido.')
				END
				ELSE IF EXISTS (
						SELECT 1
						FROM PLNU
						WHERE IDPLAN = @IDPLAN AND UNIDATENCION = @UNIDATENCION
						)
				BEGIN
					INSERT INTO @TBLERRORES (ERROR)
					VALUES ('Ya existe un registro con esa unidad de atención para el plan.')
				END
				ELSE
				BEGIN
					SET @ESTADO = ISNULL(NULLIF(LTRIM(RTRIM(@ESTADO)), ''), 'Activo')

					INSERT INTO PLNU (IDPLAN, UNIDATENCION, ESTADO)
					VALUES (@IDPLAN, @UNIDATENCION, @ESTADO)
				END
			END

			-- EDITAR (por ID si viene; si no, por IDPLAN + UNIDATENCION)
			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				IF @ID_PLNU IS NOT NULL AND @ID_PLNU > 0
				BEGIN
					IF NOT EXISTS (
							SELECT 1
							FROM PLNU
							WHERE ID = @ID_PLNU
							)
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						VALUES ('No existe el registro a editar.')
					END
					ELSE
					BEGIN
						SET @ESTADO = ISNULL(NULLIF(LTRIM(RTRIM(@ESTADO)), ''), 'Activo')

						UPDATE PLNU
						SET ESTADO = @ESTADO
						WHERE ID = @ID_PLNU
					END
				END
				ELSE IF @IDPLAN IS NOT NULL AND @UNIDATENCION IS NOT NULL
				BEGIN
					IF NOT EXISTS (
							SELECT 1
							FROM PLNU
							WHERE IDPLAN = @IDPLAN AND UNIDATENCION = @UNIDATENCION
							)
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						VALUES ('No existe el registro a editar.')
					END
					ELSE
					BEGIN
						SET @ESTADO = ISNULL(NULLIF(LTRIM(RTRIM(@ESTADO)), ''), 'Activo')

						UPDATE PLNU
						SET ESTADO = @ESTADO
						WHERE IDPLAN = @IDPLAN AND UNIDATENCION = @UNIDATENCION
					END
				END
				ELSE
				BEGIN
					INSERT INTO @TBLERRORES (ERROR)
					VALUES ('Para editar se requiere ID o IDPLAN + UNIDATENCION.')
				END
			END

			-- ELIMINAR (por ID si viene; si no, por IDPLAN + UNIDATENCION)
			IF UPPER(@PROCESO) = 'ELIMINAR' OR LOWER(@PROCESO) = 'eliminar'
			BEGIN
				IF @ID_PLNU IS NOT NULL AND @ID_PLNU > 0
				BEGIN
					IF NOT EXISTS (
							SELECT 1
							FROM PLNU
							WHERE ID = @ID_PLNU
							)
						INSERT INTO @TBLERRORES (ERROR)
						VALUES ('No existe el registro a eliminar.')
					ELSE
						DELETE
						FROM PLNU
						WHERE ID = @ID_PLNU
				END
				ELSE IF @IDPLAN IS NOT NULL AND @UNIDATENCION IS NOT NULL
				BEGIN
					IF NOT EXISTS (
							SELECT 1
							FROM PLNU
							WHERE IDPLAN = @IDPLAN AND UNIDATENCION = @UNIDATENCION
							)
						INSERT INTO @TBLERRORES (ERROR)
						VALUES ('No existe el registro a eliminar.')
					ELSE
						DELETE
						FROM PLNU
						WHERE IDPLAN = @IDPLAN AND UNIDATENCION = @UNIDATENCION
				END
				ELSE
				BEGIN
					INSERT INTO @TBLERRORES (ERROR)
					VALUES ('Para eliminar se requiere ID o IDPLAN + UNIDATENCION.')
				END
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' AS OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' AS OK

		RETURN
	END
