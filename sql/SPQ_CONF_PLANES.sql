			BEGIN
				DECLARE @PrefijoIDPLAN VARCHAR(6);
				DECLARE @PrefijoPREFIJO VARCHAR(20);
				DECLARE @PrefijoIDAREA VARCHAR(20);

				DECLARE PrefijosCursor CURSOR
