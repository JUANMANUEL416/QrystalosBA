			INSERT INTO #TEMPDATA (IDPLAN, IDSERVICIO, IDAREA, CARENCIA, CUENTAUTILP, USO, FACTOR, MANEJAPRO, MANEJAOMEX, BORRAR, COBRARA, IDTERCEROCA, IDPLANCA, REQAUTORIZACION
