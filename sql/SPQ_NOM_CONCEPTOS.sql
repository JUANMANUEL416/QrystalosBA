CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_CONCEPTOS @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @DATO NVARCHAR(MAX)
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20)
DECLARE @PROCESO VARCHAR(20), @JSONPARAM NVARCHAR(MAX)
DECLARE @CODCONCEPTO VARCHAR(20), @DESCRIPCION VARCHAR(255), @TIPO VARCHAR(7), @CLASE VARCHAR(10)
DECLARE @ESTADO VARCHAR(12), @PRIORIDAD SMALLINT, @INFO VARCHAR(2), @SEREPITE VARCHAR(2), @CNSPAGO VARCHAR(20)
DECLARE @SEIMPRIME VARCHAR(2), @CVALOR100P VARCHAR(2), @MOSTRARHORAS VARCHAR(12), @COMPROBANTE VARCHAR(2)
DECLARE @CUENTA VARCHAR(16), @NATURALEZA VARCHAR(2), @TIPOPREST VARCHAR(12), @INICIAL SMALLINT, @ITEM INT, @TODOS SMALLINT
DECLARE @RUBRO VARCHAR(50), @FIJO BIT, @VISIBLE SMALLINT, @CODHOMOLOGO VARCHAR(20), @DATOS NVARCHAR(MAX), @CNSEXCEL VARCHAR(20)
DECLARE @ID_DIAN VARCHAR(100), @RUBRO_ID INT, @CODRET VARCHAR(20), @NROLINEAS INT, @IDSEDE VARCHAR(5), @SYS_COMPUTERNAME VARCHAR(200), @COMPANIA VARCHAR(2)
DECLARE @VALOR DECIMAL(14, 6), @IDTERCERO VARCHAR(20), @FECHAINI DATETIME, @FECHAFIN DATETIME, @CNSRPDX VARCHAR(20), @INDICE INT, @ESTRUCTURA INT
DECLARE @CODCONCEPTOEDITE VARCHAR(20), @DESCRIPCIONCONCEPTO VARCHAR(250), @DOCIDEMPLEADO VARCHAR(20), @NOMBREEMPLEADO VARCHAR(250)
DECLARE @ERROR VARCHAR(2024), @ER BIT, @TERRORES SMALLINT, @TOK SMALLINT, @NUMDOC VARCHAR(20), @XFECHA VARCHAR(20), @FECHAINIPER VARCHAR(20), @FECHAFINPER VARCHAR(20)
	, @VALHORASLAB DECIMAL(18, 6), @FECHAFIN_VC VARCHAR(20), @FECHAINI_VC VARCHAR(20)
DECLARE @CODNOMINA VARCHAR(2)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
	FROM USUSU
	WHERE USUARIO = @USUARIO

	SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
	FROM UBEQ
	WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @CODCONCEPTO = CODCONCEPTO, @DESCRIPCION = DESCRIPCION, @TIPO = TIPO, @CLASE = CLASE, @ESTADO = ESTADO, @PRIORIDAD = PRIORIDAD, @INFO = INFO, @SEREPITE = 
				SEREPITE, @SEIMPRIME = SEIMPRIME, @CVALOR100P = CVALOR100P, @MOSTRARHORAS = MOSTRARHORAS, @TIPOPREST = TIPOPREST, @ID_DIAN = ID_DIAN, @CODRET = CODRET, 
				@PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO', DESCRIPCION VARCHAR(255) '$.DESCRIPCION', TIPO VARCHAR(7) '$.TIPO', CLASE VARCHAR(10) '$.CLASE', 
					ESTADO BIT '$.ESTADO', PRIORIDAD SMALLINT '$.PRIORIDAD', INFO BIT '$.INFO', SEREPITE BIT '$.SEREPITE', SEIMPRIME BIT '$.SEIMPRIME', CVALOR100P BIT 
					'$.CVALOR100P', MOSTRARHORAS VARCHAR(12) '$.MOSTRARHORAS', TIPOPREST VARCHAR(12) '$.TIPOPREST', ID_DIAN VARCHAR(100) '$.ID_DIAN', CODRET 
					VARCHAR(20) '$.CODRET', PROCESO VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('EL CODIGO ', @CODCONCEPTO, ' YA SE ENCUENTRA REGISTRADO')
					WHERE EXISTS (
							SELECT 1
							FROM NCON
							WHERE CODCONCEPTO = @CODCONCEPTO
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO NCON (
							CODCONCEPTO, DESCRIPCION, TIPO, CLASE, ESTADO, PRIORIDAD, INFO, SEREPITE, SEIMPRIME, CVALOR100P, MOSTRARHORAS, NATURALEZA, TIPOPREST, 
							INICIAL, VISIBLE, ID_DIAN, CODRET
							)
						SELECT @CODCONCEPTO, @DESCRIPCION, @TIPO, @CLASE, CASE 
								WHEN @ESTADO = 1
									THEN 'Activo'
								ELSE 'Inactivo'
								END, @PRIORIDAD, CASE 
								WHEN @INFO = 1
									THEN 'Si'
								ELSE 'No'
								END, CASE 
								WHEN @SEREPITE = 1
									THEN 'Si'
								ELSE 'No'
								END, CASE 
								WHEN @SEIMPRIME = 1
									THEN 'Si'
								ELSE 'No'
								END, CASE 
								WHEN @CVALOR100P = 1
									THEN 'Si'
								ELSE 'No'
								END, @MOSTRARHORAS, 'DB', @TIPOPREST, @INICIAL, 1, @ID_DIAN, @CODRET
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @DATO = DATO
					FROM OPENJSON(@PARAMETROS) WITH (DATO NVARCHAR(MAX) AS JSON)

					SELECT @CODCONCEPTOEDITE = CODCONCEPTOEDITE
					FROM OPENJSON(@DATO) WITH (CODCONCEPTOEDITE VARCHAR(20) '$.CODCONCEPTOEDITE')

					IF (@CODCONCEPTOEDITE <> @CODCONCEPTO)
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('EL CODIGO ', @CODCONCEPTO, ' YA SE ENCUENTRA REGISTRADO')
						WHERE EXISTS (
								SELECT 1
								FROM NCON
								WHERE CODCONCEPTO = @CODCONCEPTO
								)

						IF (
								SELECT COUNT(*)
								FROM @TBLERRORES
								) <= 0
						BEGIN
							UPDATE NCON
							SET CODCONCEPTO = @CODCONCEPTO, DESCRIPCION = @DESCRIPCION, TIPO = @TIPO, CLASE = @CLASE, ESTADO = CASE 
									WHEN @ESTADO = 1
										THEN 'Activo'
									ELSE 'Inactivo'
									END, PRIORIDAD = @PRIORIDAD, INFO = CASE 
									WHEN @INFO = 1
										THEN 'Si'
									ELSE 'No'
									END, SEREPITE = CASE 
									WHEN @SEREPITE = 1
										THEN 'Si'
									ELSE 'No'
									END, SEIMPRIME = CASE 
									WHEN @SEIMPRIME = 1
										THEN 'Si'
									ELSE 'No'
									END, CVALOR100P = CASE 
									WHEN @CVALOR100P = 1
										THEN 'Si'
									ELSE 'No'
									END, MOSTRARHORAS = @MOSTRARHORAS, TIPOPREST = @TIPOPREST, ID_DIAN = @ID_DIAN
							WHERE CODCONCEPTO = @CODCONCEPTOEDITE
						END
					END
					ELSE
					BEGIN
						UPDATE NCON
						SET DESCRIPCION = @DESCRIPCION, TIPO = @TIPO, CLASE = @CLASE, ESTADO = CASE 
								WHEN @ESTADO = 1
									THEN 'Activo'
								ELSE 'Inactivo'
								END, PRIORIDAD = @PRIORIDAD, INFO = CASE 
								WHEN @INFO = 1
									THEN 'Si'
								ELSE 'No'
								END, SEREPITE = CASE 
								WHEN @SEREPITE = 1
									THEN 'Si'
								ELSE 'No'
								END, SEIMPRIME = CASE 
								WHEN @SEIMPRIME = 1
									THEN 'Si'
								ELSE 'No'
								END, CVALOR100P = CASE 
								WHEN @CVALOR100P = 1
									THEN 'Si'
								ELSE 'No'
								END, MOSTRARHORAS = @MOSTRARHORAS, TIPOPREST = @TIPOPREST, ID_DIAN = @ID_DIAN
						WHERE CODCONCEPTO = @CODCONCEPTO
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'STATE'
	BEGIN
		BEGIN TRY
			SELECT @CODCONCEPTO = CODCONCEPTO
			FROM OPENJSON(@PARAMETROS) WITH (CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO')

			BEGIN
				UPDATE NCON
				SET ESTADO = IIF((
							SELECT ESTADO
							FROM NCON
							WHERE CODCONCEPTO = JSON_VALUE(@PARAMETROS, '$.CODCONCEPTO')
							) = 'Activo', 'Inactivo', 'Activo')
				WHERE CODCONCEPTO = JSON_VALUE(@PARAMETROS, '$.CODCONCEPTO')
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GET_NPRF_DETAIL'
	BEGIN
		SELECT @CLASE = CLASE
		FROM OPENJSON(@PARAMETROS) WITH (CLASE VARCHAR(20) '$.CLASE')

		SELECT 'OK' OK;

		WITH RegistrosConRanking
		AS (
			SELECT NPRF.CODPRF, NPRF.DESCRIPCION, NPRF.CLASE, NPRF.TIPO, NPRFD.VALOR_EMPRESA, NPRFD.VALOR_EMPLEADO, NPRFD.TIPOCALCULO, NPRFD.FECHAINI, 
				ROW_NUMBER() OVER (
					PARTITION BY NPRFD.CODPRF ORDER BY NPRFD.FECHAINI DESC
					) AS rn
			FROM NPRF
			INNER JOIN NPRFD ON NPRF.CODPRF = NPRFD.CODPRF
			WHERE NPRF.ESTADO = 'Activo' AND NPRFD.ESTADO = 'Activo' AND NPRF.CLASE = @CLASE AND NPRFD.FECHAINI <= GETDATE()
			)
		SELECT *
		FROM RegistrosConRanking
		WHERE rn = 1;

		RETURN
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @CODCONCEPTO = CODCONCEPTO
		FROM OPENJSON(@PARAMETROS) WITH (CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO')

		BEGIN TRY
			DELETE
			FROM NCON
			WHERE CODCONCEPTO = @CODCONCEPTO
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'CARGAR_EMPLEADOS_CONCEPTOS'
	BEGIN
		DECLARE @LINEA AS VARCHAR(MAX)
		DECLARE @TABLA AS TABLE (ITEM INT IDENTITY(1, 1), VALOR VARCHAR(MAX))

		SELECT @NROLINEAS = COUNT(*)
		FROM OPENJSON(@PARAMETROS, '$.LINEAS')

		SELECT @CODNOMINA = CODNOMINA
		FROM OPENJSON(@PARAMETROS) WITH (CODNOMINA VARCHAR(2) '$.CODNOMINA')

		IF @NROLINEAS > 0
		BEGIN
			SELECT @IDSEDE = COALESCE(UBEQ.IDSEDE, USUSU.IDSEDE), @COMPANIA = COALESCE(UBEQ.COMPANIA, USUSU.COMPANIA), @SYS_COMPUTERNAME = COALESCE(USUSU.
					SYS_ComputerName, HOST_NAME())
			FROM USUSU
			LEFT JOIN UBEQ ON USUSU.SYS_ComputerName = UBEQ.SYS_ComputerName
			WHERE USUSU.USUARIO = @USUARIO

			SELECT @CNSRPDX = ''

			EXEC SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE, '@RPDX', @CNSRPDX OUTPUT

			SELECT @CNSRPDX = @IDSEDE + REPLACE(SPACE(8 - LEN(@CNSRPDX)) + LTRIM(RTRIM(@CNSRPDX)), SPACE(1), 0)

			PRINT '@CNSRPDX=' + COALESCE(@CNSRPDX, '')

			SELECT @INDICE = 0

			SELECT @DESCRIPCIONCONCEPTO = ''

			DECLARE CM_CONCEPTOS CURSOR
			FOR
			SELECT VALUE
			FROM OPENJSON(@PARAMETROS, '$.LINEAS')

			OPEN CM_CONCEPTOS

			FETCH NEXT
			FROM CM_CONCEPTOS
			INTO @LINEA

			WHILE @@FETCH_STATUS = 0
			BEGIN
				DELETE @TABLA
				WHERE 1 = 1

				INSERT INTO @TABLA (VALOR)
				SELECT VALUE
				FROM string_split(@LINEA, ',')

				SELECT @ESTRUCTURA = COUNT(*)
				FROM @TABLA

				SET @ERROR = ''
				SET @ER = 0

				SELECT @NUMDOC = NULL, @DOCIDEMPLEADO = NULL, @NOMBREEMPLEADO = NULL, @CODCONCEPTO = NULL, @VALOR = NULL, @IDTERCERO = NULL, @FECHAINI = NULL, @FECHAFIN = 
					NULL, @SEREPITE = NULL

				BEGIN TRY
					SELECT @NUMDOC = VALOR
					FROM @TABLA
					WHERE ITEM = 1 + @INDICE

					SELECT @DOCIDEMPLEADO = VALOR
					FROM @TABLA
					WHERE ITEM = 2 + @INDICE

					SELECT @NOMBREEMPLEADO = VALOR
					FROM @TABLA
					WHERE ITEM = 3 + @INDICE

					SELECT @CODCONCEPTO = VALOR
					FROM @TABLA
					WHERE ITEM = 4 + @INDICE

					SELECT @VALOR = VALOR
					FROM @TABLA
					WHERE ITEM = 5 + @INDICE

					SELECT @IDTERCERO = VALOR
					FROM @TABLA
					WHERE ITEM = 6 + @INDICE

					SELECT @XFECHA = LTRIM(RTRIM(REPLACE(VALOR, CHAR(13), '')))
					FROM @TABLA
					WHERE ITEM = 7 + @INDICE

					SET @FECHAINI = COALESCE(TRY_CONVERT(DATE, @XFECHA, 105), TRY_CONVERT(DATE, @XFECHA, 103))

					IF @FECHAINI IS NULL
					BEGIN
						SELECT @FECHAINI = NULL, @ER = 1, @ERROR = 'Fecha de inicio no valida ' + ISNULL(@XFECHA, '')
					END

					SELECT @XFECHA = LTRIM(RTRIM(REPLACE(VALOR, CHAR(13), '')))
					FROM @TABLA
					WHERE ITEM = 8 + @INDICE

					SET @FECHAFIN = COALESCE(TRY_CONVERT(DATE, @XFECHA, 105), TRY_CONVERT(DATE, @XFECHA, 103))

					IF @FECHAFIN IS NULL
					BEGIN
						SELECT @FECHAFIN = NULL, @ER = 1, @ERROR = 'Fecha de final no valida ' + ISNULL(@XFECHA, '')
					END

					IF @ESTRUCTURA <> 8
					BEGIN
						SELECT @ER = 1, @ERROR = 'Error de Estructura Campos =' + CAST(@ESTRUCTURA AS VARCHAR(4))
					END

					IF @ER = 1
					BEGIN
						INSERT INTO RPDX (CNS, ID1, ID2, STRINGMEDIO2, ID4, STRINGGRANDE1, VALOR1, ID3, FECHA3, FECHA4, CANTIDAD10, STRINGMAX
							)
						SELECT @CNSRPDX, @NUMDOC, @CODCONCEPTO, @DESCRIPCIONCONCEPTO, @DOCIDEMPLEADO, @NOMBREEMPLEADO, @VALOR, @IDTERCERO, @FECHAINI, @FECHAFIN, 
							1, @ERROR
					END
					ELSE
					BEGIN
						PRINT 'Validaici�n de existencia de datos'

						IF NOT EXISTS (
								SELECT *
								FROM NEMP
								WHERE NUMDOC = @NUMDOC
								)
						BEGIN
							SELECT @ER = 1, @ERROR = @ERROR + ' - Codigo de contrato No existe'
						END

						IF NOT EXISTS (
								SELECT *
								FROM NEMP
								WHERE NUMDOC = @NUMDOC AND DOCIDEMPLEADO = @DOCIDEMPLEADO
								)
						BEGIN
							SELECT @ER = 1, @ERROR = @ERROR + ' - Documento del empleado no pertenece al numero de contrato'
						END

						IF NOT EXISTS (
								SELECT *
								FROM NCON
								WHERE CODCONCEPTO = @CODCONCEPTO
								)
						BEGIN
							SELECT @ER = 1, @ERROR = @ERROR + ' - El id del concepto no existe'
						END
						ELSE
						BEGIN
							SELECT @DESCRIPCIONCONCEPTO = DESCRIPCION
							FROM NCON
							WHERE CODCONCEPTO = @CODCONCEPTO
						END

						IF NOT EXISTS (
								SELECT *
								FROM NCON
								WHERE CODCONCEPTO = @CODCONCEPTO AND ESTADO = 'Activo'
								)
						BEGIN
							SELECT @ER = 1, @ERROR = @ERROR + ' - El id del concepto no se encuentra activo'
						END
						ELSE
						BEGIN
							SELECT @DESCRIPCIONCONCEPTO = DESCRIPCION
							FROM NCON
							WHERE CODCONCEPTO = @CODCONCEPTO
						END

						IF NOT EXISTS (
								SELECT *
								FROM NCON
								WHERE CODCONCEPTO = @CODCONCEPTO AND ESTADO = 'Activo' AND CLASE = 'Particular'
								)
						BEGIN
							SELECT @ER = 1, @ERROR = @ERROR + ' - El id del concepto no es un concepto particula'
						END
						ELSE
						BEGIN
							SELECT @DESCRIPCIONCONCEPTO = DESCRIPCION
							FROM NCON
							WHERE CODCONCEPTO = @CODCONCEPTO
						END

						IF @VALOR <= 0
						BEGIN
							SELECT @ER = 1, @ERROR = @ERROR + ',Valor debe ser positivo o 0'
						END

						IF NOT EXISTS (
								SELECT *
								FROM TER
								WHERE (IDTERCERO = @IDTERCERO)
								)
						BEGIN
							SELECT @ER = 1, @ERROR = @ERROR + ',El idtercero no Existe '
						END

						IF @FECHAFIN <= @FECHAINI
						BEGIN
							SELECT @ER = 1, @ERROR = @ERROR + ',Fecha final debe ser mayor o igual a la fecha inicial'
						END

						IF NOT EXISTS (
								SELECT *
								FROM NOMIE
								WHERE NUMDOC = @NUMDOC AND CODNOMINA = @CODNOMINA
								)
						BEGIN
							SELECT @ER = 1, @ERROR = @ERROR + ' - El Empleado ' + @DOCIDEMPLEADO + ' no existe dentro de la plantilla de la nomina'
						END
						ELSE
						BEGIN
							IF (
									(
										SELECT ESTADO
										FROM NOMIE
										WHERE CODNOMINA = @CODNOMINA AND NUMDOC = @NUMDOC
										) = 'Inactivo'
									)
							BEGIN
								SELECT ' - El Empleado ' + @DOCIDEMPLEADO + ' se encuentra inactivo en la plantilla de la nomina'
							END
						END

						SELECT @NOMBREEMPLEADO = CONCAT_WS(' ', NEMP.PRIMERNOMBRE, NEMP.SEGUNDONOMBRE, NEMP.PRIMERAPELLIDO, NEMP.SEGUNDOAPELLIDO)
						FROM NEMP
						WHERE NUMDOC = @NUMDOC

						SELECT @SEREPITE = ISNULL(NCON.SEREPITE, 'No'), @DESCRIPCIONCONCEPTO = COALESCE(NCON.DESCRIPCION, @DESCRIPCIONCONCEPTO)
						FROM NCON
						WHERE NCON.CODCONCEPTO = @CODCONCEPTO

						-- SEREPITE='No': no se acepta el mismo concepto particular con vigencia cruzada (lote ni NEMPDA)
						-- SEREPITE='Si': cada fila se carga como �tem independiente en el detalle del empleado
						IF @ER = 0 AND ISNULL(@SEREPITE, 'No') <> 'Si' AND ISNULL(@CODCONCEPTO, '') <> ''
						BEGIN
							IF EXISTS (
									SELECT 1
									FROM RPDX R
									WHERE R.CNS = @CNSRPDX AND R.ID1 = @NUMDOC AND R.ID2 = @CODCONCEPTO AND ISNULL(R.CANTIDAD10, 0) = 0 AND @FECHAFIN >= R.FECHA3 AND 
										@FECHAINI <= R.FECHA4
									)
							BEGIN
								SELECT @ER = 1, @ERROR = @ERROR + ' - El concepto ' + ISNULL(@CODCONCEPTO, '') + 
									' no permite repetirse. Ya existe otra asignaci�n del mismo concepto para este empleado con vigencia cruzada en el archivo.'
							END

							IF @ER = 0 AND EXISTS (
									SELECT 1
									FROM NEMPDA
									INNER JOIN NCON ON NCON.CODCONCEPTO = NEMPDA.CODCONCEPTO
									WHERE NEMPDA.NUMDOC = @NUMDOC AND NEMPDA.CODCONCEPTO = @CODCONCEPTO AND @FECHAFIN >= NEMPDA.FECHAINI AND @FECHAINI <= NEMPDA.
										FECHAFIN AND ISNULL(NCON.SEREPITE, 'No') <> 'Si'
									)
							BEGIN
								SELECT @ER = 1, @ERROR = @ERROR + ' - El concepto ' + ISNULL(@CODCONCEPTO, '') + 
									' no permite repetirse. Ya est� asignado al empleado con vigencia cruzada.'
							END
						END

						INSERT INTO RPDX (CNS, ID1, ID2, STRINGMEDIO2, ID4, STRINGGRANDE1, VALOR1, ID3, FECHA3, FECHA4, CANTIDAD10, STRINGMAX
							)
						SELECT @CNSRPDX, @NUMDOC, @CODCONCEPTO, @DESCRIPCIONCONCEPTO, @DOCIDEMPLEADO, @NOMBREEMPLEADO, @VALOR, @IDTERCERO, @FECHAINI, @FECHAFIN, 
							@ER, @ERROR
					END
				END TRY

				BEGIN CATCH
					SELECT @NUMDOC = VALOR
					FROM @TABLA
					WHERE ITEM = 1 + @INDICE

					INSERT INTO RPDX (CNS, ID1, STRINGGRANDE2, STRINGMAX, CANTIDAD10)
					SELECT @CNSRPDX, @NUMDOC, ERROR_MESSAGE(), @LINEA, 1
				END CATCH

				SET @INDICE += @ESTRUCTURA

				FETCH NEXT
				FROM CM_CONCEPTOS
				INTO @LINEA
			END

			CLOSE CM_CONCEPTOS

			DEALLOCATE CM_CONCEPTOS

			SELECT @NROLINEAS = COUNT(*)
			FROM RPDX
			WHERE CNS = @CNSRPDX --AND CANTIDAD=1

			SELECT @TERRORES = SUM(CASE 
						WHEN CANTIDAD10 = 1
							THEN 1
						ELSE 0
						END), @TOK = SUM(CASE 
						WHEN CANTIDAD10 = 1
							THEN 0
						ELSE 1
						END)
			FROM RPDX
			WHERE CNS = @CNSRPDX

			SELECT 'OK' OK, @CNSRPDX CNSRPDX, @NROLINEAS TODOS, @TERRORES ERRADOS, @TOK TOK

			RETURN
		END
		ELSE
		BEGIN
			SELECT 'KO', 'No se encontraron Datos para Procesar, Verfique e intente de nuevo' ERROR

			RETURN
		END
	END

	IF @METODO = 'VALIDAR_RPDX_EMPLEADO_CONCEPTOS'
	BEGIN
		SELECT @DATOS = DATOS, @CODNOMINA = CODNOMINA
		FROM OPENJSON(@PARAMETROS) WITH (DATOS NVARCHAR(MAX) AS JSON, CODNOMINA VARCHAR(2) '$.CODNOMINA')

		SELECT @DESCRIPCIONCONCEPTO = ''

		SELECT @CNSRPDX = CNS, @ITEM = ID, @NUMDOC = NUMDOC, @DOCIDEMPLEADO = DOCIDEMPLEADO, @NOMBREEMPLEADO = NOMBREEMPLEADO, @CODCONCEPTO = CODCONCEPTO, @VALOR = VALOR, 
			@IDTERCERO = IDTERCERO, @FECHAINI = FECHAINI, @FECHAFIN = FECHAFIN, @ERROR = ERRORTXT
