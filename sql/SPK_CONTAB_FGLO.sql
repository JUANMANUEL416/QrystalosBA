IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='SPK_CONTAB_FGLO' AND XTYPE='P')
BEGIN
   DROP PROCEDURE SPK_CONTAB_FGLO
END

GO
CREATE  PROCEDURE DBO.SPK_CONTAB_FGLO 
@CNSGLO           VARCHAR(20), 
@USUARIO          VARCHAR(12),
@SYS_COMPUTERNAME VARCHAR(254),
@COMPANIA         VARCHAR(2), 
@SEDE             VARCHAR(5),
@NROCOMPROBANTE   VARCHAR(20)
WITH ENCRYPTION
AS
DECLARE @COM              VARCHAR(6)
DECLARE @NOREFERENCIA     VARCHAR(20)
DECLARE @ANO              VARCHAR(4)
DECLARE @MES              INT
DECLARE @IDMODELOCONT     VARCHAR(2)
DECLARE @TIPOTERCONTABLE  VARCHAR(10) 
DECLARE @PREFIJO_USCXS    VARCHAR(10)
DECLARE @FECHATRA         DATETIME
BEGIN

   IF NOT EXISTS (SELECT * FROM FGLO WHERE CNSGLO=@CNSGLO AND VLRRECUPERAR>0) AND UPPER((SELECT MCUEORDEN_GLOSAS FROM PAR WHERE COMPANIA = @COMPANIA))<>'SI'
   BEGIN
      PRINT 'NO HAY VALORES A RECUPERAR'
      RETURN
   END

   SELECT * INTO #T FROM FGLO WHERE CNSGLO=@CNSGLO  

   IF (SELECT CASE WHEN FCIERRE IS NULL THEN 1 ELSE 0 END FROM #T )=1
   BEGIN
      UPDATE FGLO SET FCIERRE=GETDATE() WHERE CNSGLO=@CNSGLO
      UPDATE #T SET FCIERRE=GETDATE() WHERE CNSGLO=@CNSGLO
   END
   
   SELECT   @ANO            = YEAR(COALESCE(FCIERRE,FECHARESP)),
            @MES            = MONTH(COALESCE(FCIERRE,FECHARESP)),
            @FECHATRA       = COALESCE(FCIERRE,FECHARESP)
   FROM #T
   
   IF NOT EXISTS(SELECT COMPANIA,ANO,MES FROM PRI WHERE COMPANIA=@COMPANIA AND ANO=@ANO AND MES=@MES AND COALESCE(CERRADO,0)=0 AND COALESCE(CERRADO_CARTERA,0)=0)
   BEGIN
      RAISERROR('Periodo Contable NO Existe o se encuentrar cerrado', 16, 1)
      RETURN
   END
   
   SET @IDMODELOCONT = DBO.FNK_VALORVARIABLE('IDMODELOCONTABLE')
   IF ISNULL(@NROCOMPROBANTE,'') = '' -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD
   BEGIN
      SET @NROCOMPROBANTE = SPACE(20) -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD
      EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@MCP',@NROCOMPROBANTE OUTPUT -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD
      PRINT '@NROCOMPROBANTE:' + ISNULL(@NROCOMPROBANTE,'') -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD
      SELECT @NROCOMPROBANTE = @SEDE + REPLACE(SPACE(8 - CASE WHEN LEN(@NROCOMPROBANTE) > 8 THEN 8 ELSE LEN(@NROCOMPROBANTE) END)+LTRIM(RTRIM(@NROCOMPROBANTE)),SPACE(1),0) -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD
      PRINT '@NROCOMPROBANTE:' + ISNULL(@NROCOMPROBANTE,'') -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD
      --SE REVISA SI LOS COMPROBANTES SE TOMAN DE ACUERDO A SEDE

      IF (SELECT DBO.FNK_VALORVARIABLE('COMPROBMULTISEDE')) = 'SI'
      BEGIN
         SELECT @COM = RTRIM(LTRIM(COMMS.COMPROBANTE)) FROM COMMS WHERE IDSEDE = @SEDE AND COMMS.CLASE = 'FGLO' AND TIPO = 'FGLO'
      END
      ELSE
      BEGIN
         SET @COM=LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('IDCON_TCOM_RGLO')))
      END
      
      SET @PREFIJO_USCXS='@COM'+@COM
      SET @NOREFERENCIA=SPACE(20)
      EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,@PREFIJO_USCXS,@NOREFERENCIA OUTPUT   
      SELECT @NOREFERENCIA = REPLACE(SPACE(8 - LEN(@NOREFERENCIA))+LTRIM(RTRIM(@NOREFERENCIA)),SPACE(1),0)
      PRINT 'Nuevo Comprobante: '+@COM+' '+@NOREFERENCIA
      
      PRINT 'Comprobanrte Contable (MCPE)'
      INSERT INTO MCPE(NROCOMPROBANTE, COMPANIA, PROCEDENCIA, NOREFERENCIA, ANO, MES, FECHACONTABLE, TOTALDEBITO,
                      TOTALCREDITO, REFERENCIA1, REFERENCIA2, USUARIO, FECHA, LOTE, OBSERVACION, IDSEDE, ESTADO,
                      COMPROBANTE, IDTERCERO)
      SELECT @NROCOMPROBANTE, @COMPANIA, 'RGLO', @NOREFERENCIA, @ANO, @MES, 
             CAST(STR(DAY(@FECHATRA))+'/'+LTRIM(STR(@MES))+'/'+@ANO AS DATETIME), 0, 0, CNSGLO, '', @USUARIO, 
             DBO.FNK_FECHA_SIN_MLS(GETDATE()), NULL, LEFT(#T.OBSERVACION,510), @SEDE, 0, @COM, 
            (CASE WHEN #T.IDTERCERO IS NULL THEN '' ELSE #T.IDTERCERO END)
      FROM #T  
   END
   IF EXISTS(SELECT * FROM MCP WHERE NROCOMPROBANTE=@NROCOMPROBANTE) AND EXISTS(SELECT * FROM MCPE WHERE NROCOMPROBANTE=@NROCOMPROBANTE)
   BEGIN
      PRINT 'EXISTE EN LAS TABLAS DEBO BORRAR UNO'
      IF (SELECT COALESCE(ESTADO,0) FROM MCP WHERE NROCOMPROBANTE=@NROCOMPROBANTE AND COALESCE(ANULADO,0)<>1)<>0
      BEGIN 
         PRINT 'BORRO MCPE'
         DELETE MCHE WHERE NROCOMPROBANTE = @NROCOMPROBANTE
         DELETE MCPE WHERE NROCOMPROBANTE = @NROCOMPROBANTE 
         RETURN
      END
      ELSE
      BEGIN
         PRINT 'BORRO MCP'
         DELETE MCH WHERE NROCOMPROBANTE = @NROCOMPROBANTE
         DELETE MCP WHERE NROCOMPROBANTE = @NROCOMPROBANTE  
      END
   END
   IF (SELECT COUNT(*) FROM MCP WHERE NROCOMPROBANTE=@NROCOMPROBANTE )>0
   BEGIN
      INSERT INTO MCPE (COMPANIA, NROCOMPROBANTE, PROCEDENCIA, NOREFERENCIA, ANO, MES, FECHACONTABLE, TOTALDEBITO ,TOTALCREDITO, REFERENCIA1, REFERENCIA2,
                       REFERENCIA3, USUARIO, FECHA, LOTE ,OBSERVACION ,IDSEDE ,ESTADO ,ANULADO ,COMPROBANTE ,IDTERCERO, BANCO ,NOCHEQUE, VALOR_CHEQUE,
                       RPT_COMPROBANTE, FECHARADICACION, MARCA, SYS_COMPUTERNAME_MARCA, ESTADOIMP, CBTEINTERNO)
      SELECT COMPANIA, NROCOMPROBANTE, PROCEDENCIA, NOREFERENCIA, ANO, MES, FECHACONTABLE, TOTALDEBITO ,TOTALCREDITO, REFERENCIA1, REFERENCIA2,
                       REFERENCIA3, USUARIO, FECHA, LOTE ,OBSERVACION ,IDSEDE ,ESTADO ,ANULADO ,COMPROBANTE ,IDTERCERO, BANCO ,NOCHEQUE, VALOR_CHEQUE,
                       RPT_COMPROBANTE, FECHARADICACION, MARCA, SYS_COMPUTERNAME_MARCA, ESTADOIMP, CBTEINTERNO
      FROM   MCP
      WHERE NROCOMPROBANTE=@NROCOMPROBANTE
      --se borran de mcp, mch
      DELETE MCH WHERE NROCOMPROBANTE = @NROCOMPROBANTE
      DELETE MCP WHERE NROCOMPROBANTE = @NROCOMPROBANTE   
   END
   DELETE MCHE WHERE NROCOMPROBANTE=@NROCOMPROBANTE
   
   IF (SELECT MCUEORDEN_GLOSAS FROM PAR WHERE COMPANIA = @COMPANIA)='Si'
   BEGIN
      PRINT 'Contabilizando DB Glosas con Cuentas de Orden...' 
      INSERT INTO MCHE(NROCOMPROBANTE, COMPANIA, TIPO, CUENTA, IDTERCERO, CCOSTO, DETALLE, VALOR ,REFERENCIA1,
                       REFERENCIA2, ITEMREF, USUARIO, FECHA, IDAREA, PREFIJO, ESTADO, PROCESO, GENERA,    
                       CLASECONT, N_FACTURA, F_FACTURAREF, F_VENCE, PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
      SELECT @NROCOMPROBANTE, @COMPANIA, 'DB', CASE WHEN CUE.CUENTA IS NULL THEN 'NO CUEORDENGLOSA' ELSE CUE.CUENTA END, 
             #T.IDTERCERO,'' AS CCOSTO, 'RECUPERACION DE GLOSA DE FA '+#T.N_FACTURA, #T.VLRRECUPERAR, NULL, NULL, NULL, 
             @USUARIO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), '' AS IDAREA, '' AS PREFIJO, 1, 
             'CUEORDENGLOSADB', 'Movimiento','S', #T.N_FACTURA, DBO.FNK_FECHA_SIN_HORA(FTR.F_FACTURA), 
             DBO.FNK_FECHA_SIN_HORA(FTR.F_VENCE),'RGLO',@CNSGLO, #T.CODUNG, #T.CODPRG
      FROM   #T LEFT JOIN 
             FTR ON #T.N_FACTURA = FTR.N_FACTURA LEFT JOIN
             TTEC ON TTEC.TIPO=FTR.TIPOTTEC LEFT JOIN 
             CUE ON TTEC.CUEORDENGLOSACR=CUE.CUENTA AND CUE.COMPANIA=@COMPANIA
      WHERE #T.VLRRECUPERAR<>0
      
      PRINT 'Contabilizando CR Glosas con Cuentas de Orden...' 
      INSERT INTO MCHE(NROCOMPROBANTE, COMPANIA, TIPO, CUENTA, IDTERCERO, CCOSTO, DETALLE, VALOR ,REFERENCIA1,
                      REFERENCIA2, ITEMREF, USUARIO, FECHA, IDAREA, PREFIJO, ESTADO, PROCESO, GENERA,    
                      CLASECONT, N_FACTURA, F_FACTURAREF, F_VENCE, PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
      SELECT @NROCOMPROBANTE, @COMPANIA, 'CR', CASE WHEN CUE.CUENTA IS NULL THEN 'NO CUEORDENGLOSA' ELSE CUE.CUENTA END, 
             #T.IDTERCERO,'' AS CCOSTO, 'RECUPERACION DE GLOSA DE FA '+#T.N_FACTURA, #T.VLRRECUPERAR, NULL, NULL, NULL, 
             @USUARIO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), '' AS IDAREA, '' AS PREFIJO, 1, 
             'CUEORDENGLOSACR', 'Movimiento','S', #T.N_FACTURA, DBO.FNK_FECHA_SIN_HORA(FTR.F_FACTURA), 
            DBO.FNK_FECHA_SIN_HORA(FTR.F_VENCE),'RGLO',@CNSGLO, #T.CODUNG, #T.CODPRG
      FROM #T LEFT JOIN 
            FTR ON #T.N_FACTURA = FTR.N_FACTURA LEFT JOIN
            TTEC ON TTEC.TIPO=FTR.TIPOTTEC LEFT JOIN 
            CUE ON TTEC.CUEORDENGLOSADB=CUE.CUENTA AND CUE.COMPANIA=@COMPANIA
      WHERE #T.VLRRECUPERAR<>0
      
      PRINT 'Contabilizando DB Glosas Aceptadas...' 
      IF EXISTS(SELECT *       FROM #T INNER JOIN  FTR ON #T.N_FACTURA=FTR.N_FACTURA 
              INNER JOIN  MCH ON MCH.NROCOMPROBANTE=FTR.NROCOMPROBANTE 
              LEFT JOIN   CUE ON CUE.COMPANIA=@COMPANIA AND CUE.CUENTA = DBO.FNK_VALORVARIABLE('CUENTAGLOSAACEPTADA')
                    WHERE #T.VLRACEPTADO>0 
      AND MCH.PROCESO='CXC' 
      AND MCH.PROCEDENCIA='FACTURA' 
      AND MCH.TIPO='DB' )
      BEGIN
         INSERT INTO MCHE(NROCOMPROBANTE, COMPANIA, TIPO, CUENTA, IDTERCERO, CCOSTO, DETALLE, VALOR ,REFERENCIA1,
                         REFERENCIA2, ITEMREF, USUARIO, FECHA, IDAREA, PREFIJO, ESTADO, PROCESO, GENERA,    
                         CLASECONT, N_FACTURA, F_FACTURAREF, F_VENCE, PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
         SELECT @NROCOMPROBANTE, @COMPANIA, TIPO='DB', CUENTA=ISNULL(CUE.CUENTA,'USVGS_CG.ACEPT'), MCH.IDTERCERO, MCH.CCOSTO, MCH.DETALLE, 
                VALOR=(#T.VLRACEPTADO*MCH.VALOR)/(SELECT SUM(VALOR) FROM MCH WHERE NROCOMPROBANTE=FTR.NROCOMPROBANTE AND MCH.PROCESO='CXC' AND MCH.PROCEDENCIA='FACTURA' AND TIPO='DB'),
                MCH.REFERENCIA1,MCH.REFERENCIA2, MCH.ITEMREF, @USUARIO, FECHA=DBO.FNK_FECHA_SIN_MLS(GETDATE()), MCH.IDAREA, MCH.PREFIJO, ESTADO=0, 
                PROCESO='RGLOCXCDB', MCH.GENERA, MCH.CLASECONT, MCH.N_FACTURA, MCH.F_FACTURAREF, MCH.F_VENCE, PROCEDENCIA='RGLO', REFERENCIA_PRO=@CNSGLO, 
                MCH.CODUNG, MCH.CODPRG
         FROM #T INNER JOIN  FTR ON #T.N_FACTURA=FTR.N_FACTURA 
                 INNER JOIN  MCH ON MCH.NROCOMPROBANTE=FTR.NROCOMPROBANTE 
                 LEFT JOIN   CUE ON CUE.COMPANIA=@COMPANIA AND CUE.CUENTA = DBO.FNK_VALORVARIABLE('CUENTAGLOSAACEPTADA')
         WHERE #T.VLRACEPTADO>0 
         AND MCH.PROCESO='CXC' 
         AND MCH.PROCEDENCIA='FACTURA' 
         AND MCH.TIPO='DB'
      
         PRINT 'Contabilizando CR Glosas Aceptadas...' 
         INSERT INTO MCHE(NROCOMPROBANTE, COMPANIA, TIPO, CUENTA, IDTERCERO, CCOSTO, DETALLE, VALOR ,REFERENCIA1,
                          REFERENCIA2, ITEMREF, USUARIO, FECHA, IDAREA, PREFIJO, ESTADO, PROCESO, GENERA,    
                          CLASECONT, N_FACTURA, F_FACTURAREF, F_VENCE, PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
         SELECT @NROCOMPROBANTE, @COMPANIA, TIPO='CR',COALESCE ( FTR.CUENTACXC_RAD ,FTR.CUENTACXC), MCH.IDTERCERO, MCH.CCOSTO, MCH.DETALLE, 
                 VALOR=(#T.VLRACEPTADO*MCH.VALOR)/(SELECT SUM(VALOR) FROM MCH WHERE NROCOMPROBANTE=FTR.NROCOMPROBANTE AND MCH.PROCESO='CXC' AND MCH.PROCEDENCIA='FACTURA' AND TIPO='DB'),
                 MCH.REFERENCIA1,MCH.REFERENCIA2, MCH.ITEMREF, @USUARIO, FECHA=DBO.FNK_FECHA_SIN_MLS(GETDATE()), MCH.IDAREA, MCH.PREFIJO, ESTADO=0, 
                 PROCESO='RGLOCXCCR', MCH.GENERA, MCH.CLASECONT, MCH.N_FACTURA, MCH.F_FACTURAREF, MCH.F_VENCE, PROCEDENCIA='RGLO', REFERENCIA_PRO=@CNSGLO, 
                 MCH.CODUNG, MCH.CODPRG
         FROM #T INNER JOIN
              FTR ON #T.N_FACTURA=FTR.N_FACTURA INNER JOIN
              MCH ON MCH.NROCOMPROBANTE=FTR.NROCOMPROBANTE LEFT JOIN
              CUE ON CUE.COMPANIA=@COMPANIA AND CUE.CUENTA = DBO.FNK_VALORVARIABLE('CUENTAGLOSAACEPTADA')
         WHERE #T.VLRACEPTADO>0 AND MCH.PROCESO='CXC' AND MCH.PROCEDENCIA='FACTURA' AND MCH.TIPO='DB'
      END
      ELSE
      BEGIN
         INSERT INTO MCHE(NROCOMPROBANTE, COMPANIA, TIPO, CUENTA, IDTERCERO, CCOSTO, DETALLE, VALOR ,REFERENCIA1,
             	           REFERENCIA2, ITEMREF, USUARIO, FECHA, IDAREA, PREFIJO, ESTADO, PROCESO, GENERA, 
                         CLASECONT, N_FACTURA, F_FACTURAREF, F_VENCE, PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
         SELECT @NROCOMPROBANTE, @COMPANIA, 'CR',COALESCE (TTEC.CUENTARAD,FTR.CUENTACXC_RAD),
                 #T.IDTERCERO,'' AS CCOSTO, 
                'GLOSA ACEPTDADA FA: '+#T.N_FACTURA, #T.VLRACEPTADO, NULL, NULL, NULL, 
                @USUARIO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), '' AS IDAREA, '' AS PREFIJO, 1, 
                'RGLOCXCCR', 'Movimiento','S', #T.N_FACTURA, DBO.FNK_FECHA_SIN_HORA(FTR.F_FACTURA),
                DBO.FNK_FECHA_SIN_HORA(FTR.F_VENCE),'RGLO',@CNSGLO, #T.CODUNG, #T.CODPRG
         FROM   #T,FTR INNER JOIN TTEC ON FTR.TIPOTTEC=TTEC.TIPO
         WHERE  #T.VLRACEPTADO >0 
         AND FTR.N_FACTURA=#T.N_FACTURA
      
         INSERT INTO MCHE(NROCOMPROBANTE, COMPANIA, TIPO, CUENTA, IDTERCERO, CCOSTO, DETALLE, VALOR ,REFERENCIA1,
             	           REFERENCIA2, ITEMREF, USUARIO, FECHA, IDAREA, PREFIJO, ESTADO, PROCESO, GENERA, 
                         CLASECONT, N_FACTURA, F_FACTURAREF, F_VENCE, PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
         SELECT @NROCOMPROBANTE, @COMPANIA, 'DB',TTEC.CTAGLOSADB, #T.IDTERCERO,'' AS CCOSTO, 
                'GLOSA ACEPTDADA FA:  '+#T.N_FACTURA, #T.VLRACEPTADO, NULL, NULL, NULL, 
                @USUARIO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), '' AS IDAREA, '' AS PREFIJO, 1, 
                'RGLOCXCCR', 'Movimiento','S', #T.N_FACTURA, DBO.FNK_FECHA_SIN_HORA(FTR.F_FACTURA),
                DBO.FNK_FECHA_SIN_HORA(FTR.F_VENCE),'RGLO',@CNSGLO, #T.CODUNG, #T.CODPRG
         FROM   #T,FTR INNER JOIN TTEC ON FTR.TIPOTTEC=TTEC.TIPO
         WHERE  #T.VLRACEPTADO>0 
         AND FTR.N_FACTURA=#T.N_FACTURA 
      END

   END
   ELSE
   BEGIN
      INSERT INTO MCHE(NROCOMPROBANTE, COMPANIA, TIPO, CUENTA, IDTERCERO, CCOSTO, DETALLE, VALOR ,REFERENCIA1,
             	        REFERENCIA2, ITEMREF, USUARIO, FECHA, IDAREA, PREFIJO, ESTADO, PROCESO, GENERA, 
                      CLASECONT, N_FACTURA, F_FACTURAREF, F_VENCE, PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
      SELECT @NROCOMPROBANTE, @COMPANIA, 'DB', CASE WHEN DBO.FNK_VALORVARIABLE('CONTABCXC')<>'SI' 
                                                    THEN TTEC.CUENTARAD
                                                    ELSE TTEC.CUENTALG
                                                    END,
              #T.IDTERCERO,'' AS CCOSTO, 
             'RECUPERACION DE GLOSA FA: '+#T.N_FACTURA, #T.VLRRECUPERAR, NULL, NULL, NULL, 
             @USUARIO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), '' AS IDAREA, '' AS PREFIJO, 1, 
             'REC_GLOSAS', 'Movimiento','S', #T.N_FACTURA, DBO.FNK_FECHA_SIN_HORA(FTR.F_FACTURA),
             DBO.FNK_FECHA_SIN_HORA(FTR.F_VENCE),'RGLO',@CNSGLO, #T.CODUNG, #T.CODPRG
      FROM   #T,FTR INNER JOIN TTEC ON FTR.TIPOTTEC=TTEC.TIPO
      WHERE  #T.VLRRECUPERAR>0 AND FTR.N_FACTURA=#T.N_FACTURA
      
      INSERT INTO MCHE(NROCOMPROBANTE, COMPANIA, TIPO, CUENTA, IDTERCERO, CCOSTO, DETALLE, VALOR ,REFERENCIA1,
             	        REFERENCIA2, ITEMREF, USUARIO, FECHA, IDAREA, PREFIJO, ESTADO, PROCESO, GENERA, 
                      CLASECONT, N_FACTURA, F_FACTURAREF, F_VENCE, PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
      SELECT @NROCOMPROBANTE, @COMPANIA, 'CR',TTEC.CTAGLOSADB, #T.IDTERCERO,'' AS CCOSTO, 
             'RECUPERACION DE GLOSA FA: '+#T.N_FACTURA, #T.VLRRECUPERAR, NULL, NULL, NULL, 
             @USUARIO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), '' AS IDAREA, '' AS PREFIJO, 1, 
             'REC_GLOSAS', 'Movimiento','S', #T.N_FACTURA, DBO.FNK_FECHA_SIN_HORA(FTR.F_FACTURA),
             DBO.FNK_FECHA_SIN_HORA(FTR.F_VENCE),'RGLO',@CNSGLO, #T.CODUNG, #T.CODPRG
      FROM   #T,FTR INNER JOIN TTEC ON FTR.TIPOTTEC=TTEC.TIPO
      WHERE  #T.VLRRECUPERAR>0 AND FTR.N_FACTURA=#T.N_FACTURA      
      
   END
   
   EXEC SPK_NC_REVISAMCPE @NROCOMPROBANTE, @COMPANIA, @USUARIO, @SEDE, @SYS_COMPUTERNAME

   IF EXISTS(SELECT * FROM MCP WHERE NROCOMPROBANTE=@NROCOMPROBANTE)
   BEGIN
      IF EXISTS(SELECT * FROM MCPE WHERE NROCOMPROBANTE=@NROCOMPROBANTE)
      BEGIN
         DELETE MCHE WHERE NROCOMPROBANTE = @NROCOMPROBANTE
         DELETE MCPE WHERE NROCOMPROBANTE = @NROCOMPROBANTE 
      END
   END   
   DROP TABLE #T
END
