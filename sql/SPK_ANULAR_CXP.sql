IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='SPK_ANULAR_CXP' AND XTYPE='P')
BEGIN
 DROP PROCEDURE SPK_ANULAR_CXP
END

GO
CREATE PROCEDURE DBO.SPK_ANULAR_CXP
	@CNSFCXP VARCHAR(20),
	@COMPANIA VARCHAR(2),
	@SEDE VARCHAR(5)
WITH ENCRYPTION
AS
DECLARE @CNSFCOM VARCHAR(20)
DECLARE @PROCEDENCIA VARCHAR(10)
DECLARE @IDCLASEIMP VARCHAR(2)
DECLARE @IDCATEGORIA VARCHAR(10)
DECLARE @NROREFERENCIA VARCHAR(16)
BEGIN
   SELECT @IDCLASEIMP=IDCLASEIMP FROM FCXP WHERE CNSFCXP=@CNSFCXP
   SELECT @PROCEDENCIA=PROCEDENCIA,@NROREFERENCIA=NOREFERENCIA,@CNSFCOM=CNSFCOM FROM FCXP WHERE CNSFCXP=@CNSFCXP
   UPDATE FCXP SET ESTADO='A' WHERE CNSFCXP=@CNSFCXP
   UPDATE FCXPD SET ESTADO='A' WHERE CNSFCXP=@CNSFCXP
   PRINT @PROCEDENCIA
   IF @PROCEDENCIA='Salud'
   BEGIN
      PRINT 'Afectando Salud...'
      UPDATE FXPD SET ESTADO='P' 
      FROM FCXPD 
      WHERE FCXPD.CNSFCXP=@CNSFCXP AND FXPD.N_PRESUP=FCXPD.N_PRESUP AND FXPD.ITEM=FCXPD.ITEM_PRESUP
      UPDATE FXP SET ESTADO='P' WHERE (SELECT COUNT(*) FROM FXPD WHERE FXPD.N_PRESUP=FXP.N_PRESUP AND ESTADO<>'P')=0
   END
   ELSE
   IF @PROCEDENCIA='Compras' 
   BEGIN
      PRINT 'Afectando Compras...'
      UPDATE IMOVH SET ENCXP=0 
      FROM FCXPD 
      WHERE IMOVH.CNSMOV=FCXPD.N_PRESUP AND IMOVH.IDARTICULO=FCXPD.IDSERVICIO AND IMOVH.NOLOTE=FCXPD.NOLOTE AND
            FCXPD.CNSFCXP=@CNSFCXP
   END
   ELSE
   IF @PROCEDENCIA='Servicios'
   BEGIN
      PRINT 'Afectando Servicios...'
      UPDATE FCOM SET ENCXP=0,ESTADO='P' WHERE CNSFCOM=@CNSFCOM
   END
   IF @PROCEDENCIA='Anticipos'
   BEGIN
      PRINT 'Afectando Servicios...'
      UPDATE ANT SET ESTADO='I' WHERE CNSFCOM=@CNSFCOM AND NOREFERENCIA=@NROREFERENCIA
   END
   SET @IDCATEGORIA=(SELECT DBO.FNK_VALORVARIABLE('TERCATPROVEEDOR'))
   EXEC SPK_IMPUESTOS_CXP @CNSFCXP,@IDCATEGORIA,@COMPANIA,@SEDE
END
