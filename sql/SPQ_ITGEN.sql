CREATE OR ALTER PROCEDURE DBO.SPQ_ITGEN
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @PARAMETROS NVARCHAR(MAX), @MODELO         VARCHAR(100),   @METODO         VARCHAR(100)
DECLARE  @USUARIO    VARCHAR(20),   @IDTGENERICO	VARCHAR(20),	@DESCRIPCION	VARCHAR(100)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDTGENERICO = IDTGENERICO, @DESCRIPCION = DESCRIPCION
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				IDTGENERICO VARCHAR(20)  '$.IDTGENERICO', DESCRIPCION VARCHAR(100)  '$.DESCRIPCION'
			)

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'EL TIPO DE GENERICO YA EXISTE'
			WHERE EXISTS (SELECT * FROM ITGEN WHERE IDTGENERICO = @IDTGENERICO)

			IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
			BEGIN
				INSERT INTO ITGEN (IDTGENERICO ,DESCRIPCION )
				SELECT @IDTGENERICO, @DESCRIPCION
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ACTUALIZAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDTGENERICO = IDTGENERICO, @DESCRIPCION = DESCRIPCION 
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				IDTGENERICO VARCHAR(20)  '$.IDTGENERICO', DESCRIPCION VARCHAR(100)  '$.DESCRIPCION'
			)

			UPDATE ITGEN SET DESCRIPCION = @DESCRIPCION WHERE IDTGENERICO = @IDTGENERICO			
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
	
	IF @METODO = 'ELIMINAR'
	BEGIN
		BEGIN TRY
			SELECT @IDTGENERICO = JSON_VALUE(@PARAMETROS, '$.IDTGENERICO')

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'EL TIPO DE GENERICO TIENE GENERICOS RELACIONADOS (IGEN)'
			WHERE EXISTS (SELECT * FROM IGEN WHERE IDTGENERICO = @IDTGENERICO)

			IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
			BEGIN
				DELETE FROM ITGEN WHERE IDTGENERICO = @IDTGENERICO
			END		
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
END
