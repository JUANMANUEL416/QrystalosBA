CREATE OR ALTER PROCEDURE DBO.SPQ_ABRIR_NOMI @CNSPAGO VARCHAR(20)
	WITH ENCRYPTION
AS
DECLARE @NUMDOCUMENTO VARCHAR(20)
DECLARE @IDTRANSACCION VARCHAR(6)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	BEGIN TRY
		UPDATE PRSD
		SET ESTADO = 'PorPagar', CNSPAGO = @CNSPAGO, ITEM_NIEPED = NIEPED.ITEM
		FROM NIEPE
		INNER JOIN NIEPED ON NIEPE.CNSNIEPE = NIEPED.CNSNIEPE AND NIEPE.NUMDOC = NIEPED.NUMDOC
		WHERE NIEPE.CNSPAGO = @CNSPAGO AND PRSD.IDTRANSACCION = NIEPED.IDTRANSPRESTAMO AND PRSD.NUMDOCUMENTO = NIEPED.NUMDOCPRESTAMO AND PRSD.NUMCUOTA = NIEPED.
			NUMCUOTA

		UPDATE PRS
		SET ESTADO = (
				CASE 
					WHEN VLRPRESTAMO - P.VLRPAGADO <= 0
						THEN 'Pagada'
					ELSE 'PorPagar'
					END
				), VLRSALDO = VLRPRESTAMO - P.VLRPAGADO
		FROM PRS
		INNER JOIN (
			SELECT PRSD.IDTRANSACCION, PRSD.NUMDOCUMENTO, SUM(PRSD.VLRCUOTA - PRSD.VLRINTERESES) AS VLRPAGADO
			FROM PRS
			INNER JOIN PRSD ON PRS.IDTRANSACCION = PRSD.IDTRANSACCION AND PRS.NUMDOCUMENTO = PRSD.NUMDOCUMENTO
			INNER JOIN NIEPED ON PRSD.ESTADO = 'Pagada' AND PRSD.IDTRANSACCION = NIEPED.IDTRANSPRESTAMO AND PRSD.NUMDOCUMENTO = NIEPED.NUMDOCPRESTAMO AND PRSD.
				NUMCUOTA = NIEPED.NUMCUOTA
			INNER JOIN NIEPE ON NIEPE.CNSPAGO = @CNSPAGO AND NIEPE.CNSNIEPE = NIEPED.CNSNIEPE AND NIEPE.NUMDOC = PRS.IDDEUDOR
			GROUP BY PRSD.IDTRANSACCION, PRSD.NUMDOCUMENTO
			) AS P ON PRS.IDTRANSACCION = P.IDTRANSACCION AND PRS.NUMDOCUMENTO = P.NUMDOCUMENTO

		PRINT 'QUITANDO LA NOMINA DE CONTABILIDAD'

		IF (
				SELECT COUNT(*)
				FROM MCHE
				INNER JOIN NIEPE ON MCHE.NROCOMPROBANTE = NIEPE.NROCOMPROBANTE
				WHERE NIEPE.CNSPAGO = @CNSPAGO
				) > 0
		BEGIN
			DELETE MCHE
			FROM MCHE
			INNER JOIN NIEPE ON MCHE.NROCOMPROBANTE = NIEPE.NROCOMPROBANTE
			WHERE NIEPE.CNSPAGO = @CNSPAGO

			DELETE MCPE
			FROM MCPE
			INNER JOIN NIEPE ON MCPE.NROCOMPROBANTE = NIEPE.NROCOMPROBANTE
			WHERE NIEPE.CNSPAGO = @CNSPAGO
		END

		IF EXISTS (
				SELECT *
				FROM MCP
				INNER JOIN NIEPE ON MCP.NROCOMPROBANTE = NIEPE.NROCOMPROBANTE
				WHERE NIEPE.CNSPAGO = @CNSPAGO
				)
		BEGIN
			UPDATE MCP
			SET ESTADO = 0, ANULADO = 1
			FROM MCP
			INNER JOIN NIEPE ON MCP.NROCOMPROBANTE = NIEPE.NROCOMPROBANTE
			WHERE NIEPE.CNSPAGO = @CNSPAGO

			UPDATE MCH
			SET ESTADO = 0
			FROM MCH
			INNER JOIN NIEPE ON MCH.NROCOMPROBANTE = NIEPE.NROCOMPROBANTE
			WHERE NIEPE.CNSPAGO = @CNSPAGO

			DELETE MCH
			FROM MCH
			INNER JOIN NIEPE ON MCH.NROCOMPROBANTE = NIEPE.NROCOMPROBANTE
			WHERE NIEPE.CNSPAGO = @CNSPAGO

			DELETE MCP
			FROM MCP
			INNER JOIN NIEPE ON MCP.NROCOMPROBANTE = NIEPE.NROCOMPROBANTE
			WHERE NIEPE.CNSPAGO = @CNSPAGO
		END

		PRINT 'QUITANDO DE CXP'

		DELETE FCXPD
		FROM FCXPD
		INNER JOIN FCXP ON FCXPD.CNSFCXP = FCXP.CNSFCXP
		LEFT JOIN FCXPP ON FCXP.CNSFCXP = FCXPP.CNSFCXP
		WHERE FCXP.PROCEDENCIA = 'Nomina' AND FCXP.NOREFERENCIA = @CNSPAGO AND FCXPP.CNSFCXP IS NULL

		DELETE FCXP
		FROM FCXP
		LEFT JOIN FCXPP ON FCXP.CNSFCXP = FCXPP.CNSFCXP
		LEFT JOIN FCXPDBCR ON FCXP.CNSFCXP = FCXPDBCR.CNSFCXP
		WHERE FCXP.PROCEDENCIA = 'Nomina' AND FCXP.NOREFERENCIA = @CNSPAGO AND FCXPP.CNSFCXP IS NULL AND FCXPDBCR.CNSFCXP IS NULL


		UPDATE FCXP
		SET ESTADO = 'A'
		FROM FCXP
		INNER JOIN FCXPP ON FCXP.CNSFCXP = FCXPP.CNSFCXP
		WHERE FCXP.PROCEDENCIA = 'Nomina' AND FCXP.NOREFERENCIA = @CNSPAGO AND FCXPP.ESTADO = 'A'
        
		UPDATE FCXP
		SET ESTADO = 'A'
		FROM FCXP
		INNER JOIN FCXPDBCR ON FCXP.CNSFCXP = FCXPDBCR.CNSFCXP
		WHERE FCXP.PROCEDENCIA = 'Nomina' AND FCXP.NOREFERENCIA = @CNSPAGO AND FCXPDBCR.ESTADO = 'A'

		UPDATE NPER
		SET CERRADO = 0, GENERADO = 1, CONTABILIZADA = 0
		WHERE CNSPAGO = @CNSPAGO

		UPDATE NIEPE
		SET CERRADO = 0, CONTABILIZADA = 0, NROCOMPROBANTE = NULL, NOREFERENCIA = NULL
		WHERE CNSPAGO = @CNSPAGO

		UPDATE NIEPED
		SET CONTABILIZADA = 0, NROCOMPROBANTE = NULL, NOREFERENCIA = NULL
		WHERE EXISTS (
				SELECT *
				FROM NIEPE
				WHERE NIEPE.CNSNIEPE = NIEPED.CNSNIEPE AND NIEPE.NUMDOC = NIEPED.NUMDOC AND NIEPE.CNSPAGO = @CNSPAGO
				)
	END TRY

	BEGIN CATCH
		INSERT INTO @TBLERRORES (ERROR)
		SELECT ERROR_MESSAGE()
	END CATCH

	IF (
			SELECT COUNT(*)
			FROM @TBLERRORES
			) > 0
	BEGIN
		SELECT 'KO' OK

		SELECT ERROR
		FROM @TBLERRORES

		RETURN
	END

	SELECT 'OK' OK
END
