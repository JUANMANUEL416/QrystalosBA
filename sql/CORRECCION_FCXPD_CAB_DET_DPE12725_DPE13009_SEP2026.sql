/*
  CEM — Cabecera = detalle. Septiembre 2026.

  03CM002376 DPE12725:
    Encabezado neto 87.231.344 cuadra con IMOV 0300028179 y con cant×valor.
    Cada línea FCXPD trae VLR_NETO inflado (mismo neto repetido por artículo/lote).
    → VLR_NETO línea = cant×valor + IVA línea (sin IVA hoy).

  03CM002438 DPE13009:
    Encabezado 137.426.600; detalle suma 137.426.599,80 (línea 2 MX917-1 −0,20 vs IMOVH).
    → Ajuste neto línea 2 a 11.846.600,00 (6000 × 1974,433333…).

  Pre: N, sin contabilizar, sin comprobante, CUECREDITO 22050101, SALDO = neto cab.
  No contabiliza. Ejecutar bloque completo.
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;

BEGIN TRAN;

IF NOT EXISTS (
  SELECT 1 FROM dbo.FCXP
  WHERE CNSFCXP = N'03CM002376' AND NOREFERENCIA = N'DPE12725'
    AND ESTADO = N'N' AND COALESCE(CONTABILIZADA, 0) = 0
    AND COALESCE(NROCOMPROBANTE, N'') = N''
    AND ABS(VLR_NETO - 87231344.00) < 0.02
)
BEGIN
  ROLLBACK TRAN;
  THROW 55501, '03CM002376 DPE12725 no esta libre o neto cab distinto de 87231344.', 1;
END;

IF ABS(
  (SELECT SUM(VLR_NETO) FROM dbo.FCXPD WHERE CNSFCXP = N'03CM002376')
  - 87231344.00
) < 1
BEGIN
  ROLLBACK TRAN;
  THROW 55502, '03CM002376: detalle ya cuadra con cabecera; no aplica correccion de neto duplicado.', 1;
END;

IF (SELECT COUNT(*) FROM dbo.FCXPD WHERE CNSFCXP = N'03CM002376') <> 9
BEGIN
  ROLLBACK TRAN;
  THROW 55503, '03CM002376: se esperaban 9 lineas.', 1;
END;

IF NOT EXISTS (
  SELECT 1 FROM dbo.FCXP
  WHERE CNSFCXP = N'03CM002438' AND NOREFERENCIA = N'DPE13009'
    AND ESTADO = N'N' AND COALESCE(CONTABILIZADA, 0) = 0
    AND COALESCE(NROCOMPROBANTE, N'') = N''
    AND ABS(VLR_NETO - 137426600.00) < 0.02
)
BEGIN
  ROLLBACK TRAN;
  THROW 55504, '03CM002438 DPE13009 no esta libre o neto cab distinto de 137426600.', 1;
END;

UPDATE dbo.FCXPD
SET VLR_NETO = CONVERT(decimal(18, 2),
      D.CANTIDAD * D.VALOR + COALESCE(D.VLR_IVA, 0) - ISNULL(D.VLR_DESCUENTO, 0))
FROM dbo.FCXPD D
WHERE D.CNSFCXP = N'03CM002376';

UPDATE dbo.FCXPD
SET VLR_NETO = 11846600.00
WHERE CNSFCXP = N'03CM002438'
  AND ITEM = 2
  AND IDSERVICIO = N'MX917-1'
  AND ABS(VLR_NETO - 11846599.80) < 0.05;

DECLARE @NET376 decimal(18, 2) = (SELECT SUM(VLR_NETO) FROM dbo.FCXPD WHERE CNSFCXP = N'03CM002376');
DECLARE @NET438 decimal(18, 2) = (SELECT SUM(VLR_NETO) FROM dbo.FCXPD WHERE CNSFCXP = N'03CM002438');

IF ABS(@NET376 - 87231344.00) > 0.05
BEGIN
  ROLLBACK TRAN;
  THROW 55505, '03CM002376: suma detalle no cuadra con IMOV/cabecera.', 1;
END;

IF ABS(@NET438 - 137426600.00) > 0.05
BEGIN
  ROLLBACK TRAN;
  THROW 55506, '03CM002438: suma detalle no cuadra con cabecera.', 1;
END;

UPDATE dbo.FCXP
SET VLR_IVA = X.IVA,
    VLR_NETO = X.NETO,
    SALDO = X.NETO
FROM dbo.FCXP P
INNER JOIN (
  SELECT CNSFCXP,
         CONVERT(decimal(18, 2), SUM(COALESCE(VLR_IVA, 0))) AS IVA,
         CONVERT(decimal(18, 2), SUM(VLR_NETO)) AS NETO
  FROM dbo.FCXPD
  WHERE CNSFCXP IN (N'03CM002376', N'03CM002438')
  GROUP BY CNSFCXP
) X ON X.CNSFCXP = P.CNSFCXP;

IF EXISTS (
  SELECT 1
  FROM dbo.FCXP P
  INNER JOIN (
    SELECT CNSFCXP, SUM(VLR_NETO) AS SN FROM dbo.FCXPD
    WHERE CNSFCXP IN (N'03CM002376', N'03CM002438')
    GROUP BY CNSFCXP
  ) D ON D.CNSFCXP = P.CNSFCXP
  WHERE ABS(P.VLR_NETO - D.SN) > 0.01
)
BEGIN
  ROLLBACK TRAN;
  THROW 55507, 'Cabecera y detalle siguen distintos.', 1;
END;

COMMIT TRAN;

SELECT P.CNSFCXP, P.NOREFERENCIA,
  CONVERT(decimal(18, 2), P.VLR_NETO) NETO_CAB,
  CONVERT(decimal(18, 2), SUM(D.VLR_NETO)) NETO_DET,
  CONVERT(decimal(18, 2), P.VLR_NETO - SUM(D.VLR_NETO)) DIF
FROM dbo.FCXP P
JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
WHERE P.CNSFCXP IN (N'03CM002376', N'03CM002438')
GROUP BY P.CNSFCXP, P.NOREFERENCIA, P.VLR_NETO;

SELECT CNSFCXP, ITEM, IDSERVICIO, CANTIDAD, VALOR, VLR_NETO
FROM dbo.FCXPD
WHERE CNSFCXP IN (N'03CM002376', N'03CM002438')
ORDER BY CNSFCXP, ITEM;
