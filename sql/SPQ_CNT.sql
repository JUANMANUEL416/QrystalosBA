CREATE OR ALTER PROCEDURE DBO.SPQ_CNT @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @DATOS NVARCHAR(MAX)
DECLARE @USUARIO VARCHAR(20), @PROCESO VARCHAR(20)
DECLARE @IDSEDEU VARCHAR(5), @SYS_COMPUTERNAME VARCHAR(254)
DECLARE @IDPLAN VARCHAR(6), @IDCONTRATO VARCHAR(20), @IDALTERNA VARCHAR(20), @IDTERCERO VARCHAR(20), @TIPOCONTRATO VARCHAR(1), @FECHAINICIAL DATETIME, @FECHAFINAL 
	DATETIME, @VALORCONTRATO DECIMAL(14, 2), @ESTADO VARCHAR(12), @CCOSTO VARCHAR(20), @NOPOLIZA VARCHAR(20), @TIPORESTA VARCHAR(1), @MODALIDAD VARCHAR(2), 
	@DESCRIPCION VARCHAR(100), @CLASE VARCHAR(1), @FACTOR DECIMAL(14,2)
	,@VALORADMIN DECIMAL(14,2)
	,@NVOCONSEC VARCHAR(20)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
	FROM USUSU
	WHERE USUARIO = @USUARIO
	
	SELECT @IDSEDEU = IDSEDE
	FROM UBEQ
	WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	IF @METODO = 'GUARDAR'
	BEGIN


		BEGIN TRY
			SELECT @IDCONTRATO = IDCONTRATO, @IDALTERNA = IDALTERNA, @IDTERCERO = IDTERCERO, @TIPOCONTRATO = TIPOCONTRATO, @FECHAINICIAL = FECHAINICIAL, @FECHAFINAL = 
				FECHAFINAL, @VALORCONTRATO = VALORCONTRATO, @ESTADO = ESTADO, @IDPLAN = IDPLAN, @CCOSTO = CCOSTO, @NOPOLIZA = NOPOLIZA, @TIPORESTA = TIPORESTA, 
				@MODALIDAD = MODALIDAD, @DESCRIPCION = DESCRIPCION, @CLASE = CLASE, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					IDCONTRATO VARCHAR(20) '$.IDCONTRATO', IDALTERNA VARCHAR(20) '$.IDALTERNA', IDTERCERO VARCHAR(20) '$.IDTERCERO', TIPOCONTRATO VARCHAR(1) 
					'$.TIPOCONTRATO', FECHAINICIAL DATETIME '$.FECHAINICIAL', FECHAFINAL DATETIME '$.FECHAFINAL', 
					VALORCONTRATO DECIMAL(14, 2) '$.VALORCONTRATO', ESTADO VARCHAR(12) '$.ESTADO', IDPLAN VARCHAR(6) '$.IDPLAN', CCOSTO VARCHAR(20) '$.CCOSTO', 
					NOPOLIZA VARCHAR(20) '$.NOPOLIZA', TIPORESTA VARCHAR(1) '$.TIPORESTA', MODALIDAD VARCHAR(2) '$.MODALIDAD', DESCRIPCION VARCHAR(100) 
					'$.DESCRIPCION', CLASE VARCHAR(1) '$.CLASE', PROCESO VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDEU, @PREFIJO = '@CNT', @LONGITUD = 8, @NVOCONSEC = @IDCONTRATO OUTPUT

					INSERT INTO CNT (
						IDCONTRATO, IDALTERNA, IDTERCERO, TIPOCONTRATO, FECHAINICIAL, FECHAFINAL, VALORCONTRATO, ESTADO, IDPLAN, CCOSTO, NOPOLIZA, TIPORESTA, 
						MODALIDAD, DESCRIPCION, VALORBASE, VALORUPC, VALORPAB, VALORSALUD, VALORADMIN, NAFILIADOS, FACTOR, BLOQUEARMORAMA, DIASVENCIMIENTO, CLASE
						, VLRUTILIZADO, CIUDAD, ARSTIPOCONTRATO, TIPOACTOADVO, NOACTOADVO, DURACION, TIPOPLAN, MODALIDADSER, VERIFHABILITACION, VIGENCIACARNET, 
						TIPOCONTRATOIPS, PUPC, TIPOCONTRATOARS, PLANCOBROGEN, NIVEL1, NIVEL2, NIVEL3, NIVEL4, PYP, CONTROLPOR, USUARIO, FCREACION, 
						SYS_COMPUTERNAME
						)
					SELECT @IDCONTRATO, @IDALTERNA, @IDTERCERO, @TIPOCONTRATO, @FECHAINICIAL, @FECHAFINAL, @VALORCONTRATO, @ESTADO, @IDPLAN, @CCOSTO, @NOPOLIZA, 
						@TIPORESTA, @MODALIDAD, @DESCRIPCION, 0, 0, 0, 0, 0, 0, 0, 0, 0, @CLASE, 0, '', 'Continuidad', 'N', '', 0, 'NA', 'NA', 'NA', 'NA', 'NA', 0, 'Contrato', 
						0, 0, 0, 0, 0, '', 0, @USUARIO, GETDATE(), @SYS_COMPUTERNAME
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @IDCONTRATO = IDCONTRATO
					FROM OPENJSON(@PARAMETROS) WITH (IDCONTRATO VARCHAR(20) '$.IDCONTRATO')

					UPDATE CNT
					SET IDALTERNA = @IDALTERNA, IDTERCERO = @IDTERCERO, TIPOCONTRATO = @TIPOCONTRATO, FECHAINICIAL = @FECHAINICIAL, FECHAFINAL = @FECHAFINAL, 
						VALORCONTRATO = @VALORCONTRATO, ESTADO = @ESTADO, IDPLAN = @IDPLAN, CCOSTO = @CCOSTO, NOPOLIZA = @NOPOLIZA, TIPORESTA = @TIPORESTA, MODALIDAD = 
						@MODALIDAD, DESCRIPCION = @DESCRIPCION
					WHERE IDCONTRATO = @IDCONTRATO
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' AS OK, @IDCONTRATO AS IDCONTRATO
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @IDCONTRATO = IDCONTRATO
		FROM OPENJSON(@PARAMETROS) WITH (IDCONTRATO VARCHAR(20) '$.IDCONTRATO')

		BEGIN TRY
			DELETE
			FROM CNT
			WHERE IDCONTRATO = @IDCONTRATO
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ACTIVAR'
	BEGIN
		BEGIN TRY

			SELECT @IDCONTRATO = JSON_VALUE(@PARAMETROS, '$.IDCONTRATO')

			UPDATE CNT SET ESTADO = 'Activo' WHERE IDCONTRATO = @IDCONTRATO

			EXEC SPQ_GENSEQUENCE @SEDE = '01', @PREFIJO = '@LOG', @EXTRA = '', @DEFAULT = 8, @NVOCONSEC = @NVOCONSEC OUTPUT
			
			INSERT INTO USLOG (CNSLOG, COMPANIA, NOADMISION, PROCESO, REQUEST, REFERENCIA, USUARIO, FECHA, SYS_ComputerName) 
			SELECT @NVOCONSEC, '01', @IDCONTRATO, 'CONTRATOS', 'ACTIVAR',CONCAT('CNT.IDCONTRATO = ', @IDCONTRATO), @USUARIO, GETDATE(), @SYS_COMPUTERNAME

			INSERT INTO USLOGH (CNSLOG ,ITEM ,CAMPO ,VALORANT ,VALORNVO )   
			SELECT @NVOCONSEC, 1, 'ESTADO', 'Inactivo', 'Activo'

		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'SUSPENDER'
	BEGIN
		BEGIN TRY

			SELECT @IDCONTRATO = JSON_VALUE(@PARAMETROS, '$.IDCONTRATO')

			UPDATE CNT SET ESTADO = 'Suspendido' WHERE IDCONTRATO = @IDCONTRATO

			EXEC SPQ_GENSEQUENCE @SEDE = '01', @PREFIJO = '@LOG', @EXTRA = '', @DEFAULT = 8, @NVOCONSEC = @NVOCONSEC OUTPUT
			
			INSERT INTO USLOG (CNSLOG, COMPANIA, NOADMISION, PROCESO, REQUEST, REFERENCIA, USUARIO, FECHA, SYS_ComputerName) 
			SELECT @NVOCONSEC, '01', @IDCONTRATO, 'CONTRATOS', 'SUSPENDER',CONCAT('CNT.IDCONTRATO = ', @IDCONTRATO), @USUARIO, GETDATE(), @SYS_COMPUTERNAME

			INSERT INTO USLOGH (CNSLOG ,ITEM ,CAMPO ,VALORANT ,VALORNVO )   
			SELECT @NVOCONSEC, 1, 'ESTADO', 'Inactivo', 'Suspendido'

		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'FINALIZAR'
	BEGIN
		BEGIN TRY

			SELECT @IDCONTRATO = JSON_VALUE(@PARAMETROS, '$.IDCONTRATO')

			UPDATE CNT SET ESTADO = 'Liquidado' WHERE IDCONTRATO = @IDCONTRATO

			EXEC SPQ_GENSEQUENCE @SEDE = '01', @PREFIJO = '@LOG', @EXTRA = '', @DEFAULT = 8, @NVOCONSEC = @NVOCONSEC OUTPUT
			
			INSERT INTO USLOG (CNSLOG, COMPANIA, NOADMISION, PROCESO, REQUEST, REFERENCIA, USUARIO, FECHA, SYS_ComputerName) 
			SELECT @NVOCONSEC, '01', @IDCONTRATO, 'CONTRATOS', 'FINALIZAR',CONCAT('CNT.IDCONTRATO = ', @IDCONTRATO), @USUARIO, GETDATE(), @SYS_COMPUTERNAME

			INSERT INTO USLOGH (CNSLOG ,ITEM ,CAMPO ,VALORANT ,VALORNVO )   
			SELECT @NVOCONSEC, 1, 'ESTADO', 'Activo', 'Liquidado'

		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GUARDAR_CNT'
	BEGIN

		BEGIN TRY

			SELECT @IDCONTRATO = JSON_VALUE(@PARAMETROS, '$.IDCONTRATO')

			IF COALESCE(@IDCONTRATO,'') <> ''
			BEGIN -- EDITANDO
				UPDATE CNT
					SET IDALTERNA = JSON_VALUE(@PARAMETROS, '$.IDALTERNA')
						, IDTERCERO = JSON_VALUE(@PARAMETROS, '$.TER.IDTERCERO')
						, TIPOCONTRATO = JSON_VALUE(@PARAMETROS, '$.TIPOCONTRATO')
						, FECHAINICIAL = TRY_CONVERT(DATETIME, JSON_VALUE(@PARAMETROS, '$.FECHAINICIAL'))
						, FECHAFINAL = TRY_CONVERT(DATETIME, JSON_VALUE(@PARAMETROS, '$.FECHAFINAL'))
						, VALORCONTRATO = JSON_VALUE(@PARAMETROS, '$.VALORCONTRATO')
						, ESTADO = JSON_VALUE(@PARAMETROS, '$.ESTADO')
						, IDPLAN = JSON_VALUE(@PARAMETROS, '$.PLN.IDPLAN')
						, CCOSTO = JSON_VALUE(@PARAMETROS, '$.CEN.CCOSTO')
						, TIPORESTA = JSON_VALUE(@PARAMETROS, '$.TIPORESTA')
						, MODALIDAD = JSON_VALUE(@PARAMETROS, '$.MODALIDAD')
						, DESCRIPCION = JSON_VALUE(@PARAMETROS, '$.DESCRIPCION')
						, VALORADMIN = JSON_VALUE(@PARAMETROS, '$.VALORADMIN')
						, FACTOR= JSON_VALUE(@PARAMETROS, '$.FACTOR')
						, NAFILIADOS = JSON_VALUE(@PARAMETROS, '$.NAFILIADOS')
						, IDTARIFA = JSON_VALUE(@PARAMETROS, '$.TAR.IDTARIFA')
						, CONTROLPOR = JSON_VALUE(@PARAMETROS, '$.CONTROLPOR')
						, TIPOPLAN = JSON_VALUE(@PARAMETROS, '$.TIPOPLAN')
					WHERE IDCONTRATO = @IDCONTRATO

			END
			ELSE
			BEGIN

				EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDEU, @PREFIJO = '@CNT', @LONGITUD = 8, @NVOCONSEC = @IDCONTRATO OUTPUT

				INSERT INTO CNT (
					IDCONTRATO, IDALTERNA, IDTERCERO, TIPOCONTRATO, FECHAINICIAL, FECHAFINAL, VALORCONTRATO, ESTADO, IDPLAN, CCOSTO, TIPORESTA, 
					MODALIDAD, DESCRIPCION, VALORBASE, VALORUPC, VALORPAB, VALORSALUD, VALORADMIN, NAFILIADOS, FACTOR, BLOQUEARMORAMA, DIASVENCIMIENTO, CLASE
					, VLRUTILIZADO, CIUDAD, ARSTIPOCONTRATO, TIPOACTOADVO, NOACTOADVO, DURACION, TIPOPLAN, MODALIDADSER, VERIFHABILITACION, VIGENCIACARNET, 
					TIPOCONTRATOIPS, PUPC, TIPOCONTRATOARS, PLANCOBROGEN, NIVEL1, NIVEL2, NIVEL3, NIVEL4, PYP, IDTARIFA, CONTROLPOR, USUARIO, FCREACION, 
					SYS_COMPUTERNAME
					)
				SELECT @IDCONTRATO AS IDCONTRATO
					, IDALTERNA = JSON_VALUE(@PARAMETROS, '$.IDALTERNA')
					, IDTERCERO = JSON_VALUE(@PARAMETROS, '$.TER.IDTERCERO')
					, TIPOCONTRATO = JSON_VALUE(@PARAMETROS, '$.TIPOCONTRATO')
					, FECHAINICIAL = TRY_CONVERT(DATETIME, JSON_VALUE(@PARAMETROS, '$.FECHAINICIAL'))
					, FECHAFINAL = TRY_CONVERT(DATETIME, JSON_VALUE(@PARAMETROS, '$.FECHAFINAL'))
					, VALORCONTRATO = JSON_VALUE(@PARAMETROS, '$.VALORCONTRATO')
					, ESTADO = JSON_VALUE(@PARAMETROS, '$.ESTADO')
					, IDPLAN = JSON_VALUE(@PARAMETROS, '$.PLN.IDPLAN')
					, CCOSTO = JSON_VALUE(@PARAMETROS, '$.CEN.CCOSTO')
					, TIPORESTA = JSON_VALUE(@PARAMETROS, '$.TIPORESTA')
					, MODALIDAD = JSON_VALUE(@PARAMETROS, '$.MODALIDAD')
					, DESCRIPCION = JSON_VALUE(@PARAMETROS, '$.DESCRIPCION')
					, VALORBASE = 0
					, VALORUPC = 0
					, VALORPAB = 0
					, VALORSALUD = 0
					, VALORADMIN = COALESCE(JSON_VALUE(@PARAMETROS, '$.VALORADMIN'), 0)
					, NAFILIADOS = COALESCE(JSON_VALUE(@PARAMETROS, '$.NAFILIADOS'), 0)
					, FACTOR = COALESCE(JSON_VALUE(@PARAMETROS, '$.FACTOR'), 0)
					, BLOQUEARMORAMA = 0
					, DIASVENCIMIENTO = 0
					, CLASE = JSON_VALUE(@PARAMETROS, '$.CLASE')
					, VLRUTILIZADO = 0
					, CIUDAD = ''
					, ARSTIPOCONTRATO = 'Continuidad'
					, TIPOACTOADVO = 'N'
					, NOACTOADVO = ''
					, DURACION = 0
					, TIPOPLAN = JSON_VALUE(@PARAMETROS, '$.TIPOPLAN')
					, MODALIDADSER = 'NA'
					, VERIFHABILITACION = 'N'
					, VIGENCIACARNET = 'NA'
					, TIPOCONTRATOIPS = 'NA'
					, PUPC = 0
					, TIPOCONTRATOARS = 'NA'
					, PLANCOBROGEN = 0
					, NIVEL1 = 0
					, NIVEL2 = 0
					, NIVEL3 = 0
					, NIVEL4 = 0
					, PYP = 0
					, IDTARIFA = JSON_VALUE(@PARAMETROS, '$.TAR.IDTARIFA')
					, CONTROLPOR = JSON_VALUE(@PARAMETROS, '$.CONTROLPOR')
					, USUARIO = @USUARIO
					, FCREACION = GETDATE()
					, SYS_COMPUTERNAME = @SYS_COMPUTERNAME
			END

		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK, @IDCONTRATO AS IDCONTRATO
	END
END
