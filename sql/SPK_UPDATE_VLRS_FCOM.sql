IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='SPK_UPDATE_VLRS_FCOM' AND XTYPE='P')
BEGIN
 DROP PROCEDURE SPK_UPDATE_VLRS_FCOM
END

GO
CREATE PROCEDURE DBO.SPK_UPDATE_VLRS_FCOM
	@CNSFCOM	VARCHAR(20)
WITH ENCRYPTION
/* ESTADO
   C=CARGADO
   A=ANULADO
   I=CONFIRMADO EN INVENTARIO
   E=PENDIENTE EN INVENTARIO
   P=PENDIENTE O PEDIDO EN COMPRAS
*/
AS
DECLARE @TIENEIVA BIT --VLR_UNITARIO
BEGIN
   UPDATE FCOMD SET VR_UNITMASIVA = CASE WHEN FCOMD.TIENEIVA=1 THEN ROUND( (VLR_UNITARIO-(ISNULL(VR_DESCUENTO,0)/CANTIDAD)) * (1+(FACTORIVA/100)),2) ELSE
                                         ROUND( (VLR_UNITARIO-(ISNULL(VR_DESCUENTO,0)/CANTIDAD)),2)
                                    END,
                     VR_ANTESIVA   = CASE WHEN FCOMD.TIENEIVA=1 THEN ROUND(VLR_UNITARIO * CANTIDAD ,2) ELSE  ROUND(VLR_UNITARIO * CANTIDAD,2) END,
                     IVA           = CASE WHEN FCOMD.TIENEIVA=1 THEN ROUND( (VR_ANTESIVA - ISNULL(VR_DESCUENTO,0)) * (FACTORIVA/100) ,2) ELSE 0 END
                    ,VR_TOTAL      = CASE WHEN FCOMD.TIENEIVA=1 THEN ROUND(VR_ANTESIVA-ISNULL(VR_DESCUENTO,0)+IVA,2)   ELSE ROUND(VR_ANTESIVA-ISNULL(VR_DESCUENTO,0),2) END
   WHERE CNSFCOM=@CNSFCOM

   UPDATE FCOM SET VR_ANTESIVA=(SELECT SUM(VR_ANTESIVA) FROM FCOMD WHERE CNSFCOM=@CNSFCOM),
		   VR_DESCUENTO=(SELECT SUM(VR_DESCUENTO) FROM FCOMD WHERE CNSFCOM=@CNSFCOM),
		   IVA=(SELECT SUM(IVA) FROM FCOMD WHERE CNSFCOM=@CNSFCOM),
		   VR_TOTAL=(SELECT SUM(VR_TOTAL)+ISNULL(FCOM.VLR_FLETE,0) FROM FCOMD WHERE CNSFCOM=@CNSFCOM)
   WHERE CNSFCOM=@CNSFCOM
END
