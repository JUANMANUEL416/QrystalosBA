CREATE OR ALTER PROCEDURE DBO.SPK_CAMBIA_BCT_PCJ_CAJA
  @BANCO            VARCHAR(3),
  @SUCURSAL         VARCHAR(2),
  @CTA_BCO          VARCHAR(40),
  @ITEM             INT,
  @BANCO_NVO        VARCHAR(3),
  @SUCURSAL_NVO     VARCHAR(2),
  @CTA_BCO_NVO      VARCHAR(40),
  @USUARIO          VARCHAR(20),
  @SYS_COMPUTERNAME VARCHAR(254),
  @COMPANIA         VARCHAR(5),
  @IDSEDE           VARCHAR(5)
AS
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET LANGUAGE Spanish;

DECLARE
  @CODCAJA            VARCHAR(10),  @CNSFACJ            VARCHAR(20),  @PROCEDENCIA        VARCHAR(20),  @ESTADO             VARCHAR(1),
  @FECHAOK            DATETIME,  @NROCOMPROBANTE_ORI VARCHAR(20),  @NROCOMPROBANTE_NVO VARCHAR(20),  @CLASE_FAC          VARCHAR(10),
  @FCJ_PROCEDENCIA    VARCHAR(20),  @IDSEDE_MOV         VARCHAR(5),  @ITEM_NVO           INT,  @ANO                INT,
  @MES                INT,  @MCP_ESTADO         SMALLINT,  @MCP_ANO            VARCHAR(4),  @MCP_MES            INT,
  @MCP_PROCEDENCIA    VARCHAR(20),  @MCP_NOREFERENCIA   VARCHAR(20),  @MCP_IDSEDE         VARCHAR(5),
  @CNSLOG             VARCHAR(20),  @CONSEC_LOG         VARCHAR(20),  @AHORA              DATETIME = GETDATE();

BEGIN
  
  IF @BANCO = @BANCO_NVO AND @SUCURSAL = @SUCURSAL_NVO AND @CTA_BCO = @CTA_BCO_NVO
  BEGIN
    SELECT 'KO' OK, 'La cuenta destino debe ser distinta a la cuenta origen.' ERROR;
    RETURN;
  END

  IF NOT EXISTS (SELECT 1 FROM BCT WHERE BANCO = @BANCO_NVO AND SUCURSAL = @SUCURSAL_NVO AND CTA_BCO = @CTA_BCO_NVO)
    SELECT 'KO' OK, 'La cuenta bancaria destino no existe.' ERROR; RETURN;

  IF EXISTS (SELECT 1 FROM BCT WHERE BANCO = @BANCO_NVO AND SUCURSAL = @SUCURSAL_NVO AND CTA_BCO = @CTA_BCO_NVO AND COALESCE(TARCRED, 0) = 1)
    SELECT 'KO' OK, 'No se permite cambiar a una cuenta de tarjeta de cr�dito.' ERROR; RETURN;

  SELECT
    @PROCEDENCIA        = PROCEDENCIA,
    @ESTADO             = ESTADO,
    @CODCAJA            = CODCAJA,
    @CNSFACJ            = CNSFACJ,
    @FECHAOK            = COALESCE(FECHAOK, FECHAOPERACION),
    @NROCOMPROBANTE_ORI = NULLIF(LTRIM(RTRIM(NROCOMPROBANTE)), ''),
    @IDSEDE_MOV         = COALESCE(NULLIF(LTRIM(RTRIM(IDSEDE)), ''), @IDSEDE)
  FROM BMOV
  WHERE BANCO = @BANCO AND SUCURSAL = @SUCURSAL AND CTA_BCO = @CTA_BCO AND ITEM = @ITEM;

  IF @ESTADO IS NULL
  BEGIN
    SELECT 'KO' OK, 'No se encontr� el movimiento bancario origen.' ERROR;
    RETURN;
  END

  IF @PROCEDENCIA <> 'CAJA'
  BEGIN
    SELECT 'KO' OK, 'Solo se permite cambiar cuenta en movimientos de procedencia CAJA.' ERROR;
    RETURN;
  END

  IF @ESTADO <> 'O'
  BEGIN
    SELECT 'KO' OK, 'Solo se pueden cambiar cuentas de movimientos confirmados (Ok).' ERROR;
    RETURN;
  END

  IF COALESCE(@CODCAJA, '') = '' OR COALESCE(@CNSFACJ, '') = ''
  BEGIN
    SELECT 'KO' OK, 'El movimiento no est� ligado a un recibo de caja.' ERROR;
    RETURN;
  END

  SELECT
    @FCJ_PROCEDENCIA = PROCEDENCIA,
    @CLASE_FAC       = CLASE_FAC
  FROM FCJ
  WHERE CODCAJA = @CODCAJA AND CNSFACJ = @CNSFACJ;

  IF @FCJ_PROCEDENCIA IS NULL
  BEGIN
    SELECT 'KO' OK, 'No se encontr� el recibo de caja ligado al movimiento.' ERROR;
    RETURN;
  END

  IF @FCJ_PROCEDENCIA <> 'CAJA'
  BEGIN
    SELECT 'KO' OK, 'El recibo ligado no es de procedencia CAJA.' ERROR;
    RETURN;
  END

  SET @ANO = YEAR(@FECHAOK);
  SET @MES = MONTH(@FECHAOK);

  IF NOT EXISTS (SELECT 1 FROM PRI WHERE COMPANIA = @COMPANIA AND ANO = @ANO AND MES = @MES)
  BEGIN
    SELECT 'KO' OK, 'Periodo contable no existe. No se realiza ning�n cambio.' ERROR;
    RETURN;
  END

  IF (SELECT COALESCE(CERRADO, 0) FROM PRI WHERE COMPANIA = @COMPANIA AND ANO = @ANO AND MES = @MES) = 1
  BEGIN
    SELECT 'KO' OK, 'Periodo contable cerrado. No se realiza ning�n cambio.' ERROR;
    RETURN;
  END
  IF (SELECT COALESCE(CERRADO_CXP, 0) FROM PRI WHERE COMPANIA = @COMPANIA AND ANO = @ANO AND MES = @MES) = 1
  BEGIN
    SELECT 'KO' OK, 'Periodo de cuentas por pagar esta cerrado. No se permite realizar ning�n cambio.' ERROR;
    RETURN;
  END

  IF EXISTS (
    SELECT 1 FROM BMOVD
    WHERE BANCO = @BANCO AND SUCURSAL = @SUCURSAL AND CTA_BCO = @CTA_BCO AND ITEM = @ITEM
      AND COALESCE(ENPAGOS, 0) = 1
  )
  BEGIN
    SELECT 'KO' OK, 'El movimiento est� legalizado en pagos (FPAG). No se puede cambiar la cuenta.' ERROR;
    RETURN;
  END

  IF EXISTS (
    SELECT 1 FROM PCJ
    WHERE CODCAJA = @CODCAJA AND CNSFACJ = @CNSFACJ
      AND COALESCE(TARCRED, 0) = 1
  )
  BEGIN
    SELECT 'KO' OK, 'No se permite cambio de cuenta en pagos con tarjeta de cr�dito.' ERROR;
    RETURN;
  END

  SET @IDSEDE = COALESCE(@IDSEDE_MOV, @IDSEDE);

  BEGIN TRY
    BEGIN TRANSACTION;

    UPDATE BMOV
      SET ESTADO = 'A',
          RAZONANULACION = 'CAMBIO CTA BANCARIA PCJ',
          USUARIOANULA = @USUARIO,
          FECHAANU = @AHORA,
          SYS_COMPUTERNAME_ANULA = @SYS_COMPUTERNAME
    WHERE BANCO = @BANCO AND SUCURSAL = @SUCURSAL AND CTA_BCO = @CTA_BCO AND ITEM = @ITEM;

    EXEC SPK_RECALCULO_BANCOS @BANCO, @SUCURSAL, @CTA_BCO;

    SELECT @ITEM_NVO = COALESCE(MAX(ITEM), 0) + 1
    FROM BMOV
    WHERE BANCO = @BANCO_NVO AND SUCURSAL = @SUCURSAL_NVO AND CTA_BCO = @CTA_BCO_NVO;

    INSERT INTO BMOV (
      BANCO, SUCURSAL, CTA_BCO, ITEM, FECHAOPERACION, NODOCUMENTO, NOTRANSFOPER,
      IDOPERACION, VLROPERACION, DESCRIPCION, USUARIO, SYS_COMPUTERNAME,
      SALDOANTES, SALDODESP, TIPOCOBROFIN, USUARIOOPER, OKOPERACION, PROCEDENCIA,
      ESTADO, RAZONANULACION, USUARIOANULA, SYS_COMPUTERNAME_ANULA, FECHAOK, FECHAANU,
      ANTIGUA, CONTABILIZADA, MARCACONT, NROCOMPROBANTE, CODCAJA, CNSFACJ,
      NROASIENTO, CODUNG, CODPRG, GENCXP, CNSFCXP, IDSEDE
    )
    SELECT
      @BANCO_NVO, @SUCURSAL_NVO, @CTA_BCO_NVO, @ITEM_NVO, FECHAOPERACION, NODOCUMENTO, NOTRANSFOPER,
      IDOPERACION, VLROPERACION, DESCRIPCION, @USUARIO, @SYS_COMPUTERNAME,
      0, 0, TIPOCOBROFIN, USUARIOOPER, OKOPERACION, PROCEDENCIA,
      'C', NULL, NULL, NULL, FECHAOK, NULL,
      ANTIGUA, CONTABILIZADA, MARCACONT, NROCOMPROBANTE, CODCAJA, CNSFACJ,
      NROASIENTO, CODUNG, CODPRG, GENCXP, CNSFCXP, COALESCE(IDSEDE, @IDSEDE)
    FROM BMOV
    WHERE BANCO = @BANCO AND SUCURSAL = @SUCURSAL AND CTA_BCO = @CTA_BCO AND ITEM = @ITEM;

    INSERT INTO BMOVD (
      BANCO, SUCURSAL, CTA_BCO, ITEM, RENGLON, FORMAPAGO, BANCODOC, NODOCUMENTO,
      VLRITEM, IDTERCERO, RECAUDO, ENPAGOS, OK, DEVUELTO, CAUSALDEV, PROCEDENCIA,
      CODCAJA, CNSFACJ, IDTERCEROANT, VLRLEGALIZADO, LLAVEDEVCHE, CUENTA, VLRAJUSTE,
      NROCOMPROBANTE, CCOSTO, RNOMI
    )
    SELECT
      @BANCO_NVO, @SUCURSAL_NVO, @CTA_BCO_NVO, @ITEM_NVO, RENGLON, FORMAPAGO, BANCODOC, NODOCUMENTO,
      VLRITEM, IDTERCERO, RECAUDO, ENPAGOS, OK, DEVUELTO, CAUSALDEV, PROCEDENCIA,
      CODCAJA, CNSFACJ, IDTERCEROANT, VLRLEGALIZADO, LLAVEDEVCHE, CUENTA, VLRAJUSTE,
      NROCOMPROBANTE, CCOSTO, RNOMI
    FROM BMOVD
    WHERE BANCO = @BANCO AND SUCURSAL = @SUCURSAL AND CTA_BCO = @CTA_BCO AND ITEM = @ITEM;

    EXEC SPK_TOT_BMOV @BANCO_NVO, @SUCURSAL_NVO, @CTA_BCO_NVO, @ITEM_NVO;
    EXEC SPK_OK_BMOV
      @BANCO_NVO, @SUCURSAL_NVO, @CTA_BCO_NVO, @ITEM_NVO,
      @USUARIO, @SYS_COMPUTERNAME, @COMPANIA, @IDSEDE, @NROCOMPROBANTE_ORI;

    UPDATE PCJ
      SET BANCO = @BANCO_NVO,
          SUCURSAL = @SUCURSAL_NVO,
          CTA_BCO = @CTA_BCO_NVO
    WHERE CODCAJA = @CODCAJA
      AND CNSFACJ = @CNSFACJ
      AND BANCO = @BANCO
      AND SUCURSAL = @SUCURSAL
      AND CTA_BCO = @CTA_BCO;

    UPDATE FCJ
      SET BANCO = @BANCO_NVO,
          SUCURSAL = @SUCURSAL_NVO,
          CTA_BCO = @CTA_BCO_NVO
    WHERE CODCAJA = @CODCAJA AND CNSFACJ = @CNSFACJ;

    IF COALESCE(@NROCOMPROBANTE_ORI, '') <> ''
    BEGIN
      UPDATE MCP
        SET ANULADO = 1,
            ESTADO = 0
      WHERE NROCOMPROBANTE = @NROCOMPROBANTE_ORI;

      SET @NROCOMPROBANTE_NVO = '';

      IF @CLASE_FAC = 'COBRO'
      BEGIN
        EXEC SPK_CONTAB_CAJA_ING
          @CNSFACJ, @CODCAJA, @USUARIO, @SYS_COMPUTERNAME,
          @COMPANIA, @IDSEDE, @NROCOMPROBANTE_NVO;
      END
      ELSE IF @CLASE_FAC = 'PAGO'
      BEGIN
        EXEC SPK_CONTAB_CAJA_EGR
          @CNSFACJ, @CODCAJA, @USUARIO, @SYS_COMPUTERNAME,
          @COMPANIA, @IDSEDE, @NROCOMPROBANTE_NVO;
      END

      SELECT @NROCOMPROBANTE_NVO = NULLIF(LTRIM(RTRIM(NROCOMPROBANTE)), '')
      FROM FCJ
      WHERE CODCAJA = @CODCAJA AND CNSFACJ = @CNSFACJ;

      UPDATE BMOV
        SET NROCOMPROBANTE = COALESCE(@NROCOMPROBANTE_NVO, NROCOMPROBANTE)
      WHERE BANCO = @BANCO_NVO AND SUCURSAL = @SUCURSAL_NVO
        AND CTA_BCO = @CTA_BCO_NVO AND ITEM = @ITEM_NVO;

      IF COALESCE(@NROCOMPROBANTE_NVO, '') = ''
      BEGIN
        RAISERROR('No se cre� el comprobante contable nuevo.', 16, 1);
      END

      SELECT
        @MCP_ESTADO       = ESTADO,
        @MCP_ANO          = ANO,
        @MCP_MES          = MES,
        @MCP_PROCEDENCIA  = PROCEDENCIA,
        @MCP_NOREFERENCIA = NOREFERENCIA,
        @MCP_IDSEDE       = COALESCE(NULLIF(LTRIM(RTRIM(IDSEDE)), ''), @IDSEDE)
      FROM MCP
      WHERE NROCOMPROBANTE = @NROCOMPROBANTE_NVO;

      IF @MCP_ESTADO IS NULL
      BEGIN
        RAISERROR('El comprobante contable nuevo no existe en MCP.', 16, 1);
      END

      IF COALESCE(@MCP_ESTADO, 0) <> 2
      BEGIN
        IF EXISTS (
          SELECT 1
          FROM MCH
          LEFT JOIN CUE ON MCH.CUENTA = CUE.CUENTA AND CUE.TIPO = 'Detalle'
          WHERE MCH.NROCOMPROBANTE = @NROCOMPROBANTE_NVO
            AND CUE.CUENTA IS NULL
        )
        BEGIN
          RAISERROR('Existen en el comprobante cuentas que no son de Detalle. No se puede confirmar.', 16, 1);
        END

        EXEC DBO.SPK_NC_CONFIRMAR_CONTAB
          @NROCOMPROBANTE_NVO,
          @USUARIO,
          @COMPANIA,
          @MCP_IDSEDE,
          @SYS_COMPUTERNAME,
          @MCP_ANO,
          @MCP_MES,
          @MCP_PROCEDENCIA,
          @MCP_NOREFERENCIA,
          'CONTABILIZAR';
      END
    END
    ELSE
    BEGIN
      SET @NROCOMPROBANTE_NVO = NULL;
    END

    SET @CONSEC_LOG = SPACE(20);
    EXEC SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE, '@LOG', @CONSEC_LOG OUTPUT;
    SET @CNSLOG = @IDSEDE + RIGHT('00000000' + LTRIM(RTRIM(@CONSEC_LOG)), 8);

    INSERT INTO USLOG (CNSLOG, COMPANIA, NOADMISION, PROCESO, REQUEST, REFERENCIA, USUARIO, FECHA, SYS_ComputerName, TABLA)
    SELECT
      @CNSLOG, @COMPANIA, @CNSFACJ, 'CAMBIOCTABCO', 'CHANGE',
      'BMOV:' + @BANCO + '-' + @SUCURSAL + '-' + @CTA_BCO + '-' + CONVERT(VARCHAR(20), @ITEM)
        + ' FCJ:' + @CODCAJA + '-' + @CNSFACJ,
      @USUARIO, CONVERT(DATE, @AHORA), @SYS_COMPUTERNAME, 'BMOV';

    INSERT INTO USLOGH (CNSLOG, ITEM, CAMPO, VALORANT, VALORNVO)
    SELECT @CNSLOG, 1, 'BANCO', @BANCO, @BANCO_NVO
    UNION ALL SELECT @CNSLOG, 2, 'SUCURSAL', @SUCURSAL, @SUCURSAL_NVO
    UNION ALL SELECT @CNSLOG, 3, 'CTA_BCO', @CTA_BCO, @CTA_BCO_NVO
    UNION ALL SELECT @CNSLOG, 4, 'ITEM', CONVERT(VARCHAR(20), @ITEM), CONVERT(VARCHAR(20), @ITEM_NVO)
    UNION ALL SELECT @CNSLOG, 5, 'NROCOMPROBANTE', COALESCE(@NROCOMPROBANTE_ORI, ''), COALESCE(@NROCOMPROBANTE_NVO, '');

    COMMIT TRANSACTION;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0
      ROLLBACK TRANSACTION;

    SELECT 'KO' OK, ERROR_MESSAGE() ERROR;
    RETURN;
  END CATCH

  SELECT 'OK' OK,
         @ITEM_NVO ITEM,
         @BANCO_NVO BANCO,
         @SUCURSAL_NVO SUCURSAL,
         @CTA_BCO_NVO CTA_BCO,
         @NROCOMPROBANTE_NVO NROCOMPROBANTE;
END
