CREATE OR ALTER PROCEDURE DBO.SPQ_MNDV_COL
@JSON  NVARCHAR(MAX)
WITH
ENCRYPTION
AS
DECLARE @PARAMETROS  NVARCHAR(MAX)  ,@MODELO           VARCHAR(100)    ,@METODO        VARCHAR(100)  ,@USUARIO        VARCHAR(12)
       ,@GRUPO       VARCHAR(8)     ,@SYS_COMPUTERNAME VARCHAR(254)    ,@SEDE          VARCHAR(5)	   ,@A              INT
       ,@IDENTITY    INT 
       ,@PROCESO     VARCHAR(20)    ,@MNDV    NVARCHAR(MAX)
       ,@IDMONEDA    VARCHAR(3)
       ,@ITEM        INT            ,@ITEMMAX INT
       ,@FECHA       DATETIME
       ,@FECHA_STR   VARCHAR(10)
       ,@VALOR       DECIMAL(9,2)
BEGIN
   SET LANGUAGE Spanish
   SET DATEFORMAT dmy
   
   SELECT @A = ISJSON(@JSON)
   IF @A = 0
   BEGIN
     RAISERROR('Json: Formato Erroneo',16,1)
     RETURN
   END
   PRINT 'INGRESE A SPQ_MNDV_COL'
   SELECT *
   INTO #JSON
   FROM OPENJSON (@json)
   WITH (
     MODELO         VARCHAR(100)     '$.MODELO',
     METODO         VARCHAR(100)     '$.METODO',
     USUARIO        VARCHAR(12)      '$.USUARIO',
     PARAMETROS     NVARCHAR(MAX)     AS JSON
   )
   
   SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS , @USUARIO = USUARIO
   FROM #JSON
   --DEFINICION DE TABLA DE ERRORES
   DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200))
   -- TOMA DEL GRUPO, SYS_COMPUTERNAME, SEDE   DE ACUERDO AL USUARIO
   PRINT 'USUARIO:'+@USUARIO
   --SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO) FROM USUSU WHERE USUARIO = @USUARIO
   --SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
   --SELECT @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
   IF COALESCE(@SEDE,'') = '' SELECT @SEDE = '01'
   PRINT 'SEDE='+@SEDE
   IF @METODO = 'CRUDMNDV'
   BEGIN
      PRINT 'CRUDMNDV'
      SELECT @MNDV  = REGISTRO
      FROM OPENJSON (@PARAMETROS)
      WITH(
         REGISTRO   NVARCHAR(MAX)     AS JSON
      )
      
      SELECT @PROCESO     = JSON_VALUE(@MNDV ,'$.PROCESO')
      --Leo Campos enviados y los coloco en las variables respectivas
      SELECT @IDMONEDA = JSON_VALUE(@MNDV , '$.IDMONEDA' )
      SELECT @ITEM = JSON_VALUE(@MNDV , '$.ITEM' )
      SELECT @FECHA_STR = JSON_VALUE(@MNDV , '$.FECHA')
      SELECT @FECHA = CONVERT(DATE, SUBSTRING(@FECHA_STR,9,2)+'/'+SUBSTRING(@FECHA_STR,6,2)+'/'+SUBSTRING(@FECHA_STR,1,4))
      SELECT @VALOR = JSON_VALUE(@MNDV , '$.VALOR' )
      IF UPPER(@PROCESO) = 'INSERTAR'
      BEGIN
         PRINT 'INSERTAR'
         IF EXISTS(SELECT * FROM MNDV WHERE IDMONEDA = @IDMONEDA AND FECHA = @FECHA)
         begin
            INSERT INTO @TBLERRORES(ERROR) SELECT 'Fecha de Vigencia ya existe para esta Moneda'
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
         end
         BEGIN TRY
            SELECT @ITEMMAX = COALESCE(MAX(ITEM),0) + 1 FROM MNDV WHERE IDMONEDA = @IDMONEDA
            INSERT INTO MNDV(IDMONEDA,ITEM,FECHA,VALOR)
            SELECT @IDMONEDA,@ITEMMAX,@FECHA,@VALOR
            SELECT @IDENTITY = SCOPE_IDENTITY()
         END TRY
         BEGIN CATCH
            INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
         END CATCH
         IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
         BEGIN
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
         END
         SELECT 'OK' OK ,STR(@IDENTITY) CNS 
         RETURN
      END
      IF UPPER(@PROCESO) = 'EDITAR'
      BEGIN
         PRINT 'EDITAR'
         BEGIN TRY
            UPDATE MNDV SET FECHA = @FECHA,VALOR = @VALOR
            WHERE IDMONEDA = @IDMONEDA
            AND   ITEM = @ITEM
         END TRY
         BEGIN CATCH
            INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
         END CATCH
         IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
         BEGIN
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
         END
         SELECT 'OK' OK
         RETURN
      END
      RETURN
   END
END
