CREATE OR

ALTER PROCEDURE DBO.SPQ_TRAER_PLANTILLA_NOMI @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @DATOS NVARCHAR(MAX)
DECLARE @USUARIO VARCHAR(20), @PROCESO VARCHAR(20)
DECLARE @IDPLANTILLA VARCHAR(20)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GENERA_RPDX_PLANTILLA'
	BEGIN
		BEGIN TRY
			SELECT @IDPLANTILLA = IDPLANTILLA, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (IDPLANTILLA VARCHAR(20) '$.IDPLANTILLA', PROCESO VARCHAR(20) '$.PROCESO')

			DELETE RPDX
			WHERE CNS IN ('NCAR', 'NCON')

			INSERT INTO RPDX (CNS, ID1, STRINGMEDIO1, ID2, ID3, FECHA1)
			SELECT 'NCAR', NCAR.CODCARGO, NCAR.DESCRIPCION, NPLTCA.NIVEL, NPLTCA.GRADO, GETDATE()
			FROM NCAR
			INNER JOIN NPLTCA ON NCAR.CODCARGO = NPLTCA.CODCARGO AND NPLTCA.IDPLANTILLA = @IDPLANTILLA

			INSERT INTO RPDX (CNS, ID1, STRINGMEDIO1, FECHA1)
			SELECT 'NCON', NPLTCO.CODCONCEPTO, NCON.DESCRIPCION, GETDATE()
			FROM NCON
			INNER JOIN NPLTCO ON NCON.CODCONCEPTO = NPLTCO.CODCONCEPTO AND NPLTCO.IDPLANTILLA = @IDPLANTILLA
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
