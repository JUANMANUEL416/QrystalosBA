CREATE OR ALTER PROCEDURE DBO.SPQ_LISTA_AUT
@JSON  NVARCHAR(MAX) 
WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX)		,@MODELO VARCHAR(100)		,@METODO VARCHAR(100)
	,@USUARIO VARCHAR(12)				,@GRUPO VARCHAR(8)			,@SYS_COMPUTERNAME VARCHAR(254)
	,@IDSEDE VARCHAR(5)					,@USUNOMBRE VARCHAR(100)	,@SEDE VARCHAR(5)
	,@FECHA VARCHAR(10)					,@IDEMEDICA VARCHAR(4)		,@FECHA1 DATETIME
	,@SQL VARCHAR(MAX)					,@CODCAJERO VARCHAR(20)		,@COMPANIA VARCHAR(10)
	,@IDAFILIADO VARCHAR(20)			,@IDMEDICO VARCHAR(20)		,@FECHAINI DATE	, @FECHAFIN DATE
	,@OBSERVACION VARCHAR(MAX)			,@IDAUT VARCHAR(20)			,@NO_ITEM INT
	,@PROCEDENCIA VARCHAR(20)			,@VALOR DECIMAL(14, 2)		,@DIA VARCHAR(10)
	,@CONSECUTIVO VARCHAR(20)			,@MODALIDAD VARCHAR(20)		,@IDSERVICIO VARCHAR(20), @IDFARMACIA VARCHAR(20)
	,@N_FACTURA VARCHAR(20)				,@IDPLAN VARCHAR(20)		,@IDTERCERO VARCHAR(20)
	,@DOCIDAFILIADO VARCHAR(20)			,@CELULAR VARCHAR(20)		,@CODCAJA VARCHAR(20)
	,@CNSFCT VARCHAR(20)				,@CNSFACJ VARCHAR(20)		,@IDKPAGE INT
	,@COPAGO_VARIABLE DECIMAL(14, 2)	,@COPAGO_FIJO DECIMAL(14, 2),@PREFIJO VARCHAR(20)
	,@REQ_AUT BIT						,@NOAUTORIZACION VARCHAR(20),@REQ_CONSULTA BIT
	,@REQ_FARMACOS BIT					,@REQ_EXAMENES BIT			,@COPAGO_FI_CON DECIMAL(14, 2)
	,@COPA_VAR_PORC DECIMAL(14, 2)		,@COPAGO_FI_FAR DECIMAL(14, 2)	,@ID_LOGI INT
	,@COPAGO_VA_FAR DECIMAL(14, 2)		,@COPAGO_FI_EXA DECIMAL(14, 2)
	,@COPAGO_VA_EXA DECIMAL(14, 2)		,@ITEMS INT					,@COPAGOFIJO_D DECIMAL(14, 4)
	,@MIN_AUT SMALLINT					,@MOTIVO VARCHAR(20)		,@CRONICO INT     , @CONSECUTIVOHCA VARCHAR(20)
	,@NOMBREACOM VARCHAR(150)			,@TELEFONOACOM VARCHAR(50)	,@DIRECCIONACOM VARCHAR(60)
	,@PARENTESCOACOM VARCHAR(20)		,@ANIOVIG INT				,@MESVIG INT, @NOAUT VARCHAR(20), @NOITEM INT, @AMBITO VARCHAR(50)
	,@FECHA_VIGENCIA DATE				,@FECHAMAX DATE				,@IDCROVIG INT	, @CNSIDAUT VARCHAR(20)
	,@NOADMISION VARCHAR(16)			,@ESPECIALIDAD VARCHAR(20)	,@CCOSTO VARCHAR(20)	, @DATOS NVARCHAR(MAX)
	,@IDAREA VARCHAR(20)				,@IDSERMOVILIDAD VARCHAR(20) = DBO.FNK_VALORVARIABLE('IDSERMOVILIDAD')
	,@PROCESO VARCHAR(20)				,@CANTIDAD	INT			,@IDAUT_NEW VARCHAR(20)	, @CNS VARCHAR(20)
	,@IDBODEGA VARCHAR(10), @SECTOR VARCHAR(20)	, @IDADMINISTRADORA VARCHAR(20), @IDPLAN_AFI VARCHAR(20)
	,@TIPO_DOC VARCHAR(20)			,@NVOCONSEC VARCHAR(20)	,@RAZONSOCIAL VARCHAR(250), @VIAINGRESO VARCHAR(2), @NOPRESUPUESTO VARCHAR(20)
DECLARE @PRECIO_TOTAL DECIMAL(14,9), @PORCENTAJE_PRORRATEO DECIMAL(14,9), @VALOR_ITEM DECIMAL(14,9), @COBERTURA_ASEGURADORA DECIMAL(14,9)
	,@COBERTURA_PACIENTE DECIMAL(14,9), @VALOR_COPAGO DECIMAL(14,9) = 0, @VALOR_EXCEDENTE DECIMAL(14,9)=0, @TOTAL_COPAGO DECIMAL(14,9)=0
	,@VLR_COPAGOVAR DECIMAL(14,9)=0, @VLR_PRCOPAGOVAR DECIMAL(14,9)=0 , @SERVICIOS NVARCHAR(MAX) ,@ID INT
DECLARE @CLASE VARCHAR(20), @CNSIZSOLD VARCHAR(20), @IDARTICULO VARCHAR (20), @IDARTICULO_REAL VARCHAR(20), @CANTIDADSOL INT, @NOLOTE varchar(20)
DECLARE @VALOR_UNITARIO_SIN_IGV	DECIMAL(14,2)  , @MOTIVO_RECHAZO VARCHAR(250),@DATOSITEDS NVARCHAR(MAX),@DETALLESITEDS NVARCHAR(MAX)
   ,@VALOR_IGV_UNITARIO	DECIMAL(14,2), @ID_CITSITEDS INT, @COPAGOVARIABLECONSULTA DECIMAL(14,2), @MODULO VARCHAR(20)
   ,@VALOR_UNITARIO_CON_IGV	DECIMAL(14,2), @NOPRESTACION VARCHAR(20), @OBSERVACIONES NVARCHAR(MAX), @COMP_AFI VARCHAR(50)
   ,@VALOR_COPAGO_UNIT_SIN_IGV	DECIMAL(14,2)
   ,@VALOR_COPAGO_IGV_UNIT	DECIMAL(14,2)
   ,@VALOR_COPAGO_TOTAL_SIN_IGV	DECIMAL(14,2)
   ,@VALOR_COPAGO_TOTAL_CON_IGV	DECIMAL(14,2)
   ,@CNSMOV VARCHAR(20), @NOLOTEPEDIDO VARCHAR(20)
   ,@CNSIZSOL VARCHAR(20)
   ,@IDTIPOMOV VARCHAR(10)

BEGIN 
	SET LANGUAGE Spanish;  
	SET DATEFORMAT dmy
	SELECT *
	INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)  AS JSON
	)

	SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON
	--DEFINICION DE TABLA DE ERRORES
	DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200));
	-- TOMA DEL GRUPO, SYS_COMPUTERNAME, SEDE   DE ACUERDO AL USUARIOpl,   --PRINT 'USUARIO:'+@USUARIO
	SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO), @USUNOMBRE = NOMBRE FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME, @COMPANIA = COMPANIA, @CODCAJERO= CODCAJERO FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @IDSEDE = IDSEDE, @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	CREATE TABLE #VECES( FECHAMAX DATE, FECHAINICIAL DATE, VEZ VARCHAR(2), IDTERCERO VARCHAR(20), IDPLAN VARCHAR(20), IDAFILIADO VARCHAR(20), PROCEDENCIA VARCHAR(20))

	PRINT '@USUARIO='+@USUARIO

	IF @METODO = 'AGREGA_NOTA'
	BEGIN
		SELECT @IDAUT=IDAUT , @OBSERVACION = OBSERVACION, @MOTIVO = MOTIVO
		FROM OPENJSON(@PARAMETROS)
		WITH( IDAUT				VARCHAR(20)			'$.IDAUT', MOTIVO		VARCHAR(20)		'$.MOTIVO'
			,OBSERVACION		VARCHAR(MAX)		'$.OBSERVACION'
		)
		
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				SELECT @FECHA1 = DBO.FNK_GETDATE()
				INSERT INTO AUTNOT ( AUTNOT.IDAUT, AUTNOT.FECHA, AUTNOT.USUARIO, AUTNOT.NOTA, AUTNOT.MOTIVO)
				SELECT @IDAUT, @FECHA1, @USUARIO, @OBSERVACION,@MOTIVO

				-- Dispensaci�n parcial: el AUT de Delivery MAD (IDAUT_1, IDAUT_2, ...) ya puede existir.
				-- El m�dico suele guardar la nota en el AUT original despu�s de confirmar; replicarla a las hijas.
				SELECT @IDAUT_NEW = CASE
					WHEN CHARINDEX('_', @IDAUT) > 0
						AND TRY_CAST(RIGHT(@IDAUT, CHARINDEX('_', REVERSE(@IDAUT)) - 1) AS INT) IS NOT NULL
					THEN LEFT(@IDAUT, LEN(@IDAUT) - CHARINDEX('_', REVERSE(@IDAUT)))
					ELSE @IDAUT
				END

				INSERT INTO AUTNOT (IDAUT, FECHA, USUARIO, NOTA, MOTIVO)
				SELECT A.IDAUT, N.FECHA, N.USUARIO, N.NOTA, N.MOTIVO
				FROM AUT A
				INNER JOIN AUTNOT N ON N.IDAUT = @IDAUT
				WHERE A.IDAUT <> @IDAUT
					AND A.IDAUT LIKE REPLACE(@IDAUT_NEW, '_', '[_]') + '[_]%'
					AND NOT EXISTS (
						SELECT 1
						FROM AUTNOT X
						WHERE X.IDAUT = A.IDAUT
							AND X.USUARIO = N.USUARIO
							AND X.FECHA = N.FECHA
							AND X.NOTA = N.NOTA
					)
			END TRY  
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK
		END 
	END
	IF @METODO = 'APROBAR_TODOS'
	BEGIN
		SELECT @IDAUT=IDAUT
		FROM OPENJSON(@PARAMETROS)
		WITH( IDAUT VARCHAR(20) '$.IDAUT'
		)
		SELECT @IDKPAGE = COALESCE(IDKPAGE,0) FROM AUT WHERE IDAUT = @IDAUT
		IF EXISTS(SELECT * FROM AUT WHERE IDAUT = @IDAUT AND COALESCE(GENERADO,0) = 3) 
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El registro se encuentra en estado Generado.'
		END
		IF EXISTS(SELECT * FROM AUT WHERE IDAUT = @IDAUT AND COALESCE(IDKPAGE,'')<>'') 
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El registro cuenta con Link de pago Vigente'
		END
		
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				UPDATE AUTD SET GENERADO = 1, NOCOBRABLE = 0 WHERE AUTD.IDAUT = @IDAUT AND COALESCE(GENERADO,0) = 0
				SELECT @SQL='{"MODELO":"LISTA_AUT","METODO":"CALCULO_COPA_AUT","PARAMETROS":{"IDAUT":"'+@IDAUT+'"},"USUARIO":"'+@USUARIO+'"}'
				EXEC SPQ_JSON @SQL
				UPDATE AUT SET GENERADO=3 WHERE IDAUT=@IDAUT
				
				SELECT @PROCEDENCIA = CASE  COALESCE(ESPROGRAMAS,0) WHEN 1 THEN 'CRONICO' ELSE 'AGUDO' END, @PREFIJO=AUT.PREFIJO
					,@IDAFILIADO = AUT.IDAFILIADO, @VALOR = AUT.VALORCOPAGO, @USUARIO=USUARIO, @NOADMISION=NOADMISION, @IDSEDE=IDSEDE
               ,@IDTERCERO = AUT.IDTERCEROCA, @IDPLAN = IDPLAN
				FROM AUT WHERE AUT.IDAUT = @IDAUT

				IF @PREFIJO = DBO.FNK_VALORVARIABLE('PREFIJOMEDICAMENTOS') AND COALESCE(@NOADMISION,'')<>''
				BEGIN
					SELECT TOP 1 @SECTOR=SECTOR FROM HHAB WHERE NOADMISION=@NOADMISION
					IF COALESCE(@NOADMISION,'')<>''
						SELECT @IDBODEGA=DBO.FNK_BUSCA_BODEGA_IZSOL(@IDSEDE, @SECTOR)
					ELSE
					BEGIN
						IF DBO.FNK_VALORVARIABLE('BODEGA_PEDIDOINV_CE') = 'SEDE'
							SELECT @IDBODEGA = ISNULL(IDBODEGACM,IDBODEGALOG) FROM SED WHERE IDSEDE = @IDSEDE	
					END
							
					IF COALESCE(@IDBODEGA,'')=''
						SELECT @IDBODEGA = ISNULL(IDBODEGA,IDBODEGA2), @COMPANIA = COMPANIA FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
			    
					EXEC SPK_PEDIDOINVCE @IDAUT, @IDBODEGA, @COMPANIA, @IDSEDE, @USUARIO, @SYS_COMPUTERNAME, @NO_ITEM
				END

            /* INSERTA A CARGOS, Y VALIDA SI YA EXISTE, O NO EXISTE. */
            IF EXISTS (SELECT 1
                        FROM AUTD
                        INNER JOIN AUT    ON AUT.IDAUT = AUTD.IDAUT
                        INNER JOIN SER    ON SER.IDSERVICIO = AUTD.IDSERVICIO
                        LEFT JOIN HPRE    ON HPRE.PROCEDENCIA = 'AUT'    AND HPRE.NOPRESUPUESTO = AUT.IDAUT
                        LEFT JOIN HPRED    ON HPRED.NOPRESTACION = HPRE.NOPRESTACION    AND HPRED.IDSERVICIO = AUTD.IDSERVICIO
                        WHERE AUTD.IDAUT = @IDAUT
                           AND SER.PREFIJO = DBO.FNK_VALORVARIABLE('PREFIJOLABORATORIO')
                           AND HPRED.NOPRESTACION IS NULL)
               AND EXISTS (SELECT 1 FROM PPT WHERE IDTERCERO = @IDTERCERO AND IDPLAN = @IDPLAN AND PPT_TIPOADM = DBO.FNK_VALORVARIABLE('HTAD_HOSPITA'))
            BEGIN
               PRINT 'INSERTA EN HPRE'
               EXEC SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE,'@HPRE', @NOPRESTACION OUTPUT  
               SELECT @NOPRESTACION = @IDSEDE + REPLACE(SPACE(8 - LEN(@NOPRESTACION))+LTRIM(RTRIM(@NOPRESTACION)),SPACE(1),0)

               SELECT @CONSECUTIVOHCA = CONSECUTIVOHCA,  @NOADMISION=NOADMISION, @IDSEDE=IDSEDE FROM AUT WHERE IDAUT = @IDAUT
               SELECT  @IDAREA = IDAREA, @CCOSTO = CCOSTO FROM HCA WHERE CONSECUTIVO = @CONSECUTIVOHCA
               SELECT TOP 1 @NOPRESUPUESTO = NOPRESUPUESTO FROM HPREP WHERE CONSECUTIVOHCA = @CONSECUTIVOHCA
               IF COALESCE(@IDAREA,'')= ''
               BEGIN
               SELECT TOP 1 @IDAREA = IDAREA FROM HPRE
               WHERE NOADMISION = @NOADMISION ORDER BY  FECHA  DESC
               END
               IF COALESCE(@CCOSTO,'')= ''
               BEGIN
               SELECT TOP 1 @CCOSTO = HPRE.CCOSTO FROM HPRE
               INNER JOIN CEN ON HPRE.CCOSTO = CEN.CCOSTO AND CEN.ESTADO = 'Activo'
               WHERE NOADMISION = @NOADMISION ORDER BY  FECHA  DESC
               END
               INSERT INTO HPRE (NOPRESTACION, NOADMISION, FECHA, IDPLAN, IDAREAH, IDAREA, IDSEDE, ALTOCOSTO, USUARIO, CERRADA,PCUBRIMIENTO,
	               ESDEINV, PEDIDOINV, INDDEVOLUCION, PREFIJO,CCOSTO, FINALIDAD, AMBITO, PERSONAL_AT, IDAREAEQUIPO,IDMEDICO, 
	               COBRARA, IDTERCEROCA, SYS_COMPUTERNAME, IDAREAAUX, ENLAB, ANULADO, PROCEDENCIA, NOPRESUPUESTO,  CONSECUTIVOHCA)
               SELECT @NOPRESTACION, AUT.NOADMISION, DBO.FNK_GETDATE(), AUT.IDPLAN , '01', @IDAREA, AUT.IDSEDE, 'No',@USUARIO, 0, 100.00
               ,0,0, 0, DBO.FNK_VALORVARIABLE('PREFIJOLABORATORIO'), @CCOSTO, 1,NULL, NULL, NULL, NULL,'C', AUT.IDTERCEROCA, 'CAJERO_MANUAL', NULL, 0, 0, 'AUT',@IDAUT, @CONSECUTIVOHCA
               FROM AUT
               WHERE AUT.IDAUT = @IDAUT

               INSERT INTO HPRED (NOPRESTACION, NOITEM, IDSERVICIO, CANTIDAD, IDPLAN, COMENTARIOS, IDCONCEPTORIPS, USUARIO,TIPOSERCIRUGIA,FECHA,
               VIA,IDAREA,COBRARA, IDTERCEROCA, PCUBRIMIENTO, TIPODTO,DESCUENTO,CCOSTO,AQUIENCOBRO,CODCUPS,VALOR, NOAUTORIZACION,IDPROVEEDOR, PAQUETE)
               SELECT @NOPRESTACION, ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS NOITEM, AUTD.IDSERVICIO,AUTD.CANTIDAD,AUT.IDPLAN, '', '01',@USUARIO,NULL,dbo.FNK_FECHA_SIN_MLS(GETDATE()),
               'NA', @IDAREA, 'C', AUT.IDTERCEROCA, 100, 'N', 0, @CCOSTO,NULL,NULL, NULL , NULL, NULL, 0
               FROM AUTD
                        INNER JOIN AUT    ON AUT.IDAUT = AUTD.IDAUT
                        INNER JOIN SER    ON SER.IDSERVICIO = AUTD.IDSERVICIO
                        LEFT JOIN HPRE    ON HPRE.PROCEDENCIA = 'AUT'    AND HPRE.NOPRESUPUESTO = AUT.IDAUT
                        LEFT JOIN HPRED    ON HPRED.NOPRESTACION = HPRE.NOPRESTACION    AND HPRED.IDSERVICIO = AUTD.IDSERVICIO
                        WHERE AUTD.IDAUT = @IDAUT
                           AND SER.PREFIJO = DBO.FNK_VALORVARIABLE('PREFIJOLABORATORIO')
                           AND HPRED.NOPRESTACION IS NULL

               SELECT @SQL='{"MODELO":"HPRE","METODO":"RELIQUIDAR","PARAMETROS":{"NOADMISION":"'+@NOADMISION+'", "NOPRESTACION":"'+@NOPRESTACION+'"},"USUARIO":"'+@USUARIO+'"}'
               EXEC SPQ_JSON @SQL
            END
			END TRY 
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK, CASE WHEN COALESCE(AUT.IDKPAGE,'') <> '' THEN 'Se genero Link de Pago.' ELSE '' END [ESTADO]  FROM AUT WHERE IDAUT = @IDAUT
		END 
	END
	IF @METODO = 'RECHAZAR_ITEM'
	BEGIN
		SELECT @IDAUT=IDAUT, @NO_ITEM = NO_ITEM
		FROM OPENJSON(@PARAMETROS)
		WITH( IDAUT VARCHAR(20) '$.IDAUT', NO_ITEM INT '$.NO_ITEM'
		)
		IF EXISTS(SELECT * FROM AUT WHERE IDAUT = @IDAUT AND COALESCE(IDKPAGE,'') <> '') 
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El registro ya cuenta con link de Pago'
		END
	
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
			SELECT @IDSERVICIO = IDSERVICIO FROM AUTD WHERE AUTD.IDAUT = @IDAUT AND NO_ITEM = @NO_ITEM
            UPDATE AUTD SET GENERADO = 2, NOCOBRABLE = 1, ESTADO_TOMA = 'Rechazado' WHERE AUTD.IDAUT = @IDAUT AND NO_ITEM = @NO_ITEM
			UPDATE CROVIGD SET CUMPLIDA = 0, FECHA_ASIGNA = NULL WHERE CROVIGD.IDAUT = @IDAUT AND CROVIGD.IDSERVICIO = @IDSERVICIO
			IF EXISTS (SELECT * FROM LOGIS WHERE CONSECUTIVO = @IDAUT AND  LOGIS.IDSERVICIO = @IDSERVICIO)
			BEGIN
				SELECT TOP 1 @ID_LOGI = ID_LOGI FROM LOGIS WHERE CONSECUTIVO = @IDAUT AND  LOGIS.IDSERVICIO = @IDSERVICIO
				DELETE FROM LOGIS WHERE CONSECUTIVO = @IDAUT AND  LOGIS.IDSERVICIO = @IDSERVICIO
				IF NOT EXISTS (SELECT * FROM LOGIS WHERE ID_LOGI = @ID_LOGI)
				BEGIN
					DELETE FROM LOGI WHERE ID_LOGI = @ID_LOGI
				END
			END

            SELECT @SQL='{"MODELO":"LISTA_AUT","METODO":"CALCULO_COPA_AUT","PARAMETROS":{"IDAUT":"'+@IDAUT+'"},"USUARIO":"'+@USUARIO+'"}'
            EXEC SPQ_JSON @SQL
				IF NOT EXISTS(SELECT * FROM AUTD WHERE IDAUT = @IDAUT AND COALESCE(AUTD.GENERADO,0)=0)
				BEGIN
					SELECT @PROCEDENCIA = CASE  COALESCE(ESPROGRAMAS,0) WHEN 1 THEN 'CRONICO' ELSE 'AGUDO' END
						,@IDAFILIADO = AUT.IDAFILIADO, @VALOR = AUT.VALORCOPAGO
					FROM AUT WHERE AUT.IDAUT = @IDAUT
					--IF @VALOR>0 AND EXISTS (SELECT * FROM AUTD WHERE IDAUT = @IDAUT AND COALESCE(AUTD.GENERADO,0)=1)
					--AND @PREFIJO <> DBO.FNK_VALORVARIABLE('PREFIJOCONSULTA')
					--BEGIN
					--	EXEC SPK_GENERA_ORDENPAGO_IZIPAY @IDAUT, 'AUT', @PROCEDENCIA, @IDAFILIADO, @VALOR, '', @USUARIO, 0, 'CREAR'
					--END
					UPDATE AUT SET GENERADO = 3 WHERE IDAUT = @IDAUT
				END
			END TRY  
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK, CASE WHEN COALESCE(AUT.IDKPAGE,'') <> '' THEN 'Se genero Link de Pago.' ELSE '' END [ESTADO]  FROM AUT WHERE IDAUT = @IDAUT
		END 
	END
	IF @METODO = 'APROBAR_ITEM'
	BEGIN
		SELECT @IDAUT=IDAUT, @NO_ITEM = NO_ITEM
		FROM OPENJSON(@PARAMETROS)
		WITH( IDAUT VARCHAR(20) '$.IDAUT', NO_ITEM INT '$.NO_ITEM')

		IF EXISTS(SELECT * FROM AUT WHERE IDAUT = @IDAUT AND COALESCE(IDKPAGE,'') <> '') 
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El registro ya cuenta con link de Pago'
		END
	
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				SELECT @PREFIJO = PREFIJO FROM AUT WHERE IDAUT = @IDAUT
				UPDATE AUTD SET GENERADO = 1, NOCOBRABLE = 0, ESTADO_TOMA = 'Pendiente'  WHERE AUTD.IDAUT = @IDAUT AND NO_ITEM = @NO_ITEM
				IF @PREFIJO = DBO.FNK_VALORVARIABLE('PREFIJOCONSULTA')
				BEGIN
					INSERT INTO HCA_FAR_NOTI ( CONSECUTIVO, NO_ITEM, FECHA_ENVIO, USUARIO, CORREOS, CLASE, VALIDADO, PROCEDENCIA)
					SELECT @IDAUT, @NO_ITEM, DBO.FNK_GETDATE(), @USUARIO, NULL, @PREFIJO, 1, 'LISTA_TRABAJO'
				END
				/* CALCULO DE VALOR COPAGO  */
				SELECT @SQL='{"MODELO":"LISTA_AUT","METODO":"CALCULO_COPA_AUT","PARAMETROS":{"IDAUT":"'+@IDAUT+'"},"USUARIO":"'+@USUARIO+'"}'
				EXEC SPQ_JSON @SQL
				IF NOT EXISTS(SELECT 1 FROM AUTD WHERE IDAUT = @IDAUT AND COALESCE(AUTD.GENERADO,0)=0)
				BEGIN
					SELECT @PROCEDENCIA = CASE  COALESCE(ESPROGRAMAS,0) WHEN 1 THEN 'CRONICO' ELSE 'AGUDO' END
						,@IDAFILIADO = AUT.IDAFILIADO, @VALOR = AUT.VALORCOPAGO, @USUARIO=USUARIO, @NOADMISION=NOADMISION, @IDSEDE=IDSEDE
                  ,@IDTERCERO = AUT.IDTERCEROCA , @IDPLAN = AUT.IDPLAN
					FROM AUT WHERE AUT.IDAUT = @IDAUT

					IF @PREFIJO = DBO.FNK_VALORVARIABLE('PREFIJOCONSULTA')
					BEGIN
						UPDATE AUT SET GENERADO = 3, TIPOPREVIO = 2,AUT.FECHA_TIPOPREVIO = DBO.FNK_GETDATE()  WHERE IDAUT = @IDAUT		
					END
					ELSE UPDATE AUT SET GENERADO = 3 WHERE IDAUT = @IDAUT
				END

            /* INSERTA A CARGOS, Y VALIDA SI YA EXISTE, O NO EXISTE. */
            IF EXISTS (SELECT 1 FROM AUTD
                     INNER JOIN AUT    ON AUT.IDAUT = AUTD.IDAUT
                     INNER JOIN SER    ON SER.IDSERVICIO = AUTD.IDSERVICIO
                     LEFT JOIN HPRE    ON HPRE.PROCEDENCIA = 'AUT'    AND HPRE.NOPRESUPUESTO = AUT.IDAUT
                     LEFT JOIN HPRED    ON HPRED.NOPRESTACION = HPRE.NOPRESTACION    AND HPRED.IDSERVICIO = AUTD.IDSERVICIO
                     WHERE AUTD.IDAUT = @IDAUT
                       AND SER.PREFIJO = DBO.FNK_VALORVARIABLE('PREFIJOLABORATORIO')
                       AND HPRED.NOPRESTACION IS NULL
                       AND AUTD.NO_ITEM = @NO_ITEM)
               AND EXISTS (SELECT 1 FROM PPT WHERE IDTERCERO = @IDTERCERO AND IDPLAN = @IDPLAN AND PPT_TIPOADM = DBO.FNK_VALORVARIABLE('HTAD_HOSPITA'))
            BEGIN
                PRINT 'INSERTA EN HPRE'
               EXEC SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE,'@HPRE', @NOPRESTACION OUTPUT  
               SELECT @NOPRESTACION = @IDSEDE + REPLACE(SPACE(8 - LEN(@NOPRESTACION))+LTRIM(RTRIM(@NOPRESTACION)),SPACE(1),0)

