GO
CREATE PROCEDURE DBO.SPK_CONTAB_IACT
	@CNSIACTH          VARCHAR(20), 
	@USUARIO           VARCHAR(12),
	@SYS_COMPUTERNAME  VARCHAR(254),
	@COMPANIA          VARCHAR(2), 
	@SEDE              VARCHAR(5),
	@NROCOMPROBANTE    VARCHAR(20)
WITH ENCRYPTION
AS
DECLARE @COM               VARCHAR(6)
DECLARE @NOREFERENCIA      VARCHAR(20)
DECLARE @ANO		   VARCHAR(4)
DECLARE @MES		   INT
DECLARE @IDMODELOCONT	   VARCHAR(2)
DECLARE @IDPLAN		   VARCHAR(6) 
DECLARE @TIPOTERCONTABLE   VARCHAR(10) 
DECLARE @PREFIJO_USCXS     VARCHAR(10)
DECLARE @FECHATRA          DATETIME
DECLARE @IDEVENTO          VARCHAR(20)
DECLARE @TIPO              VARCHAR(20)
DECLARE @CUENTA_ACT        VARCHAR(20)
DECLARE @IDTERCERO_CIA     VARCHAR(20)
DECLARE @IDACTIVO          VARCHAR(20)
DECLARE @CCOSTO_IACT       VARCHAR(20)
DECLARE @IDAREA_IACT       VARCHAR(20)
DECLARE @IDITAR            VARCHAR(20)
DECLARE @IDTIPOACTIVO      VARCHAR(20)
DECLARE @CODUNG            VARCHAR(5)
DECLARE @CODPRG            VARCHAR(20)
DECLARE @VALOR             DECIMAL(14,2)
DECLARE @DEP_ACUMULADA     DECIMAL(14,2)
DECLARE @AJU_ACUMULADO     DECIMAL(14,2)
DECLARE @AJU_DEPACUMULADA  DECIMAL(14,2)
DECLARE @BAJA              SMALLINT,
        @PRECIOCOMERCIAL   DECIMAL(14,2)
BEGIN
 SELECT * INTO #T FROM IACTH WHERE CNSIACTH = @CNSIACTH
 SELECT @IDTERCERO_CIA = DBO.FNK_VALORVARIABLE('IDTERCEROINSTALADO')

 SELECT @ANO              = YEAR(#T.FECHAEVENTO),
        @MES              = MONTH(#T.FECHAEVENTO),
        @FECHATRA         = #T.FECHAEVENTO,
        @IDEVENTO         = #T.IDEVENTO,
        @TIPO             = IACTE.TIPO,
        @CUENTA_ACT       = IACT.CUENTA,
        @IDACTIVO         = #T.IDACTIVO,
        @CCOSTO_IACT      = IACT.CCOSTO,
        @IDAREA_IACT      = IACT.IDAREA,
        @IDITAR           = IACT.IDITAR,
        @IDTIPOACTIVO     = IACT.IDTIPOACTIVO,
        @CODUNG           = IACT.CODUNG,
        @CODPRG           = IACT.CODPRG,
        @VALOR            = ISNULL(IACT.PRECIOCOMPRA,0),
        @DEP_ACUMULADA    = ISNULL(IACT.DEPACUMHISTORICA,0),
        @AJU_ACUMULADO    = ISNULL(IACT.AJUSTEACUMULADO,0),
        @AJU_DEPACUMULADA = ISNULL(IACT.AJUSTEDEPACUMULADA,0),
        @BAJA             = ISNULL(IACTE.BAJA,0),
        @PRECIOCOMERCIAL  = IACT.PRECIOCOMERCIAL

 FROM #T INNER JOIN
      IACTE ON #T.IDEVENTO = IACTE.IDEVENTO INNER JOIN
      IACT ON #T.IDACTIVO = IACT.IDACTIVO

   IF NOT EXISTS(SELECT COMPANIA,ANO,MES FROM PRI WHERE COMPANIA=@COMPANIA AND ANO=@ANO AND MES=@MES)
   BEGIN
      RAISERROR('Periodo Contable NO Existe', 16, 1)
      RETURN
   END

 SET @IDMODELOCONT = DBO.FNK_VALORVARIABLE('IDMODELOCONTABLE')

 IF @NROCOMPROBANTE='' OR LEFT(@NROCOMPROBANTE,2) = 'IX'
 BEGIN
  IF LEFT(@NROCOMPROBANTE,2) = 'IX'
  BEGIN
   SET @COM='IX'  
  END
  ELSE
  BEGIN
  --   SET @NROCOMPROBANTE=SPACE(20)
  --   EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@MCP',@NROCOMPROBANTE OUTPUT   
  --   SELECT @NROCOMPROBANTE = @SEDE + REPLACE(SPACE(8 - LEN(@NROCOMPROBANTE))+LTRIM(RTRIM(@NROCOMPROBANTE)),SPACE(1),0)
  /***********************************************/
  PRINT '@NROCOMPROBANTE:' + ISNULL(@NROCOMPROBANTE,'') -- AGREGADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD
  IF ISNULL(@NROCOMPROBANTE,'') = '' -- AGREGADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD
  BEGIN  
     SET @NROCOMPROBANTE=SPACE(20)  
     EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@MCP',@NROCOMPROBANTE OUTPUT     
     PRINT '@NROCOMPROBANTE:' + ISNULL(@NROCOMPROBANTE,'') -- AGREGADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD
     SELECT @NROCOMPROBANTE = @SEDE + REPLACE(SPACE(8 - CASE WHEN LEN(@NROCOMPROBANTE) > 8 THEN 8 ELSE LEN(@NROCOMPROBANTE) END)+LTRIM(RTRIM(@NROCOMPROBANTE)),SPACE(1),0) -- AGREGADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD
     PRINT '@NROCOMPROBANTE:' + ISNULL(@NROCOMPROBANTE,'') -- AGREGADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD
  END
/*****************************************************/
   --SE REVISA SI LOS COMPROBANTES SE TOMAN DE ACUERDO A SEDE
   IF (SELECT DBO.FNK_VALORVARIABLE('COMPROBMULTISEDE')) = 'SI'
   BEGIN
      SELECT @COM = RTRIM(LTRIM(COMMS.COMPROBANTE)) 
      FROM   COMMS INNER JOIN #T ON COMMS.TIPO = @IDEVENTO
      WHERE  IDSEDE = @SEDE AND COMMS.CLASE = 'IACT' 
   END
   ELSE
   BEGIN
      SELECT @COM = COMPROBANTE FROM IACTE WHERE IDEVENTO = @IDEVENTO
   END
   IF @COM='' OR @COM IS NULL
      SET @COM=DBO.FNK_VALORVARIABLE('IDCON_TCOM_DEFAULT')
   IF @COM='' OR @COM IS NULL
      SET @COM='IX'
  END

  SET @PREFIJO_USCXS='@COM'+@COM
  SET @NOREFERENCIA=SPACE(20)
  EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,@PREFIJO_USCXS,@NOREFERENCIA OUTPUT   
  SELECT @NOREFERENCIA = REPLACE(SPACE(8 - LEN(@NOREFERENCIA))+LTRIM(RTRIM(@NOREFERENCIA)),SPACE(1),0)
  PRINT 'Nuevo Comprobante: '+@COM+' '+@NOREFERENCIA

  PRINT 'Comprobanrte Contable (MCP)'
  INSERT INTO MCPE(NROCOMPROBANTE, COMPANIA, PROCEDENCIA, NOREFERENCIA, ANO, MES, FECHACONTABLE, TOTALDEBITO,
                  TOTALCREDITO, REFERENCIA1, REFERENCIA2, USUARIO, FECHA, LOTE, OBSERVACION, IDSEDE, ESTADO,
                  COMPROBANTE, IDTERCERO)
  SELECT @NROCOMPROBANTE, @COMPANIA, 'IACT', @NOREFERENCIA, @ANO, @MES, @FECHATRA, 0, 
         0, CNSIACTH, IDEVENTO, @USUARIO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), NULL, OBSERVACION, @SEDE, 0,
         @COM, @IDTERCERO_CIA
  FROM #T 
 END
 ELSE
 BEGIN
   IF (SELECT COUNT(*) FROM MCP WHERE NROCOMPROBANTE=@NROCOMPROBANTE)>0
   BEGIN
      INSERT INTO MCPE (COMPANIA, NROCOMPROBANTE, PROCEDENCIA, NOREFERENCIA, ANO, MES, FECHACONTABLE, TOTALDEBITO ,TOTALCREDITO, REFERENCIA1, REFERENCIA2,
                        REFERENCIA3, USUARIO, FECHA, LOTE ,OBSERVACION ,IDSEDE ,ESTADO ,ANULADO ,COMPROBANTE ,IDTERCERO, BANCO ,NOCHEQUE, VALOR_CHEQUE,
                        RPT_COMPROBANTE, FECHARADICACION, MARCA, SYS_COMPUTERNAME_MARCA, ESTADOIMP, CBTEINTERNO)
      SELECT COMPANIA, NROCOMPROBANTE, PROCEDENCIA, NOREFERENCIA, ANO, MES, FECHACONTABLE, TOTALDEBITO ,TOTALCREDITO, REFERENCIA1, REFERENCIA2,
                        REFERENCIA3, USUARIO, FECHA, LOTE ,OBSERVACION ,IDSEDE ,ESTADO ,ANULADO ,COMPROBANTE ,IDTERCERO, BANCO ,NOCHEQUE, VALOR_CHEQUE,
                        RPT_COMPROBANTE, FECHARADICACION, MARCA, SYS_COMPUTERNAME_MARCA, ESTADOIMP, CBTEINTERNO
      FROM   MCP
      WHERE NROCOMPROBANTE=@NROCOMPROBANTE
      --se borran de mcp, mch
      DELETE MCH WHERE NROCOMPROBANTE = @NROCOMPROBANTE
      DELETE MCP WHERE NROCOMPROBANTE = @NROCOMPROBANTE   
   END
   ELSE
   BEGIN
      DELETE MCHE WHERE NROCOMPROBANTE=@NROCOMPROBANTE
   END
 END
   
 IF @TIPO = 'Entrada' --Entradas de Activos
 BEGIN
  PRINT 'Contabilizando Entradas'
  PRINT ' -Insertando Registro MCH. DB...'
  INSERT INTO MCHE(NROCOMPROBANTE,COMPANIA,TIPO,CUENTA,IDTERCERO,CCOSTO,DETALLE,VALOR,REFERENCIA1,
                  REFERENCIA2,REFERENCIA3,ITEMREF,USUARIO,FECHA,PREFIJO,IDAREA,CLASECONT,ESTADO,PROCESO,GENERA,
                  PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
  SELECT @NROCOMPROBANTE,@COMPANIA,'DB', @CUENTA_ACT, @IDTERCERO_CIA, #T.CCOSTO, #T.OBSERVACION, #T.VALOR,
         #T.IDEVENTO, #T.CNSIACTH, @IDACTIVO, NULL, @USUARIO,DBO.FNK_FECHA_SIN_MLS(GETDATE()),#T.IDEVENTO,
         #T.IDAREA, 'S', 1 ,'MOV_ENT_ACT', 'Movimiento', 'IACT', @CNSIACTH, @CODUNG, @CODPRG
  FROM #T 
  WHERE #T.VALOR<>0

  PRINT ' -Insertando Registro MCH. CR...'
  INSERT INTO MCHE(NROCOMPROBANTE,COMPANIA,TIPO,CUENTA,IDTERCERO,CCOSTO,DETALLE,VALOR,REFERENCIA1,
                  REFERENCIA2,REFERENCIA3,ITEMREF,USUARIO,FECHA,PREFIJO,IDAREA,CLASECONT,ESTADO,PROCESO,GENERA,
                  PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
  SELECT @NROCOMPROBANTE,@COMPANIA,'CR', 
         DBO.FNK_CUENTA_KMCOM(@IDMODELOCONT,'MOV_ACTIVOS','CR',#T.IDEVENTO,#T.IDAREA,#T.CCOSTO,'S',@IDTIPOACTIVO), 
         @IDTERCERO_CIA, #T.CCOSTO, #T.OBSERVACION, #T.VALOR, #T.IDEVENTO,
         #T.CNSIACTH, @IDACTIVO, NULL, @USUARIO,DBO.FNK_FECHA_SIN_MLS(GETDATE()),#T.IDEVENTO, #T.IDAREA, 'S', 1,
         'MOV_ENT_ACT', 'Movimiento','IACT',@CNSIACTH, @CODUNG, @CODPRG
  FROM #T 
  WHERE #T.VALOR<>0
 END
 ELSE
 IF @TIPO = 'Salida' -- Salidad de Activos 
 BEGIN 
  PRINT 'Contabilizando Salidas'
  IF @BAJA = 1
  BEGIN
   -- Baja Depreciaci�n Acumulada
   IF @DEP_ACUMULADA>0
   BEGIN
    PRINT ' -Insertando Registro MCH. DB Baja Depreciaci�n Acumulada...'
    INSERT INTO MCHE(NROCOMPROBANTE,COMPANIA,TIPO,CUENTA,IDTERCERO,CCOSTO,DETALLE,VALOR,REFERENCIA1,
                    REFERENCIA2,REFERENCIA3,ITEMREF,USUARIO,FECHA,PREFIJO,IDAREA,CLASECONT,ESTADO,PROCESO,GENERA,
                    PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
    SELECT @NROCOMPROBANTE,@COMPANIA,'DB', 
           DBO.FNK_CUENTA_KMCOM(@IDMODELOCONT,'DEPRECIACION','CR',@IDTIPOACTIVO,#T.IDAREA,#T.CCOSTO,'S',#T.IDACTIVO), 
           @IDTERCERO_CIA, #T.CCOSTO, #T.OBSERVACION, @DEP_ACUMULADA, 
           #T.IDEVENTO, #T.CNSIACTH, @IDACTIVO, NULL, @USUARIO,DBO.FNK_FECHA_SIN_MLS(GETDATE()),#T.IDEVENTO,
           #T.IDAREA, 'S', 1 ,'DEP_BAJ_ACUMULADA', 'Movimiento', 'IACT', @CNSIACTH, @CODUNG, @CODPRG
    FROM #T 
   END
   -- Baja Ajuste Depreciaci�n Acumulada
   IF @AJU_DEPACUMULADA>0
   BEGIN
    PRINT ' -Insertando Registro MCH. DB Baja de Ajuste Depreciaci�n Acumulada...'
    INSERT INTO MCHE(NROCOMPROBANTE,COMPANIA,TIPO,CUENTA,IDTERCERO,CCOSTO,DETALLE,VALOR,REFERENCIA1,
                    REFERENCIA2,REFERENCIA3,ITEMREF,USUARIO,FECHA,PREFIJO,IDAREA,CLASECONT,ESTADO,PROCESO,GENERA,
                    PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
    SELECT @NROCOMPROBANTE,@COMPANIA,'DB', 
           DBO.FNK_CUENTA_KMCOM(@IDMODELOCONT,'DEPRECIACION_AJI','CR',#T.IDEVENTO,#T.IDAREA,#T.CCOSTO,'S',@IDTIPOACTIVO), 
           @IDTERCERO_CIA, #T.CCOSTO, #T.OBSERVACION, @AJU_DEPACUMULADA, 
           #T.IDEVENTO, #T.CNSIACTH, @IDACTIVO, NULL, @USUARIO,DBO.FNK_FECHA_SIN_MLS(GETDATE()),#T.IDEVENTO,
           #T.IDAREA, 'S', 1 ,'V', 'Movimiento', 'IACT', @CNSIACTH, @CODUNG, @CODPRG
    FROM #T 
   END
   PRINT ' -Insertando Registro MCH DB para Gasto por Baja de Activo...'
   -- Gasto por Baja de Activo
   INSERT INTO MCHE(NROCOMPROBANTE,COMPANIA,TIPO,CUENTA,IDTERCERO,CCOSTO,DETALLE,VALOR,REFERENCIA1,
                   REFERENCIA2,REFERENCIA3,ITEMREF,USUARIO,FECHA,PREFIJO,IDAREA,CLASECONT,ESTADO,PROCESO,GENERA,
                   PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
   SELECT @NROCOMPROBANTE,@COMPANIA,'DB', 
          DBO.FNK_CUENTA_KMCOM(@IDMODELOCONT,'MOV_ACTIVOS','DB',#T.IDEVENTO,#T.IDAREA,#T.CCOSTO,'S',@IDTIPOACTIVO), 
          @IDTERCERO_CIA, #T.CCOSTO, #T.OBSERVACION, 
         abs( @PRECIOCOMERCIAL) +COALESCE(@AJU_ACUMULADO,0) -COALESCE( @DEP_ACUMULADA,0) - COALESCE(@AJU_DEPACUMULADA,0), #T.IDEVENTO,
          #T.CNSIACTH, @IDACTIVO, NULL, @USUARIO,DBO.FNK_FECHA_SIN_MLS(GETDATE()),#T.IDEVENTO, #T.IDAREA, 'S', 1,
          'IACT_BAJ_GASTO', 'Movimiento','IACT',@CNSIACTH, @CODUNG, @CODPRG
   FROM #T 
   -- Baja del Activo Fijo
   PRINT ' -Insertando Registro MCH. CR Baja del Activo Fijo...'
   INSERT INTO MCHE(NROCOMPROBANTE,COMPANIA,TIPO,CUENTA,IDTERCERO,CCOSTO,DETALLE,VALOR,REFERENCIA1,
                   REFERENCIA2,REFERENCIA3,ITEMREF,USUARIO,FECHA,PREFIJO,IDAREA,CLASECONT,ESTADO,PROCESO,GENERA,
                   PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
   SELECT @NROCOMPROBANTE,@COMPANIA,'CR', @CUENTA_ACT, @IDTERCERO_CIA, #T.CCOSTO, #T.OBSERVACION,abs(COALESCE(@PRECIOCOMERCIAL,0)), 
          #T.IDEVENTO, #T.CNSIACTH, @IDACTIVO, NULL, @USUARIO,DBO.FNK_FECHA_SIN_MLS(GETDATE()),#T.IDEVENTO,
          #T.IDAREA, 'S', 1 ,'IACT_BAJA_ACT', 'Movimiento', 'IACT', @CNSIACTH, @CODUNG, @CODPRG
   FROM #T 
   WHERE #T.VALOR<>0
   -- Baja del Ajuste por Inflaci�n
   IF @AJU_ACUMULADO>0
   BEGIN
    PRINT ' -Insertando Registro MCH. CR Baja Ajuste Acumulado del Activo...'
    INSERT INTO MCHE(NROCOMPROBANTE,COMPANIA,TIPO,CUENTA,IDTERCERO,CCOSTO,DETALLE,VALOR,REFERENCIA1,
                    REFERENCIA2,REFERENCIA3,ITEMREF,USUARIO,FECHA,PREFIJO,IDAREA,CLASECONT,ESTADO,PROCESO,GENERA,
                    PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
    SELECT @NROCOMPROBANTE,@COMPANIA,'CR', 
           DBO.FNK_CUENTA_KMCOM(@IDMODELOCONT,'INFLACION','DB',#T.IDEVENTO,#T.IDAREA,#T.CCOSTO,'S',@IDTIPOACTIVO), 
           @IDTERCERO_CIA, #T.CCOSTO, #T.OBSERVACION, @AJU_ACUMULADO, 
           #T.IDEVENTO, #T.CNSIACTH, @IDACTIVO, NULL, @USUARIO,DBO.FNK_FECHA_SIN_MLS(GETDATE()),#T.IDEVENTO,
           #T.IDAREA, 'S', 1 ,'IACT_BAJA_AJI', 'Movimiento', 'IACT', @CNSIACTH, @CODUNG, @CODPRG
    FROM #T 
   END
  END
  ELSE
  BEGIN
   PRINT ' -Insertando Registro MCH. DB...'
   INSERT INTO MCHE(NROCOMPROBANTE,COMPANIA,TIPO,CUENTA,IDTERCERO,CCOSTO,DETALLE,VALOR,REFERENCIA1,
                   REFERENCIA2,REFERENCIA3,ITEMREF,USUARIO,FECHA,PREFIJO,IDAREA,CLASECONT,ESTADO,PROCESO,GENERA,
                   PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
   SELECT @NROCOMPROBANTE,@COMPANIA,'DB', 
          DBO.FNK_CUENTA_KMCOM(@IDMODELOCONT,'MOV_ACTIVOS','DB',#T.IDEVENTO,#T.IDAREA,#T.CCOSTO,'S',@IDTIPOACTIVO), 
          @IDTERCERO_CIA, #T.CCOSTO, #T.OBSERVACION, #T.VALOR,#T.IDEVENTO,
          #T.CNSIACTH, @IDACTIVO, NULL, @USUARIO,DBO.FNK_FECHA_SIN_MLS(GETDATE()),#T.IDEVENTO, #T.IDAREA, 'S', 1,
          'MOV_ENT_ACT', 'Movimiento','IACT',@CNSIACTH, @CODUNG, @CODPRG
   FROM #T 
   WHERE #T.VALOR<>0 

   PRINT ' -Insertando Registro MCH. CR...'
   INSERT INTO MCHE(NROCOMPROBANTE,COMPANIA,TIPO,CUENTA,IDTERCERO,CCOSTO,DETALLE,VALOR,REFERENCIA1,
                   REFERENCIA2,REFERENCIA3,ITEMREF,USUARIO,FECHA,PREFIJO,IDAREA,CLASECONT,ESTADO,PROCESO,GENERA,
                   PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
   SELECT @NROCOMPROBANTE,@COMPANIA,'CR', @CUENTA_ACT, @IDTERCERO_CIA, #T.CCOSTO, #T.OBSERVACION, #T.VALOR,
          #T.IDEVENTO, #T.CNSIACTH, @IDACTIVO, NULL, @USUARIO,DBO.FNK_FECHA_SIN_MLS(GETDATE()),#T.IDEVENTO,
          #T.IDAREA, 'S', 1 ,'MOV_ENT_ACT', 'Movimiento', 'IACT', @CNSIACTH, @CODUNG, @CODPRG
   FROM #T 
   WHERE #T.VALOR<>0
  END
 END
 ELSE
 IF @TIPO = 'Traslado' -- Traslado de Activos 
 BEGIN
  PRINT 'Contabilizando Traslados'
  PRINT ' -Insertando Registro MCH. DB...'
  INSERT INTO MCHE(NROCOMPROBANTE,COMPANIA,TIPO,CUENTA,IDTERCERO,CCOSTO,DETALLE,VALOR,REFERENCIA1,
                  REFERENCIA2,REFERENCIA3,ITEMREF,USUARIO,FECHA,PREFIJO,IDAREA,CLASECONT,ESTADO,PROCESO,GENERA,
                  PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
  SELECT @NROCOMPROBANTE,@COMPANIA,'DB', 
         DBO.FNK_CUENTA_KMCOM(@IDMODELOCONT,'MOV_ACTIVOS','DB',#T.IDEVENTO,#T.IDAREA,#T.CCOSTO,'S',@IDTIPOACTIVO), 
         @IDTERCERO_CIA, #T.CCOSTO, #T.OBSERVACION, #T.VALOR,#T.IDEVENTO,
         #T.CNSIACTH, @IDACTIVO, NULL, @USUARIO,DBO.FNK_FECHA_SIN_MLS(GETDATE()),#T.IDEVENTO, #T.IDAREA, 'S', 1,
         'MOV_TRASL_ACT', 'Movimiento','IACT',@CNSIACTH, @CODUNG, @CODPRG
  FROM #T 
  WHERE #T.VALOR<>0

  PRINT ' -Insertando Registro MCH. CR...'
  INSERT INTO MCHE(NROCOMPROBANTE,COMPANIA,TIPO,CUENTA,IDTERCERO,CCOSTO,DETALLE,VALOR,REFERENCIA1,
                  REFERENCIA2,REFERENCIA3,ITEMREF,USUARIO,FECHA,PREFIJO,IDAREA,CLASECONT,ESTADO,PROCESO,GENERA,
                  PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG)
  SELECT @NROCOMPROBANTE,@COMPANIA,'CR', @CUENTA_ACT, @IDTERCERO_CIA, @CCOSTO_IACT, #T.OBSERVACION, #T.VALOR,
         #T.IDEVENTO, #T.CNSIACTH, @IDACTIVO, NULL, @USUARIO,DBO.FNK_FECHA_SIN_MLS(GETDATE()),#T.IDEVENTO, @IDAREA_IACT, 'S', 1,
         'MOV_TRASL_ACT', 'Movimiento','IACT',@CNSIACTH, @CODUNG, @CODPRG
  FROM #T 
  WHERE #T.VALOR<>0
 END
 ELSE
  PRINT 'No Existe el TIPO de Evento. '+ISNULL(@TIPO,'')

 IF LEFT(@NROCOMPROBANTE,2) <> 'IX'
 BEGIN
  PRINT 'Poniendo Estado de CONTABILIZADA en 1a Tabla IACTH'
  UPDATE IACTH SET CONTABILIZADA=1, MARCACONT=0, NROCOMPROBANTE=@NROCOMPROBANTE, APLICADA=1 WHERE IACTH.CNSIACTH=@CNSIACTH
 END

   EXEC SPK_NC_REVISAMCPE @NROCOMPROBANTE, @COMPANIA, @USUARIO, @SEDE, @SYS_COMPUTERNAME  
   EXEC SPK_PASA_MCP_MCPNIIF @NROCOMPROBANTE, @COMPANIA, @USUARIO, @SYS_COMPUTERNAME, @SEDE,@COM,''

 DROP TABLE #T
END
