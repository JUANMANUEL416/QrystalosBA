SET NOCOUNT ON;
SELECT DBO.FNK_VALORVARIABLE('CONTAB_GASTOVEN_UNI') AS CONTAB_GASTOVEN_UNI,
  DBO.FNK_VALORVARIABLE('IDINVDEVPROVEEDOR') AS IDINVDEVPROVEEDOR,
  DBO.FNK_VALORVARIABLE('IDTIPOMOVDEV_CLIENTE') AS IDTIPOMOVDEV_CLIENTE,
  DBO.FNK_VALORVARIABLE('IDINVMOVVENTAFACTURA') AS IDINVMOVVENTAFACTURA;

SELECT M.CNSMOV, M.IDTIPOMOV, YEAR(M.FECHAMOV) YM, MONTH(M.FECHAMOV) MM,
  YEAR(M.FECHACONF) YC, MONTH(M.FECHACONF) MC,
  M.CONTABILIZADA, M.NROCOMPROBANTE, M.IDTERCERO, M.IDPLAN
FROM IMOV M
WHERE M.IDBODEGA=N'044' AND M.MARCACONT=1 AND COALESCE(M.CONTABILIZADA,0)=0 AND M.ESTADO=1
ORDER BY M.IDTIPOMOV;

SELECT SUM(CASE WHEN COALESCE(CONTABILIZADA,0)=2 THEN 1 ELSE 0 END) CON_ERROR,
  SUM(CASE WHEN COALESCE(CONTABILIZADA,0)=0 THEN 1 ELSE 0 END) PEND
FROM IMOV WHERE IDBODEGA=N'044' AND MARCACONT=1 AND ESTADO=1;

