CREATE OR ALTER PROCEDURE DBO.SPQ_HACTRAND
@JSON  NVARCHAR(MAX)
WITH
ENCRYPTION
AS

DECLARE	 @PARAMETROS	NVARCHAR(MAX)	,@MODELO			VARCHAR(100)	,@METODO		VARCHAR(100)	,@USUARIO		VARCHAR(12)
		,@GRUPO			VARCHAR(8)		,@SYS_COMPUTERNAME	VARCHAR(254)	,@SEDE			VARCHAR(5)		,@FECHA			VARCHAR(10)   
		,@CNSHACTRAN    VARCHAR(20)		,@FECHA1			DATETIME		,@SQL			VARCHAR(MAX)	,@IDMEDICO		VARCHAR(20)
		,@IDAFILIADO	VARCHAR(20)		,@NVOCONSEC			VARCHAR(20)		,@COMPANIA		VARCHAR(2)		,@COLUMNAS		VARCHAR(MAX) 
		,@ITEM			INTEGER			,@WHERES			VARCHAR(MAX)	,@QUERY			VARCHAR(8000)	,@NOMBREENTIDAD VARCHAR(254)
		,@NOMBRESEDE	VARCHAR(254)	,@NOREFERENCIA		VARCHAR(20)		,@PROCEDENCIA	VARCHAR(10)		,@FIRMA			VARCHAR(MAX)
		,@TIPOESTANCIA	VARCHAR(20)		,@DIRECCION			VARCHAR(254)	,@TELEFONOS		VARCHAR(254)	,@CIUDAD		VARCHAR(254) 
		,@NIT			VARCHAR(25)		,@DV				VARCHAR(1)
