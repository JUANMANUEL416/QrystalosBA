					-- CI: citas facturadas individuales
					SELECT
						CIT.CNSHACTRAN,
						'CI',
						CIT.CONSECUTIVO AS NOREFERENCIA,
						CASE WHEN FTR.IDTERCERO <> @IDNITFONSAT THEN FTR.N_FACTURA ELSE NULL END,
						CASE WHEN FTR.IDTERCERO = @IDNITFONSAT THEN FTR.N_FACTURA ELSE NULL END,
						'Alerta',
						'No',
						COALESCE(FTR.VR_TOTAL, CIT.VALORTOTAL),
						CIT.IDTERCEROCA,
						COALESCE(CIT.SIRAS, B.SIRAS, '')
					FROM CIT
					INNER JOIN FTR ON FTR.NOREFERENCIA = CIT.CONSECUTIVO AND FTR.PROCEDENCIA = 'CI'
