	IF @METODO = 'RELIQUIDAR'
	BEGIN
		IF COALESCE(@CNSHACTRAN,'') <> ''
		BEGIN      
			DECLARE @CNSITEM INTEGER = 0
			DECLARE @IDNITFONSAT VARCHAR(20) = DBO.FNK_VALORVARIABLE('IDNITFONSAT')
			DECLARE @IDTARIFASOAT VARCHAR(20) = DBO.FNK_VALORVARIABLE('IDTARIFASOAT')
			DECLARE @TERCATASEGURADORA VARCHAR(20) = DBO.FNK_VALORVARIABLE('TERCATASEGURADORA')
			DECLARE @HAYASEGURADORA BIT = CASE WHEN EXISTS (
					SELECT 1
					FROM TER INNER JOIN TEXCA ON TEXCA.IDTERCERO = TER.IDTERCERO
