							(COALESCE(A.N_FACTURA,'') <> '' AND FTR.N_FACTURA = A.N_FACTURA)
							OR (COALESCE(A.N_FACTURA,'') = '' AND FTR.IDTERCERO = A.IDTERCEROCA)
							OR (A.IDTERCEROCA IS NULL)
