      ,@TRATAMIENTO1      VARCHAR(500),       @DIAGNOSTICO1      VARCHAR(500)
       --CMT HACTRAND
declare  @error as varchar(max)

DECLARE @TBLERRORES TABLE(ERROR VARCHAR(MAX))						 

BEGIN

	/*SPQ_HACTRAND
		Modulo:		SOAT
		Funcion:	Metodos para agregar, y actualizar la información de los detalles de atenciones de los accidentes de transito 
		Metodos:	CONSULTAR, UPDATE, INSERT, DELETE, LLENAR, DATOSAFI, RELIQUIDAR, FTRVLR
		Elabora:	13-09-2023 Edgardo Martinez
		Modificado: 29-07-2026 RELIQUIDAR — anti-duplicados (#HACTRANPREV + QX) y optimización
	*/

	SET DATEFORMAT dmy
	
	SELECT *
	INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)  AS JSON
	)

	SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON

	SELECT @WHERES = WHERES
	FROM OPENJSON (@PARAMETROS) WITH (
        WHERES         VARCHAR(2000)            '$.WHERES'        
    )
	PRINT '@WHERES: ' + @WHERES

	SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO) FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SEDE = IDSEDE, @COMPANIA=COMPANIA FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
	IF ( DBO.FNK_VALORVARIABLE('DATOSPROPIETARIO') =  'SEDE' )
	BEGIN
		PRINT 'ENTRE POR SED'
		SELECT @NOMBRESEDE =  DESCRIPCION , @DIRECCION = SED.DIRECCION , @TELEFONOS = SED.TELEFONOS , @CIUDAD = CIU.NOMBRE, @NIT = SED.NIT FROM SED LEFT JOIN CIU ON  SED.CIUDAD= CIU.CIUDAD   WHERE IDSEDE = @SEDE
	END
	ELSE
	BEGIN
		PRINT 'ENTRE POR DPR'
		SELECT @NOMBREENTIDAD =  COALESCE(  TER_REP.RAZONSOCIAL , COALESCE( CONCAT( TER. NOMBRES_R_LEGAL  , '' ,TER. P_APELLIDO_R_LEGAL  , '' , TER. S_APELLIDO_R_LEGAL ) , TER.RAZONSOCIAL   ) ) 
		, @DIRECCION = COALESCE( TER_REP.DIRECCION , TER.DIRECCION )   
		, @TELEFONOS =  COALESCE( TER_REP.TELEFONOS , TER.TELEFONOS  ) 
		, @CIUDAD = CIU.NOMBRE
		, @NIT = COALESCE( TER_REP.NIT , TER. NIT_R  )   
		, @DV = COALESCE( TER_REP.DV , TER.DV  )  
		FROM TER 
			LEFT OUTER JOIN TER TER_REP ON COALESCE(TER.NIT_R,'NO_TIENE_NIT') =COALESCE(TER_REP.NIT,'------')
			LEFT JOIN CIU ON TER.CIUDAD= CIU.CIUDAD OR  TER_REP.CIUDAD= CIU.CIUDAD 
		WHERE TER.IDTERCERO= dbo.FNK_VALORVARIABLE('IDTERCEROINSTALADO')
			and COALESCE(  TER_REP.RAZONSOCIAL , COALESCE( CONCAT( TER. NOMBRES_R_LEGAL  , '' ,TER. P_APELLIDO_R_LEGAL  , '' , TER. S_APELLIDO_R_LEGAL ) , coalesce(TER.RAZONSOCIAL ,'')  ) )<>''

	END

	


	print 'parametros: ' + @PARAMETROS
	print 'usuario: ' + COALESCE( @USUARIO,'*sin usuario*' ) +  ' | grupo: ' +   COALESCE( @GRUPO,'*sin @GRUPO*' )
	PRINT 'Compañia: ' +  COALESCE( @COMPANIA,'*sin @COMPANIA*' ) + ' | Razon Social: ' +    COALESCE( @NOMBREENTIDAD,'*sin @NOMBREENTIDAD*' )
	PRINT 'Sede: ' +  COALESCE( @SEDE,'*sin @SEDE*' )  + ' | Nombre Sede: ' +     COALESCE( @NOMBRESEDE,'*sin @NOMBRESEDE*' )
	SELECT @CNSHACTRAN = CNSHACTRAN , @ITEM =ITEM
	FROM OPENJSON(@PARAMETROS)
	WITH(CNSHACTRAN  VARCHAR(20) '$.CNSHACTRAN'
		, ITEM	INTEGER	'$.ITEM')
	
	IF @METODO = 'LLENAR'
	BEGIN
		SELECT 'OK' OK
		SELECT 
				
			coalesce( CNSHACTRAN , 	'' )         CNSHACTRAN ,
			coalesce( ITEM , 	'' )               ITEM ,
			coalesce( PROCEDENCIA , 	'' )       PROCEDENCIA  ,
			coalesce( NOREFERENCIA , 	'' )       NOREFERENCIA ,
			coalesce( N_FCT_ASEG , 	'' )         N_FCT_ASEG ,
			coalesce( N_FCT_FYG , 	'' )         N_FCT_FYG  ,
			coalesce( TA , 	'' )                 TA ,
			coalesce( FC , 	'' )                 FC ,
			coalesce( FR , 	'' )                 FR ,
			coalesce( TEMP1 , 	'' )             TEMP1  ,
			coalesce( ESTADOCONC , 	'' )         ESTADOCONC ,
			coalesce( ESTADOEMBRIAGUEZ , 	'' )   ESTADOEMBRIAGUEZ ,
			coalesce( CABEZA1 , 	'' )           CABEZA1  ,
			coalesce( CUELLO1 , 	'' )           CUELLO1  ,
			coalesce( TORAX1 , 	'' )             TORAX1 ,
			coalesce( ABDOMEN1 , 	'' )           ABDOMEN1 ,
			coalesce( GENITOURINARIO1 , 	'' )   GENITOURINARIO1  ,
			coalesce( PELVIS1 , 	'' )           PELVIS1  ,
			coalesce( DORSO1 , 	'' )             DORSO1 ,
			coalesce( NEUROLOGICO1 , 	'' )       NEUROLOGICO1 ,
			coalesce( DIAGNOSTICO1 , 	'' )       DIAGNOSTICO1 ,
			coalesce( TRATAMIENTO1 , 	'' )       TRATAMIENTO1,
			coalesce( REMITIDADE , 	'' )         REMITIDADE ,
			coalesce( REMITIDADECIUDAD , 	'' )   REMITIDADECIUDAD ,
			coalesce( FECHA_RD , 	'' )           FECHA_RD ,
			coalesce( DECLARACIONDE , 	'' )     DECLARACIONDE  ,
			coalesce( NOIDENTDECLARACION , 	'' ) NOIDENTDECLARACION ,
			coalesce( EXPEDIDAENDECLA , 	'' )   EXPEDIDAENDECLA  ,
			coalesce( TIPOGASGLOW , 	'' )       TIPOGASGLOW  ,
			coalesce( VLRGASTADO , 	0 )          VLRGASTADO ,
			coalesce( IDDX , 	'' )               IDDX ,
			coalesce( IDTERCEROEXT , 	'' )       IDTERCEROEXT ,
			coalesce( NRADICACIONF , 	'' )       NRADICACIONF ,
			coalesce( SIRAS , 	'' )             SIRAS  ,
			DBO.FNK_GETDATE() FECHAACTUAL

		FROM HACTRAND
			
		WHERE CNSHACTRAN=@CNSHACTRAN and ITEM =@ITEM			
	END--- LLENAR
	IF @METODO = 'INSERT'
	BEGIN
		SELECT *  INTO #TMPHACTRAND
		FROM OPENJSON(@PARAMETROS)
		WITH(
				CNSHACTRAN         varchar (20)             '$.CNSHACTRAN',
				ITEM               INTEGER	                '$.ITEM',
				PROCEDENCIA        varchar (10)             '$.PROCEDENCIA',
				NOREFERENCIA       varchar (16)             '$.NOREFERENCIA',
				N_FCT_ASEG         varchar (16)             '$.N_FCT_ASEG',
				N_FCT_FYG          varchar (16)             '$.N_FCT_FYG',
				TA                 varchar (10)             '$.TA',
				FC                 varchar (4)              '$.FC',
				FR                 varchar (4)              '$.FR',
				TEMP1              varchar (4)              '$.TEMP1',
				ESTADOCONC         varchar (11)             '$.ESTADOCONC',
				ESTADOEMBRIAGUEZ   varchar (2)              '$.ESTADOEMBRIAGUEZ',
				CABEZA1            varchar (500)            '$.CABEZA1',
				CUELLO1            varchar (500)            '$.CUELLO1',
				TORAX1             varchar (500)            '$.TORAX1',
				ABDOMEN1           varchar (500)            '$.ABDOMEN1',
				GENITOURINARIO1    varchar (500)            '$.GENITOURINARIO1',
				PELVIS1            varchar (500)            '$.PELVIS1',
				DORSO1             varchar (500)            '$.DORSO1',
				NEUROLOGICO1       varchar (500)            '$.NEUROLOGICO1',
				DIAGNOSTICO1       varchar (500)            '$.DIAGNOSTICO1',
				TRATAMIENTO1       varchar (500)            '$.TRATAMIENTO1',
				REMITIDADE         varchar (50)             '$.REMITIDADE',
				REMITIDADECIUDAD   varchar (5)              '$.REMITIDADECIUDAD',
				FECHA_RD           datetime		            '$.FECHA_RD',
				DECLARACIONDE      varchar (50)             '$.DECLARACIONDE',
				NOIDENTDECLARACION varchar (20)             '$.NOIDENTDECLARACION',
				EXPEDIDAENDECLA    varchar (20)             '$.EXPEDIDAENDECLA',
				TIPOGASGLOW        varchar (20)             '$.TIPOGASGLOW',
				VLRGASTADO         decimal (9)              '$.VLRGASTADO',
				IDDX               varchar (10)             '$.IDDX',
				IDTERCEROEXT       varchar (20)             '$.IDTERCEROEXT',
				NRADICACIONF       varchar (40)             '$.NRADICACIONF',
				SIRAS              varchar (20)             '$.SIRAS' ,
				CONDICIONACC		varchar (20)            '$.CONDICIONACC' 
		)
		

		IF NOT EXISTS(
			SELECT * 
			FROM HACTRAND inner join #TMPHACTRAND A
			ON HACTRAND.CNSHACTRAN= A.CNSHACTRAN  collate database_default
			AND HACTRAND.ITEM = A.ITEM 
			)
		BEGIN
			
			SELECT 	@ITEM =COALESCE(MAX(HACTRAND.ITEM),0) +1 
			FROM HACTRAND inner join #TMPHACTRAND A 	ON HACTRAND.CNSHACTRAN= A.CNSHACTRAN  collate database_default 
			WHERE 1=1 
			

			PRINT 'ITEM : ' + CONVERT( VARCHAR(20) , COALESCE( @ITEM, 0 ) ) 
			UPDATE #TMPHACTRAND SET  CNSHACTRAN =@CNSHACTRAN , ITEM = COALESCE( @ITEM, 0 )  WHERE 1=1 



			SELECT @COLUMNAS = DBO.FNK_COLUMNAS_TABLAS('HACTRAND') 

			BEGIN TRY
				PRINT 'INSERTANDO EL NUEVO REGISTRO'
				SET @SQL = '
						INSERT INTO HACTRAND ( ' +  @COLUMNAS + ')
						SELECT ' +  @COLUMNAS + ' FROM #TMPHACTRAND
					'

				INSERT INTO API_LOG ( FECHA , COMMAND  , COMMANDTYPE  , USUARIO )
				SELECT  GETDATE() , @SQL ,'SQL' , @USUARIO 
				
				print @SQL
				execute ( @SQL)

			SELECT 'OK' OK
			SELECT HACTRAND.* 
			FROM HACTRAND inner join #TMPHACTRAND A
			ON HACTRAND.CNSHACTRAN= A.CNSHACTRAN  collate database_default
			AND HACTRAND.ITEM = A.ITEM 


			END TRY
			BEGIN CATCH

				SELECT  @error = CONCAT ( 'Error Numero : ', CONVERT(VARCHAR(100), ERROR_NUMBER() ) , 
						' | Severidad : ' , CONVERT(VARCHAR(100), ERROR_SEVERITY() )  ,
						' | Estado del Error : ' ,  CONVERT(VARCHAR(100),  ERROR_STATE()  ) ,
						' | Procedimiento de Error : ' , CONVERT(VARCHAR(100), ERROR_PROCEDURE() ) ,
						' | Linea : ', CONVERT(VARCHAR(100), ERROR_LINE() ) ,
						' | Mensaje de Error : ',ERROR_MESSAGE() ) 

				PRINT 'ERROR AL INSERTAR' + CONVERT(VARCHAR(100), @@ERROR) + ' :  ' +  @error

				INSERT INTO @TBLERRORES(ERROR) SELECT 'ERROR AL INSERTAR HACTRAN: ' + CONVERT(VARCHAR(100),  @@ERROR  + ' :  ' +  @error )
			END CATCH
			--RETURN
		END 
		ELSE 
		BEGIN 

			PRINT 'YA ESTA CREADO EL ACCIDENTE NO PUEDO INSERTARLO EL MISMO IDAFILIADO ACCIDENTADO EL MISMO DIA'
			INSERT INTO @TBLERRORES(ERROR) SELECT  'YA ESTA CREADO EL ACCIDENTE NO PUEDO INSERTARLO EL MISMO IDAFILIADO ACCIDENTADO EL MISMO DIA'   
			
		END
	END	---INSERT
	IF @METODO = 'UPDATE'
	BEGIN
		SELECT * INTO #TMPHACTRANU
		FROM OPENJSON(@PARAMETROS)
		WITH(
				CNSHACTRAN         varchar (20)             '$.CNSHACTRAN',
				ITEM               INTEGER	                '$.ITEM',
				PROCEDENCIA        varchar (10)             '$.PROCEDENCIA',
				NOREFERENCIA       varchar (16)             '$.NOREFERENCIA',
				N_FCT_ASEG         varchar (16)             '$.N_FCT_ASEG',
				N_FCT_FYG          varchar (16)             '$.N_FCT_FYG',
				TA                 varchar (10)             '$.TA',
				FC                 varchar (4)              '$.FC',
				FR                 varchar (4)              '$.FR',
				TEMP1              varchar (4)              '$.TEMP1',
				ESTADOCONC         varchar (11)             '$.ESTADOCONC',
				ESTADOEMBRIAGUEZ   varchar (2)              '$.ESTADOEMBRIAGUEZ',
				CABEZA1            varchar (500)            '$.CABEZA1',
				CUELLO1            varchar (500)            '$.CUELLO1',
				TORAX1             varchar (500)            '$.TORAX1',
				ABDOMEN1           varchar (500)            '$.ABDOMEN1',
				GENITOURINARIO1    varchar (500)            '$.GENITOURINARIO1',
				PELVIS1            varchar (500)            '$.PELVIS1',
				DORSO1             varchar (500)            '$.DORSO1',
				NEUROLOGICO1       varchar (500)            '$.NEUROLOGICO1',
				DIAGNOSTICO1       varchar (500)            '$.DIAGNOSTICO1',
				TRATAMIENTO1       varchar (500)            '$.TRATAMIENTO1',
				REMITIDADE         varchar (50)             '$.REMITIDADE',
				REMITIDADECIUDAD   varchar (5)              '$.REMITIDADECIUDAD',
				FECHA_RD           datetime		            '$.FECHA_RD',
				DECLARACIONDE      varchar (50)             '$.DECLARACIONDE',
				NOIDENTDECLARACION varchar (20)             '$.NOIDENTDECLARACION',
				EXPEDIDAENDECLA    varchar (20)             '$.EXPEDIDAENDECLA',
				TIPOGASGLOW        varchar (20)             '$.TIPOGASGLOW',
				VLRGASTADO         decimal (9)              '$.VLRGASTADO',
				IDDX               varchar (10)             '$.IDDX',
				IDTERCEROEXT       varchar (20)             '$.IDTERCEROEXT',
				NRADICACIONF       varchar (40)             '$.NRADICACIONF',
				SIRAS              varchar (20)             '$.SIRAS'
		)

		IF NOT EXISTS (
			SELECT * 
			FROM HACTRAND inner join #TMPHACTRANU A
			ON HACTRAND.CNSHACTRAN= A.CNSHACTRAN  collate database_default
			AND HACTRAND.ITEM = A.ITEM 			
		)
		BEGIN 
			PRINT 'NO EXISTE EL HACTRAN PARA ACTUALIZARLO'
			INSERT INTO @TBLERRORES(ERROR) SELECT  'NO EXISTE EL HACTRAN PARA ACTUALIZARLO' 
		END
		ELSE
		BEGIN
			BEGIN TRY
				PRINT 'ACTUALIZANDO : ' + @CNSHACTRAN 
				-- SELECT * INTO TMPH FROM #TMPHACTRAND
				-- DROP TABLE TMPH

				SET @SQL = ' 
					UPDATE HACTRAND SET
						CNSHACTRAN         =  #TMPHACTRANU.CNSHACTRAN ,
						ITEM               =  #TMPHACTRANU.ITEM ,
						PROCEDENCIA        =  #TMPHACTRANU.PROCEDENCIA ,
						NOREFERENCIA       =  #TMPHACTRANU.NOREFERENCIA ,
						N_FCT_ASEG         =  #TMPHACTRANU.N_FCT_ASEG ,
						N_FCT_FYG          =  #TMPHACTRANU.N_FCT_FYG ,
						TA                 =  #TMPHACTRANU.TA ,
						FC                 =  #TMPHACTRANU.FC ,
						FR                 =  #TMPHACTRANU.FR ,
						TEMP1              =  #TMPHACTRANU.TEMP1 ,
						ESTADOCONC         =  #TMPHACTRANU.ESTADOCONC ,
						ESTADOEMBRIAGUEZ   =  #TMPHACTRANU.ESTADOEMBRIAGUEZ ,
						CABEZA1            =  #TMPHACTRANU.CABEZA1 ,
						CUELLO1            =  #TMPHACTRANU.CUELLO1 ,
						TORAX1             =  #TMPHACTRANU.TORAX1 ,
						ABDOMEN1           =  #TMPHACTRANU.ABDOMEN1 ,
						GENITOURINARIO1    =  #TMPHACTRANU.GENITOURINARIO1 ,
						PELVIS1            =  #TMPHACTRANU.PELVIS1 ,
						DORSO1             =  #TMPHACTRANU.DORSO1 ,
						NEUROLOGICO1       =  #TMPHACTRANU.NEUROLOGICO1 ,
						DIAGNOSTICO1       =  #TMPHACTRANU.DIAGNOSTICO1 ,
						TRATAMIENTO1       =  #TMPHACTRANU.TRATAMIENTO1 ,
						REMITIDADE         =  #TMPHACTRANU.REMITIDADE ,
						REMITIDADECIUDAD   =  #TMPHACTRANU.REMITIDADECIUDAD ,
						FECHA_RD           =  #TMPHACTRANU.FECHA_RD ,
						DECLARACIONDE      =  #TMPHACTRANU.DECLARACIONDE ,
						NOIDENTDECLARACION =  #TMPHACTRANU.NOIDENTDECLARACION ,
						EXPEDIDAENDECLA    =  #TMPHACTRANU.EXPEDIDAENDECLA ,
						TIPOGASGLOW        =  #TMPHACTRANU.TIPOGASGLOW ,
						VLRGASTADO         =  #TMPHACTRANU.VLRGASTADO ,
						IDDX               =  #TMPHACTRANU.IDDX ,
						IDTERCEROEXT       =  #TMPHACTRANU.IDTERCEROEXT ,
						NRADICACIONF       =  #TMPHACTRANU.NRADICACIONF ,
						SIRAS              =  #TMPHACTRANU.SIRAS 
					FROM HACTRAND INNER JOIN #TMPHACTRANU 
						ON HACTRAND.CNSHACTRAN= #TMPHACTRANU.CNSHACTRAN 
						AND HACTRAND.ITEM= #TMPHACTRANU.ITEM 
				'
				INSERT INTO API_LOG ( FECHA , COMMAND  , COMMANDTYPE  , USUARIO )
				SELECT  GETDATE() , @SQL ,'SQL' , @USUARIO 
				print @SQL
				execute ( @SQL)
				
				-- RESULTADO DEL UPDATE
				SELECT 'OK' OK
				SELECT * 
				FROM HACTRAND inner join #TMPHACTRANU A
				ON HACTRAND.CNSHACTRAN= A.CNSHACTRAN  collate database_default
				AND HACTRAND.ITEM = A.ITEM 

			END TRY
			BEGIN CATCH
			
				SELECT  @error = CONCAT ( 'Error Numero : ', CONVERT(VARCHAR(100), ERROR_NUMBER() ) , 
						' | Severidad : ' , CONVERT(VARCHAR(100), ERROR_SEVERITY() )  ,
						' | Estado del Error : ' ,  CONVERT(VARCHAR(100),  ERROR_STATE()  ) ,
						' | Procedimiento de Error : ' , CONVERT(VARCHAR(100), ERROR_PROCEDURE() ) ,
						' | Linea : ', CONVERT(VARCHAR(100), ERROR_LINE() ) ,
						' | Mensaje de Error : ',ERROR_MESSAGE() ) 

				PRINT 'NO PUEDO ACTUALIZAR EL HACTRAN: ' + @CNSHACTRAN   + ' : ' + @@ERROR  + ' :  ' +  @error
				INSERT INTO @TBLERRORES(ERROR) SELECT  'NO PUEDO  ACTUALIZAR EL HACTRAN: ' + @CNSHACTRAN  + ' : ' + @@ERROR  + ' :  ' +  @error
			
			END CATCH
		END
	END --- UPDATE

	IF @METODO = 'DELETE'
	BEGIN
		DECLARE @DELETE_TRANCOUNT INT = @@TRANCOUNT

		IF COALESCE(@CNSHACTRAN, '') = '' OR @ITEM IS NULL
		BEGIN
			INSERT INTO @TBLERRORES(ERROR)
			SELECT 'Debe indicar CNSHACTRAN e ITEM para eliminar el registro.'
		END
		ELSE
		BEGIN TRY
			IF @DELETE_TRANCOUNT = 0
				BEGIN TRANSACTION
			ELSE
				SAVE TRANSACTION DELETE_HACTRAND

			IF NOT EXISTS (
				SELECT 1
				FROM HACTRAND WITH (UPDLOCK, HOLDLOCK)
				WHERE CNSHACTRAN = @CNSHACTRAN
				  AND ITEM = @ITEM
			)
			BEGIN
				RAISERROR('No existe el registro de HACTRAND que se intenta eliminar.', 16, 1)
			END

			SELECT @PROCEDENCIA = PROCEDENCIA
			FROM HACTRAND WITH (UPDLOCK, HOLDLOCK)
			WHERE CNSHACTRAN = @CNSHACTRAN
			  AND ITEM = @ITEM

			IF UPPER(LTRIM(RTRIM(COALESCE(@PROCEDENCIA, '')))) <> 'EXTERNO'
			BEGIN
				RAISERROR('Solo se pueden eliminar registros de procedencia EXTERNO.', 16, 1)
			END

			DELETE FROM HACTRAND
			WHERE CNSHACTRAN = @CNSHACTRAN
			  AND ITEM = @ITEM
			  AND UPPER(LTRIM(RTRIM(COALESCE(PROCEDENCIA, '')))) = 'EXTERNO'

			UPDATE H
			SET H.VLRGASTADO = T.VLR_TOTAL,
				H.VLRGASTOEXTERNO = T.VLR_EXTERNO,
				H.VLRFALTA = H.TOPE - T.VLR_TOTAL
			FROM HACTRAN H
			CROSS APPLY (
				SELECT
					COALESCE(SUM(D.VLRGASTADO), 0) AS VLR_TOTAL,
					COALESCE(SUM(CASE WHEN D.PROCEDENCIA = 'EXTERNO' THEN D.VLRGASTADO ELSE 0 END), 0) AS VLR_EXTERNO
				FROM HACTRAND D
				WHERE D.CNSHACTRAN = H.CNSHACTRAN
			) T
			WHERE H.CNSHACTRAN = @CNSHACTRAN

			SET @SQL = 'DELETE HACTRAND CNSHACTRAN=' + @CNSHACTRAN + ', ITEM=' + CONVERT(VARCHAR(20), @ITEM)
			INSERT INTO API_LOG (FECHA, COMMAND, COMMANDTYPE, USUARIO)
			SELECT DBO.FNK_GETDATE(), @SQL, 'SQL', @USUARIO

			IF @DELETE_TRANCOUNT = 0
				COMMIT TRANSACTION

