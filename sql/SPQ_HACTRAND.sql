						COALESCE(FTR.VR_TOTAL, AUT.VALORTOTAL) AS VLRGASTADO,
						AUT.IDTERCEROCA AS IDTERCEROEXT,
						COALESCE(AUT.SIRAS, B.SIRAS, '') AS SIRAS
