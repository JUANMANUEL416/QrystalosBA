						AND FTR.PROCEDENCIA = 'SALUD'
						AND (
							(COALESCE(FTR.ESTADO,'P') <> 'A' AND COALESCE(FTR.TIPOANULACION,'') <> 'NC')
							OR FTR.CNSFCT IS NULL
						)
