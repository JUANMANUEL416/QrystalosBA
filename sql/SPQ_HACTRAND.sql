							(
								PREV.NOREFERENCIA = H.NOREFERENCIA
								AND COALESCE(PREV.N_FCT_ASEG,'') <> ''
								AND PREV.N_FCT_ASEG = COALESCE(H.N_FCT_ASEG,'')
							)
							OR
							(
								PREV.NOREFERENCIA = H.NOREFERENCIA
								AND COALESCE(PREV.N_FCT_FYG,'') <> ''
								AND PREV.N_FCT_FYG = COALESCE(H.N_FCT_FYG,'')
							)
							OR
							(
								PREV.NOREFERENCIA = H.NOREFERENCIA
								AND COALESCE(PREV.IDTERCEROEXT,'') <> ''
								AND PREV.IDTERCEROEXT = COALESCE(H.IDTERCEROEXT,'')
							)
							OR
							(
								PREV.NOREFERENCIA = 'VARIOS'
								AND H.NOREFERENCIA = 'VARIOS'
								AND COALESCE(PREV.N_FCT_ASEG,'') <> ''
								AND PREV.N_FCT_ASEG = COALESCE(H.N_FCT_ASEG,'')
								AND COALESCE(PREV.IDTERCEROEXT,'') = COALESCE(H.IDTERCEROEXT,'')
							)
							OR
							(
								PREV.NOREFERENCIA = 'VARIOS'
								AND H.NOREFERENCIA = 'VARIOS'
								AND COALESCE(PREV.N_FCT_FYG,'') <> ''
								AND PREV.N_FCT_FYG = COALESCE(H.N_FCT_FYG,'')
								AND COALESCE(PREV.IDTERCEROEXT,'') = COALESCE(H.IDTERCEROEXT,'')
							)
					  )
					ORDER BY
						CASE
							WHEN PREV.NOREFERENCIA = H.NOREFERENCIA
							 AND COALESCE(PREV.N_FCT_ASEG,'') <> ''
							 AND PREV.N_FCT_ASEG = COALESCE(H.N_FCT_ASEG,'') THEN 1
							WHEN PREV.NOREFERENCIA = H.NOREFERENCIA
							 AND COALESCE(PREV.N_FCT_FYG,'') <> ''
							 AND PREV.N_FCT_FYG = COALESCE(H.N_FCT_FYG,'') THEN 2
							WHEN PREV.NOREFERENCIA = H.NOREFERENCIA
							 AND COALESCE(PREV.IDTERCEROEXT,'') <> ''
							 AND PREV.IDTERCEROEXT = COALESCE(H.IDTERCEROEXT,'') THEN 3
							WHEN PREV.NOREFERENCIA = 'VARIOS'
							 AND H.NOREFERENCIA = 'VARIOS'
							 AND COALESCE(PREV.N_FCT_ASEG,'') <> ''
							 AND PREV.N_FCT_ASEG = COALESCE(H.N_FCT_ASEG,'')
							 AND COALESCE(PREV.IDTERCEROEXT,'') = COALESCE(H.IDTERCEROEXT,'') THEN 4
							WHEN PREV.NOREFERENCIA = 'VARIOS'
							 AND H.NOREFERENCIA = 'VARIOS'
							 AND COALESCE(PREV.N_FCT_FYG,'') <> ''
							 AND PREV.N_FCT_FYG = COALESCE(H.N_FCT_FYG,'')
							 AND COALESCE(PREV.IDTERCEROEXT,'') = COALESCE(H.IDTERCEROEXT,'') THEN 5
							ELSE 99
						END,
						PREV.ITEM DESC
				) P
				WHERE H.CNSHACTRAN = @CNSHACTRAN
				  AND COALESCE(P.SIRAS,'') <> ''

				UPDATE HACTRAND
				SET VLRGASTADO = AUT.VALORTOTAL
				FROM AUT
				INNER JOIN HACTRAND ON HACTRAND.CNSHACTRAN = AUT.CNSHACTRAN
					AND AUT.NOAUT = HACTRAND.NOREFERENCIA
					AND HACTRAND.PROCEDENCIA = 'CE'
					AND HACTRAND.IDTERCEROEXT = AUT.IDTERCEROCA
				WHERE HACTRAND.CNSHACTRAN = @CNSHACTRAN

				UPDATE HACTRAND
				SET VLRGASTADO = CIT.VALORTOTAL
				FROM CIT
				INNER JOIN HACTRAND ON HACTRAND.CNSHACTRAN = CIT.CNSHACTRAN
					AND CIT.CONSECUTIVO = HACTRAND.NOREFERENCIA
					AND HACTRAND.PROCEDENCIA = 'CI'
					AND HACTRAND.IDTERCEROEXT = CIT.IDTERCEROCA
				WHERE HACTRAND.CNSHACTRAN = @CNSHACTRAN

				UPDATE HACTRAND
				SET VLRGASTADO = A.VALORTOTAL
				FROM HADM
				INNER JOIN HACTRAND ON HADM.CNSHACTRAN = HACTRAND.CNSHACTRAN
					AND HACTRAND.PROCEDENCIA = 'QX'
					AND HADM.NOADMISION = HACTRAND.NOREFERENCIA
				OUTER APPLY (
					SELECT SUM(HPRED.VALOREXCEDENTE) AS VALORTOTAL
					FROM HPRE
					INNER JOIN HPRED ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
					WHERE HPRE.NOADMISION = HADM.NOADMISION
					  AND HPRE.IDTERCEROCA = HACTRAND.IDTERCEROEXT
					  AND COALESCE(HPRED.ANULADO, 0) <> 1
					  AND COALESCE(HPRED.N_FACTURA, '') = ''
				) A
				WHERE COALESCE(HADM.CLASENOPROC,'') <> 'NP'
				  AND COALESCE(HACTRAND.N_FCT_ASEG,'') = ''
				  AND COALESCE(HACTRAND.N_FCT_FYG,'') = ''
				  AND HACTRAND.CNSHACTRAN = @CNSHACTRAN
				  AND HADM.TIPOADM = @IDTARIFASOAT

				UPDATE HACTRAND
				SET VLRGASTADO = A.VALORTOTAL
				FROM HADM
