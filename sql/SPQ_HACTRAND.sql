						COALESCE(IDTERCEROEXT,'') AS IDTERCEROEXT,
						COALESCE(SIRAS,'') AS SIRAS,
						ITEM,
						ROW_NUMBER() OVER (
							PARTITION BY CNSHACTRAN, PROCEDENCIA, NOREFERENCIA,
							             COALESCE(N_FCT_ASEG,''), COALESCE(N_FCT_FYG,''), COALESCE(IDTERCEROEXT,'')
							ORDER BY ITEM DESC
						) AS RN
					FROM HACTRAND WITH (NOLOCK)
