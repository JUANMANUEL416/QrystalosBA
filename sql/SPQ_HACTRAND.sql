						ESTADOEMBRIAGUEZ,
						MAX(COALESCE(VLRGASTADO, 0)) AS VLRGASTADO,
						COALESCE(IDTERCEROEXT, '') AS IDTERCEROEXT,
						MAX(COALESCE(SIRAS, '')) AS SIRAS
					FROM DETALL_RAW
					GROUP BY
						CNSHACTRAN, PROCEDENCIA, NOREFERENCIA,
						N_FCT_ASEG, N_FCT_FYG, ESTADOCONC, ESTADOEMBRIAGUEZ,
						COALESCE(IDTERCEROEXT, '')
				)
				INSERT INTO HACTRAND (
					CNSHACTRAN, ITEM, PROCEDENCIA, NOREFERENCIA, N_FCT_ASEG, N_FCT_FYG,
					ESTADOCONC, ESTADOEMBRIAGUEZ, VLRGASTADO, IDTERCEROEXT, SIRAS
