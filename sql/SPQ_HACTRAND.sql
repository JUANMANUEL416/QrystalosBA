						FTR.IDTERCERO,
						MAX(COALESCE(CIT.SIRAS, B.SIRAS, ''))
					FROM FTR
					INNER JOIN FTRD ON FTR.CNSFCT = FTRD.CNSFTR
					INNER JOIN CIT ON FTRD.NOADMISION = CIT.CONSECUTIVO
						AND COALESCE(FTRD.PROCEDENCIA,'') = 'CI'
						AND CIT.CNSHACTRAN = @CNSHACTRAN
						AND COALESCE(CIT.ESTADO,'') <> 'A'
					LEFT JOIN #HACTRANPREV B ON B.CNSHACTRAN = CIT.CNSHACTRAN
						AND B.PROCEDENCIA = 'CI'
						AND B.NOREFERENCIA = 'VARIOS'
						AND B.N_FCT_ASEG = FTR.N_FACTURA
						AND B.IDTERCEROEXT = FTR.IDTERCERO
					LEFT JOIN AUTSES ON CIT.IDAUTSES = AUTSES.ID AND AUTSES.CNSHACTRAN = CIT.CNSHACTRAN
					WHERE FTR.NOREFERENCIA IN ('VARIOS','UNIWEB','CEUNIFICADO','MASIVA')
					  AND FTR.TIPOFAC = 'M'
					  AND COALESCE(FTR.ESTADO,'P') <> 'A'
					  AND COALESCE(FTR.TIPOANULACION,'') <> 'NC'
					  AND NOT EXISTS (
							SELECT 1
							FROM FNOT
							WHERE FNOT.N_FACTURA = FTR.N_FACTURA
							  AND FNOT.VR_TOTAL = FTR.VR_TOTAL
							  AND FNOT.ESTADO = 'O'
							  AND FNOT.CERRADA = 1
					      )
					GROUP BY CIT.CNSHACTRAN, FTR.N_FACTURA, FTR.VR_TOTAL, FTR.IDTERCERO

					UNION ALL

					-- CE: facturas masivas / varios
					SELECT
						AUT.CNSHACTRAN,
						'CE',
						'VARIOS',
						FTR.N_FACTURA,
						'',
						'Alerta',
						'No',
						FTR.VR_TOTAL,
						FTR.IDTERCERO,
						MAX(COALESCE(AUT.SIRAS, B.SIRAS, ''))
					FROM FTR
					INNER JOIN FTRD ON FTR.CNSFCT = FTRD.CNSFTR
					INNER JOIN AUT ON FTRD.NOADMISION = AUT.IDAUT
						AND COALESCE(FTRD.PROCEDENCIA,'') = 'CE'
						AND FTR.N_FACTURA = AUT.N_FACTURA
						AND AUT.CNSHACTRAN = @CNSHACTRAN
						AND COALESCE(AUT.ESTADO,'') <> 'A'
					LEFT JOIN #HACTRANPREV B ON B.CNSHACTRAN = AUT.CNSHACTRAN
						AND B.PROCEDENCIA = 'CE'
						AND B.NOREFERENCIA = 'VARIOS'
						AND B.N_FCT_ASEG = FTR.N_FACTURA
						AND B.IDTERCEROEXT = FTR.IDTERCERO
					WHERE FTR.NOREFERENCIA IN ('VARIOS','UNIWEB','CEUNIFICADO','MASIVA')
					  AND FTR.TIPOFAC = 'M'
					  AND COALESCE(FTR.ESTADO,'P') <> 'A'
					  AND COALESCE(FTR.TIPOANULACION,'') <> 'NC'
					  AND NOT EXISTS (
							SELECT 1
							FROM FNOT
							WHERE FNOT.N_FACTURA = FTR.N_FACTURA
							  AND FNOT.VR_TOTAL = FTR.VR_TOTAL
							  AND FNOT.ESTADO = 'O'
							  AND FNOT.CERRADA = 1
