CREATE OR ALTER PROCEDURE DBO.SPQ_IART
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @PARAMETROS		NVARCHAR(MAX),	@MODELO				VARCHAR(100),	@METODO				VARCHAR(100),	@USUARIO			VARCHAR(20)   
DECLARE  @GRUPO				VARCHAR(8),		@IDVARIABLE			VARCHAR(20),	@IDARTICULO			VARCHAR(20),	@IDCLASE			VARCHAR(2)
DECLARE	 @IDSUBCLASE		VARCHAR(4),		@IDGRUPO			VARCHAR(4),		@DESCRIPCION		VARCHAR(900),	@IDPRINACTIVO		VARCHAR(10)
DECLARE	 @IDFORFARM			VARCHAR(3),		@IDCONCENTRA		VARCHAR(4),		@IDUNIDAD			VARCHAR(100),	@PCOSTO				DECIMAL(9)
DECLARE	 @EXISTOTAL			DECIMAL(9),		@STOCKMINIMO		DECIMAL(9),		@STOCKMAXIMO		DECIMAL(9),		@PUNTOREORDEN		DECIMAL(9)
DECLARE	 @IDITAR			VARCHAR(2),		@ESTRANSFORMABLE	BIT,			@ESTADO				VARCHAR(8),		@IDGENERICO			VARCHAR(20)
DECLARE	 @CUENTA			VARCHAR(16),	@IDFABRICANTE		VARCHAR(20),	@ESACTIVO			BIT,			@IDTIPOACTIVO		VARCHAR(20)
DECLARE	 @IDALTERNA			VARCHAR(20),	@REGINVIMA			VARCHAR(100),	@ALTO_COSTO			BIT,			@CONT_ESPECIAL		BIT
DECLARE	 @MAT_IMPLANTACION	BIT,			@ENTREGA_TURNO		BIT,			@UTILIDAD			DECIMAL(9,2),	@DOSIFICADO			TINYINT,		@NDOSIS				BIT
DECLARE	 @CODCUM			VARCHAR(30),	@ESCALA_RIESGO		VARCHAR(20),	@IDSERVICIO			VARCHAR(20),	@PRINCIPAL			TINYINT
DECLARE	 @CLASERIESGO		VARCHAR(20),	@TESTABILIDAD		INT,			@CLASE				VARCHAR(10)
DECLARE	 @IDSERVICIOBASE	VARCHAR(20),	@CANTIDADBASE		DECIMAL(9),		@IDSERVICIOMEZCLA	VARCHAR(20),	@CANTIDADMEZCLA		DECIMAL(9)
DECLARE	 @CODIBASE			VARCHAR(20),	@CENTRAL			VARCHAR(4),		@IDSERVICIOCOBRO	DECIMAL(9),		@CTV				DECIMAL(9)
DECLARE	 @F_VIGENCIAINV		DATE,			@REGULADO			BIT,			@PRECOMERCIAL		VARCHAR(10),	@NOPOS				BIT
DECLARE	 @CONTADOR			INT,			@GRUPOI				VARCHAR(20),	@LABILIDAD			VARCHAR(20),	@HEMOCLASIFICACION	VARCHAR(10)
DECLARE	 @JUSTIFICACION		BIT,			@CODBARRA			VARCHAR(48),	@INSTITUCIONAL		BIT,			@TEMPERATURA		DECIMAL(14, 2)
DECLARE	 @ICBU				BIT,			@RMINSTOCK			BIT,			@STOCKMINREQ		SMALLINT,		@REQAUTCOMP			BIT
DECLARE	 @REQRECEP			BIT,			@REFERENCIA			VARCHAR(30),	@IUM				VARCHAR(16),	@IDSERVICIO_FAC		VARCHAR(20)
DECLARE	 @CESTE				BIT,			@MIVA				BIT,			@PROCEDIMIENTO		NVARCHAR(MAX),	@MCADFRIO			BIT
DECLARE	 @BIOLOGICO			BIT,			@UNIRS				BIT,			@ALERTA				VARCHAR(1024),	@TEMPERATURA_FIN	DECIMAL(14,2)
DECLARE  @PROCESO			VARCHAR(20)    ,@HUMEDAD_MIN		DECIMAL(14,2)	,@HUMEDAD_MAX		DECIMAL(14,2),  @IDBODEGA			VARCHAR(20)
DECLARE  @ESTANTE		    VARCHAR(20),	@ESAUTOMATICO		BIT,			@SEDE				VARCHAR(5),		@PRECNS				VARCHAR(10)
DECLARE  @IDARTICULO_ORI	VARCHAR(20), @IDARTICULO_DES	VARCHAR(20) , @UNID_VENTA INT, @PRECIO_REGULADO DECIMAL(14,2), @IDARTICULO_TXA VARCHAR(20), @MAUTORIZACION BIT
DECLARE @IDARTICULOTF_TXA VARCHAR(20), @CANTIDADTF_TXA DECIMAL(14, 2) , @IDARTICULOTF_OLD_TXA VARCHAR(20), @MMULTIPLOS_CANTTF BIT, @MULTIPLO_CANTTF SMALLINT
DECLARE @ITEM_IARTDX INT, @DXUNIRS_IARTDX VARCHAR(2048), @IDARTICULO_IARTDX VARCHAR(20)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX)) 
DECLARE @DEINVNODESER VARCHAR(20)=DBO.FNK_VALORVARIABLE('DEINVNODESER')
DECLARE @PREFIJOMEDICAMENTOS VARCHAR(20)=DBO.FNK_VALORVARIABLE('PREFIJOMEDICAMENTOS')
DECLARE @PREFIJOMEDNOPOS VARCHAR(20)=DBO.FNK_VALORVARIABLE('PREFIJOMEDNOPOS')
DECLARE @IDMEDPOSRIPS VARCHAR(20)=DBO.FNK_VALORVARIABLE('IDMEDPOSRIPS')
DECLARE @IDMEDNOPOSRIPS VARCHAR(20)=DBO.FNK_VALORVARIABLE('IDMEDNOPOSRIPS')
DECLARE @IMPUESTO_OBL VARCHAR(20)=DBO.FNK_VALORVARIABLE('IMPUESTO_OBL')
DECLARE @IART_SER_UNICO VARCHAR(20)=DBO.FNK_VALORVARIABLE('IART_SER_UNICO')
DECLARE @CREARSER BIT
DECLARE @OBSERVACION VARCHAR(1024)
DECLARE @ID INT
DECLARE @PREFIJO VARCHAR(20)
DECLARE @CLASE_KIT VARCHAR(20)
-- Para Impuestos en IART (ya no en SER)
DECLARE @IDIMPUESTO VARCHAR(10)
DECLARE @IDCLASE_IMP VARCHAR(10)
DECLARE @DMARD VARCHAR(10)
DECLARE @OTROS_DMARD VARCHAR(20)
DECLARE @INSULINA BIT
DECLARE @ESTADO_ANT VARCHAR(8)
DECLARE @ESTADO_NUE VARCHAR(8)
DECLARE @CUM_NORM VARCHAR(30)
DECLARE @DESC_NORM VARCHAR(900)
DECLARE @ID_CUM_EXISTE VARCHAR(20)
DECLARE @DESC_CUM_EXISTE VARCHAR(900)
DECLARE @ID_NOM_EXISTE VARCHAR(20)
DECLARE @DESC_NOM_EXISTE VARCHAR(900)

BEGIN

	IF ISJSON(@JSON) = 0 
	BEGIN
		RAISERROR('Json: Formato Erroneo',16,1)
		RETURN
	END

	SELECT  @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS=PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)  AS JSON
	)

	IF @METODO = 'IDITARUNIDOSIS'
	BEGIN
		SELECT IDITAR FROM ITAR INNER JOIN USVGS ON ITAR.IDITAR = USVGS.DATO
		WHERE IDVARIABLE='IDITARUNIDOSIS' 
		RETURN
	END

	IF @METODO = 'DETALLE_DOSIS'
	BEGIN
		SELECT @IDARTICULO = IDARTICULO
		  FROM   OPENJSON (@PARAMETROS)
		  WITH (IDARTICULO       VARCHAR(20)  '$.IDARTICULO')
		
		SELECT 
			IART.IDARTICULO, IART.DESCRIPCION, SER.PRESUNI, SER.EQUICC, IART.ESTADO, IART.PROCEDIMIENTO
			,IGEN.IDGENERICO, IGEN.DESCRIPCION GENERICO
			,IART.IDSERVICIOBASE, BASE.DESCRIPCION BS_DESCRIPCION, IART.CANTIDADBASE, BS.PRESUNI BS_PRESUNI, BS.EQUICC BS_EQUICC
			,IART.IDSERVICIOMEZCLA, MEZCLA.DESCRIPCION MC_DESCRIPCION, IART.CANTIDADMEZCLA, MC.PRESUNI MC_PRESUNI, MC.EQUICC MC_EQUICC
		FROM		IART 
		LEFT JOIN	IGEN ON IGEN.IDGENERICO = IART.IDGENERICO
		LEFT JOIN	IART BASE ON IART.IDSERVICIOBASE=BASE.IDARTICULO
		LEFT JOIN	IART MEZCLA ON IART.IDSERVICIOMEZCLA=MEZCLA.IDARTICULO
		LEFT JOIN   SER ON SER.IDARTICULO=IART.IDARTICULO
		LEFT JOIN   SER BS ON BASE.IDSERVICIO=BS.IDSERVICIO
		LEFT JOIN   SER MC ON MEZCLA.IDSERVICIO=MC.IDSERVICIO
		WHERE IART.IDARTICULO=@IDARTICULO

		SELECT ITXA.IDARTICULOTF IDARTICULO,IART.DESCRIPCION,ITXA.CANTIDADTF CANTIDAD 
		,SER.PRESUNI, SER.EQUICC
		FROM ITXA 
		INNER JOIN IART ON IART.IDARTICULO=ITXA.IDARTICULOTF
		LEFT JOIN SER ON SER.IDSERVICIO=IART.IDSERVICIO
		WHERE ITXA.IDARTICULO=@IDARTICULO

		RETURN
	END

	IF @METODO = 'SET_PROCEDIMIENTO'
	BEGIN
		DECLARE @PROCEDMIENTO NVARCHAR(MAX)
		SELECT @IDARTICULO = IDARTICULO, @PROCEDMIENTO=PROCEDIMIENTO
		FROM   OPENJSON (@PARAMETROS)
		WITH (
			IDARTICULO       VARCHAR(20)  '$.IDARTICULO',
			PROCEDIMIENTO    NVARCHAR(MAX)'$.PROCEDIMIENTO'
		)

		UPDATE IART SET PROCEDIMIENTO = @PROCEDMIENTO WHERE IDARTICULO = @IDARTICULO
		RETURN
	END

	IF @METODO = 'NUEVA_DOSIS'
	BEGIN
		  SELECT * INTO #IART
		  FROM   OPENJSON (@PARAMETROS)
		  WITH (   
			DESCRIPCION       VARCHAR(900)  '$.DESCRIPCION',
			HORASESTABILIDAD  INT			'$.HORASESTABILIDAD',
			IDARTICULOBASE	  VARCHAR(255)	'$.IDARTICULOBASE',
			CANTIDADBASE	  DECIMAL(14,2) '$.CANTBASE',
			IDARTICULOMEZCLA  VARCHAR(255)	'$.IDARTICULOMEZCLA',
			CANTIDADMEZCLA	  DECIMAL(14,2) '$.CANTMEZCLA'
		  )

		--INSERT INTO IART() 

		--SELECT * FROM IART
		--SELECT * FROM ITXA
		DECLARE @NVOCONSEC VARCHAR(20)
		--DECLARE @IDGENERICO VARCHAR(20)
		SELECT @NVOCONSEC = NULL 
        EXEC SPK_GENCONSECUTIVO '01', '01', '@UNIDOSIS',  @NVOCONSEC OUTPUT  
        SELECT @NVOCONSEC = 'UN' +  REPLACE(SPACE(8 - LEN(@NVOCONSEC))+LTRIM(RTRIM(@NVOCONSEC)),SPACE(1),0)

		SELECT @IDGENERICO = IGEN.IDGENERICO FROM IGEN INNER JOIN IART ON IART.IDGENERICO=IGEN.IDGENERICO
		INNER JOIN #IART ON #IART.IDARTICULOBASE=IART.IDARTICULO

		IF @IDGENERICO IS NULL
		BEGIN
			RAISERROR('El medicamento base no tiene configurado un gen�rico.',16,1)
			RETURN
		END

		INSERT INTO IART(IDARTICULO,IDITAR,DESCRIPCION,TESTABILIDAD,IDSERVICIOBASE,CANTIDADBASE,IDSERVICIOMEZCLA,CANTIDADMEZCLA,IDGENERICO,ESTADO, PCOSTO, EXISTOTAL, ESACTIVO)
		SELECT 
			@NVOCONSEC IDARTICULO
			,IDITAR = dbo.FNK_VALORVARIABLE('IDITARUNIDOSIS')
			,DESCRIPCION
			,HORASESTABILIDAD
			,IDARTICULOBASE
			,CANTIDADBASE
			,IDARTICULOMEZCLA
			,CANTIDADMEZCLA
			,@IDGENERICO IDGENERICO
			,'Activo'
         , 0
         , 0
         , 0
		FROM #IART

		--INSERT INTO ITXA(IDARTICULO,IDARTICULOTF)
		--SELECT IDARTICULOBASE, IDSERVICIOBASE FROM #IART
		--SELECT IDARTICULOMEZCLA, IDSERVICIOMEZCLA FROM #IART
	END

	IF @METODO = 'CAMBIAR_ESTADO'
	BEGIN
		SELECT @IDARTICULO = IDARTICULO
		  FROM   OPENJSON (@PARAMETROS)
		  WITH (IDARTICULO       VARCHAR(20)  '$.IDARTICULO')

		SELECT @ESTADO_ANT = ESTADO FROM IART WHERE IDARTICULO = @IDARTICULO
		SET @ESTADO_NUE = CASE WHEN @ESTADO_ANT = 'Inactivo' THEN 'Activo' ELSE 'Inactivo' END

		IF UPPER(LTRIM(RTRIM(ISNULL(@ESTADO_ANT, '')))) <> UPPER(LTRIM(RTRIM(ISNULL(@ESTADO_NUE, ''))))
		BEGIN
			INSERT INTO dbo.LOG_IART (IDARTICULO, ESTADO_ANTERIOR, ESTADO_NUEVO, FECHA, USUARIO)
			VALUES (@IDARTICULO, @ESTADO_ANT, @ESTADO_NUE, DBO.FNK_GETDATE(), @USUARIO)
		END

		UPDATE IART SET ESTADO = @ESTADO_NUE WHERE IDARTICULO = @IDARTICULO
		RETURN
	END

	IF @METODO = 'GET_LOG_ESTADO'
	BEGIN
		SELECT @IDARTICULO = JSON_VALUE(@PARAMETROS, '$.IDARTICULO')

		SELECT @IDSERVICIO = TRIM(IDSERVICIO) FROM IART WHERE IDARTICULO = @IDARTICULO

		SELECT 'OK' OK

		;WITH ARTICULOS_LOG AS (
			SELECT @IDARTICULO AS IDARTICULO
			UNION
			SELECT H.IDARTICULO
			FROM IART H
			WHERE COALESCE(H.PRINCIPAL, 0) = 0
			  AND (
					H.IDARTICULO LIKE @IDARTICULO + '%'
					OR (
						NULLIF(@IDSERVICIO, '') IS NOT NULL
						AND H.IDSERVICIO = @IDSERVICIO
					)
			  )
		)
		SELECT
			L.ID,
			L.IDARTICULO,
			IA.DESCRIPCION,
			L.ESTADO_ANTERIOR,
			L.ESTADO_NUEVO,
			L.FECHA,
			FECHA_FMT = DBO.FNK_FECHA_GRINGA(L.FECHA),
			L.USUARIO,
			U.NOMBRE
		FROM LOG_IART L
		INNER JOIN ARTICULOS_LOG AL ON AL.IDARTICULO = L.IDARTICULO
		LEFT JOIN IART IA ON IA.IDARTICULO = L.IDARTICULO
		LEFT JOIN USUSU U ON U.USUARIO = L.USUARIO
		ORDER BY L.FECHA DESC, L.ID DESC

		RETURN
	END

	IF @METODO = 'AGREGAR_INSUMO'
	BEGIN
		INSERT INTO ITXA(IDARTICULO,IDARTICULOTF,CANTIDADTF)
		SELECT IDARTICULO,IDARTICULOTF,CANTIDAD
		FROM   OPENJSON (@PARAMETROS)
		WITH (
			IDARTICULO     VARCHAR(20)  '$.IDARTICULO',
			CANTIDAD       DECIMAL(14,2)'$.CANTIDAD',
			IDARTICULOTF   VARCHAR(20)	'$.IDARTICULOTF'
		) AS #T
		WHERE NOT EXISTS(SELECT 1 FROM ITXA WHERE IDARTICULO=#T.IDARTICULO AND IDARTICULOTF=#T.IDARTICULOTF)
	END

	IF @METODO = 'DESCARTAR_INSUMO'
	BEGIN
		DECLARE @IDARTICULOTF VARCHAR(20)
		SELECT @IDARTICULO = IDARTICULO, @IDARTICULOTF = IDARTICULOTF
		FROM   OPENJSON (@PARAMETROS)
		WITH (
			IDARTICULO     VARCHAR(20)  '$.IDARTICULO',
			IDARTICULOTF   VARCHAR(20)	'$.IDARTICULOTF'
		) AS #T

		DELETE FROM ITXA WHERE IDARTICULO = @IDARTICULO AND IDARTICULOTF = @IDARTICULOTF
	END

	IF @METODO = 'VALIDA_PERMITE_HERMANO'
	BEGIN
		SELECT @IDARTICULO = LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.IDARTICULO')))

		IF COALESCE(@IDARTICULO, '') = ''
		BEGIN
			SELECT 'KO' OK, 0 PERMITE_HERMANO
			SELECT ERROR = 'Debe indicar el art�culo principal.'
			RETURN
		END

		IF NOT EXISTS (SELECT 1 FROM IART WHERE IDARTICULO = @IDARTICULO)
		BEGIN
			SELECT 'KO' OK, 0 PERMITE_HERMANO
			SELECT ERROR = 'Art�culo principal no encontrado.'
			RETURN
		END

		IF COALESCE(LTRIM(RTRIM(@DEINVNODESER)), '') = ''
		BEGIN
			SELECT 'KO' OK, 0 PERMITE_HERMANO
			SELECT ERROR = 'La variable de sistema DEINVNODESER no est� configurada. Configure el valor en USVGS e intente nuevamente.'
			RETURN
		END

		SELECT @IDSERVICIO = LTRIM(RTRIM(IART.IDSERVICIO))
		FROM IART
		WHERE IART.IDARTICULO = @IDARTICULO

		IF LTRIM(RTRIM(COALESCE(@IDSERVICIO, ''))) = LTRIM(RTRIM(@DEINVNODESER))
		BEGIN
			SELECT 'KO' OK, 0 PERMITE_HERMANO
			SELECT ERROR = 'El art�culo principal tiene IDSERVICIO igual a DEINVNODESER (' + @DEINVNODESER + '). No se permiten art�culos hermanos (comerciales por fabricante).'
			RETURN
		END

		SELECT 'OK' OK, 1 PERMITE_HERMANO
		RETURN
	END

	IF @METODO = 'CONTAR_HERMANOS'
	BEGIN
		SELECT 'OK' OK

		SELECT COUNT(*) HERMANOS FROM VWK_HERMANOS_INVENTARIO WHERE HERMANO_MAYOR=JSON_VALUE(@PARAMETROS, '$.IDSERVICIO')
		RETURN
	END

	IF @METODO = 'GET_ARTICULOS_X_FABRICANTE'
	BEGIN
		SELECT 'OK' OK

		DECLARE @IDITARUNIDOSIS VARCHAR(100) = DBO.FNK_VALORVARIABLE('IDITARUNIDOSIS')
		DECLARE @ESFARMACIA VARCHAR(100) = DBO.FNK_VALORVARIABLE('ESFARMACIA')
		DECLARE @FILTRO AS NVARCHAR(MAX) = ' COALESCE(IART.PRINCIPAL,0) = 0 '

		SELECT @IDARTICULO = JSON_VALUE(@PARAMETROS, '$.IDARTICULO')
		SELECT @ESTADO = JSON_VALUE(@PARAMETROS, '$.ESTADO')

		DECLARE @SELECT VARCHAR(MAX) = '
		SELECT IART.IDARTICULO, IART.DESCRIPCION, IART.IDFABRICANTE, TER.RAZONSOCIAL AS FABRICANTE, IART.REGINVIMA, IART.CODCUM,
			IART.F_VIGENCIAINV, IART.IUM, 
			ENTREGA_TURNO = CAST(COALESCE(IART.ENTREGA_TURNO,0) AS BIT), 
			IART.UTILIDAD, 
			MCADFRIO = CAST(COALESCE(IART.MCADFRIO,0) AS BIT),
			IART.TEMPERATURA, 
			IART.TESTABILIDAD, 
			IART.CONTADOR,
			IART.PRECIO_REGULADO,
			IART.ESTADO, 
			IART.UNID_VENTA,
			IART.MIVA,
			IART.OBSERVACION,
			IART.IDITAR,
			IART.IDCLASE,
			IART.IDSUBCLASE,
			IART.IDGRUPO,
			IART.IDIMPUESTO,            
			IDCLASE_IMP = IART.IDCLASE_IMP,
			IART.DMARD,
			IART.OTROS_DMARD,
			TIENE_SERVICIO = CASE WHEN EXISTS (SELECT 1 FROM SER S WHERE S.IDSERVICIO = IART.IDARTICULO) THEN 1 ELSE 0 END
		FROM IART 
		LEFT JOIN TER ON TER.IDTERCERO=IART.IDFABRICANTE
		'

		SELECT @IDSERVICIO = TRIM(IDSERVICIO) FROM IART WHERE IDARTICULO=@IDARTICULO

		DECLARE @SIN_SERVICIO BIT = 0
		IF COALESCE(LTRIM(RTRIM(@DEINVNODESER)), '') <> ''
		   AND LTRIM(RTRIM(COALESCE(@IDSERVICIO, ''))) = LTRIM(RTRIM(@DEINVNODESER))
			SET @SIN_SERVICIO = 1

		IF @SIN_SERVICIO = 1
		BEGIN
			SELECT @FILTRO = TRIM(@FILTRO) + ' AND IART.IDARTICULO LIKE ''' + @IDARTICULO + '-%'' AND IART.IDITAR <> ''' + @IDITARUNIDOSIS + ''''
		END
		ELSE IF @ESFARMACIA = 'SI'
		BEGIN
			IF DBO.FNK_VALORVARIABLE('INTERFAZ_INV') = 'INTER_SAP' -- CI. PERU
				SELECT @FILTRO = TRIM(@FILTRO) + ' AND IART.IDARTICULO = ''' + @IDARTICULO + ''' AND IART.IDITAR <> ''' + @IDITARUNIDOSIS + ''''
			ELSE
				SELECT @FILTRO = TRIM(@FILTRO) + ' AND IART.IDARTICULO LIKE ''' + @IDARTICULO + '%'' AND IART.IDITAR <> ''' + @IDITARUNIDOSIS + ''''
		END
		ELSE
		BEGIN
			IF DBO.FNK_VALORVARIABLE('INTERFAZ_INV') = 'INTER_SAP' -- CI. PERU
				SELECT @FILTRO = TRIM(@FILTRO) + ' AND IART.IDSERVICIO = ''' + @IDSERVICIO + ''' AND IART.IDITAR <> ''' + @IDITARUNIDOSIS + ''''
			ELSE
				SELECT @FILTRO = TRIM(@FILTRO) + ' AND IART.IDSERVICIO = ''' + @IDSERVICIO + ''' AND IART.IDITAR <> ''' + @IDITARUNIDOSIS + ''''
		END

		IF @ESTADO <> 'Todos'
			SELECT @FILTRO = TRIM(@FILTRO) + ' AND IART.ESTADO = ''' + @ESTADO + ''''

		SELECT @SELECT = @SELECT + ' WHERE ' + @FILTRO
		PRINT @SELECT
		EXEC (@SELECT)
		RETURN
	END

	IF @METODO = 'VALIDA_SERVICIO'
	BEGIN
		SELECT @IDARTICULO = JSON_VALUE(@PARAMETROS, '$.IDARTICULO')

		IF NOT EXISTS (SELECT 1 FROM IART WHERE IDARTICULO = @IDARTICULO)
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR = 'Articulo Principal no encontrado'
			RETURN
		END

		IF COALESCE(LTRIM(RTRIM(@DEINVNODESER)), '') = ''
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR = 'La variable de sistema DEINVNODESER no est� configurada. Configure el valor en USVGS e intente nuevamente.'
			RETURN
		END

		SELECT 'OK' OK
		SELECT @IDITAR = IDITAR FROM IART WHERE IDARTICULO = @IDARTICULO

		IF EXISTS (
			SELECT 1 FROM IART WHERE IDARTICULO = @IDARTICULO AND LTRIM(RTRIM(COALESCE(IDSERVICIO, ''))) = LTRIM(RTRIM(@DEINVNODESER))
		)
		AND NOT EXISTS (
			SELECT 1 FROM SER WHERE SER.IDSERVICIO = @IDARTICULO
		)
			SELECT @CREARSER = 1
		ELSE
			SELECT @CREARSER = 0

		IF @CREARSER = 1
			SELECT
				@CREARSER AS CREARSER,
				IART.IDARTICULO,
				IART.IDARTICULO AS IDSERVICIO,
				IART.CODCUM AS IDALTERNA,
				IART.DESCRIPCION AS DESCSERVICIO,
				IGEN.DESCRIPCION AS DESC_GENERICO,
				ITAR.PREFIJO,
				'Ambos' AS SEXO,
				CAST(1 AS BIT) SPD,
				CAST(IIF(ITAR.PREFIJO IN (@PREFIJOMEDICAMENTOS, @PREFIJOMEDNOPOS), 1, 0) AS BIT) MEDICAMENTOS,
				CAST(IIF(ITAR.PREFIJO = @PREFIJOMEDNOPOS, 0, 1) AS BIT) POS,
				CAST(0 AS BIT) MDOSISF,
				CAST(0 AS BIT) MULTIDOSIS,
				IDCONCEPTORIPS =
					CASE
						WHEN ITAR.PREFIJO = @PREFIJOMEDICAMENTOS THEN @IDMEDPOSRIPS
						WHEN ITAR.PREFIJO = @PREFIJOMEDNOPOS THEN @IDMEDNOPOSRIPS
						ELSE NULL
					END,
				'' AS IVA,
			(SELECT IDTARIFA, DESCTARIFA FROM TAR WHERE IDTARIFA = DBO.FNK_VALORVARIABLE('COD_TARIFA_MAT_VE') FOR JSON PATH) AS IDTARIFA,
			IART.IDITAR,
			IART.IDCLASE,
			IART.IDSUBCLASE,
			IART.IDGRUPO,
			IART.IDIMPUESTO,            
			IDCLASE_IMP = IART.IDCLASE_IMP,
			IART.MIVA,
				IART.PRECIO_REGULADO,
				1 NIVELFUNCIONARIO,
				1 NIVELSEDE,
				1 CANTIDAD,
				999 CANTMAXIMA
			FROM IART
			LEFT JOIN ITAR ON ITAR.IDITAR = IART.IDITAR
			LEFT JOIN IGEN ON IGEN.IDGENERICO = IART.IDGENERICO
			WHERE IART.IDARTICULO = @IDARTICULO
		ELSE
		SELECT
			IART.IDSERVICIO AS IDSERVICIO,
			IART.IDARTICULO ,
			IART.DESCRIPCION AS DESCRIPCION,
			'Activo' AS ESTADO,
			CAST(0 AS BIT) MIVA,                 
			CAST(0 AS BIT) MCADFRIO,
			CAST(0 AS BIT) ENTREGA_TURNO,
			0 AS UNID_VENTA,
			IART.MIVA,                 
			IART.IDITAR,
			IART.IDCLASE,
