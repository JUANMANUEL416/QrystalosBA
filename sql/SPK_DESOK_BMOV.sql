IF EXISTS (SELECT name FROM sysobjects WHERE NAME = 'SPK_DESOK_BMOV' AND type = 'P')
   DROP PROCEDURE SPK_DESOK_BMOV

GO
CREATE PROCEDURE DBO.SPK_DESOK_BMOV  
  @BANCO    VARCHAR(3),  
  @SUCURSAL VARCHAR(2),  
  @CTA_BCO  VARCHAR(40),     
  @ITEM     INT,  
  @NROCOMPROBANTE VARCHAR(20)  
WITH ENCRYPTION
AS  
DECLARE @TOTALDB DECIMAL(14,2)  
DECLARE @TOTALCR DECIMAL(14,2)  
DECLARE @CNSFCXP VARCHAR(20)
BEGIN   
SELECT @CNSFCXP=FCXP.CNSFCXP FROM BMOV INNER JOIN FCXP ON FCXP.CNSFCXP=BMOV.CNSFCXP
		WHERE BANCO=@BANCO AND SUCURSAL=@SUCURSAL AND CTA_BCO=@CTA_BCO AND ITEM=@ITEM AND GENCXP=1 AND COALESCE(FCXP.CONTABILIZADA,0)<>0
   IF (SELECT COUNT(*) FROM BMOVD WHERE BANCO=@BANCO AND SUCURSAL=@SUCURSAL AND CTA_BCO=@CTA_BCO AND ITEM=@ITEM AND ENPAGOS=1) > 0
   BEGIN 
      RETURN
   END
    IF (SELECT COUNT(*) FROM BMOV INNER JOIN FCXP ON FCXP.CNSFCXP=BMOV.CNSFCXP
		WHERE BANCO=@BANCO AND SUCURSAL=@SUCURSAL AND CTA_BCO=@CTA_BCO AND ITEM=@ITEM AND GENCXP=1 AND COALESCE(FCXP.CONTABILIZADA,0)<>0) > 0
   BEGIN 
   PRINT 'ESTA CONTABILIZA NO DESCONFIRMAR'
      
	  RETURN
   END

   IF COALESCE( @CNSFCXP,'')<>''
   BEGIN 
   UPDATE FCXP SET ESTADO='A' WHERE CNSFCXP=@CNSFCXP

   END 
  
   IF (SELECT ESTADO FROM MCP WHERE NROCOMPROBANTE=@NROCOMPROBANTE )<>2
   BEGIN
      DELETE MCH WHERE NROCOMPROBANTE=@NROCOMPROBANTE  
      UPDATE MCP SET TOTALDEBITO=0, TOTALCREDITO=0, ESTADO=0, ANULADO = 1 WHERE NROCOMPROBANTE=@NROCOMPROBANTE  
   END
    
   UPDATE BMOV SET ESTADO = 'P' , NROCOMPROBANTE = NULL, GENCXP= COALESCE(OFIN.GENCXP,0) ,CNSFCXP=''   FROM BMOV INNER JOIN OFIN ON OFIN.IDOPERACION=BMOV.IDOPERACION
   WHERE  BMOV.BANCO = @BANCO AND BMOV .SUCURSAL = @SUCURSAL AND BMOV.CTA_BCO = @CTA_BCO AND BMOV.ITEM = @ITEM  


   
   SELECT @TOTALDB = SUM(VLROPERACION) 
   FROM BMOV, OFIN 
   WHERE ESTADO = 'O'  
   AND    BMOV.BANCO = @BANCO AND BMOV.SUCURSAL = @SUCURSAL AND BMOV.CTA_BCO = @CTA_BCO  
   AND    OFIN.IDOPERACION = BMOV.IDOPERACION  
   AND    OFIN.TIPO = 'DB'   
   
   SELECT @TOTALCR = SUM(VLROPERACION) 
   FROM BMOV, OFIN 
   WHERE ESTADO = 'O'  
   AND    BMOV.BANCO = @BANCO AND BMOV.SUCURSAL = @SUCURSAL AND BMOV.CTA_BCO = @CTA_BCO  
   AND    OFIN.IDOPERACION = BMOV.IDOPERACION  
   AND    OFIN.TIPO = 'CR'   
   
   IF COALESCE(@TOTALCR,0)=0
   BEGIN  
      SELECT @TOTALCR = 0  
   END
   IF COALESCE(@TOTALDB,0)=0
   BEGIN  
      SELECT @TOTALDB = 0  
   END
   PRINT 'DEBITO='+STR(@TOTALDB)  
   PRINT 'CREDITO='+STR(@TOTALCR)  
   
   UPDATE BCT SET SALDO = @TOTALDB - @TOTALCR  
   WHERE  BANCO = @BANCO AND SUCURSAL = @SUCURSAL AND CTA_BCO = @CTA_BCO     


END
