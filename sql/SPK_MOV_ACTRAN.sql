IF EXISTS (SELECT name FROM sysobjects 
   WHERE name = 'SPK_MOV_ACTRAN' AND type = 'P')
   DROP PROCEDURE SPK_MOV_ACTRAN

GO
CREATE PROCEDURE DBO.SPK_MOV_ACTRAN 
@TIPOMOV      VARCHAR(10),
@PROCEDENCIA  VARCHAR(10),
@NOREFERENCIA VARCHAR(20)
WITH ENCRYPTION
AS
DECLARE @CNSHACTRAN VARCHAR(20) 
DECLARE @ITEM       INT
BEGIN
      IF @PROCEDENCIA  = 'QX'
      BEGIN
         SELECT @CNSHACTRAN = CNSHACTRAN FROM HADM WHERE NOADMISION = @NOREFERENCIA
      END
      IF @PROCEDENCIA = 'CI'
      BEGIN
         SELECT @CNSHACTRAN = CNSHACTRAN FROM CIT WHERE CONSECUTIVO = @NOREFERENCIA
      END
      IF @PROCEDENCIA = 'CE'
      BEGIN
         SELECT @CNSHACTRAN = CNSHACTRAN FROM AUT WHERE NOAUT = @NOREFERENCIA
      END
   IF @TIPOMOV = 'INGRESO'
   BEGIN
      IF NOT EXISTS(SELECT * FROM HACTRAND WHERE CNSHACTRAN = @CNSHACTRAN AND PROCEDENCIA = @PROCEDENCIA AND NOREFERENCIA = @NOREFERENCIA)
      BEGIN
         SELECT @ITEM = COALESCE(MAX(ITEM),0) FROM HACTRAND WHERE CNSHACTRAN = @CNSHACTRAN --JFRANCO 16/07/2015

         INSERT INTO HACTRAND(CNSHACTRAN, ITEM, PROCEDENCIA, NOREFERENCIA, VLRGASTADO, ESTADOCONC, ESTADOEMBRIAGUEZ)
         SELECT @CNSHACTRAN, @ITEM+1, @PROCEDENCIA, @NOREFERENCIA, 0, 'Alerta', 'No' 
      END
   END
   IF @TIPOMOV = 'BORRAR'
   BEGIN
      DELETE HACTRAND WHERE CNSHACTRAN = @CNSHACTRAN AND PROCEDENCIA = @PROCEDENCIA AND NOREFERENCIA = @NOREFERENCIA
   END
END
