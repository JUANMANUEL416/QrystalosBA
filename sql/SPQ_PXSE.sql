CREATE OR ALTER PROCEDURE DBO.SPQ_PXSE @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
BEGIN
	SET NOCOUNT ON;

	-- Declaraci�n de Variables
	DECLARE @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20), @PARAMETROS NVARCHAR(MAX)
	DECLARE @PROCESO VARCHAR(20), @IDSERVICIOEDITE VARCHAR(20)
	-- Variables de datos
	DECLARE @IDTERCERO VARCHAR(20), @IDADMINISTRADORA VARCHAR(20), @IDPLAN VARCHAR(6), @IDSEDE VARCHAR(5)
	DECLARE @PREFIJO VARCHAR(6), @IDSERVICIO VARCHAR(20), @TIPORESTRICCION VARCHAR(10), @IDTARIFA VARCHAR(5)
	DECLARE @FACTOR DECIMAL(7, 3), @VALOR DECIMAL(12, 3)
	-- Variables para l�gica calculada (DRY)
	DECLARE @IDTARIFA_FINAL VARCHAR(5)
	DECLARE @VALOR_FINAL DECIMAL(12, 3)
	DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@JSON) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			);

	BEGIN TRY
		BEGIN TRANSACTION;

		IF @METODO = 'GUARDAR'
		BEGIN
			SELECT @IDTERCERO = IDTERCERO, @IDADMINISTRADORA = IDADMINISTRADORA, @IDPLAN = IDPLAN, @IDSEDE = IDSEDE, @PREFIJO = PREFIJO, @IDSERVICIO = IDSERVICIO, 
				@TIPORESTRICCION = TIPORESTRICCION, @IDTARIFA = IDTARIFA, @FACTOR = FACTOR, @VALOR = VALOR, @PROCESO = PROCESO, @IDSERVICIOEDITE = IDSERVICIOEDITE
			FROM OPENJSON(@PARAMETROS) WITH (
					IDTERCERO VARCHAR(20) '$.IDTERCERO', IDADMINISTRADORA VARCHAR(20) '$.IDADMINISTRADORA', IDPLAN VARCHAR(6) '$.IDPLAN', IDSEDE VARCHAR(5) 
					'$.IDSEDE', PREFIJO VARCHAR(6) '$.PREFIJO', IDSERVICIO VARCHAR(20) '$.IDSERVICIO', TIPORESTRICCION VARCHAR(10) '$.TIPORESTRICCION', IDTARIFA 
					VARCHAR(5) '$.IDTARIFA', FACTOR DECIMAL(7, 3) '$.FACTOR', VALOR DECIMAL(12, 3) '$.VALOR', PROCESO VARCHAR(20) '$.PROCESO', IDSERVICIOEDITE 
					VARCHAR(20) '$.IDSERVICIOEDITE'
					);

			SET @IDTARIFA_FINAL = CASE 
					WHEN @TIPORESTRICCION IN ('Restringir', 'Valor')
						THEN ''
					ELSE @IDTARIFA
					END;
			SET @VALOR_FINAL = CASE 
					WHEN @TIPORESTRICCION IN ('Restringir', 'Tarifa')
						THEN 0
					ELSE @VALOR
					END;

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				-- Validaci�n de existencia
				IF EXISTS (
						SELECT 1
						FROM PXSE
						WHERE IDTERCERO = @IDTERCERO AND IDADMINISTRADORA = @IDADMINISTRADORA AND IDPLAN = @IDPLAN AND IDSEDE = @IDSEDE AND IDSERVICIO = @IDSERVICIO
						)
				BEGIN
					INSERT INTO @TBLERRORES (ERROR)
					VALUES ('LA EXCEPCI�N DE SERVICIO YA SE ENCUENTRA REGISTRADA');
				END
				ELSE
				BEGIN
					INSERT INTO [PXSE] ([IDTERCERO], [IDADMINISTRADORA], [IDPLAN], [IDSEDE], [PREFIJO], [IDSERVICIO], [TIPORESTRICCION], [IDTARIFA], [FACTOR], [VALOR]
						)
					SELECT @IDTERCERO, @IDADMINISTRADORA, @IDPLAN, @IDSEDE, @PREFIJO, @IDSERVICIO, @TIPORESTRICCION, @IDTARIFA_FINAL, @FACTOR, @VALOR_FINAL;
				END
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				-- Caso 1: Se modific� el ID del servicio (necesita validaci�n de duplicados)
				IF (@IDSERVICIOEDITE <> @IDSERVICIO)
				BEGIN
					IF EXISTS (
							SELECT 1
							FROM PXSE
							WHERE IDTERCERO = @IDTERCERO AND IDADMINISTRADORA = @IDADMINISTRADORA AND IDPLAN = @IDPLAN AND IDSEDE = @IDSEDE AND IDSERVICIO = @IDSERVICIO
							)
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						VALUES ('LA EXCEPCI�N DE SERVICIO YA SE ENCUENTRA REGISTRADA');
					END
					ELSE
					BEGIN
						UPDATE PXSE
						SET IDSERVICIO = @IDSERVICIO, TIPORESTRICCION = @TIPORESTRICCION, IDTARIFA = @IDTARIFA_FINAL, FACTOR = @FACTOR, VALOR = @VALOR_FINAL
						WHERE IDTERCERO = @IDTERCERO AND IDADMINISTRADORA = @IDADMINISTRADORA AND IDPLAN = @IDPLAN AND IDSEDE = @IDSEDE AND IDSERVICIO = @IDSERVICIOEDITE
							;
					END
				END
				ELSE
					-- Caso 2: No se modific� el ID (Update directo)
				BEGIN
					UPDATE PXSE
					SET TIPORESTRICCION = @TIPORESTRICCION, IDTARIFA = @IDTARIFA_FINAL, FACTOR = @FACTOR, VALOR = @VALOR_FINAL
					WHERE IDTERCERO = @IDTERCERO AND IDADMINISTRADORA = @IDADMINISTRADORA AND IDPLAN = @IDPLAN AND IDSEDE = @IDSEDE AND IDSERVICIO = @IDSERVICIO;
				END
			END
		END

		IF @METODO = 'ELIMINAR'
		BEGIN
			SELECT @IDTERCERO = IDTERCERO, @IDADMINISTRADORA = IDADMINISTRADORA, @IDPLAN = IDPLAN, @IDSEDE = IDSEDE, @PREFIJO = PREFIJO, @IDSERVICIO = IDSERVICIO
			FROM OPENJSON(@PARAMETROS) WITH (
					IDTERCERO VARCHAR(20) '$.IDTERCERO', IDADMINISTRADORA VARCHAR(20) '$.IDADMINISTRADORA', IDPLAN VARCHAR(6) '$.IDPLAN', IDSEDE VARCHAR(5) 
					'$.IDSEDE', PREFIJO VARCHAR(6) '$.PREFIJO', IDSERVICIO VARCHAR(20) '$.IDSERVICIO'
					);

			DELETE
			FROM PXSE
			WHERE IDTERCERO = @IDTERCERO AND IDADMINISTRADORA = @IDADMINISTRADORA AND IDPLAN = @IDPLAN AND IDSEDE = @IDSEDE AND IDSERVICIO = @IDSERVICIO AND PREFIJO = 
				@PREFIJO;
		END

		COMMIT TRANSACTION;
	END TRY

	BEGIN CATCH
		IF @@TRANCOUNT > 0
			ROLLBACK TRANSACTION;

		INSERT INTO @TBLERRORES (ERROR)
		SELECT ERROR_MESSAGE();
	END CATCH

	IF EXISTS (
			SELECT 1
			FROM @TBLERRORES
			)
	BEGIN
		SELECT 'KO' AS OK;

		SELECT ERROR
		FROM @TBLERRORES;
	END
	ELSE
	BEGIN
		SELECT 'OK' AS OK;
	END
END
