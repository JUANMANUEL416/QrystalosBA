IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME = 'SPK_CIERRE_SALDOS_INICIALES' AND XTYPE='P')
BEGIN
   DROP PROCEDURE SPK_CIERRE_SALDOS_INICIALES
END

GO
CREATE PROC DBO.SPK_CIERRE_SALDOS_INICIALES
@ANO     VARCHAR(4), 
@MES     INT,
@USUARIO VARCHAR(12)
WITH ENCRYPTION
AS
DECLARE @AUX    INT
DECLARE @ANOANT VARCHAR(4)
DECLARE @MESANT INT
BEGIN
   SELECT @AUX = COUNT(*) FROM PRI WHERE COALESCE(SI,0) = 1
   IF COALESCE(@AUX,0) > 1
   BEGIN
      RAISERROR('MAS DE UN PERIODO DEFINIDO COMO DE SALDOS INICIALES',16,1)
      RETURN
   END
   SELECT @AUX = COALESCE(SI,0) FROM PRI WHERE ANO = @ANO AND MES = @MES
   IF COALESCE(@AUX,0) <> 1
   BEGIN
      RAISERROR('PERIODO NO ESTA DEFINIDO COMO DE SALDOS INICIALES',16,1)
      RETURN
   END
   SELECT @AUX = COALESCE(PRI.CERRADO,0) FROM PRI WHERE ANO = @ANO AND MES = @MES
   IF @AUX = 1
   BEGIN
      RAISERROR('PERIODO CERRADO ',16,1)
      RETURN
   END  

   SELECT @MESANT = CASE @MES WHEN 1 THEN 12 ELSE @MES -1 END
   SELECT @ANOANT = CASE @MES WHEN 1 THEN @ANO - 1 ELSE @ANO END

   SELECT @AUX = COUNT(*) FROM MCP WHERE COALESCE(ESTADO,0) <> '2' AND COALESCE(ANULADO,0) = 0 AND ANO = @ANO AND MES = @MES
   IF COALESCE(@AUX,0) > 0
   BEGIN
      RAISERROR('FALTAN COMPROBANTES POR CONFIRMAR ',16,1)
      RETURN
   END
   CREATE TABLE #GENEALOGICO
          (CUENTA    VARCHAR(16) COLLATE database_default,   
           NOMCUENTA VARCHAR(200) COLLATE database_default,   
           TIPO      VARCHAR(7)  COLLATE database_default,   
           CENTRO    SMALLINT,   
           TERCERO   SMALLINT,  
           CLASE     VARCHAR(10) COLLATE database_default,  
           NIVEL     SMALLINT,  
           CUENTA_SUMA VARCHAR(16) COLLATE database_default,
           CUENTA_DETALLE VARCHAR(16) COLLATE database_default
          )
          
   --INSERTAMOS GENEALOGICO       
   PRINT 'INSERTAMOS GENEALOGICO'
   INSERT INTO #GENEALOGICO
   SELECT  * FROM FNK_GENEALOGICO_CUE('01')
   --BORRAMOS SALDOS DEL MES
   PRINT 'BORRAMOS SALDOS DEL MES'
   DELETE SALDOMES WHERE ANO = @ANO AND MES = @MES 
   DELETE SALDOMESTERFAC WHERE ANO = @ANO AND MES = @MES 
   --SALDOMES
   --BALANCE DEL MES  
   PRINT 'BALANCE DEL MES'
   INSERT INTO SALDOMES (ANO, MES, CUENTA, NOMCUENTA, SI, DB, CR, SF, SM, NTZ)
   SELECT @ANO, @MES, X.CUENTA, X.NOMCUENTA,
          0 SI,
          SUM(CASE MCH.TIPO WHEN 'DB' THEN MCH.VALOR ELSE 0 END) DB, 
          SUM(CASE MCH.TIPO WHEN 'CR' THEN MCH.VALOR ELSE 0 END) CR,
          0 SF,
          0 SM, 	       
          NTZ.TIPO
   FROM   MCP INNER JOIN MCH            ON MCP.NROCOMPROBANTE = MCH.NROCOMPROBANTE 
              INNER JOIN #GENEALOGICO X ON X.CUENTA_DETALLE = MCH.CUENTA
              INNER JOIN NTZ  ON  LEFT(MCH.CUENTA,1) = NTZ.N_INICIAL
   WHERE  MCP.ESTADO = 2 AND ISNULL(MCP.ANULADO,0) = 0
   AND    MCP.ANO = @ANO
   AND    MCP.MES = @MES
   GROUP BY X.CUENTA, X.NOMCUENTA, NTZ.TIPO	       
   ORDER BY X.CUENTA       
   PRINT 'SALDOS FINALES'
   UPDATE SALDOMES SET SF = CASE NTZ.TIPO WHEN 'DB' THEN SALDOMES.SI + SALDOMES.DB - SALDOMES.CR
                                                    ELSE SALDOMES.SI + SALDOMES.CR - SALDOMES.DB
                            END,                
                       SM = CASE NTZ.TIPO WHEN 'DB' THEN SALDOMES.DB - SALDOMES.CR
                                                    ELSE SALDOMES.CR - SALDOMES.DB
                            END                     
   FROM   SALDOMES INNER JOIN NTZ ON LEFT(SALDOMES.CUENTA,1) = NTZ.N_INICIAL
   WHERE  SALDOMES.ANO = @ANO
   AND    SALDOMES.MES = @MES
   
   --SALDOMESTER
   --BALANCE DEL MES
       
   PRINT 'BALANCE DEL MES POR TERCERO N_FACTURA'
   INSERT INTO SALDOMESTERFAC (ANO, MES, CUENTA, IDTERCERO, CCOSTO, N_FACTURA, NOMCUENTA, SI, DB, CR, SF, SM, NTZ)
   SELECT @ANO, @MES, MCH.CUENTA, COALESCE(MCH.IDTERCERO,''), COALESCE(MCH.CCOSTO,''), COALESCE(MCH.N_FACTURA,''), X.NOMCUENTA,
          0 SI,
          SUM(CASE MCH.TIPO WHEN 'DB' THEN MCH.VALOR ELSE 0 END) DB, 
          SUM(CASE MCH.TIPO WHEN 'CR' THEN MCH.VALOR ELSE 0 END) CR,
          0 SF,
          0 SM, 	       
          NTZ.TIPO
   FROM   MCP INNER JOIN MCH   ON MCP.NROCOMPROBANTE = MCH.NROCOMPROBANTE 
              INNER JOIN CUE X ON X.CUENTA           = MCH.CUENTA
              INNER JOIN NTZ   ON LEFT(MCH.CUENTA,1) = NTZ.N_INICIAL
   WHERE  MCP.ESTADO = 2 AND ISNULL(MCP.ANULADO,0) = 0
   AND    MCP.ANO =  @ANO
   AND    MCP.MES =  @MES
   GROUP BY MCH.CUENTA, MCH.IDTERCERO, MCH.CCOSTO, X.NOMCUENTA, MCH.N_FACTURA, NTZ.TIPO	       
   ORDER BY MCH.CUENTA, MCH.IDTERCERO, MCH.CCOSTO, MCH.N_FACTURA
   PRINT 'SALDOS FINALES POR TERCERO N_FACTURA'
   UPDATE SALDOMESTERFAC SET SF = CASE NTZ.TIPO WHEN 'DB' THEN SALDOMESTERFAC.SI + SALDOMESTERFAC.DB - SALDOMESTERFAC.CR
                                                          ELSE SALDOMESTERFAC.SI + SALDOMESTERFAC.CR - SALDOMESTERFAC.DB
                                  END,                
                             SM = CASE NTZ.TIPO WHEN 'DB' THEN SALDOMESTERFAC.DB - SALDOMESTERFAC.CR
                                                          ELSE SALDOMESTERFAC.CR - SALDOMESTERFAC.DB
                                  END                     
   FROM   SALDOMESTERFAC INNER JOIN NTZ ON LEFT(SALDOMESTERFAC.CUENTA,1) = NTZ.N_INICIAL
   WHERE  SALDOMESTERFAC.ANO = @ANO
   AND    SALDOMESTERFAC.MES = @MES

   -- CERRAMOS EL PERIODO
   PRINT 'CERRAMOS EL PERIODO'
   UPDATE PRI SET CERRADO = 1 WHERE ANO = @ANO AND MES = @MES AND COMPANIA = '01'
   
END
