CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NOMIE @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20)
DECLARE @PROCESO VARCHAR(20), @DATO NVARCHAR(MAX), @DATOS NVARCHAR(MAX), @CODCONCEPTO VARCHAR(20), @DESCRIPCION VARCHAR(255), @ITEM VARCHAR(20)
DECLARE @CODNOMINA VARCHAR(2), @NUMDOC VARCHAR(20), @ESTADO VARCHAR(12), @CNSNIEPE VARCHAR(20), @IDSEDE VARCHAR(5), @SYS_COMPUTERNAME VARCHAR(254), @COMPANIA 
	VARCHAR(2), @CollationName NVARCHAR(150), @CNSPAGO VARCHAR(20), @FECHAFIN VARCHAR(20), @CNSEXCEL VARCHAR(20), @CNS VARCHAR(20)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @JSON_EMP NVARCHAR(MAX)
DECLARE @FECHAINI DATETIME

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
	FROM USUSU
	WHERE USUARIO = @USUARIO

	SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
	FROM UBEQ
	WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	IF @METODO = 'GET_NOMIE'
	BEGIN
		SELECT @CODNOMINA = CODNOMINA
		FROM OPENJSON(@PARAMETROS) WITH (CODNOMINA VARCHAR(2) '$.CODNOMINA ')

		SELECT 'OK' OK

		SELECT NOMIE.NUMDOC, CONCAT (
				COALESCE(NEMP.PRIMERNOMBRE, ''), ' ', COALESCE(NEMP.SEGUNDONOMBRE, ''), ' ', COALESCE(NEMP.PRIMERAPELLIDO, ''), ' ', COALESCE(NEMP.
					SEGUNDOAPELLIDO, ''), ' '
				) AS NOMBRESCOMPLETOS, NEMP.ESTADO
		FROM NOMIE
		INNER JOIN NEMP ON NEMP.NUMDOC = NOMIE.NUMDOC
		WHERE NOMIE.CODNOMINA = @CODNOMINA

		RETURN
	END

	IF @METODO = 'GET_NOMIE_EMPLOYEES'
	BEGIN
		SELECT @FECHAFIN = FECHAFIN, @CODNOMINA = CODNOMINA, @CNSPAGO = CNSPAGO
		FROM OPENJSON(@PARAMETROS) WITH (FECHAFIN VARCHAR(20) '$.FECHAFIN', CODNOMINA VARCHAR(2) '$.CODNOMINA', CNSPAGO VARCHAR(20) '$.CNSPAGO')

		EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@RPDX', @LONGITUD = 8, @NVOCONSEC = @CNS OUTPUT

		DELETE RPDX
		WHERE CNS1 = 'VALIDANCON'

		BEGIN TRY
			DECLARE CUR CURSOR
			FOR
			SELECT ID1, STRINGMEDIO1
			FROM RPDX
			WHERE CNS = 'NCON';

			OPEN CUR;

			FETCH NEXT
			FROM CUR
			INTO @CODCONCEPTO, @DESCRIPCION;

			WHILE @@FETCH_STATUS = 0
			BEGIN
				SET @ITEM = (
						SELECT TOP 1 ITEM
						FROM NCOND
						WHERE CODCONCEPTO = @CODCONCEPTO AND FECHAINI < CONVERT(DATETIME, @FECHAFIN, 103)
						ORDER BY FECHAINI DESC
						)

				IF NOT EXISTS (
						SELECT 1
						FROM NCOND
						WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM
						)
				BEGIN
					INSERT INTO RPDX (CNS, CNS1, STRINGMEDIO1, STRINGMEDIO2, STRINGMEDIO3)
					SELECT @CNS, 'VALIDANCON', @CODCONCEPTO, @DESCRIPCION, CONCAT ('El Concepto: ', @CODCONCEPTO, ' con ITEM: ', @ITEM, ' No Existe en la Parametrizaci�n'
							)
				END

				FETCH NEXT
				FROM CUR
				INTO @CODCONCEPTO, @DESCRIPCION;
			END

			CLOSE CUR;

			DEALLOCATE CUR;

			SELECT 'OK' OK

			DELETE NEMPFD_RUN
			FROM NEMPFD_RUN X
			WHERE X.CNSPAGO = @CNSPAGO AND X.SYS_COMPUTERNAME = HOST_NAME()

			INSERT INTO NEMPF (CNSPAGO, NUMDOC, ITEM)
			SELECT @CNSPAGO, NEMP.NUMDOC, 'CAR00001'
			FROM NEMP
			INNER JOIN NOMIE ON NEMP.NUMDOC = NOMIE.NUMDOC AND NOMIE.CODNOMINA = (
					SELECT CODNOMINA
					FROM NPER
					WHERE CNSPAGO = @CNSPAGO
					) AND NOMIE.ESTADO = 'Activo' AND NEMP.ESTADO = 'Activo'
			LEFT JOIN NEMPF ON NEMP.NUMDOC = NEMPF.NUMDOC AND NEMPF.CNSPAGO = @CNSPAGO
			WHERE NEMPF.NUMDOC IS NULL AND (
					COALESCE(NEMP.FECHARETIRO, '') = '' OR FECHARETIRO >= (
						SELECT FECHAFIN
						FROM NPER
						WHERE CNSPAGO = @CNSPAGO
						)
					)

			SELECT NOMIE.NUMDOC, TER.RAZONSOCIAL AS NOMBRE_EMPLEADO
			FROM NEMP
			INNER JOIN TER ON NEMP.TERCEROID = TER.IDTERCERO
			INNER JOIN NOMIE ON NEMP.NUMDOC = NOMIE.NUMDOC AND NOMIE.CODNOMINA = (
					SELECT CODNOMINA
					FROM NPER
					WHERE CNSPAGO = @CNSPAGO
					) AND NOMIE.ESTADO = 'Activo' AND NEMP.ESTADO = 'Activo'
			LEFT JOIN NEMPF ON NEMP.NUMDOC = NEMPF.NUMDOC AND NEMPF.CNSPAGO = @CNSPAGO
			WHERE (
					COALESCE(NEMP.FECHARETIRO, '') = '' OR FECHARETIRO >= (
						SELECT FECHAINI
						FROM NPER
						WHERE CNSPAGO = @CNSPAGO
						)
					)

			IF (
					SELECT COUNT(*)
					FROM RPDX
					WHERE CNS = @CNS
					) > 0
			BEGIN
				EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@EXCEL', @LONGITUD = 8, @NVOCONSEC = @CNSEXCEL OUTPUT

				INSERT INTO KEXCEL_FILL (CNSEXCEL, NOMBRE, BORRAR, CONSULTA)
				SELECT @CNSEXCEL, 'conceptos con error_' + CONVERT(VARCHAR, GETDATE(), 112) + '_' + REPLACE(CONVERT(VARCHAR, GETDATE(), 108), ':', '') + '.xlsx', 1, 
					'SELECT STRINGMEDIO1 AS IDCONCEPTO, STRINGMEDIO2 AS CONCEPTO, STRINGMEDIO3 AS DESCRIPCION FROM RPDX WHERE CNS=  ''' + @CNS + ''''

				SELECT @CNSEXCEL CNSEXCEL
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GET_NOMIE_EMPLOYE_ACCOUNT'
	BEGIN
		EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@NIEPE', @LONGITUD = 8, @NVOCONSEC = @CNSNIEPE OUTPUT

		-- REVISAR USO DE CONSULTAS EN BOTON CONTABILIZAR
		SELECT @CODNOMINA = CODNOMINA, @NUMDOC = NUMDOC
		FROM OPENJSON(@PARAMETROS) WITH (CODNOMINA VARCHAR(2) '$.CODNOMINA', NUMDOC VARCHAR(20) '$.NUMDOC')

		SELECT 'OK' OK

		SELECT NUMDOC, CNSNIEPE = @CNSNIEPE, USUARIO = @USUARIO, SYS_COMPUTERNAME = @SYS_COMPUTERNAME, COMPANIA = @COMPANIA, SEDE = @IDSEDE, NROCOMPROBANTE = ''
		FROM NOMIE
		WHERE CODNOMINA = @CODNOMINA AND NUMDOC = @NUMDOC

		RETURN
	END

	IF @METODO = 'GET_NOMIE_EMPLOYEES_ACCOUNT'
	BEGIN
		SELECT @CNSPAGO = CNSPAGO
		FROM OPENJSON(@PARAMETROS) WITH (CNSPAGO VARCHAR(20) '$.CNSPAGO')

		SELECT 'OK' OK

		SELECT NIEPE.NUMDOC, CNSNIEPE, @COMPANIA AS COMPANIA, @IDSEDE AS SEDE, @USUARIO AS USUARIO, @SYS_COMPUTERNAME AS SYS_COMPUTERNAME, NROCOMPROBANTE, TER.
			RAZONSOCIAL AS NOMBRE_EMPLEADO
		FROM NIEPE
		INNER JOIN NEMP ON NEMP.NUMDOC = NIEPE.NUMDOC
		INNER JOIN TER ON TER.IDTERCERO = NEMP.TERCEROID
		WHERE CNSPAGO = @CNSPAGO AND COALESCE(CONTABILIZADA, 0) = 0

		RETURN
	END

	IF @METODO = 'UPDATE_NOMIE'
	BEGIN
		BEGIN TRY
			SELECT @DATOS = DATOS, @CODNOMINA = CODNOMINA
			FROM OPENJSON(@PARAMETROS) WITH (DATOS NVARCHAR(MAX) AS JSON, CODNOMINA VARCHAR(2) '$.CODNOMINA')

			BEGIN
				SET NOCOUNT ON;

				SELECT @CollationName = CONVERT(NVARCHAR(150), DATABASEPROPERTYEX(DB_NAME(), 'Collation'));

				CREATE TABLE #TempTable (ID INT PRIMARY KEY IDENTITY, CODNOMINA VARCHAR(2), NUMDOC VARCHAR(20));

				DECLARE @SQL NVARCHAR(MAX);

				SET @SQL = 'ALTER TABLE #TempTable ALTER COLUMN CODNOMINA VARCHAR(2) COLLATE ' + @CollationName + 
					';ALTER TABLE #TempTable ALTER COLUMN NUMDOC VARCHAR(20) COLLATE ' + @CollationName + ';';

				EXEC sp_executesql @SQL;

				INSERT INTO #TempTable (CODNOMINA, NUMDOC)
				SELECT @CODNOMINA COLLATE DATABASE_DEFAULT, JSON_VALUE(value, '$.NUMDOC') COLLATE DATABASE_DEFAULT
				FROM OPENJSON(@DATOS);

				IF ISJSON(@DATOS) = 1
				BEGIN
					INSERT INTO NOMIE (CODNOMINA, NUMDOC, ESTADO)
					SELECT t.CODNOMINA COLLATE DATABASE_DEFAULT, t.NUMDOC COLLATE DATABASE_DEFAULT, 'Activo'
					FROM #TempTable t
					LEFT JOIN NOMIE ON t.CODNOMINA COLLATE DATABASE_DEFAULT = NOMIE.CODNOMINA AND t.NUMDOC COLLATE DATABASE_DEFAULT = NOMIE.NUMDOC
					WHERE NOMIE.NUMDOC IS NULL

					DELETE NOMIE
					FROM NOMIE
					LEFT JOIN #TempTable t ON NOMIE.CODNOMINA = t.CODNOMINA COLLATE DATABASE_DEFAULT AND NOMIE.NUMDOC = t.NUMDOC COLLATE DATABASE_DEFAULT
					WHERE t.NUMDOC IS NULL AND NOMIE.CODNOMINA = jSON_VALUE(@PARAMETROS, '$.CODNOMINA') COLLATE DATABASE_DEFAULT;

					DROP TABLE #TempTable;
				END
				ELSE
				BEGIN
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ('El parametro JSON no es valido.')
				END
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
