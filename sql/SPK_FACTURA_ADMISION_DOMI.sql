AS      
DECLARE @NVOCONSEC     VARCHAR(20), @PRE VARCHAR(20), @CONSECFTR INT, @CNSRESOL VARCHAR(50)
DECLARE @NVOCONSEC1    VARCHAR(20)
DECLARE @CNSFTR        VARCHAR(20)
DECLARE @CERRADA       SMALLINT
DECLARE @FACTURADA     SMALLINT
