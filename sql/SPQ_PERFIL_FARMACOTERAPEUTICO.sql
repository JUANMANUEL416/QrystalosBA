CREATE OR ALTER PROCEDURE DBO.SPQ_PERFIL_FARMACOTERAPEUTICO
@JSON NVARCHAR(MAX)
WITH ENCRYPTION
AS
DECLARE @PARAMETROS       NVARCHAR(MAX)
      , @MODELO           VARCHAR(100)
      , @METODO           VARCHAR(100)
      , @USUARIO          VARCHAR(12)
      , @GRUPO            VARCHAR(20)
      , @USUNOMBRE        VARCHAR(250)
      , @SYS_COMPUTERNAME VARCHAR(50)
      , @COMPANIA         VARCHAR(20)
      , @IDSEDE           VARCHAR(20)
      , @SEDE             VARCHAR(20)
      , @NOADMISION       VARCHAR(20)
      , @FILTRO           VARCHAR(200)
      , @IDINVARTNA       VARCHAR(20)
      , @FFIN             DATETIME
      , @FINI             DATE
      , @I                INT
      , @I_TO             INT

DECLARE @HHOM TABLE (
    ID INT IDENTITY(1,1),
    IDSERVICIO VARCHAR(20) COLLATE DATABASE_DEFAULT,
    DESCSERVICIO VARCHAR(255) COLLATE DATABASE_DEFAULT,
    DOSIS VARCHAR(100) COLLATE DATABASE_DEFAULT
)

DECLARE @HBALID TABLE (
    ID INT IDENTITY(1,1),
    IDSERVICIO VARCHAR(20) COLLATE DATABASE_DEFAULT,
    ITEM INT,
    FECHA DATETIME,
    HORARIO VARCHAR(100) COLLATE DATABASE_DEFAULT
)

DECLARE @IZSOL TABLE (
    ID INT IDENTITY(1,1),
    IDSERVICIO VARCHAR(20) COLLATE DATABASE_DEFAULT,
    FECHA DATETIME,
    CANTIDADSOL INT,
    CANTIDADENT INT
)

BEGIN
    SET NOCOUNT ON
    SET LANGUAGE Spanish
    SET DATEFORMAT dmy

    SELECT *
    INTO #JSON
    FROM OPENJSON(@JSON)
    WITH (
        MODELO     VARCHAR(100) '$.MODELO',
        METODO     VARCHAR(100) '$.METODO',
        USUARIO    VARCHAR(12)  '$.USUARIO',
        PARAMETROS NVARCHAR(MAX) AS JSON
    )

    SELECT @MODELO = MODELO, @METODO = METODO, @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
    FROM #JSON
    SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO), @USUNOMBRE = NOMBRE FROM USUSU WHERE USUARIO = @USUARIO
    SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME, @COMPANIA = COMPANIA FROM USUSU WHERE USUARIO = @USUARIO
    SELECT @IDSEDE = IDSEDE, @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
    PRINT '@USUARIO=' + @USUARIO

    DECLARE @TBLERRORES TABLE (ERROR VARCHAR(500) COLLATE DATABASE_DEFAULT)

    SELECT @IDINVARTNA = DATO COLLATE DATABASE_DEFAULT FROM USVGS WHERE IDVARIABLE = 'IDINVARTNA'

    -- -------------------------------------------------------------------------
    -- LISTAR_PACIENTES: admisiones abiertas con >1 medicamento alto costo (HHOM)
    -- -------------------------------------------------------------------------
    IF @METODO = 'LISTAR_PACIENTES'
    BEGIN
        SELECT @FILTRO = NULLIF(LTRIM(RTRIM(FILTRO)), '')
        FROM OPENJSON(@PARAMETROS)
        WITH (FILTRO VARCHAR(200) COLLATE DATABASE_DEFAULT '$.FILTRO')

        BEGIN TRY
            SELECT 'OK' OK

            SELECT
                HADM.NOADMISION,
                AFI.DOCIDAFILIADO,
                DBO.FN_EDAD_PACIENTE(AFI.FNACIMIENTO, GETDATE(), 'ANO') AS EDAD,
                AFI.NOMBREAFI,
                COALESCE(SEC.DESCRIPCION, HHAB.DESCRIPCION, '') AS SERVICIO
            FROM HADM
                INNER JOIN AFI ON AFI.IDAFILIADO = HADM.IDAFILIADO
                LEFT JOIN HHAB ON HHAB.HABCAMA = HADM.HABCAMA
                LEFT JOIN HHAB SEC ON SEC.HABCAMA = HHAB.SECTOR AND SEC.CLASE = 'Sector'
            WHERE HADM.CERRADA = 0
              AND EXISTS (
                    SELECT HHOM.NOADMISION
                    FROM HHOM
                        INNER JOIN SER ON SER.IDSERVICIO = HHOM.IDSERVICIO
                        INNER JOIN IART ON IART.IDARTICULO = SER.IDARTICULO AND ISNULL(IART.PRINCIPAL, 0) = 1
                    WHERE SER.IDARTICULO COLLATE DATABASE_DEFAULT <> COALESCE(@IDINVARTNA, '') COLLATE DATABASE_DEFAULT
                      AND ISNULL(SER.MEDICAMENTOS, 0) = 1
                      AND ISNULL(IART.ALTO_COSTO, 0) = 1
                      AND HHOM.NOADMISION COLLATE DATABASE_DEFAULT = HADM.NOADMISION COLLATE DATABASE_DEFAULT
                    GROUP BY HHOM.NOADMISION
                    HAVING COUNT(1) > 1
              )
              AND (
                    @FILTRO IS NULL
                    OR HADM.NOADMISION COLLATE DATABASE_DEFAULT LIKE '%' + @FILTRO + '%' COLLATE DATABASE_DEFAULT
                    OR AFI.DOCIDAFILIADO COLLATE DATABASE_DEFAULT LIKE '%' + @FILTRO + '%' COLLATE DATABASE_DEFAULT
                    OR AFI.NOMBREAFI COLLATE DATABASE_DEFAULT LIKE '%' + @FILTRO + '%' COLLATE DATABASE_DEFAULT
              )
            ORDER BY AFI.NOMBREAFI, HADM.NOADMISION
        END TRY
        BEGIN CATCH
            INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
        END CATCH

        RETURN
    END

    -- -------------------------------------------------------------------------
    -- CONSULTAR_PERFIL: cabecera del paciente + detalle �ltimos 7 d�as
    -- -------------------------------------------------------------------------
    IF @METODO = 'CONSULTAR_PERFIL'
    BEGIN
        SELECT @NOADMISION = NULLIF(LTRIM(RTRIM(NOADMISION)), '')
        FROM OPENJSON(@PARAMETROS)
        WITH (NOADMISION VARCHAR(20) COLLATE DATABASE_DEFAULT '$.NOADMISION')

        IF @NOADMISION IS NULL
        BEGIN
            INSERT INTO @TBLERRORES(ERROR) SELECT 'Debe indicar el n�mero de admisi�n.'
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
        END

        IF NOT EXISTS (SELECT 1 FROM HADM WHERE NOADMISION COLLATE DATABASE_DEFAULT = @NOADMISION COLLATE DATABASE_DEFAULT)
        BEGIN
            INSERT INTO @TBLERRORES(ERROR) SELECT 'No se encontr� la admisi�n indicada.'
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
        END

        BEGIN TRY
            SELECT 'OK' OK

            -- Cabecera
            SELECT
                AFI.NOMBREAFI,
                AFI.DOCIDAFILIADO,
                AFI.SEXO,
                DBO.FN_EDAD_PACIENTE(AFI.FNACIMIENTO, GETDATE(), 'ANO') AS EDAD,
                COALESCE(MDX.DESCRIPCION, '') AS DIAGNOSTICO,
                COALESCE(SEC.DESCRIPCION, HHAB.DESCRIPCION, '') AS SERVICIO,
                COALESCE(HADM.HABCAMA, '') AS CAMA,
                HADM.NOADMISION
            FROM HADM
                INNER JOIN AFI ON AFI.IDAFILIADO = HADM.IDAFILIADO
                LEFT JOIN MDX ON MDX.IDDX = HADM.DXINGRESO
                LEFT JOIN HHAB ON HHAB.HABCAMA = HADM.HABCAMA
                LEFT JOIN HHAB SEC ON SEC.HABCAMA = HHAB.SECTOR AND SEC.CLASE = 'Sector'
            WHERE HADM.NOADMISION COLLATE DATABASE_DEFAULT = @NOADMISION COLLATE DATABASE_DEFAULT

            -- Medicamentos alto costo prescritos (HHOM)
            INSERT INTO @HHOM (IDSERVICIO, DESCSERVICIO, DOSIS)
            SELECT
                HHOM.IDSERVICIO,
                SER.DESCSERVICIO,
                CONVERT(VARCHAR(12), CONVERT(INT, HHOM.CANTIDAD)) + ' ' + ISNULL(SER.PRESUNI, 'UND')
                    + ' cada ' + CONVERT(VARCHAR(12), CONVERT(INT, HHOM.FRECUENCIA)) + ' horas'
            FROM HHOM
                INNER JOIN SER ON SER.IDSERVICIO = HHOM.IDSERVICIO
                INNER JOIN IART ON IART.IDARTICULO = SER.IDARTICULO AND ISNULL(IART.PRINCIPAL, 0) = 1
            WHERE SER.IDARTICULO COLLATE DATABASE_DEFAULT <> COALESCE(@IDINVARTNA, '') COLLATE DATABASE_DEFAULT
              AND ISNULL(SER.MEDICAMENTOS, 0) = 1
              AND ISNULL(IART.ALTO_COSTO, 0) = 1
              AND HHOM.NOADMISION COLLATE DATABASE_DEFAULT = @NOADMISION COLLATE DATABASE_DEFAULT

            -- Ventana de 7 d�as seg�n �ltima aplicaci�n en hoja de tratamiento
            SELECT @FFIN = MAX(FECHA)
            FROM DBO.VWK_HBALID
            WHERE NOADMISION COLLATE DATABASE_DEFAULT = @NOADMISION COLLATE DATABASE_DEFAULT
              AND CANTIDAD > 0
              AND ESTADO IN (1, 2)
              AND IDSERVICIO COLLATE DATABASE_DEFAULT IN (SELECT IDSERVICIO FROM @HHOM)

            SET @FINI = CONVERT(DATE, DATEADD(DAY, -7, COALESCE(@FFIN, GETDATE())))

            -- Horarios de aplicaci�n por d�a
            INSERT INTO @HBALID (ITEM, IDSERVICIO, FECHA, HORARIO)
            SELECT
                ROW_NUMBER() OVER (PARTITION BY IDSERVICIO, CONVERT(DATE, FECHA) ORDER BY IDSERVICIO, FECHA),
                IDSERVICIO,
                CONVERT(DATE, FECHA),
                RIGHT('00' + CONVERT(VARCHAR(10), DATEPART(HOUR, FECHA)), 2)
            FROM DBO.VWK_HBALID H
            WHERE NOADMISION COLLATE DATABASE_DEFAULT = @NOADMISION COLLATE DATABASE_DEFAULT
              AND CANTIDAD > 0
              AND ESTADO IN (1, 2)
              AND IDSERVICIO COLLATE DATABASE_DEFAULT IN (SELECT IDSERVICIO FROM @HHOM)
              AND FECHA >= @FINI

            SELECT @I = 1, @I_TO = COUNT(1) FROM @HBALID

            WHILE @I <= @I_TO
            BEGIN
                IF (SELECT ITEM FROM @HBALID WHERE ID = @I) > 1
                BEGIN
                    UPDATE A
                    SET HORARIO = A.HORARIO + ', ' + B.HORARIO
                    FROM @HBALID A
                        INNER JOIN @HBALID B ON A.IDSERVICIO = B.IDSERVICIO AND A.FECHA = B.FECHA
                    WHERE A.ITEM = 1 AND B.ID = @I

                    DELETE FROM @HBALID WHERE ID = @I
                END

                SET @I += 1
            END

            -- Solicitudes y entregas de farmacia
            INSERT INTO @IZSOL (IDSERVICIO, FECHA, CANTIDADSOL, CANTIDADENT)
            SELECT
                IZSOLD.IDSERVICIO,
                CONVERT(DATE, IZSOL.FECHASOL),
                SUM(IZSOLD.CANTIDADSOL),
                SUM(IZSOLDT.CANTIDADSOL)
            FROM IZSOL
                INNER JOIN IZSOLD ON IZSOLD.CNSIZSOL = IZSOL.CNSIZSOL
                INNER JOIN IZSOLDT ON IZSOLDT.CNSIZSOLD = IZSOLD.CNSIZSOLD AND IZSOLDT.IDARTICULO = IZSOLD.IDARTICULO
            WHERE IZSOL.NOADMISION COLLATE DATABASE_DEFAULT = @NOADMISION COLLATE DATABASE_DEFAULT
              AND IZSOL.CLASE COLLATE DATABASE_DEFAULT IN ('OMEDICA', '24HORAS', 'SENFER')
              AND CONVERT(DATE, IZSOL.FECHASOL) >= @FINI
              AND IZSOLD.IDSERVICIO COLLATE DATABASE_DEFAULT IN (SELECT IDSERVICIO FROM @HHOM)
            GROUP BY IZSOLD.IDSERVICIO, CONVERT(DATE, IZSOL.FECHASOL)

            -- Detalle del perfil
            SELECT
                CASE WHEN X.ITEM = 1 THEN X.DESCSERVICIO ELSE '' END AS MEDICAMENTO,
                CASE WHEN X.ITEM = 1 THEN X.DOSIS ELSE '' END AS DOSIS_SOLICITADA,
                X.FECHA,
                X.CANTIDADSOL AS CANTIDAD_SOLICITADA,
                X.CANTIDADENT AS CANTIDAD_ENTREGADA,
                X.HORARIO
            FROM (
                SELECT
                    ROW_NUMBER() OVER (PARTITION BY A.IDSERVICIO ORDER BY A.IDSERVICIO, B.FECHA DESC) AS ITEM,
                    A.DESCSERVICIO,
                    A.DOSIS,
                    B.FECHA,
                    B.HORARIO,
                    C.CANTIDADSOL,
                    C.CANTIDADENT
                FROM @HHOM A
                    INNER JOIN @HBALID B ON A.IDSERVICIO = B.IDSERVICIO
                    INNER JOIN @IZSOL C ON A.IDSERVICIO = C.IDSERVICIO AND B.FECHA = C.FECHA
            ) AS X
            ORDER BY X.DESCSERVICIO, X.FECHA DESC
        END TRY
        BEGIN CATCH
            INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
        END CATCH

        RETURN
    END

    INSERT INTO @TBLERRORES(ERROR) SELECT 'M�todo no implementado: ' + COALESCE(@METODO, '') COLLATE DATABASE_DEFAULT
    SELECT 'KO' OK
    SELECT ERROR FROM @TBLERRORES
END
