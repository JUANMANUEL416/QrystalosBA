CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NAJUST @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20), @PROCESO VARCHAR(20)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @DATOS NVARCHAR(MAX)
DECLARE @CNSAJUSTE VARCHAR(20), @FECHA DATETIME, @TIPO VARCHAR(10), @VALOR DECIMAL(14, 2), @APARTIR DATETIME
DECLARE @BASICOA DECIMAL(14, 2), @TIPOAJUS VARCHAR(10), @VLRAJUS DECIMAL(14, 2), @BASICON DECIMAL(14, 2)
DECLARE @SYS_COMPUTERNAME VARCHAR(255), @ESTADO VARCHAR(10), @COMPANIA VARCHAR(2), @IDSEDE VARCHAR(5), @GRADO VARCHAR(10), @NIVEL VARCHAR(10), @CODCARGO VARCHAR(20)
DECLARE @CollationName NVARCHAR(150)
DECLARE @SQL NVARCHAR(MAX)

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
	FROM USUSU
	WHERE USUARIO = @USUARIO

	SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
	FROM UBEQ
	WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @CNSAJUSTE = CNSAJUSTE, @FECHA = FECHA, @TIPO = TIPO, @VALOR = VALOR, @APARTIR = APARTIR, @ESTADO = ESTADO, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					CNSAJUSTE VARCHAR(20) '$.CNSAJUSTE', FECHA DATETIME '$.FECHA', TIPO VARCHAR(10) '$.TIPO', VALOR DECIMAL(14, 2) '$.VALOR', APARTIR DATETIME 
					'$.APARTIR', ESTADO VARCHAR(10) '$.ESTADO', PROCESO VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					SELECT @CNSAJUSTE = ''

					EXEC SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE, '@NAJUST', @CNSAJUSTE OUTPUT

					SELECT @CNSAJUSTE = @IDSEDE + REPLACE(SPACE(8 - LEN(@CNSAJUSTE)) + LTRIM(RTRIM(@CNSAJUSTE)), SPACE(1), 0)

					INSERT INTO [NAJUST] ([CNSAJUSTE], [FECHA], [TIPO], [VALOR], [APARTIR], [USUARIO], [SYS_COMPUTERNAME], [ESTADO])
					SELECT @CNSAJUSTE, @FECHA, @TIPO, @VALOR, @APARTIR, @USUARIO, @SYS_COMPUTERNAME, @ESTADO
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				SELECT @CNSAJUSTE = CNSAJUSTE
				FROM OPENJSON(@PARAMETROS) WITH (CNSAJUSTE VARCHAR(20) '$.CNSAJUSTE')

				UPDATE NAJUST
				SET FECHA = @FECHA, TIPO = @TIPO, VALOR = @VALOR, APARTIR = @APARTIR, ESTADO = @ESTADO
				WHERE CNSAJUSTE = @CNSAJUSTE
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GET_NCAR'
	BEGIN
		SELECT @CNSAJUSTE = CNSAJUSTE
		FROM OPENJSON(@PARAMETROS) WITH (CNSAJUSTE VARCHAR(20) '$.CNSAJUSTE')

		SELECT 'OK' OK

		SELECT NCARNG.CODCARGO, NCARNG.NIVEL, NCARNG.GRADO, NCAR.DESCRIPCION, NCARNG.DESCRIPCION AS CARGO, CONCAT (NCARNG.CODCARGO, NCARNG.NIVEL, NCARNG.GRADO
				) AS ROWKEY
		FROM NAJUSTD
		INNER JOIN NCARNG ON NAJUSTD.CODCARGO = NCARNG.CODCARGO AND NAJUSTD.NIVEL = NCARNG.NIVEL AND NAJUSTD.GRADO = NCARNG.GRADO
		INNER JOIN NCAR ON NCAR.CODCARGO = NCARNG.CODCARGO
		WHERE NAJUSTD.CNSAJUST = @CNSAJUSTE
		ORDER BY NAJUSTD.CODCARGO

		RETURN
	END

	IF @METODO = 'UPDATE_NAJUSTD'
	BEGIN
		BEGIN TRY
			SELECT @DATOS = DATOS, @CNSAJUSTE = CNSAJUSTE
			FROM OPENJSON(@PARAMETROS) WITH (DATOS NVARCHAR(MAX) AS JSON, CNSAJUSTE VARCHAR(20) '$.CNSAJUSTE')

			BEGIN
				SELECT @CollationName = CONVERT(NVARCHAR(150), DATABASEPROPERTYEX(DB_NAME(), 'Collation'));

				SET NOCOUNT ON;

				CREATE TABLE #TempTable (ID INT PRIMARY KEY IDENTITY, CNSAJUST VARCHAR(20), CODCARGO VARCHAR(20), NIVEL VARCHAR(10), GRADO VARCHAR(10)
					);

				SET @SQL = 'ALTER TABLE #TempTable ALTER COLUMN CNSAJUST VARCHAR(20) COLLATE ' + @CollationName + 
					';ALTER TABLE #TempTable ALTER COLUMN CODCARGO VARCHAR(20) COLLATE ' + @CollationName + 
					';ALTER TABLE #TempTable ALTER COLUMN NIVEL VARCHAR(10) COLLATE ' + @CollationName + 
					';ALTER TABLE #TempTable ALTER COLUMN GRADO VARCHAR(10) COLLATE ' + @CollationName + ';';

				EXEC sp_executesql @SQL;

				INSERT INTO #TempTable (CNSAJUST, CODCARGO, NIVEL, GRADO)
				SELECT @CNSAJUSTE COLLATE DATABASE_DEFAULT, JSON_VALUE(value, '$.CODCARGO') COLLATE DATABASE_DEFAULT, JSON_VALUE(value, '$.NIVEL') COLLATE 
					DATABASE_DEFAULT, JSON_VALUE(value, '$.GRADO') COLLATE DATABASE_DEFAULT
				FROM OPENJSON(@DATOS);

				IF ISJSON(@DATOS) = 1
				BEGIN
					INSERT INTO NAJUSTD (CNSAJUST, CODCARGO, NIVEL, GRADO)
					SELECT t.CNSAJUST COLLATE DATABASE_DEFAULT, t.CODCARGO COLLATE DATABASE_DEFAULT, t.NIVEL COLLATE DATABASE_DEFAULT, t.GRADO COLLATE 
						DATABASE_DEFAULT
					FROM #TempTable t
					LEFT JOIN NAJUSTD ON t.CNSAJUST COLLATE DATABASE_DEFAULT = NAJUSTD.CNSAJUST AND t.CODCARGO COLLATE DATABASE_DEFAULT = NAJUSTD.CODCARGO AND t.
						NIVEL COLLATE DATABASE_DEFAULT = NAJUSTD.NIVEL AND t.GRADO COLLATE DATABASE_DEFAULT = NAJUSTD.GRADO
					WHERE NAJUSTD.CODCARGO IS NULL

					DELETE NAJUSTD
					FROM NAJUSTD
					LEFT JOIN #TempTable t ON NAJUSTD.CNSAJUST = t.CNSAJUST COLLATE DATABASE_DEFAULT AND t.CODCARGO COLLATE DATABASE_DEFAULT = NAJUSTD.CODCARGO AND t.
						NIVEL COLLATE DATABASE_DEFAULT = NAJUSTD.NIVEL AND t.GRADO COLLATE DATABASE_DEFAULT = NAJUSTD.GRADO
					WHERE t.CODCARGO IS NULL AND NAJUSTD.CNSAJUST = jSON_VALUE(@PARAMETROS, '$.CNSAJUSTE') COLLATE DATABASE_DEFAULT;

					DROP TABLE #TempTable;
				END
				ELSE
				BEGIN
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ('El parametro JSON no es valido.')
				END
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @CNSAJUSTE = CNSAJUSTE, @CODCARGO = CODCARGO, @GRADO = GRADO, @NIVEL = NIVEL
		FROM OPENJSON(@PARAMETROS) WITH (CNSAJUSTE VARCHAR(20) '$.CNSAJUST', CODCARGO VARCHAR(20) '$.CODCARGO', NIVEL VARCHAR(10) '$.NIVEL', GRADO VARCHAR(10) '$.GRADO'
				)

		BEGIN TRY
			DELETE
			FROM NAJUSTD
			WHERE CNSAJUST = @CNSAJUSTE AND CODCARGO = @CODCARGO AND GRADO = @GRADO AND NIVEL = @NIVEL
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'APLICA_AJUSTE'
	BEGIN
		SELECT @CNSAJUSTE = CNSAJUSTE
		FROM OPENJSON(@PARAMETROS) WITH (CNSAJUSTE VARCHAR(20) '$.CNSAJUSTE')

		BEGIN TRY
			SELECT @FECHA = APARTIR, @TIPOAJUS = TIPO, @VLRAJUS = VALOR
			FROM NAJUST
			WHERE CNSAJUSTE = @CNSAJUSTE

			DECLARE AJUS_CURSOR CURSOR
			FOR
			SELECT CODCARGO, NIVEL, GRADO
			FROM NAJUSTD
			WHERE CNSAJUST = @CNSAJUSTE

			OPEN AJUS_CURSOR

			FETCH NEXT
			FROM AJUS_CURSOR
			INTO @CODCARGO, @NIVEL, @GRADO

			WHILE @@FETCH_STATUS = 0
			BEGIN
				SELECT TOP 1 @BASICOA = BASICO
				FROM NCARNGV
				WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVEL AND GRADO = @GRADO
				ORDER BY FECHA DESC

				IF @TIPOAJUS = 'Valor'
				BEGIN
					SELECT @BASICON = @BASICOA + @VLRAJUS
				END
				ELSE
				BEGIN
					SELECT @BASICON = (1 + @VLRAJUS / 100) * @BASICOA
				END

				EXEC DBO.SPK_AJUSTE_SALARIO_NEMP @CNSAJUSTE, @CODCARGO, @NIVEL, @GRADO, @BASICON, @FECHA, @USUARIO, @SYS_COMPUTERNAME

				FETCH NEXT
				FROM AJUS_CURSOR
				INTO @CODCARGO, @NIVEL, @GRADO
			END

			CLOSE AJUS_CURSOR

			DEALLOCATE AJUS_CURSOR

			UPDATE NAJUST
			SET ESTADO = 'Aplicado'
			WHERE CNSAJUSTE = @CNSAJUSTE
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ANULAR_AJUSTE'
	BEGIN
		SELECT @CNSAJUSTE = CNSAJUSTE
		FROM OPENJSON(@PARAMETROS) WITH (CNSAJUSTE VARCHAR(20) '$.CNSAJUSTE')

		BEGIN TRY
			SELECT @APARTIR = APARTIR
			FROM NAJUST
			WHERE CNSAJUSTE = @CNSAJUSTE

			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'YA SE HAN LIQUIDADO NOMINAS POSTERIORES A LA APLICACION DEL AJUSTE, SE DEBE HACER UN AJUSTE COMPLETAMENTE NUEVO'
			WHERE EXISTS (
					SELECT *
					FROM NPER
					WHERE FECHAINI >= @APARTIR AND CERRADO = 1
					)

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				DELETE NCARNGV
				WHERE COALESCE(CNSAJUSTE, '') = @CNSAJUSTE

				SELECT @FECHA = APARTIR
				FROM NAJUST
				WHERE CNSAJUSTE = @CNSAJUSTE

				DECLARE AJUS_CURSOR CURSOR
				FOR
				SELECT CODCARGO, NIVEL, GRADO
				FROM NAJUSTD
				WHERE CNSAJUST = @CNSAJUSTE

				OPEN AJUS_CURSOR

				FETCH NEXT
				FROM AJUS_CURSOR
				INTO @CODCARGO, @NIVEL, @GRADO

				WHILE @@FETCH_STATUS = 0
				BEGIN
					SELECT TOP 1 @BASICOA = BASICO
					FROM NCARNGV
					WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVEL AND GRADO = @GRADO
					ORDER BY FECHA DESC

					SELECT @BASICON = @BASICOA

					EXEC DBO.SPK_QUITA_AJUSTE_SALARIO_NEMP @CNSAJUSTE, @CODCARGO, @NIVEL, @GRADO, @BASICON, @FECHA, @USUARIO, @SYS_COMPUTERNAME

					FETCH NEXT
					FROM AJUS_CURSOR
					INTO @CODCARGO, @NIVEL, @GRADO
				END

				CLOSE AJUS_CURSOR

				DEALLOCATE AJUS_CURSOR

				UPDATE NAJUST
				SET ESTADO = 'Anulado'
				WHERE CNSAJUSTE = @CNSAJUSTE
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
