CREATE OR ALTER PROCEDURE DBO.SPK_MARCA_OP_PAGADA_POR_EGRESO
    @CODCAJA VARCHAR(20),
    @CNSFACJ VARCHAR(20),
    @USUARIO VARCHAR(12)
WITH ENCRYPTION
AS
SET NOCOUNT ON;

DECLARE @PROCEDENCIA VARCHAR(20);
DECLARE @CLASE_FAC VARCHAR(5);
DECLARE @OBSERVACION VARCHAR(255);
DECLARE @CNSFCXPPM VARCHAR(20);
DECLARE @REST VARCHAR(255);
DECLARE @POS INT;

IF COALESCE(@CODCAJA, '') = '' OR COALESCE(@CNSFACJ, '') = ''
BEGIN
    RETURN;
END

SELECT @PROCEDENCIA = PROCEDENCIA, @CLASE_FAC = CLASE_FAC, @OBSERVACION = OBSERVACION
FROM FCJ WHERE CODCAJA = @CODCAJA AND CNSFACJ = @CNSFACJ;

IF @PROCEDENCIA <> 'CXP' OR @CLASE_FAC <> 'PAGO'
BEGIN
    RETURN;
END

SELECT TOP (1) @CNSFCXPPM = CNSFCXPPM
FROM FCXPP WHERE CNSFACJ = @CNSFACJ
    AND CODCAJA = @CODCAJA
    AND ESTADO <> 'A'
    AND COALESCE(CNSFCXPPM, '') <> ''
ORDER BY CNSFCXPP DESC;

IF COALESCE(@CNSFCXPPM, '') = '' AND @OBSERVACION LIKE 'Orden: %'
BEGIN
    SET @REST = LTRIM(RTRIM(SUBSTRING(@OBSERVACION, 8, 255)));
    SET @POS = CHARINDEX(' - ', @REST);

    IF @POS > 1
    BEGIN
        SET @CNSFCXPPM = LTRIM(RTRIM(LEFT(@REST, @POS - 1)));
    END

    ELSE
    BEGIN
        SET @CNSFCXPPM = LTRIM(RTRIM(LEFT(@REST, 20)));
    END
END

UPDATE FCXPP
SET ESTADO = 'P',
    USUARIOCONF = COALESCE(USUARIOCONF, @USUARIO),
    FECHACONF = COALESCE(FECHACONF, DBO.FNK_GETDATE())
WHERE CNSFACJ = @CNSFACJ
    AND CODCAJA = @CODCAJA
    AND ESTADO <> 'A';

IF COALESCE(@CNSFCXPPM, '') = ''
BEGIN
    RETURN;
END

IF EXISTS (
    SELECT 1
    FROM FCXPP
    INNER JOIN FCJ
        ON FCJ.CNSFACJ = FCXPP.CNSFACJ
        AND FCJ.CODCAJA = FCXPP.CODCAJA
    WHERE FCXPP.CNSFCXPPM = @CNSFCXPPM
        AND FCXPP.ESTADO <> 'A'
        AND FCJ.ESTADO = 'P'
        AND COALESCE(FCJ.CERRADA, 0) = 0
        AND FCJ.PROCEDENCIA = 'CXP'
        AND FCJ.CLASE_FAC = 'PAGO'
)
BEGIN
    RETURN;
END

UPDATE FCXPP
SET ESTADO = 'P',
    USUARIOCONF = COALESCE(USUARIOCONF, @USUARIO),
    FECHACONF = COALESCE(FECHACONF, DBO.FNK_GETDATE())
WHERE CNSFCXPPM = @CNSFCXPPM
    AND ESTADO <> 'A';

UPDATE FCXPPM
SET ESTADO = 'P',
    USUARIOCONF = COALESCE(USUARIOCONF, @USUARIO),
    FECHACONF = COALESCE(FECHACONF, DBO.FNK_GETDATE()),
    OP_TER_IND = 1
WHERE CNSFCXPPM = @CNSFCXPPM
    AND ESTADO = 'C';
