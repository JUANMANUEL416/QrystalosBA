CREATE OR ALTER PROCEDURE DBO.SPQ_TEXCA @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20), @IDSEDE VARCHAR(5)
DECLARE @PROCESO VARCHAR(20)
DECLARE @IDTERCERO VARCHAR(20), @IDCATEGORIA VARCHAR(10), @ESTADO VARCHAR(10), @TIPOIPS VARCHAR(2), @IDMEDICOEXT VARCHAR(20), @NOMBREALTERNO VARCHAR(100)
DECLARE @IDCATEGORIAEDITE VARCHAR(10)
DECLARE @DATO NVARCHAR(MAX)

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @IDTERCERO = IDTERCERO, @PROCESO = PROCESO, @IDCATEGORIA = IDCATEGORIA, @ESTADO = ESTADO, @TIPOIPS = TIPOIPS, @IDMEDICOEXT = IDMEDICOEXT, 
				@NOMBREALTERNO = NOMBREALTERNO
			FROM OPENJSON(@PARAMETROS) WITH (
					PROCESO VARCHAR(20) '$.PROCESO', IDTERCERO VARCHAR(20) '$.IDTERCERO', IDCATEGORIA VARCHAR(10) '$.IDCATEGORIA', ESTADO VARCHAR(10) '$.ESTADO', 
					TIPOIPS VARCHAR(2) '$.TIPOIPS', IDMEDICOEXT VARCHAR(20) '$.IDMEDICOEXT', NOMBREALTERNO VARCHAR(100) '$.NOMBREALTERNO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('YA EXISTE LA CATEGORIA ', @IDCATEGORIA, ' PARA EL TERCERO ', @IDTERCERO)
					WHERE EXISTS (
							SELECT 1
							FROM TEXCA
							WHERE IDTERCERO = @IDTERCERO AND IDCATEGORIA = @IDCATEGORIA
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO TEXCA (IDTERCERO, IDCATEGORIA, ESTADO, TIPOIPS, IDMEDICOEXT, NOMBREALTERNO)
						SELECT @IDTERCERO, @IDCATEGORIA, CASE 
								WHEN @ESTADO = 1
									THEN 'Activo'
								ELSE 'Inactivo'
								END, @TIPOIPS, @IDMEDICOEXT, @NOMBREALTERNO
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @DATO = DATO
					FROM OPENJSON(@PARAMETROS) WITH (DATO NVARCHAR(MAX) AS JSON)

					SELECT @IDCATEGORIAEDITE = IDCATEGORIAEDITE
					FROM OPENJSON(@DATO) WITH (IDCATEGORIAEDITE VARCHAR(10) '$.IDCATEGORIAEDITE')

					UPDATE TEXCA
					SET IDCATEGORIA = @IDCATEGORIA, ESTADO = CASE 
							WHEN @ESTADO = 1
								THEN 'Activo'
							ELSE 'Inactivo'
							END, TIPOIPS = @TIPOIPS, IDMEDICOEXT = @IDMEDICOEXT, NOMBREALTERNO = @NOMBREALTERNO
					WHERE IDTERCERO = @IDTERCERO AND IDCATEGORIA = @IDCATEGORIAEDITE
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @IDTERCERO = IDTERCERO, @IDCATEGORIA = IDCATEGORIA
		FROM OPENJSON(@PARAMETROS) WITH (IDTERCERO VARCHAR(20) '$.IDTERCERO', IDCATEGORIA VARCHAR(10) '$.IDCATEGORIA')

		BEGIN TRY
			DELETE
			FROM TEXCA
			WHERE IDTERCERO = @IDTERCERO AND IDCATEGORIA = @IDCATEGORIA
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
