CREATE VIEW DBO.SERESPPCOSTO WITH SCHEMABINDING    
AS
SELECT DISTINCT DBO.ESP.IDPROVEEDOR AS IDTERCERO,DBO.ESP.IDTARIFA,DBO.SER.PREFIJO AS PREFIJO,DBO.ESP.IDSERVICIO,
       DBO.SER.DESCSERVICIO,DBO.SER.SEXO,DBO.ESP.VALOR,DBO.ESP.FACTOR,DBO.ESP.IDPLAN,    
       ROUND(DBO.IARTPCOSTO.PCOSTO * DBO.ESP.FACTOR,0) AS VLRSERVICIO,
       0 AS CIRUGIA, DBO.ESP.PAQUETE, DBO.ESP.DETALLADO, DBO.ESP.TIPOCONTRATO COLLATE database_default AS TIPOCONTRATO,
       '01/01/2000' AS FECHAINIFD ,GETDATE()+1  AS FECHAFINFD,
       DBO.SER.NIVELFUNCIONARIO, DBO.SER.NIVELSEDE, DBO.SER.MOBSOBLIGATORIA, DBO.SER.POS,
       DBO.SER.REQAUTORIZACION, DBO.SER.TIPOAUTORIZACION, DBO.ESP.IDACUMULADOR COLLATE database_default AS IDACUMULADOR, DBO.SER.MEDICAMENTOS,
       DBO.SER.IDARTICULO, DBO.SER.NIVELATENCION, DBO.SER.IDGENERICO, '01/01/2000' AS FECHAINI, 
         GETDATE()+1 AS FECHAFIN, '' AS CODIFICACION, DBO.SER.CODCUPS, DBO.SER.ESTADO
FROM   DBO.ESP
		INNER JOIN DBO.SER ON DBO.SER.IDSERVICIO=DBO.ESP.IDSERVICIO
		INNER JOIN DBO.PPT ON DBO.ESP.IDPROVEEDOR = DBO.PPT.IDTERCERO AND DBO.ESP.IDPLAN = DBO.PPT.IDPLAN
		INNER JOIN DBO.IARTPCOSTO ON DBO.SER.IDSERVICIO  = DBO.IARTPCOSTO.IDSERVICIO
WHERE  DBO.SER.IDSERVICIO = DBO.ESP.IDSERVICIO AND DBO.ESP.TIPORESTRICCION = 'PCosto' AND DBO.ESP.FACTOR>0
