CREATE OR ALTER PROCEDURE DBO.SPQ_NDISP @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @METODO VARCHAR(100)
DECLARE @NUMDOC VARCHAR(20), @USUARIO VARCHAR(12), @SYS_COMPUTERNAME VARCHAR(254), @COMPANIA VARCHAR(2), @SEDE VARCHAR(5), @IDSEDE VARCHAR(5)
DECLARE @PROCESO VARCHAR(20), @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @CODPLANTA VARCHAR(20), @PORCENTAJE DECIMAL(7, 2), @IDAREA VARCHAR(20), @CCOSTO 
	VARCHAR(20), @IDNDISP INT
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @CODPLANTA = CODPLANTA, @CCOSTO = CCOSTO, @PORCENTAJE = PORCENTAJE, @IDAREA = IDAREA, @PROCESO = PROCESO, @IDNDISP = IDNDISP
			FROM OPENJSON(@PARAMETROS) WITH (
					CODPLANTA VARCHAR(20) '$.CODPLANTA', PORCENTAJE DECIMAL(7, 2) '$.PORCENTAJE', CCOSTO VARCHAR(20) '$.CCOSTO', IDAREA VARCHAR(20) '$.IDAREA', 
					PROCESO VARCHAR(20) '$.PROCESO', IDNDISP INT '$.IDNDISP'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					IF (
							SELECT 1
							FROM NDISP
							WHERE CODPLANTA = @CODPLANTA AND CCOSTO = @CCOSTO AND IDAREA = @IDAREA
							) = 1
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('LA PLANTA YA CUENTA CON UNA DISTRIBUCION PARA EL AREA ', @IDAREA, ' Y EL CENTRO DE COSTO ', @CCOSTO, '.'
								)
					END

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO NDISP (CODPLANTA, CCOSTO, IDAREA, PORCENTAJE)
						SELECT @CODPLANTA, @CCOSTO, @IDAREA, @PORCENTAJE
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @IDNDISP = IDNDISP
					FROM OPENJSON(@PARAMETROS) WITH (IDNDISP INT '$.IDNDISP')

					IF (
							SELECT 1
							FROM NDISP
							WHERE CODPLANTA = @CODPLANTA AND CCOSTO = @CCOSTO AND IDAREA = @IDAREA AND IDNDISP <> @IDNDISP
							) = 1
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('LA PLANTA YA CUENTA CON UNA DISTRIBUCION PARA EL AREA ', @IDAREA, ' Y EL CENTRO DE COSTO ', @CCOSTO, '.'
								)
					END

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						UPDATE NDISP
						SET CCOSTO = @CCOSTO, IDAREA = @IDAREA, PORCENTAJE = @PORCENTAJE
						WHERE IDNDISP = @IDNDISP
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GET_DISTRIBUCION'
	BEGIN
		SELECT @CODPLANTA = CODPLANTA
		FROM OPENJSON(@PARAMETROS) WITH (CODPLANTA VARCHAR(20) '$.CODPLANTA')

		SELECT OK = 'OK'

		SELECT ISNULL(SUM(PORCENTAJE), 0) AS PORCENTAJE
		FROM NDISP
		WHERE CODPLANTA = @CODPLANTA;
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @IDNDISP = IDNDISP
		FROM OPENJSON(@PARAMETROS) WITH (IDNDISP INT '$.IDNDISP')

		BEGIN TRY
			DELETE
			FROM NDISP
			WHERE IDNDISP = @IDNDISP
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
