IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME = 'SPK_CIERRA_PERIODOCONTABLE' AND XTYPE='P')
BEGIN
   DROP PROCEDURE SPK_CIERRA_PERIODOCONTABLE
END

GO
CREATE PROC DBO.SPK_CIERRA_PERIODOCONTABLE 
@ANO     VARCHAR(4), 
@MES     INT,
@USUARIO VARCHAR(12)
WITH ENCRYPTION
AS
DECLARE @AUX    INT
BEGIN
   PRINT 'NUEVA CONTABILIDAD'
   SELECT @AUX = COUNT(*) FROM PRI WHERE COALESCE(SI,0) = 1
   IF COALESCE(@AUX,0) > 1
   BEGIN
      RAISERROR('MAS DE UN PERIODO DEFINIDO COMO DE SALDOS INICIALES',16,1)
      RETURN
   END
   SELECT @AUX = COALESCE(SI,0) FROM PRI WHERE ANO = @ANO AND MES = @MES
   IF COALESCE(@AUX,0) = 1
   BEGIN
      PRINT 'ES DE SALDOS INICIALES'
      EXEC SPK_CIERRE_SALDOS_INICIALES @ANO, @MES, @USUARIO
   END
   ELSE
   BEGIN
      PRINT 'ES PERIODO CONTABLE NORMAL'
      EXEC SPK_CIERRE_MES_CONTABLE @ANO, @MES, @USUARIO
   END
END
