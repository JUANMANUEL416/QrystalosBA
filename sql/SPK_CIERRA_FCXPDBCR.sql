IF EXISTS (SELECT NAME FROM SYSOBJECTS WHERE NAME = 'SPK_CIERRA_FCXPDBCR' AND TYPE = 'P')
BEGIN
   DROP PROCEDURE SPK_CIERRA_FCXPDBCR 
END

GO
CREATE PROCEDURE DBO.SPK_CIERRA_FCXPDBCR  
@CNSFCXP  VARCHAR(20),
@ITEM     SMALLINT,
@IDSEDE   VARCHAR(5),
@USUARIO  VARCHAR(20)  
WITH ENCRYPTION
AS  
DECLARE @IDTERCERONVO VARCHAR(20),  @CNSFCXPNVA   VARCHAR(20),   @IDSERVICIO  VARCHAR(10), @VALORNTA DECIMAL(14,2), @CONTABILIZADA SMALLINT,
        @OBSERVACION  VARCHAR(255), @NODOCUMENTO  VARCHAR(20),   @FECHANOT    DATETIME,    @CUENTADB VARCHAR(20),   @CUENTACR VARCHAR(20),
        @SYSCOMPUTER  VARCHAR(255), @NROCOMPROBANTE VARCHAR(20), @IDTERCERO   VARCHAR(20)     
BEGIN  
   PRINT 'INICIO CAPTURA DE DATOS'
   
   SELECT @CONTABILIZADA=CONTABILIZADA,@IDTERCERONVO=IDTERCEROGENCXP,@IDSERVICIO=IDSERVICIO,@VALORNTA=VALOR,@OBSERVACION=OBSERVACION,
          @NODOCUMENTO=NODOCUMENTO,@FECHANOT=FECHA,@CUENTACR=CUENTA_CR,@CUENTADB=CUENTA_DB,@SYSCOMPUTER=HOST_NAME(),@CNSFCXPNVA=COALESCE(CNSCXP,'')
   FROM FCXPDBCR WHERE CNSFCXP=@CNSFCXP AND ITEM=@ITEM

   IF COALESCE(@CONTABILIZADA,0)=1
   BEGIN
      PRINT 'Nota Contabilizada '
      RETURN
   END
   IF COALESCE(@CNSFCXPNVA,'')=''
   BEGIN
      PRINT 'SE GENERA LA CXP NUEVA'
      SELECT @CNSFCXPNVA=SPACE(20)
      EXEC SPK_GENCONSECUTIVO '01',@IDSEDE,'@FCXPSR', @CNSFCXPNVA OUTPUT  
      SELECT @CNSFCXPNVA = @IDSEDE + 'SR' + REPLACE(SPACE(6 - LEN(@CNSFCXPNVA))+LTRIM(RTRIM(@CNSFCXPNVA)),SPACE(1),0)   

       PRINT '@NVOCONSEC =' + @CNSFCXPNVA
       PRINT '@IDTERCERO = '+@IDTERCERO
       INSERT INTO FCXP  (CNSFCXP, FECHA, CNSFCOM, IDTERCERO, NOREFERENCIA, F_FACTURAREF, F_VENCE, VALOR, ESTADO, F_CANCELADO,
                          USUARIO, TIPOCXP, PROCEDENCIA, OBSERVACION, COMPANIA, SYS_ComputerName, USUARIOMOD, FECHAMOD, NUMCUOTA,
                          MARCACONT, CONTABILIZADA, NROCOMPROBANTE, SALDO, IDCLASEIMP, VLR_DESCUENTO, VLR_IVA, VLR_NETO, VLR_IMPUESTOS,
                          SALDO_IMPUESTO, VLR_NOTASDEBITO, VLR_COMISION, VLR_GLOSAS, VLR_FLETE, CUEDEBITO, CUECREDITO, CNSFCXPPM,
                          MODALIDAD, SUBSIDIO, IDCONTRATO, VLR_NOTASCREDITO, VLR_ABONOS, IDSEDE, PERIODO_ANO, PERIODO_MES, CODUNG,
                          CODPRG, CIUDAD, ENPRESUPUESTO, SEAMORTIZA, NUMPERAMORT, IDPROPIETARIO)
--SE HACE CAMBIO EN LA FECHA PARA QUE LLEGUE A CONTABILIDAD EN EL MOMENTO DE REALIZACION DE NOTA
       SELECT  @CNSFCXPNVA, @FECHANOT, @CNSFCXP, @IDTERCERONVO, @NODOCUMENTO, @FECHANOT, @FECHANOT, 0, 'N', NULL,
                         @USUARIO, TIPOCXP, PROCEDENCIA,@OBSERVACION, COMPANIA, @SYSCOMPUTER, @USUARIO, GETDATE(), NUMCUOTA,
                         0, 0, NULL, 0, NULL, 0, 0, 0, 0,
                         0, 0, 0, 0, 0, NULL, @CUENTACR, NULL,
                         MODALIDAD, SUBSIDIO, IDCONTRATO, 0, 0, @IDSEDE, YEAR(@FECHANOT), MONTH(@FECHANOT), CODUNG,
                         CODPRG, CIUDAD, ENPRESUPUESTO, SEAMORTIZA, NUMPERAMORT, IDPROPIETARIO
       FROM    FCXP
       WHERE   CNSFCXP   = @CNSFCXP
  
       INSERT INTO FCXPD ( CNSFCXP, ITEM, IDSERVICIO, CANTIDAD, VALOR, ESTADO, N_PRESUP, ITEM_PRESUP, IDCLASEIMP, VLR_DESCUENTO,
                           VLR_IVA, VLR_NETO, NOLOTE, IDGRUPOSER, PREFIJO, CCOSTO, CCOSTO2, IDAREAH, IDAREA, NROCOMPROBANTE,
                           CUENTA_SER, VLR_GLOSAS, CUENTA_GLO, PROCEDENCIA, CODUNG, CODPRG, IDIMPUESTO, IDCLASE, ITEM_FIMPDV,
                           CUENTA_IVA, REDONDEO)
       SELECT TOP 1 @CNSFCXPNVA, 1, @IDSERVICIO, 1, @VALORNTA, 'N', N_PRESUP, ITEM_PRESUP, NULL, 0,
                           0, @VALORNTA, NOLOTE, @IDSERVICIO, PREFIJO, CCOSTO, CCOSTO2, IDAREAH, IDAREA, NROCOMPROBANTE,
                           @CUENTADB, 0, 0, PROCEDENCIA, CODUNG, CODPRG, IDIMPUESTO, IDCLASE, ITEM_FIMPDV,
                           0, REDONDEO
       FROM   FCXPD
       WHERE  CNSFCXP   = @CNSFCXP

       PRINT 'RECALCULO DE CXP'
       EXEC SPK_CALCULOVALORESCXP @CNSFCXPNVA

       PRINT 'CONTABILIZACION '
       EXEC SPK_NC_CONTAB_CXP @CNSFCXPNVA,@USUARIO,@SYSCOMPUTER,'01',@IDSEDE,''

       PRINT 'ACTUALIZANDO LA CXP CON EL VALOR DE LA NOTA'
       IF DBO.FNK_VALORVARIABLE('CONT_FCXPDBCR_Y_FCXP') <> 'SI'
       BEGIN
          UPDATE FCXP SET VLR_NOTASDEBITO=COALESCE(VLR_NOTASDEBITO,0)+@VALORNTA WHERE CNSFCXP=@CNSFCXP
          PRINT 'RECALCULO DE CXP'
          EXEC SPK_CALCULOVALORESCXP @CNSFCXP
          SELECT @NROCOMPROBANTE=NROCOMPROBANTE FROM FCXP WHERE CNSFCXP=@CNSFCXPNVA
          PRINT '@NROCOMPROBANTE === '+COALESCE(@NROCOMPROBANTE,'XXXXX')
          IF COALESCE(@NROCOMPROBANTE,'')<>''
          BEGIN 
             UPDATE FCXPDBCR SET CONTABILIZADA=1,NROCOMPROBANTE=@NROCOMPROBANTE,CNSCXP=@CNSFCXPNVA WHERE CNSFCXP=@CNSFCXP AND ITEM=@ITEM
          END
          ELSE
          BEGIN
             UPDATE FCXPDBCR SET  CNSCXP=@CNSFCXPNVA WHERE CNSFCXP=@CNSFCXP AND ITEM=@ITEM
          END
       END 
   END
END
