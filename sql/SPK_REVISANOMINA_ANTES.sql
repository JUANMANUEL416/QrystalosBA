IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='SPK_REVISANOMINA_ANTES' AND XTYPE='P')
BEGIN
   DROP PROCEDURE SPK_REVISANOMINA_ANTES
END
GO
CREATE   PROCEDURE DBO.SPK_REVISANOMINA_ANTES
@CNSRPDX VARCHAR(20),
@CNSPAGO VARCHAR(20)
WITH ENCRYPTION
AS
DECLARE @CNSPPTO VARCHAR(20)
DECLARE @FECHINI DATETIME
DECLARE @FECHAFIN DATETIME
DECLARE @IDPLANILLA VARCHAR(20)
BEGIN
   SELECT @FECHINI=FECHAINI,@FECHAFIN=FECHAFIN  FROM NPER WHERE CNSPAGO=@CNSPAGO
   SELECT @CNSPPTO=CONSECUTIVO FROM PTPTO WHERE FECHAINI<=@FECHINI AND FECHAFIN>@FECHAFIN
   PRINT '@CNSPPTO = '+COALESCE(@CNSPPTO,'NO TENGO PPTO')
   IF COALESCE(DBO.FNK_VALORVARIABLE('TOMA_RUBROENVIO_NOMI'),'NCOND')='NCOND'
   BEGIN
      IF EXISTS(SELECT * FROM NEMPFD INNER JOIN NCOND ON NEMPFD.CODCONCEPTO=NCOND.CODCONCEPTO AND NEMPFD.ITEMCONCEPTO=NCOND.ITEM WHERE NEMPFD.CNSPAGO=@CNSPAGO AND COALESCE(NCOND.RUBRO,'')='')
      BEGIN
         INSERT INTO RPDX(CNS,ID1,STRINGGRANDE1,STRINGMEDIO1)
         SELECT DISTINCT @CNSRPDX, NCOND.CODCONCEPTO,NCON.DESCRIPCION,'No tiene Rubro Asociado'
         FROM NEMPFD INNER JOIN NCOND ON NEMPFD.CODCONCEPTO=NCOND.CODCONCEPTO 
                                         AND NEMPFD.ITEMCONCEPTO=NCOND.ITEM 
                     INNER JOIN NCON ON NCOND.CODCONCEPTO=NCON.CODCONCEPTO
         WHERE NEMPFD.CNSPAGO=@CNSPAGO AND COALESCE(NCOND.RUBRO,'')=''

         IF EXISTS( SELECT *
                     FROM NEMPFD INNER JOIN NCOND ON NEMPFD.CODCONCEPTO=NCOND.CODCONCEPTO 
                                                     AND NEMPFD.ITEMCONCEPTO=NCOND.ITEM 
                                 INNER JOIN NCON ON NCOND.CODCONCEPTO=NCON.CODCONCEPTO
                     WHERE NEMPFD.CNSPAGO=@CNSPAGO AND COALESCE(NCOND.RUBRO,'')<>''
                     AND NOT EXISTS(SELECT * FROM PTRUB WHERE NCOND.RUBRO=PTRUB.RUBRO AND CONSECUTIVO=@CNSPPTO))
         BEGIN
            INSERT INTO RPDX(CNS,ID1,STRINGGRANDE1,STRINGMEDIO1)
            SELECT DISTINCT @CNSRPDX, NCOND.CODCONCEPTO,NCON.DESCRIPCION,'Rubro No Pertenece a la Vigencia de la Nomina'
            FROM NEMPFD INNER JOIN NCOND ON NEMPFD.CODCONCEPTO=NCOND.CODCONCEPTO 
                                             AND NEMPFD.ITEMCONCEPTO=NCOND.ITEM 
                        INNER JOIN NCON ON NCOND.CODCONCEPTO=NCON.CODCONCEPTO
            WHERE NEMPFD.CNSPAGO=@CNSPAGO AND COALESCE(NCOND.RUBRO,'')<>''
            AND NOT EXISTS(SELECT * FROM PTRUB WHERE NCOND.RUBRO=PTRUB.RUBRO AND CONSECUTIVO=@CNSPPTO)
         END
      END
   END
   ELSE
   BEGIN
      SELECT @IDPLANILLA=NOMI.IDPLANTILLA 
      FROM NPER INNER JOIN NOMI ON NPER.CODNOMINA=NOMI.CODNOMINA 
      WHERE CNSPAGO=@CNSPAGO

      IF EXISTS(SELECT * FROM NEMPFD INNER JOIN NPLTCO ON NEMPFD.CODCONCEPTO=NPLTCO.CODCONCEPTO 
                                                AND NPLTCO.IDPLANTILLA=@IDPLANILLA
                  WHERE NEMPFD.CNSPAGO=@CNSPAGO AND COALESCE(NPLTCO.RUBRO,'')='')
      BEGIN
         INSERT INTO RPDX(CNS,ID1,STRINGGRANDE1,STRINGMEDIO1)
         SELECT DISTINCT @CNSRPDX, NPLTCO.CODCONCEPTO,NCON.DESCRIPCION,'No tiene Rubro Asociado'
         FROM NEMPFD INNER JOIN NPLTCO ON NEMPFD.CODCONCEPTO=NPLTCO.CODCONCEPTO 
                                          AND NPLTCO.IDPLANTILLA=@IDPLANILLA 
                     INNER JOIN NCON ON NPLTCO.CODCONCEPTO=NCON.CODCONCEPTO
         WHERE NEMPFD.CNSPAGO=@CNSPAGO AND COALESCE(NPLTCO.RUBRO,'')=''

         IF EXISTS( SELECT * FROM NEMPFD INNER JOIN NPLTCO ON NEMPFD.CODCONCEPTO=NPLTCO.CODCONCEPTO 
                                 INNER JOIN NCON ON NPLTCO.CODCONCEPTO=NCON.CODCONCEPTO 
                                                    AND NPLTCO.IDPLANTILLA=@IDPLANILLA
                     WHERE NEMPFD.CNSPAGO=@CNSPAGO AND COALESCE(NPLTCO.RUBRO,'')<>''
                     AND NOT EXISTS(SELECT * FROM PTRUB WHERE NPLTCO.RUBRO=PTRUB.RUBRO AND CONSECUTIVO=@CNSPPTO))
         BEGIN
            INSERT INTO RPDX(CNS,ID1,STRINGGRANDE1,STRINGMEDIO1)
            SELECT DISTINCT @CNSRPDX, NPLTCO.CODCONCEPTO,NCON.DESCRIPCION,'Rubro No Pertenece a la Vigencia de la Nomina'
            FROM NEMPFD INNER JOIN NPLTCO ON NEMPFD.CODCONCEPTO=NPLTCO.CODCONCEPTO 
                                             AND NPLTCO.IDPLANTILLA=@IDPLANILLA
                        INNER JOIN NCON ON NPLTCO.CODCONCEPTO=NCON.CODCONCEPTO
            WHERE NEMPFD.CNSPAGO=@CNSPAGO AND COALESCE(NPLTCO.RUBRO,'')<>''
            AND NOT EXISTS(SELECT * FROM PTRUB WHERE NPLTCO.RUBRO=PTRUB.RUBRO AND CONSECUTIVO=@CNSPPTO)
         END
      END
   END
END
