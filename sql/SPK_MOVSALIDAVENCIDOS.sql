CREATE OR ALTER PROCEDURE DBO.SPK_MOVSALIDAVENCIDOS  
@COMPANIA    VARCHAR(20) ,
@SEDE        VARCHAR(20) ,
@USUARIO     VARCHAR(20) ,
@IDBODEGA    VARCHAR (20),
@SYSCOMPUTERNAME VARCHAR(20),
@IDARTICULO VARCHAR(20)
WITH ENCRYPTION
AS  
BEGIN 
	SET NOCOUNT ON;
	SET XACT_ABORT ON;

	DECLARE @CNSMOV         VARCHAR(20)
	DECLARE @CCOSTO_IMOV    VARCHAR(20)
	DECLARE @COMPANIA_CEN   VARCHAR(20) = LTRIM(RTRIM(@COMPANIA))
	DECLARE @IDTIPOMOV      VARCHAR(20)
	DECLARE @SECONTABILIZA  INT
	DECLARE @ERRMSG         NVARCHAR(2048)

	SELECT @IDTIPOMOV = dbo.FNK_VALORVARIABLE('IDINVSALVENCIDOS')

	SELECT @CCOSTO_IMOV = CASE
			WHEN NULLIF(LTRIM(RTRIM(IBOD.CCOSTO)), '') IS NOT NULL
				 AND EXISTS (
					 SELECT 1
					 FROM dbo.CEN C WITH (NOLOCK)
					 WHERE C.COMPANIA = @COMPANIA_CEN
					   AND C.CCOSTO = LTRIM(RTRIM(IBOD.CCOSTO))
					   AND C.ESTADO = 'Activo'
				 )
				THEN LTRIM(RTRIM(IBOD.CCOSTO))
			ELSE (
				 SELECT TOP 1 C2.CCOSTO
				 FROM dbo.CEN C2 WITH (NOLOCK)
				 WHERE C2.COMPANIA = @COMPANIA_CEN
				   AND C2.ESTADO = 'Activo'
				 ORDER BY C2.CCOSTO
				)
		END
	FROM dbo.IBOD IBOD WITH (NOLOCK)
	WHERE IBOD.IDBODEGA = @IDBODEGA

	IF COALESCE(@CCOSTO_IMOV, '') = ''
	BEGIN
		RAISERROR('No hay centro de costo usable: asigne CCOSTO en la bodega (IBOD) vigente en CEN (Activo) para la compa��a, o cree al menos un centro de costo Activo en CEN.', 16, 1)
		RETURN
	END

	-- Validar config contable ANTES de crear IMOV/ISAL/bajar IEXI
	SELECT @SECONTABILIZA = IIF(ISNULL(IBOD.NOCONTABILIZA, 0) = 1, 0, COALESCE(ITMO.SECONTABILIZA, 0))
	FROM dbo.IBOD IBOD WITH (NOLOCK)
	INNER JOIN dbo.ITMO ITMO WITH (NOLOCK) ON ITMO.IDTIPOMOV = @IDTIPOMOV
	WHERE IBOD.IDBODEGA = @IDBODEGA

	IF @SECONTABILIZA = 1
	BEGIN
		IF NOT EXISTS (
			SELECT 1
			FROM KMCOM WITH (NOLOCK)
			WHERE IDTIPOCONT = 'MOV_INVENTARIO'
			  AND IDMODELOCONT = '01'
			  AND TIPO = 'CR'
			  AND PREFIJO = @IDTIPOMOV
			  AND CCOSTO = @CCOSTO_IMOV
		)
		BEGIN
			RAISERROR('Inconsistencia. No existe configuraci�n contable para confirmar el movimiento: MOV_INVENTARIO. Cuenta cr�dito.', 16, 1)
			RETURN
		END

		IF NOT EXISTS (
			SELECT 1
			FROM KMCOM WITH (NOLOCK)
			WHERE IDTIPOCONT = 'MOV_INVENTARIO'
			  AND IDMODELOCONT = '01'
			  AND TIPO = 'DB'
			  AND PREFIJO = @IDTIPOMOV
			  AND CCOSTO = @CCOSTO_IMOV
		)
		BEGIN
			RAISERROR('Inconsistencia. No existe configuraci�n contable para confirmar el movimiento: MOV_INVENTARIO. Cuenta D�bito.', 16, 1)
			RETURN
		END
	END

	IF NOT EXISTS (
		SELECT 1
		FROM IEXI WITH (NOLOCK)
		INNER JOIN IART WITH (NOLOCK) ON IART.IDARTICULO = IEXI.IDARTICULO
		WHERE DBO.FNK_SEMAFOROIEXI(IEXI.IDBODEGA, IEXI.IDARTICULO, IEXI.NOLOTE) = 1
		  AND IEXI.IDBODEGA = @IDBODEGA
		  AND IEXI.EXISLOTE > 0
		  AND IEXI.IDARTICULO = CASE WHEN COALESCE(@IDARTICULO, '') <> '' THEN @IDARTICULO ELSE IEXI.IDARTICULO END
	)
	BEGIN
		RAISERROR('No hay art�culos vencidos con existencia para generar la salida.', 16, 1)
		RETURN
	END

	BEGIN TRY
		BEGIN TRANSACTION

		PRINT'------------------------------------------------------------------------------------------------------------'
		PRINT'--CALCULANDO EL NUEVO CONSECUTIVO DEL MOVIMIENTO DE INVENTARIO '
		PRINT'------------------------------------------------------------------------------------------------------------'

		EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@MOV',@CNSMOV OUTPUT
		SELECT @CNSMOV = @SEDE +'S'+ REPLACE(SPACE(8 - LEN(@CNSMOV))+LTRIM(RTRIM(@CNSMOV)),SPACE(1),0)          
		PRINT 'CNSMOV='+@CNSMOV 
		PRINT'------------------------------------------------------------------------------------------------------------'
		PRINT'--INSERTANDO EL ENCABEZADO DEL MOVIMIENTO DE INVENATARIO'
		PRINT'------------------------------------------------------------------------------------------------------------'
		INSERT INTO IMOV(	CNSMOV,IDBODEGA,IDTIPOMOV,NODOCUMENTO,TIPODOCU,FECHAMOV,CCOSTO,IDSOLICITA,IDTERCERO,IDFUNCIONARIO,IDRECIBE,
							FACTORVENTA,ESTADO,IDBODEGAEXTERNA,CNSTRAN,OBSERVACION,CNSFCOM,SUBIOCOMPRA,NOPRESTACION,IDAREA,CONTABILIZADA,
							NROCOMPROBANTE,PROCEDENCIA,USUARIO,USUARIOCONF,FECHACONF,PARCIAL,IDAREAH,NIVELATENCION,SYS_ComputerName,
							TIENECAMBIO,IDITAR,ESTRANSITO,CNSREP,CNSIDEV,IDDEP,CNSITRA,SECONTABILIZA,F_FACTURA,F_VENCE,MARCACONT,VLR_FLETE,
							CODUNG,CODPRG,ITFC,CNSITFC,IDARTICULODESTINO,CANTIDADDESTINO,GENFACTURA,IDPLAN,FACTURADA,N_FACTURA,
							TIPO_DOC_COMPRA,NOCONSECUTIVO
						 ) 
		SELECT  @CNSMOV AS CNSMOV , @IDBODEGA AS IDBODEGA , @IDTIPOMOV AS IDTIPOMOV,
				''AS NODOCUMENTO,NULL AS TIPODOCU,DBO.FNK_FECHA_SIN_MLS(GETDATE()) AS FECHAMOV,@CCOSTO_IMOV, @USUARIO AS IDSOLICITA ,''AS IDTERECERO,
				''AS IDFUNCIONARIO,NULL AS IDRECIBE, NULL AS FACTORVENTA ,0 AS ESTADO,NULL AS IDBODEGAEXTERNA,NULL AS CNSTRAN,
				'Salida de Materiales E Insumos Vencidos Automatica'AS OBSERVACION,
				NULL AS CNSFCOM , 0 AS SUBIOCOMPRA , NULL AS NOPRESTACION , DBO.FNK_AREADELCCOSTO(@CCOSTO_IMOV) , 0 AS CONTABILIZADA ,NULL AS NROCOMPROBANTE,
				'INV' AS PROCEDENCIA,@USUARIO AS USUARIO,NULL AS USUARIOCONF,NULL AS FECHACONF,0 AS PARCIAL , NULL AS IDAREAH,NULL AS NIVELATENCION,@SYSCOMPUTERNAME AS SYSCOMPUTARNAME,
				0 AS TIENECAMBIO,'' AS IDITAR ,NULL AS ESTRANSITO, NULL AS CNSREP , NULL AS CNSIDEV , NULL AS IDDEP , NULL AS CNSITRA ,
				NULL AS SECONTABILIZA , NULL AS F_FACTURA , NULL AS F_VENCE , NULL AS MARCACONT , NULL AS VLR_FLETE , NULL AS CODUNG ,
				NULL AS CODPRG , NULL AS ITFC , NULL AS CNSITFC,NULL AS IDARTICULODESTINO , NULL AS CANTIDADDESTINO , 0 AS GENFACTURA,
				NULL AS IDPLAN , 0 AS FACTURADA, NULL AS N_FACTURA , 'N' AS [TIPO_DOC_COMPRA],NULL AS NOCONSECUTIVO
				FROM IBOD 
				WHERE IDBODEGA=@IDBODEGA
	
		PRINT'------------------------------------------------------------------------------------'
		PRINT'--INSERTANDO LOS ARTICULO VENCIDOS AL MOVIMIENTO DE INVENTARIO '
		PRINT'------------------------------------------------------------------------------------'
		INSERT INTO IMOVH (
						  CNSMOV,IDARTICULO, EXISTENCIA,CANTIDAD,CANTPEDIDA,PCOSTO,NOLOTE,NOLOTEPEDIDO,FECHAVENCE,ESTADO,
						  IDARTICULOTF,CANTIDADTF,PCOSTOANTES,CNSTRAN,ITEM,PVENTA,USUARIO,USUARIOCONF,FECHACONF,PRIEXI,
						  FECHAREPOSI,IDARTICULOORI,CANTIDADORI,TIENECAMBIO,DETALLE,CANT_EN_ACTIVOS,ENCXP,PIVA,VLRIVA,
						  PDTO,VLRDTO,CNSHTX,COTIZADO,IDIMPUESTO,IDCLASE,ITFC,CNSITFC,CUENTA_FIMPDV,IDITAR,CODCUM,CAMBIADO,
						  PCOSTOANTESMOD,USUARIOCAMBIO,IDFABRICANTE,CUENTADB,CUENTACR
						 )
		SELECT @CNSMOV AS CNSMOV ,IART.IDARTICULO,
			   EXISLOTE,EXISLOTE AS CANTIDAD,EXISLOTE AS CANTPEDIDA,IEXI.PCOSTO,
			   NOLOTE,NULL AS NOLOTEPEDIDO,FECHAVENCE,0 AS ESTADO,NULL AS IDARTICULOTF,NULL AS CANTIDADTF,NULL AS PCOSTOANTES,
			   NULL AS CNSTRAN,ROW_NUMBER() OVER (ORDER BY IEXI.IDARTICULO,IEXI.NOLOTE) AS  ITEM ,IEXI.PCOSTO AS PVENTA,
			   @USUARIO AS USUARIO ,NULL AS USUARIOCONF,NULL AS FECHACONF,0 AS PRIEXI,NULL AS FECHAREPOSI,''AS IDARTICULOORI,
			   0 AS CANTIDADORI,0 AS TIENECAMBIO,NULL AS DETALLE ,NULL AS CANT_EN_ACTIVOS,NULL AS ENCXP,NULL AS PIVA , 
			   NULL AS VLRIVA , NULL AS PDTO,NULL AS VLRDTO ,'' AS CNSHTX ,NULL AS COTIZADO,NULL AS IDIMPUESTO,
			   NULL AS IDCLASE,NULL AS ITFC,NULL AS CNSITFC , NULL AS CUENTA_FIMPDV , '' AS IDITAR ,IART.CODCUM ,
			   NULL AS CAMBIADO,IEXI.PCOSTO AS PCOSTOANTESMOD,NULL AS USUARIOCAMBIO,IART.IDFABRICANTE,NULL AS CUENTADB,
			   NULL AS CUENTACR
		FROM IEXI INNER JOIN IART ON IART.IDARTICULO = IEXI.IDARTICULO
		WHERE DBO.FNK_SEMAFOROIEXI(IEXI.IDBODEGA,IEXI.IDARTICULO,IEXI.NOLOTE) = 1  
		AND IEXI.IDBODEGA = @IDBODEGA   AND EXISLOTE > 0
		AND IEXI.IDARTICULO=CASE WHEN COALESCE(@IDARTICULO,'')<>'' THEN @IDARTICULO ELSE IEXI.IDARTICULO END

		IF NOT EXISTS (SELECT 1 FROM IMOVH WITH (NOLOCK) WHERE CNSMOV = @CNSMOV)
		BEGIN
			RAISERROR('No se insertaron l�neas en el movimiento de salida de vencidos.', 16, 1)
		END

		PRINT'--REALIZANDO ISERT EN  ISAL' 
		INSERT INTO ISAL(CNSMOV,NOLOTE,IDARTICULO,CANTIDAD,FECHA,NOLOTEPEDIDO,FECHAVENCE,PCOSTO,IDARTICULO_IMOVH)
		SELECT @CNSMOV,IEXI.NOLOTE,IEXI.IDARTICULO,IEXI.EXISLOTE,DBO.FNK_FECHA_SIN_MLS(GETDATE()) FECHA ,''AS NOLOTEPEDIDO,IEXI.FECHAVENCE,IEXI.PCOSTO,
			   IART.IDARTICULO
		FROM IEXI  INNER JOIN IART  ON IEXI.IDARTICULO=IART.IDARTICULO
		WHERE DBO.FNK_SEMAFOROIEXI(IEXI.IDBODEGA,IEXI.IDARTICULO,IEXI.NOLOTE) = 1  
		AND IEXI.IDBODEGA = @IDBODEGA   AND EXISLOTE > 0
		AND IEXI.IDARTICULO=CASE WHEN COALESCE(@IDARTICULO,'')<>'' THEN @IDARTICULO ELSE IEXI.IDARTICULO END

		PRINT'--REALIZANDO UPDATE A IEXI'
		UPDATE IEXI SET EXISLOTE=EXISLOTE-ISAL.CANTIDAD 
		FROM IEXI INNER JOIN ( SELECT IDARTICULO,NOLOTE,SUM(CANTIDAD)CANTIDAD 
							  FROM ISAL                                      
							  WHERE CNSMOV= @CNSMOV          
							  GROUP BY IDARTICULO,NOLOTE ) ISAL ON IEXI.IDARTICULO=ISAL.IDARTICULO 
																AND IEXI.NOLOTE=ISAL.NOLOTE        
		WHERE IEXI.IDBODEGA = @IDBODEGA

		PRINT 'CONFIRMO LA SALIDA DE UNA VEZ........'
		EXEC SPK_CONFIRMARSALIDAS @IDBODEGA,@CNSMOV,@USUARIO,@COMPANIA,@SEDE

		COMMIT TRANSACTION
	END TRY
	BEGIN CATCH
		IF @@TRANCOUNT > 0
			ROLLBACK TRANSACTION

		SET @ERRMSG = LEFT(ERROR_MESSAGE(), 2000)
		RAISERROR(@ERRMSG, 16, 1)
		RETURN
	END CATCH

END
