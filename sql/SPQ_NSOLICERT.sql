CREATE OR ALTER PROCEDURE DBO.SPQ_NSOLICERT
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @PARAMETROS	NVARCHAR(MAX),	@MODELO		VARCHAR(100),   @METODO		VARCHAR(100)
DECLARE  @USUARIO		VARCHAR(20),    @DIRIGIDOA VARCHAR(15),		@IDEMPLEADO VARCHAR(20)
DECLARE	 @SUELDO		BIT,			@TIPOCERT	VARCHAR(20),    @PROCESO	VARCHAR(20)
DECLARE	 @ESTADO		VARCHAR(15),    @CNSOLICERT INT,			@CARGO		BIT,		@TIPCONTRATO BIT,	@FECHINGRESO BIT
DECLARE  @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT  @TIPOCERT = TIPOCERT, @IDEMPLEADO = IDEMPLEADO, @ESTADO = ESTADO, @PROCESO = PROCESO,
					@DIRIGIDOA = DIRIGIDOA, @SUELDO = SUELDO, @CNSOLICERT = CNSOLICERT,@CARGO = CARGO,		
					@TIPCONTRATO = TIPCONTRATO,	@FECHINGRESO = FECHINGRESO
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				TIPOCERT	VARCHAR(20)	 '$.TIPOCERT',	IDEMPLEADO  VARCHAR(20)	'$.IDEMPLEADO',	ESTADO	VARCHAR(15)	'$.ESTADO',
				PROCESO	VARCHAR(20)	'$.PROCESO', DIRIGIDOA VARCHAR(15) '$.DIRIGIDOA', SUELDO BIT '$.SUELDO', CNSOLICERT INT '$.CNSOLICERT',
				CARGO BIT '$.CARGO', TIPCONTRATO BIT '$.TIPCONTRATO', FECHINGRESO BIT '$.FECHINGRESO'
			)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES(ERROR) 
					SELECT 'YA TIENES UN CERTIFICADO POR GENERAR'
					WHERE EXISTS (SELECT 1 FROM NSOLICERT WHERE IDNEMP = @IDEMPLEADO AND ESTADO = @ESTADO)

					IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
					BEGIN
						INSERT INTO NSOLICERT (TIPOCERT ,IDNEMP, ESTADO, DIRIGIDOA, SUELDO, CARGO, TIPCONTRATO, FECHINGRESO, FECHASOLI)   
						SELECT @TIPOCERT, @IDEMPLEADO, @ESTADO, @DIRIGIDOA, @SUELDO, @CARGO, @TIPCONTRATO, @FECHINGRESO, GETDATE()
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
				END CATCH

				IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
				BEGIN
					SELECT 'KO' OK
					SELECT ERROR FROM @TBLERRORES
					RETURN
				END

				SELECT 'OK' OK 
				RETURN
			END
			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					UPDATE NSOLICERT SET TIPOCERT = @TIPOCERT, DIRIGIDOA = @DIRIGIDOA, SUELDO = @SUELDO,
					CARGO = @CARGO, TIPCONTRATO = @TIPCONTRATO, FECHINGRESO = @FECHINGRESO
					WHERE CNSOLICERT = @CNSOLICERT
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
				END CATCH

				IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
				BEGIN
					SELECT 'KO' OK
					SELECT ERROR FROM @TBLERRORES
					RETURN
				END

				SELECT 'OK' OK 
				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
	IF @METODO = 'ELIMINAR'
			BEGIN

					SELECT @CNSOLICERT = JSON_VALUE(@PARAMETROS, '$.CNSOLICERT')
			BEGIN TRY
					DELETE FROM NSOLICERT WHERE CNSOLICERT = @CNSOLICERT
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
				END CATCH

				IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
				BEGIN
					SELECT 'KO' OK
					SELECT ERROR FROM @TBLERRORES
					RETURN
				END
				SELECT 'OK' OK
				END
	IF @METODO = 'GET_INFO_CERTIFICATE'
	BEGIN
		SELECT 'OK' OK

		SELECT	NSOLICERT.CNSOLICERT,CONCAT(NEMP.PRIMERNOMBRE,' ',NEMP.SEGUNDONOMBRE) AS NOMBRES,
				CONCAT(NEMP.PRIMERAPELLIDO,' ',NEMP.SEGUNDOAPELLIDO) AS APELLIDOS,
				NEMP.ESTADO,NEMP.DOCIDEMPLEADO,NEMP.NUMDOC AS IDNEMP,NEMP.FECHAINGRESO AS FECHAING,
				NEMP.BASICO,NEMP.FECHARETIRO AS FECHASAL,
				NEMP.TIPOCONTRATO AS TCONTRATO,NEMP.EMAIL,
				USUSU.USUARIO AS USUARIOCERT, NCARNG.CODCARGO,NEMP.NIVEL,NSOLICERT.SUELDO AS SUELDOSOLI,
				NCARNG.DESCRIPCION AS DESCARGO FROM NSOLICERT 
				INNER JOIN NEMP ON NSOLICERT.IDNEMP = NEMP.NUMDOC
				INNER JOIN USUSU ON USUSU.IDEMPLEADO = NEMP.NUMDOC
				INNER JOIN NCARNG ON NEMP.CODCARGO = NCARNG.CODCARGO AND NEMP.NIVEL = NCARNG.NIVEL AND NEMP.GRADO = NCARNG.GRADO
				where NSOLICERT.CNSOLICERT = JSON_VALUE(@PARAMETROS, '$.CNSOLICERT') 
		RETURN
	END
END
