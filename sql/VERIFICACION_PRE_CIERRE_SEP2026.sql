/*
  Pre-cierre septiembre 2026 — CEM. Solo SELECT.
  Usa FNK_REVISION_ANTES_CIERRE_PERIODO + foco CxP compras (F_FACTURAREF sep).
*/
SET NOCOUNT ON;

DECLARE @ANO varchar(4) = N'2026';
DECLARE @MES smallint = 9;

/* Periodo contable */
SELECT ANO, MES, CERRADO, CERRADO_CARTERA, CERRADO_CXP, CERRADO_INV
FROM dbo.PRI
WHERE ANO = @ANO AND MES = @MES;

SELECT DBO.FNK_VALORVARIABLE(N'IDCON_FCONTABLE_CXP') AS CRITERIO_FECHA_CXP;

/* Resumen revisión estándar (botón pre-cierre) */
SELECT MODULO, COUNT(*) AS CANTIDAD
FROM dbo.FNK_REVISION_ANTES_CIERRE_PERIODO(@ANO, @MES)
GROUP BY MODULO
ORDER BY CANTIDAD DESC;

SELECT TOP 30 MODULO, REFERENCIA, ERROR
FROM dbo.FNK_REVISION_ANTES_CIERRE_PERIODO(@ANO, @MES)
ORDER BY MODULO, REFERENCIA;

/* CxP sep — compras sin contabilizar (documento) */
SELECT
  COUNT(*) AS CXP_COMPRAS_SIN_CONTAB,
  SUM(CASE WHEN ABS(P.VLR_NETO - X.SN) > 0.01 THEN 1 ELSE 0 END) AS CAB_DIF_DET,
  SUM(CASE WHEN ABS(P.VLR_IVA - X.SI) > 0.01 THEN 1 ELSE 0 END) AS IVA_CAB_DIF_DET,
  SUM(CASE WHEN X.LIN_IVA_VACIO > 0 THEN 1 ELSE 0 END) AS CON_IVA_SIN_CUENTA_IVA,
  SUM(CASE WHEN X.LIN_240806 > 0 THEN 1 ELSE 0 END) AS CON_IVA_24080601,
  SUM(CASE WHEN X.LIN_EXCL_IVA > 0 THEN 1 ELSE 0 END) AS EXCLUIDOS_CON_IVA,
  SUM(CASE WHEN X.LIN_NO_DEF > 0 THEN 1 ELSE 0 END) AS CUENTA_NO_DEF,
  SUM(CASE WHEN X.LIN_FORMULA > 0 THEN 1 ELSE 0 END) AS LINEAS_FORMULA_MAL,
  CONVERT(decimal(18, 2), SUM(P.VLR_NETO)) AS SUM_NETO_PEND
FROM dbo.FCXP P
CROSS APPLY (
  SELECT SUM(D.VLR_NETO) SN, SUM(D.VLR_IVA) SI,
    SUM(CASE WHEN COALESCE(D.VLR_IVA, 0) > 0 AND COALESCE(D.CUENTA_IVA, N'') = N'' THEN 1 ELSE 0 END) LIN_IVA_VACIO,
    SUM(CASE WHEN COALESCE(D.VLR_IVA, 0) > 0 AND D.CUENTA_IVA = N'24080601' THEN 1 ELSE 0 END) LIN_240806,
    SUM(CASE WHEN COALESCE(D.VLR_IVA, 0) > 0 AND D.CUENTA_SER IN (N'14150502', N'14200502') THEN 1 ELSE 0 END) LIN_EXCL_IVA,
    SUM(CASE WHEN D.CUENTA_SER LIKE N'%NO DEF%' OR D.CUENTA_SER LIKE N'%KMCOM%' THEN 1 ELSE 0 END) LIN_NO_DEF,
    SUM(CASE WHEN ABS(D.VLR_NETO - (D.CANTIDAD * D.VALOR + COALESCE(D.VLR_IVA, 0) - ISNULL(D.VLR_DESCUENTO, 0))) > 1 THEN 1 ELSE 0 END) LIN_FORMULA
  FROM dbo.FCXPD D WHERE D.CNSFCXP = P.CNSFCXP
) X
WHERE P.PROCEDENCIA = N'Compras'
  AND P.ESTADO <> N'A'
  AND YEAR(P.F_FACTURAREF) = 2026 AND MONTH(P.F_FACTURAREF) = 9
  AND COALESCE(P.CONTABILIZADA, 0) = 0
  AND COALESCE(P.NROCOMPROBANTE, N'') = N'';

/* Detalle: CxP compras sep con algún hallazgo contable */
SELECT TOP 40
  P.CNSFCXP, P.NOREFERENCIA,
  CONVERT(decimal(18, 2), P.VLR_NETO) AS NETO,
  X.LIN_IVA_VACIO, X.LIN_240806, X.LIN_EXCL_IVA, X.LIN_NO_DEF, X.LIN_FORMULA,
  CASE WHEN ABS(P.VLR_NETO - X.SN) > 0.01 THEN 1 ELSE 0 END AS CAB_DET
FROM dbo.FCXP P
CROSS APPLY (
  SELECT SUM(D.VLR_NETO) SN,
    SUM(CASE WHEN COALESCE(D.VLR_IVA, 0) > 0 AND COALESCE(D.CUENTA_IVA, N'') = N'' THEN 1 ELSE 0 END) LIN_IVA_VACIO,
    SUM(CASE WHEN COALESCE(D.VLR_IVA, 0) > 0 AND D.CUENTA_IVA = N'24080601' THEN 1 ELSE 0 END) LIN_240806,
    SUM(CASE WHEN COALESCE(D.VLR_IVA, 0) > 0 AND D.CUENTA_SER IN (N'14150502', N'14200502') THEN 1 ELSE 0 END) LIN_EXCL_IVA,
    SUM(CASE WHEN D.CUENTA_SER LIKE N'%NO DEF%' THEN 1 ELSE 0 END) LIN_NO_DEF,
    SUM(CASE WHEN ABS(D.VLR_NETO - (D.CANTIDAD * D.VALOR + COALESCE(D.VLR_IVA, 0) - ISNULL(D.VLR_DESCUENTO, 0))) > 1 THEN 1 ELSE 0 END) LIN_FORMULA
  FROM dbo.FCXPD D WHERE D.CNSFCXP = P.CNSFCXP
) X
WHERE P.PROCEDENCIA = N'Compras'
  AND P.ESTADO <> N'A'
  AND YEAR(P.F_FACTURAREF) = 2026 AND MONTH(P.F_FACTURAREF) = 9
  AND COALESCE(P.CONTABILIZADA, 0) = 0
  AND (
    ABS(P.VLR_NETO - X.SN) > 0.01
    OR X.LIN_IVA_VACIO > 0 OR X.LIN_240806 > 0 OR X.LIN_EXCL_IVA > 0
    OR X.LIN_NO_DEF > 0 OR X.LIN_FORMULA > 0
  )
ORDER BY P.NOREFERENCIA;

/* Inventario sep confirmado sin contabilizar (muestra) */
SELECT COUNT(*) AS IMOV_CONF_SIN_CONTAB_SEP
FROM dbo.IMOV M
WHERE YEAR(M.FECHACONF) = 2026 AND MONTH(M.FECHACONF) = 9
  AND COALESCE(M.ESTADO, 0) = 1
  AND COALESCE(M.CONTABILIZADA, 0) = 0
  AND COALESCE(M.SECONTABILIZA, 0) = 1;
