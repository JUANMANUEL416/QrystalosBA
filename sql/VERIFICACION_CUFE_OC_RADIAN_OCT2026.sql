/* Normaliza número factura para cruce (FE5150 vs FE5150., FE-5150) */
;WITH BASE AS (
  SELECT
    D.CNSFCXP,
    D.NOREFERENCIA,
    P.CNSFCOM,
    T.NIT,
    LEFT(T.RAZONSOCIAL, 28) AS PROVEEDOR,
    F.N_FACTURA AS FCOM_N_FACTURA,
    F.F_FACTURA AS FCOM_F_FACTURA,
    M.CNSMOV,
    M.ESTADO AS IMOV_ESTADO,
    M.N_FACTURA AS IMOV_N_FACTURA,
    LTRIM(RTRIM(COALESCE(M.CUFE, N''))) AS IMOV_CUFE,
    R.CNSRADIAN,
    R.NODOCUMENTO AS RAD_NODOC,
    LTRIM(RTRIM(COALESCE(R.UUID, N''))) AS RAD_UUID
  FROM @DOC D
  INNER JOIN dbo.FCXP P ON P.CNSFCXP = D.CNSFCXP
  LEFT JOIN dbo.TER T ON T.IDTERCERO = P.IDTERCERO
  LEFT JOIN dbo.FCOM F ON F.CNSFCOM = P.CNSFCOM
  LEFT JOIN dbo.IMOV M ON M.CNSFCOM = P.CNSFCOM
  OUTER APPLY (
    SELECT TOP 1
      FR.CNSRADIAN,
      FR.NODOCUMENTO,
      FR.UUID,
      FR.NIT
    FROM dbo.FRADIAN FR
    WHERE FR.NIT = T.NIT
      AND (
        FR.NODOCUMENTO = D.NOREFERENCIA
        OR FR.NODOCUMENTO = D.NOREFERENCIA + N'.'
        OR REPLACE(FR.NODOCUMENTO, N'FE-', N'FE') = REPLACE(D.NOREFERENCIA, N'FE-', N'FE')
        OR FR.NODOCUMENTO = REPLACE(D.NOREFERENCIA, N'FE', N'FE-')
      )
    ORDER BY FR.FECHA DESC
  ) R
  WHERE P.ESTADO <> N'A'
)
SELECT
  CNSFCXP,
  NOREFERENCIA,
  CNSFCOM,
  NIT,
  PROVEEDOR,
  FCOM_N_FACTURA,
  CASE
    WHEN LTRIM(RTRIM(COALESCE(FCOM_N_FACTURA, N''))) IN (N'', NOREFERENCIA, NOREFERENCIA + N'.')
      OR REPLACE(FCOM_N_FACTURA, N'.', N'') = NOREFERENCIA
    THEN N'OK'
    ELSE N'DIF'
  END AS OC_FACT_VS_CXP,
  CNSMOV,
  IMOV_ESTADO,
  IMOV_N_FACTURA,
  CASE WHEN IMOV_CUFE = N'' THEN N'VACIO' ELSE N'OK' END AS IMOV_CUFE_EST,
  LEFT(IMOV_CUFE, 20) AS IMOV_CUFE_INI,
  CNSRADIAN,
  RAD_NODOC,
  LEFT(RAD_UUID, 20) AS RAD_UUID_INI,
  CASE
    WHEN RAD_UUID = N'' THEN N'SIN_RADIAN'
    WHEN IMOV_CUFE = N'' THEN N'FALTA_EN_ENTRADA'
    WHEN IMOV_CUFE = RAD_UUID THEN N'CUFE_OK'
    ELSE N'CUFE_DISTINTO'
  END AS SEMAFORO_CUFE,
  CASE
    WHEN FCOM_N_FACTURA IS NULL THEN N'Sin FCOM'
    WHEN RAD_UUID = N'' THEN N'Sin fila FRADIAN (NIT+doc)'
    WHEN IMOV_CUFE = N'' THEN N'Sincronizar: inv.ges SINCRONIZAR_CUFE_RADIAN o ACTUALIZAR_CUFE'
    WHEN IMOV_CUFE <> RAD_UUID THEN N'Revisar entrada duplicada o factura distinta en IMOV.N_FACTURA'
    WHEN LTRIM(RTRIM(COALESCE(FCOM_N_FACTURA, N''))) NOT IN (NOREFERENCIA, NOREFERENCIA + N'.')
      AND REPLACE(COALESCE(FCOM_N_FACTURA, N''), N'.', N'') <> NOREFERENCIA
    THEN N'Corregir FCOM.N_FACTURA (OC distinta a CxP/Radian)'
    ELSE N'—'
  END AS ACCION_SUGERIDA
FROM BASE
ORDER BY NOREFERENCIA, CNSMOV;

/* Resumen por factura (peor estado por CxP) */
;WITH L AS (
  SELECT
    D.NOREFERENCIA,
    MAX(CASE
      WHEN R.UUID IS NULL OR LTRIM(RTRIM(COALESCE(R.UUID, N''))) = N'' THEN 4
      WHEN LTRIM(RTRIM(COALESCE(M.CUFE, N''))) = N'' THEN 3
      WHEN LTRIM(RTRIM(COALESCE(M.CUFE, N''))) <> LTRIM(RTRIM(COALESCE(R.UUID, N''))) THEN 2
      ELSE 1
    END) AS NIVEL
  FROM @DOC D
  INNER JOIN dbo.FCXP P ON P.CNSFCXP = D.CNSFCXP
  LEFT JOIN dbo.TER T ON T.IDTERCERO = P.IDTERCERO
  LEFT JOIN dbo.IMOV M ON M.CNSFCOM = P.CNSFCOM
  OUTER APPLY (
    SELECT TOP 1 FR.UUID
    FROM dbo.FRADIAN FR
    WHERE FR.NIT = T.NIT
      AND (
        FR.NODOCUMENTO = D.NOREFERENCIA
        OR FR.NODOCUMENTO = D.NOREFERENCIA + N'.'
        OR REPLACE(FR.NODOCUMENTO, N'FE-', N'FE') = REPLACE(D.NOREFERENCIA, N'FE-', N'FE')
      )
    ORDER BY FR.FECHA DESC
  ) R
  WHERE P.ESTADO <> N'A'
  GROUP BY D.NOREFERENCIA
)
SELECT
  NOREFERENCIA,
  CASE NIVEL
    WHEN 1 THEN N'CUFE_OK'
    WHEN 2 THEN N'CUFE_DISTINTO'
    WHEN 3 THEN N'FALTA_EN_ENTRADA'
    ELSE N'SIN_RADIAN'
  END AS RESUMEN_CUFE
FROM L
ORDER BY NOREFERENCIA;

