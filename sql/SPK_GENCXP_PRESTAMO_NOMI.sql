CREATE OR ALTER PROCEDURE DBO.SPK_GENCXP_PRESTAMO_NOMI @CNSPRESTAMO VARCHAR(20), @COMPANIA VARCHAR(2), @SEDE VARCHAR(5), @USUARIO VARCHAR(12), @SYS_COMPUTERNAME VARCHAR(
		254)
	WITH ENCRYPTION
AS
DECLARE @CNSFCXP VARCHAR(20)
DECLARE @ITEM INT
DECLARE @NROCOMPROBANTE VARCHAR(20)
DECLARE @IDMODELOCONT VARCHAR(2)
DECLARE @CODNOMINA VARCHAR(20)
DECLARE @CUENTACR VARCHAR(20)
DECLARE @RUBRO VARCHAR(20)

BEGIN
	SET @IDMODELOCONT = DBO.FNK_VALORVARIABLE('IDMODELOCONTABLE')
	SET @CNSFCXP = SPACE(20)

	EXEC SPK_GENCONSECUTIVO @COMPANIA, @SEDE, '@FCXPNM', @CNSFCXP OUTPUT

	SELECT @CNSFCXP = @SEDE + 'NM' + REPLACE(SPACE(6 - LEN(@CNSFCXP)) + LTRIM(RTRIM(@CNSFCXP)), SPACE(1), 0)

	PRINT 'CNS CXP =' + @CNSFCXP
	PRINT 'FCXP.'

	INSERT INTO FCXP (
		CNSFCXP, FECHA, CNSFCOM, IDTERCERO, NOREFERENCIA, F_FACTURAREF, F_VENCE, VALOR, ESTADO, F_CANCELADO, USUARIO, PROCEDENCIA, OBSERVACION, COMPANIA, 
		SYS_COMPUTERNAME, USUARIOMOD, FECHAMOD, NUMCUOTA, MARCACONT, CONTABILIZADA, NROCOMPROBANTE, SALDO, IDCLASEIMP, VLR_DESCUENTO, VLR_IVA, VLR_NETO, 
		VLR_IMPUESTOS, VLR_NOTASDEBITO, VLR_COMISION, CUEDEBITO, CUECREDITO, CNSFCXPPM
		)
	SELECT @CNSFCXP, DBO.FNK_FECHA_SIN_MLS(GETDATE()), PRS.NUMDOCUMENTO, NEMP.TERCEROID, PRS.NUMDOCUMENTO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), DBO.
		FNK_FECHA_SIN_MLS(GETDATE()), PRS.VLRPRESTAMO, 'N', NULL, @USUARIO, 'Nomina', NCON.DESCRIPCION + ', Prestamo No. ' + PRS.NUMDOCUMENTO + ' ' + PRS.
		OBSERVACIONES, @COMPANIA, @SYS_COMPUTERNAME, NULL, NULL, NULL, 0, 0, NULL, PRS.VLRPRESTAMO, NULL, 0, 0, PRS.VLRPRESTAMO, 0, 0, 0, NULL, DBO.FNK_NC_CUENTA_KMCOM(
			@IDMODELOCONT, 'NOMINA', 'CR', PRS.CODCONCEPTO, PRS.CCOSTO, 'S', '', 0), NULL
	FROM PRS
	INNER JOIN TER ON PRS.IDPRESTADOR = TER.IDTERCERO
	INNER JOIN NCON ON PRS.CODCONCEPTO = NCON.CODCONCEPTO
	INNER JOIN NEMP ON NEMP.NUMDOC = PRS.IDDEUDOR
	WHERE PRS.NUMDOCUMENTO = @CNSPRESTAMO

	PRINT 'FCXPD.'

	INSERT INTO FCXPD (
		CNSFCXP, ITEM, IDSERVICIO, CANTIDAD, VALOR, ESTADO, N_PRESUP, ITEM_PRESUP, IDCLASEIMP, VLR_DESCUENTO, VLR_IVA, VLR_NETO, NOLOTE, PREFIJO, CCOSTO, IDAREAH, 
		IDAREA, NROCOMPROBANTE, PROCEDENCIA, CUENTA_SER, RUBRO
		)
	SELECT @CNSFCXP CNSFCXP, 1 ITEM, PRS.CODCONCEPTO IDSERVICIO, 1 CANTIDAD, ROUND(PRS.VLRPRESTAMO, 0) VALOR, 'P' ESTADO, PRS.NUMDOCUMENTO N_PRESUP, 1 ITEM_PRESUP, NULL 
		IDCLASEIMP, 0 VLR_DESCUENTO, 0 VLR_IVA, ROUND(PRS.VLRPRESTAMO, 0) VLR_NETO, NEMP.TERCEROID NOLOTE, PRS.CODCONCEPTO PREFIJO, PRS.CCOSTO CCOSTO, NULL IDAREAH, 
		PRS.IDAREA IDAREA, NULL NROCOMPROBANTE, 'Nomina', DBO.FNK_NC_CUENTA_KMCOM(@IDMODELOCONT, 'NOMINA', 'DB', PRS.CODCONCEPTO, PRS.CCOSTO, 'S', '', 0), ''
	FROM PRS
	INNER JOIN TER ON PRS.IDPRESTADOR = TER.IDTERCERO
	INNER JOIN NCON ON PRS.CODCONCEPTO = NCON.CODCONCEPTO
	INNER JOIN NEMP ON NEMP.NUMDOC = PRS.IDDEUDOR
	WHERE PRS.NUMDOCUMENTO = @CNSPRESTAMO

	EXEC SPK_CALCULOVALORESCXP @CNSFCXP

	UPDATE PRS
	SET CODCAJA = 'FCXP', CNSFACJ = @CNSFCXP, ENCAJA = 1
	WHERE NUMDOCUMENTO = @CNSPRESTAMO
END
