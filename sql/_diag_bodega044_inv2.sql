SET NOCOUNT ON;
DECLARE @d NVARCHAR(MAX) = OBJECT_DEFINITION(OBJECT_ID(N'dbo.SPK_CONTAB_MASIVA'));
SELECT
  LEN(@d) AS LEN_MASIVA,
  CASE WHEN @d LIKE N'%FECHACONF%' THEN 1 ELSE 0 END AS TIENE_FECHACONF,
  CASE WHEN @d LIKE N'%Los movimientos se marcaron%' THEN 1 ELSE 0 END AS EN_MASIVA;
SET @d = OBJECT_DEFINITION(OBJECT_ID(N'dbo.SPQ_CONTABILIDAD_3'));
SELECT
  LEN(@d) AS LEN_SPQ,
  CASE WHEN @d LIKE N'%Los movimientos se marcaron%' THEN 1 ELSE 0 END AS TIENE_MSG_INV,
  CASE WHEN @d LIKE N'%NO filtrar por FECHACONF%' THEN 1 ELSE 0 END AS TIENE_COMENT_FECHACONF;

-- Movimientos marcados sin contab: SECONTABILIZA vs ITMO
SELECT M.CNSMOV, M.IDTIPOMOV, M.SECONTABILIZA AS M_SECONT,
  ITMO.SECONTABILIZA AS T_SECONT, ITMO.TIPO,
  CASE WHEN COALESCE(M.FECHACONF,'19000101')='19000101' OR M.FECHACONF IS NULL THEN 1 ELSE 0 END AS FECHACONF_NULL
FROM IMOV M JOIN ITMO ON ITMO.IDTIPOMOV=M.IDTIPOMOV
WHERE M.IDBODEGA=N'044' AND M.MARCACONT=1 AND COALESCE(M.CONTABILIZADA,0)=0 AND M.ESTADO=1
ORDER BY M.IDTIPOMOV, M.CNSMOV;
