CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NCONDF
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @DATO					NVARCHAR(MAX)
DECLARE  @PARAMETROS			NVARCHAR(MAX),	@MODELO			VARCHAR(100),   @METODO		VARCHAR(100),	@USUARIO	VARCHAR(20)
DECLARE	 @PROCESO				VARCHAR(20)
DECLARE	 @CODCONCEPTO			VARCHAR(20),	@ITEM				DECIMAL(14,0)
DECLARE	 @PRIORIDAD				SMALLINT,		@CODCONCEPTO_OPE	VARCHAR(20)
DECLARE	 @FACTOR				DECIMAL(14,6),	@OPERACION			VARCHAR(2)
DECLARE	 @SOLICITA_CNSPAGO		VARCHAR(2),		@CNSPAGO			VARCHAR(20)
DECLARE	 @REQUIERELIQ			SMALLINT,		@VALHORASLAB		SMALLINT	
DECLARE	 @HORAS					INT,			@DIAS				INT
DECLARE	 @PRIORIDADEDITE		SMALLINT

DECLARE  @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

	IF @METODO = 'GUARDAR'
		BEGIN
			BEGIN TRY
				SELECT  @CODCONCEPTO = CODCONCEPTO, @ITEM = ITEM,@PRIORIDAD = PRIORIDAD,
						@CODCONCEPTO_OPE = CODCONCEPTO_OPE, @FACTOR = FACTOR, @OPERACION = OPERACION,
						@SOLICITA_CNSPAGO = SOLICITA_CNSPAGO, @REQUIERELIQ = REQUIERELIQ, @VALHORASLAB=VALHORASLAB,
						@HORAS = HORAS, @DIAS = DIAS,
						@PROCESO = PROCESO
				FROM	OPENJSON (@PARAMETROS) 
				WITH	(
					CODCONCEPTO		VARCHAR(20)			'$.CODCONCEPTO',
					ITEM			DECIMAL(14,0)		'$.ITEM',
					PRIORIDAD		SMALLINT			'$.PRIORIDAD',
					CODCONCEPTO_OPE	VARCHAR(20)			'$.CODCONCEPTO_OPE',
					FACTOR			DECIMAL(15,6)		'$.FACTOR',
					OPERACION		VARCHAR(2)			'$.OPERACION',
					SOLICITA_CNSPAGO	BIT				'$.SOLICITA_CNSPAGO',
					REQUIERELIQ		BIT					'$.REQUIERELIQ',
					VALHORASLAB		BIT					'$.VALHORASLAB',
					HORAS			INT					'$.HORAS',
					DIAS			INT					'$.DIAS',
					PROCESO			VARCHAR(20)			'$.PROCESO'
				)
				IF UPPER(@PROCESO) = 'INSERTAR'
				BEGIN
					BEGIN TRY
							INSERT INTO @TBLERRORES(ERROR) 
							SELECT CONCAT('LA PRIORIDAD ',@PRIORIDAD, ' YA SE ENCUENTRA REGISTRADO INGRESE UNA PRIORIDAD DIFERENTE')
							WHERE EXISTS (SELECT 1 FROM NCONDF WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM AND PRIORIDAD = @PRIORIDAD)

							IF(SELECT COUNT(*) FROM @TBLERRORES) <= 0
								BEGIN
									INSERT INTO NCONDF (CODCONCEPTO ,ITEM ,PRIORIDAD ,CODCONCEPTO_OPE ,FACTOR ,
									OPERACION ,SOLICITA_CNSPAGO ,CNSPAGO ,REQUIERELIQ ,VALHORASLAB ,HORAS , DIAS )
									SELECT @CODCONCEPTO, @ITEM, @PRIORIDAD, @CODCONCEPTO_OPE, @FACTOR,
									@OPERACION,
									CASE WHEN @SOLICITA_CNSPAGO = 1 THEN 'Si' 
									ELSE 'No' END,'',@REQUIERELIQ,@VALHORASLAB,@HORAS, @DIAS 
								END
					END TRY
					BEGIN CATCH
						INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
					END CATCH

					IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
					BEGIN
						SELECT 'KO' OK
						SELECT ERROR FROM @TBLERRORES
						RETURN
					END

					SELECT 'OK' OK 
					RETURN
				END

				IF UPPER(@PROCESO) = 'EDITAR'
					BEGIN
						BEGIN TRY
						SELECT @DATO = DATO       
							  FROM   OPENJSON (@PARAMETROS)
							  WITH (DATO NVARCHAR(MAX) AS JSON)   
							  
							  SELECT @PRIORIDADEDITE = PRIORIDADEDITE
							  FROM   OPENJSON (@DATO)
							  WITH   (   
							  PRIORIDADEDITE	SMALLINT	 '$.PRIORIDADEDITE'
							  )

							  --INSERT INTO @TBLERRORES(ERROR) 
							  --SELECT CONCAT('EL CONCEPTO ASOCIADO ',@CODCONCEPTOA, ' YA SE ENCUENTRA REGISTRADO')
							 -- WHERE EXISTS (SELECT 1 FROM NCONDA WHERE  CODCONCEPTO = @CODCONCEPTO AND CODCONCEPTOA = @CODCONCEPTOAEDITE)

								--IF(SELECT COUNT(*) FROM @TBLERRORES) <= 0
								BEGIN
									UPDATE NCONDF SET PRIORIDAD = @PRIORIDAD, 
									CODCONCEPTO_OPE = @CODCONCEPTO_OPE, FACTOR = @FACTOR, 
									OPERACION = @OPERACION, 
									SOLICITA_CNSPAGO = CASE 
									WHEN @SOLICITA_CNSPAGO = 1 THEN 'Si' 
									ELSE 'No' END, 
									REQUIERELIQ = @REQUIERELIQ,
									VALHORASLAB = @VALHORASLAB, 
									HORAS = @HORAS ,
									DIAS = @DIAS WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM 
									AND PRIORIDAD = @PRIORIDADEDITE
								END
						END TRY

						BEGIN CATCH
							INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
						END CATCH

						IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
						BEGIN
							SELECT 'KO' OK
							SELECT ERROR FROM @TBLERRORES
							RETURN
						END

						SELECT 'OK' OK 
						RETURN
					END
		END TRY

			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
			END CATCH

			IF(SELECT COUNT(*) FROM @TBLERRORES) >0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END

			SELECT 'OK' OK
		END

		IF @METODO = 'ELIMINAR'
			BEGIN
					SELECT  @CODCONCEPTO = CODCONCEPTO, @ITEM = ITEM, @PRIORIDAD = PRIORIDAD, @CODCONCEPTO_OPE = CODCONCEPTO_OPE
					FROM	OPENJSON (@PARAMETROS) 
					WITH(
						CODCONCEPTO			VARCHAR(20)			'$.CODCONCEPTO',
						ITEM				DECIMAL(14,0)		'$.ITEM',
						PRIORIDAD			SMALLINT			'$.PRIORIDAD',
						CODCONCEPTO_OPE		VARCHAR(20)			'$.CODCONCEPTO_OPE'
						)
			BEGIN TRY
					DELETE FROM NCONDF WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM 
					AND CODCONCEPTO_OPE = @CODCONCEPTO_OPE AND PRIORIDAD = @PRIORIDAD
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
				END CATCH

				IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
				BEGIN
					SELECT 'KO' OK
					SELECT ERROR FROM @TBLERRORES
					RETURN
				END
		SELECT 'OK' OK
		END
END
