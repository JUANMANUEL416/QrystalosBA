CREATE OR ALTER PROCEDURE DBO.SPK_APLICARCONTEO
	@CNSIFIS   VARCHAR(20),
	@IDBODEGA  VARCHAR(20),
	@COMPANIA  VARCHAR(10),
	@SEDE      VARCHAR(5),
	@USUARIO   VARCHAR(12)
WITH ENCRYPTION
AS
/*
	Aplica conteo fisico: genera movimientos de entrada/salida por diferencias de IFISH.
	PK IMOVH incluye NOLOTE: un articulo con varios lotes requiere NOLOTE distinto por linea.
	No usar 'AJUSTE' ni valores fijos como NOLOTE (provoca clave duplicada).
	La transaccion la controla el llamador (SPQ_CONTEOFISICO metodo APLICAR).
*/
DECLARE
	@IDTIPOMOV_ENT   VARCHAR(20),
	@IDTIPOMOV_SAL   VARCHAR(20),
	@AJUSXITAR       VARCHAR(2),
	@SYS_COMPUTERNAME VARCHAR(254),
	@CNSMOV          VARCHAR(20),
	@NVOCONSEC       VARCHAR(20),
	@SEDE_2DIGITOS   VARCHAR(2),
	@CONSECUTIVO_NUMERICO VARCHAR(20),
	@TEMP_CONSEC     VARCHAR(20),
	@I_CONSEC        INT,
	@CONSECUTIVO_8DIGITOS VARCHAR(8),
	@CCOSTO          VARCHAR(20),
	@IDAREA          VARCHAR(20),
	@ITEM            INT,
	@DETALLE         VARCHAR(60),
	@FILAS_IMOVH_SAL INT,
	@FILAS_IMOVH_ENT INT,
	@LINEAS_DIF      INT

BEGIN
	SET NOCOUNT ON;
	SET XACT_ABORT OFF;

	SELECT @IDTIPOMOV_ENT = DBO.FNK_VALORVARIABLE('IDINVSIENT')
	SELECT @IDTIPOMOV_SAL = DBO.FNK_VALORVARIABLE('IDINVSISAL')
	SELECT @AJUSXITAR = UPPER(LTRIM(RTRIM(COALESCE(DBO.FNK_VALORVARIABLE('IDINV_AJUSXITAR'), ''))))
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @DETALLE = LEFT(COALESCE(DETALLE, 'Conteo fisico'), 60) FROM IFIS WHERE CNSIFIS = @CNSIFIS

	SELECT TOP 1 @CCOSTO = IBODS.VALOR
	FROM IBODS
	INNER JOIN CEN ON CEN.CCOSTO = IBODS.VALOR AND COALESCE(CEN.ESTADO, 'Activo') = 'Activo'
	WHERE IBODS.IDBODEGA = @IDBODEGA AND IBODS.TIPO = 'CEN' AND IBODS.ACCESO = 'Si'
	ORDER BY IBODS.VALOR

	IF COALESCE(@CCOSTO, '') <> ''
		SELECT @IDAREA = IDAREA FROM CEN WHERE CCOSTO = @CCOSTO

	SELECT
		F.IDARTICULO,
		F.NOLOTE,
		F.NOLOTEPEDIDO,
		COALESCE(F.PCOSTO, IART.PCOSTO, 0) AS PCOSTO,
		COALESCE(F.CONTEO3, 0) AS CONTEO,
		COALESCE(F.EXISTOTAL, 0) AS EXISTENCIA,
		COALESCE(F.CONTEO3, 0) - COALESCE(F.EXISTOTAL, 0) AS DIFERENCIA,
		IART.IDITAR,
		IX.FECHAVENCE,
		ROW_NUMBER() OVER (ORDER BY F.IDARTICULO, F.NOLOTE) AS RN
	INTO #DIF
	FROM IFISH F
	INNER JOIN IART ON IART.IDARTICULO = F.IDARTICULO
	LEFT JOIN IEXI IX ON IX.IDBODEGA = F.IDBODEGA AND IX.IDARTICULO = F.IDARTICULO AND IX.NOLOTE = F.NOLOTE
	WHERE F.CNSIFIS = @CNSIFIS
	  AND F.IDBODEGA = @IDBODEGA
	  AND COALESCE(F.ESTADO1, 0) = 1
	  AND COALESCE(F.ESTADO2, 0) = 1
	  AND COALESCE(F.ESTADO3, 0) = 1
	  AND COALESCE(F.CONTEO3, 0) <> COALESCE(F.EXISTOTAL, 0)

	SELECT @LINEAS_DIF = COUNT(*) FROM #DIF

	IF @LINEAS_DIF = 0
	BEGIN
		UPDATE IFIS
		SET CERRADO = 1, FECHACONF = DBO.FNK_FECHA_SIN_MLS(GETDATE())
		WHERE CNSIFIS = @CNSIFIS
		RETURN
	END

	IF EXISTS (
		SELECT 1
		FROM #DIF
		WHERE COALESCE(LTRIM(RTRIM(NOLOTE)), '') = ''
	)
	BEGIN
		RAISERROR('Existen lineas con diferencia sin NOLOTE en IFISH. Corrija el detalle del conteo antes de aplicar.', 16, 1)
		RETURN
	END

	IF EXISTS (
		SELECT 1
		FROM #DIF
		WHERE COALESCE(LTRIM(RTRIM(IDITAR)), '') = ''
	)
	BEGIN
		RAISERROR('Existen articulos con diferencia sin IDITAR configurado. Revise el maestro IART antes de aplicar.', 16, 1)
		RETURN
	END

	SET @FILAS_IMOVH_SAL = 0
	SET @FILAS_IMOVH_ENT = 0

	/* ===================== SALIDAS (diferencia negativa) ===================== */
	IF EXISTS (
		SELECT 1
		FROM #DIF
		WHERE DIFERENCIA < 0
		  AND COALESCE(LTRIM(RTRIM(NOLOTE)), '') <> ''
	)
	BEGIN
		SET @NVOCONSEC = NULL
		EXEC SPQ_GENSEQUENCE @SEDE = @SEDE, @PREFIJO = '@MOV', @LONGITUD = 8, @NVOCONSEC = @NVOCONSEC OUTPUT

		IF COALESCE(@NVOCONSEC, '') = ''
		BEGIN
			RAISERROR('No fue posible generar consecutivo para la salida del conteo fisico.', 16, 1)
			RETURN
		END

		SET @SEDE_2DIGITOS = RIGHT('00' + LTRIM(RTRIM(CAST(@SEDE AS VARCHAR(20)))), 2)
		SET @TEMP_CONSEC = LTRIM(RTRIM(CAST(@NVOCONSEC AS VARCHAR(20))))
		SET @CONSECUTIVO_NUMERICO = ''
		SET @I_CONSEC = 1

		WHILE @I_CONSEC <= LEN(@TEMP_CONSEC)
		BEGIN
			IF SUBSTRING(@TEMP_CONSEC, @I_CONSEC, 1) BETWEEN '0' AND '9'
				SET @CONSECUTIVO_NUMERICO = @CONSECUTIVO_NUMERICO + SUBSTRING(@TEMP_CONSEC, @I_CONSEC, 1)
			SET @I_CONSEC = @I_CONSEC + 1
		END

		IF LEN(@CONSECUTIVO_NUMERICO) >= 2 AND LEFT(@CONSECUTIVO_NUMERICO, 2) = @SEDE_2DIGITOS
			SET @CONSECUTIVO_NUMERICO = SUBSTRING(@CONSECUTIVO_NUMERICO, 3, LEN(@CONSECUTIVO_NUMERICO))

		SET @CONSECUTIVO_8DIGITOS = RIGHT('00000000' + RIGHT(@CONSECUTIVO_NUMERICO, 8), 8)
		SET @CNSMOV = @SEDE_2DIGITOS + @CONSECUTIVO_8DIGITOS

		INSERT INTO IMOV (
			CNSMOV, IDBODEGA, IDTIPOMOV, NODOCUMENTO, FECHAMOV, CCOSTO, IDAREA,
			IDSOLICITA, IDFUNCIONARIO, ESTADO, OBSERVACION, PROCEDENCIA,
			USUARIO, SYS_ComputerName, SECONTABILIZA
		)
		VALUES (
			@CNSMOV, @IDBODEGA, @IDTIPOMOV_SAL, @CNSIFIS, DBO.FNK_FECHA_SIN_MLS(GETDATE()), @CCOSTO, @IDAREA,
			@USUARIO, @USUARIO, 0,
			LEFT('Ajuste conteo fisico ' + @CNSIFIS + ' - ' + @DETALLE, 200),
			'INV', @USUARIO, @SYS_COMPUTERNAME, 0
		)

		SET @ITEM = 0

		INSERT INTO IMOVH (
			CNSMOV, IDARTICULO, CANTIDAD, CANTPEDIDA, NOLOTE, NOLOTEPEDIDO, FECHAVENCE,
			PCOSTO, ESTADO, ITEM, IDITAR, USUARIO, DETALLE
		)
		SELECT
			@CNSMOV,
			D.IDARTICULO,
			ABS(D.DIFERENCIA),
			ABS(D.DIFERENCIA),
			D.NOLOTE,
			D.NOLOTEPEDIDO,
			D.FECHAVENCE,
			D.PCOSTO,
			0,
			@ITEM + ROW_NUMBER() OVER (ORDER BY D.RN),
			D.IDITAR,
			@USUARIO,
			LEFT('Ajuste conteo fisico ' + @CNSIFIS, 200)
		FROM #DIF D
		WHERE D.DIFERENCIA < 0
		  AND COALESCE(LTRIM(RTRIM(D.NOLOTE)), '') <> ''

		SET @FILAS_IMOVH_SAL = @@ROWCOUNT

		IF @FILAS_IMOVH_SAL = 0
		BEGIN
			DELETE FROM IMOV WHERE CNSMOV = @CNSMOV
			RAISERROR('No fue posible generar el detalle de salida del conteo fisico.', 16, 1)
			RETURN
		END

		INSERT INTO ISAL (CNSMOV, IDARTICULO, NOLOTE, CANTIDAD, FECHAVENCE)
		SELECT @CNSMOV, D.IDARTICULO, D.NOLOTE, ABS(D.DIFERENCIA), D.FECHAVENCE
		FROM #DIF D
		WHERE D.DIFERENCIA < 0
		  AND COALESCE(LTRIM(RTRIM(D.NOLOTE)), '') <> ''

		/* Salidas sin confirmar al aplicar (Confirmar Salidas / movimientos despues) */
	END

	/* ===================== ENTRADAS (diferencia positiva) ===================== */
	IF EXISTS (
		SELECT 1
		FROM #DIF
		WHERE DIFERENCIA > 0
		  AND COALESCE(LTRIM(RTRIM(NOLOTE)), '') <> ''
	)
	BEGIN
		SET @NVOCONSEC = NULL
		EXEC SPQ_GENSEQUENCE @SEDE = @SEDE, @PREFIJO = '@MOV', @LONGITUD = 8, @NVOCONSEC = @NVOCONSEC OUTPUT

		IF COALESCE(@NVOCONSEC, '') = ''
		BEGIN
			RAISERROR('No fue posible generar consecutivo para la entrada del conteo fisico.', 16, 1)
			RETURN
		END

		SET @SEDE_2DIGITOS = RIGHT('00' + LTRIM(RTRIM(CAST(@SEDE AS VARCHAR(20)))), 2)
		SET @TEMP_CONSEC = LTRIM(RTRIM(CAST(@NVOCONSEC AS VARCHAR(20))))
		SET @CONSECUTIVO_NUMERICO = ''
		SET @I_CONSEC = 1

		WHILE @I_CONSEC <= LEN(@TEMP_CONSEC)
		BEGIN
			IF SUBSTRING(@TEMP_CONSEC, @I_CONSEC, 1) BETWEEN '0' AND '9'
				SET @CONSECUTIVO_NUMERICO = @CONSECUTIVO_NUMERICO + SUBSTRING(@TEMP_CONSEC, @I_CONSEC, 1)
			SET @I_CONSEC = @I_CONSEC + 1
		END

		IF LEN(@CONSECUTIVO_NUMERICO) >= 2 AND LEFT(@CONSECUTIVO_NUMERICO, 2) = @SEDE_2DIGITOS
			SET @CONSECUTIVO_NUMERICO = SUBSTRING(@CONSECUTIVO_NUMERICO, 3, LEN(@CONSECUTIVO_NUMERICO))

		SET @CONSECUTIVO_8DIGITOS = RIGHT('00000000' + RIGHT(@CONSECUTIVO_NUMERICO, 8), 8)
		SET @CNSMOV = @SEDE_2DIGITOS + @CONSECUTIVO_8DIGITOS

		INSERT INTO IMOV (
			CNSMOV, IDBODEGA, IDTIPOMOV, NODOCUMENTO, FECHAMOV, CCOSTO, IDAREA,
			IDSOLICITA, IDFUNCIONARIO, ESTADO, OBSERVACION, PROCEDENCIA,
			USUARIO, SYS_ComputerName, SECONTABILIZA
		)
		VALUES (
			@CNSMOV, @IDBODEGA, @IDTIPOMOV_ENT, @CNSIFIS, DBO.FNK_FECHA_SIN_MLS(GETDATE()), @CCOSTO, @IDAREA,
			@USUARIO, @USUARIO, 0,
			LEFT('Ajuste conteo fisico ' + @CNSIFIS + ' - ' + @DETALLE, 200),
			'INV', @USUARIO, @SYS_COMPUTERNAME, 0
		)

		SET @ITEM = 0

		INSERT INTO IMOVH (
			CNSMOV, IDARTICULO, CANTIDAD, CANTPEDIDA, NOLOTE, NOLOTEPEDIDO, FECHAVENCE,
			PCOSTO, ESTADO, ITEM, IDITAR, USUARIO, DETALLE
		)
		SELECT
			@CNSMOV,
			D.IDARTICULO,
			D.DIFERENCIA,
			D.DIFERENCIA,
			D.NOLOTE,
			D.NOLOTEPEDIDO,
			D.FECHAVENCE,
			D.PCOSTO,
			0,
			@ITEM + ROW_NUMBER() OVER (ORDER BY D.RN),
			D.IDITAR,
			@USUARIO,
			LEFT('Ajuste conteo fisico ' + @CNSIFIS, 200)
		FROM #DIF D
		WHERE D.DIFERENCIA > 0
		  AND COALESCE(LTRIM(RTRIM(D.NOLOTE)), '') <> ''

		SET @FILAS_IMOVH_ENT = @@ROWCOUNT

		IF @FILAS_IMOVH_ENT = 0
		BEGIN
			DELETE FROM IMOV WHERE CNSMOV = @CNSMOV
			RAISERROR('No fue posible generar el detalle de entrada del conteo fisico.', 16, 1)
			RETURN
		END

		/* Entradas sin confirmar: el usuario las confirma desde movimientos (evita exigir KMCOM al aplicar) */
	END

	IF (@FILAS_IMOVH_SAL + @FILAS_IMOVH_ENT) = 0
	BEGIN
		RAISERROR('El conteo tiene diferencias pero no se generaron movimientos de ajuste en IMOVH.', 16, 1)
		RETURN
	END

	UPDATE IFIS
	SET CERRADO = 1, FECHACONF = DBO.FNK_FECHA_SIN_MLS(GETDATE())
	WHERE CNSIFIS = @CNSIFIS
END
