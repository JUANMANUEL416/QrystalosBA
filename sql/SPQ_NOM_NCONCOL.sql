CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NCONCOL @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
SET DATEFORMAT dmy

DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(12)
DECLARE @CODCONCEPTO VARCHAR(20), @ITEM INT, @NOMBRE VARCHAR(255), @PROCESO VARCHAR(20), @XFECHA VARCHAR(20)
DECLARE @FECHAAPLICA DATE, @CLASE VARCHAR(10)

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (
			MODELO VARCHAR(100) '$.MODELO',
			METODO VARCHAR(100) '$.METODO',
			USUARIO VARCHAR(12) '$.USUARIO',
			PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GET_CONCEPTOS'
	BEGIN
		SELECT 'OK' OK

		SELECT NCON.CODCONCEPTO, NCON.DESCRIPCION, NCON.CLASE, NCON.ESTADO, NCON.TIPO,
			(
				SELECT COUNT(1)
				FROM NCONCOL
				WHERE NCONCOL.CODCONCEPTO = NCON.CODCONCEPTO
				) AS TOTAL_NOMBRES
		FROM NCON
		WHERE UPPER(LTRIM(RTRIM(NCON.CLASE))) IN ('MANUAL', 'PARTICULAR')
		ORDER BY NCON.CLASE, NCON.CODCONCEPTO

		RETURN
	END

	IF @METODO = 'GET_NCONCOL'
	BEGIN
		SELECT @CODCONCEPTO = CODCONCEPTO
		FROM OPENJSON(@PARAMETROS) WITH (CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO')

		SELECT 'OK' OK

		SELECT NCONCOL.CODCONCEPTO, NCONCOL.ITEM, DBO.FNK_FECHA_GRINGA(NCONCOL.FECHAAPLICA) AS FECHAAPLICA, NCONCOL.NOMBRE, NCON.DESCRIPCION, NCON.CLASE
		FROM NCONCOL
		INNER JOIN NCON ON NCON.CODCONCEPTO = NCONCOL.CODCONCEPTO
		WHERE NCONCOL.CODCONCEPTO = @CODCONCEPTO
		ORDER BY NCONCOL.FECHAAPLICA DESC, NCONCOL.ITEM DESC

		RETURN
	END

	IF @METODO = 'GUARDAR'
	BEGIN
		SELECT @CODCONCEPTO = CODCONCEPTO, @ITEM = ITEM, @XFECHA = FECHAAPLICA, @NOMBRE = NOMBRE, @PROCESO = PROCESO
		FROM OPENJSON(@PARAMETROS) WITH (
				CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO',
				ITEM INT '$.ITEM',
				FECHAAPLICA VARCHAR(20) '$.FECHAAPLICA',
				NOMBRE VARCHAR(255) '$.NOMBRE',
				PROCESO VARCHAR(20) '$.PROCESO'
				)

		IF COALESCE(LTRIM(RTRIM(@CODCONCEPTO)), '') = ''
		BEGIN
			SELECT 'KO' OK, 'El c�digo del concepto es obligatorio.' ERROR

			RETURN
		END

		SELECT @CLASE = UPPER(LTRIM(RTRIM(CLASE)))
		FROM NCON
		WHERE CODCONCEPTO = @CODCONCEPTO

		IF @CLASE IS NULL
		BEGIN
			SELECT 'KO' OK, 'El concepto no existe en el cat�logo NCON.' ERROR

			RETURN
		END

		IF @CLASE NOT IN ('MANUAL', 'PARTICULAR')
		BEGIN
			SELECT 'KO' OK, 'Solo se pueden configurar nombres de colilla para conceptos de clase Manual o Particular.' ERROR

			RETURN
		END

		IF COALESCE(LTRIM(RTRIM(@NOMBRE)), '') = ''
		BEGIN
			SELECT 'KO' OK, 'Indique el nombre que se mostrar� en la colilla.' ERROR

			RETURN
		END

		IF ISDATE(@XFECHA) = 0
		BEGIN
			SELECT 'KO' OK, 'La fecha de aplicaci�n no es v�lida: ' + COALESCE(@XFECHA, 'NULL') ERROR

			RETURN
		END

		SELECT @FECHAAPLICA = CONVERT(DATE, @XFECHA)
		SELECT @NOMBRE = LTRIM(RTRIM(@NOMBRE))

		BEGIN TRY
			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				IF EXISTS (
						SELECT 1
						FROM NCONCOL
						WHERE CODCONCEPTO = @CODCONCEPTO AND FECHAAPLICA = @FECHAAPLICA
						)
				BEGIN
					SELECT 'KO' OK, 'Ya existe un nombre de colilla para este concepto en la fecha ' + CONVERT(VARCHAR, @FECHAAPLICA, 103) + '.' ERROR

					RETURN
				END

				SELECT @ITEM = COALESCE(MAX(ITEM), 0) + 1
				FROM NCONCOL
				WHERE CODCONCEPTO = @CODCONCEPTO

				INSERT INTO NCONCOL (CODCONCEPTO, ITEM, FECHAAPLICA, NOMBRE)
				SELECT @CODCONCEPTO, @ITEM, @FECHAAPLICA, @NOMBRE
			END
			ELSE
			BEGIN
				IF NOT EXISTS (
						SELECT 1
						FROM NCONCOL
						WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM
						)
				BEGIN
					SELECT 'KO' OK, 'No se encontr� el registro para actualizar.' ERROR

					RETURN
				END

				IF EXISTS (
						SELECT 1
						FROM NCONCOL
						WHERE CODCONCEPTO = @CODCONCEPTO AND FECHAAPLICA = @FECHAAPLICA AND ITEM <> @ITEM
						)
				BEGIN
					SELECT 'KO' OK, 'Ya existe un nombre de colilla para este concepto en la fecha ' + CONVERT(VARCHAR, @FECHAAPLICA, 103) + '.' ERROR

					RETURN
				END

				UPDATE NCONCOL
				SET FECHAAPLICA = @FECHAAPLICA, NOMBRE = @NOMBRE
				WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK, ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK, @ITEM ITEM

		RETURN
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @CODCONCEPTO = CODCONCEPTO, @ITEM = ITEM
		FROM OPENJSON(@PARAMETROS) WITH (CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO', ITEM INT '$.ITEM')

		IF NOT EXISTS (
				SELECT 1
				FROM NCONCOL
				WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM
				)
		BEGIN
			SELECT 'KO' OK, 'No se encontr� el registro para eliminar.' ERROR

			RETURN
		END

		BEGIN TRY
			DELETE NCONCOL
			WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK, ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK

		RETURN
	END
END
