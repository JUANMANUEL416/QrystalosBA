IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='SPK_CONTAB_INV_JOB' AND XTYPE='P')
BEGIN
	DROP PROCEDURE SPK_CONTAB_INV_JOB
END
GO
CREATE PROCEDURE  DBO.SPK_CONTAB_INV_JOB   
WITH ENCRYPTION
AS  
DECLARE @ITEM INT, @CNSMOV VARCHAR(20), @USUARIO VARCHAR(12)
		, @SYS_COMPUTERNAME VARCHAR(254) ,@COMPANIA	VARCHAR(2)
		, @SEDE	VARCHAR(5), @NROCOMPROBANTE	VARCHAR(20)
BEGIN
	DECLARE _CURSOR CURSOR FOR   
		SELECT ITEM, CNSMOV, USUARIO, SYS_COMPUTERNAME, COMPANIA, SEDE, NROCOMPROBANTE 
		FROM IMOVC WHERE PROCESADO IS NULL ORDER BY ITEM
	  
	OPEN _CURSOR  
	FETCH NEXT FROM _CURSOR INTO @ITEM,@CNSMOV,@USUARIO,@SYS_COMPUTERNAME,@COMPANIA,@SEDE,@NROCOMPROBANTE
		
	  
	WHILE @@FETCH_STATUS = 0  
	BEGIN  
		
		BEGIN TRY  
			PRINT 'CONTABILIZANDO MOVIMIENTO '+@CNSMOV
		    EXEC SPK_NC_CONTAB_INV  @CNSMOV,@USUARIO,@SYS_COMPUTERNAME,@COMPANIA,@SEDE,@NROCOMPROBANTE
			UPDATE IMOVC SET PROCESADO=GETDATE() WHERE ITEM=@ITEM
			DELETE FROM IMOVCE WHERE CNSMOV=@CNSMOV
		END TRY  
		BEGIN CATCH
			IF EXISTS(SELECT 1 FROM MCPE WHERE PROCEDENCIA='INV' AND REFERENCIA1=@CNSMOV)
			BEGIN
				UPDATE IMOVC SET PROCESADO=GETDATE() WHERE ITEM=@ITEM
			END	
			ELSE
			BEGIN
				INSERT INTO IMOVCE(CNSMOV, ErrorNumber, ErrorSeverity, ErrorState, ErrorProcedure, ErrorMessage)
				SELECT  
					@CNSMOV
					,ERROR_NUMBER() AS ErrorNumber  
					,ERROR_SEVERITY() AS ErrorSeverity  
					,ERROR_STATE() AS ErrorState  
					,COALESCE(ERROR_PROCEDURE(),'SPK_CONTAB_INV_JOB') AS ErrorProcedure  
					,ERROR_MESSAGE() AS ErrorMessage;
			END
		END CATCH
		

	    FETCH NEXT FROM _CURSOR INTO @ITEM,@CNSMOV,@USUARIO,@SYS_COMPUTERNAME,@COMPANIA,@SEDE,@NROCOMPROBANTE
	    END  
	CLOSE _CURSOR  
	DEALLOCATE _CURSOR  
END
