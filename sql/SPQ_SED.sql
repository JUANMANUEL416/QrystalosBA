CREATE OR ALTER PROCEDURE DBO.SPQ_SED
   @JSON  NVARCHAR(MAX)
WITH
ENCRYPTION
AS
DECLARE  @PARAMETROS NVARCHAR(MAX), @MODELO   VARCHAR(100), @METODO     VARCHAR(100), @USUARIO   VARCHAR(12), @A INT
DECLARE  @IDSEDE VARCHAR(5), @DESCRIPCION VARCHAR(50), @CIUDAD VARCHAR(5), @IDSEDE_ORI VARCHAR(5), @NUMCONS VARCHAR(20), @DESCCONS VARCHAR(100), @ESTADO VARCHAR(20), @TIPO VARCHAR (20), @PROCESO VARCHAR(20), @IDSEDCONS INT
DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200));

BEGIN
   SELECT @A = ISJSON(@JSON)
   IF @A = 0 
   BEGIN
      RAISERROR('Json: Formato Erroneo',16,1)
      RETURN
   END
   --PRINT 'INGRESE A SPQ_ACTI'
      
   SELECT *
   INTO #JSON
   FROM OPENJSON (@json)
	WITH (
	   MODELO         VARCHAR(100)     '$.MODELO',
	   METODO         VARCHAR(100)     '$.METODO',
      USUARIO        VARCHAR(12)      '$.USUARIO',
	   PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

   SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
   FROM #JSON

   IF @METODO = 'REGISTRAR'
   BEGIN

      SELECT @IDSEDE = IDSEDE, @DESCRIPCION = DESCRIPCION, @CIUDAD = CIUDAD
      FROM   OPENJSON (@PARAMETROS)
      WITH (
             IDSEDE         VARCHAR(5)    '$.IDSEDE',
             DESCRIPCION    VARCHAR(50)   '$.DESCRIPCION',
             CIUDAD         VARCHAR(5)    '$.CIUDAD'
           )

      INSERT INTO SED(IDSEDE, DESCRIPCION,CIUDAD)
      SELECT @IDSEDE, @DESCRIPCION, @CIUDAD

      RETURN
   END
   IF @METODO = 'CONSULTAR'
   BEGIN
      SELECT @IDSEDE = IDSEDE
      FROM   OPENJSON (@PARAMETROS)
      WITH (
             IDSEDE         VARCHAR(5)    '$.IDSEDE'
           )
      SELECT DESCRIPCION, CIUDAD FROM SED WHERE IDSEDE = @IDSEDE
      RETURN
   END
   IF @METODO = 'EDITAR'
   BEGIN
      SELECT @IDSEDE_ORI = IDSEDE_ORI, @IDSEDE = IDSEDE, @DESCRIPCION = DESCRIPCION, @CIUDAD = CIUDAD
      FROM   OPENJSON (@PARAMETROS)
      WITH (
             IDSEDE_ORI     VARCHAR(5)    '$.IDSEDE_ORI',
             IDSEDE         VARCHAR(5)    '$.IDSEDE',
             DESCRIPCION    VARCHAR(50)   '$.DESCRIPCION',
             CIUDAD         VARCHAR(5)    '$.CIUDAD'
           )
      UPDATE SED 
      SET   IDSEDE = @IDSEDE, DESCRIPCION = @DESCRIPCION, CIUDAD = @CIUDAD   
      WHERE IDSEDE = @IDSEDE_ORI
      RETURN
   END
   IF @METODO = 'BORRAR'
   BEGIN
      SELECT @IDSEDE = IDSEDE
      FROM   OPENJSON (@PARAMETROS)
      WITH (
             IDSEDE         VARCHAR(5)    '$.IDSEDE'
           )
      DELETE SED WHERE IDSEDE = @IDSEDE
      RETURN
   END
   IF @METODO = 'CONSULTA'
   BEGIN
      SELECT @IDSEDE = IDSEDE
      FROM   OPENJSON (@PARAMETROS)
      WITH (
             IDSEDE         VARCHAR(5)    '$.IDSEDE'
           )
      SELECT IDSEDE,DESCRIPCION, CIUDAD FROM SED WHERE @IDSEDE IS NULL OR IDSEDE = @IDSEDE
      RETURN
   END
   IF @METODO = 'CONSULTART'
   BEGIN
      SELECT @IDSEDE = IDSEDE
      FROM   OPENJSON (@PARAMETROS)
      WITH (
             IDSEDE         VARCHAR(5)    '$.IDSEDE'
           )
      SELECT IDSEDE value,  CONCAT(SED.IDSEDE , ' - ' , SED.DESCRIPCION )  label FROM SED WHERE @IDSEDE IS NULL OR IDSEDE = @IDSEDE
      RETURN
   END
   IF @METODO = 'LISTADO'
   BEGIN
      SELECT @IDSEDE = JSON_VALUE(@PARAMETROS,'$.IDSEDE')
	  SELECT 'OK' AS OK, @IDSEDE AS IDSEDE 
      SELECT * FROM SED WHERE @IDSEDE IS NULL OR IDSEDE = @IDSEDE
      RETURN
   END
   	IF @METODO = 'CRUDSEDCONS'
   	BEGIN
		
   		SELECT @IDSEDE = IDSEDE, @NUMCONS = NUMCONS, @DESCCONS = DESCCONS, @TIPO = TIPO, @ESTADO = ESTADO, @PROCESO = PROCESO, @IDSEDCONS = IDSEDCONS
   		FROM OPENJSON(@PARAMETROS)
   		WITH(		IDSEDE		VARCHAR(20)		'$.IDSEDE',			NUMCONS	VARCHAR(20)		'$.NUMCONS'
					,DESCCONS	VARCHAR(100)	'$.DESCCONS',		TIPO	VARCHAR(20)		'$.TIPO'
					,ESTADO		VARCHAR(20)		'$.ESTADO',			PROCESO	VARCHAR(20)		'$.PROCESO'
					,IDSEDCONS	INT				'$.IDSEDCONS')
   
   		IF @PROCESO = 'Nuevo' AND EXISTS (SELECT * FROM SEDCONS  WHERE IDSEDE = @IDSEDE AND NUMCONS = @NUMCONS)
   		BEGIN
   			INSERT INTO @TBLERRORES(ERROR) SELECT 'El C�digo del consultorio, ya existe para esta Sede, por favor revisar.'
   		END
		IF @PROCESO = 'Editar' AND EXISTS (SELECT * FROM SEDCONS  WHERE IDSEDE = @IDSEDE AND NUMCONS = @NUMCONS AND IDSEDCONS <> @IDSEDCONS)
   		BEGIN
   			INSERT INTO @TBLERRORES(ERROR) SELECT 'El C�digo del consultorio, ya existe para esta Sede, por favor revisar.'
   		END
   	
   		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
   		BEGIN
   			SELECT 'KO' OK
   			SELECT ERROR FROM @TBLERRORES
   			RETURN
   		END
   		ELSE
   		BEGIN
   			BEGIN TRY
   				IF @PROCESO = 'Nuevo'
				BEGIN
					INSERT INTO SEDCONS (IDSEDE, NUMCONS, DESCCONS, TIPO, ESTADO)
					SELECT @IDSEDE, @NUMCONS, @DESCCONS, @TIPO, @ESTADO
				END
				IF @PROCESO = 'Editar'
				BEGIN
					UPDATE SEDCONS SET NUMCONS = @NUMCONS, DESCCONS = @DESCCONS, TIPO = @TIPO, ESTADO = @ESTADO WHERE IDSEDCONS = @IDSEDCONS
				END
   			END TRY  
   			BEGIN CATCH 
   				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
   			END CATCH  
   			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
   			BEGIN
   				SELECT 'KO' OK
   				SELECT ERROR FROM @TBLERRORES
   				RETURN
   			END
   			SELECT 'OK'OK
   		END 
   	END 
END
