CREATE OR ALTER PROCEDURE DBO.SPQ_TANT_COL
@JSON  NVARCHAR(MAX)
WITH
ENCRYPTION
AS
DECLARE @PARAMETROS         NVARCHAR(MAX)  ,@MODELO           VARCHAR(100)    ,@METODO        VARCHAR(100)  ,@USUARIO        VARCHAR(12)
       ,@GRUPO              VARCHAR(8)     ,@SYS_COMPUTERNAME VARCHAR(254)    ,@SEDE          VARCHAR(5)	   ,@A              INT
       ,@IDENTITY           INT 
       ,@PROCESO            VARCHAR(20)    ,@TANT    NVARCHAR(MAX)
              ,@TIPOANTICIPO     VARCHAR(6)
       ,@DESCRIPCION     VARCHAR(512)
       ,@COMPROBANTE     VARCHAR(2)
       ,@CUEDEBITO     VARCHAR(16)
       ,@CUECREDITO     VARCHAR(16)
BEGIN
   SET LANGUAGE Spanish
   SET DATEFORMAT dmy
   
   SELECT @A = ISJSON(@JSON)
   IF @A = 0
   BEGIN
     RAISERROR('Json: Formato Erroneo',16,1)
     RETURN
   END
   PRINT 'INGRESE A SPQ_TANT_COL'
   SELECT *
   INTO #JSON
   FROM OPENJSON (@json)
   WITH (
     MODELO         VARCHAR(100)     '$.MODELO',
     METODO         VARCHAR(100)     '$.METODO',
     USUARIO        VARCHAR(12)      '$.USUARIO',
     PARAMETROS     NVARCHAR(MAX)     AS JSON
   )
   
   SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS , @USUARIO = USUARIO
   FROM #JSON
   --DEFINICION DE TABLA DE ERRORES
   DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200))
   -- TOMA DEL GRUPO, SYS_COMPUTERNAME, SEDE   DE ACUERDO AL USUARIO
   PRINT 'USUARIO:'+@USUARIO
   --SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO) FROM USUSU WHERE USUARIO = @USUARIO
   --SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
   --SELECT @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
   IF COALESCE(@SEDE,'') = '' SELECT @SEDE = '01'
   PRINT 'SEDE='+@SEDE
   IF @METODO = 'CRUDTANT'
   BEGIN
      PRINT 'CRUDTANT'
      SELECT @TANT  = REGISTRO
      FROM OPENJSON (@PARAMETROS)
      WITH(
         REGISTRO   NVARCHAR(MAX)     AS JSON
      )
      
      SELECT @PROCESO     = JSON_VALUE(@TANT ,'$.PROCESO')
      --Leo Campos enviados y los coloco en las variables respectivas
      SELECT @TIPOANTICIPO = JSON_VALUE(@TANT , '$.TIPOANTICIPO' )
      SELECT @DESCRIPCION = JSON_VALUE(@TANT , '$.DESCRIPCION' )
      SELECT @COMPROBANTE = JSON_VALUE(@TANT , '$.COMPROBANTE' )
      SELECT @CUEDEBITO = JSON_VALUE(@TANT , '$.CUEDEBITO' )
      SELECT @CUECREDITO = JSON_VALUE(@TANT , '$.CUECREDITO' )

      IF UPPER(@PROCESO) = 'INSERTAR'
      BEGIN
         PRINT 'INSERTAR'
         BEGIN TRY
			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'EL TIPO DE ANTICIPO YA EXISTE'
			WHERE EXISTS (SELECT 1 FROM TANT WHERE TIPOANTICIPO = @TIPOANTICIPO)

			IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
			BEGIN
				INSERT INTO TANT(TIPOANTICIPO,DESCRIPCION,COMPROBANTE,CUEDEBITO,CUECREDITO)
				SELECT @TIPOANTICIPO,@DESCRIPCION,@COMPROBANTE,@CUEDEBITO,@CUECREDITO
				SELECT @IDENTITY = SCOPE_IDENTITY()
			END
		 END TRY
         BEGIN CATCH
            INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
         END CATCH
         IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
         BEGIN
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
         END
         SELECT 'OK' OK ,@IDENTITY CNS 
         RETURN
      END

      IF UPPER(@PROCESO) = 'EDITAR'
      BEGIN
         BEGIN TRY
            UPDATE TANT SET
                    TIPOANTICIPO = @TIPOANTICIPO,DESCRIPCION = @DESCRIPCION,COMPROBANTE = @COMPROBANTE,CUEDEBITO = @CUEDEBITO,CUECREDITO = @CUECREDITO
            WHERE TIPOANTICIPO = @TIPOANTICIPO
         END TRY
         BEGIN CATCH
            INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
         END CATCH
         IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
         BEGIN
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
         END
         SELECT 'OK' OK
         RETURN
      END
      RETURN
   END
END
