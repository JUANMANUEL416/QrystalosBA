/*
  CEM — Pasar a IVA lo que quedó dentro de la base.
  Solo cuentas por pagar. No toca entradas ni existencias.

  INST258062  34CM000076  DM0864-1
    El pedido trae base 1.600.000 e IVA 304.000 (1.600 × 1.000, 19 %).
    La cuenta tiene los 1.904.000 en la base y el IVA en cero.
    Queda base 1.600.000, IVA 304.000, neto 1.904.000,
    cuenta 14200501 e IVA 24080501.
    La cabecera baja la base en 304.000 y sube el IVA en 304.000.
    El neto 7.449.750 no cambia.

  INST257463  03CM001911  DM119-5
    El pedido trae base 129.000 e IVA 24.510 (30 × 4.300, 19 %).
    La cuenta tiene los 153.510 en la base y el IVA en cero.
    Queda base 129.000, IVA 24.510, neto 153.510,
    cuenta 14200501 e IVA 24080501.
    La cabecera baja la base en 24.510 y sube el IVA en 24.510.
    El neto 1.329.190 no cambia.

  Uso:
    1. Deje @APLICAR = 0 y ejecute. Revise el listado.
    2. Ponga @APLICAR = 1 y vuelva a ejecutar.
       Si algo no cuadra, hace ROLLBACK y no deja nada.
*/

SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @APLICAR bit = 0;

SELECT
  P.NOREFERENCIA,
  D.IDSERVICIO,
  CONVERT(decimal(18, 2), D.CANTIDAD) AS CANT,
  CONVERT(decimal(18, 2), D.VALOR) AS PRECIO_HOY,
  CASE D.IDSERVICIO WHEN N'DM0864-1' THEN CONVERT(decimal(18, 2), 1000) ELSE CONVERT(decimal(18, 2), 4300) END AS PRECIO_OK,
  CONVERT(decimal(18, 2), D.CANTIDAD * D.VALOR) AS BASE_HOY,
  CASE D.IDSERVICIO WHEN N'DM0864-1' THEN CONVERT(decimal(18, 2), 1600000) ELSE CONVERT(decimal(18, 2), 129000) END AS BASE_OK,
  CONVERT(decimal(18, 2), D.VLR_IVA) AS IVA_HOY,
  CASE D.IDSERVICIO WHEN N'DM0864-1' THEN CONVERT(decimal(18, 2), 304000) ELSE CONVERT(decimal(18, 2), 24510) END AS IVA_OK,
  CONVERT(decimal(18, 2), D.VLR_NETO) AS NETO,
  D.CUENTA_SER AS CUENTA_HOY,
  N'14200501' AS CUENTA_OK,
  COALESCE(D.CUENTA_IVA, N'') AS IVA_CUENTA_HOY
FROM dbo.FCXP P
INNER JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
WHERE (P.CNSFCXP = N'34CM000076' AND D.IDSERVICIO = N'DM0864-1')
   OR (P.CNSFCXP = N'03CM001911' AND D.IDSERVICIO = N'DM119-5')
ORDER BY P.NOREFERENCIA;

IF @APLICAR = 0
  RETURN;

BEGIN TRAN;

IF EXISTS (
  SELECT 1
  FROM dbo.FCXP
  WHERE CNSFCXP IN (N'34CM000076', N'03CM001911')
    AND (
      ESTADO <> N'N'
      OR COALESCE(CONTABILIZADA, 0) <> 0
      OR COALESCE(RTRIM(NROCOMPROBANTE), N'') <> N''
    )
)
BEGIN
  ROLLBACK TRAN;
  THROW 56070, 'Alguna de las dos cuentas ya no está libre.', 1;
END;

IF NOT EXISTS (
  SELECT 1
  FROM dbo.FCXPD
  WHERE CNSFCXP = N'34CM000076'
    AND IDSERVICIO = N'DM0864-1'
    AND CANTIDAD = 1600
    AND VLR_IVA = 0
    AND VLR_NETO = 1904000
    AND CUENTA_SER = N'14200502'
)
   OR NOT EXISTS (
  SELECT 1
  FROM dbo.FCXPD
  WHERE CNSFCXP = N'03CM001911'
    AND IDSERVICIO = N'DM119-5'
    AND CANTIDAD = 30
    AND VLR_IVA = 0
    AND VLR_NETO = 153510
    AND CUENTA_SER = N'14200502'
)
BEGIN
  ROLLBACK TRAN;
  THROW 56071, 'Las líneas ya no están como se esperaba.', 1;
END;

UPDATE D
SET VALOR = 1000,
    VLR_IVA = 304000,
    VLR_NETO = 1904000,
    CUENTA_SER = N'14200501',
    CUENTA_IVA = N'24080501',
    IDIMPUESTO = REF.IDIMPUESTO,
    IDCLASE = REF.IDCLASE
FROM dbo.FCXPD D
CROSS APPLY (
  SELECT TOP 1 IDIMPUESTO, IDCLASE
  FROM dbo.FCXPD
  WHERE CNSFCXP = N'34CM000076'
    AND CUENTA_IVA = N'24080501'
    AND COALESCE(IDIMPUESTO, N'') <> N''
) REF
WHERE D.CNSFCXP = N'34CM000076'
  AND D.IDSERVICIO = N'DM0864-1';

UPDATE D
SET VALOR = 4300,
    VLR_IVA = 24510,
    VLR_NETO = 153510,
    CUENTA_SER = N'14200501',
    CUENTA_IVA = N'24080501',
    IDIMPUESTO = REF.IDIMPUESTO,
    IDCLASE = REF.IDCLASE
FROM dbo.FCXPD D
CROSS APPLY (
  SELECT TOP 1 IDIMPUESTO, IDCLASE
  FROM dbo.FCXPD
  WHERE CNSFCXP = N'03CM001911'
    AND CUENTA_IVA = N'24080501'
    AND COALESCE(IDIMPUESTO, N'') <> N''
) REF
WHERE D.CNSFCXP = N'03CM001911'
  AND D.IDSERVICIO = N'DM119-5';

UPDATE dbo.FCXP
SET VALOR = 6264150.00,
    VLR_IVA = 1185600.00
WHERE CNSFCXP = N'34CM000076'
  AND VLR_NETO = 7449750.00
  AND SALDO = 7449750.00;

UPDATE dbo.FCXP
SET VALOR = 1196000.00,
    VLR_IVA = 133190.00
WHERE CNSFCXP = N'03CM001911'
  AND VLR_NETO = 1329190.00
  AND SALDO = 1329190.00;

IF EXISTS (
  SELECT 1
  FROM dbo.FCXP P
  INNER JOIN (
    SELECT CNSFCXP,
           SUM(ROUND(CANTIDAD * VALOR, 2)) AS BASE,
           SUM(VLR_IVA) AS IVA,
           SUM(VLR_NETO) AS NETO
    FROM dbo.FCXPD
    WHERE CNSFCXP IN (N'34CM000076', N'03CM001911')
    GROUP BY CNSFCXP
  ) D ON D.CNSFCXP = P.CNSFCXP
  WHERE ABS(P.VALOR - D.BASE) > 0.02
     OR ABS(P.VLR_IVA - D.IVA) > 0.02
     OR ABS(P.VLR_NETO - D.NETO) > 0.02
     OR ABS(P.VLR_NETO - (P.VALOR + P.VLR_IVA)) > 0.02
)
BEGIN
  ROLLBACK TRAN;
  THROW 56072, 'La cabecera no cuadra con el detalle.', 1;
END;

COMMIT TRAN;

SELECT
  P.NOREFERENCIA,
  CONVERT(decimal(18, 2), P.VALOR) AS BASE,
  CONVERT(decimal(18, 2), P.VLR_IVA) AS IVA,
  CONVERT(decimal(18, 2), P.VLR_NETO) AS NETO,
  D.IDSERVICIO,
  CONVERT(decimal(18, 2), D.CANTIDAD * D.VALOR) AS BASE_LINEA,
  CONVERT(decimal(18, 2), D.VLR_IVA) AS IVA_LINEA,
  D.CUENTA_SER,
  D.CUENTA_IVA
FROM dbo.FCXP P
INNER JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
WHERE (P.CNSFCXP = N'34CM000076' AND D.IDSERVICIO = N'DM0864-1')
   OR (P.CNSFCXP = N'03CM001911' AND D.IDSERVICIO = N'DM119-5')
ORDER BY P.NOREFERENCIA;
