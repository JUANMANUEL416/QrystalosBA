IF EXISTS (SELECT name FROM sysobjects WHERE NAME = 'SPK_COPAGOHAQX' AND TYPE = 'P')
   DROP PROCEDURE SPK_COPAGOHAQX

GO
CREATE PROCEDURE DBO.SPK_COPAGOHAQX
@NOADMISION   VARCHAR(16)  
WITH ENCRYPTION
AS     
DECLARE @COPAGONOAUTORIZACION VARCHAR(20)     
DECLARE @COPAGOVALOR  DECIMAL(14,2)        
DECLARE @CANTIDAD     INT               
DECLARE @TOTAL        DECIMAL(14,2)      
DECLARE @NOPRESTACION VARCHAR(16)      
DECLARE @ITEM         INT                 
DECLARE @IDTERCERO    VARCHAR(20)      
DECLARE @IDTERCEROCA  VARCHAR(20)      
DECLARE @PORDESCONTAR DECIMAL(14,2)   
DECLARE @DTOCOPAGO    DECIMAL(14,2)   
DECLARE @DTOCOPAGO1   DECIMAL(14,2)   
DECLARE @VLRHPRED     DECIMAL(18,6)   
DECLARE @NOITEM       INT
DECLARE @INDCOP       SMALLINT
DECLARE @IDPLANCA     VARCHAR(6)
DECLARE @IDAREA       VARCHAR(20)
DECLARE @ESCIRUGIA    VARCHAR(2)
DECLARE @CARGOSENCX   SMALLINT
DECLARE @NOCOBRABLE   SMALLINT
DECLARE @VLRSERVICIO  DECIMAL(14,2)
DECLARE @CONT           INT
DECLARE @TIPRECARGONOC  VARCHAR(10)
DECLARE @DIASIGRN       SMALLINT
DECLARE @FECHACARGO     DATETIME
DECLARE @TIPODTO        VARCHAR(1)
DECLARE @IDSERVICIO     VARCHAR(20)
DECLARE @VLRRECCARGONOC DECIMAL(14,2)
DECLARE @HIRECNOC       INT  
DECLARE @HFRECNOC       INT
DECLARE @DESCUENTO      DECIMAL(14,2)
DECLARE @MANUAL         SMALLINT 
DECLARE @LUNES            SMALLINT 
DECLARE @MARTES           SMALLINT 
DECLARE @MIERCOLES        SMALLINT 
DECLARE @JUEVES           SMALLINT 
DECLARE @VIERNES          SMALLINT 
DECLARE @SABADO           SMALLINT 
DECLARE @DOMINGO          SMALLINT 
DECLARE @FESTIVOTOTAL     SMALLINT 
DECLARE @DOMIGOTOTAL      SMALLINT 
DECLARE @DHOY             INT
DECLARE @MIN_HI           INT 
DECLARE @HOR_HI           INT 
DECLARE @MIN_HID          INT 
DECLARE @MIN_HF           INT 
DECLARE @HOR_HF           INT 
DECLARE @MIN_HFD          INT 
DECLARE @FI_RN            DATETIME 
DECLARE @FF_RN            DATETIME
BEGIN  
   PRINT 'ENTRE'
   /* INICIO CALCULO DE VALORES */
   /*******************/
   DECLARE PRESTACIOND_CURSOR CURSOR FOR  
   SELECT  HPRED.NOPRESTACION, HPRED.NOITEM, COALESCE(HPRED.MANUAL,0)
   FROM    HPRE INNER JOIN HPRED ON HPRE.NOPRESTACION = HPRED.NOPRESTACION 
   WHERE   HPRE.NOADMISION = @NOADMISION
   AND    COALESCE(HPRED.FACTURADA,0)=0
   OPEN    PRESTACIOND_CURSOR  
   FETCH NEXT FROM PRESTACIOND_CURSOR  
   INTO    @NOPRESTACION, @NOITEM, @MANUAL
   WHILE   @@FETCH_STATUS = 0  
   BEGIN        
      /*******************/
      PRINT 'NOPRESTACION = ' + @NOPRESTACION
      PRINT 'NOITEM = ' + STR(@NOITEM)
      
      SELECT @IDPLANCA  = IDPLAN,   @IDTERCEROCA = IDTERCEROCA, @IDSERVICIO = IDSERVICIO ,  @TIPODTO = TIPODTO,
             @DESCUENTO = DESCUENTO, @NOCOBRABLE = COALESCE(NOCOBRABLE , 0)
      FROM   HPRED 
      WHERE  NOPRESTACION = @NOPRESTACION AND NOITEM = @NOITEM
            
      PRINT '@IDSERVICIO='+@IDSERVICIO
      
      SELECT @IDAREA = IDAREA, @FECHACARGO = FECHA, @ESCIRUGIA = COALESCE(CIRUGIA,'NO') 
      FROM   HPRE
      WHERE  NOPRESTACION = @NOPRESTACION
      IF @NOCOBRABLE IS NULL    
         SELECT @NOCOBRABLE = 0
      IF @ESCIRUGIA = '' 
         SELECT @ESCIRUGIA = 'NO'
      PRINT 'ESCIRUGIA=' + @ESCIRUGIA
      PRINT 'NOCOBRABLE='+STR(@NOCOBRABLE)
      /*PRINT 'FECHACARGO='+@FECHACARGO*/
      PRINT 'IDAREA='+@IDAREA
      IF @ESCIRUGIA = 'SI'
      BEGIN
         IF @CARGOSENCX = 1
         BEGIN
            SELECT @ESCIRUGIA = 'NO'
         END
      END
      
      IF @ESCIRUGIA <> 'SI'
      BEGIN
         PRINT 'ENTRE A NO ES CIRUGIA'
         IF @NOCOBRABLE = 0
         BEGIN
            PRINT 'NOCOBRABLE=0'
            SELECT @VLRSERVICIO = VLRSERVICIO 
            FROM   SERTOT1 
            WHERE  IDTERCERO   =  @IDTERCEROCA
            AND    IDPLAN      =  @IDPLANCA
            AND    IDSERVICIO  =  @IDSERVICIO
            AND    FECHAINIFD  <= @FECHACARGO
            AND    FECHAFINFD  >= @FECHACARGO
            AND    FECHAINI    <= @FECHACARGO
            AND    FECHAFIN    >= @FECHACARGO
            AND    IDAREACA     = @IDAREA
            
            PRINT 'VALORSERVICIO='+STR(@VLRSERVICIO)    
            SELECT @CONT = COUNT(*) FROM FES WHERE FECHA = DBO.FNK_FECHA_SIN_HORA(@FECHACARGO)
            PRINT 'CONT='+ STR(@CONT)
            
            select @DIASIGRN = 0
            
            SELECT @DHOY  = DATEPART(DW, DBO.FNK_FECHA_SIN_HORA(@FECHACARGO))
            
            
            SELECT @TIPRECARGONOC = RNXT.TIPORECARGONOC, @VLRRECCARGONOC = RNXT.VLRRECARGONOC,
                   @HIRECNOC      = RNXT.HIRECNOC,       @HFRECNOC       = RNXT.HFRECNOC, 
                   @DIASIGRN      = RNXT.DIASIGRN,       @LUNES          = RNXT.LUNES,
                   @MARTES        = RNXT.MARTES,         @MIERCOLES      = RNXT.MIERCOLES,
                   @JUEVES        = RNXT.JUEVES,         @VIERNES        = RNXT.VIERNES,
                   @SABADO        = RNXT.SABADO,         @DOMINGO        = RNXT.DOMINGO,
                   @FESTIVOTOTAL  = RNXT.FESTIVOTOTAL,   @DOMIGOTOTAL    = RNXT.DOMIGOTOTAL,
                   @MIN_HI = (RNXT.HIRECNOC/100)/60,     @MIN_HF = (RNXT.HFRECNOC/100)/60
            FROM   RNXT INNER JOIN SER ON RNXT.PREFIJO   = SER.PREFIJO 
            WHERE  RNXT.IDTERCERO = @IDTERCEROCA
            AND    RNXT.IDPLAN    = @IDPLANCA 
            AND    SER.IDSERVICIO = @IDSERVICIO  
            
            SELECT  @HOR_HI  = @MIN_HI / 60, @HOR_HF = @MIN_HF / 60
            SELECT  @MIN_HID = @MIN_HI - (@HOR_HI * 60), @MIN_HFD = @MIN_HF - (@HOR_HF * 60)      
            
            IF @CONT > 0
            BEGIN
               print 'es festivo'
               IF @FESTIVOTOTAL = 1
               BEGIN
                  IF @TIPRECARGONOC IS NOT NULL
                  BEGIN
                     IF @VLRRECCARGONOC IS NOT NULL
                     BEGIN
                        IF @TIPRECARGONOC = 'Valor'
                        BEGIN
                           SELECT  @VLRSERVICIO = @VLRSERVICIO + @VLRRECCARGONOC 
                        END
                        ELSE
                        BEGIN
                           SELECT  @VLRSERVICIO = @VLRSERVICIO  * ( 1 + ( @VLRRECCARGONOC / 100 ) )
                        END
                     END
                  END
               END   
            END
            ELSE
            BEGIN 
               IF DATEPART(HOUR, @FECHACARGO) <= 7
               BEGIN
                  SELECT @DHOY = @DHOY -1 
                  IF @DHOY = 0 
                  BEGIN
                     SELECT @DHOY = 7
                  END
               END
               
               IF    (@DHOY = 1 AND @LUNES = 1)   OR (@DHOY = 2 AND @MARTES = 1) OR (@DHOY = 3 AND @MIERCOLES = 1) OR (@DHOY = 4 AND @JUEVES = 1)
                  OR (@DHOY = 5 AND @VIERNES = 1) OR (@DHOY = 6 AND @SABADO = 1) OR (@DHOY = 7 AND @DOMINGO = 1)
               BEGIN
                  SELECT @FI_RN = CONVERT(DATETIME, (CONVERT(VARCHAR(10),DBO.FNK_FECHA_SIN_HORA(@FECHACARGO), 103)+' '+CAST(@HOR_HI AS VARCHAR(2))+':'+CAST(@MIN_HID AS VARCHAR(2))+':00.000'))
                  IF @DIASIGRN = 1
                  BEGIN
                     SELECT @FF_RN = CONVERT(DATETIME, (CONVERT(VARCHAR(10),DBO.FNK_FECHA_SIN_HORA(@FECHACARGO+1), 103)+' '+CAST(@HOR_HF AS VARCHAR(2))+':'+CAST(@MIN_HFD AS VARCHAR(2))+':59.999'))
                  END
                  ELSE
                  BEGIN
                     SELECT @FF_RN = CONVERT(DATETIME, (CONVERT(VARCHAR(10),DBO.FNK_FECHA_SIN_HORA(@FECHACARGO), 103)+' '+CAST(@HOR_HF AS VARCHAR(2))+':'+CAST(@MIN_HFD AS VARCHAR(2))+':59.999'))
                  END   
                                    
                  IF @FECHACARGO >= @FI_RN AND @FECHACARGO <= @FF_RN
                  BEGIN
                     IF @TIPRECARGONOC = 'Valor'
                     BEGIN
                        SELECT  @VLRSERVICIO = @VLRSERVICIO + @VLRRECCARGONOC 
                     END   
                     ELSE
                     BEGIN
                        SELECT  @VLRSERVICIO = @VLRSERVICIO  * ( 1 + ( @VLRRECCARGONOC / 100 ) )
                     END   
                  END
               END
               
            END
            PRINT 'VALOR DESP rnxt='+STR(@VLRSERVICIO)      
            IF @TIPODTO = 'V'
            BEGIN
               SELECT  @VLRSERVICIO = @VLRSERVICIO - @DESCUENTO
            END
            IF @TIPODTO = 'P'
            BEGIN
               SELECT  @VLRSERVICIO = @VLRSERVICIO * (1 - ( @DESCUENTO /100 ) )
            END
            PRINT 'VALOR DESP descuento='+STR(@VLRSERVICIO)
            print 'antes del update'
            IF @MANUAL <> 1
            BEGIN 
               UPDATE HPRED SET VALOR = @VLRSERVICIO 
               WHERE  NOPRESTACION = @NOPRESTACION 
               AND    NOITEM = @NOITEM
            END            
         END
         ELSE
         BEGIN
            UPDATE HPRED SET VALOR = 0
            WHERE  NOPRESTACION = @NOPRESTACION 
            AND    NOITEM = @NOITEM
         END
         
      END
      PRINT 'VALOR DESP CALCULO='+STR(@VLRSERVICIO)
      FETCH NEXT FROM PRESTACIOND_CURSOR  
      INTO    @NOPRESTACION, @NOITEM, @MANUAL
   END
   CLOSE PRESTACIOND_CURSOR  
   DEALLOCATE PRESTACIOND_CURSOR  
   /* FIN CALCULO DE VALORES */
   
   SELECT @COPAGONOAUTORIZACION = HADM.COPAGONOAUTORIZACION,  
          @PORDESCONTAR         = HADM.COPAGOVALOR,  
          @COPAGOVALOR          = HADM.COPAGOVALOR, 
          @IDTERCERO            = HADM.IDTERCERO
   FROM   HADM  
   WHERE  HADM.NOADMISION   = @NOADMISION          
   SELECT @DTOCOPAGO = 0
   
   -- CURSOR
   DECLARE PRESTACION_CURSOR CURSOR FOR  
   SELECT COUNT(*), SUM(HPRED.VALOR*HPRED.CANTIDAD), HPRED.NOPRESTACION  
   FROM  HPRE,HPRED  
   WHERE HPRE.NOADMISION   = @NOADMISION  
   AND   HPRE.NOPRESTACION = HPRED.NOPRESTACION 
   AND    COALESCE(HPRED.FACTURADA,0)=0 
   GROUP BY HPRED.NOPRESTACION                 
   OPEN PRESTACION_CURSOR  
   FETCH NEXT FROM PRESTACION_CURSOR  
   INTO @CANTIDAD, @TOTAL, @NOPRESTACION
   WHILE @@FETCH_STATUS = 0  
   BEGIN  
      PRINT 'EN CURSOR'
      UPDATE HPRE SET VALORTOTAL = @TOTAL, VALOREXEDENTE = @TOTAL,
                      VALORCOPAGO = 0,VALORPCOMP = 0           
      WHERE  HPRE.NOPRESTACION = @NOPRESTACION
             
      UPDATE HPRE SET HPRE.VALORPCOMP = (HPRE.VALORTOTAL * ((100-HPRE.PCUBRIMIENTO)/100))  
      WHERE HPRE.NOPRESTACION = @NOPRESTACION              
      
      -- BEGIN M1  EL COPAGO HECHO POR ADMISION CONTROL ENTRE VARIAS PRESTACIONES
      -- JEDM: 24-ABR-2004 
      PRINT 'NOPRESTACION='+@NOPRESTACION+' @PORDESCONTAR'+STR(@PORDESCONTAR)
       
      IF @PORDESCONTAR >= 0
      BEGIN
         IF @TOTAL <= @PORDESCONTAR
         BEGIN
            SELECT @INDCOP    = 1                -- JEDM: 25.JUL.2005
            SELECT @DTOCOPAGO = @TOTAL
         END
         ELSE
         BEGIN
            SELECT @INDCOP    = 2                -- JEDM: 25.JUL.2005
            SELECT @DTOCOPAGO = @PORDESCONTAR
         END
         SELECT @PORDESCONTAR = @PORDESCONTAR - @DTOCOPAGO
      END
                    
      SELECT @IDTERCEROCA = IDTERCEROCA FROM HPRE WHERE NOPRESTACION = @NOPRESTACION
      
      UPDATE HPRE SET VALORCOPAGO = @DTOCOPAGO
      WHERE  HPRE.NOPRESTACION = @NOPRESTACION  
      
      -- END M1
      UPDATE HPRE SET VALOREXEDENTE = (HPRE.VALORTOTAL - HPRE.VALORCOPAGO - HPRE.VALORPCOMP)  
      WHERE HPRE.NOPRESTACION = @NOPRESTACION
      
      UPDATE HPRED SET VALORPCOMP = (HPRED.VALOR*HPRED.CANTIDAD)* ((100-HPRED.PCUBRIMIENTO)/100)  
      FROM   HPRE   
      WHERE  HPRED.NOPRESTACION = @NOPRESTACION  
      AND    HPRE.NOPRESTACION = HPRED.NOPRESTACION  
      
      IF @INDCOP = 1
      BEGIN
         UPDATE HPRED SET VALORCOPAGO = HPRED.VALOR*HPRED.CANTIDAD
         FROM   HPRE
         WHERE  HPRED.NOPRESTACION = HPRE.NOPRESTACION  
         AND    HPRE.NOPRESTACION = @NOPRESTACION                               
      END
      ELSE
      BEGIN
         -- BEGIN M3 -- HACER UNO A UNO LA DISTRIBUCION DE COPAGOS AUTORIZADOS
         -- JEDM: 25.JUL.2005 
         PRINT 'SEGUNDO LOOP'
         SELECT @DTOCOPAGO1 = @DTOCOPAGO   
         DECLARE PRESTACIOND_CURSOR CURSOR FOR  
         SELECT HPRED.VALOR*HPRED.CANTIDAD, HPRED.NOITEM
         FROM   HPRED  
         WHERE  HPRED.NOPRESTACION = @NOPRESTACION  
         OPEN PRESTACIOND_CURSOR  
         FETCH NEXT FROM PRESTACIOND_CURSOR  
         INTO @VLRHPRED, @NOITEM
         WHILE @@FETCH_STATUS = 0  
         BEGIN        
            IF @DTOCOPAGO1 >= @VLRHPRED
            BEGIN
               UPDATE HPRED SET VALORCOPAGO = @VLRHPRED
               WHERE  HPRED.NOPRESTACION    = @NOPRESTACION
               AND    HPRED.NOITEM          = @NOITEM 
                  
               SELECT @DTOCOPAGO1 = @DTOCOPAGO1 - @VLRHPRED
               
            END                        
            ELSE
            BEGIN   
               UPDATE HPRED SET VALORCOPAGO = @DTOCOPAGO1   
               WHERE  HPRED.NOPRESTACION    = @NOPRESTACION
               AND    HPRED.NOITEM          = @NOITEM 
               
               SELECT @DTOCOPAGO1 = 0
               
            END
            IF @DTOCOPAGO1 = 0
            BEGIN
               BREAK
            END               
            FETCH NEXT FROM PRESTACIOND_CURSOR  
            INTO @VLRHPRED, @NOITEM   
         END
         CLOSE PRESTACIOND_CURSOR  
         DEALLOCATE PRESTACIOND_CURSOR        
      END
      
      --UPDATE HPRED SET VALORCOPAGO = (((HPRED.VALOR*HPRED.CANTIDAD)*HPRE.VALORCOPAGO)/HPRE.VALORTOTAL)  
      --FROM   HPRE
      --WHERE  HPRED.NOPRESTACION = HPRE.NOPRESTACION  
      --AND    HPRE.NOPRESTACION = @NOPRESTACION                               
      
      -- END M3
      UPDATE HPRED SET HPRED.VALOREXCEDENTE = (HPRED.VALOR*HPRED.CANTIDAD) - HPRED.VALORCOPAGO - HPRED.VALORPCOMP  
      WHERE HPRED.NOPRESTACION = @NOPRESTACION    
      
      FETCH NEXT FROM PRESTACION_CURSOR  
      INTO @CANTIDAD, @TOTAL, @NOPRESTACION
   END  
   CLOSE PRESTACION_CURSOR  
   DEALLOCATE PRESTACION_CURSOR  
   -- BEGIN M2 SI QUEDAN POR DESCONTAR MAS COPAGOS ES DECIR EL VALOR COPAGO ES MAYOR 
   -- QUE EL VALOR SERVICIO
   -- JEDM: 07/07/2004
      
   IF @PORDESCONTAR > 0
   BEGIN 
      PRINT 'FALTA POR DESCONTAR ='+STR(@PORDESCONTAR) 
      SELECT TOP 1 @NOPRESTACION = HPRE.NOPRESTACION   
      FROM  HPRE,HPRED  
      WHERE HPRE.NOADMISION   = @NOADMISION  
      PRINT 'PRESTACION A SUBIR EL COPAGO RESTANTE='+@NOPRESTACION
      UPDATE HPRE SET VALORCOPAGO = VALORCOPAGO + @PORDESCONTAR
      WHERE  HPRE.NOPRESTACION = @NOPRESTACION  
             
      UPDATE HPRED SET VALORPCOMP = (HPRED.VALOR*HPRED.CANTIDAD)* ((100-HPRED.PCUBRIMIENTO)/100)  
      FROM   HPRE   
      WHERE  HPRED.NOPRESTACION = @NOPRESTACION  
      AND    HPRE.NOPRESTACION = HPRED.NOPRESTACION  
         
      UPDATE HPRE SET VALOREXEDENTE = (HPRE.VALORTOTAL-HPRE.VALORCOPAGO-HPRE.VALORPCOMP)  
      WHERE HPRE.NOPRESTACION = @NOPRESTACION
      
      UPDATE HPRED SET VALORCOPAGO = (((HPRED.VALOR*HPRED.CANTIDAD)*HPRE.VALORCOPAGO)/HPRE.VALORTOTAL)  
      FROM   HPRE
      WHERE  HPRED.NOPRESTACION = HPRE.NOPRESTACION  
      AND    HPRE.NOPRESTACION = @NOPRESTACION                               
      
      UPDATE HPRED SET HPRED.VALOREXCEDENTE = (HPRED.VALOR*HPRED.CANTIDAD) - HPRED.VALORCOPAGO - HPRED.VALORPCOMP  
      WHERE HPRED.NOPRESTACION = @NOPRESTACION    
      
   END   
   
   --END M2 
   
END
