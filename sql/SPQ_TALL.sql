CREATE OR ALTER PROCEDURE DBO.SPQ_TALL @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @DATOS VARCHAR(MAX), @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20), @IDSEDE VARCHAR(5), @PROCESO VARCHAR(20), 
	@IDCAP INT
DECLARE @TALLERID INT, @NOMBRETALLER NVARCHAR(255), @DESCRIPCION NVARCHAR(MAX), @INSTRUCTOR NVARCHAR(150), @FECHACREACION DATETIME, @FECHACIERRE DATETIME, @ESTADO 
	BIT

BEGIN
	SET NOCOUNT ON;

	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @TALLERID = TALLERID, @NOMBRETALLER = NOMBRETALLER, @DESCRIPCION = DESCRIPCION, @INSTRUCTOR = INSTRUCTOR, @FECHACREACION = FECHACREACION, 
				@FECHACIERRE = FECHACIERRE, @ESTADO = ESTADO, @IDCAP = IDCAP, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					TALLERID INT '$.TALLERID', NOMBRETALLER NVARCHAR(255) '$.NOMBRETALLER', DESCRIPCION NVARCHAR(MAX) '$.DESCRIPCION', INSTRUCTOR NVARCHAR(150) 
					'$.INSTRUCTOR', FECHACREACION DATETIME '$.FECHACREACION', FECHACIERRE DATETIME '$.FECHACIERRE', ESTADO BIT '$.ESTADO', PROCESO VARCHAR(20) 
					'$.PROCESO', IDCAP INT '$.IDCAP'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					BEGIN TRAN

					INSERT INTO [tall] ([IDCAP], [NOMBRETALLER], [DESCRIPCION], [INSTRUCTOR], [FECHACREACION], [FECHACIERRE], [ESTADO]
						)
					SELECT @IDCAP, @NOMBRETALLER, @DESCRIPCION, @INSTRUCTOR, @FECHACREACION, @FECHACIERRE, @ESTADO

					COMMIT TRAN
				END TRY

				BEGIN CATCH
					IF @@TRANCOUNT > 0
					BEGIN
						ROLLBACK TRAN;
					END

					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					BEGIN TRAN

					UPDATE TALL
					SET IDCAP = @IDCAP, NOMBRETALLER = @NOMBRETALLER, DESCRIPCION = @DESCRIPCION, INSTRUCTOR = @INSTRUCTOR, FECHACREACION = @FECHACREACION, 
						FECHACIERRE = @FECHACIERRE, ESTADO = @ESTADO
					WHERE TALLERID = @TALLERID

					COMMIT TRAN
				END TRY

				BEGIN CATCH
					IF @@TRANCOUNT > 0
					BEGIN
						ROLLBACK TRAN;
					END

					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		BEGIN TRY
			BEGIN TRAN

			SELECT @TALLERID = TALLERID
			FROM OPENJSON(@PARAMETROS) WITH (TALLERID INT '$.TALLERID')

			DELETE
			FROM TALL
			WHERE TALLERID = @TALLERID

			COMMIT TRAN
		END TRY

		BEGIN CATCH
			IF @@TRANCOUNT > 0
			BEGIN
				ROLLBACK TRAN;
			END

			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK

		RETURN
	END
END
