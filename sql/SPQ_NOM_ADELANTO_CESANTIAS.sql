CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_ADELANTO_CESANTIAS @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20)
DECLARE @NUMDOC VARCHAR(20), @ANO VARCHAR(4), @CNSPAGO VARCHAR(20), @VALOR DECIMAL(14, 2)
DECLARE @OBSERVACION VARCHAR(512), @CNSNACE VARCHAR(20), @CODCONCEPTO VARCHAR(20)
DECLARE @SALDO DECIMAL(14, 2), @IDSEDE VARCHAR(5), @COMPANIA VARCHAR(2), @SYS_COMPUTERNAME VARCHAR(255)
DECLARE @FECHAINI DATETIME, @FECHAFIN DATETIME, @ESTADO VARCHAR(20)

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@JSON) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
	FROM USUSU
	WHERE USUARIO = @USUARIO

	SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
	FROM UBEQ
	WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	SELECT @CODCONCEPTO = COALESCE(NULLIF(LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('NOM_ADEL_CESAN'))), ''), '')

	IF @METODO = 'SALDO'
	BEGIN
		SELECT @NUMDOC = NUMDOC, @ANO = ANO
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC', ANO VARCHAR(4) '$.ANO')

		IF COALESCE(@ANO, '') = ''
			SELECT @ANO = CAST(YEAR(GETDATE()) AS VARCHAR(4))

		SELECT 'OK' OK

		SELECT DBO.FNK_SALDO_CESAN_DISPONIBLE(@NUMDOC, @ANO) AS SALDO_DISPONIBLE, DBO.FNK_VALOR_ADELANTO_CESAN_PENDIENTE(@NUMDOC, @ANO) AS ADELANTO_PENDIENTE, 
			@ANO AS ANO

		RETURN
	END

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @NUMDOC = NUMDOC, @ANO = ANO, @CNSPAGO = CNSPAGO, @VALOR = VALOR, @OBSERVACION = OBSERVACION
			FROM OPENJSON(@PARAMETROS) WITH (
					NUMDOC VARCHAR(20) '$.NUMDOC', ANO VARCHAR(4) '$.ANO', CNSPAGO VARCHAR(20) '$.CNSPAGO', VALOR DECIMAL(14, 2) '$.VALOR', OBSERVACION VARCHAR(512) 
					'$.OBSERVACION'
					)

			IF COALESCE(@CODCONCEPTO, '') = ''
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'Configure USVGS NOM_ADEL_CESAN con el c�digo del concepto Manual de adelanto.'
			END

			IF NOT EXISTS (
					SELECT 1
					FROM NCON
					WHERE CODCONCEPTO = @CODCONCEPTO AND ESTADO = 'Activo'
					)
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'El concepto de adelanto no existe o no est� Activo: ' + COALESCE(@CODCONCEPTO, '')
			END

			IF NOT EXISTS (
					SELECT 1
					FROM NEMP
					WHERE NUMDOC = @NUMDOC AND ESTADO = 'Activo'
					)
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'El empleado no existe o no est� Activo.'
			END

			IF COALESCE(@CNSPAGO, '') = '' OR NOT EXISTS (
					SELECT 1
					FROM NPER
					WHERE CNSPAGO = @CNSPAGO AND COALESCE(CERRADO, 0) = 0
					)
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'Debe indicar un per�odo de n�mina abierto (CNSPAGO).'
			END

			IF COALESCE(@ANO, '') = ''
				SELECT @ANO = CAST(YEAR(GETDATE()) AS VARCHAR(4))

			IF COALESCE(@VALOR, 0) <= 0
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'El valor del adelanto debe ser mayor a cero.'
			END

			SELECT @SALDO = DBO.FNK_SALDO_CESAN_DISPONIBLE(@NUMDOC, @ANO)

			IF COALESCE(@VALOR, 0) > COALESCE(@SALDO, 0)
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT CONCAT ('El valor excede el saldo disponible de cesant�as (', CONVERT(VARCHAR(30), COALESCE(@SALDO, 0)), ').'
						)
			END

			IF EXISTS (
					SELECT 1
					FROM NPERC
					WHERE CNSPAGO = @CNSPAGO AND NUMDOC = @NUMDOC AND CODCONCEPTO = @CODCONCEPTO
					)
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'Ya existe un adelanto del mismo concepto en este per�odo para el empleado. Anule o utiliza otro per�odo.'
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) > 0
			BEGIN
				SELECT 'KO' OK

				SELECT ERROR
				FROM @TBLERRORES

				RETURN
			END

			BEGIN TRAN

			SET @CNSNACE = ''

			EXEC SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE, 'NACE', @CNSNACE OUTPUT

			SELECT @CNSNACE = @IDSEDE + REPLACE(SPACE(8 - LEN(@CNSNACE)) + LTRIM(RTRIM(@CNSNACE)), SPACE(1), '0')

			INSERT INTO NACE (CNSNACE, NUMDOC, ANO, FECHA, CNSPAGO, CODCONCEPTO, VALOR, VALOR_APLICADO, ESTADO, OBSERVACION, USUARIO, FECHAMOD, SYS_COMPUTERNAME
				)
			SELECT @CNSNACE, @NUMDOC, @ANO, GETDATE(), @CNSPAGO, @CODCONCEPTO, @VALOR, 0, 'EnNomina', @OBSERVACION, @USUARIO, GETDATE(), @SYS_COMPUTERNAME

			INSERT INTO NPERC (
				CNSPAGO, NUMDOC, CODCONCEPTO, DETALLE, VALOR, VALOR_EMPRESA, VALOR100P, CANTIDAD, IDTRANSPRESTAMO, NUMDOCPRESTAMO, NUMCUOTA, CODPRF, IDTERCERO, 
				LIQUIDADO
				)
			SELECT @CNSPAGO, @NUMDOC, @CODCONCEPTO, 'ADECES', @VALOR, 0, @VALOR, 0, NULL, @CNSNACE, 0, (
					SELECT TOP 1 NCOND.CODPRF
					FROM NCOND
					WHERE NCOND.CODCONCEPTO = @CODCONCEPTO
					ORDER BY NCOND.ITEM
					), (
					SELECT TERCEROID
					FROM NEMP
					WHERE NUMDOC = @NUMDOC
					), 'No'

			COMMIT TRAN

			SELECT 'OK' OK

			SELECT @CNSNACE AS CNSNACE, @SALDO - @VALOR AS SALDO_RESTANTE
		END TRY

		BEGIN CATCH
			IF @@TRANCOUNT > 0
				ROLLBACK TRAN

			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()

			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES
		END CATCH

		RETURN
	END

	IF @METODO = 'ANULAR'
	BEGIN
		BEGIN TRY
			SELECT @CNSNACE = CNSNACE
			FROM OPENJSON(@PARAMETROS) WITH (CNSNACE VARCHAR(20) '$.CNSNACE')

			SELECT @ESTADO = ESTADO, @CNSPAGO = CNSPAGO, @NUMDOC = NUMDOC, @CODCONCEPTO = CODCONCEPTO
			FROM NACE
			WHERE CNSNACE = @CNSNACE

			IF @CNSNACE IS NULL OR @ESTADO IS NULL
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'Adelanto no encontrado.'
			END
			ELSE IF @ESTADO = 'Aplicado'
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'No se puede anular: el adelanto ya fue descontado en liquidaci�n de cesant�as/retiro.'
			END
			ELSE IF @ESTADO = 'Anulado'
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'El adelanto ya est� anulado.'
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) > 0
			BEGIN
				SELECT 'KO' OK

				SELECT ERROR
				FROM @TBLERRORES

				RETURN
			END

			BEGIN TRAN

			UPDATE NACE
			SET ESTADO = 'Anulado', FECHAMOD = GETDATE(), USUARIO = @USUARIO
			WHERE CNSNACE = @CNSNACE

			IF COALESCE(@CNSPAGO, '') <> '' AND EXISTS (
					SELECT 1
					FROM NPER
					WHERE CNSPAGO = @CNSPAGO AND COALESCE(CERRADO, 0) = 0
					)
			BEGIN
				DELETE
				FROM NPERC
				WHERE CNSPAGO = @CNSPAGO AND NUMDOC = @NUMDOC AND CODCONCEPTO = @CODCONCEPTO AND NUMDOCPRESTAMO = @CNSNACE
			END

			COMMIT TRAN

			SELECT 'OK' OK
		END TRY

		BEGIN CATCH
			IF @@TRANCOUNT > 0
				ROLLBACK TRAN

			SELECT 'KO' OK

			SELECT ERROR_MESSAGE() AS ERROR
		END CATCH

		RETURN
	END

	IF @METODO = 'LISTAR'
	BEGIN
		SELECT @NUMDOC = NUMDOC, @ANO = ANO, @ESTADO = ESTADO
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC', ANO VARCHAR(4) '$.ANO', ESTADO VARCHAR(20) '$.ESTADO')

		SELECT 'OK' OK

		SELECT NACE.CNSNACE, NACE.NUMDOC, TER.RAZONSOCIAL, NACE.ANO, NACE.FECHA, NACE.CNSPAGO, NACE.CODCONCEPTO, NCON.DESCRIPCION AS DESCCONCEPTO, NACE.VALOR, 
			NACE.VALOR_APLICADO, (NACE.VALOR - COALESCE(NACE.VALOR_APLICADO, 0)) AS SALDO_ADELANTO, NACE.ESTADO, NACE.OBSERVACION, NACE.
			CNSPAGO_APLICA, NACE.FECHA_APLICA, NACE.USUARIO
		FROM NACE
		INNER JOIN NEMP ON NEMP.NUMDOC = NACE.NUMDOC
		INNER JOIN TER ON TER.IDTERCERO = NEMP.TERCEROID
		LEFT JOIN NCON ON NCON.CODCONCEPTO = NACE.CODCONCEPTO
		WHERE (COALESCE(@NUMDOC, '') = '' OR NACE.NUMDOC = @NUMDOC) AND (COALESCE(@ANO, '') = '' OR NACE.ANO = @ANO) AND (COALESCE(@ESTADO, '') = '' OR NACE.ESTADO = @ESTADO
				)
		ORDER BY NACE.FECHA DESC, NACE.CNSNACE DESC

		RETURN
	END

	IF @METODO = 'REPORTE'
	BEGIN
		SELECT @ANO = ANO, @NUMDOC = NUMDOC, @FECHAINI = FECHAINI, @FECHAFIN = FECHAFIN
		FROM OPENJSON(@PARAMETROS) WITH (ANO VARCHAR(4) '$.ANO', NUMDOC VARCHAR(20) '$.NUMDOC', FECHAINI DATETIME '$.FECHAINI', FECHAFIN DATETIME '$.FECHAFIN'
				)

		IF COALESCE(@ANO, '') = ''
			SELECT @ANO = CAST(YEAR(GETDATE()) AS VARCHAR(4))

		SELECT 'OK' OK

		SELECT NACE.CNSNACE, NACE.NUMDOC, TER.RAZONSOCIAL, NEMP.DOCIDEMPLEADO, NACE.ANO, NACE.FECHA, NACE.CNSPAGO, NACE.VALOR, NACE.VALOR_APLICADO, (NACE.VALOR - COALESCE(NACE.VALOR_APLICADO, 0)
				) AS SALDO_ADELANTO, NACE.ESTADO, NACE.CNSPAGO_APLICA, NACE.FECHA_APLICA, NACE.OBSERVACION, DBO.FNK_SALDO_CESAN_DISPONIBLE(NACE.NUMDOC, NACE.
				ANO) AS SALDO_CESAN_DISPONIBLE_ACTUAL
		FROM NACE
		INNER JOIN NEMP ON NEMP.NUMDOC = NACE.NUMDOC
		INNER JOIN TER ON TER.IDTERCERO = NEMP.TERCEROID
		WHERE NACE.ANO = @ANO AND NACE.ESTADO <> 'Anulado' AND (COALESCE(@NUMDOC, '') = '' OR NACE.NUMDOC = @NUMDOC) AND (@FECHAINI IS NULL OR NACE.FECHA >= @FECHAINI
				) AND (@FECHAFIN IS NULL OR NACE.FECHA < DATEADD(DAY, 1, @FECHAFIN))
		ORDER BY TER.RAZONSOCIAL, NACE.FECHA

		RETURN
	END

	/*
		DETALLE: explicaci�n del adelanto en pren�mina (pago) o liquidaci�n (descuento Cesan).
		PARAMETROS: NUMDOC, CNSPAGO, CONTEXTO ('PRENOMINA'|'LIQUIDACION'), CODCONCEPTO (opcional), VALOR_FILA (opcional)
	*/
	IF @METODO = 'DETALLE'
	BEGIN
		DECLARE @CONTEXTO VARCHAR(20), @VALOR_FILA DECIMAL(14, 2), @CODCESAN VARCHAR(20)
		DECLARE @VALOR_BRUTO DECIMAL(14, 2), @VALOR_ADELANTO DECIMAL(14, 2), @VALOR_NETO DECIMAL(14, 2)
		DECLARE @RAZONSOCIAL VARCHAR(200), @FECHA_REG DATETIME, @FECHA_APL DATETIME

		SELECT @NUMDOC = NUMDOC, @CNSPAGO = CNSPAGO, @CONTEXTO = CONTEXTO, @CODCONCEPTO = CODCONCEPTO, @VALOR_FILA = VALOR_FILA
		FROM OPENJSON(@PARAMETROS) WITH (
				NUMDOC VARCHAR(20) '$.NUMDOC', CNSPAGO VARCHAR(20) '$.CNSPAGO', CONTEXTO VARCHAR(20) '$.CONTEXTO', CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO', 
				VALOR_FILA DECIMAL(14, 2) '$.VALOR_FILA'
				)

		SELECT @CODCESAN = COALESCE(NULLIF(LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('NOMICODCON_CESAN'))), ''), '')

		SELECT @RAZONSOCIAL = TER.RAZONSOCIAL
		FROM NEMP
		INNER JOIN TER ON TER.IDTERCERO = NEMP.TERCEROID
		WHERE NEMP.NUMDOC = @NUMDOC

		IF COALESCE(@CONTEXTO, '') = ''
			SET @CONTEXTO = CASE 
					WHEN COALESCE(@CODCONCEPTO, '') <> '' AND @CODCONCEPTO = COALESCE(NULLIF(LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('NOM_ADEL_CESAN'))), ''), '')
						THEN 'PRENOMINA'
					ELSE 'LIQUIDACION'
					END

		IF @CONTEXTO = 'PRENOMINA'
		BEGIN
			SELECT @VALOR_ADELANTO = COALESCE(SUM(NACE.VALOR), 0), @FECHA_REG = MIN(NACE.FECHA)
			FROM NACE
			WHERE NACE.CNSPAGO = @CNSPAGO AND NACE.ESTADO <> 'Anulado' AND NACE.NUMDOC IN (
					SELECT N1.NUMDOC
					FROM NEMP N1
					WHERE EXISTS (
							SELECT 1
							FROM NEMP N2
							WHERE N1.TERCEROID = N2.TERCEROID AND N2.NUMDOC = @NUMDOC
							)
					)

			IF COALESCE(@VALOR_ADELANTO, 0) = 0 AND COALESCE(@VALOR_FILA, 0) > 0
				SET @VALOR_ADELANTO = @VALOR_FILA

			SELECT 'OK' OK

			SELECT @CONTEXTO AS CONTEXTO, @NUMDOC AS NUMDOC, @RAZONSOCIAL AS RAZONSOCIAL, @CNSPAGO AS CNSPAGO, @FECHA_REG AS FECHA_REGISTRO, CAST(NULL AS DATETIME) AS 
				FECHA_APLICA, CAST(NULL AS DECIMAL(14, 2)) AS VALOR_BRUTO, @VALOR_ADELANTO AS VALOR_ADELANTO, CAST(NULL AS DECIMAL(14, 2)) AS VALOR_NETO, 
				'Este valor corresponde al adelanto de cesant�as pagado en n�mina. Se descontar� autom�ticamente al liquidar Cesant�as (pago anual o retiro).' 
				AS EXPLICACION, 'Valor adelanto pagado = ' + CONVERT(VARCHAR(30), COALESCE(@VALOR_ADELANTO, 0)) AS FORMULA

			SELECT NACE.CNSNACE, NACE.FECHA AS FECHA_REGISTRO, NACE.CNSPAGO, NACE.VALOR, NACE.VALOR_APLICADO, (NACE.VALOR - COALESCE(NACE.VALOR_APLICADO, 0)
					) AS SALDO_ADELANTO, NACE.ESTADO, NACE.CNSPAGO_APLICA, NACE.FECHA_APLICA, NACE.OBSERVACION, NACE.ANO
			FROM NACE
			WHERE NACE.CNSPAGO = @CNSPAGO AND NACE.ESTADO <> 'Anulado' AND NACE.NUMDOC IN (
					SELECT N1.NUMDOC
					FROM NEMP N1
					WHERE EXISTS (
							SELECT 1
							FROM NEMP N2
							WHERE N1.TERCEROID = N2.TERCEROID AND N2.NUMDOC = @NUMDOC
							)
					)
			ORDER BY NACE.FECHA, NACE.CNSNACE

			RETURN
		END

		-- LIQUIDACION / Cesan descontado: bruto - adelanto = neto
		SELECT @VALOR_ADELANTO = COALESCE(SUM(NACE.VALOR_APLICADO), 0), @FECHA_REG = MIN(NACE.FECHA), @FECHA_APL = MAX(NACE.FECHA_APLICA), @ANO = MAX(NACE.ANO)
		FROM NACE
		WHERE NACE.CNSPAGO_APLICA = @CNSPAGO AND COALESCE(NACE.VALOR_APLICADO, 0) > 0 AND NACE.NUMDOC IN (
				SELECT N1.NUMDOC
				FROM NEMP N1
				WHERE EXISTS (
						SELECT 1
						FROM NEMP N2
						WHERE N1.TERCEROID = N2.TERCEROID AND N2.NUMDOC = @NUMDOC
						)
				)

		SET @VALOR_NETO = COALESCE(@VALOR_FILA, 0)

		IF @VALOR_NETO = 0 AND COALESCE(@CODCESAN, '') <> ''
		BEGIN
			SELECT @VALOR_NETO = COALESCE(SUM(NIEPED.VALOR), 0)
			FROM NIEPE
			INNER JOIN NIEPED ON NIEPED.CNSNIEPE = NIEPE.CNSNIEPE AND NIEPED.NUMDOC = NIEPE.NUMDOC
			WHERE NIEPE.CNSPAGO = @CNSPAGO AND NIEPE.NUMDOC = @NUMDOC AND NIEPED.CODCONCEPTO = @CODCESAN
		END

		SET @VALOR_BRUTO = COALESCE(@VALOR_NETO, 0) + COALESCE(@VALOR_ADELANTO, 0)

		SELECT 'OK' OK

		SELECT 'LIQUIDACION' AS CONTEXTO, @NUMDOC AS NUMDOC, @RAZONSOCIAL AS RAZONSOCIAL, @CNSPAGO AS CNSPAGO, @FECHA_REG AS FECHA_REGISTRO, @FECHA_APL AS FECHA_APLICA, 
			@VALOR_BRUTO AS VALOR_BRUTO, @VALOR_ADELANTO AS VALOR_ADELANTO, @VALOR_NETO AS VALOR_NETO, 
			'Al liquidar cesant�as se rest� el adelanto pendiente del colaborador. El valor mostrado en la fila es el neto tras el descuento.' AS 
			EXPLICACION, CONVERT(VARCHAR(30), COALESCE(@VALOR_BRUTO, 0)) + ' (bruto) - ' + CONVERT(VARCHAR(30), COALESCE(@VALOR_ADELANTO, 0)) + ' (adelanto) = ' + 
			CONVERT(VARCHAR(30), COALESCE(@VALOR_NETO, 0)) + ' (neto)' AS FORMULA

		SELECT NACE.CNSNACE, NACE.FECHA AS FECHA_REGISTRO, NACE.CNSPAGO, NACE.VALOR, NACE.VALOR_APLICADO, (NACE.VALOR - COALESCE(NACE.VALOR_APLICADO, 0)
				) AS SALDO_ADELANTO, NACE.ESTADO, NACE.CNSPAGO_APLICA, NACE.FECHA_APLICA, NACE.OBSERVACION, NACE.ANO
		FROM NACE
		WHERE NACE.CNSPAGO_APLICA = @CNSPAGO AND COALESCE(NACE.VALOR_APLICADO, 0) > 0 AND NACE.NUMDOC IN (
				SELECT N1.NUMDOC
				FROM NEMP N1
				WHERE EXISTS (
						SELECT 1
						FROM NEMP N2
						WHERE N1.TERCEROID = N2.TERCEROID AND N2.NUMDOC = @NUMDOC
						)
				)
		ORDER BY NACE.FECHA, NACE.CNSNACE

		RETURN
	END

	SELECT 'KO' OK

	SELECT 'M�todo no soportado: ' + COALESCE(@METODO, '') AS ERROR
END
