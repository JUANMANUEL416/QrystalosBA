/*
  FV81974, FV82023 y FV82359. La dispensación está en el centro
  10030102, área 4110. Ya existe la cuenta de venta del prefijo 12
  en ese centro. Se copia el centro al detalle y a la autorización
  y se reconstruye el mismo comprobante.

  No cambia cantidades ni valores.

  Uso:
    1. Deje @APLICAR = 0 y ejecute.
    2. Ponga @APLICAR = 1 y vuelva a ejecutar.
       Si ya no son estas tres, no cambia nada.
*/

SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @APLICAR bit = 0;
DECLARE @PC varchar(254) = 'CONTABILIDAD';
DECLARE @MOD varchar(20) = DBO.FNK_VALORVARIABLE('IDMODELOCONTABLE');

IF OBJECT_ID('tempdb..#Tres') IS NOT NULL DROP TABLE #Tres;

IF EXISTS (
    SELECT 1 FROM dbo.PRI
    WHERE ANO = '2026' AND MES = 10 AND COALESCE(CERRADO, 0) = 1
)
    THROW 56240, 'Octubre de 2026 está cerrado en contabilidad.', 1;

SELECT
    F.N_FACTURA,
    RTRIM(D.PREFIJO) AS PREFIJO,
    E.NROCOMPROBANTE,
    E.COMPANIA,
    E.IDSEDE,
    LEFT(E.USUARIO, 12) AS USUARIO,
    A.NOAUT,
    RTRIM(I.CCOSTO) AS CCOSTO,
    RTRIM(I.IDAREA) AS IDAREA,
    DBO.FNK_NC_CUENTA_KMCOM(@MOD, 'VENTAS', 'CR', D.PREFIJO, I.CCOSTO, 'P', '', 0) AS CUENTA
INTO #Tres
FROM dbo.FTR F
INNER JOIN dbo.FTRD D ON D.CNSFTR = F.CNSFCT
INNER JOIN dbo.AUT A ON A.NOAUT = D.NOADMISION
INNER JOIN dbo.IMOV I
    ON I.NODOCUMENTO = A.CNSMOV
   AND COALESCE(I.ESTADO, 0) = 1
   AND COALESCE(RTRIM(I.CCOSTO), '') <> ''
INNER JOIN dbo.MCPE E
    ON E.NOREFERENCIA = F.N_FACTURA
   AND E.NROCOMPROBANTE = F.NROCOMPROBANTE
   AND RTRIM(E.PROCEDENCIA) = 'FACTURA'
   AND E.ESTADO = 0
   AND COALESCE(E.ANULADO, 0) <> 1
WHERE F.N_FACTURA IN ('FV81974', 'FV82023', 'FV82359')
  AND F.PROCEDENCIA = 'CE'
  AND COALESCE(F.CONTABILIZADA, 0) = 2
  AND COALESCE(RTRIM(D.CCOSTO), '') = ''
  AND COALESCE(RTRIM(A.CCOSTO), '') = '';

SELECT N_FACTURA, PREFIJO, CCOSTO, IDAREA, CUENTA, NROCOMPROBANTE
FROM #Tres
ORDER BY N_FACTURA;

IF @APLICAR = 0
    RETURN;

IF (SELECT COUNT(*) FROM #Tres) <> 3
    OR (SELECT COUNT(DISTINCT N_FACTURA) FROM #Tres) <> 3
    THROW 56241, 'Ya no son las tres facturas sin centro. No quedó ningún cambio.', 1;

IF EXISTS (
    SELECT 1 FROM #Tres
    WHERE CCOSTO <> '10030102' OR IDAREA <> '4110' OR PREFIJO <> '12'
       OR CUENTA LIKE 'NO DEF%' OR COALESCE(CUENTA, '') = ''
       OR COALESCE(USUARIO, '') = ''
)
    THROW 56242, 'El centro o la cuenta no corresponden. No quedó ningún cambio.', 1;

BEGIN TRAN;

UPDATE D
SET CCOSTO = T.CCOSTO, AREAPRESTACION = T.IDAREA
FROM dbo.FTRD D
INNER JOIN dbo.FTR F ON F.CNSFCT = D.CNSFTR
INNER JOIN #Tres T ON T.N_FACTURA = F.N_FACTURA
WHERE COALESCE(RTRIM(D.CCOSTO), '') = '';

UPDATE U
SET CCOSTO = T.CCOSTO, IDAREA = T.IDAREA
FROM dbo.AUT U
INNER JOIN #Tres T ON T.NOAUT = U.NOAUT
WHERE COALESCE(RTRIM(U.CCOSTO), '') = '';

COMMIT TRAN;

DECLARE @NF varchar(16), @NRO varchar(20), @USU varchar(12);
DECLARE @CIA varchar(2), @SEDE varchar(5), @Msg nvarchar(240);

DECLARE c CURSOR LOCAL FAST_FORWARD FOR
    SELECT N_FACTURA, NROCOMPROBANTE, USUARIO, COMPANIA, IDSEDE
    FROM #Tres
    ORDER BY N_FACTURA;

OPEN c;
FETCH NEXT FROM c INTO @NF, @NRO, @USU, @CIA, @SEDE;

WHILE @@FETCH_STATUS = 0
BEGIN
    EXEC dbo.SPK_NC_CONTAB_FTR @NF, @CIA, @USU, @PC, @SEDE, @NRO;

    IF NOT EXISTS (
        SELECT 1 FROM dbo.FTR
        WHERE N_FACTURA = @NF AND COALESCE(CONTABILIZADA, 0) = 1
    )
    OR EXISTS (
        SELECT 1 FROM dbo.MCHE H
        WHERE H.NROCOMPROBANTE = @NRO AND H.CUENTA LIKE 'NO DEF%'
    )
    BEGIN
        CLOSE c;
        DEALLOCATE c;
        SET @Msg = N'La factura ' + @NF + N' no quedó contabilizada.';
        THROW 56243, @Msg, 1;
    END

    FETCH NEXT FROM c INTO @NF, @NRO, @USU, @CIA, @SEDE;
END

CLOSE c;
DEALLOCATE c;

SELECT 'LISTO' AS GRUPO, N_FACTURA, CCOSTO, IDAREA, CUENTA FROM #Tres ORDER BY N_FACTURA;
