CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NPER @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20)
DECLARE @PROCESO VARCHAR(20), @DATOS NVARCHAR(MAX)
DECLARE @CNSPAGO VARCHAR(20), @CNSPAGOEDITE VARCHAR(20)
DECLARE @CODNOMINA VARCHAR(2), @ANO VARCHAR(4), @MES VARCHAR(2), @CODPPAG VARCHAR(5), @TIPOLIQ VARCHAR(12)
DECLARE @GENERADO SMALLINT, @CERRADO SMALLINT, @FECHAINI DATETIME, @FECHAFIN DATETIME, @AFU VARCHAR(20), @SEDE VARCHAR(20), @CCOSTO VARCHAR(20), @CARGO VARCHAR(20), 
	@filterg NVARCHAR(MAX), @CODCARGO VARCHAR(20), @NIVEL VARCHAR(20), @GRADO VARCHAR(20)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @CNSPAGO = CNSPAGO, @CODNOMINA = CODNOMINA, @ANO = ANO, @MES = MES, @CODPPAG = CODPPAG, @TIPOLIQ = TIPOLIQ, @GENERADO = GENERADO, @CERRADO = CERRADO, 
				@FECHAINI = FECHAINI, @FECHAFIN = FECHAFIN, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					CNSPAGO VARCHAR(20) '$.CNSPAGO', CODNOMINA VARCHAR(2) '$.CODNOMINA', ANO VARCHAR(4) '$.ANO', MES VARCHAR(2) '$.MES', CODPPAG VARCHAR(5) 
					'$.CODPPAG', TIPOLIQ VARCHAR(12) '$.TIPOLIQ', GENERADO SMALLINT '$.GENERADO', CERRADO SMALLINT '$.CERRADO', FECHAINI DATETIME '$.FECHAINI', 
					FECHAFIN DATETIME '$.FECHAFIN', PROCESO VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					DECLARE @CNSNUEVO INT;

					SELECT @CNSNUEVO = COUNT(*)
					FROM NPER
					WHERE CNSPAGO LIKE CONCAT (RTRIM(@CODNOMINA), RTRIM(@ANO), RTRIM(@MES), RTRIM(@CODPPAG), '%');

					IF @CNSNUEVO > 0 AND dbo.FNK_VALORVARIABLE('REPITE_NPER_NOMINA') = 'NO'
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('YA EXISTE UN PERIDO PARA EL MES ', @MES, ' Y EL A�O ', @ANO, ' EN LA NOMINA ', @CODNOMINA
								)
					END
					ELSE
					BEGIN
						IF @CNSPAGO <> ''
						BEGIN
							SET @CNSPAGO = LEFT(@CNSPAGO, CHARINDEX('-', @CNSPAGO) - 1) + '-' + CAST(@CNSNUEVO + 1 AS VARCHAR(10));
						END

						INSERT INTO NPER (CNSPAGO, CODNOMINA, ANO, MES, CODPPAG, TIPOLIQ, GENERADO, CERRADO, FECHAINI, FECHAFIN, CONTABILIZADA, ENPPTO
							)
						SELECT @CNSPAGO, @CODNOMINA, @ANO, @MES, @CODPPAG, @TIPOLIQ, @GENERADO, @CERRADO, @FECHAINI, @FECHAFIN, 0, 0
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @DATOS = DATOS
					FROM OPENJSON(@PARAMETROS) WITH (DATOS NVARCHAR(MAX) AS JSON)

					SELECT @CNSPAGOEDITE = CNSPAGOEDITE
					FROM OPENJSON(@DATOS) WITH (CNSPAGOEDITE VARCHAR(20) '$.CNSPAGOEDITE')

					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('EL PERIODO DE PAGO ', @CNSPAGOEDITE, ' YA SE ENCUENTRA CERRADO NO ES POSIBLE REALIZAR LA OPERACION'
							)
					WHERE EXISTS (
							SELECT 1
							FROM NPER
							WHERE CNSPAGO = @CNSPAGOEDITE AND CERRADO = 1
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						IF (@CNSPAGOEDITE <> @CNSPAGO)
						BEGIN
							INSERT INTO @TBLERRORES (ERROR)
							SELECT CONCAT ('EL PERIODO DE PAGO ', @CNSPAGO, ' YA SE ENCUENTRA REGISTRADO')
							WHERE EXISTS (
									SELECT 1
									FROM NPER
									WHERE CNSPAGO = @CNSPAGO
									)

							IF (
									SELECT COUNT(*)
									FROM @TBLERRORES
									) <= 0
							BEGIN
								UPDATE NPER
								SET CNSPAGO = @CNSPAGO, CODNOMINA = @CODNOMINA, ANO = @ANO, MES = @MES, CODPPAG = @CODPPAG, TIPOLIQ = @TIPOLIQ, FECHAINI = @FECHAINI, 
									FECHAFIN = @FECHAFIN
								WHERE CNSPAGO = @CNSPAGOEDITE
							END
						END
						ELSE
						BEGIN
							UPDATE NPER
							SET CODNOMINA = @CODNOMINA, ANO = @ANO, MES = @MES, CODPPAG = @CODPPAG, TIPOLIQ = @TIPOLIQ, FECHAINI = @FECHAINI, FECHAFIN = @FECHAFIN
							WHERE CNSPAGO = @CNSPAGO
						END
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GET_NPER'
	BEGIN
		SELECT @CNSPAGO = CNSPAGO
		FROM OPENJSON(@PARAMETROS) WITH (CNSPAGO VARCHAR(20) '$.CNSPAGO')

		SELECT 'OK' OK

		SELECT NPER.CNSPAGO, NPER.CODNOMINA, NPER.ANO, NPER.MES, NPER.CODPPAG, NPER.FECHAINI, NPER.FECHAFIN, NOMI.DESCRIPCION AS DESCRINOMINA, NPPAG.DESCRIPCION 
			AS DESCRIPAGO, NPLT.DESCRIPCION AS PLANTILLA, NPLT.IDPLANTILLA, NPLT.ESTADO AS ESTADOPLANTILLA, NPER.TOTAL_INGRESOS, NPER.TOTAL_EGRESOS, NPER.
			TOTAL_APORTES, NPER.TOTAL_PARAFISCALES, NPER.TOTAL_NOMINA, NPER.CERRADO
		FROM NPER
		INNER JOIN NOMI ON NOMI.CODNOMINA = NPER.CODNOMINA
		INNER JOIN NPPAG ON NPPAG.CODPPAG = NPER.CODPPAG
		INNER JOIN NPLT ON NPLT.IDPLANTILLA = NOMI.IDPLANTILLA
		WHERE NPER.CNSPAGO = @CNSPAGO

		RETURN
	END

	IF @METODO = 'GET_NIEPE_REPORT'
	BEGIN
		SELECT @CNSPAGO = CNSPAGO, @SEDE = SEDE, @CCOSTO = CCOSTO, @AFU = AFU, @CARGO = CARGO, @filterg = filterg, @CODCARGO = COALESCE(CODCARGO, ''), @NIVEL = COALESCE(NIVEL, 
				''), @GRADO = COALESCE(GRADO, '')
		FROM OPENJSON(@PARAMETROS) WITH (
				CNSPAGO VARCHAR(20) '$.CNSPAGO', SEDE VARCHAR(20) '$.SEDE', CCOSTO VARCHAR(20) '$.CCOSTO', AFU VARCHAR(20) '$.AFU', CARGO VARCHAR(20) '$.CARGO', 
				filterg VARCHAR(20) '$.filter', CODCARGO VARCHAR(20) '$.CODCARGO', NIVEL VARCHAR(20) '$.NIVEL', GRADO VARCHAR(20) '$.GRADO'
				)

		SELECT 'OK' OK

		SELECT NIEPE.CNSPAGO, NIEPE.CNSNIEPE, TER.NIT, NIEPE.NOMBRE_EMPLEADO, NIEPE.VALOR_NETO, NIEPE.VALOR_INGRESOS, NIEPE.VALOR_EGRESOS, NIEPE.VALOR_APORTES
			, NIEPE.TOTAL_NOMINA, NIEPE.NOMBRE_AREA, NIEPE.CCOSTO, NIEPE.NOMBRE_CCOSTO, NIEPE.NOMBRE_CARGO, NIEPE.GRADO, NIEPE.NIVEL, NIEPE.DETALLE_CARGO, 
			NIEPE.NUMDOC, NIEPE.NOMBRE_PERIODO, @CARGO, (
				SELECT TOP 1 VALOR100P
				FROM NIEPED
				WHERE NIEPED.CNSNIEPE = NIEPE.CNSNIEPE AND NIEPED.NUMDOC = NIEPE.NUMDOC AND NIEPED.SEIMPRIME = 'Si'
				) AS SALARIO, DEVENGADOS = (
				SELECT NOMBRE_CONCEPTO, CANTIDAD, VALOR, RAZONSOCIAL_PRF
				FROM NIEPED
				WHERE NIEPED.CNSNIEPE = NIEPE.CNSNIEPE AND NIEPED.NUMDOC = NIEPE.NUMDOC AND NIEPED.SEIMPRIME = 'Si' AND TIPO = 'Ingreso'
				FOR JSON PATH
				), DEDUCIDOS = (
				SELECT NOMBRE_CONCEPTO, CANTIDAD, VALOR, RAZONSOCIAL_PRF
				FROM NIEPED
				WHERE NIEPED.CNSNIEPE = NIEPE.CNSNIEPE AND NIEPED.NUMDOC = NIEPE.NUMDOC AND NIEPED.SEIMPRIME = 'Si' AND TIPO = 'Egreso'
				FOR JSON PATH
				)
		FROM [dbo].[NIEPE]
		INNER JOIN NEMP ON NEMP.NUMDOC = NIEPE.NUMDOC
		LEFT JOIN TER ON NEMP.TERCEROID = TER.IDTERCERO
		WHERE (
				TER.NIT LIKE '%%' + @filterg + '%%' OR NIEPE.NOMBRE_EMPLEADO LIKE '%%' + @filterg + '%%' OR NIEPE.NOMBRE_CCOSTO LIKE '%%' + @filterg + '%%' OR NIEPE.
				NOMBRE_CARGO LIKE '%%' + @filterg + '%%' OR NIEPE.NOMBRE_AREA LIKE '%%' + @filterg + '%%'
				) AND 1 = 1 AND NIEPE.CNSPAGO = @CNSPAGO AND COALESCE(NIEPE.IDAREA, '') LIKE (
				CASE 
					WHEN @AFU = '0'
						THEN '%%%%'
					ELSE '%%' + @AFU + '%%'
					END
				) AND COALESCE(NIEPE.CCOSTO, '') LIKE (
				CASE 
					WHEN @CCOSTO = '0'
						THEN '%%%%'
					ELSE '%%' + @CCOSTO + '%%'
					END
				) AND COALESCE(NIEPE.CODCARGO, '') LIKE (
				CASE 
					WHEN @CARGO = '0'
						THEN '%%%%'
					ELSE '%%' + @CODCARGO + '%%'
					END
				) AND COALESCE(NIEPE.NIVEL, '') LIKE (
				CASE 
					WHEN @CARGO = '0'
						THEN '%%%%'
					ELSE '%%' + @NIVEL + '%%'
					END
				) AND COALESCE(NIEPE.GRADO, '') LIKE (
				CASE 
					WHEN @CARGO = '0'
						THEN '%%%%'
					ELSE '%%' + @GRADO + '%%'
					END
				)
		ORDER BY NIEPE.NUMDOC

		RETURN
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @CNSPAGO = CNSPAGO
		FROM OPENJSON(@PARAMETROS) WITH (CNSPAGO VARCHAR(20) '$.CNSPAGO')

		BEGIN TRY
			INSERT INTO @TBLERRORES (ERROR)
			SELECT CONCAT ('EL PERIODO DE PAGO ', @CNSPAGO, ' CUENTA CON NOVEDADES EN PRENOMINA')
			WHERE EXISTS (
					SELECT 1
					FROM NEDIA
					WHERE CNSPAGO = @CNSPAGO
					)

			INSERT INTO @TBLERRORES (ERROR)
			SELECT CONCAT ('EL PERIODO DE PAGO ', @CNSPAGO, ' YA CUENTA CON UNA GENERACION DE PRENOMINA')
			WHERE EXISTS (
					SELECT 1
					FROM NIEPE
					WHERE CNSPAGO = @CNSPAGO
					)

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				DELETE
				FROM NPER
				WHERE CNSPAGO = @CNSPAGO
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GET_NPER_ACTIVO'
	BEGIN
		SELECT 'OK' OK

		SELECT COALESCE(p.ANO, YEAR(GETDATE())) AS ANO, COALESCE(p.MES, MONTH(GETDATE())) AS MES
		FROM (
			SELECT 1 AS X
			) t
		OUTER APPLY (
			SELECT TOP 1 ANO, MES
			FROM NPER
			WHERE CERRADO = 0
			ORDER BY FECHAINI ASC
			) p;

		RETURN
	END
END
