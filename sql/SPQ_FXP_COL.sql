CREATE OR ALTER PROCEDURE DBO.SPQ_FXP_COL @JSON NVARCHAR(MAX)
WITH ENCRYPTION
AS
SET DATEFORMAT dmy
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @PARAMETROS NVARCHAR(MAX)
DECLARE @MODELO VARCHAR(100)
DECLARE @METODO VARCHAR(100)
DECLARE @USUARIO VARCHAR(12)
DECLARE @COMPANIA VARCHAR(2)
DECLARE @IDSEDE VARCHAR(5)
DECLARE @N_PRESUP VARCHAR(16)
DECLARE @ITEM INT
DECLARE @NOPRESTACION VARCHAR(20)
DECLARE @NOITEM INT
DECLARE @IDTERCERO VARCHAR(20)
DECLARE @IDPROVEEDOR VARCHAR(20)
DECLARE @F_INICIAL DATE
DECLARE @F_FINAL DATE
DECLARE @ESTADO VARCHAR(1)
DECLARE @NOREFERENCIA VARCHAR(20)
DECLARE @QUERY NVARCHAR(MAX)
BEGIN
	SELECT *
	INTO #JSON
	FROM OPENJSON(@JSON) WITH (
		MODELO VARCHAR(100) '$.MODELO',
		METODO VARCHAR(100) '$.METODO',
		USUARIO VARCHAR(12) '$.USUARIO',
		PARAMETROS NVARCHAR(MAX) AS JSON
	)

	SELECT @MODELO = MODELO,
		@METODO = METODO,
		@PARAMETROS = PARAMETROS,
		@USUARIO = USUARIO
	FROM #JSON

	IF @METODO = 'ESTADO_FXP'
	BEGIN
		SELECT @N_PRESUP = N_PRESUP,
			@ITEM = ITEM,
			@NOPRESTACION = NOPRESTACION,
			@NOITEM = NOITEM
		FROM OPENJSON(@PARAMETROS) WITH (
			N_PRESUP VARCHAR(16) '$.N_PRESUP',
			ITEM INT '$.ITEM',
			NOPRESTACION VARCHAR(20) '$.NOPRESTACION',
			NOITEM INT '$.NOITEM'
		)

		IF COALESCE(@N_PRESUP, '') = ''
			INSERT INTO @TBLERRORES (ERROR)
			SELECT N'Falta el consecutivo CXP (N_PRESUP).'

		IF @ITEM IS NULL
			INSERT INTO @TBLERRORES (ERROR)
			SELECT N'Falta el ?tem del detalle.'

		IF COALESCE(@NOPRESTACION, '') = ''
			INSERT INTO @TBLERRORES (ERROR)
			SELECT N'Falta el n?mero de prestaci?n.'

		IF @NOITEM IS NULL
			INSERT INTO @TBLERRORES (ERROR)
			SELECT N'Falta el n?mero de ?tem de prestaci?n.'

		IF EXISTS (SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' AS OK
		SELECT ESTADO, DOCUMENTO, MENSAJE
		FROM DBO.FNK_ESTADO_FXP(@N_PRESUP, @ITEM, @NOPRESTACION, @NOITEM)
		RETURN
	END

	IF @METODO = 'CAMBIAR_TERFXP'
	BEGIN
		SELECT @N_PRESUP = N_PRESUP,
			@ITEM = ITEM,
			@NOPRESTACION = NOPRESTACION,
			@NOITEM = NOITEM,
			@IDTERCERO = IDTERCERO,
			@COMPANIA = COMPANIA,
			@IDSEDE = IDSEDE
		FROM OPENJSON(@PARAMETROS) WITH (
			N_PRESUP VARCHAR(16) '$.N_PRESUP',
			ITEM INT '$.ITEM',
			NOPRESTACION VARCHAR(20) '$.NOPRESTACION',
			NOITEM INT '$.NOITEM',
			IDTERCERO VARCHAR(20) '$.IDTERCERO',
			COMPANIA VARCHAR(2) '$.COMPANIA',
			IDSEDE VARCHAR(5) '$.IDSEDE'
		)

		IF COALESCE(@N_PRESUP, '') = ''
			INSERT INTO @TBLERRORES (ERROR)
			SELECT N'Falta el consecutivo CXP (N_PRESUP).'

		IF @ITEM IS NULL
			INSERT INTO @TBLERRORES (ERROR)
			SELECT N'Falta el ?tem del detalle.'

		IF COALESCE(@NOPRESTACION, '') = ''
			INSERT INTO @TBLERRORES (ERROR)
			SELECT N'Falta el n?mero de prestaci?n.'

		IF @NOITEM IS NULL
			INSERT INTO @TBLERRORES (ERROR)
			SELECT N'Falta el n?mero de ?tem de prestaci?n.'

		IF COALESCE(@IDTERCERO, '') = ''
			INSERT INTO @TBLERRORES (ERROR)
			SELECT N'Falta el tercero destino.'

		IF COALESCE(@COMPANIA, '') = ''
			INSERT INTO @TBLERRORES (ERROR)
			SELECT N'Falta la compa??a.'

		IF COALESCE(@IDSEDE, '') = ''
			INSERT INTO @TBLERRORES (ERROR)
			SELECT N'Falta la sede.'

		IF EXISTS (SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		IF EXISTS (
			SELECT 1
			FROM DBO.FNK_ESTADO_FXP(@N_PRESUP, @ITEM, @NOPRESTACION, @NOITEM)
			WHERE ESTADO = 1
		)
		BEGIN
			SELECT 'KO' AS OK
			SELECT MENSAJE AS ERROR
			FROM DBO.FNK_ESTADO_FXP(@N_PRESUP, @ITEM, @NOPRESTACION, @NOITEM)
			RETURN
		END

		BEGIN TRY
			EXEC DBO.SPK_CAMBIAR_TERFXP
				@N_PRESUP = @N_PRESUP,
				@ITEM = @ITEM,
				@NOPRESTACION = @NOPRESTACION,
				@NOITEM = @NOITEM,
				@IDTERCERO = @IDTERCERO,
				@COMPANIA = @COMPANIA,
				@SEDE = @IDSEDE,
				@USUARIO = @USUARIO

			SELECT 'OK' AS OK,
				N'Cambio de tercero realizado correctamente.' AS MENSAJE
		END TRY
		BEGIN CATCH
			SELECT 'KO' AS OK,
				ERROR_MESSAGE() AS ERROR
		END CATCH

		RETURN
	END

	IF @METODO IN ('IMPRIMIR_CXP', 'IMPRIMIR_CUENTA_COBRO')
	BEGIN
		SELECT @IDPROVEEDOR = IDPROVEEDOR,
			@F_INICIAL = TRY_CONVERT(DATE, F_INICIAL, 23),
			@F_FINAL = TRY_CONVERT(DATE, F_FINAL, 23),
			@ESTADO = ESTADO,
			@N_PRESUP = N_PRESUP,
			@NOREFERENCIA = NOREFERENCIA,
			@COMPANIA = COMPANIA
		FROM OPENJSON(@PARAMETROS) WITH (
			IDPROVEEDOR VARCHAR(20) '$.IDPROVEEDOR',
			F_INICIAL VARCHAR(10) '$.F_INICIAL',
			F_FINAL VARCHAR(10) '$.F_FINAL',
			ESTADO VARCHAR(1) '$.ESTADO',
			N_PRESUP VARCHAR(16) '$.N_PRESUP',
			NOREFERENCIA VARCHAR(20) '$.NOREFERENCIA',
			COMPANIA VARCHAR(2) '$.COMPANIA'
		)

		IF COALESCE(@IDPROVEEDOR, '') = ''
			INSERT INTO @TBLERRORES (ERROR)
			SELECT N'Debe indicar el proveedor para imprimir.'

		IF @F_INICIAL IS NULL OR @F_FINAL IS NULL
			INSERT INTO @TBLERRORES (ERROR)
			SELECT N'Debe indicar fecha inicial y final.'

		IF EXISTS (SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SET @QUERY = N'
		SELECT
			FXP.N_PRESUP,
			FXP.NOREFERENCIA,
			FXP.PROCEDENCIA,
			FXP.F_FACTURAREF,
			FXP.IDTERCERO,
			TER_PROV.NIT AS NIT_PROVEEDOR,
			TER_PROV.RAZONSOCIAL AS RAZONSOCIAL_PROVEEDOR,
			FXPD.ITEM,
			FXPD.IDSERVICIO,
			SER.DESCSERVICIO,
			FXPD.CANTIDAD,
			FXPD.VR_TOTAL,
			FXPD.NOPRESTACION,
			FXPD.N_FACTURA,
			FXPD.NOITEM,
			CASE FXP.PROCEDENCIA
				WHEN ''SALUD'' THEN (
					SELECT TOP 1 AFI.DOCIDAFILIADO
					FROM HADM
					INNER JOIN AFI ON HADM.IDAFILIADO = AFI.IDAFILIADO
					WHERE HADM.NOADMISION = FXP.NOREFERENCIA
				)
				WHEN ''CE'' THEN (
					SELECT TOP 1 AFI.DOCIDAFILIADO
					FROM AUT
					INNER JOIN AFI ON AUT.IDAFILIADO = AFI.IDAFILIADO
					WHERE AUT.IDAUT = FXP.NOREFERENCIA
				)
				WHEN ''CI'' THEN (
					SELECT TOP 1 AFI.DOCIDAFILIADO
					FROM CIT
					INNER JOIN AFI ON CIT.IDAFILIADO = AFI.IDAFILIADO
					WHERE CIT.CONSECUTIVO = FXP.NOREFERENCIA
				)
				WHEN ''PYP'' THEN N''PyP''
			END AS DOCIDAFILIADO,
			CASE FXP.PROCEDENCIA
				WHEN ''SALUD'' THEN (
					SELECT TOP 1 LTRIM(RTRIM(
						COALESCE(AFI.PAPELLIDO, '''') + '' '' +
						COALESCE(AFI.SAPELLIDO, '''') + '' '' +
						COALESCE(AFI.PNOMBRE, '''') + '' '' +
						COALESCE(AFI.SNOMBRE, '''')))
					FROM HADM
					INNER JOIN AFI ON HADM.IDAFILIADO = AFI.IDAFILIADO
					WHERE HADM.NOADMISION = FXP.NOREFERENCIA
				)
				WHEN ''CE'' THEN (
					SELECT TOP 1 LTRIM(RTRIM(
						COALESCE(AFI.PAPELLIDO, '''') + '' '' +
						COALESCE(AFI.SAPELLIDO, '''') + '' '' +
						COALESCE(AFI.PNOMBRE, '''') + '' '' +
						COALESCE(AFI.SNOMBRE, '''')))
					FROM AUT
					INNER JOIN AFI ON AUT.IDAFILIADO = AFI.IDAFILIADO
					WHERE AUT.IDAUT = FXP.NOREFERENCIA
				)
				WHEN ''CI'' THEN (
					SELECT TOP 1 LTRIM(RTRIM(
						COALESCE(AFI.PAPELLIDO, '''') + '' '' +
						COALESCE(AFI.SAPELLIDO, '''') + '' '' +
						COALESCE(AFI.PNOMBRE, '''') + '' '' +
						COALESCE(AFI.SNOMBRE, '''')))
					FROM CIT
					INNER JOIN AFI ON CIT.IDAFILIADO = AFI.IDAFILIADO
					WHERE CIT.CONSECUTIVO = FXP.NOREFERENCIA
				)
				WHEN ''PYP'' THEN N''Pyp''
			END AS NOMBREAFILIADO,
			CASE FXP.PROCEDENCIA
				WHEN ''SALUD'' THEN (
					SELECT TOP 1 HADM.IDTERCERO
					FROM HADM
					WHERE HADM.NOADMISION = FXP.NOREFERENCIA
				)
				WHEN ''CE'' THEN (
					SELECT TOP 1 AUT.IDCONTRATANTE
					FROM AUT
					WHERE AUT.IDAUT = FXP.NOREFERENCIA
				)
				WHEN ''CI'' THEN (
					SELECT TOP 1 CIT.IDCONTRATANTE
					FROM CIT
					WHERE CIT.CONSECUTIVO = FXP.NOREFERENCIA
				)
				WHEN ''PYP'' THEN N''PyP''
			END AS IDEMPRESA,
			CASE FXP.PROCEDENCIA
				WHEN ''SALUD'' THEN (
					SELECT TOP 1 HPRE.FECHA
					FROM HPRE
					WHERE HPRE.NOPRESTACION = FXPD.NOPRESTACION
				)
				WHEN ''CE'' THEN (
					SELECT TOP 1 AUT.FECHA
					FROM AUT
					WHERE AUT.IDAUT = FXP.NOREFERENCIA
				)
				WHEN ''CI'' THEN (
					SELECT TOP 1 CIT.FECHA
					FROM CIT
					WHERE CIT.CONSECUTIVO = FXP.NOREFERENCIA
				)
				WHEN ''PYP'' THEN FXP.F_FACTURAREF
			END AS FECHASERVICIO,
			CAST(NULL AS VARCHAR(121)) AS NOMBREEMPRESA,
			CAST(NULL AS VARCHAR(20)) AS NIT_EMPRESA
		INTO #RPT_FXP
		FROM FXP
		INNER JOIN FXPD ON FXP.N_PRESUP = FXPD.N_PRESUP AND FXP.IDTERCERO = FXPD.IDTERCERO
		INNER JOIN SER ON FXPD.IDSERVICIO = SER.IDSERVICIO
		INNER JOIN TER TER_PROV ON FXP.IDTERCERO = TER_PROV.IDTERCERO
		WHERE FXP.IDTERCERO = @IDPROVEEDOR
			AND FXP.F_FACTURAREF >= @F_INICIAL
			AND FXP.F_FACTURAREF <= @F_FINAL'

		IF COALESCE(@ESTADO, 'T') <> 'T'
		BEGIN
			IF @ESTADO = 'P'
				SET @QUERY = @QUERY + N' AND FXP.ESTADO IN (''P'',''S'')'
			ELSE
				SET @QUERY = @QUERY + N' AND FXP.ESTADO = @ESTADO'
		END

		IF COALESCE(@N_PRESUP, '') <> ''
			SET @QUERY = @QUERY + N' AND FXP.N_PRESUP LIKE ''%'' + @N_PRESUP + ''%'''

		IF COALESCE(@NOREFERENCIA, '') <> ''
			SET @QUERY = @QUERY + N' AND FXP.NOREFERENCIA LIKE ''%'' + @NOREFERENCIA + ''%'''

		SET @QUERY = @QUERY + N'
		ORDER BY TER_PROV.RAZONSOCIAL, FXP.NOREFERENCIA, FXPD.ITEM;

		UPDATE R
		SET R.NOMBREEMPRESA = TER_EMP.RAZONSOCIAL,
			R.NIT_EMPRESA = TER_EMP.NIT
		FROM #RPT_FXP R
		LEFT JOIN TER TER_EMP ON R.IDEMPRESA = TER_EMP.IDTERCERO;

		SELECT ''OK'' AS OK;

		SELECT TOP 1
			TER_INST.RAZONSOCIAL AS RAZONSOCIAL_DPR,
			COALESCE(SED.NIT, TER_INST.NIT) AS NIT_DPR,
			TER_FILTRO.TIPO_ID AS TIPO_ID_PROVEEDOR,
			TER_FILTRO.NIT AS NIT_PROVEEDOR,
			TER_FILTRO.RAZONSOCIAL AS RAZONSOCIAL_PROVEEDOR,
			@F_INICIAL AS F_INICIAL,
			@F_FINAL AS F_FINAL,
			(SELECT SUM(COALESCE(VR_TOTAL, 0)) FROM #RPT_FXP) AS TOTAL_GENERAL
		FROM TER TER_FILTRO
		INNER JOIN TER TER_INST
			ON TER_INST.IDTERCERO = DBO.FNK_VALORVARIABLE(''IDTERCEROINSTALADO'')
		LEFT JOIN SED ON SED.NIT = TER_INST.NIT
		WHERE TER_FILTRO.IDTERCERO = @IDPROVEEDOR;

		SELECT
			N_PRESUP,
			NOREFERENCIA,
			PROCEDENCIA,
			F_FACTURAREF,
			IDTERCERO,
			NIT_PROVEEDOR,
			RAZONSOCIAL_PROVEEDOR,
			ITEM,
			IDSERVICIO,
			DESCSERVICIO,
			CANTIDAD,
			VR_TOTAL,
			NOPRESTACION,
			N_FACTURA,
			NOITEM,
			DOCIDAFILIADO,
			NOMBREAFILIADO,
			NIT_EMPRESA,
			FECHASERVICIO,
			NOMBREEMPRESA
		FROM #RPT_FXP
		ORDER BY RAZONSOCIAL_PROVEEDOR, NOREFERENCIA, ITEM;'

		EXEC SP_EXECUTESQL @QUERY,
			N'@IDPROVEEDOR VARCHAR(20), @F_INICIAL DATE, @F_FINAL DATE, @ESTADO VARCHAR(1), @N_PRESUP VARCHAR(16), @NOREFERENCIA VARCHAR(20), @COMPANIA VARCHAR(2)',
			@IDPROVEEDOR = @IDPROVEEDOR,
			@F_INICIAL = @F_INICIAL,
			@F_FINAL = @F_FINAL,
			@ESTADO = @ESTADO,
			@N_PRESUP = @N_PRESUP,
			@NOREFERENCIA = @NOREFERENCIA,
			@COMPANIA = @COMPANIA

		RETURN
	END

	SELECT 'KO' AS OK,
		N'M?todo no implementado en SPQ_FXP_COL.' AS ERROR
END
