CREATE OR ALTER PROCEDURE DBO.SPQ_PXS @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20), @PROCESO VARCHAR(20);
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX));
-- Variables de datos
DECLARE @IDSEDE VARCHAR(5), @IDPLAN VARCHAR(6), @PREFIJO VARCHAR(6), @IDTERCERO VARCHAR(20)
DECLARE @IDADMINISTRADORA VARCHAR(20), @EXCOBROPC BIT, @LIQUIDARPC BIT, @COBRARPC BIT
DECLARE @TIPOTARIFA VARCHAR(6), @IDTARIFA VARCHAR(5), @FACTOR DECIMAL(10, 6)
DECLARE @PRIORIDAD SMALLINT, @UMBRAL DECIMAL(14, 2)
-- Claves originales para edici�n desde prefijos
DECLARE @IDSEDEEDITE VARCHAR(5), @PREFIJOEDITE VARCHAR(6), @IDPLANEDITE VARCHAR(6)
DECLARE @IDTERCEROEDITE VARCHAR(20), @IDADMINISTRADORAEDITE VARCHAR(20);

BEGIN
	SET NOCOUNT ON;

	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @IDSEDE = IDSEDE, @IDPLAN = IDPLAN, @PREFIJO = PREFIJO, @IDTERCERO = IDTERCERO, @EXCOBROPC = EXCOBROPC, @IDADMINISTRADORA = IDADMINISTRADORA, 
				@LIQUIDARPC = LIQUIDARPC, @COBRARPC = COBRARPC, @TIPOTARIFA = TIPOTARIFA, @IDTARIFA = IDTARIFA, @FACTOR = FACTOR, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					IDSEDE VARCHAR(5) '$.IDSEDE', IDPLAN VARCHAR(6) '$.IDPLAN', PREFIJO VARCHAR(6) '$.PREFIJO', IDTERCERO VARCHAR(20) '$.IDTERCERO', EXCOBROPC BIT 
					'$.EXCOBROPC', IDADMINISTRADORA VARCHAR(20) '$.IDADMINISTRADORA', LIQUIDARPC BIT '$.LIQUIDARPC', COBRARPC BIT '$.COBRARPC', TIPOTARIFA 
					VARCHAR(6) '$.TIPOTARIFA', IDTARIFA VARCHAR(5) '$.IDTARIFA', FACTOR DECIMAL(10, 6) '$.FACTOR', PROCESO VARCHAR(20) '$.PROCESO'
					)

			BEGIN TRANSACTION;

			IF @PROCESO = 'INSERTAR' OR (@PROCESO = 'EDITAR' AND (@IDSEDEEDITE <> @IDSEDE OR @PREFIJOEDITE <> @PREFIJO))
			BEGIN
				IF EXISTS (
						SELECT 1
						FROM PXS
						WHERE IDSEDE = @IDSEDE AND IDPLAN = @IDPLAN AND PREFIJO = @PREFIJO AND IDTERCERO = @IDTERCERO AND IDADMINISTRADORA = @IDADMINISTRADORA
						)
				BEGIN
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'EL PREFIJO YA SE ENCUENTRA REGISTRADO PARA ESTA CONFIGURACI�N.';
				END
			END

			IF NOT EXISTS (
					SELECT 1
					FROM @TBLERRORES
					)
			BEGIN
				IF @PROCESO = 'INSERTAR'
				BEGIN
					INSERT INTO [PXS] (IDSEDE, IDPLAN, PREFIJO, PRIORIDAD, IDTERCERO, UMBRAL, EXCOBROPC, IDADMINISTRADORA, LIQUIDARPC, COBRARPC, TIPOTARIFA, IDTARIFA, FACTOR
						)
					VALUES (@IDSEDE, @IDPLAN, @PREFIJO, 0, @IDTERCERO, 0, @EXCOBROPC, @IDADMINISTRADORA, @LIQUIDARPC, @COBRARPC, @TIPOTARIFA, @IDTARIFA, @FACTOR
						);
				END
				ELSE IF @PROCESO = 'EDITAR'
				BEGIN
					UPDATE PXS
					SET IDSEDE = @IDSEDE, PREFIJO = @PREFIJO, TIPOTARIFA = @TIPOTARIFA, LIQUIDARPC = @LIQUIDARPC, COBRARPC = @COBRARPC, EXCOBROPC = @EXCOBROPC, FACTOR = 
						@FACTOR, IDTARIFA = @IDTARIFA
					WHERE IDTERCERO = @IDTERCERO AND IDADMINISTRADORA = @IDADMINISTRADORA AND IDPLAN = @IDPLAN AND IDSEDE = ISNULL(@IDSEDEEDITE, @IDSEDE) AND PREFIJO = 
						ISNULL(@PREFIJOEDITE, @PREFIJO);
				END
			END

			COMMIT TRANSACTION;
		END TRY

		BEGIN CATCH
			IF @@TRANCOUNT > 0
				ROLLBACK TRANSACTION;

			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();
		END CATCH
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		BEGIN TRY
			SELECT @IDTERCERO = IDTERCERO, @IDADMINISTRADORA = IDADMINISTRADORA, @IDPLAN = IDPLAN, @IDTARIFA = IDTARIFA, @IDSEDE = IDSEDE, @PREFIJO = PREFIJO
			FROM OPENJSON(@PARAMETROS) WITH (
					IDTERCERO VARCHAR(20) '$.IDTERCERO', IDADMINISTRADORA VARCHAR(20) '$.IDADMINISTRADORA', IDPLAN VARCHAR(6) '$.IDPLAN', IDTARIFA VARCHAR(5) 
					'$.IDTARIFA', IDSEDE VARCHAR(5) '$.IDSEDE', PREFIJO VARCHAR(6) '$.PREFIJO'
					);

			DELETE
			FROM PXS
			WHERE IDTERCERO = @IDTERCERO AND IDADMINISTRADORA = @IDADMINISTRADORA AND IDPLAN = @IDPLAN AND IDTARIFA = @IDTARIFA AND IDSEDE = @IDSEDE AND PREFIJO = @PREFIJO;
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();
		END CATCH
	END

	-- CRUD desde prefijos (PRE): persiste PRIORIDAD y UMBRAL; no exige IDTARIFA
	IF @METODO IN ('GUARDAR_PRE', 'ELIMINAR_PRE')
	BEGIN
		BEGIN TRY
			SELECT @IDSEDE = NULLIF(LTRIM(RTRIM(IDSEDE)), ''), @IDPLAN = NULLIF(LTRIM(RTRIM(IDPLAN)), ''), @PREFIJO = NULLIF(LTRIM(RTRIM(PREFIJO)), ''), 
				@IDTERCERO = NULLIF(LTRIM(RTRIM(IDTERCERO)), ''), @IDADMINISTRADORA = NULLIF(LTRIM(RTRIM(IDADMINISTRADORA)), ''), @EXCOBROPC = COALESCE(EXCOBROPC, 0), 
				@LIQUIDARPC = COALESCE(LIQUIDARPC, 0), @COBRARPC = COALESCE(COBRARPC, 0), @PRIORIDAD = COALESCE(PRIORIDAD, 0), @UMBRAL = COALESCE(UMBRAL, 0), @PROCESO = 
				PROCESO, @IDSEDEEDITE = NULLIF(LTRIM(RTRIM(IDSEDEEDITE)), ''), @PREFIJOEDITE = NULLIF(LTRIM(RTRIM(PREFIJOEDITE)), ''), @IDPLANEDITE = NULLIF(LTRIM(RTRIM
				(IDPLANEDITE)), ''), @IDTERCEROEDITE = NULLIF(LTRIM(RTRIM(IDTERCEROEDITE)), ''), @IDADMINISTRADORAEDITE = NULLIF(LTRIM(RTRIM(IDADMINISTRADORAEDITE)), '')
			FROM OPENJSON(@PARAMETROS) WITH (
					IDSEDE VARCHAR(5) '$.IDSEDE', IDPLAN VARCHAR(6) '$.IDPLAN', PREFIJO VARCHAR(6) '$.PREFIJO', IDTERCERO VARCHAR(20) '$.IDTERCERO', IDADMINISTRADORA 
					VARCHAR(20) '$.IDADMINISTRADORA', EXCOBROPC BIT '$.EXCOBROPC', LIQUIDARPC BIT '$.LIQUIDARPC', COBRARPC BIT '$.COBRARPC', PRIORIDAD SMALLINT 
					'$.PRIORIDAD', UMBRAL DECIMAL(14, 2) '$.UMBRAL', PROCESO VARCHAR(20) '$.PROCESO', IDSEDEEDITE VARCHAR(5) '$.IDSEDEEDITE', PREFIJOEDITE VARCHAR(6) 
					'$.PREFIJOEDITE', IDPLANEDITE VARCHAR(6) '$.IDPLANEDITE', IDTERCEROEDITE VARCHAR(20) '$.IDTERCEROEDITE', IDADMINISTRADORAEDITE VARCHAR(20) 
					'$.IDADMINISTRADORAEDITE'
					);

			IF @METODO = 'ELIMINAR_PRE'
			BEGIN
				IF @IDSEDE IS NULL OR @IDPLAN IS NULL OR @PREFIJO IS NULL OR @IDTERCERO IS NULL OR @IDADMINISTRADORA IS NULL
				BEGIN
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'Faltan datos para eliminar el proveedor del prefijo.';
				END
				ELSE
				BEGIN
					DELETE
					FROM PXS
					WHERE IDSEDE = @IDSEDE AND IDPLAN = @IDPLAN AND PREFIJO = @PREFIJO AND IDTERCERO = @IDTERCERO AND IDADMINISTRADORA = @IDADMINISTRADORA;

					IF @@ROWCOUNT = 0
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT 'No se encontr� el proveedor de servicios para eliminar.';
					END
				END
			END
			ELSE
			BEGIN
				IF @IDSEDE IS NULL
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'Debe seleccionar la sede.';

				IF @PREFIJO IS NULL
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'Debe indicar el prefijo.';

				IF @IDPLAN IS NULL
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'Debe seleccionar el plan.';

				IF @IDTERCERO IS NULL
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'Debe seleccionar el proveedor (tercero).';

				IF @IDADMINISTRADORA IS NULL
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'Debe seleccionar la administradora.';

				IF @PRIORIDAD < 0
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'La prioridad no puede ser negativa.';

				IF @UMBRAL < 0
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'El umbral no puede ser negativo.';

				IF @IDSEDE IS NOT NULL AND NOT EXISTS (
						SELECT 1
						FROM SED
						WHERE IDSEDE = @IDSEDE
						)
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'La sede indicada no existe.';

				IF @PREFIJO IS NOT NULL AND NOT EXISTS (
						SELECT 1
						FROM PRE
						WHERE PREFIJO = @PREFIJO
						)
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'El prefijo indicado no existe.';

				IF @IDPLAN IS NOT NULL AND NOT EXISTS (
						SELECT 1
						FROM PLN
						WHERE IDPLAN = @IDPLAN
						)
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'El plan indicado no existe.';

				IF @IDTERCERO IS NOT NULL AND NOT EXISTS (
						SELECT 1
						FROM TER
						WHERE IDTERCERO = @IDTERCERO
						)
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'El tercero (proveedor) indicado no existe.';

				IF @IDADMINISTRADORA IS NOT NULL AND NOT EXISTS (
						SELECT 1
						FROM TER
						WHERE IDTERCERO = @IDADMINISTRADORA
						)
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'La administradora indicada no existe.';

				IF NOT EXISTS (
						SELECT 1
						FROM @TBLERRORES
						)
				BEGIN
					IF @PROCESO = 'EDITAR'
					BEGIN
						SET @IDSEDEEDITE = COALESCE(@IDSEDEEDITE, @IDSEDE);
						SET @PREFIJOEDITE = COALESCE(@PREFIJOEDITE, @PREFIJO);
						SET @IDPLANEDITE = COALESCE(@IDPLANEDITE, @IDPLAN);
						SET @IDTERCEROEDITE = COALESCE(@IDTERCEROEDITE, @IDTERCERO);
						SET @IDADMINISTRADORAEDITE = COALESCE(@IDADMINISTRADORAEDITE, @IDADMINISTRADORA);
					END

					IF EXISTS (
							SELECT 1
							FROM PXS
							WHERE IDSEDE = @IDSEDE AND IDPLAN = @IDPLAN AND PREFIJO = @PREFIJO AND IDTERCERO = @IDTERCERO AND IDADMINISTRADORA = @IDADMINISTRADORA AND (
									@PROCESO <> 'EDITAR' OR NOT (
										IDSEDE = @IDSEDEEDITE AND IDPLAN = @IDPLANEDITE AND PREFIJO = @PREFIJOEDITE AND IDTERCERO = @IDTERCEROEDITE AND IDADMINISTRADORA = 
										@IDADMINISTRADORAEDITE
										)
									)
							)
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT 'Ya existe un proveedor con la misma sede, plan, prefijo, tercero y administradora.';
					END
				END

				IF NOT EXISTS (
						SELECT 1
						FROM @TBLERRORES
						)
				BEGIN
					BEGIN TRANSACTION;

					IF @PROCESO = 'INSERTAR'
					BEGIN
						INSERT INTO PXS (IDSEDE, IDPLAN, PREFIJO, PRIORIDAD, IDTERCERO, UMBRAL, EXCOBROPC, IDADMINISTRADORA, LIQUIDARPC, COBRARPC, TIPOTARIFA, IDTARIFA, FACTOR
							)
						VALUES (@IDSEDE, @IDPLAN, @PREFIJO, @PRIORIDAD, @IDTERCERO, @UMBRAL, @EXCOBROPC, @IDADMINISTRADORA, @LIQUIDARPC, @COBRARPC, 'Normal', NULL, 0
							);
					END
					ELSE IF @PROCESO = 'EDITAR'
					BEGIN
						UPDATE PXS
						SET IDSEDE = @IDSEDE, IDPLAN = @IDPLAN, PREFIJO = @PREFIJO, PRIORIDAD = @PRIORIDAD, IDTERCERO = @IDTERCERO, UMBRAL = @UMBRAL, EXCOBROPC = @EXCOBROPC, 
							IDADMINISTRADORA = @IDADMINISTRADORA, LIQUIDARPC = @LIQUIDARPC, COBRARPC = @COBRARPC
						WHERE IDSEDE = @IDSEDEEDITE AND IDPLAN = @IDPLANEDITE AND PREFIJO = @PREFIJOEDITE AND IDTERCERO = @IDTERCEROEDITE AND IDADMINISTRADORA = 
							@IDADMINISTRADORAEDITE;

						IF @@ROWCOUNT = 0
						BEGIN
							INSERT INTO @TBLERRORES (ERROR)
							SELECT 'No se encontr� el proveedor de servicios para actualizar.';
						END
					END
					ELSE
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT 'Proceso no v�lido. INSERTAR o EDITAR.';
					END

					IF EXISTS (
							SELECT 1
							FROM @TBLERRORES
							)
					BEGIN
						ROLLBACK TRANSACTION;
					END
					ELSE
					BEGIN
						COMMIT TRANSACTION;
					END
				END
			END
		END TRY

		BEGIN CATCH
			IF @@TRANCOUNT > 0
				ROLLBACK TRANSACTION;

			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();
		END CATCH
	END

	IF EXISTS (
			SELECT 1
			FROM @TBLERRORES
			)
	BEGIN
		SELECT 'KO' AS OK;

		SELECT ERROR
		FROM @TBLERRORES;
	END
	ELSE
	BEGIN
		SELECT 'OK' AS OK;
	END
END
