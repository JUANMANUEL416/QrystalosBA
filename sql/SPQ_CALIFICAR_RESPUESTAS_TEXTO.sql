CREATE OR ALTER PROCEDURE DBO.SPQ_CALIFICAR_RESPUESTAS_TEXTO @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @DATOS NVARCHAR(MAX), @IDCAP INT, @RESPUESTAS NVARCHAR(MAX);
DECLARE @USUARIO VARCHAR(20), @PROCESO VARCHAR(20), @RESULTADOID INT, @PREGUNTAS NVARCHAR(MAX), @NOMBRETALLER NVARCHAR(255), @DESCRIPCION NVARCHAR(MAX)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SET NOCOUNT ON;

	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR_CALIFICACION'
	BEGIN
		SELECT @RESULTADOID = RESULTADOID, @PROCESO = PROCESO
		FROM OPENJSON(@PARAMETROS) WITH (RESULTADOID INT '$.RESULTADOID', PROCESO VARCHAR(20) '$.PROCESO')

		SELECT @RESPUESTAS = JSON_QUERY(@PARAMETROS, '$.RESPUESTAS');

		BEGIN TRY
			UPDATE RE
			SET RE.Correcta = CA.Correcta, RE.Calificada = 1
			FROM TRespEmpleado RE
			INNER JOIN OPENJSON(@RESPUESTAS) WITH (RespuestaID INT '$.RESPUESTAID', Correcta BIT '$.CORRECTA') CA ON RE.RespuestaID = CA.
				RespuestaID;

			-- Recalcular calificaci�n final
			DECLARE @TotalPreguntas INT = (
					SELECT COUNT(*)
					FROM (
						SELECT PreguntaID
						FROM TRespEmpleado
						WHERE ResultadoID = @ResultadoID
						GROUP BY PreguntaID
						) AS SUBTP
					);
			DECLARE @Correctas INT = (
					SELECT COUNT(*)
					FROM (
						SELECT PreguntaID
						FROM TRespEmpleado
						WHERE ResultadoID = @ResultadoID AND Correcta = 1
						GROUP BY PreguntaID
						) AS SUBC
					);

			UPDATE TRESULTADOS
			SET CalificacionFinal = CAST((@Correctas * 100.0) / @TotalPreguntas AS DECIMAL(5, 2))
			WHERE ResultadoID = @ResultadoID;
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GET_RESPUESTAS_TEXTO'
	BEGIN
		SELECT @RESULTADOID = RESULTADOID
		FROM OPENJSON(@PARAMETROS) WITH (RESULTADOID INT '$.RESULTADOID')

		BEGIN TRY
			SELECT 'OK' OK

			SELECT RE.RespuestaID, RE.ResultadoID, RE.PreguntaID, P.ENUNCIADO AS Pregunta, RE.RespuestaTexto AS RespuestaEmpleado, ISNULL(RE.
					OpcionID_Seleccionada, 0) AS EstadoCalificacion
			FROM TRespEmpleado RE
			INNER JOIN TPREGUNTAS P ON RE.PreguntaID = P.PREGUNTAID
			WHERE P.TIPOPREGUNTA = 'texto' AND RE.ResultadoID = @RESULTADOID
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
