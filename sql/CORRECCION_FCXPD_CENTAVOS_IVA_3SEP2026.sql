/*
  CEM — centavos / reparto IVA en detalle (cabecera ya cuadra).
  01CM000873 DPE10920 | 03CM001706 DPE10943 | 03CM002193 DPE12214

  Ajusta VLR_IVA/VLR_NETO por línea para que neto = cant×valor+IVA−dto
  sin cambiar Σ IVA ni Σ neto de cabecera (tolerancia 0,01).
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @DOC TABLE (CNSFCXP varchar(20) NOT NULL PRIMARY KEY);
INSERT INTO @DOC VALUES (N'01CM000873'), (N'03CM001706'), (N'03CM002193');

DECLARE @FIX TABLE (
  CNSFCXP varchar(20) NOT NULL,
  ITEM int NOT NULL,
  IVA_OK decimal(18, 2) NOT NULL,
  NETO_OK decimal(18, 2) NOT NULL,
  PRIMARY KEY (CNSFCXP, ITEM)
);

INSERT INTO @FIX (CNSFCXP, ITEM, IVA_OK, NETO_OK)
SELECT D.CNSFCXP, D.ITEM,
       CONVERT(decimal(18, 2), COALESCE(D.VLR_IVA, 0)),
       CONVERT(decimal(18, 2), D.CANTIDAD * D.VALOR + COALESCE(D.VLR_IVA, 0) - ISNULL(D.VLR_DESCUENTO, 0))
FROM dbo.FCXPD D
INNER JOIN @DOC C ON C.CNSFCXP = D.CNSFCXP;

/* 2193: repartir IVA cab proporcional a base por línea */
;WITH P AS (
  SELECT F.CNSFCXP, SUM(F.IVA_OK) AS IVA_SUM, MAX(PX.VLR_IVA) AS IVA_CAB
  FROM @FIX F
  INNER JOIN dbo.FCXP PX ON PX.CNSFCXP = F.CNSFCXP
  WHERE F.CNSFCXP = N'03CM002193'
  GROUP BY F.CNSFCXP
),
B AS (
  SELECT D.CNSFCXP, D.ITEM,
         CONVERT(decimal(18, 2), D.CANTIDAD * D.VALOR) AS BASE
  FROM dbo.FCXPD D
  WHERE D.CNSFCXP = N'03CM002193'
),
T AS (
  SELECT CNSFCXP, SUM(BASE) AS BASE_T FROM B GROUP BY CNSFCXP
)
UPDATE F
SET IVA_OK = CONVERT(decimal(18, 2), ROUND(P.IVA_CAB * B.BASE / NULLIF(T.BASE_T, 0), 2)),
    NETO_OK = CONVERT(decimal(18, 2), B.BASE + ROUND(P.IVA_CAB * B.BASE / NULLIF(T.BASE_T, 0), 2))
FROM @FIX F
INNER JOIN B ON B.CNSFCXP = F.CNSFCXP AND B.ITEM = F.ITEM
INNER JOIN T ON T.CNSFCXP = F.CNSFCXP
INNER JOIN P ON P.CNSFCXP = F.CNSFCXP
WHERE F.CNSFCXP = N'03CM002193';

/* Centavo en última línea si Σ IVA ≠ cab */
;WITH AJ AS (
  SELECT F.CNSFCXP, P.VLR_IVA AS IVA_CAB, SUM(F.IVA_OK) AS IVA_SUM, MAX(F.ITEM) AS ITEM_AJ
  FROM @FIX F
  INNER JOIN dbo.FCXP P ON P.CNSFCXP = F.CNSFCXP
  INNER JOIN @DOC C ON C.CNSFCXP = F.CNSFCXP
  GROUP BY F.CNSFCXP, P.VLR_IVA
  HAVING ABS(P.VLR_IVA - SUM(F.IVA_OK)) > 0.001 AND ABS(P.VLR_IVA - SUM(F.IVA_OK)) <= 1
)
UPDATE F
SET IVA_OK = CONVERT(decimal(18, 2), F.IVA_OK + (A.IVA_CAB - A.IVA_SUM)),
    NETO_OK = CONVERT(decimal(18, 2), F.NETO_OK + (A.IVA_CAB - A.IVA_SUM))
FROM @FIX F
INNER JOIN AJ A ON A.CNSFCXP = F.CNSFCXP AND F.ITEM = A.ITEM_AJ;

BEGIN TRAN;

IF (
  SELECT COUNT(*)
  FROM dbo.FCXP P
  INNER JOIN @DOC C ON C.CNSFCXP = P.CNSFCXP
  WHERE P.ESTADO = N'N' AND COALESCE(P.CONTABILIZADA, 0) = 0
) <> 3
BEGIN
  ROLLBACK TRAN;
  THROW 55201, 'Alguna CxP del bloque no esta libre.', 1;
END;

UPDATE D
SET VLR_IVA = F.IVA_OK,
    VLR_NETO = F.NETO_OK
FROM dbo.FCXPD D
INNER JOIN @FIX F ON F.CNSFCXP = D.CNSFCXP AND F.ITEM = D.ITEM
WHERE ABS(D.VLR_IVA - F.IVA_OK) > 0.001 OR ABS(D.VLR_NETO - F.NETO_OK) > 0.001;

IF EXISTS (
  SELECT 1
  FROM dbo.FCXP P
  INNER JOIN @DOC C ON C.CNSFCXP = P.CNSFCXP
  INNER JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
  GROUP BY P.CNSFCXP, P.VLR_IVA, P.VLR_NETO, P.VALOR
  HAVING ABS(SUM(D.VLR_IVA) - P.VLR_IVA) > 0.02
      OR ABS(SUM(D.VLR_NETO) - P.VLR_NETO) > 0.02
      OR ABS(P.VALOR + P.VLR_IVA - P.VLR_NETO) > 0.02
)
OR EXISTS (
  SELECT 1 FROM dbo.FCXPD D INNER JOIN @DOC C ON C.CNSFCXP = D.CNSFCXP
  WHERE ABS(D.VLR_NETO - (D.CANTIDAD * D.VALOR + COALESCE(D.VLR_IVA, 0) - ISNULL(D.VLR_DESCUENTO, 0))) > 0.02
)
BEGIN
  ROLLBACK TRAN;
  THROW 55202, 'Tras ajuste, cab/detalle o formula linea no cuadra.', 1;
END;

COMMIT TRAN;

SELECT P.CNSFCXP, P.NOREFERENCIA,
       CONVERT(decimal(18, 2), P.VALOR + P.VLR_IVA) AS NETO_ESP,
       CONVERT(decimal(18, 2), P.VLR_NETO) AS NETO_CAB,
       SUM(CASE WHEN ABS(D.VLR_NETO - (D.CANTIDAD*D.VALOR+COALESCE(D.VLR_IVA,0))) > 0.02 THEN 1 ELSE 0 END) AS LINEAS_MAL
FROM dbo.FCXP P
INNER JOIN @DOC C ON C.CNSFCXP = P.CNSFCXP
INNER JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
GROUP BY P.CNSFCXP, P.NOREFERENCIA, P.VALOR, P.VLR_IVA, P.VLR_NETO;
