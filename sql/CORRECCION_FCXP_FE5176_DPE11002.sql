  Solo FCXP / FCXPD. No toca entradas ni existencias.

  FE5176  03CM002317  Servi24
    La factura totaliza 61.443.960,32.
    Base 61.443.328. IVA 632,32, que es el 19 % de 3.328
    (lancetas 3.200 + glucómetro 128). Las tiras van exentas.
    La cuenta tiene el neto en 61.443.328 y el IVA en cero.
    Queda: lancetas IVA 608, glucómetro IVA 24,32.
    Esas dos en gravados 14200501 y cuenta de IVA 24080501.
    Las tiras siguen en 14200502.

  DPE11002  01CM000852  Tododrogas
    La factura totaliza 14.162.400, sin IVA.
      Fortidol: 12.000 × 573 = 6.876.000. Ya cuadra.
      Rosuvastatina: 32 cajas × 210.000 = 6.720.000 (32.000 tabletas × 210).
        La cuenta tiene 35.000 × 210 = 7.350.000.
      Adorem: 32 cajas × 17.700 = 566.400 (3.200 × 177).
        La cuenta tiene 3.200 × 19 = 60.800.
    La entrada sigue con 35.000 de rosuvastatina y el costo negativo de Adorem.
    Este script no la modifica.
    El número 2653000000003002 no tiene movimiento contable.

  Uso:
