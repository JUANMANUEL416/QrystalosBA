       Si algo no cuadra, hace ROLLBACK y no deja nada.
*/

SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @APLICAR bit = 0;

SELECT
  P.NOREFERENCIA,
  D.ITEM,
  D.IDSERVICIO,
  CONVERT(decimal(18, 2), D.CANTIDAD) AS CANT_HOY,
  CONVERT(decimal(18, 2),
    CASE
      WHEN P.CNSFCXP = N'01CM000852' AND D.IDSERVICIO = N'MX1096-1' THEN 32000
      ELSE D.CANTIDAD
    END) AS CANT_OK,
  CONVERT(decimal(18, 6), D.VALOR) AS PRECIO_HOY,
  CONVERT(decimal(18, 6),
    CASE
      WHEN P.CNSFCXP = N'01CM000852' AND D.IDSERVICIO = N'MX588-1' THEN 177
      ELSE D.VALOR
    END) AS PRECIO_OK,
  CONVERT(decimal(18, 2), D.VLR_IVA) AS IVA_HOY,
  CONVERT(decimal(18, 2),
    CASE
      WHEN P.CNSFCXP = N'03CM002317' AND D.IDSERVICIO = N'DM148-1' THEN 608
      WHEN P.CNSFCXP = N'03CM002317' AND D.IDSERVICIO = N'DM149-1' THEN 24.32
      ELSE 0
    END) AS IVA_OK,
  CONVERT(decimal(18, 2), D.VLR_NETO) AS NETO_HOY,
  CONVERT(decimal(18, 2),
    CASE
      WHEN P.CNSFCXP = N'03CM002317' AND D.IDSERVICIO = N'DM148-1' THEN 3808
      WHEN P.CNSFCXP = N'03CM002317' AND D.IDSERVICIO = N'DM149-1' THEN 152.32
      WHEN P.CNSFCXP = N'01CM000852' AND D.IDSERVICIO = N'MX1096-1' THEN 6720000
      WHEN P.CNSFCXP = N'01CM000852' AND D.IDSERVICIO = N'MX588-1' THEN 566400
      ELSE D.VLR_NETO
    END) AS NETO_OK,
  D.CUENTA_SER AS CUENTA_HOY,
  CASE
    WHEN P.CNSFCXP = N'03CM002317' AND D.IDSERVICIO IN (N'DM148-1', N'DM149-1') THEN N'14200501'
    ELSE D.CUENTA_SER
  END AS CUENTA_OK
FROM dbo.FCXP P
INNER JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
WHERE P.CNSFCXP IN (N'03CM002317', N'01CM000852')
ORDER BY P.NOREFERENCIA, D.ITEM;

IF @APLICAR = 0
  RETURN;

BEGIN TRAN;

DECLARE @det TABLE (ITEM int);
DECLARE @cab TABLE (CNSFCXP varchar(20));

IF EXISTS (
  SELECT 1
  FROM dbo.FCXP P
  WHERE P.CNSFCXP IN (N'03CM002317', N'01CM000852')
    AND (
      P.ESTADO <> N'N'
      OR COALESCE(P.CONTABILIZADA, 0) <> 0
      OR COALESCE(P.VLR_IMPUESTOS, 0) <> 0
      OR ABS(P.SALDO - P.VLR_NETO) > 0.01
      OR EXISTS (
        SELECT 1 FROM dbo.MCH H
        WHERE H.NROCOMPROBANTE = RTRIM(P.NROCOMPROBANTE)
      )
      OR EXISTS (
        SELECT 1 FROM dbo.MCHE H
        WHERE H.NROCOMPROBANTE = RTRIM(P.NROCOMPROBANTE)
      )
    )
)
BEGIN
  ROLLBACK TRAN;
  THROW 56110, 'Alguna de las dos cuentas ya está contabilizada o el saldo no es el neto.', 1;
END;

UPDATE dbo.FCXPD
SET VLR_IVA = 608.00,
    VLR_NETO = 3808.00,
    VLR_DESCUENTO = 0,
    CUENTA_SER = N'14200501',
    CUENTA_IVA = N'24080501',
    IDIMPUESTO = N'IVA',
    IDCLASE = N'01'
OUTPUT inserted.ITEM INTO @det
WHERE CNSFCXP = N'03CM002317'
  AND IDSERVICIO = N'DM148-1'
  AND CANTIDAD = 3200
  AND VLR_NETO = 3200.00
  AND COALESCE(VLR_IVA, 0) = 0;

IF (SELECT COUNT(*) FROM @det) <> 1
BEGIN
  ROLLBACK TRAN;
  THROW 56111, 'No se encontraron las lancetas de FE5176 en 3.200.', 1;
END;

DELETE FROM @det;

UPDATE dbo.FCXPD
SET VLR_IVA = 24.32,
    VLR_NETO = 152.32,
    VLR_DESCUENTO = 0,
    CUENTA_SER = N'14200501',
    CUENTA_IVA = N'24080501',
    IDIMPUESTO = N'IVA',
    IDCLASE = N'01'
OUTPUT inserted.ITEM INTO @det
WHERE CNSFCXP = N'03CM002317'
  AND IDSERVICIO = N'DM149-1'
  AND CANTIDAD = 128
  AND VLR_NETO = 128.00
  AND COALESCE(VLR_IVA, 0) = 0;

IF (SELECT COUNT(*) FROM @det) <> 1
BEGIN
  ROLLBACK TRAN;
  THROW 56111, 'No se encontró el glucómetro de FE5176 en 128.', 1;
END;

UPDATE dbo.FCXP
SET VLR_IVA = 632.32,
    VLR_NETO = 61443960.32,
    SALDO = 61443960.32
OUTPUT inserted.CNSFCXP INTO @cab
WHERE CNSFCXP = N'03CM002317'
  AND VLR_NETO = 61443328.00
  AND SALDO = 61443328.00
  AND COALESCE(VLR_IVA, 0) = 0;

IF (SELECT COUNT(*) FROM @cab) <> 1
BEGIN
  ROLLBACK TRAN;
  THROW 56111, 'La cabecera de FE5176 ya no está en 61.443.328.', 1;
END;

DELETE FROM @det;

UPDATE dbo.FCXPD
SET CANTIDAD = 32000,
    VLR_NETO = 6720000.00,
    VLR_IVA = 0,
    VLR_DESCUENTO = 0
OUTPUT inserted.ITEM INTO @det
WHERE CNSFCXP = N'01CM000852'
  AND IDSERVICIO = N'MX1096-1'
  AND CANTIDAD = 35000
  AND VALOR = 210
  AND VLR_NETO = 7350000.00
  AND COALESCE(VLR_IVA, 0) = 0;

IF (SELECT COUNT(*) FROM @det) <> 1
BEGIN
  ROLLBACK TRAN;
  THROW 56112, 'No se encontró la rosuvastatina de DPE11002 en 35.000.', 1;
END;

DELETE FROM @det;

UPDATE dbo.FCXPD
SET VALOR = 177,
    VLR_NETO = 566400.00,
    VLR_IVA = 0,
    VLR_DESCUENTO = 0
OUTPUT inserted.ITEM INTO @det
WHERE CNSFCXP = N'01CM000852'
  AND IDSERVICIO = N'MX588-1'
  AND CANTIDAD = 3200
  AND VLR_NETO = 60800.00
  AND COALESCE(VLR_IVA, 0) = 0;

IF (SELECT COUNT(*) FROM @det) <> 1
BEGIN
  ROLLBACK TRAN;
  THROW 56112, 'No se encontró Adorem de DPE11002 en 60.800.', 1;
END;

DELETE FROM @cab;

UPDATE dbo.FCXP
SET VALOR = 14162400.00,
    VLR_NETO = 14162400.00,
    SALDO = 14162400.00
OUTPUT inserted.CNSFCXP INTO @cab
WHERE CNSFCXP = N'01CM000852'
  AND VLR_NETO = 14286800.00
  AND SALDO = 14286800.00;

IF (SELECT COUNT(*) FROM @cab) <> 1
BEGIN
  ROLLBACK TRAN;
  THROW 56112, 'La cabecera de DPE11002 ya no está en 14.286.800.', 1;
END;

IF ABS((SELECT VLR_NETO FROM dbo.FCXP WHERE CNSFCXP = N'03CM002317') - 61443960.32) > 0.02
OR ABS((SELECT VLR_IVA FROM dbo.FCXP WHERE CNSFCXP = N'03CM002317') - 632.32) > 0.02
OR ABS((SELECT VLR_NETO FROM dbo.FCXP WHERE CNSFCXP = N'01CM000852') - 14162400.00) > 0.02
OR EXISTS (
  SELECT P.CNSFCXP
  FROM dbo.FCXP P
  INNER JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
  WHERE P.CNSFCXP IN (N'03CM002317', N'01CM000852')
  GROUP BY P.CNSFCXP, P.VLR_NETO, P.VLR_IVA
  HAVING ABS(SUM(D.VLR_NETO) - P.VLR_NETO) > 0.02
      OR ABS(SUM(D.VLR_IVA) - P.VLR_IVA) > 0.02
      OR ABS(SUM(D.VLR_NETO) - SUM(ROUND(D.CANTIDAD * D.VALOR, 2) + D.VLR_IVA - COALESCE(D.VLR_DESCUENTO, 0))) > 0.05
)
OR EXISTS (
  SELECT 1
  FROM dbo.FCXPD
  WHERE CNSFCXP = N'03CM002317'
    AND IDSERVICIO IN (N'DM148-1', N'DM149-1')
    AND (CUENTA_SER <> N'14200501' OR CUENTA_IVA <> N'24080501')
)
BEGIN
  ROLLBACK TRAN;
  THROW 56113, 'El neto o el IVA no quedaron como la factura.', 1;
END;

COMMIT TRAN;

SELECT
  P.NOREFERENCIA,
  CONVERT(decimal(18, 2), P.VALOR) AS BASE,
  CONVERT(decimal(18, 2), P.VLR_IVA) AS IVA,
  CONVERT(decimal(18, 2), P.VLR_NETO) AS NETO,
  CONVERT(decimal(18, 2), P.SALDO) AS SALDO
FROM dbo.FCXP P
WHERE P.CNSFCXP IN (N'03CM002317', N'01CM000852')
ORDER BY P.NOREFERENCIA;
