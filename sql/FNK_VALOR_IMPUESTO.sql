IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='FNK_VALOR_IMPUESTO' AND XTYPE='TF')
BEGIN
 DROP FUNCTION FNK_VALOR_IMPUESTO
END

GO
CREATE FUNCTION DBO.FNK_VALOR_IMPUESTO(@IDIMPUESTO VARCHAR(10), @IDCLASE VARCHAR(10), @FECHA DATETIME, @VALOR_ITEM DECIMAL(14,2)) 
RETURNS @TABLA
TABLE (IDIMPUESTO VARCHAR(10) COLLATE database_default,
       IDCLASE    VARCHAR(10) COLLATE database_default,
       ITEM       SMALLINT,
       VALOR      DECIMAL(14,5),
       CUENTA     VARCHAR(16) COLLATE database_default)       
WITH ENCRYPTION
AS
BEGIN
 DECLARE @IVA        VARCHAR(3)
 DECLARE @VALOR      DECIMAL(14,5)
 DECLARE @ITEM       SMALLINT
 DECLARE @PREFIJO    VARCHAR(6)

 INSERT INTO @TABLA(IDIMPUESTO, IDCLASE, ITEM, VALOR, CUENTA)
 SELECT TOP 1 FIMPDV.IDIMPUESTO, FIMPDV.IDCLASE, FIMPDV.ITEM, ISNULL(FIMPDV.VALOR,0), FIMPDV.CUENTA
 FROM FIMPDV 
 WHERE @IDIMPUESTO=FIMPDV.IDIMPUESTO AND  @IDCLASE=FIMPDV.IDCLASE AND 
       @FECHA >= FIMPDV.FECHAINI AND @FECHA < FIMPDV.FECHAFIN+1 AND 
       (@VALOR_ITEM>=FIMPDV.VALOR_INICIAL OR FIMPDV.VALOR_INICIAL IS NULL) AND @VALOR_ITEM<=
        (CASE WHEN FIMPDV.VALOR_FINAL = 0 OR FIMPDV.VALOR_FINAL IS NULL 
               THEN @VALOR_ITEM 
               ELSE FIMPDV.VALOR_FINAL 
         END)
 RETURN
END
