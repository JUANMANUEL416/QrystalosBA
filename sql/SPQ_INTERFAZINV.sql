CREATE OR ALTER PROCEDURE DBO.SPQ_INTERFAZINV
@JSON  NVARCHAR(MAX)
WITH
ENCRYPTION
AS
DECLARE @PARAMETROS         NVARCHAR(MAX)  ,@MODELO           VARCHAR(100)    ,@METODO        VARCHAR(100)  ,@USUARIO        VARCHAR(12)
       ,@GRUPO              VARCHAR(8)     ,@SYS_COMPUTERNAME VARCHAR(254)    ,@SEDE          VARCHAR(5)	   ,@A              INT
       ,@IDENTITY           INT 
       ,@PROCESO            VARCHAR(20)    ,@INTERFAXINV    NVARCHAR(MAX)
              ,@ID     INT       ,@FECHA     DATETIME       ,@FECHA_STR VARCHAR(10)       ,@ID_TRX     VARCHAR(50)       ,@SOLICITUD     VARCHAR(MAX)
       ,@FORMATEADO     VARCHAR(MAX)       ,@RESPUESTA     VARCHAR(MAX)       ,@ESTADO     VARCHAR(10)       ,@CNSMOV     VARCHAR(20)       ,@IDARTICULO     VARCHAR(20)
	   ,@JSONITF VARCHAR(MAX),	@XML VARCHAR(MAX) ,	@sUrl VARCHAR(1024),	@OK VARCHAR(4)
		,@PROCESOITF VARCHAR(10), @response VARCHAR(MAX), @CNSTRX VARCHAR(20)
BEGIN
   SET LANGUAGE Spanish
   SET DATEFORMAT dmy
   
   SELECT @A = ISJSON(@JSON)
   IF @A = 0
   BEGIN
     RAISERROR('Json: Formato Erroneo',16,1)
     RETURN
   END
   PRINT 'INGRESE A SPQ_INTERFAZINV'
   SELECT *
   INTO #JSON
   FROM OPENJSON (@json)
   WITH (
     MODELO         VARCHAR(100)     '$.MODELO',
     METODO         VARCHAR(100)     '$.METODO',
     USUARIO        VARCHAR(12)      '$.USUARIO',
     PARAMETROS     NVARCHAR(MAX)     AS JSON
   )
   
   SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS , @USUARIO = USUARIO
   FROM #JSON
   --DEFINICION DE TABLA DE ERRORES
   DECLARE @TBLERRORES TABLE(ERROR VARCHAR(500))
   -- TOMA DEL GRUPO, SYS_COMPUTERNAME, SEDE   DE ACUERDO AL USUARIO
   PRINT 'USUARIO:'+@USUARIO
   --SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO) FROM USUSU WHERE USUARIO = @USUARIO
   --SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
   --SELECT @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
   IF COALESCE(@SEDE,'') = '' SELECT @SEDE = '01'
   PRINT 'SEDE='+@SEDE
   
      
	IF UPPER(@METODO) = 'REENVIAR'
	BEGIN
		BEGIN TRY
			PRINT 'REENVIAR'
			SELECT @CNSMOV = JSON_VALUE(@PARAMETROS , '$.CNSMOV'),@ID_TRX = JSON_VALUE(@PARAMETROS , '$.IDTRX'),@ID = JSON_VALUE(@PARAMETROS , '$.ID_INTERFAXINV')

			IF COALESCE(@ID_TRX,'') = ''
			BEGIN
				SELECT 'KO' OK
				SELECT 'ES NECESARIO EL CONSECUTIVO DE TRANSACCION PARA REENVIAR LA TRAMA.' ERROR
				RETURN
			END

			SELECT @XML = CASE
							WHEN COALESCE(LTRIM(RTRIM(SOLICITUD)), '') <> '' THEN SOLICITUD
							ELSE FORMATEADO
						END
				  ,@CNSMOV = CNSMOV
				  ,@IDARTICULO = IDARTICULO
				  ,@CNSTRX = ID_TRX
				  ,@PROCESOITF = PROCESO
				  ,@ESTADO = ESTADO
			FROM INTERFAXINV
			WHERE ID = @ID

			IF @ID IS NULL OR NOT EXISTS (SELECT 1 FROM INTERFAXINV WHERE ID = @ID)
			BEGIN
				SELECT 'KO' OK
				SELECT 'No se encontr� el registro de INTERFAXINV para reprocesar.' ERROR
				RETURN
			END

			IF COALESCE(@ESTADO, '') <> 'ERRORES'
			BEGIN
				SELECT 'KO' OK
				SELECT 'Solo se pueden reprocesar tramas en estado ERRORES.' ERROR
				RETURN
			END

			-- Entrada SAP -> QTLS (ENT/SAL): reprocesa COMPRA_ARTICULO con el XML de SOLICITUD.
			-- No consultar API_LOG (COMMAND LIKE '%ID_TRX%' no es SARGable y puede tardar minutos).
			IF @PROCESOITF IN ('ENT', 'SAL')
			BEGIN
				PRINT 'REPROCESAR ENTRADA SAP->QTLS'

				IF EXISTS (
					SELECT 1
					FROM INTERFAXINV
					WHERE ID_TRX = @ID_TRX
					  AND ESTADO IN ('TERMINADO', 'OK')
				)
				BEGIN
					SELECT 'KO' OK
					SELECT 'Esta transacci�n ya tiene un procesamiento exitoso. No es necesario reprocesar.' ERROR
					RETURN
				END

				IF COALESCE(LTRIM(RTRIM(@XML)), '') = ''
				BEGIN
					SELECT 'KO' OK
					SELECT 'La trama no tiene XML de solicitud en INTERFAXINV.SOLICITUD para reprocesar.' ERROR
					RETURN
				END

				SET @XML = REPLACE(@XML, CHAR(92) + CHAR(34), CHAR(34))

				SET @JSONITF = CONCAT(
					'{"MODELO":"SAP","METODO":"COMPRA_ARTICULO","USUARIO":"TEST","PARAMETROS":',
					(
						SELECT @XML AS DATOS, 1 AS REPROCESO
						FOR JSON PATH, WITHOUT_ARRAY_WRAPPER
					),
					'}'
				)

				PRINT CONCAT('@JSONITF >', COALESCE(@JSONITF, ' SIN @JSONITF'))
				-- #JSON del caller choca con el de SPQ_SAP (temp tables de sesi�n)
				IF OBJECT_ID('tempdb..#JSON') IS NOT NULL DROP TABLE #JSON
				EXEC DBO.SPQ_SAP @JSONITF

				SELECT TOP 1
					@ESTADO = ESTADO,
					@RESPUESTA = RESPUESTA,
					@CNSMOV = CNSMOV
				FROM INTERFAXINV
				WHERE ID_TRX = @ID_TRX
				  AND ID > @ID
				ORDER BY ID DESC

				IF @ESTADO IN ('TERMINADO', 'OK')
				BEGIN
					SELECT 'OK' OK
					RETURN
				END

				INSERT INTO @TBLERRORES(ERROR)
				SELECT LEFT(COALESCE(NULLIF(LTRIM(RTRIM(@RESPUESTA)), ''), 'No se pudo reprocesar la trama de entrada. Revise el visor de interfaz.'), 500)
			END
			ELSE IF @PROCESOITF = 'CONSUMO' AND DBO.FNK_VALORVARIABLE('INTERFAZ_INV') = 'INTER_SAP'
			BEGIN
				PRINT 'REENVIO A SAP'
				SELECT @JSONITF='{ '
				SELECT @JSONITF=@JSONITF+'"xml": "'+@XML+'"'
				SELECT @JSONITF=LTRIM(RTRIM(@JSONITF)) +' }'

					PRINT CONCAT('@JSONITF >', COALESCE(@JSONITF,' SIN @JSONITF'))
					PRINT CONCAT('@CNSMOV >', COALESCE(@CNSMOV,' SIN @CNSMOV'))
					PRINT CONCAT('@IDARTICULO >', COALESCE(@IDARTICULO,' SIN @IDARTICULO'))
					PRINT CONCAT('@CNSTRX >', COALESCE(@CNSTRX,' SIN @CNSTRX'))

					SELECT @sUrl='/MovInventario/CircuitoConsumoEM'

					EXEC SPK_ENVIA_TRAMAS_CIPERU @ENDPOINT=@sUrl, @TRAMA = @JSONITF ,@OK=@OK OUTPUT,  @RESPUESTA= @response OUTPUT

					IF @OK='KO'
					BEGIN
						INSERT INTO INTERFAXINV(FECHA,ID_TRX,PROCESO,SOLICITUD,FORMATEADO,RESPUESTA,ESTADO,CNSMOV,IDARTICULO)
						SELECT DBO.FNK_GETDATE(), @CNSTRX,@PROCESOITF,@XML,@XML,@response,'ERRORES',@CNSMOV,@IDARTICULO
					END
					ELSE
					BEGIN
						-- Validaci�n inicial
						IF LEFT(LTRIM(@response), 1) NOT IN ('{', '[')
						BEGIN
							INSERT INTO INTERFAXINV(FECHA,ID_TRX,PROCESO,SOLICITUD,FORMATEADO,RESPUESTA,ESTADO,CNSMOV,IDARTICULO)
							SELECT DBO.FNK_GETDATE(), @CNSTRX,@PROCESOITF,@XML,@XML,@response,'RES_INVALI',@CNSMOV,@IDARTICULO;

							SELECT 'KO' OK
							SELECT 'La respuesta de SAP no es un JSON v�lido.' ERROR
							RETURN;
						END


						DECLARE @COD_RESULT VARCHAR(10) = JSON_VALUE(@response, '$.Items.COD_RESULT');
						DECLARE @COD_ERROR VARCHAR(10)
						DECLARE @MSG_ERROR NVARCHAR(500)

						IF JSON_QUERY(@response, '$.Items.COD_ERROR') = '[]'
							SET @COD_ERROR = 'SIN COD_ERROR';
						ELSE
							SELECT @COD_ERROR = STRING_AGG(value, ', ')
							FROM OPENJSON(JSON_QUERY(@response, '$.Items.COD_ERROR'));

						IF JSON_QUERY(@response, '$.Items.MSG_ERROR') = '[]'
							SET @MSG_ERROR = 'SIN MSG_ERROR';
						ELSE
							SELECT @MSG_ERROR = STRING_AGG(value, ', ')
							FROM OPENJSON(JSON_QUERY(@response, '$.Items.MSG_ERROR'));

						DECLARE @RPTA NVARCHAR(500) = CONCAT('Respuesta: @COD_RESULT = ', COALESCE(@COD_RESULT,'SIN @COD_RESULT'), ', @COD_ERROR = ', @COD_ERROR, ', @MSG_ERROR = ', @MSG_ERROR)
						PRINT CONCAT('@response ', COALESCE(@response,'SIN @response'))
						PRINT CONCAT('@COD_RESULT ', COALESCE(@COD_RESULT,'SIN @COD_RESULT'))
						PRINT CONCAT('@COD_ERROR ', COALESCE(@COD_ERROR,'SIN @COD_ERROR'))
						PRINT CONCAT('@MSG_ERROR ', COALESCE(@MSG_ERROR,'SIN @MSG_ERROR'))
						PRINT CONCAT('@RPTA ', COALESCE(@RPTA,'SIN @RPTA'))

						IF @COD_RESULT = '0'
						BEGIN
							INSERT INTO INTERFAXINV(FECHA,ID_TRX,PROCESO,SOLICITUD,FORMATEADO,RESPUESTA,RESPONSE,ESTADO,CNSMOV,IDARTICULO)
							SELECT DBO.FNK_GETDATE(), @CNSTRX,@PROCESOITF,@XML,@XML,COALESCE(@RPTA,'SIN @RPTA'),COALESCE(@response,'SIN @response'),'OK',@CNSMOV,@IDARTICULO
						END
						ELSE
						BEGIN
							INSERT INTO INTERFAXINV(FECHA,ID_TRX,PROCESO,SOLICITUD,FORMATEADO,RESPUESTA,RESPONSE,ESTADO,CNSMOV,IDARTICULO)
							SELECT DBO.FNK_GETDATE(), @CNSTRX,@PROCESOITF,@XML,@XML,COALESCE(@RPTA,'SIN @RPTA'),COALESCE(@response,'SIN @response'),'ERRORES',@CNSMOV,@IDARTICULO
						END
					END
			END
			ELSE
			BEGIN
				INSERT INTO @TBLERRORES(ERROR)
				SELECT CONCAT('Este tipo de proceso (', COALESCE(@PROCESOITF, ''), ') no se puede reprocesar desde el visor. Solo ENT/SAL (entrada SAP) y CONSUMO (salida a SAP).')
			END
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' OK
		RETURN
	END
END
