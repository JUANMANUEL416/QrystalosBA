CREATE OR ALTER PROCEDURE DBO.SPQ_TER_SERTOT @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20)
DECLARE @PROCESO VARCHAR(20), @CNSEXCEL VARCHAR(20), @IDSEDE VARCHAR(5), @SYS_COMPUTERNAME VARCHAR(200), @COMPANIA VARCHAR(2)
DECLARE @IDTERCERO VARCHAR(20), @IDPLAN VARCHAR(20)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'EXPORTAR'
	BEGIN
		SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
		FROM USUSU
		WHERE USUARIO = @USUARIO

		SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
		FROM UBEQ
		WHERE SYS_ComputerName = @SYS_COMPUTERNAME

		SELECT @CNSEXCEL = JSON_VALUE(@PARAMETROS, '$.CNSEXCEL')

		SELECT @IDTERCERO = IDTERCERO, @IDPLAN = IDPLAN
		FROM OPENJSON(@PARAMETROS) WITH (IDTERCERO VARCHAR(20) '$.IDTERCERO', IDPLAN VARCHAR(20) '$.IDPLAN')

		IF @CNSEXCEL IS NULL
		BEGIN
			EXEC SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE, '@EXCEL', @CNSEXCEL OUTPUT

			SELECT @CNSEXCEL = @IDSEDE + REPLACE(SPACE(8 - LEN(@CNSEXCEL)) + LTRIM(RTRIM(@CNSEXCEL)), SPACE(1), 0)
		END

		BEGIN TRY
			INSERT INTO KEXCEL_FILL (CNSEXCEL, NOMBRE, BORRAR, CONSULTA)
			SELECT @CNSEXCEL, 'SERVICIOS_' + @IDTERCERO + '_' + CONVERT(VARCHAR, GETDATE(), 112) + '_' + REPLACE(CONVERT(VARCHAR, GETDATE(), 108), ':', '') + '.xlsx', 1, 
				'SELECT IDTERCERO AS TERCERO,IDPLAN,IDTARIFA,FACTOR,IDSERVICIO,CODCUPS, DESCSERVICIO AS SERVICIO, VLRSERVICIO AS VALOR, PREFIJO, SEXO, FORMAT(FECHAINI,''yyyy-MM-dd'') AS FECHA_INICIO, FORMAT(FECHAFIN,''yyyy-MM-dd'') AS FECHA_FIN FROM SERTOT WHERE IDTERCERO = ''' 
				+ @IDTERCERO + '''' + 'AND IDPLAN = ''' + @IDPLAN + ''' AND FECHAINI<=GETDATE() AND FECHAFIN>=GETDATE() AND FECHAINIFD<=GETDATE() AND FECHAFINFD>=GETDATE() '
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK, @CNSEXCEL CNSEXCEL

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK, @CNSEXCEL CNSEXCEL
	END
END
