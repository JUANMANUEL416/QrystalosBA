CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NCONDC @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @DATOS NVARCHAR(MAX)
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20)
DECLARE @PROCESO VARCHAR(20)
DECLARE @CODCONCEPTO VARCHAR(20), @ITEM DECIMAL(14, 0), @CODCONCEPTO_BASE VARCHAR(20), @AUTOITEM_BASE DECIMAL(14, 0), @REQUIERELIQ SMALLINT, @VALHORASLAB SMALLINT, 
	@HORAS INT, @DIAS INT, @CollationName NVARCHAR(150), @SQL NVARCHAR(MAX)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @CODCONCEPTO = CODCONCEPTO, @ITEM = ITEM, @CODCONCEPTO_BASE = CODCONCEPTO_BASE, @AUTOITEM_BASE = AUTOITEM_BASE, @REQUIERELIQ = REQUIERELIQ, 
				@VALHORASLAB = VALHORASLAB, @HORAS = HORAS, @DIAS = DIAS, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO', ITEM DECIMAL(14, 0) '$.ITEM', CODCONCEPTO_BASE VARCHAR(20) '$.CODCONCEPTO_BASE', AUTOITEM_BASE 
					DECIMAL(14, 0) '$.AUTOITEM_BASE', REQUIERELIQ SMALLINT '$.REQUIERELIQ', VALHORASLAB SMALLINT '$.VALHORASLAB', HORAS INT '$.HORAS', DIAS INT 
					'$.DIAS', PROCESO VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					UPDATE NCONDC
					SET REQUIERELIQ = @REQUIERELIQ, VALHORASLAB = @VALHORASLAB, HORAS = @HORAS, DIAS = @DIAS
					WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM AND CODCONCEPTO_BASE = @CODCONCEPTO_BASE AND AUTOITEM_BASE = @AUTOITEM_BASE
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GET_NCONDC'
	BEGIN
		SELECT @CODCONCEPTO = CODCONCEPTO
		FROM OPENJSON(@PARAMETROS) WITH (CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO')

		SELECT 'OK' OK

		IF (
				SELECT COUNT(*)
				FROM NCONDC
				WHERE CODCONCEPTO = JSON_VALUE(@PARAMETROS, '$.CODCONCEPTO')
				) <> 0
			SELECT CODCONCEPTO AS CODCONCEPTO_BASE, DESCRIPCION, TIPO, CLASE
			FROM NCON
			WHERE CODCONCEPTO NOT IN (
					SELECT CODCONCEPTO_BASE
					FROM NCONDC
					WHERE CODCONCEPTO = JSON_VALUE(@PARAMETROS, '$.CODCONCEPTO')
					) AND TIPO = 'Ingreso' AND ESTADO = 'Activo'
		ELSE
			SELECT CODCONCEPTO AS CODCONCEPTO_BASE, DESCRIPCION, TIPO, CLASE
			FROM NCON
			WHERE TIPO = 'Ingreso' AND ESTADO = 'Activo'

		SELECT NCONDC.CODCONCEPTO_BASE, NCON.DESCRIPCION, REQUIERELIQ, VALHORASLAB, HORAS, DIAS, NCONDC.ITEM, NCONDC.CODCONCEPTO, NCONDC.AUTOITEM_BASE
		FROM NCONDC
		INNER JOIN NCON ON NCONDC.CODCONCEPTO_BASE = NCON.CODCONCEPTO
		WHERE NCONDC.CODCONCEPTO = JSON_VALUE(@PARAMETROS, '$.CODCONCEPTO')

		RETURN
	END

	IF @METODO = 'ADD'
	BEGIN
		BEGIN TRY
			SELECT @DATOS = DATOS, @CODCONCEPTO = CODCONCEPTO, @ITEM = ITEM
			FROM OPENJSON(@PARAMETROS) WITH (DATOS NVARCHAR(MAX) AS JSON, CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO', ITEM DECIMAL(14, 0) '$.ITEM'
					)

			CREATE TABLE #temporal (ID INT IDENTITY(1, 1) NOT NULL PRIMARY KEY, CODCONCEPTO VARCHAR(20), ITEM DECIMAL(14, 0), CODCONCEPTO_BASE VARCHAR(20)
				)

			BEGIN
				INSERT INTO #temporal (CODCONCEPTO, ITEM, CODCONCEPTO_BASE)
				SELECT jSON_VALUE(@PARAMETROS, '$.CODCONCEPTO'), jSON_VALUE(@PARAMETROS, '$.ITEM'), jSON_VALUE(value, '$.CODCONCEPTO_BASE')
				FROM OPENJSON(@DATOS)

				INSERT INTO NCONDC (CODCONCEPTO, ITEM, CODCONCEPTO_BASE, REQUIERELIQ, VALHORASLAB, HORAS, DIAS)
				SELECT CODCONCEPTO, ITEM, CODCONCEPTO_BASE, 1, 1, NULL, NULL
				FROM #temporal
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'REMOVE'
	BEGIN
		BEGIN TRY
			SELECT @DATOS = DATOS, @CODCONCEPTO = CODCONCEPTO, @ITEM = ITEM
			FROM OPENJSON(@PARAMETROS) WITH (DATOS NVARCHAR(MAX) AS JSON, CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO', ITEM DECIMAL(14, 0) '$.ITEM'
					)

			BEGIN
				SELECT @CollationName = CONVERT(NVARCHAR(150), DATABASEPROPERTYEX(DB_NAME(), 'Collation'));

				SET NOCOUNT ON;

				CREATE TABLE #temp (ID INT IDENTITY(1, 1) NOT NULL PRIMARY KEY, CODCONCEPTO VARCHAR(20), ITEM DECIMAL(14, 0), CODCONCEPTO_BASE VARCHAR(20)
					)

				SET @SQL = 'ALTER TABLE #temp ALTER COLUMN CODCONCEPTO VARCHAR(20) COLLATE ' + @CollationName + 
					';ALTER TABLE #temp ALTER COLUMN CODCONCEPTO_BASE VARCHAR(20) COLLATE ' + @CollationName + ';';

				EXEC sp_executesql @SQL;

				INSERT INTO #temp (CODCONCEPTO, ITEM, CODCONCEPTO_BASE)
				SELECT @CODCONCEPTO COLLATE DATABASE_DEFAULT, JSON_VALUE(value, '$.ITEM') COLLATE DATABASE_DEFAULT, JSON_VALUE(value, '$.CODCONCEPTO_BASE') 
					COLLATE DATABASE_DEFAULT
				FROM OPENJSON(@DATOS);

				IF ISJSON(@DATOS) = 1
				BEGIN
					DELETE NCONDC
					FROM NCONDC
					INNER JOIN #temp T ON T.CODCONCEPTO = NCONDC.CODCONCEPTO AND NCONDC.ITEM = T.ITEM AND NCONDC.CODCONCEPTO_BASE = T.CODCONCEPTO_BASE

					DROP TABLE #temp;
				END
				ELSE
				BEGIN
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ('El parametro JSON no es valido.')
				END
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
