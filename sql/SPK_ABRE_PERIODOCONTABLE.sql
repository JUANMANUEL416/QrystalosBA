IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME = 'SPK_ABRE_PERIODOCONTABLE' AND XTYPE='P')
BEGIN
   DROP PROCEDURE SPK_ABRE_PERIODOCONTABLE
END

GO
CREATE PROC DBO.SPK_ABRE_PERIODOCONTABLE
@ANO     VARCHAR(4), 
@MES     INT,
@USUARIO VARCHAR(12)
WITH ENCRYPTION
AS
DECLARE @AUX    INT
DECLARE @ANOANT VARCHAR(4)
DECLARE @MESANT INT
DECLARE @PERI   VARCHAR(6)
BEGIN
   SELECT @AUX = COUNT(*) FROM PRI WHERE COALESCE(SI,0) = 1
   IF COALESCE(@AUX,0) > 1
   BEGIN
      RAISERROR('MAS DE UN PERIODO DEFINIDO COMO DE SALDOS INICIALES',16,1)
      RETURN
   END
   SELECT @AUX = COALESCE(SI,0) FROM PRI WHERE ANO = @ANO AND MES = @MES
   IF COALESCE(@AUX,0) > 0
   BEGIN
      RAISERROR('PERIODO ESTA DEFINIDO COMO DE SALDOS INICIALES',16,1)
      RETURN
   END
   
   SELECT @PERI = @ANO + CASE WHEN @MES < 10 THEN '0' + CONVERT(VARCHAR(1),@MES) ELSE CONVERT(VARCHAR(2),@MES) END
   PRINT 'ESTE ES PERI '+@PERI
   IF (SELECT COUNT(*) 
       FROM   PRI 
       WHERE  COALESCE(SI,0) = 0 
       AND    PRI.ANO + CASE WHEN PRI.MES < 10 THEN '0' + PRI.MES ELSE PRI.MES END > @PERI
       AND    COALESCE(CERRADO,0) = 1 
      ) > 0
   BEGIN
      RAISERROR('EXISTEN PERIODOS POSTERIORES CERRADOS' ,16,1)
      RETURN   
   END
   
   SELECT @AUX = COALESCE(PRI.CERRADO,0) FROM PRI WHERE ANO = @ANO AND MES = @MES
   IF @AUX = 0
   BEGIN
      RAISERROR('PERIODO ABIERTO ',16,1)
      RETURN
   END  
           
   --BORRAMOS SALDOS DEL MES
   DELETE SALDOMES WHERE ANO = @ANO AND MES = @MES  
   --BORRAMOS SALDOS DEL MES X TERCERO
   DELETE SALDOMESTER WHERE ANO = @ANO AND MES = @MES  
   -- ABRIMOS EL PERIODO
   UPDATE PRI SET CERRADO = 0 WHERE ANO = @ANO AND MES = @MES AND COMPANIA = '01'
   
END
