/*
  CxP Compras — septiembre y octubre 2026 (CEM).
  Patrón 01CM000853: VALOR (bruto UI) = sum(cant×valor) pero VLR_NETO cab > VALOR.
  Solo SELECT.
*/
SET NOCOUNT ON;

DECLARE @DESDE date = '2026-09-01';
DECLARE @HASTA date = '2026-10-31';

IF OBJECT_ID('tempdb..#RES') IS NOT NULL DROP TABLE #RES;

SELECT
  P.CNSFCXP,
  P.NOREFERENCIA,
  P.F_FACTURAREF,
  P.ESTADO,
  P.CONTABILIZADA,
  P.NROCOMPROBANTE,
  CONVERT(decimal(18, 2), P.VALOR) AS VALOR_BRUTO,
  CONVERT(decimal(18, 2), P.VLR_NETO) AS NETO_CAB,
  CONVERT(decimal(18, 2), SUM(D.CANTIDAD * D.VALOR)) AS SUM_CANT_VALOR,
  CONVERT(decimal(18, 2), SUM(D.VLR_NETO)) AS SUM_NETO_DET,
  CONVERT(decimal(18, 2), P.VLR_NETO - P.VALOR) AS DIF_BRUTO_NETO_CAB,
  COUNT(D.ITEM) AS LINEAS,
  SUM(
    CASE
      WHEN ABS(D.VLR_NETO - (D.CANTIDAD * D.VALOR + COALESCE(D.VLR_IVA, 0) - COALESCE(D.VLR_DESCUENTO, 0))) > 1
      THEN 1 ELSE 0
    END
  ) AS LINEAS_MAL
INTO #RES
FROM dbo.FCXP P
INNER JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
WHERE P.PROCEDENCIA = N'Compras'
  AND P.ESTADO <> N'A'
  AND P.F_FACTURAREF >= @DESDE
  AND P.F_FACTURAREF <= @HASTA
GROUP BY
  P.CNSFCXP, P.NOREFERENCIA, P.F_FACTURAREF, P.ESTADO,
  P.CONTABILIZADA, P.NROCOMPROBANTE, P.VALOR, P.VLR_NETO;

SELECT
  YEAR(F_FACTURAREF) AS ANO,
  MONTH(F_FACTURAREF) AS MES,
  COUNT(*) AS TOTAL_CXP,
  SUM(CASE WHEN ABS(DIF_BRUTO_NETO_CAB) > 0.01 THEN 1 ELSE 0 END) AS BRUTO_DIF_NETO_CAB,
  SUM(CASE WHEN ABS(NETO_CAB - SUM_NETO_DET) > 0.01 THEN 1 ELSE 0 END) AS CAB_DIF_DET,
  SUM(CASE WHEN LINEAS_MAL > 0 THEN 1 ELSE 0 END) AS CON_LINEAS_MAL,
  SUM(CASE
        WHEN ABS(DIF_BRUTO_NETO_CAB) > 0.01
         AND ABS(VALOR_BRUTO - SUM_CANT_VALOR) <= 0.01
         AND LINEAS_MAL > 0
        THEN 1 ELSE 0
      END) AS PATRON_01CM000853,
  SUM(CASE WHEN COALESCE(CONTABILIZADA, 0) <> 0 THEN 1 ELSE 0 END) AS CONTABILIZADAS,
  SUM(CASE
        WHEN ABS(DIF_BRUTO_NETO_CAB) > 0.01
         AND ABS(VALOR_BRUTO - SUM_CANT_VALOR) <= 0.01
         AND LINEAS_MAL > 0
         AND COALESCE(CONTABILIZADA, 0) = 0
        THEN 1 ELSE 0
      END) AS PATRON_SIN_CONTAB
FROM #RES
GROUP BY YEAR(F_FACTURAREF), MONTH(F_FACTURAREF)
ORDER BY ANO, MES;

SELECT
  CNSFCXP,
  NOREFERENCIA,
  CONVERT(varchar(10), F_FACTURAREF, 103) AS F_FACT,
  CONTABILIZADA,
  NROCOMPROBANTE,
  VALOR_BRUTO,
  NETO_CAB,
  DIF_BRUTO_NETO_CAB,
  LINEAS,
  LINEAS_MAL
FROM #RES
WHERE ABS(DIF_BRUTO_NETO_CAB) > 0.01
  AND ABS(VALOR_BRUTO - SUM_CANT_VALOR) <= 0.01
  AND LINEAS_MAL > 0
ORDER BY F_FACTURAREF, CNSFCXP;

DROP TABLE #RES;
