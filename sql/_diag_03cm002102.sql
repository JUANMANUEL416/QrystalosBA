SET NOCOUNT ON;
DECLARE @CNS VARCHAR(20) = N'03CM002102';

SELECT P.CNSFCXP, P.NOREFERENCIA, P.VLR_NETO, P.VLR_IVA, P.CONTABILIZADA, P.ESTADO, P.CUECREDITO
FROM dbo.FCXP P WHERE P.CNSFCXP = @CNS;

SELECT D.ITEM, D.IDSERVICIO, D.CANTIDAD, D.VALOR, D.VLR_IVA, D.VLR_NETO,
  D.CUENTA_SER, D.CUENTA_IVA, D.CCOSTO, D.N_PRESUP
FROM dbo.FCXPD D WHERE D.CNSFCXP = @CNS ORDER BY D.ITEM;

SELECT D.ITEM, A.IDITAR, I.DESCRIPCION AS ITAR,
  C.MCUEGRAV, C.CUENTAGRAV, C.CUENTAREV
FROM dbo.FCXPD D
JOIN dbo.IART A ON A.IDARTICULO = D.IDSERVICIO
LEFT JOIN dbo.ITAR I ON I.IDITAR = A.IDITAR
LEFT JOIN dbo.CUE C ON C.CUENTA = D.CUENTA_SER
WHERE D.CNSFCXP = @CNS;
