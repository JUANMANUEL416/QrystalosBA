							INNER JOIN FCOMD ON FCOM.CNSFCOM = FCOMD.CNSFCOM AND  ITRAH.IDARTICULOORI=FCOMD.IDARTICULO
				WHERE ITRAH.CNSITRA=@CNSITRA

				DECLARE @CNSFCOM_PROC VARCHAR(20)
				SELECT @CNSFCOM_PROC = CNSFCOM FROM ITRA WHERE CNSITRA = @CNSITRA

				DECLARE FALTANTES CURSOR FOR 
					SELECT DISTINCT COALESCE(IDARTICULOORI,IDARTICULO)
					FROM ITRAH
					WHERE CNSITRA=@CNSITRA AND COALESCE(INICIAL,0)=0

			   OPEN FALTANTES
			   FETCH NEXT FROM FALTANTES  INTO @IDARTICULO
			   WHILE @@fetch_status=0
			   BEGIN
					SELECT @CANTOTAL=SUM(CANTIDADORI)
					FROM ITRAH
					WHERE CNSITRA=@CNSITRA
					  AND COALESCE(INICIAL,0)=1
					  AND COALESCE(NOLOTE,'') NOT IN ('','0')
					  AND (
						   COALESCE(IDARTICULOORI,IDARTICULO)=@IDARTICULO
						   OR IDARTICULO LIKE @IDARTICULO + '-%'
					  )

					SELECT @CANTORG = COALESCE(SUM(B.CANTIDADORI), 0)
					FROM ITRAH B
					WHERE B.CNSITRA = @CNSITRA
					  AND COALESCE(B.INICIAL, 0) = 0
					  AND COALESCE(B.IDARTICULOORI, B.IDARTICULO) = @IDARTICULO

					IF COALESCE(@CANTORG, 0) = 0 AND COALESCE(@CNSFCOM_PROC, '') <> ''
						SELECT @CANTORG = SUM(D.CANTIDAD)
						FROM FCOMD D
						WHERE D.CNSFCOM = @CNSFCOM_PROC AND D.IDARTICULO = @IDARTICULO

					SELECT @CANT=@CANTORG-COALESCE(@CANTOTAL,0)

					IF @CANT>0
					BEGIN 
						;WITH B AS (
							SELECT NOLOTE, ROW_NUMBER() OVER (ORDER BY NOLOTE) AS RN
							FROM ITRAH
							WHERE CNSITRA=@CNSITRA AND COALESCE(IDARTICULOORI,IDARTICULO)=@IDARTICULO AND COALESCE(INICIAL,0)=0
						)
						DELETE FROM ITRAH
						WHERE CNSITRA=@CNSITRA AND COALESCE(IDARTICULOORI,IDARTICULO)=@IDARTICULO AND COALESCE(INICIAL,0)=0
						AND NOLOTE IN (SELECT NOLOTE FROM B WHERE RN > 1)

						UPDATE ITRAH SET CANTIDADORI=@CANT, CANTIDADDES=0
						WHERE CNSITRA=@CNSITRA  AND COALESCE(IDARTICULOORI,IDARTICULO)=@IDARTICULO  AND COALESCE(INICIAL,0)= 0 
					END
					ELSE IF @CANT = 0 AND COALESCE(@CANTORG,0) > 0
					BEGIN
						DELETE FROM ITRAH
						WHERE CNSITRA=@CNSITRA
						  AND COALESCE(IDARTICULOORI,IDARTICULO)=@IDARTICULO
						  AND COALESCE(INICIAL,0)=0
					END
					FETCH NEXT FROM FALTANTES INTO @IDARTICULO
			   END

			   CLOSE FALTANTES
			   DEALLOCATE FALTANTES

				UPDATE MOV_TRAN SET MOV_TRAN.ESTADO = 'Procesado' FROM MOV_TRAN, ITRAH 
				WHERE MOV_TRAN.CNS = @CNSRPDX AND MOV_TRAN.CNSITRA = @CNSITRA AND ITRAH.CNSITRA = @CNSITRA 
					AND ITRAH.IDARTICULO = MOV_TRAN.IDARTICULO_DET AND MOV_TRAN.ESTADO = 'Activo' AND MOV_TRAN.NOLOTE = ITRAH.NOLOTE
					AND MOV_TRAN.NOLOTEPEDIDO = ITRAH.NOLOTEPEDIDO AND MOV_TRAN.CLASE = 'D'
				UPDATE MOV_TRAN SET MOV_TRAN.ESTADO = 'Procesado' FROM MOV_TRAN 
				WHERE MOV_TRAN.CNSITRA = @CNSITRA AND MOV_TRAN.CNSITRA = @CNSITRA AND MOV_TRAN.CLASE = 'M' AND MOV_TRAN.ESTADO = 'Activo'

			END TRY  
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK
		END 

	END
END
