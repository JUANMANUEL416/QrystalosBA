CREATE OR ALTER PROCEDURE DBO.SPQ_IZSOL_TRANSITO
@JSON  NVARCHAR(MAX) 
WITH
ENCRYPTION
AS
DECLARE  @PARAMETROS   NVARCHAR(MAX) ,@MODELO           VARCHAR(100) ,@METODO           VARCHAR(100)  ,@USUARIO        VARCHAR(12),
			@GRUPO        VARCHAR(8)    ,@SYS_COMPUTERNAME VARCHAR(254) ,@IDSEDE             VARCHAR(5)    ,@USUNOMBRE     VARCHAR(100), @SEDE VARCHAR(5),
			@FECHA        VARCHAR(10)   ,@IDEMEDICA        VARCHAR(4)	,@FECHA1           DATETIME		,@SQL            VARCHAR(MAX),
			@COMPANIA		VARCHAR(10)	,@IDAFILIADO VARCHAR(20)	,@FECHAINI DATE	, @CODCAJERO VARCHAR(20)
			,@CNSITRA VARCHAR(20)	,@IDBODEGA VARCHAR(20)	,@CNSFCOM VARCHAR(20), @CNS VARCHAR(20)	, @NVOCONSEC VARCHAR(20)
			,@CNSRPDX VARCHAR(20)	,@ITEM INT,		@IDARTICULO VARCHAR(20), @IDARTICULO_REAL VARCHAR(20)	, @PROCESO VARCHAR(20)
			,@IDARTICULO_LINEA VARCHAR(20)	-- art�culo de la l�nea OC/MOV_TRAN padre (autocorrecci�n loteo)
DECLARE  @NOLOTE VARCHAR(20), @CANTIDAD DECIMAL(14,2), @FECHAVENCE DATE, @REGINVIMA VARCHAR(50) ,@CODIGOBARRA VARCHAR(20),@PCOSTO DECIMAL(14,2) , @CNSRPDX_2 VARCHAR(20)
DECLARE @F_VIGENCIAINV DATE, @PC_SINIVA DECIMAL(14,2),	@TEMPERATURA DECIMAL(14,2),	@CANTIDADREV DECIMAL(14,2), @PIVA DECIMAL(14,2)	, @CUMPLE BIT
			,@APROBADO BIT	,@VALIDA_STOCKS VARCHAR(200),@CANTIDAD_TOTAL DECIMAL(14,2)	, @IDITAR VARCHAR(20), @DESC_IDARTICULO_DET VARCHAR(200)	,@ITEM_2 INT
			,@OBSERVACION VARCHAR (1000), @CANTOTAL DECIMAL(14,2),  @CANTORG DECIMAL(14,2), @CANT    DECIMAL(14,2)
			,@CUARENTENA BIT
			,@OC_VLR_UNIT DECIMAL(14,2), @OC_FACTORIVA DECIMAL(14,2)
BEGIN 
	SET LANGUAGE Spanish;  
	SET DATEFORMAT dmy
	SELECT *
	INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)  AS JSON
	)

	SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON
	--DEFINICION DE TABLA DE ERRORES
	DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200));
	-- TOMA DEL GRUPO, SYS_COMPUTERNAME, SEDE   DE ACUERDO AL USUARIOpl,   --PRINT 'USUARIO:'+@USUARIO
	SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO), @USUNOMBRE = NOMBRE FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME, @COMPANIA = COMPANIA, @CODCAJERO= CODCAJERO FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @IDSEDE = IDSEDE, @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
	PRINT '@USUARIO='+@USUARIO

	IF @METODO = 'VALIDA_TRAN'
	BEGIN
		SELECT @CNSITRA = CNSITRA, @IDBODEGA = IDBODEGA
		FROM OPENJSON (@PARAMETROS)
		WITH		 (
		CNSITRA				VARCHAR(20)			'$.CNSITRA'
		,IDBODEGA			VARCHAR(20)			'$.IDBODEGA'
		)
		SELECT @CNSFCOM =  FCOM.CNSFCOM FROM  ITRA 
			INNER JOIN FCOM ON ITRA.CNSFCOM = FCOM.CNSFCOM
		WHERE ITRA.CNSITRA = @CNSITRA
	
		IF NOT EXISTS( SELECT * FROM ITRAH WHERE CNSITRA = @CNSITRA AND COALESCE(ITRAH.INICIAL,0)=0 )
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'No cuenta con registros para Lotear.'
		END
		IF EXISTS(SELECT  FCOM.CNSFCOM FROM  ITRA 
				INNER JOIN FCOM ON ITRA.CNSFCOM = FCOM.CNSFCOM
			WHERE ITRA.CNSITRA = @CNSITRA AND COALESCE(FCOM.CNSFCOM ,'') = '')
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'No existe CNSFCOM'
		END
		IF (SELECT COALESCE(VERIFDOC,'') FROM IBOD INNER JOIN ITBOD ON IBOD.IDTBODEGA=ITBOD.IDTBODEGA 
			 WHERE IBOD.IDBODEGA=@IDBODEGA) = 'Si' 
			 AND (SELECT COUNT(*) FROM VERIF WHERE TIPO='COMPRAS' AND REFERENCIA1 = @CNSFCOM) <= 0
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'No se Ha Diligenciado el Formato de Verificaci�n de Factura, Se debe Realizar la Verificaci�n Para Continuar.'
		END
		IF (SELECT COALESCE(VERIFDOC,'') FROM IBOD INNER JOIN ITBOD ON IBOD.IDTBODEGA=ITBOD.IDTBODEGA 
			 WHERE IBOD.IDBODEGA=@IDBODEGA) = 'Si' 
			 AND (SELECT COUNT(*) FROM VERIF WHERE TIPO='COMPRAS' AND REFERENCIA1 = @CNSFCOM AND CUMPLE = 0 ) > 0
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'Existen Requisitos De la Verificaci�n de Factura Que no se Cumple... No se puede Continuar.'
		END
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				SELECT @PROCESO = COALESCE(FCOM.PROCEDENCIA,'')  FROM FCOM WHERE CNSFCOM = @CNSFCOM
				IF NOT EXISTS (SELECT 1 FROM MOV_TRAN WHERE CNSITRA = @CNSITRA AND ESTADO = 'Activo')
				BEGIN
					SELECT @CNS = NULL
					EXEC SPQ_GENSEQUENCE @SEDE=@IDSEDE,@PREFIJO='@MOV_TRAN', @LONGITUD = 8, @NVOCONSEC=@CNS OUTPUT  
					--iva MLOTEO MPRINCIPAL PROCESO
					INSERT INTO MOV_TRAN (  CNS, CNSITRA, CNSFCOM, IDBODEGA, ESTADO, CLASE, IDSERVICIO, IDARTICULO, DESC_IART, IDARTICULO_DET, NOLOTE
							, NOLOTEPEDIDO, REGINVIMA, CANTIDADSOL, CANT_LOTEADA, CANT_FALTANTE, VALOR, VALORTOTAL
							, FECHA_VENCE, TEMPERATURA, REVISADAS, APROBADO, CUMPLE, MLOTEO, USUARIO, FECHA_REGISTRO
							, PROCEDENCIA, PROCESO, FECHA_INACTIVO, USUARIO_INCATIVA, ESTANTE
							, IVA, VR_DESCUENTO, IDIMPUESTO,VLR_UNITARIO, FACTORIVA , PCOSTO)
					SELECT @CNS, @CNSITRA, @CNSFCOM, @IDBODEGA, 'Activo', 'M', IART.IDSERVICIO, ITRAH.IDARTICULO, IART.DESCRIPCION, NULL,NULL, NULL,IART.REGINVIMA
					, ITRAH.CANTIDADORI
					, 0 /* LUEGO SE DEBE DE CALCULAR CON EL DETALLE QUE TRAIGA */
					, ITRAH.CANTIDADORI /* LUEGO SE DEBE DE CALCULAR CON EL DETALLE QUE TRAIGA */
					, ITRAH.PCOSTO, NULL,NULL,NULL,NULL,0, 0
					/*
					MLOTEO = 1 No deja lotear ni MERGAS											0
					MLOTEO = 0 y MPRINCIPAL = 1 Deja Lotear UNICAMENTE al Hijo					1
					MLOTEO = 0 y MPRINCIPAL = 0 Deja Lotear a papa e hijos por igual			2
					*/
					, CASE	WHEN COALESCE(ITAR.MLOTEO,0) = 1 THEN 0 
							WHEN COALESCE(ITAR.MLOTEO,0) = 0 AND COALESCE(ITAR.MPRINCIPAL,0) = 1 THEN 1 
							WHEN COALESCE(ITAR.MLOTEO,0) = 0 AND COALESCE(ITAR.MPRINCIPAL,0) = 0 THEN 2 END
					, @USUARIO, DBO.FNK_GETDATE(), NULL, @PROCESO, NULL,NULL
					,ESTANTE = (
									SELECT TOP 1 IARTE.ESTANTE
										,IDESTANTE = E.CODIGO
										,DESCESTANTE = E.DESCRIPCION
										,IDGRUPOEST = G.CODIGO
										,DESCGRUPOEST = G.DESCRIPCION
									FROM [dbo].[IARTE]
									INNER JOIN IART ON IARTE.IDARTICULO = IART.IDARTICULO
									INNER JOIN TGEN AS E ON E.CAMPO = 'ESTANTE' AND E.TABLA = IARTE.IDBODEGA AND CODIGO = IARTE.ESTANTE
									INNER JOIN TGEN AS G ON G.CAMPO = 'ESTANTE_P' AND E.TABLA = IARTE.IDBODEGA AND G.CODIGO = E.DATO1
									WHERE IARTE.IDBODEGA = @IDBODEGA
									AND IARTE.IDARTICULO = ITRAH.IDARTICULO
									ORDER BY E.DESCRIPCION
									FOR JSON PATH
								)
					, ROUND(CASE WHEN  COALESCE(FCOMD.FACTORIVA,0)<> 0 THEN FCOMD.VLR_UNITARIO * (FCOMD.FACTORIVA/100.00) ELSE 0 END,2)
					, ROUND(CASE WHEN  COALESCE(FCOMD.VR_DESCUENTO,0)<> 0 THEN FCOMD.VR_DESCUENTO / FCOMD.CANTIDAD ELSE 0 END,2)
				--	,  ROUND (ITRAH.CANTIDADDES * ROUND( ITRAH.PCOSTO / (1+((CASE COALESCE(FCOMD.IDIMPUESTO,'') WHEN '' THEN 0 ELSE FCOMD.FACTORIVA END)/100.00)),2) * ((CASE COALESCE(FCOMD.IDIMPUESTO,'') WHEN '' THEN 0 ELSE FCOMD.FACTORIVA END)/100.00) ,2 )

					, FCOMD.IDIMPUESTO, FCOMD.VLR_UNITARIO, FCOMD.FACTORIVA, ITRAH.PCOSTO
					FROM ITRAH 
						INNER JOIN ITRA ON ITRAH.CNSITRA = ITRA.CNSITRA
						INNER JOIN IART ON ITRAH.IDARTICULO=IART.IDARTICULO 
						INNER JOIN ITAR ON IART.IDITAR=ITAR.IDITAR
						LEFT JOIN FCOMD ON FCOMD.CNSFCOM = @CNSFCOM AND ITRAH.IDARTICULO = FCOMD.IDARTICULO
					WHERE COALESCE(ITRAH.INICIAL,0)=0 AND ITRAH.CNSITRA= @CNSITRA
					SELECT 'OK' OK, @CNS CNSRPDX
				END
				IF EXISTS (SELECT * FROM MOV_TRAN WHERE CNSITRA = @CNSITRA AND ESTADO = 'Activo')
				BEGIN
					SELECT TOP 1 @CNS = CNS FROM MOV_TRAN WHERE CNSITRA = @CNSITRA AND ESTADO = 'Activo'

					IF EXISTS (SELECT  1 FROM ITRAH,MOV_TRAN 
								WHERE ITRAH.CNSITRA = @CNSITRA AND COALESCE(ITRAH.INICIAL,0) = 0  
								AND MOV_TRAN.CNS = @CNS AND MOV_TRAN.CLASE = 'M' AND MOV_TRAN.ESTADO = 'Activo' 
								AND ITRAH.IDARTICULO <> MOV_TRAN.IDARTICULO)
					BEGIN
						INSERT INTO MOV_TRAN (CNS, CNSITRA, CNSFCOM, IDBODEGA, ESTADO, CLASE, IDSERVICIO, IDARTICULO, DESC_IART, IDARTICULO_DET, NOLOTE
							, NOLOTEPEDIDO, REGINVIMA, CANTIDADSOL, CANT_LOTEADA, CANT_FALTANTE, VALOR, VALORTOTAL
							, FECHA_VENCE, TEMPERATURA, REVISADAS, APROBADO, CUMPLE, MLOTEO, USUARIO, FECHA_REGISTRO
							, PROCEDENCIA, PROCESO, FECHA_INACTIVO, USUARIO_INCATIVA, ESTANTE
							, IVA, IDIMPUESTO,VLR_UNITARIO, FACTORIVA , PCOSTO)
						SELECT @CNS, @CNSITRA, @CNSFCOM, @IDBODEGA, 'Activo', 'M', IART.IDSERVICIO, ITRAH.IDARTICULO, IART.DESCRIPCION, NULL,NULL, NULL,IART.REGINVIMA
							, ITRAH.CANTIDADORI
							, 0 /* LUEGO SE DEBE DE CALCULAR CON EL DETALLE QUE TRAIGA */
							, ITRAH.CANTIDADORI /* LUEGO SE DEBE DE CALCULAR CON EL DETALLE QUE TRAIGA */
							, ITRAH.PCOSTO, NULL,NULL,NULL,NULL,0, 0, COALESCE(ITAR.MLOTEO,0) MLOTEO, @USUARIO, DBO.FNK_GETDATE(), NULL, @PROCESO, NULL,NULL
							,ESTANTE = (
											SELECT TOP 1 IARTE.ESTANTE
												,IDESTANTE = E.CODIGO
												,DESCESTANTE = E.DESCRIPCION
												,IDGRUPOEST = G.CODIGO
												,DESCGRUPOEST = G.DESCRIPCION
											FROM [dbo].[IARTE]
											INNER JOIN IART ON IARTE.IDARTICULO = IART.IDARTICULO
											INNER JOIN TGEN AS E ON E.CAMPO = 'ESTANTE' AND E.TABLA = IARTE.IDBODEGA AND CODIGO = IARTE.ESTANTE
											INNER JOIN TGEN AS G ON G.CAMPO = 'ESTANTE_P' AND E.TABLA = IARTE.IDBODEGA AND G.CODIGO = E.DATO1
											WHERE IARTE.IDBODEGA = @IDBODEGA
											AND IARTE.IDARTICULO = ITRAH.IDARTICULO
											ORDER BY E.DESCRIPCION
											FOR JSON PATH
										)
							, COALESCE(FCOMD.IVA,0), FCOMD.IDIMPUESTO, FCOMD.VLR_UNITARIO, FCOMD.FACTORIVA, ITRAH.PCOSTO
						FROM ITRAH  
							INNER JOIN ITRA ON ITRAH.CNSITRA = ITRA.CNSITRA
							INNER JOIN IART ON ITRAH.IDARTICULO=IART.IDARTICULO 
							INNER JOIN ITAR ON IART.IDITAR=ITAR.IDITAR
							LEFT JOIN FCOMD ON FCOMD.CNSFCOM = @CNSFCOM AND ITRAH.IDARTICULO = FCOMD.IDARTICULO
						WHERE  ITRAH.CNSITRA = @CNSITRA AND COALESCE(ITRAH.INICIAL,0) = 0  
								AND NOT EXISTS (SELECT * FROM MOV_TRAN WHERE MOV_TRAN.CNS = @CNS AND MOV_TRAN.CLASE = 'M' AND MOV_TRAN.ESTADO = 'Activo' AND MOV_TRAN.CNSITRA = @CNSITRA
												AND ITRAH.IDARTICULO = MOV_TRAN.IDARTICULO )
					END

					SELECT 'OK' OK, @CNS CNSRPDX, CASE WHEN ITRA.IDTIPOMOV = DBO.FNK_VALORVARIABLE('IDINVMOV_COMPRAS') THEN 'ESCOMPRA' ELSE 'NOESCOMPRA' END ESCOM 
               FROM ITRA WHERE  CNSITRA =@CNSITRA
				END
			END TRY  
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK
		END 
	END
	IF @METODO = 'SEL_RPDX'
	BEGIN
		SELECT @CNSITRA = CNSITRA, @IDBODEGA = IDBODEGA, @CNSRPDX = CNSRPDX
		FROM OPENJSON (@PARAMETROS)
		WITH	(
			 CNSITRA	VARCHAR(20)		'$.CNSITRA'
			,IDBODEGA	VARCHAR(20)		'$.IDBODEGA'
			,CNSRPDX	VARCHAR(20)		'$.CNSRPDX'
		)
		SELECT 'OK' AS OK --PROCESO

		SELECT ITEM, CNS, CNSITRA, CNSFCOM, IDBODEGA, ESTADO, CLASE, IDSERVICIO, IDARTICULO, DESC_IART, IDARTICULO_DET
		, DESC_IDARTICULO_DET, NOLOTE, NOLOTEPEDIDO, REGINVIMA, CANTIDADSOL, CANT_LOTEADA, CANT_FALTANTE, IVA, IDIMPUESTO
		, VLR_UNITARIO, FACTORIVA, PCOSTO, VALOR, VALORTOTAL, FECHA_VENCE, TEMPERATURA, REVISADAS, APROBADO, CUMPLE, MLOTEO
		, ESTANTE, USUARIO, FECHA_REGISTRO, PROCEDENCIA, PROCESO, FECHA_INACTIVO, USUARIO_INCATIVA
		FROM MOV_TRAN
		WHERE MOV_TRAN.CNS = @CNSRPDX AND MOV_TRAN.CLASE = 'M' AND MOV_TRAN.ESTADO = 'Activo'

		SELECT ITEM, CNS, CNSITRA, CNSFCOM, IDBODEGA, ESTADO, CLASE, IDSERVICIO, IDARTICULO, DESC_IART, IDARTICULO_DET
		, DESC_IDARTICULO_DET, NOLOTE, NOLOTEPEDIDO, REGINVIMA, CANTIDADSOL, CANT_LOTEADA, CANT_FALTANTE, IVA, IDIMPUESTO
		, VLR_UNITARIO, FACTORIVA, PCOSTO, VALOR, VALORTOTAL, FECHA_VENCE, TEMPERATURA, REVISADAS, APROBADO, CUMPLE, MLOTEO
		, ESTANTE, USUARIO, FECHA_REGISTRO, PROCEDENCIA, PROCESO, FECHA_INACTIVO, USUARIO_INCATIVA
		FROM MOV_TRAN
		WHERE MOV_TRAN.CNS = @CNSRPDX AND MOV_TRAN.CLASE = 'D' AND MOV_TRAN.ESTADO = 'Activo'

		RETURN
	END
	IF @METODO = 'SEL_IART'
	BEGIN
		SELECT @CNSITRA = CNSITRA, @IDBODEGA = IDBODEGA, @CNSRPDX = CNSRPDX, @ITEM = ITEM
		FROM OPENJSON (@PARAMETROS)
		WITH		 (
		CNSITRA				VARCHAR(20)					'$.CNSITRA'
		,IDBODEGA			VARCHAR(20)					'$.IDBODEGA'
		,CNSRPDX			VARCHAR(20)					'$.CNSRPDX'
		,ITEM				INT							'$.ITEM'
		)
			
		BEGIN TRY 
			SELECT 'OK' AS OK
			SELECT @IDARTICULO = IDARTICULO, @IDARTICULO_REAL = IDARTICULO, @PROCESO = COALESCE(PROCESO,'') FROM MOV_TRAN WHERE MOV_TRAN.ITEM = @ITEM
			IF @IDBODEGA = DBO.FNK_VALORVARIABLE('IDBOD_HEMODERIVADOS')  
			BEGIN
				PRINT 'ACA'
				SELECT IART.IDARTICULO, IART.BIOLOGICO, IART.DESCRIPCION, IART.REGINVIMA, IART.F_VIGENCIAINV,DBO.FNK_SEMAFORO_TRANSITO(IART.F_VIGENCIAINV,'HEMO') PRIORIDAD , IART.CODCUM, IART.IDALTERNA , IART.IDSERVICIO, COALESCE(IART.PRINCIPAL,0) PRINCIPAL
					,IART.CODBARRA, IART.IDITAR, ITAR.MFECHAVENCIMIENTO, COALESCE(ITAR.MPRINCIPAL,0) MPRINCIPAL
				FROM IART 
					LEFT JOIN ITAR ON IART.IDITAR = ITAR.IDITAR
				WHERE IART.IDARTICULO = @IDARTICULO		
				ORDER BY  COALESCE(PRINCIPAL,0) DESC ,IART.F_VIGENCIAINV  ASC
			END
			ELSE
			BEGIN

				IF NOT EXISTS(SELECT 1 FROM IART WHERE IDSERVICIO = @IDARTICULO AND PRINCIPAL=1) -- EZ PERU COMPRA FABRICANTES EN LUGAR DE PRINCIPAL
				BEGIN
					SELECT @IDARTICULO  = IDSERVICIO FROM IART WHERE IDARTICULO = @IDARTICULO
				END
				IF DBO.FNK_VALORVARIABLE('DEINVNODESER') = @IDARTICULO
				BEGIN
					PRINT '1'
					SELECT IART.IDARTICULO	,IART.DESCRIPCION	,IART.REGINVIMA
						,IART.F_VIGENCIAINV, IART.BIOLOGICO
						,PRIORIDAD = CASE COALESCE(IART.PRINCIPAL, 0) 
							WHEN 0 THEN DBO.FNK_SEMAFORO_TRANSITO(IART.F_VIGENCIAINV,'')
							ELSE NULL END 
						,PRIORIDAD_DESC = CASE WHEN COALESCE(IART.PRINCIPAL, 0) = 0 AND DBO.FNK_SEMAFORO_TRANSITO(IART.F_VIGENCIAINV,'') = 1 THEN 'INVIMA vencido' 
							WHEN COALESCE(IART.PRINCIPAL, 0) = 0 AND DBO.FNK_SEMAFORO_TRANSITO(IART.F_VIGENCIAINV,'') = 2 THEN 'INVIMA Vigente'
							WHEN COALESCE(IART.PRINCIPAL, 0) = 0 AND DBO.FNK_SEMAFORO_TRANSITO(IART.F_VIGENCIAINV,'') = 3 THEN 'INVIMA por Vencer'
							ELSE NULL END
						,IART.CODCUM	,IART.IDALTERNA			,IART.IDSERVICIO	
						,COALESCE(IART.PRINCIPAL, 0) PRINCIPAL	,IART.CODBARRA
						,IART.IDITAR	,ITAR.MFECHAVENCIMIENTO ,COALESCE(ITAR.MPRINCIPAL, 0) MPRINCIPAL
					
					FROM IART
					LEFT JOIN ITAR ON IART.IDITAR = ITAR.IDITAR
					WHERE IART.IDARTICULO = @IDARTICULO_REAL
					--AND (COALESCE(ITAR.MPRINCIPAL, 0) = 0 OR (COALESCE(ITAR.MPRINCIPAL, 0) = 1 AND COALESCE(IART.PRINCIPAL, 0)=0))
					ORDER BY COALESCE(PRINCIPAL, 0) DESC, IART.F_VIGENCIAINV ASC
				END
				IF DBO.FNK_VALORVARIABLE('DEINVNODESER') <> @IDARTICULO AND COALESCE(@PROCESO,'') in ( '', 'IEXIF')
 				BEGIN
					PRINT '2'
					--SELECT @IDARTICULO,  @IDARTICULO_REAL, @PROCESO
					SELECT IART.IDARTICULO	,IART.DESCRIPCION	,IART.REGINVIMA
						,IART.F_VIGENCIAINV, IART.BIOLOGICO
						,PRIORIDAD = CASE COALESCE(IART.PRINCIPAL, 0) 
							WHEN 0 THEN DBO.FNK_SEMAFORO_TRANSITO(IART.F_VIGENCIAINV,'')
							ELSE NULL END 
						,PRIORIDAD_DESC = CASE WHEN COALESCE(IART.PRINCIPAL, 0) = 0 AND DBO.FNK_SEMAFORO_TRANSITO(IART.F_VIGENCIAINV,'') = 1 THEN 'INVIMA vencido' 
							WHEN COALESCE(IART.PRINCIPAL, 0) = 0 AND DBO.FNK_SEMAFORO_TRANSITO(IART.F_VIGENCIAINV,'') = 2 THEN 'INVIMA Vigente'
							WHEN COALESCE(IART.PRINCIPAL, 0) = 0 AND DBO.FNK_SEMAFORO_TRANSITO(IART.F_VIGENCIAINV,'') = 3 THEN 'INVIMA por Vencer'
							ELSE NULL END
						,IART.CODCUM	,IART.IDALTERNA			,IART.IDSERVICIO	
						,COALESCE(IART.PRINCIPAL, 0) PRINCIPAL	,IART.CODBARRA
						,IART.IDITAR	,ITAR.MFECHAVENCIMIENTO ,COALESCE(ITAR.MPRINCIPAL, 0) MPRINCIPAL
					FROM IART
					LEFT JOIN ITAR ON IART.IDITAR = ITAR.IDITAR
					WHERE IART.IDSERVICIO = @IDARTICULO
					--AND (COALESCE(ITAR.MPRINCIPAL, 0) = 0 OR (COALESCE(ITAR.MPRINCIPAL, 0) = 1 AND COALESCE(IART.PRINCIPAL, 0)=0))
					ORDER BY COALESCE(PRINCIPAL, 0) DESC, IART.F_VIGENCIAINV ASC
				END
				--IF DBO.FNK_VALORVARIABLE('DEINVNODESER') <> @IDARTICULO AND COALESCE(@PROCESO,'') in ( '', 'IEXIF')
				IF DBO.FNK_VALORVARIABLE('DEINVNODESER') <> @IDARTICULO AND COALESCE(@PROCESO,'') in ( 'ILPRE')
 				BEGIN
					PRINT '3'
					--SELECT @IDARTICULO,  @IDARTICULO_REAL, @PROCESO
					SELECT IART.IDARTICULO	,IART.DESCRIPCION	,IART.REGINVIMA
						,IART.F_VIGENCIAINV, IART.BIOLOGICO
						,PRIORIDAD = CASE COALESCE(IART.PRINCIPAL, 0) 
							WHEN 0 THEN DBO.FNK_SEMAFORO_TRANSITO(IART.F_VIGENCIAINV,'')
							ELSE NULL END 
