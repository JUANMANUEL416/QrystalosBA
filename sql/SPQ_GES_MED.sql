CREATE OR ALTER PROCEDURE DBO.SPQ_GES_MED
@JSON NVARCHAR(MAX)
WITH ENCRYPTION
AS
DECLARE   @PARAMETROS       NVARCHAR(MAX)		,@MODELO			VARCHAR(100)	,@METODO			VARCHAR(100)
		,@USUARIO			VARCHAR(12)			,@NVOCONSEC			VARCHAR(20)		,@CANTIDAD			INT
		,@SEDE				VARCHAR(5)			,@CONSECUTIVOS		NVARCHAR(MAX)	,@PROCESO			VARCHAR(20)
		,@NOADMISION		VARCHAR(20)			,@CNSMOV			VARCHAR(20)		,@IDARTICULO		VARCHAR(20)
		,@NOLOTE			VARCHAR(20)			,@IDBODEGA			VARCHAR(20)		,@COMPANIA			VARCHAR(5)
		,@IDSEDE			VARCHAR(5)			,@SYS_COMPUTERNAME	VARCHAR(50)		,@GRUPO				VARCHAR(50)
		,@CNSIZSOL			VARCHAR(20)			,@ESTADO			INT
DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200));
BEGIN
	SET DATEFORMAT dmy
	SELECT * INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		MODELO  VARCHAR(100) '$.MODELO',
		METODO  VARCHAR(100) '$.METODO',
		USUARIO VARCHAR(20) '$.USUARIO',
		PARAMETROS NVARCHAR(MAX) AS JSON
	)
	SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @IDSEDE = IDSEDE, @SEDE = IDSEDE, @COMPANIA=COMPANIA, @IDBODEGA = COALESCE(IDBODEGA, IDBODEGA2, IDBODEGANOCHE, IDBODEGACONSUMO) FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
	SELECT @GRUPO = (SELECT DBO.FNK_DESCIFRAR(USUSU.GRUPO) FROM USUSU WHERE  USUARIO = @USUARIO)
	--DEFINICION DE TABLA DE ERRORES
	--
	IF @METODO = 'REGRESA_ENFERMERIA'
	BEGIN
		SELECT  @CONSECUTIVOS = CONSECUTIVOS , @PROCESO = PROCESO
		FROM OPENJSON(@PARAMETROS)
		WITH( CONSECUTIVOS		NVARCHAR(MAX) AS JSON
			,PROCESO		VARCHAR(20)		'$.PROCESO')
		
		SELECT * INTO #CONSECUTIVOS FROM  OPENJSON(@CONSECUTIVOS)
		WITH (	CNSMOV		VARCHAR(20)			'$.CNSMOV'
				,NOLOTE		VARCHAR(20)			'$.NOLOTE' )
		
		IF 1 = 2
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El registro ya se encuentra Terminado'
		END
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				IF @PROCESO = 'SI'
				BEGIN
					UPDATE IMOVH SET RENFER = IIF(CANTREP>0,2,0), USUARIOR = NULL FROM IMOVH ,  #CONSECUTIVOS
					WHERE IMOVH.CNSMOV = #CONSECUTIVOS.CNSMOV AND IMOVH.NOLOTE = #CONSECUTIVOS.NOLOTE
				END
				IF @PROCESO = 'NO'
				BEGIN
					UPDATE IMOVH SET  RENFER = 2, USUARIOR = NULL FROM IMOVH ,  #CONSECUTIVOS
					WHERE IMOVH.CNSMOV = #CONSECUTIVOS.CNSMOV AND IMOVH.NOLOTE = #CONSECUTIVOS.NOLOTE
				END
			END TRY
			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;
			END CATCH
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK
		END
	END
	IF @METODO = 'RECIBIR_DEVOLUCION'
	BEGIN
		SELECT  @CONSECUTIVOS = CONSECUTIVOS , @NOADMISION = NOADMISION
		FROM OPENJSON(@PARAMETROS)
		WITH( CONSECUTIVOS		NVARCHAR(MAX) AS JSON
			,NOADMISION			VARCHAR(20)		'$.NOADMISION')
	
		-- ? MODIFICACI�N: Ahora se recibe el IDARTICULO desde el JSON
		SELECT ROW_NUMBER() OVER(ORDER BY NOLOTE DESC) AS FILA_CITA,* INTO #CONSECUTIVOS_2 FROM  OPENJSON(@CONSECUTIVOS)
		WITH (	CNSMOV		VARCHAR(20)			'$.CNSMOV'
				,NOLOTE		VARCHAR(20)			'$.NOLOTE'
				,IDARTICULO	VARCHAR(20)			'$.IDARTICULO' )  -- ? NUEVO: Recibir IDARTICULO del JSON
	
		IF 1 = 2
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El registro ya se encuentra Terminado'
		END
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				DECLARE @ITEM_AUTD INT
				DECLARE @LIMITE_AU INT
				SELECT @ITEM_AUTD=1,@LIMITE_AU=0
				SELECT @LIMITE_AU=COUNT(*) FROM  #CONSECUTIVOS_2
				WHILE @ITEM_AUTD<=@LIMITE_AU
				BEGIN
					-- ? MODIFICACI�N: Usar el IDARTICULO recibido del JSON en lugar de obtenerlo de IMOVH
					-- Si el IDARTICULO viene en el JSON, usarlo; si no, obtenerlo de IMOVH como respaldo
					SELECT @CNSMOV = #CONSECUTIVOS_2.CNSMOV
						  ,@NOLOTE = #CONSECUTIVOS_2.NOLOTE
						  ,@IDARTICULO = COALESCE(#CONSECUTIVOS_2.IDARTICULO, IMOVH.IDARTICULO)  -- ? Usar IDARTICULO del JSON, con fallback a IMOVH
						  ,@CANTIDAD = IMOVH.RENFER
					FROM #CONSECUTIVOS_2
					LEFT JOIN IMOVH ON IMOVH.CNSMOV = #CONSECUTIVOS_2.CNSMOV AND IMOVH.NOLOTE = #CONSECUTIVOS_2.NOLOTE
					WHERE #CONSECUTIVOS_2.FILA_CITA = @ITEM_AUTD
				
					-- Validar que el IDARTICULO existe
					IF @IDARTICULO IS NULL OR @IDARTICULO = ''
					BEGIN
						INSERT INTO @TBLERRORES(ERROR) SELECT 'IDARTICULO no v�lido para CNSMOV: ' + @CNSMOV + ', NOLOTE: ' + @NOLOTE
						SELECT @ITEM_AUTD = @ITEM_AUTD+1
						CONTINUE
					END
				
					-- ? Usar el IDARTICULO recibido (o el obtenido de IMOVH como respaldo) para el proceso
					EXEC SPK_RECUPERA_NORECIBIDOS_ENF @CNSMOV, @IDARTICULO, @NOLOTE, @NOADMISION, @USUARIO, @SEDE, @SYS_COMPUTERNAME, 1
				
					SELECT @ITEM_AUTD = @ITEM_AUTD+1
				END
			END TRY
			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;
			END CATCH
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
		
			SELECT 'OK'OK
		END
	END
END
