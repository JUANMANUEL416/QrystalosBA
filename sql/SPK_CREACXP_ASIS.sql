CREATE PROCEDURE DBO.SPK_CREACXP_ASIS
@NOADMISION    VARCHAR(16),  
@COMPANIA      VARCHAR(2),  
@SEDE          VARCHAR(5),  
@USUARIO       VARCHAR(12),
@NVOCONSECFTR  VARCHAR(20)
WITH ENCRYPTION
AS      
DECLARE @CONTADOR INT  
DECLARE @VALORES  DECIMAL(14,2)  
DECLARE @NVOCONSEC INT  
DECLARE @IDPROVEEDOR VARCHAR(20)  
DECLARE @VALOR DECIMAL(14,2)  
DECLARE @EXISTE      INT             --copiado de ven
DECLARE @FECHA       DATETIME        --copiado de ven
DECLARE @IDPROVEEDOR1 VARCHAR(20)    --copiado de ven
DECLARE @IDSERVICIO   VARCHAR(20)    --copiado de ven
DECLARE @DESCSERVICIO VARCHAR(255)   --copiado de ven
DECLARE @IDAREA       VARCHAR(20)    --copiado de ven
DECLARE @IDCIRUGIA    VARCHAR(20)    --copiado de ven
DECLARE @PREFIJO      VARCHAR(6)     --copiado de ven
DECLARE @VALOR1       DECIMAL(14,2)  --copiado de ven
DECLARE @CANTIDAD     INT            --copiado de ven  
DECLARE @NOPRESTACION VARCHAR(16)    --copiado de ven
DECLARE @NOITEM       SMALLINT       --copiado de ven
DECLARE @N_FACTURA    VARCHAR(16)    --copiado de ven
DECLARE @CCOSTO       VARCHAR(20)    --copiado de ven
DECLARE @IDAREAH      VARCHAR(20)    --copiado de ven
DECLARE @IDTERCEROCA  VARCHAR(20)    --copiado de ven
DECLARE @IDPLAN       VARCHAR(6)     --copiado de ven
DECLARE @AUX          INT            --copiado de ven
DECLARE @FECHACARGO   DATETIME
BEGIN 
   PRINT 'INGRESO A HACER FXP SEDE'+ @SEDE 
   SELECT @CONTADOR = COALESCE(COUNT(*),0)
   FROM HPRED INNER JOIN HPRE ON HPRE.NOPRESTACION = HPRED.NOPRESTACION   
   WHERE  HPRE.NOADMISION   = @NOADMISION    
   AND    COALESCE(HPRED.IDPROVEEDOR,'') <> ''
   AND    HPRED.N_FACTURA   = @NVOCONSECFTR
   AND    COALESCE(HPRE.ANULADO,0) = 0  --SJUNCO REQ 1803
   AND    COALESCE(HPRED.ANULADO,0) = 0 --SJUNCO REQ 1803
   AND    COALESCE(HPRED.CXP,0)=0
   PRINT '1'
   IF @CONTADOR <= 0  
   BEGIN
      RETURN  
   END


   PRINT '2'
   CREATE TABLE #ICXP (IDPROVEEDOR    VARCHAR(20)  COLLATE database_default, 
                       IDSERVICIO     VARCHAR(20) COLLATE database_default,  
                       VALOREXCEDENTE DECIMAL(14,2),                         
                       DESCSEVICIO    VARCHAR(255) COLLATE database_default,  
                       IDAREA         VARCHAR(20) COLLATE database_default, 
                       IDCIRUGIA      VARCHAR(20) COLLATE database_default ,
                       PREFIJO        VARCHAR(6) COLLATE database_default,  
                       VALOR          DECIMAL(14,2),
                       CANTIDAD       INT,
                       NOPRESTACION   VARCHAR(16) COLLATE database_default,  
                       NOITEM         SMALLINT ,
                       N_FACTURA      VARCHAR(16) COLLATE database_default, 
                       CCOSTO         VARCHAR(20) COLLATE database_default,
                       IDAREAH        VARCHAR(20) COLLATE database_default, 
                       ITEM           INT IDENTITY, 
                       IDTERCEROCA    VARCHAR(20) COLLATE database_default, 
                       IDPLAN         VARCHAR(6) COLLATE database_default, 
                       FACTOR         DECIMAL(14,2), 
                       VALORCXP       DECIMAL(14,2),
	                    FECHACARGO     DATETIME ) 
   
   PRINT '3'
   
   DECLARE H_CURSOR CURSOR FOR
   --INSERT INTO #ICXP                         
   SELECT HPRED.IDPROVEEDOR, SER.IDSERVICIO, SER.DESCSERVICIO,  
          HPRE.IDAREA,HPRED.IDCIRUGIA,SER.PREFIJO,HPRED.VALOR,HPRED.CANTIDAD,HPRED.NOPRESTACION,  
          HPRED.NOITEM,HPRED.N_FACTURA, HPRE.CCOSTO, HPRE.IDAREAH, HPRED.IDTERCEROCA, 
          HPRED.IDPLAN, HPRE.FECHA  
   FROM   HPRED INNER JOIN HPRE  ON HPRED.NOPRESTACION = HPRE.NOPRESTACION
                INNER JOIN SER   ON HPRED.IDSERVICIO   = SER.IDSERVICIO    
   WHERE  HPRE.NOADMISION   = @NOADMISION  
   AND    COALESCE(HPRED.IDPROVEEDOR,'') <> ''
   AND    COALESCE(HPRED.IDPROVEEDOR,'') <> dbo.FNK_VALORVARIABLE('IDTERCEROINSTALADO')  
   AND    HPRED.N_FACTURA   = @NVOCONSECFTR
   AND    COALESCE(HPRE.ANULADO,0) = 0  --SJUNCO REQ 1803
   AND    COALESCE(HPRED.ANULADO,0) = 0 --SJUNCO REQ 1803
   AND    COALESCE(HPRED.CXP,0)=0        --JJIMENEZ 21-03-13
   ORDER BY HPRED.IDPROVEEDOR   
   OPEN H_CURSOR
   FETCH NEXT FROM H_CURSOR  
   INTO  @IDPROVEEDOR, @IDSERVICIO, @DESCSERVICIO, @IDAREA, @IDCIRUGIA, @PREFIJO, @VALOR, @CANTIDAD, @NOPRESTACION,
         @NOITEM, @N_FACTURA, @CCOSTO, @IDAREAH, @IDTERCEROCA, @IDPLAN,@FECHACARGO 
   WHILE @@FETCH_STATUS = 0  
   BEGIN 
      print 'idproveedor=' + @IDPROVEEDOR
      SELECT @AUX = 1 
      WHILE  @AUX <= @CANTIDAD   
      BEGIN 
         INSERT INTO #ICXP (IDPROVEEDOR, IDSERVICIO, VALOREXCEDENTE, DESCSEVICIO, IDAREA, IDCIRUGIA,
                            PREFIJO, VALOR, CANTIDAD, NOPRESTACION, NOITEM, N_FACTURA, CCOSTO,
                            IDAREAH, IDTERCEROCA, IDPLAN, FACTOR, VALORCXP, FECHACARGO )
         SELECT @IDPROVEEDOR, @IDSERVICIO, 1 * @VALOR ,@DESCSERVICIO,  
                @IDAREA, @IDCIRUGIA, @PREFIJO, @VALOR, 1, @NOPRESTACION,  
                @NOITEM, @N_FACTURA, @CCOSTO, @IDAREAH, @IDTERCEROCA, 
                @IDPLAN, 0, 0, @FECHACARGO
         SELECT @AUX = @AUX +1
      END 
      FETCH NEXT FROM H_CURSOR  
      INTO  @IDPROVEEDOR, @IDSERVICIO, @DESCSERVICIO, @IDAREA, @IDCIRUGIA, @PREFIJO, @VALOR, @CANTIDAD, @NOPRESTACION,
            @NOITEM, @N_FACTURA, @CCOSTO, @IDAREAH, @IDTERCEROCA, @IDPLAN,@FECHACARGO 
   END
   CLOSE H_CURSOR
   DEALLOCATE H_CURSOR
   
   PRINT '4'
	UPDATE #ICXP 
	SET VALOREXCEDENTE = COALESCE(VW_CXPPROTOT.VLRSERVICIO,0),
	    VALOR = COALESCE(VW_CXPPROTOT.VLRSERVICIO,0),
		VALORCXP = CANTIDAD * COALESCE(VW_CXPPROTOT.VLRSERVICIO,0)  --MOD. JJIMENEZ 20-03-2013
	FROM   #ICXP INNER JOIN VW_CXPPROTOT ON #ICXP.IDPLAN        = VW_CXPPROTOT.IDPLAN
                                        AND #ICXP.PREFIJO       = VW_CXPPROTOT.PREFIJO
                                        AND #ICXP.IDPROVEEDOR   = VW_CXPPROTOT.IDTERCERO
	                                    AND #ICXP.IDTERCEROCA   = VW_CXPPROTOT.IDADMINISTRADORA
	                                    AND #ICXP.IDSERVICIO    = VW_CXPPROTOT.IDSERVICIO
	WHERE  #ICXP.FECHACARGO >= VW_CXPPROTOT.FECHAINIFD
    AND    #ICXP.FECHACARGO <= VW_CXPPROTOT.FECHAFINFD
    AND    #ICXP.FECHACARGO >= VW_CXPPROTOT.FECHAINI
    AND    #ICXP.FECHACARGO <= VW_CXPPROTOT.FECHAFIN

	                           
   PRINT '5'  
   --UPDATE #ICXP SET VALORCXP = #ICXP.VALOREXCEDENTE * #ICXP.FACTOR  --MOD. JJIMENEZ 20-03-2013
   --  
   CREATE TABLE #PCXP (IDPROVEEDOR VARCHAR(20),VALOR DECIMAL(14,2),NOPRESTACION VARCHAR(16))  
   INSERT INTO  #PCXP (IDPROVEEDOR,VALOR,NOPRESTACION)  
   SELECT IDPROVEEDOR, SUM(VALORCXP), NOPRESTACION  FROM #ICXP  
   WHERE COALESCE(VALORCXP,0)>0
   GROUP BY IDPROVEEDOR, NOPRESTACION 
   --CURSOR--  
   DECLARE CXP_CURSOR CURSOR FOR  
   SELECT IDPROVEEDOR,VALOR,NOPRESTACION FROM #PCXP  
   OPEN CXP_CURSOR  
   FETCH NEXT FROM CXP_CURSOR  
   INTO @IDPROVEEDOR, @VALOR, @NOPRESTACION 
   WHILE @@FETCH_STATUS = 0  
   BEGIN  
         EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@FCXP',@NVOCONSEC OUTPUT  
         SELECT @NVOCONSEC = @SEDE + REPLACE(SPACE(8 - LEN(@NVOCONSEC))+LTRIM(RTRIM(@NVOCONSEC)),SPACE(1),0)
         
         INSERT INTO FXP(N_PRESUP,IDTERCERO,NOREFERENCIA,F_FACTURAREF,F_VENCE,VR_TOTAL,ESTADO,  
                         F_CANCELADO,EMPLEADO,PROCEDENCIA,OBSERVACION,COMPANIA,INDCOBRADA)  
         SELECT @NVOCONSEC,@IDPROVEEDOR,@NOADMISION,GETDATE(),NULL,@VALOR,'P',NULL,@USUARIO,  
                'SALUD','',@COMPANIA,0  

		 -- MOD.JQUIROGA 20090615 - Ingresar el N_factura en CXPD
         INSERT INTO FXPD(N_PRESUP,IDTERCERO,ITEM,IDSERVICIO,PREFIJO,VALOR,CANTIDAD,VR_TOTAL,  
                          NOPRESTACION,NOITEM,IDCIRUGIA, N_FACTURA, ESTADO, CCOSTO, IDAREA,
                          IDAREAH, VLRORIGINAL)  
         SELECT @NVOCONSEC,@IDPROVEEDOR,ITEM,IDSERVICIO,PREFIJO,VALOR,CANTIDAD,  
                VALORCXP,NOPRESTACION,NOITEM,IDCIRUGIA, N_FACTURA, 'P', CCOSTO, IDAREA,
                IDAREAH, VALOR  
         FROM   #ICXP  
         WHERE  IDPROVEEDOR = @IDPROVEEDOR AND NOPRESTACION=@NOPRESTACION

		 UPDATE HPRED SET CXP = 1  WHERE NOPRESTACION=@NOPRESTACION AND IDPROVEEDOR=@IDPROVEEDOR
         FETCH NEXT FROM CXP_CURSOR  
         INTO  @IDPROVEEDOR,@VALOR,@NOPRESTACION  
   END  
   CLOSE CXP_CURSOR  
   DEALLOCATE CXP_CURSOR     
   UPDATE HADM SET CXP = 1  
   WHERE NOADMISION = @NOADMISION    
   DROP TABLE #ICXP  
   DROP TABLE #PCXP  

   IF EXISTS( SELECT * FROM HOMED WHERE PROCEDENCIA='HADM' AND EXISTS(SELECT * FROM HPRE INNER JOIN HPRED ON HPRE.NOPRESTACION=HPRED.NOPRESTACION 
                                                                       WHERE HPRE.NOADMISION=@NOADMISION AND HPRED.NOPRESTACION=HOMED.NOPRESTACION 
                                                                       AND HPRED.NOITEM=HOMED.ITEM))
   BEGIN
      DECLARE @NPRESTACIONH VARCHAR(20)
      DECLARE @ITEM SMALLINT
      DECLARE @IDTERCEROP VARCHAR(20)
      DECLARE @PORCEN  DECIMAL(7,2)
      DECLARE CXP_CURSOR CURSOR FOR  
      SELECT HPRED.NOPRESTACION,ITEM,IDTERCERO,PORCEN  
      FROM HOMED INNER JOIN HPRED ON HOMED.NOPRESTACION=HPRED.NOPRESTACION AND HOMED.ITEM=HPRED.NOITEM
                 INNER JOIN HPRE  ON HPRED.NOPRESTACION=HPRE.NOPRESTACION
      WHERE HOMED.PROCEDENCIA='HADM' 
      AND HPRE.NOADMISION=@NOADMISION
      ORDER BY NOPRESTACION
      OPEN CXP_CURSOR  
      FETCH NEXT FROM CXP_CURSOR  
      INTO @NPRESTACIONH,@ITEM,@IDTERCEROP, @PORCEN 
      WHILE @@FETCH_STATUS = 0  
      BEGIN  
         SELECT @VALOR=(VALOR*CANTIDAD)*(@PORCEN/100) FROM HPRED WHERE NOPRESTACION=@NPRESTACIONH AND NOITEM=@ITEM
         IF @NVOCONSECFTR IS NULL
         BEGIN
            SELECT TOP 1 @N_FACTURA = N_FACTURA FROM HPRED WHERE NOPRESTACION=@NPRESTACIONH
            SELECT @FECHA = F_FACTURA FROM FTR WHERE N_FACTURA = @N_FACTURA
         END
         
         EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@FCXP',@NVOCONSEC OUTPUT  
         SELECT @NVOCONSEC = @SEDE + REPLACE(SPACE(8 - LEN(@NVOCONSEC))+LTRIM(RTRIM(@NVOCONSEC)),SPACE(1),0)

         INSERT INTO FXP(N_PRESUP,IDTERCERO,NOREFERENCIA,F_FACTURAREF,F_VENCE,VR_TOTAL,ESTADO,  
                         F_CANCELADO,EMPLEADO,PROCEDENCIA,OBSERVACION,COMPANIA,INDCOBRADA)  
         SELECT @NVOCONSEC,@IDTERCEROP,@NOADMISION, CASE WHEN @NVOCONSECFTR IS NULL THEN @FECHA ELSE GETDATE() END, 
                NULL,@VALOR,'P',NULL,@USUARIO,  
                'SALUD','',@COMPANIA,0  

         INSERT INTO FXPD(N_PRESUP,IDTERCERO,ITEM,IDSERVICIO,PREFIJO,VALOR,CANTIDAD,VR_TOTAL,  
                          NOPRESTACION,NOITEM,IDCIRUGIA, N_FACTURA, ESTADO, CCOSTO, IDAREA,
                          IDAREAH )  
         SELECT @NVOCONSEC,@IDTERCEROP,HPRED.NOITEM,HPRED.IDSERVICIO,HPRE.PREFIJO,ROUND((@VALOR/HPRED.CANTIDAD),2),HPRED.CANTIDAD,  
                @VALOR,HPRED.NOPRESTACION,HPRED.NOITEM,HPRED.IDSERVICIO, HPRED.N_FACTURA , 'P', HPRE.CCOSTO, HPRE.IDAREA,
                HPRE.IDAREAH
         FROM   HPRE INNER JOIN HPRED ON HPRE.NOPRESTACION=HPRED.NOPRESTACION
         WHERE  HPRED.NOPRESTACION=@NPRESTACIONH
         AND    HPRED.NOITEM=@ITEM

         FETCH NEXT FROM CXP_CURSOR  
         INTO  @NPRESTACIONH,@ITEM,@IDTERCEROP, @PORCEN  
      END  
      CLOSE CXP_CURSOR      
      DEALLOCATE CXP_CURSOR      

   END


END
