/*
  CEM — Cuentas FCXPD (patrón 03CM002102 DPE12133).
  Modelo (igual VERIFICACION_VALORES_CUENTAS / lote gravada sep-2026):
    - Línea con VLR_IVA > 0: CUENTA_SER = gravada (CUENTAGRAV si hoy está en excluida MCUEGRAV=1),
      CUENTA_IVA = 24080501 (no 24080601).
    - Línea sin IVA: CUENTA_IVA vacía; servicio en excluidos si aplica.
    - Lote IEXI de la entrada (N_PRESUP): CUEDEBITO gravada, CUECREDITO reversión gravada, CUENTAIVA 24080501.

  Alcance: CxP compras sep pendientes listadas con hallazgo de cuenta (pre-cierre), patrón INS0007/INS0064/INS0065 + DM0474.

  Pre: ESTADO N, CONTABILIZADA 0, sin NROCOMPROBANTE, CUECREDITO 22050101.
  No cambia montos. Idempotente: si ya se aplicó, no exige las 5 líneas en 14200502 (55403).
  Ejecutar en CEM; revisar SELECT final.
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @DOC TABLE (CNSFCXP varchar(20) NOT NULL PRIMARY KEY);

INSERT INTO @DOC (CNSFCXP) VALUES
  (N'03CM002080'),
  (N'03CM002152'),
  (N'03CM002125'),
  (N'03CM002102'),
  (N'03CM002116'),
  (N'03CM002375'),
  (N'03CM002412'),
  (N'34CM000132');

DECLARE @N_EXCL_PEND int;
DECLARE @N_IVA_806 int;
DECLARE @N_IVA_OK int;

SELECT @N_EXCL_PEND = COUNT(*)
FROM dbo.FCXPD D
INNER JOIN @DOC X ON X.CNSFCXP = D.CNSFCXP
INNER JOIN dbo.CUE C ON C.CUENTA = D.CUENTA_SER AND COALESCE(C.MCUEGRAV, 0) = 1
WHERE COALESCE(D.VLR_IVA, 0) > 0
  AND D.CUENTA_SER = N'14200502'
  AND C.CUENTAGRAV = N'14200501'
  AND COALESCE(D.CUENTA_IVA, N'') = N'';

SELECT @N_IVA_806 = COUNT(*)
FROM dbo.FCXPD D
INNER JOIN @DOC X ON X.CNSFCXP = D.CNSFCXP
WHERE COALESCE(D.VLR_IVA, 0) > 0
  AND D.CUENTA_SER = N'14200501'
  AND COALESCE(D.CUENTA_IVA, N'') = N'24080601';

SELECT @N_IVA_OK = COUNT(*)
FROM dbo.FCXPD D
INNER JOIN @DOC X ON X.CNSFCXP = D.CNSFCXP
WHERE COALESCE(D.VLR_IVA, 0) > 0
  AND D.CUENTA_SER IN (N'14150501', N'14200501')
  AND COALESCE(D.CUENTA_IVA, N'') = N'24080501';

BEGIN TRAN;

IF (
  SELECT COUNT(*)
  FROM dbo.FCXP P
  INNER JOIN @DOC D ON D.CNSFCXP = P.CNSFCXP
  WHERE P.ESTADO = N'N'
    AND COALESCE(P.CONTABILIZADA, 0) = 0
    AND COALESCE(P.NROCOMPROBANTE, N'') = N''
    AND P.CUECREDITO = N'22050101'
    AND P.PROCEDENCIA = N'Compras'
) <> (SELECT COUNT(*) FROM @DOC)
BEGIN
  ROLLBACK TRAN;
  THROW 55401, 'Alguna CxP del lote no esta libre (N, sin comprobante, credito 22050101).', 1;
END;

IF (
  SELECT COUNT(*)
  FROM dbo.CUE
  WHERE CUENTA = N'24080501' AND TIPO = N'Detalle' AND ESTADO = N'Activa'
) <> 1
BEGIN
  ROLLBACK TRAN;
  THROW 55402, 'Cuenta IVA 24080501 no valida.', 1;
END;

/* Ya aplicado: 9 líneas con IVA en destino; nada pendiente en excluidos / 24080601 */
IF @N_EXCL_PEND = 0 AND @N_IVA_806 = 0 AND @N_IVA_OK = 9
BEGIN
  COMMIT TRAN;
  SELECT N'YA_APLICADO' AS ESTADO, @N_IVA_OK AS LINEAS_IVA_OK;
  SELECT
    P.CNSFCXP, P.NOREFERENCIA, D.ITEM, D.IDSERVICIO,
    CONVERT(decimal(18, 2), D.VLR_IVA) AS IVA, D.CUENTA_SER, D.CUENTA_IVA
  FROM @DOC X
  INNER JOIN dbo.FCXP P ON P.CNSFCXP = X.CNSFCXP
  INNER JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
  WHERE COALESCE(D.VLR_IVA, 0) > 0
  ORDER BY P.NOREFERENCIA, D.ITEM;
  RETURN;
END;

IF @N_EXCL_PEND > 0 AND @N_EXCL_PEND <> 5
BEGIN
  ROLLBACK TRAN;
  THROW 55403, 'Pendientes en 14200502 con IVA sin CUENTA_IVA: se esperaban 0 o 5, revisar detalle.', 1;
END;

IF @N_IVA_806 > 0 AND @N_IVA_806 <> 2
BEGIN
  ROLLBACK TRAN;
  THROW 55404, 'Pendientes IVA en 24080601: se esperaban 0 o 2, revisar detalle.', 1;
END;

/* Excluida → gravada + IVA (FCXPD) */
UPDATE D
SET D.CUENTA_SER = C.CUENTAGRAV,
    D.CUENTA_IVA = N'24080501'
FROM dbo.FCXPD D
INNER JOIN @DOC X ON X.CNSFCXP = D.CNSFCXP
INNER JOIN dbo.CUE C ON C.CUENTA = D.CUENTA_SER AND COALESCE(C.MCUEGRAV, 0) = 1
WHERE COALESCE(D.VLR_IVA, 0) > 0
  AND D.CUENTA_SER IN (N'14150502', N'14200502')
  AND COALESCE(C.CUENTAGRAV, N'') <> N'';

/* IVA descontable en gravada ya puesta */
UPDATE D
SET D.CUENTA_IVA = N'24080501'
FROM dbo.FCXPD D
INNER JOIN @DOC X ON X.CNSFCXP = D.CNSFCXP
WHERE COALESCE(D.VLR_IVA, 0) > 0
  AND D.CUENTA_SER IN (N'14150501', N'14200501')
  AND COALESCE(D.CUENTA_IVA, N'') IN (N'', N'24080601');

/* Sin IVA: no cuenta IVA */
UPDATE D
SET D.CUENTA_IVA = NULL
FROM dbo.FCXPD D
INNER JOIN @DOC X ON X.CNSFCXP = D.CNSFCXP
WHERE COALESCE(D.VLR_IVA, 0) <= 0
  AND COALESCE(D.CUENTA_IVA, N'') <> N'';

/* IEXI — mismas entradas que FCXPD con IVA (N_PRESUP = CNSMOV) */
UPDATE I
SET I.CUEDEBITO = D.CUENTA_SER,
    I.CUECREDITO = CG.CUENTAREV,
    I.CUENTAIVA = N'24080501'
FROM dbo.IEXI I
INNER JOIN dbo.FCXPD D
  ON D.N_PRESUP = I.CNSMOV
 AND D.IDSERVICIO = I.IDARTICULO
 AND D.IDBODEGA = I.IDBODEGA
 AND D.NOLOTE = I.NOLOTEPEDIDO
INNER JOIN @DOC X ON X.CNSFCXP = D.CNSFCXP
INNER JOIN dbo.CUE CG ON CG.CUENTA = D.CUENTA_SER
WHERE COALESCE(D.VLR_IVA, 0) > 0
  AND D.CUENTA_SER IN (N'14150501', N'14200501')
  AND COALESCE(D.CUENTA_IVA, N'') = N'24080501';

IF EXISTS (
  SELECT 1
  FROM dbo.FCXPD D
  INNER JOIN @DOC X ON X.CNSFCXP = D.CNSFCXP
  WHERE COALESCE(D.VLR_IVA, 0) > 0
    AND (
      D.CUENTA_SER IN (N'14150502', N'14200502')
      OR COALESCE(D.CUENTA_IVA, N'') <> N'24080501'
    )
)
BEGIN
  ROLLBACK TRAN;
  THROW 55405, 'Quedaron lineas con IVA mal cuenta servicio o IVA.', 1;
END;

IF EXISTS (
  SELECT 1
  FROM dbo.FCXPD D
  INNER JOIN @DOC X ON X.CNSFCXP = D.CNSFCXP
  WHERE COALESCE(D.VLR_IVA, 0) <= 0
    AND COALESCE(D.CUENTA_IVA, N'') <> N''
)
BEGIN
  ROLLBACK TRAN;
  THROW 55406, 'Quedaron lineas sin IVA con CUENTA_IVA.', 1;
END;

COMMIT TRAN;

SELECT
  P.CNSFCXP,
  P.NOREFERENCIA,
  D.ITEM,
  D.IDSERVICIO,
  CONVERT(decimal(18, 2), D.VLR_IVA) AS IVA,
  D.CUENTA_SER,
  D.CUENTA_IVA
FROM @DOC X
INNER JOIN dbo.FCXP P ON P.CNSFCXP = X.CNSFCXP
INNER JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
WHERE COALESCE(D.VLR_IVA, 0) > 0
   OR D.CUENTA_SER LIKE N'142005%' OR D.CUENTA_SER LIKE N'141505%'
ORDER BY P.NOREFERENCIA, D.ITEM;
