CREATE OR ALTER FUNCTION DBO.FNK_NC_CUENTA_KMCOM(
	@IDMODELOCONT	VARCHAR(20),
	@IDTIPOCONT	VARCHAR(20),
	@TIPO		VARCHAR(2),
	@PREFIJO	VARCHAR(20),
	@CCOSTO		VARCHAR(20),
	@CLASECONT	VARCHAR(1),
	@IDSERVICIO	VARCHAR(20),
   @PGP SMALLINT=0) 
RETURNS VARCHAR(16)
WITH ENCRYPTION
AS
BEGIN
   DECLARE @CUENTA VARCHAR(16)
   DECLARE @GRUPOPRE VARCHAR(20)
   DECLARE @GRPRE BIT
   DECLARE @HOMOLOGO VARCHAR(20)--CEN
   IF @IDTIPOCONT='VENTAS' 
   BEGIN
      SELECT @GRPRE=IIF(DBO.FNK_VALORVARIABLE('CONTAB_VENT_GRUPOPRE')='SI',1,0)
      IF @GRPRE=1
      BEGIN
         SELECT @GRUPOPRE=IIF(COALESCE(GRUPO,'')<>'',GRUPO,PREFIJO) FROM PRE WHERE PREFIJO=@PREFIJO
         SELECT @PREFIJO=@GRUPOPRE
      END
   END  
   IF NOT EXISTS(SELECT * FROM CEN WHERE CCOSTO=@CCOSTO AND ESTADO='Activo')
   BEGIN
      SELECT @HOMOLOGO=COALESCE(HOMOLOGO,'') FROM CEN WHERE CCOSTO=@CCOSTO
      IF COALESCE(@HOMOLOGO,'')<>''
      BEGIN
         SET @CCOSTO=@HOMOLOGO
      END
   END
   SET @CUENTA=(SELECT TOP 1 CASE WHEN @PGP=1 AND  COALESCE(PGP,0)=1 THEN CUEPGP  WHEN @PGP=2 AND  COALESCE(CAPITA,0)=1 THEN CUECAPITA ELSE CUENTA  END 
	             FROM   KMCOMS 
                WHERE  IDMODELOCONT = @IDMODELOCONT 
                AND    IDTIPOCONT   = @IDTIPOCONT 
                AND    TIPO         = @TIPO 
                AND    PREFIJO      = @PREFIJO 
                AND    CCOSTO       = @CCOSTO 
                AND    IDSERVICIO   = @IDSERVICIO)
   IF @CUENTA IS NULL OR @CUENTA='' --OR @CLASECONT='P'
   BEGIN
      SET @CUENTA=(SELECT TOP 1 CASE WHEN @PGP=1 AND  COALESCE(MPGP,0)=1 THEN CUECRPGP  WHEN @PGP=2 AND  COALESCE(MCAPITA,0)=1 THEN CUECRCAP ELSE CUENTA  END
	                FROM   KMCOM 
                   WHERE  IDMODELOCONT = @IDMODELOCONT 
                   AND    IDTIPOCONT   = @IDTIPOCONT 
                   AND    TIPO         = @TIPO 
                   AND    PREFIJO      = @PREFIJO 
                   AND    CCOSTO       = @CCOSTO)
   END
   IF @CUENTA IS NULL OR @CUENTA=''
      SET @CUENTA = 'NO DEF.KMCOM'
   RETURN(@CUENTA)
END
