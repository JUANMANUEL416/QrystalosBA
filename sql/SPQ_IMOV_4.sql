			SELECT @NOLOTE_HDR_AL = @SEDE + 'L' + REPLACE(SPACE(8 - LEN(@NOLOTE_HDR_AL)) + LTRIM(RTRIM(@NOLOTE_HDR_AL)), SPACE(1), '0')

			INSERT INTO IMOVH (CNSMOV, IDARTICULO, CANTPEDIDA, CANTIDAD, NOLOTE, ESTADO, ITEM, USUARIO, IDITAR, PVENTA)
			SELECT @CNSMOV, @IDART_PRINC_AL, @CANT_AL, 0, @NOLOTE_HDR_AL, 0, @ITEM_AL, @USUARIO,
				(SELECT TOP 1 IDITAR FROM IART WHERE IDARTICULO = @IDART_PRINC_AL),
				CASE WHEN COALESCE(@PVENTA_AL, 0) > 0 THEN @PVENTA_AL ELSE NULL END

			SET @CANT_ORDEN_AL = @CANT_AL
		END
		ELSE
		BEGIN
			SELECT @CANT_ORDEN_AL = COALESCE(CANTPEDIDA, 0)
			FROM IMOVH
			WHERE CNSMOV = @CNSMOV AND IDARTICULO = @IDART_PRINC_AL AND COALESCE(ESTADO, 0) <> 2
		END

		IF COALESCE(@CANT_ORDEN_AL, 0) <= 0
			SET @CANT_ORDEN_AL = @CANT_AL

		-- Si no enviaron pedido y hay varios IEXI del mismo NOLOTE, exigir NOLOTEPEDIDO
		IF COALESCE(@NOLOTEPED_AL, '') = ''
		   AND (
				SELECT COUNT(*)
				FROM IEXI
				INNER JOIN DBO.VWK_HERMANOS_INVENTARIO H ON H.IDARTICULO = IEXI.IDARTICULO
				WHERE IEXI.IDBODEGA = @IDBODEGA
				  AND IEXI.IDARTICULO = @IDART_LOTE_AL
				  AND IEXI.NOLOTE = @NOLOTE_AL
				  AND H.HERMANO_MAYOR = @IDART_PRINC_AL
				  AND COALESCE(IEXI.EXISLOTE, 0) > 0
			) > 1
		BEGIN
			ROLLBACK TRAN
			SELECT 'KO' OK, 'Debe indicar NOLOTEPEDIDO: hay varios pedidos para el mismo lote.' AS ERROR, 'ERROR_EXIS' ERROR_EXIS
			RETURN
		END

		IF NOT EXISTS (
			SELECT 1
			FROM IEXI
			INNER JOIN DBO.VWK_HERMANOS_INVENTARIO H ON H.IDARTICULO = IEXI.IDARTICULO
			WHERE IEXI.IDBODEGA = @IDBODEGA
			  AND IEXI.IDARTICULO = @IDART_LOTE_AL
			  AND IEXI.NOLOTE = @NOLOTE_AL
			  AND (COALESCE(@NOLOTEPED_AL,'') = '' OR COALESCE(IEXI.NOLOTEPEDIDO,'') = COALESCE(@NOLOTEPED_AL,''))
			  AND H.HERMANO_MAYOR = @IDART_PRINC_AL
			  AND COALESCE(IEXI.EXISLOTE, 0) > 0
		)
		BEGIN
			ROLLBACK TRAN
			SELECT 'KO' OK, 'El lote/pedido no pertenece al art�culo principal o no tiene existencia.' AS ERROR, 'ERROR_EXIS' ERROR_EXIS
			RETURN
		END

		-- UPDLOCK/HOLDLOCK coordina reservas concurrentes y CONFIRMA_SALIDA.
		SELECT TOP 1
			@EXIS_AL = COALESCE(EXISLOTE, 0),
			@FVENCE_AL = FECHAVENCE,
			@NOLOTEPED_AL = NOLOTEPEDIDO,
			@PCOSTO_AL = COALESCE(PCOSTO, 0)
		FROM IEXI WITH (UPDLOCK, HOLDLOCK, ROWLOCK)
		WHERE IDBODEGA = @IDBODEGA
		  AND IDARTICULO = @IDART_LOTE_AL
		  AND NOLOTE = @NOLOTE_AL
		  AND (COALESCE(@NOLOTEPED_AL,'') = '' OR COALESCE(NOLOTEPEDIDO,'') = COALESCE(@NOLOTEPED_AL,''))
		ORDER BY EXISLOTE DESC

		-- Precio de venta: front ? tarifa autom�tica (misma l�gica entrega din�mica)
		IF COALESCE(@PVENTA_AL, 0) <= 0
			AND @ES_VENTA_AL = 1
			AND DBO.FNK_VALORVARIABLE('PVENTA_AUTO_TARIFA') = 'SI'
			AND COALESCE(@IDTERCERO_AL, '') <> ''
			AND COALESCE(@IDPLAN_AL, '') <> ''
		BEGIN
			SELECT @IDSERVICIO_AL = COALESCE(NULLIF(IDSERVICIO, ''), IDARTICULO)
			FROM IART WITH (NOLOCK)
			WHERE IDARTICULO = @IDART_LOTE_AL

			IF COALESCE(@IDSERVICIO_AL, '') = ''
				SET @IDSERVICIO_AL = @IDART_LOTE_AL

			BEGIN TRY
				SET @PVENTA_AL = DBO.FNK_VALORSERVICIO(
					@IDTERCERO_AL,
					@IDPLAN_AL,
					@IDSERVICIO_AL,
					'',
					DBO.FNK_GETDATE(),
					@PCOSTO_AL
				)
			END TRY
			BEGIN CATCH
				SET @PVENTA_AL = NULL
			END CATCH
		END

		IF @EXIGE_PVENTA_AL = 1 AND COALESCE(@PVENTA_AL, 0) <= 0
		BEGIN
			ROLLBACK TRAN
			SELECT 'KO' OK, 'Debe indicar un Precio de Venta v�lido mayor a cero para movimientos de venta.' AS ERROR
			RETURN
		END

		SELECT @YA_AL = COALESCE(SUM(CANTIDAD), 0)
		FROM ISAL
		WHERE CNSMOV = @CNSMOV
		  AND IDARTICULO = @IDART_LOTE_AL
		  AND NOLOTE = @NOLOTE_AL
		  AND COALESCE(NOLOTEPEDIDO,'') = COALESCE(@NOLOTEPED_AL,'')

		SELECT @RESERVADO_OTROS_AL = COALESCE(SUM(CAST(S.CANTIDAD AS DECIMAL(18,4))), 0)
		FROM ISAL S
		INNER JOIN IMOV M ON M.CNSMOV = S.CNSMOV
		INNER JOIN ITMO T ON T.IDTIPOMOV = M.IDTIPOMOV
		WHERE M.CNSMOV <> @CNSMOV
		  AND M.IDBODEGA = @IDBODEGA
		  AND COALESCE(M.ESTADO, 0) = 0
		  AND COALESCE(M.ES_PICKPACK, 0) = 1
		  AND T.TIPO = 'Debito'
		  AND S.IDARTICULO = @IDART_LOTE_AL
		  AND S.NOLOTE = @NOLOTE_AL
		  AND COALESCE(S.NOLOTEPEDIDO, '') = COALESCE(@NOLOTEPED_AL, '')

		IF (@YA_AL + @CANT_AL + @RESERVADO_OTROS_AL) > @EXIS_AL
		BEGIN
			ROLLBACK TRAN
			SELECT 'KO' OK,
				'La cantidad supera la existencia disponible del lote/pedido (disponible='
				+ CONVERT(VARCHAR(30), CAST(@EXIS_AL - @YA_AL - @RESERVADO_OTROS_AL AS FLOAT))
				+ ', reservada por otros movimientos='
				+ CONVERT(VARCHAR(30), CAST(@RESERVADO_OTROS_AL AS FLOAT))
				+ ').' AS ERROR,
				'ERROR_EXIS' ERROR_EXIS
			RETURN
		END

		SELECT @TOTAL_ASIG_AL = COALESCE(SUM(CANTIDAD), 0)
		FROM ISAL
		WHERE CNSMOV = @CNSMOV
		  AND COALESCE(NULLIF(IDARTICULO_IMOVH, ''), IDARTICULO) = @IDART_PRINC_AL

		-- Un paso: si se pasa del CANTPEDIDA, ampliar la orden (tope real = existencia IEXI)
		IF (@TOTAL_ASIG_AL + @CANT_AL) > @CANT_ORDEN_AL
		BEGIN
			SET @CANT_ORDEN_AL = @TOTAL_ASIG_AL + @CANT_AL
			UPDATE IMOVH
			SET CANTPEDIDA = @CANT_ORDEN_AL
			WHERE CNSMOV = @CNSMOV AND IDARTICULO = @IDART_PRINC_AL AND COALESCE(ESTADO, 0) <> 2
		END

		BEGIN TRY
			IF EXISTS (
				SELECT 1 FROM ISAL
				WHERE CNSMOV = @CNSMOV
				  AND IDARTICULO = @IDART_LOTE_AL
				  AND NOLOTE = @NOLOTE_AL
				  AND COALESCE(NOLOTEPEDIDO,'') = COALESCE(@NOLOTEPED_AL,'')
			)
			BEGIN
				UPDATE ISAL
				SET CANTIDAD = CANTIDAD + @CANT_AL,
					IDARTICULO_IMOVH = @IDART_PRINC_AL,
					FECHAVENCE = COALESCE(@FVENCE_AL, FECHAVENCE),
					NOLOTEPEDIDO = COALESCE(@NOLOTEPED_AL, NOLOTEPEDIDO),
					PCOSTO = COALESCE(@PCOSTO_AL, PCOSTO),
					PVENTA = CASE WHEN COALESCE(@PVENTA_AL, 0) > 0 THEN @PVENTA_AL ELSE PVENTA END,
					ESTADO_PICK = 'OK'
				WHERE CNSMOV = @CNSMOV
				  AND IDARTICULO = @IDART_LOTE_AL
				  AND NOLOTE = @NOLOTE_AL
				  AND COALESCE(NOLOTEPEDIDO,'') = COALESCE(@NOLOTEPED_AL,'')
			END
			ELSE
			BEGIN
				INSERT INTO ISAL (
					CNSMOV, IDARTICULO, NOLOTE, CANTIDAD, FECHA, NOLOTEPEDIDO,
					FECHAVENCE, PCOSTO, PVENTA, IDARTICULO_IMOVH, ESTADO_PICK
				)
				VALUES (
					@CNSMOV, @IDART_LOTE_AL, @NOLOTE_AL, @CANT_AL, DBO.FNK_GETDATE(), @NOLOTEPED_AL,
					@FVENCE_AL, @PCOSTO_AL, CASE WHEN COALESCE(@PVENTA_AL, 0) > 0 THEN @PVENTA_AL ELSE NULL END,
					@IDART_PRINC_AL, 'OK'
				)
			END

			-- Solo sincroniza CANTIDAD asignada; CANTPEDIDA permanece como cantidad de la orden
			UPDATE IMOVH
			SET CANTIDAD = COALESCE((
					SELECT SUM(COALESCE(S.CANTIDAD, 0))
					FROM ISAL S
					WHERE S.CNSMOV = @CNSMOV
					  AND COALESCE(NULLIF(S.IDARTICULO_IMOVH, ''), S.IDARTICULO) = @IDART_PRINC_AL
				), 0),
				PVENTA = CASE WHEN COALESCE(@PVENTA_AL, 0) > 0 THEN @PVENTA_AL ELSE PVENTA END,
				ESTADO_VALIDA_PICK = 0,
				USUARIO_VALIDA_PICK = NULL,
				FECHA_VALIDA_PICK = NULL,
				OBS_VALIDA_PICK = CASE
					WHEN LEFT(COALESCE(OBS_VALIDA_PICK, ''), 4) = 'NOV:' THEN OBS_VALIDA_PICK
					ELSE NULL
				END
			WHERE CNSMOV = @CNSMOV AND IDARTICULO = @IDART_PRINC_AL

			-- Conservar PREPARACION_LISTA si bodega ya est� validando (0) o en packing (1/4/5).
			-- Solo en Devuelto (2) se reinicia preparaci�n.
			UPDATE IMOV
			SET PREPARACION_LISTA = 0,
				USUARIO_PREPARACION = NULL,
				FECHA_PREPARACION = NULL
			WHERE CNSMOV = @CNSMOV
			  AND COALESCE(PREPARACION_LISTA, 0) = 1
			  AND COALESCE(ESTADO_PICKPACK, 0) = 2

			UPDATE IMOV
			SET PREPARACION_LISTA = 1
			WHERE CNSMOV = @CNSMOV
			  AND COALESCE(ESTADO_PICKPACK, 0) IN (0, 1, 4, 5)
			  AND COALESCE(PREPARACION_LISTA, 0) = 0
			  AND (
					EXISTS (
						SELECT 1 FROM IMOVH H
						WHERE H.CNSMOV = @CNSMOV
						  AND COALESCE(H.ESTADO, 0) <> 2
						  AND COALESCE(H.ESTADO_VALIDA_PICK, 0) = 1
					)
					OR EXISTS (SELECT 1 FROM ISAL S WHERE S.CNSMOV = @CNSMOV)
				)

			UPDATE IMOV SET ESTADO_PICKPACK = 2
			WHERE CNSMOV = @CNSMOV AND COALESCE(ESTADO_PICKPACK, 0) = 4

			COMMIT TRAN
		SELECT 'OK' OK
		END TRY
		BEGIN CATCH
			IF @@TRANCOUNT > 0 ROLLBACK TRAN
			SELECT 'KO' OK, ERROR_MESSAGE() AS ERROR
		END CATCH
		RETURN
	END

   /* M�todo no atendido en este SP (usar MODELO IMOV / IMOV_3) */
   SELECT 'KO' OK, 'M�todo no soportado en SPQ_IMOV_4: ' + COALESCE(@METODO, '(NULL)') AS ERROR
   RETURN

   END TRY
   BEGIN CATCH
      IF @@TRANCOUNT > 0
         ROLLBACK TRAN;

      SELECT 'KO' OK,
             ERROR_MESSAGE() AS ERROR,
             ERROR_NUMBER() AS ERROR_NUMBER,
             ERROR_LINE() AS ERROR_LINE,
             COALESCE(ERROR_PROCEDURE(), 'SPQ_IMOV_4') AS ERROR_PROCEDURE;
      RETURN
   END CATCH
