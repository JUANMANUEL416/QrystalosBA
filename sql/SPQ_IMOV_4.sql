CREATE OR ALTER PROCEDURE DBO.SPQ_IMOV_4
@JSON NVARCHAR(MAX)
WITH ENCRYPTION
AS
DECLARE   @PARAMETROS       NVARCHAR(MAX)		,@MODELO			VARCHAR(100)	,@METODO			VARCHAR(100)
        ,@USUARIO			VARCHAR(12)			,@NVOCONSEC			VARCHAR(20)		,@CANTIDAD			INT
        ,@SEDE				VARCHAR(5)			,@NOADMISION		VARCHAR(16)		,@FECHA				VARCHAR(20)         
        ,@HORA				VARCHAR(10)			,@ITEM				SMALLINT		,@OBS				VARCHAR(2048)
        ,@SYS_COMPUTERNAME	VARCHAR(254)		,@GRUPO				VARCHAR(8)		,@PENDIENTES		SMALLINT
        ,@CNSMOV			VARCHAR(20)			,@FIRMA				VARBINARY(MAX)	,@IDBODEGA			VARCHAR(20)
		,@CNSITRA			VARCHAR(20)			,@datoIMOVH			NVARCHAR(MAX)	,@PROCESO			VARCHAR(50)
		,@NOLOTE			VARCHAR(50)			,@datoIMOV			NVARCHAR(MAX)	,@IDTIPOMOV			VARCHAR(20) 
		,@IDBODEGAEXTERNA	VARCHAR(20)			,@IDSEDE			VARCHAR(10)		,@COMPANIA			VARCHAR(10)
		,@CNSRPDX			VARCHAR(20)			,@IDARTICULO		VARCHAR(20)		,@IDAFILIADO		VARCHAR(20)		,@ID INT	
		,@CODIGOBARRA		VARCHAR(20)			,@ERROR				INT				,@IART_DESCRIPCION	VARCHAR(500)
		,@FVENCE			DATE				,@IDARTICULO_REAL	VARCHAR(20)		,@TOTAL				BIT		
		,@IDARTICULOTF		VARCHAR(20)			,@CANTIDADTF		INT				,@EXIST				INT				,@TRANS INT
		,@ACCION			VARCHAR(20)			,@ISAL				NVARCHAR(MAX)	,@PROCEDENCIA		VARCHAR(20)		,@IDITAR VARCHAR(20)
		,@ESTADO			VARCHAR(20)			,@FECHA_TIME		DATETIME		,@NODOCUMENTO		VARCHAR(50)		,@IDSERVICIO_NUEVO VARCHAR(20)
		,@IDARTICULO_IMOVH  VARCHAR(20)			,@CNSIZSOL			VARCHAR(20)		,@SECTOR			VARCHAR(20)		,@CNSTRAN VARCHAR(20)
		,@PREFIJO		    VARCHAR(20)			,@sel_IART_fab		NVARCHAR(MAX)	,@IDSERVICIO		VARCHAR(20)		,@IDAUT	VARCHAR(20)
		,@FDESDE			DATE				,@FHASTA			DATE
DECLARE @CODCAJA VARCHAR(20), @OK SMALLINT, @CNSACJ VARCHAR(20)	,@VALORTOTAL DECIMAL(14,2)	,@CONTADOR INT	,@DESCSERVICIO VARCHAR(200)
		,@IDALTERNA VARCHAR(50) , @OBSERVACION VARCHAR(500),@MARCACONT BIT  ,@IDTERCERO VARCHAR(20), @NOLOTEPEDIDO VARCHAR(20)
DECLARE @ARTICULOS NVARCHAR(MAX)
DECLARE @ITEM_AUTD INT		, @LIMITE_AU INT ,@IDPLAN VARCHAR(7)
DECLARE @TABLA_ERROR TABLE (ERROR VARCHAR(200), IDARTICULO VARCHAR(20), DESCRIPCION VARCHAR(900), NOLOTEPEDIDO VARCHAR(20), NOLOTE VARCHAR(30), CANTIDAD VARCHAR(20))

BEGIN
	SET NOCOUNT ON
	SET XACT_ABORT ON
	SET DATEFORMAT dmy

	BEGIN TRY
	/*
	  SPQ_IMOV_4 independiente: Pick&Pack. Sin EXEC a IMOV/_3.
	  Front: MODELO IMOV_4. Sin whitelist al inicio: cada IF @METODO atiende o cae al KO final.

	  Reserva de lotes (soft-reserve en ISAL; no descuenta IEXI hasta CONFIRMA_SALIDA):
	  - Alta/edici�n de lotes (ISAL) marca cantidad no disponible para otros PP (ES_PICKPACK=1, ESTADO=0).
	  - DEVOLVER_PICKING / CONFIRMA_PICKING / MARCAR_CORRECCION_LISTA: NO liberan reserva (ISAL permanece).
	  - Liberaci�n solo cuando: se elimina lote/IMOVH (DELETE ISAL) o packing confirma la salida (IMOV.ESTADO?1).
	*/
	SELECT @MODELO = JSON_VALUE(@JSON, '$.MODELO')
	     , @METODO = JSON_VALUE(@JSON, '$.METODO')
	     , @USUARIO = JSON_VALUE(@JSON, '$.USUARIO')
	     , @PARAMETROS = JSON_QUERY(@JSON, '$.PARAMETROS')

	DECLARE @TBLERRORES TABLE(ERROR VARCHAR(1200));

	IF @METODO IS NULL OR LTRIM(RTRIM(@METODO)) = ''
	BEGIN
		SELECT 'KO' OK, 'M�todo no indicado en SPQ_IMOV_4' AS ERROR
		RETURN
	END

	/* Sesi�n solo si hace falta (roles pickpack no requieren FNK_DESCIFRAR) */
	IF @METODO NOT IN ('OBTENER_ROLES_PICKPACK','LISTA_NOVEDADES_PICKPACK')
	   AND COALESCE(@USUARIO, '') <> ''
	BEGIN
		SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WITH (NOLOCK) WHERE USUARIO = @USUARIO
		SELECT @IDSEDE = IDSEDE, @SEDE = IDSEDE, @COMPANIA=COMPANIA, @IDBODEGA = COALESCE(IDBODEGA, IDBODEGA2, IDBODEGANOCHE, IDBODEGACONSUMO)
		FROM UBEQ WITH (NOLOCK) WHERE SYS_ComputerName = @SYS_COMPUTERNAME
		SELECT @GRUPO = DBO.FNK_DESCIFRAR(USUSU.GRUPO) FROM USUSU WITH (NOLOCK) WHERE USUARIO = @USUARIO
	END

	-- PICKING & PACKING (solo bodegas IBOD.MANEJA_PICKPACK = 1, salidas IMOV)
	-- =====================================================================================

	IF @METODO = 'LISTA_PICKING'
	BEGIN
		SELECT @IDBODEGA = JSON_VALUE(@PARAMETROS, '$.IDBODEGA')
		SELECT @ESTADO = JSON_VALUE(@PARAMETROS, '$.ESTADO_PICKPACK')

		IF COALESCE(@IDBODEGA, '') = ''
		BEGIN
			SELECT 'KO' OK, 'Debe indicar la bodega.' AS ERROR
			RETURN
		END

		IF NOT EXISTS (SELECT 1 FROM IBOD WHERE IDBODEGA = @IDBODEGA AND COALESCE(MANEJA_PICKPACK, 0) = 1)
		BEGIN
			SELECT 'KO' OK, 'La bodega no tiene habilitado Picking y Packing.' AS ERROR
			RETURN
		END

		SELECT 'OK' OK

		SELECT
			M.CNSMOV,
			M.IDBODEGA,
			M.IDTIPOMOV,
			T.DESCRIPCION AS DESC_TIPOMOV,
			M.NODOCUMENTO,
			M.FECHAMOV,
			M.IDTERCERO,
			M.IDPLAN,
			M.USUARIO,
			COALESCE(M.ESTADO_PICKPACK, 0) AS ESTADO_PICKPACK,
			CASE COALESCE(M.ESTADO_PICKPACK, 0)
				WHEN 0 THEN 'Pendiente Picking'
				WHEN 2 THEN 'Devuelto con novedad'
				WHEN 4 THEN 'Listo para reconfirmar'
				WHEN 5 THEN CASE WHEN COALESCE(M.TIENE_NOVEDAD, 0) = 1 THEN 'Picking parcial (novedad)' ELSE 'Picking parcial' END
				ELSE 'Picking confirmado'
			END AS ESTADO_PICKPACK_DESC,
			CAST(COALESCE(M.TIENE_NOVEDAD, 0) AS BIT) AS TIENE_NOVEDAD,
			COALESCE(M.ENTREGADO, 0) AS ENTREGADO
		FROM IMOV M WITH (NOLOCK)
		INNER JOIN ITMO T WITH (NOLOCK) ON T.IDTIPOMOV = M.IDTIPOMOV AND T.TIPO = 'Debito'
		WHERE M.IDBODEGA = @IDBODEGA
		  AND COALESCE(M.ESTADO, 0) = 0
		  AND COALESCE(M.ESTADO_PICKPACK, 0) IN (0, 2, 4, 5)
		  AND (@ESTADO IS NULL OR CAST(M.ESTADO_PICKPACK AS VARCHAR(5)) = @ESTADO)
		ORDER BY M.FECHAMOV DESC, M.CNSMOV DESC
		RETURN
	END

	IF @METODO = 'LISTA_PACKING'
	BEGIN
		DECLARE @ESTADO_PACK_FILTRO VARCHAR(20)

		SELECT @IDBODEGA = JSON_VALUE(@PARAMETROS, '$.IDBODEGA')
		SELECT @ESTADO_PACK_FILTRO = UPPER(NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.ESTADO'))), ''))
		IF @ESTADO_PACK_FILTRO IS NULL SET @ESTADO_PACK_FILTRO = 'PENDIENTE'

		IF COALESCE(@IDBODEGA, '') = ''
		BEGIN
			SELECT 'KO' OK, 'Debe indicar la bodega.' AS ERROR
			RETURN
		END

		IF NOT EXISTS (SELECT 1 FROM IBOD WHERE IDBODEGA = @IDBODEGA AND COALESCE(MANEJA_PICKPACK, 0) = 1)
		BEGIN
			SELECT 'KO' OK, 'La bodega no tiene habilitado Picking y Packing.' AS ERROR
			RETURN
		END

		SELECT 'OK' OK

		SELECT
			M.CNSMOV,
			M.IDBODEGA,
			M.IDTIPOMOV,
			T.DESCRIPCION AS DESC_TIPOMOV,
			M.NODOCUMENTO,
			M.FECHAMOV,
			M.USUARIO,
			M.USUARIO_PICKING,
			COALESCE(
				NULLIF((
					SELECT TOP 1 U.NOMBRE
					FROM USUSU U WITH (NOLOCK)
					WHERE U.USUARIO = M.USUARIO_PICKING
				), ''),
				M.USUARIO_PICKING
			) AS NOMBRE_PICKER,
			M.FECHA_PICKING,
			M.USUARIO_PACKING,
			M.FECHA_PACKING,
			COALESCE(M.ESTADO, 0) AS ESTADO,
			COALESCE(M.ESTADO_PICKPACK, 0) AS ESTADO_PICKPACK,
			CASE
				WHEN COALESCE(M.ESTADO_PICKPACK, 0) = 3 THEN 'SALIDA'
				ELSE 'PENDIENTE'
			END AS ESTADO_PACKING,
			CASE
				WHEN COALESCE(M.ESTADO_PICKPACK, 0) = 3 THEN 'Con salida'
				ELSE 'Pendiente de salida'
			END AS ESTADO_PACKING_DESC,
			CAST(COALESCE(M.TIENE_NOVEDAD, 0) AS BIT) AS TIENE_NOVEDAD,
			COALESCE(M.ENTREGADO, 0) AS ENTREGADO
		FROM IMOV M WITH (NOLOCK)
		INNER JOIN ITMO T WITH (NOLOCK) ON T.IDTIPOMOV = M.IDTIPOMOV AND T.TIPO = 'Debito'
		WHERE M.IDBODEGA = @IDBODEGA
		  AND COALESCE(M.ENTREGADO, 0) = 1
		  AND EXISTS (
				SELECT 1
				FROM STRING_SPLIT(COALESCE(DBO.FNK_VALORVARIABLE('IDMOVPICKPACK'), ''), ',') S
				WHERE LTRIM(RTRIM(S.value)) <> ''
				  AND LTRIM(RTRIM(S.value)) = M.IDTIPOMOV
			  )
		  AND (
				(@ESTADO_PACK_FILTRO = 'PENDIENTE'
					AND COALESCE(M.ESTADO_PICKPACK, 0) IN (1, 5)
					AND COALESCE(M.ESTADO, 0) = 0)
				OR (@ESTADO_PACK_FILTRO = 'SALIDA'
					AND COALESCE(M.ESTADO_PICKPACK, 0) = 3)
				OR (@ESTADO_PACK_FILTRO = 'TODOS'
					AND (
						(COALESCE(M.ESTADO_PICKPACK, 0) IN (1, 5) AND COALESCE(M.ESTADO, 0) = 0)
						OR COALESCE(M.ESTADO_PICKPACK, 0) = 3
					))
			  )
		ORDER BY
			CASE WHEN COALESCE(M.ESTADO_PICKPACK, 0) IN (1, 5) THEN 0 ELSE 1 END,
			COALESCE(M.FECHA_PACKING, M.FECHA_PICKING) DESC,
			M.CNSMOV DESC
		RETURN
	END

	IF @METODO = 'DETALLE_PACKING'
	BEGIN
		SELECT @CNSMOV = JSON_VALUE(@PARAMETROS, '$.CNSMOV')
		DECLARE @SOLO_NOVEDADES_DP BIT = COALESCE(TRY_CAST(JSON_VALUE(@PARAMETROS, '$.SOLO_NOVEDADES') AS BIT), 0)
		DECLARE @TODOS_LOTES_DP BIT = COALESCE(TRY_CAST(JSON_VALUE(@PARAMETROS, '$.TODOS_LOTES') AS BIT), 0)

		SELECT 'OK' OK

		-- Una fila por lote de ISAL (lo pickeado) para packing / novedades / preparaci�n
		SELECT
			S.CNSMOV,
			S.IDARTICULO,
			IART.DESCRIPCION,
			COALESCE(NULLIF(S.IDARTICULO_IMOVH, ''), S.IDARTICULO) AS IDARTICULO_PRINCIPAL,
			COALESCE(IART_P.DESCRIPCION, IART.DESCRIPCION) AS DESCRIPCION_PRINCIPAL,
			COALESCE(H.CANTPEDIDA, 0)   AS CANT_PEDIDA,
			COALESCE(S.CANTIDAD, 0)     AS CANT_PICKEADA,
			COALESCE(S.NOLOTE, '')      AS NOLOTE,
			COALESCE(S.NOLOTEPEDIDO, '') AS NOLOTEPEDIDO,
			S.FECHAVENCE,
			COALESCE(S.PCOSTO, 0)       AS PCOSTO,
			COALESCE(S.PVENTA, 0)       AS PVENTA,
			COALESCE(IART.IDSERVICIO, S.IDARTICULO) AS IDSERVICIO,
			COALESCE(S.ESTADO_PICK, 'OK') AS ESTADO_PICK,
			CASE
				WHEN @SOLO_NOVEDADES_DP = 1 THEN 'NOVEDAD'
				WHEN UPPER(LTRIM(RTRIM(COALESCE(S.ESTADO_PICK, 'OK')))) = 'NOVEDAD' THEN 'NOVEDAD'
				ELSE CASE
					WHEN COALESCE(S.CANTIDAD, 0) > 0 THEN 'OK'
					ELSE 'DIFERENCIA'
				END
			END AS ESTADO_LINEA,
			COALESCE(S.IDTIPO_NOVEDAD, '') AS IDTIPO_NOVEDAD,
			COALESCE(TG.DESCRIPCION, '')   AS TIPO_NOVEDAD_DESC,
			COALESCE(
				NULLIF(LTRIM(RTRIM(S.OBS_NOVEDAD)), ''),
				CASE
					WHEN LEFT(COALESCE(H.OBS_VALIDA_PICK, ''), 4) = 'NOV:'
					THEN NULLIF(LTRIM(RTRIM(SUBSTRING(H.OBS_VALIDA_PICK, 5, 500))), '')
					ELSE NULL
				END,
				''
			) AS OBS_NOVEDAD
		FROM ISAL S WITH (NOLOCK)
		INNER JOIN IART WITH (NOLOCK) ON IART.IDARTICULO = S.IDARTICULO
		LEFT JOIN IART IART_P WITH (NOLOCK)
			ON IART_P.IDARTICULO = COALESCE(NULLIF(S.IDARTICULO_IMOVH, ''), S.IDARTICULO)
		LEFT JOIN IMOVH H WITH (NOLOCK)
			ON H.CNSMOV = S.CNSMOV
		   AND H.IDARTICULO = COALESCE(NULLIF(S.IDARTICULO_IMOVH, ''), S.IDARTICULO)
		   AND COALESCE(H.ESTADO, 0) <> 2
		LEFT JOIN TGEN TG WITH (NOLOCK)
			ON TG.TABLA = 'PICKPACK'
		   AND TG.CAMPO = 'NOVEDAD'
		   AND TG.CODIGO = S.IDTIPO_NOVEDAD
		WHERE S.CNSMOV = @CNSMOV
		  AND (
				-- Preparaci�n / asignaci�n de lotes: todos los ISAL del movimiento
				@TODOS_LOTES_DP = 1
				OR (
					@SOLO_NOVEDADES_DP = 1
					AND (
						UPPER(LTRIM(RTRIM(COALESCE(S.ESTADO_PICK, '')))) = 'NOVEDAD'
						OR COALESCE(NULLIF(S.IDTIPO_NOVEDAD, ''), '') <> ''
						OR LEFT(COALESCE(H.OBS_VALIDA_PICK, ''), 4) = 'NOV:'
					)
				)
				OR (
					COALESCE(@SOLO_NOVEDADES_DP, 0) = 0
					AND COALESCE(@TODOS_LOTES_DP, 0) = 0
					AND EXISTS (
						SELECT 1
						FROM IMOVH HV WITH (NOLOCK)
						WHERE HV.CNSMOV = S.CNSMOV
						  AND HV.IDARTICULO = COALESCE(NULLIF(S.IDARTICULO_IMOVH, ''), S.IDARTICULO)
						  AND COALESCE(HV.ESTADO, 0) <> 2
						  AND COALESCE(HV.ESTADO_VALIDA_PICK, 0) = 1
					)
				)
		  )
		ORDER BY COALESCE(NULLIF(S.IDARTICULO_IMOVH, ''), S.IDARTICULO), S.IDARTICULO, S.NOLOTE
		RETURN
	END

	IF @METODO = 'RESUMEN_NOVEDADES_PICKPACK'
	BEGIN
		SELECT @CNSMOV = JSON_VALUE(@PARAMETROS, '$.CNSMOV')

		IF COALESCE(@CNSMOV, '') = ''
		BEGIN
			SELECT 'KO' OK, 'Debe indicar el movimiento.' AS ERROR
			RETURN
		END

		SELECT 'OK' OK

		SELECT
			S.CNSMOV,
			S.IDARTICULO,
			IART.DESCRIPCION,
			COALESCE(NULLIF(S.IDARTICULO_IMOVH, ''), S.IDARTICULO) AS IDARTICULO_PRINCIPAL,
			COALESCE(IART_P.DESCRIPCION, IART.DESCRIPCION) AS DESCRIPCION_PRINCIPAL,
			COALESCE(H.CANTPEDIDA, 0)   AS CANT_PEDIDA,
			COALESCE(S.CANTIDAD, 0)     AS CANT_PICKEADA,
			COALESCE(S.NOLOTE, '')      AS NOLOTE,
			COALESCE(S.NOLOTEPEDIDO, '') AS NOLOTEPEDIDO,
			S.FECHAVENCE,
			COALESCE(S.ESTADO_PICK, 'OK') AS ESTADO_PICK,
			'NOVEDAD' AS ESTADO_LINEA,
			COALESCE(S.IDTIPO_NOVEDAD, '') AS IDTIPO_NOVEDAD,
			COALESCE(TG.DESCRIPCION, '')   AS TIPO_NOVEDAD_DESC,
			COALESCE(
				NULLIF(LTRIM(RTRIM(S.OBS_NOVEDAD)), ''),
				CASE
					WHEN LEFT(COALESCE(H.OBS_VALIDA_PICK, ''), 4) = 'NOV:'
					THEN NULLIF(LTRIM(RTRIM(SUBSTRING(H.OBS_VALIDA_PICK, 5, 500))), '')
					ELSE NULL
				END,
				''
			) AS OBS_NOVEDAD
		FROM ISAL S WITH (NOLOCK)
		INNER JOIN IART WITH (NOLOCK) ON IART.IDARTICULO = S.IDARTICULO
		LEFT JOIN IART IART_P WITH (NOLOCK)
			ON IART_P.IDARTICULO = COALESCE(NULLIF(S.IDARTICULO_IMOVH, ''), S.IDARTICULO)
		LEFT JOIN IMOVH H WITH (NOLOCK)
			ON H.CNSMOV = S.CNSMOV
		   AND H.IDARTICULO = COALESCE(NULLIF(S.IDARTICULO_IMOVH, ''), S.IDARTICULO)
		   AND COALESCE(H.ESTADO, 0) <> 2
		LEFT JOIN TGEN TG WITH (NOLOCK)
			ON TG.TABLA = 'PICKPACK'
		   AND TG.CAMPO = 'NOVEDAD'
		   AND TG.CODIGO = S.IDTIPO_NOVEDAD
		WHERE S.CNSMOV = @CNSMOV
		  AND (
				UPPER(LTRIM(RTRIM(COALESCE(S.ESTADO_PICK, '')))) = 'NOVEDAD'
				OR COALESCE(NULLIF(S.IDTIPO_NOVEDAD, ''), '') <> ''
				OR LEFT(COALESCE(H.OBS_VALIDA_PICK, ''), 4) = 'NOV:'
		  )
		ORDER BY COALESCE(NULLIF(S.IDARTICULO_IMOVH, ''), S.IDARTICULO), S.IDARTICULO, S.NOLOTE
		RETURN
	END

	IF @METODO = 'CONFIRMAR_PREPARACION_PICKING'
	BEGIN
		SELECT @CNSMOV = JSON_VALUE(@PARAMETROS, '$.CNSMOV')
		SELECT @IDBODEGA = IDBODEGA FROM IMOV WHERE CNSMOV = @CNSMOV

		IF COALESCE(@CNSMOV, '') = '' OR COALESCE(@IDBODEGA, '') = ''
		BEGIN
			SELECT 'KO' OK, 'Movimiento o bodega no encontrados.' AS ERROR
			RETURN
		END

		IF NOT EXISTS (
			SELECT 1 FROM IMOV M
			INNER JOIN IBOD B ON B.IDBODEGA = M.IDBODEGA
			WHERE M.CNSMOV = @CNSMOV
			  AND M.IDBODEGA = @IDBODEGA
			  AND COALESCE(B.MANEJA_PICKPACK, 0) = 1
			  AND COALESCE(M.ESTADO, 0) = 0
			  AND COALESCE(M.ESTADO_PICKPACK, 0) IN (0, 2, 4, 5)
		)
		BEGIN
			SELECT 'KO' OK, 'El movimiento no est� disponible para confirmar preparaci�n.' AS ERROR
			RETURN
		END

		IF NOT EXISTS (SELECT 1 FROM ISAL WHERE CNSMOV = @CNSMOV)
		BEGIN
			SELECT 'KO' OK, 'Debe asignar al menos un lote antes de confirmar la preparaci�n.' AS ERROR
			RETURN
		END

		-- Venta cliente (factura / particular): exigir PVENTA > 0 si PVENTA_MOV_SAL o PVENTA_AUTO_TARIFA
		IF EXISTS (
			SELECT 1 FROM IMOV M WITH (NOLOCK)
			WHERE M.CNSMOV = @CNSMOV
			  AND (
					M.IDTIPOMOV = DBO.FNK_VALORVARIABLE('IDINVMOVVENTAFACTURA')
					OR M.IDTIPOMOV = DBO.FNK_VALORVARIABLE('IDINVENTA_PARTICULAR')
				)
			  AND (
					DBO.FNK_VALORVARIABLE('PVENTA_MOV_SAL') = 'SI'
					OR DBO.FNK_VALORVARIABLE('PVENTA_AUTO_TARIFA') = 'SI'
				)
		)
		AND EXISTS (
			SELECT 1 FROM ISAL S WITH (NOLOCK)
			WHERE S.CNSMOV = @CNSMOV
			  AND COALESCE(S.PVENTA, 0) <= 0
		)
		BEGIN
			SELECT 'KO' OK, 'Hay lotes sin precio de venta. Configure la tarifa o ingrese el precio antes de confirmar la preparaci�n.' AS ERROR
			RETURN
		END

		UPDATE IMOV
		SET PREPARACION_LISTA = 1,
			USUARIO_PREPARACION = @USUARIO,
			FECHA_PREPARACION = DBO.FNK_GETDATE(),
			ES_PICKPACK = 1
		WHERE CNSMOV = @CNSMOV

		SELECT 'OK' OK
		RETURN
	END

	IF @METODO = 'SINCRONIZAR_DETALLE_PICKING'
	BEGIN
		SELECT @CNSMOV = JSON_VALUE(@PARAMETROS, '$.CNSMOV')
		SELECT @IDBODEGA = IDBODEGA FROM IMOV WHERE CNSMOV = @CNSMOV

		IF COALESCE(@CNSMOV, '') = '' OR COALESCE(@IDBODEGA, '') = ''
		BEGIN
			SELECT 'KO' OK, 'Movimiento no encontrado.' AS ERROR
			RETURN
		END

		IF @@TRANCOUNT > 0
		BEGIN
			SELECT 'KO' OK, 'SINCRONIZAR_DETALLE_PICKING debe ejecutarse sin una transacci�n externa.' AS ERROR
			RETURN
		END

		DECLARE @RECURSO_LOCK_SD NVARCHAR(255)
		DECLARE @RESULTADO_LOCK_SD INT
		DECLARE @ESTADO_SD INT
		DECLARE @ES_PICKPACK_SD BIT
		DECLARE @IDBODEGA_LOCK_SD VARCHAR(20)

		BEGIN TRAN

		SET @RECURSO_LOCK_SD = N'QRY_PICKPACK_RESERVA_BODEGA_' + @IDBODEGA
		EXEC @RESULTADO_LOCK_SD = sys.sp_getapplock
			@Resource = @RECURSO_LOCK_SD,
			@LockMode = 'Exclusive',
			@LockOwner = 'Transaction',
			@LockTimeout = 15000

		IF @RESULTADO_LOCK_SD < 0
		BEGIN
			ROLLBACK TRAN
			SELECT 'KO' OK, 'No fue posible bloquear temporalmente la bodega para sincronizar el detalle. Intente nuevamente.' AS ERROR
			RETURN
		END

		-- Revalidar dentro del lock: el movimiento pudo cambiar mientras se esperaba.
		SELECT
			@ESTADO_SD = COALESCE(ESTADO, 0),
			@ES_PICKPACK_SD = COALESCE(ES_PICKPACK, 0),
			@IDBODEGA_LOCK_SD = IDBODEGA
		FROM IMOV WITH (UPDLOCK, HOLDLOCK)
		WHERE CNSMOV = @CNSMOV

		IF COALESCE(@IDBODEGA_LOCK_SD, '') <> @IDBODEGA
		   OR COALESCE(@ESTADO_SD, -1) <> 0
		   OR COALESCE(@ES_PICKPACK_SD, 0) <> 1
		BEGIN
