			@ORDEN_IMP = ORDEN_IMP,
			@MANTE = MANTE,
			@PROCESO = PROCESO
        FROM OPENJSON(@REGISTROS)
        WITH (
            COMPANIA     VARCHAR(2)     '$.COMPANIA',
            CLASE		 VARCHAR(10)    '$.CLASE',
			RUBRO		 VARCHAR(50)	'$.RUBRO',
			CONSECUTIVO		 VARCHAR(20)	'$.CONSECUTIVO',
			RUBROANT	 VARCHAR(50)	'$.RUBROANT',
			NOMRUBRO	 VARCHAR(60)	'$.NOMRUBRO',
			TIPO		 VARCHAR(7)		'$.TIPO',
			RECURSO		 VARCHAR(2)		'$.RECURSO',
			NIVEL		 SMALLINT		'$.NIVEL',
			CUENTA_SUMA	 VARCHAR(50)	'$.CUENTA_SUMA',
			ESTADO		 VARCHAR(8)		'$.ESTADO',
			DIVISION	 VARCHAR(5)			'$.DIVISION',
			ORDEN_IMP	 INT			'$.ORDEN_IMP',
			MANTE		 BIT			'$.MANTE',
			RUBRO_ID     INT            '$.RUBRO_ID',
			PROCESO      VARCHAR(20)	'$.PROCESO'
        )

        BEGIN TRY
            -- INSERTAR
            IF UPPER(@PROCESO) = 'INSERTAR'
            BEGIN
                IF (SELECT COUNT(*) FROM @TBLERRORES) = 0
                BEGIN
                    INSERT INTO PTRUB (COMPANIA, CONSECUTIVO, CLASE, RUBRO, RUBROANT, NOMRUBRO, TIPO, RECURSO, NIVEL, CUENTA_SUMA, ESTADO, DIVISION, ORDEN_IMP, MANTE)
                    VALUES (@COMPANIA, @CONSECUTIVO, @CLASE, @RUBRO, @RUBROANT, @NOMRUBRO, @TIPO, @RECURSO, @NIVEL, @CUENTA_SUMA, @ESTADO, @DIVISION, @ORDEN_IMP, @MANTE)
                END
            END

            -- EDITAR
            IF UPPER(@PROCESO) = 'EDITAR'
            BEGIN
                UPDATE PTRUB
                SET CLASE = @CLASE,
					RUBRO = @RUBRO,
					RUBROANT = @RUBROANT,
					NOMRUBRO = @NOMRUBRO,
					TIPO = @TIPO,
					RECURSO = @RECURSO,
					NIVEL = @NIVEL,
					CUENTA_SUMA = @CUENTA_SUMA,
					ESTADO = @ESTADO,
					DIVISION = @DIVISION,
					ORDEN_IMP = @ORDEN_IMP,
					MANTE = @MANTE
                WHERE RUBRO_ID = @RUBRO_ID
            END

            -- ELIMINAR
            IF UPPER(@PROCESO) = 'ELIMINAR'
            BEGIN
                DELETE FROM PTRUB
                WHERE RUBRO_ID = @RUBRO_ID
            END

        END TRY
        BEGIN CATCH
            INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
        END CATCH

        -- Retornar errores si existen
        IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
        BEGIN
            SELECT 'KO' AS OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
        END

        -- Todo ok
