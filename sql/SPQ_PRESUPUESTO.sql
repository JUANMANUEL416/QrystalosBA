        RETURN
    END

	IF @METODO = 'ENVIAR'
	BEGIN
		SELECT @CNSPAGO = CNSPAGO
		FROM OPENJSON(@PARAMETROS)
		WITH (CNSPAGO VARCHAR(20) '$.CNSPAGO');

		-- Validaci�n: No puede faltar el CDP o PPTO
		IF NOT EXISTS (SELECT 1 FROM NPER WHERE CNSPAGO=@CNSPAGO AND COALESCE(CNSCDP,'')<>'' AND COALESCE(CNSPPTO,'')<>'')
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR= 'No ha Asignado el CDP para esta n�mina.'
			RETURN
		END

		IF EXISTS(SELECT 1 FROM NPER WHERE CNSPAGO=@CNSPAGO AND ENPPTO=1)
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR= 'Este presupuesto ya fue previamente enviado'
			RETURN
		END

		-- Genera el consecutivo num�rico con tu SP est�ndar
		EXEC SPK_GENCONSECUTIVO @COMPANIA = @COMPANIA, @SEDE = @IDSEDE, @PREFIJO  = '@RPDX', @NVOCONSEC=@CNSRPDX OUTPUT
		SELECT @CNSRPDX = @IDSEDE + REPLACE(SPACE(8 - LEN(@CNSRPDX))+LTRIM(RTRIM(@CNSRPDX)),SPACE(1),0)

		-- Ejecutar SP de revisi�n
		BEGIN TRY
			EXEC SPK_REVISANOMINA_ANTES @CNSRPDX, @CNSPAGO
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'Error en SPK_REVISANOMINA_ANTES: ' + ERROR_MESSAGE()
		END CATCH
		-- Validar si hay registros en RPDX para el CNS generado
		IF (SELECT COUNT(1) FROM RPDX WHERE CNS = @CNSRPDX) > 0
