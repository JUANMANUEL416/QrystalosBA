            COMPANIA    VARCHAR(2)   '$.COMPANIA',
            RECURSO     VARCHAR(2)   '$.RECURSO',
            DESCRIPCION VARCHAR(50)  '$.DESCRIPCION'
        );

        BEGIN TRY
            IF UPPER(@PROCESO) = 'Insertar'
			BEGIN
				IF EXISTS (
					SELECT 1 FROM PTREC
					WHERE COMPANIA = @COMPANIA AND RECURSO = @RECURSO
				)
				BEGIN
					INSERT INTO @TBLERRORES (ERROR)
					VALUES ('El recurso ya existe para esta compa�ia.')
				END
				ELSE
				BEGIN
					INSERT INTO PTREC (COMPANIA, RECURSO, DESCRIPCION)
					VALUES (@COMPANIA, @RECURSO, @DESCRIPCION)
				END
			END

            IF UPPER(@PROCESO) = 'Editar'
            BEGIN
                UPDATE PTREC
                SET 
                    DESCRIPCION = @DESCRIPCION,
                    RECURSO     = @RECURSO
                WHERE RECURSO = @RECURSO AND COMPANIA = @COMPANIA
            END

            IF UPPER(@PROCESO) = 'Eliminar'
            BEGIN
                DELETE FROM PTREC
                WHERE RECURSO = @RECURSO AND COMPANIA = @COMPANIA
            END
        END TRY
        BEGIN CATCH
            INSERT INTO @TBLERRORES (ERROR)
            SELECT ERROR_MESSAGE();
        END CATCH

        IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
        BEGIN
            SELECT 'KO' AS OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
        END
        SELECT 'OK' AS OK
        RETURN
    END

