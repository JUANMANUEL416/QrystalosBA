					CLASIFICACION = @CLASIFICACION,
					ESTADO = @ESTADO
				WHERE COMPANIA = @COMPANIA AND IDTIPOMOV = @IDTIPOMOV
			END

			IF UPPER(@PROCESO) = 'ELIMINAR'
			BEGIN
				DELETE FROM PTTMOV
				WHERE COMPANIA = @COMPANIA AND IDTIPOMOV = @IDTIPOMOV
			END
		END TRY
		BEGIN CATCH
			IF ERROR_NUMBER() = 547
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				VALUES ('Aviso Importante: La Clasificaci�n seleccionada no existe en la tabla PTCLA. Por favor, seleccione una v�lida.')
			END
			ELSE
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				VALUES (ERROR_MESSAGE())
			END
		END CATCH

		IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' AS OK;
			SELECT ERROR FROM @TBLERRORES
			RETURN;
		END
		SELECT 'OK' AS OK;
		RETURN;
	END

