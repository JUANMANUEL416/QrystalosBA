		@CLASE		   VARCHAR(10),			@CONTADOR_RR DECIMAL(14, 0),
		@DESCPLAN	   VARCHAR(45),			@CONTADOR_RRR DECIMAL(14, 0),
		@RUBROANT	   VARCHAR(50),			@MSALDOXMES SMALLINT,
		@ORDEN_IMP	   INT,					@MCCOSTO SMALLINT,
		@MANTE		   BIT,					@MDIVISION SMALLINT,
		@NOMRUBRO	   VARCHAR(60),			@MDRUBROS SMALLINT,
		@RUBRORECART   VARCHAR(50),			@VALOR DECIMAL(14, 6),
		@TIPO		   VARCHAR(7),			@MES INT,
		@NIVEL		   SMALLINT,			@CERRADO_PPTO BIT,
		@CUENTA_SUMA   VARCHAR(50),
		@RUBROCOPA	   VARCHAR(50),
		@NORECOCOPA	   BIT,
