					CLASIFICACION = @CLASIFICACION
				WHERE COMPANIA = @COMPANIA AND CLASIFICACION = @CLASIFICACION
			END

			IF UPPER(@PROCESO) = 'ELIMINAR'
			BEGIN
				BEGIN TRY
					DELETE FROM PTCLA
					WHERE COMPANIA = @COMPANIA AND CLASIFICACION = @CLASIFICACION
				END TRY
				BEGIN CATCH
					IF ERROR_NUMBER() = 547 -- Violaci�n de FK
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						VALUES ('No se puede eliminar la Clasificaci�n porque est� siendo utilizada en Tipos de Movimientos.')
					END
					ELSE
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						VALUES (ERROR_MESSAGE())
					END
				END CATCH
			END
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();
		END CATCH

		IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' AS OK;
			SELECT ERROR FROM @TBLERRORES;
			RETURN;
		END
		SELECT 'OK' AS OK;
		RETURN;
	END

