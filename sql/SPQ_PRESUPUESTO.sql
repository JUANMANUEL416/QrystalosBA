			CLASIFICACION  VARCHAR(50)  '$.CLASIFICACION',
			ESTADO         VARCHAR(50)  '$.ESTADO'
		);

		BEGIN TRY
			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				IF EXISTS (
					SELECT 1 FROM PTTMOV
					WHERE COMPANIA = @COMPANIA AND IDTIPOMOV = @IDTIPOMOV
				)
				BEGIN
					INSERT INTO @TBLERRORES (ERROR)
					VALUES ('El Id tipo movimiento ya existe para esta compa�ia.')
				END
				ELSE
				BEGIN
					INSERT INTO PTTMOV (COMPANIA, IDTIPOMOV, DESCRIPCION, CLASEMOV, TIPOMOV, CLASIFICACION, ESTADO)
