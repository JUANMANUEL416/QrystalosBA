    IF @METODO = 'CRUDPTREC'
    BEGIN
        SELECT 
            @REGISTROS = REGISTRO,
            @PROCESO   = PROCESO
        FROM OPENJSON(@PARAMETROS)
        WITH (
            REGISTRO NVARCHAR(MAX) AS JSON,
            PROCESO  VARCHAR(20)   '$.PROCESO'
        )

        SELECT 
            @COMPANIA    = COMPANIA,
            @RECURSO     = RECURSO,
            @DESCRIPCION = DESCRIPCION
        FROM OPENJSON(@REGISTROS)
