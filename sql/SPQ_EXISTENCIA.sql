			INSERT INTO @TBLERRORES(ERROR) SELECT 'No est� configurado el tipo de movimiento IDINVTRASLOTESAL en variables del sistema.';
		IF COALESCE(@IDINVTRASLOTEENT_V, '') = ''
			INSERT INTO @TBLERRORES(ERROR) SELECT 'No est� configurado el tipo de movimiento IDINVTRASLOTEENT en variables del sistema.';
		IF COALESCE(@CCOSTO_BOD, '') = ''
			INSERT INTO @TBLERRORES(ERROR) SELECT 'La bodega no tiene centro de costo configurado.';

		IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		BEGIN TRY
			SET XACT_ABORT ON
			BEGIN TRAN

			-- -- 1. MOVIMIENTO DE SALIDA (ESTADO=0, pendiente para confirmaci�n) ----
			SET @CNSMOV_SAL = SPACE(20)
			EXEC SPQ_GENSEQUENCE @SEDE = @SEDE_USU, @PREFIJO = '@MOV', @LONGITUD = 8, @NVOCONSEC = @CNSMOV_SAL OUTPUT

			-- NODOCUMENTO = @CNSMOV_SAL solo de forma temporal: SPK_CONFIRMARSALIDAS lo copia
			-- al movimiento de entrada y as� localizamos @CNSMOV_ENT. Luego se limpia en ambos
			-- IMOV (traslado interno en bodega; NODOCUMENTO queda para facturas/remisiones/OC).
			INSERT INTO IMOV (
				CNSMOV, IDBODEGA, IDTIPOMOV, IDBODEGAEXTERNA, NODOCUMENTO,
				CCOSTO, IDAREA, IDITAR, OBSERVACION,
				FECHAMOV, PROCEDENCIA, USUARIO, CONTABILIZADA, ESTADO
			)
			VALUES (
				@CNSMOV_SAL, @IDBODEGA, @IDINVTRASLOTESAL_V, @IDBODEGA, @CNSMOV_SAL,
				@CCOSTO_BOD, @IDAREA_BOD, @IDITAR_ART, 'TRASLADO ENTRE LOTES DE UN ARTICULO.',
				DBO.FNK_GETDATE(), 'INV', @USUARIO, 0, 0
			);

			INSERT INTO IMOVH (
				CNSMOV, IDARTICULO, CANTIDAD, CANTPEDIDA,
				PCOSTO, PVENTA, IDITAR,
				NOLOTE, NOLOTEPEDIDO, FECHAVENCE,
				EXISTENCIA, ESTADO, USUARIO
			)
			VALUES (
				@CNSMOV_SAL, @IDARTICULO, @CANTIDAD_TRASLADO, @CANTIDAD_TRASLADO,
				@PCOSTO_ART, @PCOSTO_ART, @IDITAR_ART,
				@NOLOTE_ORIGEN, @NOLOTEPEDIDO_ORIGEN, @FECHAVENCE_ORIG,
				@EXISTENCIA_ORIG, 0, @USUARIO
			);

			-- ISAL: requerido por SPK_CONFIRMARSALIDAS para descontar IEXI origen
			-- y para que la l�gica IDINVTRASLOTESAL ubique el lote correcto.
			INSERT INTO ISAL (
				CNSMOV, NOLOTE, IDARTICULO, CANTIDAD, FECHA,
				NOLOTEPEDIDO, FECHAVENCE, PCOSTO, IDARTICULO_IMOVH
			)
			VALUES (
				@CNSMOV_SAL, @NOLOTE_ORIGEN, @IDARTICULO, @CANTIDAD_TRASLADO, DBO.FNK_GETDATE(),
				@NOLOTEPEDIDO_ORIGEN, @FECHAVENCE_ORIG, @PCOSTO_ART, @IDARTICULO
			);

			-- -- 2. CONFIRMAR SALIDA -----------------------------------------------
			-- Descontar IEXI origen (igual que CONFIRMA_SALIDA en SPQ_IMOV)
			UPDATE IEXI
			SET EXISLOTE = EXISLOTE - @CANTIDAD_TRASLADO
			WHERE IDARTICULO = @IDARTICULO
			  AND IDBODEGA   = @IDBODEGA
			  AND NOLOTE     = @NOLOTE_ORIGEN;

			-- SPK_CONFIRMARSALIDAS: confirma la salida (IMOV/IMOVH ESTADO?1),
			-- auto-crea el IMOV/IMOVH de entrada con IDTIPOMOV=IDINVTRASLOTEENT (ESTADO=0),
			-- y llama a SPK_ACTUALIZA_KARDEX para la salida.
			EXEC SPK_CONFIRMARSALIDAS @IDBODEGA, @CNSMOV_SAL, @USUARIO, @COMPANIA_USU, @SEDE_USU;

			IF (SELECT ESTADO FROM IMOV WHERE CNSMOV = @CNSMOV_SAL) <> 1
				RAISERROR('La salida no pudo ser confirmada por SPK_CONFIRMARSALIDAS.', 16, 1);

			-- -- 3. LOCALIZAR EL IMOV DE ENTRADA AUTO-CREADO ----------------------
			-- SPK_CONFIRMARSALIDAS copia NODOCUMENTO de la salida ? filtro por @CNSMOV_SAL
			SELECT @CNSMOV_ENT = CNSMOV
			FROM IMOV
			WHERE NODOCUMENTO = @CNSMOV_SAL
			  AND IDTIPOMOV   = @IDINVTRASLOTEENT_V
			  AND COALESCE(ESTADO, 0) = 0;			

			IF COALESCE(@CNSMOV_ENT, '') = ''
				RAISERROR('No se gener� el movimiento de entrada autom�ticamente.', 16, 1);

			-- -- 4. CORREGIR NOLOTE EN IMOVH DE ENTRADA ---------------------------
			-- SPK_CONFIRMARSALIDAS crea el IMOVH de entrada con NOLOTE/NOLOTEPEDIDO
			-- invertidos respecto al origen. Sobrescribimos con el lote destino correcto.
			UPDATE IMOVH
			SET NOLOTE        = @NOLOTE_DESTINO,
			    NOLOTEPEDIDO  = @NOLOTEPEDIDO_DESTINO,
			    FECHAVENCE    = @FECHAVENCE_DEST
			WHERE CNSMOV = @CNSMOV_ENT;

			-- -- 5. CONFIRMAR ENTRADA ----------------------------------------------
			-- SPK_CONFIRMARENTRADAS: confirma la entrada (IMOV/IMOVH ESTADO?1),
			-- inserta/actualiza IEXI destino (EXISLOTE += CANTIDAD),
			-- recalcula costo y llama a SPK_ACTUALIZA_KARDEX para la entrada.
			EXEC SPK_CONFIRMARENTRADAS @IDBODEGA, @CNSMOV_ENT, @USUARIO, @COMPANIA_USU, @SEDE_USU, @SYS_COMPUTERNAME;

			IF (SELECT ESTADO FROM IMOV WHERE CNSMOV = @CNSMOV_ENT) <> 1
				RAISERROR('La entrada no pudo ser confirmada por SPK_CONFIRMARENTRADAS.', 16, 1);

			COMMIT TRAN

		END TRY
		BEGIN CATCH
			IF @@TRANCOUNT > 0 ROLLBACK TRAN;
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE();
		END CATCH

		IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK, @CNSMOV_SAL CNSMOV_SAL, @CNSMOV_ENT CNSMOV_ENT
		RETURN;
	END;

	/* Dashboard gerencial de consumos: entradas, salidas y gasto del periodo. */
	IF @METODO = 'DASHBOARD_CONSUMOS'
	BEGIN
		DECLARE @ARTICULOS NVARCHAR(MAX), @PAGINA INT, @TAM INT, @SOLO_FILTRO BIT
		DECLARE @INI DATETIME, @FIN DATETIME, @DIAS INT

		SELECT
			@FECHAINI = FECHAINI,
			@FECHAFIN = FECHAFIN,
			@IDBODEGA = NULLIF(LTRIM(RTRIM(IDBODEGA)), ''),
			@ARTICULOS = ARTICULOS,
			@PAGINA = PAGINA,
			@TAM = TAM,
			@SOLO_FILTRO = SOLO_FILTRO
		FROM OPENJSON(@PARAMETROS)
		WITH (
			FECHAINI VARCHAR(20) '$.FECHAINI',
			FECHAFIN VARCHAR(20) '$.FECHAFIN',
			IDBODEGA VARCHAR(20) '$.IDBODEGA',
			ARTICULOS NVARCHAR(MAX) '$.ARTICULOS' AS JSON,
			PAGINA INT '$.PAGINA',
			TAM INT '$.TAM',
			SOLO_FILTRO BIT '$.SOLO_FILTRO'
		)

		IF COALESCE(@FECHAINI, '') = '' OR COALESCE(@FECHAFIN, '') = ''
		BEGIN
			SELECT 'KO' OK
			SELECT 'Indique fecha inicial y final.' ERROR
			RETURN
		END

		/* yyyymmdd: no depende de DATEFORMAT dmy del procedimiento */
		SET @INI = CONVERT(DATETIME, REPLACE(@FECHAINI, '-', ''))
		SET @FIN = CONVERT(DATETIME, REPLACE(@FECHAFIN, '-', ''))
		IF @FIN < @INI
		BEGIN
			SELECT 'KO' OK
			SELECT 'La fecha final no puede ser anterior a la inicial.' ERROR
			RETURN
		END

		SET @PAGINA = CASE WHEN COALESCE(@PAGINA, 1) < 1 THEN 1 ELSE COALESCE(@PAGINA, 1) END
		SET @TAM = CASE WHEN COALESCE(@TAM, 12) < 1 THEN 12 ELSE COALESCE(@TAM, 12) END
		SET @DIAS = DATEDIFF(DAY, @INI, @FIN)
		IF @DIAS < 1 SET @DIAS = 1

		SELECT IDARTICULO
		INTO #FILTRO_ART
		FROM OPENJSON(COALESCE(@ARTICULOS, '[]'))
		WITH (IDARTICULO VARCHAR(20) '$')
		WHERE COALESCE(IDARTICULO, '') <> ''

		SELECT
			H.IDARTICULO,
			A.DESCRIPCION,
			CASE WHEN T.TIPO LIKE 'Credit%' THEN 1 ELSE 0 END AS ES_ENTRADA,
			ABS(COALESCE(H.CANTIDAD, 0)) AS CANT,
			ABS(COALESCE(H.CANTIDAD, 0)) * COALESCE(NULLIF(H.PCOSTO, 0), A.PCOSTO, 0) AS VALOR,
			1 + CASE
				WHEN DATEDIFF(DAY, @INI, M.FECHAMOV) >= @DIAS THEN 3
				ELSE (DATEDIFF(DAY, @INI, M.FECHAMOV) * 4) / @DIAS
			END AS FRAGMENTO
		INTO #MOV_DASH
		FROM IMOV M WITH (NOLOCK)
		INNER JOIN ITMO T WITH (NOLOCK) ON T.IDTIPOMOV = M.IDTIPOMOV
		INNER JOIN IMOVH H WITH (NOLOCK) ON H.CNSMOV = M.CNSMOV
		INNER JOIN IART A WITH (NOLOCK) ON A.IDARTICULO = H.IDARTICULO
		WHERE COALESCE(M.ESTADO, 0) = 1
		  AND M.FECHAMOV >= @INI
		  AND M.FECHAMOV < DATEADD(DAY, 1, @FIN)
		  AND (@IDBODEGA IS NULL OR M.IDBODEGA = @IDBODEGA)
		  AND (T.TIPO LIKE 'Credit%' OR T.TIPO LIKE 'Debit%')

		SELECT
			IDARTICULO,
			MAX(DESCRIPCION) AS DESCRIPCION,
			SUM(CASE WHEN ES_ENTRADA = 1 THEN CANT ELSE 0 END) AS ENTRADAS,
			SUM(CASE WHEN ES_ENTRADA = 1 THEN VALOR ELSE 0 END) AS ENTRADAS_VALOR,
			SUM(CASE WHEN ES_ENTRADA = 0 THEN CANT ELSE 0 END) AS SALIDAS,
			SUM(CASE WHEN ES_ENTRADA = 0 THEN VALOR ELSE 0 END) AS GASTO
		INTO #AGG_ALL
		FROM #MOV_DASH
		GROUP BY IDARTICULO

		SELECT *
		INTO #AGG
		FROM #AGG_ALL A
		WHERE NOT EXISTS (SELECT 1 FROM #FILTRO_ART)
		   OR EXISTS (SELECT 1 FROM #FILTRO_ART F WHERE F.IDARTICULO = A.IDARTICULO)

		SELECT TOP 5 IDARTICULO
		INTO #TOP5
		FROM #AGG
		ORDER BY GASTO DESC, DESCRIPCION

		SELECT 'OK' OK

		SELECT
			COALESCE(SUM(A.ENTRADAS), 0) AS ENTRADAS_CANT,
			COALESCE(SUM(A.ENTRADAS_VALOR), 0) AS ENTRADAS_VALOR,
			COALESCE(SUM(A.SALIDAS), 0) AS CONSUMO_CANT,
			COALESCE(SUM(A.GASTO), 0) AS CONSUMO_VALOR,
			COALESCE(SUM(A.ENTRADAS), 0) - COALESCE(SUM(A.SALIDAS), 0) AS STOCK,
			(SELECT COUNT(*) FROM #AGG) AS N_FILTRO,
			(SELECT COUNT(*) FROM #AGG_ALL) AS N_TOTAL,
			(SELECT COALESCE(SUM(GASTO), 0) FROM #AGG_ALL) AS GASTO_TOTAL
		FROM #AGG A
		INNER JOIN #TOP5 T ON T.IDARTICULO = A.IDARTICULO

		;WITH FR AS (
			SELECT 1 AS FRAGMENTO
			UNION ALL SELECT 2
			UNION ALL SELECT 3
			UNION ALL SELECT 4
		)
		SELECT
			FR.FRAGMENTO,
			CONVERT(VARCHAR(10), CAST(DATEADD(DAY, (FR.FRAGMENTO - 1) * @DIAS / 4, @INI) AS DATE), 23) AS DESDE,
			CONVERT(VARCHAR(10), CAST(DATEADD(DAY, FR.FRAGMENTO * @DIAS / 4, @INI) AS DATE), 23) AS HASTA,
			COALESCE(SUM(CASE WHEN M.ES_ENTRADA = 1 THEN M.CANT ELSE 0 END), 0) AS ENTRADAS,
			COALESCE(SUM(CASE WHEN M.ES_ENTRADA = 0 THEN M.CANT ELSE 0 END), 0) AS SALIDAS,
			COALESCE(SUM(CASE WHEN M.ES_ENTRADA = 0 THEN M.VALOR ELSE 0 END), 0) AS GASTO,
			COALESCE(SUM(CASE WHEN M.ES_ENTRADA = 1 THEN M.CANT ELSE -M.CANT END), 0) AS STOCK
		FROM FR
		LEFT JOIN #MOV_DASH M
			ON M.FRAGMENTO = FR.FRAGMENTO
		   AND M.IDARTICULO IN (SELECT IDARTICULO FROM #TOP5)
		GROUP BY FR.FRAGMENTO
		ORDER BY FR.FRAGMENTO

		;WITH RANK AS (
			SELECT
				IDARTICULO,
				DESCRIPCION,
				ENTRADAS,
				SALIDAS,
				ENTRADAS - SALIDAS AS STOCK,
				GASTO,
				ROW_NUMBER() OVER (ORDER BY GASTO DESC, DESCRIPCION) AS FILA
			FROM #AGG_ALL A
			WHERE @SOLO_FILTRO = 0
			   OR NOT EXISTS (SELECT 1 FROM #FILTRO_ART)
			   OR EXISTS (SELECT 1 FROM #FILTRO_ART F WHERE F.IDARTICULO = A.IDARTICULO)
		)
		SELECT IDARTICULO, DESCRIPCION, ENTRADAS, SALIDAS, STOCK, GASTO, FILA
		FROM RANK
		WHERE FILA > (@PAGINA - 1) * @TAM AND FILA <= @PAGINA * @TAM
		ORDER BY FILA

		SELECT COUNT(*) AS TOTAL
		FROM #AGG_ALL A
		WHERE @SOLO_FILTRO = 0
		   OR NOT EXISTS (SELECT 1 FROM #FILTRO_ART)
		   OR EXISTS (SELECT 1 FROM #FILTRO_ART F WHERE F.IDARTICULO = A.IDARTICULO)

		RETURN
	END
