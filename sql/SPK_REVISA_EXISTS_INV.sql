IF EXISTS (SELECT NAME FROM SYSOBJECTS WHERE NAME = 'SPK_REVISA_EXISTS_INV' AND TYPE = 'P')
BEGIN
   DROP PROCEDURE SPK_REVISA_EXISTS_INV
END
GO
CREATE PROCEDURE  DBO.SPK_REVISA_EXISTS_INV  
@IDARTICULO VARCHAR(20)=NULL
WITH ENCRYPTION
AS  
DECLARE @EXISTE INT
BEGIN  
   
   UPDATE IART SET EXISTOTAL=EXIS.EXISLOTE
     ,PCOSTO = CASE WHEN PCOSTO>0 THEN PCOSTO ELSE 
		(SELECT TOP 1 VLR_UNITARIO FROM FCOMD WHERE IDARTICULO = (SELECT TOP 1 HERMANO_MAYOR FROM VWK_HERMANOS_INVENTARIO WHERE IDARTICULO=IART.IDARTICULO) ORDER BY CNSFCOM DESC )
	 END
   FROM (
         SELECT IDARTICULO,SUM(EXISLOTE) EXISLOTE FROM IEXI
         WHERE COALESCE(EXISLOTE,0)>0
         AND IDARTICULO=CASE WHEN COALESCE(@IDARTICULO,'')<>'' THEN @IDARTICULO ELSE IDARTICULO END
         GROUP BY IDARTICULO
   ) EXIS INNER JOIN IART ON EXIS.IDARTICULO=IART.IDARTICULO

   UPDATE IDXB SET EXISTOTAL=EXIS.EXISLOTE,PCOSTOM=EXIS.PCOSTOM
   FROM (SELECT IDBODEGA,IDARTICULO,SUM(EXISLOTE) EXISLOTE,AVG(PCOSTO)PCOSTOM FROM IEXI
         WHERE COALESCE(EXISLOTE,0)>0
         AND IDARTICULO=CASE WHEN COALESCE(@IDARTICULO,'')<>'' THEN @IDARTICULO ELSE IDARTICULO END
         GROUP BY IDBODEGA,IDARTICULO 
         ) EXIS INNER JOIN IDXB ON EXIS.IDARTICULO=IDXB.IDARTICULO 
                                AND EXIS.IDBODEGA=IDXB.IDBODEGA

END
