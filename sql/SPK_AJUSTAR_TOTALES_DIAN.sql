CREATE OR ALTER PROCEDURE DBO.SPK_AJUSTAR_TOTALES_DIAN
    @CNSFTR VARCHAR(40)
AS
SET NOCOUNT ON;
SET DATEFORMAT dmy;

DECLARE
    @N_FACTURA VARCHAR(20),
    @COPAGOPROP BIT,
    @VR_TOTAL DECIMAL(14, 2),
    @VALORCOPAGO_ANT DECIMAL(14, 2),
    @VALORMODERADORA_ANT DECIMAL(14, 2),
    @CP_VLR_COPAGOS_ANT DECIMAL(14, 2),
    @VALORCOPAGO_NVO DECIMAL(14, 2),
    @VALORMODERADORA_NVO DECIMAL(14, 2),
    @CP_VLR_COPAGOS_NVO DECIMAL(14, 2),
    @REGISTROS_CERO INT = 0,
    @REGISTROS_RECAUDO INT = 0,
    @TOTAL_RECAUDO_APLICADO DECIMAL(14, 2) = 0,
    @RECAUDO_COPAGO_CAJA DECIMAL(14, 2) = 0,
    @RECAUDO_MODERADORA_CAJA DECIMAL(14, 2) = 0,
    @RECAUDO_TOTAL_CAJA DECIMAL(14, 2) = 0,
    @APLICADO_COPAGO_T01 DECIMAL(14, 2) = 0,
    @APLICADO_MODERADORA_T02 DECIMAL(14, 2) = 0,
    @APLICADO_HADM DECIMAL(14, 2) = 0,
    @LINEAS_OTROS_TCOPAGO INT = 0,
    @LINEAS_TCOPAGO_CORREGIDAS INT = 0;

SELECT
    @N_FACTURA = N_FACTURA,
    @COPAGOPROP = COALESCE(COPAPROPIO, 0),
    @VALORCOPAGO_ANT = COALESCE(VALORCOPAGO, 0),
    @VALORMODERADORA_ANT = COALESCE(VALORMODERADORA, 0),
    @CP_VLR_COPAGOS_ANT = COALESCE(CP_VLR_COPAGOS, 0)
FROM FTR
WHERE CNSFCT = @CNSFTR;

IF @N_FACTURA IS NULL
BEGIN
    RAISERROR(N'No se encontr la factura para CNSFTR %s.', 16, 1, @CNSFTR);
    RETURN;
END;

IF NOT EXISTS (
    SELECT 1
    FROM FTR
    WHERE CNSFCT = @CNSFTR
      AND ESTADO = 'P'
      AND COALESCE(TIPOANULACION, '') <> 'NC'
      AND COALESCE(CAPITADA, 0) = 1
)
BEGIN
    RAISERROR(N'La factura no est pendiente, es nota crdito o no es capitada.', 16, 1);
    RETURN;
END;

IF NOT EXISTS (SELECT 1 FROM FTRDC WHERE CNSFTR = @CNSFTR)
BEGIN
    RAISERROR(N'No hay prestaciones en la relacin de cpita (FTRDC).', 16, 1);
    RETURN;
END;

IF @COPAGOPROP = 1
BEGIN
    RAISERROR(N'La factura tiene copago propio activo. El valor enviado a la DIAN es el digitado por el usuario como anticipo; no se permite recalcular totales.', 16, 1);
    RETURN;
END;

/* ------------------------------------------------------------------
   Catlogo CPCJ (KCOC y equivalente):
     02   = recaudo de copagos       ? TCOPAGO 01
     02-1 = recaudo de cuota moderadora ? TCOPAGO 02
   Reglas:
   - Recibo vlido: FCJ.ESTADO = P, CERRADA = 1, clave no vaca.
   - Sin recibo ? VLR_COPAGO = 0.
   - Con recibo ? solo conceptos 02 y 02-1 (nunca el total del recibo).
   - TCOPAGO se alinea al concepto realmente recaudado cuando la clave
     tiene un nico concepto (RIPS / DIAN).
   - HADM/INV enlazan por NOADMISION; el resto por NOPRESTACION.
     Se busca en FCJ.NOADMISION o FCJ.NOPRESTACION.
IF OBJECT_ID('tempdb..#FTRDC_AJU') IS NOT NULL
    DROP TABLE #FTRDC_AJU;

IF OBJECT_ID('tempdb..#RECAUDO_CLAVE') IS NOT NULL
    DROP TABLE #RECAUDO_CLAVE;

SELECT
    IDENTITY(INT, 1, 1)                                                 AS ID,
    D.CNSFTR,
    D.N_CUOTA,
    D.PROCEDENCIA,
    D.NOADMISION,
    D.NOPRESTACION,
    D.NOITEM,
    D.TCOPAGO,
    COALESCE(D.VLR_COPAGO, 0)                                           AS VLR_COPAGO_ORIG,
    CASE
        WHEN D.PROCEDENCIA IN ('HADM', 'INV') THEN N'ADMISION'
        ELSE N'LINEA'
    END                                                                 AS NIVEL_ENLACE,
    LTRIM(RTRIM(COALESCE(
        CASE
            WHEN D.PROCEDENCIA IN ('HADM', 'INV') THEN D.NOADMISION
            ELSE D.NOPRESTACION
        END, '')))                                                      AS FCJ_CLAVE,
    CASE
        WHEN D.TCOPAGO = '01' THEN N'01'
        WHEN D.TCOPAGO = '02' THEN N'02'
        ELSE N'OTROS'
    END                                                                 AS GRUPO_TCOPAGO,
    CASE
        WHEN D.TCOPAGO = '01' THEN N'02'
        WHEN D.TCOPAGO = '02' THEN N'02-1'
        ELSE NULL
    END                                                                 AS FCJD_CONCEPTO,
    CAST(0 AS INT)                                                      AS TIENE_RECAUDO,
    CAST(0 AS DECIMAL(14, 2))                                           AS VLR_COPAGO_NVO
INTO #FTRDC_AJU
FROM FTRDC D
WHERE D.CNSFTR = @CNSFTR;

CREATE INDEX IX_FTRDC_AJU_CLAVE ON #FTRDC_AJU (FCJ_CLAVE, NIVEL_ENLACE, GRUPO_TCOPAGO);

SELECT
    D.FCJ_CLAVE,
    D.NIVEL_ENLACE,
    CASE
        WHEN COALESCE(MAX(R.RECAUDO_COPAGO), 0) + COALESCE(MAX(R.RECAUDO_MODERADORA), 0) > 0
            THEN 1
        ELSE 0
    END                                                                 AS TIENE_RECAUDO,
    COALESCE(MAX(R.RECAUDO_COPAGO), 0)                                  AS RECAUDO_COPAGO,
    COALESCE(MAX(R.RECAUDO_MODERADORA), 0)                              AS RECAUDO_MODERADORA,
    COALESCE(MAX(R.RECAUDO_COPAGO), 0) + COALESCE(MAX(R.RECAUDO_MODERADORA), 0) AS RECAUDO_TOTAL
INTO #RECAUDO_CLAVE
FROM (
    SELECT DISTINCT
        FCJ_CLAVE,
        NIVEL_ENLACE
    FROM #FTRDC_AJU
    WHERE FCJ_CLAVE <> N''
) D
OUTER APPLY (
    SELECT
        SUM(CASE WHEN FCJD.CONCEPTO = N'02'   THEN FCJD.VALORTOTAL ELSE 0 END) AS RECAUDO_COPAGO,
        SUM(CASE WHEN FCJD.CONCEPTO = N'02-1' THEN FCJD.VALORTOTAL ELSE 0 END) AS RECAUDO_MODERADORA
    FROM FCJ
    INNER JOIN FCJD
        ON FCJ.CODCAJA = FCJD.CODCAJA
       AND FCJ.CNSFACJ = FCJD.CNSFACJ
    WHERE FCJ.ESTADO = 'P'
      AND COALESCE(FCJ.CERRADA, 0) = 1
      AND (
            FCJ.NOADMISION = D.FCJ_CLAVE
         OR FCJ.NOPRESTACION = D.FCJ_CLAVE
          )
) R
GROUP BY D.FCJ_CLAVE, D.NIVEL_ENLACE;

UPDATE A
SET TIENE_RECAUDO = CASE WHEN COALESCE(C.TIENE_RECAUDO, 0) = 1 THEN 1 ELSE 0 END
FROM #FTRDC_AJU A
LEFT JOIN #RECAUDO_CLAVE C
    ON C.FCJ_CLAVE = A.FCJ_CLAVE
   AND C.NIVEL_ENLACE = A.NIVEL_ENLACE;

SELECT
    @RECAUDO_COPAGO_CAJA = SUM(RECAUDO_COPAGO),
    @RECAUDO_MODERADORA_CAJA = SUM(RECAUDO_MODERADORA),
    @RECAUDO_TOTAL_CAJA = SUM(RECAUDO_TOTAL)
FROM #RECAUDO_CLAVE
WHERE TIENE_RECAUDO = 1;

/* ------------------------------------------------------------------
   Alinear TCOPAGO al concepto recaudado (un solo concepto en la clave).
   01 = copago (02); 02 = moderadora (02-1).
UPDATE A
SET
    TCOPAGO = N'02',
    GRUPO_TCOPAGO = N'02',
    FCJD_CONCEPTO = N'02-1'
FROM #FTRDC_AJU A
INNER JOIN #RECAUDO_CLAVE C
    ON C.FCJ_CLAVE = A.FCJ_CLAVE
   AND C.NIVEL_ENLACE = A.NIVEL_ENLACE
WHERE A.TIENE_RECAUDO = 1
  AND A.GRUPO_TCOPAGO = N'01'
  AND COALESCE(C.RECAUDO_COPAGO, 0) = 0
  AND COALESCE(C.RECAUDO_MODERADORA, 0) > 0;

SET @LINEAS_TCOPAGO_CORREGIDAS = @@ROWCOUNT;

UPDATE A
SET
    TCOPAGO = N'01',
    GRUPO_TCOPAGO = N'01',
    FCJD_CONCEPTO = N'02'
FROM #FTRDC_AJU A
INNER JOIN #RECAUDO_CLAVE C
    ON C.FCJ_CLAVE = A.FCJ_CLAVE
   AND C.NIVEL_ENLACE = A.NIVEL_ENLACE
WHERE A.TIENE_RECAUDO = 1
  AND A.GRUPO_TCOPAGO = N'02'
  AND COALESCE(C.RECAUDO_COPAGO, 0) > 0
  AND COALESCE(C.RECAUDO_MODERADORA, 0) = 0;

SET @LINEAS_TCOPAGO_CORREGIDAS = @LINEAS_TCOPAGO_CORREGIDAS + @@ROWCOUNT;

/* Sin recibo confirmado o TCOPAGO distinto de 01/02 ? cero */
UPDATE #FTRDC_AJU
SET VLR_COPAGO_NVO = 0
WHERE TIENE_RECAUDO = 0
   OR GRUPO_TCOPAGO = N'OTROS';

/* TCOPAGO 01 ? recaudo copago FCJD 02 */
;WITH SUMA_T01 AS (
    SELECT
        A.FCJ_CLAVE,
        A.NIVEL_ENLACE,
        SUM(A.VLR_COPAGO_ORIG)                                          AS TOTAL_ORIG,
        COUNT(*)                                                        AS CANT_LINEAS
    FROM #FTRDC_AJU A
    WHERE A.GRUPO_TCOPAGO = N'01'
    GROUP BY A.FCJ_CLAVE, A.NIVEL_ENLACE
)
UPDATE A
SET VLR_COPAGO_NVO =
    CASE
        WHEN C.TIENE_RECAUDO = 0 OR COALESCE(C.RECAUDO_COPAGO, 0) = 0 THEN 0
        WHEN S.TOTAL_ORIG > 0
            THEN ROUND(A.VLR_COPAGO_ORIG / S.TOTAL_ORIG * C.RECAUDO_COPAGO, 2)
        WHEN S.CANT_LINEAS > 0
            THEN ROUND(C.RECAUDO_COPAGO / S.CANT_LINEAS, 2)
        ELSE 0
    END
FROM #FTRDC_AJU A
INNER JOIN #RECAUDO_CLAVE C
    ON C.FCJ_CLAVE = A.FCJ_CLAVE
   AND C.NIVEL_ENLACE = A.NIVEL_ENLACE
INNER JOIN SUMA_T01 S
    ON S.FCJ_CLAVE = A.FCJ_CLAVE
   AND S.NIVEL_ENLACE = A.NIVEL_ENLACE
WHERE A.GRUPO_TCOPAGO = N'01'
  AND A.TIENE_RECAUDO = 1;

/* TCOPAGO 02 ? recaudo moderadora FCJD 02-1 */
;WITH SUMA_T02 AS (
    SELECT
        A.FCJ_CLAVE,
        A.NIVEL_ENLACE,
        SUM(A.VLR_COPAGO_ORIG)                                          AS TOTAL_ORIG,
        COUNT(*)                                                        AS CANT_LINEAS
    FROM #FTRDC_AJU A
    WHERE A.GRUPO_TCOPAGO = N'02'
    GROUP BY A.FCJ_CLAVE, A.NIVEL_ENLACE
)
UPDATE A
SET VLR_COPAGO_NVO =
    CASE
        WHEN C.TIENE_RECAUDO = 0 OR COALESCE(C.RECAUDO_MODERADORA, 0) = 0 THEN 0
        WHEN S.TOTAL_ORIG > 0
            THEN ROUND(A.VLR_COPAGO_ORIG / S.TOTAL_ORIG * C.RECAUDO_MODERADORA, 2)
        WHEN S.CANT_LINEAS > 0
            THEN ROUND(C.RECAUDO_MODERADORA / S.CANT_LINEAS, 2)
        ELSE 0
    END
FROM #FTRDC_AJU A
INNER JOIN #RECAUDO_CLAVE C
    ON C.FCJ_CLAVE = A.FCJ_CLAVE
   AND C.NIVEL_ENLACE = A.NIVEL_ENLACE
INNER JOIN SUMA_T02 S
    ON S.FCJ_CLAVE = A.FCJ_CLAVE
   AND S.NIVEL_ENLACE = A.NIVEL_ENLACE
WHERE A.GRUPO_TCOPAGO = N'02'
  AND A.TIENE_RECAUDO = 1;

/* Ajuste de centavos por grupo TCOPAGO y clave */
;WITH DIF_T01 AS (
    SELECT
        C.RECAUDO_COPAGO - SUM(A.VLR_COPAGO_NVO)                        AS DIFERENCIA,
        MIN(A.ID)                                                       AS ID_AJUSTE
    FROM #FTRDC_AJU A
    INNER JOIN #RECAUDO_CLAVE C
        ON C.FCJ_CLAVE = A.FCJ_CLAVE
       AND C.NIVEL_ENLACE = A.NIVEL_ENLACE
    WHERE A.GRUPO_TCOPAGO = N'01'
      AND C.TIENE_RECAUDO = 1
      AND C.RECAUDO_COPAGO > 0
    GROUP BY A.FCJ_CLAVE, A.NIVEL_ENLACE, C.RECAUDO_COPAGO
    HAVING ABS(C.RECAUDO_COPAGO - SUM(A.VLR_COPAGO_NVO)) BETWEEN 0.01 AND 0.99
)
UPDATE A
SET VLR_COPAGO_NVO = A.VLR_COPAGO_NVO + D.DIFERENCIA
FROM #FTRDC_AJU A
INNER JOIN DIF_T01 D
    ON A.ID = D.ID_AJUSTE;

;WITH DIF_T02 AS (
    SELECT
        C.RECAUDO_MODERADORA - SUM(A.VLR_COPAGO_NVO)                    AS DIFERENCIA,
        MIN(A.ID)                                                       AS ID_AJUSTE
    FROM #FTRDC_AJU A
    INNER JOIN #RECAUDO_CLAVE C
        ON C.FCJ_CLAVE = A.FCJ_CLAVE
       AND C.NIVEL_ENLACE = A.NIVEL_ENLACE
    WHERE A.GRUPO_TCOPAGO = N'02'
      AND C.TIENE_RECAUDO = 1
      AND C.RECAUDO_MODERADORA > 0
    GROUP BY A.FCJ_CLAVE, A.NIVEL_ENLACE, C.RECAUDO_MODERADORA
    HAVING ABS(C.RECAUDO_MODERADORA - SUM(A.VLR_COPAGO_NVO)) BETWEEN 0.01 AND 0.99
)
UPDATE A
SET VLR_COPAGO_NVO = A.VLR_COPAGO_NVO + D.DIFERENCIA
FROM #FTRDC_AJU A
INNER JOIN DIF_T02 D
    ON A.ID = D.ID_AJUSTE;

UPDATE F
SET
    F.VLR_COPAGO = COALESCE(A.VLR_COPAGO_NVO, 0),
    F.TCOPAGO = A.TCOPAGO
FROM FTRDC F
INNER JOIN #FTRDC_AJU A
    ON F.CNSFTR = A.CNSFTR
   AND F.N_CUOTA = A.N_CUOTA
   AND F.PROCEDENCIA = A.PROCEDENCIA
   AND F.NOADMISION = A.NOADMISION
   AND F.NOPRESTACION = A.NOPRESTACION
   AND F.NOITEM = A.NOITEM
WHERE F.CNSFTR = @CNSFTR;

SELECT
    @REGISTROS_CERO = SUM(CASE WHEN COALESCE(VLR_COPAGO_NVO, 0) = 0 THEN 1 ELSE 0 END),
    @REGISTROS_RECAUDO = SUM(CASE WHEN COALESCE(VLR_COPAGO_NVO, 0) > 0 THEN 1 ELSE 0 END),
    @TOTAL_RECAUDO_APLICADO = SUM(COALESCE(VLR_COPAGO_NVO, 0)),
    @APLICADO_COPAGO_T01 = SUM(CASE WHEN GRUPO_TCOPAGO = N'01' THEN COALESCE(VLR_COPAGO_NVO, 0) ELSE 0 END),
    @APLICADO_MODERADORA_T02 = SUM(CASE WHEN GRUPO_TCOPAGO = N'02' THEN COALESCE(VLR_COPAGO_NVO, 0) ELSE 0 END),
    @APLICADO_HADM = SUM(CASE WHEN PROCEDENCIA = N'HADM' THEN COALESCE(VLR_COPAGO_NVO, 0) ELSE 0 END),
    @LINEAS_OTROS_TCOPAGO = SUM(CASE WHEN GRUPO_TCOPAGO = N'OTROS' THEN 1 ELSE 0 END)
FROM #FTRDC_AJU;

/* Totaliza servicios / FTRD. Luego se vuelven a grabar copago y moderadora
   porque SPK_TOTALFACTURFIN (CUOTMODE_ENFACTFINAN = SI) no toma el recaudo
   de caja y puede restaurar VLR_COPAGO liquidado en FTRDC. */
EXEC DBO.SPK_TOTALFACTURFIN @N_FACTURA = @N_FACTURA;

UPDATE F
SET
    F.VLR_COPAGO = COALESCE(A.VLR_COPAGO_NVO, 0),
    F.TCOPAGO = A.TCOPAGO
FROM FTRDC F
INNER JOIN #FTRDC_AJU A
    ON F.CNSFTR = A.CNSFTR
   AND F.N_CUOTA = A.N_CUOTA
   AND F.PROCEDENCIA = A.PROCEDENCIA
   AND F.NOADMISION = A.NOADMISION
   AND F.NOPRESTACION = A.NOPRESTACION
   AND F.NOITEM = A.NOITEM
WHERE F.CNSFTR = @CNSFTR;

UPDATE D
SET D.VLR_COPAGOS = X.SUMA_COPAGO
FROM FTRD D
INNER JOIN (
    SELECT
        N_CUOTA,
        SUM(COALESCE(VLR_COPAGO, 0)) AS SUMA_COPAGO
    FROM FTRDC
    WHERE CNSFTR = @CNSFTR
    GROUP BY N_CUOTA
) X
    ON X.N_CUOTA = D.N_CUOTA
WHERE D.CNSFTR = @CNSFTR;

UPDATE FTR
SET
    VALORCOPAGO = COALESCE(@APLICADO_COPAGO_T01, 0),
    VALORMODERADORA = COALESCE(@APLICADO_MODERADORA_T02, 0),
    CP_VLR_COPAGOS = COALESCE(@TOTAL_RECAUDO_APLICADO, 0),
    VR_TOTAL = COALESCE(VALORSERVICIOS, 0)
             - COALESCE(@APLICADO_COPAGO_T01, 0)
             - COALESCE(@APLICADO_MODERADORA_T02, 0)
WHERE CNSFCT = @CNSFTR;

DROP TABLE #RECAUDO_CLAVE;
DROP TABLE #FTRDC_AJU;

SELECT
    @VALORCOPAGO_NVO = COALESCE(VALORCOPAGO, 0),
    @VALORMODERADORA_NVO = COALESCE(VALORMODERADORA, 0),
    @CP_VLR_COPAGOS_NVO = COALESCE(CP_VLR_COPAGOS, 0),
    @VR_TOTAL = COALESCE(VR_TOTAL, 0)
FROM FTR
WHERE CNSFCT = @CNSFTR;

SELECT
    'OK' AS OK,
    @N_FACTURA AS N_FACTURA,
    @VALORCOPAGO_ANT AS VALORCOPAGO_ANT,
    @VALORMODERADORA_ANT AS VALORMODERADORA_ANT,
    @CP_VLR_COPAGOS_ANT AS CP_VLR_COPAGOS_ANT,
    @VALORCOPAGO_NVO AS VALORCOPAGO_NVO,
    @VALORMODERADORA_NVO AS VALORMODERADORA_NVO,
    @CP_VLR_COPAGOS_NVO AS CP_VLR_COPAGOS_NVO,
    @VR_TOTAL AS VR_TOTAL,
    F.CP_VLR_SERVICIOS,
    F.VALORSERVICIOS,
    @REGISTROS_CERO AS REGISTROS_SIN_RECAUDO,
    @REGISTROS_RECAUDO AS REGISTROS_CON_RECAUDO,
    @TOTAL_RECAUDO_APLICADO AS TOTAL_RECAUDO_APLICADO,
    @RECAUDO_COPAGO_CAJA AS RECAUDO_COPAGO_CAJA,
    @RECAUDO_MODERADORA_CAJA AS RECAUDO_MODERADORA_CAJA,
    @RECAUDO_TOTAL_CAJA AS RECAUDO_TOTAL_CAJA,
    @APLICADO_COPAGO_T01 AS APLICADO_TCOPAGO_01,
    @APLICADO_MODERADORA_T02 AS APLICADO_TCOPAGO_02,
    @APLICADO_HADM AS APLICADO_HADM,
    @LINEAS_OTROS_TCOPAGO AS LINEAS_OTROS_TCOPAGO,
    @LINEAS_TCOPAGO_CORREGIDAS AS LINEAS_TCOPAGO_CORREGIDAS
FROM FTR F
WHERE F.CNSFCT = @CNSFTR;
