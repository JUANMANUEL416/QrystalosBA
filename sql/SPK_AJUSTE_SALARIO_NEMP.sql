IF EXISTS (SELECT NAME FROM SYSOBJECTS WHERE NAME = 'SPK_AJUSTE_SALARIO_NEMP' AND TYPE = 'P')
BEGIN
   DROP PROCEDURE SPK_AJUSTE_SALARIO_NEMP
END
GO
CREATE PROCEDURE DBO.SPK_AJUSTE_SALARIO_NEMP 
@CNSAJUSTE VARCHAR(20),
@CODCARGO  VARCHAR(20),
@NIVEL     VARCHAR(10),
@GRADO     VARCHAR(10),
@BASICO    DECIMAL(14,2),
@FECHA     DATETIME,
@USUARIO   VARCHAR(20),
@SYS_COMPUTERNAME VARCHAR (255)
WITH ENCRYPTION
AS  
DECLARE @NUMDOC VARCHAR(20)
BEGIN  
	DECLARE AJUSTE_CURSOR CURSOR FOR 
   SELECT NUMDOC FROM NEMP  
   WHERE CODCARGO=@CODCARGO 
   AND NIVEL=@NIVEL 
   AND GRADO=@GRADO       
   AND ESTADO='Activo'
   AND COALESCE(FECHARETIRO,@FECHA)>=@FECHA
   AND FECHAINGRESO<=@FECHA
	OPEN AJUSTE_CURSOR    
	FETCH NEXT FROM AJUSTE_CURSOR    
	INTO @NUMDOC
	WHILE @@FETCH_STATUS = 0    
	BEGIN 
      IF NOT EXISTS(SELECT * FROM NCARNGV WHERE CODCARGO=@CODCARGO    AND NIVEL=@NIVEL    AND GRADO=@GRADO 
                     AND DBO.FNK_FECHA(FECHA)=DBO.FNK_FECHA(@FECHA))
      BEGIN
         PRINT 'INSERT EN NCARNGV'
         INSERT INTO NCARNGV(CODCARGO, NIVEL, GRADO, BASICO, HORASDELABOR, DIAS, FECHA,CNSAJUSTE) 
         SELECT TOP 1 @CODCARGO,@NIVEL,@GRADO,@BASICO,HORASDELABOR,DIAS,@FECHA,@CNSAJUSTE
         FROM NCARNGV 
         WHERE CODCARGO=@CODCARGO 
         AND NIVEL=@NIVEL 
         AND GRADO=@GRADO 
         ORDER BY FECHA DESC
      END
	   ELSE
	   BEGIN 
		   PRINT'EXISTE SOLO ACTUALIZO HORAS LABORALES'
		   UPDATE NEMP SET HORASDELABOR=(SELECT HORASDELABOR FROM NCARNGV WHERE CODCARGO=@CODCARGO AND NIVEL=@NIVEL AND GRADO=@GRADO  AND DBO.FNK_FECHA(FECHA)=DBO.FNK_FECHA(@FECHA))
		   WHERE  NUMDOC=@NUMDOC AND CODCARGO=@CODCARGO AND NIVEL=@NIVEL AND GRADO=@GRADO 
	   END
	    
      PRINT 'EMPIEZO INSERT HISTORICO'
      INSERT INTO NEMPHIS(NUMDOC, FECHAMOV, SEXO, IDAREA, CCOSTO, FECHAINGRESO, ESTADO, FECHARETIRO, CAUSARETIRO, BASICO, CODCARGO, NIVEL, GRADO, HORASDELABOR, DIASXCARGO, CODPLANTA, TIPOSALARIO, TALLA_CALZADO, 
                           TALLA_CAMISA, TALLA_PANTALON, GRUPOSANGUINEO, LIBRETAMILITAR, ESTADOCIVIL, TIPOCONTRATO, CODNOMINA, CTA_BCO, BANCO, SUCURSAL, FNACIMIENTO, FULTIMOPAGO, TIPOCESANTIAS, FLEY50, 
                           ENSINDICATO, FORMADEPAGO, FONDODEVIVIENDA, USUARIOMOD, FECHAMOD, SYS_COMPUTERNAME, OPERACION)
      SELECT NUMDOC, @FECHA, SEXO, IDAREA, CCOSTO, FECHAINGRESO, ESTADO, FECHARETIRO, CAUSARETIRO, @BASICO, CODCARGO, NIVEL, GRADO, HORASDELABOR, DIASXCARGO, CODPLANTA, TIPOSALARIO, TALLA_CALZADO, 
             TALLA_CAMISA, TALLA_PANTALON, GRUPOSANGUINEO, LIBRETAMILITAR, ESTADOCIVIL, TIPOCONTRATO, CODNOMINA, CTA_BCO, BANCO, SUCURSAL, FNACIMIENTO, FULTIMOPAGO, TIPOCESANTIAS, FLEY50, 
            ENSINDICATO, FORMADEPAGO, FONDODEVIVIENDA, @USUARIO, GETDATE(), @SYS_COMPUTERNAME, 'CAMBIA' 
      FROM NEMP WHERE NUMDOC=@NUMDOC

      UPDATE NEMP SET BASICO=@BASICO  WHERE NUMDOC=@NUMDOC AND CODCARGO=@CODCARGO AND NIVEL=@NIVEL AND GRADO=@GRADO 

	FETCH NEXT FROM AJUSTE_CURSOR    
	INTO @NUMDOC
	END
	CLOSE AJUSTE_CURSOR
	DEALLOCATE AJUSTE_CURSOR   

END
