/*
  CEM — IVA mal sentado en dos cuentas por pagar.
  Solo FCXP/FCXPD. No toca entradas, existencias ni órdenes.

  DPE12286  03CM002248
    La factura pone el 19 % en Giralmet (base 391.595, IVA 74.403).
    Si la cuenta todavía lo tiene en Mestinon (40 × 1.017 = 40.680, 183 %),
    lo pasa a Giralmet. Si ya quedó así, no la vuelve a tocar.
    El neto 32.366.081 no cambia.

  FE5176  03CM002317
    La factura trae IVA 632,32, que es el 19 % de 3.328
    (lancetas 3.200 + glucómetro 128). Las tiras van exentas.
    Hoy los 632,32 están todos en el glucómetro (base 128 = 494 %).
    Queda: lancetas IVA 608 y glucómetro IVA 24,32.
    Las dos en gravados 14200501 y cuenta de IVA 24080501.
    El neto 61.443.960,32 no cambia.

  Uso:
    1. Deje @APLICAR = 0 y ejecute. Revise el listado.
    2. Ponga @APLICAR = 1 y vuelva a ejecutar.
       Si algo no cuadra, hace ROLLBACK y no deja nada.
*/

SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @APLICAR bit = 0;

SELECT
  P.NOREFERENCIA,
  D.IDSERVICIO,
  CONVERT(decimal(18, 2), D.CANTIDAD) AS CANTIDAD,
  CONVERT(decimal(18, 2), D.CANTIDAD * D.VALOR) AS BASE,
  CONVERT(decimal(18, 2), D.VLR_IVA) AS IVA_HOY,
  CASE
    WHEN P.CNSFCXP = N'03CM002248' AND D.IDSERVICIO = N'MX1059-1' AND D.CANTIDAD = 40 THEN CONVERT(decimal(18, 2), 0)
    WHEN P.CNSFCXP = N'03CM002248' AND D.IDSERVICIO = N'MX2819-1' THEN CONVERT(decimal(18, 2), 74403.00)
    WHEN P.CNSFCXP = N'03CM002317' AND D.IDSERVICIO = N'DM148-1' THEN CONVERT(decimal(18, 2), 608.00)
    WHEN P.CNSFCXP = N'03CM002317' AND D.IDSERVICIO = N'DM149-1' THEN CONVERT(decimal(18, 2), 24.32)
  END AS IVA_OK,
  D.CUENTA_SER AS CUENTA_HOY,
  CASE
    WHEN P.CNSFCXP = N'03CM002248' AND D.IDSERVICIO = N'MX1059-1' AND D.CANTIDAD = 40 THEN N'14150502'
    WHEN P.CNSFCXP = N'03CM002248' AND D.IDSERVICIO = N'MX2819-1' THEN N'14150501'
    WHEN P.CNSFCXP = N'03CM002317' AND D.IDSERVICIO IN (N'DM148-1', N'DM149-1') THEN N'14200501'
  END AS CUENTA_OK,
  COALESCE(D.CUENTA_IVA, N'') AS IVA_CUENTA_HOY
FROM dbo.FCXP P
INNER JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
WHERE (
    P.CNSFCXP = N'03CM002248' AND (
      (D.IDSERVICIO = N'MX1059-1' AND D.CANTIDAD = 40)
      OR D.IDSERVICIO = N'MX2819-1'
    )
  )
  OR (
    P.CNSFCXP = N'03CM002317' AND D.IDSERVICIO IN (N'DM148-1', N'DM149-1')
  )
ORDER BY P.NOREFERENCIA, D.IDSERVICIO;

IF @APLICAR = 0
  RETURN;

BEGIN TRAN;

IF EXISTS (
  SELECT 1
  FROM dbo.FCXP
  WHERE CNSFCXP IN (N'03CM002248', N'03CM002317')
    AND (
      ESTADO <> N'N'
      OR COALESCE(CONTABILIZADA, 0) <> 0
      OR COALESCE(RTRIM(NROCOMPROBANTE), N'') <> N''
    )
)
BEGIN
  ROLLBACK TRAN;
  THROW 56040, 'Alguna de las dos cuentas ya no está libre.', 1;
END;

/* DPE12286: solo si el IVA sigue en Mestinon. */
IF EXISTS (
  SELECT 1 FROM dbo.FCXPD
  WHERE CNSFCXP = N'03CM002248' AND IDSERVICIO = N'MX1059-1'
    AND CANTIDAD = 40 AND ABS(VLR_IVA - 74403.00) < 0.01 AND VLR_NETO = 115083.00
)
AND EXISTS (
  SELECT 1 FROM dbo.FCXPD
  WHERE CNSFCXP = N'03CM002248' AND IDSERVICIO = N'MX2819-1'
    AND CANTIDAD = 750 AND COALESCE(VLR_IVA, 0) = 0 AND VLR_NETO = 391595.00
)
BEGIN
  UPDATE dbo.FCXPD
  SET VLR_IVA = 0,
      VLR_NETO = 40680.00,
      CUENTA_SER = N'14150502',
      CUENTA_IVA = NULL
  WHERE CNSFCXP = N'03CM002248'
    AND IDSERVICIO = N'MX1059-1'
    AND CANTIDAD = 40
    AND ABS(VLR_IVA - 74403.00) < 0.01;

  UPDATE dbo.FCXPD
  SET VALOR = 522.126667,
      VLR_IVA = 74403.00,
      VLR_NETO = 465998.00,
      CUENTA_SER = N'14150501',
      CUENTA_IVA = N'24080501'
  WHERE CNSFCXP = N'03CM002248'
    AND IDSERVICIO = N'MX2819-1'
    AND CANTIDAD = 750
    AND COALESCE(VLR_IVA, 0) = 0;
END;

IF NOT EXISTS (
  SELECT 1 FROM dbo.FCXPD
  WHERE CNSFCXP = N'03CM002248' AND IDSERVICIO = N'MX2819-1'
    AND CANTIDAD = 750 AND ABS(VLR_IVA - 74403.00) < 0.01
    AND CUENTA_IVA = N'24080501'
)
OR NOT EXISTS (
  SELECT 1 FROM dbo.FCXPD
  WHERE CNSFCXP = N'03CM002248' AND IDSERVICIO = N'MX1059-1'
    AND CANTIDAD = 40 AND COALESCE(VLR_IVA, 0) = 0
    AND CUENTA_SER = N'14150502'
)
BEGIN
  ROLLBACK TRAN;
  THROW 56041, 'DPE12286 no quedó con el IVA en Giralmet.', 1;
END;

UPDATE dbo.FCXPD
SET VLR_IVA = 608.00,
    VLR_NETO = 3808.00,
    CUENTA_SER = N'14200501',
    CUENTA_IVA = N'24080501'
WHERE CNSFCXP = N'03CM002317'
  AND IDSERVICIO = N'DM148-1'
  AND CANTIDAD = 3200
  AND COALESCE(VLR_IVA, 0) = 0
  AND VLR_NETO = 3200.00
  AND CUENTA_SER = N'14200502';

IF @@ROWCOUNT <> 1
BEGIN
  ROLLBACK TRAN;
  THROW 56042, 'No se encontró la línea de lancetas en FE5176.', 1;
END;

UPDATE dbo.FCXPD
SET VLR_IVA = 24.32,
    VLR_NETO = 152.32
WHERE CNSFCXP = N'03CM002317'
  AND IDSERVICIO = N'DM149-1'
  AND CANTIDAD = 128
  AND ABS(VLR_IVA - 632.32) < 0.01
  AND VLR_NETO = 760.32
  AND CUENTA_SER = N'14200501'
  AND CUENTA_IVA = N'24080501';

IF @@ROWCOUNT <> 1
BEGIN
  ROLLBACK TRAN;
  THROW 56043, 'No se encontró el glucómetro con el IVA completo.', 1;
END;

IF ABS((SELECT VLR_NETO FROM dbo.FCXP WHERE CNSFCXP = N'03CM002317') - 61443960.32) > 0.02
OR ABS((SELECT VLR_IVA FROM dbo.FCXP WHERE CNSFCXP = N'03CM002317') - 632.32) > 0.02
OR ABS((SELECT VLR_NETO FROM dbo.FCXP WHERE CNSFCXP = N'03CM002248') - 32366081.00) > 0.02
OR ABS((SELECT VLR_IVA FROM dbo.FCXP WHERE CNSFCXP = N'03CM002248') - 74403.00) > 0.02
OR EXISTS (
  SELECT P.CNSFCXP
  FROM dbo.FCXP P
  INNER JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
  WHERE P.CNSFCXP IN (N'03CM002317', N'03CM002248')
  GROUP BY P.CNSFCXP, P.VLR_NETO, P.VLR_IVA
  HAVING ABS(SUM(D.VLR_NETO) - P.VLR_NETO) > 0.02
      OR ABS(SUM(D.VLR_IVA) - P.VLR_IVA) > 0.02
)
OR EXISTS (
  SELECT 1 FROM dbo.FCXPD
  WHERE CNSFCXP = N'03CM002317' AND IDSERVICIO = N'DM148-1'
    AND (ABS(VLR_IVA - 608.00) > 0.01 OR CUENTA_SER <> N'14200501' OR CUENTA_IVA <> N'24080501')
)
OR EXISTS (
  SELECT 1 FROM dbo.FCXPD
  WHERE CNSFCXP = N'03CM002317' AND IDSERVICIO = N'DM149-1'
    AND ABS(VLR_IVA - 24.32) > 0.01
)
OR EXISTS (
  SELECT 1 FROM dbo.FCXPD
  WHERE CNSFCXP = N'03CM002317' AND IDSERVICIO = N'DM106-1'
    AND (COALESCE(VLR_IVA, 0) <> 0 OR VLR_NETO <> 61440000.00)
)
BEGIN
  ROLLBACK TRAN;
  THROW 56044, 'La verificación final no cuadra. No se cambió nada.', 1;
END;

COMMIT TRAN;

SELECT
  P.NOREFERENCIA,
  D.IDSERVICIO,
  CONVERT(decimal(18, 2), D.CANTIDAD) AS CANTIDAD,
  CONVERT(decimal(18, 2), D.VLR_IVA) AS IVA,
  CONVERT(decimal(18, 2), D.VLR_NETO) AS NETO,
  D.CUENTA_SER,
  COALESCE(D.CUENTA_IVA, N'') AS CUENTA_IVA
FROM dbo.FCXP P
INNER JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
WHERE P.CNSFCXP IN (N'03CM002248', N'03CM002317')
  AND D.IDSERVICIO IN (N'MX1059-1', N'MX2819-1', N'DM148-1', N'DM149-1')
  AND NOT (D.IDSERVICIO = N'MX1059-1' AND D.CANTIDAD <> 40)
ORDER BY P.NOREFERENCIA, D.IDSERVICIO;
