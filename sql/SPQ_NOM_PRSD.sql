CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_PRSD @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20), @PROCESO VARCHAR(20)
DECLARE @NUMDOCUMENTO VARCHAR(20), @VLRINTERESES DECIMAL(14, 2), @SALDOACT DECIMAL(14, 2)
DECLARE @IDTRANSACCION VARCHAR(6), @NUMCUOTA SMALLINT, @SALDOANT DECIMAL(14, 2), @VLRCUOTA DECIMAL(14, 2)
DECLARE @FECHAPAGO DATETIME, @ESTADO VARCHAR(20), @CNSPAGO VARCHAR(20), @ITEM_NIEPED DECIMAL(14, 0), @OBSERVACION VARCHAR(512)
DECLARE @FECHAPAGO_TXT VARCHAR(40), @OBSERVACIONES VARCHAR(512)
DECLARE @SYS_COMPUTERNAME VARCHAR(200)
DECLARE @COMPANIA VARCHAR(2), @IDAREA VARCHAR(20)
DECLARE @IDSEDE VARCHAR(5)
DECLARE @ESTADOACTUAL VARCHAR(20), @CNSPAGO_ACT VARCHAR(20)

BEGIN
	SET LANGUAGE Spanish;
	-- El front envia FECHAPAGO en ISO (yyyy-mm-dd). DATEFORMAT dmy interpreta 2026-09-21 como mes 21
	-- y dispara "conversion nvarchar a datetime fuera de intervalo".
	SET DATEFORMAT ymd;

	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
	FROM USUSU
	WHERE USUARIO = @USUARIO

	SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
	FROM UBEQ
	WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @NUMDOCUMENTO = NUMDOCUMENTO, @IDTRANSACCION = IDTRANSACCION, @NUMCUOTA = NUMCUOTA, @SALDOANT = SALDOANT, @VLRCUOTA = VLRCUOTA, @VLRINTERESES = 
				VLRINTERESES, @SALDOACT = SALDOACT, @ESTADO = ESTADO, @FECHAPAGO_TXT = FECHAPAGO, @OBSERVACION = OBSERVACION, @OBSERVACIONES = OBSERVACIONES, @PROCESO 
				= PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					NUMDOCUMENTO VARCHAR(20) '$.NUMDOCUMENTO', IDTRANSACCION VARCHAR(6) '$.IDTRANSACCION', NUMCUOTA SMALLINT '$.NUMCUOTA', SALDOANT DECIMAL(14, 2
					) '$.SALDOANT', VLRCUOTA DECIMAL(14, 2) '$.VLRCUOTA', VLRINTERESES DECIMAL(14, 2) '$.VLRINTERESES', SALDOACT DECIMAL(14, 2) '$.SALDOACT', ESTADO 
					VARCHAR(20) '$.ESTADO', FECHAPAGO VARCHAR(40) '$.FECHAPAGO', OBSERVACION VARCHAR(512) '$.OBSERVACION', OBSERVACIONES VARCHAR(512) 
					'$.OBSERVACIONES', PROCESO VARCHAR(20) '$.PROCESO'
					)

			SET @IDTRANSACCION = COALESCE(@IDTRANSACCION, 'PRS')
			SET @OBSERVACION = COALESCE(@OBSERVACION, @OBSERVACIONES)

			IF @FECHAPAGO_TXT IS NOT NULL AND LTRIM(RTRIM(@FECHAPAGO_TXT)) <> ''
			BEGIN
				SET @FECHAPAGO = COALESCE(TRY_CONVERT(DATETIME, LEFT(@FECHAPAGO_TXT, 10), 23), TRY_CONVERT(DATETIME, @FECHAPAGO_TXT, 126), TRY_CONVERT(DATETIME, 
							@FECHAPAGO_TXT, 120), TRY_CONVERT(DATETIME, @FECHAPAGO_TXT, 103))

				IF @FECHAPAGO IS NULL
				BEGIN
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('La fecha de pago no es valida: ', @FECHAPAGO_TXT)
				END
			END

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					IF EXISTS (
							SELECT 1
							FROM PRSD
							WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND NUMCUOTA = @NUMCUOTA
							)
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('Ya existe la cuota ', @NUMCUOTA, ' en la libranza ', @NUMDOCUMENTO)
					END

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO [PRSD] (
							[NUMDOCUMENTO], [IDTRANSACCION], [NUMCUOTA], [SALDOANT], [VLRCUOTA], [VLRINTERESES], [SALDOACT], [ESTADO], [FECHAPAGO], [CNSPAGO], 
							[ITEM_NIEPED], [OBSERVACION]
							)
						SELECT @NUMDOCUMENTO, @IDTRANSACCION, @NUMCUOTA, @SALDOANT, @VLRCUOTA, @VLRINTERESES, @SALDOACT, COALESCE(@ESTADO, 'PorPagar'), 
							@FECHAPAGO, NULL, NULL, @OBSERVACION
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @ESTADOACTUAL = ESTADO, @CNSPAGO_ACT = CNSPAGO
					FROM PRSD
					WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND NUMCUOTA = @NUMCUOTA

					IF @ESTADOACTUAL IS NULL
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('No existe la cuota ', @NUMCUOTA, ' de la libranza ', @NUMDOCUMENTO)
					END

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0 AND @ESTADOACTUAL IN ('Pagada', 'Anulada')
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('La cuota ', @NUMCUOTA, ' esta ', @ESTADOACTUAL, ' y no permite modificar valores')
					END

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0 AND @CNSPAGO_ACT IS NOT NULL AND LTRIM(RTRIM(@CNSPAGO_ACT)) <> ''
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('La cuota ', @NUMCUOTA, ' ya fue aplicada en el periodo ', @CNSPAGO_ACT, ' y no se puede modificar'
								)
					END

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0 AND @ESTADO IN ('Pagada', 'Anulada') AND @ESTADO <> @ESTADOACTUAL
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT 'No se puede marcar una cuota como Pagada o Anulada desde este formulario. Utilice el rec�lculo o el cierre de nomina'
					END

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						UPDATE PRSD
						SET SALDOANT = @SALDOANT, VLRCUOTA = @VLRCUOTA, VLRINTERESES = @VLRINTERESES, SALDOACT = @SALDOACT, ESTADO = @ESTADO, FECHAPAGO = @FECHAPAGO, 
							OBSERVACION = @OBSERVACION
						WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND NUMCUOTA = @NUMCUOTA AND ESTADO NOT IN ('Pagada', 'Anulada'
								) AND (CNSPAGO IS NULL OR LTRIM(RTRIM(CNSPAGO)) = '')
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @NUMDOCUMENTO = NUMDOCUMENTO, @NUMCUOTA = NUMCUOTA, @IDTRANSACCION = IDTRANSACCION
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOCUMENTO VARCHAR(20) '$.NUMDOCUMENTO', NUMCUOTA SMALLINT '$.NUMCUOTA', IDTRANSACCION VARCHAR(6) '$.IDTRANSACCION'
				)

		SET @IDTRANSACCION = COALESCE(@IDTRANSACCION, 'PRS')

		BEGIN TRY
			SELECT @ESTADOACTUAL = ESTADO, @CNSPAGO_ACT = CNSPAGO
			FROM PRSD
			WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND NUMCUOTA = @NUMCUOTA

			IF @ESTADOACTUAL IS NULL
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT CONCAT ('No existe la cuota ', @NUMCUOTA, ' de la libranza ', @NUMDOCUMENTO)
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0 AND @ESTADOACTUAL IN ('Pagada', 'Anulada')
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT CONCAT ('No es posible eliminar una cuota ', @ESTADOACTUAL)
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0 AND @CNSPAGO_ACT IS NOT NULL AND LTRIM(RTRIM(@CNSPAGO_ACT)) <> ''
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT CONCAT ('La cuota ', @NUMCUOTA, ' ya fue aplicada en el periodo ', @CNSPAGO_ACT, ' y no se puede eliminar')
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				DELETE
				FROM PRSD
				WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND NUMCUOTA = @NUMCUOTA AND ESTADO NOT IN ('Pagada', 'Anulada'
						) AND (CNSPAGO IS NULL OR LTRIM(RTRIM(CNSPAGO)) = '')
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'OBTENER_VLRCUOTA'
	BEGIN
		BEGIN TRY
			SELECT @NUMDOCUMENTO = NUMDOCUMENTO, @IDTRANSACCION = IDTRANSACCION
			FROM OPENJSON(@PARAMETROS) WITH (NUMDOCUMENTO VARCHAR(20) '$.NUMDOCUMENTO', IDTRANSACCION VARCHAR(6) '$.IDTRANSACCION')

			SET @IDTRANSACCION = COALESCE(@IDTRANSACCION, 'PRS')

			SELECT @VLRCUOTA = SUM(VLRCUOTA)
			FROM PRSD
			WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO AND ESTADO <> 'Anulada'

			SELECT 'OK' OK

			SELECT COALESCE(@VLRCUOTA, 0) AS VLRCUOTA

			RETURN
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
