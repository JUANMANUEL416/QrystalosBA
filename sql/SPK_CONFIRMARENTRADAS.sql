CREATE OR ALTER PROCEDURE DBO.SPK_CONFIRMARENTRADAS
	@IDBODEGA         VARCHAR(20),
	@CNSMOV           VARCHAR(20),
	@USUARIO          VARCHAR(12),
	@COMPANIA         VARCHAR(2),
	@SEDE             VARCHAR(5),
	@SYS_COMPUTERNAME VARCHAR(255)
WITH ENCRYPTION
AS
DECLARE @ENCONTRADO    DECIMAL(9,2)
DECLARE @AFECTACOSTO   SMALLINT
DECLARE @CNSITRA       VARCHAR(20)
DECLARE @S             VARCHAR(1)
DECLARE @CNS           VARCHAR(20)
DECLARE @LONG          SMALLINT
DECLARE @P             SMALLINT
DECLARE @CONTADOR      SMALLINT  
DECLARE @CNSFCOM       VARCHAR(20)
DECLARE @CNSCTZ        VARCHAR(20)
DECLARE @IDTERCERO     VARCHAR(20)
DECLARE @IDITAR        VARCHAR(2)
DECLARE @IDTIPOMOV     VARCHAR(2)
DECLARE @SECONTABILIZA SMALLINT
DECLARE @CNSFCXP       VARCHAR(20)
DECLARE @CNSFNOT       VARCHAR(20)
DECLARE @IDCATEGORIA   VARCHAR(10) 
DECLARE @NOLOTE_CUR_DETALLE       VARCHAR(20)
DECLARE @IDARTICULO_CUR_DETALLE   VARCHAR(20)
DECLARE @CANTIDAD_CUR_DETALLE     DECIMAL(14,2)
DECLARE @PCOSTO_CUR_DETALLE       DECIMAL(14,2)
DECLARE @FECHAVENCE_CUR_DETALLE   DATETIME
DECLARE @NOLOTEPEDIDO_CUR_DETALLE VARCHAR(20)
DECLARE @DETALLE_CUR_DETALLE      VARCHAR(254)    
DECLARE @CNSFCOM_CUR_DETALLE      VARCHAR(20)  
DECLARE @TIPOACTIVO        VARCHAR(80)    
DECLARE @IDACTIVO          VARCHAR(20)    
DECLARE @VECES             DECIMAL(14,2)    
DECLARE @CANTIDAD          DECIMAL(14,2)    
DECLARE @IDARTICULO        VARCHAR(20)    
DECLARE @DESCRIPCION       VARCHAR(512)    
DECLARE @PCOSTO            DECIMAL(14,2)    
DECLARE @IDEVENTO          VARCHAR(10)    
DECLARE @CNSIACTH          VARCHAR(20)    
DECLARE @IDESTADOPENDIENTE VARCHAR(20)
DECLARE @NOLOTE            VARCHAR(20)
DECLARE @CCOSTO            VARCHAR(20) 
DECLARE @IDAREA            VARCHAR(20)
DECLARE @VIDAUTIL          INT
DECLARE @NODOCUMENTO       VARCHAR(20)
DECLARE @CUENTA            VARCHAR(16)
DECLARE @ESTADO            INT
DECLARE @NROCOMPROBANTE    VARCHAR(20)
DECLARE @FECHAMOV          DATETIME
DECLARE @TIPOBODEGA        VARCHAR(20)
DECLARE @ANO               VARCHAR(10) 
DECLARE @MES               VARCHAR(10) 
DECLARE @CERRADO           VARCHAR(10)       
DECLARE @EXCEPCION_CONT    INT
DECLARE @T_ANTICIPOS       DECIMAL(14,2)
DECLARE @CNSANT            VARCHAR(20)
DECLARE @ESTADO_ANT        VARCHAR(1)
DECLARE @RINVIMA           VARCHAR(20)
DECLARE @SELLOCALIDAD      VARCHAR(20)
DECLARE @CAPACIDAD         DECIMAL(14,2)
DECLARE @VLR_ANT_LEGAL	   DECIMAL(14,2)
DECLARE @VL_SALDO		   DECIMAL(14,2)
DECLARE @CNSIHIS        VARCHAR     (20)
DECLARE @DIA            VARCHAR    (2)
DECLARE @LOCAL_TRAN     BIT = 0
DECLARE @NOPRESTACION   VARCHAR(20)
DECLARE @NOADMISION     VARCHAR(20)
DECLARE @SQL            VARCHAR(MAX)
DECLARE @CNSIDEV        VARCHAR(20)
DECLARE @HPRE_DEV TABLE (NOPRESTACION VARCHAR(20))
BEGIN
    IF (SELECT ESTADO FROM IMOV WHERE CNSMOV=@CNSMOV)<>0
	BEGIN
		RETURN
	END

	-- Bodega efectiva = la del movimiento. El par�metro puede venir del filtro UI y no coincidir.
	SELECT @IDBODEGA = IDBODEGA
	FROM IMOV
	WHERE CNSMOV = @CNSMOV

	DECLARE @CNSITRA_MOV VARCHAR(20)

	--VALIDAR CENTROS DE COSTO Y AREA FUNCIONAL
	SELECT @CCOSTO = CCOSTO, @IDAREA = IDAREA
	FROM   IMOV 
	WHERE  CNSMOV = @CNSMOV
   IF (COALESCE(@CCOSTO,'')='' OR NOT EXISTS(SELECT * FROM CEN WHERE CCOSTO=@CCOSTO AND ESTADO='Activo'))
   BEGIN
      RAISERROR('Inconsistencia, no se encontro centro de costo asociado al Movimiento',16,1)
      RETURN
   END

	DECLARE @IDBOD_HEMODERIVADOS VARCHAR(20) 
	DECLARE @IDITARHEMODERIVADOS VARCHAR(20)
	DECLARE @IDINVMOV_MOVANUSAL	 VARCHAR(20)
   DECLARE @IDINVMOVPREDEV VARCHAR(20)
   DECLARE @IDCINVMOVPREDEV VARCHAR(20)
   DECLARE @ITARMOV TABLE(IDITAR VARCHAR(2)) 

	DECLARE @IDINVMOV_COMPRAS VARCHAR(20) 
	DECLARE @IDINVMOV_REMISION_EN VARCHAR(20) 
	DECLARE @IDINVMOV_SI VARCHAR(20) 
	DECLARE @CODBARRAS_AUT_ENT VARCHAR(20)
	DECLARE @LINEAS_PENDIENTES_OC INT
	DECLARE @ITRA_ABIERTOS_OC INT

	SELECT @IDINVMOV_COMPRAS = DATO FROM USVGS WHERE IDVARIABLE = 'IDINVMOV_COMPRAS'
	SELECT @IDINVMOV_REMISION_EN = DATO FROM USVGS WHERE IDVARIABLE = 'IDINVMOV_REMISION_EN'
	SELECT @IDINVMOV_SI = DATO FROM USVGS WHERE IDVARIABLE = 'IDINVMOV_SI'
	SELECT @CODBARRAS_AUT_ENT = DATO FROM USVGS WHERE IDVARIABLE = 'CODBARRAS_AUT_ENT'
	DECLARE @IDINVTPROPIA VARCHAR(20)
	SELECT @IDINVTPROPIA = DBO.FNK_VALORVARIABLE('IDINVTPROPIA')
	DECLARE @ES_RECEPCION_MASIVA BIT = 0

	SELECT @IDINVMOV_MOVANUSAL = DBO.FNK_VALORVARIABLE('FAR_MOVANULASALIDA')
	SELECT @IDINVMOVPREDEV = DBO.FNK_VALORVARIABLE('IDINVMOVPREDEV')
	SELECT @IDCINVMOVPREDEV = DBO.FNK_VALORVARIABLE('IDCINVMOVPREDEV')

	-- EZERPA 02/12/2020 Consultar la bodega de unidad transfusional desde la sede
	SELECT @IDBOD_HEMODERIVADOS=IDBODHEMO FROM SED WHERE IDSEDE=@SEDE
	IF COALESCE(@IDBOD_HEMODERIVADOS,'')='' SELECT @IDBOD_HEMODERIVADOS = SED.IDBODHEMO FROM UBEQ INNER JOIN SED ON SED.IDSEDE=UBEQ.IDSEDE WHERE SYS_COMPUTERNAME=@SYS_COMPUTERNAME
	IF COALESCE(@IDBOD_HEMODERIVADOS,'')='' SELECT TOP 1 @IDBOD_HEMODERIVADOS = SED.IDBODHEMO FROM SED WHERE COALESCE(SED.IDBODHEMO,'')<>''
	IF COALESCE(@IDBOD_HEMODERIVADOS,'')='' SELECT @IDBOD_HEMODERIVADOS = DATO FROM USVGS WHERE IDVARIABLE='IDBOD_HEMODERIVADOS'
	-- EZERPA 02/12/2020 END


	SELECT @IDITARHEMODERIVADOS = DATO FROM USVGS WHERE IDVARIABLE='IDITARHEMODERIVADOS'
	DECLARE @FECHACONF DATETIME = DBO.FNK_FECHA_SIN_MLS(GETDATE())
	--SELECT @SECONTABILIZA = ITMO.SECONTABILIZA FROM ITMO INNER JOIN IMOV ON IMOV.IDTIPOMOV=ITMO.IDTIPOMOV WHERE IMOV.CNSMOV=@CNSMOV

	SELECT @AFECTACOSTO = ITMO.AFECTACOSTO, @IDTIPOMOV=IMOV.IDTIPOMOV, @SECONTABILIZA=IIF(ISNULL(IBOD.NOCONTABILIZA,0)=1,0,ITMO.SECONTABILIZA),
			@NROCOMPROBANTE = IMOV.NROCOMPROBANTE,  @TIPOBODEGA = IBOD.TIPOBODEGA
			,@IDTERCERO=IMOV.IDTERCERO,@FECHAMOV = FECHAMOV, @ESTADO=IMOV.ESTADO, @IDTIPOMOV=IMOV.IDTIPOMOV 
         ,@ANO=YEAR(@FECHACONF), @MES=MONTH(@FECHACONF), @DIA=DAY(@FECHACONF),
         @SECONTABILIZA=IIF(COALESCE(IBOD.NOCONTABILIZA,0)=1,0,ITMO.SECONTABILIZA)
	FROM IMOV 
	INNER JOIN IBOD ON IBOD.IDBODEGA  = IMOV.IDBODEGA 
	INNER JOIN ITMO ON ITMO.IDTIPOMOV = IMOV.IDTIPOMOV
	WHERE  IMOV.CNSMOV=@CNSMOV

	-- Solo recepci�n masiva de OC usa PCOSTO = base DIAN y CXP desde FCOM.
	-- Confirmaci�n manual conserva el c�lculo hist�rico (no extraer/pisar IVA).
	IF EXISTS (
			SELECT 1
			FROM IMOV M
			INNER JOIN FCOM F ON F.CNSFCOM = M.CNSFCOM
			WHERE M.CNSMOV = @CNSMOV
			  AND (
					CHARINDEX('Recepci�n masiva', COALESCE(F.OBSERVACION, '')) > 0
					OR CHARINDEX('Recepcion masiva', COALESCE(F.OBSERVACION, '')) > 0
					OR EXISTS (
						SELECT 1 FROM FCOMD D
						WHERE D.CNSFCOM = F.CNSFCOM
						  AND D.DETALLE = 'Recepcion masiva'
					)
			  )
		)
		OR EXISTS (
			SELECT 1
			FROM IMOV M
			INNER JOIN ITRAH H ON H.CNSITRA = M.CNSITRA
			WHERE M.CNSMOV = @CNSMOV
			  AND H.DETALLE = 'Recepcion masiva'
		)
		SET @ES_RECEPCION_MASIVA = 1

   --Validaciones Contables
	IF @IDTIPOMOV = @IDINVMOV_COMPRAS
   BEGIN
      INSERT INTO @ITARMOV
      SELECT DISTINCT IART.IDITAR
      FROM IMOVH INNER JOIN IART ON IMOVH.IDARTICULO=IART.IDARTICULO
      WHERE IMOVH.CNSMOV=@CNSMOV

      IF NOT EXISTS(SELECT 1 FROM KMCOM WHERE IDTIPOCONT='CXP_COMPRAS' AND IDMODELOCONT='01' AND TIPO='CR' 
                     AND PREFIJO IN(SELECT IDITAR FROM @ITARMOV) AND CCOSTO=@CCOSTO)
      BEGIN
         RAISERROR('Inconsistencia. No existe configuraci�n contable  para confirmar el movimiento: CXP_COMPRAS  Cuenta Proveedor.',16,1)
         RETURN
      END
      IF NOT EXISTS(SELECT 1 FROM KMCOM WHERE IDTIPOCONT='CXP_COMPRAS' AND IDMODELOCONT='01' AND TIPO='DB' 
                     AND PREFIJO IN(SELECT IDITAR FROM @ITARMOV) AND CCOSTO=@CCOSTO)
      BEGIN
         RAISERROR('Inconsistencia. No existe configuraci�n contable  para confirmar el movimiento: CXP_COMPRAS  Cuenta DB inventario.',16,1)
         RETURN
      END
   END
   ELSE
   BEGIN
      IF COALESCE(@SECONTABILIZA,0)=1
   BEGIN
      IF NOT EXISTS(SELECT 1 FROM KMCOM WHERE IDTIPOCONT='MOV_INVENTARIO' AND IDMODELOCONT='01' AND TIPO='CR' 
                     AND PREFIJO=@IDTIPOMOV AND CCOSTO=@CCOSTO)
      BEGIN
         RAISERROR('Inconsistencia. No existe configuraci�n contable  para confirmar el movimiento: MOV_INVENTARIO.  Cuenta cr�dito.',16,1)
         RETURN
      END
      IF NOT EXISTS(SELECT 1 FROM KMCOM WHERE IDTIPOCONT='MOV_INVENTARIO' AND IDMODELOCONT='01' AND TIPO='DB' 
                     AND PREFIJO=@IDTIPOMOV AND CCOSTO=@CCOSTO)
      BEGIN
         RAISERROR('Inconsistencia. No existe configuraci�n contable  para confirmar el movimiento: MOV_INVENTARIO.  Cuenta D�bito.',16,1)
         RETURN
         END 
      END   
   END

	BEGIN TRY
		IF @@TRANCOUNT = 0
		BEGIN
			BEGIN TRAN
			SET @LOCAL_TRAN = 1
		END

	-- Completar/validar proveedor ANTES de afectar inventario o generar CxP.
	-- Evita confirmar IMOV.ESTADO=1 y quedar sin FCXP cuando IDTERCERO viene vac�o.
	SELECT @CNSFCOM = CNSFCOM, @IDTERCERO = IDTERCERO, @NODOCUMENTO = NODOCUMENTO
	FROM IMOV
	WHERE CNSMOV = @CNSMOV

	IF @IDTIPOMOV = @IDINVMOV_COMPRAS
	BEGIN
		IF COALESCE(@IDTERCERO, '') = '' AND COALESCE(@CNSFCOM, '') <> ''
		BEGIN
			UPDATE M
			SET M.IDTERCERO = F.IDTERCERO
			FROM IMOV M
			INNER JOIN FCOM F ON F.CNSFCOM = M.CNSFCOM
			WHERE M.CNSMOV = @CNSMOV
			  AND COALESCE(M.IDTERCERO, '') = ''
			  AND COALESCE(F.IDTERCERO, '') <> ''

			SELECT @IDTERCERO = IDTERCERO
			FROM IMOV
			WHERE CNSMOV = @CNSMOV
		END

		IF COALESCE(@IDTERCERO, '') = ''
			THROW 50020, 'Proveedor (IDTERCERO) es obligatorio para confirmar compras.', 1;

		IF COALESCE(@NODOCUMENTO, '') = ''
			THROW 50021, 'N�mero de factura (NODOCUMENTO) es obligatorio para confirmar compras.', 1;
	END
	
	-- IART puede existir solo para el art�culo "base" (p.ej. GM0004) aunque IMOVH traiga presentaci�n (GM0004-1).
	UPDATE IMOVH
	SET ESTADO = 9
	WHERE IMOVH.CNSMOV = @CNSMOV
	  AND COALESCE(IMOVH.ESTADO, 0) = 0 -- 20250703 -- STORRES -- SE AGREGA COALESCE PARA QUE NO DEJE POR FUERA LOS NULL
	  AND EXISTS (
			SELECT 1
			FROM IART IA
			WHERE IA.IDARTICULO = IMOVH.IDARTICULO
			   OR IA.IDARTICULO = CASE
					WHEN CHARINDEX('-', IMOVH.IDARTICULO) > 0
						THEN LEFT(IMOVH.IDARTICULO, CHARINDEX('-', IMOVH.IDARTICULO) - 1)
					ELSE IMOVH.IDARTICULO
				END
		)

	-- Fallback IMOVH->9: solo filas que siguen en ESTADO=0; no toca las ya en 9 (sin doble marcado).
	-- Mismo criterio de tr�nsito que GENERA_LOTES: CNSITRA, si vac�o CNSTRAN, si vac�o ITRA abierto por CNSMOVDES.
	SELECT @CNSITRA_MOV = COALESCE(
			NULLIF(LTRIM(RTRIM(CNSITRA)), ''),
			NULLIF(LTRIM(RTRIM(CNSTRAN)), '')
		)
	FROM IMOV
	WHERE CNSMOV = @CNSMOV

	IF COALESCE(@CNSITRA_MOV, '') = ''
	BEGIN
		SELECT TOP 1 @CNSITRA_MOV = I.CNSITRA
		FROM ITRA I
		WHERE I.CNSMOVDES = @CNSMOV
		ORDER BY I.FECHAING DESC
	END

	IF COALESCE(@CNSITRA_MOV, '') <> ''
	BEGIN
		UPDATE MH
		SET ESTADO = 9
		FROM IMOVH MH
		WHERE MH.CNSMOV = @CNSMOV
		  AND COALESCE(MH.ESTADO, 0) = 0
		  AND EXISTS (
				SELECT 1
				FROM ITRAH TH
				WHERE TH.CNSITRA = @CNSITRA_MOV
				  AND TH.NOLOTE = MH.NOLOTE
				  AND (
						TH.IDARTICULO = MH.IDARTICULO
						OR (COALESCE(TH.IDARTICULOORI, '') <> '' AND TH.IDARTICULOORI = MH.IDARTICULO)
						OR (
							CASE
								WHEN CHARINDEX('-', COALESCE(TH.IDARTICULOORI, TH.IDARTICULO)) > 0
									THEN LEFT(COALESCE(TH.IDARTICULOORI, TH.IDARTICULO), CHARINDEX('-', COALESCE(TH.IDARTICULOORI, TH.IDARTICULO)) - 1)
								ELSE COALESCE(TH.IDARTICULOORI, TH.IDARTICULO)
							END
							=
							CASE
								WHEN CHARINDEX('-', MH.IDARTICULO) > 0
									THEN LEFT(MH.IDARTICULO, CHARINDEX('-', MH.IDARTICULO) - 1)
								ELSE MH.IDARTICULO
							END
						)
					)
			)
	END

	INSERT INTO IDXB (IDBODEGA,IDARTICULO,STOCKMINIMO,STOCKMAXIMO,PUNTOREORDEN,EXISTOTAL)
	SELECT DISTINCT @IDBODEGA, UPPER(IDARTICULO),    0,   0,   0,   0
	FROM   IMOVH
	WHERE  CNSMOV=@CNSMOV AND IDARTICULO NOT IN (SELECT DISTINCT IDARTICULO FROM IDXB WHERE IDBODEGA = @IDBODEGA) 
	AND    ESTADO=9
   
	/*JEDM_2011_AGO_04: BUSCAR POSIBLE EXCEPCION CONTABLE*/
	SELECT @EXCEPCION_CONT = COALESCE(COUNT(*),0) 
	FROM   IEXCEP    
	WHERE  CLASE     = 'Contabilizacion' 
	AND    IDBODEGA  = @IDBODEGA 
	AND    IDTIPOMOV = @IDTIPOMOV

	--SELECT * INTO #IMOVH_AGRUPADO FROM VWK_IMOVH_AGRUPADO WHERE CNSMOV=@CNSMOV
	SELECT * INTO #IMOVH_AGRUPADO FROM DBO.FNK_IMOVH_AGRUPADO(@CNSMOV)
	/* EZERPA 22/12/2018 */
	DECLARE _CURSOR CURSOR FOR   
		SELECT IDARTICULO,COSTO,CANTIDAD FROM #IMOVH_AGRUPADO
	OPEN _CURSOR  
	FETCH NEXT FROM _CURSOR INTO @IDARTICULO, @PCOSTO_CUR_DETALLE, @CANTIDAD_CUR_DETALLE
	WHILE @@FETCH_STATUS = 0  
	BEGIN  
		/*EZERPA 13.12.2018 => Actualizar IDXB e IART*/
		EXEC DBO.SPK_REVISA_EXISTS_INV @IDARTICULO
		/*EZERPA END*/

		IF @AFECTACOSTO=1 AND @TIPOBODEGA='Propia'
		BEGIN      
         /* Se separa la actuaizacion de PCOSTO por Peru */
         IF DBO.FNK_VALORVARIABLE('IXCOUNTRY')='PERU' 
         BEGIN
            UPDATE IART SET         
            PCOSTO = CAST(COALESCE(@PCOSTO_CUR_DETALLE, 0) AS DECIMAL(14,2))
			   FROM IART INNER JOIN  (SELECT IDXB.IDARTICULO, ISNULL(SUM(ISNULL(EXISTOTAL,0)),0) EXISTOTAL
								   FROM   IDXB INNER JOIN IBOD ON IDXB.IDBODEGA = IBOD.IDBODEGA
								   WHERE  IBOD.TIPOBODEGA='Propia'
								   AND		IDXB.IDARTICULO IN (SELECT IDARTICULO FROM #IMOVH_AGRUPADO)
								   GROUP BY IDXB.IDARTICULO) X ON IART.IDARTICULO = X.IDARTICULO
			   WHERE @IDARTICULO = IART.IDARTICULO  
         END
         IF DBO.FNK_VALORVARIABLE('IXCOUNTRY') <> 'PERU' 
         BEGIN
            UPDATE IART SET         
               PCOSTO = CAST(
				   (
					   (CAST(ISNULL(IART.PCOSTO, 0) AS DECIMAL(14,2)) * CAST(IIF(COALESCE(X.EXISTOTAL, 0) < 0, 0, COALESCE(X.EXISTOTAL, 0)) AS DECIMAL(14,2)))
					   + (CAST(COALESCE(@PCOSTO_CUR_DETALLE, 0) AS DECIMAL(14,2)) * CAST(COALESCE(@CANTIDAD_CUR_DETALLE, 0) AS DECIMAL(14,2)))
				   ) / NULLIF(
					   CAST(IIF(COALESCE(X.EXISTOTAL, 0) <= 0, 0, X.EXISTOTAL) AS DECIMAL(14,2)) + CAST(COALESCE(@CANTIDAD_CUR_DETALLE, 0) AS DECIMAL(14,2)),
					   0
				   )
			   AS DECIMAL(14,2))
			   FROM IART INNER JOIN  (SELECT IDXB.IDARTICULO, ISNULL(SUM(ISNULL(EXISTOTAL,0)),0) EXISTOTAL
								   FROM   IDXB INNER JOIN IBOD ON IDXB.IDBODEGA = IBOD.IDBODEGA
								   WHERE  IBOD.TIPOBODEGA='Propia'
								   AND		IDXB.IDARTICULO IN (SELECT IDARTICULO FROM #IMOVH_AGRUPADO)
								   GROUP BY IDXB.IDARTICULO) X ON IART.IDARTICULO = X.IDARTICULO
			   WHERE @IDARTICULO = IART.IDARTICULO  
         END

         IF DBO.FNK_VALORVARIABLE('IXCOUNTRY')='PERU'  AND 1 = 2
         BEGIN
			   UPDATE IDXB SET         
			   PCOSTOM=((ISNULL(IDXB.PCOSTOM,0)*ISNULL(X.EXISTOTAL,0))+(@PCOSTO_CUR_DETALLE*@CANTIDAD_CUR_DETALLE))/ 
							   (ISNULL(X.EXISTOTAL,0)+@CANTIDAD_CUR_DETALLE)
			   FROM IDXB INNER JOIN  (SELECT IDXB.IDARTICULO, ISNULL(SUM(ISNULL(EXISTOTAL,0)),0) EXISTOTAL
								   FROM   IDXB INNER JOIN IBOD ON IDXB.IDBODEGA = IBOD.IDBODEGA
								   WHERE  IBOD.TIPOBODEGA='Propia'
								   AND		IDXB.IDARTICULO IN (SELECT IDARTICULO FROM #IMOVH_AGRUPADO)
                           AND IDXB.IDBODEGA=@IDBODEGA
								   GROUP BY IDXB.IDARTICULO) X ON IDXB.IDARTICULO = X.IDARTICULO
			   WHERE @IDARTICULO = IDXB.IDARTICULO 
         END
			
		END

	FETCH NEXT FROM _CURSOR INTO @IDARTICULO, @PCOSTO_CUR_DETALLE,@CANTIDAD_CUR_DETALLE
	END  
	CLOSE _CURSOR  
	DEALLOCATE _CURSOR
	/* EZERPA 22/12/2018 FIN */
   
	-- Apertura de kardex del d�a: delegada a SPK_ACTUALIZA_KARDEX (evita overflow en IHISD.PCOSTO y duplicar l�gica).

	SELECT IMOVH.IDARTICULO, NOLOTEPEDIDO,IDXB.EXISTOTAL,IART.PCOSTO,@USUARIO USUARIOCONF,@FECHACONF FECHACONF 
	INTO #IDXB_IART
	FROM #IMOVH_AGRUPADO IMOVH,IDXB,IART
	WHERE	IDXB.IDBODEGA=@IDBODEGA 
	AND		IDXB.IDARTICULO=IMOVH.IDARTICULO 
	AND     IART.IDARTICULO=IMOVH.IDARTICULO
	--DECLARE @CNSFCOM VARCHAR(20)
	SELECT @CNSFCOM=CNSFCOM FROM IMOV WHERE CNSMOV=@CNSMOV
	UPDATE IMOVH SET      
		EXISTENCIA = CAST(COALESCE(EXISTOTAL, 0) AS DECIMAL(14,2)),      
		PCOSTOANTES = CAST(COALESCE(#IDXB_IART.PCOSTO, 0) AS DECIMAL(14,2)),      
		USUARIOCONF=#IDXB_IART.USUARIOCONF,      
		FECHACONF = #IDXB_IART.FECHACONF   
	FROM #IDXB_IART INNER JOIN IMOVH ON IMOVH.NOLOTEPEDIDO=#IDXB_IART.NOLOTEPEDIDO AND IMOVH.IDARTICULO = #IDXB_IART.IDARTICULO

	-- =====================================================================
	-- Traslados (CNSITRA): no mezclar lotes proveedor distintos.
	-- 1) Prioridad match por NOLOTEPEDIDO ? sumar a esa fila IEXI (adoptar su NOLOTE).
	-- 2) Si el proveedor no existe y el NOLOTE interno est� ocupado ? generar NOLOTE nuevo.
	-- 3) NOLOTE es PK en IEXI: nunca duplicar.
	-- =====================================================================
	DECLARE @CNSITRA_TRAS VARCHAR(20)
	DECLARE @H_IDART VARCHAR(20)
	DECLARE @H_NOLOTE VARCHAR(20)
	DECLARE @H_NOLOTE_OLD VARCHAR(20)
	DECLARE @H_PEDIDO VARCHAR(20)
	DECLARE @H_CANT DECIMAL(18,6)
	DECLARE @IEXI_NOLOTE VARCHAR(20)
	DECLARE @NUEVO_NOLOTE VARCHAR(20)
	DECLARE @NOLOTE_RAW VARCHAR(20)
	DECLARE @TRY_NOLOTE INT

	IF OBJECT_ID('tempdb..#MAP_TRAS_NOLOTE') IS NOT NULL DROP TABLE #MAP_TRAS_NOLOTE
	CREATE TABLE #MAP_TRAS_NOLOTE (
		IDARTICULO   VARCHAR(20) COLLATE DATABASE_DEFAULT,
		NOLOTE_ORI   VARCHAR(20) COLLATE DATABASE_DEFAULT,
		NOLOTE_DES   VARCHAR(20) COLLATE DATABASE_DEFAULT,
		NOLOTEPEDIDO VARCHAR(20) COLLATE DATABASE_DEFAULT
	)

	-- CNSITRA = tr�nsito. CNSTRAN en custodia es el paciente: no usarlo como ITRA
	-- (disparaba el merge por NOLOTEPEDIDO y apilaba unidades de varios pacientes).
	SELECT @CNSITRA_TRAS = NULLIF(LTRIM(RTRIM(IMOV.CNSITRA)), '')
	FROM IMOV
	WHERE IMOV.CNSMOV = @CNSMOV

	IF COALESCE(@CNSITRA_TRAS, '') = ''
	BEGIN
		SELECT TOP 1 @CNSITRA_TRAS = I.CNSITRA
		FROM ITRA I
		WHERE I.CNSMOVDES = @CNSMOV
		ORDER BY I.FECHAING DESC
	END

	IF COALESCE(@CNSITRA_TRAS, '') <> ''
	   AND COALESCE(@IDTIPOMOV, '') <> COALESCE(@IDINVTPROPIA, '')
	BEGIN
		-- Custodia (IDINVTPROPIA): 1 IEXI por unidad. No adoptar el NOLOTE de otro
		-- paciente con el mismo lote de proveedor.
		-- Alinear detalle con ITRAH (lote proveedor / vencimiento de origen)
		UPDATE H
		SET
			NOLOTEPEDIDO = COALESCE(NULLIF(LTRIM(RTRIM(TH.NOLOTEPEDIDO)), ''), H.NOLOTEPEDIDO),
			FECHAVENCE = COALESCE(TH.FECHAVENCE, H.FECHAVENCE)
		FROM IMOVH H
		INNER JOIN ITRAH TH
			ON TH.CNSITRA = @CNSITRA_TRAS
