CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NEDIA @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20)
DECLARE @PROCESO VARCHAR(20), @CODCONCEPTO VARCHAR(20)
DECLARE @CNSPAGO VARCHAR(20), @NUMDOC VARCHAR(20), @ITEM DECIMAL(14, 0), @FECHAINI NVARCHAR(10), @FECHAFIN NVARCHAR(10)
DECLARE @HORAS SMALLINT, @MINUTOS SMALLINT, @IDEVENTO VARCHAR(6), @FACTOR DECIMAL(14, 6)
DECLARE @FORMALIQUIDACION VARCHAR(12), @PRORROGA BIT, @DIAS SMALLINT, @NDIAS SMALLINT, @DCALEN BIT, @HORAINI NVARCHAR(5), @HORAFIN NVARCHAR(5), @OBSERVACION VARCHAR(
		512), @INDEMNIZA BIT, @NDIASEG SMALLINT, @IDDX VARCHAR(10), @CODPRF_RECO VARCHAR(20), @RECOBRO BIT, @IDTERCERO VARCHAR(20), @FECHAINI_REG DATETIME, 
	@FECHAFIN_REG DATETIME
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @CNSPAGO = CNSPAGO, @NUMDOC = NUMDOC, @FECHAINI = FECHAINI, @FECHAFIN = FECHAFIN, @HORAS = HORAS, @MINUTOS = MINUTOS, @IDEVENTO = IDEVENTO, @FACTOR = 
				FACTOR, @FORMALIQUIDACION = FORMALIQUIDACION, @PRORROGA = PRORROGA, @DIAS = DIAS, @NDIAS = NDIAS, @DCALEN = DCALEN, @HORAINI = HORAINI, @HORAFIN = HORAFIN, 
				@ITEM = ITEM, @PROCESO = PROCESO, @OBSERVACION = OBSERVACION, @INDEMNIZA = INDEMNIZA, @NDIASEG = NDIASEG, @IDDX = IDDX, @RECOBRO = RECOBRO, @IDTERCERO = 
				IDTERCERO, @FECHAINI_REG = FECHAINI_REG, @FECHAFIN_REG = FECHAFIN_REG
			FROM OPENJSON(@PARAMETROS) WITH (
					CNSPAGO VARCHAR(20) '$.CNSPAGO', NUMDOC VARCHAR(20) '$.NUMDOC', FECHAINI NVARCHAR(10) '$.FECHAINI', FECHAFIN NVARCHAR(10) '$.FECHAFIN', HORAS 
					SMALLINT '$.HORAS', MINUTOS SMALLINT '$.MINUTOS', IDEVENTO VARCHAR(6) '$.IDEVENTO', FACTOR DECIMAL(14, 6) '$.FACTOR', FORMALIQUIDACION VARCHAR(
						12) '$.FORMALIQUIDACION', PRORROGA BIT '$.PRORROGA', DIAS SMALLINT '$.DIAS', NDIAS SMALLINT '$.NDIAS', DCALEN BIT '$.DCALEN', HORAINI 
					NVARCHAR(5) '$.HORAINI', HORAFIN NVARCHAR(5) '$.HORAFIN', ITEM DECIMAL(14, 0) '$.ITEM', PROCESO VARCHAR(20) '$.PROCESO', PROCESO VARCHAR(20) 
					'$.PROCESO', INDEMNIZA BIT '$.INDEMNIZA', OBSERVACION VARCHAR(512) '$.OBSERVACION', NDIASEG SMALLINT '$.NDIASEG', IDDX VARCHAR(10) '$.IDDX', 
					RECOBRO BIT '$.RECOBRO', IDTERCERO VARCHAR(20) '$.IDTERCERO', FECHAINI_REG DATETIME '$.FECHAINI_REG', FECHAFIN_REG DATETIME '$.FECHAFIN_REG'
					)

			DECLARE @HORAS_CALCULADAS INT
			DECLARE @MINUTOS_CALCULADOS INT

			SELECT @HORAS_CALCULADAS = CASE 
					WHEN @DIAS = 0
						THEN @HORAS
					ELSE CONVERT(INT, (E.HORASDELABOR / CAST(E.DIASXCARGO AS FLOAT)) * @DIAS)
					END, @MINUTOS_CALCULADOS = CASE 
					WHEN @DIAS = 0
						THEN @MINUTOS
					ELSE DBO.FNQ_NOVEDAD_MINUTOS(@DIAS, E.HORASDELABOR)
					END
			FROM NEMP E
			WHERE E.NUMDOC = @NUMDOC;

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				INSERT INTO NEDIA (
					CNSPAGO, NUMDOC, FECHAINI, FECHAFIN, HORAS, MINUTOS, IDEVENTO, FACTOR, FORMALIQUIDACION, PRORROGA, DIAS, NDIAS, DCALEN, OBSERVACION, INDEMNIZA, 
					NDIASEG, IDDX, RECOBRO, IDTERCERO, FECHAINI_REG, FECHAFIN_REG
					)
				SELECT @CNSPAGO, @NUMDOC, (CONVERT(DATETIME, CONCAT (@FECHAINI, ' ', @HORAINI), 111)), 
						(CONVERT(DATETIME, CONCAT (@FECHAFIN, ' ', @HORAFIN), 111)), 
					@HORAS_CALCULADAS, @MINUTOS_CALCULADOS, @IDEVENTO, @FACTOR, @FORMALIQUIDACION, @PRORROGA, @DIAS, @NDIAS, @DCALEN, @OBSERVACION, @INDEMNIZA, 
					@NDIASEG, @IDDX, @RECOBRO, @IDTERCERO, @FECHAINI_REG, @FECHAFIN_REG
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				UPDATE NEDIA
				SET FECHAINI = (CONVERT(DATETIME, CONCAT (@FECHAINI, ' ', @HORAINI), 111)), FECHAFIN = (CONVERT(DATETIME, CONCAT (@FECHAFIN, ' ', @HORAFIN), 111)
						), HORAS = @HORAS, MINUTOS = @MINUTOS, IDEVENTO = @IDEVENTO, FACTOR = @FACTOR, FORMALIQUIDACION = @FORMALIQUIDACION, PRORROGA = @PRORROGA, DIAS = 
					@DIAS, NDIAS = @NDIAS, DCALEN = @DCALEN, OBSERVACION = @OBSERVACION, INDEMNIZA = @INDEMNIZA, NDIASEG = @NDIASEG, IDDX = @IDDX, FECHAINI_REG = 
					@FECHAINI_REG, FECHAFIN_REG = @FECHAFIN_REG
				WHERE CNSPAGO = @CNSPAGO AND NUMDOC = @NUMDOC AND ITEM = @ITEM
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @CNSPAGO = CNSPAGO, @NUMDOC = NUMDOC, @ITEM = ITEM, @CODCONCEPTO = CODCONCEPTO
		FROM OPENJSON(@PARAMETROS) WITH (CNSPAGO VARCHAR(20) '$.CNSPAGO', NUMDOC VARCHAR(20) '$.NUMDOC', ITEM DECIMAL(14, 0) '$.ITEM', CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO'
				)

		BEGIN TRY
			DELETE
			FROM NEDIA
			WHERE CNSPAGO = @CNSPAGO AND NUMDOC = @NUMDOC AND ITEM = @ITEM

			IF @CODCONCEPTO = 'RET'
			BEGIN
				EXEC SPK_QUITANOV_RETIROS @CNSPAGO, @NUMDOC
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'TERCERO_RECOBRO'
	BEGIN
		SELECT @CODPRF_RECO = CODPRF_RECO, @NUMDOC = NUMDOC, @FECHAINI = FECHAINI
		FROM OPENJSON(@PARAMETROS) WITH (CODPRF_RECO VARCHAR(20) '$.CODPRF_RECO', NUMDOC VARCHAR(20) '$.NUMDOC', FECHAINI NVARCHAR(10) '$.FECHAINI'
				)

		SELECT 'OK' OK

		SELECT TOP 1 NPRFED.IDTERCERO, TER.RAZONSOCIAL
		FROM NPRFED
		INNER JOIN TER ON TER.IDTERCERO = NPRFED.IDTERCERO
		WHERE NUMDOC = @NUMDOC AND CODPRF = @CODPRF_RECO AND FECHAINI <= CONVERT(DATE, @FECHAINI, 111)
		ORDER BY FECHAINI DESC;

		RETURN
	END

	IF @METODO = 'OBTENER_DIA'
	BEGIN
		SELECT @CNSPAGO = CNSPAGO, @FECHAINI = FECHAINI
		FROM OPENJSON(@PARAMETROS) WITH (CNSPAGO VARCHAR(20) '$.CNSPAGO', FECHAINI NVARCHAR(10) '$.FECHAINI')

		SELECT 'OK' OK

		SELECT DATEDIFF(DAY, (CONVERT(DATE, @FECHAINI, 111)), CASE 
					WHEN DAY(FECHAFIN) < 30
						THEN FECHAFIN
					ELSE FECHAINI + 29
					END) + 1 AS DIA
		FROM NPER
		WHERE CNSPAGO = @CNSPAGO

		RETURN
	END

	IF @METODO = 'NEMPE_HIST'
	BEGIN
		SELECT @NUMDOC = NUMDOC, @FECHAFIN = FECHAFIN
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC', FECHAFIN NVARCHAR(10) '$.FECHAFIN')

		SELECT 'OK' OK

		SELECT FECHAING = CONVERT(CHAR, X.FECHAING, 103), X.HORASXCARGO, X.DIASXCARGO, X.BASICO, X.IDAREA, AFU.DESCRIPCION AS AFU, X.CODPLANTA, X.CODCARGO, NCAR.
			DESCRIPCION AS NCAR, X.NIVEL, X.GRADO, NCARNG.DESCRIPCION AS NCARNG
		FROM FNK_INFO_NEMPHIS(CONVERT(DATE, @FECHAFIN, 111)) X
		LEFT JOIN NCAR ON X.CODCARGO = NCAR.CODCARGO
		LEFT JOIN NCARNG ON X.CODCARGO = NCARNG.CODCARGO AND X.NIVEL = NCARNG.NIVEL AND X.GRADO = NCARNG.GRADO
		LEFT JOIN AFU ON X.IDAREA = AFU.IDAREA
		WHERE X.NUMDOC = @NUMDOC
	END
END
