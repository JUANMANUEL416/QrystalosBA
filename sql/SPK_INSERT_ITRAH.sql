CREATE OR ALTER PROCEDURE DBO.SPK_INSERT_ITRAH 
@CNS VARCHAR(16) 
WITH ENCRYPTION
AS

DECLARE @IDARTICULO VARCHAR(20)
DECLARE @CANTOTAL DECIMAL(14,2)
DECLARE @CNSITRA VARCHAR(20)
DECLARE @CNSFCOM VARCHAR(20)
DECLARE @CANTORG DECIMAL(14,2)
DECLARE @CANT    DECIMAL(14,2)

BEGIN
   INSERT INTO ITRAH (CNSITRA,IDARTICULO,NOLOTE,CANTIDADORI,CANTIDADDES,IDCAUSAL,ESTADO,       
                  PCOSTO,NOLOTEPEDIDO,FECHAVENCE,DETALLE,INICIAL,IDARTICULOORI,    
                  RINVIMA,SELLOCALIDAD,TEMPETURA,CAPACIDAD,IDDONANTE,NROUNIDAD,        
                  PROCEDENCIA,CODBANSAN,GRUPOABO,GRUPORH,FRECOLECCION,
                  CANTIDADREV,CUMPLE,APROBADO,PRESENCIA,SUBGRUPO, ESTANTE)
   SELECT ID1,ID2, ID3,CANTIDAD,CANTIDAD,'',0,VALOR1,ID4,FECHA1,'',1,ID11,
          ID9,ID5,VALOR27,VALOR5,ID12,ID13,ID14,ID15,ID16,ID17,FECHA2,
          CANTIDAD3,CANTIDAD4,CANTIDAD5,ID18, STRINGMEDIO9, ID19
   FROM RPDX
   WHERE CNS=@CNS


   SELECT @CNSITRA=ID1
   FROM RPDX
   WHERE CNS=@CNS


   SELECT @CNSFCOM = CNSFCOM
   FROM ITRA
   WHERE CNSITRA = @CNSITRA


   UPDATE ITRAH SET 
                  ODESFERA	   =FCOMD.ODESFERA,
                  OIESFERA	   =FCOMD.OIESFERA,
                  ODCILINDRO	=FCOMD.ODCILINDRO,
                  OICILINDRO	=FCOMD.OICILINDRO,
                  ODEJE	      =FCOMD.ODEJE,
                  OIEJE	      =FCOMD.OIEJE,
                  ODADICION	=FCOMD.ODADICION,
                  OIADICION	=FCOMD.OIADICION,
                  ODALT	      =FCOMD.ODALT,
                  OIALT	      =FCOMD.OIALT,
                  ODAVL	      =FCOMD.ODAVL,
                  OIAVL	      =FCOMD.OIAVL,
                  ODTLENTE	   =FCOMD.ODTLENTE,
                  OITLENTE	   =FCOMD.OITLENTE,
                  ODDNP	      =FCOMD.ODDNP,
                  OIDNP	      =FCOMD.OIDNP,
                  IVA	      =FCOMD.FACTORIVA,
                  PCSINIVA	      =FCOMD.VLR_UNITARIO
   FROM ITRAH  INNER JOIN ITRA ON ITRAH.CNSITRA = ITRA.CNSITRA
				 INNER JOIN FCOM ON ITRA.CNSFCOM = FCOM.CNSFCOM
				 INNER JOIN FCOMD ON FCOM.CNSFCOM = FCOMD.CNSFCOM AND  ITRAH.IDARTICULOORI=FCOMD.IDARTICULO


   WHERE ITRAH.CNSITRA=@CNSITRA


   DECLARE FALTANTES CURSOR FOR 
      SELECT DISTINCT COALESCE(IDARTICULOORI,IDARTICULO)
      FROM ITRAH
      WHERE CNSITRA=@CNSITRA
      AND COALESCE(INICIAL,0)=0


   OPEN FALTANTES
   FETCH NEXT FROM FALTANTES 
      INTO @IDARTICULO
   WHILE @@fetch_status=0

   BEGIN
      SELECT @CANTOTAL=SUM(CANTIDADORI)
      FROM ITRAH
      WHERE CNSITRA=@CNSITRA
        AND COALESCE(INICIAL,0)=1
        AND COALESCE(NOLOTE,'') NOT IN ('','0')
        AND (
             COALESCE(IDARTICULOORI,IDARTICULO)=@IDARTICULO
             OR IDARTICULO LIKE @IDARTICULO + '-%'
        )


      SELECT @CANTORG = COALESCE(SUM(B.CANTIDADORI), 0)
      FROM ITRAH B
      WHERE B.CNSITRA = @CNSITRA
        AND COALESCE(B.INICIAL, 0) = 0
        AND COALESCE(B.IDARTICULOORI, B.IDARTICULO) = @IDARTICULO

      IF COALESCE(@CANTORG, 0) = 0 AND COALESCE(@CNSFCOM, '') <> ''
      BEGIN
         SELECT @CANTORG = SUM(D.CANTIDAD)
         FROM FCOMD D
         WHERE D.CNSFCOM = @CNSFCOM
           AND D.IDARTICULO = @IDARTICULO
      END


      SELECT @CANT=@CANTORG-COALESCE(@CANTOTAL,0)
      IF @CANT>0
	   BEGIN 
         ;WITH B AS (
            SELECT NOLOTE, ROW_NUMBER() OVER (ORDER BY NOLOTE) AS RN
            FROM ITRAH
            WHERE CNSITRA=@CNSITRA AND COALESCE(IDARTICULOORI,IDARTICULO)=@IDARTICULO AND COALESCE(INICIAL,0)=0
         )
         DELETE FROM ITRAH
         WHERE CNSITRA=@CNSITRA AND COALESCE(IDARTICULOORI,IDARTICULO)=@IDARTICULO AND COALESCE(INICIAL,0)=0
           AND NOLOTE IN (SELECT NOLOTE FROM B WHERE RN > 1)


		 UPDATE ITRAH SET CANTIDADORI=@CANT, CANTIDADDES=0
		 WHERE CNSITRA=@CNSITRA 
		 AND COALESCE(IDARTICULOORI,IDARTICULO)=@IDARTICULO 
		 AND COALESCE(INICIAL,0)= 0 
	   END
	   ELSE IF @CANT = 0 AND COALESCE(@CANTORG,0) > 0
	   BEGIN
		 DELETE FROM ITRAH
		 WHERE CNSITRA=@CNSITRA
		   AND COALESCE(IDARTICULOORI,IDARTICULO)=@IDARTICULO
		   AND COALESCE(INICIAL,0)=0
	   END


	  UPDATE ITRAH
	  SET CANTIDADDES = 0
	  WHERE CNSITRA = @CNSITRA
	    AND COALESCE(INICIAL,0) = 0

	   FETCH NEXT FROM FALTANTES
         INTO @IDARTICULO
   END


   CLOSE FALTANTES
   DEALLOCATE FALTANTES

END
