IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME = 'SPK_CIERRE_FISCAL' AND XTYPE='P')
BEGIN
   DROP PROCEDURE SPK_CIERRE_FISCAL
END
GO
CREATE PROC DBO.SPK_CIERRE_FISCAL
@ANO     VARCHAR(4), 
@MES     INT,
@CODPRES VARCHAR(20),
@USUARIO VARCHAR(12)
WITH ENCRYPTION
AS
DECLARE @AUX    INT
DECLARE @ANOANT VARCHAR(4)
DECLARE @MESANT INT
BEGIN
   IF (SELECT COALESCE(MESDECIERRE,'') FROM PAR) <> @MES
   BEGIN
      RAISERROR('ESTE PERIODO NO ES DE CIERRE FISCAL',16,1)
      RETURN
   END
   SELECT @AUX = COUNT(*) FROM PRI WHERE COALESCE(SI,0) = 1 
   IF COALESCE(@AUX,0) > 1
   BEGIN
      RAISERROR('MAS DE UN PERIODO DEFINIDO COMO DE SALDOS INICIALES',16,1)
      RETURN
   END
   SELECT @AUX = COALESCE(SI,0) FROM PRI WHERE ANO = @ANO AND MES = @MES
   IF COALESCE(@AUX,0) > 0
   BEGIN
      RAISERROR('PERIODO ESTA DEFINIDO COMO DE SALDOS INICIALES',16,1)
      RETURN
   END
   SELECT @AUX = COALESCE(PRI.CERRADO,0) FROM PRI WHERE ANO = @ANO AND MES = @MES
   IF @AUX = 1
   BEGIN
      RAISERROR('PERIODO CERRADO ',16,1)
      RETURN
   END  
   SELECT @AUX = COUNT(*) FROM MCP WHERE COALESCE(ESTADO,0) <> '2' AND COALESCE(ANULADO,0) = 0 AND ANO = @ANO AND MES = @MES
   IF COALESCE(@AUX,0) > 0
   BEGIN
      RAISERROR('FALTAN COMPROBANTES POR CONFIRMAR ',16,1)
      RETURN
   END
   SELECT @AUX = COUNT(*) FROM MCPE WHERE ANO = @ANO AND MES = @MES
   IF COALESCE(@AUX,0) > 0
   BEGIN
      RAISERROR('COMPROBANTES ERRADOS (MCPE) ',16,1)
      RETURN
   END
   SELECT @MESANT = CASE @MES WHEN 1 THEN 12 ELSE @MES -1 END
   SELECT @ANOANT = CASE @MES WHEN 1 THEN @ANO - 1 ELSE @ANO END
   
   SELECT @AUX = COALESCE(CERRADO,0) FROM PRI WHERE ANO = @ANOANT AND MES = @MESANT
   IF @AUX = 0
   BEGIN
      RAISERROR('PERIODO ANTERIOR NO ESTA CERRADO.',16,1)
      RETURN
   END
     
   CREATE TABLE #GENEALOGICO
          (CUENTA    VARCHAR(16) COLLATE database_default,   
           NOMCUENTA VARCHAR(200) COLLATE database_default,   
           TIPO      VARCHAR(7)  COLLATE database_default,   
           CENTRO    SMALLINT,   
           TERCERO   SMALLINT,  
           CLASE     VARCHAR(10) COLLATE database_default,  
           NIVEL     SMALLINT,  
           CUENTA_SUMA VARCHAR(16) COLLATE database_default,
           CUENTA_DETALLE VARCHAR(16) COLLATE database_default
          )
          
   --INSERTAMOS GENEALOGICO       
   INSERT INTO #GENEALOGICO
   SELECT  * FROM FNK_GENEALOGICO_CUE('01')
   --BORRAMOS SALDOS DEL MES
   DELETE SDCUEFIS WHERE ANO = @ANO AND MES = @MES  
   DELETE SDCUEFI WHERE ANO = @ANO AND MES = @MES  
   PRINT 'BORRADAS TABLAS SDCUEFI'
   --BALANCE DEL MES DB Y CR CON MOVIMIENTOS DEL MES

   INSERT INTO SDCUEFIS (ANO, MES, CUENTA, IDTERCERO, CCOSTO, N_FACTURA, NOMCUENTA,SI, DB, CR, SF, SM, NTZ,CLASE)
   SELECT @ANO, @MES, X.CUENTA, COALESCE(MCH.IDTERCERO,''), COALESCE(MCH.CCOSTO,''), COALESCE(MCH.N_FACTURA,''), X.NOMCUENTA,0, 
          SUM(CASE MCH.TIPO WHEN 'DB' THEN MCH.VALOR ELSE 0 END) DB, 
          SUM(CASE MCH.TIPO WHEN 'CR' THEN MCH.VALOR ELSE 0 END) CR,
          0 SF,
          0 SM,         
          NTZ.TIPO,'Local'
   FROM   MCP INNER JOIN MCH            ON MCP.NROCOMPROBANTE = MCH.NROCOMPROBANTE 
              INNER JOIN #GENEALOGICO X ON X.CUENTA_DETALLE = MCH.CUENTA
              INNER JOIN NTZ            ON  LEFT(MCH.CUENTA,1) = NTZ.N_INICIAL             
   WHERE  MCP.ESTADO = 2 AND ISNULL(MCP.ANULADO,0) = 0
   AND    MCP.ANO = @ANO
   AND    MCP.MES = @MES
   AND    LEFT(MCH.CUENTA,1) IN ('4','5','6')
   GROUP BY X.CUENTA, COALESCE(MCH.IDTERCERO,''), COALESCE(MCH.CCOSTO,''), COALESCE(MCH.N_FACTURA,''), X.NOMCUENTA, NTZ.TIPO
   ORDER BY X.CUENTA
   /*****************************************************************************************************************/
   /* SE INSERTA EN BALANCE CUENTAS QUE NO TUVIERON MOVIMIENTO EN EL MES PERO TIENEN SALDOS ANTERIORES              */
   /*****************************************************************************************************************/
   
   INSERT INTO SDCUEFIS (ANO, MES, CUENTA, IDTERCERO, CCOSTO, N_FACTURA, NOMCUENTA,SI,DB,CR,SF, SM, NTZ,CLASE)
   SELECT @ANO, @MES, X.CUENTA, COALESCE(A.IDTERCERO,''), COALESCE(A.CCOSTO,''), COALESCE(A.N_FACTURA,''), X.NOMCUENTA, 0, 0, 0, 0, 0, NTZ.TIPO,'Local'
   FROM   SALDOMESTERFAC A INNER JOIN #GENEALOGICO X ON X.CUENTA_DETALLE = A.CUENTA
                           INNER JOIN NTZ            ON LEFT(A.CUENTA,1) = NTZ.N_INICIAL
                           INNER JOIN CUE            ON A.CUENTA = CUE.CUENTA                          
   WHERE  NOT EXISTS (SELECT * FROM SDCUEFIS B
                      WHERE  B.ANO = @ANO AND B.MES = @MES
                      AND    X.CUENTA    = B.CUENTA
                      AND    COALESCE(A.IDTERCERO,'') = COALESCE(B.IDTERCERO,'')
                      AND    COALESCE(A.CCOSTO,'')    = COALESCE(B.CCOSTO,'')
                      AND    COALESCE(A.N_FACTURA,'')    = COALESCE(B.N_FACTURA,'')
                      )
   AND    A.ANO    = @ANOANT
   AND    A.MES    = @MESANT
   AND    LEFT(A.CUENTA,1) IN ('4','5','6')
   GROUP BY X.CUENTA, COALESCE(A.IDTERCERO,''), COALESCE(A.CCOSTO,''), COALESCE(A.N_FACTURA,''), X.NOMCUENTA, NTZ.TIPO
   ORDER BY X.CUENTA      
   /******************************/
   /* COLOCAMOS SALDOS INICIALES */ 
   /******************************/

   UPDATE SDCUEFIS SET SDCUEFIS.SI = X.SF
   FROM   SDCUEFIS INNER JOIN (
                               SELECT X.CUENTA, COALESCE(SALDOMESTERFAC.IDTERCERO,'') IDTERCERO, COALESCE(SALDOMESTERFAC.CCOSTO,'') CCOSTO, 
                                      COALESCE(SALDOMESTERFAC.N_FACTURA,'') N_FACTURA,
                                      SUM(SALDOMESTERFAC.SF) SF
                               FROM   SALDOMESTERFAC INNER JOIN #GENEALOGICO X ON X.CUENTA_DETALLE = SALDOMESTERFAC.CUENTA
                               WHERE  SALDOMESTERFAC.ANO = @ANOANT
                               AND    SALDOMESTERFAC.MES = @MESANT 
                               GROUP BY X.CUENTA, COALESCE(SALDOMESTERFAC.IDTERCERO,''), COALESCE(SALDOMESTERFAC.CCOSTO,''), COALESCE(SALDOMESTERFAC.N_FACTURA,'')
                               ) X ON SDCUEFIS.CUENTA    = X.CUENTA 
                                  AND COALESCE(SDCUEFIS.IDTERCERO,'') = COALESCE(X.IDTERCERO, '')
                                  AND COALESCE(SDCUEFIS.CCOSTO,'')    = COALESCE(X.CCOSTO,'')
                                  AND COALESCE(SDCUEFIS.N_FACTURA,'') = COALESCE(X.N_FACTURA,'')
   WHERE   SDCUEFIS.ANO = @ANO
   AND     SDCUEFIS.MES = @MES 
   AND     SDCUEFIS.CLASE = 'Local'                           
   /*****************************/
   /* CALCULAMOS SALDOS FINALES */
   /*****************************/
   UPDATE SDCUEFIS SET SF = CASE NTZ.TIPO WHEN 'DB' THEN SDCUEFIS.SI + SDCUEFIS.DB - SDCUEFIS.CR
                                                    ELSE SDCUEFIS.SI + SDCUEFIS.CR - SDCUEFIS.DB
                            END,                
                       SM = CASE NTZ.TIPO WHEN 'DB' THEN SDCUEFIS.DB - SDCUEFIS.CR
                                                    ELSE SDCUEFIS.CR - SDCUEFIS.DB
                            END                     
   FROM   SDCUEFIS INNER JOIN NTZ ON LEFT(SDCUEFIS.CUENTA,1) = NTZ.N_INICIAL
   WHERE  SDCUEFIS.ANO = @ANO
   AND    SDCUEFIS.MES = @MES
   AND     SDCUEFIS.CLASE = 'Local'


   INSERT INTO SDCUEFI ( ANO, MES, CUENTA, NOMCUENTA, SI, DB, CR, SF, SM, NTZ)
   SELECT ANO, MES, CUENTA, NOMCUENTA, SUM(SI), SUM(DB), SUM(CR), SUM(SF), SUM(SF), NTZ
   FROM   SDCUEFIS
   WHERE  SDCUEFIS.ANO = @ANO
   AND    SDCUEFIS.MES = @MES
   AND     SDCUEFIS.CLASE = 'Local'
   GROUP BY ANO, MES, CUENTA, NOMCUENTA, NTZ

      -- CERRAMOS EL PERIODO
   --UPDATE PRI SET CERRADO = 1 WHERE ANO = @ANO AND MES = @MES AND COMPANIA = '01'
   
END
