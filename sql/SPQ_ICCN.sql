CREATE OR ALTER PROCEDURE DBO.SPQ_ICCN
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @PARAMETROS NVARCHAR(MAX), @MODELO         VARCHAR(100),   @METODO         VARCHAR(100)
DECLARE  @USUARIO    VARCHAR(20),   @IDCONCENTRA    VARCHAR(4),		@DESCRIPCION	VARCHAR(30)
DECLARE	 @IDITAR	 VARCHAR(2)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDCONCENTRA = IDCONCENTRA, @DESCRIPCION = DESCRIPCION, @IDITAR = IDITAR 
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				IDCONCENTRA VARCHAR(4)  '$.IDCONCENTRA', DESCRIPCION VARCHAR(30)  '$.DESCRIPCION',
				IDITAR		VARCHAR(2)  '$.IDITAR'
			)

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'LA FORMA DE CONCENTRACION YA EXISTE'
			WHERE EXISTS (SELECT * FROM ICCN WHERE IDCONCENTRA = @IDCONCENTRA)

			IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
			BEGIN
				INSERT INTO ICCN (IDCONCENTRA ,DESCRIPCION ,IDITAR ) 
				SELECT @IDCONCENTRA, @DESCRIPCION, @IDITAR
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ACTUALIZAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDCONCENTRA = IDCONCENTRA, @DESCRIPCION = DESCRIPCION, @IDITAR = IDITAR 
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				IDCONCENTRA VARCHAR(4)  '$.IDCONCENTRA', DESCRIPCION VARCHAR(30)  '$.DESCRIPCION',
				IDITAR		VARCHAR(2)  '$.IDITAR'
			)

			UPDATE ICCN SET DESCRIPCION = @DESCRIPCION, IDITAR = @IDITAR WHERE IDCONCENTRA = @IDCONCENTRA			
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
	
	IF @METODO = 'ELIMINAR'
	BEGIN
		BEGIN TRY
			SELECT @IDCONCENTRA = JSON_VALUE(@PARAMETROS, '$.IDCONCENTRA')

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'LA FORMA DE CONCENTRACION TIENE ARTICULOS RELACIONADOS (IART)'
			WHERE EXISTS (SELECT * FROM IART WHERE IDCONCENTRA = @IDCONCENTRA)

			IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
			BEGIN
				DELETE FROM ICCN WHERE IDCONCENTRA = @IDCONCENTRA
			END		
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
END
