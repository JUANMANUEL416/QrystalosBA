IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='SPK_CONFIRMAR_PAGOSMASIVO' AND XTYPE='P')
BEGIN
   DROP PROCEDURE SPK_CONFIRMAR_PAGOSMASIVO
END

GO

CREATE PROCEDURE DBO.SPK_CONFIRMAR_PAGOSMASIVO
@CNSFCXPPM             VARCHAR(20),
@COMPANIA              VARCHAR(2),
@SEDE                  VARCHAR(5),
@SYS_COMPUTERNAME      VARCHAR(255),
@USUARIO               VARCHAR(12)
WITH ENCRYPTION
AS
DECLARE @CNS              VARCHAR(20) 
DECLARE @CNSFCXP          VARCHAR(20) 
DECLARE @CNSFCXPP         VARCHAR(20) 
DECLARE @N_FACTURA        VARCHAR(20)
DECLARE @F_FACTURA        DATETIME
DECLARE @F_VENCE          DATETIME    
DECLARE @IDTERCERO        VARCHAR(20)
DECLARE @SALDO            DECIMAL(14,2)
DECLARE @OBSERVACION      VARCHAR(255) 
DECLARE @CNSFACJ          VARCHAR(20)
DECLARE @CODCAJA          VARCHAR(4)  
DECLARE @VALORTOTAL       DECIMAL(14,2)
DECLARE @NOMBRECLIENTE    VARCHAR(40)
DECLARE @CNSACJ           VARCHAR(20)  
DECLARE @IDTERCERO_ANT    VARCHAR(20)
DECLARE @ITEM             SMALLINT
DECLARE @FECHAPAGO        DATETIME
DECLARE @IDTERCERO_AFAVOR VARCHAR(20)
DECLARE @SW               INT
DECLARE @PORPAGAR         DECIMAL(14,2)
DECLARE @CODUNG           VARCHAR(5)
DECLARE @CODPRG           VARCHAR(20)
DECLARE @TIPOEGRESO       VARCHAR(8)
DECLARE @CODCAJA1         VARCHAR(4)
DECLARE @IDSEDE           VARCHAR(5)
BEGIN
	IF(SELECT ESTADO FROM FCXPPM WHERE CNSFCXPPM=@CNSFCXPPM)<>'N'
	BEGIN
		PRINT 'El estado de la orden no es pendiente por autorizar'
		RETURN
	END
	UPDATE FCXPPM SET VALOR=(SELECT SUM(ABONO) FROM FCXPP WHERE CNSFCXPPM=@CNSFCXPPM AND ESTADO<>'A')
			WHERE CNSFCXPPM=@CNSFCXPPM

	SELECT @IDTERCERO_AFAVOR = IDTERCERO_AFAVOR,
			@PORPAGAR = VALOR-(CASE WHEN (SELECT SUM(VALOR) 
											FROM FCXPCXC 
											WHERE CNSFCXPPM=@CNSFCXPPM) >0 THEN (SELECT SUM(VALOR) 
																				FROM FCXPCXC 
																				WHERE CNSFCXPPM=@CNSFCXPPM) 
									ELSE 0 
								END)
	FROM FCXPPM WHERE CNSFCXPPM=@CNSFCXPPM

	SELECT @CODCAJA1   = CAJA,@IDSEDE=IDSEDE FROM UBEQ WHERE SYS_COMPUTERNAME = @SYS_COMPUTERNAME
	SELECT @TIPOEGRESO = TIPOEGRESO FROM CAJ WHERE CODCAJA = @CODCAJA1
	SELECT @CODUNG=CODUNG , @CODPRG=CODPRG FROM SED WHERE IDSEDE = @IDSEDE


	 IF @TIPOEGRESO = '' OR @TIPOEGRESO IS NULL OR @TIPOEGRESO<>DBO.FNK_VALORVARIABLE('IDCJTECXP')
	 BEGIN
		SELECT @TIPOEGRESO = DBO.FNK_VALORVARIABLE('IDCJTECXP')
	 END
	 PRINT '@TIPOEGRESO='+@TIPOEGRESO
	 IF ISNULL(@IDTERCERO_AFAVOR,'')='' 
	 BEGIN
		SET @SW = 0
		DECLARE CUR_PAGOS CURSOR FOR
		SELECT FCXP.NOREFERENCIA, FCXPP.CNSFCXPP, FCXPP.CNSFCXP, FCXPP.ABONO, FCXP.IDTERCERO, FCXPPM.VALOR, 
			   TRIM(FCXPPM.CODCAJA), TER.RAZONSOCIAL,COALESCE(FCXPPM.FECHA,FCXPPM.F_CONTABLE), 
			   CASE WHEN COALESCE(FCXPP.OBSERVACION,'')='' THEN FCXPPM.OBSERVACION ELSE FCXPP.OBSERVACION END, 
			   FCXP.CODUNG, FCXP.CODPRG
		FROM   FCXP,FCXPPM,TER,FCXPP
		WHERE  FCXPPM.CNSFCXPPM = @CNSFCXPPM 
		AND    FCXPPM.CNSFCXPPM = FCXPP.CNSFCXPPM 
		AND    FCXPP.CNSFCXP    = FCXP.CNSFCXP 
		AND    TER.IDTERCERO    = FCXP.IDTERCERO 
		AND    FCXPP.ESTADO    <> 'A'
		ORDER BY FCXP.IDTERCERO, FCXP.NOREFERENCIA
	 END
	 ELSE
	 BEGIN
		SET @SW = 1
		DECLARE CUR_PAGOS CURSOR FOR
		SELECT FCXP.NOREFERENCIA, FCXPP.CNSFCXPP, FCXPP.CNSFCXP, FCXPP.ABONO, FCXPPM.IDTERCERO_AFAVOR, FCXPPM.VALOR, 
			   TRIM(FCXPPM.CODCAJA), TER.RAZONSOCIAL,COALESCE(FCXPPM.FECHA,FCXPPM.F_CONTABLE), 
			   CASE WHEN COALESCE(FCXPP.OBSERVACION,'')='' THEN FCXPPM.OBSERVACION ELSE FCXPP.OBSERVACION END, 
			   FCXP.CODUNG, FCXP.CODPRG
		FROM   FCXP,FCXPPM,TER,FCXPP
		WHERE  FCXPPM.CNSFCXPPM  = @CNSFCXPPM 
		AND    FCXPPM.CNSFCXPPM  = FCXPP.CNSFCXPPM 
		AND    FCXPP.CNSFCXP     = FCXP.CNSFCXP 
		AND    TER.IDTERCERO     = FCXPPM.IDTERCERO_AFAVOR 
		AND    FCXPP.ESTADO     <> 'A'
		ORDER BY FCXPPM.IDTERCERO_AFAVOR,FCXP.NOREFERENCIA
	 END
  
	 OPEN CUR_PAGOS
 
	 FETCH NEXT FROM CUR_PAGOS
	 INTO @N_FACTURA,@CNSFCXPP,@CNSFCXP,@SALDO,@IDTERCERO,@VALORTOTAL,@CODCAJA,@NOMBRECLIENTE,@FECHAPAGO, @OBSERVACION, @CODUNG, @CODPRG

	 SELECT @CNSACJ = CNSACJ FROM CAJ WHERE CODCAJA = @CODCAJA
	 SET    @IDTERCERO_ANT = ''

	 WHILE @@FETCH_STATUS = 0
	 BEGIN  
	  IF (@PORPAGAR > 0 AND @SW = 0) OR (@SW = 1)
	  BEGIN
	   IF @SALDO>@PORPAGAR 
	   Begin
		  SET @SALDO=@PORPAGAR
	   End
   
	   IF @IDTERCERO_ANT<>@IDTERCERO
	   BEGIN
		  PRINT @IDTERCERO_ANT+' '+@IDTERCERO
      
		  SET @VALORTOTAL=(SELECT SUM(ABONO) FROM FCXPP
						   WHERE CNSFCXPPM=@CNSFCXPPM AND 
								 IDTERCERO=(CASE WHEN @SW=0 THEN @IDTERCERO ELSE IDTERCERO END) AND 
								 ESTADO<>'A')
		  PRINT @VALORTOTAL
      
		  IF @VALORTOTAL>@PORPAGAR
		  Begin
			 SET @VALORTOTAL=@PORPAGAR
		  End
      
		  PRINT @VALORTOTAL
      
		  SET @IDTERCERO_ANT=@IDTERCERO
		  SET @ITEM=0
      
		  SET @CNSFACJ=SPACE(20)
		  EXEC SPK_GENCONSECUTIVO @COMPANIA,@CODCAJA,'@FCJE',@CNSFACJ OUTPUT
		  SELECT @CNSFACJ = 'E' + REPLACE(SPACE(8 - LEN(@CNSFACJ))+LTRIM(RTRIM(@CNSFACJ)),SPACE(1),0)
      
		  PRINT @CODCAJA+' '+@CNSFACJ
		  SELECT @CODUNG=CODUNG , @CODPRG=CODPRG FROM SED WHERE IDSEDE = @IDSEDE

		  INSERT INTO FCJ (CNSFACJ,CODCAJA,CODTURNO_GEN,CODTURNO_TRA,CLASE_FAC,NOADMISION,NOPRESTACION,IDPLAN,
						   VALORTOTAL,COMPANIA,IDAFILIADO,CERRADA,FECHA,TIPO,PROCEDENCIA,N_FACTURA,IDTERCERO,
						   NOMBRECLIENTE,CNSACJ,N_RECIBO,ESTADO,IMPRESO,MARCACONT,CONTABILIZADA,NROCOMPROBANTE,
						   AREAPRESTACION,CCOSTO,SUBCCOSTO,CLASER,IDCAUSALANUL,USUARIOANUL,SYS_COMPUTERNAMEANUL,
						   FECHAANU,TCNSFACJ,IDENTIFICADOR,SYS_COMPUTERNAME,OBSERVACION,RECAUDO,ENPAGOS,TIPOEGRESO,
						   IMPRESOTRAS,BANCO,SUCURSAL,CTA_BCO,USUARIO,DEAPERTURA,IMPRESOCHEQUE, CODUNG, CODPRG,
						   ARCHIVADO, DEVUELTO)
		  SELECT  @CNSFACJ, @CODCAJA, '' ,'' , 'PAGO', CASE DBO.FNK_VALORVARIABLE('IDTIPOCXP_DEFAULT') 
															WHEN 'ARS' THEN @CNSFCXPPM 
															ELSE '' 
													   END, 
				   '', '',
				  @VALORTOTAL,@COMPANIA,'',0,DBO.FNK_FECHA_SIN_MLS(@FECHAPAGO),'INTERNO','CAJA','',@IDTERCERO,
				  @NOMBRECLIENTE,@CNSACJ,'','P',0,0,0,'',
				  NULL,NULL,'','C','','','', NULL,'','',@SYS_COMPUTERNAME,
				  CASE DBO.FNK_VALORVARIABLE('IDTIPOCXP_DEFAULT') 
					   WHEN 'ARS' THEN ' -- '+@CNSFCXPPM + '--' 
					   ELSE ''
				  END + @OBSERVACION,
				  0,0,@TIPOEGRESO,
				  0,'','','',@USUARIO,0,0, @CODUNG, @CODPRG, 0, 0
	   END
   
	   SET @ITEM=@ITEM+1
   
	   -- MOD.JQUIROGA 20090811 
	   INSERT INTO FCJD (CNSFACJ,ITEM,CONCEPTO,AREAFUNCIONAL,VALORUNITARIO,CANTIDAD,VALORTOTAL,IDSERVICIO,
						 CODCAJA,N_RECIBO,TDESCUENTO,TIPODCTO,VLRDESCUENTO,DCTO)
	   SELECT @CNSFACJ,@ITEM,@TIPOEGRESO,'',@SALDO,1,@SALDO,@CNSFCXPP,@CODCAJA,'',0,'N',0,0
     
	   PRINT 'Actualizando FCXPP...'
	   UPDATE FCXPP SET ESTADO='C',USUARIOCONF=@USUARIO,FECHACONF=DBO.FNK_FECHA_SIN_MLS(GETDATE()),
						SYS_COMPUTERNAME=@SYS_COMPUTERNAME,CNSFACJ=@CNSFACJ,CODCAJA=@CODCAJA
	   WHERE CNSFCXPP=@CNSFCXPP
   
	   SET @PORPAGAR = @PORPAGAR - @SALDO
		  /****** CAMADO *** 11/05/2009 -- REQ: 1592 ***/			 	 
				UPDATE FCXP SET SALDO=SALDO-@SALDO, VLR_ABONOS=VLR_ABONOS+@SALDO WHERE CNSFCXP=@CNSFCXP           
		  /*********************************************/
	  END
	  ELSE
		 UPDATE FCXPP SET ESTADO='P',USUARIOCONF=@USUARIO,FECHACONF=DBO.FNK_FECHA_SIN_MLS(GETDATE()),
						  SYS_COMPUTERNAME=@SYS_COMPUTERNAME,CNSFACJ='',CODCAJA=''
		 WHERE CNSFCXPP=@CNSFCXPP
   
		FETCH NEXT FROM CUR_PAGOS
		INTO @N_FACTURA,@CNSFCXPP,@CNSFCXP,@SALDO,@IDTERCERO,@VALORTOTAL,@CODCAJA,@NOMBRECLIENTE,@FECHAPAGO, @OBSERVACION, @CODUNG, @CODPRG
	 END
   
	 CLOSE CUR_PAGOS
	 DEALLOCATE CUR_PAGOS

	 UPDATE FCXPPM SET
		 USUARIOCONF = @USUARIO,
		 FECHACONF   = DBO.FNK_FECHA_SIN_MLS(GETDATE()),
		 ESTADO      = 'C'
	 WHERE CNSFCXPPM=@CNSFCXPPM
END
