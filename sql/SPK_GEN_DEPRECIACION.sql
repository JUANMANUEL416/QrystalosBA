CREATE OR ALTER PROCEDURE DBO.SPK_GEN_DEPRECIACION @IDACTIVO VARCHAR(20)
	WITH ENCRYPTION
AS
DECLARE @MAXITEM INT
DECLARE @MESES INT
DECLARE @MESESADEPRECIAR INT
DECLARE @MESESDEPRECIADOS INT
DECLARE @FECHA DATETIME
DECLARE @VALORADEPRECIAR DECIMAL(15, 6)
DECLARE @PRECIOCOMPRA DECIMAL(14, 2)
DECLARE @VALORSALVAMENTO DECIMAL(14, 2)
DECLARE @PRECIOCOMERCIAL DECIMAL(14, 2)
DECLARE @DEPACUMHISTORICA DECIMAL(14, 2)
DECLARE @DEPACUMDIFERIDA DECIMAL(14, 2)
DECLARE @CUENTA VARCHAR(16)
DECLARE @AJUSTEACUMULADO DECIMAL(12, 2)
DECLARE @MESDERE INT
DECLARE @VLRDEPRE DECIMAL(14, 2)
DECLARE @SI BIT

BEGIN
	SELECT @SI = COALESCE(SI, 0)
	FROM IACT
	WHERE IDACTIVO = @IDACTIVO

	IF @SI = 0
	BEGIN
		UPDATE IACT
		SET MESESADEPRECIAR = IACTT.VIDAUTIL, VALORSALVAMENTO = COALESCE(IACT.VALORSALVAMENTO, IACTT.BASEDEPRECIABLE, 0), DEPACUMHISTORICA = 0, DEPACUMDIFERIDA = 0, 
			MESESDEPRECIADOS = 0, DEPRECIABLE = CASE 
				WHEN COALESCE(IACTT.VIDAUTIL, 0) > 0
					THEN 1
				ELSE 0
				END
		FROM IACT
		INNER JOIN IACTT ON IACT.IDTIPOACTIVO = IACTT.IDTIPOACTIVO
		WHERE IACT.IDACTIVO = @IDACTIVO

		SELECT @MESDERE = COUNT(*), @VLRDEPRE = SUM(VALORDEPRECIADO)
		FROM IACTD
		WHERE IDACTIVO = @IDACTIVO AND COALESCE(CONTABILIZADA, 0) = 1

		UPDATE IACT
		SET DEPACUMDIFERIDA = (PRECIOCOMPRA - COALESCE(VALORSALVAMENTO, 0)) - COALESCE(@VLRDEPRE, 0), MESESDEPRECIADOS = COALESCE(@MESDERE, 0), 
			DEPACUMHISTORICA = COALESCE(@VLRDEPRE, 0)
		WHERE IACT.IDACTIVO = @IDACTIVO

		IF @MESESADEPRECIAR - @MESESDEPRECIADOS <= 0
		BEGIN
			RAISERROR ('Activo Depreciado Completamente no debo hacer nada', 16, 1)

			RETURN
		END
	END

	SELECT @MESESDEPRECIADOS = ISNULL(MESESDEPRECIADOS, 0), @MESESADEPRECIAR = ISNULL(MESESADEPRECIAR, 0), @FECHA = COALESCE((
				SELECT MAX(FECHA)
				FROM IACTD
				WHERE IDACTIVO = @IDACTIVO AND CONTABILIZADA = 1 AND CLASE = 'LOCAL'
				), FECHACOMPRA), @PRECIOCOMPRA = ISNULL(PRECIOCOMPRA, 0), @DEPACUMHISTORICA = ISNULL(DEPACUMHISTORICA, 0), @VALORSALVAMENTO = ISNULL(
			VALORSALVAMENTO, 0), @PRECIOCOMERCIAL = ISNULL(PRECIOCOMERCIAL, 0), @DEPACUMHISTORICA = ISNULL(DEPACUMHISTORICA, 0), @DEPACUMDIFERIDA = ISNULL(
			DEPACUMDIFERIDA, 0), @AJUSTEACUMULADO = ISNULL(AJUSTEACUMULADO, 0), @CUENTA = CUENTA
	FROM IACT
	WHERE IDACTIVO = @IDACTIVO AND DEPRECIABLE = 1

	PRINT '1'

	SET @MESESDEPRECIADOS = ISNULL(@MESESDEPRECIADOS, 0)
	SET @MESES = @MESESDEPRECIADOS
	SET @VALORADEPRECIAR = (@PRECIOCOMPRA - @VALORSALVAMENTO) / (@MESESADEPRECIAR)

	PRINT 'BORRO LO QUE NO ESTA CONTABILIZADO'

	DELETE IACTD
	WHERE IDACTIVO = @IDACTIVO AND ITEM > @MESESDEPRECIADOS AND CONTABILIZADA = 0

	SELECT @MAXITEM = ISNULL(MAX(COALESCE(ITEM, 0)), 0)
	FROM IACTD
	WHERE IDACTIVO = @IDACTIVO

	IF @MAXITEM <> @MESES
	BEGIN
		SELECT @MESES = @MAXITEM
	END

	IF @SI = 1 AND @MAXITEM = 0
	BEGIN
		SET @MESES = @MESESDEPRECIADOS
	END

	-- SELECT @FECHA=DATEADD(MONTH,@MESES,@FECHA)
	PRINT '@FECHA =' + CONVERT(VARCHAR, @FECHA, 103)

	WHILE @MESES < @MESESADEPRECIAR
	BEGIN
		SET @FECHA = DATEADD(MONTH, 1, @FECHA)
		SET @MESES = @MESES + 1
		SET @DEPACUMHISTORICA = @DEPACUMHISTORICA + @VALORADEPRECIAR
		SET @DEPACUMDIFERIDA = @PRECIOCOMPRA - @DEPACUMHISTORICA

		IF @DEPACUMDIFERIDA <= 0
		BEGIN
			BREAK
		END

		IF @DEPACUMDIFERIDA <= @VALORADEPRECIAR
		BEGIN
			SELECT @VALORADEPRECIAR = @DEPACUMDIFERIDA

			SELECT @DEPACUMHISTORICA = @DEPACUMHISTORICA + @VALORADEPRECIAR

			SELECT @DEPACUMDIFERIDA = @PRECIOCOMPRA - @DEPACUMHISTORICA

			INSERT INTO IACTD (
				IDACTIVO, ITEM, FECHA, VALORDEPRECIADO, PRECIOCOMERCIAL, DEPACUMHISTORICA, DEPACUMDIFERIDA, AJUSTEACUMULADO, CUENTA, CONTABILIZADA, MARCACONT, 
				NROCOMPROBANTE, CLASE
				)
			SELECT @IDACTIVO, @MESES, @FECHA, @VALORADEPRECIAR, @PRECIOCOMERCIAL, @DEPACUMHISTORICA, @DEPACUMDIFERIDA, @AJUSTEACUMULADO, @CUENTA, 0, 0, '', 'Local'

			BREAK
		END

		INSERT INTO IACTD (
			IDACTIVO, ITEM, FECHA, VALORDEPRECIADO, PRECIOCOMERCIAL, DEPACUMHISTORICA, DEPACUMDIFERIDA, AJUSTEACUMULADO, CUENTA, CONTABILIZADA, MARCACONT, 
			NROCOMPROBANTE, CLASE
			)
		SELECT @IDACTIVO, @MESES, @FECHA, @VALORADEPRECIAR, @PRECIOCOMERCIAL, @DEPACUMHISTORICA, @DEPACUMDIFERIDA, @AJUSTEACUMULADO, @CUENTA, 0, 0, '', 'Local'
	END
END
