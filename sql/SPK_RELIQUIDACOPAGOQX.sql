IF EXISTS (SELECT name FROM sysobjects 
         WHERE name = 'SPK_RELIQUIDACOPAGOQX' AND type = 'P')
   DROP PROCEDURE SPK_RELIQUIDACOPAGOQX

GO
CREATE PROCEDURE DBO.SPK_RELIQUIDACOPAGOQX @NOADMISIONRLQ VARCHAR(16)  
WITH ENCRYPTION
AS  
DECLARE 
	@NOADMISION		VARCHAR(16),
	@NOPRESTACION	VARCHAR(16),
	@NOITEM			INT,
	@COPAGONOAUT	VARCHAR(20),
	@FIX			INT,
	@FIX_TO			INT,
    @COPAGOVALOR    DECIMAL(14,2)
DECLARE @HPRED TABLE (
	NOADMISION	 VARCHAR(16),
	NOPRESTACION VARCHAR(16),
	NOITEM		 INT
)
BEGIN  
	  PRINT 'ENTRE A SPK_RELIQUIDACOPAGOQX'	
     UPDATE HPRED SET VALORCOPAGO = 0 , VALORPCOMP = 0, VALORCOPAGONORMAL = 0, VALOREXCEDENTE = VALOR*CANTIDAD
     FROM  HPRE INNER JOIN HPRED ON HPRED.NOPRESTACION = HPRE.NOPRESTACION 
     AND   HPRE.NOADMISION = @NOADMISIONRLQ
	  AND   COALESCE(HPRE.CERRADA,0) <> 1 -- ADD. JQUIROGA 20090416
	  AND   COALESCE(HPRE.CIRUGIA,'') <> 'SI'
     AND   COALESCE(HPRED.FACTURADA,0)=0
     
     UPDATE HPRE SET VALORCOPAGO = 0, VALORPCOMP = 0, VALOREXEDENTE = VALORTOTAL
     WHERE  HPRE.NOADMISION = @NOADMISIONRLQ
     AND    ISNULL(HPRE.CERRADA,0)   <> 1 -- ADD. JQUIROGA 20090416
     AND    EXISTS (SELECT 1 FROM HPRED WHERE HPRE.NOPRESTACION=HPRED.NOPRESTACION AND  COALESCE(FACTURADA,0)=0)
               
     SELECT @COPAGONOAUT=COPAGONOAUTORIZACION, @COPAGOVALOR=COPAGOVALOR  FROM HADM WHERE NOADMISION=@NOADMISIONRLQ 
     IF @COPAGONOAUT<>'' AND ISNULL(@COPAGOVALOR,0)>0 AND dbo.FNK_VALORVARIABLE('IXCOUNTRY')<>'PERU'
     BEGIN  
        PRINT 'VOY A SPK_COPAGOHAQX CON @COPAGONOAUTORIZACION='+@COPAGONOAUT
        EXEC SPK_COPAGOHAQX @NOADMISIONRLQ
     END  
     ELSE  
     BEGIN                                    
        --PRESTACIONES CON DETALLE--
		INSERT INTO @HPRED (NOADMISION, NOPRESTACION, NOITEM)
        SELECT HPRE.NOADMISION, HPRED.NOPRESTACION, HPRED.NOITEM  
        FROM   HPRE INNER JOIN HPRED ON HPRE.NOPRESTACION = HPRED.NOPRESTACION  
        WHERE  HPRE.NOADMISION = @NOADMISIONRLQ  
				AND ISNULL(HPRE.CERRADA,0) <> 1 
				AND COALESCE(HPRED.FACTURADA,0)=0
             
		SELECT @FIX=1, @FIX_TO=COUNT(1) FROM @HPRED
        WHILE @FIX <= @FIX_TO
        BEGIN 
			SELECT @NOADMISION=NOADMISION, @NOPRESTACION=NOPRESTACION, @NOITEM=NOITEM FROM @HPRED WHERE ID=@FIX
            EXEC SPK_COPAGOQX @NOADMISION, @NOPRESTACION, @NOITEM 
			SET @FIX += 1
        END    

        --PRESTACIONES SIN DETALLES--  
		UPDATE HPRE SET VALORTOTAL=0, VALORCOPAGO=0, VALORPCOMP=0, VALOREXEDENTE=0
        WHERE NOADMISION=@NOADMISIONRLQ AND NOT EXISTS (SELECT 1 FROM HPRED WHERE HPRE.NOPRESTACION=HPRED.NOPRESTACION)
     END  
END
