/*
  CEM — 01CM000873: neto det -0,01 vs cab (última línea con IVA).
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @CNSFCXP varchar(20) = N'01CM000873';

BEGIN TRAN;

UPDATE D
SET VLR_NETO = CONVERT(decimal(18, 2), D.VLR_NETO - 0.01)
FROM dbo.FCXPD D
WHERE D.CNSFCXP = @CNSFCXP
  AND D.ITEM = (SELECT MAX(ITEM) FROM dbo.FCXPD WHERE CNSFCXP = @CNSFCXP);

IF ABS(
  (SELECT VLR_NETO FROM dbo.FCXP WHERE CNSFCXP = @CNSFCXP)
  - (SELECT SUM(VLR_NETO) FROM dbo.FCXPD WHERE CNSFCXP = @CNSFCXP)
) > 0.001
BEGIN
  ROLLBACK TRAN;
  THROW 55321, '873 sigue sin cuadrar cab/det.', 1;
END;

COMMIT TRAN;

SELECT N'01CM000873' AS CNSFCXP,
  CONVERT(decimal(18, 2), P.VLR_NETO) AS NETO_CAB,
  CONVERT(decimal(18, 2), SUM(D.VLR_NETO)) AS NETO_DET
FROM FCXP P JOIN FCXPD D ON D.CNSFCXP = P.CNSFCXP
WHERE P.CNSFCXP = @CNSFCXP
GROUP BY P.VLR_NETO;
