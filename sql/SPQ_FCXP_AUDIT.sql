CREATE OR ALTER PROCEDURE DBO.SPQ_FCXP_AUDIT @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
SET DATEFORMAT dmy
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE  @PARAMETROS NVARCHAR(MAX)			,@MODELO VARCHAR(100)			   ,@METODO VARCHAR(100)
		,@USUARIO VARCHAR(12)				   ,@COMPANIA VARCHAR(2)		      ,@IDSEDE      VARCHAR(5)		
      ,@SYS_COMPUTERNAME VARCHAR(200)     ,@DATOS    VARCHAR(MAX)
      ,@CNSFCXP  VARCHAR(20)              ,@SQL VARCHAR(20)                ,@ITEM SMALLINT
      ,@CLASE VARCHAR(20)                 ,@VLRGLOSA DECIMAL(14,2)         ,@VLRLEVANTA DECIMAL(14,2)
      
BEGIN
	SELECT *
	INTO #JSON
	FROM OPENJSON(@json) WITH (
			MODELO VARCHAR(100) '$.MODELO'
			,METODO VARCHAR(100) '$.METODO'
			,USUARIO VARCHAR(12) '$.USUARIO'
			,PARAMETROS NVARCHAR(MAX) AS JSON
	)

	SELECT   @MODELO = MODELO			,@METODO = METODO
			,@PARAMETROS = PARAMETROS	,@USUARIO = USUARIO
	FROM #JSON

   SELECT @IDSEDE=COALESCE(UBEQ.IDSEDE,USUSU.IDSEDE),@COMPANIA=COALESCE(UBEQ.COMPANIA,USUSU.COMPANIA),  
          @SYS_COMPUTERNAME=COALESCE(USUSU.SYS_ComputerName,HOST_NAME())   
   FROM USUSU LEFT JOIN UBEQ ON USUSU.SYS_ComputerName=UBEQ.SYS_ComputerName
    WHERE USUSU.USUARIO=@USUARIO
    IF @METODO='CERRAR_SIN_GLOSA'     
    BEGIN         
       SELECT @CNSFCXP=CNSFCXP        
       FROM   OPENJSON (@PARAMETROS)
       WITH (           
       CNSFCXP  VARCHAR(20)   '$.CNSFCXP'
       )
       IF EXISTS(SELECT * FROM FCXPS WHERE CNSFCXP=@CNSFCXP)
       BEGIN
         INSERT INTO @TBLERRORES(ERROR)
         SELECT 'Cuenta por pagar en proceso de Auditoria, No se puede Continuar'
       END
       BEGIN TRY           
             UPDATE FCXP SET AUDITADO=1,USUAUDITA=@USUARIO WHERE CNSFCXP=@CNSFCXP              
       END TRY
       BEGIN CATCH
               INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
       END CATCH
       IF(SELECT COUNT(*) FROM @TBLERRORES)>0
       BEGIN
          SELECT 'KO' OK, ERROR FROM @TBLERRORES
           RETURN
       END
       SELECT 'OK' OK 
       RETURN 
    END  
    IF @METODO='IMPRIMIR_GLOSA'     
    BEGIN   

       SELECT @CNSFCXP=CNSFCXP,@ITEM=ITEM,@CLASE=CLASE      
       FROM   OPENJSON (@PARAMETROS)
       WITH (           
       CNSFCXP   VARCHAR(20)   '$.CNSFCXP ',
       ITEM  VARCHAR(20)   '$.ITEM',
       CLASE  VARCHAR(20)   '$.CLASE'
       )
       
       SELECT 'OK'OK,  FCXP.CNSFCXP,DBO.FNK_FECHA_DDMMAA(FCXP.F_FACTURAREF)F_FACTURA,DBO.FNK_FECHA_DDMMAA(FCXPDBCR.FECHA)F_NOTA,
       TER.NIT,TER.RAZONSOCIAL,FCXP.NOREFERENCIA
       FROM FCXP INNER JOIN TER ON FCXP.IDTERCERO=TER.IDTERCERO
                 INNER JOIN FCXPDBCR ON FCXP.CNSFCXP=FCXPDBCR.CNSFCXP AND FCXPDBCR.ITEM=@ITEM
       WHERE FCXP.CNSFCXP=@CNSFCXP

       SELECT DOCUMENTO,NOMBREP,VLRITEM,SALDO,VRLEVANTADO,USULEVANTA,OBSERVACION,OBSLEVANTA
       FROM FCXPS
       WHERE CNSFCXP=@CNSFCXP
       AND @ITEM=CASE WHEN @CLASE='GLOSA' THEN ITEMNDB ELSE ITEMNCR END
    END  
    
    IF @METODO='IMPRIMIR_CONCI'     
    BEGIN   
       DECLARE @ITEM_CONCI SMALLINT
       DECLARE @CLASE_CONCI VARCHAR(20)
       SELECT @CNSFCXP=CNSFCXP,@ITEM_CONCI=ITEM,@CLASE_CONCI=CLASE      
       FROM   OPENJSON (@PARAMETROS)
       WITH (           
       CNSFCXP   VARCHAR(20)   '$.CNSFCXP ',
       ITEM  VARCHAR(20)   '$.ITEM',
       CLASE  VARCHAR(20)   '$.CLASE'
       )
       
       SELECT 'OK'OK,  FCXP.CNSFCXP,DBO.FNK_FECHA_DDMMAA(FCXP.F_FACTURAREF)F_FACTURA,DBO.FNK_FECHA_DDMMAA(FCXPDBCR.FECHA)F_NOTA,
       TER.NIT,TER.RAZONSOCIAL,FCXP.NOREFERENCIA
       FROM FCXP INNER JOIN TER ON FCXP.IDTERCERO=TER.IDTERCERO
                 INNER JOIN FCXPDBCR ON FCXP.CNSFCXP=FCXPDBCR.CNSFCXP AND FCXPDBCR.ITEM=@ITEM_CONCI
       WHERE FCXP.CNSFCXP=@CNSFCXP

       SELECT DOCUMENTO,NOMBREP,VLRITEM,SALDO,VRLEVANTADO,USULEVANTA,OBSERVACION,OBSLEVANTA
       FROM FCXPS
       WHERE CNSFCXP=@CNSFCXP
       AND @ITEM_CONCI=CASE WHEN @CLASE_CONCI='GLOSA' THEN ITEMNDB ELSE ITEMNCR END
    END
    
    IF @METODO='CRUD_FCXPS'
    BEGIN
       DECLARE @PROCESO VARCHAR(20)
       DECLARE @ITEM_FCXPS SMALLINT
       DECLARE @FECHA_FCXPS DATETIME
       DECLARE @OBSERVACION_FCXPS VARCHAR(MAX)
       DECLARE @IDDEP_FCXPS VARCHAR(10)
       DECLARE @ESTADO_FCXPS VARCHAR(20)
       DECLARE @VLRITEM_FCXPS MONEY
       DECLARE @SALDO_FCXPS MONEY
       DECLARE @VRLEVANTADO_FCXPS MONEY
       DECLARE @USUARIO_FCXPS VARCHAR(12)
       DECLARE @USULEVANTA_FCXPS VARCHAR(12)
       DECLARE @OBSLEVANTA_FCXPS VARCHAR(MAX)
       DECLARE @ITEMNDB_FCXPS SMALLINT
       DECLARE @ITEMNCR_FCXPS SMALLINT
       DECLARE @DOCUMENTO_FCXPS VARCHAR(50)
       DECLARE @NOMBREP_FCXPS VARCHAR(200)
       
       SELECT @CNSFCXP=CNSFCXP
              ,@PROCESO=PROCESO
              ,@ITEM_FCXPS=ITEM
              ,@FECHA_FCXPS=DBO.FNK_GETDATE()
              ,@OBSERVACION_FCXPS=OBSERVACION
              ,@IDDEP_FCXPS=IDDEP
              ,@ESTADO_FCXPS=ESTADO
              ,@VLRITEM_FCXPS=VLRITEM
              ,@SALDO_FCXPS=SALDO
              ,@VRLEVANTADO_FCXPS=VRLEVANTADO
              ,@USUARIO_FCXPS=USUARIO
              ,@USULEVANTA_FCXPS=USULEVANTA
              ,@OBSLEVANTA_FCXPS=OBSLEVANTA
              ,@ITEMNDB_FCXPS=ITEMNDB
              ,@ITEMNCR_FCXPS=ITEMNCR
              ,@DOCUMENTO_FCXPS=DOCUMENTO
              ,@NOMBREP_FCXPS=NOMBREP
       FROM OPENJSON(@PARAMETROS, '$.datoFCXPS')
       WITH (
              CNSFCXP VARCHAR(20) '$.CNSFCXP',
              PROCESO VARCHAR(20) '$.PROCESO',
              ITEM SMALLINT '$.ITEM',
              OBSERVACION VARCHAR(MAX) '$.OBSERVACION',
              IDDEP VARCHAR(10) '$.IDDEP',
              ESTADO VARCHAR(20) '$.ESTADO',
              VLRITEM MONEY '$.VLRITEM',
              SALDO MONEY '$.SALDO',
              VRLEVANTADO MONEY '$.VRLEVANTADO',
              USUARIO VARCHAR(12) '$.USUARIO',
              USULEVANTA VARCHAR(12) '$.USULEVANTA',
              OBSLEVANTA VARCHAR(MAX) '$.OBSLEVANTA',
              ITEMNDB SMALLINT '$.ITEMNDB',
              ITEMNCR SMALLINT '$.ITEMNCR',
              DOCUMENTO VARCHAR(50) '$.DOCUMENTO',
              NOMBREP VARCHAR(200) '$.NOMBREP'
       )
       
       IF @PROCESO='Nuevo'
       BEGIN
          BEGIN TRY
             -- Obtener el siguiente ITEM
             SELECT @ITEM_FCXPS=ISNULL(MAX(ITEM),0)+1
             FROM FCXPS
             WHERE CNSFCXP=@CNSFCXP
             
             INSERT INTO FCXPS (CNSFCXP,ITEM,FECHA,OBSERVACION,IDDEP,ESTADO,VLRITEM,SALDO,VRLEVANTADO,USUARIO,SYS_COMPUTERNAME,USULEVANTA,OBSLEVANTA,ITEMNDB,ITEMNCR,DOCUMENTO,NOMBREP)
             VALUES (@CNSFCXP,@ITEM_FCXPS,@FECHA_FCXPS,@OBSERVACION_FCXPS,@IDDEP_FCXPS,@ESTADO_FCXPS,@VLRITEM_FCXPS,@SALDO_FCXPS,@VRLEVANTADO_FCXPS,@USUARIO_FCXPS,@SYS_COMPUTERNAME,@USULEVANTA_FCXPS,@OBSLEVANTA_FCXPS,@ITEMNDB_FCXPS,@ITEMNCR_FCXPS,@DOCUMENTO_FCXPS,@NOMBREP_FCXPS)
          END TRY
          BEGIN CATCH
             INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
          END CATCH
       END
       ELSE IF @PROCESO='Editar'
       BEGIN
          BEGIN TRY
             UPDATE FCXPS SET
                FECHA=@FECHA_FCXPS,
                OBSERVACION=@OBSERVACION_FCXPS,
                IDDEP=@IDDEP_FCXPS,
                ESTADO=@ESTADO_FCXPS,
                VLRITEM=@VLRITEM_FCXPS,
                SALDO=@SALDO_FCXPS,
                VRLEVANTADO=@VRLEVANTADO_FCXPS,
                USUARIO=@USUARIO_FCXPS,
                USULEVANTA=CASE WHEN @ESTADO_FCXPS='Conci' THEN @USUARIO_FCXPS ELSE @USULEVANTA_FCXPS END,
                OBSLEVANTA=@OBSLEVANTA_FCXPS,
                ITEMNDB=@ITEMNDB_FCXPS,
                ITEMNCR=@ITEMNCR_FCXPS,
                DOCUMENTO=@DOCUMENTO_FCXPS,
                NOMBREP=@NOMBREP_FCXPS
             WHERE CNSFCXP=@CNSFCXP AND ITEM=@ITEM_FCXPS
          END TRY
          BEGIN CATCH
             INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
          END CATCH
       END
       IF(SELECT COUNT(*) FROM @TBLERRORES)>0
       BEGIN
          SELECT 'KO' OK, ERROR FROM @TBLERRORES
          RETURN
       END
       SELECT @VLRGLOSA=SUM(VLRITEM),@VLRLEVANTA=SUM(COALESCE(VRLEVANTADO,0)) FROM FCXPS WHERE CNSFCXP=@CNSFCXP
       PRINT 'ACTUALIZO FCXPDBCR'
       UPDATE FCXPDBCR SET VALOR=CASE WHEN  TIPO='DB' THEN @VLRGLOSA ELSE @VLRLEVANTA END  
       WHERE CNSFCXP=@CNSFCXP 
       AND ITEM=CASE WHEN @ESTADO_FCXPS='Glosa' THEN @ITEMNDB_FCXPS ELSE  @ITEMNCR_FCXPS END

       SELECT 'OK' OK
       RETURN
    END
    IF @METODO='ELIMINAR_FCXPS'
    BEGIN
       DECLARE @ITEM_DEL SMALLINT
       SELECT @CNSFCXP=CNSFCXP,@ITEM_DEL=ITEM
       FROM OPENJSON(@PARAMETROS)
       WITH (
              CNSFCXP VARCHAR(20) '$.CNSFCXP',
              ITEM SMALLINT '$.ITEM'
       )
       
       BEGIN TRY
          DELETE FROM FCXPS
          WHERE CNSFCXP=@CNSFCXP AND ITEM=@ITEM_DEL
       END TRY
       BEGIN CATCH
          INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
       END CATCH
       
       IF(SELECT COUNT(*) FROM @TBLERRORES)>0
       BEGIN
          SELECT 'KO' OK, ERROR FROM @TBLERRORES
          RETURN
       END
       SELECT 'OK' OK
       RETURN
    END
    
    IF @METODO='CERRAR_GLOSA'
    BEGIN
       SELECT @CNSFCXP=CNSFCXP,@ITEM=item
       FROM OPENJSON(@PARAMETROS)
       WITH (
          CNSFCXP VARCHAR(20) '$.CNSFCXP',
          ITEM  SMALLINT   '$.ITEM'
       )
       
       BEGIN TRY
          UPDATE FCXPS SET ESTADO='Glosa'
          WHERE CNSFCXP=@CNSFCXP AND ESTADO='Nuevo'
          AND ITEMNDB=@ITEM

          SELECT @SQL='EXEC SPQ_JSON''{"MODELO":"FCXP","METODO":"CONTABILIZAR_NOTACREDITO","PARAMETROS":{"CNSFCXP":"'+@CNSFCXP+'","ITEM":'+CAST(@ITEM AS VARCHAR(3))+'},"USUARIO":"'+@USUARIO+'"}'''

          EXEC (@SQL)

       END TRY
       BEGIN CATCH
          INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
       END CATCH
       
       IF(SELECT COUNT(*) FROM @TBLERRORES)>0
       BEGIN
          SELECT 'KO' OK, ERROR FROM @TBLERRORES
          RETURN
       END
       SELECT 'OK' OK
       RETURN
    END
    
    IF @METODO='CERRAR_CONCI'
    BEGIN
       SELECT @CNSFCXP=CNSFCXP
       FROM OPENJSON(@PARAMETROS)
       WITH (
              CNSFCXP VARCHAR(20) '$.CNSFCXP'
       )
       
       BEGIN TRY
          UPDATE FCXPS SET ESTADO='Conci'
          WHERE CNSFCXP=@CNSFCXP AND ESTADO='Glosa'
       END TRY
       BEGIN CATCH
          INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
       END CATCH
       
       IF(SELECT COUNT(*) FROM @TBLERRORES)>0
       BEGIN
          SELECT 'KO' OK, ERROR FROM @TBLERRORES
          RETURN
       END
       SELECT 'OK' OK
       RETURN
    END
END
