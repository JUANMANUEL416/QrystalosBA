CREATE OR ALTER PROCEDURE DBO.SPQ_CUENIIF @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
SET NOCOUNT ON;

DECLARE @PARAMETROS NVARCHAR(MAX)
DECLARE @MODELO VARCHAR(100)
DECLARE @METODO VARCHAR(100)
DECLARE @USUARIO VARCHAR(20)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @CUENTA VARCHAR(16)
DECLARE @CUENTA_ORIG VARCHAR(16)
DECLARE @NOMCUENTA VARCHAR(200)
DECLARE @TIPO VARCHAR(7)
DECLARE @NIVEL SMALLINT
DECLARE @CUENTA_SUMA VARCHAR(16)
DECLARE @CENTRO SMALLINT
DECLARE @PRODUCTO TINYINT
DECLARE @REFERENCIA SMALLINT
DECLARE @TERCERO SMALLINT
DECLARE @IMPUESTO SMALLINT
DECLARE @CORRIENTE SMALLINT
DECLARE @CLASE VARCHAR(10)
DECLARE @ESTADO VARCHAR(8)
DECLARE @IDCUENIIF INT
DECLARE @NIVEL_PADRE SMALLINT
DECLARE @CUENTA_PADRE VARCHAR(16)
DECLARE @MOVIMIENTOS INT

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@JSON) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(20) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	/* ------------------------------------------------------------------
	   GENEALOGICO
	IF @METODO = 'GENEALOGICO'
	BEGIN
		SELECT @CUENTA = LTRIM(RTRIM(CUENTA))
		FROM OPENJSON(@PARAMETROS) WITH (CUENTA VARCHAR(16) '$.CUENTA')

		IF @CUENTA IS NULL OR @CUENTA = ''
		BEGIN
			SELECT 'OK' OK, 1 AS NIVEL, CAST(NULL AS VARCHAR(16)) AS CUENTA_SUMA

			RETURN
		END

		SELECT TOP 1 @NIVEL_PADRE = NIVEL, @CUENTA_PADRE = CUENTA
		FROM DBO.FNK_GENEALOGICO_CUE_NIIF(@CUENTA)
		WHERE CUENTA <> @CUENTA
		ORDER BY CUENTA DESC

		IF @NIVEL_PADRE IS NULL OR @CUENTA_PADRE IS NULL OR LTRIM(RTRIM(@CUENTA_PADRE)) = ''
		BEGIN
			SELECT 'OK' OK, 1 AS NIVEL, CAST(NULL AS VARCHAR(16)) AS CUENTA_SUMA
		END
		ELSE
		BEGIN
			SELECT 'OK' OK, CAST(@NIVEL_PADRE + 1 AS SMALLINT) AS NIVEL, @CUENTA_PADRE AS CUENTA_SUMA
		END

		RETURN
	END

	/* ------------------------------------------------------------------
	   INSERTAR
	IF @METODO = 'INSERTAR'
	BEGIN
		SELECT @CUENTA = LTRIM(RTRIM(CUENTA)), @NOMCUENTA = LTRIM(RTRIM(NOMCUENTA)), @TIPO = LTRIM(RTRIM(TIPO)), @NIVEL = NIVEL, @CUENTA_SUMA = NULLIF(LTRIM(RTRIM(
						CUENTA_SUMA)), ''), @CENTRO = COALESCE(CENTRO, 0), @PRODUCTO = COALESCE(PRODUCTO, 0), @REFERENCIA = COALESCE(REFERENCIA, 0), @TERCERO = 
			COALESCE(TERCERO, 0), @IMPUESTO = COALESCE(IMPUESTO, 0), @CORRIENTE = COALESCE(CORRIENTE, 0), @CLASE = LTRIM(RTRIM(CLASE)), @ESTADO = LTRIM(RTRIM(ESTADO)
			)
		FROM OPENJSON(@PARAMETROS) WITH (
				CUENTA VARCHAR(16) '$.CUENTA', NOMCUENTA VARCHAR(200) '$.NOMCUENTA', TIPO VARCHAR(7) '$.TIPO', NIVEL SMALLINT '$.NIVEL', CUENTA_SUMA VARCHAR(16) 
				'$.CUENTA_SUMA', CENTRO SMALLINT '$.CENTRO', PRODUCTO TINYINT '$.PRODUCTO', REFERENCIA SMALLINT '$.REFERENCIA', TERCERO SMALLINT '$.TERCERO', 
				IMPUESTO SMALLINT '$.IMPUESTO', CORRIENTE SMALLINT '$.CORRIENTE', CLASE VARCHAR(10) '$.CLASE', ESTADO VARCHAR(8) '$.ESTADO'
				)

		IF @ESTADO IS NULL OR @ESTADO = ''
			SET @ESTADO = 'Activa'

		IF @CUENTA IS NULL OR @CUENTA = ''
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'La cuenta es obligatoria'

		IF @NOMCUENTA IS NULL OR @NOMCUENTA = ''
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'El nombre de la cuenta es obligatorio'

		IF @TIPO IS NULL OR @TIPO NOT IN ('Suma', 'Detalle')
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'El tipo debe ser Suma o Detalle'

		IF @ESTADO NOT IN ('Activa', 'Inactiva')
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'El estado debe ser Activa o Inactiva'

		IF @CLASE IS NOT NULL AND @CLASE <> '' AND @CLASE NOT IN ('CXC', 'CXP', 'OTROS')
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'La clase debe ser CXC, CXP u OTROS'

		IF @NIVEL IS NULL OR @NIVEL < 1
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'El nivel de la cuenta no es v�lido'

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		BEGIN TRY
			INSERT INTO CUENIIF (CUENTA, NOMCUENTA, TIPO, NEMONICO, CENTRO, PRODUCTO, REFERENCIA, TERCERO, IMPUESTO, ESTADO, NIVEL, CUENTA_SUMA, CLASE, CORRIENTE
				)
			VALUES (
				@CUENTA, @NOMCUENTA, @TIPO, NULL, @CENTRO, @PRODUCTO, @REFERENCIA, @TERCERO, @IMPUESTO, @ESTADO, @NIVEL, @CUENTA_SUMA, NULLIF(@CLASE, ''), 
				@CORRIENTE
				)

			SET @IDCUENIIF = SCOPE_IDENTITY()
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK, @IDCUENIIF AS IDCUENIIF

		RETURN
	END

	/* ------------------------------------------------------------------
	   EDITAR
	IF @METODO = 'EDITAR'
	BEGIN
		SELECT @IDCUENIIF = IDCUENIIF, @CUENTA = LTRIM(RTRIM(CUENTA)), @NOMCUENTA = LTRIM(RTRIM(NOMCUENTA)), @TIPO = LTRIM(RTRIM(TIPO)), @NIVEL = NIVEL, @CUENTA_SUMA = 
			NULLIF(LTRIM(RTRIM(CUENTA_SUMA)), ''), @CENTRO = COALESCE(CENTRO, 0), @PRODUCTO = COALESCE(PRODUCTO, 0), @REFERENCIA = COALESCE(REFERENCIA, 0), @TERCERO 
			= COALESCE(TERCERO, 0), @IMPUESTO = COALESCE(IMPUESTO, 0), @CORRIENTE = COALESCE(CORRIENTE, 0), @CLASE = LTRIM(RTRIM(CLASE)), @ESTADO = LTRIM(RTRIM(ESTADO
				))
		FROM OPENJSON(@PARAMETROS) WITH (
				IDCUENIIF INT '$.IDCUENIIF', CUENTA VARCHAR(16) '$.CUENTA', NOMCUENTA VARCHAR(200) '$.NOMCUENTA', TIPO VARCHAR(7) '$.TIPO', NIVEL SMALLINT '$.NIVEL'
				, CUENTA_SUMA VARCHAR(16) '$.CUENTA_SUMA', CENTRO SMALLINT '$.CENTRO', PRODUCTO TINYINT '$.PRODUCTO', REFERENCIA SMALLINT '$.REFERENCIA', TERCERO 
				SMALLINT '$.TERCERO', IMPUESTO SMALLINT '$.IMPUESTO', CORRIENTE SMALLINT '$.CORRIENTE', CLASE VARCHAR(10) '$.CLASE', ESTADO VARCHAR(8) '$.ESTADO'
				)

		IF @IDCUENIIF IS NULL
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'No se indic� el identificador de la cuenta'

		IF @ESTADO IS NULL OR @ESTADO = ''
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'Debe indicar el estado de la cuenta'

		IF @CUENTA IS NULL OR @CUENTA = ''
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'La cuenta es obligatoria'

		IF @NOMCUENTA IS NULL OR @NOMCUENTA = ''
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'El nombre de la cuenta es obligatorio'

		IF @TIPO IS NULL OR @TIPO NOT IN ('Suma', 'Detalle')
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'El tipo debe ser Suma o Detalle'

		IF @ESTADO IS NOT NULL AND @ESTADO <> '' AND @ESTADO NOT IN ('Activa', 'Inactiva')
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'El estado debe ser Activa o Inactiva'

		IF @CLASE IS NOT NULL AND @CLASE <> '' AND @CLASE NOT IN ('CXC', 'CXP', 'OTROS')
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'La clase debe ser CXC, CXP u OTROS'

		IF @NIVEL IS NULL OR @NIVEL < 1
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'El nivel de la cuenta no es v�lido'

		IF NOT EXISTS (
				SELECT 1
				FROM CUENIIF
				WHERE IDCUENIIF = @IDCUENIIF
				)
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'La cuenta NIIF no existe'

		SELECT @CUENTA_ORIG = CUENTA
		FROM CUENIIF
		WHERE IDCUENIIF = @IDCUENIIF

		IF @CUENTA_ORIG IS NOT NULL AND @CUENTA <> @CUENTA_ORIG
		BEGIN
			SELECT @MOVIMIENTOS = COUNT(*)
			FROM MCHNIIF
			WHERE CUENTA = @CUENTA_ORIG

			IF @MOVIMIENTOS > 0
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'La cuenta tiene movimientos contables. No se puede editar el c�digo de cuenta. Debe colocarla en estado Inactivo.'
		END

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		BEGIN TRY
			UPDATE CUENIIF
			SET CUENTA = @CUENTA, NOMCUENTA = @NOMCUENTA, TIPO = @TIPO, CENTRO = @CENTRO, PRODUCTO = @PRODUCTO, REFERENCIA = @REFERENCIA, TERCERO = @TERCERO, IMPUESTO = 
				@IMPUESTO, ESTADO = @ESTADO, NIVEL = @NIVEL, CUENTA_SUMA = @CUENTA_SUMA, CLASE = NULLIF(@CLASE, ''), CORRIENTE = @CORRIENTE
			WHERE IDCUENIIF = @IDCUENIIF
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK, @IDCUENIIF AS IDCUENIIF

		RETURN
	END

	/* ------------------------------------------------------------------
	   ELIMINAR
	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @IDCUENIIF = IDCUENIIF
		FROM OPENJSON(@PARAMETROS) WITH (IDCUENIIF INT '$.IDCUENIIF')

		IF @IDCUENIIF IS NULL
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'No se indic� el identificador de la cuenta'

		SELECT @CUENTA = CUENTA
		FROM CUENIIF
		WHERE IDCUENIIF = @IDCUENIIF

		IF @CUENTA IS NULL
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'La cuenta NIIF no existe'

		IF @CUENTA IS NOT NULL
		BEGIN
			SELECT @MOVIMIENTOS = COUNT(*)
			FROM MCHNIIF
			WHERE CUENTA = @CUENTA

			IF @MOVIMIENTOS > 0
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'La cuenta tiene movimientos contables. No se puede borrar. Debe colocarla en estado Inactivo.'
		END

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		BEGIN TRY
			DELETE
			FROM CUENIIF
			WHERE IDCUENIIF = @IDCUENIIF
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK

		RETURN
	END

	/* ------------------------------------------------------------------
	   CARGA_MASIVA (todo o nada)
	   1) Valida todas las filas del Excel.
	   2) Si hay alg�n error: no inserta nada y devuelve el detalle.
	   3) Solo si todas est�n correctas: inserta en orden.
	   Formato Clarion:
	   CUENTANIIF, NOMBRE CUENTA, TIPO, NEMONICO, DETALLE CCOSTO, DETALLE PRODUCTO,
	   DETALLE FACTURA (REFERENCIA), DETALLE TERCERO, ES IMPUESTO, ESTADO, NIVEL,
	   CUENTA_SUMA, CLASE
	IF @METODO = 'CARGA_MASIVA'
	BEGIN
		DECLARE @FILAS NVARCHAR(MAX)
		DECLARE @TBLCARGA TABLE (
			ORDEN INT IDENTITY(1, 1), CUENTA VARCHAR(20), NOMCUENTA VARCHAR(200), TIPO VARCHAR(20), NEMONICO VARCHAR(40), CENTRO SMALLINT, PRODUCTO SMALLINT, 
			REFERENCIA SMALLINT, TERCERO SMALLINT, IMPUESTO SMALLINT, ESTADO VARCHAR(20), CUENTA_SUMA VARCHAR(20), CLASE VARCHAR(20), NIVEL SMALLINT NULL
			)
		DECLARE @TBLERRCARGA TABLE (CUENTA VARCHAR(20), NOMCUENTA VARCHAR(200), ERROR VARCHAR(800))
		DECLARE @INSERTADOS INT = 0
		DECLARE @ERRORES_CARGA INT = 0
		DECLARE @LENC INT
		DECLARE @NEMONICO VARCHAR(40)
		DECLARE @ORDEN INT
		DECLARE @CUENTA_SUMA_OK BIT

		SELECT @FILAS = FILAS
		FROM OPENJSON(@PARAMETROS) WITH (FILAS NVARCHAR(MAX) AS JSON)

		IF @FILAS IS NULL OR ISJSON(@FILAS) <> 1
		BEGIN
			SELECT 'KO' OK, 0 AS INSERTADOS, 0 AS ERRORES

			SELECT CAST(NULL AS VARCHAR(20)) AS CUENTA, CAST(NULL AS VARCHAR(200)) AS NOMCUENTA, 'No se recibieron filas para cargar' AS ERROR
			WHERE 1 = 0

			RETURN
		END

		INSERT INTO @TBLCARGA (CUENTA, NOMCUENTA, TIPO, NEMONICO, CENTRO, PRODUCTO, REFERENCIA, TERCERO, IMPUESTO, ESTADO, CUENTA_SUMA, CLASE)
		SELECT LTRIM(RTRIM(COALESCE(CUENTA, ''))), LTRIM(RTRIM(COALESCE(NOMCUENTA, ''))), LTRIM(RTRIM(COALESCE(TIPO, ''))), NULLIF(LTRIM(RTRIM(COALESCE(
							NEMONICO, ''))), ''), COALESCE(TRY_CAST(CENTRO AS SMALLINT), 0), COALESCE(TRY_CAST(PRODUCTO AS SMALLINT), 0), COALESCE(TRY_CAST(
					REFERENCIA AS SMALLINT), 0), COALESCE(TRY_CAST(TERCERO AS SMALLINT), 0), COALESCE(TRY_CAST(IMPUESTO AS SMALLINT), 0), LTRIM(RTRIM(COALESCE(
						ESTADO, ''))), NULLIF(LTRIM(RTRIM(COALESCE(CUENTA_SUMA, ''))), ''), NULLIF(LTRIM(RTRIM(COALESCE(CLASE, ''))), '')
		FROM OPENJSON(@FILAS) WITH (
				CUENTA VARCHAR(20) '$.CUENTA', NOMCUENTA VARCHAR(200) '$.NOMCUENTA', TIPO VARCHAR(20) '$.TIPO', NEMONICO VARCHAR(40) '$.NEMONICO', CENTRO VARCHAR(
					10) '$.CENTRO', PRODUCTO VARCHAR(10) '$.PRODUCTO', REFERENCIA VARCHAR(10) '$.REFERENCIA', TERCERO VARCHAR(10) '$.TERCERO', IMPUESTO VARCHAR(10
				) '$.IMPUESTO', ESTADO VARCHAR(20) '$.ESTADO', CUENTA_SUMA VARCHAR(20) '$.CUENTA_SUMA', CLASE VARCHAR(20) '$.CLASE'
				)
		WHERE LTRIM(RTRIM(COALESCE(CUENTA, ''))) <> ''

		/* ---------- PASO 1: validar todas las filas (sin insertar) ---------- */
		DECLARE CUR_CARGA CURSOR LOCAL FAST_FORWARD
		FOR
		SELECT ORDEN, CUENTA, NOMCUENTA, TIPO, NEMONICO, CENTRO, PRODUCTO, REFERENCIA, TERCERO, IMPUESTO, ESTADO, CUENTA_SUMA, CLASE
		FROM @TBLCARGA
		ORDER BY ORDEN

		OPEN CUR_CARGA

		FETCH NEXT
		FROM CUR_CARGA
		INTO @ORDEN, @CUENTA, @NOMCUENTA, @TIPO, @NEMONICO, @CENTRO, @PRODUCTO, @REFERENCIA, @TERCERO, @IMPUESTO, @ESTADO, @CUENTA_SUMA, @CLASE

		WHILE @@FETCH_STATUS = 0
		BEGIN
			SET @LENC = LEN(@CUENTA)
			SET @NIVEL = NULL

			IF EXISTS (
					SELECT 1
					FROM @TBLCARGA
					WHERE CUENTA = @CUENTA AND ORDEN < @ORDEN
					)
			BEGIN
				INSERT INTO @TBLERRCARGA (CUENTA, NOMCUENTA, ERROR)
				SELECT @CUENTA, @NOMCUENTA, CONCAT (
						'Duplicado en el archivo: la cuenta "', @CUENTA, '" aparece m�s de una vez. ', 
						'Soluci�n: deje una sola fila por c�digo de cuenta y vuelva a cargar.'
						)

				GOTO SIGUIENTE_FILA
			END

			IF EXISTS (
					SELECT 1
					FROM CUENIIF
					WHERE CUENTA = @CUENTA
					)
			BEGIN
				INSERT INTO @TBLERRCARGA (CUENTA, NOMCUENTA, ERROR)
				SELECT @CUENTA, @NOMCUENTA, CONCAT (
						'Duplicado: la cuenta "', @CUENTA, '" ya existe en CUENIIF. ', 
						'Soluci�n: utilice otro c�digo de cuenta, o edite/inactive la existente en lugar de cargarla de nuevo.'
						)

				GOTO SIGUIENTE_FILA
			END

			IF @LENC > 1
			BEGIN
				SET @CUENTA_SUMA_OK = 0

				IF @CUENTA_SUMA IS NOT NULL AND LTRIM(RTRIM(@CUENTA_SUMA)) <> ''
				BEGIN
					IF EXISTS (
							SELECT 1
							FROM CUENIIF
							WHERE CUENTA = @CUENTA_SUMA AND TIPO = 'Suma'
							) OR EXISTS (
							SELECT 1
							FROM @TBLCARGA
							WHERE CUENTA = @CUENTA_SUMA AND TIPO = 'Suma' AND ORDEN < @ORDEN
							)
						SET @CUENTA_SUMA_OK = 1
				END

				IF @CUENTA_SUMA_OK = 0
				BEGIN
					INSERT INTO @TBLERRCARGA (CUENTA, NOMCUENTA, ERROR)
					SELECT @CUENTA, @NOMCUENTA, CASE 
							WHEN @CUENTA_SUMA IS NULL OR LTRIM(RTRIM(@CUENTA_SUMA)) = ''
								THEN CONCAT (
										'Falta CUENTA_SUMA. La cuenta "', @CUENTA, '" tiene m�s de 1 car�cter y requiere padre. ', 
										'Soluci�n: indique en CUENTA_SUMA el c�digo de una cuenta tipo Suma que ya exista (o c�rguela antes en el archivo).'
										)
							ELSE CONCAT (
									'CUENTA_SUMA inv�lida: "', @CUENTA_SUMA, '" no existe como tipo Suma (en base de datos ni antes en el archivo). ', 
									'Soluci�n: verifique el c�digo, cr�ela primero como TIPO=Suma (arriba en el Excel), o corr�jala en CUENTA_SUMA.'
									)
							END

					GOTO SIGUIENTE_FILA
				END
			END

			IF @TIPO IS NULL OR @TIPO = ''
			BEGIN
				INSERT INTO @TBLERRCARGA (CUENTA, NOMCUENTA, ERROR)
				SELECT @CUENTA, @NOMCUENTA, 'TIPO vac�o. Soluci�n: complete la columna TIPO con exactamente "Suma" o "Detalle".'

				GOTO SIGUIENTE_FILA
			END

			IF @TIPO NOT IN ('Suma', 'Detalle')
			BEGIN
				INSERT INTO @TBLERRCARGA (CUENTA, NOMCUENTA, ERROR)
				SELECT @CUENTA, @NOMCUENTA, CONCAT ('TIPO inv�lido: "', @TIPO, '". ', 'Soluci�n: utilice exactamente "Suma" o "Detalle".'
						)

				GOTO SIGUIENTE_FILA
			END

			IF @ESTADO IS NULL OR @ESTADO = ''
			BEGIN
				INSERT INTO @TBLERRCARGA (CUENTA, NOMCUENTA, ERROR)
				SELECT @CUENTA, @NOMCUENTA, 'ESTADO vac�o. Soluci�n: complete la columna ESTADO con exactamente "Activa" o "Inactiva".'

				GOTO SIGUIENTE_FILA
			END

			IF @ESTADO NOT IN ('Activa', 'Inactiva')
			BEGIN
				INSERT INTO @TBLERRCARGA (CUENTA, NOMCUENTA, ERROR)
				SELECT @CUENTA, @NOMCUENTA, CONCAT ('ESTADO inv�lido: "', @ESTADO, '". ', 'Soluci�n: utilice exactamente "Activa" o "Inactiva".'
						)

				GOTO SIGUIENTE_FILA
			END

			IF @TIPO = 'Detalle' AND (@CENTRO > 1 OR @PRODUCTO > 1 OR @REFERENCIA > 1 OR @TERCERO > 1)
			BEGIN
				INSERT INTO @TBLERRCARGA (CUENTA, NOMCUENTA, ERROR)
				SELECT @CUENTA, @NOMCUENTA, CONCAT (
						'Flags inv�lidos en cuenta Detalle (CCOSTO=', @CENTRO, ', PRODUCTO=', @PRODUCTO, ', FACTURA/REFERENCIA=', @REFERENCIA, ', TERCERO=', 
						@TERCERO, '). ', 'Soluci�n: utilice solo 0 o 1 en DETALLE CCOSTO, DETALLE PRODUCTO, DETALLE FACTURA y DETALLE TERCERO.'
						)

				GOTO SIGUIENTE_FILA
			END

			IF @LENC > 2 AND (@LENC % 2) > 0
			BEGIN
				INSERT INTO @TBLERRCARGA (CUENTA, NOMCUENTA, ERROR)
				SELECT @CUENTA, @NOMCUENTA, CONCAT (
						'Longitud de cuenta inv�lida: "', @CUENTA, '" tiene ', @LENC, ' caracteres (impar). ', 
						'Soluci�n: si la cuenta tiene m�s de 2 caracteres, la longitud debe ser par (2, 4, 6, 8.18). Ejemplo: utilice "23" o "2341", no "234".'
						)

				GOTO SIGUIENTE_FILA
			END

			IF @LENC > 18
			BEGIN
				INSERT INTO @TBLERRCARGA (CUENTA, NOMCUENTA, ERROR)
				SELECT @CUENTA, @NOMCUENTA, CONCAT (
						'Cuenta fuera de rango: "', @CUENTA, '" tiene ', @LENC, ' caracteres (m�ximo 18). ', 
						'Soluci�n: acorte el c�digo CUENTANIIF a m�ximo 18 caracteres.'
						)

				GOTO SIGUIENTE_FILA
			END

			SET @NIVEL = CASE @LENC
					WHEN 1
						THEN 1
					WHEN 2
						THEN 2
					WHEN 4
						THEN 3
					WHEN 6
						THEN 4
					WHEN 8
						THEN 5
					WHEN 10
						THEN 6
					WHEN 12
						THEN 7
					WHEN 14
						THEN 8
					WHEN 16
						THEN 9
					WHEN 18
						THEN 10
					ELSE NULL
					END

			IF @NIVEL IS NULL
			BEGIN
				INSERT INTO @TBLERRCARGA (CUENTA, NOMCUENTA, ERROR)
				SELECT @CUENTA, @NOMCUENTA, CONCAT (
						'No se pudo calcular el nivel para "', @CUENTA, '" (longitud ', @LENC, '). ', 
						'Soluci�n: utilice longitudes v�lidas 1, 2, 4, 6, 8, 10, 12, 14, 16 u 18.'
						)

				GOTO SIGUIENTE_FILA
			END

			UPDATE @TBLCARGA
			SET NIVEL = @NIVEL
			WHERE ORDEN = @ORDEN

			SIGUIENTE_FILA:

			FETCH NEXT
			FROM CUR_CARGA
			INTO @ORDEN, @CUENTA, @NOMCUENTA, @TIPO, @NEMONICO, @CENTRO, @PRODUCTO, @REFERENCIA, @TERCERO, @IMPUESTO, @ESTADO, @CUENTA_SUMA, @CLASE
		END

		CLOSE CUR_CARGA

		DEALLOCATE CUR_CARGA

		SELECT @ERRORES_CARGA = COUNT(*)
