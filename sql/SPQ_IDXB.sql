CREATE OR ALTER PROCEDURE DBO.SPQ_IDXB
@JSON  NVARCHAR(MAX) 
WITH
ENCRYPTION
AS
DECLARE  @PARAMETROS   NVARCHAR(MAX) ,@MODELO           VARCHAR(100) ,@METODO           VARCHAR(100)  ,@USUARIO        VARCHAR(12),
			@GRUPO        VARCHAR(8)    ,@SYS_COMPUTERNAME VARCHAR(254) ,@IDSEDE             VARCHAR(5)    ,@USUNOMBRE     VARCHAR(100), @SEDE VARCHAR(5),
			@FECHA        VARCHAR(10)   ,@IDEMEDICA        VARCHAR(4)	,@FECHA1           DATETIME		,@SQL            VARCHAR(MAX),
			@CODCAJERO		VARCHAR(20),@COMPANIA		VARCHAR(10)	,@IDAFILIADO VARCHAR(20)	,@IDMEDICO	VARCHAR(20)	,@FECHAINI DATE	
			,@PROCESO	VARCHAR(20)	,@datoIDXB NVARCHAR(MAX)
BEGIN 
	SET LANGUAGE Spanish;  
	SET DATEFORMAT dmy
	SELECT *
	INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',

		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)  AS JSON
	)

	SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON
	--DEFINICION DE TABLA DE ERRORES
	DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200));
	-- TOMA DEL GRUPO, SYS_COMPUTERNAME, SEDE   DE ACUERDO AL USUARIOpl,   --PRINT 'USUARIO:'+@USUARIO
	SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO), @USUNOMBRE = NOMBRE FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME, @COMPANIA = COMPANIA, @CODCAJERO= CODCAJERO FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @IDSEDE = IDSEDE, @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
	PRINT '@USUARIO='+@USUARIO

	IF @METODO = 'CRUD_IDXB'
	BEGIN
		SELECT @datoIDXB =  datoIDXB
		FROM OPENJSON (@PARAMETROS)
		WITH		 (
					datoIDXB			NVARCHAR(MAX)  AS JSON
					)
		SELECT @PROCESO     = JSON_VALUE(@datoIDXB ,'$.PROCESO') 
		SELECT    *  INTO #datoIDXB
		FROM OPENJSON (@datoIDXB)
		WITH (
			IDBODEGA				VARCHAR(20)		'$.IDBODEGA'
			,IDARTICULO				VARCHAR(20)		'$.IDARTICULO'
			,STOCKMINIMO			VARCHAR(20)		'$.STOCKMINIMO'
			,STOCKMAXIMO			VARCHAR(20)		'$.STOCKMAXIMO'
			,PUNTOREORDEN			VARCHAR(20)		'$.PUNTOREORDEN'
			,EXISTOTAL				VARCHAR(20)		'$.EXISTOTAL'
			,RAUTORIZACION			INT				'$.RAUTORIZACION'
		)
		
		IF @PROCESO = 'NUEVO' AND EXISTS (SELECT * FROM IDXB, #datoIDXB WHERE IDXB.IDBODEGA = #datoIDXB.IDBODEGA AND IDXB.IDARTICULO = #datoIDXB.IDARTICULO )
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El Articulo, ya existe para esta bodega.'
		END
	
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				IF UPPER(@PROCESO)='EDITAR'
				BEGIN
					UPDATE IDXB SET IDXB.STOCKMINIMO = #datoIDXB.STOCKMINIMO, IDXB.STOCKMAXIMO = #datoIDXB.STOCKMAXIMO, IDXB.PUNTOREORDEN = #datoIDXB.PUNTOREORDEN, IDXB.EXISTOTAL = #datoIDXB.EXISTOTAL, IDXB.RAUTORIZACION = #datoIDXB.RAUTORIZACION
					FROM IDXB, #datoIDXB WHERE IDXB.IDBODEGA = #datoIDXB.IDBODEGA AND IDXB.IDARTICULO = #datoIDXB.IDARTICULO
				END
				IF UPPER(@PROCESO)='NUEVO'
				BEGIN
					INSERT INTO IDXB (IDBODEGA, IDARTICULO, STOCKMINIMO, STOCKMAXIMO, RAUTORIZACION, PUNTOREORDEN, EXISTOTAL)
					SELECT IDBODEGA, IDARTICULO, STOCKMINIMO, STOCKMAXIMO, RAUTORIZACION, PUNTOREORDEN, EXISTOTAL
					FROM #datoIDXB
				END
				IF UPPER(@PROCESO)='BORRAR'
				BEGIN
					DELETE FROM IDXB WHERE IDXB.IDBODEGA = (SELECT IDBODEGA FROM #datoIDXB) AND IDARTICULO= (SELECT IDARTICULO FROM #datoIDXB)
				END
			END TRY  
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK
		END 
	END
	
END
