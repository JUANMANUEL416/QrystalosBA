IF EXISTS (SELECT name FROM sysobjects   WHERE name = 'SPK_CREACXP_CI' AND type = 'P')
BEGIN
   DROP PROCEDURE SPK_CREACXP_CI
END
GO
CREATE PROCEDURE DBO.SPK_CREACXP_CI
@CONSECUTIVO VARCHAR(16),
@COMPANIA      VARCHAR(2),  
@SEDE          VARCHAR(5),
@USUARIO      VARCHAR(20)  
WITH ENCRYPTION
AS      
BEGIN  
   DECLARE @NVOCONSEC INT  
   DECLARE @IDPROVEEDOR VARCHAR(20)  
   DECLARE @VALOR DECIMAL(14,2)  
   DECLARE @IDSERVICIO   VARCHAR(20)    
   DECLARE @DESCSERVICIO VARCHAR(255)   
   DECLARE @IDAREA       VARCHAR(20)    
   DECLARE @IDCIRUGIA    VARCHAR(20)    
   DECLARE @PREFIJO      VARCHAR(6)     
   DECLARE @VALOR1       DECIMAL(14,2)  
   DECLARE @CANTIDAD     INT            
   DECLARE @N_FACTURA    VARCHAR(16)    
   DECLARE @CCOSTO       VARCHAR(20)    
   DECLARE @IDAREAH      VARCHAR(20)    
   DECLARE @IDTERCEROCA  VARCHAR(20)    
   DECLARE @IDPLAN       VARCHAR(6)     
   DECLARE @AUX          INT 
   DECLARE @NOADMISION   VARCHAR(20) 
  -- DECLARE @USUARIO      VARCHAR(16) 

   PRINT 'CAPTURANDO VARIABLES'  

  CREATE TABLE #ICXP (IDPROVEEDOR    VARCHAR(20)  COLLATE database_default, 
                       IDSERVICIO     VARCHAR(20) COLLATE database_default,  
                       VALOREXCEDENTE DECIMAL(14,2),                         
                       DESCSEVICIO    VARCHAR(255) COLLATE database_default,  
                       IDAREA         VARCHAR(20) COLLATE database_default, 
                       PREFIJO        VARCHAR(6) COLLATE database_default,  
                       VALORTOTAL     DECIMAL(14,2),
                       CANTIDAD       INT,
                       NOPRESTACION   VARCHAR(16) COLLATE database_default,  
                       N_FACTURA      VARCHAR(16) COLLATE database_default, 
                       CCOSTO         VARCHAR(20) COLLATE database_default,
                       IDAREAH        VARCHAR(20) COLLATE database_default, 
                       ITEM           INT IDENTITY, 
                       IDTERCEROCA    VARCHAR(20) COLLATE database_default, 
                       IDPLAN         VARCHAR(6) COLLATE database_default, 
                       FACTOR         DECIMAL(14,2), 
                       VALORCXP       DECIMAL(14,2),
	                    FECHACARGO     DATETIME )
	                    
	IF (DBO.FNK_VALORVARIABLE('HONORATAR_DIF')='SI')
   BEGIN
        INSERT INTO #ICXP (IDPROVEEDOR, IDSERVICIO, VALOREXCEDENTE, DESCSEVICIO, IDAREA,
                         PREFIJO, VALORTOTAL, CANTIDAD, NOPRESTACION, N_FACTURA, CCOSTO,
                         IDAREAH, IDTERCEROCA, IDPLAN, FACTOR, VALORCXP, FECHACARGO )
       SELECT IDMEDICO,CIT.IDSERVICIO,VALOREXEDENTE,SER.DESCSERVICIO,IDAREA,SER.PREFIJO,CASE DBO.TARF.REDONDEO
               WHEN 'Unidad'   THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,0)
               WHEN 'Decena'   THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,-1)
               WHEN 'Centena'  THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,-2)
               WHEN 'Millar'   THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,-3)
               WHEN 'Dos Dec.' THEN ROUND(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,2)
               WHEN 'SIN'      THEN (DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO)
               ELSE round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,0)    
               END     ,
       CANTIDAD,CONSECUTIVO,N_FACTURA,CIT.CCOSTO,IDAREAH,IDTERCEROCA,CIT.IDPLAN,FACTOR,CASE DBO.TARF.REDONDEO
               WHEN 'Unidad'   THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,0)
               WHEN 'Decena'   THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,-1)
               WHEN 'Centena'  THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,-2)
               WHEN 'Millar'   THEN round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,-3)
               WHEN 'Dos Dec.' THEN ROUND(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,2)
               WHEN 'SIN'      THEN (DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO)
               ELSE round(DBO.TARDV.VALOR*DBO.PXS.FACTOR*DBO.TARF.FACTORDINERO,0)    
               END     ,FECHAATENCION 
       FROM CIT INNER JOIN SER ON CIT.IDSERVICIO=SER.IDSERVICIO
                INNER JOIN PXS ON IDTERCERO=IDMEDICO 
                INNER JOIN TARDV ON TARDV.IDSERVICIO=SER.CODCUPS
                AND CIT.IDPLAN = PXS.IDPLAN
	             AND CIT.IDTERCEROCA    = PXS.IDADMINISTRADORA
                INNER JOIN TARF ON TARDV.IDTARIFA=TARF.IDTARIFA         
       WHERE CONSECUTIVO=@CONSECUTIVO
   
   END
   ELSE
   BEGIN                    
      INSERT INTO #ICXP (IDPROVEEDOR, IDSERVICIO, VALOREXCEDENTE, DESCSEVICIO, IDAREA,
                         PREFIJO, VALORTOTAL, CANTIDAD, NOPRESTACION, N_FACTURA, CCOSTO,
                         IDAREAH, IDTERCEROCA, IDPLAN, FACTOR, VALORCXP, FECHACARGO )
      SELECT IDMEDICO,CIT.IDSERVICIO,VALOREXEDENTE,SER.DESCSERVICIO,IDAREA,SER.PREFIJO,VALORTOTAL,
      CANTIDAD,CONSECUTIVO,N_FACTURA,CIT.CCOSTO,IDAREAH,IDTERCEROCA,CIT.IDPLAN,FACTOR,VALOR,FECHAATENCION 
      FROM CIT INNER JOIN SER ON CIT.IDSERVICIO=SER.IDSERVICIO
               INNER JOIN VW_CXPPROTOT ON  CIT.IDPLAN=VW_CXPPROTOT.IDPLAN
               AND CIT.IDMEDICO   = VW_CXPPROTOT.IDTERCERO
	            AND CIT.IDTERCEROCA    = VW_CXPPROTOT.IDADMINISTRADORA
	            AND CIT.IDSERVICIO    = VW_CXPPROTOT.IDSERVICIO
      WHERE CONSECUTIVO=@CONSECUTIVO
   END

   CREATE TABLE #PCXP (IDPROVEEDOR VARCHAR(20),VALOR DECIMAL(14,2))  
   INSERT INTO  #PCXP (IDPROVEEDOR,VALOR)  
   SELECT IDPROVEEDOR, SUM(VALORCXP)  FROM #ICXP  
   GROUP BY IDPROVEEDOR 
   SELECT @VALOR= SUM(VALORCXP)  FROM #ICXP  
   GROUP BY IDPROVEEDOR 
   
   SELECT @IDPROVEEDOR=IDPROVEEDOR FROM #ICXP
   SELECT @NOADMISION=NOPRESTACION FROM #ICXP
   PRINT'INICIAMOS EL INSERT'

   EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@FCXP',@NVOCONSEC OUTPUT  
   SELECT @NVOCONSEC = @SEDE + REPLACE(SPACE(8 - LEN(@NVOCONSEC))+LTRIM(RTRIM(@NVOCONSEC)),SPACE(1),0)
   PRINT 'ESTE ES EL CONSECUTIVO DE  FXP...'+' '+CAST(@NVOCONSEC AS VARCHAR(20))
   INSERT INTO FXP(N_PRESUP,IDTERCERO,NOREFERENCIA,F_FACTURAREF,F_VENCE,VR_TOTAL,ESTADO,  
                   F_CANCELADO,EMPLEADO,PROCEDENCIA,OBSERVACION,COMPANIA,INDCOBRADA)  
   SELECT @NVOCONSEC,@IDPROVEEDOR,@NOADMISION,GETDATE(),NULL,@VALOR,'P',NULL,@USUARIO,  
          'CI','',@COMPANIA,0  

		 -- MOD.JQUIROGA 20090615 - Ingresar el N_factura en CXPD
         INSERT INTO FXPD(N_PRESUP,IDTERCERO,ITEM,IDSERVICIO,PREFIJO,VALOR,CANTIDAD,VR_TOTAL,  
                          NOPRESTACION,NOITEM,IDCIRUGIA, N_FACTURA, ESTADO, CCOSTO, IDAREA,
                          IDAREAH, VLRORIGINAL)  
         SELECT @NVOCONSEC,@IDPROVEEDOR,ITEM,IDSERVICIO,PREFIJO,VALORTOTAL,CANTIDAD,  
                VALORCXP,NOPRESTACION,'','', N_FACTURA, 'P', CCOSTO, IDAREA,
                IDAREAH, VALORTOTAL  
         FROM   #ICXP  
         WHERE  IDPROVEEDOR = @IDPROVEEDOR 
    
   
 END
