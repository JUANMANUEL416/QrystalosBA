/*
  Checklist contabilizar — lote FACTU + CxP sep corregidas (CEM). Solo SELECT.
*/
SET NOCOUNT ON;

DECLARE @SEP TABLE (CNSFCXP varchar(20) PRIMARY KEY, NOREFERENCIA varchar(20));
INSERT INTO @SEP VALUES
  (N'01CM000873', N'DPE10920'), (N'03CM001706', N'DPE10943'), (N'01CM000853', N'DPE10977'),
  (N'26CM000528', N'DPE11790'), (N'03CM002193', N'DPE12214'), (N'34CM000065', N'DPE12124'),
  (N'01CM000861', N'DPE11203');

SELECT N'SEP_CORREGIDAS' AS BLOQUE, P.CNSFCXP, P.NOREFERENCIA, P.ESTADO, P.CONTABILIZADA,
  P.NROCOMPROBANTE,
  CASE WHEN P.ESTADO <> N'N' OR COALESCE(P.CONTABILIZADA,0) <> 0 THEN N'BLOQ_ESTADO'
       WHEN ABS(P.VLR_NETO - SUM(D.VLR_NETO)) > 0.01 THEN N'CAB_DET'
       WHEN COALESCE(P.VLR_IVA,0)=0 AND ABS(P.VALOR-P.VLR_NETO)>0.02 THEN N'BRUTO_NETO'
       WHEN SUM(CASE WHEN ABS(D.VLR_NETO-(D.CANTIDAD*D.VALOR+COALESCE(D.VLR_IVA,0)-ISNULL(D.VLR_DESCUENTO,0)))>1 THEN 1 ELSE 0 END)>0
       THEN N'LINEAS_MAL'
       ELSE N'OK' END AS LISTO
FROM FCXP P JOIN FCXPD D ON D.CNSFCXP=P.CNSFCXP JOIN @SEP S ON S.CNSFCXP=P.CNSFCXP
GROUP BY P.CNSFCXP,P.NOREFERENCIA,P.ESTADO,P.CONTABILIZADA,P.NROCOMPROBANTE,P.VALOR,P.VLR_IVA,P.VLR_NETO
ORDER BY P.CNSFCXP;

SELECT N'RESUMEN_SEP' AS BLOQUE,
  SUM(CASE WHEN LISTO=N'OK' THEN 1 ELSE 0 END) AS OK,
  SUM(CASE WHEN LISTO<>N'OK' THEN 1 ELSE 0 END) AS PENDIENTE
FROM (
  SELECT CASE WHEN P.ESTADO <> N'N' OR COALESCE(P.CONTABILIZADA,0) <> 0 THEN N'BLOQ'
       WHEN ABS(P.VLR_NETO - X.SN)>0.01 THEN N'CAB'
       WHEN COALESCE(P.VLR_IVA,0)=0 AND ABS(P.VALOR-P.VLR_NETO)>0.02 THEN N'BRUTO'
       WHEN X.LM>0 THEN N'LIN'
       ELSE N'OK' END AS LISTO
  FROM FCXP P JOIN @SEP S ON S.CNSFCXP=P.CNSFCXP
  CROSS APPLY (
    SELECT SUM(D.VLR_NETO) SN,
      SUM(CASE WHEN ABS(D.VLR_NETO-(D.CANTIDAD*D.VALOR+COALESCE(D.VLR_IVA,0)-ISNULL(D.VLR_DESCUENTO,0)))>1 THEN 1 ELSE 0 END) LM
    FROM FCXPD D WHERE D.CNSFCXP=P.CNSFCXP) X
) Z;
