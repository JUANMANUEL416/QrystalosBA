/*
  Facturas de consulta externa, sede 06, emitidas del 13 al 15 de octubre
  de 2026, en comprobantes con error y sin centro de costo.

  6 copian el centro de la dispensación ligada a la autorización, porque
  ese centro ya tiene cuenta de venta del prefijo 12.
  192 no tienen dispensación: se reparten entre los centros del movimiento
  06 confirmado en octubre que ya tienen cuenta de venta del prefijo.
  3 tienen dispensación en el centro 10030102, área 4110, y ese centro no
  tiene cuenta de venta del prefijo 12. Esas no se tocan.

  No cambia cantidades ni valores. No crea filas en KMCOM.

  Uso:
    1. Deje @APLICAR = 0 y ejecute. Revise el reparto y las 3 que quedan fuera.
    2. Ponga @APLICAR = 1 y vuelva a ejecutar.
       Si ya no son 6 y 192, no cambia nada.
*/

SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @APLICAR bit = 0;
DECLARE @PC varchar(254) = 'CONTABILIDAD';
DECLARE @MOD varchar(20) = DBO.FNK_VALORVARIABLE('IDMODELOCONTABLE');

IF OBJECT_ID('tempdb..#Copia') IS NOT NULL DROP TABLE #Copia;
IF OBJECT_ID('tempdb..#Fuera') IS NOT NULL DROP TABLE #Fuera;
IF OBJECT_ID('tempdb..#Fac') IS NOT NULL DROP TABLE #Fac;
IF OBJECT_ID('tempdb..#Cen') IS NOT NULL DROP TABLE #Cen;
IF OBJECT_ID('tempdb..#Cupo') IS NOT NULL DROP TABLE #Cupo;
IF OBJECT_ID('tempdb..#Asig') IS NOT NULL DROP TABLE #Asig;

IF EXISTS (
    SELECT 1 FROM dbo.PRI
    WHERE ANO = '2026' AND MES = 10 AND COALESCE(CERRADO, 0) = 1
)
    THROW 56220, 'Octubre de 2026 está cerrado en contabilidad.', 1;

SELECT
    F.N_FACTURA,
    D.PREFIJO,
    E.NROCOMPROBANTE,
    E.COMPANIA,
    E.IDSEDE,
    LEFT(E.USUARIO, 12) AS USUARIO,
    A.NOAUT,
    I.CCOSTO,
    I.IDAREA
INTO #Copia
FROM dbo.MCPE E
INNER JOIN dbo.FTR F ON F.N_FACTURA = E.NOREFERENCIA
INNER JOIN dbo.FTRD D ON D.CNSFTR = F.CNSFCT
INNER JOIN dbo.AUT A ON A.NOAUT = D.NOADMISION
INNER JOIN dbo.IMOV I
    ON I.NODOCUMENTO = A.CNSMOV
   AND COALESCE(I.ESTADO, 0) = 1
   AND COALESCE(RTRIM(I.CCOSTO), '') <> ''
   AND COALESCE(RTRIM(I.IDAREA), '') <> ''
WHERE E.ANO = 2026 AND E.MES = 10 AND E.ESTADO = 0
  AND RTRIM(E.PROCEDENCIA) = 'FACTURA'
  AND COALESCE(E.ANULADO, 0) <> 1
  AND F.PROCEDENCIA = 'CE'
  AND COALESCE(F.ESTADO, '') <> 'A'
  AND COALESCE(F.CONTABILIZADA, 0) = 2
  AND F.NROCOMPROBANTE = E.NROCOMPROBANTE
  AND F.F_FACTURA >= '20261013' AND F.F_FACTURA < '20261016'
  AND COALESCE(RTRIM(D.CCOSTO), '') = ''
  AND COALESCE(RTRIM(D.AREAPRESTACION), '') = ''
  AND COALESCE(RTRIM(A.CCOSTO), '') = ''
  AND COALESCE(RTRIM(A.IDAREA), '') = ''
  AND E.COMPANIA = '01' AND E.IDSEDE = '06'
  AND (SELECT COUNT(*) FROM dbo.FTRD X WHERE X.CNSFTR = F.CNSFCT) = 1
  AND (
      SELECT COUNT(DISTINCT RTRIM(M.CCOSTO) + '|' + RTRIM(M.IDAREA))
      FROM dbo.IMOV M
      WHERE M.NODOCUMENTO = A.CNSMOV
        AND COALESCE(M.ESTADO, 0) = 1
        AND COALESCE(RTRIM(M.CCOSTO), '') <> ''
  ) = 1
  AND (
      SELECT COUNT(*)
      FROM dbo.KMCOM K
      WHERE K.IDMODELOCONT = @MOD
        AND K.IDTIPOCONT = 'VENTAS' AND K.TIPO = 'CR'
        AND K.PREFIJO = D.PREFIJO
        AND K.CCOSTO = I.CCOSTO AND K.IDAREA = I.IDAREA
        AND COALESCE(K.CUENTA, '') <> ''
        AND K.CUENTA NOT LIKE 'NO DEF%'
  ) = 1;

SELECT
    F.N_FACTURA,
    D.PREFIJO,
    RTRIM(I.CCOSTO) AS CCOSTO,
    RTRIM(I.IDAREA) AS IDAREA
INTO #Fuera
FROM dbo.MCPE E
INNER JOIN dbo.FTR F ON F.N_FACTURA = E.NOREFERENCIA
INNER JOIN dbo.FTRD D ON D.CNSFTR = F.CNSFCT
INNER JOIN dbo.AUT A ON A.NOAUT = D.NOADMISION
INNER JOIN dbo.IMOV I
    ON I.NODOCUMENTO = A.CNSMOV
   AND COALESCE(I.ESTADO, 0) = 1
   AND COALESCE(RTRIM(I.CCOSTO), '') <> ''
WHERE E.ANO = 2026 AND E.MES = 10 AND E.ESTADO = 0
  AND RTRIM(E.PROCEDENCIA) = 'FACTURA'
  AND COALESCE(E.ANULADO, 0) <> 1
  AND F.F_FACTURA >= '20261013' AND F.F_FACTURA < '20261016'
  AND COALESCE(RTRIM(D.CCOSTO), '') = ''
  AND E.IDSEDE = '06'
  AND NOT EXISTS (SELECT 1 FROM #Copia C WHERE C.N_FACTURA = F.N_FACTURA);

SELECT
    F.N_FACTURA,
    D.PREFIJO,
    E.NROCOMPROBANTE,
    E.COMPANIA,
    E.IDSEDE,
    LEFT(E.USUARIO, 12) AS USUARIO,
    A.NOAUT
INTO #Fac
FROM dbo.MCPE E
INNER JOIN dbo.FTR F ON F.N_FACTURA = E.NOREFERENCIA
INNER JOIN dbo.FTRD D ON D.CNSFTR = F.CNSFCT
INNER JOIN dbo.AUT A ON A.NOAUT = D.NOADMISION
WHERE E.ANO = 2026 AND E.MES = 10 AND E.ESTADO = 0
  AND RTRIM(E.PROCEDENCIA) = 'FACTURA'
  AND COALESCE(E.ANULADO, 0) <> 1
  AND F.PROCEDENCIA = 'CE'
  AND COALESCE(F.ESTADO, '') <> 'A'
  AND COALESCE(F.CONTABILIZADA, 0) = 2
  AND F.NROCOMPROBANTE = E.NROCOMPROBANTE
  AND F.F_FACTURA >= '20261013' AND F.F_FACTURA < '20261016'
  AND COALESCE(RTRIM(D.CCOSTO), '') = ''
  AND COALESCE(RTRIM(D.AREAPRESTACION), '') = ''
  AND COALESCE(RTRIM(A.CCOSTO), '') = ''
  AND COALESCE(RTRIM(A.IDAREA), '') = ''
  AND E.COMPANIA = '01' AND E.IDSEDE = '06'
  AND (SELECT COUNT(*) FROM dbo.FTRD X WHERE X.CNSFTR = F.CNSFCT) = 1
  AND NOT EXISTS (SELECT 1 FROM #Copia C WHERE C.N_FACTURA = F.N_FACTURA)
  AND NOT EXISTS (SELECT 1 FROM #Fuera U WHERE U.N_FACTURA = F.N_FACTURA)
  AND NOT EXISTS (
      SELECT 1 FROM dbo.MCP P
      WHERE P.NROCOMPROBANTE = E.NROCOMPROBANTE AND COALESCE(P.ANULADO, 0) <> 1
  );

SELECT I.CCOSTO, I.IDAREA, COUNT(*) AS MOV06
INTO #Cen
FROM dbo.IMOV I
WHERE I.IDTIPOMOV = '06'
  AND COALESCE(I.ESTADO, 0) = 1
  AND COALESCE(RTRIM(I.CCOSTO), '') <> ''
  AND COALESCE(RTRIM(I.IDAREA), '') <> ''
  AND I.FECHACONF >= '20261001'
  AND I.FECHACONF < '20261101'
GROUP BY I.CCOSTO, I.IDAREA;

;WITH Pesos AS (
    SELECT
        F.PREFIJO,
        C.CCOSTO,
        C.IDAREA,
        C.MOV06,
        SUM(C.MOV06) OVER (PARTITION BY F.PREFIJO) AS TOTAL,
        (SELECT COUNT(*) FROM #Fac X WHERE X.PREFIJO = F.PREFIJO) AS NFAC
    FROM (SELECT DISTINCT PREFIJO FROM #Fac) F
    INNER JOIN #Cen C ON 1 = 1
    WHERE (
        SELECT COUNT(*)
        FROM dbo.KMCOM K
        WHERE K.IDMODELOCONT = @MOD
          AND K.IDTIPOCONT = 'VENTAS'
          AND K.TIPO = 'CR'
          AND K.PREFIJO = F.PREFIJO
          AND K.CCOSTO = C.CCOSTO
          AND K.IDAREA = C.IDAREA
          AND COALESCE(K.CUENTA, '') <> ''
          AND K.CUENTA NOT LIKE 'NO DEF%'
    ) = 1
),
Base AS (
    SELECT *,
           CAST((MOV06 * NFAC) / NULLIF(TOTAL, 0) AS int) AS BASE,
           (MOV06 * NFAC) % NULLIF(TOTAL, 0) AS FRAC
    FROM Pesos
),
Cupo AS (
    SELECT
        PREFIJO, CCOSTO, IDAREA, MOV06,
        BASE + CASE
            WHEN ROW_NUMBER() OVER (PARTITION BY PREFIJO ORDER BY FRAC DESC, CCOSTO, IDAREA)
                 <= NFAC - SUM(BASE) OVER (PARTITION BY PREFIJO)
            THEN 1 ELSE 0 END AS CUPO
    FROM Base
)
SELECT PREFIJO, CCOSTO, IDAREA, MOV06, CUPO,
       SUM(CUPO) OVER (
           PARTITION BY PREFIJO
           ORDER BY MOV06 DESC, CCOSTO, IDAREA
           ROWS UNBOUNDED PRECEDING
       ) AS HASTA
INTO #Cupo
FROM Cupo
WHERE CUPO > 0;

SELECT
    F.N_FACTURA, F.PREFIJO, F.NROCOMPROBANTE, F.COMPANIA, F.IDSEDE,
    F.USUARIO, F.NOAUT, C.CCOSTO, C.IDAREA
INTO #Asig
FROM (
    SELECT *, ROW_NUMBER() OVER (PARTITION BY PREFIJO ORDER BY N_FACTURA) AS RN
    FROM #Fac
) F
INNER JOIN #Cupo C
    ON C.PREFIJO = F.PREFIJO
   AND F.RN > C.HASTA - C.CUPO
   AND F.RN <= C.HASTA;

SELECT 'COPIA_DISPENSACION' AS GRUPO, PREFIJO, CCOSTO, IDAREA, COUNT(*) AS FACTURAS
FROM #Copia
GROUP BY PREFIJO, CCOSTO, IDAREA
ORDER BY FACTURAS DESC;

SELECT 'SIN_CUENTA_EN_ORIGEN' AS GRUPO, N_FACTURA, PREFIJO, CCOSTO, IDAREA
FROM #Fuera
ORDER BY N_FACTURA;

SELECT 'REPARTO' AS GRUPO, PREFIJO, CCOSTO, IDAREA, MOV06, CUPO
FROM #Cupo
ORDER BY PREFIJO, MOV06 DESC, CCOSTO;

SELECT 'REPARTO_TOTAL' AS GRUPO, PREFIJO, COUNT(*) AS FACTURAS
FROM #Asig
GROUP BY PREFIJO;

IF @APLICAR = 0
    RETURN;

IF (SELECT COUNT(*) FROM #Copia) = 0
   AND (SELECT COUNT(*) FROM #Fac) = 0
   AND (SELECT COUNT(*) FROM #Fuera) = 3
BEGIN
    SELECT 'YA_APLICADO' AS GRUPO, N_FACTURA, PREFIJO, CCOSTO, IDAREA
    FROM #Fuera
    ORDER BY N_FACTURA;
    RETURN;
END

IF (SELECT COUNT(*) FROM #Copia) <> 6
    THROW 56221, 'Ya no son 6 facturas con dispensación y cuenta. No quedó ningún cambio.', 1;
IF (SELECT COUNT(*) FROM #Fuera) <> 3
    THROW 56222, 'Ya no son 3 facturas con origen sin cuenta. No quedó ningún cambio.', 1;
IF (SELECT COUNT(*) FROM #Fac) <> 192
    OR (SELECT COUNT(*) FROM #Asig) <> 192
    THROW 56223, 'Ya no son 192 facturas para repartir. No quedó ningún cambio.', 1;
IF EXISTS (SELECT 1 FROM #Copia WHERE COALESCE(USUARIO, '') = '')
    OR EXISTS (SELECT 1 FROM #Asig WHERE COALESCE(USUARIO, '') = '')
    THROW 56224, 'Hay una factura sin usuario en el comprobante. No quedó ningún cambio.', 1;

BEGIN TRAN;

UPDATE D
SET CCOSTO = C.CCOSTO, AREAPRESTACION = C.IDAREA
FROM dbo.FTRD D
INNER JOIN dbo.FTR F ON F.CNSFCT = D.CNSFTR
INNER JOIN #Copia C ON C.N_FACTURA = F.N_FACTURA
WHERE COALESCE(RTRIM(D.CCOSTO), '') = '';

UPDATE U
SET CCOSTO = C.CCOSTO, IDAREA = C.IDAREA
FROM dbo.AUT U
INNER JOIN #Copia C ON C.NOAUT = U.NOAUT
WHERE COALESCE(RTRIM(U.CCOSTO), '') = '';

UPDATE D
SET CCOSTO = A.CCOSTO, AREAPRESTACION = A.IDAREA
FROM dbo.FTRD D
INNER JOIN dbo.FTR F ON F.CNSFCT = D.CNSFTR
INNER JOIN #Asig A ON A.N_FACTURA = F.N_FACTURA
WHERE COALESCE(RTRIM(D.CCOSTO), '') = ''
  AND (SELECT COUNT(*) FROM dbo.FTRD X WHERE X.CNSFTR = F.CNSFCT) = 1;

UPDATE U
SET CCOSTO = A.CCOSTO, IDAREA = A.IDAREA
FROM dbo.AUT U
INNER JOIN #Asig A ON A.NOAUT = U.NOAUT
WHERE COALESCE(RTRIM(U.CCOSTO), '') = '';

COMMIT TRAN;

DECLARE @NF varchar(16), @NRO varchar(20), @USU varchar(12);
DECLARE @CIA varchar(2), @SEDE varchar(5), @Msg nvarchar(240);

DECLARE c CURSOR LOCAL FAST_FORWARD FOR
    SELECT N_FACTURA, NROCOMPROBANTE, USUARIO, COMPANIA, IDSEDE
    FROM (
        SELECT N_FACTURA, NROCOMPROBANTE, USUARIO, COMPANIA, IDSEDE FROM #Copia
        UNION ALL
        SELECT N_FACTURA, NROCOMPROBANTE, USUARIO, COMPANIA, IDSEDE FROM #Asig
    ) Q
    ORDER BY N_FACTURA;

OPEN c;
FETCH NEXT FROM c INTO @NF, @NRO, @USU, @CIA, @SEDE;

WHILE @@FETCH_STATUS = 0
BEGIN
    EXEC dbo.SPK_NC_CONTAB_FTR @NF, @CIA, @USU, @PC, @SEDE, @NRO;

    IF NOT EXISTS (
        SELECT 1 FROM dbo.FTR
        WHERE N_FACTURA = @NF AND COALESCE(CONTABILIZADA, 0) = 1
    )
    OR EXISTS (
        SELECT 1 FROM dbo.MCHE H
        WHERE H.NROCOMPROBANTE = @NRO AND H.CUENTA LIKE 'NO DEF%'
    )
    BEGIN
        CLOSE c;
        DEALLOCATE c;
        SET @Msg = N'La factura ' + @NF + N' no quedó contabilizada. Las anteriores de la lista sí se reconstruyeron.';
        THROW 56225, @Msg, 1;
    END

    FETCH NEXT FROM c INTO @NF, @NRO, @USU, @CIA, @SEDE;
END

CLOSE c;
DEALLOCATE c;

SELECT 'LISTO' AS GRUPO, COUNT(*) AS FACTURAS FROM #Copia
UNION ALL
SELECT 'LISTO_REPARTO', COUNT(*) FROM #Asig;
