CREATE OR ALTER PROCEDURE DBO.SPQ_NCARNGE @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20), @IDSEDE VARCHAR(5), @DATOS VARCHAR(MAX)
DECLARE @PROCESO VARCHAR(20), @CODCARGO VARCHAR(20), @NIVEL VARCHAR(10), @GRADO VARCHAR(10), @CODCONCEPTO VARCHAR(20)
DECLARE @CODCONCEPTOEEDITE VARCHAR(20), @DATO VARCHAR(MAX)

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @PROCESO = PROCESO, @CODCARGO = CODCARGO, @NIVEL = NIVEL, @GRADO = GRADO, @CODCONCEPTO = CODCONCEPTO
			FROM OPENJSON(@PARAMETROS) WITH (
					PROCESO VARCHAR(20) '$.PROCESO', CODCARGO VARCHAR(20) '$.CODCARGO', NIVEL VARCHAR(10) '$.NIVEL', GRADO VARCHAR(10) '$.GRADO', CODCONCEPTO 
					VARCHAR(20) '$.CODCONCEPTO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('EL CONCEPTO ', @CODCONCEPTO, ' YA SE ENCUENTRA REGISTRADO PARA EL CARGO')
					WHERE EXISTS (
							SELECT 1
							FROM NCARNGE
							WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVEL AND GRADO = @GRADO AND CODCONCEPTO = @CODCONCEPTO
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO NCARNGE (CODCARGO, NIVEL, GRADO, CODCONCEPTO)
						SELECT @CODCARGO, @NIVEL, @GRADO, @CODCONCEPTO
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @DATO = DATO
					FROM OPENJSON(@PARAMETROS) WITH (DATO NVARCHAR(MAX) AS JSON)

					SELECT @CODCONCEPTOEEDITE = CODCONCEPTOEEDITE
					FROM OPENJSON(@DATO) WITH (CODCONCEPTOEEDITE VARCHAR(20) '$.CODCONCEPTOEEDITE')

					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('EL CONCEPTO ', @CODCONCEPTO, ' YA SE ENCUENTRA REGISTRADO PARA EL CARGO')
					WHERE EXISTS (
							SELECT 1
							FROM NCARNGE
							WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVEL AND GRADO = @GRADO AND CODCONCEPTO = @CODCONCEPTO
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						UPDATE NCARNGE
						SET CODCONCEPTO = @CODCONCEPTO
						WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVEL AND GRADO = @GRADO AND CODCONCEPTO = @CODCONCEPTOEEDITE
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @CODCARGO = CODCARGO, @NIVEL = NIVEL, @GRADO = GRADO, @CODCONCEPTO = CODCONCEPTO
		FROM OPENJSON(@PARAMETROS) WITH (CODCARGO VARCHAR(20) '$.CODCARGO', NIVEL VARCHAR(10) '$.NIVEL', GRADO VARCHAR(10) '$.GRADO', CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO'
				)

		BEGIN TRY
			DELETE
			FROM NCARNGE
			WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVEL AND GRADO = @GRADO AND CODCONCEPTO = @CODCONCEPTO
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
