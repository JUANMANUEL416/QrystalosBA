CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_RETTER @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
BEGIN
	-- Optimizaciones de rendimiento y seguridad de transacciones
	SET NOCOUNT ON;
	SET XACT_ABORT ON;

	DECLARE @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20), @PARAMETROS NVARCHAR(MAX);
	DECLARE @PROCESO VARCHAR(20), @IDTERCERO VARCHAR(20), @CODRETI VARCHAR(10), @ESNOMINA BIT, @DESCRIPCION VARCHAR(255);
	DECLARE @CLASE VARCHAR(10), @VALOR DECIMAL(14, 2), @ESTADO VARCHAR(10), @CODRETIEDITAR VARCHAR(10);
	DECLARE @IDTERCEROOR VARCHAR(20), @IDTERCERODES VARCHAR(20);
	DECLARE @ErrorMessage NVARCHAR(MAX);
	-- Variables para control transaccional
	DECLARE @StartedTran BIT = 0;
	DECLARE @SavePointName VARCHAR(32) = 'SPQ_NOM_RETTER_sp';

	-- Extracci�n inicial de la cabecera
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			);

	BEGIN TRY
		-- Gesti�n de Transacci�n o Savepoint
		IF @@TRANCOUNT = 0
		BEGIN
			BEGIN TRANSACTION;

			SET @StartedTran = 1;
		END
		ELSE
		BEGIN
			SAVE TRANSACTION @SavePointName;
		END

		/* =========================
           L�GICA DE NEGOCIO
           ========================= */
		IF @METODO = 'GUARDAR'
		BEGIN
			SELECT @IDTERCERO = IDTERCERO, @CODRETI = CODRETI, @ESNOMINA = ESNOMINA, @DESCRIPCION = DESCRIPCION, @CLASE = CLASE, @VALOR = VALOR, @ESTADO = ESTADO, @PROCESO = 
				PROCESO, @CODRETIEDITAR = CODRETIEDITAR
			FROM OPENJSON(@PARAMETROS) WITH (
					IDTERCERO VARCHAR(20) '$.IDTERCERO', CODRETI VARCHAR(10) '$.CODRETI', ESNOMINA BIT '$.ESNOMINA', DESCRIPCION VARCHAR(255) '$.DESCRIPCION', 
					CLASE VARCHAR(10) '$.CLASE', VALOR DECIMAL(14, 2) '$.VALOR', ESTADO VARCHAR(10) '$.ESTADO', PROCESO VARCHAR(20) '$.PROCESO', CODRETIEDITAR 
					VARCHAR(10) '$.CODRETIEDITAR'
					);

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				IF EXISTS (
						SELECT 1
						FROM RETTER
						WHERE IDTERCERO = @IDTERCERO AND ESTADO = 'Activo' AND CODRETI = @CODRETI
						)
				BEGIN
					SET @ErrorMessage = CONCAT ('EL CODIGO ', @CODRETI, ' YA SE ENCUENTRA REGISTRADO PARA EL TERCERO');

					-- Este THROW saltar� directamente al CATCH
					THROW 50000, @ErrorMessage, 1;
				END
				ELSE
				BEGIN
					INSERT INTO [RETTER] ([IDTERCERO], [CODRETI], [ESNOMINA], [DESCRIPCION], [CLASE], [VALOR], [ESTADO])
					VALUES (@IDTERCERO, @CODRETI, @ESNOMINA, @DESCRIPCION, @CLASE, @VALOR, @ESTADO);
				END
			END
			ELSE IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				UPDATE RETTER
				SET ESNOMINA = @ESNOMINA, DESCRIPCION = @DESCRIPCION, CLASE = @CLASE, VALOR = @VALOR, ESTADO = @ESTADO
				WHERE IDTERCERO = @IDTERCERO AND CODRETI = @CODRETIEDITAR;

				IF @CODRETI <> @CODRETIEDITAR
				BEGIN
					UPDATE RETTER
					SET CODRETI = @CODRETI
					WHERE IDTERCERO = @IDTERCERO AND CODRETI = @CODRETIEDITAR;
				END
			END
		END
		ELSE IF @METODO = 'ELIMINAR'
		BEGIN
			SELECT @IDTERCERO = IDTERCERO, @CODRETI = CODRETI
			FROM OPENJSON(@PARAMETROS) WITH (IDTERCERO VARCHAR(20) '$.IDTERCERO', CODRETI VARCHAR(10) '$.CODRETI');

			DELETE
			FROM RETTER
			WHERE IDTERCERO = @IDTERCERO AND CODRETI = @CODRETI;
		END
		ELSE IF @METODO = 'ULTIMA_NOMINA'
		BEGIN
			SELECT @IDTERCERO = IDTERCERO
			FROM OPENJSON(@PARAMETROS) WITH (IDTERCERO VARCHAR(20) '$.IDTERCERO');

			EXEC SPK_TRAE_NCON_RETEFTE @IDTERCERO;
		END
		ELSE IF @METODO = 'COPIAR_CODIGOS'
		BEGIN
			SELECT @IDTERCEROOR = IDTERCEROOR, @IDTERCERODES = IDTERCERODES
			FROM OPENJSON(@PARAMETROS) WITH (IDTERCEROOR VARCHAR(20) '$.IDTERCEROOR', IDTERCERODES VARCHAR(20) '$.IDTERCERODES');

			EXEC SPK_TRAE_NCON_RETEFTE @IDTERCERODES, @IDTERCEROOR;
		END

		-- Si yo inici� la transacci�n, yo hago el COMMIT
		IF @StartedTran = 1
			COMMIT TRANSACTION;

		SELECT 'OK' AS OK;
	END TRY

	BEGIN CATCH
		-- Manejo de reversi�n basado en el estado de la transacci�n
		IF XACT_STATE() = - 1
		BEGIN
			-- Transacci�n hu�rfana o fatal: Rollback total
			ROLLBACK TRANSACTION;
		END
		ELSE IF XACT_STATE() = 1
		BEGIN
			-- Transacci�n salvable
			IF @StartedTran = 1
				ROLLBACK TRANSACTION;
			ELSE
				ROLLBACK TRANSACTION @SavePointName;
		END;-- Punto y coma obligatorio antes de THROW

		-- Re-lanzar el error para notificaci�n al SP Padre o Aplicaci�n
		THROW;
	END CATCH
END
