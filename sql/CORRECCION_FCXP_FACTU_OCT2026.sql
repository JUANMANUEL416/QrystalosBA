SET NOCOUNT ON;

/* =============================================================================
   PASO 1 — Tercero RAMEDICAS en FE603306 (03CM001933)
   ============================================================================= */
SET XACT_ABORT ON;

BEGIN TRAN;

IF (
  SELECT COUNT(*)
  FROM dbo.FCXP
  WHERE CNSFCXP = N'03CM001933'
    AND NOREFERENCIA = N'FE603306'
    AND ESTADO = N'N'
    AND COALESCE(CONTABILIZADA, 0) = 0
    AND COALESCE(NROCOMPROBANTE, N'') = N''
) <> 1
BEGIN
  ROLLBACK TRAN;
  THROW 51001, 'FE603306 no esta libre para cambio de tercero. No se cambio nada.', 1;
END;

IF (
  SELECT COUNT(*)
  FROM dbo.TER
  WHERE IDTERCERO = N'060000001290'
    AND NIT LIKE N'901429936%'
) <> 1
BEGIN
  ROLLBACK TRAN;
  THROW 51002, 'No se encontro tercero RAMEDICAS 060000001290. No se cambio nada.', 1;
END;

UPDATE P
SET IDTERCERO = N'060000001290',
    CUECREDITO = COALESCE(T.CUENTA, P.CUECREDITO)
FROM dbo.FCXP P
CROSS JOIN dbo.TER T
WHERE P.CNSFCXP = N'03CM001933'
  AND T.IDTERCERO = N'060000001290';

IF (
  SELECT IDTERCERO FROM dbo.FCXP WHERE CNSFCXP = N'03CM001933'
) <> N'060000001290'
BEGIN
  ROLLBACK TRAN;
  THROW 51003, 'El tercero de FE603306 no quedo en RAMEDICAS. No se cambio nada.', 1;
END;

COMMIT TRAN;

SELECT N'PASO 1 OK' AS RESULTADO, P.CNSFCXP, P.NOREFERENCIA, T.NIT, T.RAZONSOCIAL
FROM dbo.FCXP P
INNER JOIN dbo.TER T ON T.IDTERCERO = P.IDTERCERO
WHERE P.CNSFCXP = N'03CM001933';

GO

/* =============================================================================
   PASO 2 — Cuentas: líneas con IVA → gravada + 24080501 (+ lote IEXI si existe)
   ============================================================================= */
SET XACT_ABORT ON;

DECLARE @DOC2 TABLE (CNSFCXP varchar(20) NOT NULL PRIMARY KEY);
INSERT INTO @DOC2 (CNSFCXP) VALUES
  (N'03CM002017'), (N'03CM002317'), (N'03CM002183'), (N'03CM002234'),
  (N'03CM002248'), (N'03CM002315'), (N'03CM002332'), (N'03CM002342'),
  (N'03CM002340'), (N'03CM002341'), (N'03CM002359'), (N'03CM001933');

DECLARE @L TABLE (
  CNSFCXP    varchar(20) NOT NULL,
  ITEM       int NOT NULL,
  CUENTA_HOY varchar(20) NOT NULL,
  IVA_HOY    varchar(20) NOT NULL,
  CUENTA_OK  varchar(20) NOT NULL,
  REV_OK     varchar(20) NOT NULL,
  PRIMARY KEY (CNSFCXP, ITEM)
);

INSERT INTO @L (CNSFCXP, ITEM, CUENTA_HOY, IVA_HOY, CUENTA_OK, REV_OK)
SELECT
  D.CNSFCXP,
  D.ITEM,
  D.CUENTA_SER,
  COALESCE(D.CUENTA_IVA, N''),
  CASE
    WHEN D.CUENTA_SER LIKE N'1415%' OR LEFT(D.IDSERVICIO, 2) = N'MX' THEN N'14150501'
    ELSE N'14200501'
  END,
  CASE
    WHEN D.CUENTA_SER LIKE N'1415%' OR LEFT(D.IDSERVICIO, 2) = N'MX' THEN N'14150590'
    ELSE N'14200590'
  END
FROM dbo.FCXPD D
INNER JOIN @DOC2 C ON C.CNSFCXP = D.CNSFCXP
INNER JOIN dbo.FCXP P ON P.CNSFCXP = D.CNSFCXP
WHERE D.PROCEDENCIA = N'Compras'
  AND COALESCE(D.VLR_IVA, 0) > 0
  AND P.ESTADO = N'N'
  AND COALESCE(P.CONTABILIZADA, 0) = 0
  AND COALESCE(P.NROCOMPROBANTE, N'') = N''
  AND (
    D.CUENTA_SER IN (N'14150502', N'14200502')
    OR COALESCE(D.CUENTA_IVA, N'') <> N'24080501'
  );

IF NOT EXISTS (SELECT 1 FROM @L)
BEGIN
  SELECT N'PASO 2 omitido' AS RESULTADO, N'Sin lineas pendientes de cuenta IVA.' AS DETALLE;
  GOTO PASO2_FIN;
END;

BEGIN TRAN;

IF (
  SELECT COUNT(*)
  FROM @L L
  INNER JOIN dbo.FCXPD D ON D.CNSFCXP = L.CNSFCXP AND D.ITEM = L.ITEM
  WHERE D.CUENTA_SER = L.CUENTA_HOY
    AND COALESCE(D.CUENTA_IVA, N'') = L.IVA_HOY
    AND COALESCE(D.VLR_IVA, 0) > 0
) <> (SELECT COUNT(*) FROM @L)
BEGIN
  ROLLBACK TRAN;
  THROW 52002, 'PASO 2: alguna linea cambio desde la ultima verificacion. No se cambio nada.', 1;
END;

UPDATE D
SET CUENTA_SER = L.CUENTA_OK,
    CUENTA_IVA = N'24080501'
FROM dbo.FCXPD D
INNER JOIN @L L ON L.CNSFCXP = D.CNSFCXP AND L.ITEM = L.ITEM
WHERE D.CUENTA_SER = L.CUENTA_HOY
  AND COALESCE(D.CUENTA_IVA, N'') = L.IVA_HOY;

UPDATE I
SET CUEDEBITO = L.CUENTA_OK,
    CUECREDITO = L.REV_OK,
    CUENTAIVA = N'24080501'
FROM dbo.IEXI I
INNER JOIN dbo.FCXPD D
  ON D.N_PRESUP = I.CNSMOV
 AND D.IDSERVICIO = I.IDARTICULO
 AND D.IDBODEGA = I.IDBODEGA
 AND D.NOLOTE = I.NOLOTEPEDIDO
INNER JOIN @L L ON L.CNSFCXP = D.CNSFCXP AND L.ITEM = L.ITEM
WHERE I.CUEDEBITO = L.CUENTA_HOY
  AND I.CUECREDITO = CASE L.CUENTA_HOY
                       WHEN N'14150502' THEN N'14150591'
                       WHEN N'14200502' THEN N'14200591'
                       ELSE I.CUECREDITO
                     END;

IF EXISTS (
  SELECT 1
  FROM @L L
  INNER JOIN dbo.FCXPD D ON D.CNSFCXP = L.CNSFCXP AND D.ITEM = L.ITEM
  WHERE D.CUENTA_SER <> L.CUENTA_OK
     OR COALESCE(D.CUENTA_IVA, N'') <> N'24080501'
)
BEGIN
  ROLLBACK TRAN;
  THROW 52003, 'PASO 2: no todas las lineas quedaron en gravada y 24080501. No se cambio nada.', 1;
END;

COMMIT TRAN;

SELECT N'PASO 2 OK' AS RESULTADO, P.NOREFERENCIA, D.ITEM, D.VLR_IVA, D.CUENTA_SER, D.CUENTA_IVA
FROM @L L
INNER JOIN dbo.FCXPD D ON D.CNSFCXP = L.CNSFCXP AND D.ITEM = L.ITEM
INNER JOIN dbo.FCXP P ON P.CNSFCXP = D.CNSFCXP
ORDER BY P.NOREFERENCIA, D.ITEM;

PASO2_FIN:

GO

/* =============================================================================
   PASO 3 — Neto por lote (misma lógica sep-2026, solo CxP de la lista)
   ============================================================================= */
SET XACT_ABORT ON;

DECLARE @DOC TABLE (CNSFCXP varchar(20) NOT NULL PRIMARY KEY);
INSERT INTO @DOC (CNSFCXP) VALUES
  (N'03CM002017'),  /* FE5150 */
  (N'03CM002248'),  /* DPE12286 */
  (N'03CM002340'),  /* DPE12606 */
  (N'03CM002341');  /* DPE12612 */

DECLARE @MAL TABLE (
  CNSFCXP   varchar(20) NOT NULL,
  IDSERVICIO varchar(20) NOT NULL,
  PRIMARY KEY (CNSFCXP, IDSERVICIO)
);

DECLARE @FIX TABLE (
  CNSFCXP varchar(20) NOT NULL,
  ITEM    int NOT NULL,
  IVA_OK  decimal(18, 2) NOT NULL,
  NETO_OK decimal(18, 2) NOT NULL,
  PRIMARY KEY (CNSFCXP, ITEM)
);

INSERT INTO @MAL (CNSFCXP, IDSERVICIO)
SELECT D.CNSFCXP, D.IDSERVICIO
FROM dbo.FCXPD D
INNER JOIN @DOC C ON C.CNSFCXP = D.CNSFCXP
GROUP BY D.CNSFCXP, D.IDSERVICIO
HAVING COUNT(*) > 1
   AND MAX(D.VLR_NETO) - MIN(D.VLR_NETO) <= 1
   AND SUM(CASE
             WHEN ABS(D.VLR_NETO - (D.CANTIDAD * D.VALOR + COALESCE(D.VLR_IVA, 0))) > 1
             THEN 1 ELSE 0
           END) >= 1;

/* También artículos con varias líneas y cabecera <> detalle */
INSERT INTO @MAL (CNSFCXP, IDSERVICIO)
SELECT D.CNSFCXP, D.IDSERVICIO
FROM dbo.FCXPD D
INNER JOIN @DOC C ON C.CNSFCXP = D.CNSFCXP
INNER JOIN dbo.FCXP P ON P.CNSFCXP = D.CNSFCXP
WHERE P.ESTADO = N'N'
  AND COALESCE(P.CONTABILIZADA, 0) = 0
  AND NOT EXISTS (
    SELECT 1 FROM @MAL M WHERE M.CNSFCXP = D.CNSFCXP AND M.IDSERVICIO = D.IDSERVICIO
  )
GROUP BY D.CNSFCXP, D.IDSERVICIO, P.VLR_NETO
HAVING COUNT(*) > 1
   AND ABS(P.VLR_NETO - SUM(D.VLR_NETO)) > 0.01;

BEGIN TRAN;

IF (
  SELECT COUNT(*)
  FROM dbo.FCXP P
  INNER JOIN @DOC C ON C.CNSFCXP = P.CNSFCXP
  WHERE P.ESTADO = N'N'
    AND COALESCE(P.CONTABILIZADA, 0) = 0
    AND COALESCE(P.NROCOMPROBANTE, N'') = N''
    AND COALESCE(P.VLR_FLETE, 0) = 0
    AND COALESCE(P.VLR_ABONOS, 0) = 0
    AND COALESCE(P.VLR_NOTASDEBITO, 0) = 0
    AND COALESCE(P.VLR_NOTASCREDITO, 0) = 0
) <> (SELECT COUNT(*) FROM @DOC)
BEGIN
  ROLLBACK TRAN;
  THROW 53001, 'PASO 3: alguna CxP del bloque neto por lote no esta libre. No se cambio nada.', 1;
END;

INSERT INTO @FIX (CNSFCXP, ITEM, IVA_OK, NETO_OK)
SELECT D.CNSFCXP, D.ITEM,
       CONVERT(decimal(18, 2), H.IVA_OK),
       CONVERT(decimal(18, 2),
         CASE
           WHEN H.IVA_OK > 0
            AND ABS(H.BASE_OK - (D.CANTIDAD * D.VALOR + H.IVA_OK)) <= 0.05
            AND ABS(H.BASE_OK - (D.CANTIDAD * D.VALOR)) > 1
           THEN H.BASE_OK - ISNULL(D.VLR_DESCUENTO, 0)
           ELSE H.BASE_OK + H.IVA_OK - ISNULL(D.VLR_DESCUENTO, 0)
         END)
FROM dbo.FCXPD D
INNER JOIN @MAL M ON M.CNSFCXP = D.CNSFCXP AND M.IDSERVICIO = D.IDSERVICIO
CROSS APPLY (
  SELECT SUM(X.CANTIDAD * X.PCOSTO) AS BASE_OK,
         SUM(X.IVA) AS IVA_OK,
         COUNT(*) AS NGRUPOS
  FROM (
    SELECT PCOSTO,
           SUM(CANTIDAD) AS CANTIDAD,
           SUM(ISNULL(VLRIVA, 0)) AS IVA
    FROM dbo.IMOVH
    WHERE CNSMOV = D.N_PRESUP
      AND IDARTICULO = D.IDSERVICIO
      AND ISNULL(NOLOTEPEDIDO, N'') = ISNULL(D.NOLOTE, N'')
    GROUP BY PCOSTO
  ) X
  WHERE ABS(X.CANTIDAD - D.CANTIDAD) < 0.02
) H
WHERE H.NGRUPOS = 1;

;WITH PEND AS (
  SELECT D.CNSFCXP, D.ITEM, D.IDSERVICIO, D.CANTIDAD,
         ISNULL(D.VLR_DESCUENTO, 0) AS DTO,
         SUM(D.CANTIDAD) OVER (PARTITION BY D.CNSFCXP, D.IDSERVICIO) AS CANT_LIN
  FROM dbo.FCXPD D
  INNER JOIN @MAL M ON M.CNSFCXP = D.CNSFCXP AND M.IDSERVICIO = D.IDSERVICIO
  WHERE NOT EXISTS (
    SELECT 1 FROM @FIX F WHERE F.CNSFCXP = D.CNSFCXP AND F.ITEM = D.ITEM
  )
),
MOV AS (
  SELECT D.CNSFCXP, D.IDSERVICIO, MAX(D.N_PRESUP) AS CNSMOV
  FROM dbo.FCXPD D
  INNER JOIN @MAL M ON M.CNSFCXP = D.CNSFCXP AND M.IDSERVICIO = D.IDSERVICIO
  WHERE COALESCE(D.N_PRESUP, N'') <> N''
  GROUP BY D.CNSFCXP, D.IDSERVICIO
),
ENT AS (
  SELECT V.CNSFCXP, V.IDSERVICIO,
         SUM(H.CANTIDAD) AS CANT_ENT,
         SUM(H.CANTIDAD * H.PCOSTO) AS BASE_ENT,
         SUM(ISNULL(H.VLRIVA, 0)) AS IVA_ENT,
         COUNT(*) AS NGRUPOS
  FROM MOV V
  INNER JOIN (
    SELECT CNSMOV, IDARTICULO, ISNULL(NOLOTEPEDIDO, N'') AS LOTE, PCOSTO,
           SUM(CANTIDAD) AS CANTIDAD,
           SUM(ISNULL(VLRIVA, 0)) AS VLRIVA
    FROM dbo.IMOVH
    GROUP BY CNSMOV, IDARTICULO, ISNULL(NOLOTEPEDIDO, N''), PCOSTO
  ) H ON H.CNSMOV = V.CNSMOV AND H.IDARTICULO = V.IDSERVICIO
  GROUP BY V.CNSFCXP, V.IDSERVICIO
)
INSERT INTO @FIX (CNSFCXP, ITEM, IVA_OK, NETO_OK)
SELECT P.CNSFCXP, P.ITEM,
       CONVERT(decimal(18, 2), ROUND(E.IVA_ENT * P.CANTIDAD / NULLIF(P.CANT_LIN, 0), 2)),
       CONVERT(decimal(18, 2), ROUND(E.BASE_ENT * P.CANTIDAD / NULLIF(P.CANT_LIN, 0), 2)
         + ROUND(E.IVA_ENT * P.CANTIDAD / NULLIF(P.CANT_LIN, 0), 2) - P.DTO)
FROM PEND P
INNER JOIN ENT E ON E.CNSFCXP = P.CNSFCXP AND E.IDSERVICIO = P.IDSERVICIO
WHERE E.NGRUPOS = 1
  AND P.CANT_LIN > 0
  AND ABS(E.CANT_ENT - P.CANT_LIN) < 0.02;

IF EXISTS (
  SELECT 1
  FROM dbo.FCXPD D
  INNER JOIN @MAL M ON M.CNSFCXP = D.CNSFCXP AND M.IDSERVICIO = D.IDSERVICIO
  WHERE NOT EXISTS (
    SELECT 1 FROM @FIX F WHERE F.CNSFCXP = D.CNSFCXP AND F.ITEM = D.ITEM
  )
)
BEGIN
  ROLLBACK TRAN;
  THROW 53002, 'PASO 3: hay lineas sin neto por lote calculable. Revise IMOVH/N_PRESUP. No se cambio nada.', 1;
END;

UPDATE D
SET VLR_IVA = F.IVA_OK,
    VLR_NETO = F.NETO_OK
FROM dbo.FCXPD D
INNER JOIN @FIX F ON F.CNSFCXP = D.CNSFCXP AND F.ITEM = D.ITEM
WHERE ABS(D.VLR_IVA - F.IVA_OK) > 0.01
   OR ABS(D.VLR_NETO - F.NETO_OK) > 0.01;

UPDATE P
SET VLR_IVA = X.IVA,
    VLR_NETO = X.NETO,
    SALDO = X.NETO
FROM dbo.FCXP P
INNER JOIN @DOC C ON C.CNSFCXP = P.CNSFCXP
INNER JOIN (
  SELECT D.CNSFCXP,
         CONVERT(decimal(18, 2), SUM(D.VLR_IVA)) AS IVA,
         CONVERT(decimal(18, 2), SUM(D.VLR_NETO)) AS NETO
  FROM dbo.FCXPD D
  GROUP BY D.CNSFCXP
) X ON X.CNSFCXP = P.CNSFCXP;

IF EXISTS (
  SELECT 1
  FROM dbo.FCXP P
  INNER JOIN @DOC C ON C.CNSFCXP = P.CNSFCXP
  INNER JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
  GROUP BY P.CNSFCXP, P.VLR_IVA, P.VLR_NETO, P.SALDO
  HAVING ABS(SUM(D.VLR_IVA) - P.VLR_IVA) > 0.01
      OR ABS(SUM(D.VLR_NETO) - P.VLR_NETO) > 0.01
      OR ABS(P.SALDO - P.VLR_NETO) > 0.01
)
BEGIN
  ROLLBACK TRAN;
  THROW 53003, 'PASO 3: cabecera y detalle no coinciden tras el ajuste. No se cambio nada.', 1;
END;

COMMIT TRAN;

SELECT N'PASO 3 OK' AS RESULTADO, P.CNSFCXP, P.NOREFERENCIA,
       CONVERT(decimal(18, 2), P.VLR_NETO) AS NETO_CAB,
       CONVERT(decimal(18, 2), SUM(D.VLR_NETO)) AS NETO_DET
FROM dbo.FCXP P
INNER JOIN @DOC C ON C.CNSFCXP = P.CNSFCXP
INNER JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
GROUP BY P.CNSFCXP, P.NOREFERENCIA, P.VLR_NETO
ORDER BY P.NOREFERENCIA;

GO

PRINT N'Fin. Ejecute VERIFICACION_FCXP_FACTU_OCT2026.sql y contabilice solo filas con SEMAFORO = OK.';
