IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='SPK_NC_BALANCEO_CENTAVOS' AND XTYPE='P')
BEGIN
   DROP PROCEDURE SPK_NC_BALANCEO_CENTAVOS
END
GO
CREATE PROCEDURE DBO.SPK_NC_BALANCEO_CENTAVOS
@NROCOMPROBANTE VARCHAR(20)
AS
DECLARE @N_FACTURA VARCHAR(20)
DECLARE @CBTE   VARCHAR(20)
DECLARE @MES    INT
DECLARE @COMPROBANTE VARCHAR(4)
DECLARE @COMPANIA    VARCHAR(2)
DECLARE @ANO         VARCHAR(4)
DECLARE @SEDE        VARCHAR(5)
BEGIN
  PRINT 'EMPIEZO EL BALANCEO JOSE 1    @NROCOMPROBANTE'+COALESCE(@NROCOMPROBANTE,'NO HAY NADA')
   SELECT  @COMPANIA=@COMPANIA,@COMPROBANTE=COMPROBANTE,@ANO=ANO,@MES=MES FROM MCPE WHERE NROCOMPROBANTE=@NROCOMPROBANTE 
   
   DECLARE @DIFERENCIA DECIMAL(14,2)

   DECLARE BALANCEO_MCPE_CURSOR CURSOR FOR
   SELECT NROCOMPROBANTE FROM MCPE WHERE NROCOMPROBANTE=@NROCOMPROBANTE 
   OPEN BALANCEO_MCPE_CURSOR
   FETCH NEXT FROM BALANCEO_MCPE_CURSOR
   INTO @N_FACTURA
   WHILE @@FETCH_STATUS = 0
   BEGIN
	   PRINT  'INGRESO BALANCEO'
		 SELECT @DIFERENCIA = TOTALDEBITO - TOTALCREDITO 
		 FROM  MCPE 
		 WHERE NROCOMPROBANTE=@NROCOMPROBANTE 

		 PRINT 'DIFERENCIA  '+STR(@DIFERENCIA)
		 IF @DIFERENCIA < 0.00 AND  @DIFERENCIA>-2.00
		 BEGIN
			PRINT 'DIFERENCIA NEGATIVA '+STR(@DIFERENCIA)
		    SELECT @CBTE = MIN( MCHE.NROASIENTO) FROM MCHE WHERE TIPO = 'DB'
		     AND MCHE.NROCOMPROBANTE = @N_FACTURA
		 
 		   UPDATE  MCHE  SET MCHE.VALOR = MCHE.VALOR + (@DIFERENCIA * -1)
		    WHERE  MCHE.NROASIENTO      IN (@CBTE)
		 END
		 IF @DIFERENCIA > 0.00 AND  @DIFERENCIA<2.00
		 BEGIN
			PRINT 'DIFERNCIA MAYOR QUE CERO Y MENOR QUE DOS'
		    SELECT @CBTE = MIN(MCHE.NROASIENTO) FROM MCHE WHERE TIPO = 'CR'
		    AND MCHE.NROCOMPROBANTE = @N_FACTURA
		
		    UPDATE  MCHE   SET MCHE.VALOR = MCHE.VALOR + (@DIFERENCIA)
		    WHERE  MCHE.NROASIENTO      IN (@CBTE)
		 END
		 PRINT  'TERMINO Y VOY A SUMAR DE NUEVO'
		  EXEC SPK_NC_SUMA_DBCR @N_FACTURA
		 FETCH NEXT FROM BALANCEO_MCPE_CURSOR
	  INTO @N_FACTURA
   END
   CLOSE BALANCEO_MCPE_CURSOR
   DEALLOCATE BALANCEO_MCPE_CURSOR
END
