SELECT P.CNSFCXP, P.NOREFERENCIA,
  SUM(CASE WHEN COALESCE(D.VLR_IVA,0)>0 AND D.CUENTA_SER IN (N'14150502',N'14200502') THEN 1 ELSE 0 END) EXCL_IVA,
  SUM(CASE WHEN COALESCE(D.VLR_IVA,0)>0 AND COALESCE(D.CUENTA_IVA,N'')<>N'24080501' THEN 1 ELSE 0 END) IVA_CTA_MAL,
  SUM(CASE WHEN COALESCE(D.VLR_IVA,0)<=0 AND COALESCE(D.CUENTA_IVA,N'')<>N'' THEN 1 ELSE 0 END) SIN_IVA_CON_CTA,
  CASE WHEN SUM(CASE WHEN COALESCE(D.VLR_IVA,0)>0 AND (D.CUENTA_SER IN (N'14150502',N'14200502') OR COALESCE(D.CUENTA_IVA,N'')<>N'24080501') THEN 1 WHEN COALESCE(D.VLR_IVA,0)<=0 AND COALESCE(D.CUENTA_IVA,N'')<>N'' THEN 1 ELSE 0 END)=0 THEN N'OK' ELSE N'CUENTAS' END SEMAFORO
FROM @DOC X JOIN dbo.FCXP P ON P.CNSFCXP=X.CNSFCXP JOIN dbo.FCXPD D ON D.CNSFCXP=P.CNSFCXP
GROUP BY P.CNSFCXP, P.NOREFERENCIA ORDER BY P.NOREFERENCIA;
