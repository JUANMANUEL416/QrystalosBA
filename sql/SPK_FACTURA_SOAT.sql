IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME= 'SPK_FACTURA_SOAT' AND TYPE='P')
BEGIN
   DROP PROCEDURE SPK_FACTURA_SOAT
END

GO
CREATE PROC DBO.SPK_FACTURA_SOAT
@NOADMISION       VARCHAR(16),
@COMPANIA         VARCHAR(2),
@IDSEDE           VARCHAR(5),
@USUARIO          VARCHAR(12),
@NIT              VARCHAR(20),
@SYS_COMPUTERNAME VARCHAR(254),
@TFECHA           SMALLINT = 0,
@FECHAFAC         DATETIME = NULL 
WITH ENCRYPTION
AS
DECLARE @CNSFTR        VARCHAR(20), @PRE VARCHAR(20), @CONSECFTR INT, @CNSRESOL VARCHAR(50)
DECLARE @NVOCONSEC     VARCHAR(20)
DECLARE @DV            INT
DECLARE @TTEC          VARCHAR(10)
DECLARE @IDTERCERO     VARCHAR(20)
DECLARE @IDTERCEROF    VARCHAR(20)
DECLARE @IDPLAN        VARCHAR(6)        
DECLARE @CUENTACXC     VARCHAR(16)
DECLARE @CUENTACXC_RAD VARCHAR(16)
DECLARE @TV            VARCHAR(10)
DECLARE @EC            SMALLINT
DECLARE @DATO          VARCHAR(80)
DECLARE @DATO1         VARCHAR(80)
DECLARE @DATO2         VARCHAR(80)
DECLARE @DATO3         VARCHAR(80)
DECLARE @CERRADA       SMALLINT
DECLARE @FACTURADA     SMALLINT
DECLARE @FACTURABLE    SMALLINT
DECLARE @TIPOADM       VARCHAR(2)
DECLARE @IDAFILIADO    VARCHAR(20)
DECLARE @IDAREA_ALTA   VARCHAR(20) 
DECLARE @CCOSTO_ALTA   VARCHAR(20)
DECLARE @VRTOTAL       DECIMAL(14,2)
DECLARE @VRSERV        DECIMAL(14,2)
DECLARE @VRCOPA        DECIMAL(14,2)
DECLARE @VRPACO        DECIMAL(14,2)
DECLARE @VRDTO         DECIMAL(14,2)
DECLARE @VRABONO       DECIMAL(14,2)
DECLARE @TOTALFACTURA  DECIMAL(14,2)
DECLARE @VLRDEVOLUCION DECIMAL(14,2)
DECLARE @AUX1          INT
DECLARE @NOITEM_CUR    SMALLINT
DECLARE @IDFORMATOFTR  VARCHAR(20)
DECLARE @LIBERADA      VARCHAR(2)=''
DECLARE @CODUNG        VARCHAR(2)
DECLARE @CODPRG        VARCHAR(2)
DECLARE @PAQUETE       SMALLINT
DECLARE @TERCERO_AFI   VARCHAR(20)
DECLARE @PLAN_AFI      VARCHAR(6)
BEGIN 
   SELECT @IDTERCERO = IDTERCERO1 FROM HADM_T WHERE NOADMISION = @NOADMISION
   SELECT @IDPLAN    = IDPLAN FROM HADM WHERE NOADMISION = @NOADMISION
     
   SELECT @CERRADA    = CERRADA,    @FACTURADA   = FACTURADA,   @FACTURABLE  = FACTURABLE,
          @TIPOADM    = TIPOADM,    @IDAFILIADO = IDAFILIADO, @IDAREA_ALTA = IDAREA_ALTA, @CCOSTO_ALTA = CCOSTO_ALTA
   FROM   HADM WHERE NOADMISION = @NOADMISION
   SELECT @PAQUETE = COALESCE(PAQUETE,0) FROM HADM WHERE NOADMISION = @NOADMISION 
   
   SELECT @TERCERO_AFI=IDADMINISTRADORA, @PLAN_AFI=IDPLAN FROM AFI WHERE IDAFILIADO=@IDAFILIADO
   SELECT TOP 1 @TIPOADM=TIPOADM FROM HTAD WHERE TIPOATENCION='H' AND REQHABCAMA=1 AND ESTADO='Activo' AND TIPOADM NOT IN (SELECT DATO FROM USVGS WHERE IDVARIABLE='IDTARIFASOAT')
   
   IF DBO.FNK_VALORVARIABLE('MMCORPORATIVO') = 'SI'
   BEGIN
      IF DBO.FNK_VALORVARIABLE('CUF_CPF_DE_SEDE') = 'SI'
      BEGIN
         SELECT @CODUNG = DBO.FNK_CODUNG_CODPRG(@USUARIO,'CODUNG')
         SELECT @CODPRG = DBO.FNK_CODUNG_CODPRG(@USUARIO,'CODPRG')
      END
   END
   SELECT @DV = DIASVTO, @TTEC = COALESCE(TIPOTERCONTABLE,'NO')
   FROM   PPT 
   WHERE  IDTERCERO = @IDTERCERO 
   AND    IDPLAN    = CASE @IDTERCERO WHEN DBO.FNK_VALORVARIABLE('IDNITFONSAT') THEN DBO.FNK_VALORVARIABLE('IDPLANFONSAT') ELSE @IDPLAN END 
   PRINT '@TTEC='+@TTEC
   IF COALESCE(@TTEC,'NO')='NO'
   BEGIN
      RAISERROR('No Existe el Tipo de Tercero Contable... No se puede Continuar',16,1)
      RETURN
   END
   IF EXISTS(SELECT * FROM PPT WHERE IDTERCERO=@IDTERCERO AND IDPLAN=@IDPLAN AND COALESCE(MFORMATOFACTURAIND,0)=1 AND COALESCE(IDFORMATOFTR,'')<>'')
   BEGIN
      SELECT @IDFORMATOFTR=IDFORMATOFTR  FROM PPT WHERE IDTERCERO=@IDTERCERO AND IDPLAN=@IDPLAN AND COALESCE(MFORMATOFACTURAIND,0)=1 AND COALESCE(IDFORMATOFTR,'')<>''
   END
   ELSE
   BEGIN
      SELECT @IDFORMATOFTR=DBO.FNK_VALORVARIABLE('IDFORMATOFTR')
   END

   IF DBO.FNK_VALORVARIABLE('FACTSEDE') = 'SI'
   BEGIN
      SELECT @IDSEDE = IDSEDE FROM   HADM WHERE NOADMISION = @NOADMISION 
      IF DBO.FNK_VALORVARIABLE('FACTSEDEEQUIPO') = 'SI'
      BEGIN         
         IF COALESCE(@SYS_COMPUTERNAME,'') = ''
         BEGIN
            SELECT @SYS_COMPUTERNAME = HOST_NAME()
         END
         SELECT @IDSEDE = IDSEDE FROM UBEQ WHERE SYS_COMPUTERNAME = @SYS_COMPUTERNAME
      END
   END
   SELECT TOP 1 @CNSFTR=CNSFCT, @NVOCONSEC=N_FACTURA, @LIBERADA=ESTADO FROM FTR WHERE NOREFERENCIA=@NOADMISION AND ESTADO='L' AND TIPOFAC='I'

   IF @LIBERADA <> 'L'
   BEGIN
      EXEC SPK_GENCONSECUTIVO @COMPANIA,@IDSEDE,'@CNSFTR', @CNSFTR OUTPUT  
      SELECT @CNSFTR = @IDSEDE + REPLACE(SPACE(8 - LEN(@CNSFTR))+LTRIM(RTRIM(@CNSFTR)),SPACE(1),0)
            
      SET @NVOCONSEC = SPACE(20)
      EXEC SPK_GENNUMEROFACTURA @COMPANIA, @IDSEDE, NULL, @NVOCONSEC OUTPUT   
 	   PRINT 'REGRESE DE NUMFACTURA'
   END
   EXEC SPK_PREFIJOFACTURA @COMPANIA, @IDSEDE, @PRE OUTPUT  
 	PRINT '@IDTERCERO='+@IDTERCERO
 		

   SELECT @CUENTACXC = CUENTA, @CUENTACXC_RAD = CUENTARAD FROM TTEC
   WHERE TIPO = @TTEC
   PRINT '@CUENTACXC=' + @CUENTACXC
   IF @DV IS NULL
   BEGIN
      SELECT @DV = 30
   END
   IF @DV = 0
   BEGIN
      SELECT @DV = 30  
   END
               
   SELECT @TV = 'Credito'
   SELECT @EC = 0
               
   SELECT @IDTERCEROF = @IDTERCERO
            
   SELECT @DATO = DATO FROM USVGS WHERE IDVARIABLE = 'IDMONEDABASE'          
   SELECT @DATO3 = LEFT(DATO,20) FROM USVGS WHERE IDVARIABLE = 'IDFDEPFACTURACION'   
                    
   PRINT 'FACTURA 1'
   PRINT 'IDTERCERO = ' + @IDTERCEROF
   PRINT 'N_FACTURA = ' + @NVOCONSEC
   
   CREATE TABLE #FTRD1(CNSFTR VARCHAR(40), N_CUOTA	smallint IDENTITY, FECHA datetime,
                       DB_CR varchar(2), AREAPRESTACION varchar(20), UBICACION varchar(16),
                       VR_TOTAL float, IMPUTACION varchar(16), CCOSTO varchar (20),
                       PREFIJO varchar(6), ANEXO varchar(1024), REFERENCIA varchar(40), 
                       IDCIRUGIA varchar(20), CANTIDAD int, VALOR decimal(14,2),
                       VLR_SERVICI decimal(14,2), VLR_COPAGOS decimal(14,2),
                       VLR_PAGCOMP decimal(14,2), IDPROVEEDOR varchar(20),
                       NOADMISION varchar(16), NOPRESTACION	varchar(16), NOITEM int,	
                       AREAFUNCONT varchar(20), N_FACTURA varchar(16),
                       SUBCCOSTO varchar(4), PCOSTO	decimal(14,2), FECHAPREST datetime)
      
   INSERT INTO #FTRD1(CNSFTR, FECHA, DB_CR, AREAPRESTACION, UBICACION, VR_TOTAL,
                      IMPUTACION, CCOSTO, PREFIJO, ANEXO, REFERENCIA, IDCIRUGIA, CANTIDAD,
                      VALOR, VLR_SERVICI, VLR_COPAGOS, VLR_PAGCOMP, IDPROVEEDOR, NOADMISION,
                      NOPRESTACION, NOITEM, AREAFUNCONT, N_FACTURA, SUBCCOSTO, PCOSTO, FECHAPREST) 
   SELECT @CNSFTR, FECHA, 'DB', AREAPRESTACION, UBICACION, VR_TOTAL, IMPUTACION, 
          CCOSTO, PREFIJO, ANEXO, REFERENCIA, IDCIRUGIA, CANTIDAD, VALOR, VLR_SERVICI, VLR_COPAGOS,
          VLR_PAGCOMP, IDPROVEEDOR, NOADMISION, NOPRESTACION, NOITEM, AREAFUNCONT, @NVOCONSEC, SUBCCOSTO, PCOSTO,
          FECHA 
   FROM   HADM_S
   WHERE  NOADMISION   = @NOADMISION
   AND    FACTN        = 1
   PRINT 'INSERTE EN FTRD TEMPORAL 1'
   
   --REVISAMOS QUE NO VAYA A FACTURAR MAS DE UNA VEZ EL MISMO ITEM  
   IF (SELECT COALESCE(COUNT(*),0)
       FROM   (
               SELECT NOPRESTACION, NOITEM, COUNT(*) VECES
               FROM   #FTRD1
               GROUP BY NOPRESTACION, NOITEM
               HAVING COUNT(*) > 1
              ) X
      ) > 0
   BEGIN         
      DROP TABLE #FTRD1
      RAISERROR('MULTIPLE VEZ FACTURADA UN ITEM DE UNA PRESTACION.',16,1)        
      RETURN
   END
   IF DBO.FNK_VALORVARIABLE('BLOQUEADIAN')='SI'
   BEGIN
      IF DBO.FNK_VALORVARIABLE('FACTSEDE')='SI'
      BEGIN
         SELECT  @CNSRESOL=CNSRESOL FROM FDIAN WHERE IDENTIFICADOR=@IDSEDE AND VENCIDA=0 AND PROCEDENCIA = 'FTR' 
      END
      ELSE
      BEGIN
         SELECT  @CNSRESOL=CNSRESOL FROM FDIAN WHERE  VENCIDA=0 AND PROCEDENCIA = 'FTR'
      END
   END
   IF (SELECT COUNT(*) FROM FTR WHERE N_FACTURA=@NVOCONSEC)=0
   BEGIN       
      INSERT INTO FTR(CNSFCT, COMPANIA, CLASE, IDTERCERO, N_FACTURA, F_FACTURA, F_VENCE,
                      VR_TOTAL, COBRADOR, VENDEDOR, MONEDA, OCOMPRA, ESTADO, F_CANCELADO,
                      IDAFILIADO, EMPLEADO, NOREFERENCIA, PROCEDENCIA, TIPOFAC, OBSERVACION,
                      TIPOVENTA, VALORCOPAGO, DESCUENTO, VALORPCOMP, CREDITO, INDCARTERA,
                      INDCXC, MARCACONT, CONTABILIZADA, NROCOMPROBANTE, MARCA, INDASIGCXC,
                      IMPRESO, VALORSERVICIOS, CLASEANULACION, CNSLOG, USUARIOFACTURA, FECHAFAC,
                      MIVA, PIVA, VR_ABONOS, IDPLAN, FECHAPASOCXC, TIPOFIN, CNSFMAS, IDAREA_ALTA,
                      CCOSTO_ALTA, IDDEP, TIPOTTEC, CUENTACXC, CUENTACXC_RAD, IDSEDE,RDIAN,CNSRESOL,IDFORMATO) 
      SELECT @CNSFTR, @COMPANIA, 'C', 
             @IDTERCEROF, 
             @NVOCONSEC, 
             CASE @TFECHA 
                  WHEN 1 THEN @FECHAFAC 
                  ELSE GETDATE() 
             END,
             CASE @TFECHA 
                  WHEN 1 THEN @FECHAFAC +@DV
                  ELSE GETDATE() +@DV
             END, 0, NULL, NULL, LEFT(@DATO,2), NULL, 'P', NULL, 
             @IDAFILIADO, @USUARIO, @NOADMISION, 'SALUD', 'I', '', @TV, 0, 0, 0, 0, 
             0, 0, 0, 0, NULL, 0, 0, 0, 0, NULL, NULL, @USUARIO, GETDATE(), 0, 0, 0, 
             CASE @IDTERCEROF WHEN DBO.FNK_VALORVARIABLE('IDNITFONSAT') THEN DBO.FNK_VALORVARIABLE('IDPLANFONSAT') ELSE @IDPLAN END, 
             NULL, 'C', NULL, @IDAREA_ALTA, @CCOSTO_ALTA, @DATO3, @TTEC,
             @CUENTACXC, @CUENTACXC_RAD, @IDSEDE,CASE WHEN COALESCE(@CNSRESOL,'')<>'' THEN 1 ELSE 0 END,COALESCE(@CNSRESOL,''),@IDFORMATOFTR           
      PRINT 'INSERTE FTR 1'
   END
   ELSE
   BEGIN
      PRINT 'ACTUALIZO EN FTR'
      UPDATE FTR SET IDTERCERO=@IDTERCERO, IDPLAN=@IDPLAN, F_FACTURA=CASE @TFECHA WHEN 1 THEN @FECHAFAC ELSE DBO.FNK_FECHA_SIN_HORA(GETDATE()) END,
         F_VENCE=CASE @TFECHA WHEN 1 THEN @FECHAFAC + @DV ELSE DBO.FNK_FECHA_SIN_HORA(GETDATE()) + @DV END, ESTADO='P', 
         VR_TOTAL=0, EMPLEADO=@USUARIO, TIPOTTEC=@TTEC, CUENTACXC=@CUENTACXC, CUENTACXC_RAD=@CUENTACXC_RAD, CODUNG=@CODUNG, CODPRG=@CODPRG, PAQUETE=@PAQUETE
      WHERE N_FACTURA=@NVOCONSEC
   END

   INSERT INTO FTRD(CNSFTR, N_CUOTA, FECHA, DB_CR, AREAPRESTACION, UBICACION, VR_TOTAL,
                    IMPUTACION, CCOSTO, PREFIJO, ANEXO, REFERENCIA, IDCIRUGIA, CANTIDAD,
                    VALOR, VLR_SERVICI, VLR_COPAGOS, VLR_PAGCOMP, IDPROVEEDOR, NOADMISION,
                    NOPRESTACION, NOITEM, AREAFUNCONT, N_FACTURA, SUBCCOSTO, PCOSTO, FECHAPREST,
                    VLRNOTADB, VLRNOTACR )
   SELECT CNSFTR, N_CUOTA, FECHA, DB_CR, AREAPRESTACION, UBICACION, VR_TOTAL,
          IMPUTACION, CCOSTO, PREFIJO, ANEXO, REFERENCIA, IDCIRUGIA, CANTIDAD,
          VALOR, VLR_SERVICI, VLR_COPAGOS, VLR_PAGCOMP, IDPROVEEDOR, NOADMISION,
          NOPRESTACION, NOITEM, AREAFUNCONT, N_FACTURA, SUBCCOSTO, PCOSTO, FECHAPREST,
          0, 0
   FROM #FTRD1
   PRINT 'INSERTE EN FTRD REAL 1'
   DROP TABLE #FTRD1   
            
   SELECT @VRTOTAL = SUM(VR_TOTAL), @VRSERV = SUM(VLR_SERVICI), @VRCOPA = SUM(VLR_COPAGOS),
          @VRPACO  = SUM(VLR_PAGCOMP)
   FROM FTRD WHERE N_FACTURA = @NVOCONSEC
            
   SELECT @VRCOPA = 0
   UPDATE FTR SET VALORSERVICIOS = @VRSERV, VALORCOPAGO = @VRCOPA, VALORPCOMP = @VRPACO, VR_TOTAL = @VRTOTAL
   WHERE N_FACTURA = @NVOCONSEC
             
   SELECT @VLRDEVOLUCION = VALORSERVICIOS - VALORCOPAGO - VALORPCOMP -DESCUENTO - VR_ABONOS --OJO
   FROM FTR WHERE N_FACTURA = @NVOCONSEC                                                    --OJO     
             
   SELECT @TOTALFACTURA = VALORSERVICIOS - VALORCOPAGO - VALORPCOMP -DESCUENTO -- OJO QUITE MENOS ABONOS
   FROM FTR WHERE N_FACTURA = @NVOCONSEC                                       -- OJO
            
   IF @TOTALFACTURA >= 0
   BEGIN
      UPDATE FTR SET VR_TOTAL = ROUND(VALORSERVICIOS, 0) - VALORCOPAGO - VALORPCOMP -DESCUENTO -- OJO QUITE MENOS ABONOS
      WHERE  N_FACTURA = @NVOCONSEC      
   END
   ELSE
   BEGIN
      UPDATE FTR SET VR_TOTAL = 0
      WHERE  N_FACTURA = @NVOCONSEC    
   END
   PRINT 'ANTES DE IMPUESTOS 1'
   IF @EC <> 1
   BEGIN
      EXEC SPK_FAC_IMPDEDUC @NIT, @CNSFTR, @NVOCONSEC, @VRSERV    
   END
   PRINT 'DESPUES DE IMPUESTOS 1'         
   PRINT 'ACTUALIZO HPRED 1'
   UPDATE HPRED SET FACTURADA = 1, N_FACTURA = @NVOCONSEC,UTISOAT=1
   FROM   FTRD
   WHERE  HPRED.NOPRESTACION  = FTRD.NOPRESTACION
   AND    HPRED.NOITEM        = FTRD.NOITEM
   AND    FTRD.N_FACTURA      = @NVOCONSEC       
   PRINT  'TERMINO DE ACTUALIZAR HPRED 1'
   SELECT @DATO2 = DATO FROM USVGS WHERE IDVARIABLE = 'IDNITFONSAT'
   PRINT ' EMPIEZO A ACTUALIZAR HACTRAND 1'
      
   IF @IDTERCERO = @DATO2
   BEGIN
      UPDATE HACTRAND SET N_FCT_FYG = @NVOCONSEC 
      FROM   HACTRAND INNER JOIN HADM ON HACTRAND.CNSHACTRAN = HADM.CNSHACTRAN
      WHERE  HADM.NOADMISION      = @NOADMISION
      AND    HACTRAND.PROCEDENCIA = 'QX'
      AND    HACTRAND.NOREFERENCIA = @NOADMISION  
   END
   ELSE
   BEGIN
      UPDATE HACTRAND SET N_FCT_ASEG = @NVOCONSEC 
      FROM   HACTRAND INNER JOIN HADM ON HACTRAND.CNSHACTRAN = HADM.CNSHACTRAN
      WHERE  HADM.NOADMISION      = @NOADMISION
      AND    HACTRAND.PROCEDENCIA = 'QX'
      AND    HACTRAND.NOREFERENCIA = @NOADMISION 
   END
   PRINT 'TERMINO DE ACTUALIZAR HACTRAND 1'
   PRINT 'VOY A SPK_NC_CONTAB_FTR'

   IF DBO.FNK_VALORVARIABLE('CONTAB_FTR_JOB')='SI'
	BEGIN
		INSERT INTO FTRCO(N_FACTURA, USUARIO, SYS_COMPUTERNAME, COMPANIA, SEDE)
		SELECT @NVOCONSEC,@USUARIO,@SYS_COMPUTERNAME,@COMPANIA,@IDSEDE
	END
	ELSE
	BEGIN
		EXEC SPK_NC_CONTAB_FTR @NVOCONSEC, @COMPANIA, @USUARIO, @SYS_COMPUTERNAME, @IDSEDE, ''
		PRINT 'REGRESE DE SPK_NC_CONTAB_FTR'   
	END
    
   
  IF @LIBERADA = 'L'
  BEGIN
      UPDATE HADMF SET ESTADO='P'
      WHERE NOADMISION=@NOADMISION AND ESTADO='L' AND N_FACTURA=@NVOCONSEC
   END  
   ELSE
   BEGIN   
      INSERT INTO HADMF(NOADMISION, N_FACTURA, CNSFCT, ESTADO, ANEXOUNICO, IDTERCERO, IDPLAN, ITEM, DESCRIPCION)
      SELECT @NOADMISION, @NVOCONSEC, @CNSFTR, 'P', 1, @IDTERCEROF, 
             CASE @IDTERCEROF WHEN DBO.FNK_VALORVARIABLE('IDNITFONSAT') THEN DBO.FNK_VALORVARIABLE('IDPLANFONSAT') ELSE @IDPLAN END,
             1, NULL
   END
   PRINT 'TERMINO FACTURA 1'
      
      /****************************************************************************/
      /*LOS SOBRANTES PARA LA TERCERA FACTURA PASAN A UNA ADMISION DE CONTINUACION*/
      /****************************************************************************/
      SELECT @AUX1 = COUNT(1) FROM HADM_S WHERE NOADMISION = @NOADMISION AND FACTN = 3
      IF @AUX1 >= 1
      BEGIN
         PRINT 'TRASLADAR 3 FACTURA'
         DECLARE @NOPRESTACION_CUR VARCHAR(16)
         DECLARE @RPDXVEZ          VARCHAR(20)
         DECLARE @EJ               VARCHAR(2000)
         DECLARE @NUMADM           INT
         DECLARE @NVAADM           VARCHAR(16)
         EXEC SPK_GENCONSECUTIVO @COMPANIA,@IDSEDE,'@CNSFTR', @RPDXVEZ OUTPUT  
         SELECT @RPDXVEZ = @IDSEDE + REPLACE(SPACE(8 - LEN(@RPDXVEZ))+LTRIM(RTRIM(@RPDXVEZ)),SPACE(1),0)
         SELECT @EJ = 'DECLARE @AUXJ INT; SELECT @AUXJ= COUNT(*) FROM HADM WHERE NOADMISION LIKE '''+@NOADMISION+
                      '%'' ; INSERT INTO RPDX (CNS, CANTIDAD1) SELECT '''+@RPDXVEZ+''', @AUXJ '
         EXEC(@EJ)
         SELECT @NUMADM = CANTIDAD1 FROM RPDX WHERE CNS = @RPDXVEZ
         PRINT 'VECES='+STR(@NUMADM)
         SELECT @NVAADM = @NOADMISION + '-'+CAST(@NUMADM AS VARCHAR(3))
         PRINT '@NVAADM='+@NVAADM
         INSERT INTO HADM (NOADMISION, IDAFILIADO, FECHA, IDSEDE, IDPLAN, IDTERCERO, TIPOADM, HABCAMA, VIAINGRESO, 
                           CAUSAEXTERNA, CONDUSUARIA, DXINGRESO, DXEGRESO, COMPLICACION, TIPODISCAP, GRADODISCAP,
                           NOPOLIZA, NOCARNET, NOAUTORIZACION, FECHAVCEAUT, FECHAALTA, FECHASALIDA, CAUSASALIDA,
                           ESTADOPSALIDA, VRDEPOSITO, RESPCUENTA, ESTADO, URG_NOMBRE, URG_TELE, URG_DIR, IDMEDICOING,
                           IDMEDICOTRA, CAUSABMUERTE, ENFSOBREAG, OBS, FACTURADA, N_FACTURA, CNSFCT, CERRADA, PCUBRIMIENTO,
                           USUARIO, DXSALIDA1, DXSALIDA2, DXSALIDA3, DESTINO, ESTADOSALIDA, RIPS, NIVELSOCIOEC, TIPOPOLIZA,
                           IDMEDICOTRA2, IDMEDICOTRA3, ENVIO, FACTURABLE, COPAGO, COPAGONOAUTORIZACION, COPAGOVALOR, TIPOFAC,
                           VFACTURAS, DESCUENTO, TIPODTO, USUARIOALTA, TIPOCREDITO, CREDITO, INDDEVOLUCION, INDPROCESARDEV,
                           MARCA, ENVIOMARCA, VENCEAUT, MTOPE, TIPOTOPE, FECHATOPE, VALORTOPE, TOPEOTROTERCERO, CONTINUACION,
                           NOADMISIONCONT, FECHATRASHOS, CXP, VLRUTOTRAHADM, IDPROVEEDOR, TIPOCONT, IDCONTRATO, IDAREA_ALTA,
                           PREADMISION, IDCIRUGIA, PYP, CLASENOPROC, URG_VINCULO, A24H, A2448H, A4872H, A72H30D, CCOSTO_ALTA,
                           FECHAPRE, LIQESTANCIA, FACTURADAPARCIAL, TIPOCOPAGO, PROCEDENCIA, CNSHACTRAN, DECLARIESGOS, 
                           IDMEDICOALTA, CLASEING, PASADACENTRAL, CNSENTREGA, CODUNG, FECHAALTAMED, ITFC, CNSITFC, EMBARAZADA,
                           CNSTRIAGE, TTRIAGE, IDDXULTIMO, CCOSTOULTIMO, UATENINIURG, ESINSTPROV, ESEINST, FECHAESEINST, 
                           MARCAATRASO, REVESPECIALISTA, REFERIDO, IDREFERIDO, MANCOPAGOEXT, NOAUTORIZACIONEXT, VLR_COPAGOEXTERNO,
                           DIASHOSPITALIZACION, HORASQUIROFANO, TITULARPOLIZA, SINCRONIZADO, NOCOTIZACION, USUALTAMED, IDPLAN_AFI,
                           IDTERCERO_AFI, PAQUETE,TIPOESTANCIA,FECHAALTAENF)
         SELECT @NVAADM, IDAFILIADO, CONVERT(SMALLDATETIME,GETDATE()), IDSEDE, @PLAN_AFI, @TERCERO_AFI, @TIPOADM, HABCAMA, VIAINGRESO, 
                           CAUSAEXTERNA, CONDUSUARIA, DXINGRESO, DXEGRESO, COMPLICACION, TIPODISCAP, GRADODISCAP,
                           NOPOLIZA, NOCARNET, NOAUTORIZACION, FECHAVCEAUT, FECHAALTA, FECHASALIDA, CAUSASALIDA,
                           ESTADOPSALIDA, VRDEPOSITO, RESPCUENTA, ESTADO, URG_NOMBRE, URG_TELE, URG_DIR, IDMEDICOING,
                           IDMEDICOTRA, CAUSABMUERTE, ENFSOBREAG, OBS, FACTURADA, N_FACTURA, CNSFCT, 3, PCUBRIMIENTO,
                           USUARIO, DXSALIDA1, DXSALIDA2, DXSALIDA3, DESTINO, ESTADOSALIDA, RIPS, NIVELSOCIOEC, TIPOPOLIZA,
                           IDMEDICOTRA2, IDMEDICOTRA3, ENVIO, FACTURABLE, COPAGO, COPAGONOAUTORIZACION, COPAGOVALOR, TIPOFAC,
                           VFACTURAS, DESCUENTO, TIPODTO, USUARIOALTA, TIPOCREDITO, CREDITO, INDDEVOLUCION, INDPROCESARDEV,
                           MARCA, ENVIOMARCA, VENCEAUT, MTOPE, TIPOTOPE, FECHATOPE, VALORTOPE, TOPEOTROTERCERO, 1,
                           NOADMISIONCONT, FECHATRASHOS, CXP, VLRUTOTRAHADM, IDPROVEEDOR, 'I', IDCONTRATO, IDAREA_ALTA,
                           PREADMISION, IDCIRUGIA, PYP, CLASENOPROC, URG_VINCULO, A24H, A2448H, A4872H, A72H30D, CCOSTO_ALTA,
                           FECHAPRE, LIQESTANCIA, FACTURADAPARCIAL, TIPOCOPAGO, PROCEDENCIA, CNSHACTRAN, DECLARIESGOS, 
                           IDMEDICOALTA, CLASEING, PASADACENTRAL, CNSENTREGA, CODUNG, FECHAALTAMED, ITFC, CNSITFC, EMBARAZADA,
                           CNSTRIAGE, TTRIAGE, IDDXULTIMO, CCOSTOULTIMO, UATENINIURG, ESINSTPROV, ESEINST, FECHAESEINST, 
