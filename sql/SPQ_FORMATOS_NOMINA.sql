CREATE OR ALTER PROCEDURE DBO.SPQ_FORMATOS_NOMINA @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
SET DATEFORMAT dmy

DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(12), @COMPANIA VARCHAR(2), @IDSEDE VARCHAR(10), @SYS_COMPUTERNAME 
	VARCHAR(200), @DATOS VARCHAR(MAX), @PROCESO VARCHAR(10), @CONTRATOS BIT, @ESTADO VARCHAR(10), @TIPO VARCHAR(20), @OBSERVACION VARCHAR(255), @CNSFORMATO VARCHAR(
		20), @CUERPO VARCHAR(MAX)
DECLARE @IDNEMP VARCHAR(20), @BASICO DECIMAL(14, 2), @CODCARGO VARCHAR(20), @FECHAING DATETIME, @FECHASAL DATETIME, @JEFERH VARCHAR(12), @DESCARGO VARCHAR(255), 
	@TCONTRATO VARCHAR(20), @AUXTRANSP DECIMAL(14, 2), @OTROSDEV DECIMAL(14, 2), @OBSERVACIONES VARCHAR(124), @CONCEPTO1 VARCHAR(MAX), @VALOR1 DECIMAL(14, 2), 
	@CONCEPTO2 VARCHAR(MAX), @VALOR2 DECIMAL(14, 2), @CONCEPTO3 VARCHAR(MAX), @VALOR3 DECIMAL(14, 2), @CONCEPTO4 VARCHAR(MAX), @VALOR4 DECIMAL(14, 2), @CONCEPTO5 
	VARCHAR(MAX), @VALOR5 DECIMAL(14, 2), @USUARIOCERT VARCHAR(12), @CNSOLICERT VARCHAR(20), @CNSCERT VARCHAR(20)
DECLARE @TITULO VARCHAR(50), @CODIGO VARCHAR(20), @VERSION VARCHAR(50), @FECHA DATE

BEGIN
	SELECT *
	INTO #JSON
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	SELECT @MODELO = MODELO, @METODO = METODO, @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON

	IF @METODO = 'CRUD_NCERTC'
	BEGIN
		SELECT @DATOS = DATOS
		FROM OPENJSON(@PARAMETROS) WITH (DATOS NVARCHAR(MAX) AS JSON)

		SELECT @PROCESO = PROCESO, @CNSFORMATO = CNSFORMATO, @CONTRATOS = CASE 
				WHEN CONTRATOS = 'true'
					THEN 1
				ELSE 0
				END, @ESTADO = ESTADO, @OBSERVACION = OBSERVACION, @TITULO = TITULO, @CODIGO = CODIGO, @VERSION = VERSION, @FECHA = FECHA
		FROM OPENJSON(@DATOS) WITH (
				PROCESO VARCHAR(20) '$.PROCESO', CNSFORMATO VARCHAR(20) '$.CNSFORMATO', CONTRATOS VARCHAR(10) '$.CONTRATOS', ESTADO VARCHAR(10) '$.ESTADO', 
				OBSERVACION VARCHAR(255) '$.OBSERVACION', TITULO VARCHAR(50) '$.TITULO', CODIGO VARCHAR(20) '$.CODIGO', VERSION VARCHAR(50) '$.VERSION', FECHA DATE 
				'$.FECHA'
				)

		IF @PROCESO = 'Nuevo'
		BEGIN
			BEGIN TRY
				SELECT @IDSEDE = COALESCE(UBEQ.IDSEDE, USUSU.IDSEDE), @COMPANIA = UBEQ.COMPANIA
				FROM USUSU
				LEFT JOIN UBEQ ON USUSU.SYS_ComputerName = UBEQ.SYS_ComputerName
				WHERE USUARIO = @USUARIO

				PRINT 'AQUI LLAMO A GENCONSECUTIVO @IDSEDE=' + COALESCE(@IDSEDE, 'SIN SEDE') + ' COMPANIA' + COALESCE(@COMPANIA, 'CIA')

				SELECT @CNSFORMATO = ''

				EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@NCERTC', @NVOCONSEC = @CNSFORMATO OUTPUT

				PRINT '@CNSFORMATO=' + COALESCE(@CNSFORMATO, '')

				INSERT INTO NCERTC (CNSFORMATO, ENCABEZADO, CUERPO, FINAL, ESTADO, CONTRATOS, TIPO, MINUTA, OBSERVACION, RLOGO, LSUPER, WEB, TITULO, CODIGO, VERSION, FECHA
					)
				SELECT @CNSFORMATO, NULL, NULL, NULL, @ESTADO, @CONTRATOS, 'Contrato', NULL, @OBSERVACION, NULL, NULL, 1, @TITULO, @CODIGO, @VERSION, @FECHA
			END TRY

			BEGIN CATCH
				INSERT INTO @TBLERRORES (ERROR)
				SELECT ERROR_MESSAGE()
			END CATCH
		END

		IF @PROCESO = 'Edita'
		BEGIN
			IF EXISTS (
					SELECT *
					FROM NCERTC
					WHERE CNSFORMATO = @CNSFORMATO
					)
			BEGIN
				PRINT @CONTRATOS

				UPDATE NCERTC
				SET ESTADO = @ESTADO, CONTRATOS = @CONTRATOS, OBSERVACION = @OBSERVACION, TITULO = @TITULO, CODIGO = @CODIGO, VERSION = @VERSION, FECHA = @FECHA
				WHERE CNSFORMATO = @CNSFORMATO
			END
			ELSE
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'No se encontro el Certificado, Verifique e intente de nuevo'
			END
		END

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK, ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK

		RETURN
	END

	IF @METODO = 'TRAER_CUERPO'
	BEGIN
		SELECT @CNSFORMATO = CNSFORMATO, @TIPO = TIPO
		FROM OPENJSON(@PARAMETROS) WITH (CNSFORMATO VARCHAR(20) '$.CNSFORMATO', TIPO VARCHAR(20) '$.TIPO')

		IF EXISTS (
				SELECT *
				FROM NCERTC
				WHERE CNSFORMATO = @CNSFORMATO
				)
		BEGIN
			SELECT 'OK' OK, CUERPO = FORMATOWEB
			FROM NCERTC
			WHERE CNSFORMATO = @CNSFORMATO
		END
		ELSE
		BEGIN
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'No se encontro el Formato Solicitado, verifique e intente de nuevo'
		END

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK, ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK

		RETURN
	END

	IF @METODO = 'GUARDAR_CUERPO'
	BEGIN
		SELECT @DATOS = CUERPO
		FROM OPENJSON(@PARAMETROS) WITH (CUERPO NVARCHAR(MAX) AS JSON)

		PRINT @DATOS

		SELECT @CNSFORMATO = CNSFORMATO, @TIPO = TIPO, @CUERPO = CUERPO
		FROM OPENJSON(@DATOS) WITH (CNSFORMATO VARCHAR(20) '$.CNSFORMATO', TIPO VARCHAR(20) '$.TIPO', CUERPO VARCHAR(MAX) '$.CUERPO')

		IF EXISTS (
				SELECT *
				FROM NCERTC
				WHERE CNSFORMATO = @CNSFORMATO AND TIPO = @TIPO
				)
		BEGIN
			BEGIN TRY
				UPDATE NCERTC
				SET FORMATOWEB = @CUERPO
				WHERE CNSFORMATO = @CNSFORMATO AND TIPO = @TIPO
			END TRY

			BEGIN CATCH
				INSERT INTO @TBLERRORES (ERROR)
				SELECT ERROR_MESSAGE()
			END CATCH
		END
		ELSE
		BEGIN
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'No se Encontro el formato '
		END

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK, ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK

		RETURN
	END

	IF @METODO = 'TRAER_CONCEPTOS'
	BEGIN
		SELECT 'OK'

		SELECT CODCONCEPTO value, DESCRIPCION label
		FROM NCON
		WHERE ESTADO = 'Activo'
	END

	IF @METODO = 'CRUD_NCERT'
	BEGIN
		BEGIN TRY
			SELECT @IDNEMP = IDNEMP, @BASICO = BASICO, @CODCARGO = CODCARGO, @FECHAING = FECHAING, @FECHASAL = FECHASAL, @JEFERH = JEFERH, @USUARIOCERT = USUARIOCERT, 
				@TCONTRATO = TCONTRATO, @AUXTRANSP = AUXTRANSP, @OTROSDEV = OTROSDEV, @OBSERVACIONES = OBSERVACIONES, @CONCEPTO1 = CONCEPTO1, @VALOR1 = VALOR1, 
				@CONCEPTO2 = CONCEPTO2, @VALOR2 = VALOR2, @CONCEPTO3 = CONCEPTO3, @VALOR3 = VALOR3, @CONCEPTO4 = CONCEPTO4, @CNSOLICERT = CNSOLICERT, @VALOR4 = VALOR4, 
				@CONCEPTO5 = CONCEPTO5, @VALOR5 = VALOR5, @ESTADO = ESTADO, @DESCARGO = DESCARGO
			FROM OPENJSON(@PARAMETROS) WITH (
					IDNEMP VARCHAR(20) '$.IDNEMP', BASICO DECIMAL(14, 2) '$.BASICO', CODCARGO VARCHAR(20) '$.CODCARGO', FECHAING DATETIME '$.FECHAING', FECHASAL 
					DATETIME '$.FECHASAL', JEFERH VARCHAR(255) '$.JEFERH', TCONTRATO VARCHAR(20) '$.TCONTRATO', AUXTRANSP DECIMAL(14, 2) '$.AUXTRANSP', OTROSDEV 
					DECIMAL(14, 2) '$.OTROSDEV', OBSERVACIONES VARCHAR(124) '$.OBSERVACIONES', CONCEPTO1 VARCHAR(MAX) '$.CONCEPTO1', VALOR1 DECIMAL(14, 2) 
					'$.VALOR1', CONCEPTO2 VARCHAR(MAX) '$.CONCEPTO2', VALOR2 DECIMAL(14, 2) '$.VALOR2', CONCEPTO3 VARCHAR(MAX) '$.CONCEPTO3', VALOR3 DECIMAL(14, 2) 
					'$.VALOR3', CONCEPTO4 VARCHAR(MAX) '$.CONCEPTO4', VALOR4 DECIMAL(14, 2) '$.VALOR4', CONCEPTO5 VARCHAR(MAX) '$.CONCEPTO5', VALOR5 DECIMAL(14, 2) 
					'$.VALOR5', USUARIOCERT VARCHAR(12) '$.USUARIOCERT', ESTADO VARCHAR(10), DESCARGO VARCHAR(255) '$.DESCARGO', CNSOLICERT INT '$.CNSOLICERT'
					)

			BEGIN
				SELECT @IDSEDE = COALESCE(UBEQ.IDSEDE, USUSU.IDSEDE), @COMPANIA = UBEQ.COMPANIA
				FROM USUSU
				LEFT JOIN UBEQ ON USUSU.SYS_ComputerName = UBEQ.SYS_ComputerName
				WHERE USUARIO = @USUARIO

				SELECT @CNSCERT = ''

				EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '', @NVOCONSEC = @CNSCERT OUTPUT

				PRINT '@CNSCERT=' + COALESCE(@CNSCERT, '')

				INSERT INTO NCERT (
					CNSCERT, FECHA, NUMDOC, BASICO, CODCARGO, FECHAING, FECHASAL, JEFERH, USUARIO, TCONTRATO, AUXTRANSP, OTROSDEV, OBSERVACIONES, CONCEPTO1, VALOR1, 
					CONCEPTO2, VALOR2, CONCEPTO3, VALOR3, CONCEPTO4, VALOR4, CONCEPTO5, VALOR5, CNSFORMATO, ESTADO, DESCARGO
					)
				SELECT @CNSCERT, GETDATE(), @IDNEMP, @BASICO, @CODCARGO, @FECHAING, @FECHASAL, (
						SELECT DATO
						FROM USVGS
						WHERE IDVARIABLE = 'USUARIOJEFERH'
						), @USUARIOCERT, @TCONTRATO, @AUXTRANSP, @OTROSDEV, @OBSERVACIONES, @CONCEPTO1, @VALOR1, @CONCEPTO2, @VALOR2, @CONCEPTO3, @VALOR3, 
					@CONCEPTO4, @VALOR4, @CONCEPTO5, @VALOR5, @CNSFORMATO, 'Generado', @DESCARGO
			END

			BEGIN
				UPDATE NSOLICERT
				SET ESTADO = 'Generado', IDNCERT = @CNSCERT
				WHERE CNSOLICERT = JSON_VALUE(@PARAMETROS, '$.CNSOLICERT')
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK

		RETURN
	END

	IF @METODO = 'TRAER_NCERT'
	BEGIN
		SELECT @CNSCERT = CNSCERT
		FROM OPENJSON(@PARAMETROS) WITH (CNSCERT VARCHAR(20) '$.CNSCERT')

		SELECT 'OK' OK

		SELECT NSOLICERT.CARGO, NSOLICERT.FECHINGRESO, NSOLICERT.TIPCONTRATO, NSOLICERT.SUELDO, NCERT.AUXTRANSP, REPLACE(TRANSLATE(NCERT.DESCARGO, 
					'0123456789', '          '), '  ', ' ') AS DESCARGO, NCERT.OTROSDEV, NCERT.FECHAING, NCERT.BASICO, NCERT.OBSERVACIONES, NCERT.FECHA, NCERT.
			FECHASAL, NCERT.TCONTRATO, NCERT.SALPROMEDIO, NCERT.CODCARGO, NEMP.DOCIDEMPLEADO, NEMP.EMAIL, CONCAT (NEMP.PRIMERNOMBRE, ' ', NEMP.SEGUNDONOMBRE, ' ', NEMP.PRIMERAPELLIDO, ' ', NEMP.SEGUNDOAPELLIDO
				) AS NOMBREEMPLE, A.DICOM, U.NOMBRE AS NOMBREJEFE, U.CARGO AS CARGOJEFE, NSOLICERT.DIRIGIDOA, CONCEPTO2, VALOR2, CONCEPTO3, VALOR3, CONCEPTO4, VALOR4
		FROM NCERT
		INNER JOIN NEMP ON NCERT.NUMDOC = NEMP.NUMDOC
		INNER JOIN NSOLICERT ON NCERT.CNSCERT = NSOLICERT.IDNCERT
		LEFT JOIN USUSU U ON U.USUARIO = NCERT.JEFERH
		LEFT JOIN ARCHIVOS A ON A.ID = U.IDFIRMA
		WHERE NCERT.CNSCERT = JSON_VALUE(@PARAMETROS, '$.CNSCERT')

		RETURN
	END
END
