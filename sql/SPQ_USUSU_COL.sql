CREATE OR ALTER PROCEDURE DBO.SPQ_USUSU_COL
@JSON  NVARCHAR(MAX)
WITH
ENCRYPTION
AS
DECLARE @PARAMETROS          NVARCHAR(MAX) ,@MODELO           VARCHAR(100)    ,@METODO        VARCHAR(100)  ,@USUARIO        VARCHAR(12)
		,@GRUPO               VARCHAR(8)     ,@SYS_COMPUTERNAME VARCHAR(254)    ,@SEDE          VARCHAR(5)	 ,@A              INT
		,@IDENTITY            INT 
		,@PROCESO             VARCHAR(20)    ,@USUSU    NVARCHAR(MAX)           ,@DATACLAVE     NVARCHAR(MAX)
		,@COMPANIA            VARCHAR(2)
		,@USUARIO_USUSU       VARCHAR(12)
		,@NOMBRE              VARCHAR(40)
		,@GRUPO_USUSU         VARCHAR(8)    ,@TIPO                    VARCHAR(1)
		,@IDMEDICO            VARCHAR(12)   ,@SYS_ComputerName_USUSU  VARCHAR(254)
		,@NIVELFUNCIONARIO    SMALLINT      ,@CODCAJERO               VARCHAR(20)     
		,@FECHACAMBIO         DATETIME      ,@FECHACAMBIO_STR         VARCHAR(10)
		,@ESTADO              VARCHAR(8)    ,@ESMEDICO                SMALLINT
		,@IDSEDE              VARCHAR(5)    ,@IDIMAGEN                VARCHAR(20)
		,@CARGO               VARCHAR(50)   ,@TELEFONO                VARCHAR(50)
		,@CELULAR             VARCHAR(50)   ,@FECHAVENCE              DATETIME
		,@FECHAVENCE_STR      VARCHAR(10)   ,@CONECTADO               TINYINT
		,@SYS_COMP_CONECTADO  VARCHAR(254)  ,@FECHA_CONEC             DATETIME
		,@FECHA_CONEC_STR     VARCHAR(10)   ,@KEYUSER                 VARBINARY
		,@IDTERCERO           VARCHAR(20)   ,@IDFIRMA                 VARCHAR(20)
		,@IDEMPLEADO          VARCHAR(20)   ,@TIPOUSUARIOADM         VARCHAR(12)
		,@IDDEPURAR           BIT           ,@EMAIL                   VARCHAR(100)
		,@GENERO              VARCHAR(1)    ,@SOLOWEB                 BIT
		,@FECHANACIMIENTO     DATE          ,@FECHANACIMIENTO_STR     VARCHAR(10)
		,@IDEMPRESA           VARCHAR(20)   ,@F_RETIRO                DATETIME
		,@F_RETIRO_STR        VARCHAR(10)   ,@IDBODEGA                VARCHAR(20)
		,@CARNET              VARCHAR(20)	,@PORCENTAJE			  SMALLINT
       
		,@TELEGRAMID          VARCHAR(20)   ,@NOMBRES                 VARCHAR(250)
		,@APELLIDOS           VARCHAR(250)  ,@DOCID                   VARCHAR(50)
		,@TIPOIDENT           VARCHAR(20)   ,@DEPARTAMENTO            VARCHAR(100)
		,@CAMBIACLAVE         BIT           
		,@CLAVE               VARCHAR(100)  ,@CLAVE2                  VARCHAR(100)
		,@CLAVENUEVA          VARBINARY(128),@CLAVENUEVA2             VARBINARY(MAX)   
		,@CODIGO				VARCHAR(20)   ,@DFA					 BIT = 0
		,@MENSAJE			 VARCHAR(MAX)	,@CLAVE_SISPRO            VARCHAR(200)
		,@ACCESO_CUALQUIER_IP BIT=0
BEGIN
	SET LANGUAGE Spanish
	SET DATEFORMAT dmy
   
	SELECT @A = ISJSON(@JSON)
	IF @A = 0
	BEGIN
		RAISERROR('Json: Formato Erroneo',16,1)
		RETURN
	END
	PRINT 'INGRESE A SPQ_USUSU_COL'
	SELECT *
	INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)
   
	SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS , @USUARIO = USUARIO
	FROM #JSON
	--DEFINICION DE TABLA DE ERRORES
	DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200))
	-- TOMA DEL GRUPO, SYS_COMPUTERNAME, SEDE   DE ACUERDO AL USUARIO
	PRINT 'USUARIO:'+@USUARIO
	--SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO) FROM USUSU WHERE USUARIO = @USUARIO
	--SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
	--SELECT @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
	IF COALESCE(@SEDE,'') = '' SELECT @SEDE = '01'
	PRINT 'SEDE='+@SEDE
	IF @METODO = 'CRUDUSUSU'
	BEGIN
		PRINT 'CRUDUSUSU'
		SELECT @USUSU  = REGISTRO ,@DATACLAVE = DATACLAVE
		FROM OPENJSON (@PARAMETROS)
		WITH(
			REGISTRO   NVARCHAR(MAX)     AS JSON,
			DATACLAVE  NVARCHAR(MAX)     AS JSON
		)
		SELECT @PROCESO     = JSON_VALUE(@USUSU ,'$.PROCESO')
		--Leo Campos enviados y los coloco en las variables respectivas
		SELECT @COMPANIA               = JSON_VALUE(@USUSU , '$.COMPANIA' )
		SELECT @USUARIO_USUSU          = JSON_VALUE(@USUSU , '$.USUARIO' )
		SELECT @NOMBRE                 = JSON_VALUE(@USUSU , '$.NOMBRE' )
		SELECT @GRUPO_USUSU            = JSON_VALUE(@USUSU , '$.GRUPO' )
		SELECT @TIPO                   = JSON_VALUE(@USUSU , '$.TIPO' )
		SELECT @IDMEDICO               = JSON_VALUE(@USUSU , '$.IDMEDICO' )
		SELECT @NIVELFUNCIONARIO       = JSON_VALUE(@USUSU , '$.NIVELFUNCIONARIO' )
		SELECT @CODCAJERO              = JSON_VALUE(@USUSU , '$.CODCAJERO' )
		SELECT @SYS_ComputerName_USUSU = JSON_VALUE(@USUSU , '$.SYS_ComputerName' )
		IF COALESCE(JSON_VALUE(@USUSU , '$.FECHACAMBIO'),'') != ''
		BEGIN
			SELECT @FECHACAMBIO_STR        = JSON_VALUE(@USUSU , '$.FECHACAMBIO')
			SELECT @FECHACAMBIO            = CONVERT(DATE, SUBSTRING(@FECHACAMBIO_STR,9,2)+'/'+SUBSTRING(@FECHACAMBIO_STR,6,2)+'/'+SUBSTRING(@FECHACAMBIO_STR,1,4))
		END
		SELECT @ESTADO                 = JSON_VALUE(@USUSU , '$.ESTADO' )
		SELECT @ESMEDICO               = JSON_VALUE(@USUSU , '$.ESMEDICO' )
		SELECT @IDSEDE                 = JSON_VALUE(@USUSU , '$.IDSEDE' )
		SELECT @IDIMAGEN               = JSON_VALUE(@USUSU , '$.IDIMAGEN' )
		SELECT @CARGO                  = JSON_VALUE(@USUSU , '$.CARGO' )
		SELECT @TELEFONO               = JSON_VALUE(@USUSU , '$.TELEFONO' )
		SELECT @CELULAR                = JSON_VALUE(@USUSU , '$.CELULAR' )
		SELECT @PORCENTAJE             = JSON_VALUE(@USUSU , '$.PORCENTAJE' )
		IF COALESCE(JSON_VALUE(@USUSU , '$.FECHAVENCE'),'') != ''
		BEGIN
			SELECT @FECHAVENCE_STR         = JSON_VALUE(@USUSU , '$.FECHAVENCE')
			SELECT @FECHAVENCE             = CONVERT(DATE, SUBSTRING(@FECHAVENCE_STR,9,2)+'/'+SUBSTRING(@FECHAVENCE_STR,6,2)+'/'+SUBSTRING(@FECHAVENCE_STR,1,4))
		END
		SELECT @CONECTADO              = JSON_VALUE(@USUSU , '$.CONECTADO' )
		SELECT @SYS_COMP_CONECTADO     = JSON_VALUE(@USUSU , '$.SYS_COMP_CONECTADO' ) 
		IF COALESCE(JSON_VALUE(@USUSU , '$.FECHA_CONEC'),'') != ''
		BEGIN
			SELECT @FECHA_CONEC_STR        = JSON_VALUE(@USUSU , '$.FECHA_CONEC')
			SELECT @FECHA_CONEC = CONVERT(DATE, SUBSTRING(@FECHA_CONEC_STR,9,2)+'/'+SUBSTRING(@FECHA_CONEC_STR,6,2)+'/'+SUBSTRING(@FECHA_CONEC_STR,1,4))
		END
		--SELECT @KEYUSER = JSON_VALUE(@USUSU , '$.KEYUSER' )
		SELECT @IDTERCERO = JSON_VALUE(@USUSU , '$.IDTERCERO' )
		SELECT @IDFIRMA = JSON_VALUE(@USUSU , '$.IDFIRMA' )
		SELECT @IDEMPLEADO = JSON_VALUE(@USUSU , '$.IDEMPLEADO' )
		SELECT @TIPOUSUARIOADM = JSON_VALUE(@USUSU , '$.TIPO_USUARIOADM' )
		SELECT @IDDEPURAR = JSON_VALUE(@USUSU , '$.IDDEPURAR' )
		SELECT @EMAIL = JSON_VALUE(@USUSU , '$.EMAIL' )
		SELECT @GENERO = JSON_VALUE(@USUSU , '$.GENERO' )    --cmt ususu
		SELECT @FECHANACIMIENTO = JSON_VALUE(@USUSU , '$.FECHANACIMIENTO')
		--SELECT @FECHANACIMIENTO = CONVERT(DATE, SUBSTRING(@FECHANACIMIENTO_STR,9,2)+'/'+SUBSTRING(@FECHANACIMIENTO_STR,6,2)+'/'+SUBSTRING(@FECHANACIMIENTO_STR,1,4))
		SELECT @IDEMPRESA = JSON_VALUE(@USUSU , '$.IDEMPRESA' )
		IF COALESCE(JSON_VALUE(@USUSU , '$.F_RETIRO'),'') != ''
		BEGIN
			SELECT @F_RETIRO_STR = JSON_VALUE(@USUSU , '$.F_RETIRO')
			SELECT @F_RETIRO = CONVERT(DATE, SUBSTRING(@F_RETIRO_STR,9,2)+'/'+SUBSTRING(@F_RETIRO_STR,6,2)+'/'+SUBSTRING(@F_RETIRO_STR,1,4))
		END
		SELECT @IDBODEGA = JSON_VALUE(@USUSU , '$.IDBODEGA' )
		SELECT @CARNET = JSON_VALUE(@USUSU , '$.CARNET' )
		--SELECT @CLAVE = JSON_VALUE(@USUSU , '$.CLAVE' )
		--SELECT @CLAVE2 = JSON_VALUE(@USUSU , '$.CLAVE2' )
		SELECT @TELEGRAMID = JSON_VALUE(@USUSU , '$.TELEGRAMID' )
		SELECT @NOMBRES = JSON_VALUE(@USUSU , '$.NOMBRES' )
		SELECT @APELLIDOS = JSON_VALUE(@USUSU , '$.APELLIDOS' )
		SELECT @DOCID = JSON_VALUE(@USUSU , '$.DOCID' )
		SELECT @TIPOIDENT = JSON_VALUE(@USUSU , '$.TIPOIDENT' )
		SELECT @DEPARTAMENTO = JSON_VALUE(@USUSU , '$.DEPARTAMENTO' )
		SELECT @SOLOWEB      = JSON_VALUE(@USUSU , '$.SOLOWEB')
		SELECT @CLAVE_SISPRO = JSON_VALUE(@USUSU ,'$.CLAVE_SISPRO')
		SELECT @ACCESO_CUALQUIER_IP = JSON_VALUE(@USUSU ,'$.ACCESO_CUALQUIER_IP')

		SELECT @CAMBIACLAVE = JSON_VALUE(@DATACLAVE ,'$.CAMBIACLAVE')
		IF @CAMBIACLAVE = 1
		BEGIN 
			SELECT @CLAVE  = JSON_VALUE(@DATACLAVE ,'$.CLAVENUEVA')
			SELECT @CLAVE2 = JSON_VALUE(@DATACLAVE ,'$.CLAVENUEVA2')
		END
        
        IF @TIPO<>'M'
            SET @IDMEDICO=NULL

		IF UPPER(@PROCESO) = 'INSERTAR'
		BEGIN
			PRINT 'INSERTAR'
			BEGIN TRY
				INSERT INTO @TBLERRORES(ERROR) 
				SELECT 'EL CODIGO DE USUARIO YA EXISTE'
				WHERE EXISTS (SELECT 1 FROM USUSU WHERE USUARIO = @USUARIO_USUSU)

				IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
				BEGIN
					INSERT INTO USUSU(COMPANIA,USUARIO,NOMBRE,GRUPO,TIPO,IDMEDICO,NIVELFUNCIONARIO,
										CODCAJERO,SYS_ComputerName,FECHACAMBIO,ESTADO,ESMEDICO,IDSEDE,IDIMAGEN,
										CARGO,TELEFONO,CELULAR,FECHAVENCE,CONECTADO,SYS_COMP_CONECTADO,FECHA_CONEC,
										KEYUSER,IDTERCERO,IDFIRMA,IDEMPLEADO,TIPO_USUARIOADM,IDDEPURAR,EMAIL,
										GENERO,FECHANACIMIENTO,IDEMPRESA,F_RETIRO,IDBODEGA,CARNET,TELEGRAMID,NOMBRES,
										APELLIDOS,DOCID,TIPOIDENT,DEPARTAMENTO,SOLOWEB,CLAVE_SISPRO, ACCESO_CUALQUIER_IP)
					SELECT '01',@USUARIO_USUSU,@NOMBRE,DBO.FNK_CIFRAR(@GRUPO_USUSU),@TIPO,@IDMEDICO,@NIVELFUNCIONARIO,
										@CODCAJERO,@SYS_ComputerName_USUSU,@FECHACAMBIO,@ESTADO,@ESMEDICO,@IDSEDE,@IDIMAGEN,
										@CARGO,@TELEFONO,@CELULAR,@FECHAVENCE,@CONECTADO,@SYS_COMP_CONECTADO,@FECHA_CONEC,
										@KEYUSER,@IDTERCERO,@IDFIRMA,@IDEMPLEADO,@TIPOUSUARIOADM,@IDDEPURAR,@EMAIL,
										@GENERO,@FECHANACIMIENTO,@IDEMPRESA,@F_RETIRO,@IDBODEGA,@CARNET,@TELEGRAMID,@NOMBRES,
										@APELLIDOS,@DOCID,@TIPOIDENT,@DEPARTAMENTO,@SOLOWEB,@CLAVE_SISPRO, @ACCESO_CUALQUIER_IP
				END
			END TRY
			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
			END CATCH
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			/* Sincronizar MED.ESTADO con USUSU.ESTADO si existe v�nculo USUSU.IDMEDICO = MED.IDMEDICO */
			IF COALESCE(@IDMEDICO,'') <> ''
			BEGIN
				IF UPPER(LTRIM(RTRIM(COALESCE(@ESTADO,'')))) = 'INACTIVO'
					UPDATE MED SET ESTADO = 'Inactivo'
					WHERE IDMEDICO = @IDMEDICO
					  AND UPPER(LTRIM(RTRIM(COALESCE(ESTADO,'')))) = 'ACTIVO'
				ELSE IF UPPER(LTRIM(RTRIM(COALESCE(@ESTADO,'')))) = 'ACTIVO'
					UPDATE MED SET ESTADO = 'Activo'
					WHERE IDMEDICO = @IDMEDICO
					  AND UPPER(LTRIM(RTRIM(COALESCE(ESTADO,'')))) = 'INACTIVO'
			END
			IF @CAMBIACLAVE = 1
			BEGIN
			UPDATE USUSU SET CLAVE2 = PWDENCRYPT(@CLAVE) ,
							CLAVE  = HASHBYTES('SHA2_512',@CLAVE)
				WHERE  USUARIO = @USUARIO_USUSU
			END
			SELECT 'OK' OK ,@USUARIO_USUSU CNS 
			RETURN
		END
		IF UPPER(@PROCESO) = 'EDITAR'
		BEGIN
			BEGIN TRY

         -- SE AGRERGA PARA CUANDO EDITA Y NO TRAE OTRA FIRMA SE GUARDE LA QUE TENIA ANTES
         DECLARE @FIRMA_ANT INT
         SELECT @FIRMA_ANT = IDFIRMA FROM USUSU WHERE USUARIO = @USUARIO_USUSU
        IF (COALESCE(@IDFIRMA,0) = 0 )  
            SET  @IDFIRMA= @FIRMA_ANT


			UPDATE USUSU SET
					USUARIO = @USUARIO_USUSU,NOMBRE = @NOMBRE,GRUPO = DBO.FNK_CIFRAR(@GRUPO_USUSU),TIPO = @TIPO,IDMEDICO = @IDMEDICO
								,NIVELFUNCIONARIO = @NIVELFUNCIONARIO ,CODCAJERO = @CODCAJERO,SYS_ComputerName = @SYS_ComputerName_USUSU,FECHACAMBIO = @FECHACAMBIO
								,ESTADO    = @ESTADO,ESMEDICO = @ESMEDICO ,IDSEDE = @IDSEDE,IDIMAGEN = @IDIMAGEN ,CARGO = @CARGO,TELEFONO = @TELEFONO
								,CELULAR   = @CELULAR,FECHAVENCE = @FECHAVENCE,CONECTADO = @CONECTADO,SYS_COMP_CONECTADO = @SYS_COMP_CONECTADO,FECHA_CONEC = @FECHA_CONEC
								,KEYUSER   = @KEYUSER,IDTERCERO = @IDTERCERO,IDFIRMA = @IDFIRMA,IDEMPLEADO = @IDEMPLEADO,TIPO_USUARIOADM = @TIPOUSUARIOADM
								,IDDEPURAR = @IDDEPURAR,EMAIL = @EMAIL ,GENERO = @GENERO ,FECHANACIMIENTO = @FECHANACIMIENTO,IDEMPRESA = @IDEMPRESA
								,F_RETIRO  = @F_RETIRO,IDBODEGA = @IDBODEGA,CARNET = @CARNET
								,TELEGRAMID = @TELEGRAMID,NOMBRES = @NOMBRES,APELLIDOS = @APELLIDOS,DOCID = @DOCID,TIPOIDENT = @TIPOIDENT
								,DEPARTAMENTO = @DEPARTAMENTO ,SOLOWEB = @SOLOWEB ,CLAVE_SISPRO = @CLAVE_SISPRO,  PORCENTAJE = @PORCENTAJE,  ACCESO_CUALQUIER_IP = @ACCESO_CUALQUIER_IP
			WHERE USUARIO = @USUARIO_USUSU
			END TRY
			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
			END CATCH
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			IF COALESCE(@IDMEDICO,'') <> ''
			BEGIN
				IF UPPER(LTRIM(RTRIM(COALESCE(@ESTADO,'')))) = 'INACTIVO'
					UPDATE MED SET ESTADO = 'Inactivo'
					WHERE IDMEDICO = @IDMEDICO
					  AND UPPER(LTRIM(RTRIM(COALESCE(ESTADO,'')))) = 'ACTIVO'
				ELSE IF UPPER(LTRIM(RTRIM(COALESCE(@ESTADO,'')))) = 'ACTIVO'
					UPDATE MED SET ESTADO = 'Activo'
					WHERE IDMEDICO = @IDMEDICO
					  AND UPPER(LTRIM(RTRIM(COALESCE(ESTADO,'')))) = 'INACTIVO'
			END
			IF @CAMBIACLAVE = 1
			BEGIN
				print 'INGRESE A CAMBIAR CLAVE'
				print '@USUARIO_USUSU='+@USUARIO_USUSU
				print 'nueva clave='+@CLAVE
				UPDATE USUSU SET CLAVE2 = PWDENCRYPT(@CLAVE) ,
								CLAVE  = HASHBYTES('SHA2_512',@CLAVE)
					WHERE  USUARIO = @USUARIO_USUSU
				END
				SELECT 'OK' OK,@USUARIO_USUSU CNS 
			RETURN
		END
		RETURN
	END

	IF @METODO = 'CAMBIAR_IDIOMA'
	BEGIN

		BEGIN TRY
			IF COL_LENGTH('USUSU','IDIOMA') IS NOT NULL
				UPDATE USUSU SET IDIOMA=JSON_VALUE(@PARAMETROS,'$.IDIOMA')
				WHERE USUARIO = @USUARIO
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH
		IF(SELECT COUNT(*) FROM @TBLERRORES)>0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK

		RETURN
	END

	IF @METODO = 'OBTENER_IDIOMA'
	BEGIN
		SELECT OK='OK', USUARIO=@USUARIO ,IDIOMA = IDIOMA
		FROM USUSU
		WHERE USUARIO=@USUARIO
		RETURN
	END

	IF @METODO = 'OBTENER_MEDICO'
	BEGIN
		
		SELECT OK = 'OK'

		SELECT MED.IDMEDICO,MED.NOMBRE 
		FROM USUSU INNER JOIN MED ON MED.IDMEDICO=USUSU.IDMEDICO
		WHERE USUARIO=@USUARIO

	END

	IF @METODO = 'AUTORIZAR_ACCESO'
	BEGIN
		SELECT @USUARIO = JSON_VALUE(@PARAMETROS, '$.USUARIO')
		SELECT @CODIGO = JSON_VALUE(@PARAMETROS, '$.CODIGO')

		SELECT @DFA = COALESCE(DFA,0) 
			,@NOMBRE = NOMBRE
			,@CELULAR = CELULAR
		FROM USUSU WHERE USUARIO=@USUARIO

		IF @DFA = 1
		BEGIN
			IF @CODIGO IS NOT NULL
			BEGIN
				UPDATE USUSU SET CODACCESO = @CODIGO
				FROM USUSU
				WHERE USUARIO = @USUARIO
			END

			IF COALESCE(@CELULAR, '')<>''
			BEGIN
				SELECT @MENSAJE = '�Hola '+DBO.FNK_LIMPIATEXTO(@NOMBRE,'A-Z ')+'! Tu c�digo de acceso web es: '
				SELECT @MENSAJE += @CODIGO + '. Utilizalo para ingresar a nuestra plataforma.'
				EXEC SPK_SENDSMS @NUMERO=@CELULAR, @MENSAJE = @MENSAJE
			END
		END

		SELECT NOMBRE
			, REGISTRADO = CAST(IIF(CLAVE2 IS NULL, 0, 1) AS SMALLINT) 
			, ESTADO
			, DFA = CAST(COALESCE(DFA,0) AS BIT)
			, USUSU.EMAIL
			, FECHAVENCE
		FROM USUSU 
		WHERE USUARIO = @USUARIO

	END

	IF @METODO = 'ACTUALIZAR_TIPO_USUARIO'
	BEGIN
		IF COL_LENGTH('dbo.USUSU', 'DIR_JSON') IS NULL
			EXEC('ALTER TABLE dbo.USUSU ADD DIR_JSON NVARCHAR(MAX) NULL')

		IF JSON_VALUE(@PARAMETROS, '$.TIPO_USUARIOADM') = 'COND'
			AND DBO.FNK_VALORVARIABLE('USO_CONDUCTOR_DIREC') = 'SI'
		BEGIN
			DECLARE @DIR_JSON NVARCHAR(MAX)
			SELECT @DIR_JSON = COALESCE(JSON_QUERY(@PARAMETROS, '$.DIR_JSON'), DIR_JSON)
			FROM OPENJSON(@PARAMETROS)
			WITH (DIR_JSON NVARCHAR(MAX) '$.DIR_JSON')

			UPDATE USUSU
			SET TIPO=JSON_VALUE(@PARAMETROS, '$.TIPO')
				,TIPO_USUARIOADM=JSON_VALUE(@PARAMETROS, '$.TIPO_USUARIOADM')
				,LAT_USU=JSON_VALUE(@PARAMETROS, '$.LAT_USU')
				,LNG_USU=JSON_VALUE(@PARAMETROS, '$.LNG_USU')
				,CORREGIMIENTO_USU=JSON_VALUE(@PARAMETROS, '$.CORREGIMIENTO_USU')
				,DIRECCION_USU=JSON_VALUE(@PARAMETROS, '$.DIRECCION_USU')
				,DIR_JSON=@DIR_JSON
			WHERE USUARIO=JSON_VALUE(@PARAMETROS, '$.USUARIO')
		END
		ELSE
		BEGIN
			UPDATE USUSU
			SET TIPO=JSON_VALUE(@PARAMETROS, '$.TIPO')
				,TIPO_USUARIOADM=JSON_VALUE(@PARAMETROS, '$.TIPO_USUARIOADM')
			WHERE USUARIO=JSON_VALUE(@PARAMETROS, '$.USUARIO')
		END

		SELECT 'OK' AS OK
	END

	IF @METODO = 'UPDATEINFADDUSUSU' 
	BEGIN
    	BEGIN TRY
			SELECT @TELEFONO = TELEFONO,
					@CELULAR = CELULAR,
					@EMAIL = EMAIL,
					@USUARIO = USUARIO
				FROM OPENJSON(@PARAMETROS) WITH (
					TELEFONO VARCHAR(50) '$.TELEFONO',
					CELULAR VARCHAR(50) '$.CELULAR',
					EMAIL VARCHAR(100) '$.EMAIL',
					USUARIO VARCHAR(12) '$.USUARIO'
				)
			UPDATE USUSU
			SET EMAIL = @EMAIL,
				TELEFONO = @TELEFONO,
				CELULAR = @CELULAR
			WHERE USUARIO = @USUARIO
		END TRY BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH
			IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
			) > 0 
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK' OK
			RETURN
		END 
END
