  de todos, no con el de su lote. Este script deja en la línea la base y el IVA
  de la entrada. Luego iguala IVA, neto y saldo del encabezado a esa suma.

  No contabiliza. No toca VALOR. No corre SPK_CALCULOVALORESCXP.

  Solo estas CxP, estado N, sin contabilizar, sin comprobante, sin flete,
  sin abonos y sin notas. El saldo hoy es igual al neto:
    26CM000528  01CM000848  03CM001816  03CM001706  01CM000791
    01CM000843  03CM001853  01CM000824  03CM001837  03CM001873
    03CM001715  01CM000880  03CM001863  26CM000508  01CM000819
    01CM000873  01CM000875  01CM000854  01CM000803  03CM001820
    01CM000839

  Fuera de este bloque:
    01CM000861 DPE11203 ya está contabilizada (2659000000002782, 5.692.000).
    La entrada es de 300 y una línea trae 5.200. No se toca.
    03CM001888 FE71142 tiene dos lotes iguales. El neto ya es cantidad por
    precio más el IVA de cada lote.

  03CM001873, MX917-7: la entrada es un solo lote de 360. El detalle lo parte
  en 240 y 120, y las dos líneas traen 718.560. El script reparte 718.560
  en proporción a la cantidad.

  Si una línea no tiene su lote en la entrada, o al final el detalle no
  iguala el encabezado, no deja nada grabado. Ejecutar el bloque completo.
