CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_PRS @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX));
DECLARE @PARAMETROS AS NVARCHAR(MAX), @MODELO AS VARCHAR(100), @METODO AS VARCHAR(100), @USUARIO AS VARCHAR(20), @PROCESO AS VARCHAR(20);
DECLARE @CUOTAACT AS INT, @MANINTERESES AS INT, @NUMCUOTAS AS SMALLINT;
DECLARE @INTERESES AS DECIMAL(14, 2), @TTLPRESTAMO AS DECIMAL(14, 2);
DECLARE @NUMDOCUMENTO AS VARCHAR(20);
DECLARE @IDTRANSACCION AS VARCHAR(6), @COMPANIA AS VARCHAR(2), @CCOSTO AS VARCHAR(20), @IDAREA AS VARCHAR(20);
DECLARE @IDSEDE AS VARCHAR(5), @IDPRESTADOR AS VARCHAR(20), @IDDEUDOR AS VARCHAR(20), @FECHAINI AS DATETIME, @FECHADOCUMENTO AS DATETIME;
DECLARE @VLRPRESTAMO AS DECIMAL(14, 2), @VLRSALDO AS DECIMAL(14, 2), @PERIODO AS VARCHAR(20);
DECLARE @TIPOINTERES AS VARCHAR(20), @TASAINTERES AS DECIMAL(8, 4), @VLRCUOTA AS DECIMAL(14, 2), @VLRINTERESES AS DECIMAL(14, 2);
DECLARE @OBSERVACIONES AS VARCHAR(1023), @ESTADO AS VARCHAR(20), @FECHAADICION AS DATETIME;
DECLARE @FECHAMODIFICACION AS DATETIME, @CODCONCEPTO AS VARCHAR(20), @CODFINANCIACION AS VARCHAR(20);
DECLARE @ENCAJA AS SMALLINT, @CODCAJA AS VARCHAR(4), @CNSFACJ AS VARCHAR(20), @DIF AS DECIMAL(14, 2) = 0;
DECLARE @SYS_COMPUTERNAME AS VARCHAR(200);
DECLARE @NUMDOC_ORIGEN AS VARCHAR(20), @NUMDOC_DESTINO AS VARCHAR(20), @NUMDOCUMENTOS AS NVARCHAR(MAX), @CANTHOMOLOG AS INT;
DECLARE @FECHAPAGO AS DATETIME, @CUOTASAFECTADAS AS INT = 0, @ESTADOACTUAL AS VARCHAR(20);
DECLARE @OBS_PAGO_LIBRANZA AS VARCHAR(512);
DECLARE @CANT_ACTIVAS AS INT = 0, @CANT_PAGADAS AS INT = 0, @REGENERAR AS BIT = 0;
DECLARE @VLRPRESTAMO_ACT AS DECIMAL(14, 2), @NUMCUOTAS_ACT AS SMALLINT, @FECHAINI_ACT AS DATETIME;
DECLARE @PERIODO_ACT AS VARCHAR(20), @VLRCUOTA_ACT AS DECIMAL(14, 2);
DECLARE @CAPITAL_PAGADO AS DECIMAL(14, 2) = 0, @CUOTA_ULT AS INT = 0, @SALDO_RESTANTE AS DECIMAL(14, 2) = 0;

BEGIN
	/* SET LANGUAGE Spanish;
	SET DATEFORMAT dmy; */
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			);

	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
	FROM USUSU
	WHERE USUARIO = @USUARIO;

	SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
	FROM UBEQ
	WHERE SYS_ComputerName = @SYS_COMPUTERNAME;

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @NUMDOCUMENTO = NUMDOCUMENTO, @IDTRANSACCION = IDTRANSACCION, @CCOSTO = CCOSTO, @IDAREA = IDAREA, @IDPRESTADOR = IDPRESTADOR, @IDDEUDOR = IDDEUDOR, 
				@FECHAINI = FECHAINI, @FECHADOCUMENTO = FECHADOCUMENTO, @VLRPRESTAMO = VLRPRESTAMO, @VLRSALDO = VLRSALDO, @NUMCUOTAS = NUMCUOTAS, @PERIODO = PERIODO, 
				@MANINTERESES = MANINTERESES, @TIPOINTERES = TIPOINTERES, @TASAINTERES = TASAINTERES, @VLRCUOTA = VLRCUOTA, @VLRINTERESES = VLRINTERESES, 
				@TTLPRESTAMO = TTLPRESTAMO, @OBSERVACIONES = OBSERVACIONES, @ESTADO = ESTADO, @FECHAADICION = FECHAADICION, @FECHAMODIFICACION = FECHAMODIFICACION, 
				@CODCONCEPTO = CODCONCEPTO, @CODFINANCIACION = CODFINANCIACION, @PROCESO = PROCESO --, 
			FROM --@CODCAJA = CODCAJA
				OPENJSON(@PARAMETROS) WITH (
					NUMDOCUMENTO VARCHAR(20) '$.NUMDOCUMENTO', IDTRANSACCION VARCHAR(6) '$.IDTRANSACCION', COMPANIA VARCHAR(2) '$.COMPANIA', CCOSTO VARCHAR(20) 
					'$.CCOSTO', IDAREA VARCHAR(20) '$.IDAREA', IDPRESTADOR VARCHAR(20) '$.IDPRESTADOR', IDDEUDOR VARCHAR(20) '$.IDDEUDOR', FECHAINI DATETIME 
					'$.FECHAINI', FECHADOCUMENTO DATETIME '$.FECHADOCUMENTO', VLRPRESTAMO DECIMAL(14, 2) '$.VLRPRESTAMO', VLRSALDO DECIMAL(14, 2) '$.VLRSALDO', 
					NUMCUOTAS SMALLINT '$.NUMCUOTAS', PERIODO VARCHAR(20) '$.PERIODO', MANINTERESES TINYINT '$.MANINTERESES', TIPOINTERES VARCHAR(20) 
					'$.TIPOINTERES', TASAINTERES DECIMAL(8, 4) '$.TASAINTERES', VLRCUOTA DECIMAL(14, 2) '$.VLRCUOTA', VLRINTERESES DECIMAL(14, 2) '$.VLRINTERESES'
					, TTLPRESTAMO DECIMAL(14, 2) '$.TTLPRESTAMO', OBSERVACIONES VARCHAR(1023) '$.OBSERVACIONES', ESTADO VARCHAR(20) '$.ESTADO', FECHAADICION 
					DATETIME '$.FECHAADICION', FECHAMODIFICACION DATETIME '$.FECHAMODIFICACION', CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO', CODFINANCIACION 
					VARCHAR(20) '$.CODFINANCIACION', PROCESO VARCHAR(20) '$.PROCESO'
					);--, CODCAJA VARCHAR(4) '$.CODCAJA'

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					BEGIN TRANSACTION;

					EXECUTE SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE, 'PRS', @NUMDOCUMENTO OUTPUT;

					SELECT @NUMDOCUMENTO = @IDSEDE + REPLACE(SPACE(8 - LEN(@NUMDOCUMENTO)) + LTRIM(RTRIM(@NUMDOCUMENTO)), SPACE(1), 0);

					SET @VLRSALDO = COALESCE(NULLIF(@VLRSALDO, 0), @VLRPRESTAMO);

					INSERT INTO [PRS] (
						[NUMDOCUMENTO], [IDTRANSACCION], [COMPANIA], [CCOSTO], [IDAREA], [IDSEDE], [IDPRESTADOR], [IDDEUDOR], [FECHAINI], [FECHADOCUMENTO], 
						[VLRPRESTAMO], [VLRSALDO], [NUMCUOTAS], [PERIODO], [MANINTERESES], [TIPOINTERES], [TASAINTERES], [VLRCUOTA], [VLRINTERESES], 
						[TTLPRESTAMO], [OBSERVACIONES], [ESTADO], [USUARIOADICION], [EQUIPOADICIONO], [FECHAADICION], [USUARIOMODIFICO], [EQUIPOMODIFICO], 
						[FECHAMODIFICACION], [CODCONCEPTO], [CODFINANCIACION], [ENCAJA], [CODCAJA], [CNSFACJ]
						)
					SELECT @NUMDOCUMENTO, 'PRS', @COMPANIA, @CCOSTO, @IDAREA, @IDSEDE, @IDPRESTADOR, @IDDEUDOR, @FECHAINI, GETDATE(), @VLRPRESTAMO, @VLRSALDO, 
						@NUMCUOTAS, @PERIODO, @MANINTERESES, @TIPOINTERES, @TASAINTERES, @VLRCUOTA, @VLRINTERESES, @TTLPRESTAMO, @OBSERVACIONES, @ESTADO, 
						@USUARIO, @SYS_COMPUTERNAME, GETDATE(), @USUARIO, @SYS_COMPUTERNAME, GETDATE(), @CODCONCEPTO, @CODFINANCIACION, 0, 'TFCJ', '';

					EXECUTE SPK_GENERA_CUOTAS 'PRS', @NUMDOCUMENTO, @NUMCUOTAS, 0, @VLRPRESTAMO, @FECHAINI;

					COMMIT TRANSACTION;
				END TRY

				BEGIN CATCH
					ROLLBACK;

					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE();
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' AS OK;

					SELECT ERROR
					FROM @TBLERRORES;

					RETURN;
				END

				SELECT 'OK' AS OK;

				RETURN;
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @ESTADOACTUAL = ESTADO, @VLRPRESTAMO_ACT = VLRPRESTAMO, @NUMCUOTAS_ACT = NUMCUOTAS, @FECHAINI_ACT = FECHAINI, @PERIODO_ACT = PERIODO, 
						@VLRCUOTA_ACT = VLRCUOTA
					FROM PRS
					WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = COALESCE(@IDTRANSACCION, IDTRANSACCION);

					SELECT @IDTRANSACCION = COALESCE(@IDTRANSACCION, 'PRS');

					SELECT @CANT_ACTIVAS = COUNT(*), @CANT_PAGADAS = COALESCE(SUM(CASE 
									WHEN ESTADO = 'Pagada'
										THEN 1
									ELSE 0
									END), 0), @CAPITAL_PAGADO = COALESCE(SUM(CASE 
									WHEN ESTADO = 'Pagada' OR (CNSPAGO IS NOT NULL AND LTRIM(RTRIM(CNSPAGO)) <> '')
										THEN VLRCUOTA - ISNULL(VLRINTERESES, 0)
									ELSE 0
									END), 0), @CUOTA_ULT = COALESCE(MAX(CASE 
									WHEN ESTADO = 'Pagada' OR (CNSPAGO IS NOT NULL AND LTRIM(RTRIM(CNSPAGO)) <> '')
										THEN NUMCUOTA
									END), 0)
					FROM PRSD
					WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND ESTADO <> 'Anulada';

					IF @ESTADOACTUAL IS NULL
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('No existe la libranza ', @NUMDOCUMENTO);
					END

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0 AND @ESTADOACTUAL = 'Pagada' AND @ESTADO <> 'Pagada'
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('La libranza ', @NUMDOCUMENTO, ' ya esta pagada y no permite cambiar de estado');
					END

					-- No se puede bajar el capital por debajo de lo ya descontado en nomina.
					-- El rec�lculo solo redistribuye el saldo restante en cuotas pendientes.
					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0 AND @ESTADO = 'PorPagar' AND @CAPITAL_PAGADO > 0 AND ISNULL(@VLRPRESTAMO, 0) < @CAPITAL_PAGADO
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('El valor del prestamo no puede ser menor a lo ya descontado (', @CAPITAL_PAGADO, ')'
								);
					END

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0 AND @ESTADO = 'PorPagar' AND @CUOTA_ULT > 0 AND ISNULL(@NUMCUOTAS, 0) <= @CUOTA_ULT
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('El numero de cuotas debe ser mayor a las ya pagadas o aplicadas en nomina (', @CUOTA_ULT, ')'
								);
					END

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0 AND @ESTADO = 'Pagada'
					BEGIN
						IF NOT EXISTS (
								SELECT 1
								FROM PRSD
								WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION
								)
						BEGIN
							INSERT INTO @TBLERRORES (ERROR)
							SELECT CONCAT ('La libranza ', @NUMDOCUMENTO, ' no tiene cuotas generadas');
						END

						IF (
								SELECT COUNT(*)
								FROM @TBLERRORES
								) <= 0 AND NOT EXISTS (
								SELECT 1
								FROM PRSD
								WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND ESTADO <> 'Anulada'
								)
						BEGIN
							INSERT INTO @TBLERRORES (ERROR)
							SELECT CONCAT ('La libranza ', @NUMDOCUMENTO, ' solo tiene cuotas anuladas');
						END
					END

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0 AND @ESTADO = 'Anulada' AND EXISTS (
							SELECT 1
							FROM PRSD
							WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND ESTADO = 'Pagada'
							)
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('La libranza ', @NUMDOCUMENTO, ' tiene cuotas pagadas y no puede anularse');
					END

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						BEGIN TRANSACTION;

						IF @ESTADO = 'Pagada'
						BEGIN
							SELECT @FECHAPAGO = GETDATE(), @VLRSALDO = 0;

							SET @OBS_PAGO_LIBRANZA = 
								'Cuota marcada como pagada mediante pago aplicado a la libranza. No corresponde a descuento de n�mina.';

							UPDATE PRSD
							SET ESTADO = 'Pagada', FECHAPAGO = COALESCE(FECHAPAGO, @FECHAPAGO), OBSERVACION = CASE 
									WHEN CNSPAGO IS NOT NULL AND LTRIM(RTRIM(CNSPAGO)) <> ''
										THEN OBSERVACION
									WHEN OBSERVACION IS NULL OR LTRIM(RTRIM(OBSERVACION)) = ''
										THEN @OBS_PAGO_LIBRANZA
									ELSE LEFT(RTRIM(OBSERVACION) + ' | ' + @OBS_PAGO_LIBRANZA, 512)
									END
							WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND ESTADO NOT IN ('Pagada', 'Anulada'
									);

							SET @CUOTASAFECTADAS = @@ROWCOUNT;
						END
						ELSE IF @ESTADO = 'Anulada'
						BEGIN
							UPDATE PRSD
							SET ESTADO = 'Anulada'
							WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND ESTADO NOT IN ('Pagada', 'Anulada'
									);

							SET @CUOTASAFECTADAS = @@ROWCOUNT;
						END
						ELSE IF @ESTADO = 'Aplazada'
						BEGIN
							UPDATE PRSD
							SET ESTADO = 'Aplazada'
							WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND ESTADO = 'PorPagar';

							SET @CUOTASAFECTADAS = @@ROWCOUNT;
						END
						ELSE IF @ESTADO = 'PorPagar'
						BEGIN
							UPDATE PRSD
							SET ESTADO = 'PorPagar'
							WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND ESTADO = 'Aplazada';

							SET @CUOTASAFECTADAS = @@ROWCOUNT;
						END

						IF @ESTADO = 'PorPagar'
						BEGIN
							SET @SALDO_RESTANTE = ISNULL(@VLRPRESTAMO, 0) - ISNULL(@CAPITAL_PAGADO, 0);

							IF @SALDO_RESTANTE < 0
								SET @SALDO_RESTANTE = 0;
							SET @VLRSALDO = @SALDO_RESTANTE;
						END

						UPDATE PRS
						SET COMPANIA = @COMPANIA, CCOSTO = @CCOSTO, IDAREA = @IDAREA, IDSEDE = @IDSEDE, IDPRESTADOR = @IDPRESTADOR, IDDEUDOR = @IDDEUDOR, FECHAINI = 
							@FECHAINI, FECHADOCUMENTO = COALESCE(@FECHADOCUMENTO, FECHADOCUMENTO), VLRPRESTAMO = @VLRPRESTAMO, VLRSALDO = @VLRSALDO, NUMCUOTAS = 
							@NUMCUOTAS, PERIODO = @PERIODO, MANINTERESES = @MANINTERESES, TIPOINTERES = @TIPOINTERES, TASAINTERES = @TASAINTERES, VLRCUOTA = 
							@VLRCUOTA, VLRINTERESES = @VLRINTERESES, TTLPRESTAMO = @TTLPRESTAMO, OBSERVACIONES = @OBSERVACIONES, ESTADO = @ESTADO, USUARIOMODIFICO = 
							@USUARIO, EQUIPOMODIFICO = @SYS_COMPUTERNAME, FECHAMODIFICACION = GETDATE(), CODCONCEPTO = @CODCONCEPTO, CODFINANCIACION = 
							@CODFINANCIACION --, ENCAJA = @ENCAJA , CODCAJA = @CODCAJA
						WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION;

						IF @ESTADO = 'PorPagar' AND ISNULL(@NUMCUOTAS, 0) > 0 AND ISNULL(@VLRPRESTAMO, 0) > 0 AND (
								@CANT_ACTIVAS = 0 OR @VLRPRESTAMO <> @VLRPRESTAMO_ACT OR @NUMCUOTAS <> @NUMCUOTAS_ACT OR @PERIODO <> @PERIODO_ACT OR ISNULL(@VLRCUOTA, 
									0) <> ISNULL(@VLRCUOTA_ACT, 0) OR CONVERT(DATE, COALESCE(@FECHAINI, '19000101')) <> CONVERT(DATE, COALESCE(@FECHAINI_ACT, 
										'19000101'))
								)
						BEGIN
							SET @REGENERAR = 1;
						END

						IF @REGENERAR = 1
						BEGIN
							EXECUTE SPK_GENERA_CUOTAS @IDTRANSACCION, @NUMDOCUMENTO, @NUMCUOTAS, 0, @SALDO_RESTANTE, @FECHAINI;
						END

						COMMIT TRANSACTION;
					END
				END TRY

				BEGIN CATCH
					IF @@TRANCOUNT > 0
						ROLLBACK;

					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE();
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' AS OK;

					SELECT ERROR
					FROM @TBLERRORES;

					RETURN;
				END

				SELECT 'OK' AS OK, @CUOTASAFECTADAS AS CUOTAS_AFECTADAS;

				RETURN;
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' AS OK;

			SELECT ERROR
			FROM @TBLERRORES;

			RETURN;
		END

		SELECT 'OK' AS OK;
	END

	IF @METODO = 'CALUCLA_CUOTAS'
	BEGIN
		BEGIN TRY
			SELECT @NUMDOCUMENTO = NUMDOCUMENTO, @IDTRANSACCION = IDTRANSACCION, @MANINTERESES = MANINTERESES, @NUMCUOTAS = NUMCUOTAS, @VLRSALDO = VLRSALDO, 
				@VLRINTERESES = VLRINTERESES, @VLRPRESTAMO = VLRPRESTAMO
			FROM OPENJSON(@PARAMETROS) WITH (
					NUMDOCUMENTO VARCHAR(20) '$.NUMDOCUMENTO', IDTRANSACCION VARCHAR(6) '$.IDTRANSACCION', MANINTERESES INT '$.MANINTERESES', NUMCUOTAS SMALLINT 
					'$.NUMCUOTAS', VLRSALDO DECIMAL(14, 2) '$.VLRSALDO', VLRINTERESES DECIMAL(14, 2) '$.VLRINTERESES', VLRPRESTAMO DECIMAL(14, 2) '$.VLRPRESTAMO'
					);

			SET @IDTRANSACCION = COALESCE(@IDTRANSACCION, 'PRS');
			SET @MANINTERESES = COALESCE(@MANINTERESES, 0);
			SET @NUMCUOTAS = COALESCE(@NUMCUOTAS, 0);
			SET @VLRINTERESES = COALESCE(@VLRINTERESES, 0);
			SET @VLRPRESTAMO = COALESCE(@VLRPRESTAMO, 0);

			SELECT @CANT_PAGADAS = COUNT(*), @CUOTA_ULT = COALESCE(MAX(NUMCUOTA), 0), @CAPITAL_PAGADO = COALESCE(SUM(VLRCUOTA - ISNULL(VLRINTERESES, 0)), 0)
			FROM PRSD
			WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO AND (ESTADO = 'Pagada' OR (CNSPAGO IS NOT NULL AND LTRIM(RTRIM(CNSPAGO)) <> '')
					);

			IF @CANT_PAGADAS > 0
				SET @VLRSALDO = @VLRPRESTAMO - @CAPITAL_PAGADO;
			ELSE
				SET @VLRSALDO = COALESCE(NULLIF(@VLRPRESTAMO, 0), @VLRSALDO, 0);

			IF @VLRSALDO < 0
				SET @VLRSALDO = 0;

			IF @NUMCUOTAS <= 0
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'Debe indicar el numero de cuotas para calcular';
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0 AND @NUMCUOTAS - @CUOTA_ULT <= 0
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT CONCAT ('El numero de cuotas debe ser mayor a las ya pagadas (', @CUOTA_ULT, ')');
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0 AND @VLRSALDO <= 0
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'Debe indicar el valor del prestamo para calcular las cuotas';
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				SET @VLRCUOTA = ROUND(@VLRSALDO / (@NUMCUOTAS - @CUOTA_ULT), 0);
				SET @TTLPRESTAMO = @VLRPRESTAMO + @VLRINTERESES;

				SELECT 'OK' AS OK;

				SELECT @VLRCUOTA AS VLRCUOTA, @TTLPRESTAMO AS TTLPRESTAMO, @VLRINTERESES AS VLRINTERESES, @VLRSALDO AS VLRSALDO;
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' AS OK;

			SELECT ERROR
			FROM @TBLERRORES;

			RETURN;
		END

		SELECT 'OK' AS OK;
	END

	IF @METODO = 'ENVIAR_A_CXP'
	BEGIN
		SELECT @NUMDOCUMENTO = NUMDOCUMENTO
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOCUMENTO VARCHAR(20) '$.NUMDOCUMENTO');

		BEGIN TRY
			EXECUTE SPK_GENCXP_PRESTAMO_NOMI @NUMDOCUMENTO, @COMPANIA, @IDSEDE, @USUARIO, @SYS_COMPUTERNAME;
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' AS OK;

			SELECT ERROR
			FROM @TBLERRORES;

			RETURN;
		END

		SELECT 'OK' AS OK;
	END

	IF @METODO = 'MARCAR_PAGADA'
	BEGIN
		SELECT @NUMDOCUMENTO = NUMDOCUMENTO, @IDTRANSACCION = IDTRANSACCION, @FECHAPAGO = FECHAPAGO
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOCUMENTO VARCHAR(20) '$.NUMDOCUMENTO', IDTRANSACCION VARCHAR(6) '$.IDTRANSACCION', FECHAPAGO DATETIME '$.FECHAPAGO'
				);

		SELECT @FECHAPAGO = COALESCE(@FECHAPAGO, GETDATE()), @IDTRANSACCION = COALESCE(@IDTRANSACCION, 'PRS');

		BEGIN TRY
			SELECT @ESTADOACTUAL = ESTADO
			FROM PRS
			WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION;

			IF @NUMDOCUMENTO IS NULL OR LTRIM(RTRIM(@NUMDOCUMENTO)) = ''
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'Debe indicar el numero de documento de la libranza';
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0 AND @ESTADOACTUAL IS NULL
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT CONCAT ('No existe la libranza ', @NUMDOCUMENTO);
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0 AND @ESTADOACTUAL = 'Anulada'
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT CONCAT ('La libranza ', @NUMDOCUMENTO, ' se encuentra anulada y no puede marcarse como pagada');
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0 AND NOT EXISTS (
					SELECT 1
					FROM PRSD
					WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION
					)
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT CONCAT ('La libranza ', @NUMDOCUMENTO, ' no tiene cuotas generadas');
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0 AND NOT EXISTS (
					SELECT 1
					FROM PRSD
					WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND ESTADO <> 'Anulada'
					)
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT CONCAT ('La libranza ', @NUMDOCUMENTO, ' solo tiene cuotas anuladas');
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				BEGIN TRANSACTION;

				SET @OBS_PAGO_LIBRANZA = 'Cuota marcada como pagada mediante pago aplicado a la libranza. No corresponde a descuento de n�mina.';

				UPDATE PRSD
				SET ESTADO = 'Pagada', FECHAPAGO = COALESCE(FECHAPAGO, @FECHAPAGO), OBSERVACION = CASE 
						WHEN CNSPAGO IS NOT NULL AND LTRIM(RTRIM(CNSPAGO)) <> ''
							THEN OBSERVACION
						WHEN OBSERVACION IS NULL OR LTRIM(RTRIM(OBSERVACION)) = ''
							THEN @OBS_PAGO_LIBRANZA
						ELSE LEFT(RTRIM(OBSERVACION) + ' | ' + @OBS_PAGO_LIBRANZA, 512)
						END
				WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND ESTADO NOT IN ('Pagada', 'Anulada');

				SET @CUOTASAFECTADAS = @@ROWCOUNT;

				UPDATE PRS
				SET ESTADO = 'Pagada', VLRSALDO = 0, USUARIOMODIFICO = @USUARIO, EQUIPOMODIFICO = @SYS_COMPUTERNAME, FECHAMODIFICACION = GETDATE()
				WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION;

				COMMIT TRANSACTION;
			END
		END TRY

		BEGIN CATCH
			IF @@TRANCOUNT > 0
				ROLLBACK;

			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' AS OK;

			SELECT ERROR
			FROM @TBLERRORES;

			RETURN;
		END

		SELECT 'OK' AS OK, @NUMDOCUMENTO AS NUMDOCUMENTO, @IDTRANSACCION AS IDTRANSACCION, @FECHAPAGO AS FECHAPAGO, @CUOTASAFECTADAS AS CUOTAS_AFECTADAS;

		RETURN;
	END

	IF @METODO = 'GENERAR_CUOTAS'
	BEGIN
		SELECT @IDTRANSACCION = IDTRANSACCION, @NUMDOCUMENTO = NUMDOCUMENTO, @NUMCUOTAS = NUMCUOTAS, @VLRSALDO = VLRSALDO, @FECHAINI = FECHAINI
		FROM OPENJSON(@PARAMETROS) WITH (
				IDTRANSACCION VARCHAR(6) '$.IDTRANSACCION', NUMDOCUMENTO VARCHAR(20) '$.NUMDOCUMENTO', NUMCUOTAS SMALLINT '$.NUMCUOTAS', VLRSALDO DECIMAL(14, 2) 
				'$.VLRSALDO', FECHAINI DATETIME '$.FECHAINI'
				);

		BEGIN TRY
			SELECT @IDTRANSACCION = COALESCE(IDTRANSACCION, @IDTRANSACCION, 'PRS'), @ESTADOACTUAL = ESTADO, @NUMCUOTAS = NUMCUOTAS, @VLRPRESTAMO = VLRPRESTAMO, 
				@VLRSALDO = VLRSALDO, @FECHAINI = FECHAINI
			FROM PRS
			WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = COALESCE(@IDTRANSACCION, IDTRANSACCION);

			IF @ESTADOACTUAL IS NULL
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT CONCAT ('No existe la libranza ', @NUMDOCUMENTO);
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0 AND @ESTADOACTUAL IN ('Pagada', 'Anulada')
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT CONCAT ('La libranza ', @NUMDOCUMENTO, ' esta ', @ESTADOACTUAL, ' y no permite generar cuotas');
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0 AND ISNULL(@NUMCUOTAS, 0) <= 0
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'Debe indicar el numero de cuotas antes de generarlas';
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0 AND ISNULL(@VLRPRESTAMO, 0) <= 0
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'Debe indicar el valor del prestamo antes de generar las cuotas';
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				SELECT @CANT_PAGADAS = COUNT(*), @CUOTA_ULT = COALESCE(MAX(NUMCUOTA), 0), @CAPITAL_PAGADO = COALESCE(SUM(VLRCUOTA - ISNULL(VLRINTERESES, 0)), 0)
				FROM PRSD
				WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND (ESTADO = 'Pagada' OR (CNSPAGO IS NOT NULL AND LTRIM(RTRIM(CNSPAGO)) <> '')
						);

				IF @CUOTA_ULT > 0 AND @NUMCUOTAS <= @CUOTA_ULT
				BEGIN
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('El numero de cuotas debe ser mayor a las ya pagadas (', @CUOTA_ULT, ')');
				END

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) <= 0 AND @CAPITAL_PAGADO > 0 AND @VLRPRESTAMO < @CAPITAL_PAGADO
				BEGIN
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('El valor del prestamo no puede ser menor a lo ya descontado (', @CAPITAL_PAGADO, ')');
				END
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				SET @SALDO_RESTANTE = ISNULL(@VLRPRESTAMO, 0) - ISNULL(@CAPITAL_PAGADO, 0);

				IF @SALDO_RESTANTE < 0
					SET @SALDO_RESTANTE = 0;

				BEGIN TRANSACTION;

				EXECUTE SPK_GENERA_CUOTAS @IDTRANSACCION, @NUMDOCUMENTO, @NUMCUOTAS, 0, @SALDO_RESTANTE, @FECHAINI;

				COMMIT TRANSACTION;
			END
		END TRY

		BEGIN CATCH
			IF @@TRANCOUNT > 0
				ROLLBACK;

			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' AS OK;

			SELECT ERROR
			FROM @TBLERRORES;

			RETURN;
		END

		SELECT 'OK' AS OK;
	END

	IF @METODO = 'ELIMINAR_CUOTAS'
	BEGIN
		SELECT @IDTRANSACCION = IDTRANSACCION, @NUMDOCUMENTO = NUMDOCUMENTO
		FROM OPENJSON(@PARAMETROS) WITH (IDTRANSACCION VARCHAR(6) '$.IDTRANSACCION', NUMDOCUMENTO VARCHAR(20) '$.NUMDOCUMENTO');

		BEGIN TRY
			IF EXISTS (
					SELECT 1
					FROM PRSD
					WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO AND ESTADO = 'Pagada'
					) AND NOT EXISTS (
					SELECT 1
					FROM PRSD
					WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO AND ESTADO NOT IN ('Pagada', 'Anulada') AND (CNSPAGO IS NULL OR LTRIM(RTRIM(CNSPAGO)) = ''
							)
					)
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'No hay cuotas pendientes para eliminar. Las cuotas pagadas o aplicadas en nomina se conservan';
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				DELETE PRSD
				WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO AND ESTADO NOT IN ('Pagada', 'Anulada') AND (CNSPAGO IS NULL OR LTRIM(RTRIM(CNSPAGO)) = ''
						);

				SELECT @CAPITAL_PAGADO = COALESCE(SUM(VLRCUOTA - ISNULL(VLRINTERESES, 0)), 0)
				FROM PRSD
				WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO AND (ESTADO = 'Pagada' OR (CNSPAGO IS NOT NULL AND LTRIM(RTRIM(CNSPAGO)) <> '')
						);

				UPDATE PRS
				SET VLRSALDO = CASE 
						WHEN VLRPRESTAMO - @CAPITAL_PAGADO < 0
							THEN 0
						ELSE VLRPRESTAMO - @CAPITAL_PAGADO
						END, USUARIOMODIFICO = @USUARIO, EQUIPOMODIFICO = @SYS_COMPUTERNAME, FECHAMODIFICACION = GETDATE()
				WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO;
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' AS OK;

			SELECT ERROR
			FROM @TBLERRORES;

			RETURN;
		END

		SELECT 'OK' AS OK;
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @NUMDOCUMENTO = NUMDOCUMENTO
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOCUMENTO VARCHAR(20) '$.NUMDOCUMENTO');

		BEGIN TRY
			INSERT INTO @TBLERRORES (ERROR)
			SELECT CONCAT ('EXISTE CUOTAS RELACIONADOAS AL PRESTAMO ', @NUMDOCUMENTO, ' NO ES POSIBLE ELIMINARLO')
			WHERE EXISTS (
					SELECT 1
					FROM PRSD
					WHERE NUMDOCUMENTO = @NUMDOCUMENTO
					);

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				DELETE PRS
				WHERE NUMDOCUMENTO = @NUMDOCUMENTO;
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' AS OK;

			SELECT ERROR
			FROM @TBLERRORES;

			RETURN;
		END

		SELECT 'OK' AS OK;
	END

	-- nuevo metodo para validar cuales son los registros o prestamos de libranzas que se van a homolograr
	IF @METODO = 'CONSULTAR_PENDIENTES_HOMOLOG'
	BEGIN
		SELECT @NUMDOC_ORIGEN = NUMDOC_ORIGEN
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOC_ORIGEN VARCHAR(20) '$.NUMDOC_ORIGEN');

		IF NOT EXISTS (
				SELECT 1
				FROM NEMP
				WHERE NUMDOC = @NUMDOC_ORIGEN AND FECHARETIRO IS NOT NULL
				)
		BEGIN
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'El contrato origen no existe o no tiene fecha de retiro registrada';

			SELECT 'KO' AS OK;

			SELECT ERROR
			FROM @TBLERRORES;

			RETURN;
		END

		SELECT 'OK' AS OK;

		SELECT P.NUMDOCUMENTO, P.IDTRANSACCION, P.IDDEUDOR, P.IDPRESTADOR, P.CODCONCEPTO, P.VLRPRESTAMO, P.VLRSALDO, P.NUMCUOTAS, P.ESTADO, P.FECHADOCUMENTO, TER
			.RAZONSOCIAL AS NOMBRE_PRESTADOR, (
				SELECT COUNT(*)
				FROM PRSD AS D
				WHERE D.NUMDOCUMENTO = P.NUMDOCUMENTO AND D.IDTRANSACCION = P.IDTRANSACCION AND D.ESTADO = 'PorPagar'
				) AS CUOTAS_PENDIENTES
		FROM PRS AS P
		LEFT OUTER JOIN TER ON TER.IDTERCERO = P.IDPRESTADOR
		WHERE P.IDDEUDOR = @NUMDOC_ORIGEN AND P.ESTADO = 'PorPagar' AND EXISTS (
				SELECT 1
				FROM PRSD AS D
				WHERE D.NUMDOCUMENTO = P.NUMDOCUMENTO AND D.IDTRANSACCION = P.IDTRANSACCION AND D.ESTADO = 'PorPagar'
				)
		ORDER BY P.FECHADOCUMENTO DESC;

		RETURN;
	END

	-- nuevo metodo para la validacion de contratos a homologar (incluye la homologacion)
	IF @METODO = 'HOMOLOGAR_NUMDOC'
	BEGIN
		BEGIN TRY
			SELECT @NUMDOC_ORIGEN = NUMDOC_ORIGEN, @NUMDOC_DESTINO = NUMDOC_DESTINO, @NUMDOCUMENTOS = NUMDOCUMENTOS
			FROM OPENJSON(@PARAMETROS) WITH (
					NUMDOC_ORIGEN VARCHAR(20) '$.NUMDOC_ORIGEN', NUMDOC_DESTINO VARCHAR(20) '$.NUMDOC_DESTINO', NUMDOCUMENTOS NVARCHAR(MAX) '$.NUMDOCUMENTOS' 
					AS JSON
					);

			IF @NUMDOC_ORIGEN IS NULL OR @NUMDOC_DESTINO IS NULL
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'Debe indicar contrato origen y contrato destino';
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0 AND NOT EXISTS (
					SELECT 1
					FROM NEMP
					WHERE NUMDOC = @NUMDOC_ORIGEN AND FECHARETIRO IS NOT NULL
					)
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'El contrato origen no tiene fecha de retiro. Solo se homologan prestamos de contratos ratirados';
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0 AND NOT EXISTS (
					SELECT 1
					FROM NEMP
					WHERE NUMDOC = @NUMDOC_DESTINO
					)
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'El contrato destino no existe';
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				SET @CANTHOMOLOG = 0;

				-- spq realizar homologacion de las libranzas a los contratos seleccionados
				EXECUTE SPQ_HOMOLOGAR_PRS_NUMDOC @NUMDOC_DESTINO = @NUMDOC_DESTINO, @NUMDOC_ORIGEN = @NUMDOC_ORIGEN, @TERCEROID = NULL, @USUARIO = @USUARIO, 
					@SYS_COMPUTERNAME = @SYS_COMPUTERNAME, @NUMDOCUMENTOS = @NUMDOCUMENTOS, @CANTIDAD = @CANTHOMOLOG OUTPUT;

				IF @CANTHOMOLOG = 0
				BEGIN
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'No se encontraron prestamos pendientes para homologar con los criterios indicados';
				END
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE();
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' AS OK;

			SELECT ERROR
			FROM @TBLERRORES;

			RETURN;
		END

		SELECT 'OK' AS OK, @CANTHOMOLOG AS CANT_HOMOLOG, @NUMDOC_ORIGEN AS NUMDOC_ORIGEN, @NUMDOC_DESTINO AS NUMDOC_DESTINO;

		RETURN;
	END
