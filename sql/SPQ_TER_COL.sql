				EMAILRECIBOFE, @MANEXO = MANEXO, @CONDICIONPAGO = CONDICIONPAGO, @PLAZOPAGO = PLAZOPAGO, @DTOPRONTOPAGO = DTOPRONTOPAGO
			FROM OPENJSON(@PARAMETROS) WITH (
					NIT VARCHAR(20) '$.NIT', RAZONSOCIAL VARCHAR(120) '$.RAZONSOCIAL', PROCESO VARCHAR(20) '$.PROCESO', DV VARCHAR(1) '$.DV', TIPO_ID VARCHAR(3) 
					'$.TIPO_ID', IDALTERNA2 VARCHAR(20) '$.IDALTERNA2', DIRECCION VARCHAR(60) '$.DIRECCION', NATJURIDICA VARCHAR(11) '$.NATJURIDICA', CIUDAD 
					VARCHAR(5) '$.CIUDAD', TELEFONOS VARCHAR(35) '$.TELEFONOS', FAX VARCHAR(10) '$.FAX', APA VARCHAR(6) '$.APA', F_INSCRIPTO DATETIME 
					'$.F_INSCRIPTO', F_VENCIMIENT DATETIME '$.F_VENCIMIENT', TIPO_ID_R VARCHAR(3) '$.TIPO_ID_R', NIT_R VARCHAR(20) '$.NIT_R', ESTADO BIT 
					'$.ESTADO', IDACTIVIDAD VARCHAR(20) '$.IDACTIVIDAD', ENVIODICAJA SMALLINT '$.ENVIODICAJA', MODOCOPAGO VARCHAR(6) '$.MODOCOPAGO', 
					EMPIDMODELOPC VARCHAR(5) '$.EMPIDMODELOPC', DIASVTO SMALLINT '$.DIASVTO', ESEXTRANJERO SMALLINT '$.ESEXTRANJERO', AUTORETENEDOR SMALLINT 
					'$.AUTORETENEDOR', GRANCONTRIBUYENTE SMALLINT '$.GRANCONTRIBUYENTE', EMAIL VARCHAR(512) '$.EMAIL', URL VARCHAR(40) '$.URL', NOMBRES_R_LEGAL 
					VARCHAR(30) '$.NOMBRES_R_LEGAL', P_APELLIDO_R_LEGAL VARCHAR(20) '$.P_APELLIDO_R_LEGAL', S_APELLIDO_R_LEGAL VARCHAR(20) 
					'$.S_APELLIDO_R_LEGAL', DE_NIT_R_LEGAL VARCHAR(30) '$.DE_NIT_R_LEGAL', TIPOREGIMEN VARCHAR(1) '$.TIPOREGIMEN', MSUCURSALES SMALLINT 
					'$.MSUCURSALES', FORMAPRE VARCHAR(1) '$.FORMAPRE', CODIGO_ARP VARCHAR(20) '$.CODIGO_ARP', NORAD VARCHAR(20) '$.NORAD', TIPOAPORTANTE VARCHAR(
						1) '$.TIPOAPORTANTE', CODOPERADOR VARCHAR(10) '$.CODOPERADOR', CODIGO_AFP VARCHAR(20) '$.CODIGO_AFP', CODIGO_CCF VARCHAR(20) 
					'$.CODIGO_CCF', FNAC_RLEGAL DATETIME '$.FNAC_RLEGAL', HOBBIE_RL VARCHAR(20) '$.HOBBIE_RL', PROF_RL VARCHAR(20) '$.PROF_RL', EMAIL_RL VARCHAR(
						40) '$.EMAIL_RL', TIPOID_TH VARCHAR(3) '$.TIPOID_TH', NID_TH VARCHAR(20) '$.NID_TH', DE_NIT_TH VARCHAR(5) '$.DE_NIT_TH', NOMBRES_TH 
					VARCHAR(30) '$.NOMBRES_TH', P_APELLIDO_TH VARCHAR(20) '$.P_APELLIDO_TH', S_APELLIDO_TH VARCHAR(20) '$.S_APELLIDO_TH', FNAC_TH DATETIME 
					'$.FNAC_TH', HOBBIE_TH VARCHAR(20) '$.HOBBIE_TH', PROF_TH VARCHAR(20) '$.PROF_TH', EMAIL_TH VARCHAR(40) '$.EMAIL_TH', HOMOLOGO VARCHAR(20) 
					'$.HOMOLOGO', PNOMBRE VARCHAR(30) '$.PNOMBRE', SNOMBRE VARCHAR(30) '$.SNOMBRE', PAPELLIDO VARCHAR(30) '$.PAPELLIDO', SAPELLIDO VARCHAR(30) 
					'$.SAPELLIDO', CUE_BANCARIA VARCHAR(16) '$.CUE_BANCARIA', CODIGO_EAPB VARCHAR(20) '$.CODIGO_EAPB', TIPO_CUE VARCHAR(20) '$.TIPO_CUE', BANCO 
					VARCHAR(3) '$.BANCO', SUCURSAL VARCHAR(20) '$.SUCURSAL', SIIF SMALLINT '$.SIIF', SIIFCODIGOPCI VARCHAR(20) '$.SIIFCODIGOPCI', SIIFCONTRATO 
					VARCHAR(50) '$.SIIFCONTRATO', MEDIOPAGO VARCHAR(20) '$.MEDIOPAGO', COD_RESP_FISCAL VARCHAR(10) '$.COD_RESP_FISCAL', SIIFCORREOSUPER VARCHAR
					(50) '$.SIIFCORREOSUPER', EMAILRECIBOFE VARCHAR(255) '$.EMAILRECIBOFE', MANEXO SMALLINT '$.MANEXO', CONDICIONPAGO VARCHAR(20) 
					'$.CONDICIONPAGO', PLAZOPAGO SMALLINT '$.PLAZOPAGO', DTOPRONTOPAGO DECIMAL(5, 2) '$.DTOPRONTOPAGO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				SET @RAZONSOCIAL = (
						SELECT IIF(@RAZONSOCIAL = '', CONCAT (COALESCE(@PNOMBRE, ''), ' ', COALESCE(@SNOMBRE, ''), ' ', COALESCE(@PAPELLIDO, ''), ' ', COALESCE(@SAPELLIDO, ''), ' '
									), @RAZONSOCIAL)
						);

				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('EL NIT ', @NIT, ' YA SE ENCUENTRA REGISTRADO COMO TERCERO')
					WHERE EXISTS (
							SELECT 1
							FROM TER
							WHERE NIT = @NIT
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@TER', @LONGITUD = 10, @NVOCONSEC = @IDTERCERO OUTPUT

						INSERT INTO TER (
							IDTERCERO, RAZONSOCIAL, NIT, DV, TIPO_ID, IDALTERNA2, DIRECCION, NATJURIDICA, CIUDAD, TELEFONOS, FAX, APA, F_INSCRIPTO, F_VENCIMIENT, 
							TIPO_ID_R, NIT_R, ESTADO, IDACTIVIDAD, ENVIODICAJA, MODOCOPAGO, EMPIDMODELOPC, DIASVTO, ESEXTRANJERO, AUTORETENEDOR, 
							GRANCONTRIBUYENTE, EMAIL, URL, NOMBRES_R_LEGAL, P_APELLIDO_R_LEGAL, S_APELLIDO_R_LEGAL, DE_NIT_R_LEGAL, TIPOREGIMEN, MSUCURSALES, 
							FORMAPRE, CODIGO_ARP, NORAD, TIPOAPORTANTE, CODOPERADOR, CODIGO_AFP, CODIGO_CCF, FNAC_RLEGAL, HOBBIE_RL, PROF_RL, EMAIL_RL, TIPOID_TH
							, NID_TH, DE_NIT_TH, NOMBRES_TH, P_APELLIDO_TH, S_APELLIDO_TH, FNAC_TH, HOBBIE_TH, PROF_TH, EMAIL_TH, HOMOLOGO, PNOMBRE, SNOMBRE, 
							PAPELLIDO, SAPELLIDO, CUE_BANCARIA, CODIGO_EAPB, TIPO_CUE, BANCO, SUCURSAL, SIIF, SIIFCODIGOPCI, SIIFCONTRATO, MEDIOPAGO, USUCREA, 
							FECHACREA, IDALTERNA1, R_LEGAL, CUENTA, ZONA, CIA, CLASIFICADOR, IDGRUPOIMP, ASESOR_AFI, ASESOR_MTO, CTAVIGENCIAANTE, MANEXO, 
							PREFIJOXML, SUFIJOXML, RUC, PYM, REQAUTORIZA, NIIF_VTAEQUIEFECTIVOS, MANFACT, SIIFCORREOSUPER, COD_RESP_FISCAL, EMAILRECIBOFE, 
							CONDICIONPAGO, PLAZOPAGO, DTOPRONTOPAGO
							)
						SELECT @IDTERCERO, LTRIM(RTRIM(@RAZONSOCIAL)), LTRIM(RTRIM(@NIT)), @DV, @TIPO_ID, @IDALTERNA2, @DIRECCION, @NATJURIDICA, @CIUDAD, 
							@TELEFONOS, @FAX, @APA, @F_INSCRIPTO, @F_VENCIMIENT, @TIPO_ID_R, @NIT_R, CASE 
								WHEN @ESTADO = 1
									THEN 'Activo'
								ELSE 'Inactivo'
								END, @IDACTIVIDAD, @ENVIODICAJA, @MODOCOPAGO, @EMPIDMODELOPC, @DIASVTO, @ESEXTRANJERO, @AUTORETENEDOR, @GRANCONTRIBUYENTE, 
							@EMAIL, @URL, @NOMBRES_R_LEGAL, @P_APELLIDO_R_LEGAL, @S_APELLIDO_R_LEGAL, @DE_NIT_R_LEGAL, @TIPOREGIMEN, @MSUCURSALES, @FORMAPRE, 
							@CODIGO_ARP, @NORAD, @TIPOAPORTANTE, @CODOPERADOR, @CODIGO_AFP, @CODIGO_CCF, @FNAC_RLEGAL, @HOBBIE_RL, @PROF_RL, @EMAIL_RL, 
							@TIPOID_TH, @NID_TH, @DE_NIT_TH, @NOMBRES_TH, @P_APELLIDO_TH, @S_APELLIDO_TH, @FNAC_TH, @HOBBIE_TH, @PROF_TH, @EMAIL_TH, @HOMOLOGO, 
							@PNOMBRE, @SNOMBRE, @PAPELLIDO, @SAPELLIDO, @CUE_BANCARIA, @CODIGO_EAPB, @TIPO_CUE, @BANCO, @SUCURSAL, @SIIF, @SIIFCODIGOPCI, 
							@SIIFCONTRATO, @MEDIOPAGO, @USUARIO, GETDATE(), '', '', '', '', '', '', '', '', '', '', @MANEXO, '', '', '', 0, 0, 0, 0, @SIIFCORREOSUPER, 
							@COD_RESP_FISCAL, @EMAILRECIBOFE, @CONDICIONPAGO, @PLAZOPAGO, @DTOPRONTOPAGO
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				SELECT @IDTERCERO = IDTERCERO
				FROM OPENJSON(@PARAMETROS) WITH (IDTERCERO VARCHAR(20) '$.IDTERCERO')

				BEGIN TRY
					SET @RAZONSOCIAL = (
							SELECT IIF(1 = (
										SELECT 1
										FROM TER
										WHERE IDTERCERO = @IDTERCERO AND (
												ISNULL(@PNOMBRE, '') <> ISNULL(PNOMBRE, '') OR ISNULL(@SNOMBRE, '') <> ISNULL(SNOMBRE, '') OR ISNULL(@PAPELLIDO, ''
												) <> ISNULL(PAPELLIDO, '') OR ISNULL(@SAPELLIDO, '') <> ISNULL(SAPELLIDO, '')
												)
										), CONCAT (COALESCE(@PNOMBRE, ''), ' ', COALESCE(@SNOMBRE, ''), ' ', COALESCE(@PAPELLIDO, ''), ' ', COALESCE(@SAPELLIDO, ''), ' '
										), @RAZONSOCIAL)
							);

					UPDATE TER
					SET RAZONSOCIAL = LTRIM(RTRIM(@RAZONSOCIAL)), NIT = LTRIM(RTRIM(@NIT)), DV = @DV, TIPO_ID = @TIPO_ID, IDALTERNA2 = @IDALTERNA2, DIRECCION = 
						@DIRECCION, NATJURIDICA = @NATJURIDICA, CIUDAD = @CIUDAD, TELEFONOS = @TELEFONOS, FAX = @FAX, APA = @APA, F_INSCRIPTO = @F_INSCRIPTO, 
						F_VENCIMIENT = @F_VENCIMIENT, TIPO_ID_R = @TIPO_ID_R, NIT_R = @NIT_R, ESTADO = CASE 
							WHEN @ESTADO = 1
								THEN 'Activo'
							ELSE 'Inactivo'
							END, IDACTIVIDAD = @IDACTIVIDAD, ENVIODICAJA = @ENVIODICAJA, MODOCOPAGO = @MODOCOPAGO, EMPIDMODELOPC = @EMPIDMODELOPC, DIASVTO = @DIASVTO
						, ESEXTRANJERO = @ESEXTRANJERO, AUTORETENEDOR = @AUTORETENEDOR, GRANCONTRIBUYENTE = @GRANCONTRIBUYENTE, EMAIL = @EMAIL, URL = @URL, 
						NOMBRES_R_LEGAL = @NOMBRES_R_LEGAL, P_APELLIDO_R_LEGAL = @P_APELLIDO_R_LEGAL, S_APELLIDO_R_LEGAL = @S_APELLIDO_R_LEGAL, DE_NIT_R_LEGAL = 
						@DE_NIT_R_LEGAL, TIPOREGIMEN = @TIPOREGIMEN, MSUCURSALES = @MSUCURSALES, FORMAPRE = @FORMAPRE, CODIGO_ARP = @CODIGO_ARP, NORAD = @NORAD, 
						TIPOAPORTANTE = @TIPOAPORTANTE, CODOPERADOR = @CODOPERADOR, CODIGO_AFP = @CODIGO_AFP, CODIGO_CCF = @CODIGO_CCF, FNAC_RLEGAL = @FNAC_RLEGAL, 
						HOBBIE_RL = @HOBBIE_RL, PROF_RL = @PROF_RL, EMAIL_RL = @EMAIL_RL, TIPOID_TH = @TIPOID_TH, NID_TH = @NID_TH, DE_NIT_TH = @DE_NIT_TH, NOMBRES_TH = 
						@NOMBRES_TH, P_APELLIDO_TH = @P_APELLIDO_TH, S_APELLIDO_TH = @S_APELLIDO_TH, FNAC_TH = @FNAC_TH, HOBBIE_TH = @HOBBIE_TH, PROF_TH = @PROF_TH, 
						EMAIL_TH = @EMAIL_TH, HOMOLOGO = @HOMOLOGO, PNOMBRE = @PNOMBRE, SNOMBRE = @SNOMBRE, PAPELLIDO = @PAPELLIDO, SAPELLIDO = @SAPELLIDO, CUE_BANCARIA 
						= @CUE_BANCARIA, CODIGO_EAPB = @CODIGO_EAPB, TIPO_CUE = @TIPO_CUE, BANCO = @BANCO, SUCURSAL = @SUCURSAL, SIIF = @SIIF, SIIFCODIGOPCI = 
						@SIIFCODIGOPCI, SIIFCONTRATO = @SIIFCONTRATO, MEDIOPAGO = @MEDIOPAGO, COD_RESP_FISCAL = @COD_RESP_FISCAL, SIIFCORREOSUPER = 
						@SIIFCORREOSUPER, EMAILRECIBOFE = @EMAILRECIBOFE, MANEXO = @MANEXO, CONDICIONPAGO = @CONDICIONPAGO, PLAZOPAGO = @PLAZOPAGO, DTOPRONTOPAGO = 
						@DTOPRONTOPAGO
					WHERE IDTERCERO = @IDTERCERO
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GET_TEXCA_TER'
	BEGIN
		BEGIN TRY
			SELECT @IDTERCERO = IDTERCERO
			FROM OPENJSON(@PARAMETROS) WITH (IDTERCERO VARCHAR(20) '$.IDTERCERO')

			SELECT 'OK' OK

			SELECT TEXCA.IDCATEGORIA, CAT.DESCRIPCION, TEXCA.ESTADO, TEXCA.IDTERCERO, TEXCA.TIPOIPS, TEXCA.IDMEDICOEXT, TEXCA.NOMBREALTERNO
			FROM TEXCA
			INNER JOIN CAT ON CAT.IDCATEGORIA = TEXCA.IDCATEGORIA
			WHERE IDTERCERO = @IDTERCERO

			RETURN
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'STATE'
	BEGIN
		BEGIN TRY
			SELECT @IDTERCERO = IDTERCERO
			FROM OPENJSON(@PARAMETROS) WITH (IDTERCERO VARCHAR(20) '$.IDTERCERO')

			BEGIN
				UPDATE TER
				SET ESTADO = IIF((
							SELECT ESTADO
							FROM TER
							WHERE IDTERCERO = JSON_VALUE(@PARAMETROS, '$.IDTERCERO')
							) = 'Activo', 'Inactivo', 'Activo')
				WHERE IDTERCERO = JSON_VALUE(@PARAMETROS, '$.IDTERCERO')
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'UPDATE_EMAIL'
	BEGIN
		BEGIN TRY
			SELECT @IDTERCERO = IDTERCERO, @EMAIL = EMAIL
			FROM OPENJSON(@PARAMETROS) WITH (IDTERCERO VARCHAR(20) '$.IDTERCERO', EMAIL VARCHAR(512) '$.EMAIL')

			BEGIN
				UPDATE TER
				SET EMAIL = @EMAIL
				WHERE IDTERCERO = @IDTERCERO
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'EXPORTA_TER'
	BEGIN
		SELECT @CNSEXCEL = JSON_VALUE(@PARAMETROS, '$.CNSEXCEL')

		SELECT @ESTADO = ESTADO, @FILTRO = FILTRO
		FROM OPENJSON(@PARAMETROS) WITH (ESTADO VARCHAR(20) '$.ESTADO', FILTRO VARCHAR(20) '$.FILTRO')

		IF @CNSEXCEL IS NULL
		BEGIN
			EXEC SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE, '@EXCEL', @CNSEXCEL OUTPUT

			SELECT @CNSEXCEL = @IDSEDE + REPLACE(SPACE(8 - LEN(@CNSEXCEL)) + LTRIM(RTRIM(@CNSEXCEL)), SPACE(1), 0)
		END

		BEGIN TRY
			DECLARE @SQL1 NVARCHAR(MAX) = ''

			SET @SQL1 = 
				'SELECT IDTERCERO, RAZONSOCIAL,TIPO_ID AS TIPO_NIT,NIT,NATJURIDICA AS NATURALEZA, DV,TELEFONOS,EMAIL AS CORREO_ELECTRONICO,DIRECCION,IDACTIVIDAD AS ACTIVIDAD_ECONOMICA, 
				F_INSCRIPTO AS FECHA_CREACION, ESTADO FROM TER WHERE (' 
				+ 'COALESCE(RAZONSOCIAL, '''') LIKE ''%' + @FILTRO + '%'' ' + 'OR COALESCE(NIT, '''') LIKE ''%' + @FILTRO + '%'' ' + 
				'OR COALESCE(IDTERCERO, '''') LIKE ''%' + @FILTRO + '%'' )'

			IF @ESTADO = '0'
			BEGIN
				SET @SQL1 += ' AND ESTADO LIKE ''%%%%'' '
			END
			ELSE IF @ESTADO IS NULL
			BEGIN
				SET @SQL1 += ' AND (ESTADO IS NULL OR ESTADO = '''') '
			END
			ELSE IF LEN(@ESTADO) > 0
			BEGIN
				SET @SQL1 += ' AND ESTADO = ''' + @ESTADO + ''' '
			END

			INSERT INTO KEXCEL_FILL (CNSEXCEL, NOMBRE, BORRAR, CONSULTA)
			SELECT @CNSEXCEL, 'Terceros ' + CONVERT(VARCHAR, GETDATE(), 112) + '_' + REPLACE(CONVERT(VARCHAR, GETDATE(), 108), ':', '') + '.xlsx', 1, @SQL1
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK, @CNSEXCEL CNSEXCEL

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK, @CNSEXCEL CNSEXCEL
	END

	IF @METODO = 'GUARDAR_INCA_OPTION'
	BEGIN
		DECLARE @NIT_INCA_SAVE VARCHAR(50)
		DECLARE @TIPOCONTIGENCIA_SAVE VARCHAR(100)
		DECLARE @TIPODOC_JSON NVARCHAR(MAX)

		BEGIN TRY
			SELECT
				@NIT_INCA_SAVE = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.NIT'))), ''),
				@TIPOCONTIGENCIA_SAVE = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.TIPOCONTIGENCIA'))), ''),
				@TIPODOC_JSON = JSON_QUERY(@PARAMETROS, '$.TIPODOC')

			IF @NIT_INCA_SAVE IS NULL OR @TIPOCONTIGENCIA_SAVE IS NULL
				OR @TIPODOC_JSON IS NULL OR @TIPODOC_JSON IN ('', '[]')
			BEGIN
				SELECT 'KO' AS OK
				SELECT ERROR = 'Faltan parámetros: NIT, TIPOCONTIGENCIA y al menos un TIPODOC.'
				RETURN
			END

			IF OBJECT_ID('dbo.INCA_OPTION', 'U') IS NULL
			BEGIN
				SELECT 'KO' AS OK
				SELECT ERROR = 'La tabla INCA_OPTION no existe. Ejecute context/motor/INCA_OPTION.sql'
				RETURN
			END

			IF EXISTS (
				SELECT 1
				FROM dbo.INCA_OPTION
				WHERE NIT = @NIT_INCA_SAVE
					AND TIPOCONTIGENCIA = @TIPOCONTIGENCIA_SAVE
			)
			BEGIN
				UPDATE dbo.INCA_OPTION
				SET TIPODOC = @TIPODOC_JSON
				WHERE NIT = @NIT_INCA_SAVE
					AND TIPOCONTIGENCIA = @TIPOCONTIGENCIA_SAVE
			END
			ELSE
			BEGIN
				INSERT INTO dbo.INCA_OPTION (NIT, TIPOCONTIGENCIA, TIPODOC)
				VALUES (@NIT_INCA_SAVE, @TIPOCONTIGENCIA_SAVE, @TIPODOC_JSON)
			END

			SELECT 'OK' AS OK
			SELECT IDINCAOPT
			FROM dbo.INCA_OPTION
			WHERE NIT = @NIT_INCA_SAVE
				AND TIPOCONTIGENCIA = @TIPOCONTIGENCIA_SAVE
			RETURN
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' AS OK
	END

	IF @METODO = 'ELIMINAR_INCA_OPTION'
	BEGIN
		DECLARE @IDINCAOPT_DEL INT
		DECLARE @NIT_INCA_DEL VARCHAR(50)

		BEGIN TRY
			SELECT
				@IDINCAOPT_DEL = TRY_CAST(JSON_VALUE(@PARAMETROS, '$.IDINCAOPT') AS INT),
				@NIT_INCA_DEL = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.NIT'))), '')

			IF @IDINCAOPT_DEL IS NULL
			BEGIN
				SELECT 'KO' AS OK
				SELECT ERROR = 'Falta parámetro IDINCAOPT.'
				RETURN
			END

			IF OBJECT_ID('dbo.INCA_OPTION', 'U') IS NULL
			BEGIN
				SELECT 'KO' AS OK
				SELECT ERROR = 'La tabla INCA_OPTION no existe. Ejecute context/motor/INCA_OPTION.sql'
				RETURN
			END

			DELETE FROM dbo.INCA_OPTION
			WHERE IDINCAOPT = @IDINCAOPT_DEL
				AND (@NIT_INCA_DEL IS NULL OR NIT = @NIT_INCA_DEL)

			IF @@ROWCOUNT = 0
			BEGIN
				SELECT 'KO' AS OK
				SELECT ERROR = 'No se encontró el registro a eliminar.'
				RETURN
			END

			SELECT 'OK' AS OK
			RETURN
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' AS OK
	END
