	@USUCREA VARCHAR(100), @FECHACREA DATETIME, @CRONICO BIT, @CONTRATOID_MP VARCHAR(3), @PYM SMALLINT, @SYS_COMPUTERNAME VARCHAR(254), @FILTRO VARCHAR(20), 
	@CNSEXCEL VARCHAR(20), @COMPANIA VARCHAR(2), @CONDICIONPAGO VARCHAR(20), @PLAZOPAGO SMALLINT, @DTOPRONTOPAGO DECIMAL(5, 2)

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
	FROM USUSU
	WHERE USUARIO = @USUARIO

	SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
	FROM UBEQ
	WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	IF @METODO = 'GUARDAR'
	BEGIN
		SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
		FROM USUSU
		WHERE USUARIO = @USUARIO

		SELECT @IDSEDE = IDSEDE
		FROM UBEQ
		WHERE SYS_ComputerName = @SYS_COMPUTERNAME

		BEGIN TRY
			SELECT @NIT = NIT, @RAZONSOCIAL = RAZONSOCIAL, @PROCESO = PROCESO, @DV = DV, @TIPO_ID = TIPO_ID, @IDALTERNA2 = IDALTERNA2, @DIRECCION = DIRECCION, @NATJURIDICA = 
				NATJURIDICA, @CIUDAD = CIUDAD, @TELEFONOS = TELEFONOS, @FAX = FAX, @APA = APA, @F_INSCRIPTO = F_INSCRIPTO, @F_VENCIMIENT = F_VENCIMIENT, @TIPO_ID_R = 
				TIPO_ID_R, @NIT_R = NIT_R, @ESTADO = ESTADO, @IDACTIVIDAD = IDACTIVIDAD, @ENVIODICAJA = ENVIODICAJA, @MODOCOPAGO = MODOCOPAGO, @EMPIDMODELOPC = 
				EMPIDMODELOPC, @DIASVTO = DIASVTO, @ESEXTRANJERO = ESEXTRANJERO, @AUTORETENEDOR = AUTORETENEDOR, @GRANCONTRIBUYENTE = GRANCONTRIBUYENTE, @EMAIL = 
				EMAIL, @URL = URL, @NOMBRES_R_LEGAL = NOMBRES_R_LEGAL, @P_APELLIDO_R_LEGAL = P_APELLIDO_R_LEGAL, @S_APELLIDO_R_LEGAL = S_APELLIDO_R_LEGAL, 
				@DE_NIT_R_LEGAL = DE_NIT_R_LEGAL, @TIPOREGIMEN = TIPOREGIMEN, @MSUCURSALES = MSUCURSALES, @FORMAPRE = FORMAPRE, @CODIGO_ARP = CODIGO_ARP, @NORAD = 
				NORAD, @CODOPERADOR = CODOPERADOR, @CODIGO_AFP = CODIGO_AFP, @CODIGO_CCF = CODIGO_CCF, @FNAC_RLEGAL = FNAC_RLEGAL, @HOBBIE_RL = HOBBIE_RL, @PROF_RL = 
				PROF_RL, @EMAIL_RL = EMAIL_RL, @TIPOID_TH = TIPOID_TH, @NID_TH = NID_TH, @DE_NIT_TH = DE_NIT_TH, @NOMBRES_TH = NOMBRES_TH, @P_APELLIDO_TH = 
				P_APELLIDO_TH, @S_APELLIDO_TH = S_APELLIDO_TH, @FNAC_TH = FNAC_TH, @HOBBIE_TH = HOBBIE_TH, @PROF_TH = PROF_TH, @EMAIL_TH = EMAIL_TH, @HOMOLOGO = 
				HOMOLOGO, @PNOMBRE = PNOMBRE, @SNOMBRE = SNOMBRE, @PAPELLIDO = PAPELLIDO, @SAPELLIDO = SAPELLIDO, @CUE_BANCARIA = CUE_BANCARIA, @CODIGO_EAPB = 
