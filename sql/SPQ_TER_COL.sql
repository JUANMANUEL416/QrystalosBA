	DATETIME, @HOBBIE_RL VARCHAR(20), @PROF_RL VARCHAR(20), @EMAIL_RL VARCHAR(40), @TIPOID_TH VARCHAR(3), @NID_TH VARCHAR(20), @DE_NIT_TH VARCHAR(5), @NOMBRES_TH 
