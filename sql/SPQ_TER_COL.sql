	WITH ENCRYPTION
AS
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20), @IDSEDE VARCHAR(5)
DECLARE @PROCESO VARCHAR(20)
DECLARE @IDTERCERO VARCHAR(20), @RAZONSOCIAL VARCHAR(120), @NIT VARCHAR(20), @DV VARCHAR(1), @TIPO_ID VARCHAR(3), @IDALTERNA1 VARCHAR(20), @IDALTERNA2 VARCHAR(20), 
	@DIRECCION VARCHAR(60), @NATJURIDICA VARCHAR(11), @CIUDAD VARCHAR(5), @TELEFONOS VARCHAR(35), @FAX VARCHAR(10), @APA VARCHAR(6), @F_INSCRIPTO DATETIME, 
	@F_RENOVACION DATETIME, @F_VENCIMIENT DATETIME, @R_LEGAL VARCHAR(30), @TIPO_ID_R VARCHAR(3), @NIT_R VARCHAR(20), @ESTADO VARCHAR(10), @REQAUTORIZA SMALLINT, 
	@CUENTA VARCHAR(16), @ZONA VARCHAR(12), @CIA VARCHAR(2), @ACT_ECONOMICA VARCHAR(4), @ENVIODICAJA SMALLINT, @MODOCOPAGO VARCHAR(6), @EMPIDMODELOPC VARCHAR(5), 
	@DIASVTO SMALLINT, @ESEXTRANJERO SMALLINT, @CLASIFICADOR VARCHAR(20), @IDGRUPOIMP VARCHAR(2), @AUTORETENEDOR SMALLINT, @GRANCONTRIBUYENTE SMALLINT, @EMAIL 
	VARCHAR(512), @URL VARCHAR(40), @NOMBRES_R_LEGAL VARCHAR(30), @P_APELLIDO_R_LEGAL VARCHAR(20), @S_APELLIDO_R_LEGAL VARCHAR(20), @DE_NIT_R_LEGAL VARCHAR(30), 
	@IDACTIVIDAD VARCHAR(20), @TIPOREGIMEN VARCHAR(1), @MSUCURSALES SMALLINT, @FORMAPRE VARCHAR(1), @CODIGO_ARP VARCHAR(20), @NORAD VARCHAR(20), @TIPOAPORTANTE 
