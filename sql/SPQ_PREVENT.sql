CREATE OR

ALTER PROCEDURE DBO.SPQ_PREVENT @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20)
DECLARE @PROCESO VARCHAR(20), @DATO NVARCHAR(MAX)
DECLARE @CNSVAC VARCHAR(20), @ITEM DECIMAL(14, 0)
DECLARE @ITEM_NVACD DECIMAL(14, 0), @CODCONCEPTO VARCHAR(20), @CODCONCEPTOEDITE VARCHAR(20), @FECHAINI_PER VARCHAR(20), @FECHAFIN_PER VARCHAR(20), @FECHAINI 
	VARCHAR(20), @FECHAFIN VARCHAR(20), @OBSERVACION VARCHAR(512), @VALOR DECIMAL(14, 6), @VALOREDITE DECIMAL(14, 6), @IDTERCERO VARCHAR(20), @NUMDOC VARCHAR(20), 
	@CNSPAGO VARCHAR(20)
DECLARE @DIASL INT, @DIASBASE INT, @BASICO DECIMAL(14, 2), @CANTI INT, @CODPRF VARCHAR(20), @ITEM_NCOND SMALLINT, @LINEA SMALLINT, @VALOR_CNSVAC DECIMAL(14, 6), 
	@CNSLIQUIDA VARCHAR(20)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SET LANGUAGE Spanish;
	SET DATEFORMAT dmy;

	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @CNSVAC = CNSVAC, @ITEM_NVACD = ITEM_NVACD, @CODCONCEPTO = CODCONCEPTO, @FECHAINI_PER = FECHAINI_PER, @FECHAFIN_PER = FECHAFIN_PER, @OBSERVACION = 
				OBSERVACION, @VALOR = VALOR, @FECHAINI = FECHAINI, @FECHAFIN = FECHAFIN, @IDTERCERO = IDTERCERO, @NUMDOC = NUMDOC, @CNSPAGO = CNSPAGO, @CNSLIQUIDA = 
				CNSLIQUIDA, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					CNSVAC VARCHAR(20) '$.CNSVAC', ITEM_NVACD DECIMAL(14, 0) '$.ITEM_NVACD', CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO', FECHAINI_PER VARCHAR(20) 
					'$.FECHAINI_PER', FECHAFIN_PER VARCHAR(20) '$.FECHAFIN_PER', FECHAINI VARCHAR(20) '$.FECHAINI', FECHAFIN VARCHAR(20) '$.FECHAFIN', 
					OBSERVACION VARCHAR(512) '$.OBSERVACION', VALOR DECIMAL(14, 6) '$.VALOR', IDTERCERO VARCHAR(20) '$.IDTERCERO', NUMDOC VARCHAR(20) '$.NUMDOC', 
					CNSPAGO VARCHAR(20) '$.CNSPAGO', CNSLIQUIDA VARCHAR(20) '$.CNSLIQUIDA', PROCESO VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'EL VALOR A DESCONTAR ES MAYOR AL PROVISIONADO PARA EL EMPLEADO'
					WHERE EXISTS (
							SELECT 1
							FROM NVACD
							WHERE CNSVAC = @CNSVAC AND (VALOR - @VALOR) <= 0
							)

					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('EL CONCEPTO ', @CODCONCEPTO, ' YA SE ENCUENTRA APLICADO PARA EL DESCUENTO A EL EMPLEADO')
					WHERE EXISTS (
							SELECT 1
							FROM PREVENT
							WHERE CNSVAC = @CNSVAC AND CODCONCEPTO = @CODCONCEPTO
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO PREVENT (CNSVAC, ITEM_NVACD, CODCONCEPTO, FECHAINI, FECHAFIN, OBSERVACION, VALOR, IDTERCERO, CNSLIQUIDA
							)
						SELECT @CNSVAC, @ITEM_NVACD, @CODCONCEPTO, @FECHAINI_PER, @FECHAFIN_PER, @OBSERVACION, @VALOR, @IDTERCERO, @CNSLIQUIDA

						SELECT @DIASL = DATEDIFF(DAY, FECHAING, @FECHAFIN_PER), @DIASBASE = DATEDIFF(DAY, @FECHAINI, @FECHAFIN), @BASICO = BASICO, @CANTI = 
							HORASXCARGO
						FROM FNK_INFO_NEMPHIS(@FECHAFIN_PER)
						WHERE NUMDOC = @NUMDOC

						SELECT @CODPRF = CODPRF, @ITEM_NCOND = ITEM
						FROM NCOND
						WHERE CODCONCEPTO = @CODCONCEPTO

						SELECT @LINEA = COUNT(*) + 1
						FROM NEMPFD
						WHERE CNSPAGO = @CNSPAGO AND NUMDOC = @NUMDOC

						INSERT INTO NEMPFD (
							NUMDOC, CNSPAGO, ITEM, CODCONCEPTO, DETALLE, CANTIDAD, VALOR, VALOR_EMPRESA, VALOR100P, IDTRANSPRESTAMO, NUMDOCPRESTAMO, NUMCUOTA, 
							CODPRF, IDTERCERO, INCLUIR_EXCLUIR, LIQUIDAR, INFO, BASE_PRESTACIONES, ITEMCONCEPTO, VALHORASLAB, GENERANOVEFU, CODNOVEFU, 
							BASE_CALCULO, LINEA
							)
						SELECT @NUMDOC, @CNSPAGO, 'CAR00001', @CODCONCEPTO, '', @CANTI, @VALOR, 0, @VALOR, NULL, NULL, NULL, @CODPRF, @IDTERCERO, 'Automatica', 'Si', 
							'No', 'No', @ITEM_NCOND, 1, 0, 0, NULL, @LINEA

						EXEC SPK_CALCULAR_NEMPF @CNSPAGO, @NUMDOC

						UPDATE NVACD
						SET VALOR = (
								SELECT VALOR - @VALOR
								FROM NVACD
								WHERE CNSVAC = @CNSVAC
								)
						WHERE CNSVAC = @CNSVAC
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @ITEM = ITEM, @DATO = DATO
					FROM OPENJSON(@PARAMETROS) WITH (ITEM DECIMAL(14, 0) '$.ITEM', DATO NVARCHAR(MAX) AS JSON)

					SELECT @VALOREDITE = VALOREDITE, @CODCONCEPTOEDITE = CODCONCEPTOEDITE
					FROM OPENJSON(@DATO) WITH (VALOREDITE VARCHAR(20) '$.VALOREDITE', CODCONCEPTOEDITE VARCHAR(20) '$.CODCONCEPTOEDITE'
							)

					SELECT @VALOR_CNSVAC = VALOR_CNSVAC
					FROM NVACD
					WHERE CNSVAC = @CNSVAC

					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('EL CONCEPTO ', @CODCONCEPTO, ' YA SE ENCUENTRA APLICADO PARA EL DESCUENTO A EL EMPLEADO')
					WHERE EXISTS (
							SELECT 1
							FROM PREVENT
							WHERE CNSVAC = @CNSVAC AND CODCONCEPTO = @CODCONCEPTO AND ITEM <> @ITEM
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						IF (@VALOREDITE <> @VALOR)
						BEGIN
							INSERT INTO @TBLERRORES (ERROR)
							SELECT 'EL VALOR A DESCONTAR ES MAYOR AL PROVISIONADO PARA EL EMPLEADO'
							WHERE EXISTS (
									SELECT 1
									FROM NVACD
									WHERE CNSVAC = @CNSVAC AND (
											@VALOR_CNSVAC - (
												SELECT COALESCE(SUM(VALOR), 0) + @VALOR
												FROM PREVENT
												WHERE CNSVAC = @CNSVAC AND ITEM <> @ITEM
												)
											) <= 0
									)

							IF (
									SELECT COUNT(*)
									FROM @TBLERRORES
									) <= 0
							BEGIN
								UPDATE NVACD
								SET VALOR = (
										@VALOR_CNSVAC - (
											SELECT COALESCE(SUM(VALOR), 0) + @VALOR
											FROM PREVENT
											WHERE CNSVAC = @CNSVAC AND ITEM <> @ITEM
											)
										)
								WHERE CNSVAC = @CNSVAC

								UPDATE NEMPFD
								SET VALOR = @VALOR, VALOR100P = @VALOR
								WHERE NUMDOC = @NUMDOC AND CNSPAGO = @CNSPAGO AND CODCONCEPTO = @CODCONCEPTO

								UPDATE PREVENT
								SET VALOR = @VALOR
								WHERE ITEM = @ITEM

								EXEC SPK_CALCULAR_NEMPF @CNSPAGO, @NUMDOC
							END
						END

						UPDATE PREVENT
						SET CODCONCEPTO = @CODCONCEPTO, OBSERVACION = @OBSERVACION, IDTERCERO = @IDTERCERO
						WHERE ITEM = @ITEM

						SELECT @CODPRF = CODPRF, @ITEM_NCOND = ITEM
						FROM NCOND
						WHERE CODCONCEPTO = @CODCONCEPTO

						UPDATE NEMPFD
						SET CODCONCEPTO = @CODCONCEPTO, ITEMCONCEPTO = @ITEM_NCOND, CODPRF = @CODPRF, IDTERCERO = @IDTERCERO
						WHERE NUMDOC = @NUMDOC AND CNSPAGO = @CNSPAGO AND CODCONCEPTO = @CODCONCEPTOEDITE
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @CNSVAC = CNSVAC, @ITEM = ITEM, @NUMDOC = NUMDOC, @CNSPAGO = CNSPAGO, @CODCONCEPTO = CODCONCEPTO
		FROM OPENJSON(@PARAMETROS) WITH (
				CNSVAC VARCHAR(20) '$.CNSVAC', ITEM DECIMAL(14, 0) '$.ITEM', CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO', NUMDOC VARCHAR(20) '$.NUMDOC', CNSPAGO VARCHAR
				(20) '$.CNSPAGO'
				)

		BEGIN TRY
			SELECT @VALOR_CNSVAC = VALOR_CNSVAC
			FROM NVACD
			WHERE CNSVAC = @CNSVAC

			UPDATE NVACD
			SET VALOR = (
					@VALOR_CNSVAC - (
						SELECT COALESCE(SUM(VALOR), 0)
						FROM PREVENT
						WHERE CNSVAC = @CNSVAC AND ITEM <> @ITEM
						)
					)
			WHERE CNSVAC = @CNSVAC

			DELETE
			FROM PREVENT
			WHERE ITEM = @ITEM

			DELETE
			FROM NEMPFD
			WHERE NUMDOC = @NUMDOC AND CNSPAGO = @CNSPAGO AND CODCONCEPTO = @CODCONCEPTO

			EXEC SPK_CALCULAR_NEMPF @CNSPAGO, @NUMDOC
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
