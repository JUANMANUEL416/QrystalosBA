CREATE OR ALTER PROCEDURE DBO.SPQ_NEMP @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @DATOS NVARCHAR(MAX)
DECLARE @USUARIO VARCHAR(20), @PROCESOSPQ VARCHAR(20)
DECLARE @TELEFONOS VARCHAR(35), @DIRECCION VARCHAR(60)
DECLARE @NUMDOC VARCHAR(20), @SEXO VARCHAR(9), @PRIMERNOMBRE VARCHAR(39), @SEGUNDONOMBRE VARCHAR(39)
DECLARE @PRIMERAPELLIDO VARCHAR(39), @SEGUNDOAPELLIDO VARCHAR(39), @IDAREA VARCHAR(20), @CCOSTO VARCHAR(20)
DECLARE @FECHAINGRESO DATETIME, @ESTADO VARCHAR(12), @FECHARETIRO DATETIME, @CAUSARETIRO VARCHAR(5)
DECLARE @BASICO DECIMAL(14, 2), @CODCARGO VARCHAR(20), @NIVEL VARCHAR(10), @GRADO VARCHAR(10)
DECLARE @HORASDELABOR SMALLINT, @DIASXCARGO DECIMAL(14, 2), @CODPLANTA VARCHAR(20), @TIPOSALARIO VARCHAR(20)
DECLARE @TALLA_CALZADO DECIMAL(14, 2), @TALLA_CAMISA VARCHAR(12), @TALLA_PANTALON DECIMAL(14, 2), @GRUPOSANGUINEO VARCHAR(3)
DECLARE @LIBRETAMILITAR VARCHAR(20), @ESTADOCIVIL VARCHAR(20), @TIPOCONTRATO VARCHAR(20), @CODNOMINA VARCHAR(2)
DECLARE @CTA_BCO VARCHAR(40), @BANCO VARCHAR(3), @SUCURSAL VARCHAR(2), @FNACIMIENTO DATETIME
DECLARE @FULTIMOPAGO DATETIME, @TIPOCESANTIAS VARCHAR(12), @FLEY50 DATETIME, @ENSINDICATO VARCHAR(2)
DECLARE @FORMADEPAGO VARCHAR(20), @FONDODEVIVIENDA VARCHAR(20), @CODPRG VARCHAR(20), @TIPOCOTIZANTE VARCHAR(10)
DECLARE @SUBTIPOCOTIZANTE VARCHAR(10), @CLASERESIDENTE VARCHAR(2), @CODUNG VARCHAR(5), @CIUDADEXP VARCHAR(5), @CIUDAD VARCHAR(5), @FAX VARCHAR(10)
DECLARE @GRUPOPOB VARCHAR(20), @CLASEMP VARCHAR(20), @LIDER VARCHAR(20), @EMAIL VARCHAR(512)
DECLARE @IDFOTO VARCHAR(50), @GRUPO_DOC VARCHAR(20), @PROCESO VARCHAR(20), @NROCONVOCA VARCHAR(20), @CollationName NVARCHAR(150)
DECLARE @TIPO_DOC VARCHAR(10), @DOCIDEMPLEADO VARCHAR(20), @TERCEROID VARCHAR(20)
DECLARE @IDSEDE VARCHAR(5), @SYS_COMPUTERNAME VARCHAR(254), @FECHAMOV DATETIME, @NUMCONTACTOEMERG VARCHAR(20), @PARENTESCO VARCHAR(20), @CONTEMERGENCIA VARCHAR(
		150), @CNSEXCEL VARCHAR(20), @AFU VARCHAR(20), @SEDE VARCHAR(20), @PNOMBRE VARCHAR(20), @SAPELLIDO VARCHAR(20), @PAPELLIDO VARCHAR(20), @SNOMBRE VARCHAR(20)
	, @RANGOF VARCHAR(20), @FECHAINI DATETIME, @FECHAFIN DATETIME, @COMPANIA VARCHAR(2), @MES VARCHAR(2), @FECHAINIPRUEBA DATETIME, @FECHAFINPRUEBA DATETIME, 
	@CNSPAGO VARCHAR(20), @NUMDOCANTERIOR VARCHAR(20), @CANTHOMOLOG INT, @SOL_MOTIVO_RET VARCHAR(2)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
	FROM USUSU
	WHERE USUARIO = @USUARIO

	SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
	FROM UBEQ
	WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	IF @METODO = 'GUARDAR'
	BEGIN
		SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
		FROM USUSU
		WHERE USUARIO = @USUARIO

		SELECT @IDSEDE = IDSEDE
		FROM UBEQ
		WHERE SYS_ComputerName = @SYS_COMPUTERNAME

		BEGIN TRY
			SELECT @SEXO = SEXO, @PRIMERNOMBRE = PRIMERNOMBRE, @SEGUNDONOMBRE = SEGUNDONOMBRE, @PRIMERAPELLIDO = PRIMERAPELLIDO, @SEGUNDOAPELLIDO = SEGUNDOAPELLIDO, 
				@IDAREA = IDAREA, @CCOSTO = CCOSTO, @FECHAINGRESO = FECHAINGRESO, @ESTADO = ESTADO, @FECHARETIRO = FECHARETIRO, @CAUSARETIRO = CAUSARETIRO, @BASICO = 
				BASICO, @CODCARGO = CODCARGO, @NIVEL = NIVEL, @GRADO = GRADO, @HORASDELABOR = HORASDELABOR, @DIASXCARGO = DIASXCARGO, @CODPLANTA = CODPLANTA, 
				@TIPOSALARIO = TIPOSALARIO, @TALLA_CALZADO = TALLA_CALZADO, @TALLA_CAMISA = TALLA_CAMISA, @TALLA_PANTALON = TALLA_PANTALON, @GRUPOSANGUINEO = 
				GRUPOSANGUINEO, @LIBRETAMILITAR = LIBRETAMILITAR, @ESTADOCIVIL = ESTADOCIVIL, @TIPOCONTRATO = TIPOCONTRATO, @CODNOMINA = CODNOMINA, @CTA_BCO = 
				CTA_BCO, @BANCO = BANCO, @SUCURSAL = SUCURSAL, @FNACIMIENTO = FNACIMIENTO, @FULTIMOPAGO = FULTIMOPAGO, @TIPOCESANTIAS = TIPOCESANTIAS, @FLEY50 = FLEY50, 
				@ENSINDICATO = ENSINDICATO, @FORMADEPAGO = FORMADEPAGO, @FONDODEVIVIENDA = FONDODEVIVIENDA, @CODPRG = CODPRG, @TIPOCOTIZANTE = TIPOCOTIZANTE, 
				@SUBTIPOCOTIZANTE = SUBTIPOCOTIZANTE, @CLASERESIDENTE = CLASERESIDENTE, @CODUNG = CODUNG, @CIUDADEXP = CIUDADEXP, @GRUPOPOB = GRUPOPOB, @CLASEMP = 
				CLASEMP, @LIDER = LIDER, @EMAIL = EMAIL, @IDFOTO = IDFOTO, @GRUPO_DOC = GRUPO_DOC, @PROCESO = PROCESO, @NROCONVOCA = NROCONVOCA, @TIPO_DOC = TIPO_DOC, 
				@DOCIDEMPLEADO = DOCIDEMPLEADO, @TERCEROID = TERCEROID, @PROCESOSPQ = PROCESOSPQ, @CIUDAD = CIUDAD, @FAX = FAX, @DIRECCION = DIRECCION, @TELEFONOS = 
				TELEFONOS, @FECHAMOV = FECHAMOV, @NUMCONTACTOEMERG = NUMCONTACTOEMERG, @PARENTESCO = PARENTESCO, @CONTEMERGENCIA = CONTEMERGENCIA, @FECHAINIPRUEBA = 
				FECHAINIPRUEBA, @FECHAFINPRUEBA = FECHAFINPRUEBA
			FROM OPENJSON(@PARAMETROS) WITH (
					SEXO VARCHAR(9) '$.SEXO', PRIMERNOMBRE VARCHAR(39) '$.PRIMERNOMBRE', SEGUNDONOMBRE VARCHAR(39) '$.SEGUNDONOMBRE', PRIMERAPELLIDO VARCHAR(39) 
					'$.PRIMERAPELLIDO', SEGUNDOAPELLIDO VARCHAR(39) '$.SEGUNDOAPELLIDO', IDAREA VARCHAR(20) '$.IDAREA', CCOSTO VARCHAR(20) '$.CCOSTO', 
					FECHAINGRESO DATETIME '$.FECHAINGRESO', FECHAINGRESO_STR VARCHAR(10) '$.FECHAINGRESO_STR', ESTADO VARCHAR(12) '$.ESTADO', FECHARETIRO 
					DATETIME '$.FECHARETIRO', FECHARETIRO_STR VARCHAR(10) '$.FECHARETIRO_STR', CAUSARETIRO VARCHAR(5) '$.CAUSARETIRO', BASICO DECIMAL(14, 2) 
					'$.BASICO', CODCARGO VARCHAR(20) '$.CODCARGO', NIVEL VARCHAR(10) '$.NIVEL', GRADO VARCHAR(10) '$.GRADO', HORASDELABOR SMALLINT 
					'$.HORASDELABOR', DIASXCARGO DECIMAL(14, 2) '$.DIASXCARGO', CODPLANTA VARCHAR(20) '$.CODPLANTA', TIPOSALARIO VARCHAR(20) '$.TIPOSALARIO', 
					TALLA_CALZADO DECIMAL(14, 2) '$.TALLA_CALZADO', TALLA_CAMISA VARCHAR(12) '$.TALLA_CAMISA', TALLA_PANTALON DECIMAL(14, 2) '$.TALLA_PANTALON', 
					GRUPOSANGUINEO VARCHAR(3) '$.GRUPOSANGUINEO', LIBRETAMILITAR VARCHAR(20) '$.LIBRETAMILITAR', ESTADOCIVIL VARCHAR(20) '$.ESTADOCIVIL', 
					TIPOCONTRATO VARCHAR(20) '$.TIPOCONTRATO', CODNOMINA VARCHAR(2) '$.CODNOMINA', CTA_BCO VARCHAR(40) '$.CTA_BCO', BANCO VARCHAR(3) '$.BANCO', 
					SUCURSAL VARCHAR(2) '$.SUCURSAL', FNACIMIENTO DATETIME '$.FNACIMIENTO', FNACIMIENTO_STR VARCHAR(10) '$.FNACIMIENTO_STR', FULTIMOPAGO 
					DATETIME '$.FULTIMOPAGO', FULTIMOPAGO_STR VARCHAR(10) '$.FULTIMOPAGO_STR', TIPOCESANTIAS VARCHAR(12) '$.TIPOCESANTIAS', FLEY50 DATETIME 
					'$.FLEY50', FLEY50_STR VARCHAR(10) '$.FLEY50_STR', ENSINDICATO VARCHAR(2) '$.ENSINDICATO', FORMADEPAGO VARCHAR(20) '$.FORMADEPAGO', 
					FONDODEVIVIENDA VARCHAR(20) '$.FONDODEVIVIENDA', CODPRG VARCHAR(20) '$.CODPRG', TIPOCOTIZANTE VARCHAR(10) '$.TIPOCOTIZANTE', 
					SUBTIPOCOTIZANTE VARCHAR(10) '$.SUBTIPOCOTIZANTE', CLASERESIDENTE VARCHAR(2) '$.CLASERESIDENTE', CODUNG VARCHAR(5) '$.CODUNG', CIUDADEXP 
					VARCHAR(5) '$.CIUDADEXP', GRUPOPOB VARCHAR(20) '$.GRUPOPOB', CLASEMP VARCHAR(20) '$.CLASEMP', LIDER VARCHAR(20) '$.LIDER', EMAIL VARCHAR(512) 
					'$.EMAIL', IDFOTO VARCHAR(50) '$.IDFOTO', GRUPO_DOC VARCHAR(20) '$.GRUPO_DOC', PROCESO VARCHAR(20) '$.PROCESO', NROCONVOCA VARCHAR(20) 
					'$.NROCONVOCA', TIPO_DOC VARCHAR(10) '$.TIPO_DOC', DOCIDEMPLEADO VARCHAR(20) '$.DOCIDEMPLEADO', TERCEROID VARCHAR(20) '$.TERCEROID', 
					PROCESOSPQ VARCHAR(20) '$.PROCESOSPQ', CIUDAD VARCHAR(5) '$.CIUDAD', FAX VARCHAR(10) '$.FAX', DIRECCION VARCHAR(60) '$.DIRECCION', TELEFONOS 
					VARCHAR(35) '$.TELEFONOS', FECHAMOV DATETIME '$.FECHAMOV', NUMCONTACTOEMERG VARCHAR(20) '$.NUMCONTACTOEMERG', PARENTESCO VARCHAR(20) 
					'$.PARENTESCO', CONTEMERGENCIA VARCHAR(150) '$.CONTEMERGENCIA', FECHAINIPRUEBA DATETIME '$.FECHAINIPRUEBA', FECHAFINPRUEBA DATETIME 
					'$.FECHAFINPRUEBA'
					)

			SELECT @SOL_MOTIVO_RET = COALESCE(DATO, 'NO')
			FROM USVGS
			WHERE IDVARIABLE = 'SOL_MOTIVO_RET'

			IF @ESTADO = 'Inactivo' AND UPPER(LTRIM(RTRIM(COALESCE(@SOL_MOTIVO_RET, 'NO')))) = 'SI'
			BEGIN
				IF NULLIF(LTRIM(RTRIM(COALESCE(@CAUSARETIRO, ''))), '') IS NULL
				BEGIN
					SELECT 'KO' OK

					SELECT 'Debe indicar el motivo de retiro del empleado.' ERROR

					RETURN
				END

				IF NOT EXISTS (
						SELECT 1
						FROM TGEN
						WHERE TABLA = 'NEMP' AND CAMPO = 'MOTIVO_RETIRO' AND CODIGO = @CAUSARETIRO AND COALESCE(CHECK1, 1) = 1
						)
				BEGIN
					SELECT 'KO' OK

					SELECT 'El motivo de retiro seleccionado no es v�lido o est� inactivo.' ERROR

					RETURN
				END
			END

			IF UPPER(@PROCESOSPQ) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@NEMP', @LONGITUD = 8, @NVOCONSEC = @NUMDOC OUTPUT

					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('EL TERCERO ', @TERCEROID, ' YA SE ENCUENTRA REGISTRADO COMO EMPLEADO')
					WHERE EXISTS (
							SELECT 1
							FROM NEMP
							WHERE TERCEROID = @TERCEROID AND (FECHARETIRO IS NULL OR LTRIM(RTRIM(FECHARETIRO)) = '')
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO NEMP (
							NUMDOC, SEXO, PRIMERNOMBRE, SEGUNDONOMBRE, PRIMERAPELLIDO, SEGUNDOAPELLIDO, IDAREA, CCOSTO, FECHAINGRESO, ESTADO, FECHARETIRO, 
							CAUSARETIRO, BASICO, CODCARGO, NIVEL, GRADO, HORASDELABOR, DIASXCARGO, CODPLANTA, TIPOSALARIO, TALLA_CALZADO, TALLA_CAMISA, 
							TALLA_PANTALON, GRUPOSANGUINEO, LIBRETAMILITAR, ESTADOCIVIL, TIPOCONTRATO, CODNOMINA, CTA_BCO, BANCO, SUCURSAL, FNACIMIENTO, 
							FULTIMOPAGO, TIPOCESANTIAS, FLEY50, ENSINDICATO, FORMADEPAGO, FONDODEVIVIENDA, CODPRG, TIPOCOTIZANTE, SUBTIPOCOTIZANTE, 
							CLASERESIDENTE, CODUNG, CIUDADEXP, GRUPOPOB, CLASEMP, LIDER, EMAIL, IDFOTO, GRUPO_DOC, PROCESO, NROCONVOCA, TIPO_DOC, DOCIDEMPLEADO, 
							TERCEROID, NUMCONTACTOEMERG, PARENTESCO, CONTEMERGENCIA, FECHAINIPRUEBA, FECHAFINPRUEBA
							)
						SELECT @NUMDOC, @SEXO, @PRIMERNOMBRE, @SEGUNDONOMBRE, @PRIMERAPELLIDO, @SEGUNDOAPELLIDO, @IDAREA, @CCOSTO, @FECHAINGRESO, @ESTADO, 
							@FECHARETIRO, @CAUSARETIRO, @BASICO, @CODCARGO, @NIVEL, @GRADO, @HORASDELABOR, @DIASXCARGO, @CODPLANTA, @TIPOSALARIO, @TALLA_CALZADO
							, @TALLA_CAMISA, @TALLA_PANTALON, @GRUPOSANGUINEO, @LIBRETAMILITAR, @ESTADOCIVIL, @TIPOCONTRATO, @CODNOMINA, @CTA_BCO, @BANCO, 
							@SUCURSAL, @FNACIMIENTO, @FULTIMOPAGO, @TIPOCESANTIAS, @FLEY50, @ENSINDICATO, @FORMADEPAGO, @FONDODEVIVIENDA, @CODPRG, 
							@TIPOCOTIZANTE, @SUBTIPOCOTIZANTE, @CLASERESIDENTE, @CODUNG, @CIUDADEXP, @GRUPOPOB, @CLASEMP, @LIDER, @EMAIL, @IDFOTO, @GRUPO_DOC, 
							@PROCESO, @NROCONVOCA, @TIPO_DOC, @DOCIDEMPLEADO, @TERCEROID, @NUMCONTACTOEMERG, @PARENTESCO, @CONTEMERGENCIA, @FECHAINIPRUEBA, 
							@FECHAFINPRUEBA

						/*AGREGAR AL EMPLEADOS LOS CONCEPTOS QUE ESTAS SELECCIONADOS COMO BASE (BASICOS), SOLO PARA EMPLEADOS CREADOS NUEVOS*/
						INSERT INTO NPRFE (NUMDOC, CODPRF)
						SELECT @NUMDOC, CODPRF
						FROM NPRF
						WHERE ESTADO = 'Activo' AND ESBASE = 1

						/*AGREGAR DETALLE DE LOS CONCEPTOS ASICIADOS AL EMPLEAOD (PENDIENTE REVISAR COMO DETERMINAR LOS TERCEROS POR DEFECTO QUE SE ASIGNARAN)*/
						INSERT INTO NPRFED (NUMDOC, CODPRF, ITEM, FECHAINI)
						SELECT @NUMDOC, CODPRF, 1, GETDATE()
						FROM NPRF
						WHERE ESTADO = 'Activo' AND ESBASE = 1

						INSERT INTO NEMPHIS (
							NUMDOC, FECHAMOV, SEXO, FECHAINGRESO, ESTADO, TIPOSALARIO, TALLA_CALZADO, TALLA_CAMISA, TALLA_PANTALON, GRUPOSANGUINEO, ESTADOCIVIL, 
							TIPOCONTRATO, FNACIMIENTO, TIPOCESANTIAS, ENSINDICATO, FORMADEPAGO, USUARIOMOD, FECHAMOD, SYS_COMPUTERNAME, OPERACION
							)
						SELECT @NUMDOC, @FECHAMOV, @SEXO, @FECHAINGRESO, @ESTADO, @TIPOSALARIO, @TALLA_CALZADO, @TALLA_CAMISA, @TALLA_PANTALON, @GRUPOSANGUINEO, 
							@ESTADOCIVIL, @TIPOCONTRATO, @FNACIMIENTO, @TIPOCESANTIAS, @ENSINDICATO, @FORMADEPAGO, @USUARIO, GETDATE(), @SYS_COMPUTERNAME, 
							'Insertar'

						-- Copiar conceptos exceptos del contrato anterior del mismo empleado (reingreso individual)
						SELECT @NUMDOCANTERIOR = NULL

						SELECT TOP 1 @NUMDOCANTERIOR = E.NUMDOC
						FROM NEMP E
						WHERE E.TERCEROID = @TERCEROID AND E.NUMDOC <> @NUMDOC AND EXISTS (
								SELECT 1
								FROM NEMPE
								WHERE NUMDOC = E.NUMDOC
								)
						ORDER BY E.FECHAINGRESO DESC, E.NUMDOC DESC

						IF @NUMDOCANTERIOR IS NOT NULL
						BEGIN
							INSERT INTO NEMPE (NUMDOC, CODCONCEPTO)
							SELECT @NUMDOC, NE.CODCONCEPTO
							FROM NEMPE NE
							WHERE NE.NUMDOC = @NUMDOCANTERIOR AND NOT EXISTS (
									SELECT 1
									FROM NEMPE X
									WHERE X.NUMDOC = @NUMDOC AND X.CODCONCEPTO = NE.CODCONCEPTO
									)
						END

						-- Homologar libranzas del contrato retirado inmediatamente anterior
						SET @CANTHOMOLOG = 0

						EXEC SPQ_HOMOLOGAR_PRS_NUMDOC @NUMDOC_DESTINO = @NUMDOC, @NUMDOC_ORIGEN = NULL, @TERCEROID = @TERCEROID, @USUARIO = @USUARIO, 
							@SYS_COMPUTERNAME = @SYS_COMPUTERNAME, @NUMDOCUMENTOS = NULL, @CANTIDAD = @CANTHOMOLOG OUTPUT
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK, @CANTHOMOLOG CANT_HOMOLOG

				RETURN
			END

			IF UPPER(@PROCESOSPQ) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @NUMDOC = NUMDOC, @FECHAMOV = FECHAMOV
					FROM OPENJSON(@PARAMETROS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC', FECHAMOV DATETIME '$.FECHAMOV')

					UPDATE NEMP
					SET SEXO = @SEXO, PRIMERNOMBRE = @PRIMERNOMBRE, SEGUNDONOMBRE = @SEGUNDONOMBRE, PRIMERAPELLIDO = @PRIMERAPELLIDO, SEGUNDOAPELLIDO = 
						@SEGUNDOAPELLIDO, IDAREA = @IDAREA, CCOSTO = @CCOSTO, FECHAINGRESO = @FECHAINGRESO, ESTADO = @ESTADO, FECHARETIRO = @FECHARETIRO, CAUSARETIRO = 
						@CAUSARETIRO, BASICO = @BASICO, CODCARGO = @CODCARGO, NIVEL = @NIVEL, GRADO = @GRADO, HORASDELABOR = @HORASDELABOR, DIASXCARGO = @DIASXCARGO, 
						CODPLANTA = @CODPLANTA, TIPOSALARIO = @TIPOSALARIO, TALLA_CALZADO = @TALLA_CALZADO, TALLA_CAMISA = @TALLA_CAMISA, TALLA_PANTALON = 
						@TALLA_PANTALON, GRUPOSANGUINEO = @GRUPOSANGUINEO, LIBRETAMILITAR = @LIBRETAMILITAR, ESTADOCIVIL = @ESTADOCIVIL, TIPOCONTRATO = 
						@TIPOCONTRATO, CODNOMINA = @CODNOMINA, CTA_BCO = @CTA_BCO, BANCO = @BANCO, SUCURSAL = @SUCURSAL, FNACIMIENTO = @FNACIMIENTO, FULTIMOPAGO = 
						@FULTIMOPAGO, TIPOCESANTIAS = @TIPOCESANTIAS, FLEY50 = @FLEY50, ENSINDICATO = @ENSINDICATO, FORMADEPAGO = @FORMADEPAGO, FONDODEVIVIENDA = 
						@FONDODEVIVIENDA, CODPRG = @CODPRG, TIPOCOTIZANTE = @TIPOCOTIZANTE, SUBTIPOCOTIZANTE = @SUBTIPOCOTIZANTE, CLASERESIDENTE = @CLASERESIDENTE
						, CODUNG = @CODUNG, CIUDADEXP = @CIUDADEXP, GRUPOPOB = @GRUPOPOB, CLASEMP = @CLASEMP, LIDER = @LIDER, EMAIL = @EMAIL, IDFOTO = @IDFOTO, GRUPO_DOC = 
						@GRUPO_DOC, PROCESO = @PROCESO, NROCONVOCA = @NROCONVOCA, TIPO_DOC = @TIPO_DOC, DOCIDEMPLEADO = @DOCIDEMPLEADO, NUMCONTACTOEMERG = 
						@NUMCONTACTOEMERG, PARENTESCO = @PARENTESCO, CONTEMERGENCIA = @CONTEMERGENCIA, FECHAINIPRUEBA = @FECHAINIPRUEBA, FECHAFINPRUEBA = 
						@FECHAFINPRUEBA
					WHERE NUMDOC = @NUMDOC

					UPDATE TER
					SET TELEFONOS = @TELEFONOS, DIRECCION = @DIRECCION, CIUDAD = @CIUDAD, EMAIL = @EMAIL, FAX = @FAX, CUE_BANCARIA = @CTA_BCO, BANCO = @BANCO, SUCURSAL = 
						@SUCURSAL
					WHERE IDTERCERO = @TERCEROID

					EXEC DBO.SPK_ADD_HISTORICO_NEMP @NUMDOC = @NUMDOC, @USUARIO = @USUARIO, @SYS_COMPUTERNAME = @SYS_COMPUTERNAME, @OPERACION = 'CAMBIA', @FECHAMOV = 
						@FECHAMOV

					-- ACTUALIZAR CORREO EN QRY ENVIOS
					UPDATE QE
					SET QE.DESTINOS = COALESCE(NULLIF(TRIM(@EMAIL), ''), TRIM(TER.EMAIL))
					FROM QRY_ENVIOS QE
					INNER JOIN NEMP ON NEMP.NUMDOC = QE.IDAFILIADO
					INNER JOIN TER ON NEMP.TERCEROID = TER.IDTERCERO
					WHERE QE.IDAFILIADO = @NUMDOC AND QE.ESTADO <> 'ENVIADO' AND QE.CLASE = 'NOM_COLILLAS' AND COALESCE(TRIM(QE.DESTINOS), '') <> COALESCE(NULLIF(TRIM
								(@EMAIL), ''), TRIM(TER.EMAIL), '')
						--
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GETINFNEMP'
	BEGIN
		SELECT COALESCE(USUSU.EMAIL, NEMP.EMAIL, TER.EMAIL) EMAIL, TER.TELEFONOS, TER.DIRECCION
		FROM NEMP
		INNER JOIN TER ON TER.IDTERCERO = NEMP.TERCEROID
		INNER JOIN USUSU ON USUSU.IDEMPLEADO = NEMP.TERCEROID
		WHERE NEMP.TERCEROID = JSON_VALUE(@PARAMETROS, '$.IDEMPLEADO')

		RETURN
	END

	IF @METODO = 'UPDATEINFNEMP'
	BEGIN
		BEGIN TRY
			SELECT @TELEFONOS = TELEFONOS, @EMAIL = EMAIL, @DIRECCION = DIRECCION
			FROM OPENJSON(@PARAMETROS) WITH (TELEFONOS VARCHAR(35) '$.TELEFONOS', EMAIL VARCHAR(60) '$.EMAIL', DIRECCION VARCHAR(60) '$.DIRECCION'
					)

			UPDATE USUSU
			SET EMAIL = @EMAIL
			WHERE IDEMPLEADO = JSON_VALUE(@PARAMETROS, '$.IDEMPLEADO')

			UPDATE NEMP
			SET EMAIL = @EMAIL
			WHERE TERCEROID = JSON_VALUE(@PARAMETROS, '$.IDEMPLEADO')

			UPDATE TER
			SET EMAIL = @EMAIL, TELEFONOS = @TELEFONOS, DIRECCION = @DIRECCION
			WHERE IDTERCERO = JSON_VALUE(@PARAMETROS, '$.IDEMPLEADO')
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
