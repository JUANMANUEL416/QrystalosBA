/*
  CEM — Reconstruir el detalle de la nota de devolución 26CM000417.

  La nota nació de la devolución de inventario 0600012360
  (factura CVF3397677, artículo MX352-4, 6 × 7.829 = 46.974, sin IVA).
  La procedencia sigue en INV, pero el detalle de artículos se perdió.
  Sin ese detalle, al contabilizar el crédito sale a 14150502
  (medicamentos excluidos, la cuenta de la compra).

  Este script vuelve a armar la línea como la confirmación de inventario:
  el artículo devuelto, valor 46.974, sin IVA, y la cuenta de reversión
  14150591 (devolución de medicamentos excluidos).
  También deja esa cuenta en el crédito de la nota y marca el detalle
  por ítem, para que un guardado posterior no borre la línea.

  No toca la entrada, las existencias, el saldo de la cuenta por pagar
  ni el valor de la nota. La nota no está contabilizada.

  Uso:
    1. Deje @APLICAR = 0 y ejecute. Revise el listado.
    2. Ponga @APLICAR = 1 y vuelva a ejecutar.
       Si algo no cuadra, hace ROLLBACK y no deja nada.
*/

SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @APLICAR bit = 0;
DECLARE @CNS varchar(20) = N'26CM000417';
DECLARE @ITEM int = 1;
DECLARE @MOV varchar(20) = N'0600012360';
DECLARE @ART varchar(20) = N'MX352-4';
DECLARE @NETO decimal(14, 2) = 46974.00;
DECLARE @CTA_DEV varchar(20) = N'14150591';

SELECT
  N.CNSFCXP,
  N.PROCEDENCIA,
  N.CNSMOV,
  N.CUENTA_DB,
  N.CUENTA_CR AS CREDITO_HOY,
  @CTA_DEV AS CREDITO_QUEDA,
  CONVERT(decimal(18, 2), N.VLR_NETO) AS NETO_NOTA,
  N.CONTABILIZADA,
  N.MASITEM AS MASITEM_HOY,
  H.IDARTICULO,
  CONVERT(decimal(18, 2), H.CANTIDAD) AS CANTIDAD,
  CONVERT(decimal(18, 2), H.PCOSTO) AS COSTO,
  CONVERT(decimal(18, 2), H.CANTIDAD * H.PCOSTO) AS VALOR_LINEA,
  D.CUENTA_SER AS CUENTA_COMPRA,
  C.CUENTAREV AS CUENTA_DEVOLUCION,
  (SELECT COUNT(*) FROM dbo.FCXPDNOT X WHERE X.CNSFCXP = N.CNSFCXP AND X.ITEM_DBCR = N.ITEM) AS ITEMS_HOY
FROM dbo.FCXPDBCR N
INNER JOIN dbo.IMOVH H
  ON H.CNSMOV = N.CNSMOV
 AND H.IDARTICULO = @ART
INNER JOIN dbo.FCXPD D
  ON D.CNSFCXP = N.CNSFCXP
 AND D.IDSERVICIO = H.IDARTICULO
 AND D.NOLOTE = H.NOLOTEPEDIDO
INNER JOIN dbo.CUE C
  ON C.CUENTA = D.CUENTA_SER
WHERE N.CNSFCXP = @CNS
  AND N.ITEM = @ITEM;

IF @APLICAR = 0
  RETURN;

BEGIN TRAN;

IF NOT EXISTS (
  SELECT 1
  FROM dbo.FCXPDBCR
  WHERE CNSFCXP = @CNS
    AND ITEM = @ITEM
    AND PROCEDENCIA = N'INV'
    AND CNSMOV = @MOV
    AND ESTADO = N'N'
    AND COALESCE(CONTABILIZADA, 0) = 0
    AND COALESCE(RTRIM(NROCOMPROBANTE), N'') = N''
    AND CUENTA_DB = N'22050101'
    AND VLR_NETO = @NETO
    AND COALESCE(VALORIVA, 0) = 0
)
BEGIN
  ROLLBACK TRAN;
  THROW 56050, 'La nota 26CM000417 ya no está libre o cambió el valor.', 1;
END;

IF EXISTS (
  SELECT 1 FROM dbo.FCXPDNOT WHERE CNSFCXP = @CNS AND ITEM_DBCR = @ITEM
)
BEGIN
  ROLLBACK TRAN;
  THROW 56051, 'La nota ya tiene detalle. No se vuelve a armar.', 1;
END;

IF (
  SELECT COUNT(*)
  FROM dbo.IMOVH H
  INNER JOIN dbo.FCXPD D
    ON D.CNSFCXP = @CNS
   AND D.IDSERVICIO = H.IDARTICULO
   AND D.NOLOTE = H.NOLOTEPEDIDO
  WHERE H.CNSMOV = @MOV
) <> 1
BEGIN
  ROLLBACK TRAN;
  THROW 56052, 'La devolución no cruza con una sola línea de la compra.', 1;
END;

IF NOT EXISTS (
  SELECT 1
  FROM dbo.IMOVH H
  INNER JOIN dbo.FCXPD D
    ON D.CNSFCXP = @CNS
   AND D.IDSERVICIO = H.IDARTICULO
   AND D.NOLOTE = H.NOLOTEPEDIDO
  INNER JOIN dbo.CUE C
    ON C.CUENTA = D.CUENTA_SER
   AND COALESCE(C.MCUEREV, 0) = 1
   AND C.CUENTAREV = @CTA_DEV
  WHERE H.CNSMOV = @MOV
    AND H.IDARTICULO = @ART
    AND H.CANTIDAD = 6
    AND H.PCOSTO = 7829
    AND COALESCE(H.PIVA, 0) = 0
    AND ROUND(H.CANTIDAD * H.PCOSTO, 2) = @NETO
    AND D.CUENTA_SER = N'14150502'
)
BEGIN
  ROLLBACK TRAN;
  THROW 56053, 'El artículo, el valor o la cuenta de devolución no coinciden.', 1;
END;

INSERT INTO dbo.FCXPDNOT (
  CNSFCXP, VALOR_DESCUENTO, ITEM, IDSERVICIO, CANTIDAD, VALOR, PORIVA, VLR_IVA, VLR_NETO,
  DESCTO, CTA_SER, CTA_IVA, IDIMP_IVA, IDCLASE_IVA, AFECTA_IVA, AFECTA_IMPUESTOS, FECHA_CREA, ITEM_DBCR
)
SELECT
  @CNS,
  0,
  1,
  H.IDARTICULO,
  H.CANTIDAD,
  ROUND(H.CANTIDAD * H.PCOSTO, 2),
  COALESCE(H.PIVA, 0),
  0,
  ROUND(H.CANTIDAD * H.PCOSTO, 2),
  H.VLRDTO,
  C.CUENTAREV,
  NULLIF(RTRIM(D.CUENTA_IVA), N''),
  NULLIF(NULLIF(RTRIM(D.IDIMPUESTO), N''), N'0'),
  NULLIF(NULLIF(RTRIM(D.IDCLASE), N''), N'0'),
  0,
  0,
  GETDATE(),
  @ITEM
FROM dbo.IMOVH H
INNER JOIN dbo.FCXPD D
  ON D.CNSFCXP = @CNS
 AND D.IDSERVICIO = H.IDARTICULO
 AND D.NOLOTE = H.NOLOTEPEDIDO
INNER JOIN dbo.CUE C
  ON C.CUENTA = D.CUENTA_SER
WHERE H.CNSMOV = @MOV;

IF @@ROWCOUNT <> 1
BEGIN
  ROLLBACK TRAN;
  THROW 56054, 'No se insertó la línea de la devolución.', 1;
END;

UPDATE dbo.FCXPDBCR
SET CUENTA_CR = @CTA_DEV,
    MASITEM = 1
WHERE CNSFCXP = @CNS
  AND ITEM = @ITEM
  AND COALESCE(CONTABILIZADA, 0) = 0;

IF (
  SELECT COUNT(*)
  FROM dbo.FCXPDNOT
  WHERE CNSFCXP = @CNS
    AND ITEM_DBCR = @ITEM
    AND IDSERVICIO = @ART
    AND CTA_SER = @CTA_DEV
    AND COALESCE(VLR_IVA, 0) = 0
    AND VLR_NETO = @NETO
) <> 1
   OR EXISTS (
  SELECT 1
  FROM dbo.FCXPDBCR
  WHERE CNSFCXP = @CNS
    AND ITEM = @ITEM
    AND (CUENTA_CR <> @CTA_DEV OR COALESCE(MASITEM, 0) <> 1 OR VLR_NETO <> @NETO)
)
BEGIN
  ROLLBACK TRAN;
  THROW 56055, 'El detalle armado no cuadra con la nota.', 1;
END;

COMMIT TRAN;

SELECT
  N.CNSFCXP,
  N.CUENTA_DB,
  N.CUENTA_CR,
  N.MASITEM,
  CONVERT(decimal(18, 2), N.VLR_NETO) AS NETO_NOTA,
  D.ITEM,
  D.IDSERVICIO,
  CONVERT(decimal(18, 2), D.CANTIDAD) AS CANTIDAD,
  CONVERT(decimal(18, 2), D.VALOR) AS VALOR,
  CONVERT(decimal(18, 2), D.VLR_IVA) AS IVA,
  CONVERT(decimal(18, 2), D.VLR_NETO) AS NETO_LINEA,
  D.CTA_SER
FROM dbo.FCXPDBCR N
INNER JOIN dbo.FCXPDNOT D
  ON D.CNSFCXP = N.CNSFCXP
 AND D.ITEM_DBCR = N.ITEM
WHERE N.CNSFCXP = @CNS
  AND N.ITEM = @ITEM;
