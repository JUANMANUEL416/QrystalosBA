CREATE OR ALTER PROCEDURE DBO.SPK_DIAG_MCPE_ERRORES
    @NROCOMPROBANTE VARCHAR(20) = NULL,   -- NULL = revisa MCPE en error (ESTADO = '0')
    @PROCEDENCIA    VARCHAR(20) = NULL,   -- filtro opcional: CAJA, NOTDBCRCXP, FACTURA, etc.
    @ANO            VARCHAR(4)  = NULL,   -- filtro periodo (opcional)
    @MES            INT         = NULL,   -- filtro periodo (opcional)
    @TOP            INT = 200             -- m�ximo de comprobantes a revisar
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @IDIMP_IVA VARCHAR(20) = DBO.FNK_VALORVARIABLE('IDIMP_IVA');
    IF @TOP IS NULL OR @TOP < 1 SET @TOP = 200;
    IF @TOP > 2000 SET @TOP = 2000;

    IF OBJECT_ID('tempdb..#COMP') IS NOT NULL DROP TABLE #COMP;
    IF OBJECT_ID('tempdb..#ERR') IS NOT NULL DROP TABLE #ERR;

    CREATE TABLE #COMP (
        NROCOMPROBANTE VARCHAR(20) COLLATE DATABASE_DEFAULT NOT NULL PRIMARY KEY,
        PROCEDENCIA    VARCHAR(20) COLLATE DATABASE_DEFAULT NULL,
        REFERENCIA1    VARCHAR(20) COLLATE DATABASE_DEFAULT NULL,
        REFERENCIA2    VARCHAR(20) COLLATE DATABASE_DEFAULT NULL,
        COMPANIA       VARCHAR(2)  COLLATE DATABASE_DEFAULT NULL,
        ANO            VARCHAR(4)  COLLATE DATABASE_DEFAULT NULL,
        MES            INT         NULL,
        FECHACONTABLE  DATETIME    NULL,
        TOTALDEBITO   DECIMAL(18,2) NULL,
        TOTALCREDITO  DECIMAL(18,2) NULL,
        ESTADO         VARCHAR(2)  COLLATE DATABASE_DEFAULT NULL,
        ANULADO        INT         NULL,
        COMPROBANTE    VARCHAR(10) COLLATE DATABASE_DEFAULT NULL
    );

    CREATE TABLE #ERR (
        NROCOMPROBANTE VARCHAR(20)  COLLATE DATABASE_DEFAULT NOT NULL,
        PROCEDENCIA    VARCHAR(20)  COLLATE DATABASE_DEFAULT NULL,
        REFERENCIA1    VARCHAR(20)  COLLATE DATABASE_DEFAULT NULL,
        REFERENCIA2    VARCHAR(20)  COLLATE DATABASE_DEFAULT NULL,
        COD_ERROR      VARCHAR(40)  COLLATE DATABASE_DEFAULT NOT NULL,
        SEVERIDAD      VARCHAR(10)  COLLATE DATABASE_DEFAULT NOT NULL, -- ALTA / MEDIA / BAJA
        NROASIENTO     INT          NULL,
        CUENTA         VARCHAR(20)  COLLATE DATABASE_DEFAULT NULL,
        DESCRIPCION    NVARCHAR(500) COLLATE DATABASE_DEFAULT NOT NULL,
        SUGERENCIA     NVARCHAR(500) COLLATE DATABASE_DEFAULT NULL
    );

    IF COALESCE(@NROCOMPROBANTE, '') <> ''
    BEGIN
        INSERT INTO #COMP (
            NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COMPANIA,
            ANO, MES, FECHACONTABLE, TOTALDEBITO, TOTALCREDITO, ESTADO, ANULADO, COMPROBANTE
        )
        SELECT TOP (1)
            M.NROCOMPROBANTE, M.PROCEDENCIA, M.REFERENCIA1, M.REFERENCIA2, M.COMPANIA,
            M.ANO, M.MES, M.FECHACONTABLE, M.TOTALDEBITO, M.TOTALCREDITO, M.ESTADO,
            COALESCE(M.ANULADO, 0), M.COMPROBANTE
        FROM MCPE M
        WHERE M.NROCOMPROBANTE = @NROCOMPROBANTE;
    END
    ELSE
    BEGIN
        INSERT INTO #COMP (
            NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COMPANIA,
            ANO, MES, FECHACONTABLE, TOTALDEBITO, TOTALCREDITO, ESTADO, ANULADO, COMPROBANTE
        )
        SELECT TOP (@TOP)
            M.NROCOMPROBANTE, M.PROCEDENCIA, M.REFERENCIA1, M.REFERENCIA2, M.COMPANIA,
            M.ANO, M.MES, M.FECHACONTABLE, M.TOTALDEBITO, M.TOTALCREDITO, M.ESTADO,
            COALESCE(M.ANULADO, 0), M.COMPROBANTE
        FROM MCPE M
        WHERE COALESCE(M.ESTADO, '0') = '0'
          AND COALESCE(M.ANULADO, 0) = 0
          AND (@PROCEDENCIA IS NULL OR M.PROCEDENCIA = @PROCEDENCIA)
          AND (@ANO IS NULL OR M.ANO = @ANO)
          AND (@MES IS NULL OR M.MES = @MES)
        ORDER BY M.FECHACONTABLE DESC, M.NROCOMPROBANTE DESC;
    END

    IF NOT EXISTS (SELECT 1 FROM #COMP)
    BEGIN
        SELECT
            CAST(NULL AS VARCHAR(20)) AS NROCOMPROBANTE,
            CAST(NULL AS VARCHAR(20)) AS PROCEDENCIA,
            CAST(NULL AS VARCHAR(20)) AS REFERENCIA1,
            CAST(NULL AS VARCHAR(20)) AS REFERENCIA2,
            CAST('SIN_DATOS' AS VARCHAR(40)) AS COD_ERROR,
            CAST('BAJA' AS VARCHAR(10)) AS SEVERIDAD,
            CAST(NULL AS INT) AS NROASIENTO,
            CAST(NULL AS VARCHAR(20)) AS CUENTA,
            CAST(N'No se encontraron comprobantes para diagnosticar.' AS NVARCHAR(500)) AS DESCRIPCION,
            CAST(N'Indique un NROCOMPROBANTE o verifique que existan registros en MCPE con ESTADO = 0.' AS NVARCHAR(500)) AS SUGERENCIA,
            CAST(NULL AS DECIMAL(18,2)) AS TOTALDEBITO,
            CAST(NULL AS DECIMAL(18,2)) AS TOTALCREDITO,
            CAST(NULL AS DECIMAL(18,2)) AS DIFERENCIA;
        RETURN;
    END

    -- 1) Ya est� en MCP (inconsistencia)
    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'YA_EN_MCP', 'ALTA',
           N'El comprobante tambi�n existe en MCP (contabilidad definitiva).',
           N'Revise la duplicidad entre MCPE y MCP; normalmente no deber�a permanecer en errados.'
    FROM #COMP C
    INNER JOIN MCP P ON P.NROCOMPROBANTE = C.NROCOMPROBANTE;

    -- 2) Anulado en MCPE
    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'ANULADO', 'MEDIA',
           N'El comprobante est� marcado como anulado en MCPE.',
           N'No se puede pasar a MCP. Limpie o regenere el comprobante seg�n el documento de origen.'
    FROM #COMP C
    WHERE C.ANULADO = 1;

    -- 3) Sin l�neas MCHE
    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'SIN_LINEAS_MCHE', 'ALTA',
           N'No tiene l�neas en MCHE.',
           N'Reconstruya desde el origen (CAJA / CxP / Factura) o elimine el MCPE hu�rfano.'
    FROM #COMP C
    WHERE NOT EXISTS (SELECT 1 FROM MCHE H WHERE H.NROCOMPROBANTE = C.NROCOMPROBANTE);

    -- 4) Descuadre d�bito/cr�dito
    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'DESCUADRE_DB_CR', 'ALTA',
           N'Descuadre: D�bito = ' + CONVERT(NVARCHAR(30), COALESCE(C.TOTALDEBITO, 0))
             + N' | Cr�dito = ' + CONVERT(NVARCHAR(30), COALESCE(C.TOTALCREDITO, 0))
             + N' | Diferencia = ' + CONVERT(NVARCHAR(30), ABS(COALESCE(C.TOTALDEBITO, 0) - COALESCE(C.TOTALCREDITO, 0))),
           N'Revise l�neas faltantes (IVA, retenci�n, inventario) o valores mal calculados; luego cambie Revisar o Reconstruir.'
    FROM #COMP C
    WHERE ABS(COALESCE(C.TOTALDEBITO, 0) - COALESCE(C.TOTALCREDITO, 0)) > 0.01;

    -- 4b) Descuadre real en l�neas MCHE (aunque MCPE est� cuadrado)
    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'DESCUADRE_MCHE', 'ALTA',
           N'Suma MCHE: D�bito = ' + CONVERT(NVARCHAR(30), COALESCE(H.SUMDB, 0))
             + N' | Cr�dito = ' + CONVERT(NVARCHAR(30), COALESCE(H.SUMCR, 0))
             + N' | Diferencia = ' + CONVERT(NVARCHAR(30), ABS(COALESCE(H.SUMDB, 0) - COALESCE(H.SUMCR, 0))),
           N'El encabezado MCPE puede estar cuadrado pero las l�neas MCHE no. Revise cuentas vac�as, ERROR en l�neas o reconstruya.'
    FROM #COMP C
    INNER JOIN (
        SELECT NROCOMPROBANTE,
               SUM(CASE WHEN TIPO = 'DB' THEN COALESCE(VALOR, 0) ELSE 0 END) AS SUMDB,
               SUM(CASE WHEN TIPO = 'CR' THEN COALESCE(VALOR, 0) ELSE 0 END) AS SUMCR
        FROM MCHE
        GROUP BY NROCOMPROBANTE
    ) H ON H.NROCOMPROBANTE = C.NROCOMPROBANTE
    WHERE ABS(COALESCE(H.SUMDB, 0) - COALESCE(H.SUMCR, 0)) > 0.01;

    -- 4c) Totales MCPE no coinciden con suma MCHE
    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'DESCUADRE_MCPE_MCHE', 'ALTA',
           N'MCPE DB/CR = ' + CONVERT(NVARCHAR(30), COALESCE(C.TOTALDEBITO, 0)) + N' / '
             + CONVERT(NVARCHAR(30), COALESCE(C.TOTALCREDITO, 0))
             + N' | MCHE DB/CR = ' + CONVERT(NVARCHAR(30), COALESCE(H.SUMDB, 0)) + N' / '
             + CONVERT(NVARCHAR(30), COALESCE(H.SUMCR, 0)),
           N'Reconstruya el comprobante o sincronice totales MCPE con la suma de MCHE.'
    FROM #COMP C
    INNER JOIN (
        SELECT NROCOMPROBANTE,
               SUM(CASE WHEN TIPO = 'DB' THEN COALESCE(VALOR, 0) ELSE 0 END) AS SUMDB,
               SUM(CASE WHEN TIPO = 'CR' THEN COALESCE(VALOR, 0) ELSE 0 END) AS SUMCR
        FROM MCHE
        GROUP BY NROCOMPROBANTE
    ) H ON H.NROCOMPROBANTE = C.NROCOMPROBANTE
    WHERE ABS(COALESCE(C.TOTALDEBITO, 0) - COALESCE(H.SUMDB, 0)) > 0.01
       OR ABS(COALESCE(C.TOTALCREDITO, 0) - COALESCE(H.SUMCR, 0)) > 0.01;

    -- 5) Solo d�bitos o solo cr�ditos
    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'SIN_CREDITOS', 'ALTA',
           N'Tiene d�bitos, pero no tiene cr�ditos en MCHE.',
           CASE WHEN C.PROCEDENCIA = 'NOTDBCRCXP' THEN
                N'Si es INV, verifique el IMOV ligado (CNSDBCR/ITEMDBCR). Si tiene IVA, verifique la vigencia en FIMPDV.'
                ELSE N'Reconstruya el comprobante desde el documento de origen.' END
    FROM #COMP C
    WHERE EXISTS (SELECT 1 FROM MCHE H WHERE H.NROCOMPROBANTE = C.NROCOMPROBANTE AND H.TIPO = 'DB')
      AND NOT EXISTS (SELECT 1 FROM MCHE H WHERE H.NROCOMPROBANTE = C.NROCOMPROBANTE AND H.TIPO = 'CR');

    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'SIN_DEBITOS', 'ALTA',
           N'Tiene cr�ditos, pero no tiene d�bitos en MCHE.',
           N'Reconstruya el comprobante desde el documento de origen.'
    FROM #COMP C
    WHERE EXISTS (SELECT 1 FROM MCHE H WHERE H.NROCOMPROBANTE = C.NROCOMPROBANTE AND H.TIPO = 'CR')
      AND NOT EXISTS (SELECT 1 FROM MCHE H WHERE H.NROCOMPROBANTE = C.NROCOMPROBANTE AND H.TIPO = 'DB');

    -- 6) Periodo contable
    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'PERIODO_NO_EXISTE', 'ALTA',
           N'No existe el per�odo PRI para la compa��a ' + COALESCE(CONVERT(NVARCHAR(10), C.COMPANIA), N'')
             + N', a�o ' + COALESCE(CONVERT(NVARCHAR(10), C.ANO), N'')
             + N', mes ' + CONVERT(NVARCHAR(10), C.MES) + N'.',
           N'Cree el per�odo en PRI antes de contabilizar.'
    FROM #COMP C
    WHERE NOT EXISTS (
        SELECT 1 FROM PRI P
        WHERE P.COMPANIA = C.COMPANIA AND P.ANO = C.ANO AND P.MES = C.MES
    );

    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'PERIODO_CERRADO', 'ALTA',
           N'El per�odo ' + COALESCE(CONVERT(NVARCHAR(10), C.ANO), N'') + N'-'
             + RIGHT(N'0' + CONVERT(NVARCHAR(2), C.MES), 2)
             + N' est� cerrado en PRI.',
           N'Abra el per�odo o cambie la fecha contable del comprobante.'
    FROM #COMP C
    INNER JOIN PRI P ON P.COMPANIA = C.COMPANIA AND P.ANO = C.ANO AND P.MES = C.MES
    WHERE COALESCE(P.CERRADO, 0) = 1;

    -- 7) Cuenta no existe / NO DEF
    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, NROASIENTO, CUENTA, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'CUENTA_NO_EXISTE', 'ALTA', H.NROASIENTO, H.CUENTA,
           N'La cuenta ' + COALESCE(CONVERT(NVARCHAR(20), H.CUENTA), N'(vac�a)') + N' no existe en CUE.',
           N'Corrija la cuenta en MCHE o la parametrizaci�n de origen (FPA/CPCJ/KMCOM/FCXPDBCR).'
    FROM #COMP C
    INNER JOIN MCHE H ON H.NROCOMPROBANTE = C.NROCOMPROBANTE
    WHERE COALESCE(H.CUENTA, '') <> ''
      AND NOT EXISTS (SELECT 1 FROM CUE U WHERE U.CUENTA = H.CUENTA);

    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, NROASIENTO, CUENTA, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'CUENTA_VACIA', 'ALTA', H.NROASIENTO, H.CUENTA,
           N'L�nea MCHE sin cuenta (valor ' + CONVERT(NVARCHAR(30), COALESCE(H.VALOR, 0))
             + N', proceso ' + COALESCE(CONVERT(NVARCHAR(20), H.PROCESO), N'(vac�o)') + N').',
           CASE
               WHEN H.PROCESO = 'CXC_IMPUESTOS' THEN
                   N'Revise parametrizaci�n de impuestos por recaudar (KCDE/FPA, clase impuesto). Reconstruya con SPK_NC_CONTAB_CXC.'
               ELSE N'Asigne la cuenta en MCHE o reconstruya desde el documento de origen.'
           END
    FROM #COMP C
    INNER JOIN MCHE H ON H.NROCOMPROBANTE = C.NROCOMPROBANTE
    WHERE COALESCE(H.CUENTA, '') = '';

    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, NROASIENTO, CUENTA, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'CXC_IMPUESTOS_SIN_REF', 'ALTA', H.NROASIENTO, H.CUENTA,
           N'Impuesto CXC sin referencias RFECOBRAR/clase (valor ' + CONVERT(NVARCHAR(30), COALESCE(H.VALOR, 0)) + N').',
           N'El SP de contabilizaci�n no resolvi� la cuenta del impuesto. Verifique FPAGD.VLRIMPUESTO y la parametrizaci�n de impuestos por recaudar.'
    FROM #COMP C
    INNER JOIN MCHE H ON H.NROCOMPROBANTE = C.NROCOMPROBANTE
    WHERE C.PROCEDENCIA = 'CXC'
      AND H.PROCESO = 'CXC_IMPUESTOS'
      AND COALESCE(H.CUENTA, '') = ''
      AND COALESCE(H.REFERENCIA1, '') = '';

    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, NROASIENTO, CUENTA, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'KMCOM_NO_DEFINIDO', 'ALTA', H.NROASIENTO, H.CUENTA,
           N'Cuenta provisional NO DEF.KMCOM: falta parametrizar KMCOM (contabilizaci�n por ubicaci�n).',
           N'Abra la configuraci�n de KMCOM, cree la cuenta para el prefijo/�rea/centro de costo y reconstruya el comprobante.'
    FROM #COMP C
    INNER JOIN MCHE H ON H.NROCOMPROBANTE = C.NROCOMPROBANTE
    WHERE H.CUENTA LIKE 'NO DEF.KMCOM%';

    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, NROASIENTO, CUENTA, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'FIMPDV_NO_DEFINIDO', 'ALTA', H.NROASIENTO, H.CUENTA,
           N'Cuenta provisional NO DEF.FIMPDV: el impuesto del recaudo no tiene vigencia/cuenta en FIMPDV.',
           N'Configure FIMPDV (impuesto/clase/�tem) con cuenta vigente, corrija FPAGDI y reconstruya con SPK_NC_CONTAB_CXC.'
    FROM #COMP C
    INNER JOIN MCHE H ON H.NROCOMPROBANTE = C.NROCOMPROBANTE
    WHERE H.CUENTA LIKE 'NO DEF.FIMPDV%';

    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, NROASIENTO, CUENTA, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'CUENTA_NO_DEFINIDA', 'ALTA', H.NROASIENTO, H.CUENTA,
           N'Cuenta provisional: ' + CONVERT(NVARCHAR(30), H.CUENTA) + N' (parametrizaci�n incompleta).',
           N'Revise KCDE/KMCOM/PAR/FPA/CPCJ seg�n el PROCESO de la l�nea.'
    FROM #COMP C
    INNER JOIN MCHE H ON H.NROCOMPROBANTE = C.NROCOMPROBANTE
    WHERE H.CUENTA LIKE 'NO DEF%'
      AND H.CUENTA NOT LIKE 'NO DEF.KMCOM%'
      AND H.CUENTA NOT LIKE 'NO DEF.FIMPDV%';

    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, NROASIENTO, CUENTA, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'CUENTA_INACTIVA', 'MEDIA', H.NROASIENTO, H.CUENTA,
           N'La cuenta ' + CONVERT(NVARCHAR(20), H.CUENTA) + N' existe, pero no est� Activa.',
           N'Active la cuenta en CUE o c�mbiela por una cuenta vigente.'
    FROM #COMP C
    INNER JOIN MCHE H ON H.NROCOMPROBANTE = C.NROCOMPROBANTE
    INNER JOIN CUE U ON U.CUENTA = H.CUENTA
    WHERE COALESCE(U.ESTADO, '') <> 'Activa';

    -- 8) Error marcado por REVISAMCPE
    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, NROASIENTO, CUENTA, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'MCHE_ERROR', 'ALTA', H.NROASIENTO, H.CUENTA,
           N'Error en la l�nea MCHE: ' + LEFT(CONVERT(NVARCHAR(400), H.ERROR), 400),
           N'Corrija la l�nea (cuenta, tercero o centro de costo) y vuelva a Revisar.'
    FROM #COMP C
    INNER JOIN MCHE H ON H.NROCOMPROBANTE = C.NROCOMPROBANTE
    WHERE H.ERROR IS NOT NULL AND LTRIM(RTRIM(CONVERT(NVARCHAR(MAX), H.ERROR))) <> N'';

    -- 9) Tercero requerido / inexistente / inactivo
    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, NROASIENTO, CUENTA, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'TERCERO_REQUERIDO', 'ALTA', H.NROASIENTO, H.CUENTA,
           N'La cuenta ' + CONVERT(NVARCHAR(20), H.CUENTA) + N' exige tercero y la l�nea no lo tiene.',
           N'Asigne el IDTERCERO en MCHE.'
    FROM #COMP C
    INNER JOIN MCHE H ON H.NROCOMPROBANTE = C.NROCOMPROBANTE
    INNER JOIN CUE U ON U.CUENTA = H.CUENTA
    WHERE COALESCE(U.TERCERO, 0) = 1
      AND COALESCE(H.IDTERCERO, '') = '';

    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, NROASIENTO, CUENTA, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'TERCERO_NO_EXISTE', 'ALTA', H.NROASIENTO, H.CUENTA,
           N'El tercero ' + CONVERT(NVARCHAR(30), H.IDTERCERO)
             + N' no existe en TER (cuenta ' + CONVERT(NVARCHAR(20), H.CUENTA) + N').',
           N'Cree o active el tercero, o corrija el IDTERCERO en la l�nea.'
    FROM #COMP C
    INNER JOIN MCHE H ON H.NROCOMPROBANTE = C.NROCOMPROBANTE
    INNER JOIN CUE U ON U.CUENTA = H.CUENTA
    WHERE COALESCE(U.TERCERO, 0) = 1
      AND COALESCE(H.IDTERCERO, '') <> ''
      AND NOT EXISTS (SELECT 1 FROM TER T WHERE T.IDTERCERO = H.IDTERCERO);

    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, NROASIENTO, CUENTA, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'TERCERO_INACTIVO', 'MEDIA', H.NROASIENTO, H.CUENTA,
           N'El tercero ' + CONVERT(NVARCHAR(30), H.IDTERCERO) + N' no est� Activo.',
           N'Active el tercero en TER o cambie otro IDTERCERO.'
    FROM #COMP C
