    -- Resultado (contexto MCHE para abrir KMCOM desde diagn�stico)
    -- INV: PREFIJO suele ser tipo art�culo (ITAR); CCOSTO/IDAREA a menudo vienen de la bodega (IBOD via IMOV).
    SELECT
        E.NROCOMPROBANTE,
        E.PROCEDENCIA,
        E.REFERENCIA1,
        E.REFERENCIA2,
        E.COD_ERROR,
        E.SEVERIDAD,
