    WHERE C.PROCEDENCIA = 'NOTDBCRCXP'
      AND COALESCE(D.GIVA, 0) = 1
      AND COALESCE(D.VALORIVA, 0) > 0
      AND NOT EXISTS (
            SELECT 1
            FROM FIMPD F
            INNER JOIN FIMPDV V ON F.IDIMPUESTO = V.IDIMPUESTO AND F.IDCLASE = V.IDCLASE
            WHERE F.IDIMPUESTO = @IDIMP_IVA
              AND C.FECHACONTABLE BETWEEN V.FECHAINI AND V.FECHAFIN
      );

    -- 13) CAJA: recibo marcado contabilizado pero comprobante sigue en MCPE
    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'CAJA_PENDIENTE_PASE_MCP', 'ALTA',
           N'El recibo FCJ ' + CONVERT(NVARCHAR(10), F.CODCAJA) + N'/'
             + CONVERT(NVARCHAR(20), F.CNSFACJ)
             + N' tiene CONTABILIZADA = 1, pero el comprobante no pas� a MCP.',
           N'Ejecute SPK_NC_REVISAMCPE y SPK_PASA_MCP_MCPNIIF, o reconstruya con SPK_NC_CONTAB_CAJA_ING.'
    FROM #COMP C
    INNER JOIN FCJ F
        ON F.CNSFACJ = C.REFERENCIA1
       AND F.CODCAJA = C.REFERENCIA2
    WHERE C.PROCEDENCIA = 'CAJA'
      AND COALESCE(F.CONTABILIZADA, 0) = 1
      AND NOT EXISTS (SELECT 1 FROM MCP P WHERE P.NROCOMPROBANTE = C.NROCOMPROBANTE);

    -- 13b) CXC: recaudo FPAG cerrado con comprobante atascado en MCPE
    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'CXC_RECAUDO_SIN_MCP', 'ALTA',
           N'Recaudo FPAG ' + CONVERT(NVARCHAR(20), F.CNSFPAG)
             + N' cerrado (VLRTOTAL = ' + CONVERT(NVARCHAR(30), COALESCE(F.VLRTOTAL, 0))
             + N') sin pasar a MCP.',
           N'Reconstruya con SPK_NC_CONTAB_CXC y revise l�neas CXC_IMPUESTOS sin cuenta.'
    FROM #COMP C
    INNER JOIN FPAG F ON F.CNSFPAG = C.REFERENCIA1
    WHERE C.PROCEDENCIA = 'CXC'
      AND COALESCE(F.CERRADO, 0) = 1
      AND COALESCE(C.ESTADO, '0') = '0'
      AND NOT EXISTS (SELECT 1 FROM MCP P WHERE P.NROCOMPROBANTE = C.NROCOMPROBANTE);

    -- 13c) CXC: FPAGDI con impuesto sin FIMPDV (causa ra�z antes de MCPE)
    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'CXC_FPAGDI_SIN_FIMPDV', 'ALTA',
           N'FPAGDI FA ' + CONVERT(NVARCHAR(20), DI.N_FACTURA)
             + N' impuesto ' + COALESCE(CONVERT(NVARCHAR(20), DI.IDIMPUESTO), N'?')
             + N' clase ' + COALESCE(CONVERT(NVARCHAR(10), DI.IDCLASE), N'?')
             + N' �tem ' + CONVERT(NVARCHAR(10), COALESCE(DI.ITEMFIMPDV, 0))
