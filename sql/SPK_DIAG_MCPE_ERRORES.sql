        END AS NOM_PREFIJO,
        CASE
            WHEN C.PROCEDENCIA = 'INV' THEN
                COALESCE(
                    NULLIF(LTRIM(RTRIM(H.CCOSTO)), ''),
                    NULLIF(LTRIM(RTRIM(IM.CCOSTO)), ''),
                    NULLIF(LTRIM(RTRIM(IB.CCOSTO)), '')
                )
            ELSE H.CCOSTO
        END AS CCOSTO,
        CEN.DESCRIPCION AS NOM_CCOSTO,
        CASE
            WHEN C.PROCEDENCIA = 'INV' THEN
                COALESCE(
                    NULLIF(LTRIM(RTRIM(H.IDAREA)), ''),
                    NULLIF(LTRIM(RTRIM(IM.IDAREA)), ''),
                    NULLIF(LTRIM(RTRIM(IB.IDAREA)), ''),
                    CEN.IDAREA
                )
            ELSE COALESCE(H.IDAREA, CEN.IDAREA)
        END AS IDAREA,
