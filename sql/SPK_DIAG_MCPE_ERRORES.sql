                COALESCE(
                    CASE WHEN H.PREFIJO = IM.IDTIPOMOV THEN ITMO.DESCRIPCION ELSE NULL END,
                    ITAR.DESCRIPCION,
                    ITMO.DESCRIPCION
                )
            ELSE
                COALESCE(
                    PRE.NOM_PREFIJO,
                    ITAR.DESCRIPCION,
                    NCON.DESCRIPCION,
                    ITMO.DESCRIPCION,
                    CPCJ.DESCRIPCION,
                    FCTSER.DESCRIPCION,
                    IACTT.DESCRIPCION
