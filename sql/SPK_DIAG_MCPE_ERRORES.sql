        H.CLASECONT,
        H.TIPO AS TIPO_MCHE,
        H.PROCESO AS PROCESO_MCHE,
        FX.PROCEDENCIA AS FCXP_PROCEDENCIA,
        IB.IDBODEGA AS IDBODEGA_INV,
        IB.DESCRIPCION AS NOM_BODEGA_INV,
        IM.IDTIPOMOV AS IDTIPOMOV_INV,
        CASE
            WHEN C.PROCEDENCIA = 'FACTURA' THEN 'VENTAS'
            WHEN C.PROCEDENCIA = 'INV' THEN 'MOV_INVENTARIO'
            WHEN C.PROCEDENCIA = 'NOMINA' THEN 'NOMINA'
            WHEN C.PROCEDENCIA IN ('CXP', 'NOTDBCRCXP') THEN
                CASE LOWER(LTRIM(RTRIM(COALESCE(FX.PROCEDENCIA, ''))))
                    WHEN 'compras' THEN 'CXP_COMPRAS'
                    WHEN 'servicios' THEN 'CXP_SERVICIOS'
                    WHEN 'salud' THEN 'CXP_SALUD'
                    WHEN 'nomina' THEN 'NOMINA'
                    WHEN 'ventas' THEN 'VENTAS'
                    ELSE 'CXP_SERVICIOS'
                END
            ELSE NULL
        END AS IDTIPOCONT_KMCOM,
        C.TOTALDEBITO,
        C.TOTALCREDITO,
        ABS(COALESCE(C.TOTALDEBITO, 0) - COALESCE(C.TOTALCREDITO, 0)) AS DIFERENCIA,
        C.FECHACONTABLE,
        C.ANO,
        C.MES
    FROM #ERR E
    INNER JOIN #COMP C ON C.NROCOMPROBANTE = E.NROCOMPROBANTE
    LEFT JOIN MCHE H
        ON H.NROCOMPROBANTE = E.NROCOMPROBANTE
       AND H.NROASIENTO = E.NROASIENTO
    LEFT JOIN FCXP FX
        ON FX.CNSFCXP = C.REFERENCIA1
       AND C.PROCEDENCIA IN ('CXP', 'NOTDBCRCXP')
    LEFT JOIN IMOV IM
        ON C.PROCEDENCIA = 'INV'
       AND IM.CNSMOV = H.REFERENCIA2
    LEFT JOIN IBOD IB
        ON C.PROCEDENCIA = 'INV'
       AND IB.IDBODEGA = COALESCE(NULLIF(LTRIM(RTRIM(IM.IDBODEGA)), ''), NULLIF(LTRIM(RTRIM(H.REFERENCIA1)), ''))
    LEFT JOIN PRE ON PRE.PREFIJO = H.PREFIJO
    LEFT JOIN ITAR ON ITAR.IDITAR = H.PREFIJO
    LEFT JOIN NCON ON NCON.CODCONCEPTO = H.PREFIJO
    LEFT JOIN ITMO ON ITMO.IDTIPOMOV = H.PREFIJO
    LEFT JOIN CPCJ ON CPCJ.CODIGO = H.PREFIJO
    LEFT JOIN FCTSER ON FCTSER.IDTIPOSER = H.PREFIJO
    LEFT JOIN IACTT ON IACTT.IDTIPOACTIVO = H.PREFIJO
    LEFT JOIN CEN
        ON CEN.COMPANIA = C.COMPANIA
       AND CEN.CCOSTO = CASE
            WHEN C.PROCEDENCIA = 'INV' THEN
                COALESCE(
                    NULLIF(LTRIM(RTRIM(H.CCOSTO)), ''),
                    NULLIF(LTRIM(RTRIM(IM.CCOSTO)), ''),
                    NULLIF(LTRIM(RTRIM(IB.CCOSTO)), '')
                )
            ELSE H.CCOSTO
        END
    LEFT JOIN AFU
        ON AFU.IDAREA = CASE
            WHEN C.PROCEDENCIA = 'INV' THEN
                COALESCE(
                    NULLIF(LTRIM(RTRIM(H.IDAREA)), ''),
                    NULLIF(LTRIM(RTRIM(IM.IDAREA)), ''),
                    NULLIF(LTRIM(RTRIM(IB.IDAREA)), ''),
                    CEN.IDAREA
                )
            ELSE COALESCE(H.IDAREA, CEN.IDAREA)
        END
    ORDER BY
        CASE E.SEVERIDAD WHEN 'ALTA' THEN 1 WHEN 'MEDIA' THEN 2 ELSE 3 END,
        E.NROCOMPROBANTE,
        E.COD_ERROR,
        E.NROASIENTO;

    DROP TABLE #ERR;
    DROP TABLE #COMP;
END
