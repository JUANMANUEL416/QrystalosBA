    -- 11d) Suma IMOVH del IMOV ligado vs valor de la nota
    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'INV_IMOV_SUMA_VS_NOTA', 'ALTA',
           N'Suma IMOVH = ' + CONVERT(NVARCHAR(30), COALESCE(S.VLR_IMOV, 0))
             + N' | Nota VLR_NETO = ' + CONVERT(NVARCHAR(30), COALESCE(D.VLR_NETO, 0))
             + N' | Diferencia = ' + CONVERT(NVARCHAR(30), ABS(COALESCE(S.VLR_IMOV, 0) - COALESCE(D.VLR_NETO, 0))),
           N'El IMOV ligado no corresponde al valor de la nota (posible IMOV compartido entre �tems). Separe movimientos o reconstruya.'
    FROM #COMP C
    INNER JOIN FCXPDBCR D
        ON D.CNSFCXP = C.REFERENCIA1
       AND CONVERT(VARCHAR(20), D.ITEM) = C.REFERENCIA2
    INNER JOIN IMOV I
        ON I.CNSDBCR = D.CNSFCXP
       AND I.ITEMDBCR = D.ITEM
       AND COALESCE(I.ESTADO, 0) = 1
    INNER JOIN (
        SELECT CNSMOV, SUM(ROUND(CONVERT(DECIMAL(18,2), CANTIDAD * PCOSTO), 2)) AS VLR_IMOV
        FROM IMOVH
        GROUP BY CNSMOV
    ) S ON S.CNSMOV = I.CNSMOV
    WHERE C.PROCEDENCIA = 'NOTDBCRCXP'
      AND COALESCE(D.PROCEDENCIA, '') = 'INV'
      AND ABS(COALESCE(S.VLR_IMOV, 0) - COALESCE(D.VLR_NETO, 0)) > 1;

    -- 12) NOTDBCRCXP con GIVA=1: vigencia IVA en FIMPDV vs fecha del comprobante
    INSERT INTO #ERR (NROCOMPROBANTE, PROCEDENCIA, REFERENCIA1, REFERENCIA2, COD_ERROR, SEVERIDAD, DESCRIPCION, SUGERENCIA)
    SELECT C.NROCOMPROBANTE, C.PROCEDENCIA, C.REFERENCIA1, C.REFERENCIA2,
           'IVA_SIN_VIGENCIA_FIMPDV', 'ALTA',
           N'Nota con GIVA = 1 y VALORIVA = ' + CONVERT(NVARCHAR(30), COALESCE(D.VALORIVA, 0))
             + N', pero no hay vigencia FIMPDV de IVA para la fecha '
