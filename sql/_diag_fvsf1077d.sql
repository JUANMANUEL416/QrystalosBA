SET NOCOUNT ON;
DECLARE @NF VARCHAR(20) = N'FVSF1077';

SELECT F.CNSFCT, F.FACTE, F.VR_TOTAL, F.VALORSERVICIOS, F.VIVA, F.VALORCOPAGO, F.COPAPROPIO, F.CP_VLR_COPAGOS
FROM dbo.FTR F WHERE F.N_FACTURA = @NF;

SELECT TOP 1 D.METODO, D.TIPO, D.ITEM, LEN(CAST(D.xml_solicitud AS NVARCHAR(MAX))) XML_LEN
FROM dbo.FDIANR D
WHERE D.CNSDOCUMENTO = (SELECT CNSFCT FROM FTR WHERE N_FACTURA=@NF)
  AND D.METODO = N'SendBillSync' AND D.TIPO = N'FV'
ORDER BY D.ITEM DESC;
