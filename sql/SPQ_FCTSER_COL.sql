CREATE OR ALTER PROCEDURE DBO.SPQ_FCTSER_COL
@JSON  NVARCHAR(MAX)
WITH
ENCRYPTION
AS
DECLARE @PARAMETROS         NVARCHAR(MAX)  ,@MODELO           VARCHAR(100)    ,@METODO        VARCHAR(100)  ,@USUARIO        VARCHAR(12)
       ,@GRUPO              VARCHAR(8)     ,@SYS_COMPUTERNAME VARCHAR(254)    ,@SEDE          VARCHAR(5)	   ,@A              INT
       ,@IDENTITY           INT 
       ,@PROCESO            VARCHAR(20)    ,@FCTSER    NVARCHAR(MAX)
              ,@IDTIPOSER     VARCHAR(6)
       ,@CUENTA     VARCHAR(16)
       ,@DESCRIPCION     VARCHAR(60)
       ,@IDGRUPOIMP     VARCHAR(2)
       ,@DECONSUMO     SMALLINT
       ,@RUBRO     VARCHAR(50)
       ,@RUBRO_ID     INT
       ,@UNSPSC     VARCHAR(20)
BEGIN
   SET LANGUAGE Spanish
   SET DATEFORMAT dmy
   
   SELECT @A = ISJSON(@JSON)
   IF @A = 0
   BEGIN
     RAISERROR('Json: Formato Erroneo',16,1)
     RETURN
   END
   PRINT 'INGRESE A SPQ_FCTSER_COL'
   SELECT *
   INTO #JSON
   FROM OPENJSON (@json)
   WITH (
     MODELO         VARCHAR(100)     '$.MODELO',
     METODO         VARCHAR(100)     '$.METODO',
     USUARIO        VARCHAR(12)      '$.USUARIO',
     PARAMETROS     NVARCHAR(MAX)     AS JSON
   )
   
   SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS , @USUARIO = USUARIO
   FROM #JSON
   --DEFINICION DE TABLA DE ERRORES
   DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200))
   -- TOMA DEL GRUPO, SYS_COMPUTERNAME, SEDE   DE ACUERDO AL USUARIO
   PRINT 'USUARIO:'+@USUARIO
   --SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO) FROM USUSU WHERE USUARIO = @USUARIO
   --SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
   --SELECT @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
   IF COALESCE(@SEDE,'') = '' SELECT @SEDE = '01'
   PRINT 'SEDE='+@SEDE
   IF @METODO = 'CRUDFCTSER'
   BEGIN
      PRINT 'CRUDFCTSER'
      SELECT @FCTSER  = REGISTRO
      FROM OPENJSON (@PARAMETROS)
      WITH(
         REGISTRO   NVARCHAR(MAX)     AS JSON
      )
      
      SELECT @PROCESO     = JSON_VALUE(@FCTSER ,'$.PROCESO')
      --Leo Campos enviados y los coloco en las variables respectivas
      SELECT @IDTIPOSER = JSON_VALUE(@FCTSER , '$.IDTIPOSER' )
      SELECT @CUENTA = JSON_VALUE(@FCTSER , '$.CUENTA' )
      SELECT @DESCRIPCION = JSON_VALUE(@FCTSER , '$.DESCRIPCION' )
      SELECT @IDGRUPOIMP = JSON_VALUE(@FCTSER , '$.IDGRUPOIMP' )
      SELECT @DECONSUMO = JSON_VALUE(@FCTSER , '$.DECONSUMO' )
      SELECT @RUBRO = JSON_VALUE(@FCTSER , '$.RUBRO' )
      SELECT @RUBRO_ID = JSON_VALUE(@FCTSER , '$.RUBRO_ID' )
      SELECT @UNSPSC = JSON_VALUE(@FCTSER , '$.UNSPSC' )
      IF UPPER(@PROCESO) = 'INSERTAR'
      BEGIN
         PRINT 'INSERTAR'
         BEGIN TRY
            INSERT INTO FCTSER(IDTIPOSER,CUENTA,DESCRIPCION,IDGRUPOIMP,DECONSUMO,RUBRO,RUBRO_ID,
                             UNSPSC)
            SELECT @IDTIPOSER,@CUENTA,@DESCRIPCION,@IDGRUPOIMP,COALESCE(@DECONSUMO,0),@RUBRO,@RUBRO_ID,
                             @UNSPSC
            SELECT @IDENTITY = SCOPE_IDENTITY()
         END TRY
         BEGIN CATCH
            INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
         END CATCH
         IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
         BEGIN
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
         END
         SELECT 'OK' OK ,str(@IDENTITY) CNS 
         RETURN
      END
      IF UPPER(@PROCESO) = 'EDITAR'
      BEGIN
         PRINT 'EDITAR'
         BEGIN TRY
            UPDATE FCTSER SET
                    IDTIPOSER = @IDTIPOSER,CUENTA = @CUENTA,DESCRIPCION = @DESCRIPCION,IDGRUPOIMP = @IDGRUPOIMP,DECONSUMO = @DECONSUMO,RUBRO = @RUBRO,RUBRO_ID = @RUBRO_ID,
                             UNSPSC = @UNSPSC
            WHERE IDTIPOSER = @IDTIPOSER
         END TRY
         BEGIN CATCH
            INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
         END CATCH
         IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
         BEGIN
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
         END
         SELECT 'OK' OK
         RETURN
      END
      RETURN
   END
END
