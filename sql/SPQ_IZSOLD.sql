CREATE OR ALTER  PROCEDURE DBO.SPQ_IZSOLD
	@JSON  NVARCHAR(MAX)
WITH
ENCRYPTION
AS
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE  @PARAMETROS NVARCHAR(MAX)
		, @MODELO    VARCHAR(100)
		, @METODO    VARCHAR(100)
		, @USUARIO   VARCHAR(12)
		, @SYS_ComputerName VARCHAR(100)
		, @IDBODEGACONSUMO VARCHAR(20)
		, @IDSEDE VARCHAR(20)
		, @NOADMISION VARCHAR(20)
		, @IDBODEGASOL VARCHAR(20)
		, @SECTOR VARCHAR(30)
		, @CNSIZSOL VARCHAR(20)
		, @CNSIZSOLD VARCHAR(20)
		, @CCOSTO VARCHAR(20)
		, @IDPLAN VARCHAR(6)
		, @TIPO_USUARIO VARCHAR(12)
		, @CLASE VARCHAR(50) = 'SENFER'
		, @COMPANIA VARCHAR(20)
		, @IDBODEGA VARCHAR(20)
      , @ID       INT
BEGIN                                                
	SELECT *
	INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

	SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON

	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @IDSEDE = IDSEDE, @COMPANIA=COMPANIA, @IDBODEGA = COALESCE(IDBODEGA, IDBODEGA2, IDBODEGANOCHE, IDBODEGACONSUMO) 
	FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
		

	IF @METODO = 'GUARDAR_ARTICULO'
	BEGIN

		SELECT @CNSIZSOLD = JSON_VALUE(@PARAMETROS, '$.CNSIZSOLD')
			,@CNSIZSOL = JSON_VALUE(@PARAMETROS, '$.CNSIZSOL')
		BEGIN TRY
			IF COALESCE(@CNSIZSOLD, '') = ''
			BEGIN
				--EXEC SPK_GENCONSECUTIVO @COMPANIA,@IDSEDE,'@IZSOLD', @CNSIZSOLD OUTPUT  
				--SELECT @CNSIZSOLD = @IDSEDE + REPLACE(SPACE(10 - LEN(@CNSIZSOLD))+LTRIM(RTRIM(@CNSIZSOLD)),SPACE(1),0)
			
				INSERT INTO IZSOLD(CNSIZSOL,IDARTICULO,CANTIDADSOL,ESTADO,CODOM,CANTIDAD,IDSERVICIO, OBSERVACION)
				SELECT CNSIZSOL, #T.IDARTICULO, CANTIDADSOL, 1, '', 0, H.HERMANO_MAYOR, #T.OBSERVACION
				FROM OPENJSON (@PARAMETROS)
				WITH ( 
					 CNSIZSOL    VARCHAR(20)   '$.CNSIZSOL'
					,IDARTICULO  VARCHAR(20)   '$.IDARTICULO'
					,CANTIDADSOL DECIMAL(14,2) '$.CANTIDADSOL'
					,IDARTICULO  VARCHAR(20)   '$.IDARTICULO'
					,OBSERVACION VARCHAR(255)  '$.OBSERVACION'
				) AS #T INNER JOIN DBO.VWK_HERMANOS_INVENTARIO H ON #T.IDARTICULO = H.IDARTICULO
            SELECT @ID = SCOPE_IDENTITY()
            SELECT @CNSIZSOLD = CNSIZSOLD FROM IZSOLD WHERE ID = @ID
			END
			ELSE
			BEGIN
				UPDATE IZSOLD
				SET IDARTICULO = #T.IDARTICULO
					,CANTIDADSOL = #T.CANTIDADSOL
					,IDSERVICIO = H.HERMANO_MAYOR
					,OBSERVACION = #T.OBSERVACION
				FROM OPENJSON (@PARAMETROS)
				WITH ( 
					 IDARTICULO  VARCHAR(20)   '$.IDARTICULO'
					,CANTIDADSOL DECIMAL(14,2) '$.CANTIDADSOL'
					,OBSERVACION VARCHAR(255)  '$.OBSERVACION'
				) AS #T INNER JOIN DBO.VWK_HERMANOS_INVENTARIO H ON #T.IDARTICULO = H.IDARTICULO
				WHERE CNSIZSOL=@CNSIZSOL AND CNSIZSOLD=@CNSIZSOLD
			END
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()          
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK, '' CONSECUTIVO
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT OK = 'OK', * 
		FROM IZSOLD
		WHERE CNSIZSOL = @CNSIZSOL 
		AND CNSIZSOLD = @CNSIZSOLD 
		RETURN
	END

	IF @METODO = 'ELIMINAR_ARTICULO'
	BEGIN

		SELECT @CNSIZSOLD = JSON_VALUE(@PARAMETROS, '$.CNSIZSOLD')
			,@CNSIZSOL = JSON_VALUE(@PARAMETROS, '$.CNSIZSOL')
		BEGIN TRY

			DELETE FROM IZSOLD
			WHERE CNSIZSOL = @CNSIZSOL
			AND CNSIZSOLD = @CNSIZSOLD

		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()          
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK, '' CONSECUTIVO
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT OK = 'OK', CNSIZSOL = @CNSIZSOL, CNSIZSOLD = @CNSIZSOLD 
		RETURN
	END

END
