CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NCONDD
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @DATOS				NVARCHAR(MAX)
DECLARE  @PARAMETROS		NVARCHAR(MAX),	@MODELO			VARCHAR(100),   @METODO		VARCHAR(100),	@USUARIO	VARCHAR(20)
DECLARE	 @PROCESO			VARCHAR(20)
DECLARE	 @CODCONCEPTO		VARCHAR(20),	@ITEM_NCOND			DECIMAL(14,0),	@ITEM				DECIMAL(14,0)
DECLARE	 @TIPODEPENDENCIA	VARCHAR(12),	@CODDEPENDENCIA		VARCHAR(20),	@FACTOR				DECIMAL(14,6)
DECLARE	 @OPERACION			VARCHAR(2),		@REQUIERELIQ		SMALLINT,		@VALHORASLAB		SMALLINT
DECLARE	 @HORAS				INT,			@DIAS				INT,			@FACTORMAX			DECIMAL(14,2)

DECLARE  @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

	IF @METODO = 'GUARDAR'
		BEGIN
			BEGIN TRY
				SELECT  @CODCONCEPTO = CODCONCEPTO, @ITEM_NCOND = ITEM_NCOND, @ITEM = ITEM,
						@TIPODEPENDENCIA = TIPODEPENDENCIA, @CODDEPENDENCIA = CODDEPENDENCIA, @FACTOR = FACTOR,
						@OPERACION = OPERACION, @REQUIERELIQ = REQUIERELIQ, @VALHORASLAB = VALHORASLAB,
						@HORAS = HORAS, @DIAS = DIAS, @FACTORMAX = FACTORMAX,
						@PROCESO = PROCESO
				FROM	OPENJSON (@PARAMETROS) 
				WITH	(
					CODCONCEPTO		VARCHAR(20)			'$.CODCONCEPTO',
					ITEM_NCOND		DECIMAL(14,0)		'$.ITEM_NCOND',
					ITEM			DECIMAL(14,0)		'$.ITEM',
					TIPODEPENDENCIA	VARCHAR(12)			'$.TIPODEPENDENCIA',
					CODDEPENDENCIA	VARCHAR(20)			'$.CODDEPENDENCIA',
					FACTOR			DECIMAL(14,6)		'$.FACTOR',
					OPERACION		VARCHAR(2)			'$.OPERACION',
					REQUIERELIQ		BIT					'$.REQUIERELIQ',
					VALHORASLAB		BIT					'$.VALHORASLAB',
					HORAS			INT					'$.HORAS',
					DIAS			INT					'$.DIAS',
					FACTORMAX		DECIMAL(14,2)		'$.FACTORMAX',
					PROCESO			VARCHAR(20)			'$.PROCESO'
				)
				IF UPPER(@PROCESO) = 'INSERTAR'
				BEGIN
					INSERT INTO NCONDD (CODCONCEPTO ,ITEM_NCOND ,TIPODEPENDENCIA ,
					CODDEPENDENCIA ,FACTOR ,OPERACION ,REQUIERELIQ ,VALHORASLAB ,
					HORAS ,DIAS ,FACTORMAX) 
					SELECT @CODCONCEPTO, @ITEM_NCOND, @TIPODEPENDENCIA,
					@CODDEPENDENCIA, @FACTOR, @OPERACION, @REQUIERELIQ, @VALHORASLAB,
					@HORAS, @DIAS, @FACTORMAX
				END

				IF UPPER(@PROCESO) = 'EDITAR'
					BEGIN
						BEGIN TRY
								BEGIN
									UPDATE NCONDD SET TIPODEPENDENCIA = @TIPODEPENDENCIA, CODDEPENDENCIA = @CODDEPENDENCIA,
									FACTOR = @FACTOR, OPERACION = @OPERACION, REQUIERELIQ = @REQUIERELIQ,
									VALHORASLAB = @VALHORASLAB, HORAS = @HORAS ,DIAS = @DIAS, FACTORMAX = @FACTORMAX
									WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM_NCOND = @ITEM_NCOND AND ITEM = @ITEM
								END
						END TRY

						BEGIN CATCH
							INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
						END CATCH

						IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
						BEGIN
							SELECT 'KO' OK
							SELECT ERROR FROM @TBLERRORES
							RETURN
						END

						SELECT 'OK' OK 
						RETURN
					END

				END TRY
				BEGIN CATCH
					INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
				END CATCH

				IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
				BEGIN
					SELECT 'KO' OK
					SELECT ERROR FROM @TBLERRORES
					RETURN
				END

				SELECT 'OK' OK 		
		END

		IF @METODO = 'ELIMINAR'
			BEGIN
					SELECT  @CODCONCEPTO = CODCONCEPTO, @ITEM_NCOND = ITEM_NCOND, @ITEM = ITEM
					FROM	OPENJSON (@PARAMETROS) 
					WITH(
						CODCONCEPTO		VARCHAR(20)			'$.CODCONCEPTO',
						ITEM_NCOND		DECIMAL(14,0)		'$.ITEM_NCOND',
						ITEM			DECIMAL(14,0)		'$.ITEM'
						)

			BEGIN TRY
					DELETE FROM NCONDD WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM_NCOND = @ITEM_NCOND AND ITEM = @ITEM
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
				END CATCH

				IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
				BEGIN
					SELECT 'KO' OK
					SELECT ERROR FROM @TBLERRORES
					RETURN
				END
		SELECT 'OK' OK
		END
END
