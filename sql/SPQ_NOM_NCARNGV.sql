CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NCARNGV @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20)
DECLARE @PROCESO VARCHAR(20), @DATO NVARCHAR(MAX)
DECLARE @CODCARGO VARCHAR(20), @NIVEL VARCHAR(10), @GRADO VARCHAR(10), @FECHA DATETIME, @DIAS SMALLINT, @HORASDELABOR SMALLINT, @BASICO DECIMAL(14, 2)
DECLARE @FECHAEDITE DATETIME
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @CODCARGO = CODCARGO, @BASICO = BASICO, @NIVEL = NIVEL, @GRADO = GRADO, @HORASDELABOR = HORASDELABOR, @DIAS = DIAS, @FECHA = FECHA, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					CODCARGO VARCHAR(20) '$.CODCARGO', BASICO DECIMAL(14, 2) '$.BASICO', HORASDELABOR SMALLINT '$.HORASDELABOR', DIAS SMALLINT '$.DIAS', NIVEL 
					VARCHAR(10) '$.NIVEL', GRADO VARCHAR(10) '$.GRADO', FECHA DATETIME '$.FECHA', PROCESO VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'YA EXISTE UN VALOR SALARIAL PARA LA FECHA SELECCIONADA'
					WHERE EXISTS (
							SELECT 1
							FROM NCARNGV
							WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVEL AND GRADO = @GRADO AND FECHA = @FECHA
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO NCARNGV (CODCARGO, NIVEL, GRADO, BASICO, HORASDELABOR, DIAS, FECHA)
						SELECT @CODCARGO, @NIVEL, @GRADO, @BASICO, @HORASDELABOR, @DIAS, @FECHA
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				SELECT @DATO = DATO
				FROM OPENJSON(@PARAMETROS) WITH (DATO NVARCHAR(MAX) AS JSON)

				SELECT @FECHAEDITE = FECHAEDITE
				FROM OPENJSON(@DATO) WITH (FECHAEDITE DATETIME '$.FECHAEDITE')

				BEGIN TRY
					IF (@FECHAEDITE <> @FECHA)
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT 'YA EXISTE UN VALOR SALARIAL PARA LA FECHA SELECCIONADA'
						WHERE EXISTS (
								SELECT 1
								FROM NCARNGV
								WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVEL AND GRADO = @GRADO AND FECHA = @FECHA
								)

						IF (
								SELECT COUNT(*)
								FROM @TBLERRORES
								) <= 0
							UPDATE NCARNGV
							SET DIAS = @DIAS, HORASDELABOR = @HORASDELABOR, BASICO = @BASICO, FECHA = @FECHA
							WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVEL AND GRADO = @GRADO AND FECHA = @FECHAEDITE
					END
					ELSE
					BEGIN
						UPDATE NCARNGV
						SET DIAS = @DIAS, HORASDELABOR = @HORASDELABOR, BASICO = @BASICO, FECHA = @FECHA
						WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVEL AND GRADO = @GRADO AND FECHA = @FECHA
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GET_NCARNGV'
	BEGIN
		SELECT @CODCARGO = CODCARGO, @NIVEL = NIVEL, @GRADO = GRADO
		FROM OPENJSON(@PARAMETROS) WITH (CODCARGO VARCHAR(20) '$.CODCARGO', NIVEL VARCHAR(10) '$.NIVEL', GRADO VARCHAR(10) '$.GRADO')

		SELECT 'OK' OK

		SELECT FECHA, CODCARGO, BASICO, HORASDELABOR, DIAS
		FROM NCARNGV
		WHERE CODCARGO = @CODCARGO AND NIVEL = @NIVEL AND GRADO = @GRADO

		RETURN
	END
END
