CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NPRFED @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @DATO NVARCHAR(MAX)
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20)
DECLARE @PROCESO VARCHAR(20)
DECLARE @NUMDOC VARCHAR(20), @CODPRF VARCHAR(20), @ITEM DECIMAL(14, 0), @FECHAINI DATETIME, @IDTERCERO VARCHAR(20)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @NUMDOC = NUMDOC, @CODPRF = CODPRF, @ITEM = ITEM, @FECHAINI = FECHAINI, @IDTERCERO = IDTERCERO, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					NUMDOC VARCHAR(20) '$.NUMDOC', CODPRF VARCHAR(20) '$.CODPRF', ITEM DECIMAL(14, 0) '$.ITEM', PROCESO VARCHAR(20) '$.PROCESO', FECHAINI DATETIME 
					'$.FECHAINI', IDTERCERO VARCHAR(20) '$.IDTERCERO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ('EL DETALLE A GUARDAR SE ENCUENTRA DUPLICADO')
					WHERE EXISTS (
							SELECT 1
							FROM NPRFED
							WHERE NUMDOC = @NUMDOC AND CODPRF = @CODPRF AND FECHAINI = @FECHAINI
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO NPRFED (NUMDOC, CODPRF, ITEM, FECHAINI, IDTERCERO)
						SELECT @NUMDOC, @CODPRF, @ITEM, @FECHAINI, @IDTERCERO
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					UPDATE NPRFED
					SET FECHAINI = @FECHAINI, IDTERCERO = @IDTERCERO
					WHERE NUMDOC = @NUMDOC AND CODPRF = @CODPRF AND ITEM = @ITEM
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GET_NPRFED_DETALLE'
	BEGIN
		SELECT @NUMDOC = NUMDOC
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC', CODPRF VARCHAR(20) '$.CODPRF')

		SELECT 'OK' OK

		SELECT NPRFED.ITEM, NPRFED.FECHAINI, NPRFED.IDTERCERO, TER.RAZONSOCIAL, NPRFED.CODPRF
		FROM NPRFED
		LEFT JOIN TER ON TER.IDTERCERO = NPRFED.IDTERCERO
		WHERE NPRFED.NUMDOC = JSON_VALUE(@PARAMETROS, '$.NUMDOC') AND NPRFED.CODPRF = JSON_VALUE(@PARAMETROS, '$.CODPRF')

		RETURN
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @NUMDOC = NUMDOC, @ITEM = ITEM, @CODPRF = CODPRF
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOC VARCHAR(20) '$.NUMDOC', ITEM DECIMAL(14, 0) '$.ITEM', CODPRF VARCHAR(20) '$.CODPRF')

		BEGIN TRY
			DELETE
			FROM NPRFED
			WHERE NUMDOC = @NUMDOC AND CODPRF = @CODPRF AND ITEM = @ITEM
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
