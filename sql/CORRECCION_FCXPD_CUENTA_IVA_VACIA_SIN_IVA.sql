/*
  CEM — quitar CUENTA_IVA donde VLR_IVA = 0 (VALIDAR_FCXP / amarre sep).
  03CM002248 DPE12286 | 03CM002017 FE5150 | 03CM002317 FE5176
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @DOC TABLE (CNSFCXP varchar(20) NOT NULL PRIMARY KEY);
INSERT INTO @DOC VALUES
  (N'03CM002248'),
  (N'03CM002017'),
  (N'03CM002317');

BEGIN TRAN;

IF EXISTS (
  SELECT 1 FROM dbo.FCXP P
  INNER JOIN @DOC D ON D.CNSFCXP = P.CNSFCXP
  WHERE P.ESTADO <> N'N' OR COALESCE(P.CONTABILIZADA, 0) <> 0
)
BEGIN
  ROLLBACK TRAN;
  THROW 55311, 'Alguna CxP del bloque no esta libre.', 1;
END;

UPDATE FD
SET CUENTA_IVA = NULL
FROM dbo.FCXPD FD
INNER JOIN @DOC D ON D.CNSFCXP = FD.CNSFCXP
WHERE COALESCE(FD.VLR_IVA, 0) <= 0
  AND COALESCE(FD.CUENTA_IVA, N'') <> N'';

IF EXISTS (
  SELECT 1 FROM dbo.FCXPD FD
  INNER JOIN @DOC D ON D.CNSFCXP = FD.CNSFCXP
  WHERE COALESCE(FD.VLR_IVA, 0) <= 0 AND COALESCE(FD.CUENTA_IVA, N'') <> N''
)
BEGIN
  ROLLBACK TRAN;
  THROW 55312, 'Quedaron lineas sin IVA con CUENTA_IVA.', 1;
END;

COMMIT TRAN;

SELECT P.NOREFERENCIA, COUNT(*) AS LINEAS_LIMPIADAS
FROM @DOC D
INNER JOIN dbo.FCXP P ON P.CNSFCXP = D.CNSFCXP
INNER JOIN dbo.FCXPD FD ON FD.CNSFCXP = D.CNSFCXP
WHERE COALESCE(FD.VLR_IVA, 0) <= 0 AND FD.CUENTA_IVA IS NULL
GROUP BY P.NOREFERENCIA;
