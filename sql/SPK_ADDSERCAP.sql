CREATE OR ALTER PROCEDURE DBO.SPK_ADDSERCAP
    @CNSFTR      VARCHAR(20),
    @N_CUOTA     INT,
    @IDTERCERO   VARCHAR(20),
    @IDPLAN      VARCHAR(6),
    @FECHAINI    DATETIME,
    @FECHAFIN    DATETIME,
    @PROCEDENCIA VARCHAR(4),
    @CLASEORDEN  VARCHAR(10) = '',
    @IDPESPECIAL VARCHAR(5) = '',
    @RIESGO      VARCHAR(20) = '',
    @NOADMISION  VARCHAR(20) = NULL,
    @IDSEDE      VARCHAR(6) = NULL
WITH ENCRYPTION
AS
DECLARE @N_FACTURA        VARCHAR(20)
        ,@COPAGOPROP      BIT
        ,@SOLO_COPA       VARCHAR(2)
        ,@INCLUYEGESTION  VARCHAR(2)
        ,@EXCUYSERPLAN    VARCHAR(2)
        ,@FECHAFIN_EX     DATETIME
        ,@FILTRA_NOADM    BIT
        ,@FILTRA_SEDE     BIT
        ,@NOADMISION_F    VARCHAR(20)
        ,@IDSEDE_F        VARCHAR(6)
BEGIN
    SET NOCOUNT ON;

    SELECT @N_FACTURA = N_FACTURA, @COPAGOPROP = COALESCE(COPAPROPIO, 0)
    FROM FTR
    WHERE CNSFCT = @CNSFTR COLLATE DATABASE_DEFAULT

    SET @SOLO_COPA      = COALESCE(DBO.FNK_VALORVARIABLE('SOLO_COPA_RECAUDADO') COLLATE DATABASE_DEFAULT, 'NO')
    SET @INCLUYEGESTION = COALESCE(DBO.FNK_VALORVARIABLE('FTRDC_INCLUYEGESTION') COLLATE DATABASE_DEFAULT, 'SI')
    SET @EXCUYSERPLAN   = COALESCE(DBO.FNK_VALORVARIABLE('FTRDC_EXCUYSERPLAN') COLLATE DATABASE_DEFAULT, 'NO')
    SET @FECHAFIN_EX    = DATEADD(DAY, 1, @FECHAFIN)
    SET @NOADMISION_F   = COALESCE(@NOADMISION, '')
    SET @IDSEDE_F       = COALESCE(@IDSEDE, '')
    SET @FILTRA_NOADM   = CASE WHEN @NOADMISION_F = '' THEN 0 ELSE 1 END
    SET @FILTRA_SEDE    = CASE WHEN @IDSEDE_F = '' THEN 0 ELSE 1 END

    PRINT 'Asignando Servicios a la Factura No. ' + @N_FACTURA + ' PROCEDENCIA ' + @PROCEDENCIA

    IF OBJECT_ID('tempdb..#CARGOS') IS NOT NULL DROP TABLE #CARGOS;
    IF OBJECT_ID('tempdb..#EXCL_SER') IS NOT NULL DROP TABLE #EXCL_SER;
    IF OBJECT_ID('tempdb..#EXCL_PLAN') IS NOT NULL DROP TABLE #EXCL_PLAN;

    CREATE TABLE #EXCL_SER (IDSERVICIO VARCHAR(20) COLLATE DATABASE_DEFAULT NOT NULL PRIMARY KEY);
    CREATE TABLE #EXCL_PLAN (
        IDPLAN     VARCHAR(20) COLLATE DATABASE_DEFAULT NOT NULL,
        IDSERVICIO VARCHAR(20) COLLATE DATABASE_DEFAULT NOT NULL
    );

    /* Una sola lectura de la vista: rango, plan, tercero, no facturada y filtros de procedencia/sede/admision. */
    SELECT
        A.PROCEDENCIA, A.FECHA, A.NOADMISION, A.PACIENTE,
        A.NOPRESTACION, A.NOITEM, A.IDSERVICIO, A.IDAREA, A.IDPLAN,
        A.CCOSTO, A.PREFIJO, A.CANTIDAD, A.VALOR, A.VALORTOTAL,
        A.VALORCOPAGO, A.ENCAJA, A.VALORPCOMP, A.VALOREXCEDENTE,
        A.DESCUENTO, A.TIPOTERCONTABLE, A.IDSEDE,
        A.CLASEORDEN, A.IDPESPECIAL, A.RIESGO
    INTO #CARGOS
    FROM VWK_CARGOS_HADMAUTCIT A
    WHERE A.FECHA >= @FECHAINI
      AND A.FECHA < @FECHAFIN_EX
      AND A.IDPLAN = @IDPLAN COLLATE DATABASE_DEFAULT
      AND A.IDTERCEROCA = @IDTERCERO COLLATE DATABASE_DEFAULT
      AND COALESCE(A.FACTURADA, 0) = 0
      AND (@PROCEDENCIA = 'TODA' OR A.PROCEDENCIA = @PROCEDENCIA COLLATE DATABASE_DEFAULT)
      AND (@FILTRA_NOADM = 0 OR A.NOADMISION = @NOADMISION_F COLLATE DATABASE_DEFAULT)
      AND (@FILTRA_SEDE = 0 OR A.IDSEDE = @IDSEDE_F COLLATE DATABASE_DEFAULT)
    OPTION (RECOMPILE);

    CREATE CLUSTERED INDEX IX_CARGOS_HADM
        ON #CARGOS (PROCEDENCIA, NOPRESTACION, NOITEM);

    IF @INCLUYEGESTION = 'NO'
    BEGIN
        INSERT INTO #EXCL_SER (IDSERVICIO)
        SELECT DISTINCT IDSERVICIOGESTION
        FROM MES
        WHERE IDSERVICIOGESTION IS NOT NULL;

        IF NOT EXISTS (SELECT 1 FROM #EXCL_SER WHERE IDSERVICIO = 'GEST0001' COLLATE DATABASE_DEFAULT)
            INSERT INTO #EXCL_SER (IDSERVICIO) VALUES ('GEST0001');
    END

    IF @EXCUYSERPLAN = 'SI'
    BEGIN
        INSERT INTO #EXCL_PLAN (IDPLAN, IDSERVICIO)
        SELECT CAMPO, CODIGO
        FROM TGEN
        WHERE TABLA = 'EXCUYSERPLAN' COLLATE DATABASE_DEFAULT;
    END

    INSERT INTO FTRDC (
        CNSFTR, N_CUOTA, PROCEDENCIA, FECHA, NOADMISION, PACIENTE, NOPRESTACION, NOITEM,
        IDSERVICIO, IDAREA, IDPLAN, CCOSTO, PREFIJO, CANTIDAD, VALOR, VALORTOTAL,
        VLR_COPAGO, VLR_PAGCOMP, VALOREXCEDENTE, DESCUENTO, TIPOTERCERO, CUENTA,
        ENRECAUDOS, IDSEDE, TCOPAGO
    )
    SELECT @CNSFTR, @N_CUOTA, A.PROCEDENCIA, A.FECHA, A.NOADMISION, A.PACIENTE,
           A.NOPRESTACION, A.NOITEM, A.IDSERVICIO, A.IDAREA, A.IDPLAN, A.CCOSTO, A.PREFIJO,
           A.CANTIDAD, A.VALOR, A.VALORTOTAL,
           CASE WHEN @SOLO_COPA = 'SI' AND A.VALORCOPAGO > 0 AND A.ENCAJA = 0 THEN 0
                ELSE A.VALORCOPAGO END,
           A.VALORPCOMP, A.VALOREXCEDENTE, A.DESCUENTO, A.TIPOTERCONTABLE, TTEC.CUENTA,
           0, A.IDSEDE,
           CASE
               WHEN A.PROCEDENCIA = 'SALUD' COLLATE DATABASE_DEFAULT AND A.VALORCOPAGO > 0 THEN '01'
               WHEN A.PROCEDENCIA COLLATE DATABASE_DEFAULT IN ('CIT', 'ONCO', 'APLIM')
                   THEN DBO.FNK_TRAE_TIPOCOPAGO(A.NOADMISION, 'CI')
               WHEN A.PROCEDENCIA = 'INV' COLLATE DATABASE_DEFAULT THEN 'C'
               ELSE DBO.FNK_TRAE_TIPOCOPAGO(A.NOADMISION, 'CE')
           END
    FROM #CARGOS A
    LEFT JOIN TTEC ON A.TIPOTERCONTABLE COLLATE DATABASE_DEFAULT = TTEC.TIPO COLLATE DATABASE_DEFAULT
    WHERE (@CLASEORDEN IN ('TODAS', '') OR ISNULL(A.CLASEORDEN COLLATE DATABASE_DEFAULT, '') = @CLASEORDEN COLLATE DATABASE_DEFAULT)
      AND (@IDPESPECIAL = '' OR ISNULL(A.IDPESPECIAL COLLATE DATABASE_DEFAULT, '') = @IDPESPECIAL COLLATE DATABASE_DEFAULT)
      AND (@RIESGO = '' OR ISNULL(A.RIESGO COLLATE DATABASE_DEFAULT, '') = @RIESGO COLLATE DATABASE_DEFAULT)
      AND (
            (@INCLUYEGESTION = 'NO' AND NOT EXISTS (
                SELECT 1 FROM #EXCL_SER E
                WHERE E.IDSERVICIO COLLATE DATABASE_DEFAULT = A.IDSERVICIO COLLATE DATABASE_DEFAULT
            ))
            OR (@INCLUYEGESTION <> 'NO' AND A.IDSERVICIO COLLATE DATABASE_DEFAULT <> '')
          )
      AND (
            @EXCUYSERPLAN <> 'SI'
            OR NOT EXISTS (
                SELECT 1 FROM #EXCL_PLAN P
                WHERE P.IDPLAN COLLATE DATABASE_DEFAULT = A.IDPLAN COLLATE DATABASE_DEFAULT
                  AND P.IDSERVICIO COLLATE DATABASE_DEFAULT = A.IDSERVICIO COLLATE DATABASE_DEFAULT
            )
          )
      AND NOT EXISTS (
            SELECT 1
            FROM FTRDC
            WHERE CNSFTR = @CNSFTR COLLATE DATABASE_DEFAULT
              AND N_CUOTA = @N_CUOTA
              AND PROCEDENCIA COLLATE DATABASE_DEFAULT = A.PROCEDENCIA COLLATE DATABASE_DEFAULT
              AND NOADMISION COLLATE DATABASE_DEFAULT = A.NOADMISION COLLATE DATABASE_DEFAULT
              AND NOPRESTACION COLLATE DATABASE_DEFAULT = A.NOPRESTACION COLLATE DATABASE_DEFAULT
              AND NOITEM = A.NOITEM
          );

    IF @PROCEDENCIA = 'TODA' OR @PROCEDENCIA = 'HADM'
    BEGIN
        PRINT 'Colocando el N_Factura en HADMF...' + @N_FACTURA + ' NO ADMISION ' + COALESCE(@NOADMISION, '')

        INSERT INTO HADMF (NOADMISION, N_FACTURA, CNSFCT, ESTADO, N_FACTURAR, ANEXOUNICO, IDTERCERO, IDPLAN, DESCRIPCION, ITFC, CNSITFC)
        SELECT DISTINCT A.NOADMISION, @N_FACTURA, @CNSFTR, 'P', NULL, NULL, @IDTERCERO, @IDPLAN, 'FACTURA CAPITADA', 0, NULL
        FROM #CARGOS A
        INNER JOIN HPRED ON HPRED.NOPRESTACION COLLATE DATABASE_DEFAULT = A.NOPRESTACION COLLATE DATABASE_DEFAULT AND HPRED.NOITEM = A.NOITEM
        WHERE A.PROCEDENCIA = 'HADM' COLLATE DATABASE_DEFAULT
          AND A.NOADMISION COLLATE DATABASE_DEFAULT = CASE WHEN @FILTRA_NOADM = 0 THEN A.NOADMISION COLLATE DATABASE_DEFAULT ELSE @NOADMISION_F COLLATE DATABASE_DEFAULT END
          AND A.IDSEDE COLLATE DATABASE_DEFAULT = CASE WHEN @FILTRA_SEDE = 0 THEN A.IDSEDE COLLATE DATABASE_DEFAULT ELSE @IDSEDE_F COLLATE DATABASE_DEFAULT END
          AND NOT EXISTS (
                SELECT 1 FROM HADMF
                WHERE HADMF.NOADMISION COLLATE DATABASE_DEFAULT = A.NOADMISION COLLATE DATABASE_DEFAULT
                  AND HADMF.N_FACTURA COLLATE DATABASE_DEFAULT = @N_FACTURA COLLATE DATABASE_DEFAULT
          );

        PRINT 'Asignando No. de Factura a las Prestaciones...'
        UPDATE HPRED SET FACTURADA = 1, N_FACTURA = @N_FACTURA
        FROM HPRED
        INNER JOIN #CARGOS A ON HPRED.NOPRESTACION COLLATE DATABASE_DEFAULT = A.NOPRESTACION COLLATE DATABASE_DEFAULT AND HPRED.NOITEM = A.NOITEM
        WHERE A.PROCEDENCIA = 'HADM' COLLATE DATABASE_DEFAULT
          AND A.NOADMISION COLLATE DATABASE_DEFAULT = CASE WHEN @FILTRA_NOADM = 0 THEN A.NOADMISION COLLATE DATABASE_DEFAULT ELSE @NOADMISION_F COLLATE DATABASE_DEFAULT END
          AND A.IDSEDE COLLATE DATABASE_DEFAULT = CASE WHEN @FILTRA_SEDE = 0 THEN A.IDSEDE COLLATE DATABASE_DEFAULT ELSE @IDSEDE_F COLLATE DATABASE_DEFAULT END;
    END

    IF @PROCEDENCIA = 'TODA' OR @PROCEDENCIA = 'AUT'
    BEGIN
        PRINT 'Asignando No. de Factura a las Autorizaciones...'
        UPDATE AUTD SET FACTURADA = 1, N_FACTURA = @N_FACTURA
        FROM AUTD
        INNER JOIN FTRDC A ON AUTD.IDAUT COLLATE DATABASE_DEFAULT = A.NOPRESTACION COLLATE DATABASE_DEFAULT AND AUTD.NO_ITEM = A.NOITEM
        WHERE A.CNSFTR = @CNSFTR COLLATE DATABASE_DEFAULT
        AND A.N_CUOTA = @N_CUOTA
        AND A.PROCEDENCIA = 'AUT' COLLATE DATABASE_DEFAULT

        UPDATE AUT SET FACTURADA = 1, N_FACTURA = @N_FACTURA
        FROM AUT
        INNER JOIN FTRDC A ON AUT.IDAUT COLLATE DATABASE_DEFAULT = A.NOPRESTACION COLLATE DATABASE_DEFAULT
        WHERE A.CNSFTR = @CNSFTR COLLATE DATABASE_DEFAULT
        AND A.N_CUOTA = @N_CUOTA
        AND A.PROCEDENCIA = 'AUT' COLLATE DATABASE_DEFAULT
    END

    IF @PROCEDENCIA = 'TODA' OR @PROCEDENCIA = 'CIT'
    BEGIN
        PRINT 'Asignando No. de Factura a las Citas...'
        UPDATE CIT SET FACTURADA = 1, N_FACTURA = @N_FACTURA
        FROM CIT
        INNER JOIN FTRDC A ON CIT.CONSECUTIVO COLLATE DATABASE_DEFAULT = A.NOPRESTACION COLLATE DATABASE_DEFAULT
        WHERE A.CNSFTR = @CNSFTR COLLATE DATABASE_DEFAULT
        AND A.N_CUOTA = @N_CUOTA
        AND A.PROCEDENCIA = 'CIT' COLLATE DATABASE_DEFAULT
    END

    IF @PROCEDENCIA = 'TODA' OR @PROCEDENCIA = 'ONCO'
    BEGIN
        PRINT 'Asignando No. de Factura a Oncologia...'
        UPDATE HCATDIMOV SET FACTURADA = 1, N_FACTURA = @N_FACTURA
        FROM HCATDIMOV
        INNER JOIN FTRDC A ON HCATDIMOV.CONSECUTIVOCIT COLLATE DATABASE_DEFAULT = A.NOADMISION COLLATE DATABASE_DEFAULT AND HCATDIMOV.ID = A.NOITEM
        WHERE A.CNSFTR = @CNSFTR COLLATE DATABASE_DEFAULT
        AND A.N_CUOTA = @N_CUOTA
        AND A.PROCEDENCIA = 'ONCO' COLLATE DATABASE_DEFAULT

        UPDATE CIT SET FACTURADA = 1, N_FACTURA = @N_FACTURA
        FROM CIT
        INNER JOIN FTRDC A ON CIT.CONSECUTIVO COLLATE DATABASE_DEFAULT = A.NOPRESTACION COLLATE DATABASE_DEFAULT
        WHERE A.CNSFTR = @CNSFTR COLLATE DATABASE_DEFAULT
        AND A.N_CUOTA = @N_CUOTA
        AND A.PROCEDENCIA = 'ONCO' COLLATE DATABASE_DEFAULT
    END

    IF @PROCEDENCIA = 'TODA' OR @PROCEDENCIA = 'APLIM'
    BEGIN
        PRINT 'Asignando No. de Factura a Aplicacion de Medicamentos...'
        UPDATE CIT SET FACTURADA = 1, N_FACTURA = @N_FACTURA
        FROM CIT
        INNER JOIN FTRDC A ON CIT.CONSECUTIVO COLLATE DATABASE_DEFAULT = A.NOPRESTACION COLLATE DATABASE_DEFAULT
        WHERE A.CNSFTR = @CNSFTR COLLATE DATABASE_DEFAULT
        AND A.N_CUOTA = @N_CUOTA
        AND A.PROCEDENCIA = 'APLIM' COLLATE DATABASE_DEFAULT
    END

    IF @PROCEDENCIA = 'TODA' OR @PROCEDENCIA = 'INV'
    BEGIN
        PRINT 'Asignando No. de Factura a los Movimientos de Inventario...'
        UPDATE IMOV
        SET FACTURADA = 1,
            N_FACTURA = @N_FACTURA,
            NODOCUMENTO = @N_FACTURA,
            MARCACONT = 0,
            CNSITFC = @CNSFTR
        FROM IMOV
        INNER JOIN (
            SELECT DISTINCT COALESCE(A.NOPRESTACION, A.NOADMISION) AS CNSMOV
            FROM FTRDC A
            WHERE A.CNSFTR = @CNSFTR COLLATE DATABASE_DEFAULT
              AND A.N_CUOTA = @N_CUOTA
              AND A.PROCEDENCIA = 'INV' COLLATE DATABASE_DEFAULT
        ) X ON IMOV.CNSMOV COLLATE DATABASE_DEFAULT = X.CNSMOV COLLATE DATABASE_DEFAULT
        WHERE COALESCE(IMOV.FACTURADA, 0) = 0
    END

    /* Copago propio: moderadora en cero en relacion y cabecera (RIPS / DIAN) */
    IF @COPAGOPROP = 1
    BEGIN
        UPDATE FTRDC
        SET VLR_COPAGO = 0
        WHERE CNSFTR = @CNSFTR COLLATE DATABASE_DEFAULT
          AND N_CUOTA = @N_CUOTA
          AND PROCEDENCIA COLLATE DATABASE_DEFAULT <> 'HADM'
          AND (
                COALESCE(TCOPAGO COLLATE DATABASE_DEFAULT, '') = '02'
                OR EXISTS (
                    SELECT 1
                    FROM MOCCD
                    WHERE TIPODEPAGO = 'Moderadora' COLLATE DATABASE_DEFAULT
                      AND MOCCD.VALOR = FTRDC.VLR_COPAGO
                )
              );
    END

    EXEC DBO.SPK_TOTALFACTURFIN @N_FACTURA = @N_FACTURA;
END

