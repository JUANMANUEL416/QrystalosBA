CREATE OR ALTER PROCEDURE DBO.SPK_GENERA_CUOTAS @IDTRANSACCION VARCHAR(6), @NUMDOCUMENTO VARCHAR(20), @NUMCUOTAS DECIMAL(14, 2), @CUOTAACT DECIMAL(14, 2), @VLRPRESTAMO 
	DECIMAL(14, 2), @FECHAPAGO DATETIME
	WITH ENCRYPTION
AS
DECLARE @VLRCUOTA DECIMAL(14, 2)
DECLARE @VLRCUOTA_BASE DECIMAL(14, 2)
DECLARE @VLRCUOTA_INS DECIMAL(14, 2)
DECLARE @SLDINICIAL DECIMAL(14, 2)
DECLARE @INTERESES DECIMAL(14, 2)
DECLARE @MANINTERESES SMALLINT
DECLARE @SLDFINAL DECIMAL(14, 2)
DECLARE @TASAINTERES DECIMAL(8, 4)
DECLARE @TIPOINTERES VARCHAR(20)
DECLARE @PERIODO VARCHAR(20)
DECLARE @PRESTAMO DECIMAL(14, 2)
DECLARE @FECHAINI DATETIME
DECLARE @FECHA_ULT DATETIME
DECLARE @CUOTA_ULT INT
DECLARE @NUEVAS INT
DECLARE @CAPITAL_PAGADO DECIMAL(14, 2)
DECLARE @SALDO DECIMAL(14, 2)
DECLARE @SALDO_CADENA DECIMAL(14, 2)
DECLARE @VLRINTERESES_PRS DECIMAL(14, 2)
DECLARE @NUMCUOTA INT

-- Regenera SOLO cuotas pendientes. Nunca actualiza ni borra Pagada, Anulada
-- ni filas con CNSPAGO (ya aplicadas o en un periodo de nomina).
-- El valor de cada cuota nueva se calcula con el SALDO PENDIENTE / cuotas nuevas,
-- nunca con el prestamo original. La ultima cuota absorbe el redondeo y no puede
-- quedar negativa.
BEGIN
	SET @FECHAINI = @FECHAPAGO
	SET @IDTRANSACCION = COALESCE(@IDTRANSACCION, 'PRS')

	SELECT @VLRCUOTA = COALESCE(VLRCUOTA, 0), @TASAINTERES = COALESCE(TASAINTERES, 0), @TIPOINTERES = TIPOINTERES, @PERIODO = PERIODO, @MANINTERESES = COALESCE(
			MANINTERESES, 0), @PRESTAMO = COALESCE(VLRPRESTAMO, 0), @VLRINTERESES_PRS = COALESCE(VLRINTERESES, 0), @FECHAINI = COALESCE(@FECHAINI, FECHAINI)
	FROM PRS
	WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO

	IF @@ROWCOUNT = 0
	BEGIN
		RAISERROR ('No existe la libranza para generar cuotas', 16, 1)

		RETURN
	END

	SET @PRESTAMO = COALESCE(NULLIF(@PRESTAMO, 0), @VLRPRESTAMO, 0)
	SET @NUMCUOTAS = COALESCE(@NUMCUOTAS, 0)
	SET @MANINTERESES = COALESCE(@MANINTERESES, 0)

	SELECT @CAPITAL_PAGADO = COALESCE(SUM(VLRCUOTA - ISNULL(VLRINTERESES, 0)), 0)
	FROM PRSD
	WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO AND (ESTADO = 'Pagada' OR (CNSPAGO IS NOT NULL AND LTRIM(RTRIM(CNSPAGO)) <> '')
			)

	SET @SALDO = @PRESTAMO - @CAPITAL_PAGADO

	IF @SALDO < 0
	BEGIN
		RAISERROR ('El capital de la libranza no puede ser menor a las cuotas ya descontadas', 16, 1)

		RETURN
	END

	-- Si ya hay cuotas descontadas, el SALDOACT de la ultima congelada es el capital
	-- que realmente falta. Evita repartir el prestamo original cuando el acumulado
	-- de capital pagado no coincide (cuotas en 0, redondeos, etc.).
	SELECT TOP 1 @SALDO_CADENA = SALDOACT
	FROM PRSD
	WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO AND (ESTADO = 'Pagada' OR (CNSPAGO IS NOT NULL AND LTRIM(RTRIM(CNSPAGO)) <> '')
			)
	ORDER BY NUMCUOTA DESC

	IF @SALDO_CADENA IS NOT NULL AND @SALDO_CADENA > 0 AND @SALDO_CADENA <= @SALDO
		SET @SALDO = @SALDO_CADENA

	-- Compatibilidad: el 5o parametro historico es el monto a repartir (saldo), no el prestamo.
	IF @SALDO > 0 AND @CAPITAL_PAGADO = 0 AND ISNULL(@VLRPRESTAMO, 0) > 0 AND ISNULL(@VLRPRESTAMO, 0) < @SALDO
		SET @SALDO = @VLRPRESTAMO

	-- Borra pendientes sin vinculo a nomina. Conserva Pagada, Anulada y CNSPAGO.
	IF @NUMCUOTAS > 0
	BEGIN
		DELETE
		FROM PRSD
		WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO AND ESTADO NOT IN ('Pagada', 'Anulada') AND (CNSPAGO IS NULL OR LTRIM(RTRIM(CNSPAGO)) = ''
				)
	END

	SELECT @CUOTA_ULT = COALESCE(MAX(NUMCUOTA), 0)
	FROM PRSD
	WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO

	SELECT TOP 1 @FECHA_ULT = FECHAPAGO
	FROM PRSD
	WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO AND (ESTADO = 'Pagada' OR (CNSPAGO IS NOT NULL AND LTRIM(RTRIM(CNSPAGO)) <> '')
			)
	ORDER BY NUMCUOTA DESC

	SET @NUEVAS = CAST(@NUMCUOTAS AS INT) - @CUOTA_ULT

	IF @SALDO = 0 OR @NUEVAS <= 0
	BEGIN
		UPDATE PRS
		SET VLRSALDO = CASE 
				WHEN @SALDO < 0
					THEN 0
				ELSE @SALDO
				END
		WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO

		IF @SALDO > 0 AND @NUEVAS <= 0
		BEGIN
			RAISERROR ('El numero de cuotas debe ser mayor a las ya pagadas o aplicadas en nomina', 16, 1)
		END

		RETURN
	END

	-- Fecha de la primera cuota nueva: ultima aplicada + 1 periodo, o FECHAINI.
	IF @CUOTA_ULT > 0 AND @FECHA_ULT IS NOT NULL
	BEGIN
		SET @FECHAPAGO = @FECHA_ULT

		IF @PERIODO = 'Anual'
			SET @FECHAPAGO = DATEADD(YEAR, 1, @FECHAPAGO)
		ELSE IF @PERIODO = 'Mensual'
			SET @FECHAPAGO = DATEADD(MONTH, 1, @FECHAPAGO)
		ELSE IF @PERIODO = 'Quincenal'
		BEGIN
			IF DATEPART(DAY, @FECHAPAGO) <= 15
				SET @FECHAPAGO = DATEFROMPARTS(YEAR(@FECHAPAGO), MONTH(@FECHAPAGO), 16)
			ELSE
				SET @FECHAPAGO = DATEADD(MONTH, 1, DATEFROMPARTS(YEAR(@FECHAPAGO), MONTH(@FECHAPAGO), 1))
		END
	END
	ELSE
		SET @FECHAPAGO = COALESCE(@FECHAINI, GETDATE())

	-- Cuota fija = saldo pendiente / cuotas que faltan. Nunca se reutiliza PRS.VLRCUOTA
	-- (ese valor es del plan original y, con pagos, produce cuotas negativas al ajustar la ultima).
	SET @VLRCUOTA_BASE = CAST(ROUND(@SALDO / @NUEVAS, 0) AS DECIMAL(14, 2))

	IF @NUEVAS > 1 AND (@VLRCUOTA_BASE * (@NUEVAS - 1)) > @SALDO
		SET @VLRCUOTA_BASE = CAST(@SALDO / @NUEVAS AS DECIMAL(14, 2))

	IF @VLRCUOTA_BASE < 0
		SET @VLRCUOTA_BASE = 0
	SET @VLRCUOTA = @VLRCUOTA_BASE
	SET @SLDINICIAL = @SALDO
	SET @NUMCUOTA = @CUOTA_ULT + 1

	-- Interes continuo sobre el saldo restante
	IF @TIPOINTERES = 'Continuo' AND @MANINTERESES = 1
	BEGIN
		SET @INTERESES = CAST((@TASAINTERES / 100.0) * @SLDINICIAL AS DECIMAL(14, 2))

		WHILE @NUMCUOTA <= @NUMCUOTAS
		BEGIN
			IF @NUMCUOTA = CAST(@NUMCUOTAS AS INT)
				SET @VLRCUOTA_INS = @SLDINICIAL + @INTERESES
			ELSE
				SET @VLRCUOTA_INS = @VLRCUOTA_BASE

			IF @VLRCUOTA_INS < 0
				SET @VLRCUOTA_INS = 0

			IF @VLRCUOTA_INS > @SLDINICIAL + @INTERESES
				SET @VLRCUOTA_INS = @SLDINICIAL + @INTERESES
			SET @SLDFINAL = @SLDINICIAL + @INTERESES - @VLRCUOTA_INS

			IF @SLDFINAL < 0
				SET @SLDFINAL = 0

			INSERT INTO PRSD (NUMDOCUMENTO, IDTRANSACCION, NUMCUOTA, SALDOANT, VLRCUOTA, VLRINTERESES, SALDOACT, ESTADO, FECHAPAGO)
			SELECT @NUMDOCUMENTO, @IDTRANSACCION, @NUMCUOTA, @SLDINICIAL, @VLRCUOTA_INS, @INTERESES, @SLDFINAL, 'PorPagar', @FECHAPAGO

			SET @SLDINICIAL = @SLDFINAL
			SET @INTERESES = CAST((@TASAINTERES / 100.0) * @SLDINICIAL AS DECIMAL(14, 2))
			SET @NUMCUOTA = @NUMCUOTA + 1

			IF @PERIODO = 'Anual'
				SET @FECHAPAGO = DATEADD(YEAR, 1, @FECHAPAGO)
			ELSE IF @PERIODO = 'Mensual'
				SET @FECHAPAGO = DATEADD(MONTH, 1, @FECHAPAGO)
			ELSE IF @PERIODO = 'Quincenal'
			BEGIN
				IF DATEPART(DAY, @FECHAPAGO) <= 15
					SET @FECHAPAGO = DATEFROMPARTS(YEAR(@FECHAPAGO), MONTH(@FECHAPAGO), 16)
				ELSE
					SET @FECHAPAGO = DATEADD(MONTH, 1, DATEFROMPARTS(YEAR(@FECHAPAGO), MONTH(@FECHAPAGO), 1))
			END
		END
	END
			-- Interes simple: se reparte el total de intereses en las cuotas nuevas
	ELSE IF @TIPOINTERES = 'Simple' AND @MANINTERESES = 1
	BEGIN
		SET @INTERESES = CAST(@VLRINTERESES_PRS / @NUEVAS AS DECIMAL(14, 2))

		WHILE @NUMCUOTA <= @NUMCUOTAS
		BEGIN
			IF @NUMCUOTA = CAST(@NUMCUOTAS AS INT)
				SET @VLRCUOTA_INS = @SLDINICIAL + @INTERESES
			ELSE
				SET @VLRCUOTA_INS = @VLRCUOTA_BASE

			IF @VLRCUOTA_INS < 0
				SET @VLRCUOTA_INS = 0

			IF @VLRCUOTA_INS > @SLDINICIAL + @INTERESES
				SET @VLRCUOTA_INS = @SLDINICIAL + @INTERESES
			SET @SLDFINAL = @SLDINICIAL + @INTERESES - @VLRCUOTA_INS

			IF @SLDFINAL < 0
				SET @SLDFINAL = 0

			INSERT INTO PRSD (NUMDOCUMENTO, IDTRANSACCION, NUMCUOTA, SALDOANT, VLRCUOTA, VLRINTERESES, SALDOACT, ESTADO, FECHAPAGO)
			SELECT @NUMDOCUMENTO, @IDTRANSACCION, @NUMCUOTA, @SLDINICIAL, @VLRCUOTA_INS, @INTERESES, @SLDFINAL, 'PorPagar', @FECHAPAGO

			SET @SLDINICIAL = @SLDFINAL
			SET @NUMCUOTA = @NUMCUOTA + 1

			IF @PERIODO = 'Anual'
				SET @FECHAPAGO = DATEADD(YEAR, 1, @FECHAPAGO)
			ELSE IF @PERIODO = 'Mensual'
				SET @FECHAPAGO = DATEADD(MONTH, 1, @FECHAPAGO)
			ELSE IF @PERIODO = 'Quincenal'
			BEGIN
				IF DATEPART(DAY, @FECHAPAGO) <= 15
					SET @FECHAPAGO = DATEFROMPARTS(YEAR(@FECHAPAGO), MONTH(@FECHAPAGO), 16)
				ELSE
					SET @FECHAPAGO = DATEADD(MONTH, 1, DATEFROMPARTS(YEAR(@FECHAPAGO), MONTH(@FECHAPAGO), 1))
			END
		END
	END
			-- Sin intereses: reparte el saldo restante. La ultima cuota absorbe el redondeo.
	ELSE
	BEGIN
		WHILE @NUMCUOTA <= @NUMCUOTAS
		BEGIN
			IF @NUMCUOTA = CAST(@NUMCUOTAS AS INT) OR @SLDINICIAL < @VLRCUOTA_BASE
				SET @VLRCUOTA_INS = @SLDINICIAL
			ELSE
				SET @VLRCUOTA_INS = @VLRCUOTA_BASE

			IF @VLRCUOTA_INS < 0
				SET @VLRCUOTA_INS = 0
			SET @SLDFINAL = @SLDINICIAL - @VLRCUOTA_INS

			IF @SLDFINAL < 0
				SET @SLDFINAL = 0

			INSERT INTO PRSD (NUMDOCUMENTO, IDTRANSACCION, NUMCUOTA, SALDOANT, VLRCUOTA, VLRINTERESES, SALDOACT, ESTADO, FECHAPAGO)
			SELECT @NUMDOCUMENTO, @IDTRANSACCION, @NUMCUOTA, @SLDINICIAL, @VLRCUOTA_INS, 0, @SLDFINAL, 'PorPagar', @FECHAPAGO

			SET @SLDINICIAL = @SLDFINAL
			SET @NUMCUOTA = @NUMCUOTA + 1

			IF @PERIODO = 'Anual'
				SET @FECHAPAGO = DATEADD(YEAR, 1, @FECHAPAGO)
			ELSE IF @PERIODO = 'Mensual'
				SET @FECHAPAGO = DATEADD(MONTH, 1, @FECHAPAGO)
			ELSE IF @PERIODO = 'Quincenal'
			BEGIN
				IF DATEPART(DAY, @FECHAPAGO) <= 15
					SET @FECHAPAGO = DATEFROMPARTS(YEAR(@FECHAPAGO), MONTH(@FECHAPAGO), 16)
				ELSE
					SET @FECHAPAGO = DATEADD(MONTH, 1, DATEFROMPARTS(YEAR(@FECHAPAGO), MONTH(@FECHAPAGO), 1))
			END
		END
	END

	-- La ultima cuota pendiente cierra el saldo. Nunca VLRCUOTA + SALDOACT negativo.
	UPDATE PRSD
	SET VLRCUOTA = CASE 
			WHEN ISNULL(SALDOANT, 0) + ISNULL(VLRINTERESES, 0) < 0
				THEN 0
			ELSE ISNULL(SALDOANT, 0) + ISNULL(VLRINTERESES, 0)
			END, SALDOACT = 0
	WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO AND NUMCUOTA = CAST(@NUMCUOTAS AS INT) AND ESTADO = 'PorPagar' AND (CNSPAGO IS NULL OR LTRIM(RTRIM(CNSPAGO)) = ''
			)

	UPDATE PRS
	SET VLRSALDO = @SALDO, VLRCUOTA = @VLRCUOTA_BASE
	WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO
END
