IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='SPK_CAMBIAR_TERFXP' AND XTYPE='P')
BEGIN
 DROP PROCEDURE SPK_CAMBIAR_TERFXP
END

GO
CREATE PROCEDURE DBO.SPK_CAMBIAR_TERFXP
     @N_PRESUP          VARCHAR(16),
     @ITEM		INT,
     @NOPRESTACION      VARCHAR(16),
     @NOITEM            SMALLINT,
     @IDTERCERO         VARCHAR(20),
     @COMPANIA          VARCHAR(2),
     @SEDE              VARCHAR(5),
     @USUARIO           VARCHAR(12)
WITH ENCRYPTION
AS
DECLARE @NOADMISION       VARCHAR(20)
DECLARE @N_PRESUP_NEW     VARCHAR(16)
DECLARE @ITEM_NEW         INT
DECLARE @NROCOMPROBANTE   VARCHAR(20)
DECLARE @N_FACTURA        VARCHAR(16)
DECLARE @CONTABILIZADA    INT
DECLARE @SYS_COMPUTERNAME VARCHAR(128)
BEGIN
 SET @SYS_COMPUTERNAME = host_name()
 PRINT 'Cambio del tercero de un Servicio en FXP'
 SELECT @NOADMISION = NOREFERENCIA FROM FXP WHERE N_PRESUP = @N_PRESUP
 SELECT @N_PRESUP_NEW = N_PRESUP FROM FXP WHERE NOREFERENCIA=@NOADMISION AND IDTERCERO=@IDTERCERO
 IF @N_PRESUP_NEW<>'' OR NOT @N_PRESUP_NEW IS NULL
 BEGIN 
  PRINT 'Admision con tercero en una Prestaci�n.'
  PRINT 'Consecutivo de FXP: '+@N_PRESUP_NEW
  SELECT @ITEM_NEW=MAX(ITEM) FROM FXPD WHERE N_PRESUP=@N_PRESUP_NEW
  IF @ITEM_NEW IS NULL
   SET @ITEM_NEW = 1
  ELSE
   SET @ITEM_NEW = @ITEM_NEW + 1 
  UPDATE FXPD SET IDTERCERO=@IDTERCERO, N_PRESUP=@N_PRESUP_NEW, ITEM = @ITEM_NEW
  WHERE N_PRESUP=@N_PRESUP AND ITEM=@ITEM
 END
 ELSE
 BEGIN
  PRINT 'No Tiene FXP la Admision para ese tercero.'
  SET @N_PRESUP_NEW = SPACE(16)
  EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@FCXP',@N_PRESUP_NEW OUTPUT  
  PRINT 'Nuevo Consecutivo de FXP: '+@N_PRESUP_NEW
  SELECT * INTO #FXP  FROM  FXP WHERE N_PRESUP=@N_PRESUP
  UPDATE #FXP SET IDTERCERO = @IDTERCERO, N_PRESUP = @N_PRESUP_NEW
  INSERT INTO FXP
  SELECT * FROM #FXP 
  UPDATE FXPD SET IDTERCERO=@IDTERCERO, N_PRESUP=@N_PRESUP_NEW, ITEM = 1
  WHERE N_PRESUP=@N_PRESUP AND ITEM=@ITEM
 END
 IF (SELECT COUNT(*) FROM FXPD WHERE N_PRESUP=@N_PRESUP)=0
  DELETE FXP WHERE N_PRESUP=@N_PRESUP
 PRINT 'Modificando HPRED' 
 UPDATE HPRED SET IDPROVEEDOR=@IDTERCERO 
 WHERE NOPRESTACION=@NOPRESTACION AND NOITEM=@NOITEM
 PRINT 'Modificando FTRD' 
 UPDATE FTRD SET IDPROVEEDOR=@IDTERCERO 
 WHERE NOADMISION = @NOADMISION AND NOPRESTACION=@NOPRESTACION AND NOITEM=@NOITEM

 SELECT @N_FACTURA=FTR.N_FACTURA, @NROCOMPROBANTE = FTR.NROCOMPROBANTE,  @CONTABILIZADA = FTR.CONTABILIZADA
 FROM FTR INNER JOIN 
      FTRD ON FTR.N_FACTURA=FTRD.N_FACTURA 
 WHERE FTRD.NOADMISION = @NOADMISION AND FTRD.NOPRESTACION=@NOPRESTACION AND FTRD.NOITEM=@NOITEM
 IF @CONTABILIZADA = 1
 BEGIN
  PRINT 'Reconstrullendo Comprobante Contable: '+@NROCOMPROBANTE
  EXEC SPK_CONTAB_FTR @N_FACTURA, @COMPANIA, @USUARIO,@SYS_COMPUTERNAME, @SEDE, @NROCOMPROBANTE
 END
END
