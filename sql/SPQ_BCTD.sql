CREATE OR ALTER PROCEDURE DBO.SPQ_BCTD
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE
         @PARAMETROS NVARCHAR(MAX)
	   , @MODELO     NVARCHAR(MAX)
	   , @METODO     VARCHAR(100)
	   , @MODELOACT	 NVARCHAR(MAX)
	   , @USUARIO    VARCHAR(20)
	   , @ID	     INT
	   , @BANCO		 VARCHAR(5)
	   , @DATO		 VARCHAR(10)
	   , @CTA_BCO    VARCHAR(20)
	   , @CODACH     VARCHAR(20)
	   , @IDTERCERO  VARCHAR(20)
	   , @DESCRIPCION VARCHAR(30)
	   , @SUCURSAL	 VARCHAR(2)
	   , @DIRECCION  VARCHAR(100)
	   , @TELEFONO1  VARCHAR(20)
	   , @TELEFONO2  VARCHAR(20)
	   , @CONTACTO   VARCHAR(60)
	   , @CARGO		 VARCHAR(40)
	   , @FORMAPAGO  VARCHAR(10)
	   , @GENEROD    SMALLINT
	   , @CANTDOC    INT
	   , @GENAUT     SMALLINT
	   , @NOINICIAL  VARCHAR(20)
	   , @NOFINAL    VARCHAR(20)
	   , @MCNSALFA   BIT
	   , @ITEM	     SMALLINT
	   , @CNSDOC     VARCHAR(20)
	   , @NODOCUMENTO VARCHAR(10)
	   , @VALOR      DECIMAL(18,2)
	   , @IDTERCERO_IDTERCERO VARCHAR(10)
	   , @IDTERCERO_RAZONSOCIAL NVARCHAR(255)
	   , @CNSFCXPP    VARCHAR(10)
	   , @CODCAJA     VARCHAR(10)
	   , @CNSFACJ     VARCHAR(10)
	   , @N_RECIBO    VARCHAR(10)
	   , @UTILIZADO   INT
	   , @ESTADO      VARCHAR(1)
	   , @POSFECHADO  INT
	   , @POSFECHA    DATETIME
	   , @FECHA       VARCHAR(10)
	   , @CNSALFA     VARCHAR(10)
	   , @SYS_COMPUTERNAME VARCHAR(100)
	   , @COMPANIA    VARCHAR(5)
	   , @IDSEDE      VARCHAR(5)
	   , @AHORA       DATETIME = CONVERT(SMALLDATETIME, GETDATE())

DECLARE @TBLERRORES TABLE(CONTINUA VARCHAR(2), ERROR VARCHAR(500));

BEGIN
SET LANGUAGE Spanish;
   SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
   FROM OPENJSON (@json)
	WITH (
	   MODELO         VARCHAR(100)      '$.MODELO', 
	   METODO         VARCHAR(100)      '$.METODO',
	   USUARIO        VARCHAR(20)       '$.USUARIO',
	   PARAMETROS     NVARCHAR(MAX)  AS JSON
	)

	IF @METODO = 'GETFORMATOS'
	BEGIN

		SELECT @DATO = dbo.FNK_VALORVARIABLE('IDCJFPACHEQUE')
		SELECT FORMAPAGO AS value,DESCRIPCION as label FROM FPA WHERE FORMAPAGO = @DATO UNION ALL
		SELECT FORMAPAGO AS value,DESCRIPCION as label FROM FPA WHERE FORMAPAGO <> @DATO

		RETURN
	END
	IF @METODO = 'CONSULTARBCTD'
	BEGIN
		SELECT
			@BANCO = JSON_VALUE(@PARAMETROS, '$.BANCO'),
			@SUCURSAL = JSON_VALUE(@PARAMETROS, '$.SUCURSAL'),
			@CTA_BCO = JSON_VALUE(@PARAMETROS, '$.CTA_BCO');
		
		SELECT BCTD.BANCO, BCTD.SUCURSAL, BCTD.CTA_BCO, BCTD.FORMAPAGO, FPA.DESCRIPCION, BCTD.GENEROD, BCTD.CANTDOC, BCTD.GENAUT, BCTD.NOINICIAL, BCTD.NOFINAL, BCTD.MCNSALFA, BCTD.CNSDOC, BCTD.ITEM
		FROM BCTD 
		INNER JOIN FPA ON BCTD.FORMAPAGO = FPA.FORMAPAGO
		WHERE BANCO = @BANCO AND SUCURSAL = @SUCURSAL AND CTA_BCO = @CTA_BCO
		
	END
	IF @METODO = 'GUARDABCTD'
	BEGIN
		SELECT
			@BANCO = JSON_VALUE(@PARAMETROS, '$.BANCO'),
			@SUCURSAL = JSON_VALUE(@PARAMETROS, '$.SUCURSAL'),
			@CTA_BCO = JSON_VALUE(@PARAMETROS, '$.CTA_BCO'),
			@FORMAPAGO = JSON_VALUE(@PARAMETROS, '$.FORMAPAGO'),
			@GENEROD = JSON_VALUE(@PARAMETROS, '$.GENEROD'),
			@CANTDOC = JSON_VALUE(@PARAMETROS, '$.CANTDOC'),
			@GENAUT = JSON_VALUE(@PARAMETROS, '$.GENAUT'),
			@NOINICIAL = JSON_VALUE(@PARAMETROS, '$.NOINICIAL'),
			@NOFINAL = JSON_VALUE(@PARAMETROS, '$.NOFINAL'),
			@MCNSALFA = JSON_VALUE(@PARAMETROS, '$.MCNSALFA'),
			@CNSDOC = JSON_VALUE(@PARAMETROS, '$.CNSDOC');

			SELECT TOP 1 @ITEM = ITEM
			FROM BCTD
			WHERE BANCO = @BANCO AND SUCURSAL = @SUCURSAL AND CTA_BCO = @CTA_BCO
			ORDER BY ITEM DESC;

		SET @ITEM = ISNULL(@ITEM, 0) + 1;
			
		INSERT INTO BCTD (BANCO, SUCURSAL, CTA_BCO, FORMAPAGO, GENEROD, CANTDOC, GENAUT, NOINICIAL, NOFINAL, MCNSALFA, CNSDOC, ITEM)
		VALUES (@BANCO, @SUCURSAL, @CTA_BCO, @FORMAPAGO, @GENEROD, @CANTDOC, @GENAUT, @NOINICIAL, @NOFINAL, @MCNSALFA, @CNSDOC, @ITEM);

	END
	IF @METODO = 'EDITABCTD'
	BEGIN
		SELECT
			@BANCO = JSON_VALUE(@PARAMETROS, '$.BANCO'),
			@SUCURSAL = JSON_VALUE(@PARAMETROS, '$.SUCURSAL'),
			@CTA_BCO = JSON_VALUE(@PARAMETROS, '$.CTA_BCO'),
			@FORMAPAGO = JSON_VALUE(@PARAMETROS, '$.FORMAPAGO'),
			@GENEROD = JSON_VALUE(@PARAMETROS, '$.GENEROD'),
			@CANTDOC = JSON_VALUE(@PARAMETROS, '$.CANTDOC'),
			@GENAUT = JSON_VALUE(@PARAMETROS, '$.GENAUT'),
			@NOINICIAL = JSON_VALUE(@PARAMETROS, '$.NOINICIAL'),
			@NOFINAL = JSON_VALUE(@PARAMETROS, '$.NOFINAL'),
			@MCNSALFA = JSON_VALUE(@PARAMETROS, '$.MCNSALFA'),
			@CNSDOC = JSON_VALUE(@PARAMETROS, '$.CNSDOC'),
			@ITEM = JSON_VALUE(@PARAMETROS, '$.ITEM'); -- Se agrega el par�metro ITEM

		-- Actualizar la fila correspondiente
		UPDATE BCTD
		SET
			FORMAPAGO = @FORMAPAGO,
			GENEROD = @GENEROD,
			CANTDOC = @CANTDOC,
			GENAUT = @GENAUT,
			NOINICIAL = @NOINICIAL,
			NOFINAL = @NOFINAL,
			MCNSALFA = @MCNSALFA,
			CNSDOC = @CNSDOC
		WHERE
			BANCO = @BANCO AND
			SUCURSAL = @SUCURSAL AND
			CTA_BCO = @CTA_BCO AND
			ITEM = @ITEM; -- Se incluye el campo ITEM en la cl�usula WHERE
	END
	IF @METODO = 'GENDOCUMENTOS'
	BEGIN
		SELECT
			@BANCO = JSON_VALUE(@PARAMETROS, '$.BANCO'),
			@SUCURSAL = JSON_VALUE(@PARAMETROS, '$.SUCURSAL'),
			@CTA_BCO = JSON_VALUE(@PARAMETROS, '$.CTA_BCO'),
			@ITEM = JSON_VALUE(@PARAMETROS, '$.ITEM');

		SELECT @NOINICIAL = NOINICIAL, @NOFINAL = NOFINAL, @CNSDOC= CNSDOC 
		FROM BCTD 
		WHERE BANCO = @BANCO AND SUCURSAL = @SUCURSAL AND CTA_BCO = @CTA_BCO AND ITEM = @ITEM

		-- Bucle para generar documentos

		WHILE @NOINICIAL <= CAST(@NOFINAL AS INT)
		BEGIN
		PRINT @NOINICIAL
			-- Insertar un nuevo registro en la tabla BCTDD
			INSERT INTO BCTDD (BANCO, SUCURSAL, CTA_BCO, CNSDOC, NODOCUMENTO, UTILIZADO, ESTADO, USUARIO, FECHA, VALOR)
			SELECT BANCO, SUCURSAL, CTA_BCO, CNSDOC
				, CAST(@NOINICIAL AS VARCHAR(10))
				--, RIGHT(REPLICATE('0', 10) + CAST(@NOINICIAL AS VARCHAR(10)), 10)
				, NULL, 'N', @usuario, GETDATE(), 0
			FROM BCTD WHERE BANCO = @BANCO AND SUCURSAL = @SUCURSAL AND CTA_BCO = @CTA_BCO AND CNSDOC = @CNSDOC; 

			-- Incrementar el valor de nodoc
			SET @NOINICIAL = @NOINICIAL + 1;
		END;

		-- Actualizar BCTD si nodoc alcanza el valor final
		UPDATE BCTD SET GENEROD = 1 WHERE BANCO = @BANCO AND SUCURSAL = @SUCURSAL AND CTA_BCO = @CTA_BCO AND CNSDOC = @CNSDOC; -- Aqu� deber�as especificar la condici�n WHERE adecuada
		RETURN
	END
	IF @METODO = 'CONSULTABCTDD'
	BEGIN
		SELECT
			@BANCO = JSON_VALUE(@PARAMETROS, '$.BANCO'),
			@SUCURSAL = JSON_VALUE(@PARAMETROS, '$.SUCURSAL'),
			@CTA_BCO = JSON_VALUE(@PARAMETROS, '$.CTA_BCO'),
			@ITEM = JSON_VALUE(@PARAMETROS, '$.ITEM');

			SELECT @CNSDOC= CNSDOC FROM BCTD WHERE BANCO = @BANCO AND SUCURSAL = @SUCURSAL AND CTA_BCO = @CTA_BCO AND ITEM = @ITEM


			SELECT BCTDD.ESTADO
			, BCTDD.NODOCUMENTO 
			--, RIGHT(REPLICATE('0', 10) + CAST(BCTDD.NODOCUMENTO AS VARCHAR(10)), 10) AS NODOCUMENTO
			, BCTDD.CNSALFA
			, BCTDD.IDTERCERO
			, BCTDD.CNSFCXPP, BCTDD.VALOR
			, BCTDD.CODCAJA, BCTDD.CNSFACJ
			, BCTDD.UTILIZADO
			FROM BCTDD
			WHERE BANCO = @BANCO AND SUCURSAL = @SUCURSAL AND CTA_BCO = @CTA_BCO AND CNSDOC = @CNSDOC

	END
	IF @METODO = 'EDITABCTDD'
	BEGIN
		DECLARE @VARLO21 DECIMAL(14,2)
		SELECT
			@BANCO = JSON_VALUE(@PARAMETROS, '$.BANCO'),
		    @SUCURSAL = JSON_VALUE(@PARAMETROS, '$.SUCURSAL'),
			@CTA_BCO = JSON_VALUE(@PARAMETROS, '$.CTA_BCO'),

			@CNSDOC = JSON_VALUE(@PARAMETROS, '$.CNSDOC'),
			@NODOCUMENTO = JSON_VALUE(@PARAMETROS, '$.NODOCUMENTO'),
			@VALOR = JSON_VALUE(@PARAMETROS, '$.VALOR'),
			@IDTERCERO = JSON_VALUE(@PARAMETROS, '$.IDTERCERO'),

			@CNSFCXPP = JSON_VALUE(@PARAMETROS, '$.CNSFCXPP'),
			@CODCAJA = JSON_VALUE(@PARAMETROS, '$.CODCAJA'),
			@CNSFACJ = JSON_VALUE(@PARAMETROS, '$.CNSFACJ'),
			@N_RECIBO = JSON_VALUE(@PARAMETROS, '$.N_RECIBO'),
			@UTILIZADO = JSON_VALUE(@PARAMETROS, '$.UTILIZADO'),
			@ESTADO = JSON_VALUE(@PARAMETROS, '$.ESTADO'),
			@POSFECHADO = JSON_VALUE(@PARAMETROS, '$.POSFECHADO'),
			@POSFECHA = JSON_VALUE(@PARAMETROS, '$.POSFECHA'),
			@CNSALFA = JSON_VALUE(@PARAMETROS, '$.CNSALFA'),
			@FECHA = JSON_VALUE(@PARAMETROS, '$.FECHA');

		--	SELECT @VALOR VALOR


		select * FROM BCTDD WHERE BANCO = '01' AND SUCURSAL = '01' AND CTA_BCO = '16162308673' AND CNSDOC = '000123' AND NODOCUMENTO = '1'

			IF EXISTS( SELECT 1 FROM BCTDD WHERE BANCO = @BANCO AND SUCURSAL = @SUCURSAL AND CTA_BCO = @CTA_BCO AND CNSDOC = @CNSDOC AND NODOCUMENTO = @NODOCUMENTO )
			BEGIN
				UPDATE BCTDD
				SET
					VALOR = @VALOR,
					IDTERCERO = @IDTERCERO,
					CNSFCXPP = @CNSFCXPP,
					CODCAJA = @CODCAJA,
					CNSFACJ = @CNSFACJ,
					N_RECIBO = @N_RECIBO,
					UTILIZADO = @UTILIZADO,
					ESTADO = @ESTADO,
					POSFECHADO = @POSFECHADO,
					POSFECHA = @POSFECHA,
					CNSALFA = @CNSALFA,
					FECHA = @FECHA
				WHERE
					BANCO = @BANCO AND
					SUCURSAL = @SUCURSAL AND
					CTA_BCO = @CTA_BCO AND
					CNSDOC = @CNSDOC AND
					NODOCUMENTO = @NODOCUMENTO;

				--SELECT FECHA,* FROM BCTDD WHERE BANCO = @BANCO AND SUCURSAL = @SUCURSAL AND CTA_BCO = @CTA_BCO AND CNSDOC = @CNSDOC AND NODOCUMENTO = @NODOCUMENTO 
				SELECT 'OK'OK
			END
			ELSE
			BEGIN
				SELECT 'KO'OK
			END
			RETURN
	END
	IF @METODO = 'GUARDABCTDD'
	BEGIN
		 SELECT @BANCO = JSON_VALUE(@PARAMETROS, '$.BANCO'),
				@SUCURSAL = JSON_VALUE(@PARAMETROS, '$.SUCURSAL'),
				@CTA_BCO = JSON_VALUE(@PARAMETROS, '$.CTA_BCO'),
				@CNSDOC = JSON_VALUE(@PARAMETROS, '$.CNSDOC'),
				@NODOCUMENTO = JSON_VALUE(@PARAMETROS, '$.NODOCUMENTO'),
				@VALOR = JSON_VALUE(@PARAMETROS, '$.VALOR'),
				@IDTERCERO = JSON_VALUE(@PARAMETROS, '$.IDTERCERO'),
				@CNSFCXPP = JSON_VALUE(@PARAMETROS, '$.CNSFCXPP'),
				@CODCAJA = JSON_VALUE(@PARAMETROS, '$.CODCAJA'),
				@CNSFACJ = JSON_VALUE(@PARAMETROS, '$.CNSFACJ'),
				@N_RECIBO = JSON_VALUE(@PARAMETROS, '$.N_RECIBO'),
				@UTILIZADO = JSON_VALUE(@PARAMETROS, '$.UTILIZADO'),
				@ESTADO = JSON_VALUE(@PARAMETROS, '$.ESTADO'),
				@POSFECHADO = JSON_VALUE(@PARAMETROS, '$.POSFECHADO'),
				@POSFECHA = JSON_VALUE(@PARAMETROS, '$.POSFECHA'),
				@CNSALFA = JSON_VALUE(@PARAMETROS, '$.CNSALFA');



		IF NOT EXISTS(SELECT 1 FROM BCTDD WHERE BANCO = @BANCO AND SUCURSAL = @SUCURSAL AND CTA_BCO = @CTA_BCO AND CNSDOC = @CNSDOC AND NODOCUMENTO = @NODOCUMENTO)
		BEGIN

			SELECT @BANCO, @SUCURSAL, @CTA_BCO, @CNSDOC, @NODOCUMENTO, @VALOR, @IDTERCERO, @CNSFCXPP, @CODCAJA, @CNSFACJ, @N_RECIBO, @UTILIZADO, @ESTADO, @POSFECHADO, @POSFECHA, @CNSALFA

			INSERT INTO BCTDD (BANCO, SUCURSAL, CTA_BCO, CNSDOC, NODOCUMENTO, VALOR, IDTERCERO, CNSFCXPP, CODCAJA, CNSFACJ, N_RECIBO, UTILIZADO, ESTADO, POSFECHADO, POSFECHA, CNSALFA)
			SELECT @BANCO, @SUCURSAL, @CTA_BCO, @CNSDOC, @NODOCUMENTO, @VALOR, @IDTERCERO, @CNSFCXPP, @CODCAJA, @CNSFACJ, @N_RECIBO, @UTILIZADO, @ESTADO, @POSFECHADO, @POSFECHA, @CNSALFA

		END
		ELSE
		BEGIN
			SELECT 'KO'OK
		END

		RETURN
	END
	IF @METODO = 'LIBERARBCTDD'
	BEGIN
		SELECT @BANCO = JSON_VALUE(@PARAMETROS, '$.BANCO'),
			   @SUCURSAL = JSON_VALUE(@PARAMETROS, '$.SUCURSAL'),
			   @CTA_BCO = JSON_VALUE(@PARAMETROS, '$.CTA_BCO'),
			   @CNSDOC = JSON_VALUE(@PARAMETROS, '$.CNSDOC'),
			   @NODOCUMENTO = JSON_VALUE(@PARAMETROS, '$.NODOCUMENTO');



        UPDATE BCTDD 
		SET 
			IDTERCERO=NULL, 
			CODCAJA=NULL, 
			CNSFACJ=NULL, 
			N_RECIBO=NULL, 
			UTILIZADO=0, 
			ESTADO='N', 
			VALOR=0 
		FROM BCTDD
        WHERE BANCO = @BANCO 
			AND SUCURSAL= @SUCURSAL 
			AND CTA_BCO=@CTA_BCO 
			AND COALESCE(CNSDOC,'') = @CNSDOC 
			AND NODOCUMENTO=@NODOCUMENTO


	END
	IF @METODO = 'ANULARBCTDD'
	BEGIN
		SELECT @BANCO = JSON_VALUE(@PARAMETROS, '$.BANCO'),
			@SUCURSAL = JSON_VALUE(@PARAMETROS, '$.SUCURSAL'),
			@CTA_BCO = JSON_VALUE(@PARAMETROS, '$.CTA_BCO'),
			@CNSDOC = JSON_VALUE(@PARAMETROS, '$.CNSDOC'),
			@NODOCUMENTO = JSON_VALUE(@PARAMETROS, '$.NODOCUMENTO');


        UPDATE BCTDD 
		SET USUARIOANU = @USUARIO,
			FECHAANU= CONVERT(SMALLDATETIME,GETDATE()),
			ANULADODESDE = 'BANCOS',
			ESTADO='A'
		FROM BCTDD
        WHERE BANCO = @BANCO 
			AND SUCURSAL= @SUCURSAL 
			AND CTA_BCO=@CTA_BCO 
			AND COALESCE(CNSDOC,'') = @CNSDOC 
			AND NODOCUMENTO=@NODOCUMENTO

		SELECT 'OK'OK
		RETURN

	END
	IF @METODO = 'ENTREGARBCTDD'
	BEGIN
		SELECT @BANCO = JSON_VALUE(@PARAMETROS, '$.BANCO'),
			   @SUCURSAL = JSON_VALUE(@PARAMETROS, '$.SUCURSAL'),
			   @CTA_BCO = JSON_VALUE(@PARAMETROS, '$.CTA_BCO'),
			   @CNSDOC = JSON_VALUE(@PARAMETROS, '$.CNSDOC'),
			   @NODOCUMENTO = JSON_VALUE(@PARAMETROS, '$.NODOCUMENTO'),
			   @CODCAJA = JSON_VALUE(@PARAMETROS, '$.CODCAJA'),
			   @CNSFACJ = JSON_VALUE(@PARAMETROS, '$.CNSFACJ'),
			   @SYS_COMPUTERNAME = JSON_VALUE(@PARAMETROS, '$.SYS_COMPUTERNAME'),
			   @COMPANIA = JSON_VALUE(@PARAMETROS, '$.COMPANIA'),
			   @IDSEDE = JSON_VALUE(@PARAMETROS, '$.IDSEDE');


		IF  (SELECT ESTADO FROM BCTDD WHERE BANCO = @BANCO AND SUCURSAL= @SUCURSAL AND CTA_BCO=@CTA_BCO AND COALESCE(CNSDOC,'') = @CNSDOC AND NODOCUMENTO = @NODOCUMENTO ) = 'E' 
		     AND (SELECT CERRADA FROM FCJ  WHERE CNSFACJ = @CNSFACJ AND CODCAJA = @CODCAJA) = 1
		BEGIN
			EXEC SPK_NC_CONTAB_CAJA_EGR @CNSFACJ, @CODCAJA, @USUARIO, @SYS_COMPUTERNAME, @COMPANIA, @IDSEDE, ''
			SELECT 'OK'OK
		END
		ELSE
		BEGIN
			SELECT 'KO'OK, 'Recibo no se pudo Cerrar.'ERROR
		END
		RETURN
	END
	IF @METODO = 'ELIMINARBCTDD'
	BEGIN
		SELECT @BANCO = JSON_VALUE(@PARAMETROS, '$.BANCO'),
			   @SUCURSAL = JSON_VALUE(@PARAMETROS, '$.SUCURSAL'),
			   @CTA_BCO = JSON_VALUE(@PARAMETROS, '$.CTA_BCO'),
			   @CNSDOC = JSON_VALUE(@PARAMETROS, '$.CNSDOC'),
			   @NODOCUMENTO = JSON_VALUE(@PARAMETROS, '$.NODOCUMENTO');

		DELETE BCTDD
        WHERE BANCO = @BANCO 
			AND SUCURSAL= @SUCURSAL 
			AND CTA_BCO=@CTA_BCO 
			AND COALESCE(CNSDOC,'') = @CNSDOC 
			AND NODOCUMENTO=@NODOCUMENTO

		SELECT 'OK'OK

		RETURN
	END
	IF @METODO = 'GUARDAR_ESTADO'
	BEGIN
		SELECT @BANCO = BANCO, @SUCURSAL = SUCURSAL, @CTA_BCO = CTA_BCO, @CNSDOC = CNSDOC, @NODOCUMENTO = NODOCUMENTO, @ESTADO = ESTADO
		FROM OPENJSON(@PARAMETROS)
		WITH(	BANCO	VARCHAR(20)		'$.BANCO',SUCURSAL	VARCHAR(20)		'$.SUCURSAL',CTA_BCO	VARCHAR(20)		'$.CTA_BCO'
				,CNSDOC	VARCHAR(20)		'$.CNSDOC',NODOCUMENTO	VARCHAR(20)		'$.NODOCUMENTO',ESTADO	VARCHAR(20)		'$.ESTADO')

		IF 'VALIDACION' <> 'VALIDACION'
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'MENSAJE'
		END
	
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				UPDATE BCTDD SET ESTADO = @ESTADO WHERE
					BANCO = @BANCO AND
					SUCURSAL = @SUCURSAL AND
					CTA_BCO = @CTA_BCO AND
					CNSDOC = @CNSDOC AND
					NODOCUMENTO = @NODOCUMENTO
			END TRY  
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK
		END 
	END
	IF @METODO = 'ACTUALIZARCNSALFA'
	BEGIN
		SELECT
			@BANCO         = JSON_VALUE(@PARAMETROS, '$.BANCO'),
			@SUCURSAL      = JSON_VALUE(@PARAMETROS, '$.SUCURSAL'),
			@CTA_BCO       = JSON_VALUE(@PARAMETROS, '$.CTA_BCO'),
			@CNSDOC        = JSON_VALUE(@PARAMETROS, '$.CNSDOC'),
			@NODOCUMENTO   = JSON_VALUE(@PARAMETROS, '$.NODOCUMENTO'),
			@IDTERCERO     = JSON_VALUE(@PARAMETROS, '$.IDTERCERO'),
			@CNSALFA       = JSON_VALUE(@PARAMETROS, '$.CNSALFA');

		-- No actualizar si el documento est� anulado (ESTADO = 'A')
		IF EXISTS (SELECT 1 FROM BCTDD	WHERE BANCO = @BANCO AND SUCURSAL = @SUCURSAL  AND CTA_BCO = @CTA_BCO AND COALESCE(CNSDOC, '') = COALESCE(@CNSDOC, '') AND NODOCUMENTO = @NODOCUMENTO  AND ESTADO = 'A')
		BEGIN
			SELECT 'KO' AS OK, 'El documento est� anulado. No se puede modificar el c�digo Alfabanco.' AS ERROR;
			RETURN;
		END;

		-- Actualizar solo CNSALFA identificando por BANCO, SUCURSAL, CTA_BCO, CNSDOC, NODOCUMENTO (clave �nica del documento)
		UPDATE BCTDD
		SET CNSALFA = NULLIF(LTRIM(RTRIM(@CNSALFA)), '')
		WHERE BANCO = @BANCO
		  AND SUCURSAL = @SUCURSAL
		  AND CTA_BCO = @CTA_BCO
		  AND COALESCE(CNSDOC, '') = COALESCE(@CNSDOC, '')
		  AND NODOCUMENTO = @NODOCUMENTO;

		IF @@ROWCOUNT = 0
		BEGIN
			SELECT 'KO' AS OK, 'No se encontr� el documento o no se pudo actualizar.' AS ERROR;
			RETURN;
		END;

		SELECT 'OK' AS OK;
		RETURN;
	END

END
