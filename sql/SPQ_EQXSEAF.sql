CREATE OR ALTER PROCEDURE DBO.SPQ_EQXSEAF @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20), @IDSEDE VARCHAR(5), @DATOS VARCHAR(MAX)
DECLARE @PROCESO VARCHAR(20), @CODIGO VARCHAR(20), @DESCRIPCION VARCHAR(1000), @CODIGOEDITE VARCHAR(20), @CAMPO VARCHAR(20), @IDTGEN INT, @VALOR1 DECIMAL(14, 2)

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @PROCESO = PROCESO, @CODIGO = CODIGO, @DESCRIPCION = DESCRIPCION, @VALOR1 = VALOR1, @IDTGEN = IDTGEN, @CAMPO = CAMPO
			FROM OPENJSON(@PARAMETROS) WITH (
					PROCESO VARCHAR(20) '$.PROCESO', CODIGO VARCHAR(20) '$.CODIGO', DESCRIPCION VARCHAR(1000) '$.DESCRIPCION', VALOR1 DECIMAL(14, 2) '$.VALOR1', 
					IDTGEN INT '$.IDTGEN', CAMPO VARCHAR(20) '$.CAMPO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('EL CODIGO ', @CODIGO, ' YA SE ENCUENTRA REGISTRADO EN LA SECTOR')
					WHERE EXISTS (
							SELECT 1
							FROM TGEN
							WHERE TABLA = 'DOTASERVICIO' AND CAMPO = @CAMPO AND CODIGO = @CODIGO
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO TGEN (TABLA, CAMPO, CODIGO, DESCRIPCION, VALOR1)
						SELECT 'DOTASERVICIO', @CAMPO, @CODIGO, @DESCRIPCION, @VALOR1
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('EL CODIGO ', @CODIGO, ' YA SE ENCUENTRA REGISTRADO EN EL SECTOR')
					WHERE EXISTS (
							SELECT 1
							FROM TGEN
							WHERE TABLA = 'DOTASERVICIO' AND CAMPO = @CAMPO AND CODIGO = @CODIGO AND IDTGEN <> @IDTGEN
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						UPDATE TGEN
						SET CODIGO = @CODIGO, DESCRIPCION = @DESCRIPCION, VALOR1 = @VALOR1
						WHERE IDTGEN = @IDTGEN
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @CODIGO = CODIGO, @CAMPO = CAMPO
		FROM OPENJSON(@PARAMETROS) WITH (CODIGO VARCHAR(20) '$.CODIGO', CAMPO VARCHAR(20) '$.CAMPO')

		BEGIN TRY
			DELETE
			FROM TGEN
			WHERE TABLA = 'DOTASERVICIO' AND CAMPO = @CAMPO AND CODIGO = @CODIGO
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
