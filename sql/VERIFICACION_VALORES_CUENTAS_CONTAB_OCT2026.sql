/* 1 — Resumen por CxP */
SELECT
  DOC.GRUPO,
  P.CNSFCXP,
  P.NOREFERENCIA,
  P.ESTADO,
  P.CONTABILIZADA,
  CONVERT(decimal(18, 2), P.VALOR) AS VALOR,
  CONVERT(decimal(18, 2), P.VLR_IVA) AS IVA_CAB,
  CONVERT(decimal(18, 2), P.VLR_NETO) AS NETO_CAB,
  CONVERT(decimal(18, 2), SUM(D.VLR_NETO)) AS NETO_DET,
  CONVERT(decimal(18, 2), SUM(D.VLR_IVA)) AS IVA_DET,
  CONVERT(decimal(18, 2), P.VALOR + P.VLR_IVA - P.VLR_NETO) AS DIF_VALOR_IVA_NETO,
  SUM(CASE WHEN COALESCE(D.VLR_IVA, 0) > 0 AND D.CUENTA_SER IN (N'14150502', N'14200502') THEN 1 ELSE 0 END) AS LIN_EXCL_CON_IVA,
  SUM(CASE WHEN COALESCE(D.VLR_IVA, 0) > 0 AND COALESCE(D.CUENTA_IVA, N'') <> N'24080501' THEN 1 ELSE 0 END) AS LIN_IVA_CTA_MAL,
  SUM(CASE WHEN COALESCE(D.VLR_IVA, 0) <= 0 AND COALESCE(D.CUENTA_IVA, N'') <> N'' THEN 1 ELSE 0 END) AS LIN_SIN_IVA_CON_CTAIVA,
  SUM(CASE WHEN ABS(D.VLR_NETO - (D.CANTIDAD * D.VALOR + COALESCE(D.VLR_IVA, 0) - ISNULL(D.VLR_DESCUENTO, 0))) > 0.02 THEN 1 ELSE 0 END) AS LIN_FORMULA_MAL,
  CASE
    WHEN P.ESTADO = N'A' THEN N'ANULADA'
    WHEN ABS(P.VLR_NETO - SUM(D.VLR_NETO)) > 0.01 THEN N'CAB_DET'
    WHEN ABS(P.VLR_IVA - SUM(D.VLR_IVA)) > 0.01 THEN N'IVA_CAB_DET'
    WHEN ABS(P.VALOR + P.VLR_IVA - P.VLR_NETO) > 0.02 THEN N'VALOR_IVA_NETO'
    WHEN SUM(CASE WHEN COALESCE(D.VLR_IVA, 0) > 0 AND D.CUENTA_SER IN (N'14150502', N'14200502') THEN 1 ELSE 0 END) > 0 THEN N'CUENTAS'
    WHEN SUM(CASE WHEN COALESCE(D.VLR_IVA, 0) > 0 AND COALESCE(D.CUENTA_IVA, N'') <> N'24080501' THEN 1 ELSE 0 END) > 0 THEN N'CUENTAS'
    WHEN SUM(CASE WHEN ABS(D.VLR_NETO - (D.CANTIDAD * D.VALOR + COALESCE(D.VLR_IVA, 0) - ISNULL(D.VLR_DESCUENTO, 0))) > 0.02 THEN 1 ELSE 0 END) > 0 THEN N'LINEAS'
    ELSE N'OK'
  END AS SEMAFORO
FROM @DOC DOC
INNER JOIN dbo.FCXP P ON P.CNSFCXP = DOC.CNSFCXP
INNER JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
WHERE P.ESTADO <> N'A'
GROUP BY DOC.GRUPO, P.CNSFCXP, P.NOREFERENCIA, P.ESTADO, P.CONTABILIZADA,
         P.VALOR, P.VLR_IVA, P.VLR_NETO
ORDER BY DOC.GRUPO, P.NOREFERENCIA;

/* 2 — Detalle: solo problemas de cuenta */
SELECT
  P.CNSFCXP,
  P.NOREFERENCIA,
  D.ITEM,
  D.IDSERVICIO,
  CONVERT(decimal(18, 2), D.VLR_IVA) AS IVA,
  D.CUENTA_SER,
  D.CUENTA_IVA,
  CASE
    WHEN COALESCE(D.VLR_IVA, 0) > 0 AND D.CUENTA_SER IN (N'14150502', N'14200502') THEN N'Servicio excluido con IVA'
    WHEN COALESCE(D.VLR_IVA, 0) > 0 AND COALESCE(D.CUENTA_IVA, N'') <> N'24080501' THEN N'CUENTA_IVA <> 24080501'
    WHEN COALESCE(D.VLR_IVA, 0) <= 0 AND COALESCE(D.CUENTA_IVA, N'') <> N'' THEN N'IVA cero pero tiene CUENTA_IVA'
    ELSE N'?'
  END AS HALLAZGO
FROM @DOC DOC
INNER JOIN dbo.FCXP P ON P.CNSFCXP = DOC.CNSFCXP
INNER JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
WHERE P.ESTADO <> N'A'
  AND (
    (COALESCE(D.VLR_IVA, 0) > 0 AND D.CUENTA_SER IN (N'14150502', N'14200502'))
    OR (COALESCE(D.VLR_IVA, 0) > 0 AND COALESCE(D.CUENTA_IVA, N'') <> N'24080501')
    OR (COALESCE(D.VLR_IVA, 0) <= 0 AND COALESCE(D.CUENTA_IVA, N'') <> N'')
  )
ORDER BY P.NOREFERENCIA, D.ITEM;

/* 3 — Conteo global */
SELECT
  SUM(CASE WHEN SEMAFORO = N'OK' THEN 1 ELSE 0 END) AS CXP_OK,
  SUM(CASE WHEN SEMAFORO <> N'OK' THEN 1 ELSE 0 END) AS CXP_PENDIENTE
FROM (
  SELECT P.CNSFCXP,
    CASE
      WHEN ABS(P.VLR_NETO - SUM(D.VLR_NETO)) > 0.01 THEN N'X'
      WHEN ABS(P.VLR_IVA - SUM(D.VLR_IVA)) > 0.01 THEN N'X'
      WHEN ABS(P.VALOR + P.VLR_IVA - P.VLR_NETO) > 0.02 THEN N'X'
      WHEN SUM(CASE WHEN COALESCE(D.VLR_IVA, 0) > 0 AND (D.CUENTA_SER IN (N'14150502', N'14200502') OR COALESCE(D.CUENTA_IVA, N'') <> N'24080501') THEN 1 ELSE 0 END) > 0 THEN N'X'
      WHEN SUM(CASE WHEN ABS(D.VLR_NETO - (D.CANTIDAD * D.VALOR + COALESCE(D.VLR_IVA, 0) - ISNULL(D.VLR_DESCUENTO, 0))) > 0.02 THEN 1 ELSE 0 END) > 0 THEN N'X'
      ELSE N'OK'
    END AS SEMAFORO
  FROM @DOC DOC
  INNER JOIN dbo.FCXP P ON P.CNSFCXP = DOC.CNSFCXP
  INNER JOIN dbo.FCXPD D ON D.CNSFCXP = P.CNSFCXP
  WHERE P.ESTADO <> N'A'
  GROUP BY P.CNSFCXP, P.VALOR, P.VLR_IVA, P.VLR_NETO
) Z;
