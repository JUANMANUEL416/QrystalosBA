CREATE OR ALTER PROCEDURE DBO.SPQ_CONTRATOS_NOM @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(200))
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100)
DECLARE @USUARIO VARCHAR(20), @DATOS VARCHAR(MAX), @PROCESO VARCHAR(20)
DECLARE @IDNEMP VARCHAR(20), @FORMATO NVARCHAR(MAX), @CNSFORMATO NVARCHAR(MAX)
DECLARE @IDSEDE VARCHAR(10), @COMPANIA VARCHAR(2), @CNSCONTLABO VARCHAR(20)

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @PROCESO = PROCESO, @IDNEMP = IDNEMP, @CNSFORMATO = CNSFORMATO
			FROM OPENJSON(@PARAMETROS) WITH (PROCESO VARCHAR(20) '$.PROCESO', IDNEMP VARCHAR(20) '$.IDNEMP', CNSFORMATO NVARCHAR(MAX) AS JSON)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'EL EMPLEADO YA CUENTA CON UN CONTRATO ACTIVO'
					WHERE EXISTS (
							SELECT 1
							FROM NCONTLABO
							WHERE IDNEMP = @IDNEMP AND ESTADO = 'Activo'
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						SELECT @CNSFORMATO = CNSFORMATO
						FROM OPENJSON(@CNSFORMATO) WITH (CNSFORMATO NVARCHAR(MAX) '$.CNSFORMATO')

						SELECT @IDSEDE = COALESCE(UBEQ.IDSEDE, USUSU.IDSEDE), @COMPANIA = UBEQ.COMPANIA
						FROM USUSU
						LEFT JOIN UBEQ ON USUSU.SYS_ComputerName = UBEQ.SYS_ComputerName
						WHERE USUARIO = @USUARIO

						SELECT @CNSCONTLABO = ''

						EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '', @NVOCONSEC = @CNSCONTLABO OUTPUT

						PRINT '@CNSCONTLABO=' + COALESCE(@CNSCONTLABO, '')

						INSERT INTO NCONTLABO (CNSCONTLABO, IDNEMP, ESTADO, FECHA, CNSFORMATO)
						SELECT @CNSCONTLABO, @IDNEMP, 'Activo', GETDATE(), @CNSFORMATO
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GET_INFO_CONTRACT'
	BEGIN
		SELECT @CNSCONTLABO = CNSCONTLABO, @CNSFORMATO = CNSFORMATO, @IDNEMP = IDNEMP
		FROM OPENJSON(@PARAMETROS) WITH (CNSCONTLABO VARCHAR(20) '$.CNSCONTLABO', CNSFORMATO NVARCHAR(MAX) '$.CNSFORMATO', IDNEMP VARCHAR(20) '$.IDNEMP'
				)

		SELECT 'OK' AS OK

		SELECT NCONTLABO.FECHA AS FECHAGENERACION, NCERTC.FORMATOWEB, CONCAT (NEMP.PRIMERNOMBRE, ' ', NEMP.SEGUNDONOMBRE, ' ', NEMP.PRIMERAPELLIDO, ' ', NEMP.SEGUNDOAPELLIDO
				) AS EMPLEADO, NEMP.DOCIDEMPLEADO, NCERTC.TITULO, NCARNG.CODCARGO, NCARNG.DESCRIPCION AS CARGO, NEMP.FECHAINGRESO AS FECHAING, NEMP.BASICO, NEMP.
			EMAIL, NEMP.TIPOCONTRATO, NCERTC.VERSION, NCERTC.CODIGO, NCERTC.FECHA, TER.DIRECCION, TER.TELEFONOS AS TELEFONO, CIU.NOMBRE AS CIUDAD, ISNULL(DatosEPS
				.RAZONSOCIAL, 'No registra') AS EPS, ISNULL(DatosARL.RAZONSOCIAL, 'No registra') AS ARL, ISNULL(DatosCAJA.RAZONSOCIAL, 'No registra') AS 
			CAJACOMPENSACION,
			-- Campos de firma del empleado
			NCONTLABO.FECHA_FIRMA, NCONTLABO.USUARIOFIRMA,
			-- Base64 de la imagen de firma para renderizar en el PDF
			NCONTLABO.FIRMA_EMPLEADO_B64,
			-- Campos de firma del Representante Legal
			NCONTLABO.FECHA_FIRMA_REPRE, NCONTLABO.USUARIOFIRMA_REPRE, NCONTLABO.FIRMA_REPRE_B64
		FROM NCONTLABO
		INNER JOIN NCERTC ON NCERTC.CNSFORMATO = NCONTLABO.CNSFORMATO
		INNER JOIN NEMP ON NEMP.NUMDOC = NCONTLABO.IDNEMP
		INNER JOIN NCARNG ON NEMP.CODCARGO = NCARNG.CODCARGO AND NEMP.NIVEL = NCARNG.NIVEL AND NEMP.GRADO = NCARNG.GRADO
		INNER JOIN TER ON NEMP.TERCEROID = TER.IDTERCERO
		LEFT JOIN CIU ON TER.CIUDAD = CIU.CIUDAD
		-- 1. Extraer la EPS m�s reciente
		OUTER APPLY (
			SELECT TOP 1 CONCAT (T_EPS.NIT, ' ', T_EPS.RAZONSOCIAL) AS RAZONSOCIAL
			FROM NPRFED N_EPS
			INNER JOIN TGEN G_EPS ON G_EPS.CODIGO = N_EPS.codprf AND G_EPS.TABLA = 'Nomina' AND G_EPS.CAMPO = 'EPS'
			INNER JOIN TER T_EPS ON T_EPS.IDTERCERO = N_EPS.idtercero
			WHERE N_EPS.numdoc = NEMP.NUMDOC
			ORDER BY N_EPS.fechaini DESC
			) AS DatosEPS
		-- 2. Extraer la ARL m�s reciente
		OUTER APPLY (
			SELECT TOP 1 CONCAT (T_ARL.NIT, ' ', T_ARL.RAZONSOCIAL) AS RAZONSOCIAL
			FROM NPRFED N_ARL
			INNER JOIN TGEN G_ARL ON G_ARL.CODIGO = N_ARL.codprf AND G_ARL.TABLA = 'Nomina' AND G_ARL.CAMPO = 'ARL'
			INNER JOIN TER T_ARL ON T_ARL.IDTERCERO = N_ARL.idtercero
			WHERE N_ARL.numdoc = NEMP.NUMDOC
			ORDER BY N_ARL.fechaini DESC
			) AS DatosARL
		-- 3. Extraer la CAJA DE COMPENSACION m�s reciente
		OUTER APPLY (
			SELECT TOP 1 CONCAT (T_CAJA.NIT, ' ', T_CAJA.RAZONSOCIAL) AS RAZONSOCIAL
			FROM NPRFED N_CAJA
			INNER JOIN TGEN G_CAJA ON G_CAJA.CODIGO = N_CAJA.codprf AND G_CAJA.TABLA = 'Nomina' AND G_CAJA.CAMPO = 'CAJACOMPENSACION'
			INNER JOIN TER T_CAJA ON T_CAJA.IDTERCERO = N_CAJA.idtercero
			WHERE N_CAJA.numdoc = NEMP.NUMDOC
			ORDER BY N_CAJA.fechaini DESC
			) AS DatosCAJA
		WHERE NCONTLABO.CNSCONTLABO = JSON_VALUE(@PARAMETROS, '$.CNSCONTLABO')

		RETURN
	END

	IF @METODO = 'INACTIVE_CONTRACT'
	BEGIN
		SELECT @CNSCONTLABO = JSON_VALUE(@PARAMETROS, '$.CNSCONTLABO')

		BEGIN TRY
			UPDATE NCONTLABO
			SET ESTADO = 'Inactivo'
			WHERE CNSCONTLABO = @CNSCONTLABO
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	-- ============================================================
	-- NUEVO M�TODO: FIRMAR_CONTRATO
	-- Registra la firma del empleado sobre el contrato laboral.
	-- Almacena la fecha, usuario y la imagen en base64 para el PDF.
	-- El archivo binario se sube aparte via appStore.upload().
	-- ============================================================
	IF @METODO = 'FIRMAR_CONTRATO'
	BEGIN
		DECLARE @FIRMA_EMPLEADO_B64 NVARCHAR(MAX)

		-- IMPORTANTE: JSON_VALUE tiene l�mite de 4000 chars ? retorna NULL para strings
		-- grandes como el base64 de una imagen. OPENJSON WITH soporta NVARCHAR(MAX).
		SELECT @CNSCONTLABO = CNSCONTLABO, @FIRMA_EMPLEADO_B64 = FIRMA_EMPLEADO_B64
		FROM OPENJSON(@PARAMETROS) WITH (CNSCONTLABO VARCHAR(20) '$.CNSCONTLABO', FIRMA_EMPLEADO_B64 NVARCHAR(MAX) '$.FIRMA_EMPLEADO_B64')

		BEGIN TRY
			-- Validar que el contrato existe y est� Activo
			IF NOT EXISTS (
					SELECT 1
					FROM NCONTLABO
					WHERE CNSCONTLABO = @CNSCONTLABO AND ESTADO = 'Activo'
					)
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				VALUES ('El contrato no existe o no se encuentra en estado Activo')
			END

			-- Validar que el contrato no haya sido firmado previamente
			IF EXISTS (
					SELECT 1
					FROM NCONTLABO
					WHERE CNSCONTLABO = @CNSCONTLABO AND FECHA_FIRMA IS NOT NULL
					)
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				VALUES ('El contrato ya fue firmado por el empleado')
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) = 0
			BEGIN
				UPDATE NCONTLABO
				SET FECHA_FIRMA = GETDATE(), USUARIOFIRMA = @USUARIO, FIRMA_EMPLEADO_B64 = @FIRMA_EMPLEADO_B64
				WHERE CNSCONTLABO = @CNSCONTLABO
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		-- Retorna OK + datos de firma para actualizar el frontend
		SELECT 'OK' AS OK, FECHA_FIRMA, USUARIOFIRMA
		FROM NCONTLABO
		WHERE CNSCONTLABO = @CNSCONTLABO
	END

	-- ============================================================
	-- M�TODO: FIRMAR_REPRESENTANTE_LEGAL
	-- Registra la firma del Representante Legal sobre el contrato.
	-- Almacena la fecha, usuario e imagen base64 para el PDF.
	-- ============================================================
	IF @METODO = 'FIRMAR_REPRESENTANTE_LEGAL'
	BEGIN
		DECLARE @FIRMA_REPRE_B64 NVARCHAR(MAX)

		-- OPENJSON WITH soporta NVARCHAR(MAX) para base64 de imagen grande
		SELECT @CNSCONTLABO = CNSCONTLABO, @FIRMA_REPRE_B64 = FIRMA_REPRE_B64
		FROM OPENJSON(@PARAMETROS) WITH (CNSCONTLABO VARCHAR(20) '$.CNSCONTLABO', FIRMA_REPRE_B64 NVARCHAR(MAX) '$.FIRMA_REPRE_B64')

		BEGIN TRY
			IF NOT EXISTS (
					SELECT 1
					FROM NCONTLABO
					WHERE CNSCONTLABO = @CNSCONTLABO AND ESTADO = 'Activo'
					)
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				VALUES ('El contrato no existe o no se encuentra en estado Activo')
			END

			IF EXISTS (
					SELECT 1
					FROM NCONTLABO
					WHERE CNSCONTLABO = @CNSCONTLABO AND FECHA_FIRMA_REPRE IS NOT NULL
					)
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				VALUES ('El contrato ya fue firmado por el Representante Legal')
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) = 0
			BEGIN
				UPDATE NCONTLABO
				SET FECHA_FIRMA_REPRE = GETDATE(), USUARIOFIRMA_REPRE = @USUARIO, FIRMA_REPRE_B64 = @FIRMA_REPRE_B64
				WHERE CNSCONTLABO = @CNSCONTLABO
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' AS OK, FECHA_FIRMA_REPRE, USUARIOFIRMA_REPRE
		FROM NCONTLABO
		WHERE CNSCONTLABO = @CNSCONTLABO
	END
END
