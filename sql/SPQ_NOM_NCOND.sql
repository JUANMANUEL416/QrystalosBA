CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NCOND @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20)
DECLARE @PROCESO VARCHAR(20)
DECLARE @CODCONCEPTO VARCHAR(20), @ITEM DECIMAL(14, 0), @DETALLE VARCHAR(10), @FECHAINI DATETIME
DECLARE @FECHAFIN DATETIME, @TIPOCALCULO VARCHAR(10), @VALOR DECIMAL(14, 0), @VALOR_EMPRESA DECIMAL(14, 4)
DECLARE @BASE VARCHAR(20), @CONDICION VARCHAR(2), @EVALUAR VARCHAR(20), @CODPRF VARCHAR(20)
DECLARE @GENERA_CXP VARCHAR(2), @IDTERCERO VARCHAR(20), @BASE_PRESTACIONES VARCHAR(2)
DECLARE @FORMULA VARCHAR(2047), @DEFINICION VARCHAR(255), @VALIDA_ANTIGUEDAD VARCHAR(2), @DIAS_ANTIGUEDAD SMALLINT
DECLARE @CONDICION_ANTIGUEDAD VARCHAR(2), @VALIDA_FINGRESO VARCHAR(2), @FINGRESO DATETIME, @CONDICION_FINGRESO VARCHAR(2)
DECLARE @TIPOTABLA VARCHAR(20), @DMAANTIGUEDAD VARCHAR(1), @VALIDATABLA VARCHAR(20), @DMATABLA VARCHAR(1)
DECLARE @FRECUENCIA VARCHAR(12), @VALORFRECUENCIA INT, @DMAFRECUENCIA VARCHAR(1), @RELFREQFECHA VARCHAR(12)
DECLARE @FECHABASEFREQ DATETIME, @REDONDEO DECIMAL(14, 2), @HORAS INT, @DIAS INT, @GENERANOVEFU SMALLINT
DECLARE @CODNOVEFU VARCHAR(10), @VALIDA_TLABORADOPER VARCHAR(2), @HORAS_TLABORADOPER SMALLINT, @CONDICION_TLABORADOPER VARCHAR(2), @DMATLABORADOPER VARCHAR(1)
DECLARE @HORAS_TCOMPLETO SMALLINT, @TIPOVALORHORA VARCHAR(10), @RECOBRO SMALLINT, @RUBRO VARCHAR(50)
DECLARE @FIJO BIT, @CODPRF_RECO VARCHAR(20), @RUBRO_ID INT, @SINDEDUC INT, @BASERET BIT
DECLARE @ITEM_NCOND DECIMAL(14, 0)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @CODCONCEPTO = CODCONCEPTO, @ITEM = ITEM, @DETALLE = DETALLE, @FECHAINI = FECHAINI, @BASE_PRESTACIONES = BASE_PRESTACIONES, @BASERET = BASERET, 
				@CODPRF = CODPRF, @VALOR = VALOR, @VALOR_EMPRESA = VALOR_EMPRESA, @TIPOCALCULO = TIPOCALCULO, @IDTERCERO = IDTERCERO, @DEFINICION = DEFINICION, @RECOBRO 
				= RECOBRO, @CODPRF_RECO = CODPRF_RECO, @REDONDEO = REDONDEO, @GENERA_CXP = GENERA_CXP, @SINDEDUC = SINDEDUC, @CONDICION_FINGRESO = CONDICION_FINGRESO, 
				@FINGRESO = FINGRESO, @VALIDA_FINGRESO = VALIDA_FINGRESO, @CONDICION_ANTIGUEDAD = CONDICION_ANTIGUEDAD, @DMAANTIGUEDAD = DMAANTIGUEDAD, 
				@DIAS_ANTIGUEDAD = DIAS_ANTIGUEDAD, @VALIDA_ANTIGUEDAD = VALIDA_ANTIGUEDAD, @CONDICION_TLABORADOPER = CONDICION_TLABORADOPER, @DMATLABORADOPER = 
				DMATLABORADOPER, @HORAS_TLABORADOPER = HORAS_TLABORADOPER, @VALIDA_TLABORADOPER = VALIDA_TLABORADOPER, @HORAS_TCOMPLETO = HORAS_TCOMPLETO, 
				@TIPOVALORHORA = TIPOVALORHORA, @BASE = BASE, @FRECUENCIA = FRECUENCIA, @VALORFRECUENCIA = VALORFRECUENCIA, @DMAFRECUENCIA = DMAFRECUENCIA, 
				@RELFREQFECHA = RELFREQFECHA, @FECHABASEFREQ = FECHABASEFREQ, @DIAS = DIAS, @CODNOVEFU = CODNOVEFU, @CONDICION = CONDICION, @EVALUAR = EVALUAR, 
				@TIPOTABLA = TIPOTABLA, @VALIDATABLA = VALIDATABLA, @DMATABLA = DMATABLA, @RUBRO = RUBRO, @RUBRO_ID = RUBRO_ID, @FORMULA = FORMULA, @HORAS = HORAS, 
				@GENERANOVEFU = GENERANOVEFU, @FIJO = FIJO, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO', ITEM DECIMAL(14, 0) '$.ITEM', DETALLE VARCHAR(10) '$.DETALLE', FECHAINI DATETIME '$.FECHAINI', 
					FECHAFIN DATETIME '$.FECHAFIN', TIPOCALCULO VARCHAR(10) '$.TIPOCALCULO', VALOR DECIMAL(14, 0) '$.VALOR', VALOR_EMPRESA DECIMAL(14, 4) 
					'$.VALOR_EMPRESA', BASE VARCHAR(20) '$.BASE', CONDICION VARCHAR(2) '$.CONDICION', EVALUAR VARCHAR(20) '$.EVALUAR', CODPRF VARCHAR(20) 
					'$.CODPRF', GENERA_CXP VARCHAR(2) '$.GENERA_CXP', IDTERCERO VARCHAR(20) '$.IDTERCERO', BASE_PRESTACIONES VARCHAR(2) '$.BASE_PRESTACIONES', 
					FORMULA VARCHAR(2047) '$.FORMULA', DEFINICION VARCHAR(255) '$.DEFINICION', VALIDA_ANTIGUEDAD VARCHAR(2) '$.VALIDA_ANTIGUEDAD', 
					DIAS_ANTIGUEDAD SMALLINT '$.DIAS_ANTIGUEDAD', CONDICION_ANTIGUEDAD VARCHAR(2) '$.CONDICION_ANTIGUEDAD', VALIDA_FINGRESO VARCHAR(2) 
					'$.VALIDA_FINGRESO', FINGRESO DATETIME '$.FINGRESO', CONDICION_FINGRESO VARCHAR(2) '$.CONDICION_FINGRESO', TIPOTABLA VARCHAR(20) 
					'$.TIPOTABLA', DMAANTIGUEDAD VARCHAR(1) '$.DMAANTIGUEDAD', VALIDATABLA VARCHAR(20) '$.VALIDATABLA', DMATABLA VARCHAR(1) '$.DMATABLA', 
					FRECUENCIA VARCHAR(12) '$.FRECUENCIA', VALORFRECUENCIA INT '$.VALORFRECUENCIA', DMAFRECUENCIA VARCHAR(1) '$.DMAFRECUENCIA', RELFREQFECHA 
					VARCHAR(12) '$.RELFREQFECHA', FECHABASEFREQ DATETIME '$.FECHABASEFREQ', REDONDEO DECIMAL(14, 2) '$.REDONDEO', HORAS INT '$.HORAS', DIAS INT 
					'$.DIAS', GENERANOVEFU BIT '$.GENERANOVEFU', CODNOVEFU VARCHAR(10) '$.CODNOVEFU', VALIDA_TLABORADOPER VARCHAR(2) '$.VALIDA_TLABORADOPER', 
					HORAS_TLABORADOPER SMALLINT '$.HORAS_TLABORADOPER', CONDICION_TLABORADOPER VARCHAR(2) '$.CONDICION_TLABORADOPER', DMATLABORADOPER VARCHAR
					(1) '$.DMATLABORADOPER', HORAS_TCOMPLETO SMALLINT '$.HORAS_TCOMPLETO', TIPOVALORHORA VARCHAR(10) '$.TIPOVALORHORA', RECOBRO BIT '$.RECOBRO', 
					RUBRO VARCHAR(50) '$.RUBRO', FIJO BIT '$.FIJO', CODPRF_RECO VARCHAR(20) '$.CODPRF_RECO', RUBRO_ID INT '$.RUBRO_ID', SINDEDUC BIT '$.SINDEDUC', 
					BASERET BIT '$.BASERET', PROCESO VARCHAR(20) '$.PROCESO'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					INSERT INTO @TBLERRORES (ERROR)
					SELECT CONCAT ('EL CODIGO ', @CODCONCEPTO, ' Y ITEM ', @ITEM, ' YA SE ENCUENTRAN REGISTRADOS')
					WHERE EXISTS (
							SELECT 1
							FROM NCOND
							WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM
							)

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						INSERT INTO NCOND (
							CODCONCEPTO, ITEM, DETALLE, FECHAINI, FECHAFIN, TIPOCALCULO, VALOR, VALOR_EMPRESA, BASE, CONDICION, EVALUAR, CODPRF, GENERA_CXP, 
							IDTERCERO, BASE_PRESTACIONES, FORMULA, DEFINICION, VALIDA_ANTIGUEDAD, DIAS_ANTIGUEDAD, CONDICION_ANTIGUEDAD, VALIDA_FINGRESO, 
							FINGRESO, CONDICION_FINGRESO, TIPOTABLA, DMAANTIGUEDAD, VALIDATABLA, DMATABLA, FRECUENCIA, VALORFRECUENCIA, DMAFRECUENCIA, 
							RELFREQFECHA, FECHABASEFREQ, REDONDEO, HORAS, DIAS, GENERANOVEFU, CODNOVEFU, VALIDA_TLABORADOPER, CONDICION_TLABORADOPER, 
							HORAS_TLABORADOPER, DMATLABORADOPER, HORAS_TCOMPLETO, TIPOVALORHORA, RECOBRO, RUBRO, FIJO, CODPRF_RECO, RUBRO_ID, SINDEDUC, BASERET
							)
						SELECT @CODCONCEPTO, @ITEM, @DETALLE, @FECHAINI, @FECHAFIN, @TIPOCALCULO, @VALOR, @VALOR_EMPRESA, @BASE, @CONDICION, @EVALUAR, @CODPRF, 
							@GENERA_CXP, @IDTERCERO, @BASE_PRESTACIONES, @FORMULA, @DEFINICION, @VALIDA_ANTIGUEDAD, @DIAS_ANTIGUEDAD, @CONDICION_ANTIGUEDAD, 
							@VALIDA_FINGRESO, @FINGRESO, @CONDICION_FINGRESO, @TIPOTABLA, @DMAANTIGUEDAD, @VALIDATABLA, @DMATABLA, @FRECUENCIA, 
							@VALORFRECUENCIA, @DMAFRECUENCIA, @RELFREQFECHA, @FECHABASEFREQ, @REDONDEO, @HORAS, @DIAS, @GENERANOVEFU, @CODNOVEFU, 
							@VALIDA_TLABORADOPER, @CONDICION_TLABORADOPER, @HORAS_TLABORADOPER, @DMATLABORADOPER, @HORAS_TCOMPLETO, @TIPOVALORHORA, @RECOBRO
							, @RUBRO, @FIJO, @CODPRF_RECO, @RUBRO_ID, @SINDEDUC, @BASERET

						SELECT 'OK' OK

						SELECT *
						FROM NCOND
						WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM

						RETURN
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					BEGIN
						UPDATE NCOND
						SET DETALLE = @DETALLE, FECHAINI = @FECHAINI, BASE_PRESTACIONES = @BASE_PRESTACIONES, BASERET = @BASERET, CODPRF = @CODPRF, VALOR = @VALOR, 
							VALOR_EMPRESA = @VALOR_EMPRESA, TIPOCALCULO = @TIPOCALCULO, IDTERCERO = @IDTERCERO, DEFINICION = @DEFINICION, RECOBRO = @RECOBRO, 
							CODPRF_RECO = @CODPRF_RECO, REDONDEO = @REDONDEO, GENERA_CXP = @GENERA_CXP, SINDEDUC = @SINDEDUC, CONDICION_FINGRESO = 
							@CONDICION_FINGRESO, FINGRESO = @FINGRESO, VALIDA_FINGRESO = @VALIDA_FINGRESO, CONDICION_ANTIGUEDAD = @CONDICION_ANTIGUEDAD, 
							DMAANTIGUEDAD = @DMAANTIGUEDAD, DIAS_ANTIGUEDAD = @DIAS_ANTIGUEDAD, VALIDA_ANTIGUEDAD = @VALIDA_ANTIGUEDAD, CONDICION_TLABORADOPER = 
							@CONDICION_TLABORADOPER, DMATLABORADOPER = @DMATLABORADOPER, HORAS_TLABORADOPER = @HORAS_TLABORADOPER, VALIDA_TLABORADOPER = 
							@VALIDA_TLABORADOPER, HORAS_TCOMPLETO = @HORAS_TCOMPLETO, TIPOVALORHORA = @TIPOVALORHORA, BASE = @BASE, FRECUENCIA = @FRECUENCIA, 
							VALORFRECUENCIA = @VALORFRECUENCIA, DMAFRECUENCIA = @DMAFRECUENCIA, RELFREQFECHA = @RELFREQFECHA, FECHABASEFREQ = @FECHABASEFREQ, DIAS 
							= @DIAS, CODNOVEFU = @CODNOVEFU, CONDICION = @CONDICION, EVALUAR = @EVALUAR, TIPOTABLA = @TIPOTABLA, VALIDATABLA = @VALIDATABLA, DMATABLA = 
							@DMATABLA, RUBRO = @RUBRO, RUBRO_ID = @RUBRO_ID, FORMULA = @FORMULA, HORAS = @HORAS, GENERANOVEFU = @GENERANOVEFU, FIJO = @FIJO
						WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM

						SELECT 'OK' OK

						SELECT *
						FROM NCOND
						WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GET_NCOND_DETALLE'
	BEGIN
		SELECT @CODCONCEPTO = CODCONCEPTO
		FROM OPENJSON(@PARAMETROS) WITH (CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO')

		SELECT 'OK' OK

		SELECT NCOND.*, NCON.CLASE AS CLASENCON
		FROM NCOND
		INNER JOIN NCON ON NCON.CODCONCEPTO = NCOND.CODCONCEPTO
		WHERE NCOND.CODCONCEPTO = JSON_VALUE(@PARAMETROS, '$.CODCONCEPTO')

		RETURN
	END

	IF @METODO = 'GET_NCOND'
	BEGIN
		SELECT @CODCONCEPTO = CODCONCEPTO, @ITEM = ITEM
		FROM OPENJSON(@PARAMETROS) WITH (CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO', ITEM DECIMAL(14, 0) '$.ITEM')

		SELECT 'OK' OK

		SELECT *
		FROM NCOND
		WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM

		RETURN
	END

	IF @METODO = 'UPDATE_DATACONDITION'
	BEGIN
		BEGIN TRY
			SELECT @CODCONCEPTO = CODCONCEPTO, @ITEM_NCOND = ITEM_NCOND, @CONDICION = CONDICION, @EVALUAR = EVALUAR
			FROM OPENJSON(@PARAMETROS) WITH (
					CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO', ITEM_NCOND DECIMAL(14, 0) '$.ITEM_NCOND', CONDICION VARCHAR(2) '$.CONDICION', EVALUAR VARCHAR(20) 
					'$.EVALUAR'
					)

			BEGIN
				UPDATE NCOND
				SET CONDICION = @CONDICION, EVALUAR = @EVALUAR
				WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM_NCOND
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK

		RETURN
	END

	IF @METODO = 'UPDATE_DATATABLE'
	BEGIN
		BEGIN TRY
			SELECT @CODCONCEPTO = CODCONCEPTO, @ITEM = ITEM, @TIPOTABLA = TIPOTABLA, @VALIDATABLA = VALIDATABLA, @DMATABLA = DMATABLA
			FROM OPENJSON(@PARAMETROS) WITH (
					CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO', ITEM DECIMAL(14, 0) '$.ITEM', TIPOTABLA VARCHAR(20) '$.TIPOTABLA', VALIDATABLA VARCHAR(20) 
					'$.VALIDATABLA', DMATABLA VARCHAR(1) '$.DMATABLA'
					)

			BEGIN
				UPDATE NCOND
				SET TIPOTABLA = @TIPOTABLA, VALIDATABLA = @VALIDATABLA, DMATABLA = @DMATABLA
				WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK

		RETURN
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @CODCONCEPTO = CODCONCEPTO, @ITEM = ITEM
		FROM OPENJSON(@PARAMETROS) WITH (CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO', ITEM DECIMAL(14, 0) '$.ITEM')

		BEGIN TRY
			DELETE
			FROM NCOND
			WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	-- NUEVO METODO PARA VALIDADAR CONCEPTOS DE NOMINA ESPECIAL
	IF @METODO = 'COUNT_CXPESPECIAL'
	BEGIN
		SELECT 'OK' OK

		SELECT COUNT(*) AS TOTAL
		FROM NCON
		WHERE CODCONCEPTO IN (
				SELECT CODIGO
				FROM TGEN
				WHERE TABLA = 'NOMINA' AND CAMPO = 'CXPESPECIAL'
				)

		RETURN
	END
END
