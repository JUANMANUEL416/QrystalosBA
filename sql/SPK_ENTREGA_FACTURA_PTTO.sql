CREATE OR ALTER PROCEDURE DBO.SPK_ENTREGA_FACTURA_PTTO 
@N_FACTURA VARCHAR(20) , 
@IDSEDE VARCHAR(5)
WITH ENCRYPTION
AS
DECLARE @CNSFCT       VARCHAR(40)
DECLARE @CONSECUTIVO  VARCHAR(20)  --PRESUPUESTO
DECLARE @CCOSTOPRESUP VARCHAR(20)  --PRESUPUESTO
DECLARE @RECO         VARCHAR(20)  --PRESUPUESTO
DECLARE @FECHARECEP   DATETIME
DECLARE @ENPPTO       INT
DECLARE @CLASEPRECO   VARCHAR(20)
DECLARE @IDSEDEPPAL   VARCHAR(5)
DECLARE @VLR_FACTURA  DECIMAL(14,2)
BEGIN 
   PRINT 'EMPIEZO N_fACTURA='+@N_FACTURA
   SELECT @FECHARECEP=FTR.F_FACTURA,@ENPPTO=COALESCE(ENPRESUPUESTO,0),@CNSFCT=CNSFCT,@VLR_FACTURA=VR_TOTAL FROM FTR WHERE N_FACTURA=@N_FACTURA
   SELECT @CONSECUTIVO  = CONSECUTIVO FROM PTPTO WHERE FECHAINI <= @FECHARECEP AND FECHAFIN >= @FECHARECEP
   IF COALESCE(@ENPPTO,0)<>0
   BEGIN
      PRINT 'Valido detalles y datos en presupuesto'
      IF EXISTS(SELECT * FROM PTRECO  WHERE N_FACTURA=@N_FACTURA AND CONSECUTIVO=@CONSECUTIVO)
      BEGIN
         SELECT @RECO=RECO FROM   PTRECO  WHERE N_FACTURA=@N_FACTURA AND CONSECUTIVO=@CONSECUTIVO
         IF EXISTS(SELECT * FROM PTRECOD WHERE CONSECUTIVO=@CONSECUTIVO AND RECO=@RECO)
         BEGIN
            PRINT 'YA ESTA EN PRESUPUESTO ME REGRESO ACTUALIZO ESTADO FTR'
            UPDATE FTR SET ENPRESUPUESTO=1 WHERE N_FACTURA=@N_FACTURA
            RETURN
         END
         ELSE
         BEGIN
            PRINT 'NO ESTA.. CORRIGO'
            IF EXISTS(SELECT * FROM PTRECO  WHERE N_FACTURA=@N_FACTURA AND CONSECUTIVO=@CONSECUTIVO AND (ESTADO='Confirmado' OR ESTADO='Anulado'))
            BEGIN
               UPDATE PTRECO SET ESTADO='NoConfirmado' WHERE N_FACTURA=@N_FACTURA AND CONSECUTIVO=@CONSECUTIVO AND (ESTADO='Confirmado' OR ESTADO='Anulado')
            END
            INSERT INTO PTRECOD (COMPANIA, CONSECUTIVO, RECO, CLASE, RUBRO, OBJETIVO, VALOR,VALOR_RECA,SALDO,RUBRO_ID ) --, SALDO)
            SELECT '01', @CONSECUTIVO, @RECO, 'Ingreso', PLN.RUBRO, CASE COALESCE(PLN.CAPITADO,0) WHEN 0 THEN 'EVENTO' ELSE 'CAPITADO' END +
                     ' FACTURADO EN EL MES DE ' + CASE MONTH(FTR.F_FACTURA) WHEN 1  THEN 'ENERO'   WHEN 2  THEN 'FEBRERO'   WHEN 3  THEN 'MARZO'
                                                                           WHEN 4  THEN 'ABRIL'   WHEN 5  THEN 'MAYO'      WHEN 6  THEN 'JUNIO'
                                                                           WHEN 7  THEN 'JULIO'   WHEN 8  THEN 'AGOSTO'    WHEN 9  THEN 'SEPTIEMBRE'
                                                                           WHEN 10 THEN 'OCTUBRE' WHEN 11 THEN 'NOVIEMBRE' WHEN 12 THEN 'DICIEMBRE'
                                                END,
                     FTR.VR_TOTAL,0,FTR.VR_TOTAL, PLN.RUBRO_ID
            FROM   FTR  LEFT JOIN PLN          ON FTR.IDPLAN = PLN.IDPLAN
            WHERE  N_FACTURA = @N_FACTURA 
         
            UPDATE FTR SET ENPRESUPUESTO = 1, CONSECUTIVOPTO = @CONSECUTIVO, RECO = @RECO
            WHERE  N_FACTURA = @N_FACTURA

            UPDATE PTRECO SET ESTADO='Confirmado' WHERE CONSECUTIVO = @CONSECUTIVO AND  RECO = @RECO AND  N_FACTURA = @N_FACTURA

            PRINT 'ME REGRESO'
            RETURN
         END
      END

   END
   SELECT @CCOSTOPRESUP = DBO.FNK_VALORVARIABLE('PRESUP_CCOSTO')
   PRINT 'ESTE EL CCOSTO PRESUPUESTO:::: '+@CCOSTOPRESUP
   IF COALESCE(@CCOSTOPRESUP,'')=''
   BEGIN
      RAISERROR ('No Esta Configurada la Variable de Presupuesto',16,1)
      RETURN
   END  
   SELECT @CLASEPRECO = DBO.FNK_VALORVARIABLE('PRESUP_TIPORECO')
   IF COALESCE(@CLASEPRECO,'')=''
   BEGIN
      RAISERROR ('No Esta Configurada la Variable de Tipo de Reconocimiento',16,1)
      RETURN
   END  
   IF DBO.FNK_VALORVARIABLE('PRESUP_TIPORECO')='CUENTAC' --GG necesario CUENTAC para enviar a PPTO
   BEGIN  
      IF @ENPPTO=2
      BEGIN
         SELECT @RECO=RECO FROM FTR WHERE N_FACTURA=@N_FACTURA AND CONSECUTIVOPTO=@CONSECUTIVO
         IF COALESCE(@RECO,'')=''
         BEGIN
            SELECT @ENPPTO=0
         END
      END
      IF @ENPPTO=1
      BEGIN
         IF NOT EXISTS(SELECT  * FROM PTRECO WHERE N_FACTURA=@N_FACTURA AND CNSFCXC=@CNSFCT)
         BEGIN 
            UPDATE FTR SET ENPRESUPUESTO=0,RECO=NULL,CONSECUTIVOPTO=NULL  WHERE N_FACTURA=@N_FACTURA AND CNSFCT=@CNSFCT
            SELECT @ENPPTO=0
         END
      END
      IF @ENPPTO=0
      BEGIN
         SELECT @IDSEDEPPAL=LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('IDSEDEPRINCIPAL')))
         IF COALESCE(@IDSEDEPPAL,'')=''
         BEGIN
            SELECT @IDSEDEPPAL=@IDSEDE
         END
         SELECT @RECO = ISNULL(CONTADOR_RR,0) + 1 
         FROM   PTPTO 
         WHERE  COMPANIA = '01' AND CONSECUTIVO = @CONSECUTIVO
         
         SELECT @RECO = @IDSEDEPPAL + REPLACE(SPACE(8 - LEN(@RECO))+LTRIM(RTRIM(@RECO)),SPACE(1),0) 

         UPDATE PTPTO SET CONTADOR_RR = ISNULL(CONTADOR_RR,0) + 1 
         WHERE  COMPANIA    = '01' 
         AND    CONSECUTIVO = @CONSECUTIVO
      END
      ELSE
      BEGIN
         SELECT @RECO=RECO FROM FTR WHERE N_FACTURA=@N_FACTURA AND CONSECUTIVOPTO=@CONSECUTIVO
         DELETE PTRECOD WHERE RECO=@RECO AND CONSECUTIVO=@CONSECUTIVO
         DELETE PTRECO WHERE RECO=@RECO AND CONSECUTIVO=@CONSECUTIVO   
      END 

      PRINT 'CONSECUTIVO DE PTRCO :: '+@RECO            
      INSERT INTO PTRECO(COMPANIA, CONSECUTIVO, RECO, OBJETIVO, VALOR, CNSFCXC, IDTERCERO, FECHA, ESTADO, CCOSTO, N_FACTURA, CNSFTR,TIPO,IDSEDE,SALDO)
      SELECT '01', @CONSECUTIVO, @RECO, 'REGIMEN: ' + PLN.TIPOSISTEMA+ ' ' + 
               CASE COALESCE(PLN.CAPITADO,0) WHEN 0 THEN 'EVENTO' ELSE 'CAPITADO' END +
               ' FACTURADO EN EL MES DE ' + CASE MONTH(FTR.F_FACTURA) WHEN 1  THEN 'ENERO'   WHEN 2  THEN 'FEBRERO'   WHEN 3  THEN 'MARZO'
                                                                     WHEN 4  THEN 'ABRIL'   WHEN 5  THEN 'MAYO'      WHEN 6  THEN 'JUNIO'
                                                                     WHEN 7  THEN 'JULIO'   WHEN 8  THEN 'AGOSTO'    WHEN 9  THEN 'SEPTIEMBRE'
                                                                     WHEN 10 THEN 'OCTUBRE' WHEN 11 THEN 'NOVIEMBRE' WHEN 12 THEN 'DICIEMBRE'
                                          END,
               FTR.VR_TOTAL, FTR.CNSFCT, FTR.IDTERCERO, @FECHARECEP, 'NoConfirmado', @CCOSTOPRESUP, @N_FACTURA, @CNSFCT,'Suma',@IDSEDE,FTR.VR_TOTAL
      FROM   FTR  LEFT JOIN PLN ON FTR.IDPLAN = PLN.IDPLAN
      WHERE  N_FACTURA = @N_FACTURA
         

         
      INSERT INTO PTRECOD (COMPANIA, CONSECUTIVO, RECO, CLASE, RUBRO, OBJETIVO, VALOR,VALOR_RECA,SALDO,RUBRO_ID ) --, SALDO)
      SELECT '01', @CONSECUTIVO, @RECO, 'Ingreso', PLN.RUBRO, CASE COALESCE(PLN.CAPITADO,0) WHEN 0 THEN 'EVENTO' ELSE 'CAPITADO' END +
               ' FACTURADO EN EL MES DE ' + CASE MONTH(FTR.F_FACTURA) WHEN 1  THEN 'ENERO'   WHEN 2  THEN 'FEBRERO'   WHEN 3  THEN 'MARZO'
                                                                     WHEN 4  THEN 'ABRIL'   WHEN 5  THEN 'MAYO'      WHEN 6  THEN 'JUNIO'
                                                                     WHEN 7  THEN 'JULIO'   WHEN 8  THEN 'AGOSTO'    WHEN 9  THEN 'SEPTIEMBRE'
                                                                     WHEN 10 THEN 'OCTUBRE' WHEN 11 THEN 'NOVIEMBRE' WHEN 12 THEN 'DICIEMBRE'
                                          END,
               FTR.VR_TOTAL,0,FTR.VR_TOTAL, PLN.RUBRO_ID
      FROM   FTR  LEFT JOIN PLN          ON FTR.IDPLAN = PLN.IDPLAN
      WHERE  N_FACTURA = @N_FACTURA 
         
      UPDATE FTR SET ENPRESUPUESTO = 1, CONSECUTIVOPTO = @CONSECUTIVO, RECO = @RECO
      WHERE  N_FACTURA = @N_FACTURA

      UPDATE PTRECO SET ESTADO='Confirmado' WHERE CONSECUTIVO = @CONSECUTIVO AND  RECO = @RECO AND  N_FACTURA = @N_FACTURA

   END
END
