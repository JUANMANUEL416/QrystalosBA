CREATE OR ALTER PROCEDURE DBO.SPQ_ICLA
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @PARAMETROS   NVARCHAR(MAX), @MODELO         VARCHAR(100),   @METODO         VARCHAR(100)
DECLARE  @USUARIO      VARCHAR(20),   @IDCLASE	      VARCHAR(2),	  @DESCRIPCION	  VARCHAR(100)
DECLARE	 @IDITAR	   VARCHAR(2),    @IDSUBCLASE     VARCHAR(4),	  @IDGRUPO		  VARCHAR(4)
DECLARE  @PROCESO	   VARCHAR(20)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

	IF @METODO = 'CONSULTAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDCLASE = IDCLASE, @DESCRIPCION = DESCRIPCION, @IDITAR = IDITAR, @IDSUBCLASE = IDSUBCLASE, @IDGRUPO = IDGRUPO,
					@PROCESO = PROCESO
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				IDCLASE     VARCHAR(2)  '$.IDCLASE',		DESCRIPCION		VARCHAR(100) '$.DESCRIPCION',	IDITAR		VARCHAR(2) '$.IDITAR',  
				IDSUBCLASE  VARCHAR(4)	'$.IDSUBCLASE',		IDGRUPO			VARCHAR(4)	 '$.IDGRUPO',		PROCESO		VARCHAR(20) '$.PROCESO'
			)

			IF @PROCESO = 'CLASES'
			BEGIN
				SELECT ICLA.IDCLASE, ICLA.DESCRIPCION, ICLA.IDITAR, ITAR.DESCRIPCION DESC_ITAR
				FROM ICLA LEFT JOIN ITAR ON ITAR.IDITAR = ICLA.IDITAR ORDER BY ICLA.IDCLASE
				RETURN
			END
			
			IF @PROCESO = 'SUBCLASES'
			BEGIN
				SELECT ICLAH.IDCLASE, ICLAH.IDSUBCLASE, ICLAH.DESCRIPCION
				FROM ICLAH INNER JOIN ICLA ON ICLA.IDCLASE = ICLAH.IDCLASE
				WHERE ICLAH.IDCLASE = @IDCLASE ORDER BY ICLAH.IDSUBCLASE
				RETURN
			END

			IF @PROCESO = 'GRUPOS'
			BEGIN
				SELECT IGRU.IDCLASE, IGRU.IDSUBCLASE, IGRU.IDGRUPO, IGRU.DESCRIPCION
				FROM IGRU INNER JOIN ICLAH ON IGRU.IDSUBCLASE = ICLAH.IDSUBCLASE
				WHERE IGRU.IDSUBCLASE = @IDSUBCLASE ORDER BY IGRU.IDGRUPO
				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDCLASE = IDCLASE, @DESCRIPCION = DESCRIPCION, @IDITAR = IDITAR, @IDSUBCLASE = IDSUBCLASE, @IDGRUPO = IDGRUPO,
					@PROCESO = PROCESO
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				IDCLASE     VARCHAR(2)  '$.IDCLASE',		DESCRIPCION		VARCHAR(100) '$.DESCRIPCION',	IDITAR		VARCHAR(2) '$.IDITAR',  
				IDSUBCLASE  VARCHAR(4)	'$.IDSUBCLASE',		IDGRUPO			VARCHAR(4)	 '$.IDGRUPO',		PROCESO		VARCHAR(20) '$.PROCESO'
			)

			IF @PROCESO = 'CLASES'
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) 
				SELECT 'ESTA CLASE YA EXISTE'
				WHERE EXISTS (SELECT * FROM ICLA WHERE IDCLASE=@IDCLASE)

				IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
				BEGIN
					INSERT INTO ICLA (IDCLASE ,DESCRIPCION ,IDITAR )   
					SELECT @IDCLASE ,@DESCRIPCION ,@IDITAR
				END
			END
			
			IF @PROCESO = 'SUBCLASES'
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) 
				SELECT 'ESTA SUBCLASE YA EXISTE EN LA CLASE'
				WHERE EXISTS (SELECT * FROM ICLAH WHERE IDCLASE=@IDCLASE AND IDSUBCLASE=@IDSUBCLASE)

				IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
				BEGIN
					INSERT INTO ICLAH (IDCLASE ,IDSUBCLASE ,DESCRIPCION ) 
					SELECT @IDCLASE ,@IDSUBCLASE ,@DESCRIPCION
				END
			END

			IF @PROCESO = 'GRUPOS'
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) 
				SELECT 'ESTE GRUPO YA EXISTE EN LA SUBCLASE'
				WHERE EXISTS (SELECT * FROM IGRU WHERE IDCLASE=@IDCLASE AND IDSUBCLASE=@IDSUBCLASE AND IDGRUPO=@IDGRUPO)

				IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
				BEGIN
					INSERT INTO IGRU (IDCLASE ,IDSUBCLASE ,IDGRUPO ,DESCRIPCION )   
					SELECT @IDCLASE ,@IDSUBCLASE ,@IDGRUPO ,@DESCRIPCION
				END
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ACTUALIZAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDCLASE = IDCLASE, @DESCRIPCION = DESCRIPCION, @IDITAR = IDITAR, @IDSUBCLASE = IDSUBCLASE, @IDGRUPO = IDGRUPO,
					@PROCESO = PROCESO
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				IDCLASE     VARCHAR(2)  '$.IDCLASE',		DESCRIPCION		VARCHAR(100) '$.DESCRIPCION',	IDITAR		VARCHAR(2) '$.IDITAR',  
				IDSUBCLASE  VARCHAR(4)	'$.IDSUBCLASE',		IDGRUPO			VARCHAR(4)	 '$.IDGRUPO',		PROCESO		VARCHAR(20) '$.PROCESO'
			)

			IF @PROCESO = 'CLASES'
			BEGIN
				UPDATE ICLA SET DESCRIPCION = @DESCRIPCION, IDITAR = @IDITAR 
				WHERE IDCLASE = @IDCLASE
			END
			
			IF @PROCESO = 'SUBCLASES'
			BEGIN
				UPDATE ICLAH SET DESCRIPCION = @DESCRIPCION
				WHERE IDCLASE = @IDCLASE AND IDSUBCLASE = @IDSUBCLASE
			END

			IF @PROCESO = 'GRUPOS'
			BEGIN
				UPDATE IGRU SET DESCRIPCION = @DESCRIPCION   
				WHERE IDCLASE = @IDCLASE AND IDSUBCLASE = @IDSUBCLASE AND IDGRUPO = @IDGRUPO
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
	
	IF @METODO = 'ELIMINAR'
	BEGIN
		BEGIN TRY
			SELECT  @IDCLASE = IDCLASE, @IDSUBCLASE = IDSUBCLASE, @IDGRUPO = IDGRUPO, @PROCESO = PROCESO
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				IDCLASE     VARCHAR(2)  '$.IDCLASE',		IDSUBCLASE  VARCHAR(4)	'$.IDSUBCLASE',
				IDGRUPO		VARCHAR(4)	 '$.IDGRUPO',		PROCESO		VARCHAR(20) '$.PROCESO'
			)

			IF @PROCESO = 'CLASES'
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) 
				SELECT 'LA CLASE TIENE SUBCLASES ASIGNADAS'
				WHERE EXISTS (SELECT * FROM ICLAH WHERE IDCLASE = @IDCLASE)

				IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
				BEGIN
					DELETE FROM ICLA WHERE IDCLASE = @IDCLASE
				END
			END
			
			IF @PROCESO = 'SUBCLASES'
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) 
				SELECT 'LA SUBCLASE TIENE GRUPOS ASIGNADOS'
				WHERE EXISTS (SELECT * FROM IGRU WHERE IDSUBCLASE = @IDSUBCLASE)

				IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
				BEGIN
					DELETE FROM ICLAH WHERE IDCLASE = @IDCLASE AND IDSUBCLASE = @IDSUBCLASE
				END
			END

			IF @PROCESO = 'GRUPOS'
			BEGIN
				DELETE FROM IGRU WHERE IDCLASE = @IDCLASE AND IDSUBCLASE = @IDSUBCLASE AND IDGRUPO = @IDGRUPO
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
END
