      SELECT 1
      FROM IMOVH H WITH (NOLOCK)
      INNER JOIN IMOV M WITH (NOLOCK) ON M.CNSMOV = H.CNSMOV
      WHERE M.NODOCUMENTO = @CNSIZSOL_DM
        AND COALESCE(TRY_CONVERT(SMALLINT, M.ESTADO), 0) = 0
    )
    BEGIN
      SELECT 'KO' OK
      SELECT 'Hay entregas armadas. Clic derecho en cada lote ? Retirar entrega. Cuando no quede ninguno, deshaga la dispensación.' ERROR
      RETURN
    END

    SELECT TOP 1 @CNSCEFM_DM = NULLIF(LTRIM(RTRIM(AE.CNSCEFM)), '')
    FROM AUTE AE WITH (NOLOCK)
    WHERE AE.IDAUT = @IDAUT_DM
    ORDER BY AE.IDAUTE DESC

    IF COALESCE(@CNSCEFM_DM, '') = '' AND COL_LENGTH('dbo.AUTE', 'CNSIZSOL') IS NOT NULL
    BEGIN
      EXEC sp_executesql N'
        SELECT TOP 1 @O = NULLIF(LTRIM(RTRIM(CNSCEFM)), '''')
        FROM AUTE WITH (NOLOCK)
        WHERE CNSIZSOL = @C
        ORDER BY IDAUTE DESC',
        N'@C VARCHAR(20), @O VARCHAR(20) OUTPUT',
        @CNSIZSOL_DM, @CNSCEFM_DM OUTPUT
    END

    /* Snapshot para reabrir Nueva dispensación: paciente + cantidades, sin lotes. */
    INSERT INTO @CAB_DM (
      IDAFILIADO, DOCIDAFILIADO, NOMBREAFI, IDTERCEROCA, IDPLAN,
      FECHA_FORMULA, FECHAVENCE, FECHATRANSCRIPCION, DXPPAL,
      TIPO_IDMED, DOCMEDICO, NUMAUTORIZA, FECHAAUTORIZA, VALORCOPAGO,
      NOPOS, IDMIPRESS, MENTREGA, OBSERVACION, IDSEDE, CNSIZSOL, CNSCEFM
    )
    SELECT TOP 1
      COALESCE(C.IDAFILIADO, A.IDAFILIADO),
      F.DOCIDAFILIADO,
      F.NOMBREAFI,
      COALESCE(C.IDTERCEROCA, A.IDTERCEROCA, IZ.IDTERCEROC),
      COALESCE(C.IDPLAN, A.IDPLAN, IZ.IDPLAN),
      CONVERT(VARCHAR(10), COALESCE(C.FECHA_FORMULA, A.FECHA), 23),
      CONVERT(VARCHAR(10), COALESCE(C.FECHAVENCE, A.FECHAVENCE), 23),
      CONVERT(VARCHAR(10), C.FECHATRANSCRIPCION, 23),
      COALESCE(C.DXPPAL, A.DXPPAL),
      C.TIPO_IDMED,
      COALESCE(C.DOCMEDICO, A.IDMEDICOSOLICITA),
      COALESCE(C.NUMAUTORIZA, A.NUMAUTORIZA),
      CONVERT(VARCHAR(10), COALESCE(C.FECHAAUTORIZA, A.FECHAAUTORIZA), 23),
      COALESCE(C.VALORCOPAGO, A.VALORCOPAGO),
      CAST(COALESCE(C.NOPOS, 0) AS BIT),
      C.IDMIPRESS,
      COALESCE(C.MENTREGA, A.MENTREGA),
      C.OBSERVACION,
      COALESCE(C.IDSEDE, A.IDSEDE, IZ.IDSEDE),
      @CNSIZSOL_DM,
      @CNSCEFM_DM
    FROM IZSOL IZ WITH (NOLOCK)
    LEFT JOIN AUT A WITH (NOLOCK) ON A.IDAUT = IZ.NOADMISION
    LEFT JOIN CEFM C WITH (NOLOCK) ON C.CNSCEFM = @CNSCEFM_DM
    LEFT JOIN AFI F WITH (NOLOCK) ON F.IDAFILIADO = COALESCE(C.IDAFILIADO, A.IDAFILIADO)
    WHERE IZ.CNSIZSOL = @CNSIZSOL_DM

    INSERT INTO @DET_DM (IDARTICULO, IDSERVICIO, DESCRIPCION, CANTIDAD)
    SELECT
      D.IDARTICULO,
      MAX(NULLIF(LTRIM(RTRIM(D.IDSERVICIO)), '')),
      MAX(IART.DESCRIPCION),
      SUM(D.CANTIDADSOL)
