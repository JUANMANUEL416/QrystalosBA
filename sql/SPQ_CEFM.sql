    /* Médico de la transcripción ? AUT.IDSOLICITANTE / IDMEDICOSOLICITA */
    IF COALESCE(@DOCMED_A, '') <> ''
    BEGIN
      SET @IDSOL_A = LEFT(@DOCMED_A, 20)
      SET @IDMED_A = LEFT(@DOCMED_A, 12)
    END

    SET @PAT_AUT = NULL
    IF OBJECT_ID('dbo.CEFMMED', 'U') IS NOT NULL AND COALESCE(@DOCMED_A, '') <> ''
      SELECT TOP 1 @PAT_AUT = DBO.FNK_CEFM_PERSONAL_AT(ESPECIALIDAD)
      FROM CEFMMED WITH (NOLOCK)
      WHERE IDMEDICO = @DOCMED_A

    UPDATE CEFM
    SET PREFIJO = @PREF_A,
        MENTREGA = 'Institucional',
        FINALIDAD = @FIN_A,
