        FECHAAUTORIZA = DBO.FNK_CEFM_FECHA_AUT(@NUMAUT_A, @FECHAAUTZ),
        CCOSTO  = COALESCE(@CCOSTO_A, CCOSTO),
        IDAREA  = COALESCE(@IDAREA_A, IDAREA)
    WHERE CNSCEFM = @CNSCEFM

    SELECT @IDPROV_A = IDPROVEEDORDEF FROM PRE WITH (NOLOCK) WHERE PREFIJO = @PREF_A
    SET @CLASEORD_A = 'Normal'

    /* AUT de facturación se crea al CONFIRMAR la salida (SPQ_CEFM_CREA_AUT_DESDE_IMOV).
       Aquí solo: AUTE periodos + IZSOL/IZSOLD con qty = AUTED periodo 1. */
    SET @IDAUT1 = NULL
    SET @NOAUT1 = NULL
    DECLARE @AVISO_RELIQ VARCHAR(500) = NULL
    DECLARE @CNSIZSOL_FB VARCHAR(20)
    DECLARE @EXISTS_FB BIT
    DECLARE @COMPANIA_IZ VARCHAR(2)
    DECLARE @CNSMOV_PED VARCHAR(20)

    /* AUTE/AUTED desde #LINEAS (sin AUT) */
    SET @ES_IDENT_AUTE  = COALESCE(COLUMNPROPERTY(OBJECT_ID('dbo.AUTE'), 'IDAUTE', 'IsIdentity'), 0)
    SET @ES_IDENT_AUTED = COALESCE(COLUMNPROPERTY(OBJECT_ID('dbo.AUTED'), 'IDAUTED', 'IsIdentity'), 0)
    SET @IDAUTE = NULL
    DECLARE @T_AUTE_ID VARCHAR(30), @T_AUTED_ID VARCHAR(30), @T_AUTED_PK VARCHAR(30), @T_AUTED_CANT VARCHAR(30)
    DECLARE @ID_AUTE_CUR BIGINT, @ID_AUTED_CUR BIGINT, @TECHO_SM INT, @N_DET INT

    SELECT @T_AUTE_ID = t.name
    FROM sys.columns c
    INNER JOIN sys.types t ON t.user_type_id = c.user_type_id
    WHERE c.object_id = OBJECT_ID('dbo.AUTE') AND c.name = 'IDAUTE'

    SELECT @T_AUTED_ID = t.name
    FROM sys.columns c
    INNER JOIN sys.types t ON t.user_type_id = c.user_type_id
    WHERE c.object_id = OBJECT_ID('dbo.AUTED') AND c.name = 'IDAUTE'

    SELECT @T_AUTED_PK = t.name
    FROM sys.columns c
    INNER JOIN sys.types t ON t.user_type_id = c.user_type_id
    WHERE c.object_id = OBJECT_ID('dbo.AUTED') AND c.name = 'IDAUTED'

    SELECT @T_AUTED_CANT = t.name
