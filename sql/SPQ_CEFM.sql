    INNER JOIN sys.types t ON t.user_type_id = c.user_type_id
    WHERE c.object_id = OBJECT_ID('dbo.AUTED') AND c.name = 'CANTIDAD'

    SELECT @N_DET = COUNT(*) FROM #LINEAS
    SET @TECHO_SM = 32767
    IF @ES_IDENT_AUTE = 1
      SET @ID_AUTE_CUR = CAST(IDENT_CURRENT('dbo.AUTE') AS BIGINT)
    IF @ES_IDENT_AUTED = 1
      SET @ID_AUTED_CUR = CAST(IDENT_CURRENT('dbo.AUTED') AS BIGINT)

    IF @ES_IDENT_AUTE = 1 AND @T_AUTE_ID IN ('tinyint', 'smallint')
       AND COALESCE(@ID_AUTE_CUR, 0) + @N > CASE WHEN @T_AUTE_ID = 'tinyint' THEN 255 ELSE @TECHO_SM END
    BEGIN
