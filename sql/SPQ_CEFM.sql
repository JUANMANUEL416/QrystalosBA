        IF @I = 1
        BEGIN
          SET @IDAUTE = @IDAUTE_I
          IF @ES_IDENT_AUTED = 1
          BEGIN
            INSERT INTO AUTED (IDAUTE, IDSERVICIO, CANTIDAD, ESTADO, COMENTARIOS)
            SELECT
              @IDAUTE_I, L.IDSERVICIO,
              CASE
                WHEN @TIENE_POSO = 0 OR COALESCE(L.FREQ_H, 0) <= 0 OR COALESCE(L.N_LINEA, 1) <= 1 THEN
                  CASE WHEN COALESCE(L.CANTIDAD_TOTAL, 0) > 0 THEN L.CANTIDAD_TOTAL ELSE L.CANTIDAD END
                ELSE
                  CEILING(L.CANTIDAD * CASE WHEN L.TIPODURACION = 'M' AND L.TIPOFRECUENCIA = 'S' THEN 28.0 ELSE 30.0 END * (24.0 / NULLIF(L.FREQ_H, 0)))
              END,
              'En farmacia', L.COMENTARIOS
            FROM #LINEAS L
          END
          ELSE
          BEGIN
            INSERT INTO AUTED (IDAUTED, IDAUTE, IDSERVICIO, CANTIDAD, ESTADO, COMENTARIOS)
            SELECT
              LEFT(@IDAUTE_I + '-' + CAST(COALESCE(L.NO_ITEM, 1) AS VARCHAR(4)), 20),
              @IDAUTE_I, L.IDSERVICIO,
              CASE
                WHEN @TIENE_POSO = 0 OR COALESCE(L.FREQ_H, 0) <= 0 OR COALESCE(L.N_LINEA, 1) <= 1 THEN
                  CASE WHEN COALESCE(L.CANTIDAD_TOTAL, 0) > 0 THEN L.CANTIDAD_TOTAL ELSE L.CANTIDAD END
                ELSE
                  CEILING(L.CANTIDAD * CASE WHEN L.TIPODURACION = 'M' AND L.TIPOFRECUENCIA = 'S' THEN 28.0 ELSE 30.0 END * (24.0 / NULLIF(L.FREQ_H, 0)))
              END,
              'En farmacia', L.COMENTARIOS
            FROM #LINEAS L
          END

          IF COL_LENGTH('dbo.AUTED', 'NO_ITEM_CEFMD') IS NOT NULL
            EXEC sp_executesql N'
              UPDATE AD SET NO_ITEM_CEFMD = L.NO_ITEM
              FROM AUTED AD
              INNER JOIN #LINEAS L ON L.IDSERVICIO = AD.IDSERVICIO
              WHERE AD.IDAUTE = @I',
              N'@I VARCHAR(20)', @IDAUTE_I
        END
        ELSE IF @TIENE_POSO = 1
        BEGIN
          IF @ES_IDENT_AUTED = 1
          BEGIN
            INSERT INTO AUTED (IDAUTE, IDSERVICIO, CANTIDAD, ESTADO, COMENTARIOS)
            SELECT
              @IDAUTE_I, L.IDSERVICIO,
              CASE
                WHEN @I = L.N_LINEA THEN
                  CASE WHEN COALESCE(L.CANTIDAD_TOTAL, 0) > 0 THEN L.CANTIDAD_TOTAL ELSE L.CANTIDAD END - (
                    CASE WHEN L.N_LINEA > 1
                      THEN (L.N_LINEA - 1) * CEILING(L.CANTIDAD * CASE WHEN L.TIPODURACION = 'M' AND L.TIPOFRECUENCIA = 'S' THEN 28.0 ELSE 30.0 END * (24.0 / NULLIF(L.FREQ_H, 0)))
                      ELSE 0
                    END
                  )
                ELSE CEILING(L.CANTIDAD * CASE WHEN L.TIPODURACION = 'M' AND L.TIPOFRECUENCIA = 'S' THEN 28.0 ELSE 30.0 END * (24.0 / NULLIF(L.FREQ_H, 0)))
              END,
              'Pendiente', L.COMENTARIOS
            FROM #LINEAS L
            WHERE L.N_LINEA >= @I AND L.FREQ_H > 0
          END
          ELSE
          BEGIN
            INSERT INTO AUTED (IDAUTED, IDAUTE, IDSERVICIO, CANTIDAD, ESTADO, COMENTARIOS)
            SELECT
              LEFT(@IDAUTE_I + '-' + CAST(COALESCE(L.NO_ITEM, 1) AS VARCHAR(4)), 20),
              @IDAUTE_I, L.IDSERVICIO,
              CASE
                WHEN @I = L.N_LINEA THEN
                  CASE WHEN COALESCE(L.CANTIDAD_TOTAL, 0) > 0 THEN L.CANTIDAD_TOTAL ELSE L.CANTIDAD END - (
                    CASE WHEN L.N_LINEA > 1
                      THEN (L.N_LINEA - 1) * CEILING(L.CANTIDAD * CASE WHEN L.TIPODURACION = 'M' AND L.TIPOFRECUENCIA = 'S' THEN 28.0 ELSE 30.0 END * (24.0 / NULLIF(L.FREQ_H, 0)))
                      ELSE 0
                    END
