      SELECT 'Solo se envían a farmacia periodos en estado Pendiente.' ERROR
      RETURN
    END

    IF NOT EXISTS (SELECT 1 FROM AUTED WITH (NOLOCK) WHERE IDAUTE = @IDAUTE AND COALESCE(ESTADO, 'Pendiente') = 'Pendiente')
    BEGIN
      SELECT 'KO' OK
      SELECT 'No hay medicamentos pendientes en este periodo.' ERROR
      RETURN
    END

    DECLARE @CNSCEFM_A VARCHAR(20), @PERIODO VARCHAR(10), @NUM_PER INT, @DEN_PER INT
    SELECT
      @CNSCEFM_A = CNSCEFM,
      @IDAFILIADO = IDAFILIADO,
      @IDSEDE = IDSEDE,
      @PERIODO = PERIODO
