          VALUES (
            @IDAUTE_I, @IDAF, NULL,
            CAST(@I AS VARCHAR(4)) + '/' + CAST(@N AS VARCHAR(4)),
            DATEADD(MONTH, @I - 1, @FECHA_BASE), GETDATE(), @ESTADO_I, @IDS, @IDAUT_I
          )
        END

        IF COL_LENGTH('dbo.AUTE', 'CNSCEFM') IS NOT NULL
          EXEC sp_executesql N'UPDATE AUTE SET CNSCEFM = @C WHERE IDAUTE = @I',
