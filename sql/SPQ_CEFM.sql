      X.IDSERVICIO,
      X.DESCSERVICIO,
      X.EXISTENCIA
    FROM (
      SELECT
        COALESCE(NULLIF(RTRIM(IART.IDSERVICIO), ''), SER_ART.IDSERVICIO) AS IDSERVICIO,
        MAX(COALESCE(SER_PAPA.DESCSERVICIO, SER_ART.DESCSERVICIO, IART.DESCRIPCION)) AS DESCSERVICIO,
        SUM(IEXI.EXISLOTE) AS EXISTENCIA
      FROM IEXI WITH (NOLOCK)
      INNER JOIN IART WITH (NOLOCK) ON IART.IDARTICULO = IEXI.IDARTICULO
      INNER JOIN ESP E WITH (NOLOCK)
        ON E.IDSERVICIO = IART.IDARTICULO
       AND E.IDPROVEEDOR = @BOD_TER
       AND E.IDPLAN = @BOD_PLAN_ESP
       AND E.TIPORESTRICCION = 'Valor'
       AND E.FECHAINI <= CONVERT(DATE, GETDATE())
       AND E.FECHAFIN >= CONVERT(DATE, GETDATE())
       AND COALESCE(E.VALOR, 0) > 0
      OUTER APPLY (
        SELECT TOP 1 S.IDSERVICIO, S.DESCSERVICIO
        FROM SER S WITH (NOLOCK)
        WHERE S.IDARTICULO = IART.IDARTICULO
          AND S.ESTADO = 'Activo'
        ORDER BY CASE WHEN S.IDSERVICIO = IART.IDSERVICIO THEN 0 ELSE 1 END, S.IDSERVICIO
