      SELECT 'Solo aplica a Nueva dispensación (solicitud manual). Las de transcripción o Autorizador no se deshacen aquí.' ERROR
      RETURN
    END

    IF EXISTS (
      SELECT 1 FROM IMOV WITH (NOLOCK)
      WHERE NODOCUMENTO = @CNSIZSOL_DM
        AND COALESCE(TRY_CONVERT(SMALLINT, ESTADO), 0) = 1
    )
    BEGIN
      SELECT 'KO' OK
      SELECT 'El movimiento ya está confirmado. No se puede deshacer la dispensación.' ERROR
      RETURN
    END

