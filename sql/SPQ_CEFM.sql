    DECLARE @IDAUT_DM VARCHAR(20)
    DECLARE @CNSCEFM_DM VARCHAR(20)
    DECLARE @ESTADO_IZ_DM SMALLINT
    DECLARE @CLASE_DM VARCHAR(20)
    DECLARE @CAB_DM TABLE (
      IDAFILIADO VARCHAR(20),
      DOCIDAFILIADO VARCHAR(20),
      NOMBREAFI VARCHAR(200),
      IDTERCEROCA VARCHAR(20),
      IDPLAN VARCHAR(6),
      FECHA_FORMULA VARCHAR(10),
      FECHAVENCE VARCHAR(10),
