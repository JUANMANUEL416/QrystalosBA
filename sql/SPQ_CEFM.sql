    LEFT JOIN IART WITH (NOLOCK) ON IART.IDARTICULO = D.IDARTICULO
    WHERE D.CNSIZSOL = @CNSIZSOL_DM
      AND COALESCE(NULLIF(LTRIM(RTRIM(D.IDARTICULO)), ''), '') <> ''
    GROUP BY D.IDARTICULO
    HAVING SUM(COALESCE(D.CANTIDADSOL, 0)) > 0

    BEGIN TRY
      BEGIN TRAN

      IF OBJECT_ID('dbo.ISAL', 'U') IS NOT NULL
      BEGIN
        DELETE S
        FROM ISAL S
        INNER JOIN IMOV M ON M.CNSMOV = S.CNSMOV
        WHERE M.NODOCUMENTO = @CNSIZSOL_DM
          AND COALESCE(TRY_CONVERT(SMALLINT, M.ESTADO), 0) = 0
      END

      DELETE T
      FROM IZSOLDT T
      INNER JOIN IZSOLD D ON T.CNSIZSOLD = D.CNSIZSOLD OR T.CNSIZSOLD = D.NEWCNSIZOLD
      WHERE D.CNSIZSOL = @CNSIZSOL_DM

      DELETE H
      FROM IMOVH H
      INNER JOIN IMOV M ON M.CNSMOV = H.CNSMOV
      WHERE M.NODOCUMENTO = @CNSIZSOL_DM
        AND COALESCE(TRY_CONVERT(SMALLINT, M.ESTADO), 0) = 0

      DELETE FROM IMOV
      WHERE NODOCUMENTO = @CNSIZSOL_DM
        AND COALESCE(TRY_CONVERT(SMALLINT, ESTADO), 0) = 0

      IF OBJECT_ID('dbo.IZSOLNOT', 'U') IS NOT NULL
        DELETE FROM IZSOLNOT WHERE CNSIZSOL = @CNSIZSOL_DM

      DELETE FROM IZSOLD WHERE CNSIZSOL = @CNSIZSOL_DM
      DELETE FROM IZSOL WHERE CNSIZSOL = @CNSIZSOL_DM

      UPDATE AUT
      SET PEDIDOINV = 0,
          CNSMOV = NULL
      WHERE IDAUT = @IDAUT_DM

      IF COALESCE(@CNSCEFM_DM, '') <> ''
      BEGIN
        DELETE FROM AUTED
        WHERE IDAUTE IN (SELECT IDAUTE FROM AUTE WHERE CNSCEFM = @CNSCEFM_DM)

        DELETE FROM AUTE WHERE CNSCEFM = @CNSCEFM_DM
      END
      ELSE
      BEGIN
        DELETE FROM AUTED
        WHERE IDAUTE IN (SELECT IDAUTE FROM AUTE WHERE IDAUT = @IDAUT_DM)
        DELETE FROM AUTE WHERE IDAUT = @IDAUT_DM
      END

      DELETE FROM AUTD WHERE IDAUT = @IDAUT_DM
      DELETE FROM AUT WHERE IDAUT = @IDAUT_DM

      IF COALESCE(@CNSCEFM_DM, '') <> ''
        UPDATE CEFM
        SET ESTADO = 'ANULADO',
            USUARIOMOD = @USUARIO,
            FECHAMOD = GETDATE()
        WHERE CNSCEFM = @CNSCEFM_DM
          AND ESTADO = 'AUDITADO'

      COMMIT TRAN
    END TRY
    BEGIN CATCH
      IF @@TRANCOUNT > 0 ROLLBACK TRAN
      SELECT 'KO' OK
      SELECT 'No se pudo deshacer la dispensación: ' + ERROR_MESSAGE() ERROR
      RETURN
    END CATCH

    SELECT 'OK' OK, @CNSIZSOL_DM AS CNSIZSOL, @CNSCEFM_DM AS CNSCEFM,
           'Se deshizo la dispensación. Corrija y vuelva a dispensar: los lotes hay que elegirlos de nuevo.' AS MENSAJE
    SELECT * FROM @CAB_DM
    SELECT IDARTICULO, IDSERVICIO, DESCRIPCION, CANTIDAD FROM @DET_DM
    RETURN
  END

