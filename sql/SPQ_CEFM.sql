    RETURN
  END

  /* -- CNS_SER_NOTA_TECNICA: papá del SKU configurado en ESP del plan (sin stock) -- */
  IF @METODO = 'CNS_SER_NOTA_TECNICA'
  BEGIN
    DECLARE @NT_PLAN VARCHAR(20) = NULLIF(JSON_VALUE(@PARAMETROS, '$.IDPLAN'), '')
    DECLARE @NT_TER VARCHAR(20) = COALESCE(NULLIF(JSON_VALUE(@PARAMETROS, '$.IDTERCERO'), ''), '0100000011')
    DECLARE @NT_PLAN_ESP VARCHAR(20) = DBO.FNK_CEFM_PLAN_ESP(@NT_PLAN)

    IF @NT_PLAN_ESP IS NULL
    BEGIN
      SELECT 'OK' OK, CAST(NULL AS VARCHAR(20)) AS PLAN_ESP
      SELECT
        CAST(NULL AS VARCHAR(20)) AS value,
        CAST(NULL AS VARCHAR(255)) AS label,
        CAST(NULL AS VARCHAR(20)) AS IDSERVICIO,
        CAST(NULL AS VARCHAR(255)) AS DESCSERVICIO
      WHERE 1 = 0
      RETURN
    END

    SELECT 'OK' OK, @NT_PLAN_ESP AS PLAN_ESP
    SELECT
      X.IDSERVICIO AS value,
      X.DESCSERVICIO AS label,
      X.IDSERVICIO,
      X.DESCSERVICIO
    FROM (
      SELECT
        COALESCE(NULLIF(RTRIM(IART.IDSERVICIO), ''), SER_ART.IDSERVICIO, SER_DIR.IDSERVICIO) AS IDSERVICIO,
        MAX(COALESCE(SER_PAPA.DESCSERVICIO, SER_ART.DESCSERVICIO, SER_DIR.DESCSERVICIO, IART.DESCRIPCION)) AS DESCSERVICIO
      FROM ESP E WITH (NOLOCK)
      LEFT JOIN IART WITH (NOLOCK) ON IART.IDARTICULO = E.IDSERVICIO
      OUTER APPLY (
        SELECT TOP 1 S.IDSERVICIO, S.DESCSERVICIO
        FROM SER S WITH (NOLOCK)
        WHERE S.IDARTICULO = E.IDSERVICIO
          AND S.ESTADO = 'Activo'
        ORDER BY CASE WHEN S.IDSERVICIO = IART.IDSERVICIO THEN 0 ELSE 1 END, S.IDSERVICIO
      ) SER_ART
      LEFT JOIN SER SER_DIR WITH (NOLOCK)
        ON SER_DIR.IDSERVICIO = E.IDSERVICIO
       AND SER_DIR.ESTADO = 'Activo'
      LEFT JOIN SER SER_PAPA WITH (NOLOCK)
        ON SER_PAPA.IDSERVICIO = COALESCE(NULLIF(RTRIM(IART.IDSERVICIO), ''), SER_ART.IDSERVICIO, SER_DIR.IDSERVICIO)
      WHERE E.IDPROVEEDOR = @NT_TER
        AND E.IDPLAN = @NT_PLAN_ESP
        AND E.TIPORESTRICCION = 'Valor'
        AND E.FECHAINI <= CONVERT(DATE, GETDATE())
        AND E.FECHAFIN >= CONVERT(DATE, GETDATE())
        AND COALESCE(E.VALOR, 0) > 0
        AND @NT_PLAN_ESP IN ('CSRC26', 'CSRS26')
      GROUP BY COALESCE(NULLIF(RTRIM(IART.IDSERVICIO), ''), SER_ART.IDSERVICIO, SER_DIR.IDSERVICIO)
    ) X
    WHERE COALESCE(X.IDSERVICIO, '') <> ''
      AND EXISTS (
        SELECT 1 FROM SER S WITH (NOLOCK)
        WHERE S.IDSERVICIO = X.IDSERVICIO AND S.ESTADO = 'Activo'
      )
    ORDER BY X.DESCSERVICIO, X.IDSERVICIO
    RETURN
  END

  IF @METODO IN ('INFORME_CLIENTE', 'INFORME_FALTANTE')
  BEGIN
    IF OBJECT_ID('dbo.SPQ_CEFM_INFORMES', 'P') IS NULL
    BEGIN
      SELECT 'KO' OK
      SELECT 'Falta desplegar SPQ_CEFM_INFORMES.sql' ERROR
      RETURN
    END
    EXEC DBO.SPQ_CEFM_INFORMES @JSON
    RETURN
  END

  SELECT 'KO' OK
  SELECT 'Método no soportado: ' + COALESCE(@METODO, '') ERROR
END
