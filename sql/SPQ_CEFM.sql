    END

    IF @ES_IDENT_AUTED = 1 AND @T_AUTED_PK IN ('tinyint', 'smallint')
       AND COALESCE(@ID_AUTED_CUR, 0) + (@N * COALESCE(@N_DET, 1)) > CASE WHEN @T_AUTED_PK = 'tinyint' THEN 255 ELSE @TECHO_SM END
    BEGIN
      SELECT 'KO' OK
      SELECT 'No se pudieron crear los periodos AUTE: se agotó AUTED.IDAUTED ('
        + @T_AUTED_PK + ' identity=' + CAST(@ID_AUTED_CUR AS VARCHAR(20))
        + '). Hay que ALTER la columna a INT.' ERROR
      RETURN
    END

    IF @ES_IDENT_AUTE = 1 AND @T_AUTED_ID IN ('tinyint', 'smallint')
       AND COALESCE(@ID_AUTE_CUR, 0) + @N > CASE WHEN @T_AUTED_ID = 'tinyint' THEN 255 ELSE @TECHO_SM END
    BEGIN
      SELECT 'KO' OK
      SELECT 'No se pudieron crear los periodos AUTE: AUTED.IDAUTE es '
        + @T_AUTED_ID + ' y no cabe el identity de AUTE ('
        + CAST(@ID_AUTE_CUR AS VARCHAR(20))
        + '). Hay que ALTER AUTED.IDAUTE a INT.' ERROR
      RETURN
    END

    IF @T_AUTED_CANT IN ('tinyint', 'smallint')
       AND EXISTS (
         SELECT 1 FROM #LINEAS L
         WHERE COALESCE(
           CASE
             WHEN COALESCE(L.FREQ_H, 0) > 0
             THEN CEILING(L.CANTIDAD * CASE WHEN L.TIPODURACION = 'M' AND L.TIPOFRECUENCIA = 'S' THEN 28.0 ELSE 30.0 END * (24.0 / NULLIF(L.FREQ_H, 0)))
           END,
           L.CANTIDAD_TOTAL,
           L.CANTIDAD
         ) > CASE WHEN @T_AUTED_CANT = 'tinyint' THEN 255 ELSE @TECHO_SM END
       )
    BEGIN
      SELECT 'KO' OK
      SELECT 'No se pudieron crear los periodos AUTE: AUTED.CANTIDAD es '
        + @T_AUTED_CANT + ' y la cantidad del periodo supera el máximo. Revise posología (dosis × 30 días × 24 / frecuencia).' ERROR
      RETURN
    END

    IF @ES_IDENT_AUTE = 0 AND LEN(@CNSCEFM) + 1 + LEN(CAST(@N AS VARCHAR(4))) > 20
    BEGIN
      SELECT 'KO' OK
      SELECT 'CNSCEFM demasiado largo para generar IDAUTE (' + @CNSCEFM + ').' ERROR
      RETURN
    END

    BEGIN TRY
      SET @I = 1
      WHILE @I <= @N
      BEGIN
