            DATEADD(MONTH, @I - 1, @FECHA_BASE), GETDATE(), @ESTADO_I, @IDS, @IDAUT_I
          )
          SET @IDAUTE_I = CAST(SCOPE_IDENTITY() AS VARCHAR(20))
        END
        ELSE
        BEGIN
