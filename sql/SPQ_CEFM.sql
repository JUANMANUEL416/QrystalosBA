  IF @METODO = 'TRAER_DE_AUTE'
  BEGIN
    SELECT
      @IDAUTE  = JSON_VALUE(@PARAMETROS, '$.IDAUTE'),
      @IDBODEGA = JSON_VALUE(@PARAMETROS, '$.IDBODEGA')

    IF NOT EXISTS (SELECT 1 FROM AUTE WITH (NOLOCK) WHERE IDAUTE = @IDAUTE AND ESTADO = 'Pendiente')
    BEGIN
