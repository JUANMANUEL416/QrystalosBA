        SET @ESTADO_I = CASE WHEN @I = 1 THEN 'En farmacia' ELSE 'Pendiente' END
        SET @IDAUT_I  = NULL

        IF @ES_IDENT_AUTE = 0 AND EXISTS (SELECT 1 FROM AUTE WITH (NOLOCK) WHERE IDAUTE = @IDAUTE_I)
          RAISERROR('Ya existe un AUTE con el ID generado para este periodo.', 16, 1)

        IF @ES_IDENT_AUTE = 1
        BEGIN
