      SET @PREF_A = NULLIF(LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('PREFIJOMEDICAMENTOS'))), '')

    /* CCOSTO / área: equipo del usuario (UBEQ), luego JSON/sesión, nunca la bodega. */
    SELECT @CCOSTO = UBEQ.CCOSTO, @IDAREA = UBEQ.IDAREA
