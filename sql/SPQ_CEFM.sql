  /* -- REABRIR: deshace pedido de la transcripción y vuelve CEFM a INGRESADO -- */
  IF @METODO IN ('REABRIR', 'DESHACER_AUDITORIA')
  BEGIN
    SELECT @CNSCEFM = JSON_VALUE(@PARAMETROS, '$.CNSCEFM')

    IF COALESCE(@CNSCEFM, '') = ''
    BEGIN
      SELECT 'KO' OK
      SELECT 'Debe indicar la fórmula (CNSCEFM).' ERROR
      RETURN
    END

    IF NOT EXISTS (SELECT 1 FROM CEFM WITH (NOLOCK) WHERE CNSCEFM = @CNSCEFM AND ESTADO = 'AUDITADO')
    BEGIN
      SELECT 'KO' OK
      SELECT 'Solo se puede reabrir una fórmula Auditada.' ERROR
      RETURN
    END

    IF EXISTS (
      SELECT 1 FROM AUTE WITH (NOLOCK)
      WHERE CNSCEFM = @CNSCEFM
        AND COALESCE(ESTADO, 'Pendiente') IN ('Dispensado', 'Dispensacion')
    )
    BEGIN
      SELECT 'KO' OK
      SELECT 'No se puede reabrir: hay un periodo ya dispensado.' ERROR
      RETURN
    END

    IF EXISTS (
      SELECT 1 FROM AUTE WITH (NOLOCK)
      WHERE CNSCEFM = @CNSCEFM
        AND TRY_CAST(LEFT(PERIODO, CHARINDEX('/', PERIODO + '/') - 1) AS INT) > 1
        AND COALESCE(ESTADO, 'Pendiente') NOT IN ('Pendiente')
    )
    BEGIN
      SELECT 'KO' OK
      SELECT 'No se puede reabrir: hay periodos posteriores ya enviados a farmacia (Traer de).' ERROR
      RETURN
    END

    DECLARE @AUTS TABLE (IDAUT VARCHAR(20) PRIMARY KEY)
    DECLARE @SOLS TABLE (CNSIZSOL VARCHAR(20) PRIMARY KEY)
    DECLARE @CNSIZSOL_R VARCHAR(20), @ESTADO_IZSOL_R SMALLINT

    INSERT INTO @AUTS (IDAUT)
    SELECT DISTINCT NULLIF(IDAUT, '')
    FROM CEFM WITH (NOLOCK)
    WHERE CNSCEFM = @CNSCEFM
      AND COALESCE(IDAUT, '') <> ''

    INSERT INTO @AUTS (IDAUT)
    SELECT DISTINCT NULLIF(IDAUT, '')
    FROM AUTE WITH (NOLOCK)
    WHERE CNSCEFM = @CNSCEFM
      AND COALESCE(IDAUT, '') <> ''
      AND NOT EXISTS (SELECT 1 FROM @AUTS T WHERE T.IDAUT = AUTE.IDAUT)

    INSERT INTO @SOLS (CNSIZSOL)
    SELECT DISTINCT NULLIF(LTRIM(RTRIM(A.CNSMOV)), '')
    FROM AUT A WITH (NOLOCK)
    INNER JOIN @AUTS T ON T.IDAUT = A.IDAUT
    WHERE COALESCE(A.CNSMOV, '') <> ''

    INSERT INTO @SOLS (CNSIZSOL)
    SELECT DISTINCT NULLIF(LTRIM(RTRIM(Z.CNSIZSOL)), '')
    FROM IZSOL Z WITH (NOLOCK)
    INNER JOIN @AUTS T ON T.IDAUT = Z.NOADMISION
    WHERE COALESCE(Z.CNSIZSOL, '') <> ''
      AND NOT EXISTS (SELECT 1 FROM @SOLS S WHERE S.CNSIZSOL = Z.CNSIZSOL)

    IF COL_LENGTH('dbo.AUTE', 'CNSIZSOL') IS NOT NULL
    BEGIN
      IF OBJECT_ID('tempdb..#CEFMSOL') IS NOT NULL DROP TABLE #CEFMSOL
      CREATE TABLE #CEFMSOL (CNSIZSOL VARCHAR(20) PRIMARY KEY)
      EXEC sp_executesql N'
        INSERT INTO #CEFMSOL (CNSIZSOL)
        SELECT DISTINCT NULLIF(LTRIM(RTRIM(CNSIZSOL)), '''')
        FROM AUTE WITH (NOLOCK)
        WHERE CNSCEFM = @C
          AND COALESCE(CNSIZSOL, '''') <> ''''',
        N'@C VARCHAR(20)', @CNSCEFM
      INSERT INTO @SOLS (CNSIZSOL)
      SELECT CNSIZSOL FROM #CEFMSOL X
      WHERE NOT EXISTS (SELECT 1 FROM @SOLS S WHERE S.CNSIZSOL = X.CNSIZSOL)
    END

    SET @CNSIZSOL_R = NULL
    WHILE EXISTS (SELECT 1 FROM @SOLS WHERE CNSIZSOL > COALESCE(@CNSIZSOL_R, ''))
    BEGIN
      SELECT TOP 1 @CNSIZSOL_R = CNSIZSOL
      FROM @SOLS
      WHERE CNSIZSOL > COALESCE(@CNSIZSOL_R, '')
      ORDER BY CNSIZSOL

      IF NOT EXISTS (SELECT 1 FROM IZSOL WITH (NOLOCK) WHERE CNSIZSOL = @CNSIZSOL_R)
        CONTINUE

      SELECT @ESTADO_IZSOL_R = COALESCE(TRY_CONVERT(SMALLINT, ESTADO), 0)
      FROM IZSOL WITH (NOLOCK)
      WHERE CNSIZSOL = @CNSIZSOL_R

      IF @ESTADO_IZSOL_R = 2
      BEGIN
        SELECT 'KO' OK
        SELECT 'No se puede reabrir: la solicitud de farmacia ' + @CNSIZSOL_R + ' está cerrada.' ERROR
        RETURN
      END

      IF EXISTS (
        SELECT 1 FROM IMOV WITH (NOLOCK)
        WHERE NODOCUMENTO = @CNSIZSOL_R
          AND COALESCE(TRY_CONVERT(SMALLINT, ESTADO), 0) = 1
      )
      BEGIN
        SELECT 'KO' OK
        SELECT 'No se puede reabrir: la solicitud ya tiene dispensación confirmada.' ERROR
        RETURN
      END

      IF @ESTADO_IZSOL_R > 0
      BEGIN
        IF EXISTS (
          SELECT 1
          FROM IZSOLDT T WITH (NOLOCK)
          INNER JOIN IZSOLD D WITH (NOLOCK) ON T.CNSIZSOLD = D.CNSIZSOLD OR T.CNSIZSOLD = D.NEWCNSIZOLD
          LEFT JOIN IMOV M WITH (NOLOCK) ON M.CNSMOV = T.CNSMOV
          WHERE D.CNSIZSOL = @CNSIZSOL_R
            AND (
              NULLIF(LTRIM(RTRIM(T.NOLOTE)), '') IS NOT NULL
              OR NULLIF(LTRIM(RTRIM(T.CNSMOV)), '') IS NOT NULL
            )
            AND COALESCE(TRY_CONVERT(SMALLINT, M.ESTADO), 0) <> 2
        )
        BEGIN
          SELECT 'KO' OK
          SELECT 'No se puede reabrir: hay artículos procesados pendientes de confirmar.' ERROR
          RETURN
        END
      END
    END

    BEGIN TRY
      BEGIN TRAN

      SET @CNSIZSOL_R = NULL
      WHILE EXISTS (SELECT 1 FROM @SOLS WHERE CNSIZSOL > COALESCE(@CNSIZSOL_R, ''))
      BEGIN
        SELECT TOP 1 @CNSIZSOL_R = CNSIZSOL
        FROM @SOLS
        WHERE CNSIZSOL > COALESCE(@CNSIZSOL_R, '')
        ORDER BY CNSIZSOL

        IF NOT EXISTS (SELECT 1 FROM IZSOL WITH (NOLOCK) WHERE CNSIZSOL = @CNSIZSOL_R)
          CONTINUE

        IF OBJECT_ID('dbo.ISAL', 'U') IS NOT NULL
        BEGIN
          DELETE S
          FROM ISAL S
          INNER JOIN IMOV M ON M.CNSMOV = S.CNSMOV
          WHERE M.NODOCUMENTO = @CNSIZSOL_R
            AND COALESCE(TRY_CONVERT(SMALLINT, M.ESTADO), 0) = 0
        END

        DELETE T
        FROM IZSOLDT T
        INNER JOIN IZSOLD D ON T.CNSIZSOLD = D.CNSIZSOLD OR T.CNSIZSOLD = D.NEWCNSIZOLD
        WHERE D.CNSIZSOL = @CNSIZSOL_R

        DELETE H
        FROM IMOVH H
        INNER JOIN IMOV M ON M.CNSMOV = H.CNSMOV
        WHERE M.NODOCUMENTO = @CNSIZSOL_R
          AND COALESCE(TRY_CONVERT(SMALLINT, M.ESTADO), 0) = 0

        DELETE FROM IMOV
        WHERE NODOCUMENTO = @CNSIZSOL_R
          AND COALESCE(TRY_CONVERT(SMALLINT, ESTADO), 0) = 0

        IF EXISTS (
          SELECT 1
          FROM AUT A WITH (NOLOCK)
          INNER JOIN CEFM C WITH (NOLOCK) ON C.IDAUT = A.IDAUT
          WHERE NULLIF(A.CNSMOV, '') = @CNSIZSOL_R
            AND C.CNSCEFM <> @CNSCEFM
            AND C.ESTADO = 'AUDITADO'
        )
        BEGIN
          UPDATE IZSOL
          SET NOADMISION = (
            SELECT TOP 1 C.IDAUT
            FROM AUT A WITH (NOLOCK)
            INNER JOIN CEFM C WITH (NOLOCK) ON C.IDAUT = A.IDAUT
            WHERE NULLIF(A.CNSMOV, '') = @CNSIZSOL_R
              AND C.CNSCEFM <> @CNSCEFM
              AND C.ESTADO = 'AUDITADO'
              AND C.IDAUT NOT IN (SELECT IDAUT FROM @AUTS)
          )
          WHERE CNSIZSOL = @CNSIZSOL_R
            AND NOADMISION IN (SELECT IDAUT FROM @AUTS)

          UPDATE D
          SET CANTIDADSOL = CASE WHEN COALESCE(D.CANTIDADSOL, 0) > X.CANT THEN D.CANTIDADSOL - X.CANT ELSE 0 END
          FROM IZSOLD D
          INNER JOIN (
            SELECT
              COALESCE(NULLIF(AD.IDARTICULO, ''), SER.IDARTICULO, AD.IDSERVICIO) AS IDART,
              AD.IDSERVICIO,
              SUM(AD.CANTIDAD) AS CANT
            FROM AUTD AD
            INNER JOIN @AUTS T ON T.IDAUT = AD.IDAUT
            LEFT JOIN SER WITH (NOLOCK) ON SER.IDSERVICIO = AD.IDSERVICIO
            GROUP BY COALESCE(NULLIF(AD.IDARTICULO, ''), SER.IDARTICULO, AD.IDSERVICIO), AD.IDSERVICIO
          ) X ON (D.IDARTICULO = X.IDART OR D.IDSERVICIO = X.IDSERVICIO)
          WHERE D.CNSIZSOL = @CNSIZSOL_R

          DELETE FROM IZSOLD
          WHERE CNSIZSOL = @CNSIZSOL_R
            AND COALESCE(CANTIDADSOL, 0) <= 0
        END
        ELSE
        BEGIN
          DELETE FROM IZSOLD WHERE CNSIZSOL = @CNSIZSOL_R
          DELETE FROM IZSOL WHERE CNSIZSOL = @CNSIZSOL_R
        END
      END

      UPDATE AUT
      SET PEDIDOINV = 0,
          CNSMOV = NULL
      WHERE IDAUT IN (SELECT IDAUT FROM @AUTS)

      DELETE FROM AUTED
      WHERE IDAUTE IN (SELECT IDAUTE FROM AUTE WHERE CNSCEFM = @CNSCEFM)

      DELETE FROM AUTE WHERE CNSCEFM = @CNSCEFM

      DELETE FROM AUTD WHERE IDAUT IN (SELECT IDAUT FROM @AUTS)
      DELETE FROM AUT WHERE IDAUT IN (SELECT IDAUT FROM @AUTS)

      UPDATE CEFM
      SET ESTADO = 'INGRESADO',
          OBSERVACION_AUD = NULL,
          USUARIOAUD = NULL,
          FECHAAUD = NULL,
          IDAUT = NULL,
          USUARIOMOD = @USUARIO,
          FECHAMOD = GETDATE()
      WHERE CNSCEFM = @CNSCEFM

      COMMIT TRAN
    END TRY
    BEGIN CATCH
      IF @@TRANCOUNT > 0 ROLLBACK TRAN
      SELECT 'KO' OK
      SELECT 'No se pudo reabrir la transcripción: ' + ERROR_MESSAGE() ERROR
      RETURN
    END CATCH

    SELECT 'OK' OK, @CNSCEFM AS CNSCEFM, 'Se eliminó el pedido a farmacia. La fórmula quedó Ingresada para corregir y volver a guardar.' AS MENSAJE
    RETURN
  END

