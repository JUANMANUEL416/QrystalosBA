      IF ERROR_NUMBER() IN (220, 245, 8115) AND (@EM_AUTE LIKE '%smallint%' OR @EM_AUTE LIKE '%tinyint%')
        SET @EM_AUTE = @EM_AUTE
          + ' Suele ser identity smallint agotado (AUTE.IDAUTE / AUTED.IDAUTED / AUTED.IDAUTE) o AUTED.CANTIDAD smallint. Ejecute sql/CEFM_DIAG_AUTE_SMALLINT.sql.'
      SELECT 'KO' OK
      SELECT 'No se pudieron crear los periodos AUTE: ' + @EM_AUTE ERROR
