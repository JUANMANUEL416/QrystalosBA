            EXEC sp_executesql N'
              UPDATE AD SET NO_ITEM_CEFMD = L.NO_ITEM
              FROM AUTED AD
              INNER JOIN #LINEAS L ON L.IDSERVICIO = AD.IDSERVICIO
              WHERE AD.IDAUTE = @I AND L.N_LINEA >= @P AND L.FREQ_H > 0',
              N'@I VARCHAR(20), @P INT', @IDAUTE_I, @I
        END

        SET @I = @I + 1
      END
