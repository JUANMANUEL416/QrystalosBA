    /* IZSOL/IZSOLD: cantidad = AUTED del periodo 1 (nunca CANTIDAD_TOTAL de la fórmula).
       NOADMISION = afiliado (AUT aún no existe). */
    SET @CNSIZSOL_FB = NULL
    SET @COMPANIA_IZ = COALESCE(NULLIF(@COMPANIA, ''), '01')
    SET @EXISTS_FB = 1

    BEGIN TRY
      WHILE @EXISTS_FB = 1 OR COALESCE(@CNSIZSOL_FB, '') = ''
      BEGIN
        SET @EXISTS_FB = 0
        SET @CNSIZSOL_FB = NULL
        BEGIN TRY
          EXEC DBO.SPQ_GENSEQUENCE @SEDE = @IDS, @PREFIJO = '@IZSOL', @NVOCONSEC = @CNSIZSOL_FB OUTPUT
        END TRY
        BEGIN CATCH
          SET @CNSIZSOL_FB = NULL
        END CATCH
        IF COALESCE(@CNSIZSOL_FB, '') = ''
        BEGIN
          BEGIN TRY
            EXEC SPK_GENCONSECUTIVO @COMPANIA_IZ, @IDS, '@IZSOL', @CNSIZSOL_FB OUTPUT
          END TRY
          BEGIN CATCH
            SET @CNSIZSOL_FB = NULL
          END CATCH
        END
        IF COALESCE(@CNSIZSOL_FB, '') = ''
          SET @CNSIZSOL_FB = LEFT(@IDS, 2) + RIGHT(CONVERT(VARCHAR(8), GETDATE(), 112), 6) + RIGHT('0000' + CAST(ABS(CHECKSUM(NEWID())) % 10000 AS VARCHAR), 4)
        IF EXISTS (SELECT 1 FROM IZSOL WITH (NOLOCK) WHERE CNSIZSOL = @CNSIZSOL_FB)
          SET @EXISTS_FB = 1
      END

      INSERT INTO IZSOL (
        CNSIZSOL, FECHASOL, USUARIOSOL, ESTADO,
        IDBODEGASOLICITA, IDBODEGAATIENDE, CLASE, NOADMISION,
        SYS_COMPUTER, IDSEDE, IDTERCEROC, IDPLAN
      )
      VALUES (
        @CNSIZSOL_FB,
        CASE WHEN @USA_FECHA_TRANS_AUD = 'SI' AND @FECHATRANS_AUD IS NOT NULL THEN @FECHATRANS_AUD ELSE GETDATE() END,
        @USUARIO, 1,
        @IDBODEGA, @IDBODEGA, 'TRANS_CE', @IDAF,
        @SYSCOMP, @IDS, @IDT, @IDP
      )

      IF COALESCE(@IDAUTE, '') = ''
      BEGIN
        DELETE FROM IZSOL WHERE CNSIZSOL = @CNSIZSOL_FB
        RAISERROR('No hay AUTE periodo 1 para armar IZSOLD.', 16, 1)
      END

      INSERT INTO IZSOLD (CNSIZSOL, IDARTICULO, CANTIDADSOL, ESTADO, CODOM, CANTIDAD, IDSERVICIO, NEWCNSIZOLD)
      SELECT
        @CNSIZSOL_FB,
        COALESCE(SER.IDARTICULO, AD.IDSERVICIO),
        AD.CANTIDAD,
        1, '', 0,
        AD.IDSERVICIO, ''
      FROM AUTED AD WITH (NOLOCK)
      INNER JOIN SER WITH (NOLOCK) ON SER.IDSERVICIO = AD.IDSERVICIO
      WHERE AD.IDAUTE = @IDAUTE
        AND COALESCE(AD.CANTIDAD, 0) > 0
        AND COALESCE(SER.IDARTICULO, AD.IDSERVICIO, '') <> ''

      IF NOT EXISTS (SELECT 1 FROM IZSOLD WITH (NOLOCK) WHERE CNSIZSOL = @CNSIZSOL_FB)
      BEGIN
        DELETE FROM IZSOL WHERE CNSIZSOL = @CNSIZSOL_FB
        RAISERROR('AUTED periodo 1 no produjo renglones de IZSOLD (servicio sin IDARTICULO o cantidad 0).', 16, 1)
      END

      UPDATE IZSOLD SET ESTADO = 1 WHERE CNSIZSOL = @CNSIZSOL_FB
      SET @CNSMOV_PED = @CNSIZSOL_FB
    END TRY
    BEGIN CATCH
      IF COALESCE(@CNSIZSOL_FB, '') <> ''
      BEGIN
        DELETE FROM IZSOLD WHERE CNSIZSOL = @CNSIZSOL_FB
        DELETE FROM IZSOL WHERE CNSIZSOL = @CNSIZSOL_FB
      END
      IF COL_LENGTH('dbo.AUTE', 'CNSCEFM') IS NOT NULL
      BEGIN
        DELETE FROM AUTED WHERE IDAUTE IN (SELECT IDAUTE FROM AUTE WHERE CNSCEFM = @CNSCEFM)
        DELETE FROM AUTE WHERE CNSCEFM = @CNSCEFM
      END
      SELECT 'KO' OK
      SELECT 'No se generó el IZSOL (bodega ' + COALESCE(@IDBODEGA, '') + ', sede ' + COALESCE(@IDS, '') + '): ' + ERROR_MESSAGE() ERROR
      RETURN
    END CATCH

    IF COALESCE(@CNSMOV_PED, '') <> '' AND COALESCE(@IDAUTE, '') <> ''
    BEGIN
      UPDATE AUTE SET ESTADO = 'En farmacia' WHERE IDAUTE = @IDAUTE
      UPDATE AUTED SET ESTADO = 'En farmacia' WHERE IDAUTE = @IDAUTE AND COALESCE(ESTADO, 'Pendiente') IN ('Pendiente', 'En farmacia')
      IF COL_LENGTH('dbo.AUTE', 'CNSIZSOL') IS NOT NULL
        EXEC sp_executesql N'UPDATE AUTE SET CNSIZSOL = @C WHERE IDAUTE = @I',
          N'@C VARCHAR(20), @I VARCHAR(20)', @CNSMOV_PED, @IDAUTE
    END

    IF @USA_FECHA_TRANS_AUD = 'SI' AND @FECHATRANS_AUD IS NOT NULL AND COALESCE(@CNSMOV_PED, '') <> ''
      UPDATE IZSOL SET FECHASOL = @FECHATRANS_AUD WHERE CNSIZSOL = @CNSMOV_PED

    IF COALESCE(@IDBODEGA_FAR, '') <> '' AND COALESCE(@CNSMOV_PED, '') <> ''
      UPDATE IZSOL
      SET IDBODEGAATIENDE = @IDBODEGA_FAR,
          IDBODEGASOLICITA = @IDBODEGA_FAR
      WHERE CNSIZSOL = @CNSMOV_PED

    UPDATE CEFM
    SET ESTADO = 'AUDITADO',
        OBSERVACION_AUD = @OBSERVACION_AUD,
        USUARIOAUD = @USUARIO,
        FECHAAUD = GETDATE(),
        USUARIOMOD = @USUARIO,
        FECHAMOD = GETDATE()
    WHERE CNSCEFM = @CNSCEFM

    /* IDAUT se asigna al confirmar la primera salida */
    IF COL_LENGTH('dbo.CEFM', 'IDAUT') IS NOT NULL
      EXEC sp_executesql N'UPDATE CEFM SET IDAUT = NULL WHERE CNSCEFM = @C',
        N'@C VARCHAR(20)', @CNSCEFM

