CREATE OR ALTER PROCEDURE DBO.SPQ_CEFM
  @JSON NVARCHAR(MAX)
WITH ENCRYPTION
AS
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(12)
DECLARE @A INT
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(500))
DECLARE @CNSCEFM VARCHAR(20), @IDAFILIADO VARCHAR(20), @PROCESO VARCHAR(20)
DECLARE @OBSERVACION_AUD VARCHAR(500), @IDAUTE VARCHAR(20), @IDBODEGA VARCHAR(20)
DECLARE @CEFM NVARCHAR(MAX), @CEFMD NVARCHAR(MAX)
DECLARE @IDSEDE VARCHAR(5), @CCOSTO VARCHAR(20), @IDAREA VARCHAR(20)
DECLARE @PREFIJO VARCHAR(6), @OK VARCHAR(2)
DECLARE @TIPO_IDMED VARCHAR(5), @DOCMEDICO VARCHAR(20), @IDMIPRESS VARCHAR(100), @IDMEDICO_RES VARCHAR(12)
DECLARE @NOPOS BIT
DECLARE @PQR BIT
DECLARE @TIPO_IDMED_A VARCHAR(5), @DOCMEDICO_A VARCHAR(20), @IDMIPRESS_A VARCHAR(100), @IDMEDICO_A VARCHAR(12)
DECLARE @NOPOS_A BIT
DECLARE @PQR_A BIT
DECLARE @COMPANIA VARCHAR(2)

BEGIN
  SET NOCOUNT ON
  SELECT @A = ISJSON(@JSON)
  IF @A = 0
  BEGIN
    RAISERROR('Json: Formato Erroneo', 16, 1)
    RETURN
  END

  SELECT *
  INTO #JSON
  FROM OPENJSON(@JSON)
  WITH (
    MODELO     VARCHAR(100)  '$.MODELO',
    METODO     VARCHAR(100)  '$.METODO',
    USUARIO    VARCHAR(12)   '$.USUARIO',
    PARAMETROS NVARCHAR(MAX) AS JSON
  )

  SELECT @MODELO = MODELO, @METODO = METODO, @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
  FROM #JSON

  /* -- CRUDCEFM -- */
  IF @METODO = 'CRUDCEFM'
  BEGIN
    SELECT
      @PROCESO     = JSON_VALUE(@PARAMETROS, '$.PROCESO'),
      @CEFM        = JSON_QUERY(@PARAMETROS, '$.CEFM'),
      @CEFMD       = JSON_QUERY(@PARAMETROS, '$.CEFMD')

    SELECT
      @CNSCEFM          = CNSCEFM,
      @IDAFILIADO       = IDAFILIADO,
      @IDSEDE           = IDSEDE
    FROM OPENJSON(@CEFM)
    WITH (
      CNSCEFM            VARCHAR(20)  '$.CNSCEFM',
      IDAFILIADO         VARCHAR(20)  '$.IDAFILIADO',
      IDSEDE             VARCHAR(5)   '$.IDSEDE'
    )

    IF COALESCE(@IDAFILIADO, '') = ''
      INSERT INTO @TBLERRORES (ERROR) VALUES ('Debe seleccionar un afiliado.')

    SET @TIPO_IDMED = UPPER(NULLIF(JSON_VALUE(@CEFM, '$.TIPO_IDMED'), ''))
    SET @DOCMEDICO = NULLIF(JSON_VALUE(@CEFM, '$.DOCMEDICO'), '')
    /* true/1/"true"/"1" ? 1 (OPENJSON BIT + TRY_CONVERT) */
    SET @NOPOS = COALESCE(
      (SELECT NOPOS FROM OPENJSON(@CEFM) WITH (NOPOS BIT '$.NOPOS')),
      TRY_CONVERT(BIT, JSON_VALUE(@CEFM, '$.NOPOS')),
      0
    )
    SET @PQR = COALESCE(
      (SELECT PQR FROM OPENJSON(@CEFM) WITH (PQR BIT '$.PQR')),
      TRY_CONVERT(BIT, JSON_VALUE(@CEFM, '$.PQR')),
      0
    )
    SET @IDMIPRESS = NULLIF(JSON_VALUE(@CEFM, '$.IDMIPRESS'), '')
    SET @IDMEDICO_RES = NULL

    IF COALESCE(@DOCMEDICO, '') = '' OR COALESCE(@TIPO_IDMED, '') = ''
      INSERT INTO @TBLERRORES (ERROR) VALUES ('Debe seleccionar el médico de la fórmula.')

    IF COALESCE(@DOCMEDICO, '') <> '' AND OBJECT_ID('dbo.CEFMMED', 'U') IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM CEFMMED WITH (NOLOCK) WHERE IDMEDICO = @DOCMEDICO AND ESTADO = 'Activo')
      INSERT INTO @TBLERRORES (ERROR) VALUES ('El médico no está en el catálogo o está inactivo.')

    IF COALESCE(NULLIF(JSON_VALUE(@CEFM, '$.NITEPSREMITE'), ''), '') = ''
      INSERT INTO @TBLERRORES (ERROR) VALUES ('Debe indicar la IPS formulante.')

    IF COALESCE(NULLIF(JSON_VALUE(@CEFM, '$.NITEPSREMITE'), ''), '') <> ''
       AND OBJECT_ID('dbo.CEFMEPS', 'U') IS NOT NULL
       AND NOT EXISTS (
         SELECT 1 FROM CEFMEPS WITH (NOLOCK)
         WHERE NIT = JSON_VALUE(@CEFM, '$.NITEPSREMITE') AND ESTADO = 'Activo'
       )
      INSERT INTO @TBLERRORES (ERROR) VALUES ('La IPS no está en el catálogo o está inactiva.')

    IF COALESCE(NULLIF(LTRIM(RTRIM(JSON_VALUE(@CEFM, '$.DXPPAL'))), ''), '') = ''
      INSERT INTO @TBLERRORES (ERROR) VALUES ('Debe indicar el diagnóstico de la fórmula.')
    ELSE IF OBJECT_ID('dbo.MDX', 'U') IS NOT NULL
       AND NOT EXISTS (
         SELECT 1 FROM MDX WITH (NOLOCK)
         WHERE IDDX = LTRIM(RTRIM(JSON_VALUE(@CEFM, '$.DXPPAL')))
       )
      INSERT INTO @TBLERRORES (ERROR) VALUES ('El diagnóstico no existe en el catálogo.')

    IF @NOPOS = 1 AND COALESCE(@IDMIPRESS, '') = ''
      INSERT INTO @TBLERRORES (ERROR) VALUES ('Si la fórmula es NO POS debe indicar el número MIPRES.')

    IF NOT EXISTS (SELECT 1 FROM OPENJSON(@CEFMD))
      INSERT INTO @TBLERRORES (ERROR) VALUES ('La fórmula debe tener al menos un medicamento.')

    /* AUTD.AUTDIDSERVICIO es único (IDSERVICIO, IDAUT): un medicamento por fórmula. */
    IF EXISTS (
      SELECT 1
      FROM OPENJSON(@CEFMD)
      WITH (IDSERVICIO VARCHAR(20) '$.IDSERVICIO')
      WHERE COALESCE(IDSERVICIO, '') <> ''
      GROUP BY IDSERVICIO
      HAVING COUNT(*) > 1
    )
      INSERT INTO @TBLERRORES (ERROR) VALUES ('Hay medicamentos repetidos. AUT no admite el mismo servicio dos veces. Deje una sola línea por medicamento.')

    SET @IDMEDICO_RES = NULLIF(@DOCMEDICO, '')
    IF COALESCE(@DOCMEDICO, '') <> ''
    BEGIN
      IF OBJECT_ID('dbo.CEFMMED', 'U') IS NOT NULL
        SELECT TOP 1 @TIPO_IDMED = COALESCE(NULLIF(@TIPO_IDMED, ''), TIPO_ID),
                     @IDMEDICO_RES = IDMEDICO
        FROM CEFMMED WITH (NOLOCK)
        WHERE IDMEDICO = @DOCMEDICO AND ESTADO = 'Activo'

      SELECT TOP 1 @IDMEDICO_RES = COALESCE(NULLIF(IDMEDICO, ''), @IDMEDICO_RES)
      FROM MED WITH (NOLOCK)
      WHERE IDMEDICO = @DOCMEDICO
      ORDER BY CASE WHEN TIPO_ID = @TIPO_IDMED THEN 0 ELSE 1 END
    END
    IF COALESCE(@IDMEDICO_RES, '') = ''
      SET @IDMEDICO_RES = NULLIF(@DOCMEDICO, '')
    IF LEN(@IDMEDICO_RES) > 12
      SET @IDMEDICO_RES = LEFT(@IDMEDICO_RES, 12)

    IF EXISTS (SELECT 1 FROM @TBLERRORES)
    BEGIN
      SELECT 'KO' OK
      SELECT ERROR FROM @TBLERRORES
      RETURN
    END

    /* POS = PREFIJOMEDICAMENTOS; NO POS = PREFIJOMEDNOPOS (fallback PREF_MED_NOPOS) */
    IF @NOPOS = 1
    BEGIN
      SET @PREFIJO = NULLIF(LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('PREFIJOMEDNOPOS'))), '')
      IF COALESCE(@PREFIJO, '') = ''
        SET @PREFIJO = NULLIF(LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('PREF_MED_NOPOS'))), '')
      IF COALESCE(@PREFIJO, '') = ''
        INSERT INTO @TBLERRORES (ERROR) VALUES ('NO POS marcado: configure la variable PREFIJOMEDNOPOS (o PREF_MED_NOPOS).')
    END
    ELSE
      SET @PREFIJO = NULLIF(LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('PREFIJOMEDICAMENTOS'))), '')

    IF EXISTS (SELECT 1 FROM @TBLERRORES)
    BEGIN
      SELECT 'KO' OK
      SELECT ERROR FROM @TBLERRORES
      RETURN
    END

    SELECT @CCOSTO = UBEQ.CCOSTO, @IDAREA = UBEQ.IDAREA
    FROM USUSU WITH (NOLOCK)
    LEFT JOIN UBEQ WITH (NOLOCK) ON UBEQ.SYS_ComputerName = USUSU.SYS_ComputerName
    WHERE USUSU.USUARIO = @USUARIO

    IF COALESCE(@IDSEDE, '') = ''
      SELECT @IDSEDE = IDSEDE FROM USUSU WITH (NOLOCK) WHERE USUARIO = @USUARIO

    IF COALESCE(@IDSEDE, '') NOT IN ('29', '33', '34', '35')
    BEGIN
      SELECT 'KO' OK
      SELECT 'La sede de dispensación debe ser 29, 33, 34 o 35.' ERROR
      RETURN
    END

    /* Transcripción retrasada: fecha manual (ver CEFM_FECHA_TRANS en CEFM_TABLAS.sql) */
    DECLARE @USA_FECHA_TRANS VARCHAR(2) = UPPER(LTRIM(RTRIM(COALESCE(DBO.FNK_VALORVARIABLE('CEFM_FECHA_TRANS'), 'NO'))))
    DECLARE @FECHATRANSCRIPCION_IN DATETIME = TRY_CONVERT(DATETIME, JSON_VALUE(@CEFM, '$.FECHATRANSCRIPCION'))
    DECLARE @CNSGRUPO VARCHAR(20) = NULLIF(JSON_VALUE(@CEFM, '$.CNSGRUPO'), '')

    IF @USA_FECHA_TRANS = 'SI'
    BEGIN
      IF @FECHATRANSCRIPCION_IN IS NULL
      BEGIN
        SELECT 'KO' OK
        SELECT 'Debe indicar la fecha de transcripción.' ERROR
        RETURN
      END
      IF @FECHATRANSCRIPCION_IN > GETDATE()
      BEGIN
        SELECT 'KO' OK
        SELECT 'La fecha de transcripción no puede ser futura.' ERROR
        RETURN
      END
    END

    IF @PROCESO = 'Editar'
    BEGIN
      IF NOT EXISTS (SELECT 1 FROM CEFM WITH (NOLOCK) WHERE CNSCEFM = @CNSCEFM)
      BEGIN
        SELECT 'KO' OK
        SELECT 'La fórmula no existe.' ERROR
        RETURN
      END
      IF EXISTS (SELECT 1 FROM CEFM WITH (NOLOCK) WHERE CNSCEFM = @CNSCEFM AND ESTADO <> 'INGRESADO')
      BEGIN
        SELECT 'KO' OK
        SELECT 'Solo se puede editar una fórmula en estado Ingresado.' ERROR
        RETURN
      END

      IF COALESCE(@CNSGRUPO, '') = ''
        SELECT @CNSGRUPO = CNSGRUPO FROM CEFM WITH (NOLOCK) WHERE CNSCEFM = @CNSCEFM
      IF COALESCE(@CNSGRUPO, '') = ''
        SET @CNSGRUPO = LEFT(COALESCE(@IDSEDE, '01') + '01', 2)
          + RIGHT(CONVERT(VARCHAR(8), GETDATE(), 112), 6)
          + RIGHT('0000' + CAST(ABS(CHECKSUM(NEWID())) % 10000 AS VARCHAR), 4)

      UPDATE C SET
        FECHA_FORMULA    = TRY_CONVERT(DATETIME, JSON_VALUE(@CEFM, '$.FECHA_FORMULA')),
        FECHAVENCE       = TRY_CONVERT(DATETIME, JSON_VALUE(@CEFM, '$.FECHAVENCE')),
        DXPPAL           = NULLIF(JSON_VALUE(@CEFM, '$.DXPPAL'), ''),
        IDMEDICOSOLICITA = @IDMEDICO_RES,
        TIPO_IDMED       = @TIPO_IDMED,
        DOCMEDICO        = @DOCMEDICO,
        IDSEDE           = COALESCE(NULLIF(JSON_VALUE(@CEFM, '$.IDSEDE'), ''), @IDSEDE),
        MENTREGA         = 'Institucional',
        OBSERVACION      = JSON_VALUE(@CEFM, '$.OBSERVACION'),
        IDTERCEROCA      = '0100000011',
        IDPLAN           = NULLIF(JSON_VALUE(@CEFM, '$.IDPLAN'), ''),
        TIPOAFILIADO     = COALESCE(
          NULLIF(JSON_VALUE(@CEFM, '$.TIPOAFILIADO'), ''),
          (SELECT DBO.FNK_CEFM_TIPOAFILIADO(A.TIPOAFILIADO, A.TIPOUSUARIO)
           FROM AFI A WITH (NOLOCK) WHERE A.IDAFILIADO = C.IDAFILIADO)
        ),
        FINALIDAD        = DBO.FNK_CEFM_FINALIDAD_DX(),
        NUMAUTORIZA      = NULLIF(JSON_VALUE(@CEFM, '$.NUMAUTORIZA'), ''),
        FECHAAUTORIZA    = DBO.FNK_CEFM_FECHA_AUT(
          JSON_VALUE(@CEFM, '$.NUMAUTORIZA'),
          TRY_CONVERT(DATETIME, JSON_VALUE(@CEFM, '$.FECHAAUTORIZA'))
        ),
        VALORCOPAGO      = TRY_CONVERT(DECIMAL(14,2), JSON_VALUE(@CEFM, '$.VALORCOPAGO')),
        NOPOS            = @NOPOS,
        PQR              = @PQR,
        IDMIPRESS        = CASE WHEN @NOPOS = 1 THEN NULLIF(@IDMIPRESS, '') ELSE NULL END,
        NITEPSREMITE     = NULLIF(JSON_VALUE(@CEFM, '$.NITEPSREMITE'), ''),
        PREFIJO          = @PREFIJO,
        CCOSTO           = COALESCE(NULLIF(JSON_VALUE(@CEFM, '$.CCOSTO'), ''), @CCOSTO, C.CCOSTO),
        IDAREA           = COALESCE(NULLIF(JSON_VALUE(@CEFM, '$.IDAREA'), ''), @IDAREA, C.IDAREA),
        FECHATRANSCRIPCION = @FECHATRANSCRIPCION_IN,
        CNSGRUPO         = @CNSGRUPO,
        USUARIOMOD       = @USUARIO,
        FECHAMOD         = GETDATE()
      FROM CEFM C
      WHERE C.CNSCEFM = @CNSCEFM

      DELETE FROM CEFMD WHERE CNSCEFM = @CNSCEFM
    END
    ELSE
    BEGIN
      IF COALESCE(@CNSGRUPO, '') = ''
        SET @CNSGRUPO = LEFT(COALESCE(@IDSEDE, '01') + '01', 2)
          + RIGHT(CONVERT(VARCHAR(8), GETDATE(), 112), 6)
          + RIGHT('0000' + CAST(ABS(CHECKSUM(NEWID())) % 10000 AS VARCHAR), 4)

      SET @CNSCEFM = NULL
      BEGIN TRY
        EXEC DBO.SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@CEFM', @LONGITUD = 8, @NVOCONSEC = @CNSCEFM OUTPUT
      END TRY
      BEGIN CATCH
        SET @CNSCEFM = NULL
      END CATCH

      IF COALESCE(@CNSCEFM, '') = ''
      BEGIN
        BEGIN TRY
          EXEC SPK_GENCONSECUTIVO '01', @IDSEDE, '@CEFM', @CNSCEFM OUTPUT
        END TRY
        BEGIN CATCH
          SET @CNSCEFM = NULL
        END CATCH
      END

      /* SPK a veces entrega solo el entero (2, 3, 4); se formatea sede + 8 dígitos */
      IF COALESCE(@CNSCEFM, '') <> ''
         AND @CNSCEFM NOT LIKE '%[^0-9]%'
         AND LEN(@CNSCEFM) <= 8
        SET @CNSCEFM = LEFT(@IDSEDE + '01', 2) + RIGHT(REPLICATE('0', 8) + LTRIM(RTRIM(@CNSCEFM)), 8)

      IF COALESCE(@CNSCEFM, '') = ''
      BEGIN
        SELECT 'KO' OK
        SELECT 'No se pudo generar el consecutivo. Revise la secuencia @CEFM (SPQ_GENSEQUENCE).' ERROR
        RETURN
      END

      INSERT INTO CEFM (
        CNSCEFM, IDAFILIADO, FECHA, FECHA_FORMULA, FECHAVENCE,
        DXPPAL, IDMEDICOSOLICITA, TIPO_IDMED, DOCMEDICO, IDSEDE, MENTREGA, OBSERVACION,
        IDTERCEROCA, IDPLAN, TIPOAFILIADO, CLASECONTRATO,
        CCOSTO, IDAREA, PREFIJO, FINALIDAD, IDPROVEEDOR, IDSOLICITANTE,
        NUMAUTORIZA, FECHAAUTORIZA, VALORCOPAGO, NOPOS, PQR, IDMIPRESS, NITEPSREMITE, FECHATRANSCRIPCION,
        ESTADO, USUARIO, FECHAMOD, CNSGRUPO
      )
      SELECT
        @CNSCEFM,
        @IDAFILIADO,
        GETDATE(),
        TRY_CONVERT(DATETIME, JSON_VALUE(@CEFM, '$.FECHA_FORMULA')),
        TRY_CONVERT(DATETIME, JSON_VALUE(@CEFM, '$.FECHAVENCE')),
        NULLIF(JSON_VALUE(@CEFM, '$.DXPPAL'), ''),
        @IDMEDICO_RES,
        @TIPO_IDMED,
        @DOCMEDICO,
        COALESCE(NULLIF(JSON_VALUE(@CEFM, '$.IDSEDE'), ''), @IDSEDE),
        'Institucional',
        JSON_VALUE(@CEFM, '$.OBSERVACION'),
        '0100000011',
        COALESCE(
          NULLIF(JSON_VALUE(@CEFM, '$.IDPLAN'), ''),
          CASE WHEN AFI.IDADMINISTRADORA = '0100000011' THEN AFI.IDPLAN ELSE NULL END
        ),
        COALESCE(
          NULLIF(JSON_VALUE(@CEFM, '$.TIPOAFILIADO'), ''),
          DBO.FNK_CEFM_TIPOAFILIADO(AFI.TIPOAFILIADO, AFI.TIPOUSUARIO)
        ),
        CASE WHEN COALESCE(PPT.CAPITADO, 0) = 1 THEN 'C' ELSE 'E' END,
        COALESCE(NULLIF(JSON_VALUE(@CEFM, '$.CCOSTO'), ''), @CCOSTO),
        COALESCE(NULLIF(JSON_VALUE(@CEFM, '$.IDAREA'), ''), @IDAREA),
        @PREFIJO,
        DBO.FNK_CEFM_FINALIDAD_DX(),
        NULLIF(JSON_VALUE(@CEFM, '$.IDPROVEEDOR'), ''),
        NULLIF(JSON_VALUE(@CEFM, '$.IDSOLICITANTE'), ''),
        NULLIF(JSON_VALUE(@CEFM, '$.NUMAUTORIZA'), ''),
        DBO.FNK_CEFM_FECHA_AUT(
          JSON_VALUE(@CEFM, '$.NUMAUTORIZA'),
          TRY_CONVERT(DATETIME, JSON_VALUE(@CEFM, '$.FECHAAUTORIZA'))
        ),
        TRY_CONVERT(DECIMAL(14,2), JSON_VALUE(@CEFM, '$.VALORCOPAGO')),
        @NOPOS,
        @PQR,
        CASE WHEN @NOPOS = 1 THEN NULLIF(@IDMIPRESS, '') ELSE NULL END,
        NULLIF(JSON_VALUE(@CEFM, '$.NITEPSREMITE'), ''),
        @FECHATRANSCRIPCION_IN,
        'INGRESADO',
        @USUARIO,
        GETDATE(),
        @CNSGRUPO
      FROM AFI WITH (NOLOCK)
      LEFT JOIN PPT WITH (NOLOCK)
        ON PPT.IDTERCERO = '0100000011'
       AND PPT.IDPLAN = COALESCE(
            NULLIF(JSON_VALUE(@CEFM, '$.IDPLAN'), ''),
            CASE WHEN AFI.IDADMINISTRADORA = '0100000011' THEN AFI.IDPLAN ELSE NULL END
          )
      WHERE AFI.IDAFILIADO = @IDAFILIADO

      IF @@ROWCOUNT = 0
      BEGIN
        SELECT 'KO' OK
        SELECT 'El afiliado no existe.' ERROR
        RETURN
      END
    END

    INSERT INTO CEFMD (
      CNSCEFM, NO_ITEM, IDSERVICIO, CANTIDAD, FRECUENCIA, TIPOFRECUENCIA,
      DURACION, TIPODURACION, CANTIDAD_TOTAL, POSOLOGIA, COMENTARIOS
    )
    SELECT
      @CNSCEFM,
      ROW_NUMBER() OVER (ORDER BY COALESCE(NO_ITEM, 9999), IDSERVICIO),
      IDSERVICIO,
      COALESCE(CANTIDAD, 1),
      COALESCE(FRECUENCIA, 0),
      COALESCE(NULLIF(TIPOFRECUENCIA, ''), 'H'),
      COALESCE(DURACION, 0),
      COALESCE(NULLIF(TIPODURACION, ''), 'M'),
      COALESCE(CANTIDAD_TOTAL, 0),
      POSOLOGIA,
      COMENTARIOS
    FROM OPENJSON(@CEFMD)
    WITH (
      NO_ITEM          SMALLINT       '$.NO_ITEM',
      IDSERVICIO       VARCHAR(20)    '$.IDSERVICIO',
      CANTIDAD         DECIMAL(18,4)  '$.CANTIDAD',
      FRECUENCIA       DECIMAL(18,4)  '$.FRECUENCIA',
      TIPOFRECUENCIA   VARCHAR(1)     '$.TIPOFRECUENCIA',
      DURACION         DECIMAL(18,4)  '$.DURACION',
      TIPODURACION     VARCHAR(1)     '$.TIPODURACION',
      CANTIDAD_TOTAL   DECIMAL(18,2)  '$.CANTIDAD_TOTAL',
      POSOLOGIA        VARCHAR(400)   '$.POSOLOGIA',
      COMENTARIOS      VARCHAR(255)   '$.COMENTARIOS'
    )
    WHERE COALESCE(IDSERVICIO, '') <> ''

    IF COALESCE(@CNSGRUPO, '') = ''
      SELECT @CNSGRUPO = CNSGRUPO FROM CEFM WITH (NOLOCK) WHERE CNSCEFM = @CNSCEFM

    SELECT 'OK' OK, @CNSCEFM AS CNSCEFM, @CNSGRUPO AS CNSGRUPO
    RETURN
  END

  /* -- GET -- */
  IF @METODO = 'GET'
  BEGIN
    SELECT @CNSCEFM = JSON_VALUE(@PARAMETROS, '$.CNSCEFM')

    SELECT 'OK' OK

    SELECT
      C.CNSCEFM, C.IDAFILIADO, C.FECHA, C.FECHA_FORMULA, C.FECHAVENCE,
      C.DXPPAL, MDX.DESCRIPCION AS DESCDX,
      C.IDMEDICOSOLICITA, C.TIPO_IDMED, C.DOCMEDICO,
      COALESCE(CM.NOMBRE, MED.NOMBRE) AS NOMBREMEDICO,
      CM.PERSONAL_AT,
      COALESCE(ESP.CODIGO, CM.ESPECIALIDAD) AS ESPECIALIDAD,
      C.IDSEDE, C.MENTREGA, C.OBSERVACION,
      C.IDTERCEROCA, TER.RAZONSOCIAL AS NOMBREPAGADOR, C.IDPLAN, PLN.DESCPLAN,
      C.TIPOAFILIADO, C.CLASECONTRATO,
      C.CCOSTO, C.IDAREA, C.PREFIJO, C.FINALIDAD,
      C.NUMAUTORIZA, C.FECHAAUTORIZA, C.VALORCOPAGO, C.NOPOS, C.PQR, C.IDMIPRESS, C.FECHATRANSCRIPCION,
      C.ESTADO, C.OBSERVACION_AUD, C.USUARIOAUD, C.FECHAAUD,
      C.USUARIO, C.USUARIOMOD, C.FECHAMOD,
      COALESCE(
        NULLIF(C.IDAUT, ''),
        (SELECT TOP 1 E.IDAUT FROM AUTE E WITH (NOLOCK)
         WHERE E.CNSCEFM = C.CNSCEFM AND COALESCE(E.IDAUT, '') <> ''
         ORDER BY E.FECHA)
      ) AS IDAUT, C.NITEPSREMITE, C.CNSGRUPO,
      COALESCE(CE.RAZONSOCIAL, EPSREM.NOMBREEPSREMITE) AS NOMBREEPSREMITE,
      BDG.IDBODEGA_FAR, BDG.DESCBODEGA, BDG.CNSIZSOL
    FROM CEFM C WITH (NOLOCK)
    LEFT JOIN MDX WITH (NOLOCK) ON MDX.IDDX = C.DXPPAL
    LEFT JOIN MED WITH (NOLOCK) ON MED.IDMEDICO = C.IDMEDICOSOLICITA
    LEFT JOIN CEFMMED CM WITH (NOLOCK) ON CM.IDMEDICO = C.DOCMEDICO
    OUTER APPLY (
      SELECT TOP 1 T.CODIGO, T.DESCRIPCION
      FROM TGEN T WITH (NOLOCK)
      WHERE T.TABLA = 'CEFMMED' AND T.CAMPO = 'ESPECIALIDAD'
        AND (T.CODIGO = CM.ESPECIALIDAD OR T.DESCRIPCION = CM.ESPECIALIDAD)
      ORDER BY CASE WHEN T.CODIGO = CM.ESPECIALIDAD THEN 0 ELSE 1 END
    ) ESP
    LEFT JOIN TER WITH (NOLOCK) ON TER.IDTERCERO = C.IDTERCEROCA
    LEFT JOIN CEFMEPS CE WITH (NOLOCK) ON CE.NIT = C.NITEPSREMITE
    LEFT JOIN PLN WITH (NOLOCK) ON PLN.IDPLAN = C.IDPLAN
    OUTER APPLY (
      SELECT TOP 1 TER2.RAZONSOCIAL AS NOMBREEPSREMITE
      FROM TER TER2 WITH (NOLOCK)
      WHERE COALESCE(C.NITEPSREMITE, '') <> ''
        AND REPLACE(REPLACE(REPLACE(COALESCE(TER2.NIT, ''), '-', ''), '.', ''), ' ', '')
          = REPLACE(REPLACE(REPLACE(C.NITEPSREMITE, '-', ''), '.', ''), ' ', '')
    ) EPSREM
    OUTER APPLY (
      SELECT TOP 1
        COALESCE(Z.IDBODEGAATIENDE, Z.IDBODEGASOLICITA) AS IDBODEGA_FAR,
        COALESCE(IB.DESCRIPCION, Z.IDBODEGAATIENDE, Z.IDBODEGASOLICITA) AS DESCBODEGA,
        Z.CNSIZSOL
      FROM AUTE E WITH (NOLOCK)
      INNER JOIN IZSOL Z WITH (NOLOCK) ON Z.CNSIZSOL = E.CNSIZSOL
      LEFT JOIN IBOD IB WITH (NOLOCK) ON IB.IDBODEGA = COALESCE(Z.IDBODEGAATIENDE, Z.IDBODEGASOLICITA)
      WHERE E.CNSCEFM = C.CNSCEFM
        AND COALESCE(E.CNSIZSOL, '') <> ''
      ORDER BY E.FECHA DESC, Z.FECHASOL DESC
    ) BDG
    WHERE C.CNSCEFM = @CNSCEFM

    SELECT
      D.CNSCEFM, D.NO_ITEM, D.IDSERVICIO, SER.DESCSERVICIO,
      D.CANTIDAD, D.FRECUENCIA, D.TIPOFRECUENCIA,
      D.DURACION, D.TIPODURACION, D.CANTIDAD_TOTAL,
      D.POSOLOGIA, D.COMENTARIOS
    FROM CEFMD D WITH (NOLOCK)
    LEFT JOIN SER WITH (NOLOCK) ON SER.IDSERVICIO = D.IDSERVICIO
    WHERE D.CNSCEFM = @CNSCEFM
    ORDER BY D.NO_ITEM

    RETURN
  END

