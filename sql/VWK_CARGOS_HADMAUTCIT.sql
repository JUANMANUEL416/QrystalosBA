CREATE OR ALTER VIEW DBO.VWK_CARGOS_HADMAUTCIT
WITH SCHEMABINDING, ENCRYPTION    
AS    
SELECT A.NOADMISION, A.NOPRESTACION, A.NOITEM, A.PROCEDENCIA, A.FECHA,
       PACIENTE = LEFT(ISNULL(RTRIM(AFI.PAPELLIDO),'')+' '+ISNULL(RTRIM(AFI.SAPELLIDO),'')+' '+ISNULL(RTRIM(AFI.PNOMBRE),'')+' '+ISNULL(RTRIM(AFI.SNOMBRE),''),100),
		 A.IDTERCERO, A.IDPLAN, A.IDTERCEROCA, TER.RAZONSOCIAL, A.IDPLANCA, PLN.DESCPLAN NOMPLAN, A.IDAREA, AFU.DESCRIPCION NOMBREAREA, A.CCOSTO, CEN.DESCRIPCION NOMBRECCOSTO,
		 SER.PREFIJO, PRE.NOM_PREFIJO NOMPREFIJO, A.IDSERVICIO, SER.DESCSERVICIO, A.CANTIDAD, A.VALOR, (A.CANTIDAD*A.VALOR) VALORTOTAL, A.VALORCOPAGO, A.VALORPCOMP, A.VALOREXCEDENTE,
		 A.DESCUENTO, PPT.TIPOTERCONTABLE, ISNULL(PPT.CAPITADO,0) CAPITADO, A.FACTURADA, A.N_FACTURA, A.IDMEDICO, MED.NOMBRE, (A.CANTIDAD* COALESCE(SER.VLRCOSTO,0)) AS COSTOSERVICIO,
       A.CLASEORDEN, A.IDPESPECIAL, A.RIESGO, SER.CODCUPS, A.NOCOBRABLE,A.IDSEDE,AFI.IDAFILIADO,AFI.DOCIDAFILIADO,AFI.TIPO_DOC,MARCAFAC,USUMARCA,CNSFACT,NOAUTORIZACION,TIPOCOPAGO,A.CODUNG,
       A.AUTAUDITADO, A.EXONERACION, A.VALORCOPAGO_EXONERA, A.TIPO_EXONERACION,ENCAJA, A.ANOMES, A.ESAPLIM
FROM	(
		-- ADMISIONES - HAMD
		SELECT	A.FECHA, A.IDTERCERO, A.IDPLAN, A.IDTERCEROCA, A.IDPLANCA, A.IDAREA, A.CCOSTO,
				A.IDSERVICIO, A.CANTIDAD, A.VALOR, A.VALORCOPAGO, A.VALORPCOMP, A.VALOREXCEDENTE, A.DESCUENTO,
				A.NOADMISION, A.NOPRESTACION, A.NOITEM, A.FACTURADA, A.N_FACTURA, A.PROCEDENCIA, A.IDAFILIADO, A.IDMEDICO,
            A.CLASEORDEN, A.IDPESPECIAL, A.RIESGO, A.NOCOBRABLE,A.IDSEDE,MARCAFAC,USUMARCA,CNSFACT,NOAUTORIZACION,'C' TIPOCOPAGO,A.CODUNG,A.ENCAJA,
            0 AS AUTAUDITADO, 0 AS EXONERACION, 0 AS VALORCOPAGO_EXONERA, 'N/A' AS TIPO_EXONERACION, A.ANOMES, 0 ESAPLIM
		FROM  (SELECT	HPRE.FECHA, HADM.IDTERCERO, HADM.IDPLAN, HPRE.CCOSTO,
						CASE WHEN HPRED.IDTERCEROCA IS NULL OR HPRED.IDTERCEROCA='' THEN HADM.IDTERCERO ELSE HPRED.IDTERCEROCA END IDTERCEROCA,
						CASE WHEN HPRED.IDPLAN IS NULL OR HPRED.IDPLAN='' THEN HADM.IDPLAN ELSE HPRED.IDPLAN END IDPLANCA,
						HPRE.IDAREA, HPRED.IDSERVICIO,
						ISNULL(HPRED.CANTIDAD,0) CANTIDAD,
						ISNULL(HPRED.VALOR,0) VALOR,
						ISNULL(HPRED.VALORCOPAGO,0) VALORCOPAGO,
						ISNULL(HPRED.VALORPCOMP,0) VALORPCOMP,
						ISNULL(HPRED.VALOREXCEDENTE,0) VALOREXCEDENTE,
						ISNULL(HPRED.DESCUENTO,0) DESCUENTO,
						HADM.NOADMISION, HPRED.NOPRESTACION, HPRED.NOITEM, ISNULL(HPRED.FACTURADA,0) FACTURADA, HPRED.N_FACTURA,
						'HADM' PROCEDENCIA, HADM.IDAFILIADO, COALESCE(HPRED.IDPROVEEDOR,HPRE.IDMEDICO) AS IDMEDICO,
                        CASE WHEN HTAD.MPE=1 AND COALESCE(HTAD.IDPESPECIAL,'')<>'' THEN 'PyP' ELSE 'Normal' END CLASEORDEN, 
						CASE WHEN HTAD.MPE=1 AND COALESCE(HTAD.IDPESPECIAL,'')<>'' THEN HTAD.IDPESPECIAL ELSE '' END IDPESPECIAL, 
						'' RIESGO, COALESCE(HPRED.NOCOBRABLE,0) AS NOCOBRABLE,HADM.IDSEDE,COALESCE(HPRED.MARCA,0) AS MARCAFAC,
                  COALESCE(HPRED.USUARIOMARCA,'') AS USUMARCA,HPRED.CNSITFC AS CNSFACT,IIF(COALESCE(HPRED.NOAUTORIZACION,'')<>'',HPRED.NOAUTORIZACION,HADM.NOAUTORIZACION) NOAUTORIZACION,HADM.CODUNG,
                  CASE WHEN EXISTS(SELECT NOADMISION FROM DBO.FCJ WHERE NOADMISION=HADM.NOADMISION AND PROCEDENCIA='SALUD' AND ESTADO='P' AND CERRADA=1) THEN 1 ELSE 0 END ENCAJA
				, CONVERT(VARCHAR,CONCAT(YEAR(HPRE.FECHA),RIGHT('0'+CONVERT(VARCHAR,MONTH(HPRE.FECHA)),2))) AS ANOMES
                FROM	DBO.HADM	
						INNER JOIN DBO.HPRE  ON HADM.NOADMISION = HPRE.NOADMISION
						INNER JOIN DBO.HPRED ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
                        INNER JOIN DBO.PPT   ON HPRE.IDTERCEROCA=PPT.IDTERCERO AND HPRE.IDPLAN=PPT.IDPLAN
						INNER JOIN DBO.HTAD  ON HTAD.TIPOADM=HADM.TIPOADM
						-- EEMC78: 09-03-2026 PARA LAS EXCEPCIONES EN PGP Y CAPITAS VARIABLE 'EXEPCION_PPT_PGP_CAP'
						LEFT JOIN DBO.SER ON HPRED.IDSERVICIO = SER.IDSERVICIO
						LEFT JOIN DBO.USVGS EXC_PPTSERPRE_PGPCAP ON EXC_PPTSERPRE_PGPCAP.IDVARIABLE = 'EXC_PPTSERPRE_PGPCAP'
						LEFT JOIN DBO.EXPS EXPSPRE ON COALESCE(EXC_PPTSERPRE_PGPCAP.DATO,'NO')='SI'	AND EXPSPRE.IDSERVICIO = SER.PREFIJO     AND EXPSPRE.TIPO='PREFIJO'   AND EXPSPRE.IDPLAN= HPRE.IDPLAN AND COALESCE(EXPSPRE.PROCEDENCIA,'HPRE') ='HPRE'
						LEFT JOIN DBO.EXPS EXPSSER ON COALESCE(EXC_PPTSERPRE_PGPCAP.DATO,'NO')='SI'	AND EXPSSER.IDSERVICIO = SER.IDSERVICIO  AND EXPSSER.TIPO='SERVICIOS' AND EXPSSER.IDPLAN= HPRE.IDPLAN AND COALESCE(EXPSSER.PROCEDENCIA,'HPRE') ='HPRE'				
				WHERE	HADM.CERRADA = CASE WHEN (SELECT DATO FROM DBO.USVGS WHERE IDVARIABLE= 'CAPITA_HADM_ABIERTAS')<>'SI' AND (COALESCE(PPT.CAPITADO,0)=1 OR COALESCE(PPT.PGP,0)=1) THEN 1 ELSE HADM.CERRADA END AND FACTURABLE = 1 AND HADM.CLASEING = 'A'
						-- EEMC78: 09-03-2026 PARA LAS EXCEPCIONES EN PGP Y CAPITAS
						AND EXPSPRE.CNSEXPS IS  NULL AND EXPSSER.CNSEXPS IS  NULL -- PORQUE SON EXCEPCIONES	
						-- 
				) A
		UNION ALL
		-- CITAS - CIT
		SELECT A.FECHA, A.IDTERCERO, A.IDPLAN, A.IDTERCEROCA, A.IDPLANCA, A.IDAREA, A.CCOSTO,
				 A.IDSERVICIO, A.CANTIDAD, A.VALOR, A.VALORCOPAGO, A.VALORPCOMP, A.VALOREXCEDENTE, A.DESCUENTO,
				 A.NOADMISION, A.NOPRESTACION, A.NOITEM, A.FACTURADA, A.N_FACTURA, A.PROCEDENCIA, A.IDAFILIADO, A.IDMEDICO,
             A.CLASEORDEN, A.IDPESPECIAL, A.RIESGO, A.NOCOBRABLE,A.IDSEDE,A.MARCAFAC,A.USUMARCA,A.CNSFACT,NOAUTORIZACION,A.TIPOCOPAGO,A.CODUNG,A.ENCAJA,
             A.AUTAUDITADO, A.EXONERACION, A.VALORCOPAGO_EXONERA, A.TIPO_EXONERACION, A.ANOMES, A.ESAPLIM
		FROM   (SELECT	CIT.FECHA, CIT.IDCONTRATANTE IDTERCERO, CIT.IDPLAN, CIT.CCOSTO,
						CASE WHEN CIT.IDTERCEROCA IS NULL OR CIT.IDTERCEROCA='' THEN CIT.IDCONTRATANTE ELSE CIT.IDTERCEROCA END IDTERCEROCA,
						CIT.IDPLAN IDPLANCA, CIT.IDAREA, CIT.IDSERVICIO,
						CASE WHEN COALESCE(CANTIDADC,0)=0 THEN 1 ELSE CANTIDADC END CANTIDAD,
						ISNULL(CIT.VALORTOTAL,0) VALOR,
						ISNULL(CIT.VALORCOPAGO,0) VALORCOPAGO,
						0 VALORPCOMP,
						CASE ISNULL(CIT.VALOREXEDENTE,0) WHEN 0 THEN ISNULL(CIT.VALORTOTAL,0)-ISNULL(CIT.VALORCOPAGO,0) ELSE CIT.VALOREXEDENTE END VALOREXCEDENTE,
						0 DESCUENTO,
						CIT.CONSECUTIVO NOADMISION, CIT.CONSECUTIVO NOPRESTACION, 1 NOITEM,
						ISNULL(CIT.FACTURADA,0) FACTURADA, CIT.N_FACTURA, 'CIT' PROCEDENCIA, CIT.IDAFILIADO, CIT.IDMEDICO,
                  CIT.CLASEORDEN, COALESCE(CIT.IDPESPECIAL,'') IDPESPECIAL, COALESCE(CIT.RIESGO,'') RIESGO,CASE WHEN  COALESCE(FACTURABLE,0)=1 THEN 0 ELSE 1 END AS NOCOBRABLE,
                  COALESCE(CIT.IDSEDE,'') IDSEDE,COALESCE(MARCAFAC,0)MARCAFAC , COALESCE(USUARIONOFACTURABLE,'') AS USUMARCA,CNSFACT,NOAUTORIZACION,
                  CIT.TIPOCOPAGO,CIT.CODUNG,
                  CASE WHEN EXISTS(SELECT NOADMISION FROM DBO.FCJ WHERE NOADMISION=CIT.CONSECUTIVO AND PROCEDENCIA='CITAS' AND ESTADO='P' AND CERRADA=1) THEN 1 ELSE 0 END ENCAJA,
                  COALESCE(CIT.AUTAUDITADO,0) AS AUTAUDITADO, CIT.EXONERACION, CIT.VALORCOPAGO_EXONERA, COALESCE(TGEN.DESCRIPCION, '') AS TIPO_EXONERACION, CIT.ANOMES, CASE WHEN CIT.IDAPLIM IS NOT NULL THEN 1 ELSE 0 END ESAPLIM
				FROM	DBO.CIT LEFT JOIN DBO.USVGS ON USVGS.IDVARIABLE = 'RIPS_CITSOLOCUMPLIDA'
					LEFT JOIN DBO.USVGS USVGS2 ON USVGS2.IDVARIABLE = 'USA_EXONERACION'
					LEFT JOIN DBO.TGEN ON TGEN.TABLA = 'CIT' AND TGEN.CAMPO='EXONERACION' AND TGEN.CODIGO=CIT.TIPO_EXONERACION
					-- EEMC78: 09-03-2026 PARA LAS EXCEPCIONES EN PGP Y CAPITAS
					LEFT JOIN DBO.SER ON CIT.IDSERVICIO = SER.IDSERVICIO
					LEFT JOIN DBO.USVGS EXC_PPTSERPRE_PGPCAP ON EXC_PPTSERPRE_PGPCAP.IDVARIABLE = 'EXC_PPTSERPRE_PGPCAP'
					LEFT JOIN DBO.EXPS EXPSPRE ON COALESCE(EXC_PPTSERPRE_PGPCAP.DATO,'NO')='SI'	AND EXPSPRE.IDSERVICIO = SER.PREFIJO     AND EXPSPRE.TIPO='PREFIJO'   AND EXPSPRE.IDPLAN= CIT.IDPLAN AND COALESCE(EXPSPRE.PROCEDENCIA,'CIT') ='CIT'
					LEFT JOIN DBO.EXPS EXPSSER ON COALESCE(EXC_PPTSERPRE_PGPCAP.DATO,'NO')='SI'	AND EXPSSER.IDSERVICIO = SER.IDSERVICIO  AND EXPSSER.TIPO='SERVICIOS' AND EXPSSER.IDPLAN= CIT.IDPLAN AND COALESCE(EXPSSER.PROCEDENCIA,'CIT') ='CIT'				
					--
				-- WHERE	CIT.CUMPLIDA = 1 AND NOT CIT.IDAFILIADO IS NULL) A
				WHERE	COALESCE(CIT.CUMPLIDA,0) = CASE ISNULL(USVGS.DATO,'') WHEN 'SI' THEN 1 ELSE COALESCE(CIT.CUMPLIDA,0) END
					AND     NOT CIT.IDAFILIADO IS NULL  -- AND COALESCE(CIT.FACTURABLE,0)=1  Naren
					AND IDAUTSES IS NULL
					-- EEMC78: 09-03-2026 PARA LAS EXCEPCIONES EN PGP Y CAPITAS
					AND EXPSPRE.CNSEXPS IS  NULL AND EXPSSER.CNSEXPS IS  NULL -- PORQUE SON EXCEPCIONES	
					-- 
            ) A
		UNION ALL
      --ONCOLOGIA
		SELECT  A.FECHA, A.IDTERCERO, A.IDPLAN, A.IDTERCEROCA, A.IDPLANCA, A.IDAREA, A.CCOSTO,
				 A.IDSERVICIO, A.CANTIDAD, A.VALOR, A.VALORCOPAGO, A.VALORPCOMP, A.VALOREXCEDENTE, A.DESCUENTO,
				 A.NOADMISION, A.NOPRESTACION, A.NOITEM, A.FACTURADA, A.N_FACTURA, A.PROCEDENCIA, A.IDAFILIADO, A.IDMEDICO,
             A.CLASEORDEN, A.IDPESPECIAL, A.RIESGO, A.NOCOBRABLE,A.IDSEDE,A.MARCAFAC,A.USUMARCA,A.CNSFACT,NOAUTORIZACION,A.TIPOCOPAGO,A.CODUNG,A.ENCAJA,
             0 AS AUTAUDITADO, 0 AS EXONERACION, 0 AS VALORCOPAGO_EXONERA, 'N/A' AS TIPO_EXONERACION, A.ANOMES, 0 ESAPLIM
		FROM   (SELECT	CIT.FECHA, CIT.IDCONTRATANTE IDTERCERO, 
						COALESCE(NULLIF(HCATDIMOV.IDPLAN,''), CIT.IDPLAN) AS IDPLAN,--CIT.IDPLAN, 
						CIT.CCOSTO,
						COALESCE
						(
							NULLIF(HCATDIMOV.IDTERCEROCA,''),
							CASE WHEN CIT.IDTERCEROCA IS NULL OR CIT.IDTERCEROCA='' THEN CIT.IDCONTRATANTE ELSE CIT.IDTERCEROCA END
						) AS IDTERCEROCA, --CASE WHEN CIT.IDTERCEROCA IS NULL OR CIT.IDTERCEROCA='' THEN CIT.IDCONTRATANTE ELSE CIT.IDTERCEROCA END IDTERCEROCA,
						CIT.IDPLAN IDPLANCA, CIT.IDAREA, HCATDIMOV.IDSERVICIO,
						COALESCE(HCATDIMOV.CANTIDAD,0)-COALESCE(HCATDIMOV.CANT_DEVUELTA,0) CANTIDAD,
						HCATDIMOV.VLR_UNITARIO VALOR,
						0 VALORCOPAGO,
						0 VALORPCOMP,
						HCATDIMOV.VLR_UNITARIO  VALOREXCEDENTE,
						0 DESCUENTO,
						CIT.CONSECUTIVO NOADMISION, HCATDIMOV.CNSMOV NOPRESTACION, HCATDIMOV.ID NOITEM,
						ISNULL(HCATDIMOV.FACTURADA,0) FACTURADA, HCATDIMOV.N_FACTURA, 'ONCO' PROCEDENCIA, CIT.IDAFILIADO, CIT.IDMEDICO,
                  CIT.CLASEORDEN, COALESCE(CIT.IDPESPECIAL,'') IDPESPECIAL, COALESCE(CIT.RIESGO,'') RIESGO,CASE WHEN HCATDIMOV.NOCOBRABLE = 1 THEN 1 WHEN COALESCE(CIT.FACTURABLE,0)=1 THEN 0 ELSE 1 END  AS NOCOBRABLE,--CASE WHEN  COALESCE(FACTURABLE,0)=1 THEN 0 ELSE 1 END AS NOCOBRABLE,
                  COALESCE(CIT.IDSEDE,'') IDSEDE,COALESCE(HCATDIMOV.MARCAFAC,0)MARCAFAC , COALESCE(HCATDIMOV.USUMARCA,'') AS USUMARCA,HCATDIMOV.CNSFACT,CIT.NOAUTORIZACION,
                  CIT.TIPOCOPAGO,CIT.CODUNG,
                  CASE WHEN EXISTS(SELECT NOADMISION FROM DBO.FCJ WHERE NOADMISION=CIT.CONSECUTIVO AND PROCEDENCIA='CITAS' AND ESTADO='P' AND CERRADA=1) THEN 1 ELSE 0 END ENCAJA
				  , CIT.ANOMES
                FROM	DBO.HCATDIMOV  HCATDIMOV 
					INNER  JOIN DBO.CIT CIT ON HCATDIMOV.CONSECUTIVOCIT=CIT.CONSECUTIVO
					-- EEMC78: 09-03-2026 PARA LAS EXCEPCIONES EN PGP Y CAPITAS
					LEFT JOIN DBO.SER ON CIT.IDSERVICIO = SER.IDSERVICIO
					LEFT JOIN DBO.USVGS EXC_PPTSERPRE_PGPCAP ON EXC_PPTSERPRE_PGPCAP.IDVARIABLE = 'EXC_PPTSERPRE_PGPCAP'
					LEFT JOIN DBO.EXPS EXPSPRE ON COALESCE(EXC_PPTSERPRE_PGPCAP.DATO,'NO')='SI'	AND EXPSPRE.IDSERVICIO = SER.PREFIJO     AND EXPSPRE.TIPO='PREFIJO'   AND EXPSPRE.IDPLAN= CIT.IDPLAN AND COALESCE(EXPSPRE.PROCEDENCIA,'ONCO') ='ONCO'
					LEFT JOIN DBO.EXPS EXPSSER ON COALESCE(EXC_PPTSERPRE_PGPCAP.DATO,'NO')='SI'	AND EXPSSER.IDSERVICIO = SER.IDSERVICIO  AND EXPSSER.TIPO='SERVICIOS' AND EXPSSER.IDPLAN= CIT.IDPLAN AND COALESCE(EXPSSER.PROCEDENCIA,'ONCO') ='ONCO'				
					--
				WHERE 	COALESCE(CIT.CUMPLIDA,0) = 1
					AND     NOT CIT.IDAFILIADO IS NULL
					-- EEMC78: 09-03-2026 PARA LAS EXCEPCIONES EN PGP Y CAPITAS
					AND EXPSPRE.CNSEXPS IS  NULL AND EXPSSER.CNSEXPS IS  NULL -- PORQUE SON EXCEPCIONES	
					-- 
			)A -- AND COALESCE(CIT.FACTURABLE,0)=1 Naren
		UNION ALL
		-- CITAS - ONCOLOGIA
		SELECT A.FECHA, A.IDTERCERO, A.IDPLAN, A.IDTERCEROCA, A.IDPLANCA, A.IDAREA, A.CCOSTO,
				 A.IDSERVICIO, A.CANTIDAD, A.VALOR, A.VALORCOPAGO, A.VALORPCOMP, A.VALOREXCEDENTE, A.DESCUENTO,
				 A.NOADMISION, A.NOPRESTACION, A.NOITEM, A.FACTURADA, A.N_FACTURA, A.PROCEDENCIA, A.IDAFILIADO, A.IDMEDICO,
             A.CLASEORDEN, A.IDPESPECIAL, A.RIESGO, A.NOCOBRABLE,A.IDSEDE,A.MARCAFAC,A.USUMARCA,A.CNSFACT,NOAUTORIZACION,A.TIPOCOPAGO,A.CODUNG,A.ENCAJA,
             0 AS AUTAUDITADO, 0 AS EXONERACION, 0 AS VALORCOPAGO_EXONERA, 'N/A' AS TIPO_EXONERACION, A.ANOMES, 0 ESAPLIM
		FROM   (SELECT	CIT.FECHA, CIT.IDCONTRATANTE IDTERCERO, CIT.IDPLAN, CIT.CCOSTO,
						CASE WHEN CIT.IDTERCEROCA IS NULL OR CIT.IDTERCEROCA='' THEN CIT.IDCONTRATANTE ELSE CIT.IDTERCEROCA END IDTERCEROCA,
						CIT.IDPLAN IDPLANCA, CIT.IDAREA, CIT.IDSERVICIO,
						CASE WHEN COALESCE(CANTIDADC,0)=0 THEN 1 ELSE CANTIDADC END CANTIDAD,
						ISNULL(CIT.VALORTOTAL,0) VALOR,
						ISNULL(CIT.VALORCOPAGO,0) VALORCOPAGO,
						0 VALORPCOMP,
						CASE ISNULL(CIT.VALOREXEDENTE,0) WHEN 0 THEN ISNULL(CIT.VALORTOTAL,0)-ISNULL(CIT.VALORCOPAGO,0) ELSE CIT.VALOREXEDENTE END VALOREXCEDENTE,
						0 DESCUENTO,
						CIT.CONSECUTIVO NOADMISION, CIT.CONSECUTIVO NOPRESTACION, 1 NOITEM,
						ISNULL(CIT.FACTURADA,0) FACTURADA, CIT.N_FACTURA, 'ONCO' PROCEDENCIA, CIT.IDAFILIADO, CIT.IDMEDICO,
                  CIT.CLASEORDEN, COALESCE(CIT.IDPESPECIAL,'') IDPESPECIAL, COALESCE(CIT.RIESGO,'') RIESGO,CASE WHEN  COALESCE(FACTURABLE,0)=1 THEN 0 ELSE 1 END AS NOCOBRABLE,
                  COALESCE(CIT.IDSEDE,'') IDSEDE,COALESCE(MARCAFAC,0)MARCAFAC , COALESCE(USUARIONOFACTURABLE,'') AS USUMARCA,CNSFACT,NOAUTORIZACION,
                  CIT.TIPOCOPAGO,CIT.CODUNG,
                  CASE WHEN EXISTS(SELECT NOADMISION FROM DBO.FCJ WHERE NOADMISION=CIT.CONSECUTIVO AND PROCEDENCIA='CITAS' AND ESTADO='P' AND CERRADA=1) THEN 1 ELSE 0 END ENCAJA
				  , CIT.ANOMES
                FROM	DBO.CIT LEFT JOIN DBO.USVGS ON USVGS.IDVARIABLE = 'RIPS_CITSOLOCUMPLIDA'
					-- EEMC78: 09-03-2026 PARA LAS EXCEPCIONES EN PGP Y CAPITAS
					LEFT JOIN DBO.SER ON CIT.IDSERVICIO = SER.IDSERVICIO
					LEFT JOIN DBO.USVGS EXC_PPTSERPRE_PGPCAP ON EXC_PPTSERPRE_PGPCAP.IDVARIABLE = 'EXC_PPTSERPRE_PGPCAP'
					LEFT JOIN DBO.EXPS EXPSPRE ON COALESCE(EXC_PPTSERPRE_PGPCAP.DATO,'NO')='SI'	AND EXPSPRE.IDSERVICIO = SER.PREFIJO     AND EXPSPRE.TIPO='PREFIJO'   AND EXPSPRE.IDPLAN= CIT.IDPLAN AND COALESCE(EXPSPRE.PROCEDENCIA,'ONCO') ='ONCO'
					LEFT JOIN DBO.EXPS EXPSSER ON COALESCE(EXC_PPTSERPRE_PGPCAP.DATO,'NO')='SI'	AND EXPSSER.IDSERVICIO = SER.IDSERVICIO  AND EXPSSER.TIPO='SERVICIOS' AND EXPSSER.IDPLAN= CIT.IDPLAN AND COALESCE(EXPSSER.PROCEDENCIA,'ONCO') ='ONCO'				
					--
				-- WHERE	CIT.CUMPLIDA = 1 AND NOT CIT.IDAFILIADO IS NULL) A
				WHERE	COALESCE(CIT.CUMPLIDA,0) = CASE ISNULL(USVGS.DATO,'') WHEN 'SI' THEN 1 ELSE COALESCE(CIT.CUMPLIDA,0) END
					AND     NOT CIT.IDAFILIADO IS NULL --AND COALESCE(CIT.FACTURABLE,0)=1  Naren
					AND IDAUTSES IS NOT NULL
					-- EEMC78: 09-03-2026 PARA LAS EXCEPCIONES EN PGP Y CAPITAS
					AND EXPSPRE.CNSEXPS IS  NULL AND EXPSSER.CNSEXPS IS  NULL -- PORQUE SON EXCEPCIONES	
					-- 
            ) A
      UNION ALL
      -- CITAS - APLICACION DE MEDICAMENTOS
	   SELECT A.FECHA, A.IDTERCERO, A.IDPLAN, A.IDTERCEROCA, A.IDPLANCA, A.IDAREA, A.CCOSTO,
				    A.IDSERVICIO, A.CANTIDAD, A.VALOR, A.VALORCOPAGO, A.VALORPCOMP, A.VALOREXCEDENTE, A.DESCUENTO,
				    A.NOADMISION, A.NOPRESTACION, A.NOITEM, A.FACTURADA, A.N_FACTURA, A.PROCEDENCIA, A.IDAFILIADO, A.IDMEDICO,
                A.CLASEORDEN, A.IDPESPECIAL, A.RIESGO, A.NOCOBRABLE,A.IDSEDE,A.MARCAFAC,A.USUMARCA,A.CNSFACT,NOAUTORIZACION,A.TIPOCOPAGO,A.CODUNG,A.ENCAJA,
                0 AS AUTAUDITADO, 0 AS EXONERACION, 0 AS VALORCOPAGO_EXONERA, 'N/A' AS TIPO_EXONERACION, A.ANOMES, 1 ESAPLIM
		   FROM   (SELECT	CIT.FECHA, CIT.IDCONTRATANTE IDTERCERO, CIT.IDPLAN, CIT.CCOSTO,
						   CASE WHEN CIT.IDTERCEROCA IS NULL OR CIT.IDTERCEROCA='' THEN CIT.IDCONTRATANTE ELSE CIT.IDTERCEROCA END IDTERCEROCA,
						   CIT.IDPLAN IDPLANCA, CIT.IDAREA, APLIMF.IDSERVICIO,
						   CASE WHEN COALESCE(CANTIDADC,0)=0 THEN 1 ELSE CANTIDADC END CANTIDAD,
						   ISNULL(CIT.VALORTOTAL,0) VALOR,
						   ISNULL(CIT.VALORCOPAGO,0) VALORCOPAGO,
						   0 VALORPCOMP,
						   CASE ISNULL(CIT.VALOREXEDENTE,0) WHEN 0 THEN ISNULL(CIT.VALORTOTAL,0)-ISNULL(CIT.VALORCOPAGO,0) ELSE CIT.VALOREXEDENTE END VALOREXCEDENTE,
						   0 DESCUENTO,
						   CONVERT(VARCHAR, APLIMF.ID) NOADMISION, CIT.CONSECUTIVO NOPRESTACION, 1  NOITEM,
						   ISNULL(CIT.FACTURADA,0) FACTURADA, CIT.N_FACTURA, 'APLIM' PROCEDENCIA, CIT.IDAFILIADO, CIT.IDMEDICO,
                     CIT.CLASEORDEN, COALESCE(CIT.IDPESPECIAL,'') IDPESPECIAL, COALESCE(CIT.RIESGO,'') RIESGO,CASE WHEN  COALESCE(FACTURABLE,0)=1 THEN 0 ELSE 1 END AS NOCOBRABLE,
                     COALESCE(CIT.IDSEDE,'') IDSEDE,COALESCE(MARCAFAC,0)MARCAFAC , COALESCE(USUARIONOFACTURABLE,'') AS USUMARCA,CNSFACT,NOAUTORIZACION,
                     CIT.TIPOCOPAGO,CIT.CODUNG,
                     CASE WHEN EXISTS(SELECT NOADMISION FROM DBO.FCJ WHERE NOADMISION=CIT.CONSECUTIVO AND PROCEDENCIA='CITAS' AND ESTADO='P' AND CERRADA=1) THEN 1 ELSE 0 END ENCAJA
