CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NCONDBD
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @DATO			NVARCHAR(MAX)
DECLARE  @PARAMETROS	NVARCHAR(MAX),	@MODELO		VARCHAR(100),   @METODO		VARCHAR(100),	@USUARIO	VARCHAR(20)
DECLARE	 @PROCESO		VARCHAR(20)
DECLARE  @CODCONCEPTO	VARCHAR(20),	@ITEM			DECIMAL(14,0),		@PRIORIDAD_CONDICION	SMALLINT
DECLARE	 @PRIORIDAD		SMALLINT,		@FACTOR			DECIMAL(14,6),		@OPERACION				VARCHAR(2)
DECLARE  @PRIORIDADEDITE	SMALLINT
DECLARE	 @PARAMETRO		VARCHAR(20)
DECLARE	 @VALOR			DECIMAL(14,6)		
DECLARE  @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)
	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
				SELECT  @CODCONCEPTO = CODCONCEPTO, @ITEM = ITEM,
						@PRIORIDAD = PRIORIDAD, @PRIORIDAD_CONDICION = PRIORIDAD_CONDICION,
						@FACTOR	 = FACTOR, @OPERACION = OPERACION, @VALOR = VALOR,
						@PROCESO = PROCESO, @PARAMETRO = PARAMETRO
				FROM	OPENJSON (@PARAMETROS) 
				WITH	(
					CODCONCEPTO				VARCHAR(20)			'$.CODCONCEPTO',
					ITEM					DECIMAL(14,0)		'$.ITEM',
					PRIORIDAD				SMALLINT			'$.PRIORIDAD',
					PRIORIDAD_CONDICION		SMALLINT			'$.PRIORIDAD_CONDICION',
					FACTOR					DECIMAL(14,6)		'$.FACTOR',
					OPERACION				VARCHAR(2)			'$.OPERACION',
					VALOR					DECIMAL(14,6)		'$.VALOR',
					PARAMETRO				VARCHAR(20)			'$.PARAMETRO',
					PROCESO					VARCHAR(20)			'$.PROCESO'
				)
				IF UPPER(@PROCESO) = 'INSERTAR'
				BEGIN
					BEGIN TRY
								INSERT INTO @TBLERRORES(ERROR) 
								SELECT CONCAT('LA PRIORIDAD ',@PRIORIDAD, ' YA SE ENCUENTRA REGISTRADO INGRESE UNA PRIORIDAD DIFERENTE')
								WHERE EXISTS (SELECT 1 FROM NCONDBD WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM AND PRIORIDAD_CONDICION = @PRIORIDAD_CONDICION AND PRIORIDAD = @PRIORIDAD)
								IF(SELECT COUNT(*) FROM @TBLERRORES) <= 0
							BEGIN
								INSERT INTO NCONDBD (CODCONCEPTO ,ITEM ,PRIORIDAD_CONDICION ,PRIORIDAD 
								,FACTOR ,OPERACION ,PARAMETRO ,VALOR )   
								SELECT @CODCONCEPTO,@ITEM,@PRIORIDAD_CONDICION, @PRIORIDAD, @FACTOR, @OPERACION,
								@PARAMETRO, @VALOR
							END
					END TRY
					BEGIN CATCH
						INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
					END CATCH

					IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
					BEGIN
						SELECT 'KO' OK
						SELECT ERROR FROM @TBLERRORES
						RETURN
					END

					SELECT 'OK' OK 
					RETURN
					END
				
				IF UPPER(@PROCESO) = 'EDITAR'
					BEGIN
						BEGIN TRY
						SELECT @DATO = DATO       
							  FROM   OPENJSON (@PARAMETROS)
							  WITH (DATO NVARCHAR(MAX) AS JSON)   
							  
							  SELECT @PRIORIDADEDITE = PRIORIDADEDITE
							  FROM   OPENJSON (@DATO)
							  WITH   (   
							  PRIORIDADEDITE		SMALLINT		 '$.PRIORIDADEDITE'
							  )

								BEGIN
									UPDATE NCONDBD SET PRIORIDAD = @PRIORIDAD,FACTOR = @FACTOR 
									,OPERACION = @OPERACION ,PARAMETRO = @PARAMETRO ,VALOR = @VALOR
									WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM AND 
									PRIORIDAD_CONDICION = @PRIORIDAD_CONDICION  AND PRIORIDAD = @PRIORIDADEDITE
								END
						END TRY

						BEGIN CATCH
							INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
						END CATCH

						IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
						BEGIN
							SELECT 'KO' OK
							SELECT ERROR FROM @TBLERRORES
							RETURN
						END

						SELECT 'OK' OK 
						RETURN
					END

			END TRY

			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
			END CATCH

			IF(SELECT COUNT(*) FROM @TBLERRORES) >0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END

			SELECT 'OK' OK

	END

	IF @METODO = 'GET_NCONDB_DETALLE'
		BEGIN
			SELECT @CODCONCEPTO = CODCONCEPTO, @PRIORIDAD_CONDICION = PRIORIDAD_CONDICION    
					FROM   OPENJSON (@PARAMETROS)
					WITH   (
					CODCONCEPTO				VARCHAR(20)			'$.CODCONCEPTO',
					PRIORIDAD_CONDICION		SMALLINT			'$.PRIORIDAD_CONDICION'
					) 
			SELECT 'OK' OK
			SELECT *
			FROM NCONDBD
			WHERE CODCONCEPTO = JSON_VALUE(@PARAMETROS, '$.CODCONCEPTO') AND PRIORIDAD_CONDICION = JSON_VALUE(@PARAMETROS, '$.PRIORIDAD_CONDICION')
			RETURN
		END

		IF @METODO = 'ELIMINAR'
			BEGIN
					SELECT  @CODCONCEPTO = CODCONCEPTO, @ITEM = ITEM, @PRIORIDAD = PRIORIDAD, 
					@PRIORIDAD_CONDICION = PRIORIDAD_CONDICION
					FROM	OPENJSON (@PARAMETROS) 
					WITH(
						CODCONCEPTO			VARCHAR(20)			'$.CODCONCEPTO',
						ITEM				DECIMAL(14,0)		'$.ITEM',
						PRIORIDAD_CONDICION	SMALLINT			'$.PRIORIDAD_CONDICION',
						PRIORIDAD			SMALLINT			'$.PRIORIDAD'
						)

			BEGIN TRY
					DELETE FROM NCONDBD WHERE CODCONCEPTO = @CODCONCEPTO AND ITEM = @ITEM AND PRIORIDAD = @PRIORIDAD AND PRIORIDAD_CONDICION = @PRIORIDAD_CONDICION
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
				END CATCH

				IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
				BEGIN
					SELECT 'KO' OK
					SELECT ERROR FROM @TBLERRORES
					RETURN
				END
		SELECT 'OK' OK
		END
END
