OR ABS((SELECT VLR_NETO FROM dbo.FCXP WHERE CNSFCXP = N'01CM000848') - 27053205.00) > 0.02
OR ABS((SELECT VLR_NETO FROM dbo.FCXP WHERE CNSFCXP = N'03CM002017') - 65877570.25) > 0.02
OR ABS((SELECT VLR_IVA FROM dbo.FCXP WHERE CNSFCXP = N'03CM002017') - 3237595.25) > 0.02
OR ABS((SELECT VLR_NETO FROM dbo.FCXP WHERE CNSFCXP = N'03CM002403') - 75364857.58) > 0.02
OR ABS((SELECT VLR_IVA FROM dbo.FCXP WHERE CNSFCXP = N'03CM002403') - 775.58) > 0.02
