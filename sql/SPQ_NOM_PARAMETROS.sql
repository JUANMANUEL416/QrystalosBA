CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_PARAMETROS
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @PARAMETROS		NVARCHAR(MAX),	@MODELO			VARCHAR(100),   @METODO		VARCHAR(100),	@USUARIO	VARCHAR(20)
DECLARE	 @PROCESO			VARCHAR(20)
DECLARE  @CODPARAMETRO		VARCHAR(20),	@DESCRIPCION	VARCHAR(255),		@INICIAL	SMALLINT
	
DECLARE  @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

	IF @METODO = 'GUARDAR'
		BEGIN
			BEGIN TRY
				SELECT  @CODPARAMETRO = CODPARAMETRO, @DESCRIPCION = DESCRIPCION, @INICIAL = INICIAL,
						@PROCESO = PROCESO
				FROM	OPENJSON (@PARAMETROS) 
				WITH	(
					CODPARAMETRO	VARCHAR(20)			'$.CODPARAMETRO',
					DESCRIPCION		VARCHAR(255)		'$.DESCRIPCION',
					INICIAL			SMALLINT			'$.INICIAL',
					PROCESO			VARCHAR(20)			'$.PROCESO'
				)
				IF UPPER(@PROCESO) = 'INSERTAR'
				BEGIN
					BEGIN TRY
					INSERT INTO @TBLERRORES(ERROR) 
						SELECT CONCAT('EL CODIGO ',@CODPARAMETRO, ' YA SE ENCUENTRA REGISTRADO')
						WHERE EXISTS (SELECT 1 FROM NPAR WHERE CODPARAMETRO = @CODPARAMETRO)

						IF(SELECT COUNT(*) FROM @TBLERRORES) <= 0
						BEGIN
							INSERT INTO NPAR (CODPARAMETRO ,DESCRIPCION,INICIAL)   
							SELECT @CODPARAMETRO, @DESCRIPCION, null
						END
					END TRY
					BEGIN CATCH
						INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
					END CATCH

					IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
					BEGIN
						SELECT 'KO' OK
						SELECT ERROR FROM @TBLERRORES
						RETURN
					END

					SELECT 'OK' OK 
					RETURN
				END
				
				IF UPPER(@PROCESO) = 'EDITAR'
					BEGIN
						BEGIN TRY
							UPDATE NPAR SET DESCRIPCION = @DESCRIPCION, CODPARAMETRO = @CODPARAMETRO
							WHERE CODPARAMETRO = @CODPARAMETRO
						END TRY

						BEGIN CATCH
							INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
						END CATCH

						IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
						BEGIN
							SELECT 'KO' OK
							SELECT ERROR FROM @TBLERRORES
							RETURN
						END

						SELECT 'OK' OK 
						RETURN
					END
			END TRY

			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
			END CATCH

			IF(SELECT COUNT(*) FROM @TBLERRORES) >0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END

			SELECT 'OK' OK
		END
END
