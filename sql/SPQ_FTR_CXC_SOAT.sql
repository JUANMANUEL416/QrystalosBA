CREATE OR ALTER PROCEDURE DBO.SPQ_FTR_CXC_SOAT
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @PARAMETROS	NVARCHAR(MAX),	@MODELO				VARCHAR(100),		@METODO		 VARCHAR(100)
DECLARE  @USUARIO		VARCHAR(20),	@NOADMISION			VARCHAR(20),		@CNSHACTRAN	 VARCHAR(20)
DECLARE	 @ITEM			INT,			@TIPOPOLIZA			VARCHAR(13),		@IDTERCERO	 VARCHAR(20)
DECLARE	 @IDPLAN		VARCHAR(6),		@IDASEGURADORA		VARCHAR(20),		@SMDLV		 DECIMAL(9)
DECLARE  @GASTADOANTES	DECIMAL(9),		@GASTADOANTESEXT	DECIMAL(9),			@HACTRANTOPE DECIMAL(9)
DECLARE  @HACTRANTOPE1	DECIMAL(9),		@TOPE1				DECIMAL(18,6),		@TOPE2		 DECIMAL(18,6)
DECLARE  @CUANTAS		INT = 0,		@IDTERCERO1			VARCHAR(20) = NULL,	@IDTERCERO2	 VARCHAR(20) = NULL
DECLARE  @EXISTE		INT = 0,		@IDSEDE				VARCHAR(5),			@COMPANIA    VARCHAR(2)
DECLARE  @NIT           VARCHAR(20),	@SYS_COMPUTERNAME	VARCHAR(254),		@FECHAFAC	DATETIME
DECLARE  @EXISTETERCONT VARCHAR(5),		@CANTIDAD			INT,				@CANTIDAD_ORI	INT
DECLARE  @PROCESO		VARCHAR(20), @PAGADOR VARCHAR(20)
DECLARE  @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)
   SELECT @IDSEDE=COALESCE(UBEQ.IDSEDE,USUSU.IDSEDE),@COMPANIA=COALESCE(UBEQ.COMPANIA,USUSU.COMPANIA),  @SYS_COMPUTERNAME=COALESCE(USUSU.SYS_ComputerName,HOST_NAME())   FROM USUSU LEFT JOIN UBEQ ON USUSU.SYS_ComputerName=UBEQ.SYS_ComputerName
    WHERE USUSU.USUARIO=@USUARIO
	IF @METODO = 'PREPARAR_HADM'
	BEGIN
		BEGIN TRY
			SELECT @NOADMISION = NOADMISION    
			FROM   OPENJSON (@PARAMETROS)
			WITH (NOADMISION VARCHAR(20) '$.NOADMISION') 

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'NO EXISTE ACCIDENTE DE TRÁNSITO'
			WHERE NOT EXISTS (
				SELECT 1 FROM HACTRAN 
				INNER JOIN HADM ON HADM.CNSHACTRAN = HACTRAN.CNSHACTRAN
				WHERE HACTRAN.IDAFILIADO = HADM.IDAFILIADO AND NOADMISION = @NOADMISION
			)

			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'NO EXISTE HACTRAND DE PROCEDENCIA QX'
			WHERE NOT EXISTS (
				SELECT TOP 1 * FROM HACTRAND 
				INNER JOIN HADM ON HADM.CNSHACTRAN = HACTRAND.CNSHACTRAN
				WHERE HACTRAND.PROCEDENCIA = 'QX' AND HACTRAND.NOREFERENCIA = @NOADMISION
			)

			IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
			BEGIN
				SET @SMDLV = ROUND((SELECT DBO.FNK_VALORVARIABLE('IDSMMLV')) / 30, 1)
				--PRINT '@SMDLV = ' + STR(@SMDLV)

				SELECT @CNSHACTRAN = CNSHACTRAN, @TIPOPOLIZA = TIPOPOLIZA, @IDTERCERO = IDTERCERO,
					@IDPLAN = IDPLAN
				FROM HADM WHERE NOADMISION = @NOADMISION		
				--PRINT '@CNSHACTRAN = ' + @CNSHACTRAN
				--PRINT '@TIPOPOLIZA = ' + @TIPOPOLIZA
				--PRINT '@IDTERCERO = ' + @IDTERCERO
				--PRINT '@IDPLAN = ' + @IDPLAN

				SELECT @HACTRANTOPE = TOPE, @HACTRANTOPE1 = TOPE1, @IDASEGURADORA = IDASEGURADORA
				FROM HACTRAN WHERE CNSHACTRAN = @CNSHACTRAN
				--PRINT '@HACTRANTOPE = ' + STR(@HACTRANTOPE)
				--PRINT '@HACTRANTOPE1 = ' + STR(@HACTRANTOPE1)
				--PRINT '@IDASEGURADORA = ' + @IDASEGURADORA

				SELECT @ITEM = ITEM FROM HACTRAND
				WHERE HACTRAND.CNSHACTRAN = @CNSHACTRAN
				AND HACTRAND.PROCEDENCIA = 'QX' AND HACTRAND.NOREFERENCIA = @NOADMISION
				--PRINT '@ITEM = ' + STR(@ITEM)

				SELECT @GASTADOANTES = COALESCE(SUM(HACTRAND.VLRGASTADO), 0) FROM HACTRAND
				WHERE HACTRAND.CNSHACTRAN = @CNSHACTRAN
				AND ITEM < @ITEM AND PROCEDENCIA <> 'EXTERNO'
				--PRINT '@GASTADOANTES = ' + STR(@GASTADOANTES)

				SELECT @GASTADOANTESEXT = COALESCE(SUM(HACTRAND.VLRGASTADO), 0) FROM HACTRAND
				WHERE HACTRAND.CNSHACTRAN = @CNSHACTRAN
				AND PROCEDENCIA = 'EXTERNO'
				--PRINT '@GASTADOANTESEXT = ' + STR(@GASTADOANTESEXT)

				SET @GASTADOANTES += @GASTADOANTESEXT
				--PRINT '@GASTADOANTESTOTAL = ' + STR(@GASTADOANTES)

				IF(@TIPOPOLIZA = 'Vigente' OR @TIPOPOLIZA = 'Aseg. D.2497')
				BEGIN
					IF(@HACTRANTOPE1 - @GASTADOANTES) <= 0
					BEGIN
						IF(@HACTRANTOPE - @GASTADOANTES) <= 0
						BEGIN
							SELECT 'KO' KO, 'NO EXISTE VALOR DISPONIBLE PARA FACTURAR ESTA ADMISIÓN DE ACCIDENTE DE TRÁNSITO' ERROR
							RETURN
						END
						ELSE
						BEGIN
							SET @TOPE1 = @HACTRANTOPE - @GASTADOANTES
							SET @CUANTAS = 1
							SET @IDTERCERO1 = DBO.FNK_VALORVARIABLE('IDNITFONSAT')
						END
					END
					ELSE
					BEGIN
						SET @TOPE1 = @HACTRANTOPE1 - @GASTADOANTES
						SET @TOPE2 = @HACTRANTOPE - @HACTRANTOPE1
						SET @CUANTAS = 2
						SET @IDTERCERO1 = @IDASEGURADORA
						SET @IDTERCERO2 = DBO.FNK_VALORVARIABLE('IDNITFONSAT')
					END
				END
				ELSE
				BEGIN
					SET @CUANTAS = 1
					SET @TOPE1 = @HACTRANTOPE - @GASTADOANTES
					SET @IDTERCERO1 = DBO.FNK_VALORVARIABLE('IDNITFONSAT')
				END

				-- JEDM 2010.12.02 REVISAR SI YA ESTA FACTURADA
				SELECT @EXISTE = COUNT(*) FROM HPRE INNER JOIN HPRED ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
				WHERE HPRE.NOADMISION = @NOADMISION
				AND COALESCE(FACTURADA,0) = 1 AND HPRED.IDTERCEROCA = @IDTERCERO AND HPRED.IDPLAN = @IDPLAN
				
				IF COALESCE(@EXISTE,0) > 0
				BEGIN
					INSERT INTO @TBLERRORES(ERROR) 
					SELECT 'ADMISION SOAT YA TIENE ITEMS FACTURADOS'
				END

				IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
				BEGIN
					-- ESTO ESTABA ANTES Y PODRIA CAUSAR PROBLEMAS SE DEBE REVISAR SU FUNCIONALIDAD
					UPDATE HPRED SET UTISOAT = 0, VLRFALTAAPLICARSOAT = 0, HPRED.FACTURADA = 0, HPRED.N_FACTURA = ''
					FROM HPRE WHERE HPRED.NOPRESTACION = HPRE.NOPRESTACION AND HPRE.NOADMISION = @NOADMISION

					EXEC DBO.SPQ_FTR_PROCESO_SOAT @NOADMISION, @TOPE1, @TOPE2, @CUANTAS, @IDTERCERO1, @IDTERCERO2
				END
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
	IF @METODO = 'FACTURAR_SOAT'
	BEGIN
		BEGIN TRY
			SELECT @NOADMISION = NOADMISION, @IDTERCERO1 = IDTERCERO1, @IDPLAN = IDPLAN, @NIT = NIT  
			FROM   OPENJSON (@PARAMETROS)
			WITH (
				NOADMISION	VARCHAR(20) '$.NOADMISION',	IDTERCERO1 VARCHAR(20) '$.IDTERCERO1',	IDPLAN VARCHAR(6) '$.IDPLAN',
				NIT			VARCHAR(20) '$.NIT'
			) 

			IF DBO.FNK_VALORVARIABLE('FACTSEDE') = 'SI'
			BEGIN
				SELECT @IDSEDE = IDSEDE FROM   HADM WHERE NOADMISION = @NOADMISION 
				IF DBO.FNK_VALORVARIABLE('FACTSEDEEQUIPO') = 'SI'
				BEGIN         
					SELECT @IDSEDE = COALESCE(UBEQ.IDSEDE,USUSU.IDSEDE), @COMPANIA = COALESCE(UBEQ.COMPANIA,USUSU.COMPANIA)
					FROM USUSU LEFT JOIN UBEQ ON USUSU.SYS_ComputerName=UBEQ.SYS_ComputerName
					WHERE USUARIO=@USUARIO
				END
			END
			ELSE
			BEGIN
				SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA, @SYS_COMPUTERNAME = SYS_ComputerName
				FROM USUSU WHERE USUARIO = @USUARIO
			END

			PRINT 'VALIDAR PERIODOS CONTABLES'
			SELECT @FECHAFAC = GETDATE()
         DECLARE @FECHA VARCHAR(20)=CONVERT(VARCHAR,@FECHAFAC,103)
			IF NOT EXISTS(SELECT * FROM PRI WHERE FECHA_INI<=@FECHAFAC AND FECHA_FIN>@FECHAFAC AND COALESCE(CERRADO,0)=0 AND COALESCE(CERRADO_FAC,0)=0)
			BEGIN      
            RAISERROR('PERIODO CONTABLE CERRADO O NO EXISTE %s, VERIFIQUE E INTENTELO DE NUEVO', 16, 1,@FECHA)
			END
			PRINT 'VALIDAR EXISTE TERCERO CONTABLE'
			IF @IDTERCERO1 = DBO.FNK_VALORVARIABLE('IDNITFONSAT')
			BEGIN
				SELECT @EXISTETERCONT = COALESCE(TIPOTERCONTABLE, 'NO') FROM PPT WHERE IDTERCERO = @IDTERCERO1 AND IDPLAN = DBO.FNK_VALORVARIABLE('IDPLANFONSAT')
			END
			ELSE
			BEGIN
				SELECT @EXISTETERCONT = COALESCE(TIPOTERCONTABLE, 'NO') FROM PPT WHERE IDTERCERO = @IDTERCERO1 AND IDPLAN = @IDPLAN
			END
			IF @EXISTETERCONT = 'NO'
			BEGIN
            RAISERROR('INCONSISTENCIA CONTABLE, NO EXISTE TIPO TERCERO CONTABLE. REVISAR CONTRATO', 16, 1)
			END
			IF 1 = 1 -- AQUI ESTA PENDIENTE REVISAR FnValidaDian2
			BEGIN
            PRINT 'ANTES DE LLAMAR AL SPK FACTURA...'
				BEGIN TRY
					IF @FECHAFAC <> ''
					BEGIN
						EXEC SPK_FACTURA_SOAT @NOADMISION, @COMPANIA, @IDSEDE, @USUARIO, @NIT, @SYS_COMPUTERNAME, 1, @FECHAFAC 
					END
					ELSE
					BEGIN
						EXEC SPK_FACTURA_SOAT @NOADMISION, @COMPANIA, @IDSEDE, @USUARIO, @NIT, @SYS_COMPUTERNAME, 0, NULL 
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES(ERROR) SELECT 'OCURRIÓ UN ERROR AL MOMENTO DE FACTURAR'
					INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
				END CATCH
			END		
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
	IF @METODO = 'FACTURAR_SOAT_TODO'
	BEGIN
		BEGIN TRY
			SELECT @NOADMISION = NOADMISION, @IDTERCERO1 = IDTERCERO1, @IDPLAN = IDPLAN, @NIT = NIT  
			FROM   OPENJSON (@PARAMETROS)
			WITH (
				NOADMISION	VARCHAR(20) '$.NOADMISION',	IDTERCERO1 VARCHAR(20) '$.IDTERCERO1',	IDPLAN VARCHAR(6) '$.IDPLAN',
				NIT			VARCHAR(20) '$.NIT'
			) 

			IF DBO.FNK_VALORVARIABLE('FACTSEDE') = 'SI'
			BEGIN
				SELECT @IDSEDE = IDSEDE FROM   HADM WHERE NOADMISION = @NOADMISION 
				IF DBO.FNK_VALORVARIABLE('FACTSEDEEQUIPO') = 'SI'
				BEGIN         
					SELECT @IDSEDE = COALESCE(UBEQ.IDSEDE,USUSU.IDSEDE), @COMPANIA = COALESCE(UBEQ.COMPANIA,USUSU.COMPANIA)
					FROM USUSU LEFT JOIN UBEQ ON USUSU.SYS_ComputerName=UBEQ.SYS_ComputerName
					WHERE USUARIO=@USUARIO
				END
			END
			ELSE
			BEGIN
				SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA, @SYS_COMPUTERNAME = SYS_ComputerName
				FROM USUSU WHERE USUARIO = @USUARIO
			END

			PRINT 'VALIDAR PERIODOS CONTABLES'
			SELECT @FECHAFAC = GETDATE()
         DECLARE @FECHA1 VARCHAR(20)=CONVERT(VARCHAR,@FECHAFAC,103)
			IF NOT EXISTS(SELECT * FROM PRI WHERE FECHA_INI<=@FECHAFAC AND FECHA_FIN>@FECHAFAC AND COALESCE(CERRADO,0)=0 AND COALESCE(CERRADO_FAC,0)=0)
			BEGIN
            RAISERROR('PERIODO CONTABLE CERRADO O NO EXISTE %s, VERIFIQUE E INTENTELO DE NUEVO', 16, 1,@FECHA1)
			END

			PRINT 'VALIDAR EXISTE TERCERO CONTABLE'
			IF @IDTERCERO1 = DBO.FNK_VALORVARIABLE('IDNITFONSAT')
			BEGIN
				SELECT @EXISTETERCONT = COALESCE(TIPOTERCONTABLE, 'NO') FROM PPT WHERE IDTERCERO = @IDTERCERO1 AND IDPLAN = DBO.FNK_VALORVARIABLE('IDPLANFONSAT')
			END
			ELSE
			BEGIN
				SELECT @EXISTETERCONT = COALESCE(TIPOTERCONTABLE, 'NO') FROM PPT WHERE IDTERCERO = @IDTERCERO1 AND IDPLAN = @IDPLAN
			END

			IF @EXISTETERCONT = 'NO'
			BEGIN
            RAISERROR('INCONSISTENCIA CONTABLE, NO EXISTE TIPO TERCERO CONTABLE. REVISAR CONTRATO', 16, 1)
			END

			IF 1 = 1 -- AQUI ESTA PENDIENTE REVISAR FnValidaDian2
			BEGIN
				BEGIN TRY
					IF @FECHAFAC <> ''
					BEGIN
						EXEC SPK_FACTURA_SOAT_TODO @NOADMISION, @COMPANIA, @IDSEDE, @USUARIO, @NIT, @SYS_COMPUTERNAME, 1, @FECHAFAC 
					END
					ELSE
					BEGIN
						EXEC SPK_FACTURA_SOAT_TODO @NOADMISION, @COMPANIA, @IDSEDE, @USUARIO, @NIT, @SYS_COMPUTERNAME, 0, NULL 
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES(ERROR) SELECT 'OCURRIÓ UN ERROR AL MOMENTO DE FACTURAR'
					INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
				END CATCH
			END		
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' OK
	END


	IF @METODO = 'TRANSFERIR_ITEM'
	BEGIN
		BEGIN TRY
			PRINT 'TRANSFERIR ITEM'
			SELECT @NOADMISION = NOADMISION, @ITEM = ITEM, @CANTIDAD = CANTIDAD, @CANTIDAD_ORI = CANTIDAD_ORI, @PROCESO = PROCESO,@PAGADOR=PAGADOR
			FROM   OPENJSON (@PARAMETROS)
			WITH (
					NOADMISION VARCHAR(20) '$.NOADMISION', ITEM INT '$.ITEM',	CANTIDAD INT '$.CANTIDAD'
				   ,CANTIDAD_ORI INT '$.CANTIDAD_ORI',	PROCESO VARCHAR(20) '$.PROCESO',PAGADOR VARCHAR(20) '$.PAGADOR'
			) 

			IF @PROCESO = 'BAJAR'
			BEGIN
				PRINT 'TRANSFERIR DE ASEG A ADRES'
				IF @CANTIDAD > 0 AND @CANTIDAD <= @CANTIDAD_ORI
				BEGIN
					UPDATE HADM_S SET CANTIDAD = CANTIDAD - @CANTIDAD, VLR_SERVICI = (CANTIDAD - @CANTIDAD) * VALOR, 
							VR_TOTAL = (CANTIDAD - @CANTIDAD ) * VALOR 
					WHERE NOADMISION = @NOADMISION	 AND ITEM = @ITEM

					INSERT INTO HADM_S(NOADMISION, FACTN, FECHA, DB_CR, AREAPRESTACION, AREAFUNCONT, UBICACION, VR_TOTAL, IMPUTACION
							, CCOSTO, PREFIJO, ANEXO, REFERENCIA, IDCIRUGIA, VALOR, VLR_SERVICI, CANTIDAD, VLR_COPAGOS, VLR_PAGCOMP
							, IDPROVEEDOR, SUBCCOSTO, NOPRESTACION, NOITEM, PCOSTO )
					SELECT @NOADMISION,CASE WHEN @PAGADOR='ADRES' THEN 2 WHEN @PAGADOR='EPS' THEN 3 ELSE 4 END , FECHA, DB_CR, AREAPRESTACION, AREAFUNCONT, UBICACION, @CANTIDAD * VALOR, IMPUTACION
							, CCOSTO, PREFIJO, ANEXO, REFERENCIA, IDCIRUGIA, VALOR, @CANTIDAD * VALOR, @CANTIDAD, VLR_COPAGOS, VLR_PAGCOMP
							, IDPROVEEDOR, SUBCCOSTO, NOPRESTACION, NOITEM, PCOSTO 
					FROM   HADM_S 
					WHERE  NOADMISION = @NOADMISION AND    ITEM       = @ITEM

					DELETE FROM HADM_S WHERE CANTIDAD = 0 AND NOADMISION = @NOADMISION
				END
				ELSE
				BEGIN
					INSERT INTO @TBLERRORES(ERROR) 
					SELECT 'NO SE PUEDE TRANSFERIR, CANTIDAD ORIGINAL MENOR A LO SOLICITADO.'
				END
			END

			IF @PROCESO = 'SUBIR'
			BEGIN
				PRINT 'TRANSFERIR DE ADRES A ASEG'
				IF @CANTIDAD > 0 AND @CANTIDAD <= @CANTIDAD_ORI
				BEGIN
					UPDATE HADM_S SET CANTIDAD = CANTIDAD - @CANTIDAD, VLR_SERVICI = (CANTIDAD-@CANTIDAD)* VALOR, 
								VR_TOTAL = (CANTIDAD - @CANTIDAD ) * VALOR 
					 WHERE NOADMISION = @NOADMISION	 AND ITEM = @ITEM

					 INSERT INTO HADM_S(NOADMISION, FACTN, FECHA, DB_CR, AREAPRESTACION, AREAFUNCONT, UBICACION, VR_TOTAL, IMPUTACION
							, CCOSTO, PREFIJO, ANEXO, REFERENCIA, IDCIRUGIA, VALOR, VLR_SERVICI, CANTIDAD, VLR_COPAGOS, VLR_PAGCOMP
							, IDPROVEEDOR, SUBCCOSTO, NOPRESTACION, NOITEM, PCOSTO )
					SELECT @NOADMISION, CASE WHEN @PAGADOR='ASEGURADORA' THEN 1 WHEN @PAGADOR='ADRES' THEN 2 WHEN @PAGADOR='EPS' THEN 3 ELSE 4 END, FECHA, DB_CR, AREAPRESTACION, AREAFUNCONT, UBICACION, @CANTIDAD * VALOR, IMPUTACION
							, CCOSTO, PREFIJO, ANEXO, REFERENCIA, IDCIRUGIA, VALOR, @CANTIDAD * VALOR, @CANTIDAD, VLR_COPAGOS, VLR_PAGCOMP
							, IDPROVEEDOR, SUBCCOSTO, NOPRESTACION, NOITEM, PCOSTO 
					FROM   HADM_S 
					WHERE  NOADMISION = @NOADMISION AND    ITEM       = @ITEM

					DELETE FROM HADM_S WHERE CANTIDAD = 0 AND NOADMISION = @NOADMISION
				END
				ELSE
				BEGIN
					INSERT INTO @TBLERRORES(ERROR) 
					SELECT 'NO SE PUEDE TRANSFERIR, CANTIDAD ORIGINAL MENOR A LO SOLICITADO.'
				END
			END

			IF(SELECT COUNT(*) FROM @TBLERRORES) <=0
			BEGIN
				SELECT 'OK' OK
				SELECT * FROM HADM_S WHERE NOADMISION = @NOADMISION
				SELECT * FROM HADM_T WHERE NOADMISION = @NOADMISION
			   SELECT TER.RAZONSOCIAL ASEGURADORA, HADM.IDPLAN,TER2.NIT NITADRES, TER2.RAZONSOCIAL ADRES, DBO.FNK_VALORVARIABLE('IDPLANFONSAT') PLANADRES,
            TER3.NIT ARL,TER3.RAZONSOCIAL RAZONSOCIALARL,TER4.NIT EPS,TER4.RAZONSOCIAL RAZONSOCIALEPS
            FROM HADM INNER JOIN TER ON TER.IDTERCERO = HADM.IDTERCERO
			             INNER JOIN TER TER2 ON TER2.IDTERCERO = DBO.FNK_VALORVARIABLE('IDNITFONSAT')
                      INNER JOIN AFI ON HADM.IDAFILIADO=AFI.IDAFILIADO
                      INNER JOIN TER TER4 ON AFI.IDADMINISTRADORA=TER4.IDTERCERO
                      LEFT  JOIN TER TER3 ON HADM.IDTERECEROARL=TER3.IDTERCERO
			   WHERE  NOADMISION = @NOADMISION
			END

		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END
END
