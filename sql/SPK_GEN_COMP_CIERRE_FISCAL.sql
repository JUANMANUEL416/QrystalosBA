IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME = 'SPK_GEN_COMP_CIERRE_FISCAL' AND XTYPE='P')
BEGIN
   DROP PROCEDURE SPK_GEN_COMP_CIERRE_FISCAL
END

GO
CREATE PROC DBO.SPK_GEN_COMP_CIERRE_FISCAL
@ANO         VARCHAR(4), 
@MES         INT,
@COMPROBANTE VARCHAR(2),  
@USUARIO     VARCHAR(12),
@COMPANIA    VARCHAR(2),
@SEDE        VARCHAR(5)        
WITH ENCRYPTION
AS
DECLARE @AUX    INT
DECLARE @NROCOMPROBANTE VARCHAR(20)
DECLARE @NOREFERENCIA   VARCHAR(20)
DECLARE @T4 DECIMAL(16,2), @T5 DECIMAL(16,2), @T6 DECIMAL(16,2), @PYG DECIMAL(16,2)
DECLARE @CUENTA_CIE VARCHAR(16), @CUENTA_UTI VARCHAR(16), @CUENTA_PER VARCHAR(16)
DECLARE @DB DECIMAL (16,2), @CR DECIMAL (16,2)
DECLARE @C4_CR DECIMAL (16,2),  @C4_DB DECIMAL (16,2), @C5_DB DECIMAL (16,2), @C5_CR DECIMAL (16,2), @C6_DB DECIMAL (16,2), @C6_CR DECIMAL (16,2)
BEGIN
   SELECT @AUX = COUNT(*) FROM SDCUEFIS  WHERE ANO = @ANO AND MES = @MES
   IF @AUX = 0
   BEGIN
      RAISERROR('NO HA PROCESADO CUENTAS PARA EL CIERRE FISCAL',16,1)
      RETURN
   END
   SELECT @AUX = COUNT(*) FROM PRI WHERE COALESCE(CIERREFISCAL,0) = 1  AND ANO = @ANO AND MES = @MES
   IF @AUX >0
   BEGIN
      RAISERROR('CIERRE FISCAL YA APLICADO.',16,1)
      RETURN
   END
   EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@MCP', @NROCOMPROBANTE OUTPUT 
--   SELECT @NROCOMPROBANTE = @SEDE + REPLACE(SPACE(8 - LEN(@NROCOMPROBANTE))+LTRIM(RTRIM(@NROCOMPROBANTE)),SPACE(1),0)
   
   EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@COM', @NOREFERENCIA OUTPUT  
   SELECT @NOREFERENCIA = @SEDE + REPLACE(SPACE(8 - LEN(@NOREFERENCIA))+LTRIM(RTRIM(@NOREFERENCIA)),SPACE(1),0)
   PRINT '@NROCOMPROBANTE='+@NROCOMPROBANTE
   
   INSERT INTO MCP (COMPANIA, NROCOMPROBANTE, PROCEDENCIA, NOREFERENCIA, ANO, MES,
                    FECHACONTABLE, TOTALDEBITO, TOTALCREDITO, REFERENCIA1,  USUARIO, FECHA, OBSERVACION, IDSEDE, ESTADO,
                    ANULADO, COMPROBANTE, MARCA, SYS_COMPUTERNAME_MARCA, IDTERCERO)
   SELECT @COMPANIA, @NROCOMPROBANTE, 'MANUAL', @NOREFERENCIA, @ANO, @MES, DBO.MY_FNK_DIA_DEL_MES(@ANO,@MES,'U'),
          0, 0, 'CIERRE FISCAL', @USUARIO, DBO.FNK_FECHA_SIN_HORA(GETDATE()), 'CIERRE FISCAL', @SEDE, 0, 0, @COMPROBANTE,
          0, NULL, DBO.FNK_VALORVARIABLE('IDTERCEROINSTALADO')
   
   INSERT INTO MCH (COMPANIA, NROCOMPROBANTE, CUENTA, TIPO, VALOR, DETALLE, REFERENCIA1, USUARIO, FECHA, 
                    CLASECONT, ESTADO, PROCESO, GENERA, PROCEDENCIA, REFERENCIA_PRO, CCOSTO, 
                    IDTERCERO, N_FACTURA, F_FACTURAREF, F_VENCE, CODUNG, CODPRG)
   SELECT @COMPANIA, @NROCOMPROBANTE, SDCUEFIS.CUENTA, 
          TIPO = CASE SDCUEFIS.NTZ WHEN 'DB' THEN CASE WHEN SF > 0 THEN 'CR' ELSE 'DB' END
                                   ELSE           CASE WHEN SF > 0 THEN 'DB' ELSE 'CR' END 
                 END, 
          VALOR= ABS(SF),
          CUE.NOMCUENTA, CUE.CUENTA, @USUARIO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), 'S', 1, 'ESTRES', 'Movimiento', 'ERESULTADOS',
          CUE.CUENTA, SDCUEFIS.CCOSTO, SDCUEFIS.IDTERCERO, '', NULL, NULL, '', '' 
   FROM   SDCUEFIS INNER JOIN CUE ON CUE.CUENTA = SDCUEFIS.CUENTA
   WHERE  SDCUEFIS.ANO   = @ANO
   AND    SDCUEFIS.MES   = @MES      
   AND    SDCUEFIS.SF   <> 0   
   AND    CUE.TIPO = 'Detalle'
     
   SELECT @DB=SUM(VALOR) FROM MCH WHERE TIPO='DB' AND NROCOMPROBANTE=@NROCOMPROBANTE
   SELECT @CR=SUM(VALOR) FROM MCH WHERE TIPO='CR' AND NROCOMPROBANTE=@NROCOMPROBANTE

   SELECT @C4_CR = SUM(VALOR) FROM MCH WHERE  LEFT(CUENTA,1) = '4' AND TIPO = 'CR'
   SELECT @C4_DB = SUM(VALOR) FROM MCH WHERE  LEFT(CUENTA,1) = '4' AND TIPO = 'DB'
   SELECT @C5_CR = SUM(VALOR) FROM MCH WHERE  LEFT(CUENTA,1) = '5' AND TIPO = 'CR'
   SELECT @C5_DB = SUM(VALOR) FROM MCH WHERE  LEFT(CUENTA,1) = '5' AND TIPO = 'DB'
   SELECT @C6_CR = SUM(VALOR) FROM MCH WHERE  LEFT(CUENTA,1) = '6' AND TIPO = 'CR'
   SELECT @C6_DB = SUM(VALOR) FROM MCH WHERE  LEFT(CUENTA,1) = '6' AND TIPO = 'DB'
   
   SELECT @PYG = (@C4_CR - @C4_DB) - (@C5_DB - @C5_CR) - (@C6_DB - @C6_CR)
            
   SELECT @CUENTA_CIE = CUENTA_CIE, @CUENTA_UTI = CUENTA_UTI,
          @CUENTA_PER = CUENTA_PER 
   FROM   KPRES
   WHERE  CODPRES = 'REST'
   
   INSERT INTO MCH (COMPANIA, NROCOMPROBANTE, CUENTA, TIPO, VALOR, DETALLE, REFERENCIA1, USUARIO, FECHA, 
                    CLASECONT, ESTADO, PROCESO, GENERA, PROCEDENCIA, REFERENCIA_PRO, CCOSTO, 
                    IDTERCERO, N_FACTURA, F_FACTURAREF, F_VENCE, CODUNG, CODPRG)       
   SELECT @COMPANIA, @NROCOMPROBANTE, CASE WHEN @PYG > 0 THEN @CUENTA_UTI ELSE @CUENTA_PER END,
          CASE WHEN @DB > @CR THEN 'CR' ELSE 'DB' END, ABS(@DB-@CR), NOMCUENTA, CASE WHEN @DB > @CR THEN @CUENTA_UTI ELSE @CUENTA_PER END, 
          @USUARIO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), 
          'S', 1, 'ESTRES', 'Movimiento', 'ERESULTADOS',
          CASE WHEN @DB > @CR THEN @CUENTA_UTI ELSE @CUENTA_PER END, '', '', '', NULL, NULL, '', ''  
   FROM   CUE 
   WHERE  CUE.CUENTA = CASE WHEN @DB > @CR THEN @CUENTA_UTI ELSE @CUENTA_PER END
   


   PRINT 'Revision del Comprobante...'
   EXEC SPK_REVISAR_COMPROBANTE @COMPANIA, @NROCOMPROBANTE
   EXEC SPK_SUMA_DBCR @NROCOMPROBANTE        
   
   UPDATE PRI SET CIERREFISCAL = 1 WHERE ANO = @ANO AND MES = @MES
END
