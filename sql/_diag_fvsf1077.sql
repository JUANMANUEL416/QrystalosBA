SET NOCOUNT ON;
DECLARE @NF VARCHAR(20) = N'FVSF1077';

IF NOT EXISTS (SELECT 1 FROM dbo.FTR WHERE N_FACTURA = @NF)
BEGIN
  SELECT N'NO_EXISTE_FTR' AS MSG;
  SELECT TOP 5 N_FACTURA, ESTADO, CONTABILIZADA FROM dbo.FTR WHERE N_FACTURA LIKE N'%1077%' AND N_FACTURA LIKE N'FV%';
END
ELSE
BEGIN
  SELECT N'FTR' AS SEC, * FROM dbo.FTR WHERE N_FACTURA = @NF;
  SELECT N'FTRD' AS SEC, * FROM dbo.FTRD WHERE N_FACTURA = @NF;
END

SELECT N'MCP' AS SEC, P.* FROM dbo.MCP P WHERE P.REFERENCIA1 = @NF OR P.NOREFERENCIA = @NF;
SELECT N'MCPE' AS SEC, E.* FROM dbo.MCPE E WHERE E.REFERENCIA1 = @NF OR E.NOREFERENCIA = @NF;

SELECT N'IMOV' AS SEC, M.CNSMOV, M.IDTIPOMOV, M.IDBODEGA, M.CONTABILIZADA, M.NROCOMPROBANTE, M.FECHAMOV, M.NODOCUMENTO, M.ESTADO, M.SECONTABILIZA
FROM dbo.IMOV M WHERE M.NODOCUMENTO = @NF;

SELECT N'IMOV_VC' AS SEC, M.CNSMOV, M.IDTIPOMOV, M.NROCOMPROBANTE, M.CONTABILIZADA, M.NODOCUMENTO
FROM dbo.IMOV M WHERE M.IDTIPOMOV = N'VC' AND M.FECHAMOV >= '2026-09-01' AND M.FECHAMOV < '2026-10-01'
  AND ABS(COALESCE((SELECT SUM(CAST(H.CANTIDAD AS FLOAT)*CAST(H.PCOSTO AS FLOAT)) FROM IMOVH H WHERE H.CNSMOV=M.CNSMOV),0) - 59200) < 1;
