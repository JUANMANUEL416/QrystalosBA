CREATE VIEW DBO.SERETPPCOSTO WITH SCHEMABINDING    
AS     
SELECT DISTINCT DBO.ETP.IDPROVEEDOR AS IDTERCERO,DBO.ETP.IDTARIFA,DBO.ETP.PREFIJO,    
         DBO.SER.IDSERVICIO,DBO.SER.DESCSERVICIO,DBO.SER.SEXO,DBO.IARTPCOSTO.PCOSTO AS VALOR,    
         DBO.ETP.FACTOR, DBO.ETP.IDPLAN,    
         ROUND(DBO.IARTPCOSTO.PCOSTO * DBO.ETP.FACTOR,0) AS VLRSERVICIO ,0 AS CIRUGIA,DBO.ETP.PAQUETE,DBO.ETP.TIPOCONTRATO COLLATE database_default AS TIPOCONTRATO, 
         '01/01/2000' AS FECHAINIFD ,GETDATE()+1  AS FECHAFINFD,
         DBO.SER.NIVELFUNCIONARIO,DBO.SER.NIVELSEDE,DBO.SER.MOBSOBLIGATORIA,DBO.SER.POS,
         DBO.SER.REQAUTORIZACION,DBO.SER.TIPOAUTORIZACION, 'NA' COLLATE database_default AS IDACUMULADOR, DBO.SER.MEDICAMENTOS,
         DBO.SER.IDARTICULO, DBO.SER.NIVELATENCION, DBO.SER.IDGENERICO, '01/01/2000' AS FECHAINI, 
         GETDATE()+1 AS FECHAFIN, '' AS CODIFICACION, DBO.SER.CODCUPS, DBO.SER.ESTADO
FROM   DBO.ETP INNER JOIN DBO.SER        ON DBO.ETP.PREFIJO     = DBO.SER.PREFIJO
               INNER JOIN DBO.PPT        ON DBO.ETP.IDPROVEEDOR = DBO.PPT.IDTERCERO 
                                        AND DBO.ETP.IDPLAN      = DBO.PPT.IDPLAN
               INNER JOIN DBO.IARTPCOSTO ON DBO.SER.IDSERVICIO  = DBO.IARTPCOSTO.IDSERVICIO
WHERE  DBO.ETP.FACTOR > 0   
--AND    DBO.SER.ESTADO <> 'Inactivo'    
AND    DBO.ETP.TIPORESTRICCION = 'PCosto' 
AND    COALESCE(DBO.IARTPCOSTO.PCOSTO,0) >= COALESCE(DBO.ETP.VALORINI ,0)
AND    COALESCE(DBO.IARTPCOSTO.PCOSTO,0) <= COALESCE(DBO.ETP.VALORFIN ,0)
AND    DBO.SER.IDSERVICIO NOT IN    
( SELECT DBO.ESP.IDSERVICIO    
  FROM   DBO.ESP    
  WHERE  DBO.ESP.IDPROVEEDOR = DBO.ETP.IDPROVEEDOR    
  AND    DBO.ESP.IDPLAN=DBO.ETP.IDPLAN )
