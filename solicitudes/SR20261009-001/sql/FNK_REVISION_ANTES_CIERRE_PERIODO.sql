CREATE OR ALTER FUNCTION DBO.FNK_REVISION_ANTES_CIERRE_PERIODO (
@ANO      VARCHAR(4),
@MES      SMALLINT
)
RETURNS @TABLA TABLE (
	MODULO VARCHAR(20),
	REFERENCIA VARCHAR(20),
	ERROR  VARCHAR(256)
)
WITH ENCRYPTION 
AS  
BEGIN	
	--Cuentas contables usadas en mch
	INSERT INTO @TABLA
	SELECT 'CONTABILIDAD',MCP.NROCOMPROBANTE,'MOVIMIENTOS CON CUENTAS DIFERENTE A DETALLE'
	FROM MCP INNER JOIN MCH ON MCP.NROCOMPROBANTE=MCH.NROCOMPROBANTE
            WHERE MCP.ESTADO=2
            AND MCP.ANO=@ANO
            AND MCP.MES=@MES
            AND COALESCE(MCP.ANULADO,0)<>1
            AND NOT EXISTS(SELECT * FROM CUE WHERE MCH.CUENTA=CUE.CUENTA AND TIPO='Detalle')
			AND COALESCE(MCH.VALOR,0) <> 0 -- Si el valor es cero no debe validar las cuenta por que no afecta en el procesode contabilizacion

	--INVENTARIO
	INSERT INTO @TABLA
	SELECT 'INVENTARIO',IMOV.CNSMOV,'MOVIMIENTOS CONFIRMADOS SIN CONTABLIZAR'
	FROM IMOV 
	WHERE YEAR(FECHACONF)=@ANO AND MONTH(FECHACONF)=@MES AND COALESCE(CONTABILIZADA,0)=0 AND COALESCE(SECONTABILIZA,0)=1 AND COALESCE(ESTADO,0)=1
   
    --NOTAD DBCR  
	INSERT INTO @TABLA
    SELECT 'NOTASDB-CR',FNOT.CNSFNOT,'NOTAS DB-CR  SIN CONTABLIZAR O PENDIENTES POR CONFIRMAR'
	FROM FNOT
    WHERE  COALESCE(ESTADO,'')<>'A' AND YEAR(F_NOTA)=@ANO AND YEAR(F_NOTA)=@MES AND COALESCE(CONTABILIZADA,0)=0 AND COALESCE(NROCOMPROBANTE,'')=''  
   
	--CAJA
	INSERT INTO @TABLA
    SELECT 'CAJA',FCJ.CODCAJA+' - '+FCJ.CNSFACJ,'RECIBOS DE CAJA  SIN CONTABLIZAR' FROM FCJ
    WHERE COALESCE(ESTADO,'')NOT IN('A','D') AND YEAR(FECHA)=@ANO AND MONTH(FECHA)=@MES AND COALESCE(CONTABILIZADA,0)=0 AND COALESCE(NROCOMPROBANTE,'')='' AND COALESCE(CERRADA,0)= 1 AND DEAPERTURA=0 UNION ALL
	SELECT 'CAJA',FCJ.CODCAJA+' - '+FCJ.CNSFACJ,'RECIBOS DE CAJA  PENDIENTES POR CONFIRMAR' FROM FCJ
    WHERE COALESCE(ESTADO,'')NOT IN('A','D') AND YEAR(FECHA)=@ANO AND MONTH(FECHA)=@MES AND COALESCE(CERRADA,0)=0 AND DEAPERTURA=0

	--NOMINA
	INSERT INTO @TABLA
    SELECT 'NOMINA',CNSPAGO,'NOMINAS PENDIENTES POR CERRAR ' FROM NPER
    WHERE ANO=@ANO AND MES=@MES AND CERRADO=0
   
	--CUENTAS POR PAGAR
	IF DBO.FNK_VALORVARIABLE('IDCON_FCONTABLE_CXP')='Radicacion'
	BEGIN
		INSERT INTO @TABLA
		SELECT 'CXP',CNSFCXP,'CUENTAS POR PAGAR PENDIENTES POR CONTABILIZAR ' FROM FCXP
		WHERE YEAR(FECHA)=@ANO AND MONTH(FECHA)=@MES AND COALESCE(CONTABILIZADA,0)=0 AND COALESCE(NROCOMPROBANTE,'')='' AND ESTADO<>'A'      
	END
	ELSE
	BEGIN
		INSERT INTO @TABLA
		SELECT 'CXP',CNSFCXP,'CUENTAS POR PAGAR PENDIENTES POR CONTABILIZAR ' FROM FCXP
		WHERE YEAR(F_FACTURAREF)=@ANO AND MONTH(F_FACTURAREF)=@MES AND COALESCE(CONTABILIZADA,0)=0 AND COALESCE(NROCOMPROBANTE,'')=''  AND ESTADO<>'A'     
	END

	--NOTAS CXP
	INSERT INTO @TABLA
    SELECT 'CXP DBCR',CNSFCXP,'NOTAS DE CUENTAS POR PAGAR PENDIENTES POR CONTABILIZAR ' FROM FCXPDBCR
    WHERE YEAR(FECHA)=@ANO AND MONTH(FECHA)=@MES AND COALESCE(CONTABILIZADA,0)=0
    AND EXISTS(SELECT * FROM FCXP WHERE FCXPDBCR.CNSFCXP=FCXP.CNSFCXP AND ESTADO<>'A')

		--NOTAS CXP
	INSERT INTO @TABLA
    SELECT 'CXP DBCR',CNSFCXP,'NOTAS DE CUENTAS POR PAGAR PENDIENTES POR CONTABILIZAR ' FROM FCXPDBCR
    WHERE YEAR(FECHA)=@ANO AND MONTH(FECHA)=@MES AND COALESCE(CONTABILIZADA,0)=0
    AND EXISTS(SELECT * FROM FCXP WHERE FCXPDBCR.CNSFCXP=FCXP.CNSFCXP AND ESTADO<>'A')

	--VALIDAR DUPLICADOS EN FCXP
	INSERT INTO @TABLA
	SELECT
		'CXP',
		CNSFCXP,
		'CXP DUPLICADA: ' + CNSFCXP + '. EXISTEN M�LTIPLES REGISTROS ACTIVOS'
	FROM FCXP
	WHERE YEAR(F_FACTURAREF)=@ANO
	AND MONTH(F_FACTURAREF)=@MES
	AND COALESCE(ESTADO,'')<>'A'
	GROUP BY CNSFCXP
	HAVING COUNT(*)>1

	--VALIDAR DUPLICADOS EN FCXPDBCR
	INSERT INTO @TABLA
	SELECT
		'CXP DBCR',
		CNSFCXP,
		'NOTA CXP DUPLICADA: ' + CNSFCXP + '. EXISTEN M�LTIPLES REGISTROS'
	FROM FCXPDBCR
	WHERE YEAR(FECHA)=@ANO
	AND MONTH(FECHA)=@MES
	GROUP BY CNSFCXP
	HAVING COUNT(*)>1

	--VALIDAR COMPROBANTES DUPLICADOS DE CXP
	INSERT INTO @TABLA
	SELECT
		'CXP',
		F.CNSFCXP,
		'CXP: ' + F.CNSFCXP + ' TIENE M�S DE UN COMPROBANTE CONTABLE VIGENTE'
	FROM FCXP F
	INNER JOIN MCP M ON M.REFERENCIA1=F.CNSFCXP
	WHERE YEAR(F.F_FACTURAREF)=@ANO
	AND MONTH(F.F_FACTURAREF)=@MES
	AND COALESCE(F.ESTADO,'')<>'A'
	AND RTRIM(M.PROCEDENCIA)='CXP'
	AND COALESCE(M.ANULADO,0)=0
	GROUP BY F.CNSFCXP
	HAVING COUNT(DISTINCT M.NROCOMPROBANTE)>1

	--VALIDAR COMPROBANTES DUPLICADOS DE NOTAS CXP
	INSERT INTO @TABLA
	SELECT
		'CXP DBCR',
		M.REFERENCIA1,
		'NOTA CXP: ' + M.REFERENCIA1 + ' TIENE M�S DE UN COMPROBANTE CONTABLE VIGENTE'
	FROM MCP M
	WHERE RTRIM(M.PROCEDENCIA)='NOTDBCRCXP'
	AND YEAR(M.FECHACONTABLE)=@ANO
	AND MONTH(M.FECHACONTABLE)=@MES
	AND COALESCE(M.ANULADO,0)=0
	GROUP BY M.REFERENCIA1
	HAVING COUNT(DISTINCT M.NROCOMPROBANTE)>1
   
	--RECAUDOS
	INSERT INTO @TABLA
    SELECT 'RECAUDOS',CNSFPAG,'RECUADOS  PENDIENTES POR CONTABILIZAR O POR APLICAR ' FROM FPAG
    WHERE YEAR(FECHA)=@ANO AND MONTH(FECHA)=@MES AND COALESCE(CONTABILIZADO,0)=0 AND COALESCE(NROCOMPROBANTE,'')='' AND COALESCE(ESTADO,'')<>'Inactivo' and coalesce(CERRADO,0)=1
   
	--RECAUDOS
	INSERT INTO @TABLA
    SELECT 'RECAUDOS',CNSFPAG,'RECUADOS  PENDIENTES POR CONTABILIZAR O POR APLICAR ' FROM FPAG
    WHERE YEAR(FECHA)=@ANO AND MONTH(FECHA)=@MES AND COALESCE(CONTABILIZADO,0)=0 AND COALESCE(NROCOMPROBANTE,'')='' AND COALESCE(ESTADO,'')<>'Inactivo' and coalesce(CERRADO,0)=1
  
	--BANCOS
	INSERT INTO @TABLA
    SELECT 'BANCOS',BANCO+' ITEM: '+CONVERT(varchar(10),ITEM),'CTA_BCO='+CTA_BCO+' FECHA: '+CONVERT(VARCHAR,FECHAOPERACION,103)+' MOVIENTO BANCARIO  PENDIENTES POR CONTABILIZAR O POR APLICAR '
	FROM BMOV    
    WHERE YEAR(COALESCE(FECHAOPERACION,FECHAOK))=@ANO AND MONTH(COALESCE(FECHAOPERACION,FECHAOK))=@MES AND COALESCE(CONTABILIZADA,0)=0 AND COALESCE(NROCOMPROBANTE,'')='' AND COALESCE(ESTADO,'')<>'A'          
   
	--CONCILIACIONES
	INSERT INTO @TABLA
    SELECT 'CONCILIACIONES',IDFCONCI,'CONCILIACION PENDIENTES POR CONTABILIZAR O POR APLICAR ' FROM FCONCI  
    WHERE YEAR(FECHACONC)=@ANO AND MONTH(FECHACONC)=@MES AND COALESCE(CONTABILIZADA,0)=0 AND COALESCE(NROCOMPROBANTE,'')=''
    AND EXISTS(SELECT 1 FROM FCONCID WHERE FCONCI.IDFCONCI=FCONCID.IDFCONCI AND FCONCID.VLRRECUPERAR>0)
   
	--RADICACION
	INSERT INTO @TABLA
    SELECT DISTINCT 'RADICACION',CNSCXC,'RADICACION PENDIENTES POR CONTABILIZAR' FROM FCXC 
    WHERE INDRECIBIDO=1 AND YEAR(F_RECIBIDO)=@ANO AND MONTH(F_RECIBIDO)=@MES AND COALESCE(NROCOMPROBANTE,'')='' AND OBSERVACION NOT IN('CXC GENERADA EN CAJA','VENTA DESDE FARMACIA')
   
	--CIERRE DE CARTERA INVENTARIOS Y CXP
	INSERT INTO @TABLA
	SELECT DISTINCT'CIERRE','CARTERA','SE DEBE CERRAR EL PERIODO DE CARTERA ANTES DE CERRAR CONTABILIDAD'
	FROM PRI WHERE ANO=@ANO AND MES=@MES AND COALESCE(CERRADO_CARTERA,0)=0

	--CIERRE DE CXP
	INSERT INTO @TABLA
	SELECT DISTINCT 'CIERRE','CXP','SE DEBE CERRAR EL PERIODO DE CXP ANTES DE CERRAR CONTABILIDAD'
	FROM PRI WHERE ANO=@ANO AND MES=@MES AND COALESCE(CERRADO_CXP,0)=0
   
	IF  DBO.FNK_VALORVARIABLE('CONTAB_ACTFIJO')='SI' --Para las empresas que no usan el modulo de activo fijo
	BEGIN 
		INSERT INTO @TABLA
		SELECT DISTINCT 'CIERRE','ACTIVOS','EXISTEN ACTIVOS A LOS QUE NO SE LE HA REALIZADO DEPRECIACION'
		FROM IACTD WHERE YEAR(FECHA)=@ANO AND MONTH(FECHA)=@MES AND COALESCE(CONTABILIZADA,0)<>1
	END
	RETURN
END
