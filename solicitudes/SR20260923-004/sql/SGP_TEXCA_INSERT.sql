IF EXISTS (SELECT NAME FROM SYS.OBJECTS WHERE NAME =  'SGP_TEXCA_INSERT' AND TYPE = 'P') 
	DROP PROC SGP_TEXCA_INSERT 
GO
CREATE PROCEDURE DBO.SGP_TEXCA_INSERT
  @IDTERCERO VARCHAR(20) = NULL
 ,@IDCATEGORIA VARCHAR(10) = NULL
 ,@ESTADO VARCHAR(10) = NULL
 ,@TIPOIPS VARCHAR(2) = NULL
 ,@IDMEDICOEXT VARCHAR(20) = NULL
 ,@NOMBREALTERNO VARCHAR(100) = NULL
AS
BEGIN
 SET NOCOUNT OFF;

    INSERT INTO TEXCA(IDTERCERO,IDCATEGORIA,ESTADO,TIPOIPS,IDMEDICOEXT,NOMBREALTERNO)
    VALUES(@IDTERCERO,@IDCATEGORIA,@ESTADO,@TIPOIPS,@IDMEDICOEXT,@NOMBREALTERNO)
 END
