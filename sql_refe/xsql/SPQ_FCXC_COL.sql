      FROM   OPENJSON (@PARAMETROS)
      WITH (           
      CNSCXC  VARCHAR(20)   '$.CNSCXC',
      FECHA  VARCHAR(20)   '$.FECHA',
      GUIA  VARCHAR(20)   '$.GUIA'
      )
      IF EXISTS(SELECT  * FROM FCXC WHERE CNSCXC=@CNSCXC AND FENVIO IS NULL)  
      BEGIN
         BEGIN TRY           
             UPDATE FCXC SET FENVIO=@FECHARAD,QUIENRECIBIO=@USUARIO,NROGUIA=@NROGUIA WHERE CNSCXC=@CNSCXC                 
         END TRY
         BEGIN CATCH
                 INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
         END CATCH
      END
      ELSE
      BEGIN
         INSERT INTO @TBLERRORES(ERROR)
         SELECT 'La cuenta por Cobrar ya fue enviada, Verfique e intente de nuevo '
      END
      IF(SELECT COUNT(*) FROM @TBLERRORES)>0
      BEGIN
         SELECT 'KO' OK, ERROR FROM @TBLERRORES
          RETURN
      END
      SELECT 'OK' OK 
      RETURN 
   END  
   IF @METODO='ACTUALIZAR_RPDX_RADICACION'     
   BEGIN         
      SELECT @CNSCXC=CNSCXC,@CNSRPDX=CNSRPDX, @DATOS=[DATA]        
      FROM   OPENJSON (@PARAMETROS)
      WITH ( 
      CNSCXC  VARCHAR(20)   '$.CNSCXC',
      CNSRPDX  VARCHAR(20)   '$.CNSRPDX',
      [DATA] NVARCHAR(MAX) AS JSON 
      )
                 
      SELECT * INTO #FACTU       
      FROM   OPENJSON (@DATOS)
      WITH   ( 
      N_FACTURA  VARCHAR(20)   '$.N_FACTURA',
      NOREFERENCIAEXT  VARCHAR(20)   '$.NOREFERENCIAEXT',
      FECHA_RADICADO  VARCHAR(20)   '$.FECHA_RADICADO'
      ) 

      SELECT @IDSEDE= COALESCE(UBEQ.IDSEDE,USUSU.IDSEDE),@COMPANIA=UBEQ.COMPANIA 
      FROM USUSU LEFT JOIN UBEQ ON USUSU.SYS_ComputerName=UBEQ.SYS_ComputerName
      WHERE USUARIO=@USUARIO
      SELECT @MSEDE=MSEDE,@IDSEDEF=IDSEDE FROM FCXC WHERE CNSCXC=@CNSCXC
      IF @MSEDE=1 AND COALESCE(@IDSEDEF,'')<>''
      BEGIN
         SELECT @IDSEDE=@IDSEDEF
      END
      IF COALESCE(@CNSRPDX,'')=''
      BEGIN
         BEGIN TRY
            PRINT 'AQUI LLAMO A GENCONSECUTIVO @IDSEDE='+COALESCE(@IDSEDE,'SIN SEDE')  +COALESCE(@COMPANIA,'CIA') 
            SELECT @CNSRPDX=''
	         EXEC SPK_GENCONSECUTIVO @COMPANIA,@IDSEDE, '@RPDX', @CNSRPDX OUTPUT   
	         SELECT @CNSRPDX = @IDSEDE + REPLACE(SPACE(8 - LEN(@CNSRPDX))+LTRIM(RTRIM(@CNSRPDX)),SPACE(1),0)
	         PRINT '@CNSRPDX='+COALESCE(@CNSRPDX,'')                               
         END TRY
         BEGIN CATCH
               INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
         END CATCH
         IF(SELECT COUNT(*) FROM @TBLERRORES)>0
