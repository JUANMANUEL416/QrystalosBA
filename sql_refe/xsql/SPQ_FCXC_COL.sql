      UPDATE RPDX SET VALOR10=CASE WHEN  EXISTS( SELECT 1 FROM PRI WHERE FECHA_INI<=RPDX.FECHA1 AND FECHA_FIN>=RPDX.FECHA1 AND(CERRADO=1 OR CERRADO_CARTERA=1)) 
                                          OR NOT EXISTS(SELECT 2 FROM PRI WHERE FECHA_INI<=RPDX.FECHA1 AND FECHA_FIN>=RPDX.FECHA1 )
                                          THEN 1 ELSE  0 END
      WHERE CNS=@CNSRPDX
      
