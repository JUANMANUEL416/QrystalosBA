   IF @METODO = 'PRESUPUESTO_FCXC'
   BEGIN
      SELECT @CNSCXC = CNSCXC,
             @IDSEDEF = IDSEDE
      FROM   OPENJSON(@PARAMETROS)
      WITH (
         CNSCXC VARCHAR(20) '$.CNSCXC',
         IDSEDE VARCHAR(5)  '$.IDSEDE'
      )

      IF COALESCE(@CNSCXC, '') = ''
      BEGIN
         SELECT 'KO' KO, 'Debe indicar CNSCXC' ERROR
         RETURN
      END

      IF NOT EXISTS (SELECT 1 FROM FCXC WHERE CNSCXC = @CNSCXC)
      BEGIN
         SELECT 'KO' KO, 'Cuenta de cobro no encontrada' ERROR
         RETURN
      END

      IF NOT EXISTS (SELECT 1 FROM FCXCD WHERE CNSCXC = @CNSCXC)
      BEGIN
         SELECT 'KO' KO, 'La cuenta de cobro no tiene facturas en el detalle' ERROR
         RETURN
      END

      SELECT @MSEDE = MSEDE,
             @IDSEDEF = CASE WHEN COALESCE(@IDSEDEF, '') <> '' THEN @IDSEDEF ELSE IDSEDE END
      FROM   FCXC
      WHERE  CNSCXC = @CNSCXC

      IF @MSEDE = 1 AND COALESCE(@IDSEDEF, '') <> ''
      BEGIN
         SELECT @IDSEDE = @IDSEDEF
      END
      ELSE
      BEGIN
         SELECT @IDSEDE = IDSEDE
         FROM   FCXC
         WHERE  CNSCXC = @CNSCXC
      END

      IF COALESCE(@IDSEDE, '') = ''
      BEGIN
         SELECT 'KO' KO, 'Debe indicar IDSEDE' ERROR
         RETURN
      END

      IF COALESCE(DBO.FNK_VALORVARIABLE('PRESUP_CCOSTO'), '') = ''
      BEGIN
         SELECT 'KO' KO, 'No está configurada la variable PRESUP_CCOSTO (centro de costo presupuesto)' ERROR
         RETURN
      END

      IF COALESCE(DBO.FNK_VALORVARIABLE('PRESUP_TIPORECO'), '') = ''
      BEGIN
         SELECT 'KO' KO, 'No está configurada la variable PRESUP_TIPORECO (tipo de reconocimiento). Valor esperado: CUENTAC' ERROR
         RETURN
      END

      IF DBO.FNK_VALORVARIABLE('PRESUP_TIPORECO') <> 'CUENTAC'
      BEGIN
         SELECT 'KO' KO, 'PRESUP_TIPORECO debe ser CUENTAC para enviar facturas desde CxC' ERROR
         RETURN
      END

      INSERT INTO @TBLERRORES(ERROR)
      SELECT CONCAT(
                'Factura ',
                FTR.N_FACTURA,
                ' (fecha ',
                CONVERT(VARCHAR(10), FTR.F_FACTURA, 103),
                '): no existe presupuesto PTPTO vigente (FECHAINI/FECHAFIN) para esa fecha'
             )
      FROM   FCXCD
      INNER JOIN FTR ON FTR.N_FACTURA = FCXCD.N_FACTURA
      WHERE  FCXCD.CNSCXC = @CNSCXC
      AND    NOT EXISTS (
                SELECT 1
                FROM   PTPTO
                WHERE  PTPTO.FECHAINI <= FTR.F_FACTURA
                AND    PTPTO.FECHAFIN >= FTR.F_FACTURA
             )

      IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
      BEGIN
         SELECT 'KO' OK, ERROR FROM @TBLERRORES
         RETURN
      END

      BEGIN TRY
         DECLARE curFactPpto CURSOR LOCAL FAST_FORWARD FOR
            SELECT FCXCD.N_FACTURA
            FROM   FCXCD
            WHERE  FCXCD.CNSCXC = @CNSCXC
            ORDER BY FCXCD.N_FACTURA ASC

         OPEN curFactPpto
         FETCH NEXT FROM curFactPpto INTO @N_FACTURA

         WHILE @@FETCH_STATUS = 0
         BEGIN
            EXEC DBO.SPK_ENTREGA_FACTURA_PTTO
                 @N_FACTURA = @N_FACTURA,
                 @IDSEDE    = @IDSEDE

            IF NOT EXISTS (
               SELECT 1
               FROM   FTR
               WHERE  N_FACTURA = @N_FACTURA
               AND    COALESCE(ENPRESUPUESTO, 0) = 1
            )
            BEGIN
               INSERT INTO @TBLERRORES(ERROR)
               SELECT CONCAT('La factura ', @N_FACTURA, ' no quedó en presupuesto. Revise PTPTO vigente, rubro del plan (PLN.RUBRO) y variables PRESUP_CCOSTO / PRESUP_TIPORECO=CUENTAC')
            END

            FETCH NEXT FROM curFactPpto INTO @N_FACTURA
         END

         CLOSE curFactPpto
         DEALLOCATE curFactPpto

         IF (SELECT COUNT(*) FROM @TBLERRORES) = 0
         BEGIN
            UPDATE FCXC
            SET    ENPRESUPUESTO = 1
            WHERE  CNSCXC = @CNSCXC
         END
      END TRY
      BEGIN CATCH
         IF CURSOR_STATUS('local', 'curFactPpto') >= 0
         BEGIN
            IF CURSOR_STATUS('local', 'curFactPpto') = 1
               CLOSE curFactPpto
            DEALLOCATE curFactPpto
         END

         INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
      END CATCH

      IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
      BEGIN
         SELECT 'KO' OK, ERROR FROM @TBLERRORES
         RETURN
      END

      SELECT 'OK' OK
      RETURN
   END
