CREATE OR ALTER PROCEDURE DBO.SPQ_DOCXEMPQ
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @PARAMETROS	NVARCHAR(MAX),	@MODELO		VARCHAR(100),   @METODO		VARCHAR(100)
DECLARE  @USUARIO		VARCHAR(20),	@ITEM		INT,			@TIPODOC	VARCHAR(100)
DECLARE	 @DESCRIPCION	VARCHAR(255),	@CNS		VARCHAR(20),	@FECHA		DATE
DECLARE	 @PROCEDENCIA	VARCHAR(10),	@PROCFTR	VARCHAR(10),	@N_FACTURA	VARCHAR(20), @CNSFTR	VARCHAR(40)
DECLARE  @TIPOFAC		CHAR(1),		@NOADMISION	VARCHAR(20),	@MODO		VARCHAR(10)
DECLARE  @FECHAINI DATETIME, @FECHAFIN DATETIME, @IDTERCERO VARCHAR(20),@IDPLAN VARCHAR(6), @IDAFILIADO VARCHAR(20), @IDAFI VARCHAR(20)
		,@IDSEDE VARCHAR(5), @USUARIO_FCT	VARCHAR(20), @PREFIJO	VARCHAR(10), @FCTINI INT, @FCTFIN INT  ,@PLANTILLAS NVARCHAR(MAX)
		, @PREFIJO_SEDE VARCHAR(10), @CONFIGURACION NVARCHAR(MAX) = NULL, @TIPOS_DOCUMENTO NVARCHAR(MAX) = NULL, @EstaPermitido BIT
      ,@DOCUMENTOID VARCHAR(50), @PERIODO VARCHAR(7),@LISTA_DOCUMENTOS NVARCHAR(MAX)
		, @INCLUIR_HC BIT, @INCLUIR_DOCXTPO BIT, @INCLUIR_COMPSERVICIO BIT, @INCLUIR_FACTURA BIT
DECLARE  @TBLERRORES TABLE (ERROR VARCHAR(MAX))

CREATE TABLE #TempDocs (NOADMISION VARCHAR(20), MODO VARCHAR(10), IDAFILIADO VARCHAR(20), N_FACTURA	VARCHAR(20), CNSFTR	VARCHAR(40))
DECLARE @DOCXEMPQ AS TABLE (
	ITEM INT PRIMARY KEY IDENTITY(1, 1),
	TIPOITEM VARCHAR(20),
	DESCTIPOITEM VARCHAR(50),
	CNS VARCHAR(50),
	TIPODOC VARCHAR(100),
	DENOMINACION VARCHAR(200),
	CLASE VARCHAR(100),
	FECHA DATETIME,
	DETALLES NVARCHAR(MAX),
	USUARIO	VARCHAR(20),
	IDAFILIADO VARCHAR(20),
	N_FACTURA	VARCHAR(20),
	CNSFTR	VARCHAR(40),
	NOMBREAFI VARCHAR(124),
	DOCIDAFILIADO VARCHAR(20),
	PERIODO VARCHAR(6)
)

BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

	IF @METODO = 'GET_ANEXOS'
	BEGIN
		BEGIN TRY
			SELECT @PROCEDENCIA = JSON_VALUE(@PARAMETROS, '$.PROCEDENCIA')
				,@CNS = JSON_VALUE(@PARAMETROS, '$.CONSECUTIVO')
			PRINT '@PROCEDENCIA >'  + COALESCE(@PROCEDENCIA,' SIN @PROCEDENCIA')
			IF @PROCEDENCIA = 'FTR'
			BEGIN
				SET @N_FACTURA = @CNS
				SELECT @NOADMISION = NOREFERENCIA, @PROCFTR = PROCEDENCIA, @TIPOFAC = TIPOFAC FROM FTR WHERE N_FACTURA = @N_FACTURA
				IF @TIPOFAC = 'I'
				BEGIN
					INSERT INTO #TempDocs (NOADMISION, MODO) 
					SELECT @NOADMISION, CASE WHEN @PROCFTR = 'CI' THEN 'CIT' WHEN @PROCFTR = 'CE' THEN 'AUT' WHEN @PROCFTR = 'SALUD' THEN 'HADM' END 

					DECLARE DOCS_CURSOR CURSOR FOR
					SELECT NOADMISION, MODO FROM #TempDocs
				END
				IF @TIPOFAC = 'M'
				BEGIN
					DECLARE DOCS_CURSOR CURSOR FOR
					SELECT FTRD.NOADMISION, CASE WHEN FTR.PROCEDENCIA = 'CI' THEN 'CIT' WHEN FTR.PROCEDENCIA = 'CE' THEN 'AUT' WHEN FTR.PROCEDENCIA = 'SALUD' THEN 'HADM' END
					FROM FTR INNER JOIN FTRD ON FTRD.CNSFTR = FTR.CNSFCT WHERE FTR.N_FACTURA = @N_FACTURA
				END
			END
			ELSE
			BEGIN
				INSERT INTO #TempDocs (NOADMISION, MODO) 
				SELECT @CNS, @PROCEDENCIA
				
				DECLARE DOCS_CURSOR CURSOR FOR
				SELECT NOADMISION, MODO FROM #TempDocs
			END
			
			PRINT 'COMENCE EL CURSOR'
			OPEN DOCS_CURSOR    
			FETCH NEXT FROM DOCS_CURSOR    
			INTO @NOADMISION,@MODO
			WHILE @@FETCH_STATUS = 0    
			BEGIN 
				PRINT '@MODO >'  + COALESCE(@MODO,' SIN @MODO')
				PRINT '@NOADMISION >'  + COALESCE(@NOADMISION,' SIN @NOADMISION')

				IF @MODO = 'HADM'
				BEGIN
					INSERT INTO @DOCXEMPQ(TIPOITEM, DESCTIPOITEM, CNS, TIPODOC, DENOMINACION, CLASE, FECHA, DETALLES, USUARIO)
					SELECT 
						'HC',
						'Historia Clinica',
						HCA.CONSECUTIVO,
						HCA.CLASEPLANTILLA,
						MPL.DESCPLANTILLA,
						COALESCE(TGEN.DESCRIPCION,'Historia Clinica'),
						HCA.FECHA,
						( 
							SELECT
								CAST(0 AS BIT) AS ENEPICRISIS,
								CAST(COALESCE(MPL.IMPRIMEOM, 0) AS BIT) AS IMPRIMEOM,
								(
									SELECT DISTINCT HCATD.CODOM, HCCOM.DESCRIPCION FROM HCATD
									INNER JOIN HCCOM ON HCCOM.CODOM = HCATD.CODOM
									WHERE HCATD.CONSECUTIVO = HCA.CONSECUTIVO FOR JSON PATH
								) AS HCATD,
								ANTECEDENTE AS HCAAP
							FOR JSON PATH, WITHOUT_ARRAY_WRAPPER
						) AS DETALLES,
						@USUARIO
					FROM DBO.HADM WITH (NOLOCK) 
					INNER JOIN DBO.HCA ON HADM.NOADMISION=HCA.NOADMISION
					INNER JOIN DBO.MPL ON HCA.CLASEPLANTILLA=MPL.CLASEPLANTILLA
					LEFT JOIN DBO.TGEN ON MPL.CLASE=TGEN.CODIGO AND CAMPO='MPL:CLASE' AND TABLA='HC'
					LEFT JOIN DBO.HCAAP ON HCAAP.CONSECUTIVOHCA = HCA.CONSECUTIVO
					WHERE HCA.NOADMISION = @NOADMISION AND COALESCE(HCA.ANULADA,0)<>1 AND COALESCE(MPL.NOFACTURABLE,0)=0

					UNION ALL

					SELECT 
						'DX',
						'Laboratorios',
						LING.NOINGRESO,
						LORD.IDSERVICIO,
						SER.DESCSERVICIO,
						COALESCE(TGEN.DESCRIPCION,'LX-Laboratorio'),
						LORD.FECHARES,
						(
							SELECT 
								LORD.NORDEN AS NOPRESTACION,
								LORD.NOITEM,
								LING.TIPOINGRESO
							FOR JSON PATH, WITHOUT_ARRAY_WRAPPER
						) AS DETALLES,
						@USUARIO
					FROM DBO.HADM WITH (NOLOCK)
					INNER JOIN  DBO.LING  ON HADM.NOADMISION=LING.NOADMISION
					INNER JOIN DBO.LORD ON LING.NOINGRESO=LORD.NOINGRESO
					INNER JOIN DBO.SER  ON LORD.IDSERVICIO=SER.IDSERVICIO
					LEFT JOIN DBO.TGEN ON LING.AMBITOTR=TGEN.CODIGO
					WHERE HADM.NOADMISION = @NOADMISION 
					AND LORD.ESTADO='R' AND LING.TIPOINGRESO='A' AND TGEN.CAMPO='APOYODG_AMBITO' AND TGEN.TABLA='General'

					UNION ALL

					SELECT TOP 1
						'HBALI',
						'Tratamientos',
						HBALI.CNSHBALI,
						'HTRAT',
						'Hoja Tratamiento',
						'Hoja Tratamiento',
						HBALI.FECHA,
						(
							SELECT HBALI.NOADMISION, 'HBALI' AS TIPO FOR JSON PATH, WITHOUT_ARRAY_WRAPPER
						) AS DETALLES,
						@USUARIO 
					FROM DBO.HADM WITH (NOLOCK)
					INNER JOIN DBO.HBALI ON HADM.NOADMISION=HBALI.NOADMISION
					WHERE HBALI.NOADMISION = @NOADMISION

					UNION ALL

					SELECT 
						'FME',
						'Formulas Medicas',
						FME.NOCONSECUTIVO,
						'FORMULA',
						'Formula Medica',
						'Formula Medica',
						FME.FECHA,
						NULL,
						@USUARIO 
					FROM DBO.HADM WITH (NOLOCK)
					INNER JOIN DBO.FME ON HADM.NOADMISION=FME.NOADMISION
					WHERE FME.NOADMISION = @NOADMISION AND FME.PROCEDENCIA='QX'

					UNION ALL

					SELECT 
						'IME',
						'Incapacidades',
						IME.NOINCAPACIDAD,
						'INCAPACIDAD',
						'Incapacidad Medica',
						'Incapacidad Medica',
						IME.FECHA,
						NULL,
						@USUARIO 
					FROM DBO.HADM WITH (NOLOCK)
					INNER JOIN DBO.IME ON HADM.NOADMISION=IME.NOADMISION
					WHERE IME.NOADMISION = @NOADMISION

					UNION ALL

					SELECT 
						'DOCXTPO',
						'Documentos Escaneados',
						DOCXTPO.DOCUMENTOID,
						DOCXTPO.TIPODOC,
						DOCXTPO.DESCRIPCION,
						'Documento Escaneado',
						DOCXTPO.FECHA,
						( 
							SELECT DocNombre, DocExtension
							FROM DOCS WHERE DocumentoID = DOCXTPO.DOCUMENTOID
							FOR JSON PATH, WITHOUT_ARRAY_WRAPPER
						) AS DETALLES,
						@USUARIO 
					FROM DBO.HADM WITH (NOLOCK)
					INNER JOIN DBO.DOCXTPO ON HADM.IDAFILIADO=DOCXTPO.IDAFILIADO
					INNER JOIN DBO.DOCS ON DOCS.DocumentoID = DOCXTPO.DOCUMENTOID AND DOCS.DocExtension = '.pdf'
					WHERE HADM.NOADMISION = @NOADMISION	
					
					UNION ALL

					SELECT 
						'COMPSERVICIO',
						'Comprobantes Prestacion de Servicios',
						AUT.IDAUT,
						'COMPROBANTES',
						'Comprobante Prestacion de Servicio',
						'Comprobante Prestacion de Servicio',
						AUT.FECHA,
						NULL,
						@USUARIO 
					FROM DBO.HADM WITH (NOLOCK)
					INNER JOIN DBO.AUT ON HADM.NOADMISION=AUT.NOADMISION
					WHERE HADM.NOADMISION = @NOADMISION AND COALESCE(AUT.N_FACTURA,'')<>''
				END

				ELSE IF @MODO = 'CIT'
				BEGIN
					INSERT INTO @DOCXEMPQ(TIPOITEM, DESCTIPOITEM, CNS, TIPODOC, DENOMINACION, CLASE, FECHA, DETALLES, USUARIO)
					SELECT 
						'HC',
						'Historia Clinica',
						HCA.CONSECUTIVO,
						HCA.CLASEPLANTILLA,
						MPL.DESCPLANTILLA,
						COALESCE(TGEN.DESCRIPCION,'Historia Clinica'),
						HCA.FECHA,
						( 
							SELECT
								CAST(0 AS BIT) AS ENEPICRISIS,
								CAST(COALESCE(MPL.IMPRIMEOM, 0) AS BIT) AS IMPRIMEOM,
								(
									SELECT DISTINCT HCATD.CODOM, HCCOM.DESCRIPCION FROM HCATD
									INNER JOIN HCCOM ON HCCOM.CODOM = HCATD.CODOM
									WHERE HCATD.CONSECUTIVO = HCA.CONSECUTIVO FOR JSON PATH
								) AS HCATD,
								ANTECEDENTE AS HCAAP
							FOR JSON PATH, WITHOUT_ARRAY_WRAPPER
						) AS DETALLES,
						@USUARIO
					FROM DBO.CIT WITH (NOLOCK) 
					INNER JOIN DBO.HCA ON CIT.CONSECUTIVO=HCA.NOADMISION
					INNER JOIN DBO.MPL ON HCA.CLASEPLANTILLA=MPL.CLASEPLANTILLA
					LEFT JOIN DBO.TGEN ON MPL.CLASE=TGEN.CODIGO AND CAMPO='MPL:CLASE' AND TABLA='HC'
					LEFT JOIN DBO.HCAAP ON HCAAP.CONSECUTIVOHCA = HCA.CONSECUTIVO
					WHERE HCA.NOADMISION = @NOADMISION AND COALESCE(HCA.ANULADA,0)<>1 AND COALESCE(MPL.NOFACTURABLE,0)=0
				
					UNION ALL

					SELECT 
						'DX',
						'Laboratorios',
						LING.NOINGRESO,
						LORD.IDSERVICIO,
						SER.DESCSERVICIO,
						COALESCE(TGEN.DESCRIPCION,'LX-Laboratorio'),
						LORD.FECHARES,
						(
							SELECT 
								LORD.NORDEN AS NOPRESTACION,
								LORD.NOITEM,
								LING.TIPOINGRESO
							FOR JSON PATH, WITHOUT_ARRAY_WRAPPER
						) AS DETALLES,
						@USUARIO
					FROM DBO.CIT WITH (NOLOCK)
					INNER JOIN DBO.AUT ON CIT.CONSECUTIVO=AUT.CONSECUTIVOCIT
					INNER JOIN  DBO.LING  ON AUT.IDAUT=LING.NOADMISION
					INNER JOIN DBO.LORD ON LING.NOINGRESO=LORD.NOINGRESO
					INNER JOIN DBO.SER  ON LORD.IDSERVICIO=SER.IDSERVICIO
					LEFT JOIN DBO.TGEN ON LING.AMBITOTR=TGEN.CODIGO
					WHERE CIT.CONSECUTIVO = @NOADMISION 
					AND LORD.ESTADO='R' AND LING.TIPOINGRESO='A' AND TGEN.CAMPO='APOYODG_AMBITO' AND TGEN.TABLA='General'

					--UNION ALL

					--SELECT TOP 1
					--	'HBALI',
					--	'Tratamientos',
					--	HBALI.CNSHBALI,
					--	'HTRAT',
					--	'Hoja Tratamiento',
					--	'Hoja Tratamiento',
					--	HBALI.FECHA,
					--	(
					--		SELECT HBALI.NOADMISION, 'HBALI' AS TIPO FOR JSON PATH, WITHOUT_ARRAY_WRAPPER
					--	) AS DETALLES,
					--	@USUARIO 
					--FROM DBO.CIT WITH (NOLOCK)
					--INNER JOIN DBO.HBALI ON CIT.CONSECUTIVO=HBALI.NOADMISION
					--WHERE HBALI.NOADMISION = @NOADMISION

					UNION ALL

					SELECT 
						'FME',
						'Formulas Medicas',
						FME.NOCONSECUTIVO,
						'FORMULA',
						'Formula Medica',
						'Formula Medica',
						FME.FECHA,
						NULL,
						@USUARIO 
					FROM DBO.CIT WITH (NOLOCK)
					INNER JOIN DBO.FME ON CIT.IDAFILIADO=FME.NOADMISION
					WHERE CIT.CONSECUTIVO = @NOADMISION AND FME.PROCEDENCIA='HCCE'

					UNION ALL

					SELECT 
						'IME',
						'Incapacidades',
						IME.NOINCAPACIDAD,
						'INCAPACIDAD',
						'Incapacidad Medica',
						'Incapacidad Medica',
						IME.FECHA,
						NULL,
						@USUARIO 
					FROM DBO.CIT WITH (NOLOCK)
					INNER JOIN DBO.IME ON CIT.CONSECUTIVO=IME.NOADMISION
					WHERE IME.NOADMISION = @NOADMISION

					UNION ALL

					SELECT 
						'DOCXTPO',
						'Documentos Escaneados',
						DOCXTPO.DOCUMENTOID,
						DOCXTPO.TIPODOC,
						DOCXTPO.DESCRIPCION,
						'Documento Escaneado',
						DOCXTPO.FECHA,
						( 
							SELECT DocNombre, DocExtension
							FROM DOCS WHERE DocumentoID = DOCXTPO.DOCUMENTOID
							FOR JSON PATH, WITHOUT_ARRAY_WRAPPER
						) AS DETALLES,
						@USUARIO 
					FROM DBO.CIT WITH (NOLOCK)
					INNER JOIN DBO.DOCXTPO ON CIT.IDAFILIADO=DOCXTPO.IDAFILIADO
					INNER JOIN DBO.DOCS ON DOCS.DocumentoID = DOCXTPO.DOCUMENTOID AND DOCS.DocExtension = '.pdf'
					WHERE CIT.CONSECUTIVO = @NOADMISION
				
					UNION ALL

					SELECT 
						'COMPSERVICIO',
						'Comprobantes Prestacion de Servicios',
						CIT.CONSECUTIVO,
						'COMPROBANTES',
						'Comprobante Prestacion de Servicio',
						'Comprobante Prestacion de Servicio',
						CIT.FECHA,
						NULL,
						@USUARIO 
					FROM DBO.CIT WITH (NOLOCK)
					WHERE CIT.CONSECUTIVO = @NOADMISION --AND COALESCE(CIT.N_FACTURA,'')<>''
				END

				ELSE IF @MODO = 'AUT'
				BEGIN
					INSERT INTO @DOCXEMPQ(TIPOITEM, DESCTIPOITEM, CNS, TIPODOC, DENOMINACION, CLASE, FECHA, DETALLES, USUARIO)
					SELECT 
						'HC',
						'Historia Clinica',
						HCA.CONSECUTIVO,
						HCA.CLASEPLANTILLA,
						MPL.DESCPLANTILLA,
						COALESCE(TGEN.DESCRIPCION,'Historia Clinica'),
						HCA.FECHA,
						( 
							SELECT
								CAST(0 AS BIT) AS ENEPICRISIS,
								CAST(COALESCE(MPL.IMPRIMEOM, 0) AS BIT) AS IMPRIMEOM,
								(
									SELECT DISTINCT HCATD.CODOM, HCCOM.DESCRIPCION FROM HCATD
									INNER JOIN HCCOM ON HCCOM.CODOM = HCATD.CODOM
									WHERE HCATD.CONSECUTIVO = HCA.CONSECUTIVO FOR JSON PATH
								) AS HCATD,
								ANTECEDENTE AS HCAAP
							FOR JSON PATH, WITHOUT_ARRAY_WRAPPER
						) AS DETALLES,
						@USUARIO
					FROM DBO.AUT WITH (NOLOCK) 
					INNER JOIN DBO.HCA ON AUT.NOAUT=HCA.NOADMISION
					INNER JOIN DBO.MPL ON HCA.CLASEPLANTILLA=MPL.CLASEPLANTILLA
					LEFT JOIN DBO.TGEN ON MPL.CLASE=TGEN.CODIGO AND CAMPO='MPL:CLASE' AND TABLA='HC'
					LEFT JOIN DBO.HCAAP ON HCAAP.CONSECUTIVOHCA = HCA.CONSECUTIVO
					WHERE AUT.NOAUT = @NOADMISION AND COALESCE(HCA.ANULADA,0)<>1 AND COALESCE(MPL.NOFACTURABLE,0)=0
					
					UNION ALL
					
					SELECT 
						'DX',
						'Laboratorios',
						LING.NOINGRESO,
						LORD.IDSERVICIO,
						SER.DESCSERVICIO,
						COALESCE(TGEN.DESCRIPCION,'LX-Laboratorio'),
						LORD.FECHARES,
						(
							SELECT 
								LORD.NORDEN AS NOPRESTACION,
								LORD.NOITEM,
								LING.TIPOINGRESO
							FOR JSON PATH, WITHOUT_ARRAY_WRAPPER
						) AS DETALLES,
						@USUARIO
					FROM DBO.AUT WITH (NOLOCK)
					INNER JOIN  DBO.LING  ON AUT.NOAUT=LING.NOPRESTACION
					INNER JOIN DBO.LORD ON LING.NOINGRESO=LORD.NOINGRESO
					INNER JOIN DBO.SER  ON LORD.IDSERVICIO=SER.IDSERVICIO
					LEFT JOIN DBO.TGEN ON LING.AMBITOTR=TGEN.CODIGO
					WHERE AUT.NOAUT = @NOADMISION 
					AND LORD.ESTADO='R' AND LING.TIPOINGRESO='C' AND TGEN.CAMPO='APOYODG_AMBITO' AND TGEN.TABLA='General'

					UNION ALL

					SELECT 
						'DOCXTPO',
						'Documentos Escaneados',
						DOCXTPO.DOCUMENTOID,
						DOCXTPO.TIPODOC,
						DOCXTPO.DESCRIPCION,
						'Documento Escaneado',
						DOCXTPO.FECHA,
						( 
							SELECT DocNombre, DocExtension
							FROM DOCS WHERE DocumentoID = DOCXTPO.DOCUMENTOID
							FOR JSON PATH, WITHOUT_ARRAY_WRAPPER
						) AS DETALLES,
						@USUARIO 
					FROM DBO.AUT WITH (NOLOCK)
					INNER JOIN DBO.DOCXTPO ON AUT.IDAFILIADO=DOCXTPO.IDAFILIADO
					INNER JOIN DBO.DOCS ON DOCS.DocumentoID = DOCXTPO.DOCUMENTOID AND DOCS.DocExtension = '.pdf'
					WHERE AUT.NOAUT = @NOADMISION	

					UNION ALL

					SELECT 
						'COMPSERVICIO',
						'Comprobantes Prestacion de Servicios',
						AUT.IDAUT,
						'COMPROBANTES',
						'Comprobante Prestacion de Servicio',
						'Comprobante Prestacion de Servicio',
						AUT.FECHA,
						(SELECT CAST(1 AS BIT) ISAUT FOR JSON PATH, WITHOUT_ARRAY_WRAPPER),
						@USUARIO 
					FROM DBO.AUT WITH (NOLOCK)
					WHERE AUT.NOAUT = @NOADMISION AND COALESCE(AUT.N_FACTURA,'')<>''
				END

				FETCH NEXT FROM DOCS_CURSOR    
				INTO @NOADMISION,@MODO
			END
			CLOSE DOCS_CURSOR
			DEALLOCATE DOCS_CURSOR

			PRINT 'TERMINE EL CURSOR'
			
			SELECT * FROM @DOCXEMPQ
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) >0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
	END

	IF @METODO = 'GET_ANEXOS_MASIVOS_V2'
	BEGIN
		BEGIN TRY

			IF DB_NAME() NOT IN ('PARTMEDICA','KARTMEDICA')
			BEGIN
				SELECT 'OK' OK
				RETURN
			END
			
			SELECT @PROCEDENCIA = JSON_VALUE(@PARAMETROS, '$.PROCEDENCIA'),
				   @CNS = JSON_VALUE(@PARAMETROS, '$.CONSECUTIVO');

			SELECT @FECHAINI=F_INIMAS, @FECHAFIN=F_FINMAS, @IDTERCERO=IDTERMAS,
				   @IDPLAN=IDPLANMAS, @IDSEDE=IDSEDE, @USUARIO_FCT=USUARIO_FCT,
				   @FCTINI=FCTINI, @FCTFIN=FCTFIN
			FROM OPENJSON (@PARAMETROS)
			WITH (
			   F_INIMAS DATE			'$.FILTROS.dateFrom',
			   F_FINMAS DATE			'$.FILTROS.dateTo',
			   IDTERMAS VARCHAR(20)		'$.FILTROS.aseguradora.IDTERCERO',
			   IDPLANMAS VARCHAR(20)	'$.FILTROS.plan.IDPLAN',
			   IDSEDE VARCHAR(5)		'$.FILTROS.sede.value',
			   USUARIO_FCT VARCHAR(12)	'$.FILTROS.facturador.USUARIO',
			   FCTINI INT				'$.FILTROS.facturaFrom',
			   FCTFIN INT				'$.FILTROS.facturaTo'
			);

			PRINT '@FECHAINI >'  + COALESCE(CONVERT(VARCHAR, @FECHAINI),' SIN @FECHAINI')
			PRINT '@FECHAFIN >'  + COALESCE(CONVERT(VARCHAR, @FECHAFIN),' SIN @FECHAFIN')
			PRINT '@IDTERCERO >'  + COALESCE(@IDTERCERO,' SIN @IDTERCERO')
			PRINT '@IDPLAN >'  + COALESCE(@IDPLAN,' SIN @IDPLAN')
			PRINT '@IDSEDE >'  + COALESCE(@IDSEDE,' SIN @IDSEDE')
			PRINT '@USUARIO_FCT >'  + COALESCE(@USUARIO_FCT,' SIN @USUARIO_FCT')
			PRINT '@FCTINI >'  + COALESCE(CAST(@FCTINI AS VARCHAR),' SIN @FCTINI')
			PRINT '@FCTFIN >'  + COALESCE(CAST(@FCTFIN AS VARCHAR),' SIN @FCTFIN')

			SELECT @CONFIGURACION = CONFIGURACION
			FROM DOC_ANEXOS_CONFIG
			WHERE IDTERCERO = @IDTERCERO AND ACTIVO = 1

			IF @CONFIGURACION IS NULL
			BEGIN
				SELECT @CONFIGURACION = CONFIGURACION
				FROM DOC_ANEXOS_CONFIG
				WHERE IDTERCERO = 'DEFAULT'	AND IDPLAN = 'DEFAUL' AND ACTIVO = 1
			END

			IF @CONFIGURACION IS NOT NULL
			BEGIN
				SET @TIPOS_DOCUMENTO = JSON_QUERY(@CONFIGURACION, '$.tiposDocumento')
			END

			PRINT 'Tipos de documento configurados: ' + ISNULL(@TIPOS_DOCUMENTO, 'NINGUNO')

			SELECT @PREFIJO_SEDE = PREFIJO FROM FDIAN WHERE IDENTIFICADOR=COALESCE(@IDSEDE,'01') AND VENCIDA=0 AND PROCEDENCIA = 'FTR'

			PRINT 'Prefijo: ' + ISNULL(@PREFIJO_SEDE, 'NULO')
			PRINT 'Factura desde: ' + ISNULL(CAST(@FCTINI AS VARCHAR), 'NULO')
