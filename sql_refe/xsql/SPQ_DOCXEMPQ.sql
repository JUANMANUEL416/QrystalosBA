				,P.DOCIDAFILIADO
				,P.TIPO_DOC
				,P.NOMBREAFI
				,P.IDPESPECIAL
				,P.FECHADX
				,(SELECT COUNT(*) FROM @SOPORTES S WHERE S.IDAFILIADO = P.IDAFILIADO) AS TOTAL_SOPORTES
