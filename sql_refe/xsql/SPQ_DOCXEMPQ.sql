			FROM @SOPORTES S
			LEFT JOIN TGEN TGEN_AC WITH (NOLOCK)
				ON  TGEN_AC.TABLA  = 'ALTOCOSTO'
				AND TGEN_AC.CAMPO  = 'CLASE_MPL_EXPORT'
				AND TGEN_AC.CODIGO = S.CLASEPLANTILLA
			ORDER BY S.IDAFILIADO, S.FECHA, S.CNS

		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		RETURN
	END

	-- =====================================================================
	-- GET_FACTURAS_ALTOCOSTO_MASIVO
	-- ---------------------------------------------------------------------
	-- Devuelve facturas emitidas de pacientes de alto costo para empaquetar
	-- soportes de factura (paquete, medicamentos, evento, etc.).
	--
	-- Con Unidad de Atención (@IDROL informado):
	--   Facturas de AUTORIZACIONES DE PROGRAMA (AUTPG) facturadas, filtradas
	--   por periodo (AUTPG.ANOMES), Unidad de Atención (ROL) via
	--   AUTPG.IDPESPECIAL -> MPE.IDROL y EPS (AUTPG.IDTERCEROCA / FTR.IDTERCERO).
	--
	-- Sin Unidad de Atención (@IDROL vacio/null):
	--   Todas las facturas emitidas del paciente para la EPS y el rango de
	--   fechas (FTR.F_FACTURA), incluyendo medicamentos, atenciones por evento
	--   y demas procedencias distintas de caja/financiero/inventario.
	--
	-- Si la EPS no tiene facturas para un paciente, el resumen lo incluye con
	-- TOTAL_FACTURAS = 0 (sin mezclar facturas de otras EPS).
	--
	-- Pensado para empaquetamiento masivo: un unico PDF por factura
	-- aunque la factura agrupe a varios pacientes (la deduplicación de
	-- la generación del PDF la hace el frontend con N_FACTURA como llave).
	--
	-- Parametros (en @PARAMETROS, formato JSON):
	--   - DOCUMENTOS  : CSV con DOCIDAFILIADO de pacientes (obligatorio)
	--   - FECHAINI    : DATE (obligatorio) - limite inferior del periodo
	--   - FECHAFIN    : DATE (obligatorio) - limite superior del periodo
	--   - IDROL       : VARCHAR (opcional) - Unidad de Atención
	--   - IDTERCERO   : VARCHAR (obligatorio) - EPS (tercero de caja)
	--
	-- Salida:
	--   - SELECT 'OK' OK
	--   - Resultset 1: resumen por paciente (DOCIDAFILIADO, TOTAL_FACTURAS)
	--   - Resultset 2: lista de combinaciones (paciente, factura) con
	--     metadatos suficientes para nombrar el PDF y reusarlo entre
	--     carpetas (CNSFCT, N_FACTURA, ANOMES, F_FACTURA).
	-- =====================================================================
	IF @METODO = 'GET_FACTURAS_ALTOCOSTO_MASIVO'
	BEGIN
		BEGIN TRY
			DECLARE @FACT_IDROL        VARCHAR(12)
			DECLARE @FACT_IDTERCERO    VARCHAR(20)
			DECLARE @FACT_FECHAINI_DT  DATE
			DECLARE @FACT_FECHAFIN_DT  DATE
			DECLARE @FACT_LISTA_DOCS   NVARCHAR(MAX)
			DECLARE @FACT_ANOMES_INI   CHAR(6)
			DECLARE @FACT_ANOMES_FIN   CHAR(6)
			DECLARE @FACT_TIENE_IDROL  BIT = 0
			DECLARE @FACT_FECHAFIN_EXC DATE

			SELECT @FACT_LISTA_DOCS = DOCUMENTOS
				,@FACT_FECHAINI_DT  = TRY_CONVERT(DATE, FECHAINI)
				,@FACT_FECHAFIN_DT  = TRY_CONVERT(DATE, FECHAFIN)
				,@FACT_IDROL		= IDROL_FILTRO
				,@FACT_IDTERCERO    = IDTERCERO
			FROM OPENJSON (@PARAMETROS)
			WITH (
			   DOCUMENTOS NVARCHAR(MAX)		'$.DOCUMENTOS',
			   FECHAINI VARCHAR(20)			'$.FECHAINI',
			   FECHAFIN VARCHAR(20)			'$.FECHAFIN',
			   IDROL_FILTRO VARCHAR(12)		'$.IDROL',
			   IDTERCERO VARCHAR(20)		'$.IDTERCERO'
			);

			-- ---------- Validaciones ----------
			IF @FACT_FECHAINI_DT IS NULL OR @FACT_FECHAFIN_DT IS NULL
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'FECHAINI y FECHAFIN son obligatorias y deben ser fechas validas (yyyymmdd o yyyy-mm-dd).'
			END

			IF @FACT_IDROL IS NOT NULL AND LTRIM(RTRIM(@FACT_IDROL)) <> ''
				SET @FACT_TIENE_IDROL = 1
			ELSE
				SET @FACT_IDROL = NULL

			IF @FACT_IDTERCERO IS NULL OR LTRIM(RTRIM(@FACT_IDTERCERO)) = ''
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'IDTERCERO (EPS) es obligatorio.'
			END

			IF @FACT_LISTA_DOCS IS NULL OR LTRIM(RTRIM(@FACT_LISTA_DOCS)) = ''
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'DOCUMENTOS (lista CSV de DOCIDAFILIADO) es obligatorio.'
			END

			IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END

			-- Rango por ANOMES (CHAR(6) 'yyyyMM') para usar el indice sobre AUTPG.ANOMES.
			-- Evita CAST/CONVERT sobre la columna en el WHERE (SARGable).
			SET @FACT_ANOMES_INI = CONVERT(CHAR(6), @FACT_FECHAINI_DT, 112) -- yyyymmdd ? toma primeros 6 = yyyymm
			SET @FACT_ANOMES_FIN = CONVERT(CHAR(6), @FACT_FECHAFIN_DT, 112)
			SET @FACT_FECHAFIN_EXC = DATEADD(DAY, 1, @FACT_FECHAFIN_DT)

			-- ---------- Pacientes ----------
			DECLARE @FACT_PACIENTES TABLE (
				IDAFILIADO    VARCHAR(20) NOT NULL,
				DOCIDAFILIADO VARCHAR(20) NOT NULL,
				TIPO_DOC      VARCHAR(3)  NULL,
				NOMBREAFI     VARCHAR(124) NULL,
				PRIMARY KEY (IDAFILIADO)
			)

			;WITH DOCS AS (
				SELECT DISTINCT LTRIM(RTRIM(value)) AS DOCID
				FROM STRING_SPLIT(@FACT_LISTA_DOCS, ',')
				WHERE LTRIM(RTRIM(value)) <> ''
			)
			INSERT INTO @FACT_PACIENTES (IDAFILIADO, DOCIDAFILIADO, TIPO_DOC, NOMBREAFI)
			SELECT
				 AFI.IDAFILIADO
				,AFI.DOCIDAFILIADO
				,AFI.TIPO_DOC
				,CONCAT_WS(' ', AFI.PNOMBRE, AFI.SNOMBRE, AFI.PAPELLIDO, AFI.SAPELLIDO)
			FROM DOCS
			INNER JOIN AFI WITH (NOLOCK) ON AFI.DOCIDAFILIADO = DOCS.DOCID

			-- ---------- Combinaciones (paciente, factura) ----------
			-- Una fila por (IDAFILIADO, N_FACTURA). Si una AUTPG produce varias
			-- veces el mismo par (varias autorizaciones por el mismo paciente
			-- contra la misma factura), se colapsan con DISTINCT.
			DECLARE @FACT_RESULT TABLE (
				IDAFILIADO    VARCHAR(20),
				DOCIDAFILIADO VARCHAR(20),
				TIPO_DOC      VARCHAR(3),
				NOMBREAFI     VARCHAR(124),
				N_FACTURA     VARCHAR(20),
				CNSFCT        VARCHAR(40),
				F_FACTURA     DATETIME,
				ANOMES        VARCHAR(6),
				IDPESPECIAL   VARCHAR(5),
				PRIMARY KEY (IDAFILIADO, N_FACTURA)
			)

			IF @FACT_TIENE_IDROL = 1
			BEGIN
				-- Modo paquete: AUTPG facturadas filtradas por unidad de atención (MPE.IDROL)
				INSERT INTO @FACT_RESULT (
					IDAFILIADO, DOCIDAFILIADO, TIPO_DOC, NOMBREAFI,
					N_FACTURA, CNSFCT, F_FACTURA, ANOMES, IDPESPECIAL
				)
				SELECT DISTINCT
					 P.IDAFILIADO
					,P.DOCIDAFILIADO
					,P.TIPO_DOC
					,P.NOMBREAFI
					,AP.N_FACTURA
					,FTR.CNSFCT
					,FTR.F_FACTURA
					,AP.ANOMES
					,AP.IDPESPECIAL
				FROM @FACT_PACIENTES P
				INNER JOIN AUTPG AP WITH (NOLOCK)
					ON AP.IDAFILIADO = P.IDAFILIADO
				INNER JOIN MPE WITH (NOLOCK)
					ON  MPE.IDPESPECIAL = AP.IDPESPECIAL
					AND MPE.IDROL       = @FACT_IDROL
				INNER JOIN FTR WITH (NOLOCK)
					ON FTR.N_FACTURA = AP.N_FACTURA
				WHERE AP.FACTURADO = 1
				  AND AP.N_FACTURA IS NOT NULL
				  AND LTRIM(RTRIM(AP.N_FACTURA)) <> ''
				  AND AP.ANOMES BETWEEN @FACT_ANOMES_INI AND @FACT_ANOMES_FIN
				  AND AP.IDTERCEROCA = @FACT_IDTERCERO
				  AND FTR.IDTERCERO = @FACT_IDTERCERO
				  AND FTR.ESTADO = 'P'
				  AND FTR.TIPOANULACION IS NULL
			END
			ELSE
			BEGIN
				-- Modo integral: todas las facturas emitidas del paciente para la EPS
				-- en el rango (medicamentos, evento, paquete, etc.).
				INSERT INTO @FACT_RESULT (
					IDAFILIADO, DOCIDAFILIADO, TIPO_DOC, NOMBREAFI,
					N_FACTURA, CNSFCT, F_FACTURA, ANOMES, IDPESPECIAL
				)
				SELECT DISTINCT
					 P.IDAFILIADO
					,P.DOCIDAFILIADO
					,P.TIPO_DOC
					,P.NOMBREAFI
					,FTR.N_FACTURA
					,FTR.CNSFCT
					,FTR.F_FACTURA
					,CONVERT(CHAR(6), FTR.F_FACTURA, 112)
					,AP.IDPESPECIAL
				FROM @FACT_PACIENTES P
				INNER JOIN FTR WITH (NOLOCK)
					ON  FTR.IDTERCERO = @FACT_IDTERCERO
					AND FTR.ESTADO = 'P'
					AND FTR.TIPOANULACION IS NULL
					AND FTR.N_FACTURA IS NOT NULL
					AND LTRIM(RTRIM(FTR.N_FACTURA)) <> ''
					AND FTR.F_FACTURA >= @FACT_FECHAINI_DT
					AND FTR.F_FACTURA < @FACT_FECHAFIN_EXC
					AND COALESCE(FTR.PROCEDENCIA, '') NOT IN ('CAJA', 'FINANCIERO', 'INVENTARIO')
				LEFT JOIN FTRD WITH (NOLOCK)
					ON  FTRD.CNSFTR = FTR.CNSFCT
					AND FTRD.IDAFI = P.IDAFILIADO
				OUTER APPLY (
					SELECT TOP 1 ap.IDPESPECIAL
					FROM AUTPG ap WITH (NOLOCK)
					WHERE ap.IDAFILIADO = P.IDAFILIADO
					  AND ap.N_FACTURA = FTR.N_FACTURA
					  AND ap.FACTURADO = 1
					ORDER BY ap.ANOMES DESC, ap.ID DESC
				) AP
				WHERE (
						FTR.IDAFILIADO = P.IDAFILIADO
					OR  FTRD.IDAFI IS NOT NULL
				)
			END

			-- ---------- Salidas ----------
			SELECT 'OK' OK

			-- Resumen por paciente (incluye los pacientes sin facturas para reportarlos)
			SELECT
				 P.IDAFILIADO
				,P.DOCIDAFILIADO
				,P.TIPO_DOC
				,P.NOMBREAFI
				,(SELECT COUNT(*) FROM @FACT_RESULT R WHERE R.IDAFILIADO = P.IDAFILIADO) AS TOTAL_FACTURAS
			FROM @FACT_PACIENTES P
			ORDER BY P.DOCIDAFILIADO

			-- Lista (paciente, factura) - una fila por par; el frontend dedupe la
			-- generación del PDF por N_FACTURA y replica el blob entre carpetas.
			SELECT
				 IDAFILIADO
				,DOCIDAFILIADO
				,TIPO_DOC
				,NOMBREAFI
				,N_FACTURA
				,CNSFCT
				,F_FACTURA
				,ANOMES
				,IDPESPECIAL
			FROM @FACT_RESULT
			ORDER BY IDAFILIADO, ANOMES, N_FACTURA

		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		RETURN
	END
END

