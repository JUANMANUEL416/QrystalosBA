				,(SELECT COUNT(*) FROM @SOPORTES S WHERE S.IDAFILIADO = P.IDAFILIADO AND S.ORIGEN = 'PERIODO') AS TOTAL_PERIODO
				,(SELECT COUNT(*) FROM @SOPORTES S WHERE S.IDAFILIADO = P.IDAFILIADO AND S.ORIGEN = 'FALLBACK') AS TOTAL_FALLBACK
			FROM @PACIENTES P
			ORDER BY P.DOCIDAFILIADO

