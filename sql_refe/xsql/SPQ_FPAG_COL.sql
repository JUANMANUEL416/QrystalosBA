                       SELECT @VRL_PAGOF  = 0--CONVERT(DECIMAL(14,2), COALESCE(VALOR, '0')) FROM @TABLA WHERE ITEM = 4;
                       SELECT @VLR_GLOSAP = 0--CONVERT(DECIMAL(14,2), IIF(VALOR = '', '0', COALESCE(VALOR, '0'))) FROM @TABLA WHERE ITEM = 4; 
                       SELECT @TIPO_FAC   = VALOR FROM @TABLA WHERE ITEM = 4;
                
                       -- Inicializaci?n de variables de negocio
                       SELECT @IDIMPUESTO = NULL, @IDCLASE = NULL, @VLR_IMP = 0;
                       SELECT @MOTIVO_GLOSA01 = NULL, @MOTIVO_GLOSA02 = NULL, @OBSERVACIONES = NULL;
                       SELECT @IMP_ICA = NULL, @CLASE_ICA = NULL, @VLR_ICA = 0, @VLR_DTO = 0;
                       SELECT @CODRPTA = 0, @VLR_ACEPTA = 0, @CANTIDAD = 1;
                       SELECT @SaldoNeto = NULL, @CNSCXC = NULL, @CNSGLO = NULL;
                       SELECT @MIVA = NULL, @VALORSERVICIOS = NULL, @SUMIMP = 0, @VALOR1 = 0;
                       SELECT @SALDOFCXCD = 0;

                       -- Recalculo desde la tabla temporal (Fase 1)
                       SELECT @VRL_PAGOF=SUM(VALOR1), @VLR_GLOSAP=SUM(VALOR2), @VLR_ACEPTA=SUM(VALOR3)
                       FROM RPDX 
                       WHERE CNS=@CNSRPDX+'_1' AND ID1=@N_FACTU;

                       -- VALIDACIONES (Reemplazo de GOTOs por IFs anidados)
                       IF NOT EXISTS(SELECT * FROM @TBLERRORES WHERE SUBSTRING(ERROR, 1, ISNULL(NULLIF(CHARINDEX('|', ERROR), 0) - 1, LEN(ERROR))) = @N_FACTU)
                       BEGIN
                           IF NOT EXISTS(SELECT * FROM FTR WHERE N_FACTURA = @N_FACTU AND ESTADO = 'P' AND COALESCE(TIPOANULACION,'') <> 'NC')
                           BEGIN
                               INSERT INTO @TBLERRORES (ERROR) SELECT CONCAT(@N_FACTU, ' | ', 'Factura no existe o se encuentra anulada, no se puede procesar.');
                           END
                           ELSE IF @INGRESO IN ('DEVOLUCION', 'DEVPAR')
                              AND EXISTS (SELECT 1 FROM FPAGD WHERE CNSFPAG = @CNSFPAG AND N_FACTURA = @N_FACTU)
                           BEGIN
                               INSERT INTO @TBLERRORES (ERROR) SELECT CONCAT(@N_FACTU, ' | ', 'La factura ya est? en el detalle del recaudo (FPAGD). En devoluci?n solo puede registrarse una vez.');
                           END
                           ELSE IF @INGRESO IN ('GLOSAS', 'CAJA', 'BANCOS', 'CXP')
                              AND EXISTS (SELECT 1 FROM FPAGD WHERE CNSFPAG = @CNSFPAG AND N_FACTURA = @N_FACTU AND CLASE = @TIPO_FAC)
                           BEGIN
                               INSERT INTO @TBLERRORES (ERROR) SELECT CONCAT(@N_FACTU, ' | ', 'La factura y clase ya est?n en el detalle del recaudo (FPAGD).');
                           END
                           ELSE IF EXISTS (SELECT * FROM RPDX WHERE CNS = @CNSRPDX AND RPDX.ID1 = @N_FACTU
                               AND (RPDX.ID2 = @TIPO_FAC OR RPDX.GRUPOETAREO = @TIPO_FAC))
                           BEGIN
                               -- Ya procesada, ignorar
                               SET @ERROR = 'DUPLICADO'; 
                           END
                           ELSE IF EXISTS(SELECT * FROM FCXCD WHERE N_FACTURA = @N_FACTU AND SALDONETO < (@VRL_PAGOF))
                           BEGIN
                               SELECT @SALDOFCXCD = SALDONETO FROM FCXCD WHERE N_FACTURA = @N_FACTU; 
                               INSERT INTO @TBLERRORES (ERROR) SELECT CONCAT(@N_FACTU, ' | ', 'Factura no tiene Saldo en Cartera '+CAST(COALESCE(@SALDOFCXCD,0) AS VARCHAR(20))+' no se puede subir. VRL_PAGOF='+CAST(@VRL_PAGOF AS VARCHAR(20))+' VLR_GLOSAP='+CAST(@VLR_GLOSAP AS VARCHAR(20)));
                           END
                           ELSE IF COALESCE(@VRL_PAGOF + @VLR_GLOSAP, 0) <= 0
                           BEGIN
                               INSERT INTO @TBLERRORES (ERROR) SELECT CONCAT(@N_FACTU, ' | ', 'Valor del pago no puede ser menor o igual a cero, No se Puede Subir.');
                           END
                           -- ... (Resto de validaciones similares) ...
                           ELSE IF EXISTS(SELECT * FROM RPDX WHERE CNS=@CNSRPDX+'_1' AND ID1=@N_FACTU AND VALOR10=1 )
                           BEGIN
                              UPDATE RPDX SET VALOR10=1 WHERE CNS=@CNSRPDX+'_1' AND ID1=@N_FACTU;
                              INSERT INTO @TBLERRORES (ERROR) SELECT CONCAT(@N_FACTU, ' | ', 'Existen inconsistencia en el detalle de los items, revise el detalle de Glosa');
                           END
                           ELSE 
                           BEGIN
                               -- L?GICA DE INSERCI?N EXITOSA
                               SELECT @SaldoNeto = SALDONETO, @CNSCXC = CNSCXC, @CNSGLO = CNSGLO,
                                      @VALORSERVICIOS = SALDONETO 
                               FROM FCXCDV WHERE N_FACTURA = @N_FACTU AND TIPO = @TIPO_FAC;

                               IF (@SaldoNeto < 0) OR (@SaldoNeto < @VRL_PAGOF)
                               BEGIN
                                   INSERT INTO @TBLERRORES (ERROR) SELECT CONCAT(@N_FACTU, ' | ', 'El Saldo de la Factura es menor que el valor Recaudado.');
                               END
                               ELSE IF @INGRESO ='GLOSAS' AND ( @TIPO_FAC = 'F') AND EXISTS(SELECT 1 FROM FGLO WHERE N_FACTURA = @N_FACTU)
                               BEGIN
                                   INSERT INTO @TBLERRORES (ERROR) SELECT CONCAT(@N_FACTU, ' | ', 'Esta Factura ya Tiene Asociada una Glosa .. No se puede Subir');
                               END
                               ELSE
                               BEGIN
                                   -- Inserciones FTIMP y RPDX finales
                                   IF @VLR_GLOSAP = 0
                                   BEGIN
                                       IF @IDIMPUESTO IS NOT NULL AND @VLR_IMP > 0 AND @IDCLASE IS NOT NULL
                                       BEGIN
                                           /* Backup: exig?a IDCLASE id?ntico.
                                           INSERT INTO FTIMP (CNS, N_FACTURA, TIPO, CNSGLO, IDIMPUESTO, IDCLASE, FACTOR, ITEMFIMPDV, BASE, VLRIMPTO, ESGLOBAL, MODOINGRESO)
                                           SELECT @CNSRPDX, @N_FACTU, @TIPO_FAC, '', @IDIMPUESTO, @IDCLASE, VALOR, ITEM, @VRL_PAGOF, @VLR_IMP, '2', 'I' 
                                           FROM FIMPDV  
                                           WHERE IDIMPUESTO = @IDIMPUESTO AND IDCLASE = @IDCLASE AND FECHAINI <= GETDATE() AND FECHAFIN > GETDATE();
                                           */
                                           INSERT INTO FTIMP (CNS, N_FACTURA, TIPO, CNSGLO, IDIMPUESTO, IDCLASE, FACTOR, ITEMFIMPDV, BASE, VLRIMPTO, ESGLOBAL, MODOINGRESO)
                                           SELECT @CNSRPDX, @N_FACTU, @TIPO_FAC, '', IDIMPUESTO, IDCLASE, VALOR, ITEM, @VRL_PAGOF, @VLR_IMP, '2', 'I' 
                                           FROM FIMPDV  
                                           WHERE IDIMPUESTO = @IDIMPUESTO 
                                             AND (
                          IDCLASE = @IDCLASE
                          OR (
                             TRY_CAST(IDCLASE AS BIGINT) IS NOT NULL
                             AND TRY_CAST(@IDCLASE AS BIGINT) IS NOT NULL
                             AND TRY_CAST(IDCLASE AS BIGINT) = TRY_CAST(@IDCLASE AS BIGINT)
                          )
                       ) 
                                             AND FECHAINI <= GETDATE() AND FECHAFIN > GETDATE();
                                       END
                                   END 

                                   SELECT @SUMIMP = SUM(VLRIMPTO) 
                                   FROM FTIMP 
                                   WHERE CNS = @CNSRPDX AND N_FACTURA = @N_FACTU AND TIPO = @TIPO_FAC AND (COALESCE(ESGLOBAL, 0) = 0 OR COALESCE(ESGLOBAL, 0) = 2);
            
                                   IF @VRL_PAGOF > 0 AND @VLR_GLOSAP = 0 SET @VALOR1 = @VRL_PAGOF;
                                   IF @VRL_PAGOF = @VLR_GLOSAP BEGIN SET @VALOR1 = @VLR_GLOSAP; SET @CANTIDAD = 1; END
                                   ELSE IF @VRL_PAGOF > 0 AND @VLR_GLOSAP > 0 SET @VALOR1 = @VRL_PAGOF;
            
                                   INSERT INTO RPDX(CNS, ID1, VALOR1, VALOR2, ID2, ID3, ID4, VALOR3, ID5, ID6, STRINGGRANDE1,
                                                    ID7, ID8, VALOR4, VALOR11, VALOR7, VALOR9, VALOR5, CANTIDAD, CANTIDAD2, VALOR10, STRINGMAX, STRINGMEDIO1, 
                                                    GRUPOETAREO, ID11, ID12, VALOR12, ID13, ID14, ID15, VALOR13)
                                   SELECT @CNSRPDX, @N_FACTU, @VALOR1, @VLR_GLOSAP, @TIPO_FAC, @IDIMPUESTO, @IDCLASE, @VLR_IMP, @MOTIVO_GLOSA01, @MOTIVO_GLOSA02, @OBSERVACIONES,
                                          @IMP_ICA, @CLASE_ICA, @VLR_ICA, @SUMIMP, 0, 0, @VLR_DTO, @CANTIDAD, @MIVA, @VALORSERVICIOS, @ERROR, @OBSERVACIONES, @TIPO_FAC,
                                          @MOTIVO_GLOSA01, @MOTIVO_GLOSA02, @VLR_DTO, @CNSCXC, @CNSGLO, @CODRPTA, @VLR_ACEPTA;

                                   UPDATE FCXCDV 
                                   SET MARCAPAGO = 1 
                                   FROM FCXCDV 
                                   WHERE FCXCDV.N_FACTURA = @N_FACTU 
                                     AND FCXCDV.TIPO = @TIPO_FAC 
                                     AND FCXCDV.CNSCXC = @CNSCXC;
                               END
                           END
                       END -- Fin IF No existe en tabla errores
                   END -- Fin IF Longitud Linea
            
                   SET @INDICE += 16;

                   FETCH NEXT FROM @CursorEstatico INTO @LineaJSON;  
               END  

               CLOSE @CursorEstatico;  
               DEALLOCATE @CursorEstatico;  

               -- INSERT DE ERRORES ACUMULADOS
               SELECT @NROLINEAS = COUNT(*) FROM @TBLERRORES;

               IF @NROLINEAS > 0
               BEGIN
                   INSERT INTO RPDX(CNS, ID1, STRINGGRANDE1)
                   SELECT @CNSRPDX + '_ER', 
                          SUBSTRING(ERROR, 1, ISNULL(NULLIF(CHARINDEX('|', ERROR, 0), 0), LEN(ERROR)) - 1), 
                          RIGHT(ERROR, LEN(ERROR) - ISNULL(NULLIF(CHARINDEX('|', ERROR, 0), 0), LEN(ERROR))) 
                   FROM @TBLERRORES;
               END

               SELECT 'OK' OK, @CNSRPDX CNSRPDX, @CNSRPDX+'_1' CNSRPDXD, @NROLINEAS ERRADOS;
           END
           ELSE
           BEGIN
               SELECT 'KO' AS OK, 'No se encontraron Datos para Procesar, Verifique e intente de nuevo' AS ERROR;
           END

           COMMIT TRAN;
       END TRY
       BEGIN CATCH
           IF @@TRANCOUNT > 0 ROLLBACK TRAN;
           SELECT 'KO' AS OK, ERROR_MESSAGE() AS ERROR;
           RETURN;
       END CATCH
   END;
   IF @METODO='CONSULTAR_DETA_GLOSA'     
   BEGIN       
      SELECT @CNSRPDX = JSON_VALUE(@PARAMETROS, '$.CNSRPDX');
      SELECT 'OK' OK
      SELECT  ID1 AS N_FACTURA, ID2 AS TIPO, VALOR1 AS VLR_GLOSA, ID3 AS CODGLOSA, VALOR2 AS VLR_ITEM, STRINGGRANDE1 AS OBSERVACION
      FROM RPDX 
      WHERE CNS=@CNSRPDX+'_1'
      RETURN
   END 
   IF @METODO='CODIGO_GLOSA'     
   BEGIN         
      SELECT @INGRESO=INGRESO        
      FROM   OPENJSON (@PARAMETROS)
      WITH (           
      INGRESO  VARCHAR(20)   '$.INGRESO'
      )
      SELECT  'OK' OK
      IF @INGRESO='GLOSAS'
      BEGIN
         SELECT CNSFCGLO AS CODIGO,DESCRIPCION from FCGLO WHERE CLASE='GLOSA' AND ESTADO='ACTIVO' 
      END
      ELSE
      BEGIN
         SELECT CNSFCGLO AS CODIGO,DESCRIPCION from FCGLO WHERE CLASE='DEVOLUCION' AND ESTADO='ACTIVO' 
      END
      RETURN
   END  
