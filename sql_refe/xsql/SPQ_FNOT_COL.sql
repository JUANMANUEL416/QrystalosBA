CREATE OR ALTER PROCEDURE DBO.SPQ_FNOT_COL @JSON NVARCHAR(MAX)
WITH ENCRYPTION
AS
SET DATEFORMAT dmy;
SET NOCOUNT ON;

DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX));
DECLARE @PARAMETROS NVARCHAR(MAX);
DECLARE @MODELO VARCHAR(100);
DECLARE @METODO VARCHAR(100);
DECLARE @USUARIO VARCHAR(12);
DECLARE @COMPANIA VARCHAR(2);
DECLARE @IDSEDE VARCHAR(5);
DECLARE @SYS_COMPUTERNAME VARCHAR(200);
DECLARE @DATOS VARCHAR(MAX);
DECLARE @PROCESO VARCHAR(20);
DECLARE @CNSFNOT VARCHAR(20);
DECLARE @CLASE VARCHAR(20);
DECLARE @N_FACTURA VARCHAR(20);
DECLARE @F_NOTA VARCHAR(20);
DECLARE @OBSERVACION VARCHAR(520);
DECLARE @PROCEDENCIA VARCHAR(20);
DECLARE @IDCONCEPTO VARCHAR(20);
DECLARE @NIT VARCHAR(20);
DECLARE @RAZONSOCIAL VARCHAR(120);
DECLARE @DESCRIPCION VARCHAR(120);
DECLARE @CONCEPTO BIT;
DECLARE @TIPOCONCEPTO VARCHAR(20);
DECLARE @VALORCONCEPTO DECIMAL(14, 2);
DECLARE @SALDOFACTURA DECIMAL(14, 2);
DECLARE @VALOR DECIMAL(14, 2);
DECLARE @CNSCXC VARCHAR(20);
DECLARE @IDTERCERO VARCHAR(20);
DECLARE @N_FACTU VARCHAR(20);
DECLARE @IDCOPCENTO VARCHAR(20);
DECLARE @DESCONCEPTO VARCHAR(120);
DECLARE @VALORNT DECIMAL(14, 2);
DECLARE @OBSERVA VARCHAR(512);
DECLARE @NROLINEAS INT;
DECLARE @ERROR VARCHAR(256);
DECLARE @IDTER VARCHAR(20);
DECLARE @RAZONS VARCHAR(120);
DECLARE @CNSRPDX VARCHAR(20);
DECLARE @TIPO VARCHAR(2);
DECLARE @N_CUOTA INT;
DECLARE @IDSERVICIO VARCHAR(20);
DECLARE @PREFIJO VARCHAR(20);
DECLARE @IDAREA VARCHAR(20);
DECLARE @CCOSTO VARCHAR(20);
DECLARE @CANTIDAD INT;
DECLARE @VR_UNITARIO DECIMAL(14, 2);
DECLARE @VR_TOTAL DECIMAL(14, 2);
DECLARE @DETGENERADOS BIT;
DECLARE @NROCOMPROBANTE VARCHAR(20);
DECLARE @USUARIOSOL VARCHAR(20);
DECLARE @RAZONANULA VARCHAR(255);
DECLARE @ITEM INT;
DECLARE @IXCOUNTRY VARCHAR(20);
DECLARE @PIVA DECIMAL(7, 2);
DECLARE @VIVA DECIMAL(14, 2);
DECLARE @VLR_ITEM DECIMAL(14, 2);

BEGIN
	IF COALESCE(@JSON, '') = ''
	BEGIN
		SELECT 'KO' AS OK, 'JSON vac'+NCHAR(237)+'o o no v'+NCHAR(225)+'lido' AS ERROR;
		RETURN;
	END
	SELECT *
	INTO #JSON
	FROM OPENJSON(@JSON) WITH (
			MODELO VARCHAR(100) '$.MODELO'
			,METODO VARCHAR(100) '$.METODO'
			,USUARIO VARCHAR(12) '$.USUARIO'
			,PARAMETROS NVARCHAR(MAX) AS JSON
	)

	SELECT @MODELO = MODELO,
		@METODO = METODO,
		@PARAMETROS = PARAMETROS,
		@USUARIO = USUARIO
	FROM #JSON;

	SELECT @IXCOUNTRY = DBO.FNK_VALORVARIABLE('IXCOUNTRY');

	IF @METODO = 'FNOT_CRUD'
	BEGIN
		SELECT @DATOS=DATOS        
		FROM   OPENJSON (@PARAMETROS)
		WITH (           
			DATOS NVARCHAR(MAX) AS JSON 
			)           
      
			SELECT @PROCESO=PROCESO, @CNSFNOT=CNSFNOT,@CLASE=CLASE,@N_FACTURA=N_FACTURA,@CNSCXC=CNSCXC,@F_NOTA=F_NOTA,
				@OBSERVACION=OBSERVACION,@PROCEDENCIA=PROCEDENCIA,@IDCONCEPTO=IDCONCEPTO,@NIT=NIT,@RAZONSOCIAL=RAZONSOCIAL,
				@DESCRIPCION=DESCRIPCION,@CONCEPTO=CASE WHEN CONCEPTO='true' THEN 1 ELSE 0 END,@TIPOCONCEPTO=CASE WHEN TIPOCONCEPTO='Porcentaje' OR TIPOCONCEPTO='P' THEN 'P'ELSE 'V' END,
            @VALORCONCEPTO=VALORCONCEPTO,	@SALDOFACTURA=SALDOFACTURA,@VALOR=VALOR,@IDTERCERO=IDTERCERO,
            @USUARIOSOL=USUARIOSOL, @RAZONANULA=RAZONANULA
			FROM   OPENJSON (@DATOS)
			WITH   (  
			PROCESO VARCHAR(20)          '$.PROCESO',
			CNSFNOT VARCHAR(20)          '$.CNSFNOT',
			CLASE VARCHAR(20)            '$.CLASE',
			N_FACTURA VARCHAR(20)        '$.N_FACTURA',
			CNSCXC VARCHAR(20)           '$.CNSCXC',
			F_NOTA VARCHAR(20)           '$.F_NOTA',
			OBSERVACION VARCHAR(520)      '$.OBSERVACION',
			PROCEDENCIA VARCHAR(20)      '$.PROCEDENCIA',
			IDCONCEPTO VARCHAR(20)     '$.IDCONCEPTO',
			NIT VARCHAR(20)            '$.NIT',
			IDTERCERO VARCHAR(20)      '$.IDTERCERO',
			RAZONSOCIAL VARCHAR(120)      '$.RAZONSOCIAL',
			DESCRIPCION VARCHAR(120)      '$.DESCRIPCION',
			CONCEPTO VARCHAR(20)         '$.CONCEPTO',
			TIPOCONCEPTO VARCHAR(20)     '$.TIPOCONCEPTO.value',
			VALORCONCEPTO DECIMAL(14,2)    '$.VALORCONCEPTO',
			SALDOFACTURA DECIMAL(14,2)   '$.SALDOFACTURA',
			VALOR DECIMAL(14,2)          '$.VALOR',
			USUARIOSOL VARCHAR(20)       '$.USUARIOSOL',
			RAZONANULA VARCHAR(255)      '$.RAZONANULA'
			)

		/* Anular nota sin aplicar: solo CERRADA=0; marca ESTADO=A (no DELETE). */
		IF @PROCESO='ANULAR'
		BEGIN
			IF NOT EXISTS(SELECT 1 FROM FNOT WHERE CNSFNOT=@CNSFNOT AND CLASE=@CLASE)
			BEGIN
				SELECT 'KO' KO, 'Nota no encontrada, Verifique e intente de nuevo' ERROR
				RETURN
			END
			IF EXISTS(SELECT 1 FROM FNOT WHERE CNSFNOT=@CNSFNOT AND CLASE=@CLASE AND (COALESCE(CERRADA,0)=1 OR ESTADO='A'))
			BEGIN
				SELECT 'KO' KO, 'Solo se pueden anular por este medio notas sin aplicar (abiertas). Si ya está aplicada utilice la opción Anular Nota.' ERROR
				RETURN
			END
			IF LEN(LTRIM(RTRIM(COALESCE(@RAZONANULA,'')))) < 10
			BEGIN
				SELECT 'KO' KO, 'Debe indicar el motivo de anulación (mínimo 10 caracteres).' ERROR
				RETURN
			END
			BEGIN TRY
				UPDATE FNOT SET
					ESTADO = 'A',
					USUARIOANU = @USUARIO,
					USUARIOSOL = COALESCE(NULLIF(LTRIM(RTRIM(@USUARIOSOL)), ''), @USUARIO),
					FECHAANU = DBO.FNK_GETDATE(),
					RAZONANU = @RAZONANULA
				WHERE CNSFNOT = @CNSFNOT AND CLASE = @CLASE
			END TRY
			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
			END CATCH
			IF(SELECT COUNT(*) FROM @TBLERRORES)>0
			BEGIN
				SELECT 'KO' OK, ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK' OK, @CNSFNOT AS CNSFNOT, 0 AS DETGENERADOS
			RETURN
		END

		IF NOT EXISTS (SELECT 1 FROM FTR WHERE N_FACTURA = @N_FACTURA)
		BEGIN
			SELECT 'KO' AS KO, 'Factura no encontrada. Verifique e intente de nuevo' AS ERROR;
			RETURN;
		END
		IF @PROCESO='Nueva' 
		BEGIN
			IF EXISTS(SELECT * FROM FNOT WHERE N_FACTURA=@N_FACTURA AND CERRADA=0 AND ESTADO='O')
			BEGIN
			SELECT 'KO'KO,'Existe una Nota en proceso para esta Factura, No se Puede Continuar'ERROR
			RETURN
			END
			SELECT @IDSEDE=COALESCE(UBEQ.IDSEDE,USUSU.IDSEDE),@COMPANIA=COALESCE(UBEQ.COMPANIA,USUSU.COMPANIA),
			@SYS_COMPUTERNAME=COALESCE(USUSU.SYS_ComputerName,HOST_NAME())
			FROM USUSU LEFT JOIN UBEQ ON USUSU.SYS_ComputerName=UBEQ.SYS_ComputerName
			WHERE USUSU.USUARIO=@USUARIO
			BEGIN TRY
			SELECT @CNSFNOT=''
			IF @CLASE='C'
			BEGIN
			   EXEC SPK_GENCONSECUTIVO @COMPANIA,@IDSEDE, '@FNOTC', @CNSFNOT OUTPUT  
			END
			ELSE
			BEGIN
				EXEC SPK_GENCONSECUTIVO @COMPANIA,@IDSEDE, '@FNOTD', @CNSFNOT OUTPUT  
			END
			SELECT @CNSFNOT = @IDSEDE + LTRIM(RTRIM(@CLASE)) + REPLACE(SPACE(8 - LEN(@CNSFNOT)) + LTRIM(RTRIM(@CNSFNOT)), SPACE(1), '0');

			INSERT INTO FNOT(CNSFNOT, CLASE, N_FACTURA, CNSCXC, IDTERCERO, F_NOTA, VR_TOTAL, OBSERVACION, MARCA, MARCACONT, 
							CONTABILIZADA, NROCOMPROBANTE, IMPRESO, COMPANIA, USUARIO, CERRADA, ESTADO, USUARIOANU,  
							USUARIOSOL, FECHAANU, RAZONANU, PROCEDENCIA, CNSGLO, APLICADAA, LIBERAHADM, CODUNG, CODPRG, 
							ENPRESUPUESTO, IDTERCEROCOBERTURA, COBERTURA_AUT_POR, CONCEPTO, IDCONCEPTO, TIPOCONCEPTO,  
							VALORCONCEPTO, USUARIOAPLICA, DETGENERADOS, CONSECUTIVOPPTO, RECO, FACTE, CNSRESOLFE, 
							PREFIJODIANFE, CNSDIANFE, CNSMASIVO, ZIPKEY, CUDE, FACTEP, RUTARPTA, DOCUMENTOID, DOCUXMLXZIPID,
							XMLZIPID, SOLICITUDJSON, RESPUESTAJSON, PDF) 
			SELECT @CNSFNOT, @CLASE, @N_FACTURA, @CNSCXC,@IDTERCERO, DBO.FNK_GETDATE(),0,@OBSERVACION, 0, 0, 
							0, NULL, 0, @COMPANIA, @USUARIO, 0, 'O', NULL,NULL, NULL, NULL, 'NOTAS', NULL,
							CASE WHEN COALESCE(@CNSCXC,'')='' THEN 'F' ELSE'C' END,0, NULL, NULL, 0, NULL, NULL, 
							@CONCEPTO,@IDCONCEPTO, COALESCE(@TIPOCONCEPTO,'P'),COALESCE(@VALORCONCEPTO,100), NULL, 0, NULL, NULL, NULL, NULL,NULL, NULL,
							NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, 0

			END TRY
			BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
			SELECT ERROR AS ERROR FROM  @TBLERRORES 
			RETURN
			END CATCH
		END
		IF @PROCESO='Editar'
		BEGIN
			IF EXISTS(SELECT * FROM FNOT WHERE N_FACTURA=@N_FACTURA AND CERRADA=0 AND ESTADO='O' AND CNSFNOT<>@CNSFNOT)
			BEGIN
			SELECT 'KO'KO,'Existe una Nota en proceso para esta Factura, No se Puede Continuar'ERROR
			RETURN
			END
			BEGIN TRY       
			   UPDATE FNOT SET N_FACTURA=@N_FACTURA,IDTERCERO=@IDTERCERO,CNSCXC=@CNSCXC,IDCONCEPTO=@IDCONCEPTO,
			   CONCEPTO=@CONCEPTO,TIPOCONCEPTO=@TIPOCONCEPTO,VALORCONCEPTO=@VALORCONCEPTO,OBSERVACION=@OBSERVACION
			   WHERE CNSFNOT=@CNSFNOT
			END TRY
			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
			END CATCH
		END
		IF(SELECT COUNT(*) FROM @TBLERRORES)>0
		BEGIN
			SELECT 'KO' OK, ERROR FROM @TBLERRORES
			RETURN
		END
      SELECT @DETGENERADOS=0
      IF EXISTS(SELECT * FROM FNOT WHERE CNSFNOT=@CNSFNOT AND CLASE='C' AND CONCEPTO=1)
      BEGIN
         EXEC SPK_GENITEMS_NOTACR @CNSFNOT,@CLASE,@USUARIO 
         SELECT @DETGENERADOS=1
      END
		SELECT 'OK' OK,@CNSFNOT AS CNSFNOT, @DETGENERADOS AS DETGENERADOS
		RETURN 
	END  
	IF @METODO='FNOT_ADDDETA'     
	BEGIN   
		SELECT @CNSFNOT=CNSFNOT,@CLASE=CLASE       
		FROM   OPENJSON (@PARAMETROS)
		WITH (           
			CNSFNOT VARCHAR(20) '$.CNSFNOT',
			CLASE   VARCHAR(2) '$.CLASE'
			)           
		IF NOT EXISTS(SELECT * FROM FNOT WHERE CNSFNOT=@CNSFNOT AND CLASE=@CLASE)
		BEGIN
			SELECT 'KO'KO,'Nota no encontrada, Verifique e intente de nuevo'ERROR
			RETURN
		END
      --20250801 -- STORRES -- EL DETALLE MASIVO ESTA CONFIGURADO O PROGRAMADO PARA LA NOTAS CREDITO Y CAUSA ERROR AL INTENTAR USARLO POR EL DEBITO
		IF @CLASE <> 'C'
		BEGIN
			SELECT 'KO'KO,'Nota no es Credito, Debe ingresar el detalle individualmente'ERROR
			RETURN
		END
		BEGIN TRY           
			EXEC SPK_GENITEMS_NOTACR @CNSFNOT,@CLASE,@USUARIO                   
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH
		IF(SELECT COUNT(*) FROM @TBLERRORES)>0
		BEGIN
			SELECT 'KO' OK, ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' OK,@CNSFNOT CNSFNOT
		RETURN 
	END   
	IF @METODO='FNOT_DELDETA'     
	BEGIN   
		SELECT @CNSFNOT=CNSFNOT,@CLASE=CLASE       
		FROM   OPENJSON (@PARAMETROS)
		WITH (           
			CNSFNOT VARCHAR(20) '$.CNSFNOT',
			CLASE   VARCHAR(2) '$.CLASE'
			)   
            
		IF NOT EXISTS(SELECT * FROM FNOT WHERE CNSFNOT=@CNSFNOT AND CLASE=@CLASE)
		BEGIN
			SELECT 'KO'KO,'Nota no encontrada, Verifique e intente de nuevo'ERROR
			RETURN
		END
		BEGIN TRY           
			EXEC SPK_DESITEMS_NOTACR @CNSFNOT,@CLASE,@USUARIO                   
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH
		IF(SELECT COUNT(*) FROM @TBLERRORES)>0
		BEGIN
			SELECT 'KO' OK, ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' OK,@CNSFNOT CNSFNOT
		RETURN 
	END  
	IF @METODO='FNOT_APLICAR'     
	BEGIN   
		SELECT @CNSFNOT=CNSFNOT,@CLASE=CLASE       
		FROM   OPENJSON (@PARAMETROS)
		WITH (           
			CNSFNOT VARCHAR(20) '$.CNSFNOT',
			CLASE   VARCHAR(2) '$.CLASE'
			)   
            
		IF NOT EXISTS(SELECT 1 FROM FNOT WHERE CNSFNOT=@CNSFNOT AND CLASE=@CLASE)
		BEGIN
			SELECT 'KO'KO,'Nota no encontrada, Verifique e intente de nuevo'ERROR
			RETURN
		END
		IF NOT EXISTS(SELECT 1 FROM FNOTD WHERE CNSFNOT=@CNSFNOT AND CLASE=@CLASE)
		BEGIN
			SELECT 'KO'KO,'Nota Sin Detalles, no se puede Aplicar, Verifique e intente de nuevo 'ERROR
			RETURN
		END
		SELECT @F_NOTA=F_NOTA,@VALOR=VR_TOTAL,@N_FACTURA=N_FACTURA,@CNSCXC=CNSCXC 
		FROM FNOT WHERE CNSFNOT=@CNSFNOT AND CLASE=@CLASE

		IF NOT EXISTS(SELECT 1 FROM PRI WHERE FECHA_INI<=@F_NOTA AND FECHA_FIN>=@F_NOTA AND COALESCE(CERRADO_CARTERA,0)=0)
		BEGIN
			SELECT 'KO'KO,'Periodo de Cartera Cerrado o no Existe, Verique e Intente de Nuevo'ERROR
			RETURN
		END
		IF NOT EXISTS(SELECT 1 FROM PRI WHERE FECHA_INI<=@F_NOTA AND FECHA_FIN>=@F_NOTA AND COALESCE(CERRADO,0)=0)
		BEGIN
			SELECT 'KO'KO,'Periodo de Contable Cerrado o no Existe, Verique e Intente de Nuevo'ERROR
			RETURN
		END
		IF COALESCE(@VALOR,0)<=0
		BEGIN
			SELECT 'KO'KO,'El valor de la nota Credito no Puede ser Menor o Igual a Cero'ERROR
			RETURN
		END
        IF EXISTS(SELECT 1 FROM FTR WHERE N_FACTURA=@N_FACTURA AND ESTADO='P' AND COALESCE(TIPOANULACION,'')='' AND VR_TOTAL<=@VALOR) AND @CLASE<>'D'
		BEGIN
			SELECT 'KO'KO,'Inconsistencia. No se permite aplicar una nota por el 100% del valor de la factura, se debe anular desde el modulo de facturación 'ERROR
			RETURN
		END      
		IF NOT EXISTS(SELECT 1 FROM FTR WHERE N_FACTURA=@N_FACTURA AND ESTADO='P' AND COALESCE(TIPOANULACION,'')='')
		BEGIN
			SELECT 'KO'KO,'Inconsistencia en la Factura, Verifique el estado de la Factura'ERROR
			RETURN
		END
		IF @CLASE='C'
		BEGIN
			EXEC SPK_RELIQUIDA_FTR @CNSCXC,@N_FACTURA
		END
		IF @CLASE='C' AND NOT EXISTS(SELECT 1 FROM VWK_CXCDIASVTO WHERE N_FACTURA=@N_FACTURA AND CNSCXC=CASE WHEN COALESCE(@CNSCXC,'')='' THEN 'NO RADICADA' ELSE @CNSCXC END AND SALDONETO>=@VALOR AND TIPO='F' AND CLASEINFO='SINGLO' )
		BEGIN
			SELECT 'KO'KO,'Verique los Saldos, el Saldo de la Factura no cubre el Valor de la Nota 'ERROR
			RETURN
		END
		SELECT @IDSEDE=COALESCE(UBEQ.IDSEDE,USUSU.IDSEDE),@COMPANIA=COALESCE(UBEQ.COMPANIA,USUSU.COMPANIA),
		@SYS_COMPUTERNAME=COALESCE(USUSU.SYS_ComputerName,HOST_NAME())
		FROM USUSU LEFT JOIN UBEQ ON USUSU.SYS_ComputerName=UBEQ.SYS_ComputerName
		WHERE USUSU.USUARIO=@USUARIO

		BEGIN TRY   
			EXEC SPK_NOTASCXC @CNSFNOT,@CLASE,'',@IDSEDE,@COMPANIA,@USUARIO,@SYS_COMPUTERNAME               
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH
		IF(SELECT COUNT(*) FROM @TBLERRORES)>0
		BEGIN
			SELECT 'KO' OK, ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' OK,@CNSFNOT CNSFNOT
		RETURN 
	END
	IF @METODO='CARGAR_NOTAS'
	BEGIN
			
		DECLARE @LINEA AS VARCHAR(MAX)

      SELECT  @NROLINEAS=COUNT(*)
		FROM OPENJSON(@PARAMETROS, '$.LINEAS') 

      IF @NROLINEAS>0
      BEGIN

		   SELECT @IDSEDE=COALESCE(UBEQ.IDSEDE,USUSU.IDSEDE),@COMPANIA=COALESCE(UBEQ.COMPANIA,USUSU.COMPANIA),
		   @SYS_COMPUTERNAME=COALESCE(USUSU.SYS_ComputerName,HOST_NAME())
		   FROM USUSU LEFT JOIN UBEQ ON USUSU.SYS_ComputerName=UBEQ.SYS_ComputerName
		   WHERE USUSU.USUARIO=@USUARIO

         SELECT @CNSRPDX=''
		   EXEC SPK_GENCONSECUTIVO @COMPANIA,@IDSEDE, '@RPDX', @CNSRPDX OUTPUT  
		   SELECT @CNSRPDX = @IDSEDE+REPLACE(SPACE(8 - LEN(@CNSRPDX))+LTRIM(RTRIM(@CNSRPDX)),SPACE(1),0) 

		   DECLARE SUBIR_CURSOR CURSOR FOR   
	      SELECT VALUE 
		   FROM OPENJSON(@PARAMETROS, '$.LINEAS')		  
		   OPEN SUBIR_CURSOR  
		   FETCH NEXT FROM SUBIR_CURSOR INTO @LINEA
		   WHILE @@FETCH_STATUS = 0  
		   BEGIN  	  
            SELECT
               @N_FACTU     = MAX(CASE WHEN ORD = 1 THEN VAL END),
               @IDCONCEPTO  = MAX(CASE WHEN ORD = 2 THEN VAL END),
               @DESCONCEPTO = MAX(CASE WHEN ORD = 3 THEN VAL END),
               @VALOR       = CONVERT(DECIMAL(14,2), NULLIF(LTRIM(RTRIM(MAX(CASE WHEN ORD = 4 THEN VAL END))), N'')),
               @OBSERVA     = MAX(CASE WHEN ORD = 5 THEN VAL END)
            FROM DBO.FNK_SPLIT_TEXCEL(CAST(@LINEA AS NVARCHAR(MAX)), 5);

            SET @ERROR=''
            IF NOT EXISTS(SELECT * FROM FTR WHERE N_FACTURA=@N_FACTU AND ESTADO='P' AND COALESCE(TIPOANULACION,'')='')
            BEGIN
               SELECT @IDTER='',@RAZONS=''
               SET @ERROR += 'Factura no existe o se encuentra anulada, no se puede procesar'
            END
            ELSE 
            BEGIN
               SELECT @IDTER=TER.NIT,@RAZONS=RAZONSOCIAL
               FROM FTR INNER JOIN TER ON FTR.IDTERCERO=TER.IDTERCERO 
               WHERE N_FACTURA=@N_FACTU
            END
            IF NOT EXISTS(SELECT * FROM VWK_CXCDIASVTO WHERE N_FACTURA=@N_FACTU AND TIPO='F' AND SALDONETO>=@VALOR)
            BEGIN
               SET @ERROR +='Factura no tiene Saldo en Cartera en su tipo F no se puede subir'
            END
            IF NOT EXISTS(SELECT * FROM CPNT WHERE CODIGO=@IDCONCEPTO)
            BEGIN
               SET @ERROR +='Id.Concpeto no existe, o no esta homologando ante la Dian'
            END
            IF COALESCE(@VALOR,0)<=0
            BEGIN
               SET @ERROR +='Valor de la nota no puede ser menor o igual a cero, No se Puede Subir' 
            END

            INSERT INTO RPDX(CNS,ID1,ID2,ID3,STRINGMEDIO2,STRINGMEDIO1,VALOR1,STRINGGRANDE1,STRINGGRANDE2,CANTIDAD)
            SELECT @CNSRPDX,@N_FACTU,@IDCONCEPTO,@IDTER,@DESCONCEPTO,@RAZONS,@VALOR,@OBSERVA,@ERROR,CASE WHEN LEN(@ERROR)>1 THEN 1 ELSE 0 END 

		   FETCH NEXT FROM SUBIR_CURSOR INTO @LINEA
		   END  
		  
		   CLOSE SUBIR_CURSOR  
		   DEALLOCATE SUBIR_CURSOR  

         SELECT @NROLINEAS=COUNT(*) FROM RPDX WHERE CNS=@CNSRPDX AND CANTIDAD=1


         SELECT 'OK' OK,@CNSRPDX CNSRPDX,@NROLINEAS ERRADOS
         RETURN

      END
      ELSE
      BEGIN
         SELECT 'KO','No se encontraron Datos para Procesar, Verfique e intente de nuevo' ERROR
         RETURN
      END
	END
	/* Carga masiva por lotes desde JSON (front): primera llamada sin CNSRPDX genera consecutivo;
	   siguientes lotes reutilizan el mismo CNSRPDX para acumular filas en RPDX (mismo flujo que CNSSUBIR en FPAG). */
	IF @METODO='CARGAR_NOTAS_LOTE'
	BEGIN
		DECLARE @LINEA_LOTE AS VARCHAR(MAX)
		DECLARE @CNSRPDX_SOL VARCHAR(20) = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.CNSRPDX'))), '')
		DECLARE @CLASE_LOTE VARCHAR(2) = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.CLASE'))), '')
		DECLARE @ANULARFACT_LOTE VARCHAR(2) = 'NO'
		DECLARE @FACTE_FTR SMALLINT
		DECLARE @VR_TOTAL_FTR DECIMAL(14, 2)
		DECLARE @SALDO_FTR DECIMAL(14, 2)

		SELECT  @NROLINEAS=COUNT(*)
		FROM OPENJSON(@PARAMETROS, '$.LINEAS')

		IF @NROLINEAS>0
		BEGIN
			SELECT @IDSEDE=COALESCE(UBEQ.IDSEDE,USUSU.IDSEDE),@COMPANIA=COALESCE(UBEQ.COMPANIA,USUSU.COMPANIA),
			@SYS_COMPUTERNAME=COALESCE(USUSU.SYS_ComputerName,HOST_NAME())
			FROM USUSU LEFT JOIN UBEQ ON USUSU.SYS_ComputerName=UBEQ.SYS_ComputerName
			WHERE USUSU.USUARIO=@USUARIO

			IF @CNSRPDX_SOL IS NOT NULL
			BEGIN
				IF NOT EXISTS(SELECT 1 FROM RPDX WHERE CNS=@CNSRPDX_SOL)
				BEGIN
					SELECT 'KO' OK,'El CNSRPDX indicado no existe en RPDX. Revise el lote o reinicie la carga.' ERROR
					RETURN
				END
				SET @CNSRPDX=@CNSRPDX_SOL
			END
			ELSE
			BEGIN
				SELECT @CNSRPDX=''
				EXEC SPK_GENCONSECUTIVO @COMPANIA,@IDSEDE, '@RPDX', @CNSRPDX OUTPUT
				SELECT @CNSRPDX = @IDSEDE+REPLACE(SPACE(8 - LEN(@CNSRPDX))+LTRIM(RTRIM(@CNSRPDX)),SPACE(1),0)
			END

			DECLARE SUBIR_CURSOR_LOTE CURSOR FOR
			SELECT [value]
			FROM OPENJSON(@PARAMETROS, '$.LINEAS')
			OPEN SUBIR_CURSOR_LOTE
			FETCH NEXT FROM SUBIR_CURSOR_LOTE INTO @LINEA_LOTE
