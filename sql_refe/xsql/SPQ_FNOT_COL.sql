   IF @METODO='FNOT_ACTUALIZAR_FECHA'     
	BEGIN   
		SELECT @CNSFNOT=CNSFNOT, @CLASE=CLASE       
		FROM OPENJSON (@PARAMETROS)
		WITH (           
			CNSFNOT VARCHAR(20) '$.CNSFNOT',
			CLASE   VARCHAR(2)  '$.CLASE'
		)   
    
		-- Validar que la nota exista
		IF NOT EXISTS(SELECT * FROM FNOT WHERE CNSFNOT=@CNSFNOT AND CLASE=@CLASE)
		BEGIN
			SELECT 'KO' KO, 'Nota no encontrada, Verifique e intente de nuevo' ERROR
			RETURN
		END
    
		-- Validar que la nota est? cerrada
		IF NOT EXISTS(SELECT * FROM FNOT WHERE CNSFNOT=@CNSFNOT AND CLASE=@CLASE AND CERRADA=1)
		BEGIN
			SELECT 'KO' KO, 'La nota debe estar cerrada para actualizar la fecha' ERROR
			RETURN
		END
    
		-- Validar estados permitidos (FACTE 0, 1, 3 o 5)
		IF NOT EXISTS(SELECT * FROM FNOT WHERE CNSFNOT=@CNSFNOT AND CLASE=@CLASE 
					  AND (FACTE = '0' OR FACTE = '1' OR FACTE = '3' OR FACTE = '5'))
		BEGIN
			SELECT 'KO' KO, 'El estado de la nota no permite actualizar la fecha' ERROR
			RETURN
		END
    
		-- Validar que no est? anulada
		IF EXISTS(SELECT * FROM FNOT WHERE CNSFNOT=@CNSFNOT AND CLASE=@CLASE AND ESTADO='Activo')
		BEGIN
			SELECT 'KO' KO, 'No se puede actualizar la fecha de una nota anulada' ERROR
			RETURN
		END
    
		-- Obtener informaci?n del usuario
		SELECT @IDSEDE=COALESCE(UBEQ.IDSEDE,USUSU.IDSEDE),
			   @COMPANIA=COALESCE(UBEQ.COMPANIA,USUSU.COMPANIA),
			   @SYS_COMPUTERNAME=COALESCE(USUSU.SYS_ComputerName,HOST_NAME())
		FROM USUSU 
		LEFT JOIN UBEQ ON USUSU.SYS_ComputerName=UBEQ.SYS_ComputerName
		WHERE USUSU.USUARIO=@USUARIO
    
		BEGIN TRY
			-- Actualizar la fecha de la nota a la fecha/hora actual
			UPDATE FNOT 
			SET F_NOTA = DBO.FNK_GETDATE()
			WHERE CNSFNOT = @CNSFNOT 
			AND CLASE = @CLASE
        
			-- Si tiene comprobante contable, actualizar tambi?n la fecha contable
			SELECT @NROCOMPROBANTE = NROCOMPROBANTE 
			FROM FNOT 
			WHERE CNSFNOT = @CNSFNOT AND CLASE = @CLASE
        
			IF @NROCOMPROBANTE IS NOT NULL AND @NROCOMPROBANTE <> ''
			BEGIN              
			  -- Actualizar fecha del comprobante
				UPDATE MCP 
				SET FECHACONTABLE = DBO.FNK_GETDATE(),
					MES = MONTH(DBO.FNK_GETDATE())
				WHERE NROCOMPROBANTE = @NROCOMPROBANTE
			END
        
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH
    
		IF(SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK, ERROR FROM @TBLERRORES
			RETURN
		END
    
		SELECT 'OK' OK, @CNSFNOT CNSFNOT, 
			   CONVERT(VARCHAR(20), DBO.FNK_GETDATE(), 120) NUEVA_FECHA
		RETURN 
	END

