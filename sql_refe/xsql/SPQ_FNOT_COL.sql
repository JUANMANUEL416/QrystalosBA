      BEGIN
         SELECT @FACTE_FTR_ENC = COALESCE(FACTE, 0)
         FROM FTR WHERE N_FACTURA = @N_FACTURA_ENC

         IF @FACTE_FTR_ENC = 6
            SET @FACTE_DEST = 5
         ELSE IF @FACTE_FTR_ENC = 2
            SET @FACTE_DEST = 1
         ELSE
         BEGIN
            INSERT INTO @TBLERRORES(ERROR)
            SELECT 'Factura ' + @N_FACTURA_ENC + ' no se ha notificado a la DIAN (requiere FACTE=2) ni prevalidada (FACTE=6)'
         END
      END
      ELSE
      BEGIN
         -- Nota sin factura asociada: variable SI ? cola prevalidacion (5)
         IF @PREVALIDA_ACTIVA = 'SI'
            SET @FACTE_DEST = 5
      END

      IF EXISTS(SELECT * FROM FNOT WHERE CNSFNOT=@CNSFNOT AND (CERRADA=0 OR ESTADO='A'))
      BEGIN
         INSERT INTO @TBLERRORES(ERROR)
         SELECT 'No se puede enviar a la Dian una nota '+ IIF(CERRADA=0,'Sin Confirmar','Anulada') FROM FNOT WHERE CNSFNOT=@CNSFNOT
      END
      IF EXISTS(SELECT * FROM FNOT WHERE CNSFNOT=@CNSFNOT AND FACTE IN (1,5) AND  CONVERT(DATE,F_NOTA)=CONVERT(DATE,DBO.FNK_GETDATE()))
      BEGIN
         INSERT INTO @TBLERRORES(ERROR)
         SELECT 'Esta nota ya esta en proceso de envio, Validar proceso Dian '
      END
      IF(SELECT COUNT(*) FROM @TBLERRORES)>0
      BEGIN
         SELECT 'KO' OK, ERROR FROM @TBLERRORES
         RETURN
      END
      IF EXISTS(SELECT * FROM FNOT WHERE CNSFNOT=@CNSFNOT AND (FACTE=1 OR FACTE=3 OR FACTE=5 OR  CONVERT(DATE,F_NOTA)<>CONVERT(DATE,DBO.FNK_GETDATE()))
                 AND MONTH(F_NOTA)=MONTH(DBO.FNK_GETDATE()))
      BEGIN
         UPDATE FNOT SET F_NOTA=DBO.FNK_GETDATE(),FACTE=@FACTE_DEST WHERE CNSFNOT=@CNSFNOT

         SELECT 'OK'OK
         RETURN
      END
      IF EXISTS(SELECT * FROM FNOT WHERE CNSFNOT=@CNSFNOT AND (FACTE=1 OR FACTE=3 OR FACTE=5 OR  FACTE=0) AND  CONVERT(DATE,F_NOTA)<>CONVERT(DATE,DBO.FNK_GETDATE())
                 AND MONTH(F_NOTA)<MONTH(DBO.FNK_GETDATE()) AND DATEDIFF(MONTH,F_NOTA,DBO.FNK_GETDATE())<=3)
      BEGIN
         SELECT @NROCOMPROBANTE=NROCOMPROBANTE FROM FNOT WHERE CNSFNOT=@CNSFNOT
         IF EXISTS(SELECT *FROM MCPE WHERE NROCOMPROBANTE=@NROCOMPROBANTE)
         BEGIN
            INSERT INTO @TBLERRORES(ERROR)
            SELECT 'El comprobante contable de esta nota presenta errores contables, no se puede continuar'
            SELECT 'KO' OK, ERROR FROM @TBLERRORES
            RETURN
         END
         IF EXISTS(SELECT *FROM MCP INNER JOIN PRI ON MCP.ANOMES=PRI.ANOMES 
                    WHERE MCP.NROCOMPROBANTE=@NROCOMPROBANTE AND PRI.CERRADO=1)
         BEGIN
            INSERT INTO @TBLERRORES(ERROR)
            SELECT 'El Periodo contable para el comprobante contable esta Cerrado, no se puede continuar'
            SELECT 'KO' OK, ERROR FROM @TBLERRORES
            RETURN
         END
         UPDATE MCP SET FECHACONTABLE=DBO.FNK_GETDATE(),MES=MONTH(DBO.FNK_GETDATE()) WHERE NROCOMPROBANTE=@NROCOMPROBANTE
         UPDATE FNOT SET F_NOTA=DBO.FNK_GETDATE(),FACTE=@FACTE_DEST WHERE CNSFNOT=@CNSFNOT

         SELECT 'OK'OK
         RETURN
      END
      IF EXISTS(SELECT * FROM FNOT WHERE CNSFNOT=@CNSFNOT AND COALESCE(FACTE,0)=0 AND  MONTH(F_NOTA)=MONTH(DBO.FNK_GETDATE()))
      BEGIN
         UPDATE FNOT SET F_NOTA= CASE WHEN  CONVERT(DATE,F_NOTA)<CONVERT(DATE,DBO.FNK_GETDATE()) THEN  DBO.FNK_GETDATE() ELSE F_NOTA END ,FACTE=@FACTE_DEST WHERE CNSFNOT=@CNSFNOT

         SELECT 'OK'OK
         RETURN
      END
