		IF EXISTS (
			SELECT 1
			FROM FCJ
			WHERE FCJ.CODCAJA = @CODCAJA
			  AND FCJ.CNSFACJ = @CNSFACJ
			  AND FCJ.TIPOEGRESO = DBO.FNK_VALORVARIABLE('IDCJTECXP')
		)
		BEGIN
			INSERT INTO @TBLERRORES(ERROR)
			SELECT N'Egreso CXP: no se permite modificar el encabezado del comprobante.'
		END
	
