CREATE OR ALTER PROCEDURE DBO.SPQ_CONF_CAJA_2
@JSON  NVARCHAR(MAX) 
WITH
ENCRYPTION
AS
DECLARE  @PARAMETROS      NVARCHAR(MAX) ,@MODELO           VARCHAR(100) ,@METODO            VARCHAR(100)  ,@USUARIO         VARCHAR(12),
			@GRUPO           VARCHAR(8)    ,@SYS_COMPUTERNAME VARCHAR(254) ,@IDSEDE            VARCHAR(5)    ,@USUNOMBRE       VARCHAR(100),
			@FECHA           VARCHAR(10)   ,@IDEMEDICA        VARCHAR(4)	,@FECHA1            DATETIME		 ,@SQL             VARCHAR(MAX),
			@IDMEDICO        VARCHAR(20)	 ,@HORA             VARCHAR(10)	,@IDDX              VARCHAR(10)	 ,@CONSECUTIVO     VARCHAR(20),
			@IDAFILIADO      VARCHAR(20)   ,@IDPLAN           VARCHAR(10)  ,@IDTERCERO         VARCHAR(20)   ,@IDSERVICIO      VARCHAR(20),
			@NOMBREACOMPA    VARCHAR(120)  ,@TELEFONOACOMPA   VARCHAR(20)  ,@PARENTESCOACOMPA  VARCHAR(20)   ,@MODELOCITA      VARCHAR(50),
			@CLASEORDEN      VARCHAR(20)   ,@IDPESPECIAL      VARCHAR(20)  ,@IDTERCEROCA       VARCHAR(20)   ,@NOAUTORIZACION  VARCHAR(20),
		   @FECHA2          DATE          ,@CONSECUTIVOANT   VARCHAR(20)  ,@CONSECUTIVONUE    VARCHAR(20)   ,@TIPOCITA        VARCHAR(20),
		   @NOMBRE          VARCHAR(100)  ,@ATENCION         VARCHAR(50)  ,@CCOSTO            VARCHAR(570)  ,@PARTICULAR      BIT,
		   @FECHAINCIO      DATETIME      ,@FECHAFINAL       DATETIME     ,@COMPANIA          VARCHAR(2)	,@ITEM		INT ,
         @IDAUT           VARCHAR(20)   ,@NO_ITEM          SMALLINT     ,@PYP               SMALLINT      ,@ALTOCOSTO       SMALLINT,
		   @VALORAUTD       DECIMAL(12,4) ,@FECHAAUT         DATETIME     ,@COPAGOPROPIO      SMALLINT      ,@SOAT            SMALLINT,
		   @PROCEDENCIA     VARCHAR(20)   ,@IDPROVEEDOR      VARCHAR(20)  ,@IDAREA            VARCHAR(20)   ,@PARTICULAR_TIME DECIMAL(14,2),
         @FECHAINI        DATE          ,@FECHAFIN         DATE         ,@IDESPECIALIDAD    VARCHAR(20),	@TIPOEGRESO  VARCHAR(20) ,
         @I               INT           ,@I_TO             INT		      ,@OBSERVCION        VARCHAR(200)	 ,@CAUSA           VARCHAR(20),
         @OBSERVACION     VARCHAR(200)  ,@HOY              SMALLDATETIME=GETDATE()                        ,@VLR_UNIT        INT, 
         @CANTIDAD        INT           ,@UNS              VARCHAR(20)  ,@CONDICIONAL       VARCHAR(10),	@TIPOCAJA VARCHAR(20),
         @CODCAJA         VARCHAR(10)   ,@DATO             VARCHAR(100) ,@CODCAJERO         VARCHAR(20)   ,@CODTURNO        VARCHAR(4)       ,@CNSFACJ   VARCHAR(20)
        ,@CNSACJ          VARCHAR(20)   ,@NOADMISION       VARCHAR(20)  ,@CONCEPTO          VARCHAR(30)   ,@TOTAL           DECIMAL(20,4)   
        ,@TOTALFCJ        DECIMAL(12,4) ,@FALTANTE         DECIMAL(14,2),@CERRADA           SMALLINT      ,@CNSPCJ          VARCHAR(20)   
        ,@AUX             NVARCHAR(MAX) ,@PROCESO          VARCHAR(20)  ,@VALOR             DECIMAL(12,4) ,@SELECCIONADOS   VARCHAR(1000)
        ,@CNSFACJDEP      VARCHAR(50)   ,@CODCAJADEP       NVARCHAR(MAX),@CTA_BCO           VARCHAR(40)   ,@NUMEROAUTORIZA  VARCHAR(20)
        ,@NUMERODOCUMENTO VARCHAR(20)   ,@SUCURSAL         VARCHAR(20)  ,@TERCERO           NVARCHAR(MAX) ,@TIPOPAGO        NVARCHAR(MAX)
        ,@TIPO_TERCERO    NVARCHAR(MAX) ,@BANCODATO        NVARCHAR(MAX),@CNSDOC            VARCHAR(20)   ,@NUM_CUENTA      NVARCHAR(MAX)		,@NUMERO_CUENTA VARCHAR(20)
        ,@N_FACTURA       VARCHAR(16)   ,@ESTADO           VARCHAR(1)   ,@FECHAFCJ          DATE          ,@NROCOMPROBANTE  VARCHAR(20)
	     ,@FORMAPAGO       VARCHAR(20)	 ,@DESCRIPCION      VARCHAR(200)	,@DATOS             NVARCHAR(MAX) ,@DATOD           NVARCHAR(MAX)	   ,@TIPO VARCHAR(20)
	     ,@RECAUDO         BIT		       ,@NOMBREAFI        VARCHAR(200)	,@DESC_NUMDOCUMENTO VARCHAR(20)	 ,@PAG_IDPAGARE VARCHAR(20),@IDCJFPAEFECTIVO VARCHAR(10)
        ,@CLASE_FAC       VARCHAR(5)		,@NODOCUMENTO VARCHAR(20)
        ,@TRASLADO_CNSFACJ VARCHAR(20) ,@CERRADO_PRI SMALLINT ,@ESTADO_MCP VARCHAR(1) ,@CNSRESOL_FCJ VARCHAR(50) ,@N_FACTURA_FCJ VARCHAR(16),
       @ANOMES_MCP       VARCHAR(30) ,@CONTABILIZADA_FCJ SMALLINT ,@CLASE_CAJ VARCHAR(9)	,@BANCO VARCHAR(20)
DECLARE @FECHA_AUT DATETIME, @FECHAI    VARCHAR(10)

DECLARE @TABLERRR		TABLE (ERROR VARCHAR(200))

BEGIN 
	SET LANGUAGE Spanish;  
	SET DATEFORMAT dmy
	SELECT *
	INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)  AS JSON
	)

	SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON
	--DEFINICION DE TABLA DE ERRORES
	DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200));
	-- TOMA DEL GRUPO, SYS_COMPUTERNAME, SEDE   DE ACUERDO AL USUARIOpl,   --PRINT 'USUARIO:'+@USUARIO
	SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO), @USUNOMBRE = NOMBRE FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME, @COMPANIA = COMPANIA, @CODCAJERO= CODCAJERO FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @IDSEDE = IDSEDE , @IDAREA=  IDAREA ,  @CCOSTO =CCOSTO FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
	PRINT '@USUARIO='+@USUARIO

	
   IF @METODO = 'INSERTA_RECIBO'
	BEGIN
     SELECT @DATOS = DATOS, @DATOD = DATOD, @CODCAJA = CODCAJA
     FROM OPENJSON(@PARAMETROS) WITH  (	DATOS		NVARCHAR(MAX) AS JSON ,
										DATOD       NVARCHAR(MAX) AS JSON,
										CODCAJA		VARCHAR(20) '$.CODCAJA')
       SELECT * INTO #DATOS
	  FROM OPENJSON(@DATOS) 
      WITH (	
            TIPO          VARCHAR(30)   '$.TIPO' ,
            RECAUDO         BIT   '$.RECAUDO' , 
            IDTERCERO			VARCHAR(50)   '$.IDTERCERO' , 
            NOADMISION			VARCHAR(20)   '$.NOADMISION' , 
            IDAFILIADO			VARCHAR(20)   '$.IDAFILIADO' , 
            OBSERVACION         VARCHAR(200)   '$.OBSERVACION' ,
            FECHA				VARCHAR(10)		'$.FECHA' ,
            HORA				VARCHAR(5)		'$.HORA' 
            --CODCAJADEP        NVARCHAR(MAX)   AS JSON, 
              )
    SELECT * INTO #DATOD
	FROM OPENJSON(@DATOD) 
      WITH (	
            CANTIDAD			INT  '$.CANTIDAD' ,
            DESCRIPCION			NVARCHAR(MAX)   AS JSON, 
            TOTAL				VARCHAR(50)   '$.TOTAL' , 
            TIPO				VARCHAR(20)   '$.TIPO'
              )
	
	SELECT @TIPO = TIPO FROM #DATOS
	SELECT @CNSACJ = CNSACJ FROM CAJ WHERE CODCAJA = @CODCAJA 
	IF @TIPO = 'INTERNO'
	BEGIN
		SELECT @NOADMISION = NOADMISION,  @IDTERCERO = IDTERCERO, @OBSERVACION = OBSERVACION FROM #DATOS
		SELECT  @IDAFILIADO = IDAFILIADO, @IDPLAN = IDPLAN FROM HADM WHERE  NOADMISION = @NOADMISION
		SELECT @NOMBREAFI = NOMBREAFI FROM AFI WHERE  IDAFILIADO = @IDAFILIADO
		PRINT '@NOADMISION' + @NOADMISION
	END
	IF @TIPO = 'EXTERNO'
	BEGIN
		SELECT  @IDAFILIADO = IDAFILIADO, @OBSERVACION = OBSERVACION , @IDTERCERO = IDTERCERO FROM #DATOS
		SELECT @NOMBREAFI = NOMBREAFI FROM AFI WHERE  IDAFILIADO = @IDAFILIADO
	END
	IF ( @RECAUDO = 1 AND COALESCE(@IDTERCERO,'')<>'') 
	BEGIN
		SELECT @NOMBREAFI = RAZONSOCIAL FROM TER WHERE  @IDTERCERO = IDTERCERO
	END

       
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN

         BEGIN TRY
		 --FECHA
			SELECT  @FECHAI = REPLACE(JSON_VALUE(@DATOS ,'$.FECHA'),'-','')
			SELECT @HORA =		JSON_VALUE(@DATOS ,'$.HORA')
			--SELECT DBO.FNK_GETDATE()
			SELECT @FECHA_AUT = CONVERT(DATETIME,CONCAT(@FECHAI,' ',@HORA))
			SET @CNSFACJ=NULL
			EXEC SPK_GENCONSECUTIVO @COMPANIA,@CODCAJA,'@FCJ',@CNSFACJ OUTPUT
			SELECT @CNSFACJ =  REPLACE(SPACE(8 - LEN(@CNSFACJ))+LTRIM(RTRIM(@CNSFACJ)),SPACE(1),0)
	
			 INSERT INTO FCJ (CNSFACJ,TIPO,CODCAJA,COMPANIA, CLASE_FAC,CNSACJ,ESTADO,USUARIO,SYS_ComputerName,IDTERCERO, FECHA, TIPOEGRESO, OBSERVACION, PROCEDENCIA, VALORTOTAL , USUARIOLOG
			 ,BANCO, SUCURSAL, CTA_BCO, NOADMISION, CERRADA, ARCHIVADO, IDPLAN, IDAFILIADO, NOMBRECLIENTE , DEAPERTURA , RECAUDO , ENPAGOS, IMPRESO , AREAPRESTACION, CCOSTO , CLASER
			 , TCNSFACJ , IDENTIFICADOR , DEVUELTO )
			 
			 SELECT @CNSFACJ, CASE WHEN @TIPO='EXTERNO' THEN 'EXTERNO' ELSE 'INTERNO' END , @CODCAJA, @COMPANIA, 'COBRO', @CNSACJ, 'P', @CODCAJERO, @SYS_COMPUTERNAME, IDTERCERO, @FECHA_AUT, null, @OBSERVACION, 'CAJA',0, @USUARIO
			, null,null,null, @NOADMISION, 0, 0, @IDPLAN, @IDAFILIADO, @NOMBREAFI , 0  , COALESCE( RECAUDO ,0 ) , 0, 0 ,@IDAREA ,@CCOSTO ,'C' , '', '' , 0
			FROM #DATOS

			INSERT INTO FCJD (CODCAJA, CNSFACJ, ITEM, CONCEPTO, VALORUNITARIO, CANTIDAD, VALORTOTAL, TIPODCTO)
			SELECT @CODCAJA, @CNSFACJ, ROW_NUMBER()  OVER (ORDER BY TIPO),  (SELECT VALOR FROM OPENJSON(DESCRIPCION) WITH (VALOR VARCHAR(20) '$.value')), TOTAL, 1, TOTAL, 'N'
			FROM #DATOD

			--SELECT TOP 100  (SELECT VALOR FROM OPENJSON(DESCRIPCION) WITH (VALOR VARCHAR(20) '$.value')), * FROM #DATOD

			UPDATE FCJ SET VALORTOTAL =  (SELECT SUM (VALORTOTAL) FROM FCJD WHERE FCJD.CODCAJA = @CODCAJA AND FCJD.CNSFACJ = @CNSFACJ  ) WHERE FCJ.CODCAJA = @CODCAJA AND FCJ.CNSFACJ = @CNSFACJ
		
         END TRY
         BEGIN CATCH
           INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
         END CATCH
         
		 IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
	      BEGIN
		      SELECT 'KO' OK
		      SELECT ERROR FROM @TBLERRORES
		      RETURN
	      END	
	      SELECT 'OK'OK
       END
    END
	IF @METODO = 'APROVECHAMIENTO'
	BEGIN
		SELECT @CODCAJA = CODCAJA, @CNSFACJ = CNSFACJ, @VALOR = VALOR
		FROM OPENJSON(@PARAMETROS)
		WITH(	CODCAJA		VARCHAR(20)		'$.CODCAJA' ,CNSFACJ		VARCHAR(20)		 '$.CNSFACJ'
				,VALOR		DECIMAL(14,2)	'$.VALOR')
	
		IF COALESCE(@VALOR,0) = 0
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'Debe de ingresar un numero mayor a 0'
		END
		IF NOT EXISTS (SELECT * FROM FCJD WHERE CNSFACJ= @CNSFACJ AND CODCAJA= @CODCAJA)
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'No cuenta con Movimiento de Detalle.'
		END
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				SELECT @ITEM =     MAX(ITEM) FROM FCJD WHERE CNSFACJ= @CNSFACJ AND CODCAJA= @CODCAJA
		
				INSERT INTO FCJD (CODCAJA, N_RECIBO, CNSFACJ,ITEM , CONCEPTO, AREAFUNCIONAL, VALORUNITARIO, 
					CANTIDAD, VALORTOTAL, IDSERVICIO, TDESCUENTO, TIPODCTO, DCTO, VLRDESCUENTO, PCOSTOUNIT, ESIMPTOGEN, 
					CUENTACM, CCOSTO, IDAREA)
				SELECT CODCAJA, N_RECIBO, CNSFACJ, @ITEM +1 , DBO.FNK_VALORVARIABLE ('IDCJAPROVECHAMIENTO') , AREAFUNCIONAL, 
					@VALOR, 1, @VALOR, IDSERVICIO, TDESCUENTO, TIPODCTO, DCTO, VLRDESCUENTO, PCOSTOUNIT, ESIMPTOGEN, 
					CUENTACM, CCOSTO, IDAREA 
				FROM   FCJD  
					WHERE  FCJD.CODCAJA= @CODCAJA
					AND    FCJD.CNSFACJ= @CNSFACJ
					AND    FCJD.ITEM   = @ITEM

				EXEC SPK_TOTFCJ_IN @CODCAJA , @CNSFACJ

			END TRY
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK
		END 
	END	
	IF @METODO = 'DELETE_FCJD'
	BEGIN
		SELECT @CODCAJA = CODCAJA, @CNSFACJ = CNSFACJ, @CONCEPTO = CONCEPTO
		FROM OPENJSON(@PARAMETROS)
		WITH(	CODCAJA		VARCHAR(20)		'$.CODCAJA' ,CONCEPTO		VARCHAR(20)		 '$.CONCEPTO'
				,CNSFACJ	VARCHAR(20)		'$.CNSFACJ')
	
		IF EXISTS(SELECT  * FROM FCJ WHERE  CNSFACJ = @CNSFACJ AND CODCAJA = @CODCAJA AND COALESCE(CERRADA,0) = 1 )
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El registro ya se encuentra cerrado'
		END
		IF EXISTS(SELECT  * FROM FCJ WHERE  CNSFACJ = @CNSFACJ AND CODCAJA = @CODCAJA AND COALESCE(ESTADO,'') = 'D' )
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El registro ya se encuentra desechado'
		END
		IF EXISTS(SELECT  * FROM PCJ WHERE  CNSFACJ = @CNSFACJ AND CODCAJA = @CODCAJA )
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'Para editar los Conceptos de Pago, elimine las formas de pago.'
		END
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				DELETE FROM FCJD WHERE CNSFACJ = @CNSFACJ AND CODCAJA = @CODCAJA AND CONCEPTO = @CONCEPTO
				UPDATE FCJ SET VALORTOTAL =  (SELECT SUM (VALORTOTAL) FROM FCJD WHERE FCJD.CODCAJA = @CODCAJA AND FCJD.CNSFACJ = @CNSFACJ  ) WHERE FCJ.CODCAJA = @CODCAJA AND FCJ.CNSFACJ = @CNSFACJ

			END TRY
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK
			SELECT	COALESCE((SELECT SUM(VALOR) FROM PCJ WHERE  PCJ.CODCAJA = FCJ.CODCAJA AND PCJ.CNSFACJ = FCJ.CNSFACJ),0) [MONTOTOTAL]
					, FCJ.VALORTOTAL - COALESCE((SELECT SUM(VALOR) FROM PCJ WHERE  PCJ.CODCAJA = FCJ.CODCAJA AND PCJ.CNSFACJ = FCJ.CNSFACJ),0) [MONTOPENDIENTE]
			FROM [dbo].[FCJ] 
			WHERE  FCJ.CODCAJA = @CODCAJA AND FCJ.CNSFACJ = @CNSFACJ
		END 
	END
	IF @METODO = 'INSERTA_FCJD'
	BEGIN
		SELECT @CODCAJA = CODCAJA, @CNSFACJ = CNSFACJ, @CONCEPTO = CONCEPTO, @VALOR = VALOR, @PROCESO = PROCESO
		FROM OPENJSON(@PARAMETROS)
		WITH(	CODCAJA		VARCHAR(20)		'$.CODCAJA' ,CONCEPTO		VARCHAR(20)		 '$.CONCEPTO'
				,CNSFACJ	VARCHAR(20)		'$.CNSFACJ' ,VALOR			DECIMAL(14,2)		'$.VALOR'
				,PROCESO	VARCHAR(20)		 '$.PROCESO')
	
		IF EXISTS(SELECT  * FROM FCJ WHERE  CNSFACJ = @CNSFACJ AND CODCAJA = @CODCAJA AND COALESCE(CERRADA,0) = 1 )
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El registro ya se encuentra cerrado'
		END
		IF EXISTS(SELECT  * FROM FCJ WHERE  CNSFACJ = @CNSFACJ AND CODCAJA = @CODCAJA AND COALESCE(ESTADO,'') = 'D' )
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El registro ya se encuentra desechado'
		END
		IF EXISTS(SELECT  * FROM PCJ WHERE  CNSFACJ = @CNSFACJ AND CODCAJA = @CODCAJA )
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'Para editar los Conceptos de Pago, elimine las formas de pago.'
		END
		IF @PROCESO = 'Insertar' AND EXISTS (SELECT * FROM FCJD WHERE  CNSFACJ = @CNSFACJ AND CODCAJA = @CODCAJA AND CONCEPTO = @CONCEPTO)
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'Ya existe el concepto creado'
		END
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				IF @PROCESO = 'Insertar'
				BEGIN
					INSERT INTO FCJD (CODCAJA, CNSFACJ, ITEM, CONCEPTO, VALORUNITARIO, CANTIDAD, VALORTOTAL, TIPODCTO)
					SELECT @CODCAJA, @CNSFACJ,COALESCE((SELECT MAX (ITEM )FROM FCJD WHERE  FCJD.CODCAJA = @CODCAJA AND FCJD.CNSFACJ = @CNSFACJ ),0) +1 , @CONCEPTO, COALESCE(@VALOR,0), 1, COALESCE(@VALOR,0), 'N'
				END
				IF @PROCESO = 'Editar'
				BEGIN
					UPDATE FCJD SET VALORUNITARIO = @VALOR, VALORTOTAL = @VALOR WHERE FCJD.CODCAJA = @CODCAJA AND FCJD.CNSFACJ = @CNSFACJ AND CONCEPTO = @CONCEPTO
				END
				UPDATE FCJ SET VALORTOTAL =  (SELECT SUM (VALORTOTAL) FROM FCJD WHERE FCJD.CODCAJA = @CODCAJA AND FCJD.CNSFACJ = @CNSFACJ  ) WHERE FCJ.CODCAJA = @CODCAJA AND FCJ.CNSFACJ = @CNSFACJ

			END TRY
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK
			SELECT	COALESCE((SELECT SUM(VALOR) FROM PCJ WHERE  PCJ.CODCAJA = FCJ.CODCAJA AND PCJ.CNSFACJ = FCJ.CNSFACJ),0) [MONTOTOTAL]
					, FCJ.VALORTOTAL - COALESCE((SELECT SUM(VALOR) FROM PCJ WHERE  PCJ.CODCAJA = FCJ.CODCAJA AND PCJ.CNSFACJ = FCJ.CNSFACJ),0) [MONTOPENDIENTE]
			FROM [dbo].[FCJ] 
			WHERE  FCJ.CODCAJA = @CODCAJA AND FCJ.CNSFACJ = @CNSFACJ
		END 
	END
	IF @METODO = 'EDITA_FCJ'
	BEGIN
		SELECT @CODCAJA = CODCAJA, @CNSFACJ = CNSFACJ, @FECHA = FECHA, @HORA = HORA, @TIPO = TIPO
				, @IDTERCERO = IDTERCERO, @NOADMISION = NOADMISION, @RECAUDO = RECAUDO, @OBSERVACION = OBSERVACION
		FROM OPENJSON(@PARAMETROS)
		WITH(	CODCAJA			VARCHAR(20)		'$.CODCAJA' ,IDTERCERO		VARCHAR(20)		 '$.IDTERCERO'
				,TIPO			VARCHAR(20)		'$.TIPO' ,FECHA		VARCHAR(20)		 '$.FECHA'
				,HORA			VARCHAR(5)		 '$.HORA',NOADMISION		VARCHAR(20)		 '$.NOADMISION'
				,CNSFACJ		VARCHAR(20)		'$.CNSFACJ' ,RECAUDO	BIT		'$.RECAUDO' 
				,OBSERVACION	VARCHAR(MAX)		 '$.OBSERVACION')
	
		IF EXISTS(SELECT  * FROM FCJ WHERE  CNSFACJ = @CNSFACJ AND CODCAJA = @CODCAJA AND COALESCE(CERRADA,0) = 1 )
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El registro ya se encuentra cerrado'
		END
		IF EXISTS(SELECT  * FROM FCJ WHERE  CNSFACJ = @CNSFACJ AND CODCAJA = @CODCAJA AND COALESCE(ESTADO,'') = 'D' )
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El registro ya se encuentra desechado'
		END
		IF  EXISTS (SELECT * FROM FCJD WHERE  CNSFACJ = @CNSFACJ AND CODCAJA = @CODCAJA) AND 1 = 2
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'Existe conceptos de pago, debe de eliminarlos, para que se pueda editar.'
		END
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				SELECT  @FECHA = REPLACE(@FECHA,'-','')
				SELECT @FECHA_AUT = CONVERT(DATETIME,CONCAT(@FECHA,' ',@HORA))

				UPDATE FCJ SET OBSERVACION = @OBSERVACION, RECAUDO = @RECAUDO, FECHA = @FECHA_AUT , IDTERCERO = @IDTERCERO, NOADMISION = @NOADMISION, TIPO = @TIPO WHERE  FCJ.CODCAJA = @CODCAJA AND FCJ.CNSFACJ = @CNSFACJ
				UPDATE FCJ SET VALORTOTAL =  (SELECT SUM (VALORTOTAL) FROM FCJD WHERE FCJD.CODCAJA = @CODCAJA AND FCJD.CNSFACJ = @CNSFACJ  ) WHERE FCJ.CODCAJA = @CODCAJA AND FCJ.CNSFACJ = @CNSFACJ

			END TRY
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK
		END 
	END
	IF @METODO = 'IMPRIME_ARQUEO_EGRESO'
	BEGIN
      SELECT  @CODCAJA = CODCAJA, @CNSFACJ = CNSFACJ, @CNSACJ = CNSACJ
      FROM OPENJSON(@PARAMETROS)WITH(
	   CODCAJA        VARCHAR(20)    '$.CODCAJA' ,
	   CNSFACJ        VARCHAR(20)    '$.CNSFACJ' ,
	   CNSACJ         VARCHAR(20)    '$.CNSACJ' 
