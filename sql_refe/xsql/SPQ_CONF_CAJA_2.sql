		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				SELECT  @FECHAI = REPLACE(@FECHA,'-','')
				SELECT @FECHA_AUT = CONVERT(DATETIME,CONCAT(@FECHAI,' ',@HORA))

				IF COALESCE(@FECHA,'')=''
				BEGIN
					SELECT @FECHA_AUT =   CONVERT(DATETIME,CONCAT(CONVERT(VARCHAR(8), GETDATE(), 112),' ', CONVERT(VARCHAR(5), GETDATE(), 108)   )) 
				END
				UPDATE FCJ SET FECHA = @FECHA_AUT, IDTERCERO = @IDTERCERO, OBSERVACION = @OBSERVACION, TIPOEGRESO = @TIPOEGRESO  
							,CTA_BCO = @CTA_BCO, BANCO = @BANCO, SUCURSAL = @SUCURSAL
				WHERE CNSFACJ = @CNSFACJ AND CODCAJA = @CODCAJA
			END TRY  
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
