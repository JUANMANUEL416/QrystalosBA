      */

		IF EXISTS (SELECT * FROM FCJ WHERE CODCAJA = @CODCAJA AND CNSFACJ = @CNSFACJ AND COALESCE(CERRADA,0) = 1 )
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El registro ya se encuentra cerrado'
		END
