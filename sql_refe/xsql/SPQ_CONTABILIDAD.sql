			ELSE
				SET @CAST_CARTERA_ORDENAR_FINAL = 'NRO_DIAS ' + @CAST_CARTERA_ORDENAR_DIRECCION;

			;WITH CTE_CastigoCartera AS (
				SELECT
					f.CNSCXC AS CnsCXC,
					f.N_FACTURA,
					COALESCE(ftr.IDTERCERO, '') AS Id_Tercero,
