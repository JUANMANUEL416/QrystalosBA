				LEFT JOIN FTR ftr WITH (NOLOCK) ON ftr.N_FACTURA = f.N_FACTURA
				LEFT JOIN TER t WITH (NOLOCK) ON t.IDTERCERO = ftr.IDTERCERO
				WHERE 1=1
					AND COALESCE(f.SALDONETO, 0) != 0
					AND (
						(@CAST_CARTERA_ESTADO = 'CASTIGADA' AND COALESCE(f.CASTIGADA, 0) = 1 AND COALESCE(f.TCOBRO, '') = 'Castigo')
						OR
						(@CAST_CARTERA_ESTADO != 'CASTIGADA' OR @CAST_CARTERA_ESTADO IS NULL) AND NOT (COALESCE(f.CASTIGADA, 0) = 1 AND COALESCE(f.TCOBRO, '') IN ('Castigo', 'Dificil'))
					)
					AND (@CAST_CARTERA_TIPO IS NULL OR 
						(@CAST_CARTERA_TIPO = 'FACTURAS' AND f.TIPO = 'F') OR
						(@CAST_CARTERA_TIPO = 'GLOSAS' AND f.TIPO = 'G') OR
						(@CAST_CARTERA_TIPO = 'RATIFICACION' AND f.TIPO = 'R') OR
						(@CAST_CARTERA_TIPO = 'CONCILIACION' AND f.TIPO = 'C'))
					AND (@CAST_CARTERA_DIAS_INICIAL IS NULL OR 
						CASE 
							WHEN @CAST_CARTERA_FECHA IS NOT NULL AND f.F_RECIBIDO IS NOT NULL THEN
								DATEDIFF(DAY, CAST(f.F_RECIBIDO AS DATE), DATEADD(DAY, 1, CAST(@CAST_CARTERA_FECHA AS DATE)))
							WHEN f.F_RECIBIDO IS NOT NULL THEN
								DATEDIFF(DAY, CAST(f.F_RECIBIDO AS DATE), DATEADD(DAY, 1, CAST(GETDATE() AS DATE)))
