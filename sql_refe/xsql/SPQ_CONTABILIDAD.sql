			SET @CAST_CARTERA_PROC_PERIODO_ANO = YEAR(@CAST_CARTERA_PROC_FECHA_CASTIGO);
			SET @CAST_CARTERA_PROC_PERIODO_MES = MONTH(@CAST_CARTERA_PROC_FECHA_CASTIGO);
        
			SELECT @CAST_CARTERA_PROC_PERIODO_EXISTE = COUNT(1)
			FROM PRI WITH (NOLOCK)
			WHERE PRI.COMPANIA = @COMPANIA AND PRI.ANO = CAST(@CAST_CARTERA_PROC_PERIODO_ANO AS VARCHAR(4)) AND PRI.MES = @CAST_CARTERA_PROC_PERIODO_MES;
            
			IF @CAST_CARTERA_PROC_PERIODO_EXISTE = 0
			BEGIN
				SET @CAST_CARTERA_PROC_PERIODO_MSG = 'Período Contable No Existe. No se encontró ningún período contable en la tabla PRI para Compañía ' + 
					@COMPANIA + 
					', Año ' + CAST(@CAST_CARTERA_PROC_PERIODO_ANO AS VARCHAR(4)) + 
					', Mes ' + CAST(@CAST_CARTERA_PROC_PERIODO_MES AS VARCHAR(2)) + 
					'. Por favor, configure el período contable en la tabla PRI antes de procesar.';
                
				SELECT 'KO' AS OK,  @CAST_CARTERA_PROC_PERIODO_MSG AS ERROR;
				RETURN;
			END;

			BEGIN TRY
				DECLARE @CAST_CARTERA_PROC_FECHA_CASTIGO_STRING VARCHAR(10);
				DECLARE @CAST_CARTERA_PROC_FACTURAS_DESMARCADAS INT;

				SET @CAST_CARTERA_PROC_FECHA_CASTIGO_STRING = CONVERT(VARCHAR(10), @CAST_CARTERA_PROC_FECHA_CASTIGO, 103);

				EXEC SPK_NC_CONTAB_CASTIGO_CARTERA 
					@CAST_CARTERA_PROC_TIPO_PROCESO,
					@USUARIO,
					@SYS_COMPUTERNAME,
					@COMPANIA,
					@IDSEDE,
					@CAST_CARTERA_PROC_FECHA_CASTIGO_STRING,
					'';
            

				UPDATE FCXCDV
				SET MARCA = 0, EQUIMARCA = NULL
				WHERE COALESCE(FCXCDV.MARCA, 0) = 1 AND FCXCDV.EQUIMARCA = @SYS_COMPUTERNAME;
            
				SET @CAST_CARTERA_PROC_FACTURAS_DESMARCADAS = @@ROWCOUNT;
				SELECT 'OK' AS OK, 
					CASE 
						WHEN @CAST_CARTERA_PROC_TIPO_PROCESO = 'CASTIGO' THEN 
							CONCAT('Castigo de cartera procesado correctamente. Se procesaron ', CAST(@CAST_CARTERA_PROC_CANTIDAD_MARCADAS AS VARCHAR), ' factura(s). Se generó el comprobante contable correspondiente.')
						ELSE 
							CONCAT('Difícil cobro procesado correctamente. Se procesaron ', CAST(@CAST_CARTERA_PROC_CANTIDAD_MARCADAS AS VARCHAR), ' factura(s). Se generó el comprobante contable correspondiente.')
					END AS MENSAJE,
					@CAST_CARTERA_PROC_CANTIDAD_MARCADAS AS FACTURAS_PROCESADAS,
					@CAST_CARTERA_PROC_TIPO_PROCESO AS TIPO_PROCESO;

			END TRY
			BEGIN CATCH
				DECLARE @CAST_CARTERA_PROC_ERROR_MSG NVARCHAR(4000);
				SET @CAST_CARTERA_PROC_ERROR_MSG = ERROR_MESSAGE();
            
				IF @CAST_CARTERA_PROC_ERROR_MSG LIKE '%Período Contable%' OR @CAST_CARTERA_PROC_ERROR_MSG LIKE '%Periodo Contable%' OR @CAST_CARTERA_PROC_ERROR_MSG LIKE '%PERIODO%'
				BEGIN
					DECLARE @CAST_CARTERA_PROC_PERIODO_INFO NVARCHAR(1000) = '';
					DECLARE @CAST_CARTERA_PROC_PERIODO_COUNT INT = 0;
					DECLARE @CAST_CARTERA_PROC_PERIODO_TOTAL_CATCH INT = 0;
					DECLARE @CAST_CARTERA_PROC_PERIODO_CERRADO_VAL_CATCH INT = NULL;
					DECLARE @CAST_CARTERA_PROC_PERIODO_NOMBRE_CATCH NVARCHAR(50) = '';
                
					BEGIN TRY
						SELECT @CAST_CARTERA_PROC_PERIODO_COUNT = COUNT(1)
						FROM PRI WITH (NOLOCK)
						WHERE PRI.COMPANIA = @COMPANIA
							AND PRI.ANO = CAST(@CAST_CARTERA_PROC_PERIODO_ANO AS VARCHAR(4))
							AND PRI.MES = @CAST_CARTERA_PROC_PERIODO_MES;
                    
						IF @CAST_CARTERA_PROC_PERIODO_COUNT > 0
						BEGIN
							SELECT TOP 1 
								@CAST_CARTERA_PROC_PERIODO_CERRADO_VAL_CATCH = PRI.CERRADO,
								@CAST_CARTERA_PROC_PERIODO_NOMBRE_CATCH = PRI.NOMPERIODO
							FROM PRI WITH (NOLOCK)
							WHERE PRI.COMPANIA = @COMPANIA
								AND PRI.ANO = CAST(@CAST_CARTERA_PROC_PERIODO_ANO AS VARCHAR(4))
								AND PRI.MES = @CAST_CARTERA_PROC_PERIODO_MES;
						END
                    
						SELECT @CAST_CARTERA_PROC_PERIODO_TOTAL_CATCH = COUNT(1)
						FROM PRI WITH (NOLOCK)
						WHERE PRI.COMPANIA = @COMPANIA;
                    
						IF @CAST_CARTERA_PROC_PERIODO_COUNT > 0
						BEGIN
							IF @CAST_CARTERA_PROC_PERIODO_CERRADO_VAL_CATCH IS NOT NULL AND @CAST_CARTERA_PROC_PERIODO_CERRADO_VAL_CATCH = 1
							BEGIN
								SET @CAST_CARTERA_PROC_PERIODO_INFO = ' El período contable para Compañía ' + @COMPANIA + 
									', Año ' + CAST(@CAST_CARTERA_PROC_PERIODO_ANO AS VARCHAR(4)) + 
									', Mes ' + CAST(@CAST_CARTERA_PROC_PERIODO_MES AS VARCHAR(2));
                            
								IF @CAST_CARTERA_PROC_PERIODO_NOMBRE_CATCH IS NOT NULL AND @CAST_CARTERA_PROC_PERIODO_NOMBRE_CATCH != ''
									SET @CAST_CARTERA_PROC_PERIODO_INFO = @CAST_CARTERA_PROC_PERIODO_INFO + ' (' + @CAST_CARTERA_PROC_PERIODO_NOMBRE_CATCH + ')';
                            
								SET @CAST_CARTERA_PROC_PERIODO_INFO = @CAST_CARTERA_PROC_PERIODO_INFO + ' está CERRADO (CERRADO = 1). Por favor, abra el período contable (establezca CERRADO = 0) antes de procesar.';
							END
							ELSE
							BEGIN
								SET @CAST_CARTERA_PROC_PERIODO_INFO = ' Se encontró un período en PRI para Compañía ' + @COMPANIA + 
									', Año ' + CAST(@CAST_CARTERA_PROC_PERIODO_ANO AS VARCHAR(4)) + 
									', Mes ' + CAST(@CAST_CARTERA_PROC_PERIODO_MES AS VARCHAR(2));
                            
								IF @CAST_CARTERA_PROC_PERIODO_NOMBRE_CATCH IS NOT NULL AND @CAST_CARTERA_PROC_PERIODO_NOMBRE_CATCH != ''
									SET @CAST_CARTERA_PROC_PERIODO_INFO = @CAST_CARTERA_PROC_PERIODO_INFO + ' (' + @CAST_CARTERA_PROC_PERIODO_NOMBRE_CATCH + ')';
                            
								SET @CAST_CARTERA_PROC_PERIODO_INFO = @CAST_CARTERA_PROC_PERIODO_INFO + ', pero SPK lo rechazó. Verifique el estado del período en la tabla PRI (CERRADO debe ser 0 o NULL).';
							END
						END
						ELSE IF @CAST_CARTERA_PROC_PERIODO_TOTAL_CATCH > 0
						BEGIN
							SET @CAST_CARTERA_PROC_PERIODO_INFO = ' Existen ' + CAST(@CAST_CARTERA_PROC_PERIODO_TOTAL_CATCH AS VARCHAR) + 
								' período(s) en PRI para Compañía ' + @COMPANIA + 
								', pero ninguno corresponde a Año ' + CAST(@CAST_CARTERA_PROC_PERIODO_ANO AS VARCHAR(4)) + 
								', Mes ' + CAST(@CAST_CARTERA_PROC_PERIODO_MES AS VARCHAR(2)) + 
								'. Por favor, configure el período contable para este año y mes en la tabla PRI.';
						END
						ELSE
						BEGIN
							SET @CAST_CARTERA_PROC_PERIODO_INFO = ' No se encontraron períodos en PRI para Compañía ' + @COMPANIA + 
								'. Por favor, configure al menos un período contable en la tabla PRI.';
						END;
					END TRY
					BEGIN CATCH
						SET @CAST_CARTERA_PROC_PERIODO_INFO = '';
					END CATCH;
                
					IF @CAST_CARTERA_PROC_ERROR_MSG LIKE '%Cerrado%' OR @CAST_CARTERA_PROC_ERROR_MSG LIKE '%cerrado%'
					BEGIN
						IF @CAST_CARTERA_PROC_PERIODO_COUNT > 0 AND @CAST_CARTERA_PROC_PERIODO_CERRADO_VAL_CATCH = 1
						BEGIN
							SELECT 
								'KO' AS OK,
								'Período Contable Cerrado. El período para Compañía ' + @COMPANIA + 
								', Año ' + CAST(@CAST_CARTERA_PROC_PERIODO_ANO AS VARCHAR(4)) + 
								', Mes ' + CAST(@CAST_CARTERA_PROC_PERIODO_MES AS VARCHAR(2)) + 
								' está CERRADO (CERRADO = 1). Por favor, abra el período contable (establezca CERRADO = 0) antes de procesar.' AS ERROR,
								ERROR_LINE() AS LINEA_ERROR;
						END
						ELSE
						BEGIN
							SELECT 
								'KO' AS OK,
								'Período Contable Cerrado para la fecha ' + 
								CONVERT(VARCHAR(10), @CAST_CARTERA_PROC_FECHA_CASTIGO, 120) + 
								', Compañía ' + @COMPANIA + 
								'.' + @CAST_CARTERA_PROC_PERIODO_INFO AS ERROR,
								ERROR_LINE() AS LINEA_ERROR;
						END
					END
					ELSE
					BEGIN
						SELECT 
							'KO' AS OK,
							'Período Contable No Existe para la fecha ' + 
							CONVERT(VARCHAR(10), @CAST_CARTERA_PROC_FECHA_CASTIGO, 120) + 
							', Compañía ' + @COMPANIA + 
							'.' + @CAST_CARTERA_PROC_PERIODO_INFO AS ERROR,
							ERROR_LINE() AS LINEA_ERROR;
					END
				END
				ELSE
				BEGIN
					SELECT 
						'KO' AS OK,
						'Error al ejecutar SPK_NC_CONTAB_CASTIGO_CARTERA: ' + @CAST_CARTERA_PROC_ERROR_MSG AS ERROR,
						ERROR_LINE() AS LINEA_ERROR;
				END
			END CATCH;

		END TRY
		BEGIN CATCH
			SELECT 
				'KO' AS OK,
				'Error al procesar castigo de cartera: ' + ERROR_MESSAGE() AS ERROR,
				ERROR_LINE() AS LINEA_ERROR;
		END CATCH;
		RETURN
	END;
	IF @METODO = 'SEGUIMIENTO_CARTERA'
	BEGIN
		BEGIN TRY
			DECLARE 
				@SEG_IDTERCERO VARCHAR(50),
				@SEG_DIFERENCIA_OPERADOR VARCHAR(50),
				@SEG_DIFERENCIA_VALOR FLOAT,
				@SEG_BUSCAR VARCHAR(200);

			SELECT 
				@ANO = ANO,
				@MES = MES,
				@CUENTA = CUENTA,
				@SEG_IDTERCERO = IDTERCERO,
				@SEG_DIFERENCIA_OPERADOR = DIFERENCIA_OPERADOR,
				@SEG_DIFERENCIA_VALOR = DIFERENCIA_VALOR
			FROM OPENJSON(@PARAMETROS)
			WITH (
				ANO VARCHAR(4) '$.ANO',
				MES VARCHAR(2) '$.MES',
				CUENTA VARCHAR(50) '$.CUENTA',
				IDTERCERO VARCHAR(50) '$.IDTERCERO',
				DIFERENCIA_OPERADOR VARCHAR(50) '$.DIFERENCIA_OPERADOR',
				DIFERENCIA_VALOR FLOAT '$.DIFERENCIA_VALOR',
				BUSCAR VARCHAR(200) '$.BUSCAR'
			);

			-- Validación: ANO es OBLIGATORIO
			IF @ANO IS NULL OR @ANO = 0
			BEGIN
				SELECT 'KO' AS OK, 'Parámetro ANO es obligatorio y debe ser un año válido' AS ERROR;
				RETURN;
			END;

			IF @ANO < 2000 OR @ANO > 2100
			BEGIN
				SELECT 'KO' AS OK, 'El año debe estar entre 2000 y 2100' AS ERROR;
				RETURN;
			END;

			-- Validación: MES es OBLIGATORIO
			IF @MES IS NULL OR @MES = 0
			BEGIN
				SELECT 'KO' AS OK, 'Parámetro MES es obligatorio' AS ERROR;
				RETURN;
			END;
			SELECT @MES_INT=TRY_CAST(@MES AS INT)
			IF @MES_INT < 1 OR @MES_INT > 12
			BEGIN
				SELECT 'KO' AS OK, 'El mes debe estar entre 1 y 12' AS ERROR;
				RETURN;
			END;

			IF @CUENTA IS NOT NULL
			BEGIN
				SET @CUENTA = LTRIM(RTRIM(@CUENTA));
				IF @CUENTA = '' OR @CUENTA = 'null' OR @CUENTA = 'NULL'
					SET @CUENTA = NULL;
			END;

			IF @SEG_IDTERCERO IS NOT NULL
			BEGIN
				SET @SEG_IDTERCERO = LTRIM(RTRIM(@SEG_IDTERCERO));
				IF @SEG_IDTERCERO = '' OR @SEG_IDTERCERO = 'null' OR @SEG_IDTERCERO = 'NULL'
					SET @SEG_IDTERCERO = NULL;
			END;

			IF @SEG_DIFERENCIA_OPERADOR IS NOT NULL
			BEGIN
				SET @SEG_DIFERENCIA_OPERADOR = LTRIM(RTRIM(@SEG_DIFERENCIA_OPERADOR));
				IF @SEG_DIFERENCIA_OPERADOR = '' OR @SEG_DIFERENCIA_OPERADOR = 'Todos' OR @SEG_DIFERENCIA_OPERADOR = 'null' OR @SEG_DIFERENCIA_OPERADOR = 'NULL'
					SET @SEG_DIFERENCIA_OPERADOR = NULL;
			END;

			IF @SEG_DIFERENCIA_OPERADOR IS NOT NULL AND (@SEG_DIFERENCIA_VALOR IS NULL OR @SEG_DIFERENCIA_VALOR < 0)
			BEGIN
				SET @SEG_DIFERENCIA_VALOR = 0;
			END;

			IF @SEG_BUSCAR IS NOT NULL
			BEGIN
				SET @SEG_BUSCAR = LTRIM(RTRIM(@SEG_BUSCAR));
				IF @SEG_BUSCAR = '' OR @SEG_BUSCAR = 'null' OR @SEG_BUSCAR = 'NULL'
					SET @SEG_BUSCAR = NULL;
			END;

			SELECT 
				COALESCE(CAST(RPDX.ID1 AS VARCHAR(50)), '') AS ID1,
				COALESCE(CuentaInfo.NOMCUENTA, '') AS NOMBRE_CUENTA,
				COALESCE(CAST(RPDX.IDTERCERO AS VARCHAR(50)), '') AS IDTERCERO,
				COALESCE(TerceroInfo.RAZONSOCIAL, '') AS RAZON_SOCIAL,
				COALESCE(CAST(RPDX.ID2 AS VARCHAR(50)), '') AS ID2,
				CAST(COALESCE(RPDX.VALOR1, 0) AS FLOAT) AS VALOR1,
				CAST(COALESCE(RPDX.VALOR2, 0) AS FLOAT) AS VALOR2,
				CAST(COALESCE(RPDX.VALOR3, 0) AS FLOAT) AS VALOR3,
				CAST(COALESCE(RPDX.VALOR4, 0) AS FLOAT) AS VALOR4,
				CAST(COALESCE(RPDX.VALOR5, 0) AS FLOAT) AS VALOR5,
				CAST(COALESCE(RPDX.VALOR6, 0) AS FLOAT) AS VALOR6,
				CAST(COALESCE(RPDX.VALOR7, 0) AS FLOAT) AS VALOR7,
				RPDX.FECHA1
			FROM RPDX
			OUTER APPLY (
				SELECT TOP 1 CUE.NOMCUENTA
				FROM CUE
				WHERE LTRIM(RTRIM(CAST(CUE.CUENTA AS VARCHAR(50)))) = LTRIM(RTRIM(CAST(RPDX.ID1 AS VARCHAR(50))))
			) AS CuentaInfo
			OUTER APPLY (
				SELECT TOP 1 TER.RAZONSOCIAL
				FROM TER
				WHERE LTRIM(RTRIM(CAST(TER.IDTERCERO AS VARCHAR(50)))) = LTRIM(RTRIM(CAST(RPDX.IDTERCERO AS VARCHAR(50))))
			) AS TerceroInfo
			WHERE 1=1
				AND RPDX.FECHA1 IS NOT NULL
				AND YEAR(RPDX.FECHA1) = @ANO 
				AND MONTH(RPDX.FECHA1) = @MES
				AND (
					@CUENTA IS NOT NULL 
					OR (RPDX.ID1 IS NOT NULL AND LTRIM(RTRIM(CAST(RPDX.ID1 AS VARCHAR(50)))) <> '')
				)
				AND (
					@SEG_IDTERCERO IS NOT NULL 
					OR (RPDX.IDTERCERO IS NOT NULL AND LTRIM(RTRIM(CAST(RPDX.IDTERCERO AS VARCHAR(50)))) <> '')
				)
				AND (
					COALESCE(RPDX.VALOR1, 0) <> 0 
					OR COALESCE(RPDX.VALOR2, 0) <> 0
					OR COALESCE(RPDX.VALOR3, 0) <> 0
					OR COALESCE(RPDX.VALOR4, 0) <> 0
					OR COALESCE(RPDX.VALOR5, 0) <> 0
					OR COALESCE(RPDX.VALOR6, 0) <> 0
					OR COALESCE(RPDX.VALOR7, 0) <> 0
				)
				AND (@CUENTA IS NULL OR LTRIM(RTRIM(CAST(RPDX.ID1 AS VARCHAR(50)))) = LTRIM(RTRIM(@CUENTA)))
				AND (@SEG_IDTERCERO IS NULL OR LTRIM(RTRIM(CAST(RPDX.IDTERCERO AS VARCHAR(50)))) = LTRIM(RTRIM(@SEG_IDTERCERO)))
				AND (
					@SEG_DIFERENCIA_OPERADOR IS NULL
					OR @SEG_DIFERENCIA_OPERADOR = 'Todos'
					OR (
						@SEG_DIFERENCIA_OPERADOR = 'Mayor que' AND (CAST(COALESCE(RPDX.VALOR1, 0) AS FLOAT) - CAST(COALESCE(RPDX.VALOR2, 0) AS FLOAT)) > @SEG_DIFERENCIA_VALOR
					)
					OR (
						@SEG_DIFERENCIA_OPERADOR = 'Menor o Igual' AND (CAST(COALESCE(RPDX.VALOR1, 0) AS FLOAT) - CAST(COALESCE(RPDX.VALOR2, 0) AS FLOAT)) <= @SEG_DIFERENCIA_VALOR
					)
					OR (
						@SEG_DIFERENCIA_OPERADOR = 'Mayor o Igual' AND (CAST(COALESCE(RPDX.VALOR1, 0) AS FLOAT) - CAST(COALESCE(RPDX.VALOR2, 0) AS FLOAT)) >= @SEG_DIFERENCIA_VALOR
					)
					OR (
						@SEG_DIFERENCIA_OPERADOR = 'Diferente' AND (CAST(COALESCE(RPDX.VALOR1, 0) AS FLOAT) - CAST(COALESCE(RPDX.VALOR2, 0) AS FLOAT)) <> @SEG_DIFERENCIA_VALOR
					)
				)
				AND (
					@SEG_BUSCAR IS NULL
					OR (
						LOWER(LTRIM(RTRIM(CAST(RPDX.ID1 AS VARCHAR(100))))) LIKE '%' + LOWER(@SEG_BUSCAR) + '%'
						OR LOWER(COALESCE(CuentaInfo.NOMCUENTA, '')) LIKE '%' + LOWER(@SEG_BUSCAR) + '%'
						OR LOWER(LTRIM(RTRIM(CAST(RPDX.IDTERCERO AS VARCHAR(100))))) LIKE '%' + LOWER(@SEG_BUSCAR) + '%'
						OR LOWER(COALESCE(TerceroInfo.RAZONSOCIAL, '')) LIKE '%' + LOWER(@SEG_BUSCAR) + '%'
						OR LOWER(LTRIM(RTRIM(CAST(RPDX.ID2 AS VARCHAR(100))))) LIKE '%' + LOWER(@SEG_BUSCAR) + '%'
					)
				)
			ORDER BY RPDX.ID1, RPDX.IDTERCERO, RPDX.ID2;

		END TRY
		BEGIN CATCH
			SELECT 
				'KO' AS OK,
				CONCAT('Error al consultar seguimiento de cartera: ', ERROR_MESSAGE()) AS ERROR,
				ERROR_LINE() AS LINEA_ERROR,
				ERROR_NUMBER() AS ERROR_NUMBER;
		END CATCH;
	END;
