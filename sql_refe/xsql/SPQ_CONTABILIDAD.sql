				CASE WHEN (@CAST_CARTERA_ORDENAR_LIMPIO LIKE 'CNSCXC%' OR @CAST_CARTERA_ORDENAR_LIMPIO = 'CNSCXC') AND @CAST_CARTERA_ORDENAR_DIRECCION = 'ASC' THEN CnsCXC ELSE NULL END,
