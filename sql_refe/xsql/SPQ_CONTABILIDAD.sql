				CASE WHEN (@CAST_CARTERA_ORDENAR_LIMPIO LIKE 'RAZONSOCIAL%' OR @CAST_CARTERA_ORDENAR_LIMPIO = 'RAZONSOCIAL') AND @CAST_CARTERA_ORDENAR_DIRECCION = 'DESC' THEN RAZONSOCIAL ELSE NULL END DESC,
				CASE WHEN (@CAST_CARTERA_ORDENAR_LIMPIO LIKE 'TIPO_FCXCDV%' OR @CAST_CARTERA_ORDENAR_LIMPIO LIKE 'TIPO%') AND @CAST_CARTERA_ORDENAR_DIRECCION = 'ASC' THEN Tipo_FCXCDV ELSE NULL END,
