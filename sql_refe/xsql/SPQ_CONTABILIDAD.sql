							DATEDIFF(DAY, CAST(f.F_RECIBIDO AS DATE), DATEADD(DAY, 1, CAST(GETDATE() AS DATE)))
						ELSE 0
					END AS NRO_DIAS,
					ISNULL((
						SELECT COUNT(*)
						FROM FGLO g WITH (NOLOCK)
						WHERE (
							(f.CNSCXC IS NOT NULL AND g.CNSCXC = f.CNSCXC)
							OR
							(f.N_FACTURA IS NOT NULL AND g.N_FACTURA IS NOT NULL AND LTRIM(RTRIM(ISNULL(g.N_FACTURA, ''))) != '' AND g.N_FACTURA = f.N_FACTURA)
						)
						AND g.CNSGLO IS NOT NULL 
						AND LTRIM(RTRIM(ISNULL(g.CNSGLO, ''))) != ''
