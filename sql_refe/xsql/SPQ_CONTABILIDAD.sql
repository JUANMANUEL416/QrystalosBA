CREATE OR ALTER PROCEDURE DBO.SPQ_CONTABILIDAD
	@JSON NVARCHAR(MAX)
WITH ENCRYPTION
AS
BEGIN   
	SET NOCOUNT ON;
	DECLARE  @PARAMETROS NVARCHAR(MAX),		@MODELO VARCHAR(100),		@METODO			VARCHAR(100),		@QUERY				VARCHAR(MAX),
				@USUARIO VARCHAR(20),			@CNSFACJ VARCHAR(20),		@NOADMISION		VARCHAR(16),		@IDKPAGE			INT,
				@DOCIDAFILIADO VARCHAR(20),	@DocumentoID VARCHAR (50),
				@PAGOS NVARCHAR(MAX) ,			@VALOR DECIMAL(18,2) ,		@CNSFCJ			VARCHAR(20),		@CONORDEN			VARCHAR(2),
				@ITEM			INT,			@REFERENCIA	VARCHAR(20),	@PROCEDENCIA	VARCHAR(25),		@OBSERVACION		VARCHAR(200),
				@ESTADO VARCHAR(25),			@CONSECUTIVO INT,			@IDAFILIADO		VARCHAR(20),		@VLRCOPAGO			DECIMAL(16,2),
				@IDPLAN			VARCHAR(6),	@N_FACTURA VARCHAR(16),		@TCNSFACJ		VARCHAR(15),		@PAGOSTFCJ			NVARCHAR(MAX),
				@IDKPAGED			INT,		@CODCAJA VARCHAR(15),		@NOMBRECLIENTE	VARCHAR(20),		@COMPUTERNAME		VARCHAR(20),
				@VALORPAGADOD	DECIMAL(18,2),	@COMPANIA  VARCHAR(2),		@CLASE_FAC		VARCHAR(20),		@IDTERCERO			VARCHAR(20),
				@VLRPENDIENTE	DECIMAL(18,2),	@TIPO VARCHAR(50),			@CLASE			VARCHAR(50),		@FECHAPAGO			DATE,			 @FECHA DATETIME,
				@CNSACJ VARCHAR(20),			@SYS_COMPUTERNAME VARCHAR(20), @SEDE		VARCHAR(16),		@CODIGOVOUCHER		VARCHAR(100),	@NROCOMPROBANTE VARCHAR(50),
				@USUCAJA VARCHAR (50),			@RAZONANULACION VARCHAR(100)  ,@NOPRESTACION    VARCHAR(20),    @ULTIMO_ANO			INT,			@IDSEDE VARCHAR(5),
				@ULTIMO_MES INT,		        @SIGUIENTE_ANO INT,        @SIGUIENTE_MES INT,					@PERIODO_EXISTE		BIT,	        @NOMPERIODO VARCHAR(13),
				@ANO INT,						@PERIODO_ABIERTO_EXISTE BIT, @FECHA_INI DATE,					@FECHA_FIN			DATE,			@ANULAR_TRASLADO BIT,
				@CNSLOG VARCHAR(20),			@EXISTE_TRASLADO BIT;
	DECLARE @TBLERRORES TABLE(CONTINUA VARCHAR(2), ERROR VARCHAR(500))  
	
	DECLARE @NVOCONSEC INT
	,@ABRIO_PERIODO INT = 0
	,@MES VARCHAR(2)
	,@MES_INT INT
	,@CF_COUNT_SI INT
	,@CF_CERRADO_SI BIT
	,@MESDECIERRE INT
	,@ANO_CERRAR VARCHAR(4)
	,@MES_CERRAR VARCHAR(2)
	,@ANOMES_CERRAR VARCHAR(6)
	,@CF_DET_PAGINA INT
	,@CF_DET_TAMANIO_PAGINA INT
	,@CF_DET_OFFSET INT
	,@CF_DET_TOTAL_REGISTROS INT
	,@CF_ACCION VARCHAR(20)
	,@CF_COMPROBANTE VARCHAR(10)
	,@CF_CLASE VARCHAR(20)
	,@CF_NIVEL VARCHAR(10)
	,@CUENTA VARCHAR(16)
	DECLARE 
		@CTA_CAJ_REC_NOLEG VARCHAR(20),
		@CIERRECOSTOS INT,  -- Cambiar a INT primero para leer del JSON
		@CIERREIMP INT,     -- Cambiar a INT primero para leer del JSON
		@MCUEORDEN_GLOSAS VARCHAR(2),
		@MCUEORDEN_CXC VARCHAR(2),
		@MCUEORDEN_CXP VARCHAR(2),
		@MCUEORDEN_INGRESOS VARCHAR(2),
		@MCUEORDEN_EGRESOS VARCHAR(2)
		
	DECLARE
		@DEP_ENV_IDCON_TCOM_DEPR VARCHAR(50),
		@DEP_ENV_COUNT_ACTIVOS INT,
		@DEP_ENV_COUNT_INCONSISTENCIAS INT,
		@DEP_ENV_COUNT_PENDIENTES INT,
		@DEP_ENV_SQL NVARCHAR(MAX);
		
	DECLARE 
		@PROC_IDTERCERO_ACTUAL VARCHAR(50),
		@PROC_IDTERCERO_NUEVO VARCHAR(50),
		@PROC_PERIODO_CERRADO VARCHAR(6),
		@PROC_ERROR_CODE INT,
		@PROC_ERROR_MESSAGE NVARCHAR(4000);

	DECLARE @REC_CUE_PERIODO VARCHAR(6);
	
		DECLARE 
			@PROC_CUE_CUENTA_ACTUAL VARCHAR(50),
			@PROC_CUE_CUENTA_NUEVA VARCHAR(50),
			@PROC_CUE_PERIODO_CERRADO VARCHAR(6),
			@PROC_CUE_NOMCUENTA_ACTUAL VARCHAR(200),
			@PROC_CUE_NOMCUENTA_NUEVA VARCHAR(200),
			@PROC_CUE_ERROR_CODE INT,
			@PROC_CUE_ERROR_MESSAGE NVARCHAR(4000),
			@PROC_CUE_IDTERCERO VARCHAR(50);
			DECLARE 
				@CAST_CARTERA_PROC_TIPO_PROCESO VARCHAR(20),
				@CAST_CARTERA_PROC_FECHA_CASTIGO DATE,
				@CAST_CARTERA_PROC_CANTIDAD_MARCADAS INT;
					DECLARE @IDCON_TCOM_CASTICART VARCHAR(50);
	SET DATEFORMAT dmy
	SELECT *
	INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO         VARCHAR(20)     '$.USUARIO',
		DOCIDAFILIADO VARCHAR(20)		'$.DOCIDAFILIADO',
	--	TCNSFACJ		VARCHAR(15)		'$.TCNSFACJ',
		PARAMETROS     NVARCHAR(MAX)  AS JSON
	)
	SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO, @DOCIDAFILIADO= DOCIDAFILIADO-- , @TCNSFACJ= CNSFACJ
	FROM #JSON
	DECLARE @LOG_ERR TABLE (ERROR VARCHAR(500))
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME, @IDSEDE = IDSEDE FROM USUSU 	WHERE USUARIO = @USUARIO;
	SELECT @COMPANIA = COMPANIA FROM USUSU 	WHERE USUARIO = @USUARIO;

	IF @METODO = 'OBTENER_PERIODO_A_CERRAR'
	BEGIN
		SELECT @COMPANIA = COMPANIA FROM USUSU  WHERE USUARIO = @USUARIO;

		SELECT TOP 1 @ULTIMO_ANO = ANO,	@ULTIMO_MES = MES
		FROM PRI
		WHERE COMPANIA = @COMPANIA AND CERRADO = 1
		ORDER BY ANO DESC, MES DESC;

		IF @ULTIMO_ANO IS NULL
		BEGIN
			SELECT TOP 1 @SIGUIENTE_ANO = ANO, @SIGUIENTE_MES = MES, @NOMPERIODO = NOMPERIODO
			FROM PRI
			WHERE COMPANIA = @COMPANIA AND CERRADO = 0
			ORDER BY ANO ASC, MES ASC;

			IF @SIGUIENTE_ANO IS NULL
			BEGIN
				SELECT 'KO' AS OK, 'No hay periodos disponibles para cerrar' AS ERROR;
				RETURN;
			END
			SELECT  'OK' AS OK, @SIGUIENTE_ANO AS ANO, @SIGUIENTE_MES AS MES, @COMPANIA AS COMPANIA, @NOMPERIODO AS NOMPERIODO, 'Primer periodo a cerrar' AS MENSAJE;
			RETURN;
		END
		-- Calcular el siguiente periodo consecutivo
		IF @ULTIMO_MES = 12
		BEGIN
			SET @SIGUIENTE_ANO = @ULTIMO_ANO + 1;
			SET @SIGUIENTE_MES = 1;
		END
		ELSE
		BEGIN
			SET @SIGUIENTE_ANO = @ULTIMO_ANO;
			SET @SIGUIENTE_MES = @ULTIMO_MES + 1;
		END

		SELECT @PERIODO_EXISTE = CASE WHEN COUNT(*) > 0 THEN 1 ELSE 0 END, @NOMPERIODO = MAX(NOMPERIODO)
		FROM PRI
		WHERE COMPANIA = @COMPANIA AND ANO = @SIGUIENTE_ANO AND MES = @SIGUIENTE_MES AND CERRADO = 0;

		IF @PERIODO_EXISTE = 0
		BEGIN
			DECLARE @ERROR VARCHAR(500);
			SET @ERROR = CONCAT(
				'No hay periodo consecutivo para cerrar. ',
				'Último periodo cerrado: ', @ULTIMO_ANO, '-',
				RIGHT('0' + CAST(@ULTIMO_MES AS VARCHAR(2)), 2),
				'. Periodo esperado: ', @SIGUIENTE_ANO, '-',
				RIGHT('0' + CAST(@SIGUIENTE_MES AS VARCHAR(2)), 2),
				' no existe o ya está cerrado.'
			);
			SELECT  'KO' AS OK, @ERROR AS ERROR, @ULTIMO_ANO AS ULTIMO_ANO_CERRADO, @ULTIMO_MES AS ULTIMO_MES_CERRADO;
			RETURN;
		END
		SELECT  'OK' AS OK, @SIGUIENTE_ANO AS ANO, @SIGUIENTE_MES AS MES, @COMPANIA AS COMPANIA, @NOMPERIODO AS NOMPERIODO, CONCAT('Periodo ', @SIGUIENTE_ANO, '-', RIGHT('0' + CAST(@SIGUIENTE_MES AS VARCHAR(2)), 2),' listo para cerrar') AS MENSAJE;
		RETURN
	END
	IF @METODO = 'CERRAR_PERIODO'
	BEGIN
		SELECT @ANO = ANO, @MES = MES, @COMPANIA = COMPANIA
		FROM OPENJSON(@PARAMETROS)
		WITH (
			ANO INT '$.ANO',
			MES INT '$.MES',
			COMPANIA VARCHAR(2) '$.COMPANIA'
		);
		IF @ANO IS NULL OR @MES IS NULL OR @COMPANIA IS NULL
		BEGIN
			SELECT 'KO' AS OK, 'Parámetros ANO, MES y COMPANIA son obligatorios' AS ERROR;
			RETURN;
		END
		-- Verificar que el periodo existe y está abierto
		IF NOT EXISTS (SELECT 1 FROM PRI WHERE COMPANIA = @COMPANIA AND ANO = @ANO AND MES = @MES AND CERRADO = 0)
		BEGIN
			SELECT 'KO' AS OK, 'El periodo no existe o ya está cerrado' AS ERROR;
			RETURN;
		END
		BEGIN TRY
			UPDATE PRI
			SET CERRADO = 1
			WHERE COMPANIA = @COMPANIA AND ANO = @ANO AND MES = @MES;

			SELECT 'OK' AS OK, CONCAT('Periodo ', @ANO, '-',  RIGHT('0' + CAST(@MES AS VARCHAR(2)), 2),   ' cerrado exitosamente') AS MENSAJE,
				@ANO AS ANO, @MES AS MES, @COMPANIA AS COMPANIA;
		END TRY 
		BEGIN CATCH
			SELECT  'KO' AS OK, ERROR_MESSAGE() AS ERROR;
		END CATCH
		RETURN
	END
	IF @METODO = 'OBTENER_PERIODO_A_ABRIR'
	BEGIN
		BEGIN TRY
			SELECT @COMPANIA = COMPANIA FROM USUSU WHERE USUARIO = @USUARIO;
			IF @COMPANIA IS NULL
			BEGIN
				SELECT 'KO' AS OK, 'Usuario sin compañía asignada' AS ERROR;
				RETURN;
			END
			
			IF NOT EXISTS (SELECT 1 FROM PRI WHERE SI=1)
			BEGIN
				SELECT 'KO' AS OK, 'NO EXISTE UN PERIODO DE SALDOS INICIALES' AS ERROR;
				RETURN;
			END

			IF NOT EXISTS (SELECT 1 FROM PRI WHERE COALESCE(CERRADO, 0) = 1)
			BEGIN
				SELECT 'KO' AS OK, 'NO EXISTE PERIODO PENDIENTE POR ABRIR' AS ERROR;
				RETURN;
			END

			SELECT TOP 1  @ANO = ANO, @MES = MES, @NOMPERIODO = NOMPERIODO
			FROM PRI 
			WHERE COALESCE(CERRADO, 0) = 1 
			ORDER BY ANO + CASE WHEN MES < 10 THEN '0' + CONVERT(VARCHAR(1), MES) ELSE CONVERT(VARCHAR(2), MES) END DESC;

			IF @ANO IS NULL OR @MES IS NULL
			BEGIN
				SELECT 'KO' AS OK, 'No se pudo obtener el periodo a abrir' AS ERROR;
				RETURN;
			END
			SELECT 'OK' AS OK, @ANO AS ANO, @MES AS MES, @NOMPERIODO AS NOMPERIODO, @COMPANIA AS COMPANIA,CONCAT('Periodo ', @NOMPERIODO, ' listo para abrir') AS MENSAJE;
		END TRY
		BEGIN CATCH
			SELECT 'KO' AS OK,ERROR_MESSAGE() AS ERROR;
		END CATCH
	END
	IF @METODO = 'VALIDAR_INTEGRIDAD_PERIODO' --PENDIENTE
	BEGIN
		DECLARE @ERRORES TABLE (MODULO VARCHAR(50),	REFERENCIA VARCHAR(100), ERROR VARCHAR(500)	);
		BEGIN TRY
			SELECT @ANO = ANO,	@MES = MES
			FROM OPENJSON(@PARAMETROS)
			WITH (
				ANO VARCHAR(4) '$.ANO',	MES SMALLINT '$.MES'
			);
        
			IF EXISTS( SELECT 1 FROM MCP INNER JOIN MCH ON MCP.NROCOMPROBANTE=MCH.NROCOMPROBANTE
				WHERE MCP.ESTADO=2 AND MCP.ANO=@ANO AND MCP.MES=@MES AND COALESCE(MCP.ANULADO,0)<>1 
				AND NOT EXISTS(SELECT 1 FROM CUE WHERE MCH.CUENTA=CUE.CUENTA AND TIPO='Detalle')
				)
			BEGIN
				INSERT INTO @ERRORES (MODULO, REFERENCIA, ERROR)
				SELECT 'CONTABILIDAD', MCP.NROCOMPROBANTE, 'MOVIMIENTOS CON CUENTAS DIFERENTE A DETALLE'
				FROM MCP 
				INNER JOIN MCH ON MCP.NROCOMPROBANTE = MCH.NROCOMPROBANTE
				WHERE MCP.ESTADO = 2
					AND MCP.ANO = @ANO
					AND MCP.MES = @MES
					AND COALESCE(MCP.ANULADO, 0) <> 1
					AND NOT EXISTS(SELECT * FROM CUE WHERE MCH.CUENTA = CUE.CUENTA AND TIPO = 'Detalle')
					AND COALESCE(MCH.VALOR, 0) <> 0;
			END
        
			-- VALIDACIÓN 2: Inventarios
			IF EXISTS(SELECT 1 FROM IMOV WHERE YEAR(FECHACONF)=@ANO AND MONTH(FECHACONF)=@MES AND CONTABILIZADA=0 AND SECONTABILIZA=1 
				AND COALESCE(ESTADO,0)=1 AND IDTIPOMOV<>DBO.FNK_VALORVARIABLE('IDINVDEVPROVEEDOR'))
			BEGIN
				INSERT INTO @ERRORES (MODULO, REFERENCIA, ERROR)
				SELECT 'INVENTARIO', IMOV.CNSMOV, 'MOVIMIENTOS CONFIRMADOS SIN CONTABLIZAR'
				FROM IMOV 
				WHERE YEAR(FECHACONF) = @ANO 
					AND MONTH(FECHACONF) = @MES 
					AND COALESCE(CONTABILIZADA, 0) = 0 
					AND COALESCE(SECONTABILIZA, 0) = 1 
					AND COALESCE(ESTADO, 0) = 1;
			END
        
			-- VALIDACIÓN 3: Notas DB-CR
			IF EXISTS(SELECT 1 FROM FNOT WHERE COALESCE(ESTADO,'')<>'A' AND YEAR(F_NOTA)=@ANO AND YEAR(F_NOTA)=@MES AND COALESCE(CONTABILIZADA,0)=0 AND COALESCE(NROCOMPROBANTE,'')='')
			BEGIN
				INSERT INTO @ERRORES (MODULO, REFERENCIA, ERROR)
				SELECT 'NOTASDB-CR', FNOT.CNSFNOT, 'NOTAS DB-CR SIN CONTABLIZAR O PENDIENTES POR CONFIRMAR'
				FROM FNOT
				WHERE COALESCE(ESTADO, '') <> 'A' 
					AND YEAR(F_NOTA) = @ANO 
					AND MONTH(F_NOTA) = @MES 
					AND COALESCE(CONTABILIZADA, 0) = 0 
					AND COALESCE(NROCOMPROBANTE, '') = '';
			END
        
			-- VALIDACIÓN 4: Caja
			IF EXISTS(SELECT 1 FROM FCJ WHERE COALESCE(ESTADO,'')NOT IN('A','D') AND YEAR(FECHA)=@ANO AND MONTH(FECHA)=@MES AND COALESCE(CONTABILIZADA,0)=0 AND COALESCE(NROCOMPROBANTE,'')='' AND DEAPERTURA=0 )
			BEGIN
				INSERT INTO @ERRORES (MODULO, REFERENCIA, ERROR)
				SELECT 'CAJA', FCJ.CODCAJA + ' - ' + FCJ.CNSFACJ, 'RECIBOS DE CAJA SIN CONTABLIZAR'
				FROM FCJ
				WHERE COALESCE(ESTADO, '') NOT IN('A', 'D') 
					AND YEAR(FECHA) = @ANO 
					AND MONTH(FECHA) = @MES 
					AND COALESCE(CONTABILIZADA, 0) = 0 
					AND COALESCE(NROCOMPROBANTE, '') = '' 
					AND COALESCE(CERRADA, 0) = 1 
					AND DEAPERTURA = 0
				UNION ALL
				SELECT 'CAJA', FCJ.CODCAJA + ' - ' + FCJ.CNSFACJ, 'RECIBOS DE CAJA PENDIENTES POR CONFIRMAR'
				FROM FCJ
				WHERE COALESCE(ESTADO, '') NOT IN('A', 'D') 
					AND YEAR(FECHA) = @ANO 
					AND MONTH(FECHA) = @MES 
					AND COALESCE(CERRADA, 0) = 0 
					AND DEAPERTURA = 0;
			END
        
			-- VALIDACIÓN 5: Nómina
			IF EXISTS(SELECT 1 FROM NPER WHERE ANO=@ANO AND MES=@MES AND CERRADO=0)
			BEGIN
				INSERT INTO @ERRORES (MODULO, REFERENCIA, ERROR)
				SELECT 'NOMINA', CNSPAGO, 'NOMINAS PENDIENTES POR CERRAR'
				FROM NPER
				WHERE ANO = @ANO AND MES = @MES AND CERRADO = 0;
			END
        
			-- VALIDACIÓN 6: Cuentas por pagar
			IF  DBO.FNK_VALORVARIABLE('IDCON_FCONTABLE_CXP')='Radicacion'
			BEGIN
				IF EXISTS(SELECT 1 FROM FCXP WHERE YEAR(FECHA)=@ANO AND MONTH(FECHA)=@MES AND COALESCE(CONTABILIZADA,0)=0 AND COALESCE(NROCOMPROBANTE,'')='' AND ESTADO<>'A')
				BEGIN
					INSERT INTO @ERRORES (MODULO, REFERENCIA, ERROR)
					SELECT 'CXP', CNSFCXP, 'CUENTAS POR PAGAR PENDIENTES POR CONTABILIZAR'
					FROM FCXP  
					WHERE YEAR(FECHA) = @ANO AND MONTH(FECHA) = @MES AND COALESCE(CONTABILIZADA, 0) = 0  AND COALESCE(NROCOMPROBANTE, '') = '' AND ESTADO <> 'A';
				END
			END
			ELSE
			BEGIN
				IF EXISTS(SELECT 1 FROM FCXP WHERE YEAR(F_FACTURAREF)=@ANO AND MONTH(F_FACTURAREF)=@MES AND COALESCE(CONTABILIZADA,0)=0 AND COALESCE(NROCOMPROBANTE,'')='' AND ESTADO<>'A')
				BEGIN
					INSERT INTO @ERRORES (MODULO, REFERENCIA, ERROR)
					SELECT 'CXP', CNSFCXP, 'CUENTAS POR PAGAR PENDIENTES POR CONTABILIZAR'
					FROM FCXP  
					WHERE YEAR(F_FACTURAREF) = @ANO AND MONTH(F_FACTURAREF) = @MES AND COALESCE(CONTABILIZADA, 0) = 0 AND COALESCE(NROCOMPROBANTE, '') = '' AND ESTADO <> 'A';
				END
			END
        
			-- VALIDACIÓN 7: Notas CXP
			IF EXISTS(SELECT 1 FROM FCXPDBCR WHERE YEAR(FECHA)=@ANO AND MONTH(FECHA)=@MES AND COALESCE(CONTABILIZADA,0)=0 AND 
					EXISTS(SELECT 1 FROM FCXP WHERE FCXPDBCR.CNSFCXP=FCXP.CNSFCXP AND ESTADO<>'A'))
			BEGIN
				INSERT INTO @ERRORES (MODULO, REFERENCIA, ERROR)
				SELECT 'CXP DBCR', CNSFCXP, 'NOTAS DE CUENTAS POR PAGAR PENDIENTES POR CONTABILIZAR'
				FROM FCXPDBCR  
				WHERE YEAR(FECHA) = @ANO AND MONTH(FECHA) = @MES AND COALESCE(CONTABILIZADA, 0) = 0 AND EXISTS(SELECT 1 FROM FCXP WHERE FCXPDBCR.CNSFCXP = FCXP.CNSFCXP AND ESTADO <> 'A');
			END
        
			-- VALIDACIÓN 8: Recaudos
			IF EXISTS(SELECT 1 FROM FPAG WHERE YEAR(FECHA)=@ANO AND MONTH(FECHA)=@MES AND COALESCE(CONTABILIZADO,0)=0 AND COALESCE(NROCOMPROBANTE,'')='' AND COALESCE(ESTADO,'')<>'Inactivo')
			BEGIN
				INSERT INTO @ERRORES (MODULO, REFERENCIA, ERROR)
				SELECT 'RECAUDOS', CNSFPAG, 'RECAUDOS PENDIENTES POR CONTABILIZAR O POR APLICAR'
				FROM FPAG        
				WHERE YEAR(FECHA) = @ANO AND MONTH(FECHA) = @MES AND COALESCE(CONTABILIZADO, 0) = 0 AND COALESCE(NROCOMPROBANTE, '') = '' 
					AND COALESCE(ESTADO, '') <> 'Inactivo' AND COALESCE(CERRADO, 0) = 1;
			END
        
			-- VALIDACIÓN 9: Bancos
			IF EXISTS(SELECT 1 FROM BMOV WHERE YEAR(COALESCE(FECHAOPERACION,FECHAOK))=@ANO AND MONTH(COALESCE(FECHAOPERACION,FECHAOK))=@MES AND COALESCE(CONTABILIZADA,0)=0 AND COALESCE(NROCOMPROBANTE,'')='' AND COALESCE(ESTADO,'')<>'A')
			BEGIN
				INSERT INTO @ERRORES (MODULO, REFERENCIA, ERROR)
				SELECT 'BANCOS', 
					BANCO + ' ITEM: ' + CONVERT(VARCHAR(10), ITEM),
					'CTA_BCO=' + CTA_BCO + ' FECHA: ' + CONVERT(VARCHAR, FECHAOPERACION, 103) + ' MOVIMIENTO BANCARIO PENDIENTE POR CONTABILIZAR'
				FROM BMOV    
				WHERE YEAR(COALESCE(FECHAOPERACION, FECHAOK)) = @ANO 
					AND MONTH(COALESCE(FECHAOPERACION, FECHAOK)) = @MES 
					AND COALESCE(CONTABILIZADA, 0) = 0 
					AND COALESCE(NROCOMPROBANTE, '') = '' 
					AND COALESCE(ESTADO, '') <> 'A';
			END
        
			-- VALIDACIÓN 10: Conciliaciones
			IF EXISTS(SELECT 1 FROM FCONCI WHERE YEAR(FECHACONC)=@ANO AND MONTH(FECHACONC)=@MES AND COALESCE(CONTABILIZADA,0)=0 AND COALESCE(NROCOMPROBANTE,'')='' AND
					EXISTS(SELECT 1 FROM FCONCID WHERE FCONCI.IDFCONCI=FCONCID.IDFCONCI AND FCONCID.VLRRECUPERAR>0))
			BEGIN
				INSERT INTO @ERRORES (MODULO, REFERENCIA, ERROR)
				SELECT 'CONCILIACIONES', IDFCONCI, 'CONCILIACION PENDIENTE POR CONTABILIZAR O POR APLICAR'
				FROM FCONCI  
				WHERE YEAR(FECHACONC) = @ANO  AND MONTH(FECHACONC) = @MES  AND COALESCE(CONTABILIZADA, 0) = 0  AND COALESCE(NROCOMPROBANTE, '') = ''
					AND EXISTS(SELECT 1 FROM FCONCID WHERE FCONCI.IDFCONCI = FCONCID.IDFCONCI AND FCONCID.VLRRECUPERAR > 0);
			END
        
			-- VALIDACIÓN 11: Radicación
			IF EXISTS(SELECT 1 FROM FCXC WHERE INDRECIBIDO=1 AND YEAR(F_RECIBIDO)=@ANO AND MONTH(F_RECIBIDO)=@MES AND COALESCE(NROCOMPROBANTE,'')='' AND OBSERVACION NOT IN('CXC GENERADA EN CAJA','VENTA DESDE FARMACIA'))
			BEGIN
				INSERT INTO @ERRORES (MODULO, REFERENCIA, ERROR)
				SELECT 'RADICACION', CNSCXC, 'RADICACION PENDIENTE POR CONTABILIZAR'
				FROM FCXC 
				WHERE INDRECIBIDO = 1  AND YEAR(F_RECIBIDO) = @ANO AND MONTH(F_RECIBIDO) = @MES  AND COALESCE(NROCOMPROBANTE, '') = '' 
					AND OBSERVACION NOT IN('CXC GENERADA EN CAJA', 'VENTA DESDE FARMACIA');
			END
        
			-- VALIDACIÓN 12: Cierre de cartera
			IF EXISTS(SELECT 1 FROM PRI WHERE ANO = @ANO AND MES = @MES AND COALESCE(CERRADO_CARTERA, 0) = 0)
			BEGIN
				INSERT INTO @ERRORES (MODULO, REFERENCIA, ERROR)
				VALUES ('CIERRE', 'CARTERA', 'SE DEBE CERRAR EL PERIODO DE CARTERA ANTES DE CERRAR CONTABILIDAD');
			END
        
			-- VALIDACIÓN 13: Cierre de CXP
			IF EXISTS(SELECT 1 FROM PRI WHERE ANO = @ANO AND MES = @MES AND COALESCE(CERRADO_CXP, 0) = 0)
			BEGIN
				INSERT INTO @ERRORES (MODULO, REFERENCIA, ERROR)
				VALUES ('CIERRE', 'CXP', 'SE DEBE CERRAR EL PERIODO DE CXP ANTES DE CERRAR CONTABILIDAD');
			END
        
			-- VALIDACIÓN 14: Depreciación de activos
			IF DBO.FNK_VALORVARIABLE('CONTAB_ACTFIJO') = 'SI'
			BEGIN
