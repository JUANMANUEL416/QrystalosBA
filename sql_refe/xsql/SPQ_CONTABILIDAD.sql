							WHEN f.F_RECIBIDO IS NOT NULL THEN
								DATEDIFF(DAY, CAST(f.F_RECIBIDO AS DATE), DATEADD(DAY, 1, CAST(GETDATE() AS DATE)))
							ELSE 0
						END <= @CAST_CARTERA_DIAS_FINAL)
					AND (@CAST_CARTERA_IDTERCERO IS NULL OR 
						(@CAST_CARTERA_IDTERCERO = 'PARTICULAR' AND ftr.IDTERCERO IS NOT NULL AND LTRIM(RTRIM(ftr.IDTERCERO)) = 'PARTICULAR') OR
						(@CAST_CARTERA_IDTERCERO != 'PARTICULAR' AND ftr.IDTERCERO IS NOT NULL AND LTRIM(RTRIM(ftr.IDTERCERO)) = LTRIM(RTRIM(@CAST_CARTERA_IDTERCERO))))
					AND (@CAST_CARTERA_IDTERCERO IS NOT NULL OR @CAST_CARTERA_NIT IS NULL OR 
						(@CAST_CARTERA_NIT = 'PARTICULAR' AND EXISTS(
							SELECT 1 FROM FTR ftr2 WITH (NOLOCK) 
							WHERE ftr2.N_FACTURA = f.N_FACTURA 
							AND ftr2.IDTERCERO IS NOT NULL 
							AND LTRIM(RTRIM(ftr2.IDTERCERO)) = 'PARTICULAR'
						)) OR
						(@CAST_CARTERA_NIT != 'PARTICULAR' AND @CAST_CARTERA_NIT IS NOT NULL AND EXISTS(
							SELECT 1 FROM FTR ftr2 WITH (NOLOCK)
							INNER JOIN TER t2 WITH (NOLOCK) ON t2.IDTERCERO = ftr2.IDTERCERO
							WHERE ftr2.N_FACTURA = f.N_FACTURA
							AND t2.NIT IS NOT NULL 
							AND LTRIM(RTRIM(t2.NIT)) != '' 
							AND LTRIM(RTRIM(t2.NIT)) = LTRIM(RTRIM(@CAST_CARTERA_NIT))
						)))
					AND (@CAST_CARTERA_ESTADO IS NULL OR
						(@CAST_CARTERA_ESTADO = 'CASTIGADA' AND COALESCE(f.CASTIGADA, 0) = 1 AND COALESCE(f.TCOBRO, '') = 'Castigo') OR
						(@CAST_CARTERA_ESTADO = 'MARCADAS' AND COALESCE(f.MARCA, 0) = 1 AND f.EQUIMARCA = @CAST_CARTERA_SYS_COMPUTERNAME)
