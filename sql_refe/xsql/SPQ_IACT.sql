DECLARE @MESESDEPRECIADOSNIIF SMALLINT, @SECTOR VARCHAR(20), @CLASEGRUPO VARCHAR(20), @FPRIMERMTTO DATETIME, @NROMTTOANUAL SMALLINT
DECLARE @FULTIMOMTTO DATETIME
DECLARE @CLASEMMTO VARCHAR(20), @ANOFAB VARCHAR(4), @RINVIMA VARCHAR(20), @ESTAUSO VARCHAR(20), @VOLTAMAX VARCHAR(10), @VOLTAMIN VARCHAR(10)
