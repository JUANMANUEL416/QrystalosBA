				@CUENTA_AJINFLA_DEP = CUENTA_AJINFLA_DEP, @AJUSTEDEPACUMULADA = AJUSTEDEPACUMULADA, @DEPRECIABLE = DEPRECIABLE, @SUBCCOSTO = SUBCCOSTO, 
