DECLARE @PROPIEDAD VARCHAR(100), @GARANTIA VARCHAR(512), @M_DESPIECE BIT, @TIPOELEMENTO VARCHAR(20), @REFRIGERANTE VARCHAR(20), @PLACA_ACTUAL VARCHAR(20), 
	@PLACA_ANTIGUA VARCHAR(20)
DECLARE @CAPACIDAD VARCHAR(20), @CAPACITOR VARCHAR(20), @SYS_COMPUTERNAME VARCHAR(254)

--
BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GUARDAR'
	BEGIN
		SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
		FROM USUSU
		WHERE USUARIO = @USUARIO

		SELECT @IDSEDE = IDSEDE
		FROM UBEQ
		WHERE SYS_ComputerName = @SYS_COMPUTERNAME

		BEGIN TRY
			SELECT @PROCESO = PROCESO, @IDACTIVO = IDACTIVO, @IDTIPOACTIVO = IDTIPOACTIVO, @DESCRIPCION = DESCRIPCION, @FECHACOMPRA = FECHACOMPRA, @PRECIOCOMPRA = 
				PRECIOCOMPRA, @PRECIOCOMERCIAL = PRECIOCOMERCIAL, @REFERENCIA = REFERENCIA, @MODELOIACT = MODELOIACT, @MARCA = MARCA, @NOESCRITURA = NOESCRITURA, 
				@LINDEROS = LINDEROS, @NOPARTE = NOPARTE, @MATRICULA = MATRICULA, @SERIAL = SERIAL, @CCOSTO = CCOSTO, @UBICACION = UBICACION, @RESPONSABLE = RESPONSABLE, 
