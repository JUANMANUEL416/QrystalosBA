				VALORSALVAMENTO, @AJUSTEACUMULADO = AJUSTEACUMULADO, @IDAREA = IDAREA, @NOLOTE = NOLOTE, @CATEGORIA = CATEGORIA, @IDITAR = IDITAR, @IDARTICULO = 
