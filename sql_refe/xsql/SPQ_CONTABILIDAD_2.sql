			FROM OPENJSON(@PARAMETROS)
			WITH (
				REGISTRO NVARCHAR(MAX) AS JSON
			)
			SET @PROCESO = JSON_VALUE(@REGISTROS, '$.PROCESO')
			-- Extraer los valores del registro
			SELECT 
				@CODPRES = CODPRES, 
				@ITEM = ITEM,
				@TITULO = TITULO,
				@VARIABLETOTAL = VARIABLETOTAL,
				@TIPO = TIPO,
				@FORMULA = FORMULA,
				@ITEM_ANT = ITEM_ANT
			FROM OPENJSON(@REGISTROS)
			WITH (
				CODPRES VARCHAR(20) '$.CODPRES',
				ITEM INT '$.ITEM',
				TITULO VARCHAR(255) '$.TITULO',
				VARIABLETOTAL VARCHAR(50) '$.VARIABLETOTAL',
				TIPO VARCHAR(20) '$.TIPO',
				FORMULA VARCHAR(1024) '$.FORMULA',
				ITEM_ANT VARCHAR(3) '$.ITEM_ANT'
			)
			BEGIN TRY
				-- INSERTAR
				IF UPPER(@PROCESO) = 'INSERTAR'
				BEGIN
					IF @CODPRES IS NULL 
					BEGIN
						INSERT INTO @TBLERRORES(ERROR) VALUES ('C?digo de presupuesto (CODPRES) es requerido')
					END
					IF @ITEM IS NULL
					BEGIN
						INSERT INTO @TBLERRORES(ERROR) VALUES ('Item es requerido')
					END
					IF NOT EXISTS (SELECT 1 FROM KPRES WHERE CODPRES = @CODPRES)
					BEGIN
						INSERT INTO @TBLERRORES(ERROR) VALUES ('No existe el codigo en la tabla principal ' + CAST(@CODPRES AS VARCHAR))
					END
					IF EXISTS (SELECT 1 FROM KPRESD WHERE CODPRES = @CODPRES AND ITEM = @ITEM)
					BEGIN
						INSERT INTO @TBLERRORES(ERROR) VALUES ('Ya existe el Item ' + CAST(@ITEM AS VARCHAR) + ' para el crear grupos ' + @CODPRES)
					END
					-- Si no hay errores, insertar
					IF (SELECT COUNT(*) FROM @TBLERRORES) <= 0
					BEGIN
						INSERT INTO KPRESD (
							CODPRES, ITEM, TITULO, VARIABLETOTAL, TIPO, FORMULA
						)
						VALUES (
							@CODPRES, @ITEM, @TITULO, @VARIABLETOTAL, @TIPO, @FORMULA
						)
					END
				END
				-- EDITAR
				IF UPPER(@PROCESO) = 'EDITAR'
				BEGIN
					IF @CODPRES IS NULL 
					BEGIN
						INSERT INTO @TBLERRORES(ERROR) VALUES ('C?digo de presupuesto (CODPRES) es requerido')
					END
					IF @ITEM IS NULL
					BEGIN
						INSERT INTO @TBLERRORES(ERROR) VALUES ('Item es requerido')
					END
					IF(@ITEM <> @ITEM_ANT)
					BEGIN
						IF EXISTS (SELECT 1 FROM KPRESD WHERE ITEM = @ITEM)
						BEGIN
							INSERT INTO @TBLERRORES(ERROR) VALUES ('Ya existe otro item con el mismo valor')
						END
					END

					-- Si no hay errores, actualizar
					IF (SELECT COUNT(*) FROM @TBLERRORES) <= 0
					BEGIN
						UPDATE KPRESD
						SET ITEM = @ITEM,
							TITULO = @TITULO,
							VARIABLETOTAL = @VARIABLETOTAL,
							TIPO = @TIPO,
							FORMULA = @FORMULA
						WHERE CODPRES = @CODPRES AND ITEM = @ITEM_ANT
					END
				END
				-- ELIMINAR
				IF UPPER(@PROCESO) = 'ELIMINAR'
				BEGIN
					-- Validar dependencias si necesario (ej. KPRESDR)
					IF EXISTS (SELECT 1 FROM KPRESDR WHERE CODPRES = @CODPRES AND ITEM = @ITEM)
					BEGIN
						INSERT INTO @TBLERRORES(ERROR) VALUES ('No se puede eliminar: El item tiene rangos asociados (KPRESDR). Elim?nelos primero.')
					END
					IF (SELECT COUNT(*) FROM @TBLERRORES) <= 0
					BEGIN
						DELETE FROM KPRESD WHERE CODPRES = @CODPRES AND ITEM = @ITEM
					END
				END
			END TRY
			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
			END CATCH
			-- Retornar errores si existen
			IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
			BEGIN
				SELECT 'KO' AS OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			-- Todo ok
			SELECT 'OK' AS OK
			RETURN
		END
		IF @METODO = 'CRUD_KPRESDR'
		BEGIN
			DECLARE @TITULO_ANT VARCHAR(60);
			SELECT @REGISTROS = REGISTRO
			FROM OPENJSON(@PARAMETROS)
			WITH (
				REGISTRO NVARCHAR(MAX) AS JSON
			)
			SET @PROCESO = JSON_VALUE(@REGISTROS, '$.PROCESO')
			
			-- Extraer los valores del registro
			SELECT 
				@CODPRES = CODPRES, 
				@ITEM = ITEM,
				@TITULO = TITULO,
				@CUENTA_INICIAL = CUENTAINI,
				@CUENTA_FINAL = CUENTAFIN,
				@VARIABLETOTAL = VARIABLETOTAL,
				@CORRIENTE = CASE WHEN CORRIENTE = 1 THEN 1 ELSE 0 END,
				@CONORDEN = ORDEN,
				@TITULO_ANT = TITULO_ANT
			FROM OPENJSON(@REGISTROS)
			WITH (
				CODPRES VARCHAR(20) '$.CODPRES',
				ITEM INT '$.ITEM',
				TITULO VARCHAR(60) '$.TITULO',
				TITULO_ANT VARCHAR(60) '$.TITULO_ANT',
				CUENTAINI VARCHAR(16) '$.CUENTAINI',
				CUENTAFIN VARCHAR(16) '$.CUENTAFIN',
				VARIABLETOTAL VARCHAR(20) '$.VARIABLETOTAL',
				CORRIENTE INT '$.CORRIENTE',
				ORDEN INT '$.ORDEN'
			)  
			BEGIN TRY
				-- INSERTAR
				IF UPPER(@PROCESO) = 'INSERTAR'
				BEGIN
					IF @CODPRES IS NULL
					BEGIN
						INSERT INTO @TBLERRORES(ERROR) VALUES ('C?digo de presupuesto (CODPRES) es requerido')
					END
					IF @ITEM IS NULL
					BEGIN
						INSERT INTO @TBLERRORES(ERROR) VALUES ('Item es requerido')
					END
					IF @VARIABLETOTAL IS NULL 
					BEGIN
						INSERT INTO @TBLERRORES(ERROR) VALUES ('Totalizar es requerido')
					END
					IF @TITULO IS NULL OR @TITULO = ''
					BEGIN
						INSERT INTO @TBLERRORES(ERROR) VALUES ('T?tulo es requerido')
					END
					IF EXISTS (SELECT 1 FROM KPRESDR WHERE CODPRES = @CODPRES AND ITEM = @ITEM AND TITULO = @TITULO)
					BEGIN
						INSERT INTO @TBLERRORES(ERROR) VALUES ('Ya existe un rango con el T?tulo: ' + @TITULO)
					END
			
					-- Si no hay errores, insertar
					IF (SELECT COUNT(*) FROM @TBLERRORES) <= 0
					BEGIN
						INSERT INTO KPRESDR (
							CODPRES, ITEM, TITULO, CUENTAINI, CUENTAFIN, VARIABLETOTAL, CORRIENTE, ORDEN
						)
						VALUES (
							@CODPRES, @ITEM, @TITULO, @CUENTA_INICIAL, @CUENTA_FINAL, @VARIABLETOTAL, @CORRIENTE, @CONORDEN
						)
					END
				END
				-- EDITAR
				IF UPPER(@PROCESO) = 'EDITAR'
				BEGIN
					IF @TITULO_ANT IS NULL SET @TITULO_ANT = @TITULO
					IF EXISTS (SELECT 1 FROM KPRESDR WHERE CODPRES = @CODPRES AND ITEM = @ITEM AND TITULO = @TITULO AND TITULO <> @TITULO_ANT)
					BEGIN
						INSERT INTO @TBLERRORES(ERROR) VALUES ('Ya existe otro rango con el T?tulo: ' + @TITULO)
					END
					IF NOT EXISTS (SELECT 1 FROM KPRESDR WHERE CODPRES = @CODPRES AND ITEM = @ITEM AND TITULO = @TITULO_ANT)
					BEGIN
						INSERT INTO @TBLERRORES(ERROR) VALUES ('No existe el registro para actualizar')
					END
					-- Si no hay errores, actualizar
					IF (SELECT COUNT(*) FROM @TBLERRORES) <= 0
					BEGIN
						UPDATE KPRESDR
						SET 
							TITULO = @TITULO,
							CUENTAINI = @CUENTA_INICIAL,
							CUENTAFIN = @CUENTA_FINAL,
							VARIABLETOTAL = @VARIABLETOTAL,
							CORRIENTE = @CORRIENTE,
							ORDEN = @CONORDEN
						WHERE CODPRES = @CODPRES AND ITEM = @ITEM AND TITULO = @TITULO_ANT
					END
				END
				-- ELIMINAR
				IF UPPER(@PROCESO) = 'ELIMINAR'
				BEGIN
					IF (SELECT COUNT(*) FROM @TBLERRORES) <= 0
					BEGIN
						DELETE FROM KPRESDR WHERE CODPRES = @CODPRES AND ITEM = @ITEM AND TITULO = @TITULO
					END
				END
			END TRY
			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
			END CATCH
			-- Retornar errores si existen
			IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
			BEGIN
				SELECT 'KO' AS OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			-- Todo ok
			SELECT 'OK' AS OK
			RETURN
		END
