CREATE OR ALTER PROCEDURE DBO.SPQ_CONTABILIDAD_2
    @JSON NVARCHAR(MAX) 
WITH ENCRYPTION
AS
BEGIN
   
    SET NOCOUNT ON;

	DECLARE @PARAMETROS NVARCHAR(MAX),		@MODELO VARCHAR(100),		@METODO			VARCHAR(100),		@QUERY				VARCHAR(MAX),
			@USUARIO VARCHAR(20),			@CNSFACJ VARCHAR(20),		@NOADMISION		VARCHAR(16),		@IDKPAGE			INT,
			@DOCIDAFILIADO VARCHAR(20),		@DocumentoID VARCHAR (50),
			@PAGOS NVARCHAR(MAX) ,			@VALOR DECIMAL(18,2) ,		@CNSFCJ			VARCHAR(20),		@CONORDEN			VARCHAR(2),
			@ITEM			INT,			@REFERENCIA	VARCHAR(20),	@PROCEDENCIA	VARCHAR(25),		@OBSERVACION		VARCHAR(200),
			@ESTADO VARCHAR(25),			@CONSECUTIVO INT,			@IDAFILIADO		VARCHAR(20),		@VLRCOPAGO			DECIMAL(16,2),
			@IDPLAN			VARCHAR(6),		@N_FACTURA VARCHAR(16),		@TCNSFACJ		VARCHAR(15),		@PAGOSTFCJ			NVARCHAR(MAX),
			@IDKPAGED			INT,		@CODCAJA VARCHAR(15),		@NOMBRECLIENTE	VARCHAR(20),		@COMPUTERNAME		VARCHAR(20),
			@VALORPAGADOD	DECIMAL(18,2),	@COMPANIA  VARCHAR(2),		@CLASE_FAC		VARCHAR(20),		@IDTERCERO			VARCHAR(20),
			@VLRPENDIENTE	DECIMAL(18,2),	@TIPO VARCHAR(50),			@CLASE			VARCHAR(50),		@FECHAPAGO			DATE,			@FECHA				DATETIME,
			@CNSACJ VARCHAR(20),			@SYS_COMPUTERNAME VARCHAR(20), @SEDE		VARCHAR(16),		@CODIGOVOUCHER		VARCHAR(100),	@NROCOMPROBANTE		VARCHAR(50),
			@USUCAJA VARCHAR (50),			@RAZONANULACION VARCHAR(100)  ,@NOPRESTACION VARCHAR(20),	    @ULTIMO_ANO			INT,			@IDSEDE				VARCHAR(5),
			@ULTIMO_MES INT,		        @SIGUIENTE_ANO INT,        @SIGUIENTE_MES	INT,				@PERIODO_EXISTE		BIT,	        @NOMPERIODO			VARCHAR(13),
			@ANO INT,						@PERIODO_ABIERTO_EXISTE BIT, @FECHA_INI		DATE,				@FECHA_FIN			DATE,			@ANULAR_TRASLADO	BIT,
			@CNSLOG VARCHAR(20),			@EXISTE_TRASLADO BIT, 		@PERIODO_ANO	VARCHAR(4),			@PERIODO_MES		SMALLINT, 		@PERIODO_NOMBRE		VARCHAR(50),
			@CUENTA_INICIAL VARCHAR(20),	@CUENTA_FINAL VARCHAR(20),	 @ANO_INI		INT,				@MES_INI			INT,			@ANO_FIN			INT,
			@MES_FIN INT,					@CTA_INI VARCHAR(16),		@CTA_FIN		VARCHAR(16),        @PROCESO			VARCHAR(20),    @PERIODO_ANTERIOR	VARCHAR(6),
            @ANO_ANT INT,			        @MES_ANT INT,				@REGISTROS		NVARCHAR(MAX),		@CNSCIRUNI			INT,			@CNSPRO				VARCHAR(20),
			@MES SMALLINT,					@N_INICIAL VARCHAR(2),		@PYG			VARCHAR(2),			@PYGNIIF			VARCHAR(2), 	@ANOMESCERRAR		VARCHAR(6),
			@ANOMES VARCHAR(6),				@ULTIMO_ANO_CERRADO INT,	@ULTIMO_MES_CERRADO INT,			@ERRORES_INTEGRIDAD INT,			@NVOCONSEC			INT,
			@GEN_FILE BIT,					@CNSEXOFGE VARCHAR(20), 	@CNS			VARCHAR(20),		@WHERE				NVARCHAR(MAX),	@IDTERCEROINI		VARCHAR(20),
			@IDTERCEROFIN VARCHAR(20),		@CCOSTOINI VARCHAR(20),		@CCOSTOFIN		VARCHAR(20),		@TIPOMOVIMIENTO		VARCHAR(2),		@DOCUMENTO			VARCHAR(20),
			@CODUNG VARCHAR(5),				@CODPRG VARCHAR(20),		@SINCIERRE		BIT,				@TIPO_REPORTE		VARCHAR(20),	@CODPRES			VARCHAR(20), @CODPRES_ANT	VARCHAR(20),
			@DESCRIPCION VARCHAR(60),		@CUENTA_UTI VARCHAR(16),	@CUENTA_PER		VARCHAR(16),		@CUENTA_CIE			VARCHAR(16),	@IDFORMATO			VARCHAR(10),
			@TITULO VARCHAR(60),			@FORMULA	VARCHAR(1024),	@VARIABLETOTAL	VARCHAR(20),		@ITEM_ANT			VARCHAR(3),		@CORRIENTE			SMALLINT	
		;DECLARE @TBLERRORES TABLE(CONTINUA VARCHAR(2), ERROR VARCHAR(500))  
		SET DATEFORMAT dmy
		SELECT *
		INTO #JSON
		FROM OPENJSON (@json)
		WITH (
			MODELO         VARCHAR(100)     '$.MODELO',
			METODO         VARCHAR(100)     '$.METODO',
			USUARIO         VARCHAR(20)     '$.USUARIO',
			DOCIDAFILIADO VARCHAR(20)		'$.DOCIDAFILIADO',
			PARAMETROS     NVARCHAR(MAX)  AS JSON
		)
		SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO, @DOCIDAFILIADO= DOCIDAFILIADO-- , @TCNSFACJ= CNSFACJ
		FROM #JSON
		DECLARE @LOG_ERR TABLE (ERROR VARCHAR(500))
		
		IF @METODO = 'OBTENER_PERIODO_A_CERRAR'
		BEGIN  
			BEGIN TRY
				PRINT '1 VALIDACIONES'
				-- VALIDACI?N 1: Existencia de Per?odo de Saldos Iniciales
				IF (SELECT COUNT(1) FROM PRI WHERE COALESCE(SI,0) = 1) <> 1
				BEGIN
					SELECT 'KO' AS OK, 
						   ERROR = 'Inconsistencia en Cierres Contables. NO EXISTE Per?odo de Saldos Iniciales.'
					RETURN
				END
				-- VALIDACI?N 2: SI Abierto con Per?odos Cerrados
				PRINT '2 VALIDACIONES'
				IF EXISTS(SELECT 1 FROM PRI WHERE SI=1 AND COALESCE(CERRADO,0)=0)
				BEGIN
					IF (SELECT COUNT(1) FROM PRI WHERE COALESCE(SI,0) = 0 AND COALESCE(CERRADO,0)=1) > 0
					BEGIN
						SELECT 'KO' AS OK,
							   ERROR = 'Inconsistencia en Cierres Contables. El Per?odo de Saldos Iniciales No Est? Cerrado Y Existen Per?odos Siguientes Cerrados.'
						RETURN
					END
					ELSE
					BEGIN
						-- El per?odo a cerrar es el SI
						SELECT @ANOMESCERRAR = ANOMES FROM PRI WHERE SI=1 AND COALESCE(CERRADO,0)=0
					END
				END
        
				-- VALIDACI?N 3: Secuencia de Per?odos
				PRINT '3 VALIDACIONES'
				IF @ANOMESCERRAR IS NULL
				BEGIN
					DECLARE CUR_APER CURSOR FOR
					SELECT ANOMES, ANO, MES FROM PRI WHERE COALESCE(SI,0) = 0 AND COALESCE(CERRADO,0)=0 ORDER BY ANO, MES
					OPEN CUR_APER
					FETCH NEXT FROM CUR_APER INTO @ANOMES, @ANO, @MES
            
					WHILE @@FETCH_STATUS = 0
					BEGIN
						-- Verificar si existen per?odos posteriores cerrados
						IF EXISTS(SELECT 1 FROM PRI WHERE COALESCE(SI,0) = 0 AND TRY_CAST(ANOMES AS INT) > TRY_CAST(@ANOMES AS INT) AND COALESCE(CERRADO,0) = 1)
						BEGIN
							CLOSE CUR_APER
							DEALLOCATE CUR_APER
                    
							SELECT 'KO' AS OK,
								   ERROR = 'Inconsistencia en Cierres Contables. El Per?odo ' + 
										   CAST(@ANO AS VARCHAR) + '-' + RIGHT('0' + CAST(@MES AS VARCHAR), 2) + 
										   ' NO se ha Cerrado, Y Existen Per?odos Siguientes Cerrados.'
							RETURN
						END
						ELSE
						BEGIN
							-- VALIDACI?N 4: Cierre Fiscal
							PRINT '4 VALIDACIONES'
							IF EXISTS(SELECT 1 FROM PRI WHERE ANOMES=@ANOMES AND MES IN (SELECT MESDECIERRE FROM PAR WHERE COMPANIA = '01'))
							BEGIN
								-- Es un per?odo de cierre fiscal
								IF (SELECT COALESCE(CIERREFISCAL,0) FROM PRI WHERE ANOMES=@ANOMES) = 1
								BEGIN
									-- Verificar comprobantes sin confirmar o con errores
									IF (SELECT COUNT(1) FROM MCP WHERE COALESCE(ESTADO,0) <> 2 AND COALESCE(ANULADO,0) = 0 AND ANOMES=@ANOMES) > 0
									BEGIN
										CLOSE CUR_APER
										DEALLOCATE CUR_APER
                                
										SELECT 'KO' AS OK,
											   ERROR = 'Existen Comprobantes con errores o sin confirmar en el per?odo.'
										RETURN
									END 
									ELSE
									BEGIN
										SET @ANOMESCERRAR = @ANOMES
									END
								END
								ELSE
								BEGIN
									CLOSE CUR_APER
									DEALLOCATE CUR_APER
                            
									SELECT 'KO' AS OK,
										   ERROR = 'Inconsistencia en Cierres Contables. El Per?odo ' + 
												   CAST(@ANO AS VARCHAR) + '-' + RIGHT('0' + CAST(@MES AS VARCHAR), 2) + 
												   ' Es de Cierre Fiscal, Y No se ha hecho el proceso de cierre de cuentas 4,5 y 6.'
									RETURN
								END
							END
							ELSE
							BEGIN
								-- No es cierre fiscal, este es el per?odo a cerrar
								SET @ANOMESCERRAR = @ANOMES
							END
                    
							-- Salir del cursor
							BREAK
						END
                
						FETCH NEXT FROM CUR_APER INTO @ANOMES, @ANO, @MES
					END
            
					CLOSE CUR_APER
					DEALLOCATE CUR_APER
				END

				-- VALIDACI?N 5: Traslado de Costos
				PRINT '5 VALIDACIONES'
				IF @ANOMESCERRAR IS NOT NULL
				BEGIN
					IF DBO.FNK_VALORVARIABLE('CONTABGENTRASLACOSTO') = 'SI'
					BEGIN
              
						IF (SELECT COALESCE(CIERRE_TRASCOSTOS,0) FROM PRI WHERE ANO=@ANO AND MES=@MES) = 0
						BEGIN
							SELECT 'KO' AS OK,
								   ERROR = 'No Se Ha Realizado el Traslado de Costos Para Este Mes.'
							RETURN
						END
					END
				END

				-- VALIDACI?N 6: Resultado Final
				PRINT '6 VALIDACIONES'
				IF COALESCE(@ANOMESCERRAR,'') = ''
				BEGIN        
					SELECT 'KO' AS OK, ERROR = 'No Existe un Per?odo Que Cerrar.';
					RETURN
				END
        
				-- RETORNO EXITOSO

				SELECT 'OK' AS OK,  ANO, MES, COMPANIA, NOMPERIODO,  ANOMES FROM PRI WHERE ANOMES = @ANOMESCERRAR
        
			END TRY
			BEGIN CATCH
				SELECT 'KO' AS OK,
					   ERROR = ERROR_MESSAGE()
				RETURN
			END CATCH
    
			RETURN
		END
		IF @METODO = 'VALIDAR_PERIODO_BASICO'
		BEGIN
			DECLARE @DIACOM DATE
    
			BEGIN TRY
				SELECT @ANO = ANO,@MES = MES,@COMPANIA = COMPANIA
				FROM OPENJSON(@PARAMETROS)
				WITH (
					ANO INT,
					MES INT,
					COMPANIA VARCHAR(2)
				)
        
				-- Construir ANOMES
				SET @ANOMES = CAST(@ANO AS VARCHAR(4)) + RIGHT('0' + CAST(@MES AS VARCHAR(2)), 2)
        
				-- Obtener fecha del per?odo
				SET @DIACOM = DATEFROMPARTS(@ANO, @MES, 1)
        
				-- VALIDACI?N 1: Movimientos de Inventario Pendientes
				IF DBO.FNK_VALORVARIABLE('VALIDAINVCIERRECONT') = 'SI'
				BEGIN
					IF (SELECT COUNT(1) 
						FROM IMOV 
						WHERE FECHAMOV >= @DIACOM 
						  AND FECHAMOV <= EOMONTH(@DIACOM) 
						  AND COALESCE(ESTADO,0) = 0
						  AND IDTIPOMOV IN (SELECT IDTIPOMOV FROM ITMO WHERE SECONTABILIZA=1)) > 0
					BEGIN
						SELECT 'KO' AS OK,
							   ERROR = 'HAY MOVIMIENTOS DE INVENTARIO PENDIENTES POR CONFIRMAR PARA ESTE PERIODO CONTABLE'
						RETURN
					END
				END
        
				-- VALIDACI?N 2: Per?odo de Saldos Iniciales ?nico
				IF (SELECT COUNT(*) FROM PRI WHERE COALESCE(SI,0) = 1) <> 1
				BEGIN
					SELECT 'KO' AS OK,
						   ERROR = 'MAS DE UN PERIODO DEFINIDO COMO DE SALDOS INICIALES.'
					RETURN
				END
        
				-- VALIDACI?N 3: Verificar que el Per?odo NO est? ya Cerrado
				IF (SELECT COALESCE(CERRADO,0) FROM PRI WHERE ANOMES=@ANOMES) = 1
				BEGIN
					SELECT 'KO' AS OK,
						   ERROR = 'EL PERIODO YA ESTA CERRADO'
					RETURN
				END
        
				-- VALIDACI?N 4: Comprobantes sin Confirmar
				IF (SELECT COUNT(1) 
					FROM MCP 
					WHERE COALESCE(ESTADO,0) <> 2 
					  AND COALESCE(ANULADO,0) = 0 
					  AND ANOMES=@ANOMES) > 0
				BEGIN
					SELECT 'KO' AS OK,
						   ERROR = N'FALTAN COMPROBANTES POR CONFIRMAR',
						   ERRORES_DETALLE = (
							   SELECT
								   N'COMPROBANTES' AS MODULO,
								   MCP.NROCOMPROBANTE AS REFERENCIA,
								   CONCAT(
									   N'Sin confirmar. Tipo=', COALESCE(MCP.COMPROBANTE, N''),
									   N' | Estado=', COALESCE(CONVERT(VARCHAR(10), MCP.ESTADO), N''),
									   N' | Procedencia=', COALESCE(MCP.PROCEDENCIA, N''),
									   N' | NoRef=', COALESCE(MCP.NOREFERENCIA, N''),
									   N' | Usuario=', COALESCE(MCP.USUARIO, N'')
								   ) AS ERROR
							   FROM MCP
							   WHERE COALESCE(ESTADO, 0) <> 2
								 AND COALESCE(ANULADO, 0) = 0
								 AND ANOMES = @ANOMES
							   FOR JSON PATH
						   )
					RETURN
				END
        
				-- VALIDACI?N 5: Comprobantes con Errores (MCPE)
				IF (SELECT COUNT(1) FROM MCPE WHERE ANO=@ANO AND MES=@MES AND COALESCE(CLASECONTB,'') <> 'NIIF') > 0
				BEGIN
					SELECT 'KO' AS OK,
						   ERROR = N'EN EL PERIODO EXISTEN COMPROBANTES CON ERRORES (MCPE).',
						   ERRORES_DETALLE = (
							   SELECT
								   N'MCPE' AS MODULO,
								   COALESCE(MCPE.NROCOMPROBANTE, MCPE.NOREFERENCIA, N'') AS REFERENCIA,
								   CONCAT(
									   N'Comprobante con error. Procedencia=', COALESCE(MCPE.PROCEDENCIA, N''),
									   N' | Clase=', COALESCE(MCPE.CLASECONTB, N'')
								   ) AS ERROR
							   FROM MCPE
							   WHERE ANO = @ANO
								 AND MES = @MES
								 AND COALESCE(CLASECONTB, '') <> 'NIIF'
							   FOR JSON PATH
						   )
					RETURN
				END
        
				-- TODAS LAS VALIDACIONES B?SICAS PASARON
				SELECT 'OK' AS OK,
					   MENSAJE = 'Validaciones b?sicas completadas exitosamente',
					   ANO = @ANO,
					   MES = @MES,
					   ANOMES = @ANOMES
        
			END TRY
			BEGIN CATCH
				SELECT 'KO' AS OK,
					   ERROR = 'Error en validaciones b?sicas: ' + ERROR_MESSAGE(),
					   ERROR_LINE = ERROR_LINE()
				RETURN
			END CATCH
    
			RETURN
		END
		IF @METODO = 'EJECUTAR_CIERRE_PERIODO'
		BEGIN
			BEGIN TRY
				-- Extraer par?metros
				SELECT 
					@ANO = ANO,
					@MES = MES,
					@COMPANIA = COMPANIA
				FROM OPENJSON(@PARAMETROS)
				WITH (
					ANO INT,
					MES INT,
					COMPANIA VARCHAR(2)
				)
        
				SET @ANOMES = CAST(@ANO AS VARCHAR(4)) + RIGHT('0' + CAST(@MES AS VARCHAR(2)), 2)
        
				-- EJECUCI?N DEL CIERRE
				PRINT 'Ejecutando SPK_CIERRA_PERIODOCONTABLE...'
				EXEC SPK_CIERRA_PERIODOCONTABLE @ANO, @MES, @USUARIO
				PRINT 'SPK_CIERRA_PERIODOCONTABLE completado'
        
				-- LOG DE AUDITOR?A
				SELECT @COMPANIA = COMPANIA FROM USUSU WHERE USUARIO = @USUARIO
				SET @FECHA = GETDATE()
				SELECT @IDSEDE = IDSEDE 
				FROM UBEQ 
				WHERE SYS_ComputerName = (SELECT SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO)
        
				-- Generar consecutivo para log
				EXEC DBO.SPK_GENCONSECUTIVO
					@COMPANIA  = @COMPANIA,
					@SEDE      = @IDSEDE,
					@PREFIJO   = '@LOG',
					@NVOCONSEC = @NVOCONSEC OUTPUT
        
				SET @CNSLOG = @IDSEDE + RIGHT('00000000' + CAST(@NVOCONSEC AS VARCHAR(8)), 8);
        
				-- Insertar en USLOG (Log principal)
				INSERT INTO USLOG (CNSLOG, COMPANIA, NOADMISION, PROCESO, REQUEST, REFERENCIA, USUARIO, FECHA, SYS_ComputerName, TABLA)
				VALUES (
					@CNSLOG,
					@COMPANIA,
					'PERIODO ' + CAST(@ANO AS VARCHAR) + '-' + CAST(@MES AS VARCHAR),
					'CIERRE PERIODO',
					'CIERRE',
					'PERIODO ' + CAST(@ANO AS VARCHAR) + '-' + CAST(@MES AS VARCHAR),
					@USUARIO,
					@FECHA,
					HOST_NAME(),
					'PRI'
				)
        
				-- Insertar en USLOGH (Detalle del log)
				INSERT INTO USLOGH (CNSLOG, ITEM, CAMPO, VALORANT, VALORNVO)
				VALUES (@CNSLOG, 1, 'PRI:CERRADO', '0', '1')
        
				-- RETORNO EXITOSO
				SELECT 'OK' AS OK,
					   MENSAJE = 'Periodo cerrado exitosamente',
					   ANO = @ANO,
					   MES = @MES,
					   ANOMES = @ANOMES,
					   CNSLOG = @CNSLOG
        
			END TRY
			BEGIN CATCH
				SELECT 'KO' AS OK,
					   ERROR = 'Error al ejecutar el cierre: ' + ERROR_MESSAGE(),
					   ERROR_LINE = ERROR_LINE(),
					   ERROR_PROCEDURE = ERROR_PROCEDURE()
				RETURN
			END CATCH
    
			RETURN
		END
		IF @METODO = 'INICIAR_CIERRE_PERIODO'
		BEGIN
			BEGIN TRY
				DECLARE @JSON_JOB_CIERRE NVARCHAR(MAX);

				SELECT
					@ANO = ANO,
					@MES = MES,
					@COMPANIA = COMPANIA
				FROM OPENJSON(@PARAMETROS)
				WITH (
					ANO INT,
					MES INT,
					COMPANIA VARCHAR(2)
				);

				IF EXISTS (
					SELECT 1
					FROM PROCESO_JOB WITH (NOLOCK)
					WHERE TIPO = N'CIERRE_PERIODO'
					  AND ESTADO IN (N'PENDIENTE', N'PROCESANDO')
					  AND JSON_VALUE(PARAMETROS, '$.ANO') = CAST(@ANO AS VARCHAR(10))
					  AND JSON_VALUE(PARAMETROS, '$.MES') = CAST(@MES AS VARCHAR(10))
					  AND JSON_VALUE(PARAMETROS, '$.COMPANIA') = @COMPANIA
				)
				BEGIN
					SELECT 'KO' AS OK,
						   ERROR = N'Ya existe un cierre de periodo en ejecución para el mismo periodo.';
					RETURN;
				END;

				SET @JSON_JOB_CIERRE = (
					SELECT
						'PROCESO_JOB' AS MODELO,
						'INICIAR_JOB' AS METODO,
						@USUARIO AS USUARIO,
						JSON_QUERY((
							SELECT
								'CIERRE_PERIODO' AS TIPO,
								JSON_QUERY(@PARAMETROS) AS PARAMETROS
							FOR JSON PATH, WITHOUT_ARRAY_WRAPPER
						)) AS PARAMETROS
					FOR JSON PATH, WITHOUT_ARRAY_WRAPPER
				);

				EXEC DBO.SPQ_PROCESO_JOB @JSON_JOB_CIERRE;
			END TRY
			BEGIN CATCH
				SELECT 'KO' AS OK, ERROR = ERROR_MESSAGE();
			END CATCH

			RETURN;
		END
		IF @METODO = 'EJECUTAR_CIERRE_PERIODO_ASYNC'
		BEGIN
			BEGIN TRY
				DECLARE @RESULTADO_CIERRE NVARCHAR(MAX);

				SELECT
					@CNS = CNS,
					@ANO = ANO,
					@MES = MES,
					@COMPANIA = COMPANIA
				FROM OPENJSON(@PARAMETROS)
				WITH (
					CNS VARCHAR(20),
					ANO INT,
					MES INT,
					COMPANIA VARCHAR(2)
				);

				IF COALESCE(@CNS, '') = ''
				BEGIN
					SELECT 'KO' AS OK, ERROR = N'CNS es requerido.';
					RETURN;
				END;

				SET @ANOMES = CAST(@ANO AS VARCHAR(4)) + RIGHT('0' + CAST(@MES AS VARCHAR(2)), 2);

				UPDATE PROCESO_JOB
				SET ESTADO = N'PROCESANDO',
					FECHA_INICIO = COALESCE(FECHA_INICIO, GETDATE())
				WHERE CNS = @CNS;

				SELECT 'OK' AS OK, CNS = @CNS, ESTADO = N'PROCESANDO';

				BEGIN TRY
					PRINT N'Ejecutando SPK_CIERRA_PERIODOCONTABLE (async)...';
					EXEC SPK_CIERRA_PERIODOCONTABLE @ANO, @MES, @USUARIO;

					SELECT @COMPANIA = COMPANIA FROM USUSU WHERE USUARIO = @USUARIO;
					SET @FECHA = GETDATE();
					SELECT @IDSEDE = IDSEDE
					FROM UBEQ
					WHERE SYS_ComputerName = (SELECT SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO);

					EXEC DBO.SPK_GENCONSECUTIVO
						@COMPANIA  = @COMPANIA,
						@SEDE      = @IDSEDE,
						@PREFIJO   = '@LOG',
						@NVOCONSEC = @NVOCONSEC OUTPUT;

					SET @CNSLOG = @IDSEDE + RIGHT('00000000' + CAST(@NVOCONSEC AS VARCHAR(8)), 8);

					INSERT INTO USLOG (CNSLOG, COMPANIA, NOADMISION, PROCESO, REQUEST, REFERENCIA, USUARIO, FECHA, SYS_ComputerName, TABLA)
					VALUES (
						@CNSLOG,
						@COMPANIA,
						N'PERIODO ' + CAST(@ANO AS VARCHAR) + N'-' + CAST(@MES AS VARCHAR),
						N'CIERRE PERIODO',
						N'CIERRE',
						N'PERIODO ' + CAST(@ANO AS VARCHAR) + N'-' + CAST(@MES AS VARCHAR),
						@USUARIO,
						@FECHA,
						HOST_NAME(),
						N'PRI'
					);

					INSERT INTO USLOGH (CNSLOG, ITEM, CAMPO, VALORANT, VALORNVO)
					VALUES (@CNSLOG, 1, N'PRI:CERRADO', N'0', N'1');

					SET @RESULTADO_CIERRE = (
						SELECT
							OK = N'OK',
							MENSAJE = N'Periodo cerrado exitosamente',
							ANO = @ANO,
							MES = @MES,
							ANOMES = @ANOMES,
							CNSLOG = @CNSLOG
						FOR JSON PATH, WITHOUT_ARRAY_WRAPPER
					);

					UPDATE PROCESO_JOB
					SET ESTADO = N'COMPLETADO',
						FECHA_FIN = GETDATE(),
						RESULTADO_JSON = @RESULTADO_CIERRE
					WHERE CNS = @CNS;
				END TRY
				BEGIN CATCH
					UPDATE PROCESO_JOB
					SET ESTADO = N'ERROR',
						FECHA_FIN = GETDATE(),
						ERROR_MESSAGE = ERROR_MESSAGE()
					WHERE CNS = @CNS;
				END CATCH
			END TRY
			BEGIN CATCH
				SELECT 'KO' AS OK, ERROR = ERROR_MESSAGE();
			END CATCH

			RETURN;
		END
