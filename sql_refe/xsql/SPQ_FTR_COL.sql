			FROM OPENJSON(@DATOS)
			WITH (
				IDTERMAS VARCHAR(20) '$.IDTERMAS',
				IDPLANMAS VARCHAR(20) '$.IDPLANMAS',
				PROCE VARCHAR(20)      '$.PROCE',
				SEDEFMAS VARCHAR(6)    '$.SEDEFMAS'
