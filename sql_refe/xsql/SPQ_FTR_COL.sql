CREATE OR ALTER PROCEDURE DBO.SPQ_FTR_COL @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
SET DATEFORMAT dmy
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @PARAMETROS NVARCHAR(MAX)			,@MODELO VARCHAR(100)			   ,@METODO VARCHAR(100)
		,@USUARIO VARCHAR(12)				   ,@COMPANIA VARCHAR(2)		      ,@IDSEDE      VARCHAR(5)
		,@PREFIJO   VARCHAR(20)       		,@SYS_COMPUTERNAME VARCHAR(200)	,@CNSLOG	VARCHAR(20)
		,@IDMODELOAG VARCHAR(12)	         ,@PROCESO VARCHAR(100)= 'INSERT'	,@PROCESOFACTMAS INT
		,@NOW VARCHAR(20) = REPLACE(CONVERT(VARCHAR,GETDATE(),102),'.','')
		,@USUANULA   VARCHAR(20)             ,@RAZONANULA VARCHAR(256)        ,@N_FACTURA VARCHAR(20)
		,@IDDEP      VARCHAR(20)             ,@INDCARTERA BIT                 ,@INDCXC BIT
		,@PROCEDENCIA VARCHAR(20)            ,@CAPITA BIT                     ,@NOREFERENCIA VARCHAR(20)
		,@TIPOFACT VARCHAR(2)                ,@CONTABILIZADA SMALLINT
		DECLARE
		@CNSFTR VARCHAR(20)             ,@IDSEDEF VARCHAR(7)        ,@F_FACTURA DATETIME        ,@IDTERCERO VARCHAR(20)       ,@IDPLAN    VARCHAR(6)
		,@CAPIPGP   BIT                 ,@ABONOS    DECIMAL(14,2)   ,@DESCUENTOS DECIMAL(14,2)  ,@OBSERVACION VARCHAR(2048)   ,@CP_CONVENIO VARCHAR(20)
		,@CP_MODALIDAD VARCHAR(80)      ,@CP_MES       VARCHAR(20)  ,@FECHACAP_INI DATETIME     ,@FECHCACA_FIN DATETIME       ,@COPAPROPIO BIT
		,@VLRCOPAPRO DECIMAL(14,2)      ,@DV         SMALLINT       ,@TV VARCHAR(20)            ,@EC BIT                      ,@IDTERPART VARCHAR(20)
		,@IDFORMATOFTR VARCHAR(20)      ,@CNSRESOL     VARCHAR(20)  ,@TTEC VARCHAR(20)          ,@NODESCUENTACOPAGO BIT       ,@CUENTACXC VARCHAR(20)
		,@CUENTACXC_RAD VARCHAR(20)     ,@DATO  VARCHAR(20)         ,@DATO3  VARCHAR(20)        ,@NVOCONSEC  VARCHAR(20)      ,@N_CUOTA SMALLINT
		,@IDSERVICIO VARCHAR(20)        ,@ANEXO VARCHAR(2048)       ,@CANTIDAD DECIMAL(14,2)    ,@VALOR DECIMAL(14,2)         ,@VR_TOTAL DECIMAL(14,2)
		,@VALORCOPAGO  DECIMAL(14,2)		,@VALORMODERADORA  DECIMAL(14,2)
		,@CCOSTO VARCHAR(20)            ,@IDAREA VARCHAR(20)          ,@DATOS VARCHAR(MAX)           ,@CLASEORDEN VARCHAR(20)      ,@IDPESPECIAL VARCHAR(20)
		,@RIESGO VARCHAR(20)            ,@NOADMISION VARCHAR(20)      ,@IDTERCEROF VARCHAR(20)       ,@NOPRESTACION VARCHAR(20)    ,@NOITEM INT
		,@MARCAFAC BIT                  ,@USUMARCA VARCHAR(20)        ,@CNSFACT VARCHAR(20)          ,@TIPODOC VARCHAR(10)         ,@ESTDIAN SMALLINT
		,@IDAFILIADO VARCHAR(20)        ,@FECHAINI DATETIME           ,@FECHAFIN DATETIME            ,@FILTRO VARCHAR(MAX)			,@CANTIDAD_FACT_ANULAR INT
		,@CNSAGREGAPGP VARCHAR(20)      ,@COPAGOS_CP DECIMAL(14,2)    ,@VLR_CPROPIOFRD  DECIMAL(14,2),@SINENVIO BIT
		,@NOMBREXML VARCHAR(256)        ,@XML VARCHAR(MAX)            ,@NOMBREJSON VARCHAR(120)      ,@RIPSJSON VARCHAR(MAX)
		,@IDPLANSOAT VARCHAR(10)        ,@IDPLANFONSAT VARCHAR(10)    ,@IXCOUNTRY VARCHAR(20)        ,@SINCNT BIT
		,@TIPODCTO VARCHAR(2)           ,@VT DECIMAL(14,2)            ,@DESCUENTO DECIMAL(14,2)      ,@VE DECIMAL(14,2)
		,@VC DECIMAL(14,2)              ,@VP DECIMAL(14,2)            ,@F_VENCE DATETIME             ,@TIPOVENTA VARCHAR(10)
		,@CUOTAS SMALLINT               ,@NROCOMPROBANTE VARCHAR(20)  ,@DIASDIF SMALLINT             ,@TIPOFIN VARCHAR(1)          ,@NUMCONCNSFACT INT = 0
        ,@FECHAINIFIL DATE              ,@FECHAFINFIL DATE            ,@NUMCONCNSFACT2 INT = 0       ,@PART BIT
        ,@FTRAUTO  BIT                  ,@MONEDA  VARCHAR(5)          ,@TIPOCAP  SMALLINT            ,@FACTE SMALLINT
        ,@PGPEVE  VARCHAR(20)		     ,@USUARIOFACTURA VARCHAR(20)  ,@MODERADORA DECIMAL(14,2)     ,@COPAGOPROP BIT
        ,@FECHA_CAPRIPS DATE          , @CUV  VARCHAR(256)            ,@FRADICA_RIPS   DATETIME  , @JSON_RESPUESTA       VARCHAR(MAX)
	    ,@WHERE_DATA VARCHAR(500)		,@QUERY NVARCHAR(max)           ,@ARSTIPOCONTRATO VARCHAR(10)	,@RESPONSABLE VARCHAR(20)	,@RESP_NVO VARCHAR(12)
	    ,@IDCAUANULACION VARCHAR(5)  ,@GENERAR VARCHAR(3)				,@ACCION SMALLINT		,@TIPOEVENTO VARCHAR(10)	,@TOTAL_REGISTROS INT = 0
		,@REGISTROS_VALIDOS INT = 0	 ,@CONSECUTIVOCIT VARCHAR(20)		,@ALTOCOSTO VARCHAR(2)	,@ESPHD BIT = 0  ,@ESTRIPS VARCHAR(20)
		,@CNS VARCHAR(20)             ,@CANT_FACPAQ_CIT INT = 0   ,@PACIENTES_PAQUETE INT = 0 ,@FACTURAS_A_GENERAR INT = 0
BEGIN
	SELECT *
	INTO #JSON
	FROM OPENJSON(@json) WITH (
			MODELO VARCHAR(100) '$.MODELO'
			,METODO VARCHAR(100) '$.METODO'
			,USUARIO VARCHAR(12) '$.USUARIO'
			,PARAMETROS NVARCHAR(MAX) AS JSON
	)
	SELECT   @MODELO = MODELO			,@METODO = METODO
			,@PARAMETROS = PARAMETROS	,@USUARIO = USUARIO
	FROM #JSON
	SELECT @IDPLANSOAT   = DBO.FNK_VALORVARIABLE('IDPLANSOAT')
	SELECT @IDPLANFONSAT = DBO.FNK_VALORVARIABLE('IDPLANFONSAT')
	SELECT @IXCOUNTRY= DBO.FNK_VALORVARIABLE('IXCOUNTRY')

	IF @METODO = 'BUSCASED'
	BEGIN
		SELECT 'OK' AS OK
		SELECT DISTINCT COALESCE(FTR.IDSEDE,'00') value ,CONCAT(COALESCE(FTR.IDSEDE,'00'),' - ',COALESCE(SED.DESCRIPCION,'Sin Sede Asociada')) label
		FROM FTR LEFT JOIN SED ON FTR.IDSEDE=SED.IDSEDE
		RETURN
	END
	IF @METODO = 'SEDFACUMASI'
	BEGIN
		SELECT 'OK' AS OK
		SELECT DISTINCT COALESCE(SED.IDSEDE,'00') value ,CONCAT(COALESCE(SED.IDSEDE,'00'),' - ',COALESCE(SED.DESCRIPCION,'Sin Sede Asociada')) label
		FROM SED

        SELECT DBO.FNK_FECHA_GRINGA(CAST('01/'+CAST(MONTH(GETDATE()) AS VARCHAR(2))+'/'+CAST(YEAR(GETDATE()) AS VARCHAR(4)) AS DATE)) F_INICIAL,
                DBO.FNK_FECHA_GRINGA(CONVERT(DATE,GETDATE())) F_FACTURA

        SELECT SUM(CASE WHEN VK.NRODIAS<5 THEN 1 ELSE 0 END) MENOR5,SUM(CASE WHEN VK.NRODIAS>=5 AND VK.NRODIAS<=10 THEN 1 ELSE 0 END) EN5Y10,
        SUM(CASE WHEN VK.NRODIAS>=11 AND VK.NRODIAS<=15 THEN 1 ELSE 0 END)EN11Y15
        FROM FTR INNER JOIN VWK_ESTADODIAN_FTRE VK ON FTR.N_FACTURA=VK.N_FACTURA AND VK.TIPODOC='FACTURA'
        WHERE FTR.PROCEDENCIA<>'CAJA' AND VK.NRODIAS>0 AND VK.NRODIAS<=15
        RETURN
	END

	IF @METODO='ANULARFAC'
	BEGIN
		PRINT 'VOY A ANULAR '+@PARAMETROS
      DECLARE @NOREINTEGRO BIT
		SELECT @USUANULA= USUARIO,@N_FACTURA=N_FACTURA,@RAZONANULA=OBSANULA,@PART=CASE WHEN COALESCE(PART,'false')='true' THEN 1 ELSE 0 END,@IDCAUANULACION=IDCAUANULACION,
             @NOREINTEGRO=CASE WHEN NOREINTEGRO='1' THEN 1 ELSE 0 END
		FROM   OPENJSON (@PARAMETROS)
		WITH   (
				N_FACTURA VARCHAR(20)  '$.N_FACTURA'
				,USUARIO   VARCHAR(12)  '$.USUANULA'
				,OBSANULA   VARCHAR(256)  '$.OBSANULA',
				PART  VARCHAR(10)   '$.PART',
				IDCAUANULACION VARCHAR(5) '$.MOTIVO.value',
            NOREINTEGRO  VARCHAR(20)   '$.NOREINGERSO'
				)
        SELECT @NROCOMPROBANTE=NROCOMPROBANTE,@FACTE=FACTE,@IDTERCERO=IDTERCERO,@IDPLAN=IDPLAN FROM FTR WHERE N_FACTURA=@N_FACTURA
        PRINT 'FACTE='+STR(COALESCE(@FACTE,0))+'@NROCOMPROBANTE ='+COALESCE(@NROCOMPROBANTE,'SIN COMPROBANTE')
		IF NOT EXISTS(SELECT 1 FROM FTR WHERE N_FACTURA=@N_FACTURA AND ESTADO='P' AND COALESCE(TIPOANULACION,'')<>'NC')
			INSERT INTO @TBLERRORES(ERROR)
			SELECT 'Factura  Anulada...'
		IF EXISTS(SELECT 1 FROM FNOT WHERE N_FACTURA=@N_FACTURA AND ESTADO<>'A') AND @PART=0
			INSERT INTO @TBLERRORES(ERROR)
			SELECT 'Factura tiene Notas Debito/Credito Asociadas no se puede Anular'
		IF EXISTS(SELECT 1 FROM FPAGD INNER JOIN FPAG ON FPAG.CNSFPAG=FPAGD.CNSFPAG WHERE FPAGD.N_FACTURA=@N_FACTURA AND FPAG.INGRESO<>'DEVOLUCION')AND @PART=0
			INSERT INTO @TBLERRORES(ERROR)
			SELECT 'Factura tiene Pagos Asociadas no se puede Anular'
		SELECT @IDDEP=IDDEP,@INDCARTERA=INDCARTERA,@INDCXC=INDCXC,@PROCEDENCIA=PROCEDENCIA,@IDSEDE=IDSEDE,@CAPITA=COALESCE(CAPITADA,0)
		FROM FTR WHERE N_FACTURA=@N_FACTURA

		IF @PROCEDENCIA = 'SALUD' AND EXISTS(SELECT 1 FROM PPT WHERE IDTERCERO = @IDTERCERO AND IDPLAN = @IDPLAN AND PPT_TIPOADM = DBO.FNK_VALORVARIABLE('HTAD_HOSPITA'))
		BEGIN
			PRINT 'ES PHD'
			SET @ESPHD = 1
		END

		--IF @IDDEP<> DBO.FNK_VALORVARIABLE('IDFDEPFACTURACION') AND @PART=0 --- STORRES -- 20250522 -- SE QUITA VALIDACION POR QUE NO ESTA REPETIDA PERO CON MENSAJE DIFERENTE
		--	INSERT INTO @TBLERRORES(ERROR)
		--	SELECT 'Factura tiene Notas Debito/Credito Asociadas no se puede Anular'
		IF @IDDEP<> DBO.FNK_VALORVARIABLE('IDFDEPFACTURACION') AND @PART=0 AND @PROCEDENCIA NOT IN('MAD','CMV') AND ISNULL(@ESPHD,0)=0
			INSERT INTO @TBLERRORES(ERROR)
			SELECT 'La Factura No esta en el Departamento de Facturaci?n. No se puede Anular'
		IF @INDCARTERA=1  AND @PART=0 AND @PROCEDENCIA NOT IN('MAD','CMV') AND ISNULL(@ESPHD,0)=0
			INSERT INTO @TBLERRORES(ERROR)
			SELECT 'La Factura Se encuentra Asignada a una Cuenta por Cobrar no se puede Anular'
		IF @INDCXC=1  AND @PART=0 AND @PROCEDENCIA NOT IN('MAD','CMV') AND ISNULL(@ESPHD,0)=0
			INSERT INTO @TBLERRORES(ERROR)
			SELECT 'La Factura Se encuentra en una Cuenta por Cobrar ya Entregada no se puede Anular'

		DECLARE @P_CERRADO BIT, @P_CERRADO_CART BIT, @P_CERRADO_FAC BIT
		DECLARE @PERIODO_EXISTE BIT = 0
        DECLARE @FECHA_PROCESO DATE = CONVERT(DATE, GETDATE())

		SELECT @F_FACTURA = F_FACTURA, @COMPANIA = COMPANIA FROM FTR WHERE N_FACTURA = @N_FACTURA

		SELECT TOP 1 @PERIODO_EXISTE = 1, @P_CERRADO = PRI.CERRADO, @P_CERRADO_CART = COALESCE(PRI.CERRADO_CARTERA, 0), @P_CERRADO_FAC = COALESCE(PRI.CERRADO_FAC, 0)
		FROM PRI
		WHERE @FECHA_PROCESO >= CONVERT(DATE, PRI.FECHA_INI) AND @FECHA_PROCESO <= CONVERT(DATE, PRI.FECHA_FIN) AND PRI.COMPANIA = @COMPANIA

		PRINT CONCAT('data: ', @PERIODO_EXISTE, ' - ', @P_CERRADO, ' - ', @P_CERRADO_CART, ' - ', @P_CERRADO_FAC, '-', @COMPANIA)

		IF @PERIODO_EXISTE = 0
        BEGIN
            INSERT INTO @TBLERRORES(ERROR)
            SELECT 'Error Cr?tico: No existe configuraci?n de Periodo Contable para la fecha actual (' + CONVERT(VARCHAR, @FECHA_PROCESO, 103) + '). Porfavor, inicie periodo contable e intente de nuevo'
        END
        ELSE
        BEGIN
			IF @P_CERRADO = 1 AND @PART = 0
            BEGIN
                INSERT INTO @TBLERRORES(ERROR)
                SELECT 'Bloqueo: El Periodo Contable actual est? CERRADO. No se permiten anulaciones hoy.'
            END
            IF @P_CERRADO_CART = 1 AND @PART = 0
            BEGIN
                INSERT INTO @TBLERRORES(ERROR)
                SELECT 'Bloqueo: El Periodo de Cartera actual est? CERRADO.'
            END
            IF @P_CERRADO_FAC = 1 AND @PART = 0
            BEGIN
                INSERT INTO @TBLERRORES(ERROR)
                SELECT 'Bloqueo: El Periodo de Facturaci?n actual est? CERRADO.'
            END
        END
        IF @IXCOUNTRY<>'PERU' AND COALESCE(@FACTE,0)= 2 AND NOT EXISTS(SELECT * FROM MCP WHERE NROCOMPROBANTE=@NROCOMPROBANTE AND( ESTADO=2 OR COALESCE(ANULADO,0)<>1))
			INSERT INTO @TBLERRORES(ERROR)
			SELECT 'La Factura no se Encuentra correctamente contabilizada y ya fue enviada a la Dian. Es necesaria su Contabilizaci?n para generar la nota Cr?dito correspondiente'
		IF DBO.FNK_VALORVARIABLE('INTERFAZ_INV')='INTER_SAP' AND DBO.FNK_VALORVARIABLE('IXCOUNTRY') = 'PERU'
		BEGIN
			IF EXISTS(SELECT 1 FROM RIPSD WHERE RIPSD.N_FACTURA = @N_FACTURA)
			INSERT INTO @TBLERRORES(ERROR)
			SELECT 'La Factura se encuentra asignada en un lote. No se puede Anular'
		END

		IF (SELECT COUNT(1) FROM @TBLERRORES)> 0
		BEGIN
			PRINT 'ENTRO A ERRORES'
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
        print 'PASE TODAS LAS VALIDACIONES ENTRO AL BEGIN TRY'
		BEGIN TRY
			SELECT @SYS_COMPUTERNAME=COALESCE(SYS_COMPUTERNAME,HOST_NAME()) FROM USUSU WHERE USUARIO=@USUANULA
			IF @PROCEDENCIA NOT IN('FINANCIERO')
			    EXEC SPK_ANULA_FACT @N_FACTURA,'01',@IDSEDE,@USUARIO,@RAZONANULA,@SYS_COMPUTERNAME,@USUANULA,@PART,@IDCAUANULACION,@NOREINTEGRO
			ELSE
			BEGIN
				IF @CAPITA=1
					EXEC SPK_ANULA_FACT_CAPITADA @N_FACTURA,'01',@IDSEDE,@USUARIO,@RAZONANULA,@SYS_COMPUTERNAME,@USUANULA
				ELSE
 				    EXEC SPK_ANULA_FACT @N_FACTURA,'01',@IDSEDE,@USUARIO,@RAZONANULA,@SYS_COMPUTERNAME,@USUANULA,@PART,@IDCAUANULACION,@NOREINTEGRO
			END
		END TRY
		BEGIN CATCH
			IF @CAPITA=1
				INSERT INTO @TBLERRORES(ERROR) SELECT 'SPK_ANULA_FACT_CAPITADA '+@N_FACTURA+',''01'','+@IDSEDE+','+@USUARIO+','+@RAZONANULA+','+@SYS_COMPUTERNAME+','+@USUANULA
			ELSE
				INSERT INTO @TBLERRORES(ERROR) SELECT 'SPK_ANULA_FACT '+@N_FACTURA+',''01'','+@IDSEDE+','+@USUARIO+','+@RAZONANULA+','+@SYS_COMPUTERNAME+','+@USUANULA

			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH
		IF(SELECT COUNT(1) FROM @TBLERRORES)>0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' OK
		RETURN
	END
	IF @METODO='LIBERARFAC'
	BEGIN
		PRINT 'VOY A LIBERAR FACTURA'
		SELECT @USUANULA= USUARIO,@N_FACTURA=N_FACTURA,@RAZONANULA=OBSANULA,@IDCAUANULACION=IDCAUANULACION
		FROM   OPENJSON (@PARAMETROS)
		WITH   (
				N_FACTURA VARCHAR(20)  '$.N_FACTURA'
				,USUARIO   VARCHAR(12)  '$.USUANULA'
				,OBSANULA   VARCHAR(256)  '$.OBSANULA',
				IDCAUANULACION VARCHAR(5) '$.MOTIVO.value'
				)
		IF NOT EXISTS(SELECT 1 FROM FTR WHERE N_FACTURA=@N_FACTURA AND ESTADO='P' AND COALESCE(TIPOANULACION,'')<>'NC')
		BEGIN
			INSERT INTO @TBLERRORES(ERROR)
			SELECT 'Factura  Anulada...'
		END
		IF EXISTS(SELECT 1 FROM FNOT WHERE N_FACTURA=@N_FACTURA AND ESTADO<>'A')
		BEGIN
			INSERT INTO @TBLERRORES(ERROR)
			SELECT 'Factura tiene Notas Debito/Credito Asociadas no se puede liberar'
		END
		IF EXISTS(SELECT 1 FROM FPAGD INNER JOIN FPAG ON FPAG.CNSFPAG=FPAGD.CNSFPAG WHERE FPAGD.N_FACTURA=@N_FACTURA AND FPAG.INGRESO<>'DEVOLUCION')
		BEGIN
			INSERT INTO @TBLERRORES(ERROR)
			SELECT 'Factura tiene Pagos Asociadas no se puede liberar'
		END
		SELECT @IDDEP=IDDEP,@INDCARTERA=INDCARTERA,@INDCXC=INDCXC,@PROCEDENCIA=PROCEDENCIA,@IDSEDE=IDSEDE,@CAPITA=COALESCE(CAPITADA,0),
				@NOREFERENCIA=NOREFERENCIA,@TIPOFACT=TIPOFAC,@CONTABILIZADA=CONTABILIZADA, @IDPLAN = IDPLAN
		FROM FTR WHERE N_FACTURA=@N_FACTURA

		PRINT '<<<<< @IDPLANSOAT >>>> '+@IDPLANSOAT+' <<<<< @IDPLANFONSAT >>>>> '+@IDPLANFONSAT+' <<<<< @IDPLAN >>>> '+@IDPLAN
		IF @IDDEP<> DBO.FNK_VALORVARIABLE('IDFDEPFACTURACION') AND @PROCEDENCIA NOT IN ('MAD','CMV')
			INSERT INTO @TBLERRORES(ERROR) SELECT 'Factura tiene Notas Debito/Credito Asociadas no se puede liberar'
		IF @IDDEP<> DBO.FNK_VALORVARIABLE('IDFDEPFACTURACION') AND @PROCEDENCIA NOT IN ('MAD','CMV')
			INSERT INTO @TBLERRORES(ERROR) SELECT 'La Factura No esta en el Departamento de Facturaci?n. No se puede liberar'
		IF @INDCARTERA=1  AND @PROCEDENCIA NOT IN ('MAD','CMV')
			INSERT INTO @TBLERRORES(ERROR) SELECT 'La Factura Se encuentra Asignada a una Cuenta por Cobrar no se puede liberar'
		IF @INDCXC=1 AND @PROCEDENCIA NOT IN ('MAD','CMV')
			INSERT INTO @TBLERRORES(ERROR) SELECT 'La Factura Se encuentra en una Cuenta por Cobrar ya Entregada no se puede liberar'
		IF @PROCEDENCIA='SALUD' AND NOT EXISTS(SELECT * FROM HADM WHERE NOADMISION=@NOREFERENCIA)
			INSERT INTO @TBLERRORES(ERROR) SELECT 'No se encontro Nro de Admision Asociada a la Factura. No se puede liberar'
		IF @PROCEDENCIA='AUT' AND NOT EXISTS(SELECT * FROM AUT WHERE IDAUT=@NOREFERENCIA)
			INSERT INTO @TBLERRORES(ERROR) SELECT 'No se encontro Nro de Autorizaci?n Asociada a la Factura. No se puede liberar'
		IF @PROCEDENCIA='CI' AND @NOREFERENCIA <> 'VARIOS' AND NOT EXISTS(SELECT * FROM CIT WHERE CONSECUTIVO=@NOREFERENCIA) AND @IDPLAN NOT IN (@IDPLANFONSAT, @IDPLANSOAT)
			INSERT INTO @TBLERRORES(ERROR) SELECT 'No se encontro Cita  Asociada a la Factura. No se puede liberar'
		IF @PROCEDENCIA='FINANCIERO'
		BEGIN
			IF @CONTABILIZADA=0
				INSERT INTO @TBLERRORES(ERROR) SELECT 'La Factura no se ha Enviado a Contabilidad No Es nesesario Liberar'
		END
		IF (SELECT COUNT(1) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		BEGIN TRY
			SELECT @SYS_COMPUTERNAME=COALESCE(SYS_COMPUTERNAME,HOST_NAME()) FROM USUSU WHERE USUARIO=@USUANULA
			IF @PROCEDENCIA NOT IN('FINANCIERO','CAJA')
   			EXEC SPK_LIBERAR_FACT @N_FACTURA,'01',@IDSEDE,@USUARIO,@RAZONANULA,@SYS_COMPUTERNAME,@USUANULA,@IDCAUANULACION
			ELSE
			BEGIN
				IF DBO.FNK_VALORVARIABLE('IDTIPOCXP_DEFAULT')='COMER'
					EXEC SPK_LIBERA_FTR_COMER @N_FACTURA
				ELSE
					EXEC SPK_LIBERAR_FACT @N_FACTURA,'01',@IDSEDE,@USUARIO,@RAZONANULA,@SYS_COMPUTERNAME,@USUANULA
			END
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH
		IF(SELECT COUNT(1) FROM @TBLERRORES)>0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' OK
		RETURN
	END
	IF @METODO='ASINAR_RESPONSABLE'
	BEGIN
		PRINT 'VOY A ASIGNAR RESPONSABLE'
		IF COL_LENGTH('dbo.FTRLR', 'OBSERVACION') IS NULL
			ALTER TABLE dbo.FTRLR ADD OBSERVACION VARCHAR(500) NULL;

		SELECT @N_FACTURA=N_FACTURA, @RESPONSABLE=RESPONSABLE, @OBSERVACION=OBSERVACION
		FROM   OPENJSON (@PARAMETROS)
		WITH   (
				N_FACTURA VARCHAR(20)  '$.N_FACTURA'
				,RESPONSABLE VARCHAR(20) '$.RESPONSABLE'
				,OBSERVACION VARCHAR(500) '$.OBSERVACION'
				)

		BEGIN TRY
			SELECT @USUANULA = RESPONSABLE FROM FTR WHERE N_FACTURA = @N_FACTURA
			IF @USUANULA = @RESPONSABLE
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR = CONCAT('El usuario ', @RESPONSABLE, ' ya es responsable de esta factura.')
				RETURN;
			END

			UPDATE FTR SET RESPONSABLE = @RESPONSABLE
			WHERE N_FACTURA = @N_FACTURA

			INSERT INTO FTRLR (N_FACTURA, RESP_ANT, RESP_NVO, FECHA, USUARIO, OBSERVACION)
			SELECT @N_FACTURA, @USUANULA, @RESPONSABLE, GETDATE(), @USUARIO, NULLIF(LTRIM(RTRIM(@OBSERVACION)), '')
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH
		IF(SELECT COUNT(1) FROM @TBLERRORES)>0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' OK
		RETURN
	END
	IF @METODO='CREARFTR'
	BEGIN

		SELECT @DATOS=DATOS
		FROM   OPENJSON (@PARAMETROS)
		WITH (
			DATOS NVARCHAR(MAX) AS JSON
		)
