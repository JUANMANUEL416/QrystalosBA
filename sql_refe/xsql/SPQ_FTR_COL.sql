			EXEC SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE, '@RPDX', @CNSFACT_NUEVO OUTPUT
			SELECT @CNSFACT_NUEVO = @IDSEDE + REPLACE(SPACE(8 - LEN(@CNSFACT_NUEVO)) + LTRIM(RTRIM(@CNSFACT_NUEVO)), SPACE(1), 0)

