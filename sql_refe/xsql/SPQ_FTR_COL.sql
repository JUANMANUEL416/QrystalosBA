	-- =============================================
	-- METODO: REV_DUP_FTRDC
	-- Detecta prestaciones duplicadas en FTRDC (distinta procedencia, mismo afiliado/servicio/fecha)
	-- =============================================
	IF @METODO = 'REV_DUP_FTRDC'
	BEGIN
		PRINT 'REV_DUP_FTRDC'
		BEGIN TRY
			IF COALESCE(DBO.FNK_VALORVARIABLE('FTR_REV_DUP'), 'NO') <> 'SI'
			BEGIN
				SELECT 'KO' OK, 'La revisi?n de servicios duplicados no est? habilitada (FTR_REV_DUP).' AS ERROR
				RETURN
			END

			SELECT @CNSFTR = CNSFTR, @N_CUOTA = CONVERT(INT, N_CUOTA)
			FROM OPENJSON(@PARAMETROS)
			WITH (
				CNSFTR VARCHAR(40) '$.CNSFTR',
				N_CUOTA INT '$.N_CUOTA'
			)

			IF COALESCE(@CNSFTR, '') = '' OR COALESCE(@N_CUOTA, 0) = 0
			BEGIN
				SELECT 'KO' OK, 'Par?metros CNSFTR y N_CUOTA son obligatorios.' AS ERROR
				RETURN
			END

			IF NOT EXISTS (
				SELECT 1
				FROM FTR
				WHERE CNSFCT = @CNSFTR
				  AND ESTADO = 'P'
				  AND COALESCE(TIPOANULACION, '') <> 'NC'
			)
			BEGIN
				SELECT 'KO' OK, 'La factura no est? en estado pendiente o no permite revisi?n.' AS ERROR
				RETURN
			END

			SELECT
				F.CNSFTR,
				F.N_CUOTA,
				F.PROCEDENCIA,
				F.NOADMISION,
				F.NOPRESTACION,
				F.NOITEM,
				COALESCE(F.IDAFILIADO, V.IDAFILIADO, HADM.IDAFILIADO) AS IDAFILIADO,
				F.PACIENTE,
				F.IDSERVICIO,
				F.FECHA,
				F.VALOR,
				F.VALORTOTAL,
				CONVERT(DATE, F.FECHA) AS FECHA_ATENCION,
				CASE COALESCE(F.MARCA, 0)
					WHEN 1 THEN CONCAT('Marcado-', COALESCE(F.USUMARCA, ''))
					ELSE 'Asignado'
				END AS ESTADO_ACTUAL,
				COALESCE(V.DOCIDAFILIADO, AFI.DOCIDAFILIADO) AS DOCIDAFILIADO,
				SER.DESCSERVICIO,
				CONCAT(
					COALESCE(
						F.IDAFILIADO,
						V.IDAFILIADO,
						HADM.IDAFILIADO,
						CONCAT('PAC:', LTRIM(RTRIM(F.PACIENTE)))
					),
					'|', F.IDSERVICIO, '|',
					CONVERT(VARCHAR(10), CONVERT(DATE, F.FECHA), 23)
				) AS GRUPO_KEY
			INTO #DUP_BASE_FTRDC
			FROM FTRDC F
			INNER JOIN SER ON F.IDSERVICIO = SER.IDSERVICIO
			LEFT JOIN VWK_CARGOS_HADMAUTCIT V
				ON V.PROCEDENCIA = F.PROCEDENCIA
				AND V.NOADMISION = F.NOADMISION
				AND V.NOPRESTACION = F.NOPRESTACION
				AND V.NOITEM = F.NOITEM
			LEFT JOIN HADM
				ON F.PROCEDENCIA = 'HADM'
				AND HADM.NOADMISION = F.NOADMISION
			LEFT JOIN AFI ON AFI.IDAFILIADO = COALESCE(F.IDAFILIADO, V.IDAFILIADO, HADM.IDAFILIADO)
			WHERE F.CNSFTR = @CNSFTR
			  AND F.N_CUOTA = @N_CUOTA

			SELECT
				'OK' AS OK,
				(
					SELECT COUNT(DISTINCT DB.GRUPO_KEY)
					FROM #DUP_BASE_FTRDC DB
					WHERE DB.GRUPO_KEY IN (
						SELECT GRUPO_KEY
						FROM #DUP_BASE_FTRDC
						GROUP BY GRUPO_KEY
						HAVING COUNT(DISTINCT PROCEDENCIA) > 1
					)
				) AS TOTAL_GRUPOS,
				(
					SELECT COUNT(1)
					FROM #DUP_BASE_FTRDC DB
					WHERE DB.GRUPO_KEY IN (
						SELECT GRUPO_KEY
						FROM #DUP_BASE_FTRDC
						GROUP BY GRUPO_KEY
						HAVING COUNT(DISTINCT PROCEDENCIA) > 1
					)
				) AS TOTAL_REGISTROS

			SELECT
				DB.GRUPO_KEY,
				DB.PROCEDENCIA,
				DB.NOADMISION,
				DB.NOADMISION AS CONSECUTIVO,
				DB.NOPRESTACION,
				DB.NOITEM,
				DB.IDAFILIADO,
				DB.DOCIDAFILIADO,
				DB.PACIENTE,
				DB.IDSERVICIO,
				DB.DESCSERVICIO,
				DBO.FNK_FECHA_GRINGA(DB.FECHA) AS FECHA,
				DB.FECHA_ATENCION,
				DB.VALOR,
				DB.VALORTOTAL,
				DB.ESTADO_ACTUAL,
				DB.CNSFTR,
				DB.N_CUOTA
			FROM #DUP_BASE_FTRDC DB
			WHERE DB.GRUPO_KEY IN (
				SELECT GRUPO_KEY
				FROM #DUP_BASE_FTRDC
				GROUP BY GRUPO_KEY
				HAVING COUNT(DISTINCT PROCEDENCIA) > 1
			)
			ORDER BY
				DB.GRUPO_KEY,
				DB.PROCEDENCIA,
				DB.NOADMISION,
				DB.NOPRESTACION,
				DB.NOITEM

			DROP TABLE #DUP_BASE_FTRDC
		END TRY
		BEGIN CATCH
			IF OBJECT_ID('tempdb..#DUP_BASE_FTRDC') IS NOT NULL
				DROP TABLE #DUP_BASE_FTRDC
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF (SELECT COUNT(1) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		RETURN
	END

	-- =============================================
	-- METODO: APLICAR_REV_DUP_FTRDC
	-- Excluye registros descartados de FTRDC (reutiliza l?gica de QUITAR_FTRDC por ?tem)
	-- =============================================
	IF @METODO = 'APLICAR_REV_DUP_FTRDC'
	BEGIN
		PRINT 'APLICAR_REV_DUP_FTRDC'
		BEGIN TRY
			IF COALESCE(DBO.FNK_VALORVARIABLE('FTR_REV_DUP'), 'NO') <> 'SI'
			BEGIN
				SELECT 'KO' OK, 'La revisi?n de servicios duplicados no est? habilitada (FTR_REV_DUP).' AS ERROR
				RETURN
			END

			SELECT @CNSFTR = CNSFTR, @N_CUOTA = CONVERT(INT, N_CUOTA)
			FROM OPENJSON(@PARAMETROS)
			WITH (
				CNSFTR VARCHAR(40) '$.CNSFTR',
				N_CUOTA INT '$.N_CUOTA'
			)

			IF COALESCE(@CNSFTR, '') = '' OR COALESCE(@N_CUOTA, 0) = 0
			BEGIN
				SELECT 'KO' OK, 'Par?metros CNSFTR y N_CUOTA son obligatorios.' AS ERROR
				RETURN
			END

			IF NOT EXISTS (
				SELECT 1
				FROM FTR
				WHERE CNSFCT = @CNSFTR
				  AND ESTADO = 'P'
				  AND COALESCE(TIPOANULACION, '') <> 'NC'
			)
			BEGIN
				SELECT 'KO' OK, 'La factura no est? en estado pendiente o no permite revisi?n.' AS ERROR
				RETURN
			END

			SELECT
				PROCEDENCIA,
				NOADMISION,
				NOPRESTACION,
				CONVERT(INT, NOITEM) AS NOITEM
			INTO #DESCARTAR_FTRDC
			FROM OPENJSON(@PARAMETROS, '$.REGISTROS')
			WITH (
				PROCEDENCIA VARCHAR(12) '$.PROCEDENCIA',
				NOADMISION VARCHAR(16) '$.NOADMISION',
				NOPRESTACION VARCHAR(16) '$.NOPRESTACION',
				NOITEM SMALLINT '$.NOITEM'
			)

			IF NOT EXISTS (SELECT 1 FROM #DESCARTAR_FTRDC)
			BEGIN
				SELECT 'KO' OK, 'No se recibieron registros para descartar.' AS ERROR
				RETURN
			END

			SELECT @N_FACTURA = N_FACTURA, @COPAGOPROP = COALESCE(COPAPROPIO, 0)
			FROM FTR
			WHERE CNSFCT = @CNSFTR

			DECLARE curDescFtrdc CURSOR LOCAL FAST_FORWARD FOR
				SELECT PROCEDENCIA, NOADMISION, NOPRESTACION, NOITEM
				FROM #DESCARTAR_FTRDC

			OPEN curDescFtrdc
			FETCH NEXT FROM curDescFtrdc
			INTO @PROCEDENCIA, @NOADMISION, @NOPRESTACION, @NOITEM

			WHILE @@FETCH_STATUS = 0
			BEGIN
				IF NOT EXISTS (
					SELECT 1
					FROM FTRDC
					WHERE CNSFTR = @CNSFTR
					  AND N_CUOTA = @N_CUOTA
					  AND PROCEDENCIA = @PROCEDENCIA
					  AND NOADMISION = @NOADMISION
					  AND NOPRESTACION = @NOPRESTACION
					  AND NOITEM = @NOITEM
				)
				BEGIN
					INSERT INTO @TBLERRORES(ERROR)
					SELECT CONCAT(
						'Registro no encontrado en FTRDC: ',
						@PROCEDENCIA, '/', @NOADMISION, '/', @NOPRESTACION, '/', CONVERT(VARCHAR(10), @NOITEM)
					)
				END
				ELSE
				BEGIN
					IF @PROCEDENCIA = 'HADM'
					BEGIN
						UPDATE HPRED SET FACTURADA = 0, N_FACTURA = ''
						FROM HPRED
						INNER JOIN FTRDC A ON HPRED.NOPRESTACION = A.NOPRESTACION AND HPRED.NOITEM = A.NOITEM
						WHERE A.NOPRESTACION = @NOPRESTACION
						  AND A.CNSFTR = @CNSFTR
						  AND A.N_CUOTA = @N_CUOTA
						  AND A.NOITEM = @NOITEM
						  AND A.PROCEDENCIA = 'HADM'
					END
					IF @PROCEDENCIA = 'CIT'
					BEGIN
						UPDATE CIT SET FACTURADA = 0, N_FACTURA = ''
						FROM CIT
						INNER JOIN FTRDC A ON CIT.CONSECUTIVO = A.NOPRESTACION
						WHERE A.NOPRESTACION = @NOPRESTACION
						  AND A.CNSFTR = @CNSFTR
						  AND A.N_CUOTA = @N_CUOTA
						  AND A.NOITEM = @NOITEM
						  AND A.PROCEDENCIA = 'CIT'
					END
					IF @PROCEDENCIA = 'AUT'
					BEGIN
						UPDATE AUTD SET FACTURADA = 0, N_FACTURA = ''
						FROM AUTD
						INNER JOIN FTRDC A ON AUTD.IDAUT = A.NOPRESTACION AND AUTD.NO_ITEM = A.NOITEM
						WHERE A.NOPRESTACION = @NOPRESTACION
						  AND A.CNSFTR = @CNSFTR
						  AND A.N_CUOTA = @N_CUOTA
						  AND A.NOITEM = @NOITEM
						  AND A.PROCEDENCIA = 'AUT'

						IF NOT EXISTS (
							SELECT 1
							FROM AUTD
							WHERE FACTURADA = 1
							  AND COALESCE(N_FACTURA, '') <> ''
							  AND IDAUT = @NOPRESTACION
						)
						BEGIN
							UPDATE AUT SET FACTURADA = 0, N_FACTURA = ''
							FROM AUT
							INNER JOIN FTRDC A ON AUT.IDAUT = A.NOPRESTACION
							WHERE A.NOPRESTACION = @NOPRESTACION
							  AND A.CNSFTR = @CNSFTR
							  AND A.N_CUOTA = @N_CUOTA
							  AND A.NOITEM = @NOITEM
							  AND A.PROCEDENCIA = 'AUT'
						END
					END
					IF @PROCEDENCIA = 'ONCO'
					BEGIN
						UPDATE HCATDIMOV SET FACTURADA = 0, N_FACTURA = ''
						FROM HCATDIMOV
						INNER JOIN FTRDC A ON HCATDIMOV.CONSECUTIVOCIT = A.NOPRESTACION AND HCATDIMOV.ID = A.NOITEM
						WHERE A.NOPRESTACION = @NOPRESTACION
						  AND A.CNSFTR = @CNSFTR
						  AND A.N_CUOTA = @N_CUOTA
						  AND A.NOITEM = @NOITEM
						  AND A.PROCEDENCIA = 'ONCO'

						UPDATE CIT SET FACTURADA = 0, N_FACTURA = ''
						FROM CIT
						INNER JOIN FTRDC A ON CIT.CONSECUTIVO = A.NOPRESTACION
						WHERE A.NOPRESTACION = @NOPRESTACION
						  AND A.CNSFTR = @CNSFTR
						  AND A.N_CUOTA = @N_CUOTA
						  AND A.NOITEM = @NOITEM
						  AND A.PROCEDENCIA = 'ONCO'
					END
					IF @PROCEDENCIA = 'APLIM'
					BEGIN
						UPDATE CIT SET FACTURADA = 0, N_FACTURA = ''
						FROM CIT
						INNER JOIN FTRDC A ON CIT.CONSECUTIVO = A.NOPRESTACION
						WHERE A.NOPRESTACION = @NOPRESTACION
						  AND A.CNSFTR = @CNSFTR
						  AND A.N_CUOTA = @N_CUOTA
						  AND A.NOITEM = @NOITEM
						  AND A.PROCEDENCIA = 'APLIM'
					END

					DELETE FTRDC
					WHERE CNSFTR = @CNSFTR
					  AND N_CUOTA = @N_CUOTA
					  AND PROCEDENCIA = @PROCEDENCIA
					  AND NOADMISION = @NOADMISION
					  AND NOPRESTACION = @NOPRESTACION
					  AND NOITEM = @NOITEM

					-- IF @@ROWCOUNT = 0
					-- BEGIN
					-- 	INSERT INTO @TBLERRORES(ERROR)
					-- 	SELECT CONCAT(
					-- 		'No se pudo eliminar de FTRDC: ',
					-- 		@PROCEDENCIA, '/', @NOADMISION, '/', @NOPRESTACION, '/', CONVERT(VARCHAR(10), @NOITEM)
					-- 	)
					-- END
				END

				FETCH NEXT FROM curDescFtrdc
				INTO @PROCEDENCIA, @NOADMISION, @NOPRESTACION, @NOITEM
			END

			CLOSE curDescFtrdc
			DEALLOCATE curDescFtrdc
			DROP TABLE #DESCARTAR_FTRDC

			EXEC SPK_TOTALFACTURFIN @N_FACTURA;
		END TRY
		BEGIN CATCH
			IF CURSOR_STATUS('local', 'curDescFtrdc') >= 0
			BEGIN
				CLOSE curDescFtrdc
				DEALLOCATE curDescFtrdc
			END
			IF OBJECT_ID('tempdb..#DESCARTAR_FTRDC') IS NOT NULL
				DROP TABLE #DESCARTAR_FTRDC
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF (SELECT COUNT(1) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT @VR_TOTAL = VR_TOTAL, @COPAGOS_CP = CP_VLR_COPAGOS
		FROM FTR
		WHERE CNSFCT = @CNSFTR

		SELECT 'OK' OK, CP_VLR_SERVICIOS, CP_VLR_COPAGOS, VALORSERVICIOS, VR_TOTAL, VALORCOPAGO, VALORMODERADORA
		FROM FTR WHERE CNSFCT = @CNSFTR
		RETURN
	END

