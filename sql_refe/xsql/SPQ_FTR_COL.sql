	-- Alineado con worker claimNextFactura (ftre_model.js)
	-- =============================================
	IF @METODO IN ('RESET_NOTIFICADOS', 'CONTAR_FACTURAS_REENVIO', 'RESET_NOTIFICADOS_MASIVO')
	BEGIN
		DECLARE @WHERE_FILTRO NVARCHAR(MAX)
		DECLARE @CANTIDAD_REENVIO INT = 0
		DECLARE @CANTIDAD_ACTUALIZADA INT = 0
		DECLARE @FROM_FTRE NVARCHAR(MAX) = N'
			FROM FTRE
			INNER JOIN FTR ON FTR.N_FACTURA = FTRE.FTRN_FACTURA
				AND FTR.N_FACTURA = CONCAT(LTRIM(RTRIM(FTRE.PREFIJO)), FTRE.N_FACTURA)
			INNER JOIN TER ON TER.IDTERCERO = FTR.IDTERCERO'

		-- Solo filas que tienen sentido reenviar (ya notificadas, error o en proceso)
		DECLARE @COND_REENVIO NVARCHAR(500) = N'
			AND (
				COALESCE(FTRE.NOTIFICADO, 0) = 1
				OR COALESCE(FTRE.ESTADO_NOTIFICACION, 0) IN (1, 2, 3)
			)'

		IF @METODO = 'RESET_NOTIFICADOS'
		BEGIN
			BEGIN TRY
				SELECT @N_FACTURA = N_FACTURA
				FROM OPENJSON(@PARAMETROS)
				WITH (N_FACTURA VARCHAR(20) '$.N_FACTURA')

				IF COALESCE(@N_FACTURA, '') = ''
				BEGIN
					SELECT 'KO' OK, 'N_FACTURA es requerida.' AS ERROR
					RETURN
				END

				UPDATE F
				SET NOTIFICADO = 0,
					FECHA_NOTIFICADO = NULL,
					ESTADO_NOTIFICACION = 0,
					IDPROCESO = NULL,
					FECHA_PROCESO = NULL,
					MENSAJE_ERROR = NULL,
					INTENTOS_ENVIO = 0,
					ERROR = 0,
					OBSERVACION = NULL
				FROM FTRE F
				INNER JOIN FTR ON FTR.N_FACTURA = F.FTRN_FACTURA
					AND FTR.N_FACTURA = CONCAT(LTRIM(RTRIM(F.PREFIJO)), F.N_FACTURA)
				WHERE FTR.N_FACTURA = @N_FACTURA

				IF @@ROWCOUNT = 0
				BEGIN
					SELECT 'KO' OK, CONCAT('No se encontr? FTRE para la factura ', @N_FACTURA) AS ERROR
					RETURN
				END

				SELECT 'OK' OK
			END TRY
			BEGIN CATCH
				SELECT 'KO' OK, ERROR_MESSAGE() AS ERROR,
					ERROR_NUMBER() AS ERROR_NUMBER,
					ERROR_LINE() AS ERROR_LINE
			END CATCH
			RETURN
		END

		SELECT @WHERE_FILTRO = WHERE_DATA
		FROM OPENJSON(@PARAMETROS)
		WITH (WHERE_DATA NVARCHAR(MAX) '$.WHERE_DATA')

		IF COALESCE(LTRIM(RTRIM(@WHERE_FILTRO)), '') = ''
			SET @WHERE_FILTRO = N'1=1'

		-- Validaci?n b?sica del filtro din?mico (mismo criterio que READ_API_VALIDATION)
		IF @WHERE_FILTRO LIKE '%;%'
			OR @WHERE_FILTRO LIKE '%--%'
			OR @WHERE_FILTRO LIKE '%/*%'
			OR @WHERE_FILTRO LIKE '%*/%'
			OR @WHERE_FILTRO LIKE '% DROP %'
			OR @WHERE_FILTRO LIKE '% DELETE %'
			OR @WHERE_FILTRO LIKE '% INSERT %'
			OR @WHERE_FILTRO LIKE '% UPDATE %'
			OR @WHERE_FILTRO LIKE '% EXEC %'
			OR @WHERE_FILTRO LIKE '% EXECUTE %'
		BEGIN
			SELECT 'KO' OK, 'Filtro WHERE no permitido.' AS ERROR
			RETURN
		END

		IF @METODO = 'CONTAR_FACTURAS_REENVIO'
		BEGIN
			BEGIN TRY
				SET @QUERY = N'
					SELECT @CANTIDAD_REENVIO = COUNT(*)
					' + @FROM_FTRE + N'
					WHERE (' + @WHERE_FILTRO + N')
					' + @COND_REENVIO

				EXEC sp_executesql
					@QUERY,
					N'@CANTIDAD_REENVIO INT OUTPUT',
					@CANTIDAD_REENVIO = @CANTIDAD_REENVIO OUTPUT

				SELECT 'OK' OK, COALESCE(@CANTIDAD_REENVIO, 0) AS CANTIDAD
			END TRY
			BEGIN CATCH
				SELECT 'KO' OK, ERROR_MESSAGE() AS ERROR,
					ERROR_NUMBER() AS ERROR_NUMBER,
					ERROR_LINE() AS ERROR_LINE
			END CATCH
			RETURN
		END

		IF @METODO = 'RESET_NOTIFICADOS_MASIVO'
		BEGIN
			BEGIN TRY

				SET @WHERE_FILTRO = REPLACE(@WHERE_FILTRO,'FTRE', 'F')
				SET @COND_REENVIO = REPLACE(@COND_REENVIO,'FTRE', 'F')
				SET @QUERY = N'
					UPDATE F
					SET NOTIFICADO = 0,
						FECHA_NOTIFICADO = NULL,
						ESTADO_NOTIFICACION = 0,
						IDPROCESO = NULL,
						FECHA_PROCESO = NULL,
						MENSAJE_ERROR = NULL,
						INTENTOS_ENVIO = 0,
						ERROR = 0,
						OBSERVACION = NULL
					FROM FTRE F
					INNER JOIN FTR ON FTR.N_FACTURA = F.FTRN_FACTURA
						AND FTR.N_FACTURA = CONCAT(LTRIM(RTRIM(F.PREFIJO)), F.N_FACTURA)
					INNER JOIN TER ON TER.IDTERCERO = FTR.IDTERCERO
					WHERE (' + @WHERE_FILTRO + N')
					' + @COND_REENVIO

				EXEC sp_executesql @QUERY
				SET @CANTIDAD_ACTUALIZADA = @@ROWCOUNT

				SELECT 'OK' OK, @CANTIDAD_ACTUALIZADA AS CANTIDAD_ACTUALIZADA
			END TRY
			BEGIN CATCH
				SELECT 'KO' OK, ERROR_MESSAGE() AS ERROR,
					ERROR_NUMBER() AS ERROR_NUMBER,
					ERROR_LINE() AS ERROR_LINE
			END CATCH
			RETURN
		END
	END

	-- =============================================
	-- CORTCA56 ? Comparaci?n recaudo caja vs FTRDC (Excel)
	-- Dependencia: SPK_COMPARAR_RECAUDO_CAJA
	-- =============================================
	IF @METODO = 'COMPARAR_RECAUDO_CAJA'
	BEGIN
		PRINT 'COMPARAR_RECAUDO_CAJA'
		BEGIN TRY
			SELECT
				@CNSFTR = CNSFTR,
				@N_CUOTA = CONVERT(INT, N_CUOTA)
			FROM OPENJSON(@PARAMETROS)
			WITH (
				CNSFTR VARCHAR(40) '$.CNSFTR',
				N_CUOTA INT '$.N_CUOTA'
			)

			IF COALESCE(@CNSFTR, '') = ''
			BEGIN
				SELECT 'KO' OK, N'Par?metro CNSFTR es obligatorio.' AS ERROR
				RETURN
			END

			SELECT @N_FACTURA = N_FACTURA
			FROM FTR
			WHERE CNSFCT = @CNSFTR

			IF @N_FACTURA IS NULL
			BEGIN
				SELECT 'KO' OK, N'No se encontr? la factura indicada.' AS ERROR
				RETURN
			END

			IF NOT EXISTS (
				SELECT 1
				FROM FTR
				WHERE CNSFCT = @CNSFTR
				  AND COALESCE(CAPITADA, 0) = 1
			)
			BEGIN
				SELECT 'KO' OK, N'La comparaci?n de caja aplica solo a facturas capitadas / PGP.' AS ERROR
				RETURN
			END

			SELECT
				'OK' AS OK,
				@N_FACTURA AS N_FACTURA,
				@CNSFTR AS CNSFTR,
				@N_CUOTA AS N_CUOTA

			EXEC DBO.SPK_COMPARAR_RECAUDO_CAJA @CNSFTR = @CNSFTR, @N_CUOTA = @N_CUOTA
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF (SELECT COUNT(1) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		RETURN
	END

	-- =============================================
	-- CORTCA56 ? Ajuste totales FTR/FTRD para XML DIAN
	-- Dependencia: SPK_AJUSTAR_TOTALES_DIAN
	-- =============================================
	IF @METODO = 'AJUSTAR_TOTALES_DIAN'
	BEGIN
		PRINT 'AJUSTAR_TOTALES_DIAN'
		BEGIN TRY
			SELECT @CNSFTR = CNSFTR
			FROM OPENJSON(@PARAMETROS)
			WITH (CNSFTR VARCHAR(40) '$.CNSFTR')

			IF COALESCE(@CNSFTR, '') = ''
			BEGIN
				SELECT 'KO' OK, N'Par?metro CNSFTR es obligatorio.' AS ERROR
				RETURN
			END

			SELECT
				@N_FACTURA = N_FACTURA,
				@COPAGOPROP = COALESCE(COPAPROPIO, 0)
			FROM FTR
			WHERE CNSFCT = @CNSFTR

			IF @N_FACTURA IS NULL
			BEGIN
				SELECT 'KO' OK, N'No se encontr? la factura indicada.' AS ERROR
				RETURN
			END

			IF NOT EXISTS (
				SELECT 1
				FROM FTR
				WHERE CNSFCT = @CNSFTR
				  AND ESTADO = 'P'
				  AND COALESCE(TIPOANULACION, '') <> 'NC'
				  AND COALESCE(CAPITADA, 0) = 1
			)
			BEGIN
				SELECT 'KO' OK, N'La factura no est? pendiente, es nota cr?dito o no es capitada.' AS ERROR
				RETURN
			END

			IF NOT EXISTS (SELECT 1 FROM FTRDC WHERE CNSFTR = @CNSFTR)
			BEGIN
				SELECT 'KO' OK, N'No hay prestaciones en la relaci?n de c?pita (FTRDC).' AS ERROR
				RETURN
			END

			IF @COPAGOPROP = 1
			BEGIN
				SELECT 'KO' OK, N'La factura tiene copago propio activo. El valor enviado a la DIAN es el digitado por el usuario como anticipo; no se permite recalcular totales.' AS ERROR
				RETURN
			END

			EXEC DBO.SPK_AJUSTAR_TOTALES_DIAN @CNSFTR = @CNSFTR
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF (SELECT COUNT(1) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		RETURN
	END
END

