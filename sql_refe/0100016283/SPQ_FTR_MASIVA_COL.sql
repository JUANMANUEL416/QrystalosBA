         RETURN
      END

      IF @FFACTURA_FAC IS NULL
         SELECT @F_FACTURA = DBO.FNK_GETDATE()
      ELSE
         SELECT @F_FACTURA = @FFACTURA_FAC

      SELECT @COMPANIA = '01', @NIT_FAC = NIT
      FROM TER WHERE IDTERCERO = DBO.FNK_VALORVARIABLE('IDTERCEROINSTALADO')

      IF COALESCE(@NIT_FAC, '') = ''
      BEGIN
         INSERT INTO @TBLERRORES(ERROR) SELECT 'Tercero Facturador No Identificado, Revise Configuración Terceros'
         SELECT 'KO' OK
         SELECT ERROR FROM @TBLERRORES
         RETURN
      END

      IF NOT EXISTS (
         SELECT 1 FROM PRI
         WHERE FECHA_INI <= @F_FACTURA AND FECHA_FIN + 1 > @F_FACTURA AND COALESCE(CERRADO, 0) = 0
      )
      BEGIN
         INSERT INTO @TBLERRORES(ERROR) SELECT 'Periodo Contable No Existe o no Esta Abierto'
         SELECT 'KO' OK
         SELECT ERROR FROM @TBLERRORES
         RETURN
      END

      IF COALESCE(@IDSEDE_FAC, '') = '' OR UPPER(@IDSEDE_FAC) = 'TODAS'
      BEGIN
         SELECT @IDSEDE_FAC = COALESCE(NULLIF(TRIM(A.IDSEDE), ''), @SEDE, '01')
         FROM APLIM M WITH (NOLOCK)
         INNER JOIN APLI A WITH (NOLOCK) ON A.ID = M.IDAPLI
         WHERE M.ID = @IDAPLIM_FAC
      END

      IF DBO.FNK_VALORVARIABLE('FACTSEDE') = 'SI' AND (COALESCE(@IDSEDE_FAC, '') = '' OR UPPER(@IDSEDE_FAC) = 'TODAS')
      BEGIN
         INSERT INTO @TBLERRORES(ERROR) SELECT 'Debe indicar una sede concreta (FACTSEDE=SI)'
         SELECT 'KO' OK
         SELECT ERROR FROM @TBLERRORES
         RETURN
      END

      IF OBJECT_ID('tempdb..#NOPOS_AUTS') IS NOT NULL DROP TABLE #NOPOS_AUTS

      SELECT DISTINCT F.IDAUT
      INTO #NOPOS_AUTS
      FROM APLIMF F WITH (NOLOCK)
      INNER JOIN SER S WITH (NOLOCK) ON S.IDSERVICIO = F.IDSERVICIO
      INNER JOIN AUT A WITH (NOLOCK) ON A.IDAUT = F.IDAUT
      WHERE F.IDAPLIM = @IDAPLIM_FAC
        AND COALESCE(S.POS, 1) = 0
        AND COALESCE(F.FACTURADA, 0) = 0
        AND NULLIF(TRIM(F.IDAUT), '') IS NOT NULL
        AND A.ESTADO <> 'Anulada'
        AND COALESCE(A.FACTURADA, 0) = 0
        AND COALESCE(A.FACTURABLE, 0) = 1
        AND COALESCE(A.VALORTOTAL, 0) > 0
        AND (
              (COALESCE(@IDAUT_FAC, '') <> '' AND F.IDAUT = @IDAUT_FAC)
           OR (COALESCE(@IDAUT_FAC, '') = '' AND COALESCE(F.MARCA, 0) = 1)
        )

      SELECT @CANT_AUT = COUNT(1) FROM #NOPOS_AUTS
      IF COALESCE(@CANT_AUT, 0) = 0
      BEGIN
         INSERT INTO @TBLERRORES(ERROR)
         SELECT 'No hay autorizaciones pendientes de facturar para este evento (marque ítems con AUT o genere AUT primero)'
         SELECT 'KO' OK
         SELECT ERROR FROM @TBLERRORES
         IF OBJECT_ID('tempdb..#NOPOS_AUTS') IS NOT NULL DROP TABLE #NOPOS_AUTS
         RETURN
      END

      BEGIN TRY
         DECLARE @NOAUT_FAC VARCHAR(16)

         DECLARE CUR_NOPOS_FAC CURSOR LOCAL FAST_FORWARD FOR
         SELECT A.NOAUT
         FROM #NOPOS_AUTS T
         INNER JOIN AUT A ON A.IDAUT = T.IDAUT
         WHERE NULLIF(TRIM(A.NOAUT), '') IS NOT NULL

         OPEN CUR_NOPOS_FAC
         FETCH NEXT FROM CUR_NOPOS_FAC INTO @NOAUT_FAC
         WHILE @@FETCH_STATUS = 0
         BEGIN
            EXEC DBO.SPK_FACTURACE_N
               @NOAUT_FAC,
               @NIT_FAC,
               @COMPANIA,
               @IDSEDE_FAC,
               @USUARIO,
               '', '', '', '', '',
               'CE',
               @IDTERCERO,
               'FALSE',
               @IDPLAN,
               @F_FACTURA,
               NULL

            FETCH NEXT FROM CUR_NOPOS_FAC INTO @NOAUT_FAC
         END
         CLOSE CUR_NOPOS_FAC
         DEALLOCATE CUR_NOPOS_FAC

         UPDATE F
         SET FACTURADA = 1,
             N_FACTURA = A.N_FACTURA,
             MARCA = 0,
             USUARIOMARCA = NULL
         FROM APLIMF F
         INNER JOIN #NOPOS_AUTS T ON T.IDAUT = F.IDAUT
         INNER JOIN AUT A ON A.IDAUT = F.IDAUT
         WHERE F.IDAPLIM = @IDAPLIM_FAC
           AND COALESCE(A.FACTURADA, 0) = 1
           AND NULLIF(TRIM(A.N_FACTURA), '') IS NOT NULL

         IF NOT EXISTS (
            SELECT 1
            FROM APLIMF F
            INNER JOIN #NOPOS_AUTS T ON T.IDAUT = F.IDAUT
            WHERE F.IDAPLIM = @IDAPLIM_FAC
              AND COALESCE(F.FACTURADA, 0) = 1
              AND NULLIF(TRIM(F.N_FACTURA), '') IS NOT NULL
         )
         BEGIN
            INSERT INTO @TBLERRORES(ERROR)
            SELECT 'La facturación no dejó N_FACTURA en las autorizaciones; revise configuración / errores de facturación'
         END
      END TRY
      BEGIN CATCH
         IF CURSOR_STATUS('local', 'CUR_NOPOS_FAC') >= 0
         BEGIN
            CLOSE CUR_NOPOS_FAC
            DEALLOCATE CUR_NOPOS_FAC
         END
         INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
      END CATCH

      IF OBJECT_ID('tempdb..#NOPOS_AUTS') IS NOT NULL DROP TABLE #NOPOS_AUTS

      IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
      BEGIN
         SELECT 'KO' OK
         SELECT ERROR FROM @TBLERRORES
         RETURN
      END

      SELECT 'OK' OK, @CANT_AUT AS CANTIDAD, @IDAPLIM_FAC AS IDAPLIM
      RETURN
   END
END

