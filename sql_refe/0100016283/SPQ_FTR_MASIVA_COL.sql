				BEGIN CATCH
					INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
				END CATCH
				IF(SELECT COUNT(1) FROM @TBLERRORES)>0
				BEGIN
					SELECT 'KO' OK
					SELECT ERROR FROM @TBLERRORES
					RETURN
				END
				SELECT 'OK' OK
         END
      END
      ELSE IF @PROCEDENCIA='UNI'
      BEGIN
         IF @ACCION = 1
         BEGIN
            BEGIN TRY 
