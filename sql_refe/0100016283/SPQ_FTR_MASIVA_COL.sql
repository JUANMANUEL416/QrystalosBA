         SELECT @F_FACTURA=@FFACTURA

		SELECT @COMPANIA='01',@NIT=NIT
		FROM TER WHERE IDTERCERO=DBO.FNK_VALORVARIABLE('IDTERCEROINSTALADO')
		IF dbo.FNK_VALORVARIABLE('FACTSEDE')='SI'
		BEGIN
         IF @IDSEDEF = 'Todas'
