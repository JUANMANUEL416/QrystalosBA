CREATE OR ALTER PROCEDURE DBO.SPQ_NC_CONTAB_NOMINA @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @COM VARCHAR(6), @NOREFERENCIA VARCHAR(20), @ANO VARCHAR(4), @MES VARCHAR(2), @IDMODELOCONT VARCHAR(2), @IDPLAN VARCHAR(6), @TIPOTERCONTABLE VARCHAR(10), 
	@VLR_IMPUESTOS DECIMAL(14, 2), @CXP_TIPO VARCHAR(20), @PREFIJO_CUR VARCHAR(20), @CCOSTO_CUR VARCHAR(20), @IDAREA_CUR VARCHAR(20), @VLR_NETO_CUR DECIMAL(14, 2), 
	@PREFIJO_USCXS VARCHAR(10), @PROCEDENCIA VARCHAR(10), @ESTADO VARCHAR(1), @PROC_MCP VARCHAR(20), @TIPOCONTABILIZACION VARCHAR(1), @FECHATRA DATETIME, @CODUNG 
	VARCHAR(5), @MENSAJE VARCHAR(254), @NDIS INT, @TERCEROID VARCHAR(20), @METODO VARCHAR(100)
DECLARE @CNSPAGO VARCHAR(20), @NUMDOC VARCHAR(20), @CNSNIEPE VARCHAR(20), @USUARIO VARCHAR(12), @SYS_COMPUTERNAME VARCHAR(254), @COMPANIA VARCHAR(2), @SEDE VARCHAR(
		5), @NROCOMPROBANTE VARCHAR(20), @FECHACONTABLE DATETIME, @IDSEDE VARCHAR(5)
DECLARE @CNSFCXP VARCHAR(20), @CODPRF_CUR VARCHAR(20), @DESCRIPCION_CUR VARCHAR(100), @IDTERCERO_CUR VARCHAR(20), @FECHA_CUR DATETIME, @CODCONCEPTO_CUR VARCHAR(20
	), @NOMBRE_CONCEPTO_CUR VARCHAR(255), @VALOR_CUR DECIMAL(14, 2), @NUMDOC_CUR2 VARCHAR(20), @CANTIDAD_CUR2 DECIMAL(14, 2), @VALOR_CUR2 DECIMAL(14, 2), 
	@CCOSTO_CUR2 VARCHAR(20), @IDAREA_CUR2 VARCHAR(20), @CUENTA_CUR2 VARCHAR(20), @CNSNIEPE_CUR2 VARCHAR(20), @ITEMNIEPE_CUR2 DECIMAL(14, 0), @ITEM INT, @CODNOMINA 
	VARCHAR(20), @CUENTACR VARCHAR(20), @RUBRO VARCHAR(20), @PPPTO VARCHAR(20), @CDP VARCHAR(20), @TIPOCXP VARCHAR(20), @CNSRP VARCHAR(20), @CCOSTOPPTO VARCHAR(20), 
	@PORCENTAJE DECIMAL(14, 6), @RUBRO_ID INT, @VLR_SINDTO DECIMAL(14, 2), @SINDTO BIT, @NUMDOC2 VARCHAR(20), @VLR_INGRESOS DECIMAL(14, 2), @VLR_CXP DECIMAL(14, 2), 
	@MANEXO BIT, @IDTERCERO VARCHAR(20)
DECLARE @PROCESO VARCHAR(20), @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'CONTABILIZAR'
	BEGIN
		BEGIN TRY
			SELECT @PROCESO = PROCESO, @CNSPAGO = CNSPAGO, @NUMDOC = NUMDOC, @CNSNIEPE = CNSNIEPE, @COMPANIA = COMPANIA, @SEDE = SEDE, @SYS_COMPUTERNAME = SYS_COMPUTERNAME
				, @NROCOMPROBANTE = NROCOMPROBANTE, @FECHACONTABLE = CONVERT(DATE, FECHACONTABLE)
			FROM OPENJSON(@PARAMETROS) WITH (
					PROCESO VARCHAR(20) '$.PROCESO', CNSPAGO VARCHAR(20) '$.CNSPAGO', NUMDOC VARCHAR(20) '$.NUMDOC', CNSNIEPE VARCHAR(20) '$.CNSNIEPE', COMPANIA 
					VARCHAR(2) '$.COMPANIA', SEDE VARCHAR(5) '$.SEDE', SYS_COMPUTERNAME VARCHAR(254) '$.SYS_COMPUTERNAME', NROCOMPROBANTE VARCHAR(20) 
					'$.NROCOMPROBANTE', FECHACONTABLE VARCHAR(20) '$.FECHACONTABLE'
					)

			--BEGIN TRANSACTION  
			SELECT *
			INTO #T
			FROM NIEPE
			WHERE CNSPAGO = @CNSPAGO AND NUMDOC = @NUMDOC

			SELECT @TERCEROID = TERCEROID
			FROM NEMP
			WHERE NUMDOC = @NUMDOC

			SELECT NIEPED.*
			INTO #TH
			FROM NIEPE
			INNER JOIN NIEPED ON NIEPE.CNSNIEPE = NIEPED.CNSNIEPE AND NIEPE.NUMDOC = NIEPED.NUMDOC
			WHERE NIEPE.CNSPAGO = @CNSPAGO AND NIEPE.NUMDOC = @NUMDOC

			SELECT TOP 1 @CODUNG = #T.CODUNG
			FROM NOMI
			INNER JOIN #T ON NOMI.CODNOMINA = #T.CODNOMINA

			SET @MENSAJE = CAST(@CNSPAGO AS VARCHAR) + '-' + CAST(@NUMDOC AS VARCHAR) + '-' + CAST(@CNSNIEPE AS VARCHAR)

			SELECT @ANO = YEAR(@FECHACONTABLE), @MES = MONTH(@FECHACONTABLE), @FECHATRA = @FECHACONTABLE

			IF NOT EXISTS (
					SELECT COMPANIA, ANO, MES
					FROM PRI
					WHERE COMPANIA = @COMPANIA AND ANO = @ANO AND MES = @MES
					)
			BEGIN
				RAISERROR ('Periodo Contable NO Existe', 16, 1)

				RETURN
			END

			SET @IDMODELOCONT = DBO.FNK_VALORVARIABLE('IDMODELOCONTABLE')

			SELECT @TIPOCONTABILIZACION = ISNULL(DBO.FNK_VALORVARIABLE('NOMINATIPOCONTAB'), '1')

			SELECT @NDIS = ISNULL(COUNT(*), 0)
			FROM NDIS
			WHERE NDIS.CNSPAGO = @CNSPAGO AND NDIS.NUMDOC = @NUMDOC

			IF @NDIS = 0
			BEGIN
				--SI NO TIENE CONTABILIZACION, HACE LA CONTABILIZACION NORMAL.
				SET @TIPOCONTABILIZACION = '1'
			END

			DECLARE @TOTAL_PORCENTAJE DECIMAL(7, 2);-- VARIABLE PARA ALMACENAR EL % DE LA DISTRIBUCION DE LA PLANTA. 27-12-2-25 B.O

			SELECT @TOTAL_PORCENTAJE = ISNULL(SUM(NDISP.PORCENTAJE), 0)
			FROM NPLA
			INNER JOIN NDISP ON NDISP.CODPLANTA = NPLA.CODPLANTA
			WHERE NPLA.NUMDOC = @NUMDOC;-- % DE DISTRIBUCION DE LA PLANTTA DEL EMPLEADO PROCESADO.  27-12-2-25 B.O

			IF @TOTAL_PORCENTAJE = 100 AND ISNULL(DBO.FNK_VALORVARIABLE('NOMINATIPOCONTAB'), '1') = '3'
				-- VALIDAR QUE LA DISTRIBUCION CUMPLA UN 100% Y EL TIPO DE CONTABILIZACION SEA 3 (DIST. POR CCOSO DE LA PLANTA) 27-12-2-25 B.O
			BEGIN
				SET @TIPOCONTABILIZACION = '3'

				PRINT '@TIPOCONTABILIZACION=' + @TIPOCONTABILIZACION
			END
			ELSE
			BEGIN
				SET @TIPOCONTABILIZACION = '1'

				PRINT '@TIPOCONTABILIZACION=' + @TIPOCONTABILIZACION
			END

			IF ISNULL(@NROCOMPROBANTE, '') = '' -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD
			BEGIN
				SET @PROC_MCP = 'NOMINA'
				SET @NROCOMPROBANTE = SPACE(20) -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD

				EXEC SPK_GENCONSECUTIVO @COMPANIA, @SEDE, '@MCP', @NROCOMPROBANTE OUTPUT -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD

				PRINT '@NROCOMPROBANTE:' + ISNULL(@NROCOMPROBANTE, '') -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD

				SELECT @NROCOMPROBANTE = @SEDE + REPLACE(SPACE(8 - CASE 
								WHEN LEN(@NROCOMPROBANTE) > 8
									THEN 8
								ELSE LEN(@NROCOMPROBANTE)
								END) + LTRIM(RTRIM(@NROCOMPROBANTE)), SPACE(1), 0) -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD

				PRINT '@NROCOMPROBANTE:' + ISNULL(@NROCOMPROBANTE, '') -- MODIFICADO POR R.JAY 2009.04.18 PARA ELIMINAR DUPLICIDAD

				--SET @COM=LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('IDCON_TCOM_CXP_NOM')))
				IF (
						SELECT DBO.FNK_VALORVARIABLE('COMPROBMULTISEDE')
						) = 'SI'
				BEGIN
					SELECT @COM = RTRIM(LTRIM(COMMS.COMPROBANTE))
					FROM COMMS
					WHERE COMMS.IDSEDE = @SEDE AND COMMS.CLASE = 'NOMINA' AND COMMS.TIPO = 'NOMINA'
				END
				ELSE
				BEGIN
					SET @COM = LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('IDCON_TCOM_NOMINA')))
				END

				IF @COM = '' OR @COM IS NULL
					SET @COM = DBO.FNK_VALORVARIABLE('IDCON_TCOM_DEFAULT')

				IF @COM = '' OR @COM IS NULL
				BEGIN
					RAISERROR ('La variable de Sistemas IDCON_TCOM_DEFAULT está sin Definir.', 16, 1)

					--ROLLBACK
					RETURN
				END

				-- PRINT 'COM='+@COM
				SET @PREFIJO_USCXS = '@COM' + @COM
				SET @NOREFERENCIA = SPACE(20)

				EXEC SPK_GENCONSECUTIVO @COMPANIA, @SEDE, @PREFIJO_USCXS, @NOREFERENCIA OUTPUT

				SELECT @NOREFERENCIA = REPLACE(SPACE(8 - LEN(@NOREFERENCIA)) + LTRIM(RTRIM(@NOREFERENCIA)), SPACE(1), 0)

				--   PRINT 'Nuevo Comprobante: '+@COM+' '+@NOREFERENCIA
				--   PRINT 'Comprobante Contable (MCP)'
				INSERT INTO MCPE (
					NROCOMPROBANTE, COMPANIA, PROCEDENCIA, NOREFERENCIA, ANO, MES, FECHACONTABLE, TOTALDEBITO, TOTALCREDITO, REFERENCIA1, REFERENCIA2, 
					REFERENCIA3, USUARIO, FECHA, LOTE, OBSERVACION, IDSEDE, ESTADO, COMPROBANTE, IDTERCERO
					)
				SELECT @NROCOMPROBANTE, @COMPANIA, 'NOMINA', @NOREFERENCIA, @ANO, @MES, @FECHATRA, 0, 0, @NUMDOC, @CNSPAGO, @CNSNIEPE, @USUARIO, DBO.
					FNK_FECHA_SIN_MLS(GETDATE()), NULL, 'PAGO DE NOMINA', @SEDE, 0, @COM, @TERCEROID
			END
			ELSE
			BEGIN
				IF @ESTADO = 'A'
				BEGIN
					DELETE MCHE
					WHERE NROCOMPROBANTE = @NROCOMPROBANTE AND PROCEDENCIA = 'NOMINA' AND REFERENCIA_PRO = @TERCEROID

					IF (
							SELECT COUNT(*)
							FROM MCHE
							WHERE NROCOMPROBANTE = @NROCOMPROBANTE
							) = 0
					BEGIN
						UPDATE MCPE
						SET ESTADO = '2', ANULADO = 1, TOTALDEBITO = 0, TOTALCREDITO = 0, REFERENCIA3 = @CNSNIEPE
						WHERE COMPANIA = @COMPANIA AND NROCOMPROBANTE = @NROCOMPROBANTE
					END

					RETURN
				END
				ELSE
				BEGIN
					DELETE MCHE
					WHERE NROCOMPROBANTE = @NROCOMPROBANTE AND PROCEDENCIA = 'NOMINA' --AND REFERENCIA_PRO=@NUMDOC

					UPDATE MCPE
					SET OBSERVACION = 'PAGO DE NOMINA'
					WHERE MCPE.NROCOMPROBANTE = @NROCOMPROBANTE AND MCPE.PROCEDENCIA = 'NOMINA' AND MCPE.REFERENCIA1 = @NUMDOC

					SELECT @COM = COMPROBANTE, @NOREFERENCIA = NOREFERENCIA
					FROM #T
				END
			END

			-- PRINT 'Insertando Asiento DB Para Conceptos de Empleados' 
			-----------------------** CONTABILIZACION NORMAL
			PRINT '@TIPOCONTABILIZACION=' + @TIPOCONTABILIZACION

			IF @TIPOCONTABILIZACION = '1'
			BEGIN
				PRINT 'ISNERT'

				INSERT INTO MCHE (
					NROCOMPROBANTE, COMPANIA, TIPO, CUENTA, IDTERCERO, CCOSTO, DETALLE, VALOR, REFERENCIA1, REFERENCIA2, ITEMREF, USUARIO, FECHA, PREFIJO, IDAREA, 
					CLASECONT, ESTADO, PROCESO, GENERA, N_FACTURA, F_FACTURAREF, F_VENCE, CLASE_GENERA, PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG, IDSEDE
					)
				SELECT @NROCOMPROBANTE, @COMPANIA, CASE 
						WHEN NCON.TIPO = 'Ingreso'
							THEN 'DB'
						ELSE 'CR'
						END, DBO.FNK_NC_CUENTA_KMCOM(@IDMODELOCONT, 'NOMINA', CASE 
							WHEN NCON.TIPO = 'Ingreso'
								THEN 'DB'
							ELSE 'CR'
							END, NCON.CODCONCEPTO, #T.CCOSTO, 'S', #T.CODNOMINA, 0), CASE 
						WHEN COALESCE(#TH.RECOBRO, 0) = 1 AND NCON.TIPO = 'Ingreso'
							THEN #TH.IDTERCERO_RECO
						WHEN COALESCE(#TH.RECOBRO, 0) = 1 AND NCON.TIPO = 'Egreso'
							THEN @TERCEROID
						ELSE #TH.IDTERCERO_PRF
						END, #T.CCOSTO, UPPER(NCON.DESCRIPCION), #TH.VALOR, @CNSPAGO, @TERCEROID, NULL, @USUARIO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), #TH.
					CODCONCEPTO, #T.IDAREA, 'S', 1, 'NOMINA_NCON', 'Movimiento', @CNSPAGO, DBO.FNK_FECHA_SIN_HORA(@FECHATRA), DBO.FNK_FECHA_SIN_HORA(@FECHATRA
					), 'NOMINA', 'NOMINA', @TERCEROID, #T.CODUNG, NEMP.CODPRG, #T.IDSEDE
				FROM #T
				INNER JOIN #TH ON #T.CNSNIEPE = #TH.CNSNIEPE AND #T.NUMDOC = #TH.NUMDOC
				INNER JOIN NCON ON #TH.CODCONCEPTO = NCON.CODCONCEPTO
				INNER JOIN NEMP ON #TH.NUMDOC = NEMP.NUMDOC
				INNER JOIN (
					SELECT ROW_NUMBER() OVER (
							PARTITION BY CODCONCEPTO ORDER BY FECHAINI DESC
							) [RITEM], CODCONCEPTO, ITEM
					FROM NCOND
					WHERE @FECHACONTABLE >= FECHAINI
					) X ON X.CODCONCEPTO = NCON.CODCONCEPTO AND X.RITEM = 1
				INNER JOIN NCOND ON X.CODCONCEPTO = NCOND.CODCONCEPTO AND X.ITEM = NCOND.ITEM
				WHERE #TH.VALOR <> 0 AND #TH.INFO = 'No'
				ORDER BY NCON.NATURALEZA DESC
			END

			-----------------------** CONTABILIZACION NORMAL
			IF @TIPOCONTABILIZACION = '2'
			BEGIN
				-----------------------** CONTABILIZACION POR AREA FUNCIONA Y CENTRO DE COSTO --CREDITOS
				INSERT INTO MCHE (
					NROCOMPROBANTE, COMPANIA, TIPO, CUENTA, IDTERCERO, CCOSTO, DETALLE, VALOR, REFERENCIA1, REFERENCIA2, ITEMREF, USUARIO, FECHA, PREFIJO, IDAREA, 
					CLASECONT, ESTADO, PROCESO, GENERA, N_FACTURA, F_FACTURAREF, F_VENCE, CLASE_GENERA, PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG, IDSEDE
					)
				SELECT @NROCOMPROBANTE, @COMPANIA, CASE 
						WHEN NCON.TIPO = 'Ingreso'
							THEN 'DB'
						ELSE 'CR'
						END, DBO.FNK_NC_CUENTA_KMCOM(@IDMODELOCONT, 'NOMINA', CASE 
							WHEN NCON.TIPO = 'Ingreso'
								THEN 'DB'
							ELSE 'CR'
							END, NCON.CODCONCEPTO, CASE NDIS.CCOSTO
							WHEN NULL
								THEN #T.CCOSTO
							ELSE NDIS.CCOSTO
							END, 'S', #T.CODNOMINA, 0), CASE 
						WHEN COALESCE(#TH.RECOBRO, 0) = 1 AND NCON.TIPO = 'Ingreso'
							THEN #TH.IDTERCERO_RECO
						ELSE #TH.IDTERCERO_PRF
						END, NDIS.CCOSTO, UPPER(NCON.DESCRIPCION), #TH.VALOR * (
						CASE NDIS.PORCENTAJE
							WHEN NULL
								THEN 1
							ELSE NDIS.PORCENTAJE / 100
							END
						), @CNSPAGO, @TERCEROID, NULL, @USUARIO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), #TH.CODCONCEPTO, NDIS.IDAREA, 'S', 1, 'NOMINA_NCON', 
					'Movimiento', @CNSPAGO, DBO.FNK_FECHA_SIN_HORA(@FECHATRA), DBO.FNK_FECHA_SIN_HORA(@FECHATRA), 'NOMINA', 'NOMINA', @TERCEROID, #T.CODUNG, 
					NEMP.CODPRG, #T.IDSEDE
				FROM #T
				INNER JOIN #TH ON #T.CNSNIEPE = #TH.CNSNIEPE AND #T.NUMDOC = #TH.NUMDOC
				INNER JOIN NCON ON #TH.CODCONCEPTO = NCON.CODCONCEPTO
				INNER JOIN NEMP ON #TH.NUMDOC = NEMP.NUMDOC
				LEFT JOIN NDIS ON NDIS.CNSPAGO = @CNSPAGO AND #TH.NUMDOC = NDIS.NUMDOC
				INNER JOIN (
					SELECT ROW_NUMBER() OVER (
							PARTITION BY CODCONCEPTO ORDER BY FECHAINI DESC
							) [RITEM], CODCONCEPTO, ITEM
					FROM NCOND
					WHERE @FECHACONTABLE >= FECHAINI
					) X ON X.CODCONCEPTO = NCON.CODCONCEPTO AND X.RITEM = 1
				INNER JOIN NCOND ON X.CODCONCEPTO = NCOND.CODCONCEPTO AND X.ITEM = NCOND.ITEM
				WHERE #TH.VALOR <> 0 AND #TH.INFO = 'No'
				ORDER BY NCON.NATURALEZA DESC
					-----------------------** CONTABILIZACION POR CENTRO DE COSTO
			END

			-----------------------** CONTABILIZACION NORMAL
			IF @TIPOCONTABILIZACION = '3'
			BEGIN
				-----------------------** CONTABILIZACION POR AREA FUNCIONA Y CENTRO DE COSTO --CREDITOS
				INSERT INTO MCHE (
					NROCOMPROBANTE, COMPANIA, TIPO, CUENTA, IDTERCERO, CCOSTO, DETALLE, VALOR, REFERENCIA1, REFERENCIA2, ITEMREF, USUARIO, FECHA, PREFIJO, IDAREA, 
					CLASECONT, ESTADO, PROCESO, GENERA, N_FACTURA, F_FACTURAREF, F_VENCE, CLASE_GENERA, PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG, IDSEDE
					)
				SELECT @NROCOMPROBANTE, @COMPANIA, CASE 
						WHEN NCON.TIPO = 'Ingreso'
							THEN 'DB'
						ELSE 'CR'
						END, DBO.FNK_NC_CUENTA_KMCOM(@IDMODELOCONT, 'NOMINA', CASE 
							WHEN NCON.TIPO = 'Ingreso'
								THEN 'DB'
							ELSE 'CR'
							END, NCON.CODCONCEPTO, CASE NDISP.CCOSTO
							WHEN NULL
								THEN #T.CCOSTO
							ELSE NDISP.CCOSTO
							END, 'S', #T.CODNOMINA, 0), CASE 
						WHEN COALESCE(#TH.RECOBRO, 0) = 1 AND NCON.TIPO = 'Ingreso'
							THEN #TH.IDTERCERO_RECO
						ELSE #TH.IDTERCERO_PRF
						END, NDISP.CCOSTO, UPPER(NCON.DESCRIPCION), #TH.VALOR * (
						CASE NDISP.PORCENTAJE
							WHEN NULL
								THEN 1
							ELSE NDISP.PORCENTAJE / 100
							END
						), @CNSPAGO, @TERCEROID, NULL, @USUARIO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), #TH.CODCONCEPTO, NDISP.IDAREA, 'S', 1, 'NOMINA_NCON', 
					'Movimiento', @CNSPAGO, DBO.FNK_FECHA_SIN_HORA(@FECHATRA), DBO.FNK_FECHA_SIN_HORA(@FECHATRA), 'NOMINA', 'NOMINA', @TERCEROID, #T.CODUNG, 
					NEMP.CODPRG, #T.IDSEDE
				FROM #T
				INNER JOIN #TH ON #T.CNSNIEPE = #TH.CNSNIEPE AND #T.NUMDOC = #TH.NUMDOC
				INNER JOIN NCON ON #TH.CODCONCEPTO = NCON.CODCONCEPTO
				INNER JOIN NEMP ON #TH.NUMDOC = NEMP.NUMDOC
				INNER JOIN NPLA ON #T.NUMDOC = NPLA.NUMDOC
				LEFT JOIN NDISP ON NPLA.CODPLANTA = NDISP.CODPLANTA AND #T.CNSPAGO = @CNSPAGO AND #T.NUMDOC = @NUMDOC
				INNER JOIN (
					SELECT ROW_NUMBER() OVER (
							PARTITION BY CODCONCEPTO ORDER BY FECHAINI DESC
							) [RITEM], CODCONCEPTO, ITEM
					FROM NCOND
					WHERE @FECHACONTABLE >= FECHAINI
					) X ON X.CODCONCEPTO = NCON.CODCONCEPTO AND X.RITEM = 1
				INNER JOIN NCOND ON X.CODCONCEPTO = NCOND.CODCONCEPTO AND X.ITEM = NCOND.ITEM
				WHERE #TH.VALOR <> 0 AND #TH.INFO = 'No'
				ORDER BY NCON.NATURALEZA DESC
					-----------------------** CONTABILIZACION POR CENTRO DE COSTO
			END

			-- PRINT 'Insertando Asiento DB Para Conceptos de la Empresa'    
			IF @TIPOCONTABILIZACION = '1'
			BEGIN
				--CONTABILIZACION NORMAL
				INSERT INTO MCHE (
					NROCOMPROBANTE, COMPANIA, TIPO, CUENTA, IDTERCERO, CCOSTO, DETALLE, VALOR, REFERENCIA1, REFERENCIA2, ITEMREF, USUARIO, FECHA, PREFIJO, IDAREA, 
					CLASECONT, ESTADO, PROCESO, GENERA, N_FACTURA, F_FACTURAREF, F_VENCE, CLASE_GENERA, PROCEDENCIA, REFERENCIA_PRO, CODUNG, CODPRG, IDSEDE
					)
				SELECT @NROCOMPROBANTE, @COMPANIA, 'DB', DBO.FNK_NC_CUENTA_KMCOM(@IDMODELOCONT, 'NOMINA', 'DB', NCON.CODCONCEPTO, #T.CCOSTO, 'S', #T.CODNOMINA, 0
					), CASE COALESCE(#TH.RECOBRO, 0)
						WHEN 1
							THEN #TH.IDTERCERO_RECO
						ELSE #TH.IDTERCERO_PRF
						END, #T.CCOSTO, UPPER(NCON.DESCRIPCION), #TH.VALOR_APORTES, @CNSPAGO, @TERCEROID, NULL, @USUARIO, DBO.FNK_FECHA_SIN_MLS(GETDATE()), #TH
					.CODCONCEPTO, #T.IDAREA, 'S', 1, 'NOMINA_NCON', 'Movimiento', @CNSPAGO, DBO.FNK_FECHA_SIN_HORA(@FECHATRA), DBO.FNK_FECHA_SIN_HORA(
						@FECHATRA), 'NOMINA', 'NOMINA', @TERCEROID, #T.CODUNG, NEMP.CODPRG, #T.IDSEDE
				FROM #T
				INNER JOIN #TH ON #T.CNSNIEPE = #TH.CNSNIEPE AND #T.NUMDOC = #TH.NUMDOC
				INNER JOIN NCON ON #TH.CODCONCEPTO = NCON.CODCONCEPTO
				INNER JOIN NEMP ON #TH.NUMDOC = NEMP.NUMDOC
				INNER JOIN (
					SELECT ROW_NUMBER() OVER (
							PARTITION BY CODCONCEPTO ORDER BY FECHAINI DESC
							) [RITEM], CODCONCEPTO, ITEM
					FROM NCOND
					WHERE @FECHACONTABLE >= FECHAINI
					) X ON X.CODCONCEPTO = NCON.CODCONCEPTO AND X.RITEM = 1
				INNER JOIN NCOND ON X.CODCONCEPTO = NCOND.CODCONCEPTO AND X.ITEM = NCOND.ITEM
				WHERE #TH.VALOR_APORTES <> 0 AND #TH.INFO = 'No'
				ORDER BY NCON.NATURALEZA DESC
			END

			--FIN CONTABILIZACION NORMAL
			IF @TIPOCONTABILIZACION = '2'
			BEGIN
				--CONTABILIZACION POR AREA FUNCIONA Y CENTRO DE COSTO
				PRINT 'DISTRIBUCION 2'

				INSERT INTO MCHE (
