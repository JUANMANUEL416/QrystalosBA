					SELECT
						@IDTERCERO = FCXP.IDTERCERO,
						@MANEXO = COALESCE(TER.MANEXO, 0),
						@IDSEDE = FCXP.IDSEDE
					FROM FCXP
					INNER JOIN TER ON TER.IDTERCERO = FCXP.IDTERCERO
					WHERE FCXP.CNSFCXP = @CNSFCXP_IMP

					IF COALESCE(@MANEXO, 0) <> 1
						SET @ERR_GEN_ANEXO = 'El tercero asociado al registro, no corresponde, para un DOCUMENTO SOPORTE'
					ELSE
					BEGIN
						-- Sede y consecutivo: misma l?gica que GEN_NUM_DIAN (FDIAN PROCEDENCIA = CXP)
						IF DBO.FNK_VALORVARIABLE('FACTSEDE') = 'NO'
						BEGIN
							SELECT @SEDEPPAL = LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('IDSEDEPRINCIPAL')))
							IF NOT EXISTS (SELECT 1 FROM SED WHERE IDSEDE = @SEDEPPAL)
							BEGIN
								SELECT @SEDEPPAL = IDENTIFICADOR FROM FDIAN WHERE VENCIDA = 0 AND PROCEDENCIA = 'CXP'
								IF NOT EXISTS (SELECT 1 FROM SED WHERE IDSEDE = @SEDEPPAL)
									SELECT TOP 1 @SEDEPPAL = IDSEDE FROM FTR WHERE COALESCE(IDSEDE, '') <> '' ORDER BY F_FACTURA DESC
							END
							SET @IDSEDE = @SEDEPPAL
						END
						ELSE
						BEGIN
							SELECT @SEDEPPAL = COALESCE(IDSEDE, '') FROM FCXP WHERE CNSFCXP = @CNSFCXP_IMP
							IF COALESCE(@SEDEPPAL, '') = '' SET @SEDEPPAL = @IDSEDE
							SET @IDSEDE = @SEDEPPAL
						END

						SELECT TOP 1
							@PREFIJOFAC = COALESCE(FDIAN.PREFIJO, ''),
							@CNSNUEVO = COALESCE(FDIAN.CNSACTUAL, 0) + 1,
							@CNSINICIAL = FDIAN.CNSINICIAL,
							@CNSFINAL = FDIAN.CNSFINAL,
							@CNSRESOL = FDIAN.CNSRESOL
						FROM FDIAN
						WHERE FDIAN.IDENTIFICADOR = @IDSEDE
						  AND COALESCE(FDIAN.VENCIDA, 0) = 0
						  AND FDIAN.PROCEDENCIA = 'CXP'
						  AND FDIAN.CNSINICIAL <= (COALESCE(FDIAN.CNSACTUAL, 0) + 1)
						  AND (FDIAN.CNSFINAL + 1) > (COALESCE(FDIAN.CNSACTUAL, 0) + 1)
						ORDER BY FDIAN.CNSINICIAL DESC

						IF COALESCE(@CNSRESOL, '') = ''
							SET @ERR_GEN_ANEXO = 'NO existe resolucion activa para este nro de factura, No se puede Continuar'
						ELSE IF @CNSNUEVO > @CNSFINAL OR @CNSNUEVO < @CNSINICIAL
							SET @ERR_GEN_ANEXO = 'Se ha terminado los consecutivos de facturacion Habilitados, No se puede Continuar'
					END

					IF @ERR_GEN_ANEXO IS NULL
					BEGIN
						UPDATE FCXP
						SET CNSRESOL = @CNSRESOL,
							N_FACTURA = CONCAT(@PREFIJOFAC, @CNSNUEVO),
							NOREFERENCIA = CONCAT(@PREFIJOFAC, @CNSNUEVO),
							DOCEQUIVALENTE = 1, CXP_NOMINA = 1
						WHERE CNSFCXP = @CNSFCXP_IMP

						UPDATE FDIAN
						SET CNSACTUAL = @CNSNUEVO
						WHERE CNSRESOL = @CNSRESOL
						  AND PREFIJO = @PREFIJOFAC
						  AND IDENTIFICADOR = @IDSEDE
						  AND PROCEDENCIA = 'CXP'

						SET @GEN_ANEXO_OK = 1
					END
				END
				ELSE
					SET @GEN_ANEXO_OK = 1

				IF @GEN_ANEXO_OK = 1
				BEGIN
					SET @EXITOSOS_IMP = @EXITOSOS_IMP + 1
					SET @MSG_IMP = CASE
						WHEN @REQ_GEN_ANEXO = 1 THEN 'Documento soporte marcado y anexo generado correctamente.'
						ELSE 'Documento soporte marcado correctamente (anexo ya exist?a).'
					END
					INSERT INTO @RESULTADO_SOPORTE (CNSFCXP, NIT, ESTADO, MENSAJE, MANEXO_ACTUALIZADO, DOCEQUIVALENTE_ACTUALIZADO)
					VALUES (@CNSFCXP_IMP, @NIT_IMP, 'OK', @MSG_IMP, @MANEXO_UPD, @DOCEQ_UPD)
				END
				ELSE
				BEGIN
					SET @FALLIDOS_IMP = @FALLIDOS_IMP + 1
					INSERT INTO @RESULTADO_SOPORTE (CNSFCXP, NIT, ESTADO, MENSAJE, MANEXO_ACTUALIZADO, DOCEQUIVALENTE_ACTUALIZADO)
					VALUES (
						@CNSFCXP_IMP, @NIT_IMP, 'ERROR',
						CONCAT('Marcado DOCEQUIVALENTE OK, pero fall? la generaci?n del anexo: ', COALESCE(@ERR_GEN_ANEXO, 'Error desconocido.')),
						@MANEXO_UPD, @DOCEQ_UPD
					)
				END
			END TRY
			BEGIN CATCH
				SET @FALLIDOS_IMP = @FALLIDOS_IMP + 1
				INSERT INTO @RESULTADO_SOPORTE (CNSFCXP, NIT, ESTADO, MENSAJE, MANEXO_ACTUALIZADO, DOCEQUIVALENTE_ACTUALIZADO)
				VALUES (@CNSFCXP_IMP, @NIT_IMP, 'ERROR', ERROR_MESSAGE(), 0, 0)
			END CATCH

			SET @ITEM_IMP = @ITEM_IMP + 1
		END

		SELECT
			CASE WHEN @EXITOSOS_IMP > 0 THEN 'OK' ELSE 'KO' END AS OK,
			@TOTAL_IMP AS TOTAL,
			@EXITOSOS_IMP AS EXITOSOS,
			@FALLIDOS_IMP AS FALLIDOS,
			CASE
				WHEN @EXITOSOS_IMP = 0 THEN 'No se actualiz? ning?n registro.'
				WHEN @FALLIDOS_IMP > 0 THEN CONCAT('Proceso finalizado con ', @EXITOSOS_IMP, ' exitoso(s) y ', @FALLIDOS_IMP, ' error(es).')
				ELSE CONCAT('Proceso finalizado. ', @EXITOSOS_IMP, ' registro(s) actualizado(s).')
			END AS MENSAJE

		SELECT
			CNSFCXP,
			NIT,
			MENSAJE,
			MANEXO_ACTUALIZADO,
			DOCEQUIVALENTE_ACTUALIZADO
		FROM @RESULTADO_SOPORTE
		WHERE ESTADO = 'OK'
		ORDER BY ITEM ASC

		IF @FALLIDOS_IMP > 0
		BEGIN
			SELECT
				CNSFCXP,
				NIT,
				MENSAJE AS ERROR
			FROM @RESULTADO_SOPORTE
			WHERE ESTADO = 'ERROR'
			ORDER BY ITEM ASC
		END

		RETURN
	END
END

