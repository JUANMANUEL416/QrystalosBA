				   OR COALESCE(NULLIF(LTRIM(RTRIM(D.IDSERVICIO)), ''), NULLIF(LTRIM(RTRIM(D.DESCRIPCION)), '')) IS NOT NULL

				IF @@ROWCOUNT > 0
					EXEC SPK_CALCULOVALORESCXP @CNSFCXP
			END

			SELECT 'OK' AS OK, @CNSFCXP AS CNSFCXP
