	IF @METODO = 'IMPORTAR_SOPORTE_NOMINA'
	BEGIN
		DECLARE @RESULTADO_SOPORTE TABLE (
			ITEM INT IDENTITY(1,1),
			CNSFCXP VARCHAR(20),
