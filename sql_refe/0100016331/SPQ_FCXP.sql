		END

		SELECT
			ROW_NUMBER() OVER (ORDER BY LTRIM(RTRIM(JSON_VALUE(J.value, '$.CNSFCXP'))) ASC) AS ITEM,
			LTRIM(RTRIM(JSON_VALUE(J.value, '$.CNSFCXP'))) AS CNSFCXP,
			LTRIM(RTRIM(JSON_VALUE(J.value, '$.NIT'))) AS NIT,
			LTRIM(RTRIM(JSON_VALUE(J.value, '$.IDTERCERO'))) AS IDTERCERO
		INTO #IMPORT_SOPORTE
		FROM OPENJSON(@DATA_SOPORTE) AS J
		WHERE COALESCE(LTRIM(RTRIM(JSON_VALUE(J.value, '$.CNSFCXP'))), '') <> ''
		  AND (
				COALESCE(TRY_CAST(JSON_VALUE(J.value, '$.DOC_SOPORTE') AS INT), 0) = 1
				OR UPPER(LTRIM(RTRIM(COALESCE(JSON_VALUE(J.value, '$.DOC_SOPORTE'), '')))) IN ('1', 'SI', 'S', 'TRUE')
