CREATE OR ALTER PROCEDURE DBO.SPQ_FCXP
	@JSON NVARCHAR(MAX)
WITH ENCRYPTION
AS 

DECLARE @PARAMETROS       NVARCHAR(MAX) 
	    ,@MODELO VARCHAR(100)		        ,@METODO  VARCHAR(100)          ,@SEDE VARCHAR(5)		    ,@USUARIO VARCHAR(20)
		,@DocAdq VARCHAR(20)                ,@Cuds varchar(256)             ,@CNSFCXP VARCHAR(100)		,@dataFCXP NVARCHAR(MAX)
		,@datoFCXPI NVARCHAR(MAX)	        ,@CNSMOV VARCHAR(20)            ,@SYS_COMPUTERNAME VARCHAR(200)		
		,@PROCESO VARCHAR(20)			    ,@CNSFCXPI VARCHAR(20)		    ,@datoFCXPDBCR NVARCHAR(MAX)
		,@CIUDAD VARCHAR(20)	  	        ,@IDSEDE VARCHAR(20)			,@CUENTADB VARCHAR(20)		,@CUENTACR VARCHAR(20)
		,@CNSINICIAL  INT                   ,@VENCIDA SMALLINT              ,@ITEM	INT				    ,@TIPO VARCHAR(20)			
		,@datoFCXPA NVARCHAR(MAX)	        ,@datoFCXPAD NVARCHAR(MAX)      ,@CNSACTUAL   INT           ,@LONGFTRARS  INT          
		,@CONTABILIZADA	INT				    ,@NROCOMPROBANTE VARCHAR(20)	,@CNSFCOM VARCHAR(20)		,@DATO VARCHAR(20)	        
		,@IDNOTA VARCHAR(20)                ,@CNSFINAL    INT               ,@dataFCXPD	NVARCHAR(MAX)	,@NOITEM INT				
		,@OBSERVACION VARCHAR(MAX)	        ,@PROCEDE INT		            ,@PROC VARCHAR(5)           ,@PREFIJOFAC  VARCHAR(10)   
		,@COMPANIA	VARCHAR(5)		        ,@TIPOCALCULO VARCHAR(10)		,@IDIMPUESTO VARCHAR(20)	,@IDCLASE VARCHAR(20)	    
		,@WHERE_DATA VARCHAR(500)           ,@CNSNUEVO    INT               ,@FECHA_CAL	VARCHAR(8)		,@CALCULAR1 DECIMAL(14,2)	
		,@CALCULAR2 DECIMAL(14,2)	        ,@VALOR DECIMAL(14,2)	        ,@sqlCommand Nvarchar(max)  ,@CNSRESOL    VARCHAR(20)   
		,@IMPUESTO		DECIMAL(14,2)		,@VLR_IMPUESTOS DECIMAL(14,2)	,@SELECCIONADOS VARCHAR(1000)	,@CONT INT					,@I INT		                
		,@datoFCXPAG NVARCHAR(MAX)	        ,@SEDEPPAL    VARCHAR(6)        ,@IDCATEGORIA VARCHAR(10)   ,@FECHA DATE					
		,@IDTERCERO VARCHAR(20)		        ,@DIAS INT		                ,@COUNT_SEL INT	            ,@PRE VARCHAR(20)                   
		,@DOC_DISTRIBUYE VARCHAR(20)		,@MANEXO BIT	                ,@PROCEDENCIA VARCHAR(20)	,@CONSECUTIVO NVARCHAR(MAX)		
		,@ITEM_DBCR INT	                    ,@IMPUESTOS NVARCHAR(MAX)       ,@DETALLE_VALORES NVARCHAR(MAX)                       
		,@VLR_LEGALIZADO DECIMAL(14,2)      ,@VLR_ANTICIPOS DECIMAL(14,2)   ,@CNSANT VARCHAR(20)        ,@CRUCETER BIT 
		,@DATOS VARCHAR(MAX)

DECLARE @IDMODELOCONT VARCHAR(20)          ,@IDTIPOCONT VARCHAR(20)         ,@IDAREA VARCHAR(20)        ,@PREFIJO VARCHAR(20)
       ,@CCOSTO VARCHAR(20)                ,@CLASECONT VARCHAR(20)          ,@IDSERVICIO VARCHAR(20)    ,@TITULO  NVARCHAR(MAX)
	   ,@ESTADODIAN SMALLINT

DECLARE @VLR_NETO DECIMAL(14,2)            ,@VLR_GLOSAS DECIMAL(14,2)             ,@SALDO DECIMAL(14,2)                 ,@VLR_ABONOS DECIMAL(14,2)
       ,@VLR_NOTADB DECIMAL(14,2)          ,@VLR_NOTACR DECIMAL(14,2)             ,@TIENE_DIST_DET BIT = 0              ,@PERMITE_EDITAR_DIST BIT = 0
       ,@TIENE_DIST BIT = 0                ,@PERMITE_EDITAR_DIST_FCXP BIT = 0     ,@VALOR_DET_ANT DECIMAL(14,2)
       ,@VLR_NETO_DET_ANT DECIMAL(14,2)    ,@CANTIDAD_DET_ANT DECIMAL(14,2)       ,@IDSERVICIO_DET_ANT VARCHAR(20)      ,@CCOSTO_DET_ANT VARCHAR(20)
       ,@VLR_IVA_DET_ANT DECIMAL(14,2)     ,@VLR_DESCUENTO_DET_ANT DECIMAL(14,2)  ,@VALOR_ANT DECIMAL(14,2)
       ,@VLR_NETO_ANT DECIMAL(14,2)        ,@VLR_IVA_ANT DECIMAL(14,2)            ,@IDTERCERO_ANT VARCHAR(20)           ,@NOREFERENCIA_ANT VARCHAR(20)
       ,@OBSERVACION_ANT VARCHAR(MAX)      ,@VLR_DESCUENTO_ANT DECIMAL(14,2)      ,@VALOR_NUEVO DECIMAL(14,2)           ,@VLR_NETO_NUEVO DECIMAL(14,2)
       ,@CANTIDAD_NUEVO DECIMAL(14,2)      ,@IDSERVICIO_NUEVO VARCHAR(20)         ,@CCOSTO_NUEVO VARCHAR(20)            ,@VLR_IVA_NUEVO DECIMAL(14,2)
       ,@VLR_DESCUENTO_NUEVO DECIMAL(14,2) ,@PROCEDENCIA_DET_ANT VARCHAR(20)      ,@REDONDEO_DET_ANT VARCHAR(20)        ,@MIMPCONSUMO_DET_ANT BIT
       ,@IDTERCERO_DET_ANT VARCHAR(20)     ,@UNSPSC_DET_ANT VARCHAR(20)           ,@VLR_DOLARES_DET_ANT DECIMAL(14,2)   ,@CUENTA_IVA_DET_ANT VARCHAR(20)
       ,@VLRIMPCONSUMO_DET_ANT DECIMAL(14,2),@CTAIMPCONSUMO_DET_ANT VARCHAR(20)  ,@VLR_GLOSAS_DET_ANT DECIMAL(14,2)    ,@IDSEDE_DET_ANT VARCHAR(20)
       ,@IDAREA_DET_ANT VARCHAR(20)        ,@RUBRO_DET_ANT VARCHAR(50)            ,@PREFIJO_DET_ANT VARCHAR(20)         ,@CUENTA_SER_DET_ANT VARCHAR(20)
       ,@PROCEDENCIA_NUEVO VARCHAR(20)     ,@REDONDEO_NUEVO VARCHAR(20)           ,@MIMPCONSUMO_NUEVO BIT               ,@IDTERCERO_NUEVO VARCHAR(20)
       ,@UNSPSC_NUEVO VARCHAR(20)          ,@VLR_DOLARES_NUEVO DECIMAL(14,2)      ,@CUENTA_IVA_NUEVO VARCHAR(20)        ,@VLRIMPCONSUMO_NUEVO DECIMAL(14,2)
       ,@CTAIMPCONSUMO_NUEVO VARCHAR(20)   ,@VLR_GLOSAS_NUEVO DECIMAL(14,2)       ,@IDSEDE_NUEVO VARCHAR(20)            ,@IDAREA_NUEVO VARCHAR(20)
       ,@RUBRO_NUEVO VARCHAR(50)           ,@PREFIJO_NUEVO VARCHAR(20)            ,@CUENTA_SER_NUEVO VARCHAR(20)        ,@TIPODISTRIBUCION VARCHAR(20)
       ,@CNSFACJ VARCHAR(100)              ,@CODCAJA VARCHAR(50), @CNSFCXP_CLONADO VARCHAR(20) = NULL

DECLARE @IDTERCERO_SRC VARCHAR(20) = NULL  ,@VALOR_SRC DECIMAL(14,2) = NULL      ,@PROCEDENCIA_SRC VARCHAR(20) = NULL  ,@IDSEDE_SRC VARCHAR(20) = NULL

DECLARE @COD_PROC_SRC CHAR(2) = NULL        ,@CNSRADIAN_GEN VARCHAR(20)          ,@dataFCXP_RAD NVARCHAR(MAX)          ,@detalleFCXPD_RAD NVARCHAR(MAX)
       ,@PROC_RAD VARCHAR(20) = 'Servicios' ,@TIPO_CXP_RAD VARCHAR(20) = 'IPS'   ,@CUENTA_TER VARCHAR(20)              ,@NOREF_RAD VARCHAR(20)
       ,@VALOR_RAD DECIMAL(14,2)            ,@VLR_IVA_RAD DECIMAL(14,2)          ,@VLR_NETO_RAD DECIMAL(14,2)          ,@OBS_RAD VARCHAR(MAX)
       ,@FECHA_FAC_INS DATETIME             ,@FECHA_CXP_INS DATETIME             ,@FECHA_VENCE_RAD DATETIME            ,@FILAS_CONCILIADAS INT = 0;

DECLARE @DATA_SOPORTE NVARCHAR(MAX)         ,@CNSFCXP_IMP VARCHAR(20)            ,@NIT_IMP VARCHAR(20)                 ,@IDTERCERO_IMP VARCHAR(20)
       ,@FECHA_CXP_IMP DATE                 ,@FECHA_FAC_IMP DATE                  ,@EXITOSOS_IMP INT                    ,@FALLIDOS_IMP INT
       ,@TOTAL_IMP INT                      ,@MSG_IMP VARCHAR(500)                ,@MANEXO_UPD BIT                      ,@DOCEQ_UPD BIT
       ,@ITEM_IMP INT                       ,@LIMITE_IMP INT                      ,@REQ_GEN_ANEXO BIT                   ,@GEN_ANEXO_OK BIT
       ,@ERR_GEN_ANEXO VARCHAR(500)         ,@DOCEQUIVALENTE_CXP BIT;

DECLARE @FECHA_HOY DATE = CONVERT(DATE, DBO.FNK_GETDATE())
DECLARE @FECHA_MANANA DATE = DATEADD(DAY, 1, @FECHA_HOY)	
DECLARE @FECHA_DIA_INI DATETIME = CONVERT(DATE, GETDATE())
DECLARE @FECHA_DIA_FIN DATETIME = DATEADD(DAY, 1, CONVERT(DATE, GETDATE()))
DECLARE @FECHA_INICIO_BUSQ DATETIME = DATEADD(MINUTE, -2, GETDATE())
DECLARE @FECHA_FIN_BUSQ DATETIME = DATEADD(MINUTE,  2, GETDATE())

DECLARE @TBLERRORES TABLE(ERROR VARCHAR(500));
DECLARE @LOG_ERR TABLE (ERROR VARCHAR(500));

BEGIN
	SET DATEFORMAT dmy
	SET NOCOUNT ON

	SELECT *
	INTO #JSON
	FROM OPENJSON(@json) WITH (
		METODO  VARCHAR(100) '$.METODO'
		,USUARIO VARCHAR(100) '$.USUARIO'
		,PARAMETROS NVARCHAR(MAX) AS JSON
	)

	SELECT @METODO     = METODO
		,@PARAMETROS = PARAMETROS
		,@USUARIO    = USUARIO
	FROM #JSON

	--SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO) FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SEDE = IDSEDE, @IDSEDE = IDSEDE, @COMPANIA = COMPANIA FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	IF @METODO IN (
		'CONSULTAR_RESPUESTA_DIAN_NOTA',
		'CRUD_FCXPDBCR',
		'CRUD_FCXPDBCR_2',
		'CRUD_FCXPDBCR_2_MANUAL',
		'CONTABILIZAR_NOTACREDITO',
		'ENVIARDIAN_NOTACREDITO',
		'AFECTA_RETENCION',
		'VALIDA_IDNOTA',
		'CRUD_NOTA_EDITA',
		'ELIMINR_NOTACREDITO',
		'DESAPLICAR_NOTACREDITO'
	)
	BEGIN
		EXEC DBO.SPQ_FCXPDBCR @JSON = @JSON
		RETURN
	END

	
	IF @METODO = 'CONSULTAR'
	BEGIN
		SELECT @CNSFCXP = JSON_VALUE(@PARAMETROS, '$.CNSFCXP')

		SELECT 'OK' AS OK, @CNSFCXP AS CNSFCXP

		SELECT 
			FCXP.*
			,TER.RAZONSOCIAL
			,TER.NIT
			,TER.DV
			,TER.TIPO_ID
			,TGEN.DESCRIPCION AS TIPO_ID_DESC
			,COALESCE(FCXP.DISTRIBUYE, 0) AS DISTRIBUYE
			,FCXP.DOC_DISTRIBUYE
			,COALESCE(FCXP.MODIFICADO_POST_DISTRIBUCION, 0) AS MODIFICADO_POST_DISTRIBUCION
			,FCXP.FECHA_MODIFICACION_POST_DIST
			,FCXP.USUARIO_MODIFICACION_POST_DIST
			,FDIS.DESCRIPCION AS FDIS_DESC
			,FDIS.CODDISTRIBUCION AS CODDISTRIBUCION
			,FCXPD = (
				SELECT
					FCXPD.*
					, COALESCE(
						NULLIF(LTRIM(RTRIM(
							CASE FCXPD.PROCEDENCIA
								WHEN 'Servicios' THEN CASE WHEN EXISTS (SELECT 1 FROM FCTSER WHERE FCTSER.IDTIPOSER = FCXPD.IDSERVICIO) THEN (SELECT TOP 1 FCTSER.DESCRIPCION FROM FCTSER WHERE FCTSER.IDTIPOSER = FCXPD.IDSERVICIO ORDER BY FCTSER.IDTIPOSER) ELSE (SELECT TOP 1 FCTSERD.DESCRIPCION FROM FCTSERD WHERE FCTSERD.IDSERVICIO = FCXPD.IDSERVICIO ORDER BY FCTSERD.IDSERVICIO) END
								WHEN 'Salud' THEN CASE WHEN EXISTS (SELECT 1 FROM FCTSER WHERE FCTSER.IDTIPOSER = FCXPD.IDSERVICIO) THEN (SELECT TOP 1 FCTSER.DESCRIPCION FROM FCTSER WHERE FCTSER.IDTIPOSER = FCXPD.IDSERVICIO ORDER BY FCTSER.IDTIPOSER) ELSE (SELECT TOP 1 FCTSERD.DESCRIPCION FROM FCTSERD WHERE FCTSERD.IDSERVICIO = FCXPD.IDSERVICIO ORDER BY FCTSERD.IDSERVICIO) END
								WHEN 'Compras' THEN (SELECT TOP 1 IART.DESCRIPCION FROM IART WHERE IART.IDARTICULO = FCXPD.IDSERVICIO ORDER BY IART.IDARTICULO)
								WHEN 'CAJA' THEN (SELECT TOP 1 CPCJ.DESCRIPCION FROM CPCJ WHERE CPCJ.CODIGO = FCXPD.IDSERVICIO ORDER BY CPCJ.CODIGO)
								WHEN 'CAJAMENOR' THEN (SELECT TOP 1 CPCJ.DESCRIPCION FROM CPCJ WHERE CPCJ.CODIGO = FCXPD.IDSERVICIO ORDER BY CPCJ.CODIGO)
								WHEN 'Nomina' THEN (SELECT TOP 1 NCON.DESCRIPCION FROM NCON WHERE NCON.CODCONCEPTO = FCXPD.IDSERVICIO ORDER BY NCON.CODCONCEPTO)
								ELSE (SELECT TOP 1 SER.DESCSERVICIO FROM SER WHERE SER.IDSERVICIO = FCXPD.IDSERVICIO ORDER BY SER.IDSERVICIO)
							END
						)), ''),
						NULLIF(LTRIM(RTRIM(FCXPD.DESC_EXT)), '')
					) AS DESCRIPCION_SERVICIO
					, COALESCE(
						NULLIF(LTRIM(RTRIM(FCXPD.IDSERVICIO)), ''),
						NULLIF(LTRIM(RTRIM(FCXPD.COD_EXT)), '')
					) AS IDSERVICIO_REF
				FROM FCXPD
				WHERE CNSFCXP = FCXP.CNSFCXP
				FOR JSON PATH
			)
		FROM FCXP 
		INNER JOIN TER ON TER.IDTERCERO=FCXP.IDTERCERO
		LEFT JOIN TGEN ON TGEN.TABLA='General' AND TGEN.CAMPO='TIPOIDENT' AND TGEN.CODIGO=TER.TIPO_ID
		LEFT JOIN FDIS ON FCXP.DOC_DISTRIBUYE = FDIS.CODDISTRIBUCION
		WHERE CNSFCXP=@CNSFCXP

	END

	IF @METODO = 'CONSULTAR_RESPUESTA_DIAN'
	BEGIN
		SELECT @CNSFCXP = JSON_VALUE(@PARAMETROS, '$.CNSFCXP')
		SELECT 'OK' AS OK, @CNSFCXP AS CNSFCXP

		SELECT * FROM FDIANR RD INNER JOIN FCXP CXP ON CXP.CNSFCXP = RD.CNSDOCUMENTO 
		WHERE CNSDOCUMENTO = @CNSFCXP AND XML_RESPUESTA IS NOT NULL AND XML_SOLICITUD IS NOT NULL AND CXP.ESTADODIAN <> 0;
	END


	IF @METODO = 'SEL_TODOS_HPRED'
	BEGIN
		SELECT @CNSFCXP =  CNSFCXP
	   FROM OPENJSON (@PARAMETROS)
	   WITH		 (
		CNSFCXP		VARCHAR(20) '$.CNSFCXP'
		)

		IF 1 = 2
         BEGIN
            INSERT INTO @TBLERRORES(ERROR) SELECT 'XXXXXXXX'
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
         END
			
		BEGIN TRY 
			SELECT 'OK'OK
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF EXISTS(SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' AS OK
		RETURN
	END

	IF @METODO = 'CRUD_FCXP'
	BEGIN
		SELECT @dataFCXP =  dataFCXP
	   FROM OPENJSON (@PARAMETROS)
	   WITH		 (
		dataFCXP		NVARCHAR(MAX) AS JSON
		)
      DECLARE @FECHACXP DATETIME
      DECLARE @FECHAFAC DATETIME
		SELECT @PROCESO =UPPER( JSON_VALUE(@dataFCXP,'$.PROCESO'))
		SELECT @IDSEDE = JSON_VALUE(@dataFCXP,'$.IDSEDE')
		IF EXISTS (SELECT   * FROM FCXP WHERE  CNSFCXP = JSON_VALUE(@dataFCXP,'$.CNSFCXP') AND COALESCE(CONTABILIZADA,0)=1)
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El registro ya se encuentra contabilizado'
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		
		
		SELECT * INTO #DATAFCXP FROM OPENJSON(@dataFCXP)
		WITH(
		CNSFCXP				VARCHAR(20)		'$.CNSFCXP'				,TIPOCXP			VARCHAR(20)		'$.TIPOCXP'
		,IDSEDE				VARCHAR(20)		'$.IDSEDE'				,CIUDAD				VARCHAR(20)		'$.CIUDAD'
		,PROCEDENCIA		VARCHAR(20)		'$.PROCEDENCIA'			,IDTERCERO			VARCHAR(20)		'$.IDTERCERO'
		,CUECREDITO			VARCHAR(20)		'$.CUECREDITO'			,NOREFERENCIA		VARCHAR(20)		'$.NOREFERENCIA'
		,OBSERVACION		VARCHAR(MAX)	'$.OBSERVACION'			,FACCONTROL			VARCHAR(20)		'$.FACCONTROL'
		,VALOR				DECIMAL(14,2)	'$.VALOR'				,VLR_DESCUENTO		DECIMAL(14,2)	'$.VLR_DESCUENTO'
		,VLR_IVA			DECIMAL(14,2)	'$.VLR_IVA'				,VLR_NETO			DECIMAL(14,2)	'$.VLR_NETO'
		,VLR_IMPUESTOS		DECIMAL(14,2)	'$.VLR_IMPUESTOS'		,VLR_GLOSAS			DECIMAL(14,2)	'$.VLR_GLOSAS'
		,VLR_ABONOS			DECIMAL(14,2)	'$.VLR_ABONOS'			,VLR_NOTASDEBITO	DECIMAL(14,2)	'$.VLR_NOTASDEBITO'
		,VLR_NOTASCREDITO	DECIMAL(14,2)	'$.VLR_NOTASCREDITO'	,VLR_FLETE			DECIMAL(14,2)	'$.VLR_FLETE'
		,SALDO				DECIMAL(14,2)	'$.SALDO'				,SEAMORTIZA			BIT				'$.SEAMORTIZA'
		,NUMPERAMORT		INT				'$.NUMPERAMORT'			,TCAMBIO			DECIMAL(14,2)	'$.TCAMBIO'
		,CNSFCOM			VARCHAR(20)		'$.CNSFCOM'				,VARIOSTER			BIT				'$.VARIOSTER'
		,CNSRP				VARCHAR(20)		'$.CNSRP'				,CNSPPTO			VARCHAR(20)		'$.CNSPPTO'
		,CNSCDP				VARCHAR(20)		'$.CNSCDP'	            ,FECHA_GENERACION_PLANO	DATE		'$.FECHA_GENERACION_PLANO')	
      SELECT @FECHACXP=COALESCE( REPLACE(JSON_VALUE(@dataFCXP ,'$.FECHA'),'-','') , DBO.FNK_GETDATE())
      SELECT @FECHAFAC=COALESCE( REPLACE(JSON_VALUE(@dataFCXP ,'$.F_FACTURAREF'),'-','') , DBO.FNK_GETDATE())
		IF DBO.FNK_VALORVARIABLE('PRESUP_CXP_ACTIVADO') = 'SI'  
			AND EXISTS (SELECT * FROM PTRP, #DATAFCXP WHERE PTRP.IDTERCERO = #DATAFCXP.IDTERCERO AND PTRP.CONSECUTIVO = YEAR(GETDATE()) 
															AND PTRP.ESTADO = 'Confirmado' AND COALESCE(#DATAFCXP.CNSRP,'') = '' )
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'Debe de seleccionar un registro de Presupuesto'
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN 
		END
		IF (SELECT COUNT(*) FROM FCXP, #DATAFCXP WHERE FCXP.IDTERCERO= #DATAFCXP.IDTERCERO AND COALESCE(FCXP.NOREFERENCIA,'')<>'' AND FCXP.NOREFERENCIA = #DATAFCXP.NOREFERENCIA --DONATE  SE CAMBIA IDTERCERO POR NOREFERENCIA
			AND FCXP.ESTADO <> 'A' ) >0 AND UPPER(@PROCESO)='NUEVO'
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El No. de Referencia ya existe registrado en CxP de este proveedor.'
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN 
		END

		IF (SELECT COUNT(*) FROM FCXP, #DATAFCXP WHERE FCXP.IDTERCERO= #DATAFCXP.IDTERCERO AND COALESCE(FCXP.NOREFERENCIA,'')<>'' AND FCXP.NOREFERENCIA = #DATAFCXP.NOREFERENCIA -- DONATE
			AND FCXP.ESTADO <> 'A' AND FCXP.CNSFCXP <> #DATAFCXP.CNSFCXP ) >0 AND UPPER(@PROCESO)='EDITAR'
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'El No. de Referencia ya existe registrado en CxP de este proveedor.'
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN 
		END

      IF NOT EXISTS(
			SELECT 1 FROM PRI
			WHERE FECHA_INI <= @FECHAFAC AND FECHA_FIN >= @FECHAFAC
			  AND COALESCE(CERRADO, 0) = 0
			  AND COALESCE(CERRADO_CXP, 0) = 0
		)
      BEGIN
         INSERT INTO @TBLERRORES(ERROR)
         SELECT 'El periodo contable de la fecha del documento no existe, est? cerrado en contabilidad o el periodo de Cuentas por Pagar est? cerrado; no se puede continuar '
      END
	  IF NOT EXISTS(
			SELECT 1 FROM PRI
			WHERE FECHA_INI <= @FECHACXP AND FECHA_FIN >= @FECHACXP
			  AND COALESCE(CERRADO, 0) = 0
			  AND COALESCE(CERRADO_CXP, 0) = 0
		)
      BEGIN
         INSERT INTO @TBLERRORES(ERROR)
         SELECT 'El periodo contable de la fecha de la CXP no existe, est? cerrado en contabilidad o el periodo de Cuentas por Pagar est? cerrado; no se puede continuar '
      END
      IF(SELECT COUNT(*) FROM @TBLERRORES)>0
      BEGIN
         SELECT 'KO' OK, ERROR FROM @TBLERRORES
          RETURN
      END
		--IF EXISTS (SELECT  * FROM FCXPD,#DATAFCXP WHERE FCXPD.CNSFCXP = #DATAFCXP.CNSFCXP) AND UPPER(@PROCESO)='EDITAR'
		--BEGIN
		--	INSERT INTO @TBLERRORES(ERROR) SELECT 'El registro cuenta con detalle, no se puede realizar cambios.'
		--	SELECT 'KO' OK
		--	SELECT ERROR FROM @TBLERRORES
		--	RETURN 
		--END
		IF EXISTS (SELECT DBO.FNK_VALORVARIABLE('RESTRIN_CREA_CXP'))
		BEGIN
			IF (SELECT DBO.FNK_VALORVARIABLE('RESTRIN_CREA_CXP')) = 'TODO'
			BEGIN
				SELECT @COUNT_SEL = (SELECT COUNT(*) FROM FCXP,#DATAFCXP  WHERE FCXP.ESTADO='N' AND FCXP.PROCEDENCIA= #DATAFCXP.PROCEDENCIA  AND FCXP.CNSFCXP<>#DATAFCXP.CNSFCXP AND NOT EXISTS(SELECT * FROM FCXPD WHERE FCXP.CNSFCXP=FCXPD.CNSFCXP))
			END
			IF (SELECT DBO.FNK_VALORVARIABLE('RESTRIN_CREA_CXP')) = 'TERCERO'
			BEGIN
				SELECT @COUNT_SEL = (SELECT COUNT(*) FROM FCXP,#DATAFCXP WHERE FCXP.ESTADO='N' AND FCXP.IDTERCERO= #DATAFCXP.IDTERCERO AND FCXP.PROCEDENCIA= #DATAFCXP.PROCEDENCIA  AND FCXP.CNSFCXP<>#DATAFCXP.CNSFCXP AND NOT EXISTS(SELECT * FROM FCXPD WHERE FCXP.CNSFCXP=FCXPD.CNSFCXP))
			END
			IF (SELECT DBO.FNK_VALORVARIABLE('RESTRIN_CREA_CXP')) = 'USUARIO'
			BEGIN
				SELECT @COUNT_SEL = (SELECT COUNT(*) FROM FCXP,#DATAFCXP WHERE FCXP.ESTADO='N' AND FCXP.USUARIO= @USUARIO AND FCXP.PROCEDENCIA= #DATAFCXP.PROCEDENCIA  AND FCXP.CNSFCXP<>#DATAFCXP.CNSFCXP AND NOT EXISTS(SELECT * FROM FCXPD WHERE FCXP.CNSFCXP=FCXPD.CNSFCXP))
			END
			IF (SELECT DBO.FNK_VALORVARIABLE('RESTRIN_CREA_CXP')) = 'USUTER'
			BEGIN
				SELECT @COUNT_SEL = (SELECT COUNT(*) FROM FCXP,#DATAFCXP WHERE FCXP.ESTADO='N' AND FCXP.IDTERCERO= #DATAFCXP.IDTERCERO AND FCXP.USUARIO= @USUARIO AND FCXP.PROCEDENCIA= #DATAFCXP.PROCEDENCIA  AND FCXP.CNSFCXP<>#DATAFCXP.CNSFCXP AND NOT EXISTS(SELECT * FROM FCXPD WHERE FCXP.CNSFCXP=FCXPD.CNSFCXP))
			END
		END
		IF @COUNT_SEL > 0
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'Existen Cuentas por Pagar para Este Tercero Sin Detalles y sin Definir.. Se Deben Terminar o Anular.'
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN 
		END
			
		BEGIN TRY 
			IF UPPER(@PROCESO)='EDITAR'
			BEGIN
				UPDATE FCXP SET 
				 TIPOCXP			= #DATAFCXP.TIPOCXP			
				,IDSEDE				= #DATAFCXP.IDSEDE				
				,CIUDAD				= #DATAFCXP.CIUDAD				
