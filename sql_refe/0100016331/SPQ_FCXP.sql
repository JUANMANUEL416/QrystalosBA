		BEGIN
			SELECT
				@CNSFCXP_IMP = CNSFCXP,
				@NIT_IMP = NIT,
				@IDTERCERO_IMP = IDTERCERO,
				@MSG_IMP = NULL,
				@MANEXO_UPD = 0,
				@DOCEQ_UPD = 0,
				@REQ_GEN_ANEXO = 0,
				@GEN_ANEXO_OK = 0,
				@ERR_GEN_ANEXO = NULL,
				@FECHA_CXP_IMP = NULL,
				@FECHA_FAC_IMP = NULL
			FROM #IMPORT_SOPORTE
			WHERE ITEM = @ITEM_IMP

			SET @TOTAL_IMP = @TOTAL_IMP + 1

			IF NOT EXISTS (SELECT 1 FROM FCXP WHERE CNSFCXP = @CNSFCXP_IMP)
				SET @MSG_IMP = 'La cuenta por pagar no existe.'
			ELSE
			BEGIN
				SELECT
					@FECHA_CXP_IMP = CONVERT(DATE, X.FECHA),
					@FECHA_FAC_IMP = CONVERT(DATE, X.F_FACTURAREF),
					@MSG_IMP = CASE
						WHEN COALESCE(X.PROCEDENCIA, '') <> 'Nomina' OR COALESCE(X.ESTADO, '') = 'A'
							THEN 'La CxP no es de procedencia N?mina o est? anulada.'
						WHEN T.IDTERCERO IS NULL
							THEN 'El tercero no existe o no coincide con la CxP.'
						WHEN COALESCE(T.MANEXO, 0) <> 1
							THEN 'El tercero no est? marcado como DOCUMENTO SOPORTE.'
						WHEN NOT EXISTS (
							SELECT 1 FROM PRI P
							WHERE P.FECHA_INI <= CONVERT(DATE, X.F_FACTURAREF)
							  AND P.FECHA_FIN >= CONVERT(DATE, X.F_FACTURAREF)
