					CXP_NOMINA = 1
				FROM FCXP
				INNER JOIN TER ON TER.IDTERCERO = FCXP.IDTERCERO
				WHERE FCXP.CNSFCXP = @CNSFCXP_IMP
				  AND COALESCE(TER.MANEXO, 0) = 1

				IF @@ROWCOUNT = 0
				BEGIN
					SET @FALLIDOS_IMP = @FALLIDOS_IMP + 1
					INSERT INTO @RESULTADO_SOPORTE (CNSFCXP, NIT, ESTADO, MENSAJE, MANEXO_ACTUALIZADO, DOCEQUIVALENTE_ACTUALIZADO)
					VALUES (@CNSFCXP_IMP, @NIT_IMP, 'ERROR', 'No fue posible marcar DOCEQUIVALENTE en la CxP.', 0, 0)
					SET @ITEM_IMP = @ITEM_IMP + 1
					CONTINUE
				END

				SET @MANEXO_UPD = 1
				SET @DOCEQ_UPD = 1

				IF NOT EXISTS (
					SELECT 1
					FROM FCXP
					WHERE CNSFCXP = @CNSFCXP_IMP
					  AND COALESCE(N_FACTURA, '') <> ''
					  AND COALESCE(CNSRESOL, '') <> ''
				)
