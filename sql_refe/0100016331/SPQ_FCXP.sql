			RETURN
		END

		SELECT @LIMITE_IMP = COUNT(*), @ITEM_IMP = 1 FROM #IMPORT_SOPORTE
		SET @EXITOSOS_IMP = 0
		SET @FALLIDOS_IMP = 0
		SET @TOTAL_IMP = 0

