							WHERE P.FECHA_INI <= CONVERT(DATE, X.FECHA)
							  AND P.FECHA_FIN >= CONVERT(DATE, X.FECHA)
							  AND COALESCE(P.CERRADO, 0) = 0
							  AND COALESCE(P.CERRADO_CXP, 0) = 0
						) THEN 'El periodo contable de la fecha de la CXP no existe, est? cerrado o el periodo de Cuentas por Pagar est? cerrado.'
					END
				FROM FCXP AS X
				LEFT JOIN TER AS T
					ON T.IDTERCERO = X.IDTERCERO
				   AND T.NIT = @NIT_IMP
				   AND T.IDTERCERO = @IDTERCERO_IMP
				WHERE X.CNSFCXP = @CNSFCXP_IMP
			END

			IF @MSG_IMP IS NOT NULL
			BEGIN
