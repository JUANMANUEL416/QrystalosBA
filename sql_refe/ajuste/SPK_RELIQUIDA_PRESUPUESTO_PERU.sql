CREATE OR ALTER PROCEDURE SPK_RELIQUIDA_PRESUPUESTO_PERU @NOPRESUPUESTO VARCHAR(20), @PROCESO VARCHAR(20) = NULL
WITH ENCRYPTION
AS
SET NOCOUNT ON
DECLARE
   @PREFIJO		VARCHAR(10)
   ,@PROCEDENCIA	VARCHAR(20)
   ,@IDTERCERO		VARCHAR(20)
   ,@IDPLAN			VARCHAR(20)
   ,@IDAFILIADO		VARCHAR(20)
   ,@IDSERVICIO		VARCHAR(20)
   ,@NOADMISION		VARCHAR(20)
   ,@VALOR			DECIMAL(14,2)
   ,@VALORCOPAGO	DECIMAL(14,2)
   ,@VALOREXCEDENTE	DECIMAL(14,2)
   ,@IGV			DECIMAL(14,2)
   ,@MEDICAMENTOS	SMALLINT
   ,@COPAGOPROGRAMA DECIMAL(14,2)
   ,@COPAGOAGUDO	DECIMAL(14,2)
   ,@COPAGOPROGRAMA_HADM DECIMAL(14,2)
   ,@FECHA			DATETIME
   ,@PORCENTAJE_COPAGO	DECIMAL(14,2)
   ,@VALOR_UNITARIO_SIN_IGV	DECIMAL(14,2)
   ,@VALOR_IGV_UNITARIO	DECIMAL(14,2)
   ,@VALOR_UNITARIO_CON_IGV	DECIMAL(14,2)
   ,@VALOR_COPAGO_UNIT_SIN_IGV	DECIMAL(14,2)
   ,@VALOR_COPAGO_IGV_UNIT	DECIMAL(14,2)
   ,@VALOR_COPAGO_TOTAL_SIN_IGV	DECIMAL(14,2)
   ,@VALOR_COPAGO_TOTAL_CON_IGV	DECIMAL(14,2)
   ,@ID_CITSITEDS    INT
   ,@CANT_DIAS       INT
DECLARE @VALOR_SERVICIOS_SIN_IGV DECIMAL(14,2) , @VIVA DECIMAL(14,2), @VALORCOPAGO_2 DECIMAL(14,2)
   
BEGIN
   PRINT 'INGRESE SPK_RELIQUIDA_PRESUPUESTO_PERU'
	SELECT @NOADMISION = NOADMISION FROM HPREP WHERE NOPRESUPUESTO=@NOPRESUPUESTO
	SELECT @IDTERCERO=IDTERCERO, @IDPLAN=IDPLAN, @FECHA=GETDATE(), @COPAGOPROGRAMA_HADM=COALESCE(COPAGOPROGRAMA,0)
	, @COPAGOPROGRAMA=100-COALESCE(COPAGOPROGRAMA,0), @ID_CITSITEDS = ID_CITSITEDS FROM HADM WHERE NOADMISION=@NOADMISION
	IF COALESCE(@ID_CITSITEDS,0) = 0
   BEGIN
      SELECT TOP 1  @ID_CITSITEDS = ID FROM CITSITEDS WHERE CONSECUTIVO = @NOADMISION AND PROCEDENCIA = 'HADM' ORDER BY  FECHA  ASC
   END
	IF @PROCESO = 'NUEVO'
	BEGIN
		UPDATE HPREPD SET COPAGOVARIABLE = CASE WHEN COALESCE(HPREPD.F_RUTA,0) = 1 THEN 100 ELSE @COPAGOPROGRAMA END , ID_CITSITEDS = @ID_CITSITEDS
		WHERE  NOPRESUPUESTO=@NOPRESUPUESTO --AND COALESCE(HPREPD.F_RUTA,0) = 0 /*AND COALESCE(HPREPD.ESPAQUETE,0)=0*/

      IF EXISTS (SELECT  1 FROM HPREPD WHERE NOPRESUPUESTO=@NOPRESUPUESTO AND COALESCE(ESPAQUETE,0) = 1)
      BEGIN
         SELECT @CANT_DIAS = SUM(HPREPD.CANTIDAD) FROM HPREPD WHERE NOPRESUPUESTO=@NOPRESUPUESTO AND COALESCE(ESPAQUETE,0) = 1
         UPDATE HPREP SET FECHA_VENCE = DATEADD(DAY,COALESCE(@CANT_DIAS,30), FECHA) WHERE NOPRESUPUESTO=@NOPRESUPUESTO 
      END
      ELSE
      BEGIN
         UPDATE HPREP SET FECHA_VENCE = DATEADD(MONTH,1, FECHA) WHERE NOPRESUPUESTO=@NOPRESUPUESTO 
      END
	END
	DECLARE _HPREP_CURSOR CURSOR FOR
	SELECT IDSERVICIO FROM HPREPD WHERE NOPRESUPUESTO=@NOPRESUPUESTO
	OPEN _HPREP_CURSOR
	FETCH NEXT FROM _HPREP_CURSOR INTO @IDSERVICIO
	WHILE @@FETCH_STATUS=0
	BEGIN			
		SET @VALORCOPAGO = 0
		SET @VALOR = 0
		IF (SELECT PRINCIPAL FROM IART WHERE IDARTICULO=@IDSERVICIO)=1
		BEGIN
			SELECT @VALOR = MAX(VLRSERVICIO) FROM SERTOT 
			WHERE IDTERCERO = @IDTERCERO AND IDPLAN = @IDPLAN
			AND IDSERVICIO IN (SELECT IDSERVICIO FROM SER WHERE IDARTICULO IN (SELECT IDARTICULO FROM IART WHERE IDSERVICIO=@IDSERVICIO))
			AND @FECHA >= FECHAINIFD AND @FECHA <= FECHAFINFD AND @FECHA >= FECHAINI AND @FECHA <= FECHAFIN
		END
		ELSE
		BEGIN
			SELECT @VALOR = VLRSERVICIO FROM SERTOT 
			WHERE  IDTERCERO  = @IDTERCERO AND IDPLAN = @IDPLAN AND IDSERVICIO = @IDSERVICIO
			AND @FECHA >= FECHAINIFD AND @FECHA <= FECHAFINFD AND @FECHA >= FECHAINI AND @FECHA <= FECHAFIN
		END
		--SELECT @VALORCOPAGO=(@VALOR*CANTIDAD)*(@COPAGOPROGRAMA/100), @IGV=@VALOR-(@VALOR/1.18)
		--FROM HPREPD WHERE NOPRESUPUESTO=@NOPRESUPUESTO AND IDSERVICIO=@IDSERVICIO

      SELECT @VALOR_UNITARIO_SIN_IGV = F.VALOR_UNITARIO_SIN_IGV, @VALOR_IGV_UNITARIO=F.VALOR_IGV_UNITARIO,@VALOR_UNITARIO_CON_IGV=F.VALOR_UNITARIO_CON_IGV
         ,@VALOR_COPAGO_UNIT_SIN_IGV=CONVERT(DECIMAL(14,2),F.VALOR_UNITARIO_SIN_IGV  * CONVERT(DECIMAL(14,2),((COPAGOVARIABLE)/100)))
         ,@VALOR_COPAGO_IGV_UNIT=CONVERT(DECIMAL(14,2),(CONVERT(DECIMAL(14,2),F.VALOR_UNITARIO_SIN_IGV  * CONVERT(DECIMAL(14,2),((COPAGOVARIABLE)/100))) * .18))
         ,@VALOR_COPAGO_TOTAL_SIN_IGV=CONVERT(DECIMAL(14,2),F.VALOR_UNITARIO_SIN_IGV  * CONVERT(DECIMAL(14,2),((COPAGOVARIABLE)/100))) * HPREPD.CANTIDAD 
         ,@VALOR_COPAGO_TOTAL_CON_IGV=CONVERT(DECIMAL(14,2),F.VALOR_UNITARIO_CON_IGV  * CONVERT(DECIMAL(14,2),((COPAGOVARIABLE)/100))) * HPREPD.CANTIDAD 
      FROM HPREP INNER JOIN HPREPD  ON HPREP.NOPRESUPUESTO = HPREPD.NOPRESUPUESTO
                 INNER JOIN HADM    ON HPREP.NOADMISION    = HADM.NOADMISION
                 CROSS APPLY DBO.FNQ_VAL_SERTOT_PERU(
                     HPREP.FECHA,
                     HPREP.IDTERCEROCA,
                     HPREP.IDPLAN,
                     HPREPD.IDSERVICIO
                 ) F
      WHERE HPREP.NOPRESUPUESTO = @NOPRESUPUESTO AND IDSERVICIO = @IDSERVICIO

      SELECT @VALORCOPAGO=@VALOR_COPAGO_TOTAL_CON_IGV, @IGV=@VALOR_IGV_UNITARIO

		--SET @VALOR=@VALOR-@IGV
		SET @VALOR=@VALOR_UNITARIO_SIN_IGV
		UPDATE HPREPD SET VALOR=@VALOR, IGV=@IGV*CANTIDAD, VALORCOPAGO=@VALORCOPAGO
         , VALOREXCEDENTE=((@VALOR*CANTIDAD)+@IGV*CANTIDAD)-@VALORCOPAGO
         --, VALOREXCEDENTE=(@VALOR*CANTIDAD)-@VALORCOPAGO
         , VALOR_UNITARIO_SIN_IGV=@VALOR_UNITARIO_SIN_IGV, VALOR_IGV_UNITARIO=@VALOR_IGV_UNITARIO, VALOR_UNITARIO_CON_IGV=@VALOR_UNITARIO_CON_IGV
         , VALOR_COPAGO_UNIT_SIN_IGV=@VALOR_COPAGO_UNIT_SIN_IGV, VALOR_COPAGO_IGV_UNIT=@VALOR_COPAGO_IGV_UNIT, VALOR_COPAGO_TOTAL_SIN_IGV=@VALOR_COPAGO_TOTAL_SIN_IGV
		WHERE NOPRESUPUESTO=@NOPRESUPUESTO AND IDSERVICIO=@IDSERVICIO

		FETCH NEXT FROM _HPREP_CURSOR INTO @IDSERVICIO
	END
	CLOSE _HPREP_CURSOR
	DEALLOCATE _HPREP_CURSOR
	SELECT @VALOR=SUM(VALOR*CANTIDAD)+ SUM(IGV), @VALORCOPAGO=SUM(VALORCOPAGO), @VALOREXCEDENTE=SUM(VALOREXCEDENTE) 
   FROM HPREPD WHERE NOPRESUPUESTO=@NOPRESUPUESTO AND COALESCE(HPREPD.ELIMINADO,0) = 0

   SELECT @VALOR_SERVICIOS_SIN_IGV = sum( VALOR_COPAGO_TOTAL_SIN_IGV ) FROM  HPREPD WHERE NOPRESUPUESTO = @NOPRESUPUESTO  AND COALESCE(HPREPD.ELIMINADO,0) = 0 --AND COALESCE(ESPAQUETE,0)=0 
   SELECT @VIVA = CONVERT(DECIMAL(14,2), (@VALOR_SERVICIOS_SIN_IGV * 0.18))
   --SELECT @VALOR_SERVICIOS_SIN_IGV, @VIVA
   SELECT @VALORCOPAGO_2 = @VALOR_SERVICIOS_SIN_IGV+@VIVA /* SE RETIRA ESTE CALCULO, POR QUE LA BOLETA SE IMPRIME, CONNLOS DATOS DE HPREPD  */
	UPDATE HPREP SET VALORTOTAL=@VALOR, VALORCOPAGO=@VALORCOPAGO, VALOREXCEDENTE=@VALOREXCEDENTE, COPAGOPROGRAMA=@COPAGOPROGRAMA_HADM, PORCENTAJE_COPAGO=@COPAGOPROGRAMA 
   WHERE NOPRESUPUESTO=@NOPRESUPUESTO

END

