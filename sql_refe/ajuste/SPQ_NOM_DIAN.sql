CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_DIAN @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @DATO NVARCHAR(MAX)
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20)
DECLARE @PROCESO VARCHAR(20), @DATOS NVARCHAR(MAX), @CONSECUTIVO VARCHAR(7), @CNSNIEPEG INT, @CNSNIEPEG_BASE INT, @TIPONOTA INT
DECLARE @ANO VARCHAR(20), @MES VARCHAR(20), @NUMDOC VARCHAR(20), @ANULADOS VARCHAR(2), @TIPONOM VARCHAR(2), @ESTADO VARCHAR(2)
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))

BEGIN
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	IF @METODO = 'GET_TOTALS'
	BEGIN
		SELECT @ANO = ANO, @MES = MES, @ANULADOS = ANULADOS, @TIPONOM = TIPONOM, @ESTADO = ESTADO
		FROM OPENJSON(@PARAMETROS) WITH (ANO VARCHAR(20) '$.ANO', MES VARCHAR(20) '$.MES', ANULADOS VARCHAR(2) '$.ANULADOS', TIPONOM VARCHAR(2) '$.TIPONOM', ESTADO VARCHAR(2) '$.ESTADO'
				)

		SELECT 'OK' OK

		SELECT SUM(B.VALOR_NETO) AS TOTAL_VALOR_NETO, SUM(B.VALOR_INGRESOS) AS TOTAL_VALOR_INGRESOS, SUM(B.VALOR_EGRESOS) AS TOTAL_VALOR_EGRESOS, COUNT(*) AS 
			TOTAL_EMPLEADOS
		FROM NIEPEG
		INNER JOIN VWK_NIEPE B ON NIEPEG.CONSECUTIVO = B.CONSECUTIVO AND NIEPEG.NUMDOC = B.NUMDOC
		WHERE NIEPEG.CONSECUTIVO = CONCAT (@ANO, @MES) AND ISNULL(NIEPEG.ANULADO, 0) = @ANULADOS AND (@TIPONOM = '4' OR ISNULL(NIEPEG.TIPONOTA, 0) = @TIPONOM
				) AND (@ESTADO = '5' OR COALESCE(ESTADODIAN, 0) = @ESTADO)

		RETURN
	END

	IF @METODO = 'GET_NIEPED'
	BEGIN
		SELECT @ANO = ANO, @MES = MES, @NUMDOC = NUMDOC
		FROM OPENJSON(@PARAMETROS) WITH (ANO VARCHAR(20) '$.ANO', MES VARCHAR(20) '$.MES', NUMDOC VARCHAR(20) '$.NUMDOC')

		SELECT 'OK' OK

		SELECT *
		FROM VWK_NIEPED
		WHERE CONSECUTIVO = CONCAT (@ANO, @MES) AND NUMDOC = @NUMDOC

		RETURN
	END

	IF @METODO = 'GET_NIEPEG_PERIOD'
	BEGIN
		SELECT @CONSECUTIVO = CONSECUTIVO
		FROM OPENJSON(@PARAMETROS) WITH (CONSECUTIVO VARCHAR(7) '$.CONSECUTIVO')

		SELECT 'OK' OK

		SELECT COUNT(1) AS REG
		FROM NIEPEG
		WHERE CONSECUTIVO = @CONSECUTIVO AND ISNULL(ANULADO, 0) = 0

		RETURN
	END

	IF @METODO = 'GENERATE_NIEPEG'
	BEGIN
		BEGIN TRY
			SELECT @CONSECUTIVO = CONSECUTIVO
			FROM OPENJSON(@PARAMETROS) WITH (CONSECUTIVO VARCHAR(7) '$.CONSECUTIVO')

			BEGIN
				INSERT INTO NIEPEG (CONSECUTIVO, NUMDOC, FECHA)
				SELECT CONSECUTIVO, NUMDOC, FECHA
				FROM DBO.VWK_NIEPE V
				WHERE CONSECUTIVO = @CONSECUTIVO AND NOT EXISTS (
						SELECT 1
						FROM NIEPEG
						WHERE NIEPEG.CONSECUTIVO = V.CONSECUTIVO AND NIEPEG.NUMDOC = V.NUMDOC AND ISNULL(NIEPEG.ANULADO, 0) = 0
						)
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK

		RETURN
	END

	IF @METODO = 'PROCESAR_NIE'
	BEGIN
		BEGIN TRY
			SELECT @CNSNIEPEG = CNSNIEPEG
			FROM OPENJSON(@PARAMETROS) WITH (CNSNIEPEG INT '$.CNSNIEPEG')

			BEGIN
				UPDATE NIEPEG
				SET ESTADODIAN = 1
				WHERE CNSNIEPEG = @CNSNIEPEG AND COALESCE(ESTADODIAN, 0) IN (0, 3)
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK

		RETURN
	END

	IF @METODO = 'PROCESAR_NIE_FILTER'
	BEGIN
		BEGIN TRY
			SELECT @CONSECUTIVO = CONSECUTIVO
			FROM OPENJSON(@PARAMETROS) WITH (CONSECUTIVO VARCHAR(7) '$.CONSECUTIVO')

			BEGIN
				UPDATE A
				SET ESTADODIAN = 1
				FROM NIEPEG AS A
				INNER JOIN VWK_NIEPE B ON A.CONSECUTIVO = B.CONSECUTIVO AND A.NUMDOC = B.NUMDOC
				WHERE A.CONSECUTIVO = @CONSECUTIVO AND ISNULL(A.ANULADO, 0) = 0 AND COALESCE(ESTADODIAN, 0) = 0
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK

		RETURN
	END

	IF @METODO = 'CHANGE_NOM_NIEPEG'
	BEGIN
		BEGIN TRY
			SELECT @CNSNIEPEG_BASE = CNSNIEPEG_BASE, @TIPONOTA = TIPONOTA
			FROM OPENJSON(@PARAMETROS) WITH (CNSNIEPEG_BASE INT '$.CNSNIEPEG_BASE', TIPONOTA INT '$.TIPONOTA')

			BEGIN
				INSERT INTO NIEPEG (CONSECUTIVO, NUMDOC, FECHA, CNSNIEPEG_BASE, TIPONOTA, ESTADODIAN)
				SELECT CONSECUTIVO, NUMDOC, CONVERT(SMALLDATETIME, GETDATE()), CNSNIEPEG, @TIPONOTA, 1
				FROM NIEPEG
				WHERE CNSNIEPEG = @CNSNIEPEG_BASE

				SET @CNSNIEPEG = @@IDENTITY

				UPDATE NIEPEG
				SET ANULADO = 1, OBS = CONCAT ('Registro ', IIF(@TIPONOTA = 1, 'remplazado', 'eliminado'), ' por el registro CNSNIEPEG=', @CNSNIEPEG
						)
				WHERE CNSNIEPEG = @CNSNIEPEG_BASE
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK

		RETURN
	END

	-- Vista previa del XML que se enviaría a la DIAN (no guarda archivo ni notifica).
	-- SPK_GENERAR_XML_NOMINA retorna el XML cuando @PATH_URL IS NULL.
	IF @METODO = 'PREVIEW_XML'
	BEGIN
		DECLARE @NOMBRE_XML NVARCHAR(1000)
		DECLARE @AMBIENTE_XML INT
		DECLARE @TESTSETID VARCHAR(100)
		DECLARE @XMLPREVIEW TABLE ([XML] XML)

		SELECT @CNSNIEPEG = CNSNIEPEG
		FROM OPENJSON(@PARAMETROS) WITH (CNSNIEPEG INT '$.CNSNIEPEG')

		IF COALESCE(@CNSNIEPEG, 0) = 0
		BEGIN
			SELECT 'KO' OK

			SELECT 'Debe indicar el consecutivo de nómina electrónica (CNSNIEPEG).' ERROR

			RETURN
		END

		BEGIN TRY
			INSERT INTO @XMLPREVIEW ([XML])
			EXEC DBO.SPK_GENERAR_XML_NOMINA @CNSNIEPEG, NULL, @NOMBRE_XML OUTPUT, @AMBIENTE_XML OUTPUT, @TESTSETID OUTPUT
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		IF NOT EXISTS (
				SELECT 1
				FROM @XMLPREVIEW
				)
		BEGIN
			SELECT 'KO' OK

			SELECT 'SPK_GENERAR_XML_NOMINA no retornó XML. Verifique que al invocarlo con @PATH_URL NULL el procedimiento haga SELECT del XML.' ERROR

			RETURN
		END

		SELECT 'OK' OK

		SELECT CAST([XML] AS NVARCHAR(MAX)) AS [XML], @NOMBRE_XML AS NOMBRE_XML, @AMBIENTE_XML AS AMBIENTE, @TESTSETID AS TESTSETID
		FROM @XMLPREVIEW

		RETURN
	END
END

