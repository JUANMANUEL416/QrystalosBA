CREATE OR ALTER PROCEDURE DBO.SPQ_LIQUIDACION @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
BEGIN
	-- OPTIMIZACION 1: Reduce tráfico de red eliminando mensajes de metadatos
	SET NOCOUNT ON;

	DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @DATOS NVARCHAR(MAX)
	DECLARE @USUARIO VARCHAR(20), @PROCESO VARCHAR(20)
	DECLARE @CNSPAGO VARCHAR(20), @CNS VARCHAR(20), @IDSEDE VARCHAR(5), @SYS_COMPUTERNAME VARCHAR(254), @COMPANIA VARCHAR(2)
	DECLARE @CODNOMINA VARCHAR(2), @ANO VARCHAR(4), @MES VARCHAR(2), @CODPPAGO VARCHAR(5), @CNSEXCEL VARCHAR(20)
	DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
	DECLARE @COLUMNAS NVARCHAR(MAX)
	DECLARE @SQL NVARCHAR(MAX)

	-- Lectura inicial de parametros
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
	FROM USUSU
	WHERE USUARIO = @USUARIO

	SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
	FROM UBEQ
	WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	-- OPTIMIZACION 2: Estructura ELSE IF para evitar evaluaciones innecesarias
	-------------------------------------------------------------------------
	-- METODO: GENERATE_NOMINA
	-------------------------------------------------------------------------
	IF @METODO = 'GENERATE_NOMINA'
	BEGIN
		BEGIN TRY
			SELECT @CNSPAGO = CNSPAGO, @CODNOMINA = CODNOMINA, @ANO = ANO, @MES = MES, @CODPPAGO = CODPPAGO, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					CNSPAGO VARCHAR(20) '$.CNSPAGO', CODNOMINA VARCHAR(2) '$.CODNOMINA', ANO VARCHAR(4) '$.ANO', MES VARCHAR(2) '$.MES', CODPPAGO VARCHAR(5) 
					'$.CODPPAGO', PROCESO VARCHAR(20) '$.PROCESO'
					)

			-- Validación inicial de terceros
			EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@RPDX', @LONGITUD = 8, @NVOCONSEC = @CNS OUTPUT

			INSERT INTO RPDX (CNS, IDTERCERO, NOMBRE, ID1, STRINGMEDIO1)
			SELECT @CNS, NEMP.DOCIDEMPLEADO, TER.RAZONSOCIAL, NCON.CODCONCEPTO, NCON.DESCRIPCION
			FROM NEMPFD
			INNER JOIN NCON ON NEMPFD.CODCONCEPTO = NCON.CODCONCEPTO
			INNER JOIN NEMP ON NEMPFD.NUMDOC = NEMP.NUMDOC
			INNER JOIN TER ON NEMP.TERCEROID = TER.IDTERCERO
			WHERE CNSPAGO = @CNSPAGO AND NCON.TIPO = 'Ingreso' AND NEMP.TERCEROID <> NEMPFD.IDTERCERO

			-- OPTIMIZACION 3: Uso de EXISTS en lugar de COUNT(*) > 0 para validaciones rápidas
			IF EXISTS (
					SELECT 1
					FROM RPDX
					WHERE CNS = @CNS
					)
			BEGIN
				EXEC SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE, '@EXCEL', @CNSEXCEL OUTPUT

				SELECT @CNSEXCEL = @IDSEDE + REPLACE(SPACE(8 - LEN(@CNSEXCEL)) + LTRIM(RTRIM(@CNSEXCEL)), SPACE(1), 0)

				INSERT INTO KEXCEL_FILL (CNSEXCEL, NOMBRE, BORRAR, CONSULTA)
				SELECT @CNSEXCEL, 'Empleados con error de terceros' + CONVERT(VARCHAR, GETDATE(), 112) + '_' + REPLACE(CONVERT(VARCHAR, GETDATE(), 108), ':', '') + 
					'.xlsx', 1, 
					'SELECT IDTERCERO AS CODIGOTERCERO,NOMBRE AS NOMBRES,ID1 AS CODCONCEPTO,STRINGMEDIO1 AS CONCEPTO FROM RPDX WHERE CNS= ''' + @CNS + 
					''''

				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'SE EXPORTARON LOS EMPLEADOS CON ERRORES EN TERCEROS, VALIDAR EMPLEADOS.'
			END

			-- Retorno temprano si hay errores
			IF EXISTS (
					SELECT 1
					FROM @TBLERRORES
					)
			BEGIN
				SELECT 'KO' OK, @CNSEXCEL CNSEXCEL

				SELECT ERROR
				FROM @TBLERRORES

				RETURN
			END

			-------------------------------------------------------------------------
			-- OPTIMIZACION PRINCIPAL: LOGICA IF / ELSE PARA EVITAR DOBLE EJECUCION
			-------------------------------------------------------------------------
			IF UPPER(@PROCESO) = 'CLOSE'
			BEGIN
				-- >>> BLOQUE DE CIERRE <<<
				EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@RPDX', @LONGITUD = 8, @NVOCONSEC = @CNS OUTPUT

				INSERT INTO RPDX (CNS, ID1, NOMBRE, ID2, STRINGMEDIO1, ID3, ID4)
				SELECT @CNS, NIEPE.NUMDOC, NOMBRE_EMPLEADO, CODCONCEPTO, NOMBRE_CONCEPTO, IDAREA, CCOSTO
				FROM NIEPE
				INNER JOIN NIEPED ON NIEPE.CNSNIEPE = NIEPED.CNSNIEPE AND NIEPE.NUMDOC = NIEPED.NUMDOC
				WHERE NIEPE.CNSPAGO = @CNSPAGO AND DBO.FNK_NC_CUENTA_KMCOM('01', 'NOMINA', 'CR', CODCONCEPTO, CCOSTO, 'P', '', 0) LIKE '%NO%'

				IF EXISTS (
						SELECT 1
						FROM RPDX
						WHERE CNS = @CNS
						)
				BEGIN
					EXEC SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE, '@EXCEL', @CNSEXCEL OUTPUT

					SELECT @CNSEXCEL = @IDSEDE + REPLACE(SPACE(8 - LEN(@CNSEXCEL)) + LTRIM(RTRIM(@CNSEXCEL)), SPACE(1), 0)

					INSERT INTO KEXCEL_FILL (CNSEXCEL, NOMBRE, BORRAR, CONSULTA)
					SELECT @CNSEXCEL, 'Errores contables' + CONVERT(VARCHAR, GETDATE(), 112) + '_' + REPLACE(CONVERT(VARCHAR, GETDATE(), 108), ':', '') + '.xlsx', 1, 
						'SELECT ID1 AS IDEMPLEADO,NOMBRE AS NOMBRES,ID2 AS CODCONCEPTO,STRINGMEDIO1 AS CONCEPTO,ID3 AS AREA,ID4 AS CCOSTO FROM RPDX WHERE CNS= ''' 
						+ @CNS + ''''

					INSERT INTO @TBLERRORES (ERROR)
					SELECT 
						'SE DEBEN CORREGIR LOS ERRORES DE CONTABILIZACION DE LA NOMINA ANTES DE SER CERRADA..., SE EXPORTARA EL LOG DE ERRORES. COMUNQUESE CON EL AREA CONTABLE.'
				END

				IF EXISTS (
						SELECT 1
						FROM @TBLERRORES
						)
				BEGIN
					SELECT 'KO' OK, @CNSEXCEL CNSEXCEL

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				-- Validar existencia de registros antes de cerrar
				IF NOT EXISTS (
						SELECT 1
						FROM NIEPE
						WHERE CNSPAGO = @CNSPAGO
						)
				BEGIN
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'NO EXISTEN REGISTROS O DETALLES DE ESTA NOMINA, NO ES POSIBLE CERRAR UNA NOMINA SIN DETALLES.'
				END

				IF EXISTS (
						SELECT 1
						FROM @TBLERRORES
						)
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				-- Ejecución segura: Liquidar -> Cerrar -> Vacaciones
				EXEC SPQ_LIQUIDAR_NOMI @COMPANIA, @IDSEDE, @CODNOMINA, @ANO, @MES, @CODPPAGO, @USUARIO, @SYS_COMPUTERNAME, @CNSPAGO

				EXEC SPQ_CERRAR_NOMI @CNSPAGO

				EXEC SPQ_PROCESO_VACACIONES @CNSPAGO, 'CIERRE'
			END
			ELSE
			BEGIN
				-- >>> BLOQUE NORMAL (NO ES CIERRE) <<<
				-- Al estar en un ELSE, esto NUNCA se ejecutará si entra al IF anterior
				EXEC SPQ_LIQUIDAR_NOMI @COMPANIA, @IDSEDE, @CODNOMINA, @ANO, @MES, @CODPPAGO, @USUARIO, @SYS_COMPUTERNAME, @CNSPAGO
			END

			SELECT 'OK' OK
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()

			SELECT 'KO' OK, @CNSEXCEL CNSEXCEL -- Devuelve CNSEXCEL si se generó alguno

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END CATCH
	END
			-------------------------------------------------------------------------
			-- METODO: OPEN_NOMINA
			-------------------------------------------------------------------------
	ELSE IF @METODO = 'OPEN_NOMINA'
	BEGIN
		BEGIN TRY
			SELECT @CNSPAGO = CNSPAGO, @ANO = ANO, @MES = MES
			FROM OPENJSON(@PARAMETROS) WITH (CNSPAGO VARCHAR(20) '$.CNSPAGO', ANO VARCHAR(4) '$.ANO', MES VARCHAR(2) '$.MES')

			-- Validaciones usando EXISTS (mas eficiente)
			IF EXISTS (
					SELECT 1
					FROM PRI
					WHERE ANO = @ANO AND MES = @MES AND CERRADO = 1
					)
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'El periodo contable de la nomina se encuentra cerrado no se puede abrir'

			IF EXISTS (
					SELECT 1
					FROM FCXP
					LEFT JOIN FCXPP ON FCXP.CNSFCXP = FCXPP.CNSFCXP
					WHERE FCXP.PROCEDENCIA = 'Nomina' AND FCXP.NOREFERENCIA = @CNSPAGO AND COALESCE(FCXPP.CNSFCXP, '') <> '' AND FCXPP.ESTADO <> 'A'
					)
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'Existen ordenes de pagos para la nomina que se pretende abrir, debido a esto no es posible la apertura de la nomina'

			IF EXISTS (
					SELECT 1
					FROM FCXP
					INNER JOIN FCXPDBCR ON FCXP.CNSFCXP = FCXPDBCR.CNSFCXP
					WHERE FCXP.PROCEDENCIA = 'Nomina' AND FCXP.NOREFERENCIA = @CNSPAGO AND FCXPDBCR.ESTADO <> 'A'
					)
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'Existen Cuentas por pagar con notas debito o credito registradas, debido a esto no es posible la apertura de la nomina'

			IF EXISTS (
					SELECT 1
					FROM @TBLERRORES
					)
			BEGIN
				SELECT 'KO' OK

				SELECT ERROR
				FROM @TBLERRORES

				RETURN
			END

			EXEC SPQ_ABRIR_NOMI @CNSPAGO

			EXEC SPQ_PROCESO_VACACIONES @CNSPAGO, 'ABRE'

			SELECT 'OK' OK
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()

			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END CATCH
	END
			-------------------------------------------------------------------------
			-- METODO: EXPORTAR_PDF
			-------------------------------------------------------------------------
	ELSE IF @METODO = 'EXPORTAR_PDF'
	BEGIN
		SELECT @CNSPAGO = CNSPAGO
		FROM OPENJSON(@PARAMETROS) WITH (CNSPAGO VARCHAR(20) '$.CNSPAGO')

		SELECT 'OK' OK

		SELECT NEMP.DOCIDEMPLEADO, NIEPE.NOMBRE_PERIODO, NIEPE.NUMDOC, NIEPE.NOMBRE_EMPLEADO, NIEPE.NOMBRE_CCOSTO, NIEPE.DETALLE_CARGO, NIEPE.VALOR_INGRESOS, 
			NIEPE.VALOR_EGRESOS, NIEPE.VALOR_NETO, NIEPE.VALOR_APORTES, NPER.FECHAINI, NPER.FECHAFIN
		FROM NIEPE
		INNER JOIN NPER ON NPER.CNSPAGO = NIEPE.CNSPAGO
		INNER JOIN NEMP ON NEMP.NUMDOC = NIEPE.NUMDOC
		WHERE NIEPE.CNSPAGO = @CNSPAGO
	END
			-------------------------------------------------------------------------
			-- METODO: EXPORTAR_EXCEL
			-------------------------------------------------------------------------
	ELSE IF @METODO = 'EXPORTAR_EXCEL'
	BEGIN
		SELECT @CNSPAGO = CNSPAGO
		FROM OPENJSON(@PARAMETROS) WITH (CNSPAGO VARCHAR(20) '$.CNSPAGO')

		IF @CNSEXCEL IS NULL
			EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@EXCEL', @LONGITUD = 8, @NVOCONSEC = @CNSEXCEL OUTPUT

		BEGIN TRY
			INSERT INTO KEXCEL_FILL (CNSEXCEL, NOMBRE, BORRAR, CONSULTA)
			SELECT @CNSEXCEL, @CNSPAGO + '.xlsx', 1, 
				'SELECT NEMP.DOCIDEMPLEADO AS DOCUMENTO, NIEPE.NOMBRE_PERIODO AS PERIODO_NOMINA, NIEPE.NUMDOC AS IDEMPLEADO, NIEPE.NOMBRE_EMPLEADO AS NOMBRES, NIEPE.NOMBRE_CCOSTO AS CCOSTO, NIEPE.DETALLE_CARGO AS CARGO, NIEPE.VALOR_INGRESOS, 
                NIEPE.VALOR_EGRESOS, NIEPE.VALOR_NETO, NIEPE.VALOR_APORTES
                FROM NIEPE INNER JOIN NPER ON NPER.CNSPAGO = NIEPE.CNSPAGO INNER JOIN NEMP ON NEMP.NUMDOC = NIEPE.NUMDOC
                WHERE NIEPE.CNSPAGO = ''' 
				+ @CNSPAGO + ''''
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF EXISTS (
				SELECT 1
				FROM @TBLERRORES
				)
		BEGIN
			SELECT 'KO' OK, @CNSEXCEL CNSEXCEL

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK, @CNSEXCEL CNSEXCEL
	END
			-------------------------------------------------------------------------
			-- METODO: EXPORTAR_SOI
			-------------------------------------------------------------------------
	ELSE IF @METODO = 'EXPORTAR_SOI'
	BEGIN
		SELECT @CNSPAGO = CNSPAGO
		FROM OPENJSON(@PARAMETROS) WITH (CNSPAGO VARCHAR(20) '$.CNSPAGO')

		IF @CNSEXCEL IS NULL
			EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@EXCEL', @LONGITUD = 8, @NVOCONSEC = @CNSEXCEL OUTPUT

		BEGIN TRY
			INSERT INTO KEXCEL_FILL (CNSEXCEL, NOMBRE, BORRAR, CONSULTA)
			SELECT @CNSEXCEL, @CNSPAGO + '.xlsx', 1, 'SELECT * FROM DBO.TFK_SOI(''' + @CNSPAGO + ''')'
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF EXISTS (
				SELECT 1
				FROM @TBLERRORES
				)
		BEGIN
			SELECT 'KO' OK, @CNSEXCEL CNSEXCEL

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK, @CNSEXCEL CNSEXCEL
	END
			-------------------------------------------------------------------------
			-- METODO: EXPORTAR_DETALLE_NOMINA
			-------------------------------------------------------------------------
	ELSE IF @METODO = 'EXPORTAR_DETALLE_NOMINA'
	BEGIN
		SELECT @CNSPAGO = CNSPAGO
		FROM OPENJSON(@PARAMETROS) WITH (CNSPAGO VARCHAR(20) '$.CNSPAGO')

		IF @CNSEXCEL IS NULL
			EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@EXCEL', @LONGITUD = 8, @NVOCONSEC = @CNSEXCEL OUTPUT

		BEGIN TRY
			SELECT @COLUMNAS = STRING_AGG(QUOTENAME(CODCONCEPTO + ' - ' + DESCRIPCION), ',')
			FROM (
				SELECT DISTINCT NP.CODCONCEPTO, NC.DESCRIPCION
				FROM NIEPED NP
				INNER JOIN NIEPE N ON NP.CNSNIEPE = N.CNSNIEPE
				INNER JOIN NCON NC ON NC.CODCONCEPTO = NP.CODCONCEPTO
				WHERE N.CNSPAGO = @CNSPAGO
				) X

			SET @SQL = 
				'
					SELECT *
					FROM
					(
						SELECT 
							NIEPE.NUMDOC AS IDEMPLEADO,
							NIEPE.NOMBRE_EMPLEADO,
							NEMP.TIPO_DOC AS TIPO_DOCUMENTO,
							NEMP.DOCIDEMPLEADO AS DOCUMENTO,
							DBO.FNK_LIMPIATEXTO(NCARNG.DESCRIPCION, ''A-Za-z '') AS CARGO,
							NIEPE.NOMBRE_AREA AS AREA,
							NIEPE.NOMBRE_CCOSTO AS CCOSTO,
							NIEPE.BASICO,
							NIEPED.CODCONCEPTO + '' - '' + NCON.DESCRIPCION AS CODCONCEPTO,
							NIEPED.TOTAL_NOMINA AS VALOR,
							NIEPE.VALOR_NETO,
							NIEPE.VALOR_INGRESOS,
							NIEPE.VALOR_EGRESOS,
							NIEPE.VALOR_APORTES,
							NIEPE.TOTAL_NOMINA
						FROM NIEPE
						INNER JOIN NEMP ON NEMP.NUMDOC = NIEPE.NUMDOC
						INNER JOIN NIEPED 
							ON NIEPE.CNSNIEPE = NIEPED.CNSNIEPE 
							AND NIEPED.NUMDOC = NIEPE.NUMDOC 
						INNER JOIN NCON 
							ON NCON.CODCONCEPTO = NIEPED.CODCONCEPTO
							INNER JOIN NCARNG ON NCARNG.CODCARGO = NEMP.CODCARGO AND NCARNG.NIVEL = NEMP.NIVEL AND NCARNG.GRADO = NEMP.GRADO
						WHERE NIEPE.CNSPAGO = ''' 
				+ @CNSPAGO + '''
					) AS SRC
					PIVOT
					(
						SUM(VALOR)
						FOR CODCONCEPTO IN (' + @COLUMNAS + 
				')
					) AS PVT
					ORDER BY IDEMPLEADO
					'

			INSERT INTO KEXCEL_FILL (CNSEXCEL, NOMBRE, BORRAR, CONSULTA)
			VALUES (@CNSEXCEL, @CNSPAGO + '.xlsx', 1, @SQL)
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF EXISTS (
				SELECT 1
				FROM @TBLERRORES
				)
		BEGIN
			SELECT 'KO' OK, @CNSEXCEL CNSEXCEL

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK, @CNSEXCEL CNSEXCEL
	END
			-------------------------------------------------------------------------
			-- METODO: EXPORTAR_CUENTAS_DBCR
			-------------------------------------------------------------------------
	ELSE IF @METODO = 'EXPORTAR_CUENTAS_DBCR'
	BEGIN
		SELECT @CNSPAGO = CNSPAGO
		FROM OPENJSON(@PARAMETROS) WITH (CNSPAGO VARCHAR(20) '$.CNSPAGO')

		IF @CNSEXCEL IS NULL
			EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@EXCEL', @LONGITUD = 8, @NVOCONSEC = @CNSEXCEL OUTPUT

		BEGIN TRY
			SET @SQL = 
				'
						SELECT NIEPE.NUMDOC AS IDEMPLEADO, NIEPE.NOMBRE_EMPLEADO, NEMP.TIPO_DOC AS TIPO_DOCUMENTO, NEMP.DOCIDEMPLEADO AS DOCUMENTO, NIEPE.IDAREA, NIEPE.NOMBRE_AREA AS AREA, NIEPE.CCOSTO AS IDCCOSTO,NIEPE.
						NOMBRE_CCOSTO AS CCOSTO, NIEPE.BASICO, NIEPED.CODCONCEPTO AS CODCONCEPTO, NCON.DESCRIPCION AS CONCEPTO,TER.NIT, NIEPED.TOTAL_NOMINA AS VALOR, MAX(CASE 
								WHEN KMCOM.TIPO = ''DB''
									THEN KMCOM.CUENTA
								END) AS CUENTA_DEBITO, MAX(CASE 
								WHEN KMCOM.TIPO = ''CR''
									THEN KMCOM.CUENTA
								END) AS CUENTA_CREDITO
					FROM NIEPE
					INNER JOIN NEMP ON NEMP.NUMDOC = NIEPE.NUMDOC
					INNER JOIN NIEPED ON NIEPE.CNSNIEPE = NIEPED.CNSNIEPE AND NIEPED.NUMDOC = NIEPE.NUMDOC
					INNER JOIN TER ON NIEPED.IDTERCERO_PRF = TER.IDTERCERO
					INNER JOIN NCON ON NCON.CODCONCEPTO = NIEPED.CODCONCEPTO
					LEFT JOIN KMCOM ON NIEPED.CODCONCEPTO = KMCOM.PREFIJO AND NIEPE.IDAREA = KMCOM.IDAREA AND NIEPE.CCOSTO = KMCOM.CCOSTO
					WHERE NIEPE.CNSPAGO = ''' 
				+ @CNSPAGO + 
				'''
					GROUP BY NIEPE.NUMDOC, NIEPE.NOMBRE_EMPLEADO, NEMP.TIPO_DOC, NEMP.DOCIDEMPLEADO, NIEPE.NOMBRE_AREA, NIEPE.NOMBRE_CCOSTO, NIEPE.BASICO, NIEPED.CODCONCEPTO, 
						NIEPED.TOTAL_NOMINA, NIEPE.IDAREA, NIEPE.CCOSTO,NCON.DESCRIPCION,TER.NIT;
						'

			INSERT INTO KEXCEL_FILL (CNSEXCEL, NOMBRE, BORRAR, CONSULTA)
			VALUES (@CNSEXCEL, @CNSPAGO + '.xlsx', 1, @SQL)
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF EXISTS (
				SELECT 1
				FROM @TBLERRORES
				)
		BEGIN
			SELECT 'KO' OK, @CNSEXCEL CNSEXCEL

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK, @CNSEXCEL CNSEXCEL
	END
END

