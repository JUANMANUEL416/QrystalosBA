				SELECT ERROR = 'La fecha no pueden ser mayor a la fecha y hora actual.' 
				RETURN
			END

			SELECT @FECHA = FECHA FROM HADM WHERE NOADMISION = @NOADMISIONFIL
			IF @FECHA_HORA_NUEVA < @FECHA
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR = 'La fecha y hora nueva no pueden ser menor a la fecha y hora de la Admisión.'
				RETURN
			END
			SET @NVAIDAREA = @NVAFECHA + ' ' + @NVAHORA
		END

		IF @METODO = 'CONTRATO'
		BEGIN 
			IF COALESCE(@NVAIDAREA, '') = '' OR COALESCE(@NVOCCOSTO, '') = ''
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR = 'Debe seleccionar un Tercero y Plan Nuevo.'
				RETURN
			END

			IF NOT EXISTS (SELECT 1 FROM TER  WHERE IDTERCERO = @NVAIDAREA)
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR = 'El Tercero seleccionado no existe, por favor valide.'
				RETURN
			END

			IF NOT EXISTS (SELECT 1 FROM PPT  WHERE IDTERCERO = @NVAIDAREA AND IDPLAN = @NVOCCOSTO)
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR = 'El plan no pertenece al Tercero seleccionado.'
				RETURN
			END
		END

		IF @METODO IN ('NOCOBRABLE', 'COBRABLE', 'CCOSTO', 'CONTRATO', 'ALTO_COSTO', 'CAMBIA_FECHA_HORA')
		BEGIN
			EXEC SPK_AUDITOR_FACT @NOADMISIONFIL,  @NOPRESTAFIL, @PREFIL, @FECFIL, @FECFILFIN, @USUFIL, @CCOSTOFIL, @NVAIDAREA,	@NVOCCOSTO, @METODO, @IDSERVICIO
			SELECT 'OK' OK
			RETURN
		END
		
		IF @METODO = 'CAMBIA_SERVICIO'
		BEGIN
			SELECT 
			@METODO = METODO,
			@NOADMISIONFIL = NOADMISIONFIL,
			@IDSERVICIO = IDSERVICIO,
			@NVOIDSERVICIO = NVOIDSERVICIO

			FROM OPENJSON(@PARAMETROS)
			WITH (
				METODO VARCHAR(50) '$.METODO',
				NOADMISIONFIL VARCHAR(20) '$.NOADMISIONFIL',
				IDSERVICIO VARCHAR(20) '$.IDSERVICIO',
				NVOIDSERVICIO VARCHAR(20) '$.NVOIDSERVICIO'
			)

			EXEC SPK_AUD_CAMBIA_SERVICIO @NOADMISIONFIL, @IDSERVICIO, @NVOIDSERVICIO, @USUARIO

			SELECT 'OK' OK
			RETURN
		END
		RETURN
	END
	IF @METODO = 'FILTRO_HPRE'
	BEGIN
		SELECT @NOADMISION = NOADMISION, @FILTRO = FILTRO
		FROM OPENJSON(@PARAMETROS)
		WITH(	NOADMISION	VARCHAR(20)		'$.NOADMISION', FILTRO	VARCHAR(500)		'$.FILTRO')

		SELECT 'OK'OK
      	SELECT @CMD=' SELECT SUM(HPRE.VALORTOTAL) VRPRESTACIONES ,SUM(HPRE.VALOREXEDENTE) VREXCEDENTE ,SUM(HPRE.VALORCOPAGO) VRCOPAGO
				,SUM(HPRE.VALORPCOMP) VRPCOMP
			FROM   HPRE 
			WHERE  '+IIF(COALESCE(@FILTRO,'')='','NOADMISION='''+@NOADMISION+'''', @FILTRO)  
			PRINT @CMD
			EXEC (@CMD)
		
	END
	IF @METODO = 'RELIQUIDAR'
	BEGIN
		SELECT @NOADMISION = NOADMISION, @NOPRESTACION =NOPRESTACION
		FROM OPENJSON(@PARAMETROS)
		WITH(	NOADMISION	VARCHAR(20)		'$.NOADMISION', NOPRESTACION	VARCHAR(20)		'$.NOPRESTACION')

		IF 'VALIDACION' <> 'VALIDACION'
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'MENSAJE'
		END
	
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				DECLARE CURSOR_HPRE CURSOR FOR
	            SELECT NOPRESTACION, NOITEM FROM HPRED WHERE NOPRESTACION = @NOPRESTACION

	            OPEN CURSOR_HPRE 
				
	            FETCH NEXT FROM CURSOR_HPRE INTO @NOPRESTACION,@NOITEM ;

	            WHILE @@FETCH_STATUS = 0
	            BEGIN
		            EXEC SPK_COPAGOQX_PERU @NOADMISION,@NOPRESTACION,@NOITEM,0		
		            FETCH NEXT FROM CURSOR_HPRE INTO @NOPRESTACION,@NOITEM;
	            END

            CLOSE CURSOR_HPRE 
            DEALLOCATE CURSOR_HPRE    
			END TRY  
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK
		END 
	END
