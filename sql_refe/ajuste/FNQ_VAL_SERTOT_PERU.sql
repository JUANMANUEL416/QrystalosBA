CREATE OR ALTER FUNCTION DBO.FNQ_VAL_SERTOT_PERU(
    @FECHA DATE,
    @IDTERCERO VARCHAR(20),
    @IDPLAN VARCHAR(20),
    @IDSERVICIO VARCHAR(20)
)
RETURNS @Resultado TABLE(
  VALOR_UNITARIO_CON_IGV decimal(14,2)
 ,VALOR_IGV_UNITARIO decimal(14,2)
 ,VALOR_UNITARIO_SIN_IGV decimal(14,2)
)
AS
BEGIN
   DECLARE @VALORUNITCONIGV DECIMAL(14,2) ,@VALORIGVUNIT DECIMAL(14,2)
          ,@VALORUNITSINIGV DECIMAL(14,2)
   SELECT @VALORUNITCONIGV = CONVERT(DECIMAL(14,2),MAX(VLRSERVICIO)) FROM SERTOT
   WHERE  IDTERCERO  = @IDTERCERO AND IDPLAN = @IDPLAN AND IDSERVICIO = @IDSERVICIO
   AND    @FECHA >= FECHAINIFD AND @FECHA <= FECHAFINFD AND @FECHA >= FECHAINI AND @FECHA <= FECHAFIN
   SELECT @VALORIGVUNIT =  @VALORUNITCONIGV - (@VALORUNITCONIGV/1.18)
   SELECT @VALORUNITSINIGV = @VALORUNITCONIGV - @VALORIGVUNIT
   INSERT INTO @Resultado(VALOR_UNITARIO_CON_IGV ,VALOR_IGV_UNITARIO,VALOR_UNITARIO_SIN_IGV)
   SELECT coalesce(@VALORUNITCONIGV,0) ,COALESCE(@VALORIGVUNIT,0) ,COALESCE(@VALORUNITSINIGV,0)
   RETURN
END

