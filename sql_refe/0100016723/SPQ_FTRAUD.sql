CREATE OR ALTER PROCEDURE DBO.SPQ_FTRAUD
@JSON  NVARCHAR(MAX)
WITH   ENCRYPTION
AS
DECLARE  @PARAMETROS	NVARCHAR(MAX),	@MODELO			VARCHAR(100),   @METODO			VARCHAR(100)
DECLARE  @USUARIO		VARCHAR(20),	@FTRAUD_ID		INT,			@N_FACTURA		VARCHAR(16)
DECLARE	 @FECHA			DATETIME,		@USUARIO_AUD	VARCHAR(12),	@OBSERVACION	VARCHAR(8000)
DECLARE	 @ESTADO		INT,			@OBSRESPTA		VARCHAR(512),	@USURESPTA		VARCHAR(20)
DECLARE  @APRUEBA		VARCHAR(2),		@USUAPRUEBA		VARCHAR(20),	@MOTIVO_RECHAZO	VARCHAR(8000)
DECLARE  @TBLERRORES TABLE (ERROR VARCHAR(MAX))
BEGIN
	SELECT @MODELO = MODELO , @METODO = METODO , @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)
	
	-- OBTENER NOTAS DE AUDITORIA
	IF @METODO = 'GET_FTRAUD'
	BEGIN
		SELECT 'OK' OK

		SELECT * FROM FTRAUD WHERE N_FACTURA = JSON_VALUE(@PARAMETROS, '$.N_FACTURA')
		ORDER BY FTRAUD_ID DESC
		RETURN
	END

	-- CREAR NUEVA NOTA DE AUDITORIA (ESTADO 0)
	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT  @FTRAUD_ID = COALESCE(FTRAUD_ID,0), @N_FACTURA = N_FACTURA, @OBSERVACION = OBSERVACION, @USUARIO_AUD = USUARIO_AUD
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				FTRAUD_ID	INT			'$.FTRAUD_ID',		N_FACTURA  VARCHAR(16)	'$.N_FACTURA',	
				OBSERVACION	VARCHAR(8000)	'$.OBSERVACION',	USUARIO_AUD	VARCHAR(12)	'$.USUARIO_AUD'
			)

			IF @FTRAUD_ID = 0
			BEGIN			
				INSERT INTO FTRAUD (N_FACTURA, FECHA, USUARIO_AUD, OBSERVACION, ESTADO)
				SELECT @N_FACTURA, GETDATE(), @USUARIO_AUD, @OBSERVACION, 0
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END

	-- RESPONDER/CONTESTAR NOTA (ESTADO 0 -> 1)
	IF @METODO = 'RESPONDER'
	BEGIN
		BEGIN TRY
			SELECT  @FTRAUD_ID = FTRAUD_ID, @N_FACTURA = N_FACTURA, @OBSRESPTA = OBSRESPTA, @USURESPTA = USURESPTA
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				FTRAUD_ID	INT				'$.FTRAUD_ID',		N_FACTURA	VARCHAR(16)		'$.N_FACTURA',	
				OBSRESPTA	VARCHAR(512)	'$.OBSRESPTA',		USURESPTA	VARCHAR(20)		'$.USURESPTA'
			)

			-- Validar que el usuario no sea el mismo que creó la nota
			IF EXISTS (SELECT 1 FROM FTRAUD WHERE FTRAUD_ID = @FTRAUD_ID AND USUARIO_AUD = @USURESPTA)
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) SELECT 'No puede contestar una nota que usted mismo creó'
			END

			-- Validar que la nota esté en estado 0
			IF NOT EXISTS (SELECT 1 FROM FTRAUD WHERE FTRAUD_ID = @FTRAUD_ID AND ESTADO = 0)
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) SELECT 'La nota no está en estado pendiente de respuesta'
			END

			IF(SELECT COUNT(*) FROM @TBLERRORES) > 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END

			UPDATE FTRAUD 
			SET OBSRESPTA = @OBSRESPTA, 
				USUARIO = @USURESPTA,
            F_RESPTA= DBO.FNK_GETDATE(),
				ESTADO = 1
			WHERE FTRAUD_ID = @FTRAUD_ID AND N_FACTURA = @N_FACTURA

		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END

	-- APROBAR/RECHAZAR NOTA (ESTADO 1 -> 2)
	IF @METODO = 'APROBAR'
	BEGIN
		BEGIN TRY
			SELECT  @FTRAUD_ID = FTRAUD_ID, @N_FACTURA = N_FACTURA, @APRUEBA = APRUEBA, 
					@USUAPRUEBA = USUAPRUEBA, @MOTIVO_RECHAZO = COALESCE(MOTIVO_RECHAZO, '')
			FROM	OPENJSON (@PARAMETROS) 
			WITH	(
				FTRAUD_ID		INT				'$.FTRAUD_ID',		N_FACTURA		VARCHAR(16)		'$.N_FACTURA',	
				APRUEBA			VARCHAR(2)		'$.APRUEBA',		USUAPRUEBA		VARCHAR(20)		'$.USUAPRUEBA',
				MOTIVO_RECHAZO	VARCHAR(8000)	'$.MOTIVO_RECHAZO'
			)

			-- Validar que el usuario no sea el mismo que contestó la nota
			IF EXISTS (SELECT 1 FROM FTRAUD WHERE FTRAUD_ID = @FTRAUD_ID AND USURESPTA = @USUAPRUEBA)
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) SELECT 'No puede aprobar una nota que usted mismo contestó'
			END

			-- Validar que la nota esté en estado 1
			IF NOT EXISTS (SELECT 1 FROM FTRAUD WHERE FTRAUD_ID = @FTRAUD_ID AND ESTADO = 1)
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) SELECT 'La nota no está en estado pendiente de aprobación'
			END

			IF(SELECT COUNT(*) FROM @TBLERRORES) > 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END

			-- Actualizar nota a estado 2 (aprobada/rechazada)
			UPDATE FTRAUD 
			SET APRUEBA = @APRUEBA, 
				USUAPRUEBA = @USUAPRUEBA, 
            F_APRUEBA=DBO.FNK_GETDATE(),
				ESTADO = 2
			WHERE FTRAUD_ID = @FTRAUD_ID AND N_FACTURA = @N_FACTURA

			-- Si fue rechazada, crear nueva nota con el motivo
			IF @APRUEBA = 'NO' AND LEN(@MOTIVO_RECHAZO) > 0
			BEGIN
				INSERT INTO FTRAUD (N_FACTURA, FECHA, USUARIO_AUD, OBSERVACION, ESTADO)
				SELECT @N_FACTURA,DBO.FNK_GETDATE(), @USUAPRUEBA, @MOTIVO_RECHAZO, 0
			END

		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
	END

	-- INFORME DE NOTAS DE AUDITORIA
	IF @METODO = 'INFORME'
	BEGIN
		DECLARE @FECHA_INI DATE, @FECHA_FIN DATE, @FILTRO_USUARIO_AUD VARCHAR(20), @FILTRO_USURESPTA VARCHAR(20)
		DECLARE @FILTRO_ESTADO INT, @FILTRO_CON_RESPUESTA VARCHAR(2), @FILTRO_APRUEBA VARCHAR(2)
		DECLARE @SQL NVARCHAR(MAX)

		SELECT  @FECHA_INI = FECHA_INI, @FECHA_FIN = FECHA_FIN, 
				@FILTRO_USUARIO_AUD = USUARIO_AUD, @FILTRO_USURESPTA = USURESPTA,
				@FILTRO_ESTADO = ESTADO, @FILTRO_CON_RESPUESTA = CON_RESPUESTA, @FILTRO_APRUEBA = APRUEBA
		FROM	OPENJSON (@PARAMETROS) 
		WITH	(
			FECHA_INI		DATE			'$.FECHA_INI',
			FECHA_FIN		DATE			'$.FECHA_FIN',
			USUARIO_AUD		VARCHAR(20)		'$.USUARIO_AUD',
			USURESPTA		VARCHAR(20)		'$.USURESPTA',
			ESTADO			INT				'$.ESTADO',
			CON_RESPUESTA	VARCHAR(2)		'$.CON_RESPUESTA',
			APRUEBA			VARCHAR(2)		'$.APRUEBA'
		)

		SET @SQL = 'SELECT FTRAUD.N_FACTURA,DBO.FNK_FECHA_DDMMAA(FTRAUD.FECHA)FECHA,USUARIO_AUD,A.NOMBRE AUDITOR,FTRAUD.OBSERVACION,FTRAUD.ESTADO,OBSRESPTA,
                  FTRAUD.USUARIO FACTURADOR,B.NOMBRE,DBO.FNK_FECHA_DDMMAA(FTRAUD.F_RESPTA)F_RESPTA,APRUEBA,USUAPRUEBA,C.NOMBRE AS NAUDITOR,DBO.FNK_FECHA_DDMMAA(FTRAUD.F_APRUEBA)F_RESPTA,TER.NIT, TER.RAZONSOCIAL NOMBRECLIENTE
					FROM FTRAUD INNER JOIN FTR ON FTRAUD.N_FACTURA=FTR.N_FACTURA
                           INNER JOIN TER ON FTR.IDTERCERO=TER.IDTERCERO
                           LEFT JOIN USUSU A ON FTRAUD.USUARIO_AUD=A.USUARIO
                           LEFT JOIN USUSU B ON FTRAUD.USUARIO=B.USUARIO
                           LEFT JOIN USUSU C ON FTRAUD.USUAPRUEBA=C.USUARIO
					WHERE 1=1 '

		-- Filtro por fecha
		IF @FECHA_INI IS NOT NULL
			SET @SQL = @SQL + ' AND CONVERT(DATE, FTRAUD.FECHA) >= ''' + CONVERT(VARCHAR, @FECHA_INI, 23) + ''''
		
		IF @FECHA_FIN IS NOT NULL
			SET @SQL = @SQL + ' AND CONVERT(DATE, FTRAUD.FECHA) <= ''' + CONVERT(VARCHAR, @FECHA_FIN, 23) + ''''

		-- Filtro por usuario que crea
		IF @FILTRO_USUARIO_AUD IS NOT NULL AND LEN(@FILTRO_USUARIO_AUD) > 0
			SET @SQL = @SQL + ' AND FTRAUD.USUARIO_AUD = ''' + @FILTRO_USUARIO_AUD + ''''

		-- Filtro por usuario que responde
		IF @FILTRO_USURESPTA IS NOT NULL AND LEN(@FILTRO_USURESPTA) > 0
			SET @SQL = @SQL + ' AND FTRAUD.USURESPTA = ''' + @FILTRO_USURESPTA + ''''

		-- Filtro por estado
		IF @FILTRO_ESTADO IS NOT NULL
			SET @SQL = @SQL + ' AND FTRAUD.ESTADO = ' + CAST(@FILTRO_ESTADO AS VARCHAR)

		-- Filtro con/sin respuesta
		IF @FILTRO_CON_RESPUESTA = 'SI'
			SET @SQL = @SQL + ' AND FTRAUD.OBSRESPTA IS NOT NULL AND LEN(FTRAUD.OBSRESPTA) > 0'
		ELSE IF @FILTRO_CON_RESPUESTA = 'NO'
			SET @SQL = @SQL + ' AND (FTRAUD.OBSRESPTA IS NULL OR LEN(FTRAUD.OBSRESPTA) = 0)'

		-- Filtro por aprobación
		IF @FILTRO_APRUEBA IS NOT NULL AND LEN(@FILTRO_APRUEBA) > 0
			SET @SQL = @SQL + ' AND FTRAUD.APRUEBA = ''' + @FILTRO_APRUEBA + ''''

		SET @SQL = @SQL + ' ORDER BY FTRAUD.FECHA DESC'

		SELECT 'OK' OK
		EXEC sp_executesql @SQL
	END
END
