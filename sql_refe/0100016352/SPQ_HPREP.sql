CREATE OR ALTER PROCEDURE DBO.SPQ_HPREP
	@JSON  NVARCHAR(MAX)
WITH ENCRYPTION
AS
DECLARE @PARAMETROS         NVARCHAR(MAX)	,@MODELO			VARCHAR(100)    ,@METODO        VARCHAR(100)	,@USUARIO       VARCHAR(12)
	   ,@GRUPO				VARCHAR(8)		,@SYS_COMPUTERNAME	VARCHAR(254)    ,@IDSEDE          VARCHAR(5)		,@A             INT
       ,@DATOS              VARCHAR(MAX)										,@AUX			NVARCHAR(MAX)	,@CLASE			VARCHAR(20)
	   ,@COMPANIA			VARCHAR(2)		,@IDMEDICO			VARCHAR(20)		,@IDBODEGA		VARCHAR(5)
	   ,@NOADMISION			VARCHAR(20)		,@IDKPAGE			INT				,@ANOMES		VARCHAR(6)		,@IDPLAN_NUEVO VARCHAR(20)
DECLARE @NOPRESTACION		VARCHAR(20)		,@NOITEM	SMALLINT ,@IDSERVICIO	VARCHAR(20), @CNSRPDX  VARCHAR(20)  , @CREA_HADMSER INT  , @IDAFILIADO VARCHAR(20)
DECLARE @NVOCONSEC VARCHAR(20), @NOPRESUPUESTO VARCHAR(20), @CONSECUTIVOHCA VARCHAR(20), @ITEMRED INT, @CANTIDAD INT, @IDTERCERO VARCHAR(20), @IDPLAN VARCHAR(20)
	,@VALORCOPAGO DECIMAL(14,2), @VALOR DECIMAL(14,2),@VALOREXCEDENTE DECIMAL(14,2), @FECHA DATETIME, @IGV DECIMAL(14,2),@SQL VARCHAR(MAX)	,@COPAGOVARIABLE DECIMAL(14,2)
DECLARE @ANIO VARCHAR(4), @MES VARCHAR(2), @DIA  VARCHAR(2), @FECHAFINAL DATETIME, @DESCSERVICIO VARCHAR(200), @IDSERVICIOMAX NVARCHAR(MAX), @FFINAL DATE
   ,@NOPRESUPUESTOS NVARCHAR(MAX), @FECHA_CARTA VARCHAR(10) , @COD_CARTA VARCHAR(50), @OBSERVACION VARCHAR(500) , @ITEM INT, @NOPRESUPUESTO_NUEVO VARCHAR(20)
   , @NO_ITEM INT, @PROCESO VARCHAR(20), @REQ_CARTA BIT, @PERSONA_APRUEBA VARCHAR(500), @PREFIJO VARCHAR(20), @IDSERVICIO_REF VARCHAR(20), @TIPO_CARTA INT
   , @ID_CITSITEDS INT, @COPAGOVARIABLECONSULTA DECIMAL(14,2), @COPAGOCONSULTA DECIMAL(14,2), @ITEM_DISPTURD_HORA INT, @CONSECUTIVOCIT VARCHAR(20)
   , @ELIMINADO BIT, @COPAGOVARIABLE_NUEVO DECIMAL(14,2), @EDITAR_COPAGOVARIABLE BIT, @CNSHADMSER VARCHAR(20), @PROCEDENCIA VARCHAR(20), @ID INT
   , @IDAREA VARCHAR(20), @CCOSTO VARCHAR(20), @CANTIDAD_NUEVO INT, @EDITAR_CANTIDAD BIT, @FECHA_CLON VARCHAR(10), @HORA_CLON VARCHAR(6), @COBERTURADOS BIT, @REG_CARTA BIT
   , @IDSERVICIO_PAPA VARCHAR(20), @IDSERVICIO_HIJO VARCHAR(20), @EDITA_MASIVO_SITEDS BIT, @ID_CITSITEDS_ANTERIOR INT, @WHERE_DATA NVARCHAR(MAX), @sqlCommand NVARCHAR(MAX)
BEGIN
	SET LANGUAGE Spanish; 
	SET DATEFORMAT dmy
	SELECT @A = ISJSON(@JSON)
	IF @A = 0 
	BEGIN
		RAISERROR('Json: Formato Erroneo',16,1)
		RETURN
	END 
	SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS , @USUARIO = USUARIO
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)     AS JSON
	)

	--DEFINICION DE TABLA DE ERRORES
	DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200));
	-- TOMA DEL GRUPO, SYS_COMPUTERNAME, SEDE   DE ACUERDO AL USUARIO
	PRINT 'USUARIO:'+@USUARIO
	SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO) FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @IDSEDE = IDSEDE, @COMPANIA=COMPANIA, @IDBODEGA = IDBODEGA FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
	SELECT @IDMEDICO = IDMEDICO FROM USUSU WHERE USUARIO=@USUARIO
	IF COALESCE(@IDSEDE,'') = '' SELECT @IDSEDE = '01'

	/*
   HPREP.ESTADO = 0    ||  PENDIENTE
   HPREP.ESTADO = 1    ||  APROBADO DE ASEGURADORA
   HPREP.ESTADO = 1    ||  APROBADO DE PACIENTE
   HPREP.ESTADO = 3    ||  RECHAZADO POR ASEGURADORA
   HPREP.ESTADO = 4    ||  RECHAZADO POR PACIENTE
   HPREP.ESTADO = 5    ||  PRESUPUESTO UNIDO
   */
	IF @METODO = 'ACEPTAPREADM'
	BEGIN
		SELECT @NOADMISION = JSON_VALUE(@PARAMETROS, '$.NOADMISION')
		SELECT @NOPRESUPUESTO = JSON_VALUE(@PARAMETROS, '$.NOPRESUPUESTO')
		SELECT @METODO = JSON_VALUE(@PARAMETROS, '$.PROCEDENCIA')
		SELECT @OBSERVACION = JSON_VALUE(@PARAMETROS, '$.OBSERVACION')
		SELECT @PERSONA_APRUEBA = JSON_VALUE(@PARAMETROS, '$.PERSONA_APRUEBA')

      IF EXISTS (SELECT 1 FROM HPREPD
                  INNER JOIN SER ON HPREPD.IDSERVICIO = SER.IDSERVICIO
                  WHERE NOPRESUPUESTO = @NOPRESUPUESTO AND SER.PREFIJO = DBO.FNK_VALORVARIABLE('PREFIJOMEDICAMENTOS'))
         AND NOT EXISTS (SELECT 1 FROM HPREPD
                        INNER JOIN PLN ON HPREPD.IDSERVICIO = PLN.IDSERVICIO
                        WHERE NOPRESUPUESTO = @NOPRESUPUESTO ) 
         AND 1 = 2 /* SOLO DEBEN DE SER PARA LOS QUE NO SON POR REFORMULACIONES */
      BEGIN
         SELECT 'KO' OK
			SELECT ERROR = 'El presupuesto tiene Medicamentos, y requiere tener un servicio asociado a un Plan.'
			RETURN
      END

		IF (SELECT COUNT(1) FROM HADM WHERE NOADMISION=@NOADMISION)<=0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR = 'Admision no encontrada, noadmision='+COALESCE(@NOADMISION,'')
			RETURN
		END
		SELECT 'OK' OK, COALESCE(IDKPAGE,0)IDKPAGE, COALESCE(VALORCOPAGO,0) VALORCOPAGO FROM HPREP WHERE NOPRESUPUESTO = @NOPRESUPUESTO

      IF EXISTS (SELECT 1 FROM HPREP, HCA WHERE NOPRESUPUESTO =  @NOPRESUPUESTO AND HCA.CONSECUTIVO = HPREP.CONSECUTIVOHCA AND HCA.PROCEDENCIA <> 'QX')
      BEGIN
         SELECT  @CONSECUTIVOHCA =  CONSECUTIVOHCA FROM HPREP WHERE NOPRESUPUESTO =  @NOPRESUPUESTO
         UPDATE HCA SET PROCEDENCIA = 'QX' WHERE CONSECUTIVO = @CONSECUTIVOHCA
      END
      UPDATE HCATD SET APLICADA = 0 WHERE CONSECUTIVO = @CONSECUTIVOHCA
		IF @METODO='ASE'
		BEGIN
			UPDATE HADM SET ESTADO_PRE=1 WHERE NOADMISION=@NOADMISION
			UPDATE HPREP SET ESTADO=1, USUARIOPROCESA=@USUARIO WHERE NOPRESUPUESTO=@NOPRESUPUESTO
			INSERT INTO HEVEN (NOADMISION, EVENTO, USUARIO, SYS_COMPUTERNAME, CONSECUTIVOGEN, FECHA, CLASE)
			SELECT @NOADMISION, 'ACEPTA ASEGURADORA',@USUARIO, @SYS_COMPUTERNAME, 'ADMISIONES', GETDATE(), 'PREADMISION'
		END
		IF @METODO='PTE'
		BEGIN
         SELECT  @ID_CITSITEDS = ID_CITSITEDS, @IDAFILIADO = IDAFILIADO FROM HADM WHERE NOADMISION = @NOADMISION
         SELECT @CONSECUTIVOHCA = CONSECUTIVOHCA, @REG_CARTA = COALESCE(REG_CARTA,0) FROM HPREP WHERE NOPRESUPUESTO = @NOPRESUPUESTO
         IF EXISTS (SELECT 1 FROM HPREP WHERE NOPRESUPUESTO = @NOPRESUPUESTO AND PROCEDENCIA  = 'VISITA_ENF')
         BEGIN
            INSERT INTO HADMACTIV (NOADMISION, IDSERVICIO, IDAFILIADO, TIPO_USUARIO, ESTADO, FECHAGEN, USUARIO, PROCEDENCIA, TIPO, CONSECUTIVOHCA)
            SELECT @NOADMISION, HPREPD.IDSERVICIO, @IDAFILIADO, 'Enfermera', 'Por Agendar', DBO.FNK_GETDATE(), @USUARIO,NULL ,'Consulta', @CONSECUTIVOHCA
            FROM HPREPD 
            INNER JOIN SER ON HPREPD.IDSERVICIO = SER.IDSERVICIO
            WHERE NOPRESUPUESTO = @NOPRESUPUESTO AND SER.PREFIJO IN ('ASIS', 'CONS')
            UPDATE HPREP SET ESTADO=2, USUARIOPROCESA=@USUARIO, PERSONA_APRUEBA = @PERSONA_APRUEBA WHERE NOPRESUPUESTO=@NOPRESUPUESTO
            RETURN
         END
         IF @REG_CARTA = 1
         BEGIN
            UPDATE HPREP SET ESTADO=2, USUARIOPROCESA=@USUARIO, PERSONA_APRUEBA = @PERSONA_APRUEBA WHERE NOPRESUPUESTO=@NOPRESUPUESTO
            RETURN
         END

         IF EXISTS (SELECT  1 FROM HPREPD WHERE HPREPD.IDSERVICIO IN ('AENF-000004', 'AENF-000005', 'AENF-000006') AND HPREPD.NOPRESUPUESTO = @NOPRESUPUESTO)
         AND EXISTS (SELECT 1 FROM HPREP,HCA WHERE HPREP.NOPRESUPUESTO = @NOPRESUPUESTO AND HPREP.CONSECUTIVOHCA = HCA.CONSECUTIVO AND HCA.CLASEPLANTILLA = DBO.FNK_VALORVARIABLE('HADM_ENF_MPL_VALORA') )
         BEGIN
            ;WITH N AS
               (
                   SELECT TOP (1000)
                          ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS N
                   FROM sys.all_objects
               )
               INSERT INTO HADMACTIV (NOADMISION, IDSERVICIO, IDAFILIADO, TIPO_USUARIO, ESTADO, FECHAGEN, USUARIO, PROCEDENCIA, TIPO, CONSECUTIVOHCA)
               SELECT @NOADMISION, HPREPD.IDSERVICIO, @IDAFILIADO, 'Enfermera', 'Por Agendar', DBO.FNK_GETDATE(), @USUARIO,NULL , 'Consulta', @CONSECUTIVOHCA
               FROM HPREPD
               INNER JOIN SER
                   ON HPREPD.IDSERVICIO = SER.IDSERVICIO
               INNER JOIN TGEN
                   ON TGEN.CODIGO = HPREPD.IDSERVICIO
                  AND TGEN.TABLA = 'CHERIDA'
                  AND TGEN.CAMPO = '12_TOT_HER'
               INNER JOIN N
                   ON N.N <= CAST(TGEN.VALOR3 AS INT)
               WHERE HPREPD.NOPRESUPUESTO = @NOPRESUPUESTO
                 AND SER.PREFIJO IN ('ASIS', 'CONS')
                 AND SER.IDSERVICIO IN ('AENF-000004', 'AENF-000005', 'AENF-000006');

         END

         PRINT 'POR PTE'
         SELECT @CREA_HADMSER = 0
			INSERT INTO HEVEN (NOADMISION, EVENTO, USUARIO, SYS_COMPUTERNAME, CONSECUTIVOGEN, FECHA, CLASE)
			SELECT @NOADMISION, 'ACEPTA PACIENTE',@USUARIO, @SYS_COMPUTERNAME, 'ADMISIONES', DBO.FNK_GETDATE(), 'PREADMISION'
			IF (SELECT CLASEING FROM HADM WHERE NOADMISION=@NOADMISION) IN ('C')
			BEGIN
				UPDATE HADM SET ESTADO_PRE=2, CLASEING='A' WHERE NOADMISION=@NOADMISION				
            IF EXISTS (SELECT  1 FROM HPREP WHERE NOPRESUPUESTO = @NOPRESUPUESTO AND COALESCE(UNIDO,0) = 1)
            BEGIN
               DECLARE CUR_PROCESA_UNIDO CURSOR FOR
				   SELECT  HPREPD.CONSECUTIVOHCA_UNIDO, HCA.ITEMRED FROM HPREPD
                  INNER JOIN HCA ON HPREPD.CONSECUTIVOHCA_UNIDO = HCA.CONSECUTIVO
               WHERE NOPRESUPUESTO = @NOPRESUPUESTO 
               GROUP BY HPREPD.CONSECUTIVOHCA_UNIDO, HCA.ITEMRED 
				   OPEN CUR_PROCESA_UNIDO
				   FETCH NEXT FROM CUR_PROCESA_UNIDO INTO @CONSECUTIVOHCA, @ITEMRED

				   WHILE @@FETCH_STATUS = 0
				   BEGIN
                  PRINT 'ACAAAAAAAAAAAAAAAAAAA====='
					   --EXEC SPK_NHC_CONFIRMAR_OMED_HD @CONSECUTIVOHCA ,@ITEMRED ,NULL ,@IDSEDE ,@USUARIO ,@SYS_COMPUTERNAME, NULL,'HPREP'	
                  EXEC SPK_NHC_CONFIRMAR_OMED_HD_HPREP @CONSECUTIVOHCA ,@ITEMRED ,NULL ,@IDSEDE ,@USUARIO ,@SYS_COMPUTERNAME, NULL,'HPREP', 'PRIMERA'	, 'PHD', 1

                  PRINT 'SALLLLLLLLEEEEEEEEEEEEEEEEEEEEEEEEEEEEE'
					   FETCH NEXT FROM CUR_PROCESA_UNIDO INTO @CONSECUTIVOHCA, @ITEMRED
				   END
				   CLOSE CUR_PROCESA_UNIDO
				   DEALLOCATE CUR_PROCESA_UNIDO
            END
            ELSE
            BEGIN
               SELECT @CONSECUTIVOHCA = HPREP.CONSECUTIVOHCA FROM HPREP WHERE NOPRESUPUESTO = @NOPRESUPUESTO
               
				   DECLARE CUR_PROCESA CURSOR FOR
				   SELECT CONSECUTIVO, ITEMRED FROM HCA WHERE NOADMISION=@NOADMISION AND PROCEDENCIA='QX' AND COALESCE(ANULADA,0)=0 
               AND HCA.CONSECUTIVO = @CONSECUTIVOHCA
				   OPEN CUR_PROCESA
				   FETCH NEXT FROM CUR_PROCESA INTO @CONSECUTIVOHCA, @ITEMRED

				   WHILE @@FETCH_STATUS = 0
				   BEGIN
                  PRINT 'ACAAAAAAAAAAAAAAAAAAA ****'
					   --EXEC SPK_NHC_CONFIRMAR_OMED_HD @CONSECUTIVOHCA ,@ITEMRED ,NULL ,@IDSEDE ,@USUARIO ,@SYS_COMPUTERNAME, NULL,'HPREP'	
                  EXEC SPK_NHC_CONFIRMAR_OMED_HD_HPREP @CONSECUTIVOHCA ,@ITEMRED ,NULL ,@IDSEDE ,@USUARIO ,@SYS_COMPUTERNAME, NULL,'HPREP', 'PRIMERA'		, 'PHD', 0

                  PRINT 'SALLLLLLLLEEEEEEEEEEEEEEEEEEEEEEEEEEEEE'
					   FETCH NEXT FROM CUR_PROCESA INTO @CONSECUTIVOHCA, @ITEMRED
				   END
				   CLOSE CUR_PROCESA
				   DEALLOCATE CUR_PROCESA
            END
            SELECT @CREA_HADMSER = 1

			END
         ELSE
         BEGIN
            IF EXISTS (SELECT  1 FROM HPREP WHERE NOPRESUPUESTO = @NOPRESUPUESTO AND COALESCE(UNIDO,0) = 1)
            BEGIN
               PRINT 'GENERA OM DE HPREP ===========>'

               DECLARE CUR_PROCESA_2_UNIDO CURSOR FOR
				   SELECT  HPREPD.CONSECUTIVOHCA_UNIDO, HCA.ITEMRED FROM HPREPD
                  INNER JOIN HCA ON HPREPD.CONSECUTIVOHCA_UNIDO = HCA.CONSECUTIVO
               WHERE NOPRESUPUESTO = @NOPRESUPUESTO 
               GROUP BY HPREPD.CONSECUTIVOHCA_UNIDO, HCA.ITEMRED 
				   OPEN CUR_PROCESA_2_UNIDO
				   FETCH NEXT FROM CUR_PROCESA_2_UNIDO INTO @CONSECUTIVOHCA, @ITEMRED

				   WHILE @@FETCH_STATUS = 0
				   BEGIN
                  PRINT 'ACAAAAAAAAAAAAAAAAAAA ////////'
					   EXEC SPK_NHC_CONFIRMAR_OMED_HD_HPREP @CONSECUTIVOHCA ,@ITEMRED ,NULL ,@IDSEDE ,@USUARIO ,@SYS_COMPUTERNAME, NULL,'HPREP', 'SEGUNDA'	, 'PHD', 1
				
					   FETCH NEXT FROM CUR_PROCESA_2_UNIDO INTO @CONSECUTIVOHCA, @ITEMRED
				   END
				   CLOSE CUR_PROCESA_2_UNIDO
				   DEALLOCATE CUR_PROCESA_2_UNIDO
            END
            ELSE
            BEGIN
               SELECT @CONSECUTIVOHCA = HPREP.CONSECUTIVOHCA FROM HPREP WHERE NOPRESUPUESTO = @NOPRESUPUESTO

               DECLARE CUR_PROCESA_2 CURSOR FOR
				   SELECT CONSECUTIVO, ITEMRED FROM HCA WHERE NOADMISION=@NOADMISION AND PROCEDENCIA='QX' AND COALESCE(ANULADA,0)=0 AND HCA.CONSECUTIVO = @CONSECUTIVOHCA
				   OPEN CUR_PROCESA_2
				   FETCH NEXT FROM CUR_PROCESA_2 INTO @CONSECUTIVOHCA, @ITEMRED

				   WHILE @@FETCH_STATUS = 0
				   BEGIN
                  PRINT 'ACAAAAAAAAAAAAAAAAAAA .-.-.-.-.-'

					   EXEC SPK_NHC_CONFIRMAR_OMED_HD_HPREP @CONSECUTIVOHCA ,@ITEMRED ,NULL ,@IDSEDE ,@USUARIO ,@SYS_COMPUTERNAME, NULL,'HPREP', 'SEGUNDA'	, 'PHD',0
                  PRINT 'sale de ACAAAAAAAAAAAAAAAAAAA .-.-.-.-.-'
				
					   FETCH NEXT FROM CUR_PROCESA_2 INTO @CONSECUTIVOHCA, @ITEMRED
				   END
				   CLOSE CUR_PROCESA_2
				   DEALLOCATE CUR_PROCESA_2

            END
         END

         PRINT 'VA POR HADMSER =============='
			UPDATE HPREP SET ESTADO=2, USUARIOPROCESA=@USUARIO, PERSONA_APRUEBA = @PERSONA_APRUEBA WHERE NOPRESUPUESTO=@NOPRESUPUESTO

         IF EXISTS (SELECT 1 FROM  HADM WHERE NOADMISION = @NOADMISION)
         BEGIN
            SET @ITEM = 1 + ISNULL((SELECT MAX(ITEM) FROM HADMNOT WHERE NOADMISION = @NOADMISION), 0)

            INSERT INTO HADMNOT(NOADMISION, ITEM, FECHA, OBS, USUARIO, CLASE,ESTADO,ITEMREF, CODPREFIJO, IDMOTIVO,CANTIDAD, RESPONSABLE
                                 ,VALORXGLOSAR, VALORXFACTURAR, IDSERVICIO,VIGENTE, NOPRESUPUESTO)
            SELECT @NOADMISION, @ITEM, DBO.FNK_GETDATE(),@OBSERVACION, @USUARIO,'HPREP','APROBADO',0,'','',0,@USUARIO,0,0,'',1, @NOPRESUPUESTO
         END

         IF EXISTS (SELECT 1 FROM HPREP WHERE NOPRESUPUESTO = @NOPRESUPUESTO AND COALESCE(UNIDO,0) = 0)
         BEGIN
            SELECT @CONSECUTIVOHCA = CONSECUTIVOHCA FROM HPREP WHERE NOPRESUPUESTO = @NOPRESUPUESTO
			   SELECT @IDPLAN_NUEVO = HCAD.MEMO FROM HCAD 
			   INNER JOIN HCA ON HCAD.CONSECUTIVO = HCA.CONSECUTIVO
			   WHERE HCA.CLASEPLANTILLA = DBO.FNK_VALORVARIABLE('MPL_EVALU_PRIMERA') AND HCA.CONSECUTIVO = @CONSECUTIVOHCA AND HCAD.SECUENCIA = 6000
         END
         IF EXISTS (SELECT 1 FROM HPREP WHERE NOPRESUPUESTO = @NOPRESUPUESTO AND COALESCE(UNIDO,0) = 1)
         BEGIN
            --SELECT @CONSECUTIVOHCA = CONSECUTIVOHCA FROM HPREP WHERE NOPRESUPUESTO = @NOPRESUPUESTO
			   SELECT TOP 1 @IDPLAN_NUEVO = HCAD.MEMO FROM HCAD 
			   INNER JOIN HCA ON HCAD.CONSECUTIVO = HCA.CONSECUTIVO
			   WHERE HCA.CLASEPLANTILLA = DBO.FNK_VALORVARIABLE('MPL_EVALU_PRIMERA') AND HCAD.SECUENCIA = 6000 
            AND HCA.CONSECUTIVO IN (SELECT  CONSECUTIVOHCA FROM HPREP WHERE NOPRESUPUESTO_UNIDO = @NOPRESUPUESTO)
         END
       

			IF EXISTS (SELECT 1 FROM PLN WHERE PLN.IDPLAN = @IDPLAN_NUEVO) AND  COALESCE(@CREA_HADMSER,0) = 1
			BEGIN
				PRINT 'LLEGUE ACA=======>'
				UPDATE HADM SET IDPLAN = @IDPLAN_NUEVO WHERE NOADMISION = @NOADMISION
            UPDATE HPREP SET IDPLAN = @IDPLAN_NUEVO WHERE NOADMISION = @NOADMISION
				SELECT @IDTERCERO = HADM.IDTERCERO , @IDPLAN = HADM.IDPLAN FROM HADM WHERE  NOADMISION = @NOADMISION
				SELECT @FECHA = HPREP.FECHA FROM HPREP WHERE NOPRESUPUESTO = @NOPRESUPUESTO 
				--SELECT @FECHA = '2025-01-03'
      
            IF DAY(@FFINAL) = DAY(EOMONTH(@FFINAL))
            BEGIN
                -- Si FFINAL es el último día del mes: siguiente mes completo
                SET @FECHAFINAL = EOMONTH(@FECHA);
            END
            ELSE
            BEGIN
                -- Si no es último día: mismo día -1 en el mes siguiente
                SET @FECHAFINAL = DATEADD(DAY,-1,DATEADD(MONTH,1,@FECHA));
            END

            --SELECT @IDTERCERO, @IDPLAN
				IF DBO.FNK_VALORVARIABLE('USA_CONF_PAQUETE') = 'SI' AND EXISTS (SELECT 1 FROM PPT WHERE IDTERCERO = @IDTERCERO AND IDPLAN = @IDPLAN AND COALESCE(PAQUETIZADO,0) = 1)
				BEGIN
					PRINT 'USA_CONF_PAQUETE ==================000>'
					IF EXISTS (SELECT 1 FROM PPTSER WHERE IDTERCERO = @IDTERCERO AND IDPLAN = @IDPLAN AND COALESCE(IDSERVICIO,'') <>'')
					BEGIN
                  PRINT 'MIRA PPTSER'
						SELECT @ANOMES = SUBSTRING( REPLACE( CONVERT(DATE,HADM.FECHA),'-',''),1,6), @IDAFILIADO = IDAFILIADO FROM HADM WHERE  NOADMISION = @NOADMISION
                  SELECT @NVOCONSEC = NULL 
                  EXEC SPK_GENCONSECUTIVO '01', '01', '@HADMSER',  @NVOCONSEC OUTPUT  
                  SELECT @NVOCONSEC = '01' +  REPLACE(SPACE(8 - LEN(@NVOCONSEC))+LTRIM(RTRIM(@NVOCONSEC)),SPACE(1),0)

                  INSERT INTO HADMSER_LOG (NOADMISION, IDAFILIADO, IDTERCERO, IDPLAN, PAQ_TIPO_COBRO, FINICIAL, FFINAL, AUTOAMTICO,   ESTADO, FECHA_CREA, CNSHADMSER)
                  SELECT @NOADMISION, @IDAFILIADO, @IDTERCERO, @IDPLAN, PPT.PAQ_TIPO_COBRO, @FECHA, @FECHAFINAL, 1, 'Activo', DBO.FNK_GETDATE(), @NVOCONSEC
                  FROM HADM
                  INNER JOIN PPT ON HADM.IDTERCERO = PPT.IDTERCERO AND HADM.IDPLAN = PPT.IDPLAN
                  WHERE HADM.NOADMISION = @NOADMISION

						INSERT INTO HADMSER (NOADMISION, ANOMES, QMAX, QREALIZADA, IDSERVICIO, ESTADO, OBSERVACION
								, ITEM_PPTSER, TIPO,FINICIAL, FFINAL, TITULO, IDTERCERO, IDPLAN, CNSHADMSER )
						SELECT @NOADMISION, NULL, CANTIDAD, 0, PPTSER.IDSERVICIO, 'Activo', null,PPTSER.ITEM_PPTSER
								, 'PPTSER', CONVERT(DATE,@FECHA), CONVERT(DATE,@FECHAFINAL), PPTSER.DESCRIPCION, @IDTERCERO, @IDPLAN, @NVOCONSEC
						FROM PPTSER
						WHERE IDTERCERO = @IDTERCERO
							AND PPTSER.IDPLAN = @IDPLAN
							AND (PPTSER.FECHAVENCE >= GETDATE() OR COALESCE(PPTSER.FECHAVENCE,'')='')

                  /* INSERTO A HADMACTIV*/
                  IF EXISTS (SELECT 1 FROM HADMACTIV WHERE NOADMISION = @NOADMISION)
                  BEGIN
                     INSERT INTO HADMACTIV (NOADMISION, IDSERVICIO, IDAFILIADO, TIPO_USUARIO, ESTADO, FECHAGEN, USUARIO, TIPO, PROCEDENCIA, QMAX, QREALIZADA,  CNSHADMSER, ITEM_HADMSER, ID_CITSITEDS)
                     SELECT H.NOADMISION, JSON_VALUE(J.value, '$.IDSERVICIO') AS IDSERVICIO, @IDAFILIADO
                        ,COALESCE(
                        (SELECT TOP 1 MED.TIPO_USUARIO 
                        FROM MESS
                        INNER JOIN MED ON MESS.IDEMEDICA = MED.IDEMEDICA
                        WHERE MESS.IDSERVICIO = SER.IDSERVICIO
                        GROUP BY MED.TIPO_USUARIO
                        ORDER BY COUNT(*) DESC),
                        'Medico'
                        ) AS TIPO_USUARIO,
                        'Por Agendar', DBO.FNK_GETDATE(),@USUARIO , 'Consulta', 'TCONTROL', H.QMAX, 0, H.CNSHADMSER, H.ITEM_HADMSER, @ID_CITSITEDS
                     FROM HADMSER H
                        CROSS APPLY OPENJSON(H.IDSERVICIO) J
                        INNER JOIN SER ON SER.IDSERVICIO = JSON_VALUE(J.value, '$.IDSERVICIO')
                     WHERE H.CNSHADMSER = @NVOCONSEC

                     IF EXISTS (SELECT 1 FROM HADMACTIV WHERE NOADMISION = @NOADMISION AND PROCEDENCIA <> 'TCONTROL' AND COALESCE(OBSERVACION,'')<> 'TCONTROL' 
                     AND HADMACTIV.IDSERVICIO IN (SELECT H.IDSERVICIO FROM HADMACTIV H WHERE  H.NOADMISION = @NOADMISION AND H.PROCEDENCIA = 'TCONTROL'))
                     BEGIN
                        DECLARE CURSOR_NOMBRE CURSOR FOR
                     	   SELECT  ITEM, NOADMISION, IDSERVICIO, PROCEDENCIA, CONSECUTIVOCIT, ITEM_DISPTURD_HORA, ID_CITSITEDS FROM HADMACTIV WHERE NOADMISION = @NOADMISION AND PROCEDENCIA <> 'TCONTROL' AND COALESCE(OBSERVACION,'')<> 'TCONTROL' 
                           AND HADMACTIV.IDSERVICIO IN (SELECT H.IDSERVICIO FROM HADMACTIV H WHERE  H.NOADMISION = @NOADMISION AND H.PROCEDENCIA = 'TCONTROL')
                     
                     	   OPEN CURSOR_NOMBRE 
                     				
