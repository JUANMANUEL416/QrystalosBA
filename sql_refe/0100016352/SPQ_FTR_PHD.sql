							VALOREXCEDENTE,
							(COALESCE(CANTIDAD, 0) * COALESCE(VALOR, 0))
								- COALESCE(VALORCOPAGO, 0)
								- COALESCE(VALORPCOMP, 0)
						),
						NOPRESTACION_PAQ = @NOPRESTACION_PAQ,
						NOITEM_PAQ = @NOITEM_PAQ,
						PAQUETE = 1,
						VALOREXCEDENTE = 0
					WHERE NOPRESTACION = @NOPRESTACION AND NOITEM = @NOITEM
				END
				COMMIT TRAN PAQ_HPRED
			END TRY
			BEGIN CATCH
				IF @@TRANCOUNT > 0 ROLLBACK TRAN PAQ_HPRED
				SELECT 'KO' OK
				SELECT ERROR = 'Error al actualizar paquete error=' + ERROR_MESSAGE()
				RETURN
			END CATCH

			SELECT 'OK' OK
			RETURN
		END

