					WHEN COALESCE(HACTRAN.VLRFALTA, 0) - COALESCE(HACTRAN.VLRGASTOEXTERNO, 0) <= 0 THEN 0
					ELSE COALESCE(HACTRAN.VLRFALTA, 0) - COALESCE(HACTRAN.VLRGASTOEXTERNO, 0)
				END AS VLRFALTA
				,TGEN_DIS.DESCRIPCION AS DISTRITO
				,AFI.DIRECCION
				,CASE
					WHEN COALESCE(HADM.REVALU, 0) = 0 THEN 'No Requiere'
					WHEN EXISTS (SELECT 1 FROM CIT WITH (NOLOCK) WHERE CIT.NOADMISION = HADM.NOADMISION)
						AND COALESCE(HADM.REVALU, 0) = 1
						AND COALESCE(HADM.ESTADOV, '') = '' THEN 'Asignada'
					WHEN COALESCE(HADM.ESTADOV, '') = 'CUMPLIDAVAL' THEN 'Cumplida'
					WHEN COALESCE(HADM.REVALU, 0) = 1
						AND COALESCE(HADM.ESTADOV, '') = ''
						AND NOT EXISTS (SELECT 1 FROM CIT WITH (NOLOCK) WHERE CIT.NOADMISION = HADM.NOADMISION) THEN 'Sin Asignar'
					ELSE ''
				END AS ESTADO_ATENCION
			FROM HADM WITH (NOLOCK)
			INNER JOIN HTAD WITH (NOLOCK) ON HADM.TIPOADM = HTAD.TIPOADM
			INNER JOIN AFI WITH (NOLOCK) ON HADM.IDAFILIADO = AFI.IDAFILIADO
			INNER JOIN TER WITH (NOLOCK) ON HADM.IDTERCERO = TER.IDTERCERO
			LEFT JOIN TGEN TTIPMEM WITH (NOLOCK)
				ON AFI.TIPOMEMBRESIA = TTIPMEM.CODIGO
			   AND TTIPMEM.TABLA = 'AFI'
			   AND TTIPMEM.CAMPO = 'TIPO_MEMBRESIA'
			LEFT JOIN PLN WITH (NOLOCK) ON HADM.IDPLAN = PLN.IDPLAN
			LEFT JOIN HTRIAGE WITH (NOLOCK) ON HADM.CNSTRIAGE = HTRIAGE.CNSTRIAGE
			LEFT JOIN HHAB WITH (NOLOCK) ON HADM.HABCAMA = HHAB.HABCAMA
			LEFT JOIN HHAB SEC WITH (NOLOCK) ON HHAB.SECTOR = SEC.HABCAMA
			LEFT JOIN TGEN VIA WITH (NOLOCK)
				ON VIA.TABLA = 'GENERAL'
			   AND VIA.CAMPO = 'VIADEINGRESO'
			   AND VIA.CODIGO = HADM.VIAINGRESO
			LEFT JOIN SER WITH (NOLOCK) ON HADM.IDSERVICIOPAQUETE = SER.IDSERVICIO
			LEFT JOIN TER ARL WITH (NOLOCK) ON HADM.IDTERECEROARL = ARL.IDTERCERO
			LEFT JOIN RCONREF WITH (NOLOCK) ON HADM.NOADMISION = RCONREF.NOADMISION
			LEFT JOIN HACTRAN WITH (NOLOCK) ON HACTRAN.CNSHACTRAN = HADM.CNSHACTRAN
			LEFT JOIN TGEN TGEN_DIS WITH (NOLOCK)
				ON TGEN_DIS.TABLA = 'CORREGIMIENTOS'
			   AND TGEN_DIS.CAMPO = AFI.CIUDAD
			   AND TGEN_DIS.CODIGO = AFI.CORREGIMIENTO
			OUTER APPLY (
				SELECT
					SUM(HPRE.VALORCOPAGO) AS COPAGO,
					FCJ.CNSFACJ AS CNSFACJ_FCJ
				FROM HPRE WITH (NOLOCK)
				LEFT JOIN FCJ WITH (NOLOCK)
					ON HADM.NOADMISION = FCJ.NOADMISION
				   AND FCJ.PROCEDENCIA = 'SALUD'
				   AND FCJ.CERRADA = 1
				   AND FCJ.ESTADO = 'P'
				WHERE HPRE.NOADMISION = HADM.NOADMISION
				GROUP BY FCJ.CNSFACJ
			) AS JSON_DET
			OUTER APPLY (
				SELECT (
					SELECT
						FTR.N_FACTURA,
						CASE
							WHEN FTR.ESTADO = 'A' THEN 'ANULADA'
							WHEN FTR.ESTADO = 'L' THEN 'LIBERADA'
							WHEN FTR.ESTADO = 'P' AND FTR.VR_TOTAL = FTR.VLRNOTACR THEN 'ANULADA NOTA CREDITO'
							WHEN FTR.ESTADO = 'P' THEN 'ACTIVA'
							ELSE 'OTRO'
						END AS ESTADO,
						CASE COALESCE(FTR.FACTEP, '')
							WHEN '' THEN 'Sin Notificar'
							WHEN '103' THEN 'Error Valida'
							WHEN '104' THEN 'Rechazado'
							WHEN '104A' THEN 'Rechazado-api'
							WHEN '105' THEN 'Anulada'
							WHEN '108' THEN 'Baja'
							ELSE 'OK'
						END AS FACTEP,
						FTR.VR_TOTAL,
						FTR.VLRNOTACR
					FROM FTR WITH (NOLOCK)
					WHERE HADM.NOADMISION = FTR.NOREFERENCIA
					  AND FTR.PROCEDENCIA = 'SALUD'
					FOR JSON PATH
				) AS VALOR
			) AS FACTURAS_DETALLE
			WHERE HADM.TIPOADM = DBO.FNK_VALORVARIABLE('HTAD_HOSPITA')
			  AND COALESCE(HADM.USACTC, 0) = 2
			  AND (@CLASEING IS NULL OR HADM.CLASEING = @CLASEING)
			  AND (
					@BUSCAR IS NULL
					OR HADM.NOADMISION LIKE CONCAT('%', @BUSCAR, '%')
					OR AFI.NOMBREAFI LIKE CONCAT('%', @BUSCAR, '%')
					OR AFI.DOCIDAFILIADO LIKE CONCAT('%', @BUSCAR, '%')
			  )
			  AND (@SEDE_HADM IS NULL OR HADM.SEDE_HADM = @SEDE_HADM)
			  AND (@IDTERCERO IS NULL OR HADM.IDTERCERO = @IDTERCERO)
			  AND (@IDPLAN IS NULL OR HADM.IDPLAN = @IDPLAN)
			  AND (@F_INI IS NULL OR HADM.FECHA >= @F_INI)
			  AND (@F_FIN IS NULL OR HADM.FECHA < DATEADD(DAY, 1, @F_FIN))
			  AND (
					@INFO_SITEDS IS NULL
					OR (
						@INFO_SITEDS = 'CON_SITEDS'
						AND EXISTS (
							SELECT 1
							FROM CITSITEDS WITH (NOLOCK)
							INNER JOIN CONSSITEDS WITH (NOLOCK) ON CITSITEDS.ID = CONSSITEDS.ID_CITSITEDS
							WHERE CITSITEDS.ID = HADM.ID_CITSITEDS
							  AND (CITSITEDS.NAUTORIZACION IS NOT NULL OR CONSSITEDS.FECHA_AUTORIZA IS NOT NULL)
						)
					)
					OR (
						@INFO_SITEDS = 'SIN_SITEDS'
						AND NOT EXISTS (
							SELECT 1
							FROM CITSITEDS WITH (NOLOCK)
							INNER JOIN CONSSITEDS WITH (NOLOCK) ON CITSITEDS.ID = CONSSITEDS.ID_CITSITEDS
							WHERE CITSITEDS.ID = HADM.ID_CITSITEDS
							  AND (CITSITEDS.NAUTORIZACION IS NOT NULL OR CONSSITEDS.FECHA_AUTORIZA IS NOT NULL)
						)
					)
			  )
			  AND (
					@ESTADO_ATENCION IS NULL
					OR CASE
						WHEN COALESCE(HADM.REVALU, 0) = 0 THEN 'No Requiere'
						WHEN EXISTS (SELECT 1 FROM CIT WITH (NOLOCK) WHERE CIT.NOADMISION = HADM.NOADMISION)
							AND COALESCE(HADM.REVALU, 0) = 1
							AND COALESCE(HADM.ESTADOV, '') = '' THEN 'Asignada'
						WHEN COALESCE(HADM.ESTADOV, '') = 'CUMPLIDAVAL' THEN 'Cumplida'
						WHEN COALESCE(HADM.REVALU, 0) = 1
							AND COALESCE(HADM.ESTADOV, '') = ''
							AND NOT EXISTS (SELECT 1 FROM CIT WITH (NOLOCK) WHERE CIT.NOADMISION = HADM.NOADMISION) THEN 'Sin Asignar'
						ELSE ''
					END = @ESTADO_ATENCION
			  )
			  AND (
					@PRESUPUESTO_PEND = 0
					OR EXISTS (
						SELECT 1
						FROM HPREP WITH (NOLOCK)
						WHERE HPREP.NOADMISION = HADM.NOADMISION
						  AND COALESCE(HPREP.ESTADO, 0) IN (0, 1)
					)
			  )
			  AND (
					@SIN_ATENDER = 0
					OR (COALESCE(HADM.ESTADOV, '') = '' AND COALESCE(HADM.REVALU, 0) = 1)
			  )
			  AND (
					@ESTADO_HADM IS NULL
					OR (@ESTADO_HADM = 'Preadmitido' AND HADM.CLASEING = 'C' AND COALESCE(HADM.CERRADA, 0) = 0)
					OR (@ESTADO_HADM = 'Admitido' AND HADM.CLASEING = 'A' AND COALESCE(HADM.CERRADA, 0) = 0 AND HADM.FACTURABLE = 1)
					OR (@ESTADO_HADM = 'Alta Médica' AND HADM.CLASEING = 'A' AND HADM.CERRADA = 2 AND HADM.FACTURABLE = 1)
					OR (@ESTADO_HADM = 'Alta Enfermeria' AND HADM.CLASEING = 'A' AND HADM.CERRADA = 3 AND HADM.FACTURABLE = 1)
					OR (@ESTADO_HADM = 'Alta Administrativa' AND HADM.CLASEING = 'A' AND HADM.CERRADA = 1 AND HADM.FACTURABLE = 1)
					OR (@ESTADO_HADM = 'No Facturable' AND HADM.CLASEING = 'A' AND HADM.CERRADA != 1 AND HADM.FACTURABLE = 0)
					OR (@ESTADO_HADM = 'No Procesar' AND HADM.CLASEING IN ('A', 'C') AND COALESCE(HADM.CERRADA, 0) = 1 AND HADM.FACTURABLE = 0)
			  )
			ORDER BY HADM.FECHA DESC, HADM.NOADMISION DESC
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		RETURN
	END

