CREATE OR ALTER PROCEDURE DBO.SPQ_FTR_PHD
@JSON  NVARCHAR(MAX)
WITH
ENCRYPTION
AS
DECLARE @PARAMETROS         NVARCHAR(MAX)  ,@MODELO           VARCHAR(100)    ,@METODO        VARCHAR(100)  ,@USUARIO        VARCHAR(12)
       ,@GRUPO              VARCHAR(8)     ,@SYS_COMPUTERNAME VARCHAR(254)    ,@SEDE          VARCHAR(5)	   ,@A              INT
       ,@IDENTITY           INT
       ,@PROCESO            VARCHAR(20)    ,@HADM NVARCHAR(MAX)				  ,@NOADMISION     VARCHAR(16)
       ,@IDAFILIADO			VARCHAR(20)	   ,@FECHA     DATETIME
       ,@IDTERCERO          VARCHAR(20)    ,@IDPLAN           VARCHAR(6)      ,@F_INI         DATE          ,@F_FIN          DATE
       ,@TIPO_FACTURA       VARCHAR(10)    ,@CNSFCT           VARCHAR(40)     ,@N_FACTURA     VARCHAR(16)	,@F_FACTURA DATETIME
	   ,@NIT				VARCHAR(40)	   ,@COMPANIA VARCHAR(2)			  ,@PERIODO		  CHAR(6)		,@MES VARCHAR(2)
	   ,@ANO				VARCHAR(4)	   ,@TIPO_REPORTE VARCHAR(20)		  ,@REPORTE_PROVISION BIT		,@FECHA_INI DATE
	   ,@FECHA_FIN			DATE		   ,@PARTICULARES	  BIT = 0		  ,@FECHAINI	  DATETIME		,@FECHAFIN DATETIME
	   ,@FILT_NOADMISION    VARCHAR(16)    ,@FILT_DOCIDAFILIADO VARCHAR(40)      ,@FILT_NOMBREAFI NVARCHAR(200)
	   ,@NOPRESTACION       VARCHAR(20)    ,@NOITEM            SMALLINT         ,@IDSERVICIO     VARCHAR(20)
	   ,@CANTIDAD           SMALLINT       ,@VALOR             DECIMAL(14,2)    ,@PAQUETE        SMALLINT
	   ,@COMENTARIOS        VARCHAR(2048)  ,@TIPODTO           VARCHAR(1)       ,@DESCUENTO      DECIMAL(14,2)
	   ,@MANUAL             SMALLINT       ,@NOAUTORIZACION    VARCHAR(20)      ,@IDPROVEEDOR    VARCHAR(20)
	   ,@GFACSOAT           SMALLINT       ,@VALORCOPAGO       DECIMAL(14,2)    ,@VALOREXCEDENTE DECIMAL(18,6)
	   ,@AUD_CNSLOG         VARCHAR(20)    ,@AUD_OLD_IDSERVICIO VARCHAR(20)     ,@AUD_OLD_CANTIDAD VARCHAR(10)
	   ,@AUD_OLD_VALOR      VARCHAR(20)    ,@AUD_OLD_COMENTARIOS VARCHAR(2048)  ,@AUD_OLD_TIPODTO VARCHAR(1)
	   ,@AUD_OLD_DESCUENTO  VARCHAR(20)
	   ,@NOPRESTACION_PAQ   VARCHAR(20)    ,@NOITEM_PAQ         SMALLINT         ,@ACCION_PAQ     VARCHAR(12)
	   ,@CANT_CABECERAS     INT
BEGIN
   SET LANGUAGE Spanish
   SET DATEFORMAT dmy

   SELECT @A = ISJSON(@JSON)
   IF @A = 0
   BEGIN
     RAISERROR('Json: Formato Erroneo',16,1)
     RETURN
   END
   PRINT 'INGRESE A SPQ_FTR_PHD'
   SELECT *
   INTO #JSON
   FROM OPENJSON (@json)
   WITH (
     MODELO         VARCHAR(100)     '$.MODELO',
     METODO         VARCHAR(100)     '$.METODO',
     USUARIO        VARCHAR(12)      '$.USUARIO',
     PARAMETROS     NVARCHAR(MAX)     AS JSON
   )

   SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS , @USUARIO = USUARIO
   FROM #JSON
   --DEFINICION DE TABLA DE ERRORES
   DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200))
   -- TOMA DEL GRUPO, SYS_COMPUTERNAME, SEDE   DE ACUERDO AL USUARIO
   PRINT 'USUARIO:'+@USUARIO
   SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO), @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
   SELECT @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
   IF COALESCE(@SEDE,'') = '' SELECT @SEDE = '01'
   PRINT 'SEDE='+@SEDE

   -- =========================================================================
   -- METODO: LISTAR_ADMISIONES_PHD
   -- Descripcion: Lista las admisiones pendientes de facturar para PHD
   -- =========================================================================
   IF @METODO='LISTAR_ADMISIONES_PHD'
   BEGIN
   	PRINT 'LISTAR_ADMISIONES_PHD'

   	SELECT @IDTERCERO = IDTERCERO, @IDPLAN = IDPLAN, @F_INI = F_INI, @F_FIN = F_FIN
   	FROM   OPENJSON (@PARAMETROS)
   	WITH (
   		IDTERCERO   VARCHAR(20) '$.IDTERCERO'
   		,IDPLAN     VARCHAR(6)  '$.IDPLAN'
   		,F_INI      DATE        '$.F_INI'
   		,F_FIN      DATE        '$.F_FIN'
   	)

   	BEGIN TRY
   		SELECT
   			HADM.NOADMISION,
   			HADM.FECHA,
   			HADM.IDAFILIADO,
   			AFI.TIPO_DOC,
   			AFI.DOCIDAFILIADO,
   			AFI.NOMBREAFI,
   			HADM.IDTERCERO,
   			TER.RAZONSOCIAL,
   			HADM.IDPLAN,
   			PLN.DESCPLAN,
   			HADM.FECHAALTA,
   			HADM.CERRADA,
   			CASE HADM.CERRADA
   				WHEN 0 THEN 'Admitido'
   				WHEN 1 THEN 'Alta Administrativa'
   				WHEN 2 THEN 'Alta Medica'
   				WHEN 3 THEN 'Alta Enfermeria'
   				WHEN 4 THEN 'Preadmitido'
   				ELSE 'Desconocido'
   			END AS DESC_ESTADO,
   			HADM.FACTURADA,
   			HADM.N_FACTURA,
   			COALESCE(HADM.MARCA, 0) AS MARCAFAC,
   			HADM.USUARIO_MARCAFAC,
   			-- Conteo de prestaciones pendientes de facturar
   			(SELECT COUNT(*) FROM HPRE
   			 INNER JOIN HPRED ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
   			 WHERE HPRE.NOADMISION = HADM.NOADMISION
   			   AND COALESCE(HPRED.FACTURADA, 0) = 0
   			   AND COALESCE(HPRED.ANULADO, 0) = 0) AS CANT_PRESTACIONES,
   			-- Valor a pagar por la aseguradora. Si VALOREXCEDENTE es NULL (cargos de farmacia/inventario),
   			-- se calcula CANTIDAD*VALOR - copago - VALORPCOMP. Paquete/no cobrable no se imputan.
   			-- BACKUP original:
   			-- (SELECT COALESCE(SUM(COALESCE(HPRED.VALOREXCEDENTE, 0)), 0) FROM HPRE
   			--  INNER JOIN HPRED ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
   			--  WHERE HPRE.NOADMISION = HADM.NOADMISION
   			--    AND COALESCE(HPRED.FACTURADA, 0) = 0
   			--    AND COALESCE(HPRED.ANULADO, 0) = 0) AS VLR_ASEGURADORA,
   			(SELECT COALESCE(SUM(
   				CASE
   					WHEN COALESCE(HPRED.NOCOBRABLE, 0) = 1 THEN 0
   					WHEN COALESCE(HPRED.PAQUETE, 0) = 1 THEN 0
   					ELSE COALESCE(
   						HPRED.VALOREXCEDENTE,
   						(COALESCE(HPRED.CANTIDAD, 0) * COALESCE(HPRED.VALOR, 0))
   							- COALESCE(HPRED.VALORCOPAGO, 0)
   							- COALESCE(HPRED.VALORPCOMP, 0)
   					)
   				END
   			), 0) FROM HPRE
   			 INNER JOIN HPRED ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
   			 WHERE HPRE.NOADMISION = HADM.NOADMISION
   			   AND COALESCE(HPRED.FACTURADA, 0) = 0
   			   AND COALESCE(HPRED.ANULADO, 0) = 0) AS VLR_ASEGURADORA,
   			-- Información sobre facturas de corte previas (si la admisión no está cerrada)
   			CASE 
   				WHEN HADM.CERRADA != 1 THEN 
   					(SELECT COUNT(*) FROM HADMF 
   					 WHERE HADMF.NOADMISION = HADM.NOADMISION 
   					   AND HADMF.ESTADO = 'P')
   				ELSE 0
   			END AS CANT_FACTURAS_CORTE,
   			-- Última factura de corte (si aplica)
   			CASE 
   				WHEN HADM.CERRADA != 1 THEN 
   					(SELECT TOP 1 HADMF.N_FACTURA 
   					 FROM HADMF 
   					 WHERE HADMF.NOADMISION = HADM.NOADMISION 
   					   AND HADMF.ESTADO = 'P'
   					 ORDER BY HADMF.N_FACTURA DESC)
   				ELSE NULL
   			END AS ULTIMA_FACTURA_CORTE
   		FROM HADM
   		INNER JOIN AFI ON HADM.IDAFILIADO = AFI.IDAFILIADO
   		INNER JOIN TER ON HADM.IDTERCERO = TER.IDTERCERO
   		INNER JOIN PLN ON HADM.IDPLAN = PLN.IDPLAN
   		INNER JOIN PHDCAL ON PHDCAL.NOADMISION = HADM.NOADMISION
   		WHERE HADM.TIPOADM = DBO.FNK_VALORVARIABLE('HTAD_HOSPITA') -- PHD
   		  AND COALESCE(HADM.FACTURABLE, 0) = 1
   		  -- Solo admisiones no definitivamente facturadas (pueden reabrirse)
   		  AND COALESCE(HADM.FACTURADA, 0) = 0
   		  AND PHDCAL.ESTADO_CALIFICACION = 1 -- Solo admisiones aprobadas para facturación
   		  AND (@IDTERCERO IS NULL OR HADM.IDTERCERO = @IDTERCERO)
   		  AND (@IDPLAN IS NULL OR HADM.IDPLAN = @IDPLAN)
   		  -- Solo admisiones con al menos 1 prestación sin facturar (filtro por fecha de cargo HPRED.FECHA)
   		  AND EXISTS (
   		  	SELECT 1 FROM HPRE INNER JOIN HPRED ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
   		  	WHERE HPRE.NOADMISION = HADM.NOADMISION
   		  	  AND COALESCE(HPRED.FACTURADA, 0) = 0
   		  	  AND COALESCE(HPRED.ANULADO, 0) = 0
   		  	  AND COALESCE(HPRE.ANULADO, 0) = 0
   		  	  AND (@F_INI IS NULL OR HPRED.FECHA >= @F_INI)
   		  	  AND (@F_FIN IS NULL OR HPRED.FECHA < DATEADD(DAY, 1, @F_FIN))
   		  )
   		ORDER BY HADM.FECHA DESC

   		SELECT 'OK' OK
   	END TRY
   	BEGIN CATCH
   		INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
   	END CATCH
   	IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
   	BEGIN
   		SELECT 'KO' OK
   		SELECT ERROR FROM @TBLERRORES
   		RETURN
   	END
   	RETURN
   END

   -- =========================================================================
   -- METODO: LISTAR_CARGOS_ADMISION
   -- Descripcion: Lista los cargos (HPRE/HPRED) de una admision especifica
   -- =========================================================================
   IF @METODO='LISTAR_CARGOS_ADMISION'
   BEGIN
   	PRINT 'LISTAR_CARGOS_ADMISION'

   	SELECT @NOADMISION = NOADMISION, @F_INI = F_INI, @F_FIN = F_FIN
   	FROM   OPENJSON (@PARAMETROS)
   	WITH (
   		NOADMISION   VARCHAR(16) '$.NOADMISION'
   		,F_INI       DATE        '$.F_INI'
   		,F_FIN       DATE        '$.F_FIN'
   	)

   	BEGIN TRY
		SELECT 'OK' OK
   		SELECT
   			HPRE.NOPRESTACION,
   			HPRE.FECHA AS FECHA_PRESTACION,
   			HPRE.PREFIJO,
   			PRE.NOM_PREFIJO,
   			HPRE.VALORTOTAL AS VLR_TOTAL_PRE,
   			HPRE.VALORCOPAGO AS VLR_COPAGO_PRE,
   			HPRE.USUARIO,
   			HPRED.NOITEM,
   			HPRED.IDSERVICIO,
   			SER.DESCSERVICIO,
   			HPRED.CANTIDAD,
   			HPRED.VALOR AS VALOR_UNITARIO,
   			(HPRED.CANTIDAD * HPRED.VALOR) AS VALOR_TOTAL,
   			-- BACKUP original:
   			-- HPRED.VALORCOPAGO,
   			-- COALESCE(HPRED.VALOREXCEDENTE, 0) AS VALOREXCEDENTE,
   			COALESCE(HPRED.VALORCOPAGO, 0) AS VALORCOPAGO,
   			CASE
   				WHEN COALESCE(HPRED.NOCOBRABLE, 0) = 1 THEN 0
   				WHEN COALESCE(HPRED.PAQUETE, 0) = 1 THEN 0
   				ELSE COALESCE(
   					HPRED.VALOREXCEDENTE,
   					(COALESCE(HPRED.CANTIDAD, 0) * COALESCE(HPRED.VALOR, 0))
   						- COALESCE(HPRED.VALORCOPAGO, 0)
   						- COALESCE(HPRED.VALORPCOMP, 0)
   				)
   			END AS VALOREXCEDENTE,
   			HPRED.VALORPCOMP,
   			COALESCE(HPRED.FACTURADA, 0) AS FACTURADA,
   			HPRED.N_FACTURA,
   			HPRED.FECHA AS FECHA_CARGO,
   			HPRED.DXPPAL,
   			MDX.DESCRIPCION AS DESC_DX,
   			HPRED.NOAUTORIZACION,
   			COALESCE(HPRED.NOCOBRABLE, 0) AS NOCOBRABLE,
   			COALESCE(HPRED.ENCARGOS, 0) AS ENCARGOS,
   			COALESCE(HPRED.ANULADO, 0) AS ANULADO,
   			HPRED.COMENTARIOS,
   			HPRED.USUARIO AS USUARIO_DET,
   			COALESCE(HPRED.TIPODTO, 'N') AS TIPODTO,
   			COALESCE(HPRED.DESCUENTO, 0) AS DESCUENTO,
   			HPRED.IDPROVEEDOR,
   			TER.RAZONSOCIAL AS NOM_PROVEEDOR,
   			HPRED.VALOR AS VALOR, -- alias para payload HPRED
   			COALESCE(HPRED.PAQUETE, 0) AS PAQUETE,
   			HPRED.NOPRESTACION_PAQ,
   			HPRED.NOITEM_PAQ,
   			HPRED.VALOREXCEDENTE_ANT,
   			CAB.IDSERVICIO AS IDSERVICIO_PAQ,
   			SERPAQ.DESCSERVICIO AS DESCSERVICIO_PAQ,
   			ESCABECERA = CAST(CASE
   				WHEN COALESCE(HPRED.PAQUETE, 0) = 1 THEN 0
   				WHEN EXISTS (
   					SELECT 1 FROM HPREPD
   					WHERE HPREPD.NOPRESUPUESTO = HPRE.NOPRESUPUESTO
   					  AND HPREPD.IDSERVICIO = HPRED.IDSERVICIO
   					  AND COALESCE(HPREPD.ESPAQUETE, 0) = 1
   					  AND COALESCE(HPREPD.ELIMINADO, 0) = 0
   				) THEN 1
   				ELSE 0
   			END AS BIT),
   			COALESCE(HPRED.MANUAL, 0) AS MANUAL,
   			COALESCE(HPRED.COBRARA, 'C') AS COBRARA,
   			HPRED.IDTERCEROCA,
   			HPRED.IDPLAN,
   			COALESCE(HPRED.PCUBRIMIENTO, 0) AS PCUBRIMIENTO,
   			CASE
   				WHEN COALESCE(HPRED.CANTIDAD, 0) * COALESCE(HPRED.VALOR, 0) > 0
   				THEN ROUND(
   					COALESCE(HPRED.VALORCOPAGO, 0) * 100.0
   					/ (HPRED.CANTIDAD * HPRED.VALOR)
   				, 2)
   				ELSE 0
   			END AS COPAGOVARIABLE,
   			COALESCE(SER.MPROVEEDOR, 0) AS MPROVEEDOR,
   			CAST(CASE
   				WHEN EXISTS (
   					SELECT 1 FROM TGEN
   					WHERE TGEN.TABLA = 'CARGOS'
   					  AND TGEN.CAMPO = 'CAMBIAVALOR'
   					  AND TGEN.CODIGO = HPRED.IDSERVICIO
   				) THEN 1 ELSE 0
   			END AS BIT) AS ESMANUAL,
   			-- Laboratorio (PHD calificación / listado de cargos): solo si PREFIJO = variable PREFIJOLABORATORIO
   			RES_LABO = CASE
   				WHEN COALESCE(HPRE.PREFIJO, '') <> COALESCE(DBO.FNK_VALORVARIABLE('PREFIJOLABORATORIO'), '') THEN 'NA'
   				WHEN COALESCE(LAB.LORD_ESTADO, '') = 'R' THEN 'CERRADO'
   				ELSE 'SIN CERRAR'
   			END,
   			REAL_LABO = CASE
   				WHEN COALESCE(HPRE.PREFIJO, '') <> COALESCE(DBO.FNK_VALORVARIABLE('PREFIJOLABORATORIO'), '') THEN 'NA'
   				WHEN COALESCE(LAB.LORD_REALIZADO, 0) = 1 THEN 'CON RESULTADOS'
   				ELSE 'SIN RESULTADOS'
   			END, 
   			-- Clon: vive en HPREP; el cargo solo trae NOPRESUPUESTO
   			CAST(CASE WHEN COALESCE(HPREP.CLON, 0) = 1 THEN 1 ELSE 0 END AS SMALLINT) AS CLON,
   			CASE WHEN COALESCE(HPREP.CLON, 0) = 1 THEN HPREP.USUARIO ELSE NULL END AS USUARIOCLON,
   			CASE WHEN COALESCE(HPREP.CLON, 0) = 1 THEN USUCLON.NOMBRE ELSE NULL END AS NOMBRE_USUARIOCLON
   		FROM HPRE
   		INNER JOIN HPRED ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
   		INNER JOIN SER ON HPRED.IDSERVICIO = SER.IDSERVICIO
   		LEFT JOIN HPRED CAB ON CAB.NOPRESTACION = HPRED.NOPRESTACION_PAQ AND CAB.NOITEM = HPRED.NOITEM_PAQ
   		LEFT JOIN SER SERPAQ ON SERPAQ.IDSERVICIO = CAB.IDSERVICIO
   		LEFT JOIN PRE ON HPRE.PREFIJO = PRE.PREFIJO
   		LEFT JOIN TER ON HPRED.IDPROVEEDOR = TER.IDTERCERO
   		LEFT JOIN HPREP ON HPREP.NOPRESUPUESTO = HPRE.NOPRESUPUESTO
   		LEFT JOIN USUSU USUCLON ON USUCLON.USUARIO = HPREP.USUARIO
   		OUTER APPLY (
   			SELECT TOP 1
   				LORD.ESTADO AS LORD_ESTADO,
   				LORD.REALIZADO AS LORD_REALIZADO
   			FROM LING
   			INNER JOIN LORD ON LORD.NOINGRESO = LING.NOINGRESO
   				AND LORD.IDSERVICIO = HPRED.IDSERVICIO
   				AND LORD.NOITEM = HPRED.NOITEM
   			WHERE LING.NOPRESTACION = HPRE.NOPRESTACION
   				AND (LING.NOADMISION = HPRE.NOADMISION OR LING.NOADMISION IS NULL)
   			ORDER BY LORD.FECHA DESC
   		) LAB
   		LEFT JOIN MDX ON HPRED.DXPPAL = MDX.IDDX
   		WHERE HPRE.NOADMISION = @NOADMISION
   		  AND COALESCE(HPRED.ANULADO, 0) = 0
   		  AND (@F_INI IS NULL OR HPRED.FECHA >= @F_INI)
   		  AND (@F_FIN IS NULL OR HPRED.FECHA < DATEADD(DAY, 1, @F_FIN))
   		ORDER BY HPRE.FECHA DESC, HPRED.NOITEM
   	END TRY
   	BEGIN CATCH
   		INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
   	END CATCH
   	IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
   	BEGIN
   		SELECT 'KO' OK
   		SELECT ERROR FROM @TBLERRORES
   		RETURN
   	END
   	RETURN
   END

   -- =========================================================================
   -- METODO: LISTAR_CABECERAS_PAQ
   -- Cabeceras de paquete de una admision (TGEN PHD/SERVICIOSPAQ, HADM.IDSERVICIOPAQUETE,
   -- o lineas que ya tienen hijos). Si no hay catalogo, cargos no incluidos.
   -- =========================================================================
   IF @METODO = 'LISTAR_CABECERAS_PAQ'
   BEGIN
   	PRINT 'LISTAR_CABECERAS_PAQ'

   	SELECT @NOADMISION = NOADMISION, @NOPRESTACION = NOPRESTACION, @NOITEM = NOITEM
   	FROM OPENJSON (@PARAMETROS)
   	WITH (
   		NOADMISION    VARCHAR(16) '$.NOADMISION'
   		,NOPRESTACION VARCHAR(20) '$.NOPRESTACION'
   		,NOITEM       SMALLINT    '$.NOITEM'
   	)

   	BEGIN TRY
   		SELECT 'OK' OK

   		SELECT
   			HPRED.NOPRESTACION,
   			HPRED.NOITEM,
   			HPRED.IDSERVICIO,
   			SER.DESCSERVICIO,
   			HPRED.CANTIDAD,
   			COALESCE(HPRED.VALOREXCEDENTE,
   				(COALESCE(HPRED.CANTIDAD, 0) * COALESCE(HPRED.VALOR, 0))
   					- COALESCE(HPRED.VALORCOPAGO, 0)
   					- COALESCE(HPRED.VALORPCOMP, 0)
   			) AS VALOREXCEDENTE
   		FROM HPRE
   		INNER JOIN HPRED ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
   		INNER JOIN SER ON HPRED.IDSERVICIO = SER.IDSERVICIO
   		WHERE HPRE.NOADMISION = @NOADMISION
   		  AND COALESCE(HPRED.ANULADO, 0) = 0
   		  AND COALESCE(HPRED.NOCOBRABLE, 0) = 0
   		  AND COALESCE(HPRED.PAQUETE, 0) = 0
   		  AND COALESCE(HPRE.NOPRESUPUESTO, '') <> ''
   		  AND NOT (
   		  		@NOPRESTACION IS NOT NULL
   		  		AND HPRED.NOPRESTACION = @NOPRESTACION
   		  		AND (@NOITEM IS NULL OR HPRED.NOITEM = @NOITEM)
   		  )
   		  AND EXISTS (
   				SELECT 1 FROM HPREPD
   				WHERE HPREPD.NOPRESUPUESTO = HPRE.NOPRESUPUESTO
   				  AND HPREPD.IDSERVICIO = HPRED.IDSERVICIO
   				  AND COALESCE(HPREPD.ESPAQUETE, 0) = 1
   				  AND COALESCE(HPREPD.ELIMINADO, 0) = 0
   		  )
   		ORDER BY HPRED.IDSERVICIO, HPRED.NOPRESTACION, HPRED.NOITEM
   	END TRY
   	BEGIN CATCH
   		INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
   	END CATCH
   	IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
   	BEGIN
   		SELECT 'KO' OK
   		SELECT ERROR FROM @TBLERRORES
   		RETURN
   	END
   	RETURN
   END

   -- =========================================================================
   -- METODO: MARCAR_ADMISION
   -- Descripcion: Marca o desmarca una admision para facturar
   -- =========================================================================
   IF @METODO='MARCAR_ADMISION'
   BEGIN
   	PRINT 'MARCAR_ADMISION'

   	DECLARE @ACCION VARCHAR(10)

   	SELECT @NOADMISION = NOADMISION, @ACCION = ACCION
   	FROM   OPENJSON (@PARAMETROS)
   	WITH (
   		NOADMISION   VARCHAR(16) '$.NOADMISION'
   		,ACCION      VARCHAR(10) '$.ACCION'  -- 'MARCAR' o 'DESMARCAR'
   	)

   	BEGIN TRY
   		IF @ACCION = 'MARCAR'
   		BEGIN
   			UPDATE HADM
   			SET MARCA = 1,
   				USUARIO_MARCAFAC = @USUARIO
   			WHERE NOADMISION = @NOADMISION
   		END
   		ELSE IF @ACCION = 'DESMARCAR'
   		BEGIN
   			UPDATE HADM
   			SET MARCA = 0,
   				USUARIO_MARCAFAC = NULL
   			WHERE NOADMISION = @NOADMISION
   		END

   		SELECT 'OK' OK, @NOADMISION AS NOADMISION, @ACCION AS ACCION
   	END TRY
   	BEGIN CATCH
   		INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
   	END CATCH
   	IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
   	BEGIN
   		SELECT 'KO' OK
   		SELECT ERROR FROM @TBLERRORES
   		RETURN
   	END
   	RETURN
   END

   -- =========================================================================
   -- METODO: MARCAR_MASIVO
   -- Descripcion: Marca o desmarca masivamente las admisiones segun filtros
   -- =========================================================================
   IF @METODO='MARCAR_MASIVO'
   BEGIN
   	PRINT 'MARCAR_MASIVO'

   	DECLARE @ACCION_MAS VARCHAR(10)

