			END
			IF EXISTS (SELECT 1 FROM HPRED WHERE NOPRESTACION = @NOPRESTACION AND NOITEM = @NOITEM AND COALESCE(HPRED.FACTURADA, 0) = 1)
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR = 'Prestación Ya Facturada'
				RETURN
			END
			IF EXISTS (SELECT 1 FROM HPRED WHERE NOPRESTACION = @NOPRESTACION AND NOITEM = @NOITEM AND COALESCE(HPRED.ENCARGOS, 0) <> 0)
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR = 'Prestacion en apoyodx, encargos<>0'
				RETURN
			END
			IF EXISTS (SELECT 1 FROM HPRE A INNER JOIN HADM B ON A.NOADMISION = B.NOADMISION AND B.TIPOADM = dbo.FNK_VALORVARIABLE('IDTARIFASOAT')
						INNER JOIN HACTRAN C ON C.CNSHACTRAN = B.CNSHACTRAN
						WHERE NOPRESTACION = @NOPRESTACION AND COALESCE(C.VLRFALTA, 0) <= 0)
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR = 'La admision llego o sobrepaso el tope del SOAT.'
				RETURN
			END
			IF EXISTS (SELECT 1 FROM HPRED WHERE NOPRESTACION = @NOPRESTACION AND NOITEM = @NOITEM AND COALESCE(PEDIDOINV, 0) = 1 AND IDSERVICIO <> @IDSERVICIO)
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR = 'No se puede editar un servicio soliictado a inventario'
				RETURN
			END

			BEGIN TRAN
				BEGIN TRY
				SELECT @AUD_OLD_IDSERVICIO = IDSERVICIO, @AUD_OLD_CANTIDAD = CONVERT(VARCHAR(10), CANTIDAD), @AUD_OLD_VALOR = CONVERT(VARCHAR(20), VALOR),
					@AUD_OLD_COMENTARIOS = COMENTARIOS, @AUD_OLD_TIPODTO = TIPODTO, @AUD_OLD_DESCUENTO = CONVERT(VARCHAR(20), DESCUENTO)
				FROM HPRED WHERE NOPRESTACION = @NOPRESTACION AND NOITEM = @NOITEM
					IF @METODO = 'EDITAR'
					BEGIN
						-- PHD: no pisar VALOR/PAQUETE/proveedor/SOAT si el front no los envía (evita borrar copago)
						UPDATE A SET A.CANTIDAD = COALESCE(@CANTIDAD, A.CANTIDAD)
										,A.VALOR = COALESCE(@VALOR, A.VALOR)
										,A.PAQUETE = COALESCE(@PAQUETE, A.PAQUETE)
										,A.COMENTARIOS = @COMENTARIOS
										,A.TIPODTO = @TIPODTO, A.DESCUENTO = @DESCUENTO, A.[MANUAL] = @MANUAL, A.IDSERVICIO = @IDSERVICIO
										,A.IDCONCEPTORIPS = B.CODIGORIPS, A.CODCUPS = B.CODCUPS, A.NOAUTORIZACION = COALESCE(@NOAUTORIZACION, '')
										,A.IDPROVEEDOR = COALESCE(@IDPROVEEDOR, A.IDPROVEEDOR)
										,A.GFACSOAT = COALESCE(@GFACSOAT, A.GFACSOAT)
										,A.NOCOBRABLE = COALESCE(A.NOCOBRABLE, 0)
						FROM HPRED A
						INNER JOIN SER B ON B.IDSERVICIO = @IDSERVICIO
						WHERE A.NOPRESTACION = @NOPRESTACION AND A.NOITEM = @NOITEM
					END
					ELSE IF @METODO = 'ELIMINAR'
					BEGIN
						DELETE FROM HPRED WHERE NOPRESTACION = @NOPRESTACION AND NOITEM = @NOITEM AND IDSERVICIO = @IDSERVICIO
						IF NOT EXISTS (SELECT * FROM HPRED WHERE HPRED.NOPRESTACION = @NOPRESTACION)
						BEGIN
							DELETE HPRE WHERE NOPRESTACION = @NOPRESTACION
						END
					END
				END TRY
				BEGIN CATCH
					ROLLBACK
					SELECT 'KO' OK
					SELECT ERROR = 'Error al' + LOWER(@METODO) + ' prestacion=' + ERROR_MESSAGE()
					RETURN
				END CATCH
			COMMIT

			BEGIN TRY
				EXEC SPK_GENCONSECUTIVO '01', @SEDE, '@LOG', @AUD_CNSLOG OUTPUT
				SELECT @AUD_CNSLOG = @SEDE + REPLACE(SPACE(8 - LEN(@AUD_CNSLOG)) + LTRIM(RTRIM(@AUD_CNSLOG)), SPACE(1), 0)
				INSERT INTO USLOG (CNSLOG, COMPANIA, NOADMISION, PROCESO, REQUEST, REFERENCIA, USUARIO, FECHA, SYS_ComputerName, TABLA)
				SELECT @AUD_CNSLOG, @COMPANIA, @NOADMISION, 'HPRED',
					CASE WHEN @METODO = 'EDITAR' THEN 'UPDATE' ELSE 'DELETE' END,
					CASE WHEN @METODO = 'EDITAR' THEN 'EDITA DETALLE PRESTACION ' ELSE 'ELIMINA DETALLE PRESTACION ' END + @NOPRESTACION + ' ITEM ' + CAST(@NOITEM AS VARCHAR(10)),
					@USUARIO, GETDATE(), @SYS_COMPUTERNAME, 'HPRED'
				IF @METODO = 'EDITAR'
				BEGIN
					INSERT INTO USLOGH (CNSLOG, ITEM, CAMPO, VALORANT, VALORNVO)
					SELECT @AUD_CNSLOG, CAST(ROW_NUMBER() OVER (ORDER BY (SELECT 1)) AS INT), CAMPO, VALORANT, VALORNVO
					FROM (
						SELECT 'IDSERVICIO' CAMPO, @AUD_OLD_IDSERVICIO VALORANT, @IDSERVICIO VALORNVO
						UNION ALL SELECT 'CANTIDAD', @AUD_OLD_CANTIDAD, CONVERT(VARCHAR(10), @CANTIDAD)
						UNION ALL SELECT 'VALOR', @AUD_OLD_VALOR, CONVERT(VARCHAR(20), COALESCE(@VALOR, CONVERT(DECIMAL(14,2), @AUD_OLD_VALOR)))
						UNION ALL SELECT 'COMENTARIOS', @AUD_OLD_COMENTARIOS, @COMENTARIOS
						UNION ALL SELECT 'TIPODTO', @AUD_OLD_TIPODTO, @TIPODTO
						UNION ALL SELECT 'DESCUENTO', @AUD_OLD_DESCUENTO, CONVERT(VARCHAR(20), @DESCUENTO)
					) T
					WHERE ISNULL(VALORANT, '') <> ISNULL(VALORNVO, '')
				END
				ELSE
				BEGIN
					INSERT INTO USLOGH (CNSLOG, ITEM, CAMPO, VALORANT, VALORNVO)
					SELECT @AUD_CNSLOG, CAST(ROW_NUMBER() OVER (ORDER BY (SELECT 1)) AS INT), CAMPO, VALORANT, ''
					FROM (
						SELECT 'IDSERVICIO' CAMPO, @AUD_OLD_IDSERVICIO VALORANT
						UNION ALL SELECT 'CANTIDAD', @AUD_OLD_CANTIDAD
						UNION ALL SELECT 'VALOR', @AUD_OLD_VALOR
						UNION ALL SELECT 'COMENTARIOS', @AUD_OLD_COMENTARIOS
					) T
					WHERE ISNULL(VALORANT, '') <> ''
				END
			END TRY
			BEGIN CATCH END CATCH

			-- PHD: si el front envía VALORCOPAGO en EDITAR, conservarlo (SPK_COPAGOQX lo anula al cambiar cantidad)
			IF @METODO = 'EDITAR' AND @VALORCOPAGO IS NOT NULL
			BEGIN
				UPDATE HPRED
				SET VALORCOPAGO = @VALORCOPAGO
				   ,VALOREXCEDENTE = COALESCE(@VALOREXCEDENTE,
						(COALESCE(CANTIDAD, 0) * COALESCE(VALOR, 0)) - @VALORCOPAGO - COALESCE(VALORPCOMP, 0))
				WHERE NOPRESTACION = @NOPRESTACION AND NOITEM = @NOITEM
			END
			ELSE
			BEGIN
				IF EXISTS (SELECT 1 FROM HADM A WHERE A.NOADMISION = @NOADMISION AND COALESCE(A.COPAGONOAUTORIZACION, '') <> '' AND COALESCE(A.COPAGOVALOR, 0) > 0)
				BEGIN
					EXEC SPK_RELIQUIDACOPAGOQX @NOADMISION
				END
				ELSE
				BEGIN
					EXEC SPK_COPAGOQX @NOADMISION, @NOPRESTACION, @NOITEM
				END
			END
			SELECT 'OK' OK
			RETURN
		END
	END

