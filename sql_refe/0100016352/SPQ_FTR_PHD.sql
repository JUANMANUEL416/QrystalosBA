			BEGIN
				SELECT 'KO' OK
				SELECT ERROR = 'El servicio está anulado'
				RETURN
			END

			-- BACKUP original (solo volteaba el flag):
			-- UPDATE HPRED SET PAQUETE = 1 - COALESCE(PAQUETE, 0)
			-- WHERE NOPRESTACION = @NOPRESTACION AND NOITEM = @NOITEM AND IDSERVICIO = @IDSERVICIO

			IF COALESCE(@ACCION_PAQ, '') = ''
			BEGIN
				IF EXISTS (SELECT 1 FROM HPRED WHERE NOPRESTACION = @NOPRESTACION AND NOITEM = @NOITEM AND COALESCE(PAQUETE, 0) = 1)
					SET @ACCION_PAQ = 'QUITAR'
				ELSE
					SET @ACCION_PAQ = 'AGREGAR'
			END

			BEGIN TRY
				BEGIN TRAN PAQ_HPRED
				IF @ACCION_PAQ = 'QUITAR'
				BEGIN
					UPDATE HPRED
					SET VALOREXCEDENTE = COALESCE(
							VALOREXCEDENTE_ANT,
							(COALESCE(CANTIDAD, 0) * COALESCE(VALOR, 0))
								- COALESCE(VALORCOPAGO, 0)
								- COALESCE(VALORPCOMP, 0)
						),
						NOPRESTACION_PAQ = NULL,
						NOITEM_PAQ = NULL,
						VALOREXCEDENTE_ANT = NULL,
						PAQUETE = 0
					WHERE NOPRESTACION = @NOPRESTACION AND NOITEM = @NOITEM
				END
				ELSE
				BEGIN
					IF EXISTS (
						SELECT 1
						FROM HPRED
						INNER JOIN HPRE ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
						INNER JOIN HPREPD ON HPREPD.NOPRESUPUESTO = HPRE.NOPRESUPUESTO
							AND HPREPD.IDSERVICIO = HPRED.IDSERVICIO
							AND COALESCE(HPREPD.ESPAQUETE, 0) = 1
							AND COALESCE(HPREPD.ELIMINADO, 0) = 0
						WHERE HPRED.NOPRESTACION = @NOPRESTACION AND HPRED.NOITEM = @NOITEM
					)
					BEGIN
						IF @@TRANCOUNT > 0 ROLLBACK TRAN PAQ_HPRED
						SELECT 'KO' OK
						SELECT ERROR = 'No se puede incluir una cabecera de paquete dentro de otro paquete'
						RETURN
					END

					IF COALESCE(@NOPRESTACION_PAQ, '') = '' OR @NOITEM_PAQ IS NULL
					BEGIN
						SELECT @CANT_CABECERAS = COUNT(*)
						FROM HPRE
						INNER JOIN HPRED ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
						WHERE HPRE.NOADMISION = @NOADMISION
						  AND COALESCE(HPRED.ANULADO, 0) = 0
						  AND COALESCE(HPRED.NOCOBRABLE, 0) = 0
						  AND COALESCE(HPRED.PAQUETE, 0) = 0
						  AND COALESCE(HPRE.NOPRESUPUESTO, '') <> ''
						  AND NOT (HPRED.NOPRESTACION = @NOPRESTACION AND HPRED.NOITEM = @NOITEM)
						  AND EXISTS (
								SELECT 1 FROM HPREPD
								WHERE HPREPD.NOPRESUPUESTO = HPRE.NOPRESUPUESTO
								  AND HPREPD.IDSERVICIO = HPRED.IDSERVICIO
								  AND COALESCE(HPREPD.ESPAQUETE, 0) = 1
								  AND COALESCE(HPREPD.ELIMINADO, 0) = 0
						  )

						IF @CANT_CABECERAS = 1
						BEGIN
							SELECT TOP 1 @NOPRESTACION_PAQ = HPRED.NOPRESTACION, @NOITEM_PAQ = HPRED.NOITEM
							FROM HPRE
							INNER JOIN HPRED ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
							WHERE HPRE.NOADMISION = @NOADMISION
							  AND COALESCE(HPRED.ANULADO, 0) = 0
							  AND COALESCE(HPRED.NOCOBRABLE, 0) = 0
							  AND COALESCE(HPRED.PAQUETE, 0) = 0
							  AND COALESCE(HPRE.NOPRESUPUESTO, '') <> ''
							  AND NOT (HPRED.NOPRESTACION = @NOPRESTACION AND HPRED.NOITEM = @NOITEM)
							  AND EXISTS (
									SELECT 1 FROM HPREPD
									WHERE HPREPD.NOPRESUPUESTO = HPRE.NOPRESUPUESTO
									  AND HPREPD.IDSERVICIO = HPRED.IDSERVICIO
									  AND COALESCE(HPREPD.ESPAQUETE, 0) = 1
									  AND COALESCE(HPREPD.ELIMINADO, 0) = 0
