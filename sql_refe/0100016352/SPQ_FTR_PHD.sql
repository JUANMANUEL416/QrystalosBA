   				AND CARTG.ESTADO IN ('APROBADA', 'VIGENTE')
   				AND CARTG.FECHA_VENCIMIENTO >= CONVERT(DATE, GETDATE())

   			SET @FALTANTE = CASE
   				WHEN @VLR_ASEGURADORA > @VLR_CUBIERTO THEN @VLR_ASEGURADORA - @VLR_CUBIERTO
   				ELSE 0
   			END

