   					CONVERT(VARCHAR(30), @VLR_CUBIERTO),
   					' / Total a facturar: ',
   					CONVERT(VARCHAR(30), @VLR_ASEGURADORA)
   				)
   				SELECT 'KO' OK
   				SELECT ERROR FROM @TBLERRORES
   				RETURN
