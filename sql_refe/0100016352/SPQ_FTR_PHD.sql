						IF @@TRANCOUNT > 0 ROLLBACK TRAN PAQ_HPRED
						SELECT 'KO' OK
						SELECT ERROR = 'Un servicio no puede asociarse a sí mismo como paquete'
						RETURN
					END

					IF NOT EXISTS (
						SELECT 1
						FROM HPRE PITEM
						INNER JOIN HPRE PCAB ON PCAB.NOADMISION = PITEM.NOADMISION
						INNER JOIN HPRED CAB ON CAB.NOPRESTACION = @NOPRESTACION_PAQ AND CAB.NOITEM = @NOITEM_PAQ
						INNER JOIN HPREPD ON HPREPD.NOPRESUPUESTO = PCAB.NOPRESUPUESTO
							AND HPREPD.IDSERVICIO = CAB.IDSERVICIO
							AND COALESCE(HPREPD.ESPAQUETE, 0) = 1
							AND COALESCE(HPREPD.ELIMINADO, 0) = 0
						WHERE PITEM.NOPRESTACION = @NOPRESTACION
						  AND PCAB.NOPRESTACION = @NOPRESTACION_PAQ
						  AND COALESCE(CAB.ANULADO, 0) = 0
						  AND COALESCE(CAB.PAQUETE, 0) = 0
					)
					BEGIN
						IF @@TRANCOUNT > 0 ROLLBACK TRAN PAQ_HPRED
						SELECT 'KO' OK
						SELECT ERROR = 'La cabecera de paquete no existe en la misma admisión o está incluida en otro paquete'
						RETURN
					END

					UPDATE HPRED
