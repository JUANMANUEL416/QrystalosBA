				   -- Obtener de HADM (ARL)
				   SELECT @IDTERCEROCA_DESTINO = HADM.IDTERECEROARL, @IDPLAN_DESTINO = HADM.IDPLANARL
				   FROM HADM 
               WHERE NOADMISION = @NOADMISION
			   END

				-- Actualizar solo el item sin asignar
				UPDATE HPRED
				SET GFACSOAT = @NUEVO_GFACSOAT
				WHERE NOPRESTACION = @CUR_NOPRESTACION AND NOITEM = @CUR_NOITEM

				FETCH NEXT FROM cur_items INTO @CUR_NOPRESTACION, @CUR_NOITEM, @CUR_VALOR
			END

