						TIPODTO = @TIPODTO_IT, DESCUENTO = @DESCUENTO_IT, [MANUAL] = @MANUAL_IT, IDSERVICIO = @IDSERVICIO_IT,
						IDCONCEPTORIPS = B.CODIGORIPS, CODCUPS = B.CODCUPS, NOAUTORIZACION = COALESCE(@NOAUTORIZACION_IT, ''),
						IDPROVEEDOR = @IDPROVEEDOR_IT, GFACSOAT = @GFACSOAT_IT, NOCOBRABLE = COALESCE(NOCOBRABLE, 0)
					FROM HPRED A
					INNER JOIN SER B ON B.IDSERVICIO = @IDSERVICIO_IT
					WHERE A.NOPRESTACION = @NOPRESTACION_IT AND A.NOITEM = @NOITEM_IT
				COMMIT
			END TRY
			BEGIN CATCH
				IF @@TRANCOUNT > 0 ROLLBACK
				SELECT 'KO' OK
				SELECT ERROR = 'Error al editar prestacion: ' + ERROR_MESSAGE()
				RETURN
			END CATCH
		END

		IF @NOADMISION IS NULL
			SELECT @NOADMISION = NOADMISION FROM HPRE WHERE NOPRESTACION = @NOPRESTACION_IT

		IF EXISTS(SELECT 1 FROM HADM A WHERE A.NOADMISION = @NOADMISION AND COALESCE(A.COPAGONOAUTORIZACION, '') <> '' AND COALESCE(A.COPAGOVALOR, 0) > 0)
			EXEC SPK_RELIQUIDACOPAGOQX @NOADMISION
		ELSE
			EXEC SPK_COPAGOQX @NOADMISION, @NOPRESTACION_IT, @NOITEM_IT

		SELECT 'OK' OK, @NOPRESTACION_IT AS NOPRESTACION, @NOITEM_IT AS NOITEM

		SELECT
			HPRED.NOPRESTACION,
			HPRED.NOITEM,
			HPRE.PREFIJO,
			HPRE.NOADMISION,
			COALESCE(HPRED.GFACSOAT, 0) AS GFACSOAT,
			HPRED.IDSERVICIO,
			SER.DESCSERVICIO,
			CONVERT(INT, HPRED.CANTIDAD) AS CANTIDAD,
			CONVERT(DECIMAL(14, 2), HPRED.VALOR) AS VALOR,
			CONVERT(DECIMAL(14, 2), COALESCE(HPRED.CANTIDAD, 0) * COALESCE(HPRED.VALOR, 0)) AS VLRSUBTOTAL,
			CONVERT(DECIMAL(14, 2), HPRED.VALORCOPAGO) AS VALORCOPAGO,
			CONVERT(DECIMAL(14, 2), HPRED.VALOREXCEDENTE) AS VALOREXCEDENTE,
			CONVERT(DECIMAL(14, 2), HPRED.VALORPCOMP) AS VALORPCOMP,
			COALESCE(HPRED.NOCOBRABLE, 0) AS NOCOBRABLE,
			COALESCE(HPRED.PAQUETE, 0) AS PAQUETE,
			COALESCE(HPRED.NOAUTORIZACION, '') AS NOAUTORIZACION,
			COALESCE(HPRED.COMENTARIOS, '') AS COMENTARIOS,
			COALESCE(HPRED.FACTURADA, 0) AS FACTURADA,
			COALESCE(HPRED.ENCARGOS, 0) AS ENCARGOS,
			COALESCE(HPRED.COBRARA, 'C') AS COBRARA,
			HPRED.IDTERCEROCA,
			HPRED.IDPLAN,
			HPRE.FECHA,
			HPRE.IDAREA,
			HPRE.CCOSTO,
			(SELECT COALESCE(SUM(D2.CANTIDAD), 0) FROM HPRED D2 INNER JOIN HPRE H2 ON H2.NOPRESTACION = D2.NOPRESTACION WHERE H2.NOADMISION = HPRE.NOADMISION AND H2.PREFIJO = HPRE.PREFIJO AND COALESCE(D2.GFACSOAT, 0) = COALESCE(HPRED.GFACSOAT, 0)) AS TOTAL_PREFIJO_CANTIDAD,
			(SELECT COALESCE(SUM(D2.VALOREXCEDENTE), 0) FROM HPRED D2 INNER JOIN HPRE H2 ON H2.NOPRESTACION = D2.NOPRESTACION WHERE H2.NOADMISION = HPRE.NOADMISION AND H2.PREFIJO = HPRE.PREFIJO AND COALESCE(D2.GFACSOAT, 0) = COALESCE(HPRED.GFACSOAT, 0)) AS TOTAL_PREFIJO_VALOR,
			(SELECT COUNT(*) FROM HPRED D2 INNER JOIN HPRE H2 ON H2.NOPRESTACION = D2.NOPRESTACION WHERE H2.NOADMISION = HPRE.NOADMISION AND H2.PREFIJO = HPRE.PREFIJO AND COALESCE(D2.GFACSOAT, 0) = COALESCE(HPRED.GFACSOAT, 0)) AS TOTAL_PREFIJO_ITEMS,
			(SELECT COALESCE(SUM(COALESCE(D2.CANTIDAD, 0) * COALESCE(D2.VALOR, 0)), 0) FROM HPRED D2 INNER JOIN HPRE H2 ON H2.NOPRESTACION = D2.NOPRESTACION WHERE H2.NOADMISION = HPRE.NOADMISION AND COALESCE(D2.GFACSOAT, 0) = COALESCE(HPRED.GFACSOAT, 0) AND COALESCE(D2.FACTURADA, 0) = 0 AND COALESCE(D2.NOCOBRABLE, 0) = 0) AS TOTAL_RESPONSABLE_VALOR
		FROM HPRED
		INNER JOIN HPRE ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
		INNER JOIN SER ON SER.IDSERVICIO = HPRED.IDSERVICIO
		WHERE HPRED.NOPRESTACION = @NOPRESTACION_IT
		  AND HPRED.NOITEM = @NOITEM_IT

		RETURN
	END
