CREATE OR ALTER  PROCEDURE DBO.SPQ_DISTRIHPRED_SOAT @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
SET DATEFORMAT dmy
SET NOCOUNT ON

DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100)
DECLARE @USUARIO VARCHAR(12), @NOADMISION VARCHAR(20), @CNSHACTRAN VARCHAR(20),@ADRESS BIT
DECLARE @IDTERCEROCA_DESTINO VARCHAR(20), @IDPLAN_DESTINO VARCHAR(6)
DECLARE @TOPE DECIMAL(14,2), @TOPE1 DECIMAL(14,2),@VLREXTERNO DECIMAL(14,2),@DIFERENCIA DECIMAL(14,2),@ACUMLA DECIMAL(14,2),@TOPE2 DECIMAL(14,2)
DECLARE @VLRGASTADO_ANT DECIMAL(14,2), @CONSUMIDO_PREVIO DECIMAL(14,2), @TOPE1_ORIG DECIMAL(14,2), @TOPE2_ORIG DECIMAL(14,2)
DECLARE @FACT_ASE DECIMAL(14,2), @FACT_ADRES DECIMAL(14,2), @AB_ADRES DECIMAL(14,2), @AB_ASE DECIMAL(14,2)
DECLARE @DISP_ASE DECIMAL(14,2), @DISP_ADRES DECIMAL(14,2)
DECLARE @ITEMS_MOVIDOS INT
DECLARE @IDTERCERO_EPS VARCHAR(20), @IDPLAN_EPS VARCHAR(6)
DECLARE @IDTERCERO_ADRES VARCHAR(20), @IDPLAN_ADRES VARCHAR(6)
DECLARE @SIN_REDISTRIBUIR BIT
BEGIN
	SELECT *
	INTO #JSON
	FROM OPENJSON(@json) WITH (
		MODELO VARCHAR(100) '$.MODELO',
		METODO VARCHAR(100) '$.METODO',
		USUARIO VARCHAR(12) '$.USUARIO',
		PARAMETROS NVARCHAR(MAX) AS JSON
	)

	SELECT @MODELO = MODELO, @METODO = METODO,
		   @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON

	-- =============================================
	-- CARGAR_DATOS: Obtiene topes de HACTRAN y items de HPRED
	-- =============================================
	IF @METODO = 'CARGAR_DATOS'
	BEGIN
		BEGIN TRY
			SELECT @NOADMISION = NOADMISION, @CNSHACTRAN = CNSHACTRAN,
			       @SIN_REDISTRIBUIR = SIN_REDISTRIBUIR
			FROM OPENJSON(@PARAMETROS) WITH (
				NOADMISION VARCHAR(20) '$.NOADMISION',
				CNSHACTRAN VARCHAR(20) '$.CNSHACTRAN',
				SIN_REDISTRIBUIR BIT '$.SIN_REDISTRIBUIR'
			)

			IF COALESCE(@CNSHACTRAN, '') = ''
			BEGIN
				SELECT @CNSHACTRAN = CNSHACTRAN FROM HADM WHERE NOADMISION = @NOADMISION
			END

			-- Validar que exista la admisi?n
			IF NOT EXISTS (SELECT 1 FROM HADM WHERE NOADMISION = @NOADMISION)
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) SELECT 'La admisi?n no existe'
			END

			IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
         SET @ADRESS = 0
         IF EXISTS(SELECT  * FROM HACTRAN LEFT JOIN TER ON HACTRAN.IDASEGURADORA=TER.IDTERCERO
                   WHERE CNSHACTRAN=@CNSHACTRAN 
                   AND  1= CASE WHEN IDASEGURADORA IS NULL OR TER.NIT=DBO.FNK_VALORVARIABLE('IDNITFONSAT') THEN 1 WHEN TOPE1 < TOPE THEN 1 ELSE 0 END)
                  
         BEGIN
            SELECT @ADRESS=1
         END
			-- Topes disponibles del evento actual: descuentan gasto externo + monto anterior.
			-- Cascada: Aseguradora, luego ADRES, luego EPS.
         SELECT @TOPE=COALESCE(TOPE,0),@TOPE1=COALESCE(TOPE1,0),@VLREXTERNO=COALESCE(VLRGASTOEXTERNO,0)
         FROM HACTRAN WHERE CNSHACTRAN=@CNSHACTRAN
         -- HACTRAND consolida el gasto de las atenciones anteriores del accidente.
         -- EXTERNO se excluye porque el encabezado lo presenta en un campo independiente.
         SELECT @VLRGASTADO_ANT = COALESCE(SUM(COALESCE(HACTRAND.VLRGASTADO,0)), 0)
         FROM HACTRAND
         WHERE HACTRAND.CNSHACTRAN = @CNSHACTRAN
           AND UPPER(LTRIM(RTRIM(COALESCE(HACTRAND.PROCEDENCIA,'')))) <> 'EXTERNO'
           AND LTRIM(RTRIM(COALESCE(HACTRAND.NOREFERENCIA,''))) <> LTRIM(RTRIM(COALESCE(@NOADMISION,'')))
         -- Un solo barrido de cargos: gasto de esta admisión + facturado/abierto por responsable
         SELECT
            @FACT_ASE = COALESCE(SUM(CASE WHEN COALESCE(HPRED.FACTURADA,0)=1 AND HPRED.GFACSOAT=1 THEN COALESCE(HPRED.CANTIDAD,0)*COALESCE(HPRED.VALOR,0) ELSE 0 END), 0),
            @FACT_ADRES = COALESCE(SUM(CASE WHEN COALESCE(HPRED.FACTURADA,0)=1 AND HPRED.GFACSOAT=2 THEN COALESCE(HPRED.CANTIDAD,0)*COALESCE(HPRED.VALOR,0) ELSE 0 END), 0),
            @AB_ADRES = COALESCE(SUM(CASE WHEN COALESCE(HPRED.FACTURADA,0)=0 AND HPRED.GFACSOAT=2 THEN COALESCE(HPRED.CANTIDAD,0)*COALESCE(HPRED.VALOR,0) ELSE 0 END), 0),
            @AB_ASE = COALESCE(SUM(CASE WHEN COALESCE(HPRED.FACTURADA,0)=0 AND HPRED.GFACSOAT=1 THEN COALESCE(HPRED.CANTIDAD,0)*COALESCE(HPRED.VALOR,0) ELSE 0 END), 0)
         FROM HPRED
         INNER JOIN HPRE ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
         WHERE HPRE.NOADMISION = @NOADMISION
           AND COALESCE(HPRED.NOCOBRABLE, 0) = 0
         -- El monto anterior ya excluye la admision actual y el gasto externo.
         SET @TOPE1_ORIG = @TOPE1
         SET @TOPE2 = CASE WHEN @TOPE > @TOPE1_ORIG THEN @TOPE - @TOPE1_ORIG ELSE 0 END
         SET @TOPE2_ORIG = @TOPE2
         -- Cascada: (anterior + externo) al primer pagador; el resto al segundo.
         SET @CONSUMIDO_PREVIO = COALESCE(@VLREXTERNO,0) + COALESCE(@VLRGASTADO_ANT,0)
         IF @CONSUMIDO_PREVIO > 0
         BEGIN
            IF @CONSUMIDO_PREVIO <= @TOPE1_ORIG
            BEGIN
               SET @TOPE1 = @TOPE1_ORIG - @CONSUMIDO_PREVIO
            END
            ELSE
            BEGIN
               SET @DIFERENCIA = @CONSUMIDO_PREVIO - @TOPE1_ORIG
               SET @TOPE1 = 0
               IF @TOPE2 > @DIFERENCIA
                  SET @TOPE2 = @TOPE2 - @DIFERENCIA
               ELSE
                  SET @TOPE2 = 0
            END
         END
         PRINT '@TOPE1='+STR(@TOPE1)
         PRINT '@TOPE2='+STR(@TOPE2)
         PRINT '@CONSUMIDO_PREVIO='+STR(@CONSUMIDO_PREVIO)

			-- ?tems sin responsable: Aseguradora si queda tope, si no ADRES, si no EPS
			UPDATE HPRED
			SET GFACSOAT = CASE
				WHEN @TOPE1 > 0 THEN 1
				WHEN @TOPE2 > 0 THEN 2
				ELSE 3
			END
			FROM HPRED
			INNER JOIN HPRE ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
			WHERE HPRE.NOADMISION = @NOADMISION
			  AND COALESCE(HPRED.FACTURADA, 0) = 0
			  AND COALESCE(HPRED.NOCOBRABLE, 0) = 0
			  AND HPRED.GFACSOAT IS NULL

			SET @ITEMS_MOVIDOS = 0
			SET @DISP_ASE = CASE WHEN @TOPE1 > @FACT_ASE THEN @TOPE1 - @FACT_ASE ELSE 0 END
			SET @DISP_ADRES = CASE WHEN @TOPE2 > (@FACT_ADRES + @AB_ADRES) THEN @TOPE2 - @FACT_ADRES - @AB_ADRES ELSE 0 END

			-- Solo redistribuye si hay abiertos de Aseguradora que ya no caben.
			-- Si el usuario acaba de trasladar a ASEGURADORA (saldo puede quedar en rojo), no deshacerlo.
			IF @AB_ASE > @DISP_ASE AND COALESCE(@SIN_REDISTRIBUIR, 0) = 0
			BEGIN
				SET @IDTERCERO_ADRES = DBO.FNK_VALORVARIABLE('IDNITFONSAT')
				SET @IDPLAN_ADRES = DBO.FNK_VALORVARIABLE('IDPLANSOAT')
				SELECT @IDTERCERO_EPS = AFI.IDADMINISTRADORA, @IDPLAN_EPS = AFI.IDPLAN
				FROM HADM
				INNER JOIN AFI ON AFI.IDAFILIADO = HADM.IDAFILIADO
				WHERE HADM.NOADMISION = @NOADMISION

				;WITH ITEMS_EXC AS (
					SELECT HPRED.NOPRESTACION, HPRED.NOITEM,
					       COALESCE(HPRED.CANTIDAD,0)*COALESCE(HPRED.VALOR,0) AS VALOR,
					       SUM(COALESCE(HPRED.CANTIDAD,0)*COALESCE(HPRED.VALOR,0))
					         OVER (ORDER BY HPRE.FECHA, HPRED.NOPRESTACION, HPRED.NOITEM
					               ROWS UNBOUNDED PRECEDING) AS ACUM
					FROM HPRED
					INNER JOIN HPRE ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
					WHERE HPRE.NOADMISION = @NOADMISION
					  AND COALESCE(HPRED.FACTURADA,0) = 0
					  AND COALESCE(HPRED.NOCOBRABLE,0) = 0
					  AND HPRED.GFACSOAT = 1
				),
				DESTINO AS (
					SELECT NOPRESTACION, NOITEM, ACUM,
					       COALESCE((SELECT MAX(ACUM) FROM ITEMS_EXC WHERE ACUM <= @DISP_ASE), 0) AS ASE_TOMADO
					FROM ITEMS_EXC
				)
				UPDATE HPRED
				SET GFACSOAT = CASE
						WHEN D.ACUM <= @DISP_ASE THEN 1
						WHEN @DISP_ADRES > 0 AND (D.ACUM - D.ASE_TOMADO) <= @DISP_ADRES THEN 2
						ELSE 3
					END,
				    IDTERCEROCA = CASE
						WHEN D.ACUM <= @DISP_ASE THEN HPRED.IDTERCEROCA
						WHEN @DISP_ADRES > 0 AND (D.ACUM - D.ASE_TOMADO) <= @DISP_ADRES THEN @IDTERCERO_ADRES
						ELSE @IDTERCERO_EPS
					END,
				    IDPLAN = CASE
						WHEN D.ACUM <= @DISP_ASE THEN HPRED.IDPLAN
						WHEN @DISP_ADRES > 0 AND (D.ACUM - D.ASE_TOMADO) <= @DISP_ADRES THEN @IDPLAN_ADRES
						ELSE @IDPLAN_EPS
					END
				FROM HPRED
				INNER JOIN DESTINO D ON D.NOPRESTACION = HPRED.NOPRESTACION AND D.NOITEM = HPRED.NOITEM
				WHERE D.ACUM > @DISP_ASE

				SET @ITEMS_MOVIDOS = @@ROWCOUNT
			END

			-- Recordset 0: OK
			SELECT 'OK' OK, @ADRESS ADRESS, @ITEMS_MOVIDOS ITEMS_MOVIDOS

			-- Recordset 1: Topes de pantalla = tope configurado (no el saldo restante)
			SELECT 
				 @TOPE1_ORIG AS TOPE_ASEGURADORA,
				 @TOPE2_ORIG AS TOPE_ADRES,
				0 AS TOPE_ARL,
				0 AS TOPE_EPS,
				COALESCE(HACTRAN.TOPE, 0) AS TOPE_TOTAL,
				COALESCE(@VLRGASTADO_ANT, 0) AS VLRGASTADO,
				CASE WHEN  COALESCE(HACTRAN.VLRFALTA, 0)-COALESCE(HACTRAN.VLRGASTOEXTERNO,0)<=0 THEN 0 ELSE COALESCE(HACTRAN.VLRFALTA, 0)-COALESCE(HACTRAN.VLRGASTOEXTERNO,0) END  AS VLRFALTA,
        COALESCE(HACTRAN.VLRGASTOEXTERNO,0)AS GASTOEXTERNO,
				HADM.ARLRELA,
				HADM.IDTERCERO,
				TER.RAZONSOCIAL,
				HADM.IDPLAN,
				AFI.IDADMINISTRADORA,
				COALESCE(HADM.CERRADA, 0) AS CERRADA,
				CASE 
					WHEN TER1.NIT = DBO.FNK_VALORVARIABLE('IDNITFONSAT') OR COALESCE(HACTRAN.IDASEGURADORA,'')='' OR @TOPE2>0
					THEN 0  -- No mostrar ADRES
					ELSE 1  -- Mostrar ADRES
				END AS MOSTRAR_ADRES,
            HADM.FECHA,HADM.FECHAALTAMED
			FROM HADM INNER JOIN HACTRAN ON HACTRAN.CNSHACTRAN = HADM.CNSHACTRAN
         LEFT JOIN TER TER1 ON HACTRAN.IDASEGURADORA=TER1.IDTERCERO
			LEFT JOIN TER ON TER.IDTERCERO = HADM.IDTERCERO
			LEFT JOIN AFI ON AFI.IDAFILIADO = HADM.IDAFILIADO
			WHERE HADM.NOADMISION = @NOADMISION

			-- Recordset 2: consumido por responsable (agregado; no se env?an todos los ?tems)
			SELECT
				HPRED.GFACSOAT,
				SUM(COALESCE(HPRED.CANTIDAD, 0) * COALESCE(HPRED.VALOR, 0)) AS VLRSUBTOTAL,
				COUNT(*) AS CANTIDAD
			FROM HPRED
			INNER JOIN HPRE ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
			WHERE HPRE.NOADMISION = @NOADMISION
			  AND COALESCE(HPRED.NOCOBRABLE, 0) = 0
			GROUP BY HPRED.GFACSOAT

			-- Recordset 3: Nombres de responsables de pago

      SELECT 1 AS GFACSOAT, TER.IDTERCERO,TER.NIT,TER.RAZONSOCIAL AS NOMBRE
			FROM HADM
			INNER JOIN HACTRAN ON HACTRAN.CNSHACTRAN = HADM.CNSHACTRAN
			INNER JOIN TER ON HACTRAN.IDASEGURADORA = TER.IDTERCERO
			WHERE HADM.NOADMISION = @NOADMISION
         UNION ALL
         SELECT CASE WHEN @ADRESS=1 AND  @TOPE1 = @TOPE THEN 1 ELSE 2 END AS GFACSOAT, TER.IDTERCERO,TER.NIT,TER.RAZONSOCIAL
         FROM TER 
         WHERE TER.IDTERCERO= DBO.FNK_VALORVARIABLE('IDNITFONSAT') 
         UNION ALL
         SELECT  3 AS GFACSOAT, TER.IDTERCERO,TER.NIT,TER.RAZONSOCIAL
			   FROM HADM INNER JOIN HACTRAN ON HACTRAN.CNSHACTRAN = HADM.CNSHACTRAN
               INNER JOIN AFI ON HADM.IDAFILIADO=AFI.IDAFILIADO
               INNER JOIN TER ON AFI.IDADMINISTRADORA=TER.IDTERCERO
         WHERE HADM.NOADMISION = @NOADMISION
         UNION ALL
         SELECT  4 AS GFACSOAT, TER.IDTERCERO,TER.NIT,TER.RAZONSOCIAL
			FROM HADM
			LEFT JOIN HACTRAN ON HACTRAN.CNSHACTRAN = HADM.CNSHACTRAN
         LEFT JOIN TER ON HADM.IDTERECEROARL=TER.IDTERCERO
         WHERE HADM.NOADMISION = @NOADMISION
         AND COALESCE(ARLRELA,0)=1

		 -- Devuelve terceros ya facturados.
		  -- Devuelve terceros ya facturados por responsable (GFACSOAT),
		 -- validando solo por NOADMISION y cruce FTR.N_FACTURA = HPRED.N_FACTURA.
		 ;WITH FACTURAS_ADM AS (
			SELECT
				COALESCE(HPRED.GFACSOAT, 1) AS GFACSOAT,
				HPRED.N_FACTURA,
				FTR.IDTERCERO AS IDTERCERO_FTR,
				FTR.IDPLAN AS IDPLAN_FTR
			FROM HPRED
			INNER JOIN HPRE ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
			INNER JOIN FTR ON FTR.N_FACTURA = HPRED.N_FACTURA
			WHERE HPRE.NOADMISION = @NOADMISION
			  AND COALESCE(HPRED.N_FACTURA, '') <> ''
		)
		SELECT GFACSOAT, IDTERCEROCA, IDPLAN
		FROM (
			-- GFACSOAT = 1 (Aseguradora): validar contra HACTRAN.IDASEGURADORA
			SELECT DISTINCT
				1 AS GFACSOAT,
				FA.IDTERCERO_FTR AS IDTERCEROCA,
				FA.IDPLAN_FTR AS IDPLAN
			FROM FACTURAS_ADM FA
			INNER JOIN HADM ON HADM.NOADMISION = @NOADMISION
			LEFT JOIN HACTRAN ON HACTRAN.CNSHACTRAN = HADM.CNSHACTRAN
			WHERE FA.GFACSOAT = 1
			  AND COALESCE(HACTRAN.IDASEGURADORA, '') <> ''
			  AND FA.IDTERCERO_FTR = HACTRAN.IDASEGURADORA

			UNION ALL

			-- GFACSOAT = 2 (ADRES): validar tercero FONSAT
			SELECT DISTINCT
				2 AS GFACSOAT,
				FA.IDTERCERO_FTR AS IDTERCEROCA,
				FA.IDPLAN_FTR AS IDPLAN
			FROM FACTURAS_ADM FA
			WHERE FA.GFACSOAT = 2
			  AND FA.IDTERCERO_FTR = DBO.FNK_VALORVARIABLE('IDNITFONSAT')

			UNION ALL

			-- GFACSOAT = 3 (EPS): validar tercero/plan de AFI de la admisi?n
			SELECT DISTINCT
				3 AS GFACSOAT,
				FA.IDTERCERO_FTR AS IDTERCEROCA,
				FA.IDPLAN_FTR AS IDPLAN
			FROM FACTURAS_ADM FA
			INNER JOIN HADM ON HADM.NOADMISION = @NOADMISION
			INNER JOIN AFI ON AFI.IDAFILIADO = HADM.IDAFILIADO
			WHERE FA.GFACSOAT = 3
			  AND COALESCE(AFI.IDADMINISTRADORA, '') <> ''
			  AND FA.IDTERCERO_FTR = AFI.IDADMINISTRADORA
			  AND FA.IDPLAN_FTR = COALESCE(AFI.IDPLAN, '')

			UNION ALL

			-- GFACSOAT = 4 (ARL): mantener validaci?n por tercero/plan ARL de admisi?n
			SELECT DISTINCT
				4 AS GFACSOAT,
				FA.IDTERCERO_FTR AS IDTERCEROCA,
				FA.IDPLAN_FTR AS IDPLAN
			FROM FACTURAS_ADM FA
			INNER JOIN HADM ON HADM.NOADMISION = @NOADMISION
			WHERE FA.GFACSOAT = 4
			  AND COALESCE(HADM.IDTERECEROARL, '') <> ''
			  AND FA.IDTERCERO_FTR = HADM.IDTERECEROARL
			  AND FA.IDPLAN_FTR = COALESCE(HADM.IDPLANARL, '')
		) X
		GROUP BY GFACSOAT, IDTERCEROCA, IDPLAN


		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END CATCH
	END

	-- =============================================
	-- GUARDAR_DISTRIBUCION: Actualiza GFACSOAT en HPRED
	-- =============================================
	IF @METODO = 'GUARDAR_DISTRIBUCION'
	BEGIN
		BEGIN TRY
			SELECT @NOADMISION = NOADMISION
			FROM OPENJSON(@PARAMETROS) WITH (
				NOADMISION VARCHAR(20) '$.NOADMISION'
			)

			-- Crear tabla temporal con los items a actualizar
			SELECT 
				NOPRESTACION,
				NOITEM,
				GFACSOAT,
				CANTIDAD
			INTO #ITEMS_UPDATE
			FROM OPENJSON(@PARAMETROS, '$.ITEMS') WITH (
				NOPRESTACION VARCHAR(20) '$.NOPRESTACION',
				NOITEM INT '$.NOITEM',
				GFACSOAT INT '$.GFACSOAT',
				CANTIDAD DECIMAL(18,2) '$.CANTIDAD'
			)

			-- Validar que existan los items
			IF NOT EXISTS (SELECT 1 FROM #ITEMS_UPDATE)
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) SELECT 'No se recibieron items para actualizar'
			END

			IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END

			-- Validaciones de reglas de negocio
			-- Validaci?n 1: ADRES no puede tener el mismo responsable que Aseguradora
			IF EXISTS (
				SELECT 1 
				FROM #ITEMS_UPDATE I
				INNER JOIN HADM ON HADM.NOADMISION = @NOADMISION
				WHERE I.GFACSOAT = 2  -- ADRES
				  AND HADM.IDTERCERO = DBO.FNK_VALORVARIABLE('IDNITFONSAT')
			)
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) 
				SELECT 'ADRES no puede tener el mismo responsable que la Aseguradora. No se pueden hacer cambios hasta que se corrija esta situaci?n.'
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END

			-- Validaci?n 2: EPS no puede ser igual al responsable del accidente de tr?nsito
			IF EXISTS (
				SELECT 1 
				FROM #ITEMS_UPDATE I
				INNER JOIN HADM ON HADM.NOADMISION = @NOADMISION
				INNER JOIN AFI ON AFI.IDAFILIADO = HADM.IDAFILIADO
				WHERE I.GFACSOAT = 3  -- EPS
				  AND AFI.IDADMINISTRADORA = HADM.IDTERCERO
			)
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) 
				SELECT 'La EPS no puede ser igual al responsable del accidente de tr?nsito. Debe corregir esta situaci?n antes de continuar.'
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END

			-- Actualizar GFACSOAT, IDTERCEROCA e IDPLAN en HPRED seg?n el destino
			UPDATE HPRED
			SET GFACSOAT = I.GFACSOAT,
				IDTERCEROCA = CASE I.GFACSOAT
					WHEN 2 THEN DBO.FNK_VALORVARIABLE('IDNITFONSAT')  -- ADRES
					WHEN 1 THEN HADM.IDTERCERO  -- Aseguradora
					WHEN 3 THEN AFI.IDADMINISTRADORA  -- EPS
					WHEN 4 THEN HADM.IDTERECEROARL  -- ARL
					ELSE HPRED.IDTERCEROCA
				END,
				IDPLAN = CASE I.GFACSOAT
					WHEN 2 THEN DBO.FNK_VALORVARIABLE('IDPLANSOAT')  -- ADRES
					WHEN 1 THEN HADM.IDPLAN  -- Aseguradora
					WHEN 3 THEN AFI.IDPLAN  -- EPS
					WHEN 4 THEN HADM.IDPLANARL  -- ARL
					ELSE HPRED.IDPLAN
				END
			FROM HPRED
			INNER JOIN #ITEMS_UPDATE I ON I.NOPRESTACION = HPRED.NOPRESTACION 
									  AND I.NOITEM = HPRED.NOITEM
			INNER JOIN HPRE ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
			INNER JOIN HADM ON HADM.NOADMISION = HPRE.NOADMISION
			LEFT JOIN AFI ON AFI.IDAFILIADO = HADM.IDAFILIADO
			WHERE HPRE.NOADMISION = @NOADMISION

			DECLARE @REGISTROS_ACTUALIZADOS INT = @@ROWCOUNT

			-- Asegurar que todos los items restantes tengan GFACSOAT v?lido (por si acaso hay items nuevos)
			UPDATE HPRED
			SET GFACSOAT = 1 -- Aseguradora por defecto
			FROM HPRED
			INNER JOIN HPRE ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
			WHERE HPRE.NOADMISION = @NOADMISION
			  AND COALESCE(HPRED.FACTURADA, 0) = 0 -- Solo items no facturados
			  AND COALESCE(HPRED.NOCOBRABLE, 0) = 0 -- Solo items cobrables
			  AND HPRED.GFACSOAT IS NULL -- Solo los que est?n en null

			-- Reliquidar la admisi?n por cambios en tarifas y dem?s
			DECLARE @JSON_RELIQUIDAR NVARCHAR(MAX)
			SET @JSON_RELIQUIDAR = '{"MODELO":"HPRE","METODO":"HPRE","PARAMETROS":{"METODO":"RELIQUIDAR_ADMISION","NOADMISION":"' + @NOADMISION + '","PCUBRIMIENTO":"0","CCONTRATANTE":"0","NOCIRUGIA":"0","PREFIJOS":null,"IDAREA":null,"ELIMINA":"0"},"USUARIO":"' + @USUARIO + '"}'
			EXEC SPQ_JSON @JSON_RELIQUIDAR

			SELECT 'OK' OK, @REGISTROS_ACTUALIZADOS AS REGISTROS_ACTUALIZADOS

		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END CATCH
	END

	-- =============================================
	-- MOVER_ITEM: Mueve un item parcial (divide cantidad)
	-- =============================================
