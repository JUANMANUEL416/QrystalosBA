CREATE OR ALTER PROCEDURE SPK_GENCONSECUTIVO_PPTO
@COMPANIA VARCHAR(2),
@CONSECUTIVO VARCHAR(20),
@TABLA VARCHAR(10),
@CONSECUTIVONVO VARCHAR(20) OUTPUT
AS
DECLARE @CONTADOR_ACTUAL DECIMAL(18,0)
DECLARE @CONTADOR_NUEVO DECIMAL(18,0)
DECLARE @CONSECUTIVO_GENERADO VARCHAR(10)
DECLARE @CAMPO_CONTADOR VARCHAR(50)
BEGIN
	IF @COMPANIA IS NULL OR @COMPANIA = ''
	BEGIN
      RAISERROR('Compania es requeridad',16,1)
      RETURN
	END

	IF @TABLA IS NULL OR @TABLA = ''
	BEGIN
      RAISERROR('Tabla de destino es requeridad',16,1)
      RETURN
		
	END

	-- Determinar qué campo CONTADOR usar según la TABLA
	SET @CAMPO_CONTADOR = CASE UPPER(@TABLA)
		WHEN 'CDP' THEN 'CONTADOR_CDP'
		WHEN 'RP' THEN 'CONTADOR_RP'
		WHEN 'CXP' THEN 'CONTADOR_CXP'
		WHEN 'PAGOS' THEN 'CONTADOR_PAGOS'
		WHEN 'RECO' THEN 'CONTADOR_RR'
		WHEN 'RECA' THEN 'CONTADOR_RRR'
		ELSE NULL
	END

	IF @CAMPO_CONTADOR IS NULL
	BEGIN
      RAISERROR('Contador no Encontrado, verfique la tabla de destino',16,1)
      RETURN
	END

	-- Obtener el contador actual de la tabla PTPTO
	DECLARE @SQL NVARCHAR(MAX)
	SET @SQL = N'SELECT @CONTADOR = ISNULL(' + @CAMPO_CONTADOR + ', 0) FROM PTPTO WHERE COMPANIA = @COMPANIA AND CONSECUTIVO = @CONSECUTIVO'

	EXEC sp_executesql @SQL, 
		N'@COMPANIA VARCHAR(2), @CONSECUTIVO VARCHAR(20), @CONTADOR DECIMAL(18,0) OUTPUT',
		@COMPANIA = @COMPANIA,
		@CONSECUTIVO = @CONSECUTIVO,
		@CONTADOR = @CONTADOR_ACTUAL OUTPUT

	-- Verificar que existe el presupuesto
	IF @CONTADOR_ACTUAL IS NULL
	BEGIN
      RAISERROR('no se encontro el contador asociado',16,1)
      RETURN
	END

	-- Incrementar el contador
	SET @CONTADOR_NUEVO = @CONTADOR_ACTUAL + 1

	-- Actualizar el contador en PTPTO
	SET @SQL = N'UPDATE PTPTO SET ' + @CAMPO_CONTADOR + ' = @CONTADOR_NUEVO WHERE COMPANIA = @COMPANIA AND CONSECUTIVO = @CONSECUTIVO'

	EXEC sp_executesql @SQL,
		N'@COMPANIA VARCHAR(2), @CONSECUTIVO VARCHAR(20), @CONTADOR_NUEVO DECIMAL(18,0)',
		@COMPANIA = @COMPANIA,
		@CONSECUTIVO = @CONSECUTIVO,
		@CONTADOR_NUEVO = @CONTADOR_NUEVO

	-- Generar el consecutivo con formato: COMPANIA (2 dígitos) + número con ceros a la izquierda (8 dígitos)
	-- Ejemplo: 0100000001
	SET @CONSECUTIVONVO = RIGHT('00' + @COMPANIA, 2) + RIGHT('00000000' + CAST(@CONTADOR_NUEVO AS VARCHAR(8)), 8)
END

