   SELECT COMPANIA,CCOSTO, CONSECUTIVO,ANO,@MES,IDTIPOMOV,CLASE,RUBRO, SFA, SI01, TDB01, TCR01, MDB01, MCR01, SF01, CDP01, RP01, CXP01, PAG01, SI02, TDB02, TCR02, MDB02, MCR02, SF02, CDP02, RP02, CXP02, PAG02, 
         SI03, TDB03, TCR03, MDB03, MCR03, SF03, CDP03, RP03, CXP03, PAG03, SI04, TDB04, TCR04, MDB04, MCR04, SF04, CDP04, RP04, CXP04, PAG04, SI05, TDB05, TCR05, MDB05, MCR05, SF05, CDP05, 
         RP05, CXP05, PAG05, SI06, TDB06, TCR06, MDB06, MCR06, SF06, CDP06, RP06, CXP06, PAG06, SI07, TDB07, TCR07, MDB07, MCR07, SF07, CDP07, RP07, CXP07, PAG07, SI08, TDB08, TCR08, MDB08, 
