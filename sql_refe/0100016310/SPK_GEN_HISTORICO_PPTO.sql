   SELECT COMPANIA, CONSECUTIVO, CDP,@MES, ITEM, CLASE, RUBRO, RECURSO, IDTIPOMOV, OBJETIVO, VALOR, VALOR_RP, SALDO, SOLICITANTE, RUBRO_ID
   FROM PTCDPD
   WHERE EXISTS(SELECT * FROM PTCDPH WHERE PTCDPH.COMPANIA=PTCDPD.COMPANIA
                                      AND  PTCDPH.CONSECUTIVO=PTCDPD.CONSECUTIVO
                                      AND  PTCDPH.CDP=PTCDPD.CDP
                                      AND  PTCDPH.CONSECUTIVO=@CONSECUTIVO
                                      AND  PTCDPH.MES=@MES)

   PRINT'PTRP...'
   INSERT INTO PTRPH (COMPANIA, CONSECUTIVO, CCOSTO, CDP, RP, MES, OBJETIVO, VALOR, SALDO, SOLICITANTE, CNSFCOM, CNSFCXP, IDTERCERO, NODOCUMENTO, FECHARP, FECHAPLAZO, ESTADO)
   SELECT COMPANIA, CONSECUTIVO, CCOSTO, CDP, RP,@MES, OBJETIVO, VALOR, SALDO, SOLICITANTE, CNSFCOM, CNSFCXP, IDTERCERO, NODOCUMENTO, FECHARP, FECHAPLAZO, ESTADO
   FROM PTRP
   WHERE COMPANIA=@COMPANIA
   AND CONSECUTIVO=@CONSECUTIVO
   AND FECHARP<DBO.FNK_DIA_DEL_MES(@ANO,@MES,'ULTIMO')

   INSERT INTO PTRPDH(COMPANIA, CONSECUTIVO, CDP, RP, MES, CLASE, RUBRO, OBJETIVO, VALOR, VALOR_CXP, SALDO, RUBRO_ID)
   SELECT COMPANIA, CONSECUTIVO, CDP, RP, @MES, CLASE, RUBRO, OBJETIVO, VALOR, VALOR_CXP, SALDO, RUBRO_ID
   FROM PTRPD
   WHERE EXISTS(SELECT * FROM PTRPH WHERE PTRPH.COMPANIA=PTRPD.COMPANIA
                                      AND  PTRPH.CONSECUTIVO=PTRPD.CONSECUTIVO
                                      AND  PTRPH.CDP=PTRPD.CDP
                                      AND  PTRPH.RP=PTRPD.RP
                                      AND  PTRPH.CONSECUTIVO=@CONSECUTIVO
                                      AND  PTRPH.MES=@MES)


   PRINT'PTCXP...'
   INSERT INTO PTCXPH(COMPANIA, CCOSTO, CONSECUTIVO, CDP, RP, CNSCXP, MES, FECHA, VALOR, SALDO, OBSERVACION, ESTADO)   
   SELECT COMPANIA , CCOSTO, CONSECUTIVO, CDP, RP, CNSCXP,@MES, FECHA, VALOR, SALDO, OBSERVACION, ESTADO
   FROM PTCXP
   WHERE COMPANIA=@COMPANIA
   AND CONSECUTIVO=@CONSECUTIVO
   AND FECHA<DBO.FNK_DIA_DEL_MES(@ANO,@MES,'ULTIMO')

   INSERT INTO PTCXPDH(COMPANIA, CONSECUTIVO, CDP, RP, CNSCXP, ITEM, MES, CLASE, RUBRO, VALOR, VALOR_PAG, SALDO, OBSERVACION,ESTADO,RUBRO_ID)
   SELECT COMPANIA, CONSECUTIVO, CDP, RP, CNSCXP, ITEM,@MES, CLASE, RUBRO, VALOR, VALOR_PAG, SALDO, OBSERVACION, ESTADO, RUBRO_ID
   FROM PTCXPD
   WHERE EXISTS(SELECT * FROM PTCXPH WHERE PTCXPH.COMPANIA=PTCXPD.COMPANIA
                                      AND  PTCXPH.CONSECUTIVO=PTCXPD.CONSECUTIVO
                                      AND  PTCXPH.CDP=PTCXPD.CDP
                                      AND  PTCXPH.RP=PTCXPD.RP
                                      AND  PTCXPH.CNSCXP=PTCXPD.CNSCXP
                                      AND  PTCXPH.CONSECUTIVO=@CONSECUTIVO
                                      AND  PTCXPH.MES=@MES)

   PRINT 'PTPAG'
   INSERT INTO PTPAGH(COMPANIA, CCOSTO, CONSECUTIVO, CDP, RP, CNSCXP, CNSPAGO, MES, OBSERVACION, VALOR, ORIGENPAGO, FECHA, CODCAJA, CNSFACJ, BANCO, SUCURSAL, CTA_BCO, ITEM_BMOV, ESTADO)
   SELECT COMPANIA, CCOSTO, CONSECUTIVO, CDP, RP, CNSCXP, CNSPAGO, @MES, OBSERVACION, VALOR, ORIGENPAGO, FECHA, CODCAJA, CNSFACJ, BANCO, SUCURSAL, CTA_BCO, ITEM_BMOV, ESTADO
   FROM PTPAG
   WHERE COMPANIA=@COMPANIA
   AND CONSECUTIVO=@CONSECUTIVO
   AND FECHA<DBO.FNK_DIA_DEL_MES(@ANO,@MES,'ULTIMO')


   INSERT INTO PTPAGDH(COMPANIA, CONSECUTIVO, CDP, RP, CNSCXP, CNSPAGO, MES, ITEM, CLASE, RUBRO, VALOR, OBSERVACION, RUBRO_ID)
   SELECT COMPANIA, CONSECUTIVO, CDP, RP, CNSCXP, CNSPAGO,@MES,
   ROW_NUMBER() OVER(ORDER  BY COMPANIA, CONSECUTIVO, CDP, RP, CNSCXP, CNSPAGO  ASC),
   CLASE, RUBRO, SUM(VALOR), OBSERVACION, RUBRO_ID
   FROM PTPAGD
   WHERE EXISTS(SELECT * FROM PTPAGH WHERE PTPAGH.COMPANIA=PTPAGD.COMPANIA
                                      AND  PTPAGH.CONSECUTIVO=PTPAGD.CONSECUTIVO
                                      AND  PTPAGH.CDP=PTPAGD.CDP
                                      AND  PTPAGH.RP=PTPAGD.RP
                                      AND  PTPAGH.CNSPAGO=PTPAGH.CNSPAGO
                                      AND  PTPAGH.CNSCXP=PTPAGD.CNSCXP
                                      AND  PTPAGH.CONSECUTIVO=@CONSECUTIVO
                                      AND  PTPAGH.MES=@MES)
  GROUP BY COMPANIA, CONSECUTIVO, CDP, RP, CNSCXP, CNSPAGO, CLASE, RUBRO, OBSERVACION, RUBRO_ID

   PRINT 'ACUMULADOS..... Ingresos.......'

   INSERT INTO PTPTOIH (COMPANIA, CCOSTO, CONSECUTIVO, ANO, MES, IDTIPOMOV, CLASE, RUBRO, SFA, SI01, TDB01, TCR01, MDB01, MCR01, SF01, RECO01, RECA01, SI02, TDB02, TCR02, MDB02, MCR02, SF02, 
                        RECO02, RECA02,  SI03, TDB03, TCR03, MDB03, MCR03, SF03, RECO03, RECA03, SI04, TDB04, TCR04, MDB04, MCR04, SF04, RECO04, RECA04, SI05, TDB05, TCR05, MDB05, MCR05, SF05, 
                        RECO05, RECA05, SI06, TDB06,  TCR06, MDB06, MCR06, SF06, RECO06, RECA06, SI07, TDB07, TCR07, MDB07, MCR07, SF07, RECO07, RECA07, SI08, TDB08, TCR08, MDB08, MCR08, SF08, 
                        RECO08, RECA08, SI09, TDB09, TCR09,  MDB09, MCR09, SF09, RECO09, RECA09, SI10, TDB10, TCR10, MDB10, MCR10, SF10, RECO10, RECA10, SI11, TDB11, TCR11, MDB11, MCR11, SF11, 
                        RECO11, RECA11, SI12, TDB12, TCR12, MDB12, MCR12,  SF12, RECO12, RECA12, SFRECO, SFRECA, MSALDOXMES, DISRECO01, DISRECO02, DISRECO03, DISRECO04, DISRECO05, DISRECO06, 
                        DISRECO07, DISRECO08, DISRECO09, DISRECO10, DISRECO11, DISRECO12,  DISRECA01, DISRECA02, DISRECA03, DISRECA04, DISRECA05, DISRECA06, DISRECA07, DISRECA08, DISRECA09, 
                        DISRECA10, DISRECA11, DISRECA12, RUBRO_ID)
   SELECT COMPANIA, CCOSTO, CONSECUTIVO, ANO, @MES, COALESCE(IDTIPOMOV,'I'), CLASE, RUBRO, SFA, SI01, TDB01, TCR01, MDB01, MCR01, SF01, RECO01, RECA01, SI02, TDB02, TCR02, MDB02, MCR02, SF02, 
                        RECO02, RECA02,  SI03, TDB03, TCR03, MDB03, MCR03, SF03, RECO03, RECA03, SI04, TDB04, TCR04, MDB04, MCR04, SF04, RECO04, RECA04, SI05, TDB05, TCR05, MDB05, MCR05, SF05, 
                        RECO05, RECA05, SI06, TDB06,  TCR06, MDB06, MCR06, SF06, RECO06, RECA06, SI07, TDB07, TCR07, MDB07, MCR07, SF07, RECO07, RECA07, SI08, TDB08, TCR08, MDB08, MCR08, SF08, 
                        RECO08, RECA08, SI09, TDB09, TCR09,  MDB09, MCR09, SF09, RECO09, RECA09, SI10, TDB10, TCR10, MDB10, MCR10, SF10, RECO10, RECA10, SI11, TDB11, TCR11, MDB11, MCR11, SF11, 
                        RECO11, RECA11, SI12, TDB12, TCR12, MDB12, MCR12,  SF12, RECO12, RECA12, SFRECO, SFRECA, MSALDOXMES, DISRECO01, DISRECO02, DISRECO03, DISRECO04, DISRECO05, DISRECO06, 
                        DISRECO07, DISRECO08, DISRECO09, DISRECO10, DISRECO11, DISRECO12,  DISRECA01, DISRECA02, DISRECA03, DISRECA04, DISRECA05, DISRECA06, DISRECA07, DISRECA08, DISRECA09, 
                        DISRECA10, DISRECA11, DISRECA12, RUBRO_ID
   FROM PTPTOI
   WHERE COMPANIA=@COMPANIA
   AND CONSECUTIVO=@CONSECUTIVO


   PRINT 'ACUMULADOS..... Gastos.......'

   INSERT INTO PTPTOGH( COMPANIA, CCOSTO, CONSECUTIVO, ANO, MES, IDTIPOMOV, CLASE, RUBRO, SFA, SI01, TDB01, TCR01, MDB01, MCR01, SF01, CDP01, RP01, CXP01, PAG01, SI02, TDB02, TCR02, MDB02, MCR02, SF02, CDP02, 
                        RP02, CXP02, PAG02, SI03, TDB03, TCR03, MDB03, MCR03, SF03, CDP03, RP03, CXP03, PAG03, SI04, TDB04, TCR04, MDB04, MCR04, SF04, CDP04, RP04, CXP04, PAG04, SI05, TDB05, TCR05, MDB05, 
                        MCR05, SF05, CDP05, RP05, CXP05, PAG05, SI06, TDB06, TCR06, MDB06, MCR06, SF06, CDP06, RP06, CXP06, PAG06, SI07, TDB07, TCR07, MDB07, MCR07, SF07, CDP07, RP07, CXP07, PAG07, 
