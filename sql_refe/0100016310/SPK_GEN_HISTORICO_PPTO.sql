IF EXISTS (SELECT NAME FROM SYSOBJECTS WHERE NAME = 'SPK_GEN_HISTORICO_PPTO' AND TYPE = 'P')
BEGIN
   DROP PROCEDURE SPK_GEN_HISTORICO_PPTO 
END
GO
CREATE PROCEDURE DBO.SPK_GEN_HISTORICO_PPTO  
@COMPANIA  VARCHAR(2), 
@ANO       VARCHAR(4),
@MES       INT 
WITH ENCRYPTION
AS  
DECLARE @EXISTE INT
DECLARE @CONSECUTIVO VARCHAR(20)
BEGIN  
   PRINT 'EMPIEZO'
   SELECT @CONSECUTIVO=CONSECUTIVO FROM PTPTO 
   WHERE FECHAINI<=CAST('01/'+CASE WHEN @MES<10 THEN '0'+CAST(@MES AS VARCHAR(2)) ELSE CAST(@MES AS VARCHAR(2)) END+'/'+CAST(@ANO AS VARCHAR(4)) AS DATETIME )
   AND FECHAFIN>CAST('01/'+CASE WHEN @MES<10 THEN '0'+CAST(@MES AS VARCHAR(2)) ELSE CAST(@MES AS VARCHAR(2)) END+'/'+CAST(@ANO AS VARCHAR(4)) AS DATETIME )

   PRINT 'SE LIMPIAN LAS TABLAS'

   DELETE PTRECOH WHERE CONSECUTIVO=@CONSECUTIVO AND COMPANIA=@COMPANIA AND MES=@MES
   DELETE PTRECODH WHERE CONSECUTIVO=@CONSECUTIVO AND COMPANIA=@COMPANIA AND MES=@MES

   DELETE PTRECAH WHERE CONSECUTIVO=@CONSECUTIVO AND COMPANIA=@COMPANIA AND MES=@MES
   DELETE PTRECADH WHERE CONSECUTIVO=@CONSECUTIVO AND COMPANIA=@COMPANIA AND MES=@MES

   DELETE PTCDPH WHERE CONSECUTIVO=@CONSECUTIVO AND COMPANIA=@COMPANIA AND MES=@MES
   DELETE PTCDPDH WHERE CONSECUTIVO=@CONSECUTIVO AND COMPANIA=@COMPANIA AND MES=@MES

   DELETE PTRPH WHERE CONSECUTIVO=@CONSECUTIVO AND COMPANIA=@COMPANIA AND MES=@MES
   DELETE PTRPDH WHERE CONSECUTIVO=@CONSECUTIVO AND COMPANIA=@COMPANIA AND MES=@MES

   DELETE PTCXPH WHERE CONSECUTIVO=@CONSECUTIVO AND COMPANIA=@COMPANIA AND MES=@MES
   DELETE PTCXPDH WHERE CONSECUTIVO=@CONSECUTIVO AND COMPANIA=@COMPANIA AND MES=@MES

   DELETE PTPAGH WHERE CONSECUTIVO=@CONSECUTIVO AND COMPANIA=@COMPANIA AND MES=@MES
   DELETE PTPAGDH WHERE CONSECUTIVO=@CONSECUTIVO AND COMPANIA=@COMPANIA AND MES=@MES

   DELETE PTPTOIH WHERE CONSECUTIVO=@CONSECUTIVO AND COMPANIA=@COMPANIA AND MES=@MES
   DELETE PTPTOGH WHERE CONSECUTIVO=@CONSECUTIVO AND COMPANIA=@COMPANIA AND MES=@MES

   PRINT 'RECONOCIMIENTOS....'


   INSERT INTO PTRECOH(COMPANIA, CCOSTO, CONSECUTIVO, RECO, MES, OBJETIVO, VALOR, SALDO, CNSFCXC, IDTERCERO, FECHA, ESTADO, N_FACTURA, CNSFTR, TIPO, CLASE)
   SELECT COMPANIA,CCOSTO, CONSECUTIVO, RECO,@MES, OBJETIVO, VALOR, SALDO, CNSFCXC, IDTERCERO, FECHA, ESTADO, N_FACTURA, CNSFTR, TIPO, CLASE 
   FROM PTRECO
   WHERE COMPANIA=@COMPANIA
   AND CONSECUTIVO=@CONSECUTIVO
   AND FECHA<DBO.FNK_DIA_DEL_MES(@ANO,@MES,'ULTIMO')

   INSERT INTO PTRECODH(COMPANIA, CONSECUTIVO, RECO, MES, CLASE, RUBRO, OBJETIVO, VALOR, VALOR_RECA, SALDO, VLR_NOTAS, RUBRO_ID)
   SELECT COMPANIA, CONSECUTIVO, RECO,@MES, CLASE, RUBRO, OBJETIVO, VALOR, VALOR_RECA, SALDO, VLR_NOTAS, RUBRO_ID
   FROM PTRECOD
   WHERE EXISTS(SELECT * FROM PTRECOH WHERE PTRECOH.COMPANIA=PTRECOD.COMPANIA
                                     AND  PTRECOH.CONSECUTIVO=PTRECOD.CONSECUTIVO
                                     AND  PTRECOH.RECO=PTRECOD.RECO
                                     AND  PTRECOH.CONSECUTIVO=@CONSECUTIVO
                                     AND  PTRECOH.MES=@MES)

   PRINT 'RECAUDOS....'

   INSERT INTO PTRECAH(COMPANIA, CCOSTO, CONSECUTIVO, RECO, CNSPAGO, MES, OBSERVACION, VALOR, FECHA, ORIGENPAGO, CODCAJA, CNSFACJ, BANCO, SUCURSAL, CTA_BCO, ITEM_BMOV, ESTADO, TIPO)
   SELECT COMPANIA,CCOSTO, CONSECUTIVO, RECO, CNSPAGO,@MES, OBSERVACION, VALOR, FECHA, ORIGENPAGO, CODCAJA, CNSFACJ, BANCO, SUCURSAL, CTA_BCO, ITEM_BMOV, ESTADO,  TIPO
   FROM PTRECA
   WHERE COMPANIA=@COMPANIA
   AND CONSECUTIVO=@CONSECUTIVO
   AND FECHA<DBO.FNK_DIA_DEL_MES(@ANO,@MES,'ULTIMO')+1
   AND EXISTS(SELECT * FROM PTRECOH WHERE PTRECOH.RECO=PTRECA.RECO
                                    AND   PTRECOH.CONSECUTIVO=PTRECA.CONSECUTIVO
                                    AND   PTRECOH.COMPANIA=PTRECA.COMPANIA
                                    AND   PTRECOH.CONSECUTIVO=@CONSECUTIVO
                                    AND   PTRECOH.MES=@MES)


   INSERT INTO PTRECADH(COMPANIA, CONSECUTIVO, RECO, CNSPAGO, MES, CLASE, RUBRO, OBSERVACION, VALOR, RUBRO_ID)
   SELECT COMPANIA, CONSECUTIVO, RECO, CNSPAGO,@MES, CLASE, RUBRO, OBSERVACION, VALOR, RUBRO_ID
   FROM PTRECAD
   WHERE EXISTS(SELECT * FROM PTRECAH WHERE PTRECAH.COMPANIA=PTRECAD.COMPANIA
                                      AND  PTRECAH.CONSECUTIVO=PTRECAD.CONSECUTIVO
                                      AND  PTRECAH.RECO=PTRECAD.RECO
                                      AND  PTRECAH.CNSPAGO=PTRECAD.CNSPAGO
                                      AND  PTRECAH.CONSECUTIVO=@CONSECUTIVO
                                      AND  PTRECAH.MES=@MES)



   PRINT'GASTOS....'
   PRINT'CDP...'

   INSERT INTO PTCDPH (COMPANIA, CCOSTO, CONSECUTIVO, MES, CDP, IDDEP, OBJETIVO, VALOR, SALDO, FECHAEXPEDICION, FECHAVENCE, FECHAREINTEGRO, AUTORIZADOR, ESTADO, CNSPTSCDP)
   SELECT COMPANIA,CCOSTO, CONSECUTIVO,@MES, CDP, IDDEP, OBJETIVO, VALOR, SALDO, FECHAEXPEDICION, FECHAVENCE, FECHAREINTEGRO, AUTORIZADOR, ESTADO,  CNSPTSCDP
   FROM PTCDP
   WHERE COMPANIA=@COMPANIA
   AND CONSECUTIVO=@CONSECUTIVO
   AND FECHAEXPEDICION<DBO.FNK_DIA_DEL_MES(@ANO,@MES,'ULTIMO')

