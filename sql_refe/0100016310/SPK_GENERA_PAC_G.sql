IF EXISTS (SELECT NAME FROM SYSOBJECTS WHERE NAME = 'SPK_GENERA_PAC_G' AND TYPE = 'P')
   DROP PROCEDURE SPK_GENERA_PAC_G
GO
CREATE PROCEDURE DBO.SPK_GENERA_PAC_G 
@CNSRPDX     VARCHAR(20),
@CONSECUTIVO VARCHAR(20),
@MES SMALLINT
WITH ENCRYPTION
AS 
BEGIN 
   INSERT INTO RPDX(CNS,ID1,ID2,ID3,STRINGMEDIO4,ID5,STRINGMEDIO1,VALOR1,VALOR2,VALOR3,
                    VALOR4,VALOR5,VALOR6,VALOR7,VALOR8,VALOR9,VALOR10,VALOR11,VALOR12)
   SELECT @CNSRPDX,COMPANIA,MES,IDTIPOMOV,RUBRO,RECURSO,NOMRUBRO,SUM(PAC_INI),SUM(RESAGO),SUM(VLR_TDB),SUM(VLR_TCR),SUM(VLR_MDB),SUM(VLR_MCR),
          SUM(PAC_DEF),SUM(VLR_RP_MES),SUM(VLR_CXP_MES),SUM(VLR_PAG_ACU),SUM(VLR_PAG_MES),SUM(SALDO_PAC)
   FROM   dbo.FNK_PAC_G_CONSEC(@MES,@CONSECUTIVO)
   GROUP BY COMPANIA,MES,IDTIPOMOV,RUBRO,RECURSO,NOMRUBRO
   ORDER BY   COMPANIA,MES,IDTIPOMOV,RUBRO                  
END 

