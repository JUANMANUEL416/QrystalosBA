IF EXISTS (SELECT NAME FROM SYSOBJECTS WHERE NAME = 'SPK_DEL_HISTORICO_PPTO' AND TYPE = 'P')
BEGIN
   DROP PROCEDURE SPK_DEL_HISTORICO_PPTO 
END
GO
CREATE PROCEDURE DBO.SPK_DEL_HISTORICO_PPTO  
@COMPANIA  VARCHAR(2), 
@ANO       VARCHAR(4),
@MES       INT 
WITH ENCRYPTION
AS
DECLARE @CONSECUTIVO VARCHAR(20)
BEGIN  
   SELECT @CONSECUTIVO=CONSECUTIVO FROM PTPTO 
   WHERE FECHAINI<=CAST('01/'+CASE WHEN @MES<10 THEN '0'+CAST(@MES AS VARCHAR(2)) ELSE CAST(@MES AS VARCHAR(2)) END+'/'+CAST(@ANO AS VARCHAR(4)) AS DATETIME )
   AND FECHAFIN>CAST('01/'+CASE WHEN @MES<10 THEN '0'+CAST(@MES AS VARCHAR(2)) ELSE CAST(@MES AS VARCHAR(2)) END+'/'+CAST(@ANO AS VARCHAR(4)) AS DATETIME )

   DELETE PTRECODH WHERE COMPANIA=@COMPANIA AND CONSECUTIVO=@CONSECUTIVO AND MES=@MES
   DELETE PTRECOH  WHERE COMPANIA=@COMPANIA AND CONSECUTIVO=@CONSECUTIVO AND MES=@MES
   DELETE PTRECADH WHERE COMPANIA=@COMPANIA AND CONSECUTIVO=@CONSECUTIVO AND MES=@MES
   DELETE PTRECAH  WHERE COMPANIA=@COMPANIA AND CONSECUTIVO=@CONSECUTIVO AND MES=@MES
   DELETE PTCDPDH  WHERE COMPANIA=@COMPANIA AND CONSECUTIVO=@CONSECUTIVO AND MES=@MES
   DELETE PTCDPH   WHERE COMPANIA=@COMPANIA AND CONSECUTIVO=@CONSECUTIVO AND MES=@MES
   DELETE PTRPDH   WHERE COMPANIA=@COMPANIA AND CONSECUTIVO=@CONSECUTIVO AND MES=@MES
   DELETE PTRPH    WHERE COMPANIA=@COMPANIA AND CONSECUTIVO=@CONSECUTIVO AND MES=@MES
   DELETE PTCXPDH  WHERE COMPANIA=@COMPANIA AND CONSECUTIVO=@CONSECUTIVO AND MES=@MES
   DELETE PTCXPH   WHERE COMPANIA=@COMPANIA AND CONSECUTIVO=@CONSECUTIVO AND MES=@MES
   DELETE PTPAGDH  WHERE COMPANIA=@COMPANIA AND CONSECUTIVO=@CONSECUTIVO AND MES=@MES
   DELETE PTPAGH   WHERE COMPANIA=@COMPANIA AND CONSECUTIVO=@CONSECUTIVO AND MES=@MES
   DELETE PTPTOGH  WHERE COMPANIA=@COMPANIA AND CONSECUTIVO=@CONSECUTIVO AND MES=@MES
   DELETE PTPTOIH  WHERE COMPANIA=@COMPANIA AND CONSECUTIVO=@CONSECUTIVO AND MES=@MES
END

