IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='FNK_CIERRE_PERIODO_PPTO' AND XTYPE='FN')
BEGIN
   DROP FUNCTION FNK_CIERRE_PERIODO_PPTO
END
GO
CREATE FUNCTION DBO.FNK_CIERRE_PERIODO_PPTO(@COMPANIA VARCHAR(2), @ANO INT , @MES INT,@CCION VARCHAR(2))
RETURNS VARCHAR(500)
AS
BEGIN
	DECLARE @ESTADO VARCHAR(2)
	DECLARE @CUANTOS INT=0
	DECLARE @MESNAJE VARCHAR(500)
	IF @CCION='A'
	BEGIN
		SELECT @ESTADO=COALESCE(CERRADO_PPTO,'') FROM PRI WHERE ANO=@ANO AND MES=@MES AND COMPANIA=@COMPANIA
		IF COALESCE(@ESTADO,'')=''
		BEGIN
			SELECT @MESNAJE='NO SE A ABIERTO EL PERIODO PRESUPUESTAL'
		END
	END
	ELSE
	BEGIN
		SELECT @MESNAJE=' '
		SELECT @CUANTOS=COUNT(*) FROM PTRECO WHERE ESTADO='NoConfirmado' AND YEAR(FECHA)=@ANO AND MONTH(FECHA)=@MES AND COMPANIA=@COMPANIA
		IF @CUANTOS>0
		BEGIN
			SELECT @MESNAJE=@MESNAJE+' EXISTEN RECONOCIMIENTOS ',@CUANTOS=0
		END
		SELECT @CUANTOS=COUNT(*) FROM PTRECA WHERE ESTADO='NoConfirmado' AND YEAR(FECHA)=@ANO AND MONTH(FECHA)=@MES AND COMPANIA=@COMPANIA
		IF @CUANTOS>0
		BEGIN
			SELECT @MESNAJE=@MESNAJE+' EXISTEN RECUADOS ',@CUANTOS=0
		END
		SELECT @CUANTOS=COUNT(*) FROM PTCDP WHERE ESTADO='NoConfirmado' AND YEAR(FECHAEXPEDICION)=@ANO AND MONTH(FECHAEXPEDICION)=@MES AND COMPANIA=@COMPANIA
		IF @CUANTOS>0
		BEGIN
			SELECT @MESNAJE=@MESNAJE+' EXISTEN CDP´S ',@CUANTOS=0
		END
		SELECT @CUANTOS=COUNT(*) FROM PTRP WHERE ESTADO='NoConfirmado' AND YEAR(FECHARP)=@ANO AND MONTH(FECHARP)=@MES AND COMPANIA=@COMPANIA
		IF @CUANTOS>0
		BEGIN
			SELECT @MESNAJE=@MESNAJE+' EXISTEN RP´S ',@CUANTOS=0
		END
		SELECT @CUANTOS=COUNT(*) FROM PTCXP WHERE ESTADO='NoConfirmado' AND YEAR(FECHA)=@ANO AND MONTH(FECHA)=@MES AND COMPANIA=@COMPANIA
		IF @CUANTOS>0
		BEGIN
			SELECT @MESNAJE=@MESNAJE+' EXISTEN CXP ',@CUANTOS=0
		END
		SELECT @CUANTOS=COUNT(*) FROM PTPAG WHERE ESTADO='NoConfirmado' AND YEAR(FECHA)=@ANO AND MONTH(FECHA)=@MES AND COMPANIA=@COMPANIA
		IF @CUANTOS>0
		BEGIN
			SELECT @MESNAJE=@MESNAJE+' EXISTEN PAGOSCXP ',@CUANTOS=0
		END
	END
	IF LEN(@MESNAJE)>5
	BEGIN
		SELECT @MESNAJE=@MESNAJE+'SIN CONFIRMAR SE DEBEN CONFIRMAR PRIMERO ANTES DE HACER CIERRE'
	END
	ELSE
	BEGIN
		SELECT @MESNAJE='OK'
	END
	RETURN (@MESNAJE)
END

