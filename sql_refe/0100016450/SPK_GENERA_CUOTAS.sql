CREATE OR ALTER PROCEDURE DBO.SPK_GENERA_CUOTAS @IDTRANSACCION VARCHAR(6), @NUMDOCUMENTO VARCHAR(20), @NUMCUOTAS DECIMAL(14, 2), @CUOTAACT DECIMAL(14, 2), @VLRPRESTAMO 
	DECIMAL(14, 2), @FECHAPAGO DATETIME
	WITH ENCRYPTION
AS
DECLARE @VLRCUOTA DECIMAL(14, 2)
DECLARE @SLDINICIAL DECIMAL(14, 2)
DECLARE @INTERESES DECIMAL(14, 2)
DECLARE @MANINTERESES SMALLINT
DECLARE @SLDFINAL DECIMAL(14, 2)
DECLARE @TASAINTERES DECIMAL(8, 4)
DECLARE @TIPOINTERES VARCHAR(20)
DECLARE @PERIODO VARCHAR(20)
DECLARE @PRESTAMO DECIMAL(14, 2)

-- inicio                                
BEGIN -- 10
	SELECT @VLRCUOTA = VLRCUOTA, @SLDINICIAL = VLRSALDO, @INTERESES = (TASAINTERES / 100 * VLRSALDO), @SLDFINAL = VLRSALDO + (TASAINTERES / 100 * VLRSALDO
			) - VLRCUOTA, @TASAINTERES = TASAINTERES, @TIPOINTERES = TIPOINTERES, @PERIODO = PERIODO, @MANINTERESES = MANINTERESES, @PRESTAMO = VLRPRESTAMO
	FROM PRS
	WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO

	SELECT TOP 1 @FECHAPAGO = FECHAPAGO, @CUOTAACT = NUMCUOTA
	FROM PRSD
	WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO AND ESTADO = 'Pagada'
	ORDER BY FECHAPAGO DESC

	IF ISNULL(@CUOTAACT, 0) > 0
	BEGIN
		IF @PERIODO = 'Anual'
			SET @FECHAPAGO = DATEADD(YEAR, 1, @FECHAPAGO)
		ELSE IF @PERIODO = 'Mensual'
			SET @FECHAPAGO = DATEADD(MONTH, 1, @FECHAPAGO)
		ELSE IF @PERIODO = 'Quincenal'
		BEGIN
			IF DAY(@FECHAPAGO) = 1
				SET @FECHAPAGO = '16/' + STR(MONTH(@FECHAPAGO)) + '/' + STR(YEAR(@FECHAPAGO)) --DATEADD(day, 15, @FECHAPAGO )
			ELSE
				SET @FECHAPAGO = DBO.FNK_DIA_DEL_MES(YEAR(@FECHAPAGO), MONTH(@FECHAPAGO), 'PRIMERO')
		END
	END

	IF @FECHAPAGO IS NULL
	BEGIN
		SET DATEFORMAT YMD

		SELECT @FECHAPAGO = CONVERT(VARCHAR(20), GETDATE(), 112), @CUOTAACT = 0
	END

	SET DATEFORMAT DMY

	IF @NUMCUOTAS > 0 AND @VLRPRESTAMO >= 0
	BEGIN
		DELETE
		FROM PRSD
		WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO AND NUMCUOTA > @CUOTAACT AND ESTADO <> 'Pagada'
	END

	IF @TIPOINTERES = 'Continuo' AND @MANINTERESES = 1
	BEGIN
		SET @CUOTAACT = @CUOTAACT + 1

		WHILE (@NUMCUOTAS) >= @CUOTAACT
		BEGIN
			INSERT INTO PRSD (NUMDOCUMENTO, IDTRANSACCION, NUMCUOTA, SALDOANT, VLRCUOTA, VLRINTERESES, SALDOACT, ESTADO, FECHAPAGO)
			SELECT @NUMDOCUMENTO, @IDTRANSACCION, @CUOTAACT, @SLDINICIAL, @VLRCUOTA, @INTERESES, @SLDFINAL, 'PorPagar', @FECHAPAGO

			SELECT @SLDINICIAL = @SLDFINAL

			SELECT @INTERESES = (@TASAINTERES / 100 * @SLDINICIAL)

			SELECT @SLDFINAL = @SLDINICIAL + @INTERESES - @VLRCUOTA

			SET @CUOTAACT = @CUOTAACT + 1

			IF @PERIODO = 'Anual'
				SET @FECHAPAGO = DATEADD(YEAR, 1, @FECHAPAGO)

			IF @PERIODO = 'Mensual'
				SET @FECHAPAGO = DATEADD(MONTH, 1, @FECHAPAGO)

			IF @PERIODO = 'Quincenal'
			BEGIN
				IF DAY(@FECHAPAGO) = 1
					SET @FECHAPAGO = '16/' + STR(MONTH(@FECHAPAGO)) + '/' + STR(YEAR(@FECHAPAGO)) --DATEADD(day, 15, @FECHAPAGO )
				ELSE
					SET @FECHAPAGO = DBO.FNK_DIA_DEL_MES(YEAR(@FECHAPAGO), MONTH(@FECHAPAGO), 'PRIMERO')
			END

			CONTINUE
		END
	END

	IF @TIPOINTERES = 'Simple' AND @MANINTERESES = 1
	BEGIN
		PRINT 'Simple'

		SELECT @INTERESES = VLRINTERESES / (NUMCUOTAS - @CUOTAACT)
		FROM PRS
		WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO

		SET @CUOTAACT = @CUOTAACT + 1

		WHILE (@NUMCUOTAS) >= @CUOTAACT
		BEGIN
			INSERT INTO PRSD (NUMDOCUMENTO, IDTRANSACCION, NUMCUOTA, SALDOANT, VLRCUOTA, VLRINTERESES, SALDOACT, ESTADO, FECHAPAGO)
			SELECT @NUMDOCUMENTO, @IDTRANSACCION, @CUOTAACT, @SLDINICIAL, @VLRCUOTA, @INTERESES, @SLDFINAL, 'PorPagar', @FECHAPAGO

			SELECT @SLDINICIAL = @SLDFINAL

			SELECT @SLDFINAL = @SLDINICIAL + @INTERESES - @VLRCUOTA

			SET @CUOTAACT = @CUOTAACT + 1

			IF @PERIODO = 'Anual'
				SET @FECHAPAGO = DATEADD(YEAR, 1, @FECHAPAGO)

			IF @PERIODO = 'Mensual'
				SET @FECHAPAGO = DATEADD(MONTH, 1, @FECHAPAGO)

			IF @PERIODO = 'Quincenal'
			BEGIN
				IF DAY(@FECHAPAGO) = 1
					SET @FECHAPAGO = '16/' + STR(MONTH(@FECHAPAGO)) + '/' + STR(YEAR(@FECHAPAGO)) --DATEADD(day, 15, @FECHAPAGO )
				ELSE
					SET @FECHAPAGO = DBO.FNK_DIA_DEL_MES(YEAR(@FECHAPAGO), MONTH(@FECHAPAGO), 'PRIMERO')
			END

			CONTINUE
		END
	END

	--EXEC SPK_GENERA_CUOTAS 'PRS','0000100000032','10',0 , '900000','20040701'
	PRINT @FECHAPAGO

	IF @MANINTERESES = 0
	BEGIN
		SELECT @VLRCUOTA = round(@VLRPRESTAMO / (@NUMCUOTAS - @CUOTAACT), 0)

		SET @CUOTAACT = @CUOTAACT + 1

		WHILE (@NUMCUOTAS) >= @CUOTAACT
		BEGIN
			SELECT @INTERESES = 0

			IF @CUOTAACT > 1
				SELECT @SLDINICIAL = @PRESTAMO - SUM(VLRCUOTA - VLRINTERESES)
				FROM PRSD
				WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO AND NUMCUOTA < @CUOTAACT

			IF @CUOTAACT = 1
				SELECT @SLDINICIAL = @VLRPRESTAMO

			SELECT @SLDFINAL = @SLDINICIAL + @INTERESES - @VLRCUOTA

			INSERT INTO PRSD (NUMDOCUMENTO, IDTRANSACCION, NUMCUOTA, SALDOANT, VLRCUOTA, VLRINTERESES, SALDOACT, ESTADO, FECHAPAGO)
			SELECT @NUMDOCUMENTO, @IDTRANSACCION, @CUOTAACT, @SLDINICIAL, @VLRCUOTA, @INTERESES, @SLDFINAL, 'PorPagar', @FECHAPAGO

			SET @CUOTAACT = @CUOTAACT + 1

			IF @PERIODO = 'Anual'
				SET @FECHAPAGO = DATEADD(YEAR, 1, @FECHAPAGO)

			IF @PERIODO = 'Mensual'
				SET @FECHAPAGO = DATEADD(MONTH, 1, @FECHAPAGO)

			IF @PERIODO = 'Quincenal'
			BEGIN
				IF DAY(@FECHAPAGO) = 1
					SET @FECHAPAGO = '16/' + STR(MONTH(@FECHAPAGO)) + '/' + STR(YEAR(@FECHAPAGO)) --DATEADD(day, 15, @FECHAPAGO )
				ELSE
					SET @FECHAPAGO = DBO.FNK_DIA_DEL_MES(YEAR(@FECHAPAGO), MONTH(@FECHAPAGO), 'PRIMERO')
			END

			CONTINUE
		END
	END

	UPDATE PRSD
	SET VLRCUOTA = VLRCUOTA + SALDOACT, SALDOACT = 0
	WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO AND NUMCUOTA = @NUMCUOTAS
END -- 10
