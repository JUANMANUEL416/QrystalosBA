CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_PRS @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(20), @PROCESO VARCHAR(20)
DECLARE @CUOTAACT INT, @MANINTERESES INT, @NUMCUOTAS SMALLINT
DECLARE @INTERESES DECIMAL(14, 2), @TTLPRESTAMO DECIMAL(14, 2)
DECLARE @NUMDOCUMENTO VARCHAR(20)
DECLARE @IDTRANSACCION VARCHAR(6), @COMPANIA VARCHAR(2), @CCOSTO VARCHAR(20), @IDAREA VARCHAR(20)
DECLARE @IDSEDE VARCHAR(5), @IDPRESTADOR VARCHAR(20), @IDDEUDOR VARCHAR(20), @FECHAINI DATETIME, @FECHADOCUMENTO DATETIME
DECLARE @VLRPRESTAMO DECIMAL(14, 2), @VLRSALDO DECIMAL(14, 2), @PERIODO VARCHAR(20)
DECLARE @TIPOINTERES VARCHAR(20), @TASAINTERES DECIMAL(8, 4), @VLRCUOTA DECIMAL(14, 2), @VLRINTERESES DECIMAL(14, 2)
DECLARE @OBSERVACIONES VARCHAR(1023), @ESTADO VARCHAR(20), @FECHAADICION DATETIME
DECLARE @FECHAMODIFICACION DATETIME, @CODCONCEPTO VARCHAR(20), @CODFINANCIACION VARCHAR(20)
DECLARE @ENCAJA SMALLINT, @CODCAJA VARCHAR(4), @CNSFACJ VARCHAR(20), @DIF DECIMAL(14, 2) = 0
DECLARE @SYS_COMPUTERNAME VARCHAR(200)
DECLARE @NUMDOC_ORIGEN VARCHAR(20), @NUMDOC_DESTINO VARCHAR(20), @NUMDOCUMENTOS NVARCHAR(MAX), @CANTHOMOLOG INT
DECLARE @FECHAPAGO DATETIME, @CUOTASAFECTADAS INT = 0, @ESTADOACTUAL VARCHAR(20)

BEGIN
	/* SET LANGUAGE Spanish;
	SET DATEFORMAT dmy; */
	SELECT @MODELO = MODELO, @METODO = METODO, @USUARIO = USUARIO, @PARAMETROS = PARAMETROS
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
	FROM USUSU
	WHERE USUARIO = @USUARIO

	SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
	FROM UBEQ
	WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @NUMDOCUMENTO = NUMDOCUMENTO, @IDTRANSACCION = IDTRANSACCION, @CCOSTO = CCOSTO, @IDAREA = IDAREA, @IDPRESTADOR = IDPRESTADOR, @IDDEUDOR = IDDEUDOR, 
				@FECHAINI = FECHAINI, @FECHADOCUMENTO = FECHADOCUMENTO, @VLRPRESTAMO = VLRPRESTAMO, @VLRSALDO = VLRSALDO, @NUMCUOTAS = NUMCUOTAS, @PERIODO = PERIODO, 
				@MANINTERESES = MANINTERESES, @TIPOINTERES = TIPOINTERES, @TASAINTERES = TASAINTERES, @VLRCUOTA = VLRCUOTA, @VLRINTERESES = VLRINTERESES, 
				@TTLPRESTAMO = TTLPRESTAMO, @OBSERVACIONES = OBSERVACIONES, @ESTADO = ESTADO, @FECHAADICION = FECHAADICION, @FECHAMODIFICACION = FECHAMODIFICACION, 
				@CODCONCEPTO = CODCONCEPTO, @CODFINANCIACION = CODFINANCIACION, @PROCESO = PROCESO --, 
				--@CODCAJA = CODCAJA
			FROM OPENJSON(@PARAMETROS) WITH (
					NUMDOCUMENTO VARCHAR(20) '$.NUMDOCUMENTO', IDTRANSACCION VARCHAR(6) '$.IDTRANSACCION', COMPANIA VARCHAR(2) '$.COMPANIA', CCOSTO VARCHAR(20) 
					'$.CCOSTO', IDAREA VARCHAR(20) '$.IDAREA', IDPRESTADOR VARCHAR(20) '$.IDPRESTADOR', IDDEUDOR VARCHAR(20) '$.IDDEUDOR', FECHAINI DATETIME 
					'$.FECHAINI', FECHADOCUMENTO DATETIME '$.FECHADOCUMENTO', VLRPRESTAMO DECIMAL(14, 2) '$.VLRPRESTAMO', VLRSALDO DECIMAL(14, 2) '$.VLRSALDO', 
					NUMCUOTAS SMALLINT '$.NUMCUOTAS', PERIODO VARCHAR(20) '$.PERIODO', MANINTERESES TINYINT '$.MANINTERESES', TIPOINTERES VARCHAR(20) 
					'$.TIPOINTERES', TASAINTERES DECIMAL(8, 4) '$.TASAINTERES', VLRCUOTA DECIMAL(14, 2) '$.VLRCUOTA', VLRINTERESES DECIMAL(14, 2) '$.VLRINTERESES'
					, TTLPRESTAMO DECIMAL(14, 2) '$.TTLPRESTAMO', OBSERVACIONES VARCHAR(1023) '$.OBSERVACIONES', ESTADO VARCHAR(20) '$.ESTADO', FECHAADICION 
					DATETIME '$.FECHAADICION', FECHAMODIFICACION DATETIME '$.FECHAMODIFICACION', CODCONCEPTO VARCHAR(20) '$.CODCONCEPTO', CODFINANCIACION 
					VARCHAR(20) '$.CODFINANCIACION', PROCESO VARCHAR(20) '$.PROCESO' --, CODCAJA VARCHAR(4) '$.CODCAJA'
					)

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					BEGIN TRAN;

					EXEC SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE, 'PRS', @NUMDOCUMENTO OUTPUT

					SELECT @NUMDOCUMENTO = @IDSEDE + REPLACE(SPACE(8 - LEN(@NUMDOCUMENTO)) + LTRIM(RTRIM(@NUMDOCUMENTO)), SPACE(1), 0)

					INSERT INTO [PRS] (
						[NUMDOCUMENTO], [IDTRANSACCION], [COMPANIA], [CCOSTO], [IDAREA], [IDSEDE], [IDPRESTADOR], [IDDEUDOR], [FECHAINI], [FECHADOCUMENTO], 
						[VLRPRESTAMO], [VLRSALDO], [NUMCUOTAS], [PERIODO], [MANINTERESES], [TIPOINTERES], [TASAINTERES], [VLRCUOTA], [VLRINTERESES], 
						[TTLPRESTAMO], [OBSERVACIONES], [ESTADO], [USUARIOADICION], [EQUIPOADICIONO], [FECHAADICION], [USUARIOMODIFICO], [EQUIPOMODIFICO], 
						[FECHAMODIFICACION], [CODCONCEPTO], [CODFINANCIACION], [ENCAJA], [CODCAJA], [CNSFACJ]
						)
					SELECT @NUMDOCUMENTO, 'PRS', @COMPANIA, @CCOSTO, @IDAREA, @IDSEDE, @IDPRESTADOR, @IDDEUDOR, @FECHAINI, GETDATE(), @VLRPRESTAMO, @VLRSALDO, 
						@NUMCUOTAS, @PERIODO, @MANINTERESES, @TIPOINTERES, @TASAINTERES, @VLRCUOTA, @VLRINTERESES, @TTLPRESTAMO, @OBSERVACIONES, @ESTADO, 
						@USUARIO, @SYS_COMPUTERNAME, GETDATE(), @USUARIO, @SYS_COMPUTERNAME, GETDATE(), @CODCONCEPTO, @CODFINANCIACION, 0, 'TFCJ', ''

					EXEC SPK_GENERA_CUOTAS 'PRS', @NUMDOCUMENTO, @NUMCUOTAS, 0, @VLRPRESTAMO, @FECHAINI

					COMMIT TRAN;
				END TRY

				BEGIN CATCH
					ROLLBACK TRAN;

					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @ESTADOACTUAL = ESTADO
					FROM PRS
					WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION

					IF @ESTADOACTUAL IS NULL
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('No existe la libranza ', @NUMDOCUMENTO)
					END

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0 AND @ESTADOACTUAL = 'Pagada' AND @ESTADO <> 'Pagada'
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('La libranza ', @NUMDOCUMENTO, ' ya esta pagada y no permite cambiar de estado')
					END

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0 AND @ESTADO = 'PorPagar'
					BEGIN
						SELECT @DIF = COALESCE(SUM(VLRCUOTA - ISNULL(VLRINTERESES, 0)), 0)
						FROM PRSD
						WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND ESTADO <> 'Anulada'

						IF @VLRPRESTAMO <> @DIF
						BEGIN
							INSERT INTO @TBLERRORES (ERROR)
							SELECT CONCAT ('EXISTE UNA DIFERENCIA DE ', @VLRPRESTAMO - @DIF, ' CON RESPECTO A LAS CUOTAS, NO ES POSIBLE MODIFICAR'
									)
						END
					END

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0 AND @ESTADO = 'Pagada'
					BEGIN
						IF NOT EXISTS (
								SELECT 1
								FROM PRSD
								WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION
								)
						BEGIN
							INSERT INTO @TBLERRORES (ERROR)
							SELECT CONCAT ('La libranza ', @NUMDOCUMENTO, ' no tiene cuotas generadas')
						END

						IF (
								SELECT COUNT(*)
								FROM @TBLERRORES
								) <= 0 AND NOT EXISTS (
								SELECT 1
								FROM PRSD
								WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND ESTADO <> 'Anulada'
								)
						BEGIN
							INSERT INTO @TBLERRORES (ERROR)
							SELECT CONCAT ('La libranza ', @NUMDOCUMENTO, ' solo tiene cuotas anuladas')
						END
					END

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0 AND @ESTADO = 'Anulada' AND EXISTS (
							SELECT 1
							FROM PRSD
							WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND ESTADO = 'Pagada'
							)
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('La libranza ', @NUMDOCUMENTO, ' tiene cuotas pagadas y no puede anularse')
					END

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						BEGIN TRAN;

						IF @ESTADO = 'Pagada'
						BEGIN
							SELECT @FECHAPAGO = GETDATE(), @VLRSALDO = 0

							UPDATE PRSD
							SET ESTADO = 'Pagada', FECHAPAGO = COALESCE(FECHAPAGO, @FECHAPAGO)
							WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND ESTADO NOT IN ('Pagada', 'Anulada'
									)

							SET @CUOTASAFECTADAS = @@ROWCOUNT
						END
						ELSE IF @ESTADO = 'Anulada'
						BEGIN
							UPDATE PRSD
							SET ESTADO = 'Anulada'
							WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND ESTADO NOT IN ('Pagada', 'Anulada'
									)

							SET @CUOTASAFECTADAS = @@ROWCOUNT
						END
						ELSE IF @ESTADO = 'Aplazada'
						BEGIN
							UPDATE PRSD
							SET ESTADO = 'Aplazada'
							WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND ESTADO = 'PorPagar'

							SET @CUOTASAFECTADAS = @@ROWCOUNT
						END
						ELSE IF @ESTADO = 'PorPagar'
						BEGIN
							UPDATE PRSD
							SET ESTADO = 'PorPagar'
							WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND ESTADO = 'Aplazada'

							SET @CUOTASAFECTADAS = @@ROWCOUNT
						END

						UPDATE PRS
						SET COMPANIA = @COMPANIA, CCOSTO = @CCOSTO, IDAREA = @IDAREA, IDSEDE = @IDSEDE, IDPRESTADOR = @IDPRESTADOR, IDDEUDOR = @IDDEUDOR, FECHAINI = 
							@FECHAINI, FECHADOCUMENTO = COALESCE(@FECHADOCUMENTO, FECHADOCUMENTO), VLRPRESTAMO = @VLRPRESTAMO, VLRSALDO = @VLRSALDO, NUMCUOTAS = 
							@NUMCUOTAS, PERIODO = @PERIODO, MANINTERESES = @MANINTERESES, TIPOINTERES = @TIPOINTERES, TASAINTERES = @TASAINTERES, VLRCUOTA = 
							@VLRCUOTA, VLRINTERESES = @VLRINTERESES, TTLPRESTAMO = @TTLPRESTAMO, OBSERVACIONES = @OBSERVACIONES, ESTADO = @ESTADO, USUARIOMODIFICO = 
							@USUARIO, EQUIPOMODIFICO = @SYS_COMPUTERNAME, FECHAMODIFICACION = GETDATE(), CODCONCEPTO = @CODCONCEPTO, CODFINANCIACION = 
							@CODFINANCIACION --, ENCAJA = @ENCAJA , CODCAJA = @CODCAJA
						WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION

						COMMIT TRAN;
					END
				END TRY

				BEGIN CATCH
					IF @@TRANCOUNT > 0
						ROLLBACK TRAN;

					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK, @CUOTASAFECTADAS CUOTAS_AFECTADAS

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'CALUCLA_CUOTAS'
	BEGIN
		BEGIN TRY
			SELECT @NUMDOCUMENTO = NUMDOCUMENTO, @IDTRANSACCION = IDTRANSACCION, @MANINTERESES = MANINTERESES, @NUMCUOTAS = NUMCUOTAS, @VLRSALDO = VLRSALDO, 
				@VLRINTERESES = VLRINTERESES, @VLRPRESTAMO = VLRPRESTAMO
			FROM OPENJSON(@PARAMETROS) WITH (
					NUMDOCUMENTO VARCHAR(20) '$.NUMDOCUMENTO', IDTRANSACCION VARCHAR(6) '$.IDTRANSACCION', MANINTERESES INT '$.MANINTERESES', NUMCUOTAS SMALLINT 
					'$.NUMCUOTAS', VLRSALDO DECIMAL(14, 2) '$.VLRSALDO', VLRINTERESES DECIMAL(14, 2) '$.VLRINTERESES', VLRPRESTAMO DECIMAL(14, 2) '$.VLRPRESTAMO'
					)

			SELECT @CUOTAACT = COALESCE(MAX(NUMCUOTA), 0)
			FROM PRSD
			WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO AND ESTADO = 'Pagada'

			SELECT 'OK' OK

			IF @MANINTERESES = 0 AND @NUMCUOTAS - @CUOTAACT > 0
			BEGIN
				SET @VLRCUOTA = 0
				SET @VLRINTERESES = 0
				SET @TTLPRESTAMO = 0

				SELECT @VLRCUOTA = ROUND(@VLRSALDO / (@NUMCUOTAS - @CUOTAACT), 1)

				SELECT @INTERESES = COALESCE(SUM(VLRINTERESES), 0)
				FROM PRSD
				WHERE IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO AND ESTADO = 'Pagada'

				IF @INTERESES = 0
				BEGIN
					SELECT @TTLPRESTAMO = @VLRPRESTAMO + @VLRINTERESES + @INTERESES
				END

				SELECT @VLRCUOTA AS VLRCUOTA, @TTLPRESTAMO AS TTLPRESTAMO, @VLRINTERESES AS VLRINTERESES
			END

			RETURN
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ENVIAR_A_CXP'
	BEGIN
		SELECT @NUMDOCUMENTO = NUMDOCUMENTO
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOCUMENTO VARCHAR(20) '$.NUMDOCUMENTO')

		BEGIN TRY
			EXEC SPK_GENCXP_PRESTAMO_NOMI @NUMDOCUMENTO, @COMPANIA, @IDSEDE, @USUARIO, @SYS_COMPUTERNAME
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'MARCAR_PAGADA'
	BEGIN
		SELECT @NUMDOCUMENTO = NUMDOCUMENTO, @IDTRANSACCION = IDTRANSACCION, @FECHAPAGO = FECHAPAGO
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOCUMENTO VARCHAR(20) '$.NUMDOCUMENTO', IDTRANSACCION VARCHAR(6) '$.IDTRANSACCION', FECHAPAGO DATETIME '$.FECHAPAGO'
				)

		SELECT @FECHAPAGO = COALESCE(@FECHAPAGO, GETDATE()), @IDTRANSACCION = COALESCE(@IDTRANSACCION, 'PRS')

		BEGIN TRY
			SELECT @ESTADOACTUAL = ESTADO
			FROM PRS
			WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION

			IF @NUMDOCUMENTO IS NULL OR LTRIM(RTRIM(@NUMDOCUMENTO)) = ''
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'Debe indicar el numero de documento de la libranza'
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0 AND @ESTADOACTUAL IS NULL
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT CONCAT ('No existe la libranza ', @NUMDOCUMENTO)
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0 AND @ESTADOACTUAL = 'Anulada'
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT CONCAT ('La libranza ', @NUMDOCUMENTO, ' se encuentra anulada y no puede marcarse como pagada')
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0 AND NOT EXISTS (
					SELECT 1
					FROM PRSD
					WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION
					)
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT CONCAT ('La libranza ', @NUMDOCUMENTO, ' no tiene cuotas generadas')
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0 AND NOT EXISTS (
					SELECT 1
					FROM PRSD
					WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND ESTADO <> 'Anulada'
					)
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT CONCAT ('La libranza ', @NUMDOCUMENTO, ' solo tiene cuotas anuladas')
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				BEGIN TRAN;

				UPDATE PRSD
				SET ESTADO = 'Pagada', FECHAPAGO = COALESCE(FECHAPAGO, @FECHAPAGO)
				WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION AND ESTADO NOT IN ('Pagada', 'Anulada')

				SET @CUOTASAFECTADAS = @@ROWCOUNT

				UPDATE PRS
				SET ESTADO = 'Pagada', VLRSALDO = 0, USUARIOMODIFICO = @USUARIO, EQUIPOMODIFICO = @SYS_COMPUTERNAME, FECHAMODIFICACION = GETDATE()
				WHERE NUMDOCUMENTO = @NUMDOCUMENTO AND IDTRANSACCION = @IDTRANSACCION

				COMMIT TRAN;
			END
		END TRY

		BEGIN CATCH
			IF @@TRANCOUNT > 0
				ROLLBACK TRAN;

			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK, @NUMDOCUMENTO NUMDOCUMENTO, @IDTRANSACCION IDTRANSACCION, @FECHAPAGO FECHAPAGO, @CUOTASAFECTADAS CUOTAS_AFECTADAS

		RETURN
	END

	IF @METODO = 'GENERAR_CUOTAS'
	BEGIN
		SELECT @IDTRANSACCION = IDTRANSACCION, @NUMDOCUMENTO = NUMDOCUMENTO, @NUMCUOTAS = NUMCUOTAS, @VLRSALDO = VLRSALDO, @FECHAINI = FECHAINI
		FROM OPENJSON(@PARAMETROS) WITH (
				IDTRANSACCION VARCHAR(6) '$.IDTRANSACCION', NUMDOCUMENTO VARCHAR(20) '$.NUMDOCUMENTO', NUMCUOTAS SMALLINT '$.NUMCUOTAS', VLRSALDO DECIMAL(14, 2) 
				'$.VLRSALDO', FECHAINI DATETIME '$.FECHAINI'
				)

		BEGIN TRY
			EXEC SPK_GENERA_CUOTAS @IDTRANSACCION, @NUMDOCUMENTO, @NUMCUOTAS, 0, @VLRSALDO, @FECHAINI
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR_CUOTAS'
	BEGIN
		SELECT @IDTRANSACCION = IDTRANSACCION, @NUMDOCUMENTO = NUMDOCUMENTO
		FROM OPENJSON(@PARAMETROS) WITH (IDTRANSACCION VARCHAR(6) '$.IDTRANSACCION', NUMDOCUMENTO VARCHAR(20) '$.NUMDOCUMENTO')

		BEGIN TRY
			DELETE
			FROM PRSD
			WHERE ESTADO <> 'Pagada' AND IDTRANSACCION = @IDTRANSACCION AND NUMDOCUMENTO = @NUMDOCUMENTO
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @NUMDOCUMENTO = NUMDOCUMENTO
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOCUMENTO VARCHAR(20) '$.NUMDOCUMENTO')

		BEGIN TRY
			INSERT INTO @TBLERRORES (ERROR)
			SELECT CONCAT ('EXISTE CUOTAS RELACIONADOAS AL PRESTAMO ', @NUMDOCUMENTO, ' NO ES POSIBLE ELIMINARLO')
			WHERE EXISTS (
					SELECT 1
					FROM PRSD
					WHERE NUMDOCUMENTO = @NUMDOCUMENTO
					)

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				DELETE
				FROM PRS
				WHERE NUMDOCUMENTO = @NUMDOCUMENTO
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	-- nuevo metodo para validar cuales son los registros o prestamos de libranzas que se van a homolograr
	IF @METODO = 'CONSULTAR_PENDIENTES_HOMOLOG'
	BEGIN
		SELECT @NUMDOC_ORIGEN = NUMDOC_ORIGEN
		FROM OPENJSON(@PARAMETROS) WITH (NUMDOC_ORIGEN VARCHAR(20) '$.NUMDOC_ORIGEN')

		IF NOT EXISTS (
				SELECT 1
				FROM NEMP
				WHERE NUMDOC = @NUMDOC_ORIGEN AND FECHARETIRO IS NOT NULL
				)
		BEGIN
			INSERT INTO @TBLERRORES (ERROR)
			SELECT 'El contrato origen no existe o no tiene fecha de retiro registrada'

			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK

		SELECT P.NUMDOCUMENTO, P.IDTRANSACCION, P.IDDEUDOR, P.IDPRESTADOR, P.CODCONCEPTO, P.VLRPRESTAMO, P.VLRSALDO, P.NUMCUOTAS, P.ESTADO, P.FECHADOCUMENTO, TER
			.RAZONSOCIAL AS NOMBRE_PRESTADOR, (
				SELECT COUNT(*)
				FROM PRSD D
				WHERE D.NUMDOCUMENTO = P.NUMDOCUMENTO AND D.IDTRANSACCION = P.IDTRANSACCION AND D.ESTADO = 'PorPagar'
				) AS CUOTAS_PENDIENTES
		FROM PRS P
		LEFT JOIN TER ON TER.IDTERCERO = P.IDPRESTADOR
		WHERE P.IDDEUDOR = @NUMDOC_ORIGEN AND P.ESTADO = 'PorPagar' AND EXISTS (
				SELECT 1
				FROM PRSD D
				WHERE D.NUMDOCUMENTO = P.NUMDOCUMENTO AND D.IDTRANSACCION = P.IDTRANSACCION AND D.ESTADO = 'PorPagar'
				)
		ORDER BY P.FECHADOCUMENTO DESC

		RETURN
	END

	-- nuevo metodo para la validacion de contratos a homologar (incluye la homologacion)
	IF @METODO = 'HOMOLOGAR_NUMDOC'
	BEGIN
		BEGIN TRY
			SELECT @NUMDOC_ORIGEN = NUMDOC_ORIGEN, @NUMDOC_DESTINO = NUMDOC_DESTINO, @NUMDOCUMENTOS = NUMDOCUMENTOS
			FROM OPENJSON(@PARAMETROS) WITH (
					NUMDOC_ORIGEN VARCHAR(20) '$.NUMDOC_ORIGEN', NUMDOC_DESTINO VARCHAR(20) '$.NUMDOC_DESTINO', NUMDOCUMENTOS NVARCHAR(MAX) '$.NUMDOCUMENTOS' 
					AS JSON
					)

			IF @NUMDOC_ORIGEN IS NULL OR @NUMDOC_DESTINO IS NULL
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'Debe indicar contrato origen y contrato destino'
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0 AND NOT EXISTS (
					SELECT 1
					FROM NEMP
					WHERE NUMDOC = @NUMDOC_ORIGEN AND FECHARETIRO IS NOT NULL
					)
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'El contrato origen no tiene fecha de retiro. Solo se homologan prestamos de contratos ratirados'
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0 AND NOT EXISTS (
					SELECT 1
					FROM NEMP
					WHERE NUMDOC = @NUMDOC_DESTINO
					)
			BEGIN
				INSERT INTO @TBLERRORES (ERROR)
				SELECT 'El contrato destino no existe'
			END

			IF (
					SELECT COUNT(*)
					FROM @TBLERRORES
					) <= 0
			BEGIN
				SET @CANTHOMOLOG = 0

				-- spq realizar homologacion de las libranzas a los contratos seleccionados
				EXEC SPQ_HOMOLOGAR_PRS_NUMDOC @NUMDOC_DESTINO = @NUMDOC_DESTINO, @NUMDOC_ORIGEN = @NUMDOC_ORIGEN, @TERCEROID = NULL, @USUARIO = @USUARIO, 
					@SYS_COMPUTERNAME = @SYS_COMPUTERNAME, @NUMDOCUMENTOS = @NUMDOCUMENTOS, @CANTIDAD = @CANTHOMOLOG OUTPUT

				IF @CANTHOMOLOG = 0
				BEGIN
					INSERT INTO @TBLERRORES (ERROR)
					SELECT 'No se encontraron prestamos pendientes para homologar con los criterios indicados'
				END
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK, @CANTHOMOLOG CANT_HOMOLOG, @NUMDOC_ORIGEN NUMDOC_ORIGEN, @NUMDOC_DESTINO NUMDOC_DESTINO

		RETURN
	END
