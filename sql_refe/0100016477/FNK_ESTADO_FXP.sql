IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='FNK_ESTADO_FXP' AND XTYPE='TF')
BEGIN
 DROP FUNCTION FNK_ESTADO_FXP
END

GO
CREATE FUNCTION DBO.FNK_ESTADO_FXP(@N_PRESUP VARCHAR(16), @ITEM INT, @NOPRESTACION VARCHAR(20), @NOITEM INT)
RETURNS @TABLA
TABLE (ESTADO       INT,
       DOCUMENTO    VARCHAR(20)   COLLATE database_default,
       MENSAJE      VARCHAR(4000) COLLATE database_default)
WITH ENCRYPTION
AS
BEGIN
 DECLARE @NOADMISION       VARCHAR(20)
 DECLARE @NROCOMPROBANTE   VARCHAR(20)
 DECLARE @N_FACTURA        VARCHAR(16)
 DECLARE @CONTABILIZADA    INT
 DECLARE @ESTADO           INT
 DECLARE @DOCUMENTO        VARCHAR(20)
 DECLARE @MENSAJE          VARCHAR(4000)

 SET @MENSAJE = ''
 SET @ESTADO  = 9
 SELECT @NOADMISION = NOREFERENCIA FROM FXP WHERE N_PRESUP = @N_PRESUP
 SELECT @N_FACTURA=FTR.N_FACTURA, @NROCOMPROBANTE = FTR.NROCOMPROBANTE,  @CONTABILIZADA = FTR.CONTABILIZADA
 FROM FTR INNER JOIN 
      FTRD ON FTR.N_FACTURA=FTRD.N_FACTURA 
 WHERE FTRD.NOADMISION = @NOADMISION AND FTRD.NOPRESTACION=@NOPRESTACION AND FTRD.NOITEM=@NOITEM
 IF @CONTABILIZADA = 1
 BEGIN
  SET @MENSAJE = @MENSAJE + 'En Comprobante Contable: '+@NROCOMPROBANTE+CHAR(13)+CHAR(10)
  SELECT @DOCUMENTO = COMPROBANTE+' '+NOREFERENCIA, @ESTADO=ESTADO
  FROM MCP WHERE NROCOMPROBANTE=@NROCOMPROBANTE
  IF @ESTADO=2
  BEGIN
   SET @MENSAJE = @MENSAJE + 'Confirmada en Contabilidad: '+@NROCOMPROBANTE+CHAR(13)+CHAR(10)
   SET @ESTADO=1
  END
  ELSE 
  BEGIN
   SET @MENSAJE = @MENSAJE + 'No Confirmada en Contabilidad: '+@NROCOMPROBANTE+CHAR(13)+CHAR(10)
   SET @ESTADO=0
  END
 END
 ELSE
 BEGIN
  SET @MENSAJE = @MENSAJE + 'No est? en Contabilidad.'+CHAR(13)+CHAR(10)
  SET @ESTADO    = 0
  SET @DOCUMENTO = ''
 END
 INSERT INTO @TABLA (ESTADO, DOCUMENTO, MENSAJE)
 SELECT @ESTADO, @DOCUMENTO, @MENSAJE
 RETURN
END
