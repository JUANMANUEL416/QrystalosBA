CREATE OR ALTER PROCEDURE DBO.SPK_SINCRONIZAR_CUFE_RADIAN
    @CNSRADIAN       VARCHAR(20) = NULL,
    @CNSMOV          VARCHAR(20) = NULL,
    @ACTUALIZADOS    INT = NULL OUTPUT,
    @AMBIGUOS        INT = NULL OUTPUT,
    @SIN_COINCIDENCIA INT = NULL OUTPUT
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        @CNSRADIAN = NULLIF(LTRIM(RTRIM(@CNSRADIAN)), ''),
        @CNSMOV = NULLIF(LTRIM(RTRIM(@CNSMOV)), ''),
        @ACTUALIZADOS = 0,
        @AMBIGUOS = 0,
        @SIN_COINCIDENCIA = 0;

    IF OBJECT_ID(N'DBO.IMOV', N'U') IS NULL
       OR OBJECT_ID(N'DBO.FCOM', N'U') IS NULL
       OR OBJECT_ID(N'DBO.TER', N'U') IS NULL
       OR OBJECT_ID(N'DBO.FRADIAN', N'U') IS NULL
    BEGIN
        THROW 50001, 'No existen todas las tablas requeridas para sincronizar CUFE desde RADIAN.', 1;
    END;

    IF COL_LENGTH('DBO.IMOV', 'CUFE') IS NULL
    BEGIN
        THROW 50002, 'Falta la columna IMOV.CUFE. Ejecute DDL_IMOV_CUFE.sql.', 1;
    END;

    DECLARE @IDINVMOV_COMPRAS VARCHAR(20) = NULLIF(
        LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('IDINVMOV_COMPRAS'))),
        ''
    );

    IF @IDINVMOV_COMPRAS IS NULL
    BEGIN
        THROW 50003, 'La variable IDINVMOV_COMPRAS no est� configurada.', 1;
    END;

    IF @CNSRADIAN IS NULL AND @CNSMOV IS NULL
    BEGIN
        THROW 50004, 'Debe indicar CNSRADIAN o CNSMOV. Utilice SPQ_IMOV_3 para la sincronizaci�n hist�rica por lotes.', 1;
    END;

    SELECT DISTINCT
        M.CNSMOV,
        CUFE = LTRIM(RTRIM(R.UUID))
    INTO #CANDIDATOS_CUFE
    FROM DBO.IMOV AS M
    INNER JOIN DBO.FCOM AS F
        ON F.CNSFCOM = M.CNSFCOM
    INNER JOIN DBO.TER AS T
        ON T.IDTERCERO = COALESCE(NULLIF(LTRIM(RTRIM(M.IDTERCERO)), ''), F.IDTERCERO)
    CROSS APPLY (
        VALUES (
            CASE
                WHEN M.TIPO_DOC_COMPRA = 'F'
                    THEN COALESCE(
                        NULLIF(LTRIM(RTRIM(M.NODOCUMENTO)), ''),
                        NULLIF(LTRIM(RTRIM(M.N_FACTURA)), ''),
                        NULLIF(LTRIM(RTRIM(F.N_FACTURA)), '')
                    )
                ELSE COALESCE(
                    NULLIF(LTRIM(RTRIM(M.N_FACTURA)), ''),
                    NULLIF(LTRIM(RTRIM(F.N_FACTURA)), ''),
                    NULLIF(LTRIM(RTRIM(M.NODOCUMENTO)), '')
                )
            END
        )
    ) AS DOC(N_FACTURA)
    INNER JOIN DBO.FRADIAN AS R
        ON UPPER(REPLACE(LTRIM(RTRIM(R.NODOCUMENTO)), ' ', ''))
         = UPPER(REPLACE(LTRIM(RTRIM(DOC.N_FACTURA)), ' ', ''))
       AND DBO.FNK_LIMPIATEXTO(COALESCE(R.NIT, ''), '0-9')
         = DBO.FNK_LIMPIATEXTO(COALESCE(T.NIT, ''), '0-9')
    WHERE M.IDTIPOMOV = @IDINVMOV_COMPRAS
      AND COALESCE(M.CNSFCOM, '') <> ''
      AND COALESCE(M.ESTADO, 0) <> 2
      AND COALESCE(LTRIM(RTRIM(M.CUFE)), '') = ''
      AND COALESCE(M.TIPO_DOC_COMPRA, 'F') <> 'R'
      AND DOC.N_FACTURA IS NOT NULL
      AND (@CNSMOV IS NULL OR M.CNSMOV = @CNSMOV)
      AND (@CNSRADIAN IS NULL OR R.CNSRADIAN = @CNSRADIAN)
      AND LEN(LTRIM(RTRIM(R.UUID))) = 96
      AND LTRIM(RTRIM(R.UUID)) COLLATE Latin1_General_100_BIN2 NOT LIKE '%[^0-9A-Fa-f]%';

    SELECT
        C.CNSMOV,
        CUFE = MAX(C.CUFE),
        CANTIDAD_CUFE = COUNT(*)
    INTO #RESOLUCION_CUFE
    FROM #CANDIDATOS_CUFE AS C
    GROUP BY C.CNSMOV;

    SELECT @AMBIGUOS = COUNT(*)
    FROM #RESOLUCION_CUFE
    WHERE CANTIDAD_CUFE > 1;

    UPDATE M
    SET M.CUFE = R.CUFE
    FROM DBO.IMOV AS M
    INNER JOIN #RESOLUCION_CUFE AS R
        ON R.CNSMOV = M.CNSMOV
       AND R.CANTIDAD_CUFE = 1
    WHERE COALESCE(LTRIM(RTRIM(M.CUFE)), '') = ''
      AND COALESCE(M.ESTADO, 0) <> 2;

    SET @ACTUALIZADOS = @@ROWCOUNT;

    IF @CNSMOV IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM #RESOLUCION_CUFE WHERE CNSMOV = @CNSMOV)
       AND EXISTS (
            SELECT 1
            FROM DBO.IMOV
            WHERE CNSMOV = @CNSMOV
              AND IDTIPOMOV = @IDINVMOV_COMPRAS
              AND COALESCE(CNSFCOM, '') <> ''
              AND COALESCE(ESTADO, 0) <> 2
              AND COALESCE(LTRIM(RTRIM(CUFE)), '') = ''
       )
        SET @SIN_COINCIDENCIA = 1;
END
