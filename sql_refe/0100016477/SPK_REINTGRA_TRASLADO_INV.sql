CREATE OR ALTER PROC DBO.SPK_REINTGRA_TRASLADO_INV 
@CNSITRA VARCHAR(20),
@COMPANIA VARCHAR(2),
@IDSEDE VARCHAR(6),
@USUARIO VARCHAR(20),
@SYS_COMPUTERNAME VARCHAR(255)
WITH ENCRYPTION
AS 
DECLARE @CNSMOV VARCHAR(20)
DECLARE @NVOCONSEC VARCHAR(20)
DECLARE @IDTIPOMOV VARCHAR(2) 
DECLARE @IDBODEGA VARCHAR(20)
DECLARE @CLASEDEV VARCHAR(20)='TOTAL'
BEGIN
   PRINT 'SPK_REINTGRA_VENTA_INV '+@CNSITRA

   SELECT @CNSMOV=CNSMOVORI,@IDBODEGA=IDBODEGAORI FROM ITRA WHERE CNSITRA=@CNSITRA
   SELECT @IDTIPOMOV=DBO.FNK_VALORVARIABLE('IDTIMOVDEV_TRASLBOD')
   IF EXISTS(SELECT * FROM IMOV WHERE CNSMOV=@CNSMOV)
   BEGIN
      EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@MOV', @LONGITUD = 8, @NVOCONSEC = @NVOCONSEC OUTPUT 

      PRINT  '@NVOCONSEC='+@NVOCONSEC
		INSERT INTO IMOV(CNSMOV, IDBODEGA, IDTIPOMOV, NODOCUMENTO, TIPODOCU,
								FECHAMOV, CCOSTO, IDSOLICITA, IDTERCERO, IDFUNCIONARIO,
								IDRECIBE, FACTORVENTA, ESTADO, IDBODEGAEXTERNA, CNSTRAN,
								OBSERVACION, CNSFCOM, SUBIOCOMPRA, NOPRESTACION, IDAREA,
								CONTABILIZADA, NROCOMPROBANTE, PROCEDENCIA, USUARIO,
								USUARIOCONF, FECHACONF, PARCIAL, IDAREAH, NIVELATENCION, 
								SYS_ComputerName, TIENECAMBIO, IDITAR, ESTRANSITO, CNSREP,CODUNG,CODPRG, CLASENC, CNSFNOT_DEV) 
      SELECT @NVOCONSEC, IDBODEGA, @IDTIPOMOV, @CNSITRA, TIPODOCU,
								DBO.FNK_GETDATE(), CCOSTO, IDSOLICITA, IDTERCERO, IDFUNCIONARIO,
								@USUARIO, FACTORVENTA, 0, IDBODEGAEXTERNA, CNSTRAN,
								OBSERVACION, CNSFCOM, SUBIOCOMPRA, NOPRESTACION, IDAREA,
								CONTABILIZADA, NROCOMPROBANTE, PROCEDENCIA, USUARIO,
								USUARIOCONF, NULL, PARCIAL, IDAREAH, NIVELATENCION, 
								@SYS_ComputerName, TIENECAMBIO, IDITAR, ESTRANSITO, CNSREP,CODUNG,CODPRG,NULL,NULL
      FROM IMOV 
      WHERE CNSMOV=@CNSMOV
      PRINT 'VOY POR EL DETALLE'
      IF @CLASEDEV='TOTAL'
      BEGIN
		   INSERT INTO IMOVH(CNSMOV, IDARTICULO, EXISTENCIA, CANTIDAD, CANTPEDIDA, PCOSTO,
          NOLOTE, NOLOTEPEDIDO,FECHAVENCE, ESTADO, IDARTICULOTF,
          CANTIDADTF, PCOSTOANTES, CNSTRAN, ITEM, PVENTA, USUARIO, 
          USUARIOCONF, FECHACONF, PRIEXI, FECHAREPOSI, IDARTICULOORI,
          CANTIDADORI, TIENECAMBIO,IDSERVICIO)
         SELECT @NVOCONSEC,ISAL.IDARTICULO,0,ISAL.CANTIDAD,ISAL.CANTIDAD,ISAL.PCOSTO,ISAL.NOLOTE,
                ISAL.NOLOTEPEDIDO,ISAL.FECHAVENCE,0,ISAL.IDARTICULO,ISAL.CANTIDAD,ISAL.PCOSTO,NULL,NULL,NULL,@USUARIO,
                NULL,NULL,NULL,NULL,NULL,NULL,NULL,IART.IDSERVICIO
         FROM ISAL INNER JOIN IART ON ISAL.IDARTICULO=IART.IDARTICULO
         WHERE ISAL.CNSMOV=@CNSMOV
      END
      ELSE
      BEGIN
         PRINT 'VALIDAR CON ANDRE...'
         --INSERT INTO IMOVH(CNSMOV, IDARTICULO, EXISTENCIA, CANTIDAD, CANTPEDIDA, PCOSTO,
						   --NOLOTE, NOLOTEPEDIDO,FECHAVENCE, ESTADO, IDARTICULOTF,
						   --CANTIDADTF, PCOSTOANTES, CNSTRAN, ITEM, PVENTA, USUARIO, 
						   --USUARIOCONF, FECHACONF, PRIEXI, FECHAREPOSI, IDARTICULOORI,
						   --CANTIDADORI, TIENECAMBIO,IDSERVICIO)
         --SELECT @NVOCONSEC,ISAL.IDARTICULO,0,FNOTD.CANTIDAD,FNOTD.CANTIDAD,ISAL.PCOSTO,ISAL.NOLOTE,
         --       ISAL.NOLOTEPEDIDO,ISAL.FECHAVENCE,0,ISAL.IDARTICULO,FNOTD.CANTIDAD,ISAL.PCOSTO,NULL,NULL,NULL,@USUARIO,
         --       NULL,NULL,NULL,NULL,NULL,NULL,NULL,IART.IDSERVICIO
         --FROM ISAL
         --INNER JOIN IART ON ISAL.IDARTICULO=IART.IDARTICULO
         --INNER JOIN FNOTD ON ISAL.CNSFNOT_DEV = FNOTD.CNSFNOT AND FNOTD.IDSERVICIO = ISAL.IDARTICULO
         --WHERE ISAL.CNSMOV=@CNSMOV AND ISAL.CNSFNOT_DEV = @CNSFNOT 
      END
      BEGIN TRY           
         EXEC SPK_CONFIRMARENTRADAS @IDBODEGA,@NVOCONSEC,@USUARIO,@COMPANIA,@IDSEDE,@SYS_COMPUTERNAME
         -- Cierra cabecera y detalle juntos (mismo estado)
         UPDATE ITRA  SET ESTADO = 2 WHERE CNSITRA = @CNSITRA
         UPDATE ITRAH SET ESTADO = 2 WHERE CNSITRA = @CNSITRA
      END TRY
      BEGIN CATCH
              RAISERROR('Movimento no fue confirmado, verifique los movimientos',16,1)
      END CATCH
   END
END
