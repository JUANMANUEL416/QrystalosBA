CREATE OR ALTER PROCEDURE DBO.SPK_FCOM_RECALCULA_RECEPCION
	@CNSFCOM VARCHAR(20)
AS
BEGIN
	SET NOCOUNT ON;

	DECLARE @ESTADO_ACT VARCHAR(10)
	DECLARE @LINEAS_PEND INT = 0
	DECLARE @ITRA_ABIERTOS INT = 0
	DECLARE @IDINVMOV_COMPRAS VARCHAR(20)

	IF COALESCE(LTRIM(RTRIM(@CNSFCOM)), '') = ''
		RETURN

	SELECT @ESTADO_ACT = ESTADO FROM FCOM WITH (NOLOCK) WHERE CNSFCOM = @CNSFCOM
	IF @ESTADO_ACT IS NULL
		RETURN

	-- Solo OCs ya en flujo de recepci�n (parcial o confirmada en bodega)
	IF @ESTADO_ACT NOT IN ('R', 'I')
		RETURN

	SELECT @IDINVMOV_COMPRAS = DBO.FNK_VALORVARIABLE('IDINVMOV_COMPRAS')

	-- Pendientes reales: gap FCOMD vs recibido, excluyendo art�culos marcados en FCOMTRANEVT
	SELECT @LINEAS_PEND = COUNT(*)
	FROM FCOMD D WITH (NOLOCK)
	WHERE D.CNSFCOM = @CNSFCOM
	  AND D.CANTIDAD > COALESCE((
			SELECT SUM(H.CANTIDAD)
			FROM IMOV M WITH (NOLOCK)
			INNER JOIN IMOVH H WITH (NOLOCK) ON H.CNSMOV = M.CNSMOV
			WHERE COALESCE(M.ESTADO, 0) = 1
			  AND (
					M.CNSFCOM = @CNSFCOM
				 OR M.CNSITRA IN (SELECT CNSITRA FROM ITRA WITH (NOLOCK) WHERE CNSFCOM = @CNSFCOM)
				 OR M.CNSMOV IN (
						SELECT NULLIF(LTRIM(RTRIM(T.CNSMOVDES)), '')
						FROM ITRA T WITH (NOLOCK)
						WHERE T.CNSFCOM = @CNSFCOM
						  AND COALESCE(T.CNSMOVDES, '') <> ''
						  AND T.CNSMOVDES <> 'VARIOS'
					)
			  )
			  AND COALESCE(NULLIF(H.IDARTICULOORI, ''), H.IDARTICULO) = D.IDARTICULO
	  ), 0)
	  AND NOT (
			OBJECT_ID('dbo.FCOMTRANEVT', 'U') IS NOT NULL
			AND EXISTS (
				SELECT 1
				FROM FCOMTRANEVT E WITH (NOLOCK)
				WHERE E.CNSFCOM = @CNSFCOM
				  AND E.TIPO = 'ELIMINA_LINEA'
				  AND E.IDARTICULO_FCOMD = D.IDARTICULO
			)
	  )

	SELECT @ITRA_ABIERTOS = COUNT(*)
	FROM ITRA WITH (NOLOCK)
	WHERE CNSFCOM = @CNSFCOM
	  AND COALESCE(ESTADO, 0) = 0

	IF @LINEAS_PEND = 0 AND @ITRA_ABIERTOS = 0
		UPDATE FCOM SET ESTADO = 'I' WHERE CNSFCOM = @CNSFCOM AND ESTADO IN ('R', 'I')
	ELSE
		UPDATE FCOM SET ESTADO = 'R' WHERE CNSFCOM = @CNSFCOM AND ESTADO IN ('R', 'I')
END
