CREATE OR ALTER PROCEDURE DBO.SPK_CONFIRMASAL_CM
@CNSMOV   VARCHAR(20),
@USUARIO  VARCHAR(12),
@SEDE     VARCHAR(5),
@PROCESO  VARCHAR(20)

WITH ENCRYPTION
AS
DECLARE @SYS_COMPUTERNAME VARCHAR(254), @IDBODEGA VARCHAR(20), @ESTRANSITO SMALLINT, @CNSITRA VARCHAR(20), @CNSIZSOL VARCHAR(20), @SECONTABILIZA BIT=0,
@COMPANIA VARCHAR(2),
		@DEV_CNSMOV VARCHAR(20),
		@NOLOTE VARCHAR(20),
		@NOLOTEPEDIDO VARCHAR(20),
		@IDARTICULO VARCHAR(20),
		@NOADMISION VARCHAR(16),
		@IDSERVICIO VARCHAR(16),
		@CLASEIZSDOL VARCHAR(16),
		@SECTOR VARCHAR(6),
		@CANTIZSOLDENTREGADO INT,
		@CANTIZSOLDTOTAL INT,
		@CANTIDADSOL DECIMAL(14,2),
		@VLR_UNITARIO DECIMAL(14,2),
      @IDTERCEROCA VARCHAR(20),
      @IDPLANCA    VARCHAR(6),
      @IDSEDE     VARCHAR(20),
      @METODO     VARCHAR(20),
      @COPA_VAR_PORC DECIMAL(14,2)
DECLARE @HOY DATETIME=CONVERT(SMALLDATETIME,GETDATE())
BEGIN
	SET @SYS_COMPUTERNAME = HOST_NAME()   

	SELECT 
        @ESTRANSITO=ITMO.GENTRANSITO,          
	    @IDBODEGA  =IMOV.IDBODEGA,
        @CNSIZSOL  =IMOV.NODOCUMENTO,
        @SECONTABILIZA = IIF(ISNULL(IBOD.NOCONTABILIZA,0)=1,0,ISNULL(ITMO.SECONTABILIZA,0))
	FROM   IMOV 
        INNER JOIN ITMO ON IMOV.IDTIPOMOV = ITMO.IDTIPOMOV
        INNER JOIN IBOD ON IBOD.IDBODEGA = IMOV.IDBODEGA
	WHERE  IMOV.CNSMOV=@CNSMOV
   
    IF EXISTS (SELECT 1 FROM IZSOLD INNER JOIN IZSOLDT ON IZSOLDT.CNSIZSOLD=IZSOLD.CNSIZSOLD 
	           WHERE IZSOLD.CNSIZSOL=@CNSIZSOL AND IZSOLDT.ESTADO=0)
    BEGIN
        EXEC SPK_PROCESA_IZSOLDT @CNSIZSOL, @CNSMOV, '01', @SEDE, @USUARIO
    END

    -- CEFM_FECHA_TRANS: transcripci�n retrasada. Devuelve NULL para cualquier
    -- pedido que no venga de una f�rmula transcrita con fecha manual; en ese caso no cambia nada.
    DECLARE @FECHATRANS_CEFM DATETIME = DBO.FNK_CEFM_FECHATRANSCRIPCION(@CNSIZSOL)
    IF @FECHATRANS_CEFM IS NOT NULL SET @HOY = @FECHATRANS_CEFM

	UPDATE IMOVH SET ESTADO = 9 WHERE CNSMOV = @CNSMOV
      
	BEGIN TRAN
		--IDXB  ACTUALIZA EXISTENCIAS
		UPDATE IDXB 
		SET    IDXB.EXISTOTAL  = IDXB.EXISTOTAL - IMOVH.CANTIDAD
		FROM   IDXB INNER JOIN IMOVH ON IDXB.IDARTICULO = IMOVH.IDARTICULO
		WHERE  IDXB.IDBODEGA   = @IDBODEGA 
		AND    IMOVH.CNSMOV    = @CNSMOV
		--IART  ACTUALIZA EXISTENCIAS
		UPDATE IART
		SET    IART.EXISTOTAL  =  IART.EXISTOTAL - IMOVH.CANTIDAD
		FROM   IART INNER JOIN IMOVH ON IART.IDARTICULO = IMOVH.IDARTICULO
		WHERE  IMOVH.CNSMOV    = @CNSMOV
	COMMIT
	UPDATE IMOV SET ESTADO = '1', USUARIOCONF = @USUARIO, FECHACONF = @HOY,
					SECONTABILIZA = @SECONTABILIZA
	WHERE  CNSMOV = @CNSMOV

	IF @ESTRANSITO=1 
	BEGIN
		PRINT 'TRANSITO'
		SET @CNSITRA = SPACE(20)
		--EXEC SPK_GENCONSECUTIVO '01', @SEDE, '@ITRA', @CNSITRA OUTPUT
		--SELECT @CNSITRA = @SEDE + REPLACE(SPACE(8 - LEN(@CNSITRA))+LTRIM(RTRIM(@CNSITRA)),SPACE(1),0)
		EXEC DBO.SPQ_GENSEQUENCE @SEDE = @SEDE, @PREFIJO = '@ITRA', @LONGITUD = 8, @NVOCONSEC = @CNSITRA OUTPUT
		EXEC SPK_INSERTRANSITO @CNSMOV, @CNSITRA
	END

	UPDATE IMOVH SET ESTADO = 1, FECHACONF = @HOY
	WHERE  CNSMOV = @CNSMOV
   
	BEGIN TRY  
	   PRINT 'ACTUALIZA KARDEX'
	   EXEC SPK_ACTUALIZA_KARDEX @CNSMOV
	END TRY  
	BEGIN CATCH  
	    PRINT 'ERROR AL ACTUALIZAR KARDEX'
	END CATCH
	
	IF DBO.FNK_VALORVARIABLE('CONTABIMOV_JOB') COLLATE DATABASE_DEFAULT = 'SI'
	BEGIN
		INSERT INTO IMOVC(CNSMOV, USUARIO, SYS_COMPUTERNAME, COMPANIA, SEDE, NROCOMPROBANTE)
		SELECT @CNSMOV,@USUARIO,@SYS_COMPUTERNAME,'01',@SEDE,''  
	END
	ELSE
	BEGIN
		IF (SELECT  SECONTABILIZA=IIF(ISNULL(IBOD.NOCONTABILIZA,0)=1,0,ISNULL(ITMO.SECONTABILIZA,0))
			FROM IMOV 
				INNER JOIN ITMO ON IMOV.IDTIPOMOV=ITMO.IDTIPOMOV
				INNER JOIN IBOD ON IBOD.IDBODEGA=IMOV.IDBODEGA
			WHERE IMOV.CNSMOV= @CNSMOV	) <> 0
		BEGIN
			PRINT 'ENVIO A CONTABILIDAD'
			EXEC SPK_NC_CONTAB_INV  @CNSMOV,@USUARIO,@SYS_COMPUTERNAME,'01',@SEDE,''  
			PRINT 'REGRESO DE CONTABILIDAD'
		END
	END
   /* SE AGREGA PARA ONCOLOGIA */
   DECLARE @I INT, @I_TO INT, @IDITAR VARCHAR(2), @IDITARHEMODERIVADOS VARCHAR(20), @CNSIMOH VARCHAR(20)

	SELECT @CLASEIZSDOL=CLASE, @NOADMISION=NOADMISION, @SECTOR=COALESCE(SECTOR,'') FROM IZSOL WHERE CNSIZSOL=@CNSIZSOL

	SELECT @CANTIZSOLDENTREGADO= COUNT(*) FROM IZSOLD WHERE CNSIZSOL=@CNSIZSOL and ESTADO=0
	SELECT @CANTIZSOLDTOTAL= COUNT(*) FROM IZSOLD WHERE CNSIZSOL=@CNSIZSOL
	IF @CANTIZSOLDTOTAL =  @CANTIZSOLDENTREGADO
	BEGIN
		UPDATE IZSOL SET ESTADO=2 WHERE CNSIZSOL=@CNSIZSOL
		--SELECT 1 AS CERRADO
	END
	/*IF @CLASEIZSDOL <> 'PROD' AND @CLASEIZSDOL <> 'Consumo'
	BEGIN
		EXEC SPQ_GENCOBRO_INSCENTRAL @CNSMOV, @NOADMISION,@SECTOR,@USUARIO,@SEDE
	END*/

    IF @CLASEIZSDOL='ONCO'
    BEGIN
		DECLARE @CURSOR TABLE (ID INT IDENTITY, IDSERVICIO VARCHAR(20) COLLATE DATABASE_DEFAULT, CANTIDAD VARCHAR(20) COLLATE DATABASE_DEFAULT, IDARTICULO VARCHAR(20) COLLATE DATABASE_DEFAULT)

		SELECT @IDTERCEROCA=IDTERCEROC,@IDPLANCA=IDPLAN FROM IZSOL WHERE CNSIZSOL=@CNSIZSOL

		INSERT INTO @CURSOR (IDSERVICIO, CANTIDAD, IDARTICULO)
		SELECT IMOVH.IDSERVICIO, IMOVH.CANTIDAD,IMOVH.IDARTICULO
		FROM IMOVH 
		WHERE CNSMOV=@CNSMOV
  
		SELECT @I=1, @I_TO=MAX(ID) FROM @CURSOR
		WHILE @I <= @I_TO
		BEGIN  
			SELECT @IDARTICULO=IDARTICULO, @IDSERVICIO=IDSERVICIO, @CANTIDADSOL=CANTIDAD FROM @CURSOR WHERE ID=@I

         SELECT TOP 1  @VLR_UNITARIO=ROUND(COALESCE(VALOR,0),-2) 
         FROM SERTOT1
         WHERE IDTERCERO=@IDTERCEROCA
         AND IDPLAN=@IDPLANCA
         AND IDSERVICIO=@IDSERVICIO
         AND FECHAFIN>GETDATE()
         AND FECHAFINFD>GETDATE()
         AND FECHAINI<=GETDATE()
         AND FECHAINIFD<=GETDATE()

			select @NOLOTE= NOLOTE , @NOLOTEPEDIDO=NOLOTEPEDIDO FROM ISAL WHERE IDARTICULO=@IDARTICULO and CNSMOV=@CNSMOV

			INSERT INTO HCATDIMOV (CONSECUTIVOCIT ,CNSMOV ,IDSERVICIO ,IDARTICULO ,NOLOTE ,NOLOTEPEDIDO ,CANTIDAD ,CANT_DEVUELTA ,
								DEV_CNSMOV ,USUARIO ,FECHA_CREA ,ESTADO ,OBSERVACION,VLR_UNITARIO )   
			SELECT  @NOADMISION, @CNSMOV,@IDSERVICIO, @IDARTICULO,@NOLOTE,@NOLOTEPEDIDO,@CANTIDADSOL,0,NULL,@USUARIO,@HOY,0,null,@VLR_UNITARIO
			
			SET @I += 1
			END  
		DELETE @CURSOR 
	END
   IF @CLASEIZSDOL = 'SENFER' AND DBO.FNK_VALORVARIABLE('HADM_USA_ACTIVIDADES') COLLATE DATABASE_DEFAULT = 'SI' /* PARA PERU */
      AND NOT EXISTS (SELECT  1 FROM  IMOVH
                        INNER JOIN SER ON IMOVH.IDARTICULO = SER.IDSERVICIO
                     WHERE SER.PREFIJO <> DBO.FNK_VALORVARIABLE('PREFIJOMATERIALES') COLLATE DATABASE_DEFAULT
                        AND IMOVH.CNSMOV = @CNSMOV )
      AND EXISTS (SELECT  1 FROM  IMOVH                     
                     INNER JOIN SER ON IMOVH.IDARTICULO = SER.IDSERVICIO
                  WHERE SER.PREFIJO = DBO.FNK_VALORVARIABLE('PREFIJOMATERIALES') COLLATE DATABASE_DEFAULT
                     AND IMOVH.CNSMOV = @CNSMOV)
   BEGIN
      SELECT @IDTERCEROCA=IDTERCERO ,@IDPLANCA = IDPLAN, @IDSEDE = IDSEDE, @COPA_VAR_PORC = COPA_VAR_PORC FROM HADM WHERE NOADMISION=@NOADMISION

      EXEC SPK_GENCONSECUTIVO '01',@IDSEDE,'@HPREP',@METODO OUTPUT
		SELECT @METODO = @IDSEDE + RIGHT('00000000'+CONVERT(VARCHAR(8),@METODO),8)
		
		INSERT INTO HPREP (NOPRESUPUESTO, NOADMISION, FECHA, IDTERCEROCA, IDPLAN, IDSEDE, ESTADO, VALORTOTAL, VALORCOPAGO, VALOREXCEDENTE, CONSECUTIVOHCA, USUARIO, PROCEDENCIA)
		SELECT @METODO, @NOADMISION, DBO.FNK_GETDATE(), @IDTERCEROCA, @IDPLANCA, @IDSEDE, 0, NULL, NULL, NULL, '', @USUARIO, 'INSUMO'

		INSERT INTO HPREPD (NOPRESUPUESTO, NO_ITEM, IDSERVICIO, CANTIDAD, VALOR, VALORCOPAGO, VALOREXCEDENTE, USUARIO, IGV, COPAGOVARIABLE)
      SELECT @METODO, ROW_NUMBER() OVER (ORDER BY IMOVH.IDARTICULO) AS NO_ITEM, IART.IDARTICULO, IMOVH.CANTIDAD, NULL, NULL, NULL, @USUARIO, NULL
         --,  CASE 
         --    WHEN PPTD.CANTNOCOBRABLE IS NULL THEN 100 - @COPA_VAR_PORC
         --    ELSE 100 - PPTD.CANTNOCOBRABLE
         --END AS COPAGOVARIABLE
        , COALESCE(PPTD.CANTNOCOBRABLE,(100-@COPA_VAR_PORC))
      FROM  IMOVH 
         INNER JOIN IART ON IMOVH.IDARTICULO = IART.IDARTICULO
         LEFT JOIN PPTD ON IART.IDSERVICIO = PPTD.IDSERVICIO AND PPTD.IDTERCERO = @IDTERCEROCA 
            AND PPTD.IDPLAN = @IDPLANCA AND PPTD.TIPORESTRICCION = 'C' AND PPTD.TIPOCALCULO = 'P' AND COALESCE(PPTD.CANTNOCOBRABLE,0) > 0
      WHERE CNSMOV = @CNSMOV

      EXEC SPK_RELIQUIDA_PRESUPUESTO_PERU @METODO
   END

	IF DBO.FNK_VALORVARIABLE('IXCOUNTRY') COLLATE DATABASE_DEFAULT = 'PERU' AND 1 = 2
	BEGIN
	   IF DBO.FNK_VALORVARIABLE('INTERFAZ_INV') COLLATE DATABASE_DEFAULT = 'INTER_SAP'
		BEGIN
			PRINT 'INICIO EL ENVIO A SAP'
			EXEC SPK_XML_MOVIN @CNSMOV
			PRINT 'REGRESO DE ENVIO A SAP'
		END 
	END
	DECLARE @CNSIZSOL_DISP VARCHAR(20)

	-- Obtener CNSIZSOL desde IMOV.NODOCUMENTO
	SELECT @CNSIZSOL_DISP = NODOCUMENTO 
	FROM IMOV
	WHERE CNSMOV = @CNSMOV

	-- Validar que exista y que la solicitud sea de tipo DISPENSACI�N (CE / TRANS_CE / APLIM / Consumo)
	IF @CNSIZSOL_DISP IS NOT NULL 
	   AND LTRIM(RTRIM(@CNSIZSOL_DISP)) <> ''
	   AND EXISTS (
		   SELECT 1 
		   FROM IZSOL 
		   WHERE CNSIZSOL = @CNSIZSOL_DISP 
			 AND CLASE IN ('CE', 'TRANS_CE', 'APLIM', 'Consumo')  
	   )
	BEGIN
		PRINT 'ACTUALIZANDO IZSOL, IZSOLD, AUTE Y AUTED CON CANTIDADES DISPENSADAS'

		-- ===================================================================================
		-- ACTUALIZAR IZSOLD: CANTIDAD_DISPENSADA, CANTIDAD_PENDIENTE y ESTADO por art�culo
		-- IMPORTANTE: Solo considerar movimientos CONFIRMADOS (ESTADO='1')
		-- ===================================================================================
		UPDATE IZSOLD
		SET 
			-- CANTIDAD_DISPENSADA: Suma acumulada de lo realmente entregado en TODOS los movimientos confirmados
			CANTIDAD_DISPENSADA = ISNULL((
				SELECT SUM(IZSOLDT.CANTIDADSOL)
				FROM IZSOLDT
				INNER JOIN IMOV ON IZSOLDT.CNSMOV = IMOV.CNSMOV
				WHERE IZSOLDT.CNSIZSOLD = IZSOLD.CNSIZSOLD
				  AND IMOV.ESTADO = '1'  -- Solo movimientos confirmados
			), 0),
			-- CANTIDAD_PENDIENTE: Diferencia entre lo solicitado y lo dispensado acumulado
			CANTIDAD_PENDIENTE = ISNULL(IZSOLD.CANTIDADSOL, 0) - ISNULL((
				SELECT SUM(IZSOLDT.CANTIDADSOL)
				FROM IZSOLDT
				INNER JOIN IMOV ON IZSOLDT.CNSMOV = IMOV.CNSMOV
				WHERE IZSOLDT.CNSIZSOLD = IZSOLD.CNSIZSOLD
				  AND IMOV.ESTADO = '1'  -- Solo movimientos confirmados
			), 0),
			-- ESTADO: 0 = Entregado (naranja), 1 = Pendiente (verde)
			-- Se actualiza a 0 cuando CANTIDAD_DISPENSADA >= CANTIDADSOL (completamente entregado)
			-- Usa comparaci�n con tolerancia para evitar problemas de precisi�n con decimales
			ESTADO = CASE 
				WHEN ISNULL(IZSOLD.CANTIDADSOL, 0) > 0 
					AND ABS(ISNULL(IZSOLD.CANTIDADSOL, 0) - ISNULL((
						SELECT SUM(IZSOLDT.CANTIDADSOL)
						FROM IZSOLDT
						INNER JOIN IMOV ON IZSOLDT.CNSMOV = IMOV.CNSMOV
						WHERE IZSOLDT.CNSIZSOLD = IZSOLD.CNSIZSOLD
						  AND IMOV.ESTADO = '1'  -- Solo movimientos confirmados
					), 0)) <= 0.01  -- Tolerancia de 0.01 para comparaci�n de decimales
				THEN 0  -- Completamente entregado ? Naranja
				ELSE 1   -- Pendiente ? Verde
			END
		WHERE IZSOLD.CNSIZSOL = @CNSIZSOL_DISP

		PRINT 'IZSOLD actualizado: ' + CAST(@@ROWCOUNT AS VARCHAR(10)) + ' registros'

		-- ===================================================================================
		-- ACTUALIZAR IZSOL: CANTIDAD_TOTAL_DISPENSADA y CANTIDAD_TOTAL_PENDIENTE
		-- ===================================================================================
		UPDATE IZSOL
		SET 
			-- CANTIDAD_TOTAL_DISPENSADA: Suma total de todos los art�culos dispensados
			CANTIDAD_TOTAL_DISPENSADA = ISNULL((
				SELECT SUM(IZSOLDT.CANTIDADSOL)
				FROM IZSOLDT
				INNER JOIN IZSOLD ON IZSOLDT.CNSIZSOLD = IZSOLD.CNSIZSOLD
				INNER JOIN IMOV ON IZSOLDT.CNSMOV = IMOV.CNSMOV
				WHERE IZSOLD.CNSIZSOL = @CNSIZSOL_DISP
				  AND IMOV.ESTADO = '1'  -- Solo movimientos confirmados
			), 0),
			-- CANTIDAD_TOTAL_PENDIENTE: Diferencia entre lo solicitado total y lo dispensado total
			CANTIDAD_TOTAL_PENDIENTE = ISNULL((
				SELECT SUM(IZSOLD.CANTIDADSOL)
				FROM IZSOLD
				WHERE IZSOLD.CNSIZSOL = @CNSIZSOL_DISP
			), 0) - ISNULL((
				SELECT SUM(IZSOLDT.CANTIDADSOL)
				FROM IZSOLDT
				INNER JOIN IZSOLD ON IZSOLDT.CNSIZSOLD = IZSOLD.CNSIZSOLD
				INNER JOIN IMOV ON IZSOLDT.CNSMOV = IMOV.CNSMOV
				WHERE IZSOLD.CNSIZSOL = @CNSIZSOL_DISP
				  AND IMOV.ESTADO = '1'  -- Solo movimientos confirmados
			), 0)
		WHERE IZSOL.CNSIZSOL = @CNSIZSOL_DISP

		PRINT 'IZSOL actualizado correctamente'

		-- ===================================================================================
		-- ACTUALIZAR AUTE: por CNSIZSOL (flujo nuevo) o por IDAUT=NOADMISION (legado)
		-- ===================================================================================
		DECLARE @NOADMISION_IZSOL VARCHAR(20)
		SELECT @NOADMISION_IZSOL = NOADMISION 
		FROM IZSOL 
		WHERE CNSIZSOL = @CNSIZSOL_DISP

		UPDATE AUTE
		SET CNSIZSOL = @CNSIZSOL_DISP
		WHERE (CNSIZSOL IS NULL OR CNSIZSOL = '')
		  AND AUTE.IDAUT = @NOADMISION_IZSOL

		/* Flujo nuevo: NOADMISION = afiliado ? amarrar P1 por CNSCEFM */
		UPDATE AUTE
		SET CNSIZSOL = COALESCE(NULLIF(CNSIZSOL, ''), @CNSIZSOL_DISP)
		WHERE (PERIODO LIKE '1/%' OR PERIODO = '1')
		  AND (CNSIZSOL IS NULL OR CNSIZSOL = '' OR CNSIZSOL = @CNSIZSOL_DISP)
		  AND CNSCEFM IN (
		    SELECT C.CNSCEFM FROM CEFM C WITH (NOLOCK)
		    WHERE C.IDAFILIADO = @NOADMISION_IZSOL AND C.ESTADO = 'AUDITADO'
		  )

		-- ===================================================================================
		-- ACTUALIZAR AUTED: por AUTE.CNSIZSOL (preferido) o IDAUT=NOADMISION
		-- ===================================================================================
		IF EXISTS (
			SELECT 1 
			FROM AUTE 
			WHERE AUTE.CNSIZSOL = @CNSIZSOL_DISP
			   OR AUTE.IDAUT = @NOADMISION_IZSOL
		)
		BEGIN
			PRINT 'ACTUALIZANDO AUTED CON CANTIDADES DISPENSADAS'

			UPDATE AUTED
			SET 
				CANTIDADDISPENSADA = ISNULL((
					SELECT SUM(IZSOLDT.CANTIDADSOL)
					FROM IZSOLDT
					INNER JOIN IZSOLD ON IZSOLDT.CNSIZSOLD = IZSOLD.CNSIZSOLD
					INNER JOIN IART ON IZSOLD.IDARTICULO = IART.IDARTICULO
					INNER JOIN IMOV ON IZSOLDT.CNSMOV = IMOV.CNSMOV
					WHERE IZSOLD.CNSIZSOL = @CNSIZSOL_DISP
					  AND IMOV.ESTADO = '1'
					  AND IART.IDSERVICIO = AUTED.IDSERVICIO
				), 0),
				CANTIDADPENDIENTE = ISNULL(AUTED.CANTIDAD, 0) - ISNULL((
					SELECT SUM(IZSOLDT.CANTIDADSOL)
					FROM IZSOLDT
					INNER JOIN IZSOLD ON IZSOLDT.CNSIZSOLD = IZSOLD.CNSIZSOLD
					INNER JOIN IART ON IZSOLD.IDARTICULO = IART.IDARTICULO
					INNER JOIN IMOV ON IZSOLDT.CNSMOV = IMOV.CNSMOV
					WHERE IZSOLD.CNSIZSOL = @CNSIZSOL_DISP
					  AND IMOV.ESTADO = '1'
					  AND IART.IDSERVICIO = AUTED.IDSERVICIO
				), 0),
				ESTADO = CASE
					WHEN ISNULL(AUTED.CANTIDAD, 0) <= 0 THEN 'Dispensado'
					WHEN ABS(
						ISNULL(AUTED.CANTIDAD, 0) - ISNULL((
							SELECT SUM(IZSOLDT.CANTIDADSOL)
							FROM IZSOLDT
							INNER JOIN IZSOLD ON IZSOLDT.CNSIZSOLD = IZSOLD.CNSIZSOLD
							INNER JOIN IART ON IZSOLD.IDARTICULO = IART.IDARTICULO
							INNER JOIN IMOV ON IZSOLDT.CNSMOV = IMOV.CNSMOV
							WHERE IZSOLD.CNSIZSOL = @CNSIZSOL_DISP
							  AND IMOV.ESTADO = '1'
							  AND IART.IDSERVICIO = AUTED.IDSERVICIO
						), 0)
					) <= 0.01 THEN 'Dispensado'
					ELSE AUTED.ESTADO
				END
			FROM AUTED
			INNER JOIN AUTE ON AUTED.IDAUTE = AUTE.IDAUTE
			WHERE (AUTE.CNSIZSOL = @CNSIZSOL_DISP OR AUTE.IDAUT = @NOADMISION_IZSOL)
			  AND AUTED.IDSERVICIO IS NOT NULL

			PRINT 'AUTED actualizado: ' + CAST(@@ROWCOUNT AS VARCHAR(10)) + ' registros'

			UPDATE AUTE
			SET ESTADO = 'Dispensado'
			FROM AUTE
			WHERE (AUTE.CNSIZSOL = @CNSIZSOL_DISP OR AUTE.IDAUT = @NOADMISION_IZSOL)
			  AND NOT EXISTS (
				  SELECT 1
				  FROM AUTED D
				  WHERE D.IDAUTE = AUTE.IDAUTE
					AND COALESCE(D.ESTADO, '') <> 'Dispensado'
			  )

			PRINT 'AUTE actualizado a Dispensado: ' + CAST(@@ROWCOUNT AS VARCHAR(10)) + ' registros'
		END
		ELSE
		BEGIN
			PRINT 'ADVERTENCIA: No existe AUTE relacionado con CNSIZSOL=' + @CNSIZSOL_DISP + ' y NOADMISION=' + ISNULL(@NOADMISION_IZSOL, 'NULL') + '. AUTED no se actualizar�.'
		END

		-- AUT de facturaci�n (Transcripciones CE)
		IF OBJECT_ID('dbo.SPQ_CEFM_CREA_AUT_DESDE_IMOV', 'P') IS NOT NULL
		BEGIN
			DECLARE @IDAUT_DISP VARCHAR(20), @ERR_AUT_DISP VARCHAR(500)
			BEGIN TRY
				EXEC DBO.SPQ_CEFM_CREA_AUT_DESDE_IMOV
					@CNSMOV = @CNSMOV,
					@USUARIO = @USUARIO,
					@IDSEDE = @SEDE,
					@COMPANIA = '01',
					@IDAUT = @IDAUT_DISP OUTPUT,
					@ERROR = @ERR_AUT_DISP OUTPUT
			END TRY
			BEGIN CATCH
				/* silencioso: inventario ya confirmado */
			END CATCH
		END

		-- ===================================================================================
		-- INSERTAR REGISTRO EN FHIR_BUNDLE PARA GENERACI�N DE BUNDLE MedicationDispense
		-- ===================================================================================
		-- Solo insertar si no existe ya un bundle para este movimiento
		IF NOT EXISTS (
			SELECT 1 
			FROM FHIR_BUNDLE 
			WHERE TIPOCNS = 'IMOV' 
			  AND CONSECUTIVO = @CNSMOV
			  AND RESOURCE_TYPE = 'MedicationDispense'
		)
		AND DBO.FNK_VALORVARIABLE('GENERA_BUNDLES_FHIR') COLLATE DATABASE_DEFAULT = 'SI'
		BEGIN
			INSERT INTO FHIR_BUNDLE (
				RESOURCE_TYPE,
				IDRESOURCE,
				BUNDLE_TYPE,
				JSON_BUNDLE,
				ESTADO_ACTUAL,
				FECHA_CREACION,
				FECHA_ULTIMO_ESTADO,
				USUARIO_CREACION,
				OBSERVACIONES,
				TIPOCNS,
				CONSECUTIVO
			)
			VALUES (
				'MedicationDispense',
				'',  -- IDRESOURCE se generar� cuando se construya el bundle
				'transaction',
				'',  -- JSON_BUNDLE se generar� por el proceso as�ncrono
				'PORGENERAR',
				GETDATE(),
				GETDATE(),
				@USUARIO,
				'',
				'IMOV',
				@CNSMOV
			)
			
			PRINT 'Registro insertado en FHIR_BUNDLE para MedicationDispense - CNSMOV: ' + @CNSMOV
		END
		ELSE
		BEGIN
			PRINT 'Ya existe un bundle MedicationDispense para CNSMOV: ' + @CNSMOV + '. No se inserta duplicado.'
		END
	END

	-- ===================================================================================
	-- INSERTAR EN IMOVH LOS MEDICAMENTOS NO DISPENSADOS (solo para reportes)
	-- ===================================================================================
	DECLARE @CNSIZSOL_SOL VARCHAR(20)

	-- Obtener CNSIZSOL desde IMOV.NODOCUMENTO
	SELECT @CNSIZSOL_SOL = NODOCUMENTO 
	FROM IMOV
	WHERE CNSMOV = @CNSMOV

	-- Validar que exista y que la solicitud sea de tipo DISPENSACI�N (CE / TRANS_CE / APLIM / Consumo)
	IF @CNSIZSOL_SOL IS NOT NULL 
	   AND LTRIM(RTRIM(@CNSIZSOL_SOL)) <> ''
	   AND EXISTS (
		   SELECT 1 
		   FROM IZSOL 
		   WHERE CNSIZSOL = @CNSIZSOL_SOL 
			 AND CLASE IN ('CE', 'TRANS_CE', 'APLIM', 'Consumo')  
	   )
	BEGIN
		-- tempdb puede usar collation distinta a la BD; alinear antes de JOIN con IZSOLD/IMOVH
		CREATE TABLE #NO_DISPENSADOS (
			IDARTICULO VARCHAR(20) COLLATE DATABASE_DEFAULT,
			CANT_SOLICITADA DECIMAL(14,2),
			CANT_ENTREGADA DECIMAL(14,2),
			CANT_FALTANTE AS (CANT_SOLICITADA - ISNULL(CANT_ENTREGADA, 0))
		)

		-- Solicitado: desde IZSOLD
		INSERT INTO #NO_DISPENSADOS (IDARTICULO, CANT_SOLICITADA)
		SELECT 
			IDARTICULO,
			SUM(CANTIDADSOL)
		FROM IZSOLD
		WHERE CNSIZSOL = @CNSIZSOL_SOL
		GROUP BY IDARTICULO

		-- Entregado: desde IZSOLDT (TOTAL de TODOS los movimientos confirmados)
		UPDATE ND
		SET CANT_ENTREGADA = ISNULL(ENT.CANT_ENTREGADA, 0)
		FROM #NO_DISPENSADOS ND
		LEFT JOIN (
			SELECT 
				IZSOLD.IDARTICULO,
				SUM(IZSOLDT.CANTIDADSOL) AS CANT_ENTREGADA
			FROM IZSOLDT
			INNER JOIN IZSOLD ON IZSOLDT.CNSIZSOLD = IZSOLD.CNSIZSOLD
			INNER JOIN IMOV ON IZSOLDT.CNSMOV = IMOV.CNSMOV
			WHERE IZSOLD.CNSIZSOL = @CNSIZSOL_SOL
			  AND IMOV.ESTADO = '1'  -- Solo movimientos confirmados
			GROUP BY IZSOLD.IDARTICULO
		) ENT ON ND.IDARTICULO = ENT.IDARTICULO

		-- Insertar solo los faltantes en IMOVH del MISMO movimiento
		INSERT INTO IMOVH (
			CNSMOV,
			IDARTICULO,
			CANTIDAD,
			CANTPEDIDA,
			ESTADO,
			NOPRESTACION,
			NOLOTE
		)
		SELECT 
			@CNSMOV,
			ND.IDARTICULO,
			0,                     -- CANTIDAD = 0 (no se entreg�)
			ND.CANT_FALTANTE,      -- CANTPEDIDA = cantidad faltante
			99,                    -- ESTADO = 99 (no dispensado)
			@CNSIZSOL_SOL,         -- NOPRESTACION = CNSIZSOL
			''
		FROM #NO_DISPENSADOS ND
		WHERE ND.CANT_FALTANTE > 0
		  AND NOT EXISTS (
			  SELECT 1 
			  FROM IMOVH 
			  WHERE CNSMOV = @CNSMOV
				AND IDARTICULO = ND.IDARTICULO 
				AND CANTIDAD = 0 
				AND ESTADO = 99
		  )

		DROP TABLE #NO_DISPENSADOS
	END
