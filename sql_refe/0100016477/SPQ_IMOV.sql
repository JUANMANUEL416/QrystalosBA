				IART.IDIMPUESTO,
				IDCLASE = IART.IDCLASE_IMP,
            
				FIMPD.DESCRIPCION AS IMPUESTO_DESC,
				FIMPDV.VALOR AS PORCENTAJE_IVA
			FROM IMOVH
				INNER JOIN IART ON IMOVH.IDARTICULO = IART.IDARTICULO
            
				-- ? JOIN directo con IART (ya no necesita SER)
				LEFT JOIN FIMPD ON IART.IDIMPUESTO = FIMPD.IDIMPUESTO 
							   AND IART.IDCLASE_IMP = FIMPD.IDCLASE
				LEFT JOIN FIMPDV ON FIMPD.IDIMPUESTO = FIMPDV.IDIMPUESTO 
								 AND FIMPD.IDCLASE = FIMPDV.IDCLASE
			WHERE IMOVH.CNSMOV = @CNSMOV
				AND IART.MIVA = 1

		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF EXISTS(SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
    
