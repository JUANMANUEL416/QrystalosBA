							   AND IEXI.NOLOTE = ISAL.NOLOTE 
							   AND IEXI.IDARTICULO = ISAL.IDARTICULO
							   AND COALESCE(IEXI.NOLOTEPEDIDO, '') = COALESCE(ISAL.NOLOTEPEDIDO, '')
			WHERE ISAL.CNSMOV = @CNSMOV

