CREATE OR ALTER PROCEDURE DBO.SPK_INSERT_ITRA_REQ  
@CNSFCOM VARCHAR(20),  
@USUARIO VARCHAR(12),  
@SYSCOMPUTER VARCHAR(20),  
@COMPANIA VARCHAR(2),  
@SEDE VARCHAR(5)  
WITH ENCRYPTION
AS  
DECLARE @NUEVOCNS          VARCHAR(20)  
DECLARE @IDTIPOMOV         VARCHAR(2)  
DECLARE @NOLOTE            VARCHAR(20)  
DECLARE @IDARTICULO_CUR    VARCHAR(20)  
DECLARE @CANTIDAD_CUR      DECIMAL(14,2)  
DECLARE @VR_UNITMASIVA_CUR DECIMAL(14,2)  
DECLARE @VR_UNITSINIVA_CUR DECIMAL(18,6)  
DECLARE @IVA_CUR           DECIMAL(14,2)  -- SE AGREGA IVA
DECLARE @NOLOTE_CUR        VARCHAR(20)  
DECLARE @FECHAVENCE_CUR    DATETIME  
DECLARE @PCOSTOANTES_CUR   DECIMAL(16,3)  
DECLARE @DETALLE_CUR       VARCHAR(255)  
DECLARE @VUNIT_CUR         DECIMAL(14,2)
DECLARE @CONT              INT
DECLARE @TIPOREGIMEN       VARCHAR(1) 
DECLARE @DECONSUMO         SMALLINT
DECLARE @ODESFERA   VARCHAR(20)
DECLARE @OIESFERA   VARCHAR(20)
DECLARE @ODCILINDRO VARCHAR(20)
DECLARE @OICILINDRO VARCHAR(20)
DECLARE @ODEJE      VARCHAR(20)
DECLARE @OIEJE      VARCHAR(20)
DECLARE @ODADICION  VARCHAR(20)
DECLARE @OIADICION  VARCHAR(20)
DECLARE @ODALT      VARCHAR(20)
DECLARE @OIALT      VARCHAR(20)
DECLARE @ODAVL      VARCHAR(20)
DECLARE @OIAVL      VARCHAR(20)
DECLARE @ODTLENTE   VARCHAR(20)
DECLARE @OITLENTE   VARCHAR(20)
DECLARE @ODDNP      VARCHAR(20)
DECLARE @OIDNP      VARCHAR(20)
BEGIN  
   SET @IDTIPOMOV=(SELECT DATO FROM USVGS WHERE IDVARIABLE='IDINVMOV_COMPRAS')

   IF (SELECT IDTIPOSER FROM FCOM WHERE CNSFCOM=@CNSFCOM)='Presta'
      SET @IDTIPOMOV=(SELECT DATO FROM USVGS WHERE IDVARIABLE='IDINVMOV_PRESTAMOS')

   /* ACA SABEMOS SI ES REGIMEN COMUN O REGIMEN SIMPLIFICADO */
   SELECT @TIPOREGIMEN = TER.TIPOREGIMEN
   FROM   TER INNER JOIN FCOM ON TER.IDTERCERO = FCOM.IDTERCERO
   WHERE  CNSFCOM = @CNSFCOM
   
   SELECT @DECONSUMO = DECONSUMO FROM FCOM WHERE CNSFCOM = @CNSFCOM
   
   DECLARE CURSOR_COMPRA CURSOR FOR  
   SELECT FCOMD.IDARTICULO, CANTIDAD, VR_UNITMASIVA, FACTORIVA,VLR_UNITARIO, NOLOTE, FECHAVENCE, IART.PCOSTO,FCOMD.DETALLE,  ---SE AGREGA IVA Y VALOR UNITARIO
          FCOMD.VLR_UNITARIO,ODESFERA,OIESFERA,ODCILINDRO,OICILINDRO,ODEJE,OIEJE,ODADICION,OIADICION,
          ODALT,OIALT,ODAVL,OIAVL,ODTLENTE,OITLENTE,ODDNP,OIDNP
   FROM   FCOMD 
          INNER JOIN IART 
             ON FCOMD.CNSFCOM = @CNSFCOM 
            AND FCOMD.IDARTICULO = IART.IDARTICULO  
   -- No filtrar por FCOMD.TIPO: se han observado casos donde TIPO no viene exactamente como 'Articulos'
   -- y eso hace que art�culos (p.ej. biol�gicos) no se inserten en el tr�nsito.
   WHERE  FCOMD.CNSFCOM = @CNSFCOM
   
   OPEN CURSOR_COMPRA  
   
   FETCH NEXT FROM CURSOR_COMPRA  
   INTO @IDARTICULO_CUR,  @CANTIDAD_CUR,  @VR_UNITMASIVA_CUR, @IVA_CUR,@VR_UNITSINIVA_CUR, @NOLOTE_CUR, @FECHAVENCE_CUR,  
        @PCOSTOANTES_CUR, @DETALLE_CUR  , @VUNIT_CUR,
        @ODESFERA,@OIESFERA,@ODCILINDRO,@OICILINDRO,@ODEJE,@OIEJE,@ODADICION,@OIADICION,@ODALT,
        @OIALT,@ODAVL,@OIAVL,@ODTLENTE,@OITLENTE,@ODDNP,@OIDNP
        --SELECT @VR_UNITSINIVA_CUR
   SET @CONT = 0
   WHILE @@FETCH_STATUS = 0  
   BEGIN    
      SET @CONT = @CONT + 1
      IF @CONT = 1
      BEGIN
         -- Evitar duplicaci�n de consecutivo en concurrencia (sin l�mite de intentos).
         DECLARE @LOCK_RES_ITRA NVARCHAR(200) = N'QRYSTALOS:CONSEC:@ITRA:' + COALESCE(@COMPANIA,'') + N':' + COALESCE(@SEDE,'');
         DECLARE @LOCK_R_ITRA INT;
         DECLARE @LOCK_TAKEN_ITRA BIT = 0;
         WHILE 1 = 1
         BEGIN
            EXEC @LOCK_R_ITRA = sys.sp_getapplock
                 @Resource = @LOCK_RES_ITRA,
                 @LockMode = 'Exclusive',
                 @LockOwner = 'Session',
                 @LockTimeout = 10000;
            IF @LOCK_R_ITRA >= 0
            BEGIN
               SET @LOCK_TAKEN_ITRA = 1;
               BREAK;
            END

            WAITFOR DELAY '00:00:00.2';
         END

         WHILE 1 = 1
         BEGIN
            SET @NUEVOCNS = SPACE(20);
            EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@ITRA',@NUEVOCNS OUTPUT;
            SELECT @NUEVOCNS = @SEDE + REPLACE(SPACE(8 - LEN(@NUEVOCNS)) + LTRIM(RTRIM(@NUEVOCNS)), SPACE(1), 0);

            BEGIN TRY
               INSERT INTO ITRA(CNSITRA,IDBODEGAORI,IDBODEGADES,USUARIOORI,USUARIODES,USUARIOTRA,  
                                PROCEDENCIA,CNSMOVORI,CNSMOVDES,NOADMISION,FECHAING,FECHAEGR,ESTADO,  
                                IDTIPOMOV,IDDEP,CNSFCOM,CCOSTO,IDAREA,LOTEADO)  
               SELECT @NUEVOCNS,'',FCOM.IDBODEGA,@USUARIO,'',FCOM.IDTERCERO,'INV',  
                      'ORDEN DE COMPRA','','',DBO.FNK_FECHA_SIN_MLS(GETDATE()),'',0,@IDTIPOMOV,'',CNSFCOM,CCOSTO,IDAREA,0  
               FROM   FCOM 
               WHERE  CNSFCOM=@CNSFCOM;
               BREAK;
            END TRY
            BEGIN CATCH
               -- 2627/2601 = clave duplicada (PK/Unique). Reintentar con nuevo consecutivo sin tope.
               IF ERROR_NUMBER() IN (2601,2627)
               BEGIN
                  WAITFOR DELAY '00:00:00.05';
                  CONTINUE;
               END
               IF @LOCK_TAKEN_ITRA = 1
                  EXEC sys.sp_releaseapplock @Resource = @LOCK_RES_ITRA, @LockOwner = 'Session';

               DECLARE @ERRMSG_ITRA NVARCHAR(2048) = ERROR_MESSAGE();
               RAISERROR(@ERRMSG_ITRA, 16, 1);
               RETURN;
            END CATCH
         END

         IF @LOCK_TAKEN_ITRA = 1
            EXEC sys.sp_releaseapplock @Resource = @LOCK_RES_ITRA, @LockOwner = 'Session';
      END
      
      SET @NOLOTE=SPACE(20)
      EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@ICBU',@NOLOTE OUTPUT
      SELECT @NOLOTE = @SEDE +'L'+ REPLACE(SPACE(7 - LEN(@NOLOTE))+LTRIM(RTRIM(@NOLOTE)),SPACE(1),0)
      INSERT INTO ITRAH (CNSITRA,IDARTICULO,NOLOTE,CANTIDADORI,CANTIDADDES,IDCAUSAL,ESTADO,  
                         PCOSTO,NOLOTEPEDIDO,FECHAVENCE,DETALLE,IDARTICULOORI,ODESFERA,OIESFERA,ODCILINDRO,OICILINDRO,ODEJE,OIEJE,
                         ODADICION,OIADICION,ODALT,OIALT,ODAVL,OIAVL,ODTLENTE,OITLENTE,ODDNP,OIDNP,IVA,PCSINIVA,INICIAL) -- INSERT IVA  
      SELECT @NUEVOCNS AS MOV,@IDARTICULO_CUR AS IDARTICULO, @NOLOTE, @CANTIDAD_CUR AS CANTIDADORI,  
             0 AS CANTIDADDES, '' AS IDCAUSAL,0 AS ESTADO, 
             CASE @TIPOREGIMEN 
                  WHEN 'C' THEN CASE @DECONSUMO 
                                     WHEN 0 THEN @VUNIT_CUR  
                                     ELSE @VR_UNITMASIVA_CUR
                                END             
                  ELSE @VR_UNITMASIVA_CUR
             END,  
             @NOLOTE_CUR, @FECHAVENCE_CUR, @DETALLE_CUR,@IDARTICULO_CUR,
             @ODESFERA,@OIESFERA,@ODCILINDRO,@OICILINDRO,@ODEJE,@OIEJE,@ODADICION,@OIADICION,@ODALT,
             @OIALT,@ODAVL,@OIAVL,@ODTLENTE,@OITLENTE,@ODDNP,@OIDNP,@IVA_CUR,@VR_UNITSINIVA_CUR,0

      FETCH NEXT FROM CURSOR_COMPRA  
      INTO   @IDARTICULO_CUR,  @CANTIDAD_CUR, @VR_UNITMASIVA_CUR,@IVA_CUR,@VR_UNITSINIVA_CUR, @NOLOTE_CUR, @FECHAVENCE_CUR,  
             @PCOSTOANTES_CUR, @DETALLE_CUR,  @VUNIT_CUR,
             @ODESFERA,@OIESFERA,@ODCILINDRO,@OICILINDRO,@ODEJE,@OIEJE,@ODADICION,@OIADICION,@ODALT,
             @OIALT,@ODAVL,@OIAVL,@ODTLENTE,@OITLENTE,@ODDNP,@OIDNP              
   END  
   CLOSE CURSOR_COMPRA  
   DEALLOCATE CURSOR_COMPRA 

   -- Art�culos que NO manejan loteo (MLOTEO=1): quedan como recibidos al 100% y sin pendiente.
   UPDATE B
      SET B.CANTIDADDES = B.CANTIDADORI,
          B.INICIAL = 1,
		  B.NOLOTEPEDIDO = CASE WHEN COALESCE(B.NOLOTEPEDIDO,'') = '' THEN '0' ELSE B.NOLOTEPEDIDO END,
          B.FECHAVENCE = COALESCE(B.FECHAVENCE, DATEADD(DAY, 360, GETDATE()))
   FROM ITRAH B
   INNER JOIN IART ON B.IDARTICULO = IART.IDARTICULO
   INNER JOIN ITAR ON IART.IDITAR = ITAR.IDITAR
   WHERE B.CNSITRA = @NUEVOCNS
     AND COALESCE(B.INICIAL,0) = 0
     AND COALESCE(ITAR.MLOTEO,0) = 1

END
