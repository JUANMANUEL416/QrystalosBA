		BEGIN
			SELECT 'KO' AS OK
			SELECT 'No existe la tabla FCOMNOT. Ejecute el script DDL_FCOMNOT.sql.' AS ERROR
			RETURN
		END

		BEGIN TRY
			INSERT INTO FCOMNOT (CNSFCOM, FECHA, USUARIO, NOTA)
			SELECT @CNSFCOM, DBO.FNK_GETDATE(), @USUARIO, LTRIM(RTRIM(@NOTA_OC))
		END TRY
		BEGIN CATCH
			SELECT 'KO' AS OK
			SELECT ERROR_MESSAGE() AS ERROR
			RETURN
		END CATCH

		SELECT 'OK' AS OK
		RETURN
	END

