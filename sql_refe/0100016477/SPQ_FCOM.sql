		FROM OPENJSON(@PARAMETROS)
		WITH (
			CNSFCOM VARCHAR(20)  '$.CNSFCOM',
			NOTA    VARCHAR(MAX) '$.NOTA'
		)

		IF COALESCE(@CNSFCOM, '') = ''
		BEGIN
			SELECT 'KO' AS OK
			SELECT 'CNSFCOM es obligatorio.' AS ERROR
			RETURN
		END

