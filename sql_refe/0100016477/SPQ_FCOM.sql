CREATE OR ALTER PROCEDURE DBO.SPQ_FCOM @JSON  NVARCHAR(MAX)
WITH      ENCRYPTION
AS
DECLARE  @ERRORES AS TABLE(ERROR VARCHAR(MAX))
DECLARE  @PARAMETROS NVARCHAR(MAX), 
    @METODO VARCHAR(100), 
    @MODELOACT NVARCHAR(MAX)	,@PROCESO VARCHAR(20)		,@CONSECUTIVO VARCHAR(20)
    ,@USUARIO VARCHAR(12),@GRUPO VARCHAR(20), @USUNOMBRE VARCHAR(250)	
    ,@IDSEDE VARCHAR(20),	@SEDE VARCHAR(20)	,@CNSRPDX VARCHAR(20)
    ,@COMPANIA VARCHAR(20),	@IDARTICULO VARCHAR(20)	,@CANTIDAD INT , @FDESDE DATE, @FHASTA DATE
    ,@CNSFCOM VARCHAR(20) ,@CNSFCOM_NUEVO VARCHAR(20),	@datoSOL NVARCHAR(MAX)	, @VALOR DECIMAL(14,2)
    ,@SYS_COMPUTERNAME VARCHAR(50)	,@IDBODEGA VARCHAR(20)	, @IDBODEGA_DESTINO VARCHAR(20)	, @ITEMS NVARCHAR(MAX)
    ,@ORDENCOMPRA SMALLINT	, @CNSFCOMN VARCHAR(20)	, @NVOCONSEC VARCHAR(20)	,@PREFIJO VARCHAR(20)	, @OBSERVACION VARCHAR(4096)
    ,@FECHA VARCHAR(10), @N_FACTURA VARCHAR(20), @IDTERCERO VARCHAR(20), @USUARIOORDEN VARCHAR(20), @F_FACTURA VARCHAR(10), @F_VENCE VARCHAR(10)
    ,@TIPO_SEGUIMIENTO VARCHAR(20)  ,@ESTADO VARCHAR(10)
    ,@NOTA_OC VARCHAR(MAX), @USUARIO_NOTA VARCHAR(12), @ID_NOTA INT, @CNSFCOM_NOTA VARCHAR(20)
BEGIN
	SELECT *
	INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)  AS JSON
	)
	SET LANGUAGE Spanish;  
	SET DATEFORMAT dmy

	SELECT @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON
	SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO), @USUNOMBRE = NOMBRE FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME, @COMPANIA = COMPANIA FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @IDSEDE = IDSEDE, @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
	PRINT '@USUARIO='+@USUARIO

	IF @METODO IN ('RECEPCION_MASIVA', 'RECEPCION_MASIVA_PREVIEW')
	BEGIN
		EXEC DBO.SPQ_FCOM_RECEPCION_MASIVA @JSON
		RETURN
	END
	/*
	Entendiendo los estados de FCOM
		A=Anulada
		C=Por Confirmar
		P=Procesada
		R=Recepci�n parcial
		E=Por Confirmar al Almac�n (filtro UI)
		I=Confirmada en Almac�n
	*/
	IF @METODO = 'PROVEEDORES'
	BEGIN
		SELECT 'OK' AS OK
		SELECT TER.IDTERCERO, RAZONSOCIAL, NIT
		FROM TER
		INNER JOIN TEXCA ON TER.IDTERCERO=TEXCA.IDTERCERO
		WHERE TEXCA.IDCATEGORIA = 'PRO'
		RETURN
	END
	IF @METODO = 'CENTROSCOSTOS'
	BEGIN
		SELECT 'OK' AS OK
		SELECT TER.IDTERCERO, RAZONSOCIAL
		FROM TER
		INNER JOIN TEXCA ON TER.IDTERCERO=TEXCA.IDTERCERO
		WHERE TEXCA.IDCATEGORIA = 'PRO'
		RETURN
	END
	IF @METODO = 'USERAUTO'
	BEGIN
		SELECT 'OK' AS OK
		select USUARIO,NOMBRE from USUSU
		RETURN
	END
	IF @METODO = 'CENTROcOSTOS'
	BEGIN
		SELECT 'OK' AS OK
		select CCOSTO,DESCRIPCION from CEN
		RETURN
	END
	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
			SELECT @IDSEDE = IDSEDE, @COMPANIA=COMPANIA FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME

            DECLARE @NUEVO_REGISTRO AS BIT = 1
			DECLARE @HOY DATE = CAST(DBO.FNK_GETDATE() AS DATE)

            SELECT @CNSFCOM = JSON_VALUE(@PARAMETROS, '$.CNSFCOM')
			SELECT @F_FACTURA = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.F_FACTURA'))), '')
			SELECT @F_VENCE = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.F_VENCE'))), '')

			IF COALESCE(@F_FACTURA, '') <> ''
			   AND TRY_CAST(REPLACE(@F_FACTURA, '-', '') AS DATE) > @HOY
			BEGIN
				INSERT INTO @ERRORES(ERROR)
				SELECT 'La fecha de la factura no puede ser posterior a la fecha actual.'
			END

			IF COALESCE(@F_VENCE, '') <> ''
			   AND COALESCE(@F_FACTURA, '') <> ''
			   AND TRY_CAST(REPLACE(@F_VENCE, '-', '') AS DATE) < TRY_CAST(REPLACE(@F_FACTURA, '-', '') AS DATE)
			BEGIN
				INSERT INTO @ERRORES(ERROR)
				SELECT 'La fecha de vencimiento no puede ser anterior a la fecha de la factura. Verifique la fecha ingresada.'
			END

			IF EXISTS (SELECT 1 FROM @ERRORES)
			BEGIN
				SELECT 'KO' AS OK
				SELECT ERROR FROM @ERRORES
				RETURN
			END

            IF @CNSFCOM IS NOT NULL
            BEGIN
                SELECT @NUEVO_REGISTRO = 0
            END

            IF @NUEVO_REGISTRO = 1
            BEGIN
				EXEC SPQ_GENSEQUENCE @SEDE=@IDSEDE,@PREFIJO='@FCOM', @LONGITUD=8 ,@NVOCONSEC=@CNSFCOM OUTPUT
            END

			IF @NUEVO_REGISTRO = 1
            BEGIN
                INSERT INTO FCOM(CNSFCOM, COMPANIA, IDTERCERO, N_FACTURA, F_FACTURA, F_VENCE, VENDEDOR, ESTADO, F_CANCELADO, OBSERVACION, 
                    VR_ANTESIVA, IVA, VR_TOTAL, CNSFCOT, AJUSTADO, AJUSTEALPESO, ENINVENTARIO, ENCXP, VR_DESCUENTO, USUARIO, FECHA, 
                    ORDENCOMPRA, USUARIOORDEN, FECHAORDEN, IDBODEGA, CCOSTO, IDAREA, IDTIPOSER, CODUNG, CODPRG, DCONSUMO, DECONSUMO, 
                    TIPOANTICIPO, ESACTIVO, MANTICIPO, CNSPPTO, CNSCDP, CNSRP, AUTOCOMPRA, USUAUTOCOMPRA, VLR_FLETE, USUAUDITA)

                SELECT @CNSFCOM AS CNSFCOM		,@COMPANIA AS COMPANIA
                        ,IDTERCERO				,N_FACTURA
                        ,TRY_CAST(REPLACE(F_FACTURA,'-','') AS DATETIME),TRY_cAST(REPLACE(F_VENCE,'-','') AS DATETIME)
                        ,VENDEDOR				,ESTADO = 'C'
                        ,F_CANCELADO = NULL		,OBSERVACION

                        ,VR_ANTESIVA = 0		,IVA = 0
                        ,VR_TOTAL = 0			,CNSFCOT
                        ,AJUSTADO = 0			,AJUSTEALPESO = 0
                        ,ENINVENTARIO = 0		,ENCXP = 0
                        ,VR_DESCUENTO			,USUARIO = @USUARIO
                        ,DBO.FNK_GETDATE()
                        ,ORDENCOMPRA = 0		,USUARIOORDEN
                        ,TRY_CAST(REPLACE(FECHAORDEN,'-','') AS DATETIME)
                        ,IDBODEGA
                        ,CCOSTO					,IDAREA
                        ,IDTIPOSER				,CODUNG
                        ,CODPRG					,DCONSUMO = 0
                        ,1						
                        
                        ,TIPOANTICIPO
                        ,ESACTIVO = 0			,MANTICIPO
                        ,CNSPPTO = CNSPPTO		,CNSCDP
                        ,CNSRP					,AUTOCOMPRA = 0
                        ,USUAUTOCOMPRA = NULL	,VLR_FLETE = VLR_FLETE
                        ,USUAUDITA = NULL
                FROM OPENJSON(@PARAMETROS) WITH(
                    IDTERCERO VARCHAR(20) '$.IDTERCERO'
                    ,CNSFCOT VARCHAR(20) '$.CNSFCOT'
                    ,N_FACTURA VARCHAR(20) '$.N_FACTURA'
                    ,F_FACTURA VARCHAR(20) '$.F_FACTURA'
                    ,F_VENCE VARCHAR(20) '$.F_VENCE'
                    ,FECHAORDEN VARCHAR(20) '$.FECHAORDEN'
                    ,VENDEDOR VARCHAR(100) '$.VENDEDOR'
                    ,OBSERVACION VARCHAR(4096) '$.OBSERVACION'
                    ,FECHA VARCHAR(20) '$.FECHA'
                    ,USUARIOORDEN VARCHAR(20) '$.USUARIOORDEN'
                    ,IDBODEGA VARCHAR(20) '$.IDBODEGA'
                    ,CCOSTO VARCHAR(20) '$.CCOSTO'
                    ,TIPOANTICIPO VARCHAR(20) '$.TIPOANTICIPO'
                    ,MANTICIPO SMALLINT '$.MANTICIPO'
                    ,DECONSUMO SMALLINT '$.DECONSUMO'
                    ,IDTIPOSER VARCHAR(20) '$.IDTIPOSER'
                    ,VR_DESCUENTO DECIMAL(14,2) '$.VR_DESCUENTO'
                    ,VLR_FLETE DECIMAL(14,2) '$.VLR_FLETE'
                    ,IDAREA VARCHAR(20) '$.IDAREA'
                    ,CODUNG VARCHAR(20) '$.CODUNG'
                    ,CODPRG VARCHAR(20) '$.CODPRG'
                    ,CNSRP VARCHAR(20) '$.CNSRP'
                    ,CNSPPTO VARCHAR(20) '$.CNSPPTO'
                    ,CNSCDP VARCHAR(20) '$.CNSCDP'
                    
                ) AS #T
            END
            ELSE
            BEGIN
                UPDATE FCOM
                SET IDTERCERO = #T.IDTERCERO
                    ,N_FACTURA = #T.N_FACTURA
                    ,F_FACTURA = TRY_CAST(REPLACE(#T.F_FACTURA,'-','') AS DATETIME)
                    ,F_VENCE = TRY_CAST(REPLACE(#T.F_VENCE,'-','') AS DATETIME)
                    ,VENDEDOR = #T.VENDEDOR
                    ,OBSERVACION = #T.OBSERVACION
                    ,FECHAORDEN = TRY_CAST(REPLACE(#T.FECHAORDEN,'-','') AS DATETIME)
                    --,FECHA = #T.FECHA
                    ,USUARIOORDEN = #T.USUARIOORDEN
                    -- ,IDBODEGA = #T.IDBODEGA
                    ,CCOSTO = #T.CCOSTO
                    ,TIPOANTICIPO = #T.TIPOANTICIPO
                    ,MANTICIPO = #T.MANTICIPO
                    ,DECONSUMO = #T.DECONSUMO
                    ,IDTIPOSER = #T.IDTIPOSER
                    -- ,VR_DESCUENTO = #T.VR_DESCUENTO
                    ,VLR_FLETE = #T.VLR_FLETE
                    ,IDAREA = #T.IDAREA
                    ,CODUNG = #T.CODUNG
                    ,CODPRG = #T.CODPRG
                    ,CNSRP = #T.CNSRP
                    ,CNSPPTO = #T.CNSPPTO
                    ,CNSCDP = #T.CNSCDP
                 FROM FCOM INNER JOIN
					
				 OPENJSON(@PARAMETROS) WITH(
                    IDTERCERO VARCHAR(20) '$.IDTERCERO'
                    ,CNSFCOT VARCHAR(20) '$.CNSFCOT'
                    ,N_FACTURA VARCHAR(20) '$.N_FACTURA'
                    ,F_FACTURA VARCHAR(20) '$.F_FACTURA'
                    ,F_VENCE VARCHAR(20) '$.F_VENCE'
                    ,VENDEDOR VARCHAR(100) '$.VENDEDOR'
                    ,OBSERVACION VARCHAR(4096) '$.OBSERVACION'
                    ,FECHAORDEN VARCHAR(20) '$.FECHAORDEN'
                    ,FECHA VARCHAR(20) '$.FECHA'
                    ,USUARIOORDEN VARCHAR(20) '$.USUARIOORDEN'
                    ,IDBODEGA VARCHAR(20) '$.IDBODEGA'
                    ,CCOSTO VARCHAR(20) '$.CCOSTO'
                    ,TIPOANTICIPO VARCHAR(20) '$.TIPOANTICIPO'
                    ,MANTICIPO SMALLINT '$.MANTICIPO'
                    ,DECONSUMO SMALLINT '$.DECONSUMO'
                    ,IDTIPOSER VARCHAR(20) '$.IDTIPOSER'
                    ,VR_DESCUENTO DECIMAL(14,2) '$.VR_DESCUENTO'
                    ,VLR_FLETE DECIMAL(14,2) '$.VLR_FLETE'
                    ,IDAREA VARCHAR(20) '$.IDAREA'
                    ,CODUNG VARCHAR(20) '$.CODUNG'
                    ,CODPRG VARCHAR(20) '$.CODPRG'
                    ,CNSRP VARCHAR(20) '$.CNSRP'
                    ,CNSPPTO VARCHAR(20) '$.CNSPPTO'
                    ,CNSCDP VARCHAR(20) '$.CNSCDP'
                    ,CNSFCOM VARCHAR(20) '$.CNSFCOM'
                    
                ) AS #T ON FCOM.CNSFCOM = #T.CNSFCOM 
                WHERE FCOM.CNSFCOM = @CNSFCOM

            END
		END TRY
		BEGIN CATCH
			INSERT INTO @ERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (SELECT COUNT(1) FROM @ERRORES)>0
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @ERRORES
			RETURN
		END

		SELECT 'OK' AS OK, @CNSFCOM AS CNSFCOM
	END
	IF @METODO = 'CCOSTOS'
	BEGIN
		SELECT 'OK' AS OK
		SELECT CEN.CCOSTO,CEN.DESCRIPCION,AFU.IDAREA, AFU.DESCRIPCION DESCAREA FROM CEN
		INNER JOIN AFU ON AFU.IDAREA=CEN.IDAREA
		WHERE CEN.ESTADO='Activo'
		AND AFU.ESTADO=1
		ORDER BY CEN.DESCRIPCION
		RETURN
	END
	IF @METODO = 'ANULAR'
	BEGIN
		SELECT @CNSFCOM = JSON_VALUE(@PARAMETROS, '$.CNSFCOM')
		UPDATE FCOM SET ESTADO='A' WHERE CNSFCOM=@CNSFCOM
		IF EXISTS (SELECT 1 FROM  FCOM WHERE CNSFCOM = @CNSFCOM AND COALESCE(PROCEDENCIA,'') = 'ILPRE')
		BEGIN
			UPDATE ICTZD SET PROCESADO = 0, CNSFCOM = NULL WHERE CNSFCOM = @CNSFCOM
		END
		IF EXISTS (SELECT 1 FROM  FCOM WHERE CNSFCOM = @CNSFCOM AND COALESCE(PROCEDENCIA,'') = 'IEXIF')
		BEGIN
			UPDATE APLIMF SET APLIMF.ESTADO = 'PENDIENTE COMPRA' FROM APLIMF  WHERE APLIMF.ID IN  (SELECT IEXIF.IDAPLIMF FROM  IEXIF WHERE IEXIF.CNSFCOM = @CNSFCOM AND IEXIF.IDAPLIMF IS NOT NULL )
			UPDATE IEXIF SET ESTADO = 'PENDIENTE COMPRA', CNSFCOM = NULL WHERE CNSFCOM = @CNSFCOM
		END

		SELECT 'OK' AS OK, @CNSFCOM AS CNSFCOM
		RETURN
	END
	IF @METODO = 'IMPRIMIR' --MANTICIPO
	BEGIN
		SELECT @CNSFCOM = JSON_VALUE(@PARAMETROS, '$.CNSFCOM')

		SELECT 
			FCOM.IDBODEGA, IBOD.DESCRIPCION AS DESCBODEGA
			-- Datos de la sede
			,CIU.NOMBRE AS CIUDAD
			,SED.IDSEDE
			,SED.NIT AS NIT_SEDE
			,SED.DESCRIPCION AS DESCRIPCION_SEDE
			,SED.DIRECCION AS DIRECCION_SEDE
			,TER.NIT, TER.RAZONSOCIAL, TER.DV, TER.DIRECCION, TELEFONOS = DBO.FNK_TelefonosTercero(FCOM.IDTERCERO)
			,FCOM.VENDEDOR
			,FCOM.FECHA
			,FCOM.CCOSTO, CEN.DESCRIPCION DESCCOSTO
			,FCOM.IDAREA, AFU.DESCRIPCION DESCAREA
			,FCOM.F_VENCE
			,COALESCE(FCOM.MANTICIPO,0) MANTICIPO
			,FCOM.CNSFCOT
			,FCOM.OBSERVACION
			,FCOM.VLR_FLETE
			,FCOM.VR_DESCUENTO
			,FCOM.IVA
			,FCOM.VR_TOTAL
			,FECHA_IMPRESION = CURRENT_TIMESTAMP
			,ORDENCOMPRA = COALESCE(FCOM.ORDENCOMPRA, 0)
			,FCOM.IDTIPOSER
		,FCOM.N_FACTURA
		,FCOM.F_FACTURA
		,FCOM.ESTADO
			,FCOM.USUARIO
			,FCOM.USUARIOORDEN
			,NOMBRE_ELABORO = LTRIM(RTRIM(
				COALESCE(
					NULLIF(LTRIM(RTRIM(ISNULL(USU_ELAB.NOMBRES, '') + ' ' + ISNULL(USU_ELAB.APELLIDOS, ''))), ''),
					USU_ELAB.NOMBRE,
					USU_ELAB.USUARIO
				)
			))
			,NOMBRE_AUTORIZO = LTRIM(RTRIM(
				COALESCE(
					NULLIF(LTRIM(RTRIM(ISNULL(USU_AUT.NOMBRES, '') + ' ' + ISNULL(USU_AUT.APELLIDOS, ''))), ''),
					USU_AUT.NOMBRE,
					USU_AUT.USUARIO
				)
			))
			,FIRMA_ELABORO = AR_FIRMA_ELAB.DICOM
			,FIRMA_AUTORIZO = AR_FIRMA_AUT.DICOM
         ,BASE=IIF(DBO.FNK_VALORVARIABLE('BDATA_PRODUCCION')=DB_NAME(),'OK','DEMO')
			,FCOMD = (
				SELECT FCOMD.IDARTICULO, DESCRIPCION = COALESCE(IART.DESCRIPCION, FCTSERD.DESCRIPCION)
					,EXISTOTAL = IIF(USVGS.DATO='SI',
						(
						SELECT ISNULL(SUM(EXISLOTE),0)AS TOTAL 
						FROM IEXI 
						WHERE IDBODEGA = FCOM.IDBODEGA 
						AND EXISLOTE > 0 
						AND EXISTS(
							SELECT * FROM VWK_HERMANOS_INVENTARIO AS A 
							WHERE IEXI.IDARTICULO=A.IDARTICULO
							AND HERMANO_MAYOR = FCOMD.IDARTICULO)
						)
					, 0)
					, FCOMD.CANTIDAD
					, IART.IDUNIDAD
					, IART.CODCUM
					, IART.UNID_VENTA
					, FCOMD.VLR_UNITARIO
					, FCOMD.VR_ANTESIVA
					, FCOMD.IVA
					, FCOMD.VR_TOTAL
					, FCOMD.DETALLE
					, FCOMD.VR_DESCUENTO
					, OPTICA = CAST(COALESCE(ITAR.OPTICA, 0) AS BIT)
					, ODESFERA, OIESFERA, ODCILINDRO, OICILINDRO, ODEJE, OIEJE, ODADICION, OIADICION, ODALT, OIALT, ODAVL, OIAVL, ODTLENTE, OITLENTE, ODDNP, OIDNP
				FROM FCOMD
				LEFT JOIN IART ON IART.IDARTICULO = FCOMD.IDARTICULO AND FCOMD.TIPO='Articulos'
				LEFT JOIN FCTSERD ON FCTSERD.IDSERVICIO=FCOMD.IDARTICULO AND FCOMD.TIPO!='Articulos'
				LEFT JOIN ITAR ON ITAR.IDITAR = IART.IDITAR
				WHERE FCOMD.CNSFCOM = FCOM.CNSFCOM
				FOR JSON PATH
			)
		FROM FCOM 
		INNER JOIN TER ON TER.IDTERCERO = FCOM.IDTERCERO
		INNER JOIN IBOD ON IBOD.IDBODEGA = FCOM.IDBODEGA
		LEFT JOIN CEN ON CEN.CCOSTO = FCOM.CCOSTO
		LEFT JOIN AFU ON AFU.IDAREA = CEN.IDAREA
		LEFT JOIN SED ON SED.IDSEDE = CEN.IDSEDE
		LEFT JOIN CIU ON SED.CIUDAD = CIU.CIUDAD
		LEFT JOIN USVGS ON USVGS.IDVARIABLE = 'EXIS_ENORDENCOM'
		LEFT JOIN USUSU USU_ELAB ON USU_ELAB.USUARIO = FCOM.USUARIO
		LEFT JOIN ARCHIVOS AR_FIRMA_ELAB ON AR_FIRMA_ELAB.ID = USU_ELAB.IDFIRMA
		LEFT JOIN USUSU USU_AUT ON USU_AUT.USUARIO = FCOM.USUARIOORDEN
		LEFT JOIN ARCHIVOS AR_FIRMA_AUT ON AR_FIRMA_AUT.ID = USU_AUT.IDFIRMA
		WHERE CNSFCOM = @CNSFCOM



		--SELECT DBO.FNK_TelefonosTercero(IDTERCERO)
		RETURN
	END

	IF @METODO = 'CONFIRMAR_ORDEN'
	BEGIN
		SELECT @CNSFCOM = JSON_VALUE(@PARAMETROS, '$.CNSFCOM')
		SELECT @COMPANIA = COMPANIA FROM FCOM WHERE CNSFCOM = @CNSFCOM
		SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
		SELECT @IDSEDE = IDSEDE, @COMPANIA=COMPANIA FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME

		IF NOT EXISTS (SELECT * FROM FCOMD WHERE CNSFCOM = @CNSFCOM)
		BEGIN
			INSERT INTO @ERRORES(ERROR) SELECT 'No cuenta con detalle.' 
		END
		IF (SELECT COUNT(*) FROM @ERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @ERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				UPDATE FCOM 
					SET ORDENCOMPRA=CASE WHEN COALESCE(ORDENCOMPRA,0)=0 THEN 1 ELSE ORDENCOMPRA+1 END
					-- Conservar USUARIOORDEN del formulario (Usuario Autoriza); solo default si viene vac�o
					,USUARIOORDEN = COALESCE(NULLIF(LTRIM(RTRIM(USUARIOORDEN)), ''), @USUARIO)
					--,FECHAORDEN=DBO.FNK_GETDATE()
					,ESTADO=CASE WHEN ESTADO='C' THEN 'P' ELSE ESTADO END 
				WHERE CNSFCOM=@CNSFCOM

				EXEC SPK_INSERT_ITRA_REQ @CNSFCOM, @USUARIO,@SYS_COMPUTERNAME,@COMPANIA,@IDSEDE
				IF EXISTS (SELECT 1 FROM  IEXIF WHERE CNSFCOM = @CNSFCOM )
				BEGIN
					UPDATE IEXIF SET ESTADO = 'EN RUTA' WHERE CNSFCOM = @CNSFCOM
					UPDATE APLIMF SET APLIMF.ESTADO = 'EN RUTA' FROM APLIMF  WHERE APLIMF.ID IN  (SELECT IEXIF.IDAPLIMF FROM  IEXIF WHERE IEXIF.CNSFCOM = @CNSFCOM AND IEXIF.IDAPLIMF IS NOT NULL )
				END
			END TRY
			BEGIN CATCH 
				INSERT INTO @ERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @ERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @ERRORES
				RETURN
			END
			SELECT 'OK' AS OK, @CNSFCOM AS CNSFCOM
		END 
	END
	IF @METODO = 'VALIDA_CANTIDADES'
	BEGIN
		SELECT @CNSFCOM = JSON_VALUE(@PARAMETROS, '$.CNSFCOM')
		
		IF NOT EXISTS (SELECT * FROM FCOMD WHERE CNSFCOM = @CNSFCOM)
		BEGIN
			INSERT INTO @ERRORES(ERROR) SELECT 'No cuenta con detalle.' 
		END
		IF (SELECT COUNT(*) FROM @ERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @ERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				SELECT 'OK' OK, COUNT(*) CANTIDAD

				FROM FCOMD WHERE CNSFCOM = @CNSFCOM
			END TRY
			BEGIN CATCH 
				INSERT INTO @ERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @ERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @ERRORES
				RETURN
			END
			SELECT 'OK' AS OK
		END 

	END
	IF @METODO = 'MARCAR_IMPRESA'
	BEGIN
		SELECT @CNSFCOM = JSON_VALUE(@PARAMETROS, '$.CNSFCOM')
		UPDATE FCOM SET ORDENCOMPRA=ORDENCOMPRA+1  
		WHERE CNSFCOM=@CNSFCOM
		SELECT 'OK' AS OK, @CNSFCOM AS CNSFCOM
	END

	IF @METODO = 'ABRIR'
	BEGIN

		
		BEGIN TRY

			SELECT @CNSFCOM = JSON_VALUE(@PARAMETROS, '$.CNSFCOM')
			SELECT @ORDENCOMPRA = ORDENCOMPRA
			FROM FCOM 
			WHERE CNSFCOM = @CNSFCOM

			IF EXISTS(SELECT 1 FROM FCOM WHERE CNSFCOM = @CNSFCOM AND COALESCE(ORDENCOMPRA, 0)>=1 AND ESTADO IN ('P','R','I'))
			BEGIN
				IF EXISTS(SELECT 1 FROM ITRA WHERE ITRA.CNSFCOM = @CNSFCOM AND ESTADO<>0)
				   OR EXISTS(SELECT 1 FROM IMOV WHERE CNSFCOM = @CNSFCOM AND COALESCE(ESTADO, 0) = 1)
				BEGIN
					INSERT INTO @ERRORES(ERROR)
					SELECT 'No Puede Abrir la Orden de compra. Ya tiene recepci�n en bodega (parcial o total)'
				END
			END
			ELSE
			BEGIN
