			@CNSFCOM = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.CNSFCOM'))), ''),
			@IDBODEGA = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.IDBODEGA'))), ''),
			@USUARIO_NOTA = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.USUARIO_NOTA'))), '')

		IF OBJECT_ID('dbo.FCOMNOT', 'U') IS NULL
		BEGIN
			SELECT 'KO' AS OK
			SELECT 'No existe la tabla FCOMNOT. Ejecute el script DDL_FCOMNOT.sql.' AS ERROR
			RETURN
		END

		SELECT 'OK' AS OK
		SELECT
			N.ID,
			N.CNSFCOM,
			N.FECHA,
			N.NOTA,
			N.USUARIO,
			U.NOMBRE AS NOMBRE_USUARIO,
			F.IDBODEGA,
			F.ESTADO,
			T.RAZONSOCIAL
		FROM FCOMNOT N
		INNER JOIN FCOM F ON F.CNSFCOM = N.CNSFCOM
		LEFT JOIN USUSU U ON U.USUARIO = N.USUARIO
		LEFT JOIN TER T ON T.IDTERCERO = F.IDTERCERO
		WHERE (@FDESDE IS NULL OR CAST(N.FECHA AS DATE) >= @FDESDE)
		  AND (@FHASTA IS NULL OR CAST(N.FECHA AS DATE) <= @FHASTA)
		  AND (@CNSFCOM IS NULL OR N.CNSFCOM = @CNSFCOM)
		  AND (@IDBODEGA IS NULL OR F.IDBODEGA = @IDBODEGA)
		  AND (@USUARIO_NOTA IS NULL OR N.USUARIO = @USUARIO_NOTA)
		ORDER BY N.FECHA DESC, N.ID DESC
		RETURN
	END

