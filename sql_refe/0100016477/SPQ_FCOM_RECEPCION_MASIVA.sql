			UPDATE M
			SET VLRCOMPRA = (
				SELECT SUM(H.CANTIDAD * H.PCOSTO + COALESCE(H.VLRIVA, 0))
				FROM IMOVH H
				WHERE H.CNSMOV = M.CNSMOV
			)
			FROM IMOV M
			WHERE M.CNSITRA = @CNSITRA
			   OR M.CNSFCOM = @CNSFCOM;

			IF EXISTS (
				SELECT 1
				FROM IMOVH H
				INNER JOIN IMOV M ON M.CNSMOV = H.CNSMOV
				INNER JOIN #LINEAS L
					ON L.N_FACTURA = @N_FACTURA
				   AND L.IDTERCERO = @IDTERCERO
				   AND LTRIM(RTRIM(L.SKU)) = LTRIM(RTRIM(H.IDARTICULO))
				   AND LTRIM(RTRIM(L.NOLOTEPEDIDO)) = LTRIM(RTRIM(H.NOLOTEPEDIDO))
				WHERE (M.CNSITRA = @CNSITRA OR M.CNSFCOM = @CNSFCOM)
				  AND CAST(COALESCE(H.PCOSTO, 0) AS DECIMAL(18,6)) <> CAST(L.PCOSTO AS DECIMAL(18,6))
			)
			BEGIN
				RAISERROR('El costo de inventario no coincidi� con el PCOSTO del Excel (base sin IVA) en la factura %s. Revise que no haya el mismo SKU con el mismo lote dos veces. La recepci�n se revirti�.', 16, 1, @N_FACTURA);
			END

			COMMIT TRANSACTION;

			INSERT INTO @RESULTADO (N_FACTURA, IDTERCERO, CCOSTO, CNSFCOM, CNSITRA, CNSMOV, OK, ERROR)
			SELECT @N_FACTURA, @IDTERCERO, @CCOSTO, @CNSFCOM, @CNSITRA, @CNSMOV, 'OK', NULL;
		END TRY
		BEGIN CATCH
			IF CURSOR_STATUS('local', 'CUR_LOT') >= 0
			BEGIN
				CLOSE CUR_LOT;
				DEALLOCATE CUR_LOT;
			END
			IF @@TRANCOUNT > 0
				ROLLBACK TRANSACTION;

			INSERT INTO @RESULTADO (N_FACTURA, IDTERCERO, CCOSTO, CNSFCOM, CNSITRA, CNSMOV, OK, ERROR)
			SELECT @N_FACTURA, @IDTERCERO, @CCOSTO, @CNSFCOM, @CNSITRA, @CNSMOV, 'KO', LEFT(ERROR_MESSAGE(), 500);
		END CATCH

		FETCH NEXT FROM CUR_FAC INTO @N_FACTURA, @IDTERCERO;
	END
	CLOSE CUR_FAC;
	DEALLOCATE CUR_FAC;

	IF EXISTS (SELECT 1 FROM @RESULTADO WHERE OK = 'KO') AND NOT EXISTS (SELECT 1 FROM @RESULTADO WHERE OK = 'OK')
	BEGIN
		SELECT 'KO' OK,
			(SELECT COUNT(*) FROM @RESULTADO WHERE OK = 'OK') PROCESADAS,
			(SELECT COUNT(*) FROM @RESULTADO WHERE OK = 'KO') FALLIDAS;
		SELECT N_FACTURA, IDTERCERO, CCOSTO, CNSFCOM, CNSITRA, CNSMOV, OK, ERROR FROM @RESULTADO ORDER BY N_FACTURA;
		RETURN;
	END

	SELECT 'OK' OK,
		(SELECT COUNT(*) FROM @RESULTADO WHERE OK = 'OK') PROCESADAS,
		(SELECT COUNT(*) FROM @RESULTADO WHERE OK = 'KO') FALLIDAS;
	SELECT N_FACTURA, IDTERCERO, CCOSTO, CNSFCOM, CNSITRA, CNSMOV, OK, ERROR FROM @RESULTADO ORDER BY N_FACTURA;
END
