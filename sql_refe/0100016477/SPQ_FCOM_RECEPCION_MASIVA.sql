CREATE OR ALTER PROCEDURE DBO.SPQ_FCOM_RECEPCION_MASIVA
@JSON NVARCHAR(MAX)
WITH ENCRYPTION
AS
/*
  Recepci�n masiva de OC desde Excel del proveedor.
  Invocar v�a SPQ_JSON: MODELO FCOM, METODO RECEPCION_MASIVA / RECEPCION_MASIVA_PREVIEW
  (SPQ_FCOM despacha a este SP).

  Convenio DIAN: precio de l�nea = BASE sin IVA; el IVA se suma encima.
  Excel = unidades de inventario + PCOSTO unitario (2 cajas x 30 = 60 pastillas, no 2).
  No se usa UNID_VENTA ni se multiplica cantidad por empaque.
  TOTAL / LINEA_BASE opcional: PCOSTO = TOTAL / unidades (hasta 6 decimales, peso a peso).
  No se redondea a pesos enteros. IVA $ = LINEA_BASE * % (o IVA_LINEA si viene en el Excel).
  Cabecera opcional SUBTOTAL_FACTURA / IVA_FACTURA / TOTAL_FACTURA alinea FCOM peso a peso.
  Un SKU + lote proveedor repetido en la misma factura se rechaza.
  ITRAH e IMOVH.PCOSTO = base sin IVA (SPK_INSERTENTTRANSITO puede alterar; se restaura).
  Por cada N_FACTURA + proveedor: FCOM + FCOMD ? ITRA/ITRAH ? SPK_INSERTENTTRANSITO
  (IMOV ESTADO 0). No llama SPK_CONFIRMARENTRADAS.
*/
DECLARE @PARAMETROS NVARCHAR(MAX)
		,@MODELO VARCHAR(100)
		,@METODO VARCHAR(100)
		,@USUARIO VARCHAR(12)
		,@GRUPO VARCHAR(8)
		,@SYS_COMPUTERNAME VARCHAR(254)
		,@COMPANIA VARCHAR(20)
		,@IDSEDE VARCHAR(5)
		,@SEDE VARCHAR(5)
		,@USUNOMBRE VARCHAR(100)
		,@IDBODEGA VARCHAR(20)
		,@IDBODEGA_LIN VARCHAR(20)
		,@IDTERCERO VARCHAR(20)
		,@CCOSTO VARCHAR(20)
		,@IDAREA VARCHAR(20)
		,@FECHAORDEN DATE
		,@FECHA DATE
		,@F_FACTURA DATE
		,@F_VENCE DATE
		,@USUARIOORDEN VARCHAR(20)
		,@OBSERVACION VARCHAR(4096)
		,@FACTORIVA_DEFAULT DECIMAL(14,2)
		,@DECONSUMO SMALLINT
		,@LINEAS NVARCHAR(MAX)
		,@USA_LP VARCHAR(20)
		,@IDIMP_IVA VARCHAR(20)
		,@HOY DATE
		,@ERRADOS INT
		,@CNSFCOM VARCHAR(20)
		,@CNSITRA VARCHAR(20)
		,@CNSMOV VARCHAR(20)
		,@N_FACTURA VARCHAR(20)
		,@IDTIPOMOV VARCHAR(2)
		,@NOLOTE VARCHAR(20)
		,@SKU VARCHAR(20)
		,@IDARTICULO_OC VARCHAR(20)
		,@CANTIDAD DECIMAL(18,6)
		,@VLR_UNITARIO DECIMAL(18,6)
		,@NOLOTEPEDIDO VARCHAR(20)
		,@FECHAVENCE DATE
		,@FACTORIVA DECIMAL(14,2)
		,@PCOSTO DECIMAL(18,6)
		,@PCSINIVA DECIMAL(18,6)
		,@IDIMPUESTO VARCHAR(10)
		,@IDCLASE VARCHAR(10)
		,@RINVIMA VARCHAR(100)

DECLARE @TBLERRORES TABLE (ERROR VARCHAR(500));
DECLARE @RESULTADO TABLE (
	N_FACTURA VARCHAR(20),
	IDTERCERO VARCHAR(20),
	CCOSTO VARCHAR(20),
	CNSFCOM VARCHAR(20),
	CNSITRA VARCHAR(20),
	CNSMOV VARCHAR(20),
	OK VARCHAR(2),
	ERROR VARCHAR(500)
);

BEGIN
	SET LANGUAGE Spanish;
	SET DATEFORMAT dmy;
	SET NOCOUNT ON;

	SELECT @MODELO = JSON_VALUE(@JSON, '$.MODELO'),
		   @METODO = JSON_VALUE(@JSON, '$.METODO'),
		   @USUARIO = JSON_VALUE(@JSON, '$.USUARIO'),
		   @PARAMETROS = JSON_QUERY(@JSON, '$.PARAMETROS');

	SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO), @USUNOMBRE = NOMBRE
	FROM USUSU WHERE USUARIO = @USUARIO;
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME, @COMPANIA = COMPANIA
	FROM USUSU WHERE USUARIO = @USUARIO;
	SELECT @IDSEDE = IDSEDE, @SEDE = IDSEDE
	FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME;

	SELECT
		@IDBODEGA = NULLIF(LTRIM(RTRIM(IDBODEGA)), ''),
		@FACTORIVA_DEFAULT = FACTORIVA_DEFAULT,
		@DECONSUMO = COALESCE(DECONSUMO, 0),
		@LINEAS = LINEAS
	FROM OPENJSON(@PARAMETROS)
	WITH (
		IDBODEGA          VARCHAR(20)    '$.IDBODEGA',
		FACTORIVA_DEFAULT DECIMAL(14,2)  '$.FACTORIVA_DEFAULT',
		DECONSUMO         SMALLINT       '$.DECONSUMO',
		LINEAS            NVARCHAR(MAX) AS JSON
	);

	SET @HOY = CAST(DBO.FNK_GETDATE() AS DATE);
	SET @USA_LP = UPPER(LTRIM(RTRIM(COALESCE(DBO.FNK_VALORVARIABLE('USA_LISTA_PRECIOS'), 'NO'))));
	SET @IDIMP_IVA = DBO.FNK_VALORVARIABLE('IDIMP_IVA');

	IF COALESCE(@IDBODEGA, '') = ''
		INSERT INTO @TBLERRORES(ERROR) SELECT 'Debe seleccionar una bodega de sesi�n.';
	IF COALESCE(@LINEAS, '') IN ('', '[]', 'null')
		INSERT INTO @TBLERRORES(ERROR) SELECT 'El Excel no tiene l�neas para procesar.';
	IF COALESCE(@IDBODEGA, '') <> '' AND NOT EXISTS (SELECT 1 FROM IBOD WHERE IDBODEGA = @IDBODEGA)
		INSERT INTO @TBLERRORES(ERROR) SELECT 'La bodega de sesi�n no existe.';

	CREATE TABLE #LINEAS (
		FILA INT,
		SKU VARCHAR(20) COLLATE DATABASE_DEFAULT,
		N_FACTURA VARCHAR(20) COLLATE DATABASE_DEFAULT,
		CANTIDAD DECIMAL(18,6),
		VLR_UNITARIO DECIMAL(18,6),
		NOLOTEPEDIDO VARCHAR(20) COLLATE DATABASE_DEFAULT,
		FECHAVENCE DATE,
		PROVEEDOR VARCHAR(40) COLLATE DATABASE_DEFAULT,
		IDTERCERO VARCHAR(20) COLLATE DATABASE_DEFAULT,
		RAZONSOCIAL VARCHAR(200) COLLATE DATABASE_DEFAULT,
		CCOSTO VARCHAR(20) COLLATE DATABASE_DEFAULT,
		IDAREA VARCHAR(20) COLLATE DATABASE_DEFAULT,
		IDBODEGA VARCHAR(20) COLLATE DATABASE_DEFAULT,
		USUARIOORDEN VARCHAR(20) COLLATE DATABASE_DEFAULT,
		FECHAORDEN DATE,
		FECHA DATE,
		F_FACTURA DATE,
		F_VENCE DATE,
		OBSERVACION VARCHAR(4096) COLLATE DATABASE_DEFAULT,
		IDARTICULO_OC VARCHAR(20) COLLATE DATABASE_DEFAULT,
		DESCRIPCION VARCHAR(512) COLLATE DATABASE_DEFAULT,
		PRINCIPAL SMALLINT,
		IDSERVICIO VARCHAR(20) COLLATE DATABASE_DEFAULT,
		MFECHAVENCIMIENTO SMALLINT,
		IDIMPUESTO VARCHAR(10) COLLATE DATABASE_DEFAULT,
		IDCLASE VARCHAR(10) COLLATE DATABASE_DEFAULT,
		FACTORIVA DECIMAL(14,2),
		VR_ANTESIVA DECIMAL(19,6),
		IVA DECIMAL(19,6),
		VR_TOTAL DECIMAL(19,6),
		VR_UNITMASIVA DECIMAL(19,6),
		PCOSTO DECIMAL(18,6),
		LINEA_BASE DECIMAL(18,2),
		IVA_LINEA DECIMAL(18,2),
		PRECIO_CAJA DECIMAL(18,6),
		UND_EMPAQUE DECIMAL(18,6),
		CANT_CAJAS DECIMAL(18,6),
		CANT_FACTURA DECIMAL(18,6),
		UNID_VENTA DECIMAL(18,6),
		SUBTOTAL_FACTURA DECIMAL(18,2),
		IVA_FACTURA DECIMAL(18,2),
		TOTAL_FACTURA DECIMAL(18,2),
		ERROR VARCHAR(600) COLLATE DATABASE_DEFAULT
	);

	IF COALESCE(@LINEAS, '') NOT IN ('', '[]', 'null')
	BEGIN
		INSERT INTO #LINEAS (
			FILA, SKU, N_FACTURA, CANTIDAD, VLR_UNITARIO, PCOSTO, FACTORIVA, NOLOTEPEDIDO, FECHAVENCE,
			PROVEEDOR, CCOSTO, IDAREA, IDBODEGA, USUARIOORDEN,
			FECHAORDEN, FECHA, F_FACTURA, F_VENCE, OBSERVACION,
			LINEA_BASE, IVA_LINEA, PRECIO_CAJA, UND_EMPAQUE, CANT_CAJAS, CANT_FACTURA,
			SUBTOTAL_FACTURA, IVA_FACTURA, TOTAL_FACTURA, ERROR
		)
		SELECT
			COALESCE(FILA, 0),
			UPPER(LTRIM(RTRIM(SKU))),
			LEFT(LTRIM(RTRIM(N_FACTURA)), 16),
			TRY_CAST(CANTIDAD AS DECIMAL(18,6)),
			TRY_CAST(COALESCE(NULLIF(LTRIM(RTRIM(PCOSTO)), ''), VLR_UNITARIO) AS DECIMAL(18,6)),
			TRY_CAST(COALESCE(NULLIF(LTRIM(RTRIM(PCOSTO)), ''), VLR_UNITARIO) AS DECIMAL(18,6)),
			TRY_CAST(FACTORIVA AS DECIMAL(14,2)),
			LEFT(LTRIM(RTRIM(NOLOTEPEDIDO)), 20),
			COALESCE(
				TRY_CONVERT(DATE, NULLIF(LTRIM(RTRIM(FECHAVENCE)), ''), 23),
				TRY_CONVERT(DATE, NULLIF(LTRIM(RTRIM(FECHAVENCE)), ''), 112),
				TRY_CONVERT(DATE, NULLIF(LTRIM(RTRIM(FECHAVENCE)), ''), 103),
				TRY_CONVERT(DATE, NULLIF(LTRIM(RTRIM(FECHAVENCE)), ''), 105),
				TRY_CONVERT(DATE, NULLIF(LTRIM(RTRIM(FECHAVENCE)), ''), 101),
				TRY_CONVERT(DATE, NULLIF(LTRIM(RTRIM(FECHAVENCE)), ''), 1)
			),
			NULLIF(LTRIM(RTRIM(PROVEEDOR)), ''),
			NULLIF(LTRIM(RTRIM(CCOSTO)), ''),
			NULLIF(LTRIM(RTRIM(IDAREA)), ''),
			NULLIF(LTRIM(RTRIM(IDBODEGA)), ''),
			NULLIF(LTRIM(RTRIM(USUARIOORDEN)), ''),
			COALESCE(
				TRY_CONVERT(DATE, NULLIF(LTRIM(RTRIM(FECHAORDEN)), ''), 23),
				TRY_CONVERT(DATE, NULLIF(LTRIM(RTRIM(FECHAORDEN)), ''), 103),
				TRY_CONVERT(DATE, NULLIF(LTRIM(RTRIM(FECHAORDEN)), ''), 105)
			),
			COALESCE(
				TRY_CONVERT(DATE, NULLIF(LTRIM(RTRIM(FECHA)), ''), 23),
				TRY_CONVERT(DATE, NULLIF(LTRIM(RTRIM(FECHA)), ''), 103),
				TRY_CONVERT(DATE, NULLIF(LTRIM(RTRIM(FECHA)), ''), 105)
			),
			COALESCE(
				TRY_CONVERT(DATE, NULLIF(LTRIM(RTRIM(F_FACTURA)), ''), 23),
				TRY_CONVERT(DATE, NULLIF(LTRIM(RTRIM(F_FACTURA)), ''), 103),
				TRY_CONVERT(DATE, NULLIF(LTRIM(RTRIM(F_FACTURA)), ''), 105)
			),
			COALESCE(
				TRY_CONVERT(DATE, NULLIF(LTRIM(RTRIM(F_VENCE)), ''), 23),
				TRY_CONVERT(DATE, NULLIF(LTRIM(RTRIM(F_VENCE)), ''), 103),
				TRY_CONVERT(DATE, NULLIF(LTRIM(RTRIM(F_VENCE)), ''), 105)
			),
			OBSERVACION,
			TRY_CAST(LINEA_BASE AS DECIMAL(18,2)),
			TRY_CAST(IVA_LINEA AS DECIMAL(18,2)),
			TRY_CAST(PRECIO_CAJA AS DECIMAL(18,6)),
			TRY_CAST(UND_EMPAQUE AS DECIMAL(18,6)),
			TRY_CAST(CANT_CAJAS AS DECIMAL(18,6)),
			TRY_CAST(COALESCE(NULLIF(LTRIM(RTRIM(CANT_FACTURA)), ''), CANT_CAJAS) AS DECIMAL(18,6)),
			TRY_CAST(SUBTOTAL_FACTURA AS DECIMAL(18,2)),
			TRY_CAST(IVA_FACTURA AS DECIMAL(18,2)),
			TRY_CAST(TOTAL_FACTURA AS DECIMAL(18,2)),
			NULL
		FROM OPENJSON(@LINEAS)
		WITH (
			FILA              INT             '$.FILA',
			SKU               VARCHAR(40)     '$.SKU',
			N_FACTURA         VARCHAR(40)     '$.N_FACTURA',
			CANTIDAD          VARCHAR(40)     '$.CANTIDAD',
			VLR_UNITARIO      VARCHAR(40)     '$.VLR_UNITARIO',
			PCOSTO            VARCHAR(40)     '$.PCOSTO',
			FACTORIVA         VARCHAR(40)     '$.FACTORIVA',
			NOLOTEPEDIDO      VARCHAR(40)     '$.NOLOTEPEDIDO',
			FECHAVENCE        VARCHAR(40)     '$.FECHAVENCE',
			PROVEEDOR         VARCHAR(40)     '$.PROVEEDOR',
			CCOSTO            VARCHAR(20)     '$.CCOSTO',
			IDAREA            VARCHAR(20)     '$.IDAREA',
			IDBODEGA          VARCHAR(20)     '$.IDBODEGA',
			USUARIOORDEN      VARCHAR(20)     '$.USUARIOORDEN',
			FECHAORDEN        VARCHAR(40)     '$.FECHAORDEN',
			FECHA             VARCHAR(40)     '$.FECHA',
			F_FACTURA         VARCHAR(40)     '$.F_FACTURA',
			F_VENCE           VARCHAR(40)     '$.F_VENCE',
			OBSERVACION       VARCHAR(4096)   '$.OBSERVACION',
			LINEA_BASE        VARCHAR(40)     '$.LINEA_BASE',
			IVA_LINEA         VARCHAR(40)     '$.IVA_LINEA',
			PRECIO_CAJA       VARCHAR(40)     '$.PRECIO_CAJA',
			UND_EMPAQUE       VARCHAR(40)     '$.UND_EMPAQUE',
			CANT_CAJAS        VARCHAR(40)     '$.CANT_CAJAS',
			CANT_FACTURA      VARCHAR(40)     '$.CANT_FACTURA',
			SUBTOTAL_FACTURA  VARCHAR(40)     '$.SUBTOTAL_FACTURA',
			IVA_FACTURA       VARCHAR(40)     '$.IVA_FACTURA',
			TOTAL_FACTURA     VARCHAR(40)     '$.TOTAL_FACTURA'
		);
	END

	UPDATE #LINEAS
	SET FECHAVENCE = NULL
	WHERE FECHAVENCE IS NOT NULL AND FECHAVENCE <= '19000101';

	UPDATE #LINEAS
	SET IDBODEGA = COALESCE(NULLIF(IDBODEGA, ''), @IDBODEGA),
		USUARIOORDEN = COALESCE(NULLIF(USUARIOORDEN, ''), @USUARIO),
		FECHAORDEN = COALESCE(FECHAORDEN, @HOY),
		FECHA = COALESCE(FECHA, FECHAORDEN, @HOY),
		F_FACTURA = COALESCE(F_FACTURA, FECHAORDEN, @HOY);

	-- CANTIDAD = unidades de inventario (2 cajas x 30 = 60). No se multiplica por UNID_VENTA.
	UPDATE #LINEAS
	SET CANTIDAD = COALESCE(NULLIF(CANTIDAD, 0), NULLIF(CANT_FACTURA, 0), NULLIF(CANT_CAJAS, 0), CANTIDAD);

	-- Proveedor: IDTERCERO o NIT (categor�a PRO).
	UPDATE L
	SET IDTERCERO = COALESCE(
			(
				SELECT TOP 1 T.IDTERCERO
				FROM TER T
				INNER JOIN TEXCA X ON X.IDTERCERO = T.IDTERCERO AND X.IDCATEGORIA = 'PRO'
				WHERE T.IDTERCERO = L.PROVEEDOR
			),
			(
				SELECT TOP 1 T.IDTERCERO
				FROM TER T
				INNER JOIN TEXCA X ON X.IDTERCERO = T.IDTERCERO AND X.IDCATEGORIA = 'PRO'
				WHERE REPLACE(REPLACE(COALESCE(T.NIT, ''), '.', ''), '-', '')
					= REPLACE(REPLACE(COALESCE(L.PROVEEDOR, ''), '.', ''), '-', '')
			)
		),
		RAZONSOCIAL = COALESCE(
			(
				SELECT TOP 1 T.RAZONSOCIAL
				FROM TER T
				INNER JOIN TEXCA X ON X.IDTERCERO = T.IDTERCERO AND X.IDCATEGORIA = 'PRO'
				WHERE T.IDTERCERO = L.PROVEEDOR
			),
			(
				SELECT TOP 1 T.RAZONSOCIAL
				FROM TER T
				INNER JOIN TEXCA X ON X.IDTERCERO = T.IDTERCERO AND X.IDCATEGORIA = 'PRO'
				WHERE REPLACE(REPLACE(COALESCE(T.NIT, ''), '.', ''), '-', '')
					= REPLACE(REPLACE(COALESCE(L.PROVEEDOR, ''), '.', ''), '-', '')
			)
		)
	FROM #LINEAS L
	WHERE COALESCE(L.PROVEEDOR, '') <> '';

	UPDATE L
	SET SUBTOTAL_FACTURA = H.SUBTOTAL_FACTURA,
		IVA_FACTURA = H.IVA_FACTURA,
		TOTAL_FACTURA = H.TOTAL_FACTURA
	FROM #LINEAS L
	INNER JOIN (
		SELECT
			N_FACTURA,
			COALESCE(IDTERCERO, PROVEEDOR) PROV,
			MAX(SUBTOTAL_FACTURA) SUBTOTAL_FACTURA,
			MAX(IVA_FACTURA) IVA_FACTURA,
			MAX(TOTAL_FACTURA) TOTAL_FACTURA
		FROM #LINEAS
		GROUP BY N_FACTURA, COALESCE(IDTERCERO, PROVEEDOR)
	) H ON H.N_FACTURA = L.N_FACTURA AND H.PROV = COALESCE(L.IDTERCERO, L.PROVEEDOR);

	UPDATE L
	SET IDAREA = COALESCE(NULLIF(L.IDAREA, ''), C.IDAREA),
		CCOSTO = C.CCOSTO
	FROM #LINEAS L
	INNER JOIN CEN C ON C.CCOSTO = L.CCOSTO;

	UPDATE L
	SET DESCRIPCION = A.DESCRIPCION,
		PRINCIPAL = COALESCE(A.PRINCIPAL, 0),
		IDSERVICIO = A.IDSERVICIO,
		MFECHAVENCIMIENTO = COALESCE(ITAR.MFECHAVENCIMIENTO, 0),
		UNID_VENTA = COALESCE(A.UNID_VENTA, 0)
	FROM #LINEAS L
	LEFT JOIN IART A ON A.IDARTICULO = L.SKU
	LEFT JOIN ITAR ON ITAR.IDITAR = A.IDITAR;

	-- Si el Excel trae TOTAL de l�nea, PCOSTO = TOTAL / unidades (6 decimales). Si no, se respeta el PCOSTO digitado.
	UPDATE #LINEAS
	SET CANTIDAD = COALESCE(NULLIF(CANTIDAD, 0), NULLIF(CANT_FACTURA, 0), NULLIF(CANT_CAJAS, 0), CANTIDAD)
	WHERE ERROR IS NULL;

	UPDATE #LINEAS
	SET PCOSTO = CASE
			WHEN COALESCE(LINEA_BASE, 0) > 0 AND COALESCE(CANTIDAD, 0) > 0
				THEN CAST(LINEA_BASE / CANTIDAD AS DECIMAL(18,6))
			ELSE COALESCE(PCOSTO, VLR_UNITARIO)
		END
	WHERE ERROR IS NULL;

	UPDATE #LINEAS
	SET VLR_UNITARIO = PCOSTO
	WHERE ERROR IS NULL
	  AND COALESCE(PCOSTO, 0) > 0;

	UPDATE L
	SET ERROR = CASE
		WHEN COALESCE(L.SKU, '') = '' THEN 'SKU vac�o.'
		WHEN A.IDARTICULO IS NULL THEN 'SKU no encontrado en IART.'
		WHEN COALESCE(A.PRINCIPAL, 0) <> 0 THEN 'El SKU debe ser fabricante (IART.PRINCIPAL = 0).'
		WHEN COALESCE(L.N_FACTURA, '') = '' THEN 'Falta el n�mero de factura.'
		WHEN COALESCE(L.PROVEEDOR, '') = '' THEN 'Falta el proveedor (NIT o IDTERCERO).'
		WHEN COALESCE(L.IDTERCERO, '') = '' THEN 'Proveedor no encontrado. Utilice el NIT o IDTERCERO de un tercero PRO.'
		WHEN COALESCE(L.CCOSTO, '') = '' THEN 'Falta el centro de costo.'
		WHEN NOT EXISTS (SELECT 1 FROM CEN C WHERE C.CCOSTO = L.CCOSTO) THEN 'Centro de costo no existe.'
		WHEN NOT EXISTS (
			SELECT 1 FROM IBODS S
			WHERE S.IDBODEGA = L.IDBODEGA AND S.TIPO = 'CEN' AND S.VALOR = L.CCOSTO AND S.ACCESO = 'Si'
		) THEN 'El centro de costo no est� habilitado para la bodega.'
		WHEN COALESCE(L.IDAREA, '') = '' THEN 'El centro de costo no tiene �rea (IDAREA).'
		WHEN COALESCE(L.USUARIOORDEN, '') = '' THEN 'Falta el usuario que autoriza.'
		WHEN NOT EXISTS (SELECT 1 FROM USUSU U WHERE U.USUARIO = L.USUARIOORDEN) THEN 'Usuario que autoriza no existe.'
		WHEN L.F_FACTURA IS NOT NULL AND L.F_FACTURA > @HOY THEN 'La fecha de la factura no puede ser posterior a hoy.'
		WHEN L.F_VENCE IS NOT NULL AND L.F_FACTURA IS NOT NULL AND L.F_VENCE < L.F_FACTURA
			THEN 'La fecha de vencimiento de la factura no puede ser anterior a la fecha de factura.'
		WHEN COALESCE(L.CANTIDAD, 0) <= 0 THEN 'Faltan UNIDADES de inventario (2 cajas x 30 = 60, no 2).'
		WHEN COALESCE(L.PCOSTO, L.VLR_UNITARIO, 0) <= 0 THEN 'Falta PCOSTO (costo de cada unidad, sin IVA) o TOTAL de la l�nea.'
		WHEN L.FACTORIVA IS NOT NULL AND (L.FACTORIVA < 0 OR L.FACTORIVA > 100)
			THEN '% IVA debe estar entre 0 y 100.'
		WHEN COALESCE(L.NOLOTEPEDIDO, '') = '' THEN 'Lote del proveedor vac�o.'
		WHEN COALESCE(L.MFECHAVENCIMIENTO, 0) = 1 AND L.FECHAVENCE IS NULL THEN 'Falta fecha de vencimiento del lote.'
		WHEN L.FECHAVENCE IS NOT NULL AND L.FECHAVENCE < @HOY THEN 'Lote vencido; no se puede ingresar a bodega.'
		ELSE NULL
	END
	FROM #LINEAS L
	LEFT JOIN IART A ON A.IDARTICULO = L.SKU
	WHERE L.ERROR IS NULL;

	UPDATE L
	SET ERROR = 'La misma factura tiene distintos centros de costo para el mismo proveedor.'
	FROM #LINEAS L
	WHERE L.ERROR IS NULL
	  AND EXISTS (
		SELECT 1 FROM #LINEAS X
		WHERE X.N_FACTURA = L.N_FACTURA
		  AND COALESCE(X.IDTERCERO, '') = COALESCE(L.IDTERCERO, '')
		  AND COALESCE(X.CCOSTO, '') <> COALESCE(L.CCOSTO, '')
	  );

	UPDATE L
	SET IDARTICULO_OC = CASE
		WHEN @USA_LP IN ('SI', '1', 'TRUE') THEN L.SKU
		WHEN EXISTS (
			SELECT 1 FROM IART P
			WHERE P.IDARTICULO = L.IDSERVICIO AND COALESCE(P.PRINCIPAL, 0) = 1
		) THEN L.IDSERVICIO
		WHEN CHARINDEX('-', L.SKU) > 0
			 AND EXISTS (
				SELECT 1 FROM IART P
				WHERE P.IDARTICULO = LEFT(L.SKU, CHARINDEX('-', L.SKU) - 1)
				  AND COALESCE(P.PRINCIPAL, 0) = 1
			 )
			THEN LEFT(L.SKU, CHARINDEX('-', L.SKU) - 1)
		ELSE NULL
	END
	FROM #LINEAS L
	WHERE L.ERROR IS NULL;

	UPDATE #LINEAS
	SET ERROR = 'No se encontr� el art�culo principal (PRINCIPAL = 1) para el SKU. Verifique el v�nculo IDSERVICIO.'
	WHERE ERROR IS NULL
	  AND @USA_LP NOT IN ('SI', '1', 'TRUE')
	  AND COALESCE(IDARTICULO_OC, '') = '';

	-- IVA: lo define el Excel. No se usa IMPUESTO_OBL ni la tarifa de IART.
	-- IDIMPUESTO/IDCLASE se buscan en FIMPDV por el % informado (c�digos contables).
	UPDATE L
	SET FACTORIVA = COALESCE(L.FACTORIVA, 0),
		IDIMPUESTO = CASE WHEN COALESCE(L.FACTORIVA, 0) <= 0 THEN NULL ELSE I.IDIMPUESTO END,
		IDCLASE = CASE WHEN COALESCE(L.FACTORIVA, 0) <= 0 THEN NULL ELSE I.IDCLASE END
	FROM #LINEAS L
	OUTER APPLY (
		SELECT TOP 1 V.IDIMPUESTO, V.IDCLASE
		FROM FIMPDV V
		WHERE TRY_CAST(V.VALOR AS DECIMAL(14,2)) = COALESCE(L.FACTORIVA, 0)
		ORDER BY
			CASE WHEN EXISTS (
				SELECT 1 FROM IART A
