                       SET @ERROR = 'Código de glosa no existe en el maestro';
                   END
                   ELSE IF COALESCE(@VLRGLOSA, 0) <= 0
                   BEGIN
                       SET @ERROR = 'El valor de glosa debe ser mayor a cero';
                   END
                   ELSE IF COALESCE(@VLRACEPTADO, 0) > COALESCE(@VLRGLOSA, 0)
                   BEGIN
                       SET @ERROR = 'El valor aceptado no puede ser mayor al valor glosado';
                   END
                   ELSE IF LEN(ISNULL(@RESPUESTA, '')) < 10
                   BEGIN
                       SET @ERROR = 'La respuesta no puede ser menor a 10 caracteres';
                   END
                   ELSE
                   BEGIN
                       -- =======================================================================
                       -- 10. ACTUALIZAR FGLOD (RESPUESTA DE GLOSA)
                       -- =======================================================================
                       UPDATE FGLOD 
                       SET CODGLOSA = @CODGLOSA, 
                           CODRPTA = @CODRPTA,
                           VLRACEPTADO = @VLRACEPTADO,
                           RESPUESTA = @RESPUESTA,
                           VLRRECUPERAR = (VLRGLOSA - COALESCE(@VLRACEPTADO, 0)),
                           CONCEPTO = @IDCONCEPRPTAGLO_AUTO
                       WHERE CNSGLO = @CNSGLO 
                         AND ITEM = @ITEM 
                         AND N_FACTURA = @N_FACTURA;

                       SET @FILASEXITOSAS = @FILASEXITOSAS + 1;
                   END

                   -- 10.1 ACTUALIZAR ESTADO EN TABLA TEMPORAL
                   UPDATE #TMP_DATOS 
                   SET PROCESADO = 1, 
                       ERROR = @ERROR 
                   WHERE FILA = @FILA;

                   IF @ERROR IS NOT NULL
                   BEGIN
                       SET @FILASERROR = @FILASERROR + 1;
                   END

                   -- 10.2 AVANZAR A LA SIGUIENTE FILA
                   SET @FILA = @FILA + 1;
               END

               -- =======================================================================
               -- 11. INSERTAR REGISTRO DE ERRORES (Si los hay)
               -- =======================================================================
               IF @FILASERROR > 0
               BEGIN
                   INSERT INTO RPDX(CNS, ID1, ID2, ID3, STRINGGRANDE1, VALOR10)
                   SELECT 
                       @CNSRPDX,
                       FILA,
                       CNSGLO,
                       N_FACTURA,
                       ERROR,
                       1
                   FROM #TMP_DATOS 
                   WHERE ERROR IS NOT NULL;
               END

               -- =======================================================================
               -- 12. EJECUTAR RESPUESTA DE GLOSA POR CADA CNSGLO
               -- =======================================================================
               DECLARE FINDEV4_CURSOR CURSOR LOCAL FAST_FORWARD FOR 
               SELECT DISTINCT CNSGLO 
               FROM #TMP_DATOS 
               WHERE ERROR IS NULL
                 AND NOT EXISTS(
                     SELECT 1 FROM RPDX 
                     WHERE CNS = @CNSRPDX 
                       AND ID2 = #TMP_DATOS.CNSGLO COLLATE DATABASE_DEFAULT
                 );

               OPEN FINDEV4_CURSOR;
               FETCH NEXT FROM FINDEV4_CURSOR INTO @CNSGLO;

               WHILE @@FETCH_STATUS = 0
               BEGIN
                   BEGIN TRY
                       PRINT 'Ejecutando SPK_RESPUESTAGLOSA para: ' + @CNSGLO;
                    
                       EXEC SPK_RESPUESTAGLOSA 
                           @CNSGLO, 3, @IDSEDE, @COMPANIA, @USUARIO, @SYS_COMPUTERNAME, 0;
                   END TRY
                   BEGIN CATCH
                       SET @ERROR_DETALLE = ERROR_MESSAGE();
                       SET @XACT_STATE_VAL = XACT_STATE();
                   
                       PRINT 'Error en SPK_RESPUESTAGLOSA: ' + @ERROR_DETALLE;
                       PRINT 'XACT_STATE después del error: ' + CAST(@XACT_STATE_VAL AS VARCHAR);
                    
                       -- Registrar error pero continuar con el resto
                       INSERT INTO #TMP_DATOS (ERROR) 
                       SELECT 'CNSGLO: ' + @CNSGLO + ' - ' + @ERROR_DETALLE;
                   END CATCH

                   FETCH NEXT FROM FINDEV4_CURSOR INTO @CNSGLO;
               END

               CLOSE FINDEV4_CURSOR;
               DEALLOCATE FINDEV4_CURSOR;

               -- =======================================================================
               -- 13. GENERAR IMPRESIÓN DE RESPUESTAS (FGLOI) SI HAY GLOSAS CERRADAS
               -- =======================================================================
               IF EXISTS(
                   SELECT 1 FROM FGLO 
                   WHERE CNSGLO IN (
                       SELECT DISTINCT CNSGLO COLLATE DATABASE_DEFAULT FROM #TMP_DATOS WHERE ERROR IS NULL
                   )
                   AND CERRADA = 1
               )
               BEGIN 
                   -- Crear tabla temporal para glosas cerradas
                   CREATE TABLE #FGLO (
                       CNSGLO VARCHAR(50) COLLATE DATABASE_DEFAULT
                   );
                
                   INSERT INTO #FGLO (CNSGLO)
                   SELECT DISTINCT CNSGLO 
                   FROM FGLO 
                   WHERE CNSGLO IN (
                       SELECT DISTINCT CNSGLO COLLATE DATABASE_DEFAULT FROM #TMP_DATOS WHERE ERROR IS NULL
                   )
                   AND CERRADA = 1;

                   BEGIN TRY
                       PRINT 'Generando consecutivo FGLOI...';
                    
                       EXEC SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE, 'FGLOI', @CNSGLOI OUTPUT;
                       SELECT @CNSGLOI = CAST(@IDSEDE AS VARCHAR(10)) + RIGHT(REPLICATE('0', 8) + LTRIM(RTRIM(@CNSGLOI)), 8);

                       INSERT INTO FGLOI (CNSGLOI, IDTERCERO, USUARIO, FECHA, OBSERVACION, IMPRESIONES, 
                                          RADICADO, FECHARAD, USUARIORAD, CONTABILIZADA, NROCOMPROBANTE, FECHADIG)
                       SELECT @CNSGLOI, @IDTERCERO, @USUARIO, DBO.FNK_GETDATE(), 
                              'Impresión de respuestas automática', 0, 0, NULL, NULL, 0, NULL, NULL;

                       INSERT INTO FGLOID (CNSGLOI, CNSGLO, N_FACTURA, ITEM)
                       SELECT @CNSGLOI, FGLO.CNSGLO, FGLO.N_FACTURA,
                              ROW_NUMBER() OVER (ORDER BY FGLO.CNSGLO)
                       FROM FGLO 
                       WHERE FGLO.CNSGLO IN (SELECT CNSGLO COLLATE DATABASE_DEFAULT FROM #FGLO);

                       UPDATE FGLO 
                       SET ASIGNADAIMP = 1, CNSGLOI = @CNSGLOI
                       WHERE FGLO.CNSGLO IN (SELECT CNSGLO COLLATE DATABASE_DEFAULT FROM #FGLO);

                       UPDATE FGLOI 
                       SET IMPRESIONES = COALESCE(IMPRESIONES, 0) + 1 
                       WHERE CNSGLOI = @CNSGLOI;
                   END TRY
                   BEGIN CATCH
                       SET @ERROR_DETALLE = ERROR_MESSAGE();
                       SET @XACT_STATE_VAL = XACT_STATE();
                    
                       PRINT 'Error generando consecutivo: ' + @ERROR_DETALLE;
                       PRINT 'XACT_STATE: ' + CAST(@XACT_STATE_VAL AS VARCHAR);
                    
                       IF @XACT_STATE_VAL = -1
                       BEGIN
                           PRINT 'Transacción DOOMED - Saliendo';
                           SELECT 'KO' AS OK, 'Transacción en estado inválido' AS ERROR;
                           RETURN;
                       END
                       ELSE
                       BEGIN
                           INSERT INTO #TMP_DATOS (ERROR) 
                           SELECT 'Error consecutivo FGLOI: ' + @ERROR_DETALLE;
                       END
                   END CATCH

                   -- =======================================================================
                   -- 14. ENVIAR RESPUESTA A CARTERA
                   -- =======================================================================
                   PRINT '--- ENVIANDO RESPUESTA A CARTERA ---';

                   -- Declarar tabla para resultados
                   DECLARE @RESUL TABLE (
                       DATO1 VARCHAR(500) COLLATE DATABASE_DEFAULT, 
                       DATO2 VARCHAR(500) COLLATE DATABASE_DEFAULT
                   );

                   DELETE FROM @RESUL;

                   SET @SQL = N'EXEC SPQ_JSON ''{"MODELO":"FGLO_COL","METODO":"ENVIAR_RESPUESTA","PARAMETROS":{"CNSGLOI":"' + @CNSGLOI + '"},"USUARIO":"' + REPLACE(@USUARIO, '''', '''''') + '"}''';

                   INSERT INTO @RESUL (DATO1, DATO2) EXEC (@SQL);

                   SELECT @CONTADOR_REGISTROS = COUNT(*) FROM @RESUL;
                   IF @CONTADOR_REGISTROS = 0
                   BEGIN
                       PRINT 'No se recibió respuesta válida de SPQ_JSON para envío a cartera.';
                   END
                   ELSE
                   BEGIN
                       SELECT TOP 1 @CNSENTREGA = DATO2 FROM @RESUL;
                       IF COALESCE(@CNSENTREGA, '') = ''
                       BEGIN
                           SELECT TOP 1 @CNSENTREGA = CNSENTDEV FROM FGLO WHERE CNSGLOI = @CNSGLOI;
                       END

                       -- =======================================================================
                       -- 15. RECIBIR RESPUESTA EN CARTERA
                       -- =======================================================================
                       PRINT '--- RECIBIENDO RESPUESTA EN CARTERA ---';

                       DELETE FROM @RESUL;

                       SET @SQL = N'EXEC SPQ_JSON ''{"MODELO":"FGLO_COL","METODO":"RECIBIR_RPTASGLOSA","PARAMETROS":{"CNSENTREGA":"' + @CNSENTREGA + '"},"USUARIO":"' + REPLACE(@USUARIO, '''', '''''') + '"}''';
                       PRINT @SQL;

                       INSERT INTO @RESUL (DATO1, DATO2) EXEC (@SQL);

                       SELECT @CONTADOR_REGISTROS = COUNT(*) FROM @RESUL;
                       IF @CONTADOR_REGISTROS = 0
                       BEGIN
                           PRINT 'No se recibió respuesta válida de SPQ_JSON para recepción en cartera.';
                       END
                   END

                   PRINT 'TERMINO TODO.....';
                
                   -- Limpiar tabla temporal
                   DROP TABLE #FGLO;
               END

               -- =======================================================================
               -- 16. RESPUESTA FINAL AL CLIENTE
               -- =======================================================================
               SELECT 
                   'OK' AS OK,
                   @CNSRPDX AS CNSRPDX,
                   @NROLINEAS AS TOTAL_LINEAS,
                   @FILASEXITOSAS AS LINEAS_EXITOSAS,
                   @FILASERROR AS LINEAS_ERROR,
                   CASE WHEN @FILASERROR = 0 THEN 'PROCESO COMPLETADO SIN ERRORES'
                        ELSE 'PROCESO COMPLETADO CON ERRORES' 
                   END AS MENSAJE;

               SELECT ID3 AS CNSGLO, ID3 AS N_FACTURA, STRINGGRANDE1 AS ERROR 
               FROM RPDX  
               WHERE CNS = @CNSRPDX;

               -- =======================================================================
               -- 17. LIMPIEZA
               -- =======================================================================
               DROP TABLE #TMP_DATOS;

           END
           ELSE
           BEGIN
               SELECT 'KO' AS OK, 'No se encontraron Datos para Procesar' AS ERROR;
           END
       END TRY
       BEGIN CATCH
       
           IF OBJECT_ID('tempdb..#TMP_DATOS') IS NOT NULL
               DROP TABLE #TMP_DATOS;
            
           IF OBJECT_ID('tempdb..#FGLO') IS NOT NULL
               DROP TABLE #FGLO;

           SELECT 
               'KO' AS OK, 
               CONCAT(ERROR_MESSAGE(), ' -- ', ERROR_NUMBER(), ' -- ', ERROR_SEVERITY()) AS ERROR;
           RETURN;
       END CATCH
   END;
