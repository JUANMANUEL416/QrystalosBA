CREATE OR ALTER PROCEDURE DBO.SPQ_FGLO_COL @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS  
SET DATEFORMAT dmy
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE  @PARAMETROS NVARCHAR(MAX)			,@MODELO VARCHAR(100)			   ,@METODO VARCHAR(100)
		  ,@USUARIO VARCHAR(12)				  ,@COMPANIA VARCHAR(2)		       ,@IDSEDE      VARCHAR(5)		
		  ,@SYS_COMPUTERNAME VARCHAR(200)     ,@DATOS    VARCHAR(MAX)
		  ,@CNSGLO VARCHAR(20)                ,@CNSFCGLO VARCHAR(20)           ,@VALOR DECIMAL(14,2)
		  ,@PROCESO VARCHAR(20)               ,@TIPO  VARCHAR(20)              ,@TIPORESPUESTA  VARCHAR(20)
		  ,@RADICADO  VARCHAR(20)             ,@IDCONCEPTO  VARCHAR(20)        ,@VLRACEPTADO  DECIMAL(14,2)
		  ,@OBSERVACION  VARCHAR(MAX)         ,@FECHARESP  DATETIME            ,@USURESPONRTA  VARCHAR(20)
		  ,@OBSERVACIONRTA  VARCHAR(MAX)      ,@CODRPTA  VARCHAR(20)           ,@RESPUESTA  VARCHAR(MAX)
		  ,@CONCEPTO  VARCHAR(20)             ,@DESCRIPCION  VARCHAR(5000)       ,@VLRGLOSA  DECIMAL(14,2)
		  ,@CODGLOSA  VARCHAR(20)             ,@CANTIDAD  VARCHAR(20)          ,@VR_UNITARIO  VARCHAR(20)
		  ,@ITEM  INT                         ,@IDSERVICIO  VARCHAR(20)        ,@NROCOMPROBANTE  VARCHAR(20)
		  ,@NROCOMPROBANTENC  VARCHAR(20)     ,@VLRRECUPERAR  DECIMAL(14,2)    ,@CNSFNOT  VARCHAR(20)
		  ,@CNSLOG  VARCHAR(20)               ,@N_FACTURA  VARCHAR(20)         ,@VLRFACTURA DECIMAL(14,2)
		  ,@CNSRPDX VARCHAR(20)               ,@CNSGLOI  VARCHAR(20)           ,@IDTERCERO  VARCHAR(20)
		  ,@IMPRESIONES INT                   ,@CNSENTREGA VARCHAR(20)         ,@CNSFPAG VARCHAR(20)
		  ,@ESTADO VARCHAR(10)                 ,@FECHAINI DATETIME              ,@FECHAFIN DATETIME ,  @FECHAINI_STR NVARCHAR(10), @FECHAFIN_STR NVARCHAR(10)
		  ,@ASIGRESP SMALLINT				  ,@RESPONSABLE VARCHAR(20)		   ,@OBSRESPON VARCHAR (800)
		  ,@CLASE	VARCHAR(10)				  ,@GRUPO	 VARCHAR(20)		   ,@SUBGRUPO	VARCHAR(20), @CONDICION_ADICIONAL NVARCHAR(MAX)
		  ,@SQL_INFORME NVARCHAR(MAX)         ,@COND_FIX NVARCHAR(MAX)  	  ,@PREFIJOPRE VARCHAR(20), @PROCEDENCIA VARCHAR(10)
          ,@NOADMISION VARCHAR(16)            ,@N_CUOTA SMALLINT ,        @ACCION VARCHAR(20)
BEGIN
	SELECT *
	INTO #JSON 
	FROM OPENJSON(@json) WITH (
			MODELO VARCHAR(100) '$.MODELO'
			,METODO VARCHAR(100) '$.METODO'
			,USUARIO VARCHAR(12) '$.USUARIO'
			,PARAMETROS NVARCHAR(MAX) AS JSON
	)

	SELECT   @MODELO = MODELO			,@METODO = METODO
			,@PARAMETROS = PARAMETROS	,@USUARIO = USUARIO
	FROM #JSON

   SELECT @IDSEDE=COALESCE(UBEQ.IDSEDE,USUSU.IDSEDE),@COMPANIA=COALESCE(UBEQ.COMPANIA,USUSU.COMPANIA,'01'),
   @SYS_COMPUTERNAME=COALESCE(USUSU.SYS_COMPUTERNAME,HOST_NAME())
   FROM USUSU LEFT JOIN UBEQ ON USUSU.SYS_COMPUTERNAME=UBEQ.SYS_COMPUTERNAME
   WHERE USUSU.USUARIO=@USUARIO

	IF @METODO='TRAE_MOTIGLO'     
   BEGIN         
      SELECT @CNSGLO=CNSGLO        
      FROM   OPENJSON (@PARAMETROS)
      WITH (           
      CNSGLO  VARCHAR(20)   '$.CNSGLO' 
      )
      SELECT 'OK'OK
      SELECT FGLOCG.CNSFCGLO,FCGLO.DESCRIPCION,FGLOCG.VALOR,FGLOCG.OBSERVACION 
      FROM FGLOCG INNER JOIN FCGLO ON FGLOCG.CNSFCGLO=FCGLO.CNSFCGLO
      WHERE FGLOCG.CNSGLO=@CNSGLO

      SELECT  ITEM,TIPO,CODGLOSA,CODRPTA,VLRGLOSA,VLRACEPTADO,VLRRECUPERAR,
              IDSERVICIO,CONCEPTO,DESCRIPCION,OBSERVACION,RESPUESTA,CANTIDAD,
              VR_UNITARIO,ASIGRESP,RESPONSABLE,VWK_TEXCA.RAZONSOCIAL AS NOMBRE_RESPONSABLE, OBSRESPON,USUARIO
      FROM FGLOD LEFT JOIN VWK_TEXCA ON VWK_TEXCA.IDTERCERO = FGLOD.RESPONSABLE AND VWK_TEXCA.IDCATEGORIA = 'EMP'
      WHERE CNSGLO=@CNSGLO

      SELECT @N_FACTURA=N_FACTURA FROM FGLO WHERE CNSGLO=@CNSGLO
      IF (SELECT CERRADA FROM FGLO WHERE CNSGLO=@CNSGLO) = 0 
            AND EXISTS (
               SELECT 1
               FROM FTR
               LEFT JOIN FTRD ON FTRD.CNSFTR = FTR.CNSFCT
               LEFT JOIN CIT ON CIT.CONSECUTIVO = FTRD.NOADMISION
               WHERE FTR.N_FACTURA = @N_FACTURA
                 AND FTR.TIPOFAC = 'M'
                 AND FTR.PROCEDENCIA IN ('CE','CI')
                 AND CIT.TIPOCITA = 'Cita' 
            )
      BEGIN
        SELECT @PROCEDENCIA= PROCEDENCIA FROM FTR WHERE N_FACTURA=@N_FACTURA AND TIPOFAC='M' AND PROCEDENCIA IN ('CE','CI')
        SELECT 'OK' AS LIBERAR_FACTURA, @PROCEDENCIA AS PROCEDENCIA, @N_FACTURA AS N_FACTURA
      END

      RETURN
   END  
	IF @METODO='CRUD_FGLOCG'     
   BEGIN         
      SELECT @DATOS=DATOS        
      FROM   OPENJSON (@PARAMETROS)
      WITH (           
      DATOS NVARCHAR(MAX) AS JSON 
      )
                 
      SELECT @PROCESO=PROCESO, @CNSGLO =CNSGLO,@CNSFCGLO=CNSFCGLO,@VALOR=VALOR,@OBSERVACION=OBSERVACION
      FROM   OPENJSON (@DATOS)
      WITH   (  
      PROCESO  VARCHAR(20)   '$.PROCESO',
      CNSGLO  VARCHAR(20)   '$.CNSGLO',
      CNSFCGLO  VARCHAR(20)   '$.CNSFCGLO',
      VALOR  DECIMAL(14,2)   '$.VALOR',
      OBSERVACION  VARCHAR(1024)   '$.OBSERVACION'
      )   
      IF NOT EXISTS(SELECT * FROM  FGLO WHERE CNSGLO=@CNSGLO AND CERRADA=0)
      BEGIN
         INSERT INTO @TBLERRORES(ERROR)
         SELECT 'Consecutivo de Glosa no Encontrado O ya se encuentra Cerrada, Verifique e intente de nuevo'
      END
      ELSE
      BEGIN
         IF @PROCESO='Nuevo'
         BEGIN
            IF NOT EXISTS(SELECT * FROM FGLOCG WHERE CNSGLO=@CNSGLO AND CNSFCGLO=@CNSFCGLO)
            BEGIN
               INSERT INTO FGLOCG(CNSGLO,CNSFCGLO,VALOR,OBSERVACION)
               SELECT @CNSGLO,@CNSFCGLO,@VALOR,@OBSERVACION
            END
            ELSE
            BEGIN
               INSERT INTO @TBLERRORES(ERROR)
               SELECT 'Ya Existe un Motivo de Glosa con este Código, Verifique e Intente de nuevo'
            END
         END
         IF @PROCESO='Editar'
         BEGIN
            IF EXISTS(SELECT * FROM FGLOCG WHERE CNSGLO=@CNSGLO AND CNSFCGLO=@CNSFCGLO)
            BEGIN
               UPDATE FGLOCG SET VALOR=@VALOR,OBSERVACION=@OBSERVACION WHERE CNSGLO=@CNSGLO AND CNSFCGLO=@CNSFCGLO
            END
            ELSE
            BEGIN
               INSERT INTO @TBLERRORES(ERROR)
               SELECT 'Codigo de Glosa no Fue Encontrado, Verifique e intente de nuevo'
            END
         END
         IF @PROCESO='Borrar'
         BEGIN
            IF EXISTS(SELECT * FROM FGLOCG INNER JOIN FGLO ON FGLOCG.CNSGLO=FGLO.CNSGLO WHERE FGLOCG.CNSGLO=@CNSGLO AND CNSFCGLO=@CNSFCGLO AND FGLO.CERRADA=0)
            BEGIN
               DELETE FGLOCG WHERE FGLOCG.CNSGLO=@CNSGLO AND CNSFCGLO=@CNSFCGLO
            END
            ELSE
            BEGIN
               INSERT INTO @TBLERRORES(ERROR)
               SELECT 'No Fue posible Borrar el registro, verifique si la glosa ya fue cerrada'
            END
         END
      END
      IF(SELECT COUNT(*) FROM @TBLERRORES)>0
      BEGIN
         SELECT 'KO' OK, ERROR FROM @TBLERRORES
         RETURN
      END
      SELECT @VALOR=SUM(VALOR) FROM FGLOCG WHERE CNSGLO=@CNSGLO
      SELECT 'OK' OK,@VALOR VALOR
      RETURN 
   END  
	IF @METODO='CRUD_FGLO'     
   BEGIN         
      SELECT @DATOS=DATOS        
      FROM   OPENJSON (@PARAMETROS)
      WITH (           
      DATOS NVARCHAR(MAX) AS JSON 
      )
      DECLARE @APLICA  BIT

	  DECLARE @VLR_GLOSA_FGLO DECIMAL(14,2);
	  DECLARE @SUMA_MOTIVOS_FGLOCG DECIMAL(14,2);
	  DECLARE @VALIDACION_OK BIT = 1; --Bandera para ejecutar el update de glosa
      
      SELECT @CNSGLO=CNSGLO,@TIPO=TIPO,@TIPORESPUESTA=TIPORESPUESTA,@RADICADO=RADICADO,@IDCONCEPTO=IDCONCEPTO,
             @VLRACEPTADO=VLRACEPTADO,@OBSERVACION=OBSERVACION,@FECHARESP=CONVERT(DATE,FECHARESP),@USURESPONRTA=USURESPONRTA,
             @OBSERVACIONRTA=OBSERVACIONRTA,@APLICA=APLICA
      FROM   OPENJSON (@DATOS)
      WITH   ( 
      CNSGLO  VARCHAR(20)          '$.CNSGLO',
      TIPO  VARCHAR(20)            '$.TIPO.value',
      TIPORESPUESTA  VARCHAR(20)   '$.TIPORESPUESTA.value',
      RADICADO  VARCHAR(20)        '$.RADICADO',
      IDCONCEPTO  VARCHAR(20)      '$.IDCONCEPTO',
      VLRACEPTADO  DECIMAL(14,2)   '$.VLRACEPTADO',
      OBSERVACION  VARCHAR(MAX)    '$.OBSERVACION',
      FECHARESP  VARCHAR(20)       '$.FECHARESP',
      USURESPONRTA  VARCHAR(20)    '$.USURESPONRTA',
      OBSERVACIONRTA  VARCHAR(MAX) '$.OBSERVACIONRTA',
      APLICA  BIT   '$.APLICA'
      )   
      IF EXISTS(SELECT * FROM FGLO WHERE CNSGLO=@CNSGLO AND CERRADA=0)
      BEGIN
         PRINT 'INGESO'
         BEGIN TRY 
			IF @TIPORESPUESTA = 'T'
			BEGIN
				SELECT @VLR_GLOSA_FGLO = VLRGLOSA FROM FGLO WHERE CNSGLO = @CNSGLO;
				SELECT @SUMA_MOTIVOS_FGLOCG = SUM(VALOR) FROM FGLOCG WHERE CNSGLO = @CNSGLO;
				IF @VLR_GLOSA_FGLO <> ISNULL(@SUMA_MOTIVOS_FGLOCG, 0)
				BEGIN
					SET @VALIDACION_OK = 0;
					INSERT INTO @TBLERRORES(ERROR) SELECT 'El valor de los motivos  no coincide con el valor total de la glosa. No se pueden aplicar los cambios.';
				END
            IF @VLR_GLOSA_FGLO < @VLRACEPTADO
				BEGIN
					SET @VALIDACION_OK = 0;
					INSERT INTO @TBLERRORES(ERROR) SELECT 'El Valor aceptado no puede ser mayor que el valor de la glosa.';
				END
			END
			IF @VALIDACION_OK = 1
			BEGIN
				UPDATE FGLO SET TIPO=@TIPO,TIPORESPUESTA=@TIPORESPUESTA,RADICADO=@RADICADO,IDCONCEPTO=@IDCONCEPTO,VLRACEPTADO=COALESCE(@VLRACEPTADO,0),
				VLRRECUPERAR=VLRGLOSA-COALESCE(@VLRACEPTADO,0),OBSERVACION=@OBSERVACION,OBSERVACIONRTA=@OBSERVACIONRTA,USURESPONRTA=@USURESPONRTA,
				FECHARESP=@FECHARESP,USUARIO=CASE WHEN COALESCE(USUARIO,'')='' THEN  @USUARIO ELSE USUARIO END,USUARIOINGRTA=@USUARIO
				WHERE CNSGLO=@CNSGLO
				PRINT  'TERMINO UPDATE'
				IF COALESCE(@APLICA,0)=1
				BEGIN
				   PRINT 'Voy a aplicar la glosa FECHARESP'+CONVERT(VARCHAR,@FECHARESP,103)
				   IF EXISTS(SELECT * FROM PRI WHERE CONVERT(DATE,FECHA_INI)<=@FECHARESP AND CONVERT(DATE,FECHA_FIN)>=@FECHARESP AND COALESCE(CERRADO,0)=0 AND COALESCE(CERRADO_CARTERA,0)=0 )
				   BEGIN
					  SELECT @IDSEDE=COALESCE(UBEQ.IDSEDE,USUSU.IDSEDE),@COMPANIA=COALESCE(UBEQ.COMPANIA,USUSU.COMPANIA,'01'),
					  @SYS_COMPUTERNAME=COALESCE(USUSU.SYS_COMPUTERNAME,HOST_NAME())
					  FROM USUSU LEFT JOIN UBEQ ON USUSU.SYS_COMPUTERNAME=UBEQ.SYS_COMPUTERNAME
					  WHERE USUSU.USUARIO=@USUARIO
					  BEGIN TRY 
							PRINT 'Si pase voy a llamar el spk'
							EXEC SPK_RESPUESTAGLOSA @CNSGLO,3,@IDSEDE,@COMPANIA,@USUARIO,@SYS_COMPUTERNAME,0                                   
					  END TRY
					  BEGIN CATCH
							  INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
					  END CATCH
				   END
				END
			END
         END TRY
         BEGIN CATCH
                 INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
         END CATCH
      END
      ELSE
      BEGIN
         INSERT INTO @TBLERRORES(ERROR)
         SELECT 'No se Encontro la Glosa o ya esta Cerrada, Verifique e intente de nuevo'
      END
      IF(SELECT COUNT(*) FROM @TBLERRORES)>0
      BEGIN
         SELECT 'KO' OK, ERROR FROM @TBLERRORES
         RETURN
      END
      SELECT @TIPORESPUESTA=TIPORESPUESTA FROM FGLO WHERE CNSGLO=@CNSGLO
      SELECT 'OK' OK,@TIPORESPUESTA TIPORESP,@TIPO TIPO
      RETURN 
   END 
	IF @METODO='CRUD_FGLOD'
	BEGIN
		BEGIN TRY
			DECLARE @CODGLOSA_ANTERIOR VARCHAR(20);
			DECLARE @SUMA_VALOR_GLOSA DECIMAL(14,2);

			SELECT @DATOS=DATOS        
			FROM   OPENJSON (@PARAMETROS)
			WITH (           
			DATOS NVARCHAR(MAX) AS JSON 
			)
			SELECT @PROCESO =PROCESO,@CNSGLO =CNSGLO,@VLRACEPTADO =VLRACEPTADO,@VLRGLOSA =VLRGLOSA,@TIPO =TIPO,@CODGLOSA =CODGLOSA,@OBSERVACION =OBSERVACION,
			@CODRPTA =CODRPTA,@RESPUESTA =RESPUESTA,@CONCEPTO =CONCEPTO,@DESCRIPCION =DESCRIPCION,@CANTIDAD =CANTIDAD,@VR_UNITARIO =VR_UNITARIO,
			@IDSERVICIO =IDSERVICIO,@ITEM =ITEM,@ASIGRESP =ASIGRESP, @RESPONSABLE =RESPONSABLE ,@OBSRESPON = OBSRESPON, @USUARIO= USUARIO, @N_CUOTA=N_CUOTA
			FROM   OPENJSON (@DATOS)
			WITH (
				PROCESO  VARCHAR(20)       '$.PROCESO',
				CNSGLO  VARCHAR(20)        '$.CNSGLO',
				VLRACEPTADO  VARCHAR(20)   '$.VLRACEPTADO',
				VLRGLOSA  VARCHAR(20)      '$.VLRGLOSA',
				TIPO  VARCHAR(20)          '$.TIPO.value',
				CODGLOSA  VARCHAR(20)      '$.CODGLOSA',
				OBSERVACION  VARCHAR(MAX)  '$.OBSERVACION',
				CODRPTA  VARCHAR(20)       '$.CODRPTA',
				RESPUESTA  VARCHAR(MAX)    '$.RESPUESTA',
				CONCEPTO  VARCHAR(20)      '$.CONCEPTO',
				DESCRIPCION  VARCHAR(512)  '$.DESCRIPCION',
				CANTIDAD  VARCHAR(20)      '$.CANTIDAD',
				VR_UNITARIO  VARCHAR(20)   '$.VR_UNITARIO',
				ITEM  INT                  '$.ITEM',
				IDSERVICIO  VARCHAR(20)    '$.IDSERVICIO',
            N_CUOTA SMALLINT           '$.N_CUOTA',
				ASIGRESP SMALLINT		   '$.ASIGRESP',
				RESPONSABLE VARCHAR(20)	 '$.RESPONSABLE',
				OBSRESPON VARCHAR (800)	 '$.OBSRESPON',
                USUARIO VARCHAR(20)       '$.USUARIO'
			);

			IF NOT EXISTS (SELECT 1 FROM FGLO WHERE CNSGLO = @CNSGLO AND CERRADA = 0)
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) SELECT 'La glosa no se encontró o ya está cerrada.';
			END
			ELSE
			BEGIN
				IF @PROCESO = 'Nuevo'
				BEGIN 
					SELECT @ITEM = COALESCE(MAX(ITEM), 0) + 1 FROM FGLOD WHERE CNSGLO = @CNSGLO;
					INSERT INTO FGLOD (CNSGLO, ITEM, CNSCXC, N_FACTURA, USUARIO, FECHANOVEDAD, TIPO, IDSERVICIO, DESCRIPCION, CANTIDAD, VR_UNITARIO,
                               VLRGLOSA, VLRACEPTADO, VLRRECUPERAR, OBSERVACION, CERRADA, RESPUESTA, FECHARESP,  CONCEPTO,ASIGRESP, RESPONSABLE,
                               OBSRESPON, VALORFINAL, AUTORIZA, ESTADO, N_CUOTAS, USUARIOCE, TIPOTEC, F_CIERRE, CONTABILIZADA, NROCOMPROBANTE,
                               IDAREA, CCOSTO, CODUNG,  CODPRG, N_CUOTA, CODGLOSA, CODRPTA)
					SELECT CNSGLO, @ITEM, CNSCXC, N_FACTURA, @USUARIO, DBO.FNK_GETDATE(), @TIPO, @IDSERVICIO, @DESCRIPCION, @CANTIDAD, @VR_UNITARIO, 
						   @VLRGLOSA, @VLRACEPTADO, (@VLRGLOSA-@VLRACEPTADO), @OBSERVACION,CERRADA, @RESPUESTA,NULL, @CONCEPTO,@ASIGRESP,@RESPONSABLE,
						   @OBSRESPON,NULL, NULL, NULL,NULL,NULL,NULL,NULL,NULL,NULL, NULL, NULL,  NULL, NULL,
                           @N_CUOTA,
                           @CODGLOSA, @CODRPTA   
					FROM FGLO WHERE CNSGLO = @CNSGLO;
				END

				ELSE IF @PROCESO = 'Editar'
				BEGIN
					SELECT @CODGLOSA_ANTERIOR = CODGLOSA FROM FGLOD WHERE CNSGLO = @CNSGLO AND ITEM = @ITEM;
					
					UPDATE FGLOD SET TIPO=@TIPO, IDSERVICIO=@IDSERVICIO,N_CUOTA=@N_CUOTA, DESCRIPCION=@DESCRIPCION, CANTIDAD=@CANTIDAD, 
									VR_UNITARIO=@VR_UNITARIO, VLRGLOSA=@VLRGLOSA, VLRACEPTADO=@VLRACEPTADO, VLRRECUPERAR=(@VLRGLOSA-@VLRACEPTADO), 
									OBSERVACION=@OBSERVACION, RESPUESTA=@RESPUESTA, CONCEPTO=@CONCEPTO, ASIGRESP = @ASIGRESP, RESPONSABLE = @RESPONSABLE, 
									OBSRESPON=@OBSRESPON, CODGLOSA=@CODGLOSA, CODRPTA=@CODRPTA
					WHERE CNSGLO = @CNSGLO AND ITEM = @ITEM;

					IF @CODGLOSA_ANTERIOR <> @CODGLOSA
					BEGIN
						SELECT @SUMA_VALOR_GLOSA = SUM(VLRGLOSA) FROM FGLOD WHERE CNSGLO = @CNSGLO AND CODGLOSA = @CODGLOSA_ANTERIOR;
						IF COALESCE(@SUMA_VALOR_GLOSA, 0) > 0
							UPDATE FGLOCG SET VALOR = @SUMA_VALOR_GLOSA WHERE CNSGLO = @CNSGLO AND CNSFCGLO = @CODGLOSA_ANTERIOR;
						ELSE
							DELETE FROM FGLOCG WHERE CNSGLO = @CNSGLO AND CNSFCGLO = @CODGLOSA_ANTERIOR;
					END
				END

				ELSE IF @PROCESO = 'Borrar'
				BEGIN
					SELECT @CODGLOSA = CODGLOSA FROM FGLOD WHERE CNSGLO = @CNSGLO AND ITEM = @ITEM;
					DELETE FROM FGLOD WHERE CNSGLO = @CNSGLO AND ITEM = @ITEM;
				END
				-- calculo automatico de motivos FGLO

				SELECT @SUMA_VALOR_GLOSA = SUM(VLRGLOSA) FROM FGLOD WHERE CNSGLO = @CNSGLO AND CODGLOSA = @CODGLOSA;

				IF COALESCE(@SUMA_VALOR_GLOSA, 0) > 0
				BEGIN
					IF EXISTS (SELECT 1 FROM FGLOCG WHERE CNSGLO = @CNSGLO AND CNSFCGLO = @CODGLOSA)
						UPDATE FGLOCG SET VALOR = @SUMA_VALOR_GLOSA WHERE CNSGLO = @CNSGLO AND CNSFCGLO = @CODGLOSA;
					ELSE
						INSERT INTO FGLOCG (CNSGLO, CNSFCGLO, VALOR) VALUES (@CNSGLO, @CODGLOSA, @SUMA_VALOR_GLOSA);
				END
				ELSE
				BEGIN
					DELETE FROM FGLOCG WHERE CNSGLO = @CNSGLO AND CNSFCGLO = @CODGLOSA;
				END
			END

		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE();
		END CATCH

		IF(SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK, ERROR FROM @TBLERRORES; RETURN;
		END
		
		SELECT @VALOR = SUM(VLRGLOSA) FROM FGLOD WHERE CNSGLO = @CNSGLO;
		SELECT 'OK' OK, @VALOR VALOR;
		RETURN;
	END
	IF @METODO = 'BORRAR_TODO_ITEMS'
	BEGIN
		BEGIN TRY
			SELECT @CNSGLO = CNSGLO
			FROM OPENJSON (@PARAMETROS)
			WITH (
				CNSGLO VARCHAR(20) '$.CNSGLO'
			);
			IF EXISTS (SELECT 1 FROM FGLO WHERE CNSGLO = @CNSGLO AND CERRADA = 0)
			BEGIN
				IF NOT EXISTS (	SELECT 1 FROM FGLOCG WHERE CNSGLO = @CNSGLO
								UNION ALL
								SELECT 1 FROM FGLOD WHERE CNSGLO = @CNSGLO
								)
				BEGIN
					SELECT 'KO' AS KO,'No hay items o motivos para borrar.'AS MENSAJE;
					RETURN;
				END
				ELSE
				BEGIN
					DELETE FROM FGLOD WHERE CNSGLO = @CNSGLO;
					DELETE FROM FGLOCG WHERE CNSGLO = @CNSGLO;
				END
			END
			ELSE
			BEGIN
				INSERT INTO @TBLERRORES(ERROR)
				SELECT 'No se pueden borrar los detalles: la glosa no existe o ya se encuentra cerrada.';
				RETURN;
			END
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE();
		END CATCH
		IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' AS OK, ERROR FROM @TBLERRORES;
			RETURN;
		END
		ELSE
		BEGIN
			SELECT 'OK' AS OK, 'Todos los motivos e ítems han sido eliminados.' AS MENSAJE;
			RETURN;
		END
	END
	IF @METODO='APLICAR_GLOSA'     
   BEGIN         
      SELECT @CNSGLO =CNSGLO, @USUARIO = USUARIO       
      FROM   OPENJSON (@PARAMETROS)
      WITH (           
      CNSGLO  VARCHAR(20)   '$.CNSGLO',
	  USUARIO VARCHAR(12) '$.USUARIO'
      )   
      IF EXISTS(SELECT * FROM FGLO WHERE CNSGLO=@CNSGLO AND CERRADA=0)
      BEGIN
         SELECT @FECHARESP=CONVERT(DATE,FECHARESP) FROM FGLO WHERE CNSGLO=@CNSGLO
         PRINT 'Voy a aplicar la glosa FECHARESP'+CONVERT(VARCHAR,@FECHARESP,103)
         IF EXISTS(SELECT * FROM PRI WHERE CONVERT(DATE,FECHA_INI)<=@FECHARESP AND CONVERT(DATE,FECHA_FIN)>=@FECHARESP AND COALESCE(CERRADO,0)=0 AND COALESCE(CERRADO_CARTERA,0)=0 )
         BEGIN
            BEGIN TRY 
                  PRINT 'Si pase voy a llamar el spk'
                  EXEC SPK_RESPUESTAGLOSA @CNSGLO,3,@IDSEDE,@COMPANIA,@USUARIO,@SYS_COMPUTERNAME,0 
				   UPDATE FGLO
				   SET USUAPLIGLOSA = @USUARIO
				   WHERE CNSGLO = @CNSGLO;
            END TRY
            BEGIN CATCH
                     INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
            END CATCH
         END
         ELSE
         BEGIN
            INSERT INTO @TBLERRORES(ERROR)
            SELECT 'Periodo contable, cerrado o no existe, Verifique e intente de nuevo'
         END
      END
      ELSE
      BEGIN
         INSERT INTO @TBLERRORES(ERROR)
         SELECT 'No se encontro el Cnsglosa o ya fue aplicado, verifique e intente de nuevo'
