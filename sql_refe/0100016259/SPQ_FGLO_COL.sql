    IF @METODO='LIBERAR_PAC'
   BEGIN
		SELECT @N_FACTURA = N_FACTURA,
			   @PROCEDENCIA = PROCEDENCIA,
			   @NOADMISION = NOADMISION,
			   @N_CUOTA = N_CUOTA
		FROM OPENJSON(@PARAMETROS) WITH (
			N_FACTURA VARCHAR(20) '$.N_FACTURA',
			PROCEDENCIA VARCHAR(10) '$.PROCEDENCIA',
			NOADMISION VARCHAR(20) '$.NOADMISION',
			N_CUOTA NVARCHAR(32) '$.N_CUOTA'
		)

		IF @N_FACTURA IS NULL OR @PROCEDENCIA IS NULL OR @NOADMISION IS NULL
		BEGIN
			SELECT 'KO' OK, 'Faltan N_FACTURA, PROCEDENCIA, NOADMISION o N_CUOTA inválido.' AS ERROR, 'Datos incompletos.' AS MENSAJE
			RETURN
		END

		IF UPPER(@PROCEDENCIA) = 'CI'
		BEGIN
			IF NOT EXISTS (SELECT 1 FROM CIT WHERE CONSECUTIVO = @NOADMISION AND TIPOCITA ='Cita')
			BEGIN
				SELECT 'KO' OK, 'No existe CIT para CONSECUTIVO  indicados.' AS ERROR, 'Cita no encontrada.' AS MENSAJE
				RETURN
			END

			UPDATE CIT
			   SET N_FACTURA = NULL,
				   FACTURADA = 0
			 WHERE CONSECUTIVO = @NOADMISION
			   AND N_FACTURA = @N_FACTURA
               AND TIPOCITA='Cita'

			IF @@ROWCOUNT = 0
			BEGIN
				SELECT 'KO' OK, 'No se actualizó CIT (revisar N_FACTURA o estado de la cita).' AS ERROR, 'Sin cambios.' AS MENSAJE
				RETURN
			END

			SELECT 'OK' OK, CAST(NULL AS VARCHAR(MAX)) AS ERROR, 'Cita liberada: N_FACTURA=NULL, FACTURADA=0.' AS MENSAJE
			RETURN
		END

		IF UPPER(@PROCEDENCIA) = 'CE'
		BEGIN
			IF NOT EXISTS (SELECT 1 FROM AUT WHERE IDAUT = @NOADMISION)
			BEGIN
				SELECT 'KO' OK, 'No existe CE para CONSECUTIVO  indicados.' AS ERROR, 'Cita no encontrada.' AS MENSAJE
				RETURN
			END

			UPDATE AUT
			   SET N_FACTURA = NULL,
				   FACTURADA = 0
			 WHERE IDAUT = @NOADMISION
			UPDATE AUTD
			   SET N_FACTURA = NULL,
				   FACTURADA = 0
			 WHERE IDAUT = @NOADMISION  
               

			IF @@ROWCOUNT = 0
			BEGIN
				SELECT 'KO' OK, 'No se actualizó CE (revisar N_FACTURA o estado de la cita).' AS ERROR, 'Sin cambios.' AS MENSAJE
				RETURN
			END

			SELECT 'OK' OK, CAST(NULL AS VARCHAR(MAX)) AS ERROR, 'Cita liberada: N_FACTURA=NULL, FACTURADA=0.' AS MENSAJE
			RETURN
		END

		SELECT 'KO' OK, 'PROCEDENCIA no válida para LIBERAR_PAC.' AS ERROR, 'Procedencia no soportada.' AS MENSAJE
		RETURN
   END
