CREATE OR ALTER PROCEDURE DBO.SPQ_ADELANTO_CESAN @METODO VARCHAR(20), @NUMDOC VARCHAR(20) = NULL, @ANO VARCHAR(4) = NULL, @CNSPAGO_APLICA VARCHAR(20) = NULL, @MONTO_A_CUBRIR 
	DECIMAL(14, 2) = NULL
AS
DECLARE @CNSNACE VARCHAR(20)
DECLARE @PENDIENTE DECIMAL(14, 2)
DECLARE @RESTANTE DECIMAL(14, 2)
DECLARE @APLICAR DECIMAL(14, 2)

BEGIN
	SET @METODO = UPPER(LTRIM(RTRIM(COALESCE(@METODO, ''))))

	IF @METODO = 'APLICAR'
	BEGIN
		SET @RESTANTE = COALESCE(@MONTO_A_CUBRIR, DBO.FNK_VALOR_ADELANTO_CESAN_PENDIENTE(@NUMDOC, @ANO))

		IF COALESCE(@RESTANTE, 0) <= 0
			RETURN

		DECLARE C_ADEL CURSOR LOCAL FAST_FORWARD
		FOR
		SELECT CNSNACE, (VALOR - COALESCE(VALOR_APLICADO, 0))
		FROM NACE
		WHERE ANO = @ANO AND ESTADO IN ('Registrado', 'EnNomina') AND (VALOR - COALESCE(VALOR_APLICADO, 0)) > 0 AND NUMDOC IN (
				SELECT N1.NUMDOC
				FROM NEMP N1
				WHERE EXISTS (
						SELECT 1
						FROM NEMP N2
						WHERE N1.TERCEROID = N2.TERCEROID AND N2.NUMDOC = @NUMDOC
						)
				)
		ORDER BY FECHA, CNSNACE

		OPEN C_ADEL

		FETCH NEXT
		FROM C_ADEL
		INTO @CNSNACE, @PENDIENTE

		WHILE @@FETCH_STATUS = 0 AND @RESTANTE > 0
		BEGIN
			SET @APLICAR = CASE 
					WHEN @PENDIENTE <= @RESTANTE
						THEN @PENDIENTE
					ELSE @RESTANTE
					END

			UPDATE NACE
			SET VALOR_APLICADO = COALESCE(VALOR_APLICADO, 0) + @APLICAR, ESTADO = CASE 
					WHEN COALESCE(VALOR_APLICADO, 0) + @APLICAR >= VALOR
						THEN 'Aplicado'
					ELSE ESTADO
					END, CNSPAGO_APLICA = @CNSPAGO_APLICA, FECHA_APLICA = GETDATE(), FECHAMOD = GETDATE()
			WHERE CNSNACE = @CNSNACE

			SET @RESTANTE = @RESTANTE - @APLICAR

			FETCH NEXT
			FROM C_ADEL
			INTO @CNSNACE, @PENDIENTE
		END

		CLOSE C_ADEL

		DEALLOCATE C_ADEL

		RETURN
	END

	IF @METODO = 'DESAPLICAR'
	BEGIN
		IF COALESCE(@CNSPAGO_APLICA, '') = ''
			RETURN

		UPDATE NACE
		SET VALOR_APLICADO = 0, ESTADO = CASE 
				WHEN CNSPAGO IS NOT NULL AND CNSPAGO <> ''
					THEN 'EnNomina'
				ELSE 'Registrado'
				END, CNSPAGO_APLICA = NULL, FECHA_APLICA = NULL, FECHAMOD = GETDATE()
		WHERE CNSPAGO_APLICA = @CNSPAGO_APLICA AND (ESTADO = 'Aplicado' OR COALESCE(VALOR_APLICADO, 0) > 0)

		RETURN
	END

	IF @METODO = 'DESAPLICAR_UNICO'
	BEGIN
		DECLARE @TERCEROID VARCHAR(20);

		SELECT @TERCEROID = TERCEROID
		FROM NEMP
		WHERE NUMDOC = @NUMDOC;

		IF COALESCE(@CNSPAGO_APLICA, '') = ''
			RETURN

		UPDATE NACE
		SET VALOR_APLICADO = 0, ESTADO = CASE 
				WHEN CNSPAGO IS NOT NULL AND CNSPAGO <> ''
					THEN 'EnNomina'
				ELSE 'Registrado'
				END, CNSPAGO_APLICA = NULL, FECHA_APLICA = NULL, FECHAMOD = GETDATE()
		WHERE CNSPAGO_APLICA = @CNSPAGO_APLICA AND NUMDOC IN (
				SELECT NUMDOC
				FROM NEMP
				WHERE TERCEROID = @TERCEROID
				) AND (ESTADO = 'Aplicado' OR COALESCE(VALOR_APLICADO, 0) > 0)

		RETURN
	END
END

