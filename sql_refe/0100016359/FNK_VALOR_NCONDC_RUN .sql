IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='FNK_VALOR_NCONDC_RUN' AND XTYPE='FN')
BEGIN
 DROP FUNCTION FNK_VALOR_NCONDC_RUN 
END

GO
CREATE FUNCTION DBO.FNK_VALOR_NCONDC_RUN(  
    @NUMDOC      VARCHAR(20),   
    @CODCONCEPTO VARCHAR(20),   
    @ITEM        DECIMAL(14,0),  
    @FECHAINI    DATETIME,   
    @FECHAFIN    DATETIME,   
    @CNSPAGO     VARCHAR(20))    
RETURNS DECIMAL(15,6)  
BEGIN    
   DECLARE @VALOR            DECIMAL(15,6)  
   DECLARE @VALOR_CALCULO    DECIMAL(15,6)  
   DECLARE @CODCONCEPTO_BASE VARCHAR(20)  
   DECLARE @REQUIERELIQ      SMALLINT  
   DECLARE @VALHORASLAB      SMALLINT  
   DECLARE @HORAS_COMP        INT  
   DECLARE @DIAS_LAB         INT  
  
 IF @DIAS_LAB = 0  
  SET @DIAS_LAB = NULL  
  
 DECLARE CUR_NCONDC CURSOR FOR    
 SELECT CODCONCEPTO_BASE, ISNULL(REQUIERELIQ,1), ISNULL(VALHORASLAB,0), HORAS, DIAS  
 FROM NCONDC WHERE CODCONCEPTO=@CODCONCEPTO AND ITEM=@ITEM  
  
 SET @VALOR = 0    
  
 OPEN CUR_NCONDC  
  
 FETCH NEXT FROM CUR_NCONDC    
 INTO @CODCONCEPTO_BASE, @REQUIERELIQ, @VALHORASLAB, @HORAS_COMP, @DIAS_LAB  
  
 WHILE @@FETCH_STATUS = 0     
 BEGIN      
  SET @VALOR_CALCULO = 0  
  IF @REQUIERELIQ = 1  
  BEGIN  
      IF (SELECT COUNT(*) FROM NEMPFD_RUN WHERE CNSPAGO=@CNSPAGO AND NUMDOC=@NUMDOC AND CODCONCEPTO=@CODCONCEPTO_BASE AND SYS_COMPUTERNAME=HOST_NAME())>0  
      BEGIN 
         SELECT @VALOR_CALCULO = ISNULL(V.VALOR_EMPLEADO,0)  
         FROM DBO.FNK_VALORCONCEPTO_NEMPFD_RUN(@NUMDOC, @CODCONCEPTO_BASE, @FECHAINI, @FECHAFIN, @CNSPAGO, @VALHORASLAB, @HORAS_COMP, @DIAS_LAB) AS V    
      END
  END  
  ELSE 
  BEGIN
      SELECT @VALOR_CALCULO = ISNULL(V.VALOR_EMPLEADO,0)  
      FROM DBO.FNK_VALORCONCEPTO_NEMPFD_RUN(@NUMDOC, @CODCONCEPTO_BASE, @FECHAINI, @FECHAFIN, @CNSPAGO, @VALHORASLAB, @HORAS_COMP, @DIAS_LAB) AS V    
  END 
  IF EXISTS(SELECT * FROM NEVED WHERE IDEVENTO = 'RET' AND  CODCONCEPTO=@CODCONCEPTO_BASE )
  BEGIN
      SELECT @VALOR_CALCULO=DBO.FNK_VALOR_CONCEP_RETIRO_RUN(@CNSPAGO ,@NUMDOC , @CODCONCEPTO_BASE )
  END
  SELECT  @VALOR= COALESCE(@VALOR,0) + COALESCE(@VALOR_CALCULO,0)
  
  FETCH NEXT FROM CUR_NCONDC    
  INTO @CODCONCEPTO_BASE, @REQUIERELIQ, @VALHORASLAB, @HORAS_COMP, @DIAS_LAB  
 END    
 CLOSE CUR_NCONDC  
 DEALLOCATE CUR_NCONDC  
 RETURN @VALOR  
END  


