CREATE OR ALTER PROCEDURE DBO.SPQ_FRT_NEMP @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
SET DATEFORMAT dmy

DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(12), @COMPANIA VARCHAR(2), @DATOS VARCHAR(MAX)
DECLARE @CNSEXCEL VARCHAR(20), @IDSEDE VARCHAR(5), @SYS_COMPUTERNAME VARCHAR(200)
DECLARE @ITEM INT, @NROLINEAS INT, @CNSPAGO VARCHAR(20), @CNSRPDX VARCHAR(20), @INDICE INT, @TERRORES SMALLINT, @TOK SMALLINT, @ESTRUCTURA INT, @ERROR VARCHAR(2024), @ER 
	BIT, @NUMDOC VARCHAR(20), @NOMBREEMPLEADO VARCHAR(250), @FECHARETIRO DATE, @XFECHA VARCHAR(20), @TODOS SMALLINT, @IDEVENTO VARCHAR(6), @FACTOR DECIMAL(14, 6), 
	@FECHAINI DATETIME, @CODNOMINA VARCHAR(2), @JSONPARAM NVARCHAR(MAX)

BEGIN
	SELECT *
	INTO #JSON
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	SELECT @MODELO = MODELO, @METODO = METODO, @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON

	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
	FROM USUSU
	WHERE USUARIO = @USUARIO

	SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
	FROM UBEQ
	WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	IF @METODO = 'CARGAR_EMPLEADOS'
	BEGIN
		DECLARE @LINEA AS VARCHAR(MAX)
		DECLARE @TABLA AS TABLE (ITEM INT IDENTITY(1, 1), VALOR VARCHAR(MAX))

		SELECT @NROLINEAS = COUNT(*)
		FROM OPENJSON(@PARAMETROS, '$.LINEAS')

		SELECT @CODNOMINA = CODNOMINA
		FROM OPENJSON(@PARAMETROS) WITH (CODNOMINA VARCHAR(2) '$.CODNOMINA')

		IF @NROLINEAS > 0
		BEGIN
			SELECT @IDSEDE = COALESCE(UBEQ.IDSEDE, USUSU.IDSEDE), @COMPANIA = COALESCE(UBEQ.COMPANIA, USUSU.COMPANIA), @SYS_COMPUTERNAME = COALESCE(USUSU.
					SYS_ComputerName, HOST_NAME())
			FROM USUSU
			LEFT JOIN UBEQ ON USUSU.SYS_ComputerName = UBEQ.SYS_ComputerName
			WHERE USUSU.USUARIO = @USUARIO

			----PRINT 'AQUI LLAMO A GENCONSECUTIVO @IDSEDE=' + COALESCE(@IDSEDE, 'SIN SEDE')
			SELECT @CNSRPDX = ''

			EXEC SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE, '@RPDX', @CNSRPDX OUTPUT

			SELECT @CNSRPDX = @IDSEDE + REPLACE(SPACE(8 - LEN(@CNSRPDX)) + LTRIM(RTRIM(@CNSRPDX)), SPACE(1), 0)

			--PRINT '@CNSRPDX=' + COALESCE(@CNSRPDX, '')
			SELECT @INDICE = 0

			DECLARE SUBIR_CURSOR CURSOR
			FOR
			SELECT VALUE
			FROM OPENJSON(@PARAMETROS, '$.LINEAS')

			OPEN SUBIR_CURSOR

			FETCH NEXT
			FROM SUBIR_CURSOR
			INTO @LINEA

			WHILE @@FETCH_STATUS = 0
			BEGIN
				DELETE @TABLA
				WHERE 1 = 1

				INSERT INTO @TABLA (VALOR)
				SELECT VALUE
				FROM string_split(@LINEA, ',')

				SELECT @ESTRUCTURA = COUNT(*)
				FROM @TABLA

				SET @ERROR = ''
				SET @ER = 0

				SELECT @NUMDOC = NULL, @NOMBREEMPLEADO = NULL, @FECHARETIRO = NULL

				BEGIN TRY
					SELECT @NUMDOC = VALOR
					FROM @TABLA
					WHERE ITEM = 1 + @INDICE

					SELECT @NOMBREEMPLEADO = VALOR
					FROM @TABLA
					WHERE ITEM = 2 + @INDICE

					SELECT @XFECHA = VALOR
					FROM @TABLA
					WHERE ITEM = 3 + @INDICE

					IF ISDATE(@XFECHA) = 1
					BEGIN
						SELECT @FECHARETIRO = CONVERT(DATE, VALOR)
						FROM @TABLA
						WHERE ITEM = 3 + @INDICE
					END
					ELSE
					BEGIN
						SELECT @FECHARETIRO = NULL, @ER = 1, @ERROR = 'Fecha de Retiro no Valida ' + @XFECHA
					END

					IF @ESTRUCTURA <> 3
					BEGIN
						SELECT @ER = 1, @ERROR = 'Error de Estructura Campos =' + CAST(@ESTRUCTURA AS VARCHAR(4))
					END

					IF @ER = 1
					BEGIN
						IF NOT EXISTS (
								SELECT *
								FROM RPDX
								WHERE CNS = @CNSRPDX AND ID1 = @NUMDOC
								)
						BEGIN
							INSERT INTO RPDX (CNS, ID1, STRINGGRANDE1, ID2, CANTIDAD10, STRINGMAX)
							SELECT @CNSRPDX, @NUMDOC, @NOMBREEMPLEADO, @FECHARETIRO, 1, @ERROR
						END
					END
					ELSE
					BEGIN
						--PRINT 'Validaición de existencia de datos'
						IF NOT EXISTS (
								SELECT *
								FROM NEMP
								WHERE NUMDOC = @NUMDOC
								)
						BEGIN
							SELECT @ER = 1, @ERROR = @ERROR + ' - Codigo de contrato No existe'
						END

						IF (
								SELECT CASE 
										WHEN FECHARETIRO IS NULL
											THEN 0
										ELSE 1
										END
								FROM NEMP
								WHERE NUMDOC = @NUMDOC
								) = 1
						BEGIN
							SELECT @ER = 1, @ERROR = @ERROR + ' - El Empleado ya registra una fecha de retiro'
						END

						IF NOT EXISTS (
								SELECT *
								FROM NOMIE
								WHERE NUMDOC = @NUMDOC AND CODNOMINA = @CODNOMINA
								)
						BEGIN
							SELECT @ER = 1, @ERROR = @ERROR + ' - El Contrato ' + @NUMDOC + ' no existe dentro de la plantilla de la nomina'
						END
						ELSE
						BEGIN
							IF (
									(
										SELECT ESTADO
										FROM NOMIE
										WHERE CODNOMINA = @CODNOMINA AND NUMDOC = @NUMDOC
										) = 'Inactivo'
									)
							BEGIN
								SELECT ' - El Contrato ' + @NUMDOC + ' se encuentra inactivo en la plantilla de la nomina'
							END
						END

						IF NOT EXISTS (
								SELECT *
								FROM RPDX
								WHERE CNS = @CNSRPDX AND ID1 = @NUMDOC
								)
						BEGIN
							INSERT INTO RPDX (CNS, ID1, STRINGGRANDE1, ID2, CANTIDAD10, STRINGMAX)
							SELECT @CNSRPDX, @NUMDOC, @NOMBREEMPLEADO, @FECHARETIRO, @ER, @ERROR
						END
					END
				END TRY

				BEGIN CATCH
					SELECT @NUMDOC = VALOR
					FROM @TABLA
					WHERE ITEM = 1 + @INDICE

					INSERT INTO RPDX (CNS, ID1, STRINGGRANDE2, STRINGMAX, CANTIDAD10)
					SELECT @CNSRPDX, @NUMDOC, ERROR_MESSAGE(), @LINEA, 1
				END CATCH

				SET @INDICE += @ESTRUCTURA

				FETCH NEXT
				FROM SUBIR_CURSOR
				INTO @LINEA
			END

			CLOSE SUBIR_CURSOR

			DEALLOCATE SUBIR_CURSOR

			SELECT @NROLINEAS = COUNT(*)
			FROM RPDX
			WHERE CNS = @CNSRPDX --AND CANTIDAD=1

			SELECT @TERRORES = SUM(CASE 
						WHEN CANTIDAD10 = 1
							THEN 1
						ELSE 0
						END), @TOK = SUM(CASE 
						WHEN CANTIDAD10 = 1
							THEN 0
						ELSE 1
						END)
			FROM RPDX
			WHERE CNS = @CNSRPDX

			SELECT 'OK' OK, @CNSRPDX CNSRPDX, @NROLINEAS TODOS, @TERRORES ERRADOS, @TOK TOK

			RETURN
		END
		ELSE
		BEGIN
			SELECT 'KO', 'No se encontraron Datos para Procesar, Verfique e intente de nuevo' ERROR

			RETURN
		END
	END

	IF @METODO = 'EXPORTA_EMPLEADOS'
	BEGIN
		SELECT @CNSEXCEL = JSON_VALUE(@PARAMETROS, '$.CNSEXCEL')

		SELECT @CNSPAGO = CNSPAGO
		FROM OPENJSON(@PARAMETROS) WITH (CNSPAGO VARCHAR(20) '$.CNSPAGO')

		IF @CNSEXCEL IS NULL
		BEGIN
			EXEC SPK_GENCONSECUTIVO @COMPANIA, @IDSEDE, '@EXCEL', @CNSEXCEL OUTPUT

			SELECT @CNSEXCEL = @IDSEDE + REPLACE(SPACE(8 - LEN(@CNSEXCEL)) + LTRIM(RTRIM(@CNSEXCEL)), SPACE(1), 0)
		END

		BEGIN TRY
			INSERT INTO KEXCEL_FILL (CNSEXCEL, NOMBRE, BORRAR, CONSULTA)
			SELECT @CNSEXCEL, 'Empleados ' + CONVERT(VARCHAR, GETDATE(), 112) + '_' + REPLACE(CONVERT(VARCHAR, GETDATE(), 108), ':', '') + '.xlsx', 1, 
				'SELECT NEMP.NUMDOC, CONCAT('' '' + COALESCE(NEMP.PRIMERAPELLIDO, ''''), '' '' + COALESCE(NEMP.SEGUNDOAPELLIDO, ''''), '' '' + COALESCE(NEMP.PRIMERNOMBRE, ''''), '' '' + COALESCE(NEMP.SEGUNDONOMBRE, '''')) AS NOMBREEMPLEADO,NEMP.DOCIDEMPLEADO  FROM NEMPF INNER JOIN NEMP ON NEMP.NUMDOC = NEMPF.NUMDOC WHERE NEMPF.CNSPAGO = ''' 
				+ @CNSPAGO + ''''
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK, @CNSEXCEL CNSEXCEL

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK, @CNSEXCEL CNSEXCEL
	END

	IF @METODO = 'VALIDAR_RPDX_EMPLEADO'
	BEGIN
		SELECT @DATOS = DATOS, @CODNOMINA = CODNOMINA
		FROM OPENJSON(@PARAMETROS) WITH (DATOS NVARCHAR(MAX) AS JSON, CODNOMINA VARCHAR(2) '$.CODNOMINA')

		SELECT @CNSRPDX = CNS, @ITEM = ID, @NUMDOC = NUMDOC, @NOMBREEMPLEADO = NOMBREEMPLEADO, @XFECHA = CONVERT(VARCHAR, CAST(REPLACE(FECHARETIRO, '-', '/') AS DATE), 103
			), @ERROR = ERRORTXT
		FROM OPENJSON(@DATOS) WITH (
				CNS VARCHAR(20) '$.CNS', ID INT '$.ID', NUMDOC VARCHAR(20) '$.NUMDOC', NOMBREEMPLEADO VARCHAR(250) '$.NOMBREEMPLEADO', FECHARETIRO VARCHAR(20) 
				'$.FECHARETIRO', ERRORTXT VARCHAR(20) '$.ERRORTXT'
				)

		--PRINT 'Validaición de existencia de datos'
		SELECT @ER = 0, @ERROR = ''

		IF ISDATE(@XFECHA) = 0
		BEGIN
			SELECT @ER = 1, @ERROR = 'Fecha de Ingreso no Valida =' + @XFECHA
		END
		ELSE
		BEGIN
			SELECT @FECHARETIRO = CAST(@XFECHA AS DATE)

			IF @FECHARETIRO < (
					SELECT FECHAINGRESO
					FROM NEMP
					WHERE NUMDOC = @NUMDOC
					)
			BEGIN
				SELECT @ER = 1, @ERROR = @ERROR + ' - Fecha de Retiro Es Menor a la fecha de ingreso' + @XFECHA
			END
		END

		IF NOT EXISTS (
				SELECT *
				FROM NEMP
				WHERE NUMDOC = @NUMDOC
				)
		BEGIN
			SELECT @ER = 1, @ERROR = @ERROR + ' - Codigo de contrato No existe'
		END

		IF EXISTS (
				SELECT 1
				FROM RPDX
				WHERE CNS = @CNSRPDX AND ID1 = @NUMDOC AND ITEM <> @ITEM
				)
		BEGIN
			SELECT @ER = 1, @ERROR = @ERROR + ' - Codigo de contrato duplicado'
		END

		IF (
				SELECT CASE 
						WHEN FECHARETIRO IS NULL
							THEN 0
						ELSE 1
						END
				FROM NEMP
				WHERE NUMDOC = @NUMDOC
				) = 1
		BEGIN
			SELECT @ER = 1, @ERROR = @ERROR + ' - El Empleado ya registra una fecha de retiro'
		END

		IF NOT EXISTS (
				SELECT *
				FROM NOMIE
				WHERE NUMDOC = @NUMDOC AND CODNOMINA = @CODNOMINA
				)
		BEGIN
			SELECT @ER = 1, @ERROR = @ERROR + ' - El Contrato ' + @NUMDOC + ' no existe dentro de la plantilla de la nomina'
		END
		ELSE
		BEGIN
			IF (
					(
						SELECT ESTADO
						FROM NOMIE
						WHERE CODNOMINA = @CODNOMINA AND NUMDOC = @NUMDOC
						) = 'Inactivo'
					)
			BEGIN
				SELECT ' - El Contrato ' + @NUMDOC + ' se encuentra inactivo en la plantilla de la nomina'
			END
		END

		--PRINT 'ACTUALIZO RPDX ITEM=' + CAST(@ITEM AS VARCHAR(20)) + '@ER=' + CAST(@ER AS VARCHAR(2))
		BEGIN TRY
			UPDATE RPDX
			SET ID1 = @NUMDOC, STRINGGRANDE1 = @NOMBREEMPLEADO, ID2 = @FECHARETIRO, CANTIDAD10 = @ER, STRINGMAX = @ERROR
			WHERE ITEM = @ITEM
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK, ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT @TERRORES = SUM(CASE 
					WHEN CANTIDAD10 = 1
						THEN 1
					ELSE 0
					END), @TOK = SUM(CASE 
					WHEN CANTIDAD10 = 1
						THEN 0
					ELSE 1
					END), @TODOS = COUNT(*)
		FROM RPDX
		WHERE CNS = @CNSRPDX

		SELECT 'OK' OK, @TERRORES ERRADOS, @TOK TOK, @TODOS TODOS

		RETURN
	END

	IF @METODO = 'ELIMINAR_RPDX_EMPLEADO'
	BEGIN
		SELECT @DATOS = DATOS
		FROM OPENJSON(@PARAMETROS) WITH (DATOS NVARCHAR(MAX) AS JSON)

		SELECT @CNSRPDX = CNS, @ITEM = ID
		FROM OPENJSON(@DATOS) WITH (CNS VARCHAR(20) '$.CNS', ID INT '$.ID')

		BEGIN TRY
			DELETE
			FROM RPDX
			WHERE ITEM = @ITEM
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK, ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT @TERRORES = SUM(CASE 
					WHEN CANTIDAD10 = 1
						THEN 1
					ELSE 0
					END), @TOK = SUM(CASE 
					WHEN CANTIDAD10 = 1
						THEN 0
					ELSE 1
					END), @TODOS = COUNT(*)
		FROM RPDX
		WHERE CNS = @CNSRPDX

		SELECT 'OK' OK, @TERRORES ERRADOS, @TOK TOK, @TODOS TODOS

		RETURN
	END

	IF @METODO = 'RETIRAR_EMPLEADOS'
	BEGIN
		SELECT @CNSRPDX = CNS, @CNSPAGO = CNSPAGO, @FECHAINI = FECHAINI
		FROM OPENJSON(@PARAMETROS) WITH (CNS VARCHAR(20) '$.CNS', CNSPAGO VARCHAR(20) '$.CNSPAGO', FECHAINI DATETIME '$.FECHAINI')

		SELECT @IDEVENTO = NEVE.IDEVENTO, @FACTOR = MAX(COALESCE(NEVED.FACTOR, 0))
		FROM NEVE
		LEFT JOIN NEVED ON NEVED.IDEVENTO = NEVE.IDEVENTO
		WHERE (NEVE.IDEVENTO LIKE '%ret%' OR NEVE.DESCRIPCION LIKE '%ret%')
		GROUP BY NEVE.IDEVENTO, NEVE.DESCRIPCION
		ORDER BY NEVE.IDEVENTO

		DECLARE RET_CURSOR CURSOR
		FOR
		SELECT ITEM, ID1 AS NUMDOC, STRINGGRANDE1 AS NOMBREEMPLEADO, ID2 AS FECHARETIRO
		FROM RPDX
		WHERE CNS = @CNSRPDX AND CANTIDAD10 = 0
		ORDER BY ITEM

		OPEN RET_CURSOR

		FETCH NEXT
		FROM RET_CURSOR
		INTO @ITEM, @NUMDOC, @NOMBREEMPLEADO, @FECHARETIRO

		WHILE @@FETCH_STATUS = 0
		BEGIN
			-- 'CAMBIANDO FECHA DE RETIRO DEL EMPLEADO'
			UPDATE NEMP
			SET FECHARETIRO = @FECHARETIRO
			WHERE NUMDOC = @NUMDOC

			-- 'AGREGANDO LA NOVEDAD DE RETIRO'
			INSERT INTO NEDIA (CNSPAGO, NUMDOC, FECHAINI, FECHAFIN, HORAS, MINUTOS, IDEVENTO, FACTOR, FORMALIQUIDACION, PRORROGA, DIAS, NDIAS, DCALEN, CNSMASIVO
				)
			SELECT @CNSPAGO, @NUMDOC, @FECHAINI, @FECHARETIRO, 0, 0, @IDEVENTO, @FACTOR, 'PorFecha', 0, 0, 0, 0, @CNSRPDX

			EXEC DBO.SPK_ADD_HISTORICO_NEMP @NUMDOC = @NUMDOC, @USUARIO = @USUARIO, @SYS_COMPUTERNAME = @SYS_COMPUTERNAME, @OPERACION = 'CAMBIA', @FECHAMOV = 
				@FECHARETIRO

			FETCH NEXT
			FROM RET_CURSOR
			INTO @ITEM, @NUMDOC, @NOMBREEMPLEADO, @FECHARETIRO
		END

		CLOSE RET_CURSOR

		DEALLOCATE RET_CURSOR

		SELECT 'OK' OK

		SELECT *
		INTO #RPDX_ELIMINADOS
		FROM RPDX
		WHERE CNS = @CNSRPDX AND CANTIDAD10 = 0;

		DELETE RPDX
		WHERE CNS = @CNSRPDX AND CANTIDAD10 = 0;

		SELECT ID1 AS NUMDOC
		FROM #RPDX_ELIMINADOS;

		RETURN
	END

	IF @METODO = 'LISTAR_EMPLEADOS_NOMINA'
	BEGIN
		SELECT @CODNOMINA = CODNOMINA
		FROM OPENJSON(@PARAMETROS) WITH (CODNOMINA VARCHAR(20) '$.CODNOMINA')

		SELECT 'OK' OK

		SELECT NEMP.NUMDOC, TER.RAZONSOCIAL, NEMP.DOCIDEMPLEADO, NEMP.FECHAINGRESO
		FROM NOMIE
		INNER JOIN NEMP ON NEMP.NUMDOC = NOMIE.NUMDOC
		INNER JOIN TER ON TER.IDTERCERO = NEMP.TERCEROID
		WHERE NEMP.ESTADO = 'ACTIVO' AND NOMIE.ESTADO = 'ACTIVO' AND NEMP.FECHARETIRO IS NULL AND NOMIE.CODNOMINA = @CODNOMINA
	END
END

