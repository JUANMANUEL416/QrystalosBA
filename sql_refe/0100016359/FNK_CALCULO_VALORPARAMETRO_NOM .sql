IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='FNK_CALCULO_VALORPARAMETRO_NOM' AND XTYPE='FN')
BEGIN
 DROP FUNCTION FNK_CALCULO_VALORPARAMETRO_NOM 
END

GO
CREATE FUNCTION DBO.FNK_CALCULO_VALORPARAMETRO_NOM(  
  @CODPARAMETRO VARCHAR(20),  
  @FECHAINI   DATETIME,  
  @FECHAFIN   DATETIME)   
RETURNS DECIMAL(14,5)  
AS    
BEGIN    
 DECLARE @VALOR DECIMAL(14,5)  
 SELECT TOP 1 @VALOR = VALOR FROM NPARV   
 WHERE CODPARAMETRO=@CODPARAMETRO AND FECHAFIN>=@FECHAFIN  
 ORDER BY FECHAFIN
 IF @VALOR IS NULL  
  SET @VALOR=0  
 RETURN(@VALOR)  
END  


