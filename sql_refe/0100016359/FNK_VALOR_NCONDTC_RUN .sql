IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='FNK_VALOR_NCONDTC_RUN' AND XTYPE='FN')
BEGIN
 DROP FUNCTION FNK_VALOR_NCONDTC_RUN 
END

GO
CREATE FUNCTION DBO.FNK_VALOR_NCONDTC_RUN(
    @NUMDOC      VARCHAR(20), 
    @CODCONCEPTO VARCHAR(20), 
    @ITEM        DECIMAL(14,0), 
    @FECHAINI    DATETIME, 
    @FECHAFIN    DATETIME, 
    @CNSPAGO     VARCHAR(20))  
RETURNS DECIMAL(15,6)
BEGIN  
 DECLARE @VALOR            DECIMAL(15,6)
 DECLARE @VALOR_CALCULO    DECIMAL(15,6)
 DECLARE @FACTOR           DECIMAL(15,6)
 DECLARE @OPERACION        VARCHAR(2)
 DECLARE @CODCONCEPTO_BASE VARCHAR(20)
 DECLARE @VALHORASLAB      SMALLINT
 DECLARE @HORAS_COMP        INT
 DECLARE @DIAS_LAB         INT
 DECLARE CUR_NCONDTC CURSOR FOR  
 SELECT CODCONCEPTO_BASE, FACTOR, OPERACION, ISNULL(VALHORASLAB,0), HORAS, DIAS
 FROM NCONDTC
 WHERE CODCONCEPTO=@CODCONCEPTO AND ITEM=@ITEM

 SET @VALOR = 0  

 OPEN CUR_NCONDTC

 FETCH NEXT FROM CUR_NCONDTC  
 INTO @CODCONCEPTO_BASE, @FACTOR, @OPERACION, @VALHORASLAB, @HORAS_COMP, @DIAS_LAB

 WHILE @@FETCH_STATUS = 0   
 BEGIN    

  IF @DIAS_LAB = 0
   SET @DIAS_LAB = NULL

  SET @VALOR_CALCULO = 0
  SELECT @VALOR_CALCULO = ISNULL(V.VALOR_EMPLEADO,0) * ISNULL(@FACTOR,0)   
  FROM FNK_VALORCONCEPTO_NEMPFD_RUN(@NUMDOC, @CODCONCEPTO_BASE, @FECHAINI, @FECHAFIN, @CNSPAGO, @VALHORASLAB, @HORAS_COMP, @DIAS_LAB) AS V  

  SET @VALOR =  
  CASE @OPERACION  
   WHEN '+' THEN @VALOR + @VALOR_CALCULO  
   WHEN '-' THEN @VALOR - @VALOR_CALCULO  
   WHEN '*' THEN @VALOR * @VALOR_CALCULO   
   WHEN '/' THEN @VALOR / @VALOR_CALCULO  
  END  
  FETCH NEXT FROM CUR_NCONDTC  
  INTO @CODCONCEPTO_BASE, @FACTOR, @OPERACION, @VALHORASLAB, @HORAS_COMP, @DIAS_LAB  
 END  
 CLOSE CUR_NCONDTC
 DEALLOCATE CUR_NCONDTC
 RETURN @VALOR
END


