CREATE OR ALTER PROCEDURE DBO.SPK_LIQUIDAR_NOMI_NEMP
@COMPANIA         VARCHAR(2), 
@SEDE             VARCHAR(5),
@CODNOMINA        VARCHAR(2),
@ANO              VARCHAR(4), 
@MES              VARCHAR(2), 
@CODPAGO          VARCHAR(5),
@USUARIO          VARCHAR(12),
@SYS_COMPUTERNAME VARCHAR(255),
@CNSPAGO          VARCHAR(20),
@NUMDOC           VARCHAR(20)
WITH ENCRYPTION
AS
DECLARE @CNSNIEPE         VARCHAR(20)
DECLARE @FECHAINI         DATETIME
DECLARE @FECHAFIN         DATETIME
BEGIN
    SELECT @FECHAINI=FECHAINI,@FECHAFIN=FECHAFIN FROM NPER WHERE CNSPAGO=@CNSPAGO  

    DELETE NIEPED FROM NIEPE
    WHERE NIEPE.CNSNIEPE=NIEPED.CNSNIEPE AND NIEPE.CNSPAGO=@CNSPAGO AND NIEPE.NUMDOC=@NUMDOC

    DELETE NIEPE WHERE NIEPE.CNSPAGO=@CNSPAGO AND NIEPE.NUMDOC=@NUMDOC

    SET @CNSNIEPE=SPACE(20)
    EXEC SPK_GENCONSECUTIVO @COMPANIA,@SEDE,'@NIEPE',@CNSNIEPE OUTPUT   
    SELECT @CNSNIEPE = @SEDE + REPLACE(SPACE(8 - LEN(@CNSNIEPE))+LTRIM(RTRIM(@CNSNIEPE)),SPACE(1),0)

    INSERT INTO NIEPE(CNSPAGO,CNSNIEPE,COMPANIA,CODNOMINA,ANO,MES,CODPAGO,NOMBRE_PERIODO,NUMDOC,NOMBRE_EMPLEADO,
	            IDAREA,NOMBRE_AREA,CCOSTO,NOMBRE_CCOSTO,CODCARGO,NOMBRE_CARGO,NIVEL,GRADO,DETALLE_CARGO,
                    BASICO,VALOR_NETO,VALOR_INGRESOS,VALOR_EGRESOS,VALOR_APORTES,TOTAL_NOMINA,FECHA,USUARIO,
                    SYS_COMPUTERNAME,CERRADO,GENERADO,PAGADO,ITEM,IDSEDE,CODUNG)
    SELECT @CNSPAGO,@CNSNIEPE,COMPANIA,CODNOMINA,ANO,MES,CODPAGO,NOMBRE_PERIODO,NUMDOC,NOMBRE_EMPLEADO,
        IDAREA,NOMBRE_AREA,CCOSTO,NOMBRE_CCOSTO,CODCARGO,NOMBRE_CARGO,NIVEL,GRADO,DETALLE_CARGO,
        BASICO,0,0,0,0,0,DBO.FNK_FECHA_SIN_MLS(GETDATE()),
        USUARIO,SYS_COMPUTERNAME,CERRADO,GENERADO,0,ROW_NUMBER() OVER(ORDER BY NUMDOC ASC) AS Item,IDSEDE,CODUNG
    FROM FNK_LIQUIDAR_NOMI_NEMP(@COMPANIA,@CODNOMINA,@ANO,@MES,@CODPAGO,@USUARIO,@SYS_COMPUTERNAME,@CNSPAGO, @NUMDOC)
    GROUP BY COMPANIA,CODNOMINA,ANO,MES,CODPAGO,NOMBRE_PERIODO,NUMDOC,NOMBRE_EMPLEADO,IDAREA,NOMBRE_AREA,CODCARGO,
            BASICO,NOMBRE_CARGO,NIVEL,GRADO,USUARIO,SYS_COMPUTERNAME,CERRADO,GENERADO,CCOSTO,NOMBRE_CCOSTO,
            DETALLE_CARGO,IDSEDE,CODUNG

    DBCC CHECKIDENT (NIEPED, RESEED, 0)
    INSERT INTO NIEPED(CNSNIEPE,NUMDOC,CODCONCEPTO,NOMBRE_CONCEPTO,DETALLE,CANTIDAD,TIPO,VALOR,VALOR_APORTES,TOTAL_NOMINA,
                    VALOR100P,CVALOR100P,BASE_PRESTACIONES,INFO,CODPRF,NOMBRE_PRF,IDTERCERO_PRF,RAZONSOCIAL_PRF,
                    PAGO_NOMI,PAGO_PRF,SEIMPRIME,IDTRANSPRESTAMO,NUMDOCPRESTAMO,NUMCUOTA,CODFINANCIACION,CNSLIQRET)
    SELECT @CNSNIEPE,NUMDOC,CODCONCEPTO,NOMBRE_CONCEPTO,DETALLE,CANTIDAD,TIPO,VALOR,VALOR_APORTES,TOTAL_NOMINA,
        VALOR100P,CVALOR100P,BASE_PRESTACIONES,INFO,CODPRF,NOMBRE_PRF,IDTERCERO_PRF,RAZONSOCIAL_PRF,0,0,SEIMPRIME,
        IDTRANSPRESTAMO,NUMDOCPRESTAMO,NUMCUOTA,CODFINANCIACION,CNSLIQRET
    FROM FNK_LIQUIDAR_NOMI_NEMP(@COMPANIA,@CODNOMINA,@ANO,@MES,@CODPAGO,@USUARIO,@SYS_COMPUTERNAME,@CNSPAGO, @NUMDOC)
    ORDER BY NUMDOC, LINEA

    UPDATE NIEPE SET
	VALOR_INGRESOS = ISNULL((SELECT SUM(VALOR) FROM NIEPED WHERE CNSNIEPE=@CNSNIEPE AND NIEPE.NUMDOC=NIEPED.NUMDOC AND TIPO='Ingreso' AND INFO='No'),0), 
	VALOR_EGRESOS  = ISNULL((SELECT SUM(VALOR) FROM NIEPED WHERE CNSNIEPE=@CNSNIEPE AND NIEPE.NUMDOC=NIEPED.NUMDOC AND TIPO='Egreso' AND INFO='No'),0),
	VALOR_APORTES  = ISNULL((SELECT SUM(VALOR_APORTES) FROM NIEPED WHERE CNSNIEPE=@CNSNIEPE AND NIEPE.NUMDOC=NIEPED.NUMDOC AND INFO='No'),0),
	TOTAL_NOMINA   = 0
    WHERE CNSNIEPE=@CNSNIEPE AND NUMDOC=@NUMDOC

    UPDATE NIEPE SET VALOR_NETO=VALOR_INGRESOS-VALOR_EGRESOS WHERE CNSNIEPE=@CNSNIEPE AND NUMDOC=@NUMDOC
    UPDATE NIEPE SET TOTAL_NOMINA = VALOR_NETO + VALOR_EGRESOS + VALOR_APORTES WHERE CNSNIEPE=@CNSNIEPE AND NUMDOC=@NUMDOC

    --LIQUIDACION PAGOS X TERCERO
    DELETE NPERPD WHERE CNSPAGO=@CNSPAGO
    DELETE NPERP WHERE CNSPAGO=@CNSPAGO

    INSERT INTO NPERP (CNSPAGO,CODPRF,PAGO,TOTAL_PARAFISCALES)
    SELECT NIEPE.CNSPAGO,NIEPED.CODPRF,'No',SUM(NIEPED.TOTAL_NOMINA)
    FROM NIEPE INNER JOIN 
        NIEPED ON NIEPE.CNSNIEPE=NIEPED.CNSNIEPE AND NIEPE.NUMDOC=NIEPED.NUMDOC LEFT JOIN
        NPRF ON NIEPED.CODPRF = NPRF.CODPRF LEFT JOIN
        TER ON NIEPED.IDTERCERO_PRF = TER.IDTERCERO
    WHERE NIEPE.CNSPAGO=@CNSPAGO AND NIEPED.INFO='No' AND NIEPED.TOTAL_NOMINA<>0 AND
        NOT NPRF.CODPRF IS NULL AND NOT TER.IDTERCERO IS NULL
    GROUP BY NIEPE.CNSPAGO,NIEPED.CODPRF 

    INSERT INTO NPERPD (CNSPAGO,CODPRF,IDTERCERO,PAGADO,FECHA_PAGO,TOTAL_PARAFISCALES,NROCOMPROBANTE,CONTABILIZADA,COMPROBANTE,NOREFERENCIA)
    SELECT NIEPE.CNSPAGO,NIEPED.CODPRF,NIEPED.IDTERCERO_PRF,'No',NULL,
    CASE WHEN NPRF.CLASE='Salario' THEN MAX(NIEPE.valor_neto) ELSE SUM(NIEPED.TOTAL_NOMINA) END,'' ,0 ,NULL ,NULL
    FROM NIEPE INNER JOIN 
        NIEPED ON NIEPE.CNSNIEPE=NIEPED.CNSNIEPE AND NIEPE.NUMDOC=NIEPED.NUMDOC LEFT JOIN
        NPRF ON NIEPED.CODPRF = NPRF.CODPRF LEFT JOIN
        TER ON NIEPED.IDTERCERO_PRF = TER.IDTERCERO
    WHERE NIEPE.CNSPAGO=@CNSPAGO AND NIEPED.INFO='No' AND NIEPED.TOTAL_NOMINA<>0 AND
        NOT NPRF.CODPRF IS NULL AND NOT TER.IDTERCERO IS NULL 
    GROUP BY NIEPE.CNSPAGO,NIEPED.CODPRF,NIEPED.IDTERCERO_PRF, NPRF.CLASE

    --CALCULO FINAL DE NOMINA
    PRINT 'Actualiza valores de NPER'
    UPDATE NPER SET 
	GENERADO           = 1, 
	TOTAL_INGRESOS     = CASE WHEN V.TOTAL_INGRESOS IS NULL THEN 0 ELSE V.TOTAL_INGRESOS END, 
        TOTAL_EGRESOS      = CASE WHEN V.TOTAL_EGRESOS IS NULL THEN 0 ELSE V.TOTAL_EGRESOS END,  
        TOTAL_APORTES      = CASE WHEN V.TOTAL_APORTES IS NULL THEN 0 ELSE V.TOTAL_APORTES END,
	TOTAL_PARAFISCALES = CASE WHEN P.TOTAL_PARAFISCALES IS NULL THEN 0 ELSE P.TOTAL_PARAFISCALES END
    FROM NPER,
        (SELECT SUM(VALOR_INGRESOS) AS TOTAL_INGRESOS,SUM(VALOR_EGRESOS) AS TOTAL_EGRESOS,
        SUM(VALOR_APORTES) AS TOTAL_APORTES FROM NIEPE WHERE CNSPAGO=@CNSPAGO) V,
        (SELECT SUM(TOTAL_PARAFISCALES) AS TOTAL_PARAFISCALES
        FROM NPERP INNER JOIN NPRF ON NPRF.CODPRF=NPERP.CODPRF WHERE NPERP.CNSPAGO=@CNSPAGO AND NPRF.CLASE='Parafiscal') P
    WHERE CNSPAGO=@CNSPAGO

    UPDATE NPER SET TOTAL_NOMINA=TOTAL_INGRESOS+TOTAL_APORTES+TOTAL_PARAFISCALES 
    WHERE CNSPAGO=@CNSPAGO

    PRINT 'CONTROL DE CONCEPTOS QUE TIENEN RECOBROS'

    UPDATE NIEPED SET RECOBRO=1,IDTERCERO_RECO=RECO.IDTERCERO
    FROM NIEPED INNER JOIN (SELECT NEDIA.CNSPAGO,NEDIA.NUMDOC,NCOND.CODCONCEPTO,NEDIA.IDTERCERO
                            FROM NEDIA 
                                INNER JOIN NEVE ON NEDIA.IDEVENTO=NEVE.IDEVENTO
                                INNER JOIN NCOND ON NEVE.CODCONCEPTO=NCOND.CODCONCEPTO 
                            WHERE NEDIA.CNSPAGO=@CNSPAGO AND NEDIA.NUMDOC=@NUMDOC AND COALESCE(NEDIA.RECOBRO,0)=1 
                            ) RECO  ON NIEPED.NUMDOC=RECO.NUMDOC AND NIEPED.CODCONCEPTO=RECO.CODCONCEPTO
    WHERE NIEPED.CNSNIEPE=@CNSNIEPE AND NIEPED.NUMDOC=@NUMDOC
   
    DELETE NIEPER WHERE CNSPAGO=@CNSPAGO AND NUMDOC=@NUMDOC
 
    INSERT INTO NIEPER (CNSPAGO, NUMDOC, CODCONCEPTO, TOTAL_NOMINA, IDTERCERO_PRF, ESTADO, VLRPAGO, USUARIOP, DESCRIPCION)
    SELECT @CNSPAGO,NIEPE.NUMDOC,NIEPED.CODCONCEPTO,NIEPED.TOTAL_NOMINA,NIEPED.IDTERCERO_RECO,'Nuevo',0,NULL,NULL
    FROM NIEPE INNER JOIN NIEPED ON NIEPE.CNSNIEPE=NIEPED.CNSNIEPE AND NIEPE.NUMDOC=NIEPED.NUMDOC
    WHERE NIEPE.CNSPAGO=@CNSPAGO  AND NIEPE.NUMDOC=@NUMDOC AND COALESCE(NIEPED.RECOBRO,0)=1

    PRINT 'PARA CAMBIO DE TERCERO AL ENVIAR A CONTABILIDAD .. CONCEPTOS COMO RETENCION, DECUCCIONES O SERVICIOS AL EMPLEADO'

    UPDATE NIEPED SET RECOBRO=1 
    FROM NIEPED INNER JOIN NCOND ON NIEPED.CODCONCEPTO=NCOND.CODCONCEPTO 
                INNER JOIN NCON ON NCOND.CODCONCEPTO=NCON.CODCONCEPTO AND NIEPED.CODCONCEPTO=NCON.CODCONCEPTO
    WHERE NIEPED.CNSNIEPE=@CNSNIEPE AND NIEPED.NUMDOC=@NUMDOC AND NCON.TIPO='Egreso' AND NCOND.RECOBRO=1

END

