IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME='SPK_CALCULAR_NEMPF' AND XTYPE='P')
BEGIN
   DROP PROCEDURE SPK_CALCULAR_NEMPF
END
GO
CREATE PROCEDURE DBO.SPK_CALCULAR_NEMPF
@CNSPAGO VARCHAR(20),   
@NUMDOC   VARCHAR(20)
WITH ENCRYPTION
AS
DECLARE @PTOPE	DECIMAL(14,6)
BEGIN
   SELECT @PTOPE = NOMI.MAXADEDUCIR
   FROM NPER INNER JOIN NOMI ON NPER.CNSPAGO=@CNSPAGO AND NPER.CODNOMINA=NOMI.CODNOMINA
   IF @PTOPE IS NULL
      SET @PTOPE=0
   
   UPDATE NEMPF 
   SET    VALOR_NETO	        = ISNULL(V.INGRESOS,0)-ISNULL(V.EGRESOS,0),
          VALOR_INGRESOS     = ISNULL(V.INGRESOS,0),
          VALOR_EGRESOS      = ISNULL(V.EGRESOS,0),
          VALOR_APORTES	     = ISNULL(V.APORTES,0),
          VALOR_INGRESOS100P = ISNULL(V.INGRESOS100P,0),
          PEGRESOS           = CASE WHEN ISNULL(V.INGRESOS,0)=0 THEN 0 ELSE (ISNULL(V.EGRESOS,0)*100)/ISNULL(V.INGRESOS,0) END,
          PLIBRE_EGRESOS     = CASE WHEN ISNULL(V.INGRESOS,0)=0 THEN 0 ELSE @PTOPE-((ISNULL(V.EGRESOS,0)*100)/ISNULL(V.INGRESOS,0)) END
   FROM   NEMPF LEFT JOIN (
                            SELECT A.CNSPAGO, A.NUMDOC, A.ITEM, 
                                   INGRESOS=SUM(A.INGRESOS), EGRESOS=SUM(A.EGRESOS), APORTES=SUM(A.APORTES), INGRESOS100P=SUM(A.INGRESOS100P) 
                            FROM   ( SELECT NEMPFD.CNSPAGO, NEMPFD.NUMDOC, NEMPFD.ITEM,
                                         INGRESOS = CASE WHEN NCON.TIPO='Ingreso' AND NEMPFD.LIQUIDAR='Si' AND NEMPFD.INFO='No' THEN SUM(NEMPFD.VALOR) ELSE 0 END,
                                         EGRESOS  = CASE WHEN NCON.TIPO='Egreso'  AND NEMPFD.LIQUIDAR='Si' AND NEMPFD.INFO='No' THEN SUM(NEMPFD.VALOR) ELSE 0 END,
                                         APORTES  = CASE WHEN NEMPFD.LIQUIDAR='Si' AND NEMPFD.INFO='No' THEN SUM(NEMPFD.VALOR_EMPRESA) ELSE 0 END,
                                         INGRESOS100P = CASE WHEN NCON.TIPO='Ingreso' AND NEMPFD.LIQUIDAR='Si' AND NEMPFD.INFO='No' THEN SUM(NEMPFD.VALOR100P) ELSE 0 END
                                    FROM NEMPFD INNER JOIN NCON ON NEMPFD.CODCONCEPTO=NCON.CODCONCEPTO AND NEMPFD.CNSPAGO=@CNSPAGO AND 
                                         NEMPFD.NUMDOC = (SELECT CASE WHEN @NUMDOC='' THEN NEMPFD.NUMDOC ELSE @NUMDOC END)
                                    GROUP BY NEMPFD.CNSPAGO, NEMPFD.NUMDOC, NEMPFD.ITEM, NCON.TIPO, NEMPFD.LIQUIDAR, NEMPFD.INFO
                                   ) AS A 
                            GROUP BY A.CNSPAGO, A.NUMDOC, A.ITEM
                          ) AS V ON NEMPF.CNSPAGO = V.CNSPAGO 
                                AND NEMPF.NUMDOC  = V.NUMDOC 
                                AND NEMPF.ITEM    = V.ITEM
   WHERE  NEMPF.CNSPAGO = @CNSPAGO 
   AND    NEMPF.NUMDOC  = (SELECT CASE WHEN @NUMDOC='' THEN NEMPF.NUMDOC ELSE @NUMDOC END)

   UPDATE NEMPFD 
   SET    PSOBREINGRESOS = V.PORCENTAJE
   FROM   NEMPFD INNER JOIN  (
                             SELECT A.CNSPAGO, A.NUMDOC, A.ITEM, A.CODCONCEPTO, A.LINEA, 
                                    PORCENTAJE = CASE WHEN B.VALOR_INGRESOS<>0 AND NOT B.VALOR_INGRESOS IS NULL THEN (A.VALOR*100)/B.VALOR_INGRESOS ELSE 0 END
                             FROM   NEMPFD A INNER JOIN NEMPF B ON A.CNSPAGO = B.CNSPAGO 
                                                               AND A.NUMDOC  = B.NUMDOC 
                                                               AND A.ITEM    = B.ITEM 
                                                               AND A.CNSPAGO = @CNSPAGO 
                                                               AND A.NUMDOC  = (SELECT CASE WHEN @NUMDOC='' THEN A.NUMDOC ELSE @NUMDOC END)
                            ) AS V ON NEMPFD.CNSPAGO     = V.CNSPAGO 
                                  AND NEMPFD.NUMDOC      = V.NUMDOC 
                                  AND NEMPFD.ITEM        = V.ITEM 
                                  AND NEMPFD.CODCONCEPTO = V.CODCONCEPTO 
                                  AND NEMPFD.LINEA       = V.LINEA 
                                  AND NEMPFD.INFO        = 'No'
END


