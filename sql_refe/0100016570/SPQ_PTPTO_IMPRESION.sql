CREATE OR ALTER PROCEDURE DBO.SPQ_PTPTO_IMPRESION @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
SET DATEFORMAT dmy
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE  @PARAMETROS NVARCHAR(MAX)			  ,@MODELO VARCHAR(100)			    ,@METODO VARCHAR(100)
		,@USUARIO VARCHAR(12)			   	  ,@COMPANIA VARCHAR(2)		        ,@IDSEDE VARCHAR(5)		
        ,@SYS_COMPUTERNAME VARCHAR(200)       ,@DATOS    VARCHAR(MAX)
        ,@PTABLA VARCHAR(20)                  ,@CNSMOV   VARCHAR(20)            ,@PTPTO VARCHAR(20)
        ,@PTCDP VARCHAR(20)                   ,@PTRP VARCHAR(20)                ,@PTCXP VARCHAR(20)
        ,@PTPAG VARCHAR(20)                   ,@RECO VARCHAR(20)                ,@RECA VARCHAR(20)
        ,@CONSECUTIVO1 VARCHAR(20)            ,@CONSECUTIVO2 VARCHAR(20)        ,@CONSECUTIVO3 VARCHAR(20)
        ,@CDP_ARBOL VARCHAR(21)               ,@RP_ARBOL VARCHAR(20)            ,@NIVEL_MINIMO INT
        ,@CONSECUTIVO_ARBOL  VARCHAR(20)      ,@NIVELR INT                      ,@SOLO_DETALLE BIT
BEGIN
	SELECT *
	INTO #JSON
	FROM OPENJSON(@json) WITH (
			MODELO VARCHAR(100) '$.MODELO'
			,METODO VARCHAR(100) '$.METODO'
			,USUARIO VARCHAR(12) '$.USUARIO'
			,PARAMETROS NVARCHAR(MAX) AS JSON
	)

	SELECT   @MODELO = MODELO			,@METODO = METODO
			,@PARAMETROS = PARAMETROS	,@USUARIO = USUARIO
	FROM #JSON

   IF @METODO='PPTO_PROCESOS'     
   BEGIN                        
      SELECT @PTABLA=PTABLA,@CNSMOV=CONSECUTIVO,@PTPTO=PTPTO,@COMPANIA=COMPANIA,@CONSECUTIVO1=CONSECUTIVO1,@CONSECUTIVO2=CONSECUTIVO2,@CONSECUTIVO3=CONSECUTIVO3     
      FROM   OPENJSON (@PARAMETROS)
      WITH   (  
      PTABLA  VARCHAR(20)   '$.TABLA',
      CONSECUTIVO  VARCHAR(20)   '$.CONSECUTIVO',
      CONSECUTIVO1  VARCHAR(20)   '$.CONSECUTIVO1',
      CONSECUTIVO2  VARCHAR(20)   '$.CONSECUTIVO2',
      CONSECUTIVO3  VARCHAR(20)   '$.CONSECUTIVO3',
      PTPTO  VARCHAR(20)   '$.PTPTO',
      COMPANIA  VARCHAR(20)   '$.COMPANIA'
      )  
      SELECT 'OK' OK
      IF @PTABLA='PTMOV' 
      BEGIN
         PRINT 'INGRESO A PTMOV'
         SELECT CONSECUTIVO,CNSMOV,RESOLUCION,DBO.FNK_FECHA_DDMMAA(FECHAMOV) FECHAMOV,DETALLE,@USUARIO USUARIO
         FROM PTMOV 
         WHERE CONSECUTIVO=@PTPTO 
         AND CNSMOV=@CNSMOV
         
         SELECT  PTMOVD.CLASEMOV,PTMOVD.CLASE,PTMOVD.RUBRO,PTRUB.NOMRUBRO,PTMOVD.RECURSO,PTREC.DESCRIPCION,
         CASE WHEN PTMOVD.TIPOMOV='DB' THEN PTMOVD.VALOR ELSE 0 END DEBITO, CASE WHEN PTMOVD.TIPOMOV='CR' THEN PTMOVD.VALOR ELSE 0 END CREDITO
         FROM PTMOVD INNER JOIN PTRUB ON PTMOVD.RUBRO_ID=PTRUB.RUBRO_ID
                     LEFT  JOIN PTREC ON PTMOVD.RECURSO=PTREC.RECURSO
         WHERE CNSMOV=@CNSMOV
         AND PTMOVD.CLASE='Ingreso'
         ORDER BY PTMOVD.TIPOMOV

         SELECT PTMOVD.CLASEMOV,PTMOVD.CLASE,PTMOVD.RUBRO,PTRUB.NOMRUBRO,PTMOVD.RECURSO,PTREC.DESCRIPCION,
         CASE WHEN PTMOVD.TIPOMOV='DB' THEN PTMOVD.VALOR ELSE 0 END DEBITO, CASE WHEN PTMOVD.TIPOMOV='CR' THEN PTMOVD.VALOR ELSE 0 END CREDITO
         FROM PTMOVD INNER JOIN PTRUB ON PTMOVD.RUBRO_ID=PTRUB.RUBRO_ID
                     LEFT  JOIN PTREC ON PTMOVD.RECURSO=PTREC.RECURSO
         WHERE CNSMOV=@CNSMOV
         AND PTMOVD.CLASE='Gasto'
         ORDER BY PTMOVD.TIPOMOV

      END
      IF @PTABLA='PTRECO'
      BEGIN
         PRINT 'INGRESO A PTRECO'
         SELECT CONSECUTIVO,RECO,NIT,TER.DV,RAZONSOCIAL,DBO.FNK_FECHA_DDMMAA(PTRECO.FECHA) FECHA,PTRECO.OBJETIVO,@USUARIO USUARIO
         FROM PTRECO INNER JOIN TER ON PTRECO.IDTERCERO=TER.IDTERCERO
         WHERE CONSECUTIVO=@PTPTO 
         AND RECO=@CNSMOV         
         AND PTRECO.CONSECUTIVO=@PTPTO
         AND PTRECO.COMPANIA=@COMPANIA

         SELECT PTRUB.RUBRO,PTRUB.NOMRUBRO,PTRUB.RECURSO,PTREC.DESCRIPCION,PTRECOD.VALOR,PTRECOD.SALDO
         FROM PTRECO INNER JOIN PTRECOD ON PTRECO.COMPANIA=PTRECOD.COMPANIA AND PTRECO.CONSECUTIVO=PTRECOD.CONSECUTIVO AND PTRECO.RECO=PTRECOD.RECO
                     INNER JOIN PTRUB ON PTRECOD.RUBRO_ID=PTRUB.RUBRO_ID
                     INNER JOIN PTREC ON PTRUB.RECURSO=PTREC.RECURSO
         WHERE PTRECO.CONSECUTIVO=@PTPTO 
         AND PTRECO.RECO=@CNSMOV         
         AND PTRECO.CONSECUTIVO=@PTPTO
         AND PTRECO.COMPANIA=@COMPANIA

      END
      IF @PTABLA='PTRECA'
      BEGIN
         PRINT 'INGRESO A PTRECA'
         SELECT CONSECUTIVO,RECO,NIT,TER.DV,RAZONSOCIAL,DBO.FNK_FECHA_DDMMAA(PTRECO.FECHA) FECHA,PTRECO.OBJETIVO,@USUARIO USUARIO
         FROM PTRECO INNER JOIN TER ON PTRECO.IDTERCERO=TER.IDTERCERO
         WHERE CONSECUTIVO=@PTPTO 
         AND RECO=@CNSMOV         
         AND PTRECO.CONSECUTIVO=@PTPTO
         AND PTRECO.COMPANIA=@COMPANIA

         SELECT PTRUB.RUBRO,PTRUB.NOMRUBRO,PTRUB.RECURSO,PTREC.DESCRIPCION,PTRECAD.VALOR
         FROM PTRECA INNER JOIN PTRECAD ON PTRECA.COMPANIA=PTRECAD.COMPANIA AND PTRECA.CONSECUTIVO=PTRECAD.CONSECUTIVO AND PTRECA.RECO=PTRECAD.RECO AND PTRECA.CNSPAGO=PTRECAD.CNSPAGO
                     INNER JOIN PTRUB ON PTRECAD.RUBRO_ID=PTRUB.RUBRO_ID
                     INNER JOIN PTREC ON PTRUB.RECURSO=PTREC.RECURSO
         WHERE PTRECA.CONSECUTIVO=@PTPTO 
         AND PTRECA.RECO=@CNSMOV    
         AND PTRECA.CNSPAGO=@CONSECUTIVO1
         AND PTRECA.CONSECUTIVO=@PTPTO
         AND PTRECA.COMPANIA=@COMPANIA
      END
      IF @PTABLA='PTCDP'
      BEGIN
         PRINT 'INGRESO A PTRECA'
         SELECT CONSECUTIVO,CDP,DBO.FNK_FECHA_DDMMAA(PTCDP.FECHAEXPEDICION) FECHA,DBO.FNK_FECHA_DDMMAA(PTCDP.FECHAREINTEGRO)FECHAREINTEGRO,PTCDP.OBJETIVO,@USUARIO USUARIO
         FROM PTCDP 
         WHERE PTCDP.CONSECUTIVO=@PTPTO 
         AND PTCDP.CDP=@CNSMOV         
         AND PTCDP.COMPANIA=@COMPANIA

         SELECT PTRUB.RUBRO,PTRUB.NOMRUBRO,PTRUB.RECURSO,PTCDPD.IDTIPOMOV,PTCDPD.VIGENCIA,PTREC.DESCRIPCION,PTCDPD.VALOR,PTCDPD.SALDO
         FROM PTCDP INNER JOIN PTCDPD ON PTCDP.COMPANIA=PTCDPD.COMPANIA AND PTCDP.CONSECUTIVO=PTCDPD.CONSECUTIVO AND PTCDP.CDP=PTCDPD.CDP 
                     INNER JOIN PTRUB ON PTCDPD.RUBRO_ID=PTRUB.RUBRO_ID
                     INNER JOIN PTREC ON PTRUB.RECURSO=PTREC.RECURSO
         WHERE PTCDP.CONSECUTIVO=@PTPTO 
         AND PTCDP.CDP=@CNSMOV    
         AND PTCDP.COMPANIA=@COMPANIA
      END
      IF @PTABLA='PTRP'
      BEGIN
         PRINT 'INGRESO A PTCRP'
         SELECT PTRP.CONSECUTIVO,PTRP.CDP,PTRP.RP,DBO.FNK_FECHA_DDMMAA(PTCDP.FECHAEXPEDICION) FECHAEXPEDICION,DBO.FNK_FECHA_DDMMAA(PTCDP.FECHAREINTEGRO) FECHAVENCE,
               DBO.FNK_FECHA_DDMMAA(PTRP.FECHARP)FECHA,DBO.FNK_FECHA_DDMMAA(PTRP.FECHAPLAZO)FECHAPLAZO,PTRP.OBJETIVO,@USUARIO USUARIO,
               TER.TIPO_ID,TER.NIT,TER.DV,TER.RAZONSOCIAL,PTRP.NODOCUMENTO AS NCONTRATO
         FROM PTRP INNER JOIN PTCDP ON PTRP.COMPANIA=PTCDP.COMPANIA AND PTRP.CONSECUTIVO=PTCDP.CONSECUTIVO AND PTRP.CDP=PTCDP.CDP
                   INNER JOIN TER ON PTRP.IDTERCERO=TER.IDTERCERO
         WHERE PTRP.CONSECUTIVO=@PTPTO 
         AND PTRP.CDP= @CONSECUTIVO1        
         AND PTRP.RP= @CNSMOV
         AND PTRP.COMPANIA=@COMPANIA

         SELECT PTRUB.RUBRO,PTRUB.NOMRUBRO,PTRUB.RECURSO,PTCDPD.IDTIPOMOV,PTCDPD.VIGENCIA,PTREC.DESCRIPCION,PTRPD.VALOR,PTRPD.SALDO
         FROM PTRP INNER JOIN PTRPD ON PTRP.COMPANIA=PTRPD.COMPANIA AND PTRP.CONSECUTIVO=PTRPD.CONSECUTIVO AND PTRP.CDP=PTRPD.CDP AND PTRP.RP=PTRPD.RP
                   INNER JOIN PTCDPD ON PTRPD.COMPANIA=PTCDPD.COMPANIA AND PTRPD.CONSECUTIVO=PTCDPD.CONSECUTIVO AND PTRPD.CDP=PTCDPD.CDP AND PTRPD.ITEMCDPD=PTCDPD.ITEM
                     INNER JOIN PTRUB ON PTCDPD.RUBRO_ID=PTRUB.RUBRO_ID
                     INNER JOIN PTREC ON PTRUB.RECURSO=PTREC.RECURSO
         WHERE PTRP.CONSECUTIVO=@PTPTO 
         AND PTRP.CDP= @CONSECUTIVO1        
         AND PTRP.RP= @CNSMOV
         AND PTRP.COMPANIA=@COMPANIA
      END 
      IF @PTABLA='PTCXP'
      BEGIN
         PRINT 'INGRESO A PTCXP'
         /* JSON: CONSECUTIVO=CDP (@CNSMOV), CONSECUTIVO1=RP, CONSECUTIVO2=CNSCXP, PTPTO=consecutivo proceso */
         SELECT PTRP.CONSECUTIVO, PTRP.CCOSTO, PTRP.CDP,PTRP.RP,PTCXP.CNSCXP,DBO.FNK_FECHA_DDMMAA(PTCDP.FECHAEXPEDICION) FECHAEXPEDICION,DBO.FNK_FECHA_DDMMAA(PTCDP.FECHAREINTEGRO) FECHAVENCE,
               DBO.FNK_FECHA_DDMMAA(PTRP.FECHARP)FECHA,DBO.FNK_FECHA_DDMMAA(PTRP.FECHAPLAZO)FECHAPLAZO,PTRP.OBJETIVO,@USUARIO USUARIO,
               TER.TIPO_ID,TER.NIT,TER.DV,TER.RAZONSOCIAL,PTRP.NODOCUMENTO AS NCONTRATO
         FROM PTCXP INNER JOIN  PTRP  ON PTCXP.COMPANIA=PTRP.COMPANIA AND PTCXP.CONSECUTIVO=PTRP.CONSECUTIVO AND PTCXP.CDP=PTRP.CDP AND PTCXP.RP=PTRP.RP
                   INNER JOIN PTCDP ON PTRP.COMPANIA=PTCDP.COMPANIA AND PTRP.CONSECUTIVO=PTCDP.CONSECUTIVO AND PTRP.CDP=PTCDP.CDP
                   INNER JOIN TER ON PTRP.IDTERCERO=TER.IDTERCERO
         WHERE PTCXP.COMPANIA=@COMPANIA
         AND PTCXP.CONSECUTIVO=@PTPTO
         AND PTCXP.CDP=@CNSMOV
         AND PTCXP.RP=@CONSECUTIVO1
         AND PTCXP.CNSCXP=@CONSECUTIVO2


         SELECT PTRUB.RUBRO,PTRUB.NOMRUBRO,PTRUB.RECURSO,PTCDPD.IDTIPOMOV,PTCDPD.VIGENCIA,PTREC.DESCRIPCION,PTCXPD.VALOR,PTCXPD.SALDO
         FROM PTCXP INNER JOIN PTCXPD ON PTCXP.COMPANIA=PTCXPD.COMPANIA AND PTCXP.CONSECUTIVO=PTCXPD.CONSECUTIVO AND PTCXP.CDP=PTCXPD.CDP AND PTCXP.RP=PTCXPD.RP AND PTCXP.CNSCXP=PTCXPD.CNSCXP
                     INNER JOIN PTCDPD ON PTCXPD.COMPANIA=PTCDPD.COMPANIA AND PTCXPD.CONSECUTIVO=PTCDPD.CONSECUTIVO AND PTCXPD.CDP=PTCDPD.CDP AND PTCXPD.ITEMCDPD=PTCDPD.ITEM
                     INNER JOIN PTRUB ON PTCDPD.RUBRO_ID=PTRUB.RUBRO_ID
                     INNER JOIN PTREC ON PTRUB.RECURSO=PTREC.RECURSO
         WHERE PTCXP.COMPANIA=@COMPANIA
         AND PTCXP.CONSECUTIVO=@PTPTO
         AND PTCXP.CDP=@CNSMOV
         AND PTCXP.RP=@CONSECUTIVO1
         AND PTCXP.CNSCXP=@CONSECUTIVO2
      END 
      IF @PTABLA='PTPAG'
      BEGIN
         PRINT 'INGRESO A PTPAG'
         /* Cabecera: PTPAG + RP/CDP/tercero. CONSECUTIVO3 JSON = CNSPAGO; PTPTO = consecutivo proceso */
         SELECT PTRP.CONSECUTIVO,PTRP.CDP,PTRP.RP,PTPAG.CNSCXP,PTPAG.CNSPAGO,
               DBO.FNK_FECHA_DDMMAA(PTCDP.FECHAEXPEDICION) FECHAEXPEDICION,DBO.FNK_FECHA_DDMMAA(PTCDP.FECHAREINTEGRO) FECHAVENCE,
               DBO.FNK_FECHA_DDMMAA(PTPAG.FECHA) FECHA,DBO.FNK_FECHA_DDMMAA(PTRP.FECHARP) FECHARP,DBO.FNK_FECHA_DDMMAA(PTRP.FECHAPLAZO) FECHAPLAZO,
               PTRP.OBJETIVO,PTPAG.OBSERVACION,PTPAG.ESTADO,PTPAG.CCOSTO,PTPAG.VALOR,@USUARIO USUARIO,
               TER.TIPO_ID,TER.NIT,TER.DV,TER.RAZONSOCIAL,PTRP.NODOCUMENTO AS NCONTRATO
         FROM PTPAG INNER JOIN PTRP ON PTPAG.COMPANIA=PTRP.COMPANIA AND PTPAG.CONSECUTIVO=PTRP.CONSECUTIVO AND PTPAG.CDP=PTRP.CDP AND PTPAG.RP=PTRP.RP
                    INNER JOIN PTCDP ON PTRP.COMPANIA=PTCDP.COMPANIA AND PTRP.CONSECUTIVO=PTCDP.CONSECUTIVO AND PTRP.CDP=PTCDP.CDP
                    INNER JOIN TER ON PTRP.IDTERCERO=TER.IDTERCERO
         WHERE PTPAG.COMPANIA=@COMPANIA
         AND PTPAG.CONSECUTIVO=@PTPTO
         AND PTPAG.CNSPAGO=@CONSECUTIVO3

         /* Detalle: l?neas del pago (PTPAGD), mismo encadenamiento rubro/recurso que PTCXPD */
         SELECT PTRUB.RUBRO,PTRUB.NOMRUBRO,PTRUB.RECURSO,PTCDPD.IDTIPOMOV,PTCDPD.VIGENCIA,PTREC.DESCRIPCION,PTPAGD.VALOR,CAST(0 AS DECIMAL(18,2)) AS SALDO
         FROM PTPAG INNER JOIN PTPAGD ON PTPAG.COMPANIA=PTPAGD.COMPANIA AND PTPAG.CONSECUTIVO=PTPAGD.CONSECUTIVO AND PTPAG.CDP=PTPAGD.CDP AND PTPAG.RP=PTPAGD.RP AND PTPAG.CNSCXP=PTPAGD.CNSCXP AND PTPAG.CNSPAGO=PTPAGD.CNSPAGO
                    INNER JOIN PTCDPD ON PTPAGD.COMPANIA=PTCDPD.COMPANIA AND PTPAGD.CONSECUTIVO=PTCDPD.CONSECUTIVO AND PTPAGD.CDP=PTCDPD.CDP AND PTPAGD.ITEMCDPD=PTCDPD.ITEM
                    INNER JOIN PTRUB ON PTCDPD.RUBRO_ID=PTRUB.RUBRO_ID
                    INNER JOIN PTREC ON PTRUB.RECURSO=PTREC.RECURSO
         WHERE PTPAG.COMPANIA=@COMPANIA
         AND PTPAG.CONSECUTIVO=@PTPTO
         AND PTPAG.CNSPAGO=@CONSECUTIVO3
      END 
      IF @PTABLA='PTNOT'
      BEGIN
         /* JSON: CONSECUTIVO = PTNOT.CONSECUTIVO (presupuesto factura), CONSECUTIVO1 = RECO, CONSECUTIVO2 = CNSNOTA, COMPANIA */
         PRINT 'INGRESO A PTNOT'
         SELECT PTNOT.COMPANIA,
                PTNOT.CONSECUTIVO,
                PTNOT.RECO,
                PTNOT.CNSNOTA,
                DBO.FNK_FECHA_DDMMAA(PTNOT.FECHA) AS FECHA,
                PTNOT.CNSCXC,
                PTNOT.N_FACTURA,
                PTNOT.VR_TOTAL,
                PTNOT.OBSERVACION,
                PTNOT.CLASE,
                PTNOT.ESTADO,
                PTNOT.CONSECUTIVON,
                PTNOT.RUBRON,
                TER.IDTERCERO,
                TER.RAZONSOCIAL,
                TER.NIT,
                @USUARIO AS USUARIO
         FROM PTNOT
              INNER JOIN PTRECO ON PTNOT.COMPANIA = PTRECO.COMPANIA
                                 AND PTNOT.CONSECUTIVO = PTRECO.CONSECUTIVO
                                 AND PTNOT.RECO = PTRECO.RECO
              LEFT JOIN TER ON PTRECO.IDTERCERO = TER.IDTERCERO
         WHERE PTNOT.COMPANIA = @COMPANIA
           AND PTNOT.CONSECUTIVO = @CNSMOV
           AND PTNOT.RECO = @CONSECUTIVO1
           AND PTNOT.CNSNOTA = @CONSECUTIVO2

         SELECT PTNOT.CNSNOTA,
                PTNOT.CONSECUTIVO,
                PTNOT.RECO,
                PTNOT.N_FACTURA,
                PTNOT.CNSCXC,
                PTNOT.VR_TOTAL
         FROM PTNOT
         WHERE PTNOT.COMPANIA = @COMPANIA
           AND PTNOT.CONSECUTIVO = @CNSMOV
           AND PTNOT.RECO = @CONSECUTIVO1
           AND PTNOT.CNSNOTA = @CONSECUTIVO2
      END 
   END  
   
   IF @METODO = 'RP_ARBOL_DETALLE'
   BEGIN
      SELECT @COMPANIA = CASE
                WHEN COALESCE(NULLIF(LTRIM(RTRIM(JSON_COMPANIA)), ''), '') <> ''
                    THEN NULLIF(LTRIM(RTRIM(JSON_COMPANIA)), '')
                ELSE @COMPANIA
            END
           , @CONSECUTIVO_ARBOL = NULLIF(LTRIM(RTRIM(JSON_CONSECUTIVO)), '')
           , @CDP_ARBOL = NULLIF(LTRIM(RTRIM(JSON_CDP)), '')
           , @RP_ARBOL = NULLIF(LTRIM(RTRIM(JSON_RP)), '')
           , @NIVEL_MINIMO = COALESCE(JSON_NIVEL_MINIMO, 0)
           , @NIVELR = JSON_NIVELR
      FROM OPENJSON(@PARAMETROS)
      WITH (
          JSON_COMPANIA     VARCHAR(2)  '$.COMPANIA'
        , JSON_CONSECUTIVO  VARCHAR(20) '$.CONSECUTIVO'
        , JSON_CDP          VARCHAR(21) '$.CDP'
        , JSON_RP           VARCHAR(20) '$.RP'
        , JSON_NIVEL_MINIMO INT         '$.NIVEL_MINIMO'
        , JSON_NIVELR       INT         '$.NIVELR'
      );

      IF COALESCE(@COMPANIA, '') = ''
      BEGIN
         SELECT 'KO' AS OK, 'Debe indicar COMPANIA' AS ERROR;
         RETURN;
      END;

      IF COALESCE(@CONSECUTIVO_ARBOL, '') = ''
      BEGIN
         SELECT 'KO' AS OK, 'Debe indicar CONSECUTIVO (presupuesto)' AS ERROR;
         RETURN;
      END;

      IF COALESCE(@CDP_ARBOL, '') = ''
      BEGIN
         SELECT 'KO' AS OK, 'Debe indicar CDP' AS ERROR;
         RETURN;
      END;

      IF @NIVEL_MINIMO IS NULL
         SET @NIVEL_MINIMO = 0;

      SET @SOLO_DETALLE = CASE
         WHEN COALESCE(@NIVELR, 0) = 8 THEN 1
         WHEN @NIVEL_MINIMO = 8 THEN 1
         ELSE 0
      END;

      IF @SOLO_DETALLE = 0
      BEGIN
         IF @NIVEL_MINIMO < 0
            SET @NIVEL_MINIMO = 0;

         IF @NIVEL_MINIMO > 6
            SET @NIVEL_MINIMO = 6;
      END;

      IF NOT EXISTS (
         SELECT 1
         FROM PTCDP
         WHERE PTCDP.COMPANIA = @COMPANIA
           AND PTCDP.CONSECUTIVO = @CONSECUTIVO_ARBOL
           AND PTCDP.CDP = @CDP_ARBOL
      )
      BEGIN
         SELECT 'KO' AS OK, 'CDP no encontrado para el presupuesto indicado' AS ERROR;
         RETURN;
      END;

      IF COALESCE(@RP_ARBOL, '') <> ''
         AND NOT EXISTS (
            SELECT 1
            FROM PTRP
            WHERE PTRP.COMPANIA = @COMPANIA
              AND PTRP.CONSECUTIVO = @CONSECUTIVO_ARBOL
              AND PTRP.CDP = @CDP_ARBOL
              AND PTRP.RP = @RP_ARBOL
         )
      BEGIN
         SELECT 'KO' AS OK, 'RP no encontrado para el CDP indicado' AS ERROR;
         RETURN;
      END;

      SELECT 'OK' AS OK;

      SELECT
          X.RUBRO
        , X.NOMRUBRO
        , X.TIPO
        , X.NIVEL
        , COALESCE(PTCDPD.VIGENCIA, 'Actual') AS VIGENCIA
        , PTCDPD.RECURSO
        , PTREC.DESCRIPCION AS DESCRIPCION_RECURSO
        , PTCDPD.IDTIPOMOV
        , PTTMOV.DESCRIPCION AS DESCRIPCION_TIPOMOV
        , SUM(PTCDPD.VALOR) AS VALOR
      FROM PTCDPD
      INNER JOIN DBO.FNK_GENEALOGICO_PTRUB() X
          ON PTCDPD.RUBRO = X.RUBRO_DETALLE
         AND PTCDPD.CONSECUTIVO = X.CONSECUTIVO
         AND X.COMPANIA = PTCDPD.COMPANIA
      INNER JOIN PTREC
          ON PTCDPD.RECURSO = PTREC.RECURSO
      INNER JOIN PTTMOV
          ON PTCDPD.IDTIPOMOV = PTTMOV.IDTIPOMOV
      WHERE PTCDPD.COMPANIA = @COMPANIA
        AND PTCDPD.CONSECUTIVO = @CONSECUTIVO_ARBOL
        AND X.CONSECUTIVO = @CONSECUTIVO_ARBOL
        AND PTCDPD.CDP = @CDP_ARBOL
        AND (
              COALESCE(@RP_ARBOL, '') = ''
              OR EXISTS (
                  SELECT 1
                  FROM PTRPD
                  WHERE PTRPD.COMPANIA = PTCDPD.COMPANIA
                    AND PTRPD.CONSECUTIVO = PTCDPD.CONSECUTIVO
                    AND PTRPD.CDP = PTCDPD.CDP
                    AND PTRPD.RP = @RP_ARBOL
                    AND PTRPD.ITEMCDPD = PTCDPD.ITEM
              )
            )
        AND (
              (@SOLO_DETALLE = 1 AND X.TIPO = 'Detalle')
              OR (@SOLO_DETALLE = 0 AND (@NIVEL_MINIMO <= 0 OR X.NIVEL >= @NIVEL_MINIMO))
            )
      GROUP BY
          X.RUBRO
        , X.NOMRUBRO
        , X.TIPO
        , X.NIVEL
        , COALESCE(PTCDPD.VIGENCIA, 'Actual')
        , PTCDPD.RECURSO
        , PTREC.DESCRIPCION
        , PTCDPD.IDTIPOMOV
        , PTTMOV.DESCRIPCION
      ORDER BY X.RUBRO;

      RETURN;
   END
END
