				LEFT OUTER JOIN qxpcxd	on hpred.CONSECUTIVOCX =qxpcxd.CONSECUTIVO and hpred.ITEMCIRUGIA = QXPCXD.ITEM and hpre.CIRUGIA='SI'
				LEFT OUTER JOIN SER		ON QXPCXD.IDSERVICIO = SER.IDSERVICIO 
			WHERE FCXC.CNSCXC=  @CNSCXC	 AND COALESCE(QXPCXD.consecutivo,'')<>''	 
			UNION ALL
			SELECT  
				COALESCE( FTR.N_FACTURA,'') CAMPO01_NUMEROFACTURA,
					 HPRED.NOPRESTACION 
						, qxpcxd.CONSECUTIVO, QXPCXD.ITEM 
					, CONCAT( 
						CASE 
								when COALESCE( Ser.CODFURIPS,'8') = 2  
								then CASE 
									WHEN LEN(Ser.IDSERVICIO) =  5 THEN Ser.IDSERVICIO
									WHEN LEN(Ser.IDALTERNA) =  5 THEN Ser.IDALTERNA
									ELSE Ser.IDSERVICIO
								END 
							ELSE  ''
						END 		
						, '- ', QXPCXD.ITEM, '- ' , convert(varchar(10) , row_number() over (partition by hpred.idcirugia order by hpred.idservicio ) ) )  ord ,
					CASE DBO.FNK_VALORVARIABLE ('FURIPS_T_RADICADO' ) 
					WHEN 'CXC' THEN  COALESCE( @CNSCXC ,'')
						WHEN 'ADM' THEN COALESCE( FTR.NOREFERENCIA  , '' ) 
						ELSE  COALESCE( A.NRORADICADO ,'') 
						END 	CAMPO02_CONSECUTIVO_RECLAMACION,
					COALESCE( S.CODFURIPS,'8') CAMPO03_TIPOSERVICIO,
					--CASE 
					--	when COALESCE( S.CODFURIPS,'8') =1		THEN 
					--		CASE	WHEN  COALESCE(S.CODCUM,'')='' THEN S.IDSERVICIO ELSE S.CODCUM END 
					--	when COALESCE( S.CODFURIPS,'8') = 2  then 
					--		CASE 
					--			WHEN LEN(S.IDSERVICIO) =  5 THEN S.IDSERVICIO
					--			WHEN LEN(S.IDALTERNA) =  5 THEN S.IDALTERNA
					--			ELSE S.IDSERVICIO
					--		END 
					--	ELSE  ''
					--END CAMPO04_CODIGOSERVICIO,
					CASE when COALESCE( S.CODFURIPS,'8') =1 
							THEN CASE WHEN  COALESCE(S.CODCUM,'')='' THEN S.IDSERVICIO ELSE S.CODCUM END 
						when COALESCE( S.CODFURIPS,'8') = 2  
							then CASE 
								WHEN LEN(S.IDSERVICIO) =  5 THEN S.IDSERVICIO
								WHEN LEN(S.IDALTERNA) =  5 THEN S.IDALTERNA
								ELSE S.IDSERVICIO
							END 
						when COALESCE( S.CODFURIPS,'8') = 6  
							then  COALESCE( (SELECT TOP 1 ISNULL(IART2.REGINVIMA,IART.REGINVIMA)
									FROM SER 
										INNER JOIN  HPRED  ON SER.IDSERVICIO= HPRED.IDSERVICIO 
										INNER JOIN IART ON SER.IDARTICULO = IART.IDARTICULO  
										INNER JOIN IART IART2 ON IART.IDSERVICIO= IART2.IDSERVICIO
										LEFT JOIN IMOVH ON HPRED.CNSMOV = IMOVH.CNSMOV AND  IART2.IDARTICULO = IMOVH.IDARTICULO  
										WHERE  SER.IDSERVICIO =S.IDSERVICIO  AND HPRED.NOPRESTACION = FD.noprestacion)
										, '' )
						ELSE  ''
					END CAMPO04_CODIGOSERVICIO,
					CONCAT( 
						CASE 
							WHEN LEN(Ser.IDSERVICIO) =  5 THEN Ser.IDSERVICIO
							WHEN LEN(Ser.IDALTERNA) =  5 THEN Ser.IDALTERNA
							ELSE Ser.IDSERVICIO
						END 		
						, '- ' , S.DESCSERVICIO )  CAMPO05_NOMBRESERVICIO,
					COALESCE( FD.CANTIDAD,1) CAMPO06_CANTIDADSERVICIO,
					COALESCE( FD.VALOR,0) CAMPO07_VALORUNITARIO,
					COALESCE( FD.VLR_SERVICI,0) CAMPO08_VALORTOTAL,
					COALESCE( FD.VLR_SERVICI,0) CAMPO09_VALORRECLAMADO
				From FCXC INNER JOIN  FCXCD ON FCXC.CNSCXC=FCXCD.CNSCXC
					INNER JOIN		FTR		ON FCXCD.N_FACTURA=FTR.N_FACTURA		  AND COALESCE( FTR.TIPOANULACION,'')<>'NC'  AND FTR.ESTADO ='P'
					LEFT OUTER JOIN FTRD FD	ON FTR.N_fACTURA = FD.N_FACTURA
					LEFT OUTER JOIN HADM B	ON FTR.NOREFERENCIA=B.NOADMISION AND FTR.PROCEDENCIA='SALUD'
					INNER JOIN		AFI E	ON FTR.IDAFILIADO = E.IDAFILIADO
					LEFT OUTER JOIN HACTRAN A ON  A.CNSHACTRAN  = B.CNSHACTRAN  
					LEFT OUTER JOIN SER	S	ON FD.REFERENCIA=S.IDSERVICIO
					LEFT OUTER JOIN TER		ON A.IDASEGURADORA =TER.IDTERCERO
					LEFT OUTER JOIN hpred	ON FD.n_Factura = hpred.n_Factura and FD.noprestacion = hpred.noprestacion and FD.NOITEM =hpred.NOITEM 
					LEFT OUTER JOIN hpre	on hpred.noprestacion=hpre.noprestacion
				    LEFT OUTER JOIN qxpcxd	on hpred.CONSECUTIVOCX =qxpcxd.CONSECUTIVO and hpred.ITEMCIRUGIA = QXPCXD.ITEM and hpre.CIRUGIA='SI'
					LEFT OUTER JOIN ser		ON qxpcxd.IDSERVICIO = ser.IDSERVICIO 
				WHERE FCXC.CNSCXC= @CNSCXC 
					AND 	 COALESCE(qxpcxd.CONSECUTIVO,'')<>''  
					AND COALESCE( FD.VLR_SERVICI,0) <> 0  
		)B
		ORDER BY CAMPO01_NUMEROFACTURA, CAMPO02_CONSECUTIVO_RECLAMACION, ORD, CAMPO03_TIPOSERVICIO,  
			UPPER(DBO.FNK_LIMPIATEXTO(CAMPO05_NOMBRESERVICIO, 'A-Za-z0-9Ññ\ \.\/\:\-'))   
		RETURN
	END-- 'FURIPS 1 Y 2 POR CUENTA DE COBRO' 
