CREATE OR ALTER PROCEDURE DBO.SPQ_FURIPS
@JSON  NVARCHAR(MAX)
WITH
ENCRYPTION
AS
DECLARE	 @PARAMETROS   NVARCHAR(MAX),@MODELO           VARCHAR(100) ,@METODO		VARCHAR(100)	,@USUARIO      VARCHAR(12)
		,@GRUPO        VARCHAR(8)	,@SYS_COMPUTERNAME VARCHAR(254) ,@SEDE			VARCHAR(5)		,@FECHA        VARCHAR(10)   
		,@CNSHACTRAN    VARCHAR(20)	,@FECHA1           DATETIME		,@SQL			VARCHAR(MAX)	,@IDMEDICO     VARCHAR(20)
		,@CNSCXC		VARCHAR(20)	,@FIRMAREPRE	   VARCHAR(MAX)	,@NOMBREREPRE	VARCHAR(100)
		,@PAPELLIDOREPRE	VARCHAR(100)		,@SAPELLIDOREPRE	VARCHAR(100)	,@TIPOIDREPRE	VARCHAR(20)
		,@NITREPRE		VARCHAR(20) , @NOREFERENCIA		VARCHAR(20), @PROCEDENCIA	VARCHAR(20) ,	@SIRAS		VARCHAR(20) ,	@FTR 	VARCHAR(20) 
		,@VR_FTR		FLOAT ,		 @CODHABILITA		VARCHAR (20) 
		
DECLARE @IDTERCERO VARCHAR(20)
DECLARE @ESMUNDIAL BIT
BEGIN
	SET DATEFORMAT dmy
-----------------------------------------------------
	/*	DBO.SPQ_FURIPS
	Modulo:		SOAT
	Funcion:	Consultas y procedimientos para la exportacion delos FURIPS
	Metodos:	
				FURIPS		(Para exportar los planos FURIPS 1 Y 2 ) , 
				FURIPSCXC	(Para exportar los planos FURIPS 1 Y 2 Por Cuenta de Cobro ) , 
				PDFFURIPS	(Para exportar los PDF del FURIPS A Y B),				
				continua en SPQ_FURIPS_V2
	Elabora:	Edgardo Martinez
	Fecha:		16-06-2023
	Modificado:	16-02-2024 Edgardo : modifica la forma como muestra el medico
*/  

	SELECT *
	INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)  AS JSON
	)


	SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON
	
	IF @METODO NOT IN ('FURIPS', 'FURIPSCXC')
	BEGIN
		EXEC DBO.SPQ_FURIPS_V2 @JSON
		RETURN
	END
	
	DECLARE @IDNITFONSAT VARCHAR(50),
		@PREFIJOTRASLADOS VARCHAR(50),
		@FURRIP_FAC_FONSAT VARCHAR(10),
		@FURRIP_FAC_ASEGU VARCHAR(10),
		@FTRTRASLADONOFURIPS VARCHAR(10),
		@FURIPS_T_RADICADO VARCHAR(20);

	SET @IDNITFONSAT = DBO.FNK_VALORVARIABLE('IDNITFONSAT');
	SET @PREFIJOTRASLADOS = DBO.FNK_VALORVARIABLE('PREFIJOTRASLADOS');
	SET @FURRIP_FAC_FONSAT = DBO.FNK_VALORVARIABLE('FURRIP_FAC_FONSAT');
	SET @FURRIP_FAC_ASEGU = DBO.FNK_VALORVARIABLE('FURRIP_FAC_ASEGU');
	SET @FTRTRASLADONOFURIPS = DBO.FNK_VALORVARIABLE('FTRTRASLADONOFURIPS');
	SET @FURIPS_T_RADICADO = DBO.FNK_VALORVARIABLE('FURIPS_T_RADICADO');

	DECLARE @TBLERRORES TABLE(ERROR VARCHAR(MAX));
	SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO) FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	SELECT @CNSHACTRAN  = COALESCE(CNSHACTRAN, '')
		,@PROCEDENCIA = COALESCE(PROCEDENCIA, '')
		,@NOREFERENCIA = COALESCE(NOREFERENCIA, '')
		,@FTR = COALESCE(FACTURA, '')
	FROM OPENJSON(@PARAMETROS)
	WITH(
		CNSHACTRAN		VARCHAR(20) '$.CNSHACTRAN ',
		PROCEDENCIA		VARCHAR(20) '$.PROCEDENCIA',
		NOREFERENCIA	VARCHAR(20) '$.NOREFERENCIA',
		FACTURA			VARCHAR(20) '$.FACTURA'
	)
		
	SELECT TOP 1 @SIRAS = SIRAS  FROM HACTRAND WHERE CNSHACTRAN  = @CNSHACTRAN  AND PROCEDENCIA = @PROCEDENCIA  AND NOREFERENCIA = @NOREFERENCIA

	IF @FTR =''   -- SI NO RECIBIÓ LA FACTURA 
	BEGIN
		SET @VR_FTR = 0
		PRINT 'NO TRAE FACTURA POR LO QUE PONE EL VALOR EN 0'

	END
	ELSE
	BEGIN
		SELECT  @VR_FTR = VR_TOTAL FROM FTR WHERE   N_FACTURA = @FTR
		PRINT @FTR +' FACTURA ' + @FTR +' POR EL VALOR :' + CONVERT(VARCHAR(20) ,@VR_FTR )
	END

	IF @PROCEDENCIA = '' 
	BEGIN
		SELECT TOP 1 @PROCEDENCIA ='QX', @NOREFERENCIA = NOADMISION FROM HADM  WHERE CNSHACTRAN = @CNSHACTRAN
		SELECT TOP 1 @PROCEDENCIA ='CI', @NOREFERENCIA = CONSECUTIVO  FROM CIT  WHERE CNSHACTRAN = @CNSHACTRAN
		SELECT TOP 1 @PROCEDENCIA ='CE', @NOREFERENCIA = NOAUT  FROM AUT  WHERE CNSHACTRAN = @CNSHACTRAN
		PRINT ' LA PROCEDENCIA ESTA VACIA . TOMO POR DEFECTO : '  + @PROCEDENCIA + ' CON LA ADMISION: ' +@NOREFERENCIA 
	END

	IF  @METODO IN ( 'FURIPS', 'PDFFURIPS', 'FURTRAN', 'PDFFURTRAN', 'FUCTAS')
	BEGIN
		SELECT  @CODHABILITA = LEFT(COALESCE( CODHABILITA, COALESCE( IDSGSSS,'')),12)  
		FROM SED  LEFT OUTER JOIN  FTR ON SED.IDSEDE =FTR.IDSEDE INNER JOIN TER ON FTR.IDTERCERO = TER.IDTERCERO  
		WHERE PROCEDENCIA = CASE @PROCEDENCIA WHEN 'QX' THEN 'SALUD' ELSE @PROCEDENCIA END  
			AND NOREFERENCIA = @NOREFERENCIA 
			AND COALESCE(FTR.ESTADO,'A')<>'A' 
			AND COALESCE(FTR.TIPOANULACION,'')<>'NC'
	END
	ELSE SELECT @CODHABILITA = IDALTERNA2 FROM TER WHERE IDTERCERO  = DBO.FNK_VALORVARIABLE ('IDTERCEROINSTALADO' )

	IF (COALESCE(@CODHABILITA, '') = '')
		SELECT @CODHABILITA = IDALTERNA2 FROM TER WHERE IDTERCERO  = DBO.FNK_VALORVARIABLE ('IDTERCEROINSTALADO' )
		
	IF @METODO = 'FURIPS'  -- 'FURIPS 1 Y 2' 
	BEGIN
		PRINT '---------------------------'
		PRINT 'FURIPS' 
		PRINT 'FACTURA : ' +  @FTR
		PRINT 'VALOR :  ' + CAST ( @VR_FTR AS VARCHAR(30) )
		
		SELECT @IDTERCERO=NIT FROM HACTRAN INNER JOIN TER ON TER.IDTERCERO=HACTRAN.IDASEGURADORA WHERE CNSHACTRAN=@CNSHACTRAN
		SELECT @ESMUNDIAL=IIF( @IDTERCERO='860037013',1,0)

		SELECT 'OK' OK

		-- PARA VALIDACIONES
		DECLARE @SINCONDUCTOR AS SMALLINT	,@ESACC AS SMALLINT	, @SINPROPIETARIO AS SMALLINT	, @SINPOLIZA AS SMALLINT	, @SINVEHICULO AS SMALLINT	, @SINPLACA AS SMALLINT
		SELECT @SINCONDUCTOR = CASE UPPER( A.TIPOPOLIZA ) 
									WHEN 'VEHICULO EN FUGA'	THEN 1	 --3
									WHEN 'AUTO EN FUGA'	THEN 1	
									WHEN 'AUTO FANTASMA'	THEN 1   --5
									WHEN 'NO ASEGURADO PROPIETARIO'	THEN 1  --7
									WHEN 'NO ASEG. PROP'	THEN 1
									ELSE 0   --- 1,2,4,6,7,8
								END 
			,  @SINPROPIETARIO = CASE UPPER( A.TIPOPOLIZA ) 
									WHEN 'VEHICULO EN FUGA'	THEN 1	 --3
									WHEN 'AUTO EN FUGA'	THEN 1		
									WHEN 'AUTO FANTASMA'	THEN 1   --5
									WHEN 'NO ASEGURADO PROPIETARIO'	THEN 1  --7
									WHEN 'NO ASEG. PROP'	THEN 1
									--WHEN 'NO ASEG. PLAC'	THEN 1 --8
									ELSE 0   --- 1,2,4,6,7  --DICE 7 PERO ES INDETERMINADO EL PROPIETARO
 								END 
			, @SINPOLIZA = CASE UPPER( A.TIPOPOLIZA ) 
							WHEN 'NO ASEGURADO'		THEN 1 --2
							WHEN 'AUTO EN FUGA'		THEN 1 --3
							WHEN 'AUTO FANTASMA'	THEN 1 --5
							WHEN 'NO ASEGURADO PROPIETARIO'	THEN 1  --7
							WHEN 'NO ASEG. PROP'	THEN 1
							WHEN 'NO ASEG. PLAC'	THEN 1 --8
							ELSE 0 -- 1,4,5
						END 
			, @SINVEHICULO = CASE UPPER(A.TIPOPOLIZA )
								WHEN 'AUTO EN FUGA'		THEN 1 --3
								WHEN 'AUTO FANTASMA'	THEN 1 --5
									ELSE 0 --1,2,4,6,7,8
								END 
			, @SINPLACA = CASE UPPER(A.TIPOPOLIZA )
									WHEN 'AUTO EN FUGA'		THEN 1 --3
									WHEN 'AUTO FANTASMA'	THEN 1 --5
									WHEN 'No Aseg. plac'	THEN 1 --8
									ELSE 0 
								END --1,2,4,6,7
			, @ESACC = IIF(NATUREVENTO = 'ACCTR' ,1 ,0 ) 
			
		FROM HACTRAN A
		WHERE CNSHACTRAN = @CNSHACTRAN
		/*
		1 = Asegurado
		2 = No asegurado
		3 = Vehículo fantasma
		4 = Póliza falsa
		6= Asegurado D.2497
		7 = No Asegurado – Propietario indeterminado o sin información
		8 = No Asegurado – Sin Placa
		*/
		----------
		-- DIAGNOSTICOS
		----------
		BEGIN -- FURIPS1
			IF @PROCEDENCIA = 'QX'  --'SALUD'
			BEGIN
			 SELECT COALESCE( A.NRORADICADOANT,'') CAMPO01_NUMERO_RADICADO_ANTERIOR,
					COALESCE( RESPGLOSA, '') CAMPO02_RGO, -- 1,2,6 
					COALESCE(  @FTR , '')   CAMPO03_NUMERO_FACTURA,
					CASE DBO.FNK_VALORVARIABLE ('FURIPS_T_RADICADO' ) 
						WHEN 'CXC' THEN  COALESCE( @CNSCXC ,'')
						 WHEN 'ADM' THEN COALESCE( @NOREFERENCIA, '' ) 
						 ELSE  COALESCE( A.NRORADICADO ,'') 
						 END CAMPO04_CONSECUTIVO_RECLAMACION,
					@CODHABILITA  CAMPO05_CODIGO_HABILITACION,
					LEFT(E.PAPELLIDO,20) CAMPO06_PAPELLIDO_VICTIMA, 
					COALESCE( E.SAPELLIDO,'') CAMPO07_SAPELLIDO_VICTIMA,
					LEFT(E.PNOMBRE,20) CAMPO08_PNOMBRE_VICTIMA,
					COALESCE( E.SNOMBRE,'') CAMPO09_SNOMBRE_VICTIMA,
					CASE  WHEN E.TIPO_DOC IN ('CC' ,'CE' ,'CN' ,'PA' ,'RC' ,'TI' ,'AS' ,'MS' ,'PT' ,'PE' ,'SC' ,'CD' ,'DE') THEN  E.TIPO_DOC  ELSE '' END   CAMPO10_TIPODOC_VICTIMA, 
					LEFT(COALESCE(E.DOCIDAFILIADO,''),16) CAMPO11_NUMDOCUMENTO_VICTIMA,
					COALESCE( convert(varchar(10) ,E.FNACIMIENTO ,103) ,'') CAMPO12_FECHANACIMIENTO_VICTIMA,
					case when COALESCE(FORMAT( E.FECHAFALLECE ,'dd/MM/yyyy') ,'01/01/1900')='01/01/1900' then '' else COALESCE(FORMAT( E.FECHAFALLECE ,'dd/MM/yyyy') ,'') end	CAMPO13_FECHAFALLECIMIENTO,-- (DD/MM/AAAA)
					CASE WHEN E.SEXO IN ('F','M','O') THEN E.SEXO  WHEN E.SEXO ='Masculino' THEN 'M'   WHEN E.SEXO ='Femenino' THEN 'F'  ELSE 'O' END  CAMPO14_SEXO, -- F,M,O
					COALESCE( LEFT(E.DIRECCION,100),'') CAMPO15_DIRECCION, 
					CASE LEN( COALESCE( E.CIUDAD, '')) WHEN 5 THEN LEFT(COALESCE( E.CIUDAD, ''),2) WHEN 4 THEN LEFT(COALESCE( E.CIUDAD, ''),1) ELSE '' END CAMPO16_CODDEPARTAMENTO, -- AFI
					COALESCE(RIGHT(E.CIUDAD,3),'') CAMPO17_CODMUNICIPIORESIDENCIA,
					LEFT(COALESCE(E.TELEFONORES,''),10) CAMPO18_TELEFONOVICTIMA,
					CASE A.CONDICIONACC WHEN 'Conducto' THEN 1 WHEN 'Peaton' THEN '2' WHEN 'Ocupante' THEN '3' WHEN 'Ciclista' THEN '4' ELSE '1' END CAMPO19_CONDICIONVICTIMA, 
					CASE   A.NATUREVENTO 
						WHEN 'ACCTR' THEN '01'   -- Accidente de Tránsito
						WHEN 'SISMO' THEN '02'   -- Sismo
						WHEN 'MAREM' THEN '03'   -- Maremoto
						WHEN 'ERUPV' THEN '04'   -- Erupciones Volcánicas
						WHEN 'HURAC' THEN '16'   -- Huracán
						WHEN 'INUND' THEN '06'   -- Inundaciones
						WHEN 'AVALA' THEN '07'   -- Avalancha
						WHEN 'DESLI' THEN '05'   -- Deslizamiento de Tierra
						WHEN 'INCEN' THEN '08'   -- Incendio Natural
						WHEN 'EXPLO' THEN '09'   -- Explosión
						WHEN 'MASAC' THEN '13'   -- Masacre
						WHEN 'MINAA' THEN '15'   -- Mina Antipersonal
						WHEN 'COMBA' THEN '11'   -- Combate
						WHEN 'INCEM' THEN '10'   -- Incendio Terrorista
						WHEN 'ATAQU' THEN '12'   -- Ataques a Municipios
						WHEN 'OTRO' THEN '17'   -- Otro
						WHEN 'DESPL' THEN '14'   -- Desplazados
						WHEN 'RAYO' THEN '25'   -- Rayo
						WHEN 'VENDA' THEN '26'   -- Vendaval
						WHEN 'TORNA' THEN '27'   -- Tornado
						ELSE '01'
					END  CAMPO20_NATURALEZAEVENTO, ---REVISAR TGEN PARA COMPLETAR  -- SELECT * FROM  TGEN WHERE TABLA='GENERAL' AND CAMPO='NATUREVENTO' ORDER BY DATO1
					LEFT(COALESCE( A.NATURCUAL,''),25) CAMPO21_DESCRIPCIONOTROEVENTO, 
					COALESCE(LEFT(A.SITIOACC, 100),'') CAMPO22_DIRECCIONOCURRENCIA, 
					case when COALESCE(FORMAT( A.FECHAACC ,'dd/MM/yyyy') ,'01/01/1900')='01/01/1900' then '' else COALESCE(FORMAT( A.FECHAACC ,'dd/MM/yyyy') ,'') end CAMPO23_FECHAOCURRENCIA, 
					COALESCE(FORMAT( A.FECHAACC ,N'HH:mm'),'')  CAMPO24_HORAOCURRENCIA, 
					CASE LEN( COALESCE( A.CIUDAD, '')) WHEN 5 THEN LEFT(COALESCE( A.CIUDAD, ''),2) WHEN 4 THEN LEFT(COALESCE( A.CIUDAD, ''),1) ELSE '' END CAMPO25_CODDEPARTAMENTOOCURRENCIA, --AUT
					CASE LEN( COALESCE( A.CIUDAD, '')) WHEN 5 THEN RIGHT(COALESCE( A.CIUDAD, ''),3) WHEN 4 THEN RIGHT(COALESCE( A.CIUDAD, ''),3)  ELSE '' END  CAMPO26_CODMUNICIPIOOCURRENCIA,
					CASE A.ZONA WHEN 'URBANA' THEN 'U' WHEN 'RURAL' THEN 'R' ELSE '' END CAMPO27_ZONAOCURRENCIA,
					CASE A.TIPOPOLIZA
						WHEN 'ASEGURADO'				THEN '1'	WHEN 'Vigente'			THEN '1'	WHEN 'NO ASEGURADO'		THEN '2'	WHEN 'No Asegurado'		THEN '2'
						WHEN 'VEHICULO FANTASMA'		THEN '3'	WHEN 'Auto Fantasma'	THEN '3'	WHEN 'POLIZA FALSA'		THEN '4'	WHEN 'FALSA'			THEN '4'
						WHEN 'VEHICULO EN FUGA'			THEN '3'	WHEN 'Auto en Fuga'		THEN '3'	WHEN 'ASEGURADO D.2497'	THEN '6'	WHEN 'Aseg. D.2497'		THEN '6'
						WHEN 'NO ASEGURADO PROPIETARIO'	THEN '7'	WHEN 'No Aseg. prop'	THEN '7'	WHEN 'No Aseg. plac'	THEN '8'
						ELSE CASE 
							WHEN A.FECHAACC >= A.FECHAINIPOL
								AND A.FECHAACC <= A.FECHAFINPOL
								AND COALESCE( A.NOPOLIZA, '') <> ''
								THEN '1'
							ELSE CASE 
									WHEN (
											A.FECHAACC < A.FECHAINIPOL
											OR A.FECHAACC > A.FECHAFINPOL
											)
										AND COALESCE( A.NOPOLIZA, '') <> ''
										THEN '2'
									ELSE CASE 
											WHEN COALESCE( A.NOPOLIZA, '') = ''
												THEN '4'
											ELSE 'ERROR EN ESTADO ASEGURAMIENTO'
											END
									END
							END
						END CAMPO28_ESTADOASEGURAMIENTO
					, 
					CAMPO29_MARCA			= IIF( @SINVEHICULO = 1  , '' , COALESCE( A.MARCA  ,''))  , 
					CAMPO30_PLACA			= IIF( @SINVEHICULO = 1  , '',  COALESCE( A.PLACA  ,'') ) , 
					CAMPO31_TIPOVEHICULO	= IIF( @SINVEHICULO = 1  , '',  COALESCE( A.TIPOVEHICULO,'') )   , -- AGREGAR TIPOVEHICULO ES OBLIGATORIO PARA LOS ESTADOS DE ASEGURAMIENTO 1, 2, 4, 6 Y 7 LAS NUEVAS OPCIONES SON:
					CASE A.TIPOPOLIZA
						WHEN 'ASEGURADO'		THEN COALESCE( TER.IDALTERNA2 ,'') -- '1'
						WHEN 'Vigente'			THEN COALESCE( TER.IDALTERNA2 ,'') -- '1'
						WHEN 'NO ASEGURADO'		THEN  COALESCE( ( SELECT IDALTERNA2 FROM TER WHERE IDTERCERO = DBO.FNK_VALORVARIABLE('IDNITFONSAT')) ,'') -- '2'
						WHEN 'No Asegurado'		THEN  COALESCE( ( SELECT IDALTERNA2 FROM TER WHERE IDTERCERO = DBO.FNK_VALORVARIABLE('IDNITFONSAT')) ,'') -- '2'
						WHEN 'Auto Fantasma'	THEN  COALESCE( ( SELECT IDALTERNA2 FROM TER WHERE IDTERCERO = DBO.FNK_VALORVARIABLE('IDNITFONSAT')) ,'') --'3' 
						WHEN 'AUTO FANTASMA'	THEN  COALESCE( ( SELECT IDALTERNA2 FROM TER WHERE IDTERCERO = DBO.FNK_VALORVARIABLE('IDNITFONSAT')) ,'') --'3' 
						WHEN 'Auto en Fuga'		THEN  COALESCE( ( SELECT IDALTERNA2 FROM TER WHERE IDTERCERO = DBO.FNK_VALORVARIABLE('IDNITFONSAT')) ,'') --'3' 
						WHEN 'AUTO EN FUGA'		THEN  COALESCE( ( SELECT IDALTERNA2 FROM TER WHERE IDTERCERO = DBO.FNK_VALORVARIABLE('IDNITFONSAT')) ,'') --'3' 
						WHEN 'POLIZA FALSA'		THEN  COALESCE( TER.IDALTERNA2 ,'') -- '4'
						WHEN 'ASEGURADO D.2497'	THEN  COALESCE( TER.IDALTERNA2 ,'') -- '6'
						WHEN 'Aseg. D.2497'		THEN  COALESCE( TER.IDALTERNA2 ,'') --'6'
						ELSE ''
					END	CAMPO32_CODASEGURADORA,  -- TER.IDALTERNA2
					CAMPO33_NUMEROPOLIZASOAT				= IIF( @SINPOLIZA = 1 , '' ,  COALESCE( A.NOPOLIZA,'')  )   , 
					CAMPO34_FECHAINICIOVIGENCIAPOLIZA		= IIF( @SINPOLIZA = 1 , '' , CASE  when COALESCE(convert(varchar(10) ,  A.FECHAINIPOL ,103) ,'01/01/1900') ='01/01/1900' then '' else COALESCE(convert(varchar(10) ,  A.FECHAINIPOL ,103) ,'')  end )  ,
					CAMPO35_FECHAFINVIGENCIAPOLIZA			= IIF( @SINPOLIZA = 1 , '' ,  case when COALESCE( convert(varchar(10) , A.FECHAFINPOL ,103) ,'01/01/1900')  ='01/01/1900' then '' else COALESCE( convert(varchar(10) , A.FECHAFINPOL ,103) ,'')  end ) ,
					CAMPO36_NUMERORADICADOSIRAS				= IIF( @ESACC = 1 , COALESCE( @SIRAS , COALESCE( A.NOSIRAS,'') ) , '' )  , 
					CASE A.COBROEXCEPOL WHEN 'S' THEN '1' WHEN 'SI' THEN '1' ELSE '0' END CAMPO37_COBROAGOTAMIENTOTOPEASEGURADORA, -- SI ES IDASEGURADORA ES ADRES VA 0 PERO SI NO 1 
					COALESCE( A.CUPSPPALHOSP,'')  CAMPO38_CODIGOCUPSSERVICIOPPALHOSPITALIZACION, -- AGREGAR CUPSPPALHOSP
					COALESCE( A.COMPLEJIDADQX ,3) CAMPO39_COMPLEJIDADPROCEDIMIENTOQUIRURGICO, --  AGREGAR COMPLEJIDADQX OPCIONES 1= ALTA , 2= MEDIA, 3= BAJA ,  TAMAÑO 1, NUMERICO
					COALESCE( A.CUPSPPALQX,'') CAMPO40_CODIGOCUPSPROCEDIMIENTOQUIRURGICOPPAL,  -- AGREGAR CUPSPPALQX
					COALESCE( A.CUPSSECQX,'') CAMPO41_CODIGOCUPSPROCEDIMIENTOQUIRURGICOSEC, -- AGREGAR CUPSSECQX
					COALESCE( A.PRESTOUCI,0 ) CAMPO42_PRESTOSERVICIOUCI, 
					CASE WHEN COALESCE( A.PRESTOUCI,0 ) =1  
						THEN
							CASE WHEN CONVERT( VARCHAR(3),COALESCE(A.DIASUCI,0 ) ) ='0'  THEN  
									CASE WHEN DATEDIFF(DD, COALESCE(  B.FECHAALTAMED, B.FECHA) , B.FECHA ) <0 THEN '' ELSE CONVERT( VARCHAR(3), DATEDIFF(DD, COALESCE(  B.FECHAALTAMED, B.FECHA) , B.FECHA ) ) END 							
								ELSE CONVERT( VARCHAR(3), A.DIASUCI )
							END
						ELSE '' 
					END CAMPO43_DIASUCIRECLAMADOS, ---CALCULO FECHAEGRESO - FECHAINGRESO 
					CAMPO44_TIPODOCPROPIETARIO				= IIF( @SINPROPIETARIO = 1 , '', CASE  WHEN A.PROTIPO_ID  IN ('CC' ,'CE' ,'NI'  ,'PT' ,'PE' ,'SC' ,'CD' ,'DE','TI') THEN  A.PROTIPO_ID   ELSE '' END ) , --  OBLIGATORIO PARA EL ESTADO DE ASEGURAMIENTO 1, 2, 4 O 6 LAS OPCIONES SON:
					CAMPO45_NUMDOCIDENTIDADPROPIETARIO		= IIF( @SINPROPIETARIO = 1 , '',  	COALESCE( A.PRODOCUMENTO,'') ) , 
					CAMPO46_PAPELLIDOPROPIETARIO			= IIF( @SINPROPIETARIO = 1 , '', COALESCE( A.PROPAPELLIDO,'') ) , -- O RAZON SOCIAL EN CASO DE EMPRESA
					CAMPO47_SAPELLIDOPROPIETARIO			= IIF( @SINPROPIETARIO = 1 , '', COALESCE( A.PROSAPELLIDO,'') ) , 
					CAMPO48_PNOMBREPROPIETARIO				= IIF( @SINPROPIETARIO = 1 , '', COALESCE( A.PROPNOMBRE,'')	 ) , 
					CAMPO49_SNOMBREPROPIETARIO				= IIF( @SINPROPIETARIO = 1 , '' , 	COALESCE( A.PROSNOMBRE,'')   ) , 
