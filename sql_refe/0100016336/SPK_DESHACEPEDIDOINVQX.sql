IF EXISTS (SELECT name FROM sysobjects WHERE name = 'SPK_DESHACEPEDIDOINVQX' AND type = 'P')
   DROP PROCEDURE SPK_DESHACEPEDIDOINVQX

GO
CREATE PROCEDURE DBO.SPK_DESHACEPEDIDOINVQX
@NOPRESTACION VARCHAR(16)
WITH ENCRYPTION
AS
DECLARE @CNSMOV VARCHAR(20) 
DECLARE @VECES  INT
DECLARE @ESTADO INT
BEGIN
   SELECT  @VECES=COUNT(1)
   FROM   HPRED
   WHERE  HPRED.NOPRESTACION=@NOPRESTACION

   IF DBO.FNK_VALORVARIABLE('PEDIDOHPREAIZSOL')<>'SI'
   BEGIN
      IF @VECES>1
      BEGIN
         PRINT 'MAS DE UNO '
         DECLARE MOV_C CURSOR FOR
         SELECT CNSMOV, COUNT(*) AS VECES
         FROM   HPRED
         WHERE  HPRED.NOPRESTACION = @NOPRESTACION
         GROUP BY CNSMOV
         OPEN  MOV_C
         FETCH NEXT FROM MOV_C
         INTO  @CNSMOV, @VECES
         WHILE @@FETCH_STATUS = 0  
         BEGIN     
            SELECT @ESTADO = ESTADO FROM IMOV WHERE CNSMOV = @CNSMOV
            IF @ESTADO = 0
            BEGIN
               UPDATE HPRED SET CNSMOV=''
               FROM HPRED INNER JOIN SER ON HPRED.IDSERVICIO=SER.IDSERVICIO
                          INNER JOIN IMOVH ON SER.IDARTICULO=IMOVH.IDARTICULO
               WHERE HPRED.NOPRESTACION=@NOPRESTACION
               AND HPRED.CNSMOV=@CNSMOV
               AND IMOVH.CNSMOV=@CNSMOV
               DELETE IMOVH WHERE CNSMOV = @CNSMOV
               DELETE IMOV WHERE CNSMOV = @CNSMOV
               UPDATE HPRE SET PEDIDOINV = 0, CNSMOV='' WHERE NOPRESTACION = @NOPRESTACION
            END
            FETCH NEXT FROM MOV_C
            INTO  @CNSMOV, @VECES
         END
         CLOSE MOV_C
         DEALLOCATE MOV_C
      END
      ELSE
      BEGIN
         PRINT' UNO SOLO....'
         SELECT @CNSMOV=CNSMOV FROM HPRE WHERE NOPRESTACION=@NOPRESTACION
         SELECT @ESTADO = ESTADO FROM IMOV WHERE CNSMOV = @CNSMOV
         PRINT '@ESTADO == '+LTRIM(RTRIM(STR(@ESTADO)))
         IF @ESTADO = 0
         BEGIN
            PRINT 'VOY A BORRAR....'
            DELETE IMOVH WHERE CNSMOV = @CNSMOV
            DELETE IMOV WHERE CNSMOV = @CNSMOV
            UPDATE HPRED SET CNSMOV = '' WHERE NOPRESTACION = @NOPRESTACION
            UPDATE HPRE SET PEDIDOINV = 0, CNSMOV='' WHERE NOPRESTACION = @NOPRESTACION
         END
      END      
   END
   ELSE
   BEGIN
       SELECT @CNSMOV=ISNULL(CNSMOV,'') FROM HPRE WHERE NOPRESTACION=@NOPRESTACION
       IF @CNSMOV<>''
       BEGIN
          IF (SELECT ESTADO FROM IZSOL WHERE CNSIZSOL=@CNSMOV)=1
          BEGIN
             IF NOT EXISTS (SELECT 1 FROM IMOV WHERE ESTADO IN (0,1) AND NODOCUMENTO=@CNSMOV AND PROCEDENCIA='CM_SOL'
                              AND NOT EXISTS (SELECT 1 FROM IMOVH WHERE IMOVH.CNSMOV=IMOV.CNSMOV))
             BEGIN
                DELETE IMOVH WHERE EXISTS (SELECT 1 FROM IMOV WHERE IMOV.CNSMOV=IMOVH.CNSMOV AND IMOV.ESTADO IN (0,2) AND IMOV.NODOCUMENTO=@CNSMOV AND IMOV.PROCEDENCIA='CM_SOL')
                DELETE IMOV WHERE ESTADO IN (0,2) AND NODOCUMENTO=@CNSMOV AND PROCEDENCIA='CM_SOL'
                DELETE IZSOLDT WHERE EXISTS (SELECT 1 FROM IZSOLD WHERE IZSOLD.CNSIZSOLD=IZSOLDT.CNSIZSOLD AND IZSOLD.CNSIZSOL=@CNSMOV)
                DELETE IZSOLD WHERE CNSIZSOL=@CNSMOV
                DELETE IZSOL WHERE CNSIZSOL=@CNSMOV
                UPDATE HPRE SET PEDIDOINV=0, CNSMOV=NULL WHERE NOPRESTACION=@NOPRESTACION
             END
          END
       END
   END
END

