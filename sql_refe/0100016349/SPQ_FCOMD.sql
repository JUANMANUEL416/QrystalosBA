CREATE OR ALTER PROCEDURE DBO.SPQ_FCOMD @JSON  NVARCHAR(MAX)
WITH      ENCRYPTION
AS
DECLARE  @ERRORES AS TABLE(ERROR VARCHAR(MAX))
DECLARE  @PARAMETROS NVARCHAR(MAX), 
		 @METODO VARCHAR(100), 
		 @MODELOACT NVARCHAR(MAX), 
		 @USUARIO VARCHAR(12),
		 @IDSEDE VARCHAR(20),
		 @COMPANIA VARCHAR(20),
		 @IDIMPUESTO VARCHAR(20),
		 @IDARTICULO VARCHAR(20),
		 @VALOR VARCHAR(100),
		 @VR_ANTESIVA decimal(9),
		 @VR_TOTAL decimal(9),
		 @IVA decimal(9),
		 @VR_DESCUENTO decimal(9),
		 @CNSFCOM VARCHAR(20),
		 @SYS_COMPUTERNAME VARCHAR(50),
		 @REQAUTCOMP SMALLINT,
		 @VLR_UNITARIO DECIMAL(14,2),
		 @CANTIDAD DECIMAL(14,2),
		 @filaIART NVARCHAR(MAX),
		 @dataVarios NVARCHAR(MAX)
BEGIN
	BEGIN TRY

	SELECT *
	INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)  AS JSON
	)
	SELECT @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON
	IF @METODO = 'IARTPRIN'
	BEGIN
		SELECT 'OK' AS OK
		SELECT IART.DESCRIPCION,IART.IDARTICULO
		FROM IART
		INNER JOIN SER ON SER.IDSERVICIO=IART.IDSERVICIO
		WHERE PRINCIPAL = '1'
		RETURN
	END
	IF @METODO = 'IMPUESTOSTIPE'
	BEGIN
		SELECT 'OK' AS OK
		SELECT @IDARTICULO = IDARTICULO FROM OPENJSON(@PARAMETROS) WITH(IDARTICULO VARCHAR(100) '$.IDARTICULO')
		
		SELECT FIMP.DESCRIPCION, FIMP.TIPO, FIMP.IDIMPUESTO 
		from FIMP
		inner JOIN IART on IART.IDARTICULO = @IDARTICULO
		inner JOIN SER ON SER.IDSERVICIO=IART.IDSERVICIO
		inner JOIN ITAR ON ITAR.IDITAR=IART.IDITAR
		inner JOIN USVGS ON USVGS.IDVARIABLE='IDIMP_IVA'
		INNER JOIN FIMPDV on FIMPDV.IDIMPUESTO = FIMP.IDIMPUESTO 
		where FIMP.IDIMPUESTO=  COALESCE(SER.IDIMPUESTO,  USVGS.DATO)
		GROUP BY FIMP.IDIMPUESTO, FIMP.DESCRIPCION, FIMP.TIPO
		RETURN
	END
	IF @METODO = 'CLASEIMPUESTOS'
	BEGIN
		SELECT 'OK' AS OK
		SELECT @IDIMPUESTO = IDIMPUESTO FROM OPENJSON(@PARAMETROS) WITH(IDIMPUESTO VARCHAR(20) '$.IDIMPUESTO')
		SELECT @VALOR = VALOR FROM OPENJSON(@PARAMETROS) WITH(VALOR VARCHAR(100) '$.VALOR')
		
		SELECT FIMPD.IDCLASE, FIMPD.DESCRIPCION , FIMPDV.VALOR AS VALOR
		FROM FIMPD 
		INNER JOIN FIMPDV on FIMPDV.IDIMPUESTO = FIMPD.IDIMPUESTO
		INNER JOIN USVGS on USVGS.IDVARIABLE='IDIVA'
		where FIMPD.IDIMPUESTO=@IDIMPUESTO
		/*AND FIMPDV.VALOR_INICIAL <= COALESCE(@VALOR, 1)
		AND FIMPDV.VALOR_FINAL >= COALESCE(@VALOR, 1)*/
		GROUP BY FIMPD.IDCLASE, FIMPD.DESCRIPCION, VALOR
		RETURN
	END
	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			
			SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
			SELECT @IDSEDE = IDSEDE, @COMPANIA=COMPANIA FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
			SELECT @CNSFCOM = JSON_VALUE(@PARAMETROS, '$.CNSFCOM')
				, @IDARTICULO = JSON_VALUE(@PARAMETROS, '$.IDARTICULO')
				--, @TOTAL_BRUTO = JSON_VALUE(@PARAMETROS, '$.IDARTICULO')
			SELECT @COMPANIA = COMPANIA FROM FCOM WHERE CNSFCOM = @CNSFCOM

			SELECT @REQAUTCOMP = COALESCE(IART.REQAUTCOMP, 0)
			FROM IART
			WHERE IDARTICULO = @IDARTICULO

			SELECT @VLR_UNITARIO = TRY_CAST(JSON_VALUE(@PARAMETROS, '$.VLR_UNITARIO') AS DECIMAL(14,2))
			IF @VLR_UNITARIO IS NULL OR @VLR_UNITARIO <= 0
			BEGIN
				INSERT INTO @ERRORES(ERROR)
				SELECT 'El valor unitario debe ser mayor a cero.'
				SELECT 'KO' AS OK
				SELECT ERROR FROM @ERRORES
				RETURN
			END
			IF TRY_CAST(JSON_VALUE(@PARAMETROS, '$.CANTIDAD') AS DECIMAL(14,2)) IS NULL
				OR TRY_CAST(JSON_VALUE(@PARAMETROS, '$.CANTIDAD') AS DECIMAL(14,2)) <= 0
			BEGIN
				INSERT INTO @ERRORES(ERROR)
				SELECT 'La cantidad debe ser mayor a cero.'
				SELECT 'KO' AS OK
				SELECT ERROR FROM @ERRORES
				RETURN
			END

			DELETE FROM FCOMD WHERE CNSFCOM = @CNSFCOM AND IDARTICULO = @IDARTICULO --FIMPD
		--VLR_UNITARIO, VR_ANTESIVA, IVA, VR_TOTAL, VR_UNITMASIVA
			INSERT INTO FCOMD (CNSFCOM, IDARTICULO, ESTADO, VLR_UNITARIO, CANTIDAD, VR_ANTESIVA, IVA, VR_TOTAL, VR_UNITMASIVA, COMPANIA, TIENEIVA, FACTORIVA, DETALLE, TIPO, IDIMPUESTO, IDCLASE, UTILIDAD, TDESCUENTO, TIPODTO, PDTO, VR_DESCUENTO, ODESFERA, OIESFERA, ODCILINDRO, OICILINDRO, ODEJE, OIEJE, ODADICION, OIADICION, ODALT, OIALT, ODAVL, OIAVL, ODTLENTE, OITLENTE, ODDNP, OIDNP, CNSFMED, REQAUTCOMP, CANTISOL, TEMP, HUMEDAD, NOLOTE, FECHAVENCE)
			SELECT CNSFCOM = @CNSFCOM
					, IDARTICULO
					, ESTADO = 'P'
					--, ROUND(VLR_UNITARIO,2)
					, ROUND(TRY_CAST(VLR_UNITARIO AS DECIMAL(14,2)),2)
					, CANTIDAD
					, ROUND(VR_ANTESIVA,2)
					, ROUND(IVA,2,1)
					, ROUND(VR_TOTAL,2)
					--, TOTAL_BRUTO
					, ROUND(VR_UNITMASIVA,2)
					, COMPANIA = @COMPANIA
					, TIENEIVA
					, FACTORIVA
					, DETALLE, TIPO
					, IDIMPUESTO, IDCLASE, UTILIDAD
					, TDESCUENTO, TIPODTO, PDTO, ROUND(VR_DESCUENTO,2)
					, ODESFERA, OIESFERA, ODCILINDRO, OICILINDRO, ODEJE, OIEJE, ODADICION, OIADICION, ODALT, OIALT, ODAVL, OIAVL, ODTLENTE, OITLENTE, ODDNP, OIDNP
					, CNSFMED
					, REQAUTCOMP = @REQAUTCOMP
					, CANTISOL
					, TEMP
					, HUMEDAD
					, NOLOTE = COALESCE(NOLOTE, '')
					, FECHAVENCE
				--, IDTUTELD, DECONSUMO
			FROM OPENJSON(@PARAMETROS) WITH(
				IDARTICULO		VARCHAR(20)		'$.IDARTICULO'
				, VLR_UNITARIO	VARCHAR(100) 	'$.VLR_UNITARIO'
				, CANTIDAD		DECIMAL(14, 2)	'$.CANTIDAD'
				, VR_ANTESIVA	DECIMAL(14, 2)	'$.VR_ANTESIVA'
				, IVA			DECIMAL(14, 2)	'$.IVA'
				, VR_TOTAL		DECIMAL(14, 5)	'$.VR_TOTAL'
				--, TOTAL_BRUTO	DECIMAL(14, 5)	'$.TOTAL_BRUTO'
				, VR_UNITMASIVA	DECIMAL(14, 2)	'$.VR_UNITMASIVA'
				, TIENEIVA		SMALLINT		'$.TIENEIVA'
				, FACTORIVA		DECIMAL(14, 2)	'$.FACTORIVA'
				, DETALLE		VARCHAR(255)	'$.DETALLE'
				, TIPO			VARCHAR(12)		'$.TIPO'
				, IDIMPUESTO	VARCHAR(10)		'$.IDIMPUESTO'
				, IDCLASE		VARCHAR(10)		'$.IDCLASE'
				, UTILIDAD		DECIMAL(14, 2)	'$.UTILIDAD'
				, TDESCUENTO	TINYINT			'$.TDESCUENTO'
				, TIPODTO		VARCHAR(1)		'$.TIPODTO'
				, PDTO			DECIMAL(14, 2)	'$.PDTO'
				, VR_DESCUENTO	DECIMAL(14, 2)	'$.VR_DESCUENTO'
				, ODESFERA		VARCHAR(20)		'$.ODESFERA'
				, OIESFERA		VARCHAR(20)		'$.OIESFERA'
				, ODCILINDRO    VARCHAR(20)		'$.ODCILINDRO'
				, OICILINDRO    VARCHAR(20)		'$.OICILINDRO'
				, ODEJE			VARCHAR(20)		'$.ODEJE'
				, OIEJE			VARCHAR(20)		'$.OIEJE'
				, ODADICION		VARCHAR(20)		'$.ODADICION'
				, OIADICION		VARCHAR(20)		'$.OIADICION'
				, ODALT			VARCHAR(20)		'$.ODALT'
				, OIALT			VARCHAR(20)		'$.OIALT'
				, ODAVL			VARCHAR(20)		'$.ODAVL'
				, OIAVL			VARCHAR(20)		'$.OIAVL'
				, ODTLENTE		VARCHAR(20)		'$.ODTLENTE'
				, OITLENTE		VARCHAR(20)		'$.OITLENTE'
				, ODDNP			VARCHAR(20)		'$.ODDNP'
				, OIDNP			VARCHAR(20)		'$.OIDNP'
				, CNSFMED		VARCHAR(20)		'$.CNSFMED'
				, CANTISOL		DECIMAL(14, 2)	'$.CANTISOL'
				, HUMEDAD		DECIMAL(14, 2)	'$.HUMEDAD'
				, TEMP			DECIMAL(14, 2)	'$.TEMP'
				, NOLOTE		VARCHAR(20)		'$.NOLOTE'
				, FECHAVENCE	DATE			'$.FECHAVENCE'
			) AS #T

			EXEC DBO.SPK_UPDATE_VLRS_FCOM @CNSFCOM
		END TRY
		BEGIN CATCH
			INSERT INTO @ERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (SELECT COUNT(1) FROM @ERRORES)>0
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @ERRORES
			RETURN
		END

		SELECT 'OK' AS OK
		RETURN
	END
	IF @METODO = 'GUARDAR_DEPRECATED'
	BEGIN
		BEGIN TRY
			SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
			SELECT @IDSEDE = IDSEDE, @COMPANIA=COMPANIA FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
			SELECT @CNSFCOM = CNSFCOM FROM OPENJSON(@PARAMETROS) WITH(CNSFCOM VARCHAR(20) '$.CNSFCOM')
			SELECT @VR_ANTESIVA = VR_ANTESIVA FROM OPENJSON(@PARAMETROS) WITH(VR_ANTESIVA VARCHAR(20) '$.VR_ANTESIVA_FCOM')
			SELECT @IVA = IVA FROM OPENJSON(@PARAMETROS) WITH(IVA decimal(9) '$.IVA_FCOM')
			SELECT @VR_TOTAL = VR_TOTAL FROM OPENJSON(@PARAMETROS) WITH(VR_TOTAL decimal(9) '$.VR_TOTAL_FCOM')
			SELECT @VR_DESCUENTO = VR_DESCUENTO FROM OPENJSON(@PARAMETROS) WITH(VR_DESCUENTO decimal(9) '$.VR_DESCUENTO_FCOM')
			update FCOM SET 
			VR_ANTESIVA=@VR_ANTESIVA,
			IVA=@IVA,
			VR_TOTAL=@VR_TOTAL,
			VR_DESCUENTO=@VR_DESCUENTO
			where CNSFCOM= @CNSFCOM
			
			INSERT INTO FCOMD (CNSFCOM ,IDARTICULO ,ESTADO ,VLR_UNITARIO ,CANTIDAD ,VR_ANTESIVA ,IVA ,VR_TOTAL ,
			VR_UNITMASIVA ,COMPANIA ,TIENEIVA ,FACTORIVA ,VR_DESCUENTO ,DETALLE ,
			TIPO ,IDIMPUESTO ,IDCLASE,TDESCUENTO ,TIPODTO ,
			TEMP ,HUMEDAD ,CANTISOL,NOLOTE,REQAUTCOMP)   
			SELECT @CNSFCOM ,IDARTICULO ,'P' ,VLR_UNITARIO ,CANTIDAD ,VR_ANTESIVA ,IVA ,VR_TOTAL ,
			VR_UNITMASIVA ,@COMPANIA ,TIENEIVA ,FACTORIVA ,VR_DESCUENTO ,DETALLE ,
			'Articulos' ,IDIMPUESTO ,IDCLASE,TDESCUENTO ,'V' ,
			TEMP ,HUMEDAD ,CANTISOL,'',REQAUTCOMP
			FROM OPENJSON(@PARAMETROS) WITH(
				IDARTICULO VARCHAR(20) '$.IDARTICULO',
				VLR_UNITARIO decimal(9) '$.VLR_UNITARIO',
				CANTIDAD decimal(9) '$.CANTIDAD',
				VR_ANTESIVA decimal(9) '$.VR_ANTESIVA',
				IVA decimal(9) '$.IVA',
				VR_TOTAL decimal(9) '$.VR_TOTAL',
				VR_UNITMASIVA decimal(9) '$.VR_UNITMASIVA',
				TIENEIVA smallint '$.TIENEIVA',
				FACTORIVA decimal(5) '$.FACTORIVA',
				VR_DESCUENTO decimal(9) '$.VR_DESCUENTO',
				DETALLE VARCHAR(255) '$.DETALLE',
				IDIMPUESTO VARCHAR(10) '$.IDIMPUESTO',
				IDCLASE VARCHAR(10) '$.IDCLASE',
				TDESCUENTO tinyint '$.TDESCUENTO',
				TEMP decimal(5) '$.TEMP',
				HUMEDAD decimal(5) '$.HUMEDAD',
				CANTISOL smallint '$.CANTISOL',
				REQAUTCOMP bit '$.REQAUTCOMP'
			) AS #T
		END TRY
		BEGIN CATCH
			INSERT INTO @ERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (SELECT COUNT(1) FROM @ERRORES)>0
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @ERRORES
			RETURN
		END

		SELECT 'OK' AS OK

	END
	IF @METODO = 'ELIMINAR'
	BEGIN
		BEGIN TRY
			
			SELECT @CNSFCOM = JSON_VALUE(@PARAMETROS, '$.CNSFCOM')
				,@IDARTICULO = JSON_VALUE(@PARAMETROS, '$.IDARTICULO')

			DELETE FROM FCOMD WHERE CNSFCOM = @CNSFCOM AND IDARTICULO = @IDARTICULO

			EXEC DBO.SPK_UPDATE_VLRS_FCOM @CNSFCOM

		END TRY
		BEGIN CATCH
			INSERT INTO @ERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (SELECT COUNT(1) FROM @ERRORES)>0
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @ERRORES
			RETURN
		END

		SELECT 'OK' AS OK
	END

	IF @METODO = 'TRAER_IMPUESTO'
	BEGIN

		DECLARE @PRECIO_TOTAL DECIMAL(14,2) -- Resulta de FCOMD.VLR_UNITARIO * FCOD.CATIDAD

		SELECT @IDARTICULO = JSON_VALUE(@PARAMETROS, '$.IDARTICULO')
			,@PRECIO_TOTAL = JSON_VALUE(@PARAMETROS, '$.PRECIO_TOTAL')

		SELECT OK = 'OK'

		DECLARE @FECHA_ACTUAL AS DATE = CURRENT_TIMESTAMP
		SELECT * FROM DBO.FNK_PIVA_IART(@IDARTICULO, @FECHA_ACTUAL, @PRECIO_TOTAL)
		
		RETURN

	END
	IF @METODO = 'EXCEL_DETALLE'
	BEGIN
		SELECT @CNSFCOM = CNSFCOM
		FROM OPENJSON(@PARAMETROS)
		WITH( CNSFCOM		VARCHAR(20)		'$.CNSFCOM')
		SELECT 'OK'OK
		SELECT IART.IDARTICULO AS COD_ARTICULO, IART.DESCRIPCION [ARTICULO], FCOMD.CANTIDAD AS SOLICITADO, FCOMD.VLR_UNITARIO AS PRECIO, FCOMD.VR_TOTAL FROM FCOMD
		INNER JOIN IART ON FCOMD.IDARTICULO = IART.IDARTICULO
		WHERE CNSFCOM = @CNSFCOM
	END	
	IF @METODO = 'INSERTA_FCOMD'
	BEGIN
		SELECT @CNSFCOM = CNSFCOM, @filaIART = filaIART, @dataVarios = dataVarios
		FROM OPENJSON(@PARAMETROS)
		WITH( CNSFCOM		VARCHAR(20)			'$.CNSFCOM'
		,filaIART			NVARCHAR(MAX)		AS JSON
		,dataVarios			NVARCHAR(MAX)		AS JSON
		)
		SELECT * INTO #filaIART FROM OPENJSON (@filaIART)
		WITH(
		IDARTICULO		VARCHAR(20)		'$.IDARTICULO'
		)
		SELECT * INTO #dataVarios FROM OPENJSON (@dataVarios)
		WITH(			
		CANTIDAD			INT				'$.CANTIDAD'
		,VLRUNI				DECIMAL(14,2)	'$.VLRUNI'
		,TIVA				BIT				'$.TIVA'
		,MIMPUESTOS			BIT				'$.MIMPUESTOS'
		,IDIMPUESTO			VARCHAR(20)		'$.IDIMPUESTO'
		,IDCLASE			VARCHAR(20)		'$.IDCLASE'
		,FIVA				DECIMAL(14,2)	'$.FIVA'
		,VR_ANTESIVA		DECIMAL(14,2)	'$.VR_ANTESIVA'
		,IVA				DECIMAL(14,2)	'$.IVA'
		,VR_TOTAL			DECIMAL(14,2)	'$.VR_TOTAL'
		,VR_UNITMASIVA		DECIMAL(14,2)	'$.VR_UNITMASIVA'
		)

		IF NOT EXISTS (SELECT 1 FROM #dataVarios)
			INSERT INTO @ERRORES(ERROR) SELECT 'No se recibieron datos del detalle (dataVarios).'
		ELSE
		BEGIN
			IF EXISTS (SELECT 1 FROM #dataVarios WHERE CANTIDAD IS NULL OR CANTIDAD <= 0)
				INSERT INTO @ERRORES(ERROR) SELECT 'La cantidad es obligatoria y debe ser mayor a cero.'
			IF EXISTS (SELECT 1 FROM #dataVarios WHERE VLRUNI IS NULL OR VLRUNI <= 0)
				INSERT INTO @ERRORES(ERROR) SELECT 'El valor unitario es obligatorio y debe ser mayor a cero.'
			IF EXISTS (SELECT 1 FROM #dataVarios WHERE COALESCE(TIVA, 0) = 1 AND (IDIMPUESTO IS NULL OR LTRIM(RTRIM(IDIMPUESTO)) = ''))
				INSERT INTO @ERRORES(ERROR) SELECT 'Debe indicar el código de impuesto cuando Tiene IVA está activo.'
			IF EXISTS (SELECT 1 FROM #dataVarios WHERE COALESCE(TIVA, 0) = 1 AND (FIVA IS NULL OR FIVA < 0))
				INSERT INTO @ERRORES(ERROR) SELECT 'El factor de IVA es obligatorio cuando Tiene IVA está activo.'
		END

		IF (SELECT COUNT(*) FROM @ERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @ERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				INSERT INTO FCOMD (CNSFCOM, IDARTICULO, ESTADO, VLR_UNITARIO, CANTIDAD, VR_ANTESIVA, IVA, VR_TOTAL, VR_UNITMASIVA,  TIENEIVA, FACTORIVA, TIPO, IDIMPUESTO, IDCLASE, TIPODTO, COMPANIA, NOLOTE)
			SELECT CNSFCOM = @CNSFCOM
					 ,#filaIART.IDARTICULO, 'P', #dataVarios.VLRUNI, #dataVarios.CANTIDAD, #dataVarios.VR_ANTESIVA, #dataVarios.IVA, #dataVarios.VR_TOTAL, #dataVarios.VR_UNITMASIVA,  #dataVarios.TIVA, #dataVarios.FIVA, 'Articulos', #dataVarios.IDIMPUESTO, #dataVarios.IDCLASE, 'P', @COMPANIA,0
			FROM 	
			#filaIART, #dataVarios

			EXEC DBO.SPK_UPDATE_VLRS_FCOM @CNSFCOM
			END TRY  
			BEGIN CATCH 
				INSERT INTO @ERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @ERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @ERRORES
				RETURN
			END
			SELECT 'OK'OK
		END 
	END
	IF @METODO = 'ELIMINA_FCOMD'
	BEGIN
		SELECT @CNSFCOM = CNSFCOM, @IDARTICULO = IDARTICULO
		FROM OPENJSON(@PARAMETROS)
		WITH( CNSFCOM		VARCHAR(20)			'$.CNSFCOM'
		,IDARTICULO			VARCHAR(20)			'$.IDARTICULO'
		)
		IF (SELECT COUNT(*) FROM @ERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @ERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				DELETE FROM FCOMD  WHERE CNSFCOM = @CNSFCOM AND IDARTICULO = @IDARTICULO
				EXEC DBO.SPK_UPDATE_VLRS_FCOM @CNSFCOM
			END TRY  
			BEGIN CATCH 
				INSERT INTO @ERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @ERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @ERRORES
				RETURN
			END
			SELECT 'OK'OK
		END 
	END

	IF @METODO = 'GUARDAR_MASIVO'
	BEGIN
		BEGIN TRY
			DECLARE @DETALLES NVARCHAR(MAX) -- Array completo de detalles
			DECLARE @DETALLE_JSON NVARCHAR(MAX) -- Detalle individual
			DECLARE @INDICE VARCHAR(10)
			DECLARE @INDICE_INT INT = 0
			DECLARE @TOTAL_DETALLES INT = 0
			DECLARE @EXITOSOS INT = 0
			DECLARE @FALLIDOS INT = 0
			DECLARE @MENSAJE_ERROR VARCHAR(MAX)
			DECLARE @IDARTICULO_ACTUAL VARCHAR(20)
		
			-- Tabla temporal para almacenar resultados
			DECLARE @RESULTADOS TABLE (
				INDICE INT,
				IDARTICULO VARCHAR(20),
				OK VARCHAR(2),
				MENSAJE VARCHAR(MAX)
			)
		
			SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
			SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
		
			-- Obtener CNSFCOM y array de detalles
			SELECT @CNSFCOM = JSON_VALUE(@PARAMETROS, '$.CNSFCOM')
				, @DETALLES = JSON_QUERY(@PARAMETROS, '$.DETALLES')
		
			-- Validar que CNSFCOM existe
			IF NOT EXISTS(SELECT 1 FROM FCOM WHERE CNSFCOM = @CNSFCOM)
			BEGIN
				INSERT INTO @ERRORES(ERROR)
				SELECT 'La orden de compra ' + @CNSFCOM + ' no existe'
				SELECT 'KO' AS OK
				SELECT ERROR FROM @ERRORES
				RETURN
			END
		
			SELECT @COMPANIA = COMPANIA FROM FCOM WHERE CNSFCOM = @CNSFCOM
		
			-- Contar total de detalles
			SELECT @TOTAL_DETALLES = COUNT(*)
			FROM OPENJSON(@DETALLES)
		
			-- Crear tabla temporal con los detalles
			SELECT 
				[key] AS INDICE_JSON,
				[value] AS DETALLE_JSON
			INTO #DETALLES_TEMP
			FROM OPENJSON(@DETALLES)
		
			-- Procesar cada detalle
			DECLARE detalle_cursor CURSOR FOR
			SELECT INDICE_JSON, DETALLE_JSON
			FROM #DETALLES_TEMP
			ORDER BY CAST(INDICE_JSON AS INT)
		
			OPEN detalle_cursor
			FETCH NEXT FROM detalle_cursor INTO @INDICE, @DETALLE_JSON
		
			WHILE @@FETCH_STATUS = 0
			BEGIN
				BEGIN TRY
					SET @INDICE_INT = CAST(@INDICE AS INT)
					-- Extraer datos del detalle actual
					SELECT @IDARTICULO_ACTUAL = JSON_VALUE(@DETALLE_JSON, '$.IDARTICULO')
				
					-- Validar que el artículo existe
					IF NOT EXISTS(SELECT 1 FROM IART WHERE IDARTICULO = @IDARTICULO_ACTUAL)
					BEGIN
						SET @MENSAJE_ERROR = 'El artículo ' + @IDARTICULO_ACTUAL + ' no existe'
						INSERT INTO @RESULTADOS(INDICE, IDARTICULO, OK, MENSAJE)
						VALUES(@INDICE_INT, @IDARTICULO_ACTUAL, 'KO', @MENSAJE_ERROR)
						SET @FALLIDOS = @FALLIDOS + 1
						GOTO SIGUIENTE_DETALLE
					END

					IF TRY_CAST(JSON_VALUE(@DETALLE_JSON, '$.VLR_UNITARIO') AS DECIMAL(14,2)) IS NULL
						OR TRY_CAST(JSON_VALUE(@DETALLE_JSON, '$.VLR_UNITARIO') AS DECIMAL(14,2)) <= 0
					BEGIN
						SET @MENSAJE_ERROR = 'El valor unitario debe ser mayor a cero'
						INSERT INTO @RESULTADOS(INDICE, IDARTICULO, OK, MENSAJE)
						VALUES(@INDICE_INT, @IDARTICULO_ACTUAL, 'KO', @MENSAJE_ERROR)
						SET @FALLIDOS = @FALLIDOS + 1
						GOTO SIGUIENTE_DETALLE
					END
					IF TRY_CAST(JSON_VALUE(@DETALLE_JSON, '$.CANTIDAD') AS DECIMAL(14,2)) IS NULL
						OR TRY_CAST(JSON_VALUE(@DETALLE_JSON, '$.CANTIDAD') AS DECIMAL(14,2)) <= 0
					BEGIN
						SET @MENSAJE_ERROR = 'La cantidad debe ser mayor a cero'
						INSERT INTO @RESULTADOS(INDICE, IDARTICULO, OK, MENSAJE)
						VALUES(@INDICE_INT, @IDARTICULO_ACTUAL, 'KO', @MENSAJE_ERROR)
						SET @FALLIDOS = @FALLIDOS + 1
						GOTO SIGUIENTE_DETALLE
					END
				
					-- Obtener REQAUTCOMP del artículo
					SELECT @REQAUTCOMP = COALESCE(IART.REQAUTCOMP, 0)
					FROM IART
					WHERE IDARTICULO = @IDARTICULO_ACTUAL
				
					-- Eliminar detalle existente si existe (para permitir actualización)
					DELETE FROM FCOMD WHERE CNSFCOM = @CNSFCOM AND IDARTICULO = @IDARTICULO_ACTUAL
				
					-- Insertar el nuevo detalle usando la misma lógica que GUARDAR
					INSERT INTO FCOMD (
						CNSFCOM, IDARTICULO, ESTADO, VLR_UNITARIO, CANTIDAD, VR_ANTESIVA, IVA, VR_TOTAL, 
						VR_UNITMASIVA, COMPANIA, TIENEIVA, FACTORIVA, DETALLE, TIPO, IDIMPUESTO, IDCLASE, 
						UTILIDAD, TDESCUENTO, TIPODTO, PDTO, VR_DESCUENTO, 
						ODESFERA, OIESFERA, ODCILINDRO, OICILINDRO, ODEJE, OIEJE, ODADICION, OIADICION, 
						ODALT, OIALT, ODAVL, OIAVL, ODTLENTE, OITLENTE, ODDNP, OIDNP, 
						CNSFMED, REQAUTCOMP, CANTISOL, TEMP, HUMEDAD, NOLOTE, FECHAVENCE
					)
					SELECT 
						CNSFCOM = @CNSFCOM
						, IDARTICULO
						, ESTADO = 'P'
						, ROUND(TRY_CAST(VLR_UNITARIO AS DECIMAL(14,2)), 2)
						, CANTIDAD
						, ROUND(VR_ANTESIVA, 2)
						, ROUND(IVA, 2, 1)
						, ROUND(VR_TOTAL, 2)
						, ROUND(VR_UNITMASIVA, 2)
						, COMPANIA = @COMPANIA
						, TIENEIVA
						, FACTORIVA
						, DETALLE
						, TIPO = COALESCE(TIPO, 'Articulos')
						, IDIMPUESTO
						, IDCLASE
						, UTILIDAD
						, TDESCUENTO
						, TIPODTO
						, PDTO
						, ROUND(VR_DESCUENTO, 2)
						, ODESFERA, OIESFERA, ODCILINDRO, OICILINDRO, ODEJE, OIEJE, ODADICION, OIADICION
						, ODALT, OIALT, ODAVL, OIAVL, ODTLENTE, OITLENTE, ODDNP, OIDNP
						, CNSFMED
						, REQAUTCOMP = @REQAUTCOMP
						, CANTISOL
						, TEMP
						, HUMEDAD
						, NOLOTE = COALESCE(NOLOTE, 0)
						, FECHAVENCE
					FROM OPENJSON(@DETALLE_JSON) WITH(
						IDARTICULO		VARCHAR(20)		'$.IDARTICULO'
						, VLR_UNITARIO	VARCHAR(100)	'$.VLR_UNITARIO'
						, CANTIDAD		DECIMAL(14, 2)	'$.CANTIDAD'
						, VR_ANTESIVA	DECIMAL(14, 2)	'$.VR_ANTESIVA'
						, IVA			DECIMAL(14, 2)	'$.IVA'
						, VR_TOTAL		DECIMAL(14, 5)	'$.VR_TOTAL'
						, VR_UNITMASIVA	DECIMAL(14, 2)	'$.VR_UNITMASIVA'
						, TIENEIVA		SMALLINT		'$.TIENEIVA'
						, FACTORIVA		DECIMAL(14, 2)	'$.FACTORIVA'
						, DETALLE		VARCHAR(255)	'$.DETALLE'
						, TIPO			VARCHAR(12)		'$.TIPO'
						, IDIMPUESTO	VARCHAR(10)		'$.IDIMPUESTO'
						, IDCLASE		VARCHAR(10)		'$.IDCLASE'
						, UTILIDAD		DECIMAL(14, 2)	'$.UTILIDAD'
						, TDESCUENTO	TINYINT			'$.TDESCUENTO'
						, TIPODTO		VARCHAR(1)		'$.TIPODTO'
						, PDTO			DECIMAL(14, 2)	'$.PDTO'
						, VR_DESCUENTO	DECIMAL(14, 2)	'$.VR_DESCUENTO'
						, ODESFERA		VARCHAR(20)		'$.ODESFERA'
						, OIESFERA		VARCHAR(20)		'$.OIESFERA'
						, ODCILINDRO	VARCHAR(20)		'$.ODCILINDRO'
						, OICILINDRO	VARCHAR(20)		'$.OICILINDRO'
						, ODEJE			VARCHAR(20)		'$.ODEJE'
						, OIEJE			VARCHAR(20)		'$.OIEJE'
						, ODADICION		VARCHAR(20)		'$.ODADICION'
						, OIADICION		VARCHAR(20)		'$.OIADICION'
						, ODALT			VARCHAR(20)		'$.ODALT'
						, OIALT			VARCHAR(20)		'$.OIALT'
						, ODAVL			VARCHAR(20)		'$.ODAVL'
						, OIAVL			VARCHAR(20)		'$.OIAVL'
						, ODTLENTE		VARCHAR(20)		'$.ODTLENTE'
						, OITLENTE		VARCHAR(20)		'$.OITLENTE'
						, ODDNP			VARCHAR(20)		'$.ODDNP'
						, OIDNP			VARCHAR(20)		'$.OIDNP'
						, CNSFMED		VARCHAR(20)		'$.CNSFMED'
						, CANTISOL		DECIMAL(14, 2)	'$.CANTISOL'
						, HUMEDAD		DECIMAL(14, 2)	'$.HUMEDAD'
						, TEMP			DECIMAL(14, 2)	'$.TEMP'
						, NOLOTE		VARCHAR(20)		'$.NOLOTE'
						, FECHAVENCE	DATE			'$.FECHAVENCE'
					) AS #T
				
					-- Si llegó aquí, el detalle se guardó correctamente
					INSERT INTO @RESULTADOS(INDICE, IDARTICULO, OK, MENSAJE)
					VALUES(@INDICE_INT, @IDARTICULO_ACTUAL, 'OK', 'Detalle guardado correctamente')
					SET @EXITOSOS = @EXITOSOS + 1
				
				END TRY
				BEGIN CATCH
					SET @MENSAJE_ERROR = ERROR_MESSAGE()
					INSERT INTO @RESULTADOS(INDICE, IDARTICULO, OK, MENSAJE)
					VALUES(@INDICE_INT, ISNULL(@IDARTICULO_ACTUAL, 'N/A'), 'KO', @MENSAJE_ERROR)
					SET @FALLIDOS = @FALLIDOS + 1
				END CATCH
			
				SIGUIENTE_DETALLE:
				FETCH NEXT FROM detalle_cursor INTO @INDICE, @DETALLE_JSON
			END
		
			CLOSE detalle_cursor
			DEALLOCATE detalle_cursor
		
			-- Actualizar valores totales de la orden de compra
			IF @EXITOSOS > 0
			BEGIN
				EXEC DBO.SPK_UPDATE_VLRS_FCOM @CNSFCOM
			END
		
			-- Retornar resumen
			SELECT 'OK' AS OK
			SELECT @TOTAL_DETALLES AS TOTAL_DETALLES
				, @EXITOSOS AS EXITOSOS
				, @FALLIDOS AS FALLIDOS
		
			-- Retornar resultados detallados
			SELECT INDICE, IDARTICULO, OK, MENSAJE
			FROM @RESULTADOS
			ORDER BY INDICE
		
		END TRY
		BEGIN CATCH
			INSERT INTO @ERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (SELECT COUNT(1) FROM @ERRORES) > 0
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @ERRORES
			RETURN
		END
	END

	END TRY
	BEGIN CATCH
		/* Seguridad global: cierra cualquier transacción huérfana y reporta el error */
		IF @@TRANCOUNT > 0
			ROLLBACK TRAN;

		SELECT 'KO' OK,
			ERROR_MESSAGE() AS ERROR,
			ERROR_NUMBER() AS ERROR_NUMBER,
			ERROR_LINE() AS ERROR_LINE,
			COALESCE(ERROR_PROCEDURE(), 'SPQ_FCOMD') AS ERROR_PROCEDURE;
		RETURN
	END CATCH

END

