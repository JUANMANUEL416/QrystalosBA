						'P',
						ICTZD.CANTIDAD,
						NULL,
						'Articulos',
						'P',
						CASE
							WHEN ICTZD.CANTIDAD > 32767 THEN 32767
							WHEN ICTZD.CANTIDAD < -32768 THEN -32768
							ELSE CAST(ICTZD.CANTIDAD AS SMALLINT)
						END,
						'',
						@COMPANIA,
						CASE
							WHEN ICTZD.CANTIDAD > 0 THEN
								CASE
									WHEN COALESCE(ICTZD.TIENEIVA, 0) = 1 AND COALESCE(ICTZD.VALOR_IMPUESTO, 0) > 0 THEN
										(ICTZD.VLR_TOTAL / (1 + (ICTZD.VALOR_IMPUESTO / 100))) / ICTZD.CANTIDAD
									ELSE
