					TER.RAZONSOCIAL AS [PROVEEDOR],
					TER.NIT AS [NIT],
					COUNT(DISTINCT ICTZ.CNSICTZ) AS [TOTAL_COTIZACIONES],
					COUNT(ICTZD.CNSICTZD) AS [TOTAL_LINEAS],
					SUM(ICTZD.CANTIDAD) AS [TOTAL_CANTIDAD],
					SUM(ICTZD.VLR_TOTAL * ICTZD.CANTIDAD) AS [VALOR_TOTAL],
					COUNT(CASE WHEN COALESCE(ICTZD.PROCESADO,0) = 1 THEN 1 END) AS [ORDENES_GENERADAS],
					AVG(ICTZD.VLR_TOTAL) AS [PRECIO_PROMEDIO]
				FROM ICTZ
				INNER JOIN ICTZD ON ICTZ.CNSICTZ = ICTZD.CNSICTZ
				INNER JOIN TER ON ICTZD.IDTERCERO = TER.IDTERCERO
				WHERE CONVERT(DATE,ICTZ.FECHA) BETWEEN CONVERT(DATE,@FINICIAL) AND CONVERT(DATE,@FFINAL)
				AND (@IDTERCERO IS NULL OR ICTZD.IDTERCERO = @IDTERCERO)
				GROUP BY TER.IDTERCERO, TER.RAZONSOCIAL, TER.NIT
				ORDER BY SUM(ICTZD.VLR_TOTAL * ICTZD.CANTIDAD) DESC

			END TRY
			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE();
			END CATCH

			IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
			BEGIN
				SELECT 'KO' OKPQ
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END

			SELECT 'OK' OK
		END
