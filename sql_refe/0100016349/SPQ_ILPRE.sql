					UPDATE ICTZD SET PROCESADO = 1, CNSFCOM = @CNSFCOM
					FROM ICTZD
					WHERE CNSICTZ = @CNSICTZ
					AND COALESCE(PROCESADO,0) = 0
					AND ICTZD.IDTERCERO = @IDTERCERO
					AND COALESCE(ICTZD.VLR_TOTAL,0) <> 0
					AND COALESCE(ICTZD.CANTIDAD,0) > 0

