								ICTZD.VLR_TOTAL - (ICTZD.VLR_TOTAL / (1 + (ICTZD.VALOR_IMPUESTO / 100)))
							ELSE 0
						END,
						ICTZD.VLR_TOTAL,
						CASE
							WHEN ICTZD.CANTIDAD > 0 THEN ICTZD.VLR_TOTAL / ICTZD.CANTIDAD
							ELSE 0
