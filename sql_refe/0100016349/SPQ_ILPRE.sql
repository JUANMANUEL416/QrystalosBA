						SET @LISTA_CNSFCOM = @CNSFCOM
					ELSE
						SET @LISTA_CNSFCOM = @LISTA_CNSFCOM + ', ' + @CNSFCOM

					FETCH NEXT FROM CURSOR_OC_1 INTO @IDTERCERO;
				END
				CLOSE CURSOR_OC_1;
				DEALLOCATE CURSOR_OC_1;

				-- Actualizar ICTZ con el estado y la lista de CNSFCOM generados
				UPDATE ICTZ
				SET ESTADO = 'Compra',
					CNSFCOM_LIST = @LISTA_CNSFCOM
				WHERE CNSICTZ = @CNSICTZ

			END TRY
			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE();
			END CATCH
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
