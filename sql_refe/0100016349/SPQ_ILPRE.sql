CREATE OR ALTER PROCEDURE DBO.SPQ_ILPRE
@JSON NVARCHAR(MAX)
WITH ENCRYPTION
AS
DECLARE   @PARAMETROS       NVARCHAR(MAX),      @MODELO         VARCHAR(100)	,@METODO      VARCHAR(100)
        , @QUERY            VARCHAR(MAX),       @USUARIO        VARCHAR(12)	
        , @SEDE             VARCHAR(5)			,@FECHA       VARCHAR(20)			,@TIEMPO_COMIDA INT
        , @HORA             VARCHAR(10)       , @ITEM           INT		,@OBS         VARCHAR(2048)
        , @SYS_COMPUTERNAME VARCHAR(254)      , @GRUPO          VARCHAR(8)		,@ESTADO VARCHAR (20)
		, @PROCESO VARCHAR(50)		,@IDROL VARCHAR(20)		,@DESCRIPCION VARCHAR(200)	, @MARCADOS_ITEMS NVARCHAR(MAX), @MARCADOS BIT
		, @TIPO VARCHAR(20)	,@PROCEDENCIA VARCHAR(20)		,@UNIDATENCION VARCHAR(200)	, @SINESPECIALISTAS BIT, @SINGENERAL BIT
		,@BODEGAACTUAL BIT		,@SELECCIONADO BIT	,@IDARTICULO VARCHAR(20)	,@BODEGASELECCIONADA VARCHAR(20)
		,@COMPANIA VARCHAR(10), @FECHA_CTZ VARCHAR(8)	,@SYSCOMPUTERNAME VARCHAR(50)	, @CNSRPDX VARCHAR(20)	, @LONGITUD INT	, @PREFIJO VARCHAR(20)
		,@IDSEDE VARCHAR(20)	,@IDMEDICO VARCHAR(20)	,@HORAINI VARCHAR(5), @HORAFIN VARCHAR(5)	, @IDEMEDICA VARCHAR(20)
		,@DATOS VARCHAR(MAX)	,@RAZONSOCIAL VARCHAR(500)	, @TELEFONOS VARCHAR(20), @EMAIL VARCHAR(500)
		,@TIPO_ID VARCHAR(20), @DIRECCION VARCHAR(500), @NIT VARCHAR(50)	,	@IDSERVICIO  VARCHAR(20),  @NOREFERENCIA VARCHAR(50),  @VALOR DECIMAL(14,2)
DECLARE @Columnas NVARCHAR(MAX)	,@ITEM_NUEVO INT	, @CNSILPRE INT,  @CNSILPRED INT	, @IDTERCERO VARCHAR(20)	, @CNSICTZ	INT, @CNSICTZD INT
	,@FINICIAL VARCHAR(10), @FFINAL VARCHAR(10)	, @VLR_MIN_ACEPT DECIMAL(18,2)	, @CANTIDAD INT	,@OBSERVACION VARCHAR(500)	,@ColumnList NVARCHAR(MAX)  , @CNSFCOM VARCHAR(20)
	,@FECHAVENCE VARCHAR(10), @NOLOTEPEDIDO VARCHAR(20), @RINVIMA VARCHAR(50), @NOLOTE VARCHAR(20), @VLR_TOTAL DECIMAL(14,2)	, @IDBODEGA VARCHAR(20)
DECLARE @SQL NVARCHAR(MAX)	,@CCOSTO VARCHAR(20), @IDAREA VARCHAR(20), @PRIORIDAD INT
DECLARE @MIVA BIT, @IDIMPUESTO VARCHAR(20), @IDCLASE VARCHAR(20)
DECLARE @VALOR_IMPUESTO DECIMAL(14,2), @TIENEIVA SMALLINT
DECLARE @ITEM_INICIO INT
DECLARE @ITEM_FINAL INT
DECLARE @IDSEDEATENCION VARCHAR(20)
DECLARE @ColumnListWithAlias NVARCHAR(MAX)
DECLARE @ColumnListPivot NVARCHAR(MAX);
BEGIN
	SET LANGUAGE Spanish
	SET DATEFORMAT dmy
	SET DATEFIRST 1
	--SELECT @JSON
	SELECT *
	INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		MODELO  VARCHAR(100) '$.MODELO',
		METODO  VARCHAR(100) '$.METODO',
		USUARIO VARCHAR(20) '$.USUARIO',
		PARAMETROS NVARCHAR(MAX) AS JSON
	)
	SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON
	--DEFINICION DE TABLA DE ERRORES
	DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200));
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SEDE = IDSEDE, @IDSEDE = IDSEDE, @COMPANIA = COMPANIA FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	IF @METODO = 'DESCARGA_ESTRUCTURA_HOMOLOGACION'
	BEGIN
		SELECT 'OK' OK
		SELECT  NULL IDTERCERO, NULL IDSERVICIO, NULL CODCUM

		SELECT SER.IDSERVICIO, SER.DESCSERVICIO FROM SER WHERE SER.PREFIJO IN (DBO.FNK_VALORVARIABLE('PREFIJOMEDICAMENTOS'), DBO.FNK_VALORVARIABLE('PREFIJOMEDNOPOS'))
		AND SER.ESTADO = 'Inactivo'

		SELECT IDTERCERO, RAZONSOCIAL FROM TER WHERE EXISTS (SELECT 1 FROM TEXCA WHERE TEXCA.IDTERCERO = TER.IDTERCERO AND TEXCA.IDCATEGORIA = DBO.FNK_VALORVARIABLE('TERCATIFART') )
	END
	-- IMPORTAR LOTES (ICTZD / TER)
	IF @METODO = 'IMPORTAR_LOTE_1'
	BEGIN
		BEGIN TRY
			-- Obtener la fecha de la cotización
			SELECT @FECHA = FECHA
			FROM ICTZ
			WHERE CNSICTZ = (SELECT TOP 1 CNSICTZ FROM OPENJSON(@PARAMETROS, '$.DATOS')
							 WITH (CNSICTZ NVARCHAR(20) '$.CNSICTZ'))

			-- Tabla para errores de validación
			DECLARE @ERRORES_VALIDACION TABLE (
				IDARTICULO NVARCHAR(50),
				IDTERCERO NVARCHAR(50),
				RAZONSOCIAL NVARCHAR(200),
				DESCRIPCION NVARCHAR(200),
				ERROR NVARCHAR(500)
			)

			-- Validar que cada proveedor tenga precio para el artículo
			INSERT INTO @ERRORES_VALIDACION (IDARTICULO, IDTERCERO, RAZONSOCIAL, DESCRIPCION, ERROR)
			SELECT
				j.IDARTICULO,
				j.IDTERCERO,
				COALESCE(TER.RAZONSOCIAL, j.IDTERCERO),
				COALESCE(IART.DESCRIPCION, j.IDARTICULO),
				'Artículo: ' + COALESCE(IART.DESCRIPCION, j.IDARTICULO) +
				' | Proveedor: ' + COALESCE(TER.RAZONSOCIAL, j.IDTERCERO) +
				' - No tiene precio activo y vigente'
			FROM OPENJSON(@PARAMETROS, '$.DATOS')
			WITH (
				CNSICTZ    NVARCHAR(20) '$.CNSICTZ',
				IDTERCERO  NVARCHAR(50) '$.IDTERCERO',
				IDARTICULO NVARCHAR(50) '$.IDARTICULO'
			) AS j
			LEFT JOIN TER ON j.IDTERCERO = TER.IDTERCERO
			LEFT JOIN IART ON j.IDARTICULO = IART.IDARTICULO
			WHERE j.IDTERCERO IS NOT NULL
			  AND j.IDTERCERO != ''
			  AND NOT EXISTS (
				SELECT 1
				FROM ILPRE PRE
				INNER JOIN ILPRED PRED ON PRE.CNSILPRE = PRED.CNSILPRE
				WHERE PRE.IDTERCERO = j.IDTERCERO
				AND PRED.IDSERVICIO = j.IDARTICULO
				AND PRE.ESTADO = 'Activo'
				AND PRED.ESTADO = 'Activo'
				AND @FECHA BETWEEN PRE.FINICIAL AND PRE.FFINAL
			)

			-- Si hay errores, retornarlos
			IF EXISTS (SELECT 1 FROM @ERRORES_VALIDACION)
			BEGIN
				-- Concatenar todos los errores en un solo mensaje
				DECLARE @MSG_ERRORES NVARCHAR(MAX) = ''
				SELECT @MSG_ERRORES = @MSG_ERRORES + ERROR + CHAR(13) + CHAR(10)
				FROM @ERRORES_VALIDACION
		
				SELECT 'KO' AS OK, @MSG_ERRORES AS ERROR
				SELECT * FROM @ERRORES_VALIDACION
				RETURN
			END

			-- Si pasa validación, insertar con cálculo de VLR_TOTAL desde ILPRED usando PRIORIDAD
			-- ILPRED.VALOR = precio unitario SIN IVA; VLR_TOTAL en ICTZD = total línea CON IVA cuando aplica
			INSERT INTO ICTZD (CNSICTZ, IDTERCERO, IDSERVICIO, CANTIDAD, VLR_TOTAL)
			SELECT
				j.CNSICTZ,
				j.IDTERCERO,
				j.IDARTICULO AS IDSERVICIO,
				j.CANTIDAD,
				COALESCE((
					SELECT TOP 1
						CASE
							WHEN COALESCE(IART_IMP.MIVA, 0) = 1 AND COALESCE(FIMPDV_IMP.VALOR, 0) > 0 THEN
								ILPRED.VALOR * j.CANTIDAD * (1 + FIMPDV_IMP.VALOR / 100.0)
							ELSE
								ILPRED.VALOR * j.CANTIDAD
						END
					FROM ILPRED
					INNER JOIN ILPRE ON ILPRED.CNSILPRE = ILPRE.CNSILPRE
					INNER JOIN ICTZ ON ICTZ.CNSICTZ = j.CNSICTZ
					INNER JOIN IART IART_IMP ON ILPRED.IDSERVICIO = IART_IMP.IDARTICULO
					LEFT JOIN SER SER_IMP ON SER_IMP.IDSERVICIO = IART_IMP.IDARTICULO
					LEFT JOIN FIMPD FIMPD_IMP ON ISNULL(SER_IMP.IDIMPUESTO, IART_IMP.IDIMPUESTO) = FIMPD_IMP.IDIMPUESTO
						AND IART_IMP.IDCLASE_IMP = FIMPD_IMP.IDCLASE
					LEFT JOIN FIMPDV FIMPDV_IMP ON FIMPD_IMP.IDIMPUESTO = FIMPDV_IMP.IDIMPUESTO AND FIMPD_IMP.IDCLASE = FIMPDV_IMP.IDCLASE
					WHERE ILPRED.IDSERVICIO = j.IDARTICULO
					  AND ILPRE.IDTERCERO = j.IDTERCERO
					  AND ILPRED.ESTADO = 'Activo'
					  AND ILPRE.ESTADO = 'Activo'
					  AND CONVERT(DATE, ICTZ.FECHA) BETWEEN CONVERT(DATE, ILPRE.FINICIAL) AND CONVERT(DATE, ILPRE.FFINAL)
					ORDER BY COALESCE(ILPRED.PRIORIDAD, 999) ASC, ILPRED.VALOR ASC, ILPRED.CNSILPRED ASC
				), 0) AS VLR_TOTAL
			FROM OPENJSON(@PARAMETROS, '$.DATOS')
			WITH (
				CNSICTZ    NVARCHAR(20) '$.CNSICTZ',
				IDTERCERO  NVARCHAR(50) '$.IDTERCERO',
				IDARTICULO NVARCHAR(50) '$.IDARTICULO',
				CANTIDAD   DECIMAL(18,2) '$.CANTIDAD'
			) AS j
			WHERE NOT EXISTS (
				SELECT 1 FROM ICTZD i
				WHERE ISNULL(i.CNSICTZ,'') = ISNULL(j.CNSICTZ,'')
				  AND ISNULL(i.IDTERCERO,'') = ISNULL(j.IDTERCERO,'')
				  AND ISNULL(i.IDSERVICIO,'') = ISNULL(j.IDARTICULO,'')
			);

			-- Insertar proveedores que no existan
			INSERT INTO TER (IDTERCERO)
			SELECT DISTINCT j.IDTERCERO
			FROM OPENJSON(@PARAMETROS, '$.DATOS')
			WITH (IDTERCERO NVARCHAR(50) '$.IDTERCERO') AS j
			WHERE NOT EXISTS (
				SELECT 1 FROM TER t
				WHERE ISNULL(t.IDTERCERO,'') = ISNULL(j.IDTERCERO,'')
			);

			SELECT 'OK' AS OK;

		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) VALUES(ERROR_MESSAGE());
			SELECT 'KO' AS OK;
			SELECT ERROR FROM @TBLERRORES;
		END CATCH
		RETURN;
	END

	-- ============================================================
	-- CARGA MASIVA ICTZD (IDARTICULO + CANTIDAD + NIT proveedor)
	-- VALIDAR_MASIVO_ICTZD: solo valida; no inserta
	-- IMPORTAR_MASIVO_ICTZD: revalida e inserta (mismas reglas que GUARDA_ICTZD)
	-- DESCARGA_PLANTILLA_MASIVO_ICTZD: plantilla + catálogos de apoyo
	-- ============================================================
	IF @METODO IN ('VALIDAR_MASIVO_ICTZD', 'IMPORTAR_MASIVO_ICTZD')
	BEGIN
		DECLARE @ES_IMPORTAR BIT = CASE WHEN @METODO = 'IMPORTAR_MASIVO_ICTZD' THEN 1 ELSE 0 END

		SELECT @CNSICTZ = CNSICTZ, @DATOS = DATOS
		FROM OPENJSON(@PARAMETROS)
		WITH (CNSICTZ INT '$.CNSICTZ', DATOS NVARCHAR(MAX) AS JSON)

		IF COALESCE(@CNSICTZ, 0) = 0
		BEGIN
			SELECT 'KO' OK, 'No existe CNSICTZ de cotización.' ERROR
			RETURN
		END

		IF NOT EXISTS (SELECT 1 FROM ICTZ WHERE CNSICTZ = @CNSICTZ)
		BEGIN
			SELECT 'KO' OK, 'La cotización indicada no existe.' ERROR
			RETURN
		END

		IF EXISTS (SELECT 1 FROM ICTZ WHERE CNSICTZ = @CNSICTZ AND COALESCE(ESTADO, '') = 'Compra')
		BEGIN
			SELECT 'KO' OK, 'La cotización ya tiene orden de compra. No se puede cargar detalle.' ERROR
			RETURN
		END

		DECLARE @FECHA_COT_MASIVO DATE
		SELECT @FECHA_COT_MASIVO = CONVERT(DATE, FECHA) FROM ICTZ WHERE CNSICTZ = @CNSICTZ

		IF OBJECT_ID('tempdb..#CARGA_MASIVO') IS NOT NULL DROP TABLE #CARGA_MASIVO
		CREATE TABLE #CARGA_MASIVO (
			FILA INT,
			IDARTICULO VARCHAR(20),
			CANTIDAD DECIMAL(18,2),
			NIT VARCHAR(50),
			IDTERCERO VARCHAR(20) NULL,
			RAZONSOCIAL VARCHAR(500) NULL,
			DESCRIPCION VARCHAR(500) NULL,
			PRECIO_UNITARIO DECIMAL(18,4) NULL,
			VLR_TOTAL DECIMAL(18,2) NULL,
			MIVA BIT NULL,
			IDIMPUESTO VARCHAR(20) NULL,
			IDCLASE VARCHAR(20) NULL,
			VALOR_IMPUESTO DECIMAL(14,2) NULL,
			TIENEIVA SMALLINT NULL,
			ERROR NVARCHAR(500) NULL
		)

		INSERT INTO #CARGA_MASIVO (FILA, IDARTICULO, CANTIDAD, NIT)
		SELECT
			COALESCE(j.FILA, ROW_NUMBER() OVER (ORDER BY (SELECT NULL))) AS FILA,
			NULLIF(LTRIM(RTRIM(j.IDARTICULO)), ''),
			TRY_CONVERT(DECIMAL(18,2), j.CANTIDAD),
			NULLIF(REPLACE(REPLACE(LTRIM(RTRIM(j.NIT)), '.', ''), '-', ''), '')
		FROM OPENJSON(@DATOS)
		WITH (
			FILA INT '$.FILA',
			IDARTICULO VARCHAR(50) '$.IDARTICULO',
			CANTIDAD NVARCHAR(50) '$.CANTIDAD',
			NIT VARCHAR(50) '$.NIT'
		) j

		IF NOT EXISTS (SELECT 1 FROM #CARGA_MASIVO)
		BEGIN
			SELECT 'KO' OK, 'El archivo no contiene filas para procesar.' ERROR
			RETURN
		END

		-- Artículo obligatorio / existe / activo / no principal
		UPDATE C SET ERROR = COALESCE(ERROR + ' | ', '') + 'IDARTICULO es obligatorio'
		FROM #CARGA_MASIVO C WHERE C.IDARTICULO IS NULL

		UPDATE C SET
			DESCRIPCION = IART.DESCRIPCION,
			ERROR = CASE
				WHEN COALESCE(IART.ESTADO, '') NOT IN ('', 'Activo') THEN COALESCE(C.ERROR + ' | ', '') + 'El artículo está inactivo'
				WHEN COALESCE(IART.PRINCIPAL, 0) = 1 THEN COALESCE(C.ERROR + ' | ', '') + 'El artículo es principal y no se puede cotizar'
				ELSE C.ERROR
			END
		FROM #CARGA_MASIVO C
		INNER JOIN IART ON IART.IDARTICULO = C.IDARTICULO
		WHERE C.IDARTICULO IS NOT NULL

		UPDATE C SET ERROR = COALESCE(ERROR + ' | ', '') + 'El artículo no existe en IART'
		FROM #CARGA_MASIVO C
		WHERE C.IDARTICULO IS NOT NULL
		  AND NOT EXISTS (SELECT 1 FROM IART WHERE IART.IDARTICULO = C.IDARTICULO)

		-- Cantidad
		UPDATE C SET ERROR = COALESCE(ERROR + ' | ', '') + 'CANTIDAD debe ser mayor a 0'
		FROM #CARGA_MASIVO C
		WHERE C.CANTIDAD IS NULL OR C.CANTIDAD <= 0

		-- NIT obligatorio
		UPDATE C SET ERROR = COALESCE(ERROR + ' | ', '') + 'NIT del proveedor es obligatorio'
		FROM #CARGA_MASIVO C WHERE C.NIT IS NULL

		-- Resolver proveedor por NIT (prioriza categoría IFART)
		;WITH TER_NIT AS (
			SELECT
				C.FILA,
				TER.IDTERCERO,
				TER.RAZONSOCIAL,
				ROW_NUMBER() OVER (
					PARTITION BY C.FILA
					ORDER BY CASE WHEN TEXCA.IDTERCERO IS NOT NULL THEN 0 ELSE 1 END, TER.IDTERCERO
				) AS RN,
				COUNT(*) OVER (PARTITION BY C.FILA) AS CNT
			FROM #CARGA_MASIVO C
			INNER JOIN TER ON REPLACE(REPLACE(LTRIM(RTRIM(TER.NIT)), '.', ''), '-', '') = C.NIT
			LEFT JOIN TEXCA ON TEXCA.IDTERCERO = TER.IDTERCERO
				AND TEXCA.IDCATEGORIA = DBO.FNK_VALORVARIABLE('TERCATIFART')
				AND COALESCE(TEXCA.ESTADO, 'Activo') = 'Activo'
			WHERE C.NIT IS NOT NULL
		)
		UPDATE C SET
			IDTERCERO = T.IDTERCERO,
			RAZONSOCIAL = T.RAZONSOCIAL,
			ERROR = CASE
				WHEN T.CNT > 1 AND T.RN = 1 THEN
					-- Si hay varios pero ya priorizamos IFART, aceptamos el RN=1 sin error
					C.ERROR
				ELSE C.ERROR
			END
		FROM #CARGA_MASIVO C
		INNER JOIN TER_NIT T ON T.FILA = C.FILA AND T.RN = 1

		UPDATE C SET ERROR = COALESCE(ERROR + ' | ', '') + 'No existe tercero con ese NIT'
		FROM #CARGA_MASIVO C
		WHERE C.NIT IS NOT NULL AND C.IDTERCERO IS NULL

		-- Precio vigente ILPRE/ILPRED + total con IVA (misma lógica de GUARDA / selección manual)
		UPDATE C SET
			PRECIO_UNITARIO = P.PRECIO_UNITARIO,
			VLR_TOTAL = P.VLR_TOTAL,
			MIVA = P.MIVA,
			IDIMPUESTO = P.IDIMPUESTO,
			IDCLASE = P.IDCLASE,
			VALOR_IMPUESTO = P.VALOR_IMPUESTO,
			TIENEIVA = P.TIENEIVA
		FROM #CARGA_MASIVO C
		CROSS APPLY (
			SELECT TOP 1
				ILPRED.VALOR AS PRECIO_UNITARIO,
				CASE
					WHEN COALESCE(IART_IMP.MIVA, 0) = 1 AND COALESCE(FIMPDV_IMP.VALOR, 0) > 0 THEN
						ROUND(ILPRED.VALOR * C.CANTIDAD * (1 + FIMPDV_IMP.VALOR / 100.0), 2)
					ELSE
						ROUND(ILPRED.VALOR * C.CANTIDAD, 2)
				END AS VLR_TOTAL,
				CAST(COALESCE(IART_IMP.MIVA, 0) AS BIT) AS MIVA,
				ISNULL(SER_IMP.IDIMPUESTO, IART_IMP.IDIMPUESTO) AS IDIMPUESTO,
				IART_IMP.IDCLASE_IMP AS IDCLASE,
				CAST(COALESCE(FIMPDV_IMP.VALOR, 0) AS DECIMAL(14,2)) AS VALOR_IMPUESTO,
				CAST(CASE WHEN COALESCE(IART_IMP.MIVA, 0) = 1 AND COALESCE(FIMPDV_IMP.VALOR, 0) > 0 THEN 1 ELSE 0 END AS SMALLINT) AS TIENEIVA
			FROM ILPRED
			INNER JOIN ILPRE ON ILPRED.CNSILPRE = ILPRE.CNSILPRE
			INNER JOIN IART IART_IMP ON ILPRED.IDSERVICIO = IART_IMP.IDARTICULO
			LEFT JOIN SER SER_IMP ON SER_IMP.IDSERVICIO = IART_IMP.IDARTICULO
			LEFT JOIN FIMPD FIMPD_IMP ON ISNULL(SER_IMP.IDIMPUESTO, IART_IMP.IDIMPUESTO) = FIMPD_IMP.IDIMPUESTO
				AND IART_IMP.IDCLASE_IMP = FIMPD_IMP.IDCLASE
			LEFT JOIN FIMPDV FIMPDV_IMP ON FIMPD_IMP.IDIMPUESTO = FIMPDV_IMP.IDIMPUESTO AND FIMPD_IMP.IDCLASE = FIMPDV_IMP.IDCLASE
			WHERE ILPRED.IDSERVICIO = C.IDARTICULO
			  AND ILPRE.IDTERCERO = C.IDTERCERO
			  AND ILPRED.ESTADO = 'Activo'
			  AND ILPRE.ESTADO = 'Activo'
			  AND @FECHA_COT_MASIVO BETWEEN CONVERT(DATE, ILPRE.FINICIAL) AND CONVERT(DATE, ILPRE.FFINAL)
			ORDER BY COALESCE(ILPRED.PRIORIDAD, 999) ASC, ILPRED.VALOR ASC, ILPRED.CNSILPRED ASC
		) P
		WHERE C.IDARTICULO IS NOT NULL AND C.IDTERCERO IS NOT NULL AND C.CANTIDAD > 0

		UPDATE C SET ERROR = COALESCE(ERROR + ' | ', '') +
			'No hay precio activo/vigente en lista de precios (ILPRE) para este artículo y proveedor'
		FROM #CARGA_MASIVO C
		WHERE C.IDARTICULO IS NOT NULL AND C.IDTERCERO IS NOT NULL
		  AND (C.PRECIO_UNITARIO IS NULL OR C.VLR_TOTAL IS NULL OR C.VLR_TOTAL <= 0)

		-- Duplicado en el Excel (mismo artículo)
		UPDATE C SET ERROR = COALESCE(ERROR + ' | ', '') + 'Artículo duplicado en el archivo Excel'
		FROM #CARGA_MASIVO C
		WHERE C.IDARTICULO IS NOT NULL
		  AND EXISTS (
			SELECT 1 FROM #CARGA_MASIVO X
			WHERE X.IDARTICULO = C.IDARTICULO AND X.FILA <> C.FILA
		  )

		-- Ya existe en la cotización
		UPDATE C SET ERROR = COALESCE(ERROR + ' | ', '') + 'El artículo ya existe en esta cotización'
		FROM #CARGA_MASIVO C
		WHERE C.IDARTICULO IS NOT NULL
		  AND EXISTS (
			SELECT 1 FROM ICTZD
			WHERE ICTZD.CNSICTZ = @CNSICTZ AND ICTZD.IDSERVICIO = C.IDARTICULO
		  )

		IF EXISTS (SELECT 1 FROM #CARGA_MASIVO WHERE ERROR IS NOT NULL)
		BEGIN
			SELECT 'KO' OK,
				CAST((SELECT COUNT(*) FROM #CARGA_MASIVO WHERE ERROR IS NOT NULL) AS VARCHAR(20)) +
				' fila(s) con error. Descargue el Excel de errores.' ERROR
			SELECT
				FILA, IDARTICULO, DESCRIPCION, CANTIDAD, NIT, IDTERCERO, RAZONSOCIAL,
				PRECIO_UNITARIO, VLR_TOTAL, ERROR
			FROM #CARGA_MASIVO
			ORDER BY FILA
			RETURN
		END

		-- Vista previa OK
		SELECT 'OK' OK,
			CAST((SELECT COUNT(*) FROM #CARGA_MASIVO) AS VARCHAR(20)) + ' fila(s) válidas.' MENSAJE

		SELECT
			FILA, IDARTICULO, DESCRIPCION, CANTIDAD, NIT, IDTERCERO, RAZONSOCIAL,
			PRECIO_UNITARIO, VLR_TOTAL, MIVA, IDIMPUESTO, IDCLASE, VALOR_IMPUESTO, TIENEIVA
		FROM #CARGA_MASIVO
		ORDER BY FILA

		IF @ES_IMPORTAR = 1
		BEGIN
			BEGIN TRY
				INSERT INTO ICTZD (
					CNSICTZ, IDSERVICIO, NOREFERENCIA, CANTIDAD,
					MIVA, IDIMPUESTO, IDCLASE, VALOR_IMPUESTO, TIENEIVA,
					IDTERCERO, VLR_TOTAL
				)
				SELECT
					@CNSICTZ, C.IDARTICULO, NULL, C.CANTIDAD,
					C.MIVA, C.IDIMPUESTO, C.IDCLASE, C.VALOR_IMPUESTO, C.TIENEIVA,
					C.IDTERCERO, C.VLR_TOTAL
				FROM #CARGA_MASIVO C
				WHERE NOT EXISTS (
					SELECT 1 FROM ICTZD I
					WHERE I.CNSICTZ = @CNSICTZ AND I.IDSERVICIO = C.IDARTICULO
				)
			END TRY
			BEGIN CATCH
				SELECT 'KO' OK, ERROR_MESSAGE() ERROR
				RETURN
			END CATCH

			SELECT 'OK' OK, 'Importación completada' MENSAJE
		END

		RETURN
	END

	IF @METODO = 'DESCARGA_PLANTILLA_MASIVO_ICTZD'
	BEGIN
		SELECT @CNSICTZ = CNSICTZ
		FROM OPENJSON(@PARAMETROS)
		WITH (CNSICTZ INT '$.CNSICTZ')

		SELECT 'OK' OK

		-- Hoja plantilla (3 filas de ejemplo vacías)
		SELECT CAST(NULL AS VARCHAR(20)) AS IDARTICULO,
			   CAST(NULL AS DECIMAL(18,2)) AS CANTIDAD,
			   CAST(NULL AS VARCHAR(50)) AS NIT
		WHERE 1 = 0
		UNION ALL
		SELECT NULL, NULL, NULL
		UNION ALL
		SELECT NULL, NULL, NULL
		UNION ALL
		SELECT NULL, NULL, NULL

		-- Catálogo artículos (no principales)
		SELECT IART.IDARTICULO, IART.CODCUM, IART.DESCRIPCION, ITAR.DESCRIPCION AS TIPO_ARTICULO
		FROM IART
		INNER JOIN ITAR ON IART.IDITAR = ITAR.IDITAR
		WHERE COALESCE(IART.PRINCIPAL, 0) = 0
