IF EXISTS (SELECT name FROM sysobjects WHERE name = 'SPK_ESTADO_ADMI_PE' AND type = 'P')
   DROP PROCEDURE SPK_ESTADO_ADMI_PE
GO
CREATE PROC DBO.SPK_ESTADO_ADMI_PE
@NOADMISION VARCHAR(16),
@RPDX       VARCHAR(20),
@PASO       VARCHAR(1) = ''
WITH ENCRYPTION
AS
DECLARE @CONT                 INT
DECLARE @COPAGONOAUTORIZACION VARCHAR(20)
DECLARE @COPAGOVALOR          DECIMAL(14,2)
DECLARE @VALOR                DECIMAL(14,2)
DECLARE @NOPRESTACION         VARCHAR(16)
DECLARE @DATO                 VARCHAR(80)
DECLARE @IDPLAN               VARCHAR(6) 
DECLARE @CERRADA              SMALLINT
DECLARE @MAN_COPAGOEXT		   SMALLINT
DECLARE @VLR_COPAGOEXTERNO	   DECIMAL(14,2)
DECLARE @TIPOADM              VARCHAR(2)
DECLARE @USACTC               SMALLINT
DECLARE @CONTAR               INT
DECLARE @NOAUTORIZACION			VARCHAR(20)
DECLARE @IDSEDE					VARCHAR(5)
DECLARE @IDTERCERO				VARCHAR(20)
BEGIN
   SELECT @CONT = ISNULL(COUNT(*),0) FROM HPRE WHERE NOADMISION = @NOADMISION AND ISNULL(ANULADO,0)=0 --SJUNCO REQ 1803
   
   IF @CONT = 0
   BEGIN
      PRINT 'SIN CARGOS'
      INSERT INTO RPDX ( CNS, NOMBRE ) 
      SELECT @RPDX, 'ADMISION SIN PRESTACIONES (CARGOS)'
      RETURN
   END
   IF EXISTS(SELECT * FROM HADM INNER JOIN AFI ON HADM.IDAFILIADO=AFI.IDAFILIADO 
   WHERE HADM.NOADMISION=@NOADMISION AND LEN(COALESCE(AFI.IDALTERNA,''))<15)
   BEGIN 
      --PRINT 'SIN CARGOS'
      --INSERT INTO RPDX ( CNS, NOMBRE ) 
      --SELECT @RPDX, LEFT('AFILIADO SIN CODIGO DE AFILIACION, NO SE PUEDE CONTINUAR...',150)
      --RETURN
      UPDATE AFI SET AFI.IDALTERNA=REPLACE(SPACE(15-LEN(AFI.IDALTERNA)),SPACE(1),0)+AFI.IDALTERNA
      FROM HADM INNER JOIN AFI ON HADM.IDAFILIADO=AFI.IDAFILIADO 
      WHERE HADM.NOADMISION=@NOADMISION AND LEN(COALESCE(AFI.IDALTERNA,''))<15
   END
   PRINT 'REVISO SI EL CONTRATO PIDE SEDE ATENCION'
   IF EXISTS(SELECT * FROM HADM INNER JOIN PPT ON HADM.IDTERCERO=PPT.IDTERCERO AND HADM.IDPLAN=PPT.IDPLAN AND HADM.NOADMISION=@NOADMISION AND COALESCE(PPT.PSEDEAT,0)=1)
   BEGIN
      IF EXISTS(SELECT * FROM HADMAUT WHERE NOADMISION=@NOADMISION AND (COALESCE(SEDEAT,'')='' OR COALESCE(SEDEAT,'')='00'))
      BEGIN
	      INSERT INTO RPDX (CNS, NOMBRE)
         SELECT @RPDX, LEFT('Existen Autorizaciones sin Sede de Atención, Dato Requerido para Facturar',150)          
      END
   END
   RETURN
   DELETE HPRE WHERE NOADMISION=@NOADMISION AND NOT EXISTS(SELECT * FROM HPRED WHERE HPRED.NOPRESTACION=HPRE.NOPRESTACION)
   IF DBO.FNK_VALORVARIABLE('MOV_SIN_CERRAR')='SI'
   BEGIN
      PRINT 'MIRO SOLICITUDES DE FARMACIA'
      IF ( SELECT COUNT(1) FROM IZSOL WHERE IZSOL.NOADMISION=@NOADMISION AND COALESCE(IZSOL.ESTADO,0)=1 AND CLASE NOT IN ('HPRE','AUT','CE'))>0
      BEGIN 
         INSERT INTO RPDX (CNS, NOMBRE)
         SELECT @RPDX,LEFT('Solicitudes sin cerrar de farmacia: '+  IZSOL.CNSIZSOL ,150)  
         FROM IZSOL 
         WHERE IZSOL.NOADMISION=@NOADMISION AND IZSOL.ESTADO=1 AND CLASE NOT IN ('HPRE','AUT','CE')
      END
   
      PRINT 'MIRO MOVIMIENTOS DE FARMACIA'
      IF (  SELECT COUNT(1) FROM IZSOL 
      INNER JOIN IMOV ON IZSOL.CNSIZSOL=IMOV.NODOCUMENTO AND IMOV.PROCEDENCIA='CM_SOL'
      WHERE IZSOL.NOADMISION=@NOADMISION AND COALESCE(IMOV.ESTADO,0)=0)>0
      BEGIN 
         INSERT INTO RPDX (CNS, NOMBRE)
         SELECT @RPDX,LEFT('Movimientos de inventario sin cerrar: '+  IMOV.CNSMOV ,150)  FROM IZSOL 
            INNER JOIN IMOV ON IZSOL.CNSIZSOL=IMOV.NODOCUMENTO AND IMOV.PROCEDENCIA='CM_SOL'
            WHERE IZSOL.NOADMISION=@NOADMISION AND COALESCE(IMOV.ESTADO,0)=0
      END
   END
   PRINT 'MIRAR HPRE SIN HPRED O HPRED CON VALORES EN 0'
   DECLARE PRESTACIOND_CURSOR CURSOR FOR  
   SELECT NOPRESTACION FROM HPRE WHERE NOADMISION = @NOADMISION AND ISNULL(ANULADO,0)=0 --SJUNCO REQ 1803
   OPEN PRESTACIOND_CURSOR  
   FETCH NEXT FROM PRESTACIOND_CURSOR  
   INTO @NOPRESTACION
   WHILE @@FETCH_STATUS = 0  
   BEGIN        
      SELECT @CONT = COALESCE(COUNT(*),0) FROM HPRED WHERE HPRED.NOPRESTACION = @NOPRESTACION --SJUNCO REQ 1803
      IF @CONT = 0
      BEGIN
         INSERT INTO RPDX ( CNS, NOMBRE ) 
         SELECT @RPDX, 'PRESTACION '+@NOPRESTACION+' SIN DETALLES'         
      END
      
      SELECT @CONT = COUNT(*) FROM HPRED 
      WHERE  HPRED.NOPRESTACION = @NOPRESTACION
      AND    COALESCE(HPRED.VALOR,0)        = 0 
      AND    COALESCE(HPRED.NOCOBRABLE,0)   = 0
      AND    ISNULL(ANULADO,0)  = 0 --SJUNCO REQ 1803
      AND    COALESCE(HPRED.ENCARGOS,0) = 0
      IF @CONT > 0
      BEGIN
         INSERT INTO RPDX ( CNS, NOMBRE ) 
         SELECT @RPDX, 'PRESTACION '+RTRIM(LTRIM(@NOPRESTACION))+' Tiene Detalles con valor en 0'         
      END
           
      FETCH NEXT FROM PRESTACIOND_CURSOR  
      INTO @NOPRESTACION
   END
   CLOSE PRESTACIOND_CURSOR  
   DEALLOCATE PRESTACIOND_CURSOR  

	IF EXISTS(	SELECT DISTINCT HPRE.NOPRESTACION 
               FROM   HPRE INNER JOIN HPRED ON HPRED.NOPRESTACION = HPRE.NOPRESTACION
				   WHERE  HPRE.VALORTOTAL = 0 
               AND    HPRED.NOCOBRABLE <> 1 
               AND    HPRE.NOADMISION = @NOADMISION 
               AND    COALESCE(HPRE.ANULADO,0)   = 0--SJUNCO REQ 1803
               AND    COALESCE(HPRED.ENCARGOS,0) = 0 )
	BEGIN
	   INSERT INTO RPDX ( CNS, NOMBRE ) 
	   SELECT DISTINCT @RPDX, HPRED.NOPRESTACION+': PRESTACION COBRABLE CON VALOR CERO O CON VALOR NULO '
      FROM   HPRE INNER JOIN HPRED ON HPRED.NOPRESTACION = HPRE.NOPRESTACION
		WHERE  HPRE.VALORTOTAL = 0 
      AND    HPRED.NOCOBRABLE <> 1 
      AND    HPRE.NOADMISION = @NOADMISION 
      AND    COALESCE(HPRE.ANULADO,0)   = 0--SJUNCO REQ 1803
      AND    COALESCE(HPRED.ENCARGOS,0) = 0
      AND    COALESCE(HPRED.FACTURADA,0) = 0
	END
   /* NO PERMITIR PRESTACIONES NO COBRABLES CON VALOR MAYOR A CERO */
   IF EXISTS(	SELECT DISTINCT HPRE.NOPRESTACION 
               FROM   HPRE INNER JOIN HPRED ON HPRED.NOPRESTACION = HPRE.NOPRESTACION
               AND    COALESCE(HPRED.NOCOBRABLE,0) = 1
               AND    HPRE.NOADMISION = @NOADMISION 
               AND    COALESCE(HPRE.ANULADO,0)   = 0 
               AND    COALESCE(HPRED.ENCARGOS,0) = 0
               AND    COALESCE(HPRED.FACTURADA,0) = 0
               AND    (HPRED.VALOR>0 OR HPRED.VALOREXCEDENTE>0) )
	BEGIN
	   INSERT INTO RPDX ( CNS, NOMBRE ) 
	   SELECT DISTINCT @RPDX, HPRED.NOPRESTACION+': PRESTACION NO COBRABLE CON VALOR MAYOR A CERO - IDSERVICIO: '+HPRED.IDSERVICIO
      FROM   HPRE INNER JOIN HPRED ON HPRED.NOPRESTACION = HPRE.NOPRESTACION
      AND    COALESCE(HPRED.NOCOBRABLE,0) = 1
      AND    HPRE.NOADMISION = @NOADMISION 
      AND    COALESCE(HPRE.ANULADO,0)   = 0 
      AND    COALESCE(HPRED.ENCARGOS,0) = 0
      AND    COALESCE(HPRED.FACTURADA,0) = 0
      AND    (HPRED.VALOR>0 OR HPRED.VALOREXCEDENTE>0)
	END

   /*NO PERMITIR VALORES DE CANTIDADES NEGATIVAS NI VALORES NEGATIVOS   JEDM.2011.10.10*/
   IF (	SELECT COALESCE(COUNT(*),0)
         FROM   HPRE INNER JOIN HPRED ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
			WHERE  HPRED.CANTIDAD < 0 
         AND    HPRED.NOCOBRABLE <> 1 
         AND    HPRE.NOADMISION = @NOADMISION 
         AND    COALESCE(HPRE.ANULADO,0)   = 0--SJUNCO REQ 1803
         AND    COALESCE(HPRED.ENCARGOS,0) = 0 ) > 0        
	BEGIN
	   INSERT INTO RPDX ( CNS, NOMBRE ) 
	   SELECT @RPDX, 'PRESTACIONES CON CANTIDAD NEGATIVA, NOPRESTACION = '+HPRED.NOPRESTACION
	   FROM   HPRE INNER JOIN HPRED ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
		WHERE  HPRED.CANTIDAD < 0 
      AND    HPRE.NOADMISION = @NOADMISION 
      AND    COALESCE(HPRE.ANULADO,0)   = 0--SJUNCO REQ 1803
      AND    COALESCE(HPRED.ENCARGOS,0) = 0
	END
   IF (	SELECT COALESCE(COUNT(*),0)
         FROM   HPRE INNER JOIN HPRED ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
			WHERE  COALESCE(HPRED.VALOR,0) < 0 
         AND    HPRE.NOADMISION = @NOADMISION 
         AND    COALESCE(HPRE.ANULADO,0)   = 0--SJUNCO REQ 1803
         AND    COALESCE(HPRED.ENCARGOS,0) = 0 ) > 0        
	BEGIN
	   INSERT INTO RPDX ( CNS, NOMBRE ) 
	   SELECT @RPDX, 'PRESTACIONES CON VALORES NEGATIVOS, NOPRESTACION = '+HPRED.NOPRESTACION
	   FROM   HPRE INNER JOIN HPRED ON HPRE.NOPRESTACION = HPRED.NOPRESTACION
		WHERE  HPRED.CANTIDAD < 0 
      AND    HPRED.NOCOBRABLE <> 1 
      AND    HPRE.NOADMISION = @NOADMISION 
      AND    COALESCE(HPRE.ANULADO,0)   = 0--SJUNCO REQ 1803
      AND    COALESCE(HPRED.ENCARGOS,0) = 0
	END

   IF DBO.FNK_VALORVARIABLE('ASI_VAL_CCAF_CARGOS')='SI'
   BEGIN
      PRINT 'Revision de KMCOM Antes de Facturar'
      IF NOT EXISTS(SELECT * FROM KMCOM INNER JOIN HPRE ON HPRE.PREFIJO=KMCOM.PREFIJO AND HPRE.IDAREA=KMCOM.IDAREA AND HPRE.CCOSTO=KMCOM.CCOSTO 
                     WHERE KMCOM.IDMODELOCONT=DBO.FNK_VALORVARIABLE('IDMODELOCONTABLE')
                     AND KMCOM.IDTIPOCONT='VENTAS'
                     AND HPRE.NOADMISION=@NOADMISION)
      BEGIN 
	      INSERT INTO RPDX (CNS, NOMBRE)
         SELECT @RPDX, LEFT('No Existe Configuración Contable para las Siguientes Prestaciones',150) 
         INSERT INTO RPDX (CNS, NOMBRE)
         SELECT @RPDX,'Prestacion: '+HPRE.NOPRESTACION+' PREFIJO: '+HPRE.PREFIJO+' IDAREA: '+HPRE.IDAREA+' CCOSTO: '+HPRE.CCOSTO
         FROM HPRE WHERE NOT EXISTS(SELECT * FROM KMCOM WHERE  HPRE.PREFIJO=KMCOM.PREFIJO AND HPRE.IDAREA=KMCOM.IDAREA AND HPRE.CCOSTO=KMCOM.CCOSTO 
         AND  KMCOM.IDMODELOCONT=DBO.FNK_VALORVARIABLE('IDMODELOCONTABLE')
         AND KMCOM.IDTIPOCONT='VENTAS')
         AND HPRE.NOADMISION=@NOADMISION
      END
   END
END

