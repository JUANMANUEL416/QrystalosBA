CREATE OR ALTER PROCEDURE DBO.SPQ_ORDEN_PAGO
@JSON  NVARCHAR(MAX) 
WITH
ENCRYPTION
AS
DECLARE  @PARAMETROS        NVARCHAR(MAX)               ,@MODELO            VARCHAR(100)                    ,@METODO            VARCHAR(100)  
        ,@USUARI            VARCHAR(12)                 ,@GRUPO             VARCHAR(8)                      ,@SYS_COMPUTERNAME  VARCHAR(254) 
        ,@IDSEDE            VARCHAR(5)                  ,@USUNOMBRE         VARCHAR(100)                    ,@SEDE              VARCHAR(5)
        ,@FECHA             DATE                        ,@IDEMEDICA         VARCHAR(4)	                    ,@FECHA1            DATETIME		
        ,@SQL               VARCHAR(MAX)                ,@CODCAJERO		    VARCHAR(20)                     ,@COMPANIA		    VARCHAR(10)	
        ,@IDAFILIADO        VARCHAR(20)	                ,@IDMEDICO	        VARCHAR(20)	                    ,@FECHAINI          DATE	
        ,@FECHAFIN	        DATE	                    ,@CONSECUTIVOS	    NVARCHAR(MAX)	                ,@MARCAR            BIT	   
        ,@NOAUTORIZACION    VARCHAR(50)	                ,@CONSECUTIVO       VARCHAR(20)                     ,@OBSERVACION	    VARCHAR (200)	
        ,@IDCAUSAL          VARCHAR(20)	                ,@IDSERVICIO        VARCHAR(20)	                    ,@DATO              INT		
        ,@CNSIZSOL          VARCHAR(20)            		,@CONSECUTIVOCAN    VARCHAR(20)
        ,@IDAUT             VARCHAR(20)		            ,@VR_TOTAL          DECIMAL(14,2)                   ,@VLRDEPOSITOS      DECIMAL(14,2) 
		,@MENSAJE           VARCHAR(500)		        ,@PROCESO           VARCHAR(50)	                    ,@PROCEDENCIA       VARCHAR(20)
        ,@ITEM              INT		                    ,@TIPOFAC           VARCHAR(20)                     ,@LIMITE            INT
		,@CNSFCXPPM         VARCHAR(20)		            ,@CNSFACJ           VARCHAR(20)	                    ,@CODCAJA           VARCHAR(20)	
        ,@CNSFCXPP          VARCHAR(20)                 ,@CNSFCXP           VARCHAR(20)                     ,@ITEM_CANT         INT
		,@ESTADO            VARCHAR (20)	            ,@F_FACTURAREF      DATE	                        ,@CONTABILIZADA     INT	
        ,@VALOR             DECIMAL(14,2)	            ,@VLR_ABONO         DECIMAL(14,2)	                ,@CNSFCOM           VARCHAR(20)
		,@VLR_ANTICIPO      DECIMAL(14,2)	            ,@SALDOANTE         DECIMAL(14,2)	                ,@IDTERCERO         VARCHAR(20)	
        ,@dataFCXPPM_Sel    NVARCHAR(MAX)               ,@FECHA_TIME        DATETIME                        ,@ANIO              VARCHAR(20)	
        ,@MES               INT	                        ,@ABONO             DECIMAL(14,2)	                ,@FECHAPPAGO        DATE	
        ,@VALORPPAGO        DECIMAL(14,2)               ,@WHERE_DATA        VARCHAR(MAX)                    ,@sqlCommand        Nvarchar(max)
		,@LINEA             VARCHAR(MAX)                ,@NROLINEAS         INT                             ,@CNSRPDX           VARCHAR(20)
        ,@ERROR             VARCHAR(120)                ,@INDICE            INT                             ,@DATOS             VARCHAR(MAX)     
		,@SICXP             INT                         ,@ENPRESUPUESTO     INT                             ,@CNSRP             VARCHAR(20)
        ,@CNSPPTO           VARCHAR(20)                 ,@CNSCDP            VARCHAR(20)                     ,@NROCOMPROBANTE    VARCHAR(50)
		,@ESTADO_FCXP       VARCHAR(20)                 ,@USUARIO           VARCHAR(20)                     ,@VLR_ANTICIPOS_LIQ DECIMAL(14,2)
        ,@VLR_ORIGEN_LIQ    DECIMAL(14,2)                                                                                                   

DECLARE @CNSFCXPs_JSON            NVARCHAR(MAX),         @CUECREDITO         VARCHAR(20),                    @CNSFCXPPM_ACTUAL   VARCHAR(20),      
        @CANTIDAD_ORDENES         INT,
		@ESTADO_FILTRO            VARCHAR(20),           @NOMBRE_ARCHIVO     VARCHAR(255),                   @CANTIDAD_REGISTROS INT,              
		@VALOR_TOTAL              DECIMAL(14,2),         @TIPO_TRANSACCION   VARCHAR(10),                    @CNSFCXPPH          VARCHAR(20),                    
		@CANTIDAD_REGISTROS_LOCAL INT,                   @VALOR_TOTAL_LOCAL  DECIMAL(14,2),                  @TIPO_TRANSACCION_LOCAL  VARCHAR(10),      
		@OBSERVACION_LOCAL        VARCHAR(MAX),          @CNSFCXPPH_LOCAL    VARCHAR(20),                    @PRE_LOCAL               VARCHAR(20),                    
		@PRE                      VARCHAR(20),           @NOMBRE_ARCHIVO_LOCAL      VARCHAR(255),            @CNSFCXPPM_JSON_LOCAL    NVARCHAR(MAX);

DECLARE @CODCAJA_ORDEN_TER VARCHAR(20),                     @IDTERCERO_AFAVOR_ORDEN_TER VARCHAR(20),        @FECHA_ORDEN_TER DATETIME,
		@OBSERVACION_ORDEN_TER VARCHAR(255),                @CONCEPTO_EGRESO_TER VARCHAR(20),               @CODUNG_ORDEN_TER VARCHAR(20),                      
		@CNSACJ_ORDEN_TER VARCHAR(20),                      @CNSFCXP_DESAUTH VARCHAR(20),                   @CNSFCXPP_DESAUTH VARCHAR(20),
		@IDTERCERO_ACTUAL_TER VARCHAR(20),                  @TOTAL_ABONO_TERCERO_TER DECIMAL(14,2),         @CNSFACJ_ACTUAL_TER VARCHAR(20),
		@TOTAL_PROCESADOS_TER INT = 0,                      @TOTAL_TERCEROS_TER INT = 0,                    @CXP_PROCESADAS_TERCERO_TER INT,
		@FORMA_PAGO_ORDEN_TER VARCHAR(20),                  @BANCO_PAGO_ORDEN_TER VARCHAR(20),              @CTA_BCO_PAGO_ORDEN_TER VARCHAR(50),
		@SUCURSAL_PAGO_ORDEN_TER VARCHAR(50),               @IDTERCERO_PAGO_ORDEN_TER VARCHAR(20),          @NUMERODOCUMENTO_PAGO_ORDEN_TER VARCHAR(50),
		@NUMEROAUTORIZA_PAGO_ORDEN_TER VARCHAR(50),         @TIPOEGRESO_CXP_TER VARCHAR(20),                @CODCAJA_DESAUTH VARCHAR(20),
		@CUENTA_PCJ_TER VARCHAR(20),                        @CNSPCJ_ACTUAL_TER VARCHAR(20),                 @CNSFACJ_DESAUTH VARCHAR(20),
		@CNSFCXPPM_DESAUTH VARCHAR(20)                     

DECLARE @EGRESOS_JSON_MASIVO NVARCHAR(MAX),                 @CNSFCXPPM_MASIVO VARCHAR(20),                  @CNSFACJ_MASIVO VARCHAR(20),
        @CODCAJA_MASIVO VARCHAR(20),                        @CNSACJ_MASIVO VARCHAR(20),                     @FECHAFCJ_MASIVO DATETIME,
        @TOTAL_FCJ_MASIVO DECIMAL(14,2),                    @ESTADO_FCJ_MASIVO VARCHAR(20),                 @PROCEDENCIA_FCJ_MASIVO VARCHAR(20),
        @CERRADA_FCJ_MASIVO INT,                            @VLR_PCJ_MASIVO DECIMAL(14,2),                  @CONFIRMADOS_MASIVO INT = 0,
        @CANT_EGRESOS_MASIVO INT = 0,                       @CANT_ORDENES_MASIVO INT = 0,                   @OP_TER_IND_MASIVO BIT = 0,
        @DESDE_CAJA_MASIVO BIT = 0,                         @PENDIENTES_MASIVO INT = 0,
        @RETIRA_EGR_CAJA BIT = 0,                           @OP_TER_IND_ABRIR BIT = 0,                      @DESDE_CAJA_TXT VARCHAR(20);
		
		
DECLARE @FCJ_OP TABLE (CODCAJA VARCHAR(20), CNSFACJ VARCHAR(20), CNSACJ VARCHAR(20), ESTADO VARCHAR(20), CERRADA INT)
DECLARE @EGRESOS_SEL TABLE (CODCAJA VARCHAR(20), CNSFACJ VARCHAR(20), CNSACJ VARCHAR(20), CNSFCXPPM VARCHAR(20))
DECLARE @TABLA TABLE(ITEM INT IDENTITY(1,1), VALOR VARCHAR(MAX));
DECLARE @TABLERRR TABLE(ERROR VARCHAR(200));
DECLARE @CNSFCXPPM_TER              VARCHAR(20);
DECLARE @EGRESOS_ABRIR TABLE (CODCAJA VARCHAR(20), CNSFACJ VARCHAR(20))

BEGIN
    SET LANGUAGE Spanish;
    SET DATEFORMAT DMY;

    SELECT * INTO #JSON
    FROM OPENJSON(@JSON)
    WITH
    (
        MODELO      VARCHAR(100) '$.MODELO',
        METODO      VARCHAR(100) '$.METODO',
        USUARIO     VARCHAR(12)  '$.USUARIO',
        PARAMETROS  NVARCHAR(MAX) AS JSON
    );

    SELECT
        @MODELO     = MODELO,
        @METODO     = METODO,
        @PARAMETROS = PARAMETROS,
        @USUARIO    = USUARIO
    FROM #JSON;

    DECLARE @TBLERRORES TABLE(ERROR VARCHAR(500));

    SELECT
        @GRUPO            = DBO.FNK_DESCIFRAR(U.GRUPO),
        @USUNOMBRE        = U.NOMBRE,
        @SYS_COMPUTERNAME = U.SYS_COMPUTERNAME,
        @COMPANIA         = U.COMPANIA,
        @CODCAJERO        = U.CODCAJERO,
        @IDSEDE           = B.IDSEDE,
        @SEDE             = B.IDSEDE
    FROM USUSU U
    LEFT JOIN UBEQ B
        ON B.SYS_COMPUTERNAME = U.SYS_COMPUTERNAME
    WHERE U.USUARIO = @USUARIO;

	IF @METODO = 'AUTORIZAR'
	BEGIN
		SELECT @CNSFCXPPM = CNSFCXPPM
		FROM OPENJSON(@PARAMETROS)
		WITH( CNSFCXPPM			VARCHAR(20)		'$.CNSFCXPPM'
		)

		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				IF (SELECT DBO.FNK_VALORVARIABLE('FECHAORDENPAGO')) = 'CONTABLE'
				BEGIN
					UPDATE FCXPPM SET F_CONTABLE = DBO.FNK_GETDATE() WHERE CNSFCXPPM = @CNSFCXPPM
				END
					EXEC SPK_CONFIRMAR_PAGOSMASIVO @CNSFCXPPM, @COMPANIA, @IDSEDE, @SYS_COMPUTERNAME, @USUARIO
			END TRY  
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK
		END 
	END
	
	IF @METODO = 'OBTENER_ORDENES_POR_CUENTAS'
	BEGIN
		BEGIN TRY	
			-- Obtener parámetros
			SELECT 
				@CNSFCXPs_JSON = CNSFCXPs,
				@ESTADO_FILTRO = ESTADO
			FROM OPENJSON(@PARAMETROS)
			WITH (
				CNSFCXPs NVARCHAR(MAX) '$.CNSFCXPs',
				ESTADO VARCHAR(20) '$.ESTADO'
			)
		
			-- Validar que se hayan proporcionado cuentas
			IF @CNSFCXPs_JSON IS NULL OR @CNSFCXPs_JSON = ''
			BEGIN
				SELECT 'KO' AS OK, 'No se proporcionaron cuentas por pagar para consultar' AS ERROR
				RETURN
			END
		
			-- Crear tabla temporal con las cuentas proporcionadas
			DECLARE @CUENTAS_CONSULTAR TABLE (CNSFCXP VARCHAR(20))
		
			INSERT INTO @CUENTAS_CONSULTAR (CNSFCXP)
			SELECT VALUE
			FROM OPENJSON(@CNSFCXPs_JSON)
		
			-- Obtener órdenes de pago asociadas a las cuentas
			SELECT 'OK' AS OK
		
			SELECT DISTINCT
				FCXPP.CNSFCXPPM,
				FCXPP.CNSFCXPP,
				FCXPP.CNSFCXP,
				FCXPPM.FECHA,
				FCXPPM.ESTADO,
				FCXPPM.VALOR,
				FCXP.IDTERCERO,
				TER.NIT,
				TER.RAZONSOCIAL,
				FCXP.CUECREDITO
			FROM FCXPP
			INNER JOIN FCXP ON FCXPP.CNSFCXP = FCXP.CNSFCXP
			INNER JOIN FCXPPM ON FCXPP.CNSFCXPPM = FCXPPM.CNSFCXPPM
			LEFT JOIN TER ON FCXP.IDTERCERO = TER.IDTERCERO
			INNER JOIN @CUENTAS_CONSULTAR CC ON FCXPP.CNSFCXP = CC.CNSFCXP
			WHERE FCXPP.ESTADO <> 'A'
				AND (@ESTADO_FILTRO IS NULL OR @ESTADO_FILTRO = '' OR FCXPPM.ESTADO = @ESTADO_FILTRO)
			ORDER BY FCXPP.CNSFCXPPM, FCXPP.CNSFCXP
		
		END TRY
		BEGIN CATCH
			SELECT 'KO' AS OK, ERROR_MESSAGE() AS ERROR
			RETURN
		END CATCH
	END
	
	IF @METODO = 'DESAUTORIZAR'
	BEGIN
		SELECT @CNSFCXPPM = CNSFCXPPM
		FROM OPENJSON(@PARAMETROS)
		WITH( CNSFCXPPM VARCHAR(20) '$.CNSFCXPPM')
    
		IF EXISTS (SELECT * FROM FCXPP INNER JOIN FCJ ON FCXPP.CODCAJA=FCJ.CODCAJA AND FCXPP.CNSFACJ=FCJ.CNSFACJ 
		WHERE  FCXPP.CNSFCXPPM = @CNSFCXPPM AND FCJ.ESTADO = 'P' AND FCXPP.ESTADO <> 'A' AND FCJ.CERRADA = 1)
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'items de la orden de pago ya se encuentran confirmados en Caja'
		END
    
		DECLARE @FCJ_ANULAR TABLE (
			CNSFACJ VARCHAR(20),
			CODCAJA VARCHAR(20)
		)
    
		INSERT INTO @FCJ_ANULAR (CNSFACJ, CODCAJA)
		SELECT DISTINCT FCJ.CNSFACJ, FCJ.CODCAJA
		FROM FCXPP
		INNER JOIN FCJ ON FCXPP.CODCAJA = FCJ.CODCAJA AND FCXPP.CNSFACJ = FCJ.CNSFACJ
		WHERE FCXPP.CNSFCXPPM = @CNSFCXPPM
			AND FCXPP.ESTADO <> 'A'
			AND FCJ.ESTADO = 'P'

		IF EXISTS (SELECT * FROM @FCJ_ANULAR FA 
				   INNER JOIN FCJ ON FA.CNSFACJ = FCJ.CNSFACJ AND FA.CODCAJA = FCJ.CODCAJA 
				   WHERE COALESCE(FCJ.CERRADA,0) = 1 
				   AND FCJ.PROCEDENCIA <> 'CXP')
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'No se puede desechar/utilizar un recibo confirmado.'
		END
    
		DELETE PCJ
		FROM PCJ
		INNER JOIN @FCJ_ANULAR FA
			ON PCJ.CNSFACJ = FA.CNSFACJ
			AND PCJ.CODCAJA = FA.CODCAJA
		INNER JOIN FCJ
			ON FA.CNSFACJ = FCJ.CNSFACJ
			AND FA.CODCAJA = FCJ.CODCAJA
		WHERE FCJ.PROCEDENCIA = 'CXP'

		IF EXISTS (
			SELECT 1
			FROM @FCJ_ANULAR FA
			INNER JOIN PCJ
				ON FA.CNSFACJ = PCJ.CNSFACJ
				AND FA.CODCAJA = PCJ.CODCAJA
			INNER JOIN FCJ
				ON FA.CNSFACJ = FCJ.CNSFACJ
				AND FA.CODCAJA = FCJ.CODCAJA
			WHERE COALESCE(FCJ.PROCEDENCIA, '') <> 'CXP'
		)
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'No Se Puede Desechar Un Recibo Con Registros En Forma De Pago.'
		END
    
		IF EXISTS (SELECT * FROM @FCJ_ANULAR FA INNER JOIN FCJ ON FA.CNSFACJ = FCJ.CNSFACJ AND FA.CODCAJA = FCJ.CODCAJA 
				   WHERE FCJ.ESTADO = 'A')
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'No Se Puede Desechar/Utilizar Un Recibo Anulado.'
		END
    
		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				DECLARE @CNSFACJ_ANULAR VARCHAR(20)
				DECLARE @CODCAJA_ANULAR VARCHAR(20)
            
				DECLARE CURSOR_FCJ_ANULAR CURSOR FOR
				SELECT CNSFACJ, CODCAJA
				FROM @FCJ_ANULAR
            
				OPEN CURSOR_FCJ_ANULAR
				FETCH NEXT FROM CURSOR_FCJ_ANULAR INTO @CNSFACJ_ANULAR, @CODCAJA_ANULAR
            
				WHILE @@FETCH_STATUS = 0
				BEGIN
					DELETE FCJD 
					WHERE CNSFACJ = @CNSFACJ_ANULAR 
						AND CODCAJA = @CODCAJA_ANULAR
                
					UPDATE FCJ 
					SET ESTADO = 'A', 
						FECHA = DBO.FNK_GETDATE(),
						IDAFILIADO = NULL,
						IDTERCERO = NULL,
						PROCEDENCIA = 'CAJA',
						NOMBRECLIENTE = NULL,
						TIPO = 'INTERNO',
						USUARIO = @USUARIO,
						SYS_ComputerName = @SYS_COMPUTERNAME,
						OBSERVACION = 'Anulado por desautorizaciÃ³n de orden de pago ' + @CNSFCXPPM,
						DEAPERTURA = 0,
						NOADMISION = NULL,
						CNSACJ = NULL,
						ARCHIVADO = 0,
						DEVUELTO = 0,
						CERRADA = 0 
					WHERE FCJ.CNSFACJ = @CNSFACJ_ANULAR 
						AND FCJ.CODCAJA = @CODCAJA_ANULAR
                
					FETCH NEXT FROM CURSOR_FCJ_ANULAR INTO @CNSFACJ_ANULAR, @CODCAJA_ANULAR
				END
            
				CLOSE CURSOR_FCJ_ANULAR
				DEALLOCATE CURSOR_FCJ_ANULAR
            
				UPDATE FCXPP
				SET CNSFACJ = '',
					CODCAJA = '',
					ESTADO = 'N', 
					USUARIOCONF = NULL,
					FECHACONF = NULL
				WHERE CNSFCXPPM = @CNSFCXPPM
					AND ESTADO <> 'A'
            
				EXEC SPK_DESCONFIRMAR_PAGOSMASIVO @CNSFCXPPM, @COMPANIA, @IDSEDE, @SYS_COMPUTERNAME, @USUARIO
            
				UPDATE FCXPPM
				SET ESTADO = 'N',
					USUARIOCONF = NULL,
					FECHACONF = NULL
				WHERE CNSFCXPPM = @CNSFCXPPM
            
			END TRY  
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE();  
			END CATCH  
    
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
    
			SELECT 'OK'OK
		END 
	END

	IF @METODO = 'DESAUTORIZAR_POR_RECIBO'
	BEGIN
		DECLARE @MODO_OP VARCHAR(20)
		DECLARE @ITEMS_JSON NVARCHAR(MAX)

		SET @CNSFACJ_DESAUTH = JSON_VALUE(@PARAMETROS, '$.CNSFACJ')
		SET @CODCAJA_DESAUTH = JSON_VALUE(@PARAMETROS, '$.CODCAJA')
		SET @MODO_OP = JSON_VALUE(@PARAMETROS, '$.MODO')
		SET @ITEMS_JSON = JSON_QUERY(@PARAMETROS, '$.ITEMS')

		IF @ITEMS_JSON IS NULL
		BEGIN
			SET @ITEMS_JSON = JSON_VALUE(@PARAMETROS, '$.ITEMS')
		END

		SET @MODO_OP = UPPER(LTRIM(RTRIM(COALESCE(@MODO_OP, ''))))
		IF @MODO_OP NOT IN ('ANULAR', 'DESCONFIRMAR')
		BEGIN
			SET @MODO_OP = 'ANULAR'
		END

		IF @CNSFACJ_DESAUTH IS NULL OR @CNSFACJ_DESAUTH = ''
		BEGIN
			INSERT INTO @TBLERRORES(ERROR)
			SELECT 'El parametro CNSFACJ es requerido'
		END

		IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		BEGIN TRY
			DECLARE @ORDENES_AFECTADAS TABLE (CNSFCXPPM VARCHAR(20) PRIMARY KEY)
			DECLARE @ITEMS_ANULAR TABLE (
				CNSFCXPPM VARCHAR(20),
				CNSFCXPP VARCHAR(20),
				CNSFCXP VARCHAR(20)
			)

			INSERT INTO @ITEMS_ANULAR (CNSFCXPPM, CNSFCXPP, CNSFCXP)
			SELECT
				FCXPP.CNSFCXPPM,
				FCXPP.CNSFCXPP,
				FCXPP.CNSFCXP
			FROM FCXPP
			WHERE FCXPP.CNSFACJ = @CNSFACJ_DESAUTH
				AND (@CODCAJA_DESAUTH IS NULL OR @CODCAJA_DESAUTH = '' OR FCXPP.CODCAJA = @CODCAJA_DESAUTH)
				AND COALESCE(FCXPP.CNSFCXPPM, '') <> ''
				AND COALESCE(FCXPP.CNSFCXPP, '') <> ''
				AND (
					@MODO_OP = 'DESCONFIRMAR'
					OR FCXPP.ESTADO <> 'A'
				)

			IF @ITEMS_JSON IS NOT NULL
				AND @ITEMS_JSON <> ''
				AND @ITEMS_JSON <> '[]'
			BEGIN
				INSERT INTO @ITEMS_ANULAR (CNSFCXPPM, CNSFCXPP, CNSFCXP)
				SELECT
					J.CNSFCXPPM,
					J.CNSFCXPP,
					J.CNSFCXP
				FROM OPENJSON(@ITEMS_JSON)
				WITH (
					CNSFCXPPM VARCHAR(20) '$.CNSFCXPPM',
					CNSFCXPP VARCHAR(20) '$.CNSFCXPP',
					CNSFCXP VARCHAR(20) '$.CNSFCXP'
				) J
				WHERE COALESCE(J.CNSFCXPPM, '') <> ''
					AND COALESCE(J.CNSFCXPP, '') <> ''
					AND NOT EXISTS (
						SELECT 1
						FROM @ITEMS_ANULAR I
						WHERE I.CNSFCXPPM = J.CNSFCXPPM
							AND I.CNSFCXPP = J.CNSFCXPP
					)
			END

			INSERT INTO @ORDENES_AFECTADAS (CNSFCXPPM)
			SELECT DISTINCT CNSFCXPPM
			FROM @ITEMS_ANULAR
			WHERE COALESCE(CNSFCXPPM, '') <> ''

			IF NOT EXISTS (SELECT 1 FROM @ITEMS_ANULAR)
			BEGIN
				INSERT INTO @TBLERRORES(ERROR)
				SELECT 'No hay items de orden de pago vinculados a este recibo'
			END

			IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END

			IF @MODO_OP = 'DESCONFIRMAR'
			BEGIN
				UPDATE FCXPP
				SET ESTADO = 'N',
					CNSFACJ = '',
					CODCAJA = '',
					USUARIOCONF = NULL,
					FECHACONF = NULL
				WHERE CNSFCXPP IN (
					SELECT I.CNSFCXPP
					FROM @ITEMS_ANULAR I
					WHERE COALESCE(I.CNSFCXPP, '') <> ''
				)

				DECLARE CURSOR_ORDEN_DESCONF CURSOR FOR
				SELECT CNSFCXPPM
				FROM @ORDENES_AFECTADAS
				ORDER BY CNSFCXPPM

				OPEN CURSOR_ORDEN_DESCONF
				FETCH NEXT FROM CURSOR_ORDEN_DESCONF INTO @CNSFCXPPM_DESAUTH

				WHILE @@FETCH_STATUS = 0
				BEGIN
					IF DBO.FNK_VALORVARIABLE('FECHAORDENPAGO') = 'CONTABLE'
					BEGIN
						UPDATE FCXPPM
						SET F_CONTABLE = NULL
						WHERE CNSFCXPPM = @CNSFCXPPM_DESAUTH
					END

					UPDATE FCXPP
					SET ESTADO = 'N',
						CNSFACJ = '',
						CODCAJA = '',
						USUARIOCONF = NULL,
						FECHACONF = NULL
					WHERE CNSFCXPP IN (
						SELECT I.CNSFCXPP
						FROM @ITEMS_ANULAR I
						WHERE I.CNSFCXPPM = @CNSFCXPPM_DESAUTH
							AND COALESCE(I.CNSFCXPP, '') <> ''
					)

					SELECT @ABONO = COALESCE(SUM(ABONO), 0)
					FROM FCXPP
					WHERE CNSFCXPPM = @CNSFCXPPM_DESAUTH
						AND ESTADO <> 'A'

					UPDATE FCXPPM
					SET ESTADO = 'N',
						USUARIOCONF = NULL,
						FECHACONF = NULL,
						CERRADA = 0,
						OP_TER_IND = 0,
						VALOR = @ABONO
					WHERE CNSFCXPPM = @CNSFCXPPM_DESAUTH

					FETCH NEXT FROM CURSOR_ORDEN_DESCONF INTO @CNSFCXPPM_DESAUTH
				END

				CLOSE CURSOR_ORDEN_DESCONF
				DEALLOCATE CURSOR_ORDEN_DESCONF

				DECLARE CURSOR_CXP_DESCONF CURSOR FOR
				SELECT DISTINCT CNSFCXP
				FROM @ITEMS_ANULAR
				WHERE COALESCE(CNSFCXP, '') <> ''
				ORDER BY CNSFCXP

				OPEN CURSOR_CXP_DESCONF
				FETCH NEXT FROM CURSOR_CXP_DESCONF INTO @CNSFCXP_DESAUTH

				WHILE @@FETCH_STATUS = 0
				BEGIN
					EXEC SPK_CALCULOVALORESCXP @CNSFCXP_DESAUTH

					IF EXISTS (
						SELECT 1
						FROM FCXPP
						WHERE CNSFCXP = @CNSFCXP_DESAUTH
							AND ESTADO <> 'A'
					)
					BEGIN
