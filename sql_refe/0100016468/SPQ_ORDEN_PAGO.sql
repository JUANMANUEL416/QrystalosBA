				SELECT CONCAT(
					'La orden de pago ',
					@CNSFCXPPM_MASIVO,
					' no esta marcada como egresos individuales por proveedor (OP_TER_IND).'
				)
			END
		END

		IF COALESCE(@CNSFCXPPM_MASIVO, '') <> ''
			AND EXISTS (
				SELECT 1
				FROM FCXPPM
				WHERE CNSFCXPPM = @CNSFCXPPM_MASIVO
					AND COALESCE(FORMA_PAGO, '') <> ''
			)
		BEGIN
			DECLARE @FORMA_PAGO_MASIVO VARCHAR(20)
			DECLARE @BANCO_PAGO_MASIVO VARCHAR(20)
			DECLARE @CTA_BCO_PAGO_MASIVO VARCHAR(50)
			DECLARE @SUCURSAL_PAGO_MASIVO VARCHAR(50)
			DECLARE @IDTERCERO_PAGO_MASIVO VARCHAR(20)
			DECLARE @NUMDOC_PAGO_MASIVO VARCHAR(50)
			DECLARE @NUMAUT_PAGO_MASIVO VARCHAR(50)
			DECLARE @CUENTA_PCJ_MASIVO VARCHAR(20)
			DECLARE @CNSPCJ_MASIVO VARCHAR(20)
			DECLARE @FECHA_PAGO_MASIVO DATETIME
			DECLARE @IDTERCERO_FCJ_MASIVO VARCHAR(20)
			DECLARE @VALOR_FCJ_PCJ_MASIVO DECIMAL(14,2)
			DECLARE @CNSACJ_PCJ_MASIVO VARCHAR(20)

			SELECT
				@FORMA_PAGO_MASIVO = FORMA_PAGO,
				@BANCO_PAGO_MASIVO = BANCO_PAGO,
				@CTA_BCO_PAGO_MASIVO = CTA_BCO_PAGO,
				@SUCURSAL_PAGO_MASIVO = SUCURSAL_PAGO,
				@IDTERCERO_PAGO_MASIVO = IDTERCERO_PAGO,
				@NUMDOC_PAGO_MASIVO = NUMERODOCUMENTO_PAGO,
				@NUMAUT_PAGO_MASIVO = NUMEROAUTORIZA_PAGO,
				@FECHA_PAGO_MASIVO = FECHA
			FROM FCXPPM
			WHERE CNSFCXPPM = @CNSFCXPPM_MASIVO

			SELECT @CUENTA_PCJ_MASIVO = CUENTA
			FROM FPA
			WHERE FORMAPAGO = @FORMA_PAGO_MASIVO

			DECLARE CURSOR_PCJ_MASIVO CURSOR FOR
			SELECT E.CODCAJA, E.CNSFACJ, FCJ.IDTERCERO, FCJ.VALORTOTAL, FCJ.CNSACJ
			FROM @EGRESOS_SEL E
			INNER JOIN FCJ
				ON FCJ.CNSFACJ = E.CNSFACJ
				AND FCJ.CODCAJA = E.CODCAJA
			WHERE NOT EXISTS (
				SELECT 1
				FROM PCJ
				WHERE PCJ.CNSFACJ = E.CNSFACJ
					AND PCJ.CODCAJA = E.CODCAJA
			)
			ORDER BY E.CODCAJA, E.CNSFACJ

			OPEN CURSOR_PCJ_MASIVO
			FETCH NEXT FROM CURSOR_PCJ_MASIVO INTO
				@CODCAJA_MASIVO, @CNSFACJ_MASIVO, @IDTERCERO_FCJ_MASIVO, @VALOR_FCJ_PCJ_MASIVO, @CNSACJ_PCJ_MASIVO

			WHILE @@FETCH_STATUS = 0
			BEGIN
				SET @CNSPCJ_MASIVO = NULL
				EXEC SPK_GENCONSECUTIVO '01', @IDSEDE, '@PCJ', @CNSPCJ_MASIVO OUTPUT
				SELECT @CNSPCJ_MASIVO = CONCAT(
					@IDSEDE,
					REPLACE(CONCAT(SPACE(8 - LEN(@CNSPCJ_MASIVO)), LTRIM(RTRIM(@CNSPCJ_MASIVO))), SPACE(1), 0)
				)

				INSERT INTO PCJ (
					CNSPCJ, CODCAJA, CNSFACJ, TIPOPAGO, VALOR,
					BANCO, SUCURSAL, CTA_BCO, NUMERODOCUMENTO, NUMEROAUTORIZA,
					CNSACJ, IDTERCERO, CUENTA, FECHA, IMPRESO
				)
				VALUES (
					@CNSPCJ_MASIVO,
					@CODCAJA_MASIVO,
					@CNSFACJ_MASIVO,
					@FORMA_PAGO_MASIVO,
					@VALOR_FCJ_PCJ_MASIVO,
					@BANCO_PAGO_MASIVO,
					@SUCURSAL_PAGO_MASIVO,
					@CTA_BCO_PAGO_MASIVO,
					@NUMDOC_PAGO_MASIVO,
					@NUMAUT_PAGO_MASIVO,
					@CNSACJ_PCJ_MASIVO,
					COALESCE(@IDTERCERO_PAGO_MASIVO, @IDTERCERO_FCJ_MASIVO),
					@CUENTA_PCJ_MASIVO,
					@FECHA_PAGO_MASIVO,
					0
				)

				FETCH NEXT FROM CURSOR_PCJ_MASIVO INTO
					@CODCAJA_MASIVO, @CNSFACJ_MASIVO, @IDTERCERO_FCJ_MASIVO, @VALOR_FCJ_PCJ_MASIVO, @CNSACJ_PCJ_MASIVO
			END

			CLOSE CURSOR_PCJ_MASIVO
			DEALLOCATE CURSOR_PCJ_MASIVO
		END

		SELECT @CANT_EGRESOS_MASIVO = COUNT(*)
		FROM @EGRESOS_SEL

		DECLARE CURSOR_VALIDA_MASIVO CURSOR FOR
		SELECT CODCAJA, CNSFACJ
		FROM @EGRESOS_SEL
		ORDER BY CODCAJA, CNSFACJ

		OPEN CURSOR_VALIDA_MASIVO
		FETCH NEXT FROM CURSOR_VALIDA_MASIVO INTO @CODCAJA_MASIVO, @CNSFACJ_MASIVO

		WHILE @@FETCH_STATUS = 0
		BEGIN
			SET @TOTAL_FCJ_MASIVO = NULL
			SET @ESTADO_FCJ_MASIVO = NULL
			SET @FECHAFCJ_MASIVO = NULL
			SET @PROCEDENCIA_FCJ_MASIVO = NULL
			SET @CERRADA_FCJ_MASIVO = NULL
			SET @CNSACJ_MASIVO = NULL
			SET @VLR_PCJ_MASIVO = 0

			SELECT
				@TOTAL_FCJ_MASIVO = VALORTOTAL,
				@ESTADO_FCJ_MASIVO = ESTADO,
				@FECHAFCJ_MASIVO = FECHA,
				@PROCEDENCIA_FCJ_MASIVO = PROCEDENCIA,
				@CERRADA_FCJ_MASIVO = COALESCE(CERRADA, 0),
				@CNSACJ_MASIVO = CNSACJ
			FROM FCJ
			WHERE CODCAJA = @CODCAJA_MASIVO
				AND CNSFACJ = @CNSFACJ_MASIVO

			IF @ESTADO_FCJ_MASIVO IS NULL
			BEGIN
				INSERT INTO @TBLERRORES(ERROR)
				SELECT CONCAT('No existe el egreso ', @CNSFACJ_MASIVO, ' en la caja ', @CODCAJA_MASIVO, '.')
			END
			ELSE
			BEGIN
				IF @PROCEDENCIA_FCJ_MASIVO <> 'CXP'
				BEGIN
					INSERT INTO @TBLERRORES(ERROR)
					SELECT CONCAT('El egreso ', @CNSFACJ_MASIVO, ' no es de procedencia CXP.')
				END

				IF @ESTADO_FCJ_MASIVO = 'A'
				BEGIN
					INSERT INTO @TBLERRORES(ERROR)
					SELECT CONCAT('No se puede confirmar el egreso anulado ', @CNSFACJ_MASIVO, '.')
				END

				IF @ESTADO_FCJ_MASIVO = 'D'
				BEGIN
					INSERT INTO @TBLERRORES(ERROR)
					SELECT CONCAT('No se puede confirmar el egreso desechado ', @CNSFACJ_MASIVO, '.')
				END

				IF @CERRADA_FCJ_MASIVO = 1
				BEGIN
					INSERT INTO @TBLERRORES(ERROR)
					SELECT CONCAT('El egreso ', @CNSFACJ_MASIVO, ' ya se encuentra confirmado.')
				END

				IF COALESCE(@TOTAL_FCJ_MASIVO, 0) <= 0
				BEGIN
					INSERT INTO @TBLERRORES(ERROR)
					SELECT CONCAT('El egreso ', @CNSFACJ_MASIVO, ' tiene valor cero.')
				END

				SELECT @VLR_PCJ_MASIVO = COALESCE(SUM(VALOR), 0)
				FROM PCJ
				WHERE CODCAJA = @CODCAJA_MASIVO
					AND CNSFACJ = @CNSFACJ_MASIVO

				IF @VLR_PCJ_MASIVO = 0
				BEGIN
					INSERT INTO @TBLERRORES(ERROR)
					SELECT CONCAT('El egreso ', @CNSFACJ_MASIVO, ' no tiene forma de pago.')
				END
				ELSE IF @VLR_PCJ_MASIVO <> @TOTAL_FCJ_MASIVO
				BEGIN
					INSERT INTO @TBLERRORES(ERROR)
					SELECT CONCAT(
						'El egreso ',
						@CNSFACJ_MASIVO,
						' tiene forma de pago distinta al valor del recibo.'
					)
				END

				IF NOT EXISTS (
					SELECT 1
					FROM PRI
					WHERE ANO = YEAR(@FECHAFCJ_MASIVO)
						AND MES = MONTH(@FECHAFCJ_MASIVO)
						AND COALESCE(CERRADO, 0) = 0
				)
				BEGIN
					INSERT INTO @TBLERRORES(ERROR)
					SELECT CONCAT(
						'El periodo contable del egreso ',
						@CNSFACJ_MASIVO,
						' no existe o esta cerrado.'
					)
				END

				IF (
					SELECT COUNT(1)
					FROM ACJ
					WHERE CODCAJA = @CODCAJA_MASIVO
						AND ABIERTA = 1
				) = 0
				BEGIN
					INSERT INTO @TBLERRORES(ERROR)
					SELECT CONCAT('La caja ', @CODCAJA_MASIVO, ' no se encuentra abierta.')
				END

				IF (
					SELECT COUNT(1)
					FROM ACJ
					WHERE CODCAJA = @CODCAJA_MASIVO
						AND ABIERTA = 1
				) > 1
				BEGIN
					INSERT INTO @TBLERRORES(ERROR)
					SELECT CONCAT('La caja ', @CODCAJA_MASIVO, ' se encuentra abierta mas de una vez.')
				END
			END

			FETCH NEXT FROM CURSOR_VALIDA_MASIVO INTO @CODCAJA_MASIVO, @CNSFACJ_MASIVO
		END

		CLOSE CURSOR_VALIDA_MASIVO
		DEALLOCATE CURSOR_VALIDA_MASIVO

		IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		DECLARE CURSOR_CONFIRMA_MASIVO CURSOR FOR
		SELECT CODCAJA, CNSFACJ
		FROM @EGRESOS_SEL
		ORDER BY CODCAJA, CNSFACJ

		OPEN CURSOR_CONFIRMA_MASIVO
		FETCH NEXT FROM CURSOR_CONFIRMA_MASIVO INTO @CODCAJA_MASIVO, @CNSFACJ_MASIVO

		WHILE @@FETCH_STATUS = 0
		BEGIN
			BEGIN TRY
				EXEC SPK_CIERRERECIBO_CAJA
					@CODCAJA_MASIVO,
					@CNSFACJ_MASIVO,
					@COMPANIA,
					@IDSEDE,
					@USUARIO,
					@SYS_COMPUTERNAME

				SET @CONFIRMADOS_MASIVO = @CONFIRMADOS_MASIVO + 1
			END TRY
			BEGIN CATCH
				INSERT INTO @TBLERRORES(ERROR)
				SELECT CONCAT(
					'Error al confirmar el egreso ',
					@CNSFACJ_MASIVO,
					': ',
					ERROR_MESSAGE()
				)
			END CATCH

			FETCH NEXT FROM CURSOR_CONFIRMA_MASIVO INTO @CODCAJA_MASIVO, @CNSFACJ_MASIVO
		END

		CLOSE CURSOR_CONFIRMA_MASIVO
		DEALLOCATE CURSOR_CONFIRMA_MASIVO

		IF COALESCE(@CNSFCXPPM_MASIVO, '') <> ''
		BEGIN
			SELECT @PENDIENTES_MASIVO = COUNT(*)
			FROM FCXPP
			INNER JOIN FCJ
				ON FCJ.CNSFACJ = FCXPP.CNSFACJ
				AND FCJ.CODCAJA = FCXPP.CODCAJA
			WHERE FCXPP.CNSFCXPPM = @CNSFCXPPM_MASIVO
				AND FCXPP.ESTADO <> 'A'
				AND FCJ.ESTADO = 'P'
				AND CAST(COALESCE(FCJ.CERRADA, 0) AS INT) = 0
				AND FCJ.PROCEDENCIA = 'CXP'
				AND FCJ.CLASE_FAC = 'PAGO'

			IF @DESDE_CAJA_MASIVO = 1
				OR @PENDIENTES_MASIVO = 0
			BEGIN
				UPDATE FCXPP
				SET ESTADO = 'P',
					USUARIOCONF = COALESCE(USUARIOCONF, @USUARIO),
					FECHACONF = COALESCE(FECHACONF, DBO.FNK_GETDATE())
				WHERE CNSFCXPPM = @CNSFCXPPM_MASIVO
					AND ESTADO <> 'A'

				UPDATE FCXPPM
				SET ESTADO = 'P',
					USUARIOCONF = COALESCE(USUARIOCONF, @USUARIO),
					FECHACONF = COALESCE(FECHACONF, DBO.FNK_GETDATE()),
					OP_TER_IND = 1
				WHERE CNSFCXPPM = @CNSFCXPPM_MASIVO
					AND ESTADO IN ('N', 'C')
			END
		END

		IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK,
				@CONFIRMADOS_MASIVO CONFIRMADOS,
				@CANT_EGRESOS_MASIVO TOTAL,
				@CNSFCXPPM_MASIVO CNSFCXPPM
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK,
			@CONFIRMADOS_MASIVO CONFIRMADOS,
			@CANT_EGRESOS_MASIVO TOTAL,
			@CNSFCXPPM_MASIVO CNSFCXPPM
		RETURN
	END

	IF @METODO = 'MARCAR_PAGADA_POR_EGRESO'
	BEGIN
		SELECT
			@CODCAJA = CODCAJA,
			@CNSFACJ = CNSFACJ
		FROM OPENJSON(@PARAMETROS)
		WITH (
			CODCAJA VARCHAR(20) '$.CODCAJA',
			CNSFACJ VARCHAR(20) '$.CNSFACJ'
		)

		IF COALESCE(@CODCAJA, '') = '' OR COALESCE(@CNSFACJ, '') = ''
		BEGIN
			SELECT 'KO' OK
			SELECT 'CODCAJA y CNSFACJ son requeridos.' ERROR
			RETURN
		END

		BEGIN TRY
			EXEC DBO.SPK_MARCA_OP_PAGADA_POR_EGRESO
				@CODCAJA,
				@CNSFACJ,
				@USUARIO
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		SELECT 'OK' OK
		RETURN
	END
END

