CREATE OR ALTER PROCEDURE DBO.SPQ_CONF_CXP
@JSON  NVARCHAR(MAX) 
WITH
ENCRYPTION
AS
DECLARE  @PARAMETROS   NVARCHAR(MAX) ,@MODELO           VARCHAR(100) ,@METODO           VARCHAR(100)  ,@USUARIO        VARCHAR(12),
			@GRUPO        VARCHAR(8)    ,@SYS_COMPUTERNAME VARCHAR(254) ,@IDSEDE             VARCHAR(5)    ,@USUNOMBRE     VARCHAR(100), @SEDE VARCHAR(5),
			@FECHA        VARCHAR(10)   ,@IDEMEDICA        VARCHAR(4)	,@FECHA1           DATETIME		,@SQL            VARCHAR(MAX),
			@CODCAJERO		VARCHAR(20),@COMPANIA		VARCHAR(10)		,@FECHAINI DATE	, @CUENTA_INICIAL VARCHAR(20) , @CUENTA_FINAL VARCHAR(20)
			,@FECHAFIN	DATE		,@CONSECUTIVO VARCHAR(20)		,@DETALLADO BIT, @ANIO VARCHAR(4), @MES VARCHAR(2),@WHERE_DATA VARCHAR(500)
			,@OBSERVACION	VARCHAR (200)		,@IDSERVICIO VARCHAR(20)	,@CONT INT	,@sqlCommand Nvarchar(max),@WHERE_DETA VARCHAR(500)
			,@MENSAJE VARCHAR(500)		,@PROCESO VARCHAR(50)	,@PROCEDENCIA VARCHAR(20), @ITEM INT	
			,@IDTERCERO VARCHAR(20)	,@F_FINAL DATE
			,@CCOSTO VARCHAR(20)		,@IDAREA	VARCHAR(20)		,@TIENE VARCHAR(20)		,@CANTIDAD INT	,@DETALLE VARCHAR (500)
			,@IDPROVEEDOR VARCHAR(20)	,@F_INICIAL DATE	,@CONTA INT		,@DIAS INT	,@CUENTA VARCHAR(20)	,@FECHA_REFERENCIA VARCHAR(20)
DECLARE @TABLERRR		TABLE (ERROR VARCHAR(200))

BEGIN 
	SET LANGUAGE Spanish;  
	SET DATEFORMAT dmy
	SELECT *
	INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)  AS JSON
	)

	SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON
	--DEFINICION DE TABLA DE ERRORES
	DECLARE @TBLERRORES TABLE(ERROR VARCHAR(200));
	-- TOMA DEL GRUPO, SYS_COMPUTERNAME, SEDE   DE ACUERDO AL USUARIOpl,   --PRINT 'USUARIO:'+@USUARIO
	SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO), @USUNOMBRE = NOMBRE FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME, @COMPANIA = COMPANIA, @CODCAJERO= CODCAJERO FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @IDSEDE = IDSEDE, @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME
	PRINT '@USUARIO='+@USUARIO

	IF @METODO = 'HIST_TOTALES'
	BEGIN
		SELECT @IDTERCERO = IDTERCERO, @PROCEDENCIA = PROCEDENCIA, @F_FINAL = F_FINAL
		FROM OPENJSON (@PARAMETROS)
		WITH		 (
			IDTERCERO				VARCHAR(20)		'$.IDTERCERO'
			,PROCEDENCIA			VARCHAR(20)		'$.PROCEDENCIA'
			,F_FINAL				DATE			'$.F_FINAL'
		)
		SELECT 'OK'OK
		SELECT X.IDTERCERO, X.RAZONSOCIAL, SUM(X.VALOR) VALOR, SUM(X.VLR_IVA) VLR_IVA, SUM(X.VLR_IMPUESTO) VLR_IMPUESTO, SUM(X.VLR_NOTASDEBITO) VLR_NOTASDEBITO, 
			SUM(X.VLR_NOTASCREDITO) VLR_NOTASCREDITO, SUM(X.VLR_FLETE) VLR_FLETE, SUM(X.ABONOS) ABONOS, SUM(X.SALDO) SALDO,  
			SUM(COALESCE (CASE WHEN CASE WHEN X.SALDO = 0 THEN 0 ELSE DATEDIFF(DAY, FCXP.FECHA, @F_FINAL) END <= 30 THEN X.SALDO END, 0)) [D_0_30], 
			SUM(COALESCE (CASE WHEN CASE WHEN X.SALDO = 0 THEN 0 ELSE DATEDIFF(DAY, FCXP.FECHA, @F_FINAL) END BETWEEN 31 AND 60 THEN X.SALDO END, 0)) [D_31_60], 
			SUM(COALESCE (CASE WHEN CASE WHEN X.SALDO = 0 THEN 0 ELSE DATEDIFF(DAY, FCXP.FECHA, @F_FINAL) END BETWEEN 61  AND 90 THEN X.SALDO END, 0)) [D_61_90], 
			SUM(COALESCE (CASE WHEN CASE WHEN X.SALDO = 0 THEN 0 ELSE DATEDIFF(DAY, FCXP.FECHA, @F_FINAL) END BETWEEN 91 AND 120 THEN X.SALDO END, 0)) [D_91_120], 
			SUM(COALESCE (CASE WHEN CASE WHEN X.SALDO = 0 THEN 0 ELSE DATEDIFF(DAY, FCXP.FECHA, @F_FINAL) END BETWEEN 121 AND 150 THEN X.SALDO END, 0)) [D_121_150], 
			SUM(COALESCE (CASE WHEN CASE WHEN X.SALDO = 0 THEN 0 ELSE DATEDIFF(DAY, FCXP.FECHA, @F_FINAL) END BETWEEN 151 AND 180 THEN X.SALDO END, 0)) [D_151_180], 
			SUM(COALESCE (CASE WHEN CASE WHEN X.SALDO = 0 THEN 0 ELSE DATEDIFF(DAY, FCXP.FECHA, @F_FINAL) END BETWEEN 181 AND 360 THEN X.SALDO END, 0)) [D_181_360], 
			SUM(COALESCE (CASE WHEN CASE WHEN X.SALDO = 0 THEN 0 ELSE DATEDIFF(DAY, FCXP.FECHA, @F_FINAL) END > 361 THEN X.SALDO END, 0)) [D_360_MAS]
		FROM   DBO.FNK_VENCIMIENTO_HISTORICO(@F_FINAL) X 
												INNER JOIN FCXP ON X.CNSFCXP = FCXP.CNSFCXP 
		WHERE X.IDTERCERO = @IDTERCERO
		AND X.PROCEDENCIA= COALESCE(@PROCEDENCIA, X.PROCEDENCIA)
		GROUP BY X.IDTERCERO, X.RAZONSOCIAL
	END
	IF @METODO = 'DETALLADO_HIST_TOTALES'
	BEGIN
		SELECT @IDTERCERO = IDTERCERO, @PROCEDENCIA = PROCEDENCIA, @F_FINAL = F_FINAL
		FROM OPENJSON (@PARAMETROS)
		WITH		 (
			IDTERCERO				VARCHAR(20)		'$.IDTERCERO'
			,PROCEDENCIA			VARCHAR(20)		'$.PROCEDENCIA'
			,F_FINAL				DATE			'$.F_FINAL'
		)
		SELECT 'OK'OK
		SELECT TER.IDTERCERO, TER.TIPO_ID,TER.NIT, TER.RAZONSOCIAL, X.ANO, X.MES, X.CNSFCXP, X.NOREFERENCIA, X.OBSERVACION, X.VALOR, X.VLR_IVA, X.VLR_IMPUESTO, X.VLR_NOTASDEBITO, X.VLR_NOTASCREDITO, 
		X.VLR_FLETE, X.ABONOS, X.SALDO, X.PROCEDENCIA, DATEDIFF(DAY, FCXP.FECHA, @F_FINAL) DIAS, 
		COALESCE (CASE WHEN CASE WHEN X.SALDO = 0 THEN 0 ELSE DATEDIFF(DAY, FCXP.FECHA, '13/12/2024 23:59:59') END <= 30 THEN X.SALDO END, 0) [D_0_30], 
		COALESCE (CASE WHEN CASE WHEN X.SALDO = 0 THEN 0 ELSE DATEDIFF(DAY, FCXP.FECHA, '13/12/2024 23:59:59') END BETWEEN 31 AND 60 THEN X.SALDO END, 0) [D_31_60], 
		COALESCE (CASE WHEN CASE WHEN X.SALDO = 0 THEN 0 ELSE DATEDIFF(DAY, FCXP.FECHA, '13/12/2024 23:59:59') END BETWEEN 61  AND 90 THEN X.SALDO END, 0) [D_61_90], 
		COALESCE (CASE WHEN CASE WHEN X.SALDO = 0 THEN 0 ELSE DATEDIFF(DAY, FCXP.FECHA, '13/12/2024 23:59:59') END BETWEEN 91 AND 120 THEN X.SALDO END, 0) [D_91_120], 
		COALESCE (CASE WHEN CASE WHEN X.SALDO = 0 THEN 0 ELSE DATEDIFF(DAY, FCXP.FECHA, '13/12/2024 23:59:59') END BETWEEN 121 AND 150 THEN X.SALDO END, 0) [D_121_150], 
		COALESCE (CASE WHEN CASE WHEN X.SALDO = 0 THEN 0 ELSE DATEDIFF(DAY, FCXP.FECHA, '13/12/2024 23:59:59') END BETWEEN 151 AND 180 THEN X.SALDO END, 0) [D_151_180], 
		COALESCE (CASE WHEN CASE WHEN X.SALDO = 0 THEN 0 ELSE DATEDIFF(DAY, FCXP.FECHA, '13/12/2024 23:59:59') END BETWEEN 181 AND 360 THEN X.SALDO END, 0) [D_181_360], 
		COALESCE (CASE WHEN CASE WHEN X.SALDO = 0 THEN 0 ELSE DATEDIFF(DAY, FCXP.FECHA, '13/12/2024 23:59:59') END > 360 THEN X.SALDO END, 0)  [D_360_MAS]
		FROM   DBO.FNK_VENCIMIENTO_HISTORICO(@F_FINAL) X INNER JOIN FCXP ON X.CNSFCXP = FCXP.CNSFCXP 
		INNER JOIN TER ON X.IDTERCERO = TER.IDTERCERO
		WHERE X.IDTERCERO = @IDTERCERO
		AND X.PROCEDENCIA= COALESCE(@PROCEDENCIA, X.PROCEDENCIA)
		ORDER BY X.ANO, X.MES
	END
	IF @METODO = 'EXPORTAR_CXP_PENDIENTES'
	BEGIN
		SELECT @PROCESO = PROCESO, @WHERE_DATA = WHERE_DATA, @WHERE_DETA = WHERE_DETA
		FROM OPENJSON(@PARAMETROS)
		WITH( PROCESO			VARCHAR(20)		 '$.PROCESO' ,WHERE_DETA			VARCHAR(500)		 '$.WHERE_DETA'		
		,WHERE_DATA			VARCHAR(500)		 '$.WHERE_DATA'		)

		IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		ELSE
		BEGIN
			BEGIN TRY
				SELECT 'OK'OK
				SET @sqlCommand = '
					SELECT  TER.NIT,TER.TIPO_ID, TER.RAZONSOCIAL,SUM(VWK_CXPDIASVTO.PORVENCER)PORVENCER,SUM(VWK_CXPDIASVTO.DM0_30)DM0_30, SUM(VWK_CXPDIASVTO.DM31_60)DM31_60    
					,SUM(VWK_CXPDIASVTO.DM61_90)DM61_90, SUM(VWK_CXPDIASVTO.DM91_120)DM91_120, SUM(VWK_CXPDIASVTO.DM121_150)DM121_150
					, SUM(VWK_CXPDIASVTO.DM151_180)DM151_180    ,SUM(VWK_CXPDIASVTO.DM181_360)DM181_360,SUM(VWK_CXPDIASVTO.DM361_MAS)DM361_MAS    
					FROM [dbo].[VWK_CXPDIASVTO]
					LEFT JOIN  TER  ON VWK_CXPDIASVTO.IDTERCERO = TER.IDTERCERO
					WHERE '+ @WHERE_DATA 

					EXEC sys.sp_executesql @sqlCommand
			
				SET @sqlCommand = '
					SELECT VWK_CXPDIASVTO.CNSFCXP,TER.TIPO_ID, TER.NIT, TER.RAZONSOCIAL, DBO.FNK_FECHA_DDMMAA(VWK_CXPDIASVTO.F_FACTURAREF) [FECH_FACTURA],DBO.FNK_FECHA_DDMMAA(VWK_CXPDIASVTO.F_VENCE) [FECH_VENCE],VWK_CXPDIASVTO.PROCEDENCIA,VWK_CXPDIASVTO.NOREFERENCIA,VWK_CXPDIASVTO.DIASVENCE ,(VWK_CXPDIASVTO.PORVENCER)PORVENCER,(VWK_CXPDIASVTO.DM0_30)DM0_30, (VWK_CXPDIASVTO.DM31_60)DM31_60  
					,(VWK_CXPDIASVTO.DM61_90)DM61_90, (VWK_CXPDIASVTO.DM91_120)DM91_120, (VWK_CXPDIASVTO.DM121_150)DM121_150, (VWK_CXPDIASVTO.DM151_180)DM151_180   
					,(VWK_CXPDIASVTO.DM181_360)DM181_360,(VWK_CXPDIASVTO.DM361_MAS)DM361_MAS   
					FROM [dbo].[VWK_CXPDIASVTO] 
					LEFT JOIN  TER  ON VWK_CXPDIASVTO.IDTERCERO = TER.IDTERCERO      
											WHERE '+ @WHERE_DETA

				EXEC sys.sp_executesql @sqlCommand
			END TRY
			BEGIN CATCH 
				INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE() ;  
			END CATCH  
			IF (SELECT COUNT(*) FROM @TBLERRORES)> 0
			BEGIN
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END
			SELECT 'OK'OK
		END 
	END	
	IF @METODO = 'EXPORTAR_CXP_ESPERADAS'
	BEGIN
		SELECT @PROCESO = PROCESO, @WHERE_DATA = WHERE_DATA
		FROM OPENJSON(@PARAMETROS)
		WITH( PROCESO			VARCHAR(20)		 '$.PROCESO'
		,WHERE_DATA			VARCHAR(500)		 '$.WHERE_DATA'		)

			SELECT 'OK'OK
			SET @sqlCommand = '
				SELECT   TER.NIT, FXP.IDTERCERO, TER.RAZONSOCIAL, FXP.N_PRESUP, FXP.NOREFERENCIA, FXP.F_FACTURAREF, FXP.VR_TOTAL, FXP.OBSERVACION,FXP.PROCEDENCIA  
				FROM [dbo].[FXP] 
					INNER JOIN  TER ON FXP.IDTERCERO = TER.IDTERCERO   
				WHERE '+ @WHERE_DATA 

				EXEC sys.sp_executesql @sqlCommand
			
			SET @sqlCommand = '
				SELECT FXP.IDTERCERO, TER.NIT, TER.RAZONSOCIAL, FXPD.N_PRESUP, FXPD.ITEM, FXPD.IDSERVICIO, SER.DESCSERVICIO, FXPD.PREFIJO, FXPD.VALOR, FXPD.CANTIDAD, FXPD.VR_TOTAL, FXPD.NOPRESTACION , FXPD.NOITEM, FXPD.IDCIRUGIA, FXPD.N_FACTURA, FXPD.ESTADO, FXPD.CCOSTO, FXPD.IDAREAH, FXPD.IDAREA, FXPD.VLRORIGINAL   
				FROM [dbo].[FXPD]
					INNER JOIN   SER ON FXPD.IDSERVICIO = SER.IDSERVICIO  
					INNER JOIN FXP ON  FXP.N_PRESUP =  FXPD.N_PRESUP 
					INNER JOIN  TER ON FXP.IDTERCERO = TER.IDTERCERO   
				WHERE '+ @WHERE_DATA 

			EXEC sys.sp_executesql @sqlCommand
		
	END	

	IF @METODO = 'EXPORTAR_CXP'
	BEGIN
		SELECT @IDPROVEEDOR = IDPROVEEDOR,  @F_FINAL = F_FINAL, @F_INICIAL = F_INICIAL, @CONTA = CONTA, @DIAS = DIAS
		FROM OPENJSON (@PARAMETROS)
		WITH		 (	IDPROVEEDOR		VARCHAR(20)		'$.IDPROVEEDOR'
						,F_INICIAL		DATE			'$.F_INICIAL'
						,F_FINAL		DATE			'$.F_FINAL'
						,CONTA			INT				'$.CONTA'
						,DIAS			INT				'$.DIAS'	)
		
		SELECT 'OK'OK
		SELECT  FCXP.CNSFCXP, FCXP.IDTERCERO, TER.RAZONSOCIAL,FCXP.CONTABILIZADA,  FCXP.NOREFERENCIA, FCXP.F_FACTURAREF, FCXP.F_VENCE, FCXP.VALOR, FCXP.CONTABILIZADA, FCXP.NROCOMPROBANTE
		, FCXP.SALDO, FCXP.VLR_ABONOS, FCXP.VLR_NOTASDEBITO FROM FCXP 
		INNER JOIN TER ON FCXP.IDTERCERO = TER.IDTERCERO
		WHERE CONVERT(DATE,FCXP.FECHA) >= @F_INICIAL AND CONVERT(DATE,FCXP.FECHA) <= @F_FINAL 
		AND FCXP.CONTABILIZADA = CASE WHEN @CONTA = 0 THEN 0  WHEN @CONTA = 1 THEN 1 ELSE  FCXP.CONTABILIZADA END
		AND FCXP.IDTERCERO = COALESCE(@IDPROVEEDOR, FCXP.IDTERCERO)

	END
	IF @METODO = 'RPT_CXP_PENDIENTES'
	BEGIN
		SELECT @IDPROVEEDOR = IDPROVEEDOR,  @F_FINAL = F_FINAL, @F_INICIAL = F_INICIAL, @CONTA = CONTA, @DIAS = DIAS
		FROM OPENJSON (@PARAMETROS)
		WITH		 (	IDPROVEEDOR		VARCHAR(20)		'$.IDPROVEEDOR'
						,F_INICIAL		DATE			'$.F_INICIAL'
						,F_FINAL		DATE			'$.F_FINAL'
						,CONTA			INT				'$.CONTA'
						,DIAS			INT				'$.DIAS'	)
		
		SELECT 'OK'OK
		SELECT @CONTA = CASE @CONTA WHEN 3 THEN NULL WHEN 1 THEN 1 WHEN 0 THEN 0 END
		SELECT FCXP.CNSFCXP, FCXP.IDTERCERO, TER.RAZONSOCIAL, FCXP.NOREFERENCIA, FCXP.F_FACTURAREF, FCXP.F_VENCE, FCXP.VALOR, FCXP.CONTABILIZADA, FCXP.NROCOMPROBANTE
		, FCXP.SALDO, FCXP.VLR_ABONOS, FCXP.VLR_NOTASDEBITO FROM FCXP 
		INNER JOIN TER ON FCXP.IDTERCERO = TER.IDTERCERO
		WHERE CONVERT(DATE,FCXP.FECHA) >= @F_INICIAL AND CONVERT(DATE,FCXP.FECHA) <= @F_FINAL 
		AND FCXP.CONTABILIZADA = CASE WHEN @CONTA = 0 THEN 0  WHEN @CONTA = 1 THEN 1 ELSE  FCXP.CONTABILIZADA END
		AND FCXP.IDTERCERO = COALESCE(@IDPROVEEDOR, FCXP.IDTERCERO)

		SELECT @DIAS DIAS, SUM(FCXP.VALOR)VALOR, SUM(FCXP.SALDO) SALDO, SUM(FCXP.VLR_ABONOS) VLR_ABONOS, SUM(FCXP.VLR_NOTASDEBITO) VLR_NOTASDEBITO FROM FCXP 
		INNER JOIN TER ON FCXP.IDTERCERO = TER.IDTERCERO
		WHERE CONVERT(DATE,FCXP.FECHA) >= @F_INICIAL AND CONVERT(DATE,FCXP.FECHA) <= @F_FINAL 
		AND FCXP.CONTABILIZADA = CASE WHEN @CONTA = 0 THEN 0  WHEN @CONTA = 1 THEN 1 ELSE  FCXP.CONTABILIZADA END
		AND FCXP.IDTERCERO = COALESCE(@IDPROVEEDOR, FCXP.IDTERCERO)

	END
	IF @METODO = 'VENCIMIENTO_TERCERO'
	BEGIN
		SELECT @IDTERCERO = IDTERCERO,  @F_FINAL = F_FINAL, @F_INICIAL = F_INICIAL, @PROCEDENCIA = PROCEDENCIA, @CUENTA = CUENTA, @FECHA_REFERENCIA = FECHA_REFERENCIA, @PROCESO = PROCESO
		FROM OPENJSON (@PARAMETROS)
		WITH		 (	IDTERCERO			VARCHAR(20)		'$.IDTERCERO' , PROCESO			VARCHAR(20)		'$.PROCESO' 
						,F_INICIAL			DATE			'$.F_INICIAL'
						,F_FINAL			DATE			'$.F_FINAL'
						,PROCEDENCIA		VARCHAR(20)		'$.PROCEDENCIA'
						,CUENTA				VARCHAR(20)		'$.CUENTA'
						,FECHA_REFERENCIA	VARCHAR(20)		'$.FECHA_REFERENCIA'	)
		
		SELECT 'OK'OK
		IF @PROCESO = 'EXPORTAR'
		BEGIN
			SELECT A.IDTERCERO, B.NIT,B.RAZONSOCIAL,SUM(SALDO)SALDO,SUM(PORVENCER) AS POR_VENCER, 
				SUM(DM0_30)DM0_30,SUM(DM31_60)DM31_60,SUM(DM61_90)DM61_90, 
				SUM(DM91_120)DM91_120,SUM(DM121_150)DM121_150,SUM(DM151_180)DM151_180,SUM(DM181_360)DM181_360,SUM(DM361_MAS)DM361_MAS  
			FROM FNK_VENCIMIENTOSCXP('',@FECHA_REFERENCIA) A INNER JOIN TER B ON A.IDTERCERO=B.IDTERCERO  
			WHERE SALDO>0 AND CONVERT(DATE,A.F_FACTURAREF) >= CONVERT(DATE,@F_INICIAL) AND CONVERT(DATE,A.F_FACTURAREF) < CONVERT(DATE,@F_FINAL)
				AND A.IDTERCERO = COALESCE(@IDTERCERO, A.IDTERCERO) AND CUECREDITO= COALESCE(@CUENTA,CUECREDITO )
			GROUP BY A.IDTERCERO, B.NIT, B.RAZONSOCIAL

			SELECT A.IDTERCERO, A.NOREFERENCIA,dbo.FNK_FECHA(A.F_FACTURAREF) F_FACTURA,DBO.FNK_FECHA(A.F_VENCE) F_VENCE,A.DIASVENCE,SUM(SALDO)SALDO,SUM(PORVENCER) AS POR_VENCER, 
				SUM(DM0_30)DM0_30,SUM(DM31_60)DM31_60,SUM(DM61_90)DM61_90, 
				SUM(DM91_120)DM91_120,SUM(DM121_150)DM121_150,SUM(DM151_180)DM151_180,SUM(DM181_360)DM181_360,SUM(DM361_MAS)DM361_MAS  
			FROM FNK_VENCIMIENTOSCXP(@IDTERCERO,@FECHA_REFERENCIA) A INNER JOIN TER B ON A.IDTERCERO=B.IDTERCERO  
			WHERE SALDO>0 AND CUECREDITO= COALESCE(@CUENTA,CUECREDITO ) AND CONVERT(DATE,A.F_FACTURAREF) >= CONVERT(DATE,@F_INICIAL) AND CONVERT(DATE,A.F_FACTURAREF) < CONVERT(DATE,@F_FINAL)
			GROUP BY A.NOREFERENCIA,A.DIASVENCE,dbo.FNK_FECHA(A.F_FACTURAREF),DBO.FNK_FECHA(A.F_VENCE),A.IDTERCERO

			RETURN
		END
		ELSE
		BEGIN
			SELECT A.IDTERCERO, B.NIT,B.RAZONSOCIAL,SUM(SALDO)SALDO,SUM(PORVENCER) AS POR_VENCER, 
				SUM(DM0_30)DM0_30,SUM(DM31_60)DM31_60,SUM(DM61_90)DM61_90, 
				SUM(DM91_120)DM91_120,SUM(DM121_150)DM121_150,SUM(DM151_180)DM151_180,SUM(DM181_360)DM181_360,SUM(DM361_MAS)DM361_MAS  
			FROM FNK_VENCIMIENTOSCXP('',@FECHA_REFERENCIA) A INNER JOIN TER B ON A.IDTERCERO=B.IDTERCERO  
			WHERE SALDO>0 AND CONVERT(DATE,A.F_FACTURAREF) >= CONVERT(DATE,@F_INICIAL) AND CONVERT(DATE,A.F_FACTURAREF) < CONVERT(DATE,@F_FINAL)
				AND A.IDTERCERO = COALESCE(@IDTERCERO, A.IDTERCERO) AND CUECREDITO= COALESCE(@CUENTA,CUECREDITO )
			GROUP BY A.IDTERCERO, B.NIT, B.RAZONSOCIAL

			SELECT SUM(SALDO)SALDO,SUM(PORVENCER) AS POR_VENCER,SUM(DM0_30)DM0_30,SUM(DM31_60)DM31_60,SUM(DM61_90)DM61_90, 
				SUM(DM91_120)DM91_120,SUM(DM121_150)DM121_150,SUM(DM151_180)DM151_180,SUM(DM181_360)DM181_360,SUM(DM361_MAS)DM361_MAS 
			FROM FNK_VENCIMIENTOSCXP('',@FECHA_REFERENCIA) A INNER JOIN TER B ON A.IDTERCERO=B.IDTERCERO  
			WHERE SALDO>0 AND CONVERT(DATE,A.F_FACTURAREF) >= CONVERT(DATE,@F_INICIAL) AND CONVERT(DATE,A.F_FACTURAREF) < CONVERT(DATE,@F_FINAL)
				AND A.IDTERCERO = COALESCE(@IDTERCERO, A.IDTERCERO) AND CUECREDITO= COALESCE(@CUENTA,CUECREDITO )
		END
	END
	IF @METODO = 'VENCIMIENTO_TERCERO_DETALLE'
	BEGIN
		SELECT @IDTERCERO = IDTERCERO,  @F_FINAL = F_FINAL, @F_INICIAL = F_INICIAL, @PROCEDENCIA = PROCEDENCIA, @CUENTA = CUENTA, @FECHA_REFERENCIA = FECHA_REFERENCIA
		FROM OPENJSON (@PARAMETROS)
		WITH		 (	IDTERCERO			VARCHAR(20)		'$.IDTERCERO'
						,F_INICIAL			DATE			'$.F_INICIAL'
						,F_FINAL			DATE			'$.F_FINAL'
						,PROCEDENCIA		VARCHAR(20)		'$.PROCEDENCIA'
						,CUENTA				VARCHAR(20)		'$.CUENTA'
						,FECHA_REFERENCIA	VARCHAR(20)		'$.FECHA_REFERENCIA'	)
		
		SELECT 'OK'OK
		SELECT A.NOREFERENCIA,dbo.FNK_FECHA(A.F_FACTURAREF) F_FACTURA,DBO.FNK_FECHA(A.F_VENCE) F_VENCE,A.DIASVENCE,SUM(SALDO)SALDO,SUM(PORVENCER) AS POR_VENCER, 
		SUM(DM0_30)DM0_30,SUM(DM31_60)DM31_60,SUM(DM61_90)DM61_90, 
		SUM(DM91_120)DM91_120,SUM(DM121_150)DM121_150,SUM(DM151_180)DM151_180,SUM(DM181_360)DM181_360,SUM(DM361_MAS)DM361_MAS  
		FROM FNK_VENCIMIENTOSCXP(@IDTERCERO,@FECHA_REFERENCIA) A INNER JOIN TER B ON A.IDTERCERO=B.IDTERCERO  
		WHERE SALDO>0 AND CUECREDITO= COALESCE(@CUENTA,CUECREDITO ) AND CONVERT(DATE,A.F_FACTURAREF) >= CONVERT(DATE,@F_INICIAL) AND CONVERT(DATE,A.F_FACTURAREF) < CONVERT(DATE,@F_FINAL)
