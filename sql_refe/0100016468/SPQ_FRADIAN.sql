CREATE OR ALTER PROC DBO.SPQ_FRADIAN
    @JSON  NVARCHAR(MAX)
WITH ENCRYPTION
AS
DECLARE  @PARAMETROS    NVARCHAR(MAX)
        ,@METODO        VARCHAR(100)    ,@USUARIO   VARCHAR(12)
		,@PDF           VARBINARY(MAX)  ,@CNSRADIAN VARCHAR(20)
        ,@PDFBLOB       VARCHAR(MAX)    ,@XML       VARCHAR(MAX)
        ,@CODIGO        VARCHAR(20)     ,@OBSERVACION VARCHAR(MAX)
		,@ITEM			INT             ,@UUID      VARCHAR(500)
        ,@NODOCUMENTO   VARCHAR(100)    ,@NIT       VARCHAR(50)

		,@NOMBRES_USUARIO	VARCHAR(250),@APELLIDOS_USUARIO		VARCHAR(250)
		,@schemeName_USUARIO VARCHAR(50),@DEPARTAMENTO_USUARIO	VARCHAR(100)
		,@CARGO_USUARIO		VARCHAR(50)	,@DOCID_USUARIO			VARCHAR(50)

DECLARE @TBLERRORES TABLE(ERROR VARCHAR(1000))
BEGIN
    SELECT * 
	INTO #JSON
	FROM OPENJSON (@JSON)
	WITH (
		METODO         VARCHAR(100)     '$.METODO',
		USUARIO        VARCHAR(12)      '$.USUARIO',
		PARAMETROS     NVARCHAR(MAX)  AS JSON
	)

    SELECT  @METODO     = METODO 
            ,@PARAMETROS = PARAMETROS
            ,@USUARIO    = USUARIO
	FROM #JSON

    IF @METODO = 'ARCHIVOS'
    BEGIN
        SELECT @CNSRADIAN = CNSRADIAN
        FROM OPENJSON(@PARAMETROS)
        WITH(
            CNSRADIAN VARCHAR(20) '$.CNSRADIAN' 
        )

        SELECT @PDF = CAST(PDF_FS AS varbinary(MAX)),
            @XML = DOCXML
        FROM DOCS_RADIAN 
        WHERE @CNSRADIAN = CNSRADIAN

        SELECT 'OK' AS OK

        SELECT @PDFBLOB = CAST(N'' AS XML).value('xs:base64Binary(xs:hexBinary(sql:column("bin")))', 'VARCHAR(MAX)')
        FROM (
            SELECT @PDF AS bin
        ) AS bin_sql_server_temp

        SELECT @PDF AS PDF, @XML AS DOCXML
        
        RETURN
    END

    IF @METODO = 'ADDEVENTO'
    BEGIN
		SELECT 
			@NOMBRES_USUARIO = NOMBRES
			,@APELLIDOS_USUARIO = APELLIDOS
			,@schemeName_USUARIO=(SELECT TOP 1 DATO1 FROM TGEN WHERE TABLA='GENERAL' AND CAMPO='TIPOIDENT' AND CODIGO=USUSU.TIPOIDENT)
			,@DEPARTAMENTO_USUARIO = DEPARTAMENTO
			,@CARGO_USUARIO = CARGO
			,@DOCID_USUARIO = DOCID
		FROM USUSU
		WHERE USUARIO = @USUARIO

		INSERT INTO @TBLERRORES(ERROR)
		SELECT 'Los nombres del usuario ' + @USUARIO + ' son obligatorios' WHERE COALESCE(@NOMBRES_USUARIO,'')=''
		UNION ALL SELECT 'Los apellidos del usuario ' + @USUARIO + ' son obligatorios' WHERE COALESCE(@APELLIDOS_USUARIO,'')='' 
		UNION ALL SELECT 'El tipo de documento del usuario ' + @USUARIO + ' es obligatorio' WHERE COALESCE(@schemeName_USUARIO,'')=''
		UNION ALL SELECT 'El tipo departamento donde labora el usuario ' + @USUARIO + ' es obligatorio' WHERE COALESCE(@DEPARTAMENTO_USUARIO,'')=''
		UNION ALL SELECT 'El cargo del usuario ' + @USUARIO + ' es obligatorio' WHERE COALESCE(@CARGO_USUARIO,'')=''
		UNION ALL SELECT 'El documento de identidad del usuario ' + @USUARIO + ' es obligatorio' WHERE COALESCE(@DOCID_USUARIO,'')=''
		
		IF (SELECT COUNT(1) FROM @TBLERRORES)<=0
		BEGIN
			SELECT @CNSRADIAN = CNSRADIAN
				,@CODIGO = CODIGO
				,@OBSERVACION = OBSERVACION
				,@UUID = UUID
				,@NODOCUMENTO = NODOCUMENTO
				,@NIT = NIT
			FROM OPENJSON(@PARAMETROS)
			WITH(
				CNSRADIAN VARCHAR(20) '$.CNSRADIAN',
				CODIGO VARCHAR(20) '$.CODEVENTO',
				UUID VARCHAR(500) '$.UUID',
				NODOCUMENTO VARCHAR(100) '$.NODOCUMENTO',
				NIT VARCHAR(50) '$.NIT',
				OBSERVACION VARCHAR(MAX) '$.OBSERVACION'
			)
			INSERT INTO FRADIAND (
				CNSRADIAN, USUARIO, CODEVENTO, OBSERVACION--, UUID, NODOCUMENTO
			)
			SELECT @CNSRADIAN, @USUARIO, @CODIGO, @OBSERVACION--, @UUID, @NODOCUMENTO

			-- Actualizar NODOCUMENTO en FRADIAN
			UPDATE FRADIAN
			SET NODOCUMENTO = COALESCE(@NODOCUMENTO, NODOCUMENTO),
				NIT = COALESCE(@NIT, NIT),
				UUID = COALESCE(@UUID, UUID)
			WHERE CNSRADIAN = @CNSRADIAN

			SELECT @@IDENTITY AS ITEM, 'OK' AS OK
		END
		ELSE
		BEGIN
			SELECT 'KO' AS OK
			SELECT * FROM @TBLERRORES
		END

    END

	IF @METODO = 'DELEVENTO'
	BEGIN
		SELECT @ITEM = ITEM
        FROM OPENJSON(@PARAMETROS)
        WITH(ITEM INT '$.ITEM')

		IF @ITEM IS NULL
			INSERT INTO @TBLERRORES(ERROR)
			SELECT 'El item es obligatorio para identificar el evento a eliminar'

		IF NOT EXISTS(SELECT * FROM FRADIAND WHERE ITEM=@ITEM AND COALESCE(PROCESADO,0)=0)
			INSERT INTO @TBLERRORES(ERROR)
			SELECT 'Evento no puede eliminarse porque ya esten estado PROCESADO'

		BEGIN TRY
			DELETE FROM FRADIAND WHERE ITEM=@ITEM
			AND NOT EXISTS(SELECT * FROM @TBLERRORES)
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) 
			SELECT ERROR_MESSAGE()            
		END CATCH

		IF EXISTS(SELECT * FROM @TBLERRORES)
		BEGIN
			SELECT 'KO'OK
			SELECT ERROR FROM @TBLERRORES
		END
		ELSE
		BEGIN
			SELECT 'OK' AS OK, @ITEM AS ITEM
		END
		RETURN
	END

	IF @METODO = 'REENCOLAR_EVENTO'
	BEGIN
		SELECT @ITEM = ITEM
        FROM OPENJSON(@PARAMETROS)
        WITH(ITEM INT '$.ITEM')

		IF EXISTS(SELECT * FROM FRADIAND WHERE ITEM=@ITEM AND COALESCE(PROCESADO,0)=1 AND COALESCE(ERROR,0)=0)
			INSERT INTO @TBLERRORES(ERROR)
			SELECT 'Evento no puede cambiar de estado porque ya esta PROCESADO'

		BEGIN TRY
			UPDATE FRADIAND 
			SET PROCESADO=0, ERROR=0, FECHAPROCESADO=NULL
			WHERE ITEM=@ITEM
			AND NOT EXISTS(SELECT * FROM @TBLERRORES)
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) 
			SELECT ERROR_MESSAGE()            
		END CATCH

		IF EXISTS(SELECT * FROM @TBLERRORES)
		BEGIN
			SELECT 'KO'OK
			SELECT ERROR FROM @TBLERRORES
		END
		ELSE
		BEGIN
			SELECT 'OK' AS OK, @ITEM AS ITEM
		END
		RETURN
	END

	IF @METODO = 'MATRIZ_EVENTOS'
	BEGIN
		SELECT 'OK' AS OK

		SELECT CODIGO,DESCRIPCION 
		FROM TGEN 
		WHERE TABLA = 'FRADIAN' 
		AND CAMPO='EVENTOS' 
		ORDER BY DESCRIPCION

		RETURN
	END

    IF @METODO = 'GETEVENTOS'
    BEGIN
        SELECT @CNSRADIAN = CNSRADIAN
        FROM OPENJSON(@PARAMETROS)
        WITH(
            CNSRADIAN VARCHAR(20) '$.CNSRADIAN' 
        )

        DECLARE @TABLA AS TABLE(
            ID INT IDENTITY(1,1) PRIMARY KEY,
            FECHA DATETIME,
            CODEVENTO VARCHAR(20) DEFAULT '',
            DESCRIPCION VARCHAR(200) DEFAULT '',
            ESTADO VARCHAR(100) DEFAULT 'PROCESADO',
            USUARIO VARCHAR(200) DEFAULT 'SISTEMA',
            OBSERVACION VARCHAR(MAX) DEFAULT '',
			ITEM INT DEFAULT -1
        )

        SELECT 'OK' AS OK, @CNSRADIAN AS CNSRADIAN

        INSERT INTO @TABLA(FECHA,DESCRIPCION,USUARIO)
        SELECT TOP 1 FECHAEMISION, 'Emisión de Documento', RAZONSOCIAL FROM FRADIAN WHERE CNSRADIAN = @CNSRADIAN ORDER BY FECHA DESC 
        
        INSERT INTO @TABLA(FECHA,DESCRIPCION, USUARIO)
        SELECT TOP 1 FECHARADICACION,'Radicación de Documento a la DIAN', RAZONSOCIAL
        FROM FRADIAN WHERE CNSRADIAN = @CNSRADIAN AND FECHARADICACION IS NOT NULL ORDER BY FECHA DESC
        
        INSERT INTO @TABLA(FECHA,DESCRIPCION, USUARIO)
        SELECT TOP 1 FECHA,'Recepción del Documento', 'Correo' FROM FRADIAN WHERE CNSRADIAN = @CNSRADIAN AND FECHARECEPCION IS NOT NULL
        ORDER BY FECHA DESC

        INSERT INTO @TABLA(FECHA,CODEVENTO,USUARIO,OBSERVACION,ESTADO,DESCRIPCION,ITEM)
        SELECT FECHA,CODEVENTO,USUARIO,FRADIAND.OBSERVACION,
            CASE WHEN COALESCE(ERROR,0)=1 THEN 'ERROR'
            ELSE    CASE COALESCE(PROCESADO,0) WHEN 0 THEN 'PENDIENTE'
                    ELSE 'PROCESADO' END
            END 
            ,TGEN.DESCRIPCION
			,ITEM
        FROM FRADIAND 
        LEFT JOIN TGEN ON TGEN.TABLA='FRADIAN' AND TGEN.CAMPO='EVENTOS' AND FRADIAND.CODEVENTO = TGEN.CODIGO
        WHERE CNSRADIAN = @CNSRADIAN ORDER BY FECHA DESC

        SELECT * FROM @TABLA ORDER BY FECHA DESC

        RETURN
    END

	IF @METODO = 'GETENVIO'
	BEGIN

		SELECT @NODOCUMENTO = NODOCUMENTO 
		FROM FRADIAN 
		WHERE CNSRADIAN = JSON_VALUE(@PARAMETROS,'$.CNSRADIAN')
		

		SELECT METODO, FECHA, XML_SOLICITUD, XML_RESPUESTA
		FROM FDIANR 
		WHERE TIPO='EV'
		AND CNSDOCUMENTO = JSON_VALUE(@PARAMETROS,'$.ITEM')
		AND NUMDOC = @NODOCUMENTO
		ORDER BY ITEM DESC

	END

	IF @METODO = 'ACTUALIZAR_DATOS'
	BEGIN

		SELECT @CNSRADIAN = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.CNSRADIAN'))), '')

		BEGIN TRY
			UPDATE FRADIAN
			SET FECHAEMISION = COALESCE(FRADIAN.FECHAEMISION,CAST(REPLACE(LEFT(CONCAT(#T.FECHAEMISION,' ',#T.HORAEMISION),19),'-','') AS DATETIME))
				,MONTO = COALESCE(FRADIAN.MONTO,#T.MONTO)
				,DOCUMENTOXML = COALESCE(FRADIAN.DOCUMENTOXML,#T.DOCUMENTOXML)
				,UUID = COALESCE(NULLIF(LTRIM(RTRIM(FRADIAN.UUID)), ''),#T.UUID)

			FROM FRADIAN
			INNER JOIN OPENJSON(@PARAMETROS)
			WITH(
				CNSRADIAN VARCHAR(20) '$.CNSRADIAN',
				UUID VARCHAR(200) '$.UUID',
				FECHAEMISION DATE '$.FECHAEMISION',
				HORAEMISION TIME '$.HORAEMISION',
				DOCUMENTOXML VARCHAR(MAX) '$.DOCUMENTOXML',
				MONTO DECIMAL(14,2) '$.MONTO'
			) AS #T ON FRADIAN.CNSRADIAN = #T.CNSRADIAN

			-- No bloquea RADIAN si la conciliación no está desplegada o falla:
			-- la captura manual/masiva de IMOV.CUFE continúa disponible.
			IF @CNSRADIAN IS NOT NULL
			   AND OBJECT_ID(N'DBO.SPK_SINCRONIZAR_CUFE_RADIAN', N'P') IS NOT NULL
			BEGIN
				BEGIN TRY
					DECLARE @CUFE_ACTUALIZADOS_RADIAN INT
						,@CUFE_AMBIGUOS_RADIAN INT
						,@CUFE_SIN_COINCIDENCIA_RADIAN INT

					EXEC DBO.SPK_SINCRONIZAR_CUFE_RADIAN
						@CNSRADIAN = @CNSRADIAN,
						@CNSMOV = NULL,
						@ACTUALIZADOS = @CUFE_ACTUALIZADOS_RADIAN OUTPUT,
						@AMBIGUOS = @CUFE_AMBIGUOS_RADIAN OUTPUT,
						@SIN_COINCIDENCIA = @CUFE_SIN_COINCIDENCIA_RADIAN OUTPUT
				END TRY
				BEGIN CATCH
					PRINT CONCAT('Sincronización CUFE RADIAN pendiente: ', ERROR_MESSAGE())
				END CATCH
			END

		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) 
			SELECT ERROR_MESSAGE()      
			RETURN
		END CATCH

		SELECT 'OK' AS OK
		
		RETURN
	END

	IF @METODO = 'LOG'
	BEGIN
		DECLARE @DESCRIPCION VARCHAR(MAX)
		DECLARE @TIPO VARCHAR(1)
		SELECT @DESCRIPCION = JSON_VALUE(@PARAMETROS,'$.DESCRIPCION')
			,@TIPO = JSON_VALUE(@PARAMETROS,'$.TIPO')

		IF OBJECT_ID('FRADIANL','U') IS NOT NULL
		BEGIN
			
			INSERT INTO FRADIANL(DESCRIPCION, TIPO)
			SELECT @DESCRIPCION, COALESCE(@TIPO, 'I')
			WHERE @DESCRIPCION IS NOT NULL
		END
		ELSE
		BEGIN
			INSERT INTO TGEN(TABLA,CAMPO,CODIGO,DESCRIPCION,DATO1,FECHA1)
			SELECT 'FDIANR','LOG',LEFT(NEWID(),20),@DESCRIPCION,@TIPO,CURRENT_TIMESTAMP
			WHERE @DESCRIPCION IS NOT NULL
		END
		RETURN
	END


	IF @METODO = 'GETULTIMOSEVENTOS'
	BEGIN

		SELECT OK = 'OK'

		SELECT 
			DISTINCT COALESCE((SELECT TOP 1 CONCAT(TGEN.CODIGO, '|', TGEN.DESCRIPCION)
			FROM FRADIAND
			INNER JOIN TGEN ON TABLA='FRADIAN' AND CAMPO='EVENTOS' AND CODIGO=FRADIAND.CODEVENTO
			WHERE TGEN.CODIGO = FRADIAND.CODEVENTO
			AND FRADIAND.CNSRADIAN = FRADIAN.CNSRADIAN
			ORDER BY FECHA DESC, PROCESADO DESC),'') AS EVENTO
		FROM FRADIAN
		WHERE EXISTS(SELECT 1 FROM FRADIAND WHERE CNSRADIAN = FRADIAN.CNSRADIAN)

	END
	
END

