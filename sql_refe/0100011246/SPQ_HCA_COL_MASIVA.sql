CREATE OR ALTER PROCEDURE DBO.SPQ_HCA_COL_MASIVA
@JSON NVARCHAR(MAX)
WITH ENCRYPTION
AS
DECLARE @TBLERRORES     TABLE (ERROR VARCHAR(MAX))
DECLARE @PARAMETROS     NVARCHAR(MAX)	   ,@MODELO      VARCHAR(100)	,@METODO   VARCHAR(100)	,@GRUPO    VARCHAR(8) ,@SEDE  VARCHAR(5)			
	    ,@USUARIO        VARCHAR(20)	      ,@QUERY       NVARCHAR(MAX),@UNICO    INT 
       ,@TIPO           VARCHAR(20)       ,@DESCRIPCION VARCHAR(MAX) ,@PARAM    NVARCHAR(500)
       ,@IDAFILIADO     VARCHAR(20)
BEGIN
   SET DATEFORMAT dmy
	SET NOCOUNT ON

	SELECT *
	INTO #JSON
	FROM OPENJSON(@json) WITH (
			 MODELO  VARCHAR(100) '$.MODELO'
			,METODO  VARCHAR(100) '$.METODO'
			,USUARIO VARCHAR(100) '$.USUARIO'
			,PARAMETROS NVARCHAR(MAX) AS JSON
	)          
   SELECT @MODELO = MODELO ,@METODO = METODO ,@PARAMETROS = PARAMETROS ,@USUARIO = USUARIO FROM #JSON
	IF @METODO = 'CONSULTAR'
   BEGIN
        SET @TIPO = JSON_VALUE(@PARAMETROS, '$.TIPO');
        SELECT value AS CONSECUTIVO
        INTO #Consecutivos
        FROM OPENJSON(@PARAMETROS, '$.CONSECUTIVO');

        SELECT TOP 1 @IDAFILIADO = IDAFILIADO FROM HCA WHERE CONSECUTIVO IN (SELECT  CONSECUTIVO FROM #Consecutivos)

        --OK
        SELECT 'OK' OK
        --AFI
        SELECT AFI.IDAFILIADO, AFI.TIPO_DOC ,AFI.DOCIDAFILIADO, AFI.SEXO, AFI.NOMBREAFI ,AFI.FNACIMIENTO
              ,AFI.ESTADO_CIVIL ,AFI.ZONA ,AFI.IDOCUPACION, OCU.DESCRIPCION DESCOCUPACION
              ,AFI.IDSEDE ,SED.DESCRIPCION SEDE_AFILIADO ,AFI.GRUPOETNICO ,AFI.DIRECCION ,AFI.TELEFONORES
              ,AFI.CELULAR 
              ,ESCOLARIDAD = (SELECT DESCRIPCION FROM TGEN WHERE TABLA='AFI' AND CAMPO='ESCOLARIDAD' AND CODIGO=AFI.IDESCOLARIDAD)
              ,CASE AFI.TIPOAFILIADO WHEN 'C' THEN 'Cotizante'
                                     WHEN 'B' THEN 'Beneficiario'
                                     WHEN 'J' THEN 'Jubilado'
                                     WHEN 'A' THEN 'Adicional'
                                     WHEN 'S' THEN 'Sustitución Pensional'
                                     ELSE ''
               END VINCULACION
              ,AFI.CIUDAD ,CIU.NOMBRE CIUNOMBRE
              ,AFI.IDADMINISTRADORA ,TER.RAZONSOCIAL
              ,AFI.IDPLAN           ,PLN.DESCPLAN  
        FROM   AFI LEFT JOIN OCU ON AFI.IDOCUPACION = OCU.OCUPACION
                   LEFT JOIN SED ON AFI.IDSEDE      = SED.IDSEDE
                   LEFT JOIN CIU ON AFI.CIUDAD      = CIU.CIUDAD
                   LEFT JOIN TER ON AFI.IDADMINISTRADORA = TER.IDTERCERO
                   LEFT JOIN PLN ON AFI.IDPLAN      = PLN.IDPLAN
        WHERE IDAFILIADO = @IDAFILIADO
        --ENCABEZADOS DE LAS HC
        SELECT HCA.CONSECUTIVO ,HCA.FECHA ,COALESCE(HCA.FECHAATIENDE,HCA.FECHA) FECHAATIENDE ,HCA.IDMEDICO
              ,MED.NOMBRE ,MPL.DESCPLANTILLA, CIT.IDSERVICIO, SER.DESCSERVICIO ,HCA.REVISAESP ,HCA.IDEMEDICA
              ,MES.DESCRIPCION NOMESP_IDEMEDICA,HCA.MED_ESPEC ,MES1.DESCRIPCION NOMESP_MED_ESPEC
              ,FIRMA = (SELECT DICOM FROM ARCHIVOS WHERE ID = MED.IDFIRMA) 
              ,HCA.IDDX , MDX.DESCRIPCION, COALESCE(MDX.CONFIDENCIAL,0) CONFIDENCIAL
              ,EDAD = (SELECT  ANO, MES, DIA FROM dbo.FNK_EDAD_ANO_MES_DIA(AFI.FNACIMIENTO, HCA.FECHA) FOR JSON PATH)
        FROM   HCA LEFT JOIN MED ON HCA.IDMEDICO = MED.IDMEDICO
                   LEFT JOIN MPL ON HCA.CLASEPLANTILLA = MPL.CLASEPLANTILLA 
                   LEFT JOIN CIT ON HCA.NOADMISION     = CIT.CONSECUTIVO
                   LEFT JOIN SER ON CIT.IDSERVICIO     = SER.IDSERVICIO
                   LEFT JOIN MES ON HCA.IDEMEDICA      = MES.IDEMEDICA
                   LEFT JOIN MES MES1 ON HCA.MED_ESPEC = MES1.IDEMEDICA
                   LEFT JOIN MDX ON HCA.IDDX           = MDX.IDDX
                   LEFT JOIN AFI ON HCA.IDAFILIADO     = AFI.IDAFILIADO
        WHERE  HCA.CONSECUTIVO IN (SELECT CONSECUTIVO FROM #Consecutivos)
        ORDER BY MPL.DESCPLANTILLA, HCA.FECHA
         
        --DETALLES DE LAS HC (HCAD) 
        SELECT * INTO #hcad_C 
		  FROM (SELECT HCAD.CONSECUTIVO
				        ,HCAD.CAMPO
				        ,HCAD.SECUENCIA
				        ,CASE WHEN HCAD.TIPOCAMPO = '' THEN MPLD.TIPO_CAMPO ELSE HCAD.TIPOCAMPO END TIPOCAMPO
				        ,MPLD.DESCCAMPO
				        ,MPLD.DEPENDEDE
				        ,DEFAULT1
				        ,HCAD.ALFANUMERICO
				        ,CASE 
				        	WHEN HCAD.TIPOCAMPO = 'Krystalos' AND MPLD.O_KRYSTALOS='SERVICIO' AND COALESCE(MPLD.IMP_CODIGO,'')<>'IDSERVICIO'
				        		THEN (
				        				SELECT '['+IIF(COALESCE(MPLD.IMP_CODIGO,'')='AMBOS',COALESCE(SER.IDSERVICIO,'')+' - ','')+COALESCE(SER.CODCUPS,SER.IDSERVICIO,'')+']'
				        				FROM SER WHERE IDSERVICIO=HCAD.ALFANUMERICO
				        				)
				        	ELSE HCAD.ALFANUMERICO
				        	END
				        	KRYSTALOSCOD
                    ,HCAD.FECHA
					     -- EZERPA 20231019, LO QUE PARECE UN ESPACIO NO ES UN ESPACIO, OJO CON ESO, NO TOCAR
					     ,MEMO = dbo.FNK_LIMPIATEXTO(REPLACE(REPLACE(REPLACE(REPLACE(HCAD.MEMO,'__','_ '),'--','- '),'	',' '),'*','* '),'/^[\w\W ]+$/')
					     ,HCAD.NUMERICO
					     ,CASE HCAD.TIPOCAMPO
						     WHEN 'Lista'
						      THEN (
								      SELECT TOP 1 MPLDL.DESCRIPCION
								      FROM MPLDL
								      WHERE MPLD.CLASEPLANTILLA = MPLDL.CLASEPLANTILLA
									      AND MPLD.CAMPO = MPLDL.CAMPO
									      AND MPLDL.VALOR = HCAD.NUMERICO
								      )
						     ELSE ''
						   END MPLDLDESCRIPCION
					     ,MPLD.C_KRYSTALOS
					     ,MPLD.D_KRYSTALOS
					     ,MPLD.F_KRYSTALOS
					     ,MPLD.O_KRYSTALOS
					     ,MPLD.T_KRYSTALOS
                    ,'SELECT @DESCRIPCION_OUT= ' 
					      +CASE 
						     WHEN HCAD.TIPOCAMPO = 'Krystalos' AND MPLD.O_KRYSTALOS='SERVICIO' AND COALESCE(MPLD.IMP_CODIGO,'')<>'IDSERVICIO'
						      THEN 'IIF(COALESCE(SER.DESCRIPCION_CUPS,'''')<>'''',SER.DESCRIPCION_CUPS,SER.DESCSERVICIO)'
						     ELSE MPLD.D_KRYSTALOS
						    END 
						   + ' FROM ' + MPLD.T_KRYSTALOS + ' WHERE ' + MPLD.C_KRYSTALOS + ' = ''' + HCAD.ALFANUMERICO + ''' AND ' + CASE WHEN COALESCE(MPLD.F_KRYSTALOS,'') = '' THEN '1=1' ELSE  COALESCE(MPLD.F_KRYSTALOS,'') END K1
					     ,'' HCADCP
					     ,IMAGEN = 
						     CASE WHEN HCAD.TIPOCAMPO!='Imagen' OR COALESCE(HCAD.ALFANUMERICO, '')='' THEN NULL 
						     ELSE 
						      (
						      SELECT TOP 1 CAST(N'' AS XML).value('xs:base64Binary(xs:hexBinary(sql:column("bin")))', 'VARCHAR(MAX)')  
						      FROM (SELECT DOCFS AS BIN FROM DOCS WHERE DOCUMENTOID = HCAD.ALFANUMERICO) AS X
						      ) END
					     ,ARCHIVO_IMAGEN = 
						     CASE WHEN HCAD.TIPOCAMPO!='Imagen' OR COALESCE(HCAD.ALFANUMERICO, '')='' THEN NULL 
						     ELSE (SELECT DOCUMENTOID,DOCNOMBRE,DOCEXTENSION FROM DOCS WHERE DOCS.DOCUMENTOID=HCAD.ALFANUMERICO AND DOCCNSAUXILIAR=HCAD.CONSECUTIVO FOR JSON AUTO)
						     END
					     ,MPLD.IMPRIMESINDATO
					     ,ENEPICRISIS = COALESCE(HCAD.ENEPICRISIS, MPLD.ENEPICRISIS, 0)
					     ,CAST(COALESCE(MPLD.NOIMPRIME, 0) AS BIT) AS NOIMPRIME
					     , HCAD.IDIMAGEN , HCAD.ANCHOIMG, HCAD.ALTOIMG, HCAD.ESCALAX, HCAD.ESCALAY, CAST(COALESCE(MPLD.IMPHORA,0) AS BIT) IMPHORA
				  FROM HCAD INNER JOIN MPLD ON HCAD.CLASEPLANTILLA = MPLD.CLASEPLANTILLA
				        	                   AND HCAD.CAMPO = MPLD.CAMPO
				  WHERE HCAD.CONSECUTIVO IN (SELECT CONSECUTIVO FROM #Consecutivos)
            ) X
		   ALTER TABLE #hcad_C ADD UNICO INT IDENTITY
			ALTER TABLE #hcad_C ADD KRYSTALOSDESC VARCHAR(500)
			SET @PARAM = N'@DESCRIPCION_OUT VARCHAR(500) OUTPUT'

			DECLARE HCAD_c CURSOR FOR
			SELECT k1,UNICO FROM #hcad_C WHERE TIPOCAMPO = 'Krystalos'
			OPEN HCAD_c
			FETCH NEXT FROM HCAD_c INTO @QUERY,@UNICO
			WHILE @@FETCH_STATUS = 0
			BEGIN
				BEGIN TRY  
					EXEC sp_executesql @QUERY ,@PARAM ,@DESCRIPCION_OUT = @DESCRIPCION OUTPUT

					UPDATE #hcad_C SET KRYSTALOSDESC = @DESCRIPCION WHERE UNICO = @UNICO
				END TRY  
				BEGIN CATCH  
					UPDATE #hcad_C SET KRYSTALOSDESC = '' WHERE UNICO = @UNICO 
				END CATCH

				SELECT @DESCRIPCION = NULL
				FETCH NEXT FROM HCAD_c INTO @QUERY,@UNICO
			END
			CLOSE HCAD_c
			DEALLOCATE HCAD_c
			
			SELECT
				CONSECUTIVO		,CAMPO		,DEFAULT1
				,SECUENCIA		,TIPOCAMPO	,DESCCAMPO
				,ALFANUMERICO	,FECHA		,MEMO
				,DEPENDEDE
				,NUMERICO		,MPLDLDESCRIPCION
				,C_KRYSTALOS	,D_KRYSTALOS
				,F_KRYSTALOS	,O_KRYSTALOS
				,T_KRYSTALOS	,KRYSTALOSDESC
				,KRYSTALOSCOD
				,IIF(TIPOCAMPO = 'Krystalos'
				,(SELECT DESCRIPCION FROM MDX AS X WHERE X.IDDX=ALFANUMERICO), '')KRYSTALOSDESC2
				,IMAGEN		,ARCHIVO_IMAGEN		,IMPRIMESINDATO
				,NOIMPRIME
				, #HCAD_C.IDIMAGEN , #HCAD_C.ANCHOIMG, #HCAD_C.ALTOIMG, #HCAD_C.ESCALAX, #HCAD_C.ESCALAY, #HCAD_C.IMPHORA
			FROM #HCAD_C 
			WHERE COALESCE(IMPRIMESINDATO, 0) = 1
			OR (
				DBO.FNK_LIMPIATEXTO(COALESCE(ALFANUMERICO, ''),'A-Z0-9')<>''
				OR DBO.FNK_LIMPIATEXTO(COALESCE(MEMO, ''),'A-Z0-9')<>''
				OR FECHA IS NOT NULL
				OR NUMERICO IS NOT NULL
				OR IMAGEN IS NOT NULL
				OR ARCHIVO_IMAGEN IS NOT NULL
				OR (TIPOCAMPO='MultiCheck'
					AND EXISTS (SELECT * FROM HCADL WHERE CONSECUTIVO=#HCAD_C.CONSECUTIVO  AND SECUENCIA=#HCAD_C.SECUENCIA AND CHECKM>0)
				)
				OR (TIPOCAMPO='ImgDescrita'
					AND EXISTS (SELECT * FROM HCADL WHERE CONSECUTIVO=#HCAD_C.CONSECUTIVO  AND SECUENCIA=#HCAD_C.SECUENCIA )
				)
			)
			ORDER BY CONSECUTIVO, SECUENCIA	
			
			

   END
END


