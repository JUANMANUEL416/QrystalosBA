				@CLASEPLANTILLA = COALESCE(NULLIF(J.CLASEPLANTILLA, ''), @CLASEPLANTILLA)
			FROM OPENJSON(@PARAMETROS)
			WITH (
				IDAFILIADO VARCHAR(20) '$.IDAFILIADO',
				CLASEPLANTILLA VARCHAR(20) '$.CLASEPLANTILLA'
			) J;
		END;

		SELECT
			HCA.CONSECUTIVO,
			HCA.FECHA,
			HCA.IDMEDICO,
			MED.NOMBRE AS NOMBRE_MEDICO,
			PLN.IDPLAN,
			PLN.DESCPLAN,
			-- Variables estáticas paciente (formatos especiales HCA; antes AFICOL.CONSULTAAFI_BY_CINF)
			TGEN.CODIGO AS TIPODOC,
			AFI.IDAFILIADO,
			AFI.DOCIDAFILIADO AS DOCUMENTO,
			AFI.NOMBREAFI AS NOMBREAFILIADO,
			AFI.PNOMBRE AS PRIMER_NOMBRE,
			AFI.SNOMBRE AS SEGUNDO_NOMBRE,
			AFI.PAPELLIDO AS PRIMER_APELLIDO,
			AFI.SAPELLIDO AS SEGUNDO_APELLIDO,
			AFI.EDAD AS EDADAFI,
			AFI.SEXO,
			--CONVERT(VARCHAR(10), AFI.FNACIMIENTO, 23) AS FNACIMIENTO,
			CONVERT(VARCHAR(10), AFI.FNACIMIENTO, 103) AS FNACIMIENTO,
			CONVERT(VARCHAR(10), HCA.FECHA, 103) + ' ' + LEFT(CONVERT(VARCHAR(8), HCA.FECHA, 108), 5) AS FECHA_ATENCION,
			AFI.CELULAR AS CELULAR_AFI,
			AFI.DIRECCION AS DIRECCION_AFI,
			AFI.EMAIL AS EMAIL_AFI,
			AFI.NUMERO_FICHA,
			DETALLE_JSON.DETALLE
		FROM HCA
		INNER JOIN AFI ON HCA.IDAFILIADO = AFI.IDAFILIADO
		LEFT JOIN TGEN ON AFI.TIPO_DOC = TGEN.CODIGO
			AND TGEN.TABLA = 'General'
			AND TGEN.CAMPO = 'TIPOIDENT'
		LEFT JOIN MED ON MED.IDMEDICO = HCA.IDMEDICO
		LEFT JOIN PLN ON PLN.IDPLAN = COALESCE(NULLIF(HCA.IDPLAN, ''), AFI.IDPLAN)
		OUTER APPLY (
			SELECT
				HCAD.CAMPO,
				HCAD.SECUENCIA,
				HCAD.TIPOCAMPO,
				HCAD.ALFANUMERICO,
				HCAD.LISTA,
				HCAD.MEMO,
				HCAD.NUMERICO,
				MPLD.DESCCAMPO
			FROM HCAD
			INNER JOIN MPLD ON HCAD.CAMPO = MPLD.CAMPO
				AND HCA.CLASEPLANTILLA = MPLD.CLASEPLANTILLA
			WHERE HCAD.CONSECUTIVO = HCA.CONSECUTIVO
			FOR JSON PATH
		) AS DETALLE_JSON(DETALLE)
		WHERE HCA.IDAFILIADO = @IDAFILIADO
		  AND HCA.CLASEPLANTILLA = @CLASEPLANTILLA
		ORDER BY HCA.FECHA ASC;

	END


