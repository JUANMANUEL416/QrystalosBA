			    FROM   HCASV LEFT JOIN TGSV ON TGSV.CODIGOSV = HCASV.CODIGOSV AND TGSV.GRUPO = HCASV.GRUPO AND TGSV.CLASESV = HCASV.CLASESV
			    WHERE  HCASV.CONSECUTIVO=@CONSECUTIVO
			    ORDER BY CONSECUTIVO, ORDENSV
            END
			*/
		END

		IF OBJECT_ID('tempdb..#MPLD') IS NOT NULL DROP TABLE #MPLD
		SELECT MPLD.CLASEPLANTILLA, MPLD.SECUENCIA, MPLD.CAMPO, MPLD.TIPO_CAMPO, MPLD.DESCCAMPO, MPLD.DEPENDEDE, MPLD.DEFAULT1
			,MPLD.O_KRYSTALOS, MPLD.C_KRYSTALOS, MPLD.D_KRYSTALOS, MPLD.F_KRYSTALOS, MPLD.T_KRYSTALOS, MPLD.IMP_CODIGO
			,MPLD.IMPRIMESINDATO, MPLD.ENEPICRISIS, MPLD.NOIMPRIME, MPLD.IMPHORA, MPLD.MATRIZ
			,OTRO_MODULO = CAST(COALESCE(MPLD.OTRO_MODULO,'') AS NVARCHAR(MAX))
		INTO #MPLD
		FROM MPLD
		WHERE MPLD.CLASEPLANTILLA = @CLASEPLANTILLA
			AND MPLD.TIPO_CAMPO <> 'Grafica'
			AND MPLD.ESTADO <> 'Inactivo'
			AND @CLASEPLANTILLA <> @CLASE_PLANTILLA_EVOLUCION
			AND MPLD.CLASEPLANTILLA NOT IN ('MP_RIAS','IN_RIAS','PI_RIAS','ADO_RIAS','JU_RIAS')

		IF COALESCE(@NOADMISION,'') = ''
			UPDATE #MPLD SET OTRO_MODULO = '[]' WHERE TIPO_CAMPO = 'Informativo'
		ELSE
		BEGIN
			DECLARE @CUR_OTRO_SEC INT, @CUR_OTRO_JSON NVARCHAR(MAX)
			DECLARE @NOM_MOD NVARCHAR(128), @COLS_MOD NVARCHAR(MAX), @SQL_OTRO NVARCHAR(MAX), @JSON_OTRO NVARCHAR(MAX)
			DECLARE cur_otro CURSOR LOCAL FOR
				SELECT SECUENCIA, OTRO_MODULO FROM #MPLD
				WHERE TIPO_CAMPO = 'Informativo'
					AND ISJSON(OTRO_MODULO) = 1
					AND LOWER(LTRIM(RTRIM(ISNULL(JSON_VALUE(OTRO_MODULO, '$.ES_OTRO_MODULO'),'')))) = 'true'
			OPEN cur_otro
			FETCH NEXT FROM cur_otro INTO @CUR_OTRO_SEC, @CUR_OTRO_JSON
			WHILE @@FETCH_STATUS = 0
			BEGIN
				SET @NOM_MOD = JSON_VALUE(@CUR_OTRO_JSON, '$.NOM_MODULO')
				SELECT @COLS_MOD = STRING_AGG(QUOTENAME(LTRIM(RTRIM([value]))), ',')
				FROM OPENJSON(JSON_QUERY(@CUR_OTRO_JSON, '$.COLUMNAS_MODULO'))
				IF @NOM_MOD IS NOT NULL AND @COLS_MOD IS NOT NULL
				BEGIN
					IF @NOM_MOD = 'HACTRAN'
						SET @SQL_OTRO = N'SET @json = (SELECT NATUREVENTO,FECHAACC,TIPOVEHICULO,CONDICIONACC,INFORME FROM HACTRAN WITH (NOLOCK) WHERE CNSHACTRAN = (SELECT CNSHACTRAN FROM HADM WHERE NOADMISION = @noadm) FOR JSON PATH, INCLUDE_NULL_VALUES)'
					ELSE
						SET @SQL_OTRO = N'SET @json = (SELECT ' + @COLS_MOD + N' FROM ' + QUOTENAME(@NOM_MOD) + N' WITH (NOLOCK) WHERE NOADMISION = @noadm FOR JSON PATH, INCLUDE_NULL_VALUES)'
					SET @JSON_OTRO = NULL
					BEGIN TRY
						EXEC sp_executesql @SQL_OTRO,
							N'@json NVARCHAR(MAX) OUTPUT, @noadm VARCHAR(20)',
							@json = @JSON_OTRO OUTPUT,
							@noadm = @NOADMISION
						UPDATE #MPLD SET OTRO_MODULO = COALESCE(@JSON_OTRO, '[]') WHERE SECUENCIA = @CUR_OTRO_SEC
					END TRY
					BEGIN CATCH
						UPDATE #MPLD SET OTRO_MODULO = '[]' WHERE SECUENCIA = @CUR_OTRO_SEC
					END CATCH
				END
				FETCH NEXT FROM cur_otro INTO @CUR_OTRO_SEC, @CUR_OTRO_JSON
			END
			CLOSE cur_otro
			DEALLOCATE cur_otro
		END
		BEGIN -- 4.- Cuerpo de la Historia HCAD
			DECLARE @HCAD_C AS TABLE (
				UNICO INT IDENTITY,
				CONSECUTIVO VARCHAR(MAX),
				CAMPO VARCHAR(50),
				SECUENCIA INT,
				TIPOCAMPO VARCHAR(MAX),
				DESCCAMPO VARCHAR(MAX),
				DEPENDEDE VARCHAR(MAX),
				DEFAULT1 VARCHAR(MAX),
				ALFANUMERICO VARCHAR(MAX),
				KRYSTALOSCOD VARCHAR(MAX),
				FECHA DATETIME,
				MEMO VARCHAR(MAX),
				NUMERICO DECIMAL(18,2),
				MPLDLDESCRIPCION VARCHAR(MAX),
				C_KRYSTALOS VARCHAR(MAX),
				D_KRYSTALOS VARCHAR(MAX),
				F_KRYSTALOS VARCHAR(MAX),
				O_KRYSTALOS VARCHAR(MAX),
				T_KRYSTALOS VARCHAR(MAX),
				K1 VARCHAR(MAX),
				HCADCP VARCHAR(MAX),
				IMAGEN VARCHAR(MAX),
				ARCHIVO_IMAGEN VARCHAR(MAX),
				IMPRIMESINDATO VARCHAR(MAX),
				ENEPICRISIS BIT,
				NOIMPRIME BIT,
				IDIMAGEN VARCHAR(100),
				ANCHOIMG INT,
				ALTOIMG INT,
				ESCALAX INT,
				ESCALAY INT,
                IMPHORA BIT,
                KRYSTALOSDESC VARCHAR(MAX),
                MATRIZ NVARCHAR(MAX),
                MATRIZCONF NVARCHAR(MAX),
                OTRO_MODULO NVARCHAR(MAX)
			)
            INSERT INTO @HCAD_C (CONSECUTIVO, CAMPO, SECUENCIA, TIPOCAMPO, DESCCAMPO, DEPENDEDE, DEFAULT1, ALFANUMERICO, KRYSTALOSCOD, FECHA, MEMO, NUMERICO, MPLDLDESCRIPCION, C_KRYSTALOS, D_KRYSTALOS, F_KRYSTALOS, O_KRYSTALOS, T_KRYSTALOS, K1, HCADCP, IMAGEN, ARCHIVO_IMAGEN, IMPRIMESINDATO, ENEPICRISIS, NOIMPRIME, IDIMAGEN, ANCHOIMG, ALTOIMG, ESCALAX, ESCALAY, IMPHORA, MATRIZ, MATRIZCONF, OTRO_MODULO)
            SELECT CONSECUTIVO, CAMPO, SECUENCIA, TIPOCAMPO, DESCCAMPO, DEPENDEDE, DEFAULT1, ALFANUMERICO, KRYSTALOSCOD, FECHA, MEMO, NUMERICO, MPLDLDESCRIPCION, C_KRYSTALOS, D_KRYSTALOS, F_KRYSTALOS, O_KRYSTALOS, T_KRYSTALOS, K1, HCADCP, IMAGEN, ARCHIVO_IMAGEN, IMPRIMESINDATO, ENEPICRISIS, NOIMPRIME, IDIMAGEN, ANCHOIMG, ALTOIMG, ESCALAX, ESCALAY, IMPHORA, MATRIZ, MATRIZCONF, OTRO_MODULO
			FROM (SELECT HCAD.CONSECUTIVO
					,HCAD.CAMPO
					,HCAD.SECUENCIA
					,CASE WHEN HCAD.TIPOCAMPO = '' THEN M.TIPO_CAMPO ELSE HCAD.TIPOCAMPO END TIPOCAMPO
					,M.DESCCAMPO
					,M.DEPENDEDE
					,M.DEFAULT1
					,HCAD.ALFANUMERICO
					,CASE
						WHEN HCAD.TIPOCAMPO = 'Krystalos' AND M.O_KRYSTALOS='SERVICIO' AND COALESCE(M.IMP_CODIGO,'')<>'IDSERVICIO'
							THEN (
									SELECT '['+IIF(COALESCE(M.IMP_CODIGO,'')='AMBOS',COALESCE(SER.IDSERVICIO,'')+' - ','')+COALESCE(SER.CODCUPS,SER.IDSERVICIO,'')+']'
									FROM SER WHERE IDSERVICIO=HCAD.ALFANUMERICO
									)
						ELSE HCAD.ALFANUMERICO
						END
						KRYSTALOSCOD
					,HCAD.FECHA
					,MEMO = dbo.FNK_LIMPIATEXTO(REPLACE(REPLACE(REPLACE(REPLACE(HCAD.MEMO,'__','_ '),'--','- '),'	',' '),'*','* '),'/^[\w\W ]+$/')
					,HCAD.NUMERICO
					,CASE HCAD.TIPOCAMPO
						WHEN 'Lista'
							THEN (
									SELECT TOP 1 MPLDL.DESCRIPCION
									FROM MPLDL
									WHERE M.CLASEPLANTILLA = MPLDL.CLASEPLANTILLA AND M.CAMPO = MPLDL.CAMPO AND MPLDL.VALOR = HCAD.NUMERICO
									)
						ELSE ''
						END MPLDLDESCRIPCION
					,M.C_KRYSTALOS
					,M.D_KRYSTALOS
					,M.F_KRYSTALOS
					,M.O_KRYSTALOS
                    ,M.T_KRYSTALOS
