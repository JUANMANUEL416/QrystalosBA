			SELECT * FROM AFIFAMREL WHERE IDAFILIADO = @IDAFILIADO

			SELECT AFIECOMAPA.ID ,AFIECOMAPA.IDAFILIADO ,AFIECOMAPA.FECHA ,AFIECOMAPA.IDAFIFAM1 ,AFIECOMAPA.TRABAJO ,AFIECOMAPA.AMIGOS ,AFIECOMAPA.EDUCACION ,AFIECOMAPA.RELIGION
