				 								AND AIEPIAFI.IDAFILIADO     = @IDAFILIADO
				 			LEFT JOIN HCA      ON AIEPIAFI.CONSECUTIVOHCA = HCA.CONSECUTIVO
			    WHERE (
				 		(@CLASEPLANTILLA = 'IN_RIAS' AND CNFAIEPI.CLASE IN ('ASPECTOS'))
				 		OR (@CLASEPLANTILLA = 'PI_RIAS' AND CNFAIEPI.CLASE IN ('AIEPI','ASPECTOS'))
				 	)
