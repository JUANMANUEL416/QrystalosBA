				, O.DISPENSACION ,O.ESCALIDAD ,O.CALIDAD ,O.ESADMINISTRACION ,O.ADMINISTRACION ,O.ESUSO ,O.USO ,O.RECOMENDACIONES
			FROM HCPRUM O LEFT JOIN SER ON SER.IDSERVICIO=O.IDSERVICIO
			WHERE O.CONSECUTIVOHCA=@CONSECUTIVO
		END
