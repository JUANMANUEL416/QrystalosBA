			    ,CNFRIAEXA.ORDEN CNFRIAEXA_ORDEN ,CNFRIAEXA.IDSERVICIO CNFRIAEXA_IDSERVICIO ,CNFRIAEXA.IDHOMOLOGO CNFRIAEXA_IDHOMOLOGO
