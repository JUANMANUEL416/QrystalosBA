CREATE OR ALTER PROCEDURE DBO.SPQ_HCA_COL_V3
	@JSON NVARCHAR(MAX)
WITH ENCRYPTION
AS
DECLARE @DXS AS TABLE (
	CONSECUTIVO VARCHAR(20)		,IDAFILIADO VARCHAR(20)		,NOADMISION VARCHAR(20)
	,PROCEDENCIA VARCHAR(20)	,FECHA DATETIME				,TIPO VARCHAR(20)
	,DX VARCHAR(20)				,TIPODX VARCHAR(20)			,ESTADO VARCHAR(20)
	,DESCRIPCION VARCHAR(MAX)	,FECHASINTOMAS DATETIME		,FECHACONFIRMACION DATETIME
	,CONFIDENCIAL BIT DEFAULT 0
	)
DECLARE @PARAMETROS      NVARCHAR(MAX)	,@FINI			    DATE
		,@FFIN			    DATE			,@MODELO          VARCHAR(100)
		,@METODO		    VARCHAR(100)	,@QUERY           NVARCHAR(MAX)
		,@GRUPO		       VARCHAR(8)		,@SEDE            VARCHAR(5)
		,@USUARIO		    VARCHAR(20) ,@FILTRO		    VARCHAR(250)
	    ,@ORDEN           VARCHAR(100)	,@PAGINA          INT
	    ,@FILASXPAG       INT			,@DEFCOLUMNS      BIT
	    ,@NOADMISION      VARCHAR(16)	,@CONSECUTIVO     VARCHAR(13)
	    ,@UNICO           INT			,@DESCRIPCION     VARCHAR(MAX)
	    ,@PARAM           NVARCHAR(500)	,@FECHAHCA        DATETIME
	    ,@CNSWEB          VARCHAR(100)	,@CLASEPLANTILLA  VARCHAR(8)
	    ,@IDAFILIADO      VARCHAR(20)	,@IDMEDICO        VARCHAR(20)
	    ,@SYS_COMPUTERNAM VARCHAR(200)	,@CONSECUTIVOS    VARCHAR(8000)
	    ,@IDMEDICO_AUX     VARCHAR(20)	,@IDMEDICO_ESPECIALISTA VARCHAR(20)
	    ,@MESES_HISTORICO  INT			,@CONSECUTIVOHCA   VARCHAR(20)
		,@ENEPICRISIS	   SMALLINT = 0	,@SYS_COMPUTERNAME VARCHAR(1000)
		,@CORREOS VARCHAR(MAX)			,@CORREGIMIENTO VARCHAR(20)
		,@DPR_RAZONSOCIAL VARCHAR(1000),@DPR_NIT  VARCHAR(20)
		,@DPR_DV	 VARCHAR(1)			,@DPR		VARCHAR(10) = dbo.FNK_VALORVARIABLE('DATOSPROPIETARIO')
		,@EXISTS_COLUMN_CNSHCA_CITACONTROL BIT = IIF(COL_LENGTH('CIT','CNSHCA_CITACONTROL') IS NOT NULL,1,0)
		,@DIAS_CADUCIDAD_OM INT
		,@ASI_UTILIZAFIRMA_HC VARCHAR(2) = DBO.FNK_VALORVARIABLE('ASI_UTILIZAFIRMA_HC')
		,@SEXO VARCHAR(15)
		,@CODIGO_MED VARCHAR(20) = DBO.FNK_VALORVARIABLE('OMCODMEDICAMENTOS')
		,@CLASE_PLANTILLA_EVOLUCION VARCHAR(20)= dbo.FNK_VALORVARIABLE('HCPLANTILLARED')
		,@CONSECUTIVO_HCADX VARCHAR(20)	,@ESPROGRAMAS BIT
		,@IDFIRMA	UNIQUEIDENTIFIER	,@FIRMA		VARBINARY(MAX)
		,@FIRMABLOB	VARCHAR(MAX)		,@IDAUT		VARCHAR(20)
		,@ID_QCORE10 INT				,@DPR_DIRECCION VARCHAR(MAX)
		,@NIT_DPR VARCHAR(20)			,@IDPLAN	VARCHAR(20)
		,@FECHA_DILIGENCIA DATETIME
		DECLARE @DBNAME_DOCU VARCHAR(200)
		DECLARE @USA_DOCU_BD VARCHAR(2)
		DECLARE @SQL NVARCHAR(MAX);
BEGIN
	SET DATEFORMAT dmy
	SET NOCOUNT ON
	SET DATEFIRST 1;

	SELECT *
	INTO #JSON
	FROM OPENJSON(@json) WITH (
			MODELO  VARCHAR(100) '$.MODELO'
			,METODO  VARCHAR(100) '$.METODO'
			,CNSWEB  VARCHAR(100) '$.CNSWEB'
			,USUARIO VARCHAR(100) '$.USUARIO'
			,DEFCOLUMNS BIT '$.DEFCOLUMNS'
			,PARAMETROS NVARCHAR(MAX) AS JSON
	)

	SELECT @MODELO  = MODELO
		,@METODO     = METODO
		,@PARAMETROS = PARAMETROS
		,@DEFCOLUMNS = DEFCOLUMNS
		,@USUARIO    = USUARIO
		,@CNSWEB     = CNSWEB
	FROM #JSON

	SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO), @IDMEDICO = IDMEDICO FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME FROM USUSU WHERE USUARIO = @USUARIO
	SELECT @SEDE = IDSEDE FROM UBEQ WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	SELECT @DPR_RAZONSOCIAL = RAZONSOCIAL, @DPR_NIT = NIT, @DPR_DV=  DV
		,@DPR_DIRECCION = TER.DIRECCION
	FROM TER
	--LEFT JOIN CIU ON CIU.CIUDAD=TER.CIUDAD
	WHERE IDTERCERO = dbo.FNK_VALORVARIABLE('IDTERCEROINSTALADO')

	IF @METODO = 'CONSULTAR_PANTALLA'
	BEGIN
		SELECT @DBNAME_DOCU = DBO.FNK_VALORVARIABLE('NAME_DOCU_DB');
		SELECT @USA_DOCU_BD = DBO.FNK_VALORVARIABLE ('USA_DOCU_BD')

		SELECT @FILTRO = FILTRO
			,@PAGINA = PAGINA
			,@FILASXPAG = FILASXPAG
			,@ORDEN = ORDEN
			,@CONSECUTIVO = CONSECUTIVO
			,@CONSECUTIVOS = CONSECUTIVOS
			,@ENEPICRISIS = ENEPICRISIS
		FROM OPENJSON(@PARAMETROS) WITH (
			FILTRO VARCHAR(250) '$.FILTRO'
			,PAGINA INT '$.PAGINA'
			,FILASXPAG INT '$.FILASXPAG'
			,ORDEN VARCHAR(100) '$.ORDEN'
			,CONSECUTIVO VARCHAR(13) '$.CONSECUTIVO'
			,ENEPICRISIS SMALLINT '$.ENEPICRISIS'
			,CONSECUTIVOS VARCHAR(8000) '$.CONSECUTIVOS'
		)

		SELECT @NOADMISION = NOADMISION
			,@FECHAHCA = FECHA
			,@CLASEPLANTILLA = CLASEPLANTILLA
			,@IDAFILIADO = IDAFILIADO
			,@FECHA_DILIGENCIA = HCA.FECHA_DILIGENCIA

		FROM HCA
		WHERE CONSECUTIVO = @CONSECUTIVO

		-- 1.- OK de la consulta
		SELECT 'OK' OK ,@CONSECUTIVO CONSECUTIVO
		BEGIN -- 2.- Datos de la Historia Clinica
			BEGIN TRY
				SELECT @DIAS_CADUCIDAD_OM = DBO.FNK_VALORVARIABLE('DIAS_CADUCIDAD_OM')
			END TRY
			BEGIN CATCH
				SELECT @DIAS_CADUCIDAD_OM = 0
			END CATCH

			IF @DIAS_CADUCIDAD_OM IS NULL
				SELECT @DIAS_CADUCIDAD_OM = 0

			SELECT @NIT_DPR = NIT FROM TER WHERE IDTERCERO = DBO.FNK_VALORVARIABLE('IDTERCEROINSTALADO')
			
            SELECT @IDPLAN = COALESCE(HCA.IDPLAN,CIT.IDPLAN,HADM.IDPLAN)
			FROM HCA WITH(NOLOCK)
                LEFT JOIN CIT WITH(NOLOCK) ON CIT.CONSECUTIVO = COALESCE(HCA.CONSECUTIVOCIT,HCA.NOADMISION,'') AND HCA.PROCEDENCIA NOT IN ('QX')
			    LEFT JOIN HADM WITH(NOLOCK) ON HADM.NOADMISION = HCA.NOADMISION
			WHERE HCA.CONSECUTIVO = @CONSECUTIVO

			SELECT
				HCA.CONSECUTIVO
				,HCA.FECHA
				,HCA.CNSWEB
				,HCA.CLASE
				,HCA.PROCEDENCIA
				,HCA.IDAFILIADO
				,HCA.IDMEDICO
				,HCA.CLASEPLANTILLA
				,HCA.NOADMISION
				,HCA.REVISADO
				,ANULADA = COALESCE(HCA.ANULADA,0)
				,HCA.TIPODX
				,HCA.IDDX
                ,MPL.MTACTIVO
				,COALESCE(MPL.FORMATO_ESPECIAL,0) AS FORMATO_ESPECIAL
				,IMPRIMEOM = COALESCE(MPL.IMPRIMEOM,0)
				,HCA.DX1
				,HCA.DX2
				,HCA.DX3
				,HCA.DX4
                ,AFI.DOCIDAFILIADO
				,NOMBREMEDICODIL = CASE WHEN @ASI_UTILIZAFIRMA_HC <> 'SI' THEN '' ELSE MED.NOMBRE END
				,CMPMEDICODIL = CASE WHEN @ASI_UTILIZAFIRMA_HC <> 'SI' THEN '' ELSE MED.NO_REGISTRO END
				,RMMEDICODIL = MED.BEEPER
				,RNE = MED.BEEPER
				,MED.FIRMA_ANCHO
				,MED.FIRMA_ALTO
				,MED.FIRMA_X
				,MED.FIRMA_Y
				,MED.FIRMA_IMPRIME_DATOS_MED
                ,FIRMA = CASE WHEN @ASI_UTILIZAFIRMA_HC <> 'SI' THEN NULL ELSE (SELECT DICOM FROM ARCHIVOS WHERE ID = MED.IDFIRMA) END
                ,UTILIZAFIRMA = IIF(@ASI_UTILIZAFIRMA_HC <> 'SI', 0, 1)
				,MPL.DESCPLANTILLA
                ,GRUPAL=CAST(COALESCE(MPL.GRUPAL,0) AS BIT)
                ,TIENEOM=CAST(COALESCE(MPL.TIENEOM,0) AS BIT)
				, DATARTICULACIONES  = HCA.ARTICULACIONES
                ,ARTICULACIONES=CAST(COALESCE(MPL.ARTICULACIONES,0) AS BIT)
                ,TIENEPRUM=CAST(COALESCE(MPL.TIENEPRUM,0) AS BIT)
                ,MPL.PIDESV
                ,MPL.PIDEDXR
                ,MPL.PIDEDX
                ,MPL.HURG
				,HCAPM = (SELECT ORDEN, OBSERVACION FROM HCAPM WITH(NOLOCK) WHERE CONSECUTIVO=HCA.CONSECUTIVO FOR JSON PATH)
                ,IDPLAN = COALESCE (HCA.IDPLAN,CIT.IDPLAN,HADM.IDPLAN)
                ,NOAUTORIZACION = COALESCE(CIT.NOAUTORIZACION, HADM.NOAUTORIZACION,'')
				,ESPECIALIDADMEDDIL = CASE WHEN @ASI_UTILIZAFIRMA_HC <> 'SI' THEN '' ELSE MES.DESCRIPCION END
                ,PLN.DESCPLAN
                ,PLN2.DESCPLAN DESCPLAN_CIT   
                ,FECHA_INGRESO = HADM.FECHA
                ,FECHAINGRESO = CONVERT(VARCHAR,HADM.FECHA,103)
                ,FECHA_ALTA = HADM.FECHAALTAMED
                ,FECHAALTA = CONVERT(VARCHAR,HADM.FECHAALTA,103)+' '+CONVERT(VARCHAR,HADM.FECHAALTA,108)
                ,COALESCE(HADM.HABCAMA,'') AS HABCAMA
                ,IDXINGRESO = DX5.IDDX
                ,DXINGRESO_CONFIDENCIAL = CAST(DX5.CONFIDENCIAL AS BIT)
                ,DXINGRESO =  DX5.DESCRIPCION
                ,MEDT.NOMBRE  [MEDICOTRATANTE]
                ,MEDING.NOMBRE MEDICOINGRESA
                ,VIADEINGRESO.DESCRIPCION VIAINGRESO
                ,CAUSAEXTERNA.DESCRIPCION CAUSAEXTERNA
                ,CLASE_REGISTRO_MEDICO = (SELECT TOP 1 DESCRIPCION FROM TGEN WHERE TABLA='MED' AND CAMPO='CLASE_REGISTRO' AND CODIGO=MED.CLASE_REGISTRO)
			FROM HCA WITH(NOLOCK)
                INNER JOIN MED WITH(NOLOCK) ON HCA.IDMEDICO = MED.IDMEDICO
                INNER JOIN AFI WITH(NOLOCK) ON AFI.IDAFILIADO=HCA.IDAFILIADO
			    LEFT JOIN MPL WITH(NOLOCK) ON MPL.CLASEPLANTILLA=HCA.CLASEPLANTILLA
                LEFT JOIN CIT WITH(NOLOCK) ON CIT.CONSECUTIVO = COALESCE(HCA.CONSECUTIVOCIT,HCA.NOADMISION,'') AND HCA.PROCEDENCIA NOT IN ('QX')
                LEFT JOIN MED AS MEDESP WITH(NOLOCK) ON MEDESP.IDMEDICO = HCA.IDMEDICOESP
                LEFT JOIN MES WITH(NOLOCK) ON MES.IDEMEDICA = COALESCE(HCA.IDEMEDICA, HCA.MED_ESPEC, MED.IDEMEDICA)
                LEFT JOIN MES AS MESESP WITH(NOLOCK) ON MESESP.IDEMEDICA = COALESCE(HCA.IDEMEDICAESP, MEDESP.IDEMEDICA)
                LEFT JOIN HADM WITH(NOLOCK) ON HADM.NOADMISION = HCA.NOADMISION
			    LEFT JOIN MED MEDT WITH(NOLOCK) ON COALESCE(HADM.IDMEDICOTRA, HADM.IDMEDICOING) = MEDT.IDMEDICO
			    LEFT JOIN MED MEDING WITH(NOLOCK) ON COALESCE(HADM.IDMEDICOING, HADM.IDMEDICOTRA) = MEDING.IDMEDICO
                LEFT JOIN PLN WITH(NOLOCK) ON PLN.IDPLAN = COALESCE(HCA.IDPLAN,HADM.IDPLAN,CIT.IDPLAN)
                LEFT JOIN PLN PLN2 WITH(NOLOCK) ON PLN2.IDPLAN=COALESCE(HCA.IDPLAN,CIT.IDPLAN,HADM.IDPLAN)
			    LEFT JOIN MDX DX5 WITH(NOLOCK) ON DX5.IDDX = HADM.DXINGRESO
                LEFT JOIN TGEN VIADEINGRESO WITH(NOLOCK) ON VIADEINGRESO.TABLA='General' AND VIADEINGRESO.CAMPO='VIADEINGRESO' AND VIADEINGRESO.CODIGO = HADM.VIAINGRESO
			    LEFT JOIN TGEN CAUSAEXTERNA WITH(NOLOCK) ON CAUSAEXTERNA.TABLA='General' AND CAUSAEXTERNA.CAMPO='CAUSAEXTERNA' AND CAUSAEXTERNA.CODIGO = HADM.CAUSAEXTERNA
			WHERE HCA.CONSECUTIVO =@CONSECUTIVO
		END
		BEGIN -- 3.- Signos Vitales
			SELECT 'OK' OK
			/*En consultar pantalla no se usa este select 12 y el 3 tampoco, se usa ok como comodin

            IF EXISTS(SELECT 1 FROM HCA WHERE HCA.CONSECUTIVO = @CONSECUTIVO AND HCA.CLASEPLANTILLA IN ('MP_RIAS','PI_RIAS','IN_RIAS','ADO_RIAS','JU_RIAS','ADU_RIAS','VE_RIAS'))
            BEGIN
                SELECT @IDAFILIADO = IDAFILIADO FROM HCA WHERE CONSECUTIVO = @CONSECUTIVO
                SELECT OBSERVACION = DBO.FNK_LIMPIATEXTO(HCASVT.OBSERVACION,'/^[\w\W ]+$/')
                    ,JSON_VALORES = (
