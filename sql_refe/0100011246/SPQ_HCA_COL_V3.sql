											    AND AFIRIAEXA.CLASERIA = CNFRIAEXA.CLASERIA
		    WHERE  AFIRIAEXA.IDAFILIADO = @IDAFILIADO
		    AND    AFIRIAEXA.CLASERIA   = @CLASEPLANTILLA
		END
		BEGIN -- 24. HCPRUM
