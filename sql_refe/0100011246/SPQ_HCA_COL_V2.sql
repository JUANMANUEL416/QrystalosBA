CREATE OR ALTER PROCEDURE DBO.SPQ_HCA_COL_V2
	@JSON NVARCHAR(MAX)
WITH ENCRYPTION
AS
DECLARE @DXS AS TABLE (
	CONSECUTIVO VARCHAR(20)		,IDAFILIADO VARCHAR(20)		,NOADMISION VARCHAR(20)
	,PROCEDENCIA VARCHAR(20)	,FECHA DATETIME				,TIPO VARCHAR(20)
	,DX VARCHAR(20)				,TIPODX VARCHAR(20)			,ESTADO VARCHAR(20)
	,DESCRIPCION VARCHAR(MAX)	,FECHASINTOMAS DATETIME		,FECHACONFIRMACION DATETIME
	,CONFIDENCIAL BIT DEFAULT 0
	)
DECLARE @PARAMETROS     NVARCHAR(MAX)	,@FINI			    DATE
		,@FFIN			DATE			,@MODELO            VARCHAR(100)
		,@METODO		VARCHAR(100)	,@QUERY             NVARCHAR(MAX)
		,@GRUPO		    VARCHAR(8)		,@SEDE              VARCHAR(5)
		,@USUARIO		VARCHAR(20)     ,@FILTRO		    VARCHAR(250)
	    ,@ORDEN         VARCHAR(100)	,@PAGINA            INT
	    ,@FILASXPAG     INT			    ,@DEFCOLUMNS        BIT
	    ,@NOADMISION    VARCHAR(16)	    ,@CONSECUTIVO       VARCHAR(13)
	    ,@UNICO         INT			    ,@DESCRIPCION       VARCHAR(MAX)
	    ,@PARAM         NVARCHAR(500)	,@FECHAHCA          DATETIME
	    ,@CNSWEB        VARCHAR(100)	,@CLASEPLANTILLA    VARCHAR(8)
	    ,@IDAFILIADO    VARCHAR(20)	    ,@IDMEDICO          VARCHAR(20)
	    ,@SYS_COMPUTERNAM VARCHAR(200)	,@CONSECUTIVOS      VARCHAR(8000)
	    ,@IDMEDICO_AUX     VARCHAR(20)	,@IDMEDICO_ESPECIALISTA VARCHAR(20)
	    ,@MESES_HISTORICO  INT			,@CONSECUTIVOHCA    VARCHAR(20)
		,@ENEPICRISIS	   SMALLINT = 0	,@SYS_COMPUTERNAME  VARCHAR(1000)
		,@CORREOS           VARCHAR(MAX),@CORREGIMIENTO     VARCHAR(20)
		,@DPR_RAZONSOCIAL VARCHAR(1000) ,@DPR_NIT           VARCHAR(20)
		,@DPR_DV	        VARCHAR(1)	,@DPR		        VARCHAR(10) = dbo.FNK_VALORVARIABLE('DATOSPROPIETARIO')
		,@EXISTS_COLUMN_CNSHCA_CITACONTROL BIT = IIF(COL_LENGTH('CIT','CNSHCA_CITACONTROL') IS NOT NULL,1,0)
		,@DIAS_CADUCIDAD_OM INT
		,@ASI_UTILIZAFIRMA_HC VARCHAR(2) = DBO.FNK_VALORVARIABLE('ASI_UTILIZAFIRMA_HC')
		,@SEXO              VARCHAR(15)
		,@CODIGO_MED VARCHAR(20) = DBO.FNK_VALORVARIABLE('OMCODMEDICAMENTOS')
		,@CLASE_PLANTILLA_EVOLUCION                         VARCHAR(20)= dbo.FNK_VALORVARIABLE('HCPLANTILLARED')
		,@CONSECUTIVO_HCADX VARCHAR(20)	,@ESPROGRAMAS       BIT
		,@IDFIRMA	UNIQUEIDENTIFIER	,@FIRMA		        VARBINARY(MAX)
		,@FIRMABLOB	VARCHAR(MAX)		,@IDAUT		        VARCHAR(20)
		,@ID_QCORE10 INT				,@DPR_DIRECCION     VARCHAR(MAX)
		,@NIT_DPR VARCHAR(20)			,@IDPLAN	        VARCHAR(20)
		,@FECHA_DILIGENCIA DATETIME
		,@_CNSFUAT VARCHAR(7), @_CNSFAT VARCHAR(7)
		DECLARE @DBNAME_DOCU VARCHAR(200)
		DECLARE @USA_DOCU_BD VARCHAR(2)
		DECLARE @HTAD_CRONICO VARCHAR(10)
		DECLARE @SQL NVARCHAR(MAX);
		DECLARE @AGEN_OM_XESPT VARCHAR(20), @PIDE_CITACONTROL VARCHAR(20), @DEMO VARCHAR(20)
		DECLARE @FILTRA_AUD_OM BIT = CASE WHEN OBJECT_ID('DBO.HCATD_AUD','U') IS NOT NULL THEN 1 ELSE 0 END
BEGIN
	SET DATEFORMAT dmy
	SET NOCOUNT ON
	SET DATEFIRST 1;

	SELECT *
	INTO #JSON
	FROM OPENJSON(@json) WITH (
			MODELO  VARCHAR(100) '$.MODELO'
			,METODO  VARCHAR(100) '$.METODO'
			,CNSWEB  VARCHAR(100) '$.CNSWEB'
			,USUARIO VARCHAR(100) '$.USUARIO'
			,DEFCOLUMNS BIT '$.DEFCOLUMNS'
			,PARAMETROS NVARCHAR(MAX) AS JSON
	)

	SELECT @MODELO  = MODELO
		,@METODO     = METODO
		,@PARAMETROS = PARAMETROS
		,@DEFCOLUMNS = DEFCOLUMNS
		,@USUARIO    = USUARIO
		,@CNSWEB     = CNSWEB
	FROM #JSON

	-- OPT: Unificar 2 SELECTs en 1
	SELECT @GRUPO = DBO.FNK_DESCIFRAR(GRUPO), @IDMEDICO = IDMEDICO, @SYS_COMPUTERNAME = SYS_COMPUTERNAME
	FROM USUSU WITH(NOLOCK) WHERE USUARIO = @USUARIO

	SELECT @SEDE = IDSEDE FROM UBEQ WITH(NOLOCK) WHERE SYS_ComputerName = @SYS_COMPUTERNAME

	SELECT @DPR_RAZONSOCIAL = RAZONSOCIAL, @DPR_NIT = NIT, @DPR_DV=  DV
		,@DPR_DIRECCION = TER.DIRECCION
	FROM TER WITH(NOLOCK)
	WHERE IDTERCERO = dbo.FNK_VALORVARIABLE('IDTERCEROINSTALADO')

	IF @METODO = 'CONSULTAR'
	BEGIN
		SELECT @DBNAME_DOCU = DBO.FNK_VALORVARIABLE('NAME_DOCU_DB')
			,@USA_DOCU_BD = DBO.FNK_VALORVARIABLE ('USA_DOCU_BD')
			,@AGEN_OM_XESPT = DBO.FNK_VALORVARIABLE ('AGEN_OM_XESPT')
			,@PIDE_CITACONTROL = DBO.FNK_VALORVARIABLE ('PIDE_CITACONTROL')
			,@HTAD_CRONICO = DBO.FNK_VALORVARIABLE ('HTAD_CRONICO')
			,@DEMO = null--IIF(DBO.FNK_VALORVARIABLE ('BDATA_PRODUCCION')<>DB_NAME(),'DEMO',NULL)

		SELECT @FILTRO = FILTRO
			,@PAGINA = PAGINA
			,@FILASXPAG = FILASXPAG
			,@ORDEN = ORDEN
			,@CONSECUTIVO = CONSECUTIVO
			,@CONSECUTIVOS = CONSECUTIVOS
			,@ENEPICRISIS = ENEPICRISIS
		FROM OPENJSON(@PARAMETROS) WITH (
				FILTRO VARCHAR(250) '$.FILTRO'
				,PAGINA INT '$.PAGINA'
				,FILASXPAG INT '$.FILASXPAG'
				,ORDEN VARCHAR(100) '$.ORDEN'
				,CONSECUTIVO VARCHAR(13) '$.CONSECUTIVO'
				,ENEPICRISIS SMALLINT '$.ENEPICRISIS'
				,CONSECUTIVOS VARCHAR(8000) '$.CONSECUTIVOS'
		)

		DECLARE @CONSECUTIVOS_TABLA AS TABLE(ITEM INT IDENTITY(1,1) PRIMARY KEY,CONSECUTIVO VARCHAR(20))


		INSERT INTO @CONSECUTIVOS_TABLA (CONSECUTIVO)
		SELECT @CONSECUTIVO UNION ALL
		SELECT WORD FROM DBO.FNK_EXPLODE(@CONSECUTIVOS, ',') WHERE COALESCE(WORD,'')<>''
		
		DECLARE @ESCE BIT=IIF(NOT EXISTS(SELECT 1 FROM HCA WHERE HCA.CONSECUTIVO IN (SELECT CONSECUTIVO FROM @CONSECUTIVOS_TABLA) AND HCA.PROCEDENCIA IN('QX','AUDIT')),1,0)

		SELECT @NOADMISION = H.NOADMISION
			,@FECHAHCA = H.FECHA
			,@CLASEPLANTILLA = H.CLASEPLANTILLA
			,@IDAFILIADO = H.IDAFILIADO
			,@IDPLAN = COALESCE(H.IDPLAN, CIT.IDPLAN, HADM.IDPLAN)
			,@NIT_DPR = TER_PROV.NIT
		FROM HCA H WITH(NOLOCK)
			LEFT JOIN CIT WITH(NOLOCK) ON CIT.CONSECUTIVO = COALESCE(H.CONSECUTIVOCIT,H.NOADMISION,'') AND H.PROCEDENCIA NOT IN ('QX')
			LEFT JOIN HADM WITH(NOLOCK) ON HADM.NOADMISION = H.NOADMISION
			CROSS APPLY (SELECT NIT FROM TER WITH(NOLOCK) WHERE IDTERCERO = DBO.FNK_VALORVARIABLE('IDTERCEROINSTALADO')) TER_PROV
		WHERE H.CONSECUTIVO = (
			SELECT TOP 1 CN.CONSECUTIVO
			FROM HCA WITH(NOLOCK) INNER JOIN @CONSECUTIVOS_TABLA CN ON HCA.CONSECUTIVO = CN.CONSECUTIVO
			WHERE (@ENEPICRISIS IS NULL OR HCA.ENEPICRISIS = @ENEPICRISIS)
			ORDER BY HCA.FECHA DESC
		)

		SELECT @_CNSFUAT = RIGHT('0000000'+CAST(
			IIF(@CLASEPLANTILLA='FUAT', (SELECT COUNT(1) FROM HCA X WITH(NOLOCK) WHERE COALESCE(ANULADA,0)=0 AND X.CLASEPLANTILLA='FUAT' AND X.FECHA<@FECHAHCA)+1, 0) AS VARCHAR), 7)
		,@_CNSFAT = RIGHT('0000000'+CAST(
			IIF(@CLASEPLANTILLA='FAT', (SELECT COUNT(1) FROM HCA X WITH(NOLOCK) WHERE COALESCE(ANULADA,0)=0 AND X.CLASEPLANTILLA='FAT' AND X.FECHA<@FECHAHCA)+1, 0) AS VARCHAR), 7)

		DECLARE @PERMISO_IMP_MPL BIT=0
		IF EXISTS(SELECT 1 FROM USGRUH WITH(NOLOCK) WHERE GRUPO=@GRUPO AND IDPROCEDIMIENTO='HCA_WEB' AND IDCONTROL='print_every' AND PERMISO=1)
			SET @PERMISO_IMP_MPL=1

		-- 1.- OK de la consulta
		SELECT 'OK' OK ,@CONSECUTIVO CONSECUTIVO

		BEGIN -- 2.- Datos de la Historia Clinica
			BEGIN TRY
				SELECT @DIAS_CADUCIDAD_OM = DBO.FNK_VALORVARIABLE('DIAS_CADUCIDAD_OM')
			END TRY
			BEGIN CATCH
				SELECT @DIAS_CADUCIDAD_OM = 0
			END CATCH

			IF @DIAS_CADUCIDAD_OM IS NULL
				SELECT @DIAS_CADUCIDAD_OM = 0
			
			SELECT
             /**** HCA ****/
				 HCA.CONSECUTIVO
				,HCA.FECHA
				,HCA.CNSWEB
				,AHORA = DBO.FNK_GETDATE()
				,HCA.CLASE
				,HCA.PROCEDENCIA
				,HCA.IDAFILIADO
				,HCA.IDMEDICO
				,HCA.TIPODX
				,HCA.IDDX
				,MPL.MTACTIVO
				,HCA.DX1
				,HCA.DX2
				,HCA.DX3
				,HCA.DX4
				,HCA.CLASEPLANTILLA
				,HCA.NOADMISION
				,HCA.REVISAESP
				,HCA.REVISADO
				,NOTA_ACLARA
				,HCA.IDMEDICOESP
				,ANULADA = COALESCE(HCA.ANULADA,0)
				,HCA.CHECK1 ,HCA.CHECK2 ,HCA.CHECK3
				,IDAREA = COALESCE(X.IDAREA,HCA.IDAREA)
				,OCULPAPROGRAMAS = IIF(HCA.FECHA > '20210824', 'SI','NO')
				,DEMO = @DEMO


			/**** MED ****/
				,NOMBREMEDICODIL = CASE WHEN @ASI_UTILIZAFIRMA_HC <> 'SI' THEN '' ELSE MED.NOMBRE END
				,CMPMEDICODIL = CASE WHEN @ASI_UTILIZAFIRMA_HC <> 'SI' THEN '' ELSE MED.NO_REGISTRO END
				,RMMEDICODIL = MED.BEEPER
				,RNE = MED.BEEPER
				,MED.FIRMA_ANCHO
				,MED.FIRMA_ALTO
				,MED.FIRMA_X
				,MED.FIRMA_Y
				,MED.FIRMA_IMPRIME_DATOS_MED

			/**** AFI ****/
                ,AFI.DOCIDAFILIADO
				,EDAD = (SELECT  ANO, MES, DIA FROM dbo.FNK_EDAD_ANO_MES_DIA(AFI.FNACIMIENTO, HCA.FECHA) FOR JSON PATH)

            /**** CIT/HADM ****/
				,IDPLAN = COALESCE(HADM.IDPLAN,CIT.IDPLAN,HCA.IDPLAN)
				,MPE.DESCESPECIAL AS PROGRAMA_ESPECIAL
				,HABITANTE_CALLE = CAST(IIF((SELECT COUNT(1) FROM TGEN WITH(NOLOCK) WHERE TABLA='PLN' AND CAMPO='HABITANTES_CALLE' AND CODIGO = COALESCE(HADM.IDPLAN,CIT.IDPLAN,HCA.IDPLAN))>0,1,0) AS BIT)
				,URG_NOMBRE = COALESCE(NULLIF(CIT.NOMBREACOMPA, ''), NULLIF(HADM.URG_NOMBRE,''), AFI.URG_NOMBRE)
				,URG_VINCULO = COALESCE(NULLIF(CIT.PARENTESCORESPO,''), NULLIF(HADM.URG_VINCULO,''), AFI.URG_VINCULO)
				,URG_TELE = COALESCE(NULLIF(CIT.TELEFONOACOMPA,''), NULLIF(HADM.URG_TELE,''), AFI.URG_TELE)
				,URG_DIR = HADM.URG_DIR
				,NOMBRERESPO = COALESCE(CIT.NOMBRERESPO, HADM.NOMBRERESPO)
				,PARENTESCORESPO = COALESCE(CIT.PARENTESCORESPO, HADM.PARENTESCORESPO)
				,TELEFONORESPO = COALESCE(CIT.TELEFONORESPO, HADM.TELEFONORESPO)
				,IDPLAN_CIT = COALESCE(HCA.IDPLAN,CIT.IDPLAN)
				,CITAS_CONTROL_DIPONIBLES = IIF(@AGEN_OM_XESPT='SI' AND @PIDE_CITACONTROL='SI',0,COALESCE(
					(
						SELECT COUNT(1)
						FROM CIT WITH(NOLOCK)
						WHERE CIT.IDMEDICO = @IDMEDICO
						AND CAST(CIT.FECHA AS DATE) > CAST(HCA.FECHA AS DATE)
						AND COALESCE(CIT.IDAFILIADO, '') = ''
						AND CIT.TIPOCITA IN ('Control', 'Cita', 'Cit', 'Mode')
						AND COALESCE(CIT.BLOQUEADO,0)=0
						AND NOT EXISTS(
							SELECT 1
							FROM MAGPRP WITH(NOLOCK)
							WHERE MAGPRP.IDMEDICO = CIT.IDMEDICO
							AND CIT.FECHA BETWEEN MAGPRP.FECHAINICIAL AND MAGPRP.FECHAFINAL
						)
					),0))
				,IMP_LOGO_SEC = CAST(IIF(COALESCE(HCA.CONSECUTIVOCIT, '')='', 0, IIF(CIT.IDPESPECIAL = '000',1,0)) AS BIT)
				,NOAUTORIZACION = COALESCE(CIT.NOAUTORIZACION, HADM.NOAUTORIZACION,'')
				,FECHA_INGRESO = HADM.FECHA
				,FECHAINGRESO = CONVERT(VARCHAR,HADM.FECHA,103)
				,FECHA_ALTA = HADM.FECHAALTAMED
				,FECHAALTA = CONVERT(VARCHAR,HADM.FECHAALTA,103)+' '+CONVERT(VARCHAR,HADM.FECHAALTA,108)
				,COALESCE(HADM.HABCAMA,X.HABCAMA,'') AS HABCAMA
				,IDXINGRESO = DX5.IDDX
				,DXINGRESO_CONFIDENCIAL = CAST(DX5.CONFIDENCIAL AS BIT)
				,DXINGRESO =  DX5.DESCRIPCION
				,EMBARAZADA = COALESCE(HADM.EMBARAZADA, CIT.EMBARAZADA)

            /**** MEDESP ****/
				,FIRMAMEDICOESP = FirmaEsp.DICOM
				,MEDESP.NOMBRE ESPECIALISTA_NOMBRE
				,MEDESP.NO_REGISTRO ESPECIALISTA_NO_REGISTRO

            /**** MESESP ****/
				,MESESP.DESCRIPCION ESPECIALISTA_ESPECIALIDAD

            /**** MEDT ****/
				,MEDT.NOMBRE  [MEDICOTRATANTE]

            /**** MEDING ****/
				, MEDING.NOMBRE MEDICOINGRESA

            /**** TER ****/
				,TER.IDTERCERO
				,TER.RAZONSOCIAL CONTRATANTE

            /**** MPL ****/
				,MPL.DESCPLANTILLA
				,IMPRIMEOM = COALESCE(MPL.IMPRIMEOM,0)
				,MPL.PIDEDX ,MPL.PIDEDXR   ,MPL.PIDESV
                ,MPL.TIENEOM ,MPL.TIENEPRUM
				,ENEPICRISIS = COALESCE(HCA.ENEPICRISIS, MPL.ENEPICRISIS, 0)
				,OM_ENEPICRISIS = CAST(COALESCE(OM_ENEPICRISIS, 0) AS BIT)
				,MPL.HURG
				,MPL.M2465

				,COALESCE(MPL.FORMATO_ESPECIAL,0) AS FORMATO_ESPECIAL
				,REVISA_FAMILIOGRAMA =
				  CASE
					WHEN DBO.FNK_VALORVARIABLE('REVISAR_FAMILIOGRAMA') = 'SI'
					  THEN CAST(ISNULL(MPL.REVISA_FAMILIOGRAMA, 0) AS bit)
					ELSE CAST(0 AS bit)
				  END
				,IMPMPL = CAST(IIF(@PERMISO_IMP_MPL=1,1,COALESCE(MPLXUSU.IMPMPL, 0)) AS BIT)

            /**** MES ****/
				,ESPECIALIDADMEDDIL = CASE WHEN @ASI_UTILIZAFIRMA_HC <> 'SI' THEN '' ELSE MES.DESCRIPCION END

            /**** MDX ****/
				,MDX.DESCRIPCION DXPRINCIPAL
				,DX1.DESCRIPCION DIAG1
				,DX2.DESCRIPCION DIAG2
				,DX3.DESCRIPCION DIAG3
				,DX4.DESCRIPCION DIAG4

            /**** TGEN ****/
				,VIADEINGRESO.DESCRIPCION VIAINGRESO
				,CAUSAEXTERNA.DESCRIPCION CAUSAEXTERNA
				,CLASE_REGISTRO_MEDICO = (SELECT TOP 1 DESCRIPCION FROM TGEN WITH(NOLOCK) WHERE TABLA='MED' AND CAMPO='CLASE_REGISTRO' AND CODIGO=MED.CLASE_REGISTRO)

            /**** PLN ****/
				,PLN.DESCPLAN
				,PLN2.DESCPLAN DESCPLAN_CIT

            /**** SER ****/
				,SER.DESCSERVICIO

            /**** CEN ****/
				,COALESCE(CIT.IDSEDE, HADM.IDSEDE, CEN.IDSEDE, LEFT(HCA.CONSECUTIVO,2), @SEDE) IDSEDE

            /**** SED ****/
				,IIF(@DPR='DPR',@DPR_RAZONSOCIAL,SED.DESCRIPCION) DESCSEDE
				,IIF(@DPR='DPR',@DPR_NIT,SED.NIT) NIT
				,IIF(@DPR='DPR',@DPR_DV,SED.DV) DV
				,IIF(@DPR='DPR',NULL,COALESCE(SED.CODHABILITA,SED.IDSGSSS)) CODHABILITA
				,DIRECCION = IIF(@DPR='DPR',@DPR_DIRECCION,CONCAT(SED.DIRECCION,' - ',COALESCE(CIU_SED.NOMBRE, '')))

            /**** DICOM ****/
				,FIRMA = CASE WHEN @ASI_UTILIZAFIRMA_HC <> 'SI' THEN NULL ELSE FirmaMed.DICOM END

            /**** OTROS ****/
				,UTILIZAFIRMA = IIF(@ASI_UTILIZAFIRMA_HC <> 'SI', 0, 1)
                ,DATARTICULACIONES  = HCA.ARTICULACIONES
                ,ARTICULACIONES     = MPL.ARTICULACIONES
			-- OPT: Usar variables precalculadas en lugar de subconsultas por fila
				,CONSECUTIVOFUAT = @_CNSFUAT
				,CONSECUTIVOFAT = @_CNSFAT
				,HCO = HcoData.HCO_JSON
				,FECHA_CADUCIDAD = CASE WHEN @DIAS_CADUCIDAD_OM>0 THEN DATEADD(DAY, @DIAS_CADUCIDAD_OM, HCA.FECHA) ELSE NULL END
				,TIPO_ATECION = CASE WHEN HCA.PROCEDENCIA = 'QX' THEN 'Hospitalizacion' ELSE COALESCE(CIT.ATENCION, 'Ambulatoria') END
				,CNSCIT_CITACONTROL = IIF(COALESCE(CIT.CNSHCA_CITACONTROL,'')='', NULL, IIF(@EXISTS_COLUMN_CNSHCA_CITACONTROL=0, NULL, (SELECT TOP 1 CONSECUTIVO FROM CIT WITH(NOLOCK) WHERE CNSHCA_CITACONTROL = HCA.CONSECUTIVO)))
				,FECHA_CITACONTROL = IIF(COALESCE(CIT.CNSHCA_CITACONTROL,'')='', NULL, IIF(@EXISTS_COLUMN_CNSHCA_CITACONTROL=0, NULL, (SELECT TOP 1 FECHA FROM CIT WITH(NOLOCK) WHERE CNSHCA_CITACONTROL = HCA.CONSECUTIVO)))
				,HCAPM = HcapmData.HCAPM_JSON
				,FME = (
					SELECT FME.NOCONSECUTIVO
						,FME.NOADMISION
						,FME.FECHA
						,FME.IDDX
						,MDX.DESCRIPCION DESCDX
						,FME.IDMEDICO
						,MED.NOMBRE NOMBREMED
						,COALESCE(FME.PEDIDOINV, 0) PEDIDOINV
						,FME.DX1
						,MDX1.DESCRIPCION DESCDX1
						,FME.DX2
						,MDX2.DESCRIPCION DESCDX2
						,FME.CLASEORDEN
						,FME.IDPESPECIAL
						,MPE.DESCESPECIAL
						,COALESCE(FME.CNSMOV, '') CNSMOV
						,FME.PROCEDENCIA
						,COALESCE(FME.ENCARGOS, 0) ENCARGOS
						,FME.NOPRESTACION
						,FME.CNSHCA
						,FME.CNSWEB
						,FME.TIPOFORMULA
						,FME.OPTI
						,FMED = (
							SELECT FMED.NOITEM
								,FMED.IDSERVICIO
								,FMED.CANTIDAD
								,FMED.COMENTARIOS
								,FMED.POSCANTDIA
								,FMED.POSDIAS
								,FMED.POSFRECUENCIA
								,FMED.POSOLOGIA
								,FMED.FRACCION
								,FMED.MEXTERNO
								,FMED.DESCRIPCIONEXT
								,CAST(COALESCE(FMED.MPOSOLOGIA, 0) AS BIT) MPOSOLOGIA
								,SER.DESCSERVICIO
								,ODESFERA
								,ODCILINDRO
								,ODEJE
								,ODADICION
								,ODALT
								,ODAVL
								,ODTLENTE
								,OIESFERA
								,OICILINDRO
								,OIEJE
								,OIADICION
								,OIALT
								,OIAVL
								,OITLENTE
								,FUSO
								,ODDNP
								,OIDNP
								,DP
							FROM FMED WITH(NOLOCK)
							LEFT JOIN SER WITH(NOLOCK) ON FMED.IDSERVICIO = SER.IDSERVICIO
							WHERE FMED.NOCONSECUTIVO = FME.NOCONSECUTIVO
							FOR JSON PATH
							)
						,IDFIRMA = (
							SELECT DICOM
							FROM ARCHIVOS WITH(NOLOCK)
							WHERE ID = MED.IDFIRMA
							)
						,MED.NO_REGISTRO
						,FME.FANULA
						,FME.USUANULA
						,ANULADA = CAST(COALESCE(FME.ANULADA, 0) AS BIT)
						,MES.DESCRIPCION AS ESPECIALIDADMED
						,DIRECCION = IIF(@DPR='DPR',@DPR_DIRECCION,CONCAT(SED.DIRECCION,' - ',COALESCE(CIU_SED.NOMBRE, '')))
					FROM [dbo].[FME] WITH(NOLOCK)
					INNER JOIN MDX WITH(NOLOCK) ON FME.IDDX = MDX.IDDX
					LEFT JOIN MED WITH(NOLOCK) ON FME.IDMEDICO = MED.IDMEDICO
					LEFT JOIN MDX MDX1 WITH(NOLOCK) ON FME.DX1 = MDX1.IDDX
					LEFT JOIN MDX MDX2 WITH(NOLOCK) ON FME.DX2 = MDX2.IDDX
					LEFT JOIN MPE WITH(NOLOCK) ON FME.IDPESPECIAL = MPE.IDPESPECIAL
					LEFT JOIN MES WITH(NOLOCK) ON MES.IDEMEDICA = MED.IDEMEDICA
					LEFT JOIN SED WITH(NOLOCK) ON SED.IDSEDE = COALESCE(CIT.IDSEDE, HADM.IDSEDE, CEN.IDSEDE, LEFT(HCA.CONSECUTIVO,2), @SEDE)
					LEFT JOIN CIU CIU_SED WITH(NOLOCK) ON CIU_SED.CIUDAD=SED.CIUDAD
					WHERE FME.CNSHCA = HCA.CONSECUTIVO
					FOR JSON PATH)
				,PIE_PAGINA = IIF(@NIT_DPR = '20100054184',
					CASE
						WHEN PPT.PPT_TIPOADM = DBO.FNK_VALORVARIABLE('HTAD_HOSPITA') THEN
