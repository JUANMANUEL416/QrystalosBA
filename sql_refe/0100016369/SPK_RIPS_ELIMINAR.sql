IF EXISTS(SELECT NAME FROM SYSOBJECTS WHERE NAME = 'SPK_RIPS_ELIMINAR' AND XTYPE='P')
BEGIN
   DROP PROCEDURE SPK_RIPS_ELIMINAR
END

GO
CREATE PROCEDURE DBO.SPK_RIPS_ELIMINAR
	@ENVIO     VARCHAR(6),
	@IDTERCERO VARCHAR(20)
WITH ENCRYPTION
AS
DECLARE @CNSCXC VARCHAR(20)
DECLARE @CAPITADO SMALLINT
DECLARE @ESTADO VARCHAR(2)
BEGIN
	IF DBO.FNK_VALORVARIABLE('IXCOUNTRY')<>'PERU'
	BEGIN
		DELETE RRIPS_AF WHERE ENVIO=@ENVIO AND IDTERCERO=@IDTERCERO
		DELETE RRIPS_AD WHERE ENVIO=@ENVIO AND IDTERCERO=@IDTERCERO
		DELETE RRIPS_US WHERE ENVIO=@ENVIO AND IDTERCERO=@IDTERCERO
		DELETE RRIPS_CT WHERE ENVIO=@ENVIO -- AND IDTERCERO=@IDTERCERO
		DELETE RRIPS_AC WHERE ENVIO=@ENVIO AND IDTERCERO=@IDTERCERO
		DELETE RRIPS_AP WHERE ENVIO=@ENVIO AND IDTERCERO=@IDTERCERO
		DELETE RRIPS_AH WHERE ENVIO=@ENVIO AND IDTERCERO=@IDTERCERO
		DELETE RRIPS_AU WHERE ENVIO=@ENVIO AND IDTERCERO=@IDTERCERO
		DELETE RRIPS_AM WHERE ENVIO=@ENVIO AND IDTERCERO=@IDTERCERO
		DELETE RRIPS_AN WHERE ENVIO=@ENVIO AND IDTERCERO=@IDTERCERO
		DELETE RRIPS_AT WHERE ENVIO=@ENVIO AND IDTERCERO=@IDTERCERO
	END
	ELSE
	BEGIN
		DELETE TRAMA_DATE WHERE IDTRAMA=@ENVIO
		DELETE TRAMA_DFAC WHERE IDTRAMA=@ENVIO
		DELETE TRAMA_DSER WHERE IDTRAMA=@ENVIO
		DELETE TRAMA_DFAR WHERE IDTRAMA=@ENVIO
	END
	SELECT @CNSCXC = CNSCXC, @CAPITADO=COALESCE(CAPITADO,0), @ESTADO=ESTADO FROM RIPS WHERE ENVIO = @ENVIO AND IDTERCERO=@IDTERCERO
   
	--DELETE  FCXCEVAL  WHERE CNSFCXC  =  @CNSCXC
	--DELETE  FCXCEVALG  WHERE CNSFCXC =  @CNSCXC
 
	UPDATE FTRD SET FTRD.CODEVAL = NULL
	FROM   FTRD INNER JOIN RIPSD ON FTRD.N_FACTURA = RIPSD.N_FACTURA
	WHERE  RIPSD.ENVIO = @ENVIO AND RIPSD.IDTERCERO=@IDTERCERO
   
	IF DBO.FNK_valorvariable('RIPSDESHACERTODO') = 'SI' --AND (SELECT ESTADO FROM RIPS WHERE ENVIO=@ENVIO AND IDTERCERO=@IDTERCERO)<>'01'
	BEGIN
		IF @CAPITADO=1
			DELETE RIPSD WHERE ENVIO=@ENVIO AND IDTERCERO=@IDTERCERO
		ELSE
		BEGIN
			DELETE RIPSD WHERE ENVIO=@ENVIO AND IDTERCERO=@IDTERCERO AND @ESTADO<>'01'			
		END
	END
	UPDATE RIPS SET ENVIADO = 'N', ESTADO = '01' WHERE ENVIO=@ENVIO 
END


