	IF @METODO = 'PROCESAR_TODOS_HPRED'
	BEGIN
		SELECT @AMBITO =  AMBITO
		FROM OPENJSON (@PARAMETROS)
		WITH		 (
					AMBITO			VARCHAR(20)  '$.AMBITO'
					)

		IF NOT EXISTS(SELECT * FROM HPRED INNER JOIN SER ON HPRED.IDSERVICIO = SER.IDSERVICIO WHERE MARCA = 1 AND USUARIOMARCA = @USUARIO AND COALESCE(ENLAB,0) = 0 AND SER.AMBITO = @AMBITO )
         BEGIN
            INSERT INTO @TBLERRORES(ERROR) SELECT 'No hay Ordenes de Apoyo y Diagnostico marcadas con su usuario.'
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
         END

		SELECT ROW_NUMBER()OVER(ORDER BY  HPRED.NOPRESTACION  DESC) FILA, HPRED.NOPRESTACION, HPRED.NOITEM, HPRED.MARCA, HPRED.USUARIOMARCA INTO #TOTAL 
		FROM    HPRED 
			INNER JOIN SER ON HPRED.IDSERVICIO = SER.IDSERVICIO
			INNER JOIN HPRE ON HPRE.NOPRESTACION=HPRED.NOPRESTACION
			INNER JOIN HADM ON HPRE.NOADMISION=HADM.NOADMISION					  
		WHERE   HPRED.APOYODG_AMBITO  =  @AMBITO 
		AND     HPRED.MARCA = 1
		AND     HPRED.USUARIOMARCA = @USUARIO
		AND     HPRED.ENLAB <> 1 /* AQUI CONTROLO LO DE QUE YA TRAJE ALGUNO */
		AND     COALESCE(HPRED.ENCARGOS,0) <> (CASE @ADX_SOLO_ORDEN WHEN 'SI' THEN 0 ELSE 1 END)
		AND     ISNULL(HPRED.NOCOBRABLE,0)=0
		AND     ISNULL(HPRED.ANULADO,0)=0
		AND     COALESCE(HADM.CERRADA,0) <> 1

		BEGIN TRY 

			DECLARE CUR_HPRED CURSOR FOR
			  SELECT   HPRED.NOPRESTACION,HPRED.NOITEM,HPRED.IDSERVICIO
			  FROM    HPRED 
					INNER JOIN SER ON HPRED.IDSERVICIO = SER.IDSERVICIO
					INNER JOIN HPRE ON HPRE.NOPRESTACION=HPRED.NOPRESTACION
					INNER JOIN HADM ON HPRE.NOADMISION=HADM.NOADMISION					  
				WHERE   HPRED.APOYODG_AMBITO  =  @AMBITO 
				AND     HPRED.MARCA = 1
				AND     HPRED.USUARIOMARCA = @USUARIO
				AND     HPRED.ENLAB <> 1 /* AQUI CONTROLO LO DE QUE YA TRAJE ALGUNO */
				AND     COALESCE(HPRED.ENCARGOS,0) <> (CASE @ADX_SOLO_ORDEN WHEN 'SI' THEN 0 ELSE 1 END)
				AND     ISNULL(HPRED.NOCOBRABLE,0)=0
				AND     ISNULL(HPRED.ANULADO,0)=0
				AND     COALESCE(HADM.CERRADA,0) <> 1
   
			  OPEN CUR_HPRED
   
			  FETCH NEXT FROM CUR_HPRED
			  INTO  @NOPRESTACION,@NOITEM,@IDSERVICIO
   
			  WHILE @@FETCH_STATUS = 0
			  BEGIN
				 --EXEC SPK_TRAE_UN_INGRESOS @NOPRESTACION, @NOITEM, '01','01',@USUARIO,'A',@AMBITO,@IDSERVICIO
				 EXEC SPK_TRAE_A_INGRESOS @NOPRESTACION, @NOITEM, '01','01',@USUARIO,'A',@AMBITO
				 
				 UPDATE HPRED SET MARCA=0, USUARIOMARCA=NULL WHERE NOPRESTACION=@NOPRESTACION AND NOITEM=@NOITEM

      			 FETCH NEXT FROM CUR_HPRED
				 INTO  @NOPRESTACION,@NOITEM,@IDSERVICIO      
			  END   
			  CLOSE CUR_HPRED
			  DEALLOCATE CUR_HPRED

		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF EXISTS(SELECT 1 FROM @TBLERRORES)
		BEGIN
			SELECT 'KO' AS OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		SELECT 'OK' AS OK, CONCAT( (SELECT COUNT(*) FROM #TOTAL),' Registros.') FILAS_AFECTADAS
		RETURN
	END
