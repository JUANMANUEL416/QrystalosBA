	BEGIN
		SELECT @PRESTACIONES =  PRESTACIONES, @PROCESO =  PROCESO, @CANTIDAD = CANTIDAD
	   FROM OPENJSON (@PARAMETROS)
	   WITH		 (
		PRESTACIONES		NVARCHAR(MAX) AS JSON
		,PROCESO			INT  '$.PROCESO'
		,CANTIDAD			INT  '$.CANTIDAD'
		)
		SELECT ROW_NUMBER()OVER(ORDER BY  NOPRESTACION  DESC) FILA, * INTO #TB_HPRED
		FROM OPENJSON (@PRESTACIONES)
		WITH (
			NOPRESTACION		VARCHAR(20)  '$.NOPRESTACION'
			,NOITEM				INT  '$.NOITEM'
		)
		SELECT @VALIDATE = 0
		SELECT TOP 1 @NOADMISION = HPRE.NOADMISION FROM HPRE, #TB_HPRED WHERE HPRE.NOPRESTACION = #TB_HPRED.NOPRESTACION
		IF (SELECT CERRADA FROM HADM WHERE  NOADMISION = @NOADMISION) = 1
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'No se puede Procesar, tiene Alta de Administrativa'
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END
		/* Valida que registro no cumple con las condiciones para ser tratado  */
		IF EXISTS(SELECT #TB_HPRED.NOPRESTACION, #TB_HPRED.NOITEM ,  HPRED.IDSERVICIO, SER.DESCSERVICIO , SER.AMBITO , COALESCE( NUM_ORDEN, 0) NUM_ORDEN,  HPRE.IDSEDE, U1.DATO INTERFAZ_LX, U2.DATO ITF_LX_HABILITA_EDIC
			,CASE WHEN (SER.AMBITO = 'LX' AND U1.DATO = 'ANNARLAB' AND COALESCE(HPRED.NUM_ORDEN, 0) <> 0 AND U2.DATO <> 'SI' ) THEN 'No Habiltada esta Opcion'
			ELSE 'Habilitado' END ESTADO
		FROM #TB_HPRED
			INNER JOIN HPRED ON #TB_HPRED.NOPRESTACION = HPRED.NOPRESTACION AND #TB_HPRED.NOITEM = HPRED.NOITEM  
