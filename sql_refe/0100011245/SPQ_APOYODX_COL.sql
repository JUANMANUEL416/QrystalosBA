	BEGIN
		SELECT @AUTORIZACIONES =  AUTORIZACIONES, @MARCAR =  MARCAR
	   FROM OPENJSON (@PARAMETROS)
	   WITH		 (
		AUTORIZACIONES		NVARCHAR(MAX) AS JSON
		,MARCAR				BIT  '$.MARCAR'
		)

		SELECT ROW_NUMBER()OVER(ORDER BY  IDAUT  DESC) FILA, * INTO #TABLA_AUTD
		FROM OPENJSON (@AUTORIZACIONES)
		WITH (
			IDAUT		VARCHAR(20)  '$.IDAUT'
			,NO_ITEM				INT  '$.NO_ITEM'
		)

		IF 1 = 2
         BEGIN
            INSERT INTO @TBLERRORES(ERROR) SELECT 'XXXXXXXX'
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
         END
			
		BEGIN TRY 
			SELECT 'OK'OK
			
            SELECT @ITEM_REGISTRO=1,@LIMITE_REGISTRO=0
            SELECT @LIMITE_REGISTRO=COUNT(*) FROM  #TABLA_AUTD
			WHILE @ITEM_REGISTRO<=@LIMITE_REGISTRO
            BEGIN
				IF @MARCAR = 1
				BEGIN
					UPDATE AUTD SET MARCA = 1, USUARIOMARCA = @USUARIO FROM AUTD INNER JOIN #TABLA_AUTD ON AUTD.IDAUT  = #TABLA_AUTD.IDAUT AND AUTD.NO_ITEM = #TABLA_AUTD.NO_ITEM
					WHERE #TABLA_AUTD.FILA = @ITEM_REGISTRO
				END
				IF @MARCAR = 0
				BEGIN
					UPDATE AUTD SET MARCA = NULL, USUARIOMARCA = NULL FROM AUTD INNER JOIN #TABLA_AUTD ON AUTD.IDAUT  = #TABLA_AUTD.IDAUT AND AUTD.NO_ITEM = #TABLA_AUTD.NO_ITEM
					WHERE #TABLA_AUTD.FILA = @ITEM_REGISTRO
				END
