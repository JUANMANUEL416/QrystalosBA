   SELECT @PERMISO = IIF(COUNT(*)>= 1, 1 , 0)FROM USGRUH WHERE USGRUH.IDCONTROL = 'Resultados_Cerrado' AND USGRUH.PERMISO = 1 AND USGRUH.GRUPO = @GRUPO
	IF @METODO = 'AMBITOS'
