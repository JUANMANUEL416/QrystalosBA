		WHERE (CASE WHEN (SER.AMBITO = 'LX' AND U1.DATO = 'ANNARLAB' AND COALESCE(HPRED.NUM_ORDEN, 0) <> 0 AND U2.DATO <> 'SI' ) THEN 'No Habiltada esta Opcion'
			ELSE 'Habilitado' END) = 'No Habiltada esta Opcion') AND @PROCESO = 2
		BEGIN
			SELECT @VALIDATE = 1
		END
		IF @VALIDATE>0
		BEGIN
            --INSERT INTO @TBLERRORES(ERROR) SELECT 'Hay registros que no permiten que se procese.'
            SELECT 'OK' OK, 'ERROR'ERROR
            --SELECT ERROR FROM @TBLERRORES
			SELECT #TB_HPRED.NOPRESTACION, #TB_HPRED.NOITEM ,  HPRED.IDSERVICIO, SER.DESCSERVICIO , SER.AMBITO , COALESCE( NUM_ORDEN, 0) NUM_ORDEN,  HPRE.IDSEDE, U1.DATO INTERFAZ_LX, U2.DATO ITF_LX_HABILITA_EDIC
				,CASE WHEN (SER.AMBITO = 'LX' AND U1.DATO = 'ANNARLAB' AND COALESCE(HPRED.NUM_ORDEN, 0) <> 0 AND U2.DATO <> 'SI' ) THEN 'No Habiltada esta Opcion'
				ELSE 'Habilitado' END ESTADO
			FROM #TB_HPRED
				INNER JOIN HPRED ON #TB_HPRED.NOPRESTACION = HPRED.NOPRESTACION AND #TB_HPRED.NOITEM = HPRED.NOITEM  
				INNER JOIN SER ON HPRED.IDSERVICIO = SER.IDSERVICIO
				INNER JOIN HPRE ON HPRED.NOPRESTACION = HPRE.NOPRESTACION
				INNER JOIN USVGS U1 ON U1.IDVARIABLE = 'INTERFAZ_LX'
				INNER JOIN USVGS U2 ON U2.IDVARIABLE = 'ITF_LX_HABILITA_EDIC'
			WHERE (CASE WHEN (SER.AMBITO = 'LX' AND U1.DATO = 'ANNARLAB' AND COALESCE(HPRED.NUM_ORDEN, 0) <> 0 AND U2.DATO <> 'SI' ) THEN 'No Habiltada esta Opcion'
				ELSE 'Habilitado' END) = 'No Habiltada esta Opcion'

            RETURN
         END


		IF 1 = 2
		BEGIN
            INSERT INTO @TBLERRORES(ERROR) SELECT 'XXXXXXXX'
            SELECT 'KO' OK
            SELECT ERROR FROM @TBLERRORES
            RETURN
         END
			
		BEGIN TRY 
            SELECT @ITEM_REGISTRO=1,@LIMITE_REGISTRO=0
            SELECT @LIMITE_REGISTRO=COUNT(*) FROM  #TB_HPRED
			WHILE @ITEM_REGISTRO<=@LIMITE_REGISTRO
            BEGIN
					SELECT @NOPRESTACION =#TB_HPRED.NOPRESTACION, @NOITEM = #TB_HPRED.NOITEM , @IDSERVICIO = HPRED.IDSERVICIO , @AMBITO = SER.AMBITO
						,@NUM_ORDEN = COALESCE( NUM_ORDEN, 0), @IDSEDE = HPRE.IDSEDE
					FROM #TB_HPRED
						INNER JOIN HPRED ON #TB_HPRED.NOPRESTACION = HPRED.NOPRESTACION AND #TB_HPRED.NOITEM = HPRED.NOITEM  
						INNER JOIN SER ON HPRED.IDSERVICIO = SER.IDSERVICIO
						INNER JOIN HPRE ON HPRED.NOPRESTACION = HPRE.NOPRESTACION
					WHERE  #TB_HPRED.FILA = @ITEM_REGISTRO
				IF @PROCESO = 1
				BEGIN
					IF @AMBITO = 'LX' AND @NUM_ORDEN <> 0 AND (SELECT DATO FROM USVGS WHERE  IDVARIABLE = 'INTERFAZ_LX') = 'ANNARLAB' AND (SELECT DATO FROM USVGS WHERE  IDVARIABLE = 'ITF_LX_HABILITA_EDIC')<> 'SI'
					BEGIN
						INSERT INTO @TBLERRORES(ERROR) SELECT 'No habilitada esta opción.'
						SELECT 'KO' OK
						SELECT ERROR FROM @TBLERRORES
						RETURN
					END
					IF (SELECT CANTIDAD FROM HPRED WHERE NOPRESTACION = @NOPRESTACION AND NOITEM = @NOITEM )>1
					BEGIN
						IF @CANTIDAD>0 AND @CANTIDAD <> (SELECT CANTIDAD FROM HPRED WHERE NOPRESTACION = @NOPRESTACION AND NOITEM = @NOITEM ) 
						BEGIN
							IF NOT EXISTS (SELECT 1 FROM HPRED WHERE NOPRESTACION = @NOPRESTACION AND NOITEM = @NOITEM AND COALESCE(FACTURADA,0)=0 AND COALESCE( N_FACTURA,'')='')
							BEGIN
								INSERT INTO @TBLERRORES(ERROR) SELECT 'Ésta prestación se encuentra facturada, y no puede realizarse cambios, debe traer la cantidad igual a la solicitud. '
								SELECT 'KO' OK
								SELECT ERROR FROM @TBLERRORES
								RETURN
							END
							SELECT @NVOCONSEC = NULL
							EXEC SPK_GENCONSECUTIVO '01',@IDSEDE,'@HPRE', @NVOCONSEC OUTPUT  
							SELECT @NVOCONSEC = @IDSEDE + REPLACE(SPACE(10 - LEN(@NVOCONSEC))+LTRIM(RTRIM(@NVOCONSEC)),SPACE(1),0) 

							BEGIN TRY
								EXEC SPK_DUPLICA_HPRED @NOPRESTACION, @NOITEM, @NVOCONSEC, @CANTIDAD, @USUARIO, @SYS_COMPUTERNAME
							END TRY
							BEGIN CATCH
								INSERT INTO @TBLERRORES(ERROR)
								SELECT ERROR_MESSAGE()
							END CATCH
						END
					END
               PRINT 'SPK_TRAE_A_INGRESOS==>'
					EXEC SPK_TRAE_UN_INGRESOS @NOPRESTACION , @NOITEM, '01', @IDSEDE, @USUARIO, 'A', @AMBITO, @IDSERVICIO
               --SELECT  @NOPRESTACION , @NOITEM, '01', @IDSEDE, @USUARIO, 'A', @AMBITO
					--EXEC SPK_TRAE_A_INGRESOS @NOPRESTACION , @NOITEM, '01', @IDSEDE, @USUARIO, 'A', @AMBITO
					SELECT @ITEM_REGISTRO = @ITEM_REGISTRO+1 
				END
				IF @PROCESO = 2
				BEGIN
					IF @AMBITO = 'LX' AND @NUM_ORDEN <> 0 AND (SELECT DATO FROM USVGS WHERE  IDVARIABLE = 'INTERFAZ_LX') = 'ANNARLAB' AND (SELECT DATO FROM USVGS WHERE  IDVARIABLE = 'ITF_LX_HABILITA_EDIC')<> 'SI'
					BEGIN
						INSERT INTO @TBLERRORES(ERROR) SELECT 'No habilitada esta opción.'
