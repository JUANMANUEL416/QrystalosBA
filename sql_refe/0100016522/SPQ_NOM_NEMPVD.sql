CREATE OR ALTER PROCEDURE DBO.SPQ_NOM_NEMPVD @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
SET DATEFORMAT dmy

DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE @PARAMETROS NVARCHAR(MAX), @MODELO VARCHAR(100), @METODO VARCHAR(100), @USUARIO VARCHAR(12), @COMPANIA VARCHAR(2), @IDSEDE VARCHAR(5), @SYS_COMPUTERNAME 
	VARCHAR(200), @DATOS VARCHAR(MAX), @OBSERVACIONES VARCHAR(512)
DECLARE @CNSNEMPVD VARCHAR(20), @NUMDOC VARCHAR(20), @ITEM SMALLINT, @EVENTO VARCHAR(6), @NDIAS DECIMAL(7, 4), @CNSPAGO VARCHAR(20), @ESTADO VARCHAR(10), @FECHAINI 
	DATETIME, @SABADO SMALLINT, @DOMINGO SMALLINT, @FESTIVO SMALLINT, @DIASCAL SMALLINT, @PROCE VARCHAR(10), @PROCESO VARCHAR(20)

BEGIN
	SELECT *
	INTO #JSON
	FROM OPENJSON(@json) WITH (MODELO VARCHAR(100) '$.MODELO', METODO VARCHAR(100) '$.METODO', USUARIO VARCHAR(12) '$.USUARIO', PARAMETROS NVARCHAR(MAX) AS JSON
			)

	SELECT @MODELO = MODELO, @METODO = METODO, @PARAMETROS = PARAMETROS, @USUARIO = USUARIO
	FROM #JSON

	IF @METODO = 'GUARDAR'
	BEGIN
		BEGIN TRY
			SELECT @NUMDOC = NUMDOC, @ITEM = ITEM, @EVENTO = EVENTO, @NDIAS = NDIAS, @OBSERVACIONES = OBSERVACIONES, @CNSPAGO = CNSPAGO, @ESTADO = ESTADO, @FECHAINI = 
				FECHAINI, @CNSPAGO = CNSPAGO, @SABADO = SABADO, @DOMINGO = DOMINGO, @FESTIVO = FESTIVO, @DIASCAL = DIASCAL, @PROCE = PROCE, @PROCESO = PROCESO
			FROM OPENJSON(@PARAMETROS) WITH (
					NUMDOC VARCHAR(20) '$.NUMDOC', ITEM SMALLINT '$.ITEM', EVENTO VARCHAR(6) '$.EVENTO', NDIAS DECIMAL(7, 4) '$.NDIAS', OBSERVACIONES VARCHAR(512) 
					'$.OBSERVACIONES', CNSPAGO VARCHAR(20) '$.CNSPAGO', ESTADO VARCHAR(10) '$.ESTADO', FECHAINI DATETIME '$.FECHASALIDA', SABADO SMALLINT 
					'$.SABADO', DOMINGO SMALLINT '$.DOMINGO', FESTIVO SMALLINT '$.FESTIVO', DIASCAL SMALLINT '$.DIASCAL', PROCE VARCHAR(10) '$.PROCE', PROCESO 
					VARCHAR(20) '$.PROCESO'
					)

			SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
			FROM USUSU
			WHERE USUARIO = @USUARIO

			SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
			FROM UBEQ
			WHERE SYS_ComputerName = @SYS_COMPUTERNAME

			IF UPPER(@PROCESO) = 'INSERTAR'
			BEGIN
				BEGIN TRY
					IF (
							SELECT CERRADO
							FROM NPER
							WHERE CNSPAGO = @CNSPAGO
							) = 1
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('EL PERIODO ', @CNSPAGO, ' SE ENCUENTRRA CERRADO, NO SERA POSIBLE CREAR LA NOVEDAD'
								)
					END

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@NEMPVD', @LONGITUD = 8, @NVOCONSEC = @CNSNEMPVD OUTPUT

						INSERT INTO NEMPVD (
							CNSNEMPVD, NUMDOC, ITEM, EVENTO, NDIAS, OBSERVACIONES, CNSPAGO, USUARIO, SYS_COMPUTERNAME, ESTADO, FECHAINI, SABADO, DOMINGO, FESTIVO, 
							DIASCAL, PROCE
							)
						SELECT @CNSNEMPVD, @NUMDOC, @ITEM, @EVENTO, @NDIAS, @OBSERVACIONES, @CNSPAGO, @USUARIO, @SYS_COMPUTERNAME, 'Nuevo', @FECHAINI, @SABADO, 
							@DOMINGO, @FESTIVO, @DIASCAL, 'Novedad'
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END

			IF UPPER(@PROCESO) = 'EDITAR'
			BEGIN
				BEGIN TRY
					SELECT @CNSNEMPVD = CNSNEMPVD
					FROM OPENJSON(@PARAMETROS) WITH (CNSNEMPVD VARCHAR(20) '$.CNSNEMPVD')

					SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
					FROM USUSU
					WHERE USUARIO = @USUARIO

					SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
					FROM UBEQ
					WHERE SYS_ComputerName = @SYS_COMPUTERNAME

					IF (
							SELECT CERRADO
							FROM NPER
							WHERE CNSPAGO = @CNSPAGO
							) = 1
					BEGIN
						INSERT INTO @TBLERRORES (ERROR)
						SELECT CONCAT ('EL PERIODO ', @CNSPAGO, ' SE ENCUENTRRA CERRADO, NO SERA POSIBLE EDITAR LA NOVEDAD'
								)
					END

					IF (
							SELECT COUNT(*)
							FROM @TBLERRORES
							) <= 0
					BEGIN
						UPDATE NEMPVD
						SET EVENTO = @EVENTO, CNSPAGO = @CNSPAGO, NDIAS = @NDIAS, FECHAINI = @FECHAINI, SABADO = @SABADO, DOMINGO = @DOMINGO, FESTIVO = @FESTIVO, DIASCAL = 
							@DIASCAL, USUARIO = @USUARIO, SYS_COMPUTERNAME = @SYS_COMPUTERNAME, OBSERVACIONES = @OBSERVACIONES
						WHERE CNSNEMPVD = @CNSNEMPVD AND ITEM = @ITEM
					END
				END TRY

				BEGIN CATCH
					INSERT INTO @TBLERRORES (ERROR)
					SELECT ERROR_MESSAGE()
				END CATCH

				IF (
						SELECT COUNT(*)
						FROM @TBLERRORES
						) > 0
				BEGIN
					SELECT 'KO' OK

					SELECT ERROR
					FROM @TBLERRORES

					RETURN
				END

				SELECT 'OK' OK

				RETURN
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'JUSTIFICA_VACACIONES'
	BEGIN
		BEGIN TRY
			SELECT @SYS_COMPUTERNAME = SYS_COMPUTERNAME
			FROM USUSU
			WHERE USUARIO = @USUARIO

			SELECT @IDSEDE = IDSEDE, @COMPANIA = COMPANIA
			FROM UBEQ
			WHERE SYS_ComputerName = @SYS_COMPUTERNAME

			SELECT @NUMDOC = NUMDOC, @ITEM = ITEM, @EVENTO = EVENTO, @NDIAS = NDIAS, @OBSERVACIONES = OBSERVACIONES, @CNSPAGO = CNSPAGO, @FECHAINI = FECHAINI, @DIASCAL = 
				DIASCAL
			FROM OPENJSON(@PARAMETROS) WITH (
					NUMDOC VARCHAR(20) '$.NUMDOC', ITEM SMALLINT '$.ITEM', EVENTO VARCHAR(6) '$.EVENTO', NDIAS DECIMAL(7, 4) '$.NDIAS', OBSERVACIONES VARCHAR(512) 
					'$.OBSERVACIONES', CNSPAGO VARCHAR(20) '$.CNSPAGO', FECHAINI DATETIME '$.FECHAINI', DIASCAL SMALLINT '$.DIASCAL'
					)

			EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@NEMPVD', @LONGITUD = 8, @NVOCONSEC = @CNSNEMPVD OUTPUT

			INSERT INTO NEMPVD (CNSNEMPVD, NUMDOC, ITEM, EVENTO, NDIAS, OBSERVACIONES, CNSPAGO, USUARIO, SYS_COMPUTERNAME, ESTADO, FECHAINI, SABADO, DOMINGO, FESTIVO, DIASCAL, PROCE
				)
			SELECT @CNSNEMPVD, @NUMDOC, @ITEM, @EVENTO, @NDIAS, @OBSERVACIONES, @CNSPAGO, @USUARIO, @SYS_COMPUTERNAME, 'EnNomina', @FECHAINI, 0, 0, 0, @NDIAS, 
				'JustVaca'

			UPDATE NEMPV
			SET DIASP = COALESCE(DIASP, 0) + @NDIAS
			WHERE NUMDOC = @NUMDOC AND ITEM = @ITEM

			UPDATE NEMPV
			SET ESTADO = CASE 
					WHEN DIASG >= NDIAS
						THEN CASE 
								WHEN DIASP >= DIASG
									THEN 'Pagado'
								ELSE 'Cumplidas'
								END
					ELSE 'Proceso'
					END
			WHERE NUMDOC = @NUMDOC AND ITEM = @ITEM
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END

	IF @METODO = 'ANULAR_JUSVAC'
	BEGIN
		SELECT @CNSNEMPVD = CNSNEMPVD, @NUMDOC = NUMDOC, @ITEM = ITEM, @PROCE = PROCE
		FROM OPENJSON(@PARAMETROS) WITH (CNSNEMPVD VARCHAR(20) '$.CNSNEMPVD', NUMDOC VARCHAR(20) '$.NUMDOC', ITEM INT '$.ITEM', PROCE VARCHAR(10) '$.PROCE'
				)

		BEGIN TRY
			UPDATE NEMPVD
			SET ESTADO = 'Anulado'
			WHERE CNSNEMPVD = @CNSNEMPVD

			IF (@PROCE = 'JustVaca')
			BEGIN
				UPDATE NEMPV
				SET DIASP = DIASP - NEMPVD.NDIAS
				FROM NEMPV
				INNER JOIN NEMPVD ON NEMPV.NUMDOC = NEMPVD.NUMDOC
				WHERE NEMPVD.CNSNEMPVD = @CNSNEMPVD AND NEMPV.ITEM = @ITEM

				UPDATE NEMPV
				SET ESTADO = CASE 
						WHEN DIASG >= NDIAS
							THEN CASE 
									WHEN DIASP >= DIASG
										THEN 'Pagado'
									ELSE 'Cumplidas'
									END
						ELSE 'Proceso'
						END
				WHERE NUMDOC = @NUMDOC AND ITEM = @ITEM
			END
		END TRY

		BEGIN CATCH
			INSERT INTO @TBLERRORES (ERROR)
			SELECT ERROR_MESSAGE()
		END CATCH

		IF (
				SELECT COUNT(*)
				FROM @TBLERRORES
				) > 0
		BEGIN
			SELECT 'KO' OK

			SELECT ERROR
			FROM @TBLERRORES

			RETURN
		END

		SELECT 'OK' OK
	END
END
