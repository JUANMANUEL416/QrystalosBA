
CREATE OR ALTER PROCEDURE DBO.SPK_INSERT_CXP_INV
@CNSFCXP VARCHAR(20),
@CNSMOV VARCHAR(20),
@PROCE  VARCHAR(10)=NULL
WITH ENCRYPTION
AS
-- bugfix/COESME600 -- 2026-09-07 -- Valores de l?nea a DECIMAL(14,4) para no perder cent?simas
DECLARE @VALOR_CUR DECIMAL(14,4)
DECLARE @IDARTICULO_CUR VARCHAR(20)
DECLARE @CANTIDAD_CUR DECIMAL(14,4)
DECLARE @NOLOTE_CUR VARCHAR(20)
DECLARE @PREFIJO_CUR VARCHAR(6) 
DECLARE @CCOSTO_CUR  VARCHAR(20) 
DECLARE @IDAREA_CUR  VARCHAR(20)
DECLARE @IDGRUPOIMP_CUR VARCHAR(20)
DECLARE @VLRDTO_CUR  DECIMAL(14,4)
DECLARE @VLRIVA_CUR  DECIMAL(14,4)
DECLARE @VLRNETO_CUR DECIMAL(14,4)
DECLARE @ITEM        INT
DECLARE @ITEM_ANT    INT
DECLARE @IDCLASEIMP  VARCHAR(2)
DECLARE @VLR_FLETE   DECIMAL(14,2)
DECLARE @CODUNG      VARCHAR(5)
DECLARE @CODPRG      VARCHAR(20)
DECLARE @IDGRUPO     VARCHAR(20)
DECLARE @IDIMPUESTO  VARCHAR(10)
DECLARE @IDCLASE     VARCHAR(10)
DECLARE @FECHA_FAC   DATETIME
DECLARE @ITEM_FIMPDV SMALLINT
DECLARE @CUENTA_IVA  VARCHAR(16)
DECLARE @DECONSUMO   SMALLINT
DECLARE @VLRIMPCONSUMO DECIMAL(14,4)
DECLARE @ESACTIVO    SMALLINT
DECLARE @NOLE_CUR    VARCHAR(20)
DECLARE @ITAR_MIVA   SMALLINT
DECLARE @ITAR_CUEIVA VARCHAR(20)
DECLARE @FECHACXP    DATETIME
DECLARE @CNSFCOM     VARCHAR(20)
DECLARE @IDBODEGA    VARCHAR(20)
DECLARE @NOLOTEINTER VARCHAR(20)
DECLARE @PIVA_CUR    DECIMAL(14,4)
DECLARE @FECHA_IMP   DATETIME
DECLARE @RECONSTRUYE SMALLINT
DECLARE @FECHAVENCE_CUR DATETIME
DECLARE @PCOSTO_GRP  DECIMAL(18,6)
BEGIN
	PRINT 'ENTRE A CREAR FCXPD CNSMOV = '+@CNSMOV
	PRINT '@CNSFCXP...'+@CNSFCXP
	SELECT @IDCLASEIMP=IDCLASEIMP, @FECHA_FAC = F_FACTURAREF,@FECHACXP=FECHA FROM FCXP WHERE CNSFCXP=@CNSFCXP
	-- VER SI ES DECONSUMO EN LA ORDEN DE COMPRA B29102006_001
	SELECT @DECONSUMO = FCOM.DECONSUMO, @CNSFCOM=IMOV.CNSFCOM
	FROM   FCOM INNER JOIN IMOV ON FCOM.CNSFCOM = IMOV.CNSFCOM
	WHERE  IMOV.CNSMOV = @CNSMOV
	-- E29102006_001

	PRINT'BORRO EL DETALLE SI LOS HAY'
	/* bugfix/COESME600 -- 2026-09-07
	   Reconstrucci?n: borra FCXPD del movimiento aunque IMOVH.ENCXP=1. */
	SELECT @RECONSTRUYE = 0
	IF EXISTS(SELECT * FROM FCXPD WHERE CNSFCXP=@CNSFCXP AND N_PRESUP=@CNSMOV)
	BEGIN
		DELETE FCXPD WHERE CNSFCXP=@CNSFCXP AND N_PRESUP=@CNSMOV
		SELECT @RECONSTRUYE = 1
	END   

   /* bugfix/MEDICAL782 -- 2026-09-08
      Al reconstruir, ESTADO=9 aunque ENCXP=1; si no, el cursor no lee IMOVH. */
   UPDATE IMOVH SET ESTADO=9
   WHERE CNSMOV=@CNSMOV
     AND (COALESCE(ENCXP,0)=0 OR @RECONSTRUYE=1)

   IF DBO.FNK_VALORVARIABLE('REDONDEO_COMPRAS_CXP')<>'SI'
   BEGIN
      DECLARE CUR_MOV CURSOR FOR
      SELECT IMOVH.IDARTICULO, IMOVH.CANTIDAD,
             -- bugfix/COESME600 -- 2026-09-07 -- ROUND a 4 decimales (antes 2: 1398.842 ? 1398.84)
             /* bugfix/MEDICAL782 -- 2026-09-08
                PCOSTO de la entrada actual es base sin IVA (VLRIVA va aparte).
                Solo se resta IVA/cantidad si el costo ya trae el IVA incluido (tasa sobre neto). */
             ROUND(IMOVH.COSTO,4)+(ROUND(COALESCE(IMOVH.DESCUENTO,0)/NULLIF(IMOVH.CANTIDAD,0),4))
             - CASE
                  WHEN COALESCE(IMOVH.IVA,0) <= 0 OR COALESCE(IMOVH.CANTIDAD,0) <= 0 THEN 0
                  WHEN (IMOVH.COSTO * IMOVH.CANTIDAD) <= COALESCE(IMOVH.IVA,0) THEN 0
                  WHEN ABS((IMOVH.IVA * 100.0 / NULLIF(IMOVH.COSTO * IMOVH.CANTIDAD, 0)) - COALESCE(NULLIF(IMOVH.PIVA, 0), 19))
                     <= ABS((IMOVH.IVA * 100.0 / NULLIF(IMOVH.COSTO * IMOVH.CANTIDAD - IMOVH.IVA, 0)) - COALESCE(NULLIF(IMOVH.PIVA, 0), 19))
                  THEN 0
                  ELSE ROUND(IMOVH.IVA / IMOVH.CANTIDAD, 4)
               END,
             IMOVH.NOLOTEPEDIDO, IART.IDITAR, IMOV.CCOSTO, IMOV.IDAREA, ITAR.IDGRUPOIMP, COALESCE(IMOVH.DESCUENTO,0),
             COALESCE(IMOVH.IVA,0), IMOVH.COSTO*IMOVH.CANTIDAD, IMOV.CODUNG, IMOV.CODPRG, IART.IDGRUPO, IMOVH.IDIMPUESTO, IMOVH.IDCLASE,COALESCE(IMOVH.VLRIMPCONSUMO,0) ,
             IART.ESACTIVO,COALESCE(ITAR.MIVA,0), COALESCE(ITAR.CUE_IVA,'') ,IMOV.IDBODEGA,
             (SELECT TOP 1 NOLOTE FROM IMOVH X WHERE X.CNSMOV=@CNSMOV AND X.IDARTICULO=IMOVH.IDARTICULO AND X.NOLOTEPEDIDO=IMOVH.NOLOTEPEDIDO)  NOLOTE,
             IMOVH.FECHAVENCE, IMOVH.COSTO
      FROM	 IMOV,VWK_IMOVH_AGRUPADO IMOVH,ITAR,IART  
      WHERE  IMOV.CNSMOV     = @CNSMOV 
      AND    IMOVH.ESTADO    = 9 
      AND    IMOV.CNSMOV     = IMOVH.CNSMOV 
      AND    IMOVH.CANTIDAD  > 0 
      AND    IART.IDARTICULO = IMOVH.IDARTICULO
      AND    IART.IDITAR     = ITAR.IDITAR 
   END
   ELSE
   BEGIN --IMOVH
      DECLARE CUR_MOV CURSOR FOR
      SELECT IMOVH.IDARTICULO, IMOVH.CANTIDAD,
             /* bugfix/MEDICAL782 -- 2026-09-08 -- Misma regla de base: no restar IVA si PCOSTO ya es sin IVA. */
             ROUND(IMOVH.COSTO,3)+(ROUND(COALESCE(IMOVH.DESCUENTO,0)/NULLIF(IMOVH.CANTIDAD,0),3))
             - CASE
                  WHEN COALESCE(IMOVH.IVA,0) <= 0 OR COALESCE(IMOVH.CANTIDAD,0) <= 0 THEN 0
                  WHEN (IMOVH.COSTO * IMOVH.CANTIDAD) <= COALESCE(IMOVH.IVA,0) THEN 0
                  WHEN ABS((IMOVH.IVA * 100.0 / NULLIF(IMOVH.COSTO * IMOVH.CANTIDAD, 0)) - COALESCE(NULLIF(IMOVH.PIVA, 0), 19))
                     <= ABS((IMOVH.IVA * 100.0 / NULLIF(IMOVH.COSTO * IMOVH.CANTIDAD - IMOVH.IVA, 0)) - COALESCE(NULLIF(IMOVH.PIVA, 0), 19))
                  THEN 0
                  ELSE ROUND(IMOVH.IVA / IMOVH.CANTIDAD, 3)
               END,
             IMOVH.NOLOTEPEDIDO, IART.IDITAR, IMOV.CCOSTO, IMOV.IDAREA, ITAR.IDGRUPOIMP, COALESCE(IMOVH.DESCUENTO,0),
             COALESCE(IMOVH.IVA,0), ROUND(IMOVH.COSTO*IMOVH.CANTIDAD,0), IMOV.CODUNG, IMOV.CODPRG, IART.IDGRUPO, IMOVH.IDIMPUESTO, IMOVH.IDCLASE,COALESCE(IMOVH.VLRIMPCONSUMO,0) ,
             IART.ESACTIVO,COALESCE(ITAR.MIVA,0), COALESCE(ITAR.CUE_IVA,''),IMOV.IDBODEGA,
             (SELECT TOP 1 NOLOTE FROM IMOVH X WHERE X.CNSMOV=@CNSMOV AND X.IDARTICULO=IMOVH.IDARTICULO AND X.NOLOTEPEDIDO=IMOVH.NOLOTEPEDIDO)  NOLOTE,
             IMOVH.FECHAVENCE, IMOVH.COSTO
      FROM	 IMOV,VWK_IMOVH_AGRUPADO IMOVH,ITAR,IART  
      WHERE  IMOV.CNSMOV     = @CNSMOV 
      AND    IMOVH.ESTADO    = 9 
      AND    IMOV.CNSMOV     = IMOVH.CNSMOV 
      AND    IMOVH.CANTIDAD  > 0 
      AND    IART.IDARTICULO = IMOVH.IDARTICULO
      AND    IART.IDITAR     = ITAR.IDITAR 
   END
   OPEN CUR_MOV
   FETCH NEXT FROM CUR_MOV
   INTO @IDARTICULO_CUR, @CANTIDAD_CUR, @VALOR_CUR ,@NOLOTE_CUR, @PREFIJO_CUR, @CCOSTO_CUR, @IDAREA_CUR,
        @IDGRUPOIMP_CUR, @VLRDTO_CUR, @VLRIVA_CUR, @VLRNETO_CUR, @CODUNG, @CODPRG, @IDGRUPO, @IDIMPUESTO, @IDCLASE,@VLRIMPCONSUMO, @ESACTIVO,
        @ITAR_MIVA,@ITAR_CUEIVA,@IDBODEGA,@NOLOTEINTER, @FECHAVENCE_CUR, @PCOSTO_GRP
   
   SELECT @ITEM=MAX(ITEM)+1 FROM FCXPD WHERE CNSFCXP=@CNSFCXP  
   IF @ITEM IS NULL
   BEGIN
      SET @ITEM=1
   END
   SET @ITEM_ANT=@ITEM
   WHILE @@FETCH_STATUS = 0
   BEGIN 
      /* IVA de esta fila: artículo + lote de compra + vencimiento + costo.
         No usar la suma del artículo ni la de toda la entrada. */
      SELECT @VLRIVA_CUR = COALESCE(SUM(H.VLRIVA), 0)
      FROM IMOVH H
      WHERE H.CNSMOV = @CNSMOV
        AND H.IDARTICULO = @IDARTICULO_CUR
        AND ISNULL(H.NOLOTEPEDIDO, '') = ISNULL(@NOLOTE_CUR, '')
        AND H.ESTADO = 9
        AND H.PCOSTO = @PCOSTO_GRP
        AND ((H.FECHAVENCE = @FECHAVENCE_CUR) OR (H.FECHAVENCE IS NULL AND @FECHAVENCE_CUR IS NULL))

      /* bugfix/MEDICAL782 -- 2026-09-08
         IMOVH a veces trae VLRIVA/PIVA sin IDIMPUESTO/IDCLASE (o con 0 por la vista).
         Cascada: IART (IDCLASE_IMP, luego IDCLASE), luego ITAR, si no variable IDIMP_IVA + FIMPDV (valor y vigencia). */
      IF COALESCE(@VLRIVA_CUR, 0) > 0
      BEGIN
         IF LTRIM(RTRIM(COALESCE(@IDIMPUESTO, ''))) IN ('', '0') SET @IDIMPUESTO = NULL
         IF LTRIM(RTRIM(COALESCE(@IDCLASE, ''))) IN ('', '0') SET @IDCLASE = NULL

         IF NOT EXISTS (
            SELECT 1 FROM FIMPD
            WHERE FIMPD.IDIMPUESTO = @IDIMPUESTO AND FIMPD.IDCLASE = @IDCLASE
         )
         BEGIN
            SELECT @IDIMPUESTO = NULL, @IDCLASE = NULL

            SELECT
               @IDIMPUESTO = NULLIF(LTRIM(RTRIM(IART.IDIMPUESTO)), ''),
               @IDCLASE = CASE
                  WHEN EXISTS (
                     SELECT 1 FROM FIMPD F
                     WHERE F.IDIMPUESTO = IART.IDIMPUESTO AND F.IDCLASE = IART.IDCLASE_IMP
                  ) THEN IART.IDCLASE_IMP
                  WHEN EXISTS (
                     SELECT 1 FROM FIMPD F
                     WHERE F.IDIMPUESTO = IART.IDIMPUESTO AND F.IDCLASE = IART.IDCLASE
                  ) THEN IART.IDCLASE
                  ELSE NULL
               END
            FROM IART
            WHERE IART.IDARTICULO = @IDARTICULO_CUR

            IF NOT EXISTS (
               SELECT 1 FROM FIMPD
               WHERE FIMPD.IDIMPUESTO = @IDIMPUESTO AND FIMPD.IDCLASE = @IDCLASE
            )
            BEGIN
               SELECT
                  @IDIMPUESTO = NULLIF(LTRIM(RTRIM(ITAR.IDIMPUESTO)), ''),
                  @IDCLASE = NULLIF(LTRIM(RTRIM(ITAR.IDCLASE)), '')
               FROM ITAR
               INNER JOIN IART ON IART.IDITAR = ITAR.IDITAR
               WHERE IART.IDARTICULO = @IDARTICULO_CUR

               IF NOT EXISTS (
                  SELECT 1 FROM FIMPD
                  WHERE FIMPD.IDIMPUESTO = @IDIMPUESTO AND FIMPD.IDCLASE = @IDCLASE
               )
               BEGIN
                  SELECT @IDIMPUESTO = NULLIF(LTRIM(RTRIM(DBO.FNK_VALORVARIABLE('IDIMP_IVA'))), '')
                  SELECT @PIVA_CUR = NULL
                  SELECT TOP 1 @PIVA_CUR = COALESCE(IMOVH.PIVA, 0)
                  FROM IMOVH
                  WHERE IMOVH.CNSMOV = @CNSMOV
                    AND IMOVH.IDARTICULO = @IDARTICULO_CUR
                    AND IMOVH.NOLOTEPEDIDO = @NOLOTE_CUR

                  IF COALESCE(@PIVA_CUR, 0) = 0 AND COALESCE(@VLRIVA_CUR, 0) > 0
                     AND (@CANTIDAD_CUR * @VALOR_CUR) > 0
                  BEGIN
                     SELECT @PIVA_CUR = ROUND(@VLRIVA_CUR * 100.0 / (@CANTIDAD_CUR * @VALOR_CUR), 2)
                  END

                  SELECT @FECHA_IMP = COALESCE(@FECHA_FAC, @FECHACXP)
                  SELECT @IDCLASE = NULL
                  SELECT TOP 1 @IDCLASE = FIMPDV.IDCLASE
                  FROM FIMPDV
                  INNER JOIN FIMPD ON FIMPD.IDIMPUESTO = FIMPDV.IDIMPUESTO AND FIMPD.IDCLASE = FIMPDV.IDCLASE
                  WHERE FIMPDV.IDIMPUESTO = @IDIMPUESTO
                    AND @FECHA_IMP IS NOT NULL
                    AND CONVERT(DATE, @FECHA_IMP) >= CONVERT(DATE, FIMPDV.FECHAINI)
                    AND CONVERT(DATE, @FECHA_IMP) <= CONVERT(DATE, FIMPDV.FECHAFIN)
                    AND ROUND(FIMPDV.VALOR, 2) = ROUND(COALESCE(@PIVA_CUR, 0), 2)
                  ORDER BY
                     CASE WHEN COALESCE(@ITAR_CUEIVA, '') <> '' AND FIMPDV.CUENTA = @ITAR_CUEIVA THEN 0 ELSE 1 END,
                     CASE WHEN FIMPD.DESCRIPCION LIKE N'%COMPRA%' THEN 0 ELSE 1 END,
                     FIMPDV.IDCLASE
               END
            END
         END
      END

		IF DBO.FNK_VALORVARIABLE('CUENTA_IVA_CXP')='SI'
      BEGIN 
         PRINT 'CUENTA_IVA_CXP=SI'
         IF @ITAR_MIVA=0
         BEGIN
            SELECT @ITEM_FIMPDV = ITEM, @CUENTA_IVA = CUENTA
            FROM   FNK_VALOR_IMPUESTO(@IDIMPUESTO, @IDCLASE, @FECHA_FAC, @VALOR_CUR)
         END
         ELSE
         BEGIN
            SELECT @ITEM_FIMPDV = ITEM, @CUENTA_IVA = CUENTA
            FROM   DBO.FNK_PIVA_IART(@IDARTICULO_CUR, @FECHA_FAC, @VALOR_CUR)            
         END
      END
      ELSE 
      BEGIN
         PRINT 'CUENTA_IVA_CXP=NO'
         SELECT @CUENTA_IVA=NULL,@ITEM_FIMPDV=NULL
      END
      PRINT 'CREO FCXPD CON ITEM= ' +STR(@ITEM)
      PRINT 'IVA: '+@CUENTA_IVA
      IF UPPER(DBO.FNK_VALORVARIABLE('CONTAB_INV_IVA_ITAR'))='SI' AND  @ITAR_MIVA=1
      BEGIN
         PRINT 'CUENTA IVA DESDE ITAR'
         INSERT INTO FCXPD (CNSFCXP,ITEM,IDSERVICIO,CANTIDAD,VALOR,VLR_DESCUENTO,VLR_IVA,VLR_NETO,ESTADO,
                            N_PRESUP,ITEM_PRESUP,IDCLASEIMP,NOLOTE,PREFIJO,CCOSTO,IDAREA, VLR_GLOSAS, PROCEDENCIA,
                            CUENTA_SER, CODUNG, CODPRG, IDIMPUESTO, IDCLASE, ITEM_FIMPDV, CUENTA_IVA,MIMPCONSUMO,VLRIMPCONSUMO,CTAIMPCONSUMO,IDBODEGA,NOLOTEINTER) --@VLRIMPCONSUMO
         SELECT @CNSFCXP,@ITEM,@IDARTICULO_CUR,@CANTIDAD_CUR,@VALOR_CUR,@VLRDTO_CUR,@VLRIVA_CUR,
                (@CANTIDAD_CUR*@VALOR_CUR)+@VLRIVA_CUR-@VLRDTO_CUR,'P',
                @CNSMOV, 0, @IDGRUPOIMP_CUR,@NOLOTE_CUR,@PREFIJO_CUR,@CCOSTO_CUR,@IDAREA_CUR,0,'Compras',
                DBO.FNK_CUENTA_KMCOM(DBO.FNK_VALORVARIABLE('IDMODELOCONTABLE'),'CXP_COMPRAS','DB',@PREFIJO_CUR,@IDAREA_CUR,@CCOSTO_CUR,'S',@IDGRUPO),
                @CODUNG, @CODPRG, @IDIMPUESTO, @IDCLASE, @ITEM_FIMPDV,@CUENTA_IVA,CASE WHEN COALESCE(@VLRIMPCONSUMO,0)>0 THEN 1 ELSE 0 END,
                CASE WHEN COALESCE(@VLRIMPCONSUMO,0)>0 THEN @VLRIMPCONSUMO ELSE 0 END,
                CASE WHEN COALESCE(@VLRIMPCONSUMO,0)>0 THEN COALESCE(DBO.FNK_VALORVARIABLE('CTAIMPUESTOCONSUMO'),'') ELSE '' END,@IDBODEGA,@NOLOTEINTER
      END
      ELSE
      BEGIN
         INSERT INTO FCXPD (CNSFCXP,ITEM,IDSERVICIO,CANTIDAD,VALOR,VLR_DESCUENTO,VLR_IVA,VLR_NETO,ESTADO,
                            N_PRESUP,ITEM_PRESUP,IDCLASEIMP,NOLOTE,PREFIJO,CCOSTO,IDAREA, VLR_GLOSAS, PROCEDENCIA,
                            CUENTA_SER, CODUNG, CODPRG, IDIMPUESTO, IDCLASE, ITEM_FIMPDV, CUENTA_IVA,MIMPCONSUMO,VLRIMPCONSUMO,CTAIMPCONSUMO,IDBODEGA,NOLOTEINTER) --@VLRIMPCONSUMO
         SELECT @CNSFCXP,@ITEM,@IDARTICULO_CUR,@CANTIDAD_CUR,@VALOR_CUR,@VLRDTO_CUR,@VLRIVA_CUR,
                (@CANTIDAD_CUR*@VALOR_CUR)+@VLRIVA_CUR-@VLRDTO_CUR,'P',
                @CNSMOV, 0, @IDGRUPOIMP_CUR,@NOLOTE_CUR,@PREFIJO_CUR,@CCOSTO_CUR,@IDAREA_CUR,0,'Compras',
                DBO.FNK_CUENTA_KMCOM(DBO.FNK_VALORVARIABLE('IDMODELOCONTABLE'),'CXP_COMPRAS','DB',@PREFIJO_CUR,@IDAREA_CUR,@CCOSTO_CUR,'S',@IDGRUPO),
                @CODUNG, @CODPRG, @IDIMPUESTO, @IDCLASE, CASE @DECONSUMO WHEN 0 THEN @ITEM_FIMPDV
                                                                         ELSE NULL
                                                         END, 
                CASE @ESACTIVO WHEN 1 THEN DBO.FNK_CUENTA_KMCOM(DBO.FNK_VALORVARIABLE('IDMODELOCONTABLE'),'CXP_COMPRAS','DB',@PREFIJO_CUR,@IDAREA_CUR,@CCOSTO_CUR,'S',@IDGRUPO)
                                       ELSE CASE @DECONSUMO WHEN 0 THEN CASE WHEN COALESCE(@VLRIVA_CUR,0)>0 THEN   @CUENTA_IVA ELSE '' END
                                                            ELSE CASE WHEN COALESCE(@VLRIVA_CUR,0)>0 THEN   @CUENTA_IVA ELSE '' END  END
                END,CASE WHEN COALESCE(@VLRIMPCONSUMO,0)>0 THEN 1 ELSE 0 END,CASE WHEN COALESCE(@VLRIMPCONSUMO,0)>0 THEN @VLRIMPCONSUMO ELSE 0 END,
                CASE WHEN COALESCE(@VLRIMPCONSUMO,0)>0 THEN COALESCE(DBO.FNK_VALORVARIABLE('CTAIMPUESTOCONSUMO'),'') ELSE '' END,@IDBODEGA,@NOLOTEINTER
      END
      SET @ITEM=@ITEM+1
      FETCH NEXT FROM CUR_MOV
      INTO @IDARTICULO_CUR,@CANTIDAD_CUR,@VALOR_CUR,@NOLOTE_CUR,@PREFIJO_CUR,@CCOSTO_CUR,@IDAREA_CUR,
           @IDGRUPOIMP_CUR,@VLRDTO_CUR,@VLRIVA_CUR,@VLRNETO_CUR, @CODUNG, @CODPRG, @IDGRUPO, @IDIMPUESTO, @IDCLASE,@VLRIMPCONSUMO, @ESACTIVO,
           @ITAR_MIVA,@ITAR_CUEIVA,@IDBODEGA,@NOLOTEINTER, @FECHAVENCE_CUR, @PCOSTO_GRP
           
   END
   CLOSE CUR_MOV
   DEALLOCATE CUR_MOV
   PRINT 'VALIDO CUENTAS FINALES'
   IF EXISTS(SELECT * FROM FCXPD INNER JOIN CUE ON FCXPD.CUENTA_SER=CUE.CUENTA  
            WHERE FCXPD.CNSFCXP=@CNSFCXP AND COALESCE(FCXPD.VLR_IVA,0)>0 
            AND COALESCE(MCUEGRAV,0)=1)
   BEGIN
      UPDATE FCXPD SET CUENTA_SER=CUENTAGRAV
      FROM FCXPD INNER JOIN CUE ON FCXPD.CUENTA_SER=CUE.CUENTA  
            WHERE FCXPD.CNSFCXP=@CNSFCXP AND COALESCE(FCXPD.VLR_IVA,0)>0 
            AND COALESCE(MCUEGRAV,0)=1
   END
   IF EXISTS(SELECT * FROM FCXPD INNER JOIN ITAR ON FCXPD.PREFIJO=ITAR.IDITAR
             WHERE FCXPD.CNSFCXP=@CNSFCXP AND COALESCE(FCXPD.VLR_IVA,0)>0
             AND COALESCE(ITAR.CUE_IVA,'')<>''
             AND COALESCE(FCXPD.CUENTA_IVA,'')<>COALESCE(ITAR.CUE_IVA,''))
   BEGIN
      PRINT 'ERROR EN CUENTAS DE IVA, VOY A ACTUALIZAR'
      UPDATE FCXPD SET CUENTA_IVA=ITAR.CUE_IVA
      FROM FCXPD INNER JOIN ITAR ON FCXPD.PREFIJO=ITAR.IDITAR
                   WHERE FCXPD.CNSFCXP=@CNSFCXP AND COALESCE(FCXPD.VLR_IVA,0)>0
                   AND COALESCE(ITAR.CUE_IVA,'')<>''
                   AND COALESCE(FCXPD.CUENTA_IVA,'')<>COALESCE(ITAR.CUE_IVA,'')
   END

   UPDATE FCXPD SET CUENTA_IVA=NULL WHERE CNSFCXP=@CNSFCXP AND  COALESCE(VLR_IVA,0)<=0 AND COALESCE(CUENTA_IVA,'')<>''

   PRINT 'ACTUALIZO IEXI'
   UPDATE IEXI SET CUEDEBITO=FCXPD.CUENTA_SER,CUECREDITO=CASE WHEN COALESCE(CUE.MCUEREV,0)=1 THEN CUENTAREV ELSE FCXPD.CUENTA_SER END,
                    CUENTAIVA=FCXPD.CUENTA_IVA
   FROM FCXPD INNER JOIN IEXI ON FCXPD.IDBODEGA=IEXI.IDBODEGA AND FCXPD.IDSERVICIO=IEXI.IDARTICULO 
                                 AND IEXI.NOLOTEPEDIDO=FCXPD.NOLOTE
              INNER JOIN CUE ON FCXPD.CUENTA_SER=CUE.CUENTA
   WHERE FCXPD.CNSFCXP=@CNSFCXP
   AND IEXI.CNSFCOM=@CNSFCOM
   AND COALESCE(IEXI.CUEDEBITO,'')=''

   UPDATE FCXPD SET CUENTA_IVA=NULL 
   WHERE FCXPD.CNSFCXP=@CNSFCXP
   AND COALESCE(VLR_IVA,0)<=0
   AND COALESCE(CUENTA_IVA,'')<>''

   SELECT @VLR_FLETE = SUM(F.VLR_FLETE)
   FROM (SELECT DISTINCT CNSMOV, VLR_FLETE 
        FROM IMOV INNER JOIN FCXPD ON IMOV.CNSMOV=FCXPD.N_PRESUP
        WHERE FCXPD.CNSFCXP=@CNSFCXP) AS F
   
   IF @VLR_FLETE IS NULL 
   BEGIN
      SET @VLR_FLETE=0
   END
   
   IF @ITEM_ANT<>@ITEM
   BEGIN
      UPDATE FCXP 
      SET VALOR = X.VALORTOTAL, 
          SALDO = X.VLR_NETO+@VLR_FLETE-ISNULL(VLR_NOTASDEBITO,0)+ISNULL(VLR_NOTASCREDITO,0),
          VLR_DESCUENTO = X.VLR_DESCUENTO, 
          VLR_IVA = X.VLR_IVA,
          VLR_FLETE = @VLR_FLETE, 
          VLR_NETO = X.VLR_NETO+@VLR_FLETE
      FROM (SELECT SUM(VALOR * CANTIDAD) VALORTOTAL, SUM(VLR_NETO) VLR_NETO, SUM(VLR_DESCUENTO) VLR_DESCUENTO, SUM(VLR_IVA) VLR_IVA
            FROM FCXPD WHERE CNSFCXP=@CNSFCXP) X
      WHERE CNSFCXP=@CNSFCXP
   END
   UPDATE IMOVH SET ESTADO=1, ENCXP=1 WHERE CNSMOV=@CNSMOV AND ESTADO=9

   EXEC SPK_CALCULOVALORESCXP @CNSFCXP
   
	IF COALESCE(@PROCE,'')='COMPRAS' AND EXISTS (SELECT 1 FROM DOCXTPO WHERE TIPO='FCOM' AND NODOCUMENTO=@CNSFCOM)
	BEGIN
		--Borro posible Duplicidad
		DELETE FROM DOCXTPO WHERE TIPO='FCXP' AND NODOCUMENTO=@CNSFCXP

		INSERT INTO DOCXTPO (TIPO, NODOCUMENTO, IDAFILIADO, TIPODOC, FECHADOC, FECHA, USUARIO, SYS_ComputerName, RUTA, DESCRIPCION, ITEM, USUMARCA, MARCA, DOCUMENTOID)
