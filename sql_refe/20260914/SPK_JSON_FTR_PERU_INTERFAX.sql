CREATE OR ALTER PROCEDURE DBO.SPK_JSON_FTR_PERU_INTERFAX
@N_FACTURA  VARCHAR(20),
@MODO_PRUEBAS	INT=0,
@ENVIO_PORLOTE	INT=0
WITH ENCRYPTION
AS 
DECLARE 
 @JSON VARCHAR(MAX)
,@JSOND VARCHAR(MAX)                    ,@CODDOC VARCHAR(4)                      ,@PREFACT VARCHAR(4)                     ,@NFACTURA VARCHAR(20)
,@F_EMISION VARCHAR(10)                 ,@H_EMISION VARCHAR(8)                   ,@F_VENCE   VARCHAR(10)                  ,@TIPODOC   VARCHAR(2)
,@CODPAIS1  VARCHAR(3)                  ,@PERINICIAL  VARCHAR(10)                ,@PERFINAL  VARCHAR(10)                  ,@NOADMISION  VARCHAR(20)
,@GUIA1  VARCHAR(20)                    ,@TGUIA1 VARCHAR(2)                      ,@GUIA2  VARCHAR(20)                     ,@TGUIA2 VARCHAR(2)
,@NITEMISOR VARCHAR(20)                 ,@DVEMISIOR VARCHAR(1)                   ,@RAZONSOCIALEMI VARCHAR(125)            ,@CODPOSTALEMI VARCHAR(10)
,@DIRECCIOEMI VARCHAR(255)              ,@CIUDADEMI   VARCHAR(45)                ,@DEPAREMI   VARCHAR(45)                 ,@DISTRIEMI   VARCHAR(45)
,@PAISEMI   VARCHAR(2)                  ,@NITRECEP VARCHAR(20)                   ,@DVRECEP VARCHAR(1)                     ,@RAZONSOCIALRECEP VARCHAR(125)
,@CODPOSTALRECEP VARCHAR(10)            ,@DIRECCIORECEP VARCHAR(255)             ,@CIUDADRECEP   VARCHAR(45)              ,@DEPARRECEP   VARCHAR(45)
,@DISTRIRECEP  VARCHAR(45)              ,@PAISRECEP   VARCHAR(2)                 ,@CODSUNAT   VARCHAR(4)                  ,@VR_BRUTO DECIMAL(14,2)
,@VR_AFECTO DECIMAL(14,2)               ,@VR_INAFECTO DECIMAL(14,2)              ,@VR_COPAFECTO DECIMAL(14,2)             ,@VR_COPINAFECTO DECIMAL(14,2)
,@VR_IVA DECIMAL(14,2)                  ,@NOMBREI VARCHAR(1)                     ,@CODIMP  VARCHAR(4)                     ,@IMP     VARCHAR(4)
,@CODINTER VARCHAR(4)                   ,@VR_BRUTO1 DECIMAL(14,2)                ,@VR_NETO DECIMAL(14,2)                  ,@VR_IVA1 DECIMAL(14,2)
,@PVIVA   DECIMAL(7,2)                  ,@VR_LETRAS VARCHAR(2048)                ,@DNI   VARCHAR(20)                      ,@NOMBEPTE VARCHAR(120)
,@VRCOPAGO DECIMAL(14,2)                ,@LEYENDA VARCHAR(520)                   ,@OBSERVACION VARCHAR(255)               ,@NBOLE INT                              
,@B     INT                             ,@PORCO DECIMAL(7,4)                     ,@PORCOAFE DECIMAL(7,4)                  ,@PORCOINA DECIMAL(7,4)                  
,@ITEM VARCHAR(4)                        ,@CANTIDAD VARCHAR(4)
,@VALOR1 VARCHAR(20)                    ,@VALOR2 VARCHAR(20)                     ,@VALOR3 VARCHAR(20)                     ,@VALOR4 VARCHAR(20)
,@VALOR5 VARCHAR(20)                    ,@VALOR6 VARCHAR(20)                     ,@ANEXO VARCHAR(255)                     ,@REFERENCIA VARCHAR(20)
,@VALOR7 VARCHAR(20)                    ,@VALOR8 VARCHAR(20)                     ,@VALOR9 VARCHAR(20)                     
,@OK VARCHAR(10)                        ,@AFECTA SMALLINT                        ,@MIXTA BIT                              ,@FACTEP VARCHAR(10)
,@ERFACTEP VARCHAR(60)                  ,@ESPAQ BIT                              ,@TIPOFACT VARCHAR(2) --INDIVIDUAL,MASIVA 
,@CORRELATIVO VARCHAR(20)               ,@MAILRECEPTOR VARCHAR(256)              ,@USUARIOFACT VARCHAR(20)                 ,@NROITEM SMALLINT
,@TOKEN VARCHAR(50)                     ,@CODQR VARCHAR(100)                     ,@CODHASH VARCHAR(50)                     ,@ESTDOC  VARCHAR(10)
,@URLFACTEP VARCHAR(256)                ,@DESCSUNAT VARCHAR(MAX)                 ,@ERRORES VARCHAR(MAX)                    ,@sUrl VARCHAR(MAX) 
,@obj INT                               ,@valorDeRegreso INT                     ,@response NVARCHAR(MAX)                  ,@src VARCHAR(255)
,@desc VARCHAR(255)                     ,@URLFACT VARCHAR(255)                   ,@BODY VARCHAR(MAX)                       ,@PAQUETE BIT
,@DIASVENCE SMALLINT                    ,@F_FACTURA DATETIME                     ,@MNT_PENDIENTE VARCHAR(20)               ,@NCUOTAS SMALLINT
,@VLR_CUOTA DECIMAL(14,2)               ,@VLR_PENDIENTE DECIMAL(14,2)            ,@PROCEDENCIAFTR VARCHAR(20)              ,@CNSFCT VARCHAR(20)
,@TIPODOC_AFI VARCHAR(1)                ,@NOMBRES VARCHAR(60)                    ,@PAPELLIDO VARCHAR(100)                  ,@SAPELLIDO VARCHAR(100)
,@DIRECCION_AFI VARCHAR(40)             ,@TELEFONO_AFI VARCHAR(40)               ,@EMAIL_AFI VARCHAR(40)                   ,@PAIS_AFI VARCHAR(40)
,@CIUDAD_AFI VARCHAR(40)                ,@DISTRITO_AFI VARCHAR(40)               ,@SITTEDS VARCHAR(40)                     ,@PREFIJO VARCHAR(20)
,@NPREFIJO VARCHAR(120)                 ,@FECHAPRES VARCHAR(10)                  ,@IDPLAN VARCHAR(6)                       ,@USUMEDICO VARCHAR(20)
,@ESPECIALIDAD VARCHAR(10)				,@NOM_CIUDAD_AFI VARCHAR(45)             ,@NOM_DISTRITO_AFI VARCHAR(45)			   ,@VLR_IM_TOTA_BASE DECIMAL(14,2)
,@PK_VALE_PREFA VARCHAR(20)				,@TIPOPAGO VARCHAR(3)					 ,@ISPOS INT							   ,@IDCJFPAPOS VARCHAR (20)
,@IDKPAGE INT							,@RTA_IZIPAY NVARCHAR(MAX)				 ,@USUARIOCAJA VARCHAR(30)				   ,@CO_SECTOR VARCHAR(2)
,@IDAUT VARCHAR(13)						,@ISMAD INT								 ,@RAZONSOCIAL_ASEG VARCHAR(125)		   ,@DE_COMPANIA VARCHAR(125)
,@IDTERCEROPARTICULAR VARCHAR(20)		,@IDAFILIADO VARCHAR(20)				 ,@FE_INIC_VIGE VARCHAR(10)				   ,@FE_FINA_VIGE VARCHAR(10)
,@PC_COPAGO DECIMAL(14,2)				,@IM_DEDUCIBLE VARCHAR(10)			 ,@ESPART INT = 0						   ,@CO_POSTAL VARCHAR(20)
,@CO_CEBE VARCHAR(20)               ,@ESBOLETA INT = 0	                   ,@ESFACTURAPACIENTE INT = 0	   ,@ESFACTURAGARANTE INT = 0	,@CO_MECA_SAP VARCHAR(2) = '01', @CO_OF_VTA_SAP VARCHAR(4)
,@NO_TITULAR VARCHAR(250)           ,@IDMAD INT                      ,@NOADMI VARCHAR(20), @IM_PREC_BASE VARCHAR(10), @IM_BASE_ITEM VARCHAR(10), @IM_TOTA_BASE VARCHAR(10),@IM_COPAGO VARCHAR(10),@IM_REAL_GASTO VARCHAR(10)
,@NU_REME VARCHAR(20)   , @VALOR13 DECIMAL(14,5), @VALOR14 DECIMAL(14,5), @IM_TOTA_IGV  DECIMAL(14,2), @VLR_IM_PREC_BASE DECIMAL(14,2), @VLR_IM_BASE_ITEM DECIMAL(14,2), @PROCEFTRD VARCHAR(20) , @VLR_BASE_SINIGV_IM_BASE_ITEM DECIMAL(14,2)
,@USR_CAJ_MAD VARCHAR(30),@USR_CAJ_PHD VARCHAR(30),@USR_VCAJ_MAD VARCHAR(30),@USR_VCAJ_PHD VARCHAR(30),@USR_CAJ_CMV VARCHAR(30),@USR_VCAJ_CMV VARCHAR(30),@ISCV INT
DECLARE @VLR_AFECTO DECIMAL(14,2), @VLR_INAFECTO DECIMAL(14,2), @VLR_SUBTOTAL DECIMAL(14,2)  ,@VALOR10 DECIMAL(14,5), @VALOR11 DECIMAL(14,5), @AJUSTAR_VALOR BIT, @VALOR12 DECIMAL(14,5), @IM_COASEGURO VARCHAR(10), @CANT_DEDUCIBLE VARCHAR(10),@NOITEM SMALLINT
DECLARE @TIPO_TARJETA VARCHAR(10), @FECHA_TRANS VARCHAR(30), @DIGITOS_TARJETA VARCHAR(4), @FORMA_TARJETA CHAR(1),@NUMERO_REFERENCIA VARCHAR(20),@ID_TRANSACCION VARCHAR(50),@NOPRESTACION VARCHAR(20),@IDTERCERO VARCHAR(20),@MEC_FACT VARCHAR(10),@CANT_REME VARCHAR(20),@CNSCXC VARCHAR(20),@CO_SUB_MECA VARCHAR(20),@DESCPLAN VARCHAR(45)
DECLARE @BOLETA TABLE(N_FACTURA VARCHAR(20), VALOR DECIMAL(14,2),ID INT IDENTITY(1,1))
DECLARE @RPTA TABLE(ID INT,DATOS VARCHAR(500))
DECLARE @Intentos INT = 0
DECLARE @MaxIntentos INT = 2
DECLARE @NU_ENCUENTRO  VARCHAR(10), @CO_ESP_SAP  VARCHAR(10), @CO_ASEGURA VARCHAR(20),@PK_VALE_BOLETA VARCHAR(20), @PC_COASEGU VARCHAR(3) = ''

BEGIN  
	PRINT 'INGRESE A SPK_JSON_FTR_PERU_INTERFAX'
	PRINT '@MODO_PRUEBAS >'  + COALESCE(STR(@MODO_PRUEBAS),' SIN @MODO_PRUEBAS')

   SELECT @FACTEP=FTR.FACTEP,@CNSFCT=FTR.ID,@PK_VALE_PREFA=CONVERT(VARCHAR,CONCAT(CONVERT(INT,FTR.IDSEDE),CONVERT(INT,RIGHT(CNSFCT,LEN(FTR.IDSEDE)))),20),@ERFACTEP=RAZONANULACION,@CODDOC='0101',@PREFACT=REPLACE(FDIAN.PREFIJO,'-',''),@NFACTURA=FTR.N_FACTURA,@F_FACTURA=F_FACTURA,@F_EMISION=REPLACE(CONVERT(VARCHAR,F_FACTURA,102),'.',''),
   @H_EMISION=REPLACE(CONVERT(VARCHAR,F_FACTURA,108),'.',''),@F_VENCE= REPLACE(CONVERT(VARCHAR,F_VENCE,102),'.','-'),@TIPODOC= CASE WHEN TIPOFIN='N' THEN '03' ELSE '01' END,@CODPAIS1='PE',
   @PERINICIAL=REPLACE(CONVERT(VARCHAR,CAST('01/'+CASE WHEN MONTH(F_FACTURA)<10 THEN '0' ELSE '' END+CAST(MONTH(F_FACTURA) AS VARCHAR(2))+'/'+CAST(YEAR(F_FACTURA) AS VARCHAR(4))AS DATETIME),102),'.','-'),
   @PERFINAL=REPLACE(CONVERT(VARCHAR,CAST('01/'+CASE WHEN MONTH(F_FACTURA)<10 THEN '0' ELSE '' END+CAST(MONTH(F_FACTURA) AS VARCHAR(2))+'/'+CAST(YEAR(F_FACTURA) AS VARCHAR(4)) AS DATETIME)+29,102),'.','-'),
   @NOADMISION=FTR.NOREFERENCIA,@GUIA1='T001-00000001',@TGUIA1='09',@GUIA2='T001-00000002',@TGUIA2='99',
   @IDAFILIADO=FTR.IDAFILIADO,
   @DNI=CASE WHEN LEN( AFI.DOCIDAFILIADO)=8 THEN  AFI.DOCIDAFILIADO 
		     WHEN LEN(AFI.DOCIDAFILIADO)<8 THEN REPLACE(SPACE(8-LEN(AFI.DOCIDAFILIADO)),SPACE(1),0)+AFI.DOCIDAFILIADO
			 ELSE RIGHT(AFI.DOCIDAFILIADO,8)
	   END,
   @NOMBEPTE=dbo.FNK_LIMPIATEXTO(AFI.NOMBREAFI,'0-9 A-Z().;:,'),
   @NOMBRES=CONCAT(AFI.PNOMBRE,' ',COALESCE(AFI.SNOMBRE,'')),
   @PAPELLIDO=COALESCE(AFI.PAPELLIDO,''),
   @SAPELLIDO=COALESCE(AFI.SAPELLIDO,''),
   @DIRECCION_AFI=LEFT(COALESCE(dbo.FNK_LIMPIATEXTO(AFI.DIRECCION,'0-9 A-Z().;:,'),''),40),
   @TELEFONO_AFI=COALESCE(AFI.TELEFONORES,AFI.CELULAR,''),
   @EMAIL_AFI=COALESCE(AFI.EMAIL,''),
   --@PAIS_AFI=COALESCE(AFI.PA,''),
   @CIUDAD_AFI=COALESCE(AFI.CIUDAD,''),
   @NOM_CIUDAD_AFI=COALESCE(CIU.NOMBRE,''),
   @DISTRITO_AFI=COALESCE(AFI.CIUDAD,''),
   @NOM_DISTRITO_AFI=COALESCE(CIU.NOMBRE,''),
   @CO_POSTAL=COALESCE(AFI.CORREGIMIENTO,''),
   @VRCOPAGO=FTR.VALORCOPAGO,@AFECTA=CASE WHEN FTR.VIVA>0 THEN 1 ELSE 0 END,
   @TIPOFACT=FTR.TIPOFAC,@PAQUETE=COALESCE(PAQUETE,0),@USUARIOFACT=FTR.USUARIOFACTURA,
   @NCUOTAS=COALESCE(FTR.CUOTAS,1),@PROCEDENCIAFTR=FTR.PROCEDENCIA,
   @TIPODOC_AFI=CONVERT(VARCHAR(1),CONVERT(INT,COALESCE(TGEN.VALOR1,0))),
   @IDPLAN=FTR.IDPLAN,@DESCPLAN = PLN.DESCPLAN,@USUMEDICO='Pruebas Med',@ESPECIALIDAD='MEDICINA G',@IDTERCERO=FTR.IDTERCERO,
   @MEC_FACT=FTR.MEC_FACT
   FROM FTR INNER JOIN FDIAN ON FTR.CNSRESOL=FDIAN.CNSRESOL
            LEFT  JOIN AFI  ON FTR.IDAFILIADO=AFI.IDAFILIADO
			LEFT JOIN TGEN ON AFI.TIPO_DOC =TGEN.CODIGO AND TGEN.TABLA='General' AND TGEN.CAMPO='TIPOIDSUNAT'
			LEFT JOIN CIU ON CIU.CIUDAD = AFI.CIUDAD
			LEFT JOIN PLN ON PLN.IDPLAN = FTR.IDPLAN
   WHERE FTR.N_FACTURA=@N_FACTURA
   AND FDIAN.PROCEDENCIA=CASE WHEN FTR.TIPOFIN='N' THEN 'BOLE' ELSE 'FTR' END

   SELECT @USUMEDICO=COALESCE(MED.NOMBRE, ''),@ESPECIALIDAD=COALESCE(MES.DESCRIPCION, ''), @CO_ESP_SAP = COALESCE(MES.IDEMEDICA_ALTERNA,MES.IDEMEDICA)
   FROM FTR INNER JOIN FTRD ON FTRD.CNSFTR=FTR.CNSFCT
	INNER JOIN MED ON MED.IDMEDICO=FTRD.IDPROVEEDOR
	INNER JOIN MES ON MES.IDEMEDICA=MED.IDEMEDICA
   WHERE FTR.N_FACTURA=@N_FACTURA

   IF @PROCEDENCIAFTR IN ('MAD','CMV') AND @MEC_FACT IN ('CPM','MER')
	SELECT TOP 1 @NOADMISION=CAST(MAD.ID AS VARCHAR) FROM MAD WHERE MAD.N_FACTURA=@N_FACTURA
   ELSE IF @PROCEDENCIAFTR IN ('MAD','CMV') AND @MEC_FACT = 'PPS' AND TRY_CAST(@NOADMISION AS BIGINT) IS NULL
	SELECT TOP 1 @NOADMISION=CAST(MAD.ID AS VARCHAR) FROM MAD WHERE MAD.N_FACTURA_PPS=@N_FACTURA

   SELECT @CNSCXC = CNSCXC FROM FCXCD WHERE N_FACTURA = @N_FACTURA 
   SELECT @CANT_REME = COUNT(1) FROM FCXCD WHERE CNSCXC = @CNSCXC
   SELECT @NU_REME = 'Q' + RIGHT(YEAR(FCXC.FECHACXC), 2) + '-' + RIGHT(FCXC.CNSCXC, 6) FROM FCXC WHERE CNSCXC = @CNSCXC
   SELECT @CO_ASEGURA=@DNI

   SELECT @IDTERCEROPARTICULAR = DBO.FNK_VALORVARIABLE('IDTERCEROPARTICULAR')

   -- Usuarios caja SAP (USVGS). Si variable ausente o DATO vacío: compatibilidad con valores históricos.
   SELECT @USR_CAJ_MAD = COALESCE(NULLIF(LTRIM(RTRIM(CAST(DBO.FNK_VALORVARIABLE('USR_CAJ_MAD') AS VARCHAR(30)))), ''), 'MPEREIRA')
        , @USR_CAJ_PHD = COALESCE(NULLIF(LTRIM(RTRIM(CAST(DBO.FNK_VALORVARIABLE('USR_CAJ_PHD') AS VARCHAR(30)))), ''), 'RPAZ')
        , @USR_VCAJ_MAD = COALESCE(NULLIF(LTRIM(RTRIM(CAST(DBO.FNK_VALORVARIABLE('USR_VCAJ_MAD') AS VARCHAR(30)))), ''), 'UMAD_CAJERO_VIRTUAL')
        , @USR_VCAJ_PHD = COALESCE(NULLIF(LTRIM(RTRIM(CAST(DBO.FNK_VALORVARIABLE('USR_VCAJ_PHD') AS VARCHAR(30)))), ''), 'UPHD_CAJERO_VIRTUAL')
        , @USR_CAJ_CMV = COALESCE(NULLIF(LTRIM(RTRIM(CAST(DBO.FNK_VALORVARIABLE('USR_CAJ_CMV') AS VARCHAR(30)))), ''), 'WPIZARRO_3')
        , @USR_VCAJ_CMV = COALESCE(NULLIF(LTRIM(RTRIM(CAST(DBO.FNK_VALORVARIABLE('USR_VCAJ_CMV') AS VARCHAR(30)))), ''), 'UCMV_CAJERO_VIRTUAL')

   SET @ISCV = 0

   PRINT '@PROCEDENCIAFTR >'  + COALESCE(@PROCEDENCIAFTR,' SIN @PROCEDENCIAFTR')
   PRINT '@NOADMISION >'  + COALESCE(@NOADMISION,' SIN @NOADMISION')
   PRINT '@NU_REME >'  + COALESCE(@NU_REME,' SIN @NU_REME')

   IF @MODO_PRUEBAS = 1
   BEGIN
		SELECT @NU_REME = 'PRUEBAS', @CANT_REME='1'
   END

   IF @TIPODOC = '01'
   BEGIN
	   IF @PROCEDENCIAFTR IN ('MAD', 'SALUD', 'CMV')
         SET @ESFACTURAGARANTE = 1
      ELSE 
         SET @ESFACTURAPACIENTE = 1 
   END
   ELSE
   BEGIN
      SET @ESBOLETA = 1 
   END

   IF @ESFACTURAGARANTE = 1 AND COALESCE(@NU_REME,'')='' AND @MODO_PRUEBAS = 0
   BEGIN
		PRINT 'FACTURA NO ESTA RELACIONADA EN NINGUNA REMESA.'
		INSERT INTO FTRAPILOG(N_FACTURA,TIPODOC,ESTADOC,ERRORES,METODO,JSONSOLICITUD,JSONRESPUESTA)
		SELECT @N_FACTURA,@TIPODOC,'KO','FACTURA NO ESTA RELACIONADA EN NINGUNA REMESA. POR FAVOR VALIDE.','INTER_FTR',NULL,NULL
		RETURN
   END

   IF @PROCEDENCIAFTR IN ('CI', 'CE')
   BEGIN
		IF @PROCEDENCIAFTR = 'CE'
		BEGIN
			SELECT TOP 1 @IDAUT = IDAUT FROM AUTD WHERE NFACTURA = @N_FACTURA OR N_FACTURA = @N_FACTURA
			SELECT @ISMAD = CASE
				WHEN COALESCE(AUT.NOADMISION,'') <> '' THEN 0
				WHEN EXISTS(SELECT 1 FROM MAD INNER JOIN CIT ON CIT.IDMAD=MAD.ID INNER JOIN AUT ON AUT.CONSECUTIVOCIT=CIT.CONSECUTIVO) THEN 1 END
			FROM AUT WHERE IDAUT = @IDAUT

			IF @ISMAD = 1
			BEGIN
				SELECT @ISCV = CASE WHEN CIT.PROCEDENCIA = 'CV' THEN 1 ELSE 0 END
				FROM AUT INNER JOIN CIT ON CIT.CONSECUTIVO = AUT.CONSECUTIVOCIT
				WHERE AUT.IDAUT = @IDAUT

				IF @ISCV = 1
					SELECT @USUARIOCAJA = IIF(@ESFACTURAPACIENTE = 1, @USR_CAJ_CMV, @USR_VCAJ_CMV), @CO_SECTOR = 'B8'
				ELSE
					SELECT @USUARIOCAJA = IIF(@ESFACTURAPACIENTE = 1, @USR_CAJ_MAD, @USR_VCAJ_MAD), @CO_SECTOR = 'B4'
			END
			ELSE
				SELECT @USUARIOCAJA = IIF(@ESFACTURAPACIENTE = 1, @USR_CAJ_PHD, @USR_VCAJ_PHD), @CO_SECTOR = 'D6'
		END
		ELSE
		BEGIN
			SELECT @ISMAD = 1, @ISCV = CASE WHEN CIT.PROCEDENCIA = 'CV' THEN 1 ELSE 0 END
			FROM CIT WHERE CIT.N_FACTURA = @N_FACTURA

			IF @ISCV = 1
				SELECT @USUARIOCAJA = IIF(@ESFACTURAPACIENTE = 1, @USR_CAJ_CMV, @USR_VCAJ_CMV), @CO_SECTOR = 'B8'
			ELSE
				SELECT @USUARIOCAJA = IIF(@ESFACTURAPACIENTE = 1, @USR_CAJ_MAD, @USR_VCAJ_MAD), @CO_SECTOR = 'B4'
		END

		IF EXISTS (SELECT 1 FROM FTR WHERE NOREFERENCIA = @NOADMISION AND COALESCE(TIPOANULACION,'')<>'')
		BEGIN
			PRINT 'TIENE NOTA CREDITO ENVIO CON EL USUARIO DE CAJA Y NO EL VIRTUAL'
			IF @ISMAD = 1
			BEGIN
				IF @ISCV = 1
					SELECT @USUARIOCAJA = @USR_CAJ_CMV
				ELSE
					SELECT @USUARIOCAJA = @USR_CAJ_MAD
			END
			ELSE
				SELECT @USUARIOCAJA = @USR_CAJ_PHD
		END

		PRINT '@ISCV >'  + COALESCE(CAST(@ISCV AS VARCHAR),' SIN @ISCV')
		PRINT '@USUARIOCAJA >'  + COALESCE(@USUARIOCAJA,' SIN @USUARIOCAJA')
   END
   ELSE IF @PROCEDENCIAFTR IN ('MAD', 'CMV')
   BEGIN
		SELECT @ISMAD = 1
		IF @PROCEDENCIAFTR = 'CMV'
			SET @ISCV = 1
		ELSE
			SELECT @ISCV = CASE WHEN EXISTS(
				SELECT 1 FROM MAD INNER JOIN CIT ON CIT.IDMAD = MAD.ID
				WHERE CIT.PROCEDENCIA = 'CV'
				  AND (MAD.N_FACTURA = @N_FACTURA OR MAD.N_FACTURA_PPS = @N_FACTURA)
			) THEN 1 ELSE 0 END

		IF @ISCV = 1
			SELECT @USUARIOCAJA = IIF(@ESFACTURAPACIENTE = 1, @USR_CAJ_CMV, @USR_VCAJ_CMV), @CO_SECTOR = 'B8'
		ELSE
			SELECT @USUARIOCAJA = @USR_CAJ_MAD, @CO_SECTOR = 'B4'
   END
   ELSE IF @PROCEDENCIAFTR = 'SALUD'
		SELECT @USUARIOCAJA = @USR_CAJ_PHD, @CO_SECTOR = 'D6'
   ELSE IF @PROCEDENCIAFTR = 'HPREP'
	   SELECT @USUARIOCAJA = IIF(@ESFACTURAPACIENTE = 1, @USR_CAJ_PHD, @USR_VCAJ_PHD), @CO_SECTOR = 'D6'

	IF @ESFACTURAGARANTE = 1
   BEGIN
      SELECT @USUARIOCAJA = @USUARIOFACT
   END

   SELECT @CORRELATIVO= RIGHT(@N_FACTURA,LEN(@N_FACTURA)-(LEN(@PREFACT)+1))
   SELECT @NITEMISOR= NIT,@DVEMISIOR=6,@RAZONSOCIALEMI=dbo.FNK_LIMPIATEXTO(RAZONSOCIAL,'0-9 A-Z().;:,'),@CODPOSTALEMI='150101',@DIRECCIOEMI=DIRECCION,@CIUDADEMI=CIU.NOMBRE,
   @DEPAREMI=DEP.NOMBRE,@DISTRIEMI='',@PAISEMI='PE',@MAILRECEPTOR=COALESCE(TER.EMAIL,'')
   FROM TER LEFT JOIN CIU ON TER.CIUDAD=CIU.CIUDAD
           LEFT JOIN DEP ON CIU.DPTO =DEP.DPTO
   WHERE IDTERCERO=DBO.FNK_VALORVARIABLE('IDTERCEROINSTALADO')

   SELECT @NITRECEP=CASE WHEN FTR.IDTERCERO=FTR.IDAFILIADO AND COALESCE(TER.RUC,'')<> '' AND FTR.TIPOFIN='C' THEN RUC ELSE NIT END ,
          @DVRECEP=CASE WHEN FTR.IDTERCERO=FTR.IDAFILIADO AND COALESCE(TER.RUC,'')<> '' AND FTR.TIPOFIN='C'  THEN 6 ELSE CONVERT(VARCHAR(1),CONVERT(INT,COALESCE(TGEN.VALOR1,0))) END,
          @RAZONSOCIALRECEP=dbo.FNK_LIMPIATEXTO(RAZONSOCIAL,'0-9 A-Z().;:,'),@CODPOSTALRECEP='150101',@DIRECCIORECEP= dbo.FNK_LIMPIATEXTO(DIRECCION,'0-9 A-Z().;:,'),@CIUDADRECEP=CIU.NOMBRE,
   @DEPARRECEP=DEP.NOMBRE,@DISTRIRECEP='',@PAISRECEP='PE',@CODSUNAT='0000'
   FROM FTR INNER JOIN TER ON FTR.IDTERCERO=TER.IDTERCERO
            LEFT JOIN CIU ON TER.CIUDAD=CIU.CIUDAD
            LEFT JOIN DEP ON CIU.DPTO =DEP.DPTO
            LEFT JOIN TGEN ON TER.TIPO_ID =TGEN.CODIGO AND TGEN.TABLA='General' AND TGEN.CAMPO='TIPOIDSUNAT'
   WHERE FTR.N_FACTURA=@N_FACTURA

   IF @DVRECEP='1' AND LEN(@NITRECEP)<>8
   BEGIN
	  SELECT @NITRECEP=CASE WHEN LEN(@NITRECEP)=8 THEN  @NITRECEP
		     WHEN LEN(@NITRECEP)<8 THEN REPLACE(SPACE(8-LEN(@NITRECEP)),SPACE(1),0)+@NITRECEP
			 ELSE RIGHT(@NITRECEP,8) END
   END

   SELECT @LEYENDA='SITEDS:'+CAST(COALESCE(dbo.FNK_LIMPIATEXTO(VENDEDOR,'0-9 A-Z'),'') AS VARCHAR(20)),@SITTEDS=CAST(COALESCE(dbo.FNK_LIMPIATEXTO(VENDEDOR,'0-9 A-Z'),'') AS VARCHAR(20))
   FROM FTR WHERE N_FACTURA=@N_FACTURA

   SELECT @ESPAQ= CASE WHEN COUNT(*)>0 THEN 1 ELSE 0 END FROM FTRD WHERE N_FACTURA=@N_FACTURA AND COALESCE(PAQUETE,0)=2

