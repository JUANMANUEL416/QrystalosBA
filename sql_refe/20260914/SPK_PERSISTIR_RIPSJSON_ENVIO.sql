CREATE OR ALTER PROCEDURE DBO.SPK_PERSISTIR_RIPSJSON_ENVIO
	@TIPODOC VARCHAR(20),
	@CNSDOC VARCHAR(20),
	@JSON_ENVIO NVARCHAR(MAX)
AS
BEGIN
	SET NOCOUNT ON;
	DECLARE @CLASE CHAR(1);

	IF COALESCE(@JSON_ENVIO, N'') = N''
		OR COALESCE(@CNSDOC, N'') = N''
		RETURN;

	/* Facturas (FV): FTRJSON por CNSFCT */
	IF UPPER(LTRIM(RTRIM(@TIPODOC))) = N'FACTURA'
	BEGIN
		IF NOT EXISTS (SELECT 1 FROM DBO.FTRJSON WHERE CNSFCT = @CNSDOC)
			INSERT INTO DBO.FTRJSON (CNSFCT, JSON_ENVIO)
			VALUES (@CNSDOC, @JSON_ENVIO);
		ELSE
			UPDATE DBO.FTRJSON
			SET JSON_ENVIO = @JSON_ENVIO
			WHERE CNSFCT = @CNSDOC;

		RETURN;
	END

	/* Notas CR/DB y notas de ajuste: FNOTJSON por CNSFNOT + CLASE */
	SET @CLASE = CASE UPPER(LTRIM(RTRIM(@TIPODOC)))
		WHEN N'NOTACR' THEN N'C'
		WHEN N'NOTADB' THEN N'D'
		WHEN N'AJUSTE' THEN N'A'
		ELSE NULL
	END;

	IF @CLASE IS NULL
		RETURN;

	IF NOT EXISTS (
		SELECT 1
		FROM DBO.FNOTJSON
		WHERE CNSFNOT = @CNSDOC
		  AND CLASE = @CLASE
	)
		INSERT INTO DBO.FNOTJSON (CNSFNOT, CLASE, JSON_ENVIO)
		VALUES (@CNSDOC, @CLASE, @JSON_ENVIO);
	ELSE
		UPDATE DBO.FNOTJSON
		SET JSON_ENVIO = @JSON_ENVIO
		WHERE CNSFNOT = @CNSDOC
		  AND CLASE = @CLASE;
END

