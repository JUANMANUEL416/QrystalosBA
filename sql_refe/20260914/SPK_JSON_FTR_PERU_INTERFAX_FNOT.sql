CREATE OR ALTER PROCEDURE DBO.SPK_JSON_FTR_PERU_INTERFAX_FNOT
@CNSFNOT  VARCHAR(20),
@N_FACTURA  VARCHAR(20),
@MODO_PRUEBAS	INT=0
WITH ENCRYPTION
AS 
DECLARE 
 @JSON VARCHAR(MAX)
,@JSOND VARCHAR(MAX)                    ,@CODDOC VARCHAR(4)                      ,@PREFACT VARCHAR(4)                     ,@NFACTURA VARCHAR(20)
,@PK_PREABO VARCHAR(20)                 ,@NU_PREABO VARCHAR(20)                  ,@PK_PREFA_ORIG VARCHAR(20)              ,@NU_PREFA_ORIG VARCHAR(20)
,@NU_COMP_SUNAT VARCHAR(20)             ,@CO_MOTI_SAP VARCHAR(20)                ,@IM_TOTA_BASE VARCHAR(20)               ,@IM_TOTA_IGV VARCHAR(20)
,@IM_TOTAL VARCHAR(20)                  ,@CO_USUA_TRAN VARCHAR(20)               ,@CO_USUA_REM VARCHAR(20)                ,@NU_REME VARCHAR(20)
,@CAN_REM VARCHAR(20)                   ,@FEC_PRE_ABONO VARCHAR(20)              ,@BODY VARCHAR(MAX)                      ,@TIPOFNOT VARCHAR(10)
,@TIPODOC VARCHAR(4)                    ,@CNSDOCUMENTO VARCHAR(20)               ,@COMPANIA VARCHAR(2)                    ,@IDSEDE VARCHAR(6)
,@TIPODOCREL VARCHAR(2)                 ,@ID_ITEM_PREABO VARCHAR(20)
,@PK_VALE_PREABO VARCHAR(20)            ,@IM_BASE_ITEM VARCHAR(20)               ,@CO_PRES_ITEM VARCHAR(20)               ,@DE_PRES_ITEM VARCHAR(20)
,@CA_ITEM VARCHAR(20)                   ,@PC_IGV VARCHAR(20)                     ,@CO_SUB_MECA VARCHAR(20)                ,@CO_TIPO_ITEM VARCHAR(20)
,@CONTADOR INT                          ,@OK VARCHAR(4)                          ,@sUrl VARCHAR(2049)                     ,@response VARCHAR(MAX)
,@PROCEDENCIAFTR VARCHAR(20)			,@ISMAD INT								 ,@IDAUT VARCHAR(13)
,@ESBOLETA INT = 0	                   ,@ESFACTURAPACIENTE INT = 0	   ,@ESFACTURAGARANTE INT = 0
,@MEC_FACT VARCHAR(10),@CNSCXC VARCHAR(20), @PROCEFTRD VARCHAR(20),@ANEXO VARCHAR(255),@REFERENCIA VARCHAR(20),@PK_VALE_PREFA VARCHAR(20),@PK_VALE_BOLETA VARCHAR(20),@NOPRESTACION VARCHAR(20),@NOITEM SMALLINT
,@USR_CAJ_MAD VARCHAR(30),@USR_CAJ_PHD VARCHAR(30),@USR_VCAJ_MAD VARCHAR(30),@USR_VCAJ_PHD VARCHAR(30),@USR_CAJ_CMV VARCHAR(30),@USR_VCAJ_CMV VARCHAR(30),@ISCV INT, @NOADMISION VARCHAR(20)
BEGIN

   PRINT '@MODO_PRUEBAS >'  + COALESCE(STR(@MODO_PRUEBAS),' SIN @MODO_PRUEBAS')

   -- Usuarios caja SAP (USVGS). Si variable ausente o DATO vacío: compatibilidad con valores históricos.
   SELECT @USR_CAJ_MAD = COALESCE(NULLIF(LTRIM(RTRIM(CAST(DBO.FNK_VALORVARIABLE('USR_CAJ_MAD') AS VARCHAR(30)))), ''), 'MPEREIRA')
        , @USR_CAJ_PHD = COALESCE(NULLIF(LTRIM(RTRIM(CAST(DBO.FNK_VALORVARIABLE('USR_CAJ_PHD') AS VARCHAR(30)))), ''), 'RPAZ')
        , @USR_VCAJ_MAD = COALESCE(NULLIF(LTRIM(RTRIM(CAST(DBO.FNK_VALORVARIABLE('USR_VCAJ_MAD') AS VARCHAR(30)))), ''), 'UMAD_CAJERO_VIRTUAL')
        , @USR_VCAJ_PHD = COALESCE(NULLIF(LTRIM(RTRIM(CAST(DBO.FNK_VALORVARIABLE('USR_VCAJ_PHD') AS VARCHAR(30)))), ''), 'UPHD_CAJERO_VIRTUAL')
        , @USR_CAJ_CMV = COALESCE(NULLIF(LTRIM(RTRIM(CAST(DBO.FNK_VALORVARIABLE('USR_CAJ_CMV') AS VARCHAR(30)))), ''), 'WPIZARRO_3')
        , @USR_VCAJ_CMV = COALESCE(NULLIF(LTRIM(RTRIM(CAST(DBO.FNK_VALORVARIABLE('USR_VCAJ_CMV') AS VARCHAR(30)))), ''), 'UCMV_CAJERO_VIRTUAL')

   SET @ISCV = 0

   IF EXISTS(SELECT  * FROM FNOT WHERE CNSFNOT=@CNSFNOT AND N_FACTURA=@N_FACTURA AND COALESCE(CNSDIANFE,'')='')
   BEGIN
      SELECT @TIPODOC=(CASE FNOT.CLASE WHEN 'C' THEN '07' WHEN 'D' THEN '08' ELSE '' END),@IDSEDE=FTR.IDSEDE, @COMPANIA='01',
      @TIPODOCREL= CASE WHEN FTR.TIPOFIN='N' THEN '03' ELSE '01' END, @PROCEDENCIAFTR=FTR.PROCEDENCIA,
	  @MEC_FACT=FTR.MEC_FACT,@NOADMISION=FTR.NOREFERENCIA
      FROM FNOT INNER JOIN FTR ON FNOT.N_FACTURA=FTR.N_FACTURA
      WHERE  CNSFNOT=@CNSFNOT 
      AND FTR.N_FACTURA=@N_FACTURA
      
      IF @TIPODOCREL = '01'
      BEGIN
	      IF @PROCEDENCIAFTR IN ('MAD', 'SALUD', 'CMV')
            SET @ESFACTURAGARANTE = 1
         ELSE 
            SET @ESFACTURAPACIENTE = 1 
      END
      ELSE
      BEGIN
         SET @ESBOLETA = 1 
      END

      SET @TIPOFNOT=(CASE @TIPODOC WHEN '07' THEN IIF(@ESBOLETA = 1 OR @ESFACTURAPACIENTE = 1,'NCB','NCF') WHEN '08' THEN IIF(@ESBOLETA = 1 OR @ESFACTURAPACIENTE = 1,'NDB','NDF') END)
      SET @CNSDOCUMENTO = SPACE(20)
      PRINT '@COMPANIA= '+COALESCE(@COMPANIA,'SIN CIA')+'@IDSEDE '+COALESCE(@IDSEDE,'SIN SEDE')+'@TIPOFNOT ='+COALESCE(@TIPOFNOT,'SINTIPONC')
      EXEC SPK_GENNUMEROFACTURA @COMPANIA, @IDSEDE, NULL, @CNSDOCUMENTO OUTPUT, @TIPOFNOT
      PRINT 'REGRESO DE SPK_GENNUMEROFACTURA '
      UPDATE FNOT SET CNSDIANFE=@CNSDOCUMENTO WHERE CNSFNOT=@CNSFNOT AND N_FACTURA=@N_FACTURA

   END

   PRINT '@NOADMISION >'  + COALESCE(@NOADMISION,' SIN @NOADMISION')

   IF @PROCEDENCIAFTR IN ('CI', 'CE')
   BEGIN
		IF @PROCEDENCIAFTR = 'CE'
		BEGIN
			SELECT @ISMAD = CASE
				WHEN COALESCE(AUT.NOADMISION,'') <> '' THEN 0
				WHEN EXISTS(SELECT 1 FROM MAD INNER JOIN CIT ON CIT.IDMAD=MAD.ID INNER JOIN AUT ON AUT.CONSECUTIVOCIT=CIT.CONSECUTIVO) THEN 1 END
			FROM AUT WHERE IDAUT = @NOADMISION

			IF @ISMAD = 1
			BEGIN
				SELECT @ISCV = CASE WHEN CIT.PROCEDENCIA = 'CV' THEN 1 ELSE 0 END
				FROM AUT INNER JOIN CIT ON CIT.CONSECUTIVO = AUT.CONSECUTIVOCIT
				WHERE AUT.IDAUT = @NOADMISION

				IF @ISCV = 1
					SELECT @CO_USUA_TRAN = @USR_CAJ_CMV
				ELSE
					SELECT @CO_USUA_TRAN = @USR_CAJ_MAD
			END
			ELSE
				SELECT @CO_USUA_TRAN = @USR_CAJ_PHD
		END
		ELSE
		BEGIN
			SELECT @ISCV = CASE WHEN CIT.PROCEDENCIA = 'CV' THEN 1 ELSE 0 END
			FROM CIT WHERE CIT.CONSECUTIVO = @NOADMISION

			IF @ISCV = 1
				SELECT @CO_USUA_TRAN = @USR_CAJ_CMV
			ELSE
				SELECT @CO_USUA_TRAN = @USR_CAJ_MAD
		END
   END
   ELSE
   BEGIN
		SELECT @CO_USUA_TRAN = @USR_CAJ_PHD
   END

   PRINT '@ISMAD >'  + COALESCE(CAST(@ISMAD AS VARCHAR),' SIN @ISMAD')
   PRINT '@ISCV >'  + COALESCE(CAST(@ISCV AS VARCHAR),' SIN @ISCV')

    SELECT @PK_PREABO=FNOT.ID,@NU_PREABO=FNOT.CNSDIANFE,@NU_PREFA_ORIG=FNOT.N_FACTURA,@NU_COMP_SUNAT=COALESCE(FTR.N_FACT_EXTERNO,''),
    @CO_MOTI_SAP='06',@IM_TOTA_BASE= CAST(SUM(FNOTD.VR_TOTAL-CASE WHEN COALESCE(FNOTD.PIVA,0)>0 THEN FNOTD.VALORIVA ELSE 0 END) AS VARCHAR(20)),
    @IM_TOTA_IGV=CAST(SUM(CASE WHEN COALESCE(FNOTD.PIVA,0)>0 THEN FNOTD.VALORIVA ELSE 0 END)AS VARCHAR(20)),
    @IM_TOTAL=CAST(FNOT.VR_TOTAL AS VARCHAR(20)),
    --@CO_USUA_TRAN=FNOT.USUARIO,
    @NU_REME='',
    @CAN_REM='',
	 @PK_VALE_PREABO=CONVERT(VARCHAR,CONCAT(CONVERT(INT,FTR.IDSEDE),CONVERT(INT,RIGHT(CNSFCT,LEN(FTR.IDSEDE)))),20),
    @FEC_PRE_ABONO=REPLACE(CONVERT(VARCHAR,FNOT.F_NOTA,102),'.',''),
    @PK_PREFA_ORIG=FTR.ID
    FROM FNOT INNER JOIN FNOTD ON FNOT.CNSFNOT=FNOTD.CNSFNOT
              INNER JOIN FTR ON FNOT.N_FACTURA=FTR.N_FACTURA
    WHERE FNOT.CNSFNOT= @CNSFNOT
    AND FNOT.N_FACTURA= @N_FACTURA
    GROUP BY FNOT.ID,FNOT.CNSDIANFE,FNOT.N_FACTURA,
    FNOT.VR_TOTAL,
    FNOT.USUARIO,
	FTR.N_FACT_EXTERNO,
	CONVERT(VARCHAR,CONCAT(CONVERT(INT,FTR.IDSEDE),CONVERT(INT,RIGHT(CNSFCT,LEN(FTR.IDSEDE)))),20),
    REPLACE(CONVERT(VARCHAR,FNOT.F_NOTA,102),'.',''),
    FTR.ID

	-- Boletas paciente CE/HPREP: totales del preabono alineados a la prefactura (FTR)
	IF @ESFACTURAGARANTE = 0 AND @PROCEDENCIAFTR IN ('CE','HPREP')
	BEGIN
		SELECT @IM_TOTA_BASE = CAST(FTR.VALOR_SERVICIOS_SIN_IGV AS VARCHAR(20)),
			   @IM_TOTA_IGV = CAST(COALESCE(FTR.VIVA,0) AS VARCHAR(20)),
			   @IM_TOTAL = CAST(FTR.VR_TOTAL AS VARCHAR(20))
		FROM FTR
		WHERE FTR.N_FACTURA = @N_FACTURA
	END

	IF @ESFACTURAGARANTE = 1
	BEGIN
		SELECT @CNSCXC = CNSCXC FROM FNOT WHERE CNSFNOT = @CNSFNOT 
		SELECT @CAN_REM = COUNT(1) FROM FCXCD WHERE CNSCXC = @CNSCXC
		SELECT @NU_REME = 'Q' + RIGHT(YEAR(GETDATE()), 2) + '-' + RIGHT(@CNSCXC, 6)
		SELECT @CO_USUA_REM = USUARIO FROM FCXC WHERE CNSCXC = @CNSCXC
		SELECT @CO_USUA_TRAN=@CO_USUA_REM,@PK_VALE_PREABO=''

		SELECT @CO_MOTI_SAP = IDCAUANULACION FROM FTR WHERE N_FACTURA = @N_FACTURA

		IF @PROCEDENCIAFTR IN ('MAD','CMV')
			SET @CO_SUB_MECA = IIF(@MEC_FACT = 'CPM','200','114')   -- 200 CPM; 114 PPS/MER MAD-CMV; PHD 115
	END

	IF @MODO_PRUEBAS = 1
	BEGIN
		SELECT @NU_REME = 'PRUEBAS', @CAN_REM='1'
	END

	SELECT @CONTADOR =0
   SELECT @JSON='{ '
   SELECT @JSON=@JSON+' "EPreabono":{ '
   SELECT @JSON=@JSON+'"PK_PREABO":"QA'+@PK_PREABO+'",'
   SELECT @JSON=@JSON+'"NU_PREABO":"'+@PK_PREABO+'",'
   SELECT @JSON=@JSON+'"PK_PREFA_ORIG":"QP'+@PK_PREFA_ORIG+'",'
   SELECT @JSON=@JSON+'"NU_PREFA_ORIG":"'+@NU_PREFA_ORIG+'",'
   SELECT @JSON=@JSON+'"NU_COMP_SUNAT":"'+@NU_COMP_SUNAT+'",'
   SELECT @JSON=@JSON+'"CO_MOTI_SAP":"'+@CO_MOTI_SAP+'",'
   SELECT @JSON=@JSON+'"IM_TOTA_BASE":"'+@IM_TOTA_BASE+'",'
   SELECT @JSON=@JSON+'"IM_TOTA_IGV":"'+@IM_TOTA_IGV+'",'
   SELECT @JSON=@JSON+'"IM_TOTAL":"'+@IM_TOTAL+'",'
   SELECT @JSON=@JSON+'"CO_USUA_TRAN":"'+@CO_USUA_TRAN+'",'	
   SELECT @JSON=@JSON+'"CO_USUA_REM":"'+COALESCE(@CO_USUA_REM,'')+'",'
   SELECT @JSON=@JSON+'"NU_REME":"'+@NU_REME+'",'
   SELECT @JSON=@JSON+'"CAN_REM":"'+@CAN_REM+'",'
   SELECT @JSON=@JSON+'"FEC_PRE_ABONO":"'+@FEC_PRE_ABONO+'",'
   IF @ESFACTURAGARANTE = 1
      SELECT @JSON=@JSON+'"ID_SYS": "QH",'

   PRINT @JSON

   SELECT @JSON=@JSON+' "EPreabonoDetalle": [ '
   PRINT 'DETALLES DE LA NOTA' --FNOTD

   IF @ESFACTURAGARANTE = 1 AND @PROCEDENCIAFTR IN ('MAD','CMV') AND @MEC_FACT = 'CPM'
   BEGIN
		PRINT '----------------------------------------------------------------------'
		PRINT 'ES FACT. GARANTE MAD/CMV - CPM'
		DECLARE @VECES INT = 1;
		SET @CA_ITEM='1'
		
		WHILE @VECES <= 3
		BEGIN
			PRINT '@VECES >'  + COALESCE(CAST(@VECES AS VARCHAR),' SIN @VECES')
			SELECT @ANEXO= dbo.FNK_LIMPIATEXTO(CASE WHEN COALESCE(SER.DESCRIPCION_CUPS,'')='' THEN SER.DESCSERVICIO ELSE SER.DESCRIPCION_CUPS END,'0-9 A-Z'), 
               @REFERENCIA=dbo.FNK_LIMPIATEXTO(COALESCE(SER.IDSERVICIO,FTRD.REFERENCIA),'0-9 A-Z'),
			   @PC_IGV=CONVERT(VARCHAR(20),CONVERT(INT,COALESCE(PIVA,0)))
			FROM FTRD 
			LEFT JOIN SER ON SER.IDSERVICIO=DBO.FNK_VALORVARIABLE('MAD_SER_HOMCPMTRAMA')
			LEFT JOIN PRE ON SER.PREFIJO=PRE.PREFIJO
			WHERE N_FACTURA=@N_FACTURA AND FTRD.PAQUETE = 0

			IF @VECES = 1
			BEGIN
				SET @IM_BASE_ITEM = @IM_TOTA_BASE -- @IM_TOTAL
			END
			ELSE IF @VECES = 2
			BEGIN
				SET @IM_BASE_ITEM = '-' + @IM_TOTA_BASE -- @IM_TOTAL
			END
			ELSE
			BEGIN
				SELECT @IM_BASE_ITEM = '0', @PC_IGV = '0'
			END

			SELECT @JSON=@JSON+' { '
			SELECT @JSON=@JSON+'"PK_PREABO":"QA'+@PK_PREABO+'",'
			SELECT @JSON=@JSON+'"NU_PREABO":"'+@PK_PREABO+'",'
			SELECT @JSON=@JSON+'"ID_ITEM_PREABO":"'+CAST(@VECES AS VARCHAR(10))+'0",'
			SELECT @JSON=@JSON+'"PK_VALE_PREABO":"'+@PK_VALE_PREABO+'",'
			SELECT @JSON=@JSON+'"IM_BASE_ITEM":"'+@IM_BASE_ITEM+'",'
			SELECT @JSON=@JSON+'"CO_PRES_ITEM":"'+@REFERENCIA+'",'
			SELECT @JSON=@JSON+'"DE_PRES_ITEM":"'+@ANEXO+'",'
			SELECT @JSON=@JSON+'"CA_ITEM":"'+@CA_ITEM+'",'
			SELECT @JSON=@JSON+'"PC_IGV":"'+@PC_IGV+'",'
			--SELECT @JSON=@JSON+'"CO_SUB_MECA":"'+@CO_SUB_MECA+'",'
			SELECT @JSON=@JSON+'"CO_SUB_MECA":"",'
			SELECT @JSON=@JSON+'"CO_TIPO_ITEM":"I"'   
			SELECT @JSON=@JSON+'   '
			IF @VECES < 3
				SELECT @JSON=@JSON+' }, '
			ELSE
				SELECT @JSON=@JSON+' } '

			PRINT '@JSOND > ' + @JSON

			SET @VECES += 1;
		END

		SELECT @CONTADOR=3
   END

   IF @ESFACTURAGARANTE = 1 AND @PROCEDENCIAFTR IN ('MAD','CMV') AND @MEC_FACT IN ('PPS','MER')
   BEGIN
		PRINT '----------------------------------------------------------------------'
		PRINT 'ES FACT. GARANTE MAD/CMV - PPS/MER'

		SELECT @NOPRESTACION = FTRD.NOPRESTACION,@NOITEM=NOITEM
		FROM FTRD
		WHERE N_FACTURA=@N_FACTURA AND PAQUETE = 0

		SET @PK_VALE_PREFA=RIGHT(@NOPRESTACION, 9) + CONVERT(VARCHAR(20), @NOITEM)

		SELECT @PK_VALE_PREABO=CONVERT(VARCHAR,CONCAT(CONVERT(INT,FTR.IDSEDE),CONVERT(INT,RIGHT(CNSFCT,LEN(FTR.IDSEDE)))),20)
		FROM FTR WHERE NOREFERENCIA = @NOPRESTACION

		PRINT '@PK_VALE_PREABO >'  + COALESCE(@PK_VALE_PREABO,' SIN @PK_VALE_PREABO')

		IF COALESCE(@PK_VALE_PREABO,'') = ''
		BEGIN
			SET @PK_VALE_PREABO = @PK_VALE_PREFA
		END

   END


   DECLARE @N_CUOTA INT 
   DECLARE XMLFNOTD_CURSOR CURSOR FOR
   SELECT ITEM  FROM FNOTD WHERE CNSFNOT=@CNSFNOT AND N_FACTURA=@N_FACTURA
   AND COALESCE(FNOTD.VR_TOTAL,0)>0
   ORDER BY ITEM ASC
   OPEN XMLFNOTD_CURSOR    
   FETCH NEXT FROM XMLFNOTD_CURSOR    
   INTO @N_CUOTA
   WHILE @@FETCH_STATUS = 0    
   BEGIN 
      SELECT @CONTADOR=@CONTADOR+1
      IF @CONTADOR>1
      BEGIN
         SELECT @JSON=@JSON+' , '
      END
      SELECT @ID_ITEM_PREABO=CAST((@CONTADOR*10) AS varchar(20)),@IM_BASE_ITEM=CAST(VR_TOTAL AS varchar(20)),
      @CO_PRES_ITEM=dbo.FNK_LIMPIATEXTO(FNOTD.IDSERVICIO,'0-9 A-Z'),@DE_PRES_ITEM=dbo.FNK_LIMPIATEXTO(FNOTD.DESCRIPCION,'0-9 A-Z().;:,'),
      @CA_ITEM=CAST(FNOTD.CANTIDAD AS VARCHAR(20)),
      @PC_IGV=CAST(CASE WHEN  FNOTD.PIVA>0 THEN FNOTD.PIVA ELSE 0 END AS VARCHAR(20)),
      @CO_SUB_MECA='', @CO_TIPO_ITEM='I'
      FROM FNOTD LEFT JOIN SER ON FNOTD.IDSERVICIO=SER.IDSERVICIO AND FNOTD.TIPO='S'
                 LEFT JOIN CPNT ON FNOTD.IDSERVICIO=CPNT.CODIGO AND FNOTD.TIPO='C'
      WHERE CNSFNOT=@CNSFNOT
      AND N_FACTURA=@N_FACTURA
      AND N_CUOTA=@N_CUOTA

		IF @PROCEDENCIAFTR IN ('CE','HPREP') AND @ESFACTURAGARANTE = 0
		BEGIN
			SELECT @IM_BASE_ITEM = CAST(COALESCE(FTRD.VALOR_COPAGO_TOTAL_SIN_IGV,0) AS VARCHAR(20)),
				   @CA_ITEM = CAST(CONVERT(INT, CEILING(FTRD.CANTIDAD)) AS VARCHAR(20))
			FROM FTRD
			WHERE FTRD.N_FACTURA = @N_FACTURA
			AND FTRD.N_CUOTA = @N_CUOTA
		END

	  IF @ESFACTURAGARANTE = 1
	  BEGIN
		IF @MEC_FACT = 'CPM'
			SET @IM_BASE_ITEM = '0'
		ELSE
			SET @IM_BASE_ITEM = @IM_TOTA_BASE
	  END 
		

      SELECT @JSON=@JSON+'{ '
      SELECT @JSON=@JSON+'"PK_PREABO":"QA'+@PK_PREABO+'",'
      SELECT @JSON=@JSON+'"NU_PREABO":"'+@PK_PREABO+'",'
      SELECT @JSON=@JSON+'"ID_ITEM_PREABO":"'+@ID_ITEM_PREABO+'",'
      SELECT @JSON=@JSON+'"PK_VALE_PREABO":"'+@PK_VALE_PREABO+'",'
      SELECT @JSON=@JSON+'"IM_BASE_ITEM":"'+@IM_BASE_ITEM+'",'
      SELECT @JSON=@JSON+'"CO_PRES_ITEM":"'+@CO_PRES_ITEM+'",'
      SELECT @JSON=@JSON+'"DE_PRES_ITEM":"'+@DE_PRES_ITEM+'",'
      SELECT @JSON=@JSON+'"CA_ITEM":"'+@CA_ITEM+'",'
      SELECT @JSON=@JSON+'"PC_IGV":"'+@PC_IGV+'",'
      SELECT @JSON=@JSON+'"CO_SUB_MECA":"'+@CO_SUB_MECA+'",'
      SELECT @JSON=@JSON+'"CO_TIPO_ITEM":"'+@CO_TIPO_ITEM+'"'
           
      SELECT @JSON=@JSON+'}'


	   FETCH NEXT FROM XMLFNOTD_CURSOR    
	   INTO @N_CUOTA
   END
   CLOSE XMLFNOTD_CURSOR
   DEALLOCATE XMLFNOTD_CURSOR

	SELECT @JSON=LTRIM(RTRIM(@JSON)) +' ] } }'

   PRINT @JSON

   IF LEN(@JSON)<10
   BEGIN
      PRINT 'NO TENGO DATOS'
      RETURN
   END

  PRINT 'DEFINITIVO'
  PRINT '@JSON DEFINITIVO > '  + COALESCE(@JSON,' SIN @JSON')

  SELECT @BODY=@JSON
  IF @ESBOLETA = 1 OR @ESFACTURAPACIENTE = 1 -- BOLETA
  BEGIN
      SELECT @sUrl='/FacturacionPaciente/AbonoPacienteEM'
  END
  ELSE
  BEGIN
      SELECT @sUrl='/FacturacionGarante/AbonoGaranteEM'
  END

  PRINT '@sUrl >'  + COALESCE(@sUrl,' SIN @sUrl')

  IF @MODO_PRUEBAS=1
  BEGIN
	RETURN --PARA PRUEBAS
  END

  EXEC SPK_ENVIA_TRAMAS_CIPERU @ENDPOINT=@sUrl, @TRAMA = @BODY,@OK=@OK OUTPUT,  @RESPUESTA= @response OUTPUT

  --EXEC SPK_ENVIA_JSON_INTERFAX @JSON,@sUrl,@OK OUTPUT,@response OUTPUT

  IF @OK='KO'
  BEGIN
     INSERT INTO FTRAPILOG(N_FACTURA,TIPODOC,ESTADOC,ERRORES,METODO,JSONSOLICITUD,JSONRESPUESTA)
     SELECT @N_FACTURA,@TIPODOC,'KO',@response,'INTER_FNOT',@JSON,@response
  END
  ELSE
  BEGIN
     IF ISJSON(@response)=1
     BEGIN
        PRINT 'PARCIAR RESPUESTA'

		DECLARE @CodigoRespuesta NVARCHAR(10)
        DECLARE @DescRespuesta NVARCHAR(100)
        DECLARE @DetalleError NVARCHAR(500)

		SET @CodigoRespuesta = COALESCE(
			JSON_VALUE(@response, '$.EPreabonoResponse.co_rcode'),
			JSON_VALUE(@response, '$.EPreabonoResponse.CO_RCODE'),
			JSON_VALUE(@response, '$."MT_zposd020_CreacionPreAbono_res".co_rcode'),
			JSON_VALUE(@response, '$."MT_zposd020_CreacionPreAbono_res".CO_RCODE'),
			'1'
		);
		SET @DescRespuesta = COALESCE(
			JSON_VALUE(@response, '$.EPreabonoResponse.de_respuesta'),
			JSON_VALUE(@response, '$.EPreabonoResponse.DE_RESPUESTA'),
			JSON_VALUE(@response, '$."MT_zposd020_CreacionPreAbono_res".de_respuesta'),
			JSON_VALUE(@response, '$."MT_zposd020_CreacionPreAbono_res".DE_RESPUESTA'),
			'SIN DescRespuesta'
		);
		SET @DetalleError = COALESCE(
			JSON_VALUE(@response, '$.EPreabonoResponse.de_info_error'),
			JSON_VALUE(@response, '$.EPreabonoResponse.DE_INFO_ERRO'),
			JSON_VALUE(@response, '$.EPreabonoResponse.DE_INFO_ERROR'),
			JSON_VALUE(@response, '$."MT_zposd020_CreacionPreAbono_res".de_info_error'),
			JSON_VALUE(@response, '$."MT_zposd020_CreacionPreAbono_res".DE_INFO_ERRO'),
			JSON_VALUE(@response, '$."MT_zposd020_CreacionPreAbono_res".DE_INFO_ERROR'),
			'SIN DetalleError'
		);

		DECLARE @RPTA_MSG NVARCHAR(500) = 'Respuesta: @CodigoRespuesta = '+@CodigoRespuesta+', @DescRespuesta = '+@DescRespuesta+', @DetalleError = '+@DetalleError
		PRINT '@response '+COALESCE(@response,'SIN @response') 
		PRINT '@CodigoRespuesta '+COALESCE(@CodigoRespuesta,'SIN @CodigoRespuesta') 
		PRINT '@DescRespuesta '+COALESCE(@DescRespuesta,'SIN @DescRespuesta') 
		PRINT '@DetalleError '+COALESCE(@DetalleError,'SIN @DetalleError') 
		PRINT '@RPTA_MSG '+COALESCE(@RPTA_MSG,'SIN @RPTA_MSG') 

		IF @CodigoRespuesta = '0'
        BEGIN
            UPDATE FNOT SET FACTEP = '102', RESPUESTAJSON = @RPTA_MSG WHERE N_FACTURA = @N_FACTURA;

			INSERT INTO FTRAPILOG(N_FACTURA,CNSFNOT,TIPODOC,ESTADOC,ERRORES,METODO,JSONSOLICITUD,JSONRESPUESTA)
			SELECT @N_FACTURA,@PK_PREABO,@TIPODOC,'OK',@DetalleError,'INTER_FNOT',@JSON,@response
        END
		ELSE
		BEGIN		
