		END

		-- Validar que exista la admisión
		IF NOT EXISTS (SELECT 1 FROM HADM WHERE NOADMISION = @NOADMISION)
		BEGIN
			INSERT INTO @TBLERRORES(ERROR) SELECT 'La admisión con número ' + @NOADMISION + ' no existe.'
