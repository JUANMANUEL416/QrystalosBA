			-- Actualizar VALORTOTAL de las citas de la admisión según precio vigente del servicio
			UPDATE CIT
			SET CIT.VALORTOTAL = ISNULL(DBO.FNK_VLR_SERTOT(CIT.IDTERCEROCA, CIT.IDPLAN, CIT.IDSERVICIO, CIT.FECHA), 0)
			FROM CIT
			WHERE CIT.CONSECUTIVO IN (SELECT CONSECUTIVO FROM CIT WHERE NOADMISION = @NOADMISION AND COALESCE(FACTURADA, 0) = 0)
			
			-- Cursor sobre citas de la admisión no facturadas
			DECLARE aut_reliquidar CURSOR LOCAL FAST_FORWARD FOR
			SELECT A.IDAUT
			FROM AUT A
			WHERE A.CONSECUTIVOCIT IN (SELECT CONSECUTIVO FROM CIT WHERE NOADMISION = @NOADMISION AND COALESCE(FACTURADA, 0) = 0)

			-- Reliquidar cada AUT asociado a esta cita
			OPEN aut_reliquidar
