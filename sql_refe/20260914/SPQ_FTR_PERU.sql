			SET CIT.VALORTOTAL = ISNULL(DBO.FNK_VLR_SERTOT(CIT.IDTERCEROCA, CIT.IDPLAN, CIT.IDSERVICIO, CIT.FECHA), 0)
			FROM CIT
			WHERE CIT.CONSECUTIVO = @CONSECUTIVO

			-- Reliquidar cada AUT asociado a la cita 
			DECLARE aut_reliquidar CURSOR LOCAL FAST_FORWARD FOR
				SELECT A.IDAUT
				FROM AUT A
				WHERE A.CONSECUTIVOCIT = @CONSECUTIVO

			OPEN aut_reliquidar
			FETCH NEXT FROM aut_reliquidar INTO @IDAUT_REL
			WHILE @@FETCH_STATUS = 0
			BEGIN
				EXEC DBO.SPK_RECALCULAR_COPAGOS_AUTD @IDAUT_REL
				FETCH NEXT FROM aut_reliquidar INTO @IDAUT_REL
			END
			CLOSE aut_reliquidar
			DEALLOCATE aut_reliquidar
		END TRY
		BEGIN CATCH
			IF CURSOR_STATUS('local','aut_reliquidar') = 1
			BEGIN
				CLOSE aut_reliquidar
				DEALLOCATE aut_reliquidar
			END
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
			SELECT 'KO' OK, ERROR FROM @TBLERRORES
			RETURN
		END CATCH
	
		SELECT 'OK' OK
		RETURN                 
	END

