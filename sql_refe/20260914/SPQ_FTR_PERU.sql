			BEGIN
				CLOSE aut_reliquidar
				DEALLOCATE aut_reliquidar
			END
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
			SELECT 'KO' OK, ERROR FROM @TBLERRORES
			RETURN
		END CATCH
	
