CREATE OR ALTER FUNCTION DBO.FNK_RIPS_JSON_USAR_ASYNC
(
	@CNSFCT VARCHAR(20),
	@TIPODOC VARCHAR(20)
)
RETURNS BIT
AS
BEGIN
	DECLARE @CONFIG NVARCHAR(MAX);
	DECLARE @PROCEDENCIA VARCHAR(20);
	DECLARE @VR_TOTAL DECIMAL(14,2);
	DECLARE @VALOR_MINIMO DECIMAL(14,2);
	DECLARE @CNSFACT VARCHAR(20) = RTRIM(LTRIM(@CNSFCT));
	DECLARE @N_FACTURA VARCHAR(20);

	SET @CONFIG = DBO.FNK_VALORVARIABLE(N'CONFIG_GENE_FEV');

	IF COALESCE(@CONFIG, N'') = N'' OR ISJSON(@CONFIG) <> 1
		RETURN 1;

	SET @VALOR_MINIMO = COALESCE(
		TRY_CAST(JSON_VALUE(@CONFIG, N'$.valorMinimoAsync') AS DECIMAL(14, 2)),
		0
	);

	SET @PROCEDENCIA = NULL;
	SET @VR_TOTAL = NULL;
	SET @N_FACTURA = NULL;

	IF UPPER(RTRIM(LTRIM(@TIPODOC))) = N'FACTURA'
	BEGIN
		SELECT @PROCEDENCIA = PROCEDENCIA
		     , @VR_TOTAL = VR_TOTAL
		FROM FTR
		WHERE CNSFCT = @CNSFACT;
	END
	ELSE IF UPPER(RTRIM(LTRIM(@TIPODOC))) = N'AJUSTE'
	BEGIN
		SELECT TOP 1
			@N_FACTURA = FGLO.N_FACTURA,
			@PROCEDENCIA = FTR.PROCEDENCIA,
			@VR_TOTAL = FTR.VR_TOTAL
		FROM FGLO
		INNER JOIN FTR ON FTR.N_FACTURA = FGLO.N_FACTURA
		WHERE RTRIM(FGLO.CNSGLO) = @CNSFACT;

		IF COALESCE(@N_FACTURA, N'') = N''
		BEGIN
			SELECT TOP 1
				@N_FACTURA = FTR.N_FACTURA,
				@PROCEDENCIA = FTR.PROCEDENCIA,
				@VR_TOTAL = FTR.VR_TOTAL
			FROM FTR
			WHERE RTRIM(FTR.CNSFCT) = @CNSFACT;
		END
	END
	ELSE
	BEGIN
		SELECT @PROCEDENCIA = FTR.PROCEDENCIA
		     , @VR_TOTAL = COALESCE(FNOT.VR_TOTAL, FTR.VR_TOTAL)
		FROM FNOT
		INNER JOIN FTR ON FNOT.N_FACTURA = FTR.N_FACTURA
		WHERE FNOT.CNSFNOT = @CNSFACT;
	END

	IF COALESCE(@PROCEDENCIA, N'') <> N''
	   AND EXISTS (
			SELECT 1
			FROM OPENJSON(@CONFIG, N'$.procedenciasSinAsync')
			WHERE UPPER(RTRIM(LTRIM([value]))) = UPPER(RTRIM(LTRIM(@PROCEDENCIA)))
	   )
		RETURN 0;

	IF COALESCE(@VR_TOTAL, 0) < @VALOR_MINIMO
		RETURN 0;

	RETURN 1;
END

