CREATE OR ALTER PROCEDURE DBO.SPQ_IMOV_PDF
    @DATOS  VARCHAR(100),
    @CNSMOV VARCHAR(20) = NULL,
    @IDSEDE VARCHAR(5)  = NULL,
    @USUARIO VARCHAR(128) = NULL
WITH ENCRYPTION
AS
BEGIN
    SET NOCOUNT ON;

    /*
        SPQ_IMOV_PDF: procedimiento nuevo para impresión del COMPROBANTE DE MOVIMIENTO
        DE INVENTARIO vía pdf-report-service (reportName: comprobante_movimiento_inventario).

        NO reemplaza a SPQ_IZSOL (METODO=IMPRE_MOVIMIENTO), SPQ_IMOV (METODO=FIRMA) ni
        SPQ_INV_ENFERMERIA (METODO=BUSCAR_USUFIRMARECIBIDO), que quedan intactos como
        legacy para el flujo jsPDF actual (impri_mov en IndexComponent.vue).

        Diferencia clave vs. el bloque IMPRE_MOVIMIENTO legacy: la cabecera usa LEFT JOIN
        (en vez de INNER JOIN) contra IZSOL, para no descartar el movimiento completo
        cuando IMOV.NODOCUMENTO no corresponde a un CNSIZSOL (p.ej. movimientos manuales
        o de otro origen). Eso es lo que producía CMI_NOT_FOUND en el reporte nuevo.

        DISPENSADO: una fila por IMOVH (artículo+lote). No hacer INNER JOIN 1:N a IZSOLDT
        (varias líneas IZSOLD del mismo artículo/lote triplicaban CANTPEDIDA de IMOVH).
        Se une DetSol con ROW_NUMBER RN=1 sobre IZSOLDT/IZSOLD solo para vía y prescripción.
    */

    IF @DATOS = 'MOVIMIENTO'
    BEGIN
        IF COALESCE(@CNSMOV, '') = ''
        BEGIN
            SELECT ERROR = 'CNSMOV requerido';
            RETURN;
        END

        /* CABECERA */
        SELECT
            OK = 'OK',
            USUARIOSOL = CASE WHEN DBO.FNK_VALORVARIABLE('IZSOL_MED_SOLI') = 'SI' THEN MED.IDMEDICO ELSE IZSOL.USUARIOSOL END,
            NOMBRE = CASE WHEN DBO.FNK_VALORVARIABLE('IZSOL_MED_SOLI') = 'SI' THEN MED.NOMBRE ELSE USUSU.NOMBRE END,
            IZSOL.CNSIZSOL,
            IMOV.CNSMOV,
            IMOV.FECHAMOV,
            IMOV.CCOSTO,
            IMOV.IDAREA,
            IMOV.IDBODEGA,
            IBOD.DESCRIPCION IDBODEGA_DESC,
            IMOV.IDTIPOMOV,
            ITMO.DESCRIPCION IDTIPOMOV_DESC,
            NOADMISION = CASE WHEN IZSOL.CLASE IN ('FORMEDCE', 'HPRE') THEN IZSOL.NOADMISION ELSE COALESCE(AUT.IDAUT, HADM.NOADMISION) END,
            IMOV.IDFUNCIONARIO,
            USU_FUN.NOMBRE AS NOMBRE_FUNCIONARIO,
            AFI.DOCIDAFILIADO,
            AFI.NOMBREAFI,
            AFI.TELEFONORES,
            PERIODO = CASE WHEN IZSOL.CLASE = 'CE' THEN COALESCE(AE.PERIODO, AUT.PERIODO_DISPENSA) END,
            FECHA_FORMULA = COALESCE(HCA.FECHA, CASE WHEN IZSOL.CLASE = 'CE' THEN AUT.FECHA_FORMULA END),
            AFI.TIPO_DOC,
            AFI.IDAFILIADO,
            AFI.DIRECCION,
            IDTERCERO = CASE IZSOL.CLASE
                WHEN 'APLIM' THEN APTER.IDTERCERO
                WHEN 'CE' THEN AU.IDTERCERO
                WHEN 'ONCO' THEN CI.IDTERCERO
                WHEN 'FORMEDCE' THEN TER.IDTERCERO
                WHEN 'HPRE' THEN TER.IDTERCERO
                ELSE COALESCE(HADM.IDTERCERO, TER.IDTERCERO)
            END,
            RAZONSOCIAL = CASE IZSOL.CLASE
                WHEN 'APLIM' THEN APTER.RAZONSOCIAL
                WHEN 'CE' THEN AU.RAZONSOCIAL
                WHEN 'ONCO' THEN CI.RAZONSOCIAL
                WHEN 'FORMEDCE' THEN TER.RAZONSOCIAL
                WHEN 'HPRE' THEN TER.RAZONSOCIAL
                ELSE TER.RAZONSOCIAL
            END,
            IDPLAN = CASE IZSOL.CLASE
                WHEN 'APLIM' THEN APLI.IDPLAN
                WHEN 'CE' THEN AUT.IDPLAN
                WHEN 'ONCO' THEN CIT.IDPLAN
                WHEN 'FORMEDCE' THEN IZSOL.IDPLAN
                WHEN 'HPRE' THEN IZSOL.IDPLAN
                ELSE HADM.IDPLAN
            END,
            DESCPLAN = CASE IZSOL.CLASE
                WHEN 'APLIM' THEN PAPLI.DESCPLAN
                WHEN 'CE' THEN PAUT.DESCPLAN
                WHEN 'ONCO' THEN PCIT.DESCPLAN
                WHEN 'FORMEDCE' THEN PLN.DESCPLAN
                WHEN 'HPRE' THEN PLN.DESCPLAN
                ELSE PLN.DESCPLAN
            END,
            IMOV.IDITAR,
            ITAR.DESCRIPCION IDITAR_DESC,
            CEN.DESCRIPCION CCOSTO_DESC,
            AFU.DESCRIPCION IDAREA_DESC,
            IMOV.ESTADO,
            ESTADO_DESC = CASE WHEN IMOV.ESTADO = 0 THEN 'NO CONFIRMADO' WHEN IMOV.ESTADO = 1 THEN 'CONFIRMADO' END,
            CAMA = COALESCE(HHAB_IZSOL.CAMA, ''),
            CAMA_DESC = COALESCE(HHAB_IZSOL.DESCRIPCION, ''),
            IZSOL.IDSEDE
        FROM IMOV WITH (NOLOCK)
            LEFT JOIN IZSOL WITH (NOLOCK) ON IMOV.NODOCUMENTO = IZSOL.CNSIZSOL
            LEFT JOIN HCA WITH (NOLOCK) ON IZSOL.CONSECUTIVOHCA = HCA.CONSECUTIVO
            LEFT JOIN MED WITH (NOLOCK) ON HCA.IDMEDICO = MED.IDMEDICO
            LEFT JOIN USUSU WITH (NOLOCK) ON IZSOL.USUARIOSOL = USUSU.USUARIO
            LEFT JOIN USUSU USU_FUN WITH (NOLOCK) ON IMOV.IDFUNCIONARIO = USU_FUN.USUARIO
            LEFT JOIN ITMO WITH (NOLOCK) ON IMOV.IDTIPOMOV = ITMO.IDTIPOMOV
            LEFT JOIN IBOD WITH (NOLOCK) ON IMOV.IDBODEGA = IBOD.IDBODEGA
            LEFT JOIN HADM WITH (NOLOCK) ON IZSOL.NOADMISION = HADM.NOADMISION AND IZSOL.CLASE NOT IN ('FORMEDCE', 'HPRE')
            LEFT JOIN QXPCX WITH (NOLOCK) ON QXPCX.CONSECUTIVO = IZSOL.CNSIZSOLM AND IZSOL.CLASE = 'QXPGCX'
            LEFT JOIN HADM H WITH (NOLOCK) ON QXPCX.NOADMISION = H.NOADMISION AND IZSOL.CLASE = 'QXPGCX'
            LEFT JOIN CXPS WITH (NOLOCK) ON CXPS.NOPROGRAMACION = CASE WHEN IZSOL.CLASE = 'QXPGCX' AND LEN(IZSOL.NOADMISION) < 10 THEN IZSOL.NOADMISION ELSE '9999' END
            LEFT JOIN CIT WITH (NOLOCK) ON IZSOL.NOADMISION = CIT.CONSECUTIVO AND IZSOL.CLASE = 'ONCO'
            LEFT JOIN AUT WITH (NOLOCK) ON IZSOL.NOADMISION = AUT.IDAUT AND IZSOL.CLASE = 'CE'
            LEFT JOIN APLIM WITH (NOLOCK) ON IZSOL.NOADMISION = CAST(APLIM.ID AS VARCHAR) AND IZSOL.CLASE = 'APLIM'
            LEFT JOIN APLI WITH (NOLOCK) ON APLIM.IDAPLI = APLI.ID AND IZSOL.CLASE = 'APLIM'
            LEFT JOIN AFI WITH (NOLOCK) ON AFI.IDAFILIADO = CASE
                WHEN IZSOL.CLASE = 'QXPGCX' AND LEN(IZSOL.CNSIZSOLM) < 10 THEN CXPS.IDAFILIADO
                WHEN IZSOL.CLASE = 'QXPGCX' AND LEN(IZSOL.CNSIZSOLM) >= 10 THEN H.IDAFILIADO
                WHEN IZSOL.CLASE = 'APLIM' THEN APLI.IDAFILIADO
                WHEN IZSOL.CLASE = 'CE' THEN AUT.IDAFILIADO
                WHEN IZSOL.CLASE = 'ONCO' THEN CIT.IDAFILIADO
                WHEN IZSOL.CLASE = 'FORMEDCE' THEN IZSOL.NOADMISION
                WHEN IZSOL.CLASE = 'HPRE' THEN IZSOL.NOADMISION
                ELSE HADM.IDAFILIADO
            END
            LEFT JOIN PLN WITH (NOLOCK) ON PLN.IDPLAN = CASE
                WHEN IZSOL.CLASE = 'APLIM' THEN APLI.IDPLAN
                WHEN IZSOL.CLASE = 'CE' THEN AUT.IDPLAN
                WHEN IZSOL.CLASE = 'ONCO' THEN CIT.IDPLAN
                WHEN IZSOL.CLASE IN ('FORMEDCE', 'HPRE') THEN IZSOL.IDPLAN
                ELSE HADM.IDPLAN
            END
            LEFT JOIN AUTE AE WITH (NOLOCK) ON AUT.IDAUT = AE.IDAUT AND IZSOL.CLASE = 'CE'
            LEFT JOIN PLN PAPLI WITH (NOLOCK) ON PAPLI.IDPLAN = APLI.IDPLAN AND IZSOL.CLASE = 'APLIM'
            LEFT JOIN TER WITH (NOLOCK) ON TER.IDTERCERO = CASE
                WHEN IZSOL.CLASE = 'APLIM' THEN APLI.IDTERCERO
                WHEN IZSOL.CLASE = 'CE' THEN AUT.IDCONTRATANTE
                WHEN IZSOL.CLASE = 'ONCO' THEN CIT.IDCONTRATANTE
                WHEN IZSOL.CLASE IN ('FORMEDCE', 'HPRE') THEN IZSOL.IDTERCEROC
                ELSE HADM.IDTERCERO
            END
            LEFT JOIN TER CI WITH (NOLOCK) ON CI.IDTERCERO = CIT.IDTERCEROCA AND IZSOL.CLASE = 'ONCO'
            LEFT JOIN TER AU WITH (NOLOCK) ON AU.IDTERCERO = AUT.IDCONTRATANTE AND IZSOL.CLASE = 'CE'
            LEFT JOIN TER APTER WITH (NOLOCK) ON APTER.IDTERCERO = APLI.IDTERCERO AND IZSOL.CLASE = 'APLIM'
            LEFT JOIN PLN PAUT WITH (NOLOCK) ON PAUT.IDPLAN = AUT.IDPLAN AND IZSOL.CLASE = 'CE'
            LEFT JOIN PLN PCIT WITH (NOLOCK) ON PCIT.IDPLAN = CIT.IDPLAN AND IZSOL.CLASE = 'ONCO'
            LEFT JOIN ITAR WITH (NOLOCK) ON IMOV.IDITAR = ITAR.IDITAR
            LEFT JOIN CEN WITH (NOLOCK) ON IMOV.CCOSTO = CEN.CCOSTO
            LEFT JOIN AFU WITH (NOLOCK) ON IMOV.IDAREA = AFU.IDAREA
            LEFT JOIN HHAB HHAB_IZSOL WITH (NOLOCK) ON HADM.HABCAMA = HHAB_IZSOL.HABCAMA
        WHERE IMOV.CNSMOV = @CNSMOV;

        /* DISPENSADO: 1 fila por IMOVH (artículo+lote) con CANTPEDIDA real del movimiento.
           DetSol (RN=1) toma una sola IZSOLDT/IZSOLD por artículo+lote; evita multiplicar
           CANTPEDIDA cuando hay N líneas IZSOLD del mismo lote. */
        SELECT
            IMOVH.CNSMOV,
            IMOVH.IDARTICULO,
            IART.DESCRIPCION,
            COALESCE(IART.IDUNIDAD, '') IDUNIDAD,
            COALESCE(IMOVH.CANTPEDIDA, 0) CANTPEDIDA,
            COALESCE(IMOVH.PCOSTOANTES, 0) PCOSTOANTES,
            IMOVH.PCOSTOANTES * IMOVH.CANTPEDIDA PCOSTO,
            IMOVH.PVENTA,
            IMOVH.NOLOTE,
            IMOVH.NOLOTEPEDIDO,
            IMOVH.FECHAVENCE,
            COALESCE(IEXI.SELLOCALIDAD, IMOVH.SELLOCALIDAD, '') SELLOCALIDAD,
            COALESCE(VIA_TGEN.DESCRIPCION, DetSol.VIA_APLICACION, '') VIA_APLICACION,
            COALESCE(IFFA.DESCRIPCION, '') FORMA_FARMACEUTICA,
            /* Última HCATD I/B que afectó la dosis; strip desde 'Equivale' (sin recalcular) */
            PRESCRIPCION = IIF(
                CHARINDEX('Equivale', COALESCE(UltOmDosis.PRESCRIPCION, DetSol.PRESCRIPCION, '')) > 0,
                RTRIM(SUBSTRING(
                    COALESCE(UltOmDosis.PRESCRIPCION, DetSol.PRESCRIPCION, ''),
                    1,
                    CHARINDEX('Equivale', COALESCE(UltOmDosis.PRESCRIPCION, DetSol.PRESCRIPCION, '')) - 1
                )),
                COALESCE(UltOmDosis.PRESCRIPCION, DetSol.PRESCRIPCION, '')
            )
        FROM IMOVH WITH (NOLOCK)
            INNER JOIN IART WITH (NOLOCK) ON IMOVH.IDARTICULO = IART.IDARTICULO
            INNER JOIN IMOV WITH (NOLOCK) ON IMOV.CNSMOV = IMOVH.CNSMOV
            INNER JOIN (
                SELECT
                    IZSOLDT.CNSMOV,
                    IZSOLDT.IDARTICULOREAL,
                    IZSOLDT.NOLOTE,
                    IZSOLD.VIA_APLICACION,
                    IZSOLD.PRESCRIPCION,
                    IZSOLD.IDSERVICIO,
                    IZSOLD.CODOM,
                    IZSOL.NOADMISION,
                    IZSOL.FECHASOL,
                    ROW_NUMBER() OVER (
                        PARTITION BY IZSOLDT.CNSMOV, IZSOLDT.IDARTICULOREAL, IZSOLDT.NOLOTE
                        ORDER BY IZSOLDT.CNSIZSOLDT DESC
                    ) AS RN
                FROM IZSOLDT WITH (NOLOCK)
                    INNER JOIN IZSOLD WITH (NOLOCK) ON IZSOLD.CNSIZSOLD = IZSOLDT.CNSIZSOLD
                    LEFT JOIN IZSOL WITH (NOLOCK) ON IZSOL.CNSIZSOL = IZSOLD.CNSIZSOL
                WHERE IZSOLDT.CNSMOV = @CNSMOV
            ) DetSol ON DetSol.CNSMOV = IMOVH.CNSMOV
                AND DetSol.IDARTICULOREAL = IMOVH.IDARTICULO
                AND DetSol.NOLOTE = IMOVH.NOLOTE
                AND DetSol.RN = 1
            LEFT JOIN IEXI WITH (NOLOCK) ON IEXI.IDBODEGA = IMOV.IDBODEGA
                AND IEXI.IDARTICULO = IMOVH.IDARTICULO
                AND IEXI.NOLOTE = IMOVH.NOLOTE
            LEFT JOIN IFFA WITH (NOLOCK) ON IFFA.IDFORFARM = IART.IDFORFARM
            LEFT JOIN TGEN VIA_TGEN WITH (NOLOCK) ON VIA_TGEN.TABLA = 'General'
                AND VIA_TGEN.CAMPO = 'VIAAPLICACION'
                AND LTRIM(RTRIM(VIA_TGEN.CODIGO)) = LTRIM(RTRIM(DetSol.VIA_APLICACION))
            OUTER APPLY (
                SELECT TOP 1 HCATD.PRESCRIPCION
                FROM HCATD WITH (NOLOCK)
                INNER JOIN HCA WITH (NOLOCK) ON HCA.CONSECUTIVO = HCATD.CONSECUTIVO
                WHERE HCA.NOADMISION = DetSol.NOADMISION
                    AND HCATD.IDSERVICIO = COALESCE(DetSol.IDSERVICIO, IART.IDSERVICIO)
                    AND HCATD.CLASE IN ('I', 'B')
                    AND (
                        DetSol.CODOM IS NULL
                        OR LTRIM(RTRIM(DetSol.CODOM)) = ''
                        OR HCATD.CODOM = DetSol.CODOM
                    )
                    AND (
                        DetSol.FECHASOL IS NULL
                        OR HCA.FECHA <= DetSol.FECHASOL
                    )
                ORDER BY HCA.FECHA DESC
            ) UltOmDosis
        WHERE IMOVH.CNSMOV = @CNSMOV
            AND COALESCE(IMOVH.CANTPEDIDA, 0) > 0;

        /* TOTALES (solo sobre líneas dispensadas con lote/fecha) */
        SELECT
            SUM(IMOVH.CANTPEDIDA) TOTAL_CANTPEDIDA,
            SUM(IMOVH.PCOSTOANTES) TOTAL_PCOSTOANTES,
            SUM(IMOVH.PCOSTOANTES * IMOVH.CANTPEDIDA) TOTAL_PCOSTO
        FROM IMOVH WITH (NOLOCK)
        WHERE IMOVH.CNSMOV = @CNSMOV
            AND COALESCE(IMOVH.CANTPEDIDA, 0) > 0
            AND (
                (IMOVH.NOLOTE IS NOT NULL AND LTRIM(RTRIM(IMOVH.NOLOTE)) <> '')
                OR (IMOVH.NOLOTEPEDIDO IS NOT NULL AND LTRIM(RTRIM(IMOVH.NOLOTEPEDIDO)) <> '')
                OR (IMOVH.FECHAVENCE IS NOT NULL)
            );

        /* FALTANTES (no dispensados) */
        SELECT
            IMOVH.CNSMOV,
            IMOVH.IDARTICULO,
            IART.DESCRIPCION,
            COALESCE(IART.IDUNIDAD, '') IDUNIDAD,
            COALESCE(IMOVH.CANTPEDIDA, 0) CANTPEDIDA,
            COALESCE(IMOVH.PCOSTOANTES, 0) PCOSTOANTES,
            IMOVH.PCOSTOANTES * IMOVH.CANTPEDIDA PCOSTO,
            IMOVH.PVENTA,
            IMOVH.NOLOTE,
            IMOVH.NOLOTEPEDIDO,
            IMOVH.FECHAVENCE,
            COALESCE(IEXI.SELLOCALIDAD, IMOVH.SELLOCALIDAD, '') SELLOCALIDAD
        FROM IMOVH WITH (NOLOCK)
            INNER JOIN IART WITH (NOLOCK) ON IMOVH.IDARTICULO = IART.IDARTICULO
            INNER JOIN IMOV WITH (NOLOCK) ON IMOV.CNSMOV = IMOVH.CNSMOV
            LEFT JOIN IEXI WITH (NOLOCK) ON IEXI.IDBODEGA = IMOV.IDBODEGA
                AND IEXI.IDARTICULO = IMOVH.IDARTICULO
                AND IEXI.NOLOTE = IMOVH.NOLOTE
        WHERE IMOVH.CNSMOV = @CNSMOV
            AND COALESCE(IMOVH.CANTPEDIDA, 0) = 0;

        RETURN;
    END

    IF @DATOS = 'FIRMA_ELABORO'
    BEGIN
        IF COALESCE(@CNSMOV, '') = ''
        BEGIN
            SELECT ERROR = 'CNSMOV requerido';
            RETURN;
        END

        SELECT TOP 1
            OK = 'OK',
            FIRMA = COALESCE(AM.DICOM, AU.DICOM),
            NOMBRE = USU_FUN.NOMBRE,
            USUARIO = USU_FUN.USUARIO
        FROM IMOV WITH (NOLOCK)
            INNER JOIN USUSU USU_FUN WITH (NOLOCK) ON IMOV.IDFUNCIONARIO = USU_FUN.USUARIO
            LEFT JOIN MED WITH (NOLOCK) ON USU_FUN.IDMEDICO = MED.IDMEDICO
            LEFT JOIN ARCHIVOS AU WITH (NOLOCK) ON AU.ID = USU_FUN.IDFIRMA
            LEFT JOIN ARCHIVOS AM WITH (NOLOCK) ON AM.ID = MED.IDFIRMA
        WHERE IMOV.CNSMOV = @CNSMOV;

        RETURN;
    END

    IF @DATOS = 'FIRMA_RECIBIDO'
    BEGIN
        IF COALESCE(@CNSMOV, '') = ''
        BEGIN
            SELECT ERROR = 'CNSMOV requerido';
            RETURN;
        END

        DECLARE @USUARIOFIRMA VARCHAR(20);

        SELECT @USUARIOFIRMA = IMOV.USUFIRMARECIBIDO
        FROM IMOV WITH (NOLOCK)
            INNER JOIN USUSU WITH (NOLOCK) ON IMOV.USUFIRMARECIBIDO = USUSU.USUARIO
        WHERE IMOV.CNSMOV = @CNSMOV;

        IF COALESCE(@USUARIOFIRMA, '') = ''
        BEGIN
            SELECT OK = 'OK', FIRMA = CAST(NULL AS VARBINARY(MAX)), NOMBRE = CAST(NULL AS VARCHAR(200)), USUARIO = CAST(NULL AS VARCHAR(20));
            RETURN;
        END

        SELECT TOP 1
            OK = 'OK',
            FIRMA = COALESCE(AM.DICOM, AU.DICOM),
            NOMBRE = USUSU.NOMBRE,
            USUARIO = USUSU.USUARIO
        FROM IMOV WITH (NOLOCK)
            INNER JOIN USUSU WITH (NOLOCK) ON IMOV.USUFIRMARECIBIDO = USUSU.USUARIO
            LEFT JOIN MED WITH (NOLOCK) ON USUSU.IDMEDICO = MED.IDMEDICO
            LEFT JOIN ARCHIVOS AU WITH (NOLOCK) ON AU.ID = USUSU.IDFIRMA
            LEFT JOIN ARCHIVOS AM WITH (NOLOCK) ON AM.ID = MED.IDFIRMA
        WHERE IMOV.CNSMOV = @CNSMOV;

        RETURN;
    END

    IF @DATOS = 'EMPRESA'
    BEGIN
        DECLARE @UBICACIONLOGO VARCHAR(512) = dbo.FNK_VALORVARIABLE('UBICACIONLOGO');
        DECLARE @LOGO VARBINARY(MAX);
        DECLARE @LOGO_B64 VARCHAR(MAX);
        DECLARE @SQLString NVARCHAR(1000);

        /* Sede del encabezado = sede de la bodega del movimiento (IBOD.IDSEDE_BOD).
           Fallback: IZSOL.IDSEDE, luego @IDSEDE recibido. */
        IF COALESCE(@CNSMOV, '') <> ''
        BEGIN
            SELECT TOP 1
                @IDSEDE = COALESCE(
                    NULLIF(LTRIM(RTRIM(IBOD.IDSEDE_BOD)), ''),
                    NULLIF(LTRIM(RTRIM(IZSOL.IDSEDE)), ''),
                    @IDSEDE
                )
            FROM IMOV WITH (NOLOCK)
                LEFT JOIN IBOD WITH (NOLOCK) ON IMOV.IDBODEGA = IBOD.IDBODEGA
                LEFT JOIN IZSOL WITH (NOLOCK) ON IMOV.NODOCUMENTO = IZSOL.CNSIZSOL
            WHERE IMOV.CNSMOV = @CNSMOV;
        END

        IF COALESCE(@UBICACIONLOGO, '') <> ''
        BEGIN
            BEGIN TRY
                SET @SQLString = 'SELECT @LOGO = col FROM OPENROWSET(BULK ''' + @UBICACIONLOGO + ''', SINGLE_BLOB) Tbl(col)';
                EXECUTE sp_executesql @SQLString, N'@LOGO VARBINARY(MAX) OUTPUT', @LOGO = @LOGO OUTPUT;
                SELECT @LOGO_B64 = CAST(N'' AS XML).value('xs:base64Binary(xs:hexBinary(sql:column("bin")))', 'VARCHAR(MAX)')
                FROM (SELECT @LOGO AS bin) AS bin_sql_server_temp;
            END TRY
            BEGIN CATCH
                SET @LOGO_B64 = NULL;
            END CATCH
        END

        SELECT TOP 1
            RAZONSOCIAL = COALESCE(LTRIM(RTRIM(TER.RAZONSOCIAL)), ''),
            SEDE_DESC = REPLACE(LTRIM(RTRIM(TER.RAZONSOCIAL)),COALESCE(LTRIM(RTRIM(SED.DESCRIPCION)), ''), ''),
            DIRECCION = LTRIM(RTRIM(CONCAT(
                NULLIF(LTRIM(RTRIM(SED.DIRECCION)), ''),
                CASE WHEN NULLIF(LTRIM(RTRIM(SED.DIRECCION)), '') IS NOT NULL
                      AND NULLIF(LTRIM(RTRIM(CIU_SED.NOMBRE)), '') IS NOT NULL
                     THEN CONCAT(' - ', CIU_SED.NOMBRE)
                     WHEN NULLIF(LTRIM(RTRIM(CIU_SED.NOMBRE)), '') IS NOT NULL
                     THEN CIU_SED.NOMBRE ELSE '' END
            ))),
            TELEFONOS = COALESCE(SED.TELEFONOS, TER.TELEFONOS, ''),
            CIUDAD = COALESCE(CIU_SED.NOMBRE, ''),
            @LOGO_B64 AS LOGO_B64
        FROM TER WITH (NOLOCK)
            LEFT JOIN SED WITH (NOLOCK) ON SED.IDSEDE = @IDSEDE
            LEFT JOIN CIU CIU_SED WITH (NOLOCK) ON CIU_SED.CIUDAD = SED.CIUDAD
        WHERE TER.IDTERCERO = dbo.FNK_VALORVARIABLE('IDTERCEROINSTALADO');

        RETURN;
    END

    SELECT ERROR = 'DATOS no soportado: ' + COALESCE(@DATOS, '');
END

