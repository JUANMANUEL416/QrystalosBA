				FROM IZSOLDT DT WITH (NOLOCK)
				GROUP BY DT.CNSIZSOLD
				HAVING SUM(DT.CANTIDADSOL) > 0
			) ENT ON ENT.CNSIZSOLD COLLATE Modern_Spanish_CI_AS = IZSOLD.CNSIZSOLD COLLATE Modern_Spanish_CI_AS
			OUTER APPLY (
				SELECT TOP 1
					M.CNSMOV,
					M.FECHACONF,
					M.FECHAMOV,
					M.USUARIOCONF,
					M.USUARIO
				FROM IMOV M WITH (NOLOCK)
				WHERE M.NODOCUMENTO COLLATE Modern_Spanish_CI_AS = IZSOL.CNSIZSOL COLLATE Modern_Spanish_CI_AS
				  AND M.PROCEDENCIA COLLATE Modern_Spanish_CI_AS = 'CM_SOL'
				  AND M.ESTADO = 1
				ORDER BY COALESCE(M.FECHACONF, M.FECHAMOV) DESC
			) IMOV
			LEFT JOIN USUSU U WITH (NOLOCK)
				ON U.USUARIO COLLATE Modern_Spanish_CI_AS = COALESCE(IMOV.USUARIOCONF, IMOV.USUARIO) COLLATE Modern_Spanish_CI_AS
			WHERE IZSOL.NOADMISION COLLATE Modern_Spanish_CI_AS = @NOADMISION COLLATE Modern_Spanish_CI_AS
			  AND IZSOLD.IDARTICULO COLLATE Modern_Spanish_CI_AS = @IDARTICULO COLLATE Modern_Spanish_CI_AS
			  AND (
					COALESCE(LTRIM(RTRIM(@CNSIZSOL)), '') = ''
					OR IZSOL.CNSIZSOL COLLATE Modern_Spanish_CI_AS <> @CNSIZSOL COLLATE Modern_Spanish_CI_AS
				  )
			  AND IMOV.CNSMOV IS NOT NULL
			ORDER BY COALESCE(IMOV.FECHACONF, IMOV.FECHAMOV) DESC
		END TRY
		BEGIN CATCH
			INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
		END CATCH

		IF (SELECT COUNT(*) FROM @TBLERRORES) > 0
		BEGIN
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		RETURN
	END
END

