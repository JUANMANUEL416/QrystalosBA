			END
			-- Si no se encontró CLASE o NOADMISION, intentar obtener desde HADM directamente
			IF @NOADMISION_ORIGEN IS NULL OR @NOADMISION_ORIGEN = ''
			BEGIN
				SELECT TOP 1 @NOADMISION_ORIGEN = HADM.NOADMISION
				FROM IZSOL
				INNER JOIN HADM ON LTRIM(RTRIM(IZSOL.NOADMISION)) = LTRIM(RTRIM(HADM.NOADMISION))
				WHERE IZSOL.CNSIZSOL = @CNSIZSOL_ORIGEN
					AND IZSOL.NOADMISION IS NOT NULL
					AND IZSOL.NOADMISION <> ''
				ORDER BY IZSOL.FECHASOL DESC
			END
			-- Si aún no se encontró, usar el NOADMISION del IZSOL como fallback
			IF @NOADMISION_ORIGEN IS NULL OR @NOADMISION_ORIGEN = ''
			BEGIN
				SELECT @NOADMISION_ORIGEN = NOADMISION
				FROM IZSOL
				WHERE CNSIZSOL = @CNSIZSOL_ORIGEN
					AND NOADMISION IS NOT NULL
					AND NOADMISION <> ''
			END
		END

		-- ========================================================================
		-- 4. VALIDAR CONFIGURACIÓN Y TIPO DE MOVIMIENTO
		-- ========================================================================
	
		-- Obtener el tipo de movimiento de entrada para devoluciones
		SELECT @IDTIPOMOV_ENTRADA = DBO.FNK_VALORVARIABLE('IDINVMOV_DEVOLUCION')

		-- Validar que la variable esté configurada (es obligatoria)
		IF COALESCE(@IDTIPOMOV_ENTRADA, '') = ''
		BEGIN
			ROLLBACK TRANSACTION
			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'Error: La variable de configuración IDINVMOV_DEVOLUCION no está configurada. Es obligatorio configurar esta variable antes de realizar devoluciones.'
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		-- Validar que el tipo de movimiento existe y está activo
		IF NOT EXISTS (SELECT 1 FROM ITMO WHERE IDTIPOMOV = @IDTIPOMOV_ENTRADA AND ESTADO = 'Activo')
		BEGIN
			ROLLBACK TRANSACTION
			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'Error: El tipo de movimiento de entrada configurado en la variable IDINVMOV_DEVOLUCION (' + @IDTIPOMOV_ENTRADA + ') no existe o no está activo.'
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		-- Validar que hay artículos para devolver
		IF @ARTICULOS IS NULL OR LEN(LTRIM(RTRIM(@ARTICULOS))) = 0
		BEGIN
			ROLLBACK TRANSACTION
			INSERT INTO @TBLERRORES(ERROR) 
			SELECT 'No se especificaron artículos para devolver.'
			SELECT 'KO' OK
			SELECT ERROR FROM @TBLERRORES
			RETURN
		END

		-- ========================================================================
		-- 5. GENERAR CONSECUTIVO Y CREAR MOVIMIENTO DE ENTRADA
		-- ========================================================================
	
		BEGIN TRY
			-- Generar consecutivo para el movimiento de entrada
			DECLARE @NVOCONSEC VARCHAR(20)
			EXEC SPQ_GENSEQUENCE @SEDE = @SEDE, @PREFIJO = '@MOV', @LONGITUD = 8, @NVOCONSEC = @NVOCONSEC OUTPUT

			IF @NVOCONSEC IS NULL OR @NVOCONSEC = ''
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) 
				SELECT 'Error al generar consecutivo para el movimiento de entrada.'
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END

			DECLARE @SEDE_2DIGITOS VARCHAR(2) = RIGHT('00' + LTRIM(RTRIM(CAST(@SEDE AS VARCHAR(20)))), 2)
			DECLARE @CONSECUTIVO_NUMERICO VARCHAR(20) = ''
			DECLARE @TEMP_CONSEC VARCHAR(20) = LTRIM(RTRIM(CAST(@NVOCONSEC AS VARCHAR(20))))
			DECLARE @I_CONSEC INT = 1
	
			WHILE @I_CONSEC <= LEN(@TEMP_CONSEC)
			BEGIN
				IF SUBSTRING(@TEMP_CONSEC, @I_CONSEC, 1) BETWEEN '0' AND '9'
					SET @CONSECUTIVO_NUMERICO = @CONSECUTIVO_NUMERICO + SUBSTRING(@TEMP_CONSEC, @I_CONSEC, 1)
				SET @I_CONSEC = @I_CONSEC + 1
			END
	
			IF LEN(@CONSECUTIVO_NUMERICO) >= 2 AND LEFT(@CONSECUTIVO_NUMERICO, 2) = @SEDE_2DIGITOS
				SET @CONSECUTIVO_NUMERICO = SUBSTRING(@CONSECUTIVO_NUMERICO, 3, LEN(@CONSECUTIVO_NUMERICO))
	
			DECLARE @CONSECUTIVO_8DIGITOS VARCHAR(8) = RIGHT('00000000' + RIGHT(@CONSECUTIVO_NUMERICO, 8), 8)
			SET @CNSMOV_ENTRADA = @SEDE_2DIGITOS + @CONSECUTIVO_8DIGITOS

			-- Obtener datos del movimiento original
			SELECT 
				@CCOSTO_ORIGEN = IMOV.CCOSTO,
				@IDAREA_ORIGEN = IMOV.IDAREA,
				@IDTERCERO_ORIGEN = IMOV.IDTERCERO,
				@CNSIZSOL_ORIGEN_TEMP = IMOV.NODOCUMENTO
			FROM IMOV
			WHERE IMOV.CNSMOV = @CNSMOV

			-- Validar que el CCOSTO existe y está activo en CEN
			IF @CCOSTO_ORIGEN IS NULL OR @CCOSTO_ORIGEN = '' OR NOT EXISTS (
				SELECT 1 FROM CEN WHERE CCOSTO = @CCOSTO_ORIGEN AND ESTADO = 'Activo'
			)
			BEGIN
				-- Intentar obtener el CCOSTO del IZSOL relacionado
				IF @CNSIZSOL_ORIGEN_TEMP IS NOT NULL AND @CNSIZSOL_ORIGEN_TEMP <> ''
				BEGIN
					SELECT @CCOSTO_ORIGEN = IZSOL.SECTOR
					FROM IZSOL
					WHERE IZSOL.CNSIZSOL = @CNSIZSOL_ORIGEN_TEMP
						AND IZSOL.SECTOR IS NOT NULL
						AND IZSOL.SECTOR <> ''
						AND EXISTS (SELECT 1 FROM CEN WHERE CCOSTO = IZSOL.SECTOR AND ESTADO = 'Activo')
				END

				-- Si aún no hay CCOSTO válido, obtener uno de la bodega o por defecto
				IF @CCOSTO_ORIGEN IS NULL OR @CCOSTO_ORIGEN = '' OR NOT EXISTS (
					SELECT 1 FROM CEN WHERE CCOSTO = @CCOSTO_ORIGEN AND ESTADO = 'Activo'
				)
				BEGIN
					-- Obtener un CCOSTO válido de la bodega
					SELECT TOP 1 @CCOSTO_ORIGEN = IBODS.VALOR
					FROM IBODS
					INNER JOIN CEN ON IBODS.VALOR = CEN.CCOSTO
					WHERE IBODS.IDBODEGA = @IDBODEGA
						AND IBODS.TIPO = 'CEN'
						AND IBODS.ACCESO = 'Si'
						AND CEN.ESTADO = 'Activo'
					ORDER BY IBODS.VALOR

					-- Si aún no hay CCOSTO, usar el primero disponible activo
					IF @CCOSTO_ORIGEN IS NULL OR @CCOSTO_ORIGEN = ''
					BEGIN
						SELECT TOP 1 @CCOSTO_ORIGEN = CCOSTO
						FROM CEN
						WHERE ESTADO = 'Activo'
						ORDER BY CCOSTO
					END
				END
			END

			-- Validar que finalmente tenemos un CCOSTO válido
			IF @CCOSTO_ORIGEN IS NULL OR @CCOSTO_ORIGEN = '' OR NOT EXISTS (
				SELECT 1 FROM CEN WHERE CCOSTO = @CCOSTO_ORIGEN AND ESTADO = 'Activo'
			)
			BEGIN
				INSERT INTO @TBLERRORES(ERROR) 
				SELECT 'No se pudo determinar un centro de costo válido para el movimiento de devolución.'
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				RETURN
			END

			-- Si no hay IDAREA, obtenerlo del CCOSTO
			IF @IDAREA_ORIGEN IS NULL OR @IDAREA_ORIGEN = ''
			BEGIN
				SELECT @IDAREA_ORIGEN = IDAREA
				FROM CEN
				WHERE CCOSTO = @CCOSTO_ORIGEN
			END

			-- ========================================================================
			-- Crear IMOV con ESTADO = 0 (sin confirmar)
			-- ?? MODIFICADO: Incluir motivo en OBSERVACION
			-- ========================================================================
			INSERT INTO IMOV (
				CNSMOV, IDBODEGA, IDTIPOMOV, NODOCUMENTO, FECHAMOV, CCOSTO, 
				IDSOLICITA, IDFUNCIONARIO, ESTADO, OBSERVACION, PROCEDENCIA,
				USUARIO, SYS_ComputerName, IDAREA, IDTERCERO, SECONTABILIZA
			)
			VALUES (
				@CNSMOV_ENTRADA, 
				@IDBODEGA, 
				@IDTIPOMOV_ENTRADA, 
				COALESCE(@NOADMISION_ORIGEN, @CNSMOV), 
				DBO.FNK_FECHA_SIN_MLS(GETDATE()), 
				@CCOSTO_ORIGEN,
				@USUARIO, 
				@USUARIO, 
				0, 
				'Devolución de inventario - Movimiento origen: ' + @CNSMOV + ' - Motivo: ' + @MOTIVO_DEVOLUCION, 
				'DEVOLUCION', 
				@USUARIO, 
				@SYS_COMPUTERNAME, 
				@IDAREA_ORIGEN, 
				@IDTERCERO_ORIGEN, 
				0
			)

			-- ========================================================================
			-- 6. PROCESAR ARTÍCULOS A DEVOLVER
			-- ========================================================================
		
			-- Usar los MISMOS lotes que salieron (de ISAL)
			SELECT * INTO #ARTICULOS_DEVOLUCION
			FROM OPENJSON(@ARTICULOS)
			WITH (
				IDARTICULO		VARCHAR(20)		'$.IDARTICULO'
				,NOLOTE			VARCHAR(50)		'$.NOLOTE'
				,NOLOTEPEDIDO	VARCHAR(50)		'$.NOLOTEPEDIDO'
				,CANTIDAD		DECIMAL(14,2)	'$.CANTIDAD'
				,PCOSTO			DECIMAL(14,2)	'$.PCOSTO'
				,FECHAVENCE		DATE			'$.FECHAVENCE'
			)

			-- Validar cantidades y procesar artículos
			DECLARE CURSOR_ARTICULOS CURSOR FOR
			SELECT
				IDARTICULO,
				NOLOTE,
				NOLOTEPEDIDO,
				CANTIDAD,
				PCOSTO,
				FECHAVENCE
			FROM #ARTICULOS_DEVOLUCION
			WHERE COALESCE(CANTIDAD, 0) > 0

			DECLARE @CANTIDAD_DISPENSADA DECIMAL(14,2) = 0
			DECLARE @CANTIDAD_YA_DEV DECIMAL(14,2) = 0
			DECLARE @CANTIDAD_PEND_DEV DECIMAL(14,2) = 0
			DECLARE @IDITAR_ART VARCHAR(20)
			DECLARE @IDSERVICIO_ART VARCHAR(20)

			SET @CONTADOR = 0
			OPEN CURSOR_ARTICULOS
			FETCH NEXT FROM CURSOR_ARTICULOS
			INTO @IDARTICULO_DEV, @NOLOTE_DEV, @NOLOTEPEDIDO_DEV, @CANTIDAD_DEV, @PCOSTO_DEV, @FECHAVENCE_DEV

			WHILE @@FETCH_STATUS = 0
			BEGIN
				SET @CANTIDAD_DISPENSADA = 0
				SET @CANTIDAD_YA_DEV = 0
				SET @CANTIDAD_PEND_DEV = 0
				SET @IDITAR_ART = NULL
				SET @IDSERVICIO_ART = NULL

				SELECT @CANTIDAD_DISPENSADA = COALESCE(SUM(CANTIDAD), 0)
				FROM IMOVH
				WHERE CNSMOV = @CNSMOV
					AND IDARTICULO = @IDARTICULO_DEV
					AND NOLOTE = @NOLOTE_DEV
					AND COALESCE(NOLOTEPEDIDO, '') = COALESCE(@NOLOTEPEDIDO_DEV, '')
					AND ESTADO = 1

				SELECT @CANTIDAD_YA_DEV = COALESCE(SUM(H.CANTIDAD), 0)
				FROM IMOV M
				INNER JOIN IMOVH H ON H.CNSMOV = M.CNSMOV
				WHERE M.PROCEDENCIA = 'DEVOLUCION'
				  AND M.ESTADO = 1
				  AND M.OBSERVACION LIKE 'Devolución de inventario - Movimiento origen: ' + @CNSMOV + '%'
				  AND H.IDARTICULO = @IDARTICULO_DEV
				  AND H.NOLOTE = @NOLOTE_DEV
				  AND COALESCE(H.NOLOTEPEDIDO, '') = COALESCE(@NOLOTEPEDIDO_DEV, '')

				SET @CANTIDAD_PEND_DEV = @CANTIDAD_DISPENSADA - @CANTIDAD_YA_DEV

				IF @CANTIDAD_PEND_DEV <= 0
				BEGIN
					ROLLBACK TRANSACTION
					INSERT INTO @TBLERRORES(ERROR)
					SELECT 'No hay cantidad pendiente por devolver del artículo '
						+ COALESCE(@IDARTICULO_DEV, '') + ' etiqueta ' + COALESCE(@NOLOTE_DEV, '')
						+ ' (ya devuelto: ' + CAST(@CANTIDAD_YA_DEV AS VARCHAR(20)) + ').'
					SELECT 'KO' AS RESULTADO, 'KO' AS OK
					SELECT ERROR FROM @TBLERRORES
					CLOSE CURSOR_ARTICULOS
					DEALLOCATE CURSOR_ARTICULOS
					DROP TABLE #ARTICULOS_DEVOLUCION
					DELETE FROM IMOV WHERE CNSMOV = @CNSMOV_ENTRADA
					RETURN
				END

				IF @CANTIDAD_DEV > @CANTIDAD_PEND_DEV
				BEGIN
					ROLLBACK TRANSACTION
					INSERT INTO @TBLERRORES(ERROR)
					SELECT 'La cantidad a devolver (' + CAST(@CANTIDAD_DEV AS VARCHAR) +
						') excede lo pendiente (' + CAST(@CANTIDAD_PEND_DEV AS VARCHAR) +
						') para el artículo ' + @IDARTICULO_DEV + ' etiqueta ' + @NOLOTE_DEV
						+ ' (dispensado: ' + CAST(@CANTIDAD_DISPENSADA AS VARCHAR) +
						', ya devuelto: ' + CAST(@CANTIDAD_YA_DEV AS VARCHAR) + ').'
					SELECT 'KO' AS RESULTADO, 'KO' AS OK
					SELECT ERROR FROM @TBLERRORES
					CLOSE CURSOR_ARTICULOS
					DEALLOCATE CURSOR_ARTICULOS
					DROP TABLE #ARTICULOS_DEVOLUCION
					DELETE FROM IMOV WHERE CNSMOV = @CNSMOV_ENTRADA
					RETURN
				END

				SELECT
					@IDITAR_ART = IDITAR,
					@IDSERVICIO_ART = IDSERVICIO
				FROM IART
				WHERE IDARTICULO = @IDARTICULO_DEV

				-- Insertar en IMOVH con ESTADO = 0 y usando el MISMO LOTE
				-- NO generar nuevo lote, usar el lote original (@NOLOTE_DEV)
				INSERT INTO IMOVH (
					CNSMOV, IDARTICULO, CANTIDAD, PCOSTO, NOLOTE, NOLOTEPEDIDO, FECHAVENCE,
					ESTADO, DETALLE, IDITAR, IDSERVICIO
				)
				VALUES (
					@CNSMOV_ENTRADA, 
					@IDARTICULO_DEV, 
					@CANTIDAD_DEV, 
					@PCOSTO_DEV, 
					@NOLOTE_DEV, 
					@NOLOTEPEDIDO_DEV, 
					@FECHAVENCE_DEV, 
					0,
					'Devolución - Movimiento origen: ' + @CNSMOV, 
					@IDITAR_ART, 
					@IDSERVICIO_ART
				)

				SET @CONTADOR = @CONTADOR + 1

				FETCH NEXT FROM CURSOR_ARTICULOS
				INTO @IDARTICULO_DEV, @NOLOTE_DEV, @NOLOTEPEDIDO_DEV, @CANTIDAD_DEV, @PCOSTO_DEV, @FECHAVENCE_DEV
			END

			CLOSE CURSOR_ARTICULOS
			DEALLOCATE CURSOR_ARTICULOS

			-- Validar que se insertaron artículos
			IF @CONTADOR = 0
			BEGIN
				ROLLBACK TRANSACTION
				INSERT INTO @TBLERRORES(ERROR) 
				SELECT 'No se insertaron artículos en el movimiento de entrada.'
				SELECT 'KO' OK
				SELECT ERROR FROM @TBLERRORES
				DELETE FROM IMOV WHERE CNSMOV = @CNSMOV_ENTRADA
				IF OBJECT_ID('tempdb..#ARTICULOS_DEVOLUCION') IS NOT NULL DROP TABLE #ARTICULOS_DEVOLUCION
				RETURN
			END

			SET XACT_ABORT OFF
			EXEC SPK_CONFIRMARENTRADAS @IDBODEGA, @CNSMOV_ENTRADA, @USUARIO, @COMPANIA, @IDSEDE, @SYS_COMPUTERNAME

			IF NOT EXISTS (SELECT 1 FROM IMOV WHERE CNSMOV = @CNSMOV_ENTRADA AND ESTADO = 1)
			BEGIN
				ROLLBACK TRANSACTION
				INSERT INTO @TBLERRORES(ERROR)
				SELECT 'No se pudo confirmar el movimiento de entrada de devolución.'
				SELECT 'KO' AS RESULTADO, 'KO' AS OK
				SELECT ERROR FROM @TBLERRORES
				IF OBJECT_ID('tempdb..#ARTICULOS_DEVOLUCION') IS NOT NULL DROP TABLE #ARTICULOS_DEVOLUCION
				RETURN
			END

			/* Totales de lo realmente devuelto (para clonar solo eso en la nueva IZSOL) */
			DECLARE @CANT_TOTAL_DEVUELTA DECIMAL(14,2) = 0
			SELECT @CANT_TOTAL_DEVUELTA = COALESCE(SUM(CANTIDAD), 0)
			FROM #ARTICULOS_DEVOLUCION
			-- 8. ¿Devolución TOTAL o parcial?
			-- ========================================================================
			DECLARE @ES_DEVOLUCION_TOTAL BIT = 0
			DECLARE @CNSIZSOL_MARCADO VARCHAR(50) = NULL
			DECLARE @CNSIZSOL_ANTES_MARCA VARCHAR(50) = @CNSIZSOL_ORIGEN
			DECLARE @CNSIZSOL_BASE VARCHAR(50) = @CNSIZSOL_ORIGEN
			DECLARE @NUEVO_CNSIZSOL VARCHAR(50) = NULL
			DECLARE @NVOCONSEC_IZSOL VARCHAR(20)

			/* Total = no queda remanente en ninguna línea IMOVH del movimiento origen */
			IF NOT EXISTS (
				SELECT 1
				FROM IMOVH H
				WHERE H.CNSMOV = @CNSMOV
				  AND COALESCE(H.ESTADO, 0) = 1
				  AND COALESCE(H.CANTIDAD, 0) > 0
				  AND COALESCE(H.CANTIDAD, 0) > COALESCE((
						SELECT SUM(H2.CANTIDAD)
						FROM IMOV M2
						INNER JOIN IMOVH H2 ON H2.CNSMOV = M2.CNSMOV
						WHERE M2.PROCEDENCIA = 'DEVOLUCION'
						  AND M2.ESTADO = 1
						  AND M2.OBSERVACION LIKE 'Devolución de inventario - Movimiento origen: ' + @CNSMOV + '%'
						  AND H2.IDARTICULO = H.IDARTICULO
						  AND H2.NOLOTE = H.NOLOTE
						  AND COALESCE(H2.NOLOTEPEDIDO, '') = COALESCE(H.NOLOTEPEDIDO, '')
				  ), 0)
			)
				SET @ES_DEVOLUCION_TOTAL = 1

			-- Última entrada de devolución asociada (parcial o total)
			UPDATE IMOV
			SET CNSIDEV = @CNSMOV_ENTRADA,
				OBSERVACION = LEFT(
					COALESCE(OBSERVACION, '')
					+ CASE WHEN @ES_DEVOLUCION_TOTAL = 1
						THEN ' | Devolución TOTAL'
						ELSE ' | Devolución parcial ' + @CNSMOV_ENTRADA
					  END,
					500
				)
			WHERE CNSMOV = @CNSMOV

			-- Solo en devolución TOTAL: marcar y cerrar movimiento de salida
			IF @ES_DEVOLUCION_TOTAL = 1
			BEGIN
				UPDATE IMOV
				SET TIENE_DEVOLUCION = 1
				WHERE CNSMOV = @CNSMOV

				IF @CLASE_IZSOL = 'CE'
				BEGIN
					UPDATE IMOV
					SET ESTADO = 2,
						OBSERVACION = LEFT(
							COALESCE(OBSERVACION, '') + ' | Cerrado por devolución CE total',
							500
						)
					WHERE CNSMOV = @CNSMOV
					  AND PROCEDENCIA = 'CM_SOL'
					  AND ESTADO <> 2
				END
			END

			-- ========================================================================
			-- 9. Marcar solicitud origen (sin alterar CANTIDADSOL vs IZSOLDT)
			--    Debe PERMANECER CERRADA. Lo devuelto va a una NUEVA solicitud.
			-- ========================================================================
			IF @CNSIZSOL_BASE IS NOT NULL AND @CNSIZSOL_BASE <> ''
			BEGIN
				UPDATE IZSOL
				SET
					ESTADO = 2,
					MOTIVO_DEVOLUCION = CASE
						WHEN @ES_DEVOLUCION_TOTAL = 1 THEN @MOTIVO_DEVOLUCION
						ELSE LEFT(
							COALESCE(MOTIVO_DEVOLUCION + ' | ', '')
							+ 'Parcial: ' + @MOTIVO_DEVOLUCION,
							1048
						)
					END,
					USUARIO_DEVUELVE = @USUARIO,
					FECHA_DEVUELVE = GETDATE(),
					TIENE_DEVOLUCION = CASE
						WHEN @ES_DEVOLUCION_TOTAL = 1 THEN 1
						ELSE COALESCE(TIENE_DEVOLUCION, 0)
					END
				WHERE CNSIZSOL = @CNSIZSOL_BASE
			END

			-- ========================================================================
			-- 10. Siempre marcar ...-D + crear nueva solicitud solo con lo devuelto
			--     Movimiento salida: ESTADO=2 (CE) SOLO si devolución total
			-- ========================================================================
			IF @CNSIZSOL_BASE IS NOT NULL AND @CNSIZSOL_BASE <> ''
			BEGIN
				-- 10.1 Distintivo -D siempre (parcial o total)
				IF @CNSIZSOL_BASE NOT LIKE '%-D'
				BEGIN
					SET @CNSIZSOL_MARCADO = @CNSIZSOL_BASE + '-D'
					SET @CNSIZSOL_ANTES_MARCA = @CNSIZSOL_BASE

					WHILE EXISTS (SELECT 1 FROM IZSOL WHERE CNSIZSOL = @CNSIZSOL_MARCADO)
						AND EXISTS (SELECT 1 FROM IZSOL WHERE CNSIZSOL = @CNSIZSOL_BASE)
						SET @CNSIZSOL_MARCADO = @CNSIZSOL_MARCADO + '-D'

					IF EXISTS (SELECT 1 FROM IZSOL WHERE CNSIZSOL = @CNSIZSOL_BASE)
					   AND NOT EXISTS (SELECT 1 FROM IZSOL WHERE CNSIZSOL = @CNSIZSOL_MARCADO)
					BEGIN
						UPDATE IZSOL SET CNSIZSOL = @CNSIZSOL_MARCADO WHERE CNSIZSOL = @CNSIZSOL_BASE
						UPDATE IZSOLD SET CNSIZSOL = @CNSIZSOL_MARCADO WHERE CNSIZSOL = @CNSIZSOL_BASE
						UPDATE IMOV
						SET NODOCUMENTO = @CNSIZSOL_MARCADO
						WHERE NODOCUMENTO = @CNSIZSOL_ANTES_MARCA
						  AND PROCEDENCIA IN ('CM_SOL', 'Consumo')
						SET @CNSIZSOL_BASE = @CNSIZSOL_MARCADO
					END
				END
				ELSE
				BEGIN
					SET @CNSIZSOL_MARCADO = @CNSIZSOL_BASE
					SET @CNSIZSOL_ANTES_MARCA = LEFT(@CNSIZSOL_BASE, CHARINDEX('-D', @CNSIZSOL_BASE + '-D') - 1)
					IF @CNSIZSOL_ANTES_MARCA = '' SET @CNSIZSOL_ANTES_MARCA = @CNSIZSOL_BASE
				END

				-- Asegurar que la ...-D siga cerrada tras el rename
				UPDATE IZSOL
				SET ESTADO = 2
				WHERE CNSIZSOL = @CNSIZSOL_BASE
				  AND COALESCE(ESTADO, 0) <> 2

				-- 10.2 Generar nuevo CNSIZSOL
				DECLARE @INTENTOS_CNS INT = 0
				DECLARE @MAX_NUM BIGINT
				DECLARE @LEN_NUM INT = 10
				DECLARE @SEDE_IZSOL VARCHAR(5) = COALESCE(NULLIF(LTRIM(RTRIM(@SEDE)), ''), LEFT(@CNSIZSOL_ORIGEN, 2))

				IF LEN(@CNSIZSOL_ORIGEN) > 2 AND @CNSIZSOL_ORIGEN NOT LIKE '%-%'
					SET @LEN_NUM = LEN(@CNSIZSOL_ORIGEN) - LEN(@SEDE_IZSOL)
				IF @LEN_NUM < 6 SET @LEN_NUM = 8
				IF @LEN_NUM > 12 SET @LEN_NUM = 10

				SET @NUEVO_CNSIZSOL = NULL
				WHILE @INTENTOS_CNS < 30
				BEGIN
					SET @INTENTOS_CNS = @INTENTOS_CNS + 1
					SET @NVOCONSEC_IZSOL = NULL
					EXEC SPQ_GENSEQUENCE
						@SEDE = @SEDE_IZSOL,
						@PREFIJO = '@IZSOL',
						@LONGITUD = @LEN_NUM,
						@NVOCONSEC = @NVOCONSEC_IZSOL OUTPUT

					IF COALESCE(@NVOCONSEC_IZSOL, '') = '' CONTINUE

					IF LEFT(@NVOCONSEC_IZSOL, LEN(@SEDE_IZSOL)) = @SEDE_IZSOL
						SET @NUEVO_CNSIZSOL = @NVOCONSEC_IZSOL
					ELSE
						SET @NUEVO_CNSIZSOL = @SEDE_IZSOL
							+ RIGHT(REPLICATE('0', @LEN_NUM) + LTRIM(RTRIM(@NVOCONSEC_IZSOL)), @LEN_NUM)

					IF NOT EXISTS (SELECT 1 FROM IZSOL WITH (NOLOCK) WHERE CNSIZSOL = @NUEVO_CNSIZSOL)
						BREAK
					SET @NUEVO_CNSIZSOL = NULL
				END

				IF @NUEVO_CNSIZSOL IS NULL OR EXISTS (SELECT 1 FROM IZSOL WITH (NOLOCK) WHERE CNSIZSOL = @NUEVO_CNSIZSOL)
				BEGIN
					SELECT @MAX_NUM = MAX(TRY_CAST(
						CASE
							WHEN LEFT(CNSIZSOL, LEN(@SEDE_IZSOL)) = @SEDE_IZSOL
								THEN SUBSTRING(CNSIZSOL, LEN(@SEDE_IZSOL) + 1, 50)
							ELSE NULL
						END AS BIGINT))
					FROM IZSOL WITH (NOLOCK)
					WHERE CNSIZSOL LIKE @SEDE_IZSOL + '%'
