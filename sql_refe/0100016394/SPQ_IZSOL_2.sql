		SELECT @FECHA_HCA_CI = HCA.FECHA
		FROM HCA WITH (NOLOCK)
		WHERE HCA.CONSECUTIVO = @CONSECUTIVOHCA_CI

		SELECT 'OK' AS OK

		-- Candidatos: solo solicitudes (CNSIZSOL) que realmente tienen linea PR/IN del servicio
		-- ordenado por HCATD I/B de la admision. Asi la prioridad por HC impresa no elige un
		-- CNSIZSOL que carezca de la linea (que haria desaparecer la fila sin fallback).
		;WITH InicioHc AS (
			SELECT DISTINCT
				HCATD.IDSERVICIO
			   ,IZSOL.CNSIZSOL
			   ,IZSOL.CONSECUTIVOHCA
			   ,IZSOL.FECHASOL
			FROM HCATD WITH (NOLOCK)
			INNER JOIN IZSOL  WITH (NOLOCK)
				ON IZSOL.CONSECUTIVOHCA = HCATD.CONSECUTIVO
			   AND IZSOL.NOADMISION = @NOADMISION_CI
			INNER JOIN IZSOLD WITH (NOLOCK) ON IZSOLD.CNSIZSOL = IZSOL.CNSIZSOL
			INNER JOIN IART   WITH (NOLOCK) ON IART.IDARTICULO = IZSOLD.IDARTICULO
			WHERE HCATD.CLASE IN ('I', 'B')
			  AND COALESCE(IZSOLD.IDSERVICIO, IART.IDSERVICIO) = HCATD.IDSERVICIO
			  AND COALESCE(NULLIF(LTRIM(RTRIM(IZSOLD.TIPOM)), ''), 'PR') IN ('PR', 'IN')
			  AND (
					@FECHA_HCA_CI IS NULL
					-- Misma HC impresa: incluir aunque FECHASOL sea unos minutos posterior
					-- (IZSOL se genera al guardar la OM; HCA.FECHA queda antes).
				 OR (@CONSECUTIVOHCA_CI IS NOT NULL
					 AND IZSOL.CONSECUTIVOHCA = @CONSECUTIVOHCA_CI)
				 OR IZSOL.FECHASOL <= @FECHA_HCA_CI
			  )
		),
		SolicitudReciente AS (
			SELECT
				IDSERVICIO
			   ,CNSIZSOL
			   ,CONSECUTIVOHCA
			   ,ROW_NUMBER() OVER (
					PARTITION BY IDSERVICIO
					ORDER BY
						CASE WHEN CONSECUTIVOHCA = @CONSECUTIVOHCA_CI THEN 0 ELSE 1 END  -- 1) prioriza la HC impresa
					   ,FECHASOL DESC                                                    -- 2) la mas reciente
					   ,CNSIZSOL DESC                                                    -- 3) desempate deterministico
				 ) AS RN
			FROM InicioHc
		)
		SELECT
			COALESCE(IZSOLD.IDSERVICIO, IART.IDSERVICIO) AS IDSERVICIO
		   ,IZSOLD.IDARTICULO
		   ,COALESCE(NULLIF(LTRIM(RTRIM(MAX(IZSOLD.TIPOM))), ''), 'PR') AS TIPOM
		   ,SUM(IZSOLD.CANTIDADSOL) AS CANTIDADSOL
		   ,sr.CONSECUTIVOHCA
		   ,sr.CNSIZSOL
		FROM SolicitudReciente sr
		INNER JOIN IZSOLD WITH (NOLOCK) ON IZSOLD.CNSIZSOL = sr.CNSIZSOL
		INNER JOIN IART WITH (NOLOCK) ON IART.IDARTICULO = IZSOLD.IDARTICULO
		WHERE sr.RN = 1
		  AND COALESCE(IZSOLD.IDSERVICIO, IART.IDSERVICIO) = sr.IDSERVICIO
		  AND COALESCE(NULLIF(LTRIM(RTRIM(IZSOLD.TIPOM)), ''), 'PR') IN ('PR', 'IN')
		GROUP BY
			COALESCE(IZSOLD.IDSERVICIO, IART.IDSERVICIO)
		   ,IZSOLD.IDARTICULO
		   ,sr.CONSECUTIVOHCA
		   ,sr.CNSIZSOL
		ORDER BY IDSERVICIO, IDARTICULO

		RETURN
	END

