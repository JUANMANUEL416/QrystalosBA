CREATE OR ALTER PROCEDURE DBO.SPQ_IMOV_VENTA @JSON NVARCHAR(MAX)
	WITH ENCRYPTION
AS
SET DATEFORMAT dmy
DECLARE @TBLERRORES TABLE (ERROR VARCHAR(MAX))
DECLARE  @PARAMETROS NVARCHAR(MAX)			,@MODELO VARCHAR(100)			   ,@METODO VARCHAR(100)
		,@USUARIO VARCHAR(12)				   ,@COMPANIA VARCHAR(2)		      ,@IDSEDE      VARCHAR(5)		
      ,@SYS_COMPUTERNAME VARCHAR(200)     ,@DATOS    VARCHAR(MAX)          ,@SQL VARCHAR(MAX)
      ,@CNSMOV VARCHAR(20)                ,@MARCACONT BIT                  ,@IDTERCERO VARCHAR(20)
      ,@IDPLAN VARCHAR(6)                 ,@OBSERVACION VARCHAR(255)
      ,@IDBODEGA VARCHAR(20)              ,@IDTIPOMOV VARCHAR(2)           ,@NVOCONSEC VARCHAR(20)
      ,@CNSITRA VARCHAR(20)               ,@CLASEDEV VARCHAR(20)           ,@CANTDEV SMALLINT
      ,@IDARTICULO VARCHAR(20)            ,@NOLOTE VARCHAR(20)             ,@NOLOTEPEDIDO VARCHAR(20)
      ,@CONTABILIZADA BIT
BEGIN
	SELECT *
	INTO #JSON
	FROM OPENJSON(@json) WITH (
			MODELO VARCHAR(100) '$.MODELO'
			,METODO VARCHAR(100) '$.METODO'
			,USUARIO VARCHAR(12) '$.USUARIO'
			,PARAMETROS NVARCHAR(MAX) AS JSON
	)

	SELECT   @MODELO = MODELO			,@METODO = METODO
			,@PARAMETROS = PARAMETROS	,@USUARIO = USUARIO
	FROM #JSON
   SELECT @IDSEDE=COALESCE(UBEQ.IDSEDE,USUSU.IDSEDE),@COMPANIA=COALESCE(UBEQ.COMPANIA,USUSU.COMPANIA),  @SYS_COMPUTERNAME=COALESCE(USUSU.SYS_ComputerName,HOST_NAME())   FROM USUSU LEFT JOIN UBEQ ON USUSU.SYS_ComputerName=UBEQ.SYS_ComputerName
    WHERE USUSU.USUARIO=@USUARIO

   IF @METODO='MARCA_FACTURAR'     
   BEGIN         
      SELECT @CNSMOV=CNSMOV,@MARCACONT=MARCACONT,@IDTERCERO=IDTERCERO,@IDPLAN =IDPLAN       
      FROM   OPENJSON (@PARAMETROS)
      WITH (           
      CNSMOV  VARCHAR(20)   '$.CNSMOV',
      MARCACONT  BIT   '$.MARCACONT',
      IDTERCERO  VARCHAR(20)   '$.IDTERCERO',
      IDPLAN   VARCHAR(20)   '$.IDPLAN '
      )
      IF EXISTS(SELECT * FROM IMOV WHERE CNSMOV=@CNSMOV AND IDTERCERO=@IDTERCERO AND IDPLAN=@IDPLAN AND COALESCE(FACTURADA,0)=0 AND COALESCE(GENFACTURA,0)=1)
      BEGIN
         BEGIN TRY           
               UPDATE IMOV SET MARCACONT=@MARCACONT,USUENVIA=CASE @MARCACONT WHEN 1 THEN @USUARIO ELSE NULL END WHERE   CNSMOV=@CNSMOV AND IDTERCERO=@IDTERCERO AND IDPLAN=@IDPLAN AND COALESCE(FACTURADA,0)=0 AND COALESCE(GENFACTURA,0)=1            
         END TRY
         BEGIN CATCH
                 INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
         END CATCH  
      END
      ELSE
      BEGIN
         INSERT INTO @TBLERRORES(ERROR)
         SELECT 'Movimiento de Inventario no cumple con las condiciones para marcar factura '
      END
      IF(SELECT COUNT(*) FROM @TBLERRORES)>0
      BEGIN
         SELECT 'KO' OK, ERROR FROM @TBLERRORES
          RETURN
      END
      SELECT 'OK' OK,COUNT(*)as MARCADOS FROM IMOV 
      WHERE IDTERCERO=@IDTERCERO 
      AND IDPLAN=@IDPLAN 
      AND COALESCE(FACTURADA,0)=0 
      AND COALESCE(GENFACTURA,0)=1 
      AND MARCACONT=1 
      AND USUENVIA=@USUARIO
      RETURN 
   END  
   IF @METODO='FACTMASIVO_INV'     
   BEGIN         
      SELECT @IDTERCERO=IDTERCERO,@IDPLAN =IDPLAN       
      FROM   OPENJSON (@PARAMETROS)
      WITH (           
      IDTERCERO  VARCHAR(20)   '$.IDTERCERO',
      IDPLAN   VARCHAR(20)   '$.IDPLAN '
      )
      DECLARE @N_FACTURA VARCHAR(20)
      IF EXISTS(SELECT * FROM IMOV WHERE IDTERCERO=@IDTERCERO  AND IDPLAN=@IDPLAN AND COALESCE(FACTURADA,0)=0 AND COALESCE(GENFACTURA,0)=1    AND MARCACONT=1 AND USUENVIA=@USUARIO)  
      BEGIN
         BEGIN TRY           
             EXEC SPK_FAC_VENTA_INV_MASIVA @COMPANIA,@IDSEDE,@USUARIO,@IDTERCERO,@IDPLAN

             SELECT TOP 1 @N_FACTURA = N_FACTURA  FROM IMOV 
               WHERE IDTERCERO=@IDTERCERO 
               AND IDPLAN=@IDPLAN 
               AND COALESCE(FACTURADA,0)=1 
               AND COALESCE(GENFACTURA,0)=1 
               AND MARCACONT=1 
               AND USUENVIA=@USUARIO

            UPDATE IMOV SET MARCACONT=0,USUENVIA=NULL
               WHERE IDTERCERO=@IDTERCERO 
               AND IDPLAN=@IDPLAN 
               AND COALESCE(FACTURADA,0)=1 
               AND COALESCE(GENFACTURA,0)=1 
               AND MARCACONT=1 
               AND USUENVIA=@USUARIO

         END TRY
         BEGIN CATCH
                 INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
         END CATCH
         IF(SELECT COUNT(*) FROM @TBLERRORES)>0
         BEGIN
            SELECT 'KO' OK, ERROR FROM @TBLERRORES
             RETURN
         END
         SELECT 'OK' OK,@N_FACTURA N_FACTURA
         RETURN 
      END
   END
   IF @METODO='ANULA_IMOV_SALVENTA'     
   BEGIN         
      SELECT @CNSMOV=CNSMOV, @OBSERVACION=MOTIVO        
      FROM   OPENJSON (@PARAMETROS)
      WITH (           
      CNSMOV  VARCHAR(20)   '$.CNSMOV',
      MOTIVO  VARCHAR(200)   '$.MOTIVO'
      )
      IF EXISTS(SELECT * FROM IMOV WHERE CNSMOV=@CNSMOV AND ESTADO=1)
      BEGIN 
         SELECT @CNSMOV=CNSMOV,@IDBODEGA=IDBODEGA,@CLASEDEV='TOTAL' FROM IMOV WHERE CNSMOV=@CNSMOV
         SELECT @IDTIPOMOV=DBO.FNK_VALORVARIABLE('IDTIPOMOVDEV_CLIENTE')
         BEGIN TRY           
                             
            EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@MOV', @LONGITUD = 8, @NVOCONSEC = @NVOCONSEC OUTPUT 

            PRINT  '@NVOCONSEC='+@NVOCONSEC
		      INSERT INTO IMOV(CNSMOV, IDBODEGA, IDTIPOMOV, NODOCUMENTO, TIPODOCU,
								      FECHAMOV, CCOSTO, IDSOLICITA, IDTERCERO, IDFUNCIONARIO,
								      IDRECIBE, FACTORVENTA, ESTADO, IDBODEGAEXTERNA, CNSTRAN,
								      OBSERVACION, CNSFCOM, SUBIOCOMPRA, NOPRESTACION, IDAREA,
								      CONTABILIZADA, NROCOMPROBANTE, PROCEDENCIA, USUARIO,
								      USUARIOCONF, FECHACONF, PARCIAL, IDAREAH, NIVELATENCION, 
								      SYS_ComputerName, TIENECAMBIO, IDITAR, ESTRANSITO, CNSREP,CODUNG,CODPRG, CLASENC, CNSFNOT_DEV) 
            SELECT @NVOCONSEC, IDBODEGA, @IDTIPOMOV, @CNSITRA, TIPODOCU,
								      DBO.FNK_GETDATE(), CCOSTO, IDSOLICITA, IDTERCERO, IDFUNCIONARIO,
								      @USUARIO, FACTORVENTA, 0, IDBODEGAEXTERNA, CNSTRAN,
								      OBSERVACION, CNSFCOM, SUBIOCOMPRA, NOPRESTACION, IDAREA,
								      CONTABILIZADA, NROCOMPROBANTE, PROCEDENCIA, USUARIO,
								      USUARIOCONF, NULL, PARCIAL, IDAREAH, NIVELATENCION, 
								      @SYS_ComputerName, TIENECAMBIO, IDITAR, ESTRANSITO, CNSREP,CODUNG,CODPRG,NULL,NULL
            FROM IMOV 
            WHERE CNSMOV=@CNSMOV
            PRINT 'VOY POR EL DETALLE'
            IF @CLASEDEV='TOTAL'
            BEGIN
		         INSERT INTO IMOVH(CNSMOV, IDARTICULO, EXISTENCIA, CANTIDAD, CANTPEDIDA, PCOSTO,
						         NOLOTE, NOLOTEPEDIDO,FECHAVENCE, ESTADO, IDARTICULOTF,
						         CANTIDADTF, PCOSTOANTES, CNSTRAN, ITEM, PVENTA, USUARIO, 
						         USUARIOCONF, FECHACONF, PRIEXI, FECHAREPOSI, IDARTICULOORI,
						         CANTIDADORI, TIENECAMBIO,IDSERVICIO)
               SELECT @NVOCONSEC,ISAL.IDARTICULO,0,(ISAL.CANTIDAD-COALESCE(ISAL.CANTDEV,0)),(ISAL.CANTIDAD-COALESCE(ISAL.CANTDEV,0)),ISAL.PCOSTO,ISAL.NOLOTE,
                        ISAL.NOLOTEPEDIDO,ISAL.FECHAVENCE,0,ISAL.IDARTICULO,ISAL.CANTIDAD,ISAL.PCOSTO,NULL,NULL,NULL,@USUARIO,
                        NULL,NULL,NULL,NULL,NULL,NULL,NULL,IART.IDSERVICIO
               FROM ISAL INNER JOIN IART ON ISAL.IDARTICULO=IART.IDARTICULO
               WHERE ISAL.CNSMOV=@CNSMOV
               UPDATE IMOV SET ESTADO=2, OBSERVACION=@OBSERVACION,USUENVIA=@USUARIO WHERE CNSMOV=@CNSMOV
            END
            EXEC SPK_CONFIRMARENTRADAS @IDBODEGA,@NVOCONSEC,@USUARIO,@COMPANIA,@IDSEDE,@SYS_COMPUTERNAME
          END TRY
         BEGIN CATCH
                  INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
         END CATCH
      END
      ELSE
      BEGIN
         INSERT INTO @TBLERRORES(ERROR)
         SELECT 'El movimiento no esta Preparado para Anular '
      END
      IF(SELECT COUNT(*) FROM @TBLERRORES)>0
      BEGIN
         SELECT 'KO' OK, ERROR FROM @TBLERRORES
            RETURN
      END
      SELECT 'OK' OK 
      RETURN    
   END  
   IF @METODO='DEVUELVE_ARTICULO'     
   BEGIN         
      SELECT @DATOS=DATOS,@CANTDEV=CANTDEV        
      FROM   OPENJSON (@PARAMETROS)
      WITH (           
      DATOS NVARCHAR(MAX) AS JSON,
      CANTDEV SMALLINT   '$.CANTDEV'
      )   
      SELECT @CNSMOV=CNSMOV,@IDARTICULO=IDARTICULO,@NOLOTE=NOLOTE,@NOLOTEPEDIDO=NOLOTEPEDIDO      
      FROM   OPENJSON (@DATOS)
      WITH   (  
      CNSMOV  VARCHAR(20)   '$.CNSMOV',
      IDARTICULO  VARCHAR(20)   '$.IDARTICULO',
      NOLOTE  VARCHAR(20)   '$.NOLOTE',
      NOLOTEPEDIDO  VARCHAR(20)   '$.NOLOTEPEDIDO'
      )    
      IF EXISTS(SELECT * FROM IMOV WHERE CNSMOV=@CNSMOV AND ESTADO=1)
      BEGIN 
         SELECT @CNSMOV=CNSMOV,@IDBODEGA=IDBODEGA,@CLASEDEV='PARCIAL',@CONTABILIZADA=CONTABILIZADA FROM IMOV WHERE CNSMOV=@CNSMOV
         SELECT @IDTIPOMOV=DBO.FNK_VALORVARIABLE('IDTIPOMOVDEV_CLIENTE')
         BEGIN TRY           
                             
            EXEC SPQ_GENSEQUENCE @SEDE = @IDSEDE, @PREFIJO = '@MOV', @LONGITUD = 8, @NVOCONSEC = @NVOCONSEC OUTPUT 



            PRINT  '@NVOCONSEC='+@NVOCONSEC
		      INSERT INTO IMOV(CNSMOV, IDBODEGA, IDTIPOMOV, NODOCUMENTO, TIPODOCU,
								      FECHAMOV, CCOSTO, IDSOLICITA, IDTERCERO, IDFUNCIONARIO,
								      IDRECIBE, FACTORVENTA, ESTADO, IDBODEGAEXTERNA, CNSTRAN,
								      OBSERVACION, CNSFCOM, SUBIOCOMPRA, NOPRESTACION, IDAREA,
								      CONTABILIZADA, NROCOMPROBANTE, PROCEDENCIA, USUARIO,
								      USUARIOCONF, FECHACONF, PARCIAL, IDAREAH, NIVELATENCION, 
								      SYS_ComputerName, TIENECAMBIO, IDITAR, ESTRANSITO, CNSREP,CODUNG,CODPRG, CLASENC, CNSFNOT_DEV,SECONTABILIZA) 
            SELECT @NVOCONSEC, IDBODEGA, @IDTIPOMOV, @CNSMOV, TIPODOCU,
								      DBO.FNK_GETDATE(), CCOSTO, IDSOLICITA, IDTERCERO, IDFUNCIONARIO,
								      @USUARIO, FACTORVENTA, 0, IDBODEGAEXTERNA, CNSTRAN,
								      OBSERVACION, CNSFCOM, SUBIOCOMPRA, NOPRESTACION, IDAREA,
								      CONTABILIZADA, NROCOMPROBANTE, PROCEDENCIA, USUARIO,
								      USUARIOCONF, NULL, PARCIAL, IDAREAH, NIVELATENCION, 
								      @SYS_ComputerName, TIENECAMBIO, IDITAR, ESTRANSITO, CNSREP,CODUNG,CODPRG,NULL,NULL,
                              CASE WHEN COALESCE(@CONTABILIZADA,0)<>0 THEN 1 ELSE 0 END -- SI EL ORIGINAL NO ESTA CONTABILIZADO LA DEVOLUCION TAMPOCO
            FROM IMOV 
            WHERE CNSMOV=@CNSMOV
            PRINT 'VOY POR EL DETALLE'
            IF @CLASEDEV='PARCIAL'
            BEGIN
		         INSERT INTO IMOVH(CNSMOV, IDARTICULO, EXISTENCIA, CANTIDAD, CANTPEDIDA, PCOSTO,
						         NOLOTE, NOLOTEPEDIDO,FECHAVENCE, ESTADO, IDARTICULOTF,
						         CANTIDADTF, PCOSTOANTES, CNSTRAN, ITEM, PVENTA, USUARIO, 
						         USUARIOCONF, FECHACONF, PRIEXI, FECHAREPOSI, IDARTICULOORI,
						         CANTIDADORI, TIENECAMBIO,IDSERVICIO)
               SELECT @NVOCONSEC,ISAL.IDARTICULO,0,@CANTDEV,@CANTDEV,ISAL.PCOSTO,ISAL.NOLOTE,
                        ISAL.NOLOTEPEDIDO,ISAL.FECHAVENCE,0,ISAL.IDARTICULO,ISAL.CANTIDAD,ISAL.PCOSTO,NULL,NULL,NULL,@USUARIO,
                        NULL,NULL,NULL,NULL,NULL,NULL,NULL,IART.IDSERVICIO
               FROM ISAL INNER JOIN IART ON ISAL.IDARTICULO=IART.IDARTICULO
               WHERE ISAL.CNSMOV=@CNSMOV
               AND ISAL.IDARTICULO=@IDARTICULO
               AND ISAL.NOLOTE=@NOLOTE
               AND ISAL.NOLOTEPEDIDO=@NOLOTEPEDIDO
            END
            UPDATE ISAL SET CANTDEV=COALESCE(CANTDEV,0)+@CANTDEV 
            WHERE CNSMOV=@CNSMOV AND IDARTICULO=@IDARTICULO
            AND NOLOTE=@NOLOTE
            AND NOLOTEPEDIDO=@NOLOTEPEDIDO

            EXEC SPK_CONFIRMARENTRADAS @IDBODEGA,@NVOCONSEC,@USUARIO,@COMPANIA,@IDSEDE,@SYS_COMPUTERNAME
            IF NOT EXISTS(SELECT * FROM ISAL WHERE CNSMOV=@CNSMOV AND CANTIDAD-COALESCE(CANTDEV,0)>0) AND COALESCE(@CONTABILIZADA,0)=0
            BEGIN
               PRINT 'Marco el movimiento de salida como que no se contabiliza'
               UPDATE IMOV SET SECONTABILIZA=0 WHERE CNSMOV=@CNSMOV
            END
          END TRY
         BEGIN CATCH
                  INSERT INTO @TBLERRORES(ERROR) SELECT ERROR_MESSAGE()
         END CATCH
      END
      ELSE
      BEGIN
         INSERT INTO @TBLERRORES(ERROR)
         SELECT 'El movimiento no esta Preparado para Anular '
      END
      IF(SELECT COUNT(*) FROM @TBLERRORES)>0
      BEGIN
         SELECT 'KO' OK, ERROR FROM @TBLERRORES
            RETURN
      END
      SELECT 'OK' OK 
   END
   IF @METODO='LIMPIA_MARCAS'     
   BEGIN    
      IF EXISTS(SELECT * FROM IMOV WHERE MARCACONT=1 AND USUENVIA=@USUARIO AND IDTIPOMOV=DBO.FNK_VALORVARIABLE('IDINVMOVVENTAFACTURA'))
      BEGIN
         UPDATE IMOV SET MARCACONT=0,USUENVIA=NULL WHERE MARCACONT=1 AND USUENVIA=@USUARIO 
      END
      SELECT 'OK'OK
      RETURN
   END  
   IF @METODO='ANEXO_PREVIO'     
   BEGIN         
      SELECT @DATOS=DATOS        
      FROM   OPENJSON (@PARAMETROS)
      WITH (           
      DATOS  VARCHAR(MAX)   '$.WHERE'
      )
      SELECT 'OK'OK
      
      SET @SQL='
      SELECT TOP 1 TER.NIT,TER.RAZONSOCIAL,PLN.IDPLAN,PLN.DESCPLAN,
      CASE WHEN DB_NAME()=DBO.FNK_VALORVARIABLE(''BDATA_PRODUCCION'') THEN ''OK'' ELSE ''DEMO'' END DEMO,
      '''+@USUARIO+''' USUARIO,'''+@SYS_COMPUTERNAME+''' EQUIPO, DBO.FNK_FECHA_DDMMAA(GETDATE())+'' ''+LEFT(CONVERT(VARCHAR,GETDATE(),108),10) FIMPRESION      
      FROM IMOV INNER JOIN TER ON IMOV.IDTERCERO=TER.IDTERCERO
                INNER JOIN PLN ON IMOV.IDPLAN=PLN.IDPLAN
      WHERE '+LTRIM(RTRIM(@DATOS))
      PRINT @SQL
      EXEC (@SQL)
      SET @SQL='
      SELECT ROW_NUMBER() OVER ( ORDER BY IMOV.CNSMOV) ITEM,IMOV.CNSMOV,DBO.FNK_FECHA_DDMMAA(IMOV.FECHACONF)FECHACONF,IMOV.IDAREA,IMOV.CCOSTO, PREFIJO=D.PREFIJO, 
		      CASE WHEN dbo.FNK_VALORVARIABLE(''CLASE_IPS'') = ''OPTICA'' THEN  CASE WHEN COALESCE(F.GARANTIA, 0) = 0 THEN COALESCE(C.DESCRIPCION, '''')+'' ''+''Producto sin Garantia''
																											      ELSE COALESCE(C.DESCRIPCION, '''')+'' ''+COALESCE(F.COMENTARIOS, '''')
																											      END
																			     ELSE C.DESCRIPCION
																			     END ANEXO,
		        E.IDARTICULO,C.IDSERVICIO,CONVERT(INT,(E.CANTIDAD-COALESCE(E.CANTDEV,0))) CANTIDAD, 
              CONVERT(DECIMAL(14,2),DBO.FNK_VALORSERVICIO(IMOV.IDTERCERO, IMOV.IDPLAN, E.IDARTICULO, '''', IMOV.FECHACONF,E.PCOSTO)) VLR_UNIT, 
              CONVERT(DECIMAL(14,2),DBO.FNK_VALORSERVICIO(IMOV.IDTERCERO, IMOV.IDPLAN, E.IDARTICULO, '''', IMOV.FECHACONF,E.PCOSTO) * (E.CANTIDAD-COALESCE(E.CANTDEV,0)))VLR_TOTAL, 
              VALORCOPAGO = 0, VALORPCOMP = 0, IDPROVEEDOR = NULL, NOADMISION=IMOV.CNSMOV,TER.NIT NITPROVE, TER.RAZONSOCIAL AS RAZONPROV, TERF.NIT NITFABRI,TERF.RAZONSOCIAL RAZONFABRI,
              E.PCOSTO,E.NOLOTE,E.NOLOTEPEDIDO
       FROM   IMOV  INNER JOIN ISAL  E ON IMOV.CNSMOV     = E.CNSMOV 
	                  LEFT JOIN IART  C ON E.IDARTICULO = C.IDARTICULO 
                     LEFT JOIN ITAR  D ON C.IDITAR     = D.IDITAR
				         LEFT JOIN SER   F ON C.IDSERVICIO = F.IDSERVICIO
                     LEFT JOIN IEXI  ON E.IDARTICULO=IEXI.IDARTICULO AND E.NOLOTE=IEXI.NOLOTE AND E.NOLOTEPEDIDO=IEXI.NOLOTEPEDIDO AND COALESCE(IEXI.CNSFCOM,'''')<>''''
                     LEFT JOIN IMOV G ON IEXI.CNSMOV=G.CNSMOV
                     LEFT JOIN TER ON G.IDTERCERO=TER.IDTERCERO
                     LEFT JOIN TER TERF ON C.IDFABRICANTE=TERF.IDTERCERO
      WHERE '+LTRIM(RTRIM(@DATOS))
      PRINT @SQL
      EXEC (@SQL)
      RETURN
   END  
END

