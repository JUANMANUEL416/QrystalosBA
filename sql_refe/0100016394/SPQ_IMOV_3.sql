			RETURN
		END

		DECLARE @CNSMOV_CUFE VARCHAR(20) = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.CNSMOV'))), '')
		DECLARE @CUFE_IMOV VARCHAR(96) = LEFT(NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.CUFE'))), ''), 96)
		DECLARE @IDINVMOV_COMPRAS_CUFE VARCHAR(20) = DBO.FNK_VALORVARIABLE('IDINVMOV_COMPRAS')

		IF @CNSMOV_CUFE IS NULL
		BEGIN
			SELECT 'KO' AS OK
			SELECT 'Debe indicar CNSMOV' AS ERROR
			RETURN
		END

		IF @CUFE_IMOV IS NULL
		BEGIN
			SELECT 'KO' AS OK
			SELECT 'Debe indicar el CUFE del proveedor' AS ERROR
			RETURN
		END

		IF NOT EXISTS (SELECT 1 FROM IMOV WHERE CNSMOV = @CNSMOV_CUFE)
		BEGIN
			SELECT 'KO' AS OK
			SELECT 'El movimiento no existe' AS ERROR
			RETURN
		END

		IF EXISTS (SELECT 1 FROM IMOV WHERE CNSMOV = @CNSMOV_CUFE AND COALESCE(ESTADO, 0) = 2)
		BEGIN
			SELECT 'KO' AS OK
			SELECT 'No se puede registrar CUFE en un movimiento anulado' AS ERROR
			RETURN
		END

		IF NOT EXISTS (
			SELECT 1 FROM IMOV
			WHERE CNSMOV = @CNSMOV_CUFE
			  AND IDTIPOMOV = @IDINVMOV_COMPRAS_CUFE
			  AND COALESCE(CNSFCOM, '') <> ''
		)
		BEGIN
			SELECT 'KO' AS OK
			SELECT 'El CUFE solo aplica a entradas por orden de compra' AS ERROR
			RETURN
		END

		UPDATE IMOV
		SET CUFE = @CUFE_IMOV
		WHERE CNSMOV = @CNSMOV_CUFE
		  AND COALESCE(ESTADO, 0) <> 2
		  AND IDTIPOMOV = @IDINVMOV_COMPRAS_CUFE
		  AND COALESCE(CNSFCOM, '') <> ''

		SELECT 'OK' AS OK, @CNSMOV_CUFE AS CNSMOV, @CUFE_IMOV AS CUFE
		RETURN
	END

	-- ============================================================
	-- Plantilla Excel: entradas por compra sin CUFE
	-- ============================================================
	IF @METODO = 'PLANTILLA_CUFE'
	BEGIN
		IF COL_LENGTH('dbo.IMOV', 'CUFE') IS NULL
		BEGIN
			SELECT 'KO' AS OK
			SELECT 'Falta la columna IMOV.CUFE. Ejecute sql/DDL_IMOV_CUFE.sql' AS ERROR
			RETURN
		END

		DECLARE @IDBODEGA_CUFE_IMOV VARCHAR(20) = NULLIF(LTRIM(RTRIM(JSON_VALUE(@PARAMETROS, '$.IDBODEGA'))), '')
		DECLARE @IDINVMOV_COMPRAS_PLT VARCHAR(20) = DBO.FNK_VALORVARIABLE('IDINVMOV_COMPRAS')

		SELECT 'OK' AS OK
		SELECT
			IMOV.CNSMOV,
			IMOV.CNSFCOM,
			CASE
				WHEN IMOV.TIPO_DOC_COMPRA = 'F'
					THEN COALESCE(NULLIF(IMOV.NODOCUMENTO, ''), NULLIF(IMOV.N_FACTURA, ''), NULLIF(FCOM.N_FACTURA, ''), '')
				ELSE COALESCE(NULLIF(IMOV.N_FACTURA, ''), NULLIF(FCOM.N_FACTURA, ''), NULLIF(IMOV.NODOCUMENTO, ''), '')
			END AS N_FACTURA,
			CONVERT(VARCHAR(10), COALESCE(IMOV.F_FACTURA, FCOM.F_FACTURA, IMOV.FECHAMOV), 23) AS F_FACTURA,
			CASE COALESCE(IMOV.ESTADO, 0) WHEN 1 THEN 'Confirmado' WHEN 0 THEN 'Sin Confirmar' ELSE 'Anulado' END AS ESTADO,
			COALESCE(TER.NIT, '') AS NIT,
			COALESCE(TER.RAZONSOCIAL, '') AS RAZONSOCIAL,
			CAST('' AS VARCHAR(96)) AS CUFE
		FROM IMOV WITH (NOLOCK)
		LEFT JOIN FCOM WITH (NOLOCK) ON FCOM.CNSFCOM = IMOV.CNSFCOM
		LEFT JOIN TER WITH (NOLOCK)
			ON TER.IDTERCERO = COALESCE(NULLIF(IMOV.IDTERCERO, ''), FCOM.IDTERCERO)
		WHERE IMOV.IDTIPOMOV = @IDINVMOV_COMPRAS_PLT
		  AND COALESCE(IMOV.CNSFCOM, '') <> ''
		  AND COALESCE(IMOV.ESTADO, 0) <> 2
		  AND COALESCE(IMOV.CUFE, '') = ''
		  AND (@IDBODEGA_CUFE_IMOV IS NULL OR IMOV.IDBODEGA = @IDBODEGA_CUFE_IMOV)
		ORDER BY IMOV.FECHAMOV DESC, IMOV.CNSMOV DESC

		RETURN
	END

	-- ============================================================
	-- Carga masiva CUFE desde Excel (JSON: CNSMOV, CUFE)
	-- ============================================================
	IF @METODO = 'CARGAR_CUFE_MASIVO'
	BEGIN
		IF COL_LENGTH('dbo.IMOV', 'CUFE') IS NULL
		BEGIN
			SELECT 'KO' AS OK
			SELECT 'Falta la columna IMOV.CUFE. Ejecute sql/DDL_IMOV_CUFE.sql' AS ERROR
			RETURN
		END

		DECLARE @DATOS_CUFE_IMOV NVARCHAR(MAX) = JSON_QUERY(@PARAMETROS, '$.DATOS')
		IF @DATOS_CUFE_IMOV IS NULL OR ISJSON(@DATOS_CUFE_IMOV) <> 1
		BEGIN
			SELECT 'KO' AS OK
			SELECT 'No se recibieron datos válidos para actualizar CUFE.' AS ERROR
			RETURN
		END

		DECLARE @IDINVMOV_COMPRAS_MAS VARCHAR(20) = DBO.FNK_VALORVARIABLE('IDINVMOV_COMPRAS')
		DECLARE @RES_CUFE_IMOV TABLE (
			CNSMOV VARCHAR(20),
			CUFE VARCHAR(96),
			OK BIT,
			MENSAJE VARCHAR(200)
		)

		;WITH SRC AS (
			SELECT
				NULLIF(LTRIM(RTRIM(J.CNSMOV)), '') AS CNSMOV,
				LEFT(NULLIF(LTRIM(RTRIM(J.CUFE)), ''), 96) AS CUFE
			FROM OPENJSON(@DATOS_CUFE_IMOV)
			WITH (
				CNSMOV VARCHAR(20) '$.CNSMOV',
				CUFE VARCHAR(96) '$.CUFE'
			) J
		)
		INSERT INTO @RES_CUFE_IMOV (CNSMOV, CUFE, OK, MENSAJE)
		SELECT
			S.CNSMOV,
			S.CUFE,
			CASE
				WHEN S.CNSMOV IS NULL THEN 0
				WHEN S.CUFE IS NULL THEN 0
				WHEN M.CNSMOV IS NULL THEN 0
				WHEN COALESCE(M.ESTADO, 0) = 2 THEN 0
				WHEN M.IDTIPOMOV <> @IDINVMOV_COMPRAS_MAS OR COALESCE(M.CNSFCOM, '') = '' THEN 0
				ELSE 1
			END,
			CASE
				WHEN S.CNSMOV IS NULL THEN 'CNSMOV vacío'
				WHEN S.CUFE IS NULL THEN 'CUFE vacío'
				WHEN M.CNSMOV IS NULL THEN 'Movimiento no existe'
				WHEN COALESCE(M.ESTADO, 0) = 2 THEN 'Movimiento anulado'
				WHEN M.IDTIPOMOV <> @IDINVMOV_COMPRAS_MAS OR COALESCE(M.CNSFCOM, '') = '' THEN 'No es entrada por orden de compra'
				ELSE 'OK'
			END
		FROM SRC S
		LEFT JOIN IMOV M ON M.CNSMOV = S.CNSMOV

		UPDATE M
		SET M.CUFE = R.CUFE
		FROM IMOV M
		INNER JOIN @RES_CUFE_IMOV R ON R.CNSMOV = M.CNSMOV
		WHERE R.OK = 1

		SELECT 'OK' AS OK,
			(SELECT COUNT(*) FROM @RES_CUFE_IMOV WHERE OK = 1) AS ACTUALIZADOS,
			(SELECT COUNT(*) FROM @RES_CUFE_IMOV WHERE OK = 0) AS ERRORES

		SELECT CNSMOV, CUFE, OK, MENSAJE
		FROM @RES_CUFE_IMOV
		ORDER BY OK, CNSMOV

		RETURN
	END

   /* Método no pertenece a SPQ_IMOV_3 */
   SELECT 'KO' OK, 'Método no soportado en SPQ_IMOV_3: ' + COALESCE(@METODO, '(NULL)') AS ERROR
   RETURN

   END TRY
   BEGIN CATCH
      /* Solo deshacer transacciones propias; si XACT_ABORT dejó la TX doomed, rollback obligatorio */
      IF XACT_STATE() = -1
         ROLLBACK TRAN;
      ELSE IF @TRANCOUNT_INICIAL = 0 AND @@TRANCOUNT > 0
         ROLLBACK TRAN;

      SELECT 'KO' OK,
             ERROR_MESSAGE() AS ERROR,
             ERROR_NUMBER() AS ERROR_NUMBER,
             ERROR_LINE() AS ERROR_LINE,
             COALESCE(ERROR_PROCEDURE(), 'SPQ_IMOV_3') AS ERROR_PROCEDURE;
      RETURN
   END CATCH
