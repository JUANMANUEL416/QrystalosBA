			) PRES ON IART.PRECOMERCIAL = PRES.CODIGO
			LEFT JOIN ITRAH WITH (NOLOCK) ON ITRAH.CNSITRA = IMOV.CNSITRA
				AND IMOVH.IDARTICULO = ITRAH.IDARTICULO
				AND IMOVH.NOLOTE = ITRAH.NOLOTE
		WHERE IMOV.IDTIPOMOV = @IDTIPOMOV_CUST_T
		  AND IMOV.IDTERCERO = @IDTERCERO_CUST_T
		  AND (@FDESDE IS NULL OR IMOV.FECHAMOV >= CAST(@FDESDE AS DATETIME))
		  AND (@FHASTA IS NULL OR IMOV.FECHAMOV < DATEADD(DAY, 1, CAST(@FHASTA AS DATETIME)))
		  AND IMOV.IDBODEGA = COALESCE(@IDBODEGA_CUST_T, IMOV.IDBODEGA)
		  AND (@ESTADO_CUST_T IS NULL OR IMOV.ESTADO = @ESTADO_CUST_T)
		GROUP BY
			COALESCE(IMOV.CNSITRA, ''),
			COALESCE(AFI.NOMBREAFI, ''),
