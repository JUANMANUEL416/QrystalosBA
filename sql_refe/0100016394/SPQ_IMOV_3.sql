				OR IMOV.CNSMOV > COALESCE(@ULTIMO_CNSMOV_SYNC_CUFE, @DESDE_CNSMOV_SYNC_CUFE)
		  )

		SELECT
			@ACTUALIZADOS_SYNC_CUFE = COALESCE(SUM(ACTUALIZADOS), 0),
			@AMBIGUOS_SYNC_CUFE = COALESCE(SUM(AMBIGUOS), 0),
			@SIN_COINCIDENCIA_SYNC_CUFE = COALESCE(SUM(SIN_COINCIDENCIA), 0),
			@ERRORES_SYNC_CUFE = COALESCE(SUM(CASE WHEN ERROR IS NULL THEN 0 ELSE 1 END), 0)
		FROM @RESULTADO_LOTE_SYNC_CUFE

		SELECT
			'OK' AS OK,
			@TOTAL_LOTE_SYNC_CUFE AS REVISADOS,
			@ACTUALIZADOS_SYNC_CUFE AS ACTUALIZADOS,
			@AMBIGUOS_SYNC_CUFE AS AMBIGUOS,
			@SIN_COINCIDENCIA_SYNC_CUFE AS SIN_COINCIDENCIA,
			@ERRORES_SYNC_CUFE AS ERRORES,
			COALESCE(@ULTIMO_CNSMOV_SYNC_CUFE, @DESDE_CNSMOV_SYNC_CUFE, '') AS ULTIMO_CNSMOV,
			@PENDIENTES_SYNC_CUFE AS PENDIENTES,
			CAST(CASE WHEN @PENDIENTES_SYNC_CUFE = 0 THEN 1 ELSE 0 END AS BIT) AS FINALIZADO,
			@FECHA_INI_SYNC_CUFE AS FECHA_INI,
			@FECHA_FIN_SYNC_CUFE AS FECHA_FIN,
			DATEDIFF(MILLISECOND, @INICIO_LOTE_SYNC_CUFE, SYSDATETIME()) AS DURACION_MS

		SELECT
			ITEM,
			CNSMOV,
			ACTUALIZADOS,
			AMBIGUOS,
			SIN_COINCIDENCIA,
			ERROR
		FROM @RESULTADO_LOTE_SYNC_CUFE
		ORDER BY ITEM

