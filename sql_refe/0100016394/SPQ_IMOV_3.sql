			CASE
				WHEN @IDINVMOV_DISPEN_NUM IS NOT NULL
					AND TRY_CONVERT(INT, IMOV.IDTIPOMOV) = @IDINVMOV_DISPEN_NUM
				THEN COALESCE(AFI_CNSTRAN.DOCIDAFILIADO, AFI_IZSOL.DOCIDAFILIADO, AFI_HADM.DOCIDAFILIADO, '')
				ELSE ''
			END AS DOCUMENTO_PACIENTE,
			CASE
				WHEN @IDINVMOV_DISPEN_NUM IS NOT NULL
					AND TRY_CONVERT(INT, IMOV.IDTIPOMOV) = @IDINVMOV_DISPEN_NUM
				THEN COALESCE(AFI_CNSTRAN.NOMBREAFI, AFI_IZSOL.NOMBREAFI, AFI_HADM.NOMBREAFI, '')
				ELSE ''
			END AS NOMBRE_PACIENTE,
			IMOV.CNSFCOM AS NRO_COMPRA,
			CASE IMOV.TIPO_DOC_COMPRA 
				WHEN 'F' THEN 'Factura'
				WHEN 'R' THEN 'Remisión'
				WHEN 'N' THEN 'No Aplica'
			END AS TIPO_DOCUMENTO,
			IMOV.NODOCUMENTO AS NRO_FACTURA_O_REMISION,
			CONVERT(VARCHAR(10), IMOV.F_FACTURA, 23) AS FECHA_FACTURA,
			CONVERT(VARCHAR(10), IMOV.F_VENCE, 23) AS FECHA_VENCIMIENTO_FACTURA,
			IART.IDARTICULO AS [COD.ARTICULO],
			DETALLE_EFECTIVO.NOLOTE AS LOTE_INTERNO,
			DETALLE_EFECTIVO.NOLOTEPEDIDO AS LOTE_ARTICULO,
			IART.DESCRIPCION AS ARTICULO,
			DETALLE_EFECTIVO.CANTIDAD AS CANTIDAD,
			DETALLE_EFECTIVO.PCOSTO AS COSTO,
			DETALLE_EFECTIVO.PVENTA AS PRECIO,
			CONVERT(VARCHAR(10), IMOV.FECHAMOV, 23) AS FECHA_FECHAMOVIMIENTO,
			CONVERT(VARCHAR(10), DETALLE_EFECTIVO.FECHACONF, 23) AS FECHA_CONFIRMACION,
			(DETALLE_EFECTIVO.CANTIDAD * DETALLE_EFECTIVO.PVENTA) AS TOTAL,
			ITAR.DESCRIPCION AS TIPOARTICULO,
			TER.NIT AS NIT_PROVEEDOR,
			TER.RAZONSOCIAL AS PROVEEDOR_OC,
			USUSU_SOLI.NOMBRE AS SOLICITANTE,
			BOD_ORIGEN.DESCRIPCION AS [BODEGA ORIGEN],
			IMOV.OBSERVACION AS OBSERVACION
		FROM IMOV
		INNER JOIN DETALLE_EFECTIVO ON IMOV.CNSMOV = DETALLE_EFECTIVO.CNSMOV
		INNER JOIN IART ON DETALLE_EFECTIVO.IDARTICULO = IART.IDARTICULO
		LEFT JOIN ITAR ON IART.IDITAR = ITAR.IDITAR
		INNER JOIN IBOD ON IMOV.IDBODEGA = IBOD.IDBODEGA
		INNER JOIN ITMO ON IMOV.IDTIPOMOV = ITMO.IDTIPOMOV
		LEFT JOIN TER ON IMOV.IDTERCERO = TER.IDTERCERO
		LEFT JOIN USUSU USUSU_SOLI ON IMOV.IDSOLICITA = USUSU_SOLI.USUARIO
		LEFT JOIN IBOD BOD_ORIGEN ON IMOV.IDBODEGAEXTERNA = BOD_ORIGEN.IDBODEGA
		LEFT JOIN AFI AFI_CNSTRAN ON AFI_CNSTRAN.IDAFILIADO = COALESCE(
			NULLIF(LTRIM(RTRIM(DETALLE_EFECTIVO.CNSTRAN)), ''),
			NULLIF(LTRIM(RTRIM(IMOV.CNSTRAN)), '')
		)
		LEFT JOIN IZSOL ON IMOV.NODOCUMENTO = IZSOL.CNSIZSOL
		LEFT JOIN HADM HADM_IZ ON IZSOL.NOADMISION = HADM_IZ.NOADMISION AND IZSOL.CLASE NOT IN ('FORMEDCE', 'HPRE')
		LEFT JOIN QXPCX QXPCX_IZ ON QXPCX_IZ.CONSECUTIVO = IZSOL.CNSIZSOLM AND IZSOL.CLASE = 'QXPGCX'
		LEFT JOIN HADM H_IZ ON QXPCX_IZ.NOADMISION = H_IZ.NOADMISION AND IZSOL.CLASE = 'QXPGCX'
		LEFT JOIN CXPS CXPS_IZ ON CXPS_IZ.NOPROGRAMACION = CASE
			WHEN IZSOL.CLASE = 'QXPGCX' AND LEN(IZSOL.NOADMISION) < 10 THEN IZSOL.NOADMISION
			ELSE '9999'
		END
		LEFT JOIN CIT CIT_IZ ON IZSOL.NOADMISION = CIT_IZ.CONSECUTIVO AND IZSOL.CLASE = 'ONCO'
		LEFT JOIN AUT AUT_IZ ON IZSOL.NOADMISION = AUT_IZ.IDAUT AND IZSOL.CLASE = 'CE'
		LEFT JOIN APLIM APLIM_IZ ON IZSOL.NOADMISION = CAST(APLIM_IZ.ID AS VARCHAR) AND IZSOL.CLASE = 'APLIM'
		LEFT JOIN APLI APLI_IZ ON APLIM_IZ.IDAPLI = APLI_IZ.ID AND IZSOL.CLASE = 'APLIM'
		LEFT JOIN AFI AFI_IZSOL ON AFI_IZSOL.IDAFILIADO = CASE
			WHEN IZSOL.CLASE = 'QXPGCX' AND LEN(IZSOL.CNSIZSOLM) < 10 THEN CXPS_IZ.IDAFILIADO
			WHEN IZSOL.CLASE = 'QXPGCX' AND LEN(IZSOL.CNSIZSOLM) >= 10 THEN H_IZ.IDAFILIADO
			WHEN IZSOL.CLASE = 'APLIM' THEN APLI_IZ.IDAFILIADO
			WHEN IZSOL.CLASE = 'CE' THEN AUT_IZ.IDAFILIADO
			WHEN IZSOL.CLASE = 'ONCO' THEN CIT_IZ.IDAFILIADO
			WHEN IZSOL.CLASE IN ('FORMEDCE', 'HPRE') THEN IZSOL.NOADMISION
			ELSE HADM_IZ.IDAFILIADO
		END
		LEFT JOIN HADM HADM_NODOC ON IMOV.NODOCUMENTO = HADM_NODOC.NOADMISION
		LEFT JOIN AFI AFI_HADM ON AFI_HADM.IDAFILIADO = HADM_NODOC.IDAFILIADO
		WHERE
			/* Mismo criterio de fechas que la grilla: siempre FECHAMOV */
			(@FDESDE IS NULL OR CONVERT(DATE, IMOV.FECHAMOV) >= CONVERT(DATE, @FDESDE))
			AND (@FHASTA IS NULL OR CONVERT(DATE, IMOV.FECHAMOV) <= CONVERT(DATE, @FHASTA))
			AND (NULLIF(@IDBODEGA, '') IS NULL OR IMOV.IDBODEGA = @IDBODEGA)
			AND (@ESTADO IS NULL OR IMOV.ESTADO = @ESTADO)
			AND (@ESTADO_PICKPACK_PARAM IS NULL OR COALESCE(IMOV.ESTADO_PICKPACK, 0) = @ESTADO_PICKPACK_PARAM)
			AND (
				@ESTADO_PICKPACK_PARAM IS NULL
				OR EXISTS (
					SELECT 1
					FROM STRING_SPLIT(COALESCE(DBO.FNK_VALORVARIABLE('IDMOVPICKPACK'), ''), ',') S
					WHERE LTRIM(RTRIM(S.value)) <> ''
					  AND LTRIM(RTRIM(S.value)) = IMOV.IDTIPOMOV
				)
			)
			/* Filtro tipo artículo: igual que la grilla (cabecera IMOV.IDITAR) */
			AND (NULLIF(@IDITAR, '') IS NULL OR IMOV.IDITAR = @IDITAR)
			AND (NULLIF(@MOVIMIENTO, '') IS NULL OR IMOV.IDTIPOMOV = @MOVIMIENTO)
			AND (@TIPO_MOV_PARAM IS NULL OR ITMO.TIPO = @TIPO_MOV_PARAM)
			AND (@IDTIPOMOV_NUM IS NULL OR TRY_CONVERT(INT, IMOV.IDTIPOMOV) = @IDTIPOMOV_NUM)
			AND (
				@IDINVMOV_COMPRAS_NUM IS NULL
				OR @IDTIPOMOV_NUM IS NULL
				OR @IDTIPOMOV_NUM <> @IDINVMOV_COMPRAS_NUM
				OR COALESCE(IMOV.CNSFCOM, '') <> ''
			)
		ORDER BY IMOV.FECHAMOV DESC, IMOV.CNSMOV, IART.IDARTICULO
	END

