			INNER JOIN IART WITH (NOLOCK) ON IMOVH.IDARTICULO = IART.IDARTICULO
			LEFT JOIN AFI WITH (NOLOCK) ON AFI.IDAFILIADO = COALESCE(NULLIF(IMOVH.CNSTRAN, ''), IMOV.CNSTRAN)
			LEFT JOIN IFFA WITH (NOLOCK) ON IFFA.IDFORFARM = IART.IDFORFARM
			LEFT JOIN (
