CREATE OR ALTER PROCEDURE SPQ_GENERANOTADB_DEVOLUCION_INV
@CNSMOVDEV    VARCHAR(20),
@CNSMOVCOMPRA VARCHAR(20),
@USUARIO  VARCHAR(12),
@COMPANIA VARCHAR(2),
@SEDE     VARCHAR(5),
@SYS_COMPUTERNAME VARCHAR(20)
WITH ENCRYPTION
AS
DECLARE @CONCEPTONOTA VARCHAR(20),
        @CNSFCOM      VARCHAR(20),
        @CNSFCXP      VARCHAR(20),
        @IDTERCERO    VARCHAR(20),
        @NODOCUMENTO  VARCHAR(20),
        @ESTADOCXP    VARCHAR(3),
        @SALDOCXP     DECIMAL(14,2),
        @CUENTACR     VARCHAR(20),
        @CUENTADB     VARCHAR(20),
        @VALOR        DECIMAL(14,2),
        @CCOSTO       VARCHAR(20),
        @ITEM         INT,
        @DESCUENTOS   DECIMAL(14,2),
		  @IVA          INT,
        @VALORCONIVA  DECIMAL(14,2),
        @VALORSINIVA  DECIMAL(14,2),
        @VLRNETO      DECIMAL(14,2),
        @VLRIMPUESTOS DECIMAL(14,2),
        @IVACALCULO   DECIMAL(14,2),
        @VALORCALCULO DECIMAL(14,2),
        @FACT_RETEIVA DECIMAL(14,2),
        @VLRRETIVA    DECIMAL(14,2),
        @IDBODEGA     VARCHAR(5)

BEGIN
	PRINT'CAPTURANDO DATOS'
	PRINT '@CNSMOVDEV = '+@CNSMOVDEV
	PRINT '@CNSMOVCOMPRA = '+@CNSMOVCOMPRA
	SELECT @CONCEPTONOTA=dbo.FNK_VALORVARIABLE('IDINVNOTADB_DEV')
	SELECT @CNSFCOM=CNSFCOM,@IDTERCERO=IDTERCERO,@NODOCUMENTO=NODOCUMENTO,@CCOSTO=CCOSTO FROM IMOV WHERE CNSMOV=@CNSMOVCOMPRA
	SELECT @CNSFCXP=CNSFCXP, @ESTADOCXP=COALESCE(ESTADO,'A'), @SALDOCXP=SALDO, @CUENTACR=CUECREDITO
	FROM FCXP 
	WHERE  CNSFCOM=@CNSFCOM AND IDTERCERO=@IDTERCERO AND NOREFERENCIA=@NODOCUMENTO AND ESTADO<>'A'

    PRINT 'VALIDO SI TIENE IVA Y NO IVA LA DEVOLCION'

	   IF @ESTADOCXP='A'
	   BEGIN
		   PRINT'LA  CXP ESTA ANULADA O NO EXISTE'
		   RETURN
	   END
	   IF @SALDOCXP<=0 --OR LEN(@SALDOCXP-(@VLRNETO-@DESCUENTOS))>10
	   BEGIN
		   PRINT 'LA CXP NO TIENE SALDO PARA HACER NOTAS'
		   RETURN
	   END 

   DECLARE @CUE_DEBITO VARCHAR(20)
   DECLARE @CUE_REVERSION VARCHAR(20)
   DECLARE @CUE_IVA VARCHAR(20)
   DECLARE @CUE_IVAREVER VARCHAR(20)
   DECLARE @PIVA DECIMAL(7,2)
   DECLARE @VLR_IVA DECIMAL(14,2)
   DECLARE @CANTIDAD SMALLINT
   DECLARE @VRL_BRUTO DECIMAL(14,2)
   DECLARE @VLR_BASE DECIMAL(14,2)


   PRINT 'SE CREA FCXPDBCR'

	SELECT @ITEM=COALESCE(MAX(ITEM),0)+1 FROM FCXPDBCR WHERE CNSFCXP=@CNSFCXP


	INSERT INTO FCXPDBCR(CNSFCXP,IDNOTA,ITEM,VALOR,TIPO,FECHA,OBSERVACION,ESTADO,PROCEDENCIA,CUENTA_DB,CUENTA_CR,USUARIO,SYS_COMPUTERNAME,
				MARCACONT,CONTABILIZADA,NROCOMPROBANTE,CODUNG,CODPRG,ENPRESUPUESTO,CCOSTO,NOREFERENCIA,DECRUCES,VLR_IMPUESTOS,
				VLR_NETO,PORCENTAJEIVA,VALORIVA,FACTURADA,N_FACTURA,GIMPUESTOS,GIVA,CNSMOV)
	SELECT  @CNSFCXP,@CONCEPTONOTA,@ITEM,0,'DB',GETDATE(),' DEVOLUCION A PROVEEDOR '+@IDTERCERO+' FACTURA: '+@NODOCUMENTO +' CNSCOMPRA: '+@CNSFCXP,
			'N','INV',@CUENTACR,NULL,@USUARIO,@SYS_COMPUTERNAME,0,0,NULL,'','',0,@CCOSTO,@NODOCUMENTO,0,0,
			0,@PIVA,0,0,@CNSMOVCOMPRA,0,0,@CNSMOVDEV 


   INSERT INTO FCXPDNOT(CNSFCXP,VALOR_DESCUENTO,ITEM,IDSERVICIO,CANTIDAD,VALOR,PORIVA,VLR_IVA,VLR_NETO,DESCTO,CTA_SER,CTA_IVA,IDIMP_IVA,IDCLASE_IVA,AFECTA_IVA,AFECTA_IMPUESTOS,FECHA_CREA,ITEM_DBCR)
   SELECT @CNSFCXP,0,ROW_NUMBER() OVER(ORDER  BY IMOVH.IDARTICULO  ASC),IMOVH.IDARTICULO,IMOVH.CANTIDAD,(IMOVH.CANTIDAD*IMOVH.PCOSTO),IMOVH.PIVA,CASE WHEN COALESCE(IMOVH.PIVA,0)>0 THEN (IMOVH.CANTIDAD*IMOVH.VLRIVA) ELSE 0 END,
   CASE WHEN COALESCE(IMOVH.PIVA,0)>0 THEN (IMOVH.CANTIDAD*IMOVH.PCOSTO)/(1+(IMOVH.PIVA/100)) ELSE (IMOVH.CANTIDAD*IMOVH.PCOSTO) END,
   IMOVH.VLRDTO, FCXPD.CUENTA_SER,FCXPD.CUENTA_IVA,FCXPD.IDIMPUESTO,FCXPD.IDCLASE, CASE WHEN COALESCE(IMOVH.PIVA,0)>0 THEN 1 ELSE 0 END,0,DBO.FNK_GETDATE(),@ITEM
   FROM IMOVH LEFT JOIN FCXPD ON IMOVH.IDARTICULO=FCXPD.IDSERVICIO AND IMOVH.NOLOTEPEDIDO=FCXPD.NOLOTE
   WHERE IMOVH.CNSMOV=@CNSMOVDEV
   AND FCXPD.CNSFCXP=@CNSFCXP

   PRINT 'ACTUALIZO CUENTAS'

   PRINT 'VALIDO CUENTAS FINALES'
   IF EXISTS(SELECT * FROM FCXPDNOT INNER JOIN CUE ON FCXPDNOT.CTA_SER=CUE.CUENTA  
            WHERE FCXPDNOT.CNSFCXP=@CNSFCXP
            AND FCXPDNOT.ITEM_DBCR=@ITEM
            AND COALESCE(CUE.MCUEREV,0)=1)
   BEGIN
      UPDATE FCXPDNOT SET CTA_SER=CUENTAREV
      FROM FCXPDNOT INNER JOIN CUE ON FCXPDNOT.CTA_SER=CUE.CUENTA  
      WHERE FCXPDNOT.CNSFCXP=@CNSFCXP
      AND FCXPDNOT.ITEM_DBCR=@ITEM
      AND COALESCE(CUE.MCUEREV,0)=1
   END
   IF EXISTS(SELECT * FROM FCXPDNOT INNER JOIN CUE ON FCXPDNOT.CTA_SER=CUE.CUENTA  
             WHERE FCXPDNOT.CNSFCXP=@CNSFCXP
             AND FCXPDNOT.ITEM_DBCR=@ITEM
             AND COALESCE(FCXPDNOT.VLR_IVA,0)>0
             AND COALESCE(CUE.MCUEGRAV,0)=1)
   BEGIN
      UPDATE MCHE SET CUENTA=CUENTAGRAV
      FROM FCXPDNOT INNER JOIN CUE ON FCXPDNOT.CTA_SER=CUE.CUENTA  
      WHERE FCXPDNOT.CNSFCXP=@CNSFCXP
      AND FCXPDNOT.ITEM_DBCR=@ITEM
      AND COALESCE(FCXPDNOT.VLR_IVA,0)>0
      AND COALESCE(CUE.MCUEGRAV,0)=1
   END
   IF EXISTS(SELECT * FROM FCXPDNOT INNER JOIN CUE ON FCXPDNOT.CTA_IVA=CUE.CUENTA  
            WHERE FCXPDNOT.CNSFCXP=@CNSFCXP
            AND FCXPDNOT.ITEM_DBCR=@ITEM
            AND COALESCE(CUE.MCUEREV,0)=1)
   BEGIN
      UPDATE FCXPDNOT SET CTA_IVA=CUENTAREV
      FROM FCXPDNOT INNER JOIN CUE ON FCXPDNOT.CTA_IVA=CUE.CUENTA  
      WHERE FCXPDNOT.CNSFCXP=@CNSFCXP
      AND FCXPDNOT.ITEM_DBCR=@ITEM
      AND COALESCE(CUE.MCUEREV,0)=1
   END


   SELECT @IVACALCULO=@VLR_IVA,@VALORCALCULO=@VLR_BASE,@CUE_IVAREVER=NULL,@CUE_REVERSION=NULL

   SELECT @IVACALCULO=SUM(COALESCE(VLR_IVA,0)),@VLR_BASE=SUM(COALESCE(VLR_NETO,0)),@VALOR=SUM(VALOR)
   FROM FCXPDNOT
   WHERE FCXPDNOT.CNSFCXP=@CNSFCXP
   AND FCXPDNOT.ITEM_DBCR=@ITEM


	IF EXISTS( SELECT * FROM FCXPI WHERE CNSFCXP=@CNSFCXP AND IDIMPUESTO=DBO.FNK_VALORVARIABLE('IDIMP_RETEIVA') )
	BEGIN
		SELECT @FACT_RETEIVA=COALESCE(VALORIMP,0)  FROM FCXPI 
      WHERE CNSFCXP=@CNSFCXP AND IDIMPUESTO=DBO.FNK_VALORVARIABLE('IDIMP_RETEIVA')

		SELECT @VLRRETIVA=@IVACALCULO *(@FACT_RETEIVA/100)
	END
	ELSE
	BEGIN
		SELECT @VLRRETIVA=0
	END

	SELECT  @VLRIMPUESTOS= SUM(@VLR_BASE*(VALORIMP/100)) FROM FCXPI 
   WHERE CNSFCXP=@CNSFCXP 
   AND IDIMPUESTO<>DBO.FNK_VALORVARIABLE('IDIMP_RETEIVA')

	SELECT @VLRIMPUESTOS=(COALESCE(@VLRIMPUESTOS,0)+COALESCE(@VLRRETIVA,0))


   UPDATE FCXPDBCR SET VALOR=@VALOR,VALORIVA=@IVACALCULO,VLR_IMPUESTOS=@VLRIMPUESTOS,VLR_NETO=@VALOR, GIVA=CASE WHEN COALESCE(@IVACALCULO,0)>0 THEN 1 ELSE 0 END,
   GIMPUESTOS=CASE WHEN COALESCE(@VLRIMPUESTOS,0)>0 THEN 1 ELSE 0 END
   WHERE CNSFCXP=@CNSFCXP
   AND ITEM=@ITEM

   PRINT 'ACTUALIZANDO EL VALOR DE NOTAS EN FCXP '+@CNSFCXP
   UPDATE FCXP SET VLR_NOTASDEBITO=COALESCE(VLR_NOTASDEBITO,0)+(@VALOR-@VLRIMPUESTOS) WHERE CNSFCXP=@CNSFCXP

   PRINT 'RELIQUIDANDO SALDOS'
   EXEC SPK_CALCULOVALORESCXP @CNSFCXP

   UPDATE IMOV SET CNSDBCR = @CNSFCXP, ITEMDBCR = @ITEM    WHERE  IMOV.CNSMOV = @CNSMOVDEV   

   PRINT 'ACTUALIZO IEXI'
       
	SELECT @IDBODEGA=IDBODEGA FROM IMOV WHERE CNSMOV=@CNSMOVDEV

	--Se trae update a SPK ya que en clarion quedaba incompleto el proceso OSOLANO 20230120
	UPDATE IEXI SET EXISLOTE=EXISLOTE-ISAL.CANTIDAD   
	FROM IEXI 
		INNER JOIN ( SELECT IDARTICULO,NOLOTE,SUM(CANTIDAD)CANTIDAD 
					FROM ISAL                                      
					WHERE CNSMOV=@CNSMOVDEV
					GROUP BY IDARTICULO,NOLOTE 
					) ISAL ON IEXI.IDARTICULO=ISAL.IDARTICULO AND IEXI.NOLOTE=ISAL.NOLOTE        
	WHERE IEXI.IDBODEGA=@IDBODEGA

	PRINT 'ENVIANDO A CONTABLIDAD'
   IF COALESCE(DBO.FNK_VALORVARIABLE('ENVIACONTAB_NOTDEVOL'),'')<>'NO'
   BEGIN
	   IF (SELECT COALESCE(DEVTOTAL, 0) FROM IMOV WHERE CNSMOV = @CNSMOVDEV) <> 0
	   BEGIN
		   EXEC  SPK_NC_CONTAB_CXPFNT_TOTAL @CNSFCXP,@ITEM,@USUARIO,@SYS_COMPUTERNAME ,@COMPANIA, @SEDE,''
	   END
	   ELSE
	   BEGIN
		   EXEC  SPK_NC_CONTAB_CXPFNT @CNSFCXP,@ITEM,@USUARIO,@SYS_COMPUTERNAME ,@COMPANIA, @SEDE,'' 
	   END
   END
 END
