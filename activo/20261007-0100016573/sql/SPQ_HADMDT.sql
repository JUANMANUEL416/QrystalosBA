CREATE OR ALTER PROCEDURE DBO.SPQ_HADMDT
	@JSON  NVARCHAR(MAX)
WITH
ENCRYPTION
AS
DECLARE  
	@PARAMETROS NVARCHAR(MAX),	@MODELO	VARCHAR(100),	@METODO		 VARCHAR(100), 
	@NOADMISION  VARCHAR(16),
    @IDTERCERO VARCHAR(20)    ,@TIPODTO VARCHAR(1)     ,@DESCUENTO VARCHAR(9),
	@ID          INT
BEGIN
	SELECT *
	INTO #JSON
	FROM OPENJSON (@json)
	WITH (
		MODELO         VARCHAR(100)     '$.MODELO',
		METODO         VARCHAR(100)     '$.METODO',
		PARAMETROS     NVARCHAR(MAX)  AS JSON
	)

	SELECT @MODELO = MODELO , @METODO = METODO , @PARAMETROS = PARAMETROS
	FROM #JSON


	IF @METODO = 'INSERTAR'
	BEGIN
		SELECT @NOADMISION = NOADMISION, @TIPODTO= TIPODTO, @DESCUENTO= DESCUENTO, @IDTERCERO= IDTERCERO
		FROM OPENJSON (@PARAMETROS)
		WITH ( NOADMISION	VARCHAR(16)	'$.NOADMISION'
			  ,TIPODTO VARCHAR(1)       '$.TIPODTO'
			  ,DESCUENTO VARCHAR(9)     '$.DESCUENTO'
			  ,IDTERCERO VARCHAR(20)    '$.IDTERCERO'
			)
		INSERT INTO HADMDT (IDTERCERO, TIPODTO, DESCUENTO, NOADMISION)
		VALUES ( @IDTERCERO, @TIPODTO, @DESCUENTO, @NOADMISION)

		SELECT  'OK' OK
	END

	
	IF @METODO = 'ACTUALIZAR'
	BEGIN
		SELECT @NOADMISION = NOADMISION, @TIPODTO= TIPODTO, @DESCUENTO= DESCUENTO, @IDTERCERO= IDTERCERO, @ID= ID
		FROM OPENJSON (@PARAMETROS)
		WITH ( NOADMISION	VARCHAR(16)	'$.NOADMISION'
			  ,TIPODTO VARCHAR(1)       '$.TIPODTO'
			  ,DESCUENTO VARCHAR(9)     '$.DESCUENTO'
			  ,IDTERCERO VARCHAR(20)    '$.IDTERCERO'
			  ,ID        INT            '$.ID'
			)

		UPDATE HADMDT 
			SET IDTERCERO= @IDTERCERO, TIPODTO = @TIPODTO, DESCUENTO = @DESCUENTO, NOADMISION = @NOADMISION
		WHERE ID = @ID

		SELECT  'OK' OK
	END

	IF @METODO = 'ELIMINAR'
	BEGIN
		SELECT @ID = ID
		FROM OPENJSON (@PARAMETROS)
		WITH (
			ID INT '$.ID'
		)

		DELETE FROM HADMDT WHERE ID = @ID
		
		SELECT  'OK' OK
	END

END

